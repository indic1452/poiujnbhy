def разметка(у: Уровень) -> tuple[dict[int, list[int]], dict[int, list[int]], dict[int, int]]:
    """Для каждого притока (с нуля): позиции его данных, его C-битов и бита возможности.

    В каждом блоке за служебным битом идут биты притоков 1, 2, …, n по
    очереди. Возможность стаффинга притока i — его первый бит в блоке
    ``блок_стаффинга`` подцикла i; в позиции данных она не входит.
    """
    данные: dict[int, list[int]] = {t: [] for t in range(у.притоков)}
    c: dict[int, list[int]] = {t: [у.служебный(t, б) for б in у.c_блоки]
                               for t in range(у.притоков)}
    стаффинг = {t: у.служебный(t, у.блок_стаффинга) + 1 + t for t in range(у.притоков)}
    for п in range(у.подциклов):
        for б in range(у.блоков):
            начало = у.служебный(п, б) + 1
            for k in range(у.данных):
                данные[k % у.притоков].append(начало + k)
    for t, место in стаффинг.items():
        данные[t].remove(место)
    return данные, c, стаффинг


def _эталон(у: Уровень) -> tuple[np.ndarray, np.ndarray]:
    """Позиции и значения синхробитов M-цикла: F-биты всех подциклов и M-биты."""
    позиции, значения = [], []
    for п in range(у.подциклов):
        for б, з in zip(у.f_блоки, у.f_значения, strict=True):
            позиции.append(у.служебный(п, б))
            значения.append(з)
    for п, з in zip(у.м_подциклы, у.м_значения, strict=True):
        позиции.append(у.служебный(п, 0))
        значения.append(з)
    return np.array(позиции), np.array(значения, dtype=np.uint8)


def кадр(биты: np.ndarray, у: Уровень) -> dict | None:
    """Начало M-цикла по F- и M-битам и доля M-циклов, где они совпали целиком."""
    L = у.цикл
    таблица = сложить(биты, L)
    if len(таблица) < 32:
        return None
    среднее = таблица.mean(axis=0)
    позиции, значения = _эталон(у)
    места = (np.arange(L)[:, None] + позиции[None, :]) % L
    откл = np.abs(среднее[места] - значения.astype(np.float64)).max(axis=1)
    лучший = int(np.argmin(откл))
    if откл[лучший] > ПОСТОЯННЫЙ:
        return None
    циклы = сложить(биты, L, лучший)
    совпали = np.all(циклы[:, позиции] == значения, axis=1)
    первый = int(np.argmax(совпали))
    доля = float(совпали[первый:].mean())
    if доля < ПОРОГ:
        return None
    return {"начало": лучший + первый * L, "доля": доля, "циклов": len(циклы) - первый}


def разнести(биты: np.ndarray, у: Уровень, начало: int, *, стаффинг_всегда: bool = False
             ) -> tuple[list[np.ndarray], list[float]]:
    """Притоки со снятым стаффингом и доля циклов со стаффингом у каждого.

    ``стаффинг_всегда`` — режим C-bit parity: возможность пуста в каждом
    цикле, C-биты не читаются. Инверсия притоков здесь не снимается.
    """
    таблица = сложить(биты, у.цикл, начало)
    данные, c, стаффинг = разметка(у)
    притоки, доли = [], []
    for t in range(у.притоков):
        if стаффинг_всегда:
            пустой = np.ones(len(таблица), dtype=bool)
        else:
            # Большинство из трёх C-битов: 1 — возможность несёт пустышку.
            пустой = таблица[:, c[t]].sum(axis=1) * 2 > len(c[t])
        позиции = sorted(данные[t] + [стаффинг[t]])
        столбец = позиции.index(стаффинг[t])
        значения = таблица[:, позиции]
        маска = np.ones(значения.shape, dtype=bool)
        маска[пустой, столбец] = False
        притоки.append(значения[маска])
        доли.append(float(пустой.mean()))
    return притоки, доли


def _скорость(у: Уровень, доля: float) -> tuple[float, float]:
    """Скорость притока по доле стаффинга при номинальной скорости агрегата и её отклонение."""
    бит_в_цикле = у.данных * у.блоков * у.подциклов // у.притоков - доля
    скорость = у.скорость / у.цикл * бит_в_цикле
    return скорость, (скорость / у.скорость_притока - 1) * 1e6


def _строки_стаффинга(у: Уровень, доли: list[float], всегда: bool) -> list[str]:
    строки = []
    for t, доля in enumerate(доли):
        скорость, ppm = _скорость(у, доля)
        строки.append(
            f"приток {t + 1}: стаффинг в {доля * 100:.1f} % циклов → скорость "
            f"{скорость / 1000:.3f} кбит/с при номинальной скорости агрегата"
            + ("" if всегда else f" ({ppm:+.0f} ppm от номинала {у.приток})"))
    return строки


def _притоки_t1(притоки: list[np.ndarray]) -> tuple[list[np.ndarray], list[str], list[float]]:
    """Снять инверсию притоков M12 по найденному в них циклу T1.

    Каждый приток пробуется прямым и инверсным; решает, в каком виде цикл T1
    держится лучше. Если он одинаково держится в обоих (SF неотличим от своей
    инверсии) или не найден вовсе — инверсия остаётся по стандарту (2 и 4).
    """
    итог, строки, доли = [], [], []
    for номер, приток in enumerate(притоки, start=1):
        по_стандарту = номер in ИНВЕРСНЫЕ_M12
        прямой = кадр_t1(приток)
        обратный = кадр_t1(1 - приток)
        доля_п = прямой["доля"] if прямой else 0.0
        доля_о = обратный["доля"] if обратный else 0.0
        if max(доля_п, доля_о) < ПОРОГ:
            инверсия, основание, вид, доля = по_стандарту, "цикл T1 не найден — по стандарту", "", 0.0
        elif доля_п >= ПОРОГ and доля_о >= ПОРОГ and abs(доля_п - доля_о) < 0.05:
            инверсия = по_стандарту
            основание = "цикл T1 держится в обоих видах — по стандарту"
            вид, доля = (обратный if инверсия else прямой)["вид"], max(доля_п, доля_о)
        else:
            инверсия = доля_о > доля_п
            основание = "по циклу T1" + ("" if инверсия == по_стандарту else
                                        ", НЕ как в стандарте")
            вид, доля = (обратный if инверсия else прямой)["вид"], max(доля_п, доля_о)
        итог.append(1 - приток if инверсия else приток)
        доли.append(доля)
        строки.append(
            f"приток {номер}: {'инвертирован' if инверсия else 'прямой'} ({основание}); "
            + (f"цикл T1 {вид} совпал в {доля * 100:.1f} % сверхциклов" if вид else
               "цикла T1 в притоке нет"))
    return итог, строки, доли


def ds2(биты: np.ndarray) -> Находка | None:
    """DS2 (M12): 4 × T1 со стаффингом; притоки — дальше, с инверсией, снятой по данным."""
    найдено = кадр(биты, DS2)
    if найдено is None:
        return None
    начало, доля = найдено["начало"], найдено["доля"]
    притоки, доли = разнести(биты, DS2, начало)
    притоки, строки_t1, доли_t1 = _притоки_t1(притоки)
    циклы = сложить(биты, DS2.цикл, начало)
    x = float(циклы[:, DS2.служебный(3, 0)].mean())
    найдено_t1 = sum(д >= ПОРОГ for д in доли_t1)
    подробно = [
        f"M-цикл 1176 бит с бита {начало}: 4 подцикла × 6 блоков × 49 бит (служебный бит + "
        f"48 бит 4 притоков T1 побитно); служебные биты подцикла M, C1, F0, C2, C3, F1",
        f"F0 = 0, F1 = 1, M-биты 011X; бит X = 1 в {x * 100:.1f} % циклов",
        "C-биты подцикла i — стаффинг притока i (большинство из трёх), возможность — первый "
        "бит притока i в 6-м блоке подцикла i",
    ]
    подробно += _строки_стаффинга(DS2, доли, False)
    подробно += строки_t1
    if not найдено_t1:
        подробно.append("ни в одном притоке цикла T1 нет — разуплотнение не подтверждено данными")
    return Находка(
        уровень="PDH", что=f"PDH DS2 ({DS2.стандарт}): 4 × T1 со стаффингом",
        уверенность=доля,
        мера=f"F- и M-биты совпали в {доля * 100:.1f} % M-циклов; цикл T1 найден в "
             f"{найдено_t1} из 4 притоков",
        подробно=подробно,
        дальше={t + 1: приток for t, приток in enumerate(притоки)},
        вид_дальше="притоки", сверка=float(np.mean(доли_t1)))


def _проверка_ds2(притоки: list[np.ndarray]) -> tuple[list[np.ndarray], list[float], list[bool]]:
    """Цикл DS2 в каждом притоке DS3: прямом, а если нет — инверсном."""
    итог, доли, инверсии = [], [], []
    for приток in притоки:
        прямой = кадр(приток, DS2)
        обратный = None if прямой else кадр(1 - приток, DS2)
        инверсия = обратный is not None
        итог.append(1 - приток if инверсия else приток)
        доли.append((обратный or прямой or {"доля": 0.0})["доля"])
        инверсии.append(инверсия)
    return итог, доли, инверсии


def ds3(биты: np.ndarray) -> Находка | None:
    """DS3: 7 × DS2, M23 или C-bit parity; P-биты — проверка, притоки — дальше."""
    найдено = кадр(биты, DS3)
    if найдено is None:
        return None
    начало, доля = найдено["начало"], найдено["доля"]
    циклы = сложить(биты, DS3.цикл, начало)
    служебные = np.zeros(DS3.цикл, dtype=bool)
    for п in range(DS3.подциклов):
        for б in range(DS3.блоков):
            служебные[DS3.служебный(п, б)] = True
    чётность = циклы[:, ~служебные].sum(axis=1) % 2
    p = циклы[:, [DS3.служебный(2, 0), DS3.служебный(3, 0)]]
    # P1 = P2 = чётность данных ПРЕДЫДУЩЕГО цикла; полярность — по данным.
    прямая = float(np.mean(np.all(p[1:] == чётность[:-1, None], axis=1))) if len(p) > 1 else 0.0
    обратная = float(np.mean(np.all(p[1:] != чётность[:-1, None], axis=1))) if len(p) > 1 else 0.0
    доля_p = max(прямая, обратная)
    x = float(циклы[:, [DS3.служебный(0, 0), DS3.служебный(1, 0)]].mean())
    # C-bit parity: CP (C-биты подцикла 3) повторяют P1 того же цикла, AIC = 1.
    _, c, _ = разметка(DS3)
    cp = float(np.mean(np.all(циклы[:, c[2]] == p[:, :1], axis=1)))
    aic = float(циклы[:, c[0][0]].mean())
    c_bit = cp >= 0.9 and aic >= 0.9
    варианты = []
    for всегда in (False, True):
        притоки, доли = разнести(биты, DS3, начало, стаффинг_всегда=всегда)
        притоки, доли_ds2, инверсии = _проверка_ds2(притоки)
        варианты.append((sum(д >= ПОРОГ for д in доли_ds2), всегда == c_bit, всегда,
                         притоки, доли, доли_ds2, инверсии))
    найдено_ds2, _, всегда, притоки, доли, доли_ds2, инверсии = max(
        варианты, key=lambda в: (в[0], в[1]))
    режим = "C-bit parity" if всегда else "M23"
    подробно = [
        f"M-цикл 4760 бит с бита {начало}: 7 подциклов × 8 блоков × 85 бит (служебный бит + "
        f"84 бита 7 притоков DS2 побитно); служебные биты подцикла X/P/M, F1, C1, F2, C2, F3, "
        f"C3, F4",
        f"F-биты 1001 в каждом подцикле, M-биты 010 в подциклах 5–7; X1, X2 = 1 в "
        f"{x * 100:.1f} % случаев",
        f"P-биты (подциклы 3 и 4) = чётность данных предыдущего M-цикла "
        f"{'' if прямая >= обратная else '(с инверсией) '}— сошлись в {доля_p * 100:.1f} % циклов",
        f"признаки C-bit parity: C-биты подцикла 3 повторяют P-биты в {cp * 100:.1f} % циклов, "
        f"AIC (C1 подцикла 1) = 1 в {aic * 100:.1f} %",
        f"режим {режим}: " + ("стаффинг в каждом цикле, C-биты заняты служебными каналами"
                             if всегда else
                             "C-биты подцикла i — стаффинг притока i (большинство из трёх), "
                             "возможность — первый бит притока i в 8-м блоке подцикла i")
        + ("" if всегда == c_bit else " — выбран по циклам DS2 в притоках вопреки C-битам"),
    ]
    подробно += _строки_стаффинга(DS3, доли, всегда)
    for номер, (д, инв) in enumerate(zip(доли_ds2, инверсии, strict=True), start=1):
        подробно.append(f"приток {номер}: " + (
            f"цикл DS2 совпал в {д * 100:.1f} % M-циклов" + (" (приток инвертирован)" if инв else "")
            if д >= ПОРОГ else "цикла DS2 нет"))
    if not найдено_ds2:
        подробно.append("ни в одном притоке цикла DS2 нет — разуплотнение не подтверждено данными")
    return Находка(
        уровень="PDH", что=f"PDH DS3 ({DS3.стандарт}, {режим}): 7 × DS2 со стаффингом",
        уверенность=доля,
        мера=f"F- и M-биты совпали в {доля * 100:.1f} % M-циклов, P-биты — в "
             f"{доля_p * 100:.1f} %; цикл DS2 найден в {найдено_ds2} из 7 притоков",
        подробно=подробно,
        дальше={t + 1: приток for t, приток in enumerate(притоки)},
        вид_дальше="притоки", сверка=float(np.mean(доли_ds2)))


def найти(биты: np.ndarray) -> Находка | None:
    """T1, DS2 или DS3 — что опознается по синхробитам первым."""
    выборка = биты[:ВЫБОРКА]
    for проба in (t1, ds2, ds3):
        найдено = проба(выборка)
        if найдено is not None and найдено.уверенность >= ПОРОГ:
            return найдено
    return None
