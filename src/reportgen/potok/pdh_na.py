"""Североамериканская и японская PDH: T1/DS1, DS2 (M12), DS3 (M23 и C-bit parity).

**T1 (DS1, 1544 кбит/с).** Цикл 193 бита: F-бит и 24 канальных интервала
по 8 бит. Цикловая синхронизация живёт только в F-битах, поэтому поток
складывается по 193 бита и ищется столбец, в котором F-биты через цикл
повторяют известную последовательность:

- SF (D4) — сверхцикл 12 циклов, F-биты 100011011100 (Ft = 101010 в
  нечётных циклах, Fs = 001110 в чётных). Особенность, найденная при
  разработке: инверсия этой последовательности — она же, сдвинутая на
  6 циклов, поэтому по F-битам SF нельзя сказать, инвертирован ли поток;
- ESF — сверхцикл 24 цикла: FPS 001011 в F-битах циклов 4, 8, …, 24,
  CRC-6 C1…C6 в циклах 2, 6, …, 22, канал данных DL (4 кбит/с) — в
  нечётных. CRC-6 по G.704 §2.1.3.1.3: остаток от деления M(x)·x⁶ на
  x⁶ + x + 1, где M — все 4632 бита ПРЕДЫДУЩЕГО сверхцикла с F-битами,
  принятыми за 1, первый бит — старший, C1 — старший бит остатка. Это
  по памяти — поэтому перебираются и варианты (F-биты как переданы, C1 —
  младший), а в отчёт идёт тот, что сошёлся в данных, и доля сошедшихся.

**DS2 (6312 кбит/с, M12, G.743 / ANSI T1.107).** M-цикл 1176 бит = 4
подцикла × 6 блоков × 49 бит; блок — служебный бит и 48 бит данных, в
которых 4 притока DS1 чередуются побитно. Служебные биты блоков подцикла:
M, C1, F0, C2, C3, F1 (F0 = 0, F1 = 1; M-биты подциклов 0, 1, 1, X).
Стаффинг положительный: C-биты подцикла i — управление притоком i (решает
большинство из трёх, 1 — стаффинг), возможность — первый бит притока i в
6-м блоке подцикла i. По стандарту DS1 № 2 и № 4 передаются
инвертированными; это не принимается на слово — каждый приток пробуется
прямым и инверсным, решает найденный в нём цикл T1. Если приток SF (см.
выше) или цикла T1 в нём нет, остаётся инверсия по стандарту, и отчёт
говорит, что она не проверена.

**DS3 (44736 кбит/с, G.752 / ANSI T1.107).** M-цикл 4760 бит = 7 подциклов
× 8 блоков × 85 бит (служебный бит + 84 бита данных, 7 притоков DS2
побитно). Служебные биты блоков подцикла: X/P/M, F1, C1, F2, C2, F3, C3, F4;
F-биты 1001; первые биты подциклов — X1, X2, P1, P2, M1, M2, M3 с M = 010.
P1 = P2 = чётность всех 4704 бит данных предыдущего M-цикла (полярность
перебирается, в отчёт — сошедшаяся и доля). M23: C-биты подцикла i —
стаффинг притока i, возможность — первый бит притока i в 8-м блоке
подцикла i. C-bit parity: стаффинг в каждом цикле (притоки по 6306,272
кбит/с), C-биты заняты другим: AIC = C1 подцикла 1 = 1, C-биты подцикла 3
(CP) повторяют P-биты. Режим опознаётся по CP и AIC, но разуплотняется
поток обоими способами, и решает то, в каком из них в притоках находится
цикл DS2.

Уверенность находки — доля циклов, в которых синхробиты (F, M, FPS)
совпали целиком. Разбор подтверждается отдельно и сообщается в «сверке»:
у ESF — доля сверхциклов с верной CRC-6, у DS2 и DS3 — насколько цикл
нижнего уровня держится в выделенных притоках. Ошибись разуплотнение хоть
на один бит стаффинга — цикл притока развалится.
"""

from __future__ import annotations

from dataclasses import dataclass
