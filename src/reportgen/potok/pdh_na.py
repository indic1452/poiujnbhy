@dataclass(frozen=True)
class Уровень:
    имя: str
    стандарт: str
    скорость: int                  # номинальная скорость агрегата, бит/с
    приток: str
    скорость_притока: int
    подциклов: int                 # столько же, сколько притоков
    блоков: int                    # блоков в подцикле
    данных: int                    # бит данных в блоке (после служебного)
    f_блоки: tuple[int, ...]       # блоки подцикла со служебным F-битом
    f_значения: tuple[int, ...]
    c_блоки: tuple[int, ...]       # блоки подцикла с C-битами
    блок_стаффинга: int            # блок подцикла i с возможностью стаффинга притока i
    м_подциклы: tuple[int, ...]    # подциклы, первый служебный бит которых — M
    м_значения: tuple[int, ...]

    @property
    def притоков(self) -> int:
        return self.подциклов

    @property
    def блок(self) -> int:
        return 1 + self.данных

    @property
    def подцикл(self) -> int:
        return self.блоков * self.блок

    @property
    def цикл(self) -> int:
        return self.подциклов * self.подцикл

    def служебный(self, подцикл: int, блок: int) -> int:
        return подцикл * self.подцикл + блок * self.блок


DS2 = Уровень("DS2", "M12, G.743 / ANSI T1.107", 6_312_000, "T1", 1_544_000,
              4, 6, 48, (2, 5), (0, 1), (1, 3, 4), 5, (0, 1, 2), (0, 1, 1))
DS3 = Уровень("DS3", "G.752 / ANSI T1.107", 44_736_000, "DS2", 6_312_000,
              7, 8, 84, (1, 3, 5, 7), (1, 0, 0, 1), (2, 4, 6), 7, (4, 5, 6), (0, 1, 0))
УРОВНИ = (DS2, DS3)
