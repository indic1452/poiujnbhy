#: Столбец складки «постоянен», если в нём не больше этой доли чужих бит.
ПОСТОЯННЫЙ = 0.03
ВЫБОРКА = 1 << 23
#: Цикл нижнего уровня считается найденным в притоке, если синхробиты
#: совпали целиком не меньше чем в такой доле циклов.
ПОРОГ = 0.5

# -- T1 / DS1 --------------------------------------------------------------------

T1_ЦИКЛ = 193
T1_СКОРОСТЬ = 1_544_000
#: SF (D4): F-биты циклов 1…12 — Ft 101010 в нечётных, Fs 001110 в чётных.
SF_F = np.array([1, 0, 0, 0, 1, 1, 0, 1, 1, 1, 0, 0], dtype=np.uint8)
#: ESF: номера циклов сверхцикла (с нуля) и их F-биты.
ESF_FPS = np.array([0, 0, 1, 0, 1, 1], dtype=np.uint8)
ESF_FPS_ЦИКЛЫ = np.arange(3, 24, 4)     # циклы 4, 8, …, 24
ESF_CRC_ЦИКЛЫ = np.arange(1, 24, 4)     # циклы 2, 6, …, 22: C1…C6
ESF_DL_ЦИКЛЫ = np.arange(0, 24, 2)      # нечётные циклы 1, 3, …, 23
#: Коды BOC канала данных ESF (T1.403): 6 бит слова «0 xxxxxx 0 11111111», старший первым. Таблица —
#: FreeBSD sys/dev/lmc/if_lmc.h (T1BOP_*); запись слова — CISCO-IF-LOOPBACK-MIB («00001110 11111111»).
BOC_КОДЫ = {0x00: "жёлтая авария (RAI)", 0x07: "включить шлейф линии", 0x1C: "снять шлейф линии",
            0x0A: "включить шлейф нагрузки", 0x19: "снять шлейф нагрузки",
            0x09: "включить сетевой шлейф", 0x12: "снять сетевой шлейф"}
#: Код BOC засчитывается от стольких слов подряд: случайные данные так не повторяются.
BOC_ПОВТОРОВ = 10
#: Отчёт PRM (T1.403) — кадр LAPD в DL: SAPI 14 (0x38 или 0x3A с C/R), 0x01, UI 0x03 и 4 пары октетов
#: (текущая секунда и три прежних). Биты пары — FreeBSD if_lmc.h (T1PRM_*), пара читается как 16 бит,
#: первый октет — младший (lmcconfig.c); группы ошибок CRC — по старшинству G1…G6.
PRM_CRC = ((0x1000, "1"), (0x0400, "2–5"), (0x0080, "6–10"), (0x0020, "11–100"), (0x0004, "101–319"),
           (0x0001, "320 и больше"))
PRM_ФЛАГИ = ((0x8000, "FE"), (0x4000, "SE"), (0x2000, "LB"), (0x0040, "LV"), (0x0002, "SL"))
ESF_ДЛИНА = 24 * T1_ЦИКЛ                # 4632 бита
CRC6 = 0b1000011                        # x^6 + x + 1
#: Не меньше стольких сверхциклов нужно для решения.
СВЕРХЦИКЛОВ_ОТ = 16


@lru_cache(maxsize=4)
def _веса_crc6(длина: int) -> np.ndarray:
    """Вклад каждого бита блока в остаток M(x)·x⁶ mod (x⁶+x+1): столбцы C1…C6.

    CRC линейна, поэтому остаток сверхцикла — сумма по модулю 2 вкладов его
    единичных бит; вклад бита j (первый бит — старший) — x^(длина−1−j+6) mod g.
    """
    веса = np.zeros((длина, 6), dtype=np.float32)
    остаток = CRC6 ^ (1 << 6)            # x^6 mod g = x + 1
    for j in range(длина - 1, -1, -1):
        веса[j] = [(остаток >> (5 - i)) & 1 for i in range(6)]
        остаток <<= 1
        if остаток & (1 << 6):
            остаток ^= CRC6
    return веса


def crc6(блоки: np.ndarray) -> np.ndarray:
    """CRC-6 (x⁶+x+1, нулевое начальное значение) строк таблицы: (строк, 6), C1 — старший."""
    блоки = np.atleast_2d(блоки)
    return (блоки.astype(np.float32) @ _веса_crc6(блоки.shape[1])).astype(np.int64) % 2


def _сверка_crc_esf(сверхциклы: np.ndarray) -> tuple[float, str]:
    """Доля сверхциклов, у которых C1…C6 равны CRC-6 предыдущего, и сошедшийся вариант."""
    if len(сверхциклы) < 2:
        return 0.0, ""
    f_столбцы = T1_ЦИКЛ * np.arange(24)
    принятые = сверхциклы[1:, T1_ЦИКЛ * ESF_CRC_ЦИКЛЫ]
    лучшая, вариант = -1.0, ""
    for f_единицы in (True, False):
        блоки = сверхциклы[:-1].copy()
        if f_единицы:
            блоки[:, f_столбцы] = 1
        остатки = crc6(блоки)
        for старший in (True, False):
            расчёт = остатки if старший else остатки[:, ::-1]
            доля = float(np.mean(np.all(расчёт == принятые, axis=1)))
            if доля > лучшая + 1e-12:
                лучшая = доля
                вариант = ("F-биты при расчёте приняты за 1" if f_единицы
                           else "F-биты при расчёте взяты как переданы") + \
                          (", C1 — старший бит остатка" if старший
                           else ", C1 — младший бит остатка")
    return лучшая, вариант


def _лучшее_место(откл: np.ndarray) -> tuple[int, int] | None:
    """(фаза, столбец) с наименьшим отклонением от эталона — если оно в допуске."""
    место = np.unravel_index(int(np.argmin(откл)), откл.shape)
    if откл[место] > ПОСТОЯННЫЙ:
        return None
    return int(место[0]), int(место[1])


def кадр_t1(биты: np.ndarray) -> dict | None:
    """Цикл T1 по F-битам: вид (SF / ESF), начало сверхцикла и доля совпадений.

    Поток складывается по 193 бита; в столбце F-битов средние по фазе
    сверхцикла должны повторять эталон (SF — все 12, ESF — FPS в 6 циклах
    из 24). Затем по каждому сверхциклу проверяется, совпали ли его
    синхробиты целиком; разбор начинается с первого совпавшего.
    """
    таблица = сложить(биты, T1_ЦИКЛ)
    циклов = len(таблица)
    if циклов < 24 * СВЕРХЦИКЛОВ_ОТ:
        return None
    for вид, длина, строки, эталон in (
            ("SF", 12, np.arange(12), SF_F),
            ("ESF", 24, ESF_FPS_ЦИКЛЫ, ESF_FPS)):
        n = циклов // длина
        среднее = таблица[:n * длина].reshape(n, длина, T1_ЦИКЛ).mean(axis=0)
        фазы = (np.arange(длина)[:, None] + строки[None, :]) % длина
        откл = np.abs(среднее[фазы] - эталон[None, :, None].astype(np.float64)).max(axis=1)
        место = _лучшее_место(откл)
        if место is None:
            continue
        фаза, столбец = место
        начало = фаза * T1_ЦИКЛ + столбец
        сверхциклы = сложить(биты, длина * T1_ЦИКЛ, начало)
        if len(сверхциклы) < 2:
            continue
        совпали = np.all(сверхциклы[:, T1_ЦИКЛ * строки] == эталон, axis=1)
        # Доля — от первого совпавшего сверхцикла: то, что до него, — не T1.
        первый = int(np.argmax(совпали))
        доля = float(совпали[первый:].mean())
        if доля < ПОРОГ:
            continue
        итог = {"вид": вид, "начало": начало + первый * длина * T1_ЦИКЛ, "доля": доля,
                "сверхциклов": len(сверхциклы)}
        if вид == "ESF":
            сверка, вариант = _сверка_crc_esf(сверхциклы[первый:первый + 2048])
            итог.update(crc=сверка, вариант_crc=вариант)
        return итог
    return None


def boc(dl: np.ndarray) -> list[tuple[int, int]]:
    """Коды BOC в DL: [(код, слов подряд)] — серии не короче BOC_ПОВТОРОВ, по месту в ряду.

    Фаза слов у каждой серии своя (между сообщениями — HDLC или заполнение любой длины).
    """
    серии: list[tuple[int, int, int]] = []
    for фаза in range(16):
        n = (len(dl) - фаза) // 16
        слова = dl[фаза:фаза + 16 * n].reshape(n, 16)
        годно = (слова[:, 0] == 0) & (слова[:, 7] == 0) & np.all(слова[:, 8:] == 1, axis=1)
        коды = слова[:, 1:7] @ (1 << np.arange(5, -1, -1))
        начало, прежний, длина = 0, None, 0
        for k, (g, код) in enumerate(zip(годно.tolist() + [False], коды.tolist() + [-1], strict=True)):
            if g and код == прежний:
                длина += 1
                continue
            if прежний is not None and длина >= BOC_ПОВТОРОВ:
                серии.append((фаза + 16 * начало, прежний, длина))
            начало, прежний, длина = (k, код, 1) if g else (k, None, 0)
    return [(код, длина) for _, код, длина in sorted(серии)]


def prm(кадр: bytes) -> list[str] | None:
    """Отчёт PRM по секундам (текущая первой) или None, если кадр — не PRM."""
    if len(кадр) != 11 or кадр[0] not in (0x38, 0x3A) or кадр[1:3] != b"\x01\x03":
        return None
    итог = []
    for i in range(4):
        слово = кадр[3 + 2 * i] | (кадр[4 + 2 * i] << 8)
        crc = next((текст for маска, текст in PRM_CRC if слово & маска), "0")
        флаги = [имя for маска, имя in PRM_ФЛАГИ if слово & маска]
        итог.append(f"N {(слово >> 8) & 3}: ошибок CRC {crc}" + (f", {', '.join(флаги)}" if флаги else ""))
    return итог


def t1(биты: np.ndarray) -> Находка | None:
    """T1/DS1: сверхцикл SF или ESF по F-битам, 24 КИ по 8 бит — дальше, как каналы."""
    найдено = кадр_t1(биты)
    if найдено is None:
        return None
    начало, доля, вид = найдено["начало"], найдено["доля"], найдено["вид"]
    циклы = сложить(биты, T1_ЦИКЛ, начало)
    каналы = {номер: циклы[:, 1 + 8 * (номер - 1):1 + 8 * номер].reshape(-1)
              for номер in range(1, 25)}
    подробно = [f"цикл 193 бита (F-бит + 24 КИ по 8 бит), 8000 циклов в секунду, "
                f"начало сверхцикла — бит {начало} выборки"]
    сверка = доля
    if вид == "SF":
        что = "T1/DS1 (1544 кбит/с), сверхцикл SF (D4) из 12 циклов: 24 КИ по 8 бит"
        мера = f"F-биты 100011011100 совпали целиком в {доля * 100:.1f} % сверхциклов"
        подробно.append("SF (D4): Ft 101010 в F-битах нечётных циклов, Fs 001110 — в чётных; "
                        "инверсия потока по F-битам SF неотличима (сдвиг на 6 циклов)")
    else:
        сверка = найдено["crc"]
        что = "T1/DS1 (1544 кбит/с), сверхцикл ESF из 24 циклов: 24 КИ по 8 бит"
        мера = (f"FPS 001011 совпала в {доля * 100:.1f} % сверхциклов; CRC-6 верна в "
                f"{сверка * 100:.1f} %")
        подробно.append(
            f"ESF: FPS 001011 в F-битах циклов 4, 8, …, 24; CRC-6 (x⁶+x+1) по предыдущему "
            f"сверхциклу в циклах 2, 6, …, 22 сошлась в {сверка * 100:.1f} % сверхциклов "
            f"({найдено['вариант_crc']})")
        if сверка < ПОРОГ:
            подробно.append("CRC-6 не сходится ни в одном из вариантов расчёта — цикл ESF "
                            "держится только на FPS")
        сверхциклы = сложить(биты, ESF_ДЛИНА, начало)
        dl = сверхциклы[:, T1_ЦИКЛ * ESF_DL_ЦИКЛЫ].reshape(-1)
        подробно.append(f"канал данных DL (4 кбит/с, F-биты нечётных циклов): {len(dl)} бит, "
                        f"единиц {dl.mean() * 100:.1f} %")
        for код, повторов in boc(dl):
            подробно.append(f"в DL — BOC 0x{код:02X}: {BOC_КОДЫ.get(код, 'нет в таблице T1.403')} "
                            f"({повторов} слов подряд)")
        if len(dl) >= 2048:
            from . import hdlc  # noqa: PLC0415
            кадры_dl = hdlc.найти(dl)
            if кадры_dl is not None and кадры_dl.уверенность >= ПОРОГ:
                подробно.append(f"в DL — HDLC: {кадры_dl.мера}")
                отчёты = [о for о in map(prm, кадры_dl.дальше) if о is not None]
                if отчёты:
                    подробно.append(f"в DL — отчёты PRM (T1.403): {len(отчёты)}; последний — "
                                    + "; ".join(отчёты[-1]))
    подробно += описать_каналы(каналы)
    return Находка(уровень="цикл", что=что, уверенность=доля, мера=мера,
                   подробно=подробно, дальше=каналы, вид_дальше="каналы", сверка=сверка)


