"""PDH со стаффингом согласования скоростей: E2, E3, E4 (G.742, G.751).

Притоки плезиохронной иерархии идут каждый от своего генератора, и их
скорости чуть расходятся. Мультиплексор выравнивает их положительным
стаффингом (в отечественной литературе — согласование скоростей,
выравнивание): в каждом цикле у каждого притока есть одна «возможность
стаффинга» — бит, который несёт либо данные, либо пустышку. Что именно —
сообщают биты управления Cj: три (у E4 — пять) повтора в разных наборах
цикла, решает большинство, поэтому одиночная ошибка линии не сбивает
демультиплексор.

Разбор: цикл по синхрослову (FAS), нарезка наборов, побитовое разделение
притоков, решение по Cj большинством и выбрасывание пустых бит. Проверка —
не на слово анализатора: в выделенном притоке E2 должен найтись цикл E1
с FAS 0011011, в притоке E3 — цикл E2 и т. д. Ошибись разбор хоть на один
бит стаффинга — цикл притока развалится.

Доля циклов со стаффингом — это расстройка частоты притока: по ней
считается его скорость при номинальной скорости агрегата.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .nahodka import Находка

#: Столбец цикла «постоянен», если в нём не больше этой доли чужих бит.
ПОСТОЯННЫЙ = 0.03
ВЫБОРКА = 1 << 23


@dataclass(frozen=True)
class Иерархия:
    имя: str
    стандарт: str
    скорость: int              # номинальная скорость агрегата, бит/с
    приток: str
    скорость_притока: int
    наборы: tuple[int, ...]    # длины наборов цикла, бит
    fas: tuple[int, ...]
    служебных: int             # FAS + авария + национальные биты в начале набора I
    притоков: int = 4

    @property
    def цикл(self) -> int:
        return sum(self.наборы)

    @property
    def повторов_cj(self) -> int:
        return len(self.наборы) - 1


ИЕРАРХИИ = (
    Иерархия("E2", "G.742", 8_448_000, "E1", 2_048_000, (212,) * 4,
             (1, 1, 1, 1, 0, 1, 0, 0, 0, 0), 12),
    Иерархия("E3", "G.751", 34_368_000, "E2", 8_448_000, (384,) * 4,
             (1, 1, 1, 1, 0, 1, 0, 0, 0, 0), 12),
    Иерархия("E4", "G.751", 139_264_000, "E3", 34_368_000, (488,) * 6,
             (1, 1, 1, 1, 1, 0, 1, 0, 0, 0, 0, 0), 16),
)


def разметка(и: Иерархия) -> tuple[dict[int, list[int]], dict[int, list[int]], dict[int, int]]:
    """Для каждого притока: позиции его данных, его битов Cj и его бита стаффинга.

    Набор I: служебные биты, затем данные. Наборы II…последний: первыми —
    по одному Cj на приток; в последнем наборе после Cj — по одному биту
    возможности стаффинга на приток. Данные притоков чередуются побитно.
    """
    данные: dict[int, list[int]] = {t: [] for t in range(и.притоков)}
    cj: dict[int, list[int]] = {t: [] for t in range(и.притоков)}
    стаффинг: dict[int, int] = {}
    начало = 0
    for номер, длина in enumerate(и.наборы):
        место = начало
        if номер == 0:
            место += и.служебных
        else:
            for t in range(и.притоков):
                cj[t].append(место + t)
            место += и.притоков
            if номер == len(и.наборы) - 1:
                for t in range(и.притоков):
                    стаффинг[t] = место + t
                место += и.притоков
        for k, позиция in enumerate(range(место, начало + длина)):
            данные[k % и.притоков].append(позиция)
        начало += длина
    return данные, cj, стаффинг


def _начало_цикла(биты: np.ndarray, и: Иерархия) -> tuple[int, float] | None:
    """Где в цикле стоит FAS и в какой доле циклов он совпал."""
    L = и.цикл
    циклов = len(биты) // L
    if циклов < 32:
        return None
    таблица = биты[:циклов * L].reshape(циклов, L)
    среднее = таблица.mean(axis=0)
    fas = np.array(и.fas, dtype=np.float64)
    f = len(fas)
    по_кругу = np.concatenate([среднее, среднее[:f]])
    окна = np.lib.stride_tricks.sliding_window_view(по_кругу, f)[:L]
    годные = np.flatnonzero(np.all(np.abs(окна - fas) <= ПОСТОЯННЫЙ, axis=1))
    if not len(годные):
        return None
    начало = int(годные[0])
    ряд = биты[начало:]
    циклов = len(ряд) // L
    слово = ряд[:циклов * L].reshape(циклов, L)[:, :f]
    совпало = float(np.mean(np.all(слово == fas.astype(np.uint8), axis=1)))
    return начало, совпало


def приток(биты: np.ndarray, и: Иерархия, начало: int, t: int) -> tuple[np.ndarray, int, int]:
    """Приток t (с 0) со снятым стаффингом: (биты, циклов со стаффингом, циклов). Каждый цикл решается
    сам по себе (Cj и возможность — в нём же), поэтому циклы можно разбирать кусками подряд."""
    L = и.цикл
    ряд = биты[начало:]
    циклов = len(ряд) // L
    таблица = ряд[:циклов * L].reshape(циклов, L)
    данные, cj, стаффинг = разметка(и)
    # Решение большинством: Cj = 1 в большинстве повторов — бит
    # возможности стаффинга пустой.
    пустой = таблица[:, cj[t]].sum(axis=1) * 2 > len(cj[t])
    позиции = sorted(данные[t] + [стаффинг[t]])
    столбец = позиции.index(стаффинг[t])
    значения = таблица[:, позиции]
    маска = np.ones(значения.shape, dtype=bool)
    маска[пустой, столбец] = False
    return значения[маска], int(np.count_nonzero(пустой)), циклов


def разнести(биты: np.ndarray, и: Иерархия, начало: int
             ) -> tuple[list[np.ndarray], list[float]]:
    """Притоки со снятым стаффингом и доля циклов со стаффингом у каждого."""
    притоки, доли = [], []
    for t in range(и.притоков):
        ряд, пустых, циклов = приток(биты, и, начало, t)
        притоки.append(ряд)
        доли.append(пустых / циклов if циклов else float("nan"))
    return притоки, доли


def слой(слова: str) -> tuple[Иерархия, int]:
    """«pdh E2|E3|E4 приток N» → (иерархия, номер притока с 0)."""
    import re  # noqa: PLC0415
    м = re.search(r"e[234]", слова.lower())
    if м is None:
        raise ValueError("pdh: «pdh E2|E3|E4 приток N»")
    и = next(и for и in ИЕРАРХИИ if и.имя == м.group(0).upper())
    числа = [int(ч) for ч in re.findall(r"\d+", слова)]
    номер = числа[-1] if len(числа) > 1 else 1
    if not 1 <= номер <= и.притоков:
        raise ValueError(f"pdh: приток — от 1 до {и.притоков}")
    return и, номер - 1


def описать_слой(и: Иерархия, начало: int, совпало: float, t: int, пустых: int, циклов: int) -> str:
    """Строка подробностей ручного слоя «pdh …» (в памяти и по кускам — одна и та же)."""
    return (f"цикл {и.имя} {и.цикл} бит, FAS с бита {начало} (совпал в {совпало * 100:.1f} % циклов начала); "
            f"приток {t + 1} ({и.приток}): циклов {циклов}, стаффинг в "
            f"{пустых / max(1, циклов) * 100:.1f} %")


def найти(биты: np.ndarray) -> Находка | None:
    """E2/E3/E4 по FAS; притоки со снятым стаффингом — дальше, на проверку."""
    выборка = биты[:ВЫБОРКА]
    for и in ИЕРАРХИИ:
        найдено = _начало_цикла(выборка, и)
        if найдено is None:
            continue
        начало, совпало = найдено
        if совпало < 0.5:
            continue
        притоки, доли = разнести(выборка, и, начало)
        данные, _, _ = разметка(и)
        частота_цикла = и.скорость / и.цикл
        подробно = [
            f"цикл {и.цикл} бит, FAS {''.join(map(str, и.fas))} с бита {начало}; наборов "
            f"{len(и.наборы)} по {и.наборы[0]} бит; {и.притоков} притока {и.приток} "
            f"с побитным чередованием",
            f"биты управления стаффингом Cj — по {и.повторов_cj} на приток, решение "
            f"большинством; возможность стаффинга — одна на приток в цикле",
        ]
        for t, доля in enumerate(доли):
            бит_в_цикле = len(данные[t]) + 1 - доля
            скорость = частота_цикла * бит_в_цикле
            отклонение = (скорость / и.скорость_притока - 1) * 1e6
            подробно.append(
                f"приток {t + 1}: стаффинг в {доля * 100:.1f} % циклов → скорость "
                f"{скорость / 1000:.3f} кбит/с при номинальной скорости агрегата "
                f"({отклонение:+.0f} ppm от номинала {и.приток})")
        return Находка(
            уровень="цикл",
            что=f"PDH {и.имя} ({и.стандарт}): {и.притоков} × {и.приток} со стаффингом "
                f"согласования скоростей",
            уверенность=совпало,
            мера=f"FAS совпал в {round(совпало * 100, 1)} % циклов",
            подробно=подробно,
            дальше={t + 1: приток for t, приток in enumerate(притоки)},
            вид_дальше="притоки")
    return None
