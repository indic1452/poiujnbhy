# -*- coding: utf-8 -*-
"""OTN (ITU-T G.709): кадр OTUk 4 × 4080 байт, скремблер, SM/PM, FEC, нагрузка OPUk.

Кадр OTUk — 4 строки по 4080 байт (16 320 байт, 130 560 бит) при любом k:
OTU1, OTU2, OTU3 и OTU4 отличаются только скоростью, поэтому k называется
лишь тогда, когда скорость потока известна (параметр ``скорость``).

Строение кадра (строка, столбец — с единицы, как в G.709):

- строка 1, столбцы 1–6 — FAS: OA1 OA1 OA1 OA2 OA2 OA2 = F6 F6 F6 28 28 28;
  столбец 7 — MFAS, счётчик сверхцикла 0…255;
- строка 1, столбцы 8–10 — SM (контроль секции): TTI, BIP-8, BEI/BIAE и признаки;
- строка 3, столбцы 10–12 — PM (контроль тракта ODUk): TTI, BIP-8, BEI;
- столбцы 15–16 — заголовок OPUk: строка 4 столбец 15 — PSI (PSI[0] — тип
  нагрузки PT, индекс — MFAS), строки 1–3 столбец 16 — JC, строка 4
  столбец 16 — NJO;
- столбцы 17–3824 — нагрузка OPUk; столбцы 3825–4080 — FEC RS(255, 239).

Что проверяется данными, а что взято из стандарта «на слово»:

- **Граница кадра** — FAS (48 бит, до 4 ошибок) с шагом ровно 130 560 бит в
  большинстве кадров, при любом битовом сдвиге и в инверсном виде.
- **Скремблер** — аддитивный кадровый, со сбросом на старшем бите MFAS; FAS
  (48 бит) не скремблируется. Полином и начальное состояние ищутся ВСЛЕПУЮ
  ``skrembler.найти_по_кадру`` (Берлекэмп — Мэсси по устойчивым столбцам
  кадра: пустые байты заголовков ODU/OPU — это чистая ПСП). Полином
  G.709 x¹⁶ + x¹² + x³ + x + 1 с начальным FFFF (в двух порядках разрядов) —
  только запасная гипотеза. Любая гипотеза, в том числе найденная вслепую,
  принимается лишь при подтверждении: MFAS после снятия идёт +1 от кадра к
  кадру И сходится хотя бы одна проверка, покрывающая весь кадр (SM BIP-8,
  синдромы RS или нули в неиспользуемых столбцах FEC). MFAS один полином не
  подтверждает: первые 8 бит ПСП при состоянии FFFF — единицы при любых отводах.
- **SM BIP-8** (строка 1, столбец 9) — чётность по байтам OPUk (столбцы
  15–3824 всех строк) кадра i, передаётся в кадре i + 2: доля совпавших
  кадров и доля совпавших бит (у случайного — 0,5). PM BIP-8 (строка 3,
  столбец 11) — так же. Если стандартное место не сходится, для справки
  перебираются столбцы 8–10 и задержки 0–3 кадра.
- **FEC** — RS(255, 239) над GF(256) по x⁸ + x⁴ + x³ + x² + 1, корни
  порождающего многочлена α⁰…α¹⁵; строка — 16 кодовых слов с чередованием по
  байтам (слово j — байты j, j + 16, …). Проверка — доля слов с нулевым
  синдромом; если не сходится, корни ищутся вслепую ``rs_bch.общие_корни``.
  Нули во всех столбцах FEC — «FEC не используется».
- **Данными НЕ проверяются** (взяты из G.709, сообщаются как есть): раскладка
  TTI (SAPI — байты 0–15, DAPI — 16–31, остальное — оператору, индекс MFAS
  mod 64), названия типов нагрузки PT, смысл JC при асинхронном отображении
  (AMP, PT 0x02: 00 — без выравнивания, 01 — NJO несёт данные, 11 — PJO
  пустой). Правильность нагрузки проверяет следующий уровень разбора: в
  нагрузке должен найтись GFP, цикл SDH и т. п.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from typing import Any

import numpy as np

from . import rs_bch, sinhro, skrembler
from .nahodka import Находка

СТРОК = 4
СТОЛБЦОВ = 4080
КАДР_БАЙТ = СТРОК * СТОЛБЦОВ                 # 16 320
КАДР_БИТ = 8 * КАДР_БАЙТ                     # 130 560
FAS = bytes.fromhex("F6F6F6282828")
FAS_БИТ = np.unpackbits(np.frombuffer(FAS, dtype=np.uint8))
#: Сколько бит FAS может не совпасть (из 48).
ОШИБОК_FAS = 4
#: Не скремблируется: FAS, 6 байт.
НЕ_СКРЕМБЛИРУЕТСЯ = 8 * len(FAS)
#: Кадров на поиск скремблера и на проверки BIP-8/RS.
КАДРОВ_СКРЕМБЛЕР = 32
КАДРОВ_ПРОВЕРКА = 16
#: Меньше — не разбираем: MFAS и BIP-8 (сдвиг на 2 кадра) не на чем проверить.
КАДРОВ_НАИМЕНЬШЕ = 3

# Места в кадре: (строка, столбец) — с нуля (в G.709 — с единицы).
MFAS = (0, 6)
SM_TTI, SM_BIP, SM_BEI = (0, 7), (0, 8), (0, 9)
PM_TTI, PM_BIP = (2, 9), (2, 10)
PSI = (3, 14)
JC_СТОЛБЕЦ = 15                              # строки 1–3
NJO, PJO = (3, 15), (3, 16)
OPU = slice(14, 3824)                        # столбцы 15–3824
НАГРУЗКА = slice(16, 3824)                   # столбцы 17–3824
FEC = slice(3824, 4080)                      # столбцы 3825–4080
BIP_ЗАДЕРЖКА = 2                             # BIP-8 кадра i — в кадре i + 2

#: Запасная гипотеза скремблера по G.709: x¹⁶ + x¹² + x³ + x + 1 в двух порядках
#: разрядов (s[n] = s[n−1] ⊕ s[n−3] ⊕ s[n−12] ⊕ s[n−16] и обратный), сброс в FFFF.
СТАНДАРТНЫЕ_ОТВОДЫ: tuple[tuple[int, ...], ...] = ((1, 3, 12, 16), (4, 13, 15, 16))
СТАНДАРТНОЕ_НАЧАЛЬНОЕ = np.ones(16, dtype=np.uint8)

#: RS(255, 239) G.709: примитивный многочлен поля и корни α^0…α^15.
RS_МНОГОЧЛЕН = 0x11D
RS_N, RS_K = 255, 239
RS_ПЕРВЫЙ_КОРЕНЬ = 0
RS_ЧЕРЕДОВАНИЕ = 16

#: Номинальные скорости OTUk, бит/с: 255/(239 − k) × скорость STM-N.
СКОРОСТИ = {
    "OTU1": 255 / 238 * 2_488_320_000,
    "OTU2": 255 / 237 * 9_953_280_000,
    "OTU3": 255 / 236 * 39_813_120_000,
    "OTU4": 255 / 227 * 99_532_800_000,
}
#: Допуск на измеренную скорость при опознании k (относительный).
СКОРОСТЬ_ДОПУСК = 1e-3

#: Типы нагрузки PT (G.709, таблица значений PSI[0]) — по памяти, данными
#: не проверяются; прочие показываются числом.
ТИПЫ_НАГРУЗКИ = {
    0x01: "экспериментальное отображение",
    0x02: "асинхронное отображение CBR (AMP), например STM-N",
    0x03: "бит-синхронное отображение CBR (BMP), например STM-N",
    0x05: "GFP",
    0x06: "виртуальная сцепка",
    0x20: "мультиплексная структура ODU (слоты 2,5 Гбит/с)",
    0x21: "мультиплексная структура ODU (слоты 1,25 Гбит/с)",
    0xFD: "тестовый сигнал NULL",
    0xFE: "тестовый сигнал PRBS",
}
PT_AMP = 0x02

#: Пороги принятия гипотезы скремблера.
MFAS_ОТ = 0.5
BIP_БИТ_ОТ = 0.75          # у случайного — 0,5
ДОЛЯ_ОТ = 0.5


# -- граница кадра ---------------------------------------------------------------------

def выровнять(биты: np.ndarray) -> dict[str, Any] | None:
    """Начало первого целого кадра по FAS: сдвиг, инверсия, доля кадров с FAS.

    FAS ищется в первых трёх кадрах (свёрткой, ``sinhro.несовпадения``);
    засчитывается фаза, в которой FAS повторяется ровно через 130 560 бит.
    """
    биты = np.asarray(биты, dtype=np.uint8)
    if len(биты) < КАДРОВ_НАИМЕНЬШЕ * КАДР_БИТ:
        return None
    проба = биты[:min(len(биты), 3 * КАДР_БИТ + НЕ_СКРЕМБЛИРУЕТСЯ)]
    н = sinhro.несовпадения(проба, FAS_БИТ)
    лучшее = None
    for инверсия, места in ((False, np.flatnonzero(н <= ОШИБОК_FAS)),
                            (True, np.flatnonzero(НЕ_СКРЕМБЛИРУЕТСЯ - н <= ОШИБОК_FAS))):
        if not len(места):
            continue
        фазы = Counter((места % КАДР_БИТ).tolist())
        фаза, раз = фазы.most_common(1)[0]
        if раз >= 2 and (лучшее is None or раз > лучшее[2]):
            лучшее = (фаза, инверсия, раз)
    if лучшее is None:
        return None
    начало, инверсия, _ = лучшее
    кадров = (len(биты) - начало) // КАДР_БИТ
    if кадров < КАДРОВ_НАИМЕНЬШЕ:
        return None
    ряд = биты[начало:начало + кадров * КАДР_БИТ]
    if инверсия:
        ряд = 1 - ряд
    заголовки = ряд.reshape(кадров, КАДР_БИТ)[:, :НЕ_СКРЕМБЛИРУЕТСЯ]
    ошибок = (заголовки != FAS_БИТ).sum(axis=1)
    return {"начало": int(начало), "инверсия": bool(инверсия), "кадров": int(кадров),
            "fas": float(np.mean(ошибок <= ОШИБОК_FAS)), "ряд": ряд.astype(np.uint8)}


def в_кадры(ряд: np.ndarray) -> np.ndarray:
    """Выровненные биты → байты кадров: кадры × 4 строки × 4080."""
    кадров = len(ряд) // КАДР_БИТ
    return np.packbits(ряд[:кадров * КАДР_БИТ].reshape(кадров, КАДР_БИТ), axis=1
                       ).reshape(кадров, СТРОК, СТОЛБЦОВ)


# -- проверки --------------------------------------------------------------------------

def mfas_подряд(кадры: np.ndarray) -> float:
    """Доля соседних кадров, у которых MFAS растёт на 1 по модулю 256."""
    if len(кадры) < 2:
        return 0.0
    m = кадры[:, MFAS[0], MFAS[1]].astype(np.int64)
    return float(np.mean((m[1:] - m[:-1]) % 256 == 1))


def bip8(кадры: np.ndarray, место: tuple[int, int] = SM_BIP,
         задержка: int = BIP_ЗАДЕРЖКА) -> tuple[float, float]:
    """BIP-8 по OPUk кадра i против байта ``место`` кадра i + задержка.

    Возвращает (доля кадров с полным совпадением, доля совпавших бит).
    """
    if len(кадры) <= задержка:
        return 0.0, 0.0
    чётность = np.bitwise_xor.reduce(кадры[:, :, OPU].reshape(len(кадры), -1), axis=1)
    переданный = кадры[:, место[0], место[1]]
    if задержка:
        разность = чётность[:-задержка] ^ переданный[задержка:]
    else:
        разность = чётность ^ переданный
    return (float(np.mean(разность == 0)),
            1.0 - float(np.unpackbits(разность).mean()))


def _bip8_где(кадры: np.ndarray) -> tuple[tuple[int, int], int, float]:
    """Для справки: где в строке 1 (столбцы 8–10) и с какой задержкой BIP-8 сходится лучше."""
    лучшее = ((0, 0), 0, 0.0)
    for столбец in (7, 8, 9):
        for задержка in range(4):
            доля, _ = bip8(кадры, (0, столбец), задержка)
            if доля > лучшее[2]:
                лучшее = ((0, столбец), задержка, доля)
    return лучшее


def rs_слова(кадры: np.ndarray) -> np.ndarray:
    """Кодовые слова RS: строка из 4080 байт → 16 слов по 255 байт с чередованием по байтам."""
    return кадры.reshape(len(кадры), СТРОК, RS_N, RS_ЧЕРЕДОВАНИЕ).transpose(
        0, 1, 3, 2).reshape(-1, RS_N)


def rs_синдромы(слова: np.ndarray, многочлен: int = RS_МНОГОЧЛЕН,
                первый: int = RS_ПЕРВЫЙ_КОРЕНЬ, корней: int = RS_N - RS_K) -> np.ndarray:
    """Синдромы c(α^j), j = первый … первый + корней − 1 (схема Горнера, старший байт первым)."""
    степень, _, умножение = rs_bch.поле(многочлен)
    точки = степень[первый:первый + корней]
    S = np.zeros((len(слова), корней), dtype=умножение.dtype)
    for i in range(слова.shape[1]):
        S = умножение[S, точки[None, :]] ^ слова[:, i:i + 1]
    return S


def fec(кадры: np.ndarray) -> dict[str, Any]:
    """FEC: используется ли, доля слов с нулевым синдромом, вслепую найденные корни."""
    столбцы = кадры[:, :, FEC]
    нулевых = float(np.mean(столбцы == 0))
    if нулевых >= 0.99:
        return {"используется": False, "нулевых_байт": нулевых}
    слова = rs_слова(кадры)
    доля = float(np.mean(~rs_синдромы(слова).any(axis=1)))
    итог: dict[str, Any] = {"используется": True, "нулевых_байт": нулевых,
                            "слов": int(len(слова)), "доля": доля}
    if доля < ДОЛЯ_ОТ:
        корни, зануление = rs_bch.общие_корни(слова[:256], RS_МНОГОЧЛЕН)
        итог["корни"] = корни if len(корни) <= 32 else []
        итог["зануление"] = зануление
    return итог


def проверки(кадры: np.ndarray) -> dict[str, Any]:
    """MFAS, SM/PM BIP-8, FEC — на выборке до ``КАДРОВ_ПРОВЕРКА`` кадров (MFAS — на всех)."""
    выборка = кадры[:КАДРОВ_ПРОВЕРКА]
    sm = bip8(выборка, SM_BIP)
    pm = bip8(выборка, PM_BIP)
    return {"mfas": mfas_подряд(кадры), "bip_sm": sm, "bip_pm": pm, "fec": fec(выборка)}


def _подтверждено(п: dict[str, Any]) -> bool:
    """Гипотеза скремблера подтверждена: MFAS подряд и сходится проверка по всему кадру."""
    f = п["fec"]
    весь_кадр = (п["bip_sm"][1] >= BIP_БИТ_ОТ
                 or (f["используется"] and f["доля"] >= ДОЛЯ_ОТ)
                 or (not f["используется"]))
    return п["mfas"] >= MFAS_ОТ and весь_кадр


# -- скремблер -------------------------------------------------------------------------

def снять(ряд: np.ndarray, отводы: Sequence[int], начальное: np.ndarray) -> np.ndarray:
    """Снять кадровый скремблер: ПСП от старшего бита MFAS, FAS не трогается."""
    return skrembler.снять_по_кадру(ряд, отводы, np.asarray(начальное, dtype=np.uint8),
                                    КАДР_БИТ, НЕ_СКРЕМБЛИРУЕТСЯ)


def скремблер(ряд: np.ndarray) -> dict[str, Any] | None:
    """Найти и подтвердить скремблер на выборке выровненных кадров.

    Порядок гипотез: без скремблера; найденный вслепую; запасные по G.709.
    Возвращает первую подтверждённую (с проверками на её выборке) или None.
    """
    выборка = ряд[:min(len(ряд) // КАДР_БИТ, КАДРОВ_СКРЕМБЛЕР) * КАДР_БИТ]
    кадров = len(выборка) // КАДР_БИТ
    гипотезы: list[dict[str, Any]] = [{"отводы": None, "способ": "скремблера нет: MFAS идёт "
                                        "подряд без снятия"}]
    вслепую = "не искался: меньше 8 кадров"
    if кадров >= 8:
        найдено = skrembler.найти_по_кадру(выборка, КАДР_БИТ, пропуск=НЕ_СКРЕМБЛИРУЕТСЯ)
        вслепую = ("не найден: по устойчивым столбцам кадра Берлекэмп — Мэсси не дал "
                   "полинома степени до 64" if найдено is None else "найден")
        if найдено is not None:
            гипотезы.append({"отводы": tuple(найдено["отводы"]),
                             "начальное": np.array([int(c) for c in найдено["начальное"]],
                                                   dtype=np.uint8),
                             "способ": "вслепую — " + str(найдено["способ"]),
                             "вслепую": True})
    for отводы in СТАНДАРТНЫЕ_ОТВОДЫ:
        гипотезы.append({"отводы": отводы, "начальное": СТАНДАРТНОЕ_НАЧАЛЬНОЕ,
                         "способ": "запасная гипотеза по G.709 (сброс в FFFF), "
                                   "подтверждена проверками", "вслепую": False})
    отвергнуто = []
    for г in гипотезы:
        if г["отводы"] is None:
            снятый = выборка
        else:
            снятый = снять(выборка, г["отводы"], г["начальное"])
        п = проверки(в_кадры(снятый))
        if _подтверждено(п):
            return {**г, "отвергнуто": отвергнуто, "поиск_вслепую": вслепую}
        if г["отводы"] is not None:
            отвергнуто.append(skrembler.полином_словами(г["отводы"])
                              + (" (найден вслепую)" if г["вслепую"] else ""))
    return None


# -- разбор заголовков -----------------------------------------------------------------

def _текст(байты: Sequence[int | None]) -> str | None:
    """Печатный текст (ASCII 0x20–0x7E, хвост из нулей/пробелов отброшен) или None.

    Байты, не попавшие в выборку (None), показываются «·»: часть TTI при
    выборке короче сверхцикла из 64 кадров.
    """
    знаки = "".join("·" if б is None else chr(б) for б in байты).rstrip("\0 ")
    if not знаки.strip("·") or any(з != "·" and not " " <= з <= "~" for з in знаки):
        return None
    return знаки


def _шестн(байты: Sequence[int | None]) -> str:
    return " ".join("··" if б is None else f"{б:02X}" for б in байты)


def по_сверхциклу(кадры: np.ndarray, место: tuple[int, int], период: int
                  ) -> list[int | None]:
    """Байт ``место`` по индексу MFAS mod период — большинство по сверхциклам; None — не было."""
    индексы = кадры[:, MFAS[0], MFAS[1]].astype(np.int64) % период
    значения = кадры[:, место[0], место[1]]
    итог: list[int | None] = []
    for i in range(период):
        были = значения[индексы == i]
        итог.append(int(Counter(были.tolist()).most_common(1)[0][0]) if len(были) else None)
    return итог


def tti(кадры: np.ndarray, место: tuple[int, int]) -> dict[str, Any]:
    """TTI (64 байта по MFAS mod 64): SAPI, DAPI, поле оператора — текстом или HEX."""
    байты = по_сверхциклу(кадры, место, 64)
    собрано = sum(б is not None for б in байты)
    части = {}
    # SAPI[0] и DAPI[0] — нулевые байты по G.709, текст — со следующего.
    for имя, от, до in (("SAPI", 1, 16), ("DAPI", 17, 32), ("оператор", 32, 64)):
        кусок = байты[от:до]
        if all(б in (None, 0) for б in кусок):
            continue
        текст = _текст(кусок)
        части[имя] = f"«{текст}»" if текст is not None else _шестн(кусок)
    return {"собрано": собрано, "части": части}


def psi(кадры: np.ndarray) -> dict[str, Any]:
    """PSI по MFAS (0…255); PT = PSI[0], если кадр с MFAS = 0 попал в выборку."""
    байты = по_сверхциклу(кадры, PSI, 256)
    pt = байты[0]
    return {"pt": pt, "имя": ТИПЫ_НАГРУЗКИ.get(pt, "") if pt is not None else "",
            "частный": pt is not None and 0x80 <= pt <= 0x8F}


def jc(кадры: np.ndarray) -> dict[str, Any]:
    """JC (строки 1–3, столбец 16): биты 7–8, решение большинством из трёх."""
    биты = кадры[:, 0:3, JC_СТОЛБЕЦ] & 0x03
    решение = np.full(len(кадры), -1, dtype=np.int64)
    for значение in range(4):
        решение[(биты == значение).sum(axis=1) >= 2] = значение
    return {"решение": решение,
            "счёт": {v: int(np.sum(решение == v)) for v in (0, 1, 2, 3)},
            "без_большинства": int(np.sum(решение < 0)),
            "ненулевых_байт": float(np.mean(кадры[:, 0:3, JC_СТОЛБЕЦ] != 0))}


def нагрузка(кадры: np.ndarray, pt: int | None, решение_jc: np.ndarray
             ) -> tuple[np.ndarray, bool]:
    """Биты нагрузки OPUk (столбцы 17–3824, 4 строки) и учтён ли стаффинг AMP.

    При PT = 0x02 (AMP) и ненулевых JC: 01 — NJO несёт данные (перед PJO),
    11 — PJO пустой; иначе столбцы 17–3824 как есть.
    """
    основа = кадры[:, :, НАГРУЗКА]
    if pt != PT_AMP or not np.any((решение_jc == 1) | (решение_jc == 3)):
        return np.unpackbits(основа.reshape(-1)), False
    куски = []
    for f in range(len(кадры)):
        куски.append(основа[f, :3].reshape(-1))
        if решение_jc[f] == 1:
            куски.append(кадры[f, NJO[0], NJO[1]:NJO[1] + 1])
        куски.append(основа[f, 3, (0 if решение_jc[f] != 3 else 1):])
    return np.unpackbits(np.concatenate(куски)), True


def скорость_k(скорость: float | None) -> tuple[str, float] | None:
    """k по номинальной скорости: («OTU2», отклонение в ppm) или None."""
    if not скорость:
        return None
    for имя, номинал in СКОРОСТИ.items():
        if abs(скорость / номинал - 1) <= СКОРОСТЬ_ДОПУСК:
            return имя, (скорость / номинал - 1) * 1e6
    return None


# -- верхний уровень -------------------------------------------------------------------

def разобрать(биты: np.ndarray) -> dict[str, Any] | None:
    """Полный разбор: граница, скремблер, проверки, заголовки, нагрузка; None — FAS нет."""
    граница = выровнять(биты)
    if граница is None:
        return None
    ряд = граница.pop("ряд")
    скр = скремблер(ряд)
    итог: dict[str, Any] = {**граница, "скремблер": скр}
    if скр is None:
        итог["проверки"] = проверки(в_кадры(ряд[:КАДРОВ_СКРЕМБЛЕР * КАДР_БИТ]))
        return итог
    снятый = ряд if скр["отводы"] is None else снять(ряд, скр["отводы"], скр["начальное"])
    кадры = в_кадры(снятый)
    п = проверки(кадры)
    if п["bip_sm"][0] < ДОЛЯ_ОТ:
        п["bip_sm_где"] = _bip8_где(кадры[:КАДРОВ_ПРОВЕРКА])
    с = psi(кадры)
    стаффинг = jc(кадры)
    биты_нагрузки, amp = нагрузка(кадры, с["pt"], стаффинг["решение"])
    итог.update({"проверки": п, "psi": с, "jc": стаффинг, "amp": amp,
                 "tti_sm": tti(кадры, SM_TTI), "tti_pm": tti(кадры, PM_TTI),
                 "mfas_первый": int(кадры[0, MFAS[0], MFAS[1]]),
                 "нагрузка": биты_нагрузки})
    return итог


def _доля(x: float) -> str:
    return f"{x * 100:.1f} %"


def найти(биты: np.ndarray, скорость: float | None = None) -> Находка | None:
    """OTUk по FAS; скремблер вслепую; MFAS, BIP-8, RS; нагрузка OPUk — дальше битами.

    ``скорость`` (бит/с) — если известна, по ней называется k (OTU1…OTU4).
    """
    р = разобрать(np.asarray(биты, dtype=np.uint8))
    if р is None:
        return None
    п = р["проверки"]
    f = п["fec"]
    k = скорость_k(скорость)
    имя = k[0] if k else "OTUk"
    подробно = [
        f"кадр 4 × 4080 байт (130 560 бит), первый целый — с бита {р['начало']}"
        f"{', поток инвертирован' if р['инверсия'] else ''}; кадров {р['кадров']}; "
        f"FAS F6F6F6282828 на месте в {_доля(р['fas'])} кадров"]
    if k:
        подробно.append(f"{k[0]} по скорости: {скорость / 1e9:.6f} Гбит/с, отклонение от "
                        f"номинала {k[1]:+.0f} ppm")
    elif скорость:
        подробно.append(f"скорость {скорость / 1e9:.6f} Гбит/с не совпала с номиналом "
                        f"OTU1–OTU4 — k не указывается")
    скр = р["скремблер"]
    меры = [р["fas"], п["mfas"], п["bip_sm"][1]]
    if скр is None:
        подробно.append("скремблер не найден и не подтверждён: ни вслепую, ни запасная "
                        "гипотеза G.709 не дали MFAS подряд со сходящимся BIP-8/FEC")
        уверенность = float(np.mean(меры))
        return Находка(уровень="OTN", что=f"OTN (G.709): {имя}, кадр 4×4080 — скремблер не снят",
                       уверенность=уверенность,
                       мера=f"FAS на месте в {_доля(р['fas'])} кадров; MFAS после снятия "
                            f"не подтверждён", подробно=подробно, сверка=уверенность)
    if скр["отводы"] is None:
        подробно.append("скремблер: " + скр["способ"])
    else:
        полином = skrembler.полином_словами(скр["отводы"])
        начальное = "".join(map(str, np.asarray(скр["начальное"]).tolist()))
        сверка_g709 = ("совпадает с G.709 x¹⁶ + x¹² + x³ + x + 1"
                       if tuple(скр["отводы"]) == СТАНДАРТНЫЕ_ОТВОДЫ[0] else
                       "обратный к записи G.709 (другой порядок разрядов)"
                       if tuple(скр["отводы"]) == СТАНДАРТНЫЕ_ОТВОДЫ[1] else
                       "не совпадает с G.709")
        подробно.append(
            f"скремблер аддитивный кадровый, полином {полином} ({сверка_g709}), первые 16 бит "
            f"ПСП после сброса {начальное}"
            f"{' = FFFF, как в G.709' if начальное == '1' * 16 else ''}; сброс на старшем "
            f"бите MFAS, FAS не скремблирован; найден: {скр['способ']}")
        if not скр["вслепую"]:
            подробно.append("поиск скремблера вслепую: " + скр["поиск_вслепую"])
        if скр["отвергнуто"]:
            подробно.append("отвергнуты проверками: " + "; ".join(скр["отвергнуто"]))
    подробно.append(f"MFAS после снятия идёт +1 по модулю 256 в {_доля(п['mfas'])} пар кадров "
                    f"(первый MFAS = {р['mfas_первый']})")
    sm_кадров, sm_бит = п["bip_sm"]
    подробно.append(f"SM BIP-8 (строка 1, столбец 9; по OPUk кадра i, передаётся в кадре i+2): "
                    f"совпал в {_доля(sm_кадров)} кадров, бит — {_доля(sm_бит)} "
                    f"(у случайного ≈ 50 %)")
    if "bip_sm_где" in п:
        место, задержка, доля = п["bip_sm_где"]
        подробно.append(f"для справки: лучше всего BIP-8 сходится в строке 1 столбце "
                        f"{место[1] + 1} с задержкой {задержка} кадр(а) — {_доля(доля)} кадров")
    pm_кадров, pm_бит = п["bip_pm"]
    подробно.append(f"PM BIP-8 (строка 3, столбец 11): совпал в {_доля(pm_кадров)} кадров, "
                    f"бит — {_доля(pm_бит)}")
    if f["используется"]:
        меры.append(f["доля"])
        подробно.append(f"FEC RS(255,239), GF(256) по x⁸+x⁴+x³+x²+1, корни α⁰…α¹⁵, 16 слов на "
                        f"строку с чередованием по байтам: нулевой синдром у "
                        f"{_доля(f['доля'])} из {f['слов']} слов")
        if "корни" in f:
            подробно.append("синдромы RS(255,239) не сходятся — возможно, другой (усиленный) "
                            "FEC; общие корни слов вслепую: "
                            + (", ".join(f"α^{j}" for j in f["корни"]) if f["корни"]
                               else "не найдены"))
    else:
        подробно.append("FEC не используется: столбцы 3825–4080 после снятия скремблера — нули "
                        f"({_доля(f['нулевых_байт'])} байт)")
    for имя_tti, ключ in (("SM TTI", "tti_sm"), ("PM TTI", "tti_pm")):
        т = р[ключ]
        if т["части"]:
            подробно.append(f"{имя_tti} (собрано {т['собрано']} из 64 байт): " + "; ".join(
                f"{ч} {з}" for ч, з in т["части"].items()))
        elif т["собрано"]:
            подробно.append(f"{имя_tti}: пуст (собрано {т['собрано']} из 64 байт)")
    с = р["psi"]
    if с["pt"] is None:
        подробно.append("PT (PSI[0]) не попал в выборку: нет кадра с MFAS = 0")
    else:
        подробно.append(f"тип нагрузки PT = 0x{с['pt']:02X}"
                        + (f" — {с['имя']}" if с["имя"] else
                           " — частное использование" if с["частный"] else ""))
    ст = р["jc"]
    ненулевых = ст["счёт"][1] + ст["счёт"][2] + ст["счёт"][3]
    if ненулевых or ст["ненулевых_байт"] > 0.05:
        строка = (f"JC (строки 1–3, столбец 16): стаффинг есть — биты JC 01 в {ст['счёт'][1]}, "
                  f"11 в {ст['счёт'][3]}, 10 в {ст['счёт'][2]} кадрах из {р['кадров']}")
        строка += ("; учтён по правилам AMP (NJO/PJO)" if р["amp"] else
                   "; нагрузка выдана без снятия стаффинга (PT не AMP или неизвестен)")
        подробно.append(строка)
    else:
        подробно.append("JC (строки 1–3, столбец 16): нулевые — стаффинга нет")
    подробно.append(f"нагрузка OPUk (столбцы 17–3824, 4 строки): {len(р['нагрузка'])} бит — "
                    f"дальше битами")
    уверенность = float(np.mean(меры))
    мера = (f"FAS на месте в {_доля(р['fas'])} кадров, MFAS +1 в {_доля(п['mfas'])} пар, "
            f"SM BIP-8 — {_доля(sm_кадров)} кадров ({_доля(sm_бит)} бит)"
            + (f", нулевой синдром RS(255,239) у {_доля(f['доля'])} слов"
               if f["используется"] else ", FEC не используется"))
    return Находка(
        уровень="OTN",
        что=f"OTN (G.709): {имя}, кадр 4×4080"
            + (f", нагрузка PT 0x{с['pt']:02X}" if с["pt"] is not None else ""),
        уверенность=уверенность, мера=мера, подробно=подробно,
        дальше=р["нагрузка"], вид_дальше="биты", сверка=уверенность)
