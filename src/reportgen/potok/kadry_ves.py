"""Кадры и пакеты этапов автомата — по всему файлу.

Автомат ищет строение по началу файла (выборке, ``razbor.ВЫБОРКА_БИТ``). Битовые этапы со слоем
потом пересчитываются по всему файлу шагами по кускам (``zadaniya.пересчитать_этапы``), а этап с
выходом «кадры» или «пакеты» — здесь: поток прежнего пересчитанного этапа идёт кусками через тот
же разборщик кадров, что нашёл их по выборке; незакрытый кадр (всё после последнего флага)
переносится в следующий кусок, кадры сразу пишутся на диск — в том же виде, что выгрузка этапа
по выборке (``zadaniya.выгрузка``): .sig, .pcap или .ts. Память не растёт с размером файла.

Разборщик — свойство находки «кадры_слой», строкой, как слой стола:

* «hdlc fcs 16|32 порядок старший|младший [инверсия] [nrzi]» — битстаффинг (``hdlc``);
* «ppp fcs 16|32 сдвиг s порядок …» и «slip сдвиг s порядок …» — октетный стаффинг (``oktety``);
* «atm сдвиг s начало b скремблер да|нет» — ячейки ATM, PDU AAL5 с верной CRC-32 (``gfp.atm``);
* «gfp маска M скремблер да|нет|инверсия порядок … [многочлен авто] канал L [upi u]» — кадры
  клиентов GFP окнами с перекрытием (``gfp.разобрать``);
* «bbframe nbch n kbch k t t короткий|нормальный выход ts|gse» — DVB-S2 после LDPC (``dvbs2``);
* «ip» — пакеты IP в кадрах прежнего этапа (.sig или .pcap), «pcap» — пакеты IP захвата pcap (вход).
"""

from __future__ import annotations

import struct
from collections.abc import Callable, Iterator, Sequence
from pathlib import Path
from typing import Any

import numpy as np

from .bity import в_байты

#: Кусок потока, бит (2 МБ данных — как у шагов по кускам).
КУСОК_БИТ = 1 << 24
#: Кусок файла кадров или захвата, байт.
КУСОК_БАЙТ = 1 << 22
#: Незакрытый кадр длиннее — не кадр (флага нет дальше этого): хвост сбрасывается, память не растёт.
ХВОСТ_БИТ_ДО = 1 << 24
#: Окно разбора GFP (бит) и запас перед ним на захват синхронизма и прогрев дескремблера x⁴³.
ОКНО_GFP = 1 << 25
КАДР_GFP_БИТ = (0xFFFF + 4) * 8
ЗАПАС_GFP = 6 * КАДР_GFP_БИТ
#: Ключи строки разборщика (за ключом — значение); остальные слова — признаки.
КЛЮЧИ = ("fcs", "порядок", "сдвиг", "начало", "скремблер", "маска", "многочлен", "канал", "upi", "nbch", "kbch",
         "t", "выход")
#: Пакеты IP в pcap — LINKTYPE_RAW (как выгрузка этапа «пакеты»).
КАНАЛ_IP = 101

Ход = Callable[[float, str], None]


def разобрать_слой(слой: str) -> dict[str, Any]:
    """Строка разборщика → {"вид", ключ: значение, "признаки": {…}}."""
    слова = str(слой).split()
    if not слова:
        raise ValueError("разборщик кадров не задан")
    итог: dict[str, Any] = {"вид": слова[0].lower(), "признаки": set()}
    i = 1
    while i < len(слова):
        if слова[i] in КЛЮЧИ and i + 1 < len(слова):
            итог[слова[i]] = слова[i + 1]
            i += 2
        else:
            итог["признаки"].add(слова[i])
            i += 1
    return итог


def слой_находки(находка: Any) -> str | None:
    """Разборщик кадров находки («кадры_слой»); HDLC, найденный после снятия NRZI, — с признаком nrzi."""
    слой = (находка.свойства or {}).get("кадры_слой")
    if not слой:
        return None
    if str(слой).startswith("hdlc") and (находка.что or "").startswith("NRZI → "):
        слой += " nrzi"
    return str(слой)


def _ниже(путь: str, выше: str) -> bool:
    """Находка с путём ``путь`` разобрана в выходе находки с путём ``выше`` (уровнем ниже)."""
    путь, выше = путь or "", выше or ""
    return путь != выше and (not выше or путь.startswith(выше + " → "))


def пункты_плана(находки: Sequence[Any], список: Sequence[dict[str, Any]],
                 план: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
    """Кадровые этапы — продолжением плана пересчёта (``zadaniya.план_всего_файла``): этап кадров
    сразу после последнего пересчитанного битового этапа (или первый — тогда от входа), и за ним — IP
    в его кадрах. Пункт: {"номер", "шаги" (битовые — до кадров), "кадры" (разборщик), "из" (у IP —
    номер этапа кадров)}. Этап, уже разобранный по всему файлу (свойство «весь_файл»), не повторяется."""
    номер = int(план[-1]["номер"]) + 1 if план else 1
    if номер > min(len(находки), len(список)):
        return []
    находка, запись = находки[номер - 1], список[номер - 1]
    слой = слой_находки(находка)
    if not слой or not запись.get("выгрузка") or (находка.свойства or {}).get("весь_файл"):
        return []
    путь = находка.путь or ""
    шаги: list[dict[str, Any]] = []
    if план:
        if not _ниже(путь, находки[номер - 2].путь):
            return []                                # кадры не в выходе прежнего этапа
    elif путь == "младший бит первым":
        шаги = [{"вид": "слой", "вкл": True, "слой": "реверс 8"}]
    elif путь:
        return []                                    # кадры не в самом входе (притоке, канале…)
    пункты = [{"номер": номер, "шаги": шаги, "кадры": слой}]
    if номер < min(len(находки), len(список)):
        ip, запись_ip = находки[номер], список[номер]
        if (ip.уровень == "сетевой" and ip.вид_дальше == "пакеты" and запись_ip.get("выгрузка") == "pcap"
                and _ниже(ip.путь, путь)):
            пункты.append({"номер": номер + 1, "шаги": [], "кадры": "ip", "из": номер})
    return пункты


# -- запись: тот же вид, что выгрузка этапа по выборке ----------------------------------------

class _Выход:
    """Кадры — в файл: .sig (два байта длины, старший первым, и кадр), .pcap (свой тип канала) или .ts."""

    def __init__(self, куда: Path, вид: str, канал: int | None = None):
        self.вид, self.записей, self.пропущено = вид, 0, 0
        self.файл = open(куда, "wb")  # noqa: SIM115 — закрывает закрыть()
        if вид == "pcap":
            self.файл.write(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, int(канал or КАНАЛ_IP)))

    def записать(self, кадры: Sequence[bytes]) -> None:
        части: list[bytes] = []
        for кадр in кадры:
            if self.вид == "sig":
                if len(кадр) > 0xFFFF:
                    self.пропущено += 1                  # длина в .sig — два байта
                    continue
                части += (struct.pack(">H", len(кадр)), bytes(кадр))
            elif self.вид == "pcap":
                части += (struct.pack("<IIII", 0, 0, len(кадр), len(кадр)), bytes(кадр))
            else:
                части.append(bytes(кадр))
            self.записей += 1
        if части:
            self.файл.write(b"".join(части))

    def закрыть(self) -> None:
        self.файл.close()


# -- разборщики: кусок потока → готовые кадры ---------------------------------------------------

def _пусто() -> np.ndarray:
    return np.zeros(0, dtype=np.uint8)


class _Hdlc:
    """HDLC с битстаффингом: кадры между флагами (``hdlc.кадры``) с верной FCS, без FCS. Хвост — от
    последнего флага: кадр, разрезанный куском, собирается в следующем."""

    def __init__(self, п: dict[str, Any]):
        from . import hdlc  # noqa: PLC0415
        self.hdlc = hdlc
        self.fcs = int(п.get("fcs") or 16)
        self.верна = hdlc.fcs32_верна if self.fcs == 32 else hdlc.fcs16_верна
        self.младший = п.get("порядок") == "младший"
        self.инверсия = "инверсия" in п["признаки"]
        self.nrzi = "nrzi" in п["признаки"]
        self.хвост = _пусто()
        self.прежний: int | None = None              # последний бит прежнего куска (NRZI)

    def подать(self, биты: np.ndarray) -> list[bytes]:
        if not len(биты):
            return []
        биты = np.asarray(биты, dtype=np.uint8)
        if self.nrzi:
            # NRZI (1 — переход) — как lineynye.nrzi над всем рядом: первый бит ряда — 0.
            прежние = np.concatenate([[биты[0] if self.прежний is None else self.прежний], биты[:-1]])
            self.прежний = int(биты[-1])
            биты = (биты != прежние).astype(np.uint8)
        if self.младший:
            биты = self.hdlc._перевернуть_в_байтах(биты)     # куски кратны байту: байты — те же, что у ряда
        if self.инверсия:
            биты = (1 - биты).astype(np.uint8)
        ряд = np.concatenate([self.хвост, биты]) if len(self.хвост) else биты
        места = self.hdlc.флаги(ряд)
        if not len(места):
            self.хвост = ряд[-7:].copy()             # флаг может начаться в конце куска
            return []
        кадры = self.hdlc.кадры(ряд)
        self.хвост = ряд[int(места[-1]):].copy()
        if len(self.хвост) > ХВОСТ_БИТ_ДО:
            self.хвост = self.хвост[-7:].copy()
        n = self.fcs // 8
        return [кадр[:-n] for кадр in кадры if self.верна(кадр)]

    def закончить(self) -> list[bytes]:
        return []                                    # кадр без закрывающего флага — не кадр


class _Октеты:
    """Асинхронное HDLC/PPP (0x7E, экран 0x7D, FCS) и SLIP (0xC0): байты с бита ``сдвиг``, кадры между
    разделителями (``oktety``); часть после последнего разделителя ждёт следующего куска."""

    def __init__(self, п: dict[str, Any], slip: bool):
        from . import hdlc, oktety  # noqa: PLC0415
        self.oktety, self.slip = oktety, slip
        self.разделитель = bytes([oktety.SLIP_КОНЕЦ if slip else oktety.ФЛАГ])
        self.fcs = int(п.get("fcs") or 16)
        self.верна = hdlc.fcs32_верна if self.fcs == 32 else hdlc.fcs16_верна
        self.пропустить = int(п.get("сдвиг") or 0)
        self.порядок = п.get("порядок") or "старший"
        self.биты = _пусто()
        self.хвост = b""
        self.сброшен = False

    def подать(self, биты: np.ndarray) -> list[bytes]:
        if self.пропустить:
            k = min(self.пропустить, len(биты))
            биты, self.пропустить = биты[k:], self.пропустить - k
        ряд = np.concatenate([self.биты, биты]) if len(self.биты) else np.asarray(биты, dtype=np.uint8)
        целых = len(ряд) // 8 * 8
        self.биты = ряд[целых:].copy()
        части = (self.хвост + в_байты(ряд[:целых], self.порядок)).split(self.разделитель)
        self.хвост, тела = части[-1], части[:-1]
        if self.сброшен and тела:
            тела, self.сброшен = тела[1:], False     # конец сброшенного длинного «кадра»
        if len(self.хвост) > ХВОСТ_БИТ_ДО // 8:
            self.хвост, self.сброшен = b"", True
        return self._кадры(тела)

    def закончить(self) -> list[bytes]:
        # Часть после последнего разделителя — тоже тело (как split над всем рядом).
        return [] if self.сброшен else self._кадры([self.хвост])

    def _кадры(self, тела: list[bytes]) -> list[bytes]:
        if not тела:
            return []
        данные = self.разделитель.join(тела)
        if self.slip:
            return self.oktety.кадры_slip(данные)
        n = self.fcs // 8
        return [кадр[:-n] for кадр, _ in self.oktety.кадры_асинхронные(данные) if self.верна(кадр)]


class _Atm:
    """Ячейки ATM (53 байта) с бита ``сдвиг`` и байта ``начало``: нагрузки (при «скремблер да» — без x⁴³ + 1,
    сплошь по всем ячейкам), PDU AAL5 по каналам с верной CRC-32 — как ``gfp._aal5``."""

    def __init__(self, п: dict[str, Any]):
        from .gfp import crc32_bzip2  # noqa: PLC0415
        self.crc = crc32_bzip2
        self.пропустить_бит = int(п.get("сдвиг") or 0)
        self.пропустить_байт = int(п.get("начало") or 0)
        self.скремблер = п.get("скремблер") == "да"
        self.биты = _пусто()
        self.байты = b""
        self.x43: np.ndarray | None = None           # последние 43 бита нагрузок (дескремблер)
        self.собрано: dict[tuple[int, int], bytearray] = {}

    def подать(self, биты: np.ndarray) -> list[bytes]:
        if self.пропустить_бит:
            k = min(self.пропустить_бит, len(биты))
            биты, self.пропустить_бит = биты[k:], self.пропустить_бит - k
        ряд = np.concatenate([self.биты, биты]) if len(self.биты) else np.asarray(биты, dtype=np.uint8)
        целых = len(ряд) // 8 * 8
        self.биты = ряд[целых:].copy()
        данные = self.байты + в_байты(ряд[:целых])
        if self.пропустить_байт:
            k = min(self.пропустить_байт, len(данные))
            данные, self.пропустить_байт = данные[k:], self.пропустить_байт - k
        ячеек = len(данные) // 53
        self.байты = данные[ячеек * 53:]
        if not ячеек:
            return []
        ячейки = np.frombuffer(данные[:ячеек * 53], dtype=np.uint8).reshape(ячеек, 53).copy()
        if self.скремблер:
            x = np.unpackbits(ячейки[:, 5:].reshape(-1))
            if self.x43 is None:
                # Как gfp._снять_x43 над всеми ячейками: первые 43 бита — нули.
                y = np.zeros(len(x), dtype=np.uint8)
                y[43:] = x[43:] ^ x[:-43]
            else:
                ряд_ = np.concatenate([self.x43, x])
                y = ряд_[43:] ^ ряд_[:-43]
            self.x43 = (np.concatenate([self.x43, x]) if self.x43 is not None else x)[-43:].copy()
            ячейки[:, 5:] = np.packbits(y).reshape(-1, 48)
        vpi = ((ячейки[:, 0].astype(int) & 0x0F) << 4) | (ячейки[:, 1] >> 4)
        vci = ((ячейки[:, 1].astype(int) & 0x0F) << 12) | (ячейки[:, 2].astype(int) << 4) | (ячейки[:, 3] >> 4)
        pt = (ячейки[:, 3] >> 1) & 0x07
        итог = []
        for номер, (п, к, т) in enumerate(zip(vpi.tolist(), vci.tolist(), pt.tolist(), strict=True)):
            if (п, к) == (0, 0) or т & 0b100:
                continue                             # пустая ячейка или служебная (OAM)
            self.собрано.setdefault((п, к), bytearray()).extend(ячейки[номер, 5:].tobytes())
            if т & 0b001:                            # последняя ячейка PDU
                pdu = bytes(self.собрано.pop((п, к)))
                длина = int.from_bytes(pdu[-6:-4], "big")
                if self.crc(pdu[:-4]) == int.from_bytes(pdu[-4:], "big"):
                    итог.append(pdu[:длина] if длина <= len(pdu) - 8 else pdu)
        return итог

    def закончить(self) -> list[bytes]:
        return []


class _Bbframe:
    """DVB-S2 после LDPC: слова БЧХ по nbch бит с начала потока (``dvbs2.снять``), поля данных — пакеты TS
    (``dvbs2.СборкаTS``, пакет на стыке кусков собирается) или PDU IP из GSE (фрагменты — между кусками)."""

    def __init__(self, п: dict[str, Any]):
        from . import dvbs2  # noqa: PLC0415
        self.dvbs2 = dvbs2
        self.код = dvbs2.код_слоя(int(п["nbch"]), int(п["kbch"]), int(п["t"]), "короткий" in п["признаки"])
        self.ts = п.get("выход") == "ts"
        self.сборка = dvbs2.СборкаTS()
        self.gse = dvbs2.Gse()
        self.хвост = _пусто()

    def подать(self, биты: np.ndarray) -> list[bytes]:
        ряд = np.concatenate([self.хвост, биты]) if len(self.хвост) else np.asarray(биты, dtype=np.uint8)
        n = self.код.nbch
        слов = len(ряд) // n
        self.хвост = ряд[слов * n:].copy()
        if not слов:
            return []
        к = self.dvbs2.снять(ряд[:слов * n], self.код, кадров=слов)
        итог: list[bytes] = []
        for з, поле in zip(к.заголовки, к.поля, strict=True):
            if self.ts:
                итог += self.сборка.подать(з, поле)
            elif з.crc_верна:
                self.dvbs2.разобрать_gse(поле, self.gse)
        if not self.ts:
            итог = [pdu for тип, pdu in self.gse.pdu if тип in (0x0800, 0x86DD)]
            self.gse.pdu.clear()
        return итог

    def закончить(self) -> list[bytes]:
        return []


class _Pcap:
    """Записи классического pcap кусками байт — как ``karta.pcap``: запись длиннее 256 КБ — конец разбора."""

    def __init__(self) -> None:
        self.буфер = b""
        self.порядок: str | None = None
        self.канал = 0
        self.стоп = False

    def подать(self, данные: bytes) -> list[bytes]:
        if self.стоп:
            return []
        б = self.буфер + данные
        место = 0
        if self.порядок is None:
            if len(б) < 24:
                self.буфер = б
                return []
            if б[:4] in (b"\xd4\xc3\xb2\xa1", b"\x4d\x3c\xb2\xa1"):
                self.порядок = "<"
            elif б[:4] in (b"\xa1\xb2\xc3\xd4", b"\xa1\xb2\x3c\x4d"):
                self.порядок = ">"
            else:
                raise ValueError("вход — не pcap")
            self.канал = struct.unpack(self.порядок + "I", б[20:24])[0] & 0xFFFF
            место = 24
        записи = []
        while место + 16 <= len(б):
            записано = struct.unpack(self.порядок + "I", б[место + 8:место + 12])[0]
            if записано > 262_144:
                self.стоп = True
                break
            if место + 16 + записано > len(б):
                break
            записи.append(б[место + 16:место + 16 + записано])
            место += 16 + записано
        self.буфер = b"" if self.стоп else б[место:]
        return записи


def кадры_файла(путь: str | Path) -> Iterator[tuple[list[bytes], float]]:
    """Кадры выгрузки этапа (.sig или .pcap) пачками — и доля прочитанного файла."""
    путь = Path(путь)
    всего = max(1, путь.stat().st_size)
    прочитано = 0
    with open(путь, "rb") as файл:
        if путь.suffix.lower() == ".pcap":
            разбор = _Pcap()
            while кусок := файл.read(КУСОК_БАЙТ):
                прочитано += len(кусок)
                yield разбор.подать(кусок), прочитано / всего
            return
        буфер = b""
        while кусок := файл.read(КУСОК_БАЙТ):
            прочитано += len(кусок)
            б, место, кадры = буфер + кусок, 0, []
            while место + 2 <= len(б):
                длина = int.from_bytes(б[место:место + 2], "big")
                if место + 2 + длина > len(б):
                    break
                кадры.append(б[место + 2:место + 2 + длина])
                место += 2 + длина
            буфер = б[место:]
            yield кадры, прочитано / всего


def _ip(кадры: Sequence[bytes]) -> list[bytes]:
    """Пакеты IP в кадрах — как ``pakety.найти_в_кадрах`` (голый IP, PPP, Ethernet, LLC/SNAP)."""
    from . import pakety  # noqa: PLC0415
    return [п.сырые for п in (pakety.в_кадре(bytes(к)) for к in кадры) if п is not None]


def _что_выходит(п: dict[str, Any]) -> tuple[str, str]:
    """(расширение выгрузки, слово для счёта)."""
    вид = п["вид"]
    if вид in ("ip", "pcap"):
        return "pcap", "пакетов"
    if вид == "gfp":
        return "pcap", "кадров"
    if вид == "bbframe" and п.get("выход") == "ts":
        return "ts", "пакетов TS"
    return "sig", "кадров"


def кадры_по_всему(источник: Any, свойства: dict[str, Any] | str, куда: str | Path,
                   ход: Ход | None = None) -> dict[str, Any]:
    """Кадры или пакеты этапа — по всему потоку прежнего этапа, файлом ``куда`` (вид — как у выгрузки
    этапа по выборке).

    ``источник`` — биты прежнего этапа (``hranenie.Источник``); у «ip» — файл кадров прежнего этапа
    (.sig или .pcap), у «pcap» — массив самого захвата. ``свойства`` — свойства находки (нужен
    «кадры_слой») или сама строка разборщика. Итог: {"кадров", "выгрузка", "байт", "выход", "пропущено"}.
    """
    слой = свойства.get("кадры_слой") if isinstance(свойства, dict) else свойства
    п = разобрать_слой(str(слой or ""))
    вид = п["вид"]
    расширение, слово = _что_выходит(п)
    куда = Path(куда)

    def сказать(доля: float, выход: _Выход) -> None:
        if ход is not None:
            ход(max(0.0, min(1.0, доля)), f"{слово} {выход.записей}")
    if вид == "gfp":
        выход = _Выход(куда, "pcap", int(п.get("канал") or 0))
        try:
            _gfp_окнами(источник, п, выход, сказать)
        finally:
            выход.закрыть()
    else:
        выход = _Выход(куда, расширение)
        try:
            if вид == "ip":
                for кадры, доля in кадры_файла(источник):
                    выход.записать(_ip(кадры))
                    сказать(доля, выход)
            elif вид == "pcap":
                разбор, прочитано = _Pcap(), 0
                for данные in источник.байты_кусками(КУСОК_БАЙТ):
                    прочитано += len(данные)
                    выход.записать(_ip(разбор.подать(данные)))
                    сказать(прочитано / max(1, источник.байт), выход)
            else:
                разборщик = _разборщик(п)
                сделано = 0
                for биты in источник.куски(КУСОК_БИТ):
                    сделано += len(биты)
                    выход.записать(разборщик.подать(биты))
                    сказать(сделано / max(1, источник.бит), выход)
                выход.записать(разборщик.закончить())
        finally:
            выход.закрыть()
    return {"кадров": выход.записей, "выгрузка": расширение, "байт": куда.stat().st_size,
            "выход": f"{выход.записей} {слово}", "пропущено": выход.пропущено}


def _разборщик(п: dict[str, Any]):
    вид = п["вид"]
    if вид == "hdlc":
        return _Hdlc(п)
    if вид in ("ppp", "slip"):
        return _Октеты(п, slip=вид == "slip")
    if вид == "atm":
        return _Atm(п)
    if вид == "bbframe":
        return _Bbframe(п)
    raise ValueError(f"разборщик кадров «{вид}» не известен")


def _gfp_окнами(источник: Any, п: dict[str, Any], выход: _Выход, сказать: Callable[[float, _Выход], None]) -> None:
    """GFP окнами по ``ОКНО_GFP`` бит (``gfp.разобрать`` с маской, скремблером и порядком находки): из окна —
    кадры, чей заголовок в его части [от, до); следующее окно начинается за ``ЗАПАС_GFP`` до «до» — на захват
    синхронизма и прогрев дескремблера, кадр на стыке окон берётся целиком из прежнего."""
    from . import gfp  # noqa: PLC0415
    маска = int(str(п["маска"]), 16)
    скремблер = п.get("скремблер") or "авто"
    порядок = п.get("порядок") or "авто"
    многочлен = "авто" if п.get("многочлен") == "авто" else "стандарт"
    канал = int(п.get("канал") or gfp.LINKTYPE_GFP_F)
    upi = int(п["upi"]) if п.get("upi") not in (None, "") else None
    всего = int(источник.бит)
    начало, от = 0, 0
    while начало < всего:
        конец = min(всего, начало + ОКНО_GFP)
        последнее = конец >= всего
        до = всего if последнее else конец - КАДР_GFP_БИТ
        р = gfp.разобрать(источник.биты(начало, конец), маска=маска, скремблер=скремблер, порядок=порядок,
                          многочлен=многочлен, от_бита=начало, всего_бит=всего)
        if р is not None:
            места = р.выделение.места
            свои = {i for i in р.кадры if от <= р.бит(места[i]) < до}
            if канал == gfp.LINKTYPE_GFP_F or upi is None:
                кадры = [gfp.кадр_gfp(р, i) for i, к in sorted(р.кадры.items())
                         if i in свои and not к.прогрев and not к.оборван and к.thec != "ошибка"]
            else:
                кадры = []
                for к in р.клиенты():
                    if к.номер not in свои:
                        continue
                    if к.upi != upi:
                        выход.пропущено += 1          # клиент другого вида: в pcap один тип канала
                        continue
                    кадры.append(к.данные[:-4] if upi == 1 and gfp.fcs_ethernet_верна(к.данные) else к.данные)
            выход.записать(кадры)
        сказать(до / max(1, всего), выход)
        if последнее:
            break
        от = до
        начало = max(начало + 8, (до - ЗАПАС_GFP) // 8 * 8)


# -- пересчёт этапа в исполнителе ---------------------------------------------------------------

def пересчитать_этап(папка: str | Path, пункт: dict[str, Any], источник: Any, ход: Ход) -> None:
    """Кадровый пункт плана (``пункты_плана``) — в ``zadaniya.пересчитать_этапы``: битовые шаги пункта (если
    есть) по кускам, кадры — по всему потоку, выгрузка подменяет выборочный «этап-N.*»; метка «весь-N.бит»
    (число кадров) — этап готов (после перезапуска сервера не повторяется); сервер узнаёт сообщением «кадры»."""
    from ..fayly import записать_атомарно  # noqa: PLC0415
    from . import ispolniteli  # noqa: PLC0415
    from .hranenie import Источник  # noqa: PLC0415
    from .zadaniya import _заменить  # noqa: PLC0415
    папка = Path(папка)
    номер = int(пункт["номер"])
    п = разобрать_слой(пункт["кадры"])
    расширение, слово = _что_выходит(п)
    метка = папка / f"весь-{номер}.бит"
    if метка.exists():
        файл = папка / f"этап-{номер}.{расширение}"
        if файл.exists():
            ispolniteli.сообщить("кадры", {"номер": номер, "выход": f"{int(метка.read_text(encoding='utf-8'))} {слово}",
                                           "выгрузка": расширение, "выгрузка_байт": файл.stat().st_size})
        return                                       # пересчитан до перезапуска сервера
    временные: list[Path] = []
    try:
        if пункт.get("из"):
            источник = next(iter(sorted(папка.glob(f"этап-{int(пункт['из'])}.*"))), None)
            if источник is None:
                raise ValueError(f"нет выгрузки этапа {пункт['из']}")
        elif пункт.get("шаги"):
            from .potokovo import выполнить  # noqa: PLC0415
            биты = папка / f"весь-{номер}.биты"
            временные.append(биты)
            бит, _ = выполнить(источник, пункт["шаги"], биты, ход=lambda д, с: ход(д / 2, с))
            источник = Источник(биты, бит=бит)
            ход_ = ход
            ход = lambda д, с: ход_(0.5 + д / 2, с)  # noqa: E731
        временный = папка / f"весь-{номер}.tmp"
        временные.append(временный)
        итог = кадры_по_всему(источник, пункт["кадры"], временный, ход)
        файл = папка / f"этап-{номер}.{итог['выгрузка']}"
        for прежний in папка.glob(f"этап-{номер}.*"):
            if прежний != файл:
                прежний.unlink(missing_ok=True)
        _заменить(временный, файл)
    finally:
        for путь in временные:
            путь.unlink(missing_ok=True)
    записать_атомарно(метка, str(итог["кадров"]))
    ispolniteli.сообщить("кадры", {"номер": номер, "выход": итог["выход"], "выгрузка": итог["выгрузка"],
                                   "выгрузка_байт": итог["байт"]})
