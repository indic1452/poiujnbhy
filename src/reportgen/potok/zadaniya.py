"""Задания разбора потока для страницы «Разбор потока»: в фоне, по этапам.

Разбор потока занимает от секунд до десятков минут, и держать ради него
запрос нельзя. Поэтому — задания: файл принят, задание встало в очередь,
страница спрашивает его состояние и показывает этапы по мере того, как
они находятся, и журнал: что анализатор пробует прямо сейчас.

Одно задание идёт за раз: разбор занимает процессор целиком, два
параллельных шли бы оба вдвое дольше. Остальные ждут в очереди.

Каждое задание лежит в своей папке: исходный файл, результат (JSON) и
потоки после этапов — чтобы их можно было скачать и продолжить разбор с
любого этапа, в том числе сняв слой вручную. Задания переживают
перезапуск сервера: состояние читается из папки.
"""

from __future__ import annotations

import json
import queue
import secrets
import struct
import threading
import time
from collections.abc import Sequence
from pathlib import Path
from typing import Any

import numpy as np

#: Сколько последних строк журнала хода держать.
ЖУРНАЛ = 400
#: Сколько заданий хранить на пользователя (старые удаляются).
ХРАНИТЬ = 30


def _упаковать_биты(биты: np.ndarray) -> bytes:
    return np.packbits(np.asarray(биты, dtype=np.uint8)).tobytes()


def выгрузка(дальше: Any, вид: str) -> tuple[bytes, str] | None:
    """Что отдать на скачивание после этапа: (байты, расширение)."""
    if дальше is None:
        return None
    if вид in ("биты",) and len(дальше):
        return _упаковать_биты(дальше), "bin"
    if вид == "кадры" and len(дальше) and getattr(дальше, "канал", None):
        # Кадры канального протокола (MTP2, LAPD, FR, AX.25) — pcap с его типом канала.
        заголовок = struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, дальше.канал)
        return заголовок + b"".join(struct.pack("<IIII", 0, 0, len(к), len(к)) + bytes(к)
                                    for к in дальше), "pcap"
    if вид == "кадры" and len(дальше):
        # Как .Sig: два байта длины (старший первым) и кадр.
        return b"".join(struct.pack(">H", len(к)) + bytes(к) for к in дальше), "sig"
    if вид == "пакеты" and len(дальше):
        сырые = [getattr(п, "сырые", None) for п in дальше]
        if all(с is not None for с in сырые):
            заголовок = struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 65535, 101)
            записи = b"".join(struct.pack("<IIII", 0, 0, len(с), len(с)) + с for с in сырые)
            return заголовок + записи, "pcap"
    if вид == "пакеты TS" and len(дальше):
        return np.asarray(дальше, dtype=np.uint8).tobytes(), "ts"
    if вид == "притоки" and isinstance(дальше, dict) and дальше:
        первый = next(iter(дальше.values()))
        return _упаковать_биты(первый), "bin"
    return None


#: Сколько притоков этапа хранить по отдельности (у STM-1 — 63 TU-12).
ПРИТОКОВ_ДО = 256
#: Сколько записей журнала массива хранить на этап.
ЖУРНАЛ_СТОЛА = 300


class Задания:
    """Очередь заданий разбора с журналом хода и этапами."""

    def __init__(self, папка: Path):
        from . import ldpc  # noqa: PLC0415
        self.папка = Path(папка)
        # Матрицы LDPC, загруженные аналитиками, — в своей папке рядом (она
        # идёт в резервную копию, разборы — нет): слой «ldpc ИМЯ» находит их по имени.
        ldpc.КАТАЛОГ = self.папка.parent / "ldpc"
        self._lock = threading.Lock()
        self._очередь: queue.Queue[str] = queue.Queue()
        self._журналы: dict[str, list[str]] = {}
        self._поток: threading.Thread | None = None
        self._идёт: str = ""

    # -- приём ------------------------------------------------------------

    def создать(self, *, владелец: int, имя: str, данные: bytes, профиль: str = "обычно",
                снять: Sequence[str] = (), от: str = "", символ: Sequence[int] = (),
                фм: Sequence[int] = (),
                разбирать: bool = True, происхождение: Sequence[str] = (),
                шаги: Sequence[dict[str, Any]] = ()) -> str:
        """Новое задание.

        ``шаги`` — ручная обработка производного потока (канал по маске,
        снятые слои): ``данные`` — поток, к которому они применяются (он
        хранится как «исходник.bin» — узел можно пересобрать и без родителя),
        результат — «вход.bin». ``разбирать=False`` — без автомата: шаги
        выполняются сразу в своём потоке, не дожидаясь очереди разборов.
        """
        ид = time.strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)
        папка = self.папка / ид
        папка.mkdir(parents=True, exist_ok=True)
        (папка / ("исходник.bin" if шаги else "вход.bin")).write_bytes(данные)
        self._записать(ид, {"ид": ид, "владелец": владелец, "имя": имя, "профиль": профиль,
                            "снять": list(снять), "от": от, "состояние": "ждёт",
                            "символ": [int(k) for k in символ], "фм": [int(k) for k in фм],
                            "разбирать": bool(разбирать),
                            "происхождение": list(происхождение),
                            "шаги": [dict(ш) for ш in шаги],
                            "создано": time.time(), "байт": len(данные), "этапы": [],
                            "отчёт": "", "ошибка": ""})
        with self._lock:
            self._журналы[ид] = []
        if not разбирать:
            threading.Thread(target=self._только_шаги, args=(ид,), daemon=True,
                             name="reportgen-potok-shagi").start()
        else:
            self._очередь.put(ид)
            self._запустить()
        self._прибрать(владелец)
        return ид

    def _выполнить_шаги(self, ид: str) -> None:
        """Шаги ручной обработки: исходник.bin → вход.bin, описание — в «происхождение»."""
        from .rastr import применить  # noqa: PLC0415
        состояние = self._прочитать_файл(ид)
        if not состояние.get("шаги"):
            return
        папка = self.папка / ид
        биты = np.unpackbits(np.frombuffer((папка / "исходник.bin").read_bytes(), dtype=np.uint8))
        биты, описание = применить(биты, состояние["шаги"], ход=lambda с: self._ход(ид, с))
        данные = np.packbits(биты).tobytes()
        (папка / "вход.bin").write_bytes(данные)
        состояние = self._прочитать_файл(ид)
        состояние.update(происхождение=описание, байт=len(данные))
        self._записать(ид, состояние)
        self._ход(ид, f"шаги выполнены: {len(биты)} бит")

    def _только_шаги(self, ид: str) -> None:
        try:
            состояние = self._прочитать_файл(ид)
            состояние.update(состояние="идёт", начато=time.time())
            self._записать(ид, состояние)
            self._выполнить_шаги(ид)
            состояние = self._прочитать_файл(ид)
            состояние.update(состояние="готово", закончено=time.time())
        except FileNotFoundError:
            return                                   # узел удалили, пока шли шаги
        except Exception as ошибка:                  # noqa: BLE001 — поток не роняет приложение
            состояние = self._прочитать_файл(ид)
            состояние.update(состояние="ошибка", ошибка=str(ошибка))
        self._записать(ид, состояние)

    def продолжить(self, ид: str, этап: int, *, владелец: int, снять: Sequence[str] = (),
                   профиль: str = "обычно") -> str:
        """Новое задание — с потока после этапа ``этап`` (1…), со снятием слоёв."""
        состояние = self.прочитать(ид)
        файл = self._выгрузка_этапа(ид, этап)
        if файл is None or файл.suffix != ".bin":
            raise ValueError("после этого этапа нет битового потока — продолжать не с чего")
        имя = f"{состояние['имя']} → этап {этап}"
        return self.создать(владелец=владелец, имя=имя, данные=файл.read_bytes(),
                            профиль=профиль, снять=снять, от=f"{ид}#{этап}")

    # -- чтение -----------------------------------------------------------

    def прочитать(self, ид: str) -> dict[str, Any]:
        путь = self.папка / ид / "состояние.json"
        if not путь.exists():
            raise KeyError(ид)
        состояние = json.loads(путь.read_text(encoding="utf-8"))
        with self._lock:
            состояние["журнал"] = list(self._журналы.get(ид, []))[-80:]
            if состояние["состояние"] == "ждёт":
                состояние["перед_ним"] = list(self._очередь.queue).index(ид) \
                    if ид in self._очередь.queue else 0
        return состояние

    def список(self, владелец: int | None = None) -> list[dict[str, Any]]:
        итог = []
        if not self.папка.exists():
            return итог
        for папка in sorted(self.папка.iterdir(), reverse=True):
            путь = папка / "состояние.json"
            if not путь.exists():
                continue
            с = json.loads(путь.read_text(encoding="utf-8"))
            if владелец is not None and с.get("владелец") != владелец:
                continue
            итог.append({к: с.get(к) for к in ("ид", "имя", "состояние", "создано", "байт",
                                                 "профиль", "от", "снять", "разбирать")}
                        | {"этапов": len(с.get("этапы") or []), "шаги": с.get("шаги") or []})
        return итог

    # -- дерево обработки -----------------------------------------------------

    def дерево(self, ид: str, владелец: int) -> dict[str, Any]:
        """Всё дерево, в котором стоит узел: корень, этапы-развилки и производные.

        Узел — задание; его дети — задания с «от» = «ид#этап». Родителя,
        которого удалили, нет — тогда корнем становится ближайший живой.
        """
        все = {з["ид"]: з for з in self.список(владелец)}
        if ид not in все:
            raise KeyError(ид)
        корень = ид
        while True:
            родитель = (все[корень].get("от") or "").split("#")[0]
            if родитель not in все:
                break
            корень = родитель
        дети: dict[str, list[dict[str, Any]]] = {}
        for з in все.values():
            родитель = (з.get("от") or "").split("#")[0]
            if родитель in все:
                дети.setdefault(родитель, []).append(з)

        def кратко(ид_: str) -> dict[str, Any]:
            """Этапы узла коротко — для сетки массивов на рабочем столе."""
            try:
                с = self._прочитать_файл(ид_)
            except (OSError, ValueError):
                return {"этапы_кратко": [], "происхождение": []}
            return {"этапы_кратко": [{к: э.get(к) for к in ("номер", "уровень", "что", "выход", "выгрузка",
                                                           "уверенность")}
                                     | {"притоков": len(э.get("притоки") or [])}
                                     for э in с.get("этапы") or []],
                    "происхождение": с.get("происхождение") or []}

        def узел(з: dict[str, Any]) -> dict[str, Any]:
            от = з.get("от") or ""
            return {**з, **кратко(з["ид"]), "этап_родителя": int(от.split("#")[1]) if "#" in от else None,
                    "дети": [узел(д) for д in sorted(дети.get(з["ид"], []),
                                                     key=lambda д: д.get("создано") or 0)]}

        return узел(все[корень])

    def удалить(self, ид: str, владелец: int) -> list[str]:
        """Удалить узел и всю ветвь под ним. Идущий разбор не трогаем."""
        дерево = self.дерево(ид, владелец)

        def найти(у: dict[str, Any]) -> dict[str, Any] | None:
            if у["ид"] == ид:
                return у
            for д in у["дети"]:
                н = найти(д)
                if н:
                    return н
            return None

        def все_ид(у: dict[str, Any]) -> list[str]:
            return [у["ид"]] + [и for д in у["дети"] for и in все_ид(д)]

        удаляемые = все_ид(найти(дерево))
        with self._lock:
            if self._идёт in удаляемые:
                raise ValueError("в этой ветви идёт разбор — дождитесь его конца")
        for и in удаляемые:
            папка = self.папка / и
            for файл in папка.iterdir():
                файл.unlink()
            папка.rmdir()
            with self._lock:
                self._журналы.pop(и, None)
        return удаляемые

    def файл_этапа(self, ид: str, этап: int) -> Path | None:
        return self._выгрузка_этапа(ид, этап)

    # -- журнал массива на рабочем столе ------------------------------------------

    def журнал_стола(self, ид: str) -> dict[str, list[dict[str, Any]]]:
        """Записи аналитика и итоги операций по массивам узла: {этап: [записи]}."""
        путь = self.папка / ид / "журнал-стола.json"
        if not путь.exists():
            return {}
        try:
            return json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            return {}

    def записать_в_журнал(self, ид: str, этап: int, запись: dict[str, Any]) -> dict[str, Any]:
        if not (self.папка / ид).exists():
            raise KeyError(ид)
        чистая = {"время": time.time(), "операция": str(запись.get("операция", ""))[:200],
                  "текст": str(запись.get("текст", ""))[:20000],
                  "слой": str(запись.get("слой", ""))[:2000]}
        with self._lock:
            журнал = self.журнал_стола(ид)
            записи = журнал.setdefault(str(int(этап)), [])
            записи.append(чистая)
            del записи[:-ЖУРНАЛ_СТОЛА]
            путь = self.папка / ид / "журнал-стола.json"
            временный = путь.with_suffix(".tmp")
            временный.write_text(json.dumps(журнал, ensure_ascii=False), encoding="utf-8")
            временный.replace(путь)
        return чистая

    def приток(self, ид: str, этап: int, номер: int) -> tuple[bytes, str]:
        """Байты притока этапа и его имя."""
        состояние = self.прочитать(ид)
        этапы = состояние.get("этапы") or []
        if not 1 <= int(этап) <= len(этапы):
            raise ValueError("нет такого этапа")
        притоки = этапы[int(этап) - 1].get("притоки") or []
        запись = next((п for п in притоки if п["номер"] == int(номер)), None)
        файл = self.папка / ид / f"приток-{int(этап)}-{int(номер)}.bin"
        if запись is None or not файл.exists():
            raise ValueError("у этого этапа нет такого притока")
        return файл.read_bytes(), запись["имя"]

    def биты(self, ид: str, этап: int) -> np.ndarray:
        """Биты потока: этап 0 — исходный файл, дальше — поток после этапа (.bin)."""
        if int(этап) == 0:
            данные = (self.папка / ид / "вход.bin").read_bytes()
        else:
            файл = self._выгрузка_этапа(ид, этап)
            if файл is None or файл.suffix != ".bin":
                raise ValueError("у этого этапа нет битового потока")
            данные = файл.read_bytes()
        return np.unpackbits(np.frombuffer(данные, dtype=np.uint8))

    # -- работа -----------------------------------------------------------

    def _запустить(self) -> None:
        with self._lock:
            if self._поток is None or not self._поток.is_alive():
                self._поток = threading.Thread(target=self._работать, name="reportgen-potok",
                                               daemon=True)
                self._поток.start()

    def _работать(self) -> None:
        while True:
            try:
                ид = self._очередь.get(timeout=5)
            except queue.Empty:
                return
            if not (self.папка / ид / "состояние.json").exists():
                continue                         # узел удалили, пока он ждал
            with self._lock:
                self._идёт = ид
            try:
                self._выполнить_шаги(ид)
                self._разобрать(ид)
            except FileNotFoundError:
                pass
            except Exception as ошибка:          # noqa: BLE001 — поток не роняет приложение
                try:
                    состояние = self._прочитать_файл(ид)
                    состояние.update(состояние="ошибка", ошибка=str(ошибка))
                    self._записать(ид, состояние)
                except FileNotFoundError:
                    pass
            finally:
                with self._lock:
                    self._идёт = ""

    def _ход(self, ид: str, строка: str) -> None:
        with self._lock:
            журнал = self._журналы.setdefault(ид, [])
            журнал.append(time.strftime("%H:%M:%S ") + строка)
            del журнал[:-ЖУРНАЛ]

    def _разобрать(self, ид: str) -> None:
        from .razbor import разобрать, этапы  # noqa: PLC0415 — тяжёлый импорт

        состояние = self._прочитать_файл(ид)
        состояние.update(состояние="идёт", начато=time.time())
        self._записать(ид, состояние)
        папка = self.папка / ид
        найдено: list[dict[str, Any]] = []

        def ход(строка: str) -> None:
            self._ход(ид, строка)

        def этап(находка) -> None:
            # Этап найден — сразу на страницу, не дожидаясь конца разбора.
            найдено.append({"уровень": находка.уровень, "что": находка.что,
                            "мера": находка.мера})
            текущее = self._прочитать_файл(ид)
            текущее["найдено_пока"] = list(найдено)
            self._записать(ид, текущее)

        разбор = разобрать(папка / "вход.bin", имя=состояние["имя"],
                           профиль=состояние.get("профиль", "обычно"),
                           снять=состояние.get("снять") or (), ход=ход, этап=этап,
                           символ=состояние.get("символ") or (), фм=состояние.get("фм") or ())
        список = этапы(разбор)
        for номер, (запись, находка) in enumerate(zip(список, разбор.находки, strict=False), start=1):
            выгружено = выгрузка(находка.дальше, находка.вид_дальше)
            if выгружено is not None:
                данные, расширение = выгружено
                (папка / f"этап-{номер}.{расширение}").write_bytes(данные)
                запись["выгрузка"] = расширение
                запись["выгрузка_байт"] = len(данные)
            if находка.вид_дальше == "притоки" and isinstance(находка.дальше, dict):
                # Каждый приток — своим файлом: скачать или разобрать отдельным узлом.
                запись["притоки"] = []
                for k, (имя, ряд) in enumerate(list(находка.дальше.items())[:ПРИТОКОВ_ДО]):
                    (папка / f"приток-{номер}-{k}.bin").write_bytes(_упаковать_биты(ряд))
                    запись["притоки"].append({"номер": k, "имя": str(имя), "бит": int(len(ряд))})
        состояние = self._прочитать_файл(ид)
        состояние.update(состояние="готово", этапы=список, отчёт=разбор.отчёт(предел=60000),
                         секунд=разбор.секунд, закончено=time.time(),
                         карта=(разбор.карта.подробно if разбор.карта else []),
                         не_найдено=разбор.не_найдено, ограничения=разбор.ограничения,
                         содержимое=разбор.содержимое)
        self._записать(ид, состояние)
        self._ход(ид, f"готово за {разбор.секунд:.1f} с: этапов {len(список)}")

    # -- хранение ---------------------------------------------------------

    def _выгрузка_этапа(self, ид: str, этап: int) -> Path | None:
        for путь in (self.папка / ид).glob(f"этап-{int(этап)}.*"):
            return путь
        return None

    def _прочитать_файл(self, ид: str) -> dict[str, Any]:
        return json.loads((self.папка / ид / "состояние.json").read_text(encoding="utf-8"))

    def _записать(self, ид: str, состояние: dict[str, Any]) -> None:
        путь = self.папка / ид / "состояние.json"
        временный = путь.with_suffix(".tmp")
        временный.write_text(json.dumps(состояние, ensure_ascii=False), encoding="utf-8")
        временный.replace(путь)

    def _прибрать(self, владелец: int) -> None:
        свои = [з for з in self.список(владелец) if з["состояние"] in ("готово", "ошибка")]
        for лишнее in свои[ХРАНИТЬ:]:
            папка = self.папка / лишнее["ид"]
            for файл in папка.iterdir():
                файл.unlink()
            папка.rmdir()
