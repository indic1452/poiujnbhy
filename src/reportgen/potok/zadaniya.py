# -- ветки дерева обработки: что лежит под узлом таблицы массивов ----------------------

def _узел_дерева(у: dict[str, Any], ид: str) -> dict[str, Any] | None:
    """Узел задания ``ид`` в дереве (от ``дерево``/``деревья_сессии``)."""
    if у["ид"] == ид:
        return у
    for д in у["дети"]:
        н = _узел_дерева(д, ид)
        if н:
            return н
    return None


def _ид_ветви(у: dict[str, Any]) -> list[str]:
    """Задание узла и все задания под ним — родители раньше детей."""
    return [у["ид"]] + [и for д in у["дети"] for и in _ид_ветви(д)]


def _узлы_ветви(у: dict[str, Any]) -> list[dict[str, Any]]:
    """Узел задания и все узлы под ним — родители раньше детей."""
    return [у] + [н for д in у["дети"] for н in _узлы_ветви(д)]


def _массивов(у: dict[str, Any]) -> int:
    """Сколько массивов (узлов сетки) в ветви задания: вход, выход каждого этапа и всё под ними."""
    return 1 + len(у["этапы_кратко"]) + sum(_массивов(д) for д in у["дети"])


def _без_этапов_с(путь: Path, этап: int) -> None:
    """Журнал или разметка массивов задания ({этап: …}) — без этапов с ``этап`` и дальше."""
    if not путь.exists():
        return
    try:
        все = json.loads(путь.read_text(encoding="utf-8"))
    except ValueError:
        return                                   # битый файл читается как пустой — его и не трогаем
    записать_атомарно(путь, json.dumps({к: в for к, в in все.items() if int(к) < этап}, ensure_ascii=False))


# -- что делает исполнитель (процесс): функции уровня модуля, аргументы — пути и словари --------

def каталоги_рядом(папка_заданий: Path) -> dict[str, str]:
    """Папки матриц LDPC и плоскостей моддекодера рядом с заданиями — их видит и исполнитель."""
    return {"ldpc": str(Path(папка_заданий).parent / "ldpc"),
            "ploskosti": str(Path(папка_заданий).parent / "ploskosti")}


def применить_каталоги(каталоги: dict[str, str]) -> None:
    """В исполнителе: те же папки матриц и плоскостей, что у сервера (свои файлы отдела)."""
    from . import ldpc, moddekoder  # noqa: PLC0415
    if каталоги.get("ldpc"):
        ldpc.КАТАЛОГ = Path(каталоги["ldpc"])
    if каталоги.get("ploskosti"):
        moddekoder.КАТАЛОГ = Path(каталоги["ploskosti"])


def в_исполнителе(каталоги: dict[str, str], функция: Callable[..., Any], args: tuple, kwargs: dict) -> Any:
    """Обёртка задачи стола: папки отдела — как у сервера, затем сам расчёт."""
    применить_каталоги(каталоги)
    return функция(*args, **kwargs)


def _прочитать_состояние(папка: Path) -> dict[str, Any]:
    return json.loads((папка / "состояние.json").read_text(encoding="utf-8"))


def _записать_состояние(папка: Path, состояние: dict[str, Any]) -> None:
    записать_атомарно(папка / "состояние.json", json.dumps(состояние, ensure_ascii=False))


def _ход_в_сервер(строка: str) -> None:
    """Строка журнала хода — в сервер (там её видит страница); отменённый разбор здесь и останавливается."""
    ispolniteli.сообщить("ход", time.strftime("%H:%M:%S ") + строка)


def выполнить_шаги(папка: Path, ход: Callable[[str], None] = _ход_в_сервер) -> None:
    """Шаги ручной обработки: исходник.bin → вход.bin, описание — в «происхождение»."""
    from .rastr import применить  # noqa: PLC0415
    состояние = _прочитать_состояние(папка)
    if not состояние.get("шаги"):
        return
    биты = np.unpackbits(np.frombuffer((папка / "исходник.bin").read_bytes(), dtype=np.uint8))
    if isinstance(состояние.get("исходных_бит"), int):
        биты = биты[:состояние["исходных_бит"]]
    биты, описание = применить(биты, состояние["шаги"], ход=ход)
    данные = np.packbits(биты).tobytes()
    записать_атомарно(папка / "вход.bin", данные)
    состояние = _прочитать_состояние(папка)
    # Точная длина в битах: файл — целые байты, хвост последнего дополнен нулями.
    состояние.update(происхождение=описание, байт=len(данные), бит=int(len(биты)))
    _записать_состояние(папка, состояние)
    ход(f"шаги выполнены: {len(биты)} бит")


#: Метка «остановить автомат» в папке задания: сервер кладёт её, разбор в исполнителе (процессе или
#: нити) видит её и кончается с тем, что уже нашёл, — как по исчерпанию времени.
СТОП_ФАЙЛ = "стоп"
#: Как часто разбор смотрит, не положили ли метку, секунд.
СТОП_КАЖДЫЕ = 0.5


def _ждать_стопа(стоп: Path, готово: threading.Event) -> None:
    """Пока идёт разбор: появилась метка — исчерпать бюджет текущего разбора (после текущей проверки
    он выдаёт то, что нашёл)."""
    from .razbor import _ТЕКУЩИЙ  # noqa: PLC0415 — тяжёлый импорт
    while not готово.wait(СТОП_КАЖДЫЕ):
        if стоп.exists() and _ТЕКУЩИЙ.бюджет is not None:
            _ТЕКУЩИЙ.бюджет.исчерпан = True
            _ТЕКУЩИЙ.бюджет.конец = 0.0
            return


def разобрать_задание(папка: Path, ход: Callable[[str], None] = _ход_в_сервер) -> dict[str, Any]:
    """Автоматический разбор входа задания: этапы — по мере нахождения, файлы этапов; итог — словарем
    для состояния (его записывает сервер, когда примет итог: «готово» на диске — значит, задание
    уже не занято исполнителем)."""
    from .razbor import разобрать, этапы  # noqa: PLC0415 — тяжёлый импорт

    состояние = _прочитать_состояние(папка)
    найдено: list[dict[str, Any]] = []
    стоп = папка / СТОП_ФАЙЛ
    стоп.unlink(missing_ok=True)                 # метка от прерванного прежнего разбора — не в счёт
    готово = threading.Event()
    threading.Thread(target=_ждать_стопа, args=(стоп, готово), name="reportgen-stop", daemon=True).start()

    def этап(находка) -> None:
        # Этап найден — сразу на страницу, не дожидаясь конца разбора.
        найдено.append({"уровень": находка.уровень, "что": находка.что, "мера": находка.мера})
        текущее = _прочитать_состояние(папка)
        текущее["найдено_пока"] = list(найдено)
        _записать_состояние(папка, текущее)

    try:
        разбор = разобрать(папка / "вход.bin", имя=состояние["имя"], профиль=состояние.get("профиль", "обычно"),
                           снять=состояние.get("снять") or (), ход=ход, этап=этап,
                           символ=состояние.get("символ") or (), фм=состояние.get("фм") or ())
    finally:
        готово.set()
        стоп.unlink(missing_ok=True)
    список = этапы(разбор)
    for номер, (запись, находка) in enumerate(zip(список, разбор.находки, strict=False), start=1):
        выгружено = выгрузка(находка.дальше, находка.вид_дальше)
        if выгружено is not None:
            данные, расширение = выгружено
            записать_атомарно(папка / f"этап-{номер}.{расширение}", данные)
            запись["выгрузка"] = расширение
            запись["выгрузка_байт"] = len(данные)
        if находка.вид_дальше == "притоки" and isinstance(находка.дальше, dict):
            # Каждый приток — своим файлом: скачать или разобрать отдельным узлом.
            запись["притоки"] = []
            for k, (имя, ряд) in enumerate(list(находка.дальше.items())[:ПРИТОКОВ_ДО]):
                записать_атомарно(папка / f"приток-{номер}-{k}.bin", _упаковать_биты(ряд))
                запись["притоки"].append({"номер": k, "имя": str(имя), "бит": int(len(ряд))})
    ход(f"готово за {разбор.секунд:.1f} с: этапов {len(список)}")
    return {"состояние": "готово", "этапы": список, "отчёт": разбор.отчёт(предел=60000),
            "секунд": разбор.секунд, "закончено": time.time(),
            "карта": (разбор.карта.подробно if разбор.карта else []),
            "не_найдено": разбор.не_найдено, "ограничения": разбор.ограничения,
            "содержимое": разбор.содержимое}


def выполнить_задание(папка: str, каталоги: dict[str, str], разбирать: bool) -> dict[str, Any] | None:
    """Задача исполнителя: шаги ручной обработки и (если ``разбирать``) автоматический разбор задания.

    Всё читается из папки задания и пишется в неё же (атомарно): процессу не нужно ничего,
    кроме пути. Итог — поля состояния «готово» (их пишет сервер). Папку удалили, пока
    задание ждало, — None, без ошибки.
    """
    применить_каталоги(каталоги)
    папка = Path(папка)
    try:
        состояние = _прочитать_состояние(папка)
        состояние.update(состояние="идёт", начато=time.time(), ошибка="")
        _записать_состояние(папка, состояние)
        выполнить_шаги(папка)
        if разбирать:
            return разобрать_задание(папка)
    except FileNotFoundError:
        if (папка / "состояние.json").exists():
            raise
        return None
    return {"состояние": "готово", "закончено": time.time()}


class Задания:
    """Очередь заданий разбора с журналом хода и этапами."""

    #: Что исполнитель делает с заданием (функция уровня модуля: её передаёт pickle). Проверки
    #: очереди подменяют её своей — долгой и предсказуемой.
    выполнить = staticmethod(выполнить_задание)

    def __init__(self, папка: Path, *, разборов: int = 0, стол: int = 0, на_человека: int = 0,
                 процессы: bool | None = None, восстановить: bool = True):
        """``разборов`` — сколько разборов идут одновременно (0 — по числу ядер), ``стол`` — сколько тяжёлых
        операций стола, ``на_человека`` — разборов одного человека одновременно, ``процессы`` — считать в
        процессах (по умолчанию) или в нитях; всё это — настройки ``potok_*`` (см. docs/20-potok.md)."""
        from . import ldpc, moddekoder  # noqa: PLC0415
        self.папка = Path(папка)
        # Матрицы LDPC, загруженные аналитиками, — в своей папке рядом (она
        # идёт в резервную копию, разборы — нет): слой «ldpc ИМЯ» находит их по имени. Туда же
        # отдел кладёт свои файлы матриц (alist, базовая с Z, адреса DVB, H в тексте): папка
        # создаётся при старте, автомат и окно «LDPC» пробуют файлы сами.
        ldpc.подготовить_каталог(self.папка.parent / "ldpc")
        # Плоскости модуляционного декодера (.etl) — тоже рядом: аналитик кладёт туда свои
        # картинки созвездий, окно и автомат видят их при каждом запросе.
        moddekoder.КАТАЛОГ = self.папка.parent / "ploskosti"
        moddekoder.КАТАЛОГ.mkdir(parents=True, exist_ok=True)
        self._каталоги = каталоги_рядом(self.папка)
        self._lock = threading.Lock()
        self._журналы: dict[str, list[str]] = {}
        # Задачи исполнителей по заданиям: ждут или идут (законченные убираются).
        self._задачи: dict[str, ispolniteli.Задача] = {}
        self._идут_вручную: set[str] = set()
        self._закрывается = False
        self._кэш: OrderedDict[tuple, np.ndarray] = OrderedDict()
        self._итоги: OrderedDict[tuple, Any] = OrderedDict()
        self._кэш_lock = threading.Lock()
        процессы = ispolniteli.процессами(процессы)
        размер = ispolniteli.размер_разборов(разборов)
        self._параметры_пулов = {
            "razbory": (размер, {"процессы": процессы, "понизить": 5,
                                 "на_владельца": ispolniteli.на_человека(размер, на_человека)}),
            # Стол: тяжёлые операции окон и ручные шаги производных потоков — по две на человека
            # одновременно, остальные его операции ждут (чужие — нет).
            "stol": (ispolniteli.размер_стола(стол), {"процессы": процессы, "понизить": 2, "на_владельца": 2}),
        }
        if восстановить:
            self._восстановить()

    # -- приём ------------------------------------------------------------

    def создать(self, *, владелец: int, имя: str, данные: bytes, профиль: str = "обычно",
                снять: Sequence[str] = (), от: str = "", символ: Sequence[int] = (),
                фм: Sequence[int] = (),
                разбирать: bool = True, происхождение: Sequence[str] = (),
                шаги: Sequence[dict[str, Any]] = (), сессия: str = "", бит: int | None = None) -> str:
        """Новое задание.

        ``шаги`` — ручная обработка производного потока (канал по маске,
        снятые слои): ``данные`` — поток, к которому они применяются (он
        хранится как «исходник.bin» — узел можно пересобрать и без родителя),
        результат — «вход.bin». ``разбирать=False`` — без автомата: шаги
        выполняются в исполнителях стола, не дожидаясь очереди разборов.
        ``сессия`` — задание принадлежит сессии: его видят все её участники, а уборка
        старых заданий его не трогает (удаляется вместе с сессией).
        ``бит`` — точная длина ``данные`` в битах, если хвост последнего байта — не данные.
        """
        ид = time.strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)
        папка = self.папка / ид
        папка.mkdir(parents=True, exist_ok=True)
        записать_атомарно(папка / ("исходник.bin" if шаги else "вход.bin"), bytes(данные))
        self._записать(ид, {"ид": ид, "владелец": владелец, "имя": имя, "профиль": профиль,
                            "снять": list(снять), "от": от, "состояние": "ждёт",
                            "символ": [int(k) for k in символ], "фм": [int(k) for k in фм],
                            "разбирать": bool(разбирать),
                            "происхождение": list(происхождение),
                            "шаги": [dict(ш) for ш in шаги], "сессия": сессия,
                            "создано": time.time(), "байт": len(данные), "этапы": [],
                            **({} if бит is None else {"исходных_бит" if шаги else "бит": int(бит)}),
                            "отчёт": "", "ошибка": ""})
        with self._lock:
            self._журналы[ид] = []
        self._поставить(ид, владелец, bool(разбирать))
        self._прибрать(владелец)
        return ид

    def _пул(self, имя: str) -> ispolniteli.Пул:
        """Общий пул исполнителей (закрытый другим владельцем — например, остановленным приложением
        в тестах — заводится заново с теми же настройками)."""
        размер, параметры = self._параметры_пулов[имя]
        пул = getattr(self, "_" + имя, None)
        if пул is None or (пул._закрыт and not self._закрывается):
            пул = ispolniteli.общий(имя, размер, **параметры)
            setattr(self, "_" + имя, пул)
        return пул

    @property
    def разборы(self) -> ispolniteli.Пул:
        return self._пул("razbory")

    @property
    def стол(self) -> ispolniteli.Пул:
        return self._пул("stol")

    def _поставить(self, ид: str, владелец: Any, разбирать: bool) -> None:
        """Задание — в очередь исполнителей: разбор — к разборам, одни ручные шаги — к столу."""
        пул = self.разборы if разбирать else self.стол
        задача = пул.подать(self.выполнить, str(self.папка / ид), self._каталоги, разбирать,
                            владелец=владелец, имя=ид, срок=None,
                            при_сообщении=lambda вид, данные: self._сообщение(ид, вид, данные),
                            при_конце=lambda з: self._конец(ид, з))
        задача.пул = пул
        with self._lock:
            if not задача.готова():
                self._задачи[ид] = задача

    def _сообщение(self, ид: str, вид: str, данные: Any) -> None:
        """Ход из исполнителя: строка журнала (время проставил исполнитель)."""
        if вид == "ход":
            with self._lock:
                журнал = self._журналы.setdefault(ид, [])
                журнал.append(str(данные))
                del журнал[:-ЖУРНАЛ]

    def _конец(self, ид: str, задача: ispolniteli.Задача) -> None:
        """Исполнитель закончил задание: итог (поля «готово»), ошибка или отмена — в состояние на диске."""
        with self._lock:
            if self._задачи.get(ид) is задача:
                del self._задачи[ид]
        if self._закрывается and задача.состояние != "готово":
            return                                   # при выключении идущие остаются «идёт» — возобновятся
        try:
            состояние = self._прочитать_файл(ид)
        except (OSError, ValueError):
            return                                   # задание удалили
        if задача.состояние == "готово":
            if not isinstance(задача.итог, dict):
                return                               # папку удалили, пока задание ждало
            состояние.update(задача.итог)
        elif задача.состояние == "отменено":
            состояние.update(состояние="отменено", ошибка="разбор отменён", закончено=time.time())
            self._ход(ид, "разбор отменён")
        else:
            ошибка = задача.ошибка
            состояние.update(состояние="ошибка", закончено=time.time(),
                             ошибка=str(ошибка) or type(ошибка).__name__ if ошибка else "ошибка исполнителя")
        try:
            self._записать(ид, состояние)
        except OSError:
            pass

    def отменить(self, ид: str) -> str:
        """Отменить ждущее или идущее задание: «снято» (ещё ждало), «отменяется» (идёт — остановится через
        секунды), пусто — нечего отменять (уже закончено)."""
        with self._lock:
            задача = self._задачи.get(ид)
        if задача is None:
            return ""
        итог = задача.пул.отменить(задача)
        return {"снята": "снято", "отменяется": "отменяется"}.get(итог, "")

    def _восстановить(self) -> None:
        """После перезапуска сервера: ждавшие задания — снова в очередь, прерванные посреди разбора — тоже,
        с пометкой в журнале (прерванные ``ПЕРЕЗАПУСКОВ_ДО`` раз — ошибкой: вдруг они и роняют сервер)."""
        if not self.папка.exists():
            return
        незавершённые = []
        for папка in self.папка.iterdir():
            try:
                с = _прочитать_состояние(папка)
            except (OSError, ValueError):
                continue
            if с.get("состояние") in ("ждёт", "идёт") and с.get("ид") not in self._задачи:
                незавершённые.append(с)
        for с in sorted(незавершённые, key=lambda с: (с.get("создано") or 0, с.get("ид") or "")):
            ид = с["ид"]
            if с["состояние"] == "идёт":
                с["перезапусков"] = int(с.get("перезапусков") or 0) + 1
                if с["перезапусков"] >= ПЕРЕЗАПУСКОВ_ДО:
                    с.update(состояние="ошибка", ошибка=f"разбор {с['перезапусков']} раза прерывался перезапуском "
                             "сервера — не возобновляется сам: запустите его заново (продолжить или пересобрать)")
                    self._записать(ид, с)
                    continue
                с.update(состояние="ждёт", найдено_пока=[])
                self._записать(ид, с)
                self._ход(ид, "разбор прерван перезапуском сервера — начат заново")
            self._поставить(ид, с.get("владелец"), bool(с.get("разбирать", True)))

    def посчитать(self, функция: Callable[..., Any], *args: Any, владелец: Any = 0, срок: float | None = None,
                  **kwargs: Any) -> Any:
        """Тяжёлый расчёт стола — в исполнителе стола (отдельный процесс), с папками матриц и плоскостей.

        ``функция`` — уровня модуля, аргументы — простые (``источник`` массива, а не его биты). Ошибка
        расчёта поднимается здесь же; не уложился в срок — ``ispolniteli.СрокВышел``.
        """
        return self.стол.выполнить(в_исполнителе, self._каталоги, функция, args, kwargs, владелец=владелец,
                                   срок=СРОК_СТОЛА if срок is None else срок)

    def подать_расчёт(self, функция: Callable[..., Any], *args: Any, владелец: Any = 0,
                      при_сообщении: Callable[[str, Any], None] | None = None,
                      срок_задачи: float | None = None) -> ispolniteli.Задача:
        """Долгий расчёт стола (разметка вслепую) — в исполнителе, без ожидания: задача с ходом и отменой."""
        задача = self.стол.подать(в_исполнителе, self._каталоги, функция, args, {}, владелец=владелец,
                                  при_сообщении=при_сообщении, срок=срок_задачи,
                                  имя=getattr(функция, "__name__", "расчёт"))
        задача.пул = self.стол
        return задача

    def источник(self, ид: str, этап: int):
        """Массив задания для исполнителя: путь файла и длина в битах (сами биты он читает сам)."""
        from .stol_raschety import Источник  # noqa: PLC0415
        файл = self.файл_бит(ид, этап)
        сведения = файл.stat()
        return Источник(str(файл), self.длина_бит(ид, этап), сведения.st_mtime_ns, сведения.st_size)

    def идущие(self) -> set[str]:
        """Задания, которые сейчас разбираются (или выполняют шаги) в исполнителях."""
        with self._lock:
            return {и for и, з in self._задачи.items() if з.состояние == "идёт"} | self._идут_вручную

    @property
    def _идёт(self) -> str:
        """Одно из идущих заданий (пусто — ни одного); присваивание — для проверок: «идёт» вручную."""
        return next(iter(sorted(self.идущие())), "")

    @_идёт.setter
    def _идёт(self, ид: str) -> None:
        self._идут_вручную = {ид} if ид else set()

    def _освободить(self, удаляемые: Sequence[str], причина: str) -> None:
        """Перед удалением заданий: ждущие — снять с очереди; если хоть одно идёт — ничего не трогать
        (ValueError с ``причина``)."""
        if self.идущие() & set(удаляемые):
            raise ValueError(причина)
        with self._lock:
            задачи = [self._задачи[и] for и in удаляемые if и in self._задачи]
        for пул in (self.разборы, self.стол):
            if not пул.снять([з for з in задачи if з.пул is пул]):
                raise ValueError(причина)

    def закрыть(self) -> None:
        """Остановить исполнителей (выключение сервера): идущие задания останутся «идёт» и возобновятся
        при следующем запуске."""
        self._закрывается = True
        for пул in (self.разборы, self.стол):
            пул.закрыть()

    def продолжить(self, ид: str, этап: int, *, владелец: int, снять: Sequence[str] = (),
                   профиль: str = "обычно") -> str:
        """Новое задание — с потока после этапа ``этап`` (1…), со снятием слоёв."""
        состояние = self.прочитать(ид)
        файл = self._выгрузка_этапа(ид, этап)
        if файл is None or файл.suffix != ".bin":
            raise ValueError("после этого этапа нет битового потока — продолжать не с чего")
        имя = f"{состояние['имя']} → этап {этап}"
        return self.создать(владелец=владелец, имя=имя, данные=файл.read_bytes(),
                            профиль=профиль, снять=снять, от=f"{ид}#{этап}",
                            сессия=состояние.get("сессия") or "")

    def остановить(self, ид: str) -> bool:
        """Остановить идущий автомат задания: разбор кончается с тем, что уже нашёл, — как по исчерпанию времени
        (после текущей проверки). Разбор идёт в исполнителе — ему кладётся метка в папку задания. False —
        задание сейчас не разбирается (ждёт в очереди или уже готово)."""
        if ид not in self.идущие():
            return False
        try:
            записать_атомарно(self.папка / ид / СТОП_ФАЙЛ, b"1")
        except OSError:
            return False
        self._ход(ид, "остановлено оператором: разбор закончит текущую проверку и выдаст то, что уже нашёл")
        return True

    # -- чтение -----------------------------------------------------------

    def прочитать(self, ид: str) -> dict[str, Any]:
        путь = self.папка / ид / "состояние.json"
        if not путь.exists():
            raise KeyError(ид)
        состояние = json.loads(путь.read_text(encoding="utf-8"))
        with self._lock:
            состояние["журнал"] = list(self._журналы.get(ид, []))[-80:]
            задача = self._задачи.get(ид)
        if состояние["состояние"] == "ждёт":
            состояние["перед_ним"] = задача.пул.перед(задача) if задача is not None else 0
        return состояние

    def список(self, владелец: int | None = None, сессии: Sequence[str] = (),
               без_сессий: bool = False) -> list[dict[str, Any]]:
        """Задания владельца и задания доступных ему сессий (``сессии``).

        ``без_сессий`` — только задания вне сессий (список «Мои разборы»).
        """
        итог = []
        if not self.папка.exists():
            return итог
        сессии = set(сессии)
        for папка in sorted(self.папка.iterdir(), reverse=True):
            путь = папка / "состояние.json"
            if not путь.exists():
                continue
            с = json.loads(путь.read_text(encoding="utf-8"))
            if без_сессий and с.get("сессия"):
                continue
            if владелец is not None and с.get("владелец") != владелец and с.get("сессия") not in сессии:
                continue
            итог.append({к: с.get(к) for к in ("ид", "имя", "состояние", "создано", "байт",
                                                 "профиль", "от", "снять", "разбирать", "сессия",
                                                 "владелец")}
                        | {"этапов": len(с.get("этапы") or []), "шаги": с.get("шаги") or []})
        # Свежие сверху: по времени создания — у заданий одной секунды имя папки
        # различается случайным хвостом, и уборка иначе могла бы снести новое.
        итог.sort(key=lambda з: з.get("создано") or 0, reverse=True)
        return итог

    # -- дерево обработки -----------------------------------------------------

    def дерево(self, ид: str, владелец: int, сессии: Sequence[str] = ()) -> dict[str, Any]:
        """Всё дерево, в котором стоит узел: корень, этапы-развилки и производные.

        Узел — задание; его дети — задания с «от» = «ид#этап». Родителя,
        которого удалили, нет — тогда корнем становится ближайший живой.
        """
        все = {з["ид"]: з for з in self.список(владелец, сессии)}
        if ид not in все:
            raise KeyError(ид)
        корень = ид
        while True:
            родитель = (все[корень].get("от") or "").split("#")[0]
            if родитель not in все:
                break
            корень = родитель
        return self._деревья(все, [корень])[0]

    def деревья_сессии(self, сессия: str) -> list[dict[str, Any]]:
        """Деревья всех файлов сессии за один проход по заданиям — по порядку добавления файлов.

        Стол сессии открывается одним запросом, а не запросом на каждый файл
        (каждый из которых заново перечитывал бы все задания).
        """
        все = {з["ид"]: з for з in self.список() if з.get("сессия") == сессия}
        корни = sorted((и for и, з in все.items() if (з.get("от") or "").split("#")[0] not in все),
                       key=lambda и: (все[и].get("создано") or 0, и))
        return self._деревья(все, корни)

    def _деревья(self, все: dict[str, dict[str, Any]], корни: Sequence[str]) -> list[dict[str, Any]]:
        дети: dict[str, list[dict[str, Any]]] = {}
        for з in все.values():
            родитель = (з.get("от") or "").split("#")[0]
            if родитель in все:
                дети.setdefault(родитель, []).append(з)

        def кратко(ид_: str) -> dict[str, Any]:
            """Этапы узла коротко — для сетки массивов на рабочем столе."""
            try:
                с = self._прочитать_файл(ид_)
            except (OSError, ValueError):
                return {"этапы_кратко": [], "происхождение": []}
            return {"этапы_кратко": [{к: э.get(к) for к in ("номер", "уровень", "что", "выход", "выгрузка",
                                                           "уверенность")}
                                     | {"притоков": len(э.get("притоки") or [])}
                                     for э in с.get("этапы") or []],
                    "происхождение": с.get("происхождение") or []}

        def узел(з: dict[str, Any]) -> dict[str, Any]:
            от = з.get("от") or ""
            return {**з, **кратко(з["ид"]), "этап_родителя": int(от.split("#")[1]) if "#" in от else None,
                    "дети": [узел(д) for д in sorted(дети.get(з["ид"], []),
                                                     key=lambda д: д.get("создано") or 0)]}

        return [узел(все[к]) for к in корни]

    def удалить(self, ид: str, владелец: int, сессии: Sequence[str] = ()) -> list[str]:
        """Удалить узел и всю ветвь под ним. Идущий разбор не трогаем."""
        удаляемые = _ид_ветви(_узел_дерева(self.дерево(ид, владелец, сессии), ид))
        self._освободить(удаляемые, "в этой ветви идёт разбор — дождитесь его конца")
        self._стереть(удаляемые)
        return удаляемые

    def удалить_ветку(self, ид: str, этап: int, владелец: int, сессии: Sequence[str] = (),
                      нельзя: Callable[[dict[str, Any]], str] = lambda у: "") -> dict[str, Any]:
        """Удалить ветку таблицы массивов с узла (задание, этап) — всё, что под ним в сетке.

        Этап 0 — вход задания: задание и всё, что из него получено (как ``удалить``).
        Этап k ≥ 1 — выход этапа автомата: этапы k, k+1, … задания (их файлы, сведения в
        состоянии, журнал и разметка, запомненные итоги) и производные задания, выросшие из
        этих этапов, — со своими ветвями; этапы до k и выросшее из них остаются. Идущий
        разбор не трогаем. ``нельзя(узел)`` — почему пользователю нельзя удалить узел (пусто —
        можно): проверяется у каждого задания, которое уйдёт, — чужое внутри ветки не удаляется
        заодно со своим, вся ветка отвергается (ValueError). Итог — удалённые задания,
        сколько этапов задания ушло и сколько массивов (узлов сетки) всего.
        """
        return self._удалить_с(_узел_дерева(self.дерево(ид, владелец, сессии), ид), int(этап), нельзя)

    def удалить_ветки(self, пункты: Sequence[tuple[str, int]], владелец: int, сессии: Sequence[str] = (),
                      нельзя: Callable[[dict[str, Any]], str] = lambda у: "") -> dict[str, Any]:
        """Удалить несколько веток одним вызовом — по порядку пунктов (задание, этап).

        Ветка, которой уже нет (ушла вместе с выбранной выше, удалена кем-то раньше или не
        видна пользователю), пропускается. ``нельзя(узел)`` — почему пользователю нельзя
        удалить узел задания (пусто — можно): отказ, как и идущий разбор, не мешает
        остальным веткам — он попадает в итог с причиной.
        """
        итог: dict[str, Any] = {"задания": [], "этапы": [], "массивов": 0, "пропущено": 0, "отказано": []}
        for ид, этап in пункты:
            try:
                узел = _узел_дерева(self.дерево(ид, владелец, сессии), ид)
            except KeyError:
                узел = None
            if узел is None or not 0 <= этап <= len(узел["этапы_кратко"]):
                итог["пропущено"] += 1
                continue
            причина = нельзя(узел)
            if not причина:
                try:
                    ветка = self._удалить_с(узел, этап, нельзя)
                except ValueError as ошибка:
                    причина = str(ошибка)
            if причина:
                итог["отказано"].append({"ид": ид, "этап": этап, "причина": причина})
                continue
            итог["задания"] += ветка["задания"]
            итог["массивов"] += ветка["массивов"]
            if этап:
                итог["этапы"].append({"ид": ид, "с": этап, "этапов": ветка["этапов"]})
        return итог

    def _удалить_с(self, узел: dict[str, Any], этап: int,
                   нельзя: Callable[[dict[str, Any]], str] = lambda у: "") -> dict[str, Any]:
        """Удаление ветки с узла дерева ``узел`` (задание) и его этапа ``этап`` — см. ``удалить_ветку``."""
        ид = узел["ид"]
        этапов = len(узел["этапы_кратко"])
        if not 0 <= этап <= этапов:
            raise KeyError(f"{ид}#{этап}")
        дети = [д for д in узел["дети"] if (д["этап_родителя"] or 0) >= этап] if этап else [узел]
        чужих = sum(1 for д in дети for н in _узлы_ветви(д) if нельзя(н))
        if чужих:
            raise ValueError(f"в ветке есть чужие узлы ({чужих}): их вправе удалить только их автор или владелец сессии")
        удаляемые = [и for д in дети for и in _ид_ветви(д)]
        # Этап k ≥ 1 переписывает состояние самого задания — и его разбор не должен идти.
        self._освободить(удаляемые + ([] if not этап else [ид]), "в этой ветви идёт разбор — дождитесь его конца")
        массивов = sum(_массивов(д) for д in дети)
        self._стереть(удаляемые)
        if not этап:
            return {"задания": удаляемые, "этапов": 0, "массивов": массивов}
        папка = self.папка / ид
        лишние = [путь for н in range(этап, этапов + 1)
                  for путь in [*папка.glob(f"этап-{н}.*"), *папка.glob(f"приток-{н}-*.bin")]]
        for путь in лишние:
            путь.unlink(missing_ok=True)
        self._забыть({str(путь) for путь in лишние})
        with self._lock:
            состояние = self._прочитать_файл(ид)
            состояние["этапы"] = состояние["этапы"][:этап - 1]
            # Отчёт уходит помощнику: пусть знает, что этих находок больше нет.
            пометка = f"Этап {этап} удалён вручную." if этапов == этап else f"Этапы {этап}–{этапов} удалены вручную."
            состояние["отчёт"] = "\n\n".join(ч for ч in ((состояние.get("отчёт") or "").rstrip(), пометка) if ч)
            self._записать(ид, состояние)
            for имя in ("журнал-стола.json", "разметка.json"):
                _без_этапов_с(папка / имя, этап)
        return {"задания": удаляемые, "этапов": этапов - этап + 1, "массивов": массивов + этапов - этап + 1}

    def удалить_сессию(self, сессия: str) -> list[str]:
        """Удалить все задания сессии. Идущий разбор не трогаем — тогда ничего не удаляем."""
        свои = [з["ид"] for з in self.список() if з.get("сессия") == сессия]
        self._освободить(свои, "в сессии идёт разбор — дождитесь его конца или отмените его")
        self._стереть(свои)
        return свои

    def _стереть(self, удаляемые: Sequence[str]) -> None:
        """Папки заданий — с диска; их журналы хода, биты и итоги расчётов — из памяти."""
        стёртые: set[str] = set()
        for и in удаляемые:
            папка = self.папка / и
            # Ту же ветку мог только что удалить другой участник сессии: чего уже нет — пропускаем.
            try:
                for файл in (папка.iterdir() if папка.is_dir() else ()):
                    стёртые.add(str(файл))
                    файл.unlink(missing_ok=True)
                папка.rmdir()
            except FileNotFoundError:
                pass
            with self._lock:
                self._журналы.pop(и, None)
        self._забыть(стёртые)

    def _забыть(self, файлы: set[str]) -> None:
        """Распакованные биты и итоги расчётов удалённых файлов больше не нужны — память освобождается."""
        with self._кэш_lock:
            for запас in (self._кэш, self._итоги):
                for ключ in [к for к in запас if к[0] in файлы]:
                    del запас[ключ]

    def файл_этапа(self, ид: str, этап: int) -> Path | None:
        return self._выгрузка_этапа(ид, этап)

    # -- разметка бит массива ----------------------------------------------------------

    def разметка(self, ид: str, этап: int) -> dict[str, Any]:
        """Разметка массива (отрезки, правила, закладки) — общая для всех, кто видит задание."""
        путь = self.папка / ид / "разметка.json"
        пустая = {"отрезки": [], "правила": [], "закладки": []}
        try:
            все = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
        except ValueError:
            все = {}
        return пустая | (все.get(str(int(этап))) or {})

    def записать_разметку(self, ид: str, этап: int, разметка: dict[str, Any]) -> None:
        путь = self.папка / ид / "разметка.json"
        with self._lock:
            try:
                все = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
            except ValueError:
                все = {}
            if разметка.get("отрезки") or разметка.get("правила") or разметка.get("закладки"):
                все[str(int(этап))] = разметка
            else:
                все.pop(str(int(этап)), None)
            записать_атомарно(путь, json.dumps(все, ensure_ascii=False))

    def биты_участка(self, ид: str, этап: int, от: int = 0, до: int | None = None) -> np.ndarray:
        """Биты [от, до) массива — без распаковки всего файла.

        Поиску периода или скремблера нужно начало потока, а распаковать массив
        в сотни мегабайт — секунды: читается и распаковывается только участок
        (если весь массив уже в памяти — берётся из неё).
        """
        файл = self.файл_бит(ид, этап)
        сведения = файл.stat()
        with self._кэш_lock:
            биты = self._кэш.get((str(файл), сведения.st_mtime_ns, сведения.st_size))
        всего = self.длина_бит(ид, этап)
        до = всего if до is None else max(0, min(int(до), всего))
        от = max(0, min(int(от), до))
        if биты is not None:
            return биты[от:до]
        with файл.open("rb") as поток:
            поток.seek(от // 8)
            кусок = поток.read((до + 7) // 8 - от // 8)
        биты = np.unpackbits(np.frombuffer(кусок, dtype=np.uint8))[от % 8:от % 8 + до - от]
        биты.flags.writeable = False
        return биты

    def запомнить(self, ид: str, этап: int, ключ: str, посчитать) -> Any:
        """Результат долгого расчёта над массивом — один раз на файл и параметры.

        Файл этапа после записи не меняется, поэтому ключ — путь, время и размер
        файла плюс имя и параметры расчёта: повторный запрос (второй пользователь
        сессии, возврат к массиву) отвечает сразу. ``посчитать()`` сам берёт нужные
        биты (``биты`` или ``биты_участка``).
        """
        файл = self.файл_бит(ид, этап)
        сведения = файл.stat()
        полный = (str(файл), сведения.st_mtime_ns, сведения.st_size, ключ)
        with self._кэш_lock:
            if полный in self._итоги:
                self._итоги.move_to_end(полный)
                return self._итоги[полный]
        итог = посчитать()
        with self._кэш_lock:
            self._итоги[полный] = итог
            while len(self._итоги) > ИТОГОВ_ПОМНИТЬ:
                self._итоги.popitem(last=False)
        return итог

    # -- журнал массива на рабочем столе ------------------------------------------

    def журнал_стола(self, ид: str) -> dict[str, list[dict[str, Any]]]:
        """Записи аналитика и итоги операций по массивам узла: {этап: [записи]}."""
        путь = self.папка / ид / "журнал-стола.json"
        if not путь.exists():
            return {}
        try:
            return json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            return {}

    def записать_в_журнал(self, ид: str, этап: int, запись: dict[str, Any]) -> dict[str, Any]:
        if not (self.папка / ид).exists():
            raise KeyError(ид)
        чистая = {"время": time.time(), "операция": str(запись.get("операция", ""))[:200],
                  "текст": str(запись.get("текст", ""))[:20000],
                  "слой": str(запись.get("слой", ""))[:2000]}
        with self._lock:
            журнал = self.журнал_стола(ид)
            записи = журнал.setdefault(str(int(этап)), [])
            записи.append(чистая)
            del записи[:-ЖУРНАЛ_СТОЛА]
            путь = self.папка / ид / "журнал-стола.json"
            записать_атомарно(путь, json.dumps(журнал, ensure_ascii=False))
        return чистая

    def приток(self, ид: str, этап: int, номер: int) -> tuple[bytes, str]:
        """Байты притока этапа и его имя."""
        состояние = self.прочитать(ид)
        этапы = состояние.get("этапы") or []
        if not 1 <= int(этап) <= len(этапы):
            raise ValueError("нет такого этапа")
        притоки = этапы[int(этап) - 1].get("притоки") or []
        запись = next((п for п in притоки if п["номер"] == int(номер)), None)
        файл = self.папка / ид / f"приток-{int(этап)}-{int(номер)}.bin"
        if запись is None or not файл.exists():
            raise ValueError("у этого этапа нет такого притока")
        return файл.read_bytes(), запись["имя"]

    def файл_бит(self, ид: str, этап: int) -> Path:
        """Файл битового потока массива: этап 0 — вход задания, дальше — поток после этапа."""
        if int(этап) == 0:
            файл = self.папка / ид / "вход.bin"
            if not файл.exists():
                raise ValueError("поток массива ещё не готов")
            return файл
        файл = self._выгрузка_этапа(ид, этап)
        if файл is None or файл.suffix != ".bin":
            raise ValueError("у этого этапа нет битового потока")
        return файл

    def длина_бит(self, ид: str, этап: int) -> int:
        """Сколько бит в массиве: файл — целые байты, а после шагов (обрезка, разметка) длина бывает не кратна 8."""
        размер = self.файл_бит(ид, этап).stat().st_size * 8
        if int(этап):
            return размер
        бит = self._прочитать_файл(ид).get("бит")
        return int(бит) if isinstance(бит, int) and 0 <= бит <= размер else размер

    def биты(self, ид: str, этап: int) -> np.ndarray:
        """Биты потока: этап 0 — исходный файл, дальше — поток после этапа (.bin).

        Распакованные биты держатся в памяти (до ``КЭШ_БИТ``): каждое действие на
        рабочем столе берёт биты массива, и файл не читается заново. Ключ — путь,
        время изменения и размер: пересобранный массив читается заново. Массив
        только для чтения — чтобы действие не испортило его для следующих.
        """
        файл = self.файл_бит(ид, этап)
        сведения = файл.stat()
        ключ = (str(файл), сведения.st_mtime_ns, сведения.st_size)
        with self._кэш_lock:
            биты = self._кэш.get(ключ)
            if биты is not None:
                self._кэш.move_to_end(ключ)
                return биты
        биты = np.unpackbits(np.frombuffer(файл.read_bytes(), dtype=np.uint8))[:self.длина_бит(ид, этап)]
        биты.flags.writeable = False
        if len(биты) <= КЭШ_БИТ:
            with self._кэш_lock:
                self._кэш[ключ] = биты
                while sum(len(б) for б in self._кэш.values()) > КЭШ_БИТ:
                    self._кэш.popitem(last=False)
        return биты

    # -- журнал хода --------------------------------------------------------

    def _ход(self, ид: str, строка: str) -> None:
        with self._lock:
            журнал = self._журналы.setdefault(ид, [])
            журнал.append(time.strftime("%H:%M:%S ") + строка)
            del журнал[:-ЖУРНАЛ]

    # -- хранение ---------------------------------------------------------

    def _выгрузка_этапа(self, ид: str, этап: int) -> Path | None:
        for путь in (self.папка / ид).glob(f"этап-{int(этап)}.*"):
            return путь
        return None

    def _прочитать_файл(self, ид: str) -> dict[str, Any]:
        return json.loads((self.папка / ид / "состояние.json").read_text(encoding="utf-8"))

    def _записать(self, ид: str, состояние: dict[str, Any]) -> None:
        записать_атомарно(self.папка / ид / "состояние.json", json.dumps(состояние, ensure_ascii=False))

    def _прибрать(self, владелец: int) -> None:
        свои = [з for з in self.список(владелец, без_сессий=True) if з["состояние"] in ЗАКОНЧЕНО]
        лишние = [з["ид"] for з in свои[ХРАНИТЬ:]]
        try:
            self._освободить(лишние, "")
        except ValueError:
            return                                   # старое задание снова в работе — уберём в другой раз
        # Два запроса одного человека убирают одновременно: чего уже нет — пропускается.
        self._стереть(лишние)
