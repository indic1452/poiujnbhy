def _ход_в_сервер(строка: str) -> None:
    """Строка журнала хода — в сервер (там её видит страница); отменённый разбор здесь и останавливается."""
    ispolniteli.сообщить("ход", time.strftime("%H:%M:%S ") + строка)


def _доля_в_сервер(доля: float, строка: str) -> None:
    """Ход шагов по кускам: доля сделанного и строка — в сервер (отменённые шаги здесь и останавливаются)."""
    ispolniteli.сообщить("доля", round(float(доля), 4))
    _ход_в_сервер(строка)


def выполнить_шаги(папка: Path, ход: Callable[[str], None] = _ход_в_сервер,
                   доля: Callable[[float, str], None] | None = None, в_памяти_до: int = В_ПАМЯТИ_ДО) -> None:
    """Шаги ручной обработки: исходник → вход.bin, описание — в «происхождение».

    Массив больше ``в_памяти_до`` бит идёт по кускам (``potokovo``): итог пишется на диск по мере
    готовности, доля сделанного — серверу (``доля``), отмена — как у любой задачи исполнителя.
    """
    from .potokovo import выполнить  # noqa: PLC0415
    состояние = _прочитать_состояние(папка)
    if not состояние.get("шаги"):
        return
    источник = массив_узла(папка, состояние, "исходник")
    сказать = доля or (lambda д, строка: ход(строка))
    свойства: list[dict[str, Any]] = []
    бит, описание = выполнить(источник, состояние["шаги"], папка / "вход.bin", ход=сказать, в_памяти_до=в_памяти_до,
                              свойства=свойства)
    состояние = _прочитать_состояние(папка)
    # Точная длина в битах: файл — целые байты, хвост последнего дополнен нулями.
    состояние.update(происхождение=описание, байт=(бит + 7) // 8, бит=int(бит))
    if свойства and свойства[-1]:
        # Свойства последнего слоя (у ТКБ — блок данных и кадр): окна стола берут из них
        # параметры следующего шага, как автомат (ПСП со сбросом на блоке).
        from .razbor import простые_свойства  # noqa: PLC0415
        состояние["свойства"] = простые_свойства(свойства[-1])
    _записать_состояние(папка, состояние)
    ход(f"шаги выполнены: {бит} бит")


#: Метка «остановить автомат» в папке задания: сервер кладёт её, разбор в исполнителе (процессе или
#: нити) видит её и кончается с тем, что уже нашёл, — как по исчерпанию времени.
СТОП_ФАЙЛ = "стоп"
#: Метка «идёт автомат» (не шаги): только тогда «Остановить» оставляет найденное, иначе — отмена.
РАЗБОР_ФАЙЛ = "разбор-идёт"
#: Как часто разбор смотрит, не положили ли метку, секунд.
СТОП_КАЖДЫЕ = 0.5


def _ждать_стопа(стоп: Path, готово: threading.Event) -> None:
    """Пока идёт разбор: появилась метка — исчерпать бюджет текущего разбора (после текущей проверки
    он выдаёт то, что нашёл)."""
    from .razbor import _ТЕКУЩИЙ  # noqa: PLC0415 — тяжёлый импорт
    while not готово.wait(СТОП_КАЖДЫЕ):
        if стоп.exists() and _ТЕКУЩИЙ.бюджет is not None:
            # Сам разбор видит метку через отмена=стоп.exists (в Бюджет.вышел); нить — для долгих
            # проверок, что сверяются только со сроком «конец»: им он обнуляется сразу.
            _ТЕКУЩИЙ.бюджет.остановлен = _ТЕКУЩИЙ.бюджет.исчерпан = True
            _ТЕКУЩИЙ.бюджет.конец = 0.0
            return


def _поток_большого(папка: Path, состояние: dict[str, Any], источник: Массив,
                    ход: Callable[[str], None]) -> tuple[Массив, str] | None:
    """Вход — большой (в память не читается) .Sig или текст «0101…» своим файлом: его поток кусками в
    «поток.bin», как его читает разбор небольшого файла (тела пакетов подряд, биты текста). Итог — поток
    и его вид; None — вход не такой (или ссылка на файл сервера): разбирается сырыми байтами."""
    from .chtenie import (  # noqa: PLC0415
        РАСШИРЕНИЯ_SIG,
        РАСШИРЕНИЯ_ТЕКСТА,
        биты_текста_в_файл,
        разобрать_sig_файл,
        тела_в_файл,
    )
    if источник.ссылка is not None or источник.смещение or источник.развернуть:
        return None
    расширение = Path(состояние.get("имя") or "").suffix.lower()
    куда = папка / ПОТОК_ФАЙЛ
    if расширение in РАСШИРЕНИЯ_SIG:
        ход(f"большой .Sig ({источник.байт >> 20} МБ): разметка пакетов по всему файлу")
        найдено = разобрать_sig_файл(источник.путь)
        if найдено is not None:
            начала, длины, _, _ = найдено
            ход(f"тела {len(длины)} пакетов подряд — в поток кусками")
            if тела_в_файл(источник.путь, начала, длины, куда):
                return Массив(куда), "sig"
    elif расширение in РАСШИРЕНИЯ_ТЕКСТА:
        ход(f"большой текст ({источник.байт >> 20} МБ): биты «0101…» — в поток кусками")
        бит = биты_текста_в_файл(источник.путь, куда)
        if бит:
            return Массив(куда, бит=бит), "текст"
    куда.unlink(missing_ok=True)
    return None


def разобрать_задание(папка: Path, ход: Callable[[str], None] = _ход_в_сервер,
                      в_памяти_до: int = В_ПАМЯТИ_ДО) -> dict[str, Any]:
    """Автоматический разбор входа задания: этапы — по мере нахождения, файлы этапов; итог — словарем
    для состояния (его записывает сервер, когда примет итог: «готово» на диске — значит, задание
    уже не занято исполнителем)."""
    from .razbor import ВЫБОРКА_БИТ, разобрать, этапы  # noqa: PLC0415 — тяжёлый импорт

    состояние = _прочитать_состояние(папка)
    найдено: list[dict[str, Any]] = []
    стоп = папка / СТОП_ФАЙЛ
    стоп.unlink(missing_ok=True)                 # метка от прерванного прежнего разбора — не в счёт
    (папка / РАЗБОР_ФАЙЛ).touch()
    for метка in [*папка.glob("весь-*"), папка / ПОТОК_ФАЙЛ]:
        метка.unlink(missing_ok=True)            # пересчёт по всему файлу прежнего разбора — не в счёт
    готово = threading.Event()
    threading.Thread(target=_ждать_стопа, args=(стоп, готово), name="reportgen-stop", daemon=True).start()

    def этап(находка) -> None:
        # Этап найден — сразу на страницу, не дожидаясь конца разбора.
        найдено.append({"уровень": находка.уровень, "что": находка.что, "мера": находка.мера})
        текущее = _прочитать_состояние(папка)
        текущее["найдено_пока"] = list(найдено)
        _записать_состояние(папка, текущее)

    # Небольшой свой файл читается как всегда (.Sig, текст с битами — по имени); ссылка на файл
    # сервера и большой массив — только начало в память, остальное кусками с диска.
    источник = массив_узла(папка, состояние, "вход")
    большой = источник.ссылка is not None or источник.бит > в_памяти_до
    # Большой .Sig или текст «0101…»: поток (тела пакетов, биты текста) — кусками в «поток.bin», как его читает
    # разбор небольшого файла; с него же потом и пересчёт по всему файлу.
    свой_поток = _поток_большого(папка, состояние, источник, ход) if большой else None
    if свой_поток is not None:
        источник = свой_поток[0]
    try:
        разбор = разобрать(None if большой else папка / "вход.bin", имя=состояние["имя"],
                           профиль=состояние.get("профиль", "обычно"),
                           снять=состояние.get("снять") or (), ход=ход, этап=этап,
                           символ=состояние.get("символ") or (), фм=состояние.get("фм") or (),
                           период_до=состояние.get("период_до"),
                           источник=источник if большой else None, отмена=стоп.exists,
                           с_уровня=состояние.get("с_уровня") or None)
    finally:
        готово.set()
        стоп.unlink(missing_ok=True)
        (папка / РАЗБОР_ФАЙЛ).unlink(missing_ok=True)
    # Автомат ищет по началу потока (выборка); у потока длиннее выборки этапы с известным слоем потом
    # пересчитываются по всему файлу (``пересчитать_этапы``), остальные остаются по началу файла. Поток —
    # тот, что читал автомат: у .Sig — тела пакетов, у текста «0101…» — его биты, а не байты файла.
    поток = разбор.поток
    вид_потока = свой_поток[1] if свой_поток is not None else поток.вид
    бит_потока = источник.бит if большой or поток.вид == "bin" else поток.бит_всего
    # Вход узла — поток этапа, найденный по началу файла родителя: и всё, что найдено в нём, — по началу файла.
    вход_выборка = bool(состояние.get("по_выборке"))
    длиннее_выборки = вход_выборка or бит_потока > ВЫБОРКА_БИТ
    ограничения = list(разбор.ограничения)
    if вход_выборка:
        ограничения.insert(0, "вход — поток этапа по началу файла: этапы тоже по началу файла")
    if свой_поток is not None:
        ограничения.insert(0, f"большой .Sig: разобраны тела пакетов подряд, {источник.байт} байт"
                           if вид_потока == "sig" else f"большой текст: разобраны его биты «0101…», {источник.бит} бит")
    список = этапы(разбор)
    for номер, (запись, находка) in enumerate(zip(список, разбор.находки, strict=False), start=1):
        if длиннее_выборки and запись.get("выход"):
            # Этапы большого файла — по его началу (выборке), пока их не пересчитали по всему файлу.
            запись["выход"] += " — по началу файла"
            запись["по_выборке"] = True
        if находка.вид_дальше == "биты" and находка.дальше is not None:
            запись["бит"] = int(len(находка.дальше))      # точная длина: файл этапа — целые байты
        выгружено = выгрузка(находка.дальше, находка.вид_дальше)
        if выгружено is not None:
            данные, расширение = выгружено
            записать_атомарно(папка / f"этап-{номер}.{расширение}", данные)
            запись["выгрузка"] = расширение
            запись["выгрузка_байт"] = len(данные)
        if находка.вид_дальше == "притоки" and isinstance(находка.дальше, dict):
            # Каждый приток — своим файлом: скачать или разобрать отдельным узлом.
            притоки = list(находка.дальше.items())
            запись["притоки"] = []
            for k, (имя, ряд) in enumerate(притоки[:ПРИТОКОВ_ДО]):
                записать_атомарно(папка / f"приток-{номер}-{k}.bin", _упаковать_биты(ряд))
                запись["притоки"].append({"номер": k, "имя": str(имя), "бит": int(len(ряд)),
                                          **({"по_выборке": True} if длиннее_выборки else {})})
            if len(притоки) > ПРИТОКОВ_ДО:
                запись["притоков_всего"] = len(притоки)
                ограничения.append(f"этап {номер}: сохранены первые {ПРИТОКОВ_ДО} притоков из {len(притоки)}")
    ход(f"готово за {разбор.секунд:.1f} с: этапов {len(список)}")
    план: list[dict[str, Any]] = []
    весь_файл: dict[str, Any] = {}
    if длиннее_выборки and not вход_выборка:
        if поток.вид != "bin" and not поток.целиком:
            ограничения.append(f"поток ({поток.вид}) целиком не читается — этапы по всему файлу не пересчитываются")
        else:
            план = план_всего_файла(разбор.находки, список, состояние.get("снять") or ())
    if план and поток.вид != "bin" and not большой:
        # .Sig и текст «0101…»: пересчёт — с того же потока, что читал автомат.
        записать_атомарно(папка / ПОТОК_ФАЙЛ, bytes(поток.данные))
        весь_файл["поток_бит"] = int(бит_потока)
    elif план and свой_поток is not None:
        весь_файл["поток_бит"] = int(источник.бит)   # поток большого .Sig или текста уже в «поток.bin»
    elif свой_поток is not None:
        (папка / ПОТОК_ФАЙЛ).unlink(missing_ok=True)  # пересчитывать нечего — копия потока не нужна
    for п in план:
        список[п["номер"] - 1]["весь"] = "ждёт"
    return {"состояние": "готово", "этапы": список, "отчёт": разбор.отчёт(предел=60000),
            "секунд": разбор.секунд, "закончено": time.time(),
            "карта": (разбор.карта.подробно if разбор.карта else []),
            "не_найдено": разбор.не_найдено, "ограничения": ограничения,
            "содержимое": разбор.содержимое,
            # Автомат читал не байты входа, а свой поток (.Sig — тела пакетов, текст — биты): вход — не тот поток.
            **({"поток_вид": вид_потока} if вид_потока != "bin" else {}),
            # Файл длиннее выборки: этапы со слоем — по всему файлу (задачу ставит сервер, см. ``пересчитать_этапы``).
            **({"весь_файл": {"состояние": "ждёт", "план": план, **весь_файл}} if план else {})}


def план_всего_файла(находки: Sequence[Any], список: Sequence[dict[str, Any]],
                     снять: Sequence[str] = ()) -> list[dict[str, Any]]:
    """Какие этапы пересчитать по всему файлу: номер этапа и шаги от прежнего пересчитанного потока
    (этап 0 — вход). Подряд с первого, пока у этапа битовый выход и известный слой; цикл без слоя и
    без выхода пропускается (его шаги — следующему этапу), на любом другом этапе план кончается.
    Слои, снятые вручную при запуске (``снять``), — первыми этапами: их шаг — само указание аналитика."""
    from .razbor import шаги_по_этапам  # noqa: PLC0415
    находки = list(находки)
    ручных = 0
    for указание, находка in zip(снять, находки, strict=False):
        if находка.уровень != "вручную" or not str(указание).strip():
            break
        ручных += 1
    шаги_этапов = ([[{"вид": "слой", "вкл": True, "слой": str(у).strip()}] for у in list(снять)[:ручных]]
                   + шаги_по_этапам(находки[ручных:]))
    план: list[dict[str, Any]] = []
    копится: list[dict[str, Any]] = []
    for номер, (шаги, находка, запись) in enumerate(zip(шаги_этапов, находки, список, strict=False), start=1):
        биты = запись.get("выгрузка") == "bin"
        if находка.уровень == "цикл" and not (находка.свойства or {}).get("слой"):
            if биты:
                break                                # выход цикла без слоя по всему файлу не повторить
            копится += шаги
            continue
        if not биты or not шаги:
            break
        план.append({"номер": номер, "шаги": [*копится, *шаги]})
        копится = []
    return план


def _по_всему(этап: dict[str, Any], бит: int) -> None:
    """Пометки этапа, пересчитанного по всему файлу: точная длина, выход и размер выгрузки."""
    этап.pop("по_выборке", None)
    этап.update(весь="готово", выход=f"{бит} бит — весь файл", бит=int(бит), выгрузка_байт=(int(бит) + 7) // 8)


def _заменить(временный: Path, путь: Path) -> None:
    """Подменить файл этапа (на Windows его может держать открытым чтение — тогда подождать)."""
    for пауза in (*ПАУЗЫ, *([1.0] * 20), None):
        try:
            os.replace(временный, путь)
            return
        except PermissionError:
            if пауза is None:
                raise
            time.sleep(пауза)


def _в_плане(папка: Path, номер: int) -> bool:
    """Этап ``номер`` ещё в плане пересчёта (его не удалили, пока шёл пересчёт)."""
    try:
        план = (_прочитать_состояние(папка).get("весь_файл") or {}).get("план") or []
    except (OSError, ValueError):
        return False
    return any(int(п["номер"]) == номер for п in план)


def вход_пересчёта(папка: Path, состояние: dict[str, Any]) -> Массив:
    """С чего пересчитывать этапы: поток, который читал автомат (.Sig, текст «0101…» — «поток.bin»), иначе вход."""
    бит = (состояние.get("весь_файл") or {}).get("поток_бит")
    if бит is not None:
        return Массив(Path(папка) / ПОТОК_ФАЙЛ, бит=int(бит))
    return массив_узла(папка, состояние, "вход")


def пересчитать_этапы(папка: str | Path, в_памяти_до: int = В_ПАМЯТИ_ДО) -> dict[str, Any]:
    """Этапы автомата — по всему файлу (в исполнителе): шаги плана («весь_файл» в состоянии) по кускам
    от потока входа, выход каждого этапа подменяет его выборочный «этап-N.bin»; сервер узнаёт о готовом
    этапе сообщением «этап». Этап удалили, пока шёл пересчёт, — план обрезан: дальше не считается и файл
    удалённого этапа не пишется. Отмена — как у шагов: на ближайшем ходе."""
    from .potokovo import выполнить  # noqa: PLC0415
    папка = Path(папка)
    состояние = _прочитать_состояние(папка)
    план = (состояние.get("весь_файл") or {}).get("план") or []
    источник = вход_пересчёта(папка, состояние)
    for k, п in enumerate(план):
        номер = int(п["номер"])
        if not _в_плане(папка, номер):
            break
        файл = папка / f"этап-{номер}.bin"
        метка = папка / f"весь-{номер}.бит"
        if метка.exists():
            # Пересчитан раньше (до перезапуска сервера или отмены): сообщение о нём могло не дойти.
            бит = int(метка.read_text(encoding="utf-8"))
            ispolniteli.сообщить("этап", {"номер": номер, "бит": бит})
            источник = Массив(файл, бит=бит)
            continue

        def ход(доля: float, строка: str, k: int = k, номер: int = номер) -> None:
            _доля_в_сервер((k + доля) / len(план), f"этап {номер} по всему файлу: {строка}")
        временный = папка / f"весь-{номер}.tmp"
        try:
            бит, _ = выполнить(источник, п["шаги"], временный, ход=ход, в_памяти_до=в_памяти_до)
            if not _в_плане(папка, номер):
                break
            _заменить(временный, файл)
        finally:
            временный.unlink(missing_ok=True)
        записать_атомарно(метка, str(int(бит)))
        ispolniteli.сообщить("этап", {"номер": номер, "бит": int(бит)})
        источник = Массив(файл, бит=int(бит))
    return {"этапов": len(план)}


def выполнить_задание(папка: str, каталоги: dict[str, str], разбирать: bool) -> dict[str, Any] | None:
    """Задача исполнителя: шаги ручной обработки и (если ``разбирать``) автоматический разбор задания.

    Всё читается из папки задания и пишется в неё же (атомарно): процессу не нужно ничего,
    кроме пути. Итог — поля состояния «готово» (их пишет сервер). Папку удалили, пока
    задание ждало, — None, без ошибки.
    """
    применить_каталоги(каталоги)
    папка = Path(папка)
    try:
        состояние = _прочитать_состояние(папка)
        состояние.update(состояние="идёт", начато=time.time(), ошибка="")
        _записать_состояние(папка, состояние)
        (папка / РАЗБОР_ФАЙЛ).unlink(missing_ok=True)   # от прерванного прежнего прогона
        в_памяти_до = int(каталоги.get("в_памяти_до") or В_ПАМЯТИ_ДО)
        выполнить_шаги(папка, доля=_доля_в_сервер, в_памяти_до=в_памяти_до)
        if разбирать:
            return разобрать_задание(папка, в_памяти_до=в_памяти_до)
    except FileNotFoundError:
        if (папка / "состояние.json").exists():
            raise
        return None
    return {"состояние": "готово", "закончено": time.time()}


class Задания:
    """Очередь заданий разбора с журналом хода и этапами."""

    #: Что исполнитель делает с заданием (функция уровня модуля: её передаёт pickle). Проверки
    #: очереди подменяют её своей — долгой и предсказуемой.
    выполнить = staticmethod(выполнить_задание)

    def __init__(self, папка: Path, *, разборов: int = 0, стол: int = 0, на_человека: int = 0,
                 процессы: bool | None = None, восстановить: bool = True, в_памяти_мб: int | None = None):
        """``разборов`` — сколько разборов идут одновременно (0 — по числу ядер), ``стол`` — сколько тяжёлых
        операций стола, ``на_человека`` — разборов одного человека одновременно, ``процессы`` — считать в
        процессах (по умолчанию) или в нитях; всё это — настройки ``potok_*`` (см. docs/20-potok.md)."""
        from . import ldpc, moddekoder  # noqa: PLC0415
        self.папка = Path(папка)
        # Матрицы LDPC, загруженные аналитиками, — в своей папке рядом (она
        # идёт в резервную копию, разборы — нет): слой «ldpc ИМЯ» находит их по имени. Туда же
        # отдел кладёт свои файлы матриц (alist, базовая с Z, адреса DVB, H в тексте): папка
        # создаётся при старте, автомат и окно «LDPC» пробуют файлы сами.
        ldpc.подготовить_каталог(self.папка.parent / "ldpc")
        # Плоскости модуляционного декодера (.etl) — тоже рядом: аналитик кладёт туда свои
        # картинки созвездий, окно и автомат видят их при каждом запросе.
        moddekoder.КАТАЛОГ = self.папка.parent / "ploskosti"
        moddekoder.КАТАЛОГ.mkdir(parents=True, exist_ok=True)
        self._каталоги = каталоги_рядом(self.папка)
        # Настройки анализа людей (максимальный период поиска) — рядом с заданиями, не среди них:
        # задание берёт предел владельца при постановке в очередь.
        from .nastroyki import НастройкиЛюдей  # noqa: PLC0415
        self.настройки = НастройкиЛюдей(self.папка.parent / "potok_nastroyki")
        #: Массив до стольких бит берётся в память целиком; больше — окнами и по кускам (и в исполнителях).
        self.в_памяти_до = (int(в_памяти_мб) << 23) if в_памяти_мб else В_ПАМЯТИ_ДО
        self._каталоги["в_памяти_до"] = str(self.в_памяти_до)
        self._доли: dict[str, float] = {}
        self._lock = threading.Lock()
        self._журналы: dict[str, list[str]] = {}
        # Задачи исполнителей по заданиям: ждут или идут (законченные убираются).
        self._задачи: dict[str, ispolniteli.Задача] = {}
        # Пересчёты этапов по всему файлу у готовых заданий — отдельно: удаление этапов и «Остановить»
        # автомата их не снимают.
        self._пересчёты: dict[str, ispolniteli.Задача] = {}
        self._запуск_всего = threading.Lock()
        self._идут_вручную: set[str] = set()
        self._закрывается = False
        self._кэш: OrderedDict[tuple, np.ndarray] = OrderedDict()
        self._итоги: OrderedDict[tuple, Any] = OrderedDict()
        self._кэш_lock = threading.Lock()
        процессы = ispolniteli.процессами(процессы)
        размер = ispolniteli.размер_разборов(разборов)
        self._параметры_пулов = {
            "razbory": (размер, {"процессы": процессы, "понизить": 5,
                                 "на_владельца": ispolniteli.на_человека(размер, на_человека)}),
            # Стол: тяжёлые операции окон и ручные шаги производных потоков — по две на человека
            # одновременно, остальные его операции ждут (чужие — нет).
            "stol": (ispolniteli.размер_стола(стол), {"процессы": процессы, "понизить": 2, "на_владельца": 2}),
            # Пересчёт этапов по всему файлу (минуты и часы) — своими исполнителями: места стола остаются
            # окнам, а очередь между людьми — как у разборов.
            "ves": (размер, {"процессы": процессы, "понизить": 5,
                             "на_владельца": ispolniteli.на_человека(размер, на_человека)}),
        }
        if восстановить:
            self._восстановить()

    # -- приём ------------------------------------------------------------

    def создать(self, *, владелец: int, имя: str, данные: bytes = b"", профиль: str = "обычно",
                с_уровня: str = "неизвестно",
                снять: Sequence[str] = (), от: str = "", символ: Sequence[int] = (),
                фм: Sequence[int] = (),
                разбирать: bool = True, происхождение: Sequence[str] = (),
                шаги: Sequence[dict[str, Any]] = (), сессия: str = "", бит: int | None = None,
                источник: Массив | None = None, переместить: Path | None = None,
                по_выборке: bool = False) -> str:
        """Новое задание.

        ``шаги`` — ручная обработка производного потока (канал по маске,
        снятые слои): ``данные`` — поток, к которому они применяются (он
        хранится как «исходник.bin» — узел можно пересобрать и без родителя),
        результат — «вход.bin». ``разбирать=False`` — без автомата: шаги
        выполняются в исполнителях стола, не дожидаясь очереди разборов.
        ``сессия`` — задание принадлежит сессии: его видят все её участники, а уборка
        старых заданий его не трогает (удаляется вместе с сессией).
        ``бит`` — точная длина ``данные`` в битах, если хвост последнего байта — не данные.
        ``с_уровня`` — с какого уровня автомат начинает разбор (razbor.УРОВНИ_СТАРТА), хранится у узла.
        ``по_выборке`` — поток взят из этапа, найденного по началу файла: и этапы узла — по началу файла.

        Большой поток не передаётся байтами: ``источник`` — массив на диске (``hranenie.Источник``:
        файл сервера по ссылке остаётся ссылкой — без копии; файл другого узла связывается жёсткой
        ссылкой, его часть — копируется кусками), ``переместить`` — готовый файл (принятый кусками),
        который переносится в папку задания.
        """
        ид = time.strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)
        папка = self.папка / ид
        папка.mkdir(parents=True, exist_ok=True)
        файл = папка / ("исходник.bin" if шаги else "вход.bin")
        ссылка: dict[str, Any] | None = None
        if источник is not None:
            бит = источник.бит if бит is None else min(int(бит), источник.бит)
            байт = (бит + 7) // 8
            if источник.ссылка is not None:
                ссылка = {**источник.ссылка, "смещение": источник.смещение, "байт": байт,
                          "развернуть": источник.развернуть}
            else:
                источник.в_файл(файл)
        elif переместить is not None:
            os.replace(переместить, файл)
            байт = файл.stat().st_size
        else:
            записать_атомарно(файл, bytes(данные))
            байт = len(данные)
        self._записать(ид, {"ид": ид, "владелец": владелец, "имя": имя, "профиль": профиль,
                            "с_уровня": с_уровня, "снять": list(снять), "от": от, "состояние": "ждёт",
                            "символ": [int(k) for k in символ], "фм": [int(k) for k in фм],
                            "разбирать": bool(разбирать),
                            "происхождение": list(происхождение),
                            "шаги": [dict(ш) for ш in шаги], "сессия": сессия,
                            "создано": time.time(), "байт": байт, "этапы": [],
                            "период_до": self.настройки.период_до(владелец),
                            **({} if бит is None else {"исходных_бит" if шаги else "бит": int(бит)}),
                            **({} if ссылка is None else {("исходник_ссылка" if шаги else "ссылка"): ссылка}),
                            **({"по_выборке": True} if по_выборке else {}),
                            "отчёт": "", "ошибка": ""})
        with self._lock:
            self._журналы[ид] = []
        self._поставить(ид, владелец, bool(разбирать))
        self._прибрать(владелец)
        return ид

    def _пул(self, имя: str) -> ispolniteli.Пул:
        """Общий пул исполнителей (закрытый другим владельцем — например, остановленным приложением
        в тестах — заводится заново с теми же настройками)."""
        размер, параметры = self._параметры_пулов[имя]
        пул = getattr(self, "_" + имя, None)
        if пул is None or (пул._закрыт and not self._закрывается):
            пул = ispolniteli.общий(имя, размер, **параметры)
            setattr(self, "_" + имя, пул)
        return пул

    @property
    def разборы(self) -> ispolniteli.Пул:
        return self._пул("razbory")

    @property
    def стол(self) -> ispolniteli.Пул:
        return self._пул("stol")

    @property
    def весь(self) -> ispolniteli.Пул:
        return self._пул("ves")

    def _поставить(self, ид: str, владелец: Any, разбирать: bool) -> None:
        """Задание — в очередь исполнителей: разбор — к разборам, одни ручные шаги — к столу."""
        пул = self.разборы if разбирать else self.стол
        задача = пул.подать(self.выполнить, str(self.папка / ид), self._каталоги, разбирать,
                            владелец=владелец, имя=ид, срок=None,
                            при_сообщении=lambda вид, данные: self._сообщение(ид, вид, данные),
                            при_конце=lambda з: self._конец(ид, з))
        задача.пул = пул
        with self._lock:
            if not задача.готова():
                self._задачи[ид] = задача

    def _сообщение(self, ид: str, вид: str, данные: Any) -> None:
        """Ход из исполнителя: строка журнала (время проставил исполнитель)."""
        if вид == "ход":
            with self._lock:
                журнал = self._журналы.setdefault(ид, [])
                журнал.append(str(данные))
                del журнал[:-ЖУРНАЛ]
        elif вид == "доля":
            with self._lock:
                self._доли[ид] = float(данные)
        elif вид == "этап" and isinstance(данные, dict):
            try:
                self._этап_по_всему(ид, данные)
            except (OSError, ValueError, KeyError):
                pass                                 # узел удалили

    def _конец(self, ид: str, задача: ispolniteli.Задача) -> None:
        """Исполнитель закончил задание: итог (поля «готово»), ошибка или отмена — в состояние на диске."""
        with self._lock:
            if self._задачи.get(ид) is задача:
                del self._задачи[ид]
            self._доли.pop(ид, None)
        if self._закрывается and задача.состояние != "готово":
            return                                   # при выключении идущие остаются «идёт» — возобновятся
        try:
            состояние = self._прочитать_файл(ид)
        except (OSError, ValueError):
            return                                   # задание удалили
        if задача.состояние == "готово":
            if not isinstance(задача.итог, dict):
                return                               # папку удалили, пока задание ждало
            состояние.update(задача.итог)
        elif задача.состояние == "отменено":
            состояние.update(состояние="отменено", ошибка="разбор отменён", закончено=time.time())
            self._ход(ид, "разбор отменён")
        else:
            ошибка = задача.ошибка
            состояние.update(состояние="ошибка", закончено=time.time(),
                             ошибка=str(ошибка) or type(ошибка).__name__ if ошибка else "ошибка исполнителя")
        try:
            self._записать(ид, состояние)
        except OSError:
            return
        if задача.состояние == "готово" and (состояние.get("весь_файл") or {}).get("состояние") == "ждёт":
            self._этапы_по_всему(ид, состояние.get("владелец"))

    def _этапы_по_всему(self, ид: str, владелец: Any) -> None:
        """Этапы, найденные по началу файла, — пересчитать по всему файлу задачей исполнителя (с ходом и отменой).
        Свой пул: места стола (окна этого человека) пересчёт не занимает."""
        план = (self._прочитать_файл(ид).get("весь_файл") or {}).get("план") or []
        self._ход(ид, f"этапы {', '.join(str(п['номер']) for п in план)} пересчитываются по всему файлу")
        задача = self.весь.подать(в_исполнителе, self._каталоги, пересчитать_этапы, (str(self.папка / ид),),
                                  {"в_памяти_до": self.в_памяти_до}, владелец=владелец, имя=ид, срок=None,
                                  при_сообщении=lambda вид, данные: self._сообщение(ид, вид, данные),
                                  при_конце=lambda з: self._конец_всего(ид, з))
        задача.пул = self.весь
        with self._lock:
            if not задача.готова():
                self._пересчёты[ид] = задача

    def пересчитать_по_всему(self, ид: str) -> list[int]:
        """Снова пересчитать этапы по всему файлу (после «Остановить» или ошибки): этапы плана без готового
        пересчёта — «ждёт», задача — в очередь. Итог — номера этапов плана; ValueError — нечего или уже идёт."""
        with self._запуск_всего:
            with self._lock:
                if ид in self._пересчёты:
                    raise ValueError("пересчёт по всему файлу уже идёт")
                с = self._прочитать_файл(ид)
                весь = с.get("весь_файл") or {}
                if с.get("состояние") != "готово" or not весь.get("план"):
                    raise ValueError("пересчитывать по всему файлу нечего")
                if весь.get("состояние") == "готово":
                    raise ValueError("этапы уже пересчитаны по всему файлу")
                номера = [int(п["номер"]) for п in весь["план"]]
                for э in с.get("этапы") or []:
                    if э.get("номер") in номера and э.get("весь") != "готово":
                        э["весь"] = "ждёт"
                весь["состояние"] = "ждёт"
                весь.pop("ошибка", None)
                self._записать(ид, с)
            self._этапы_по_всему(ид, с.get("владелец"))
        return номера

    def _этап_по_всему(self, ид: str, данные: dict[str, Any]) -> None:
        """Этап пересчитан по всему файлу: выход и пометки этапа — в состояние, старые биты — из памяти.
        Этапа уже нет (удалили, пока считался) — то, что исполнитель успел дописать, убирается."""
        номер, бит = int(данные["номер"]), int(данные["бит"])
        папка = self.папка / ид
        self._забыть({str(папка / f"этап-{номер}.bin")})
        with self._lock:
            с = self._прочитать_файл(ид)
            этап = next((э for э in с.get("этапы") or [] if э.get("номер") == номер), None)
            if этап is None:
                for путь in (папка / f"этап-{номер}.bin", папка / f"весь-{номер}.бит"):
                    путь.unlink(missing_ok=True)
                return
            if этап.get("весь") == "готово" and этап.get("бит") == бит:
                return                               # уже отмечен (повтор после перезапуска)
            _по_всему(этап, бит)
            self._записать(ид, с)
        self._ход(ид, f"этап {номер} пересчитан по всему файлу: {бит} бит")

    def _конец_всего(self, ид: str, задача: ispolniteli.Задача) -> None:
        """Пересчёт этапов по всему файлу кончился: готово, отменён (этапы остаются по началу) или ошибка.

        Состояние сверяется с метками «весь-N.бит»: этап, чей файл уже подменён, — по всему файлу, даже если
        сообщение о нём не дошло (отмена сразу после подмены, перезапуск сервера); файлы удалённых этапов,
        которые исполнитель успел дописать, — с диска."""
        if self._закрывается and задача.состояние != "готово":
            return                                   # при выключении — возобновится при запуске
        папка = self.папка / ид
        сверены: set[str] = set()
        # Задача уходит из идущих под той же блокировкой, что пишется итог: «Пересчитать» не начнёт новый
        # пересчёт, пока итог прежнего не записан.
        with self._lock:
            if self._пересчёты.get(ид) is задача:
                del self._пересчёты[ид]
            self._доли.pop(ид, None)
            try:
                с = self._прочитать_файл(ид)
            except (OSError, ValueError):
                return                               # узел удалили
            весь = с.get("весь_файл") or {}
            этапы_ = с.get("этапы") or []
            for путь in [*папка.glob("этап-*.bin"), *папка.glob("весь-*.*")]:
                номер_ = re.match(r"(?:этап|весь)-(\d+)\.", путь.name)
                if путь.suffix == ".tmp" or (номер_ and int(номер_.group(1)) > len(этапы_)):
                    путь.unlink(missing_ok=True)
            готовы = set()
            for п in весь.get("план") or []:
                номер = int(п["номер"])
                try:
                    бит = int((папка / f"весь-{номер}.бит").read_text(encoding="utf-8"))
                except (OSError, ValueError):
                    continue
                for э in этапы_:
                    if э.get("номер") == номер:
                        if э.get("весь") != "готово" or э.get("бит") != бит:
                            _по_всему(э, бит)
                            сверены.add(str(папка / f"этап-{номер}.bin"))
                        готовы.add(номер)
            if задача.состояние == "готово" or all(int(п["номер"]) in готовы for п in весь.get("план") or []):
                итог = "готово"
            else:
                итог = "отменено" if задача.состояние == "отменено" else "ошибка"
            весь["состояние"] = итог
            if итог == "ошибка":
                весь["ошибка"] = str(задача.ошибка or "ошибка исполнителя")
            for э in этапы_:
                if э.get("весь") in ВЕСЬ_ИДЁТ:
                    э["весь"] = итог
            с["весь_файл"] = весь
            self._записать(ид, с)
        self._забыть(сверены)
        self._ход(ид, {"готово": "все этапы пересчитаны по всему файлу" if весь.get("план")
                       else "пересчитывать по всему файлу нечего — этапы удалены",
                       "отменено": "пересчёт по всему файлу остановлен — остальные этапы по началу файла"}.get(
                           итог, f"пересчёт по всему файлу не удался: {весь.get('ошибка')}"))

    def отменить(self, ид: str, *, весь: bool = False) -> str:
        """Отменить ждущее или идущее задание (``весь`` — его пересчёт этапов по всему файлу): «снято» (ещё
        ждало), «отменяется» (идёт — остановится через секунды), пусто — нечего отменять (уже закончено)."""
        with self._lock:
            задача = (self._пересчёты if весь else self._задачи).get(ид)
        if задача is None:
            return ""
        итог = задача.пул.отменить(задача)
        return {"снята": "снято", "отменяется": "отменяется"}.get(итог, "")

    def пересчитывается(self, ид: str, этап: int) -> bool:
        """Этап ``этап`` (1…) ждёт пересчёта по всему файлу или пересчитывается: его поток пока по началу файла."""
        return (self._этап(ид, этап) or {}).get("весь") in ВЕСЬ_ИДЁТ

    def проверить_целый(self, ид: str, этап: int) -> None:
        """Поток этапа берут целиком (скачать, продолжить, завести узел): пока этап пересчитывается по
        всему файлу — ``Пересчитывается``."""
        if self.пересчитывается(ид, этап):
            raise Пересчитывается("этап пересчитывается по всему файлу — дождитесь конца")

    def по_выборке(self, ид: str, этап: int) -> bool:
        """Поток массива (вход задания или выход этапа) — лишь по началу файла: этап найден по выборке и не
        пересчитан, или сам узел заведён из такого потока."""
        try:
            с = self._прочитать_файл(ид)
        except (OSError, ValueError):
            return False
        if с.get("по_выборке"):
            return True
        return bool(int(этап) >= 1 and (self._этап(ид, этап, с) or {}).get("по_выборке"))

    def слой_притока(self, ид: str, этап: int, номер: int) -> str:
        """Приток PDH, найденный по началу файла прямо во входе (этап 1), — слоем «pdh E2 приток k» со всего
        входа; пусто — так нельзя (приток не PDH, найден глубже или вход сам по началу файла)."""
        try:
            с = self._прочитать_файл(ид)
        except (OSError, ValueError):
            return ""
        э = self._этап(ид, этап, с)
        # Вход .Sig или текст «0101…» — не тот поток, что читал автомат: слой со входа дал бы мусор.
        if (int(этап) != 1 or not э or not э.get("по_выборке") or э.get("путь") or с.get("по_выборке")
                or с.get("поток_вид")):
            return ""
        уровень = re.match(r"PDH (E[234]) ", str(э.get("что") or ""))
        запись = next((п for п in э.get("притоки") or [] if п.get("номер") == int(номер)), None)
        if not уровень or not запись or not str(запись.get("имя")).isdigit():
            return ""
        return f"pdh {уровень.group(1)} приток {запись['имя']}"

    def _этап(self, ид: str, этап: int, состояние: dict[str, Any] | None = None) -> dict[str, Any] | None:
        if int(этап) < 1:
            return None
        if состояние is None:
            try:
                состояние = self._прочитать_файл(ид)
            except (OSError, ValueError):
                return None
        return next((э for э in состояние.get("этапы") or [] if э.get("номер") == int(этап)), None)

    def _восстановить(self) -> None:
        """После перезапуска сервера: ждавшие задания — снова в очередь, прерванные посреди разбора — тоже,
        с пометкой в журнале (прерванные ``ПЕРЕЗАПУСКОВ_ДО`` раз — ошибкой: вдруг они и роняют сервер)."""
        if not self.папка.exists():
            return
        незавершённые = []
        весь_файл = []
        for папка in self.папка.iterdir():
            try:
                с = _прочитать_состояние(папка)
            except (OSError, ValueError):
                continue
            if с.get("состояние") in ("ждёт", "идёт") and с.get("ид") not in self._задачи:
                незавершённые.append(с)
            elif (с.get("состояние") == "готово" and (с.get("весь_файл") or {}).get("состояние") == "ждёт"
                  and с.get("ид") not in self._пересчёты):
                весь_файл.append(с)                  # пересчёт этапов по всему файлу прервал перезапуск
        for с in sorted(незавершённые, key=lambda с: (с.get("создано") or 0, с.get("ид") or "")):
            ид = с["ид"]
            if с["состояние"] == "идёт":
                с["перезапусков"] = int(с.get("перезапусков") or 0) + 1
                if с["перезапусков"] >= ПЕРЕЗАПУСКОВ_ДО:
                    с.update(состояние="ошибка", ошибка=f"разбор {с['перезапусков']} раза прерывался перезапуском "
                             "сервера — не возобновляется сам: запустите его заново (продолжить или пересобрать)")
                    self._записать(ид, с)
                    continue
                с.update(состояние="ждёт", найдено_пока=[])
                self._записать(ид, с)
                self._ход(ид, "разбор прерван перезапуском сервера — начат заново")
            self._поставить(ид, с.get("владелец"), bool(с.get("разбирать", True)))
        for с in sorted(весь_файл, key=lambda с: (с.get("создано") or 0, с.get("ид") or "")):
            self._этапы_по_всему(с["ид"], с.get("владелец"))

    def посчитать(self, функция: Callable[..., Any], *args: Any, владелец: Any = 0, срок: float | None = None,
                  **kwargs: Any) -> Any:
        """Тяжёлый расчёт стола — в исполнителе стола (отдельный процесс), с папками матриц и плоскостей.

        ``функция`` — уровня модуля, аргументы — простые (``источник`` массива, а не его биты). Ошибка
        расчёта поднимается здесь же; не уложился в срок — ``ispolniteli.СрокВышел``.
        """
        return self.стол.выполнить(в_исполнителе, self._каталоги, функция, args, kwargs, владелец=владелец,
                                   срок=СРОК_СТОЛА if срок is None else срок)

    def подать_расчёт(self, функция: Callable[..., Any], *args: Any, владелец: Any = 0,
                      при_сообщении: Callable[[str, Any], None] | None = None,
                      срок_задачи: float | None = None) -> ispolniteli.Задача:
        """Долгий расчёт стола (разметка вслепую) — в исполнителе, без ожидания: задача с ходом и отменой."""
        задача = self.стол.подать(в_исполнителе, self._каталоги, функция, args, {}, владелец=владелец,
                                  при_сообщении=при_сообщении, срок=срок_задачи,
                                  имя=getattr(функция, "__name__", "расчёт"))
        задача.пул = self.стол
        return задача

    def источник(self, ид: str, этап: int):
        """Массив задания для исполнителя: путь файла и длина в битах (сами биты он читает сам);
        у ссылки на файл сервера — ещё отпечаток, часть и порядок бит, и предел памяти."""
        from .stol_raschety import Источник  # noqa: PLC0415
        м = self.массив(ид, этап)
        if м.ссылка is not None:
            return Источник(str(м.путь), м.бит, int(м.ссылка["хэш"][:15], 16), int(м.ссылка["размер"]), смещение=м.смещение,
                            развернуть=м.развернуть, ссылка=dict(м.ссылка), предел=self.в_памяти_до)
        сведения = м.путь.stat()
        return Источник(str(м.путь), м.бит, сведения.st_mtime_ns, сведения.st_size, предел=self.в_памяти_до)

    def идущие(self) -> set[str]:
        """Задания, которые сейчас разбираются (или выполняют шаги) в исполнителях."""
        with self._lock:
            return {и for и, з in self._задачи.items() if з.состояние == "идёт"} | self._идут_вручную

    @property
    def _идёт(self) -> str:
        """Одно из идущих заданий (пусто — ни одного); присваивание — для проверок: «идёт» вручную."""
        return next(iter(sorted(self.идущие())), "")

    @_идёт.setter
    def _идёт(self, ид: str) -> None:
        self._идут_вручную = {ид} if ид else set()

    def _освободить(self, удаляемые: Sequence[str], причина: str) -> None:
        """Перед удалением заданий: ждущие (и их ждущие пересчёты по всему файлу) — снять с очереди; если
        хоть одно идёт — ничего не трогать (ValueError с ``причина``)."""
        if self.идущие() & set(удаляемые):
            raise ValueError(причина)
        with self._lock:
            задачи = [з for и in удаляемые for з in (self._задачи.get(и), self._пересчёты.get(и)) if з is not None]
        if any(з.состояние == "идёт" for з in задачи):
            raise ValueError(причина and "в этой ветви идёт пересчёт по всему файлу — остановите его или дождитесь конца")
        for пул in (self.разборы, self.стол, self.весь):
            if not пул.снять([з for з in задачи if з.пул is пул]):
                raise ValueError(причина)

    def закрыть(self) -> None:
        """Остановить исполнителей (выключение сервера): идущие задания останутся «идёт» и возобновятся
        при следующем запуске."""
        self._закрывается = True
        for пул in (self.разборы, self.стол, self.весь):
            пул.закрыть()

    def продолжить(self, ид: str, этап: int, *, владелец: int, снять: Sequence[str] = (),
                   профиль: str = "обычно", с_уровня: str = "неизвестно") -> str:
        """Новое задание — с потока после этапа ``этап`` (1…), со снятием слоёв. Этап ещё пересчитывается по
        всему файлу — ``Пересчитывается``; этап по началу файла — и новый узел помечен так же."""
        состояние = self.прочитать(ид)
        файл = self._выгрузка_этапа(ид, этап)
        if файл is None or файл.suffix != ".bin":
            raise ValueError("после этого этапа нет битового потока — продолжать не с чего")
        self.проверить_целый(ид, этап)
        выборка = self.по_выборке(ид, этап)
        имя = f"{состояние['имя']} → этап {этап}" + (" (по началу файла)" if выборка else "")
        return self.создать(владелец=владелец, имя=имя, источник=self.массив(ид, этап),
                            профиль=профиль, с_уровня=с_уровня, снять=снять, от=f"{ид}#{этап}",
                            сессия=состояние.get("сессия") or "", по_выборке=выборка)

    def остановить(self, ид: str) -> bool:
        """Остановить идущий автомат задания: разбор кончается с тем, что уже нашёл, — как по исчерпанию времени
        (после текущей проверки). Разбор идёт в исполнителе — ему кладётся метка в папку задания. False —
        задание сейчас не разбирается (ждёт в очереди или уже готово)."""
        if ид not in self.идущие() or not (self.папка / ид / РАЗБОР_ФАЙЛ).exists():
            return False
        try:
            записать_атомарно(self.папка / ид / СТОП_ФАЙЛ, b"1")
        except OSError:
            return False
        self._ход(ид, "остановлено оператором: разбор закончит текущую проверку и выдаст то, что уже нашёл")
        return True

    # -- чтение -----------------------------------------------------------

    def прочитать(self, ид: str) -> dict[str, Any]:
        путь = self.папка / ид / "состояние.json"
        if not путь.exists():
            raise KeyError(ид)
        состояние = json.loads(путь.read_text(encoding="utf-8"))
        with self._lock:
            состояние["журнал"] = list(self._журналы.get(ид, []))[-80:]
            задача = self._задачи.get(ид)
            пересчёт = self._пересчёты.get(ид)
            if ид in self._доли:
                состояние["доля"] = self._доли[ид]
        if состояние["состояние"] == "ждёт":
            состояние["перед_ним"] = задача.пул.перед(задача) if задача is not None else 0
        if пересчёт is not None and пересчёт.состояние == "ждёт" and состояние.get("весь_файл"):
            состояние["весь_файл"]["перед_ним"] = пересчёт.пул.перед(пересчёт)   # пересчёт в очереди
        return состояние

    def список(self, владелец: int | None = None, сессии: Sequence[str] = (),
               без_сессий: bool = False) -> list[dict[str, Any]]:
        """Задания владельца и задания доступных ему сессий (``сессии``).

        ``без_сессий`` — только задания вне сессий (список «Мои разборы»).
        """
        итог = []
        if not self.папка.exists():
            return итог
        сессии = set(сессии)
        for папка in sorted(self.папка.iterdir(), reverse=True):
            путь = папка / "состояние.json"
            if not путь.exists():
                continue
            с = json.loads(путь.read_text(encoding="utf-8"))
            if без_сессий and с.get("сессия"):
                continue
            if владелец is not None and с.get("владелец") != владелец and с.get("сессия") not in сессии:
                continue
            итог.append({к: с.get(к) for к in ("ид", "имя", "состояние", "создано", "байт",
                                                 "профиль", "с_уровня", "от", "снять", "разбирать",
                                                 "сессия", "владелец", "по_выборке")}
                        | {"этапов": len(с.get("этапы") or []), "шаги": с.get("шаги") or []})
        # Свежие сверху: по времени создания — у заданий одной секунды имя папки
        # различается случайным хвостом, и уборка иначе могла бы снести новое.
        итог.sort(key=lambda з: з.get("создано") or 0, reverse=True)
        return итог

    # -- дерево обработки -----------------------------------------------------

    def дерево(self, ид: str, владелец: int, сессии: Sequence[str] = ()) -> dict[str, Any]:
        """Всё дерево, в котором стоит узел: корень, этапы-развилки и производные.

        Узел — задание; его дети — задания с «от» = «ид#этап». Родителя,
        которого удалили, нет — тогда корнем становится ближайший живой.
        """
        все = {з["ид"]: з for з in self.список(владелец, сессии)}
        if ид not in все:
            raise KeyError(ид)
        корень = ид
        while True:
            родитель = (все[корень].get("от") or "").split("#")[0]
            if родитель not in все:
                break
            корень = родитель
        return self._деревья(все, [корень])[0]

    def деревья_сессии(self, сессия: str) -> list[dict[str, Any]]:
        """Деревья всех файлов сессии за один проход по заданиям — по порядку добавления файлов.

        Стол сессии открывается одним запросом, а не запросом на каждый файл
        (каждый из которых заново перечитывал бы все задания).
        """
        все = {з["ид"]: з for з in self.список() if з.get("сессия") == сессия}
        корни = sorted((и for и, з in все.items() if (з.get("от") or "").split("#")[0] not in все),
                       key=lambda и: (все[и].get("создано") or 0, и))
        return self._деревья(все, корни)

    def _деревья(self, все: dict[str, dict[str, Any]], корни: Sequence[str]) -> list[dict[str, Any]]:
        дети: dict[str, list[dict[str, Any]]] = {}
        for з in все.values():
            родитель = (з.get("от") or "").split("#")[0]
            if родитель in все:
                дети.setdefault(родитель, []).append(з)

        def кратко(ид_: str) -> dict[str, Any]:
            """Этапы узла коротко — для сетки массивов на рабочем столе."""
            try:
                с = self._прочитать_файл(ид_)
            except (OSError, ValueError):
                return {"этапы_кратко": [], "происхождение": []}
            return {"этапы_кратко": [{к: э.get(к) for к in ("номер", "уровень", "что", "выход", "выгрузка",
                                                           "уверенность", "весь", "по_выборке")}
                                     | {"притоков": len(э.get("притоки") or [])}
                                     for э in с.get("этапы") or []],
                    "происхождение": с.get("происхождение") or []}

        def узел(з: dict[str, Any]) -> dict[str, Any]:
            от = з.get("от") or ""
            return {**з, **кратко(з["ид"]), "этап_родителя": int(от.split("#")[1]) if "#" in от else None,
                    "дети": [узел(д) for д in sorted(дети.get(з["ид"], []),
                                                     key=lambda д: д.get("создано") or 0)]}

        return [узел(все[к]) for к in корни]

    def удалить(self, ид: str, владелец: int, сессии: Sequence[str] = ()) -> list[str]:
        """Удалить узел и всю ветвь под ним. Идущий разбор не трогаем."""
        удаляемые = _ид_ветви(_узел_дерева(self.дерево(ид, владелец, сессии), ид))
        self._освободить(удаляемые, "в этой ветви идёт разбор — дождитесь его конца")
        self._стереть(удаляемые)
        return удаляемые

    def удалить_ветку(self, ид: str, этап: int, владелец: int, сессии: Sequence[str] = (),
                      нельзя: Callable[[dict[str, Any]], str] = lambda у: "") -> dict[str, Any]:
        """Удалить ветку таблицы массивов с узла (задание, этап) — всё, что под ним в сетке.

        Этап 0 — вход задания: задание и всё, что из него получено (как ``удалить``).
        Этап k ≥ 1 — выход этапа автомата: этапы k, k+1, … задания (их файлы, сведения в
        состоянии, журнал и разметка, запомненные итоги) и производные задания, выросшие из
        этих этапов, — со своими ветвями; этапы до k и выросшее из них остаются. Идущий
        разбор не трогаем. ``нельзя(узел)`` — почему пользователю нельзя удалить узел (пусто —
        можно): проверяется у каждого задания, которое уйдёт, — чужое внутри ветки не удаляется
        заодно со своим, вся ветка отвергается (ValueError). Итог — удалённые задания,
        сколько этапов задания ушло и сколько массивов (узлов сетки) всего.
        """
        return self._удалить_с(_узел_дерева(self.дерево(ид, владелец, сессии), ид), int(этап), нельзя)

    def удалить_ветки(self, пункты: Sequence[tuple[str, int]], владелец: int, сессии: Sequence[str] = (),
                      нельзя: Callable[[dict[str, Any]], str] = lambda у: "") -> dict[str, Any]:
        """Удалить несколько веток одним вызовом — по порядку пунктов (задание, этап).

        Ветка, которой уже нет (ушла вместе с выбранной выше, удалена кем-то раньше или не
        видна пользователю), пропускается. ``нельзя(узел)`` — почему пользователю нельзя
        удалить узел задания (пусто — можно): отказ, как и идущий разбор, не мешает
        остальным веткам — он попадает в итог с причиной.
        """
        итог: dict[str, Any] = {"задания": [], "этапы": [], "массивов": 0, "пропущено": 0, "отказано": []}
        for ид, этап in пункты:
            try:
                узел = _узел_дерева(self.дерево(ид, владелец, сессии), ид)
            except KeyError:
                узел = None
            if узел is None or not 0 <= этап <= len(узел["этапы_кратко"]):
                итог["пропущено"] += 1
                continue
            причина = нельзя(узел)
            if not причина:
                try:
                    ветка = self._удалить_с(узел, этап, нельзя)
                except ValueError as ошибка:
                    причина = str(ошибка)
            if причина:
                итог["отказано"].append({"ид": ид, "этап": этап, "причина": причина})
                continue
            итог["задания"] += ветка["задания"]
            итог["массивов"] += ветка["массивов"]
            if этап:
                итог["этапы"].append({"ид": ид, "с": этап, "этапов": ветка["этапов"]})
        return итог

    def _удалить_с(self, узел: dict[str, Any], этап: int,
                   нельзя: Callable[[dict[str, Any]], str] = lambda у: "") -> dict[str, Any]:
        """Удаление ветки с узла дерева ``узел`` (задание) и его этапа ``этап`` — см. ``удалить_ветку``."""
        ид = узел["ид"]
        этапов = len(узел["этапы_кратко"])
        if not 0 <= этап <= этапов:
            raise KeyError(f"{ид}#{этап}")
        дети = [д for д in узел["дети"] if (д["этап_родителя"] or 0) >= этап] if этап else [узел]
        чужих = sum(1 for д in дети for н in _узлы_ветви(д) if нельзя(н))
        if чужих:
            raise ValueError(f"в ветке есть чужие узлы ({чужих}): их вправе удалить только их автор или владелец сессии")
        удаляемые = [и for д in дети for и in _ид_ветви(д)]
        # Этап k ≥ 1 переписывает состояние самого задания — и его разбор не должен идти; пересчёт его этапов
        # по всему файлу идёт дальше — план обрезается до этапов раньше k (см. ``пересчитать_этапы``).
        причина = "в этой ветви идёт разбор — дождитесь его конца"
        if этап and ид in self.идущие():
            raise ValueError(причина)
        self._освободить(удаляемые, причина)
        массивов = sum(_массивов(д) for д in дети)
        self._стереть(удаляемые)
        if not этап:
            return {"задания": удаляемые, "этапов": 0, "массивов": массивов}
        папка = self.папка / ид
        # Сперва состояние (этапы и план пересчёта), потом файлы: пересчёт видит обрезанный план и файлы
        # удалённых этапов не пишет (успел дописать — уберёт ``_этап_по_всему`` или ``_конец_всего``).
        with self._lock:
            состояние = self._прочитать_файл(ид)
            состояние["этапы"] = состояние["этапы"][:этап - 1]
            весь = состояние.get("весь_файл")
            if весь:
                весь["план"] = [п for п in весь.get("план") or [] if int(п["номер"]) < этап]
                if not весь["план"]:
                    весь["состояние"] = "готово"     # пересчитывать больше нечего (ждущий пересчёт снят ниже)
            # Отчёт уходит помощнику: пусть знает, что этих находок больше нет.
            пометка = f"Этап {этап} удалён вручную." if этапов == этап else f"Этапы {этап}–{этапов} удалены вручную."
            состояние["отчёт"] = "\n\n".join(ч for ч in ((состояние.get("отчёт") or "").rstrip(), пометка) if ч)
            self._записать(ид, состояние)
            for имя in ("журнал-стола.json", "разметка.json", ВИД_ФАЙЛ):
                _без_этапов_с(папка / имя, этап)
        лишние = [путь for н in range(этап, этапов + 1)
                  for путь in [*папка.glob(f"этап-{н}.*"), *папка.glob(f"приток-{н}-*.bin"), *папка.glob(f"весь-{н}.*")]]
        for путь in лишние:
            путь.unlink(missing_ok=True)
        self._забыть({str(путь) for путь in лишние})
        if весь and not весь["план"]:
            self.отменить(ид, весь=True)
        return {"задания": удаляемые, "этапов": этапов - этап + 1, "массивов": массивов + этапов - этап + 1}

    def удалить_сессию(self, сессия: str) -> list[str]:
        """Удалить все задания сессии. Идущий разбор не трогаем — тогда ничего не удаляем."""
        свои = [з["ид"] for з in self.список() if з.get("сессия") == сессия]
        self._освободить(свои, "в сессии идёт разбор — дождитесь его конца или отмените его")
        self._стереть(свои)
        return свои

    def _стереть(self, удаляемые: Sequence[str]) -> None:
        """Папки заданий — с диска; их журналы хода, биты и итоги расчётов — из памяти."""
        стёртые: set[str] = set()
        for и in удаляемые:
            папка = self.папка / и
            # Ту же ветку мог только что удалить другой участник сессии: чего уже нет — пропускаем.
            try:
                for файл in (папка.iterdir() if папка.is_dir() else ()):
                    стёртые.add(str(файл))
                    файл.unlink(missing_ok=True)
                папка.rmdir()
            except FileNotFoundError:
                pass
            with self._lock:
                self._журналы.pop(и, None)
        self._забыть(стёртые)

    def _забыть(self, файлы: set[str]) -> None:
        """Распакованные биты и итоги расчётов удалённых файлов больше не нужны — память освобождается."""
        with self._кэш_lock:
            for запас in (self._кэш, self._итоги):
                for ключ in [к for к in запас if к[0] in файлы]:
                    del запас[ключ]

    def файл_этапа(self, ид: str, этап: int) -> Path | None:
        return self._выгрузка_этапа(ид, этап)

    # -- разметка бит массива ----------------------------------------------------------

    def разметка(self, ид: str, этап: int) -> dict[str, Any]:
        """Разметка массива (отрезки, правила, закладки) — общая для всех, кто видит задание."""
        путь = self.папка / ид / "разметка.json"
        пустая = {"отрезки": [], "правила": [], "закладки": []}
        try:
            все = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
        except ValueError:
            все = {}
        return пустая | (все.get(str(int(этап))) or {})

    def записать_разметку(self, ид: str, этап: int, разметка: dict[str, Any]) -> None:
        путь = self.папка / ид / "разметка.json"
        with self._lock:
            try:
                все = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
            except ValueError:
                все = {}
            if разметка.get("отрезки") or разметка.get("правила") or разметка.get("закладки"):
                все[str(int(этап))] = разметка
            else:
                все.pop(str(int(этап)), None)
            записать_атомарно(путь, json.dumps(все, ensure_ascii=False))

    # -- вид массива: период строки и прочее, что относится к самим данным ---------------

    def вид(self, ид: str, этап: int) -> dict[str, Any]:
        """Вид массива на столе (период, первый бит, порядок, выравнивание…) — свой у каждого узла,
        общий для участников сессии; пусто — вида ещё нет (стол берёт свой по умолчанию)."""
        путь = self.папка / ид / ВИД_ФАЙЛ
        try:
            все = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
        except ValueError:
            все = {}
        return dict(все.get(str(int(этап))) or {})

    def записать_вид(self, ид: str, этап: int, вид: dict[str, Any], *, кто: int = 0,
                     откуда: str = "оператор") -> dict[str, Any]:
        """Сохранить вид массива (очищенный ``чистый_вид``); пустой — удалить. Возвращает сохранённое."""
        путь = self.папка / ид / ВИД_ФАЙЛ
        if not (self.папка / ид).is_dir():
            raise KeyError(ид)
        чистый = чистый_вид(вид)
        if чистый:
            чистый.update(изменил=int(кто), изменено=time.time(), откуда=str(откуда)[:200])
        with self._lock:
            try:
                все = json.loads(путь.read_text(encoding="utf-8")) if путь.exists() else {}
            except ValueError:
                все = {}
            if чистый:
                все[str(int(этап))] = чистый
            else:
                все.pop(str(int(этап)), None)
            записать_атомарно(путь, json.dumps(все, ensure_ascii=False))
        return чистый

    def биты_участка(self, ид: str, этап: int, от: int = 0, до: int | None = None) -> np.ndarray:
        """Биты [от, до) массива — без распаковки всего файла.

        Поиску периода или скремблера нужно начало потока, а распаковать массив
        в сотни мегабайт — секунды: читается и распаковывается только участок
        (если весь массив уже в памяти — берётся из неё). Массив любого размера, и ссылка тоже.
        """
        массив = self.массив(ид, этап)
        with self._кэш_lock:
            биты = self._кэш.get(массив.ключ)
        до = массив.бит if до is None else max(0, min(int(до), массив.бит))
        от = max(0, min(int(от), до))
        if биты is not None:
            return биты[от:до]
        биты = массив.биты(от, до)
        биты.flags.writeable = False
        return биты

    def запомнить(self, ид: str, этап: int, ключ: str, посчитать) -> Any:
        """Результат долгого расчёта над массивом — один раз на файл и параметры.

        Файл этапа после записи не меняется, поэтому ключ — путь, время и размер
        файла плюс имя и параметры расчёта: повторный запрос (второй пользователь
        сессии, возврат к массиву) отвечает сразу. ``посчитать()`` сам берёт нужные
        биты (``биты`` или ``биты_участка``).
        """
        к = self.массив(ид, этап).ключ
        полный = (*к[:3], ключ, *к[3:])         # имя расчёта — четвёртым, как прежде
        with self._кэш_lock:
            if полный in self._итоги:
                self._итоги.move_to_end(полный)
                return self._итоги[полный]
        итог = посчитать()
        with self._кэш_lock:
            self._итоги[полный] = итог
            while len(self._итоги) > ИТОГОВ_ПОМНИТЬ:
                self._итоги.popitem(last=False)
        return итог

    # -- журнал массива на рабочем столе ------------------------------------------

    def журнал_стола(self, ид: str) -> dict[str, list[dict[str, Any]]]:
        """Записи аналитика и итоги операций по массивам узла: {этап: [записи]}."""
        путь = self.папка / ид / "журнал-стола.json"
        if not путь.exists():
            return {}
        try:
            return json.loads(путь.read_text(encoding="utf-8"))
        except ValueError:
            return {}

    def записать_в_журнал(self, ид: str, этап: int, запись: dict[str, Any]) -> dict[str, Any]:
        if not (self.папка / ид).exists():
            raise KeyError(ид)
        чистая = {"время": time.time(), "операция": str(запись.get("операция", ""))[:200],
                  "текст": str(запись.get("текст", ""))[:20000],
                  "слой": str(запись.get("слой", ""))[:2000]}
        with self._lock:
            журнал = self.журнал_стола(ид)
            записи = журнал.setdefault(str(int(этап)), [])
            записи.append(чистая)
            del записи[:-ЖУРНАЛ_СТОЛА]
            путь = self.папка / ид / "журнал-стола.json"
            записать_атомарно(путь, json.dumps(журнал, ensure_ascii=False))
        return чистая

    def приток(self, ид: str, этап: int, номер: int) -> tuple[bytes, str]:
        """Байты притока этапа и его имя."""
        состояние = self.прочитать(ид)
        этапы = состояние.get("этапы") or []
        if not 1 <= int(этап) <= len(этапы):
            raise ValueError("нет такого этапа")
        притоки = этапы[int(этап) - 1].get("притоки") or []
        запись = next((п for п in притоки if п["номер"] == int(номер)), None)
        файл = self.папка / ид / f"приток-{int(этап)}-{int(номер)}.bin"
        if запись is None or not файл.exists():
            raise ValueError("у этого этапа нет такого притока")
        return файл.read_bytes(), запись["имя"]

    def файл_бит(self, ид: str, этап: int) -> Path:
        """Файл битового потока массива: этап 0 — вход задания, дальше — поток после этапа.

        У узла, добавленного по ссылке, своего файла нет — его биты читает ``массив``.
        """
        if int(этап) == 0:
            файл = self.папка / ид / "вход.bin"
            if not файл.exists():
                try:
                    ссылка = self._прочитать_файл(ид).get("ссылка")
                except (OSError, ValueError):
                    ссылка = None
                if ссылка:
                    raise ValueError("массив — ссылка на файл сервера: его читает массив()")
                raise ValueError("поток массива ещё не готов")
            return файл
        файл = self._выгрузка_этапа(ид, этап)
        if файл is None or файл.suffix != ".bin":
            raise ValueError("у этого этапа нет битового потока")
        return файл

    def _источник_узла(self, ид: str, состояние: dict[str, Any], что: str) -> Массив:
        """Вход или исходник узла (см. ``массив_узла``); новое время файла по ссылке — в состояние."""
        ключ = "ссылка" if что == "вход" else "исходник_ссылка"

        def сверено(новая: dict[str, Any]) -> None:
            # Файл скопировали заново (время другое, содержимое то же) — помним новое время.
            with self._lock:
                с = self._прочитать_файл(ид)
                if с.get(ключ):
                    с[ключ] = {**с[ключ], "изменён_нс": новая["изменён_нс"]}
                    self._записать(ид, с)
        return массив_узла(self.папка / ид, состояние, что, сверено)

    def массив(self, ид: str, этап: int) -> Массив:
        """Биты массива на диске — окнами и кусками (см. hranenie): этап 0 — вход задания
        (свой файл или ссылка на файл сервера), дальше — поток после этапа (.bin).

        Файл по ссылке удалён или изменён — ``ФайлИзменён`` (это ValueError) со словами.
        """
        if int(этап) == 0:
            return self._источник_узла(ид, self._прочитать_файл(ид), "вход")
        файл = self.файл_бит(ид, этап)
        # Точная длина: хвост последнего байта — не данные. Файл пересчитанного этапа подменён, а пометка
        # ещё прежняя (по началу файла) — длина по файлу, а не по пометке.
        бит = (self._этап(ид, этап) or {}).get("бит")
        годна = isinstance(бит, int) and (бит + 7) // 8 == файл.stat().st_size
        return Массив(файл, бит=бит if годна else None)

    def длина_бит(self, ид: str, этап: int) -> int:
        """Сколько бит в массиве: файл — целые байты, а после шагов (обрезка, разметка) длина бывает не кратна 8."""
        return self.массив(ид, этап).бит

    def биты(self, ид: str, этап: int) -> np.ndarray:
        """Биты потока: этап 0 — исходный файл, дальше — поток после этапа (.bin).

        Распакованные биты держатся в памяти (до ``КЭШ_БИТ``): каждое действие на
        рабочем столе берёт биты массива, и файл не читается заново. Ключ — путь,
        время изменения и размер: пересобранный массив читается заново. Массив
        только для чтения — чтобы действие не испортило его для следующих.

        Массив больше ``в_памяти_до`` бит целиком не берётся — ``СлишкомБольшой``:
        такому действию нужны окно (``биты_участка``) или проход по кускам (``массив``).
        """
        массив = self.массив(ид, этап)
        ключ = массив.ключ
        with self._кэш_lock:
            биты = self._кэш.get(ключ)
            if биты is not None:
                self._кэш.move_to_end(ключ)
                return биты
        if массив.бит > self.в_памяти_до:
            raise СлишкомБольшой(f"Массив {массив.бит // 8 >> 20} МБ больше предела ({self.в_памяти_до // 8 >> 20} МБ)")
        биты = массив.все()
        биты.flags.writeable = False
        if len(биты) <= КЭШ_БИТ:
            with self._кэш_lock:
                self._кэш[ключ] = биты
                while sum(len(б) for б in self._кэш.values()) > КЭШ_БИТ:
                    self._кэш.popitem(last=False)
        return биты

    # -- журнал хода --------------------------------------------------------

    def _ход(self, ид: str, строка: str) -> None:
        with self._lock:
            журнал = self._журналы.setdefault(ид, [])
            журнал.append(time.strftime("%H:%M:%S ") + строка)
            del журнал[:-ЖУРНАЛ]

    # -- хранение ---------------------------------------------------------

    def _выгрузка_этапа(self, ид: str, этап: int) -> Path | None:
        for путь in (self.папка / ид).glob(f"этап-{int(этап)}.*"):
            return путь
        return None

    def _прочитать_файл(self, ид: str) -> dict[str, Any]:
        return json.loads((self.папка / ид / "состояние.json").read_text(encoding="utf-8"))

    def _записать(self, ид: str, состояние: dict[str, Any]) -> None:
        записать_атомарно(self.папка / ид / "состояние.json", json.dumps(состояние, ensure_ascii=False))

    def _прибрать(self, владелец: int) -> None:
        свои = [з for з in self.список(владелец, без_сессий=True) if з["состояние"] in ЗАКОНЧЕНО]
        лишние = [з["ид"] for з in свои[ХРАНИТЬ:]]
        try:
            self._освободить(лишние, "")
        except ValueError:
            return                                   # старое задание снова в работе — уберём в другой раз
        # Два запроса одного человека убирают одновременно: чего уже нет — пропускается.
        self._стереть(лишние)
