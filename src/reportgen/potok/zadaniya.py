"""Задания разбора потока для страницы «Разбор потока»: в фоне, по этапам.

Разбор потока занимает от секунд до десятков минут, и держать ради него
запрос нельзя. Поэтому — задания: файл принят, задание встало в очередь,
страница спрашивает его состояние и показывает этапы по мере того, как
они находятся, и журнал: что анализатор пробует прямо сейчас.

Разборы идут параллельно, каждый — в своём процессе-исполнителе (см.
``ispolniteli``): их столько, сколько ядер (настройка ``potok_razborov``),
очередь между людьми честная — человек с двадцатью файлами не задерживает
остальных. Ход разбора исполнитель присылает в сервер сразу — журнал виден
вживую; состояние задания исполнитель пишет на диск атомарно. Ручные шаги
производного потока (без автомата) идут в исполнителях стола — не ждут
долгих разборов. Задание можно отменить — и ждущее, и идущее.

Каждое задание лежит в своей папке: исходный файл, результат (JSON) и
потоки после этапов — чтобы их можно было скачать и продолжить разбор с
любого этапа, в том числе сняв слой вручную. Задания переживают
перезапуск сервера: состояние читается из папки, а незавершённые (ждавшие
и прерванные посреди разбора) встают в очередь заново.
"""

