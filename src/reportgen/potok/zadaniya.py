#: Вид массивов узла на столе ({этап: вид}): период строки, первый бит, порядок, выравнивание.
ВИД_ФАЙЛ = "вид-стола.json"
#: Наибольшая длина строки (период) битового просмотра.
ВИД_ШИРИНА_ДО = 1 << 20
#: Вид просмотра: значения, которые знает стол.
ВИДЫ_ПРОСМОТРА = ("биты", "hex", "dec", "bin", "текст", "HEX", "DEC", "BIN", "ТЕКСТ")
ВИДЫ_КАДРОВ = ("2", "10", "16", "т")


def чистый_вид(данные: Any) -> dict[str, Any]:
    """Вид массива из запроса — только знакомые поля в своих пределах; лишнее отбрасывается,
    неверное значение — ValueError (ширина, сдвиг — целые, ширина от 1 до ВИД_ШИРИНА_ДО)."""
    if данные in (None, {}):
        return {}
    if not isinstance(данные, dict):
        raise ValueError("вид — объект {ширина, сдвиг, принят, порядок, …}")

    def целое(ключ: str, от: int, до: int) -> int | None:
        if данные.get(ключ) in (None, ""):
            return None
        if isinstance(данные[ключ], bool):
            raise ValueError(f"{ключ} — целое число")
        try:
            значение = int(данные[ключ])
        except (TypeError, ValueError, OverflowError):
            raise ValueError(f"{ключ} — целое число") from None
        if not от <= значение <= до:
            raise ValueError(f"{ключ} — от {от} до {до}")
        return значение

    итог: dict[str, Any] = {}
    for ключ, от, до in (("ширина", 1, ВИД_ШИРИНА_ДО), ("сдвиг", 0, 1 << 40), ("шаг", 1, ВИД_ШИРИНА_ДО),
                         ("ширинаМетки", 1, 64)):
        значение = целое(ключ, от, до)
        if значение is not None:
            итог[ключ] = значение
    if "ширина" in итог and "сдвиг" in итог:
        итог["сдвиг"] %= итог["ширина"]
    if "принят" in данные:
        итог["принят"] = bool(данные["принят"]) and "ширина" in итог
    if данные.get("порядок") in ("старший", "младший"):
        итог["порядок"] = данные["порядок"]
    if данные.get("вид") in ВИДЫ_ПРОСМОТРА:
        итог["вид"] = данные["вид"]
    if str(данные.get("кадрыВид") or "") in ВИДЫ_КАДРОВ:
        итог["кадрыВид"] = str(данные["кадрыВид"])
    строки = данные.get("строкиПо")
    if isinstance(строки, dict) and str(строки.get("слово") or "").strip():
        слово = str(строки["слово"]).strip()[:300]
        try:
            ошибок, не_ближе = int(строки.get("ошибок") or 0), int(строки.get("неБлиже") or 0)
        except (TypeError, ValueError, OverflowError):
            raise ValueError("строкиПо: ошибок и неБлиже — целые числа") from None
        итог["строкиПо"] = {"слово": слово, "ошибок": max(0, min(64, ошибок)),
                            "неБлиже": max(0, min(ВИД_ШИРИНА_ДО, не_ближе))}
    return итог


#: Шаги, после которых строка массива та же (длина и место бит): ребёнок наследует вид родителя.
#: Обрезка и «сдвиг» переносят первый бит; коды, маски, вырезка по разметке — нет (строка другая).
_ВИД_СОХРАНЯЮТ = ("инверсия", "xor", "скремблер", "моддекодер", "метки", "реверс", "nrzi", "накоплен")


def унаследованный_вид(вид: dict[str, Any], шаги: Sequence[dict[str, Any]]) -> dict[str, Any]:
    """Вид ребёнка по виду родителя и шагам, которыми ребёнок получен; пусто — не наследуется."""
    if not вид or not вид.get("ширина"):
        return {}
    итог = {к: в for к, в in вид.items() if к in ("ширина", "сдвиг", "принят", "порядок", "вид", "шаг",
                                                    "ширинаМетки", "кадрыВид", "строкиПо")}
    ширина = int(итог["ширина"])
    for шаг in шаги:
        if not шаг.get("вкл", True):
            continue
        if шаг.get("вид") != "слой":
            return {}
        слой = str(шаг.get("слой") or "").strip().lower()
        слово = слой.split()[0] if слой else ""
        числа = [int(ч) for ч in re.findall(r"\d+", слой)]
        if слово.startswith("обрез") or слово == "сдвиг":
            # «обрезка начало N конец M», «сдвиг N»: первый бит строки уезжает на N.
            итог["сдвиг"] = (int(итог.get("сдвиг") or 0) - (числа[0] if числа else 0)) % ширина
            итог.pop("строкиПо", None)
        elif слово.startswith("аддитивн") and any(с in слой for с in ("кадр", "блок", "начальн")):
            continue
        elif not any(слово.startswith(с) for с in _ВИД_СОХРАНЯЮТ):
            return {}
    return итог
