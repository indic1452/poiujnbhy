"""Октетный стаффинг: асинхронное HDLC/PPP (RFC 1662) и SLIP (RFC 1055).

Битстаффинг — это синхронное HDLC (модуль hdlc). На асинхронных линиях
(модемы, радиомодемы, последовательные порты) прозрачность обеспечивается
иначе — целыми байтами:

- **асинхронное HDLC / PPP**: кадр между флагами-байтами 0x7E; байт 0x7E
  или 0x7D внутри кадра (и управляющие байты по карте ACCM) передаётся как
  0x7D и сам байт с инвертированным битом 5 (xor 0x20). В конце кадра —
  FCS-16 или FCS-32, как в синхронном HDLC. Верная FCS доказывает и границы
  кадров, и снятое экранирование;
- **SLIP**: кадр кончается байтом 0xC0, внутри 0xC0 → 0xDB 0xDC, 0xDB →
  0xDB 0xDD. Проверочной суммы нет — правильность разбора доказывают
  контрольные суммы пакетов IP в кадрах.

Байтовая граница в битовом ряду неизвестна (поток мог прийти после снятия
скремблера или кода), поэтому выравнивание берётся по флагам: у настоящих
флагов-байтов позиция по модулю 8 одна и та же.
"""

from __future__ import annotations

from collections import Counter

import numpy as np

from . import hdlc, pakety
from .bity import в_байты
from .nahodka import Находка

ФЛАГ = 0x7E
ЭКРАН = 0x7D
SLIP_КОНЕЦ, SLIP_ЭКРАН, SLIP_ВМЕСТО_КОНЦА, SLIP_ВМЕСТО_ЭКРАНА = 0xC0, 0xDB, 0xDC, 0xDD
ВЫБОРКА = 1 << 23
ПРОВЕРЯТЬ_КАДРОВ = 3000


def снять_экранирование(тело: bytes) -> tuple[bytes, int] | None:
    """0x7D x → x ^ 0x20. Возвращает кадр и число снятых экранов (None — кадр битый)."""
    if ЭКРАН not in тело:
        return тело, 0
    итог = bytearray()
    экранов = 0
    шаг = iter(тело)
    for байт in шаг:
        if байт == ЭКРАН:
            следующий = next(шаг, None)
            if следующий is None:
                return None                     # экран в конце кадра — кадр оборван
            итог.append(следующий ^ 0x20)
            экранов += 1
        else:
            итог.append(байт)
    return bytes(итог), экранов


def кадры_асинхронные(данные: bytes) -> list[tuple[bytes, int]]:
    """Кадры между флагами 0x7E со снятым экранированием: (кадр, экранов)."""
    итог = []
    for тело in данные.split(bytes([ФЛАГ])):
        if len(тело) < 4:                       # пусто между соседними флагами
            continue
        снято = снять_экранирование(тело)
        if снято is not None:
            итог.append(снято)
    return итог


def кадры_slip(данные: bytes) -> list[bytes]:
    итог = []
    for тело in данные.split(bytes([SLIP_КОНЕЦ])):
        if len(тело) < 20:
            continue
        кадр = bytearray()
        годен = True
        шаг = iter(тело)
        for байт in шаг:
            if байт == SLIP_ЭКРАН:
                следующий = next(шаг, None)
                if следующий == SLIP_ВМЕСТО_КОНЦА:
                    кадр.append(SLIP_КОНЕЦ)
                elif следующий == SLIP_ВМЕСТО_ЭКРАНА:
                    кадр.append(SLIP_ЭКРАН)
                else:
                    годен = False               # после экрана недопустимый байт
                    break
            else:
                кадр.append(байт)
        if годен:
            итог.append(bytes(кадр))
    return итог


def _выравнивания(биты: np.ndarray, байт: int) -> list[int]:
    """Сдвиги (0…7), при которых байт-разделитель чаще всего стоит на границе."""
    if len(биты) < 64:
        return [0]
    значение = np.zeros(len(биты) - 7, dtype=np.uint8)
    for сдвиг in range(8):
        значение = (значение << 1) | биты[сдвиг:len(биты) - 7 + сдвиг]
    места = np.flatnonzero(значение == байт)
    if not len(места):
        return [0]
    счёт = Counter((места % 8).tolist())
    return [сдвиг for сдвиг, _ in счёт.most_common(2)]


def найти(биты: np.ndarray) -> Находка | None:
    """Асинхронное HDLC/PPP или SLIP в битовом ряду: любой сдвиг и порядок бит."""
    выборка = биты[:ВЫБОРКА]
    return _асинхронное(выборка) or _slip(выборка)


def _асинхронное(выборка: np.ndarray) -> Находка | None:
    лучшее = None
    # 0x7E — палиндром по битам: флаг одинаков при обоих порядках, поэтому
    # порядок бит в байте решает только FCS.
    for сдвиг in _выравнивания(выборка, ФЛАГ):
        for порядок in ("старший", "младший"):
            данные = в_байты(выборка[сдвиг:], порядок)
            if данные.count(ФЛАГ) < 4:
                continue
            собрано = кадры_асинхронные(данные)[:ПРОВЕРЯТЬ_КАДРОВ]
            if not собрано:
                continue
            верно16 = sum(hdlc.fcs16_верна(кадр) for кадр, _ in собрано)
            верно32 = sum(hdlc.fcs32_верна(кадр) for кадр, _ in собрано)
            верно, вид = (верно32, 32) if верно32 > верно16 else (верно16, 16)
            доля = верно / len(собрано)
            if лучшее is None or доля > лучшее[0]:
                лучшее = (доля, вид, сдвиг, порядок, собрано, верно)
    if лучшее is None or лучшее[0] < 0.2:
        return None
    доля, вид, сдвиг, порядок, собрано, верно = лучшее
    проверка = hdlc.fcs32_верна if вид == 32 else hdlc.fcs16_верна
    годные = [(кадр[:-(вид // 8)], экранов) for кадр, экранов in собрано if проверка(кадр)]
    экранов = sum(э for _, э in годные)
    с_экраном = sum(1 for _, э in годные if э)
    длины = Counter(len(кадр) for кадр, _ in годные)
    кадры = [кадр for кадр, _ in годные]
    подробно = [
        f"байтовая граница — с бита {сдвиг} ряда; порядок бит в байте: {порядок} первым",
        f"кадров проверено: {len(собрано)}, FCS-{вид} верна у {верно}",
        f"экранированных байт (0x7D + байт xor 0x20) снято: {экранов}, "
        f"в {с_экраном} кадрах из {len(годные)}",
        "длины кадров (байт, без FCS): " + ", ".join(
            f"{длина}×{счёт}" for длина, счёт in длины.most_common(6)),
    ]
    if кадры and all(кадр[:2] == b"\xff\x03" for кадр in кадры[:50] if len(кадр) > 2):
        подробно.append("адрес 0xFF и управление 0x03 — PPP в асинхронном HDLC (RFC 1662)")
    return Находка(
        уровень="канальный",
        что=f"асинхронное HDLC-обрамление с октетным стаффингом (0x7D), FCS-{вид}",
        уверенность=доля,
        мера=f"FCS верна у {round(доля * 100)} % из {len(собрано)} кадров после снятия "
             f"экранирования",
        подробно=подробно, дальше=кадры, вид_дальше="кадры")


def _slip(выборка: np.ndarray) -> Находка | None:
    for сдвиг in _выравнивания(выборка, SLIP_КОНЕЦ):
        for порядок in ("старший", "младший"):
            данные = в_байты(выборка[сдвиг:], порядок)
            if данные.count(SLIP_КОНЕЦ) < 4:
                continue
            кадры = кадры_slip(данные)[:ПРОВЕРЯТЬ_КАДРОВ]
            внутри = pakety.найти_в_кадрах(кадры, "кадров SLIP")
            if внутри is None or внутри.уверенность < 0.5:
                continue
            экранов = sum(данные.count(bytes([SLIP_ЭКРАН, х]))
                          for х in (SLIP_ВМЕСТО_КОНЦА, SLIP_ВМЕСТО_ЭКРАНА))
            return Находка(
                уровень="канальный", что="SLIP — октетный стаффинг 0xC0/0xDB (RFC 1055)",
                уверенность=внутри.уверенность,
                мера=f"в кадрах между байтами 0xC0 после снятия экранирования {внутри.мера}",
                подробно=[f"байтовая граница — с бита {сдвиг} ряда; порядок бит: {порядок} "
                          f"первым",
                          f"кадров: {len(кадры)}, экранированных байт: {экранов}",
                          "проверочной суммы у SLIP нет — разбор подтверждён пакетами IP"],
                дальше=кадры, вид_дальше="кадры")
    return None
