# -*- coding: utf-8 -*-
"""Цикл, синхрослово, каналы мультиплексора.

Длина цикла ищется автокорреляцией битового ряда: в цикловом потоке бит
через ровно цикл совпадает с текущим чаще, чем в случайном, — за счёт
синхрослова, служебных битов и свободных каналов. Этого перекоса хватает,
даже когда постоянных бит в цикле два процента: на выборке в четыре
миллиона бит шум автокорреляции — около 0,0005, а перекос от синхрослова
E1 — около 0,01. Считается через БПФ, за секунды.

Дальше поток «складывается» по длине цикла в таблицу: строка — цикл,
столбец — позиция бита в цикле. Постоянные столбцы — синхрослово и
служебные биты; нарезка по 8 бит даёт канальные интервалы, и по каждому
считается, что в нём: тишина, постоянное заполнение, речь, данные,
HDLC.

E1 по G.704 узнаётся отдельно и точно: FAS 0011011 в КИ0 через цикл.
"""

from __future__ import annotations

import re
from collections import Counter
from typing import Dict, List, Optional, Tuple

import numpy as np

from . import hdlc
from .bity import в_байты
from .nahodka import Находка
from .statistika import энтропия

#: Наименьший и наибольший рассматриваемый цикл, бит.
ЦИКЛ_ОТ = 32
ЦИКЛ_ДО = 1 << 16
#: Выборка для поиска цикла, бит: больше — точнее, но дольше.
ВЫБОРКА = 1 << 22
#: Сколько «сигм» шума должен превышать пик автокорреляции.
ПОРОГ_СИГМ = 8.0
#: Столбец постоянен, если в нём так мало «чужих» бит (допускаем ошибки линии).
ПОСТОЯННЫЙ = 0.03
FAS = np.array([0, 0, 1, 1, 0, 1, 1], dtype=np.uint8)


def автокорреляция(биты: np.ndarray, наибольший: int) -> np.ndarray:
    """r[P] — средняя похожесть бита на бит через P (для ±1: от −1 до 1)."""
    x = биты.astype(np.float32) * 2 - 1
    x -= x.mean()
    n = len(x)
    размер = 1 << int(np.ceil(np.log2(2 * n)))
    спектр = np.fft.rfft(x, размер)
    полная = np.fft.irfft(спектр * np.conj(спектр), размер)[:наибольший + 1]
    return полная / (n - np.arange(наибольший + 1)) / max(1e-9, float((x * x).mean()))


def длина_цикла(биты: np.ndarray) -> tuple[int, float, float] | None:
    """Длина цикла, пик корреляции и уровень шума — или None, если цикла нет."""
    выборка = биты[:ВЫБОРКА]
    if len(выборка) < 64 * ЦИКЛ_ОТ:
        return None
    наибольший = min(ЦИКЛ_ДО, len(выборка) // 16)
    r = автокорреляция(выборка, наибольший)
    шум = 1.0 / np.sqrt(len(выборка))
    окно = r[ЦИКЛ_ОТ:]
    лучший = int(np.argmax(окно)) + ЦИКЛ_ОТ
    пик = float(r[лучший])
    if пик < ПОРОГ_СИГМ * шум:
        return None
    # Основной период — наименьший, у которого пик не слабее 60 % лучшего и
    # который повторяется на кратных: иначе вместо цикла взяли бы сверхцикл.
    for p in range(ЦИКЛ_ОТ, лучший + 1):
        if r[p] < 0.6 * пик:
            continue
        кратные = [r[k * p] for k in range(2, 5) if k * p <= наибольший]
        if all(к >= 0.5 * пик for к in кратные):
            return p, float(r[p]), шум
    return лучший, пик, шум


#: Синхрослово короче этого не держит кадр: ищем другой цикл.
СЛОВО_ОТ = 8
#: Сколько узких пиков автокорреляции проверять.
УЗКИХ_ПИКОВ = 12


def _узкий_цикл(биты: np.ndarray):
    """Цикл по узкому пику автокорреляции: (длина, пик, шум, таблица, участки) или None.

    Пик кадра с синхрословом узкий: через бит от него корреляции нет. Пики
    самой нагрузки (флаги HDLC, повторяющиеся заголовки) широкие — их соседи
    почти так же высоки. Берём пики, выпуклость которых (превышение над
    соседями) велика, и первый, у которого есть синхрослово.
    """
    выборка = биты[:ВЫБОРКА]
    if len(выборка) < 64 * ЦИКЛ_ОТ:
        return None
    наибольший = min(ЦИКЛ_ДО, len(выборка) // 16)
    r = автокорреляция(выборка, наибольший + 1)
    шум = 1.0 / np.sqrt(len(выборка))
    середина = r[ЦИКЛ_ОТ:наибольший]
    выпуклость = середина - np.maximum(r[ЦИКЛ_ОТ - 1:наибольший - 1], r[ЦИКЛ_ОТ + 1:наибольший + 1])
    for i in np.argsort(-выпуклость)[:УЗКИХ_ПИКОВ]:
        if выпуклость[i] < ПОРОГ_СИГМ * шум:
            break
        длина = int(i) + ЦИКЛ_ОТ
        таблица = сложить(выборка, длина)
        участки = постоянные_участки(таблица)
        if участки and участки[0][1] >= СЛОВО_ОТ:
            return длина, float(r[длина]), шум, таблица, участки
    return None


def сложить(биты: np.ndarray, длина: int, начало: int = 0) -> np.ndarray:
    """Поток → таблица «цикл × позиция бита»."""
    циклов = (len(биты) - начало) // длина
    return биты[начало:начало + циклов * длина].reshape(циклов, длина)


def постоянные_участки(таблица: np.ndarray) -> List[tuple[int, int, str]]:
    """Участки подряд идущих постоянных столбцов: (начало, длина, значение)."""
    среднее = таблица.mean(axis=0)
    постоянные = (среднее <= ПОСТОЯННЫЙ) | (среднее >= 1 - ПОСТОЯННЫЙ)
    участки = []
    место = 0
    while место < len(среднее):
        if not постоянные[место]:
            место += 1
            continue
        конец = место
        while конец < len(среднее) and постоянные[конец]:
            конец += 1
        значение = "".join("1" if с > 0.5 else "0" for с in среднее[место:конец])
        участки.append((место, конец - место, значение))
        место = конец
    return sorted(участки, key=lambda у: -у[1])


def e1(биты: np.ndarray) -> Находка | None:
    """E1 по G.704: FAS 0011011 в КИ0 через цикл, 32 КИ по 8 бит."""
    таблица = сложить(биты[:ВЫБОРКА], 512)
    if len(таблица) < 32:
        return None
    среднее = таблица.mean(axis=0)
    for место in range(512):
        окно = [(место + k) % 512 for k in range(7)]
        if np.all(np.abs(среднее[окно] - FAS) <= ПОСТОЯННЫЙ):
            break
    else:
        return None
    начало = (место - 1) % 512                 # бит Si перед FAS — начало КИ0
    таблица = сложить(биты, 512, начало)
    совпало = float(np.mean(np.all(таблица[:, 1:8] == FAS, axis=1)))
    nfas = float(np.mean(таблица[:, 256 + 1] == 1))
    циклы = сложить(биты, 256, начало)
    каналы = разнести(циклы)
    подробно = [
        f"FAS 0011011 в КИ0 чётных циклов: совпал в {round(совпало * 100, 1)} % пар циклов; "
        f"бит 2 КИ0 нечётных циклов (NFAS) равен 1 в {round(nfas * 100, 1)} %",
        f"начало цикла — бит {начало} выборки; цикл 256 бит, 125 мкс, 2048 кбит/с",
    ]
    подробно += сверхцикл_cas(каналы)
    # КИ0 — служебный интервал: его «содержимое» — FAS и NFAS, а не нагрузка.
    описание = описать_каналы({номер: ряд for номер, ряд in каналы.items() if номер})
    подробно += ["КИ0: цикловая синхронизация (FAS / NFAS), служебные биты Si и Sa"]
    подробно += описание
    return Находка(
        уровень="цикл", что="E1 по G.704: цикл 256 бит, 32 канальных интервала по 8 бит",
        уверенность=совпало,
        мера=f"FAS совпал в {round(совпало * 100, 1)} % циклов с FAS",
        подробно=подробно, дальше=каналы, вид_дальше="каналы")


def сверхцикл_cas(каналы: Dict[int, np.ndarray]) -> List[str]:
    """Сверхцикл CAS в КИ16: MFAS 0000 в старших битах раз в 16 циклов."""
    if 16 not in каналы or len(каналы[16]) < 64:
        return []
    ки16 = каналы[16].reshape(-1, 8)
    нули = np.all(ки16[:, :4] == 0, axis=1)
    места = np.flatnonzero(нули)
    if len(места) < 4:
        return []
    шаги = Counter(np.diff(места).tolist())
    шаг, счёт = шаги.most_common(1)[0]
    if шаг == 16 and счёт >= 0.8 * (len(места) - 1):
        return ["КИ16: сверхцикл из 16 циклов (MFAS 0000 раз в 16 циклов) — "
                "сигнализация по выделенному каналу (CAS)"]
    return []


def разнести(циклы: np.ndarray) -> Dict[int, np.ndarray]:
    """Таблица циклов → битовые ряды каналов (по 8 бит на цикл)."""
    if циклы.shape[1] % 8:
        return {}
    интервалов = циклы.shape[1] // 8
    return {номер: циклы[:, 8 * номер:8 * номер + 8].reshape(-1)
            for номер in range(интервалов)}


def что_в_канале(ряд: np.ndarray) -> str:
    """Что в канальном интервале — одной строкой."""
    байты = np.frombuffer(в_байты(ряд), dtype=np.uint8)
    if not len(байты):
        return "пусто"
    частоты = np.bincount(байты, minlength=256)
    частый = int(частоты.argmax())
    доля = частоты[частый] / len(байты)
    э = энтропия(байты)
    if доля >= 0.95:
        return f"постоянное заполнение 0x{частый:02X}"
    найдено = hdlc.найти(ряд) if len(ряд) >= 2048 else None
    if найдено is not None and найдено.уверенность >= 0.5:
        return f"HDLC: {найдено.мера}"
    if частый in (0xD5, 0x55, 0x54, 0xD4) and доля > 0.4:
        return f"тишина A-закона (0x{частый:02X} в {round(доля * 100)} %), речь в паузах"
    if э > 7.8:
        return f"случайный на вид ({э:.2f} бит/байт): данные, шифр или скремблер"
    return f"переменное содержимое, {э:.2f} бит/байт, чаще всего 0x{частый:02X}"


def описать_каналы(каналы: Dict[int, np.ndarray], *, предел: int = 64) -> List[str]:
    """Каналы — сгруппированными: одинаковые по виду идут одной строкой.

    Тридцать строк «случайный на вид» съедали окно модели и прятали то, ради
    чего список нужен: какой канал — не такой, как все.
    """
    описания = {номер: что_в_канале(каналы[номер]) for номер in sorted(каналы)[:предел]}
    группы: Dict[str, List[int]] = {}
    for номер, описание in описания.items():
        группы.setdefault(_вид(описание), []).append(номер)
    строки = []
    for вид, номера in sorted(группы.items(), key=lambda пара: пара[1][0]):
        if len(номера) == 1:
            строки.append(f"КИ{номера[0]}: {описания[номера[0]]}")
        else:
            строки.append(f"{_диапазоны(номера)}: {вид}"
                          + _энтропии([описания[н] for н in номера]))
    return строки


def _вид(описание: str) -> str:
    """Описание канала без чисел энтропии и частого байта: по нему каналы и группируются."""
    описание = re.sub(r"\s*\([0-9.]+ бит/байт\)", "", описание)
    return re.sub(r", [0-9.]+ бит/байт, чаще всего 0x[0-9A-F]{2}$", "", описание)


def _энтропии(описания: List[str]) -> str:
    """« (4.56–4.90 бит/байт)» — разброс энтропии по группе каналов, если он есть."""
    числа = [float(м) for о in описания for м in re.findall(r"([0-9]+\.[0-9]+) бит/байт", о)]
    if not числа:
        return ""
    return (f" ({min(числа):.2f} бит/байт)" if min(числа) == max(числа)
            else f" ({min(числа):.2f}–{max(числа):.2f} бит/байт)")


def _диапазоны(номера: List[int]) -> str:
    части = []
    начало = предыдущий = номера[0]
    for номер in номера[1:] + [None]:
        if номер is not None and номер == предыдущий + 1:
            предыдущий = номер
            continue
        части.append(f"КИ{начало}" if начало == предыдущий else f"КИ{начало}–КИ{предыдущий}")
        if номер is not None:
            начало = предыдущий = номер
    return ", ".join(части)


#: Повтор цикла: расхождение с одним из прежних циклов — не больше этой доли бит.
ПОВТОР_РАСХОЖДЕНИЕ = 0.05
#: Насколько далеко назад искать повторяемый цикл.
ПОВТОР_ШАГ_ДО = 16
#: Сколько циклов-повторов нужно, чтобы о них говорить.
ПОВТОРОВ_ОТ = 8
#: Постоянные участки ближе этого расстояния — одно служебное слово
#: (в заголовке бывают и переменные биты: счётчик, признак режима).
ЗАЗОР_СЛОВА = 8
_ЕДИНИЦ = np.array([bin(i).count("1") for i in range(256)], dtype=np.int32)


def повторы(таблица: np.ndarray) -> Optional[dict]:
    """Циклы, почти целиком повторяющие один из прежних (заполнение без данных).

    Модем без данных шлёт заполнение, и циклы повторяются — через один,
    через четыре (сверхцикл). Для разбора это подарок: повторы показывают
    сверхцикл и заодно меряют ошибки в линии — два приёма одного и того же
    расходятся только ошибками, вдвое чаще, чем каждый с оригиналом.
    """
    n, L = таблица.shape
    if n < 2 * ПОВТОРОВ_ОТ:
        return None
    упаковано = np.packbits(таблица, axis=1)
    шаг = np.zeros(n, dtype=np.int32)
    for m in range(1, min(ПОВТОР_ШАГ_ДО, n - 1) + 1):
        d = _ЕДИНИЦ[np.bitwise_xor(упаковано[m:], упаковано[:-m])].sum(axis=1)
        новые = (d <= ПОВТОР_РАСХОЖДЕНИЕ * L) & (шаг[m:] == 0)
        шаг[m:][новые] = m
    есть = шаг > 0
    if int(есть.sum()) < ПОВТОРОВ_ОТ:
        return None
    частый, раз = Counter(шаг[есть].tolist()).most_common(1)[0]
    # Ошибки — по столбцам: признаки режима и счётчики в заголовке расходятся
    # и в повторах, но их немного — самые несогласные 5 % столбцов отброшены.
    номера = np.flatnonzero(есть)
    несогласие = (таблица[номера] != таблица[номера - шаг[номера]]).mean(axis=0)
    оставить = max(1, int(round(0.95 * L)))
    ошибок = float(np.sort(несогласие)[:оставить].mean()) / 2
    return {"доля": float(есть.mean()), "шаг": int(частый), "доля_шага": раз / int(есть.sum()),
            "ошибок": ошибок, "повторов": int(есть.sum())}


def описать_повторы(п: dict) -> str:
    return (f"повторы циклов: {п['доля'] * 100:.0f} % циклов почти целиком повторяют прежний "
            f"(чаще всего — через {п['шаг']}, {п['доля_шага'] * 100:.0f} % повторов): заполнение "
            f"без данных, сверхцикл {п['шаг']} цикл(а); по расхождениям повторов вероятность "
            f"ошибки в линии ≈ {п['ошибок']:.1e}")


def _служебные_слова(участки: List[tuple[int, int, str]], длина: int
                     ) -> List[Tuple[int, int]]:
    """Постоянные участки, сведённые в служебные слова: (начало, длина) по порядку."""
    по_порядку = sorted((н, д) for н, д, _ in участки)
    слова: List[List[int]] = []
    for н, д in по_порядку:
        if слова and н - (слова[-1][0] + слова[-1][1]) <= ЗАЗОР_СЛОВА:
            слова[-1][1] = н + д - слова[-1][0]
        else:
            слова.append([н, д])
    return [(н, д) for н, д in слова]


#: Насколько далеко от ожидаемого места искать служебные слова после сбоя, бит.
ОКНО_МАХОВИКА = 16


def маховик(биты: np.ndarray, длина: int, места: np.ndarray, образец: np.ndarray,
            окно: int = ОКНО_МАХОВИКА) -> Tuple[List[int], dict]:
    """Начала циклов с маховиком по всем постоянным столбцам сразу.

    Короткое синхрослово (8 бит) случайно встречается рядом с ожидаемым
    местом чуть не в каждом цикле — с ним маховик «проскальзывает» на
    ровном месте. Все постоянные столбцы цикла вместе (десятки бит) случайно
    не совпадают: сверка по ним, допуск — восьмая часть от их числа.
    """
    допуск = max(1, len(места) // 8)
    место, начала = 0, []
    на_месте = нет = проскальзываний = 0
    while место + длина <= len(биты):
        if int(np.count_nonzero(биты[место + места] != образец)) <= допуск:
            на_месте += 1
        else:
            лучшее = None
            for сдвиг in range(-окно, окно + 1):
                где = место + сдвиг
                if где < 0 or где + длина > len(биты):
                    continue
                ошибок = int(np.count_nonzero(биты[где + места] != образец))
                if ошибок <= допуск and (лучшее is None or (ошибок, abs(сдвиг)) < лучшее[:2]):
                    лучшее = (ошибок, abs(сдвиг), сдвиг)
            if лучшее is not None:
                место += лучшее[2]
                проскальзываний += 1
            else:
                нет += 1
        начала.append(место)
        место += длина
    return начала, {"на_месте": на_месте, "нет_на_месте": нет, "проскальзываний": проскальзываний}


#: Циклов в куске, по которому берётся шаблон служебных слов.
КУСОК_ШАБЛОНА = 64


def _без_срыва(таблица: np.ndarray) -> np.ndarray:
    """Кусок таблицы циклов, где постоянных столбцов больше всего.

    После проскальзывания столбцы таблицы «от бита 0» съезжают, и по всей
    таблице постоянными остаются лишь случайно совпавшие. Кусок из
    нескольких десятков циклов без срыва показывает служебные слова целиком.
    """
    if len(таблица) <= 2 * КУСОК_ШАБЛОНА:
        return таблица
    лучший, счёт = таблица, -1
    for от in range(0, len(таблица) - КУСОК_ШАБЛОНА + 1, КУСОК_ШАБЛОНА):
        кусок = таблица[от:от + КУСОК_ШАБЛОНА]
        среднее = кусок.mean(axis=0)
        постоянных = int(np.count_nonzero((среднее <= ПОСТОЯННЫЙ) | (среднее >= 1 - ПОСТОЯННЫЙ)))
        if постоянных > счёт:
            лучший, счёт = кусок, постоянных
    return лучший


def нагрузка(биты: np.ndarray, длина: int) -> Optional[Tuple[np.ndarray, dict]]:
    """Нагрузка цикла: кадры по служебным словам с маховиком, без самих слов.

    Кадры выравниваются каждый заново (проскальзывание не сбивает нарезку до
    конца файла). Кадр начинается со служебного слова, в которое входит
    синхрослово (постоянные участки с переменными битами между ними — одно
    слово), и все служебные слова вырезаются: остаётся то, что передаёт
    модем, — для следующего уровня разбора (код, скремблер, пакеты).
    """
    if len(биты) < 4 * длина:
        return None
    таблица = _без_срыва(сложить(биты[:ВЫБОРКА], длина))
    участки = постоянные_участки(таблица)
    if not участки:
        return None
    начало = участки[0][0]
    среднее = таблица.mean(axis=0)
    места = np.flatnonzero((среднее <= ПОСТОЯННЫЙ) | (среднее >= 1 - ПОСТОЯННЫЙ))
    образец = (среднее[места] > 0.5).astype(np.uint8)
    начала, сводка = маховик(биты, длина, места, образец)
    слова = _служебные_слова(участки, длина)
    своё = next(с for с in слова if с[0] <= начало < с[0] + с[1])[0]
    строки = [биты[н + своё:н + своё + длина] for н in начала if н + своё + длина <= len(биты)]
    if len(строки) < 4:
        return None
    таблица = np.stack(строки)
    оставить = np.ones(длина, dtype=bool)
    вырезано = []
    for н, д in слова:
        место = (н - своё) % длина
        оставить[(место + np.arange(д)) % длина] = False
        вырезано.append((место, д))
    return таблица[:, оставить].reshape(-1), {
        "кадров": len(таблица), "бит": int(оставить.sum()), "вырезано": sorted(вырезано), **сводка}


def найти(биты: np.ndarray) -> Находка | None:
    """Цикл в битовом ряду: сперва E1, потом любой."""
    найдено = e1(биты)
    if найдено is not None and найдено.уверенность >= 0.5:
        return найдено
    цикл = длина_цикла(биты)
    if цикл is None:
        return None
    длина, пик, шум = цикл
    таблица = сложить(биты[:ВЫБОРКА], длина)
    участки = постоянные_участки(таблица)
    if not участки or участки[0][1] < СЛОВО_ОТ:
        # Широкие пики самой нагрузки (заполнение HDLC, заголовки пакетов)
        # бывают выше пика кадра — пробуем узкие пики.
        другой = _узкий_цикл(биты)
        if другой is None:
            if not участки:
                return None
        else:
            длина, пик, шум, таблица, участки = другой
    начало, размер, значение = участки[0]
    # Цикл из двух одинаковых половин: синхрослово стоит и через полцикла —
    # значит, цикл вдвое короче (сверхцикл взялся из-за медленных полей).
    while длина % 2 == 0 and длина // 2 >= ЦИКЛ_ОТ:
        половина = длина // 2
        вторая = (начало + половина) % длина
        if not any(н == вторая and з == значение for н, _, з in участки):
            break
        длина = половина
        таблица = сложить(биты[:ВЫБОРКА], длина)
        участки = постоянные_участки(таблица)
        if not участки:
            return None
        начало, размер, значение = участки[0]
    подробно = [
        f"пик автокорреляции {пик:.4f} при шуме {шум:.4f} ({пик / шум:.0f} сигм)",
        f"постоянные участки цикла (начало, бит): " + "; ".join(
            f"{н}: {з if len(з) <= 32 else з[:32] + '…'} ({д} бит)"
            for н, д, з in участки[:6]),
    ]
    # Синхрослово проверяем по всем циклам: совпало ли оно целиком.
    слово = np.frombuffer(значение.encode(), dtype=np.uint8) - ord("0")
    полная = сложить(биты, длина)
    совпало = float(np.mean(np.all(полная[:, начало:начало + размер] == слово, axis=1)))
    каналы: Dict[int, np.ndarray] = {}
    if длина % 8 == 0:
        # Нарезку по байтам выравниваем по началу синхрослова: служебное
        # слово стоит в начале своего интервала почти всегда.
        сдвиг = начало % 8
        циклы = сложить(биты, длина, сдвиг)
        каналы = разнести(циклы)
        подробно.append(f"цикл кратен байту: {длина // 8} интервалов по 8 бит, "
                        f"нарезка от бита {сдвиг}")
        подробно += описать_каналы(каналы)
    # Мультиплекс со стаффингом: каналы управления (копии бита в кадре) и знак.
    try:
        from . import stafing  # noqa: PLC0415
        стаффинг = stafing.найти(биты, длина, 0)
    except ValueError:
        стаффинг = None
    for г in (стаффинг or {}).get("группы", []):
        места = г.get("места") or []
        if not места:
            # Копии бита без места возможности — не стаффинг, а служебный бит,
            # повторённый для надёжности (признак режима, счётчик, сигнализация).
            подробно.append(
                f"служебный бит, повторённый в столбцах {', '.join(map(str, г['столбцы']))} "
                f"(несогласных {г['несогласных'] * 100:.1f} %, единица в "
                f"{г['доля_стаффинга'] * 100:.1f} % циклов): места возможности стаффинга нет")
            continue
        if len(места) == 1:
            где = (f"; возможность — столбец {места[0]['столбец']}, "
                   f"{'положительный' if места[0]['знак'] == '+' else 'отрицательный'}")
        else:
            где = "; места возможности — " + ", ".join(f"{м['столбец']}{м['знак']}" for м in места)
        подробно.append(
            f"стаффинг: канал управления — столбцы {', '.join(map(str, г['столбцы']))} (большинство, "
            f"несогласных {г['несогласных'] * 100:.1f} %), стаффинг в {г['доля_стаффинга'] * 100:.1f} % кадров" + где)
    повтор = повторы(сложить(биты[:ВЫБОРКА], длина))
    if повтор is not None:
        подробно.append(описать_повторы(повтор))
    return Находка(
        уровень="цикл", что=f"цикл {длина} бит, синхрослово {размер} бит",
        свойства={"длина": длина, "повторы": повтор},
        уверенность=совпало,
        мера=f"самый длинный постоянный участок совпал целиком в "
             f"{round(совпало * 100, 1)} % циклов",
        подробно=подробно, дальше=каналы or None, вид_дальше="каналы" if каналы else "")
