# -*- coding: utf-8 -*-
"""Цикл, синхрослово, каналы мультиплексора.

Длина цикла ищется автокорреляцией битового ряда: в цикловом потоке бит
через ровно цикл совпадает с текущим чаще, чем в случайном, — за счёт
синхрослова, служебных битов и свободных каналов. Этого перекоса хватает,
даже когда постоянных бит в цикле два процента: на выборке в четыре
миллиона бит шум автокорреляции — около 0,0005, а перекос от синхрослова
E1 — около 0,01. Считается через БПФ, за секунды.

Дальше поток «складывается» по длине цикла в таблицу: строка — цикл,
столбец — позиция бита в цикле. Постоянные столбцы — синхрослово и
служебные биты; нарезка по 8 бит даёт канальные интервалы, и по каждому
считается, что в нём: тишина, постоянное заполнение, речь, данные,
HDLC.

E1 по G.704 узнаётся отдельно и точно: FAS 0011011 в КИ0 через цикл.
"""

from __future__ import annotations

from collections import Counter
from typing import Dict, List

import numpy as np

from . import hdlc
from .bity import в_байты
from .nahodka import Находка
from .statistika import энтропия

#: Наименьший и наибольший рассматриваемый цикл, бит.
ЦИКЛ_ОТ = 32
ЦИКЛ_ДО = 1 << 16
#: Выборка для поиска цикла, бит: больше — точнее, но дольше.
ВЫБОРКА = 1 << 22
#: Сколько «сигм» шума должен превышать пик автокорреляции.
ПОРОГ_СИГМ = 8.0
#: Столбец постоянен, если в нём так мало «чужих» бит (допускаем ошибки линии).
ПОСТОЯННЫЙ = 0.03
FAS = np.array([0, 0, 1, 1, 0, 1, 1], dtype=np.uint8)


def автокорреляция(биты: np.ndarray, наибольший: int) -> np.ndarray:
    """r[P] — средняя похожесть бита на бит через P (для ±1: от −1 до 1)."""
    x = биты.astype(np.float32) * 2 - 1
    x -= x.mean()
    n = len(x)
    размер = 1 << int(np.ceil(np.log2(2 * n)))
    спектр = np.fft.rfft(x, размер)
    полная = np.fft.irfft(спектр * np.conj(спектр), размер)[:наибольший + 1]
    return полная / (n - np.arange(наибольший + 1)) / max(1e-9, float((x * x).mean()))


def длина_цикла(биты: np.ndarray) -> tuple[int, float, float] | None:
    """Длина цикла, пик корреляции и уровень шума — или None, если цикла нет."""
    выборка = биты[:ВЫБОРКА]
    if len(выборка) < 64 * ЦИКЛ_ОТ:
        return None
    наибольший = min(ЦИКЛ_ДО, len(выборка) // 16)
    r = автокорреляция(выборка, наибольший)
    шум = 1.0 / np.sqrt(len(выборка))
    окно = r[ЦИКЛ_ОТ:]
    лучший = int(np.argmax(окно)) + ЦИКЛ_ОТ
    пик = float(r[лучший])
    if пик < ПОРОГ_СИГМ * шум:
        return None
    # Основной период — наименьший, у которого пик не слабее 60 % лучшего и
    # который повторяется на кратных: иначе вместо цикла взяли бы сверхцикл.
    for p in range(ЦИКЛ_ОТ, лучший + 1):
        if r[p] < 0.6 * пик:
            continue
        кратные = [r[k * p] for k in range(2, 5) if k * p <= наибольший]
        if all(к >= 0.5 * пик for к in кратные):
            return p, float(r[p]), шум
    return лучший, пик, шум


def сложить(биты: np.ndarray, длина: int, начало: int = 0) -> np.ndarray:
    """Поток → таблица «цикл × позиция бита»."""
    циклов = (len(биты) - начало) // длина
    return биты[начало:начало + циклов * длина].reshape(циклов, длина)


def постоянные_участки(таблица: np.ndarray) -> List[tuple[int, int, str]]:
    """Участки подряд идущих постоянных столбцов: (начало, длина, значение)."""
    среднее = таблица.mean(axis=0)
    постоянные = (среднее <= ПОСТОЯННЫЙ) | (среднее >= 1 - ПОСТОЯННЫЙ)
    участки = []
    место = 0
    while место < len(среднее):
        if not постоянные[место]:
            место += 1
            continue
        конец = место
        while конец < len(среднее) and постоянные[конец]:
            конец += 1
        значение = "".join("1" if с > 0.5 else "0" for с in среднее[место:конец])
        участки.append((место, конец - место, значение))
        место = конец
    return sorted(участки, key=lambda у: -у[1])


def e1(биты: np.ndarray) -> Находка | None:
    """E1 по G.704: FAS 0011011 в КИ0 через цикл, 32 КИ по 8 бит."""
    таблица = сложить(биты[:ВЫБОРКА], 512)
    if len(таблица) < 32:
        return None
    среднее = таблица.mean(axis=0)
    for место in range(512):
        окно = [(место + k) % 512 for k in range(7)]
        if np.all(np.abs(среднее[окно] - FAS) <= ПОСТОЯННЫЙ):
            break
    else:
        return None
    начало = (место - 1) % 512                 # бит Si перед FAS — начало КИ0
    таблица = сложить(биты, 512, начало)
    совпало = float(np.mean(np.all(таблица[:, 1:8] == FAS, axis=1)))
    nfas = float(np.mean(таблица[:, 256 + 1] == 1))
    циклы = сложить(биты, 256, начало)
    каналы = разнести(циклы)
    подробно = [
        f"FAS 0011011 в КИ0 чётных циклов: совпал в {round(совпало * 100, 1)} % пар циклов; "
        f"бит 2 КИ0 нечётных циклов (NFAS) равен 1 в {round(nfas * 100, 1)} %",
        f"начало цикла — бит {начало} выборки; цикл 256 бит, 125 мкс, 2048 кбит/с",
    ]
    подробно += сверхцикл_cas(каналы)
    # КИ0 — служебный интервал: его «содержимое» — FAS и NFAS, а не нагрузка.
    описание = описать_каналы({номер: ряд for номер, ряд in каналы.items() if номер})
    подробно += ["КИ0: цикловая синхронизация (FAS / NFAS), служебные биты Si и Sa"]
    подробно += описание
    return Находка(
        уровень="цикл", что="E1 по G.704: цикл 256 бит, 32 канальных интервала по 8 бит",
        уверенность=совпало,
        мера=f"FAS совпал в {round(совпало * 100, 1)} % циклов с FAS",
        подробно=подробно, дальше=каналы, вид_дальше="каналы")


def сверхцикл_cas(каналы: Dict[int, np.ndarray]) -> List[str]:
    """Сверхцикл CAS в КИ16: MFAS 0000 в старших битах раз в 16 циклов."""
    if 16 not in каналы or len(каналы[16]) < 64:
        return []
    ки16 = каналы[16].reshape(-1, 8)
    нули = np.all(ки16[:, :4] == 0, axis=1)
    места = np.flatnonzero(нули)
    if len(места) < 4:
        return []
    шаги = Counter(np.diff(места).tolist())
    шаг, счёт = шаги.most_common(1)[0]
    if шаг == 16 and счёт >= 0.8 * (len(места) - 1):
        return ["КИ16: сверхцикл из 16 циклов (MFAS 0000 раз в 16 циклов) — "
                "сигнализация по выделенному каналу (CAS)"]
    return []


def разнести(циклы: np.ndarray) -> Dict[int, np.ndarray]:
    """Таблица циклов → битовые ряды каналов (по 8 бит на цикл)."""
    if циклы.shape[1] % 8:
        return {}
    интервалов = циклы.shape[1] // 8
    return {номер: циклы[:, 8 * номер:8 * номер + 8].reshape(-1)
            for номер in range(интервалов)}


def что_в_канале(ряд: np.ndarray) -> str:
    """Что в канальном интервале — одной строкой."""
    байты = np.frombuffer(в_байты(ряд), dtype=np.uint8)
    if not len(байты):
        return "пусто"
    частоты = np.bincount(байты, minlength=256)
    частый = int(частоты.argmax())
    доля = частоты[частый] / len(байты)
    э = энтропия(байты)
    if доля >= 0.95:
        return f"постоянное заполнение 0x{частый:02X}"
    найдено = hdlc.найти(ряд) if len(ряд) >= 2048 else None
    if найдено is not None and найдено.уверенность >= 0.5:
        return f"HDLC: {найдено.мера}"
    if частый in (0xD5, 0x55, 0x54, 0xD4) and доля > 0.4:
        return f"тишина A-закона (0x{частый:02X} в {round(доля * 100)} %), речь в паузах"
    if э > 7.8:
        return f"случайный на вид ({э:.2f} бит/байт): данные, шифр или скремблер"
    return f"переменное содержимое, {э:.2f} бит/байт, чаще всего 0x{частый:02X}"


def описать_каналы(каналы: Dict[int, np.ndarray], *, предел: int = 64) -> List[str]:
    """Каналы — сгруппированными: одинаковые по виду идут одной строкой.

    Тридцать строк «случайный на вид» съедали окно модели и прятали то, ради
    чего список нужен: какой канал — не такой, как все.
    """
    описания = {номер: что_в_канале(каналы[номер]) for номер in sorted(каналы)[:предел]}
    группы: Dict[str, List[int]] = {}
    for номер, описание in описания.items():
        группы.setdefault(_вид(описание), []).append(номер)
    строки = []
    for вид, номера in sorted(группы.items(), key=lambda пара: пара[1][0]):
        if len(номера) == 1:
            строки.append(f"КИ{номера[0]}: {описания[номера[0]]}")
        else:
            строки.append(f"{_диапазоны(номера)}: {вид}")
    return строки


def _вид(описание: str) -> str:
    """Описание канала без чисел энтропии: по нему каналы и группируются."""
    import re  # noqa: PLC0415

    return re.sub(r"\s*\([0-9.]+ бит/байт\)", "", описание)


def _диапазоны(номера: List[int]) -> str:
    части = []
    начало = предыдущий = номера[0]
    for номер in номера[1:] + [None]:
        if номер is not None and номер == предыдущий + 1:
            предыдущий = номер
            continue
        части.append(f"КИ{начало}" if начало == предыдущий else f"КИ{начало}–КИ{предыдущий}")
        if номер is not None:
            начало = предыдущий = номер
    return ", ".join(части)


def найти(биты: np.ndarray) -> Находка | None:
    """Цикл в битовом ряду: сперва E1, потом любой."""
    найдено = e1(биты)
    if найдено is not None and найдено.уверенность >= 0.5:
        return найдено
    цикл = длина_цикла(биты)
    if цикл is None:
        return None
    длина, пик, шум = цикл
    таблица = сложить(биты[:ВЫБОРКА], длина)
    участки = постоянные_участки(таблица)
    if not участки:
        return None
    начало, размер, значение = участки[0]
    подробно = [
        f"пик автокорреляции {пик:.4f} при шуме {шум:.4f} ({пик / шум:.0f} сигм)",
        f"постоянные участки цикла (начало, бит): " + "; ".join(
            f"{н}: {з if len(з) <= 32 else з[:32] + '…'} ({д} бит)"
            for н, д, з in участки[:6]),
    ]
    # Синхрослово проверяем по всем циклам: совпало ли оно целиком.
    слово = np.frombuffer(значение.encode(), dtype=np.uint8) - ord("0")
    полная = сложить(биты, длина)
    совпало = float(np.mean(np.all(полная[:, начало:начало + размер] == слово, axis=1)))
    каналы: Dict[int, np.ndarray] = {}
    if длина % 8 == 0:
        # Нарезку по байтам выравниваем по началу синхрослова: служебное
        # слово стоит в начале своего интервала почти всегда.
        сдвиг = начало % 8
        циклы = сложить(биты, длина, сдвиг)
        каналы = разнести(циклы)
        подробно.append(f"цикл кратен байту: {длина // 8} интервалов по 8 бит, "
                        f"нарезка от бита {сдвиг}")
        подробно += описать_каналы(каналы)
    return Находка(
        уровень="цикл", что=f"цикл {длина} бит, синхрослово {размер} бит",
        уверенность=совпало,
        мера=f"самый длинный постоянный участок совпал целиком в "
             f"{round(совпало * 100, 1)} % циклов",
        подробно=подробно, дальше=каналы or None, вид_дальше="каналы" if каналы else "")
