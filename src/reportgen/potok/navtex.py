"""NAVTEX (SITOR-B, ITU-R M.476/M.625, M.540): код CCIR 476 с повтором знака через пять мест.

Как у fldigi (navtex.cxx) и SDRangel (sdrbase/util/navtex.cpp):
- знак — 7 бит, первым передаётся младший (так у fldigi; SDRangel собирает знак старшим вперёд —
  таблица та же с обратным порядком бит); годный знак — ровно четыре B (единицы) из семи, при
  обратной полярности — три; буква A = B B B Y Y Y B;
- режим B (FEC): каждый знак передаётся дважды — первый раз (DX) и повтор (RX) через пять знаковых
  мест (35 бит); места DX и RX чередуются; при фазировании в местах DX — фазирующий 2 (0x66),
  в местах RX — фазирующий 1 (0x0F); α в обоих местах — конец передачи;
- регистры: LTRS 0x5A, FIGS 0x36; служебные 0x0F, 0x66, β 0x33, знак 32 0x6A пропускаются;
  регистр цифр — международный по M.476 (J — звонок, D — «кто там?», S — апостроф);
- сообщение: «ZCZC B1B2B3B4» … «NNNN»: B1 — станция (A–Z), B2 — вид сообщения, B3B4 — номер.
"""

from __future__ import annotations

import re
from collections import Counter
from dataclasses import dataclass, field

import numpy as np

from .nahodka import Находка

# код (младший бит — первый переданный) → (буква, цифра); по SDRangel и fldigi
КОДЫ = {
    0x17: ("J", "\x07"), 0x1B: ("F", "!"), 0x1D: ("C", ":"), 0x1E: ("K", "("), 0x27: ("W", "2"),
    0x2B: ("Y", "6"), 0x2D: ("P", "0"), 0x2E: ("Q", "1"), 0x35: ("G", "&"), 0x39: ("M", "."),
    0x3A: ("X", "/"), 0x3C: ("V", "="), 0x47: ("A", "-"), 0x4B: ("S", "'"), 0x4D: ("I", "8"),
    0x4E: ("U", "7"), 0x53: ("D", "\x05"), 0x55: ("R", "4"), 0x56: ("E", "3"), 0x59: ("N", ","),
    0x5C: (" ", " "), 0x63: ("Z", "+"), 0x65: ("L", ")"), 0x69: ("H", "£"), 0x6C: ("\n", "\n"),
    0x71: ("O", "9"), 0x72: ("B", "?"), 0x74: ("T", "5"), 0x78: ("\r", "\r"),
}
LTRS, FIGS, АЛЬФА, БЕТА, ПОВТОР, ЗНАК32 = 0x5A, 0x36, 0x0F, 0x33, 0x66, 0x6A
СЛУЖЕБНЫЕ = (АЛЬФА, БЕТА, ПОВТОР, ЗНАК32)
СДВИГ = 5                        # повтор — через пять знаковых мест
ОКНО, В_ОКНЕ = 14, 10            # участок: в любых 14 знаках подряд не меньше 10 годных — замирание
                                 # на 4 места (280 мс) не рвёт передачу: повтор через 5 мест её чинит
НАЙТИ_ОТ = 40                    # знаков в участке
ПОВТОРОВ_ОТ = 0.5                # доля совпавших пар DX/RX
РАЗНЫХ_ОТ = 6                    # разных знаков (не служебных), подтверждённых повтором: простой
                                 # из одного кода (1110001…) даёт одну букву при любом сдвиге
ВЕС = np.array([bin(i).count("1") for i in range(128)])

ВИДЫ = {
    "A": "навигационное предупреждение", "B": "метеорологическое предупреждение",
    "C": "ледовая обстановка", "D": "поиск и спасение, пиратство", "E": "метеопрогноз",
    "F": "лоцманская служба", "G": "сообщение АИС", "H": "LORAN", "I": "не используется",
    "J": "спутниковая навигация", "K": "прочие навигационные средства",
    "L": "навигационное предупреждение (дополнение к A)", "T": "испытательная передача",
    "V": "извещение рыбакам (США)", "W": "экологическое (США)",
    "X": "особая служба (по решению IMO)", "Y": "особая служба (по решению IMO)",
    "Z": "сообщений нет",
}


def годный(код: int) -> bool:
    return bin(код).count("1") == 4


ВЕСА_БИТ = np.array([1, 2, 4, 8, 16, 32, 64], dtype=np.uint8)


def _коды(биты: np.ndarray, сдвиг: int) -> np.ndarray:
    """Коды по 7 бит (первый — младший) с места ``сдвиг``; произведение в uint8 — сумма не больше 127."""
    ряд = биты[сдвиг:]
    return ряд[:len(ряд) // 7 * 7].reshape(-1, 7) @ ВЕСА_БИТ


@dataclass
class Передача:
    бит: int                      # место первого знака участка в битах
    инверсия: bool
    коды: list[int]
    текст: str = ""
    исправлено: int = 0           # взят повтор вместо испорченного первого
    потеряно: int = 0             # испорчены оба
    повторов: float = 0.0         # доля совпавших пар DX/RX
    сообщения: list[dict] = field(default_factory=list)


def _участки(годные: np.ndarray) -> list[tuple[int, int]]:
    """Участки знаков, где в любом окне из 14 подряд не меньше 10 годных; начало — с годного знака."""
    if len(годные) < ОКНО:
        return []
    сумма = np.convolve(годные.astype(np.int64), np.ones(ОКНО, dtype=np.int64), mode="valid")
    края = np.diff(np.concatenate([[0], (сумма >= В_ОКНЕ).astype(np.int8), [0]]))
    итог = []
    for н, к in zip(np.flatnonzero(края == 1).tolist(), np.flatnonzero(края == -1).tolist(), strict=False):
        к = к - 1 + ОКНО                                  # последнее хорошее окно кончается здесь
        while not годные[н]:
            н += 1
        итог.append((н, к))
    return итог


def разобрать(коды: list[int]) -> tuple[str, int, int, float]:
    """Знаки участка → текст; места DX — та чётность, где знак совпадает со знаком через пять мест."""
    n = len(коды)
    счёт = [sum(1 for j in range(ч, n - СДВИГ, 2) if годный(коды[j]) and коды[j] == коды[j + СДВИГ])
            for ч in (0, 1)]
    ч = int(счёт[1] > счёт[0])
    пар = max(1, len(range(ч, n - СДВИГ, 2)))
    # текст — от первого до последнего места DX, подтверждённого повтором; вне них — случайно годные знаки
    # шума вокруг передачи (у оборванной записи последние знаки без повтора не подтвердить — отбрасываются)
    подтверждены = [j for j in range(ч, n - СДВИГ, 2) if годный(коды[j]) and коды[j] == коды[j + СДВИГ]]
    места = range(подтверждены[0], подтверждены[-1] + 1, 2) if подтверждены else range(0)
    текст, исправлено, потеряно, цифры = [], 0, 0, False
    for j in места:
        dx = коды[j]
        rx = коды[j + СДВИГ] if j + СДВИГ < n else None
        if dx == АЛЬФА and rx == АЛЬФА:
            break                                                  # конец передачи
        if годный(dx):
            код = dx
        elif rx is not None and годный(rx):
            код, исправлено = rx, исправлено + 1
        else:
            потеряно += 1
            текст.append("*")
            continue
        if код == LTRS:
            цифры = False
        elif код == FIGS:
            цифры = True
        elif код in КОДЫ:
            знак = КОДЫ[код][цифры]
            if знак not in "\r\x05\x07":
                текст.append(знак)
    return "".join(текст), исправлено, потеряно, счёт[ч] / пар


def сообщения(текст: str) -> list[dict]:
    итог = []
    for м in re.finditer(r"ZCZC ?([A-Z])([A-Z])(\d\d)(.*?)(NNNN|$)", текст, re.S):
        итог.append({"станция": м.group(1), "вид": м.group(2), "номер": м.group(3),
                     "текст": м.group(4).strip(), "полное": м.group(5) == "NNNN"})
    return итог


def передачи(биты: np.ndarray) -> list[Передача]:
    """Все участки SITOR-B: при любом битовом сдвиге и полярности, с повтором через пять знаков."""
    биты = np.asarray(биты, dtype=np.uint8)
    найдено: list[Передача] = []
    for инверсия in (False, True):
        ряд = 1 - биты if инверсия else биты
        for сдвиг in range(7):
            коды = _коды(ряд, сдвиг)
            for н, к in _участки(ВЕС[коды] == 4):
                участок = коды[н:к].tolist()
                # разные знаки — только подтверждённые повтором: случайные годные знаки шума по краям не в счёт
                разных = {x for x, y in zip(участок, участок[СДВИГ:], strict=False) if x == y and годный(x)} - set(СЛУЖЕБНЫЕ)
                if к - н < НАЙТИ_ОТ or len(разных) < РАЗНЫХ_ОТ:
                    continue
                п = Передача(сдвиг + 7 * н, инверсия, [int(x) for x in коды[н:к]])
                п.текст, п.исправлено, п.потеряно, п.повторов = разобрать(п.коды)
                if п.повторов >= ПОВТОРОВ_ОТ:
                    п.сообщения = сообщения(п.текст)
                    найдено.append(п)
    # другой сдвиг или полярность той же передачи годных знаков не дают — участки не перекрываются
    return sorted(найдено, key=lambda п: п.бит)


def найти(биты: np.ndarray) -> Находка | None:
    пп = передачи(биты)
    if not пп:
        return None
    все = [с for п in пп for с in п.сообщения]
    станции = Counter(с["станция"] for с in все)
    виды = Counter(с["вид"] for с in все)
    подробно = [f"передач: {len(пп)}, знаков: {sum(len(п.коды) for п in пп) // 2}"
                + (" — полярность обратная" if all(п.инверсия for п in пп) else ""),
                f"повтор (RX) вместо испорченного DX: {sum(п.исправлено for п in пп)}, "
                f"испорчены оба: {sum(п.потеряно for п in пп)}"]
    if все:
        подробно.append("станции: " + ", ".join(f"{с} × {к}" for с, к in станции.most_common()))
        подробно.append("виды: " + ", ".join(f"{в} ({ВИДЫ.get(в, 'неизвестный')}) × {к}"
                                           for в, к in виды.most_common()))
    for с in все[:30]:
        подробно.append(f"{с['станция']}{с['вид']}{с['номер']} — {ВИДЫ.get(с['вид'], 'неизвестный вид')}"
                        + ("" if с["полное"] else " (без NNNN)") + f": {с['текст'][:200]}")
    if not все:
        подробно.append("текст: " + " | ".join(п.текст[:200] for п in пп[:5]))
    return Находка(
        уровень="канальный", что="NAVTEX / SITOR-B (CCIR 476, режим B): сообщения морской безопасности",
        уверенность=1.0 if все else 0.9,
        мера=f"{sum(int((ВЕС[п.коды] == 4).sum()) for п in пп)} знаков с 4 единицами из 7, пары DX/RX через 5 мест",
        подробно=подробно, свойства={"передач": len(пп), "сообщений": len(все), "станций": len(станции)})


def закодировать(текст: str, фазирование: int = 8) -> np.ndarray:
    """Текст → биты режима B (для проверок): фазирование, пары DX/RX, α в конце."""
    обратно = {}
    for код, (б, ц) in КОДЫ.items():
        обратно.setdefault(("б", б), код)
        обратно.setdefault(("ц", ц), код)
    коды, цифры = [], False
    for с in текст.upper():
        if not цифры and ("б", с) in обратно:
            коды.append(обратно[("б", с)])
        elif цифры and ("ц", с) in обратно:
            коды.append(обратно[("ц", с)])
        elif ("б", с) in обратно:
            цифры = False
            коды += [LTRS, обратно[("б", с)]]
        elif ("ц", с) in обратно:
            цифры = True
            коды += [FIGS, обратно[("ц", с)]]
    места = []
    for _ in range(фазирование):
        места += [ПОВТОР, АЛЬФА]
    for i in range(len(коды) + 2):
        места.append(коды[i] if i < len(коды) else АЛЬФА)
        места.append(коды[i - 2] if 2 <= i < len(коды) + 2 else АЛЬФА)
    места += [АЛЬФА, АЛЬФА] * 3
    return np.array([(к >> b) & 1 for к in места for b in range(7)], dtype=np.uint8)
