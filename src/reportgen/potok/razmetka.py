ВЫБОРКА_АНАЛИЗА = 1 << 18
ПЕРИОД_ДО = 1 << 14
ПЕРИОД_ОТ = 4
#: Период засчитывается, если совпадений символов больше ожидаемого на столько разбросов.
ПОРОГ_ПЕРИОДА = 8.0
#: Синхрослово кадра — не короче стольких постоянных символов.
СЛОВО_ОТ = 2
#: Место кадра постоянно, если один символ стоит там в такой доле кадров.
ПОСТОЯННО_ОТ = 0.9
#: Место кадра почти постоянно (служебное), если один символ стоит там в такой доле кадров.
ПОСТОЯННОЕ_МЕСТО = 0.5
#: Мера строк: кадров с данными — не больше; длины строк — в этих пределах (как у ``tpc``).
КАДРОВ_СТРОК = 64
