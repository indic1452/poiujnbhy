"""Разметка вслепую: какая истинная метка у каждого символа, если демодулятор нумерует точки по-своему.

Биты от демодулятора — метки символов в ЧУЖОЙ разметке. Истинная разметка —
перестановка π на M символах: не только поворот, отражение, перестановка бит
и инверсия (их перебирает ``ploskost``), а любая — «чутка изменённое
созвездие», где точкам даны другие значения. Здесь:

**(а) Анализ на уровне символов**, от разметки не зависящий: частоты
символов, переходы, период кадра и места синхрослова. Одинаковые символы на
одних и тех же местах кадра остаются одинаковыми при любой π, поэтому период и
синхрослово видны до того, как разметка найдена (``анализ``).

**(б) Синхрослово известно в битах** (введено, из библиотеки или найдено
раньше) — π выводится прямо: принятые символы синхрослова сопоставляются с его
истинными метками при каждом сдвиге слова относительно границ символов
(``по_синхрослову``); что слово не покрыло — перебором по мере.

**(в) Поиск по мере структуры** потока после перестановки:

- строки кода произведения (ТКБ) в кадрах — ``МераСтрок``. Чётность окна бит
  в кадре — это чётность меток целых символов внутри окна плюс частичные
  символы на краях. Чётность метки целого символа — функция h: символ → {0, 1},
  у ФМ-8 она делит 8 символов на две четвёрки: 35 классов (с точностью до
  дополнения) вместо 40 320 перестановок. Этап А: для каждого класса h и всех
  длин строк сразу — энергия перекоса чётности окон, где на краю не больше
  одного частичного символа; окна разбиваются на группы по значению этого
  символа (его вклад в группе постоянен). Суммы по кадрам — произведением
  матриц (все концы окна сразу). Этап Б: у лучшего класса — все 576
  перестановок, переводящих его четвёрку в метки чётного веса, точной мерой
  строк на найденных длине и начале. Вместе этапы проходят все 8! перестановок.
  Инверсию бит метки (x ⊕ c) мера строк не различает — выходят 8
  равноценных, какой верный, решает то, что под кодом;
- линейная сложность (Берлекэмп — Мэсси, векторно по перестановкам) — у
  тестовой ПСП при верной разметке она равна степени регистра, у прочих —
  половине длины отрезка (``МераЛРП``);
- байтовая структура — падение энтропии байт по всем выравниваниям; байт по
  перестановке собирается из гистограмм троек и четвёрок символов, выборка
  проходится один раз (``МераБайт``).

До 8 точек — полный перебор; у 16, 32 и 64 точек — сначала группа симметрий
созвездия × перестановки бит × инверсии бит (старты), затем местный поиск:
обмены пар меток, пока мера растёт, и отжиг (случайные обмены) с нескольких
стартов. Ход — долей работы и оценкой срока (``ход``), ``срок`` — секунд.
"""

from __future__ import annotations

import itertools
import math
import time
from collections.abc import Callable, Sequence
from dataclasses import dataclass, field
