# -- символы -----------------------------------------------------------------------------------

def в_символы(биты: np.ndarray, k: int, фаза: int = 0) -> np.ndarray:
    """Биты → метки по k бит (старший первым) с бита ``фаза``; хвост отбрасывается."""
    ряд = np.asarray(биты[фаза:], dtype=np.uint8)
    n = len(ряд) // k
    return ряд[:n * k].reshape(n, k).astype(np.int64) @ (1 << np.arange(k - 1, -1, -1))


def в_биты(символы: np.ndarray, k: int) -> np.ndarray:
    """Метки → биты (старший первым); у пачки (B × n) — B × n·k."""
    a = np.asarray(символы, dtype=np.int64)
    биты = ((a[..., None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8)
    return биты.reshape(a.shape[:-1] + (-1,))


def применить(биты: np.ndarray, k: int, таблица: Sequence[int], фаза: int = 0) -> np.ndarray:
    """Поток меток → поток истинных меток: метка v → таблица[v]."""
    return в_биты(np.asarray(таблица, dtype=np.int64)[в_символы(биты, k, фаза)], k)


def _вес(M: int) -> np.ndarray:
    return np.array([bin(v).count("1") for v in range(M)], dtype=np.int64)


# -- (а) анализ на уровне символов --------------------------------------------------------------

def _совпадения(символы: np.ndarray, M: int, до: int) -> np.ndarray:
    """Сколько раз s[i] == s[i + d] для d = 0…до (свёртка индикаторов через БПФ)."""
    n = len(символы)
    размер = 1 << int(math.ceil(math.log2(max(2, n + до + 1))))
    итог = np.zeros(до + 1)
    for v in np.unique(символы):
        x = np.fft.rfft((символы == v).astype(np.float64), размер)
        итог += np.fft.irfft(x * np.conj(x), размер)[:до + 1]
    return np.round(итог)


def период(символы: np.ndarray, M: int, *, до: int = ПЕРИОД_ДО) -> dict[str, Any] | None:
    """Период кадра по совпадениям символов на расстоянии d: {символов, отрыв} или None.

    Ожидаемая доля совпадений у независимых символов — Σp²; отрыв — избыток в
    разбросах. Берётся наибольший отрыв, затем наименьший его делитель с
    отрывом не меньше половины (кратные периода совпадают не хуже).
    """
    n = len(символы)
    до = min(до, n // 4)
    if до < ПЕРИОД_ОТ:
        return None
    p = np.bincount(символы, minlength=M) / n
    ждать = float((p ** 2).sum())
    if ждать >= 1 - 1e-12:
        return None
    d = np.arange(до + 1)
    пар = n - d
    z = (_совпадения(символы, M, до) / np.maximum(1, пар) - ждать) / np.sqrt(ждать * (1 - ждать) / np.maximum(1, пар))
    z[:ПЕРИОД_ОТ] = 0
    лучший = int(np.argmax(z))
    if z[лучший] < ПОРОГ_ПЕРИОДА:
        return None
    for делитель in range(ПЕРИОД_ОТ, лучший):
        if лучший % делитель == 0 and z[делитель] >= z[лучший] / 2:
            лучший = делитель
            break
    return {"символов": лучший, "отрыв": round(float(z[лучший]), 1)}


def постоянные_места(символы: np.ndarray, длина: int, *, от: float = ПОСТОЯННО_ОТ) -> list[dict[str, Any]]:
    """Места кадра, где стоит один и тот же символ (при любой разметке): участки подряд.

    Каждый участок — {начало, длина, символы, доля}; «чередуется» — если в
    чётных и нечётных кадрах там стоят разные постоянные символы (синхрослово
    через кадр, как у Comtech).
    """
    строк = len(символы) // длина
    if строк < 4:
        return []
    таблица = символы[:строк * длина].reshape(строк, длина)

    def мода(т: np.ndarray) -> tuple[np.ndarray, np.ndarray]:
        M = int(т.max()) + 1
        счёт = np.stack([(т == v).sum(axis=0) for v in range(M)])
        return счёт.argmax(axis=0), счёт.max(axis=0) / len(т)

    вся, доля = мода(таблица)
    чёт, доля_ч = мода(таблица[0::2])
    нечёт, доля_н = мода(таблица[1::2])
    постоянно = доля >= от
    чередуется = ~постоянно & (доля_ч >= от) & (доля_н >= от) & (чёт != нечёт)
    итог = []
    место = 0
    while место < длина:
        if not (постоянно[место] or чередуется[место]):
            место += 1
            continue
        конец = место
        while конец < длина and (постоянно[конец] or чередуется[конец]):
            конец += 1
        участок = {"начало": место, "длина": конец - место,
                   "символы": [int(v) for v in чёт[место:конец]],
                   "доля": round(float(np.where(постоянно, доля, np.minimum(доля_ч, доля_н))[место:конец].min()), 3)}
        if чередуется[место:конец].any():
            участок["чередуется"] = True
            участок["символы_нечётных"] = [int(v) for v in нечёт[место:конец]]
        итог.append(участок)
        место = конец
    return итог


def кадр_по_повтору(символы: np.ndarray, P: int, k: int) -> tuple[int, list[dict[str, Any]]]:
    """Кадр и его постоянные места по периоду повтора P (в символах).

    Повтор бывает кратным кадру (заполнение повторяется через несколько кадров):
    кадр — наименьший делитель P, на котором есть постоянное слово не короче байта
    (синхрослово стоит в каждом кадре); нет такого — сам P.
    """
    слово_от = max(СЛОВО_ОТ, -(-8 // k))
    for d in range(ПЕРИОД_ОТ, P):
        if P % d == 0:
            места = постоянные_места(символы, d)
            if max((у["длина"] for у in места), default=0) >= слово_от:
                return d, места
    return P, постоянные_места(символы, P)


def анализ(биты: np.ndarray, k: int, *, фаза: int | None = None, выборка: int = ВЫБОРКА_АНАЛИЗА,
           период_до: int = ПЕРИОД_ДО) -> dict[str, Any]:
    """Частоты символов, переходы, период кадра и постоянные места — не зависят от разметки.

    ``фаза`` — граница символа (бит 0…k−1); None — та, при которой период
    виден сильнее всего (синхрослово целыми символами).
    """
    M = 1 << k
    фазы = range(k) if фаза is None else (int(фаза),)
    лучший: dict[str, Any] | None = None
    for ф in фазы:
        символы = в_символы(np.asarray(биты[:выборка * k + k]), k, ф)
        п = период(символы, M, до=период_до)
        сила = п["отрыв"] if п else 0.0
        if лучший is None or сила > лучший["сила"]:
            лучший = {"сила": сила, "фаза": ф, "символы": символы, "период": п}
    assert лучший is not None
    символы = лучший["символы"]
    n = len(символы)
    частоты = np.bincount(символы, minlength=M) / max(1, n)
    переходы = np.bincount(символы[:-1] * M + символы[1:], minlength=M * M).reshape(M, M) if n > 1 else np.zeros((M, M))
    ждать = float((частоты ** 2).sum())
    итог: dict[str, Any] = {
        "k": k, "M": M, "фаза": лучший["фаза"], "символов": int(n),
        "частоты": [round(float(ч), 5) for ч in частоты],
        "переходы": переходы.astype(int).tolist(),
        "повторов_подряд": round(float(np.trace(переходы) / max(1, n - 1)), 5),
        "повторов_ждать": round(ждать, 5),
        "частые_переходы": [[int(i // M), int(i % M), int(переходы.ravel()[i])]
                            for i in np.argsort(-переходы.ravel(), kind="stable")[:8]],
        "период": лучший["период"],
    }
    if лучший["период"]:
        итог["кадр"], итог["места"] = кадр_по_повтору(символы, лучший["период"]["символов"], k)
        if any(у.get("чередуется") for у in итог["места"]):
            итог["цикл"] = 2 * итог["кадр"]
    return итог


# -- (б) по синхрослову ---------------------------------------------------------------------------

def по_синхрослову(слово: Sequence[int], принятые: Sequence[int], k: int, *, инверсия: bool = True
                   ) -> list[dict[str, Any]]:
    """Сопоставить принятые символы синхрослова (подряд) с его истинными битами: варианты по убыванию покрытия.

    Слово ставится со сдвигом s бит относительно начала первого принятого
    символа (s от −(длина слова − k) до k·(символов − 1)); символ, целиком
    лежащий под словом, даёт пару «принятый → истинный». Вариант годен, если
    пары согласны (один принятый — одна истинная метка, и наоборот).
    {соответствие, покрыто, пар, сдвиг, инверсия}. ``инверсия`` — пробовать и
    инвертированное слово.
    """
    слово = [int(б) & 1 for б in слово]
    принятые = [int(v) for v in принятые]
    n, m = len(слово), len(принятые)
    итог = []
    for инв in ((False, True) if инверсия else (False,)):
        биты = [б ^ инв for б in слово]
        for сдвиг in range(-(n - k), k * (m - 1) + 1):
            пары: dict[int, int] = {}
            обратно: dict[int, int] = {}
            годно, всего = True, 0
            for j in range(m):
                начало = k * j - сдвиг
                if начало < 0 or начало + k > n:
                    continue
                истинная = int("".join(map(str, биты[начало:начало + k])), 2)
                v = принятые[j]
                if пары.get(v, истинная) != истинная or обратно.get(истинная, v) != v:
                    годно = False
                    break
                пары[v], обратно[истинная] = истинная, v
                всего += 1
            if годно and всего:
                итог.append({"соответствие": dict(sorted(пары.items())), "покрыто": len(пары), "пар": всего,
                             "сдвиг": сдвиг, "инверсия": инв})
    итог.sort(key=lambda в: (-в["покрыто"], -в["пар"], в["инверсия"], abs(в["сдвиг"])))
    return итог


def дополнения(соответствие: dict[int, int], M: int) -> np.ndarray:
    """Все перестановки (таблицы принятый → истинный), продолжающие частичное соответствие."""
    свободные_вход = [v for v in range(M) if v not in соответствие]
    свободные_выход = [t for t in range(M) if t not in соответствие.values()]
    if math.factorial(len(свободные_вход)) > 40320:
        raise ValueError(f"синхрослово покрыло {len(соответствие)} символов из {M}: остальные {len(свободные_вход)}! "
                         f"перестановок — больше 40 320; нужен поиск по мере")
    основа = np.zeros(M, dtype=np.int64)
    for v, t in соответствие.items():
        основа[v] = t
    итог = []
    for хвост in itertools.permutations(свободные_выход):
        т = основа.copy()
        т[свободные_вход] = хвост
        итог.append(т)
    return np.array(итог, dtype=np.int64).reshape(-1, M)


# -- меры: векторно по пачке таблиц (B × M) ----------------------------------------------------

class МераЛРП:
    """Линейная сложность потока после перестановки — Берлекэмп — Мэсси по нескольким отрезкам, векторно.

    Мера — (длина/2 − сложность) / √(длина/4) по медиане отрезков: у ПСП степени
    D при верной разметке сложность D, у прочих — около половины длины.
    Инверсия бит метки прибавляет к ряду периодический узор (период k): сложность
    растёт не больше чем на k.
    """

    имя = "линейная сложность (ЛРП)"

    def __init__(self, символы: np.ndarray, k: int, *, отрезков: int = ОТРЕЗКОВ_ЛРП, длина: int = ДЛИНА_ЛРП):
        self.k = k
        n = длина // k
        шаг = max(n, len(символы) // max(1, отрезков))
        self.отрезки = [символы[i:i + n] for i in range(0, len(символы) - n + 1, шаг)][:отрезков]
        self.длина = n * k

    @staticmethod
    def сложность(ряды: np.ndarray) -> np.ndarray:
        """Линейная сложность каждой строки (B × n бит) над GF(2) — Берлекэмп — Мэсси, все строки сразу."""
        ряды = np.asarray(ряды, dtype=np.uint8)
        B, n = ряды.shape
        C = np.zeros((B, n + 1), np.uint8)
        Bp = np.zeros((B, n + 1), np.uint8)
        C[:, 0] = Bp[:, 0] = 1
        L = np.zeros(B, np.int64)
        m = np.ones(B, np.int64)
        строки = np.arange(B)[:, None]
        места = np.arange(n + 1)[None, :]
        for N in range(n):
            d = ряды[:, N].copy()
            if N:
                d ^= ((C[:, 1:N + 1] & ряды[:, N - 1::-1]).sum(axis=1) & 1).astype(np.uint8)
            d = d.astype(bool)
            if not d.any():
                m += 1
                continue
            откуда = места - m[:, None]
            сдвинутая = np.where(откуда >= 0, Bp[строки, np.maximum(откуда, 0)], 0).astype(np.uint8)
            рост = d & (2 * L <= N)
            старая = C[рост].copy()
            C[d] ^= сдвинутая[d]
            Bp[рост] = старая
            L = np.where(рост, N + 1 - L, L)
            m = np.where(рост, 1, m + 1)
        return L

    def оценить(self, таблицы: np.ndarray) -> np.ndarray:
        # Медиана по отрезкам: ошибка линии портит один отрезок, а отрезок, где встречаются не все символы
        # (начало ПСП из нулей), не различает таблицы, отличающиеся на отсутствующих, — и по минимуму
        # неверная таблица сравнялась бы с верной.
        сложности = np.stack([self.сложность(в_биты(таблицы[:, отрезок], self.k).reshape(len(таблицы), -1))
                              for отрезок in self.отрезки])
        return (self.длина / 2 - np.median(сложности, axis=0)) / math.sqrt(self.длина / 4)


class МераБайт:
    """Дешёвая байтовая мера: вероятность совпадения 8-битовых окон потока после перестановки (Σp²) по всем сдвигам.

    Окно с бита r символа накрывает символы s₁…s_T: целые в середине, а на краях —
    младшие k − r бит метки s₁ и старшие m бит метки s_T. Перестановка биективна:
    окна совпадают, когда совпадают средние символы, а у краёв — лишь те биты меток,
    что попали в окно. Значит, у каждой перестановки Σp² считается по гистограмме
    кусков (s₁, середина, s_T), собранной один раз: ключ куска — (биты метки s₁ в
    окне, середина, биты метки s_T в окне), сумма квадратов счётчиков по ключам —
    без прохода по потоку (4 096 ячеек у ФМ-8 и ФМ-16).

    Повторяющиеся участки в естественном порядке бит (флаги HDLC, заполнение)
    дают мало различных окон; перестановка меток разносит их по многим. Это
    первая ступень: лучших переоценивает полная мера структуры
    (``skrembler.мера_полная`` — байты, кадры с верной FCS, цикл). Инверсия бит
    метки (x ⊕ c) меры не меняет. Сдвиги, у которых кусков больше ``ЯЧЕЕК_ДО``,
    не считаются (у ФМ-64 — окно через три символа).
    """

    имя = "байтовая структура"
    ЯЧЕЕК_ДО = 1 << 16

    def __init__(self, символы: np.ndarray, k: int):
        self.k, self.M = k, 1 << k
        M = self.M
        self.части = []
        for r in range(k):
            T = -(-(r + 8) // k)
            сред = M ** max(0, T - 2)
            n = len(символы) - T
            if n <= 0 or M * сред * M > self.ЯЧЕЕК_ДО:
                continue
            середина = np.zeros(n, np.int64)
            for j in range(1, T - 1):
                середина = середина * M + символы[j:j + n]
            счёт = np.bincount((символы[:n] * сред + середина) * M + символы[T - 1:T - 1 + n],
                               minlength=M * сред * M).astype(np.float64)
            ячейки = np.flatnonzero(счёт)
            младших = k - r if r else k           # у первого символа в окне — младшие k − r бит (r = 0: весь)
            старших = (r + 8) % k or k           # у последнего — старшие m бит (m = k: весь)
            # До 16 точек — свёрткой тензора K[a, b, a′, b′] = Σ по середине счёт·счёт (M⁴ ячеек): быстрее ключей.
            K = None
            if M ** 4 <= self.ЯЧЕЕК_ДО:
                куски = счёт.reshape(M, сред, M)
                K = np.einsum("amb,cmd->abcd", куски, куски)
            self.части.append({"вес": счёт[ячейки], "a": ячейки // (сред * M), "середина": (ячейки // M) % сред,
                               "b": ячейки % M, "сред": сред, "маска1": (1 << младших) - 1,
                               "маска2": ((1 << старших) - 1) << (k - старших), "всего": float(n) ** 2, "K": K})

    def оценить(self, таблицы: np.ndarray) -> np.ndarray:
        таблицы = np.asarray(таблицы, dtype=np.int64)
        B, M = len(таблицы), self.M
        итог = np.zeros(B)
        for ч in self.части:
            if ч["K"] is not None:
                п1, п2 = таблицы & ч["маска1"], таблицы & ч["маска2"]
                E1 = (п1[:, :, None] == п1[:, None, :]).astype(np.float64)          # B × a × a′
                E2 = (п2[:, :, None] == п2[:, None, :]).astype(np.float64)          # B × b × b′
                итог += 256 * np.einsum("xac,xbd,abcd->x", E1, E2, ч["K"], optimize=True) / ч["всего"] - 1
                continue
            размер = M * ч["сред"] * M
            ключ = ((таблицы[:, ч["a"]] & ч["маска1"]) * ч["сред"] + ч["середина"]) * M + (таблицы[:, ч["b"]] & ч["маска2"])
            ключ = ключ + размер * np.arange(B)[:, None]
            счёт = np.bincount(ключ.ravel(), weights=np.broadcast_to(ч["вес"], ключ.shape).ravel(), minlength=размер * B)
            итог += 256 * (счёт.reshape(B, размер) ** 2).sum(axis=1) / ч["всего"] - 1
        return итог / max(1, len(self.части))


class МераСтрок:
    """Строки кода произведения в кадрах: перекос чётности окон L бит с мест o + j·L.

    ``символы`` — кадры × символов (кадры с данными, граница символа — на месте);
    окно — биты кадра [a, a + L) от первой границы символа.
    """

    имя = "строки кода в кадрах"

    def __init__(self, символы: np.ndarray, k: int):
        self.S = np.asarray(символы, dtype=np.int64)
        self.k, self.M = k, 1 << k
        self.F, self.Q = self.S.shape
        # Места кадра с почти постоянным символом (синхрослово, служебные поля) — чётность окна там
        # постоянна при любой разметке: окна, задевающие их, не считаются.
        доля = np.stack([(self.S == g).mean(axis=0) for g in range(self.M)]).max(axis=0)
        self.постоянных = np.concatenate([[0], np.cumsum(доля >= ПОСТОЯННОЕ_МЕСТО)])

    def _переменные(self, a: np.ndarray, e: np.ndarray) -> np.ndarray:
        """Окна бит [a, e) кадра, не задевающие почти постоянных символов."""
        k = self.k
        return self.постоянных[np.minimum(-(-e // k), self.Q)] - self.постоянных[a // k] == 0

    # -- этап А: классы чётности --

    def _энергии(self, h: np.ndarray, пары: Sequence[tuple[np.ndarray, np.ndarray]]) -> list[np.ndarray]:
        """Энергии окон по местам (начальный символ, конечный) трёх видов: без частичных символов, с частичным в
        начале и в конце — по группам значения частичного символа (его вклад в группе постоянен)."""
        F, Q, M = self.F, self.Q, self.M
        P = np.concatenate([np.zeros((F, 1), np.uint8), np.bitwise_xor.accumulate(h[self.S], axis=1)], axis=1)
        U = (1 - 2 * P.astype(np.float32))                     # F × (Q+1)
        (i0, j0), (i1, j1), (i2, j2) = пары
        C0 = (U[:, i0] * U[:, j0]).sum(axis=0)
        # Начало: частичный символ q, целые — с q+1 до конечного j; конец: частичный символ q = j, целые — с i.
        # Суммы по кадрам в группах значения частичного символа — по разности d = j − i (полоса шириной
        # в наибольшую длину окна), bincount по (значение, место).
        D = int(max((j1 - i1).max(initial=1), (j2 - i2).max(initial=1)))
        Eн = np.zeros((Q, D + 1))
        Eк = np.zeros((Q + 1, D + 1))
        ключ = (self.S * Q + np.arange(Q)).ravel()
        for d in range(1, D + 1):
            if d <= Q:
                w = (U[:, 1:Q + 1] * U[:, np.minimum(np.arange(Q) + d, Q)]).ravel()
                г = np.bincount(ключ, weights=w, minlength=M * Q).reshape(M, Q)
                Eн[:, d] = (г * г).sum(axis=0) - F
                # Конец: частичный символ q, начало i = q − d: U[i]·U[q]·[S[q] = g].
                w = (U[:, np.maximum(np.arange(Q) - d, 0)] * U[:, :Q]).ravel()
                г = np.bincount(ключ, weights=w, minlength=M * Q).reshape(M, Q)
                Eк[:Q, d] = (г * г).sum(axis=0) - F
        return [C0 * C0 - F, Eн[i1, j1 - i1], Eк[j2, j2 - i2]]

    def _окна(self, от: int, до: int):
        """Окна [a, a + L) всех длин: (длина, место, вид, i, j, группа) — вид 0: без частичных, 1: начало, 2: конец."""
        k, Q = self.k, self.Q
        n = k * Q
        L = np.concatenate([np.full(max(0, n - дл + 1), дл) for дл in range(от, min(до, n // 2) + 1)])
        a = np.concatenate([np.arange(max(0, n - дл + 1)) for дл in range(от, min(до, n // 2) + 1)])
        e = a + L
        ra, re_ = a % k, e % k
        вид = np.full(len(a), -1)
        вид[(ra == 0) & (re_ == 0)] = 0
        вид[(ra != 0) & (re_ == 0)] = 1
        вид[(ra == 0) & (re_ != 0)] = 2
        годно = (вид >= 0) & (e // k <= Q) & (a // k < Q)
        вид[(вид == 2) & (e // k >= Q)] = -1
        годно &= (вид >= 0) & self._переменные(a, e)
        return L[годно], a[годно], вид[годно], (a // k)[годно], (e // k)[годно]

    def классы(self, *, от: int = СТРОКА_ОТ, до: int = СТРОКА_ДО, срок: float | None = None,
               ход: Ход | None = None, только: Sequence[Sequence[int]] | None = None) -> list[dict[str, Any]]:
        """Этап А: для каждого класса чётности h — лучшая (длина, начало) и отрыв; по убыванию отрыва.

        ``только`` — не все классы, а эти (h — 0/1 по символам): у 16+ точек классов тысячи.
        """
        M, F = self.M, self.F
        L, a, вид, i, j = self._окна(от, до)
        o = a % L
        # Ключ (длина, начало) — сквозной номер; дисперсии окон под нулевой гипотезой.
        ключ_L = np.unique(L)
        база = np.concatenate([[0], np.cumsum(ключ_L)])[np.searchsorted(ключ_L, L)]
        ключ = база + o
        всего_ключей = int(ключ_L.sum())
        начала_ключей = np.concatenate([[0], np.cumsum(ключ_L)])
        n_g = np.stack([(self.S == g).sum(axis=0) for g in range(M)])       # M × Q
        var_гр = (2 * n_g * (n_g - 1)).sum(axis=0).astype(np.float64)       # по месту частичного символа
        var = np.where(вид == 0, 2.0 * F * (F - 1), np.where(вид == 1, var_гр[np.minimum(i, self.Q - 1)],
                                                               var_гр[np.minimum(j, self.Q - 1)]))
        # Различные пары (начальный символ, конечный) каждого вида окна — энергии считаются только у них.
        пары, обратно = [], []
        for в_ in range(3):
            код, обр = np.unique(i[вид == в_] * (self.Q + 1) + j[вид == в_], return_inverse=True)
            пары.append((код // (self.Q + 1), код % (self.Q + 1)))
            обратно.append(обр)
        знам = np.sqrt(np.maximum(1e-9, np.bincount(ключ, weights=var, minlength=всего_ключей)))
        классы = ([np.array([1 if v in с else 0 for v in range(M)], np.uint8)
                   for с in itertools.combinations(range(M), M // 2) if 0 in с] if только is None
                  else [np.asarray(h, dtype=np.uint8) for h in только])
        итог = []
        конец = None if срок is None else time.monotonic() + срок
        for номер, h in enumerate(классы):
            e = np.zeros(len(вид))
            for в_, значения in enumerate(self._энергии(h, пары)):
                e[вид == в_] = значения[обратно[в_]]
            z = np.bincount(ключ, weights=e, minlength=всего_ключей) / знам
            лучший = int(np.argmax(z))
            длина = int(ключ_L[np.searchsorted(np.cumsum(ключ_L), лучший, side="right")])
            начало = лучший - int(начала_ключей[np.searchsorted(ключ_L, длина)])
            # Кандидаты (длина, начало) — лучшие различные длины: окно из нескольких строк тоже чётное,
            # а у кратного k нет частичных символов, и оно выходит сильнее самой строки; какая из них
            # строка, решает точная мера на этапе Б.
            кандидаты = []
            for и in np.argsort(-z, kind="stable"):
                дл = int(ключ_L[np.searchsorted(np.cumsum(ключ_L), int(и), side="right")])
                if all(дл != к[0] for к in кандидаты):
                    кандидаты.append((дл, int(и) - int(начала_ключей[np.searchsorted(ключ_L, дл)]), round(float(z[и]), 1)))
                if len(кандидаты) >= КАНДИДАТОВ_ДЛИН:
                    break
            итог.append({"класс": [v for v in range(M) if h[v] == h[0]], "длина": длина, "начало": начало,
                         "отрыв": round(float(z[лучший]), 1), "кандидаты": кандидаты})
            if ход:
                ход((номер + 1) / len(классы), f"классы чётности: {номер + 1} из {len(классы)}")
            if конец is not None and time.monotonic() > конец:
                break
        итог.sort(key=lambda в: -в["отрыв"])
        return итог

    # -- этап Б: точная мера на длине и начале --

    def чётности(self, таблицы: np.ndarray, a: np.ndarray, e: np.ndarray) -> np.ndarray:
        """Чётность окон бит [a, e) кадра у каждой таблицы: B × кадров × окон.

        Чётность окна — чётность меток целых символов (по накопленной сумме) плюс
        биты частичных символов на краях (по маске метки) — без развёртки в биты.
        """
        k, M = self.k, self.M
        таблицы = np.asarray(таблицы, dtype=np.int64)
        вес = _вес(M) % 2
        чёт_метки = вес[таблицы].astype(np.uint8)                       # B × M
        P = np.concatenate([np.zeros((len(таблицы), self.F, 1), np.uint8),
                            np.bitwise_xor.accumulate(чёт_метки[:, self.S], axis=2)], axis=2)
        qa, ra, qe, re_ = a // k, a % k, e // k, e % k
        итог = P[:, :, qe] ^ P[:, :, qa + (ra > 0)]
        for r in range(1, k):
            for край, q, маска in ((ra == r, qa, (1 << (k - r)) - 1), (re_ == r, qe, ((1 << r) - 1) << (k - r))):
                if край.any():
                    часть = (вес[таблицы & маска] % 2).astype(np.uint8)       # B × M
                    итог[:, :, край] ^= часть[:, self.S[:, q[край]]]
        return итог

    def оценить(self, таблицы: np.ndarray, длина: int, начало: int) -> np.ndarray:
        """Сумма по местам o + j·L квадрата перекоса чётности окна (за вычетом 1/F), в разбросах."""
        k, F = self.k, self.F
        n = k * self.Q
        места = np.arange(начало % длина, n - длина + 1, длина)
        места = места[self._переменные(места, места + длина)]
        места = места[(места + длина) // k < self.Q + ((места + длина) % k == 0)]
        if not len(места):
            return np.zeros(len(таблицы))
        итог = []
        for с in range(0, len(таблицы), ПАЧКА):
            чёт = self.чётности(таблицы[с:с + ПАЧКА], места, места + длина)
            перекос = (1 - 2 * чёт.mean(axis=1)) ** 2 - 1 / F                  # B × мест
            итог.append(перекос.sum(axis=1) * F / math.sqrt(2 * len(места)))
        return np.concatenate(итог)

    def оценить_все_длины(self, таблицы: np.ndarray, *, от: int = СТРОКА_ОТ, до: int = СТРОКА_ДО
                          ) -> list[tuple[float, int, int]]:
        """(мера, длина, начало) лучшей длины для каждой таблицы — как ``tpc.мера_в_кадрах``, но на своих кадрах."""
        k, F = self.k, self.F
        n = k * self.Q
        итог = []
        for т in таблицы:
            биты = ((np.asarray(т)[self.S][..., None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8).reshape(F, n)
            P = np.concatenate([np.zeros((F, 1), np.uint8), np.bitwise_xor.accumulate(биты, axis=1)], axis=1)
            лучшее = (0.0, 0, 0)
            for L in range(от, min(до, n // 2) + 1):
                J = (n + 1 - L) // L
                перекос = (1 - 2 * (P[:, L:L + J * L] ^ P[:, :J * L]).mean(axis=0)) ** 2
                с_ = перекос.reshape(J, L).mean(axis=0)
                о = int(np.argmax(с_))
                мера = (float(с_[о]) - 1 / F) * F * math.sqrt(J / 2)
                if мера > лучшее[0]:
                    лучшее = (мера, L, о)
            итог.append(лучшее)
        return итог


# -- кадры для меры строк ------------------------------------------------------------------------

def символы_кадров(биты: np.ndarray, начала: Sequence[int], длина: int, k: int, фаза: int,
                   *, кадров: int = КАДРОВ_СТРОК) -> tuple[np.ndarray, int] | None:
    """Кадры с данными (без повторов) символами: (кадры × символов, смещение первой границы символа от начала кадра).

    ``фаза`` — граница символа в файле (бит фаза + k·j). Длина кадра должна
    делиться на k (иначе у кадров разная фаза символа).
    """
    from . import tpc  # noqa: PLC0415

    if длина % k:
        return None
    начала = [int(н) for н in начала]
    if not начала:
        return None
    сдвиг = (фаза - начала[0]) % k
    Q = (длина - сдвиг) // k + (1 if сдвиг else 0)
    годные = [н for н in начала if (н - начала[0]) % k == 0 and н + сдвиг + k * Q <= len(биты)]
    if len(годные) < 8:
        return None
    окна = tpc._окна_кадров(биты, годные, длина, 0)
    без = np.flatnonzero(tpc.без_повторов(окна))
    if len(без) < 8:
        return None
    выбор = np.asarray(годные)[без[:кадров]] + сдвиг
    индексы = выбор[:, None] + np.arange(k * Q)[None, :]
    блоки = np.asarray(биты, dtype=np.uint8)[индексы].reshape(len(выбор), Q, k).astype(np.int64)
    return блоки @ (1 << np.arange(k - 1, -1, -1)), сдвиг


# -- поиск -----------------------------------------------------------------------------------------

def все_перестановки(M: int) -> np.ndarray:
    if M > 8:
        raise ValueError("полный перебор — только до 8 точек (8! = 40 320)")
    return np.array(list(itertools.permutations(range(M))), dtype=np.int64)


def _по_классу(класс: Sequence[int], M: int) -> np.ndarray:
    """Все таблицы, переводящие символы класса в метки чётного веса, прочие — в нечётные."""
    вес = _вес(M) % 2
    чётные = [t for t in range(M) if not вес[t]]
    нечётные = [t for t in range(M) if вес[t]]
    вход_ч = list(класс)
    вход_н = [v for v in range(M) if v not in класс]
    итог = []
    for а in itertools.permutations(чётные):
        for б in itertools.permutations(нечётные):
            т = np.zeros(M, np.int64)
            т[вход_ч], т[вход_н] = а, б
            итог.append(т)
    return np.array(итог)


def равноценные(таблица: Sequence[int], M: int) -> list[list[int]]:
    """Таблица и её сдвиги x ⊕ c (инверсии бит метки) — мера строк их не различает."""
    т = np.asarray(таблица, dtype=np.int64)
    return [(т ^ c).tolist() for c in range(M)]


def поиск_строк(кадры: np.ndarray, k: int, *, срок: float | None = None, ход: Ход | None = None,
                лучших: int = 8) -> dict[str, Any] | None:
    """Разметка по строкам кода в кадрах (до 8 точек): этапы А и Б. None — строки не проявились."""
    M = 1 << k
    if M > 8 or M < 4:
        return None
    мера = МераСтрок(кадры, k)
    начало_времени = time.monotonic()
    классы = мера.классы(срок=срок, ход=(lambda д, т: ход(0.8 * д, т)) if ход else None)
    if not классы or классы[0]["отрыв"] < ПОРОГ_СТРОК:
        return None
    лучший = классы[0]
    таблицы = _по_классу(лучший["класс"], M)
    меры = np.full(len(таблицы), -np.inf)
    длины = np.zeros((len(таблицы), 2), np.int64)
    for номер, (длина, начало, _) in enumerate(лучший["кандидаты"]):
        м = мера.оценить(таблицы, длина, начало)
        лучше = м > меры
        меры[лучше], длины[лучше] = м[лучше], (длина, начало)
        if ход:
            ход(0.8 + 0.2 * (номер + 1) / len(лучший["кандидаты"]), "перестановки лучшего класса")
    порядок = np.argsort(-меры, kind="stable")
    вершина = float(меры[порядок[0]])
    # Равные вершине — это класс x ⊕ c (с чётным c) и совпадения; добавляем и нечётные c.
    итог: list[list[int]] = []
    for i in порядок:
        if меры[i] < 0.999 * вершина or len(итог) >= лучших:
            break
        for т in равноценные(таблицы[i], M):
            if т not in итог:
                итог.append(т)
    толпа = np.delete(меры, порядок[:max(1, len(итог) // 2)])
    длина, начало = (int(x) for x in длины[порядок[0]])
    лучший = {**лучший, "длина": длина, "начало": начало}
    return {"мера": "строки", "таблицы": итог[:max(лучших, M)], "оценка": round(вершина, 1),
            "класс": лучший, "второй_класс": классы[1] if len(классы) > 1 else None,
            "следующая": round(float(толпа.max()), 1) if len(толпа) else 0.0,
            "время": round(time.monotonic() - начало_времени, 2),
            "перебрано": f"{len(классы)} классов чётности × {len(таблицы)} перестановок (все {math.factorial(M)})"}


def перебор(мера, M: int, *, срок: float | None = None, ход: Ход | None = None, лучших: int = 8,
            таблицы: np.ndarray | None = None) -> dict[str, Any]:
    """Все перестановки (или данные ``таблицы``) — мерой пачками: лучшие, медиана, разброс, сколько оценено."""
    if таблицы is None:
        таблицы = все_перестановки(M)
    конец = None if срок is None else time.monotonic() + срок
    меры = np.full(len(таблицы), -np.inf)
    сделано = 0
    for с in range(0, len(таблицы), ПАЧКА):
        меры[с:с + ПАЧКА] = мера.оценить(таблицы[с:с + ПАЧКА])
        сделано = min(len(таблицы), с + ПАЧКА)
        if ход:
            ход(сделано / len(таблицы), f"{мера.имя}: {сделано} из {len(таблицы)}")
        if конец is not None and time.monotonic() > конец:
            break
    оценено = меры[:сделано]
    порядок = np.argsort(-оценено, kind="stable")[:лучших]
    медиана = float(np.median(оценено))
    разброс = float(1.4826 * np.median(np.abs(оценено - медиана))) or 1e-9
    return {"таблицы": [таблицы[i].tolist() for i in порядок], "меры": [round(float(оценено[i]), 3) for i in порядок],
            "медиана": round(медиана, 3), "разброс": round(разброс, 4), "оценено": сделано, "всего": len(таблицы),
            "отрыв": round((float(оценено[порядок[0]]) - медиана) / разброс, 1) if сделано else 0.0}


# -- местный поиск (16, 32, 64 точки) ------------------------------------------------------------

def соседи(таблица: np.ndarray) -> np.ndarray:
    """Все таблицы, отличающиеся обменом двух меток."""
    M = len(таблица)
    пары = [(i, j) for i in range(M) for j in range(i + 1, M)]
    итог = np.repeat(таблица[None, :], len(пары), axis=0)
    for n, (i, j) in enumerate(пары):
        итог[n, i], итог[n, j] = таблица[j], таблица[i]
    return итог


def местный_поиск(оценить: Callable[[np.ndarray], np.ndarray], старты: np.ndarray, *, срок: float = 30.0,
                  ход: Ход | None = None, сид: int = 1, отжиг: int = 3) -> dict[str, Any]:
    """Подъём обменами пар с каждого старта; затем отжиг: случайные обмены лучшей и снова подъём.

    ``оценить`` — мера пачки таблиц (B × M). Итог — лучшая таблица, её мера,
    мера стартов и сколько оценено.
    """
    rng = np.random.default_rng(сид)
    начало = time.monotonic()
    конец = начало + срок
    оценок = 0
    лучшая, лучшая_мера = None, -np.inf
    меры_стартов = оценить(старты)
    оценок += len(старты)
    порядок = np.argsort(-меры_стартов, kind="stable")
    попыток = len(порядок) + отжиг

    def подъём(т: np.ndarray, м: float) -> tuple[np.ndarray, float]:
        nonlocal оценок
        while time.monotonic() < конец:
            с_ = соседи(т)
            м_с = оценить(с_)
            оценок += len(с_)
            i = int(np.argmax(м_с))
            if м_с[i] <= м + 1e-9:
                break
            т, м = с_[i], float(м_с[i])
        return т, м

    for номер, i in enumerate(порядок):
        т, м = подъём(старты[i].copy(), float(меры_стартов[i]))
        if м > лучшая_мера:
            лучшая, лучшая_мера = т, м
        if ход:
            ход(min(1.0, max((номер + 1) / попыток, (time.monotonic() - начало) / срок)), f"старт {номер + 1} из {len(порядок)}")
        if time.monotonic() > конец:
            break
    for шаг in range(отжиг):
        if time.monotonic() > конец or лучшая is None:
            break
        т = лучшая.copy()
        for _ in range(max(2, len(т) // 8)):
            i, j = rng.choice(len(т), 2, replace=False)
            т[i], т[j] = т[j], т[i]
        т, м = подъём(т, float(оценить(т[None, :])[0]))
        оценок += 1
        if м > лучшая_мера:
            лучшая, лучшая_мера = т, м
        if ход:
            ход(min(1.0, (len(порядок) + шаг + 1) / попыток), f"отжиг {шаг + 1} из {отжиг}")
    return {"таблица": None if лучшая is None else лучшая.tolist(), "мера": round(float(лучшая_мера), 3),
            "мера_стартов": round(float(меры_стартов.max()), 3), "оценено": оценок,
            "время": round(time.monotonic() - начало, 2)}


def старты_группы(k: int, основы: Sequence[Sequence[int]] = (), *, до: int = 4096, сид: int = 1) -> np.ndarray:
    """Таблицы-старты: основы (таблицы плоскостей) × перестановки бит × инверсии бит метки, без повторов.

    У ФМ основы — повороты и отражения по кругу (натуральный и Грей), у КАМ —
    симметрии квадрата (``ploskost``); больше ``до`` — случайная выборка.
    """
    M = 1 << k
    вес = 1 << np.arange(k - 1, -1, -1)
    метки = в_биты(np.arange(M), k).reshape(M, k)
    итог: dict[tuple, None] = {}
    основы = [np.asarray(о, dtype=np.int64) for о in основы] or [np.arange(M)]
    перестановки = list(itertools.permutations(range(k)))
    for о in основы:
        for п in перестановки:
            переставлено = (метки[о][:, list(п)] @ вес)
            for c in range(M):
                итог.setdefault(tuple((переставлено ^ c).tolist()), None)
    таблицы = np.array(list(итог), dtype=np.int64)
    if len(таблицы) > до:
        таблицы = таблицы[np.random.default_rng(сид).choice(len(таблицы), до, replace=False)]
    return таблицы


def основы_плоскостей(k: int) -> list[list[int]]:
    """Таблицы симметрий созвездия: ФМ — поворот × отражение × Грей/натуральный; КАМ — 8 симметрий квадрата."""
    from . import ploskost  # noqa: PLC0415

    M = 1 << k
    метки = в_биты(np.arange(M), k)
    итог: dict[tuple, None] = {tuple(range(M)): None}
    if k <= 6:
        for код in ("Грей", "натуральный"):
            for r in range(M):
                for отр in (False, True):
                    т = в_символы(ploskost.преобразовать_фм(метки, k, код=код, поворот=r, отражение=отр), k)
                    итог.setdefault(tuple(т.tolist()), None)
    if k % 2 == 0:
        for в in ploskost.варианты(k):
            т = в_символы(ploskost.преобразовать(метки, k, **в), k)
            итог.setdefault(tuple(т.tolist()), None)
    return [list(т) for т in итог]


# -- сводный поиск --------------------------------------------------------------------------------

@dataclass
class Итог:
    """Найденная разметка: таблица принятая метка → истинная и как найдена."""

    таблица: list[int]
    мера: float
    как: str
    подробно: list[str] = field(default_factory=list)
    равноценные: list[list[int]] = field(default_factory=list)
    сведения: dict[str, Any] = field(default_factory=dict)

    def в_словарь(self) -> dict[str, Any]:
        return {"таблица": self.таблица, "мера": self.мера, "как": self.как, "подробно": self.подробно,
                "равноценные": self.равноценные, **self.сведения}


def искать(биты: np.ndarray, k: int, *, мера: str = "авто", кадры: tuple[Sequence[int], int] | None = None,
           фаза: int = 0, срок: float | None = 60.0, ход: Ход | None = None, старты: np.ndarray | None = None,
           лучших: int = 8) -> Итог | None:
    """Слепой поиск разметки: мера «строки» (нужны кадры), «лрп», «байты» или «авто».

    «Авто»: есть кадры — строки; иначе ЛРП (тестовая ПСП), если выделяется, иначе байты.
    У 16+ точек — местный поиск со стартов группы (или данных ``старты``).
    """
    M = 1 << k
    if not 2 <= M <= 256:
        raise ValueError("бит на символ — от 1 до 8")
    начало = time.monotonic()
    if M == 2:
        return Итог([1, 0], 0.0, "у ФМ-2 разметок две: как есть и инверсия",
                    равноценные=[[0, 1], [1, 0]])
    виды = [мера] if мера != "авто" else (["строки"] if кадры else []) + ["лрп", "байты"]
    символы = в_символы(np.asarray(биты), k, фаза)
    for вид in виды:
        осталось = None if срок is None else max(1.0, срок - (time.monotonic() - начало))
        if вид == "строки":
            if not кадры:
                raise ValueError("мера «строки» — по кадрам: нужны начала кадров и длина")
            if M > 8:
                итог = _строки_местно(биты, k, кадры, фаза, осталось, ход, старты)
            else:
                найдено = символы_кадров(np.asarray(биты), кадры[0], кадры[1], k, фаза)
                if найдено is None:
                    continue
                р = поиск_строк(найдено[0], k, срок=осталось, ход=ход, лучших=лучших)
                if р is None:
                    continue
                кл = р["класс"]
                итог = Итог(р["таблицы"][0], р["оценка"], "строки кода в кадрах",
                            [f"перебрано: {р['перебрано']}; кадров с данными — {len(найдено[0])}",
                             f"класс чётности символов {кл['класс']}: строка {кл['длина']} бит с бита {кл['начало']} кадра, "
                             f"отрыв {кл['отрыв']:g} разбросов"
                             + (f" (следующий класс — {р['второй_класс']['отрыв']:g})" if р["второй_класс"] else ""),
                             f"мера строк у лучшей перестановки — {р['оценка']:g}, у лучшей не из её класса x ⊕ c — "
                             f"{р['следующая']:g}; равноценных (инверсии бит метки) — {len(р['таблицы'])}"],
                            равноценные=р["таблицы"], сведения={"строка": кл["длина"], "начало_строки": кл["начало"]})
            if итог is not None:
                итог.сведения["время"] = round(time.monotonic() - начало, 2)
                return итог
            continue
        if M > 8:
            итог = _ряд_местно(символы, k, вид, осталось, ход, старты)
            if итог is not None:
                итог.сведения["время"] = round(time.monotonic() - начало, 2)
                return итог
            continue
        итог = _лрп(символы, k, осталось, ход) if вид == "лрп" else _байты(биты, символы, k, фаза, осталось, ход)
        if итог is not None:
            итог.сведения["время"] = round(time.monotonic() - начало, 2)
            return итог
    return None


def по_классам_инверсии(M: int) -> np.ndarray:
    """Перестановки с таблица[0] = 0 — по одной из каждого класса «x ⊕ c» (у ФМ-8 их 5 040 из 40 320)."""
    return np.array([(0, *п) for п in itertools.permutations(range(1, M))], dtype=np.int64)


def _лрп(символы: np.ndarray, k: int, срок: float | None, ход: Ход | None) -> Итог | None:
    """Тестовая ПСП: линейная сложность по классам x ⊕ c, затем все c у лучших классов."""
    M = 1 << k
    м = МераЛРП(символы, k)
    if not м.отрезки:
        return None                       # поток короче отрезка
    р = перебор(м, M, таблицы=по_классам_инверсии(M), срок=срок, ход=ход, лучших=4)
    if not р["таблицы"]:
        return None
    кандидаты = np.array([np.asarray(т) ^ c for т in р["таблицы"] for c in range(M)], dtype=np.int64)
    меры = м.оценить(кандидаты)
    порядок = np.argsort(-меры, kind="stable")
    сложность = [м.длина / 2 - меры[i] * math.sqrt(м.длина / 4) for i in порядок]
    if сложность[0] > ЛРП_ДОЛЯ * м.длина:
        return None
    лучшая = кандидаты[порядок[0]].tolist()
    равные = [кандидаты[i].tolist() for i, сл in zip(порядок, сложность, strict=True) if сл <= сложность[0] + k]
    return Итог(лучшая, round(float(меры[порядок[0]]), 3), м.имя,
                [f"линейная сложность лучшей разметки — {сложность[0]:.0f} на отрезке {м.длина} бит (у прочих — около "
                 f"{м.длина // 2}); перебрано {р['оценено']} классов «x ⊕ c» из {р['всего']} и все c у лучших "
                 f"(инверсия бит метки прибавляет к ПСП узор с периодом символа: сложность растёт не больше чем на {k})",
                 f"почти равных (сложность до {сложность[0] + k:.0f}) — {len(равные)}: инверсии бит метки"],
                равноценные=равные, сведения={"отрыв": р["отрыв"], "сложность": int(сложность[0])})


#: Полная мера структуры — по стольким битам.
ВЫБОРКА_ПОЛНОЙ = 1 << 17
#: Байтовая мера: сколько лучших классов «x ⊕ c» по дешёвой ступени переоценивать полной мерой (все c).
БАЙТЫ_ЛУЧШИМ = 12
#: Полная мера лучшей разметки должна превышать медиану лучших на столько и быть больше второй в столько раз.
БАЙТЫ_НАД = 0.2
БАЙТЫ_ВО_СКОЛЬКО = 1.5


def _байты(биты: np.ndarray, символы: np.ndarray, k: int, фаза: int, срок: float | None, ход: Ход | None
           ) -> Итог | None:
    """Байтовая структура в две ступени: совпадения окон у всех перестановок, полная мера — у лучших."""
    from . import skrembler  # noqa: PLC0415

    M = 1 << k
    конец = None if срок is None else time.monotonic() + срок
    м = МераБайт(символы[:ВЫБОРКА_БАЙТ], k)
    # Инверсия бит метки (x ⊕ c) меры не меняет: по одной таблице из каждого класса.
    р = перебор(м, M, таблицы=по_классам_инверсии(M), срок=None if конец is None else 0.7 * срок,
                ход=(lambda д, т: ход(0.7 * д, т)) if ход else None, лучших=БАЙТЫ_ЛУЧШИМ)
    выборка = np.asarray(биты[фаза:фаза + ВЫБОРКА_ПОЛНОЙ // k * k])
    оценки = []
    кандидаты = [np.asarray(т) ^ c for т in р["таблицы"] for c in range(M)]
    for номер, т in enumerate(кандидаты):
        оценки.append(skrembler.мера_полная(применить(выборка, k, т)))
        if ход:
            ход(0.7 + 0.3 * (номер + 1) / len(кандидаты), f"полная мера у лучших: {номер + 1} из {len(кандидаты)}")
        if конец is not None and time.monotonic() > конец and номер >= 1:
            break
    if not оценки:
        return None
    порядок = np.argsort(-np.array(оценки), kind="stable")
    лучшая = оценки[порядок[0]]
    # Равные лучшей (обычно — инверсия всех бит: HDLC ищется и в инверсном потоке) — равноценные; вторая — из прочих.
    равные = [кандидаты[i].tolist() for i in порядок if оценки[i] >= лучшая - 1e-9]
    вторая = max((о for о in оценки if о < лучшая - 1e-9), default=0.0)
    середина = float(np.median(оценки))
    if лучшая < середина + БАЙТЫ_НАД or лучшая < БАЙТЫ_ВО_СКОЛЬКО * вторая:
        return None
    таблица = равные[0]
    return Итог(таблица, round(float(лучшая), 3), м.имя,
                [f"первая ступень — совпадения 8-битовых окон у {р['оценено']} классов «x ⊕ c» (все {math.factorial(M)} "
                 f"перестановок: инверсия бит метки меры не меняет); лучший класс — отрыв {р['отрыв']:g} разбросов",
                 f"полная мера структуры (байты, кадры с верной FCS, цикл) у {len(оценки)} лучших: {лучшая:.2f} "
                 f"против {вторая:.2f} у следующей, медиана {середина:.2f}; равных лучшей — {len(равные)}"],
                равноценные=равные, сведения={"отрыв": р["отрыв"]})


#: Поиск без кадров у 16+ точек: стартов (классов группы), раскрываемых соседей на шаге, кандидатов на полную меру.
ПУЧОК_СТАРТОВ = 4
ПУЧОК_РАСКРЫТЬ = 8
ПУЧОК_ПЕРВЫХ = 3
ПУЧОК_ВТОРЫХ = 5
#: Полная мера у пучка — по стольким битам (все инверсии бит метки лучших классов).
ВЫБОРКА_ПУЧКА = 1 << 15


def _ряд_местно(символы: np.ndarray, k: int, вид: str, срок: float | None, ход: Ход | None,
                старты: np.ndarray | None) -> Итог | None:
    """16+ точек без кадров: старты группы → обмены пар (пучком, на два обмена) → полная мера у лучших.

    Дешёвая мера (совпадения окон) верную разметку ставит высоко среди соседей
    старта, но не всегда выше всех таблиц вообще: подъём по ней уходит от
    истины. Поэтому соседи на один и два обмена от лучших стартов оцениваются
    дешёвой мерой; старты, лучшие ``ПУЧОК_ПЕРВЫХ`` соседей на один обмен у каждого
    и лучшие ``ПУЧОК_ВТОРЫХ`` на два — полной мерой структуры
    (байты, кадры с верной FCS, цикл) со всеми инверсиями бит метки x ⊕ c
    (дешёвая мера их не различает).
    «Чутка изменённое» созвездие — один-два обмена меток — так находится.
    """
    from . import skrembler  # noqa: PLC0415

    M = 1 << k
    начало = time.monotonic()
    конец = начало + (срок or 30.0)
    выборка = символы[:ВЫБОРКА_БАЙТ]
    дешёвая = МераБайт(выборка, k)
    группа = старты_группы(k, основы_плоскостей(k), до=1 << 16)
    представители = np.unique(группа ^ группа[:, :1], axis=0)
    меры = дешёвая.оценить(представители)
    отобраны = представители[np.argsort(-меры, kind="stable")[:ПУЧОК_СТАРТОВ]]
    if старты is not None:
        отобраны = np.concatenate([np.asarray(старты, dtype=np.int64), отобраны])
    # Кандидаты на полную меру: сами старты, лучшие соседи на один обмен у каждого и лучшие на два — в целом
    # (дешёвая мера у двух обменов бывает выше истины: им — меньше мест).
    пучок: dict[tuple, float] = {}
    лучшие: list[tuple] = []

    def взять(таблицы: np.ndarray, меры_: np.ndarray, сколько: int) -> None:
        for i in np.argsort(-меры_, kind="stable"):
            ключ = tuple((таблицы[i] ^ таблицы[i][0]).tolist())
            if ключ not in лучшие:
                лучшие.append(ключ)
                сколько -= 1
            if сколько <= 0:
                break

    вторые_все, м2_все = [], []
    for номер, старт in enumerate(отобраны):
        первые = соседи(старт)
        м1 = дешёвая.оценить(первые)
        взять(старт[None, :], дешёвая.оценить(старт[None, :]), 1)
        взять(первые, м1, ПУЧОК_ПЕРВЫХ)
        вторые = np.concatenate([соседи(первые[i]) for i in np.argsort(-м1, kind="stable")[:ПУЧОК_РАСКРЫТЬ]])
        вторые_все.append(вторые)
        м2_все.append(дешёвая.оценить(вторые))
        пучок.update((tuple(т), 0.0) for т in первые)
        if ход:
            ход(0.4 * (номер + 1) / len(отобраны), f"обмены пар от старта {номер + 1} из {len(отобраны)}")
        if time.monotonic() > конец:
            break
    if вторые_все:
        взять(np.concatenate(вторые_все), np.concatenate(м2_все), ПУЧОК_ВТОРЫХ)
        пучок.update((tuple(т), 0.0) for т in np.concatenate(вторые_все))
    выборка_полной = символы[:ВЫБОРКА_ПУЧКА // k]
    кандидаты, полные = [], []
    for номер, т in enumerate(лучшие):
        for c in range(M):
            в = np.array(т, dtype=np.int64) ^ c
            кандидаты.append(в)
            полные.append(skrembler.мера_полная(в_биты(в[выборка_полной], k)))
        if ход:
            ход(0.4 + 0.6 * (номер + 1) / len(лучшие), f"полная мера: класс {номер + 1} из {len(лучшие)}")
        if time.monotonic() > конец and номер >= 1:
            break
    if not полные:
        return None
    исходная = skrembler.мера_полная(в_биты(выборка_полной, k))
    i = int(np.argmax(полные))
    # Равные лучшей (инверсия всех бит — HDLC ищется и в инверсном потоке) — равноценные; вторая — из прочих.
    равные = [кандидаты[j].tolist() for j in np.argsort(-np.array(полные), kind="stable") if полные[j] >= полные[i] - 1e-9]
    вторая = max((о for о in полные if о < полные[i] - 1e-9), default=0.0)
    if полные[i] < исходная + БАЙТЫ_НАД or полные[i] < БАЙТЫ_ВО_СКОЛЬКО * вторая:
        return None
    return Итог(равные[0], round(float(полные[i]), 3), "местный поиск: байтовая структура ряда",
                [f"стартов группы {len(группа)} (симметрии созвездия × перестановки бит × инверсии), классов «x ⊕ c» — "
                 f"{len(представители)}; от {len(отобраны)} лучших по дешёвой мере (совпадения окон) — соседи на один и "
                 f"два обмена пар: {len(пучок)} таблиц, на полную меру — {len(лучшие)} классов",
                 f"полная мера структуры (байты, кадры с верной FCS, цикл) у {len(полные)} таблиц лучших классов (все "
                 f"инверсии бит метки): {полные[i]:.2f} против "
                 f"{вторая:.2f} у следующей; поток как есть — {исходная:.2f}; равных лучшей — {len(равные)}; "
                 f"{time.monotonic() - начало:.1f} с"], равноценные=равные)


def чётность_меток(таблицы: np.ndarray, M: int) -> np.ndarray:
    """Класс чётности каждой таблицы: h[v] = чётность веса метки таблица[v], с точностью до дополнения (h[0] = 0)."""
    h = (_вес(M)[np.asarray(таблицы, dtype=np.int64)] % 2).astype(np.uint8)
    return h ^ h[:, :1]


def _строки_местно(биты: np.ndarray, k: int, кадры: tuple[Sequence[int], int], фаза: int, срок: float | None,
                   ход: Ход | None, старты: np.ndarray | None) -> Итог | None:
    """16+ точек в кадрах: группа и соседи на один обмен → классы чётности → точная мера → обмены пар.

    У «чутка изменённого» созвездия (один-два обмена меток) старт группы строк
    не открывает: почти в каждой строке есть неверный символ. Поэтому классы
    чётности меток (от них зависит чётность целых символов в окне) берутся у
    стартов группы и у всех их соседей на один обмен; этап А по ним даёт класс,
    длину и начало строки; таблицы этого класса — точной мерой; затем подъём
    обменами пар и отжиг на найденной длине.
    """
    M = 1 << k
    начало_ = time.monotonic()
    конец = начало_ + (срок or 60.0)
    найдено = символы_кадров(np.asarray(биты), кадры[0], кадры[1], k, фаза, кадров=64)
    if найдено is None:
        return None
    мера = МераСтрок(найдено[0], k)
    группа = старты_группы(k, основы_плоскостей(k), до=1 << 16)
    представители = np.unique(группа ^ группа[:, :1], axis=0)
    if старты is not None:
        представители = np.concatenate([np.asarray(старты, dtype=np.int64), представители])
    кандидаты = np.concatenate([представители] + [соседи(т) for т in представители])
    h = чётность_меток(кандидаты, M)
    классы_h, обратно = np.unique(h, axis=0, return_inverse=True)
    обратно = np.ravel(обратно)
    if ход:
        ход(0.0, f"классов чётности у группы и соседей: {len(классы_h)}")
    классы = мера.классы(только=классы_h, срок=0.6 * (конец - time.monotonic()),
                         ход=(lambda д, т: ход(0.6 * д, т)) if ход else None)
    if not классы or классы[0]["отрыв"] < ПОРОГ_СТРОК:
        return None
    лучший = классы[0]
    h_лучший = np.array([0 if v in лучший["класс"] else 1 for v in range(M)], np.uint8)
    h_лучший ^= h_лучший[0]
    свои = кандидаты[np.flatnonzero((классы_h[обратно] == h_лучший).all(axis=1))]
    меры = np.full(len(свои), -np.inf)
    длины = np.zeros((len(свои), 2), np.int64)
    for длина, начало, _ in лучший["кандидаты"]:
        м = мера.оценить(свои, длина, начало)
        лучше = м > меры
        меры[лучше], длины[лучше] = м[лучше], (длина, начало)
    i = int(np.argmax(меры))
    длина, начало = (int(x) for x in длины[i])
    р = местный_поиск(lambda т: мера.оценить(т, длина, начало), свои[np.argsort(-меры, kind="stable")[:4]],
                      срок=max(1.0, конец - time.monotonic()), ход=(lambda д, т: ход(0.6 + 0.4 * д, т)) if ход else None)
    if р["таблица"] is None or р["мера"] < ПОРОГ_СТРОК:
        return None
    return Итог(р["таблица"], р["мера"], "местный поиск: строки кода в кадрах",
                [f"классы чётности меток у {len(представители)} классов группы (симметрии × перестановки бит × инверсии) и "
                 f"их соседей на один обмен: {len(классы_h)}; лучший — строка {длина} бит с бита {начало}, отрыв "
                 f"{лучший['отрыв']:g} разбросов",
                 f"таблиц этого класса среди кандидатов — {len(свои)}, лучшая — {float(меры[i]):g}; обмены пар и отжиг: "
                 f"{р['мера']:g}; оценено {р['оценено']} таблиц; {time.monotonic() - начало_:.1f} с"],
                равноценные=равноценные(р["таблица"], M), сведения={"строка": длина, "начало_строки": начало})


# -- поиски в фоне (для окна): ход, срок, остановка -----------------------------------------------

class Остановлено(Exception):
    """Поиск остановлен из окна."""


class Поиски:
    """Слепые поиски в фоне: у каждого — ход (доля и слова), прошло, осталось (оценка), итог или ошибка.

    У одного человека — один поиск: новый останавливает прежний. Готовые хранятся
    ``ХРАНИТЬ`` секунд, всего — не больше ``ВСЕГО``.
    """

    ХРАНИТЬ = 600.0
    ВСЕГО = 32

    def __init__(self) -> None:
        import threading  # noqa: PLC0415

        self._lock = threading.Lock()
        self._все: dict[str, dict[str, Any]] = {}

    def начать(self, владелец: int, задача: Callable[[Ход], Any], описание: str = "") -> str:
        import secrets  # noqa: PLC0415
        import threading  # noqa: PLC0415

        ид = secrets.token_hex(6)
        запись = {"ид": ид, "владелец": владелец, "описание": описание, "доля": 0.0, "ход": "начат",
                  "начало": time.monotonic(), "конец": None, "итог": None, "ошибка": "", "стоп": False}
        with self._lock:
            self._прибрать()
            for другая in self._все.values():
                if другая["владелец"] == владелец and другая["конец"] is None:
                    другая["стоп"] = True
            self._все[ид] = запись

        def ход(доля: float, текст: str) -> None:
            if запись["стоп"]:
                raise Остановлено
            запись["доля"], запись["ход"] = max(запись["доля"], min(1.0, float(доля))), текст

        def выполнить() -> None:
            try:
                запись["итог"] = задача(ход)
            except Остановлено:
                запись["ошибка"] = "остановлено"
            except (ValueError, MemoryError) as ошибка:
                запись["ошибка"] = str(ошибка) or ошибка.__class__.__name__
            finally:
                запись["конец"] = time.monotonic()

        threading.Thread(target=выполнить, daemon=True, name="reportgen-razmetka").start()
        return ид

    def _прибрать(self) -> None:
        сейчас = time.monotonic()
        for ид in [и for и, з in self._все.items() if з["конец"] is not None and сейчас - з["конец"] > self.ХРАНИТЬ]:
            del self._все[ид]
        while len(self._все) >= self.ВСЕГО:
            старейший = min(self._все, key=lambda и: self._все[и]["начало"])
            self._все[старейший]["стоп"] = True
            del self._все[старейший]

    def состояние(self, ид: str, владелец: int) -> dict[str, Any]:
        with self._lock:
            запись = self._все.get(ид)
        if запись is None or запись["владелец"] != владелец:
            raise KeyError(ид)
        прошло = (запись["конец"] or time.monotonic()) - запись["начало"]
        доля = запись["доля"]
        осталось = None if запись["конец"] is not None or доля <= 0.01 else прошло * (1 - доля) / доля
        return {"ид": ид, "описание": запись["описание"], "доля": round(доля, 4), "ход": запись["ход"],
                "прошло": round(прошло, 1), "осталось": None if осталось is None else round(осталось, 1),
                "готово": запись["конец"] is not None, "итог": запись["итог"], "ошибка": запись["ошибка"]}

    def остановить(self, ид: str, владелец: int) -> None:
        with self._lock:
            запись = self._все.get(ид)
            if запись is None or запись["владелец"] != владелец:
                raise KeyError(ид)
            запись["стоп"] = True


ПОИСКИ = Поиски()
