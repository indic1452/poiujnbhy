# -*- coding: utf-8 -*-
"""Коды Рида — Соломона и БЧХ вслепую: корни порождающего многочлена.

Циклический код — это слова, делящиеся на порождающий многочлен g(x).
Значит, у каждого кодового слова c(x) те же корни, что у g(x). У БЧХ и
Рида — Соломона корни g(x) — подряд идущие степени примитивного элемента
поля: α^b, α^(b+1), …, α^(b+2t−1). Отсюда слепое опознание: вычисляем
значения слов во всех элементах поля GF(2^m) и ищем общие нули. Их число
— 2t (у РС это ровно n − k), первая степень — b (fcr), а поле задаётся
примитивным многочленом, который тоже неизвестен: перебираем все
примитивные многочлены степени m — их немного, и они не выписываются по
памяти, а порождаются и проверяются здесь же.

У слова с ошибками значения в корнях ненулевые (это и есть синдромы),
поэтому корнем считается элемент, где зануляется большинство слов, — метод
терпит ошибки линии.

- БЧХ: символы — биты, слово длиной n ≤ 2^m − 1 (укороченное — меньше);
- РС: символы — m-битовые (обычно байты), слово — n символов, n ≤ 2^m − 1.
"""

from __future__ import annotations

from functools import lru_cache
from typing import Dict, List, Sequence, Tuple

import numpy as np

#: Доля слов, зануляющихся в элементе поля, чтобы считать его корнем (у двоичного кода: там
#: и не корень зануляет до половины слов — α⁰ = 1 у слов чётного веса).
КОРЕНЬ_ОТ = 0.5
#: То же для кода РС над GF(2^m), m ≥ 4: не корень зануляет слово с вероятностью 2^−m, так что
#: корень виден и тогда, когда ошибки есть в большей части слов.
КОРЕНЬ_РС_ОТ = 0.15


def _степень_многочлена(p: int) -> int:
    return p.bit_length() - 1


def _умножить_по_модулю(a: int, b: int, p: int) -> int:
    m = _степень_многочлена(p)
    итог = 0
    while b:
        if b & 1:
            итог ^= a
        b >>= 1
        a <<= 1
        if a >> m & 1:
            a ^= p
    return итог


def примитивный(p: int) -> bool:
    """Многочлен p степени m примитивен: порядок x по модулю p равен 2^m − 1."""
    m = _степень_многочлена(p)
    if m < 1 or not p & 1:
        return False
    порядок = (1 << m) - 1
    x, степень = 1, 0
    while True:
        x = _умножить_по_модулю(x, 2, p)
        степень += 1
        if x == 1:
            return степень == порядок
        if степень > порядок:
            return False


@lru_cache(maxsize=None)
def примитивные(m: int) -> Tuple[int, ...]:
    return tuple(p for p in range(1 << m, 1 << (m + 1)) if примитивный(p))


@lru_cache(maxsize=32)
def поле(p: int) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """(степени α, логарифмы, таблица умножения) для GF(2^m) по многочлену p."""
    m = _степень_многочлена(p)
    q = 1 << m
    степень = np.zeros(2 * q, dtype=np.int64)
    логарифм = np.zeros(q, dtype=np.int64)
    x = 1
    for i in range(q - 1):
        степень[i] = x
        логарифм[x] = i
        x = _умножить_по_модулю(x, 2, p)
    степень[q - 1:2 * q - 2] = степень[:q - 1]
    a = np.arange(q)
    умножение = степень[(логарифм[a][:, None] + логарифм[a][None, :]) % (q - 1)]
    умножение[0, :] = 0
    умножение[:, 0] = 0
    тип = np.uint8 if q <= 256 else np.uint16
    return степень, логарифм, умножение.astype(тип)


def значения(слова: np.ndarray, p: int) -> np.ndarray:
    """c(α^j) для каждого слова (строка — символы от старшей степени) и j = 0…q−2."""
    степень, _, умножение = поле(p)
    q = len(умножение)
    точки = степень[:q - 1]
    M, n = слова.shape
    S = np.zeros((M, q - 1), dtype=умножение.dtype)
    for i in range(n):
        S = умножение[S, точки[None, :]] ^ слова[:, i:i + 1].astype(умножение.dtype)
    return S


def общие_корни(слова: np.ndarray, p: int, *, от: float = КОРЕНЬ_ОТ) -> Tuple[List[int], float]:
    """Степени j, где зануляется не меньше доли ``от`` слов, и средняя доля зануления в них."""
    нули = (значения(слова, p) == 0).mean(axis=0)
    # У настоящих корней доля зануления одна и та же — доля слов без ошибок.
    # Случайный «корень» даёт около половины: например, α⁰ = 1 зануляет слово
    # чётного веса, а таких половина. Поэтому порог — не ниже 0,8 от лучшего.
    порог = max(от, 0.8 * float(нули.max()))
    корни = [int(j) for j in np.flatnonzero(нули >= порог)]
    return корни, float(нули[корни].mean()) if корни else 0.0


def _подряд_с_шагом(корни: List[int], q1: int) -> Tuple[int, int, int]:
    """Самая длинная цепочка корней β^b … β^(b+длина−1), β = α^шаг: (b, длина, шаг).

    Порождающий многочлен бывает задан корнями не подряд идущих степеней α, а
    степеней другого примитивного элемента (у CCSDS — α^11). Перебираются все шаги,
    взаимно простые с q − 1; при равной длине — меньший шаг (обычно 1).
    """
    from math import gcd  # noqa: PLC0415
    лучшее = (0, 0, 1)
    for шаг in range(1, q1):
        if gcd(шаг, q1) != 1:
            continue
        обратный = pow(шаг, -1, q1)
        b, длина = _подряд([(е * обратный) % q1 for е in корни], q1)
        if длина > лучшее[1]:
            лучшее = (b, длина, шаг)
    return лучшее


def _подряд(корни: List[int], q1: int) -> Tuple[int, int]:
    """Самая длинная цепочка подряд идущих степеней (по кругу): (начало, длина)."""
    множество = set(корни)
    лучшее = (0, 0)
    for b in корни:
        if (b - 1) % q1 in множество:
            continue
        длина = 0
        while (b + длина) % q1 in множество and длина < q1:
            длина += 1
        лучшее = max(лучшее, (b, длина), key=lambda х: х[1])
    return лучшее


def опознать(слова: np.ndarray, m: int, *, двоичный: bool) -> Dict | None:
    """Перебор примитивных многочленов степени m: поле, корни, fcr, t."""
    лучшее = None
    от = КОРЕНЬ_ОТ if двоичный or m < 4 else КОРЕНЬ_РС_ОТ
    for p in примитивные(m):
        корни, доля = общие_корни(слова, p, от=от)
        if not корни:
            continue
        b, подряд, шаг = _подряд_с_шагом(корни, (1 << m) - 1)
        if лучшее is None or (подряд, доля) > (лучшее["подряд"], лучшее["доля"]):
            лучшее = {"многочлен": p, "корни": корни, "fcr": b, "подряд": подряд,
                      "доля": доля, "m": m, "шаг": шаг}
    if лучшее is None or лучшее["подряд"] < 2:
        return None
    n = слова.shape[1]
    if двоичный:
        # У двоичного кода корни идут циклотомическими классами: число корней
        # — это n − k, а конструктивное расстояние — подряд идущие + 1.
        лучшее["вид"] = "БЧХ"
        лучшее["k"] = n - len(лучшее["корни"])
        лучшее["t"] = лучшее["подряд"] // 2
    else:
        лучшее["вид"] = "Рида — Соломона"
        лучшее["k"] = n - len(лучшее["корни"])
        лучшее["t"] = len(лучшее["корни"]) // 2
    лучшее["n"] = n
    return лучшее


def в_символы(биты: np.ndarray, m: int) -> np.ndarray:
    """Слова из бит (M × n·m) → символы (M × n), старший бит символа первым."""
    M, L = биты.shape
    n = L // m
    веса = 1 << np.arange(m - 1, -1, -1)
    return (биты[:, :n * m].reshape(M, n, m) * веса).sum(axis=2)


# -- исправление ошибок: Берлекэмп — Мэсси, поиск Ченя, формула Форни ----------------------
#
# Код задаётся полем (многочлен p), корнями порождающего многочлена β^fcr … β^(fcr+2t−1),
# где β = α^шаг (обычно шаг 1; у CCSDS корни — степени α^11), и длиной слова n ≤ 2^m − 1
# (укороченный код — меньше: старшие символы — невидимые нули). Слово — строка символов от
# старшей степени (первый переданный символ — коэффициент при x^(n−1)).
#
# Синдромы S_j = r(β^(fcr+j)) считаются для всех слов сразу; у слова с ошибками
# Берлекэмп — Мэсси даёт многочлен локаторов Λ(x) = Π(1 − X_k·x), его корни ищутся
# перебором (Ченя) по местам слова, значения ошибок — по Форни:
# Y_k = X_k^(1−fcr) · Ω(X_k⁻¹) / Λ′(X_k⁻¹), Ω(x) = S(x)·Λ(x) mod x^(2t). У двоичного
# кода (БЧХ) значение ошибки — 1. Исправление проверяется: синдромы исправленного
# слова — нули; иначе слово оставляется как есть и считается неисправимым.


@lru_cache(maxsize=32)
def _таблицы(p: int) -> Tuple[Tuple[int, ...], Tuple[int, ...], int]:
    """Степени (2q) и логарифмы (q) элементов GF(2^m) — списками для скалярной арифметики."""
    степень, логарифм, умножение = поле(p)
    return tuple(степень.tolist()), tuple(логарифм.tolist()), len(умножение) - 1


def синдромы(слова: np.ndarray, p: int, fcr: int, корней: int, шаг: int = 1) -> np.ndarray:
    """S_j = c(β^(fcr+j)), j = 0 … корней−1, β = α^шаг, для каждого слова (схема Горнера)."""
    степень, _, умножение = поле(p)
    Q = len(умножение) - 1
    точки = степень[(шаг * (fcr + np.arange(корней))) % Q]
    слова = np.asarray(слова)
    S = np.zeros((len(слова), корней), dtype=умножение.dtype)
    for i in range(слова.shape[1]):
        S = умножение[S, точки[None, :]] ^ слова[:, i:i + 1].astype(умножение.dtype)
    return S


def берлекэмп_мэсси_поле(S: Sequence[int], p: int) -> Tuple[List[int], int]:
    """Многочлен локаторов ошибок Λ (Λ[0] = 1) и его степень по синдромам над GF(2^m)."""
    степень, логарифм, Q = _таблицы(p)

    def умн(a: int, b: int) -> int:
        return 0 if not a or not b else степень[логарифм[a] + логарифм[b]]

    C, B = [1], [1]
    L, m, b = 0, 1, 1
    for n in range(len(S)):
        d = S[n]
        for i in range(1, min(L, len(C) - 1) + 1):
            d ^= умн(C[i], S[n - i])
        if not d:
            m += 1
            continue
        коэф = степень[(логарифм[d] - логарифм[b]) % Q]
        прежний = C[:]
        if len(C) < len(B) + m:
            C += [0] * (len(B) + m - len(C))
        for i, bi in enumerate(B):
            C[i + m] ^= умн(коэф, bi)
        if 2 * L <= n:
            L, B, b, m = n + 1 - L, прежний, d, 1
        else:
            m += 1
    while len(C) > 1 and not C[-1]:
        C.pop()
    return C, L


def _исправить_слово(слово: np.ndarray, S: Sequence[int], p: int, fcr: int, шаг: int,
                     двоичный: bool) -> int:
    """Исправить одно слово по его синдромам (на месте): число исправленных символов или −1."""
    степень, логарифм, Q = _таблицы(p)
    Λ, L = берлекэмп_мэсси_поле(S, p)
    n = len(слово)
    if not L or 2 * L > len(S) or len(Λ) - 1 != L:
        return -1
    степени = np.asarray(степень)
    e = np.arange(n)
    значение = np.zeros(n, dtype=np.int64)
    for i, c in enumerate(Λ):
        if c:
            значение ^= степени[(логарифм[c] - шаг * e * i) % Q]
    места = np.flatnonzero(значение == 0)                 # степени e: X = β^e
    if len(места) != L:
        return -1

    def умн(a: int, b: int) -> int:
        return 0 if not a or not b else степень[логарифм[a] + логарифм[b]]

    def в_точке(многочлен: Sequence[int], x_лог: int) -> int:
        итог = 0
        for i, c in enumerate(многочлен):
            if c:
                итог ^= степень[(логарифм[c] + x_лог * i) % Q]
        return итог

    Ω = [0] * len(S)
    for k in range(len(S)):
        for i in range(min(k, L) + 1):
            Ω[k] ^= умн(S[k - i], Λ[i])
    производная = [Λ[i] if i % 2 else 0 for i in range(1, len(Λ))]
    for e_ in места.tolist():
        x_обр = (-шаг * e_) % Q                              # log X⁻¹
        if двоичный:
            слово[n - 1 - e_] ^= 1
            continue
        знаменатель = в_точке(производная, x_обр)
        if not знаменатель:
            return -1
        числитель = в_точке(Ω, x_обр)
        if not числитель:
            return -1
        # Y = X^(1−fcr) · Ω(X⁻¹) / Λ′(X⁻¹)
        лог_y = (шаг * e_ * (1 - fcr) + логарифм[числитель] - логарифм[знаменатель]) % Q
        слово[n - 1 - e_] ^= степень[лог_y]
    return L


def исправить(слова: np.ndarray, p: int, fcr: int, корней: int, шаг: int = 1, *,
              двоичный: bool = False) -> Tuple[np.ndarray, np.ndarray]:
    """Исправить слова кода РС (символы) или БЧХ (биты): (исправленные, исправлено в слове).

    ``исправлено`` — число исправленных символов (битов) в слове, −1 — слово
    неисправимо (оставлено как есть). Корректирующая способность — корней // 2.
    """
    слова = np.array(слова, dtype=np.int64)
    S = синдромы(слова, p, fcr, корней, шаг)
    исправлено = np.zeros(len(слова), dtype=np.int64)
    плохие = np.flatnonzero(S.any(axis=1))
    for i in плохие.tolist():
        копия = слова[i].copy()
        число = _исправить_слово(копия, S[i].tolist(), p, fcr, шаг, двоичный)
        if число > 0:
            if синдромы(копия[None, :], p, fcr, корней, шаг).any():
                число = -1
            else:
                слова[i] = копия
        исправлено[i] = число if число > 0 else -1
    return слова, исправлено


def закодировать_рс(данные: Sequence[int], p: int, fcr: int, корней: int, шаг: int = 1) -> List[int]:
    """Систематическое слово РС: данные и проверочные — остаток D(x)·x^корней по g(x) = Π (x − β^(fcr+j)).

    Первый символ — старший коэффициент (как у libfec и у ``синдромы``).
    """
    степень, логарифм, Q = _таблицы(p)

    def умн(a: int, b: int) -> int:
        return 0 if not a or not b else степень[логарифм[a] + логарифм[b]]

    g = [1]
    for j in range(корней):
        корень = степень[(шаг * (fcr + j)) % Q]
        g = [a ^ умн(b, корень) for a, b in zip(g + [0], [0] + g)]      # g(x) · (x + корень)
    остаток = [0] * корней
    for d in данные:
        обратная = d ^ остаток[0]
        остаток = остаток[1:] + [0]
        if обратная:
            for i in range(корней):
                остаток[i] ^= умн(обратная, g[i + 1])
    return list(данные) + остаток


def исправить_со_стираниями(слово: Sequence[int], стирания: Sequence[int], p: int, fcr: int, корней: int,
                            шаг: int = 1) -> Tuple[List[int], int]:
    """Исправить слово РС с известными местами стираний: (слово, исправлено символов) или (слово, −1).

    Стёртые символы считаются нулями; ошибок e и стираний f исправимо, пока 2e + f ≤ корней.
    Синдромы Форни T(x) = S(x)·Γ(x) mod x^корней без первых f, где Γ — многочлен стираний;
    по ним — многочлен ошибок Λ (Берлекэмп — Мэсси); Ψ = Λ·Γ; значения — формулой Форни.
    """
    степень, логарифм, Q = _таблицы(p)

    def умн(a: int, b: int) -> int:
        return 0 if not a or not b else степень[логарифм[a] + логарифм[b]]

    def произведение(a: Sequence[int], b: Sequence[int]) -> List[int]:
        итог = [0] * (len(a) + len(b) - 1)
        for i, x in enumerate(a):
            for j, y in enumerate(b):
                итог[i + j] ^= умн(x, y)
        return итог

    def в_точке(многочлен: Sequence[int], x_лог: int) -> int:
        итог = 0
        for i, c in enumerate(многочлен):
            if c:
                итог ^= степень[(логарифм[c] + x_лог * i) % Q]
        return итог

    n = len(слово)
    слово = list(слово)
    стирания = sorted(set(стирания))
    for i in стирания:
        слово[i] = 0
    f = len(стирания)
    S = синдромы(np.array([слово]), p, fcr, корней, шаг)[0].tolist()
    if not any(S):                                                       # быстрый путь: ошибок нет
        return слово, 0
    Γ = [1]
    for i in стирания:
        Γ = произведение(Γ, [1, степень[(шаг * (n - 1 - i)) % Q]])
    Θ = произведение(S, Γ)[:корней]
    T = Θ[f:]
    Λ, L = берлекэмп_мэсси_поле(T, p)
    if 2 * L + f > корней or len(Λ) - 1 != L:                           # и f > корней — тоже здесь
        return слово, -1
    Ψ = произведение(Λ, Γ)
    места = [e for e in range(n) if в_точке(Ψ, (-шаг * e) % Q) == 0]       # X = β^e — корни Ψ(X⁻¹)
    if len(места) < L + f:                                               # корней не больше степени Ψ
        return слово, -1
    Ω = произведение(S, Ψ)[:корней]
    производная = [Ψ[i] if i % 2 else 0 for i in range(1, len(Ψ))]
    исправлено = 0
    for e in места:
        x_обр = (-шаг * e) % Q
        знаменатель = в_точке(производная, x_обр)
        if not знаменатель:
            return слово, -1
        числитель = в_точке(Ω, x_обр)
        if not числитель:
            continue                                                     # стёртый символ был нулём
        лог_y = (шаг * e * (1 - fcr) + логарифм[числитель] - логарифм[знаменатель]) % Q
        слово[n - 1 - e] ^= степень[лог_y]
        исправлено += 1
    if синдромы(np.array([слово]), p, fcr, корней, шаг).any():         # страховка, как у ``исправить``
        return слово, -1
    return слово, исправлено


def итог_словами(исправлено: np.ndarray, единиц: str, на: str, всего: int, *,
                 в_чём: str = "словах", чего: str = "слов") -> Tuple[str, float]:
    """Итог исправления одной строкой и доля ошибок в линии до декодирования (по исправленным).

    ``исправлено`` — по слову: сколько исправлено, −1 — неисправимо; ``единиц`` —
    «байт», «бит», «символов»; ``на`` — единица доли; ``всего`` — всего единиц в
    словах. Если ошибок не было — так и сказано: исправлять было нечего.
    """
    число = int(исправлено[исправлено > 0].sum())
    неисправимых = int((исправлено < 0).sum())
    ошибок = число / max(1, всего)
    if not число and not неисправимых:
        return f"ошибок нет: синдромы нулевые у всех {len(исправлено)} {чего} — исправлять нечего", 0.0
    return (f"исправлено {число} {единиц} в {int((исправлено > 0).sum())} {в_чём} из {len(исправлено)}; "
            f"неисправимых (ошибка обнаружена, но не исправлена) — {неисправимых}; ошибок в линии до "
            f"декодирования ≈ {ошибок:.1e} на {на} (по исправленным — оценка снизу)", ошибок)

