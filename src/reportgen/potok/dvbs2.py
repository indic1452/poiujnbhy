def _многочлен(строка: str) -> int:
    """Коэффициенты от младшей степени → целое (бит k — коэффициент при x^k)."""
    return sum(1 << k for k, ч in enumerate(строка) if ч == "1")


def _умножить(a: int, b: int) -> int:
    итог = 0
    while b:
        if b & 1:
            итог ^= a
        a <<= 1
        b >>= 1
    return итог


@cache
def порождающий(короткий: bool, t: int) -> int:
    """g(x) кода БЧХ DVB-S2: произведение первых t минимальных многочленов."""
    g = 1
    for строка in (_КОРОТКИЕ if короткий else _НОРМАЛЬНЫЕ)[:t]:
        g = _умножить(g, _многочлен(строка))
    return g


