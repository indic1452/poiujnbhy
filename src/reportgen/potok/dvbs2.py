"""DVB-S2/S2X после LDPC: внешний код БЧХ, кадр BBFRAME, пакеты TS и GSE → IP.

Цепочка передатчика (ETSI EN 302 307-1, разд. 5): пакеты TS или GSE →
BBFRAME (заголовок BBHEADER 80 бит с CRC-8 и поле данных) → скремблер BB
(ПСП 1 + x¹⁴ + x¹⁵, начальное 100101010000000, заново в каждом кадре) →
внешний код БЧХ (kbch → nbch бит) → LDPC. После снятия LDPC в потоке — слова
БЧХ по nbch бит. Разбор идёт обратно:

1. **Длина слова БЧХ** — по заголовку: снятый скремблер в начале каждого
   слова даёт BBHEADER с верной CRC-8 (x⁸+x⁷+x⁶+x⁴+x²+1). Случайно CRC-8
   сходится раз на 256 — а у настоящего потока у каждого кадра.
2. **Код БЧХ** — порождающий многочлен (произведение 8, 10 или 12
   минимальных многочленов над GF(2¹⁶), у короткого кадра — 12 над GF(2¹⁴)):
   остаток слова от деления на него — нуль. Ненулевой — ошибки: исправление
   (Берлекэмп — Мэсси, Ченя) до t = 12/10/8 бит на слово.
3. **BBHEADER**: MATYPE (TS/GS, SIS/MIS, CCM/ACM, ISSYI, NPD, RO), ISI, UPL,
   DFL, SYNC, SYNCD — поле данных длиной DFL.
4. **TS** (TS/GS = 11): поле данных — пакеты по 188 байт, синхробайт каждого
   заменён CRC-8 предыдущего пакета; SYNCD — расстояние в битах до первого
   целого пакета. Синхробайт 0x47 возвращается, CRC-8 сверяется.
5. **GSE** (TS/GS = 01, ETSI TS 102 606-1): пакеты с заголовком S, E, LT,
   длина; фрагменты (ID фрагмента, полная длина, CRC-32 MPEG-2 у последнего)
   собираются; тип протокола — EtherType (0x0800 — IPv4, 0x86DD — IPv6).

Многочлены и длины — из GNU Radio gr-dtv (dvb_bch_bb_impl.cc), поля
заголовка — из gr-dtv (dvb_bbheader_bb_impl.cc) и Wireshark
(packet-dvb-s2-bb.c).
"""

