def остаток(биты: np.ndarray, g: int) -> int:
    """Остаток от деления слова (первый бит — старшая степень) на g(x) над GF(2)."""
    r = g.bit_length() - 1
    слово = int.from_bytes(np.packbits(np.asarray(биты, dtype=np.uint8)).tobytes(), "big")
    слово >>= (-len(биты)) % 8
    while слово.bit_length() > r:
        слово ^= g << (слово.bit_length() - 1 - r)
    return слово


def закодировать(данные: np.ndarray, код: Код) -> np.ndarray:
    """Систематический кодер БЧХ (для проверок): данные kbch бит + проверочные n − k."""
    r = код.nbch - код.kbch
    п = остаток(np.concatenate([данные, np.zeros(r, np.uint8)]), код.g)
    проверка = np.array([(п >> (r - 1 - i)) & 1 for i in range(r)], dtype=np.uint8)
    return np.concatenate([np.asarray(данные, dtype=np.uint8), проверка])


# -- исправление ошибок (двоичный БЧХ над GF(2^m)) -------------------------------------------

@lru_cache(maxsize=2)
def _поле(p: int) -> tuple[np.ndarray, np.ndarray]:
    """Таблицы степеней (удвоенная длина — без взятия по модулю) и логарифмов GF(2^m)."""
    m = p.bit_length() - 1
    Q = (1 << m) - 1
    степень = np.zeros(2 * Q, dtype=np.int64)
    логарифм = np.zeros(Q + 1, dtype=np.int64)
    x = 1
    for i in range(Q):
        степень[i] = x
        логарифм[x] = i
        x <<= 1
        if x >> m:
            x ^= p
    степень[Q:] = степень[:Q]
    return степень, логарифм


def исправить_бчх(слово: np.ndarray, код: Код) -> tuple[np.ndarray, int]:
    """Двоичный БЧХ: синдромы S1…S2t, Берлекэмп — Мэсси, поиск Ченя. (слово, исправлено | −1).

    Первый бит слова — старшая степень (как у кодера gr-dtv); укороченный код —
    тот же, что полный с нулями впереди, поэтому степени считаются от конца слова.
    """
    p = ПОЛЕ_КОРОТКОГО if код.короткий else ПОЛЕ_НОРМАЛЬНОГО
    степень, логарифм = _поле(p)
    Q = len(логарифм) - 1
    n = len(слово)
    степени = (n - 1 - np.flatnonzero(слово)).astype(np.int64)
    S = [int(np.bitwise_xor.reduce(степень[(j * степени) % Q])) if len(степени) else 0
         for j in range(1, 2 * код.t + 1)]
    if not any(S):
        return слово, 0

    def умн(a: int, b: int) -> int:
        return 0 if not a or not b else int(степень[логарифм[a] + логарифм[b]])

    # Берлекэмп — Мэсси над GF(2^m).
    C, B, L, m_, b = [1], [1], 0, 1, 1
    for k in range(len(S)):
        d = S[k]
        for i in range(1, L + 1):
            if i < len(C):
                d ^= умн(C[i], S[k - i])
        if not d:
            m_ += 1
            continue
        коэф = int(степень[(логарифм[d] - логарифм[b]) % Q])
        прежний = C[:]
        C += [0] * max(0, len(B) + m_ - len(C))
        for i, bi in enumerate(B):
            C[i + m_] ^= умн(коэф, bi)
        if 2 * L <= k:
            L, B, b, m_ = k + 1 - L, прежний, d, 1
        else:
            m_ += 1
    while len(C) > 1 and not C[-1]:
        C.pop()
    if L > код.t or len(C) - 1 != L:
        return слово, -1
    # Поиск Ченя: ошибка в степени d, если Λ(α^(−d)) = 0.
    d = np.arange(n, dtype=np.int64)[::-1]                # степень бита i — n − 1 − i
    сумма = np.zeros(n, dtype=np.int64)
    for k, ck in enumerate(C):
        if ck:
            сумма ^= степень[(логарифм[ck] - k * d) % Q]
    места = np.flatnonzero(сумма == 0)
    if len(места) != L:
        return слово, -1
    исправленное = слово.copy()
    исправленное[места] ^= 1
    return исправленное, L


# -- скремблер BB и CRC-8 -----------------------------------------------------------------

@lru_cache(maxsize=1)
def _псп() -> np.ndarray:
    """ПСП скремблера BB на нормальный кадр: 1 + x¹⁴ + x¹⁵, начальное 100101010000000 (gr-dtv)."""
    sr, итог = 0x4A80, np.empty(64800, dtype=np.uint8)
    for i in range(64800):
        b = (sr ^ (sr >> 1)) & 1
        итог[i] = b
        sr = (sr >> 1) | (0x4000 if b else 0)
    return итог


def скремблер(биты: np.ndarray) -> np.ndarray:
    """Снять (или наложить — операция та же) скремблер BB с кадра BBFRAME."""
    биты = np.asarray(биты, dtype=np.uint8)
    return биты ^ _псп()[:len(биты)]


def crc8(данные: bytes) -> int:
    """CRC-8 DVB-S2: x⁸+x⁷+x⁶+x⁴+x²+1 (0xD5), старшим битом вперёд, начальное 0."""
    crc = 0
    for байт in данные:
        crc ^= байт
        for _ in range(8):
            crc = ((crc << 1) ^ 0xD5) & 0xFF if crc & 0x80 else (crc << 1) & 0xFF
    return crc


def crc32_mpeg2(данные: bytes) -> int:
    """CRC-32/MPEG-2 (0x04C11DB7, начальное 0xFFFFFFFF, без отражений) — у последнего фрагмента GSE."""
    crc = 0xFFFFFFFF
    for байт in данные:
        crc ^= байт << 24
        for _ in range(8):
            crc = ((crc << 1) ^ 0x04C11DB7) & 0xFFFFFFFF if crc & 0x80000000 else (crc << 1) & 0xFFFFFFFF
    return crc


# -- BBHEADER --------------------------------------------------------------------------------

ПОТОКИ = {0b00: "пакетированный (generic packetized)", 0b01: "непрерывный (GSE)",
          0b10: "GSE высокой эффективности (GSE-HEM, S2X)", 0b11: "транспортный поток (TS)"}
СКАТЫ = {0b00: "0,35", 0b01: "0,25", 0b10: "0,20", 0b11: "признак малого ската (S2X: 0,15/0,10/0,05)"}


@dataclass
class Заголовок:
    ts_gs: int
    mis: bool
    acm: bool
    issyi: bool
    npd: bool
    ro: int
    isi: int
    upl: int
    dfl: int
    sync: int
    syncd: int
    crc_верна: bool
    hem: bool = False


def заголовок(байты: bytes) -> Заголовок:
    """BBHEADER (10 байт): MATYPE-1, MATYPE-2, UPL, DFL, SYNC, SYNCD, CRC-8.

    CRC-8 считается по первым 9 байтам; в режиме высокой эффективности (HEM)
    она сложена с 0x80 (gr-dtv add_crc8_bits: INPUTMODE_HIEFF).
    """
    m1 = байты[0]
    crc = crc8(байты[:9])
    return Заголовок(
        ts_gs=m1 >> 6, mis=not (m1 >> 5) & 1, acm=not (m1 >> 4) & 1, issyi=bool((m1 >> 3) & 1), npd=bool((m1 >> 2) & 1), ro=m1 & 3,
        isi=байты[1], upl=int.from_bytes(байты[2:4], "big"), dfl=int.from_bytes(байты[4:6], "big"),
        sync=байты[6], syncd=int.from_bytes(байты[7:9], "big"),
        crc_верна=байты[9] in (crc, crc ^ 0x80), hem=байты[9] == crc ^ 0x80)


# -- поле данных: пакеты TS ------------------------------------------------------------------

def пакеты_ts(кадры: Sequence[tuple[Заголовок, bytes]]) -> tuple[list[bytes], int, int]:
    """Пакеты TS из полей данных подряд: (пакеты с синхробайтом 0x47, CRC-8 верна, сверено).

    Синхробайт каждого пакета в поле данных заменён CRC-8 предыдущего (EN 302 307-1
    5.1.4). Поля данных кадров подряд — один поток: пакет, разрезанный границей
    кадра, продолжается в следующем. SYNCD — расстояние в битах от начала поля до
    первого целого пакета: по нему поток ловится в начале и после пропущенного кадра.
    """
    сборка = СборкаTS()
    пакеты = [пакет for з, поле in кадры for пакет in сборка.подать(з, поле)]
    return пакеты, сборка.верно, сборка.сверено


class СборкаTS:
    """``пакеты_ts`` по кадру: недособранный пакет и последний пакет — между кадрами (для разбора по кускам)."""

    def __init__(self) -> None:
        self.буфер: bytearray | None = None
        self.последний: bytes | None = None
        self.верно = self.сверено = 0

    def подать(self, з: Заголовок, поле: bytes) -> list[bytes]:
        пакеты: list[bytes] = []
        if not з.crc_верна or not поле:
            self.буфер = None                              # кадр потерян — ждём следующий SYNCD
            return пакеты
        if self.буфер is None:
            if з.syncd == 0xFFFF or з.syncd // 8 > len(поле):
                return пакеты                              # в поле нет начала пакета
            self.буфер = bytearray(поле[з.syncd // 8:])
            прежний = None
        else:
            self.буфер += поле
            прежний = self.последний
        while len(self.буфер) >= 188:
            кусок = bytes(self.буфер[:188])
            del self.буфер[:188]
            if прежний is not None:
                self.сверено += 1
                self.верно += кусок[0] == crc8(прежний[1:])
            прежний = b"\x47" + кусок[1:]
            пакеты.append(прежний)
            self.последний = прежний
        return пакеты


# -- поле данных: пакеты GSE -----------------------------------------------------------------

@dataclass
class Gse:
    """Собранные PDU GSE и счёт проверок."""
    pdu: list[tuple[int, bytes]] = field(default_factory=list)   # (тип протокола, PDU)
    фрагментов: int = 0
    crc_верно: int = 0
    crc_неверно: int = 0
    набивка: int = 0
    ошибок: int = 0
    сборка: dict[int, bytearray] = field(default_factory=dict)
    метки: dict[int, int] = field(default_factory=dict)


ДЛИНЫ_МЕТКИ = {0: 6, 1: 3, 2: 0, 3: 0}


def _pdu(данные: bytes, lt: int) -> tuple[int, bytes] | None:
    """Тип протокола, метка, PDU; тип < 0x600 — расширенный заголовок (здесь PDU не выделяется)."""
    if len(данные) < 2:
        return None
    тип = int.from_bytes(данные[:2], "big")
    return тип, данные[2 + ДЛИНЫ_МЕТКИ[lt]:]


def разобрать_gse(поле: bytes, итог: Gse) -> None:
    """Пакеты GSE одного поля данных (ETSI TS 102 606-1; Wireshark packet-dvb-s2-bb.c)."""
    место = 0
    while место + 2 <= len(поле):
        слово = int.from_bytes(поле[место:место + 2], "big")
        s, e, lt, длина = слово >> 15, (слово >> 14) & 1, (слово >> 12) & 3, слово & 0x0FFF
        if not s and not e and lt == 0:
            итог.набивка += 1                                 # набивка до конца поля данных
            return
        конец = место + 2 + длина
        if конец > len(поле):
            итог.ошибок += 1
            return
        тело = поле[место + 2:конец]
        if s and e:                                           # целый PDU
            pdu = _pdu(тело, lt)
            if pdu is not None:
                итог.pdu.append(pdu)
        else:
            итог.фрагментов += 1
            if not тело:
                итог.ошибок += 1
                return
            ид, данные = тело[0], тело[1:]
            if s:                                             # первый: полная длина, тип, метка, …
                итог.сборка[ид] = bytearray(данные)
                итог.метки[ид] = lt
            elif ид in итог.сборка:
                if e:
                    собрано, crc = итог.сборка.pop(ид) + данные[:-4], int.from_bytes(данные[-4:], "big")
                    if crc32_mpeg2(bytes(собрано)) == crc and len(собрано) >= 2 \
                            and int.from_bytes(собрано[:2], "big") == len(собрано) - 2:
                        итог.crc_верно += 1
                        pdu = _pdu(bytes(собрано[2:]), итог.метки.pop(ид, 2))
                        if pdu is not None:
                            итог.pdu.append(pdu)
                    else:
                        итог.crc_неверно += 1
                else:
                    итог.сборка[ид] += данные
        место = конец


# -- поиск в потоке после LDPC ---------------------------------------------------------------

#: Сколько слов проверять заголовком при поиске длины; ``КАДРОВ_ДО`` — сколько кадров разбирает ``снять`` по
#: умолчанию (автомат разбирает все кадры выборки).
СЛОВ_ПРОБЫ = 4
КАДРОВ_ДО = 400


def _заголовок_слова(биты: np.ndarray, начало: int) -> Заголовок:
    return заголовок(np.packbits(скремблер(биты[начало:начало + 80])).tobytes())


def длина_слова(биты: np.ndarray) -> tuple[Код, int] | None:
    """Код БЧХ по потоку: BBHEADER с верной CRC-8 в начале каждого слова и нулевой остаток."""
    for длина in sorted({к.nbch for к in КОДЫ}):
        слов = min(СЛОВ_ПРОБЫ, len(биты) // длина)
        if слов < 2:
            continue
        if sum(_заголовок_слова(биты, i * длина).crc_верна for i in range(слов)) < слов - (слов > 2):
            continue
        # Одна длина — у нескольких кодов (у нормального 2/3 и S2X 20/30 разные t): решает остаток.
        # Слово кода с большим t делится и на g меньшего t (g_t12 = g_t10 · g11 · g12): сначала больший.
        for код in sorted((к for к in КОДЫ if к.nbch == длина), key=lambda к: -к.t):
            нулевых = sum(остаток(биты[i * длина:(i + 1) * длина], код.g) == 0 for i in range(слов))
            if нулевых * 2 >= слов:
                return код, слов
    return None


@dataclass
class Кадры:
    код: Код
    заголовки: list[Заголовок]
    поля: list[bytes]
    исправлено: int = 0
    неисправимо: int = 0


def снять(биты: np.ndarray, код: Код, кадров: int = КАДРОВ_ДО) -> Кадры:
    """Слова БЧХ → исправленные ошибки → скремблер BB → BBHEADER и поле данных каждого кадра."""
    слов = min(кадров, len(биты) // код.nbch)
    слова = np.asarray(биты[:слов * код.nbch], dtype=np.uint8).reshape(слов, код.nbch)
    плохие = [i for i in range(слов) if остаток(слова[i], код.g)]
    исправлено = неисправимо = 0
    for i in плохие:
        строка, число = исправить_бчх(слова[i], код)
        if число > 0:                                     # L корней при L ≤ t — слово уже кодовое
            слова[i] = строка
            исправлено += число
        else:
            неисправимо += 1
    заголовки, поля = [], []
    for строка in слова:
        кадр = скремблер(строка[:код.kbch])
        з = заголовок(np.packbits(кадр[:80]).tobytes())
        заголовки.append(з)
        поля.append(np.packbits(кадр[80:80 + min(з.dfl, код.kbch - 80)]).tobytes() if з.crc_верна else b"")
    return Кадры(код, заголовки, поля, исправлено, неисправимо)


def найти(биты: np.ndarray) -> Находка | None:
    """DVB-S2 после LDPC: код БЧХ, BBFRAME, пакеты TS или GSE."""
    найдено = длина_слова(np.asarray(биты, dtype=np.uint8))
    if найдено is None:
        return None
    код, _ = найдено
    # Все кадры выборки: выход этапа — с её начала до конца, не первые КАДРОВ_ДО.
    к = снять(np.asarray(биты, dtype=np.uint8), код, кадров=len(биты) // код.nbch)
    верных = [з for з in к.заголовки if з.crc_верна]
    if not верных:
        return None
    главный = верных[0]
    подробно = [
        f"код БЧХ {код.nbch} → {код.kbch} бит, t = {код.t} ({код.имя}; {'GF(2¹⁴)' if код.короткий else 'GF(2¹⁶)'})",
        f"слов БЧХ {len(к.заголовки)}: исправлено бит {к.исправлено}, неисправимых слов {к.неисправимо}",
        f"BBHEADER с верной CRC-8: {len(верных)} из {len(к.заголовки)}"
        + (" (режим высокой эффективности, HEM)" if главный.hem else ""),
        f"поток: {ПОТОКИ[главный.ts_gs]}; {'несколько потоков (MIS), ISI ' + str(главный.isi) if главный.mis else 'один поток (SIS)'}; "
        f"{'ACM/VCM' if главный.acm else 'CCM'}; скат {СКАТЫ[главный.ro]}"
        + ("; ISSY" if главный.issyi else "") + ("; удаление пустых пакетов (NPD)" if главный.npd else ""),
        f"UPL {главный.upl} бит, DFL {главный.dfl} бит, SYNC 0x{главный.sync:02X}, SYNCD {главный.syncd}",
    ]
    дальше, вид, выход = None, "", ""
    if главный.ts_gs == 0b11 and главный.upl == 188 * 8:
        пакеты, верно, сверено = пакеты_ts(list(zip(к.заголовки, к.поля, strict=True)))
        подробно.append(f"пакетов TS {len(пакеты)}; CRC-8 пакета (вместо синхробайта) верна у {верно} из {сверено}")
        дальше, вид, выход = np.frombuffer(b"".join(пакеты), dtype=np.uint8), "пакеты TS", "ts"
    elif главный.ts_gs in (0b01, 0b10):
        g = Gse()
        for з, поле in zip(к.заголовки, к.поля, strict=True):
            if з.crc_верна:
                разобрать_gse(поле, g)
        типы: dict[str, int] = {}
        for тип, _ in g.pdu:
            имя = {0x0800: "IPv4", 0x86DD: "IPv6", 0x0806: "ARP"}.get(тип, f"0x{тип:04X}")
            типы[имя] = типы.get(имя, 0) + 1
        подробно.append(f"GSE: PDU {len(g.pdu)} ({', '.join(f'{и}×{с}' for и, с in типы.items()) or 'нет'}); "
                        f"фрагментов {g.фрагментов}, CRC-32 собранных верна у {g.crc_верно}"
                        + (f", неверна у {g.crc_неверно}" if g.crc_неверно else "")
                        + (f"; ошибок длины {g.ошибок}" if g.ошибок else ""))
        дальше, вид, выход = [pdu for тип, pdu in g.pdu if тип in (0x0800, 0x86DD)], "кадры", "gse"
    return Находка(
        уровень="канальный", что="DVB-S2: BBFRAME после внешнего кода БЧХ", уверенность=len(верных) / len(к.заголовки),
        мера=f"BBHEADER с верной CRC-8 в начале {len(верных)} из {len(к.заголовки)} слов по {код.nbch} бит, "
             f"остаток от деления на порождающий многочлен БЧХ — нуль",
        подробно=подробно, дальше=дальше, вид_дальше=вид,
        свойства={"кадры_слой": слой_кадров(код, выход)} if выход else {})


def слой_кадров(код: Код, выход: str) -> str:
    """Разборщик кадров для пересчёта этапа по всему файлу (``kadry_ves``): код БЧХ и выход (ts — пакеты TS,
    gse — PDU IP)."""
    return (f"bbframe nbch {код.nbch} kbch {код.kbch} t {код.t} {'короткий' if код.короткий else 'нормальный'} "
            f"выход {выход}")


def код_слоя(nbch: int, kbch: int, t: int, короткий: bool) -> Код:
    """Код БЧХ по строке ``слой_кадров``."""
    for код in КОДЫ:
        if (код.nbch, код.kbch, код.t, код.короткий) == (nbch, kbch, t, короткий):
            return код
    raise ValueError(f"код БЧХ DVB-S2 {nbch} → {kbch}, t = {t} не известен")
