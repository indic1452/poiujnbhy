# -*- coding: utf-8 -*-
"""Мультиплекс со стаффингом общего вида: канал управления, знак, разуплотнение притока.

Для PDH (E2/E3/E4) разметка известна по стандарту — это модуль pdh. Здесь —
неизвестный мультиплекс (РРЛ, свои форматы), где разметку восстанавливает
аналитик. Признаки, на которых это держится, от формата не зависят:

- **биты управления** стаффингом (Cj) повторяются в кадре несколько раз
  (обычно 3 или 5 — решает большинство, одиночная ошибка линии не сбивает
  демультиплексор): столбцы растра, которые почти всегда равны друг другу
  внутри кадра, но от кадра к кадру меняются. Каждая такая группа — канал
  управления одного притока; доля кадров «со стаффингом» — расстройка
  частоты притока;
- **положительный стаффинг** — есть бит возможности: при «нет стаффинга» он
  несёт данные (случаен), при «стаффинг» — пустышку (постоянен или
  по-другому распределён);
- **отрицательный** — наоборот: служебная позиция, обычно постоянная, при
  «стаффинг» несёт лишний бит данных.

Позиция возможности и знак ищутся по тому, как столбец ведёт себя в кадрах
с управлением «0» и «1». Разуплотнение: биты притока берутся из позиций
данных (маска аналитика), а бит возможности вставляется или выбрасывается
по решению большинства в каждом кадре.
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Sequence

import numpy as np

#: Столбцы группы управления совпадают не реже чем в стольких кадрах.
СОГЛАСИЕ = 0.95
#: Столбец считается «меняющимся», если в нём от 1 % до 99 % единиц.
МЕНЯЕТСЯ = (0.01, 0.99)
КАДРОВ_ДО = 20000


def кадры(биты: np.ndarray, период: int, сдвиг: int = 0) -> np.ndarray:
    if период < 8:
        raise ValueError("нужна длина кадра — период растра (от 8 бит)")
    ряд = биты[сдвиг % период:]
    сколько = min(КАДРОВ_ДО, len(ряд) // период)
    if сколько < 32:
        raise ValueError(f"нужно хотя бы 32 кадра по {период} бит")
    return ряд[:сколько * период].reshape(сколько, период)


def _энтропия(доля: float) -> float:
    if доля <= 0 or доля >= 1:
        return 0.0
    return float(-(доля * np.log2(доля) + (1 - доля) * np.log2(1 - доля)))


def группы_управления(таблица: np.ndarray, *, наименьшая: int = 2, наибольшая: int = 7
                      ) -> List[Dict[str, Any]]:
    """Группы столбцов, равных друг другу почти во всех кадрах и меняющихся от кадра к кадру.

    Кадр за кадром такие столбцы — копии одного бита. У данных соседние
    столбцы совпадают в половине кадров, у постоянных полей группа
    вырождена (не меняется) — те и другие отсеиваются.
    """
    доли = таблица.mean(axis=0)
    кандидаты = np.flatnonzero((доли > МЕНЯЕТСЯ[0]) & (доли < МЕНЯЕТСЯ[1]))
    if len(кандидаты) < 2:
        return []
    # Попарное согласие столбцов-кандидатов: доля кадров, где они равны.
    x = таблица[:, кандидаты].astype(np.float32) * 2 - 1
    согласие = (x.T @ x / len(таблица) + 1) / 2
    свободен = np.ones(len(кандидаты), dtype=bool)
    группы = []
    for i in np.argsort(-np.abs(доли[кандидаты] - 0.5)):
        if not свободен[i]:
            continue
        члены = [j for j in range(len(кандидаты)) if свободен[j] and согласие[i, j] >= СОГЛАСИЕ]
        if not наименьшая <= len(члены) <= наибольшая:
            continue
        # Все попарно согласны — иначе это не копии одного бита.
        if min(согласие[a, b] for a in члены for b in члены) < СОГЛАСИЕ:
            continue
        столбцы = sorted(int(кандидаты[j]) for j in члены)
        решение = (таблица[:, столбцы].sum(axis=1) * 2 > len(столбцы)).astype(np.uint8)
        несогласных = float(np.mean(таблица[:, столбцы].min(axis=1) != таблица[:, столбцы].max(axis=1)))
        группы.append({"столбцы": столбцы, "доля_стаффинга": round(float(решение.mean()), 4),
                       "несогласных": round(несогласных, 4),
                       "согласие": round(float(min(согласие[a, b] for a in члены for b in члены)), 4)})
        for j in члены:
            свободен[j] = False
    return sorted(группы, key=lambda г: г["столбцы"][0])


def решение(таблица: np.ndarray, столбцы: Sequence[int]) -> np.ndarray:
    """Решение большинством по группе управления: 1 — «стаффинг» в этом кадре."""
    return (таблица[:, list(столбцы)].sum(axis=1) * 2 > len(столбцы)).astype(np.uint8)


def возможность(таблица: np.ndarray, группа: Sequence[int], *, лучших: int = 3,
                 кроме: Sequence[int] = ()) -> List[Dict[str, Any]]:
    """Где бит возможности стаффинга и какой знак: по поведению столбцов при «0» и «1».

    Положительный: столбец случаен при «нет стаффинга» и постоянен при «стаффинг».
    Отрицательный: постоянен при «нет» и случаен при «стаффинг». Мера — разность
    энтропий столбца в двух состояниях (в битах), чем ближе к 1, тем яснее.
    """
    р = решение(таблица, группа).astype(bool)
    if р.all() or not р.any():
        return []
    оценки = []
    for столбец in range(таблица.shape[1]):
        if столбец in группа or столбец in кроме:
            continue
        при_0 = _энтропия(float(таблица[~р, столбец].mean()))
        при_1 = _энтропия(float(таблица[р, столбец].mean()))
        разница = при_0 - при_1
        if abs(разница) < 0.5:
            continue
        оценки.append({"столбец": столбец, "знак": "+" if разница > 0 else "−",
                       "мера": round(abs(разница), 3),
                       "энтропия_без": round(при_0, 3), "энтропия_со": round(при_1, 3)})
    return sorted(оценки, key=lambda о: -о["мера"])[:лучших]


def разуплотнить(биты: np.ndarray, период: int, сдвиг: int, данные: Sequence[int],
                 управление: Sequence[int], возможность_: int, знак: str,
                 полярность: int = 1) -> tuple[np.ndarray, Dict[str, Any]]:
    """Поток притока: позиции данных по порядку, бит возможности — по решению большинства.

    Положительный знак: бит возможности идёт в поток, только когда стаффинга
    нет. Отрицательный: служебная позиция идёт в поток, только когда стаффинг
    есть. ``полярность`` — какое значение управления означает «стаффинг» (1 или 0).
    """
    данные = sorted(set(int(п) for п in данные) - set(управление) - {возможность_})
    if not данные:
        raise ValueError("позиции данных притока пусты")
    if знак not in ("+", "−", "-"):
        raise ValueError("знак стаффинга: + (положительный) или − (отрицательный)")
    таблица = кадры(биты, период, сдвиг)
    р = решение(таблица, управление)
    if not полярность:
        р = 1 - р
    # Бит возможности стоит в кадре на своём месте среди данных.
    порядок = sorted(данные + [возможность_])
    место = порядок.index(возможность_)
    части = []
    for кадр, стаффинг in zip(таблица, р):
        брать = (not стаффинг) if знак == "+" else bool(стаффинг)
        биты_кадра = кадр[порядок]
        части.append(биты_кадра if брать else np.delete(биты_кадра, место))
    поток = np.concatenate(части).astype(np.uint8)
    несогласных = float(np.mean(таблица[:, list(управление)].min(axis=1) != таблица[:, list(управление)].max(axis=1)))
    return поток, {"кадров": len(таблица), "доля_стаффинга": round(float(р.mean()), 4),
                   "несогласных": round(несогласных, 4), "данных_в_кадре": len(данные),
                   "расстройка": round(float(р.mean()) / (len(данные) + (1 if знак != "+" else 0)), 6)}


def найти(биты: np.ndarray, период: int, сдвиг: int = 0) -> Optional[Dict[str, Any]]:
    """Группы управления и для каждой — лучший кандидат возможности стаффинга со знаком."""
    таблица = кадры(биты, период, сдвиг)
    группы = группы_управления(таблица)
    if not группы:
        return None
    управляющие = [c for г in группы for c in г["столбцы"]]
    for г in группы:
        # Биты управления других притоков — не возможность этого.
        г["возможность"] = возможность(таблица, г["столбцы"], кроме=управляющие)
    # Бит возможности — у одного притока: у того, для кого он явнее всего. При
    # кратных долях стаффинга (0,3 и 0,2 — оба периодичны) бит чужого притока
    # тоже зависит от этого управления, но слабее.
    хозяин: Dict[int, float] = {}
    for г in группы:
        for в in г["возможность"]:
            хозяин[в["столбец"]] = max(хозяин.get(в["столбец"], 0.0), в["мера"])
    for г in группы:
        г["возможность"] = [в for в in г["возможность"] if в["мера"] >= хозяин[в["столбец"]]]
    return {"кадров": len(таблица), "группы": группы}
