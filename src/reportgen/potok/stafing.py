"""Мультиплекс со стаффингом общего вида: канал управления, знак, разуплотнение притока.

Для PDH (E2/E3/E4) разметка известна по стандарту — это модуль pdh. Здесь —
неизвестный мультиплекс (РРЛ, свои форматы), где разметку восстанавливает
аналитик. Признаки, на которых это держится, от формата не зависят:

- **биты управления** стаффингом (Cj) повторяются в кадре несколько раз
  (обычно 3 или 5 — решает большинство, одиночная ошибка линии не сбивает
  демультиплексор): столбцы растра, которые почти всегда равны друг другу
  внутри кадра, но от кадра к кадру меняются. Каждая такая группа — канал
  управления одного притока; доля кадров «со стаффингом» — расстройка
  частоты притока;
- **положительный стаффинг** — есть бит возможности: при «нет стаффинга» он
  несёт данные (случаен), при «стаффинг» — пустышку (постоянен или
  по-другому распределён);
- **отрицательный** — наоборот: служебная позиция, обычно постоянная, при
  «стаффинг» несёт лишний бит данных.

Позиция возможности и знак ищутся по тому, как столбец ведёт себя в кадрах
с управлением «0» и «1». Разуплотнение: биты притока берутся из позиций
данных (маска аналитика), а бит возможности вставляется или выбрасывается
по решению большинства в каждом кадре.
"""

from __future__ import annotations

from collections.abc import Sequence
from typing import Any

import numpy as np

#: Столбцы группы управления совпадают не реже чем в стольких кадрах.
СОГЛАСИЕ = 0.95
#: Столбец считается «меняющимся», если в нём от 1 % до 99 % единиц.
МЕНЯЕТСЯ = (0.01, 0.99)
КАДРОВ_ДО = 20000
#: Сколько мест возможности искать у одной группы управления.
МЕСТ_ДО = 16
#: Место входит в набор группы, если его мера не меньше этой доли от лучшей.
ЯВНЫЕ = 0.8
#: Энтропия пустого бита возможности (в состоянии, где он постоянен) — не больше:
#: 0,3 бита — это до ~5 % несогласных значений.
ПУСТОЙ_ДО = 0.3


def кадры(биты: np.ndarray, период: int, сдвиг: int = 0) -> np.ndarray:
    if период < 8:
        raise ValueError("нужна длина кадра — период растра (от 8 бит)")
    ряд = биты[сдвиг % период:]
    сколько = min(КАДРОВ_ДО, len(ряд) // период)
    if сколько < 32:
        raise ValueError(f"нужно хотя бы 32 кадра по {период} бит")
    return ряд[:сколько * период].reshape(сколько, период)


def _энтропии(доли: np.ndarray) -> np.ndarray:
    """Двоичная энтропия каждой доли (0 и 1 — ноль)."""
    p = np.clip(np.asarray(доли, dtype=np.float64), 1e-300, 1.0)
    q = np.clip(1.0 - np.asarray(доли, dtype=np.float64), 1e-300, 1.0)
    итог = -(p * np.log2(p) + q * np.log2(q))
    итог[(доли <= 0) | (доли >= 1)] = 0.0
    return итог


def _энтропия(доля: float) -> float:
    if доля <= 0 or доля >= 1:
        return 0.0
    return float(-(доля * np.log2(доля) + (1 - доля) * np.log2(1 - доля)))


#: У столбца больше стольких согласных — их список не хранится (память), а при надобности
#: пересчитывается: группы из такого столбца почти никогда не выходит.
СОСЕДЕЙ_ХРАНИТЬ = 64
#: Попарное согласие столбцов считается блоками — не больше стольких чисел за раз:
#: у длинного цикла вся матрица (кандидатов в квадрате) не помещается в память.
ЧИСЕЛ_ЗА_РАЗ = 1 << 24


def группы_управления(таблица: np.ndarray, *, наименьшая: int = 2, наибольшая: int = 7
                      ) -> list[dict[str, Any]]:
    """Группы столбцов, равных друг другу почти во всех кадрах и меняющихся от кадра к кадру.

    Кадр за кадром такие столбцы — копии одного бита. У данных соседние
    столбцы совпадают в половине кадров, у постоянных полей группа
    вырождена (не меняется) — те и другие отсеиваются.
    """
    доли = таблица.mean(axis=0)
    кандидаты = np.flatnonzero((доли > МЕНЯЕТСЯ[0]) & (доли < МЕНЯЕТСЯ[1]))
    if len(кандидаты) < 2:
        return []
    x = таблица[:, кандидаты].astype(np.float32) * 2 - 1
    всего = len(кандидаты)

    def согласие(строки, столбцы=slice(None)) -> np.ndarray:
        """Попарное согласие столбцов-кандидатов: доля кадров, где они равны."""
        return (x[:, строки].T @ x[:, столбцы] / len(таблица) + 1) / 2

    # Для каждого кандидата — список согласных с ним (и он сам); матрица целиком
    # не строится, а считается блоками строк.
    соседи: list[np.ndarray | None] = [None] * всего
    блок = max(1, ЧИСЕЛ_ЗА_РАЗ // всего)
    for начало in range(0, всего, блок):
        согласны = согласие(slice(начало, начало + блок)) >= СОГЛАСИЕ
        for r in np.flatnonzero(согласны.sum(axis=1) <= СОСЕДЕЙ_ХРАНИТЬ):
            соседи[начало + r] = np.flatnonzero(согласны[r])
    свободен = np.ones(всего, dtype=bool)
    группы = []
    for i in np.argsort(-np.abs(доли[кандидаты] - 0.5)):
        if not свободен[i]:
            continue
        свои = соседи[i] if соседи[i] is not None else np.flatnonzero(согласие([i])[0] >= СОГЛАСИЕ)
        члены = свои[свободен[свои]]
        if not наименьшая <= len(члены) <= наибольшая:
            continue
        # Все попарно согласны — иначе это не копии одного бита.
        попарно = float(согласие(члены, члены).min())
        if попарно < СОГЛАСИЕ:
            continue
        столбцы = sorted(int(кандидаты[j]) for j in члены)
        решение = (таблица[:, столбцы].sum(axis=1) * 2 > len(столбцы)).astype(np.uint8)
        несогласных = float(np.mean(таблица[:, столбцы].min(axis=1) != таблица[:, столбцы].max(axis=1)))
        группы.append({"столбцы": столбцы, "доля_стаффинга": round(float(решение.mean()), 4),
                       "несогласных": round(несогласных, 4), "согласие": round(попарно, 4)})
        свободен[члены] = False
    return sorted(группы, key=lambda г: г["столбцы"][0])


def решение(таблица: np.ndarray, столбцы: Sequence[int]) -> np.ndarray:
    """Решение большинством по группе управления: 1 — «стаффинг» в этом кадре."""
    return (таблица[:, list(столбцы)].sum(axis=1) * 2 > len(столбцы)).astype(np.uint8)


def возможность(таблица: np.ndarray, группа: Sequence[int], *, лучших: int = 3,
                 кроме: Sequence[int] = ()) -> list[dict[str, Any]]:
    """Где бит возможности стаффинга и какой знак: по поведению столбцов при «0» и «1».

    Положительный: столбец случаен при «нет стаффинга» и постоянен при «стаффинг».
    Отрицательный: постоянен при «нет» и случаен при «стаффинг». Мера — разность
    энтропий столбца в двух состояниях (в битах), чем ближе к 1, тем яснее.
    """
    р = решение(таблица, группа).astype(bool)
    if р.all() or not р.any():
        return []
    оценки = []
    # Энтропии всех столбцов в обоих состояниях — сразу (по столбцу в цикле — долго у кадров в тысячи бит);
    # дальше — только столбцы, где разница заметна.
    # Суммы — целые: доли те же, что по столбцу (np.mean), до последнего бита.
    единиц_1 = р.astype(np.int64) @ таблица.astype(np.int64)
    единиц = таблица.sum(axis=0, dtype=np.int64)
    n1 = int(р.sum())
    энтр_0 = _энтропии((единиц - единиц_1) / (len(р) - n1))
    энтр_1 = _энтропии(единиц_1 / n1)
    пропустить = {int(c) for c in группа} | {int(c) for c in кроме}
    заметные = np.flatnonzero((np.abs(энтр_0 - энтр_1) >= 0.5) & (np.minimum(энтр_0, энтр_1) <= ПУСТОЙ_ДО))
    for столбец in заметные.tolist():
        if столбец in пропустить:
            continue
        при_0 = float(энтр_0[столбец])
        при_1 = float(энтр_1[столбец])
        разница = при_0 - при_1
        # Бит возможности в одном из состояний — пустой, то есть постоянный
        # (с поправкой на ошибки линии). Столбец, который лишь «менее случаен»
        # при одном решении (заполнение в части кадров), — не место стаффинга.
        if abs(разница) < 0.5 or min(при_0, при_1) > ПУСТОЙ_ДО:
            continue
        оценки.append({"столбец": столбец, "знак": "+" if разница > 0 else "−",
                       "мера": round(abs(разница), 3),
                       "энтропия_без": round(при_0, 3), "энтропия_со": round(при_1, 3)})
    return sorted(оценки, key=lambda о: -о["мера"])[:лучших]


def правило(управление: Sequence[int], возможности: Sequence[tuple], полярность: int = 1) -> dict[str, Any]:
    """Правило стаффинга: группа управления и места, которыми она распоряжается.

    ``возможности`` — пары (позиция, знак): «+» — место несёт данные, когда
    стаффинга нет (положительный), «−» — когда стаффинг есть (отрицательный).
    Одна группа может распоряжаться несколькими местами сразу (стаффинг по
    несколько бит), у каждого места — свой знак.
    """
    места = []
    for позиция, знак in возможности:
        if знак not in ("+", "−", "-"):
            raise ValueError("знак стаффинга: + (положительный) или − (отрицательный)")
        места.append((int(позиция), "+" if знак == "+" else "−"))
    if not управление:
        raise ValueError("у правила стаффинга нет столбцов управления")
    if not места:
        raise ValueError("у правила стаффинга нет мест возможности")
    return {"управление": sorted({int(c) for c in управление}), "возможности": места,
            "полярность": 1 if полярность else 0}


def разуплотнить_по_правилам(биты: np.ndarray, период: int, сдвиг: int, данные: Sequence[int],
                             правила: Sequence[dict[str, Any]]) -> tuple[np.ndarray, dict[str, Any]]:
    """Поток притока: позиции данных всегда, места возможности — по решению своего правила.

    Биты берутся в кадре по порядку позиций. Решение каждого правила — большинством
    по его столбцам управления; ``полярность`` — какое значение значит «стаффинг».
    """
    if not правила:
        raise ValueError("нет ни одного правила стаффинга")
    служебные = {c for п in правила for c in п["управление"]}
    места = [м for п in правила for м, _ in п["возможности"]]
    if len(set(места)) != len(места):
        raise ValueError("место возможности указано в двух правилах")
    if служебные & set(места):
        raise ValueError("столбец и управление, и место возможности")
    данные = sorted({int(п) for п in данные} - служебные - set(места))
    if not данные:
        raise ValueError("позиции данных притока пусты")
    if max(данные + места) >= период or min(данные + места) < 0 or max(служебные) >= период:
        raise ValueError(f"позиции должны быть внутри кадра 0…{период - 1}")
    таблица = кадры(биты, период, сдвиг)
    брать = np.zeros(таблица.shape, dtype=bool)
    брать[:, данные] = True
    сводки = []
    for п in правила:
        р = решение(таблица, п["управление"]).astype(bool)
        if not п["полярность"]:
            р = ~р
        for место, знак in п["возможности"]:
            брать[:, место] = ~р if знак == "+" else р
        несогласных = float(np.mean(таблица[:, п["управление"]].min(axis=1) != таблица[:, п["управление"]].max(axis=1)))
        сводки.append({"управление": п["управление"], "доля_стаффинга": round(float(р.mean()), 4),
                       "несогласных": round(несогласных, 4), "мест": len(п["возможности"])})
    # Логическая выборка по строкам: биты кадра по порядку позиций, кадр за кадром.
    поток = таблица[брать].astype(np.uint8)
    бит_в_кадре = брать.sum(axis=1)
    return поток, {"кадров": len(таблица), "данных_в_кадре": len(данные), "правила": сводки,
                   "бит_в_кадре": {"от": int(бит_в_кадре.min()), "до": int(бит_в_кадре.max()),
                                   "среднее": round(float(бит_в_кадре.mean()), 4)},
                   # Доля стаффинга первого правила — для прежней сводки одним числом.
                   "доля_стаффинга": сводки[0]["доля_стаффинга"],
                   "несогласных": сводки[0]["несогласных"]}


def разуплотнить(биты: np.ndarray, период: int, сдвиг: int, данные: Sequence[int],
                 управление: Sequence[int], возможность_: int, знак: str,
                 полярность: int = 1) -> tuple[np.ndarray, dict[str, Any]]:
    """Один приток, одна группа управления, одно место возможности (частный случай)."""
    if знак not in ("+", "−", "-"):
        raise ValueError("знак стаффинга: + (положительный) или − (отрицательный)")
    поток, сводка = разуплотнить_по_правилам(
        биты, период, сдвиг, данные, [правило(управление, [(возможность_, знак)], полярность)])
    данных = сводка["данных_в_кадре"]
    сводка["расстройка"] = round(сводка["доля_стаффинга"] / (данных + (1 if знак != "+" else 0)), 6)
    return поток, сводка


def найти(биты: np.ndarray, период: int, сдвиг: int = 0) -> dict[str, Any] | None:
    """Группы управления и для каждой — лучший кандидат возможности стаффинга со знаком."""
    таблица = кадры(биты, период, сдвиг)
    группы = группы_управления(таблица)
    if not группы:
        return None
    управляющие = [c for г in группы for c in г["столбцы"]]
    for г in группы:
        # Биты управления других притоков — не возможность этого.
        г["возможность"] = возможность(таблица, г["столбцы"], кроме=управляющие, лучших=МЕСТ_ДО)
    # Бит возможности — у одного притока: у того, для кого он явнее всего. При
    # кратных долях стаффинга (0,3 и 0,2 — оба периодичны) бит чужого притока
    # тоже зависит от этого управления, но слабее.
    хозяин: dict[int, float] = {}
    for г in группы:
        for в in г["возможность"]:
            хозяин[в["столбец"]] = max(хозяин.get(в["столбец"], 0.0), в["мера"])
    for г in группы:
        г["возможность"] = [в for в in г["возможность"] if в["мера"] >= хозяин[в["столбец"]]]
        # Места этой группы: все явные кандидаты не слабее ЯВНЫЕ от лучшего — стаффинг
        # бывает по несколько бит за раз, и знак у мест может быть разный.
        лучший = г["возможность"][0]["мера"] if г["возможность"] else 0.0
        г["места"] = sorted(({"столбец": в["столбец"], "знак": в["знак"]}
                             for в in г["возможность"] if в["мера"] >= ЯВНЫЕ * лучший),
                            key=lambda м: м["столбец"])
    return {"кадров": len(таблица), "группы": группы}
