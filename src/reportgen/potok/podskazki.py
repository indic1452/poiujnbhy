"""Что делать, когда разбор встал: приметы потока, подсказки и вопрос помощнику.

Автоматический разбор останавливается там, где ни одна гипотеза не
подтвердилась. Дальше аналитик действует сам, и первое, что ему нужно, —
приметы потока в этом месте: перекос нулей и единиц, серии, байтовое
выравнивание, периоды, линейные связи соседних бит. По приметам здесь
строятся подсказки с готовым действием (сложить по периоду, снять слой,
запустить инструмент, разобрать глубже), а для вопроса помощнику — текст
с ходом разбора: помощник знает теорию из библиотеки и отвечает по ней.

Правила подсказок — те же рассуждения, которыми аналитик пользуется
вручную; каждое проверено на синтетических потоках (см. тесты).
"""

from __future__ import annotations

from typing import Any, Dict, List

import numpy as np

from . import rastr
from .kod import проверки

ВЫБОРКА = 1 << 20
#: Длиннее — уже пауза (заполнение): у случайного ряда серия 32 бита
#: встречается реже раза на миллиард бит.
ПАУЗА = 32


def _энтропия_байт(биты: np.ndarray, сдвиг: int) -> float:
    ряд = биты[сдвиг:]
    байты = np.packbits(ряд[:len(ряд) // 8 * 8])
    if not len(байты):
        return 0.0
    частоты = np.bincount(байты, minlength=256) / len(байты)
    частоты = частоты[частоты > 0]
    return float(-(частоты * np.log2(частоты)).sum())


def _серии(биты: np.ndarray) -> tuple[int, float]:
    """Самая длинная серия одинаковых бит и доля бит в сериях не короче ПАУЗА."""
    if len(биты) < 2:
        return len(биты), 0.0
    границы = np.flatnonzero(np.diff(биты.astype(np.int8))) + 1
    длины = np.diff(np.concatenate([[0], границы, [len(биты)]]))
    return int(длины.max()), float(длины[длины >= ПАУЗА].sum() / len(биты))


def приметы(биты: np.ndarray) -> Dict[str, Any]:
    """Приметы потока в этом месте разбора — всё быстрое, за секунды."""
    выборка = np.asarray(биты[:ВЫБОРКА], dtype=np.uint8)
    if len(выборка) < 4096:
        return {"бит": int(len(биты)), "мало": True}
    энтропии = [_энтропия_байт(выборка, с) for с in range(8)]
    лучший_сдвиг = int(np.argmin(энтропии))
    серия, в_паузах = _серии(выборка)
    пары = []
    for фаза in (0, 1):
        п = выборка[фаза:фаза + (len(выборка) - фаза) // 2 * 2].reshape(-1, 2)
        пары.append(float(np.mean(п[:, 0] == п[:, 1])))
    # Флаг HDLC 01111110 в любом месте: у случайного ряда — раз на 256 позиций.
    окна = np.lib.stride_tricks.sliding_window_view(выборка[:1 << 18], 8)
    флагов = int(np.count_nonzero((окна @ (1 << np.arange(7, -1, -1))) == 0x7E))
    смещения, окон = проверки(выборка[:1 << 17], 16, 1)
    смещения[0] = 0
    return {
        "бит": int(len(биты)),
        "доля_единиц": round(float(выборка.mean()), 4),
        "энтропия_байт": round(max(энтропии), 3),
        "энтропия_мин": round(min(энтропии), 3),
        "сдвиг_байта": лучший_сдвиг,
        "серия_до": серия,
        "в_паузах": round(в_паузах, 4),
        "пар_без_перехода": round(min(пары), 4),
        "связи_сигм": round(float(np.abs(смещения).max() * np.sqrt(окон)), 1),
        "флагов_к_случайному": round(флагов / max(1.0, (len(окна)) / 256), 2),
        "периоды": rastr.периоды(выборка, 4),
    }


def _подсказка(что: str, почему: str, *действия: Dict[str, Any]) -> Dict[str, Any]:
    """Подсказка и действия к ней: у каждого — вид, параметры и надпись кнопки."""
    return {"что": что, "почему": почему, "действия": list(действия)}


def подсказки(состояние: Dict[str, Any], этап: int, п: Dict[str, Any]) -> List[Dict[str, Any]]:
    """Подсказки с действием по приметам и по тому, что уже найдено и отвергнуто."""
    итог: List[Dict[str, Any]] = []
    if п.get("мало"):
        return [_подсказка("Слишком короткий поток", "меньше 4 Кбит: статистика ненадёжна — "
                           "нужна запись длиннее")]
    этапы = состояние.get("этапы") or []
    найдено = {э.get("уровень") for э in этапы[:этап] if isinstance(э, dict)}
    ограничения = " ".join(состояние.get("ограничения") or [])
    случайный = (abs(п["доля_единиц"] - 0.5) < 0.01 and п["энтропия_мин"] > 7.9
                 and not п["периоды"] and п["связи_сигм"] < 12 and п["в_паузах"] < 0.001)

    if "время разбора исчерпано" in ограничения or "остановлен на глубине" in ограничения:
        итог.append(_подсказка(
            "Разобрать глубже",
            "автомат упёрся в " + ("время" if "время" in ограничения else "глубину") +
            ": профиль «глубоко» даёт больше времени, длинные коды (LDPC, турбо), "
            "перфорацию и перебор свёрточного перемежения Форни до 128 × 128",
            {"вид": "профиль", "профиль": "глубоко", "кнопка": "Разобрать с профилем «глубоко»"}))

    if п["пар_без_перехода"] < 0.02:
        итог.append(_подсказка(
            "Манчестерский код в линии",
            f"пар бит без перехода в середине — {п['пар_без_перехода'] * 100:.2f} % "
            "(у случайного ряда 50 %): в каждой паре переход — это манчестер",
            {"вид": "слой", "слой": "манчестер", "кнопка": "Снять манчестер и разобрать"}))
    elif п["серия_до"] <= 5 and abs(п["доля_единиц"] - 0.5) < 0.03 and not случайный:
        итог.append(_подсказка(
            "Код в линии с ограничением серий",
            f"самая длинная серия одинаковых бит — {п['серия_до']}: так строят 4B/5B и "
            "8B/10B (серии не длиннее 3 и 5); автомат проверяет их при разборе",
            {"вид": "разобрать", "кнопка": "Разобрать этот поток"}))

    if п["периоды"] and "цикл" not in найдено:
        главный = п["периоды"][0]
        итог.append(_подсказка(
            f"Период {главный['период']} бит — сложите поток по нему",
            f"пик автокорреляции {главный['сила']}σ" +
            (f" ({главный['заметка']})" if главный["заметка"] else "") +
            ": в растре постоянные столбцы — синхрослово, полосы — каналы. Выделите "
            "столбцы канала и сохраните маску — канал выйдет отдельным потоком",
            *[{"вид": "растр", "период": р["период"], "кнопка": f"Растр по {р['период']}"}
              for р in п["периоды"][:3]],
            {"вид": "инструмент", "имя": "цикл", "кнопка": "Найти цикл"}))

    # Связи есть и у открытого текста, и у заполнения — о коде или ПСП они
    # говорят, только когда поток на вид случаен: баланс и полная энтропия.
    похож_на_случайный = abs(п["доля_единиц"] - 0.5) < 0.03 and п["энтропия_мин"] > 7.5
    if (п["связи_сигм"] >= 20 and похож_на_случайный and п["пар_без_перехода"] >= 0.02
            and "код" not in найдено):
        итог.append(_подсказка(
            "Биты на вид случайны, но линейно связаны: код или ПСП",
            f"на окне 16 бит есть проверочная связь силой {п['связи_сигм']}σ. Так выглядит "
            "помехоустойчивый код (свёрточный, короткий блочный) — или аддитивная ПСП на "
            "паузах между кадрами. Если код не опознаётся — проверьте перемежение над ним "
            "(блочное или Форни) профилем «глубоко»",
            {"вид": "инструмент", "имя": "код", "кнопка": "Найти код"},
            {"вид": "инструмент", "имя": "скремблер", "кнопка": "Найти скремблер"}))

    if п["в_паузах"] >= 0.02:
        итог.append(_подсказка(
            "В потоке паузы — по ним открывается скремблер",
            f"{п['в_паузах'] * 100:.1f} % бит стоит в сериях от {ПАУЗА} бит: заполнение между "
            "кадрами. Аддитивная ПСП на паузе видна как есть, самосинхронизирующийся "
            "скремблер — по вычислению Берлекэмпа — Мэсси",
            {"вид": "инструмент", "имя": "скремблер", "кнопка": "Найти скремблер"},
            {"вид": "инструмент", "имя": "кадры", "кнопка": "Найти кадры"}))

    if п["флагов_к_случайному"] >= 3 and "канальный" not in найдено:
        итог.append(_подсказка(
            "Много флагов 01111110 — кадры HDLC",
            f"флаг встречается в {п['флагов_к_случайному']} раза чаще, чем в случайном ряду: "
            "между кадрами HDLC/PPP стоят флаги, внутри кадров — битстаффинг",
            {"вид": "инструмент", "имя": "кадры", "кнопка": "Найти кадры"}))

    if п["энтропия_байт"] - п["энтропия_мин"] >= 0.15 and п["сдвиг_байта"]:
        итог.append(_подсказка(
            f"Байтовая структура со сдвигом {п['сдвиг_байта']} бит",
            f"энтропия байтов при сдвиге {п['сдвиг_байта']} — {п['энтропия_мин']} бит, при "
            f"других — до {п['энтропия_байт']}: байты начинаются не с первого бита",
            {"вид": "слой", "слой": f"сдвиг {п['сдвиг_байта']}", "кнопка": "Сдвинуть и разобрать"}))

    if abs(п["доля_единиц"] - 0.5) > 0.03 and "скремблер" not in найдено:
        итог.append(_подсказка(
            "Нули и единицы не сбалансированы — скремблера, скорее всего, нет",
            f"единиц {п['доля_единиц'] * 100:.1f} %: после скремблера было бы около 50 %. "
            "Ищите кадры и цикл прямо здесь",
            {"вид": "инструмент", "имя": "кадры", "кнопка": "Найти кадры"},
            {"вид": "инструмент", "имя": "цикл", "кнопка": "Найти цикл"}))

    if случайный:
        итог.append(_подсказка(
            "Структуры не видно",
            "баланс 50 %, байты равновероятны, периодов, пауз и связей нет. Так выглядят: "
            "скремблер без пауз (снимается и через дифференциальное кодирование — "
            "попробуйте слой «nrzi», потом скремблер), метки КАМ в неверной плоскости "
            "(укажите бит на символ и подберите плоскость), шифрование или сжатие "
            "(смотрите карту файла)",
            {"вид": "инструмент", "имя": "скремблер", "кнопка": "Найти скремблер"},
            {"вид": "слой", "слой": "nrzi", "кнопка": "Снять nrzi и разобрать"}))
        итог.append(_подсказка(
            "Если это метки демодулятора КАМ",
            "в неверной плоскости (поворот, отражение, порядок бит, Грей) скремблер не "
            "находится; перебор плоскостей ищет ту, где он есть",
            {"вид": "инструмент", "имя": "плоскость", "кнопка": "Подобрать плоскость"}))

    # LDPC: вслепую без перфорации — автомат (профиль «глубоко»); с перфорацией
    # или длиннее предела — по матрице из стандарта, её помогает найти помощник.
    ldpc_этап = next((э for э in этапы if isinstance(э, dict) and "LDPC" in str(э.get("что"))), None)
    if ldpc_этап is not None or (п["связи_сигм"] >= 20 and похож_на_случайный
                                 and п["пар_без_перехода"] >= 0.02):
        итог.append(_подсказка(
            "Если это LDPC (в том числе с перфорацией)",
            "выколотых позиций в потоке нет, и вслепую такой код не снять; снимается он по "
            "матрице из стандарта: помощник найдёт в библиотеке, какой это код и где его "
            "таблица, вы вставите её в «Матрицы LDPC» (в растре) и снимете слоем "
            "«ldpc ИМЯ выколоты … укорочены …»",
            {"вид": "помощник", "тема": "ldpc", "кнопка": "Спросить помощника про LDPC"}))

    for э in этапы[max(0, этап - 1):этап + 1]:
        if isinstance(э, dict) and э.get("альтернативы"):
            итог.append(_подсказка(
                f"На этапе {э['номер']} были и другие гипотезы",
                "автомат выбрал сильнейшую, но если дальше тупик — проверьте вручную: " +
                "; ".join(э["альтернативы"][:4])))
            break

    итог.append(_подсказка(
        "Спросить помощника",
        "помощник получит ход разбора и приметы потока и ответит по библиотеке: какие "
        "структуры так выглядят и какими приёмами их вскрывают",
        {"вид": "помощник", "кнопка": "Спросить помощника"}))
    return итог


