def контекст(состояние: Dict[str, Any], этап: int, п: Dict[str, Any],
             список: List[Dict[str, Any]]) -> str:
    """Текст для помощника: ход разбора, где встали, приметы и подсказки."""
    строки = [f"Разбор потока «{состояние.get('имя', '')}», {состояние.get('байт', 0)} байт, "
              f"профиль «{состояние.get('профиль', '')}»."]
    for запись in состояние.get("происхождение") or []:
        строки.append(f"Поток выделен вручную: {запись}.")
    for слой in состояние.get("снять") or []:
        строки.append(f"Снято вручную до разбора: {слой}.")
    этапы = состояние.get("этапы") or []
    if этапы:
        строки.append("")
        строки.append("Цепочка, найденная анализатором:")
        for э in этапы:
            строки.append(f"{э['номер']}. [{э['уровень']}] {э['что']} — {э['мера']}")
            for деталь in (э.get("подробно") or [])[:4]:
                строки.append(f"   · {деталь}")
            if э.get("альтернативы"):
                строки.append("   другие гипотезы: " + "; ".join(э["альтернативы"][:4]))
    else:
        строки.append("Анализатор цепочки не нашёл.")
    if состояние.get("не_найдено"):
        строки.append("")
        строки.append("Проверено и не найдено: " + "; ".join(состояние["не_найдено"][:30]))
    if состояние.get("ограничения"):
        строки.append("Ограничения разбора: " + "; ".join(состояние["ограничения"]))
    if состояние.get("карта"):
        строки.append("Карта файла: " + "; ".join(состояние["карта"][:8]))
    строки.append("")
    место = "исходный поток" if этап == 0 else f"поток после этапа {этап}"
    строки.append(f"Приметы ({место}):")
    if п.get("мало"):
        строки.append(f"поток короткий — {п['бит']} бит")
    else:
        строки += [
            f"бит {п['бит']}; единиц {п['доля_единиц'] * 100:.2f} %",
            f"энтропия байтов {п['энтропия_мин']}–{п['энтропия_байт']} бит из 8 "
            f"(наименьшая при сдвиге {п['сдвиг_байта']})",
            f"самая длинная серия {п['серия_до']} бит; в паузах (серии от {ПАУЗА}) "
            f"{п['в_паузах'] * 100:.2f} % бит; пар без перехода {п['пар_без_перехода'] * 100:.1f} %",
            f"линейные связи на окне 16 бит: {п['связи_сигм']}σ; флагов 01111110 — в "
            f"{п['флагов_к_случайному']} раза больше, чем в случайном ряду",
            "периоды: " + ("; ".join(f"{р['период']} бит ({р['сила']}σ"
                                     f"{', ' + р['заметка'] if р['заметка'] else ''})"
                                     for р in п["периоды"]) or "выраженных нет"),
        ]
    строки.append("")
    строки.append("Подсказки анализатора:")
    строки += [f"- {х['что']}: {х['почему']}" for х in список
               if not any(д.get("вид") == "помощник" for д in х["действия"])]
    строки.append("")
    строки.append("Инструменты, доступные аналитику:")
    строки += [f"- {х}" for х in ИНСТРУМЕНТЫ_АНАЛИТИКА]
    return "\n".join(строки)


def вопрос(состояние: Dict[str, Any], этап: int) -> str:
    этапы = состояние.get("этапы") or []
    if этап and этап <= len(этапы):
        где = f"после этапа {этап} ({этапы[этап - 1]['что']})"
    elif этапы:
        где = f"после этапа {len(этапы)} ({этапы[-1]['что']})"
    else:
        где = "в самом начале — анализатор цепочки не нашёл"
    return (f"Разбор неизвестного потока встал {где}. Ход разбора и приметы потока — во "
            "вложении. Какие структуры по теории так выглядят и какими приёмами, по шагам, "
            "их проверить и снять? Опирайся на документы библиотеки и называй их.")


def этап_целиком(состояние: Dict[str, Any], номер: int) -> str:
    """Этап целиком — все подробности и все другие гипотезы (в общем ходе — первые четыре)."""
    этапы = состояние.get("этапы") or []
    if not 1 <= номер <= len(этапы):
        return ""
    э = этапы[номер - 1]
    строки = [f"Этап {номер} целиком: [{э['уровень']}] {э['что']} — {э['мера']}"]
    if э.get("путь"):
        строки.append(f"где в цепочке: {э['путь']}")
    if э.get("выход"):
        строки.append(f"выход этапа: {э['выход']}")
    строки += [f"   · {деталь}" for деталь in э.get("подробно") or []]
    if э.get("альтернативы"):
        строки.append("другие гипотезы на этом уровне:")
        строки += [f"   - {а}" for а in э["альтернативы"]]
    return "\n".join(строки)


def вопрос_об_этапе(состояние: Dict[str, Any], номер: int) -> str:
    """Вопрос помощнику об одном этапе: что найдено, верно ли толкование, что дальше."""
    этапы = состояние.get("этапы") or []
    if not 1 <= номер <= len(этапы):
        return вопрос(состояние, номер)
    э = этапы[номер - 1]
    return (f"На этапе {номер} разбора анализатор нашёл: {э['что']} ({э['мера']}). Подробности "
            "этапа, другие гипотезы и весь ход разбора — во вложении. Что это за структура по "
            "стандартам и документам библиотеки (назови их), верно ли толкование, чем его можно "
            "дополнительно проверить и что делать с потоком после этого этапа?")


def вопрос_о_синхро(найдено: Dict[str, Any]) -> str:
    """Вопрос помощнику о синхрокомбинации: слово в HEX и битах — так его ищет поиск."""
    длина = (f", повторяется через {найдено['длина_кадра']} бит" if найдено.get("длина_кадра")
             else "")
    инверсия = ", приходит инверсной" if найдено.get("инверсия") else ""
    return (f"В потоке после демодуляции синхрокомбинация {найдено['слово']}{длина}{инверсия}. "
            "В каких системах и стандартах используется такая синхрокомбинация, как устроен "
            "кадр (длина, поля, что идёт за синхрокомбинацией: заголовок, кодирование, "
            "скремблирование) и как его разбирать дальше? Опирайся на документы библиотеки и "
            "называй их.")


def вопрос_о_ldpc(состояние: Dict[str, Any], этап: int, п: Dict[str, Any]) -> str:
    """Вопрос помощнику: какой это LDPC, где его матрица и какая перфорация."""
    этапы = состояние.get("этапы") or []
    найдено = next((э for э in этапы if "LDPC" in str(э.get("что"))), None)
    что = (f"Анализатор нашёл: {найдено['что']} ({найдено['мера']}). " if найдено else
           f"Поток после этапа {этап} на вид случаен, но линейно связан "
           f"({п.get('связи_сигм', 0)}σ на окне 16 бит) — похоже на LDPC. ")
    return (что + "Помоги снять его вручную по документам библиотеки: в каких стандартах такой "
            "код (длина слова, скорость, размер циркулянта Z), где в документе матрица "
            "проверок — базовая матрица сдвигов или таблица адресов (назови документ и "
            "таблицу), какие позиции слова выколоты (перфорация) и укорочены, как слово "
            "выравнивается в кадре. Что вставить в анализатор: вид матрицы, Z или n и k, и "
            "указание «ldpc ИМЯ выколоты … укорочены …».")
