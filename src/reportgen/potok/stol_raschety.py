#: График автокорреляции — не больше стольких точек: длиннее — по корзинам из нескольких лагов
#: (в точке — сильнейший лаг корзины и её наименьшее значение), иначе миллион лагов — мегабайты
#: в браузер ради графика шириной в экран.
АВТОКОРРЕЛЯЦИЯ_ТОЧЕК = 1 << 16


def автокорреляция(источник: Источник, наибольший: int) -> dict[str, Any]:
    """Автокорреляция начала массива по лагам 0…наибольший (не дальше половины выборки).

    Лагов больше АВТОКОРРЕЛЯЦИЯ_ТОЧЕК — точки по корзинам из ``шаг`` лагов: ``r`` — наибольшее
    в корзине, ``лаги`` — на каком лаге оно, ``r_мин`` — наименьшее (для огибающей графика).
    """
    from . import cikl  # noqa: PLC0415
    выборка = источник.участок(0, cikl.ВЫБОРКА)
    лагов = min(int(наибольший), len(выборка) // 2)
    шум = round(1.0 / len(выборка) ** 0.5, 5) if len(выборка) else 0.0
    if лагов < 1:
        return {"r": [], "бит": len(выборка), "шум": шум, "лагов": 0, "шаг": 1}
    r = cikl.автокорреляция(выборка, лагов)
    итог: dict[str, Any] = {"бит": len(выборка), "шум": шум, "лагов": лагов, "шаг": 1}
    if лагов + 1 <= АВТОКОРРЕЛЯЦИЯ_ТОЧЕК:
        итог["r"] = [round(float(x), 4) for x in r]
        return итог
    шаг = -(-(лагов + 1) // АВТОКОРРЕЛЯЦИЯ_ТОЧЕК)
    корзин = -(-(лагов + 1) // шаг)
    полные = np.full(корзин * шаг, np.nan)
    полные[:лагов + 1] = r
    корзины = полные.reshape(корзин, шаг)
    где = np.nanargmax(корзины, axis=1)
    итог.update({"шаг": int(шаг), "r": [round(float(x), 4) for x in корзины[np.arange(корзин), где]],
                 "лаги": (np.arange(корзин) * шаг + где).tolist(),
                 "r_мин": [round(float(x), 4) for x in np.nanmin(корзины, axis=1)]})
    return итог


def инструмент(источник: Источник, маска: Any, вид: str, k: int, параметры: dict[str, Any]) -> dict[str, Any]:
    from . import rastr  # noqa: PLC0415
    биты = _по_маске(источник.биты(), маска)
    найдено = rastr.инструмент(биты, вид, k, **параметры)
    итог = rastr.в_словарь(найдено)
    if итог is not None and not any(п.startswith("слой для снятия: ") for п in итог["подробно"]):
        # Инструмент нашёл то же, что автомат, — и шагом стола это снимается так же (журнал → «Снять»).
        from .razbor import слои_находки  # noqa: PLC0415
        слои = слои_находки(найдено)
        if len(слои) == 1:
            итог["подробно"].append(f"слой для снятия: {слои[0]}")
    return {"found": итог, "bits": int(len(биты))}


