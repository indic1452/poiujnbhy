def ldpc_восстановить(источник: Источник, n: int, начало: int, шаг: int, бит: int, срок: float,
                      снимок: str) -> dict[str, Any]:
    """«Восстановить матрицу» окна LDPC: проверки по словам потока (ldpc_vosst). Найденное пишется в файл
    ``снимок`` после каждого раунда (не чаще раза в 3 с) и в конце: «Стоп» снимает задачу, а найденное
    сервер читает из снимка."""
    from . import ispolniteli, ldpc_vosst  # noqa: PLC0415
    биты = np.asarray(источник.участок(0, бит))
    было = [0.0]

    def снять_снимок(проверки: list, сведения: dict) -> None:
        if time.monotonic() - было[0] >= 3.0:
            было[0] = time.monotonic()
            ldpc_vosst.записать_снимок(снимок, проверки, сведения)

    итог = ldpc_vosst.восстановить_по_потоку(биты, n, начало=начало, шаг=шаг, срок=срок,
                                             стоп=ispolniteli.отменено, ход=ВХоде(), снимок=снять_снимок)
    словарь = итог.словарь()
    ldpc_vosst.записать_снимок(снимок, итог.проверки, {**{к: в for к, в in словарь.items() if к != "ход"},
                                                      "раунд": итог.раундов})
    return словарь


def моддекодер_просмотр(источник: Источник, параметры: dict[str, Any], показать: int, с: int,
                        кадр_: Any) -> dict[str, Any]:
    import base64  # noqa: PLC0415

    from . import moddekoder  # noqa: PLC0415
    н = moddekoder.настройки(параметры)
    выборка = источник.участок(0, moddekoder.ВЫБОРКА_СИМВОЛОВ * н.k)
    всего = len(источник)
    д = moddekoder.декодер(н)
    кадр = moddekoder.кадр(кадр_)
    ряд = д.применить(выборка)
    try:
        вариантов: int | None = moddekoder.число_вариантов(н)
    except ValueError:
        вариантов = None
    показано = ряд[с:с + показать]
    return {"биты": base64.b64encode(np.packbits(показано).tobytes()).decode("ascii"),
            "бит": int(len(показано)), "с": с, "мера": round(moddekoder.мера(ряд, кадр), 3),
            "мера_исходного": round(moddekoder.мера(выборка[:len(ряд)], кадр), 3),
            "таблица": list(д.таблица), "номера": list(д.номера), "метки": list(д.метки),
            "запись": moddekoder.запись(д.таблица or д.метки), "описание": д.описание, "слой": д.слой(),
            "символов": всего // н.k, "хвост": всего % н.k, "вариантов": вариантов}


def моддекодер_все(источник: Источник, параметры: dict[str, Any], с: int, по: int, срок: float, лучших: int,
                   кадр_: Any) -> dict[str, Any]:
    from . import moddekoder  # noqa: PLC0415
    н = moddekoder.настройки(параметры)
    выборка = источник.участок(0, moddekoder.ВЫБОРКА_СИМВОЛОВ * н.k)
    return moddekoder.перебор(выборка, н, с, по, срок=срок, лучших=лучших, кадр=moddekoder.кадр(кадр_))


#: Проба равноценных идёт, пока окно ещё перебирает варианты: ниже его приоритетом (на столько),
#: чтобы перебор не замедлялся, — проба берёт процессор, когда перебору он не нужен.
ПРОБА_НИЖЕ = 5


def _ниже_приоритетом(насколько: int):
    """Контекст: процесс исполнителя на время расчёта уступает процессор (POSIX; где нельзя — как есть)."""
    import contextlib  # noqa: PLC0415
    import os  # noqa: PLC0415

    @contextlib.contextmanager
    def контекст():
        было = None
        try:
            было = os.getpriority(os.PRIO_PROCESS, 0)
            os.setpriority(os.PRIO_PROCESS, 0, min(19, было + насколько))
        except (AttributeError, OSError):
            было = None
        try:
            yield
        finally:
            if было is not None:
                try:
                    os.setpriority(os.PRIO_PROCESS, 0, было)
                except OSError:                    # вернуть приоритет вправе не всякий — останется ниже
                    pass
    return контекст()


def моддекодер_равноценные(источник: Источник, параметры: dict[str, Any], таблицы: list[list[int]],
                           известные: dict[str, dict[str, Any]], кадр_: Any, длина: int, начало: int,
                           срок: float, фоном: bool = False) -> dict[str, Any]:
    """«Дек. всех» → как выбрал бы автомат: факты пробы кода в кадрах под таблицами (``modem.факты_равноценных``).

    Таблицы идут в порядке окна (мера, геометрические, номер): у тех, что окно ещё не оценило
    (дополнение по инверсии бит метки), мера считается здесь же (``moddekoder.меры_таблиц``) — от
    порядка зависит лишь, сколько ПСП блока проверять. ``фоном`` — проба заранее, пока окно перебирает:
    ниже приоритетом (``ПРОБА_НИЖЕ``). Кадры — как у автомата: по служебным словам
    (``razbor._кадры_модема``) на начале массива; не нашлись — ровно через ``длина`` с бита ``начало``.
    """
    from . import moddekoder, modem, razbor  # noqa: PLC0415
    н = moddekoder.настройки(параметры)
    выборка = источник.участок(0, razbor.ВЫБОРКА_БИТ)
    новые = [т for т in таблицы if moddekoder.запись(т) not in известные]
    оценки = dict(известные)
    for о in moddekoder.меры_таблиц(выборка[:moddekoder.ВЫБОРКА_СИМВОЛОВ * н.k], н, новые, moddekoder.кадр(кадр_)):
        оценки[о["таблица"]] = {**о, "номер": None}

    def порядок(т: list[int]) -> tuple:
        о = оценки[moddekoder.запись(т)]
        return -float(о["мера"]), not о.get("как"), о.get("номер") if о.get("номер") is not None else 1 << 62

    таблицы = sorted(таблицы, key=порядок)
    кадры = razbor._кадры_модема(выборка, длина)
    if кадры is not None:
        начала, длина = list(кадры[0]), int(кадры[1])
    else:
        начала = list(range(начало % длина, len(выборка) - длина + 1, длина))
    with _ниже_приоритетом(ПРОБА_НИЖЕ if фоном else 0):
        итог = modem.факты_равноценных(выборка, н.k, таблицы, начала, длина, срок=срок)
    итог["кадры"]["по_словам"] = кадры is not None
    итог["порядок"] = [moddekoder.запись(т) for т in таблицы]
    return итог


def ткб_поиск(источник: Источник, тело: dict[str, Any], срок: float) -> dict[str, Any]:
    """Поиск блочных турбокодов (часть окна) — см. ``api.potok_tkb_search``: тело уже проверено сервером."""
    from . import razbor, tpc, tpc_rezhimy  # noqa: PLC0415
    ряд = источник.участок(0, tpc_rezhimy.ВЫБОРКА)
    с, по, кадры, кадр = тело["с"], тело["по"], list(тело["кадры"]), тело["кадр"]
    синхрослово = тело["синхрослово"]
    режимы = [tpc_rezhimy.режим(и) for и in тело["режимы"]] or list(tpc_rezhimy.КАТАЛОГ)
    по = min(по, len(режимы))
    if кадр:
        кадры = sorted(set(кадры) | {кадр})
    elif с == 0 and not кадры:
        кадры = tpc_rezhimy.длины_кадра(ряд, синхрослово)
        if not синхрослово.strip():
            # Как автомат: кадр — по служебным словам (cikl.найти сокращает сверхцикл до кадра,
            # чередующееся слово — пополам). Пик автокорреляции у сверхкадра (у K2964 — 23712 = 8 × 2964)
            # давал длины, кратные кадру, без самого кадра: слепой поиск шёл по ним, а перебор
            # режимов по трём длинам — минутами. Кратные кадру длины не пробуются.
            по_словам = razbor._кадры_модема(ряд, None)
            if по_словам is not None:
                кадры = [по_словам[1]] + [к for к in кадры if к % по_словам[1]]
    метки = None
    м = тело.get("метки")
    if isinstance(м, dict):
        метки = tpc_rezhimy.Метки(*м["поля"])
    elif с == 0 and not тело.get("без_меток") and not тело.get("слепой"):
        метки = tpc_rezhimy.найти_метки(ряд, tpc_rezhimy.периоды_меток(ряд, кадры))
    if тело.get("слепой"):
        варианты = []
        try:
            if кадры:
                данные, находка = tpc.снять_в_кадрах(ряд, razbor.начала_кадров(ряд, кадры[0]), кадры[0])
                находка.свойства["слой"] = f"ткб кадр {кадры[0]}"
            else:
                данные, находка = tpc.снять(ряд)
                находка.свойства["слой"] = (f"ткб строка {находка.свойства['строка']} начало "
                                            f"{находка.свойства['начало']} столбец {находка.свойства['столбец']} "
                                            f"блок {находка.свойства['блок']}"
                                            + (f" глубина {находка.свойства['глубина']} плоскость "
                                               f"{находка.свойства['плоскость']}" if находка.свойства.get("глубина")
                                               else " двумерный"))
            if находка.уверенность >= tpc_rezhimy.НАЙДЕН_ОТ:
                в = tpc_rezhimy.Вариант(tpc_rezhimy.КАТАЛОГ[0], int(находка.свойства.get("кадр") or 0),
                                        int(находка.свойства.get("начало_блока") or 0), float(находка.уверенность),
                                        чисто=float(находка.уверенность), слепой=True, находка=находка)
                варианты.append(в.в_словарь())
        except ValueError:
            pass
        return {"найдено": варианты, "по": по, "всего": len(режимы), "кадры": кадры}
    итог = tpc_rezhimy.поиск(ряд, режимы=режимы, кадры=кадры, с=с, по=по, срок=срок, метки=метки)
    return {"найдено": [в.в_словарь() for в in tpc_rezhimy.упорядочить(итог["найдено"])],
            "по": итог["по"], "всего": итог["всего"], "кадры": кадры,
            "метки": метки.в_словарь() if метки is not None else None}


def ткб_снять(источник: Источник, слой: str, бит: int | None, показать: int) -> dict[str, Any]:
    """Снять ТКБ слоем окна: просмотр (``бит`` — сколько с начала) или весь этап (``бит`` None — для REC)."""
    import base64  # noqa: PLC0415

    from . import razbor, tpc_rezhimy  # noqa: PLC0415
    ряд = источник.участок(0, None if бит is None else бит)
    данные, находка = razbor.снять_вручную(ряд, слой)
    if бит is None:
        return {"данные": np.packbits(данные).tobytes(), "бит": int(len(данные)),
                "режим": str((находка.свойства or {}).get("режим") or "tkb")}
    показано = min(len(данные), показать)
    блок: dict[str, Any] | None = None
    м = re.search(r"режим\s+(\S+)", слой, re.IGNORECASE)
    if м:
        # Слой снят — режим в каталоге есть; раскладка — с укорочением B, подобранным по кадру.
        г = tpc_rezhimy.геометрия(tpc_rezhimy.режим(м.group(1)), бит_укор=(находка.свойства or {}).get("бит_укор"))
        блок = {"форма": list(г.форма), "метки": base64.b64encode(tpc_rezhimy.метки_мест(г).tobytes()).decode("ascii")}
    # Первая строка подробностей слоя ТКБ — что снято и мера (находка слоя — «снято по указанию»).
    return {"что": находка.подробно[0] if находка.подробно else находка.что, "мера": находка.мера,
            "уверенность": находка.уверенность, "подробно": находка.подробно,
            "биты": base64.b64encode(np.packbits(данные[:показано]).tobytes()).decode("ascii"),
            "бит": int(показано), "данных": int(len(данные)), "блок": блок,
            "свойства": {к: v for к, v in (находка.свойства or {}).items() if isinstance(v, (int, float, str))}}


