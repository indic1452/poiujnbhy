"""Тяжёлые расчёты рабочего стола — в исполнителях (отдельных процессах), не в веб-сервере.

Окна поиска стола (поиск периода, автокорреляция, скремблер, моддекодер, ТКБ, LDPC,
разметка, статистика NIST…) считают секунды чистого питона. В процессе сервера такой
расчёт держит интерпретатор (GIL), и лёгкие запросы остальных людей ждут его. Поэтому
сами расчёты — здесь, функциями уровня модуля: сервер передаёт исполнителю
``Источник`` (путь файла массива и его длину) и параметры окна, исполнитель сам читает
нужные биты и возвращает готовый ответ (словари, числа, строки — всё, что передаёт
pickle). Проверка прав, разбор запроса и запоминание итогов остаются в сервере.

Функции получают ``Источник``, а не биты: массив в сотни мегабайт передавать в процесс
незачем — исполнитель читает с диска только нужный участок и держит распакованные
массивы в своей памяти (``КЭШ_БИТ``), чтобы следующее действие над тем же массивом не
читало файл заново.
"""

from __future__ import annotations

import re
import threading
import time
from collections import OrderedDict
from dataclasses import dataclass
from typing import Any

import numpy as np

#: Распакованных бит в памяти одного исполнителя (по байту на бит): 256 МБ на процесс.
КЭШ_БИТ = 1 << 28

_кэш: OrderedDict[tuple, np.ndarray] = OrderedDict()
_кэш_lock = threading.Lock()


@dataclass(frozen=True)
class Источник:
    """Массив задания для исполнителя: файл (биты упакованы, старший первым) и длина в битах.

    ``метка`` и ``размер`` — время изменения и размер файла: пересобранный массив — другой ключ.
    """

    файл: str
    бит: int
    метка: int = 0
    размер: int = 0
    #: Часть файла и порядок бит (массив по ссылке на файл сервера — см. hranenie), отпечаток ссылки.
    смещение: int = 0
    развернуть: bool = False
    ссылка: dict | None = None
    #: Массив больше стольких бит целиком в память не берётся: ``биты()`` — его начало (0 — без предела).
    предел: int = 0

    def __len__(self) -> int:
        return self.бит

    @property
    def по_ссылке(self) -> bool:
        return bool(self.ссылка or self.смещение or self.развернуть)

    @property
    def часть(self) -> bool:
        """``биты()`` отдаёт лишь начало массива (он больше предела памяти)."""
        return bool(self.предел) and self.бит > self.предел

    def _массив(self):
        from .hranenie import Источник as Массив  # noqa: PLC0415
        return Массив(self.файл, смещение=self.смещение, бит=self.бит, развернуть=self.развернуть,
                      ссылка=self.ссылка)

    def биты(self) -> np.ndarray:
        """Весь массив (только для чтения), из памяти исполнителя, если уже читался.

        Массив больше ``предел`` бит (гигабайтный файл — 8 Гбит) целиком не распаковывается: отдаётся
        его начало в пределах памяти, сервер помечает ответ «по первым N МБ» (``часть``)."""
        if self.часть:
            return self.участок(0, self.предел)
        ключ = (self.файл, self.метка, self.размер, self.смещение, self.развернуть)
        with _кэш_lock:
            биты = _кэш.get(ключ)
            if биты is not None:
                _кэш.move_to_end(ключ)
                return биты
        if self.по_ссылке:
            биты = self._массив().все()
        else:
            with open(self.файл, "rb") as поток:
                биты = np.unpackbits(np.frombuffer(поток.read(), dtype=np.uint8))[:self.бит]
        биты.flags.writeable = False
        if len(биты) <= КЭШ_БИТ:
            with _кэш_lock:
                _кэш[ключ] = биты
                while sum(len(б) for б in _кэш.values()) > КЭШ_БИТ:
                    _кэш.popitem(last=False)
        return биты

    def участок(self, от: int = 0, до: int | None = None) -> np.ndarray:
        """Биты [от, до) — без распаковки всего файла (если массив уже в памяти — из неё)."""
        до = self.бит if до is None else max(0, min(int(до), self.бит))
        от = max(0, min(int(от), до))
        with _кэш_lock:
            биты = _кэш.get((self.файл, self.метка, self.размер, self.смещение, self.развернуть))
        if биты is not None:
            return биты[от:до]
        if self.по_ссылке:
            биты = self._массив().биты(от, до)
            биты.flags.writeable = False
            return биты
        with open(self.файл, "rb") as поток:
            поток.seek(от // 8)
            кусок = поток.read((до + 7) // 8 - от // 8)
        биты = np.unpackbits(np.frombuffer(кусок, dtype=np.uint8))[от % 8:от % 8 + до - от]
        биты.flags.writeable = False
        return биты


