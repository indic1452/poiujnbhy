def проба_шагов(источник: Источник, шаги: list[dict[str, Any]], бит: int) -> dict[str, Any]:
    from . import rastr  # noqa: PLC0415
    from .bity import в_байты  # noqa: PLC0415
    проба = источник.участок(0, бит)
    шаги = rastr.проверить_шаги(шаги)
    итог, описание = rastr.применить(проба, шаги)
    доля = float(np.mean(итог)) if len(итог) else 0.0
    return {"бит_на_входе": int(len(проба)), "весь_поток": int(len(источник)), "бит_на_выходе": int(len(итог)),
            "описание": описание, "доля_единиц": round(доля, 4), "начало": в_байты(итог[:4096]).hex()}


