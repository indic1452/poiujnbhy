def скремблер(источник: Источник, степень: int, отводов: int, первый: int, аддитивный: bool, кадр: int,
              начало_кадра: int, установок: int) -> dict[str, Any]:
    from . import skrembler  # noqa: PLC0415
    биты = источник.участок(первый, первый + skrembler.ВЫБОРКА_ПЕРЕБОРА)
    итог = skrembler.перебор_степени(биты, степень, отводов)
    for номер, лучший in enumerate(итог["лучшие"]):
        # Мультипликативный: регистр — первые биты потока (с первого бита дескремблера).
        лучший["самосинхр"] = "".join(str(int(б)) for б in биты[:степень])
        if аддитивный and номер < установок:
            уст = skrembler.начальная_установка(
                биты, лучший["отводы"], кадр=кадр, начало_кадра=(начало_кадра - первый) % кадр if кадр else 0)
            # Места — в битах массива, а не выборки с первого бита.
            if уст["способ"] == "кадр":
                уст["место"] = (уст["место"] + первый) % кадр
                уст["слой"] = уст["слой"].rsplit(" начало ", 1)[0] + f" начало {уст['место']}"
            else:
                уст["место"] += первый
                if " с бита " in уст["слой"]:
                    уст["слой"] = уст["слой"].rsplit(" с бита ", 1)[0] + f" с бита {уст['место']}"
            лучший["аддитивный"] = уст
    return итог


def статистика(источник: Источник, от: int, длина: int, разметка: dict[str, Any] | None) -> dict[str, Any]:
    from . import rastr, statistika_bit  # noqa: PLC0415
    # ENT считает байты участка, упакованные с его первого бита.
    биты = (rastr.по_разметке(источник.биты(), разметка, "взять")[от:от + длина] if разметка
            else источник.участок(от, от + длина))
    return statistika_bit.проверить(биты)


