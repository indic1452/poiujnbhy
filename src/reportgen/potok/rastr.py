# -*- coding: utf-8 -*-
"""Растр потока и ручные инструменты аналитика.

Автоматический разбор — не всё. Аналитик привык смотреть на поток глазами:
сложить его по периоду в картинку (строка — цикл, 0 — чёрный, 1 — зелёный),
подвигать период и сдвиг, пока синхрослово не встанет столбиком, выделить
столбцы канала, вырезать их в отдельный поток и дальше разбирать его —
руками или автоматом. Здесь — серверная часть этого:

- окно бит для отрисовки (исходный поток или поток после любого этапа);
- кандидаты периода по автокорреляции;
- маска канала: период, сдвиг, позиции бит в цикле → поток канала;
- быстрые инструменты над потоком или каналом: найти скремблер, код,
  HDLC/GFP/ATM, цикл, модуляционную плоскость; снять слой вручную.

Всё, что меняет поток (канал по маске, снятый слой), становится новым
«производным» разбором — с тем же растром и теми же инструментами, и его
можно отдать и на автоматический разбор.
"""

from __future__ import annotations

import base64
from typing import Any, Dict, List, Optional, Sequence

import numpy as np

from . import cikl, gfp, hdlc, kod, oktety, ploskost, skrembler
from .bity import в_биты
from .nahodka import Находка

#: Больше этого за один запрос окна не отдаём: растр рисует видимое.
ОКНО_ДО = 1 << 22
ПЕРИОД_ДО = 1 << 16
#: Порог пика периода в сигмах шума автокорреляции (с поправкой на число лагов).
ПОРОГ_СИГМ = 7.0


def окно(биты: np.ndarray, начало: int, сколько: int) -> Dict[str, Any]:
    """Кусок потока для отрисовки: биты, упакованные старшим первым, в base64."""
    начало = max(0, int(начало))
    сколько = max(0, min(int(сколько), ОКНО_ДО, len(биты) - начало))
    кусок = биты[начало:начало + сколько]
    return {"всего": int(len(биты)), "начало": начало, "бит": int(len(кусок)),
            "данные": base64.b64encode(np.packbits(кусок).tobytes()).decode("ascii")}


def _новый(r: np.ndarray, p: int, q: int, шум: float) -> bool:
    """Даёт ли период p, кратный q, новое: заметно ли меньше расхождений, чем при q.

    Кратное верного периода повторяет его пик (r[2P] ≈ r[P]) — это гармоника.
    Настоящий больший цикл (синхрослово раз в 256 бит над байтовым заполнением,
    FAS через цикл у E1) снимает заметную часть оставшихся расхождений.
    """
    прирост = float(r[p] - r[q])
    return прирост >= max(4 * шум, min(0.2 * (1 - float(r[q])), 0.25 * abs(float(r[q]))))


def периоды(биты: np.ndarray, сколько: int = 8) -> List[Dict[str, Any]]:
    """Кандидаты периода: пики автокорреляции, сильнейшие первыми (в сигмах шума).

    Пики стоят и на кратных периода — это гармоники, их не показываем. Но
    кратный бывает и настоящим: у E1 байтовое заполнение даёт период 8,
    синхрослово — цикл 256, а FAS через цикл — 512. Кратный остаётся в списке,
    только если снимает заметную часть расхождений (см. ``_новый``), и
    помечается, из скольких меньших периодов он сложен. Выбирает аналитик.
    """
    выборка = биты[:cikl.ВЫБОРКА]
    if len(выборка) < 64 * 8:
        return []
    наибольший = min(ПЕРИОД_ДО, len(выборка) // 8)
    r = cikl.автокорреляция(выборка, наибольший)
    # Шум автокорреляции — 1/√N, только если биты независимы. У манчестера и
    # других кодов в линии соседние произведения повторяются, и шум вдвое
    # больше по дисперсии: берём его по самим лагам (медиана модулей), но не
    # больше трёх теоретических — иначе у потока, где коррелировано всё,
    # «шумом» стала бы сама структура.
    шум = 1.0 / np.sqrt(len(выборка))
    шум = max(шум, min(1.4826 * float(np.median(np.abs(r[8:]))), 3 * шум))
    r[:8] = 0
    # Лагов десятки тысяч: 4 сигмы шум превысит где-нибудь почти наверняка;
    # пики слабее четверти главного — обычно отзвуки синхрослова на почти кратных.
    порог = max(ПОРОГ_СИГМ * шум, 0.25 * float(r.max()))
    взятые: List[int] = []
    for место in np.argsort(-r)[:400]:
        место = int(место)
        if r[место] < порог or len(взятые) >= сколько:
            break
        # Свести к наименьшему делителю, над которым пик ничего не прибавляет.
        основной = next((d for d in range(8, место + 1)
                         if место % d == 0 and r[d] >= порог and not _новый(r, место, d, шум)),
                        место)
        if основной in взятые or any(основной % п == 0 and not _новый(r, основной, п, шум)
                                      for п in взятые):
            continue
        # Отзвук синхрослова: лаг рядом с кратным взятого периода (синхрослово
        # похоже само на себя со сдвигом на бит-другой) и слабее его.
        if any(основной > п and min(основной % п, п - основной % п) <= max(2, п // 8)
               and r[основной] < r[п] for п in взятые):
            continue
        взятые.append(основной)
    итог = []
    for п in взятые:
        меньшие = [q for q in взятые if q < п and п % q == 0]
        итог.append({"период": п, "сила": round(float(r[п] / шум), 1),
                     "заметка": f"сверхцикл: {п // max(меньшие)} × {max(меньшие)}"
                     if меньшие else ""})
    return итог


def по_маске(биты: np.ndarray, маска: Dict[str, Any]) -> np.ndarray:
    """Поток канала: из каждого цикла — биты на заданных позициях, по порядку."""
    период = int(маска["период"])
    сдвиг = int(маска.get("сдвиг", 0)) % max(1, период)
    позиции = sorted({int(п) for п in маска.get("позиции", []) if 0 <= int(п) < период})
    if период < 1 or not позиции:
        raise ValueError("маска пуста: нужен период и хотя бы одна позиция в цикле")
    ряд = биты[сдвиг:]
    циклов = len(ряд) // период
    return ряд[:циклов * период].reshape(циклов, период)[:, позиции].reshape(-1)


def столбцы(биты: np.ndarray, период: int, сдвиг: int = 0, циклов: int = 4096) -> List[float]:
    """Доля единиц в каждом столбце растра — по первым ``циклов`` циклам."""
    период = int(период)
    if период < 1 or период > ПЕРИОД_ДО:
        raise ValueError("период — от 1 до 65 536 бит")
    ряд = биты[int(сдвиг) % период:]
    сколько = min(циклов, len(ряд) // период)
    if not сколько:
        return []
    return [round(float(х), 3) for х in
            ряд[:сколько * период].reshape(сколько, период).mean(axis=0)]


#: Быстрые инструменты: имя → что делает. Все — над битами потока или канала.
ИНСТРУМЕНТЫ = {
    "скремблер": "найти скремблер (самосинхронизирующийся или аддитивный, любые отводы)",
    "код": "найти помехоустойчивый код (свёрточный 1/2, короткий блочный)",
    "кадры": "найти кадры: HDLC (битовый и октетный стаффинг), GFP, ATM",
    "цикл": "найти цикл и синхрослово, каналы",
    "плоскость": "подобрать модуляционную плоскость КАМ (нужно k — бит на символ)",
    "плоскость-фм": "подобрать модуляционную плоскость ФМ (нужно k — бит на символ)",
    "скремблер-кадр": "аддитивная ПСП со сбросом в каждом кадре: отводы и начальное состояние",
}


def _скремблер_по_кадру(биты: np.ndarray, *, период: int = 0, сдвиг: int = 0, пропуск: int = 0,
                        отводы: Sequence[int] = ()) -> Optional[Находка]:
    """Кадровый скремблер по растру: кадр — период, начало — сдвиг растра."""
    if период < 16:
        raise ValueError("нужна длина кадра — период растра (засинхронизируйте растр)")
    найдено = skrembler.найти_по_кадру(биты, int(период), начало=int(сдвиг) % int(период),
                                       пропуск=int(пропуск), отводы=list(отводы) or None)
    if найдено is None:
        return None
    слой = (f"аддитивный отводы {','.join(map(str, найдено['отводы']))} кадр {период} "
            f"начальное {найдено['начальное']} пропуск {пропуск} начало {int(сдвиг) % int(период)}")
    return Находка(
        уровень="скремблер", что=f"кадровый аддитивный скремблер {найдено['полином']}",
        уверенность=float(найдено["совпало"]),
        мера=f"устойчивых столбцов {найдено['устойчивых']}; после снятия в них нули — "
             f"{найдено['совпало'] * 100:.1f} %",
        подробно=[f"начальное состояние (первые {max(найдено['отводы'])} бит ПСП после сброса): "
                  f"{найдено['начальное']}", найдено["способ"], f"слой для снятия: {слой}"],
        дальше=None, вид_дальше="")


def инструмент(биты: np.ndarray, имя: str, k: int = 0, **параметры: Any) -> Optional[Находка]:
    выборка = биты[:1 << 23]
    if имя == "скремблер-кадр":
        return _скремблер_по_кадру(выборка, **параметры)
    if имя == "скремблер":
        return skrembler.найти(выборка)
    if имя == "код":
        return kod.найти(выборка, длинные=False)
    if имя == "кадры":
        return hdlc.найти(выборка) or oktety.найти(выборка) or gfp.найти(выборка)
    if имя == "цикл":
        return cikl.найти(выборка)
    if имя == "плоскость":
        if not k:
            raise ValueError("для плоскости нужно k — бит на символ КАМ")
        return ploskost.найти(выборка, int(k), лучших=1)
    if имя == "плоскость-фм":
        if not k:
            raise ValueError("для плоскости нужно k — бит на символ ФМ")
        return ploskost.найти_фм(выборка, int(k), лучших=1)
    raise ValueError(f"нет инструмента «{имя}»")


def в_словарь(находка: Optional[Находка]) -> Optional[Dict[str, Any]]:
    if находка is None:
        return None
    return {"уровень": находка.уровень, "что": находка.суть, "мера": находка.мера,
            "уверенность": round(float(находка.уверенность), 3),
            "подробно": list(находка.подробно)}


def производный(биты: np.ndarray, маска: Optional[Dict[str, Any]],
                снять: Sequence[str]) -> tuple[bytes, List[str]]:
    """Новый поток: канал по маске и/или снятые вручную слои. Биты → байты и описание."""
    from .razbor import снять_вручную  # noqa: PLC0415 — круговой импорт

    описание: List[str] = []
    if маска:
        биты = по_маске(биты, маска)
        описание.append(f"канал по маске: период {маска['период']}, сдвиг "
                        f"{маска.get('сдвиг', 0)}, позиции {_диапазоны(маска.get('позиции', []))}")
    for слой in снять:
        биты, запись = снять_вручную(биты, слой)
        описание.append(запись.что)
    return np.packbits(биты).tobytes(), описание


def описать_шаг(шаг: Dict[str, Any]) -> str:
    """Шаг ручной обработки словами: для имени узла и дерева."""
    if шаг.get("вид") == "маска":
        маска = шаг["маска"]
        return (f"канал по маске: период {маска['период']}, сдвиг {маска.get('сдвиг', 0)}, "
                f"позиции {_диапазоны(маска.get('позиции', []))}")
    return str(шаг.get("слой", ""))


def проверить_шаги(шаги: Sequence[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """Шаги из запроса → чистый список {вид, маска|слой, вкл}; ошибки формы — ValueError."""
    итог = []
    for шаг in шаги:
        if not isinstance(шаг, dict):
            raise ValueError("шаг — объект {вид, маска | слой}")
        вкл = bool(шаг.get("вкл", True))
        if шаг.get("вид") == "маска":
            маска = шаг.get("маска") or {}
            период = int(маска.get("период", 0))
            позиции = sorted({int(п) for п in маска.get("позиции", []) if 0 <= int(п) < период})
            if период < 1 or период > ПЕРИОД_ДО or not позиции:
                raise ValueError("маска пуста: нужен период и хотя бы одна позиция в цикле")
            итог.append({"вид": "маска", "вкл": вкл, "маска": {
                "период": период, "сдвиг": int(маска.get("сдвиг", 0)), "позиции": позиции}})
        elif шаг.get("вид") == "слой" and str(шаг.get("слой", "")).strip():
            итог.append({"вид": "слой", "вкл": вкл, "слой": str(шаг["слой"]).strip()[:500]})
        else:
            raise ValueError("шаг — «маска» или «слой»")
    if len(итог) > 24:
        raise ValueError("шагов больше 24")
    return итог


def применить(биты: np.ndarray, шаги: Sequence[Dict[str, Any]], ход=None
              ) -> tuple[np.ndarray, List[str]]:
    """Включённые шаги по порядку: маска канала или снятие слоя. Биты и описание."""
    from .razbor import снять_вручную  # noqa: PLC0415 — круговой импорт

    описание: List[str] = []
    for номер, шаг in enumerate(шаги, start=1):
        if not шаг.get("вкл", True):
            continue
        if ход:
            ход(f"шаг {номер}: {описать_шаг(шаг)}")
        if шаг["вид"] == "маска":
            биты = по_маске(биты, шаг["маска"])
            описание.append(описать_шаг(шаг))
        else:
            биты, запись = снять_вручную(биты, шаг["слой"])
            описание.append(запись.что + (": " + "; ".join(запись.подробно[:3])
                                           if запись.подробно else ""))
        if not len(биты):
            raise ValueError(f"после шага {номер} поток пуст")
    return биты, описание


def _диапазоны(позиции: Sequence[int]) -> str:
    п = sorted({int(х) for х in позиции})
    части, начало = [], None
    for i, х in enumerate(п):
        if начало is None:
            начало = х
        if i + 1 == len(п) or п[i + 1] != х + 1:
            части.append(str(начало) if начало == х else f"{начало}–{х}")
            начало = None
    return ", ".join(части)


def биты_файла(данные: bytes) -> np.ndarray:
    return в_биты(данные)
