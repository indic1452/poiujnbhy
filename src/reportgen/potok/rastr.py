#: Больше этого за один запрос окна не отдаём: растр рисует видимое.
ОКНО_ДО = 1 << 22
ПЕРИОД_ДО = 1 << 16
#: Порог пика периода в сигмах шума автокорреляции (с поправкой на число лагов).
ПОРОГ_СИГМ = 7.0


def окно(биты: np.ndarray, начало: int, сколько: int) -> dict[str, Any]:
    """Кусок потока для отрисовки: биты, упакованные старшим первым, в base64."""
    начало = max(0, int(начало))
    сколько = max(0, min(int(сколько), ОКНО_ДО, len(биты) - начало))
    кусок = биты[начало:начало + сколько]
    return {"всего": int(len(биты)), "начало": начало, "бит": int(len(кусок)),
            "данные": base64.b64encode(np.packbits(кусок).tobytes()).decode("ascii")}


#: Сколько ячеек (строки × пиксели) отдаёт сетка за раз.
СЕТКА_ДО = 1 << 22
#: Сколько строк таблицы кадров за раз.
СТРОК_ДО = 2000


def сетка(биты: np.ndarray, период: int, сдвиг: int, строка: int, строк: int,
          столбец: int, столбцов: int, на_пиксель: int = 1) -> dict[str, Any]:
    """Прямоугольник растра: строки × столбцы, для битового просмотра на рабочем столе.

    ``на_пиксель`` > 1 — сжатие по горизонтали: в пикселе доля единиц в стольких
    битах (0…255), так кадр в десятки тысяч бит помещается на экран целиком.
    При 1 — сами биты, упакованные по строкам (каждая строка — с целого байта).
    """
    период = max(1, min(int(период), ПЕРИОД_ДО * 16))
    сдвиг = max(0, int(сдвиг))
    на_пиксель = max(1, min(int(на_пиксель), 64))
    всего_строк = max(0, (len(биты) - сдвиг) // период)
    строка = max(0, min(int(строка), max(0, всего_строк - 1)))
    строк = max(0, min(int(строк), всего_строк - строка))
    столбец = max(0, min(int(столбец), период - 1))
    столбцов = max(1, min(int(столбцов), период - столбец))
    пикселей = -(-столбцов // на_пиксель)
    if строк * пикселей * max(1, 8 // на_пиксель if на_пиксель < 8 else 1) > СЕТКА_ДО:
        строк = max(1, СЕТКА_ДО // max(1, пикселей))
    if not строк:
        return {"всего_строк": всего_строк, "строк": 0, "пикселей": пикселей, "данные": "",
                "вид": "биты" if на_пиксель == 1 else "доли", "всего_бит": int(len(биты))}
    начало = сдвиг + строка * период
    таблица = биты[начало:начало + строк * период].reshape(строк, период)[:, столбец:столбец + столбцов]
    if на_пиксель == 1:
        данные = np.packbits(таблица, axis=1).tobytes()
        вид = "биты"
    else:
        полных = столбцов // на_пиксель * на_пиксель
        доли = таблица[:, :полных].reshape(строк, -1, на_пиксель).mean(axis=2)
        if полных < столбцов:
            доли = np.concatenate([доли, таблица[:, полных:].mean(axis=1, keepdims=True)], axis=1)
        данные = np.round(доли * 255).astype(np.uint8).tobytes()
        вид = "доли"
    return {"всего_строк": всего_строк, "строк": строк, "пикселей": пикселей, "строка": строка,
            "столбец": столбец, "столбцов": столбцов, "на_пиксель": на_пиксель, "вид": вид,
            "всего_бит": int(len(биты)), "данные": base64.b64encode(данные).decode("ascii")}


def _строки_байт(биты: np.ndarray, период: int, сдвиг: int, порядок: str = "старший") -> np.ndarray:
    """Кадры по периоду → байты строками (хвост строки дополняется нулями до байта)."""
    период = max(8, int(период))
    сдвиг = max(0, int(сдвиг))
    строк = max(0, (len(биты) - сдвиг) // период)
    таблица = биты[сдвиг:сдвиг + строк * период].reshape(строк, период)
    if период % 8:
        таблица = np.concatenate([таблица, np.zeros((строк, 8 - период % 8), dtype=np.uint8)], axis=1)
    if порядок == "младший":
        таблица = таблица.reshape(строк, -1, 8)[:, :, ::-1].reshape(строк, -1)
    return np.packbits(таблица, axis=1)


def отбор_кадров(байты: np.ndarray, отбор: Sequence[dict[str, Any]]) -> np.ndarray:
    """Номера кадров, у которых байт (или полубайт) на месте равен значению; «не» — кроме."""
    годные = np.ones(len(байты), dtype=bool)
    for у in отбор:
        место = int(у["место"])
        if not 0 <= место < байты.shape[1]:
            raise ValueError(f"байта {место + 1} в кадре нет")
        столбец = байты[:, место].astype(np.int32)
        if у.get("полубайт") == "старший":
            столбец = столбец >> 4
        elif у.get("полубайт") == "младший":
            столбец = столбец & 15
        совпало = столбец == int(у["значение"])
        годные &= ~совпало if у.get("не") else совпало
    return np.flatnonzero(годные)


def кадры_таблицей(биты: np.ndarray, период: int, сдвиг: int, начало: int, сколько: int,
                   отбор: Sequence[dict[str, Any]] = (), порядок: str = "старший") -> dict[str, Any]:
    """Таблица кадров для рабочего стола: байты строками, с отбором по байту или полубайту."""
    байты = _строки_байт(биты, период, сдвиг, порядок)
    номера = отбор_кадров(байты, отбор) if отбор else np.arange(len(байты))
    начало = max(0, int(начало))
    сколько = max(0, min(int(сколько), СТРОК_ДО))
    выбрано = номера[начало:начало + сколько]
    return {"всего": int(len(байты)), "отобрано": int(len(номера)), "байт_в_кадре": int(байты.shape[1]),
            "начало": начало, "номера": [int(н) for н in выбрано],
            "данные": base64.b64encode(байты[выбрано].tobytes()).decode("ascii")}


def столбец_кадров(биты: np.ndarray, период: int, сдвиг: int, место: int, ширина: int = 1,
                   отбор: Sequence[dict[str, Any]] = (), порядок: str = "старший") -> dict[str, Any]:
    """Полная статистика столбца кадров — та же, что у матрицы байт в пакетах."""
    from ..setevoy.statistika import столбец  # noqa: PLC0415
    байты = _строки_байт(биты, период, сдвиг, порядок)
    if отбор:
        байты = байты[отбор_кадров(байты, отбор)]
    return столбец([bytes(р) for р in байты[:50000]], int(место), max(1, min(8, int(ширина))))


def _новый(r: np.ndarray, p: int, q: int, шум: float) -> bool:
    """Даёт ли период p, кратный q, новое: заметно ли меньше расхождений, чем при q.

    Кратное верного периода повторяет его пик (r[2P] ≈ r[P]) — это гармоника.
    Настоящий больший цикл (синхрослово раз в 256 бит над байтовым заполнением,
    FAS через цикл у E1) снимает заметную часть оставшихся расхождений.
    """
    прирост = float(r[p] - r[q])
    return прирост >= max(4 * шум, min(0.2 * (1 - float(r[q])), 0.25 * abs(float(r[q]))))


def делители(n: int) -> list[int]:
    """Все делители n по возрастанию — за √n шагов (перебор до n на лагах в десятки тысяч
    занимал больше, чем сама автокорреляция)."""
    малые, большие = [], []
    d = 1
    while d * d <= n:
        if n % d == 0:
            малые.append(d)
            if d * d != n:
                большие.append(n // d)
        d += 1
    return малые + большие[::-1]


def периоды(биты: np.ndarray, сколько: int = 8) -> list[dict[str, Any]]:
    """Кандидаты периода: пики автокорреляции, сильнейшие первыми (в сигмах шума).

    Пики стоят и на кратных периода — это гармоники, их не показываем. Но
    кратный бывает и настоящим: у E1 байтовое заполнение даёт период 8,
    синхрослово — цикл 256, а FAS через цикл — 512. Кратный остаётся в списке,
    только если снимает заметную часть расхождений (см. ``_новый``), и
    помечается, из скольких меньших периодов он сложен. Выбирает аналитик.
    """
    выборка = биты[:cikl.ВЫБОРКА]
    if len(выборка) < 64 * 8:
        return []
    наибольший = min(ПЕРИОД_ДО, len(выборка) // 8)
    r = cikl.автокорреляция(выборка, наибольший)
    # Шум автокорреляции — 1/√N, только если биты независимы. У манчестера и
    # других кодов в линии соседние произведения повторяются, и шум вдвое
    # больше по дисперсии: берём его по самим лагам (медиана модулей), но не
    # больше трёх теоретических — иначе у потока, где коррелировано всё,
    # «шумом» стала бы сама структура.
    шум = 1.0 / np.sqrt(len(выборка))
    шум = max(шум, min(1.4826 * float(np.median(np.abs(r[8:]))), 3 * шум))
    r[:8] = 0
    # Лагов десятки тысяч: 4 сигмы шум превысит где-нибудь почти наверняка;
    # пики слабее четверти главного — обычно отзвуки синхрослова на почти кратных.
    порог = max(ПОРОГ_СИГМ * шум, 0.25 * float(r.max()))
    взятые: list[int] = []
    for место in np.argsort(-r)[:400]:
        место = int(место)
        if r[место] < порог or len(взятые) >= сколько:
            break
        # Свести к наименьшему делителю, над которым пик ничего не прибавляет.
        основной = next((d for d in делители(место) if d >= 8
                         and r[d] >= порог and not _новый(r, место, d, шум)),
                        место)
        if основной in взятые or any(основной % п == 0 and not _новый(r, основной, п, шум)
                                      for п in взятые):
            continue
        # Отзвук синхрослова: лаг рядом с кратным взятого периода (синхрослово
        # похоже само на себя со сдвигом на бит-другой) и слабее его.
        if any(основной > п and min(основной % п, п - основной % п) <= max(2, п // 8)
               and r[основной] < r[п] for п in взятые):
            continue
        взятые.append(основной)
    итог = []
    for п in взятые:
        меньшие = [q for q in взятые if q < п and п % q == 0]
        итог.append({"период": п, "сила": round(float(r[п] / шум), 1),
                     "заметка": f"сверхцикл: {п // max(меньшие)} × {max(меньшие)}"
                     if меньшие else ""})
    return итог


#: Быстрый поиск периода по синхромаркеру.
#: Автокорреляция — по началу потока не длиннее этого (два миллиона бит — десятые доли секунды).
ВЫБОРКА_МАРКЕРА = 1 << 21
#: Сколько лучших лагов автокорреляции проверять свёрткой, если перебрать все дорого.
КАНДИДАТОВ_МАРКЕРА = 64
#: Свёртка кандидата — не больше стольких бит (строк × период): всё вместе — доли секунды.
СВЁРТКА_БИТ = 1 << 19
СВЁРТКА_ВСЕХ_ДО = 1 << 26
#: Меньше стольких циклов — маркер не отличить от случайного совпадения.
ЦИКЛОВ_ОТ = 16
#: Вес маркера считаем по стольким циклам самое большее — и не больше чем по стольким битам.
ЦИКЛОВ_ВЕСА = 4096
ВЕС_БИТ = 1 << 23


def бит_поиску_периода(до: int, глубина_до: int) -> int:
    """Сколько бит от начала потока нужно поиску периода: остальное он не смотрит."""
    return max(ВЫБОРКА_МАРКЕРА, ВЕС_БИТ, СВЁРТКА_БИТ, ЦИКЛОВ_ОТ * int(до)) + int(до) + int(глубина_до)


def _маркер(биты: np.ndarray, период: int, глубина_от: int, глубина_до: int,
            доля: float) -> tuple[int, int] | None:
    """Самая длинная кольцевая серия устойчивых столбцов свёртки: (начало, глубина)."""
    строк = min(len(биты) // период, max(ЦИКЛОВ_ОТ, СВЁРТКА_БИТ // период))
    if строк < ЦИКЛОВ_ОТ:
        return None
    единиц = биты[:строк * период].reshape(строк, период).sum(axis=0, dtype=np.int32)
    устойчив = np.maximum(единиц, строк - единиц) >= доля * строк
    if устойчив.all():
        return 0, min(период, глубина_до)
    края = np.diff(np.concatenate(([0], устойчив, устойчив, [0])).astype(np.int8))
    начала, концы = np.flatnonzero(края == 1), np.flatnonzero(края == -1)
    длины = концы - начала
    if not len(длины):
        return None
    лучшая = int(np.argmax(длины))
    глубина = min(int(длины[лучшая]), период)
    if глубина < глубина_от:
        return None
    return int(начала[лучшая]) % период, min(глубина, глубина_до)


def поиск_периода(биты: np.ndarray, *, от: int = 8, до: int = 8192, шаг: int = 1,
                  глубина_от: int = 8, глубина_до: int = 64, качество: float = 90,
                  сколько: int = 20) -> list[dict[str, Any]]:
    """Быстрый поиск периода по синхромаркеру: период, первый бит, вес.

    Синхромаркер — D подряд идущих бит цикла (глубина_от ≤ D ≤ глубина_до),
    одинаковых почти во всех циклах. Кандидаты периода — лаги от…до с шагом:
    все, если свернуть их дёшево, иначе лучшие по автокорреляции (гармоники —
    кратные меньшего лага, над которым они ничего не прибавляют, — пропускаются).
    Каждый кандидат сворачивается: поток режется на строки длины периода,
    столбец устойчив, если в нём не меньше «качество» % одинаковых бит; маркер —
    самая длинная кольцевая серия устойчивых столбцов. Первый бит — где маркер
    начинается в потоке (меньше периода); вес — доля циклов, в которых маркер
    совпал с образцом не меньше чем на «качество» % бит. Кратные найденного
    периода с тем же весом помечаются и уходят вниз списка.
    """
    от, до, шаг = int(от), int(до), max(1, int(шаг))
    глубина_от, глубина_до = max(1, int(глубина_от)), int(глубина_до)
    if not 2 <= от <= до <= ПЕРИОД_ДО:
        raise ValueError("период — от 2 до 65 536 бит, начальный не больше конечного")
    if глубина_до < глубина_от:
        raise ValueError("наибольшая глубина маркера меньше наименьшей")
    if not 50 <= качество <= 100:
        raise ValueError("качество синхромаркера — от 50 до 100 %")
    доля = качество / 100
    n = len(биты)
    лаги = np.arange(от, до + 1, шаг)
    лаги = лаги[(n // лаги >= ЦИКЛОВ_ОТ) & (лаги >= глубина_от)]
    if not len(лаги):
        return []
    цена = np.minimum(n // лаги, np.maximum(ЦИКЛОВ_ОТ, СВЁРТКА_БИТ // лаги)) * лаги
    if int(цена.sum()) <= СВЁРТКА_ВСЕХ_ДО:
        кандидаты = [int(л) for л in лаги]
    else:
        выборка = биты[:ВЫБОРКА_МАРКЕРА]
        r = cikl.автокорреляция(выборка, int(лаги[-1]))
        шум = 1.0 / np.sqrt(len(выборка))
        кандидаты = []
        for л in лаги[np.argsort(-r[лаги], kind="stable")]:
            л = int(л)
            if len(кандидаты) >= КАНДИДАТОВ_МАРКЕРА:
                break
            if any(д >= 2 and r[д] > 0 and not _новый(r, л, д, шум) for д in делители(л)[:-1]):
                continue
            кандидаты.append(л)
    найдено = []
    for период in кандидаты:
        маркер = _маркер(биты, период, глубина_от, глубина_до, доля)
        if маркер is None:
            continue
        начало, глубина = маркер
        ряд = биты[начало:]
        строк = min(ЦИКЛОВ_ВЕСА, max(ЦИКЛОВ_ОТ, ВЕС_БИТ // период), (len(ряд) - глубина) // период + 1)
        окна = np.lib.stride_tricks.as_strided(
            ряд, shape=(строк, глубина), strides=(ряд.strides[0] * период, ряд.strides[0]))
        образец = окна.sum(axis=0, dtype=np.int32) * 2 >= строк
        совпало = (окна == образец).sum(axis=1) >= доля * глубина
        найдено.append({"период": период, "первый_бит": начало, "глубина": глубина,
                        "вес": round(float(совпало.mean()), 4),
                        "маркер": "".join("1" if б else "0" for б in образец), "заметка": ""})
    # Кратное периода несёт тот же маркер (дважды, трижды за строку) и весит почти
    # столько же — по меньшему числу циклов даже случайно больше: сверяем с меньшими.
    основные: list[dict[str, Any]] = []
    кратные: list[dict[str, Any]] = []
    for н in sorted(найдено, key=lambda н: н["период"]):
        меньший = next((о for о in основные if н["период"] % о["период"] == 0
                        and о["вес"] >= н["вес"] - 0.02), None)
        if меньший is None:
            основные.append(н)
        else:
            н["заметка"] = f"кратен {меньший['период']}"
            кратные.append(н)

    def порядок(н: dict[str, Any]) -> tuple:
        return -н["вес"], -н["глубина"], н["период"]

    # Кратные — внизу, по возрастанию: вес у них тот же, различает их только период.
    return (sorted(основные, key=порядок) + sorted(кратные, key=lambda н: н["период"]))[:max(1, int(сколько))]


def по_маске(биты: np.ndarray, маска: dict[str, Any]) -> np.ndarray:
    """Поток канала: из каждого цикла — биты на заданных позициях, по порядку."""
    период = int(маска["период"])
    сдвиг = int(маска.get("сдвиг", 0)) % max(1, период)
    позиции = sorted({int(п) for п in маска.get("позиции", []) if 0 <= int(п) < период})
    if период < 1 or not позиции:
        raise ValueError("маска пуста: нужен период и хотя бы одна позиция в цикле")
    ряд = биты[сдвиг:]
    циклов = len(ряд) // период
    return ряд[:циклов * период].reshape(циклов, период)[:, позиции].reshape(-1)


#: Разметка бит аналитиком: столько отрезков и правил самое большее.
ОТРЕЗКОВ_ДО = 100_000
ПРАВИЛ_ДО = 64
ДЕЙСТВИЯ_РАЗМЕТКИ = {"взять": "взять размеченные биты", "убрать": "убрать размеченные биты",
                     "инверсия": "инвертировать размеченные биты"}


def проверить_разметку(разметка: dict[str, Any]) -> dict[str, Any]:
    """Разметка из запроса → чистый вид; ошибки формы — ValueError.

    Отрезки — [начало, длина] в битах потока (слитые и упорядоченные); правила —
    «ширина бит с места сдвиг в каждом периоде»: бит 3 с периодом 256 —
    {период 256, сдвиг 3, ширина 1}; от и до (бит потока) ограничивают правило участком.
    """
    if not isinstance(разметка, dict):
        raise ValueError("разметка — объект {отрезки, правила}")
    отрезки = []
    for о in list(разметка.get("отрезки") or [])[:ОТРЕЗКОВ_ДО + 1]:
        начало, длина = int(о[0]), int(о[1])
        if начало < 0 or длина < 1:
            raise ValueError("отрезок разметки — [начало ≥ 0, длина ≥ 1]")
        отрезки.append((начало, длина))
    if len(отрезки) > ОТРЕЗКОВ_ДО:
        raise ValueError(f"отрезков разметки больше {ОТРЕЗКОВ_ДО}")
    слитые: list[list[int]] = []
    for начало, длина in sorted(отрезки):
        if слитые and начало <= слитые[-1][0] + слитые[-1][1]:
            слитые[-1][1] = max(слитые[-1][1], начало + длина - слитые[-1][0])
        else:
            слитые.append([начало, длина])
    правила = []
    for п in list(разметка.get("правила") or []):
        период, сдвиг, ширина = int(п.get("период", 0)), int(п.get("сдвиг", 0)), int(п.get("ширина", 1))
        от, до = int(п.get("от", 0)), int(п.get("до", 0))
        if not 1 <= период <= ПЕРИОД_ДО or not 1 <= ширина <= период or сдвиг < 0 or от < 0 or до < 0:
            raise ValueError("правило разметки: период 1…65 536, ширина 1…период, сдвиг ≥ 0")
        правила.append({"период": период, "сдвиг": сдвиг % период, "ширина": ширина, "от": от, "до": до})
    if len(правила) > ПРАВИЛ_ДО:
        raise ValueError(f"правил разметки больше {ПРАВИЛ_ДО}")
    return {"отрезки": слитые, "правила": правила}


def маска_разметки(n: int, разметка: dict[str, Any]) -> np.ndarray:
    """Какие из n бит размечены: отрезки и правила вместе."""
    маска = np.zeros(n, dtype=bool)
    for начало, длина in разметка.get("отрезки") or []:
        маска[начало:начало + длина] = True
    for п in разметка.get("правила") or []:
        период = п["период"]
        # Место в цикле считаем от начала потока: бит k с периодом P — k, k+P, k+2P…
        шаблон = np.zeros(период, dtype=bool)
        шаблон[(п["сдвиг"] + np.arange(п["ширина"])) % период] = True
        от, до = п.get("от", 0), min(п.get("до") or n, n)
        if от < до:
            маска[от:до] |= np.resize(np.roll(шаблон, -(от % период)), до - от)
    return маска


def по_разметке(биты: np.ndarray, разметка: dict[str, Any], действие: str) -> np.ndarray:
    """Взять размеченные биты новым потоком, убрать их или инвертировать."""
    маска = маска_разметки(len(биты), разметка)
    if действие == "взять":
        return биты[маска]
    if действие == "убрать":
        return биты[~маска]
    if действие == "инверсия":
        return биты ^ маска.astype(np.uint8)
    raise ValueError("действие с разметкой — взять, убрать или инверсия")


def описать_разметку(разметка: dict[str, Any]) -> str:
    части = []
    отрезки = разметка.get("отрезки") or []
    if отрезки:
        всего = sum(д for _, д in отрезки)
        части.append(f"{len(отрезки)} отрезк. ({всего} бит)" if len(отрезки) > 1
                     else f"биты {отрезки[0][0]}–{отрезки[0][0] + отрезки[0][1] - 1}")
    for п in разметка.get("правила") or []:
        места = f"бит {п['сдвиг']}" if п["ширина"] == 1 else f"биты {п['сдвиг']}–{п['сдвиг'] + п['ширина'] - 1}"
        части.append(f"{места} с периодом {п['период']}")
    return "; ".join(части) or "пусто"


def столбцы(биты: np.ndarray, период: int, сдвиг: int = 0, циклов: int = 4096) -> list[float]:
    """Доля единиц в каждом столбце растра — по первым ``циклов`` циклам."""
    период = int(период)
    if период < 1 or период > ПЕРИОД_ДО:
        raise ValueError("период — от 1 до 65 536 бит")
    ряд = биты[int(сдвиг) % период:]
    сколько = min(циклов, len(ряд) // период)
    if not сколько:
        return []
    return [round(float(х), 3) for х in
            ряд[:сколько * период].reshape(сколько, период).mean(axis=0)]


