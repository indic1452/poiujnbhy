"""Растр потока и ручные инструменты аналитика.

Автоматический разбор — не всё. Аналитик привык смотреть на поток глазами:
сложить его по периоду в картинку (строка — цикл, 0 — чёрный, 1 — зелёный),
подвигать период и сдвиг, пока синхрослово не встанет столбиком, выделить
столбцы канала, вырезать их в отдельный поток и дальше разбирать его —
руками или автоматом. Здесь — серверная часть этого:

- окно бит для отрисовки (исходный поток или поток после любого этапа);
- кандидаты периода по автокорреляции;
- маска канала: период, сдвиг, позиции бит в цикле → поток канала;
- быстрые инструменты над потоком или каналом: найти скремблер, код,
  HDLC/GFP/ATM, цикл, модуляционную плоскость; снять слой вручную.

Всё, что меняет поток (канал по маске, снятый слой), становится новым
«производным» разбором — с тем же растром и теми же инструментами, и его
можно отдать и на автоматический разбор.
"""

from __future__ import annotations

import base64
from collections.abc import Sequence
from typing import Any

import numpy as np

from . import cikl, gfp, hdlc, kod, oktety, ploskost, skrembler
