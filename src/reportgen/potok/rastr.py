def _скремблер_по_кадру(биты: np.ndarray, *, период: int = 0, сдвиг: int = 0, пропуск: int = 0,
                        отводы: Sequence[int] = ()) -> Находка | None:
    """Кадровый скремблер по растру: кадр — период, начало — сдвиг растра."""
    if период < 16:
        raise ValueError("нужна длина кадра — период растра (засинхронизируйте растр)")
    найдено = skrembler.найти_по_кадру(биты, int(период), начало=int(сдвиг) % int(период),
                                       пропуск=int(пропуск), отводы=list(отводы) or None)
    if найдено is None:
        return None
    слой = (f"аддитивный отводы {','.join(map(str, найдено['отводы']))} кадр {период} "
            f"начальное {найдено['начальное']} пропуск {пропуск} начало {int(сдвиг) % int(период)}")
    return Находка(
        уровень="скремблер", что=f"кадровый аддитивный скремблер {найдено['полином']}",
        уверенность=float(найдено["совпало"]),
        мера=f"устойчивых столбцов {найдено['устойчивых']}; после снятия в них нули — "
             f"{найдено['совпало'] * 100:.1f} %",
        подробно=[f"начальное состояние (первые {max(найдено['отводы'])} бит ПСП после сброса): "
                  f"{найдено['начальное']}", найдено["способ"], f"слой для снятия: {слой}"],
        дальше=None, вид_дальше="")


def инструмент(биты: np.ndarray, имя: str, k: int = 0, **параметры: Any) -> Находка | None:
    выборка = биты[:1 << 23]
    if имя == "скремблер-кадр":
        return _скремблер_по_кадру(выборка, **параметры)
    if имя == "скремблер":
        return skrembler.найти(выборка)
    if имя == "код":
        return kod.найти(выборка, длинные=False)
    if имя == "кадры":
        return hdlc.найти(выборка) or oktety.найти(выборка) or gfp.найти(выборка)
    if имя == "цикл":
        return cikl.найти(выборка)
    if имя == "dmr":
        from . import dmr  # noqa: PLC0415
        return dmr.найти(выборка)
    if имя == "v110":
        from . import v110  # noqa: PLC0415
        return v110.найти(выборка)
    if имя == "trau":
        from . import trau  # noqa: PLC0415
        return trau.найти(выборка)
    if имя == "плоскость":
        if not k:
            raise ValueError("для плоскости нужно k — бит на символ КАМ")
        return ploskost.найти(выборка, int(k), лучших=1)
    if имя == "поля":
        период, сдвиг = int(параметры.get("период") or 0), int(параметры.get("сдвиг") or 0)
        if период < 16:
            raise ValueError("нужна длина кадра — ширина растра от 16 бит")
        байты = _строки_байт(выборка, период, сдвиг)
        if len(байты) < 20:
            raise ValueError("мало кадров этой длины (нужно от 20)")
        from . import polya  # noqa: PLC0415
        return polya.найти([bytes(р) for р in байты[:5000]], f"кадров по {период} бит")
    if имя == "ldpc":
        # Как детектор автомата: PLHEADER DVB-S2 — код по MODCOD, иначе опознаватель по синдрому.
        from .razbor import Бюджет, ПРОФИЛИ, _ldpc, _ldpc_plframe  # noqa: PLC0415
        import time  # noqa: PLC0415
        б = Бюджет(конец=time.monotonic() + 120, профиль=ПРОФИЛИ["обычно"])
        from . import dvbs2_pl  # noqa: PLC0415
        заголовки = dvbs2_pl.найти(выборка)
        return (_ldpc_plframe(заголовки, б) if заголовки is not None else None) or _ldpc(выборка, б)
    if имя == "плоскость-фм":
        if not k:
            raise ValueError("для плоскости нужно k — бит на символ ФМ")
        return ploskost.найти_фм(выборка, int(k), лучших=1)
    raise ValueError(f"нет инструмента «{имя}»")


def в_словарь(находка: Находка | None) -> dict[str, Any] | None:
    if находка is None:
        return None
    return {"уровень": находка.уровень, "что": находка.суть, "мера": находка.мера,
            "уверенность": round(float(находка.уверенность), 3),
            "подробно": list(находка.подробно)}


def производный(биты: np.ndarray, маска: dict[str, Any] | None,
                снять: Sequence[str]) -> tuple[bytes, list[str]]:
    """Новый поток: канал по маске и/или снятые вручную слои. Биты → байты и описание."""
    from .razbor import снять_вручную  # noqa: PLC0415 — круговой импорт

    описание: list[str] = []
    if маска:
        биты = по_маске(биты, маска)
        описание.append(f"канал по маске: период {маска['период']}, сдвиг "
                        f"{маска.get('сдвиг', 0)}, позиции {_диапазоны(маска.get('позиции', []))}")
    for слой in снять:
        биты, запись = снять_вручную(биты, слой)
        описание.append(запись.что)
    return np.packbits(биты).tobytes(), описание


def описать_шаг(шаг: dict[str, Any]) -> str:
    """Шаг ручной обработки словами: для имени узла и дерева."""
    if шаг.get("вид") == "маска":
        маска = шаг["маска"]
        return (f"канал по маске: период {маска['период']}, сдвиг {маска.get('сдвиг', 0)}, "
                f"позиции {_диапазоны(маска.get('позиции', []))}")
    if шаг.get("вид") == "разметка":
        return f"{ДЕЙСТВИЯ_РАЗМЕТКИ[шаг['действие']]}: {описать_разметку(шаг['разметка'])}"
    return str(шаг.get("слой", ""))


#: Шаг-слой — не длиннее; шаг модуляционного декодера несёт таблицу целиком (у КАМ-1024 — 1708 знаков base64).
СЛОЙ_ДО = 500
СЛОЙ_МОДДЕКОДЕРА_ДО = 2048


def проверить_шаги(шаги: Sequence[dict[str, Any]]) -> list[dict[str, Any]]:
    """Шаги из запроса → чистый список {вид, маска|слой, вкл}; ошибки формы — ValueError."""
    итог = []
    for шаг in шаги:
        if not isinstance(шаг, dict):
            raise ValueError("шаг — объект {вид, маска | слой}")
        вкл = bool(шаг.get("вкл", True))
        if шаг.get("вид") == "маска":
            маска = шаг.get("маска") or {}
            период = int(маска.get("период", 0))
            позиции = sorted({int(п) for п in маска.get("позиции", []) if 0 <= int(п) < период})
            if период < 1 or период > ПЕРИОД_ДО or not позиции:
                raise ValueError("маска пуста: нужен период и хотя бы одна позиция в цикле")
            итог.append({"вид": "маска", "вкл": вкл, "маска": {
                "период": период, "сдвиг": int(маска.get("сдвиг", 0)), "позиции": позиции}})
        elif шаг.get("вид") == "слой" and str(шаг.get("слой", "")).strip():
            слой = str(шаг["слой"]).strip()
            итог.append({"вид": "слой", "вкл": вкл,
                         "слой": слой[:СЛОЙ_МОДДЕКОДЕРА_ДО if слой.lower().startswith("моддекодер") else СЛОЙ_ДО]})
        elif шаг.get("вид") == "разметка":
            if шаг.get("действие") not in ДЕЙСТВИЯ_РАЗМЕТКИ:
                raise ValueError("действие с разметкой — взять, убрать или инверсия")
            разметка = проверить_разметку(шаг.get("разметка") or {})
            if not разметка["отрезки"] and not разметка["правила"]:
                raise ValueError("разметка пуста: отметьте биты")
            итог.append({"вид": "разметка", "вкл": вкл, "действие": шаг["действие"], "разметка": разметка})
        else:
            raise ValueError("шаг — «маска», «разметка» или «слой»")
    if len(итог) > 24:
        raise ValueError("шагов больше 24")
    return итог


def применить(биты: np.ndarray, шаги: Sequence[dict[str, Any]], ход=None,
              свойства: list[dict[str, Any]] | None = None) -> tuple[np.ndarray, list[str]]:
    """Включённые шаги по порядку: маска канала или снятие слоя. Биты и описание.

    ``свойства`` — сюда по шагу складываются свойства находки слоя (у ТКБ — блок данных, кадр).
    """
    from .razbor import снять_вручную  # noqa: PLC0415 — круговой импорт

    описание: list[str] = []
    for номер, шаг in enumerate(шаги, start=1):
        if not шаг.get("вкл", True):
            continue
        if ход:
            ход(f"шаг {номер}: {описать_шаг(шаг)}")
        if шаг["вид"] == "маска":
            биты = по_маске(биты, шаг["маска"])
            описание.append(описать_шаг(шаг))
        elif шаг["вид"] == "разметка":
            биты = по_разметке(биты, шаг["разметка"], шаг["действие"])
            описание.append(описать_шаг(шаг))
        else:
            биты, запись = снять_вручную(биты, шаг["слой"])
            описание.append(запись.что + (": " + "; ".join(запись.подробно[:3])
                                           if запись.подробно else ""))
            if свойства is not None:
                свойства.append(dict(запись.свойства or {}))
        if not len(биты):
            raise ValueError(f"после шага {номер} поток пуст")
    return биты, описание


def _диапазоны(позиции: Sequence[int]) -> str:
    п = sorted({int(х) for х in позиции})
    части, начало = [], None
    for i, х in enumerate(п):
        if начало is None:
            начало = х
        if i + 1 == len(п) or п[i + 1] != х + 1:
            части.append(str(начало) if начало == х else f"{начало}–{х}")
            начало = None
    return ", ".join(части)


