def _по_кругу(имя: str, углы: list[float], k: int) -> Созвездие:
    """Метка v — под углом углы[v] (радианы) на единичной окружности."""
    return Созвездие(имя, tuple((_метка(v, k), round(math.cos(у), 12), round(math.sin(у), 12))
                                for v, у in enumerate(углы)), встроенная=True, вид="ФМ")


def _фм(M: int, код) -> list[float]:
    """Углы меток ФМ-M: точка n — под углом 2πn/M, её метка — код(n)."""
    углы = [0.0] * M
    for n in range(M):
        углы[код(n)] = 2 * math.pi * n / M
    return углы


@lru_cache(maxsize=1)
def _встроенные() -> tuple[Созвездие, ...]:
    итог = [_по_кругу("ФМ2", _фм(2, int), 1)]
    for k in (2, 3, 4):
        итог += [_по_кругу(f"ФМ{1 << k} натуральный", _фм(1 << k, int), k),
                 _по_кругу(f"ФМ{1 << k} Грей", _фм(1 << k, _грей), k)]
    итог += [_по_кругу("DVB-S2 QPSK", [a * math.pi / 4 for a in DVBS2_QPSK], 2),
             _по_кругу("DVB-S2 8PSK", [a * math.pi / 4 for a in DVBS2_8PSK], 3)]
    # КАМ-16: уровни −3, −1, 1, 3 по I и по Q; метка — код Грея уровня I, затем код Грея уровня Q.
    итог.append(_кам_грей("КАМ16 Грей", 2, 2))
    # Дальше — добавленные позже (порядок прежних не меняется).
    for k in (5, 6):
        итог += [_по_кругу(f"ФМ{1 << k} натуральный", _фм(1 << k, int), k),
                 _по_кругу(f"ФМ{1 << k} Грей", _фм(1 << k, _грей), k)]
    итог += [_кам_грей("КАМ8 прямоугольная Грей", 2, 1), _кам_грей("КАМ64 Грей", 3, 3),
             _кам_грей("КАМ256 Грей", 4, 4), _крест("КАМ32 крест", 5), _крест("КАМ128 крест", 7),
             _apsk("DVB-S2 16APSK (γ 3,15)", DVBS2_16APSK, 4), _apsk("DVB-S2 32APSK (γ 2,84; 5,27)", DVBS2_32APSK, 5)]
    return tuple(итог)


def _кам_грей(имя: str, бит_i: int, бит_q: int) -> Созвездие:
    """Прямоугольная КАМ: уровни 2i − (A − 1) по I и по Q; метка — код Грея уровня I, затем код Грея уровня Q."""
    A, B = 1 << бит_i, 1 << бит_q
    k = бит_i + бит_q
    return Созвездие(имя, tuple((_метка((_грей(i) << бит_q) | _грей(q), k), float(2 * i - A + 1), float(2 * q - B + 1))
                               for i in range(A) for q in range(B)), встроенная=True)


def _крест(имя: str, k: int) -> Созвездие:
    """Крестовая КАМ: 32 точки — сетка 6 × 6 без угловых точек, 128 — 12 × 12 без углов 2 × 2. Метки — номера
    точек по порядку чтения (сверху вниз, слева направо), без притязаний на чью-либо разметку: своя — в папке
    плоскостей или «Своя разметка»."""
    сторона, срез = {5: (6, 1), 7: (12, 2)}[k]
    места = [(x, y) for y in range(сторона - 1, -1, -1) for x in range(сторона)
             if not ((x < срез or x >= сторона - срез) and (y < срез or y >= сторона - срез))]
    return Созвездие(имя, tuple((_метка(n, k), float(2 * x - сторона + 1), float(2 * y - сторона + 1))
                               for n, (x, y) in enumerate(места)), встроенная=True, вид="общее")


def _apsk(имя: str, точки: tuple[tuple[float, float], ...], k: int) -> Созвездие:
    """APSK: точка с меткой i — (радиус, угол в долях π) из таблицы; метка i — номер, старший бит первым."""
    return Созвездие(имя, tuple((_метка(i, k), round(r * math.cos(а * math.pi), 12), round(r * math.sin(а * math.pi), 12))
                               for i, (r, а) in enumerate(точки)), встроенная=True, вид="общее")


def встроенные() -> list[Созвездие]:
    return list(_встроенные())


# -- файл .etl: текстовая картинка созвездия -----------------------------------------------

def _текст(данные: bytes) -> str:
    for кодировка in ("utf-8-sig", "cp1251"):
        try:
            return данные.decode(кодировка)
        except UnicodeDecodeError:
            continue
    raise ValueError("файл .etl — не текст в utf-8 или cp1251")


def _число(т: str) -> float:
    return float(т.replace(",", "."))


def разобрать_etl(данные: bytes | str, имя: str = "") -> Созвездие:
    """Картинка созвездия (или строки координат) → созвездие; ошибки ввода — ValueError с понятным словом.

    Строки, начинающиеся с «#» или «;», — примечания; «# вид: общее» (ФМ, КАМ) задаёт вид
    плоскости. Если есть строка «метка = x y» (или «метка: x, y», полярно «метка = r @ угол»),
    все точки задаются так — координаты точные; иначе — текстовая картинка, как раньше.
    """
    if isinstance(данные, bytes):
        if len(данные) > ETL_ДО:
            raise ValueError(f"файл .etl больше {ETL_ДО // 1024} КБ — это не картинка созвездия")
        данные = _текст(данные)
    строки = данные.splitlines()
    вид = ""
    for строка in строки:
        м = _ВИД.match(строка)
        if м:
            вид = {"фм": "ФМ", "кам": "КАМ", "общее": "общее", "общий": "общее", "apsk": "общее",
                   "афм": "общее"}.get(м.group(1).strip().lower().rstrip(".,;"), "")
            if not вид:
                raise ValueError(f"вид «{м.group(1)}»: ФМ, КАМ или общее")
    содержательные = [(номер, строка) for номер, строка in enumerate(строки)
                      if строка.strip() and not _ПРИМЕЧАНИЕ.match(строка)]
    точные = any(_КООРДИНАТЫ.fullmatch(строка) for _, строка in содержательные)
    токены: list[tuple[str, int, float, float]] = []
    if точные:
        for номер, строка in содержательные:
            м = _КООРДИНАТЫ.fullmatch(строка)
            if not м:
                raise ValueError(f"строка {номер + 1}: «{строка.strip()[:40]}» — ждём «метка = x y» (или «метка = r @ угол»)")
            а, б = _число(м.group(2)), _число(м.group(4))
            if not (math.isfinite(а) and math.isfinite(б)):
                raise ValueError(f"строка {номер + 1}: координаты — конечные числа")
            x, y = (а * math.cos(math.radians(б)), а * math.sin(math.radians(б))) if м.group(3) else (а, б)
            токены.append((м.group(1), номер, x, y))
    else:
        токены = [(м.group(), номер, (м.start() + м.end() - 1) / 2, float(-номер * АСПЕКТ))
                  for номер, строка in содержательные
                  for м in _ТОКЕН.finditer(строка.expandtabs(8))]
    if not токены:
        raise ValueError("в файле нет меток: метка точки — k символов 0 и 1 на месте точки созвездия")
    первый = токены[0]
    k = len(первый[0])
    for т in токены:
        if len(т[0]) != k:
            raise ValueError(f"разное число бит в метках: «{первый[0]}» в строке {первый[1] + 1} и «{т[0]}» "
                             f"в строке {т[1] + 1}")
    if k > БИТ_ДО:
        raise ValueError(f"метки по {k} бит: не больше {БИТ_ДО} бит на символ ({1 << БИТ_ДО} точки)")
    где: dict[str, int] = {}
    for метка, строка, _, _ in токены:
        if метка in где:
            raise ValueError(f"метка «{метка}» повторяется: строки {где[метка] + 1} и {строка + 1}")
        где[метка] = строка
    if len(токены) != 1 << k:
        raise ValueError(f"меток {len(токены)}, а при {k} бит на символ их должно быть {1 << k} (2^{k})")
    с = Созвездие(имя, tuple((метка, float(x), float(y)) for метка, _, x, y in токены), точные=точные, вид=вид)
    плоскость(с)                       # геометрия — сразу: точки на одном луче и т. п.
    return с


def в_etl(с: Созвездие) -> str:
    """Созвездие → картинка .etl (по идеальной геометрии): разбор картинки даёт те же точки по номерам.

    ФМ рисуется повёрнутой на полшага — ни одна точка не ложится на ось; столбцы и
    строки — по различным значениям x и y, между метками — пробел. Общая плоскость
    (APSK, крест, своя) — строками координат «метка = x y» с «# вид: общее».
    """
    п = плоскость(с)
    k, M = с.k, с.M
    if п.вид == "общее":
        return "\n".join([f"# {с.имя}" if с.имя else "# плоскость", "# вид: общее",
                          *(f"{_метка(м, k)} = {x:.6f} {y:.6f}" for м, (x, y) in zip(п.метки, п.xy, strict=True))]) + "\n"
    if п.вид == "ФМ":
        углы = (np.arange(M) + 0.5) * 2 * np.pi / M
        xy = np.round(np.column_stack([np.cos(углы), np.sin(углы)]), 9)
    else:
        xy = np.round(np.array(п.xy), 9)
    xs, ys = sorted(set(xy[:, 0].tolist())), sorted(set(xy[:, 1].tolist()), reverse=True)
    строки = [[" "] * (len(xs) * (k + 1)) for _ in ys]
    for n, (x, y) in enumerate(xy.tolist()):
        начало = xs.index(x) * (k + 1)
        строки[ys.index(y)][начало:начало + k] = _метка(п.метки[n], k)
    return "\n".join("".join(с_).rstrip() for с_ in строки) + "\n"


def своя_разметка(основа: Созвездие, метки: Sequence[str], имя: str) -> Созвездие:
    """Та же геометрия, что у ``основы``, но свои метки точкам (по номерам точек плоскости основы)."""
    п = плоскость(основа)
    k, M = основа.k, основа.M
    метки = [str(м).strip() for м in метки]
    if len(метки) != M:
        raise ValueError(f"меток {len(метки)}, а точек {M}")
    for м in метки:
        if not re.fullmatch(r"[01]+", м) or len(м) != k:
            raise ValueError(f"метка «{м[:20]}»: {k} символов 0 и 1")
    if len(set(метки)) != M:
        повтор = next(м for м in метки if метки.count(м) > 1)
        raise ValueError(f"метка «{повтор}» повторяется: у каждой точки своя")
    с = Созвездие(имя, tuple((м, x, y) for м, (x, y) in zip(метки, п.xy, strict=True)), точные=True,
                  вид=п.вид if п.вид != "ФМ" else "ФМ")
    плоскость(с)
    return с


# -- папка плоскостей --------------------------------------------------------------------------

def файлы() -> list[Path]:
    """Файлы *.etl папки плоскостей (расширение — в любом регистре), по имени."""
    if КАТАЛОГ is None or not КАТАЛОГ.is_dir():
        return []
    return sorted((п for п in КАТАЛОГ.iterdir() if п.is_file() and п.suffix.lower() == ".etl"),
                  key=lambda п: п.name.lower())


def прочитать(путь: Path) -> Созвездие:
    if путь.stat().st_size > ETL_ДО:
        raise ValueError(f"файл .etl больше {ETL_ДО // 1024} КБ — это не картинка созвездия")
    return разобрать_etl(путь.read_bytes(), путь.name)


def в_словарь(с: Созвездие) -> dict[str, Any]:
    п = плоскость(с)
    return {"имя": с.имя, "встроенная": с.встроенная, "k": с.k, "M": с.M, "вид": п.вид,
            "точки": [[_метка(м, с.k), round(x, 4), round(y, 4)] for м, (x, y) in zip(п.метки, п.xy, strict=True)]}


def список() -> list[dict[str, Any]]:
    """Встроенные и файлы папки — каждый раз заново: аналитик кладёт файлы сам. Битый — с ошибкой."""
    итог = [в_словарь(с) for с in встроенные()]
    for путь in файлы():
        try:
            итог.append(в_словарь(прочитать(путь)))
        except (ValueError, OSError) as ошибка:
            итог.append({"имя": путь.name, "встроенная": False, "ошибка": str(ошибка)})
    return итог


def годные(M: int) -> list[Созвездие]:
    """Встроенные и годные файлы папки с M точками."""
    итог = [с for с in встроенные() if с.M == M]
    for путь in файлы():
        try:
            с = прочитать(путь)
        except (ValueError, OSError):
            continue
        if с.M == M:
            итог.append(с)
    return итог


def файл(имя: str) -> Path | None:
    """Файл папки плоскостей с этим именем (только из списка папки — не путь)."""
    return next((п for п in файлы() if п.name == имя), None)


def найти(имя: str) -> Созвездие:
    """Плоскость по имени: встроенная — по названию, из папки — по имени файла."""
    for с in встроенные():
        if с.имя == имя:
            return с
    путь = файл(имя)
    if путь is None:
        raise ValueError(f"плоскости «{имя}» нет ни среди встроенных, ни в папке плоскостей")
    try:
        return прочитать(путь)
    except ValueError as ошибка:
        raise ValueError(f"{путь.name}: {ошибка}") from None


def чистое_имя(имя: str) -> str:
    """Имя файла плоскости: без пути и лишних знаков, с расширением .etl."""
    имя = re.sub(r"[^\w .()\-]", "_", str(имя).replace("\\", "/").split("/")[-1]).strip(" .")
    if not имя.lower().endswith(".etl"):
        raise ValueError("плоскость — файл с расширением .etl")
    return имя if len(имя) <= 120 else имя[:116] + имя[-4:]


def сохранить(имя: str, данные: bytes) -> dict[str, Any]:
    """Положить .etl в папку плоскостей — только если он разбирается (битый не сохраняется)."""
    from ..fayly import записать_атомарно  # noqa: PLC0415

    if КАТАЛОГ is None:
        raise ValueError("папка плоскостей не задана")
    имя = чистое_имя(имя)
    с = разобрать_etl(данные, имя)
    КАТАЛОГ.mkdir(parents=True, exist_ok=True)
    записать_атомарно(КАТАЛОГ / имя, данные)
    return в_словарь(с)


# -- декодер: таблица подстановки ----------------------------------------------------------

def _переставить(v: int, перестановка: tuple[int, ...], k: int) -> int:
    """Бит i новой метки (с 1, слева) — бит перестановка[i] старой; пусто — как есть."""
    if not перестановка:
        return v
    return sum(((v >> (k - p)) & 1) << (k - 1 - i) for i, p in enumerate(перестановка))


def запись(таблица) -> str:
    """Таблица подстановки строкой: до 10 меток — цифрами подряд («16053247»), больше — через пробел."""
    return ("" if len(таблица) <= 10 else " ").join(map(str, таблица))


def _числа(значение: Any, цифрами: int) -> list[int] | None:
    """Список чисел из JSON-массива или строки; строка из ``цифрами`` цифр подряд — по цифре; None — не числа."""
    if isinstance(значение, list):
        try:
            return [int(ч) for ч in значение]
        except (TypeError, ValueError, OverflowError):
            return None
    т = str(значение).strip()
    if len(т) == цифрами and т.isdigit():
        return [int(ц) for ц in т]
    return [int(ч) for ч in re.findall(r"\d+", т)]


def _перестановка(значение: Any, k: int, что: str) -> tuple[int, ...]:
    """«1,2,3», «1 2 3», «123», [1, 2, 3] → (1, 2, 3); пусто — тождественная."""
    числа = _числа(значение, k)
    if числа == []:
        return tuple(range(1, k + 1))
    if числа is None or sorted(числа) != list(range(1, k + 1)):
        raise ValueError(f"{что}: перестановка чисел 1…{k} по одному разу («{','.join(map(str, range(1, k + 1)))}»)")
    return tuple(числа)


def _таблица(значение: Any, M: int, что: str = "таблица") -> tuple[int, ...]:
    """«16053247», «1 6 0 5 3 2 4 7», [1, 6, …] → перестановка чисел 0…M−1.

    Цифрами подряд пишется таблица до 8 меток; у 16 и больше меток M цифр подряд — не
    перестановка (меток больше 10), и отказ тот же, что и у одного большого числа.
    """
    числа = _числа(значение, M)
    if числа is None or sorted(числа) != list(range(M)):
        raise ValueError(f"{что}: перестановка чисел 0…{M - 1} по одному разу")
    return tuple(числа)


def модуляция(текст: Any) -> tuple[str, int]:
    """«ФМ8», «ФМ-16», «КАМ16», «АФМ32» (APSK) → (вид, k)."""
    м = re.fullmatch(r"\s*(ФМ|КАМ|АФМ|APSK)\s*-?\s*(\d+)\s*", str(текст or "").upper())
    if not м:
        raise ValueError("модуляция: ФМ2…ФМ64, КАМ8…КАМ256 или АФМ16, АФМ32 (APSK)")
    M = int(м.group(2))
    if M not in {1 << k for k in range(1, БИТ_ДО + 1)}:
        raise ValueError(f"модуляция: число точек — степень двойки от 2 до {1 << БИТ_ДО}")
    return {"APSK": "АФМ"}.get(м.group(1), м.group(1)), M.bit_length() - 1


@dataclass(frozen=True)
class Настройки:
    """Параметры окна: что с чем сопоставить и как."""

    k: int
    вид: str
    демодулятор: Созвездие
    вид_кода: Созвездие
    относительная: bool = False
    инверсия: bool = False
    поворот: float = 0.0
    вход: tuple[int, ...] = ()
    выход: tuple[int, ...] = ()
    #: 0 — метки самого вида кода; N ≥ 1 — вариант N разметки точек вида кода.
    вариант: int = 0
    только_грей: bool = True
    #: Внешняя таблица: метка демодулятора → метка вида кода (относительный режим — разность → метка).
    таблица: tuple[int, ...] = ()


def настройки(данные: dict[str, Any], найти_=None) -> Настройки:
    """Параметры из запроса (ключи по-русски) → Настройки; ошибки — ValueError."""
    if not isinstance(данные, dict):
        raise ValueError("параметры — объект {модуляция, демодулятор, вид_кода, …}")
    найти_ = найти_ or найти
    вид, k = модуляция(данные.get("модуляция"))
    M = 1 << k
    дем, код = (найти_(str(данные.get(ключ) or "")) for ключ in ("демодулятор", "вид_кода"))
    for роль, с in (("демодулятор", дем), ("вид кода", код)):
        if с.M != M:
            raise ValueError(f"{роль} «{с.имя}» — {с.M} точек, а модуляция {вид}{M}: нужна таблица на {M} точек")
    относительная = bool(данные.get("относительная"))
    if относительная and {вид, плоскость(дем).вид, плоскость(код).вид} != {"ФМ"}:
        raise ValueError("относительный (дифференциальный) режим — только для ФМ: у КАМ и АФМ точки не на окружности")
    try:
        поворот = float(данные.get("поворот") or 0)
        вариант = int(данные.get("вариант") or 0)
    except (TypeError, ValueError, OverflowError):
        raise ValueError("поворот и вариант — числа") from None
    if not math.isfinite(поворот):
        raise ValueError("поворот и вариант — числа")
    таблица = данные.get("таблица")
    н = Настройки(k=k, вид=вид, демодулятор=дем, вид_кода=код, относительная=относительная,
                  инверсия=bool(данные.get("инверсия")), поворот=поворот,
                  вход=_перестановка(данные.get("вход") or "", k, "вход"),
                  выход=_перестановка(данные.get("выход") or "", k, "выход"),
                  вариант=вариант, только_грей=данные.get("только_грей", True) is not False,
                  таблица=_таблица(таблица, M, "внешняя таблица") if таблица not in (None, "", []) else ())
    if вариант:
        разметка(н, вариант)          # номер — в пределах
    return н


def _сопоставление(н: Настройки) -> list[int]:
    """Номер точки демодулятора → номер точки вида кода: инверсия, поворот, ближайшая точка."""
    дем, код = плоскость(н.демодулятор), плоскость(н.вид_кода)
    xy = np.array(дем.xy) * (1, -1 if н.инверсия else 1)
    φ = math.radians(н.поворот)
    xy = xy @ np.array([[math.cos(φ), math.sin(φ)], [-math.sin(φ), math.cos(φ)]])
    цели = np.array(код.xy)
    до = np.hypot(*(xy[:, None, :] - цели[None, :, :]).transpose(2, 0, 1))
    между = np.hypot(*(цели[:, None, :] - цели[None, :, :]).transpose(2, 0, 1))
    np.fill_diagonal(между, np.inf)
    if (до.min(axis=1) >= между.min() / 2).any():
        название = {"ФМ": "ФМ", "КАМ": "КАМ"}.get(код.вид, "этой плоскости ") + f"-{len(цели)}"
        raise ValueError(f"поворот {н.поворот:g}° не переводит созвездие в себя; для {название} шаг {код.шаг:g}°")
    куда = до.argmin(axis=1).tolist()
    if len(set(куда)) < len(куда):
        raise ValueError(f"созвездия демодулятора «{н.демодулятор.имя}» и вида кода «{н.вид_кода.имя}» разной "
                         f"формы: несколько точек ложатся на одну")
    return куда


def _номера_по_кругу(н: Настройки) -> list[int]:
    """Номер точки демодулятора → номер по окружности после инверсии и поворота (от наименьшего угла ≥ 0)."""
    M = 1 << н.k
    # Углы — кратные 360/M (у M до 64 — точные двоичные дроби) плюс поворот: округлять нечего.
    углы = (np.arange(M) * 360.0 / M * (-1 if н.инверсия else 1) + н.поворот) % 360
    return np.argsort(np.argsort(углы, kind="stable"), kind="stable").tolist()


def _точки(н: Настройки) -> list[int]:
    """Метка потока → номер точки: абсолютный режим — точки вида кода, относительный — по окружности."""
    M = 1 << н.k
    номер = {м: n for n, м in enumerate(плоскость(н.демодулятор).метки)}
    куда = _номера_по_кругу(н) if н.относительная else _сопоставление(н)
    return [куда[номер[_переставить(v, н.вход, н.k)]] for v in range(M)]


@dataclass(frozen=True)
class Декодер:
    """Готовая подстановка: абсолютная (таблица) или относительная (номера и метки разностей)."""

    k: int
    таблица: tuple[int, ...] = ()
    номера: tuple[int, ...] = ()
    метки: tuple[int, ...] = ()
    описание: str = field(default="", compare=False)

    def применить(self, биты: np.ndarray) -> np.ndarray:
        """Поток меток → поток; хвост, не кратный k, отбрасывается."""
        k = self.k
        n = len(биты) // k
        веса = 1 << np.arange(k - 1, -1, -1)
        символы = (np.asarray(биты[:n * k], dtype=np.int64).reshape(n, k) * веса).sum(axis=1)
        if self.номера:
            номера = np.asarray(self.номера, dtype=np.int64)[символы]
            разности = (номера - np.concatenate(([0], номера[:-1]))) % (1 << k)
            выход = np.asarray(self.метки, dtype=np.int64)[разности]
        else:
            выход = np.asarray(self.таблица, dtype=np.int64)[символы]
        return ((выход[:, None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8).ravel()

    def слой(self) -> str:
        """Шаг обработки — самодостаточный: таблица прямо в тексте, описание — в скобках.

        От 128 точек таблица числами длиннее шага (500 знаков) — она пишется байтами в base64
        (алфавит URL-safe, без «/»: «моддекодер 8 б64: …»).
        """
        # Алфавит base64 без «/» и «+» (URL-safe): «/» разделяет таблицы относительного режима.
        запись_ = (lambda т: base64.urlsafe_b64encode(bytes(т)).decode("ascii")) if self.k >= СЛОЙ_Б64_ОТ else \
            (lambda т: " ".join(map(str, т)))
        б64 = " б64" if self.k >= СЛОЙ_Б64_ОТ else ""
        if self.номера:
            основа = f"моддекодер {self.k}{б64} относительная: {запись_(self.номера)} / {запись_(self.метки)}"
        else:
            основа = f"моддекодер {self.k}{б64}: {запись_(self.таблица)}"
        место = СЛОЙ_ДО - len(основа) - 3
        return основа + (f" ({self.описание[:место]})" if self.описание and место > 0 else "")


def описание(н: Настройки) -> str:
    """Параметры словами — для журнала и для шага обработки."""
    def имя(с: Созвездие) -> str:
        return f"«{с.имя}»" + (" (встроенная)" if с.встроенная else "")

    части = [f"{н.вид}{1 << н.k}, {'относительная' if н.относительная else 'абсолютная'}",
             f"демодулятор {имя(н.демодулятор)}"]
    if н.таблица:
        части.append(f"внешняя таблица {запись(н.таблица)}")
    else:
        части.append(f"вид кода {имя(н.вид_кода)}" + (
            f", метки — {'код Грея, ' if н.только_грей else ''}вариант №{н.вариант} из {число_вариантов(н)}"
            if н.вариант else ""))
    if н.относительная or not н.таблица:
        части += [f"поворот {н.поворот:g}°", "инверсия спектра" if н.инверсия else "без инверсии"]
    части += [f"вход {','.join(map(str, н.вход))}", f"выход {','.join(map(str, н.выход))}"]
    return "; ".join(части)


def декодер(н: Настройки, метки_кода: tuple[int, ...] | None = None) -> Декодер:
    """Таблица подстановки по настройкам (``метки_кода`` — своя разметка точек вида кода)."""
    M = 1 << н.k
    выход = [_переставить(v, н.выход, н.k) for v in range(M)]
    if н.таблица and not н.относительная:
        return Декодер(н.k, tuple(выход[н.таблица[_переставить(v, н.вход, н.k)]] for v in range(M)),
                       описание=описание(н))
    if метки_кода is None:
        метки_кода = н.таблица or (разметка(н, н.вариант) if н.вариант else плоскость(н.вид_кода).метки)
    точки = _точки(н)
    if н.относительная:
        return Декодер(н.k, номера=tuple(точки), метки=tuple(выход[м] for м in метки_кода), описание=описание(н))
    return Декодер(н.k, tuple(выход[метки_кода[т]] for т in точки), описание=описание(н))


def из_слоя(указание: str) -> Декодер:
    """«моддекодер k: t0 … t(M−1) (описание)» или «моддекодер k относительная: n0 … / m0 … (описание)»."""
    голова, двоеточие, хвост = указание.partition(":")
    м = re.fullmatch(r"\s*моддекодер\s+(\d+)\s*(б64)?\s*(относительная)?\s*", голова, re.IGNORECASE)
    if not м or not двоеточие or not 1 <= int(м.group(1)) <= БИТ_ДО:
        raise ValueError(f"моддекодер: «моддекодер k: t0 … t(M−1)» или «моддекодер k относительная: номера / "
                         f"метки», k — от 1 до {БИТ_ДО} бит на символ")
    k = int(м.group(1))
    M = 1 << k
    таблицы, _, описание_ = хвост.partition("(")
    описание_ = описание_.rstrip().removesuffix(")")

    def прочесть(т: str, что: str) -> tuple[int, ...]:
        if not м.group(2):
            return _таблица(т, M, что)
        try:
            сжато = т.strip()
            if not re.fullmatch(r"[A-Za-z0-9_\-]*={0,2}", сжато):
                raise ValueError(что)
            return _таблица(list(base64.urlsafe_b64decode(сжато)), M, что)
        except (ValueError, TypeError):
            raise ValueError(f"{что}: байты в base64 — перестановка чисел 0…{M - 1}") from None

    if м.group(3):
        номера, косая, метки = таблицы.partition("/")
        if not косая:
            raise ValueError("моддекодер относительная: номера точек и метки разностей — через «/»")
        return Декодер(k, номера=прочесть(номера, "номера точек"),
                       метки=прочесть(метки, "метки разностей"), описание=описание_)
    return Декодер(k, прочесть(таблицы, "таблица"), описание=описание_)


def снять(биты: np.ndarray, указание: str) -> tuple[np.ndarray, list[str]]:
    """Слой «моддекодер …» — ряд и подробности для журнала."""
    д = из_слоя(указание)
    ряд = д.применить(биты)
    подробно = [д.описание] if д.описание else []
    if д.номера:
        подробно.append(f"относительный режим: номер точки по метке {запись(д.номера)}, метка по разности "
                        f"номеров {запись(д.метки)}; первый символ — от номера 0")
    else:
        подробно.append("таблица меток: " + ", ".join(f"{_метка(v, д.k)}→{_метка(т, д.k)}"
                                                   for v, т in enumerate(д.таблица)))
    хвост = len(биты) % д.k
    if хвост:
        подробно.append(f"хвост {хвост} бит (не кратен {д.k}) отброшен")
    return ряд, подробно


# -- варианты разметки вида кода: все или только коды Грея ----------------------------------

@lru_cache(maxsize=64)
def _варианты_грея(M: int, соседи: tuple[tuple[int, int], ...]) -> tuple[tuple[int, ...], ...]:
    """Все разметки точек 0…M−1 метками, у которых соседние точки отличаются одним битом.

    Точки размечаются по номерам 0, 1, …; метки пробуются по возрастанию — порядок
    лексикографический по (метка точки 0, метка точки 1, …).
    """
    прежние = [sorted({b if a == n else a for a, b in соседи if n in (a, b) and min(a, b) < n}) for n in range(M)]
    биты = M.bit_length() - 1
    метки = list(range(M))           # начальные значения не читаются: точка размечается раньше, чем её метку спросят
    занято = [False] * M
    итог: list[tuple[int, ...]] = []

    def шаг(n: int) -> None:
        if n == M:
            if len(итог) >= ГРЕЯ_ДО:
                raise ValueError(f"вариантов кода Грея больше {ГРЕЯ_ДО}: перебор для {M} точек не поддерживается")
            итог.append(tuple(метки))
            return
        if прежние[n]:
            кандидаты = sorted({метки[прежние[n][0]] ^ (1 << b) for b in range(биты)})
        else:
            кандидаты = range(M)
        for v in кандидаты:
            if not занято[v] and all(bin(v ^ метки[m]).count("1") == 1 for m in прежние[n]):
                метки[n], занято[v] = v, True
                шаг(n + 1)
                занято[v] = False

    шаг(0)
    return tuple(итог)


def _перестановка_номер(номер: int, M: int) -> tuple[int, ...]:
    """Перестановка 0…M−1 с этим номером (с 0) в лексикографическом порядке."""
    остались = list(range(M))
    итог = []
    for i in range(M, 0, -1):
        j, номер = divmod(номер, math.factorial(i - 1))
        итог.append(остались.pop(j))
    return tuple(итог)


def число_вариантов(н: Настройки) -> int:
    M = 1 << н.k
    if M > ВАРИАНТЫ_ТОЧЕК_ДО:
        raise ValueError(f"варианты разметки — только до {ВАРИАНТЫ_ТОЧЕК_ДО} точек: у {M} точек даже кодов Грея "
                         f"слишком много")
    if н.только_грей:
        всего = len(_варианты_грея(M, плоскость(н.вид_кода).соседи))
        if not всего:
            raise ValueError(f"у плоскости «{н.вид_кода.имя}» нет разметок кодом Грея (соседние точки не могут "
                             f"отличаться одним битом): «все варианты» — до {ВСЕ_ДО} точек, иначе разметка вслепую")
        return всего
    if M > ВСЕ_ДО:
        raise ValueError(f"все варианты — только до {ВСЕ_ДО} точек ({ВСЕ_ДО}! = {math.factorial(ВСЕ_ДО)}); "
                         f"для {M} точек — только коды Грея")
    return math.factorial(M)


def разметка(н: Настройки, номер: int) -> tuple[int, ...]:
    """Вариант ``номер`` (с 1): метки точек вида кода по номерам."""
    всего = число_вариантов(н)
    if not 1 <= номер <= всего:
        raise ValueError(f"вариант — от 1 до {всего}")
    if н.только_грей:
        return _варианты_грея(1 << н.k, плоскость(н.вид_кода).соседи)[номер - 1]
    return _перестановка_номер(номер - 1, 1 << н.k)


def мера(биты: np.ndarray, кадр: tuple[int, int] | None = None) -> float:
    """Мера структуры варианта: отрыв кода — как у подбора плоскости (проверки на окне 12 бит,
    чётность строк кода произведения, в разбросах) — плюс падение байтовой энтропии × 100
    (у случайного ряда — около 2, у HDLC с IP — десятки).

    ``кадр`` — (длина, первый бит) кадров модема (строка просмотра): тогда ещё и чётность строк
    кода внутри кадров (``tpc.мера_в_кадрах``) — сквозь синхрослова и служебные слова кадра
    строки кода в сплошном потоке сбиваются, а в кадре видны.
    """
    from . import ploskost, skrembler, tpc  # noqa: PLC0415 — круговой импорт

    итог = float(ploskost._мера_кода(биты)) + 100 * skrembler.мера_структуры(биты)
    if кадр:
        длина, начало = кадр
        итог += float(tpc.мера_в_кадрах(биты, list(range(начало % длина, len(биты), длина))[:КАДРОВ_ДЛЯ_МЕРЫ], длина))
    return итог


def кадр(значение: Any) -> tuple[int, int] | None:
    """{длина, начало} из запроса → (длина, начало); пусто — без меры по кадрам."""
    if not значение:
        return None
    try:
        длина, начало = int(значение["длина"]), int(значение.get("начало") or 0)
    except (TypeError, ValueError, KeyError, AttributeError, OverflowError):
        длина, начало = 0, -1
    if not КАДР_ОТ <= длина <= КАДР_ДО or начало < 0:
        raise ValueError(f"кадр: {{длина, начало}} — длина от {КАДР_ОТ} до {КАДР_ДО} бит, начало — номер бита от 0")
    return длина, начало


def _геометрические(н: Настройки) -> dict[tuple, str]:
    """Подстановки, которые дают сами метки вида кода при повороте на кратное шага и инверсии.

    Их неоднозначность — от восстановления несущей: при равной мере они выше
    прочих (инверсию всех бит метки мера не различает, а поворотом она не бывает).
    """
    итог: dict[tuple, str] = {}
    основа = replace(н, вариант=0, таблица=())
    if н.относительная:
        # Инверсия меняет знак разности номеров: метка разности d — у точки −d.
        метки = декодер(основа).метки
        итог[метки] = "как вид кода"
        итог.setdefault(tuple(метки[-d % len(метки)] for d in range(len(метки))), "как вид кода с инверсией спектра")
        return итог
    шаг = плоскость(н.вид_кода).шаг
    for r in range(round(360 / шаг)):
        for инверсия in (False, True):
            try:
                д = декодер(replace(основа, поворот=r * шаг, инверсия=инверсия))
            except ValueError:
                continue
            итог.setdefault(д.таблица, f"поворот {r * шаг:g}°" + (", инверсия спектра" if инверсия else ""))
    return итог


def перебор(биты: np.ndarray, н: Настройки, с: int, по: int, *, срок: float | None = None,
            лучших: int = 20, кадр: tuple[int, int] | None = None) -> dict[str, Any]:
    """«Дек. всех»: варианты с номерами с…по (с 1, включительно) — мера каждого и лучшие.

    Мера — по выборке (``ВЫБОРКА_СИМВОЛОВ`` символов от начала). ``срок`` — секунд:
    по истечении перебор останавливается (хотя бы один вариант оценивается), ``до`` —
    номер последнего оценённого: окно просит следующую часть с него. Лучшие — по
    мере, при равной — геометрические (поворот, инверсия), затем по номеру. ``кадр`` — (длина,
    первый бит) кадров для меры (см. ``мера``).
    """
    всего = число_вариантов(н)
    с, по = max(1, int(с)), min(int(по), всего)
    if с > по:
        raise ValueError(f"варианты — с 1 по {всего}")
    k, M = н.k, 1 << н.k
    выборка = np.asarray(биты[:ВЫБОРКА_СИМВОЛОВ * k], dtype=np.uint8)
    n = len(выборка) // k
    символы = (выборка[:n * k].reshape(n, k).astype(np.int64) << np.arange(k - 1, -1, -1)).sum(axis=1)
    выход = np.array([_переставить(v, н.выход, k) for v in range(M)], dtype=np.int64)
    точки = np.array(_точки(н), dtype=np.int64)
    if н.относительная:
        номера = точки[символы]
        символы = (номера - np.concatenate(([0], номера[:-1]))) % M
        точки = np.arange(M)
    биты_меток = ((np.arange(M)[:, None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8)
    геометрические = _геометрические(н)
    конец = None if срок is None else time.monotonic() + срок
    меры, лучшие, номер = [], [], с - 1
    for номер in range(с, по + 1):  # noqa: B007 — последний номер нужен после цикла
        таблица = выход[np.asarray(разметка(н, номер), dtype=np.int64)[точки]]
        м = мера(биты_меток[таблица[символы]].ravel(), кадр)
        меры.append(round(м, 4))
        ключ = tuple(таблица.tolist())
        лучшие.append({"номер": номер, "таблица": запись(ключ), "мера": round(м, 4),
                       "как": геометрические.get(ключ, "")})
        if конец is not None and time.monotonic() > конец:
            break
    лучшие.sort(key=lambda в: (-в["мера"], not в["как"], в["номер"]))
    середина = float(np.median(меры))
    return {"всего": всего, "с": с, "до": номер, "меры": меры, "лучшие": лучшие[:max(1, int(лучших))],
            "медиана": round(середина, 4),
            "разброс": round(1.4826 * float(np.median(np.abs(np.array(меры) - середина))), 4)}


# -- для автомата: пары плоскостей ------------------------------------------------------------

def варианты_автомата(k: int) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    """Подбор плоскости ФМ-2^k: все пары (демодулятор, вид кода) из встроенных и папки.

    Абсолютные — повороты на шаг 360/M и инверсия (одинаковые таблицы — одна);
    относительные — инверсия (поворот в них меняет лишь первый символ). Вариант —
    {"таблица"} или {"номера", "метки"} и «имя» — описание параметров.
    """
    M = 1 << k
    плоскости = [с for с in годные(M) if плоскость(с).вид == "ФМ"]
    абсолютные: dict[tuple, dict[str, Any]] = {}
    относительные: dict[tuple, dict[str, Any]] = {}
    for дем in плоскости:
        for код in плоскости:
            for инверсия in (False, True):
                н = Настройки(k=k, вид="ФМ", демодулятор=дем, вид_кода=код, инверсия=инверсия,
                              вход=tuple(range(1, k + 1)), выход=tuple(range(1, k + 1)))
                д = декодер(replace(н, относительная=True))
                относительные.setdefault((д.номера, д.метки), {"номера": list(д.номера), "метки": list(д.метки),
                                                               "имя": д.описание})
                for r in range(M):
                    д = декодер(replace(н, поворот=r * плоскость(код).шаг))
                    абсолютные.setdefault(д.таблица, {"таблица": list(д.таблица), "имя": д.описание})
    return list(абсолютные.values()), list(относительные.values())
