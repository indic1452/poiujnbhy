@dataclass(frozen=True)
class Созвездие:
    """Точки созвездия: (метка, x, y); метка — k символов 0/1, старший бит первым."""

    имя: str
    точки: tuple[tuple[str, float, float], ...]
    встроенная: bool = False
    #: Координаты точные (строки «метка = x y» или встроенная), а не места знаков текстовой картинки.
    точные: bool = False
    #: Вид, заданный строкой «# вид: …» (или у встроенной): пусто — по геометрии.
    вид: str = ""

    @property
    def k(self) -> int:
        return len(self.точки[0][0])

    @property
    def M(self) -> int:
        return len(self.точки)


@dataclass(frozen=True)
class Плоскость:
    """Созвездие, приведённое к идеальной геометрии: точки по номерам."""

    вид: str                                   # «ФМ», «КАМ» или «общее»
    метки: tuple[int, ...]                     # метка точки с номером n
    xy: tuple[tuple[float, float], ...]        # идеальные координаты точки с номером n
    соседи: tuple[tuple[int, int], ...]        # номера соседних точек: по окружности или по сетке
    шаг: float                                 # наименьший поворот, переводящий созвездие в себя, °


def _метка(v: int, k: int) -> str:
    return format(v, f"0{k}b")


@lru_cache(maxsize=512)
def плоскость(с: Созвездие) -> Плоскость:
    """Вид созвездия (ФМ, КАМ или общее), номера точек и идеальные координаты; ошибки геометрии — ValueError.

    КАМ — точки заполняют сетку (различных столбцов × строк = M, от 8 точек). ФМ у
    текстовой картинки — точки на разных лучах из центра (важен только порядок по
    углу); у точных координат — на одной окружности через равные углы. Прочее
    (APSK, крестовые КАМ, несимметричные) — «общее»: точки как даны, приведённые к
    центру и единичной средней мощности; у картинки — только по строке «# вид: общее».
    """
    M = с.M
    xy = np.array([(x, y) for _, x, y in с.точки], dtype=float)
    метки = [int(м, 2) for м, _, _ in с.точки]
    if с.вид == "общее":
        return _общая(с, xy, метки)
    # Координаты точные: у картинки — половины и чётные, у встроенных и строк координат — как даны.
    столбцы = sorted(set(np.round(xy[:, 0], 9).tolist()))
    строки = sorted(set(np.round(xy[:, 1], 9).tolist()))
    if M >= 8 and len(столбцы) * len(строки) == M:
        i = [столбцы.index(x) for x in np.round(xy[:, 0], 9).tolist()]
        q = [строки.index(y) for y in np.round(xy[:, 1], 9).tolist()]
        порядок = sorted(range(M), key=lambda j: (-q[j], i[j]))
        a, b = len(столбцы), len(строки)
        точки = np.array([(i[j] - (a - 1) / 2, q[j] - (b - 1) / 2) for j in порядок])
        точки /= np.sqrt((точки ** 2).sum(axis=1).mean())
        место = {(i[j], q[j]): n for n, j in enumerate(порядок)}
        соседи = sorted(tuple(sorted((n, место[(ii + di, qq + dq)]))) for (ii, qq), n in место.items()
                        for di, dq in ((1, 0), (0, 1)) if (ii + di, qq + dq) in место)
        return Плоскость("КАМ", tuple(метки[j] for j in порядок),
                         tuple((float(x), float(y)) for x, y in точки), tuple(соседи), 90.0 if a == b else 180.0)
    if с.вид == "КАМ":
        raise ValueError(f"вид «КАМ», а точки не заполняют сетку: различных столбцов {len(столбцы)}, строк "
                         f"{len(строки)}, точек {M}")
    d = xy - xy.mean(axis=0)
    в_центре = np.flatnonzero(np.hypot(d[:, 0], d[:, 1]) < 1e-9)
    if (с.точные or с.встроенная) and с.вид != "ФМ":
        r = np.hypot(d[:, 0], d[:, 1])
        углы = np.sort(np.degrees(np.arctan2(d[:, 1], d[:, 0])) % 360)
        шаги = np.diff(np.concatenate([углы, [углы[0] + 360]]))
        if len(в_центре) or r.max() - r.min() > 1e-6 * r.max() or np.abs(шаги - 360 / M).max() > 1e-6:
            return _общая(с, xy, метки)
    if len(в_центре):
        raise ValueError(f"точка «{с.точки[в_центре[0]][0]}» в центре созвездия: у ФМ все точки на окружности")
    углы = np.round(np.degrees(np.arctan2(d[:, 1], d[:, 0])), 7) % 360
    порядок = np.argsort(углы, kind="stable")
    for a, b in zip(порядок[:-1], порядок[1:], strict=True):
        if углы[b] - углы[a] < 1e-6:
            raise ValueError(f"точки «{с.точки[a][0]}» и «{с.точки[b][0]}» на одном луче из центра: "
                             f"порядок ФМ по углу не определён (APSK и прочие — строкой «# вид: общее» "
                             f"или координатами «метка = x y»)")
    углы_ид = 2 * np.pi * np.arange(M) / M
    return Плоскость("ФМ", tuple(метки[j] for j in порядок),
                     tuple((float(np.cos(у)), float(np.sin(у))) for у in углы_ид),
                     tuple(sorted({tuple(sorted((n, (n + 1) % M))) for n in range(M)})), 360.0 / M)


#: Общая плоскость: соседи — пары не дальше этой доли от наименьшего расстояния каждой из двух точек.
СОСЕДИ_ДО = 1.25
#: Поворот переводит общую плоскость в себя, если каждая точка ложится ближе этой доли наименьшего расстояния.
ПОВОРОТ_ДОПУСК = 0.25


def _общая(с: Созвездие, xy: np.ndarray, метки: list[int]) -> Плоскость:
    """Точки как даны: центр — среднее, средняя мощность — 1; номера — как читают картинку (сверху вниз, слева направо)."""
    M = с.M
    d = xy - xy.mean(axis=0)
    мощность = float((d ** 2).sum(axis=1).mean())
    if мощность <= 0:
        raise ValueError("все точки созвездия совпадают")
    d /= math.sqrt(мощность)
    между = np.hypot(*(d[:, None, :] - d[None, :, :]).transpose(2, 0, 1))
    np.fill_diagonal(между, np.inf)
    ближе = между.min()
    if ближе < 1e-6:
        i, j = np.unravel_index(int(np.argmin(между)), между.shape)
        raise ValueError(f"точки «{с.точки[i][0]}» и «{с.точки[j][0]}» совпадают")
    порядок = sorted(range(M), key=lambda j: (-round(float(d[j, 1]), 6), round(float(d[j, 0]), 6)))
    место = {j: n for n, j in enumerate(порядок)}
    своё = между.min(axis=1)
    соседи = sorted({(min(место[i], место[j]), max(место[i], место[j])) for i in range(M) for j in range(M)
                     if i != j and между[i, j] <= СОСЕДИ_ДО * min(своё[i], своё[j])})
    return Плоскость("общее", tuple(метки[j] for j in порядок), tuple((float(d[j, 0]), float(d[j, 1])) for j in порядок),
                     tuple(соседи), _шаг_поворота(d[порядок], ближе))


def _шаг_поворота(xy: np.ndarray, ближе: float) -> float:
    """Наименьший поворот 360/n°, переводящий точки в себя (каждая — к своей, ближе допуска); иначе 360°."""
    M = len(xy)
    for n in range(M, 1, -1):
        φ = 2 * math.pi / n
        повёрнуто = xy @ np.array([[math.cos(φ), math.sin(φ)], [-math.sin(φ), math.cos(φ)]])
        до = np.hypot(*(повёрнуто[:, None, :] - xy[None, :, :]).transpose(2, 0, 1))
        куда = до.argmin(axis=1)
        if до.min(axis=1).max() < ПОВОРОТ_ДОПУСК * ближе and len(set(куда.tolist())) == M:
            return 360.0 / n
    return 360.0


# -- встроенные созвездия (генерируются, не по памяти) -------------------------------------

def _грей(n: int) -> int:
    return n ^ (n >> 1)


