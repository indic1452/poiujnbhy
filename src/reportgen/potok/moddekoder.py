"""Модуляционный декодер — как окно «Модуляционный декодер» в софте отдела аналитиков.

Демодулятор отдаёт метку точки созвездия (k бит на символ), но нумерует точки
по-своему; модулятор на передаче нумеровал их иначе («вид кода»), а несущая
восстановлена с точностью до поворота и, бывает, с инверсией спектра. Декодер
переводит метки демодулятора в метки вида кода:

1. перестановка бит входа: вход «1,2,3» — бит i новой метки берётся из бита
   p[i] старой (нумерация с 1, слева направо — от старшего бита метки);
2. точка по таблице демодулятора;
3. инверсия спектра — зеркало y → −y (сопряжение);
4. поворот на φ градусов против часовой стрелки;
5. ближайшая точка созвездия вида кода: оба созвездия приведены к общему центру
   и единичной средней мощности; если поворот не переводит созвездие в себя
   (до ближайшей точки не ближе половины наименьшего расстояния между точками
   вида кода) — ошибка «поворот φ° не переводит созвездие в себя; для ФМ-M шаг
   360/M°»;
6. метка этой точки у вида кода;
7. перестановка бит выхода — так же, как у входа.

Всё это сводится к таблице подстановки метка → метка: она и применяется к
потоку любой длины (numpy, сразу), хвост, не кратный k, отбрасывается.

**Относительный (дифференциальный) режим** — только для ФМ: у метки берётся
номер n точки демодулятора по окружности — по углу после инверсии и поворота,
от точки с наименьшим неотрицательным углом; на выходе — метка точки вида кода с
номером (n[i] − n[i−1]) mod M (номера вида кода — так же по углу). Первый
символ — относительно номера 0. Поворот в этом режиме меняет лишь первый символ.

**Геометрия.** У ФМ важен только порядок точек по углу: точка с номером n
считается лежащей под углом n·360/M. У КАМ (точки заполняют сетку: различных
столбцов × строк = M, от 8 точек) — уровни I и Q по номерам различных столбцов и
строк, номера точек — как читают картинку: сверху вниз, слева направо.

**Файл .etl** — текстовая картинка созвездия: метка каждой точки (k символов 0 и
1) написана там, где точка лежит на плоскости I/Q. Токены — серии 0/1, не
прилепленные к буквам и другим цифрам; x — середина токена в символах, y —
−(номер строки) × 2 (знак примерно вдвое выше ширины; для ФМ растяжение оси
порядок точек по углу не меняет). Кодировка — utf-8 или cp1251, конец строки —
любой.

**Варианты.** Вместо меток вида кода можно взять любую разметку его точек:
все M! («все варианты», только до 8 точек) или только коды Грея — соседние по
окружности (по сетке) точки отличаются одним битом. Порядок — лексикографический
по (метка точки 0, метка точки 1, …), номера с 1. «Дек. всех» оценивает каждый
вариант мерой структуры и показывает лучшие с отрывом от толпы.
"""

