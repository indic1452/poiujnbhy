"""Кадр модема: синхрослово, плоскость созвездия и код произведения внутри кадров.

Спутниковый модем (Comtech и др.) шлёт кадры: синхрослово (часто в двух
чередующихся вариантах) и блок помехоустойчивого кода — например, TPC
(64, 57) × (46, 39) в кадре 2964 бит. Демодулятор отдаёт метки созвездия в
своей нумерации, и строки кода видны, только когда плоскость подобрана
верно. Здесь это делается по кадрам:

1. начала кадров — по служебным словам цикла с маховиком (``cikl.кадры``);
2. код в кадрах как есть (``tpc.найти_в_кадрах``);
3. если модуляция известна (ФМ-2^k по имени файла или от аналитика) —
   подбор плоскости по мере строк кода в кадрах; у нескольких вариантов
   мера бывает почти одинаковой (часть бит метки верна, и под ними тоже
   виден код — только слабее), поэтому код снимается у каждого из лучших, и
   берётся тот, у кого проверок больше всего (полный код, а не его часть).
"""

from __future__ import annotations

from collections.abc import Sequence

import numpy as np

from . import ploskost, skrembler, tpc, tpc_rezhimy
from .nahodka import Находка

#: Сколько лучших вариантов плоскости пробовать кодом.
ЛУЧШИХ_ВАРИАНТОВ = 24
#: Варианты с мерой не ниже этой доли от лучшей — «почти равные».
РАВНЫЕ = 0.9
#: По скольким первым кадрам пробуется код у каждого из почти равных вариантов.
КАДРОВ_ПРОБЫ = 160


_проверок = tpc.проверок


#: Доля чистых блоков слепого снятия, при которой каталог режимов не нужен.
ВСЁ_ЧИСТО = 0.99
#: Мера структуры, с которой данные под кодом считаются открытыми сразу.
СТРУКТУРА_СРАЗУ = 0.3


def простота(код: Находка) -> tuple[int, float]:
    """Насколько просто то, что под кодом: (ступень, мера).

    3 — структура видна сразу (мера структуры); 2 — данные под ПСП блока,
    и она ЛРП; 1 — прочее, мера — отрыв лучшего самосинхронизирующегося
    скремблера от толпы (у верного варианта скремблер снимается и открывает
    структуру, у прочих её портит узор инверсии).

    Варианты меток, отличающиеся инверсией бита метки, снимают код одинаково
    (маска на кадре — смещение кода), но данные у них разные: у верного —
    сами данные (под скремблером), у прочих — ещё и узор инверсии. Этим они
    и различаются.
    """
    данные = np.asarray(код.дальше[:1 << 20], dtype=np.uint8)
    мера = skrembler.мера_структуры(данные)
    if мера >= СТРУКТУРА_СРАЗУ:
        return 3, мера
    блок = (код.свойства or {}).get("данных_в_блоке")
    if блок and skrembler.блоковая_псп(данные, int(блок)) is not None:
        return 2, мера
    return 1, skrembler.отрыв(данные)


def _выбрать_равноценный(равные: list) -> tuple[int, str]:
    """Из вариантов, снимающих код одинаково, — тот, под которым данные проще: (номер, пояснение)."""
    данные = [np.asarray(с[1].дальше[:1 << 20], dtype=np.uint8) for с in равные]
    блоки = [(с[1].свойства or {}).get("данных_в_блоке") for с in равные]
    return выбрать_по_простоте(
        len(равные),
        lambda j: skrembler.мера_структуры(данные[j]),
        lambda j: bool(блоки[j]) and skrembler.блоковая_псп(данные[j], int(блоки[j])) is not None,
        lambda j: skrembler.отрыв(данные[j]))


def выбрать_по_простоте(n: int, структура, лрп, отрыв) -> tuple[int, str]:
    """Выбор автомата среди n вариантов, снимающих код одинаково: (номер, пояснение).

    То же, что максимум ``простота`` по вариантам (при равной — первый), но части простоты
    считаются только там, где они решают: ``структура(j)`` — мера структуры данных под кодом
    j-го варианта (дёшево — у всех), ``лрп(j)`` — данные под ПСП блока, и она ЛРП (дорого: по
    убыванию меры структуры до первого «да» — выше него ступень 2 не бывает), ``отрыв(j)`` —
    отрыв скремблера (только если ни ступени 3, ни 2 нет ни у кого). Так считает и автомат
    (``_выбрать_равноценный``), и окно «Дек. всех» — по готовым фактам.
    """
    вступление = (f"равноценных по коду вариантов — {n} (отличаются инверсией бит метки: "
                  f"код снимается одинаково, данные — нет); ")
    меры = [структура(j) for j in range(n)]
    сразу = [j for j in range(n) if меры[j] >= СТРУКТУРА_СРАЗУ]
    if сразу:
        return (max(сразу, key=lambda j: (меры[j], -j)),
                вступление + "выбран тот, под которым данные открываются сразу")
    i = next((j for j in sorted(range(n), key=lambda j: (-меры[j], j)) if лрп(j)), None)
    if i is not None:
        return i, вступление + "выбран тот, под которым данные — под ПСП блока, и она ЛРП"
    # Отрыв: при равном — первый (равный следующему всё равно «не проще прочих» — взят первый).
    отрывы = [отрыв(j) for j in range(n)]
    i = max(range(n), key=отрывы.__getitem__)
    мера = отрывы[i]
    прочие = sorted((м for j, м in enumerate(отрывы) if j != i), reverse=True)
    if мера < skrembler.ВЫДЕЛЯЕТСЯ or (прочие and мера < 1.5 * прочие[0]):
        return 0, вступление + ("данные ни под одним не проще прочих — взят первый по мере; данные "
                                "могут отличаться от истинных постоянной маской на блоке (её снимет "
                                "ПСП блока по заполнению)")
    return i, вступление + (f"выбран тот, под которым сильнее всего проявляется скремблер (отрыв "
                            f"{мера:.0f} разбросов против {прочие[0]:.0f} у следующего)")


def _снять_лучший(биты: np.ndarray, k: int, начала: list[int], длина: int, старт: int,
                  варианты: list[tuple[float, dict[str, object], int]]):
    """Код у почти равных по мере вариантов (пробой по первым кадрам), выбор и снятие целиком.

    (код, вариант, фаза, мера, пояснение выбора) или None.
    """
    лучшая = варианты[0][0]
    # Проба — по первым КАДРОВ_ПРОБЫ кадрам: у каждого из почти равных
    # вариантов снимать код целиком долго, а число проверок и то, что под
    # кодом, видны и по части. Целиком снимается только выбранный.
    сняты = []
    for мера, вариант, фаза in варианты[:ЛУЧШИХ_ВАРИАНТОВ]:
        if мера < РАВНЫЕ * лучшая:
            break
        ряд = ploskost.с_фазой(биты, k, вариант, фаза)
        свои = [н - фаза for н in начала if н >= фаза]
        проба = tpc.найти_в_кадрах(ряд, свои[старт:старт + КАДРОВ_ПРОБЫ], длина)
        if проба is not None:
            сняты.append(((_проверок(проба), проба.уверенность), проба, вариант, фаза, мера, ряд, свои))
    if not сняты:
        return None
    сняты.sort(key=lambda с: с[0], reverse=True)
    равные = [с for с in сняты if с[0] == сняты[0][0]]
    выбор = ""
    if len(равные) > 1:
        # Код снимается одинаково — решает то, что под ним (порядок меры сохраняется).
        i, выбор = _выбрать_равноценный(равные)
        сняты.remove(равные[i])
        сняты.insert(0, равные[i])
    for _, _, вариант, фаза, мера, ряд, свои in сняты:
        код = tpc.найти_в_кадрах(ряд, свои, длина)
        if код is not None:
            # Начало первого кадра — по меткам до подбора плоскости: после него служебное слово
            # выглядит иначе, и кадры по нему встают на бит-другой в стороне (ручной слой — «с бита»).
            код.свойства["первый_кадр"] = int(свои[0]) if свои else 0
            return код, вариант, фаза, мера, выбор
    return None


# -- окно «Дек. всех»: равноценные варианты — в том порядке, в каком их выбрал бы автомат -------------

#: Секунд на пробу равноценных кодом в кадрах (не уложилась — порядок окна остаётся по мере).
ПРОБА_СРОК = 30.0


class НужныФакты(LookupError):
    """Для выбора среди этих таблиц фактов пробы мало (проба шла по другому набору)."""


def сдвиг_инверсии(таблица: Sequence[int], основа: Sequence[int]) -> int | None:
    """c, если таблица = основа ⊕ c (те же метки с инверсией бит c), иначе None."""
    if len(таблица) != len(основа) or not len(основа):
        return None
    c = int(таблица[0]) ^ int(основа[0])
    return c if all(int(т) ^ int(о) == c for т, о in zip(таблица, основа, strict=True)) else None


def _маска_инверсии(c: int, k: int, кадры: Sequence[int], длина_ряда: int, свойства: dict) -> np.ndarray | None:
    """Во что инверсия бит c у каждой метки (с бита 0) переходит в данных под кодом, снятым в кадрах."""
    с = свойства or {}
    if not с.get("строка") or not с.get("строк_в_кадре"):
        return None
    o, ширина = int(с.get("начало_в_кадре") or 0), int(с["строк_в_кадре"]) * int(с["строка"])
    начала = np.asarray([int(н) + o for н in кадры if 0 <= int(н) + o and int(н) + o + ширина <= длина_ряда],
                        dtype=np.int64)
    if not len(начала):
        return None
    биты_c = np.array([(c >> (k - 1 - i)) & 1 for i in range(k)], dtype=np.uint8)
    return tpc.маска_данных(с, биты_c[(начала[:, None] + np.arange(ширина)[None, :]) % k])


def факты_равноценных(биты: np.ndarray, k: int, таблицы: Sequence[Sequence[int]], начала: Sequence[int],
                      длина: int, *, срок: float | None = None, отрыв: bool | None = None) -> dict[str, object]:
    """Проба кода в кадрах под каждой таблицей (с бита 0) и простота данных под ним — как у автомата.

    Код — ``tpc.найти_в_кадрах`` по ``КАДРОВ_ПРОБЫ`` кадрам с участка с данными (``_снять_лучший``).
    Таблицы, отличающиеся от уже пробованной инверсией бит метки (``сдвиг_инверсии``), код снимают
    так же (маска на кадре — смещение кода): их данные — данные пробованной ⊕ маска
    (``tpc.маска_данных``), без нового поиска кода — так восемь вариантов ФМ-8 пробуются за
    время одного. Части простоты (``выбрать_по_простоте``): мера структуры — у всех, отрыв
    скремблера — если ни у одной нет ни ступени 3, ни 2 (или ``отрыв`` — True).
    ПСП блока — по убыванию меры структуры до первого «да» (выбор между таблицами ниже него
    она уже не меняет). Итог (простые типы — для кэша и ответа окну): {"таблицы": {запись: факты}, "код": {что,
    мера, уверенность}, "кадры", "уложилась", "время"}.
    """
    import time  # noqa: PLC0415

    t0 = time.monotonic()
    конец = t0 + (ПРОБА_СРОК if срок is None else срок)
    начала = [int(н) for н in начала]
    старт = tpc.начало_данных(биты, начала, длина)
    кадры = начала[старт:старт + КАДРОВ_ПРОБЫ]
    # Код ищется только в этих кадрах — и метки переводятся только до них (с запасом на строку за
    # концом кадра): у мегабайта выборки перевод всех меток дольше самой пробы кода.
    if кадры:
        биты = биты[:max(кадры) + 2 * (длина + tpc.ДЛИНА_ДО)]
    длина_ряда = len(биты) - len(биты) % k
    факты: dict[str, dict[str, object]] = {}
    данные: dict[str, np.ndarray] = {}
    основа: tuple | None = None          # (таблица, код или None, данные, ключ) — первая пробованная
    уложилась = True
    код_итог = None
    for т in таблицы:
        т = [int(x) for x in т]
        ключ = " ".join(map(str, т))
        if ключ in факты:
            continue
        if time.monotonic() > конец:
            уложилась = False
            break
        c = сдвиг_инверсии(т, основа[0]) if основа is not None else None
        if c is not None and основа[1] is None:
            факты[ключ] = {"снят": False, "путь": "маска"}
            continue
        if c is not None:
            маска = _маска_инверсии(c, k, кадры, длина_ряда, основа[1].свойства)
            if маска is not None and len(маска) >= len(основа[2]):
                данные[ключ] = основа[2] ^ маска[:len(основа[2])]
                факты[ключ] = {**{п: факты[основа[3]][п] for п in ("снят", "проверок", "уверенность", "блок")},
                               "путь": "маска"}
                continue
        код = tpc.найти_в_кадрах(ploskost.с_фазой(биты, k, {"таблица": т}, 0), кадры, длина)
        if код is None:
            факты[ключ] = {"снят": False, "путь": "проба"}
        else:
            данные[ключ] = np.asarray(код.дальше[:1 << 20], dtype=np.uint8)
            факты[ключ] = {"снят": True, "проверок": int(_проверок(код)), "уверенность": float(код.уверенность),
                           "блок": int((код.свойства or {}).get("данных_в_блоке") or 0), "путь": "проба"}
            if код_итог is None:
                код_итог = {"что": код.что, "мера": код.мера, "уверенность": float(код.уверенность),
                            "кадров": len(кадры)}
        if основа is None:
            основа = (т, код, данные.get(ключ), ключ)
    for ключ, д in данные.items():
        факты[ключ]["структура"] = float(skrembler.мера_структуры(д))
    # ПСП блока — как в ``выбрать_по_простоте``: по убыванию меры структуры (при равной — в порядке
    # таблиц) до первого «да»; ниже него она выбора уже не меняет (у подмножества с ним — тоже).
    ключи = list(данные)
    if not any(факты[к]["структура"] >= СТРУКТУРА_СРАЗУ for к in ключи):
        for ключ in sorted(ключи, key=lambda к: (-факты[к]["структура"], ключи.index(к))):
            if time.monotonic() > конец:
                уложилась = False
                break
            ф = факты[ключ]
            ф["лрп"] = bool(ф["блок"]) and skrembler.блоковая_псп(данные[ключ], int(ф["блок"])) is not None
            if ф["лрп"]:
                break
    нужен_отрыв = отрыв if отрыв is not None else not any(
        ф.get("структура", 0) >= СТРУКТУРА_СРАЗУ or ф.get("лрп") for ф in факты.values())
    if нужен_отрыв and уложилась:
        for ключ, д in данные.items():
            if time.monotonic() > конец:
                уложилась = False
                break
            факты[ключ]["отрыв"] = float(skrembler.отрыв(д))
    return {"таблицы": факты, "код": код_итог, "уложилась": уложилась,
            "кадры": {"длина": int(длина), "первый": начала[0] if начала else 0, "кадров": len(начала),
                      "старт": int(старт), "проба": len(кадры)},
            "время": round(time.monotonic() - t0, 2)}


def решить_равноценные(таблицы: Sequence[Sequence[int]], факты: dict[str, object]) -> dict[str, object]:
    """Выбор автомата среди таблиц (в порядке окна — по мере) по фактам пробы (``факты_равноценных``).

    Как ``_снять_лучший``: снявшие код — выше, по числу проверок и чистоте блоков (при равных —
    порядок окна), из равных по коду — ``выбрать_по_простоте``. Итог: «порядок» (номера в
    ``таблицы``), «выбран» (номер или None — код не снялся ни под одной), «выбор» — пояснение
    автомата, «ступень» выбранного (3 — данные открыты, 2 — ПСП блока, 1 — скремблер, 0 — по
    коду). Фактов не хватает (проба шла по другому набору) — ``НужныФакты``.
    """
    по_ключу = факты.get("таблицы") or {}
    ф = []
    for т in таблицы:
        x = по_ключу.get(" ".join(str(int(v)) for v in т))
        if x is None:
            raise НужныФакты("таблица без пробы")
        ф.append(x)
    n = len(ф)
    сняты = [j for j in range(n) if ф[j].get("снят")]
    if not сняты:
        return {"порядок": list(range(n)), "выбран": None, "выбор": "", "ступень": 0}

    def ключ(j: int) -> tuple:
        return ф[j]["проверок"], ф[j]["уверенность"]

    сняты.sort(key=ключ, reverse=True)
    равные = [j for j in сняты if ключ(j) == ключ(сняты[0])]
    выбор, ступень = "", 0
    if len(равные) > 1:
        def взять(поле: str):
            def значение(i: int):
                v = ф[равные[i]].get(поле)
                if v is None:
                    raise НужныФакты(поле)
                return v
            return значение
        i, выбор = выбрать_по_простоте(len(равные), взять("структура"), взять("лрп"), взять("отрыв"))
        лучший = ф[равные[i]]
        ступень = (3 if лучший["структура"] >= СТРУКТУРА_СРАЗУ else 2 if лучший.get("лрп")
                   else 1 if "выбран тот" in выбор else 0)
        сняты.remove(равные[i])
        сняты.insert(0, равные[i])
    return {"порядок": сняты + [j for j in range(n) if j not in сняты], "выбран": сняты[0], "выбор": выбор,
            "ступень": ступень, "равных": len(равные)}


#: Разметка вслепую в кадрах модема (любая перестановка меток, до 8 точек): секунд на все фазы символа.
РАЗМЕТКА_СРОК = 90.0


def _вслепую(биты: np.ndarray, k: int, начала: list[int], длина: int, старт: int, срок: float | None):
    """Разметка вслепую по строкам кода в кадрах: (варианты [(мера, вариант, фаза)], итог поиска) или None."""
    import time  # noqa: PLC0415

    from . import razmetka  # noqa: PLC0415

    if not 2 < (1 << k) <= 8 or длина % k:
        return None
    конец = time.monotonic() + (РАЗМЕТКА_СРОК if срок is None else срок)
    for фаза in range(k):
        осталось = конец - time.monotonic()
        if осталось <= 0:
            break
        итог = razmetka.искать(биты, k, мера="строки", кадры=(начала[старт:], длина), фаза=фаза, срок=осталось)
        if итог is None:
            continue
        return [(итог.мера, {"таблица": т, "имя": f"таблица {' '.join(map(str, т))}", "вслепую": True}, фаза)
                for т in итог.равноценные], итог
    return None


def код_в_кадрах(биты: np.ndarray, начала: Sequence[int], длина: int, *, фм: Sequence[int] = (),
                 срок_вслепую: float | None = None) -> tuple[list[Находка], np.ndarray] | None:
    """Плоскость (если нужна) и код произведения в кадрах: (находки, данные) или None.

    Если ни поворот, ни отражение, ни таблицы плоскостей код не открыли — разметка
    ищется вслепую (любая перестановка меток; ``срок_вслепую`` — секунд).
    """
    начала = [int(н) for н in начала]
    как_есть = tpc.найти_в_кадрах(биты, начала, длина)
    if как_есть is None or как_есть.уверенность < ВСЁ_ЧИСТО:
        # Режим модема из каталога: укорочение B, гипердиагональ, выколотые биты — то, чего
        # слепое снятие не видит. Берётся, если объясняет блоки не хуже слепого.
        по_режиму = tpc_rezhimy.найти_в_кадрах(биты, длина, начала)
        if по_режиму is not None and (как_есть is None or по_режиму.уверенность >= как_есть.уверенность):
            return [по_режиму], по_режиму.дальше
    if как_есть is not None:
        как_есть.свойства["первый_кадр"] = начала[0] if начала else 0
        return [tpc_rezhimy.подписать(как_есть)], как_есть.дальше
    # Подбор плоскости и проба кода — с участка с данными: запись часто начинается
    # с долгой паузы из одинаковых кадров заполнения, по ним код не виден.
    старт = tpc.начало_данных(биты, начала, длина)
    for k in фм:
        варианты = ploskost.варианты_фм_в_кадрах(биты, k, начала[старт:], длина)
        снято = _снять_лучший(биты, k, начала, длина, старт, варианты) if варианты else None
        вслепую = None
        if снято is None:
            вслепую = _вслепую(биты, k, начала, длина, старт, срок_вслепую)
            if вслепую is None:
                continue
            варианты = вслепую[0]
            снято = _снять_лучший(биты, k, начала, длина, старт, варианты)
            if снято is None:
                continue
        код, вариант, фаза, мера, выбор = снято
        лучшая = варианты[0][0]
        база = варианты[-1][0] if варианты else 0.0
        ош = float(код.свойства.get("ошибок_в_линии", 0.0))
        es = ош_фм(ош, k)
        if es is not None:
            from math import log10  # noqa: PLC0415
            с = код.свойства
            скорость = с["данных_в_блоке"] / max(1, с["строка"] * с["столбец"] * max(1, с.get("глубина") or 0))
            код.подробно.append(
                f"ошибок в линии до декодирования ≈ {ош:.1e} (по исправленным); для ФМ-{1 << k} с кодом "
                f"Грея при жёстких решениях это Es/N0 ≈ {es:.1f} дБ, Eb/N0 ≈ {es - 10 * log10(k):.1f} дБ на "
                f"кодовый бит (≈ {es - 10 * log10(k * скорость):.1f} дБ на бит данных) — оценка по "
                f"приближению для больших ОСШ")
        if вслепую is not None:
            _, итог = вслепую
            плоскость = Находка(
                уровень="плоскость",
                что=f"модуляционная плоскость ФМ-{1 << k}: разметка найдена вслепую по строкам кода в кадрах — "
                    f"{вариант['имя']} (принятая метка → истинная), фаза символа {фаза}",
                уверенность=код.уверенность,
                мера=f"строки кода в кадрах выделяются на {мера:.0f} разбросов; код под этой разметкой "
                     f"снимается целиком ({_проверок(код)} проверок)",
                подробно=[f"повороты, отражения, перестановки бит и таблицы плоскостей код не открыли — метки "
                          f"даны точкам иначе; разметка (принятая метка → истинная) найдена перебором всех "
                          f"перестановок меток за {итог.сведения.get('время', 0):g} с", *итог.подробно]
                         + ([выбор] if выбор else []),
                свойства={"вариант": вариант, "фаза": фаза, "k": k, "вслепую": True})
            return [плоскость, код], код.дальше
        плоскость = Находка(
            уровень="плоскость",
            что=f"модуляционная плоскость ФМ-{1 << k} подобрана по коду в кадрах: "
                f"{ploskost.имя_фм(вариант, k)}, фаза символа {фаза}",
            уверенность=код.уверенность,
            мера=f"строки кода в кадрах выделяются на {мера:.0f} разбросов; код под этим вариантом "
                 f"снимается целиком ({_проверок(код)} проверок)",
            подробно=[f"перебрано вариантов меток: {len(ploskost.варианты_фм(k))} × {k} фазы символа; "
                      f"почти равных по мере — {sum(1 for м, *_ in варианты if м >= РАВНЫЕ * лучшая)}: "
                      f"из них выбран тот, под которым у кода больше всего проверок "
                      f"(у частично верных вариантов виден лишь подкод)",
                      f"мера у худшего из лучших вариантов — {база:.0f}"] + ([выбор] if выбор else []),
            свойства={"вариант": вариант, "фаза": фаза, "k": k})
        return [плоскость, код], код.дальше
    return None


def ош_фм(ош: float, k: int) -> float | None:
    """Es/N0 (дБ) ФМ-2^k с кодом Грея при жёстких решениях по вероятности ошибки на бит.

    Приближение для больших ОСШ: ош ≈ (2/k)·Q(√(2·Es/N0)·sin(π/M)) (ошибка — в
    соседнюю точку, у соседей по Грею различается один бит); у ФМ-2 —
    ош = Q(√(2·Es/N0)). Q(x) = ½·erfc(x/√2); обращается делением пополам.
    """
    from math import erfc, pi, sin, sqrt  # noqa: PLC0415
    if not 0 < ош < 0.2 or k < 1:
        return None
    M = 1 << k

    def ош_при(дб: float) -> float:
        es = 10 ** (дб / 10)
        if k == 1:
            return 0.5 * erfc(sqrt(es))
        return (2 / k) * 0.5 * erfc(sqrt(2 * es) * sin(pi / M) / sqrt(2))

    низ, верх = -10.0, 40.0
    for _ in range(80):
        середина = (низ + верх) / 2
        if ош_при(середина) > ош:
            низ = середина
        else:
            верх = середина
    return (низ + верх) / 2


def разобрать_кадры(биты: np.ndarray, длина_цикла: int, *, фм: Sequence[int] = (),
                    срок_вслепую: float | None = None
                    ) -> tuple[list[Находка], np.ndarray, dict[str, object]] | None:
    """Кадры по циклу → плоскость → код: (находки, данные, сведения о кадрах) или None."""
    from . import cikl  # noqa: PLC0415

    найдено = cikl.кадры(биты, длина_цикла)
    if найдено is None:
        return None
    начала, сведения = найдено
    итог = код_в_кадрах(биты, начала, int(сведения["кадр"]), фм=фм, срок_вслепую=срок_вслепую)
    if итог is None:
        return None
    находки, данные = итог
    return находки, данные, сведения
