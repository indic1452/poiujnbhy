# -*- coding: utf-8 -*-
"""Кадр модема: синхрослово, плоскость созвездия и код произведения внутри кадров.

Спутниковый модем (Comtech и др.) шлёт кадры: синхрослово (часто в двух
чередующихся вариантах) и блок помехоустойчивого кода — например, TPC
(64, 57) × (46, 39) в кадре 2964 бит. Демодулятор отдаёт метки созвездия в
своей нумерации, и строки кода видны, только когда плоскость подобрана
верно. Здесь это делается по кадрам:

1. начала кадров — по служебным словам цикла с маховиком (``cikl.кадры``);
2. код в кадрах как есть (``tpc.найти_в_кадрах``);
3. если модуляция известна (ФМ-2^k по имени файла или от аналитика) —
   подбор плоскости по мере строк кода в кадрах; у нескольких вариантов
   мера бывает почти одинаковой (часть бит метки верна, и под ними тоже
   виден код — только слабее), поэтому код снимается у каждого из лучших, и
   берётся тот, у кого проверок больше всего (полный код, а не его часть).
"""

from __future__ import annotations

from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from . import ploskost, skrembler, tpc
from .nahodka import Находка

#: Сколько лучших вариантов плоскости пробовать кодом.
ЛУЧШИХ_ВАРИАНТОВ = 24
#: Варианты с мерой не ниже этой доли от лучшей — «почти равные».
РАВНЫЕ = 0.9
#: По скольким первым кадрам пробуется код у каждого из почти равных вариантов.
КАДРОВ_ПРОБЫ = 160


_проверок = tpc.проверок


#: Мера структуры, с которой данные под кодом считаются открытыми сразу.
СТРУКТУРА_СРАЗУ = 0.3


def простота(код: Находка) -> Tuple[int, float]:
    """Насколько просто то, что под кодом: (ступень, мера).

    3 — структура видна сразу (мера структуры); 2 — данные под ПСП блока,
    и она ЛРП; 1 — прочее, мера — отрыв лучшего самосинхронизирующегося
    скремблера от толпы (у верного варианта скремблер снимается и открывает
    структуру, у прочих её портит узор инверсии).

    Варианты меток, отличающиеся инверсией бита метки, снимают код одинаково
    (маска на кадре — смещение кода), но данные у них разные: у верного —
    сами данные (под скремблером), у прочих — ещё и узор инверсии. Этим они
    и различаются.
    """
    данные = np.asarray(код.дальше[:1 << 20], dtype=np.uint8)
    мера = skrembler.мера_структуры(данные)
    if мера >= СТРУКТУРА_СРАЗУ:
        return 3, мера
    блок = (код.свойства or {}).get("данных_в_блоке")
    if блок and skrembler.блоковая_псп(данные, int(блок)) is not None:
        return 2, мера
    return 1, skrembler.отрыв(данные)


def _выбрать_равноценный(равные: list) -> Tuple[int, str]:
    """Из вариантов, снимающих код одинаково, — тот, под которым данные проще: (номер, пояснение)."""
    оценки = [простота(с[1]) for с in равные]
    i = max(range(len(равные)), key=lambda j: (оценки[j], -j))
    ступень, мера = оценки[i]
    вступление = (f"равноценных по коду вариантов — {len(равные)} (отличаются инверсией бит метки: "
                  f"код снимается одинаково, данные — нет); ")
    if ступень == 3:
        return i, вступление + "выбран тот, под которым данные открываются сразу"
    if ступень == 2:
        return i, вступление + "выбран тот, под которым данные — под ПСП блока, и она ЛРП"
    прочие = sorted((м for j, (_, м) in enumerate(оценки) if j != i), reverse=True)
    if мера < skrembler.ВЫДЕЛЯЕТСЯ or (прочие and мера < 1.5 * прочие[0]):
        return 0, вступление + ("данные ни под одним не проще прочих — взят первый по мере; данные "
                                "могут отличаться от истинных постоянной маской на блоке (её снимет "
                                "ПСП блока по заполнению)")
    return i, вступление + (f"выбран тот, под которым сильнее всего проявляется скремблер (отрыв "
                            f"{мера:.0f} разбросов против {прочие[0]:.0f} у следующего)")


def код_в_кадрах(биты: np.ndarray, начала: Sequence[int], длина: int, *, фм: Sequence[int] = ()
                 ) -> Optional[Tuple[List[Находка], np.ndarray]]:
    """Плоскость (если нужна) и код произведения в кадрах: (находки, данные) или None."""
    начала = [int(н) for н in начала]
    как_есть = tpc.найти_в_кадрах(биты, начала, длина)
    if как_есть is not None:
        return [как_есть], как_есть.дальше
    for k in фм:
        варианты = ploskost.варианты_фм_в_кадрах(биты, k, начала, длина)
        if not варианты:
            continue
        лучшая = варианты[0][0]
        # Проба — по первым КАДРОВ_ПРОБЫ кадрам: у каждого из почти равных
        # вариантов снимать код целиком долго, а число проверок и то, что под
        # кодом, видны и по части. Целиком снимается только выбранный.
        сняты = []
        for мера, вариант, фаза in варианты[:ЛУЧШИХ_ВАРИАНТОВ]:
            if мера < РАВНЫЕ * лучшая:
                break
            ряд = ploskost.с_фазой(биты, k, вариант, фаза)
            свои = [н - фаза for н in начала if н >= фаза]
            проба = tpc.найти_в_кадрах(ряд, свои[:КАДРОВ_ПРОБЫ], длина)
            if проба is not None:
                сняты.append(((_проверок(проба), проба.уверенность), проба, вариант, фаза, мера, ряд, свои))
        if not сняты:
            continue
        сняты.sort(key=lambda с: с[0], reverse=True)
        равные = [с for с in сняты if с[0] == сняты[0][0]]
        выбор = ""
        if len(равные) > 1:
            # Код снимается одинаково — решает то, что под ним (порядок меры сохраняется).
            i, выбор = _выбрать_равноценный(равные)
            сняты.remove(равные[i])
            сняты.insert(0, равные[i])
        код = None
        for _, _, вариант, фаза, мера, ряд, свои in сняты:
            код = tpc.найти_в_кадрах(ряд, свои, длина)
            if код is not None:
                break
        if код is None:
            continue
        база = варианты[-1][0] if варианты else 0.0
        плоскость = Находка(
            уровень="плоскость",
            что=f"модуляционная плоскость ФМ-{1 << k} подобрана по коду в кадрах: "
                f"{ploskost.имя_фм(вариант, k)}, фаза символа {фаза}",
            уверенность=код.уверенность,
            мера=f"строки кода в кадрах выделяются на {мера:.0f} разбросов; код под этим вариантом "
                 f"снимается целиком ({_проверок(код)} проверок)",
            подробно=[f"перебрано вариантов меток: {len(ploskost.варианты_фм(k))} × {k} фазы символа; "
                      f"почти равных по мере — {sum(1 for м, *_ in варианты if м >= РАВНЫЕ * лучшая)}: "
                      f"из них выбран тот, под которым у кода больше всего проверок "
                      f"(у частично верных вариантов виден лишь подкод)",
                      f"мера у худшего из лучших вариантов — {база:.0f}"] + ([выбор] if выбор else []),
            свойства={"вариант": вариант, "фаза": фаза, "k": k})
        return [плоскость, код], код.дальше
    return None


def разобрать_кадры(биты: np.ndarray, длина_цикла: int, *, фм: Sequence[int] = ()
                    ) -> Optional[Tuple[List[Находка], np.ndarray, Dict[str, object]]]:
    """Кадры по циклу → плоскость → код: (находки, данные, сведения о кадрах) или None."""
    from . import cikl  # noqa: PLC0415

    найдено = cikl.кадры(биты, длина_цикла)
    if найдено is None:
        return None
    начала, сведения = найдено
    итог = код_в_кадрах(биты, начала, int(сведения["кадр"]), фм=фм)
    if итог is None:
        return None
    находки, данные = итог
    return находки, данные, сведения
