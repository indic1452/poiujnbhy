def вставки(с: np.ndarray, период_до: int = 300, порог: float = 0.9) -> tuple[int, int, int] | None:
    """Постоянный символ с периодом P (синхробайт DSS через 147): (P, вычет, значение) или None.

    Совпадения с[i] = с[i + P] по вычетам i mod P; у столбца синхробайта их почти все.
    """
    с = np.asarray(с[:1 << 15], dtype=np.int64)
    лучшее = None
    for P in range(8, min(период_до, len(с) // 8) + 1):
        строк = len(с) // P
        м = с[:строк * P].reshape(строк, P)
        доля = (м[1:] == м[:-1]).mean(axis=0)
        r = int(np.argmax(доля))
        if доля[r] >= порог and (лучшее is None or доля[r] > лучшее[0] + 1e-9):
            значения, сколько = np.unique(м[:, r], return_counts=True)
            лучшее = (float(доля[r]), P, r, int(значения[np.argmax(сколько)]))
            if доля[r] >= 0.99:
                break
    return None if лучшее is None else лучшее[1:]


def убрать_вставки(с: np.ndarray, P: int, вычет: int) -> np.ndarray:
    """Убрать символы на местах вычет + k·P."""
    ок = (np.arange(len(с)) % P) != вычет % P
    return np.asarray(с)[ок]


def _хвосты_j83b(биты: np.ndarray) -> tuple[np.ndarray, str] | None:
    """Хвост кадра FEC J.83B (синхро 28 или 32 бит через кадр): биты с конца первого хвоста без
    хвостов и описание, или None. Кадр до первого хвоста неполный — отбрасывается."""
    for синхро, кадр, хвост in ХВОСТЫ_J83B:
        период = кадр + хвост
        if len(биты) < 2 * период + len(синхро):
            continue
        образец = np.array([int(ч) for ч in синхро], dtype=np.uint8)
        окно = биты[:период + len(синхро)].astype(np.int64) * 2 - 1
        for инв in (0, 1):
            о = образец ^ инв
            корр = np.correlate(окно, о.astype(np.int64) * 2 - 1, mode="valid")
            for м in np.flatnonzero(корр >= len(о) - 4).tolist():
                повторов = [м + k * период for k in range(1, 4) if м + k * период + len(о) <= len(биты)]
                if not повторов or any(int((биты[н:н + len(о)] ^ о).sum()) > 2 for н in повторов):
                    continue
                ок = np.ones(len(биты), dtype=bool)
                ок[:м + хвост] = False
                for н in range(м + период, len(биты), период):
                    ок[н:н + хвост] = False
                return биты[ок], (f"хвост кадра FEC J.83B {хвост} бит через {кадр} бит (синхро {синхро}"
                                  + (", инвертирован" if инв else "") + f") убран, первый — с бита {м}")
    return None


