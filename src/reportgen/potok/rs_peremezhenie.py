def _взвесить(X: np.ndarray, j: int, p: int, n: np.ndarray) -> np.ndarray:
    """X·α^(−j·n) поэлементно (n — номер символа в снятом ряду)."""
    if not j:
        return X
    степень, логарифм, _ = rs_bch.поле(p)
    Q = len(логарифм) - 1
    return np.where(X == 0, 0, степень[(логарифм[X] - j * n) % Q])


def _синдромы_ноль(слова: np.ndarray, п: dict) -> np.ndarray:
    S = rs_bch.синдромы(слова, п["многочлен"], п["fcr"], п["корней"], п.get("шаг", 1))
    return ~S.any(axis=1)


