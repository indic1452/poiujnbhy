#: Слов на одну фазу φ в быстрой проверке.
СЛОВ_ПРОВЕРКИ = 48


def фазы_по_снятию(y: np.ndarray, B: int, d: int, N: int, *, j: int = 0, p: int = 0x11D, N_слова: int | None = None,
                   слов: int = СЛОВ_ПРОВЕРКИ) -> tuple[np.ndarray, int]:
    """Счёт равенств префикса снятого ряда (корень α^j) по (φ, начало слова mod N): (таблица B × N, окон на клетку).

    ``N_слова`` — длина проверяемой части слова (J.83B: 127 из 128).
    """
    Nw = N_слова or N
    нужно_d = d * (B - 1)
    слов = min(слов, (len(y) - нужно_d) // N - 1)
    if слов < 2:
        return np.zeros((B, N), dtype=np.int64), 0
    T = слов * N
    тип = np.uint8 if int(np.max(y[:T + Nw + нужно_d], initial=0)) < 256 else np.uint16
    n = np.arange(T + Nw, dtype=np.int64)
    φ = np.arange(B, dtype=np.int64)[:, None]
    X = np.asarray(y, dtype=тип)[n[None, :] + d * ((n[None, :] - φ) % B)]
    if j:
        степень, логарифм, умн = rs_bch.поле(p)
        Q = len(логарифм) - 1
        X = умн[X, степень[(-j * n) % Q].astype(np.intp)[None, :]].astype(тип)
    P = np.zeros((B, T + Nw + 1), dtype=тип)
    P[:, 1:] = np.bitwise_xor.accumulate(X, axis=1)
    равно = P[:, Nw:Nw + T] == P[:, :T]
    счёт = равно.reshape(B, слов, N).sum(axis=1)
    return счёт, слов


