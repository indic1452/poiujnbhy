# -- перемежитель ----------------------------------------------------------------------------------


def перемежить(x: np.ndarray, B: int, d: int, фаза: int = 0) -> np.ndarray:
    """Символ n → место n + d·((n − фаза) mod B); места, куда ничего не пришло (начало), — нули."""
    x = np.asarray(x)
    n = np.arange(len(x), dtype=np.int64)
    куда = n + d * ((n - фаза) % B)
    ок = куда < len(x)
    y = np.zeros(len(x), dtype=x.dtype)
    y[куда[ок]] = x[ок]
    return y


def снять(y: np.ndarray, B: int, d: int, фаза: int = 0) -> np.ndarray:
    """x[n] = y[n + d·((n − фаза) mod B)]; хвост d·(B − 1) символов не восстанавливается."""
    y = np.asarray(y)
    сколько = max(0, len(y) - d * (B - 1))
    n = np.arange(сколько, dtype=np.int64)
    return y[n + d * ((n - фаза) % B)]


def допустим(B: int, d: int) -> bool:
    return B >= 2 and d >= 1 and math.gcd(d + 1, B) == 1


def подпись(B: int, d: int) -> str:
    """«Форни I = 12, M = 17» или «Рэмси II N1 = 13, N2 = 146»."""
    if d % B == 0:
        return f"Форни I = {B}, M = {d // B}"
    return f"Рэмси II N1 = {d + 1}, N2 = {B}"


def слой_перемежения(B: int, d: int) -> str:
    return f"форни {B} {d // B}" if d % B == 0 else f"рэмси {d + 1} {B}"


# -- префиксы --------------------------------------------------------------------------------------


def префикс(с: np.ndarray, I: int) -> np.ndarray:
    """P(t), t = 0 … len(с): XOR с[u] по u < t, u ≡ t (mod I)."""
    с = np.asarray(с, dtype=np.int64)
    L = len(с)
    R = -(-L // I)
    ряд = np.zeros(R * I, dtype=np.int64)
    ряд[:L] = с
    P = np.zeros((R + 1, I), dtype=np.int64)
    if R:
        P[1:] = np.bitwise_xor.accumulate(ряд.reshape(R, I), axis=0)
    return P.ravel()[:L + 1]


def сумма_слов(y: np.ndarray, B: int, d: int) -> np.ndarray:
    """A(t) = ⊕_(j<B) P_B(t + j(d+1)): у выровненного слова длины N с начала s — A(s + N) ⊕ A(s) = XOR слова."""
    L = len(y)
    if L + 1 - B * (d + 1) < 1:
        return np.zeros(0, dtype=np.int64)
    PB = префикс(y, B)
    Q = префикс(PB, d + 1)
    охват = B * (d + 1)
    return Q[охват:L + 2] ^ Q[:L + 2 - охват]


