"""Код Рида — Соломона со свёрточным перемежением символов: профили стандартов и поиск вслепую.

**Перемежитель.** Коммутатор с периодом B, приращение задержки d символов на положение: символ
номер n (считая от фазы φ, где коммутатор в положении 0) выходит на месте

    n + d·((n − φ) mod B),      снятие:  x[n] = y[n + d·((n − φ) mod B)].

Это взаимно однозначно, когда НОД(d + 1, B) = 1. По документам:

- Форни I ветвей, M ячеек (DVB EN 300 421, МСЭ-R BO.1516 п. 5.4.1 — I = 12, M = 17; ATSC A/53 ч. 2
  п. 5.2.3 — B = 52, M = 4; J.83 прил. B п. B.5.2 — I, J): ветвь j задерживает на j·M ячеек, а ячейка
  ветви сдвигается раз в I символов — B = I, d = M·I;
- Рэмси II (N1, N2) (BO.1516 п. 5.4.2, рис. 24b, система B — DirecTV DSS, N1 = 13, N2 = 146): регистр
  с отводами, задержка байта k блока из N2 — (N1 − 1)·k — B = N2, d = N1 − 1. Коммутатор в 0 в начале
  каждого пакета, так что слово РС из N2 байт выходит символами через N1: n, n + 13, n + 26, …

**Слово в выходном потоке.** Если слово кода начинается на положении 0 коммутатора и длиной
N = M′·B (DVB: 204 = 17·12, DSS: 146 = 1·146, J.83B: 128), его символы на выходе — на местах
s + B·q + (d + 1)·j, q < M′, j < B. Сумма (XOR) символов такого слова через префиксы:
P_B(t) — XOR y[u] по u < t, u ≡ t (mod B); A(t) = ⊕_j P_B(t + j(d + 1)) (тоже префиксом, с шагом
d + 1); слово чистое при корне α⁰ ⇔ A(s + N) = A(s). Фаза φ не перебирается — она в s mod B, а
длина N и начало — по парам равных значений A, как у rs_slepoy (ступень 1: XOR символов слова не
зависит от поля, базиса и порядка бит). На сдвинутой битовой фазе равенство выполняется по части
бит символа — фаз 0 и 4 хватает для отсева (сдвиг не больше 2: доля 1/4 против 1/256 у фона).

Семейства вслепую: «рэмси» — M′ = 1 (N = B, любое d): A(t) — префикс с шагом I = d + 1, и все
длины N находятся одним проходом на шаг; «форни» — d = M·B, N = M′·B: проход на пару (B, M).
Невыровненное перемежение (ATSC: слово 207 при B = 52 — начала слов ходят по положениям
коммутатора) — только профилем: снятие с перебором фазы φ.

**Профили** (быстрая проверка): DSS — RS(146,130) Рэмси II (13, 146), синхробайт 0x1D перед
каждой группой из 146 байт (BO.1516 п. 5.3.2, вставляется после перемежения); DVB / J.83 A, C /
ISDB-T — RS(204,188) Форни (12, 17); BO.1516 система C — RS(204,188) корни α¹…α¹⁶, Форни (12, 19);
ATSC — RS(207,187) Форни (52, 4); J.83 прил. B — RS(128,122) над GF(128) x⁷ + x³ + 1, корни α¹…α⁵ и
расширенный символ c(α⁶), Форни (I, J) по 7-битным символам, хвост кадра FEC (42/40 бит).
Проверка — снятие перемежения при каждой фазе φ (векторно), префикс в корне кода, затем синдромы.
"""

