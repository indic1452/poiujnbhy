"""Поля неизвестных пакетов: постоянные, счётчики, длины, типы, контрольная сумма.

Когда кадры выделены (HDLC, SLIP, пакеты .Sig, циклы с синхрословом), а
протокол внутри неизвестен, его формат восстанавливается по статистике
позиций — так делает аналитик вручную, выписывая кадры столбиком:

- **постоянное поле** — одно значение почти во всех кадрах (синхрослово,
  адрес, версия протокола);
- **счётчик** — у соседних кадров значение растёт на 1 (по модулю 2⁸ или
  2¹⁶, в обоих порядках байт): номер кадра, последовательность;
- **длина** — значение равно длине кадра минус постоянная (1 или 2 байта,
  в обоих порядках): поле длины заголовка;
- **тип** — немного разных значений с неравномерной частотой: код команды,
  тип сообщения;
- **контрольная сумма** в конце — CRC, опознаётся модулем crc (многочлен,
  init, xorout, отражения).

Каждое поле — со своей долей совпадений: вывод проверяем.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence

import numpy as np

from . import crc as crc_
from .nahodka import Находка

ПОЗИЦИЙ_ДО = 64
ДОЛЯ = 0.95


def _таблица(кадры: Sequence[bytes], длина: int) -> np.ndarray:
    return np.array([list(к[:длина]) for к in кадры if len(к) >= длина], dtype=np.int64)


def поля(кадры: Sequence[bytes]) -> list[dict]:
    """Поля заголовка: позиция, ширина, вид, подробности, доля совпадений."""
    кадры = [bytes(к) for к in кадры if к]
    if len(кадры) < 8:
        return []
    длины = np.array([len(к) for к in кадры])
    # Общая часть — по самому короткому кадру: выбрасывать короткие кадры
    # нельзя, иначе у счётчика появятся пропуски и он перестанет быть «+1».
    общая = int(min(ПОЗИЦИЙ_ДО, длины.min()))
    if общая < 1:
        return []
    T = _таблица(кадры, общая)
    итог: list[dict] = []
    занято = np.zeros(общая, dtype=bool)
    переменная_длина = len(set(длины.tolist())) > 1

    # Двухбайтовые счётчики и длины — раньше однобайтовых: иначе старший байт
    # 16-битного счётчика выглядел бы «постоянным», а младший — счётчиком.
    for i in range(общая - 1):
        for порядок, (a, b) in (("big", (i, i + 1)), ("little", (i + 1, i))):
            значения = T[:, a] * 256 + T[:, b]
            шаги = np.diff(значения) % 65536
            if len(set(значения.tolist())) > 256 and np.mean(шаги == 1) >= ДОЛЯ:
                итог.append({"место": i, "ширина": 2, "вид": "счётчик",
                             "подробно": f"16 бит, порядок {порядок}-endian, +1 на кадр",
                             "доля": float(np.mean(шаги == 1))})
                занято[i:i + 2] = True
                break
            if переменная_длина and not занято[i]:
                разность = длины[:len(значения)] - значения
                часто, сколько = Counter(разность.tolist()).most_common(1)[0]
                if сколько / len(значения) >= ДОЛЯ and np.ptp(значения) > 0:
                    итог.append({"место": i, "ширина": 2, "вид": "длина",
                                 "подробно": f"16 бит, {порядок}-endian: длина кадра − {часто}",
                                 "доля": сколько / len(значения)})
                    занято[i:i + 2] = True
                    break
    for i in range(общая):
        if занято[i]:
            continue
        столбец = T[:, i]
        счёт = Counter(столбец.tolist())
        значение, сколько = счёт.most_common(1)[0]
        if сколько / len(столбец) >= ДОЛЯ:
            итог.append({"место": i, "ширина": 1, "вид": "постоянное",
                         "подробно": f"0x{значение:02X}", "доля": сколько / len(столбец)})
            continue
        шаги = np.diff(столбец) % 256
        if np.mean(шаги == 1) >= ДОЛЯ:
            итог.append({"место": i, "ширина": 1, "вид": "счётчик",
                         "подробно": "8 бит, +1 на кадр", "доля": float(np.mean(шаги == 1))})
            continue
        if переменная_длина:
            разность = длины[:len(столбец)] - столбец
            часто, сколько = Counter(разность.tolist()).most_common(1)[0]
            if сколько / len(столбец) >= ДОЛЯ and np.ptp(столбец) > 0:
                итог.append({"место": i, "ширина": 1, "вид": "длина",
                             "подробно": f"длина кадра − {часто}",
                             "доля": сколько / len(столбец)})
                continue
        if 2 <= len(счёт) <= 16 and len(столбец) >= 40:
            итог.append({"место": i, "ширина": 1, "вид": "тип",
                         "подробно": ", ".join(f"0x{з:02X}×{с}" for з, с in счёт.most_common(6)),
                         "доля": 1.0})
    return sorted(итог, key=lambda п: п["место"])


def найти(кадры: Sequence[bytes], откуда: str = "кадров") -> Находка | None:
    """Формат неизвестных кадров: поля заголовка и контрольная сумма."""
    найдено = поля(кадры)
    сумма = crc_.найти(кадры)
    if not найдено and сумма is None:
        return None
    подробно = [f"поле @{п['место']}"
                + (f"–{п['место'] + п['ширина'] - 1}" if п["ширина"] > 1 else "")
                + f": {п['вид']} — {п['подробно']} ({п['доля'] * 100:.0f} % {откуда})"
                for п in найдено]
    что = "формат кадров: " + (", ".join(sorted({п["вид"] for п in найдено})) or "—")
    уверенность = float(np.mean([п["доля"] for п in найдено])) if найдено else 0.0
    if сумма is not None:
        w = сумма["w"]
        имя = сумма["имя"] or "не из каталога"
        параметры = (f"многочлен 0x{сумма['P']:0{w // 4}X}, refin {сумма['refin']}, "
                     f"refout {сумма['refout']}, в кадре {сумма['порядок']}-endian")
        if сумма["init"] is not None:
            параметры += f", init 0x{сумма['init']:0{w // 4}X}, xorout 0x{сумма['xorout']:0{w // 4}X}"
            if сумма["верно"] is not None:
                параметры += f"; сошлась у {сумма['верно'] * 100:.1f} % кадров"
        else:
            параметры += (f"; все кадры одной длины — init и xorout по отдельности не "
                          f"определить, их общий вклад 0x{сумма['вклад']:0{w // 4}X}")
        подробно.append(f"в конце кадра — CRC-{w} ({имя}): {параметры}")
        что += f"; CRC-{w} в конце ({имя})"
        уверенность = max(уверенность, сумма["верно"] or 0.9)
    return Находка(уровень="формат", что=что, уверенность=уверенность,
                   мера=f"по {len(кадры)} {откуда}: поля — по доле совпадений, CRC — "
                        f"пересчётом по найденной модели",
                   подробно=подробно, дальше=None)
