"""Внешний код Рида — Соломона IESS-308/309/310 с перемежением (вкладка «RS» декодера отдела).

Сами IESS в открытом доступе не нашлись (istochniki/README.md, раздел turbo); параметры —
по документам, которые их пересказывают, по два на каждое утверждение:

- поле GF(2^8) по p(x) = x^8 + x^7 + x^2 + x + 1, порождающий g(x) = Π (x − α^i),
  i = 120 … 119 + 2t; укорочение — нулями в начале слова (ETSI ETR 192 — выдержка
  IESS-308, п. 6.1, стр. PDF 16–18);
- коды: IDR E1 — (219, 201), T1 — (225, 205), T2/E2 — (194, 178), IBS и малые IDR —
  (126, 112), 34 Мбит/с — (208, 192), 8PSK TCM (IESS-310) — (219, 201) (Comtech CDM-600
  стр. PDF 120; Radyne DMD20 табл. 3-1 стр. 46; TEC GR IDR-001 стр. 25);
- глубина перемежения — 4 при Витерби, 8 при последовательном декодере и 8PSK
  (CDM-600 стр. 120; DMD20 табл. 3-1).

Перемежение — блочное по символам (ETR 192 п. 6.1.5: «block interleaving», глубина 4):
I слов пишутся строками, передаются столбцами. Точная схема IESS (рис. 6 документа) в
открытых пересказах не приведена — это допущение, оно названо в отчёте слоя. Начало
слова и фаза байта находятся по доле слов с нулевым синдромом. В записи модема 3/4 + RS(225,205)
перемежение оказалось Рэмси II (8, 225) под разностным кодером — это профили «iess …»
модуля rs_peremezhenie.
"""

from __future__ import annotations

import numpy as np

from . import rs_bch

ПОЛЕ = 0x187                    # x^8 + x^7 + x^2 + x + 1 (ETR 192 п. 6.1.1.1)
ПЕРВЫЙ = 120                    # α^120 … α^(119 + 2t) (ETR 192 п. 6.1.1.2)
assert rs_bch.примитивный(ПОЛЕ)
#: Коды по режимам (CDM-600 стр. 120, DMD20 табл. 3-1, TEC GR стр. 25).
КОДЫ = {"idr e1": (219, 201), "idr t1": (225, 205), "idr t2": (194, 178), "idr e2": (194, 178),
        "ibs": (126, 112), "idr 34": (208, 192), "iess-310": (219, 201)}
assert all((n - k) % 2 == 0 for n, k in КОДЫ.values())


def перемежить(слова: np.ndarray, глубина: int) -> np.ndarray:
    """Слова (группы × I × n) → символы в порядке передачи (столбцами)."""
    return слова.transpose(0, 2, 1).reshape(-1)


def _слова(символы: np.ndarray, n: int, глубина: int, начало: int) -> np.ndarray:
    с = символы[начало:]
    групп = len(с) // (n * глубина)
    return с[:групп * n * глубина].reshape(групп, n, глубина).transpose(0, 2, 1)


def _байты(биты: np.ndarray, фаза: int) -> np.ndarray:
    б = np.asarray(биты[фаза:], dtype=np.uint8)
    return np.packbits(б[:len(б) // 8 * 8]).astype(np.int64)


def выровнять(биты: np.ndarray, n: int, k: int, глубина: int, групп: int = 3
              ) -> tuple[int, int, float] | None:
    """(фаза бита, начало в символах, доля слов с нулевым синдромом) — лучшее выравнивание."""
    лучшее = None
    for фаза in range(8):
        символы = _байты(биты[:(групп + 2) * n * глубина * 8 + 64], фаза)
        for начало in range(n * глубина):
            слова = _слова(символы, n, глубина, начало)[:групп].reshape(-1, n)
            if not len(слова):
                break
            доля = float((~rs_bch.синдромы(слова, ПОЛЕ, ПЕРВЫЙ, n - k).any(axis=1)).mean())
            if лучшее is None or доля > лучшее[2]:
                лучшее = (фаза, начало, доля)
            if доля >= 0.5:
                # Случайное слово даёт нулевой синдром с вероятностью 256^−(n−k): здесь начало
                # верно с точностью до s < I символов (тогда годны I − s слов группы из I) —
                # лучшее из следующих I начал.
                def доля_(н: int, символы: np.ndarray = символы) -> float:
                    с_ = _слова(символы, n, глубина, н)[:групп].reshape(-1, n)
                    return float((~rs_bch.синдромы(с_, ПОЛЕ, ПЕРВЫЙ, n - k).any(axis=1)).mean())
                лучшее_н = max(range(начало, начало + глубина), key=доля_)
                return фаза, лучшее_н % (n * глубина), доля_(лучшее_н)
    return лучшее


def снять(биты: np.ndarray, слова: str) -> tuple[np.ndarray, list[str]]:
    """Слой «рс iess N K [глубина I]» или «рс iess idr e1|t1|t2|ibs|idr 34|iess-310 [глубина I]»."""
    import re  # noqa: PLC0415
    слова = слова.lower()
    n = k = None
    for имя, (n_, k_) in КОДЫ.items():
        if имя in слова:
            n, k = n_, k_
    числа = re.search(r"(?<![\w-])(\d{2,3})[\s,/]+(\d{2,3})\b", слова)
    if числа:
        n, k = int(числа.group(1)), int(числа.group(2))
    if n is None or not (0 < k < n <= 255) or (n - k) % 2:
        raise ValueError("RS IESS: «рс iess N K [глубина I]» (N − K чётно, N ≤ 255) или режим: "
                         + ", ".join(КОДЫ))
    г = re.search(r"глубин\w*\s+(\d+)", слова)
    глубина = int(г.group(1)) if г else 4
    выр = выровнять(биты, n, k, глубина)
    if выр is None or выр[2] < 0.05:
        raise ValueError(f"RS ({n}, {k}) IESS при глубине {глубина}: слов с нулевым синдромом нет "
                         f"ни при одном выравнивании")
    фаза, начало, доля = выр
    слова_ = _слова(_байты(биты, фаза), n, глубина, начало).reshape(-1, n)
    исправленные, исправлено = rs_bch.исправить(слова_, ПОЛЕ, ПЕРВЫЙ, n - k)
    данные = исправленные[:, :k].astype(np.uint8)
    ряд = np.unpackbits(данные.reshape(-1))
    подробно = [f"RS ({n}, {k}), t = {(n - k) // 2}: поле x^8 + x^7 + x^2 + x + 1, корни α^120 … "
                f"α^{119 + n - k} (ETR 192 — выдержка IESS-308, п. 6.1)",
                f"перемежение блочное по символам, глубина {глубина} (допущение: схема IESS в открытых "
                f"источниках не приведена); начало — бит {фаза + 8 * начало}",
                rs_bch.итог_словами(исправлено, "символов", "символ", n * len(исправлено))[0],
                f"до исправления нулевой синдром у {доля * 100:.0f} % слов выборки"]
    return ряд, подробно
