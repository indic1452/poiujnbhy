"""VDL Mode 2 (ICAO 9776, ETSI EN 301 841): пачки D8PSK — преамбула, заголовок, RS(255, 249), кадры AVLC.

Как у dumpvdl2 (demod.c, decode.c, bitstream.c, rs.c, avlc.c):
- символ D8PSK — 3 бита (старший первым) по коду Грея {0, 1, 3, 2, 6, 7, 5, 4} от приращения фазы
  в π/4; преамбула — 16 символов с известными фазами, в битах — 15 приращений (45 бит);
  у сопряжённого спектра (I и Q переставлены) приращение меняет знак — символы перекодируются;
- за преамбулой всё скремблировано: x¹⁵ + x + 1, начальное 0x6959;
- заголовок 25 бит: 3 резервных (нули), длина передачи 17 бит (младшим вперёд), 5 проверочных бит
  кода (25, 20) — синдром по матрице H, исправление по таблице синдромов;
- данные: октеты (младшим битом вперёд) блоками по 249, у каждого 6 проверочных RS(255, 249)
  (GF(256), x⁸ + x⁷ + x² + x + 1, первый корень α¹²⁰); у последнего неполного блока проверочных
  2 (до 30 октетов), 4 (до 67) или 6, короче 3 октетов — ни одного; недостающие — стирания;
  октеты данных и проверочные перемежены по столбцам блоков;
- в данных — кадры HDLC (флаги 0x7E, битстаффинг) AVLC: адреса получателя и отправителя (по 4 октета:
  24 бита адреса, 3 бита вида, бит состояния), поле управления, данные, FCS (CRC-16/X.25).
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

import numpy as np

from . import acars, rs_bch
from .nahodka import Находка

# фазы символов преамбулы (накопленные, в π/4), как pr_phase у dumpvdl2
ФАЗЫ_ПРЕАМБУЛЫ = (0, 3, -3, 1, 1, 2, 0, 4, -3, 4, -2, 3, 1, -2, -3, 0)
ГРЕЙ = (0, 1, 3, 2, 6, 7, 5, 4)
LFSR_НАЧАЛО = 0x6959
ОШИБОК_ПРЕАМБУЛЫ_ДО = 3
H = (0b0000000011111111111110000, 0b0011111100001111111101000, 0b1100011100110000111100100,
     0b1101101101010011001100010, 0b0110100111100101010100001)
# синдром → ошибка в 25-битовом заголовке (syndtable dumpvdl2)
ТАБЛИЦА_СИНДРОМОВ = (
    0, 1 << 0, 1 << 1, (1 << 23 | 1 << 2), 1 << 2, (1 << 23 | 1 << 1), 1 << 24, 1 << 23, 1 << 3, 1 << 22,
    1 << 21, 1 << 20, 1 << 19, (1 << 24 | 1 << 20), 1 << 18, 1 << 17, 1 << 4, 1 << 16, (1 << 23 | 1 << 14),
    1 << 15, (1 << 23 | 1 << 15), 1 << 14, 1 << 13, (1 << 24 | 1 << 16), 1 << 12, 1 << 11, 1 << 10, 1 << 9,
    1 << 8, 1 << 7, 1 << 6, 1 << 5)
ДЛИНА_ДО, ДЛИНА_ИСПРАВЛЕННОГО_ДО = 0x3FFF, 0x1FFF
RS_N, RS_K, RS_ПОЛЕ, RS_FCR = 255, 249, 0x187, 120
FCS_ВЕРНА = 0xF0B8
ВИДЫ_АДРЕСА = {1: "борт", 4: "наземная станция", 5: "наземная станция", 7: "всем"}
U_КОМАНДЫ = {0x00: "UI", 0x03: "DM", 0x10: "DISC", 0x18: "UA", 0x21: "FRMR", 0x2B: "XID", 0x38: "TEST"}  # по mfunc
S_КОМАНДЫ = ("RR", "RNR", "REJ", "SREJ")


def _преамбула() -> np.ndarray:
    биты = []
    for a, b in zip(ФАЗЫ_ПРЕАМБУЛЫ, ФАЗЫ_ПРЕАМБУЛЫ[1:]):
        с = ГРЕЙ[(b - a) % 8]
        биты += [(с >> 2) & 1, (с >> 1) & 1, с & 1]
    return np.array(биты, dtype=np.uint8)


ПРЕАМБУЛА = _преамбула()


def сопрячь(биты: np.ndarray) -> np.ndarray:
    """Символы (по 3 бита) сопряжённого спектра: приращение фазы k → −k."""
    обратный = {g: i for i, g in enumerate(ГРЕЙ)}
    перевод = np.array([ГРЕЙ[(8 - обратный[g]) % 8] for g in range(8)], dtype=np.uint8)
    n = len(биты) // 3 * 3
    т = биты[:n].reshape(-1, 3)
    с = перевод[т[:, 0] * 4 + т[:, 1] * 2 + т[:, 2]]
    return np.stack([(с >> 2) & 1, (с >> 1) & 1, с & 1], axis=1).reshape(-1).astype(np.uint8)


def гамма(длина: int, lfsr: int = LFSR_НАЧАЛО) -> np.ndarray:
    """Скремблирующая последовательность x¹⁵ + x + 1 (как bitstream_descramble)."""
    итог = np.zeros(длина, dtype=np.uint8)
    for i in range(длина):
        бит = (lfsr ^ (lfsr >> 14)) & 1
        lfsr = (lfsr >> 1) | (бит << 14)
        итог[i] = бит
    return итог


def _чётность(v: int) -> int:
    return bin(v).count("1") & 1


def синдром(заголовок: int) -> int:
    итог = 0
    for i, строка in enumerate(H):
        итог |= _чётность(заголовок & строка) << (4 - i)
    return итог


def заголовок(биты: np.ndarray) -> Optional[Tuple[int, int]]:
    """25 бит (после снятия скремблера) → (длина передачи в битах, синдром) или None."""
    слово = int("".join(map(str, биты[:25].tolist())), 2) & ((1 << 22) - 1)   # резервные — нули
    с = синдром(слово)
    слово ^= ТАБЛИЦА_СИНДРОМОВ[с]
    if слово >> 22:
        return None
    длина_обратно = (слово >> 5) & ((1 << 17) - 1)
    длина = int(format(длина_обратно, "017b")[::-1], 2)
    if длина > ДЛИНА_ДО or (с and длина > ДЛИНА_ИСПРАВЛЕННОГО_ДО):
        return None
    return длина, с


def проверочных(октетов: int) -> int:
    """Проверочных октетов у блока из ``октетов`` данных (get_fec_octetcount)."""
    return 0 if октетов < 3 else 2 if октетов < 31 else 4 if октетов < 68 else 6


def раскладка(длина: int) -> Tuple[int, int, int, int]:
    """(октетов данных, блоков, октетов в последнем блоке, проверочных всего)."""
    октетов = (длина + 7) // 8
    блоков, последний = divmod(октетов, RS_K)
    проверочных_всего = блоков * (RS_N - RS_K)
    if последний:
        блоков += 1
        проверочных_всего += проверочных(последний)
    return октетов, блоков, последний or RS_K, проверочных_всего


def _места(строк: int, ширина: int, всего: int, сдвиг: int) -> List[Tuple[int, int]]:
    """Порядок передачи: по столбцам, в последней строке — только её ширина (deinterleave dumpvdl2)."""
    последняя = всего % ширина or ширина
    итог = []
    for столбец in range(ширина):
        for строка in range(строк):
            if строка == строк - 1 and столбец >= последняя:
                continue
            итог.append((строка, сдвиг + столбец))
    return итог


@dataclass
class Кадр:
    октеты: bytes
    поля: Dict[str, str] = field(default_factory=dict)


@dataclass
class Пачка:
    бит: int
    сопряжение: bool
    длина: int
    синдром: int
    исправлено: int = 0
    кадры: List[Кадр] = field(default_factory=list)


def fcs(данные: bytes) -> int:
    c = 0xFFFF
    for б in данные:
        c ^= б
        for _ in range(8):
            c = (c >> 1) ^ 0x8408 if c & 1 else c >> 1
    return c


def _адрес(б: bytes) -> Tuple[int, int, int]:
    """(адрес 24 бита, вид, бит состояния) как parse_dlc_addr."""
    v = (б[0] >> 1) | (б[1] << 6) | (б[2] << 13) | ((б[3] & 0xFE) << 20)
    v = int(format(v & ((1 << 28) - 1), "028b")[::-1], 2)
    return v & 0xFFFFFF, (v >> 24) & 7, (v >> 27) & 1


def _acars(данные: bytes) -> str:
    """ACARS в кадре I (после FF FF 01): режим, регистрация, метка, блок, текст — до ETX/ETB (биты чётности сняты)."""
    знаки = bytes(б & 0x7F for б in данные)
    конец = min((i for i, б in enumerate(знаки) if б in (0x03, 0x17)), default=len(знаки))
    if конец < 12:
        return знаки[:конец].decode("ascii", "replace")
    п = acars.Блок(0, False, знаки[:конец + 1], True, 0).поля()
    return (f"{п['адрес']} [{п['метка']}] блок {п['блок']}"
            + (f", сообщение {п['сообщение']}, рейс {п['рейс']}" if п.get("рейс") else "")
            + (f": {п['текст']}" if п["текст"] else ""))


def avlc(октеты: bytes) -> Optional[Dict[str, str]]:
    """Поля кадра AVLC или None, если короче 11 октетов или FCS неверна."""
    if len(октеты) < 11 or fcs(октеты) != FCS_ВЕРНА:
        return None
    получатель, вид_п, земля = _адрес(октеты[0:4])
    отправитель, вид_о, ответ = _адрес(октеты[4:8])
    у = октеты[8]
    данные = октеты[9:-2]
    п = {"от": f"{отправитель:06X} ({ВИДЫ_АДРЕСА.get(вид_о, 'резерв')})",
         "кому": f"{получатель:06X} ({ВИДЫ_АДРЕСА.get(вид_п, 'резерв')})",
         "состояние": "на земле" if земля else "в воздухе", "вид": "ответ" if ответ else "команда"}
    if у & 1 == 0:
        п["кадр"] = f"I (N(S) {(у >> 1) & 7}, N(R) {у >> 5})"
        if данные[:3] == b"\xff\xff\x01":
            п["ACARS"] = _acars(данные[3:])
    elif у & 3 == 1:
        п["кадр"] = f"S {S_КОМАНДЫ[(у >> 2) & 3]} (N(R) {у >> 5})"
    else:
        команда = (у >> 2) & 0x3B                              # без бита P/F (U_MFUNC dumpvdl2)
        п["кадр"] = "U " + U_КОМАНДЫ.get(команда, f"0x{команда:02X}")
    if данные and "ACARS" not in п:
        п["данные"] = данные[:32].hex(" ") + (" …" if len(данные) > 32 else "")
    return п


def кадры_hdlc(биты: np.ndarray) -> Optional[List[bytes]]:
    """Кадры между флагами 0x7E со снятием битстаффинга (как bitstream_copy_next_frame); None — ошибка."""
    итог: List[bytes] = []
    кадр: List[int] = []
    единиц, начат = 0, False
    for б in биты.tolist():
        if б == 0 and единиц == 5:
            единиц = 0
            continue
        if б == 1:
            единиц += 1
            if единиц > 6:
                return None
            кадр.append(1)
            continue
        кадр.append(0)
        if единиц == 6:                                      # флаг 01111110
            тело = кадр[:-8]
            if начат and тело:
                if len(тело) % 8:
                    return None
                итог.append(np.packbits(np.array(тело, dtype=np.uint8).reshape(-1, 8)[:, ::-1]).tobytes())
            начат, кадр = True, []
        единиц = 0
    return итог


def _пачка(ряд: np.ndarray, м: int, сопряжение: bool) -> Optional[Пачка]:
    """Пачка с начала заголовка ``м`` (биты уже в прямом виде)."""
    хвост = ряд[м:м + 25]
    if len(хвост) < 25:
        return None
    г = гамма(25)
    з = заголовок(хвост ^ г)
    if з is None:
        return None
    длина, с = з
    октетов, блоков, последний, проверочных_всего = раскладка(длина)
    всего = 25 + 8 * (октетов + проверочных_всего)
    if м + всего > len(ряд):
        return None
    чистые = ряд[м:м + всего] ^ гамма(всего)
    байты = np.packbits(чистые[25:].reshape(-1, 8)[:, ::-1], axis=1).reshape(-1)
    данные, проверка = байты[:октетов], байты[октетов:]
    таблица = np.zeros((блоков, RS_N), dtype=np.int64)
    for (строка, столбец), б in zip(_места(блоков, RS_K, октетов, 0), данные.tolist()):
        таблица[строка, столбец] = б
    строк_проверки = блоков - (1 if проверочных(последний) == 0 else 0)
    for (строка, столбец), б in zip(_места(строк_проверки, RS_N - RS_K, проверочных_всего, RS_K),
                                    проверка.tolist()):
        таблица[строка, столбец] = б
    исправлено = 0
    выход = []
    for r in range(блоков):
        в_блоке = последний if r == блоков - 1 else RS_K
        есть = RS_N - RS_K if r < блоков - 1 else проверочных(в_блоке)
        if есть:
            стёрто = list(range(RS_K + есть, RS_N))
            слово, число = rs_bch.исправить_со_стираниями(таблица[r].tolist(), стёрто, RS_ПОЛЕ, RS_FCR,
                                                          RS_N - RS_K)
            if число < 0:
                return None
            исправлено += число - sum(1 for i in стёрто if слово[i])
            таблица[r] = слово
        выход += таблица[r, :в_блоке].tolist()
    биты = np.unpackbits(np.array(выход, dtype=np.uint8)[:, None], axis=1)[:, ::-1].reshape(-1)[:длина]
    кадры = кадры_hdlc(биты)
    if кадры is None:
        return None
    п = Пачка(м, сопряжение, длина, с, исправлено)
    for к in кадры:
        поля = avlc(к)
        if поля is not None:
            п.кадры.append(Кадр(к, поля))
    return п if п.кадры else None


КУСОК = 11                                      # 4 куска по 11 бит: при ≤ 3 ошибках один цел


def преамбулы(ряд: np.ndarray) -> List[int]:
    """Места преамбулы (не больше 3 ошибок): кандидаты — где один из четырёх кусков по 11 бит совпал
    точно (по принципу Дирихле), затем полная сверка 45 бит."""
    n = len(ряд) - len(ПРЕАМБУЛА) + 1
    if n <= 0:
        return []
    б = ряд.astype(np.int16)
    слово = np.zeros(len(ряд) - КУСОК + 1, dtype=np.int16)
    for k in range(КУСОК):
        слово |= б[k:k + len(слово)] << k
    кандидаты = np.zeros(n, dtype=bool)
    for ч in range(len(ПРЕАМБУЛА) // КУСОК):
        кусок = int(sum(int(x) << k for k, x in enumerate(ПРЕАМБУЛА[ч * КУСОК:(ч + 1) * КУСОК])))
        кандидаты |= слово[ч * КУСОК:ч * КУСОК + n] == кусок
    места = np.flatnonzero(кандидаты)
    if not len(места):
        return []
    окна = ряд[места[:, None] + np.arange(len(ПРЕАМБУЛА))]
    ошибок = (окна != ПРЕАМБУЛА).sum(axis=1)
    return места[ошибок <= ОШИБОК_ПРЕАМБУЛЫ_ДО].tolist()


def пачки(биты: np.ndarray) -> List[Пачка]:
    биты = np.asarray(биты, dtype=np.uint8)
    итог: List[Пачка] = []
    if len(биты) < len(ПРЕАМБУЛА) + 25:
        return итог
    for сопряжение, сдвиг in [(False, 0)] + [(True, s) for s in range(3)]:
        ряд = биты if not сопряжение else np.concatenate([биты[:сдвиг], сопрячь(биты[сдвиг:])])
        # у сопряжённого ряда при чужом выравнивании символов преамбула — шум: совпадений нет
        for м in преамбулы(ряд):
            п = _пачка(ряд, м + len(ПРЕАМБУЛА), сопряжение)
            if п is not None:
                итог.append(п)
    return sorted(итог, key=lambda п: п.бит)


def описание(к: Кадр) -> str:
    п = к.поля
    части = [f"{п['от']} → {п['кому']}", п["состояние"], п["вид"], п["кадр"]]
    if "ACARS" in п:
        части.append("ACARS: " + п["ACARS"][:120])
    elif "данные" in п:
        части.append("данные: " + п["данные"])
    return "; ".join(части)


def найти(биты: np.ndarray) -> Optional[Находка]:
    пп = пачки(биты)
    if not пп:
        return None
    кадры = [к for п in пп for к in п.кадры]
    от = Counter(к.поля["от"] for к in кадры)
    виды = Counter(к.поля["кадр"].split(" (")[0] for к in кадры)
    подробно = [f"пачек: {len(пп)}, кадров AVLC с верной FCS: {len(кадры)}"
                + (" — спектр сопряжён (I и Q переставлены)" if all(п.сопряжение for п in пп) else ""),
                f"заголовков с исправленной ошибкой: {sum(1 for п in пп if п.синдром)}; "
                f"октетов, исправленных RS(255, 249): {sum(п.исправлено for п in пп)}",
                "отправители: " + ", ".join(f"{а} × {к}" for а, к in от.most_common(12)),
                "кадры: " + ", ".join(f"{в} × {к}" for в, к in виды.most_common())]
    подробно += [описание(к) for к in кадры[:30]]
    return Находка(
        уровень="канальный", что="VDL Mode 2: пачки D8PSK с кадрами AVLC (ACARS, ATN)",
        уверенность=1.0, мера=f"{len(пп)} пачек: преамбула, заголовок, RS(255, 249), FCS кадров",
        подробно=подробно, свойства={"пачек": len(пп), "кадров": len(кадры), "отправителей": len(от)})


# --- для проверок: сборка пачки ---

def адрес(номер: int, вид: int, состояние: int = 0, последний: bool = False) -> bytes:
    """Обратное к ``_адрес``: в каждом октете 7 бит (со 2-го), бит 0 — продолжение (1 — конец адресов)."""
    w = int(format(номер | (вид << 24) | (состояние << 27), "028b")[::-1], 2)
    return bytes([((w >> (7 * k)) & 0x7F) << 1 | (1 if последний and k == 3 else 0) for k in range(4)])


def кадр_avlc(получатель: bytes, отправитель: bytes, управление: int, данные: bytes = b"") -> bytes:
    тело = получатель + отправитель + bytes([управление]) + данные
    c = fcs(тело) ^ 0xFFFF
    return тело + bytes([c & 0xFF, c >> 8])


def закодировать(кадры: List[bytes], заполнение: int = 0) -> np.ndarray:
    """Кадры → биты пачки: преамбула, заголовок, данные и проверочные RS, скремблер.

    ``заполнение`` — биты дополнения до октета после последнего флага (их отбрасывает длина заголовка)."""
    полезные: List[int] = [0, 1, 1, 1, 1, 1, 1, 0]
    for к in кадры:
        единиц = 0
        for б in к:
            for i in range(8):
                бит = (б >> i) & 1
                полезные.append(бит)
                единиц = единиц + 1 if бит else 0
                if единиц == 5:
                    полезные.append(0)
                    единиц = 0
        полезные += [0, 1, 1, 1, 1, 1, 1, 0]
    длина = len(полезные)
    октетов, блоков, последний, проверочных_всего = раскладка(длина)
    полезные += [заполнение] * (8 * октетов - длина)
    байты = np.packbits(np.array(полезные, dtype=np.uint8).reshape(-1, 8)[:, ::-1], axis=1).reshape(-1).tolist()
    таблица = np.zeros((блоков, RS_N), dtype=np.int64)
    for r in range(блоков):
        кусок = байты[r * RS_K:(r + 1) * RS_K]
        таблица[r] = rs_bch.закодировать_рс(кусок + [0] * (RS_K - len(кусок)), RS_ПОЛЕ, RS_FCR, RS_N - RS_K)
    данные = [int(таблица[s, c]) for s, c in _места(блоков, RS_K, октетов, 0)]
    строк_проверки = блоков - (1 if проверочных(последний) == 0 else 0)
    проверка = [int(таблица[s, c]) for s, c in _места(строк_проверки, RS_N - RS_K, проверочных_всего, RS_K)]
    слово = int(format(длина, "017b")[::-1], 2) << 5
    слово |= next(x for x in range(32) if синдром(слово | x) == 0)
    биты = [int(b) for b in format(слово, "025b")]
    for б in данные + проверка:
        биты += [(б >> i) & 1 for i in range(8)]
    биты = np.array(биты, dtype=np.uint8) ^ гамма(len(биты))
    return np.concatenate([ПРЕАМБУЛА, биты]).astype(np.uint8)
