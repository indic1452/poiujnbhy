# -- многочлены и составляющие коды ---------------------------------------------------------------

#: Порождающие многочлены кодов Хэмминга (n, k) — [istochniki/tpc/ieee802/802161pc-00_35.pdf,
#: стр. 5 PDF, Table 1]; до (63, 57) они же — [istochniki/tpc/ieee802/C80216a-02_55.pdf,
#: стр. 16, Table 203]. Сверка обоих — в tests/test_potok_tpc_rezhimy.py.
МНОГОЧЛЕНЫ_ХЭММИНГА = {(7, 4): "x3+x+1", (15, 11): "x4+x+1", (31, 26): "x5+x2+1",
                       (63, 57): "x6+x+1", (127, 120): "x7+x3+1"}
#: БЧХ (31, 21) и бит общей чётности = (32, 21) — [istochniki/tpc/itu/ITU-R_M.584-2.pdf,
#: стр. 4, п. 1.4]: 21 бит данных (x^30…x^10), остаток деления на многочлен — x^9…x^0,
#: затем бит общей чётности.
МНОГОЧЛЕН_БЧХ_31_21 = "x10+x9+x8+x6+x5+x3+1"


def многочлен(запись: str) -> int:
    """«x6+x+1» → целое: бит i — коэффициент при x^i."""
    итог = 0
    for член in запись.lower().replace(" ", "").split("+"):
        if член == "1":
            итог |= 1
        elif член == "x":
            итог |= 2
        elif член.startswith("x"):
            итог |= 1 << int(член[1:])
        else:
            raise ValueError(f"не понимаю член многочлена «{член}»")
    return итог


@dataclass(frozen=True)
class Код:
    """Составляющий код оси: систематический, данные первыми, затем проверки.

    ``вид``: «Хэмминг+» (расширенный: остаток деления на ``g`` и бит общей
    чётности в конце — 802.16.1pc-00/35 стр. 5), «Хэмминг» (без бита
    чётности), «чётность» (n, n − 1), «БЧХ+» (остаток деления и бит общей
    чётности — ITU-R M.584). ``t`` — сколько ошибок в слове исправляется.
    """

    n: int
    k: int
    вид: str
    g: int = 0
    t: int = 1

    @property
    def запись(self) -> str:
        return f"({self.n},{self.k})"


def хэмминг_расширенный(n: int) -> Код:
    m = n.bit_length() - 1 if n & (n - 1) == 0 else None
    if m is None or (n - 1, n - 1 - m) not in МНОГОЧЛЕНЫ_ХЭММИНГА:
        raise ValueError(f"расширенного Хэмминга длины {n} нет в таблице многочленов")
    nb, kb = n - 1, n - 1 - m
    return Код(n, kb, "Хэмминг+", многочлен(МНОГОЧЛЕНЫ_ХЭММИНГА[(nb, kb)]), 1)


def хэмминг(n: int) -> Код:
    """Хэмминг без бита чётности: (2^m − 1, 2^m − 1 − m)."""
    for (nb, kb), g in МНОГОЧЛЕНЫ_ХЭММИНГА.items():
        if nb == n:
            return Код(nb, kb, "Хэмминг", многочлен(g), 1)
    raise ValueError(f"кода Хэмминга длины {n} нет в таблице многочленов")


def чётность(n: int) -> Код:
    return Код(n, n - 1, "чётность", 0, 0)


def бчх_32_21() -> Код:
    return Код(32, 21, "БЧХ+", многочлен(МНОГОЧЛЕН_БЧХ_31_21), 2)


def _остаток(степень: int, g: int) -> int:
    """x^степень mod g над GF(2)."""
    r = g.bit_length() - 1
    v = 1 << степень
    for i in range(степень, r - 1, -1):                 # старшие степени — по одной, сверху вниз
        if v >> i & 1:
            v ^= g << (i - r)
    return v


@functools.cache
def порождающая(код: Код) -> np.ndarray:
    """G (k × n): строка i — слово с единственной единицей на i-м бите данных."""
    n, k = код.n, код.k
    G = np.zeros((k, n), np.uint8)
    G[:, :k] = np.eye(k, dtype=np.uint8)
    if код.вид == "чётность":
        G[:, k] = 1
        return G
    с_чётностью = код.вид.endswith("+")
    nb = n - 1 if с_чётностью else n
    r = nb - k
    if код.g.bit_length() - 1 != r:
        raise ValueError(f"степень многочлена {код.g.bit_length() - 1} не равна n − k = {r} у {код.запись}")
    for i in range(k):
        остаток = _остаток(nb - 1 - i, код.g)            # данные — старшие степени, первый бит — x^(nb−1)
        for j in range(r):
            G[i, k + j] = остаток >> (r - 1 - j) & 1
    if с_чётностью:
        G[:, n - 1] = G[:, :nb].sum(axis=1) & 1
    return G


@functools.cache
def проверочная(код: Код) -> np.ndarray:
    """H ((n − k) × n) систематического кода: G = [I | P] → H = [Pᵀ | I]."""
    G = порождающая(код)
    k, n = G.shape
    return np.hstack([G[:, k:].T, np.eye(n - k, dtype=np.uint8)]).astype(np.uint8)


def мин_расстояние(код: Код, до_k: int = 16) -> int | None:
    """Наименьший вес ненулевого слова — перебором (только при k ≤ до_k)."""
    if код.k > до_k:
        return None
    G = порождающая(код).astype(np.int64)
    данные = ((np.arange(1, 1 << код.k)[:, None] >> np.arange(код.k)[None, :]) & 1)
    return int(((данные @ G) & 1).sum(axis=1).min())


