"""ТКБ по режимам модемов: каталог режимов с первоисточниками, снятие и поиск режима вслепую.

Слепое снятие (``tpc``) находит строки, столбцы и глубину по потоку, но не
видит того, чего в потоке «не хватает»: укорочения на отдельные биты (B/Q),
выкалывания, добавочной чётности по гипердиагонали (eTPC, «+»), служебных
бит кадра. Здесь каждый режим описан целиком — составляющие коды по осям,
укорочение, гипердиагональ, выкалывание, порядок передачи, длина кадра — и
по описанию строятся слова всех осей блока и проверки к ним. Составляющие
коды — любые линейные систематические: расширенный Хэмминг, Хэмминг без
бита чётности, код чётности, расширенный БЧХ; проверки строятся по
порождающему многочлену, а если в потоке они иные (другой порядок
проверочных бит у кодера модема), — выделяются по потоку ранговым методом
при той же геометрии блока.

Каталог (``КАТАЛОГ``) — режимы из первоисточников (папка istochniki/tpc
репозитория: даташиты AHA4501/AHA4524, руководства Radyne/Comtech,
вклады IEEE 802.16, патент eTPC US7356752, White Paper Advantech) и
режимы со снимков окна «Поиск блочных турбокодов» софта отдела. У каждого
— источник (файл и страница) и отметка достоверности: «Ф» — из файла,
«А» — арифметика скорости по источнику и снимку, «Г» — гипотеза, «С» —
только со снимка софта отдела.

Поиск режима: для каждой длины строки — профиль чётности окон по кадрам
(у строки кода чётность постоянна в каждом кадре — при скремблере со
сбросом на блоке тоже), по нему — фаза блока в кадре; у лучших фаз —
постоянство синдромов всех осей и гипердиагонали, затем декодирование
пробных блоков. Итог — доля блоков, где выполнены все проверки.
"""

