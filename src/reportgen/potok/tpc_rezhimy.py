#: Итераций жёсткого декодирования (все оси по кругу).
ИТЕРАЦИЙ = 8
#: Блоков за раз (матрицы синдромов не раздуваются).
БЛОКОВ_ЗА_РАЗ = 256


def синдромы(блоки: np.ndarray, ось: Ось) -> np.ndarray:
    """Синдромы слов оси (блоков × слов), целыми: бит i — i-я проверка.

    Синдром — сумма (XOR) синдромов одиночных ошибок на местах единиц слова:
    без умножения матриц (оно здесь медленнее и зависит от библиотеки BLAS).
    """
    nb = len(блоки)
    if ось.H.shape[0] > 62:
        raise ValueError("синдром длиннее 62 проверок")
    столбцы = (ось.H.T.astype(np.int64) * _вес_синдромов(ось.H.shape[0])).sum(axis=1)
    слова = блоки[:, ось.слова]
    return np.bitwise_xor.reduce(слова.astype(np.int64) * столбцы, axis=-1).reshape(nb, -1)


def цели_синдромов(блоки: np.ndarray, ось: Ось) -> np.ndarray:
    """Синдром каждого места слова, общий у двух третей блоков (маска на блоке после кода), иначе 0.

    Скремблер со сбросом на блоке, наложенный после кодера, прибавляет к
    каждому блоку одну маску: синдром слова на месте p становится постоянным
    s_p ≠ 0. Большинство по блокам его и даёт.
    """
    с = синдромы(блоки, ось)
    if len(с) < 4:
        return np.zeros(с.shape[1], np.int64)
    # Значение большинства, если оно есть, — медиана отсортированного столбца; маска — если так у двух
    # третей блоков и больше (у слова без маски ненулевой синдром от ошибок линии бывает у немногих, но
    # при восьми пробных блоках простое большинство среди сотни слов случайно набирается).
    кандидат = np.sort(с, axis=0)[len(с) // 2]
    большинство = (с == кандидат[None, :]).sum(axis=0) * 3 >= 2 * len(с)
    return np.where(большинство, кандидат, 0).astype(np.int64)


def _исправить_ось(блоки: np.ndarray, ось: Ось, цели: np.ndarray | None) -> int:
    """Одна ось: исправить ошибки по таблице синдромов (на месте). Возвращает число исправлений."""
    if ось.исправления is None:
        return 0
    с = синдромы(блоки, ось)
    if цели is not None:
        с = с ^ цели[None, :]
    bi, wi = np.nonzero(с)
    if not len(bi):
        return 0
    места = ось.исправления[с[bi, wi]]                             # (ошибочных × t)
    исправлено = 0
    for j in range(места.shape[1]):
        есть = места[:, j] >= 0
        if not есть.any():
            continue
        b, w, p = bi[есть], wi[есть], места[есть, j]
        свободно = ~ось.закреплено[w, p]
        b, w, p = b[свободно], w[свободно], p[свободно]
        np.bitwise_xor.at(блоки, (b, ось.слова[w, p]), 1)
        исправлено += int(len(b))
    return исправлено


def _левая_обратная(M: np.ndarray) -> np.ndarray | None:
    """A (u × r) с A·M = I над GF(2) для M (r × u) полного ранга по столбцам, иначе None."""
    r, u = M.shape
    расш = np.hstack([M.astype(np.uint8), np.eye(r, dtype=np.uint8)])
    строка = 0
    опорные = []
    for c in range(u):
        p = next((i for i in range(строка, r) if расш[i, c]), None)
        if p is None:
            return None
        расш[[строка, p]] = расш[[p, строка]]
        for i in range(r):
            if i != строка and расш[i, c]:
                расш[i] ^= расш[строка]
        опорные.append(строка)
        строка += 1
    return расш[опорные, u:]


def план_стираний(г: Геометрия) -> list[tuple[int, int, np.ndarray, np.ndarray]]:
    """Порядок восстановления выколотых мест: (ось, слово, места в слове, A) — по кругу, пока восстанавливается."""
    if not len(г.выколото):
        return []
    неизвестно = np.zeros(г.размер, bool)
    неизвестно[г.выколото] = True
    оси = г.оси + ([г.гипер] if г.гипер is not None else [])
    план = []
    while неизвестно.any():
        сдвинулось = False
        for i, ось in enumerate(оси):
            есть = неизвестно[ось.слова]
            for w in np.flatnonzero(есть.any(axis=1)):
                места = np.flatnonzero(есть[w])
                A = _левая_обратная(ось.H[:, места])
                if A is None:
                    continue
                план.append((i, int(w), места, A))
                неизвестно[ось.слова[w, места]] = False
                сдвинулось = True
        if not сдвинулось:
            break
    return план


def _восстановить(блоки: np.ndarray, г: Геометрия, план, цели: list[np.ndarray | None]) -> None:
    """Выколотые места по плану: e = A · (H·w ⊕ цель), где w — слово с нулями на стёртых."""
    if not план:
        return
    оси = г.оси + ([г.гипер] if г.гипер is not None else [])
    блоки[:, г.выколото] = 0
    for i, w, места, A in план:
        ось = оси[i]
        слова = блоки[:, ось.слова[w]].astype(np.int64)
        с = (слова @ ось.H.T.astype(np.int64)) & 1                   # блоков × r
        if цели[i] is not None and цели[i][w]:
            с ^= (цели[i][w] >> np.arange(ось.H.shape[0])) & 1
        e = (с @ A.T.astype(np.int64)) & 1
        блоки[:, ось.слова[w, места]] = e.astype(np.uint8)


def _слово_места(ось: Ось, размер: int) -> np.ndarray:
    """Номер слова оси, в которое входит место блока (−1 — не входит)."""
    итог = np.full(размер, -1, np.int64)
    итог[ось.слова] = np.arange(len(ось.слова))[:, None]
    return итог


def _пересечения(блоки: np.ndarray, г: Геометрия, оси: list[Ось], цели: list[np.ndarray | None]) -> int:
    """Места, где нарушены слова всех осей, проходящих через место (не меньше двух осей), — перевернуть.

    Так исправляются ошибки там, где составляющий код их только обнаруживает
    (код чётности, двойная ошибка расширенного Хэмминга): одиночная ошибка —
    на пересечении нарушенной строки и нарушенного столбца (и диагонали).
    Место переворачивается, только если у какой-нибудь из его осей оно —
    единственное такое место в своём слове: две ошибки в двух строках и двух
    столбцах дают четыре угла, и ни один не единственный — их не трогаем.
    """
    nb, размер = блоки.shape
    нарушено = np.ones((nb, размер), bool)
    осей_через = np.zeros(размер, np.int32)
    места = []
    for ось, ц in zip(оси, цели, strict=True):
        с = синдромы(блоки, ось)
        if ц is not None:
            с = с ^ ц[None, :]
        место = _слово_места(ось, размер)
        есть = место >= 0
        нарушено[:, есть] &= (с != 0)[:, место[есть]]
        осей_через += есть
        места.append((место, есть))
    нарушено &= (осей_через >= 2)[None, :]
    нарушено[:, г.закреплено] = False
    if not нарушено.any():
        return 0
    единственное = np.zeros_like(нарушено)
    for (место, есть), ось in zip(места, оси, strict=True):
        в_слове = нарушено[:, ось.слова].sum(axis=2)                   # блоков × слов
        единственное[:, есть] |= (в_слове == 1)[:, место[есть]]
    перевернуть = нарушено & единственное
    блоки ^= перевернуть.astype(np.uint8)
    return int(перевернуть.sum())


#: Решение по кандидатам у блоков, оставшихся с нарушениями: не больше стольких мест-кандидатов, ошибок
#: и измерений неоднозначности (свободных переменных системы).
ПЕРЕБОР_МЕСТ_ДО = 128
ПЕРЕБОР_ОШИБОК_ДО = 8
ПЕРЕБОР_СВОБОДНЫХ_ДО = 10


#: Запас (в битах) проверок блока над числом наборов: 2^−запас — доля чужих блоков, которые решение
#: «очистило» бы случайно.
ПЕРЕБОР_ЗАПАС = 10


def предел_перебора(г: Геометрия) -> int:
    """Наибольшее число ошибок w (не больше ``ПЕРЕБОР_ОШИБОК_ДО``), при котором проверок в блоке больше
    log₂(числа наборов из 1…w мест) на ``ПЕРЕБОР_ЗАПАС``: случайный блок синдромом какого-нибудь набора
    не совпадает (у крошечного кода 802.16 в 96 бит с 19 проверками — одно место). Нули Q — данные
    кода (их кодер кодирует), не проверки."""
    проверок = г.передаётся - len(г.данные) - г.режим.нулей
    наборов, w = 0, 0
    for i in range(1, ПЕРЕБОР_ОШИБОК_ДО + 1):
        наборов += math.comb(г.размер, i)
        if math.log2(наборов) + ПЕРЕБОР_ЗАПАС > проверок:
            break
        w = i
    return w


def перебор_осмыслен(г: Геометрия) -> bool:
    return предел_перебора(г) >= 1


def _решение_gf2(столбцы: list[int], цель: int) -> tuple[int, list[int]] | None:
    """x (битовая маска кандидатов) с Σ x_j·столбец_j = цель над GF(2) и базис решений однородной системы."""
    базис: dict[int, tuple[int, int]] = {}                 # старший бит → (вектор, какие кандидаты)
    нули: list[int] = []
    for j, v in enumerate(столбцы):
        c = 1 << j
        while v:
            p = v.bit_length() - 1
            if p not in базис:
                базис[p] = (v, c)
                break
            bv, bc = базис[p]
            v, c = v ^ bv, c ^ bc
        else:
            нули.append(c)
    v, c = цель, 0
    while v:
        p = v.bit_length() - 1
        if p not in базис:
            return None
        bv, bc = базис[p]
        v, c = v ^ bv, c ^ bc
    return c, нули


def _наименьшее(x: int, нули: list[int]) -> int | None:
    """Единственное решение наименьшего веса среди x ⊕ span(нули) (два равных — None)."""
    лучшее, вес, равных = x, x.bit_count(), 1
    for маска in range(1, 1 << len(нули)):
        y = x
        for i, z in enumerate(нули):
            if маска >> i & 1:
                y ^= z
        w = y.bit_count()
        if w < вес:
            лучшее, вес, равных = y, w, 1
        elif w == вес:
            равных += 1
    return лучшее if равных == 1 else None


def _перебор(блоки: np.ndarray, г: Геометрия, оси: list[Ось], цели: list[np.ndarray | None],
             только: np.ndarray | None = None) -> int:
    """Блоки, где итерации не сняли нарушений: наименьший набор мест, после переворота которых все проверки выполнены.

    Кандидаты — места, где нарушены все слова, проходящие через место (сперва
    только такие; если решения нет — ещё места, где нарушены все, кроме одного,
    при трёх словах и больше): так снимаются две ошибки в одной строке кода
    чётности (строка их не видит, столбцы и диагонали — видят) и ошибка в бите
    гиперчётности (он входит в одно слово). Набор — решение системы над GF(2)
    «сумма синдромов одиночных ошибок кандидатов = синдром блока» (ранговым
    методом, без перебора сочетаний); если решений несколько — берётся
    единственное наименьшего веса, два равных (четыре угла) — блок не
    трогается. Вес — не больше ``предел_перебора``; кандидатов больше
    ``ПЕРЕБОР_МЕСТ_ДО`` — блок не трогается (это не ошибки линии, а чужой код).
    У выколотых блоков перебора нет: стёртые места зависят от переворотов.
    ``только`` — маска блоков, которые рассматривать.
    """
    предел = предел_перебора(г) if not len(г.выколото) else 0
    if not предел or not len(блоки):
        return 0
    размер = блоки.shape[1]
    синдр = []
    for ось, ц in zip(оси, цели, strict=True):
        с = синдромы(блоки, ось)
        синдр.append(с ^ ц[None, :] if ц is not None else с)
    плохо = np.any([с.any(axis=1) for с in синдр], axis=0)
    if только is not None:
        плохо &= только
    плохие = np.flatnonzero(плохо)
    if not len(плохие):
        return 0
    места_осей = [_слово_места(ось, размер) for ось in оси]
    через = np.sum([м >= 0 for м in места_осей], axis=0)
    # Синдром одиночной ошибки на месте — битами общей строки проверок блока (оси подряд, слова подряд).
    вклад = np.zeros(размер, object)
    сдвиг = 0
    for ось, м in zip(оси, места_осей, strict=True):
        r = ось.H.shape[0]
        столбцы = (ось.H.T.astype(np.int64) * _вес_синдромов(r)).sum(axis=1)
        поз = np.full(размер, -1, np.int64)
        поз[ось.слова] = np.arange(ось.слова.shape[1])[None, :]
        for p in np.flatnonzero(м >= 0):
            вклад[p] ^= int(столбцы[поз[p]]) << (сдвиг + int(м[p]) * r)
        сдвиг += len(ось.слова) * r
    свободно = np.ones(размер, bool)
    свободно[г.закреплено] = False
    нарушено = np.zeros((len(плохие), размер), np.int8)
    for м, с in zip(места_осей, синдр, strict=True):
        есть = м >= 0
        нарушено[:, есть] += (с[плохие] != 0)[:, м[есть]]
    строго = свободно[None, :] & (нарушено >= 1) & (нарушено == через[None, :])
    мягко = строго | (свободно[None, :] & (нарушено >= 1) & (через >= 3)[None, :]
                      & (нарушено >= через[None, :] - 1))
    исправлено = 0
    for j, b in enumerate(плохие):
        цель, сдвиг = 0, 0
        for ось, с in zip(оси, синдр, strict=True):
            r = ось.H.shape[0]
            for w in np.flatnonzero(с[b]):
                цель ^= int(с[b, w]) << (сдвиг + int(w) * r)
            сдвиг += len(ось.слова) * r
        найдено = None
        for годно in (строго[j], мягко[j]):
            канд = np.flatnonzero(годно)
            if not len(канд) or len(канд) > ПЕРЕБОР_МЕСТ_ДО:
                continue
            решение = _решение_gf2([вклад[p] for p in канд], цель)
            if решение is None or len(решение[1]) > ПЕРЕБОР_СВОБОДНЫХ_ДО:
                continue
            x = _наименьшее(*решение)
            if x is not None and 0 < x.bit_count() <= предел:
                найдено = канд[[i for i in range(len(канд)) if x >> i & 1]]
            break
        if найдено is not None:
            блоки[b, найдено] ^= 1
            исправлено += len(найдено)
    return исправлено


def декодировать(г: Геометрия, блоки: np.ndarray, *, итераций: int = ИТЕРАЦИЙ,
                 цели: list[np.ndarray | None] | None = None) -> tuple[np.ndarray, dict[str, object]]:
    """Итеративное жёсткое декодирование блоков (блоков × размер): оси по кругу, выколотые — по проверкам."""
    блоки = np.ascontiguousarray(блоки, dtype=np.uint8).copy()
    оси = г.оси + ([г.гипер] if г.гипер is not None else [])
    цели = list(цели) if цели is not None else [None] * len(оси)
    цели += [None] * (len(оси) - len(цели))
    план = план_стираний(г)
    _восстановить(блоки, г, план, цели)
    исходные = блоки.copy()
    до = [_без_нарушений(блоки, ось, ц) for ось, ц in zip(оси, цели, strict=True)]
    for _ in range(итераций):
        за_круг = 0
        for ось, ц in zip(г.оси, цели, strict=False):
            за_круг += _исправить_ось(блоки, ось, ц)
            # Выколотые — снова по проверкам: исправления меняют то, из чего они восстановлены.
            _восстановить(блоки, г, план, цели)
        за_круг += _пересечения(блоки, г, оси, цели)
        _восстановить(блоки, г, план, цели)
        if not за_круг:
            break
    _перебор(блоки, г, оси, цели)
    # Итерации у тяжёлого блока могут «исправить» не то (ложное пересечение) — тогда решение ищется
    # ещё и по принятому блоку, как он был.
    остались = ~_чистые(блоки, оси, цели)
    if остались.any() and перебор_осмыслен(г):
        заново = исходные.copy()
        if _перебор(заново, г, оси, цели, только=остались):
            годны = остались & _чистые(заново, оси, цели)
            блоки[годны] = заново[годны]
    # Исправлено — сколько мест блока итог изменил против принятого (выколотые не в счёт).
    разница = блоки != исходные
    разница[:, г.выколото] = False
    всего = int(разница.sum())
    чистые = np.ones(len(блоки), bool)
    после = []
    for ось, ц in zip(оси, цели, strict=True):
        с = синдромы(блоки, ось)
        if ц is not None:
            с = с ^ ц[None, :]
        плохие = с.any(axis=1)
        чистые &= ~плохие
        после.append(float(np.mean(~(с != 0))) if с.size else 1.0)
    сводка: dict[str, object] = {"исправлено": всего, "блоков_чисто": float(np.mean(чистые)) if len(блоки) else 0.0,
                                 "чистые": чистые}
    for ось, д, п in zip(оси, до, после, strict=True):
        сводка[f"{ось.имя}_до"] = д
        сводка[f"{ось.имя}_после"] = п
    return блоки, сводка


def _чистые(блоки: np.ndarray, оси: list[Ось], цели: list[np.ndarray | None]) -> np.ndarray:
    """Блоки, где выполнены все проверки всех осей."""
    итог = np.ones(len(блоки), bool)
    for ось, ц in zip(оси, цели, strict=True):
        с = синдромы(блоки, ось)
        итог &= ~(с ^ ц[None, :] if ц is not None else с).any(axis=1)
    return итог


def _без_нарушений(блоки: np.ndarray, ось: Ось, цели: np.ndarray | None) -> float:
    с = синдромы(блоки, ось)
    if цели is not None:
        с = с ^ цели[None, :]
    return float(np.mean(с == 0)) if с.size else 1.0


