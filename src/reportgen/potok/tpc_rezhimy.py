@dataclass
class Вариант:
    """Найденный режим: где блоки, какие проверки, что вышло на пробных блоках."""

    режим: Режим
    T: int
    фаза: int
    мера: float
    чисто: float = 0.0
    оси: dict[str, float] = field(default_factory=dict)
    гипер_сдвиг: tuple[int, ...] = ()
    гипер_смещение: tuple[int, ...] = ()
    бит_укор: int | None = None
    выучены: tuple[str, ...] = ()
    ошибок: float = 0.0
    слепой: bool = False
    находка: Находка | None = None

    def ключ(self) -> tuple:
        """Сравнение фаз одного режима: свои проверки, чистые блоки, согласие осей, мера строк."""
        return (-len(self.выучены), round(self.чисто, 3), round(min(self.оси.values(), default=0.0), 3), self.мера)

    def слой(self) -> str:
        if self.слепой:
            return self.находка.свойства.get("слой", "ткб") if self.находка else "ткб"
        части = [f"ткб режим {self.режим.ид}", f"кадр {self.T}", f"фаза {self.фаза}"]
        if self.бит_укор is not None and self.бит_укор != self.режим.бит_укор:
            части.append(f"укорочение {self.бит_укор}")
        if self.режим.гипер and (self.гипер_сдвиг, self.гипер_смещение) != гипер_по_умолчанию(self.режим):
            части.append("гипер " + " ".join(str(v) for v in self.гипер_сдвиг + self.гипер_смещение))
        return " ".join(части)

    def подпись(self) -> str:
        """Как в софте отдела: «скорость (T=…) (n,k)x(n,k) [укор./перфор./модем]»."""
        if self.слепой and self.находка is not None:
            с = self.находка.свойства
            n = [с.get("строка"), с.get("столбец")] + ([с["глубина"]] if с.get("глубина") else [])
            k = [с.get("k1"), с.get("k2")] + ([с["k3"]] if с.get("глубина") else [])
            коды = "x".join(f"({a},{b})" for a, b in zip(n, k, strict=True))
            T = с.get("кадр") or int(np.prod(n))
            return f"{с['данных_в_блоке'] / T:.3f} (T={T}) {коды} [слепой поиск]"
        р = self.режим
        г = геометрия(р, бит_укор=self.бит_укор)
        пометки = []
        if self.бит_укор or р.бит_укор or р.строк_укор or any(р.укор):
            пометки.append("укор.")
        if р.выколото or "перфор" in р.ид:
            пометки.append("перфор.")
        пометки.append(р.модем)
        return f"{len(г.данные) / self.T:.3f} (T={self.T}) {р.коды} [{', '.join(пометки)}]"

    def в_словарь(self) -> dict[str, object]:
        return {"ид": self.режим.ид if not self.слепой else "слепой", "подпись": self.подпись(), "T": self.T,
                "фаза": self.фаза, "мера": round(self.мера, 4), "чисто": round(self.чисто, 4),
                "оси": {к: round(v, 4) for к, v in self.оси.items()}, "слой": self.слой(),
                "выучены": list(self.выучены), "ошибок": self.ошибок, "слепой": self.слепой,
                "метка": "слепой" if self.слепой else self.режим.метка,
                "источник": "" if self.слепой else self.режим.источник,
                "примечание": "" if self.слепой else self.режим.примечание}


def _кадры_выборки(ряд: np.ndarray, T: int, запас: int, нужно: int) -> np.ndarray:
    """Номера кадров (начало f·T) с различным содержимым, чтобы окно [f·T, f·T + T + запас) влезло."""
    всего = (len(ряд) - запас) // T
    if всего < 2:
        return np.zeros(0, np.int64)
    таблица = ряд[:всего * T].reshape(всего, T)
    номера = слепой.отобрать_без_повторов(таблица, нужно)
    return np.asarray(номера, np.int64)


def _профиль(окна: np.ndarray, L: int, шаг: int) -> np.ndarray:
    """Перекос чётности (1 − 2p)² слова из L бит с шагом ``шаг`` от каждого места окна кадра."""
    F, W = окна.shape
    длина = W - (L - 1) * шаг
    if длина <= 0:
        return np.zeros(0)
    if шаг == 1:
        накоп = np.concatenate([np.zeros((F, 1), np.uint8), np.bitwise_xor.accumulate(окна, axis=1)], axis=1)
        ч = накоп[:, L:L + длина] ^ накоп[:, :длина]
    else:
        ч = np.zeros((F, длина), np.uint8)
        for j in range(L):
            ч ^= окна[:, j * шаг:j * шаг + длина]
    return (1 - 2 * ч.mean(axis=0)) ** 2


def _строки_шаблона(г: Геометрия) -> tuple[np.ndarray, int]:
    """Начала полных строк в передаваемом блоке и шаг внутри строки (1 — подряд, иначе спираль)."""
    обратный = np.full(г.размер, -1, np.int64)
    обратный[г.порядок] = np.arange(г.передаётся)
    слова = г.оси[0].слова
    места = обратный[слова]                                   # строк × X
    целые = (места >= 0).all(axis=1)
    места = np.sort(места[целые], axis=1)                       # у спирали строка идёт не подряд
    if not len(места):
        return np.zeros(0, np.int64), 1
    разности = np.diff(места, axis=1)
    if (разности == 1).all():
        return места[:, 0], 1
    шаг = int(разности[0, 0])
    if (разности == шаг).all():
        return места[:, 0], шаг
    return np.zeros(0, np.int64), 1


def _согласие_синдромов(блоки: np.ndarray, ось: Ось, стёрто: np.ndarray | None = None
                        ) -> tuple[float, np.ndarray]:
    """Доля слов оси, у которых синдром совпал с общим для этого места (и цели мест).

    ``стёрто`` — маска мест блока, которые не передаются (выколоты): слова с
    ними не судятся (их синдром зависит от невосстановленных бит).
    """
    цели = цели_синдромов(блоки, ось)
    с = синдромы(блоки, ось)
    совпало = с == цели[None, :]
    if стёрто is not None and стёрто.any():
        целые = ~стёрто[ось.слова].any(axis=1)
        if not целые.any():
            return 1.0, цели
        совпало = совпало[:, целые]
    return float(np.mean(совпало)), цели


def _подобрать_гипер(блоки: np.ndarray, г: Геометрия) -> tuple[tuple[int, ...], tuple[int, ...], float]:
    """Сдвиг и смещение гипердиагонали, при которых её чётность выполняется в большинстве блоков.

    Для каждого сдвига диагонали D — суммы основы вдоль диагоналей; бит
    гиперчётности (y, x) должен равняться D(y + by, x + bx) при каком-то
    смещении: согласие по всем смещениям сразу — взаимная корреляция ±1
    через БПФ, сложенная по блокам.
    """
    р = г.режим
    Z, Y, X = г.основа
    трёх = р.измерений == 3
    nb = len(блоки)
    if трёх:
        основа = блоки[:, :Z * Y * X].reshape(nb, Z, Y, X)
        гипер = блоки[:, Z * Y * X:].reshape(nb, Y, X)
    else:
        основа = блоки[:, :Y * X].reshape(nb, Y, X)
        гипер = блоки[:, Y * X:].reshape(nb, X)
    знак_г = 1.0 - 2.0 * гипер
    по_умолч = гипер_по_умолчанию(р)
    лучшее = (по_умолч[0], по_умолч[1], -1.0)
    for сдвиг in (ГИПЕР_СДВИГИ_3D if трёх else ГИПЕР_СДВИГИ_2D):
        if трёх:
            dy, dx = сдвиг
            D = np.zeros((nb, Y, X), np.uint8)
            for z in range(Z):
                D ^= np.roll(основа[:, z], ((Z - z) * dy, (Z - z) * dx), axis=(1, 2))
            с = np.fft.ifft2(np.conj(np.fft.fft2(знак_г)) * np.fft.fft2(1.0 - 2.0 * D)).real.sum(axis=0)
        else:
            a, = сдвиг
            D = np.zeros((nb, X), np.uint8)
            for r in range(Y):
                D ^= np.roll(основа[:, r], -a * r, axis=1)          # D[c] = Σ_r строка_r[c + a·r]
            с = np.fft.ifft(np.conj(np.fft.fft(знак_г)) * np.fft.fft(1.0 - 2.0 * D)).real.sum(axis=0)
        i = int(np.argmax(с))
        доля = float((1 + с.flat[i] / (nb * гипер[0].size)) / 2)
        if доля > лучшее[2] + 1e-9:
            смещение = tuple(int(v) for v in np.unravel_index(i, с.shape))
            лучшее = (сдвиг, смещение, доля)
    сдвиг, смещение, доля = лучшее
    # Смещение по умолчанию записано как в патенте (отрицательным) — то же по модулю — оставить его.
    if сдвиг == по_умолч[0] and all((a - b) % m == 0 for a, b, m in
                                    zip(смещение, по_умолч[1], (Y, X) if трёх else (X,), strict=True)):
        смещение = по_умолч[1]
    return сдвиг, смещение, доля


#: Бит служебного слова — одинаков в стольких кадрах (ошибки линии портят немногие).
ПОСТОЯННО_ОТ = 0.9


def _служебных_после(ряд: np.ndarray, кадры: np.ndarray, T: int, конец: int) -> int:
    """Сколько бит после конца блока постоянны во всех кадрах (синхрослово; чередование через кадр — тоже)."""
    места = (конец + np.arange(T)) % T
    окна = ряд[(кадры[:, None] * T + места[None, :])]
    чёт, нечёт = окна[кадры % 2 == 0], окна[кадры % 2 == 1]
    постоянно = np.ones(T, bool)
    for часть in (чёт, нечёт):
        if len(часть) >= 2:
            доля = часть.mean(axis=0)
            постоянно &= np.maximum(доля, 1 - доля) >= ПОСТОЯННО_ОТ
    n = int(np.argmin(постоянно)) if not постоянно.all() else T
    return n


def оценить(ряд: np.ndarray, р: Режим, T: int | None = None, *, кадров: int = КАДРОВ_ПОИСКА,
            декодировать_пробу: bool = True) -> Вариант | None:
    """Лучшая фаза режима в потоке и что вышло на пробных блоках (или None — режима нет).

    ``T`` — длина кадра (по умолчанию из режима; 0 — блоки подряд). У режимов
    «K» (``кадр_мин``) укорочение B подбирается: блок — кадр без служебных
    бит, постоянных во всех кадрах.
    """
    г = геометрия(р)
    T = int(T or р.кадр or г.передаётся)
    if р.кадр_мин and T < р.кадр:
        return None
    if not р.кадр_мин and T < г.передаётся:
        return None
    Nt_max = г.передаётся
    # Больших блоков — меньше: пробы хватает и по 16 блокам в 16 кбит.
    кадров = max(12, min(кадров, БИТ_ПРОБЫ // max(1, Nt_max)))
    кадры = _кадры_выборки(ряд, T, Nt_max + T, кадров)
    if len(кадры) < 4:
        return None
    окна = ряд[кадры[:, None] * T + np.arange(T + Nt_max)[None, :]]
    начала_строк, шаг = _строки_шаблона(г)
    if not len(начала_строк):
        return None
    X = г.основа[2]
    P = _профиль(окна, X, шаг)
    отн = начала_строк
    # Векторно: мера(φ) = среднее P[φ + сдвиг0 + отн_j] по строкам j.
    idx = np.arange(T)[:, None] + отн[None, :]
    годные = (idx >= 0).all(axis=1) & (idx < len(P)).all(axis=1)
    idx = np.clip(idx, 0, len(P) - 1)
    мера = np.where(годные, P[idx].mean(axis=1), 0.0)
    F = len(кадры)
    шум = 1.0 / F
    порог = max(0.2, 4 * шум)
    лучшие = [int(φ) for φ in np.argsort(-мера)[:ФАЗ_ПРОВЕРЯТЬ] if мера[φ] >= порог]
    # Строки видны и со сдвигом на целую строку (у коротких строк — на много строк): фазы,
    # равные лучшим по модулю длины строки, отбираются по согласию синдромов всех осей.
    кандидаты = list(dict.fromkeys(лучшие + [φ for φ0 in лучшие[:2] for φ in range(φ0 % (X * шаг), T, X * шаг)
                                            if годные[φ] and мера[φ] >= порог]))
    if len(кандидаты) > ФАЗ_ПРОВЕРЯТЬ:
        оценки = []
        for φ in кандидаты:
            блоки = блоки_из_потока(ряд, г, кадры[:КАДРОВ_ОТБОРА] * T + φ)
            оценки.append(min((_согласие_синдромов(блоки, ось, г.стёрто)[0] for ось in г.оси[1:]), default=0.0)
                          if len(блоки) >= 4 else 0.0)
        кандидаты = [кандидаты[i] for i in np.argsort(оценки, kind="stable")[::-1][:ФАЗ_ПРОВЕРЯТЬ]]
    лучший: Вариант | None = None
    for φ in кандидаты:
        бит_укор = None
        if р.кадр_мин:
            # Строки выровнены по концу блока; служебные — постоянные биты после него.
            конец = (φ + г.передаётся) % T
            S = _служебных_после(ряд, кадры, T, конец)
            Nt = T - S
            бит_укор = р.бит_укор + (г.передаётся - Nt)
            if бит_укор < 0 or бит_укор > г.данных_по_осям[2]:
                continue
            гг = геометрия(р, бит_укор=бит_укор)
            начало = (конец - гг.передаётся) % T
        else:
            гг = г
            начало = φ
        вариант = _проверить(ряд, гг, T, начало, кадры, float(мера[φ]), бит_укор, декодировать_пробу)
        if вариант is not None and (лучший is None or вариант.ключ() > лучший.ключ()):
            лучший = вариант
    return лучший


def _проверить(ряд: np.ndarray, г: Геометрия, T: int, начало: int, кадры: np.ndarray, мера: float,
               бит_укор: int | None, декодировать_пробу: bool) -> Вариант | None:
    """Проверки всех осей (и гипердиагонали) на пробных блоках с фазы ``начало``."""
    р = г.режим
    начала = кадры * T + начало
    блоки = блоки_из_потока(ряд, г, начала)
    if len(блоки) < 4:
        return None
    вариант = Вариант(р, T, int(начало), мера, бит_укор=бит_укор)
    if р.гипер:
        сдвиг, смещение, доля = _подобрать_гипер(блоки, г)
        г = геометрия(р, сдвиг, смещение, бит_укор)
        вариант.гипер_сдвиг, вариант.гипер_смещение = сдвиг, смещение
        вариант.оси["гипердиагонали"] = доля
    for ось in г.оси:
        доля, _ = _согласие_синдромов(блоки, ось, г.стёрто)
        вариант.оси[ось.имя] = доля
    if not декодировать_пробу:
        вариант.чисто = min(вариант.оси.values())
        return вариант
    _, сводка = снять_блоки(г, блоки)
    вариант.чисто = float(сводка["блоков_чисто"])
    вариант.выучены = tuple(сводка.get("выучены", ()))
    вариант.ошибок = float(сводка["исправлено"]) / max(1, len(блоки) * г.передаётся)
    return вариант


def снять_блоки(г: Геометрия, блоки: np.ndarray) -> tuple[np.ndarray, dict[str, object]]:
    """Декодировать блоки режима: цели синдромов (маска после кода) и, если нужно, проверки по потоку.

    Если у оси синдромы почти не постоянны, а чётность слов постоянна, — у
    модема другой порядок проверочных бит: проверки той же размерности
    выделяются по словам потока (``tpc.проверки``) и заменяют построенные по
    многочлену.
    """
    выучены = []
    оси = []
    for ось in г.оси:
        доля, _ = _согласие_синдромов(блоки, ось, г.стёрто)
        if доля < СВОИ_ПРОВЕРКИ_ОТ and ось.H.shape[0] > 1:
            слова = блоки[:, ось.слова].reshape(-1, ось.слова.shape[1])
            H = слепой.проверки(слова)
            if len(H) >= ось.H.shape[0]:
                H = H[:ось.H.shape[0]]
                новая = Ось(ось.имя, ось.слова, H[:, :-1].astype(np.uint8), ось.t if len(H) == ось.H.shape[0] else 1,
                            закреплено=ось.закреплено)
                if _согласие_синдромов(блоки, новая, г.стёрто)[0] > доля:
                    оси.append(новая)
                    выучены.append(ось.имя)
                    continue
        оси.append(ось)
    if выучены:
        г = replace(г, оси=оси)
    все = г.оси + ([г.гипер] if г.гипер is not None else [])
    цели = [цели_синдромов(блоки, ось) for ось in все]
    if len(г.выколото):
        # У слов с выколотыми местами синдром до восстановления зависит от данных — цель у них 0.
        for ось, ц in zip(все, цели, strict=True):
            ц[г.стёрто[ось.слова].any(axis=1)] = 0
    цели = [ц if ц.any() else None for ц in цели]
    итог, сводка = декодировать(г, блоки, цели=цели)
    сводка["выучены"] = выучены
    сводка["геометрия"] = г
    сводка["цели"] = цели
    return итог, сводка


# -- снятие в потоке ------------------------------------------------------------------------------

def начала_блоков(ряд: np.ndarray, T: int, фаза: int, Nt: int) -> np.ndarray:
    """Начала блоков: фаза + f·T, пока блок влезает."""
    всего = (len(ряд) - фаза - Nt) // T + 1 if len(ряд) >= фаза + Nt else 0
    return фаза + T * np.arange(max(0, всего), dtype=np.int64)


def снять(ряд: np.ndarray, р: Режим, *, T: int | None = None, фаза: int | None = None,
          гипер: tuple[int, ...] | None = None, бит_укор: int | None = None) -> tuple[np.ndarray, Находка]:
    """Снять ТКБ заданного режима: (данные, находка). Чего нет — находится по потоку."""
    ряд = np.asarray(ряд, dtype=np.uint8)
    г0 = геометрия(р, бит_укор=бит_укор)
    T = int(T or р.кадр or г0.передаётся)
    вариант = None
    if фаза is None or (р.гипер and гипер is None):
        вариант = оценить(ряд[:ВЫБОРКА], р, T, декодировать_пробу=False)
        if вариант is None:
            raise ValueError(f"режим {р.ид}: строк кода с кадром {T} в потоке не видно")
        if фаза is None:
            фаза = вариант.фаза
            if бит_укор is None:
                бит_укор = вариант.бит_укор
    сдвиг = смещение = None
    if гипер is not None:
        половина = len(гипер) // 2
        сдвиг, смещение = tuple(гипер[:половина]), tuple(гипер[половина:])
    elif вариант is not None and р.гипер:
        сдвиг, смещение = вариант.гипер_сдвиг, вариант.гипер_смещение
    г = геометрия(р, сдвиг, смещение, бит_укор)
    начала = начала_блоков(ряд, T, int(фаза) % T, г.передаётся)
    if len(начала) < 1:
        raise ValueError(f"режим {р.ид}: в потоке нет ни одного блока")
    данные_ч, сводки, всего_исправлено, чистых = [], [], 0, 0
    выучены: list[str] = []
    for i in range(0, len(начала), БЛОКОВ_ЗА_РАЗ * 8):
        блоки = блоки_из_потока(ряд, г, начала[i:i + БЛОКОВ_ЗА_РАЗ * 8])
        итог, сводка = снять_блоки(г, блоки)
        данные_ч.append(данные_блоков(сводка["геометрия"], итог))
        сводки.append(сводка)
        всего_исправлено += int(сводка["исправлено"])
        чистых += int(np.sum(сводка["чистые"]))
        выучены = list(dict.fromkeys(выучены + list(сводка["выучены"])))
    данные = np.concatenate(данные_ч) if данные_ч else np.zeros(0, np.uint8)
    блоков = len(начала)
    чисто = чистых / блоков
    первая = сводки[0]
    оси = [о.имя for о in г.оси] + (["гипердиагонали"] if г.гипер is not None else [])
    k = len(г.данные)
    подробно = [
        f"режим {р.ид}: {р.коды}, {р.модем}; блок {г.передаётся} бит (в кадре {T}), данных {k} "
        f"({k / г.передаётся:.3f} от блока, {k / T:.3f} от кадра)",
        f"первый блок — с бита {int(фаза) % T}; блоков {блоков}; исправлено {всего_исправлено} "
        f"(≈ {всего_исправлено / max(1, блоков * г.передаётся):.1e} ошибок на бит линии)",
        "без нарушений до декодирования (первая часть): " + ", ".join(
            f"{имя} {первая[f'{имя}_до'] * 100:.1f} %" for имя in оси),
        f"источник: {р.источник} [{р.метка}]",
    ]
    if р.примечание:
        подробно.append(р.примечание)
    if бит_укор is not None and бит_укор != р.бит_укор:
        подробно.append(f"укорочение первой строки подобрано по кадру: B = {бит_укор} бит")
    if р.гипер:
        подробно.append(f"гипердиагональ: сдвиг {г.гипер_сдвиг}, смещение {г.гипер_смещение}"
                        + (" (как в патенте US7356752)" if (г.гипер_сдвиг, г.гипер_смещение)
                           == гипер_по_умолчанию(р) else " (подобраны по потоку)"))
    if р.выколото:
        подробно.append(f"выколото {р.выколото} последних бит блока — восстановлены по проверкам осей")
    if выучены:
        подробно.append("проверки " + ", ".join(выучены) + " выделены по потоку: порядок проверочных бит у "
                        "кодера модема иной, чем у кодера по многочлену (геометрия та же)")
    if any(ц is not None for ц in первая["цели"]):
        подробно.append("синдромы постоянны, но не нулевые: на блок после кодера наложена постоянная маска "
                        "(скремблер со сбросом на блоке) — данные остаются под ней")
    находка = Находка(
        уровень="код",
        что=f"ТКБ режим {р.ид} {р.коды}, скорость {k}/{г.передаётся}",
        уверенность=float(чисто),
        мера=f"блоков без нарушений всех проверок после декодирования {чисто * 100:.1f} %",
        подробно=подробно, дальше=данные, вид_дальше="биты",
        сверка=float(первая[f"{г.оси[0].имя}_до"]),
        свойства={"режим": р.ид, "кадр": T, "фаза": int(фаза) % T, "данных_в_блоке": k,
                  "блок": г.передаётся, "блоков": блоков, "бит_укор": бит_укор,
                  "ошибок_в_линии": всего_исправлено / max(1, блоков * г.передаётся),
                  "строка": г.основа[2], "столбец": г.основа[1], "глубина": г.основа[0] if р.измерений == 3 else 0,
                  "k1": г.данных_по_осям[2], "k2": г.данных_по_осям[1],
                  "k3": г.данных_по_осям[0] if р.измерений == 3 else 0})
    return данные, находка


# -- поиск по каталогу ----------------------------------------------------------------------------

def длины_кадра(ряд: np.ndarray, синхрослово: str = "") -> list[int]:
    """Длины кадра потока: по синхрослову (частое расстояние между вхождениями) или по циклу."""
    итог: list[int] = []
    слово = "".join(ч for ч in синхрослово if ч in "01")
    if len(слово) >= 8:
        образец = np.frombuffer(слово.encode(), np.uint8) - 48
        L = len(образец)
        выборка = ряд[:ВЫБОРКА]
        if len(выборка) > L:
            окна = np.lib.stride_tricks.sliding_window_view(выборка, L)
            места = np.flatnonzero((окна == образец).all(axis=1))
            if len(места) >= 3:
                разности, сколько = np.unique(np.diff(места), return_counts=True)
                итог.append(int(разности[np.argmax(сколько)]))
    else:
        from . import cikl  # noqa: PLC0415
        найдено = cikl.длина_цикла(ряд[:ВЫБОРКА]) or cikl.гребёнка(ряд[:ВЫБОРКА])
        if найдено is not None:
            L = int(найдено[0])
            итог.append(L)
            if L % 2 == 0:
                итог.append(L // 2)                     # чередующееся синхрослово — цикл из двух кадров
    return итог


def поиск(ряд: np.ndarray, *, режимы: Sequence[Режим] | None = None, кадры: Sequence[int] = (),
          с: int = 0, по: int | None = None, срок: float | None = None) -> dict[str, object]:
    """Режимы каталога с номерами [с, по) — какие есть в потоке (часть не дольше ``срок`` секунд).

    ``кадры`` — длины кадра, найденные в потоке (по синхрослову или циклу):
    каждый режим пробуется со своей длиной кадра и с каждой из этих, если
    блок в неё помещается. Возвращает {"найдено": [варианты], "по": следующий
    номер, "всего": режимов}.
    """
    ряд = np.asarray(ряд[:ВЫБОРКА], dtype=np.uint8)
    режимы = list(режимы if режимы is not None else КАТАЛОГ)
    по = len(режимы) if по is None else min(по, len(режимы))
    конец = time.monotonic() + срок if срок else None
    найдено: list[Вариант] = []
    i = с
    while i < по:
        р = режимы[i]
        i += 1
        г = геометрия(р)
        длины = {int(р.кадр or г.передаётся)}
        for T in кадры:
            T = int(T)
            if (T >= г.передаётся and not р.кадр_мин) or (р.кадр_мин and T >= р.кадр):
                if not р.кадр or р.кадр_мин or T == р.кадр or T >= г.передаётся:
                    длины.add(T)
        лучший = None
        for T in sorted(длины):
            try:
                в = оценить(ряд, р, T)
            except ValueError:
                в = None
            if в is not None and в.чисто >= НАЙДЕН_ОТ and (лучший is None or в.чисто > лучший.чисто):
                лучший = в
        if лучший is not None:
            найдено.append(лучший)
        if конец is not None and time.monotonic() > конец:
            break
    return {"найдено": найдено, "по": i, "всего": len(режимы)}


def упорядочить(варианты: Sequence[Вариант]) -> list[Вариант]:
    """Лучшие первыми: чище блоки, больше проверок (полный код, а не его часть), точнее кадр."""
    def ключ(в: Вариант):
        if в.слепой:
            return (в.чисто, 0, 0.0)
        г = геометрия(в.режим, бит_укор=в.бит_укор)
        проверок = г.передаётся - len(г.данные)
        return (round(в.чисто, 2), проверок, в.мера)
    return sorted(варианты, key=ключ, reverse=True)


def найти(ряд: np.ndarray, *, кадры: Sequence[int] | None = None, срок: float | None = None) -> Вариант | None:
    """Лучший режим каталога в потоке (или None)."""
    if кадры is None:
        кадры = длины_кадра(ряд)
    итог = поиск(ряд, кадры=кадры, срок=срок)
    варианты = упорядочить(итог["найдено"])
    return варианты[0] if варианты else None


def найти_в_кадрах(ряд: np.ndarray, длина: int) -> Находка | None:
    """Для автомата: режим каталога с кадром ``длина`` — снятый целиком (или None).

    Пробуются режимы, у которых блок помещается в кадр; найденный снимается
    по всему потоку.
    """
    вариант = найти(ряд, кадры=[длина])
    if вариант is None or вариант.T != длина:
        return None
    г = геометрия(вариант.режим, бит_укор=вариант.бит_укор)
    try:
        _, находка = снять(ряд, вариант.режим, T=вариант.T, фаза=вариант.фаза,
                           гипер=(вариант.гипер_сдвиг + вариант.гипер_смещение) if вариант.режим.гипер else None,
                           бит_укор=вариант.бит_укор)
    except ValueError:
        return None
    if находка.уверенность < НАЙДЕН_ОТ:
        return None
    находка.свойства["слой"] = вариант.слой()
    находка.свойства["данных_в_блоке"] = len(г.данные)
    return находка
