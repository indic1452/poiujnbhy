def синдромы(блоки: np.ndarray, ось: Ось) -> np.ndarray:
    """Синдромы слов оси (блоков × слов), целыми: бит i — i-я проверка.

    Синдром — сумма (XOR) синдромов одиночных ошибок на местах единиц слова:
    без умножения матриц (оно здесь медленнее и зависит от библиотеки BLAS).
    """
    nb = len(блоки)
    if ось.H.shape[0] > 62:
        raise ValueError("синдром длиннее 62 проверок")
    столбцы = (ось.H.T.astype(np.int64) * _вес_синдромов(ось.H.shape[0])).sum(axis=1)
    слова = блоки[:, ось.слова]
    return np.bitwise_xor.reduce(слова.astype(np.int64) * столбцы, axis=-1).reshape(nb, -1)


def цели_синдромов(блоки: np.ndarray, ось: Ось) -> np.ndarray:
    """Синдром каждого места слова, общий у большинства блоков (маска на блоке после кода), иначе 0.

    Скремблер со сбросом на блоке, наложенный после кодера, прибавляет к
    каждому блоку одну маску: синдром слова на месте p становится постоянным
    s_p ≠ 0. Большинство по блокам его и даёт.
    """
    с = синдромы(блоки, ось)
    if len(с) < 4:
        return np.zeros(с.shape[1], np.int64)
    # Значение большинства, если оно есть, — медиана отсортированного столбца.
    кандидат = np.sort(с, axis=0)[len(с) // 2]
    большинство = (с == кандидат[None, :]).sum(axis=0) * 2 > len(с)
    return np.where(большинство, кандидат, 0).astype(np.int64)


def _исправить_ось(блоки: np.ndarray, ось: Ось, цели: np.ndarray | None) -> int:
    """Одна ось: исправить ошибки по таблице синдромов (на месте). Возвращает число исправлений."""
    if ось.исправления is None:
        return 0
    с = синдромы(блоки, ось)
    if цели is not None:
        с = с ^ цели[None, :]
    bi, wi = np.nonzero(с)
    if not len(bi):
        return 0
    места = ось.исправления[с[bi, wi]]                             # (ошибочных × t)
    исправлено = 0
    for j in range(места.shape[1]):
        есть = места[:, j] >= 0
        if not есть.any():
            continue
        b, w, p = bi[есть], wi[есть], места[есть, j]
        свободно = ~ось.закреплено[w, p]
        b, w, p = b[свободно], w[свободно], p[свободно]
        np.bitwise_xor.at(блоки, (b, ось.слова[w, p]), 1)
        исправлено += int(len(b))
    return исправлено


def _левая_обратная(M: np.ndarray) -> np.ndarray | None:
    """A (u × r) с A·M = I над GF(2) для M (r × u) полного ранга по столбцам, иначе None."""
    r, u = M.shape
    расш = np.hstack([M.astype(np.uint8), np.eye(r, dtype=np.uint8)])
    строка = 0
    опорные = []
    for c in range(u):
        p = next((i for i in range(строка, r) if расш[i, c]), None)
        if p is None:
            return None
        расш[[строка, p]] = расш[[p, строка]]
        for i in range(r):
            if i != строка and расш[i, c]:
                расш[i] ^= расш[строка]
        опорные.append(строка)
        строка += 1
    return расш[опорные, u:]


def план_стираний(г: Геометрия) -> list[tuple[int, int, np.ndarray, np.ndarray]]:
    """Порядок восстановления выколотых мест: (ось, слово, места в слове, A) — по кругу, пока восстанавливается."""
    if not len(г.выколото):
        return []
    неизвестно = np.zeros(г.размер, bool)
    неизвестно[г.выколото] = True
    оси = г.оси + ([г.гипер] if г.гипер is not None else [])
    план = []
    while неизвестно.any():
        сдвинулось = False
        for i, ось in enumerate(оси):
            есть = неизвестно[ось.слова]
            for w in np.flatnonzero(есть.any(axis=1)):
                места = np.flatnonzero(есть[w])
                A = _левая_обратная(ось.H[:, места])
                if A is None:
                    continue
                план.append((i, int(w), места, A))
                неизвестно[ось.слова[w, места]] = False
                сдвинулось = True
        if not сдвинулось:
            break
    return план


def _восстановить(блоки: np.ndarray, г: Геометрия, план, цели: list[np.ndarray | None]) -> None:
    """Выколотые места по плану: e = A · (H·w ⊕ цель), где w — слово с нулями на стёртых."""
    if not план:
        return
    оси = г.оси + ([г.гипер] if г.гипер is not None else [])
    блоки[:, г.выколото] = 0
    for i, w, места, A in план:
        ось = оси[i]
        слова = блоки[:, ось.слова[w]].astype(np.int64)
        с = (слова @ ось.H.T.astype(np.int64)) & 1                   # блоков × r
        if цели[i] is not None and цели[i][w]:
            с ^= (цели[i][w] >> np.arange(ось.H.shape[0])) & 1
        e = (с @ A.T.astype(np.int64)) & 1
        блоки[:, ось.слова[w, места]] = e.astype(np.uint8)


def _слово_места(ось: Ось, размер: int) -> np.ndarray:
    """Номер слова оси, в которое входит место блока (−1 — не входит)."""
    итог = np.full(размер, -1, np.int64)
    итог[ось.слова] = np.arange(len(ось.слова))[:, None]
    return итог


def _пересечения(блоки: np.ndarray, г: Геометрия, оси: list[Ось], цели: list[np.ndarray | None]) -> int:
    """Места, где нарушены слова всех осей, проходящих через место (не меньше двух осей), — перевернуть.

    Так исправляются ошибки там, где составляющий код их только обнаруживает
    (код чётности, двойная ошибка расширенного Хэмминга): одиночная ошибка —
    на пересечении нарушенной строки и нарушенного столбца (и диагонали).
    Место переворачивается, только если у какой-нибудь из его осей оно —
    единственное такое место в своём слове: две ошибки в двух строках и двух
    столбцах дают четыре угла, и ни один не единственный — их не трогаем.
    """
    nb, размер = блоки.shape
    нарушено = np.ones((nb, размер), bool)
    осей_через = np.zeros(размер, np.int32)
    места = []
    for ось, ц in zip(оси, цели, strict=True):
        с = синдромы(блоки, ось)
        if ц is not None:
            с = с ^ ц[None, :]
        место = _слово_места(ось, размер)
        есть = место >= 0
        нарушено[:, есть] &= (с != 0)[:, место[есть]]
        осей_через += есть
        места.append((место, есть))
    нарушено &= (осей_через >= 2)[None, :]
    нарушено[:, г.закреплено] = False
    if not нарушено.any():
        return 0
    единственное = np.zeros_like(нарушено)
    for (место, есть), ось in zip(места, оси, strict=True):
        в_слове = нарушено[:, ось.слова].sum(axis=2)                   # блоков × слов
        единственное[:, есть] |= (в_слове == 1)[:, место[есть]]
    перевернуть = нарушено & единственное
    блоки ^= перевернуть.astype(np.uint8)
    return int(перевернуть.sum())


def декодировать(г: Геометрия, блоки: np.ndarray, *, итераций: int = ИТЕРАЦИЙ,
                 цели: list[np.ndarray | None] | None = None) -> tuple[np.ndarray, dict[str, object]]:
    """Итеративное жёсткое декодирование блоков (блоков × размер): оси по кругу, выколотые — по проверкам."""
    блоки = np.ascontiguousarray(блоки, dtype=np.uint8).copy()
    оси = г.оси + ([г.гипер] if г.гипер is not None else [])
    цели = list(цели) if цели is not None else [None] * len(оси)
    цели += [None] * (len(оси) - len(цели))
    план = план_стираний(г)
    _восстановить(блоки, г, план, цели)
    до = [_без_нарушений(блоки, ось, ц) for ось, ц in zip(оси, цели, strict=True)]
    всего = 0
    for _ in range(итераций):
        за_круг = 0
        for ось, ц in zip(г.оси, цели, strict=False):
            за_круг += _исправить_ось(блоки, ось, ц)
            # Выколотые — снова по проверкам: исправления меняют то, из чего они восстановлены.
            _восстановить(блоки, г, план, цели)
        за_круг += _пересечения(блоки, г, оси, цели)
        _восстановить(блоки, г, план, цели)
        всего += за_круг
        if not за_круг:
            break
    чистые = np.ones(len(блоки), bool)
    после = []
    for ось, ц in zip(оси, цели, strict=True):
        с = синдромы(блоки, ось)
        if ц is not None:
            с = с ^ ц[None, :]
        плохие = с.any(axis=1)
        чистые &= ~плохие
        после.append(float(np.mean(~(с != 0))) if с.size else 1.0)
    сводка: dict[str, object] = {"исправлено": всего, "блоков_чисто": float(np.mean(чистые)) if len(блоки) else 0.0,
                                 "чистые": чистые}
    for ось, д, п in zip(оси, до, после, strict=True):
        сводка[f"{ось.имя}_до"] = д
        сводка[f"{ось.имя}_после"] = п
    return блоки, сводка


def _без_нарушений(блоки: np.ndarray, ось: Ось, цели: np.ndarray | None) -> float:
    с = синдромы(блоки, ось)
    if цели is not None:
        с = с ^ цели[None, :]
    return float(np.mean(с == 0)) if с.size else 1.0


