def блоки_из_потока(ряд: np.ndarray, г: Геометрия, начала: Sequence[int]) -> np.ndarray:
    """Передаваемые биты блоков с данных начал → полные блоки (блоков × размер), укороченное и выколотое — 0."""
    начала = np.asarray([н for н in начала if 0 <= н and н + г.передаётся <= len(ряд)], np.int64)
    блоки = np.zeros((len(начала), г.размер), np.uint8)
    if len(начала):
        блоки[:, г.порядок] = ряд[начала[:, None] + np.arange(г.передаётся)[None, :]]
    return блоки


