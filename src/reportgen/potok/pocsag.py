"""POCSAG (ITU-R M.584): пакеты по синхрослову, BCH (31, 21) с исправлением, адреса и сообщения.

Раскладка — как у multimon-ng (pocsag.c) и MMDVMHost (POCSAGDefines.h):
- пакет — синхрослово 0x7CD215D8 и 16 кодовых слов (8 кадров по 2), всего 544 бита; перед первым
  пакетом — преамбула 1010…;
- кодовое слово 32 бита: старший бит 0 — адрес, 1 — сообщение; дальше 20 бит данных (у адреса —
  18 бит адреса и 2 бита функции), 10 проверочных BCH (31, 21) с x¹⁰+x⁹+x⁸+x⁶+x⁵+x³+1 и бит
  чётности; слово простоя 0x7A89C197;
- адрес (RIC) = 18 бит адреса · 8 + номер кадра в пакете; сообщение — подряд 20-битовые куски
  данных до следующего адреса или слова простоя;
- цифровое сообщение: тетрады младшим битом вперёд, таблица «084 2.6]195-3U7[» (по перевёрнутой
  тетраде, как conv_table multimon-ng); текстовое — 7-битовые символы ASCII младшим битом вперёд.
Функция 0 — обычно цифровое, 3 — текстовое (как режим STANDARD multimon-ng).
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from itertools import combinations
from typing import Dict, List, Optional, Tuple

import numpy as np

from .nahodka import Находка

СИНХРО = 0x7CD215D8
ПРОСТОЙ = 0x7A89C197
ПОРОЖДАЮЩИЙ = 0b11101101001                     # x¹⁰+x⁹+x⁸+x⁶+x⁵+x³+1
ПАКЕТ = 32 * 17
ОШИБОК_СИНХРО = 2
ЦИФРЫ = "084 2.6]195-3U7["
#: Меньше пакетов — не POCSAG.
НАЙТИ_ОТ = 2


def _остаток(слово31: int) -> int:
    for сдвиг in range(30, 9, -1):
        if слово31 >> сдвиг & 1:
            слово31 ^= ПОРОЖДАЮЩИЙ << (сдвиг - 10)
    return слово31


def закодировать(данные21: int) -> int:
    """21 бит (флаг и 20 бит) → кодовое слово 32 бита (для проверок и синтеза)."""
    слово = данные21 << 10
    слово |= _остаток(слово)
    return (слово << 1) | (bin(слово).count("1") & 1)


def _синдромы() -> Tuple[Dict[int, int], Dict[int, int]]:
    одна = {_остаток(1 << i): 1 << i for i in range(31)}
    две = {_остаток((1 << i) | (1 << j)): (1 << i) | (1 << j) for i, j in combinations(range(31), 2)}
    return одна, две


ОДНА, ДВЕ = _синдромы()


def исправить(слово: int) -> Optional[Tuple[int, int]]:
    """(исправленное слово, число исправленных бит) — до двух ошибок в 32 битах, иначе None."""
    s = _остаток(слово >> 1)
    нечётно = bin(слово).count("1") & 1
    if s == 0:
        return (слово ^ 1, 1) if нечётно else (слово, 0)
    if s in ОДНА:
        исправленное = слово ^ (ОДНА[s] << 1)
        return (исправленное, 1) if нечётно else (исправленное ^ 1, 2)
    if s in ДВЕ and not нечётно:
        return слово ^ (ДВЕ[s] << 1), 2
    return None


def цифровое(данные: List[int]) -> str:
    """20-битовые куски → цифровое сообщение (тетрады младшим битом вперёд)."""
    итог = []
    for кусок in данные:
        for k in range(5):
            тетрада = (кусок >> (16 - 4 * k)) & 0xF
            итог.append(ЦИФРЫ[тетрада])
    return "".join(итог).rstrip(" ")


def текстовое(данные: List[int]) -> str:
    """20-битовые куски → текст: 7-битовые символы младшим битом вперёд."""
    биты = "".join(format(к, "020b") for к in данные)
    итог = []
    for i in range(0, len(биты) - 6, 7):
        код = int(биты[i:i + 7][::-1], 2)
        if код in (0, 3, 4, 23):                      # NUL, ETX, EOT, ETB — конец/заполнение
            break
        итог.append(chr(код) if 32 <= код < 127 else f"<{код:02X}>")
    return "".join(итог)


@dataclass
class Сообщение:
    адрес: int
    функция: int
    данные: List[int] = field(default_factory=list)
    оборвано: bool = False

    def текст(self) -> str:
        if not self.данные:
            текст = "(вызов без сообщения)"
        else:
            текст = (цифровое(self.данные) if self.функция == 0 else текстовое(self.данные)) or "(пусто)"
        return текст + (" [оборвано: неисправимое слово]" if self.оборвано else "")


def синхрослова(биты: np.ndarray) -> List[Tuple[int, bool]]:
    """(место, инверсия) всех синхрослов с не более чем ОШИБОК_СИНХРО ошибками."""
    биты = np.asarray(биты, dtype=np.uint8)
    if len(биты) < 32:
        return []
    эталон = np.array([(СИНХРО >> (31 - i)) & 1 for i in range(32)], dtype=np.uint8)
    окна = np.lib.stride_tricks.sliding_window_view(биты, 32)
    разных = (окна != эталон).sum(axis=1)
    итог = [(int(м), False) for м in np.flatnonzero(разных <= ОШИБОК_СИНХРО)]
    итог += [(int(м), True) for м in np.flatnonzero(разных >= 32 - ОШИБОК_СИНХРО)]
    return sorted(итог)


def разобрать(биты: np.ndarray) -> Dict[str, object]:
    """Пакеты от каждого синхрослова: сообщения, исправленные и неисправимые слова."""
    биты = np.asarray(биты, dtype=np.uint8)
    места = синхрослова(биты)
    сообщения: List[Сообщение] = []
    текущее: Optional[Сообщение] = None
    исправлено = неисправимых = слов = простоя = 0
    пакетов = 0
    for место, инверсия in места:
        if место + ПАКЕТ > len(биты):
            break
        пакет = биты[место + 32:место + ПАКЕТ]
        if инверсия:
            пакет = 1 - пакет
        пакетов += 1
        for n in range(16):
            слово = int("".join(map(str, пакет[32 * n:32 * n + 32])), 2)
            слов += 1
            годно = исправить(слово)
            if годно is None:
                # Неисправимое слово могло быть и адресом следующего вызова — сообщение обрывается.
                неисправимых += 1
                if текущее is not None:
                    текущее.оборвано = True
                текущее = None
                continue
            слово, ошибок = годно
            исправлено += ошибок
            if слово == ПРОСТОЙ:
                простоя += 1
                текущее = None
                continue
            if слово >> 31:
                if текущее is not None:
                    текущее.данные.append((слово >> 11) & 0xFFFFF)
                continue
            текущее = Сообщение(((слово >> 13) & 0x3FFFF) << 3 | (n // 2), (слово >> 11) & 3)
            сообщения.append(текущее)
    return {"пакетов": пакетов, "сообщения": сообщения, "исправлено": исправлено,
            "неисправимых": неисправимых, "слов": слов, "простоя": простоя,
            "инверсия": bool(места and all(и for _, и in места))}


def найти(биты: np.ndarray) -> Optional[Находка]:
    р = разобрать(биты)
    if р["пакетов"] < НАЙТИ_ОТ or р["неисправимых"] > 0.3 * р["слов"]:
        return None
    сообщения: List[Сообщение] = р["сообщения"]
    подробно = [f"пакетов (синхрослово 0x7CD215D8 + 16 кодовых слов): {р['пакетов']}"
                + (" — полярность обратная" if р["инверсия"] else ""),
                f"кодовых слов {р['слов']}: слов простоя {р['простоя']}, исправлено бит {р['исправлено']}, "
                f"неисправимых {р['неисправимых']} (BCH (31, 21) + чётность, до 2 ошибок)",
                f"вызовов: {len(сообщения)}; адресов: {len({с.адрес for с in сообщения})}"]
    функции = Counter(с.функция for с in сообщения)
    if функции:
        подробно.append("функции: " + ", ".join(f"{ф} × {к}" for ф, к in sorted(функции.items())))
    for с in сообщения[:40]:
        подробно.append(f"RIC {с.адрес}, функция {с.функция}: {с.текст()}")
    if len(сообщения) > 40:
        подробно.append(f"… и ещё {len(сообщения) - 40}")
    return Находка(
        уровень="канальный", что="POCSAG: пейджинговые вызовы",
        уверенность=1 - р["неисправимых"] / max(1, р["слов"]),
        мера=f"{р['пакетов']} пакетов по 544 бита; верных кодовых слов {р['слов'] - р['неисправимых']} из {р['слов']}",
        подробно=подробно, свойства={"вызовов": len(сообщения), "исправлено": р["исправлено"]})


def передать(вызовы: List[Tuple[int, int, str]], преамбула: int = 576) -> np.ndarray:
    """Синтез потока (для проверок): [(адрес, функция, текст)] → биты с преамбулой и пакетами.

    Текст при функции 0 — цифры (из ЦИФРЫ), иначе ASCII. Адрес ставится в свой кадр
    (адрес mod 8), до него — слова простоя.
    """
    слова: List[int] = []
    for адрес, функция, текст in вызовы:
        кадр = адрес & 7
        while len(слова) % 16 != 2 * кадр:
            слова.append(ПРОСТОЙ)
        слова.append(закодировать(((адрес >> 3) << 2) | функция))
        if функция == 0:
            тетрады = [ЦИФРЫ.index(ц) for ц in текст]            # уже в порядке передачи
            тетрады += [ЦИФРЫ.index(" ")] * (-len(тетрады) % 5)
            for i in range(0, len(тетрады), 5):
                кусок = 0
                for т in тетрады[i:i + 5]:
                    кусок = (кусок << 4) | т
                слова.append(закодировать((1 << 20) | кусок))
        else:
            биты = "".join(format(ord(с), "07b")[::-1] for с in текст + "\x04")
            биты += "0" * (-len(биты) % 20)
            for i in range(0, len(биты), 20):
                слова.append(закодировать((1 << 20) | int(биты[i:i + 20], 2)))
    слова.append(ПРОСТОЙ)
    while len(слова) % 16:
        слова.append(ПРОСТОЙ)
    поток = "10" * (преамбула // 2)
    for i in range(0, len(слова), 16):
        поток += format(СИНХРО, "032b") + "".join(format(с, "032b") for с in слова[i:i + 16])
    return np.array([int(б) for б in поток], dtype=np.uint8)
