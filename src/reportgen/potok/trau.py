"""Кадры TRAU (GSM Abis, 3GPP TS 48.060 / 08.60): подканалы 16 кбит/с, вид кадра, данные → V.110.

Кадр — 320 бит (20 мс при 16 кбит/с): 16 нулей, затем единица в начале каждого 16-битового
слова (биты 16, 32, …, 304) — 35 бит синхрокомбинации (08.60 4.8.1; libosmo-abis
src/trau/trau_frame.c encode_sync16). Биты 17–21 — C1…C5, вид кадра и направление
(trau_frame.h TRAU_FT_*). В канале 64 кбит/с E1 — четыре подканала по 16 кбит/с: биты 1–2,
3–4, 5–6 и 7–8 каждого октета.

Кадр данных (08.60 3.3.1, decode16_data): октеты 4–39 — четыре группы по 9 октетов, у каждого
октета первый бит — единица, остальные 7 — биты D. Группа — это кадр V.110 без октета нулей:
приставив восемь нулей, получаем кадр 80 бит, и дальше разбирает v110.
"""

from __future__ import annotations

from collections import Counter

import numpy as np

from . import v110
from .nahodka import Находка

ДЛИНА = 320
НУЛИ = np.arange(16)
ЕДИНИЦЫ = np.arange(16, ДЛИНА, 16)
КАДРОВ_ОТ = 16
ОБРАЗЕЦ = 300
СОГЛАСИЕ = 0.9

#: C1…C5 → (вид, направление) — trau_frame.h TRAU_FT_* (вверх — от БС к TRAU, вниз — к БС).
ВИДЫ: dict[int, tuple[str, str]] = {
    0x02: ("речь FR", "вверх"), 0x1C: ("речь FR", "вниз"), 0x1A: ("речь EFR", ""),
    0x06: ("речь AMR", ""), 0x03: ("речь HR", "вверх"), 0x1D: ("речь HR", "вниз"),
    0x05: ("O&M", "вверх"), 0x1B: ("O&M", "вниз"), 0x08: ("данные", "вверх"), 0x16: ("данные", "вниз"),
    0x09: ("данные HR", "вверх"), 0x17: ("данные HR", "вниз"), 0x14: ("синхронизация D145", ""),
    0x1F: ("расширенные данные (E-data)", ""), 0x10: ("пустой кадр", "вверх"), 0x0E: ("пустой кадр", "вниз"),
    0x1E: ("обмен конфигурацией", ""),
}
ДАННЫЕ = (0x08, 0x16)


def _верные(кадры: np.ndarray) -> np.ndarray:
    return (кадры[:, НУЛИ] == 0).all(1) & (кадры[:, ЕДИНИЦЫ] == 1).all(1)


def выровнять(биты: np.ndarray) -> tuple[int, float, np.ndarray] | None:
    """Начало кадра по 35 битам синхрокомбинации: (сдвиг, доля верных кадров, кадры)."""
    биты = np.asarray(биты, dtype=np.uint8)
    кадров = len(биты) // ДЛИНА - 1
    if кадров < КАДРОВ_ОТ:
        return None
    образец = min(кадров, ОБРАЗЕЦ)
    лучший = max(((сдвиг, float(_верные(биты[сдвиг:сдвиг + образец * ДЛИНА].reshape(образец, ДЛИНА)).mean()))
                  for сдвиг in range(ДЛИНА)), key=lambda п: п[1])
    if лучший[1] < СОГЛАСИЕ:
        return None
    сдвиг = лучший[0]
    кадров = (len(биты) - сдвиг) // ДЛИНА
    кадры = биты[сдвиг:сдвиг + кадров * ДЛИНА].reshape(кадров, ДЛИНА)
    верно = float(_верные(кадры).mean())
    return (сдвиг, верно, кадры) if верно >= СОГЛАСИЕ else None


def вид(кадры: np.ndarray) -> np.ndarray:
    """C1…C5 каждого кадра числом (C1 — старший)."""
    return кадры[:, 17:22].astype(np.int64) @ np.array([16, 8, 4, 2, 1])


def кадры_v110(кадры: np.ndarray) -> np.ndarray:
    """Кадры данных TRAU → поток кадров V.110 (по четыре на кадр TRAU)."""
    группы = кадры[:, 32:320].reshape(len(кадры), 4, 72)
    нули = np.zeros((len(кадры), 4, 8), dtype=np.uint8)
    return np.concatenate([нули, группы], axis=2).reshape(-1)


def подканалы(биты: np.ndarray) -> list[tuple[int, np.ndarray]]:
    """Четыре подканала 16 кбит/с канала 64 кбит/с: (номер 1–4, биты)."""
    октеты = np.asarray(биты[:len(биты) // 8 * 8], dtype=np.uint8).reshape(-1, 8)
    return [(k + 1, октеты[:, 2 * k:2 * k + 2].reshape(-1)) for k in range(4)]


def _разобрать(биты: np.ndarray) -> dict[str, object] | None:
    найдено = выровнять(биты)
    if найдено is None:
        return None
    сдвиг, верно, кадры = найдено
    годные = кадры[_верные(кадры)]
    виды = вид(годные)
    счёт = Counter(int(в) for в in виды)
    данные = годные[np.isin(виды, ДАННЫЕ)]
    return {"сдвиг": сдвиг, "верно": верно, "кадров": len(кадры), "счёт": счёт, "данные": данные}


def _словами(счёт: Counter) -> str:
    итог = []
    for код, с in счёт.most_common():
        имя, куда = ВИДЫ.get(код, (f"C1–C5 = {код:05b}", ""))
        итог.append(f"{имя}{' ' + куда if куда else ''} × {с}")
    return ", ".join(итог)


def найти(биты: np.ndarray) -> Находка | None:
    """TRAU 16 кбит/с прямо в потоке или в подканалах канала 64 кбит/с; данные — через V.110."""
    биты = np.asarray(биты, dtype=np.uint8)
    итоги: list[tuple[int, dict[str, object]]] = []
    прямо = _разобрать(биты)
    if прямо is not None:
        итоги.append((0, прямо))
    else:
        for номер, поток in подканалы(биты):
            р = _разобрать(поток)
            if р is not None:
                итоги.append((номер, р))
    if not итоги:
        return None
    подробно: list[str] = []
    дальше = None
    всего = Counter()
    for номер, р in итоги:
        где = "поток" if номер == 0 else f"подканал {номер} (биты {2 * номер - 1}–{2 * номер} октета)"
        всего.update(р["счёт"])
        подробно.append(f"{где}: кадры 320 бит с бита {р['сдвиг']}, синхрокомбинация 35 бит верна в "
                        f"{р['верно'] * 100:.1f} % из {р['кадров']}; " + _словами(р["счёт"]))
        if len(р["данные"]) and дальше is None:
            внутри = v110.найти(кадры_v110(р["данные"]))
            if внутри is not None:
                подробно.append(f"{где}: в кадрах данных — {внутри.что} ({внутри.мера})")
                подробно += [f"  {п}" for п in внутри.подробно]
                дальше = внутри.дальше
    уверенность = min(float(р["верно"]) for _, р in итоги)
    главное = ВИДЫ.get(всего.most_common(1)[0][0], ("кадры", ""))[0]
    return Находка(
        уровень="канальный",
        что=f"GSM Abis: кадры TRAU 16 кбит/с ({главное})"
            + (f", подканалов {len(итоги)}" if итоги[0][0] else ""),
        уверенность=уверенность,
        мера=f"синхрокомбинация 35 бит верна не меньше чем в {уверенность * 100:.0f} % кадров",
        подробно=подробно, дальше=дальше, вид_дальше="биты" if дальше is not None else "",
        свойства={"подканалы": [н for н, _ in итоги], "виды": dict(всего)})


def закодировать(c5: int, d: np.ndarray, кадров: int) -> np.ndarray:
    """Кадры TRAU (для проверок): синхрокомбинация, C1…C5 и биты между единицами слов подряд из ``d``."""
    итог = np.zeros((кадров, ДЛИНА), dtype=np.uint8)
    итог[:, ЕДИНИЦЫ] = 1
    итог[:, 17:22] = [(c5 >> (4 - i)) & 1 for i in range(5)]
    свободные = np.array([i for i in range(22, ДЛИНА) if i not in set(ЕДИНИЦЫ.tolist())])
    итог[:, свободные] = np.resize(np.asarray(d, dtype=np.uint8), (кадров, len(свободные)))
    return итог.reshape(-1)
