"""Выколотые (punctured) свёрточные коды: скорость k/(k+1), материнский код, шаблон.

Скорости 2/3, 3/4, 5/6, 7/8 обычно получают из материнского кода 1/2
выкалыванием: из 2k бит на k входных передаются k+1, остальные выбрасываются
по шаблону с периодом k. Таблицы шаблонов по памяти не вписываются —
шаблоны перебираются все: при k = 7 это 3432 варианта, и каждый проверяется
быстро, линейной алгеброй.

Проверка кандидата (материнский код, шаблон, начало периода): выколотый код
на окне из B периодов — линейный код; его проверочные векторы (ядро
порождающей матрицы окна) должны выполняться на окнах потока. У верного
кандидата доля нарушений мала (только от ошибок линии), у неверного —
около половины.
"""

from __future__ import annotations

import time
from functools import lru_cache
from itertools import combinations

import numpy as np

from . import gf2, svyortka

#: Материнские коды 1/2 с наибольшим свободным расстоянием, K = 3…9, восьмерично в записи
#: стандартов (старший бит — текущий вход; 171/133 — DVB-S, CCSDS). Во внутреннюю запись
#: переводятся зеркалом (svyortka.зеркало).
СТАНДАРТНЫЕ = ((0o171, 0o133, 7), (0o7, 0o5, 3), (0o17, 0o15, 4), (0o35, 0o23, 5),
               (0o75, 0o53, 6), (0o371, 0o247, 8), (0o753, 0o561, 9))
МАТЕРИНСКИЕ = tuple((svyortka.зеркало(a, K), svyortka.зеркало(b, K), K) for a, b, K in СТАНДАРТНЫЕ)
#: Окно — K − 1 + ЗАПАС периодов: на окне из B периодов у выколотого кода
#: B(k+1) выходов и Bk + K − 1 неизвестных входов (с состоянием), то есть
#: проверок B − K + 1.
ЗАПАС_ПЕРИОДОВ = 6
НАРУШЕНИЙ_ДО = 0.25


def _закодировать_окно(g1: int, g2: int, K: int, входов: int) -> np.ndarray:
    """Порождающая матрица материнского кода на окне: (входов + K − 1) × 2·входов.

    Строки — единичные входы, включая K − 1 бит «до окна» (состояние на
    входе окна неизвестно, поэтому оно тоже переменная).
    """
    всего = входов + K - 1
    G = np.zeros((всего, 2 * входов), dtype=np.uint8)
    for строка in range(всего):
        u = np.zeros(всего, dtype=np.uint8)
        u[строка] = 1
        регистр = 0
        for t in range(всего):
            регистр = ((регистр << 1) | int(u[t])) & ((1 << K) - 1)
            if t >= K - 1:
                шаг = t - (K - 1)
                G[строка, 2 * шаг] = bin(регистр & g1).count("1") & 1
                G[строка, 2 * шаг + 1] = bin(регистр & g2).count("1") & 1
    return G


@lru_cache(maxsize=64)
def _материнская(g1: int, g2: int, K: int, входов: int) -> np.ndarray:
    return _закодировать_окно(g1, g2, K, входов)


def проверки_кандидата(g1: int, g2: int, K: int, шаблон: tuple[int, ...], k: int
                       ) -> np.ndarray:
    """Проверочные векторы выколотого кода на окне из K − 1 + ЗАПАС периодов."""
    входов = k * (K - 1 + ЗАПАС_ПЕРИОДОВ)
    G = _материнская(g1, g2, K, входов)
    оставить = np.array([i for i in range(2 * входов) if шаблон[i % (2 * k)]])
    H = gf2.ядро(G[:, оставить])        # h: G · hᵀ = 0 → каждое окно кода их выполняет
    return лёгкие(H)


def лёгкие(H: np.ndarray, попыток: int = 24, сид: int = 1) -> np.ndarray:
    """Самые лёгкие проверки того же пространства (Ли — Брикелл).

    Базис ядра плотный — в каждой проверке половина окна, и при ошибках
    линии она нарушается почти в половине окон, вровень со случайной. У
    лёгкой проверки нарушений мало: вес ×доля ошибок. Ищем их случайными
    перестановками позиций и приведением к ступенчатому виду.
    """
    r, w = H.shape
    if r < 2:
        return H
    случай = np.random.default_rng(сид)
    лучшие = {}
    for _ in range(попыток):
        порядок = случай.permutation(w)
        приведённая, _ = gf2.привести(gf2.упаковать(H[:, порядок]), w)
        for строка in gf2.распаковать(приведённая, w):
            исходная = np.zeros(w, dtype=np.uint8)
            исходная[порядок] = строка
            лучшие.setdefault(np.packbits(исходная).tobytes(), исходная)
    все = np.array(list(лучшие.values()))
    return все[np.argsort(все.sum(axis=1), kind="stable")][:max(r, 4)]


def окна(биты: np.ndarray, n: int, начало: int, ширина: int, сколько: int = 3000
         ) -> np.ndarray:
    """Окна потока шириной ``ширина``, начинающиеся на границе периода (шаг n)."""
    ряд = биты[начало:]
    всего = min(сколько, (len(ряд) - ширина) // n)
    индексы = np.arange(всего)[:, None] * n + np.arange(ширина)[None, :]
    return ряд[индексы]


def шаблоны(k: int):
    """Все шаблоны периода k: 2k позиций (X1 Y1 X2 Y2 …), оставлено k + 1."""
    for оставленные in combinations(range(2 * k), k + 1):
        шаблон = [0] * (2 * k)
        for i in оставленные:
            шаблон[i] = 1
        yield tuple(шаблон)


def _нарушено(биты: np.ndarray, H: np.ndarray, n: int, начало: int, сколько: int
              ) -> float | None:
    W = окна(биты, n, начало, H.shape[1], сколько)
    if len(W) < 100:
        return None
    # Лучшая (наименее нарушаемая) из лёгких проверок: у верного кандидата
    # она лёгкая и нарушается редко, у неверного все — около половины. Проверка,
    # нарушенная почти всегда, — та же проверка при инвертированной ветви (CCSDS):
    # h·x = 1 вместо 0.
    доли = (((W.astype(np.int32) @ H.T.astype(np.int32)) & 1).mean(axis=0))
    return float(np.minimum(доли, 1 - доли).min())


def опознать(биты: np.ndarray, *, глубоко: bool = False, бюджет: float = 60.0) -> dict | None:
    """Перебор: скорость k/(k+1), материнский код, шаблон, начало периода.

    Порог — статистический: у неверного кандидата доля нарушений около 0,5
    с разбросом 1/(2√N) по N окнам, и лучшая из его проверок должна
    отстоять от половины на десять разбросов (окна перекрываются — берём
    N/4). Сперва отсев на 600 окнах, подтверждение — на 8000.

    По умолчанию — скорости 2/3 и 3/4 со всеми материнскими кодами и 5/6 с
    K = 7; ``глубоко`` — все скорости до 7/8 (3432 шаблона на код).
    """
    конец = time.monotonic() + бюджет
    план = [(2, МАТЕРИНСКИЕ), (3, МАТЕРИНСКИЕ), (5, МАТЕРИНСКИЕ[:1])]
    if глубоко:
        план = [(k, МАТЕРИНСКИЕ) for k in (2, 3, 5, 7, 4, 6)]
    for k, материнские in план:
        n = k + 1
        for g1, g2, K in материнские:
            for шаблон in шаблоны(k):
                if time.monotonic() > конец:
                    return None
                if not any(шаблон[0::2]) or not any(шаблон[1::2]):
                    continue                       # одна из ветвей выколота целиком
                H = проверки_кандидата(g1, g2, K, шаблон, k)
                if not len(H):
                    continue
                for начало in range(n):
                    грубо = _нарушено(биты, H, n, начало, 600)
                    if грубо is None:
                        return None
                    if грубо > 0.45:
                        continue
                    точно = _нарушено(биты, H, n, начало, 8000)
                    окон = min(8000, (len(биты) - начало - H.shape[1]) // n)
                    порог = 0.5 - 10 * np.sqrt(0.25 / max(1, окон / 4))
                    if точно is not None and точно < порог:
                        return {"k": k, "n": n, "g1": g1, "g2": g2, "K": K, "шаблон": шаблон,
                                "начало": начало, "нарушено": точно}
    return None


def выколоть(закодированное: np.ndarray, шаблон: tuple[int, ...]) -> np.ndarray:
    период = len(шаблон)
    целых = len(закодированное) - len(закодированное) % период
    маска = np.tile(np.array(шаблон, dtype=bool), целых // период)
    return закодированное[:целых][маска]


def вставить_стирания(принятое: np.ndarray, шаблон: tuple[int, ...]) -> tuple[np.ndarray, np.ndarray]:
    """Обратно к материнскому потоку: (биты, маска переданных)."""
    передано_за_период = sum(шаблон)
    периодов = len(принятое) // передано_за_период
    маска = np.tile(np.array(шаблон, dtype=bool), периодов)
    биты = np.zeros(len(маска), dtype=np.uint8)
    биты[маска] = принятое[:периодов * передано_за_период]
    return биты, маска


def найти(биты: np.ndarray, *, глубоко: bool = False, бюджет: float = 60.0):
    """Выколотый свёрточный код — находка для отчёта, данные — после Витерби со стираниями."""
    from . import kod, svyortka
    from .nahodka import Находка
    выборка = биты[:1 << 18]
    о = опознать(выборка, глубоко=глубоко, бюджет=бюджет)
    if о is None:
        return None
    k, n, g1, g2, K, шаблон = о["k"], о["n"], о["g1"], о["g2"], о["K"], о["шаблон"]
    # Декодируется больше, чем смотрелось при опознании: следующему уровню нужны кадры.
    передано = sum(шаблон)
    материнский, известно = вставить_стирания(
        биты[о["начало"]:о["начало"] + kod.шагов_декодера(K) * передано // k], шаблон)
    маски = kod.инверсии_ветвей(материнский, [g1, g2], K, известно)
    декодировано = {}
    for маска in маски:
        снятый = материнский ^ (np.resize(np.array(маска, dtype=np.uint8), len(материнский)) & известно)
        декодировано[маска] = svyortka.витерби(снятый, [g1, g2], K, известно)
    данные = декодировано[маски[0]]
    инверсия = kod.инверсия_словами(маски[0], [g1, g2]) if len(маски) == 1 else ""
    x = "".join(map(str, шаблон[0::2]))
    y = "".join(map(str, шаблон[1::2]))
    подробно = [
        f"на {k} входных бит материнский код 1/2 даёт {2 * k}, передаются {n} по шаблону "
        f"X {x} / Y {y} (1 — передан, 0 — выколот; X — ветвь {svyortka.зеркало(g1, K):o}, "
        f"Y — ветвь {svyortka.зеркало(g2, K):o})",
        f"начало периода — бит {о['начало']} потока",
        "шаблоны не взяты из таблицы, а перебраны все — найденный проверен проверками "
        "выколотого кода на окнах потока",
        f"декодер Витерби со стираниями на месте выколотых бит: {len(данные)} бит данных",
    ] + ([инверсия] if инверсия else [])
    if len(маски) > 1:
        подробно.append(
            "инверсия ветвей по коду неразличима: инвертированная на переданных местах ветвь сама — "
            "кодовая последовательность выколотого кода, и перекодированное расходится с принятым "
            "одинаково; декодированное у вариантов отличается на периодический узор — верный "
            "выбирает проверка ниже (FCS, цикл): " + "; ".join(
                kod.инверсия_словами(м, [g1, g2]).split(" — ")[0] or "без инверсии" for м in маски))
    return Находка(
        уровень="код",
        что=f"выколотый свёрточный код скорости {k}/{n}: материнский K={K}, {svyortka.запись([g1, g2], K)}, "
            f"шаблон X {x} / Y {y}" + (f"; {инверсия.split(' — ')[0]}" if инверсия else ""),
        уверенность=max(0.0, min(1.0, (0.5 - о["нарушено"]) / 0.4)),
        мера=f"лучшая проверка кода нарушена в {о['нарушено'] * 100:.1f} % окон (у неверного "
             f"шаблона — около 50 %)",
        подробно=подробно,
        дальше=({(kod.инверсия_словами(м, [g1, g2]).split(" — ")[0] or "без инверсии ветвей"): д
                 for м, д in декодировано.items()} if len(маски) > 1 else данные),
        вид_дальше="варианты" if len(маски) > 1 else "биты", сверка=1 - о["нарушено"])
