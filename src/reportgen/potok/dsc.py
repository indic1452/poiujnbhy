def знак(биты: np.ndarray) -> int:
    """10 бит → знак 0–127 или −1, если число нулей не сходится с проверочными битами."""
    инфо = sum(int(биты[i]) << i for i in range(7))
    проверка = int(биты[7]) * 4 + int(биты[8]) * 2 + int(биты[9])
    return инфо if 7 - bin(инфо).count("1") == проверка else -1


def в_биты(s: int) -> list[int]:
    нули = 7 - bin(s).count("1")
    return [(s >> i) & 1 for i in range(7)] + [(нули >> 2) & 1, (нули >> 1) & 1, нули & 1]


def знаки_везде(биты: np.ndarray) -> np.ndarray:
    """Знак, начинающийся с каждого бита (−1 — негодный); для поиска фазирования при любом сдвиге.

    Сдвинутыми срезами (int16), без матрицы окон: выборка автомата — миллионы бит."""
    n = len(биты) - 9
    if n <= 0:
        return np.zeros(0, dtype=np.int16)
    б = биты.astype(np.int16)
    инфо = np.zeros(n, dtype=np.int16)
    единиц = np.zeros(n, dtype=np.int16)
    for i in range(7):
        инфо |= б[i:i + n] << i
        единиц += б[i:i + n]
    проверка = (б[7:7 + n] << 2) | (б[8:8 + n] << 1) | б[9:9 + n]
    return np.where(7 - единиц == проверка, инфо, -1).astype(np.int16)


def _начала(зн: np.ndarray) -> list[int]:
    """Места первого знака сообщения (бит), где фазирование достигнуто по правилу M.493."""
    n = len(зн)
    места = [(-12 + 2 * i, ФАЗА_DX, False) for i in range(6)]
    места += [(-11 + 2 * i, rx, True) for i, rx in enumerate(ФАЗА_RX[:6])] + [(1, 105, True), (3, 104, True)]
    всего = np.zeros(n, dtype=np.int16)
    rx = np.zeros(n, dtype=np.int16)
    for место, ждём, это_rx in места:
        с = 10 * место
        сдвинуто = np.full(n, -1, dtype=np.int16)
        if с >= 0:
            сдвинуто[:n - с] = зн[с:]
        else:
            сдвинуто[-с:] = зн[:n + с]
        совпало = (сдвинуто == ждём).astype(np.int16)
        всего += совпало
        if это_rx:
            rx += совпало
    return np.flatnonzero((всего >= 3) & (rx >= 1)).tolist()


def цифры(знаки: list[int]) -> str:
    return "".join(f"{s:02d}" if 0 <= s <= 99 else "??" for s in знаки)


def mmsi(знаки: list[int]) -> str:
    ц = цифры(знаки)
    return ц[:9] if ц.endswith("0") else f"{ц[:9]}-{ц[9]}"


def место_судна(знаки: list[int]) -> str:
    """10 цифр: четверть (0 — СВ, 1 — СЗ, 2 — ЮВ, 3 — ЮЗ), широта ГГММ, долгота ГГГММ; 9999999999 — нет."""
    ц = цифры(знаки)
    if ц == "9999999999":
        return "место не указано"
    ns, ew = {"0": ("N", "E"), "1": ("N", "W"), "2": ("S", "E"), "3": ("S", "W")}.get(ц[0], ("?", "?"))
    return f"{ц[1:3]}°{ц[3:5]}′{ns} {ц[5:8]}°{ц[8:10]}′{ew}"


def частота(знаки: list[int], i: int):
    """Частота или канал с места i: (текст, следующее место); 126 126 126 — сведений нет."""
    if знаки[i:i + 3] == [126, 126, 126]:
        return "нет сведений", i + 3
    ц = цифры(знаки[i:i + 3])
    if ц[:1] == "4":
        ц, i = цифры(знаки[i:i + 4]), i + 4
        return f"{int(ц[1:]) * 10 / 1000:.2f} кГц", i
    i += 3
    if ц[:1] in ("0", "1", "2"):
        return f"{int(ц) * 100 / 1000:.1f} кГц", i
    if ц[:1] == "3":
        return f"канал ПВ/КВ {ц[1:]}", i
    if ц[:1] == "9":
        return f"канал УКВ {ц[2:]}", i
    return f"частота {ц}", i


@dataclass
class Вызов:
    бит: int
    инверсия: bool
    знаки: list[int]
    исправлено: int = 0           # знаков взято из RX: DX негоден
    по_ecc: int = 0               # знаков взято из RX по ECC: DX годен, но неверен
    поля: dict[str, str] = field(default_factory=dict)
    годный: bool = False


def разобрать(знаки: list[int]) -> dict[str, str]:
    """Поля сообщения (порядок M.493, как у SDRangel); ``знаки`` — от первого указателя формата до ECC."""
    ф = знаки[0]
    п: dict[str, str] = {"формат": ФОРМАТЫ.get(ф, str(ф))}
    i = 2
    категория = 112 if ф == 112 else None
    if ф != 112:
        if ф != 116:
            адрес = знаки[i:i + 5]
            i += 5
            if ф == 102:
                ц = цифры(адрес)
                # четверть (0 — СВ, 1 — СЗ, 2 — ЮВ, 3 — ЮЗ), угол: широта ГГ, долгота ГГГ; размер: Δφ ГГ, Δλ ГГ
                п["район"] = (f"угол {ц[1:3]}°{'N' if ц[0] in '01' else 'S'} {ц[3:6]}°{'E' if ц[0] in '02' else 'W'}, "
                              f"размер {ц[6:8]}° × {ц[8:10]}°")
            else:
                п["кому"] = mmsi(адрес)
        категория = знаки[i]
        i += 1
        п["категория"] = КАТЕГОРИИ.get(категория, str(категория))
    п["от"] = mmsi(знаки[i:i + 5])
    i += 5
    if ф != 112:
        п["команда 1"] = КОМАНДЫ_1.get(знаки[i], str(знаки[i]))
        i += 1
        if категория != 112:
            п["команда 2"] = КОМАНДЫ_2.get(знаки[i], str(знаки[i]))
            i += 1
    if категория == 112 and ф != 112:
        п["терпящий бедствие"] = mmsi(знаки[i:i + 5])
        i += 5
    if ф == 112:
        п["бедствие"] = БЕДСТВИЯ.get(знаки[i], str(знаки[i]))
        п["место"] = место_судна(знаки[i + 1:i + 6])
        i += 6
    elif категория != 112 and i < len(знаки) - 2:
        if знаки[i] == 55:                                 # 55 — вместо частот место: 5 знаков за ним
            п["место"] = место_судна(знаки[i + 1:i + 6])
            i += 6
        else:
            п["частота 1"], i = частота(знаки, i)
            if ф != 123 and i < len(знаки) - 2:
                п["частота 2"], i = частота(знаки, i)
    if категория == 112 and i + 3 <= len(знаки) - 2:
        время = цифры(знаки[i:i + 2])
        п["время"] = "не указано" if время == "8888" else f"{время[:2]}:{время[2:]} UTC"
        п["связь потом"] = КОМАНДЫ_1.get(знаки[i + 2], str(знаки[i + 2]))
        i += 3
    if i < len(знаки) - 2:
        п["ещё"] = " ".join(str(s) for s in знаки[i:-2])
    п["конец"] = КОНЦЫ.get(знаки[-2], str(знаки[-2]))
    return п


def ecc(знаки: list[int]) -> int:
    """ECC: исключающее ИЛИ знаков от указателя формата (один раз) до конца включительно."""
    итог = 0
    for s in знаки[1:]:
        итог ^= s
    return итог


def _проверен(в: Вызов) -> bool:
    з = в.знаки
    if -1 in з or з[0] != з[1] or з[0] not in ФОРМАТЫ or з[-2] not in КОНЦЫ or ecc(з[:-1]) != з[-1]:
        return False
    try:
        в.поля = разобрать(з)
    except IndexError:                                    # поля не помещаются в сообщение
        return False
    return True


def _годный(в: Вызов, расхождения: list[tuple]) -> Вызов | None:
    """Вызов как есть или, если ECC не сошёлся, с заменой части DX на несовпавшие RX."""
    if _проверен(в):
        return в
    if len(расхождения) > РАСХОЖДЕНИЙ_ДО:
        return None
    for маска in range(1, 1 << len(расхождения)):
        з = list(в.знаки)
        for б, (k, rx) in enumerate(расхождения):
            if маска >> б & 1:
                з[k] = rx
        вариант = Вызов(в.бит, в.инверсия, з, в.исправлено, bin(маска).count("1"))
        if _проверен(вариант):
            return вариант
    return None


def вызовы(биты: np.ndarray) -> list[Вызов]:
    биты = np.asarray(биты, dtype=np.uint8)
    итог: list[Вызов] = []
    for инверсия in (False, True):
        зн = знаки_везде(1 - биты if инверсия else биты)
        # фазирование на своих местах только у одного начала: сдвиг на место (10 бит) или пару мест
        # сдвигает все RX (111 → 110 …), и RX не совпадает ни один — повторно один вызов не найти
        for м in _начала(зн):
            сообщение, исправлено, расхождения = [], 0, []
            for k in range(ДЛИНА_ДО):
                dx_место, rx_место = м + 20 * k, м + 20 * k + 10 * СДВИГ
                if rx_место >= len(зн):
                    break
                dx, rx = int(зн[dx_место]), int(зн[rx_место])
                исправлено += dx < 0                                   # если негоден и RX — вызов отброшен
                if 0 <= dx != rx >= 0:
                    расхождения.append((k, rx))
                сообщение.append(dx if dx >= 0 else rx)
                if k >= 1 and сообщение[-2] in КОНЦЫ:                  # за концом — ECC
                    break
            if len(сообщение) < 2 or сообщение[-2] not in КОНЦЫ:
                continue
            в = _годный(Вызов(м, инверсия, сообщение, исправлено), расхождения)
            if в is not None:
                итог.append(в)
    return sorted(итог, key=lambda в: в.бит)


def описание(в: Вызов) -> str:
    п = в.поля
    части = [п["формат"]]
    for ключ in ("категория", "от", "кому", "район", "терпящий бедствие", "бедствие", "место", "время",
                 "команда 1", "команда 2", "частота 1", "частота 2", "связь потом", "ещё", "конец"):
        if ключ in п:
            части.append(f"{ключ}: {п[ключ]}")
    return "; ".join(части)


def найти(биты: np.ndarray) -> Находка | None:
    вв = вызовы(биты)
    if not вв:
        return None
    форматы = Counter(в.поля["формат"] for в in вв)
    от = Counter(в.поля["от"] for в in вв)
    подробно = [f"вызовов с верным ECC: {len(вв)}" + (" — полярность обратная" if all(в.инверсия for в in вв) else ""),
                "виды: " + ", ".join(f"{ф} × {к}" for ф, к in форматы.most_common()),
                "станции (MMSI): " + ", ".join(f"{м} × {к}" for м, к in от.most_common(12)),
                f"знаков взято из повтора (RX): {sum(в.исправлено for в in вв)} — DX негоден, "
                f"{sum(в.по_ecc for в in вв)} — DX годен, но неверен (по ECC)"]
    подробно += [описание(в) for в in вв[:30]]
    return Находка(
        уровень="канальный", что="ЦИВ (DSC, ITU-R M.493): вызовы морской подвижной службы",
        уверенность=1.0, мера=f"{len(вв)} вызовов: фазирование, повтор DX/RX, верный ECC",
        подробно=подробно, свойства={"вызовов": len(вв), "станций": len(от)})


def закодировать(сообщение: list[int], точки: int = 20) -> np.ndarray:
    """Сообщение (от указателя формата до конца, без ECC) → биты: точки, фазирование, DX/RX, ECC."""
    полное = list(сообщение) + [ecc(сообщение)]
    dx = [ФАЗА_DX] * 6 + полное + [сообщение[-1]] * 2
    rx = list(ФАЗА_RX) + полное
    места = []
    for d, r in zip(dx, rx, strict=False):
        места += [d, r]
    биты = [1, 0] * (точки // 2)
    for s in места:
        биты += в_биты(s)
    return np.array(биты, dtype=np.uint8)
