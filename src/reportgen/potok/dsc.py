"""ЦИВ (DSC, ITU-R M.493): вызовы морской подвижной службы — знаки 10 бит, фазирование, повтор DX/RX, ECC.

Как у SDRangel (sdrbase/util/dsc.cpp, plugins/channelrx/demoddsc/dscdemodsink.cpp) и KiwiSDR
(web/extensions/FSK/DSC.js; место вместо частот — знак 55 и пять знаков места за ним, как у KiwiSDR):
- знак — 10 бит: 7 информационных младшим вперёд и 3 проверочных — число нулей среди информационных,
  старшим вперёд (125 = 1011111001); у обратной полярности знаки тоже годны (127 − s), поэтому полярность
  узнаётся только по фазированию;
- места DX и RX чередуются; фазирование: DX — 125 (шесть раз), RX — 111, 110, 109, 108, 107, 106, затем
  105, 104 уже между первыми знаками сообщения; повтор знака (RX) — через пять мест после DX;
  фазирование достигнуто, если совпали на своих местах два DX и один RX, один DX и два RX или три RX;
- сообщение: указатель формата дважды, адрес, категория, свой номер (MMSI), команды, частоты или место,
  конец (117 — нужно подтверждение, 122 — подтверждение, 127 — прочее) и ECC — исключающее ИЛИ знаков
  от указателя формата (один раз) до конца включительно;
- знак выбирается из DX, если он годен, иначе из RX; если ECC не сошёлся, перебираются места, где DX и RX
  годны, но различны (до четырёх), — годный вариант с верным ECC принимается.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field

import numpy as np

from .nahodka import Находка

ФАЗА_DX, ФАЗА_RX = 125, (111, 110, 109, 108, 107, 106, 105, 104)
СДВИГ = 5
ДЛИНА_ДО = 40                                   # знаков в сообщении — больше не бывает
РАСХОЖДЕНИЙ_ДО = 4                              # перебор DX/RX при неверном ECC — не больше 2⁴ вариантов

