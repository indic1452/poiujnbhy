# -*- coding: utf-8 -*-
"""Турбокод (PCCC) вслепую: ветви, длина блока, перестановка перемежителя.

Параллельный турбокод скорости 1/3 передаёт на каждый бит тройку: данные
u, проверку p1 первого рекурсивного систематического кодера (RSC) по u и
проверку p2 второго — по перемежённым данным u∘π. Опознание по шагам:

1. **Ветви.** Между u и p1 есть проверочная связь RSC (g_прям·u = g_обр·p1),
   она находится как у свёрточного кода; с p2 связи нет — это и отличает
   турбокод от свёрточного 1/3.
2. **Длина блока.** Каждый блок кончается хвостом (обнуление регистров
   кодеров), и связь u–p1 на стыке блоков рвётся. Нарушения связи идут
   с периодом блока — он находится по спектру.
3. **Перемежитель.** Из p2 обратным рекурсивным расчётом (второй кодер тот
   же RSC и стартует с нуля) восстанавливаются перемежённые данные u∘π. Для
   каждой позиции i блока «подпись» — её биты по всем блокам; позиция j
   исходных данных с той же подписью и есть π(i). Нужны десятки блоков.
4. **Вид перестановки.** Проверяется квадратичная QPP π(i) = f1·i + f2·i²
   (mod K) — перемежитель LTE; коэффициенты подбираются по самой
   перестановке, таблица стандарта не нужна.
"""

from __future__ import annotations

from typing import Dict, List, Tuple

import numpy as np

from . import svyortka


def связь_u_p1(u: np.ndarray, p1: np.ndarray, обратная: int, прямая: int) -> np.ndarray:
    """Нарушение связи g_прям·u + g_обр·p1 = 0 в каждой позиции (0/1)."""
    def свёртка(ряд: np.ndarray, g: int) -> np.ndarray:
        итог = np.zeros(len(ряд), dtype=np.uint8)
        степень = g.bit_length() - 1
        for i in range(степень + 1):
            if g >> (степень - i) & 1:        # старший бит — самый старый
                итог[степень - i:] ^= ряд[:len(ряд) - (степень - i)] if степень - i else ряд
        return итог
    return свёртка(u, прямая) ^ свёртка(p1, обратная)


def длина_блока(нарушения: np.ndarray, до: int = 8192) -> Tuple[int, float] | None:
    """Период всплесков нарушений: (период в шагах, сила пика в сигмах)."""
    x = нарушения.astype(np.float64) - нарушения.mean()
    if not x.any():
        return None
    n = len(x)
    размер = 1 << int(np.ceil(np.log2(2 * n)))
    спектр = np.fft.rfft(x, размер)
    r = np.fft.irfft(спектр * np.conj(спектр), размер)[:min(до, n // 4) + 1]
    r /= r[0]
    шум = 1 / np.sqrt(n)
    окно = r[8:]
    лучший = int(np.argmax(окно)) + 8
    if r[лучший] < 8 * шум:
        return None
    # Основной период — наименьший с пиком не слабее 60 % лучшего.
    for p in range(8, лучший + 1):
        if r[p] >= 0.6 * r[лучший]:
            return p, float(r[p] / шум)
    return лучший, float(r[лучший] / шум)


def восстановить_перемежённые(p2: np.ndarray, обратная: int, прямая: int, K: int
                              ) -> np.ndarray:
    """u∘π из проверки p2 второго RSC, стартующего с нулевого состояния.

    p = чётность(r & прямая), u = чётность(r & обратная), r = (s << 1) | a.
    Младший бит прямой — единица, поэтому a находится из p.
    """
    память = (1 << (K - 1)) - 1
    s = 0
    итог = np.zeros(len(p2), dtype=np.uint8)
    for t, p in enumerate(p2):
        a = int(p) ^ (bin((s << 1) & прямая).count("1") & 1)
        r = (s << 1) | a
        итог[t] = bin(r & обратная).count("1") & 1
        s = r & память
    return итог


def _счёт_единиц(x: np.ndarray) -> np.ndarray:
    """Число единиц в каждом uint64 (побайтно по таблице)."""
    таблица = np.array([bin(i).count("1") for i in range(256)], dtype=np.uint8)
    return таблица[x.view(np.uint8)].reshape(*x.shape, 8).sum(axis=-1)


def _подписи(биты: np.ndarray) -> np.ndarray:
    """Столбцы (блоки × K) → подписи uint64 по до 64 блокам."""
    B = min(len(биты), 64)
    веса = (np.uint64(1) << np.arange(B, dtype=np.uint64))
    return np.bitwise_or.reduce(биты[:B].T.astype(np.uint64) * веса, axis=1)


def _сопоставить(подписи_pi: np.ndarray, маски: np.ndarray, подписи_u: np.ndarray
                 ) -> np.ndarray:
    """Для каждой i — j с ближайшей подписью по известным битам, или −1."""
    K = len(подписи_pi)
    π = np.full(K, -1, dtype=np.int64)
    for начало in range(0, K, 512):
        кусок = подписи_pi[начало:начало + 512]
        маска = маски[начало:начало + 512]
        известно = np.maximum(1, _счёт_единиц(маска))
        расстояния = _счёт_единиц((кусок[:, None] ^ подписи_u[None, :]) & маска[:, None])
        доли = расстояния / известно[:, None]
        порядок = np.argsort(доли, axis=1)[:, :2]
        ближайшие = np.take_along_axis(доли, порядок, axis=1)
        # Ближайшая из сотен чужих подписей отстоит на 15–20 бит из 64, а не на
        # половину: порог — относительный, вторая вдвое дальше первой.
        годны = (ближайшие[:, 0] * 2 + 0.06 <= ближайшие[:, 1]) & (известно >= 12)
        π[начало:начало + len(кусок)] = np.where(годны, порядок[:, 0], -1)
    return π


def перестановка(u: np.ndarray, u_pi: np.ndarray, раундов: int = 4
                 ) -> Tuple[np.ndarray, float]:
    """π по подписям: u, u_pi — блоки × K. Возвращает π и долю найденных позиций.

    Подпись позиции — её биты по блокам (до 64). Позиции i перемежённых
    данных сопоставляется позиция j исходных с ближайшей подписью. Ошибка в
    p2 портит восстановленные u∘π от места ошибки до конца блока, поэтому
    раунды: по уже найденным позициям предсказываем u∘π, в каждом блоке
    находим первое расхождение и дальше этот блок в сравнении не участвует.
    """
    B = min(len(u), 64)
    u, u_pi = u[:B], u_pi[:B]
    K = u.shape[1]
    подписи_u = _подписи(u)
    годен = np.ones((B, K), dtype=bool)
    π = np.full(K, -1, dtype=np.int64)
    for _ in range(раундов):
        маски = _подписи(годен.astype(np.uint8))
        π = _сопоставить(_подписи(u_pi), маски, подписи_u)
        известны = np.flatnonzero(π >= 0)
        if not len(известны):
            break
        предсказано = u[:, π[известны]]
        расходится = предсказано != u_pi[:, известны]
        новый = np.ones((B, K), dtype=bool)
        # Ошибка в p2 даёт расхождения примерно в половине позиций до конца
        # блока; одиночное расхождение — это ошибка в самих данных или неверно
        # сопоставленная позиция, блок из-за неё не выбрасываем.
        окно = np.ones(8, dtype=np.int32)
        for блок in range(B):
            подряд = np.convolve(расходится[блок].astype(np.int32), окно)[7:]
            места = np.flatnonzero(подряд >= 3)
            if len(места):
                новый[блок, известны[места[0]]:] = False
        if np.array_equal(новый, годен):
            break
        годен = новый
    return π, float((π >= 0).mean())


def qpp(π: np.ndarray, *, согласие: float = 0.97) -> Tuple[int, int, float] | None:
    """QPP π(i) = (f1·i + f2·i²) mod K по найденным позициям (часть может быть −1).

    Перебираются f2 = 0…K−1; f1 берётся из позиции i = 1 (если она найдена),
    иначе из первой найденной нечётной i, для которой i обратимо по модулю K.
    Засчитывается, если формула совпала с найденной π в доле ``согласие``
    позиций. Возвращает (f1, f2, доля совпадений).
    """
    K = len(π)
    известны = np.flatnonzero(π >= 0)
    if len(известны) < max(8, K // 2):
        return None
    опорная = next((int(i) for i in известны if i and np.gcd(int(i), K) == 1), None)
    if опорная is None:
        return None
    обратный = pow(опорная, -1, K)
    i = известны.astype(np.int64)
    цель = π[известны]
    for f2 in range(K):
        f1 = ((int(π[опорная]) - f2 * опорная * опорная) * обратный) % K
        совпало = float(np.mean((f1 * i + f2 * i * i) % K == цель))
        if совпало >= согласие:
            return f1, f2, совпало
    return None


def _центры(нарушения: np.ndarray, период: int, сколько: int = 2) -> List[int]:
    """Шаги цикла, где связь рвётся чаще всего (хвост и стык блоков)."""
    циклов = len(нарушения) // период
    сложено = нарушения[:циклов * период].reshape(циклов, период).mean(axis=0)
    # Сглаживаем окном в хвост: хвост — полоса, а не одна точка.
    окно = np.convolve(np.concatenate([сложено, сложено[:7]]), np.ones(8), "valid")[:период]
    return [int(ц) for ц in np.argsort(-окно)[:сколько]]


def вскрыть(тройки: np.ndarray, обратная: int, прямая: int, K: int, период: int,
            нарушения: np.ndarray, хвост_до: int = 8) -> Dict | None:
    """Перебор разметки блока: где перестановка восстанавливается однозначно.

    Пик спектра при ошибках линии размыт, поэтому пробуются и соседние
    периоды, и начала блока около полосы нарушений, и длины хвоста 0…8
    шагов. Решает перемежитель: при неверной разметке перестановка не
    складывается (повторы, выход за длину блока, мало сопоставленных).
    """
    кандидаты: List[Dict] = []
    for период_ in (период, период - 1, период + 1, период - 2, период + 2):
        блоков = len(тройки) // период_ - 1
        if блоков < 16:
            continue
        начала = sorted({(ц + d) % период_ for ц in _центры(нарушения, период_)
                         for d in range(-4, хвост_до + 12)})
        for начало in начала:
            блоки = тройки[начало:начало + блоков * период_].reshape(блоков, период_, 3)
            u_pi_полные = np.array([восстановить_перемежённые(блок[:, 2], обратная, прямая, K)
                                    for блок in блоки[:64]])
            for хвост in range(0, хвост_до + 1):
                длина = период_ - хвост
                u = блоки[:64, :длина, 0]
                π, доля = перестановка(u, u_pi_полные[:, :длина])
                найдено = int((π >= 0).sum())
                однозначна = len(set(π[π >= 0].tolist())) == найдено
                в_диапазоне = bool(np.all(π[π >= 0] < длина))
                # При верной длине образ π — ровно 0…длина−1: лишняя позиция
                # хвоста не сопоставится, недостающая — выпадет.
                ключ = (однозначна and в_диапазоне, найдено - (длина - найдено))
                кандидаты.append({"начало": начало, "хвост": хвост, "длина": длина, "π": π,
                                  "доля": доля, "блоков": блоков, "ключ": ключ,
                                  "период": период_})
    if not кандидаты:
        return None
    кандидаты.sort(key=lambda к: к["ключ"], reverse=True)
    лучшее = кандидаты[0]
    найдено = None
    # Формула QPP, сошедшаяся с найденными позициями, — сильнее счёта
    # позиций: при ошибках линии верная разметка может немного уступить
    # соседней, но формула сойдётся только на верной.
    for кандидат in кандидаты[:8]:
        if кандидат["доля"] < 0.5:
            break
        найдено = qpp(кандидат["π"])
        if найдено is not None:
            лучшее = кандидат
            break
    if лучшее["доля"] < 0.5:
        return лучшее
    лучшее["qpp"] = найдено
    if найдено is not None:
        # Формула дополняет позиции, не сопоставленные из-за ошибок.
        f1, f2, _ = найдено
        i = np.arange(лучшее["длина"], dtype=np.int64)
        лучшее["π"] = (f1 * i + f2 * i * i) % лучшее["длина"]
    return лучшее


def _решётка(обратная: int, прямая: int, K: int) -> Tuple[np.ndarray, np.ndarray]:
    """Для состояния s и входа u: следующее состояние и проверочный бит RSC."""
    состояний = 1 << (K - 1)
    следующее = np.zeros((состояний, 2), dtype=np.int64)
    проверка = np.zeros((состояний, 2), dtype=np.int64)
    for s in range(состояний):
        for u in (0, 1):
            a = u ^ (bin((s << 1) & обратная).count("1") & 1)
            r = (s << 1) | a
            следующее[s, u] = r & (состояний - 1)
            проверка[s, u] = bin(r & прямая).count("1") & 1
    return следующее, проверка


def _bcjr(L_сист: np.ndarray, L_пров: np.ndarray, L_апр: np.ndarray,
          следующее: np.ndarray, проверка: np.ndarray) -> np.ndarray:
    """Max-log-MAP по блокам (блоки × шаги): апостериорные LLR данных.

    LLR > 0 — бит 0. Начало — нулевое состояние, конец — любое (хвост
    не используется: так проще и почти не хуже).
    """
    B, T = L_сист.shape
    S = следующее.shape[0]
    x_u = np.array([1.0, -1.0])                      # u = 0 → +1
    x_p = 1.0 - 2.0 * проверка                        # S × 2
    НЕТ = -1e9
    α = np.full((T + 1, B, S), НЕТ)
    α[0, :, 0] = 0.0
    γ = np.empty((T, B, S, 2))
    for t in range(T):
        γ[t] = (0.5 * (L_сист[:, t] + L_апр[:, t])[:, None, None] * x_u[None, None, :]
                + 0.5 * L_пров[:, t][:, None, None] * x_p[None, :, :])
    for t in range(T):
        кандидаты = α[t][:, :, None] + γ[t]           # B × S × 2
        новое = np.full((B, S), НЕТ)
        for u in (0, 1):
            np.maximum.at(новое, (slice(None), следующее[:, u]), кандидаты[:, :, u])
        α[t + 1] = новое - новое.max(axis=1, keepdims=True)
    β = np.zeros((B, S))
    L = np.zeros((B, T))
    for t in range(T - 1, -1, -1):
        далее = β[:, следующее]                       # B × S × 2
        полные = α[t][:, :, None] + γ[t] + далее
        L[:, t] = полные[:, :, 0].max(axis=1) - полные[:, :, 1].max(axis=1)
        β = (γ[t] + далее).max(axis=2)
        β -= β.max(axis=1, keepdims=True)
    return L


def декодировать(u: np.ndarray, p1: np.ndarray, p2: np.ndarray, π: np.ndarray,
                 обратная: int, прямая: int, K: int, доля_ошибок: float,
                 итераций: int = 8) -> np.ndarray:
    """Итеративное турбодекодирование жёстких решений: исправленные данные (блоки × длина)."""
    p = min(max(доля_ошибок, 1e-4), 0.3)
    Lc = np.log((1 - p) / p)
    L_u = Lc * (1 - 2.0 * u)
    L_p1 = Lc * (1 - 2.0 * p1)
    L_p2 = Lc * (1 - 2.0 * p2)
    следующее, проверка = _решётка(обратная, прямая, K)
    обратная_π = np.argsort(π)
    L_апр = np.zeros_like(L_u)
    for _ in range(итераций):
        L1 = _bcjr(L_u, L_p1, L_апр, следующее, проверка)
        внешняя1 = L1 - L_u - L_апр
        L2 = _bcjr(L_u[:, π], L_p2, внешняя1[:, π], следующее, проверка)
        внешняя2 = L2 - L_u[:, π] - внешняя1[:, π]
        L_апр = внешняя2[:, обратная_π]
    L = L_u + L_апр + внешняя1
    return (L < 0).astype(np.uint8)


def найти(биты: np.ndarray):
    """Турбокод 1/3: ветви, блок, перемежитель (перестановка и QPP), декодирование."""
    from .nahodka import Находка
    о = svyortka.опознать(биты[:1 << 18])
    if о is None or о["n"] != 3 or len(о["несвязанные"]) != 1:
        return None
    связанная = next(j for j in (1, 2) if j not in о["несвязанные"])
    p2_ветвь = о["несвязанные"][0]
    тройки = биты[о["сдвиг"]:]
    тройки = тройки[:len(тройки) // 3 * 3].reshape(-1, 3)
    K = о["K"]
    лучшее = None
    # Какая из связанных ветвей — данные, по связи не сказать: пробуем обе.
    for u_ветвь, p1_ветвь in ((0, связанная), (связанная, 0)):
        # В равносильном несистематическом виде u = g_обр·a, p1 = g_прям·a:
        # многочлен ветви данных — обратная связь RSC, ветви проверки — прямая.
        обратная = о["многочлены"][u_ветвь]
        прямая = о["многочлены"][p1_ветвь]
        упорядочено = тройки[:, [u_ветвь, p1_ветвь, p2_ветвь]]
        нарушения = связь_u_p1(упорядочено[:, 0], упорядочено[:, 1], обратная, прямая)
        период = длина_блока(нарушения)
        if период is None:
            continue
        вскрыто = вскрыть(упорядочено, обратная, прямая, K, период[0], нарушения)
        if вскрыто is not None and (лучшее is None or вскрыто["доля"] > лучшее[0]["доля"]):
            лучшее = (вскрыто, упорядочено, обратная, прямая, u_ветвь, p1_ветвь)
    if лучшее is None or лучшее[0]["доля"] < 0.5:
        return None
    в, упорядочено, обратная, прямая, u_ветвь, p1_ветвь = лучшее
    длина, период, начало = в["длина"], в["период"], в["начало"]
    блоков = (len(упорядочено) - начало) // период
    блоки = упорядочено[начало:начало + блоков * период].reshape(блоков, период, 3)[:, :длина]
    подробно = [
        f"три ветви: данные — ветвь {u_ветвь}, проверка первого кодера — ветвь "
        f"{p1_ветвь}, второго — ветвь {p2_ветвь} "
        f"(в естественном порядке данных она ни с чем не связана — считается по "
        f"перемежённым данным)",
        f"составляющий код — рекурсивный систематический, K = {K}: обратная связь "
        f"{обратная:o}, прямая {прямая:o} (восьмерично)",
        f"блок: {длина} бит данных + хвост {в['хвост']} шагов, период {период} троек; "
        f"начало блока — тройка {начало}; блоков в выборке {блоков}",
        f"перестановка перемежителя восстановлена по данным для "
        f"{в['доля'] * 100:.1f} % позиций блока",
    ]
