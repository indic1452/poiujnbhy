"""Линейная алгебра над GF(2) на упакованных битах: ранг, ядро, приведение.

Строка матрицы — массив uint64 (64 столбца на слово). Исключение Гаусса
идёт по столбцам: для каждого столбца ищется строка с единицей, и ею
гасятся единицы этого столбца во всех остальных строках — одной векторной
операцией на все строки сразу. Этого хватает на матрицы в тысячи столбцов
за секунды — ранговый метод поиска кода длиной до нескольких тысяч бит
(LDPC, двоичный образ кодов Рида — Соломона и БЧХ).
"""

from __future__ import annotations

import numpy as np


def упаковать(биты: np.ndarray) -> np.ndarray:
    """Строки из 0/1 (M × L) → M × ⌈L/64⌉ uint64; столбец j — бит j % 64 слова j // 64."""
    M, L = биты.shape
    слов = (L + 63) // 64
    дополнено = np.zeros((M, слов * 64), dtype=np.uint8)
    дополнено[:, :L] = биты
    # little-endian по битам: бит j слова — столбец 64·w + j.
    байты = np.packbits(дополнено.reshape(M, слов, 8, 8)[:, :, :, ::-1], axis=-1)
    return байты.reshape(M, слов * 8).view(np.uint64).reshape(M, слов)


def распаковать(строки: np.ndarray, L: int) -> np.ndarray:
    M, слов = строки.shape
    байты = строки.view(np.uint8).reshape(M, слов, 8, 1)
    биты = np.unpackbits(байты, axis=-1)[:, :, :, ::-1].reshape(M, слов * 64)
    return биты[:, :L]


def привести(строки: np.ndarray, L: int) -> tuple[np.ndarray, list[int]]:
    """Ступенчатый вид (приведённый): матрица и опорные столбцы. Меняет копию."""
    a = строки.copy()
    M = len(a)
    опорные: list[int] = []
    r = 0
    for j in range(L):
        if r >= M:
            break
        w, b = divmod(j, 64)
        маска = np.uint64(1) << np.uint64(b)
        столбец = (a[r:, w] & маска) != 0
        есть = np.flatnonzero(столбец)
        if not len(есть):
            continue
        p = r + int(есть[0])
        if p != r:
            a[[r, p]] = a[[p, r]]
        с_единицей = (a[:, w] & маска) != 0
        с_единицей[r] = False
        if с_единицей.any():
            a[с_единицей] ^= a[r]
        опорные.append(j)
        r += 1
    return a[:r], опорные


def ранг(биты: np.ndarray) -> int:
    return len(привести(упаковать(биты), биты.shape[1])[1])


def ядро(биты: np.ndarray, предел: int | None = None) -> np.ndarray:
    """Базис ядра {h : A·hᵀ = 0} — проверочные векторы для строк-слов A (K × L)."""
    L = биты.shape[1]
    приведённая, опорные = привести(упаковать(биты), L)
    свободные = [j for j in range(L) if j not in set(опорные)]
    if предел is not None:
        свободные = свободные[:предел]
    if not свободные:
        return np.zeros((0, L), dtype=np.uint8)
    плотная = распаковать(приведённая, L)                     # r × L
    базис = np.zeros((len(свободные), L), dtype=np.uint8)
    for i, f in enumerate(свободные):
        базис[i, f] = 1
        базис[i, опорные] = плотная[:, f]
    return базис
