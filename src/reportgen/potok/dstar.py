"""D-STAR (JARL): заголовок передачи с позывными и короткие текстовые сообщения медленных данных.

Как у прошивки MMDVM (DStarRX.cpp, DStarTX.cpp) и MMDVMHost (DStarDefines.h, DStarSlowData.cpp):
- заголовок: синхронизация 0x557650 (24 бита), затем 660 бит: скремблер x⁷+x⁴+1 (начальное —
  все единицы; таблица SCRAMBLE_TABLE_RX), перемежение (12 столбцов по 28 и 12 по 27 бит, место —
  строка·24 + столбец; INTERLEAVE_TABLE_RX), свёрточный код K = 3, 1/2 (первый бит 1+D+D², второй
  1+D²), 330 бит (41 байт и 2 бита хвоста), байты — младшим битом вперёд; CRC — CCITT X.25
  (начальное 0xFFFF, отражённый, инверсия; младший байт первым);
- поля заголовка: три байта флагов, RPT2, RPT1, UR, MY по 8 знаков, суффикс MY — 4, CRC;
- речь: кадры по 96 бит (AMBE 72 + медленные данные 24), в кадре 0 каждого сверхкадра из 21 кадра —
  синхронизация данных 0xAAB468; медленные данные — байты младшим вперёд XOR 70 4F 93, по два кадра
  (1–2, 3–4, …) на блок из 6 байт: тип 0x40–0x43 — четыре части текста по 5 знаков;
- конец передачи — 0xAAAA135E.
"""

from __future__ import annotations

from collections import Counter
from typing import Dict, List, Optional, Tuple

import numpy as np

from .hdlc import fcs16
from .nahodka import Находка

СИНХРО_ЗАГОЛОВКА = 0x557650
СИНХРО_ДАННЫХ = 0xAAB468
КОНЕЦ = 0xAAAA135E
ЗАГОЛОВОК_БИТ = 660
КАДР = 96
СВЕРХКАДР = 21
МЕДЛЕННЫЕ_XOR = (0x70, 0x4F, 0x93)


def _биты(значение: int, длина: int) -> np.ndarray:
    return np.array([(значение >> (длина - 1 - i)) & 1 for i in range(длина)], dtype=np.uint8)


def _скремблер() -> np.ndarray:
    s, итог = 0x7F, []
    for _ in range(ЗАГОЛОВОК_БИТ):
        б = ((s >> 6) ^ (s >> 3)) & 1
        итог.append(б)
        s = ((s << 1) | б) & 0x7F
    return np.array(итог, dtype=np.uint8)


def _перемежение() -> np.ndarray:
    """Бит эфира i → место в последовательности кодера."""
    места = []
    for i in range(ЗАГОЛОВОК_БИТ):
        if i < 12 * 28:
            места.append((i % 28) * 24 + i // 28)
        else:
            j = i - 12 * 28
            места.append((j % 27) * 24 + 12 + j // 27)
    return np.array(места)


СКРЕМБЛЕР = _скремблер()
ПЕРЕМЕЖЕНИЕ = _перемежение()


def закодировать_свёрткой(биты: np.ndarray) -> np.ndarray:
    d1 = d2 = 0
    итог = []
    for d in биты:
        итог += [(d + d1 + d2) & 1, (d + d2) & 1]
        d2, d1 = d1, int(d)
    return np.array(итог, dtype=np.uint8)


def витерби(пары: np.ndarray) -> Tuple[np.ndarray, int]:
    """Жёсткий Витерби K = 3 (7, 5): (биты, расстояние до ближайшего кодового слова)."""
    пары = np.asarray(пары, dtype=np.uint8).reshape(-1, 2)
    INF = 1 << 30
    метрики = [0, INF, INF, INF]                     # состояние = (d1 << 1) | d2
    пути: List[List[int]] = [[], [], [], []]
    for a, b in пары:
        новые, новые_пути = [INF] * 4, [None] * 4
        for s in range(4):
            if метрики[s] >= INF:
                continue
            d1, d2 = s >> 1, s & 1
            for d in (0, 1):
                g1, g0 = (d + d1 + d2) & 1, (d + d2) & 1
                m = метрики[s] + (g1 != a) + (g0 != b)
                t = (d << 1) | d1
                if m < новые[t]:
                    новые[t], новые_пути[t] = m, пути[s] + [d]
        метрики, пути = новые, новые_пути
    лучшее = int(np.argmin(метрики))
    return np.array(пути[лучшее], dtype=np.uint8), int(метрики[лучшее])


def _в_байты_младшим(биты: np.ndarray) -> bytes:
    биты = np.asarray(биты, dtype=np.uint8)
    return np.packbits(биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1], axis=1).reshape(-1).tobytes()


def _из_байт_младшим(данные: bytes) -> np.ndarray:
    return np.array([(б >> k) & 1 for б in данные for k in range(8)], dtype=np.uint8)


def crc_заголовка(данные39: bytes) -> bytes:
    return (fcs16(данные39) ^ 0xFFFF).to_bytes(2, "little")


def декодировать_заголовок(эфир: np.ndarray) -> Tuple[bytes, bool, int]:
    """660 бит эфира → (41 байт, CRC верна, исправлено бит)."""
    б = np.asarray(эфир, dtype=np.uint8)[:ЗАГОЛОВОК_БИТ] ^ СКРЕМБЛЕР
    промежуточные = np.zeros(ЗАГОЛОВОК_БИТ, dtype=np.uint8)
    промежуточные[ПЕРЕМЕЖЕНИЕ] = б
    данные, ошибок = витерби(промежуточные)
    заголовок = _в_байты_младшим(данные[:328])
    return заголовок, crc_заголовка(заголовок[:39]) == заголовок[39:41], ошибок


def закодировать_заголовок(заголовок41: bytes) -> np.ndarray:
    биты = np.concatenate([_из_байт_младшим(заголовок41), np.zeros(2, dtype=np.uint8)])
    свёртка = закодировать_свёрткой(биты)
    return свёртка[ПЕРЕМЕЖЕНИЕ] ^ СКРЕМБЛЕР


ФЛАГИ = ((0x80, "данные"), (0x40, "через ретранслятор"), (0x20, "прервана"), (0x10, "управляющий сигнал"),
         (0x08, "срочно"))


def поля(заголовок: bytes) -> Dict[str, object]:
    т = заголовок.decode("ascii", "replace")
    флаг = заголовок[0]
    return {"флаги": [имя for бит, имя in ФЛАГИ if флаг & бит], "управление": флаг & 7,
            "rpt2": т[3:11].rstrip(), "rpt1": т[11:19].rstrip(), "ur": т[19:27].rstrip(),
            "my": т[27:35].rstrip(), "суффикс": т[35:39].rstrip()}


def описание(п: Dict[str, object]) -> str:
    my = str(п["my"]) + (f"/{п['суффикс']}" if п["суффикс"] else "")
    return (f"{my} → {п['ur']} через {п['rpt1']} / {п['rpt2']}"
            + (f" ({', '.join(п['флаги'])})" if п["флаги"] else ""))


def _места(биты: np.ndarray, слово: int, длина: int) -> List[Tuple[int, bool]]:
    if len(биты) < длина:
        return []
    окна = np.lib.stride_tricks.sliding_window_view(биты, длина)
    эталон = _биты(слово, длина)
    итог = [(int(м), False) for м in np.flatnonzero((окна == эталон).all(axis=1))]
    итог += [(int(м), True) for м in np.flatnonzero((окна != эталон).all(axis=1))]
    return sorted(итог)


def тексты(биты: np.ndarray, синхро: List[Tuple[int, bool]]) -> List[str]:
    """Тексты медленных данных по сверхкадрам (от каждой синхронизации данных)."""
    итог = []
    for место, инверсия in синхро:
        начало = место - 72                                  # синхронизация — в медленных данных кадра 0
        части: Dict[int, str] = {}
        for пара in range(10):
            байты = b""
            for k in (1 + 2 * пара, 2 + 2 * пара):
                от = начало + k * КАДР + 72
                if от < 0 or от + 24 > len(биты):
                    break
                кусок = биты[от:от + 24]
                байты += bytes(б ^ x for б, x in zip(_в_байты_младшим(1 - кусок if инверсия else кусок),
                                                     МЕДЛЕННЫЕ_XOR, strict=True))
            if len(байты) == 6 and байты[0] & 0xF0 == 0x40 and байты[0] & 0x0F < 4:
                части[байты[0] & 0x0F] = bytes(б & 0x7F for б in байты[1:]).decode("ascii", "replace")
        if len(части) == 4:
            итог.append("".join(части[i] for i in range(4)).rstrip())
    return итог


def найти(биты: np.ndarray) -> Optional[Находка]:
    биты = np.asarray(биты, dtype=np.uint8)
    заголовки = []
    for место, инверсия in _места(биты, СИНХРО_ЗАГОЛОВКА, 24):
        эфир = биты[место + 24:место + 24 + ЗАГОЛОВОК_БИТ]
        if len(эфир) < ЗАГОЛОВОК_БИТ:
            continue
        заголовок, верна, ошибок = декодировать_заголовок(1 - эфир if инверсия else эфир)
        if верна:
            заголовки.append((место, поля(заголовок), ошибок))
    синхро = _места(биты, СИНХРО_ДАННЫХ, 24)
    шаги = Counter((б - а) % (КАДР * СВЕРХКАДР) == 0 for (а, _), (б, _) in zip(синхро, синхро[1:], strict=False))
    сверхкадров = шаги[True]
    if not заголовки and сверхкадров < 3:
        return None
    текст = тексты(биты, синхро)
    концы = len(_места(биты, КОНЕЦ, 32))
    подробно = [f"заголовков с верной CRC: {len(заголовки)}; синхронизаций данных с шагом сверхкадра "
                f"(21 × 96 бит): {сверхкадров}; концов передачи: {концы}"]
    for _, п, ошибок in заголовки[:30]:
        подробно.append(описание(п) + (f"; исправлено бит {ошибок}" if ошибок else ""))
    for т, к in Counter(текст).most_common(10):
        подробно.append(f"текст медленных данных: «{т}»" + (f" × {к}" if к > 1 else ""))
    позывные = Counter(п["my"] for _, п, _ in заголовки)
    return Находка(
        уровень="канальный", что="D-STAR: заголовки передач и речь",
        уверенность=1.0 if заголовки else 0.8,
        мера=f"{len(заголовки)} заголовков (свёрточный код, CRC верна), {сверхкадров} сверхкадров речи",
        подробно=подробно, свойства={"заголовков": len(заголовки), "позывные": dict(позывные)})


def заголовок_из_полей(my: str, ur: str = "CQCQCQ", rpt1: str = "", rpt2: str = "", суффикс: str = "",
                       флаг: int = 0) -> bytes:
    """41 байт заголовка с CRC (для проверок)."""
    тело = (bytes([флаг, 0, 0]) + rpt2.ljust(8).encode() + rpt1.ljust(8).encode() + ur.ljust(8).encode()
            + my.ljust(8).encode() + суффикс.ljust(4).encode())
    return тело + crc_заголовка(тело)


def передача(заголовок41: bytes, текст: str = "", сверхкадров: int = 2) -> np.ndarray:
    """Преамбула, заголовок, речь (нули AMBE) с текстом в медленных данных, конец — для проверок."""
    части = [np.array([1, 0] * 32, dtype=np.uint8), _биты(СИНХРО_ЗАГОЛОВКА, 24), закодировать_заголовок(заголовок41)]
    текст = текст.ljust(20)[:20]
    блоки = [bytes([0x40 | i]) + текст[5 * i:5 * i + 5].encode() for i in range(4)]
    for _ in range(сверхкадров):
        for k in range(СВЕРХКАДР):
            части.append(np.zeros(72, dtype=np.uint8))
            if k == 0:
                части.append(_биты(СИНХРО_ДАННЫХ, 24))
                continue
            пара, вторая = (k - 1) // 2, (k - 1) % 2
            блок = блоки[пара] if пара < 4 else bytes([0x66] * 6)
            три = блок[3 * вторая:3 * вторая + 3]
            части.append(_из_байт_младшим(bytes(б ^ x for б, x in zip(три, МЕДЛЕННЫЕ_XOR, strict=True))))
    части.append(_биты(КОНЕЦ, 32))
    return np.concatenate(части)
