# -*- coding: utf-8 -*-
"""Свёрточные коды скорости 1/n (n = 2…4): многочлены, систематичность, Витерби.

Код 1/n: на каждый входной бит u — n выходных, c_j = g_j · u. Между любыми
двумя ветвями есть проверочная связь g_b·c_a + g_a·c_b = 0 — она занимает
K блоков по n бит, и её находят проверки Уолша — Адамара на окнах шириной
n·K с шагом n (устойчиво к ошибкам линии). Из связей между ветвью 1 и
каждой другой восстанавливаются все многочлены.

Один и тот же набор кодовых слов дают несистематический кодер (g_1, …, g_n)
и рекурсивный систематический (1, g_2/g_1, …) — так устроены ветви
турбокодов. По самим словам их не различить, а данные выходят разные.
Поэтому проверяется и то, и другое: если ветвь 1 и есть данные (у
рекурсивного систематического), следующий уровень разбора сойдётся именно
на ней.

Ветвь, не связанная с остальными ни одной связью, — признак турбокода:
вторая проверочная ветвь считается по ПЕРЕМЕЖЁННЫМ данным, и в естественном
порядке связи с ними нет.
"""

from __future__ import annotations

from typing import Dict, List, Sequence, Tuple

import numpy as np

from .kod import инверсия_ветвей, инверсия_словами, витерби_n, проверки, шагов_декодера

ПОРОГ = 0.2
ШИРИНА_ДО = 20


def связь(биты: np.ndarray, n: int, a: int, b: int, K: int, сдвиг: int
          ) -> Tuple[float, int] | None:
    """Сильнейшая связь между ветвями a и b кода 1/n в окне K блоков: (смещение, h)."""
    # Берём только биты ветвей a и b — окно шириной 2K вместо nK.
    блоков = (len(биты) - сдвиг) // n
    ряд = биты[сдвиг:сдвиг + блоков * n].reshape(блоков, n)[:, [a, b]].reshape(-1)
    смещения, окон = проверки(ряд[:1 << 18], 2 * K, 2, 0)
    смещения[0] = 0
    порог = max(ПОРОГ, 8 / np.sqrt(max(1, окон)))
    ширина = 2 * K
    лучшее = None
    for h in np.flatnonzero(np.abs(смещения) > порог):
        h = int(h)
        if h >> (ширина - 2) and h & 0b11:        # связь занимает ровно K блоков
            if лучшее is None or abs(смещения[h]) > лучшее[0]:
                лучшее = (float(abs(смещения[h])), h)
    return лучшее


def умножить(a: int, b: int) -> int:
    """Произведение многочленов над GF(2) (биты — коэффициенты)."""
    итог = 0
    while b:
        if b & 1:
            итог ^= a
        a <<= 1
        b >>= 1
    return итог


def делить(a: int, b: int) -> Tuple[int, int]:
    """Частное и остаток многочленов над GF(2)."""
    частное = 0
    while a and a.bit_length() >= b.bit_length():
        сдвиг = a.bit_length() - b.bit_length()
        частное |= 1 << сдвиг
        a ^= b << сдвиг
    return частное, a


def нод(a: int, b: int) -> int:
    while b:
        a, b = b, делить(a, b)[1]
    return a


def нок(a: int, b: int) -> int:
    return умножить(a, делить(b, нод(a, b))[0])


def _ветви_связи(h: int, K: int) -> Tuple[int, int]:
    биты_h = [(h >> (2 * K - 1 - i)) & 1 for i in range(2 * K)]
    на_a = int("".join(map(str, биты_h[0::2])), 2)
    на_b = int("".join(map(str, биты_h[1::2])), 2)
    return на_a, на_b


def _связь_наименьшая(биты, n, a, b, сдвиг):
    for K in range(3, ШИРИНА_ДО // 2 + 1):
        найдено = связь(биты, n, a, b, K, сдвиг)
        if найдено is not None:
            return K, найдено[0], найдено[1]
    return None


def опознать(биты: np.ndarray) -> Dict | None:
    """Код 1/n: n, выравнивание, K, многочлены; несвязанные ветви (турбо).

    Выравнивание блока выбирается по ветви 0: при верном у связей ветви 0 со
    всеми остальными одна и та же «своя» сторона (g_0) и наименьшее K; при
    сдвинутом связь либо рвётся, либо удлиняется на шаг.
    """
    итоги = []
    for n in (2, 3, 4):
        варианты = []
        for сдвиг in range(n):
            связи = {j: _связь_наименьшая(биты, n, 0, j, сдвиг) for j in range(1, n)}
            есть = {j: с for j, с in связи.items() if с is not None}
            if not есть:
                continue
            g0 = {_ветви_связи(h, K)[1] for K, _, h in есть.values()}
            ключ = (len(есть), len(g0) == 1, -max(K for K, _, _ in есть.values()),
                    sum(сила for _, сила, _ in есть.values()))
            варианты.append((ключ, сдвиг, есть))
        if not варианты:
            continue
        _, сдвиг, есть = max(варианты, key=lambda в: в[0])
        K = max(K for K, _, _ in есть.values())
        # c0·g_j + c_j·g0 = 0: на ветви 0 стоит g_j, на ветви j — g0 — но
        # сокращённые на общий делитель f = НОД(g0, g_j). Поэтому g0 — НОК
        # сокращённых «своих» сторон, а g_j = (сторона ветви 0)·(g0 / своя).
        пары = {j: _ветви_связи(h, Kj) for j, (Kj, _, h) in есть.items()}
        g0 = 1
        for _, своя in пары.values():
            g0 = нок(g0, своя)
        многочлены = {0: g0}
        for j, (на_0, своя) in пары.items():
            многочлены[j] = умножить(на_0, делить(g0, своя)[0])
        K = max(K, g0.bit_length(), *(g.bit_length() for g in многочлены.values()))
        итоги.append({"n": n, "сдвиг": сдвиг, "K": K, "многочлены": многочлены,
                      "несвязанные": [j for j in range(1, n) if j not in есть],
                      "сила": max(сила for _, сила, _ in есть.values())})
    if not итоги:
        return None
    # Верное n даёт связь во всех окнах; неверное смешивает ветви, и связь
    # выполняется лишь в части окон — её смещение заметно меньше. При
    # равенстве — меньшее n.
    return max(итоги, key=lambda и: (round(и["сила"], 2), -и["n"]))


def зеркало(g: int, K: int) -> int:
    """Многочлен в записи стандартов ↔ во внутренней записи (операция сама себе обратна).

    Внутри регистр — (s << 1) | вход: новый бит — младший, и старший бит многочлена
    умножает самый старый вход. В стандартах (CCSDS 131.0-B, 3GPP 36.212, DVB) и в
    библиотеках (libfec: CCSDS — 0x4F и 0x6D при том же регистре; GNU Radio cc_encoder —
    109 и 79) запись обратная: старший бит — текущий вход, 171/133 — это 0x4F/0x6D.
    Всё, что видит и вводит аналитик, — в записи стандартов.
    """
    return int(format(g, f"0{K}b")[::-1], 2)


def запись(многочлены: Sequence[int], K: int) -> str:
    """Многочлены внутренней записи — восьмерично, как в стандартах: «171/133»."""
    return "/".join(f"{зеркало(g, K):o}" for g in многочлены)


def кодировать(данные: np.ndarray, многочлены: List[int], K: int) -> np.ndarray:
    n = len(многочлены)
    регистр = 0
    выход = np.zeros(n * len(данные), dtype=np.uint8)
    for i, u in enumerate(данные):
        регистр = ((регистр << 1) | int(u)) & ((1 << K) - 1)
        for j, g in enumerate(многочлены):
            выход[n * i + j] = bin(регистр & g).count("1") & 1
    return выход


def кодировать_кольцо(данные: np.ndarray, многочлены: List[int], K: int) -> np.ndarray:
    """Кодер с циклическим хвостом (tail-biting, 3GPP 36.212 5.1.3.1): регистр заранее
    заполнен последними K − 1 битами блока — начальное и конечное состояния совпадают
    (как CC_TAILBITING в GNU Radio cc_encoder)."""
    регистр = 0
    for бит in данные[len(данные) - (K - 1):]:
        регистр = ((регистр << 1) | int(бит)) & ((1 << K) - 1)
    n = len(многочлены)
    выход = np.zeros(n * len(данные), dtype=np.uint8)
    for i, u in enumerate(данные):
        регистр = ((регистр << 1) | int(u)) & ((1 << K) - 1)
        for j, g in enumerate(многочлены):
            выход[n * i + j] = bin(регистр & g).count("1") & 1
    return выход


def витерби_кольцо(блоки: np.ndarray, многочлены: List[int], K: int) -> np.ndarray:
    """Декодер кода с циклическим хвостом: блок трижды подряд (декодер начинает с равных
    метрик — начальное состояние не известно), берутся решения средней копии — к ней
    путь уже сошёлся к верному состоянию, а конец блока продолжен его же началом.

    ``блоки`` — (число блоков, n · длина) принятых бит; итог — (число блоков, длина)."""
    блоки = np.atleast_2d(np.asarray(блоки, dtype=np.uint8))
    n = len(многочлены)
    L = блоки.shape[1] // n
    итог = np.zeros((len(блоки), L), dtype=np.uint8)
    for номер, блок in enumerate(блоки):
        тройной = np.tile(блок[:n * L], 3)
        итог[номер] = витерби_n(тройной, многочлены, K)[L:2 * L]
    return итог


def кодировать_rsc(данные: np.ndarray, обратная: int, прямая: int, K: int) -> np.ndarray:
    """Рекурсивный систематический кодер (1, прямая/обратная): пары (u, p).

    Соглашение то же, что у несистематического: регистр r = (r << 1) | бит,
    новый бит — младший. Во внутренний регистр входит a = u + Σ обратных
    отводов по прошлым a, так что чётность (r & обратная) равна u.
    """
    память = (1 << (K - 1)) - 1
    s = 0
    выход = np.zeros(2 * len(данные), dtype=np.uint8)
    for i, u in enumerate(данные):
        a = int(u) ^ (bin((s << 1) & обратная).count("1") & 1)
        r = (s << 1) | a
        выход[2 * i] = u
        выход[2 * i + 1] = bin(r & прямая).count("1") & 1
        s = r & память
    return выход


def витерби(биты: np.ndarray, многочлены: List[int], K: int,
            известно: np.ndarray | None = None) -> np.ndarray:
    """Жёсткие решения, код 1/n (регистр — как в kod); память ограничена — см. ``kod.витерби_n``.

    ``известно`` — маска переданных бит: у выколотого кода на месте
    выброшенных стоят стирания, они в метрику не входят.
    """
    return витерби_n(биты, многочлены, K, известно)


def витерби_с_нуля(принятые: np.ndarray, многочлены: Sequence[int], K: int,
                   известно: np.ndarray | None = None) -> np.ndarray:
    """Блоковый декодер Витерби: путь начинается и кончается в нулевом состоянии (хвост из K − 1 нулей).

    Регистр — (s << 1) | бит, выход ветви j — чётность (регистр & g_j), как у ``кодировать``;
    ``известно`` — маска переданных бит, стирания в метрику не входят. Итог — все шаги с хвостом.
    У короткого блока с хвостом конец в нуле — сильное знание: argmin по состояниям его теряет.
    """
    n = len(многочлены)
    S = 1 << (K - 1)
    шагов = len(принятые) // n
    принятые = np.asarray(принятые[:n * шагов], dtype=np.int64).reshape(шагов, n)
    маска = (np.ones((шагов, n), dtype=np.int64) if известно is None
             else np.asarray(известно[:n * шагов], dtype=np.int64).reshape(шагов, n))
    t = np.arange(S)
    регистры = np.stack([t, t | S])                                   # к состоянию t из t >> 1 и (t >> 1) | S/2
    выход = np.stack([np.array([[bin(int(r) & g).count("1") & 1 for r in ряд] for ряд in регистры])
                      for g in многочлены], axis=-1)                    # (2, S, n)
    большое = 1 << 30
    метрика = np.full(S, большое, dtype=np.int64)
    метрика[0] = 0
    решения = np.zeros((шагов, S), dtype=bool)
    p0, p1 = t >> 1, (t >> 1) | (S >> 1)
    for k in range(шагов):
        цена = ((выход != принятые[k]) & (маска[k] == 1)).sum(axis=-1)   # (2, S)
        m0 = метрика[p0] + цена[0]
        m1 = метрика[p1] + цена[1]
        решения[k] = m1 < m0
        метрика = np.minimum(m0, m1)
    итог = np.zeros(шагов, dtype=np.uint8)
    состояние = 0
    for k in range(шагов - 1, -1, -1):
        итог[k] = состояние & 1
        состояние = (состояние >> 1) | (int(решения[k, состояние]) << (K - 2))
    return итог


#: Как в kod: расхождение перекодированного с принятым в каждой восьмой части
#: выборки — не больше этой доли от того же на случайных битах.
ДОЛЯ_ОТ_СЛУЧАЙНОГО = 0.75
ВЫБОРКА = 1 << 18


def _расхождение(биты: np.ndarray, многочлены: List[int], K: int) -> Tuple[np.ndarray, np.ndarray]:
    данные = витерби(биты, многочлены, K)
    перекодировано = кодировать(данные, многочлены, K)
    длина = min(len(перекодировано), len(биты))
    return данные, перекодировано[:длина] != биты[:длина]


_БАЗА: Dict[Tuple, float] = {}


def _база(многочлены: List[int], K: int) -> float:
    ключ = (tuple(многочлены), K)
    if ключ not in _БАЗА:
        случайные = np.random.default_rng(12345).integers(0, 2, 3 << 12, dtype=np.uint8)
        _БАЗА[ключ] = float(_расхождение(случайные, многочлены, K)[1].mean())
    return _БАЗА[ключ]


def найти(биты: np.ndarray):
    """Свёрточный код скорости 1/3 или 1/4 (1/2 ищет kod) — находка для отчёта."""
    from .nahodka import Находка
    о = опознать(биты[:ВЫБОРКА])
    if о is None or о["n"] < 3 or о["несвязанные"]:
        return None
    n, K, сдвиг = о["n"], о["K"], о["сдвиг"]
    if K > ШИРИНА_ДО // 2:
        # Связи ищутся до K = ШИРИНА_ДО / 2; длиннее многочлен получается только
        # из НОК несогласных связей — это шум, а не код (и Витерби на 2¹⁸
        # состояний не по силам).
        return None
    многочлены = [о["многочлены"][j] for j in range(n)]
    маска = инверсия_ветвей(биты[сдвиг:], многочлены, K)
    поток = биты[сдвиг:сдвиг + n * шагов_декодера(K)]
    поток = поток ^ np.resize(np.array(маска, dtype=np.uint8), len(поток))
    данные, расходится = _расхождение(поток, многочлены, K)
    база = _база(многочлены, K)
    части = [float(ч.mean()) for ч in np.array_split(расходится, 8) if len(ч)]
    if max(части) > ДОЛЯ_ОТ_СЛУЧАЙНОГО * база:
        return None
    ошибок = float(расходится.mean())
    имена = запись(многочлены, K)
    инверсия = инверсия_словами(маска, многочлены)
    return Находка(
        уровень="код", что=f"свёрточный код скорости 1/{n}, K={K}, {имена}"
                           + (f"; {инверсия}" if инверсия else ""),
        уверенность=min(1.0, о["сила"] / 0.5),
        мера=f"проверочные связи между ветвями выполнены (смещение {о['сила']:.2f}); "
             f"перекодированный поток совпал с принятым в {(1 - ошибок) * 100:.2f} % бит "
             f"(у случайного ряда — {(1 - база) * 100:.1f} %)",
        подробно=[f"порождающие многочлены (восьмерично): {имена}, K = {K}, первый бит "
                  f"тройки — бит {сдвиг} потока",
                  "этот же код даёт и рекурсивный систематический кодер (1, g2/g1, …): "
                  "если ветвь 1 и есть данные — следующий уровень сойдётся на ней",
                  f"оценка доли ошибок в линии: {ошибок * 100:.2f} %",
                  f"декодер Витерби (жёсткие решения) по первым {len(данные)} битам данных"],
        дальше=данные, вид_дальше="биты", сверка=1 - ошибок)
