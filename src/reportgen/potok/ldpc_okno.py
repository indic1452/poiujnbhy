"""Окно «LDPC» стола анализа — как вкладка LDPC декодера софта отдела.

Параметры окна (словарь из браузера) превращаются в слои разбора — те же, что понимает
«снять вручную» и цепочки конфигураций: «ldpc ИМЯ … [синхро СЛОВО длина N [распределённое]
[с синхрословом]]», затем постобработка — «скремблер a,b» (мультипликативный,
самосинхронизирующийся), «аддитивный отводы 14,15 кадр N начальное … [пропуск s]»
(ПСП DVB 1 + x¹⁴ + x¹⁵, регистр 100101010000000 заново в каждом блоке, EN 302 307-1, 5.2.2) и «инверсия». «Просмотр»
декодирует начало массива, «Автомат» сам ищет код и схему среди кодов выбранного типа и скорости
(или всех встроенных и файлов отдела).
"""

from __future__ import annotations

import re
from typing import Any

import numpy as np

from . import ldpc, sinhro

#: Загрузка регистра ПСП DVB (EN 302 307-1 v1.4.1, 5.2.2, стр. PDF 21–22: «1 + X14 + X15», «loading of the
#: sequence (100101010000000) into the PRBS register … at the start of every BBFRAME»).
DVB_РЕГИСТР = "100101010000000"


def dvb_первые(n: int = 15) -> str:
    """Первые n бит ПСП DVB после загрузки регистра (рис. 5 стандарта): регистр x1…x15, выход
    x14 ⊕ x15, он же вдвигается в x1. Слой «аддитивный … начальное» ждёт именно первые биты ПСП."""
    r = [int(ч) for ч in DVB_РЕГИСТР]
    итог = []
    for _ in range(n):
        b = r[13] ^ r[14]
        итог.append(b)
        r = [b] + r[:-1]
    return "".join(map(str, итог))
#: Сколько слов декодирует «Просмотр» и сколько бит выборки берёт «Автомат».
СЛОВ_ПРОСМОТРА = 24
АВТОМАТ_БИТ = 1 << 21


def _позиции(текст: Any) -> str:
    т = str(текст or "").strip()
    if т and not re.fullmatch(r"[\d\s,\-–…\.]+", т):
        raise ValueError("позиции — числа и диапазоны («0-191, 1000-1023»)")
    return т


def слой(п: dict[str, Any]) -> str:
    """Слой «ldpc …» по параметрам окна."""
    код = str(п.get("код") or "").strip()
    if not ldpc.ИМЯ.fullmatch(код):
        raise ValueError("выберите код (тип и скорость) или файл матрицы")
    части = ["ldpc", код]
    if п.get("выколоты"):
        части += ["выколоты", _позиции(п["выколоты"])]
    if п.get("укорочены"):
        части += ["укорочены", _позиции(п["укорочены"])]
    перемежение = str(п.get("перемежение") or "").strip()
    if перемежение:
        if not re.fullmatch(r"1367|(?:8PSK|16APSK|32APSK)(?:\s+\d{3,5})?", перемежение, re.I):
            raise ValueError("перемежение — 1367 (F-LDPC) или 8PSK/16APSK/32APSK [порядок столбцов]")
        части += ["перемежение", перемежение]
    с = п.get("синхро") or {}
    вид = str(с.get("вид") or "нет")
    if вид != "нет":
        слово = sinhro.слово(str(с.get("слово") or ""))
        длина = int(с.get("длина") or 0)
        if длина <= len(слово):
            raise ValueError("длина кадра — больше длины синхрослова")
        if с.get("длина_слова") and int(с["длина_слова"]) != len(слово):
            raise ValueError(f"длина синхрослова {int(с['длина_слова'])}, а в поле — {len(слово)} бит")
        части += ["синхро", "".join(map(str, слово.tolist())), "длина", str(длина)]
        if вид == "распределённое":
            части.append("распределённое")
        if с.get("выводить"):
            части.append("с синхрословом")
    if п.get("итераций"):
        части += ["итераций", str(min(200, max(1, int(п["итераций"]))))]
    return " ".join(части)


def _блок_выхода(п: dict[str, Any]) -> tuple[int, int]:
    """Длина блока на выходе декодера и сколько бит в его начале — синхрослово (сброс ПСП DVB — в каждом блоке)."""
    схема, _, _ = ldpc.из_указания(слой({**п, "синхро": None}))
    k = len(ldpc.информационные(схема.матрица))
    с = п.get("синхро") or {}
    if str(с.get("вид") or "нет") == "нет":
        return k, 0
    слово = sinhro.слово(str(с.get("слово") or ""))
    кадр = ldpc.Кадр(слово, int(с.get("длина") or 0), с.get("вид") == "распределённое", bool(с.get("выводить")))
    слов = (кадр.длина - len(слово)) // схема.длина
    s = len(слово) if кадр.с_синхрословом else 0
    return s + слов * k, s


def постобработка(п: dict[str, Any]) -> list[str]:
    """Слои постобработки по порядку окна: мультипликативный дескремблер, аддитивный DVB, инверсия."""
    итог = []
    отводы = str(п.get("мультипликативный") or "").strip()
    if отводы:
        числа = [int(x) for x in re.findall(r"\d+", отводы)]
        if not числа or max(числа) > 64:
            raise ValueError("мультипликативный дескремблер: отводы — степени многочлена («18,23» для 1 + x⁻¹⁸ + x⁻²³)")
        итог.append("скремблер " + ",".join(map(str, sorted(set(числа)))))
    if п.get("аддитивный_dvb"):
        блок, пропуск = _блок_выхода(п)
        итог.append(f"аддитивный отводы 14,15 кадр {блок} начальное {dvb_первые()}"
                    + (f" пропуск {пропуск}" if пропуск else ""))
    if п.get("инверсия"):
        итог.append("инверсия")
    return итог


def просмотр(биты: np.ndarray, п: dict[str, Any]) -> dict[str, Any]:
    """Декодировать начало массива (до СЛОВ_ПРОСМОТРА слов) с постобработкой: итог и отчёт."""
    from .razbor import снять_вручную  # noqa: PLC0415 — razbor тянет всё
    основной = слой(п)
    схема, _, _ = ldpc.из_указания(основной)
    кадр = ldpc.кадр_из_указания(основной)
    бит = (кадр.длина * (СЛОВ_ПРОСМОТРА // max(1, (кадр.длина - len(кадр.слово)) // схема.длина) + 2)
           if кадр else схема.длина * (СЛОВ_ПРОСМОТРА + 2))
    ряд, находка = снять_вручную(биты[:бит], основной)
    подробно = list(находка.подробно)
    слои = [основной]
    for доп in постобработка(п):
        ряд, н = снять_вручную(ряд, доп)
        подробно += [f"{доп}: " + "; ".join(н.подробно)] if н.подробно else [доп]
        слои.append(доп)
    сошлось = next((float(м.group(1)) for с in подробно for м in [re.search(r"синдром обнулился у \d+ \(([\d.]+) %\)", с)] if м),
                   None)
    return {"слои": слои, "подробно": подробно, "сошлось": сошлось, "бит": int(len(ряд)),
            "биты": ряд, "n": схема.матрица.n, "k": len(ldpc.информационные(схема.матрица)), "в_потоке": схема.длина}


def кандидаты(п: dict[str, Any], типы: list[dict]) -> list[str] | None:
    """Коды для автомата: выбранного типа и скорости (или всего типа); без типа — None (все)."""
    тип = next((т for т in типы if т["тип"] == п.get("тип")), None)
    if тип is None:
        return None
    скорости = [с for с in тип["скорости"] if not п.get("скорость") or с["подпись"] == п["скорость"]]
    if тип.get("блоки") and п.get("блок"):
        скорости = [с for с in скорости if с.get("блок") == int(п["блок"])]
    итог: list[str] = []
    for с in скорости:
        итог += [и for и in с["коды"] if и not in итог]
    return итог


def автомат(биты: np.ndarray, п: dict[str, Any], типы: list[dict], бюджет: float = 60.0) -> dict[str, Any]:
    """Найти код и схему самому: среди кандидатов типа (встроенные и файлы отдела) или всех.

    Если задано синхрослово — сперва оно убирается (слова кода ищутся в нагрузке кадров).
    """
    имена = кандидаты(п, типы)
    файлы = {str(ф["имя"]) for ф in ldpc.список() if "ошибка" not in ф}
    загруженные = None
    встроенные_имена = None
    if имена is not None:
        встроенные_имена = [и for и in имена if и not in файлы]
        загруженные = [(и, ldpc.схема_сохранённая(и)) for и in имена if и in файлы]
        if not имена:
            return {"найдено": None, "почему": "у выбранного типа нет ни одного кода: матрица закрыта — "
                                                "положите файл отдела в папку ldpc"}
    выборка = биты[:АВТОМАТ_БИТ]
    с = п.get("синхро") or {}
    кадр = None
    if str(с.get("вид") or "нет") != "нет":
        кадр = ldpc.Кадр(sinhro.слово(str(с.get("слово") or "")), int(с.get("длина") or 0),
                         с.get("вид") == "распределённое")
        начало, инверсия, доля = ldpc._начало_кадров(выборка, кадр)
        ряд = выборка[начало:]
        ряд = (1 - ряд).astype(np.uint8) if инверсия else ряд
        кадров = len(ряд) // кадр.длина
        лишние = np.zeros(кадр.длина, dtype=bool)
        лишние[кадр.места()] = True
        выборка = ряд[:кадров * кадр.длина].reshape(кадров, кадр.длина)[:, ~лишние].reshape(-1)
    найдено = ldpc.найти_по_матрицам(выборка, схемы=загруженные, встроенные=True, имена=встроенные_имена,
                                     бюджет=бюджет, блок=(кадр.длина - len(кадр.слово)) if кадр else None)
    if найдено is None:
        return {"найдено": None, "почему": "ни один код не совпал: проверки нарушены примерно в половине случаев "
                                            "при любом начале (другой код, другая схема передачи или поток ещё "
                                            "не очищен — скремблер, перемежение, кадры модема)"}
    имя = str(найдено.свойства["матрица"])
    схема = найдено.свойства["схема"]
    стандарт = ldpc.схема_сохранённая(имя)
    # Поля окна: выколотые и укороченные — только если схема не та, что у кода по стандарту/файлу.
    def поле(найдено_: np.ndarray, своё: np.ndarray) -> str:
        return "" if np.array_equal(найдено_, своё) else ldpc.позиции_строкой(найдено_)

    м = re.search(r"перемежение бит (\S+) \((\d*)\)", найдено.что)
    return {"найдено": {
        "код": имя, "что": найдено.что, "мера": найдено.мера, "подробно": list(найдено.подробно),
        "начало": int(найдено.свойства["начало"]), "выколоты": поле(схема.выколоты, стандарт.выколоты),
        "укорочены": поле(схема.укорочены, стандарт.укорочены),
        "перемежение": (м.group(1) + (" " + м.group(2) if м.group(2) else "")) if м else "",
        "сошлось": round(float(найдено.уверенность) * 100, 1)}}
