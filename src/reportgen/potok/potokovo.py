def потоковый(шаг: dict[str, Any], окно_синхро: int = ОКНО_СИНХРО) -> _Шаг | None:
    """Потоковое исполнение шага или None — шагу нужен весь ряд."""
    from . import sinhro  # noqa: PLC0415
    from .razbor import _число_после  # noqa: PLC0415
    if шаг["вид"] == "маска":
        return _Маска(шаг)
    if шаг["вид"] == "разметка":
        return _Разметка(шаг)
    указание = str(шаг["слой"])
    слова = указание.strip().lower()
    вид = слова.split()[0] if слова else ""
    числа = [int(ч) for ч in re.findall(r"\d+", слова)]
    if вид == "инверсия":
        return _ПоГруппам(указание, 1)
    if вид == "сдвиг" and числа:
        с = _Сдвиг(числа[0])
        с.что = _Простой(указание).что
        return с
    if вид in ("nrzi", "дифференциальное", "дифференциальный"):
        return _Nrzi(указание)
    if вид.startswith("накоплен") or вид in ("дифкодер", "nrzi-код"):
        return _Накопление(указание)
    if вид == "скремблер" and числа:
        return _Скремблер(указание, числа)
    if вид.startswith("обрез"):
        return _Обрезка(указание, _число_после(слова, "начал") or 0, _число_после(слова, "конец") or 0)
    if вид.startswith("усеч") or вид.startswith("выреза"):
        return _Усечение(указание, _число_после(слова, "от") or 0, _число_после(слова, "до"),
                         _число_после(слова, "длин"))
    if вид == "реверс":
        n = числа[0] if числа else 8
        return _ПоГруппам(указание, n) if n >= 2 else None
    if вид.startswith("прорежив") and числа and числа[0] >= 2:
        return _ПоГруппам(указание, числа[0], хвост=True)
    if вид.startswith("выброс") and числа and числа[0] >= 2:
        k = числа[0]
        return _Выбросить(указание, k, числа[1] % k if len(числа) > 1 else 0)
    if вид.startswith("пилот") or вид.startswith("вставк"):
        return _Пилоты(указание)               # вырезать вставку — как снять_вручную (не «вставить»)
    if вид == "пары":
        return _Пары(указание)
    if вид == "pdh":
        return _Pdh(указание)
    if вид == "gfp":
        return _Gfp(указание)
    if вид.startswith(("свёрточн", "сверточн", "выколот")) or вид in ("нск", "nsk"):
        return _Свёртка(указание)
    if вид.startswith("встав") and числа and числа[0] >= 2:
        k = числа[0]
        бит = 1 if re.search(r"(?<!\w)бит\w*\s+1", слова) else 0
        return _Вставить(указание, k, числа[1] % k if len(числа) > 1 else 0, бит)
    if вид in ("xor", "синхро", "кадры"):
        части = указание.split()
        if len(части) < 2:
            return None
        образец = sinhro.слово(части[1])
        if вид == "xor":
            return _ПоГруппам(указание, len(образец), хвост=True)
        ошибок_ = re.search(r"ошиб\w*\s+(\d+)", слова)
        ошибок = int(ошибок_.group(1)) if ошибок_ else 0
        if вид == "синхро":
            return _Синхро(указание, образец, ошибок, окно_синхро)
        длина_ = re.search(r"длин\w*\s+(\d+)", слова)
        return _Кадры(указание, образец, int(длина_.group(1)), ошибок, окно_синхро) if длина_ else None
    if вид == "метки" and числа:
        return _ПоГруппам(указание, числа[0])
    if вид == "биты" and "символ" in слова and числа:
        return _ПоГруппам(указание, числа[0])
    if вид in ("фм", "psk") and числа and 1 <= числа[0] <= 6:
        явно = re.search(r"поворот\s+(\d+)", слова) or "отраж" in слова or "натурал" in слова or \
            re.search(r"биты\s+(\d(?:[-,\s]+\d)+)", слова)
        return _ПоГруппам(указание, числа[0]) if явно else None
    if вид == "плоскость" and числа:
        from .razbor import _вариант_плоскости  # noqa: PLC0415
        return _ПоГруппам(указание, числа[0]) if _вариант_плоскости(слова) is not None else None
    if вид.startswith("моддекодер") and "относительн" in слова:
        return _Относительный(указание)
    if вид.startswith("моддекодер"):
        from . import moddekoder  # noqa: PLC0415
        return _ПоГруппам(указание, moddekoder.из_слоя(указание.strip()).k, хвост_словами=True)
    if вид.startswith("аддитивн"):
        return _аддитивный(указание, слова)
    return None


def _аддитивный(указание: str, слова: str) -> _Шаг | None:
    """Аддитивная ПСП с заданным начальным состоянием — непрерывная или со сбросом в кадре."""
    from . import sinhro  # noqa: PLC0415
    from .razbor import _число_после  # noqa: PLC0415
    отводы_ = re.search(r"отвод\w*\s+([\d\s,]+)", слова)
    отводы = tuple(int(ч) for ч in re.findall(r"\d+", отводы_.group(1))) if отводы_ else ()
    нач_ = re.search(r"начальн\w*\s+(\S+)", слова)
    if not отводы or not нач_:
        return None                         # состояние ищется по ряду — нужен весь ряд
    длина = _число_после(слова, "кадр")
    регистр = sinhro.слово(нач_.group(1))
    степень = max(отводы)
    if len(регистр) < степень:
        return None                         # ошибку скажет исполнение в памяти
    if длина is None:
        # «с бита M» — регистр на бите M: ПСП отматывается назад к биту 0 и дальше идёт кусок за куском.
        return _АддитивныйНепрерывный(указание, отводы, регистр[:степень], _число_после(слова, r"с\s+бита") or 0)
    пропуск = _число_после(слова, "пропуск") or 0
    начало = _число_после(слова, r"начало\b") or 0
    if not 0 <= пропуск < длина:
        return None
    return _АддитивныйКадр(указание, отводы, регистр, длина, пропуск, начало)


class _АддитивныйНепрерывный(_Простой):
    """ПСП с регистром на бите ``место`` — с бита 0 продолжается кусок за куском (регистр — последние биты ПСП)."""

    def __init__(self, указание: str, отводы: Sequence[int], регистр: np.ndarray, место: int = 0):
        from . import skrembler  # noqa: PLC0415
        self.отводы, self.степень, self.место = tuple(отводы), max(отводы), место
        регистр = np.asarray(регистр, dtype=np.uint8)
        # Регистр на бите 0: биты ПСП перед местом (назад по рекурренте) и сам регистр — первые «степень» бит.
        self._регистр = np.concatenate([skrembler.псп_назад(отводы, регистр, место), регистр])[:self.степень]
        super().__init__(указание, [f"ПСП {skrembler.полином_словами(отводы)}: регистр "
                                   f"{''.join(map(str, регистр.tolist()))} на бите {место} (на первом бите — "
                                   f"{''.join(map(str, self._регистр.tolist()))})"])
        # ПСП начинается с самого регистра: запас — выработанное, но ещё не отданное.
        self._запас = self._регистр.copy()
        self._хвост = self._регистр.copy()
        self._всего = 0

    def закончить(self) -> np.ndarray:
        if not 0 <= self.место <= max(0, self._всего - self.степень):
            raise ValueError(f"место начального состояния — от 0 до {max(0, self._всего - self.степень)}")
        return _пусто()

    def подать(self, биты: np.ndarray) -> np.ndarray:
        from . import skrembler  # noqa: PLC0415
        n = len(биты)
        self._всего += n
        if not n:
            return _пусто()
        if len(self._запас) < n:
            ещё = skrembler.псп(self.отводы, self._хвост, n - len(self._запас) + self.степень)[self.степень:]
            self._хвост = np.concatenate([self._хвост, ещё])[-self.степень:].copy()
            self._запас = np.concatenate([self._запас, ещё])
        ряд, self._запас = self._запас[:n], self._запас[n:]
        return биты ^ ряд


class _АддитивныйКадр(_Шаг):
    def __init__(self, указание: str, отводы, начальное: np.ndarray, длина: int, пропуск: int, начало: int):
        from . import skrembler  # noqa: PLC0415
        from .razbor import _кратко  # noqa: PLC0415
        self.длина = длина
        self._сдвиг = _Сдвиг(начало)
        self._маска = np.zeros(длина, dtype=np.uint8)
        self._маска[пропуск:] = skrembler.псп(отводы, np.asarray(начальное, dtype=np.uint8), длина - пропуск)
        self._буфер = _пусто()
        подробно = [f"кадровый аддитивный скремблер {skrembler.полином_словами(отводы)}, сброс в каждом кадре "
                    f"{длина} бит (с бита {начало}, первые {пропуск} бит кадра не скремблированы)",
                    f"начальное состояние (первые {max(отводы)} бит ПСП после сброса): "
                    f"{''.join(map(str, np.asarray(начальное)[:max(отводы)].tolist()))}; начальное состояние задано"]
        self.что = f"снято по указанию: {_кратко(указание)}: " + "; ".join(подробно)

    def подать(self, биты: np.ndarray) -> np.ndarray:
        биты = self._сдвиг.подать(биты)
        if len(self._буфер):
            биты = np.concatenate([self._буфер, биты])
        кадров = len(биты) // self.длина
        self._буфер = биты[кадров * self.длина:].copy()
        return (биты[:кадров * self.длина].reshape(кадров, self.длина) ^ self._маска).reshape(-1)


