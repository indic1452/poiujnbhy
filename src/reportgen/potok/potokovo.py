"""Шаги обработки над большим массивом — потоком, кусками, с записью итога на диск.

Массив в гигабайт целиком в память не берётся (биты — по байту на бит). Шаги
выполняются так:

* массив до ``в_памяти_до`` бит — целиком в памяти, как всегда (``rastr.применить``);
* больше — по кускам: подряд идущие потоковые шаги (обрезка, инверсия, сдвиг,
  мультипликативный и аддитивный скремблер (и ПСП с места), xor, прореживание, выбросить и
  вставить биты, вырезать вставку (пилоты), пары, реверс в группах, NRZI, накопление, метки и
  биты символа, ФМ и КАМ с заданным вариантом, моддекодер таблицей и относительный, канал по
  маске, разметка, синхронизация и выравнивание кадров по синхрокомбинации, приток PDH,
  свёрточный, выколотый и НСК (Витерби потоком), GFP окнами) пропускают каждый кусок по
  цепочке, итог сразу пишется в файл; кусок за куском — ход, между кусками — проверка отмены;
* слой, которому нужен весь ряд (коды: LDPC, ТКБ, турбо, РС; V.110…), получает ряд целиком,
  если тот помещается в память, а больше — кусками не длиннее ``в_памяти_до`` бит: по сетке
  слов или кадров, если их место известно (``_сетка``: итог как над всем рядом), иначе
  независимо (каждый кусок слой синхронизирует заново; об этом — строка в описании). Слои,
  которые кусками дали бы неверный итог (переворот задом наперёд, поиск лучшего варианта
  плоскости без явного варианта), на таком массиве не выполняются — с объяснением, что сделать.

Итог потоковых шагов совпадает с итогом в памяти бит в бит (проверяется тестами на
малых массивах с маленькими кусками), описание — тоже. Исключения — поиск
синхрокомбинации («синхро», «кадры»): начало ищется в первых ``ОКНО_СИНХРО`` битах,
на большем массиве счёт вхождений в описании — по этому окну.
"""

