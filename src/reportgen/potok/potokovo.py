def _кусками_можно(шаг: dict[str, Any]) -> bool:
    вид = str(шаг.get("слой", "")).strip().lower().split()[:1]
    return bool(вид) and any(вид[0].startswith(п) for п in КУСКАМИ)


def выполнить(источник: Источник, шаги: Sequence[dict[str, Any]], куда: str | Path, *,
              ход: Callable[[float, str], None] | None = None,
              отмена: Callable[[], bool] | None = None,
              кусок_бит: int = КУСОК_БИТ, в_памяти_до: int = В_ПАМЯТИ_ДО,
              окно_синхро: int = ОКНО_СИНХРО) -> tuple[int, list[str]]:
    """Шаги над массивом ``источник`` — итог в файл ``куда`` (упакованные биты); (бит, описание).

    ``ход(доля, строка)`` — сколько сделано (0…1) и что сейчас; ``отмена()`` — True, если
    пора остановиться (тогда ``Отменено``, недописанный файл удаляется).
    """
    from .rastr import описать_шаг, применить  # noqa: PLC0415
    куда = Path(куда)
    шаги = [ш for ш in шаги if ш.get("вкл", True)]
    сказать = ход or (lambda доля, строка: None)

    def проверить() -> None:
        if отмена is not None and отмена():
            raise Отменено("шаги остановлены")

    if источник.бит <= в_памяти_до:
        сказать(0.0, "весь массив — в памяти")
        биты, описание = применить(источник.все(), шаги, ход=lambda строка: сказать(0.0, строка))
        проверить()
        with Приёмник(куда) as приёмник:
            приёмник.записать(биты)
            бит = приёмник.закрыть()
        сказать(1.0, f"готово: {бит} бит")
        return бит, описание

    # Шаги — участками: подряд идущие потоковые — один проход, слой целиком — свой.
    участки: list[tuple[str, list]] = []
    for номер, шаг in enumerate(шаги, start=1):
        п = потоковый(шаг, окно_синхро)
        if п is not None and участки and участки[-1][0] == "поток":
            участки[-1][1].append((номер, шаг, п))
        elif п is not None:
            участки.append(("поток", [(номер, шаг, п)]))
        else:
            участки.append(("целиком", [(номер, шаг, None)]))
    описание: list[str] = []
    текущий = источник
    временные: list[Path] = []
    try:
        for и, (вид, состав) in enumerate(участки):
            последний = и == len(участки) - 1
            выход = куда if последний else куда.with_name(f"{куда.stem}.шаг{и}.bin")
            if not последний:
                временные.append(выход)

            def доля(часть: float, и=и) -> float:
                return (и + max(0.0, min(1.0, часть))) / len(участки)

            if вид == "поток":
                описание += _поток(текущий, состав, выход, сказать, доля, проверить, кусок_бит)
            else:
                описание += _целиком(текущий, состав[0], выход, сказать, доля, проверить, в_памяти_до,
                                     описать_шаг, применить)
            прежний = текущий
            текущий = Источник(выход, бит=_бит(выход))
            if прежний is not источник and прежний.путь in временные:
                прежний.путь.unlink(missing_ok=True)
    finally:
        for путь in временные:
            путь.unlink(missing_ok=True)
    сказать(1.0, f"готово: {текущий.бит} бит")
    return текущий.бит, описание


_ДЛИНЫ: dict[str, int] = {}


def _бит(путь: Path) -> int:
    return _ДЛИНЫ.pop(str(путь), путь.stat().st_size * 8)


def _поток(источник: Источник, состав, выход: Path, сказать, доля, проверить, кусок_бит: int) -> list[str]:
    шаги = [п for _, _, п in состав]
    вышло = [0] * len(шаги)
    имена = ", ".join(str(ш.get("слой") or ш.get("вид")) for _, ш, _ in состав)
    начало = time.monotonic()
    with Приёмник(выход) as приёмник:
        прочитано = 0
        for кусок in источник.куски(кусок_бит):
            проверить()
            for k, шаг in enumerate(шаги):
                кусок = шаг.подать(кусок)
                вышло[k] += len(кусок)
                if not len(кусок):
                    break
            приёмник.записать(кусок)
            прочитано += кусок_бит
            часть = min(1.0, прочитано / max(1, источник.бит))
            скорость = прочитано / 8 / max(1e-6, time.monotonic() - начало) / (1 << 20)
            сказать(доля(часть), f"{имена}: {min(прочитано, источник.бит) // 8 >> 20} из "
                                 f"{источник.бит // 8 >> 20} МБ ({скорость:.0f} МБ/с)")
        # Остатки по цепочке: что придержал шаг k, проходит через шаги после него.
        for k, шаг in enumerate(шаги):
            хвост = шаг.закончить()
            вышло[k] += len(хвост)
            for j in range(k + 1, len(шаги)):
                хвост = шаги[j].подать(хвост)
                вышло[j] += len(хвост)
            приёмник.записать(хвост)
        for k, (номер, _, _) in enumerate(состав):
            if not вышло[k]:
                raise ValueError(f"после шага {номер} поток пуст")
        бит = приёмник.закрыть()
    _ДЛИНЫ[str(выход)] = бит
    return [ш.описание() for ш in шаги]


def _целиком(источник: Источник, пункт, выход: Path, сказать, доля, проверить, в_памяти_до: int,
             описать_шаг, применить) -> list[str]:
    номер, шаг, _ = пункт
    имя = описать_шаг(шаг)
    if источник.бит <= в_памяти_до:
        сказать(доля(0.0), f"шаг {номер}: {имя} — над всем рядом ({источник.бит} бит)")
        биты, описание = применить(источник.все(), [шаг])
        проверить()
        with Приёмник(выход) as приёмник:
            приёмник.записать(биты)
            _ДЛИНЫ[str(выход)] = приёмник.закрыть()
        return описание
    if not _кусками_можно(шаг):
        raise ValueError(
            f"шаг {номер} «{имя}»: слою нужен весь ряд, а в нём {источник.бит // 8 >> 20} МБ — больше, чем "
            f"обрабатывается в памяти ({в_памяти_до // 8 >> 20} МБ). Сократите ряд (обрезка, усечение, канал "
            f"по маске) или задайте слой явно (вариант плоскости, начальное состояние ПСП)")
    описание: list[str] = []
    кусков = -(-источник.бит // в_памяти_до)
    with Приёмник(выход) as приёмник:
        for н, кусок in enumerate(источник.куски(в_памяти_до), start=1):
            проверить()
            сказать(доля((н - 1) / кусков), f"шаг {номер}: {имя} — кусок {н} из {кусков}")
            биты, о = применить(кусок, [шаг])
            if not описание:
                описание = list(о)
            приёмник.записать(биты)
        _ДЛИНЫ[str(выход)] = приёмник.закрыть()
    описание.append(f"слой выполнен кусками по {в_памяти_до // 8 >> 20} МБ ({кусков} кусков) независимо: ряд "
                    f"больше, чем обрабатывается в памяти; на стыках кусков слой синхронизируется заново")
    return описание
