"""Шаги обработки над большим массивом — потоком, кусками, с записью итога на диск.

Массив в гигабайт целиком в память не берётся (биты — по байту на бит). Шаги
выполняются так:

* массив до ``в_памяти_до`` бит — целиком в памяти, как всегда (``rastr.применить``);
* больше — по кускам: подряд идущие потоковые шаги (обрезка, инверсия, сдвиг,
  самосинхронизирующийся и аддитивный скремблер, xor, прореживание, выбросить и
  вставить биты, реверс в группах, NRZI, накопление, метки и биты символа, ФМ и КАМ с
  заданным вариантом, моддекодер таблицей, канал по маске, разметка, синхронизация и
  выравнивание кадров по синхрокомбинации) пропускают каждый кусок по цепочке, итог
  сразу пишется в файл; кусок за куском — ход, между кусками — проверка отмены;
* слой, которому нужен весь ряд (коды: LDPC, ТКБ, свёрточный, турбо, РС; GFP, V.110…),
  получает ряд целиком, если тот помещается в память, а больше — кусками по
  ``в_памяти_до`` бит независимо (каждый кусок слой синхронизирует заново; об этом —
  строка в описании). Слои, которые кусками дали бы неверный итог (переворот задом
  наперёд, поиск лучшего варианта плоскости без явного варианта), на таком массиве не
  выполняются — с объяснением, что сделать.

Итог потоковых шагов совпадает с итогом в памяти бит в бит (проверяется тестами на
малых массивах с маленькими кусками), описание — тоже. Исключения — поиск
синхрокомбинации («синхро», «кадры»): начало ищется в первых ``ОКНО_СИНХРО`` битах,
на большем массиве счёт вхождений в описании — по этому окну.
"""

from __future__ import annotations

import re
import time
from collections.abc import Callable, Sequence
from pathlib import Path
from typing import Any

import numpy as np

from .hranenie import Источник, Приёмник

#: Кусок, которым идут потоковые шаги (бит).
КУСОК_БИТ = 1 << 26
#: Массив до стольких бит обрабатывается целиком в памяти (64 МБ файла).
В_ПАМЯТИ_ДО = 1 << 29
#: Начало кадров («синхро», «кадры») ищется в стольких первых битах.
ОКНО_СИНХРО = 1 << 26


class Отменено(Exception):
    """Шаги остановлены по просьбе человека."""


# -- потоковые шаги ----------------------------------------------------------------------

class _Шаг:
    """Потоковый шаг: ``подать`` кусок — получить, что готово; ``закончить`` — остаток."""

    что: str = ""

    def подать(self, биты: np.ndarray) -> np.ndarray:
        raise NotImplementedError

    def закончить(self) -> np.ndarray:
        return np.zeros(0, dtype=np.uint8)

    def описание(self) -> str:
        return self.что


def _пусто() -> np.ndarray:
    return np.zeros(0, dtype=np.uint8)


class _ПоГруппам(_Шаг):
    """Слой без памяти между группами по ``g`` бит: ``снять_вручную`` над кусками, выровненными на g.

    Итог куска, начатого с границы группы, — ровно его часть итога над всем рядом. ``хвост`` —
    неполная последняя группа тоже обрабатывается (xor, прореживание), иначе отбрасывается,
    как и в памяти (метки символов). Описание — по первому вызову (у этих слоёв оно от длины
    ряда не зависит); ``хвост_словами`` — строка про отброшенный хвост (моддекодер).
    """

    def __init__(self, указание: str, g: int, хвост: bool = False, хвост_словами: bool = False):
        self.указание, self.g, self.хвост, self.хвост_словами = указание, max(1, int(g)), хвост, хвост_словами
        self._буфер = _пусто()
        self._запись = None
        self._всего = 0

    def _снять(self, биты: np.ndarray) -> np.ndarray:
        from .razbor import снять_вручную  # noqa: PLC0415 — круговой импорт
        ряд, запись = снять_вручную(биты, self.указание)
        if self._запись is None:
            self._запись = запись
        return np.asarray(ряд, dtype=np.uint8)

    def подать(self, биты: np.ndarray) -> np.ndarray:
        self._всего += len(биты)
        if len(self._буфер):
            биты = np.concatenate([self._буфер, биты])
        целых = len(биты) // self.g * self.g
        self._буфер = биты[целых:].copy()
        return self._снять(биты[:целых]) if целых else _пусто()

    def закончить(self) -> np.ndarray:
        остаток, self._буфер = self._буфер, _пусто()
        if self._запись is None:
            # Ряд короче группы: в памяти слой видел бы его целиком — так и здесь.
            return self._снять(остаток)
        return self._снять(остаток) if (self.хвост and len(остаток)) else _пусто()

    def описание(self) -> str:
        if self._запись is None:
            return ""
        подробно = list(self._запись.подробно)
        if self.хвост_словами:
            подробно = [с for с in подробно if not с.startswith("хвост ")]
        if self.хвост_словами and self._всего % self.g:
            подробно.append(f"хвост {self._всего % self.g} бит (не кратен {self.g}) отброшен")
        return self._запись.что + (": " + "; ".join(подробно[:3]) if подробно else "")


class _Сдвиг(_Шаг):
    """Пропустить первые ``n`` бит; ``до`` — оставить не дальше этого бита (усечение)."""

    def __init__(self, от: int, до: int | None = None):
        self.от, self.до, self._место = от, до, 0

    def подать(self, биты: np.ndarray) -> np.ndarray:
        начало, self._место = self._место, self._место + len(биты)
        a = max(0, self.от - начало)
        b = len(биты) if self.до is None else max(0, min(len(биты), self.до - начало))
        return биты[a:b] if a < b else _пусто()


class _Обрезка(_Шаг):
    """Отрезать ``начало`` бит с начала и ``конец`` с конца: последние ``конец`` бит придерживаются."""

    def __init__(self, указание: str, начало: int, конец: int):
        self.указание, self.начало, self.конец = указание, начало, конец
        self._всего = 0
        self._сдвиг = _Сдвиг(начало)
        self._придержано = _пусто()

    def подать(self, биты: np.ndarray) -> np.ndarray:
        self._всего += len(биты)
        биты = self._сдвиг.подать(биты)
        if not self.конец:
            return биты
        биты = np.concatenate([self._придержано, биты]) if len(self._придержано) else биты
        отдать = max(0, len(биты) - self.конец)
        self._придержано = биты[отдать:].copy()
        return биты[:отдать]

    def закончить(self) -> np.ndarray:
        if self.начало + self.конец >= self._всего:
            raise ValueError(f"обрезка: отрезать {self.начало} + {self.конец} бит — не меньше всего потока "
                             f"({self._всего} бит)")
        return _пусто()

    def описание(self) -> str:
        from .razbor import _кратко  # noqa: PLC0415
        осталось = self._всего - self.начало - self.конец
        return (f"снято по указанию: {_кратко(self.указание)}: отрезано с начала {self.начало} бит, с конца "
                f"{self.конец} бит: осталось {осталось} бит из {self._всего}")


class _Усечение(_Шаг):
    def __init__(self, указание: str, от: int, до: int | None, длина: int | None):
        self.указание, self.от = указание, от
        self.конец = от + длина if длина is not None else до
        self._сдвиг = _Сдвиг(от, self.конец)
        self._всего = 0

    def подать(self, биты: np.ndarray) -> np.ndarray:
        self._всего += len(биты)
        return self._сдвиг.подать(биты)

    def закончить(self) -> np.ndarray:
        конец = self._всего if self.конец is None else self.конец
        if not 0 <= self.от < конец <= self._всего:
            raise ValueError(f"усечение: нужно 0 ≤ от < до ≤ {self._всего} — «усечение от N длина M»")
        return _пусто()

    def описание(self) -> str:
        from .razbor import _кратко  # noqa: PLC0415
        конец = self._всего if self.конец is None else self.конец
        return (f"снято по указанию: {_кратко(self.указание)}: оставлены биты {self.от}…{конец - 1} "
                f"({конец - self.от} бит из {self._всего})")


