class _Маска(_Шаг):
    """Канал по маске: после ``сдвиг`` бит — из каждого цикла биты на позициях; неполный цикл — прочь."""

    def __init__(self, шаг: dict[str, Any]):
        from .rastr import описать_шаг  # noqa: PLC0415
        маска = шаг["маска"]
        self.период = int(маска["период"])
        self.позиции = sorted({int(п) for п in маска.get("позиции", []) if 0 <= int(п) < self.период})
        if self.период < 1 or not self.позиции:
            raise ValueError("маска пуста: нужен период и хотя бы одна позиция в цикле")
        self._сдвиг = _Сдвиг(int(маска.get("сдвиг", 0)) % max(1, self.период))
        self._буфер = _пусто()
        self.что = описать_шаг(шаг)

    def подать(self, биты: np.ndarray) -> np.ndarray:
        биты = self._сдвиг.подать(биты)
        if len(self._буфер):
            биты = np.concatenate([self._буфер, биты])
        циклов = len(биты) // self.период
        self._буфер = биты[циклов * self.период:].copy()
        return биты[:циклов * self.период].reshape(циклов, self.период)[:, self.позиции].reshape(-1)


class _Разметка(_Шаг):
    """Взять, убрать или инвертировать размеченные биты: маска считается для окна куска."""

    def __init__(self, шаг: dict[str, Any]):
        from .rastr import описать_шаг  # noqa: PLC0415
        self.разметка, self.действие = шаг["разметка"], шаг["действие"]
        if self.действие not in ("взять", "убрать", "инверсия"):
            raise ValueError("действие с разметкой — взять, убрать или инверсия")
        self._место = 0
        self.что = описать_шаг(шаг)

    def подать(self, биты: np.ndarray) -> np.ndarray:
        маска = маска_окна(self._место, self._место + len(биты), self.разметка)
        self._место += len(биты)
        if self.действие == "взять":
            return биты[маска]
        if self.действие == "убрать":
            return биты[~маска]
        return биты ^ маска.astype(np.uint8)


def маска_окна(от: int, до: int, разметка: dict[str, Any]) -> np.ndarray:
    """Какие из бит [от, до) размечены — то же, что ``rastr.маска_разметки`` над всем рядом, но для окна.

    Правило без «до» в памяти тянется до конца ряда — здесь до конца окна: то же самое.
    """
    маска = np.zeros(до - от, dtype=bool)
    for начало, длина in разметка.get("отрезки") or []:
        a, b = max(от, начало), min(до, начало + длина)
        if a < b:
            маска[a - от:b - от] = True
    for п in разметка.get("правила") or []:
        период = п["период"]
        шаблон = np.zeros(период, dtype=bool)
        шаблон[(п["сдвиг"] + np.arange(п["ширина"])) % период] = True
        a = max(от, п["от"])
        b = min(до, п["до"] or до)
        if a < b:
            # В памяти шаблон кладётся от «от» правила: бит x размечен, если шаблон[x mod период].
            места = np.arange(a, b) % период
            маска[a - от:b - от] |= шаблон[места]
    return маска


class _Синхро(_Шаг):
    """Поток с первой синхрокомбинации (её ищут в первых ``окно`` битах); инверсная — поток инвертируется."""

    def __init__(self, указание: str, образец: np.ndarray, ошибок: int, окно: int):
        self.указание, self.образец, self.ошибок, self.окно = указание, образец, ошибок, окно
        self._буфер: list[np.ndarray] = []
        self._в_буфере = 0
        self._найдено: dict[str, Any] | None = None
        self._сдвиг: _Сдвиг | None = None

    def _найти(self) -> np.ndarray:
        from . import sinhro  # noqa: PLC0415
        ряд = np.concatenate(self._буфер) if self._буфер else _пусто()
        self._буфер, self._в_буфере = [], 0
        найдено = sinhro.найти(ряд, self.образец, self.ошибок)
        if найдено["начало"] is None:
            raise ValueError(f"синхрокомбинация {найдено['слово']} не найдена")
        self._найдено = найдено
        self._сдвиг = _Сдвиг(найдено["начало"])
        return self._выход(ряд)

    def _выход(self, биты: np.ndarray) -> np.ndarray:
        ряд = self._сдвиг.подать(биты)
        return (1 - ряд).astype(np.uint8) if self._найдено["инверсия"] else ряд

    def подать(self, биты: np.ndarray) -> np.ndarray:
        if self._найдено is not None:
            return self._выход(биты)
        self._буфер.append(биты)
        self._в_буфере += len(биты)
        return self._найти() if self._в_буфере >= self.окно else _пусто()

    def закончить(self) -> np.ndarray:
        return self._найти() if self._найдено is None else _пусто()

    def описание(self) -> str:
        from . import sinhro  # noqa: PLC0415
        from .razbor import _кратко  # noqa: PLC0415
        н = self._найдено or {}
        подробно = [sinhro.описать(н), f"поток начат с бита {н.get('начало')}" +
                    (" и инвертирован: синхрокомбинация шла инверсной" if н.get("инверсия") else "")]
        return f"снято по указанию: {_кратко(self.указание)}: " + "; ".join(подробно)


class _Кадры(_Шаг):
    """Кадры по синхрокомбинации с маховиком (``sinhro.выровнять``) — потоком.

    Перед каждым кадром нужно знать несовпадения на ``окно`` бит вокруг ожидаемого
    места: кусок обрабатывается, пока за текущим кадром есть запас; остаток ждёт
    следующего куска, а последний — обрабатывается в ``закончить`` как в памяти.
    """

    def __init__(self, указание: str, образец: np.ndarray, длина: int, ошибок: int, окно_синхро: int):
        from . import sinhro  # noqa: PLC0415
        if длина < len(образец):
            raise ValueError("кадр не может быть короче синхрокомбинации")
        self.указание, self.образец, self.длина, self.ошибок = указание, образец, длина, ошибок
        self.окно = sinhro.ОКНО_ПОИСКА
        self._синхро = _Синхро(указание, образец, ошибок, окно_синхро)
        self._ряд = _пусто()
        self._место = 0
        self.на_месте = self.нет = self.проскальзываний = self.кадров = 0
        self._готово = False

    def _кадры(self, последний: bool) -> np.ndarray:
        from . import sinhro  # noqa: PLC0415
        if self._готово:
            return _пусто()
        биты, L, длина, окно = self._ряд, len(self.образец), self.длина, self.окно
        н = sinhro.несовпадения(биты, self.образец)
        место, кадры = self._место, []
        # Не последний кусок: кадр берётся, только если впереди хватает бит и на кадр, и на поиск
        # синхрокомбинации у следующего — тогда решение то же, что над всем рядом.
        запас = 0 if последний else длина + окно + L + 1
        while место + длина <= len(биты) and (последний or место + запас + длина <= len(биты)):
            if н[место] <= self.ошибок:
                self.на_месте += 1
            else:
                от, до = max(0, место - окно), min(len(н), место + окно + 1)
                рядом = np.flatnonzero(н[от:до] <= self.ошибок)
                if len(рядом):
                    место = от + int(рядом[np.argmin(np.abs(рядом + от - место))])
                    self.проскальзываний += 1
                    if место + длина > len(биты):
                        self._готово = True
                        break
                else:
                    self.нет += 1
            кадры.append(биты[место:место + длина])
            место += длина
        # Сзади держим окно поиска: проскальзывание может уйти назад на ``окно`` бит.
        отрезать = max(0, место - окно)
        self._ряд = биты[отрезать:].copy()
        self._место = место - отрезать
        self.кадров += len(кадры)
        return np.concatenate(кадры) if кадры else _пусто()

    def подать(self, биты: np.ndarray) -> np.ndarray:
        биты = self._синхро.подать(биты)
        if not len(биты):
            return _пусто()
        self._ряд = np.concatenate([self._ряд, биты]) if len(self._ряд) else биты
        return self._кадры(последний=False)

    def закончить(self) -> np.ndarray:
        хвост = self._синхро.закончить()
        if len(хвост):
            self._ряд = np.concatenate([self._ряд, хвост]) if len(self._ряд) else хвост
        итог = self._кадры(последний=True)
        if not self.кадров:
            raise ValueError("ни одного целого кадра")
        return итог

    def описание(self) -> str:
        from . import sinhro  # noqa: PLC0415
        from .razbor import _кратко  # noqa: PLC0415
        н = self._синхро._найдено or {}
        return (f"снято по указанию: {_кратко(self.указание)}: кадров {self.кадров} по {self.длина} бит от "
                f"синхрокомбинации {sinhro.словами(self.образец) if not н else н['слово']}: на месте {self.на_месте}, "
                f"нет на месте {self.нет}, проскальзываний {self.проскальзываний}")


