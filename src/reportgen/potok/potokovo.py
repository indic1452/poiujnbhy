class _Nrzi(_Простой):
    """y[0] = 0, y[i] = x[i] ≠ x[i−1]: помнится последний бит прошлого куска."""

    def __init__(self, указание: str):
        super().__init__(указание)
        self._прежний: int | None = None

    def подать(self, биты: np.ndarray) -> np.ndarray:
        if not len(биты):
            return _пусто()
        прежний = биты[0] if self._прежний is None else self._прежний
        self._прежний = int(биты[-1])
        ряд = np.empty(len(биты), dtype=np.uint8)
        ряд[0] = 0 if прежний == биты[0] else 1
        ряд[1:] = биты[1:] != биты[:-1]
        return ряд


class _Накопление(_Простой):
    def __init__(self, указание: str):
        super().__init__(указание, ["накопление по модулю 2 (дифференциальный кодер): y[i] = y[i−1] ⊕ x[i]"])
        self._было = 0

    def подать(self, биты: np.ndarray) -> np.ndarray:
        if not len(биты):
            return _пусто()
        ряд = np.bitwise_xor.accumulate(np.asarray(биты, dtype=np.uint8))
        if self._было:
            ряд ^= 1
        self._было = int(ряд[-1])
        return ряд


class _Скремблер(_Простой):
    """Мультипликативный: x[n] = y[n] ⊕ y[n−a] ⊕ …; первые max(a) бит уходят."""

    def __init__(self, указание: str, отводы: Sequence[int]):
        from . import skrembler  # noqa: PLC0415
        super().__init__(указание, [f"полином {skrembler.полином_словами(отводы)}"])
        self.отводы = [int(о) for о in отводы]
        self.степень = max(self.отводы)
        self._история = _пусто()

    def подать(self, биты: np.ndarray) -> np.ndarray:
        if not len(биты):
            return _пусто()
        ряд = np.concatenate([self._история, биты]) if len(self._история) else np.asarray(биты, dtype=np.uint8)
        выход = ряд.copy()
        for отвод in self.отводы:
            выход[отвод:] ^= ряд[:-отвод]
        начало = len(self._история)
        self._история = ряд[-self.степень:].copy()
        # Пока история короче степени, первые биты ряда — те, что уходят и в памяти.
        return выход[max(начало, self.степень):]


class _Вставить(_Шаг):
    """На каждое k-е место с фазы f — бит b; свои биты — подряд на прочие места."""

    def __init__(self, указание: str, k: int, фаза: int, бит: int):
        self.указание, self.k, self.фаза, self.бит = указание, k, фаза, бит
        self._свои = 0                     # сколько своих бит уже поставлено
        self._выдано = 0                   # сколько бит итога уже выдано
        прочие = [r for r in range(k) if r != фаза]
        self._места = np.asarray(прочие, dtype=np.int64)

    def подать(self, биты: np.ndarray) -> np.ndarray:
        n = len(биты)
        if not n:
            return _пусто()
        j = np.arange(self._свои, self._свои + n, dtype=np.int64)
        места = j // (self.k - 1) * self.k + self._места[j % (self.k - 1)]
        конец = int(места[-1]) + 1
        ряд = np.full(конец - self._выдано, self.бит, dtype=np.uint8)
        ряд[места - self._выдано] = биты
        self._свои += n
        self._выдано = конец
        return ряд

    def описание(self) -> str:
        from .razbor import _кратко  # noqa: PLC0415
        return (f"снято по указанию: {_кратко(self.указание)}: вставлен бит {self.бит} на каждое {self.k}-е "
                f"место с {self.фаза}-го: {self._выдано} бит")


class _Пилоты(_Шаг):
    """Вырезать периодическую вставку («пилоты|вставка период P места …»): места периода — от бита 0
    всего потока, как ``vstavka.снять``; совпадение со «значения» — по всем местам вставки."""

    def __init__(self, указание: str):
        from . import vstavka  # noqa: PLC0415
        self.указание = указание
        self.в = vstavka.разобрать_слой(указание.strip().lower())
        self._оставить = vstavka.маска(self.в.период, self.в)
        self._значения = np.array([int(ч) for ч in self.в.значения], dtype=np.uint8)
        self._место = self._вышло = self._на_местах = self._совпало = 0

    def подать(self, биты: np.ndarray) -> np.ndarray:
        маска = np.resize(np.roll(self._оставить, -(self._место % self.в.период)), len(биты))
        self._место += len(биты)
        ряд = биты[маска]
        self._вышло += len(ряд)
        if len(self._значения):
            на_местах = биты[~маска]
            ожидаемо = np.resize(np.roll(self._значения, -(self._на_местах % len(self._значения))), len(на_местах))
            self._совпало += int(np.count_nonzero(на_местах == ожидаемо))
            self._на_местах += len(на_местах)
        return ряд

    def описание(self) -> str:
        from .razbor import _кратко  # noqa: PLC0415
        в = self.в
        подробно = [f"вырезаны места {','.join(map(str, в.места))} каждого периода {в.период} бит "
                    f"(от начала потока): {self._место} → {self._вышло} бит"]
        if в.значения:
            доля = self._совпало / self._на_местах if self._на_местах else float("nan")
            подробно.append(f"на местах вставки значения {в.значения} совпали у {доля * 100:.2f} % бит")
        return f"снято по указанию: {_кратко(self.указание.strip())}: " + "; ".join(подробно)


class _Пары(_Шаг):
    """«пары [обмен] [инв 1] [инв 2] [фаза 1]»: пары бит с фазы — кусок начинается с начала пары, бит без
    пары в конце куска ждёт следующего (в конце потока — как у ``simvoly.Симметрия.применить``)."""

    def __init__(self, указание: str):
        from . import simvoly  # noqa: PLC0415
        from .razbor import _кратко  # noqa: PLC0415
        self.симметрия, self.фаза = simvoly.разобрать_слой(указание.strip().lower())
        self.что = f"снято по указанию: {_кратко(указание.strip())}: пары бит с {self.фаза}-го: {self.симметрия.имя()}"
        self._буфер = _пусто()
        self._место = 0                    # номер в потоке первого бита буфера

    def _взять(self, ряд: np.ndarray) -> np.ndarray:
        с = self.симметрия
        итог = np.empty(len(ряд), dtype=np.uint8)
        a = (self.фаза - self._место) % 2                  # 1 — первый бит без пары (бит 0 при фазе 1)
        if a and len(ряд):
            итог[0] = с.взять(ряд[:1], np.zeros(1, np.int64), 1)[0]
        пар = (len(ряд) - a) // 2
        if пар:
            п = ряд[a:a + 2 * пар].reshape(пар, 2)
            if с.обмен:
                п = п[:, ::-1]
            итог[a:a + 2 * пар] = (п ^ np.array([с.инв_первого, с.инв_второго], dtype=np.uint8)).reshape(-1)
        if a + 2 * пар < len(ряд):
            итог[-1] = с.взять(ряд[-1:], np.zeros(1, np.int64), 0)[0]
        return итог

    def подать(self, биты: np.ndarray) -> np.ndarray:
        ряд = np.concatenate([self._буфер, биты]) if len(self._буфер) else биты
        n = len(ряд)
        if n and (self._место + n - 1 - self.фаза) % 2 == 0:
            n -= 1                                         # последний бит — первый в паре: ждёт второго
        итог = self._взять(ряд[:n])
        self._буфер = ряд[n:].copy()
        self._место += n
        return итог

    def закончить(self) -> np.ndarray:
        итог = self._взять(self._буфер)
        self._буфер = _пусто()
        return итог


class _Относительный(_ПоГруппам):
    """«моддекодер k относительная: …»: разность номеров точек — с последним символом прошлого куска."""

    def __init__(self, указание: str):
        from . import moddekoder  # noqa: PLC0415
        self._д = moddekoder.из_слоя(указание.strip())
        super().__init__(указание, self._д.k, хвост_словами=True)
        self._прежний = 0                  # номер точки прошлого символа (первый символ — от номера 0)

    def _снять(self, биты: np.ndarray) -> np.ndarray:
        ряд = super()._снять(биты)
        k = self.g
        n = len(биты) // k
        if n:
            веса = 1 << np.arange(k - 1, -1, -1)
            первый, последний = (int((биты[i * k:(i + 1) * k].astype(np.int64) * веса).sum()) for i in (0, n - 1))
            метка = self._д.метки[(self._д.номера[первый] - self._прежний) % (1 << k)]
            ряд[:k] = (метка >> np.arange(k - 1, -1, -1)) & 1
            self._прежний = self._д.номера[последний]
        return ряд


class _Pdh(_Шаг):
    """«pdh E2|E3|E4 приток N»: начало цикла — по первым ``pdh.ВЫБОРКА`` битам (как в памяти), дальше
    приток из целых циклов кусок за куском: Cj и возможность стаффинга у каждого цикла — свои."""

    def __init__(self, указание: str):
        from . import pdh  # noqa: PLC0415
        self.указание = указание
        self.иерархия, self.t = pdh.слой(указание)
        self._буфер: list[np.ndarray] = []
        self._в_буфере = 0
        self._найдено: tuple[int, float] | None = None
        self._сдвиг: _Сдвиг | None = None
        self._хвост = _пусто()
        self.пустых = self.циклов = 0

    def _циклы(self, биты: np.ndarray) -> np.ndarray:
        from . import pdh  # noqa: PLC0415
        биты = self._сдвиг.подать(биты)
        if len(self._хвост):
            биты = np.concatenate([self._хвост, биты])
        L = self.иерархия.цикл
        целых = len(биты) // L * L
        self._хвост = биты[целых:].copy()
        ряд, пустых, циклов = pdh.приток(биты[:целых], self.иерархия, 0, self.t)
        self.пустых += пустых
        self.циклов += циклов
        return ряд

    def _найти(self) -> np.ndarray:
        from . import pdh  # noqa: PLC0415
        ряд = np.concatenate(self._буфер) if self._буфер else _пусто()
        self._буфер, self._в_буфере = [], 0
        self._найдено = pdh._начало_цикла(ряд[:pdh.ВЫБОРКА], self.иерархия)
        if self._найдено is None:
            raise ValueError(f"цикл {self.иерархия.имя} не найден")
        self._сдвиг = _Сдвиг(self._найдено[0])
        return self._циклы(ряд)

    def подать(self, биты: np.ndarray) -> np.ndarray:
        from . import pdh  # noqa: PLC0415
        if self._найдено is not None:
            return self._циклы(биты)
        self._буфер.append(биты)
        self._в_буфере += len(биты)
        return self._найти() if self._в_буфере >= pdh.ВЫБОРКА else _пусто()

    def закончить(self) -> np.ndarray:
        return self._найти() if self._найдено is None else _пусто()

    def описание(self) -> str:
        from . import pdh  # noqa: PLC0415
        from .razbor import _кратко  # noqa: PLC0415
        начало, совпало = self._найдено or (0, 0.0)
        return (f"снято по указанию: {_кратко(self.указание.strip())}: "
                + pdh.описать_слой(self.иерархия, начало, совпало, self.t, self.пустых, self.циклов))


class _Gfp(_Шаг):
    """«gfp …»: окнами по ``gfp.БИТ_ДО`` (``gfp.ОкнаGFP``) кусок за куском — те же кадры и окна, что у слоя над
    всем массивом в памяти; держится окно и кусок. Описание — как у слоя: счёт кадров — по всем окнам."""

    def __init__(self, указание: str):
        from . import gfp  # noqa: PLC0415
        self.указание = указание
        self.п = gfp.разобрать_указание(указание.strip().lower())
        self._буфер: list[np.ndarray] = []
        self._база = 0                     # номер в потоке первого бита буфера
        self._всего = 0
        self._окна = None
        self._р: Any = None                # следующее окно (первое — найдено заранее)
        self._р0: Any = None
        self._одно: Any = None             # массив не длиннее окна: разбор разом
        self._счёт: Any = None
        self._потерь = self._байт = 0

    def _массив(self) -> np.ndarray:
        if len(self._буфер) > 1:
            self._буфер = [np.concatenate(self._буфер)]
        return self._буфер[0] if self._буфер else _пусто()

    def _окна_готовые(self, последние: bool) -> np.ndarray:
        from collections import Counter  # noqa: PLC0415

        from . import gfp  # noqa: PLC0415
        п, части = self.п, []
        if self._окна is None:
            от = п["с_бита"]
            if self._всего <= от + gfp.БИТ_ДО and not последние:
                return _пусто()
            if от and от >= self._всего:
                raise ValueError(f"GFP: с бита {от} — за концом массива ({self._всего} бит)")
            ряд = self._массив()[от - self._база:от - self._база + gfp.БИТ_ДО]
            р, причина = gfp.разобрать_с_причиной(ряд, маска=п["маска"], скремблер=п["скремблер"], порядок=п["порядок"],
                                                  многочлен=п["многочлен"], от_бита=от, всего_бит=self._всего)
            if р is None:
                raise ValueError("GFP: " + (причина or "заголовков с верным cHEC подряд не найдено"
                                            + ("" if п["маска"] == "авто" else f" с маской {п['маска']:08X}")))
            if self._всего <= от + gfp.БИТ_ДО:
                self._одно = р
                итог = gfp.выход(р, п["выход"], п["канал"])
                self._байт = len(итог) // 8
                return итог
            self._окна, self._р, self._р0, self._счёт = gfp.ОкнаGFP(р, от), р, р, Counter()
        о = self._окна
        while True:
            последнее = последние and о.старт + gfp.БИТ_ДО >= self._всего
            if not последнее and self._всего <= о.старт + gfp.БИТ_ДО:
                break                                       # окну нужно больше бит
            р = self._р if self._р is not None else о.разобрать(
                self._массив()[о.старт - self._база:о.старт - self._база + gfp.БИТ_ДО])
            self._р = None
            взяты, потери = о.взять(р, последнее)
            if р is not None:
                части.append(gfp.выход(р, п["выход"], п["канал"], взяты))
                self._счёт += gfp.счёт_кадров(р, взяты)
                self._потерь += len(потери)
            if последнее:
                break
            self._буфер = [self._массив()[о.старт - self._база:].copy()]
            self._база = о.старт
        итог = np.concatenate(части) if части else _пусто()
        self._байт += len(итог) // 8
        return итог

    def подать(self, биты: np.ndarray) -> np.ndarray:
        self._буфер.append(биты)
        self._всего += len(биты)
        return self._окна_готовые(последние=False)

    def закончить(self) -> np.ndarray:
        return self._окна_готовые(последние=True)

    def описание(self) -> str:
        from . import gfp  # noqa: PLC0415
        from .razbor import _кратко  # noqa: PLC0415
        п = self.п
        if self._одно is not None:
            подробно = gfp.строки_сводки(self._одно)
        else:
            подробно = gfp.строки_сводки(self._р0)
            подробно[2] = gfp.строка_кадров(self._счёт)
            подробно = [с for с in подробно if not с.startswith(("разобраны биты", "потерь синхронизации"))]
            подробно += ([f"потерь синхронизации: {self._потерь}"] if self._потерь else []) + [
                f"разобран весь массив окнами по {gfp.БИТ_ДО} бит ({self._окна.окон} окон)"]
        подробно.append(f"выход — {п['выход']}" + (f", канал CID {п['канал']}" if п["канал"] is not None else "")
                        + f": {self._байт} байт")
        return f"снято по указанию: {_кратко(self.указание.strip())}: " + "; ".join(подробно[:3])


class _Свёртка(_Шаг):
    """«свёрточный …», «выколотый …», «нск …»: выравнивание — по первым ``razbor.проба_слоя`` битам (как в
    памяти), дальше Витерби по мере прихода потока (``kod.ВитербиПоток``) — бит в бит как над всем рядом;
    «кольцо L» — блоки сами по себе."""

    def __init__(self, указание: str):
        from .razbor import проба_слоя  # noqa: PLC0415
        self.указание, self.слова = указание, указание.strip().lower()
        self.проба = проба_слоя(self.слова)
        self._буфер: list[np.ndarray] = []
        self._в_буфере = 0
        self.план: dict | None = None
        self._декодер = None
        self._мил_сдвиг: _Сдвиг | None = None
        self._хвост = _пусто()            # неполный период MIL или блок кольца
        self._сдвиг: _Сдвиг | None = None
        self._кольцо = [0, 0]             # бит в блоках, расхождений

    def _начать(self) -> np.ndarray:
        from . import kod  # noqa: PLC0415
        from .razbor import план_свёртки  # noqa: PLC0415
        ряд = np.concatenate(self._буфер) if self._буфер else _пусто()
        self._буфер = []
        п = self.план = план_свёртки(ряд[:self.проба], self.слова)
        if п["мил"]:
            self._мил_сдвиг = _Сдвиг(п["мил"][0])
        if not п["кольцо"]:
            self._декодер = kod.ВитербиПоток(п["многочлены"], п["K"], п["шаблон"])
            self._сдвиг = _Сдвиг(п["сдвиг"])
        return self._дальше(ряд)

    def _целые(self, биты: np.ndarray, g: int) -> np.ndarray:
        биты = np.concatenate([self._хвост, биты]) if len(self._хвост) else биты
        целых = len(биты) // g * g
        self._хвост = биты[целых:].copy()
        return биты[:целых]

    def _дальше(self, биты: np.ndarray) -> np.ndarray:
        from .razbor import _мил, кольцо_блоками  # noqa: PLC0415
        п = self.план
        if п["мил"]:
            биты = _мил(self._целые(self._мил_сдвиг.подать(биты), п["мил"][1]), 0, п["мил"][1])
        if п["кольцо"]:
            данные, расхождений, бит = кольцо_блоками(self._целые(биты, len(п["многочлены"]) * п["кольцо"]),
                                                       п["многочлены"], п["K"], п["кольцо"])
            self._кольцо[0] += бит
            self._кольцо[1] += расхождений
            return данные
        return self._декодер.подать(self._сдвиг.подать(биты))

    def подать(self, биты: np.ndarray) -> np.ndarray:
        if self.план is not None:
            return self._дальше(биты)
        self._буфер.append(биты)
        self._в_буфере += len(биты)
        return self._начать() if self._в_буфере >= self.проба else _пусто()

    def закончить(self) -> np.ndarray:
        итог = self._начать() if self.план is None else _пусто()
        п = self.план
        if п["кольцо"]:
            if not self._кольцо[0]:
                raise ValueError(f"кольцо: поток короче одного блока ({len(п['многочлены']) * п['кольцо']} бит)")
            return итог
        return np.concatenate([итог, self._декодер.закончить()])

    def описание(self) -> str:
        from .razbor import _кратко, строка_кольца  # noqa: PLC0415
        п = self.план or {"подробно": [], "кольцо": None}
        подробно = list(п["подробно"])
        if п["кольцо"]:
            подробно.insert(0, строка_кольца(п["кольцо"], self._кольцо[0], self._кольцо[1], len(п["многочлены"])))
        return f"снято по указанию: {_кратко(self.указание.strip())}" + (": " + "; ".join(подробно[:3]) if подробно else "")


