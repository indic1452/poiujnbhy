def _сетка(источник: Источник, шаг: dict[str, Any]) -> tuple[int, int, str] | None:
    """Куски по сетке слов или кадров, чтобы стык не рвал слово: (начало сетки, период, слой для кусков после
    первого). У «ldpc … начало N [шаг M] [маска C]» — слова с N через M (маска — через C·M); у «plframe …» —
    кадры PLFRAME (первый и длина — по заголовкам начала массива); у «рс N K … сдвиг S» — блоки РС с бита S
    (кускам после первого — «сдвиг 0»); у ТКБ — см. ``_сетка_ткб``; у «4b5b»/«8b10b» — символы с выравнивания
    по началу массива. Иначе — None (куски как есть)."""
    слой = str(шаг.get("слой", "")).strip()
    вид = слой.lower().split()[:1]
    if not вид:
        return None
    try:
        if вид[0] == "ldpc" and re.search(r"начал\w*\s+\d+", слой) and not re.search(r"синхро\s", слой):
            from . import ldpc  # noqa: PLC0415
            начало = int(re.search(r"начал\w*\s+(\d+)", слой).group(1))
            шаг_ = re.search(r"шаг\s+(\d+)", слой)
            период = int(шаг_.group(1)) if шаг_ else ldpc.из_указания(слой)[0].длина
            маска = re.search(r"маск\w*\s+(\d+)", слой)
            период *= max(1, int(маска.group(1))) if маска else 1
            return начало, период, re.sub(r"(начал\w*\s+)\d+", r"\g<1>0", слой, count=1)
        if вид[0] == "plframe":
            from . import dvbs2_pl  # noqa: PLC0415
            з = dvbs2_pl.найти_с_кадрами(источник.биты(0, min(источник.бит, 1 << 24)))
            с = (з.свойства or {}) if з is not None else {}
            if с.get("fec_кадры") is not None and с.get("шаг") and с.get("первый") is not None:
                return int(с["первый"]), int(с["шаг"]), слой
        if вид[0] in ("tpc", "тпк", "ткб"):
            return _сетка_ткб(слой)
        if вид[0] in ("4b5b", "4b/5b", "8b10b", "8b/10b"):
            # Символы кода в линии — с выравнивания по началу массива (как у слоя): стыки — на границах символов.
            from . import lineynye  # noqa: PLC0415
            ширина = 5 if вид[0].startswith("4b") else 10
            сдвиг = lineynye.выравнивание(источник.биты(0, min(источник.бит, lineynye.ВЫБОРКА)), ширина)
            return None if сдвиг is None else (сдвиг, ширина, слой)
        if вид[0] in ("рс", "rs") and re.search(r"сдвиг\s+\d+", слой, re.I) and not re.search(r"вслеп|iess|перемеж", слой, re.I):
            # «рс N K … сдвиг S [кадр L блоки …]»: блоки с бита S через N·I·m (в кадрах — через L).
            from . import rs_slepoy  # noqa: PLC0415
            п = rs_slepoy.разобрать_слой(слой)
            return (int(п["сдвиг"]), int(п["кадр"] or п["N"] * п["I"] * п["m"]),
                    re.sub(r"(сдвиг\s+)\d+", r"\g<1>0", слой, count=1, flags=re.I))
    except (ValueError, KeyError, AttributeError):
        return None
    return None


def _заменить(слой: str, слово: str, значение: int) -> str:
    return re.sub(rf"(?<!\w)({слово}\s+)\d+", rf"\g<1>{значение}", слой, count=1, flags=re.I)


def _сетка_ткб(слой: str) -> tuple[int, int, str] | None:
    """Сетка блоков ТКБ (см. ``_сетка``), если слой задаёт их место:

    * «ткб режим ИМЯ [кадр T] фаза φ» — блоки с φ через T; с «метки P L φм [инверсия m s]» — метки
      выбрасываются раньше: стык ставится на начало метки k, за которой в ряду без меток начинается
      блок (φм + k·(P − L) ≡ φ по модулю T), кускам после первого — «фаза 0», «метки P L 0», номер
      инвертированной метки — от этой;
    * «tpc строка n1 столбец n2 [блок b] [глубина n3 плоскость p] начало o» (двумерный или с глубиной) —
      блоки с o + (b + p·n2)·n1 через n1·n2·n3; в кадрах модема («кадр L строк R с бита S») — стык на
      начале кадра, с которого строки ложатся на начало блока; кускам после первого — блок и плоскость 0
      (и начало 0 или «с бита 0»).
    """
    from . import tpc_rezhimy  # noqa: PLC0415
    from .razbor import _число_после  # noqa: PLC0415
    с = слой.lower()
    if re.search(r"(?<!\w)режим\s+\S", с):
        фаза = _число_после(с, r"фаза\b")
        if фаза is None:
            return None                     # фаза ищется по каждому куску — независимо
        р = tpc_rezhimy.режим(re.search(r"(?<!\w)режим\s+(\S+)", с).group(1))
        бит_укор = _число_после(с, r"укорочение\b")
        метки = tpc_rezhimy.метки_из_текста(с)
        T = _число_после(с, r"кадр\b")
        if метки is None:
            T = int(T or р.кадр or tpc_rezhimy.геометрия(р, бит_укор=бит_укор).передаётся)
            return фаза % T, T, _заменить(слой, "фаза", 0)
        T = int(T or tpc_rezhimy.геометрия(р, бит_укор=бит_укор).передаётся)
        P, L, φ = метки.период, метки.длина, метки.начало
        g = math.gcd(P - L, T)
        if (фаза - φ) % g:
            return None
        Tg = T // g
        k0 = (фаза - φ) // g * pow((P - L) // g, -1, Tg) % Tg if Tg > 1 else 0
        K = math.lcm(Tg, метки.через) if метки.через else Tg
        новые = tpc_rezhimy.Метки(P, L, 0, "", метки.через, (метки.инв - k0) % метки.через if метки.через else 0)
        кускам = re.sub(r"(?<!\w)метки\s+\d+\s+\d+\s+\d+(?:\s+инверсия\s+\d+\s+\d+)?", новые.текст(),
                        _заменить(слой, "фаза", 0), count=1, flags=re.I)
        return φ + k0 * P, K * P, кускам
    n1, n2, o = _число_после(с, r"строка\b"), _число_после(с, "столбец"), _число_после(с, r"начало\b")
    n3 = _число_после(с, "глубина")
    if not n1 or not n2 or o is None or not (n3 or "двумерн" in с):
        return None
    в_блоке = n2 * (n3 or 1)                # строк в блоке
    B0 = (_число_после(с, "блок") or 0) % n2 + ((_число_после(с, "плоскость") or 0) % n3 * n2 if n3 else 0)
    кускам = _заменить(_заменить(слой, "блок", 0), "плоскость", 0)
    кадр = _число_после(с, r"кадр\b")
    if кадр is None:
        return o % n1 + B0 * n1, n1 * в_блоке, _заменить(кускам, r"начало\b", 0)
    R, S = _число_после(с, r"строк\b"), _число_после(с, r"с\s+бита")
    if not R or S is None:
        return None
    g = math.gcd(R, в_блоке)
    if B0 % g:
        return None
    Bg = в_блоке // g
    F0 = B0 // g * pow(R // g, -1, Bg) % Bg if Bg > 1 else 0
    return S % кадр + F0 * кадр, Bg * кадр, _заменить(кускам, r"с\s+бита", 0)


def _кусками_можно(шаг: dict[str, Any]) -> bool:
    вид = str(шаг.get("слой", "")).strip().lower().split()[:1]
    return bool(вид) and any(вид[0].startswith(п) for п in КУСКАМИ)


def выполнить(источник: Источник, шаги: Sequence[dict[str, Any]], куда: str | Path, *,
              ход: Callable[[float, str], None] | None = None,
              отмена: Callable[[], bool] | None = None,
              кусок_бит: int = КУСОК_БИТ, в_памяти_до: int = В_ПАМЯТИ_ДО,
              окно_синхро: int = ОКНО_СИНХРО,
              свойства: list[dict[str, Any]] | None = None) -> tuple[int, list[str]]:
    """Шаги над массивом ``источник`` — итог в файл ``куда`` (упакованные биты); (бит, описание).

    ``ход(доля, строка)`` — сколько сделано (0…1) и что сейчас; ``отмена()`` — True, если
    пора остановиться (тогда ``Отменено``, недописанный файл удаляется). ``свойства`` — сюда по
    шагу-слою складываются свойства его находки (как у ``rastr.применить``: у ТКБ — блок, кадр).
    """
    from .rastr import описать_шаг, применить  # noqa: PLC0415
    куда = Path(куда)
    шаги = [ш for ш in шаги if ш.get("вкл", True)]
    сказать = ход or (lambda доля, строка: None)

    def проверить() -> None:
        if отмена is not None and отмена():
            raise Отменено("шаги остановлены")

    if источник.бит <= в_памяти_до:
        сказать(0.0, "весь массив — в памяти")
        with _с_ходом_слоя(сказать, проверить, lambda часть: часть):
            биты, описание = применить(источник.все(), шаги, ход=lambda строка: сказать(0.0, строка), свойства=свойства)
        проверить()
        with Приёмник(куда) as приёмник:
            приёмник.записать(биты)
            бит = приёмник.закрыть()
        сказать(1.0, f"готово: {бит} бит")
        return бит, описание

    # Шаги — участками: подряд идущие потоковые — один проход, слой целиком — свой.
    участки: list[tuple[str, list]] = []
    for номер, шаг in enumerate(шаги, start=1):
        п = потоковый(шаг, окно_синхро)
        if п is not None and участки and участки[-1][0] == "поток":
            участки[-1][1].append((номер, шаг, п))
        elif п is not None:
            участки.append(("поток", [(номер, шаг, п)]))
        else:
            участки.append(("целиком", [(номер, шаг, None)]))
    описание: list[str] = []
    текущий = источник
    временные: list[Path] = []
    try:
        for и, (вид, состав) in enumerate(участки):
            последний = и == len(участки) - 1
            выход = куда if последний else куда.with_name(f"{куда.stem}.шаг{и}.bin")
            if not последний:
                временные.append(выход)

            def доля(часть: float, и=и) -> float:
                return (и + max(0.0, min(1.0, часть))) / len(участки)

            if вид == "поток":
                описание += _поток(текущий, состав, выход, сказать, доля, проверить, кусок_бит)
                if свойства is not None:
                    свойства += [dict(getattr(getattr(п, "_запись", None), "свойства", None) or {})
                                 for _, ш, п in состав if ш["вид"] == "слой"]
            else:
                описание += _целиком(текущий, состав[0], выход, сказать, доля, проверить, в_памяти_до,
                                     описать_шаг, применить, свойства)
            прежний = текущий
            текущий = Источник(выход, бит=_бит(выход))
            if прежний is not источник and прежний.путь in временные:
                прежний.путь.unlink(missing_ok=True)
    finally:
        for путь in временные:
            путь.unlink(missing_ok=True)
    сказать(1.0, f"готово: {текущий.бит} бит")
    return текущий.бит, описание


_ДЛИНЫ: dict[str, int] = {}


def _бит(путь: Path) -> int:
    return _ДЛИНЫ.pop(str(путь), путь.stat().st_size * 8)


def _поток(источник: Источник, состав, выход: Path, сказать, доля, проверить, кусок_бит: int) -> list[str]:
    шаги = [п for _, _, п in состав]
    вышло = [0] * len(шаги)
    имена = ", ".join(str(ш.get("слой") or ш.get("вид")) for _, ш, _ in состав)
    начало = time.monotonic()
    with Приёмник(выход) as приёмник:
        прочитано = 0
        for кусок in источник.куски(кусок_бит):
            проверить()
            for k, шаг in enumerate(шаги):
                кусок = шаг.подать(кусок)
                вышло[k] += len(кусок)
                if not len(кусок):
                    break
            приёмник.записать(кусок)
            прочитано += кусок_бит
            часть = min(1.0, прочитано / max(1, источник.бит))
            скорость = прочитано / 8 / max(1e-6, time.monotonic() - начало) / (1 << 20)
            сказать(доля(часть), f"{имена}: {min(прочитано, источник.бит) // 8 >> 20} из "
                                 f"{источник.бит // 8 >> 20} МБ ({скорость:.0f} МБ/с)")
        # Остатки по цепочке: что придержал шаг k, проходит через шаги после него.
        for k, шаг in enumerate(шаги):
            хвост = шаг.закончить()
            вышло[k] += len(хвост)
            for j in range(k + 1, len(шаги)):
                хвост = шаги[j].подать(хвост)
                вышло[j] += len(хвост)
            приёмник.записать(хвост)
        for k, (номер, _, _) in enumerate(состав):
            if not вышло[k]:
                raise ValueError(f"после шага {номер} поток пуст")
        бит = приёмник.закрыть()
    _ДЛИНЫ[str(выход)] = бит
    return [ш.описание() for ш in шаги]


def _целиком(источник: Источник, пункт, выход: Path, сказать, доля, проверить, в_памяти_до: int,
             описать_шаг, применить, свойства: list | None = None) -> list[str]:
    номер, шаг, _ = пункт
    имя = описать_шаг(шаг)
    if источник.бит <= в_памяти_до:
        сказать(доля(0.0), f"шаг {номер}: {имя} — над всем рядом ({источник.бит} бит)")
        with _с_ходом_слоя(сказать, проверить, доля):
            биты, описание = применить(источник.все(), [шаг], свойства=свойства)
        проверить()
        with Приёмник(выход) as приёмник:
            приёмник.записать(биты)
            _ДЛИНЫ[str(выход)] = приёмник.закрыть()
        return описание
    if not _кусками_можно(шаг):
        raise ValueError(
            f"Шаг {номер} «{имя}»: массив {источник.бит // 8 >> 20} МБ больше предела ({в_памяти_до // 8 >> 20} МБ). "
            f"Сократите массив или задайте слой явно")
    описание: list[str] = []
    хвост = ""
    сетка = _сетка(источник, шаг)
    if сетка is not None and сетка[1] < в_памяти_до // 2:
        # Стыки кусков — на границах слов (кадров): ни одно слово не рвётся, итог — как над всем рядом.
        # Куски поровну (не больше предела): короткий последний кусок слою может не годиться (мало блоков).
        начало_сетки, период, слой_кусков = сетка
        наибольший = max(период, (в_памяти_до - начало_сетки) // период * период)
        остаток = max(0, источник.бит - начало_сетки)
        на_кусок = -(-остаток // max(1, -(-остаток // наибольший)))
        длина_куска = max(период, -(-на_кусок // период) * период)
        границы = [0] + list(range(начало_сетки + длина_куска, источник.бит, длина_куска)) + [источник.бит]
        границы = [г for i, г in enumerate(границы) if i == 0 or г > границы[i - 1]]
        куски_ = [(границы[i], границы[i + 1]) for i in range(len(границы) - 1)]
        шаги_ = [шаг] + [{**шаг, "слой": слой_кусков}] * (len(куски_) - 1)
    else:
        длина_куска = -(-источник.бит // -(-источник.бит // в_памяти_до))          # поровну, не больше предела
        куски_ = [(от, min(источник.бит, от + длина_куска)) for от in range(0, источник.бит, длина_куска)]
        шаги_ = [шаг] * len(куски_)
    кусков = len(куски_)
    with Приёмник(выход) as приёмник:
        for н, ((от, до), шаг_куска) in enumerate(zip(куски_, шаги_, strict=True), start=1):
            кусок = источник.биты(от, до)
            проверить()
            сказать(доля((н - 1) / кусков), f"шаг {номер}: {имя} — кусок {н} из {кусков}")
            try:
                with _с_ходом_слоя(сказать, проверить, lambda часть, н=н: доля((н - 1 + часть) / кусков)):
                    биты, о = применить(кусок, [шаг_куска], свойства=свойства if н == 1 else None)
            except ValueError as ошибка:
                if н == 1 or н < кусков:
                    raise
                # Последний кусок короче прочих — слою может не хватить его на целое слово или кадр.
                хвост = f"последний кусок ({len(кусок)} бит) слой не взял: {ошибка}"
                continue
            if not описание:
                описание = list(о)
            приёмник.записать(биты)
        _ДЛИНЫ[str(выход)] = приёмник.закрыть()
    if хвост:
        описание.append(хвост)
    if сетка is not None and сетка[1] < в_памяти_до // 2:
        описание.append(f"слой выполнен кусками ({кусков}) по сетке слов (кадров) через {сетка[1]} бит: ряд больше, "
                        f"чем обрабатывается в памяти; стыки — на границах слов, слова не рвутся")
    else:
        описание.append(f"слой выполнен кусками по {длина_куска // 8 >> 20} МБ ({кусков} кусков) независимо: ряд "
                        f"больше, чем обрабатывается в памяти; на стыках кусков слой синхронизируется заново")
    return описание
