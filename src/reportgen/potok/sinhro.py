# -*- coding: utf-8 -*-
"""Синхрокомбинация: найти, засинхронизироваться, выровнять кадры.

После демодуляции главное в потоке — синхрокомбинация: по ней видно,
где начинается кадр, какой он длины и часто — что это за система. Здесь:

- слово задаётся битами («0011011») или шестнадцатеричным («0x1ACFFC1D»,
  «47h»); ищется с допуском ошибок и в инверсном виде (фазовая
  неоднозначность демодулятора переворачивает все биты);
- по расстояниям между вхождениями — длина кадра и доля регулярных;
- синхронизация: поток с первого бита синхрокомбинации;
- выравнивание кадров «с маховиком»: каждый кадр начинается со своей
  синхрокомбинации; если её нет на месте (ошибки), кадр берётся по
  ожидаемому месту, если она нашлась рядом — это проскальзывание бит, и
  отсчёт перестраивается по ней;
- известные синхрокомбинации — только те, что уже стоят в анализаторе и
  проверены его тестами (FAS E1…E4, флаг HDLC, синхробайт MPEG-TS, пустой
  кадр GFP). Остальное помощник ищет по библиотеке.
"""

from __future__ import annotations

import re
from typing import Any, Dict, List, Optional, Tuple

import numpy as np

from . import cikl, gfp, hdlc, pdh

СЛОВО_ДО = 128
#: Больше вхождений не возвращаем: для растра и шага хватит.
ПОЗИЦИЙ_ДО = 5000
#: На сколько бит в каждую сторону искать сбежавшую синхрокомбинацию.
ОКНО_ПОИСКА = 16


def слово(текст: str) -> np.ndarray:
    """«0011011» — биты; «0x47», «47h», «1ACF FC1D» — шестнадцатеричное (старший бит первым)."""
    т = (текст or "").strip().lower().replace("_", "")
    if not т:
        raise ValueError("синхрокомбинация пуста")
    сжато = re.sub(r"\s+", "", т)
    if сжато.startswith("0b"):
        сжато = сжато[2:]
        if not re.fullmatch(r"[01]+", сжато):
            raise ValueError("после 0b — только 0 и 1")
    # «0x…» и «…h» сюда не попадут: в них есть буквы x и h.
    if re.fullmatch(r"[01]+", сжато):
        биты = np.frombuffer(сжато.encode(), dtype=np.uint8) - ord("0")
    else:
        сжато = сжато.removeprefix("0x").removesuffix("h")
        if not re.fullmatch(r"[0-9a-f]+", сжато):
            raise ValueError("синхрокомбинация — биты (0011011) или HEX (0x1ACFFC1D)")
        биты = np.array([int(б) for ц in сжато for б in format(int(ц, 16), "04b")], dtype=np.uint8)
    if len(биты) > СЛОВО_ДО:
        raise ValueError(f"синхрокомбинация длиннее {СЛОВО_ДО} бит")
    return биты.astype(np.uint8)


def словами(биты: np.ndarray) -> str:
    """Биты и, если длина кратна 4, HEX: «0011011», «0x47 (01000111)»."""
    двоичное = "".join(map(str, биты.tolist()))
    if len(биты) % 4 == 0:
        return f"0x{int(двоичное, 2):0{len(биты) // 4}X} ({двоичное})"
    return двоичное


def несовпадения(биты: np.ndarray, образец: np.ndarray) -> np.ndarray:
    """Для каждой позиции — сколько бит слова не совпало (свёртка через БПФ)."""
    L = len(образец)
    n = len(биты) - L + 1
    if n <= 0:
        return np.zeros(0, dtype=np.int32)
    x = биты.astype(np.float64) * 2 - 1
    w = образец[::-1].astype(np.float64) * 2 - 1
    размер = 1 << int(np.ceil(np.log2(len(x) + L)))
    свёртка = np.fft.irfft(np.fft.rfft(x, размер) * np.fft.rfft(w, размер), размер)
    совпало = np.rint((свёртка[L - 1:L - 1 + n] + L) / 2).astype(np.int32)
    return L - совпало


def найти(биты: np.ndarray, образец: np.ndarray, ошибок: int = 0) -> Dict[str, Any]:
    """Вхождения прямого и инверсного слова, шаг повторения, известна ли комбинация."""
    L = len(образец)
    if L < 4:
        raise ValueError("синхрокомбинация короче 4 бит найдётся где угодно")
    ошибок = max(0, min(int(ошибок), L // 4))
    н = несовпадения(биты, образец)
    прямые = np.flatnonzero(н <= ошибок)
    инверсные = np.flatnonzero(L - н <= ошибок)
    # Случайно слово длины L с ≤ e ошибками стоит в позиции с вероятностью
    # Σ C(L, i) / 2^L — столько «вхождений» было бы и без синхрокомбинации.
    from math import comb  # noqa: PLC0415
    случайно = len(н) * sum(comb(L, i) for i in range(ошибок + 1)) / 2.0 ** L
    главные = прямые if len(прямые) >= len(инверсные) else инверсные
    шаги = _шаги(главные)
    длина = шаги[0]["шаг"] if шаги and шаги[0]["доля"] >= 0.3 else None
    return {
        "слово": словами(образец), "бит": L, "ошибок": ошибок,
        "прямых": int(len(прямые)), "инверсных": int(len(инверсные)),
        "случайно": round(случайно, 1),
        "первое": int(прямые[0]) if len(прямые) else None,
        "первое_инверсное": int(инверсные[0]) if len(инверсные) else None,
        "инверсия": bool(len(инверсные) > len(прямые)),
        "шаги": шаги,
        "длина_кадра": длина,
        # Начало — первое вхождение, за которым синхрокомбинация повторяется
        # с шагом кадра: случайное совпадение в данных началом не станет.
        "начало": _начало(главные, длина),
        "позиции": главные[:ПОЗИЦИЙ_ДО].tolist(),
        "известная": известная(образец),
    }


def _начало(позиции: np.ndarray, длина: Optional[int]) -> Optional[int]:
    if not len(позиции):
        return None
    if длина:
        есть = set(позиции.tolist())
        for п in позиции[:ПОЗИЦИЙ_ДО].tolist():
            if п + длина in есть and п + 2 * длина in есть:
                return int(п)
    return int(позиции[0])


def _шаги(позиции: np.ndarray) -> List[Dict[str, Any]]:
    """Частые расстояния между соседними вхождениями — кандидаты длины кадра."""
    if len(позиции) < 3:
        return []
    разности = np.diff(позиции)
    значения, сколько = np.unique(разности, return_counts=True)
    порядок = np.argsort(-сколько)[:5]
    return [{"шаг": int(значения[i]), "раз": int(сколько[i]),
             "доля": round(float(сколько[i] / len(разности)), 3)} for i in порядок]


def известные() -> List[Tuple[str, np.ndarray]]:
    """Синхрокомбинации, которые анализатор уже знает (и проверяет тестами)."""
    итог = [("FAS E1 (G.704), в КИ0 чётных циклов, цикл 256 бит", cikl.FAS),
            ("флаг HDLC/PPP 01111110", hdlc.ФЛАГ)]
    for и in pdh.ИЕРАРХИИ:
        итог.append((f"FAS {и.имя} ({и.стандарт}), цикл {и.цикл} бит",
                     np.array(и.fas, dtype=np.uint8)))
    итог.append(("синхробайт MPEG-TS 0x47, пакет 188 байт (204 с RS)",
                 np.unpackbits(np.array([0x47], dtype=np.uint8))))
    итог.append(("инвертированный синхробайт DVB 0xB8 — первый пакет группы из восьми",
                 np.unpackbits(np.array([0xB8], dtype=np.uint8))))
    итог.append(("пустой кадр GFP (G.7041) после маски: B6AB31E0",
                 np.unpackbits(np.frombuffer(gfp.МАСКА, dtype=np.uint8))))
    return итог


def известная(образец: np.ndarray) -> List[str]:
    """Что это за слово, если анализатор его знает: точно, инверсно или как часть."""
    итог = []
    for имя, эталон in известные():
        э = эталон.astype(np.uint8)
        for вид, x in (("", образец), ("инверсная: ", 1 - образец)):
            if np.array_equal(x, э):
                итог.append(вид + имя)
            elif len(x) > len(э) and _входит(x, э):
                итог.append(вид + "содержит " + имя)
            elif len(x) >= 6 and len(x) < len(э) and _входит(э, x):
                итог.append(вид + "часть: " + имя)
    return итог


def _входит(длинное: np.ndarray, короткое: np.ndarray) -> bool:
    return bool(len(несовпадения(длинное, короткое)) and
                (несовпадения(длинное, короткое) == 0).any())


def синхронизировать(биты: np.ndarray, образец: np.ndarray, ошибок: int = 0
                     ) -> Tuple[np.ndarray, Dict[str, Any]]:
    """Поток с первого бита синхрокомбинации (первой из повторяющихся с шагом кадра).

    Если синхрокомбинация идёт инверсной — фазовая неоднозначность
    демодулятора, — поток переворачивается.
    """
    найдено = найти(биты, образец, ошибок)
    начало = найдено["начало"]
    if начало is None:
        raise ValueError(f"синхрокомбинация {найдено['слово']} не найдена")
    if найдено["инверсия"]:
        return (1 - биты[начало:]).astype(np.uint8), найдено
    return биты[начало:], найдено


def выровнять(биты: np.ndarray, образец: np.ndarray, длина: int, ошибок: int = 0,
              окно: int = ОКНО_ПОИСКА) -> Tuple[np.ndarray, Dict[str, Any]]:
    """Кадры по синхрокомбинации с маховиком: каждый — от своей синхрокомбинации.

    Возвращает кадры подряд (по ``длина`` бит, первым — синхрокомбинация) и
    сводку: сколько кадров, сколько раз синхрокомбинации не было на месте и
    сколько проскальзываний (синхрокомбинация нашлась со сдвигом).
    """
    L = len(образец)
    if длина < L:
        raise ValueError("кадр не может быть короче синхрокомбинации")
    биты, найдено = синхронизировать(биты, образец, ошибок)
    н = несовпадения(биты, образец)
    место, кадры = 0, []
    на_месте = нет = проскальзываний = 0
    while место + длина <= len(биты):
        if н[место] <= ошибок:
            на_месте += 1
        else:
            от, до = max(0, место - окно), min(len(н), место + окно + 1)
            рядом = np.flatnonzero(н[от:до] <= ошибок)
            if len(рядом):
                # Ближайшее к ожидаемому месту вхождение.
                место = от + int(рядом[np.argmin(np.abs(рядом + от - место))])
                проскальзываний += 1
                if место + длина > len(биты):
                    break
            else:
                нет += 1
        кадры.append(биты[место:место + длина])
        место += длина
    if not кадры:
        raise ValueError("ни одного целого кадра")
    return np.concatenate(кадры), {
        **{к: найдено[к] for к in ("слово", "инверсия", "известная")},
        "кадров": len(кадры), "на_месте": на_месте, "нет_на_месте": нет,
        "проскальзываний": проскальзываний, "длина": int(длина),
    }


def описать(найдено: Dict[str, Any]) -> str:
    """Одна строка для отчёта и вопроса помощнику."""
    части = [f"синхрокомбинация {найдено['слово']}, {найдено['бит']} бит, ошибок до "
             f"{найдено['ошибок']}: прямых {найдено['прямых']}, инверсных "
             f"{найдено['инверсных']} (случайно ожидалось бы {найдено['случайно']})"]
    if найдено["шаги"]:
        части.append("шаг повторения: " + ", ".join(
            f"{ш['шаг']} бит ×{ш['раз']} ({ш['доля'] * 100:.0f} %)" for ш in найдено["шаги"][:3]))
    if найдено["известная"]:
        части.append("знакомо анализатору: " + "; ".join(найдено["известная"]))
    return "; ".join(части)


def из_столбцов(биты: np.ndarray, период: int, сдвиг: int, позиции: List[int]
                ) -> Optional[np.ndarray]:
    """Синхрокомбинация из выделенных столбцов растра: большинство по циклам.

    Столбцы должны идти подряд; неустойчивый столбец (от 20 до 80 % единиц)
    — не синхрокомбинация, тогда None.
    """
    позиции = sorted(set(int(п) for п in позиции))
    if not позиции or позиции[-1] - позиции[0] + 1 != len(позиции):
        raise ValueError("выделите подряд идущие столбцы")
    доли = np.array(cikl.сложить(биты[:cikl.ВЫБОРКА], период, сдвиг % период)
                    [:, позиции].mean(axis=0))
    if np.any((доли > 0.2) & (доли < 0.8)):
        return None
    return (доли >= 0.5).astype(np.uint8)
