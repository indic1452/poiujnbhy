def известная(образец: np.ndarray) -> List[str]:
    """Что это за слово, если анализатор его знает: точно, инверсно или как часть."""
    итог = []
    for имя, эталон in известные():
        э = эталон.astype(np.uint8)
        for вид, x in (("", образец), ("инверсная: ", 1 - образец)):
            if np.array_equal(x, э):
                итог.append(вид + имя)
            elif len(x) > len(э) and _входит(x, э):
                итог.append(вид + "содержит " + имя)
            elif len(x) >= 6 and len(x) < len(э) and _входит(э, x):
                итог.append(вид + "часть: " + имя)
    return итог


def _входит(длинное: np.ndarray, короткое: np.ndarray) -> bool:
    return bool(len(несовпадения(длинное, короткое)) and
                (несовпадения(длинное, короткое) == 0).any())


def синхронизировать(биты: np.ndarray, образец: np.ndarray, ошибок: int = 0
                     ) -> Tuple[np.ndarray, Dict[str, Any]]:
    """Поток с первого бита синхрокомбинации (первой из повторяющихся с шагом кадра).

    Если синхрокомбинация идёт инверсной — фазовая неоднозначность
    демодулятора, — поток переворачивается.
    """
    найдено = найти(биты, образец, ошибок)
    начало = найдено["начало"]
    if начало is None:
        raise ValueError(f"синхрокомбинация {найдено['слово']} не найдена")
    if найдено["инверсия"]:
        return (1 - биты[начало:]).astype(np.uint8), найдено
    return биты[начало:], найдено


def выровнять(биты: np.ndarray, образец: np.ndarray, длина: int, ошибок: int = 0,
              окно: int = ОКНО_ПОИСКА) -> Tuple[np.ndarray, Dict[str, Any]]:
    """Кадры по синхрокомбинации с маховиком: каждый — от своей синхрокомбинации.

    Возвращает кадры подряд (по ``длина`` бит, первым — синхрокомбинация) и
    сводку: сколько кадров, сколько раз синхрокомбинации не было на месте и
    сколько проскальзываний (синхрокомбинация нашлась со сдвигом).
    """
    L = len(образец)
    if длина < L:
        raise ValueError("кадр не может быть короче синхрокомбинации")
    биты, найдено = синхронизировать(биты, образец, ошибок)
    н = несовпадения(биты, образец)
    место, кадры = 0, []
    на_месте = нет = проскальзываний = 0
    while место + длина <= len(биты):
        if н[место] <= ошибок:
            на_месте += 1
        else:
            от, до = max(0, место - окно), min(len(н), место + окно + 1)
            рядом = np.flatnonzero(н[от:до] <= ошибок)
            if len(рядом):
                # Ближайшее к ожидаемому месту вхождение.
                место = от + int(рядом[np.argmin(np.abs(рядом + от - место))])
                проскальзываний += 1
                if место + длина > len(биты):
                    break
            else:
                нет += 1
        кадры.append(биты[место:место + длина])
        место += длина
    if not кадры:
        raise ValueError("ни одного целого кадра")
    return np.concatenate(кадры), {
        **{к: найдено[к] for к in ("слово", "инверсия", "известная")},
        "кадров": len(кадры), "на_месте": на_месте, "нет_на_месте": нет,
        "проскальзываний": проскальзываний, "длина": int(длина),
    }


def описать(найдено: Dict[str, Any]) -> str:
    """Одна строка для отчёта и вопроса помощнику."""
    части = [f"синхрокомбинация {найдено['слово']}, {найдено['бит']} бит, ошибок до "
             f"{найдено['ошибок']}: прямых {найдено['прямых']}, инверсных "
             f"{найдено['инверсных']} (случайно ожидалось бы {найдено['случайно']})"]
    if найдено["шаги"]:
        части.append("шаг повторения: " + ", ".join(
            f"{ш['шаг']} бит ×{ш['раз']} ({ш['доля'] * 100:.0f} %)" for ш in найдено["шаги"][:3]))
    if найдено["известная"]:
        части.append("знакомо анализатору: " + "; ".join(найдено["известная"]))
    return "; ".join(части)


def из_столбцов(биты: np.ndarray, период: int, сдвиг: int, позиции: List[int]
                ) -> Optional[np.ndarray]:
    """Синхрокомбинация из выделенных столбцов растра: большинство по циклам.

    Столбцы должны идти подряд; неустойчивый столбец (от 20 до 80 % единиц)
    — не синхрокомбинация, тогда None.
    """
    позиции = sorted(set(int(п) for п in позиции))
    if not позиции or позиции[-1] - позиции[0] + 1 != len(позиции):
        raise ValueError("выделите подряд идущие столбцы")
    доли = np.array(cikl.сложить(биты[:cikl.ВЫБОРКА], период, сдвиг % период)
                    [:, позиции].mean(axis=0))
    if np.any((доли > 0.2) & (доли < 0.8)):
        return None
    return (доли >= 0.5).astype(np.uint8)
