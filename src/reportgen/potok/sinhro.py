def _дибиты(символы: str) -> int:
    """Синхрослово 4FSK записью DSD (символ «1» — +3, дибит 01; «3» — −3, дибит 11) → число."""
    return int("".join({"1": "01", "3": "11"}[с] for с in символы), 2)


