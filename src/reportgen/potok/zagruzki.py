"""Приём файла потока кусками: с ходом, отменой и докачкой после обрыва.

Файл в гигабайт одним запросом не идёт: браузер держит его в памяти целиком,
обрыв связи на 900-м мегабайте — всё сначала, а сервер читал бы его в память.
Поэтому загрузка — запись: имя, объём, сколько принято; куски (по несколько МБ)
дописываются в файл «.part» строго по порядку — кусок не с того места получает
отказ с тем, сколько принято, и браузер продолжает с этого места (после обрыва,
перезагрузки страницы, повтора). Готовый файл переносится в папку задания без
копии. Брошенные загрузки убираются через ``ХРАНИТЬ_СЕКУНД``.
"""

from __future__ import annotations

import json
import secrets
import threading
import time
from pathlib import Path
from typing import Any

from ..fayly import записать_атомарно

#: Кусок загрузки по умолчанию (браузер может слать и меньше).
КУСОК = 8 << 20
#: Кусок не больше этого — тело запроса читается в память.
КУСОК_ДО = 32 << 20
#: Недокачанная загрузка хранится столько (неделя): докачать можно и назавтра.
ХРАНИТЬ_СЕКУНД = 7 * 24 * 3600


class ОшибкаЗагрузки(ValueError):
    """Кусок не с того места, загрузка не своя или уже закончена."""

    def __init__(self, текст: str, принято: int = 0):
        super().__init__(текст)
        self.принято = принято


class Загрузки:
    """Недокачанные файлы: ``<папка>/<ид>.json`` (сведения) и ``<ид>.part`` (принятое)."""

    def __init__(self, папка: Path):
        self.папка = Path(папка)
        self._lock = threading.Lock()

    def _путь(self, ид: str, расширение: str) -> Path:
        if not (len(ид) == 16 and all(c in "0123456789abcdef" for c in ид)):
            raise KeyError(ид)
        return self.папка / f"{ид}.{расширение}"

    def начать(self, *, владелец: int, имя: str, размер: int, сведения: dict[str, Any]) -> dict[str, Any]:
        """Новая загрузка: ``сведения`` — что сделать с файлом, когда он придёт (сессия, обрезка…)."""
        if размер <= 0:
            raise ОшибкаЗагрузки("файл пуст")
        self.папка.mkdir(parents=True, exist_ok=True)
        self.прибрать()
        ид = secrets.token_hex(8)
        запись = {"ид": ид, "владелец": int(владелец), "имя": имя, "размер": int(размер), "принято": 0,
                  "создано": time.time(), "тронуто": time.time(), "сведения": dict(сведения)}
        self._путь(ид, "part").write_bytes(b"")
        записать_атомарно(self._путь(ид, "json"), json.dumps(запись, ensure_ascii=False))
        return запись

    def прочитать(self, ид: str, владелец: int) -> dict[str, Any]:
        путь = self._путь(ид, "json")
        if not путь.exists():
            raise KeyError(ид)
        запись = json.loads(путь.read_text(encoding="utf-8"))
        if запись["владелец"] != int(владелец):
            raise KeyError(ид)                        # чужая загрузка — как будто её нет
        # Принято — сколько на самом деле в файле: запись могла не успеть обновиться при обрыве.
        запись["принято"] = min(запись["размер"], self._путь(ид, "part").stat().st_size)
        return запись

    def дописать(self, ид: str, владелец: int, место: int, данные: bytes) -> int:
        """Кусок с места ``место``; итог — сколько принято. Не то место — ``ОшибкаЗагрузки``."""
        if len(данные) > КУСОК_ДО:
            raise ОшибкаЗагрузки(f"кусок больше {КУСОК_ДО >> 20} МБ")
        with self._lock:
            запись = self.прочитать(ид, владелец)
            принято = запись["принято"]
            if место != принято:
                raise ОшибкаЗагрузки(f"ожидался кусок с байта {принято}, пришёл с {место}", принято)
            if принято + len(данные) > запись["размер"]:
                raise ОшибкаЗагрузки("кусок за концом файла — объём больше заявленного", принято)
            with open(self._путь(ид, "part"), "r+b") as файл:
                файл.seek(принято)
                файл.write(данные)
                файл.truncate()
            запись["принято"] = принято + len(данные)
            запись["тронуто"] = time.time()
            записать_атомарно(self._путь(ид, "json"), json.dumps(запись, ensure_ascii=False))
            return запись["принято"]

    def забрать(self, ид: str, владелец: int) -> tuple[Path, dict[str, Any]]:
        """Принятый целиком файл и сведения загрузки; сама запись убирается (файл — забрать до конца
        запроса: перенести в задание или удалить)."""
        with self._lock:
            запись = self.прочитать(ид, владелец)
            if запись["принято"] != запись["размер"]:
                raise ОшибкаЗагрузки(f"принято {запись['принято']} байт из {запись['размер']} — загрузка не "
                                     f"закончена", запись["принято"])
            self._путь(ид, "json").unlink(missing_ok=True)
            return self._путь(ид, "part"), запись

    def отменить(self, ид: str, владелец: int) -> None:
        with self._lock:
            self.прочитать(ид, владелец)
            for расширение in ("part", "json"):
                self._путь(ид, расширение).unlink(missing_ok=True)

    def список(self, владелец: int) -> list[dict[str, Any]]:
        """Недокачанные загрузки человека — чтобы страница предложила докачать."""
        итог = []
        for путь in sorted(self.папка.glob("*.json")) if self.папка.exists() else []:
            try:
                итог.append(self.прочитать(путь.stem, владелец))
            except (KeyError, OSError, ValueError):
                continue
        return итог

    def прибрать(self) -> None:
        """Брошенные загрузки (не трогали дольше ``ХРАНИТЬ_СЕКУНД``) — с диска."""
        срок = time.time() - ХРАНИТЬ_СЕКУНД
        for путь in self.папка.glob("*.json"):
            try:
                if json.loads(путь.read_text(encoding="utf-8")).get("тронуто", 0) >= срок:
                    continue
            except (OSError, ValueError):
                pass
            путь.with_suffix(".part").unlink(missing_ok=True)
            путь.unlink(missing_ok=True)
