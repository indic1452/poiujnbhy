"""Биты массивов разбора на диске: окна, куски, ссылки на файлы сервера.

Поток в гигабайт — это 8 Гбит, а распакованный массив бит (байт на бит) — 8 ГБ
памяти: так держать его нельзя. Поэтому массив живёт на диске упакованным (старший
бит байта первым), а читается окнами: просмотру — только видимое, операции — кусками
по порядку, с записью итога снова на диск (``Приёмник``).

Файл из папки входных файлов сервера (общий модуль ``fayly_ssylki``: папки, обзор, безопасные
пути) не копируется: узел хранит ссылку — путь,
размер, время изменения и отпечаток (SHA-256 первого и последнего мегабайта с
размером) — и смещение с длиной, если взята часть, и признак «младший бит первым»
(разворот бит в байте делается при чтении окна, а не копией файла). Перед каждым
чтением ссылка сверяется: файл удалили, урезали или переписали — ``ФайлИзменён``
со словами, а не мусор вместо бит. Время изменения поменялось, а содержимое то же
(файл скопировали заново) — ссылка молча обновляется.

Почему не ``numpy.memmap``: на Windows отображённый файл нельзя удалить или
переписать, пока жив хоть один вид на него (а ссылки ведут на файлы общих папок,
которые отдел перекладывает), и отображение файла с сетевой папки рвётся при
обрыве связи ошибкой доступа к памяти, а не исключением. Чтение окна — открыть,
сдвинуться, прочитать, закрыть: файл не держится открытым между запросами.
"""

from __future__ import annotations

import hashlib
import os
import shutil
from collections.abc import Iterator
from pathlib import Path
from typing import Any

import numpy as np

from .. import fayly_ssylki

#: Файл по ссылке удалён, недоступен или изменён после добавления — та же ошибка, что у общего
#: модуля файлов по ссылке («Анализ пакетов»): обработчики отвечают на неё 409.
from ..fayly_ssylki import ФайлИзменён

#: Сколько байт читать за раз при проходе по файлу.
КУСОК_БАЙТ = 8 << 20
#: Отпечаток содержимого — столько байт с начала и с конца файла.
ОТПЕЧАТОК_БАЙТ = 1 << 20

#: Байт с битами в обратном порядке: файл «младшим битом первым» читается так.
_НАОБОРОТ = bytes(int(f"{b:08b}"[::-1], 2) for b in range(256))


def отпечаток(путь: str | Path) -> dict[str, Any]:
    """Размер, время изменения (как ``fayly_ssylki.отпечаток``) и отпечаток содержимого файла."""
    путь = Path(путь)
    сведения = fayly_ssylki.отпечаток(путь)
    return {"путь": str(путь), "размер": int(сведения["размер"]), "изменён_нс": int(сведения["изменён_нс"]),
            "хэш": _хэш(путь, int(сведения["размер"]))}


def _хэш(путь: Path, размер: int) -> str:
    h = hashlib.sha256(str(размер).encode("ascii"))
    with open(путь, "rb") as файл:
        h.update(файл.read(ОТПЕЧАТОК_БАЙТ))
        if размер > ОТПЕЧАТОК_БАЙТ:
            файл.seek(max(ОТПЕЧАТОК_БАЙТ, размер - ОТПЕЧАТОК_БАЙТ))
            h.update(файл.read(ОТПЕЧАТОК_БАЙТ))
    return h.hexdigest()


def сверить(ссылка: dict[str, Any]) -> dict[str, Any] | None:
    """Файл по ссылке тот же? None — да, как был; словарь — да, но с новым временем
    изменения (содержимое то же — записать в ссылку); ``ФайлИзменён`` — нет."""
    путь = Path(ссылка["путь"])
    try:
        сведения = путь.stat()
    except FileNotFoundError:
        raise ФайлИзменён(f"Файл {путь.name} удалён или перенесён") from None
    except OSError:
        raise ФайлИзменён(f"Файл {путь.name} недоступен") from None
    if сведения.st_size == ссылка["размер"] and сведения.st_mtime_ns == ссылка["изменён_нс"]:
        return None
    if сведения.st_size != ссылка["размер"]:
        raise ФайлИзменён(f"Файл {путь.name} изменён — добавьте его заново")
    try:
        хэш = _хэш(путь, int(сведения.st_size))
    except OSError:
        raise ФайлИзменён(f"Файл {путь.name} недоступен") from None
    if хэш != ссылка["хэш"]:
        raise ФайлИзменён(f"Файл {путь.name} изменён — добавьте его заново")
    return {**ссылка, "изменён_нс": int(сведения.st_mtime_ns)}


class Источник:
    """Биты массива: файл на диске (или его часть), старшим битом байта первым.

    ``смещение`` и ``байт`` — какая часть файла (в байтах); ``бит`` — точная длина в битах,
    если хвост последнего байта не в счёт; ``развернуть`` — в файле младший бит байта
    первым (разворачивается при чтении); ``ссылка`` — сверять файл перед чтением
    (словарь из ``отпечаток``); ``сверено`` — куда сообщить обновлённую ссылку.
    """

    def __init__(self, путь: str | Path, *, смещение: int = 0, байт: int | None = None,
                 бит: int | None = None, развернуть: bool = False,
                 ссылка: dict[str, Any] | None = None, сверено=None):
        self.путь = Path(путь)
        self.ссылка = ссылка
        self._сверено = сверено
        if ссылка is not None:
            self.сверить()
            размер = int(ссылка["размер"])
        else:
            размер = self.путь.stat().st_size
        self.смещение = max(0, min(int(смещение), размер))
        self.байт = размер - self.смещение if байт is None else max(0, min(int(байт), размер - self.смещение))
        self.бит = self.байт * 8 if бит is None else max(0, min(int(бит), self.байт * 8))
        self.развернуть = bool(развернуть)

    def сверить(self) -> None:
        if self.ссылка is None:
            return
        новая = сверить(self.ссылка)
        if новая is not None:
            self.ссылка = новая
            if self._сверено is not None:
                self._сверено(новая)

    def __len__(self) -> int:
        return self.бит

    @property
    def ключ(self) -> tuple:
        """Для запоминания расчётов: файл, его время и часть."""
        if self.ссылка is not None:
            return (str(self.путь), self.ссылка["хэш"], self.смещение, self.бит, self.развернуть)
        сведения = self.путь.stat()
        return (str(self.путь), сведения.st_mtime_ns, сведения.st_size, self.смещение, self.бит, self.развернуть)

    # -- чтение ----------------------------------------------------------------

    def байты(self, от: int = 0, сколько: int | None = None) -> bytes:
        """Байты массива [от, от + сколько) — как они лежат в потоке (старший бит первым)."""
        от = max(0, min(int(от), self.байт))
        сколько = self.байт - от if сколько is None else max(0, min(int(сколько), self.байт - от))
        if not сколько:
            return b""
        self.сверить()
        with open(self.путь, "rb") as файл:
            файл.seek(self.смещение + от)
            данные = файл.read(сколько)
        if len(данные) != сколько:
            raise ФайлИзменён(f"Файл {self.путь.name} изменён — добавьте его заново")
        return данные.translate(_НАОБОРОТ) if self.развернуть else данные

    def биты(self, от: int = 0, до: int | None = None) -> np.ndarray:
        """Биты [от, до) — распаковывается только это окно."""
        до = self.бит if до is None else max(0, min(int(до), self.бит))
        от = max(0, min(int(от), до))
        if от == до:
            return np.zeros(0, dtype=np.uint8)
        кусок = self.байты(от // 8, (до + 7) // 8 - от // 8)
        return np.unpackbits(np.frombuffer(кусок, dtype=np.uint8))[от % 8:от % 8 + до - от]

    def куски(self, кусок_бит: int = КУСОК_БАЙТ * 8, от: int = 0, до: int | None = None
              ) -> Iterator[np.ndarray]:
        """Биты [от, до) по порядку кусками не длиннее ``кусок_бит``."""
        до = self.бит if до is None else max(0, min(int(до), self.бит))
        место = max(0, int(от))
        кусок_бит = max(1, int(кусок_бит))
        while место < до:
            следующее = min(до, место + кусок_бит)
            yield self.биты(место, следующее)
            место = следующее

    def байты_кусками(self, кусок: int = КУСОК_БАЙТ) -> Iterator[bytes]:
        """Все байты массива по порядку — для выгрузки и копирования (хвост байта — как в файле)."""
        место = 0
        while место < self.байт:
            данные = self.байты(место, min(кусок, self.байт - место))
            yield данные
            место += len(данные)

    def все(self) -> np.ndarray:
        """Весь массив бит в памяти — только для массивов, которые туда помещаются."""
        return self.биты(0, self.бит)

    def целый_файл(self) -> bool:
        """Массив — весь файл как есть: его можно связать или отдать без перекладки."""
        return (self.ссылка is None and not self.смещение and not self.развернуть
                and self.байт == self.путь.stat().st_size)

    def в_файл(self, куда: str | Path) -> None:
        """Записать массив в файл: жёсткой ссылкой на тот же файл, если можно, иначе копией по кускам."""
        куда = Path(куда)
        if self.целый_файл():
            связать_или_копировать(self.путь, куда)
            return
        with open(куда, "wb") as файл:
            for данные in self.байты_кусками():
                файл.write(данные)


def связать_или_копировать(откуда: str | Path, куда: str | Path) -> None:
    """Файл массива — в другую папку заданий: жёсткая ссылка (места не занимает, NTFS тоже умеет),
    а где нельзя (другой диск, FAT) — копия кусками, без чтения в память."""
    откуда, куда = Path(откуда), Path(куда)
    try:
        os.link(откуда, куда)
    except OSError:
        with open(откуда, "rb") as вход, open(куда, "wb") as выход:
            shutil.copyfileobj(вход, выход, КУСОК_БАЙТ)


class Приёмник:
    """Запись бит в файл кусками: упаковка по 8 бит, хвост короче байта ждёт следующего куска.

    Пишется во временный файл рядом, на место встаёт при ``закрыть`` — недописанный
    массив (отмена, ошибка) не выдаёт себя за готовый.
    """

    def __init__(self, путь: str | Path):
        self.путь = Path(путь)
        self._врем = self.путь.with_name(self.путь.name + ".part")
        self._файл = open(self._врем, "wb")
        self._хвост = np.zeros(0, dtype=np.uint8)
        self.бит = 0

    def записать(self, биты: np.ndarray) -> None:
        if not len(биты):
            return
        self.бит += len(биты)
        биты = np.asarray(биты, dtype=np.uint8)
        if len(self._хвост):
            биты = np.concatenate([self._хвост, биты])
        целых = len(биты) // 8 * 8
        if целых:
            self._файл.write(np.packbits(биты[:целых]).tobytes())
        self._хвост = биты[целых:].copy()

    def закрыть(self) -> int:
        """Дописать хвост (дополнив нулями до байта) и поставить файл на место; итог — длина в битах."""
        if len(self._хвост):
            self._файл.write(np.packbits(self._хвост).tobytes())
        self._файл.close()
        os.replace(self._врем, self.путь)
        return self.бит

    def бросить(self) -> None:
        """Отменить запись: временный файл удаляется."""
        try:
            self._файл.close()
        finally:
            self._врем.unlink(missing_ok=True)

    def __enter__(self) -> Приёмник:
        return self

    def __exit__(self, тип, *_) -> None:
        if тип is not None:
            self.бросить()


class Окно:
    """Массив бит «как ndarray» для тех, кому нужны длина и срезы (растр, сетка, вырезка):
    срез читает с диска только своё окно. Шагом срез не берётся."""

    def __init__(self, источник: Источник):
        self.источник = источник

    def __len__(self) -> int:
        return self.источник.бит

    def __getitem__(self, ключ):
        if isinstance(ключ, slice):
            if ключ.step not in (None, 1):
                raise ValueError("срез массива на диске — без шага")
            от, до, _ = ключ.indices(self.источник.бит)
            return self.источник.биты(от, max(от, до))
        место = int(ключ)
        if место < 0:
            место += self.источник.бит
        if not 0 <= место < self.источник.бит:
            raise IndexError(место)
        return self.источник.биты(место, место + 1)[0]
