"""LDPC в кадрах модема: слова кода — кадры цикла, матрица — восстановлением по словам (ldpc_vosst).

Кадр найден циклом (синхрослово и длина; у чередующегося синхрослова — половина цикла). Внутри кадра —
заголовок (синхрослово, служебные поля) и слово кода; где кончается заголовок, по постоянству не видно:
поля меняются от кадра к кадру. Нагрузка цикла (всё, кроме постоянных участков) слово рвёт — переменные
биты заголовка остаются в ней, а у демодулятора, пишущего младшим битом вперёд, на стыке байт в нагрузку
уходят и биты соседнего слова.

Поэтому здесь:

1. **Слова — кадры целиком**, в обоих порядках бит в байте (если кадры лежат по байтам): проверки кода
   разрежены в любом порядке, но квазициклическая структура видна только в своём.
2. **Проба** — восстановление проверок на кадрах целиком (короткий срок). Широкие проверки (через весь
   кадр) — проверки кода; узкие — связи полей заголовка (признак чётного кадра и т. п.), их не берём.
   Порядок бит — тот, где широких больше; слово кода — от первого до последнего их столбца.
3. **Начало слова.** У квазициклического кода блоки по Z начинаются с начала слова: из начал у первого
   покрытого столбца берётся то, при котором найденные проверки, сдвинутые в блоках, — тоже проверки.
4. **Восстановление** на словах кода — со структурой и достройкой по ядру (всё пространство проверок).
5. **Снятие** — декодер по найденной H; данные — в порядке бит файла (у демодулятора «младшим вперёд»
   порядок бит в слове кода свой, а то, что над кодом, — скремблер, кадры — идёт в порядке файла).

Повторы кадров (заполнение) ничего не доказывают — восстановление берёт только различные кадры и при
малом их числе честно отказывается (``ldpc_vosst.различных_нужно``).
"""

from __future__ import annotations

import time
from collections.abc import Callable
from dataclasses import dataclass, field

import numpy as np

from . import cikl, ldpc_vosst
from .nahodka import Находка

#: Порядок бит «младший первым» — так он называется в разборе.
МЛАДШИЙ = "младший бит байта первым"
#: Кадров в пробе и в снятии — не больше стольких (выборка разбора и так ограничена).
КАДРОВ_ДО = 4096
#: Широкая проверка — от первого до последнего столбца не меньше этой доли кадра.
ШИРОКАЯ_ОТ = 1 / 8
#: Широких проверок в пробе — не меньше стольких, иначе кода в кадрах нет.
ШИРОКИХ_ОТ = 8
#: Начало слова ищется в стольких битах до первого покрытого столбца; конец — у конца кадра, если
#: непокрытый хвост не длиннее этого.
КРАЙ = 32
#: Доля срока на пробу одного порядка бит (не больше ПРОБА_ДО с).
ПРОБА_ДОЛЯ = 0.15
ПРОБА_ДО = 25.0
#: Принять: независимых проверок не меньше max(16, n/50), декодер сошёлся у такой доли слов.
СОШЛОСЬ_ОТ = 0.5


def в_порядке(биты: np.ndarray, порядок: str) -> np.ndarray:
    """Ряд в порядке бит ``порядок`` («» — как прочитан, МЛАДШИЙ — перевёрнут в каждом байте)."""
    if not порядок:
        return биты
    return биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1].reshape(-1)


def в_файле(позиции: np.ndarray, порядок: str) -> np.ndarray:
    """Номера бит ряда в порядке ``порядок`` → номера тех же бит в порядке файла (перестановка в байте)."""
    if not порядок:
        return позиции
    return (позиции // 8) * 8 + 7 - позиции % 8


def широкие(проверки: list[np.ndarray], кадр: int) -> list[np.ndarray]:
    """Проверки через весь кадр (веса не меньше 3): связи полей заголовка узки — они не проверки кода."""
    return [h for h in проверки if len(h) >= 3 and int(h[-1] - h[0]) >= ШИРОКАЯ_ОТ * кадр]


@dataclass
class Кадры:
    """Кадры в одном порядке бит: начала, длина, слова (кадры × длина)."""
    порядок: str
    начала: list[int]
    кадр: int
    W: np.ndarray
    проба: ldpc_vosst.Итог | None = None
    широкие: list[np.ndarray] = field(default_factory=list)


def кадры(биты: np.ndarray, цикл: int, порядок: str = "") -> Кадры | None:
    """Кадры цикла в порядке бит ``порядок``: по служебным словам с маховиком (у чередующегося синхрослова —
    через полцикла)."""
    ряд = в_порядке(биты, порядок)
    найдено = cikl.кадры(ряд, цикл)
    if найдено is None:
        return None
    начала, сведения = найдено
    F = int(сведения["кадр"])
    начала = [н for н in начала if н + F <= len(ряд)][:КАДРОВ_ДО]
    if len(начала) < 16:
        return None
    return Кадры(порядок, начала, F, np.stack([ряд[н:н + F] for н in начала]))


def _начало_слова(к: Кадры, от: int, конец: int) -> tuple[int, tuple | None]:
    """Начало слова кода в кадре: у квазициклического кода — то из начал в КРАЙ бит до ``от``, при котором
    сдвинутые в блоках проверки выполнены (оператор ldpc_vosst); (начало, оператор или None)."""
    лучшее: tuple[int, tuple | None] = (от, None)
    for h0 in range(от, max(-1, от - КРАЙ - 1), -1):
        свои = [h - h0 for h in к.широкие if h[0] >= h0 and h[-1] < конец]
        if len(свои) < 3:
            continue
        W = к.W[:, h0:конец]
        легчайшие = sorted(свои, key=len)
        порог = max(0.15, min(ldpc_vosst.ДОЛЯ_ДО, 4 * float(np.median(ldpc_vosst.нарушения(W[:512], легчайшие[:6])))))
        оператор = ldpc_vosst.найти_оператор(W, легчайшие, порог)
        if оператор is not None and оператор[0].startswith("квазициклический"):
            return h0, оператор
    return лучшее


def найти(биты: np.ndarray, цикл: int, *, срок: float = 120.0, порядки: tuple[str, ...] = ("",),
          стоп: Callable[[], bool] | None = None, ход: Callable[[str], None] | None = None
          ) -> tuple[Находка | None, str]:
    """LDPC в кадрах цикла длиной ``цикл``: (находка или None, почему нет)."""
    начато = time.monotonic()

    def остаток() -> float:
        return срок - (time.monotonic() - начато)

    def пора() -> bool:
        return остаток() <= 0 or (стоп is not None and стоп())

    варианты: list[Кадры] = []
    почему: list[str] = []
    for порядок in порядки:
        к = кадры(биты, цикл, порядок)
        if к is None:
            continue
        нужно = ldpc_vosst.различных_нужно(к.кадр)
        различных = len(ldpc_vosst.различные_слова(к.W))
        if различных < нужно:
            почему.append(f"различных кадров {различных} из {len(к.W)} — мало для слова до {к.кадр} бит "
                          f"(нужно от {нужно}): поток почти повторяется (заполнение), проверки кода от "
                          f"связей данных не отделить")
            break                  # перестановка бит в байте различных кадров не прибавит
        if пора():
            break
        if ход is not None:
            ход(f"LDPC в кадрах {к.кадр} бит" + (f" ({порядок})" if порядок else "") + ": пробую восстановить проверки")
        к.проба = ldpc_vosst.восстановить(к.W, срок=min(ПРОБА_ДО, ПРОБА_ДОЛЯ * срок), стоп=стоп)
        к.широкие = широкие(к.проба.проверки, к.кадр)
        варианты.append(к)
    if not варианты:
        return None, "; ".join(почему) or "кадров нет"
    к = max(варианты, key=lambda в: len(в.широкие))
    if len(к.широкие) < ШИРОКИХ_ОТ:
        return None, (f"проверок через весь кадр {len(к.широкие)} (нужно от {ШИРОКИХ_ОТ}) — кода в кадрах "
                      f"{к.кадр} бит не видно")
    # Столбцы узких связей — поля заголовка: в широкие проверки они попадают лишь суммой со связью, и
    # слово кода начинается после них.
    поля = np.zeros(к.кадр, dtype=bool)
    for h in к.проба.проверки:
        if int(h[-1] - h[0]) < ШИРОКАЯ_ОТ * к.кадр:
            поля[h] = True
    от = min(int(h[~поля[h]][0]) for h in к.широкие if (~поля[h]).any())
    до = max(int(h[-1]) for h in к.широкие)
    конец = к.кадр if к.кадр - 1 - до <= КРАЙ else до + 1
    h0, оператор = _начало_слова(к, от, конец)
    n = конец - h0
    W = к.W[:, h0:конец]
    начальные = [h - h0 for h in к.широкие if h[0] >= h0 and h[-1] < конец]
    if ход is not None:
        ход(f"LDPC в кадрах {к.кадр} бит: слово — биты {h0}…{конец - 1} кадра"
            + (f", {оператор[0]}" if оператор else "") + "; восстанавливаю проверки")
    итог = ldpc_vosst.восстановить(W, срок=max(10.0, остаток()), стоп=стоп, начальные=начальные)
    if итог.ранг < max(16, n // 50) or итог.сошлось < СОШЛОСЬ_ОТ:
        return None, (f"в кадрах {к.кадр} бит проверок {итог.ранг}, декодер сошёлся у {итог.сошлось * 100:.0f} % "
                      "слов — мало для снятия")
    return снять(биты, к, h0, конец, итог), ""


def снять(биты: np.ndarray, к: Кадры, h0: int, конец: int, итог: ldpc_vosst.Итог) -> Находка:
    """Декодировать все кадры по найденной H; данные — в порядке бит файла."""
    n = конец - h0
    W = к.W[:, h0:конец]
    исправленные, ок = ldpc_vosst.декодировать(W, итог.проверки)
    данные = ldpc_vosst.позиции_данных(итог.проверки, n)
    k = len(данные)
    # Данные кадра — в порядке файла: у «младшего первым» перестановка зависит от места кадра в байте.
    выход = np.empty((len(W), k), dtype=np.uint8)
    for i, н in enumerate(к.начала):
        порядок = np.argsort(в_файле(н + h0 + данные, к.порядок), kind="stable")
        выход[i] = исправленные[i, данные[порядок]]
    исправлено = int((исправленные != W).sum())
    имя = ""
    from . import ldpc  # noqa: PLC0415
    if ldpc.КАТАЛОГ is not None:
        try:
            имя = ldpc_vosst.сохранить(итог, откуда=f"автомат, кадр {к.кадр} бит, слово с бита {h0}")
        except (ValueError, OSError):
            имя = ""
    скорость = k / n
    return Находка(
        уровень="код",
        что=f"LDPC ({n}, {k}) в кадре {к.кадр} бит, скорость {скорость:.3f} — матрица восстановлена по кадрам"
            + (f" ({итог.оператор})" if итог.оператор else ""),
        уверенность=float(min(1.0, ок.mean())),
        мера=(f"независимых проверок {итог.ранг}" + (" (все)" if итог.точно else "")
              + f", выполнены в {итог.доля * 100:.1f} % кадров; декодер сошёлся у {ок.mean() * 100:.0f} % кадров"),
        подробно=[
            f"слово кода — биты {h0}…{конец - 1} кадра (до него — заголовок {h0} бит)"
            + (f"; порядок бит в байте — {к.порядок}: квазициклическая структура видна только так" if к.порядок else ""),
            f"кадров {len(W)}, различных {итог.слов}; BER ≈ {итог.ошибок:.1e}; исправлено бит {исправлено}",
            f"данные — {k} бит каждого слова (опорные столбцы H — проверочные); на выходе — в порядке бит файла",
        ] + ([f"матрица сохранена в папку отдела: «{имя}»"] if имя else
             ["матрица не сохранена: папка матриц отдела не задана"]) + итог.ход[-3:],
        дальше=выход.reshape(-1), вид_дальше="биты",
        свойства={"n": n, "k": k, "кадр": к.кадр, "начало_слова": h0, "порядок": к.порядок,
                  "данных_в_блоке": k, "Z": итог.Z, "матрица_файл": имя, "восстановлена": итог.словарь()})
