"""Настройки анализа потоков у каждого человека: наибольший период поиска.

Период (цикл, кадр, длина строки растра) у РРЛ и модемов бывает в сотни тысяч
бит. Прежде поиск периода везде был зашит константами (8192, 16 384, 65 536), и
длинный цикл не находился ни автоматом, ни окнами стола. Теперь предел один —
«максимальный период поиска» в настройках анализа человека:

- автомат (цикл и синхрослово, кадры, длина блока турбокода) ищет период не
  длиннее его — значение берётся при постановке разбора в очередь и хранится в
  задании (``период_до``), разбор читает его через :func:`период_до`;
- окна стола (поиск периода F3, автокорреляция, кандидаты периода, разметка
  символов) берут его как верхнюю границу по умолчанию.

``0`` — без предела: период ограничивает только длина записи (в ней должно
уложиться несколько периодов) и время. Настройки — файл
``<папка>/<ид человека>.json``; применяются сразу, без перезапуска.
"""

from __future__ import annotations

import contextvars
import json
import threading
from collections.abc import Iterator
from contextlib import contextmanager
from pathlib import Path
from typing import Any

from ..fayly import записать_атомарно

#: Максимальный период поиска по умолчанию, бит.
ПЕРИОД_ДО = 1_000_000
#: Меньше этого — не настройка, а ошибка ввода (у E1 цикл 256 бит, у мелких кадров — десятки).
ПЕРИОД_ДО_ОТ = 64
#: Больше этого числа бит в массиве не бывает (длина — 32-битное целое со знаком).
ПЕРИОД_ДО_НАИБОЛЬШИЙ = (1 << 31) - 1
#: Значение «без предела»: период ограничивает только длина записи.
БЕЗ_ПРЕДЕЛА = 0

ОШИБКА_ПЕРИОДА = (f"предел периода — целое от {ПЕРИОД_ДО_ОТ} до {ПЕРИОД_ДО_НАИБОЛЬШИЙ:,}".replace(",", " ")
                  + " бит или 0")


def период_из(значение: Any) -> int:
    """Число из ввода настройки: целое, строка цифр (пробелы между разрядами можно); иначе ValueError."""
    if isinstance(значение, bool):
        raise ValueError(ОШИБКА_ПЕРИОДА)
    if isinstance(значение, float):
        if not значение.is_integer():
            raise ValueError(ОШИБКА_ПЕРИОДА)
        значение = int(значение)
    if isinstance(значение, str):
        текст = значение.replace(" ", "").replace(" ", "").replace("_", "")
        if not текст.isdigit():
            raise ValueError(ОШИБКА_ПЕРИОДА)
        значение = int(текст)
    if not isinstance(значение, int):
        raise ValueError(ОШИБКА_ПЕРИОДА)
    if значение != БЕЗ_ПРЕДЕЛА and not ПЕРИОД_ДО_ОТ <= значение <= ПЕРИОД_ДО_НАИБОЛЬШИЙ:
        raise ValueError(ОШИБКА_ПЕРИОДА)
    return значение


def проверить(данные: Any) -> dict[str, Any]:
    """Настройки из запроса → чистый вид ({период_до}); ошибки ввода — ValueError словами."""
    if not isinstance(данные, dict):
        raise ValueError("настройки — объект {период_до}")
    итог = по_умолчанию()
    if "период_до" in данные:
        итог["период_до"] = период_из(данные["период_до"])
    return итог


def по_умолчанию() -> dict[str, Any]:
    return {"период_до": ПЕРИОД_ДО}


def наибольший(период_до: int | None, бит: int, периодов: int = 1) -> int:
    """Наибольший период, который есть смысл искать в записи из ``бит`` бит.

    Не длиннее настройки (``None`` — значение по умолчанию, 0 — без предела) и такой, чтобы
    в записи уложилось не меньше ``периодов`` периодов.
    """
    по_длине = max(0, int(бит)) // max(1, int(периодов))
    до = ПЕРИОД_ДО if период_до is None else int(период_до)
    return по_длине if до == БЕЗ_ПРЕДЕЛА else min(до, по_длине)


# -- предел текущего разбора ------------------------------------------------------------------
# Автомат зовёт поиск цикла из многих мест (каждый уровень, каждая ветвь); передавать предел
# аргументом через все — переписать полмодуля. Разбор ставит предел на время своей работы,
# поиск цикла читает его здесь.

_ТЕКУЩИЙ: contextvars.ContextVar[int | None] = contextvars.ContextVar("период_до", default=None)


def период_до() -> int:
    """Максимальный период поиска текущего разбора (без разбора — по умолчанию); 0 — без предела."""
    значение = _ТЕКУЩИЙ.get()
    return ПЕРИОД_ДО if значение is None else значение


@contextmanager
def с_пределом(до: int | None) -> Iterator[None]:
    """На время блока — свой максимальный период поиска (None — по умолчанию)."""
    метка = _ТЕКУЩИЙ.set(None if до is None else период_из(до))
    try:
        yield
    finally:
        _ТЕКУЩИЙ.reset(метка)


# -- хранение ---------------------------------------------------------------------------------

class НастройкиЛюдей:
    """Настройки анализа каждого человека — файл ``<папка>/<ид>.json``."""

    def __init__(self, папка: Path):
        self.папка = Path(папка)
        self._lock = threading.Lock()

    def _путь(self, пользователь: int) -> Path:
        return self.папка / f"{int(пользователь)}.json"

    def прочитать(self, пользователь: int) -> dict[str, Any]:
        """Настройки человека; испорченный или отсутствующий файл — значения по умолчанию."""
        try:
            данные = json.loads(self._путь(пользователь).read_text(encoding="utf-8"))
            return проверить(данные)
        except (OSError, ValueError, TypeError):
            return по_умолчанию()

    def записать(self, пользователь: int, данные: Any) -> dict[str, Any]:
        """Изменить настройки человека (что не названо — остаётся прежним); ошибки ввода — ValueError."""
        if not isinstance(данные, dict):
            raise ValueError("настройки — объект {период_до}")
        with self._lock:
            итог = проверить(self.прочитать(пользователь) | данные)
            self.папка.mkdir(parents=True, exist_ok=True)
            записать_атомарно(self._путь(пользователь), json.dumps(итог, ensure_ascii=False))
        return итог

    def период_до(self, пользователь: int) -> int:
        return int(self.прочитать(пользователь)["период_до"])
