"""Длинные линейные блочные коды вслепую: длина слова, проверки, LDPC.

Короткие коды (n ≤ 16) ищутся проверками Уолша — Адамара (kod), а длинные —
LDPC (сотни и тысячи бит), двоичный образ кодов Рида — Соломона и БЧХ — так
не видны: проверка длиной в сотни бит не помещается в окно. Для них —
ранговый метод, устойчивый к ошибкам линии.

**Зависимости с учётом шума.** Поток режется на слова длиной L; строки
матрицы — слова, столбцы — позиции. Проверка кода h — это вектор, для
которого W·hᵀ = 0 в каждом слове без ошибок. Точный ранг ломается от первой
же ошибки, поэтому зависимости ищутся на части слов (первые P строк), а
проверяются на остальных: у настоящей проверки доля слов, где она нарушена,
мала (у слова с ошибкой в одной из её позиций), у случайного вектора —
половина. Так работает при ошибках линии примерно до 10⁻³ для слов в сотни
бит (метод Барбье — Сико — Уку, «исключение через выбор опорных»).

**Длина слова.** Зависимости есть, только когда L кратна n (и окна
выровнены) или L ≥ 2n (тогда в окне всегда есть целое слово). Перебираем L
и берём первую, где они нашлись; выравнивание — по носителю проверок.

**Разреженные проверки.** Найденные зависимости — случайные векторы
пространства проверок, в них по половине единиц. У LDPC же есть базис из
разреженных проверок (вес 3…30). Их ищем в найденном пространстве методом
информационных множеств (Ли — Брикелл): случайная перестановка позиций,
приведение к ступенчатому виду — строки с малым весом и есть разреженные
проверки. Каждая сверяется с потоком.

**Квазицикличность.** Почти все стандартные LDPC — квазициклические: проверки
переходят в проверки при циклическом сдвиге внутри блоков по Z позиций.
Проверяем это для делителей n — так находится размер циркулянта Z.
"""

from __future__ import annotations

import time
from collections import Counter

import numpy as np

from . import gf2
from .nahodka import Находка

#: Доля нарушений, ниже которой вектор считается проверкой кода.
НАРУШЕНИЙ_ДО = 0.3
#: Сколько слов сверх длины слова брать для проверки найденных зависимостей.
ЗАПАС_СЛОВ = 400
#: Наибольшая длина слова при переборе, бит.
ДЛИНА_ДО = 1024
#: Для обычного разбора: слова до 512 бит и 20 с; глубокий — до 2048 и 5 минут.
ОБЫЧНО = {"до": 512, "бюджет": 20.0}
ГЛУБОКО = {"до": 2048, "бюджет": 300.0}
#: Наибольший вес «разреженной» проверки.
РАЗРЕЖЕННАЯ_ДО = 40
#: У LDPC проверки легче этой доли длины слова; у БЧХ, Голея и коротких кодов — тяжелее.
ДОЛЯ_ВЕСА_LDPC = 0.25
#: Сколько наборов слов пробовать при поиске проверок с учётом шума (предел — бюджет времени).
ШУМНЫХ_ПОПЫТОК = 2000
#: Проверки с учётом шума ищутся, если по найденным проверкам доля ошибок линии не меньше этой.
ОШИБОК_ОТ = 1e-5
#: Раз в столько попыток проверяется, растёт ли ранг найденных проверок; не вырос СТОЯТЬ_ДО раз подряд —
#: набор насыщен.
КАЖДЫЕ = 20
СТОЯТЬ_ДО = 6
#: Глубина чередования символов РС, которую пробовать (слова по байтам вперемешку).
ГЛУБИНА_РС_ДО = 16


def слова(биты: np.ndarray, L: int, начало: int = 0, сколько: int | None = None) -> np.ndarray:
    ряд = биты[начало:]
    всего = len(ряд) // L
    if сколько is not None:
        всего = min(всего, сколько)
    return ряд[:всего * L].reshape(всего, L)


def нарушения(W: np.ndarray, H: np.ndarray) -> np.ndarray:
    """Для каждой проверки (строка H) — доля слов W, где она нарушена."""
    if not len(H):
        return np.zeros(0)
    синдромы = (W.astype(np.int32) @ H.T.astype(np.int32)) & 1
    return синдромы.mean(axis=0)


def зависимости(W: np.ndarray, опорных: int) -> tuple[np.ndarray, np.ndarray]:
    """Проверки по первым ``опорных`` словам, сверенные с остальными.

    Возвращает векторы и доли нарушений на проверочных словах. Слова с
    ошибками среди опорных повышают ранг и «съедают» часть проверок, но
    оставшиеся — настоящие.
    """
    опорные, проверочные = W[:опорных], W[опорных:]
    H = gf2.ядро(опорные)
    if not len(H) or not len(проверочные):
        return H, np.ones(len(H))
    return H, нарушения(проверочные, H)


def длина_слова(биты: np.ndarray, *, до: int = ДЛИНА_ДО, бюджет: float = 30.0
                ) -> tuple[int, int, int] | None:
    """(L, найдено проверок, из скольких) — первая длина окна с проверками кода."""
    конец = time.monotonic() + бюджет
    for L in range(8, до + 1):
        if time.monotonic() > конец:
            return None
        опорных = L + 16
        W = слова(биты, L, сколько=опорных + ЗАПАС_СЛОВ)
        if len(W) < опорных + 64:
            return None
        H, доли = зависимости(W, опорных)
        годных = int(np.count_nonzero(доли < НАРУШЕНИЙ_ДО))
        if годных:
            return L, годных, len(H)
    return None


def _проверок(биты: np.ndarray, n: int, начало: int) -> int:
    опорных = n + 16
    W = слова(биты, n, начало, опорных + ЗАПАС_СЛОВ)
    if len(W) < опорных + 64:
        return 0
    _, доли = зависимости(W, опорных)
    return int(np.count_nonzero(доли < НАРУШЕНИЙ_ДО))


def выровнять(биты: np.ndarray, L: int) -> tuple[int, int] | None:
    """По окну L, где нашлись проверки, — длина слова n и начало слова.

    Кандидаты n — делители L. Для каждого начала слова, где проверки есть,
    их тем больше, чем точнее граница: при сдвинутой границе в окно целиком
    попадают лишь проверки, лежащие по одну её сторону (у LDPC такие есть —
    проверки разрежены), при верной — все. Кандидаты начала берутся из
    носителей проверок окна L: у проверок одного слова он внутри
    [начало, начало + n).
    """
    опорных = L + 16
    W = слова(биты, L, 0, опорных + ЗАПАС_СЛОВ)
    H, доли = зависимости(W, опорных)
    H = H[доли < НАРУШЕНИЙ_ДО]
    if not len(H):
        return None
    редкие = разреженные(H, W, попыток=40)
    носители = редкие if len(редкие) else H
    лучшее = None
    for n in sorted(d for d in range(8, L + 1) if L % d == 0):
        # Граница слова — там, где носители проверок начинаются или кончаются.
        счёт_начал: Counter = Counter({0: 1})
        for h in носители:
            места = np.flatnonzero(h)
            счёт_начал[int(места[0]) % n] += 1
            счёт_начал[int(места[-1] + 1) % n] += 1
        начала = [начало for начало, _ in счёт_начал.most_common(24)]
        for начало in начала:
            счёт = _проверок(биты, n, начало)
            if счёт and (лучшее is None or счёт / n > лучшее[0] + 1e-9):
                лучшее = (счёт / n, n, начало)
    if лучшее is None:
        return None
    # Уточнение: число проверок растёт по мере приближения к истинной границе
    # (в окно целиком попадает больше проверок) — идём туда, где их больше.
    _, n, начало = лучшее
    счёт = _проверок(биты, n, начало)
    for шаг in (1, -1):
        while True:
            соседний = _проверок(биты, n, (начало + шаг) % n)
            if соседний <= счёт:
                break
            начало, счёт = (начало + шаг) % n, соседний
    return n, начало


def пространство(W: np.ndarray, n: int) -> np.ndarray:
    """Проверки кода с учётом шума: объединение по нескольким наборам опорных слов."""
    найдено: list[np.ndarray] = []
    for проход in range(4):
        сдвиг = проход * (n + 16)
        часть = W[сдвиг:]
        if len(часть) < n + 16 + 64:
            break
        H, доли = зависимости(часть, n + 16)
        найдено.append(H[доли < НАРУШЕНИЙ_ДО])
    if not найдено:
        return np.zeros((0, n), dtype=np.uint8)
    все = np.vstack(найдено)
    приведённая, опорные = gf2.привести(gf2.упаковать(все), n)
    return gf2.распаковать(приведённая, n)


def разреженные(H: np.ndarray, W: np.ndarray, *, попыток: int = 200,
                вес_до: int = РАЗРЕЖЕННАЯ_ДО, сид: int = 1) -> np.ndarray:
    """Разреженные проверки в пространстве H (Ли — Брикелл), сверенные с потоком."""
    r, n = H.shape
    if not r:
        return H
    случай = np.random.default_rng(сид)
    найдено: dict[bytes, np.ndarray] = {}
    for _ in range(попыток):
        порядок = случай.permutation(n)
        переставлено = H[:, порядок]
        приведённая, опорные = gf2.привести(gf2.упаковать(переставлено), n)
        плотная = gf2.распаковать(приведённая, n)
        веса = плотная.sum(axis=1)
        for строка in плотная[(веса > 0) & (веса <= вес_до)]:
            исходная = np.zeros(n, dtype=np.uint8)
            исходная[порядок] = строка
            найдено.setdefault(np.packbits(исходная).tobytes(), исходная)
        if len(найдено) >= 4 * r:
            break
    if not найдено:
        return np.zeros((0, n), dtype=np.uint8)
    кандидаты = np.array(list(найдено.values()))
    доли = нарушения(W, кандидаты)
    return кандидаты[доли < НАРУШЕНИЙ_ДО]


def размер_циркулянта(проверки: np.ndarray, W: np.ndarray) -> int | None:
    """Наименьший Z > 1, делитель n, при котором сдвиг внутри блоков Z — снова проверка."""
    if not len(проверки):
        return None
    n = проверки.shape[1]
    образцы = проверки[:16]
    for Z in range(2, n // 2 + 1):
        if n % Z:
            continue
        сдвинуто = образцы.reshape(len(образцы), n // Z, Z)
        сдвинуто = np.roll(сдвинуто, 1, axis=2).reshape(len(образцы), n)
        if np.all(нарушения(W, сдвинуто) < НАРУШЕНИЙ_ДО):
            return Z
    return None


def описать(биты: np.ndarray, *, до: int = ДЛИНА_ДО, бюджет: float = 30.0) -> dict | None:
    """Полный слепой разбор длинного кода: n, k, проверки, LDPC-признаки, Z."""
    окно = длина_слова(биты, до=до, бюджет=бюджет)
    if окно is None:
        return None
    L, _, _ = окно
    выровнено = выровнять(биты, L)
    if выровнено is None:
        return None
    n, начало = выровнено
    W = слова(биты, n, начало)
    H = пространство(W, n)
    r = len(H)
    итог = {"n": n, "k": n - r, "начало": начало, "проверок": r,
            "нарушено": float(нарушения(W, H).mean()) if r else 1.0}
    редкие = разреженные(H, W)
    if len(редкие):
        веса = редкие.sum(axis=1)
        итог["разреженных"] = len(редкие)
        итог["веса_строк"] = Counter(веса.tolist())
        # Ранг разреженных: покрывают ли они всё пространство проверок.
        итог["ранг_разреженных"] = gf2.ранг(редкие)
        итог["Z"] = размер_циркулянта(редкие, W)
        итог["столбцы"] = Counter(редкие.sum(axis=0).tolist())
    return итог


def проверки_с_шумом(W: np.ndarray, *, доля_опорных: float = 0.75, попыток: int = 300,
                     вес_до: int = РАЗРЕЖЕННАЯ_ДО, сид: int = 1, бюджет: float = 60.0
                     ) -> np.ndarray:
    """Разреженные проверки при ошибках линии: случайные наборы слов + Ли — Брикелл.

    Берём P ≈ ¾·n случайных слов и случайную перестановку позиций, приводим
    к ступенчатому виду. Для каждой свободной позиции j вектор
    e_j + Σ R[i, j]·e_{опорная i} зануляет все P слов; если он лёгкий — это
    кандидат. Разреженная проверка кода попадает в кандидаты, когда все её
    позиции, кроме одной, оказались среди опорных, а P слов её не нарушили —
    при весе 7, n = 648, ошибках 10⁻³ это доли процента на попытку, но
    проверок сотни и попыток сотни. Случайный лёгкий вектор, зануляющий сотни
    случайных слов, практически невозможен (2⁻ᴾ), поэтому ложных почти нет,
    а каждый кандидат ещё сверяется со всеми словами.
    """
    M, n = W.shape
    P = int(доля_опорных * n)
    if M < P + 64:
        return np.zeros((0, n), dtype=np.uint8)
    случай = np.random.default_rng(сид)
    конец = time.monotonic() + бюджет
    найдено: dict[bytes, np.ndarray] = {}
    ранг, стоит = 0, 0
    for попытка in range(попыток):
        if time.monotonic() > конец:
            break
        if попытка and попытка % КАЖДЫЕ == 0 and найдено:
            # Насыщение: ранг сверенных с потоком проверок не растёт СТОЯТЬ_ДО проверок подряд.
            кандидаты = np.array(list(найдено.values()))
            новый = gf2.ранг(кандидаты[нарушения(W, кандидаты) < НАРУШЕНИЙ_ДО])
            стоит = стоит + 1 if новый <= ранг else 0
            ранг = max(ранг, новый)
            if стоит >= СТОЯТЬ_ДО:
                break
        строки = случай.choice(M, P, replace=False)
        порядок = случай.permutation(n)
        приведённая, опорные = gf2.привести(gf2.упаковать(W[строки][:, порядок]), n)
        R = gf2.распаковать(приведённая, n)
        свободные = np.setdiff1d(np.arange(n), опорные)
        веса = R[:, свободные].sum(axis=0) + 1
        for j in свободные[веса <= вес_до]:
            h = np.zeros(n, dtype=np.uint8)
            h[j] = 1
            h[np.array(опорные)[R[:, j] == 1]] = 1
            исходная = np.zeros(n, dtype=np.uint8)
            исходная[порядок] = h
            найдено.setdefault(np.packbits(исходная).tobytes(), исходная)
    if not найдено:
        return np.zeros((0, n), dtype=np.uint8)
    кандидаты = np.array(list(найдено.values()))
    return кандидаты[нарушения(W, кандидаты) < НАРУШЕНИЙ_ДО]


def дополнить_сдвигами(проверки: np.ndarray, Z: int, W: np.ndarray) -> np.ndarray:
    """Квазициклический код: все сдвиги найденных проверок внутри блоков Z, сверенные."""
    n = проверки.shape[1]
    все: dict[bytes, np.ndarray] = {}
    for h in проверки:
        блоки = h.reshape(n // Z, Z)
        for s in range(Z):
            вектор = np.roll(блоки, s, axis=1).reshape(n)
            все.setdefault(np.packbits(вектор).tobytes(), вектор)
    кандидаты = np.array(list(все.values()))
    return кандидаты[нарушения(W, кандидаты) < НАРУШЕНИЙ_ДО]


def независимые(проверки: np.ndarray) -> np.ndarray:
    """Независимые проверки, начиная с самых лёгких: разреженный базис пространства.

    Жадно по весу: проверка берётся, если она не выражается через уже
    взятые. Приведение ведётся нарастающе — каждая новая строка сокращается
    по уже приведённым опорным строкам, без пересчёта с нуля.
    """
    if not len(проверки):
        return проверки
    n = проверки.shape[1]
    порядок = np.argsort(проверки.sum(axis=1), kind="stable")
    упакованные = gf2.упаковать(проверки[порядок])
    опорные_строки: list[np.ndarray] = []
    опорные_столбцы: list[int] = []
    выбрано: list[int] = []
    for номер, строка in enumerate(упакованные):
        остаток = строка.copy()
        for опорная, столбец in zip(опорные_строки, опорные_столбцы, strict=False):
            w, b = divmod(столбец, 64)
            if (int(остаток[w]) >> b) & 1:
                остаток ^= опорная
        единицы = np.flatnonzero(gf2.распаковать(остаток[None, :], n)[0])
        if not len(единицы):
            continue
        опорные_строки.append(остаток)
        опорные_столбцы.append(int(единицы[0]))
        выбрано.append(int(порядок[номер]))
    return проверки[выбрано]


def мин_сумма(W: np.ndarray, H: np.ndarray, итераций: int = 30) -> tuple[np.ndarray, np.ndarray]:
    """Декодер «минимум — сумма» по разреженной H на жёстких решениях.

    Возвращает исправленные слова и признак «синдром нулевой» для каждого.
    """
    m, n = H.shape
    степени = H.sum(axis=1)
    d = max(2, int(степени.max()))                          # у проверки веса 1 — ещё фиктивная позиция
    связи = np.full((m, d), n, dtype=np.int64)              # n — фиктивная позиция
    for i in range(m):
        позиции = np.flatnonzero(H[i])
        связи[i, :len(позиции)] = позиции
    есть = связи < n
    канал = (1.0 - 2.0 * W.astype(np.float32))              # +1 для 0, −1 для 1
    M = len(W)
    к_проверке = np.zeros((M, m, d), dtype=np.float32)
    слова_ = W.copy()
    for _ in range(итераций):
        # Сумма входящих в каждую позицию сообщений от проверок.
        сумма = np.zeros((M, n + 1), dtype=np.float32)
        np.add.at(сумма, (slice(None), связи), к_проверке * есть)
        полная = канал + сумма[:, :n]
        слова_ = (полная < 0).astype(np.uint8)
        синдром = (слова_.astype(np.int32) @ H.T.astype(np.int32)) & 1
        if not синдром.any():
            break
        # Сообщения позиция → проверка: всё, кроме своего.
        дополненная = np.concatenate([полная, np.zeros((M, 1), np.float32)], axis=1)
        от_позиции = дополненная[:, связи] - к_проверке
        от_позиции = np.where(есть, от_позиции, np.float32(1e9))
        знак = np.sign(от_позиции)
        знак[знак == 0] = 1
        модуль = np.abs(от_позиции)
        общий_знак = np.prod(знак, axis=2, keepdims=True)
        порядок = np.sort(модуль, axis=2)
        первый, второй = порядок[:, :, :1], порядок[:, :, 1:2]
        наименьший = np.where(модуль == первый, второй, первый)
        к_проверке = 0.75 * общий_знак * знак * наименьший * есть
    синдром = (слова_.astype(np.int32) @ H.T.astype(np.int32)) & 1
    return слова_, ~синдром.any(axis=1)


def информационные(H: np.ndarray) -> np.ndarray:
    """Позиции, на которых код систематичен: опорные столбцы порождающей матрицы."""
    n = H.shape[1]
    G = gf2.ядро(H) if len(H) else np.eye(n, dtype=np.uint8)
    _, опорные = gf2.привести(gf2.упаковать(G), n)
    return np.array(опорные, dtype=np.int64)


def _опознать_циклический(W: np.ndarray, n: int) -> dict | None:
    """Рида — Соломона (символы m бит, при чередовании глубины I) или БЧХ — по общим корням слов.

    Слово длиной I·N символов из I слов РС, перемешанных по символам (CCSDS, IESS),
    разбирается на I слов по N символов: символ j·I + i — i-го слова.
    """
    from . import rs_bch
    образец = W[:128]
    for m in (8, 4, 5, 6, 7, 9, 10, 3):
        if n % m:
            continue
        for I in range(1, ГЛУБИНА_РС_ДО + 1):
            N = n // m // I
            if (n // m) % I or not 4 <= N <= (1 << m) - 1:
                continue
            символы = rs_bch.в_символы(образец, m)
            слова_рс = символы.reshape(len(символы), N, I).transpose(0, 2, 1).reshape(-1, N)[:128]
            найдено = rs_bch.опознать(слова_рс, m, двоичный=False)
            if найдено is not None and найдено["подряд"] >= 2:
                найдено["глубина"] = I
                найдено["n"] = N
                найдено["k"] = N - len(найдено["корни"])
                return найдено
    m = max(3, int(np.ceil(np.log2(n + 1))))
    if m <= 8:
        return rs_bch.опознать(образец, m, двоичный=True)
    return None


def _в_биты_символов(символы: np.ndarray, m: int) -> np.ndarray:
    """Символы (M × N) → биты (M × N·m), старший бит символа первым."""
    сдвиги = np.arange(m - 1, -1, -1)
    return ((символы[..., None] >> сдвиги) & 1).astype(np.uint8).reshape(len(символы), -1)


def исправить_циклический(W: np.ndarray, п: dict) -> tuple[np.ndarray, list[str], dict]:
    """Исправить слова РС (с чередованием) или БЧХ по найденным корням: (слова, отчёт, числа)."""
    from . import rs_bch
    m, p, fcr, шаг = п["m"], п["многочлен"], п["fcr"], п.get("шаг", 1)
    корней = п["подряд"] - п["подряд"] % 2
    if корней < 2:
        return W, ["корней подряд меньше двух — ошибки не исправляются"], {}
    if п["вид"] == "БЧХ":
        исправленные, исправлено = rs_bch.исправить(W, p, fcr, корней, шаг, двоичный=True)
        слова_ = исправленные.astype(np.uint8)
        единица, всего_символов = "бит", W.size
    else:
        I = п.get("глубина", 1)
        символы = rs_bch.в_символы(W, m)
        M, всего = символы.shape
        N = всего // I
        подслова = символы.reshape(M, N, I).transpose(0, 2, 1).reshape(M * I, N)
        исправленные, исправлено = rs_bch.исправить(подслова, p, fcr, корней, шаг)
        символы = исправленные.reshape(M, I, N).transpose(0, 2, 1).reshape(M, всего)
        слова_ = _в_биты_символов(символы, m)
        единица, всего_символов = "символов", подслова.size
    число = int(исправлено[исправлено > 0].sum())
    неисправимых = int((исправлено < 0).sum())
    итог, ошибок = rs_bch.итог_словами(исправлено, единица, "бит" if единица == "бит" else "символ",
                                       всего_символов)
    строки = [f"исправление алгебраическое (Берлекэмп — Мэсси, Ченя, Форни): до {корней // 2} "
              f"{единица} в слове", итог]
    return слова_, строки, {"исправлено": число, "неисправимых": неисправимых, "ошибок_в_линии": ошибок}


def _промах_границы(проверки: np.ndarray, n: int) -> int:
    """На сколько бит сдвинуть начало слова: крайние позиции, не входящие ни в одну проверку, — кусок
    соседнего слова (в конце окна — начало следующего: сдвиг назад; в начале — конец предыдущего:
    вперёд). Промах больше n/8 или проверок нет — 0."""
    if not len(проверки):
        return 0
    занятые = np.flatnonzero(проверки.any(axis=0))
    хвост, голова = n - 1 - int(занятые[-1]), int(занятые[0])
    if хвост and not голова and хвост <= n // 8:
        return -хвост
    if голова and not хвост and голова <= n // 8:
        return голова
    return 0


def найти(биты: np.ndarray, *, до: int = ДЛИНА_ДО, бюджет: float = 30.0) -> Находка | None:
    """Длинный линейный блочный код: LDPC, двоичный образ РС, БЧХ и прочие."""
    from .nahodka import Находка
    начало_работы = time.monotonic()
    окно = длина_слова(биты, до=до, бюджет=бюджет)
    if окно is None:
        return None
    L, _, _ = окно
    выровнено = выровнять(биты, L)
    if выровнено is None:
        return None
    n, начало = выровнено
    итог = _разобрать(биты, n, начало, бюджет=бюджет, начало_работы=начало_работы)
    return итог[0] if итог else None


#: Столбец нагрузки считается постоянным (заполнение), если одно значение в нём — не реже этой доли кадров
#: (ошибки линии портят и заполнение); при малом числе кадров — только строго одинаковый.
ПОСТОЯННЫЙ_ОТ = 0.95
КАДРОВ_ДЛЯ_ДОЛИ = 20


def _постоянные(W: np.ndarray) -> np.ndarray:
    """Столбцы (почти) одинаковые во всех строках: заполнение, а не биты слов кода."""
    if len(W) < КАДРОВ_ДЛЯ_ДОЛИ:
        return np.all(W == W[:1], axis=0)
    доля = W.mean(axis=0)
    return (доля <= 1 - ПОСТОЯННЫЙ_ОТ) | (доля >= ПОСТОЯННЫЙ_ОТ)


def хвост_нагрузки(нагрузка: np.ndarray) -> int:
    """Сколько последних столбцов нагрузки (кадров × P) постоянны во всех кадрах — заполнение (и, бывает,
    постоянный последний бит слова). Один кадр — хвоста не видно (0)."""
    кадров, P = нагрузка.shape
    if кадров < 2:
        return 0
    разные = np.flatnonzero(~_постоянные(нагрузка))
    return P - int(разные[-1]) - 1 if len(разные) else P


def _проверок_в_кадрах(биты: np.ndarray, n: int) -> int:
    """Проверки окна n с начала ряда, в которые входит хоть один непостоянный столбец: связи одних
    постоянных столбцов (заполнение, попавшее в окно) — не код."""
    опорных = n + 16
    W = слова(биты, n, 0, опорных + ЗАПАС_СЛОВ)
    if len(W) < опорных + 64:
        return 0
    H, доли = зависимости(W, опорных)
    H = H[доли < НАРУШЕНИЙ_ДО]
    return int(np.count_nonzero(H[:, ~_постоянные(W)].any(axis=1))) if len(H) else 0


def найти_в_кадрах(нагрузка: np.ndarray, *, до: int = ГЛУБОКО["до"], бюджет: float = 60.0
                   ) -> tuple[Находка, np.ndarray] | None:
    """Вслепую, когда известна нагрузка кадров (кадров × P бит, синхрослово убрано): слова кода лежат
    с начала нагрузки подряд, их m в кадре, в конце — заполнение (столбцы, одинаковые во всех кадрах).
    Перебора длины окна нет: пробуются только n = P′/m, где P′ — нагрузка без хвоста (от P − t до P,
    t — сколько последних столбцов постоянны: последний бит слова тоже бывает постоянным), от меньших n
    (64 ≤ n ≤ ``до``); первая длина с проверками — длина слова. Возвращает находку и разреженные
    проверки (у LDPC — его H; пусто, если код не LDPC)."""
    начало_работы = time.monotonic()
    P = нагрузка.shape[1]
    t = хвост_нагрузки(нагрузка)
    if t > P // 2:
        return None                                   # нагрузка почти вся постоянна — кода в ней нет
    длины = sorted({(P_ // m, P_) for P_ in range(P - t, P + 1) for m in range(1, P_ // 64 + 1)
                    if P_ % m == 0 and P_ // m <= до})
    for n, P_ in длины:
        if time.monotonic() - начало_работы > бюджет:
            return None
        ряд = нагрузка[:, :P_].reshape(-1)
        if _проверок_в_кадрах(ряд, n):
            return _разобрать(ряд, n, 0, бюджет=бюджет, начало_работы=начало_работы)
    # Слов меньше, чем нужно ранговому методу (n + 80): у квазициклического кода блочный циклический
    # сдвиг слова — тоже слово, и каждое слово даёт до Z слов. Пробуются Z — делители n.
    for n, P_ in длины:
        W = нагрузка[:, :P_].reshape(-1, n)
        if len(W) >= n + 16 + 64 or n > СДВИГАМИ_ДО:
            continue
        # Сдвиг по блокам меньше настоящего циркулянта (его делитель) бывает симметрией лишь части
        # проверок: находится надкод. Поэтому после первого Z с проверками пробуются кратные ему, и
        # берётся Z, при котором проверок больше всего.
        лучшие: list[tuple[int, int]] = []
        for Z in циркулянты(n, len(W)):
            if time.monotonic() - начало_работы > бюджет:
                return None
            if лучшие and Z % лучшие[0][1]:
                continue
            проверок = _проверок_в_кадрах(со_сдвигами(W, Z, n + 16 + СДВИГАМИ_ЗАПАС).reshape(-1), n)
            if проверок:
                лучшие.append((проверок, Z))
        for _, Z in sorted(лучшие, key=lambda п: (-п[0], п[1]))[:1]:
            ряд = со_сдвигами(W, Z, n + 16 + СДВИГАМИ_ЗАПАС).reshape(-1)
            найдено = _разобрать(ряд, n, 0, бюджет=бюджет, начало_работы=начало_работы)
            if найдено is None:
                continue
            н, H = найдено
            k = int(н.свойства["k"])
            н.дальше = np.asarray(н.дальше)[:len(W) * k]
            н.подробно.insert(0, f"слов в записи {len(W)} — меньше, чем нужно ранговому методу ({n + 80}): "
                                 f"к ним добавлены их блочные циклические сдвиги по Z = {Z} бит (у "
                                 f"квазициклического кода это тоже слова); данные — только исходных слов")
            н.свойства["сдвигами_z"] = Z
            return н, H
    return None


#: Слова и их сдвиги: строк сверх n + 16 (сверка найденных связей); слово — не длиннее СДВИГАМИ_ДО.
СДВИГАМИ_ЗАПАС = 128
СДВИГАМИ_ДО = 2048
#: Блоков в слове квазициклического кода — не больше стольких; циркулянт — не меньше ЦИРКУЛЯНТ_ОТ.
БЛОКОВ_ДО = 96
ЦИРКУЛЯНТ_ОТ = 8


def циркулянты(n: int, слов: int) -> list[int]:
    """Размеры циркулянта Z для пробы сдвигами: делители n (n/Z ≤ БЛОКОВ_ДО), при которых слов·Z
    хватает ранговому методу; от меньших (больше блоков — реже совпадает случайно)."""
    нужно = n + 16 + 64
    return [Z for Z in range(ЦИРКУЛЯНТ_ОТ, n // 2 + 1)
            if n % Z == 0 and n // Z <= БЛОКОВ_ДО and слов * Z >= нужно]


def со_сдвигами(W: np.ndarray, Z: int, нужно: int) -> np.ndarray:
    """Слова и их блочные циклические сдвиги на 1, 2, … бит внутри блоков по Z (исходные — первыми),
    пока строк не станет ``нужно`` (или все Z сдвигов)."""
    M, n = W.shape
    блоки = W.reshape(M, n // Z, Z)
    сдвигов = min(Z, -(-нужно // M))
    return np.concatenate([np.roll(блоки, j, axis=2).reshape(M, n) for j in range(сдвигов)], axis=0)


def _разобрать(биты: np.ndarray, n: int, начало: int, *, бюджет: float, начало_работы: float
               ) -> tuple[Находка, np.ndarray] | None:
    """Код с известными длиной слова и началом: пространство проверок, разреженный базис (с учётом
    ошибок линии), LDPC или циклический код, исправление. Находка и разреженные проверки."""
    W = слова(биты, n, начало)
    H = пространство(W, n)
    редкие = разреженные(H, W) if len(H) else H
    # Ошибки линии: опорные слова с ошибками «съедают» проверки — пространство неполное (у F-LDPC
    # K = 256 при 10⁻³ из 256 проверок остаётся ~70, у K = 512 — одна). Есть ли ошибки, видно по уже
    # найденным проверкам: проверка веса w нарушается примерно в w·p слов. Если p заметно больше нуля,
    # разреженные проверки ищутся ещё и по случайным наборам слов (проверки_с_шумом): у лёгких проверок
    # (вес до ~15) так находится весь базис. Каждая найденная сверена с потоком.
    опора = редкие if len(редкие) else H
    ошибок = float(np.mean(нарушения(W[:2000], опора) / np.maximum(1, опора.sum(axis=1)))) if len(опора) else 0.0
    осталось = бюджет - (time.monotonic() - начало_работы)
    if ошибок >= ОШИБОК_ОТ and осталось > 1 and len(W) >= n // 2 + 64:
        шумные = проверки_с_шумом(W, попыток=ШУМНЫХ_ПОПЫТОК, бюджет=осталось)
        if len(шумные):
            редкие = np.vstack([редкие, шумные]) if len(редкие) else шумные
        # При ошибках и граница слова находится с промахом на несколько бит: тогда крайние позиции окна
        # (кусок соседнего слова) не входят ни в одну найденную проверку, а проверки через границу не
        # находятся. Сдвигаем начало на эти позиции и добираем проверки ещё раз.
        сдвиг = _промах_границы(редкие, n)
        if сдвиг:
            начало = (начало + сдвиг) % n
            W = слова(биты, n, начало)
            редкие = np.roll(редкие, -сдвиг, axis=1)
            редкие = редкие[нарушения(W[:2000], редкие) < НАРУШЕНИЙ_ДО]
            осталось = бюджет - (time.monotonic() - начало_работы)
            if осталось > 1:
                шумные = проверки_с_шумом(W, попыток=ШУМНЫХ_ПОПЫТОК, бюджет=осталось, сид=2)
                if len(шумные):
                    редкие = np.vstack([редкие, шумные]) if len(редкие) else шумные
    Z = размер_циркулянта(редкие, W) if len(редкие) else None
    if Z and len(редкие):
        редкие = дополнить_сдвигами(редкие, Z, W)
    # Для отчёта и декодера — независимый базис из самых лёгких проверок:
    # у LDPC это и есть его матрица H (с точностью до порядка строк).
    редкие = независимые(редкие) if len(редкие) else редкие
    ранг_редких = len(редкие)
    r = max(len(H), ранг_редких)
    if not r:
        # Окно дало связи, а на выровненных словах их нет — кода нет (k = n).
        return None
    k = n - r
    нарушено = float(нарушения(W, H).mean()) if len(H) else 1.0
    подробно = [f"длина слова n = {n}, начало слова — бит {начало}; проверок {r} → k = {k}, "
                f"скорость {k}/{n}"]
    from .kod import ИЗВЕСТНЫЕ  # noqa: PLC0415
    что = f"линейный блочный код ({n}, {k})" + (
        f" — параметры как у кода {ИЗВЕСТНЫЕ[(n, k)]}" if (n, k) in ИЗВЕСТНЫЕ else "")
    ldpc = ранг_редких >= max(1, int(0.9 * r)) and len(редкие) and \
        int(редкие.sum(axis=1).max()) <= min(РАЗРЕЖЕННАЯ_ДО, ДОЛЯ_ВЕСА_LDPC * n)
    циклический = None
    if ldpc:
        веса = Counter(редкие.sum(axis=1).tolist())
        столбцы = Counter(редкие.sum(axis=0).tolist())
        что = f"LDPC ({n}, {k})" + (f", квазициклический, циркулянт Z = {Z}" if Z else "")
        подробно.append("проверки разрежены — признак LDPC: вес строк " + ", ".join(
            f"{в}×{с}" for в, с in sorted(веса.items())) + "; вес столбцов " + ", ".join(
            f"{в}×{с}" for в, с in sorted(столбцы.items())))
        if Z:
            подробно.append(f"проверки переходят в проверки при циклическом сдвиге внутри "
                            f"блоков по {Z} бит: базовая матрица {r // Z} × {n // Z}")
    else:
        циклический = _опознать_циклический(W, n)
        if циклический is not None:
            п = циклический
            I = п.get("глубина", 1)
            что = (f"код {п['вид']} ({п['n']}, {п['k']}), t = {п['t']}"
                   + (f", символ {п['m']} бит" if п["вид"] != "БЧХ" else "")
                   + (f", чередование {I} слов по символам" if I > 1 else ""))
            β = "α" if п.get("шаг", 1) == 1 else f"β = α^{п['шаг']}"
            подробно.append(
                f"поле GF(2^{п['m']}) по многочлену 0x{п['многочлен']:X}; корни порождающего "
                f"многочлена — степени {β} с {п['fcr']}-й по {п['fcr'] + п['подряд'] - 1}-ю подряд "
                f"({п['подряд']}), всего корней {len(п['корни'])}; слова зануляются в корнях в "
                f"{п['доля'] * 100:.1f} % случаев")
            if I > 1:
                подробно.append(f"слово {n} бит — {I} слов РС по {п['n']} символов, перемешанных по "
                                f"символам (символ j·{I} + i — i-го слова)")
    # Исправление ошибок: для LDPC — декодер «минимум — сумма» по найденным проверкам.
    слова_ = W
    годных = float(np.mean(~(((W.astype(np.int32) @ H.T.astype(np.int32)) & 1).any(axis=1)))) \
        if len(H) else 0.0
    свойства: dict = {"n": n, "k": k, "начало": начало}
    if ldpc:
        слова_, чисто = мин_сумма(W[:4000], редкие)
        подробно.append(f"слов без ошибок до декодирования: {годных * 100:.1f} %; после "
                        f"декодера «минимум — сумма» по найденным проверкам: "
                        f"{чисто.mean() * 100:.1f} %")
    elif циклический is not None:
        подробно.append(f"слов с нулевым синдромом до декодирования: {годных * 100:.1f} %")
        слова_, строки, числа = исправить_циклический(W, циклический)
        подробно += строки
        свойства.update(числа)
    else:
        from . import ispravlenie  # noqa: PLC0415
        исправленные, исправлено, таблица = ispravlenie.исправить(W, H)
        if таблица is None:
            подробно.append(f"слов с нулевым синдромом: {годных * 100:.1f} % (проверок больше 64 — "
                            f"ошибки не исправляются)")
        else:
            from . import rs_bch  # noqa: PLC0415
            слова_ = исправленные
            бит = int(исправлено[исправлено > 0].sum())
            итог, ошибок = rs_bch.итог_словами(исправлено, "бит", "бит", W.size)
            подробно.append(f"слов с нулевым синдромом до декодирования: {годных * 100:.1f} %; "
                            f"исправление по синдрому — гарантированно до t = {таблица.t} ошибок в "
                            f"слове: {итог}")
            свойства.update({"t": таблица.t, "исправлено": бит, "неисправимых": int((исправлено < 0).sum()),
                             "ошибок_в_линии": ошибок})
    позиции = информационные(редкие if ldpc else H)
    подробно.append("данные взяты с позиций, где код систематичен (" + (
        "первые k" if np.array_equal(позиции, np.arange(len(позиции))) else "выборочные")
        + f" {len(позиции)} позиций слова) — в предположении систематического кодера")
    подробно.append(f"поиск занял {time.monotonic() - начало_работы:.1f} с")
    return Находка(
        уровень="код", что=что, уверенность=max(0.0, 1 - 2 * нарушено),
        мера=f"{r} проверочных связей выполнены в среднем в "
             f"{(1 - нарушено) * 100:.1f} % слов (у случайного вектора — 50 %)",
        подробно=подробно, дальше=слова_[:, позиции].reshape(-1), вид_дальше="биты",
        сверка=1 - нарушено, свойства=свойства), (редкие if ldpc else np.zeros((0, n), dtype=np.uint8))


# -- код Рида — Соломона в блоке известной длины (кадр без синхрослова, выход декодера) ------
#
# Длина блока известна (нагрузка цикла, данные внутреннего кода): блок из P байт — это I слов
# РС по N = P / I символов, перемешанных по символам (CCSDS, IESS: байт j·I + i — i-го слова).
# Байты бывают в двойном базисе Берлекэмпа (CCSDS): перед расчётом РС их переводят в обычный.
# Таблица перехода — по libfec (Ph. Karn, gen_ccsds_tal.c): бит k входа добавляет tal[7 − k]
# (tal = 8D EF EC 86 FA 99 AF 7B); проверка — прямой и обратный переходы взаимно обратны,
# и слова CCSDS (255, 223) после перехода делятся на порождающий многочлен (тест).

_TAL = (0x8D, 0xEF, 0xEC, 0x86, 0xFA, 0x99, 0xAF, 0x7B)


def _двойной_базис() -> tuple[np.ndarray, np.ndarray]:
    """(обычный → двойной, двойной → обычный) — таблицы на 256 значений."""
    в_двойной = np.zeros(256, dtype=np.uint8)
    for i in range(256):
        v = 0
        for k in range(8):
            if i >> k & 1:
                v ^= _TAL[7 - k]
        в_двойной[i] = v
    из_двойного = np.zeros(256, dtype=np.uint8)
    из_двойного[в_двойной] = np.arange(256, dtype=np.uint8)
    return в_двойной, из_двойного


В_ДВОЙНОЙ, ИЗ_ДВОЙНОГО = _двойной_базис()
#: Слов РС (после разбора чередования) для поиска корней — меньше, чем в общем поиске: блок
#: известен, перебор — по глубине и базису.
СЛОВ_ДЛЯ_КОРНЕЙ = 64
#: Наименьшая длина слова РС в символах, которую пробовать в блоке.
РС_N_ОТ = 16


def рс_в_блоке(биты: np.ndarray, длина: int, *, бюджет: float = 30.0) -> Находка | None:
    """Код РС над GF(256) по блокам длиной ``длина`` бит: чередование, базис, исправление ошибок."""
    from . import rs_bch
    from .nahodka import Находка
    if длина % 8 or длина < 8 * РС_N_ОТ:
        return None
    P = длина // 8
    блоков = len(биты) // длина
    if блоков < 8:
        return None
    конец = time.monotonic() + бюджет
    байты = np.packbits(np.asarray(биты[:блоков * длина], dtype=np.uint8).reshape(блоков, длина), axis=1)
    # Сперва глубины, при которых слово длиннее (полная длина 255 — чаще всего).
    глубины = sorted((I for I in range(1, ГЛУБИНА_РС_ДО + 1)
                      if P % I == 0 and РС_N_ОТ <= P // I <= 255), key=lambda I: -(P // I))
    найдено = None
    for базис in ("обычный", "двойной"):
        б = байты if базис == "обычный" else ИЗ_ДВОЙНОГО[байты]
        for I in глубины:
            if time.monotonic() > конец:
                return None
            N = P // I
            образец = б[:max(1, СЛОВ_ДЛЯ_КОРНЕЙ // I + 1)].astype(np.int64)
            слова = образец.reshape(-1, N, I).transpose(0, 2, 1).reshape(-1, N)[:СЛОВ_ДЛЯ_КОРНЕЙ]
            п = rs_bch.опознать(слова, 8, двоичный=False)
            if п is not None and п["подряд"] >= 4:
                найдено = (базис, I, N, п)
                break
        if найдено:
            break
    if найдено is None:
        return None
    базис, I, N, п = найдено
    б = (байты if базис == "обычный" else ИЗ_ДВОЙНОГО[байты]).astype(np.int64)
    корней = п["подряд"] - п["подряд"] % 2
    k = N - корней
    слова = б.reshape(блоков, N, I).transpose(0, 2, 1).reshape(блоков * I, N)
    до = float(np.mean(~rs_bch.синдромы(слова[:4096], п["многочлен"], п["fcr"], корней, п["шаг"]).any(axis=1)))
    исправленные, исправлено = rs_bch.исправить(слова, п["многочлен"], п["fcr"], корней, п["шаг"])
    блоки = исправленные.reshape(блоков, I, N).transpose(0, 2, 1).reshape(блоков, P).astype(np.uint8)
    if базис == "двойной":
        блоки = В_ДВОЙНОЙ[блоки]
    данные = np.unpackbits(блоки[:, :I * k], axis=1).reshape(-1)
    число = int(исправлено[исправлено > 0].sum())
    неисправимых = int((исправлено < 0).sum())
    β = "α" if п["шаг"] == 1 else f"β = α^{п['шаг']}"
    что = (f"код Рида — Соломона ({N}, {k}) над GF(256), t = {корней // 2}"
           + (f", чередование {I} слов по байтам" if I > 1 else "")
           + (", двойной базис (как у CCSDS)" if базис == "двойной" else "")
           + f" — в блоке {P} байт")
    return Находка(
        уровень="код", что=что, уверенность=до if до >= 0.5 else п["доля"],
        мера=f"слова зануляются в корнях порождающего многочлена в {п['доля'] * 100:.1f} % случаев; "
             f"нулевой синдром до исправления — у {до * 100:.1f} % слов",
        подробно=[
            f"поле GF(256) по многочлену 0x{п['многочлен']:X}; корни — степени {β} с {п['fcr']}-й "
            f"по {п['fcr'] + корней - 1}-ю ({корней} подряд)",
            f"блок {P} байт = {I} × {N}: байт j·{I} + i — i-го слова; данные — первые {I * k} байт "
            f"блока, проверочные — последние {I * корней}"
            + ("; байты в двойном базисе Берлекэмпа — для расчёта переводятся в обычный "
               "(таблица перехода как у libfec)" if базис == "двойной" else ""),
            "исправление алгебраическое (Берлекэмп — Мэсси, Ченя, Форни): "
            + rs_bch.итог_словами(исправлено, "байт", "байт", слова.size)[0],
        ],
        дальше=данные, вид_дальше="биты", сверка=до,
        свойства={"N": N, "k": k, "глубина": I, "базис": базис, "многочлен": п["многочлен"],
                  "fcr": п["fcr"], "шаг": п["шаг"], "исправлено": число, "неисправимых": неисправимых,
                  "данных_в_блоке": 8 * I * k})
