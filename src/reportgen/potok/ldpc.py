ПРОБНЫХ_СЛОВ = 8


def _пробное(биты: np.ndarray, схема: Схема, начало: int, слов: int) -> Tuple[float, float]:
    """Пробное декодирование нескольких слов: (доля сошедшихся, доля исправленных принятых бит)."""
    L = схема.длина
    слов = min(слов, (len(биты) - начало) // L)
    if слов < 1:
        return 0.0, 1.0
    принятые = биты[начало:начало + слов * L].reshape(слов, L)
    слова, сошлось = мин_сумма(схема.llr(принятые), схема.матрица.связи(), схема.матрица.n, 50)
    return float(сошлось.mean()), float((слова[:, схема.переданы] != принятые).mean())


def варианты_схемы(схема: Схема, блок: Optional[int] = None, как: str = ""
                   ) -> List[Tuple[str, Схема]]:
    """Как слово может лежать в потоке: базовая схема и, если известен блок данных, частые.

    Если длина блока данных известна (нагрузка кадра, выход декодера) и
    переданное слово короче базового в целое число раз меньше блока,
    недостающие d позиций — ещё выколотые первые или последние переданные
    позиции (согласование скорости) либо укороченные первые или последние
    информационные (дополняющие нули).
    """
    матрица = схема.матрица
    база = как or ("по схеме, сохранённой с матрицей" if len(схема.выколоты) or len(схема.укорочены)
                   else "слово передаётся целиком")
    итог = [(база, схема)]
    L0 = схема.длина
    if not блок or схема.порядок is not None:
        return итог
    длины = sorted({блок // м for м in range(1, СЛОВ_В_БЛОКЕ_ДО + 1)
                    if блок % м == 0 and L0 // 2 <= блок // м < L0}, reverse=True)
    if not длины:
        return итог
    занято = np.zeros(матрица.n, dtype=bool)
    занято[схема.выколоты] = True
    занято[схема.укорочены] = True
    данные = информационные(матрица)
    данные = данные[~занято[данные]]
    пусто = np.array([], dtype=np.int64)
    приставка = "" if база == "слово передаётся целиком" else f"{база}; "
    for L in длины:
        d = L0 - L
        for имя, выколоты, укорочены in (
                (f"выколоты первые {d} переданных позиций", схема.переданы[:d], пусто),
                (f"выколоты последние {d} переданных позиций", схема.переданы[L0 - d:], пусто),
                (f"укорочены первые {d} информационных позиций", пусто, данные[:d]),
                (f"укорочены последние {d} информационных позиций", пусто, данные[len(данные) - d:])):
            if len(укорочены) and d > len(данные):
                continue
            try:
                итог.append((приставка + имя, Схема(матрица, np.union1d(схема.выколоты, выколоты),
                                                    np.union1d(схема.укорочены, укорочены))))
            except ValueError:
                continue
    return итог


def найти_по_матрицам(биты: np.ndarray, *, блок: Optional[int] = None, бюджет: float = 30.0,
                      схемы: Optional[Sequence[Tuple[str, Схема]]] = None, встроенные: bool = False):
    """Код LDPC по загруженным матрицам — сам: схема передачи, начало слова, декодирование.

    Каждая матрица пробуется со схемой, сохранённой вместе с ней, и — если
    известна длина блока данных — с частыми схемами выкалывания и укорочения.
    Совпадение — вычислимые проверки при лучшем начале слова почти не нарушены
    (у чужой матрицы и при неверном начале — около половины); из совпавших
    берётся лучшая. ``схемы`` — [(имя, Схема)], по умолчанию — все загруженные;
    ``встроенные`` — ещё и встроенные коды стандартов (со схемой стандарта), при
    известном блоке — только те, чьё слово ложится в блок.
    """
    from .nahodka import Находка  # noqa: PLC0415
    конец = time.monotonic() + бюджет
    if схемы is None:
        схемы = []
        for м in список():
            try:
                схемы.append((str(м["имя"]), схема_сохранённая(str(м["имя"]))))
            except (ValueError, OSError, KeyError):
                continue
    схемы = [(имя, с, "") for имя, с in схемы]
    загруженных = len(схемы)
    if встроенные:
        from . import ldpc_std  # noqa: PLC0415
        загружены = {имя for имя, _, _ in схемы}
        for имя in ldpc_std.подходящие(блок, бит=len(биты)):
            if имя not in загружены:
                схемы.append((имя, None, "по схеме стандарта" if ldpc_std.выколоты_по_стандарту(имя)
                              else "слово передаётся целиком"))
    совпавшие = []
    проверено = 0

    def совпало(проба) -> bool:
        return (проба is not None and проба[1] <= СОВПАДЕНИЕ_ДО and проба[1] <= 0.5 * проба[2]
                and проба[2] >= МЕДИАНА_ОТ)

    for имя, сохранённая, как in схемы:
        if time.monotonic() > конец:
            break
        if сохранённая is None:
            from . import ldpc_std  # noqa: PLC0415
            # Встроенный код: схема стандарта и, у DVB-S2, перемежения бит перед модуляцией.
            перемежения = [("", как)] + [(вид, f"{как}; перемежение бит {вид} ({столбцы})")
                                          for вид, столбцы in ldpc_std.перемежения(имя)]
            if not блок:
                # Без блока — только сами схемы стандарта: проверки для пробы готовы (матрица
                # строится один раз), вся схема — лишь если совпало.
                for вид, вариант in перемежения:
                    L, проверки = ldpc_std.проба(имя, ПРОБА_ПРОВЕРОК, вид)
                    проба = _проба(биты, L, проверки, min(ПРОБА_СЛОВ, max(4, ПРОБА_БИТ // L)))
                    проверено += 1
                    if совпало(проба):
                        начало, нарушено, медиана = проба
                        совпавшие.append((нарушено, медиана, имя, вариант, ldpc_std.схема(имя, вид), начало))
                continue
            базы = [(вариант, ldpc_std.схема(имя, вид)) for вид, вариант in перемежения]
        else:
            базы = [(как, сохранённая)]
        for как_база, база in базы:
            for вариант, схема in варианты_схемы(база, блок, как_база):
                if time.monotonic() > конец:
                    break
                проба = _проба(биты, схема.длина, проверки_для_пробы(схема, ПРОБА_ПРОВЕРОК)[0],
                               min(ПРОБА_СЛОВ, max(4, ПРОБА_БИТ // схема.длина)))
                проверено += 1
                if совпало(проба):
                    начало, нарушено, медиана = проба
                    совпавшие.append((нарушено, медиана, имя, вариант, схема, начало))
    if not совпавшие:
        return None
    совпавшие.sort(key=lambda с: с[0])                      # при равных — в порядке перебора
    лучшее = совпавшие[0]
    почти = [с for с in совпавшие if с[0] <= лучшее[0] + max(РАВНЫЕ_ДО, 0.5 * лучшее[0])]
    выбор = ""
    if len(почти) > 1:
        # Почти равные схемы (соседние варианты выкалывания, та же матрица с иным началом):
        # по проверкам не различить — у верной декодер сходится и правит лишь ошибки линии,
        # у почти верной — ещё и биты, которые она кладёт не туда.
        почти = почти[:РАВНЫХ_ПРОБОВАТЬ]
        пробы = [_пробное(биты, с[4], с[5], ПРОБНЫХ_СЛОВ) for с in почти]
        лучший = min(range(len(почти)), key=lambda i: (-пробы[i][0], пробы[i][1]))
        лучшее = почти[лучший]
        выбор = ("почти равные по проверкам схемы различены пробным декодированием "
                 f"{ПРОБНЫХ_СЛОВ} слов (сошлось, исправлено принятых бит): " + "; ".join(
                     f"«{с[2]}» {с[3]}, начало {с[5]} — {п[0] * 100:.0f} %, {п[1] * 100:.2f} %"
                     + (" ← выбрана" if i == лучший else "") for i, (с, п) in enumerate(zip(почти, пробы))))
    нарушено, медиана, имя, вариант, схема, начало = лучшее
    данные, подробно, сошлось = _снять(биты, схема, начало=начало)
    if выбор:
        подробно.insert(0, выбор)
    м = схема.матрица
    k = len(информационные(м))
    return Находка(
        уровень="код",
        что=f"LDPC ({м.n}, {k}) по матрице «{имя}»" + (f" ({м.откуда})" if м.откуда else "")
            + f"; {вариант}",
        уверенность=float(сошлось),
        мера=f"вычислимые проверки при найденном начале слова нарушены в {нарушено * 100:.1f} % "
             f"(при неверном начале — около {медиана * 100:.0f} %); синдром обнулился у "
             f"{сошлось * 100:.1f} % слов",
        подробно=[f"матрица и схема найдены перебором: загруженных матриц {загруженных}"
                  + (f", встроенных кодов стандартов {len(схемы) - загруженных}" if встроенные else "")
                  + f", схем проверено {проверено}; начало слова — бит {начало}"] + подробно,
        дальше=данные, вид_дальше="биты",
        свойства={"n": м.n, "k": k, "матрица": имя, "начало": начало,
                  "выколото": int(len(схема.выколоты)), "укорочено": int(len(схема.укорочены))})

