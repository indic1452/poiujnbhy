def список() -> list[dict[str, object]]:
    """Загруженные матрицы (JSON) и файлы отдела в папке ldpc; битый файл — с «ошибкой»."""
    if КАТАЛОГ is None or not КАТАЛОГ.exists():
        return []
    итог = []
    for путь in sorted(КАТАЛОГ.glob("*.json")):
        данные = json.loads(путь.read_text(encoding="utf-8"))
        итог.append({"имя": путь.stem, "владелец": данные.get("владелец", 0),
                     **данные.get("сводка", {}), "выколоты": данные.get("выколоты", ""),
                     "укорочены": данные.get("укорочены", "")})
    загружены = {э["имя"] for э in итог}
    for имя, путь in файлы().items():
        if имя in загружены:
            continue
        запись = _из_файла(путь)
        if "ошибка" in запись:
            итог.append({"имя": имя, "файл": путь.name, "ошибка": запись["ошибка"], "владелец": 0})
            continue
        итог.append({"имя": имя, "файл": путь.name, "вид": запись["вид"], "владелец": 0, **запись["сводка"],
                     "выколоты": запись["выколоты"], "укорочены": запись["укорочены"],
                     "перемежение": запись["перемежение"]})
    return итог


