def подготовить_каталог(путь: Path) -> None:
    """Папка матриц отдела: создаётся при старте, с памяткой о форматах."""
    global КАТАЛОГ
    КАТАЛОГ = Path(путь)
    КАТАЛОГ.mkdir(parents=True, exist_ok=True)
    памятка = КАТАЛОГ / "_ПРОЧТИ.txt"
    if not памятка.exists():
        try:
            памятка.write_text(ПАМЯТКА, encoding="utf-8")
        except OSError:
            pass


def _имя_файла(путь: Path) -> str:
    """Имя матрицы из имени файла: недопустимые знаки — «_»."""
    return re.sub(r"[^0-9A-Za-zА-Яа-яЁё_.\-]", "_", путь.stem)[:60].lstrip(".") or "_"


def файлы() -> dict[str, Path]:
    """Файлы матриц отдела в папке ldpc: имя → путь (JSON загруженных сюда не входят)."""
    if КАТАЛОГ is None or not КАТАЛОГ.exists():
        return {}
    итог: dict[str, Path] = {}
    for путь in sorted(КАТАЛОГ.iterdir()):
        if путь.is_file() and путь.suffix.lower() in РАСШИРЕНИЯ and not путь.name.startswith(("_", ".")):
            итог.setdefault(_имя_файла(путь), путь)
    return итог


def _из_файла(путь: Path) -> dict:
    """Разобранный файл (с кэшем по времени изменения): матрица, схема, сводка — или ошибка."""
    ст = путь.stat()
    ключ = (str(путь), ст.st_mtime_ns, ст.st_size)
    if ключ not in _КЭШ_ФАЙЛОВ:
        try:
            if ст.st_size > 64 * 1024 * 1024:
                raise ValueError("файл больше 64 МБ")
            м, поля, вид = разобрать_файл(путь.read_text(encoding="utf-8", errors="replace"), путь.name)
            выколоты, укорочены = поля.get("выколоты", ""), поля.get("укорочены", "")
            if поля.get("данные"):
                # Позиции данных записаны в файле (восстановленная по потоку H): декодер выдаёт их.
                м.данные = позиции(поля["данные"], м.n)
            схема = Схема(м, позиции(выколоты, м.n), позиции(укорочены, м.n))
            перемежение = поля.get("перемежение", "").strip()
            if перемежение == "1367":
                from . import ldpc_flex  # noqa: PLC0415
                схема = Схема(м, схема.выколоты, схема.укорочены, схема.переданы[ldpc_flex.порядок_канала(схема.длина)])
            elif перемежение:
                from . import ldpc_std  # noqa: PLC0415
                вид_п = перемежение.split()
                столбцы = вид_п[1] if len(вид_п) > 1 else "".join(
                    str(j) for j in range(ldpc_std.бит_на_символ(вид_п[0])))
                схема = Схема(м, схема.выколоты, схема.укорочены, схема.переданы[перемежитель(схема.длина, столбцы)])
            запись = {"матрица": м, "схема": схема, "вид": вид, "выколоты": выколоты, "укорочены": укорочены,
                      "перемежение": перемежение, "сводка": м.сводка()}
        except (ValueError, KeyError, IndexError, OSError) as ошибка:
            запись = {"ошибка": str(ошибка)}
        for старый in [к for к in _КЭШ_ФАЙЛОВ if к[0] == str(путь)]:
            del _КЭШ_ФАЙЛОВ[старый]
        _КЭШ_ФАЙЛОВ[ключ] = запись
    return _КЭШ_ФАЙЛОВ[ключ]


def _файл_матрицы(имя: str) -> dict | None:
    """Разобранный файл отдела с этим именем (если нет загруженной JSON с тем же именем)."""
    if КАТАЛОГ is None or (КАТАЛОГ / f"{имя}.json").exists():
        return None
    путь = файлы().get(имя)
    if путь is None:
        return None
    запись = _из_файла(путь)
    if "ошибка" in запись:
        raise ValueError(f"файл матрицы «{путь.name}» не разобран: {запись['ошибка']}")
    return запись


# -- хранение ----------------------------------------------------------------------------

def _путь(имя: str) -> Path:
    if КАТАЛОГ is None:
        raise ValueError("каталог матриц LDPC не задан")
    if not ИМЯ.fullmatch(имя or "") or имя.startswith("."):
        raise ValueError("имя матрицы — буквы, цифры, «_», «-», «.» (до 60 знаков)")
    return КАТАЛОГ / f"{имя}.json"


def сохранить(имя: str, матрица: Матрица, владелец: int = 0, *, выколоты: str = "",
              укорочены: str = "") -> dict[str, object]:
    """Сохранить матрицу — и, если известна, схему передачи: выколотые и укороченные позиции.

    Схема нужна автомату: по ней он сам пробует матрицу на потоке (без неё —
    всё слово целиком и, если известна длина блока, частые схемы).
    """
    путь = _путь(имя)
    Схема(матрица, позиции(выколоты, матрица.n), позиции(укорочены, матрица.n))   # проверка
    путь.parent.mkdir(parents=True, exist_ok=True)
    сводка = матрица.сводка()
    путь.write_text(json.dumps({"n": матрица.n, "откуда": матрица.откуда, "владелец": владелец,
                                "строки": [с.tolist() for с in матрица.строки],
                                "выколоты": выколоты.strip(), "укорочены": укорочены.strip(),
                                "сводка": сводка}, ensure_ascii=False), encoding="utf-8")
    return {"имя": имя, **сводка, "выколоты": выколоты.strip(), "укорочены": укорочены.strip()}


def _данные_матрицы(имя: str) -> dict:
    путь = _путь(имя)
    if not путь.exists():
        raise ValueError(f"матрицы «{имя}» нет — загрузите её в растре («Матрицы LDPC»)")
    return json.loads(путь.read_text(encoding="utf-8"))


