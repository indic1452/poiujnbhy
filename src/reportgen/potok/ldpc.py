# -- информационные позиции ----------------------------------------------------------------

def _треугольная_справа(матрица: Матрица) -> bool:
    """Последние m столбцов — нижнетреугольные с единичной диагональю (накопитель)."""
    k = матрица.n - матрица.m
    столбцы, _ = матрица.подряд()
    проверочные = столбцы >= k
    наибольший = np.full(матрица.m, -1, dtype=np.int64)
    np.maximum.at(наибольший, матрица._номера_строк()[проверочные], столбцы[проверочные] - k)
    return bool(np.array_equal(наибольший, np.arange(матрица.m)))


def информационные_сводка(матрица: Матрица) -> tuple[int, str]:
    if матрица.данные is not None:
        k = len(матрица.данные)
        if np.array_equal(матрица.данные, np.arange(k)):
            return k, f"первые {k} позиций (по стандарту)"
        return k, f"{k} позиций данных, заданных с матрицей ({позиции_строкой(матрица.данные)[:80]})"
    if матрица.n - матрица.m > 0 and _треугольная_справа(матрица):
        return матрица.n - матрица.m, "первые k позиций (проверочная часть — накопитель)"
    if матрица.n > ПЛОТНО_ДО:
        return матрица.n - матрица.m, "первые n − m позиций (ранг не проверялся: код длинный)"
    r = gf2.ранг(матрица.плотная())
    return матрица.n - r, "по опорным столбцам (исключение Гаусса)"


def информационные(матрица: Матрица) -> np.ndarray:
    """Позиции данных: систематическая часть кода."""
    if матрица.данные is not None:
        return матрица.данные
    if (матрица.n - матрица.m > 0 and _треугольная_справа(матрица)) or матрица.n > ПЛОТНО_ДО:
        return np.arange(матрица.n - матрица.m)
    H = матрица.плотная()
    # Проверочные — опорные столбцы H, приведённой справа налево: тогда данные — в начале.
    _, опорные = gf2.привести(gf2.упаковать(H[:, ::-1]), матрица.n)
    проверочные = {матрица.n - 1 - j for j in опорные}
    return np.array([j for j in range(матрица.n) if j not in проверочные], dtype=np.int64)


# -- перфорация и декодирование ---------------------------------------------------------------

def позиции_строкой(позиции_: np.ndarray) -> str:
    """Номера позиций → «0-191, 1000-1023» (обратное к ``позиции``)."""
    п = np.unique(np.asarray(позиции_, dtype=np.int64))
    if not len(п):
        return ""
    разрывы = np.flatnonzero(np.diff(п) != 1)
    начала = np.concatenate([[п[0]], п[разрывы + 1]])
    концы = np.concatenate([п[разрывы], [п[-1]]])
    return ", ".join(str(a) if a == b else f"{a}-{b}" for a, b in zip(начала.tolist(), концы.tolist(), strict=True))


def позиции(указание: str, n: int) -> np.ndarray:
    """«0-191, 1000-1023» → номера позиций слова."""
    итог = set()
    for a, b, одна in re.findall(r"(\d+)\s*(?:[-–…]|\.\.)\s*(\d+)|(\d+)", указание or ""):
        a, b = (int(одна), int(одна)) if одна else (int(a), int(b))
        if a > b or b >= n:
            raise ValueError(f"позиции {a}–{b} вне слова 0…{n - 1}")
        итог.update(range(a, b + 1))
    return np.array(sorted(итог), dtype=np.int64)


def мин_сумма(llr: np.ndarray, связи: np.ndarray, n: int, итераций: int = 50
              ) -> tuple[np.ndarray, np.ndarray]:
    """Декодер «минимум — сумма» (с поправкой 0,75) по мягким входам; LLR > 0 — ноль.

    Стёртые позиции (выколотые) — LLR 0, известные нули (укороченные) —
    большое положительное. Возвращает слова и признак нулевого синдрома.

    Сообщения — по рёбрам графа подряд (без дополнения строк до наибольшего веса): у проверки —
    два наименьших модуля и чётность знаков отрезком (``reduceat``), у позиции — сумма отрезком по
    рёбрам, упорядоченным по столбцам. Проверка веса 1 — позиция обязана быть нулём (сообщение 10⁹).
    """
    M = len(llr)
    есть = связи < n
    степени = есть.sum(axis=1)
    столбец = связи[есть].astype(np.int64)                      # рёбра по проверкам подряд
    непустые = степени > 0
    if not len(столбец):
        слова = (llr < 0).astype(np.uint8)
        return слова, np.ones(M, dtype=bool)
    степени_н = степени[непустые]
    начала = np.concatenate([[0], np.cumsum(степени_н)[:-1]]).astype(np.int64)
    по_столбцам = np.argsort(столбец, kind="stable")
    упорядочено = столбец[по_столбцам]
    свои = np.flatnonzero(np.diff(np.concatenate([[-1], упорядочено])))
    занятые = упорядочено[свои]
    llr = np.asarray(llr, dtype=np.float32)
    к_проверке = np.zeros((M, len(столбец)), dtype=np.float32)
    слова = (llr < 0).astype(np.uint8)
    for шаг in range(итераций):
        полная = llr.copy()
        if шаг:
            полная[:, занятые] += np.add.reduceat(к_проверке[:, по_столбцам], свои, axis=1)
        слова = (полная < 0).astype(np.uint8)
        if not np.bitwise_xor.reduceat(слова[:, столбец], начала, axis=1).any():
            break
        от_позиции = полная[:, столбец] - к_проверке
        минус = (от_позиции < 0).astype(np.uint8)
        модуль = np.abs(от_позиции)
        знак = np.repeat(np.bitwise_xor.reduceat(минус, начала, axis=1), степени_н, axis=1) ^ минус
        первый = np.minimum.reduceat(модуль, начала, axis=1)
        первый_р = np.repeat(первый, степени_н, axis=1)
        наименьшие = модуль == первый_р
        второй = np.minimum.reduceat(np.where(наименьшие, np.float32(np.inf), модуль), начала, axis=1)
        второй = np.where(np.add.reduceat(наименьшие.astype(np.int32), начала, axis=1) >= 2, первый, второй)
        второй = np.where(np.isinf(второй), np.float32(1e9), второй).astype(np.float32)
        величина = np.where(наименьшие, np.repeat(второй, степени_н, axis=1), первый_р)
        к_проверке = (np.float32(0.75) * величина * (1.0 - 2.0 * знак)).astype(np.float32)
    синдром = np.bitwise_xor.reduceat(слова[:, столбец], начала, axis=1)
    return слова, ~синдром.any(axis=1)


def мин_сумма_прежний(llr: np.ndarray, связи: np.ndarray, n: int, итераций: int = 50
                      ) -> tuple[np.ndarray, np.ndarray]:
    """Прежняя запись того же декодера (по дополненным строкам) — эталон для тестов."""
    M = len(llr)
    m, d = связи.shape
    есть = связи < n
    к_проверке = np.zeros((M, m, d), dtype=np.float32)
    слова = (llr < 0).astype(np.uint8)
    дополненные = np.concatenate([слова, np.zeros((M, 1), np.uint8)], axis=1)
    for _ in range(итераций):
        сумма = np.zeros((M, n + 1), dtype=np.float32)
        np.add.at(сумма, (slice(None), связи), к_проверке * есть)
        полная = llr + сумма[:, :n]
        слова = (полная < 0).astype(np.uint8)
        дополненные[:, :n] = слова
        синдром = np.bitwise_xor.reduce(np.where(есть, дополненные[:, связи], 0), axis=2)
        if not синдром.any():
            break
        расширенная = np.concatenate([полная, np.zeros((M, 1), np.float32)], axis=1)
        от_позиции = расширенная[:, связи] - к_проверке
        от_позиции = np.where(есть, от_позиции, np.float32(1e9))
        знак = np.where(от_позиции < 0, -1.0, 1.0).astype(np.float32)
        модуль = np.abs(от_позиции)
        общий = np.prod(знак, axis=2, keepdims=True)
        порядок = np.sort(модуль, axis=2)
        первый, второй = порядок[:, :, :1], порядок[:, :, 1:2]
        наименьший = np.where(модуль == первый, второй, первый)
        к_проверке = (0.75 * общий * знак * наименьший * есть).astype(np.float32)
    дополненные[:, :n] = слова
    синдром = np.bitwise_xor.reduce(np.where(есть, дополненные[:, связи], 0), axis=2)
    return слова, ~синдром.any(axis=1)


@dataclass
class Схема:
    """Как слово кода лежит в потоке: что передано, что выколото, что укорочено.

    ``порядок`` — в каком порядке позиции слова идут в потоке, если не подряд
    (перемежение бит перед модуляцией): перестановка переданных позиций.
    """
    матрица: Матрица
    выколоты: np.ndarray
    укорочены: np.ndarray
    порядок: np.ndarray | None = None

    def __post_init__(self):
        общие = np.intersect1d(self.выколоты, self.укорочены)
        if len(общие):
            raise ValueError(f"позиция {общие[0]} и выколота, и укорочена")
        лишние = np.zeros(self.матрица.n, dtype=bool)
        лишние[self.выколоты] = True
        лишние[self.укорочены] = True
        self.переданы = np.flatnonzero(~лишние)
        if self.порядок is not None:
            порядок = np.asarray(self.порядок, dtype=np.int64)
            if not np.array_equal(np.sort(порядок), self.переданы):
                raise ValueError("порядок в потоке — не перестановка переданных позиций слова")
            self.переданы = порядок
        if len(self.переданы) < self.матрица.m // 4:
            raise ValueError("передано слишком мало позиций слова")

    @property
    def длина(self) -> int:
        return len(self.переданы)

    def связи_декодера(self) -> np.ndarray:
        """Связи для декодера без проверок, которые ничего не дают: в проверке есть выколотая позиция, которой
        нет больше ни в одной проверке (у 5G NR при обрезке хвоста — почти половина строк). Её значение
        стёрто, и сообщения такой проверки к остальным позициям — нули; выбрасываются, пока такие есть
        (позиции данных не выбрасываются: их значение нужно на выходе)."""
        if getattr(self, "_связи_декодера", None) is not None:
            return self._связи_декодера
        м = self.матрица
        связи = м.связи()
        if len(self.выколоты):
            выколото = np.zeros(м.n + 1, dtype=bool)
            выколото[self.выколоты] = True
            выколото[информационные(м)] = False
            выколото[м.n] = False
            живые = np.ones(м.m, dtype=bool)
            while True:
                степень = np.bincount(связи[живые].reshape(-1), minlength=м.n + 1)
                висячие = выколото & (степень == 1)
                лишние = живые & висячие[связи].any(axis=1)
                if not лишние.any():
                    break
                живые &= ~лишние
            if not живые.all():
                связи = связи[живые]
                d = int((связи < м.n).sum(axis=1).max()) if len(связи) else 1
                связи = np.sort(связи, axis=1)[:, :max(1, d)]
        self._связи_декодера = связи
        return связи

    def llr(self, принятые: np.ndarray) -> np.ndarray:
        """Слова по длине передачи → LLR полного слова."""
        M = len(принятые)
        L = np.zeros((M, self.матрица.n), dtype=np.float32)
        L[:, self.переданы] = 1.0 - 2.0 * принятые.astype(np.float32)
        L[:, self.укорочены] = 50.0
        return L


def перемежитель(n: int, столбцы: str) -> np.ndarray:
    """Перемежение бит «запись по столбцам — чтение по строкам» (DVB-S2, 5.3.3): какая позиция
    слова идёт в потоке i-й.

    Слово пишется в c = len(столбцы) столбцов по n / c бит (столбец j — позиции
    j·n/c … (j + 1)·n/c − 1) и читается по строкам: в строке r сперва бит столбца
    ``столбцы[0]``, затем ``столбцы[1]`` и т. д. — старший бит символа первым (как
    в GNU Radio gr-dtv, dvbs2_interleaver_bb, и xdsopl/LDPC, itls_handler).
    """
    c = len(столбцы)
    if c < 2 or n % c or sorted(столбцы) != [str(j) for j in range(c)]:
        raise ValueError(f"перемежение «{столбцы}»: нужны все столбцы 0…{c - 1} и n, кратное {c}")
    строк = n // c
    откуда = np.array([int(j) * строк for j in столбцы], dtype=np.int64)
    return (np.arange(строк)[:, None] + откуда[None, :]).reshape(-1)


def вычислимые(схема: Схема, сколько: int | None = None) -> list[np.ndarray]:
    """Проверки, которые считаются по принятым битам: без выколотых позиций.

    Возвращает их в номерах позиций ПЕРЕДАННОГО слова (укороченные — нули, их
    из проверки можно просто выбросить). ``сколько`` — не больше стольких,
    равномерно по всем вычислимым (для пробы матрицы на потоке).
    """
    м = схема.матрица
    столбцы, границы = м.подряд()
    номер = м._номера_строк()
    выколото = np.zeros(м.n, dtype=bool)
    выколото[схема.выколоты] = True
    укорочено = np.zeros(м.n, dtype=bool)
    укорочено[схема.укорочены] = True
    куда = np.full(м.n, -1, dtype=np.int64)
    куда[схема.переданы] = np.arange(схема.длина)
    с_выколотыми = np.bincount(номер[выколото[столбцы]], minlength=м.m) > 0
    осталось = np.bincount(номер[~укорочено[столбцы]], minlength=м.m)
    годные = np.flatnonzero(~с_выколотыми & (осталось > 0))
    if сколько is not None:
        годные = годные[::max(1, len(годные) // max(1, сколько))][:сколько]
    итог = []
    for i in годные:
        с = столбцы[границы[i]:границы[i + 1]]
        итог.append(куда[с[~укорочено[с]]])
    return итог


#: Сумма — не больше стольких строк H (строка и опорные строки её выколотых позиций).
СЛОЖЕННЫХ_СТРОК_ДО = 4


def сложенные(схема: Схема, сколько: int) -> list[np.ndarray]:
    """Проверки, сложенные из нескольких строк H так, что выколотые позиции сократились: их
    можно посчитать по принятым битам.

    Нужны, когда выколотые позиции входят почти во все строки: у 5G NR (граф 1) первые 2Z
    позиций — во всех 46Z строках, у AR4JA (CCSDS) выколотые блок-столбцы — во всех
    строках; одиночных вычислимых проверок тогда нет. Сперва — пары строк с одними и теми
    же выколотыми позициями (сумма разрежена почти как сами строки); не хватает — строка
    вместе с опорными: строками, где выколота ровно одна позиция, по одной на каждую её
    выколотую (всего не больше СЛОЖЕННЫХ_СТРОК_ДО строк). Возвращает не больше
    ``сколько`` — равномерно, в номерах позиций переданного слова.
    """
    м = схема.матрица
    столбцы, границы = м.подряд()
    выколото = np.zeros(м.n, dtype=bool)
    выколото[схема.выколоты] = True
    if not выколото.any() or сколько < 1:
        return []
    укорочено = np.zeros(м.n, dtype=bool)
    укорочено[схема.укорочены] = True
    куда = np.full(м.n, -1, dtype=np.int64)
    куда[схема.переданы] = np.arange(схема.длина)
    выколотые: dict[int, tuple[int, ...]] = {}
    for i in np.unique(м._номера_строк()[выколото[столбцы]]).tolist():
        с = столбцы[границы[i]:границы[i + 1]]
        выколотые[i] = tuple(с[выколото[с]].tolist())
    последняя: dict[tuple[int, ...], int] = {}
    пары: list[tuple[int, ...]] = []
    for i, ключ in выколотые.items():
        if ключ in последняя:
            пары.append((последняя[ключ], i))
        последняя[ключ] = i
    выбор = пары[::max(1, len(пары) // сколько)][:сколько]
    if len(выбор) < сколько:
        опорная: dict[int, int] = {}
        for i, ключ in выколотые.items():
            if len(ключ) == 1:
                опорная.setdefault(ключ[0], i)
        с_опорными = [(i,) + tuple(опорная[c] for c in ключ) for i, ключ in выколотые.items()
                      if 2 <= len(ключ) < СЛОЖЕННЫХ_СТРОК_ДО and all(c in опорная for c in ключ)]
        осталось = сколько - len(выбор)
        выбор += с_опорными[::max(1, len(с_опорными) // осталось)][:осталось]
    итог = []
    for набор in выбор:
        все, раз = np.unique(np.concatenate([столбцы[границы[i]:границы[i + 1]] for i in набор]),
                             return_counts=True)
        сумма = все[раз % 2 == 1]
        сумма = сумма[~укорочено[сумма]]
        if len(сумма) and not выколото[сумма].any():
            итог.append(куда[сумма])
    return итог


def проверки_для_пробы(схема: Схема, сколько: int) -> tuple[list[np.ndarray], int]:
    """Вычислимые проверки (равномерно, не больше ``сколько``), а если их меньше — и сложенные из
    нескольких строк: (проверки, из них сложенных)."""
    одиночные = вычислимые(схема, сколько)
    сложено = сложенные(схема, сколько - len(одиночные)) if len(одиночные) < сколько else []
    return одиночные + сложено, len(сложено)


def найти_начало(биты: np.ndarray, схема: Схема, бюджет: float = 60.0
                 ) -> tuple[int, float, str]:
    """Начало слова в потоке: где вычислимые проверки нарушены реже всего.

    Одиночных вычислимых проверок мало (выколотые позиции входят почти во все
    строки) — добавляются суммы строк, в которых выколотые сокращаются; нет и их —
    пробным декодированием: у верного начала декодер сходится.
    """
    L = схема.длина
    слов = min(СЛОВ_ДЛЯ_НАЧАЛА, len(биты) // L - 1)
    if слов < 2:
        raise ValueError(f"в потоке меньше двух слов по {L} бит")
    выборка = биты[:(слов + 1) * L].astype(np.uint8)
    проверки, сложено = проверки_для_пробы(схема, 400)
    проба = _проба(биты, L, проверки, СЛОВ_ДЛЯ_НАЧАЛА)
    if проба is not None:
        начало, нарушено, медиана = проба
        return начало, нарушено, (
            f"по {len(проверки)} вычислимым проверкам"
            + (f" (из них {сложено} — суммы строк, в которых выколотые позиции сокращаются)"
               if сложено else "")
            + f": нарушено {нарушено * 100:.1f} % (при неверном начале — около {медиана * 100:.0f} %)")
    конец = time.monotonic() + бюджет
    связи = схема.связи_декодера()
    лучшее = (-1.0, 0)
    for начало in range(L):
        if time.monotonic() > конец:
            break
        слова = выборка[начало:начало + 2 * L].reshape(2, L)
        _, сошлось = мин_сумма(схема.llr(слова), связи, схема.матрица.n, 15)
        доля = float(сошлось.mean())
        if доля > лучшее[0]:
            лучшее = (доля, начало)
            if доля == 1.0:
                break
    if лучшее[0] <= 0:
        raise ValueError("начало слова не найдено: ни при одном сдвиге декодер не сошёлся "
                         "(задайте «начало N» или проверьте матрицу и перфорацию)")
    return лучшее[1], 1 - лучшее[0], "пробным декодированием (вычислимых проверок нет)"


def _проба(биты: np.ndarray, L: int, проверки: Sequence[np.ndarray], слов_до: int
           ) -> tuple[int, float, float] | None:
    """Начало слова по вычислимым проверкам: (начало, доля нарушенных, медиана по всем началам).

    У верной матрицы при верном начале проверки нарушены только ошибками
    линии, у чужой (и при неверном начале) — около половины. ``L`` — длина слова
    в потоке. None — проверок меньше трёх или слов меньше двух.
    """
    слов = min(слов_до, len(биты) // L - 1)
    if слов < 2 or len(проверки) < 3:
        return None
    выборка = биты[:(слов + 1) * L].astype(np.uint8)
    нарушено = np.zeros(слов * L, dtype=np.float64)
    for с in проверки:
        чётность = np.zeros(слов * L, dtype=np.uint8)
        for p in с:
            чётность ^= выборка[p:p + слов * L]
        нарушено += чётность
    по_началу = нарушено.reshape(слов, L).mean(axis=0) / len(проверки)
    начало = int(np.argmin(по_началу))
    return начало, float(по_началу[начало]), float(np.median(по_началу))


#: Что выводит снятие LDPC: информационные биты, исправленные слова (переданные позиции, в порядке потока)
#: или ошибки линии (принятое ⊕ исправленное — для оценки BER).
ВЫВОДЫ = ("данные", "слова", "ошибки")


def декодировать(принятые: np.ndarray, схема: Схема, *, итераций: int = 50, пачка: int = 32,
                 вывод: str = "данные", llr=None) -> tuple[np.ndarray, int, int]:
    """Декодер по пачкам слов (слов × длина в потоке): (выход слов × …, сошлось, исправлено бит).

    ``вывод`` — «данные» (информационные позиции), «слова» (исправленные переданные позиции) или
    «ошибки» (принятое ⊕ исправленное). ``llr(кусок, от)`` — свои мягкие входы пачки (повторы NR).
    Ход — в шаги стола (``potokovo.ход_слоя``), там же отмена."""
    from .potokovo import ход_слоя  # noqa: PLC0415
    if вывод not in ВЫВОДЫ:
        raise ValueError(f"вывод — {', '.join(ВЫВОДЫ)}")
    слов = len(принятые)
    связи = схема.связи_декодера()
    данные = информационные(схема.матрица)
    итог, сошлось, исправлено = [], 0, 0
    for от in range(0, слов, пачка):
        кусок = принятые[от:от + пачка]
        слова, ок = мин_сумма(схема.llr(кусок) if llr is None else llr(кусок, от), связи, схема.матрица.n, итераций)
        сошлось += int(ок.sum())
        переданные = слова[:, схема.переданы]
        исправлено += int((переданные != кусок).sum())
        итог.append(слова[:, данные] if вывод == "данные" else переданные if вывод == "слова" else переданные ^ кусок)
        ход_слоя((от + len(кусок)) / слов, f"LDPC: слов {от + len(кусок)} из {слов}, сошлось {сошлось}")
    return np.concatenate(итог, axis=0), сошлось, исправлено


def вывод_словами(вывод: str, схема: Схема) -> str:
    """Что на выходе снятия — строкой отчёта."""
    if вывод == "слова":
        return f"на выходе — исправленные слова: {схема.длина} переданных позиций в порядке потока"
    if вывод == "ошибки":
        return "на выходе — ошибки линии: принятое ⊕ исправленное (единица — исправленный бит)"
    return f"на выходе — информационные биты: {информационные_сводка(схема.матрица)[1]}"


def снять(биты: np.ndarray, схема: Схема, *, начало: int | None = None,
          итераций: int = 50, слов_до: int | None = None, пачка: int = 32, вывод: str = "данные"
          ) -> tuple[np.ndarray, list[str]]:
    """Декодировать слова (все, если ``слов_до`` не задан) и вернуть их информационные биты подряд."""
    данные, подробно, _ = _снять(биты, схема, начало=начало, итераций=итераций, слов_до=слов_до,
                                 пачка=пачка, вывод=вывод)
    return данные, подробно


def _снять(биты: np.ndarray, схема: Схема, *, начало: int | None = None,
           итераций: int = 50, слов_до: int | None = None, пачка: int = 32, вывод: str = "данные"
           ) -> tuple[np.ndarray, list[str], float]:
    """Снятие: информационные биты, строки отчёта и доля слов с обнулившимся синдромом."""
    подробно = []
    if начало is None:
        начало, _, как = найти_начало(биты, схема)
        подробно.append(f"начало слова — бит {начало}, найдено {как}")
    L = схема.длина
    слов = (len(биты) - начало) // L
    if слов_до is not None:
        слов = min(слов_до, слов)
    if слов < 1:
        raise ValueError("в потоке нет ни одного целого слова")
    принятые = биты[начало:начало + слов * L].reshape(слов, L)
    выход, сошлось, исправлено = декодировать(принятые, схема, итераций=итераций, пачка=пачка, вывод=вывод)
    данные = информационные(схема.матрица)
    подробно += [
        f"код ({схема.матрица.n}, {len(данные)}), {схема.матрица.откуда}; в потоке слово "
        f"{L} бит: выколото {len(схема.выколоты)}, укорочено {len(схема.укорочены)}",
        f"слов {слов}: синдром обнулился у {сошлось} ({сошлось / слов * 100:.1f} %); "
        f"исправлено бит {исправлено} ({исправлено / (слов * L) * 100:.3f} % принятых)",
        вывод_словами(вывод, схема),
    ]
    if сошлось < слов * 0.5:
        подробно.append("меньше половины слов сошлось — проверьте матрицу, перфорацию и начало")
    return выход.reshape(-1), подробно, сошлось / слов


def из_указания(слова: str) -> tuple[Схема, int | None, int]:
    """«ldpc ИМЯ [выколоты 0-191] [укорочены 0-99] [перемежение 8PSK [210] | перемежение 4+12APSK [3021]
    | перемежение 1367]
    [начало N] [итераций K]». У встроенного кода без «выколоты»/«укорочены» — схема стандарта."""
    части = слова.split()
    if len(части) < 2:
        raise ValueError("ldpc: нужно имя загруженной матрицы — «ldpc ИМЯ выколоты 0-191»")
    матрица = прочитать(части[1])

    def после(слово: str) -> str:
        м = re.search(слово + r"\w*\s+([\d\s,\-–…\.]+?)(?=\s+[А-Яа-яЁёA-Za-z]|$)", слова)
        return м.group(1) if м else ""

    выколоты = позиции(после("выколот"), матрица.n)
    укорочены = позиции(после("укороч"), матрица.n)
    if _встроенная(части[1]):
        стандарт = схема_сохранённая(части[1])            # по стандарту (у NR — первые 2Z)
        if "выколот" not in слова:
            выколоты = стандарт.выколоты
        if "укороч" not in слова:
            укорочены = стандарт.укорочены
    начало_ = re.search(r"начал\w*\s+(\d+)", слова)
    итераций_ = re.search(r"итерац\w*\s+(\d+)", слова)
    начало = int(начало_.group(1)) if начало_ else None
    итераций = min(200, int(итераций_.group(1))) if итераций_ else 50
    схема = Схема(матрица, выколоты, укорочены)
    if re.search(r"перемеж\w*\s+1367\b", слова):
        from . import ldpc_flex  # noqa: PLC0415
        return (Схема(матрица, выколоты, укорочены, схема.переданы[ldpc_flex.порядок_канала(схема.длина)]),
                начало, итераций)
    перемежение = re.search(r"перемеж\w*\s+(\d+(?:\+\d+)*(?:rb)?a?psk)(?:\s+(\d{3,8}))?", слова.lower())
    if перемежение:
        from . import ldpc_std  # noqa: PLC0415
        вид = перемежение.group(1).upper()
        столбцы = перемежение.group(2) or ldpc_std.столбцы_перемежения(части[1], вид)
        return (Схема(матрица, выколоты, укорочены, схема.переданы[перемежитель(схема.длина, столбцы)]),
                начало, итераций)
    return схема, начало, итераций


# -- кадры модема: синхрослово сосредоточенное или распределённое ------------------------------

@dataclass
class Кадр:
    """Как слова кода лежат в кадрах модема: синхрослово, длина кадра, что выводить."""
    слово: np.ndarray
    длина: int
    распределённое: bool = False
    с_синхрословом: bool = False

    def __post_init__(self):
        s = len(self.слово)
        if s < 4 or self.длина <= s:
            raise ValueError("кадр: синхрослово не короче 4 бит, кадр длиннее синхрослова")
        if self.распределённое and self.длина % s:
            raise ValueError(f"распределённое синхрослово: длина кадра {self.длина} не делится на {s} бит слова")

    def места(self) -> np.ndarray:
        """Места бит синхрослова в кадре: подряд в начале или по одному через каждые длина/s бит."""
        s = len(self.слово)
        return np.arange(s) * (self.длина // s) if self.распределённое else np.arange(s)


def _начало_кадров(биты: np.ndarray, кадр: Кадр, кадров_до: int = 64) -> tuple[int, bool, float]:
    """Начало первого кадра: при каком сдвиге синхрослово на своих местах в кадрах нарушено реже
    всего (прямое или инверсное) — (сдвиг, инверсия, доля несовпавших бит)."""
    N = кадр.длина
    кадров = min(кадров_до, len(биты) // N - 1)
    if кадров < 2:
        raise ValueError(f"в потоке меньше трёх кадров по {N} бит")
    места = кадр.места()
    выборка = биты[:(кадров + 1) * N].astype(np.int16)
    несовпало = np.zeros(N)
    for j, м in enumerate(места.tolist()):
        # Для каждого сдвига c: бит c + м в каждом кадре против бита слова j.
        окно = выборка[м:м + кадров * N].reshape(кадров, N)
        несовпало += (окно != int(кадр.слово[j])).sum(axis=0)
    несовпало /= кадров * len(места)
    прямое, инверсное = int(np.argmin(несовпало)), int(np.argmax(несовпало))
    if 1 - несовпало[инверсное] < несовпало[прямое]:
        return инверсное, True, float(1 - несовпало[инверсное])
    return прямое, False, float(несовпало[прямое])


def снять_в_кадрах(биты: np.ndarray, схема: Схема, кадр: Кадр, *, итераций: int = 50,
                   слов_до: int | None = None, вывод: str = "данные") -> tuple[np.ndarray, list[str]]:
    """Слова кода в кадрах модема: синхрослово (сосредоточенное в начале кадра или распределённое по
    одному биту через длина/s бит) убирается, в остатке кадра — целое число слов кода подряд (хвост
    короче слова — заполнение). На выходе — данные каждого слова; «с синхрословом» — перед данными
    каждого кадра его синхрослово."""
    N, L = кадр.длина, схема.длина
    начало, инверсия, доля = _начало_кадров(биты, кадр)
    if доля > 0.2:
        raise ValueError(f"синхрослово не найдено: лучшее совпадение — {(1 - доля) * 100:.0f} % бит")
    ряд = биты[начало:]
    if инверсия:
        ряд = (1 - ряд).astype(np.uint8)
    кадров = len(ряд) // N
    кадры = ряд[:кадров * N].reshape(кадров, N)
    лишние = np.zeros(N, dtype=bool)
    лишние[кадр.места()] = True
    нагрузка = кадры[:, ~лишние]
    слов_в_кадре = нагрузка.shape[1] // L
    if not слов_в_кадре:
        raise ValueError(f"в кадре {N} бит без синхрослова {нагрузка.shape[1]} бит — меньше слова кода ({L})")
    if слов_до is not None:
        кадров = min(кадров, max(1, слов_до // слов_в_кадре))
    слова = нагрузка[:кадров, :слов_в_кадре * L].reshape(-1)
    данные, подробно, _ = _снять(слова, схема, начало=0, итераций=итераций, слов_до=кадров * слов_в_кадре,
                                 вывод=вывод)
    k = len(данные) // (кадров * слов_в_кадре)
    по_кадрам = данные.reshape(кадров, слов_в_кадре * k)
    if кадр.с_синхрословом:
        синхро = кадры[:кадров, лишние]
        по_кадрам = np.concatenate([синхро, по_кадрам], axis=1)
    хвост = нагрузка.shape[1] - слов_в_кадре * L
    return по_кадрам.reshape(-1).astype(np.uint8), [
        f"кадры {N} бит с бита {начало}{' (поток инверсный)' if инверсия else ''}: синхрослово "
        f"{''.join(map(str, кадр.слово.tolist()))} ({'распределённое, бит через ' + str(N // len(кадр.слово)) if кадр.распределённое else 'сосредоточенное'}) "
        f"— несовпало {доля * 100:.1f} % его бит; в кадре {слов_в_кадре} слов по {L} бит"
        + (f", хвост {хвост} бит (заполнение) отброшен" if хвост else ""),
        *подробно, "на выходе " + ("синхрослово и " if кадр.с_синхрословом else "") + "данные слов по кадрам"]


def кадр_из_указания(слова: str) -> Кадр | None:
    """«… синхро СЛОВО длина N [распределённое] [с синхрословом]» → Кадр; нет «синхро» — None."""
    from . import sinhro  # noqa: PLC0415
    м = re.search(r"синхро\s+(\S+)\s+длина\s+(\d+)", слова)
    if not м:
        return None
    return Кадр(sinhro.слово(м.group(1)), int(м.group(2)), распределённое="распредел" in слова,
                с_синхрословом="с синхрослов" in слова)


# -- автомат: загруженные матрицы пробуются сами ---------------------------------------------

#: Проверок на пробу совпадения матрицы с потоком и слов в пробе.
ПРОБА_ПРОВЕРОК = 64
ПРОБА_СЛОВ = 12
#: Длинному слову хватает и меньшего числа слов: не больше стольких бит на пробу (но не меньше
#: четырёх слов — 256 проверок на каждое начало: у чужой матрицы нарушено не меньше трети).
ПРОБА_БИТ = 1 << 18
#: Совпадение: при лучшем начале вычислимые проверки нарушены не чаще этой доли и не
#: чаще половины медианы по всем началам (у чужой матрицы — около половины при любом).
СОВПАДЕНИЕ_ДО = 0.2
#: Слово короче блока данных в целое число раз — до стольких слов в блоке.
СЛОВ_В_БЛОКЕ_ДО = 64
#: При неверном начале проверки нарушены хотя бы в такой доле (медиана по началам): у
#: заполнения (нули, повторы) проверки выполнены при любом начале — это не код.
МЕДИАНА_ОТ = 0.25
#: Схемы почти равны по проверкам, если нарушенных у них больше, чем у лучшей, не более чем
#: на столько (доля) или вполовину; тогда решает пробное декодирование стольких слов.
РАВНЫЕ_ДО = 0.02
РАВНЫХ_ПРОБОВАТЬ = 6
ПРОБНЫХ_СЛОВ = 8
#: Проверок на каждое начало в пробе (проверок × слов): вычислимых проверок бывает мало (у сильно
#: выколотой схемы — три), тогда берётся больше слов, пока хватает ПРОБА_БИТ.
ПРОБА_ОТСЧЁТОВ = ПРОБА_ПРОВЕРОК * ПРОБА_СЛОВ
#: Совпадение засчитывается, только если у случайных бит столь малая доля нарушенных при лучшем
#: из всех начал получилась бы с вероятностью не больше этой (точный хвост биномиального
#: распределения, умноженный на число начал и проверенных схем; слова — без повторов): иначе минимум
#: по тысяче начал при трёх проверках на слово случайно опускается ниже СОВПАДЕНИЕ_ДО, а у заполнения
#: (кадры повторяются) — и при шести проверках на восьми разных словах.
СЛУЧАЙНО_ДО = 1e-6


def слов_для_пробы(L: int, проверок: int) -> int:
    """Слов в пробе: ПРОБА_ОТСЧЁТОВ проверок на начало, но не больше ПРОБА_БИТ бит (и не меньше 4 слов)."""
    нужно = max(ПРОБА_СЛОВ, -(-ПРОБА_ОТСЧЁТОВ // max(1, проверок)))
    return min(нужно, max(4, ПРОБА_БИТ // L))


def случайно(нарушено: float, отсчётов: int, начал: int) -> float:
    """Вероятность, что у случайных бит лучшее из ``начал`` начал даст не больше ``нарушено``
    нарушенных из ``отсчётов`` проверок (каждая нарушена с вероятностью ½; оценка сверху)."""
    k = int(round(нарушено * отсчётов))
    логи = [math.lgamma(отсчётов + 1) - math.lgamma(i + 1) - math.lgamma(отсчётов - i + 1)
            for i in range(k + 1)]
    верх = max(логи)
    лог_хвост = верх + math.log(sum(math.exp(л - верх) for л in логи)) - отсчётов * math.log(2)
    return min(1.0, начал * math.exp(лог_хвост))


def различные(биты: np.ndarray, L: int, проверки: Sequence[np.ndarray], начало: int, слов: int
              ) -> tuple[int, float, int]:
    """Слова пробы при найденном начале — без повторов: (различных слов, доля нарушенных, отсчётов).

    Повтор слова (заполнение, повтор цикла) ничего не добавляет к доказательству: проверка, случайно
    выполненная в одном слове, выполнена и во всех его копиях. Значимость считается по различным словам."""
    слов = min(слов, (len(биты) - начало) // L)
    if слов < 1 or not len(проверки):
        return 0, 0.5, 0
    слова = np.unique(биты[начало:начало + слов * L].reshape(слов, L), axis=0)
    нарушено = sum(int(np.bitwise_xor.reduce(слова[:, с], axis=1).sum()) for с in проверки)
    отсчётов = len(слова) * len(проверки)
    return len(слова), нарушено / отсчётов, отсчётов


def _пробное(биты: np.ndarray, схема: Схема, начало: int, слов: int) -> tuple[float, float]:
    """Пробное декодирование нескольких слов: (доля сошедшихся, доля исправленных принятых бит)."""
    L = схема.длина
    слов = min(слов, (len(биты) - начало) // L)
    if слов < 1:
        return 0.0, 1.0
    принятые = биты[начало:начало + слов * L].reshape(слов, L)
    слова, сошлось = мин_сумма(схема.llr(принятые), схема.связи_декодера(), схема.матрица.n, 50)
    return float(сошлось.mean()), float((слова[:, схема.переданы] != принятые).mean())


def варианты_схемы(схема: Схема, блок: int | None = None, как: str = ""
                   ) -> list[tuple[str, Схема]]:
    """Как слово может лежать в потоке: базовая схема и, если известен блок данных, частые.

    Если длина блока данных известна (нагрузка кадра, выход декодера) и
    переданное слово короче базового в целое число раз меньше блока,
    недостающие d позиций — ещё выколотые первые или последние переданные
    позиции (согласование скорости) либо укороченные первые или последние
    информационные (дополняющие нули).
    """
    матрица = схема.матрица
    база = как or ("по схеме, сохранённой с матрицей" if len(схема.выколоты) or len(схема.укорочены)
                   else "слово передаётся целиком")
    итог = [(база, схема)]
    L0 = схема.длина
    if not блок or схема.порядок is not None:
        return итог
    длины = sorted({блок // м for м in range(1, СЛОВ_В_БЛОКЕ_ДО + 1)
                    if блок % м == 0 and L0 // 2 <= блок // м < L0}, reverse=True)
    if not длины:
        return итог
    занято = np.zeros(матрица.n, dtype=bool)
    занято[схема.выколоты] = True
    занято[схема.укорочены] = True
    данные = информационные(матрица)
    данные = данные[~занято[данные]]
    пусто = np.array([], dtype=np.int64)
    приставка = "" if база == "слово передаётся целиком" else f"{база}; "
    for L in длины:
        d = L0 - L
        for имя, выколоты, укорочены in (
                (f"выколоты первые {d} переданных позиций", схема.переданы[:d], пусто),
                (f"выколоты последние {d} переданных позиций", схема.переданы[L0 - d:], пусто),
                (f"укорочены первые {d} информационных позиций", пусто, данные[:d]),
                (f"укорочены последние {d} информационных позиций", пусто, данные[len(данные) - d:])):
            if len(укорочены) and d > len(данные):
                continue
            try:
                итог.append((приставка + имя, Схема(матрица, np.union1d(схема.выколоты, выколоты),
                                                    np.union1d(схема.укорочены, укорочены))))
            except ValueError:
                continue
    return итог


def найти_по_матрицам(биты: np.ndarray, *, блок: int | None = None, бюджет: float = 30.0,
                      схемы: Sequence[tuple[str, Схема]] | None = None, встроенные: bool = False,
                      имена: Sequence[str] | None = None):
    """Код LDPC по загруженным матрицам — сам: схема передачи, начало слова, декодирование.

    Каждая матрица пробуется со схемой, сохранённой вместе с ней, и — если
    известна длина блока данных — с частыми схемами выкалывания и укорочения.
    Совпадение — вычислимые проверки при лучшем начале слова почти не нарушены
    (у чужой матрицы и при неверном начале — около половины); из совпавших
    берётся лучшая. ``схемы`` — [(имя, Схема)], по умолчанию — все загруженные;
    ``встроенные`` — ещё и встроенные коды стандартов (со схемой стандарта), при
    известном блоке — только те, чьё слово ложится в блок; ``имена`` — только эти встроенные
    (окно «LDPC»: коды выбранного типа и скорости).
    """
    from .nahodka import Находка  # noqa: PLC0415
    конец = time.monotonic() + бюджет
    if схемы is None:
        схемы = []
        for м in список():
            if "ошибка" in м:
                continue
            try:
                схемы.append((str(м["имя"]), схема_сохранённая(str(м["имя"]))))
            except (ValueError, OSError, KeyError):
                continue
    схемы = [(имя, с, "") for имя, с in схемы]
    загруженных = len(схемы)
    if встроенные:
        from . import ldpc_std  # noqa: PLC0415
        загружены = {имя for имя, _, _ in схемы}
        for имя in ldpc_std.подходящие(блок, бит=len(биты), имена=None if имена is None else list(имена)):
            if имя not in загружены:
                схемы.append((имя, None, "по схеме стандарта" if ldpc_std.выколоты_по_стандарту(имя)
                              else "слово передаётся целиком"))
    совпавшие = []
    проверено = 0

    def совпало(проба, L: int, проверки, слов: int) -> float | None:
        """Вероятность случайного совпадения (по различным словам, на одно начало из L) или None — не совпало."""
        if (проба is None or проба[1] > СОВПАДЕНИЕ_ДО or проба[1] > 0.5 * проба[2]
                or проба[2] < МЕДИАНА_ОТ):
            return None
        _, доля, отсчётов = различные(биты, L, проверки, проба[0], слов)
        if доля > СОВПАДЕНИЕ_ДО:
            return None
        p = случайно(доля, отсчётов, L)
        return p if p <= СЛУЧАЙНО_ДО else None

    for имя, сохранённая, как in схемы:
        if time.monotonic() > конец:
            break
        if сохранённая is None:
            from . import ldpc_std  # noqa: PLC0415
            # Встроенный код: схема стандарта и, у DVB-S2, перемежения бит перед модуляцией.
            перемежения = [("", как)] + [(вид, f"{как}; перемежение бит {вид} ({столбцы})")
                                          for вид, столбцы in ldpc_std.перемежения(имя)]
            if not блок:
                # Без блока — только сами схемы стандарта: проверки для пробы готовы (матрица
                # строится один раз), вся схема — лишь если совпало.
                for вид, вариант in перемежения:
                    L, проверки = ldpc_std.проба(имя, ПРОБА_ПРОВЕРОК, вид)
                    слов = min(слов_для_пробы(L, len(проверки)), len(биты) // L - 1)
                    проба = _проба(биты, L, проверки, слов)
                    проверено += 1
                    if (p := совпало(проба, L, проверки, слов)) is not None:
                        начало, нарушено, медиана = проба
                        совпавшие.append((нарушено, медиана, имя, вариант, ldpc_std.схема(имя, вид), начало, p))
                continue
            базы = [(вариант, ldpc_std.схема(имя, вид)) for вид, вариант in перемежения]
        else:
            базы = [(как, сохранённая)]
        for как_база, база in базы:
            for вариант, схема in варианты_схемы(база, блок, как_база):
                if time.monotonic() > конец:
                    break
                проверки = проверки_для_пробы(схема, ПРОБА_ПРОВЕРОК)[0]
                слов = min(слов_для_пробы(схема.длина, len(проверки)), len(биты) // схема.длина - 1)
                проба = _проба(биты, схема.длина, проверки, слов)
                проверено += 1
                if (p := совпало(проба, схема.длина, проверки, слов)) is not None:
                    начало, нарушено, медиана = проба
                    совпавшие.append((нарушено, медиана, имя, вариант, схема, начало, p))
    # Поправка на перебор: из сотен схем (выкалывание по блоку, перемежения) одна случайно совпадает чаще —
    # вероятность случайного совпадения умножается на число проверенных схем.
    совпавшие = [с[:6] for с in совпавшие if с[6] * max(1, проверено) <= СЛУЧАЙНО_ДО]
    if not совпавшие:
        return None
    совпавшие.sort(key=lambda с: с[0])                      # при равных — в порядке перебора
    лучшее = совпавшие[0]
    почти = [с for с in совпавшие if с[0] <= лучшее[0] + max(РАВНЫЕ_ДО, 0.5 * лучшее[0])]
    выбор = ""
    if len(почти) > 1:
        # Почти равные схемы (соседние варианты выкалывания, та же матрица с иным началом):
        # по проверкам не различить — у верной декодер сходится и правит лишь ошибки линии,
        # у почти верной — ещё и биты, которые она кладёт не туда.
        почти = почти[:РАВНЫХ_ПРОБОВАТЬ]
        пробы = [_пробное(биты, с[4], с[5], ПРОБНЫХ_СЛОВ) for с in почти]
        лучший = min(range(len(почти)), key=lambda i: (-пробы[i][0], пробы[i][1]))
        лучшее = почти[лучший]
        выбор = ("почти равные по проверкам схемы различены пробным декодированием "
                 f"{ПРОБНЫХ_СЛОВ} слов (сошлось, исправлено принятых бит): " + "; ".join(
                     f"«{с[2]}» {с[3]}, начало {с[5]} — {п[0] * 100:.0f} %, {п[1] * 100:.2f} %"
                     + (" ← выбрана" if i == лучший else "") for i, (с, п) in enumerate(zip(почти, пробы, strict=False))))
    нарушено, медиана, имя, вариант, схема, начало = лучшее
    данные, подробно, сошлось = _снять(биты, схема, начало=начало)
    if выбор:
        подробно.insert(0, выбор)
    м = схема.матрица
    k = len(информационные(м))
    return Находка(
        уровень="код",
        что=f"LDPC ({м.n}, {k}) по матрице «{имя}»" + (f" ({м.откуда})" if м.откуда else "")
            + f"; {вариант}",
        уверенность=float(сошлось),
        мера=f"вычислимые проверки при найденном начале слова нарушены в {нарушено * 100:.1f} % "
             f"(при неверном начале — около {медиана * 100:.0f} %); синдром обнулился у "
             f"{сошлось * 100:.1f} % слов",
        подробно=[f"матрица и схема найдены перебором: загруженных матриц {загруженных}"
                  + (f", встроенных кодов стандартов {len(схемы) - загруженных}" if встроенные else "")
                  + f", схем проверено {проверено}; начало слова — бит {начало}"] + подробно,
        дальше=данные, вид_дальше="биты",
        свойства={"n": м.n, "k": k, "матрица": имя, "начало": начало,
                  "выколото": int(len(схема.выколоты)), "укорочено": int(len(схема.укорочены)),
                  "схема": схема})

