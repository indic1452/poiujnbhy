# -*- coding: utf-8 -*-
"""LDPC по известной матрице: загрузка H из стандарта, перфорация, укорочение, декодирование.

Вслепую длинный код с перфорацией не восстановить: выколотых позиций в
потоке нет, и проверки, которые их касаются, по принятым битам не
вычисляются. Но аналитику и не нужно вслепую — ему нужно снять код, когда
по синхрокомбинации, длине кадра и скорости уже ясно, какой это стандарт:
матрица проверок в стандарте напечатана. Помощник находит её в библиотеке,
аналитик вставляет её сюда в одном из видов, в которых её печатают:

- **alist** (формат Маккея: размеры, веса, номера единиц по столбцам и по
  строкам) — так раздают матрицы в наборах для моделирования;
- **базовая матрица сдвигов** с размером циркулянта Z (−1 или «-» — нулевой
  блок, s — единичная матрица, циклически сдвинутая вправо на s: в строке r
  единица в столбце (r + s) mod Z) — так печатают QC-LDPC (IEEE 802.11n,
  802.16e, базовые графы 5G NR — для выбранного Z);
- **таблица адресов** в духе DVB-S2/T2: строка i — адреса проверок для
  группы из 360 информационных бит; бит m группы идёт в проверки
  (x + (m mod 360)·q) mod (N − K), q = (N − K)/360, проверочная часть —
  накопитель (двухдиагональная). Формулу сверяйте с документом из
  библиотеки: её здесь не придумывают, а берут оттуда же, откуда таблицу.

Снятие: принятые биты режутся на слова по n − (выколотых) − (укороченных)
бит, начало слова ищется по проверкам, которые по принятым битам
вычисляются; выколотые позиции входят в декодер «минимум — сумма» со
стёртым значением (LLR 0), укороченные — как известные нули. На выходе —
информационные биты каждого слова.
"""

from __future__ import annotations

import json
import re
import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from . import gf2

#: Где лежат загруженные матрицы (задаёт очередь заданий или команда).
КАТАЛОГ: Optional[Path] = None
#: Имя матрицы — как слово в указании слоя.
ИМЯ = re.compile(r"[0-9A-Za-zА-Яа-яЁё_.\-]{1,60}")
#: Плотное исключение Гаусса — до такой длины (дальше нужна структура).
ПЛОТНО_ДО = 20000
СЛОВ_ДЛЯ_НАЧАЛА = 40


@dataclass
class Матрица:
    """Разреженная H: для каждой строки — номера столбцов с единицей."""
    n: int
    строки: List[np.ndarray]
    откуда: str = ""
    #: Позиции данных, если их задаёт стандарт (у 5G NR — первые 22Z или 10Z).
    данные: Optional[np.ndarray] = None
    _подряд: Optional[Tuple[np.ndarray, np.ndarray]] = field(default=None, repr=False, compare=False)

    @property
    def m(self) -> int:
        return len(self.строки)

    def подряд(self) -> Tuple[np.ndarray, np.ndarray]:
        """Строки подряд: столбцы всех строк и границы строк (m + 1 чисел) — для счёта без циклов."""
        if self._подряд is None:
            длины = np.fromiter((len(с) for с in self.строки), dtype=np.int64, count=self.m)
            границы = np.concatenate([[0], np.cumsum(длины)]).astype(np.int64)
            столбцы = (np.concatenate(self.строки).astype(np.int64) if self.m
                       else np.zeros(0, dtype=np.int64))
            self._подряд = (столбцы, границы)
        return self._подряд

    def _номера_строк(self) -> np.ndarray:
        """Номер строки для каждого элемента ``подряд()[0]``."""
        return np.repeat(np.arange(self.m), np.diff(self.подряд()[1]))

    def связи(self) -> np.ndarray:
        """m × d номеров столбцов; недостающие — фиктивный столбец n."""
        столбцы, границы = self.подряд()
        длины = np.diff(границы)
        итог = np.full((self.m, int(длины.max())), self.n, dtype=np.int64)
        итог[self._номера_строк(), np.arange(len(столбцы)) - np.repeat(границы[:-1], длины)] = столбцы
        return итог

    def плотная(self) -> np.ndarray:
        H = np.zeros((self.m, self.n), dtype=np.uint8)
        H[self._номера_строк(), self.подряд()[0]] = 1
        return H

    def веса(self) -> Tuple[List[int], List[int]]:
        строк = sorted({len(с) for с in self.строки})
        столбцов = np.bincount(np.concatenate(self.строки), minlength=self.n)
        return строк, sorted(set(столбцов.tolist()))

    def сводка(self) -> Dict[str, object]:
        строк, столбцов = self.веса()
        k, как = информационные_сводка(self)
        return {"n": self.n, "m": self.m, "k": k, "скорость": round(k / self.n, 4),
                "веса_строк": строк, "веса_столбцов": столбцов, "откуда": self.откуда,
                "данные": как}


# -- загрузка -----------------------------------------------------------------------------

def _числа(текст: str) -> List[int]:
    return [int(ч) for ч in re.findall(r"-?\d+", текст)]


def _по_строкам(n: int, m: int, строка: np.ndarray, столбец: np.ndarray, откуда: str) -> Матрица:
    """Единицы H парами (строка, столбец) → матрица: столбцы каждой из m строк по возрастанию."""
    порядок = np.lexsort((столбец, строка))
    строка, столбец = строка[порядок], столбец[порядок].astype(np.int64)
    границы = np.searchsorted(строка, np.arange(m + 1)).astype(np.int64)
    г = границы.tolist()
    return Матрица(n, [столбец[г[i]:г[i + 1]] for i in range(m)], откуда,
                   _подряд=(столбец, границы))


def из_alist(текст: str) -> Матрица:
    """Формат alist: n m; наибольшие веса; веса столбцов; веса строк; столбцы; строки."""
    числа = _числа(текст)
    if len(числа) < 4:
        raise ValueError("alist: нет заголовка «n m»")
    n, m = числа[0], числа[1]
    if n < 2 or m < 1 or m >= n * 4:
        raise ValueError(f"alist: странные размеры n = {n}, m = {m}")
    место = 4
    веса_столбцов = числа[место:место + n]
    место += n
    веса_строк = числа[место:место + m]
    место += m
    наиб_столбец = max(веса_столбцов) if веса_столбцов else 0
    # Столбцы — по наибольшему весу в строке (дополнены нулями) или ровно по весу.
    остаток = np.array(числа[место:], dtype=np.int64)
    дополнены = len(остаток) >= n * наиб_столбец + m * max(веса_строк, default=0)
    ширины = np.full(n, наиб_столбец) if дополнены else np.maximum(np.array(веса_столбцов), 0)
    значения = остаток[:int(ширины.sum())]
    столбец = np.repeat(np.arange(n), ширины)[:len(значения)]
    есть = значения != 0
    значения, столбец = значения[есть], столбец[есть]
    вне = np.flatnonzero((значения < 1) | (значения > m))
    if len(вне):
        raise ValueError(f"alist: строка {значения[вне[0]]} вне 1…{m} в столбце {столбец[вне[0]] + 1}")
    итог = _по_строкам(n, m, значения - 1, столбец, "alist")
    if [len(с) for с in итог.строки] != list(веса_строк):
        raise ValueError("alist: веса строк не сходятся с номерами по столбцам")
    return итог


def из_прототипа(текст: str, Z: int) -> Матрица:
    """Базовая матрица сдвигов: −1/«-» — нулевой блок, s ≥ 0 — сдвиг вправо на s mod Z."""
    if Z < 1:
        raise ValueError("нужен размер циркулянта Z")
    ряды = []
    for строка in текст.strip().splitlines():
        значения = re.findall(r"-1|-|\d+", строка)
        if значения:
            ряды.append([-1 if з in ("-", "-1") else int(з) for з in значения])
    if not ряды or len({len(р) for р in ряды}) != 1:
        raise ValueError("базовая матрица: во всех строках должно быть одно число столбцов")
    P = np.array(ряды, dtype=np.int64)
    mb, nb = P.shape
    if (P < 0).all(axis=1).any():
        raise ValueError("базовая матрица: есть строка без единого блока")
    # Блок (i, j) со сдвигом s: в строке i·Z + r единица в столбце j·Z + (r + s) mod Z.
    bi, bj = np.nonzero(P >= 0)
    r = np.arange(Z)
    строка = (bi[:, None] * Z + r).reshape(-1)
    столбец = (bj[:, None] * Z + (r + P[bi, bj][:, None]) % Z).reshape(-1)
    return _по_строкам(nb * Z, mb * Z, строка, столбец, f"базовая {mb}×{nb}, Z = {Z}")


def из_адресов(текст: str, n: int, k: int, группа: int = 360) -> Матрица:
    """Таблица адресов (DVB-S2/T2): строка — адреса для группы информационных бит."""
    m = n - k
    if m <= 0 or k <= 0 or k % группа or m % группа:
        raise ValueError(f"адреса: нужны n > k, кратные {группа}")
    q = m // группа
    ряды = [_числа(с) for с in текст.strip().splitlines() if _числа(с)]
    if len(ряды) != k // группа:
        raise ValueError(f"адреса: строк {len(ряды)}, а групп информационных бит {k // группа}")
    t = np.arange(группа)
    строка, столбец = [], []
    for i, адреса in enumerate(ряды):
        x = np.array(адреса, dtype=np.int64)
        вне = (x < 0) | (x >= m)
        if вне.any():
            raise ValueError(f"адреса: {x[вне][0]} вне 0…{m - 1}")
        # Бит t группы i — в проверки (x + t·q) mod m.
        строка.append(((x[:, None] + t * q) % m).reshape(-1))
        столбец.append(np.broadcast_to(i * группа + t, (len(x), группа)).reshape(-1))
    # Проверочная часть — накопитель: p_i входит в проверки i и i + 1.
    p = np.arange(m)
    строка += [p, p[1:]]
    столбец += [k + p, k + p[1:] - 1]
    return _по_строкам(n, m, np.concatenate(строка), np.concatenate(столбец), f"адреса, n = {n}, k = {k}")


def загрузить(вид: str, текст: str, *, Z: int = 0, n: int = 0, k: int = 0) -> Матрица:
    if вид == "alist":
        return из_alist(текст)
    if вид in ("прототип", "базовая"):
        return из_прототипа(текст, Z)
    if вид == "адреса":
        return из_адресов(текст, n, k)
    raise ValueError(f"неизвестный вид матрицы «{вид}»: alist, базовая, адреса")


# -- хранение ----------------------------------------------------------------------------

def _путь(имя: str) -> Path:
    if КАТАЛОГ is None:
        raise ValueError("каталог матриц LDPC не задан")
    if not ИМЯ.fullmatch(имя or "") or имя.startswith("."):
        raise ValueError("имя матрицы — буквы, цифры, «_», «-», «.» (до 60 знаков)")
    return КАТАЛОГ / f"{имя}.json"


def сохранить(имя: str, матрица: Матрица, владелец: int = 0, *, выколоты: str = "",
              укорочены: str = "") -> Dict[str, object]:
    """Сохранить матрицу — и, если известна, схему передачи: выколотые и укороченные позиции.

    Схема нужна автомату: по ней он сам пробует матрицу на потоке (без неё —
    всё слово целиком и, если известна длина блока, частые схемы).
    """
    путь = _путь(имя)
    Схема(матрица, позиции(выколоты, матрица.n), позиции(укорочены, матрица.n))   # проверка
    путь.parent.mkdir(parents=True, exist_ok=True)
    сводка = матрица.сводка()
    путь.write_text(json.dumps({"n": матрица.n, "откуда": матрица.откуда, "владелец": владелец,
                                "строки": [с.tolist() for с in матрица.строки],
                                "выколоты": выколоты.strip(), "укорочены": укорочены.strip(),
                                "сводка": сводка}, ensure_ascii=False), encoding="utf-8")
    return {"имя": имя, **сводка, "выколоты": выколоты.strip(), "укорочены": укорочены.strip()}


def _данные_матрицы(имя: str) -> dict:
    путь = _путь(имя)
    if not путь.exists():
        raise ValueError(f"матрицы «{имя}» нет — загрузите её в растре («Матрицы LDPC»)")
    return json.loads(путь.read_text(encoding="utf-8"))


def _матрица(данные: dict) -> Матрица:
    return Матрица(int(данные["n"]), [np.array(с, dtype=np.int64) for с in данные["строки"]],
                   данные.get("откуда", ""))


def _встроенная(имя: str) -> bool:
    """Имени нет среди загруженных, но есть среди встроенных кодов стандартов."""
    from . import ldpc_std  # noqa: PLC0415
    return (КАТАЛОГ is None or not (КАТАЛОГ / f"{имя}.json").exists()) and ldpc_std.есть(имя)


def прочитать(имя: str) -> Матрица:
    if _встроенная(имя):
        from . import ldpc_std  # noqa: PLC0415
        return ldpc_std.матрица(имя)
    return _матрица(_данные_матрицы(имя))


def схема_сохранённая(имя: str) -> "Схема":
    """Матрица со схемой передачи, сохранённой вместе с ней (без схемы — всё слово); у встроенного
    кода — схема стандарта."""
    if _встроенная(имя):
        from . import ldpc_std  # noqa: PLC0415
        return ldpc_std.схема(имя)
    данные = _данные_матрицы(имя)
    матрица = _матрица(данные)
    return Схема(матрица, позиции(данные.get("выколоты", ""), матрица.n),
                 позиции(данные.get("укорочены", ""), матрица.n))


def список() -> List[Dict[str, object]]:
    if КАТАЛОГ is None or not КАТАЛОГ.exists():
        return []
    итог = []
    for путь in sorted(КАТАЛОГ.glob("*.json")):
        данные = json.loads(путь.read_text(encoding="utf-8"))
        итог.append({"имя": путь.stem, "владелец": данные.get("владелец", 0),
                     **данные.get("сводка", {}), "выколоты": данные.get("выколоты", ""),
                     "укорочены": данные.get("укорочены", "")})
    return итог


def владелец(имя: str) -> Optional[int]:
    путь = _путь(имя)
    if not путь.exists():
        return None
    return int(json.loads(путь.read_text(encoding="utf-8")).get("владелец", 0))


def удалить(имя: str) -> None:
    _путь(имя).unlink(missing_ok=True)


# -- информационные позиции ----------------------------------------------------------------

def _треугольная_справа(матрица: Матрица) -> bool:
    """Последние m столбцов — нижнетреугольные с единичной диагональю (накопитель)."""
    k = матрица.n - матрица.m
    столбцы, _ = матрица.подряд()
    проверочные = столбцы >= k
    наибольший = np.full(матрица.m, -1, dtype=np.int64)
    np.maximum.at(наибольший, матрица._номера_строк()[проверочные], столбцы[проверочные] - k)
    return bool(np.array_equal(наибольший, np.arange(матрица.m)))


def информационные_сводка(матрица: Матрица) -> Tuple[int, str]:
    if матрица.данные is not None:
        return len(матрица.данные), f"первые {len(матрица.данные)} позиций (по стандарту)"
    if матрица.n - матрица.m > 0 and _треугольная_справа(матрица):
        return матрица.n - матрица.m, "первые k позиций (проверочная часть — накопитель)"
    if матрица.n > ПЛОТНО_ДО:
        return матрица.n - матрица.m, "первые n − m позиций (ранг не проверялся: код длинный)"
    r = gf2.ранг(матрица.плотная())
    return матрица.n - r, "по опорным столбцам (исключение Гаусса)"


def информационные(матрица: Матрица) -> np.ndarray:
    """Позиции данных: систематическая часть кода."""
    if матрица.данные is not None:
        return матрица.данные
    if (матрица.n - матрица.m > 0 and _треугольная_справа(матрица)) or матрица.n > ПЛОТНО_ДО:
        return np.arange(матрица.n - матрица.m)
    H = матрица.плотная()
    # Проверочные — опорные столбцы H, приведённой справа налево: тогда данные — в начале.
    _, опорные = gf2.привести(gf2.упаковать(H[:, ::-1]), матрица.n)
    проверочные = {матрица.n - 1 - j for j in опорные}
    return np.array([j for j in range(матрица.n) if j not in проверочные], dtype=np.int64)


# -- перфорация и декодирование ---------------------------------------------------------------

def позиции(указание: str, n: int) -> np.ndarray:
    """«0-191, 1000-1023» → номера позиций слова."""
    итог = set()
    for a, b, одна in re.findall(r"(\d+)\s*(?:[-–…]|\.\.)\s*(\d+)|(\d+)", указание or ""):
        a, b = (int(одна), int(одна)) if одна else (int(a), int(b))
        if a > b or b >= n:
            raise ValueError(f"позиции {a}–{b} вне слова 0…{n - 1}")
        итог.update(range(a, b + 1))
    return np.array(sorted(итог), dtype=np.int64)


def мин_сумма(llr: np.ndarray, связи: np.ndarray, n: int, итераций: int = 50
              ) -> Tuple[np.ndarray, np.ndarray]:
    """Декодер «минимум — сумма» (с поправкой 0,75) по мягким входам; LLR > 0 — ноль.

    Стёртые позиции (выколотые) — LLR 0, известные нули (укороченные) —
    большое положительное. Возвращает слова и признак нулевого синдрома.
    """
    M = len(llr)
    m, d = связи.shape
    есть = связи < n
    к_проверке = np.zeros((M, m, d), dtype=np.float32)
    слова = (llr < 0).astype(np.uint8)
    дополненные = np.concatenate([слова, np.zeros((M, 1), np.uint8)], axis=1)
    for _ in range(итераций):
        сумма = np.zeros((M, n + 1), dtype=np.float32)
        np.add.at(сумма, (slice(None), связи), к_проверке * есть)
        полная = llr + сумма[:, :n]
        слова = (полная < 0).astype(np.uint8)
        дополненные[:, :n] = слова
        синдром = np.bitwise_xor.reduce(np.where(есть, дополненные[:, связи], 0), axis=2)
        if not синдром.any():
            break
        расширенная = np.concatenate([полная, np.zeros((M, 1), np.float32)], axis=1)
        от_позиции = расширенная[:, связи] - к_проверке
        от_позиции = np.where(есть, от_позиции, np.float32(1e9))
        знак = np.where(от_позиции < 0, -1.0, 1.0).astype(np.float32)
        модуль = np.abs(от_позиции)
        общий = np.prod(знак, axis=2, keepdims=True)
        порядок = np.sort(модуль, axis=2)
        первый, второй = порядок[:, :, :1], порядок[:, :, 1:2]
        наименьший = np.where(модуль == первый, второй, первый)
        к_проверке = (0.75 * общий * знак * наименьший * есть).astype(np.float32)
    дополненные[:, :n] = слова
    синдром = np.bitwise_xor.reduce(np.where(есть, дополненные[:, связи], 0), axis=2)
    return слова, ~синдром.any(axis=1)


@dataclass
class Схема:
    """Как слово кода лежит в потоке: что передано, что выколото, что укорочено.

    ``порядок`` — в каком порядке позиции слова идут в потоке, если не подряд
    (перемежение бит перед модуляцией): перестановка переданных позиций.
    """
    матрица: Матрица
    выколоты: np.ndarray
    укорочены: np.ndarray
    порядок: Optional[np.ndarray] = None

    def __post_init__(self):
        общие = np.intersect1d(self.выколоты, self.укорочены)
        if len(общие):
            raise ValueError(f"позиция {общие[0]} и выколота, и укорочена")
        лишние = np.zeros(self.матрица.n, dtype=bool)
        лишние[self.выколоты] = True
        лишние[self.укорочены] = True
        self.переданы = np.flatnonzero(~лишние)
        if self.порядок is not None:
            порядок = np.asarray(self.порядок, dtype=np.int64)
            if not np.array_equal(np.sort(порядок), self.переданы):
                raise ValueError("порядок в потоке — не перестановка переданных позиций слова")
            self.переданы = порядок
        if len(self.переданы) < self.матрица.m // 2:
            raise ValueError("передано слишком мало позиций слова")

    @property
    def длина(self) -> int:
        return len(self.переданы)

    def llr(self, принятые: np.ndarray) -> np.ndarray:
        """Слова по длине передачи → LLR полного слова."""
        M = len(принятые)
        L = np.zeros((M, self.матрица.n), dtype=np.float32)
        L[:, self.переданы] = 1.0 - 2.0 * принятые.astype(np.float32)
        L[:, self.укорочены] = 50.0
        return L


def перемежитель(n: int, столбцы: str) -> np.ndarray:
    """Перемежение бит «запись по столбцам — чтение по строкам» (DVB-S2, 5.3.3): какая позиция
    слова идёт в потоке i-й.

    Слово пишется в c = len(столбцы) столбцов по n / c бит (столбец j — позиции
    j·n/c … (j + 1)·n/c − 1) и читается по строкам: в строке r сперва бит столбца
    ``столбцы[0]``, затем ``столбцы[1]`` и т. д. — старший бит символа первым (как
    в GNU Radio gr-dtv, dvbs2_interleaver_bb, и xdsopl/LDPC, itls_handler).
    """
    c = len(столбцы)
    if c < 2 or n % c or sorted(столбцы) != [str(j) for j in range(c)]:
        raise ValueError(f"перемежение «{столбцы}»: нужны все столбцы 0…{c - 1} и n, кратное {c}")
    строк = n // c
    откуда = np.array([int(j) * строк for j in столбцы], dtype=np.int64)
    return (np.arange(строк)[:, None] + откуда[None, :]).reshape(-1)


def вычислимые(схема: Схема, сколько: Optional[int] = None) -> List[np.ndarray]:
    """Проверки, которые считаются по принятым битам: без выколотых позиций.

    Возвращает их в номерах позиций ПЕРЕДАННОГО слова (укороченные — нули, их
    из проверки можно просто выбросить). ``сколько`` — не больше стольких,
    равномерно по всем вычислимым (для пробы матрицы на потоке).
    """
    м = схема.матрица
    столбцы, границы = м.подряд()
    номер = м._номера_строк()
    выколото = np.zeros(м.n, dtype=bool)
    выколото[схема.выколоты] = True
    укорочено = np.zeros(м.n, dtype=bool)
    укорочено[схема.укорочены] = True
    куда = np.full(м.n, -1, dtype=np.int64)
    куда[схема.переданы] = np.arange(схема.длина)
    с_выколотыми = np.bincount(номер[выколото[столбцы]], minlength=м.m) > 0
    осталось = np.bincount(номер[~укорочено[столбцы]], minlength=м.m)
    годные = np.flatnonzero(~с_выколотыми & (осталось > 0))
    if сколько is not None:
        годные = годные[::max(1, len(годные) // max(1, сколько))][:сколько]
    итог = []
    for i in годные:
        с = столбцы[границы[i]:границы[i + 1]]
        итог.append(куда[с[~укорочено[с]]])
    return итог


#: Сумма — не больше стольких строк H (строка и опорные строки её выколотых позиций).
СЛОЖЕННЫХ_СТРОК_ДО = 4


def сложенные(схема: Схема, сколько: int) -> List[np.ndarray]:
    """Проверки, сложенные из нескольких строк H так, что выколотые позиции сократились: их
    можно посчитать по принятым битам.

    Нужны, когда выколотые позиции входят почти во все строки: у 5G NR (граф 1) первые 2Z
    позиций — во всех 46Z строках, у AR4JA (CCSDS) выколотые блок-столбцы — во всех
    строках; одиночных вычислимых проверок тогда нет. Сперва — пары строк с одними и теми
    же выколотыми позициями (сумма разрежена почти как сами строки); не хватает — строка
    вместе с опорными: строками, где выколота ровно одна позиция, по одной на каждую её
    выколотую (всего не больше СЛОЖЕННЫХ_СТРОК_ДО строк). Возвращает не больше
    ``сколько`` — равномерно, в номерах позиций переданного слова.
    """
    м = схема.матрица
    столбцы, границы = м.подряд()
    выколото = np.zeros(м.n, dtype=bool)
    выколото[схема.выколоты] = True
    if not выколото.any() or сколько < 1:
        return []
    укорочено = np.zeros(м.n, dtype=bool)
    укорочено[схема.укорочены] = True
    куда = np.full(м.n, -1, dtype=np.int64)
    куда[схема.переданы] = np.arange(схема.длина)
    выколотые: Dict[int, Tuple[int, ...]] = {}
    for i in np.unique(м._номера_строк()[выколото[столбцы]]).tolist():
        с = столбцы[границы[i]:границы[i + 1]]
        выколотые[i] = tuple(с[выколото[с]].tolist())
    последняя: Dict[Tuple[int, ...], int] = {}
    пары: List[Tuple[int, ...]] = []
    for i, ключ in выколотые.items():
        if ключ in последняя:
            пары.append((последняя[ключ], i))
        последняя[ключ] = i
    выбор = пары[::max(1, len(пары) // сколько)][:сколько]
    if len(выбор) < сколько:
        опорная: Dict[int, int] = {}
        for i, ключ in выколотые.items():
            if len(ключ) == 1:
                опорная.setdefault(ключ[0], i)
        с_опорными = [(i,) + tuple(опорная[c] for c in ключ) for i, ключ in выколотые.items()
                      if 2 <= len(ключ) < СЛОЖЕННЫХ_СТРОК_ДО and all(c in опорная for c in ключ)]
        осталось = сколько - len(выбор)
        выбор += с_опорными[::max(1, len(с_опорными) // осталось)][:осталось]
    итог = []
    for набор in выбор:
        все, раз = np.unique(np.concatenate([столбцы[границы[i]:границы[i + 1]] for i in набор]),
                             return_counts=True)
        сумма = все[раз % 2 == 1]
        сумма = сумма[~укорочено[сумма]]
        if len(сумма) and not выколото[сумма].any():
            итог.append(куда[сумма])
    return итог


def проверки_для_пробы(схема: Схема, сколько: int) -> Tuple[List[np.ndarray], int]:
    """Вычислимые проверки (равномерно, не больше ``сколько``), а если их меньше — и сложенные из
    нескольких строк: (проверки, из них сложенных)."""
    одиночные = вычислимые(схема, сколько)
    сложено = сложенные(схема, сколько - len(одиночные)) if len(одиночные) < сколько else []
    return одиночные + сложено, len(сложено)


def найти_начало(биты: np.ndarray, схема: Схема, бюджет: float = 60.0
                 ) -> Tuple[int, float, str]:
    """Начало слова в потоке: где вычислимые проверки нарушены реже всего.

    Одиночных вычислимых проверок мало (выколотые позиции входят почти во все
    строки) — добавляются суммы строк, в которых выколотые сокращаются; нет и их —
    пробным декодированием: у верного начала декодер сходится.
    """
    L = схема.длина
    слов = min(СЛОВ_ДЛЯ_НАЧАЛА, len(биты) // L - 1)
    if слов < 2:
        raise ValueError(f"в потоке меньше двух слов по {L} бит")
    выборка = биты[:(слов + 1) * L].astype(np.uint8)
    проверки, сложено = проверки_для_пробы(схема, 400)
    проба = _проба(биты, L, проверки, СЛОВ_ДЛЯ_НАЧАЛА)
    if проба is not None:
        начало, нарушено, медиана = проба
        return начало, нарушено, (
            f"по {len(проверки)} вычислимым проверкам"
            + (f" (из них {сложено} — суммы строк, в которых выколотые позиции сокращаются)"
               if сложено else "")
            + f": нарушено {нарушено * 100:.1f} % (при неверном начале — около {медиана * 100:.0f} %)")
    конец = time.monotonic() + бюджет
    связи = схема.матрица.связи()
    лучшее = (-1.0, 0)
    for начало in range(L):
        if time.monotonic() > конец:
            break
        слова = выборка[начало:начало + 2 * L].reshape(2, L)
        _, сошлось = мин_сумма(схема.llr(слова), связи, схема.матрица.n, 15)
        доля = float(сошлось.mean())
        if доля > лучшее[0]:
            лучшее = (доля, начало)
            if доля == 1.0:
                break
    if лучшее[0] <= 0:
        raise ValueError("начало слова не найдено: ни при одном сдвиге декодер не сошёлся "
                         "(задайте «начало N» или проверьте матрицу и перфорацию)")
    return лучшее[1], 1 - лучшее[0], "пробным декодированием (вычислимых проверок нет)"


def _проба(биты: np.ndarray, L: int, проверки: Sequence[np.ndarray], слов_до: int
           ) -> Optional[Tuple[int, float, float]]:
    """Начало слова по вычислимым проверкам: (начало, доля нарушенных, медиана по всем началам).

    У верной матрицы при верном начале проверки нарушены только ошибками
    линии, у чужой (и при неверном начале) — около половины. ``L`` — длина слова
    в потоке. None — проверок меньше трёх или слов меньше двух.
    """
    слов = min(слов_до, len(биты) // L - 1)
    if слов < 2 or len(проверки) < 3:
        return None
    выборка = биты[:(слов + 1) * L].astype(np.uint8)
    нарушено = np.zeros(слов * L, dtype=np.float64)
    for с in проверки:
        чётность = np.zeros(слов * L, dtype=np.uint8)
        for p in с:
            чётность ^= выборка[p:p + слов * L]
        нарушено += чётность
    по_началу = нарушено.reshape(слов, L).mean(axis=0) / len(проверки)
    начало = int(np.argmin(по_началу))
    return начало, float(по_началу[начало]), float(np.median(по_началу))


def снять(биты: np.ndarray, схема: Схема, *, начало: Optional[int] = None,
          итераций: int = 50, слов_до: int = 4000, пачка: int = 32
          ) -> Tuple[np.ndarray, List[str]]:
    """Декодировать слова и вернуть их информационные биты подряд."""
    данные, подробно, _ = _снять(биты, схема, начало=начало, итераций=итераций, слов_до=слов_до,
                                 пачка=пачка)
    return данные, подробно


def _снять(биты: np.ndarray, схема: Схема, *, начало: Optional[int] = None,
           итераций: int = 50, слов_до: int = 4000, пачка: int = 32
           ) -> Tuple[np.ndarray, List[str], float]:
    """Снятие: информационные биты, строки отчёта и доля слов с обнулившимся синдромом."""
    подробно = []
    if начало is None:
        начало, _, как = найти_начало(биты, схема)
        подробно.append(f"начало слова — бит {начало}, найдено {как}")
    L = схема.длина
    слов = min(слов_до, (len(биты) - начало) // L)
    if слов < 1:
        raise ValueError("в потоке нет ни одного целого слова")
    принятые = биты[начало:начало + слов * L].reshape(слов, L)
    связи = схема.матрица.связи()
    данные = информационные(схема.матрица)
    итог, сошлось, исправлено = [], 0, 0
    for от in range(0, слов, пачка):
        кусок = принятые[от:от + пачка]
        слова, ок = мин_сумма(схема.llr(кусок), связи, схема.матрица.n, итераций)
        сошлось += int(ок.sum())
        исправлено += int((слова[:, схема.переданы] != кусок).sum())
        итог.append(слова[:, данные])
    подробно += [
        f"код ({схема.матрица.n}, {len(данные)}), {схема.матрица.откуда}; в потоке слово "
        f"{L} бит: выколото {len(схема.выколоты)}, укорочено {len(схема.укорочены)}",
        f"слов {слов}: синдром обнулился у {сошлось} ({сошлось / слов * 100:.1f} %); "
        f"исправлено бит {исправлено} ({исправлено / (слов * L) * 100:.3f} % принятых)",
        f"на выходе — информационные биты: {информационные_сводка(схема.матрица)[1]}",
    ]
    if сошлось < слов * 0.5:
        подробно.append("меньше половины слов сошлось — проверьте матрицу, перфорацию и начало")
    return np.concatenate(итог, axis=0).reshape(-1), подробно, сошлось / слов


def из_указания(слова: str) -> Tuple[Схема, Optional[int], int]:
    """«ldpc ИМЯ [выколоты 0-191] [укорочены 0-99] [перемежение 8PSK [210]] [начало N] [итераций K]»."""
    части = слова.split()
    if len(части) < 2:
        raise ValueError("ldpc: нужно имя загруженной матрицы — «ldpc ИМЯ выколоты 0-191»")
    матрица = прочитать(части[1])

    def после(слово: str) -> str:
        м = re.search(слово + r"\w*\s+([\d\s,\-–…\.]+?)(?=\s+[А-Яа-яЁёA-Za-z]|$)", слова)
        return м.group(1) if м else ""

    выколоты = позиции(после("выколот"), матрица.n)
    if "выколот" not in слова and _встроенная(части[1]):
        выколоты = схема_сохранённая(части[1]).выколоты          # по стандарту (у NR — первые 2Z)
    укорочены = позиции(после("укороч"), матрица.n)
    начало_ = re.search(r"начал\w*\s+(\d+)", слова)
    итераций_ = re.search(r"итерац\w*\s+(\d+)", слова)
    перемежение = re.search(r"перемеж\w*\s+(8psk|16apsk|32apsk)(?:\s+(\d{3,5}))?", слова.lower())
    if перемежение:
        from . import ldpc_std  # noqa: PLC0415
        вид = перемежение.group(1).upper()
        столбцы = перемежение.group(2) or ldpc_std.столбцы_перемежения(части[1], вид)
        схема = Схема(матрица, выколоты, укорочены)
        return (Схема(матрица, выколоты, укорочены, схема.переданы[перемежитель(схема.длина, столбцы)]),
                int(начало_.group(1)) if начало_ else None,
                min(200, int(итераций_.group(1))) if итераций_ else 50)
    return (Схема(матрица, выколоты, укорочены),
            int(начало_.group(1)) if начало_ else None,
            min(200, int(итераций_.group(1))) if итераций_ else 50)


