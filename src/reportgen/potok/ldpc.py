#: чаще половины медианы по всем началам (у чужой матрицы — около половины при любом).
СОВПАДЕНИЕ_ДО = 0.2
#: Слово короче блока данных в целое число раз — до стольких слов в блоке.
СЛОВ_В_БЛОКЕ_ДО = 64
#: При неверном начале проверки нарушены хотя бы в такой доле (медиана по началам): у
