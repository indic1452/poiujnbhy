#: Расширения файлов матриц, которые автомат и окна читают из папки ldpc как есть.
РАСШИРЕНИЯ = (".alist", ".qc", ".base", ".adr", ".h", ".txt")
_КЭШ_ФАЙЛОВ: dict[tuple, dict] = {}


def в_alist(матрица: Матрица) -> str:
    """Матрица в формате alist (Маккей): номера дополнены нулями до наибольшего веса."""
    столбцы: list[list[int]] = [[] for _ in range(матрица.n)]
    for i, строка in enumerate(матрица.строки):
        for c in строка.tolist():
            столбцы[c].append(i + 1)
    вс, вр = max(map(len, столбцы)), max(len(с) for с in матрица.строки)
    строки = [f"{матрица.n} {матрица.m}", f"{вс} {вр}", " ".join(str(len(с)) for с in столбцы),
              " ".join(str(len(с)) for с in матрица.строки)]
    строки += [" ".join(map(str, с + [0] * (вс - len(с)))) for с in столбцы]
    строки += [" ".join(map(str, [c + 1 for c in с.tolist()] + [0] * (вр - len(с)))) for с in матрица.строки]
    return "\n".join(строки) + "\n"


def _мета(текст: str) -> tuple[str, dict[str, str]]:
    """Строки-примечания («# выколоты: 0-191», «% Z = 96», «// n = 64800») → (текст без них, поля)."""
    поля: dict[str, str] = {}
    строки = []
    for строка in текст.splitlines():
        голая = строка.strip()
        if голая.startswith(("#", "%", "//", ";")):
            м = re.match(r"(?:#|%|//|;)+\s*([A-Za-zА-Яа-яЁё]+)\s*[:=]?\s*(.*)", голая)
            if м:
                поля[м.group(1).lower()] = м.group(2).strip()
            continue
        м = re.fullmatch(r"\s*([ZzNnKk]|группа)\s*[:=]\s*(\d+)\s*", строка)
        if м:
            поля[м.group(1).lower()] = м.group(2)
            continue
        строки.append(строка)
    return "\n".join(строки), поля


def разобрать_файл(текст: str, имя_файла: str = "") -> tuple[Матрица, dict[str, str], str]:
    """Файл матрицы в любом из видов, в которых её печатают: (матрица, примечания, вид).

    - ``*.alist`` — формат Маккея;
    - базовая матрица сдвигов: строка «Z = 96» (или «# Z: 96», или «_z96» в имени файла) и ряды
      сдвигов (−1 или «-» — нулевой блок);
    - таблица адресов DVB: строки «n = 64800» и «k = 32400» (и, если не 360, «группа = …»);
    - «H в тексте»: ряды из 0 и 1 одной длины (пробелы между знаками допустимы).

    Примечания «# выколоты: …», «# укорочены: …», «# перемежение: 1367 | 8PSK 012», «# откуда: …»
    задают схему передачи и происхождение — с ними автомат пробует матрицу сразу как надо.
    """
    тело, поля = _мета(текст)
    z_имени = re.search(r"[_\-.]z(\d+)(?:\D|$)", имя_файла.lower())
    if имя_файла.lower().endswith(".alist"):
        м, вид = из_alist(тело), "alist"
    elif "z" in поля or z_имени:
        м, вид = из_прототипа(тело, int(поля.get("z") or z_имени.group(1))), "базовая"
    elif "n" in поля and "k" in поля:
        м, вид = из_адресов(тело, int(поля["n"]), int(поля["k"]), int(поля.get("группа") or 360)), "адреса"
    else:
        ряды = [re.sub(r"[\s,]", "", с) for с in тело.splitlines() if с.strip()]
        if ряды and all(re.fullmatch(r"[01]+", р) for р in ряды) and len({len(р) for р in ряды}) == 1:
            H = np.array([[ord(ч) - 48 for ч in р] for р in ряды], dtype=np.uint8)
            if not H.any(axis=1).all():
                raise ValueError("H в тексте: есть пустая строка проверок")
            строка, столбец = np.nonzero(H)
            м, вид = _по_строкам(H.shape[1], H.shape[0], строка, столбец, "H в тексте"), "H в тексте"
        else:
            try:
                м, вид = из_alist(тело), "alist"
            except ValueError:
                raise ValueError("не узнан вид: нужен alist, базовая с «Z = …», адреса с «n = …, k = …» "
                                 "или ряды 0/1 (H в тексте)") from None
    м.откуда = поля.get("откуда") or f"файл {имя_файла} ({вид})"
    return м, поля, вид


