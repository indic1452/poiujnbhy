"""CCSDS: кадры телеметрии TM (132.0-B) и AOS (732.0-B), пакеты Space Packet (133.0-B).

После синхрослова ASM, рандомизатора и кода Рида — Соломона (всё это
снимается раньше) идут кадры канала передачи данных фиксированной длины:

- **TM**: заголовок 6 байт — версия 00, SCID (10 бит), VCID (3), флаг OCF,
  счётчик кадров главного канала MCFC (8 бит, +1 каждый кадр), счётчик
  виртуального канала VCFC (8), слово состояния поля данных (флаг вторичного
  заголовка, синхронизации, порядка пакетов, длина сегмента, указатель первого
  заголовка пакета FHP, 11 бит: 0x7FF — начала пакета нет, 0x7FE — только
  заполнение); в конце — OCF (слово CLCW, 4 байта) и FECF (CRC-16 CCITT).
- **AOS**: версия 01, SCID (8), VCID (6), счётчик VCFC (24 бита), поле
  сигнализации; заголовок M_PDU с FHP (11 бит) у пакетного канала.
- **Space Packet**: заголовок 6 байт — версия 000, тип, флаг вторичного
  заголовка, APID (11 бит; 0x7FF — заполнение), флаги сегментации, счётчик
  (14 бит), длина поля данных − 1. Пакеты идут подряд через границы кадров
  виртуального канала: FHP говорит, где в кадре начинается первый.

Длина кадра и его начало находятся по счётчику кадров: байт, растущий на 1 от
кадра к кадру на одном и том же месте, — MCFC (у TM) или младший байт VCFC (у
AOS с одним каналом). Поля — по gr-satellites (ccsds/telemetry.py,
space_packet.py) и Wireshark (packet-ccsds.c); длина пакета — поле длины + 7
(CCSDS 133.0-B 4.1.3.5; так и у Wireshark).
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Tuple

import numpy as np

from .nahodka import Находка

#: Длины кадров, которые пробуются (байт): от короткого кадра до 2048 (TM — до 2048, AOS — так же).
ДЛИНА_ОТ, ДЛИНА_ДО = 64, 2048
#: Сколько байт потока смотреть при поиске длины и сколько кадров разбирать.
ВЫБОРКА = 1 << 15
КАДРОВ_ДО = 5000
#: Доля переходов «+1» у счётчика кадров, чтобы признать длину.
ДОЛЯ_СЧЁТЧИКА = 0.9


def crc16_ccitt(данные: bytes) -> int:
    """FECF (CCSDS 132.0-B 4.1.6): x¹⁶ + x¹² + x⁵ + 1, начальное 0xFFFF, без отражений."""
    crc = 0xFFFF
    for байт in данные:
        crc ^= байт << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc


def счётчик_кадров(данные: bytes) -> Optional[Tuple[int, int, float]]:
    """(длина кадра, место счётчика от начала потока по модулю длины, доля «+1»)."""
    б = np.frombuffer(данные[:ВЫБОРКА], dtype=np.uint8).astype(np.int16)
    лучшее = None
    for длина in range(ДЛИНА_ОТ, min(ДЛИНА_ДО, len(б) // 8) + 1):
        плюс = ((б[длина:] - б[:-длина]) & 0xFF) == 1
        строк = len(плюс) // длина
        доли = плюс[:строк * длина].reshape(строк, длина).mean(axis=0)
        место = int(np.argmax(доли))
        if доли[место] >= ДОЛЯ_СЧЁТЧИКА:
            # Кратная длина тоже даёт «+1» не будет (там +2, +3 …) — первая найденная и есть длина.
            лучшее = (длина, место, float(доли[место]))
            break
    return лучшее


@dataclass
class Кадр:
    версия: int
    scid: int
    vcid: int
    счётчик: int
    ocf: bool
    fhp: Optional[int]
    данные: bytes
    clcw: Optional[int] = None
    vcfc: int = 0                       # счётчик виртуального канала (у TM — 8 бит, у AOS — он же счётчик)


@dataclass
class Разбор:
    вид: str
    длина: int
    начало: int
    кадры: List[Кадр] = field(default_factory=list)
    fecf: Optional[bool] = None
    fecf_верна: int = 0
    пропущено: int = 0
    пакеты: List[bytes] = field(default_factory=list)
    неполных: int = 0


def _кадры(данные: bytes, длина: int, начало: int, вид: str, fecf: bool) -> List[Кадр]:
    итог = []
    for м in range(начало, len(данные) - длина + 1, длина):
        к = данные[м:м + длина]
        конец = длина - (2 if fecf else 0)
        if вид == "TM":
            слово = int.from_bytes(к[:2], "big")
            версия, scid, vcid, ocf = слово >> 14, (слово >> 4) & 0x3FF, (слово >> 1) & 7, слово & 1
            состояние = int.from_bytes(к[4:6], "big")
            вторичный = состояние >> 15
            начало_данных = 6
            if вторичный:
                начало_данных += 1 + (к[6] & 0x3F)          # длина вторичного заголовка − 1
            clcw = int.from_bytes(к[конец - 4:конец], "big") if ocf else None
            итог.append(Кадр(версия, scid, vcid, к[2], bool(ocf), состояние & 0x7FF,
                             к[начало_данных:конец - (4 if ocf else 0)], clcw, к[3]))
        else:                                               # AOS: M_PDU после заголовка 6 байт
            слово = int.from_bytes(к[:2], "big")
            версия, scid, vcid = слово >> 14, (слово >> 6) & 0xFF, слово & 0x3F
            счёт = int.from_bytes(к[2:5], "big")
            итог.append(Кадр(версия, scid, vcid, счёт, False,
                             int.from_bytes(к[6:8], "big") & 0x7FF, к[8:конец], None, счёт))
        if len(итог) >= КАДРОВ_ДО:
            break
    return итог


def _пакеты(кадры: List[Кадр], р: Разбор, модуль: int) -> None:
    """Space Packet подряд по каждому виртуальному каналу: начало — по FHP, продолжение — через кадры.

    Пропущенный кадр канала (счётчик VCFC прыгнул) рвёт пакет: сборка ждёт следующего FHP."""
    буферы: Dict[int, Optional[bytearray]] = {}
    счётчики: Dict[int, int] = {}
    for к in кадры:
        if к.vcid in счётчики and (к.vcfc - счётчики[к.vcid]) % модуль != 1:
            буферы[к.vcid] = None
        счётчики[к.vcid] = к.vcfc
        if к.fhp == 0x7FE:                                  # только заполнение
            continue
        буфер = буферы.get(к.vcid)
        if буфер is None:
            if к.fhp is None or к.fhp >= len(к.данные):      # 0x7FF — начала пакета в кадре нет
                continue                                    # ждём кадр с началом пакета
            буфер = bytearray(к.данные[к.fhp:])
        else:
            буфер += к.данные
        while len(буфер) >= 6:
            длина = int.from_bytes(буфер[4:6], "big") + 7
            if (буфер[0] >> 5) != 0:
                р.неполных += 1                              # версия не 000 — потеряли разметку
                буфер = None
                break
            if len(буфер) < длина:
                break
            р.пакеты.append(bytes(буфер[:длина]))
            del буфер[:длина]
        буферы[к.vcid] = буфер


def _заголовки_годны(данные: bytes, р: Разбор) -> bool:
    """Без FECF — заголовки должны быть как у CCSDS почти во всех кадрах: SCID один, FHP в
    пределах поля данных (или 0x7FF/0x7FE); у TM при флаге синхронизации 0 длина сегмента — 11
    (132.0-B 4.1.2.7.5)."""
    scid = Counter(к.scid for к in р.кадры).most_common(1)[0][0]
    годных = 0
    for н, к in enumerate(р.кадры):
        годен = к.scid == scid and (к.fhp in (0x7FE, 0x7FF) or к.fhp < len(к.данные))
        if р.вид == "TM":
            состояние = int.from_bytes(данные[р.начало + н * р.длина + 4:р.начало + н * р.длина + 6], "big")
            годен = годен and ((состояние >> 14) & 1 or (состояние >> 11) & 3 == 3)
        годных += годен
    return годных >= 0.9 * len(р.кадры)


def разобрать(данные: bytes) -> Optional[Разбор]:
    найдено = счётчик_кадров(данные)
    if найдено is None:
        return None
    длина, место, _ = найдено
    # TM: счётчик MCFC — третий байт; AOS: младший байт VCFC — пятый. Решает версия в заголовке.
    # Сперва AOS: у настоящего TM на месте «версии» AOS — FECF прошлого кадра (01 — в четверти
    # кадров), а у настоящего AOS на месте версии TM — старший байт VCFC, почти всегда 00.
    for вид, смещение, версия in (("AOS", 4, 1), ("TM", 2, 0)):  # noqa: B007 — вид нужен после цикла
        начало = (место - смещение) % длина
        первые = [данные[м] >> 6 for м in range(начало, min(len(данные), начало + 32 * длина), длина)]
        if первые and sum(в == версия for в in первые) >= 0.9 * len(первые):
            break
    else:
        return None
    # FECF: CRC-16 последних двух байт кадра по всему кадру.
    пробные = [данные[м:м + длина] for м in range(начало, min(len(данные) - длина + 1, начало + 32 * длина), длина)]
    верных = sum(crc16_ccitt(к[:-2]) == int.from_bytes(к[-2:], "big") for к in пробные)
    fecf = верных >= 0.5 * len(пробные)
    р = Разбор(вид, длина, начало, fecf=fecf)
    р.кадры = _кадры(данные, длина, начало, вид, fecf)
    if not р.кадры or not fecf and not _заголовки_годны(данные, р):
        return None
    if fecf:
        р.fecf_верна = sum(crc16_ccitt(данные[м:м + длина - 2]) == int.from_bytes(данные[м + длина - 2:м + длина], "big")
                           for м in range(начало, начало + len(р.кадры) * длина, длина))
    модуль = 256 if вид == "TM" else 1 << 24
    предыдущий: Dict[int, int] = {}
    for к in р.кадры:
        ключ = -1 if вид == "TM" else к.vcid                 # у TM MCFC общий для всех VC
        if ключ in предыдущий:
            р.пропущено += (к.счётчик - предыдущий[ключ] - 1) % модуль
        предыдущий[ключ] = к.счётчик
    _пакеты(р.кадры, р, модуль)
    return р


def найти(данные: bytes) -> Optional[Находка]:
    р = разобрать(данные)
    if р is None:
        return None
    scid = Counter(к.scid for к in р.кадры).most_common(1)[0][0]
    vc = Counter(к.vcid for к in р.кадры)
    подробно = [
        f"кадр {р.длина} байт с байта {р.начало}; SCID {scid} (0x{scid:X}); виртуальные каналы: "
        + ", ".join(f"VC {в}×{с}" for в, с in sorted(vc.items())),
        f"кадров {len(р.кадры)}; пропущено по счётчику {'MCFC' if р.вид == 'TM' else 'VCFC'}: {р.пропущено}",
    ]
    if р.fecf:
        подробно.append(f"FECF (CRC-16 CCITT) верна у {р.fecf_верна} из {len(р.кадры)} кадров")
    else:
        подробно.append("FECF нет (или не сходится): кадр без CRC-16")
    clcw = [к.clcw for к in р.кадры if к.clcw is not None]
    if clcw:
        c = Counter(clcw).most_common(1)[0][0]
        подробно.append(f"OCF — CLCW: VC {(c >> 18) & 0x3F}, отчёт FARM-B {c & 0xFF}, "
                        f"нет РЧ {(c >> 15) & 1}, нет битовой синхронизации {(c >> 14) & 1}, "
                        f"блокировка {(c >> 13) & 1}, ожидание {(c >> 12) & 1}, повтор {(c >> 11) & 1}")
    заполнение = sum(1 for к in р.кадры if к.fhp == 0x7FE)
    if заполнение:
        подробно.append(f"кадров только с заполнением (FHP 0x7FE): {заполнение}")
    if р.пакеты:
        apid = Counter(int.from_bytes(п[:2], "big") & 0x7FF for п in р.пакеты)
        подробно.append(f"Space Packet: {len(р.пакеты)}; APID: " + ", ".join(
            f"{a}{' (заполнение)' if a == 0x7FF else ''}×{с}" for a, с in apid.most_common(8))
            + (f"; разметка потеряна {р.неполных} раз" if р.неполных else ""))
    return Находка(
        уровень="канальный", что=f"CCSDS {р.вид}: кадры канала передачи данных"
        + (" и Space Packet" if р.пакеты else ""),
        уверенность=(р.fecf_верна / len(р.кадры)) if р.fecf else 0.9,
        мера=f"счётчик кадров растёт на 1 от кадра к кадру по {р.длина} байт"
             + (f"; FECF верна у {р.fecf_верна} из {len(р.кадры)}" if р.fecf else ""),
        подробно=подробно, дальше=р.пакеты or None, вид_дальше="кадры" if р.пакеты else "")
