"""Периодическая вставка известных бит (пилот-символы): период, места, значения — и её вырезание.

Модем вставляет в поток известные символы через равные промежутки: пилот QPSK «11» — 2 бита через
каждые 126 бит данных (период 128), пилот-блоки, опорные символы. Синхрослово кадра — тоже известные
биты, но оно одно на кадр и длинное; вставка — короткая и частая: несколько бит на период в десятки и
сотни бит, и периодов в кадре много. Пока вставка в потоке, кадр в ней не той длины (16 896 вместо
16 632), а слова кода порваны каждые P бит — поэтому вставку вырезают первой.

Поиск:

1. **В кадре.** Цикл найден (синхрослово и длина L): поток складывается по делителям P длины L, при
   которых на кадр приходится не меньше ПОВТОРОВ_ОТ периодов, — от меньших P. Место, где бит почти во
   всех периодах один и тот же (не реже ПОСТОЯННО_ОТ: ошибки линии допускаются), — вставка; таких мест
   от 1 до БИТ_ДО и не больше доли ДОЛЯ_ДО периода, остальные места периода — живые данные. Синхрослово
   при свёртке по P < L постоянным не выходит: оно лишь в одном периоде из L/P.
2. **Без кадра** — сам найденный «цикл» короткий и с горсткой постоянных бит (не больше САМА_БИТ_ДО):
   это не кадр с синхрословом, а пилоты.
3. **Сплошной поток** (``найти``): кандидаты P — пики автокорреляции (перекос бит через P — от вставки),
   проверка — той же свёрткой, со строгим пределом САМА_БИТ_ДО.

Вырезание — по местам периода от начала потока (фаза та же, что у выборки). Ошибки на местах вставки —
оценка BER линии: значения там известны.
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

from .nahodka import Находка

#: Период вставки, бит: не короче и не длиннее (сплошной поток).
ПЕРИОД_ОТ = 16
ПЕРИОД_ДО = 4096
#: Мест вставки в периоде — не больше (в кадре: до трёх символов QPSK или двух 8PSK; канальный интервал
#: мультиплексора с постоянным заполнением — 8 бит — вставкой не считается) и доля периода — не больше.
БИТ_ДО = 6
ДОЛЯ_ДО = 1 / 16
#: Без кадра (сам «цикл» — вставка, или сплошной поток) — мест не больше: короткое синхрослово кадра
#: (8 бит и длиннее) вставкой не считается.
САМА_БИТ_ДО = 4
#: Место известно, если бит в нём совпадает не меньше чем в такой доле периодов.
ПОСТОЯННО_ОТ = 0.97
#: Периодов вставки в кадре — не меньше (иначе это поле кадра, а не вставка).
ПОВТОРОВ_ОТ = 8
#: Периодов в выборке для решения — не меньше.
ПЕРИОДОВ_ОТ = 64
#: Остальные места периода — данные: среднее совпадение по ним меньше этого (не постоянный поток).
ЖИВЫЕ_ДО = 0.9
#: Участков вставки в периоде — не больше (символ, пара символов…).
УЧАСТКОВ_ДО = 4
#: Выборка для поиска, бит.
ВЫБОРКА = 1 << 22
#: Пик автокорреляции — во столько «сигм» шума.
ПОРОГ_СИГМ = 8.0
КАНДИДАТОВ = 24


@dataclass
class Вставка:
    период: int
    места: tuple[int, ...]           # места в периоде от начала потока
    значения: str                    # биты на этих местах
    согласие: float                  # наименьшая доля периодов, где бит на месте совпал
    ошибок: float                    # доля ошибок на местах вставки — оценка BER линии
    периодов: int                    # по скольким периодам выборки

    @property
    def бит(self) -> int:
        return len(self.места)

    def слой(self) -> str:
        """Ручной слой (стол, «снять»): «пилоты период P места a,b значения 11»."""
        return f"пилоты период {self.период} места {','.join(map(str, self.места))} значения {self.значения}"

    def участки(self) -> list[tuple[int, int]]:
        return _участки(np.isin(np.arange(self.период), self.места))


def _участки(маска: np.ndarray) -> list[tuple[int, int]]:
    м = np.concatenate([[False], np.asarray(маска, dtype=bool), [False]]).astype(np.int8)
    края = np.flatnonzero(np.diff(м))
    return [(int(a), int(b - a)) for a, b in zip(края[::2], края[1::2], strict=True)]


def проверить(биты: np.ndarray, P: int, *, бит_до: int = БИТ_ДО) -> Вставка | None:
    """Вставка с периодом P: места, где бит почти во всех периодах один и тот же, — или None."""
    if P < 2:
        return None
    строк = min(len(биты), ВЫБОРКА) // P
    if строк < ПЕРИОДОВ_ОТ:
        return None
    таблица = np.asarray(биты[:строк * P], dtype=np.uint8).reshape(строк, P)
    доля = таблица.mean(axis=0)
    согласие = np.maximum(доля, 1 - доля)
    постоянные = согласие >= ПОСТОЯННО_ОТ
    c = int(постоянные.sum())
    if not 1 <= c <= бит_до or c > max(1.0, ДОЛЯ_ДО * P):
        return None
    if float(согласие[~постоянные].mean()) >= ЖИВЫЕ_ДО:
        return None                      # поток почти постоянный — не вставка в данных
    if len(_участки(постоянные)) > УЧАСТКОВ_ДО:
        return None
    места = tuple(int(м) for м in np.flatnonzero(постоянные))
    значения = "".join("1" if доля[м] > 0.5 else "0" for м in места)
    return Вставка(P, места, значения, float(согласие[постоянные].min()),
                   float(1 - согласие[постоянные].mean()), строк)


def _делители(L: int) -> list[int]:
    return sorted({d for i in range(1, int(L ** 0.5) + 1) if L % i == 0 for d in (i, L // i)})


def в_цикле(биты: np.ndarray, L: int) -> Вставка | None:
    """Вставка внутри кадра длины L (период — делитель L, периодов в кадре не меньше ПОВТОРОВ_ОТ), или сам
    короткий «кадр» L с горсткой постоянных бит — пилоты, а не синхрослово."""
    if L < ПЕРИОД_ОТ:
        return None
    for P in _делители(L):
        if P < ПЕРИОД_ОТ or L // P < ПОВТОРОВ_ОТ:
            continue
        в = проверить(биты, P)
        if в is not None:
            return в
    if L <= ПЕРИОД_ДО:
        return проверить(биты, L, бит_до=САМА_БИТ_ДО)
    return None


def найти(биты: np.ndarray) -> Вставка | None:
    """Вставка в сплошном потоке: кандидаты — пики автокорреляции, от меньших периодов."""
    from . import cikl  # noqa: PLC0415
    x = np.asarray(биты[:ВЫБОРКА], dtype=np.uint8)
    if len(x) < ПЕРИОДОВ_ОТ * ПЕРИОД_ОТ * 4:
        return None
    до = min(ПЕРИОД_ДО, len(x) // ПЕРИОДОВ_ОТ)
    r = cikl.автокорреляция(x, до + 1)
    шум = 1.0 / np.sqrt(len(x))
    лаги = np.arange(ПЕРИОД_ОТ, до)
    пики = лаги[(r[лаги] >= ПОРОГ_СИГМ * шум) & (r[лаги] >= r[лаги - 1]) & (r[лаги] >= r[лаги + 1])]
    if not len(пики):
        return None
    пики = np.sort(пики[np.argsort(-r[пики])[:КАНДИДАТОВ]])
    for P in пики.tolist():
        в = проверить(x, P, бит_до=САМА_БИТ_ДО)
        if в is not None:
            return в
    return None


def маска(длина: int, в: Вставка) -> np.ndarray:
    """True — бит потока длины ``длина`` остаётся (не место вставки)."""
    оставить = np.ones(в.период, dtype=bool)
    оставить[list(в.места)] = False
    повторов = -(-длина // в.период)
    return np.tile(оставить, повторов)[:длина]


def снять(биты: np.ndarray, в: Вставка) -> np.ndarray:
    """Поток без вставки: места периода от начала потока вырезаны, остальное — подряд."""
    биты = np.asarray(биты, dtype=np.uint8)
    return np.ascontiguousarray(биты[маска(len(биты), в)])


def находка(в: Вставка, было: int, стало: int, *, кадр: int = 0) -> Находка:
    данных = в.период - в.бит
    уч = ", ".join(f"{н}…{н + д - 1}" if д > 1 else str(н) for н, д in в.участки())
    подробно = [
        f"период {в.период} бит: {в.бит} известных бит (места {уч}, значения {в.значения}) и {данных} бит данных"
        + (f" — пилот-символ{'ы' if в.бит > 2 else ''}" if в.бит <= 8 else ""),
        f"ошибок на местах вставки {в.ошибок:.1e} (оценка BER линии: значения там известны)",
        f"вставка вырезана: {было} → {стало} бит; кадр и код ищутся в потоке без неё",
        f"слой стола: «{в.слой()}»",
    ]
    if кадр:
        подробно.insert(1, f"вставка видна внутри кадра {кадр} бит ({кадр // в.период} периодов на кадр): "
                           f"без неё кадр — {кадр // в.период * данных} бит")
    return Находка(
        уровень="вставка",
        что=f"периодическая вставка известных бит: {в.бит} бит ({в.значения}) через каждые {в.период} "
            f"(места {уч}) — вырезана",
        уверенность=float(min(1.0, в.согласие)),
        мера=f"на {в.бит} местах периода бит один и тот же в {в.согласие * 100:.2f} % из {в.периодов} периодов; "
             f"остальные {данных} мест — данные",
        подробно=подробно, вид_дальше="биты",
        свойства={"период": в.период, "места": list(в.места), "значения": в.значения, "слой": в.слой(),
                  "ошибок": в.ошибок, "кадр": кадр})


def разобрать_слой(слова: str) -> Вставка:
    """«пилоты период 128 места 38,39 [значения 11]» → Вставка (для ручного снятия)."""
    import re  # noqa: PLC0415
    период = re.search(r"период\w*\s+(\d+)", слова)
    места = re.search(r"мест\w*\s+([\d,\s\-…]+)", слова)
    if период is None or места is None:
        raise ValueError("пилоты: «пилоты период P места a,b[,c…] [значения 11]» — места в периоде с нуля")
    P = int(период.group(1))
    список: list[int] = []
    for кусок in re.split(r"[,\s]+", места.group(1).strip()):
        if not кусок:
            continue
        if re.fullmatch(r"\d+[-…]\d+", кусок):
            a, b = (int(x) for x in re.split(r"[-…]", кусок))
            список += list(range(a, b + 1))
        elif кусок.isdigit():
            список.append(int(кусок))
    список = sorted(set(список))
    if P < 2 or not список or список[-1] >= P or len(список) >= P:
        raise ValueError(f"пилоты: места — от 0 до {P - 1}, не все места периода")
    значения = re.search(r"значени\w*\s+([01]+)", слова)
    return Вставка(P, tuple(список), значения.group(1) if значения else "", 1.0, 0.0, 0)
