"""F-LDPC (TrellisWare) — код, на котором построен Datum FlexLDPC: кодер, матрица проверок, схема передачи.

Всё — по тексту патента US 7,673,213 B2 (кодер 1500, абзацы (133)–(150)); таблицы (дизеры,
параметры перемежителя, J, шаблоны выкалывания) — в ``data/ldpc_fldpc.json``, построены из
текста патента сценарием ``istochniki/ldpc/proverki/postroit_fldpc.py`` и сверены с копиями в
US 7,958,425 B2. Что «Datum FlexLDPC основан на F-LDPC TrellisWare», сказано в White Paper Datum
(istochniki/ldpc/datum/Datum_FlexLDPC_White_Paper.pdf, стр. 2); стоят ли в модемах Datum именно
значения патента по умолчанию — не подтверждено (гипотеза, её и проверяет проба на потоке).

Кодер (K бит данных, K — 128…16384 из таблицы 39):

1. внешний код — 2-состоянийный, скорость 2/4, пары бит (b¹, b²) → четвёрка
   c = (b¹⊕s, b¹⊕s, b¹⊕b², b¹⊕b²), новое состояние s = b² (таблица 37); «хвост»: первая пара
   задаёт начальное состояние и подаётся в конце (абзац (136));
2. перемежитель DRP длиной 2K: v(i) = c(I_a(I_b(I_c(i)))), I_a(i) = 64⌊i/64⌋ + r(i mod 64),
   I_b(i) = (s + i·p) mod 2K, I_c(i) = 64⌊i/64⌋ + w(i mod 64) (абзац (137), таблицы 38–39);
3. проверка чётности по J бит (последняя группа — остаток < J бит, абзац (141));
4. аккумулятор с нулевым начальным состоянием, без завершения (таблица 41, абзац (145));
5. выкалывание чётности с периодом 32 по таблице 42 (P/16 оставленных, P = 8…16);
6. в канал — данные, затем оставшаяся чётность; перед модулятором — перемежение
   v_o(i) = v_p((1367·i) mod M) (абзацы (148)–(149)).

Матрица проверок: проверка m — p_m ⊕ p_{m−1} ⊕ (сумма выходов внешнего кода группы m), выход
внешнего кода — сумма двух бит данных; данные — первые K позиций, чётность — после них.
"""

from __future__ import annotations

import json
import re
from fractions import Fraction
from functools import lru_cache
from pathlib import Path

import numpy as np

ДАННЫЕ = Path(__file__).with_name("data") / "ldpc_fldpc.json"
#: Длины блока данных, для которых в патенте есть дизер и параметры перемежителя (таблицы 38–39).
РАЗМЕРЫ = (128, 256, 512, 1024, 2048, 4096, 8192, 16384)
#: Шаблоны выкалывания: оставлено P из 16 (таблица 42).
ДОЛИ = tuple(range(8, 17))
#: J «грубых» скоростей патента (таблица 40): r = J/(J + 2).
J_ПАТЕНТА = (2, 4, 8, 16, 32)
#: Datum FlexLDPC (M7, PSM-500): блоки 256…16k, семь скоростей (White Paper, стр. 3; M7 IOM стр. 32–34).
#: Скорость → варианты (J, P) кода патента с этой скоростью: у 3/4, 7/8, 10/11 выкалыванием из таблицы 42
#: не получить — J = 6, 14, 20 без выкалывания (J программируется, абзац (141)); 14/17 не ложится ни
#: в одно целое J — вариантов нет (гипотеза, не факт: какие J и P стоят в модеме, не опубликовано).
DATUM_БЛОКИ = (256, 512, 1024, 2048, 4096, 8192, 16384)
DATUM_СКОРОСТИ = {"1/2": ((2, 16),), "2/3": ((4, 16),), "3/4": ((6, 16),), "14/17": (),
                  "7/8": ((14, 16),), "10/11": ((20, 16),), "16/17": ((32, 16),)}
#: Datum M7XC LDPC-Gen2: блоки 2k…16k (MIB DATUM-M7XC-MODEM-MIB, rxLdpcBlock), 12 скоростей
#: (rxLdpcModcod) — все ложатся в семейство r/(r + p(1 − r)) кодера 1500 (сверка sverka_fldpc.py).
GEN2_БЛОКИ = (2048, 4096, 8192, 16384)
GEN2_СКОРОСТИ = ("1/2", "8/15", "4/7", "8/13", "2/3", "16/23", "8/11", "16/21", "4/5", "16/19", "8/9", "16/17")


@lru_cache(maxsize=1)
def таблицы() -> dict:
    return json.loads(ДАННЫЕ.read_text(encoding="utf-8"))


def скорость(J: int, P: int = 16) -> Fraction:
    """Номинальная скорость r_p = r/(r + p(1 − r)), r = J/(J + 2), p = P/16 (абзац (115))."""
    r, p = Fraction(J, J + 2), Fraction(P, 16)
    return r / (r + p * (1 - r))


def равносильный(K: int, J: int, P: int) -> tuple[int, int]:
    """(J, P) без лишнего выкалывания: при P = 8 (оставлен каждый второй бит чётности, шаблон 0101…)
    аккумулятор после J бит даёт в оставленных битах то же, что без выкалывания после 2J бит, —
    слова кодов (J, 8/16) и (2J, 16/16) совпадают (абзац (175) патента: SPC и выкалывание «обмениваются»),
    если 2K делится на 2J."""
    if P == 8 and (2 * K) % (2 * J) == 0:
        return 2 * J, 16
    return J, P


def варианты_скорости(скорость_: Fraction | str, J_из=J_ПАТЕНТА, K: int = 16384) -> list[tuple[int, int]]:
    """Разные коды патента со скоростью ``скорость_``: J из ``J_из``, P = 8…16; равносильные
    (J, 8) и (2J, 16) — одним вариантом (без выкалывания)."""
    цель = Fraction(скорость_)
    итог: list[tuple[int, int]] = []
    for J in J_из:
        for P in reversed(ДОЛИ):
            if скорость(J, P) == цель and равносильный(K, J, P) not in итог:
                итог.append(равносильный(K, J, P))
    return итог


def имя(K: int, J: int, P: int = 16) -> str:
    return f"fldpc-k{K}-j{J}-p{P}"


def разобрать_имя(имя_: str) -> tuple[int, int, int] | None:
    """«fldpc-k1024-j4-p12» → (1024, 4, 12); не F-LDPC или вне таблиц патента — None."""
    м = re.fullmatch(r"fldpc-k(\d+)-j(\d+)-p(\d+)", (имя_ or "").lower())
    if not м:
        return None
    K, J, P = (int(x) for x in м.groups())
    if K not in РАЗМЕРЫ or not 2 <= J <= 64 or P not in ДОЛИ:
        return None
    return K, J, P


@lru_cache(maxsize=16)
def перемежитель(K: int) -> np.ndarray:
    """π длиной 2K: v_out(i) = c(π(i)) (DRP, абзац (137))."""
    т = таблицы()
    if str(K) not in т["p_s"]:
        raise ValueError(f"F-LDPC: для K = {K} в патенте нет параметров перемежителя (есть {РАЗМЕРЫ})")
    p, s = т["p_s"][str(K)]
    r, w = np.array(т["r"]), np.array(т["w"][str(K)])
    n = 2 * K
    i = np.arange(n)
    Ia = 64 * (i // 64) + r[i % 64]
    Ib = (s + i * p) % n
    Ic = 64 * (i // 64) + w[i % 64]
    return Ia[Ib[Ic]]


def _выход_внешнего(K: int) -> tuple[np.ndarray, np.ndarray]:
    """Для каждого из 2K выходов внешнего кода — два номера бит данных, сумма которых он есть."""
    пар = K // 2
    q = (np.arange(пар) + 1) % пар                     # четвёрка k — от пары k + 1 (первая — в конце)
    b1, b2, пред = 2 * q, 2 * q + 1, (2 * q - 1) % K   # состояние — второй бит предыдущей пары
    a = np.stack([b1, b1, b1, b1], axis=1).reshape(-1)
    b = np.stack([пред, пред, b2, b2], axis=1).reshape(-1)
    return a, b


def групп(K: int, J: int) -> int:
    return -(-2 * K // J)


def кодировать(данные: np.ndarray, J: int, P: int = 16, *, канал: bool = False) -> np.ndarray:
    """Слово в потоке: K бит данных, затем оставленная чётность; ``канал`` — перемежение 1367."""
    u = np.asarray(данные, dtype=np.uint8) & 1
    K = len(u)
    a, b = _выход_внешнего(K)
    c = u[a] ^ u[b]
    v = c[перемежитель(K)]
    L = групп(K, J)
    d = np.zeros(L, dtype=np.uint8)
    np.bitwise_xor.at(d, np.arange(2 * K) // J, v)
    чётность = np.bitwise_xor.accumulate(d)
    слово = np.concatenate([u, чётность[оставлены(L, P)]])
    return слово[порядок_канала(len(слово))] if канал else слово


def оставлены(L: int, P: int) -> np.ndarray:
    """Номера оставленных бит чётности (таблица 42, период 32)."""
    шаблон = np.array([ч == "1" for ч in таблицы()["выкалывание"][str(P)]])
    return np.flatnonzero(шаблон[np.arange(L) % 32])


def порядок_канала(M: int) -> np.ndarray:
    """Перемежение перед модулятором: i-й бит в канале — бит (1367·i) mod M слова (абзац (149))."""
    шаг = int(таблицы()["перемежение_канала"])
    if np.gcd(шаг, M) != 1:
        raise ValueError(f"перемежение {шаг}·i mod {M}: не перестановка")
    return (шаг * np.arange(M, dtype=np.int64)) % M


@lru_cache(maxsize=24)
def матрица(K: int, J: int):
    """Матрица проверок (ldpc.Матрица): n = K + ⌈2K/J⌉, данные — первые K позиций."""
    from . import ldpc  # noqa: PLC0415 — ldpc зовёт ldpc_std, тот — этот модуль
    a, b = _выход_внешнего(K)
    π = перемежитель(K)
    L = групп(K, J)
    ряд = np.arange(2 * K) // J
    # Сумма по модулю 2: одинаковые (строка, бит данных) сокращаются.
    ключ = np.concatenate([ряд * K + a[π], ряд * K + b[π]])
    значения, раз = np.unique(ключ, return_counts=True)
    значения = значения[раз % 2 == 1]
    строка = np.concatenate([значения // K, np.arange(L), np.arange(1, L)])
    столбец = np.concatenate([значения % K, K + np.arange(L), K + np.arange(L - 1)])
    м = ldpc._по_строкам(K + L, L, строка, столбец,
                         f"F-LDPC TrellisWare (US 7,673,213), K = {K}, J = {J}")
    м.данные = np.arange(K, dtype=np.int64)
    return м


def выколоты(K: int, J: int, P: int) -> np.ndarray:
    L = групп(K, J)
    остались = np.zeros(L, dtype=bool)
    остались[оставлены(L, P)] = True
    return K + np.flatnonzero(~остались)


def схема(K: int, J: int, P: int = 16, *, канал: bool = False):
    """Схема передачи (ldpc.Схема): выколотая чётность, при ``канал`` — перемежение 1367."""
    from . import ldpc  # noqa: PLC0415
    # (J, 8/16) — то же слово, что (2J, 16/16): декодировать без стёртых позиций надёжнее.
    J, P = равносильный(K, J, P)
    м = матрица(K, J)
    с = ldpc.Схема(м, выколоты(K, J, P), np.array([], dtype=np.int64))
    if канал:
        с = ldpc.Схема(м, с.выколоты, с.укорочены, с.переданы[порядок_канала(с.длина)])
    return с


def datum() -> list[dict[str, object]]:
    """Режимы Datum (FlexLDPC M7/PSM-500 и LDPC-Gen2 M7XC) → коды патента: блок, скорость, (J, P)."""
    итог = []
    for K in DATUM_БЛОКИ:
        for ск, варианты in DATUM_СКОРОСТИ.items():
            итог.append({"модем": "Datum FlexLDPC (M7, PSM-500)", "K": K, "скорость": ск,
                         "варианты": [имя(K, J, P) for J, P in варианты]})
    for K in GEN2_БЛОКИ:
        for ск in GEN2_СКОРОСТИ:
            итог.append({"модем": "Datum M7XC LDPC-Gen2", "K": K, "скорость": ск,
                         "варианты": [имя(K, J, P) for J, P in варианты_скорости(ск, K=K)]})
    return итог


def имена_datum() -> list[str]:
    """Все коды патента, которыми могут быть режимы Datum (без повторов, в порядке блоков)."""
    итог: list[str] = []
    for р in datum():
        for и in р["варианты"]:
            if и not in итог:
                итог.append(и)
    return итог
