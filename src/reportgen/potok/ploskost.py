# -*- coding: utf-8 -*-
"""Модуляционная плоскость: какие метки у символов КАМ на самом деле.

Демодулятор КАМ-M (k = log2 M бит на символ) выдаёт метки, но истинную
плоскость он знает лишь с точностью до симметрий созвездия: несущая
восстанавливается с неоднозначностью поворота на 90°, спектр может быть
инвертирован (отражение), а в выходном слове неизвестны порядок бит,
расположение I и Q (половинами или вперемешку) и код меток (Грей или
натуральный). Аналитик перебирает это вручную, пока не «проявится»
скремблер. Здесь перебор тот же, но автоматический:

- метка → индексы уровней по I и по Q (при заданной раскладке и коде);
- симметрия квадрата (8 штук: 4 поворота × отражение) — над индексами:
  отрицание уровня m → M' − 1 − m, поворот на 90° — (I, Q) → (−Q, I);
- обратно в метку в том же коде.

Для ФМ-M (M = 2^k точек на окружности) симметрии другие — повороты на
2π/M и отражение: над номером точки на окружности n → (±n + r) mod M, в
коде Грея (по окружности) или натуральном. Для прочих созвездий (APSK,
крестовые КАМ) — ручные операции над символом: перестановка меток и
перестановка бит внутри символа (см. ``переставить_метки``, ``переставить_биты``).

Каждый вариант — гипотеза; какой верный, решает то, что под ним
открывается (скремблер, код, цикл) — это делает дерево гипотез разбора.
Здесь же — быстрый отбор: по линейной сложности окон (Берлекэмп — Мэсси) и
проверкам Уолша — Адамара, чтобы в дерево шли лучшие несколько вариантов,
а не все 64.
"""

from __future__ import annotations

import re
import time
from itertools import permutations, product
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from . import skrembler, tpc
from .kod import проверки
from .nahodka import Находка

ВЫБОРКА = 1 << 17


def _в_грей(x: np.ndarray) -> np.ndarray:
    return x ^ (x >> 1)


def _из_грея(g: np.ndarray, бит: int) -> np.ndarray:
    x = g.copy()
    сдвиг = 1
    while сдвиг < бит:
        x ^= x >> сдвиг
        сдвиг <<= 1
    return x


def _символы(биты: np.ndarray, k: int, порядок: str) -> np.ndarray:
    сколько = len(биты) // k
    блоки = биты[:сколько * k].reshape(сколько, k).astype(np.int64)
    if порядок == "младший":
        блоки = блоки[:, ::-1]
    веса = 1 << np.arange(k - 1, -1, -1)
    return (блоки * веса).sum(axis=1)


def _в_биты(символы: np.ndarray, k: int, порядок: str) -> np.ndarray:
    биты = ((символы[:, None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8)
    if порядок == "младший":
        биты = биты[:, ::-1]
    return биты.reshape(-1)


def _разложить(символы: np.ndarray, k: int, раскладка: str) -> Tuple[np.ndarray, np.ndarray]:
    h = k // 2
    if раскладка == "половинами":
        return символы >> h, символы & ((1 << h) - 1)
    # Вперемешку: I0 Q0 I1 Q1 … (старшие биты первыми).
    i = np.zeros_like(символы)
    q = np.zeros_like(символы)
    for j in range(h):
        i |= ((символы >> (k - 1 - 2 * j)) & 1) << (h - 1 - j)
        q |= ((символы >> (k - 2 - 2 * j)) & 1) << (h - 1 - j)
    return i, q


def _сложить(i: np.ndarray, q: np.ndarray, k: int, раскладка: str) -> np.ndarray:
    h = k // 2
    if раскладка == "половинами":
        return (i << h) | q
    символы = np.zeros_like(i)
    for j in range(h):
        символы |= ((i >> (h - 1 - j)) & 1) << (k - 1 - 2 * j)
        символы |= ((q >> (h - 1 - j)) & 1) << (k - 2 - 2 * j)
    return символы


#: Симметрии квадрата над индексами уровней (i, q), уровни 0…L−1.
СИММЕТРИИ = {
    "без поворота": lambda i, q, L: (i, q),
    "поворот 90°": lambda i, q, L: (L - 1 - q, i),
    "поворот 180°": lambda i, q, L: (L - 1 - i, L - 1 - q),
    "поворот 270°": lambda i, q, L: (q, L - 1 - i),
    "отражение по I": lambda i, q, L: (i, L - 1 - q),
    "отражение по Q": lambda i, q, L: (L - 1 - i, q),
    "обмен I и Q": lambda i, q, L: (q, i),
    "обмен с поворотом": lambda i, q, L: (L - 1 - q, L - 1 - i),
}


def преобразовать(биты: np.ndarray, k: int, *, порядок: str, раскладка: str, код: str,
                  симметрия: str) -> np.ndarray:
    """Применить один вариант плоскости к потоку меток."""
    h = k // 2
    L = 1 << h
    символы = _символы(биты, k, порядок)
    i, q = _разложить(символы, k, раскладка)
    if код == "Грей":
        i, q = _из_грея(i, h), _из_грея(q, h)
    i, q = СИММЕТРИИ[симметрия](i, q, L)
    if код == "Грей":
        i, q = _в_грей(i), _в_грей(q)
    return _в_биты(_сложить(i, q, k, раскладка), k, порядок)


def варианты(k: int) -> List[Dict[str, str]]:
    итог = []
    for порядок, раскладка, код, симметрия in product(
            ("старший", "младший"), ("половинами", "вперемешку"), ("Грей", "натуральный"),
            СИММЕТРИИ):
        if симметрия == "без поворота":
            continue                     # тождественное — это сам поток
        итог.append({"порядок": порядок, "раскладка": раскладка, "код": код,
                     "симметрия": симметрия})
    return итог


# -- ФМ: точки на окружности ------------------------------------------------------------

def преобразовать_фм(биты: np.ndarray, k: int, *, порядок: str, код: str, поворот: int,
                     отражение: bool, метка: Optional[Sequence[int]] = None,
                     код_выход: Optional[str] = None) -> np.ndarray:
    """ФМ-2^k: номер точки n → (±n + поворот) mod M; метка — Грей по окружности или натуральная.

    ``метка`` — перестановка бит в метке (бит i метки — бит метка[i] кода):
    демодулятор и модулятор могут по-разному нумеровать биты символа, и
    тогда поворот в коде Грея не тот — без перестановки его не найти.
    ``код_выход`` — код меток на выходе, если он не тот, что у демодулятора:
    демодулятор отдаёт номер точки натуральным кодом («машинный»), а модем
    нумеровал точки кодом Грея («Turbo» у Comtech: 0, 1, 3, 2, 6, 7, 5, 4 по
    окружности) — и наоборот.
    """
    M = 1 << k
    символы = _символы(биты, k, порядок)
    if метка is not None:
        символы = _переставить_метку(символы, k, _обратная(метка))
    n = _из_грея(символы, k) if код == "Грей" else символы
    n = ((-n if отражение else n) + поворот) % M
    метки = _в_грей(n) if (код_выход or код) == "Грей" else n
    if метка is not None:
        метки = _переставить_метку(метки, k, метка)
    return _в_биты(метки, k, порядок)


def _обратная(перестановка: Sequence[int]) -> List[int]:
    обратная = [0] * len(перестановка)
    for i, j in enumerate(перестановка):
        обратная[j] = i
    return обратная


def _переставить_метку(символы: np.ndarray, k: int, откуда: Sequence[int]) -> np.ndarray:
    """Бит i новой метки (0 — старший) — бит откуда[i] старой."""
    итог = np.zeros_like(символы)
    for i, j in enumerate(откуда):
        итог |= ((символы >> (k - 1 - j)) & 1) << (k - 1 - i)
    return итог


#: До скольких бит на символ перебираются все перестановки бит метки (k! штук).
ПЕРЕСТАНОВКИ_ДО = 3


def варианты_фм(k: int) -> List[Dict[str, object]]:
    """Все различные варианты: поворот × отражение × коды меток × перестановка бит метки.

    Варианты с одинаковой таблицей перекодировки меток — один вариант (в коде
    Грея часть поворотов с перестановкой совпадают), тождественный — не вариант.
    """
    M = 1 << k
    перестановки = (list(permutations(range(k))) if k <= ПЕРЕСТАНОВКИ_ДО
                    else [tuple(range(k)), tuple(range(k - 1, -1, -1))])
    итог, было = [], {tuple(range(M))}
    метки = _в_биты(np.arange(M), k, "старший")
    for (код, выход), метка, поворот, отражение in product(
            (("Грей", "Грей"), ("натуральный", "натуральный"), ("натуральный", "Грей"),
             ("Грей", "натуральный")), перестановки, range(M), (False, True)):
        вариант = {"порядок": "старший", "код": код, "поворот": поворот, "отражение": отражение,
                   "метка": list(метка)}
        if выход != код:
            вариант["код_выход"] = выход
        таблица = tuple(_символы(преобразовать_фм(метки, k, **вариант), k, "старший").tolist())
        if таблица in было:
            continue
        было.add(таблица)
        итог.append(вариант)
    return итог


def имя_фм(вариант: Dict[str, object], k: int) -> str:
    градусы = вариант["поворот"] * 360 / (1 << k)
    метка = вариант.get("метка")
    перестановка = (f", биты метки {'-'.join(map(str, метка))}"
                    if метка is not None and list(метка) != list(range(k)) else "")
    код = вариант["код"] if not вариант.get("код_выход") else f"{вариант['код']} → {вариант['код_выход']}"
    return (f"поворот {вариант['поворот']} ({градусы:g}°)"
            f"{', отражение' if вариант['отражение'] else ''}, {код}{перестановка}, "
            f"{вариант['порядок']} бит первым")


# -- ручные операции над символом --------------------------------------------------------------

def переставить_метки(биты: np.ndarray, k: int, таблица: List[int], порядок: str = "старший"
                      ) -> np.ndarray:
    """Метка v → таблица[v]: любая перестановка меток (APSK, крестовые КАМ, своё)."""
    M = 1 << k
    if sorted(таблица) != list(range(M)):
        raise ValueError(f"таблица меток — перестановка чисел 0…{M - 1} (все по одному разу)")
    символы = _символы(биты, k, порядок)
    return _в_биты(np.asarray(таблица, dtype=np.int64)[символы], k, порядок)


def переставить_биты(биты: np.ndarray, k: int, откуда: List[int]) -> np.ndarray:
    """Бит i нового символа — бит откуда[i] старого (0 — первый в потоке)."""
    if sorted(откуда) != list(range(k)):
        raise ValueError(f"перестановка бит символа — числа 0…{k - 1} по одному разу")
    сколько = len(биты) // k
    return биты[:сколько * k].reshape(сколько, k)[:, откуда].reshape(-1)


#: Строки кода произведения — до какой длины искать при подборе плоскости.
СТРОКА_ДО = 272


def _мера_кода(биты: np.ndarray) -> float:
    """Дешёвая часть меры: сила проверок кода на окне 12 бит и чётность строк TPC."""
    смещения, окон = проверки(биты[:1 << 16], 12, 1)
    смещения[0] = 0
    return max(float(np.abs(смещения).max()) * np.sqrt(окон),
               tpc.мера_строк(биты[:1 << 16], до=СТРОКА_ДО))


def _мера(биты: np.ndarray) -> float:
    """Мера «здесь проявилась структура»: отрыв скремблера, сила проверок кода
    на окне 12 бит и чётность строк кода произведения (TPC) до 272 бит."""
    return max(skrembler.отрыв(биты), _мера_кода(биты))


#: Если код виден дешёвой мерой — полная мера (со скремблером, ~0,5 с) только у стольких лучших.
ПОЛНАЯ_ЛУЧШИМ = 8


def _оценить(выборка: np.ndarray, варианты_: List[Dict[str, object]], преобразовать_,
             до: Optional[float] = None) -> Tuple[float, List[Tuple[float, Dict[str, object]]], int]:
    """(мера потока как есть, [(мера, вариант)] по убыванию, оценено полной мерой) — в две ступени.

    Полная мера дорога из-за скремблера, а вариантов у ФМ-8 — 331. Сперва
    дешёвая мера кода по всем; если какой-то вариант выделяется ею явно (код
    проявился), полная — только у лучших, иначе (кода нет, ищем скремблер) —
    у всех, лучшими по дешёвой мере вперёд. ``до`` — срок (time.monotonic):
    после него полная мера больше не считается.
    """
    база_кода = _мера_кода(выборка)
    ряды = [(в, преобразовать_(выборка, в)) for в in варианты_]
    дешёвые = sorted(((_мера_кода(р), i) for i, (_, р) in enumerate(ряды)), reverse=True)
    if дешёвые and дешёвые[0][0] >= max(12.0, 1.5 * база_кода, база_кода + 10):
        отбор = [i for _, i in дешёвые[:ПОЛНАЯ_ЛУЧШИМ]]
    else:
        отбор = [i for _, i in дешёвые]
    оценки = []
    for i in отбор:
        if до is not None and оценки and time.monotonic() > до:
            break
        оценки.append((_мера(ряды[i][1]), ряды[i][0]))
    оценки.sort(key=lambda о: о[0], reverse=True)
    return _мера(выборка), оценки, len(отбор)


def найти_фм(биты: np.ndarray, k: int, лучших: int = 3, *, бюджет: Optional[float] = None
            ) -> Находка | None:
    """Лучшие варианты плоскости ФМ-2^k (BPSK, QPSK, 8PSK, 16PSK…); ``бюджет`` — секунд на перебор."""
    if k < 1 or k > 6:
        return None
    выборка = биты[:ВЫБОРКА - ВЫБОРКА % k]
    все = варианты_фм(k)
    до = time.monotonic() + бюджет if бюджет is not None else None
    база, оценки, намечено = _оценить(выборка, все, lambda р, в: преобразовать_фм(р, k, **в), до)
    второй = оценки[1][0] if len(оценки) > 1 else 0.0
    # У ФМ-16 и выше неверный поворот сохраняет часть бит метки (в коде Грея
    # соседние точки отличаются одним битом), и скремблер виден и «как есть»,
    # только слабее: порог — заметный прирост, а не полуторный.
    if not оценки or оценки[0][0] < max(12.0, 1.2 * база, база + 10):
        return None
    дальше = {имя_фм(в, k): преобразовать_фм(биты[:len(биты) - len(биты) % k], k, **в)
              for _, в in оценки[:лучших]}
    return Находка(
        уровень="плоскость", что=f"модуляционная плоскость ФМ-{1 << k} подобрана",
        уверенность=min(1.0, оценки[0][0] / 50),
        мера=f"после преобразования скремблер (или код) выделяется на {оценки[0][0]:.0f} "
             f"разбросов; у потока как есть — {база:.0f}, у следующего варианта — {второй:.0f}",
        подробно=[f"перебрано вариантов: {len(все)} ({1 << k} поворотов × отражение × "
                  f"Грей/натуральный × перестановка бит метки; одинаковые таблицы меток — "
                  f"один вариант)" + (f"; код проявился у {намечено} лучших по дешёвой мере — "
                                      f"полная мера (со скремблером) только у них"
                                      if намечено < len(все) else "")
                  + (f"; полная мера — у {len(оценки)} из {намечено} (лучшие по дешёвой мере "
                     f"вперёд): кончилось время подбора" if len(оценки) < намечено else ""),
                  "лучшие: " + "; ".join(f"{имя} — {о[0]:.1f}"
                                         for имя, о in zip(дальше, оценки[:лучших]))],
        дальше=дальше, вид_дальше="варианты")


#: Сколько кадров смотреть при подборе плоскости по коду в кадрах.
КАДРОВ_ДЛЯ_ПЛОСКОСТИ = 32


def с_фазой(биты: np.ndarray, k: int, вариант: Dict[str, object], фаза: int) -> np.ndarray:
    """Поток от бита ``фаза`` (граница символа), преобразованный вариантом плоскости ФМ."""
    ряд = биты[фаза:]
    return преобразовать_фм(ряд[:len(ряд) - len(ряд) % k], k, **вариант)


def варианты_фм_в_кадрах(биты: np.ndarray, k: int, начала: Sequence[int], длина: int
                          ) -> List[Tuple[float, Dict[str, object], int]]:
    """Варианты плоскости ФМ-2^k с мерой строк кода в кадрах: [(мера, вариант, фаза)], лучшие первыми.

    Кадр модема начинается с синхрослова, а границы символов в файле
    неизвестны (фаза символа — 0…k−1 бит от начала файла): перебираются и
    фазы. Мера — tpc.мера_в_кадрах по первым кадрам. Пусто — ни один
    вариант не выделился против потока как есть.
    """
    from . import tpc  # noqa: PLC0415

    начала = [int(н) for н in начала][:КАДРОВ_ДЛЯ_ПЛОСКОСТИ]
    if len(начала) < 8:
        return []
    конец = min(len(биты), начала[-1] + длина + tpc.ДЛИНА_ДО + k)
    база = tpc.мера_в_кадрах(биты[:конец], начала, длина)
    классы = классы_по_инверсии(k) if длина % k == 0 else [[в] for в in варианты_фм(k)]
    оценки = []
    for фаза in range(k):
        участок = биты[фаза:конец]
        участок = участок[:len(участок) - len(участок) % k]
        свои = [н - фаза for н in начала if н >= фаза]
        for класс in классы:
            мера = tpc.мера_в_кадрах(преобразовать_фм(участок, k, **класс[0]), свои, длина)
            оценки += [(мера, вариант, фаза) for вариант in класс]
    оценки.sort(key=lambda о: -о[0])
    # Своя структура у потока бывает и без подбора (заполнение, служебные слова) —
    # вариант засчитывается, только если выделяется над ней с запасом.
    if not оценки or оценки[0][0] < база + max(tpc.ПОРОГ_Z, НАД_ИСХОДНЫМ * база):
        return []
    return оценки


#: Во сколько (долей) мера лучшего варианта должна превышать меру потока как есть.
НАД_ИСХОДНЫМ = 0.25


def классы_по_инверсии(k: int) -> List[List[Dict[str, object]]]:
    """Варианты меток ФМ-2^k, собранные в классы «отличаются лишь инверсией бит метки».

    Два варианта, у которых таблицы меток отличаются на постоянную x ⊕ c, дают
    в кадре длиной, кратной k, одинаковую меру чётности строк: инверсия
    переворачивает чётность окна на одном и том же месте всех кадров, и
    перекос (1 − 2p)² не меняется. Мера считается по одному варианту класса.
    """
    все = np.unpackbits(np.arange(1 << k, dtype=np.uint8)[:, None], axis=1)[:, 8 - k:].reshape(-1)
    классы: Dict[bytes, List[Dict[str, object]]] = {}
    for вариант in варианты_фм(k):
        образ = преобразовать_фм(все, k, **вариант).reshape(-1, k)
        классы.setdefault((образ ^ образ[0]).tobytes(), []).append(вариант)
    return list(классы.values())


def найти(биты: np.ndarray, k: int, лучших: int = 3, *, бюджет: Optional[float] = None
          ) -> Находка | None:
    """Лучшие варианты плоскости для k бит на символ — как варианты для дерева."""
    if k < 2 or k % 2 or k > 12:
        return None
    выборка = биты[:ВЫБОРКА - ВЫБОРКА % k]
    база = _мера(выборка)
    до = time.monotonic() + бюджет if бюджет is not None else None
    оценки = []
    for вариант in варианты(k):
        if до is not None and оценки and time.monotonic() > до:
            break
        ряд = преобразовать(выборка, k, **вариант)
        оценки.append((_мера(ряд), вариант))
    оценки.sort(key=lambda о: о[0], reverse=True)
    # Верный вариант выделяется вдвое и больше: у неверных скремблер не
    # проявляется, отрыв на уровне шума (единицы разбросов).
    второй = оценки[1][0] if len(оценки) > 1 else 0.0
    if not оценки or оценки[0][0] < max(12.0, 1.5 * база):
        return None
    дальше = {}
    for мера, вариант in оценки[:лучших]:
        имя = (f"{вариант['симметрия']}, {вариант['код']}, I/Q {вариант['раскладка']}, "
               f"{вариант['порядок']} бит первым")
        дальше[имя] = преобразовать(биты[:len(биты) - len(биты) % k], k, **вариант)
    return Находка(
        уровень="плоскость", что=f"модуляционная плоскость КАМ-{1 << k} подобрана",
        уверенность=min(1.0, оценки[0][0] / 50),
        мера=f"после преобразования скремблер (или код) выделяется на {оценки[0][0]:.0f} "
             f"разбросов; у потока как есть — {база:.0f}, у следующего варианта — {второй:.0f}",
        подробно=[f"перебрано вариантов: {len(оценки)} (8 симметрий квадрата × Грей/"
                  f"натуральный × раскладка I/Q × порядок бит)",
                  "лучшие: " + "; ".join(f"{list(дальше)[j]} — {оценки[j][0]:.1f}"
                                         for j in range(min(лучших, len(дальше))))],
        дальше=дальше, вид_дальше="варианты")


