# -*- coding: utf-8 -*-
"""Модуляционная плоскость: какие метки у символов КАМ на самом деле.

Демодулятор КАМ-M (k = log2 M бит на символ) выдаёт метки, но истинную
плоскость он знает лишь с точностью до симметрий созвездия: несущая
восстанавливается с неоднозначностью поворота на 90°, спектр может быть
инвертирован (отражение), а в выходном слове неизвестны порядок бит,
расположение I и Q (половинами или вперемешку) и код меток (Грей или
натуральный). Аналитик перебирает это вручную, пока не «проявится»
скремблер. Здесь перебор тот же, но автоматический:

- метка → индексы уровней по I и по Q (при заданной раскладке и коде);
- симметрия квадрата (8 штук: 4 поворота × отражение) — над индексами:
  отрицание уровня m → M' − 1 − m, поворот на 90° — (I, Q) → (−Q, I);
- обратно в метку в том же коде.

Каждый вариант — гипотеза; какой верный, решает то, что под ним
открывается (скремблер, код, цикл) — это делает дерево гипотез разбора.
Здесь же — быстрый отбор: по линейной сложности окон (Берлекэмп — Мэсси) и
проверкам Уолша — Адамара, чтобы в дерево шли лучшие несколько вариантов,
а не все 64.
"""

from __future__ import annotations

from itertools import product
from typing import Dict, List, Tuple

import numpy as np

from . import skrembler
from .kod import проверки
from .nahodka import Находка

ВЫБОРКА = 1 << 17


def _в_грей(x: np.ndarray) -> np.ndarray:
    return x ^ (x >> 1)


def _из_грея(g: np.ndarray, бит: int) -> np.ndarray:
    x = g.copy()
    сдвиг = 1
    while сдвиг < бит:
        x ^= x >> сдвиг
        сдвиг <<= 1
    return x


def _символы(биты: np.ndarray, k: int, порядок: str) -> np.ndarray:
    сколько = len(биты) // k
    блоки = биты[:сколько * k].reshape(сколько, k).astype(np.int64)
    if порядок == "младший":
        блоки = блоки[:, ::-1]
    веса = 1 << np.arange(k - 1, -1, -1)
    return (блоки * веса).sum(axis=1)


def _в_биты(символы: np.ndarray, k: int, порядок: str) -> np.ndarray:
    биты = ((символы[:, None] >> np.arange(k - 1, -1, -1)) & 1).astype(np.uint8)
    if порядок == "младший":
        биты = биты[:, ::-1]
    return биты.reshape(-1)


def _разложить(символы: np.ndarray, k: int, раскладка: str) -> Tuple[np.ndarray, np.ndarray]:
    h = k // 2
    if раскладка == "половинами":
        return символы >> h, символы & ((1 << h) - 1)
    # Вперемешку: I0 Q0 I1 Q1 … (старшие биты первыми).
    i = np.zeros_like(символы)
    q = np.zeros_like(символы)
    for j in range(h):
        i |= ((символы >> (k - 1 - 2 * j)) & 1) << (h - 1 - j)
        q |= ((символы >> (k - 2 - 2 * j)) & 1) << (h - 1 - j)
    return i, q


def _сложить(i: np.ndarray, q: np.ndarray, k: int, раскладка: str) -> np.ndarray:
    h = k // 2
    if раскладка == "половинами":
        return (i << h) | q
    символы = np.zeros_like(i)
    for j in range(h):
        символы |= ((i >> (h - 1 - j)) & 1) << (k - 1 - 2 * j)
        символы |= ((q >> (h - 1 - j)) & 1) << (k - 2 - 2 * j)
    return символы


#: Симметрии квадрата над индексами уровней (i, q), уровни 0…L−1.
СИММЕТРИИ = {
    "без поворота": lambda i, q, L: (i, q),
    "поворот 90°": lambda i, q, L: (L - 1 - q, i),
    "поворот 180°": lambda i, q, L: (L - 1 - i, L - 1 - q),
    "поворот 270°": lambda i, q, L: (q, L - 1 - i),
    "отражение по I": lambda i, q, L: (i, L - 1 - q),
    "отражение по Q": lambda i, q, L: (L - 1 - i, q),
    "обмен I и Q": lambda i, q, L: (q, i),
    "обмен с поворотом": lambda i, q, L: (L - 1 - q, L - 1 - i),
}


def преобразовать(биты: np.ndarray, k: int, *, порядок: str, раскладка: str, код: str,
                  симметрия: str) -> np.ndarray:
    """Применить один вариант плоскости к потоку меток."""
    h = k // 2
    L = 1 << h
    символы = _символы(биты, k, порядок)
    i, q = _разложить(символы, k, раскладка)
    if код == "Грей":
        i, q = _из_грея(i, h), _из_грея(q, h)
    i, q = СИММЕТРИИ[симметрия](i, q, L)
    if код == "Грей":
        i, q = _в_грей(i), _в_грей(q)
    return _в_биты(_сложить(i, q, k, раскладка), k, порядок)


def варианты(k: int) -> List[Dict[str, str]]:
    итог = []
    for порядок, раскладка, код, симметрия in product(
            ("старший", "младший"), ("половинами", "вперемешку"), ("Грей", "натуральный"),
            СИММЕТРИИ):
        if симметрия == "без поворота":
            continue                     # тождественное — это сам поток
        итог.append({"порядок": порядок, "раскладка": раскладка, "код": код,
                     "симметрия": симметрия})
    return итог


def _мера(биты: np.ndarray) -> float:
    """Мера «здесь проявилась структура»: отрыв скремблера и сила проверок кода."""
    смещения, окон = проверки(биты[:1 << 16], 12, 1)
    смещения[0] = 0
    return max(skrembler.отрыв(биты), float(np.abs(смещения).max()) * np.sqrt(окон))


def найти(биты: np.ndarray, k: int, лучших: int = 3) -> Находка | None:
    """Лучшие варианты плоскости для k бит на символ — как варианты для дерева."""
    if k < 2 or k % 2 or k > 12:
        return None
    выборка = биты[:ВЫБОРКА - ВЫБОРКА % k]
    база = _мера(выборка)
    оценки = []
    for вариант in варианты(k):
        ряд = преобразовать(выборка, k, **вариант)
        оценки.append((_мера(ряд), вариант))
    оценки.sort(key=lambda о: о[0], reverse=True)
    # Верный вариант выделяется вдвое и больше: у неверных скремблер не
    # проявляется, отрыв на уровне шума (единицы разбросов).
    второй = оценки[1][0] if len(оценки) > 1 else 0.0
    if not оценки or оценки[0][0] < max(12.0, 1.5 * база):
        return None
    дальше = {}
    for мера, вариант in оценки[:лучших]:
        имя = (f"{вариант['симметрия']}, {вариант['код']}, I/Q {вариант['раскладка']}, "
               f"{вариант['порядок']} бит первым")
        дальше[имя] = преобразовать(биты[:len(биты) - len(биты) % k], k, **вариант)
    return Находка(
        уровень="плоскость", что=f"модуляционная плоскость КАМ-{1 << k} подобрана",
        уверенность=min(1.0, оценки[0][0] / 50),
        мера=f"после преобразования скремблер (или код) выделяется на {оценки[0][0]:.0f} "
             f"разбросов; у потока как есть — {база:.0f}, у следующего варианта — {второй:.0f}",
        подробно=[f"перебрано вариантов: {len(оценки)} (8 симметрий квадрата × Грей/"
                  f"натуральный × раскладка I/Q × порядок бит)",
                  "лучшие: " + "; ".join(f"{list(дальше)[j]} — {оценки[j][0]:.1f}"
                                         for j in range(min(лучших, len(дальше))))],
        дальше=дальше, вид_дальше="варианты")
