"""Встроенные коды LDPC КНР: ABS-S, CMMB, DTMB, BeiDou — из первоисточников.

Данные — ``data/ldpc_kitay.json``, собираются скриптом
``istochniki/ldpc_kitay/proverki/sborka_kitay.py`` из файлов в ``istochniki/ldpc_kitay/``
(там же — откуда каждый файл и что сверено):

- **ABS-S** (先进卫星广播系统, спутниковое вещание КНР, «Чжунсин-9» и далее; стандарт
  GD/J 043—2011 в открытом доступе не найден): 10 кодов QC-LDPC длиной 15360, циркулянт
  32 × 32, базовые матрицы — приложения A–J патента CN101150730 (Академия радиовещания ГУРТ;
  то же семейство — US8689092 Availink). В стандарт, по открытым статьям, вошли 8 скоростей
  (1/2 … 9/10); данные — первые k бит слова (полезная нагрузка и CRC-32), проверочные — в конце;
- **CMMB** (GY/T 220.1-2006, мобильное ТВ): (9216, 4608) и (9216, 6912); по вектору COL_ORDER
  (прил. C, формула 10) проверочные лежат на COL_ORDER(0 … 9215 − K), данные — на остальных;
- **DTMB** (GB 20600-2006, наземное ТВ): (7493, 3048/4572/6096), в потоке 7488 бит — первые
  5 проверочных не передаются; данные — последние k бит слова;
- **BeiDou** (ICD B1C, B2a, PPP-B2b): 64-ричные LDPC над GF(2⁶) — здесь их двоичный образ:
  символ — 6 бит старшим вперёд, каждая проверка над GF(64) — 6 двоичных проверок.

Имена — как слово в слое: ``ldpc abs-s-15360-11520``, ``ldpc cmmb-9216-4608``.
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

import numpy as np

ДАННЫЕ = Path(__file__).with_name("data") / "ldpc_kitay.json"
#: GF(2⁶) с p(x) = 1 + x + x⁶ (ICD B1C, п. 6.2.2.2): вектор 1 — [000001].
МНОГОЧЛЕН_GF64 = 0b1000011


@lru_cache(maxsize=1)
def записи() -> dict[str, dict]:
    return json.loads(ДАННЫЕ.read_text(encoding="utf-8"))


def есть(имя: str) -> bool:
    return имя in записи()


def список() -> list[dict[str, object]]:
    return [{"имя": имя, "семейство": з["семейство"], "n": з["n"], "k": з["k"], "скорость": з["скорость"],
             "откуда": з["откуда"], "выколоты": з.get("выколоты", "")} for имя, з in записи().items()]


def умножить_gf64(a: int, b: int) -> int:
    """Произведение в GF(2⁶) по модулю 1 + x + x⁶."""
    итог = 0
    while b:
        if b & 1:
            итог ^= a
        b >>= 1
        a <<= 1
        if a & 0x40:
            a ^= МНОГОЧЛЕН_GF64
    return итог


def двоичный_образ(индексы: list[list[int]], элементы: list[list[int]]) -> tuple[np.ndarray, np.ndarray]:
    """Проверки кода над GF(64) → двоичные (строка, столбец): символ j — биты 6j … 6j + 5,
    старший первым; проверка i — 6 двоичных проверок (по биту суммы Σ h·x)."""
    строка, столбец = [], []
    for i, (сим, эл) in enumerate(zip(индексы, элементы, strict=True)):
        for j, h in zip(сим, эл, strict=True):
            for s in range(6):                      # бит s символа x (вес 2^s) — позиция 6j + 5 − s
                произведение = умножить_gf64(h, 1 << s)
                for t in range(6):                  # бит t суммы — проверка 6i + 5 − t
                    if произведение >> t & 1:
                        строка.append(6 * i + 5 - t)
                        столбец.append(6 * j + 5 - s)
    return np.array(строка, dtype=np.int64), np.array(столбец, dtype=np.int64)


@lru_cache(maxsize=8)
def матрица(имя: str):
    """Матрица проверок кода (ldpc.Матрица) с позициями данных по стандарту."""
    from . import ldpc  # noqa: PLC0415 — ldpc зовёт ldpc_std, тот — этот модуль
    з = записи()[имя]
    n, k = з["n"], з["k"]
    if "тройки" in з:
        Z = з["Z"]
        t = np.array(з["тройки"], dtype=np.int64)
        r = np.arange(Z)
        строка = (t[:, 0:1] * Z + r).reshape(-1)
        столбец = (t[:, 1:2] * Z + (r + t[:, 2:3]) % Z).reshape(-1)
        м = ldpc._по_строкам(n, n - k, строка, столбец, з["откуда"])
        м.данные = np.arange(k, dtype=np.int64)
    elif з.get("gf64"):
        строка, столбец = двоичный_образ(з["индексы"], з["элементы"])
        # Одна и та же единица может прийти от двух бит символа — по модулю 2 она сокращается.
        пары, число = np.unique(строка * n + столбец, return_counts=True)
        пары = пары[число % 2 == 1]
        м = ldpc._по_строкам(n, n - k, пары // n, пары % n, з["откуда"])
        м.данные = np.arange(k, dtype=np.int64)
    else:
        м = ldpc.Матрица(n, [np.array(с, dtype=np.int64) for с in з["строки"]], з["откуда"])
        if "данные" in з:
            м.данные = np.array(з["данные"], dtype=np.int64)
        else:
            м.данные = np.arange(з["данные_с"], n, dtype=np.int64)
    return м
