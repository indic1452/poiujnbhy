"""Прагматический решётчатый код (Trellis, TCM): 8PSK 2/3 и 16QAM 3/4 по меткам символов.

Вкладка «Trellis» декодера отдела. Открытое определение — ETSI EN 301 210 V1.1.1
(DVB-DSNG, istochniki/turbo/trellis/…): рис. 5–7 и табл. 3–4 (стр. PDF 13–16), рис. 13
(стр. 20). Кодированная ветвь — свёрточный код 1/2 K = 7 (171/133, EN 300 421): X → C1,
Y → C2; некодированные биты (U) выбирают точку среди «параллельных переходов».

- 8PSK 2/3 (2 кодированных бита на символ): метка (U1, C2, C1), точки через 45° с 22,5°:
  000, 001, 011, 010, 100, 101, 111, 110 (рис. 7);
- 16QAM 3/4: ось I — (U1, C1): −3 → 11, −1 → 10, 1 → 01, 3 → 00; ось Q — (U2, C2) так же
  (рис. 13).

Байты данных раскладываются по табл. 3: 8PSK 2/3 — байт A в кодированную ветвь (старший
бит первым), байт B — в некодированную (NE1); 16QAM 3/4 — A кодируется, B и D идут в
NE2/NE1 (B7 B5 B3 B1 D7 D5 D3 D1 и B6 B4 B2 B0 D6 D4 D2 D0).

Декодирование — по меткам символов, пришедшим из плоскости: метка → точка; мера ветви
Витерби — расстояние до ближайшей точки с данной парой (C2, C1); после Витерби
некодированные биты — от ближайшей точки с восстановленной парой. Как метки плоскости
соответствуют точкам, в потоке не видно: перебираются повороты и отражение (и код меток
— по рис. 7 или Грей/натуральный номер точки); берётся вариант с наименьшей мерой пути.

IESS-310 (прагматический 8PSK 2/3 Qualcomm, CDM-600 стр. 7-5) устроен так же, но его
отображение и дифференциальный кодер в открытых источниках не найдены: для него — тот же
декодер с перебором поворотов и отражения (гипотеза, не стандарт).
"""

from __future__ import annotations

import numpy as np

#: Рис. 7 (стр. PDF 16): метка (U1 C2 C1) точки k (угол 22,5° + 45°·k).
ФМ8_МЕТКИ = (0b000, 0b001, 0b011, 0b010, 0b100, 0b101, 0b111, 0b110)
#: Рис. 13 (стр. PDF 20): уровень −3, −1, 1, 3 → (U, C).
КАМ16_УРОВНИ = ((1, 1), (1, 0), (0, 1), (0, 0))
#: EN 300 421 табл. 2 (через EN 301 210 п. 4.6): G1 = 171 (X), G2 = 133 (Y), K = 7.
G1, G2, K = 0o171, 0o133, 7

assert sorted(ФМ8_МЕТКИ) == list(range(8))
# Некодированный бит U1 различает противоположные точки (рис. 7).
assert all(ФМ8_МЕТКИ[k + 4] == ФМ8_МЕТКИ[k] | 0b100 for k in range(4))


def _чётность(x: int) -> int:
    return bin(x).count("1") & 1


def _решётка() -> tuple[np.ndarray, np.ndarray]:
    """Состояние — 6 прошлых бит (старший — самый недавний); X, Y по записи стандарта
    (старший бит многочлена — текущий вход)."""
    S = 1 << (K - 1)
    следующее = np.zeros((S, 2), dtype=np.int64)
    выход = np.zeros((S, 2), dtype=np.int64)                 # 2·C2 + C1 = 2·Y + X
    for s in range(S):
        for b in (0, 1):
            рег = (b << (K - 1)) | s                           # текущий бит — старший
            x, y = _чётность(рег & G1), _чётность(рег & G2)
            следующее[s, b] = рег >> 1
            выход[s, b] = 2 * y + x
    return следующее, выход


СЛЕДУЮЩЕЕ, ВЫХОД = _решётка()


def точки(режим: str) -> tuple[np.ndarray, np.ndarray]:
    """Точки созвездия (комплексные, по номеру) и метка DSNG каждой точки.

    Метка 8PSK — (U1, C2, C1); метка 16QAM — (U2, U1, C2, C1)."""
    if режим == "8psk":
        угол = np.deg2rad(22.5 + 45 * np.arange(8))
        return np.exp(1j * угол), np.array(ФМ8_МЕТКИ)
    уровни = np.array([-3, -1, 1, 3])
    т, м = [], []
    for qi in range(4):
        for ii in range(4):
            u1, c1 = КАМ16_УРОВНИ[ii]
            u2, c2 = КАМ16_УРОВНИ[qi]
            т.append(уровни[ii] + 1j * уровни[qi])
            м.append((u2 << 3) | (u1 << 2) | (c2 << 1) | c1)
    return np.array(т), np.array(м)


def _без_кодированных(метка: np.ndarray, режим: str) -> np.ndarray:
    return метка >> 2


def закодировать(данные: np.ndarray, режим: str) -> np.ndarray:
    """Байты данных (биты, старший первым) → метки DSNG символов (для сверки)."""
    б = np.asarray(данные, dtype=np.uint8)
    на = 16 if режим == "8psk" else 24
    б = б[:len(б) // на * на].reshape(-1, на)
    A = б[:, :8].reshape(-1)
    if режим == "8psk":
        U = б[:, 8:16].reshape(-1)
    else:
        B, D = б[:, 8:16], б[:, 16:24]
        U2 = np.concatenate([B[:, 0::2], D[:, 0::2]], axis=1).reshape(-1)
        U1 = np.concatenate([B[:, 1::2], D[:, 1::2]], axis=1).reshape(-1)
        U = 2 * U2 + U1
    s = 0
    метки = np.zeros(len(A), dtype=np.int64)
    for t, a in enumerate(A):
        c = int(ВЫХОД[s, a])
        s = int(СЛЕДУЮЩЕЕ[s, a])
        метки[t] = (int(U[t]) << 2) | c
    return метки


def _витерби(меры: np.ndarray) -> tuple[np.ndarray, float]:
    """Меры символов по паре (C2, C1) (T × 4) → биты кодированной ветви и мера пути."""
    T = len(меры)
    S = СЛЕДУЮЩЕЕ.shape[0]
    пред_s = np.zeros((S, 2), dtype=np.int64)
    пред_b = np.zeros((S, 2), dtype=np.int64)
    счёт = np.zeros(S, dtype=np.int64)
    for s in range(S):
        for b in (0, 1):
            s2 = СЛЕДУЮЩЕЕ[s, b]
            пред_s[s2, счёт[s2]], пред_b[s2, счёт[s2]] = s, b
            счёт[s2] += 1
    выход_пред = ВЫХОД[пред_s, пред_b]                          # S × 2
    путь = np.zeros(S)
    откуда = np.zeros((T, S), dtype=np.int8)
    for t in range(T):
        кандидаты = путь[пред_s] + меры[t][выход_пред]
        выбор = np.argmin(кандидаты, axis=1)
        путь = кандидаты[np.arange(S), выбор]
        откуда[t] = выбор
    s = int(np.argmin(путь))
    мера = float(путь[s])
    биты = np.zeros(T, dtype=np.uint8)
    for t in range(T - 1, -1, -1):
        j = откуда[t, s]
        биты[t] = пред_b[s, j]
        s = int(пред_s[s, j])
    return биты, мера


def _номера(метки: np.ndarray, режим: str, код: str, поворот: int, отражение: bool) -> np.ndarray:
    """Метки плоскости → номер точки DSNG с учётом кода меток, поворота и отражения."""
    т, м = точки(режим)
    n = len(т)
    if код == "dsng":
        номер = np.argsort(м)[метки]
    elif код == "грей":
        обратный = np.zeros(n, dtype=np.int64)
        for i in range(n):
            обратный[i ^ (i >> 1)] = i
        номер = обратный[метки]
    else:
        номер = метки.copy()
    if режим == "8psk":
        if отражение:
            номер = (-номер - 1) % 8
        return (номер + поворот) % 8
    # 16QAM: номер = 4·qi + ii; поворот на 90° — (ii, qi) → (3 − qi, ii).
    ii, qi = номер % 4, номер // 4
    if отражение:
        ii = 3 - ii
    for _ in range(поворот % 4):
        ii, qi = 3 - qi, ii
    return 4 * qi + ii


def декодировать(метки: np.ndarray, режим: str, *, код: str = "dsng", поворот: int = 0,
                 отражение: bool = False) -> tuple[np.ndarray, float]:
    """Метки символов → байты данных (биты) и средняя мера пути на символ."""
    т, м = точки(режим)
    номер = _номера(np.asarray(метки, dtype=np.int64), режим, код, поворот, отражение)
    r = т[номер]
    расстояния = np.abs(r[:, None] - т[None, :]) ** 2          # T × точек
    пара = м & 3
    меры = np.stack([расстояния[:, пара == c].min(axis=1) for c in range(4)], axis=1)
    A, мера = _витерби(меры)
    пары = np.zeros(len(A), dtype=np.int64)
    s = 0
    for t, a in enumerate(A):
        пары[t] = ВЫХОД[s, a]
        s = СЛЕДУЮЩЕЕ[s, a]
    # Некодированные — от ближайшей точки с восстановленной парой.
    годные = (пара[None, :] == пары[:, None])
    ближайшая = np.where(годные, расстояния, np.inf).argmin(axis=1)
    U = _без_кодированных(м[ближайшая], режим)
    на = 8
    целых = len(A) // на * на
    A, U = A[:целых].reshape(-1, 8), U[:целых].reshape(-1, 8)
    if режим == "8psk":
        биты = np.concatenate([A, U], axis=1)
    else:
        U2, U1 = U >> 1, U & 1
        B = np.zeros((len(A), 8), dtype=np.int64)
        D = np.zeros((len(A), 8), dtype=np.int64)
        B[:, 0::2], B[:, 1::2] = U2[:, :4], U1[:, :4]
        D[:, 0::2], D[:, 1::2] = U2[:, 4:], U1[:, 4:]
        биты = np.concatenate([A, B, D], axis=1)
    return биты.reshape(-1).astype(np.uint8), мера / max(1, len(номер))


def снять(биты: np.ndarray, слова: str) -> tuple[np.ndarray, list[str]]:
    """Слой «trellis 8psk|16qam [код dsng|грей|натуральный] [поворот r] [отражение]».

    Без поворота — перебор поворотов, отражения и (без «код») кода меток по мере пути."""
    import re  # noqa: PLC0415
    слова = слова.lower()
    режим = "16qam" if ("16" in слова or "кам" in слова or "qam" in слова) else "8psk"
    k = 3 if режим == "8psk" else 4
    б = np.asarray(биты, dtype=np.uint8)
    б = б[:len(б) // k * k].reshape(-1, k)
    метки = б @ (1 << np.arange(k - 1, -1, -1))
    выборка = метки[:3000]
    коды = [к for к in ("dsng", "грей", "натуральный") if к[:3] in слова] or ["dsng", "грей", "натуральный"]
    п_ = re.search(r"поворот\s+(\d+)", слова)
    повороты = [int(п_.group(1))] if п_ else list(range(8 if режим == "8psk" else 4))
    отражения = [True] if "отраж" in слова else ([False] if п_ else [False, True])
    варианты = []
    for код in коды:
        for поворот in повороты:
            for отражение in отражения:
                _, мера = декодировать(выборка, режим, код=код, поворот=поворот, отражение=отражение)
                варианты.append((мера, код, поворот, отражение))
    варианты.sort()
    мера, код, поворот, отражение = варианты[0]
    данные, мера = декодировать(метки, режим, код=код, поворот=поворот, отражение=отражение)
    имя = "8PSK 2/3" if режим == "8psk" else "16QAM 3/4"
    подробно = [f"прагматический TCM {имя} (EN 301 210, рис. 5–7, 13, табл. 3–4): 171/133 K = 7, "
                f"{'2 кодированных бита' if режим == '8psk' else '2 кодированных бита'} на символ",
                f"метки плоскости: код «{код}», поворот {поворот}, отражение {'да' if отражение else 'нет'}"
                + (" — выбран перебором по мере пути" if len(варианты) > 1 else ""),
                f"средняя мера пути на символ {мера:.3f} (0 — без ошибок)"]
    if len(варианты) > 1:
        второй = варианты[1]
        подробно.append(f"следующий вариант: код «{второй[1]}», поворот {второй[2]}, мера {второй[0]:.3f}")
    return данные, подробно
