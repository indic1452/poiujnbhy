"""Прагматический решётчатый код (Trellis, TCM) по меткам символов: 8PSK 2/3, 5/6, 8/9; 16QAM 3/4, 7/8.

Вкладка «Trellis» декодера отдела (тот же набор скоростей — в патенте RU2317641).
Открытое определение — ETSI EN 301 210 V1.1.1 (DVB-DSNG, istochniki/turbo/trellis/…):
рис. 5–12 и табл. 3–4 (стр. PDF 13–19), рис. 7, 10, 13 (стр. 16, 18, 20). Кодированная
ветвь — свёрточный код 1/2 K = 7 (171/133, EN 300 421): X и Y; у 8/9 и 7/8 — он же,
выколотый до 2/3 и 3/4 (табл. 4). Некодированные биты (U) выбирают точку среди
«параллельных переходов».

- 8PSK 2/3 (2 кодированных бита на символ): метка (U1, C2, C1), точки через 45° с 22,5°:
  000, 001, 011, 010, 100, 101, 111, 110 (рис. 7);
- 8PSK 5/6 и 8/9 (1 кодированный бит): метка (U2, U1, C1) — номер точки (рис. 10);
- 16QAM 3/4 и 7/8: ось I — (U1, C1), ось Q — (U2, C2): −3 → 11, −1 → 10, 1 → 01, 3 → 00
  (рис. 13); метка здесь — (U2, U1, C2, C1).

Байты данных раскладываются по табл. 3 (параллельно-параллельный преобразователь; A —
первый байт, старший бит первым), кодированные и некодированные биты по символам — по
табл. 4 («последовательность символов»).

Декодирование — по меткам символов из плоскости: метка → точка; мера кодированного
бита (у 8PSK 2/3 — пары C2, C1 одного шага) — расстояние до ближайшей точки с таким
битом (у 16QAM — по своей оси), дальше Витерби по выколотой решётке; некодированные
биты — от ближайшей точки с восстановленными кодированными. Как метки плоскости
соответствуют точкам, в потоке не видно: перебираются повороты, отражение и код меток
(по рисунку стандарта, Грей, натуральный номер) — берётся вариант с наименьшей мерой.

IESS-310 (прагматический 8PSK 2/3 Qualcomm, CDM-600 стр. 7-5) устроен так же, но его
отображение и дифференциальный кодер в открытых источниках не найдены: для него — тот же
декодер с перебором (гипотеза, не стандарт).
"""

from __future__ import annotations

from dataclasses import dataclass

import numpy as np

#: Рис. 7 (стр. PDF 16): метка (U1 C2 C1) точки k (угол 22,5° + 45°·k).
ФМ8_МЕТКИ = (0b000, 0b001, 0b011, 0b010, 0b100, 0b101, 0b111, 0b110)
#: Рис. 10 (стр. PDF 18): метка (U2 U1 C1) точки k — номер точки.
ФМ8_1CBPS = (0b000, 0b001, 0b010, 0b011, 0b100, 0b101, 0b110, 0b111)
#: Рис. 13 (стр. PDF 20): уровень −3, −1, 1, 3 → (U, C).
КАМ16_УРОВНИ = ((1, 1), (1, 0), (0, 1), (0, 0))
#: EN 300 421 табл. 2 (через EN 301 210 п. 4.6): G1 = 171 (X), G2 = 133 (Y), K = 7.
G1, G2, K = 0o171, 0o133, 7

assert sorted(ФМ8_МЕТКИ) == list(range(8))
# Некодированный бит U1 различает противоположные точки (рис. 7); у 1CBPS C1 — соседние.
assert all(ФМ8_МЕТКИ[k + 4] == ФМ8_МЕТКИ[k] | 0b100 for k in range(4))

A, B, D, F, G, H, L = range(7)          # байты P по табл. 3: A (первый), B, D, F, G, H, L (последний)


def _б(байт: int, *биты: int) -> list[tuple[int, int]]:
    return [(байт, b) for b in биты]


@dataclass(frozen=True)
class Режим:
    """Режим TCM по табл. 3–4 EN 301 210: раскладка байтов в группы и символы.

    Группа — одна колонка табл. 3 (8 групп на блок ``байт`` байт). У группы: биты E в
    порядке входа кодера (``E[g]``), какие выходы X, Y по шагам передаются (``шаблон``:
    строки X и Y), и символы — некодированные биты U (``U[g][s]``, старший первым) и номера
    кодированных в переданной последовательности группы (``C[s]``, старший первым).
    """
    имя: str
    модуляция: str                          # «8psk» или «16qam»
    c_бит: int                              # кодированных бит на символ
    байт: int
    E: tuple
    U: tuple
    C: tuple
    шаблон: tuple = ("1", "1")


def _группы(столбцы: dict[str, list]) -> dict[str, list]:
    """Столбцы табл. 3 записаны от LAST к FIRST — группа 0 — самый правый столбец."""
    return {к: list(reversed(в)) for к, в in столбцы.items()}


def _режимы() -> dict[str, Режим]:
    р = {}
    # 8PSK 2/3: NE1 — B0…B7, E1 — A0…A7 (табл. 3); U1 = NE1, C2 = Y1, C1 = X1 (табл. 4).
    т = _группы({"NE1": _б(B, *range(8)), "E1": _б(A, *range(8))})
    р["8psk 2/3"] = Режим("8PSK 2/3", "8psk", 2, 2, tuple([e] for e in т["E1"]),
                          tuple([[u]] for u in т["NE1"]), ([1, 0],))
    # 8PSK 5/6: G3 G7 F3 F7 D3 D7 B3 B7 → NE4 … (табл. 3); символы: первый U2 = NE4, U1 = NE3,
    # C1 = X1; второй U2 = NE2, U1 = NE1, C1 = Y1 (табл. 4).
    т = _группы({"NE4": [(G, 3), (G, 7), (F, 3), (F, 7), (D, 3), (D, 7), (B, 3), (B, 7)],
                 "NE3": [(G, 2), (G, 6), (F, 2), (F, 6), (D, 2), (D, 6), (B, 2), (B, 6)],
                 "NE2": [(G, 1), (G, 5), (F, 1), (F, 5), (D, 1), (D, 5), (B, 1), (B, 5)],
                 "NE1": [(G, 0), (G, 4), (F, 0), (F, 4), (D, 0), (D, 4), (B, 0), (B, 4)],
                 "E1": _б(A, *range(8))})
    р["8psk 5/6"] = Режим("8PSK 5/6", "8psk", 1, 5, tuple([e] for e in т["E1"]),
                          tuple([[т["NE4"][g], т["NE3"][g]], [т["NE2"][g], т["NE1"][g]]] for g in range(8)),
                          ([0], [1]))
    # 8PSK 8/9: 4 группы на 4 байта; E2, E1 → кодер 2/3 (выколот X2); символы: U2 U1 C1 —
    # NE6 NE5 X1, NE4 NE3 Y1, NE2 NE1 Y2 (табл. 4).
    т = _группы({"NE6": [(F, 5), (F, 7), (B, 1), (B, 7)], "NE5": [(F, 4), (F, 6), (B, 0), (B, 6)],
                 "NE4": [(F, 3), (D, 3), (D, 7), (B, 5)], "NE3": [(F, 2), (D, 2), (D, 6), (B, 4)],
                 "NE2": [(F, 1), (D, 1), (D, 5), (B, 3)], "NE1": [(F, 0), (D, 0), (D, 4), (B, 2)],
                 "E2": [(A, 1), (A, 3), (A, 5), (A, 7)], "E1": [(A, 0), (A, 2), (A, 4), (A, 6)]})
    р["8psk 8/9"] = Режим("8PSK 8/9", "8psk", 1, 4, tuple([т["E2"][g], т["E1"][g]] for g in range(4)),
                          tuple([[т[f"NE{2 * s + 2}"][g], т[f"NE{2 * s + 1}"][g]] for s in (2, 1, 0)]
                                for g in range(4)), ([0], [1], [2]), ("10", "11"))
    # 16QAM 3/4: NE2 — D1 D3 D5 D7 B1 B3 B5 B7, NE1 — D0 … B6; U2 = NE2, U1 = NE1, C2 = Y1, C1 = X1.
    т = _группы({"NE2": [(D, 1), (D, 3), (D, 5), (D, 7), (B, 1), (B, 3), (B, 5), (B, 7)],
                 "NE1": [(D, 0), (D, 2), (D, 4), (D, 6), (B, 0), (B, 2), (B, 4), (B, 6)],
                 "E1": _б(A, *range(8))})
    р["16qam 3/4"] = Режим("16QAM 3/4", "16qam", 2, 3, tuple([e] for e in т["E1"]),
                           tuple([[т["NE2"][g], т["NE1"][g]]] for g in range(8)), ([1, 0],))
    # 16QAM 7/8: E3 E2 E1 → кодер 3/4 (выколоты X2, Y3); первый символ U2 U1 C2 C1 = NE4 NE3 Y1 X1,
    # второй — NE2 NE1 X3 Y2 (табл. 4).
    т = _группы({"NE4": [(L, 3), (L, 7), (G, 3), (G, 7), (D, 3), (D, 7), (B, 3), (B, 7)],
                 "NE3": [(L, 2), (L, 6), (G, 2), (G, 6), (D, 2), (D, 6), (B, 2), (B, 6)],
                 "NE2": [(L, 1), (L, 5), (G, 1), (G, 5), (D, 1), (D, 5), (B, 1), (B, 5)],
                 "NE1": [(L, 0), (L, 4), (G, 0), (G, 4), (D, 0), (D, 4), (B, 0), (B, 4)],
                 "E3": [(H, 2), (H, 5), (F, 0), (F, 3), (F, 6), (A, 1), (A, 4), (A, 7)],
                 "E2": [(H, 1), (H, 4), (H, 7), (F, 2), (F, 5), (A, 0), (A, 3), (A, 6)],
                 "E1": [(H, 0), (H, 3), (H, 6), (F, 1), (F, 4), (F, 7), (A, 2), (A, 5)]})
    р["16qam 7/8"] = Режим("16QAM 7/8", "16qam", 2, 7,
                           tuple([т["E3"][g], т["E2"][g], т["E1"][g]] for g in range(8)),
                           tuple([[т["NE4"][g], т["NE3"][g]], [т["NE2"][g], т["NE1"][g]]] for g in range(8)),
                           ([1, 0], [3, 2]), ("101", "110"))
    return р


РЕЖИМЫ = _режимы()
for _р in РЕЖИМЫ.values():
    # Каждый бит блока встречается ровно раз (табл. 3), число символов в группе — по табл. 4.
    _все = [b for g in range(len(_р.E)) for b in _р.E[g] + [u for s in _р.U[g] for u in s]]
    assert sorted(_все) == [(байт, бит) for байт in range(_р.байт) for бит in range(8)], _р.имя
    _передано = sum(ш.count("1") for ш in _р.шаблон) * len(_р.E[0]) // len(_р.шаблон[0])
    assert sorted(c for s in _р.C for c in s) == list(range(_передано)), _р.имя


def _чётность(x: int) -> int:
    return bin(x).count("1") & 1


def _решётка() -> tuple[np.ndarray, np.ndarray]:
    """Состояние — 6 прошлых бит (старший — самый недавний); X, Y по записи стандарта
    (старший бит многочлена — текущий вход). Выход — 2·Y + X."""
    S = 1 << (K - 1)
    следующее = np.zeros((S, 2), dtype=np.int64)
    выход = np.zeros((S, 2), dtype=np.int64)
    for s in range(S):
        for b in (0, 1):
            рег = (b << (K - 1)) | s
            следующее[s, b] = рег >> 1
            выход[s, b] = 2 * _чётность(рег & G2) + _чётность(рег & G1)
    return следующее, выход


СЛЕДУЮЩЕЕ, ВЫХОД = _решётка()


def точки(модуляция: str, c_бит: int = 2) -> tuple[np.ndarray, np.ndarray]:
    """Точки созвездия (комплексные, по номеру) и метка каждой точки (см. описание модуля)."""
    if модуляция == "8psk":
        угол = np.deg2rad(22.5 + 45 * np.arange(8))
        return np.exp(1j * угол), np.array(ФМ8_МЕТКИ if c_бит == 2 else ФМ8_1CBPS)
    уровни = np.array([-3, -1, 1, 3])
    т, м = [], []
    for qi in range(4):
        for ii in range(4):
            u1, c1 = КАМ16_УРОВНИ[ii]
            u2, c2 = КАМ16_УРОВНИ[qi]
            т.append(уровни[ii] + 1j * уровни[qi])
            м.append((u2 << 3) | (u1 << 2) | (c2 << 1) | c1)
    return np.array(т), np.array(м)


def режим(имя: str) -> Режим:
    имя = имя.lower().replace("пск", "psk").replace("кам", "qam")
    if имя in ("8psk", "16qam"):
        имя += " 2/3" if имя == "8psk" else " 3/4"
    if имя not in РЕЖИМЫ:
        raise ValueError("Trellis: режимы " + ", ".join(РЕЖИМЫ))
    return РЕЖИМЫ[имя]


def _шаги(р: Режим) -> tuple[np.ndarray, np.ndarray]:
    """Для переданных кодированных бит группы: шаг кодера в группе и выход (0 — X, 1 — Y)."""
    шаг, выход = [], []
    for t in range(len(р.E[0])):
        for в, строка in enumerate(р.шаблон):
            if строка[t % len(строка)] == "1":
                шаг.append(t)
                выход.append(в)
    return np.array(шаг), np.array(выход)


def закодировать(данные: np.ndarray, имя: str) -> np.ndarray:
    """Биты данных (байты A, B, … старшим битом первым) → метки символов."""
    р = режим(имя)
    б = np.asarray(данные, dtype=np.uint8)
    на = 8 * р.байт
    блоки = б[:len(б) // на * на].reshape(-1, на)
    шаг, выход = _шаги(р)
    s = 0
    метки = []
    for блок in блоки:
        def бит(ссылка):
            return int(блок[8 * ссылка[0] + 7 - ссылка[1]])
        for g in range(len(р.E)):
            выходы = []
            for e in р.E[g]:
                выходы.append(int(ВЫХОД[s, бит(e)]))
                s = int(СЛЕДУЮЩЕЕ[s, бит(e)])
            кодированные = [(выходы[t] >> в) & 1 for t, в in zip(шаг, выход, strict=True)]
            for u, c in zip(р.U[g], р.C, strict=True):
                метка = 0
                for x in [бит(x) for x in u] + [кодированные[j] for j in c]:
                    метка = (метка << 1) | x
                метки.append(метка)
    return np.array(метки, dtype=np.int64)


def _витерби(меры: np.ndarray) -> tuple[np.ndarray, float]:
    """Меры шагов по выходу 2·Y + X (T × 4) → биты кодированной ветви и мера пути."""
    T = len(меры)
    S = СЛЕДУЮЩЕЕ.shape[0]
    пред_s = np.zeros((S, 2), dtype=np.int64)
    пред_b = np.zeros((S, 2), dtype=np.int64)
    счёт = np.zeros(S, dtype=np.int64)
    for s in range(S):
        for b in (0, 1):
            s2 = СЛЕДУЮЩЕЕ[s, b]
            пред_s[s2, счёт[s2]], пред_b[s2, счёт[s2]] = s, b
            счёт[s2] += 1
    выход_пред = ВЫХОД[пред_s, пред_b]
    путь = np.zeros(S)
    откуда = np.zeros((T, S), dtype=np.int8)
    for t in range(T):
        кандидаты = путь[пред_s] + меры[t][выход_пред]
        выбор = np.argmin(кандидаты, axis=1)
        путь = кандидаты[np.arange(S), выбор]
        откуда[t] = выбор
    s = int(np.argmin(путь))
    мера = float(путь[s])
    биты = np.zeros(T, dtype=np.uint8)
    for t in range(T - 1, -1, -1):
        j = откуда[t, s]
        биты[t] = пред_b[s, j]
        s = int(пред_s[s, j])
    return биты, мера


def _номера(метки: np.ndarray, р: Режим, код: str, поворот: int, отражение: bool) -> np.ndarray:
    """Метки плоскости → номер точки с учётом кода меток, поворота и отражения."""
    т, м = точки(р.модуляция, р.c_бит)
    n = len(т)
    if код == "dsng":
        номер = np.argsort(м)[метки]
    elif код == "грей":
        обратный = np.zeros(n, dtype=np.int64)
        for i in range(n):
            обратный[i ^ (i >> 1)] = i
        номер = обратный[метки]
    else:
        номер = метки.copy()
    if р.модуляция == "8psk":
        if отражение:
            номер = (-номер - 1) % 8
        return (номер + поворот) % 8
    # 16QAM: номер = 4·qi + ii; поворот на 90° — (ii, qi) → (3 − qi, ii).
    ii, qi = номер % 4, номер // 4
    if отражение:
        ii = 3 - ii
    for _ in range(поворот % 4):
        ii, qi = 3 - qi, ii
    return 4 * qi + ii


def декодировать(метки: np.ndarray, имя: str, *, код: str = "dsng", поворот: int = 0,
                 отражение: bool = False) -> tuple[np.ndarray, float]:
    """Метки символов → биты данных (байты A, B, … подряд) и средняя мера пути на символ."""
    р = режим(имя)
    т, м = точки(р.модуляция, р.c_бит)
    символов = sum(len(с) for с in р.C) and len(р.C)
    на_группу = символов
    групп = len(метки) // на_группу
    номер = _номера(np.asarray(метки[:групп * на_группу], dtype=np.int64), р, код, поворот, отражение)
    r = т[номер].reshape(групп, на_группу)
    шагов = len(р.E[0])
    шаг, выход = _шаги(р)
    меры = np.zeros((групп, шагов, 4))
    c_метки = м & ((1 << р.c_бит) - 1)
    for s_, c in enumerate(р.C):
        расстояния = np.abs(r[:, s_, None] - т[None, :]) ** 2          # групп × точек
        if р.c_бит == 2 and р.модуляция == "8psk":
            # Пара (C2, C1) одного шага — мера совместная.
            j2, j1 = c
            t_ = шаг[j1]
            пары = np.stack([расстояния[:, c_метки == v].min(axis=1) for v in range(4)], axis=1)
            меры[:, t_] += пары[:, [2 * yx[0] + yx[1] if выход[j2] == 1 else 2 * yx[1] + yx[0]
                                    for yx in ((0, 0), (0, 1), (1, 0), (1, 1))]]
            continue
        for позиция, j in enumerate(c):
            бит_метки = len(c) - 1 - позиция                          # C2 — бит 1, C1 — бит 0
            if р.модуляция == "16qam":
                # Ось: C1 — I (с U1), C2 — Q (с U2): расстояние только по своей оси.
                ось = r[:, s_].real if бит_метки == 0 else r[:, s_].imag
                уровни = т.real if бит_метки == 0 else т.imag
                д = (ось[:, None] - уровни[None, :]) ** 2
            else:
                д = расстояния
            для = [д[:, ((c_метки >> бит_метки) & 1) == v].min(axis=1) for v in (0, 1)]
            for xy in range(4):
                меры[:, шаг[j], xy] += для[(xy >> выход[j]) & 1]
    A_биты, мера = _витерби(меры.reshape(-1, 4))
    A_биты = A_биты.reshape(групп, шагов)
    s = 0
    выходы = np.zeros((групп, шагов), dtype=np.int64)
    for g in range(групп):
        for t in range(шагов):
            выходы[g, t] = ВЫХОД[s, A_биты[g, t]]
            s = СЛЕДУЮЩЕЕ[s, A_биты[g, t]]
    кодированные = (выходы[:, шаг] >> выход[None, :]) & 1                  # групп × переданных
    итог = np.zeros((групп // len(р.E), 8 * р.байт), dtype=np.uint8)
    for g in range(групп // len(р.E) * len(р.E)):
        блок, gg = divmod(g, len(р.E))
        for t, e in enumerate(р.E[gg]):
            итог[блок, 8 * e[0] + 7 - e[1]] = A_биты[g, t]
        for s_, (u, c) in enumerate(zip(р.U[gg], р.C, strict=True)):
            c_знач = 0
            for j in c:
                c_знач = (c_знач << 1) | int(кодированные[g, j])
            годные = np.flatnonzero(c_метки == c_знач)
            ближайшая = годные[np.argmin(np.abs(r[g, s_] - т[годные]))]
            u_знач = int(м[ближайшая]) >> р.c_бит
            for i, ссылка in enumerate(u):
                итог[блок, 8 * ссылка[0] + 7 - ссылка[1]] = (u_знач >> (len(u) - 1 - i)) & 1
    return итог.reshape(-1), мера / max(1, групп * на_группу)


def снять(биты: np.ndarray, слова: str) -> tuple[np.ndarray, list[str]]:
    """Слой «trellis 8psk [2/3|5/6|8/9] | 16qam [3/4|7/8] [код dsng|грей|натуральный]
    [поворот r] [отражение]». Без поворота — перебор поворотов, отражения и кода меток."""
    import re  # noqa: PLC0415
    слова = слова.lower()
    модуляция = "16qam" if ("16" in слова or "кам" in слова or "qam" in слова) else "8psk"
    скорость = re.search(r"\b([2-8]/[3-9])\b", слова)
    р = режим(модуляция + (" " + скорость.group(1) if скорость else ""))
    k = 3 if р.модуляция == "8psk" else 4
    б = np.asarray(биты, dtype=np.uint8)
    б = б[:len(б) // k * k].reshape(-1, k)
    метки = б @ (1 << np.arange(k - 1, -1, -1))
    выборка = метки[:3000]
    коды = [к for к in ("dsng", "грей", "натуральный") if к[:3] in слова] or ["dsng", "грей", "натуральный"]
    п_ = re.search(r"поворот\s+(\d+)", слова)
    повороты = [int(п_.group(1))] if п_ else list(range(8 if р.модуляция == "8psk" else 4))
    отражения = [True] if "отраж" in слова else ([False] if п_ else [False, True])
    варианты = []
    for код in коды:
        for поворот in повороты:
            for отражение in отражения:
                _, мера = декодировать(выборка, р.имя.lower(), код=код, поворот=поворот, отражение=отражение)
                варианты.append((мера, код, поворот, отражение))
    варианты.sort()
    _, код, поворот, отражение = варианты[0]
    данные, мера = декодировать(метки, р.имя.lower(), код=код, поворот=поворот, отражение=отражение)
    подробно = [f"прагматический TCM {р.имя} (EN 301 210, табл. 3–4, рис. 7/10/13): 171/133 K = 7"
                + (", выколот" if len(р.шаблон[0]) > 1 else "") + f", {р.c_бит} кодированных бит на символ",
                f"метки плоскости: код «{код}», поворот {поворот}, отражение {'да' if отражение else 'нет'}"
                + (" — выбран перебором по мере пути" if len(варианты) > 1 else ""),
                f"средняя мера пути на символ {мера:.3f} (0 — без ошибок)"]
    if len(варианты) > 1:
        второй = варианты[1]
        подробно.append(f"следующий вариант: код «{второй[1]}», поворот {второй[2]}, мера {второй[0]:.3f}")
    return данные, подробно
