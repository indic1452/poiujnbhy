"""Восстановление матрицы LDPC ядром, когда слов больше длины слова (весь файл, а не выборка).

Частичный Гаусс со Штерном (``ldpc_vosst``) нужен, когда слов меньше n. Если файл длинный и различных слов
больше n, пространство проверок даёт прямо ядро матрицы слов (Гаусс по n столбцам — секунды при n в тысячи
бит), и это надёжнее: коллизиям Штерна мешает заполнение — у почти одинаковых слов (простой канала,
счётчики) строки частичного Гаусса вырождены.

**Ошибки линии.** Слово с ошибкой несёт своё направление (вектор ошибки не выражается через другие слова), и
позиции его ошибок выпадают из ядра — нулевые столбцы. Такие слова — ровно те, что не входят ни в одну
линейную зависимость слов (``gf2.зависимые_строки``): они убираются до ядра. Вместе с ними уходят и слова с
единственным в своём роде содержимым — это сужает только охват данных, не проверки.

**Связи данных.** Если чистые слова не покрывают код (у заполнения), в ядре кроме проверок кода — связи
данных. Проверки LDPC разрежены, связи данных — нет (как правило): разреженный базис ядра ищется Ли —
Брикеллом (случайная перестановка столбцов, ступенчатый вид — лёгкие строки и есть проверки), и каждая
сверяется со всеми словами: у проверки нарушения — лишь от ошибок линии. Квазициклическая (или IRA)
структура, если найдена по первым проверкам (``ldpc_vosst.найти_оператор``), достраивает орбиты.

**Инверсия и другие постоянные добавки.** Если слова в потоке — кодовые с одной и той же добавкой v (инверсия
всех бит, инверсия одного бита символа ФМ-4), проверки с h·v = 1 нарушены во всех словах и в ядро слов не
попадают. Разность двух слов — кодовое слово при любой v: ядро строится по словам, сложенным с одним чистым
(опорным) словом, сверка и декодирование — тоже (после декодирования опорное слово прибавляется обратно), а
ожидаемый синдром каждой проверки — её чётность на опорном слове.

**Проверки в начале слова.** Позиции данных — дополнение опорных столбцов H. У кодов стандартов проверочные
позиции в конце слова, но бывают и в начале (модемы CASC): где они — видно по весу столбцов (у проверочной
части — лестница, столбцы веса 2): опорные столбцы берутся с той стороны слова, где столбцы легче.
"""

from __future__ import annotations

import time
from collections.abc import Callable

import numpy as np

from . import gf2, ldpc_vosst

#: Различных слов нужно не меньше n + СЛОВ_СВЕРХ (иначе — частичный Гаусс ``ldpc_vosst``).
СЛОВ_СВЕРХ = 64
#: Слов в ядро — не больше стольких длин слова (дольше Гаусс, а проверок не прибавится).
СЛОВ_ДО_РАЗ = 1.6
#: Наибольший вес разреженной проверки.
ВЕС_ДО = 48
#: Перестановок без новой независимой проверки подряд — и поиск закончен.
СТОЯТЬ_ДО = 10
#: Слов на сверку проверок — не больше.
СВЕРКА_ДО = 4096
#: Доля слов с нарушенной проверкой — не больше (у проверки — лишь слова с ошибкой на её носителе).
НАРУШЕНИЙ_ДО = 0.05
#: Разреженных проверок достаточно, когда их ранг — такая доля размерности ядра.
ДОЛЯ_РАНГА = 0.9
#: Перестановок в пробе нарезки.
ПРОБА_ПЕРЕСТАНОВОК = 2


def слов_нужно(n: int) -> int:
    return n + СЛОВ_СВЕРХ


def различные(W: np.ndarray) -> np.ndarray:
    """Номера различных слов (точные повторы убраны) в исходном порядке."""
    _, первые = np.unique(np.packbits(W, axis=1), axis=0, return_index=True)
    return np.sort(первые)


def проверки_в_начале(проверки: list[np.ndarray], n: int, r: int) -> bool:
    """Проверочная часть — в начале слова: столбцы первых r позиций легче последних r (лестница — вес 2)."""
    if not проверки or not 0 < r < n:
        return False
    столбцы = np.bincount(np.concatenate([np.asarray(h, dtype=np.int64) for h in проверки]), minlength=n)
    начало, конец = столбцы[:r], столбцы[n - r:]
    return float(начало[начало > 0].mean() if (начало > 0).any() else 0) + 0.3 < \
        float(конец[конец > 0].mean() if (конец > 0).any() else 0)


def позиции_данных(проверки: list[np.ndarray], n: int, в_начале: bool) -> np.ndarray:
    """Позиции данных: дополнение опорных столбцов H; при проверках в начале слова опорные — как можно ближе
    к началу (данные — в конце), иначе — как у ``ldpc_vosst.позиции_данных``."""
    if not в_начале:
        return ldpc_vosst.позиции_данных(проверки, n)
    прямой = ldpc_vosst.Базис(n)
    for h in проверки:
        прямой.добавить(np.sort(np.asarray(h, dtype=np.int64)))
    проверочные = set(прямой.по_опорному)
    return np.array([j for j in range(n) if j not in проверочные], dtype=np.int64)


def _позиции_по_ядру(K: np.ndarray, живые: np.ndarray, n: int, в_начале: bool) -> tuple[np.ndarray, int]:
    """Позиции данных по ядру (вся размерность, не только разреженные): опорные столбцы ядра, приведённого с
    начала слова (проверки в начале) или с конца, — проверочные; граница проверочной части — крайний опорный.
    Данные — позиции за границей (и постоянные там же); опорных нет лишь на нескольких позициях до границы —
    это проверочные биты, чьи данные выколоты (пилоты на месте бит кода): их нет и в данных."""
    nl = len(живые)
    порядок = np.arange(nl) if в_начале else np.arange(nl)[::-1]
    _, опорные = gf2.привести(gf2.упаковать(K[:, порядок]), nl)
    места = живые[порядок[np.asarray(опорные, dtype=np.int64)]]
    if not len(места):
        return np.arange(n, dtype=np.int64), 0
    if в_начале:
        граница = int(места.max()) + 1
        данные = np.arange(граница, n, dtype=np.int64)
        непарных = граница - len(места) - int((~np.isin(np.arange(граница), живые)).sum())
    else:
        граница = int(места.min())
        данные = np.arange(0, граница, dtype=np.int64)
        непарных = (n - граница) - len(места) - int((~np.isin(np.arange(граница, n), живые)).sum())
    return данные, max(0, int(непарных))


#: Слов для отсева ошибок — все различные (больше слов — полнее охват данных, меньше связей данных в ядре);
#: при полном ранге — меньше во столько раз (до ОТСЕВ_ПОПЫТОК раз).
ОТСЕВ_МЕНЬШЕ = 0.85
ОТСЕВ_ПОПЫТОК = 4


def _без_ошибок(D: np.ndarray, живые: np.ndarray, сказать: Callable[[str], None]) -> np.ndarray:
    """Слова без ошибок линии: те, что входят в линейные зависимости слов. Пока ранг слов меньше числа
    столбцов (слов с ошибками меньше n − k), слово с ошибкой — вне зависимостей; при полном ранге в
    зависимостях все — тогда слов берётся меньше."""
    nl = len(живые)
    слов = len(D)
    for _ in range(ОТСЕВ_ПОПЫТОК):
        часть = D[:слов]
        зависимые, ранг = gf2.зависимые_и_ранг(часть[:, живые])
        if ранг < nl:
            сказать(f"слов вне зависимостей {int((~зависимые).sum())} из {слов} (ошибки линии и редкое содержимое) "
                    f"— убраны; ранг слов {ранг}; ядро по {int(зависимые.sum())} словам")
            return часть[зависимые]
        сказать(f"ранг {слов} слов полный ({ранг}): слов с ошибками больше избытка кода — беру меньше слов")
        слов = int(слов * ОТСЕВ_МЕНЬШЕ)
    return D[:слов]


def восстановить(W: np.ndarray, *, срок: float = 120.0, стоп: Callable[[], bool] | None = None,
                 ход: Callable[[str], None] | None = None, сид: int = 1, вес_до: int = ВЕС_ДО,
                 проба: bool = False, доля_ранга: float = ДОЛЯ_РАНГА) -> ldpc_vosst.Итог:
    """Проверки кода по словам W (слов × n, слов больше n): ядро чистых слов, разреженный базис, структура.

    ``проба`` — быстро понять, есть ли код при такой нарезке: ядро всех различных слов (без отсева слов с
    ошибками) и ПРОБА_ПЕРЕСТАНОВОК перестановок. Поиск разреженных останавливается, когда их ранг дошёл до
    ``доля_ранга`` размерности ядра (остальное — плотные связи данных или дорогие тяжёлые проверки).

    В итоге сверх полей ``ldpc_vosst.Итог``: ``данные`` — позиции данных (по опорным столбцам ядра: с той
    стороны слова, где проверочная часть), ``в_начале`` — проверочная часть в начале слова, ``непарных`` —
    опорных столбцов за границей проверочной части, ``без_проверок`` — позиции, которых нет ни в одной
    найденной проверке (ошибки там не исправить; у кода с выколотыми битами — пилоты поверх бит слова — такие
    позиции не входят ни в одну проверку без выколотых)."""
    начато = time.monotonic()
    W = np.ascontiguousarray(np.asarray(W, dtype=np.uint8))
    M, n = W.shape
    итог = ldpc_vosst.Итог(n=n, шаг=n, слов=M)

    def сказать(строка: str) -> None:
        итог.ход.append(строка)
        if ход is not None:
            ход(строка)

    def пора() -> bool:
        return time.monotonic() - начато > срок or (стоп is not None and стоп())

    свои = различные(W)
    D = W[свои]
    итог.слов = len(D)
    if len(D) < слов_нужно(n):
        итог.почему = (f"различных слов {len(D)} — меньше длины слова {n} + {СЛОВ_СВЕРХ}: ядро не покрывает "
                       "проверки (нужен частичный Гаусс)")
        return итог
    D = D[:int(СЛОВ_ДО_РАЗ * n)]
    постоянные = ldpc_vosst.постоянные_столбцы(D)
    итог.постоянные = постоянные
    живые = np.setdiff1d(np.arange(n), постоянные)
    if len(живые) < 16:
        итог.почему = "почти все столбцы постоянны — кода в словах нет"
        return итог
    сверка = W[:СВЕРКА_ДО]
    сказать(f"слов {M}, различных {len(D)} по {n} бит; постоянных столбцов {len(постоянные)}; "
            "ищу зависимости слов (слова с ошибками — вне зависимостей)")
    if проба:
        чистые = D
    else:
        чистые = _без_ошибок(D, живые, сказать)
    # Опорное слово: разности слов с ним — кодовые при любой постоянной добавке (инверсия и т. п.).
    опора = np.ascontiguousarray(чистые[0]) if len(чистые) else np.zeros(n, dtype=np.uint8)
    итог.опора = опора
    сверка = сверка ^ опора
    K = gf2.ядро((чистые[1:] ^ опора)[:, живые])
    d = len(K)
    итог.размерность = d
    if not d or пора():
        итог.почему = "ядро пусто: линейных связей в словах нет — кода нет" if not d else "время вышло"
        итог.секунд = time.monotonic() - начато
        return итог
    сказать(f"ядро: {d} независимых связей на {len(живые)} позициях — ищу разреженный базис (Ли — Брикелл)")
    rng = np.random.default_rng(сид)
    базис = ldpc_vosst.Базис(n)
    виденные: set[bytes] = set()
    отвергнуто = 0
    стоит = 0
    итераций = 0
    оператор = None
    развёрнуто: set[bytes] = set()
    упаковано = gf2.упаковать(K)
    nl = len(живые)

    def принять(кандидаты: list[np.ndarray]) -> int:
        nonlocal отвергнуто
        свежие = []
        for h in кандидаты:
            ключ = h.tobytes()
            if ключ not in виденные:
                виденные.add(ключ)
                свежие.append(h)
        if not свежие:
            return 0
        доли = ldpc_vosst.нарушения(сверка, свежие)
        новых = 0
        for h, f in zip(свежие, доли, strict=True):
            if f > НАРУШЕНИЙ_ДО:
                отвергнуто += 1
            elif базис.добавить(h):
                новых += 1
        return новых

    цель = d if проба else max(1, int(np.ceil(доля_ранга * d)))
    while базис.ранг < цель and стоит < СТОЯТЬ_ДО and not пора() and not (проба and итераций >= ПРОБА_ПЕРЕСТАНОВОК):
        итераций += 1
        порядок = rng.permutation(nl)
        переставлено = gf2.упаковать(gf2.распаковать(упаковано, nl)[:, порядок])
        приведено, _ = gf2.привести(переставлено, nl)
        строки = gf2.распаковать(приведено, nl)
        веса = строки.sum(axis=1)
        лёгкие = [np.sort(живые[порядок[np.flatnonzero(с)]]) for с in строки[(веса >= 2) & (веса <= вес_до)]]
        новых = принять(лёгкие)
        if оператор is None and базис.ранг >= 8:
            образцы = sorted(базис.взятые, key=len)[:32]
            порог = max(0.02, min(ldpc_vosst.ДОЛЯ_ДО, 4 * float(np.median(ldpc_vosst.нарушения(сверка[:512], образцы[:6])))))
            оператор = ldpc_vosst.найти_оператор(сверка, образцы, порог) or False
            if оператор:
                итог.оператор, итог.Z = оператор[0], int(оператор[1])
                сказать(f"структура: {оператор[0]} — проверки достраиваются орбитами")
        if оператор:
            for h in list(базис.взятые):
                ключ = h.tobytes()
                if ключ in развёрнуто:
                    continue
                развёрнуто.add(ключ)
                новых += принять([g for g in ldpc_vosst.орбита(h, оператор[1], оператор[2])
                                  if g is not None and len(g)])
                if пора():
                    break
        стоит = 0 if новых else стоит + 1
        if итераций % 10 == 0:
            сказать(f"перестановок {итераций}: независимых проверок {базис.ранг} из {d}")
    проверки = sorted(базис.взятые, key=len)
    итог.проверки = проверки
    итог.ранг = базис.ранг
    итог.найдено = len(виденные) - отвергнуто
    итог.k = n - max(итог.ранг, d)
    итог.итераций = итераций
    итог.точно = итог.ранг == d
    if проверки:
        доли = ldpc_vosst.нарушения(сверка, проверки)
        итог.доля = float(1 - доли.mean())
        итог.ошибок = ldpc_vosst.оценка_шума(float(доли.mean()), int(np.mean([len(h) for h in проверки])))
    if not проба and проверки:
        покрыты = np.zeros(n, dtype=bool)
        for h in проверки:
            покрыты[h] = True
        покрыты[постоянные] = True
        итог.без_проверок = np.flatnonzero(~покрыты)
        итог.в_начале = проверки_в_начале(проверки, n, max(d, итог.ранг))
        if итог.ранг >= d:
            # Орбиты достроили проверки и через позиции, выпавшие из ядра (ошибки линии): опорные — по ним.
            плотная = np.zeros((len(проверки), n), dtype=np.uint8)
            for i, h in enumerate(проверки):
                плотная[i, h] = 1
            итог.данные, итог.непарных = _позиции_по_ядру(плотная[:, живые], живые, n, итог.в_начале)
        else:
            итог.данные, итог.непарных = _позиции_по_ядру(K, живые, n, итог.в_начале)
    if проверки:
        ожидаемый = np.array([int(опора[h].sum() & 1) for h in проверки], dtype=np.uint8)
        if ожидаемый.any():
            сказать(f"у {int(ожидаемый.sum())} из {len(проверки)} проверок чётность на словах — единица: слова "
                     "кода с постоянной добавкой (инверсия бит или символов) — сверка и декодирование по разности "
                     "с опорным словом")
    итог.секунд = time.monotonic() - начато
    итог.почему = ("найден разреженный базис всего ядра" if итог.точно else
                   f"разреженных независимых проверок {итог.ранг} из {d} связей ядра (остальные — плотные: связи "
                   "данных заполнения или тяжёлые проверки)")
    сказать(f"итог: проверок {итог.ранг} (из {d} связей ядра), вес {min(map(len, проверки)) if проверки else 0}…"
            f"{max(map(len, проверки)) if проверки else 0}; перестановок {итераций}; отвергнуто {отвергнуто}; "
            f"{итог.секунд:.0f} с")
    return итог


def синдромы(W: np.ndarray, проверки: list[np.ndarray]) -> np.ndarray:
    """Слова × проверки: 1 — проверка нарушена."""
    return np.stack([np.bitwise_xor.reduce(W[:, h], axis=1) for h in проверки], axis=1).astype(np.uint8)


#: Переворотов бит (жёсткое решение) — не больше стольких шагов; не сошедшиеся — «минимумом — суммой».
ПЕРЕВОРОТОВ = 12


def _переворот(W: np.ndarray, проверки: list[np.ndarray]) -> np.ndarray:
    """Жёсткий декодер переворотом бит (Галлагер): в слове с нарушенными проверками переворачиваются биты, у
    которых нарушенных проверок больше всего (не меньше двух). При редких ошибках линии — за шаг-два и в разы
    быстрее «минимума — суммы»."""
    слова = W.copy()
    n = W.shape[1]
    for _ in range(ПЕРЕВОРОТОВ):
        S = синдромы(слова, проверки)
        плохие = S.any(axis=1)
        if not плохие.any():
            break
        счёт = np.zeros((int(плохие.sum()), n), dtype=np.int16)
        Sп = S[плохие].astype(np.int16)
        for i, h in enumerate(проверки):
            счёт[:, h] += Sп[:, i:i + 1]
        наибольший = счёт.max(axis=1, keepdims=True)
        перевернуть = (счёт == наибольший) & (наибольший >= 2)
        if not перевернуть.any():
            break
        слова[плохие] ^= перевернуть.astype(np.uint8)
    return слова


def декодировать(W: np.ndarray, проверки: list[np.ndarray], итераций: int = 30, опора: np.ndarray | None = None
                 ) -> tuple[np.ndarray, np.ndarray, int]:
    """Слова, исправленные по найденным проверкам (только слова с ненулевым синдромом: сперва переворотом бит,
    не сошедшиеся — «минимумом — суммой»), признак «синдром нулевой» и число исправленных бит. ``опора`` —
    чистое слово потока, если слова — кодовые с постоянной добавкой: декодируется разность с ним."""
    W = np.asarray(W, dtype=np.uint8)
    if опора is not None:
        исправленные, ок, исправлено = декодировать(W ^ опора, проверки, итераций)
        return исправленные ^ опора, ок, исправлено
    итог = W.copy()
    ок = np.ones(len(W), dtype=bool)
    if not проверки:
        return итог, ок, 0
    плохие = np.flatnonzero(синдромы(W, проверки).any(axis=1))
    if len(плохие):
        слова = _переворот(W[плохие], проверки)
        остались = синдромы(слова, проверки).any(axis=1)
        if остались.any():
            ещё, сошлось = ldpc_vosst.декодировать(W[плохие[остались]], проверки, итераций=итераций)
            слова[остались] = ещё
        итог[плохие] = слова
        ок[плохие] = ~синдромы(слова, проверки).any(axis=1)
    return итог, ок, int((итог != W).sum())


# -- сохранение и повторный разбор по сохранённой матрице -------------------------------------------

def имя(итог: ldpc_vosst.Итог) -> str:
    return ldpc_vosst.имя_файла(итог)


def сохранить(итог: ldpc_vosst.Итог, откуда: str = "", имя_: str | None = None) -> str:
    """Положить найденную H файлом alist в папку матриц отдела (с позициями данных — «# данные:»): второй
    разбор того же потока берёт её сразу (``сохранённая``)."""
    from . import ldpc  # noqa: PLC0415
    if ldpc.КАТАЛОГ is None:
        raise ValueError("папка матриц LDPC не задана")
    имя_ = имя_ or имя(итог)
    м = ldpc.Матрица(итог.n, [np.sort(np.asarray(h, dtype=np.int64)) for h in итог.проверки],
                     откуда or f"восстановлена по {итог.слов} словам")
    данные = getattr(итог, "данные", None)
    м.данные = данные if данные is not None else ldpc_vosst.позиции_данных(итог.проверки, итог.n)
    строки = [f"# откуда: {откуда or 'восстановлена по потоку'} — {итог.слов} слов по {итог.n} бит, независимых "
              f"проверок {итог.ранг} из {итог.размерность} связей ядра"
              + (f", {итог.оператор}" if итог.оператор else "") + f", BER ≈ {итог.ошибок:.1e}",
              f"# данные: {ldpc.позиции_строкой(м.данные)}"]
    ldpc.КАТАЛОГ.mkdir(parents=True, exist_ok=True)
    (ldpc.КАТАЛОГ / f"{имя_}.alist").write_text("\n".join(строки) + "\n" + ldpc.в_alist(м), encoding="utf-8")
    return имя_


#: Сохранённая матрица подходит, если её проверки нарушены в среднем не больше чем в такой доле слов.
СОХРАНЁННАЯ_ДО = 0.02


def опорное(W: np.ndarray, проверки: list[np.ndarray]) -> np.ndarray | None:
    """Опорное слово для слов с постоянной добавкой: ожидаемый синдром — чётность большинства слов по каждой
    проверке; опорное — первое слово с таким синдромом по всем проверкам (None — добавки нет или такого слова
    нет)."""
    S = синдромы(np.asarray(W, dtype=np.uint8), проверки)
    ожидаемый = (S.mean(axis=0) > 0.5).astype(np.uint8)
    if not ожидаемый.any():
        return None
    совпали = np.flatnonzero((S == ожидаемый).all(axis=1))
    return np.asarray(W[совпали[0]], dtype=np.uint8).copy() if len(совпали) else None


def сохранённая(W: np.ndarray) -> tuple[str, list[np.ndarray], np.ndarray] | None:
    """Восстановленная раньше матрица той же длины, чьи проверки выполнены в словах W (может быть, с
    постоянной добавкой — инверсией): (имя, проверки, позиции данных) — или None."""
    from . import ldpc  # noqa: PLC0415
    n = W.shape[1]
    выборка = np.asarray(W[:256], dtype=np.uint8)
    for имя_ in ldpc.файлы():
        if not имя_.startswith(f"восст-{n}-"):
            continue
        try:
            м = ldpc.прочитать(имя_)
        except (ValueError, OSError, KeyError):
            continue
        if м.n != n or not м.строки:
            continue
        доли = ldpc_vosst.нарушения(выборка, м.строки[:64])
        if float(np.minimum(доли, 1 - доли).mean()) > СОХРАНЁННАЯ_ДО:
            continue
        данные = м.данные if м.данные is not None else ldpc.информационные(м)
        return имя_, [np.asarray(h, dtype=np.int64) for h in м.строки], np.asarray(данные, dtype=np.int64)
    return None
