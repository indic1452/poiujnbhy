"""GFP (G.7041) и ATM: кадры по контрольной сумме заголовка.

Обе процедуры выделяют кадры не флагами, а проверкой заголовка — так же
поступает и аппаратура.

**GFP.** Основной заголовок — 2 байта длины нагрузки (PLI) и 2 байта CRC-16 над
ними (cHEC: x¹⁶ + x¹² + x⁵ + 1, начальное значение 0), сложенные с маской. По
G.7041 маска — B6AB31E0 (так и в RFC 2823 для SDL, предшественника GFP), но на
аппаратуре встречаются и другие (в обработках отдела — 000119D8, B6AB3325,
вариант NEC). Маска не угадывается, а находится:

- CRC0 (без начального значения) линейна: CRC0(a ⊕ b) = CRC0(a) ⊕ CRC0(b).
  Для настоящего заголовка на линии синдром s = cHEC ⊕ CRC0(PLI) равен
  Mc ⊕ CRC0(Mp) (Mp, Mc — половины маски) — один и тот же у всех заголовков при
  любой маске (и при любом начальном значении и выходном XOR CRC). У случайного
  места s равномерен. Поэтому пик гистограммы s по всем байтовым местам
  (8 битовых сдвигов × 2 порядка бит в байте) — это места заголовков.
- Соседние заголовки стоят через d = 4 + PLI байт: Mp = PLI_линии ⊕ (d − 4)
  большинством по парам соседей, и Mc = s ⊕ CRC0(Mp).
- Пустой кадр (PLI = 0, cHEC = 0) на линии — это сама маска. Инверсия всего
  потока — просто другая маска (маска ⊕ FFFFFFFF); нагрузку под
  мультипликативным x⁴³ + 1 инверсия не меняет (сокращается), без
  скремблера — видна по tHEC.

Кадры выделяются по всему потоку автоматом HUNT → PRESYNC → SYNC (RFC 2823,
3.9–3.10; DELTA = 1): в HUNT и PRESYNC принимается только заголовок без
ошибок, в SYNC одиночная ошибка cHEC исправляется по таблице синдромов, а
неисправимая — потеря синхронизации и снова HUNT. Область нагрузки снимается
с x⁴³ + 1 сквозным состоянием по кадрам подряд; после захвата синхронизма
первые 43 бита — прогрев дескремблера (не восстанавливаются). Заголовок типа
(PTI, PFI, EXI, UPI) с tHEC — одиночная ошибка исправляется; линейный
расширенный заголовок (EXI 1) — CID, запас, eHEC (только проверка);
pFCS — CRC-32/BZIP2 по полю данных клиента (как в Wireshark packet-gfp.c).
Таблицы PTI, EXI, UPI — ``gfp_tablicy`` (собраны программой из packet-gfp.c).

**ATM.** Ячейка 53 байта, заголовок 5 байт: GFC/VPI, VCI, PT, CLP и HEC —
CRC-8 (x⁸ + x² + x + 1) над четырьмя байтами, сложенная с 0x55. Ячейки
выделяются по сходящемуся HEC через каждые 53 байта.
"""

