def находка(р: РазборGFP) -> Находка:
    с = р.счёт()
    данные = [т for т in с["типы"] if т["pti"] == 0]
    клиенты = клиентские_кадры(р)
    подробно = строки_сводки(р) + [f"слой для снятия: {слой(р)}"]
    return Находка(
        уровень="канальный",
        что="GFP (G.7041)" + (f": {данные[0]['upi_словами']}" if данные else ""),
        уверенность=р.доля,
        мера=f"{с['кадров']} кадров в синхронизме (HUNT → PRESYNC → SYNC по cHEC), "
             f"{р.доля * 100:.1f} % байт от первого заголовка; маска {р.маска:08X}",
        подробно=подробно, дальше=клиенты, вид_дальше="кадры",
        свойства={"gfp": True, "маска": р.маска, "скремблер": р.скремблер,
                  "клиенты": [к.данные for к in р.клиенты()]})


def gfp(биты: np.ndarray) -> Находка | None:
    """GFP в битовом ряду вслепую (маска любая) — для автомата разбора и инструмента «кадры».

    Находкой считается не меньше ``ПОДРЯД`` кадров в синхронизме; если маска не из
    предустановок, нужны и кадры с нагрузкой с верным tHEC — иначе любое повторяющееся
    четырёхбайтовое слово сошло бы за «пустые кадры GFP» со своей маской."""
    р = разобрать(биты[:ВЫБОРКА])
    if р is None or len(р.выделение.места) < ПОДРЯД:
        return None
    if р.маска not in МАСКИ and (р.маска ^ 0xFFFFFFFF) not in МАСКИ and осмысленных(р) < ПОДРЯД:
        return None
    return находка(р)


def осмысленных(р: РазборGFP) -> int:
    """Кадры с верным tHEC и определённым типом: PTI 000/100/101 и UPI не «резерв, не
    используется» (0 и 255) — нулевое поле типа с нулевым tHEC сходится у любых нулей."""
    return sum(1 for к in р.кадры.values() if к.thec in ("верен", "исправлен") and к.pti in PTI
               and к.upi not in (0, 0xFF))


def разобрать_указание(слова: str) -> dict[str, Any]:
    """«gfp [маска авто|HEX] [скремблер авто|да|нет|инверсия] [порядок авто|старший|младший]
    [многочлен стандарт|авто] [канал N] [выход поток|клиенты|кадры]» → параметры."""
    def после(ключ: str, по: str) -> str:
        м = re.search(r"(?<!\w)" + ключ + r"\w*\s+(\S+)", слова)
        return м.group(1) if м else по
    маска_ = после("маск", "авто")
    if маска_ != "авто" and not re.fullmatch(r"(0x)?[0-9a-fA-F]{8}", маска_):
        raise ValueError("GFP: маска — «авто» или 8 шестнадцатеричных знаков (B6AB31E0)")
    скр = после("скрембл", "авто")
    if скр not in ("авто", "да", "нет", "инверсия"):
        raise ValueError("GFP: скремблер — авто, да, нет или инверсия")
    порядок = после("порядок", "авто")
    if порядок not in ("авто", "старший", "младший"):
        raise ValueError("GFP: порядок бит — авто, старший или младший")
    вид = после("выход", "поток")
    if вид not in ("поток", "клиенты", "кадры"):
        raise ValueError("GFP: выход — поток, клиенты или кадры")
    канал = после("канал", "")
    if канал and not канал.isdigit():
        raise ValueError("GFP: канал — номер CID (0…255)")
    return {"маска": "авто" if маска_ == "авто" else int(маска_[-8:], 16), "скремблер": скр,
            "порядок": порядок, "многочлен": "авто" if после("многочлен", "стандарт") == "авто" else "стандарт",
            "канал": int(канал) if канал else None, "выход": вид}


def снять(биты: np.ndarray, слова: str) -> tuple[np.ndarray, list[str]]:
    """Ручной слой «gfp …»: биты выбранного выхода и сводка."""
    п = разобрать_указание(слова)
    р = разобрать(биты[:БИТ_ДО], маска=п["маска"], скремблер=п["скремблер"], порядок=п["порядок"],
                  многочлен=п["многочлен"])
    if р is None:
        raise ValueError("GFP: заголовков с верным cHEC подряд не найдено"
                         + ("" if п["маска"] == "авто" else f" с маской {п['маска']:08X}"))
    ряд = выход(р, п["выход"], п["канал"])
    подробно = строки_сводки(р)
    if len(биты) > БИТ_ДО:
        подробно.append(f"разобраны первые {БИТ_ДО} бит из {len(биты)}")
    подробно.append(f"выход — {п['выход']}" + (f", канал CID {п['канал']}" if п["канал"] is not None else "")
                    + f": {len(ряд) // 8} байт")
    return ряд, подробно


def таблица(р: РазборGFP, от: int = 0, сколько: int = 200, пустые: bool = True) -> dict[str, Any]:
    """Строки таблицы кадров для окна стола: место в битах, PLI, PTI, UPI, CID, проверки."""
    в = р.выделение
    номера = range(len(в.места)) if пустые else sorted(set(р.кадры) | {
        i for i, pli in enumerate(в.pli) if 0 < pli < 4})
    номера = list(номера)
    строки = []
    for i in номера[от:от + сколько]:
        к = р.кадры.get(i)
        pli = в.pli[i]
        строка = {"№": i, "бит": р.бит(в.места[i]), "pli": pli,
                  "chec": "исправлен" if в.исправлен[i] else "верен",
                  "вид": "пустой" if pli == 0 else "служебный" if pli < 4 else "нагрузка"}
        if к is not None:
            строка.update({"pti": к.pti, "pfi": к.pfi, "exi": к.exi, "upi": к.upi, "cid": к.cid,
                           "thec": к.thec, "ehec": к.ehec, "pfcs": к.pfcs, "оборван": к.оборван,
                           "upi_словами": имя_upi(к.pti, к.upi) if к.pti is not None else "",
                           "данных": len(к.данные)})
            if к.прогрев:
                строка["вид"] = "прогрев x⁴³"
            elif к.pti == 4:
                строка["вид"] = "CMF"
            elif к.pti == 0:
                строка["вид"] = "данные"
            elif к.pti is not None:
                строка["вид"] = PTI.get(к.pti, ("", "резерв"))[1]
        строки.append(строка)
    return {"всего": len(номера), "от": от, "строки": строки}


def сводка(р: РазборGFP) -> dict[str, Any]:
    """Сводка для окна стола: маска, пустой кадр на линии, счёт, строки словами и слои."""
    с = р.счёт()
    return {"маска": f"{р.маска:08X}", "маска_словами": имя_маски(р.маска),
            "пустой": пустой_на_линии(р.маска, р.порядок), "сдвиг": р.сдвиг, "порядок": р.порядок,
            "многочлен": р.модель.имя, "скремблер": р.скремблер,
            "доли_thec": {к: round(д, 3) for к, д in р.доли_thec.items()},
            "доля": round(р.доля, 4), "счёт": с, "строки": строки_сводки(р),
            "слой_поток": слой(р, "поток"), "слой_клиенты": слой(р, "клиенты"),
            "слои_cid": {str(c): слой(р, "клиенты", c) for c in с["cid"]},
            "gfp_t": ({"суперблоков": р.gfp_t["суперблоков"],
                       "доля_управляющих": round(р.gfp_t["доля_управляющих"], 3),
                       "многочлен": f"0x{р.gfp_t['crc']['P']:04X}" if р.gfp_t["crc"] else None}
                      if р.gfp_t else None)}


