ПОДРЯД = 8
#: Сколько верных заголовков подряд нужно в PRESYNC сверх первого (G.7041 советует 1).
DELTA = 1
#: Сколько бит смотрит автомат разбора; окно стола — сколько попросят (до ``БИТ_ДО``).
ВЫБОРКА = 1 << 23
БИТ_ДО = 1 << 26
#: На скольких байтах сверять места-кандидаты при слепом поиске маски.
СВЕРКА_БАЙТ = 1 << 18
#: По скольким первым областям нагрузки выбирать режим скремблера (по доле верных tHEC).
СВЕРКА_THEC = 4000
#: По скольким суперблокам GFP-T искать их CRC-16 вслепую.
СВЕРКА_СУПЕРБЛОКОВ = 2000
#: Пиков синдрома на каждый сдвиг и порядок бит: каждый — кандидат (сдвиг, порядок, маска),
#: который сверяется выделением кадров. У настоящего GFP пик заголовков один, остальное — запас:
#: без скремблера свои пики дают поле типа и CID с верными HEC и постоянные слова клиента.
ПИКОВ = 4
#: Суперблок GFP-T: 8 × 8 октетов, октет флагов, 2 октета CRC-16.
СУПЕРБЛОК = 67


@dataclass(frozen=True)
class Модель:
    """Линейная часть CRC-16 основного заголовка и порядок байт cHEC в линии."""
    имя: str
    P: int = 0x1021
    refin: bool = False
    refout: bool = False
    порядок: str = "big"


СТАНДАРТ = Модель("CRC-16 x¹⁶ + x¹² + x⁵ + 1 (G.7041)")


@lru_cache(maxsize=64)
def _таблица(модель: Модель) -> np.ndarray:
    """CRC0 модели (без начального и выходного XOR) для всех 65 536 двухбайтовых слов."""
    базис = [crc_.crc((1 << i).to_bytes(2, "big"), 16, модель.P, 0, модель.refin, модель.refout, 0)
             for i in range(16)]
    слова = np.arange(65536, dtype=np.uint32)
    итог = np.zeros(65536, dtype=np.uint16)
    for i, значение in enumerate(базис):
        итог[(слова >> i) & 1 == 1] ^= значение
    if модель.порядок == "little":
        итог = ((итог >> 8) | (итог << 8)).astype(np.uint16)
    return итог


def hec16(данные: bytes) -> int:
    """cHEC/tHEC/eHEC: CRC-16 x¹⁶ + x¹² + x⁵ + 1, начальное 0, без выходного XOR."""
    return crc_.crc(данные, 16, 0x1021, 0, False, False, 0)


def hec8(данные: bytes) -> int:
    return crc_.crc(данные, 8, 0x07, 0, False, False, 0) ^ 0x55


_ОБРАТНЫЙ = bytes(int(f"{i:08b}"[::-1], 2) for i in range(256))


def crc32_bzip2(данные: bytes) -> int:
    """pFCS GFP: CRC-32 0x04C11DB7, начальное FFFFFFFF, старшим битом вперёд, дополнение
    (CRC-32/BZIP2; Wireshark: fcs == ~crc32_mpeg2). Через zlib: отражённая CRC от
    отражённых байт, результат отражён обратно."""
    return int(f"{zlib.crc32(bytes(данные).translate(_ОБРАТНЫЙ)):032b}"[::-1], 2)


def синдромы(б: np.ndarray, модель: Модель = СТАНДАРТ) -> np.ndarray:
    """s = cHEC ⊕ CRC0(PLI) каждого байтового места (4 байта с этого места)."""
    b = б.astype(np.uint32)                    # короче 4 байт — срезы пусты, синдромов нет
    pli = (b[:-3] << 8) | b[1:-2]
    chec = (b[2:-1] << 8) | b[3:]
    return (chec ^ _таблица(модель)[pli]).astype(np.uint16)


def синдром_маски(маска: int, модель: Модель = СТАНДАРТ) -> int:
    """Синдром настоящих заголовков при этой маске: Mc ⊕ CRC0(Mp)."""
    return int(синдромы(np.frombuffer(маска.to_bytes(4, "big"), dtype=np.uint8), модель)[0])


@lru_cache(maxsize=64)
def одиночные(модель: Модель = СТАНДАРТ) -> dict[int, int]:
    """Синдром одиночной ошибки в 32-битном заголовке → номер бита (0 — первый в линии).
    Пусто, если синдромы двух ошибок совпадают (исправлять нельзя)."""
    итог: dict[int, int] = {}
    for бит in range(32):
        с = синдром_маски(1 << (31 - бит), модель)     # у многочленов с x⁰ не ноль
        if с in итог:
            return {}
        итог[с] = бит
    return итог


def байты_ряда(биты: np.ndarray, сдвиг: int, порядок: str, фаза: int = 0) -> np.ndarray:
    """Байты GFP с битового сдвига ``сдвиг`` линии. «младший» — файл записан младшим битом
    вперёд: биты линии развернуты внутри каждого байта файла, поэтому сначала они разворачиваются
    обратно (байты файла начинаются с бита ``фаза`` ряда — участок бывает взят не с границы
    байта; неполный байт в начале отбрасывается), затем сдвиг и упаковка старшим битом вперёд.
    Граница байта GFP от границы байта файла не зависит."""
    ряд = линия(биты, порядок, фаза)[сдвиг:]
    return np.packbits(ряд[:len(ряд) - len(ряд) % 8])


def линия(биты: np.ndarray, порядок: str, фаза: int = 0) -> np.ndarray:
    """Биты в порядке линии: при «младший» развернуты обратно в каждом байте файла (байты
    файла — с бита ``фаза``; неполный байт в начале и в конце отбрасывается)."""
    ряд = np.asarray(биты, dtype=np.uint8)
    if порядок != "младший":
        return ряд
    ряд = ряд[фаза:]
    return np.unpackbits(np.packbits(ряд[:len(ряд) - len(ряд) % 8], bitorder="little"))


def бит_в_ряду(место_байт: int, сдвиг: int, порядок: str, фаза: int = 0) -> int:
    """Бит ряда (как он лежит в массиве), с которого начинается байт ``место_байт`` из
    ``байты_ряда``: при «младший» первый бит линии этого байта — в развёрнутом байте файла."""
    линия = сдвиг + 8 * место_байт
    if порядок == "младший":
        return фаза + (линия & ~7) + 7 - (линия & 7)
    return линия


def имя_upi(pti: int, upi: int) -> str:
    """UPI словами: для CMF (PTI 100) — своя таблица, для прочих — таблица данных клиента."""
    for от, до, _, русское in (UPI_УПРАВЛЕНИЕ if pti == 4 else UPI_ДАННЫЕ):
        if от <= upi <= до:
            return русское
    return f"0x{upi:02X}"


def имя_маски(маска: int) -> str:
    """Откуда маска: предустановка, инверсия предустановки или своя."""
    if маска in МАСКИ:
        return МАСКИ[маска]
    обратная = маска ^ 0xFFFFFFFF
    if обратная in МАСКИ:
        return f"поток инвертирован: это {обратная:08X} ({МАСКИ[обратная]}) ⊕ FFFFFFFF"
    return "нестандартная"


def пустой_на_линии(маска: int, порядок: str) -> str:
    """Как пустой кадр (PLI = 0, cHEC = 0) выглядит на линии: байты и биты в порядке передачи."""
    байты = маска.to_bytes(4, "big")
    биты = в_биты(байты, порядок)
    return (" ".join(f"{б:02X}" for б in байты) + " (биты на линии: "
            + " ".join("".join(map(str, байт)) for байт in биты.reshape(4, 8).tolist()) + ")")


# -- слепой поиск маски ------------------------------------------------------------------

@dataclass
class Кандидат:
    сдвиг: int
    порядок: str
    модель: Модель
    синдром: int
    мест: int
    маска: int | None = None
    в_синхронизме: int = 0      # байт в кадрах серий не короче ПОДРЯД (кадр целиком в ряду)
    всего_в_синхронизме: int = 0  # байт во всех кадрах в синхронизме
    верных_thec: int = 0        # кадров с верным tHEC (лучший из режимов скремблера)


def _порог(мест: int) -> float:
    """Сколько раз синдром должен встретиться, чтобы быть пиком: заметно чаще случайного
    (λ = мест / 65 536, у случайного места синдром равномерен)."""
    λ = мест / 65536
    return max(ПОДРЯД, λ + 6 * λ ** 0.5 + 4)


def _пики(с: np.ndarray, сколько: int) -> list[tuple[int, int]]:
    """Синдромы-пики, не больше ``сколько`` лучших."""
    if not len(с):
        return []
    счёт = np.bincount(с, minlength=65536)
    порог = _порог(len(с))
    лучшие = np.argsort(счёт, kind="stable")[::-1][:сколько]
    return [(int(s), int(счёт[s])) for s in лучшие if счёт[s] >= порог]


def маска_по_местам(б: np.ndarray, с: np.ndarray, синдром: int, модель: Модель = СТАНДАРТ,
                    годные_места: np.ndarray | None = None) -> int | None:
    """Маска по местам с этим синдромом: Mp — большинством по соседям, Mc = s ⊕ CRC0(Mp).
    ``годные_места`` — какие места учитывать (без окон из одних нулей)."""
    места = np.flatnonzero((с == синдром) if годные_места is None else (с == синдром) & годные_места)
    d = np.diff(места)
    годные = (d >= 4) & (d <= 0xFFFF + 4)          # PLI от 0 до FFFF
    начала = места[:-1][годные]
    pli_линии = (б[начала].astype(np.int64) << 8) | б[начала + 1]
    голоса = Counter((pli_линии ^ (d[годные] - 4)).tolist())
    if not голоса:
        return None
    mp, за = голоса.most_common()[0]
    if за < 2:                                      # нужны хотя бы две согласные пары соседей
        return None
    # Mc — как на линии (таблица модели уже в порядке байт cHEC на линии).
    return (mp << 16) | (синдром ^ int(_таблица(модель)[mp]))


def модели_каталога() -> list[Модель]:
    """Линейные части CRC-16 из каталога RevEng (без G.7041) — оба порядка байт cHEC."""
    виды: dict[tuple[int, bool, bool], str] = {}
    for имя, w, P, _, refin, refout, *_ in crc_katalog.REVENG:
        if w == 16 and (P, refin, refout) != (0x1021, False, False):
            виды.setdefault((P, refin, refout), имя)
    return [Модель(f"{имя} (многочлен 0x{P:04X}{', отражённая' if refin else ''}, cHEC "
                   f"{'старшим' if порядок == 'big' else 'младшим'} байтом вперёд)", P, refin, refout, порядок)
            for (P, refin, refout), имя in виды.items() for порядок in ("big", "little")]


def найти_маску(биты: np.ndarray, *, маска: int | None = None, порядки=("старший", "младший"),
                модели: list[Модель] | None = None, фаза: int = 0) -> list[Кандидат]:
    """Места заголовков и маска: по пику синдромов (маска не задана) или по заданной.

    Возвращает кандидатов от лучшего к худшему: у каждого проверено, сколько байт в
    начале ряда выделяется кадрами в синхронизме.
    """
    модели = модели or [СТАНДАРТ]
    найдены: list[Кандидат] = []
    for модель in модели:
        for порядок in порядки:
            биты_линии = линия(биты, порядок, фаза)
            for сдвиг in range(8):
                б = байты_ряда(биты_линии, сдвиг, "старший")
                с = синдромы(б, модель)
                if маска is not None:
                    s0 = синдром_маски(маска, модель)
                    # И у заданной маски её синдром должен быть пиком — иначе случайная пара
                    # «заголовков» сошла бы за GFP (и другие многочлены не пробовались бы).
                    сколько = int(np.count_nonzero(с == s0))
                    if сколько >= _порог(len(с)):
                        найдены.append(Кандидат(сдвиг, порядок, модель, s0, сколько, маска))
                    continue
                # Окно из одних нулей даёт синдром 0 при любой модели — в пике не учитывается
                # (иначе нули и поле типа с верным tHEC без скремблера забивают пик заголовков).
                ненули = (б[:-3] | б[1:-2] | б[2:-1] | б[3:]) != 0
                # Лучшие пики — у каждого сдвига и порядка свои: общий отбор отдавал все места
                # пикам синдрома 0 полей типа и CID на других сдвигах.
                for s0, сколько in _пики(с[ненули], ПИКОВ):
                    м = маска_по_местам(б, с, s0, модель, ненули)
                    if м is not None:
                        найдены.append(Кандидат(сдвиг, порядок, модель, s0, сколько, м))
    найдены.sort(key=lambda к: -к.мест)
    for к in найдены:
        б = байты_ряда(биты[:фаза + 8 * (СВЕРКА_БАЙТ + 1)], к.сдвиг, к.порядок, фаза)[:СВЕРКА_БАЙТ]
        в = выделить(б, синдромы(б, к.модель), к.синдром, к.маска >> 16, одиночные(к.модель))
        к.всего_в_синхронизме = в.байт_в_синхронизме
        к.в_синхронизме = в.байт_в_сериях(len(б))
        if к.в_синхронизме:
            к.верных_thec = _верных_thec(б.tobytes(), в, к.модель)
    # Лучший — больше байт в кадрах длинных серий, затем больше верных tHEC, затем больше байт
    # в синхронизме вообще, затем предустановленная маска и больше мест с синдромом (сортировка
    # устойчива). Слепой поиск берёт только кандидатов с длинной серией; заданной маске
    # хватает и коротких (её выбрал человек).
    найдены.sort(key=lambda к: (-к.в_синхронизме, -к.верных_thec, -к.всего_в_синхронизме,
                                к.маска not in МАСКИ))
    return [к for к in найдены if (к.в_синхронизме if маска is None else к.всего_в_синхронизме)]


def _верных_thec(bb: bytes, в: Выделение, модель: Модель) -> int:
    """Сколько первых областей нагрузки (до ``СВЕРКА_THEC``) с верным tHEC — при лучшем из
    режимов скремблера (x⁴³ + 1, нет, инверсия)."""
    области = dict(list(_области(bb, в).items())[:СВЕРКА_THEC])
    лучший = 0
    for режим in ("x43", "нет", "инверсия"):
        снятые, прогрев = снять_x43(области, в, режим)
        лучший = max(лучший, sum(1 for i, о in снятые.items() if i not in прогрев and len(о) >= 4
                                 and _hec(о, 0, модель)[0] == "верен"))
    return лучший


# -- выделение кадров: HUNT → PRESYNC → SYNC ---------------------------------------------

@dataclass
class Выделение:
    места: list[int] = field(default_factory=list)      # байт основного заголовка
    pli: list[int] = field(default_factory=list)
    исправлен: list[bool] = field(default_factory=list)  # одиночная ошибка cHEC исправлена
    серия: list[int] = field(default_factory=list)       # номер захвата синхронизма
    потери: list[int] = field(default_factory=list)     # байт заголовка, на котором потерян
    байт_в_синхронизме: int = 0                         # кадры целиком в ряду

    def байт_в_сериях(self, n: int, от: int = ПОДРЯД) -> int:
        """Байт в кадрах серий (захватов синхронизма) не короче ``от`` кадров; кадр, чей конец
        за концом ряда (``n`` байт), не считается. Случайное совпадение даёт серию в 1–2 кадра."""
        if not self.места:
            return 0
        серия = np.array(self.серия)
        длина = 4 + np.array(self.pli, dtype=np.int64)
        годные = (np.array(self.места) + длина <= n) & (np.bincount(серия)[серия] >= от)
        return int(длина[годные].sum())


def выделить(б: np.ndarray, с: np.ndarray, синдром: int, маска_pli: int, одиночные_: dict[int, int],
             delta: int = DELTA) -> Выделение:
    """Кадры по всему ряду байт: HUNT (только верный заголовок) → PRESYNC (delta верных
    подряд) → SYNC (одиночная ошибка cHEC исправляется, неисправимая — снова HUNT)."""
    итог = Выделение()
    n = len(б)
    bb = б.tobytes()
    mv = memoryview(np.ascontiguousarray(с, dtype=np.uint16))
    верные = np.flatnonzero(с == синдром)
    серия = 0
    k = 0
    while k < len(верные):
        h = int(верные[k])
        цепь = [h]
        p = h
        for _ in range(delta):
            p += 4 + (((bb[p] << 8) | bb[p + 1]) ^ маска_pli)
            if p + 4 > n or mv[p] != синдром:
                break
            цепь.append(p)
        if len(цепь) <= delta:
            k += 1
            continue
        серия += 1
        p = h
        while p + 4 <= n:
            ошибка = mv[p] ^ синдром
            pli = ((bb[p] << 8) | bb[p + 1]) ^ маска_pli
            if ошибка:
                бит = одиночные_.get(ошибка)
                if бит is None:
                    итог.потери.append(p)
                    break
                if бит < 16:
                    pli ^= 1 << (15 - бит)
            итог.места.append(p)
            итог.pli.append(pli)
            итог.исправлен.append(bool(ошибка))
            итог.серия.append(серия)
            if p + 4 + pli <= n:                    # кадр за концом ряда не засчитывается
                итог.байт_в_синхронизме += 4 + pli
            p += 4 + pli
        k = int(np.searchsorted(верные, p))        # сам p не верен (потеря) или за концом ряда
    return итог


# -- область нагрузки ---------------------------------------------------------------------

@dataclass
class Кадр:
    """Кадр GFP с нагрузкой (PLI ≥ 4): что прочитано в области нагрузки."""
    номер: int                  # номер в выделении
    нагрузка: bytes             # область нагрузки после скремблера (без основного заголовка)
    прогрев: bool = False       # заголовок типа в первых 43 битах после захвата синхронизма
    оборван: bool = False       # конец кадра за концом ряда
    thec: str = ""              # «верен», «исправлен», «ошибка», «прогрев», «мало байт»
    pti: int | None = None      # поле типа — None, пока не прочитано (прогрев, ошибка tHEC, мало байт)
    pfi: int | None = None
    exi: int | None = None
    upi: int | None = None
    cid: int | None = None
    ehec: str = ""              # «верен», «ошибка» или «» (нет расширенного заголовка)
    pfcs: str = ""              # «верна», «неверна» или «» (нет pFCS)
    данные: bytes = b""         # поле данных клиента (без расширенного заголовка и pFCS)


def _области(б: bytes, в: Выделение) -> dict[int, bytes]:
    """Области нагрузки непустых кадров: номер кадра → байты (последний может быть короче).
    Служебные кадры (PLI 1–3) тоже здесь: их октеты — область нагрузки, скремблер x⁴³ + 1
    идёт и по ним."""
    return {i: б[в.места[i] + 4:в.места[i] + 4 + в.pli[i]] for i in range(len(в.места)) if в.pli[i]}


def снять_x43(области: dict[int, bytes], в: Выделение, режим: str) -> tuple[dict[int, bytes], set[int]]:
    """Области после снятия скремблера: «x43» — сквозное состояние по кадрам одной серии,
    первые 43 бита серии — прогрев; «нет» — как есть; «инверсия» — байты инвертированы.
    Возвращает области и номера кадров, чей заголовок типа попал в прогрев."""
    if режим == "нет":
        return dict(области), set()
    if режим == "инверсия":
        return {i: bytes(x ^ 0xFF for x in о) for i, о in области.items()}, set()
    итог: dict[int, bytes] = {}
    прогрев: set[int] = set()
    по_сериям: dict[int, list[int]] = {}
    for i in области:
        по_сериям.setdefault(в.серия[i], []).append(i)
    for номера in по_сериям.values():
        y = np.unpackbits(np.frombuffer(b"".join(области[i] for i in номера), dtype=np.uint8))
        x = y.copy()
        x[43:] ^= y[:-43]
        сплошь = np.packbits(x).tobytes()
        место = 0
        for i in номера:
            if место < 6:                          # байты 0–5 задевают первые 43 бита (5 байт и 3 бита)
                прогрев.add(i)
            итог[i] = сплошь[место:место + len(области[i])]
            место += len(области[i])
    return итог, прогрев


def _hec(б: bytes, от: int, модель: Модель) -> tuple[str, int]:
    """Два байта с HEC за ними (4 байта с ``от``): «верен», «исправлен» или «ошибка» — и
    16-битное значение двух байт (с исправленной одиночной ошибкой)."""
    значение = (б[от] << 8) | б[от + 1]
    с = ((б[от + 2] << 8) | б[от + 3]) ^ int(_таблица(модель)[значение])
    if с == 0:
        return "верен", значение
    бит = одиночные(модель).get(с)
    if бит is None:
        return "ошибка", значение
    if бит < 16:
        значение ^= 1 << (15 - бит)
    return "исправлен", значение


def разобрать_нагрузку(номер: int, область: bytes, модель: Модель = СТАНДАРТ) -> Кадр:
    """Заголовок типа (PTI, PFI, EXI, UPI) с tHEC, расширенный заголовок, pFCS, данные клиента."""
    к = Кадр(номер, область)
    if len(область) < 4:
        к.thec = "мало байт"
        return к
    к.thec, тип = _hec(область, 0, модель)
    if к.thec == "ошибка":
        return к
    к.pti, к.pfi, к.exi, к.upi = тип >> 13, (тип >> 12) & 1, (тип >> 8) & 0x0F, тип & 0xFF
    начало = 4
    if к.exi == 1 and len(область) >= 8:
        # Линейный кадр: CID, запас, eHEC (исправление одиночной ошибки eHEC источниками не
        # подтверждено — только проверка).
        к.cid = область[4]
        к.ehec = "верен" if _hec(область, 4, модель)[0] == "верен" else "ошибка"
        начало = 8
    конец = len(область)
    if к.pfi and конец - начало >= 4:
        конец -= 4
        к.pfcs = "верна" if crc32_bzip2(область[начало:конец]) == int.from_bytes(область[конец:], "big") \
            else "неверна"
    к.данные = область[начало:конец]
    return к


def доля_thec(области: dict[int, bytes], прогрев: set[int], модель: Модель = СТАНДАРТ) -> float:
    """Доля областей (без прогрева) с верным без исправления tHEC."""
    номера = [i for i in области if i not in прогрев and len(области[i]) >= 4]
    if not номера:
        return 0.0
    return sum(1 for i in номера if _hec(области[i], 0, модель)[0] == "верен") / len(номера)


# -- GFP-T: суперблоки 64B/65B -------------------------------------------------------------

def суперблоки(кадры: list[Кадр]) -> dict[str, Any] | None:
    """Суперблоки кадров прозрачного отображения: 8 × 8 октетов, октет флагов, CRC-16.

    Структура — по открытым выдержкам (в сохранённых источниках текста G.7041 нет);
    CRC-16 суперблока не задаётся, а ищется вслепую (crc.найти) по самим суперблокам.
    Таблицы отображения кодов управления 8B/10B в открытых источниках нет — символы
    клиента не восстанавливаются."""
    блоки = [к.данные[i:i + СУПЕРБЛОК] for к in кадры if к.upi in UPI_ПРОЗРАЧНЫЕ and к.pti == 0
             and к.данные and len(к.данные) % СУПЕРБЛОК == 0 for i in range(0, len(к.данные), СУПЕРБЛОК)]
    if not блоки:
        return None
    модель = crc_.найти(блоки[:СВЕРКА_СУПЕРБЛОКОВ], ширины=(16,))
    флаги = np.unpackbits(np.frombuffer(b"".join(б[64:65] for б in блоки), dtype=np.uint8))
    верных = None
    if модель is not None:
        # Суперблоки одной длины: начальное и выходной XOR не разделить — проверяется их общий
        # вклад (init = 0, xorout = вклад).
        init = модель["init"] or 0
        xorout = модель["xorout"] if модель["init"] is not None else (
            crc_._отразить(модель["вклад"], 16) if модель["refout"] else модель["вклад"])
        верных = sum(1 for б in блоки if crc_.crc(б[:65], 16, модель["P"], init, модель["refin"], модель["refout"],
                                                   xorout) == int.from_bytes(б[65:], модель["порядок"])) / len(блоки)
    return {"суперблоков": len(блоки), "crc": модель, "доля_управляющих": float(флаги.mean()),
            "верных_crc": верных}


# -- итог разбора -----------------------------------------------------------------------

@dataclass
class РазборGFP:
    """Всё о GFP в ряду: маска, выделение, кадры с нагрузкой, счёт."""
    маска: int
    сдвиг: int
    порядок: str
    модель: Модель
    выделение: Выделение
    кадры: dict[int, Кадр]
    скремблер: str                        # «x43», «нет», «инверсия»
    доли_thec: dict[str, float]           # режим → доля верных tHEC
    всего_байт: int
    от_бита: int                          # с какого бита массива взят ряд
    gfp_t: dict[str, Any] | None = None
    бит_участка: int = 0                  # сколько бит разобрано (с ``от_бита``)
    всего_бит: int = 0                    # сколько бит во всём массиве

    def участок(self) -> dict[str, int]:
        """Разобранный участок массива: биты [от, до) из всего."""
        return {"от": self.от_бита, "до": self.от_бита + self.бит_участка, "всего": self.всего_бит}

    @property
    def фаза(self) -> int:
        """С какого бита ряда начинаются байты массива (участок взят с бита ``от_бита``)."""
        return -self.от_бита % 8

    def бит(self, место_байт: int) -> int:
        """Место в битах массива по месту в байтах ряда (первый бит байта на линии)."""
        return self.от_бита + бит_в_ряду(место_байт, self.сдвиг, self.порядок, self.фаза)

    @property
    def доля(self) -> float:
        """Доля байт от первого заголовка до конца ряда, покрытых кадрами в синхронизме."""
        в = self.выделение
        if not в.места:
            return 0.0
        return min(1.0, в.байт_в_синхронизме / (self.всего_байт - в.места[0]))   # заголовок в ряду — не 0

    def клиенты(self, cid: int | None = None) -> list[Кадр]:
        """Кадры данных клиента (PTI 000) с верным или исправленным tHEC, без прогрева."""
        return [к for к in self.кадры.values() if к.pti == 0 and not к.прогрев and not к.оборван
                and к.thec in ("верен", "исправлен") and (cid is None or к.cid == cid)]

    def счёт(self) -> dict[str, Any]:
        в = self.выделение
        pli = np.array(в.pli, dtype=np.int64)
        к = list(self.кадры.values())
        # Кадр, оборванный концом участка, проверить нельзя: tHEC и pFCS считаются без него.
        целые = [х for х in к if not х.оборван]
        thec = Counter(х.thec for х in целые)
        типы = Counter((х.pti, х.pfi, х.exi, х.upi) for х in к if х.pti is not None and not х.прогрев)
        с_данными = [х for х in к if х.pti == 0 and not х.прогрев]
        длины = pli[pli >= 4]
        return {
            "кадров": len(в.места), "пустых": int(np.count_nonzero(pli == 0)),
            "служебных": int(np.count_nonzero((pli > 0) & (pli < 4))),
            "с_нагрузкой": len(к), "данных_клиента": len(с_данными),
            "cmf": sum(1 for х in к if х.pti == 4 and not х.прогрев),
            "управляющих": sum(1 for х in к if х.pti == 5 and not х.прогрев),
            "прочих_pti": sum(1 for х in к if х.pti not in (None, 0, 4, 5) and not х.прогрев),
            "исправлено_chec": int(sum(в.исправлен)),
            "потерь": len(в.потери), "потери_бит": [self.бит(м) for м in в.потери[:200]],
            "thec": {"верен": thec["верен"], "исправлен": thec["исправлен"], "ошибка": thec["ошибка"],
                     "прогрев": thec["прогрев"], "мало": thec["мало байт"]},
            "ehec": dict(Counter(х.ehec for х in к if х.ehec)),
            "pfcs": dict(Counter(х.pfcs for х in целые if х.pfcs)),
            "типы": [{"pti": pti, "pfi": pfi, "exi": exi, "upi": upi, "кадров": n,
                      "upi_словами": имя_upi(pti, upi)}
                     for (pti, pfi, exi, upi), n in типы.most_common(12)],
            "cid": dict(sorted(Counter(х.cid for х in с_данными if х.cid is not None).items())),
            "длины": {"от": int(длины.min()), "до": int(длины.max()),
                      "частые": [[int(д), int(n)] for д, n in Counter(длины.tolist()).most_common(5)]}
            if len(длины) else None,
            "fcs_ethernet": _fcs_ethernet(self.клиенты()),
        }


def _fcs_ethernet(кадры: list[Кадр]) -> dict[str, int] | None:
    """Ethernet в GFP лежит с FCS (G.7041 7.1.1, по комментарию Wireshark): сколько FCS сошлось."""
    ethernet = [к.данные for к in кадры if к.upi == 1 and len(к.данные) >= 18]
    if not ethernet:
        return None
    return {"верна": sum(1 for д in ethernet if fcs_ethernet_верна(д)), "всего": len(ethernet)}


def fcs_ethernet_верна(кадр: bytes) -> bool:
    return len(кадр) >= 18 and zlib.crc32(кадр[:-4]) == int.from_bytes(кадр[-4:], "little")


def разобрать(биты: np.ndarray, *, маска: int | str | None = None, скремблер: str = "авто",
              порядок: str = "авто", многочлен: str = "стандарт", от_бита: int = 0,
              всего_бит: int | None = None) -> РазборGFP | None:
    """GFP во всём ряду. ``маска`` — число, «авто» или None (ищется); ``скремблер`` —
    «авто», «да» (x⁴³ + 1), «нет», «инверсия» (без скремблера, нагрузка инвертирована);
    ``порядок`` бит в байте — «авто», «старший», «младший»; ``многочлен`` — «стандарт»
    или «авто» (если с G.7041 пика нет — линейные части CRC-16 каталога RevEng); ряд — биты
    массива с ``от_бита``, во всём массиве ``всего_бит`` (по умолчанию — до конца ряда).
    None — GFP нет (почему — ``разобрать_с_причиной``)."""
    return разобрать_с_причиной(биты, маска=маска, скремблер=скремблер, порядок=порядок,
                                многочлен=многочлен, от_бита=от_бита, всего_бит=всего_бит)[0]


def разобрать_с_причиной(биты: np.ndarray, *, маска: int | str | None = None, скремблер: str = "авто",
                         порядок: str = "авто", многочлен: str = "стандарт", от_бита: int = 0,
                         всего_бит: int | None = None) -> tuple[РазборGFP | None, str]:
    """Как ``разобрать``, и почему GFP нет: найденное слепым поиском (маска не задана) проходит
    ту же проверку, что и автомат (``сомнение``) — иначе окно и ручной слой показывали бы «GFP»
    в HDLC, ATM, SDH. Причина пустая, если заголовков с верным cHEC подряд нет вовсе."""
    р = _разобрать(биты, маска=маска, скремблер=скремблер, порядок=порядок, многочлен=многочлен,
                   от_бита=от_бита)
    if р is not None:
        р.бит_участка = len(биты)
        р.всего_бит = от_бита + len(биты) if всего_бит is None else всего_бит
    if р is not None and not isinstance(маска, int) and (причина := сомнение(р)):
        return None, причина
    return р, ""


def _разобрать(биты: np.ndarray, *, маска: int | str | None, скремблер: str, порядок: str, многочлен: str,
               от_бита: int) -> РазборGFP | None:
    заданная = маска if isinstance(маска, int) else None
    порядки = ("старший", "младший") if порядок == "авто" else (порядок,)
    фаза = -от_бита % 8
    найдены = найти_маску(биты, маска=заданная, порядки=порядки, фаза=фаза)
    if not найдены and многочлен == "авто":
        найдены = найти_маску(биты, маска=заданная, порядки=порядки, модели=модели_каталога(), фаза=фаза)
    if not найдены:
        return None
    лучший = найдены[0]
    б = байты_ряда(биты, лучший.сдвиг, лучший.порядок, фаза)
    в = выделить(б, синдромы(б, лучший.модель), лучший.синдром, лучший.маска >> 16,
                 одиночные(лучший.модель))
    bb = б.tobytes()
    области = _области(bb, в)
    доли: dict[str, float] = {}
    if скремблер == "авто":
        варианты = ("x43", "нет", "инверсия")
        for режим in варианты:
            снятые, прогрев = снять_x43(dict(list(области.items())[:СВЕРКА_THEC]), в, режим)
            доли[режим] = доля_thec(снятые, прогрев, лучший.модель)
        режим = max(варианты, key=lambda р: (доли[р], р == "x43"))
    else:
        режим = {"да": "x43", "x43": "x43", "нет": "нет", "инверсия": "инверсия"}[скремблер]
    снятые, прогрев = снять_x43(области, в, режим)
    кадры: dict[int, Кадр] = {}
    for i, область in снятые.items():
        if в.pli[i] < 4:
            continue                                # служебный кадр — поля типа нет
        # Заголовок типа в прогреве дескремблера не восстановлен — кадр не разбирается.
        к = Кадр(i, область, прогрев=True, thec="прогрев") if i in прогрев else \
            разобрать_нагрузку(i, область, лучший.модель)
        к.оборван = в.места[i] + 4 + в.pli[i] > len(bb)
        кадры[i] = к
    итог = РазборGFP(лучший.маска, лучший.сдвиг, лучший.порядок, лучший.модель, в, кадры, режим, доли,
                     len(bb), от_бита)
    итог.gfp_t = суперблоки(итог.клиенты())
    return итог


