def кадр_gfp(р: РазборGFP, i: int) -> bytes:
    """Кадр GFP для pcap (LINKTYPE_GFP_F, как ждёт Wireshark): основной заголовок без маски,
    область нагрузки без скремблера."""
    в = р.выделение
    pli = в.pli[i]
    заголовок = pli.to_bytes(2, "big") + hec16(pli.to_bytes(2, "big")).to_bytes(2, "big")
    к = р.кадры.get(i)
    return заголовок + (к.нагрузка if к is not None else b"")


def клиентские_кадры(р: РазборGFP, cid: int | None = None) -> kanal.Кадры | None:
    """Кадры клиентов с типом канала pcap по UPI (Ethernet — без FCS, если она верна);
    клиенты разных или неизвестных видов — кадры GFP целиком (LINKTYPE 171)."""
    клиенты = р.клиенты(cid)
    if not клиенты:
        return None
    виды = {к.upi for к in клиенты}
    if len(виды) == 1 and (upi := next(iter(виды))) in UPI_LINKTYPE:
        return kanal.Кадры([к.данные[:-4] if upi == 1 and fcs_ethernet_верна(к.данные) else к.данные
                            for к in клиенты], UPI_LINKTYPE[upi])
    return кадры_gfp(р, cid)


def кадры_gfp(р: РазборGFP, cid: int | None = None) -> kanal.Кадры | None:
    """Кадры GFP с нагрузкой (без пустых и прогрева) — pcap LINKTYPE_GFP_F."""
    номера = [i for i, к in р.кадры.items() if not к.прогрев and not к.оборван and к.thec != "ошибка"
              and (cid is None or к.cid == cid)]
    return kanal.Кадры([кадр_gfp(р, i) for i in номера], LINKTYPE_GFP_F) if номера else None


def выход(р: РазборGFP, вид: str = "поток", cid: int | None = None) -> np.ndarray:
    """Биты для следующего этапа: «поток» — области нагрузки подряд (без скремблера),
    «клиенты» — поля данных клиента подряд (так находится вложенный GFP), «кадры» —
    кадры GFP целиком подряд (заголовок без маски, нагрузка без скремблера)."""
    if вид == "клиенты":
        части = [к.данные for к in р.клиенты(cid)]
    elif вид == "кадры":
        части = [кадр_gfp(р, i) for i in range(len(р.выделение.места))
                 if cid is None or (i in р.кадры and р.кадры[i].cid == cid)]
    else:
        части = [к.нагрузка for i, к in sorted(р.кадры.items()) if not к.прогрев
                 and (cid is None or к.cid == cid)]
    return в_биты(b"".join(части))


def слой(р: РазборGFP, вид: str = "поток", cid: int | None = None) -> str:
    """Строка ручного слоя, которая снимает этот GFP."""
    return (f"gfp маска {р.маска:08X} скремблер {'да' if р.скремблер == 'x43' else р.скремблер}"
            + (f" порядок {р.порядок}" if р.порядок != "старший" else "")
            + (" многочлен авто" if р.модель != СТАНДАРТ else "")
            + (f" с бита {р.от_бита}" if р.от_бита else "")
            + (f" канал {cid}" if cid is not None else "") + f" выход {вид}")


