"""Исправление ошибок двоичного линейного кода по синдрому — лидеры смежных классов.

Проверочная матрица H (r × n) найдена по потоку. Ошибка e даёт синдром H·eᵀ; у кода
с минимальным расстоянием d все ошибки веса ≤ t = ⌊(d − 1)/2⌋ дают разные синдромы.
Таблица «синдром → ошибка» строится перебором весов 1, 2, …: ошибка веса w попадает в
таблицу, если её синдром ещё не занят ошибкой меньшего веса и не общий у двух ошибок
веса w (тогда исправление было бы угадыванием). Гарантированная способность t —
наибольший вес, до которого все ошибки попали в таблицу; сверх неё таблица дописывает
однозначные классы следующего веса (так декодирует и приёмник: ближайшее кодовое
слово). Синдром вне таблицы — ошибка обнаружена, но не исправлена.

Так исправляются коды Хэмминга (t = 1), Голея (t = 3), короткие БЧХ и любые линейные
коды, у которых проверок немного (r ≤ 64) и таблица не больше ТАБЛИЦА_ДО записей.
"""

from __future__ import annotations

from itertools import combinations
from math import comb

import numpy as np

from . import gf2

#: Наибольшее число записей таблицы синдромов (ошибок, перебираемых по весам).
ТАБЛИЦА_ДО = 1 << 20
#: Наибольший перебираемый вес ошибки.
ВЕС_ДО = 6


class Таблица:
    """Синдромы (упорядочены) → места ошибки; t — гарантированная исправляющая способность."""

    def __init__(self, синдромы: np.ndarray, места: np.ndarray, t: int, r: int):
        self.синдромы, self.места, self.t, self.r = синдромы, места, t, r

    def __len__(self) -> int:
        return len(self.синдромы)


def _в_числа(биты: np.ndarray) -> np.ndarray:
    """Строки бит (≤ 64) → uint64, бит j — разряд j."""
    веса = (np.uint64(1) << np.arange(биты.shape[1], dtype=np.uint64))
    return (биты.astype(np.uint64) * веса).sum(axis=1, dtype=np.uint64) if биты.shape[1] else \
        np.zeros(len(биты), dtype=np.uint64)


def независимые(H: np.ndarray) -> np.ndarray:
    """Независимые строки H (ступенчатый вид над GF(2))."""
    if not len(H):
        return H
    n = H.shape[1]
    ред, опорные = gf2.привести(gf2.упаковать(np.asarray(H, dtype=np.uint8)), n)
    return gf2.распаковать(ред, n)[:len(опорные)]


def таблица(H: np.ndarray) -> Таблица | None:
    """Таблица исправления по проверкам H (строки — проверки) или None, если проверок > 64.

    Веса перебираются, пока все ошибки веса w однозначны (t = w); на первом весе с
    совпадениями в таблицу идут только однозначные классы, и перебор кончается.
    """
    H = независимые(H)
    r, n = H.shape if len(H) else (0, 0)
    if not r or r > 64:
        return None
    столбцы = _в_числа(H.T)                              # синдром ошибки в месте j
    известные = np.zeros(1, dtype=np.uint64)             # синдромы ошибок меньшего веса и 0
    записи_с: list = []
    записи_м: list = []
    t = 0
    for w in range(1, min(ВЕС_ДО, n) + 1):
        if len(записи_с) + comb(n, w) > ТАБЛИЦА_ДО:
            break
        места = np.array(list(combinations(range(n), w)), dtype=np.int32)
        синдр = np.bitwise_xor.reduce(столбцы[места], axis=1)
        значения, обратно, сколько = np.unique(синдр, return_inverse=True, return_counts=True)
        годные = (~np.isin(значения, известные) & (сколько == 1))[обратно]
        записи_с.append(синдр[годные])
        записи_м.append(np.pad(места[годные], ((0, 0), (0, ВЕС_ДО - w)), constant_values=-1))
        известные = np.union1d(известные, значения)
        if not годные.all():
            break
        t = w
        if len(известные) >= (1 << r):
            break
    синдромы = np.concatenate(записи_с) if записи_с else np.zeros(0, dtype=np.uint64)
    места = np.concatenate(записи_м) if записи_м else np.zeros((0, ВЕС_ДО), dtype=np.int32)
    порядок = np.argsort(синдромы)
    return Таблица(синдромы[порядок], места[порядок], t, r)


def исправить(слова: np.ndarray, H: np.ndarray, т: Таблица | None = None
              ) -> tuple[np.ndarray, np.ndarray, Таблица | None]:
    """Исправить слова (строки бит): (исправленные, исправлено бит в слове (−1 — нет), таблица)."""
    слова = np.array(слова, dtype=np.uint8)
    т = т if т is not None else таблица(H)
    исправлено = np.zeros(len(слова), dtype=np.int64)
    if т is None:
        return слова, исправлено, None
    H = независимые(H)
    синдр = _в_числа((слова.astype(np.int64) @ H.T.astype(np.int64)) % 2)
    ненулевые = np.flatnonzero(синдр)
    if not len(ненулевые) or not len(т):
        исправлено[ненулевые] = -1
        return слова, исправлено, т
    i = np.minimum(np.searchsorted(т.синдромы, синдр[ненулевые]), len(т) - 1)
    найдено = т.синдромы[i] == синдр[ненулевые]
    for слово, строка in zip(ненулевые[найдено].tolist(), i[найдено].tolist(), strict=False):
        места = т.места[строка]
        места = места[места >= 0]
        слова[слово, места] ^= 1
        исправлено[слово] = len(места)
    исправлено[ненулевые[~найдено]] = -1
    return слова, исправлено, т
