"""Поток TDM из псевдопроводов в захвате: SAToP (RFC 4553), CESoPSN (RFC 5086), CESoETH (MEF 8).

Пакеты разбирает анализатор пакетов (setevoy): уровень «PW-TDM» даёт номер и место нагрузки,
цепь различается меткой MPLS или ECID. В UDP номера портов у псевдопровода не закреплены, поэтому
поток UDP признаётся TDM по виду: у почти всех датаграмм одна длина, первые 4 бита слова — нули,
номера идут подряд. RTP (12 байт, версия 2, номер = номеру слова) — в UDP перед словом, в MPLS —
после него (Wireshark packet-pw-satop.c).

Нагрузки ставятся по номеру (16 бит, с переходом через 65535); пропавший пакет заполняется
единицами (так приёмник подставляет AIS) — длина потока и положение кадров не сбиваются.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from dataclasses import dataclass, field

import numpy as np

from .nahodka import Находка

ПАКЕТОВ_ОТ = 16
ДОЛЯ_ПОДРЯД = 0.9


@dataclass
class Цепь:
    """Одна цепь TDM: откуда, куски (номер, нагрузка) и итог сборки."""
    имя: str
    куски: list[tuple[int, bytes]] = field(default_factory=list)
    rtp: bool = False


def _rtp(д: bytes, м: int, номер: int) -> bool:
    """RTP версии 2 без маркера, номер как у слова псевдопровода."""
    return len(д) >= м + 12 and д[м] == 0x80 and not д[м + 1] & 0x80 and int.from_bytes(д[м + 2:м + 4], "big") == номер


def _из_mpls(п) -> tuple[str, int, bytes, bool] | None:
    """Пакет, разобранный как PW-TDM: (цепь, номер, нагрузка, есть RTP)."""
    уровни = {у.протокол: у for у in п.уровни}
    у = уровни.get("PW-TDM")
    if у is None:
        return None
    д = п.данные
    м = у.смещение
    номер = int.from_bytes(д[м + 2:м + 4], "big")
    длина_cw = д[м + 1] & 0x3F
    начало, конец = м + 4, (м + длина_cw if длина_cw else len(д))
    rtp = _rtp(д, начало, номер)
    if rtp:
        начало += 12
    if "CESoETH" in уровни:
        цепь = f"MEF 8, ECID 0x{int.from_bytes(д[уровни['CESoETH'].смещение:уровни['CESoETH'].смещение + 4], 'big') >> 12:05x}"
    else:
        метки = п.поля_фильтра().get("mpls.label", [])
        цепь = "MPLS, метки " + "/".join(str(м_) for м_ in метки)
    return цепь, номер, д[начало:max(начало, конец)], rtp


def _из_udp(п) -> tuple[str, bytes] | None:
    """Датаграмма UDP, которую никто не опознал: (поток, нагрузка) — кандидат в псевдопровод."""
    # RTP опознаётся анализатором сам (по версии 2) — нагрузку UDP берём целиком, от заголовка UDP.
    if п.порт_от is None or п.протокол not in ("UDP", "RTP"):
        return None
    у = next((у_ for у_ in п.уровни if у_.протокол == "UDP"), None)
    if у is None:
        return None
    поля = п.поля_фильтра()
    длина = (поля.get("udp.length") or [0])[0]
    нагрузка = п.данные[у.смещение + 8:у.смещение + max(8, длина)]
    if len(нагрузка) < 8:
        return None
    src = (поля.get("ip.src") or поля.get("ipv6.src") or ["?"])[0]
    dst = (поля.get("ip.dst") or поля.get("ipv6.dst") or ["?"])[0]
    return f"UDP {src}:{п.порт_от} → {dst}:{п.порт_к}", нагрузка


def _udp_как_tdm(датаграммы: list[bytes]) -> tuple[list[tuple[int, bytes]], bool] | None:
    """Поток UDP — псевдопровод TDM? Одна длина, слово с нулями в битах 0–3, номера подряд."""
    if len(датаграммы) < ПАКЕТОВ_ОТ:
        return None
    длина, сколько = Counter(len(д) for д in датаграммы).most_common(1)[0]
    if сколько < ДОЛЯ_ПОДРЯД * len(датаграммы):
        return None
    for rtp in (False, True):
        сдвиг = 12 if rtp else 0
        if длина < сдвиг + 8:
            continue
        куски, подряд, прежний = [], 0, None
        for д in датаграммы:
            if len(д) != длина or д[сдвиг] & 0xF0 or д[сдвиг + 1] & 0xC0:
                continue
            номер = int.from_bytes(д[сдвиг + 2:сдвиг + 4], "big")
            if rtp and not _rtp(д, 0, номер):
                continue
            подряд += прежний is not None and номер == (прежний + 1) & 0xFFFF
            прежний = номер
            куски.append((номер, д[сдвиг + 4:]))
        if len(куски) >= ДОЛЯ_ПОДРЯД * len(датаграммы) and подряд >= ДОЛЯ_ПОДРЯД * (len(куски) - 1):
            return куски, rtp
    return None


def собрать(куски: list[tuple[int, bytes]]) -> tuple[bytes, int, int]:
    """Нагрузки по номеру (с переходом через 65535): (поток, пропущено пакетов, повторов)."""
    if not куски:
        return b"", 0, 0
    полные, база, прежний = [], 0, None
    for номер, нагрузка in куски:
        if прежний is not None and номер < прежний and прежний - номер > 0x8000:
            база += 0x10000
        elif прежний is not None and номер > прежний and номер - прежний > 0x8000:
            база -= 0x10000
        полные.append((база + номер, нагрузка))
        прежний = номер
    по_номеру: dict[int, bytes] = {}
    повторов = 0
    for н, нагрузка in полные:
        повторов += н in по_номеру
        по_номеру.setdefault(н, нагрузка)
    размер = Counter(len(н) for н in по_номеру.values()).most_common(1)[0][0]
    первый, последний = min(по_номеру), max(по_номеру)
    итог, пропущено = bytearray(), 0
    for н in range(первый, последний + 1):
        кусок = по_номеру.get(н)
        if кусок is None:
            пропущено += 1
            кусок = b"\xff" * размер
        итог += кусок
    return bytes(итог), пропущено, повторов


def цепи(записи) -> list[tuple[Цепь, bytes, int, int]]:
    """Цепи TDM захвата: (цепь, поток байт, пропущено пакетов, повторов) — самые длинные первыми."""
    from ..setevoy import разобрать_пакет  # noqa: PLC0415
    по_имени: dict[str, Цепь] = {}
    udp: dict[str, list[bytes]] = defaultdict(list)
    for запись in записи:
        п = разобрать_пакет(запись.данные, запись.канал)
        найдено = _из_mpls(п)
        if найдено is not None:
            имя, номер, нагрузка, rtp = найдено
            цепь = по_имени.setdefault(имя, Цепь(имя))
            цепь.куски.append((номер, нагрузка))
            цепь.rtp |= rtp
            continue
        кандидат = _из_udp(п)
        if кандидат is not None:
            udp[кандидат[0]].append(кандидат[1])
    for имя, датаграммы in udp.items():
        как_tdm = _udp_как_tdm(датаграммы)
        if как_tdm is not None:
            по_имени[имя] = Цепь(имя, как_tdm[0], как_tdm[1])
    итог = []
    for цепь in по_имени.values():
        if len(цепь.куски) < ПАКЕТОВ_ОТ:
            continue
        поток, пропущено, повторов = собрать(цепь.куски)
        итог.append((цепь, поток, пропущено, повторов))
    итог.sort(key=lambda т: -len(т[1]))
    return итог


def найти(записи) -> Находка | None:
    """Находка «псевдопроводы TDM»: цепи и их потоки (байты) — дальше разбирается каждый поток."""
    найдено = цепи(записи)
    if not найдено:
        return None
    подробно, дальше = [], {}
    for цепь, поток, пропущено, повторов in найдено:
        размер = Counter(len(н) for _, н in цепь.куски).most_common(1)[0][0]
        вид = (f"кратно 32 байтам — E1 целиком (SAToP), {размер // 32} кадров G.704 на пакет" if размер % 32 == 0
               else f"кратно 24 — T1 целиком, {размер // 24} кадров на пакет" if размер % 24 == 0
               else "n×64 кбит/с (CESoPSN): число КИ на кадр — делитель нагрузки")
        подробно.append(f"{цепь.имя}: пакетов {len(цепь.куски)}, нагрузка {размер} байт — {вид}"
                        + (", с RTP" if цепь.rtp else "")
                        + f"; собрано {len(поток)} байт, пропущено пакетов {пропущено} (заполнены единицами)"
                        + (f", повторов {повторов}" if повторов else ""))
        дальше[цепь.имя] = np.unpackbits(np.frombuffer(поток, dtype=np.uint8))
    полных = sum(1 for _, _, п_, _ in найдено if п_ == 0)
    return Находка(
        уровень="канальный", что=f"псевдопроводы TDM (SAToP / CESoPSN / MEF 8): цепей {len(найдено)}",
        уверенность=полных / len(найдено),
        мера=f"нагрузки поставлены по номерам слова псевдопровода; без пропусков — {полных} из {len(найдено)}",
        подробно=подробно, дальше=дальше, вид_дальше="притоки")
