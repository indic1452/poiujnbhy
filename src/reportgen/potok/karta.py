"""Карта файла: участки разной природы, известные сигнатуры, сжатие, pcap.

Запись с объекта редко однородна: заголовок прибора, вставки служебных
данных, сжатые куски, участки шума между сеансами. Прежде чем разбирать
поток, полезно увидеть его «рельеф»:

- **энтропия по окнам** — где поток случаен (шифр, сжатие, скремблер или
  код над случайными данными), где упорядочен (текст, заголовки,
  заполнение), где пусто; границы участков;
- **сигнатуры** известных форматов в любом месте файла: архивы и сжатие
  (gzip, zlib, zip, bzip2, xz, 7z), изображения, PDF, исполняемые файлы,
  захваты сетевого трафика (pcap, pcapng);
- **сжатие** проверяется делом — попыткой распаковать: сигнатура zlib из
  двух байт встречается и случайно;
- **pcap** разбирается сразу: пакеты по заголовкам записей и тип канального
  уровня — дальше это кадры для разбора IP.

Высокая энтропия сама по себе не отличает шифр от сжатия и от кода над
случайными данными; поэтому в отчёте это «похоже на случайный», а не
«зашифровано».
"""

from __future__ import annotations

import struct
import zlib

import numpy as np

from .nahodka import Находка
from .statistika import энтропия

ОКНО = 4096

СИГНАТУРЫ = (
    (b"\x1f\x8b\x08", "gzip"), (b"PK\x03\x04", "zip"), (b"BZh", "bzip2"),
    (b"\xfd7zXZ\x00", "xz"), (b"7z\xbc\xaf\x27\x1c", "7z"), (b"\x89PNG\r\n\x1a\n", "PNG"),
    (b"\xff\xd8\xff", "JPEG"), (b"%PDF-", "PDF"), (b"\x7fELF", "ELF"),
    (b"\xd4\xc3\xb2\xa1", "pcap"), (b"\xa1\xb2\xc3\xd4", "pcap"),
    (b"\x4d\x3c\xb2\xa1", "pcap (нс)"), (b"\xa1\xb2\x3c\x4d", "pcap (нс)"),
    (b"\x0a\x0d\x0d\x0a", "pcapng"), (b"RIFF", "RIFF (WAV/AVI)"), (b"OggS", "Ogg"),
)
#: Типы канального уровня pcap (LINKTYPE_*): что лежит в записи.
КАНАЛЫ_PCAP = {0: "loopback BSD", 1: "Ethernet", 9: "PPP", 12: "IP", 101: "IP",
               104: "Cisco HDLC", 113: "Linux cooked", 228: "IPv4", 229: "IPv6"}


def участки(данные: bytes, окно: int = ОКНО) -> list[tuple[int, int, str, float]]:
    """(начало, конец, характер, средняя энтропия) — соседние окна одного характера слиты."""
    итог: list[tuple[int, int, str, float]] = []
    for начало in range(0, len(данные), окно):
        кусок = данные[начало:начало + окно]
        if len(кусок) < 64:
            break
        h = энтропия(np.frombuffer(кусок, dtype=np.uint8))
        if len(set(кусок)) == 1:
            характер = f"заполнение 0x{кусок[0]:02X}"
        elif h > 7.5:
            характер = "похоже на случайный"
        elif h > 5.5:
            характер = "смешанный"
        else:
            характер = "упорядоченный"
        if итог and итог[-1][2] == характер:
            н, _, х, сред = итог[-1]
            итог[-1] = (н, начало + len(кусок), х, (сред + h) / 2)
        else:
            итог.append((начало, начало + len(кусок), характер, h))
    # Короткие участки (меньше четырёх окон) — колебание около порога, а не
    # другая природа: вливаем их в предыдущий.
    слитые: list[tuple[int, int, str, float]] = []
    for участок in итог:
        н, к, х, h = участок
        if слитые and (к - н < 4 * окно or слитые[-1][2] == х):
            пн, _, пх, ph = слитые[-1]
            слитые[-1] = (пн, к, пх, (ph + h) / 2)
        else:
            слитые.append(участок)
    return слитые


def сигнатуры(данные: bytes, предел: int = 50) -> list[tuple[int, str]]:
    найдено: list[tuple[int, str]] = []
    for подпись, имя in СИГНАТУРЫ:
        место = данные.find(подпись)
        while место >= 0 and len(найдено) < предел:
            найдено.append((место, имя))
            место = данные.find(подпись, место + 1)
    return sorted(найдено)


def распаковать_zlib(данные: bytes, предел: int = 200) -> list[tuple[int, int, bytes]]:
    """Куски zlib: (место, сжатых байт, распакованное) — только те, что распаковались."""
    итог = []
    for место in range(len(данные) - 2):
        if len(итог) >= предел:
            break
        b0, b1 = данные[место], данные[место + 1]
        if b0 & 0x0F != 8 or (b0 << 8 | b1) % 31:
            continue
        распаковщик = zlib.decompressobj()
        try:
            вышло = распаковщик.decompress(данные[место:место + (1 << 22)], 1 << 24)
        except zlib.error:
            continue
        if распаковщик.eof and len(вышло) >= 16:
            сжато = len(данные[место:место + (1 << 22)]) - len(распаковщик.unused_data)
            итог.append((место, сжато, вышло))
    return итог


def pcap(данные: bytes) -> tuple[str, list[bytes]] | None:
    """Классический pcap: тип канала и пакеты (кадры канального уровня)."""
    if len(данные) < 24:
        return None
    магия = данные[:4]
    if магия in (b"\xd4\xc3\xb2\xa1", b"\x4d\x3c\xb2\xa1"):
        порядок = "<"
    elif магия in (b"\xa1\xb2\xc3\xd4", b"\xa1\xb2\x3c\x4d"):
        порядок = ">"
    else:
        return None
    канал = struct.unpack(порядок + "I", данные[20:24])[0] & 0xFFFF
    место = 24
    пакеты: list[bytes] = []
    while место + 16 <= len(данные) and len(пакеты) < 200_000:
        _, _, записано, _ = struct.unpack(порядок + "IIII", данные[место:место + 16])
        if записано > 262_144 or место + 16 + записано > len(данные):
            break
        пакеты.append(данные[место + 16:место + 16 + записано])
        место += 16 + записано
    return КАНАЛЫ_PCAP.get(канал, f"тип {канал}"), пакеты


def описать(данные: bytes) -> Находка | None:
    """Карта файла для отчёта — если в нём есть что-то кроме однородного потока."""
    карта = участки(данные)
    подписи = сигнатуры(данные)
    сжатое = распаковать_zlib(данные[:1 << 22]) if len(данные) <= 64 << 20 else []
    if len(карта) <= 1 and not подписи and not сжатое:
        return None
    подробно = []
    if len(карта) > 1:
        подробно.append("участки (по окнам 4 КБ): " + "; ".join(
            f"{н:#x}–{к:#x}: {х} ({h:.2f} бит/байт)" for н, к, х, h in карта[:12])
            + (" …" if len(карта) > 12 else ""))
    if подписи:
        подробно.append("сигнатуры: " + ", ".join(f"{имя} @ {место:#x}"
                                                   for место, имя in подписи[:12]))
    if сжатое:
        подробно.append("распаковались куски zlib: " + ", ".join(
            f"@ {м:#x}: {с} → {len(в)} байт" for м, с, в in сжатое[:6]))
    return Находка(уровень="файл", что="карта файла: " + (
        f"{len(карта)} участков разной природы" if len(карта) > 1 else "однородный")
        + (f"; сигнатуры: {', '.join(sorted({и for _, и in подписи}))}" if подписи else ""),
        уверенность=1.0, мера="энтропия по окнам, сигнатуры, пробная распаковка",
        подробно=подробно, дальше=сжатое or None, вид_дальше="распакованное" if сжатое else "")
