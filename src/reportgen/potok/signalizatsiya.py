"""Сигнализация E1: биты ABCD по каналам (CAS в КИ16), линейная R2, тоны MFC R2, R1/R1.5 и DTMF.

CAS (G.704 5.1.3): сверхцикл из 16 циклов; в цикле 0 КИ16 начинается с 0000 (MFAS), в цикле k
(1…15) старшая тетрада КИ16 — ABCD канала КИ k, младшая — канала КИ k+16.

Линейная R2 (Q.421, цифровая): смысл имеют биты A и B (C D обычно 01). Состояния — как в openr2
(src/r2proto.c standard_cas_signals): вперёд 10 — исходное / отбой вперёд, 00 — занятие; назад
10 — исходное, 11 — подтверждение занятия, отбой назад или блокировка, 01 — ответ.

Тоны — в каналах с речью A-закона (G.711): отсчёты 8000 в секунду, энергия частот — Гёрцелем по
блокам. MFC R2 (Q.441): вперёд 1380…1980 Гц, назад 1140…540 Гц, шаг 120 Гц, «2 из 6», код пары —
как r2_mf_positions openr2 (1247B-358C--69D---0E----F), блок 133 отсчёта, порог 5·10⁸, перекос
не больше 5 раз, прочие частоты слабее второй в 12,6 раза (r2engine.c). R1 / R1.5 (российская
многочастотная, «2 из 6»): 700…1700 Гц, шаг 200 Гц, код пары — bell_mf_positions spandsp
(1247C-358A--69*---0B----#), блок 120. DTMF: строки 697/770/852/941, столбцы 1209/1336/1477/1633
(spandsp dtmf.c, 123A 456B 789C *0#D), блок 102.
"""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

ЧАСТОТА = 8000

# -- A-закон (G.711) -----------------------------------------------------------------------


def _alaw_таблица() -> np.ndarray:
    """Байт A-закона → отсчёт (как alaw2lin G.711: инверсия чётных бит 0x55, знак, сегмент)."""
    итог = np.zeros(256, dtype=np.int32)
    for б in range(256):
        a = б ^ 0x55
        сегмент = (a >> 4) & 7
        мантисса = a & 0x0F
        значение = (мантисса << 4) + 8 if сегмент == 0 else ((мантисса << 4) + 0x108) << (сегмент - 1)
        итог[б] = значение if a & 0x80 else -значение
    return итог


ALAW = _alaw_таблица()


def отсчёты(байты: np.ndarray) -> np.ndarray:
    return ALAW[np.asarray(байты, dtype=np.uint8)]


# -- Гёрцель по блокам ---------------------------------------------------------------------


def энергии(x: np.ndarray, частоты: Sequence[float], блок: int) -> np.ndarray:
    """|X(f)|² каждого блока из ``блок`` отсчётов для каждой частоты: (блоков, частот)."""
    блоков = len(x) // блок
    if not блоков:
        return np.zeros((0, len(частоты)))
    кадры = x[:блоков * блок].reshape(блоков, блок).astype(np.float64)
    n = np.arange(блок)
    базис = np.exp(-2j * np.pi * np.outer(np.asarray(частоты, dtype=np.float64), n) / ЧАСТОТА)
    return np.abs(кадры @ базис.T) ** 2


@dataclass(frozen=True)
class Набор:
    имя: str
    частоты: Tuple[float, ...]
    блок: int
    коды: str                       # код пары (i < j) по индексу i·5 + j − 1 (как в openr2/spandsp)
    порог: float
    перекос: float = 5.0
    пик: float = 12.6


MFC_ВПЕРЁД = Набор("MFC R2 вперёд", (1380.0, 1500.0, 1620.0, 1740.0, 1860.0, 1980.0), 133,
                   "1247B-358C--69D---0E----F", 5.0e8)
MFC_НАЗАД = Набор("MFC R2 назад", (1140.0, 1020.0, 900.0, 780.0, 660.0, 540.0), 133,
                  "1247B-358C--69D---0E----F", 5.0e8)
R1 = Набор("R1 / R1.5 (700–1700 Гц)", (700.0, 900.0, 1100.0, 1300.0, 1500.0, 1700.0), 120,
           "1247C-358A--69*---0B----#", 5.0e8 * (120 / 133) ** 2)
ДВА_ИЗ_ШЕСТИ = (MFC_ВПЕРЁД, MFC_НАЗАД, R1)
DTMF_СТРОКИ = (697.0, 770.0, 852.0, 941.0)
DTMF_СТОЛБЦЫ = (1209.0, 1336.0, 1477.0, 1633.0)
DTMF_КОДЫ = "123A456B789C*0#D"
DTMF_БЛОК = 102
DTMF_ПОРОГ = 5.0e8 * (102 / 133) ** 2


def _два_из_шести(э: np.ndarray, набор: Набор) -> List[str]:
    """Код каждого блока ('' — нет тона) по правилу openr2: две сильнейшие частоты, перекос, пик."""
    порядок = np.argsort(-э, axis=1)
    итог = []
    for строка, (б, в) in zip(э, порядок[:, :2], strict=True):
        if not (строка[б] >= набор.порог and строка[в] >= набор.порог and строка[б] < строка[в] * набор.перекос):
            итог.append("")
            continue
        прочие = np.delete(строка, [б, в])
        if np.any(прочие * набор.пик >= строка[в]):
            итог.append("")
            continue
        i, j = sorted((int(б), int(в)))
        итог.append(набор.коды[i * 5 + j - 1])
    return итог


def _dtmf(x: np.ndarray) -> List[str]:
    стр = энергии(x, DTMF_СТРОКИ, DTMF_БЛОК)
    стб = энергии(x, DTMF_СТОЛБЦЫ, DTMF_БЛОК)
    итог = []
    for р, с in zip(стр, стб, strict=True):
        i, j = int(р.argmax()), int(с.argmax())
        if р[i] < DTMF_ПОРОГ or с[j] < DTMF_ПОРОГ or р[i] > с[j] * 6.3 or с[j] > р[i] * 2.5:
            итог.append("")
            continue
        if np.any(np.delete(р, i) * 6.3 >= р[i]) or np.any(np.delete(с, j) * 6.3 >= с[j]):
            итог.append("")
            continue
        итог.append(DTMF_КОДЫ[4 * i + j])
    return итог


def цифры(коды: List[str], подряд: int = 2) -> List[Tuple[int, str]]:
    """Коды блоков → (номер блока начала, цифра): тон не короче ``подряд`` блоков, после паузы или смены."""
    итог, прежний, длина, начало = [], "", 0, 0
    for n, к in enumerate(коды + [""]):
        if к == прежний:
            длина += 1
            continue
        if прежний and длина >= подряд:
            итог.append((начало, прежний))
        прежний, длина, начало = к, 1, n
    return итог


def тоны(байты: np.ndarray) -> Optional[Tuple[str, List[Tuple[float, str]]]]:
    """Набор в канале: (вид сигнализации, [(секунда, цифра)]) — у какого набора больше цифр."""
    x = отсчёты(байты)
    лучший = None
    for набор in ДВА_ИЗ_ШЕСТИ:
        найдено = цифры(_два_из_шести(энергии(x, набор.частоты, набор.блок), набор))
        if найдено and (лучший is None or len(найдено) > len(лучший[1])):
            лучший = (набор.имя, [(н * набор.блок / ЧАСТОТА, ц) for н, ц in найдено])
    найдено = цифры(_dtmf(x))
    if найдено and (лучший is None or len(найдено) > len(лучший[1])):
        лучший = ("DTMF", [(н * DTMF_БЛОК / ЧАСТОТА, ц) for н, ц in найдено])
    return лучший


# -- ABCD и линейная R2 ------------------------------------------------------------------------

ВПЕРЁД = {0b10: "исходное / отбой вперёд", 0b00: "занятие"}
НАЗАД = {0b10: "исходное", 0b11: "подтверждение занятия / отбой назад / блокировка", 0b01: "ответ"}


def abcd(ки16: np.ndarray) -> Optional[Tuple[np.ndarray, List[int]]]:
    """ABCD каналов по сверхциклу CAS: (сверхциклы × 30 значений 0…15, номера КИ)."""
    байты = np.asarray(ки16, dtype=np.uint8)
    места = np.flatnonzero((байты >> 4) == 0)
    if len(места) < 4:
        return None
    шаг = Counter(np.diff(места).tolist()).most_common(1)[0][0]
    if шаг != 16:
        return None
    начало = int(Counter((места % 16).tolist()).most_common(1)[0][0])
    сверхциклов = (len(байты) - начало) // 16
    if сверхциклов < 2:
        return None
    таблица = байты[начало:начало + 16 * сверхциклов].reshape(сверхциклов, 16)
    значения = np.concatenate([таблица[:, 1:16] >> 4, таблица[:, 1:16] & 0x0F], axis=1)
    return значения, list(range(1, 16)) + list(range(17, 32))


def линия(значения: np.ndarray, номера: List[int]) -> List[str]:
    """Сводка по каналам: смена состояний AB и их смысл по Q.421 в прямом и обратном направлении."""
    строки = []
    for k, ки in enumerate(номера):
        ряд = (значения[:, k] >> 2).tolist()
        смены = [ряд[0]] + [b for a, b in zip(ряд, ряд[1:], strict=False) if b != a]
        if len(смены) == 1:
            continue
        виды = set(смены)
        if виды <= set(ВПЕРЁД):
            толк, имена = "вперёд", ВПЕРЁД
        elif виды <= set(НАЗАД):
            толк, имена = "назад", НАЗАД
        else:
            толк, имена = "направление неясно", {}
        цепь = " → ".join(f"{v:02b}" + (f" ({имена[v]})" if v in имена else "") for v in смены[:8])
        строки.append(f"КИ{ки}: AB {цепь}" + (" …" if len(смены) > 8 else "") + f" — {толк}")
    return строки


def сводка(каналы: Dict[int, np.ndarray]) -> List[str]:
    """Строки для отчёта E1: ABCD по КИ16 и цифры набора в речевых каналах."""
    from .bity import в_байты  # noqa: PLC0415
    строки: List[str] = []
    if 16 in каналы and len(каналы[16]) >= 16 * 8 * 4:
        найдено = abcd(np.frombuffer(в_байты(каналы[16]), dtype=np.uint8))
        if найдено is not None:
            значения, номера = найдено
            постоянные = Counter(int(v) for v in значения[-1])
            строки.append(f"CAS: ABCD по {len(значения)} сверхциклам; последнее состояние каналов — "
                          + ", ".join(f"{v:04b}×{с}" for v, с in постоянные.most_common(4)))
            строки += линия(значения, номера)[:30]
    for ки, ряд in sorted(каналы.items()):
        if ки in (0, 16) or len(ряд) < 8 * 2000:
            continue
        найдено = тоны(np.frombuffer(в_байты(ряд), dtype=np.uint8))
        if найдено is not None:
            вид, набор = найдено
            строки.append(f"КИ{ки}: {вид} — " + " ".join(ц for _, ц in набор[:40])
                          + (" …" if len(набор) > 40 else "") + f" (с {набор[0][0]:.2f} с)")
    return строки
