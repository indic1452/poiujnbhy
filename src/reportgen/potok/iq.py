"""Вход I/Q: отсчёты символов (мягкие решения) → созвездие по облаку → жёсткие решения → метки.

Если аналитику прислали не биты, а отсчёты символов I/Q, созвездие и его
поворот видны по облаку точек:

1. отсчёты: int8, uint8, int16, float32 чередованием I, Q (или Q, I), порядок
   байт — младшим или старшим вперёд; WAV с двумя каналами (PCM 8/16/24/32 бит
   или float32) — по заголовку;
2. кластеры — k-средних (Ллойд, начальные центры k-means++, без сторонних
   пакетов); число точек задаётся или находится: из степеней двойки берётся
   то, у которого отношение наименьшего расстояния между центрами к разбросу
   внутри кластеров наибольшее (лишние кластеры делят облако пополам —
   расстояние мало; недостающие сливают — разброс велик);
3. облако приводится к центру и единичной средней мощности центров; поворот
   (и инверсия спектра) — перебором угла с шагом 0,25° и уточнением: сумма
   квадратов расстояний от центров до ближайших идеальных точек плоскости;
4. жёсткие решения: ближайшая точка выбранной плоскости (.etl) — её метка;
   или «по кластерам»: метка — номер кластера по порядку чтения (сверху
   вниз, слева направо) — тогда разметку ищет «Разметка вслепую».

Облако оценивается по началу записи, а решения — по всей записи кусками
(``решения_по_всему``): запись в сотни мегабайт не берётся в память целиком.
"""

from __future__ import annotations

import math
import struct
from typing import Any

import numpy as np

#: Форматы отсчётов: (тип numpy без порядка байт, смещение нуля).
ФОРМАТЫ = {"int8": ("i1", 0.0), "uint8": ("u1", 127.5), "int16": ("i2", 0.0), "float32": ("f4", 0.0)}
#: k-средних: отсчётов в выборке для кластеров и итераций Ллойда.
ВЫБОРКА = 1 << 15
ВЫБОРКА_ЧИСЛА = 1 << 13
ИТЕРАЦИЙ = 60
#: Числа точек, которые пробуются при поиске.
ЧИСЛА_ТОЧЕК = (2, 4, 8, 16, 32, 64)
#: Картинка облака — не больше стольких точек.
ОБЛАКО_ДО = 4000
#: Число точек созвездия — не больше (задаётся; находится — из ``ЧИСЛА_ТОЧЕК``).
ТОЧЕК_ДО = 1024
#: Выборка для кластеров — не меньше стольких отсчётов на точку (у КАМ-1024 — 65 536 отсчётов).
НА_ТОЧКУ = 64


def _wav(данные: bytes) -> tuple[np.ndarray, str]:
    """RIFF/WAVE с двумя каналами → комплексные отсчёты (канал 1 — I, канал 2 — Q)."""
    if len(данные) < 12 or данные[:4] != b"RIFF" or данные[8:12] != b"WAVE":
        raise ValueError("не WAV: нет заголовка RIFF/WAVE")
    место, формат, данные_wav = 12, None, None
    while место + 8 <= len(данные):
        имя, размер = данные[место:место + 4], struct.unpack("<I", данные[место + 4:место + 8])[0]
        тело = данные[место + 8:место + 8 + размер]
        if имя == b"fmt " and len(тело) >= 16:
            тег, каналов, частота, _, _, бит = struct.unpack("<HHIIHH", тело[:16])
            if тег == 0xFFFE and len(тело) >= 26:
                тег = struct.unpack("<H", тело[24:26])[0]
            формат = (тег, каналов, частота, бит)
        elif имя == b"data":
            данные_wav = тело
        место += 8 + размер + (размер & 1)
    if формат is None or данные_wav is None:
        raise ValueError("WAV без блока fmt или data")
    тег, каналов, частота, бит = формат
    if каналов != 2:
        raise ValueError(f"WAV: каналов {каналов}, а для I/Q нужно два")
    if тег == 3 and бит == 32:
        x = np.frombuffer(данные_wav[:len(данные_wav) // 8 * 8], "<f4").astype(np.float64)
    elif тег == 1 and бит in (8, 16, 32):
        тип = {8: "u1", 16: "<i2", 32: "<i4"}[бит]
        x = np.frombuffer(данные_wav[:len(данные_wav) // (бит // 4) * (бит // 4)], тип).astype(np.float64)
        if бит == 8:
            x -= 128
    elif тег == 1 and бит == 24:
        сырьё = np.frombuffer(данные_wav[:len(данные_wav) // 6 * 6], np.uint8).reshape(-1, 3).astype(np.int32)
        x = (сырьё[:, 0] | (сырьё[:, 1] << 8) | (сырьё[:, 2] << 16)).astype(np.int64)
        x = np.where(x >= 1 << 23, x - (1 << 24), x).astype(np.float64)
    else:
        raise ValueError(f"WAV: формат {тег}, {бит} бит — поддерживаются PCM 8/16/24/32 и float32")
    x = x[:len(x) // 2 * 2]
    return x[0::2] + 1j * x[1::2], f"WAV: 2 канала, {бит} бит, {'float' if тег == 3 else 'PCM'}, {частота} Гц"


def прочитать(данные: bytes, формат: str = "авто", *, порядок: str = "младший", каналы: str = "IQ",
              пропуск: int = 0) -> tuple[np.ndarray, str]:
    """Байты → комплексные отсчёты и описание; ошибки ввода — ValueError.

    ``порядок`` — байт в числе: «младший» (little-endian) или «старший»;
    ``каналы`` — «IQ» или «QI»; ``пропуск`` — байт заголовка до отсчётов.
    «авто» — WAV по заголовку, иначе отказ: формат сырых отсчётов по байтам не угадать.
    """
    данные = bytes(данные)[max(0, int(пропуск)):]
    формат = str(формат or "авто").strip().lower()
    if формат in ("авто", "wav"):
        if данные[:4] == b"RIFF":
            z, описание = _wav(данные)
        elif формат == "wav":
            raise ValueError("не WAV: нет заголовка RIFF/WAVE")
        else:
            raise ValueError("формат отсчётов не определить по байтам: укажите int8, uint8, int16 или float32 "
                             "(или WAV)")
    elif формат in ФОРМАТЫ:
        тип, ноль = ФОРМАТЫ[формат]
        if порядок not in ("младший", "старший"):
            raise ValueError("порядок байт — младший или старший")
        dt = np.dtype(("<" if порядок == "младший" else ">") + тип)
        x = np.frombuffer(данные[:len(данные) // (2 * dt.itemsize) * 2 * dt.itemsize], dt).astype(np.float64) - ноль
        z = x[0::2] + 1j * x[1::2]
        описание = f"{формат}, I и Q чередованием, {порядок} байт первым" if dt.itemsize > 1 else \
            f"{формат}, I и Q чередованием"
    else:
        raise ValueError("формат отсчётов: int8, uint8, int16, float32 или WAV")
    if каналы not in ("IQ", "QI"):
        raise ValueError("порядок каналов — IQ или QI")
    if каналы == "QI":
        z = z.imag + 1j * z.real
        описание += "; каналы Q, I"
    z = z[np.isfinite(z)]
    if len(z) < 16:
        raise ValueError(f"отсчётов {len(z)}: для облака нужно хотя бы 16")
    return z, описание


# -- кластеры ----------------------------------------------------------------------------------

def _кусок(K: int) -> int:
    """Отсчётов в куске при расстояниях до K центров: матрица — не больше ~4 млн чисел (до 256 центров — 16 384)."""
    return min(1 << 14, max(256, (1 << 22) // max(1, K)))


def _ближайшие(z: np.ndarray, ц: np.ndarray) -> np.ndarray:
    """Номер ближайшего центра каждого отсчёта (кусками — без огромной матрицы расстояний); от БОЛЬШОЕ_K центров —
    по ячейкам (``_ближайшие_по_ячейкам``)."""
    if len(ц) >= БОЛЬШОЕ_K:
        return _ближайшие_по_ячейкам(np.asarray(z), np.asarray(ц))
    return _ближайшие_все(z, ц)


def _ближайшие_все(z: np.ndarray, ц: np.ndarray) -> np.ndarray:
    итог = np.empty(len(z), np.int64)
    шаг = _кусок(len(ц))
    for с in range(0, len(z), шаг):
        кусок = z[с:с + шаг]
        итог[с:с + len(кусок)] = ((кусок.real[:, None] - ц.real[None, :]) ** 2
                                 + (кусок.imag[:, None] - ц.imag[None, :]) ** 2).argmin(axis=1)
    return итог


def _ллойд(z: np.ndarray, K: int, rng: np.random.Generator, итераций: int,
           ц: np.ndarray | None = None) -> tuple[np.ndarray, np.ndarray, float]:
    if ц is None:
        центры = [z[rng.integers(len(z))]]
        до = np.abs(z - центры[0]) ** 2
        for _ in range(1, K):
            сумма = до.sum()
            i = int(rng.choice(len(z), p=до / сумма)) if сумма > 0 else int(rng.integers(len(z)))
            центры.append(z[i])
            до = np.minimum(до, np.abs(z - z[i]) ** 2)
        ц = np.array(центры)
    метки = _ближайшие(z, ц)
    for _ in range(итераций):
        счёт = np.bincount(метки, minlength=K)
        суммы = np.bincount(метки, weights=z.real, minlength=K) + 1j * np.bincount(метки, weights=z.imag, minlength=K)
        пустые = счёт == 0
        ц = np.where(пустые, ц, суммы / np.maximum(1, счёт))
        if пустые.any():
            # Пустой кластер — в самый далёкий от своего центра отсчёт.
            дальний = np.argsort(-np.abs(z - ц[метки]))[:int(пустые.sum())]
            ц[np.flatnonzero(пустые)] = z[дальний]
        новые = _ближайшие(z, ц)
        if np.array_equal(новые, метки):
            break
        метки = новые
    return ц, метки, float(np.mean(np.abs(z - ц[метки]) ** 2))


def _поправить(z: np.ndarray, ц: np.ndarray, м: np.ndarray, разброс: float, rng: np.random.Generator,
               итераций: int) -> tuple[np.ndarray, np.ndarray, float]:
    """Слить два слишком близких центра и разделить самый широкий кластер — пока разброс падает.

    Ллойд застревает, когда одну точку созвездия делят два центра, а две
    соседние — один: тогда пара центров вдвое ближе прочих.
    """
    K = len(ц)
    for _ in range(K):
        между = np.abs(ц[:, None] - ц[None, :])
        np.fill_diagonal(между, np.inf)
        ближний = между.min(axis=1)
        i = int(np.argmin(ближний))
        if ближний[i] >= 0.6 * float(np.median(ближний)):
            break
        j = int(np.argmin(между[i]))
        счёт = np.bincount(м, minlength=K)
        ширина = np.bincount(м, weights=np.abs(z - ц[м]) ** 2, minlength=K) / np.maximum(1, счёт)
        ширина[[i, j]] = -1
        w = int(np.argmax(ширина))
        новый = ц.copy()
        новый[i] = (ц[i] * счёт[i] + ц[j] * счёт[j]) / max(1, счёт[i] + счёт[j])
        точки = z[м == w]
        if len(точки) < 2:
            break
        # Делим по главному направлению разброса кластера.
        d = точки - точки.mean()
        угол = 0.5 * math.atan2(2 * float(np.mean(d.real * d.imag)), float(np.mean(d.real ** 2 - d.imag ** 2)))
        сдвиг = math.sqrt(max(1e-12, float(ширина[w]))) * np.exp(1j * угол)
        новый[w], новый[j] = ц[w] + сдвиг, ц[w] - сдвиг
        ц2, м2, р2 = _ллойд(z, K, rng, итераций, новый)
        if р2 >= разброс:
            break
        ц, м, разброс = ц2, м2, р2
    return ц, м, разброс


# -- большие созвездия (от 128 точек): k-means++ по подвыборке, Ллойд по кандидатам, поправка пачкой --------

#: С этого числа кластеров — быстрый путь: у КАМ-1024 полный Ллойд — 65 536 × 1024 расстояний на шаг.
БОЛЬШОЕ_K = 128
#: k-means++ — по подвыборке: столько отсчётов на кластер.
НАЧАЛО_НА_ТОЧКУ = 16
#: Поправка пачкой: кругов не больше; центр «лишний», если ближе этой доли медианы до ближайшего соседа;
#: кластер «двойной», если его разброс больше медианы во столько раз.
КРУГОВ_ПОПРАВКИ = 24
ЛИШНИЙ = 0.6
ДВОЙНОЙ = 4.0


class _Ячейки:
    """Точно ближайшая точка без матрицы отсчёты × точки: плоскость — ячейки со стороной h (медиана расстояния
    до ближайшей точки), отсчёт сравнивается с точками своей ячейки и восьми соседних. Если найденная точка
    дальше, чем край этих девяти ячеек, — ближе может оказаться другая: такие отсчёты (выбросы за краем облака,
    пустые места) — полным расчётом. У КАМ-1024 — 18 кандидатов вместо 1024. Ячеек больше ``ЯЧЕЕК_ДО`` или
    точек в ячейке больше 16 — всё полным расчётом."""

    def __init__(self, ц: np.ndarray):
        self.ц = ц = np.asarray(ц, dtype=np.complex128)
        K = len(ц)
        между = np.abs(ц[:, None] - ц[None, :])
        np.fill_diagonal(между, np.inf)
        self.h = h = float(np.median(между.min(axis=1))) if K > 1 else 0.0
        self.таблица = None
        if not h > 0:
            return
        self.x0, self.y0 = float(ц.real.min()) - h, float(ц.imag.min()) - h
        ix = np.floor((ц.real - self.x0) / h).astype(np.int64)
        iy = np.floor((ц.imag - self.y0) / h).astype(np.int64)
        self.Gx, self.Gy = Gx, Gy = int(ix.max()) + 2, int(iy.max()) + 2
        ячейка = ix * Gy + iy
        счёт = np.bincount(ячейка, minlength=Gx * Gy)
        if Gx * Gy > ЯЧЕЕК_ДО or int(счёт.max()) > 16:
            return
        порядок = np.argsort(ячейка, kind="stable")
        место = np.arange(K) - np.concatenate(([0], np.cumsum(счёт)[:-1]))[ячейка[порядок]]
        self.таблица = np.full((Gx * Gy, int(счёт.max())), -1, np.int64)
        self.таблица[ячейка[порядок], место] = порядок
        self.сдвиги = np.array([dx * Gy + dy for dx in (-1, 0, 1) for dy in (-1, 0, 1)])
        self.цк = np.append(ц, np.inf + 0j)                   # −1 — пустое место: бесконечно далеко

    def ближайшие(self, z: np.ndarray) -> np.ndarray:
        z = np.asarray(z, dtype=np.complex128)
        if self.таблица is None:
            return _ближайшие_все(z, self.ц)
        h, x0, y0, Gx, Gy = self.h, self.x0, self.y0, self.Gx, self.Gy
        итог = np.empty(len(z), np.int64)
        for с in range(0, len(z), 1 << 15):
            кусок = z[с:с + (1 << 15)]
            jx = np.clip(np.floor((кусок.real - x0) / h), 1, Gx - 2).astype(np.int64)
            jy = np.clip(np.floor((кусок.imag - y0) / h), 1, Gy - 2).astype(np.int64)
            кандидаты = self.таблица[(jx * Gy + jy)[:, None] + self.сдвиги[None, :]].reshape(len(кусок), -1)
            до = np.abs(кусок[:, None] - self.цк[кандидаты]) ** 2
            лучший = до.argmin(axis=1)
            ближе = до[np.arange(len(кусок)), лучший]
            край = np.minimum.reduce([кусок.real - (x0 + (jx - 1) * h), x0 + (jx + 2) * h - кусок.real,
                                      кусок.imag - (y0 + (jy - 1) * h), y0 + (jy + 2) * h - кусок.imag])
            итог[с:с + len(кусок)] = кандидаты[np.arange(len(кусок)), лучший]
            сомнительные = np.flatnonzero(~(ближе <= np.maximum(край, 0) ** 2))
            if len(сомнительные):
                итог[с + сомнительные] = _ближайшие_все(кусок[сомнительные], self.ц)
        return итог


def _ближайшие_по_ячейкам(z: np.ndarray, ц: np.ndarray) -> np.ndarray:
    return _Ячейки(ц).ближайшие(z)


#: Ячеек — не больше (иначе — полный расчёт).
ЯЧЕЕК_ДО = 1 << 20


def _ллойд_большой(z: np.ndarray, K: int, rng: np.random.Generator, итераций: int,
                   ц: np.ndarray | None = None) -> tuple[np.ndarray, np.ndarray, float]:
    """Ллойд для многих кластеров: k-means++ — по подвыборке (НАЧАЛО_НА_ТОЧКУ отсчётов на кластер), ближайший
    центр — по ячейкам (``_ближайшие``), остальное — как у ``_ллойд``."""
    if ц is None:
        начало = z if len(z) <= НАЧАЛО_НА_ТОЧКУ * K else z[rng.choice(len(z), НАЧАЛО_НА_ТОЧКУ * K, replace=False)]
        ц, _, _ = _ллойд(начало, K, rng, 0)                    # только k-means++ (ноль шагов Ллойда)
    return _ллойд(z, K, rng, итераций, np.array(ц, dtype=np.complex128))


def _поправить_пачкой(z: np.ndarray, ц: np.ndarray, м: np.ndarray, разброс: float, rng: np.random.Generator,
                      итераций: int) -> tuple[np.ndarray, np.ndarray, float]:
    """Как ``_поправить``, но сразу все пары: у 1024 кластеров k-means++ оставляет десятки точек созвездия с двумя
    центрами и столько же центров на двух точках. Центр «лишний» (ближе ЛИШНИЙ медианы до соседа) сливается
    с соседом, «двойной» кластер (разброс больше ДВОЙНОЙ медиан) делится по главному направлению — пока разброс
    падает, не больше КРУГОВ_ПОПРАВКИ кругов."""
    K = len(ц)
    for _ in range(КРУГОВ_ПОПРАВКИ):
        между = np.abs(ц[:, None] - ц[None, :])
        np.fill_diagonal(между, np.inf)
        ближний = между.min(axis=1)
        сосед = между.argmin(axis=1)
        счёт = np.bincount(м, minlength=K)
        ширина = np.bincount(м, weights=np.abs(z - ц[м]) ** 2, minlength=K) / np.maximum(1, счёт)
        занято = np.zeros(K, bool)
        пары = []
        for i in np.argsort(ближний, kind="stable"):
            if ближний[i] >= ЛИШНИЙ * float(np.median(ближний)):
                break
            j = int(сосед[i])
            if not занято[i] and not занято[j]:
                пары.append((int(i), j))
                занято[[i, j]] = True
        порог = ДВОЙНОЙ * float(np.median(ширина))
        широкие = [int(w) for w in np.argsort(-ширина, kind="stable") if ширина[w] > порог and not занято[w]
                   and счёт[w] >= 2][:len(пары)]
        if not широкие:
            break
        новый = ц.copy()
        for (i, j), w in zip(пары, широкие, strict=False):
            новый[i] = (ц[i] * счёт[i] + ц[j] * счёт[j]) / max(1, счёт[i] + счёт[j])
            точки = z[м == w]
            d = точки - точки.mean()
            угол = 0.5 * math.atan2(2 * float(np.mean(d.real * d.imag)), float(np.mean(d.real ** 2 - d.imag ** 2)))
            сдвиг = math.sqrt(max(1e-12, float(ширина[w]))) * np.exp(1j * угол)
            новый[w], новый[j] = ц[w] + сдвиг, ц[w] - сдвиг
        ц2, м2, р2 = _ллойд_большой(z, K, rng, итераций, новый)
        if р2 >= разброс:
            break
        ц, м, разброс = ц2, м2, р2
    return ц, м, разброс


#: k-средних: запусков с разных начальных центров (берётся с наименьшим разбросом); от БОЛЬШОЕ_K — один.
ЗАПУСКОВ = 4


def k_средних(z: np.ndarray, K: int, *, итераций: int = ИТЕРАЦИЙ, сид: int = 1, запусков: int = ЗАПУСКОВ
              ) -> tuple[np.ndarray, np.ndarray]:
    """Центры K кластеров и номер кластера каждого отсчёта: k-means++ и Ллойд, лучший из нескольких запусков.

    От ``БОЛЬШОЕ_K`` кластеров — быстрый путь (``_ллойд_большой``, ``_поправить_пачкой``), один запуск:
    у КАМ-1024 на 65 536 отсчётах — секунды.
    """
    z = np.asarray(z, dtype=np.complex128)
    if K < 1 or K > len(z):
        raise ValueError(f"кластеров {K}, а отсчётов {len(z)}")
    rng = np.random.default_rng(сид)
    if K >= БОЛЬШОЕ_K:
        ц, м, _ = _поправить_пачкой(z, *_ллойд_большой(z, K, rng, итераций), rng, итераций)
        return ц, м
    лучший = None
    for _ in range(max(1, запусков)):
        ц, м, разброс = _поправить(z, *_ллойд(z, K, rng, итераций), rng, итераций)
        if лучший is None or разброс < лучший[2]:
            лучший = (ц, м, разброс)
    return лучший[0], лучший[1]


def отделимость(z: np.ndarray, центры: np.ndarray, метки: np.ndarray) -> float:
    """Наименьшее расстояние между центрами к корню среднего квадрата разброса внутри кластеров."""
    if len(центры) < 2:
        return 0.0
    между = np.abs(центры[:, None] - центры[None, :])
    np.fill_diagonal(между, np.inf)
    разброс = math.sqrt(float(np.mean(np.abs(z - центры[метки]) ** 2))) or 1e-12
    return float(между.min()) / разброс


def число_точек(z: np.ndarray, варианты=ЧИСЛА_ТОЧЕК, *, сид: int = 1) -> tuple[int, list[dict[str, Any]]]:
    """Число точек созвездия по облаку: лучшая отделимость из степеней двойки; и оценка каждого."""
    выборка = _выборка(z, сид, ВЫБОРКА_ЧИСЛА)
    оценки = []
    for K in варианты:
        if K * 8 > len(выборка):
            continue
        ц, м = k_средних(выборка, K, сид=сид)
        оценки.append({"точек": K, "отделимость": round(отделимость(выборка, ц, м), 3)})
    if not оценки:
        raise ValueError("отсчётов мало для поиска числа точек")
    лучший = max(оценки, key=lambda о: о["отделимость"])
    return лучший["точек"], оценки


def _выборка(z: np.ndarray, сид: int = 1, сколько: int = ВЫБОРКА) -> np.ndarray:
    if len(z) <= сколько:
        return np.asarray(z)
    return np.asarray(z)[np.sort(np.random.default_rng(сид).choice(len(z), сколько, replace=False))]


def привести(z: np.ndarray, центры: np.ndarray, веса: np.ndarray) -> tuple[complex, float]:
    """Центр и масштаб облака: среднее центров (по весам) и корень средней мощности центров."""
    веса = np.asarray(веса, dtype=float) / max(1.0, float(np.sum(веса)))
    середина = complex(np.sum(центры * веса))
    масштаб = math.sqrt(float(np.sum(np.abs(центры - середина) ** 2 * веса))) or 1.0
    return середина, масштаб


# -- поворот -----------------------------------------------------------------------------------

def _стоимость(ц: np.ndarray, веса: np.ndarray, идеал: np.ndarray, φ: np.ndarray, ячейки: _Ячейки | None = None
               ) -> np.ndarray:
    """Сумма по центрам (с весами) квадрата расстояния до ближайшей идеальной точки при повороте на φ (массив).

    Углы — кусками: массив углы × центры × точки не больше ~4 млн чисел; ``ячейки`` (у больших плоскостей) —
    ближайшая точка по ячейкам, без этого массива.
    """
    if ячейки is not None:
        повёрнуто = (ц[None, :] * np.exp(1j * φ)[:, None]).ravel()
        до = (np.abs(повёрнуто - идеал[ячейки.ближайшие(повёрнуто)]) ** 2).reshape(len(φ), len(ц))
        return (до * веса[None, :]).sum(axis=1)
    итог = np.empty(len(φ))
    шаг = max(1, (1 << 22) // max(1, len(ц) * len(идеал)))
    for с in range(0, len(φ), шаг):
        повёрнуто = ц[None, :] * np.exp(1j * φ[с:с + шаг])[:, None]
        до = np.abs(повёрнуто[:, :, None] - идеал[None, None, :]).min(axis=2) ** 2
        итог[с:с + шаг] = (до * веса[None, :]).sum(axis=1)
    return итог


#: Грубый поиск поворота — по стольким центрам (дальним от центра: поворот у них заметнее); уточнение — по всем.
ГРУБО_ЦЕНТРОВ = 64


def выровнять(центры: np.ndarray, веса: np.ndarray, идеал: np.ndarray, *, шаг: float = 360.0) -> dict[str, Any]:
    """Поворот (градусы, против часовой) и инверсия, при которых центры ложатся на идеальные точки.

    ``центры`` — уже приведённые (центр 0, мощность 1); ``идеал`` — точки плоскости
    (комплексные, тоже приведённые). Поворот — в [0, шаг): повороты на шаг симметрии
    плоскости неразличимы по облаку. Итог: {поворот, инверсия, ошибка} — ошибка —
    корень среднего квадрата расстояния центров до точек.
    """
    веса = np.asarray(веса, dtype=float) / max(1e-12, float(np.sum(веса)))
    лучшее = None
    # Углы — в [0, шаг): у плоскости с шагом симметрии стоимость с этим периодом. У больших созвездий угол ищется
    # по ГРУБО_ЦЕНТРОВ дальним центрам с весом (у 1024 центров полный перебор углов — десятки секунд), ошибка —
    # по всем; до 64 центров это все центры.
    идеал = np.asarray(идеал, dtype=np.complex128)
    я = _Ячейки(идеал) if len(идеал) >= БОЛЬШОЕ_K else None
    дальность = np.abs(центры) * (np.asarray(веса) > 0)
    if я is not None:
        # У больших — дальние из тех, что при любом повороте остаются внутри прямоугольника точек плоскости: снаружи
        # ячейки пусты, и ближайшая ищется полным расчётом (у 1024 точек — вдесятеро дольше).
        внутри = min(float(идеал.real.max()), -float(идеал.real.min()), float(идеал.imag.max()), -float(идеал.imag.min()))
        if int((дальность <= внутри).sum()) >= 8:
            дальность = np.where(дальность <= внутри, дальность, 0.0)
    грубо = np.argsort(-дальность, kind="stable")[:ГРУБО_ЦЕНТРОВ]
    for инверсия in (False, True):
        ц = np.conj(центры) if инверсия else np.asarray(центры)
        φ = np.radians(np.arange(0.0, min(360.0, шаг), 0.25))
        цг, вг = ц[грубо], веса[грубо]
        с = _стоимость(цг, вг, идеал, φ, я)
        i = int(np.argmin(с))
        # Уточнение: золотое сечение в окрестности ±0,25°.
        а, б = φ[i] - math.radians(0.25), φ[i] + math.radians(0.25)
        for _ in range(40):
            м1, м2 = б - (б - а) / 1.618, а + (б - а) / 1.618
            if _стоимость(цг, вг, идеал, np.array([м1]), я)[0] < _стоимость(цг, вг, идеал, np.array([м2]), я)[0]:
                б = м2
            else:
                а = м1
        угол = (а + б) / 2
        стоимость = float(_стоимость(ц, веса, идеал, np.array([угол]), я)[0])
        if лучшее is None or стоимость < лучшее[0] - 1e-12:
            лучшее = (стоимость, math.degrees(угол) % 360, инверсия)
    стоимость, угол, инверсия = лучшее
    угол = угол % шаг if шаг < 360 else угол
    if шаг - угол < 1e-6:
        угол = 0.0
    return {"поворот": round(угол, 3), "инверсия": инверсия, "ошибка": round(math.sqrt(стоимость), 4)}


# -- решения -----------------------------------------------------------------------------------

def повернуть(z: np.ndarray, поворот: float, инверсия: bool) -> np.ndarray:
    """Инверсия спектра (сопряжение), затем поворот на φ° против часовой стрелки."""
    z = np.conj(z) if инверсия else np.asarray(z)
    return z * np.exp(1j * math.radians(поворот))


def по_плоскости(z: np.ndarray, идеал: np.ndarray, метки: np.ndarray) -> np.ndarray:
    """Жёсткие решения: метка ближайшей идеальной точки (z — приведённые и повёрнутые отсчёты)."""
    if len(идеал) >= БОЛЬШОЕ_K:
        return np.asarray(метки)[_ближайшие(np.asarray(z, dtype=np.complex128), np.asarray(идеал, dtype=np.complex128))]
    итог = np.empty(len(z), np.int64)
    for с in range(0, len(z), 1 << 16):
        кусок = z[с:с + (1 << 16)]
        итог[с:с + len(кусок)] = np.asarray(метки)[np.abs(кусок[:, None] - идеал[None, :]).argmin(axis=1)]
    return итог


def порядок_чтения(центры: np.ndarray) -> np.ndarray:
    """Номер кластера по порядку чтения: сверху вниз, слева направо (строки — с допуском четверти расстояния)."""
    между = np.abs(центры[:, None] - центры[None, :])
    np.fill_diagonal(между, np.inf)
    допуск = float(между.min()) / 4 if len(центры) > 1 else 1.0
    порядок = sorted(range(len(центры)), key=lambda i: (-round(float(центры[i].imag) / допуск), float(центры[i].real)))
    номер = np.empty(len(центры), np.int64)
    номер[порядок] = np.arange(len(центры))
    return номер


def по_кластерам(z: np.ndarray, центры: np.ndarray) -> np.ndarray:
    """Жёсткие решения «своей разметкой»: номер ближайшего кластера по порядку чтения."""
    номер = порядок_чтения(центры)
    if len(центры) >= БОЛЬШОЕ_K:
        return номер[_ближайшие(np.asarray(z, dtype=np.complex128), np.asarray(центры, dtype=np.complex128))]
    итог = np.empty(len(z), np.int64)
    for с in range(0, len(z), 1 << 16):
        кусок = z[с:с + (1 << 16)]
        итог[с:с + len(кусок)] = номер[np.abs(кусок[:, None] - центры[None, :]).argmin(axis=1)]
    return итог


def облако(z: np.ndarray, *, точек: int = 0, сид: int = 1) -> dict[str, Any]:
    """Облако для окна: число точек (задано или найдено), центры, веса, приведённые отсчёты для картинки."""
    if точек and (точек < 2 or точек & (точек - 1) or точек > ТОЧЕК_ДО):
        raise ValueError(f"число точек — степень двойки от 2 до {ТОЧЕК_ДО}")
    выборка = _выборка(z, сид, max(ВЫБОРКА, НА_ТОЧКУ * точек))
    оценки: list[dict[str, Any]] = []
    if not точек:
        точек, оценки = число_точек(выборка, сид=сид)
    ц, м = k_средних(выборка, точек, сид=сид)
    веса = np.bincount(м, minlength=точек)
    середина, масштаб = привести(выборка, ц, веса)
    показ = выборка[:: max(1, len(выборка) // ОБЛАКО_ДО)][:ОБЛАКО_ДО]
    return {"точек": точек, "оценки": оценки, "центры": (ц - середина) / масштаб, "веса": веса,
            "середина": середина, "масштаб": масштаб, "показ": (показ - середина) / масштаб,
            "отделимость": round(отделимость(выборка, ц, м), 3)}


# -- решения по всей записи кусками ----------------------------------------------------------------

#: Отсчётов в куске при решениях по всей записи.
КУСОК_ОТСЧЁТОВ = 1 << 21


def _разметка_wav(читать, начало: int, всего: int) -> tuple[int, int, int, int, int]:
    """Заголовок WAV по месту (без чтения данных): (тег, бит, начало данных, конец данных, каналов) — как ``_wav``."""
    if читать(начало, 4) != b"RIFF" or читать(начало + 8, 4) != b"WAVE":
        raise ValueError("не WAV: нет заголовка RIFF/WAVE")
    место, формат, данные = начало + 12, None, None
    while место + 8 <= всего:
        заголовок = читать(место, 8)
        имя, размер = заголовок[:4], struct.unpack("<I", заголовок[4:8])[0]
        if имя == b"fmt ":
            тело = читать(место + 8, min(размер, 40))
            if len(тело) >= 16:
                тег, каналов, _, _, _, бит = struct.unpack("<HHIIHH", тело[:16])
                if тег == 0xFFFE and len(тело) >= 26:
                    тег = struct.unpack("<H", тело[24:26])[0]
                формат = (тег, бит, каналов)
        elif имя == b"data":
            данные = (место + 8, min(всего, место + 8 + размер))
        место += 8 + размер + (размер & 1)
    if формат is None or данные is None:
        raise ValueError("WAV без блока fmt или data")
    return формат[0], формат[1], данные[0], данные[1], формат[2]


def куски_отсчётов(читать, всего: int, формат: str = "авто", *, порядок: str = "младший", каналы: str = "IQ",
                   пропуск: int = 0, кусок: int = КУСОК_ОТСЧЁТОВ):
    """Отсчёты всей записи кусками — те же, что ``прочитать`` над всеми байтами: ``читать(от, сколько)`` — байты
    записи, ``всего`` — их число. Ошибки ввода — ValueError, как у ``прочитать``."""
    начало = max(0, int(пропуск))
    формат = str(формат or "авто").strip().lower()
    if формат in ("авто", "wav"):
        if читать(начало, 4) == b"RIFF":
            тег, бит, от, до, каналов = _разметка_wav(читать, начало, всего)
            if каналов != 2:
                raise ValueError(f"WAV: каналов {каналов}, а для I/Q нужно два")
            if тег == 3 and бит == 32:
                тип, ноль = "<f4", 0.0
            elif тег == 1 and бит in (8, 16, 32):
                тип, ноль = {8: "u1", 16: "<i2", 32: "<i4"}[бит], (128.0 if бит == 8 else 0.0)
            elif тег == 1 and бит == 24:
                тип, ноль = "24", 0.0
            else:
                raise ValueError(f"WAV: формат {тег}, {бит} бит — поддерживаются PCM 8/16/24/32 и float32")
            пара = 2 * (бит // 8)
        elif формат == "wav":
            raise ValueError("не WAV: нет заголовка RIFF/WAVE")
        else:
            raise ValueError("формат отсчётов не определить по байтам: укажите int8, uint8, int16 или float32 "
                             "(или WAV)")
    elif формат in ФОРМАТЫ:
        if порядок not in ("младший", "старший"):
            raise ValueError("порядок байт — младший или старший")
        т_, ноль = ФОРМАТЫ[формат]
        тип = ("<" if порядок == "младший" else ">") + т_
        пара, от, до = 2 * np.dtype(тип).itemsize, начало, всего
    else:
        raise ValueError("формат отсчётов: int8, uint8, int16, float32 или WAV")
    if каналы not in ("IQ", "QI"):
        raise ValueError("порядок каналов — IQ или QI")
    до = от + (до - от) // пара * пара
    for место in range(от, до, кусок * пара):
        данные = читать(место, min(кусок * пара, до - место))
        if тип == "24":
            сырьё = np.frombuffer(данные, np.uint8).reshape(-1, 3).astype(np.int32)
            x = (сырьё[:, 0] | (сырьё[:, 1] << 8) | (сырьё[:, 2] << 16)).astype(np.int64)
            x = np.where(x >= 1 << 23, x - (1 << 24), x).astype(np.float64)
        else:
            x = np.frombuffer(данные, тип).astype(np.float64) - ноль
        z = x[0::2] + 1j * x[1::2]
        if каналы == "QI":
            z = z.imag + 1j * z.real
        yield z[np.isfinite(z)]


def решения_по_всему(источник: Any, куда: str, *, формат: str, порядок: str = "младший", каналы: str = "IQ",
                     пропуск: int = 0, развернуть: bool = False, середина: complex, масштаб: float,
                     поворот: float = 0.0, инверсия: bool = False, k: int, идеал: np.ndarray | None = None,
                     метки: np.ndarray | None = None, центры: np.ndarray | None = None) -> dict[str, int]:
    """Жёсткие решения по всей записи кусками (в исполнителе стола): метки ближайшей точки плоскости (``идеал``,
    ``метки``) или номера кластеров (``центры`` — уже повёрнутые) — по k бит в файл ``куда``.

    ``источник`` — массив задания (``stol_raschety.Источник`` или ``hranenie.Источник``): байты читаются окнами,
    ``развернуть`` — переворот бит в байте записи. Итог: {"отсчётов", "бит"}."""
    from .hranenie import Приёмник  # noqa: PLC0415
    from .razmetka import в_биты  # noqa: PLC0415
    массив = источник._массив() if hasattr(источник, "_массив") else источник
    наоборот = bytes(int(f"{i:08b}"[::-1], 2) for i in range(256))
    всего = массив.бит // 8

    def читать(от: int, сколько: int) -> bytes:
        данные = массив.байты(от, max(0, min(сколько, всего - от)))
        return данные.translate(наоборот) if развернуть else данные
    отсчётов = 0
    with Приёмник(куда) as приёмник:
        for z in куски_отсчётов(читать, всего, формат, порядок=порядок, каналы=каналы, пропуск=пропуск):
            приведённые = повернуть((z - середина) / масштаб, поворот, инверсия)
            решения = по_плоскости(приведённые, идеал, метки) if идеал is not None else по_кластерам(приведённые, центры)
            приёмник.записать(в_биты(решения, k))
            отсчётов += len(z)
        if отсчётов < 16:
            raise ValueError(f"отсчётов {отсчётов}: для облака нужно хотя бы 16")
        бит = приёмник.закрыть()
    return {"отсчётов": отсчётов, "бит": int(бит)}
