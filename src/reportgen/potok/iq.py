"""Вход I/Q: отсчёты символов (мягкие решения) → созвездие по облаку → жёсткие решения → метки.

Если аналитику прислали не биты, а отсчёты символов I/Q, созвездие и его
поворот видны по облаку точек:

1. отсчёты: int8, uint8, int16, float32 чередованием I, Q (или Q, I), порядок
   байт — младшим или старшим вперёд; WAV с двумя каналами (PCM 8/16/24/32 бит
   или float32) — по заголовку;
2. кластеры — k-средних (Ллойд, начальные центры k-means++, без сторонних
   пакетов); число точек задаётся или находится: из степеней двойки берётся
   то, у которого отношение наименьшего расстояния между центрами к разбросу
   внутри кластеров наибольшее (лишние кластеры делят облако пополам —
   расстояние мало; недостающие сливают — разброс велик);
3. облако приводится к центру и единичной средней мощности центров; поворот
   (и инверсия спектра) — перебором угла с шагом 0,25° и уточнением: сумма
   квадратов расстояний от центров до ближайших идеальных точек плоскости;
4. жёсткие решения: ближайшая точка выбранной плоскости (.etl) — её метка;
   или «по кластерам»: метка — номер кластера по порядку чтения (сверху
   вниз, слева направо) — тогда разметку ищет «Разметка вслепую».
"""

from __future__ import annotations

import math
import struct
from typing import Any

import numpy as np

#: Форматы отсчётов: (тип numpy без порядка байт, смещение нуля).
ФОРМАТЫ = {"int8": ("i1", 0.0), "uint8": ("u1", 127.5), "int16": ("i2", 0.0), "float32": ("f4", 0.0)}
#: k-средних: отсчётов в выборке для кластеров и итераций Ллойда.
ВЫБОРКА = 1 << 15
ВЫБОРКА_ЧИСЛА = 1 << 13
ИТЕРАЦИЙ = 60
#: Числа точек, которые пробуются при поиске.
ЧИСЛА_ТОЧЕК = (2, 4, 8, 16, 32, 64)
#: Картинка облака — не больше стольких точек.
ОБЛАКО_ДО = 4000


def _wav(данные: bytes) -> tuple[np.ndarray, str]:
    """RIFF/WAVE с двумя каналами → комплексные отсчёты (канал 1 — I, канал 2 — Q)."""
    if len(данные) < 12 or данные[:4] != b"RIFF" or данные[8:12] != b"WAVE":
        raise ValueError("не WAV: нет заголовка RIFF/WAVE")
    место, формат, данные_wav = 12, None, None
    while место + 8 <= len(данные):
        имя, размер = данные[место:место + 4], struct.unpack("<I", данные[место + 4:место + 8])[0]
        тело = данные[место + 8:место + 8 + размер]
        if имя == b"fmt " and len(тело) >= 16:
            тег, каналов, частота, _, _, бит = struct.unpack("<HHIIHH", тело[:16])
            if тег == 0xFFFE and len(тело) >= 26:
                тег = struct.unpack("<H", тело[24:26])[0]
            формат = (тег, каналов, частота, бит)
        elif имя == b"data":
            данные_wav = тело
        место += 8 + размер + (размер & 1)
    if формат is None or данные_wav is None:
        raise ValueError("WAV без блока fmt или data")
    тег, каналов, частота, бит = формат
    if каналов != 2:
        raise ValueError(f"WAV: каналов {каналов}, а для I/Q нужно два")
    if тег == 3 and бит == 32:
        x = np.frombuffer(данные_wav[:len(данные_wav) // 8 * 8], "<f4").astype(np.float64)
    elif тег == 1 and бит in (8, 16, 32):
        тип = {8: "u1", 16: "<i2", 32: "<i4"}[бит]
        x = np.frombuffer(данные_wav[:len(данные_wav) // (бит // 4) * (бит // 4)], тип).astype(np.float64)
        if бит == 8:
            x -= 128
    elif тег == 1 and бит == 24:
        сырьё = np.frombuffer(данные_wav[:len(данные_wav) // 6 * 6], np.uint8).reshape(-1, 3).astype(np.int32)
        x = (сырьё[:, 0] | (сырьё[:, 1] << 8) | (сырьё[:, 2] << 16)).astype(np.int64)
        x = np.where(x >= 1 << 23, x - (1 << 24), x).astype(np.float64)
    else:
        raise ValueError(f"WAV: формат {тег}, {бит} бит — поддерживаются PCM 8/16/24/32 и float32")
    x = x[:len(x) // 2 * 2]
    return x[0::2] + 1j * x[1::2], f"WAV: 2 канала, {бит} бит, {'float' if тег == 3 else 'PCM'}, {частота} Гц"


def прочитать(данные: bytes, формат: str = "авто", *, порядок: str = "младший", каналы: str = "IQ",
              пропуск: int = 0) -> tuple[np.ndarray, str]:
    """Байты → комплексные отсчёты и описание; ошибки ввода — ValueError.

    ``порядок`` — байт в числе: «младший» (little-endian) или «старший»;
    ``каналы`` — «IQ» или «QI»; ``пропуск`` — байт заголовка до отсчётов.
    «авто» — WAV по заголовку, иначе отказ: формат сырых отсчётов по байтам не угадать.
    """
    данные = bytes(данные)[max(0, int(пропуск)):]
    формат = str(формат or "авто").strip().lower()
    if формат in ("авто", "wav"):
        if данные[:4] == b"RIFF":
            z, описание = _wav(данные)
        elif формат == "wav":
            raise ValueError("не WAV: нет заголовка RIFF/WAVE")
        else:
            raise ValueError("формат отсчётов не определить по байтам: укажите int8, uint8, int16 или float32 "
                             "(или WAV)")
    elif формат in ФОРМАТЫ:
        тип, ноль = ФОРМАТЫ[формат]
        if порядок not in ("младший", "старший"):
            raise ValueError("порядок байт — младший или старший")
        dt = np.dtype(("<" if порядок == "младший" else ">") + тип)
        x = np.frombuffer(данные[:len(данные) // (2 * dt.itemsize) * 2 * dt.itemsize], dt).astype(np.float64) - ноль
        z = x[0::2] + 1j * x[1::2]
        описание = f"{формат}, I и Q чередованием, {порядок} байт первым" if dt.itemsize > 1 else \
            f"{формат}, I и Q чередованием"
    else:
        raise ValueError("формат отсчётов: int8, uint8, int16, float32 или WAV")
    if каналы not in ("IQ", "QI"):
        raise ValueError("порядок каналов — IQ или QI")
    if каналы == "QI":
        z = z.imag + 1j * z.real
        описание += "; каналы Q, I"
    z = z[np.isfinite(z)]
    if len(z) < 16:
        raise ValueError(f"отсчётов {len(z)}: для облака нужно хотя бы 16")
    return z, описание


# -- кластеры ----------------------------------------------------------------------------------

def _ближайшие(z: np.ndarray, ц: np.ndarray) -> np.ndarray:
    """Номер ближайшего центра каждого отсчёта (кусками — без огромной матрицы расстояний)."""
    итог = np.empty(len(z), np.int64)
    for с in range(0, len(z), 1 << 14):
        кусок = z[с:с + (1 << 14)]
        итог[с:с + len(кусок)] = ((кусок.real[:, None] - ц.real[None, :]) ** 2
                                 + (кусок.imag[:, None] - ц.imag[None, :]) ** 2).argmin(axis=1)
    return итог


def _ллойд(z: np.ndarray, K: int, rng: np.random.Generator, итераций: int,
           ц: np.ndarray | None = None) -> tuple[np.ndarray, np.ndarray, float]:
    if ц is None:
        центры = [z[rng.integers(len(z))]]
        до = np.abs(z - центры[0]) ** 2
        for _ in range(1, K):
            сумма = до.sum()
            i = int(rng.choice(len(z), p=до / сумма)) if сумма > 0 else int(rng.integers(len(z)))
            центры.append(z[i])
            до = np.minimum(до, np.abs(z - z[i]) ** 2)
        ц = np.array(центры)
    метки = _ближайшие(z, ц)
    for _ in range(итераций):
        счёт = np.bincount(метки, minlength=K)
        суммы = np.bincount(метки, weights=z.real, minlength=K) + 1j * np.bincount(метки, weights=z.imag, minlength=K)
        пустые = счёт == 0
        ц = np.where(пустые, ц, суммы / np.maximum(1, счёт))
        if пустые.any():
            # Пустой кластер — в самый далёкий от своего центра отсчёт.
            дальний = np.argsort(-np.abs(z - ц[метки]))[:int(пустые.sum())]
            ц[np.flatnonzero(пустые)] = z[дальний]
        новые = _ближайшие(z, ц)
        if np.array_equal(новые, метки):
            break
        метки = новые
    return ц, метки, float(np.mean(np.abs(z - ц[метки]) ** 2))


def _поправить(z: np.ndarray, ц: np.ndarray, м: np.ndarray, разброс: float, rng: np.random.Generator,
               итераций: int) -> tuple[np.ndarray, np.ndarray, float]:
    """Слить два слишком близких центра и разделить самый широкий кластер — пока разброс падает.

    Ллойд застревает, когда одну точку созвездия делят два центра, а две
    соседние — один: тогда пара центров вдвое ближе прочих.
    """
    K = len(ц)
    for _ in range(K):
        между = np.abs(ц[:, None] - ц[None, :])
        np.fill_diagonal(между, np.inf)
        ближний = между.min(axis=1)
        i = int(np.argmin(ближний))
        if ближний[i] >= 0.6 * float(np.median(ближний)):
            break
        j = int(np.argmin(между[i]))
        счёт = np.bincount(м, minlength=K)
        ширина = np.bincount(м, weights=np.abs(z - ц[м]) ** 2, minlength=K) / np.maximum(1, счёт)
        ширина[[i, j]] = -1
        w = int(np.argmax(ширина))
        новый = ц.copy()
        новый[i] = (ц[i] * счёт[i] + ц[j] * счёт[j]) / max(1, счёт[i] + счёт[j])
        точки = z[м == w]
        if len(точки) < 2:
            break
        # Делим по главному направлению разброса кластера.
        d = точки - точки.mean()
        угол = 0.5 * math.atan2(2 * float(np.mean(d.real * d.imag)), float(np.mean(d.real ** 2 - d.imag ** 2)))
        сдвиг = math.sqrt(max(1e-12, float(ширина[w]))) * np.exp(1j * угол)
        новый[w], новый[j] = ц[w] + сдвиг, ц[w] - сдвиг
        ц2, м2, р2 = _ллойд(z, K, rng, итераций, новый)
        if р2 >= разброс:
            break
        ц, м, разброс = ц2, м2, р2
    return ц, м, разброс


#: k-средних: запусков с разных начальных центров (берётся с наименьшим разбросом).
ЗАПУСКОВ = 4


def k_средних(z: np.ndarray, K: int, *, итераций: int = ИТЕРАЦИЙ, сид: int = 1, запусков: int = ЗАПУСКОВ
              ) -> tuple[np.ndarray, np.ndarray]:
    """Центры K кластеров и номер кластера каждого отсчёта: k-means++ и Ллойд, лучший из нескольких запусков."""
    z = np.asarray(z, dtype=np.complex128)
    if K < 1 or K > len(z):
        raise ValueError(f"кластеров {K}, а отсчётов {len(z)}")
    rng = np.random.default_rng(сид)
    лучший = None
    for _ in range(max(1, запусков)):
        ц, м, разброс = _поправить(z, *_ллойд(z, K, rng, итераций), rng, итераций)
        if лучший is None or разброс < лучший[2]:
            лучший = (ц, м, разброс)
    return лучший[0], лучший[1]


def отделимость(z: np.ndarray, центры: np.ndarray, метки: np.ndarray) -> float:
    """Наименьшее расстояние между центрами к корню среднего квадрата разброса внутри кластеров."""
    if len(центры) < 2:
        return 0.0
    между = np.abs(центры[:, None] - центры[None, :])
    np.fill_diagonal(между, np.inf)
    разброс = math.sqrt(float(np.mean(np.abs(z - центры[метки]) ** 2))) or 1e-12
    return float(между.min()) / разброс


def число_точек(z: np.ndarray, варианты=ЧИСЛА_ТОЧЕК, *, сид: int = 1) -> tuple[int, list[dict[str, Any]]]:
    """Число точек созвездия по облаку: лучшая отделимость из степеней двойки; и оценка каждого."""
    выборка = _выборка(z, сид, ВЫБОРКА_ЧИСЛА)
    оценки = []
    for K in варианты:
        if K * 8 > len(выборка):
            continue
        ц, м = k_средних(выборка, K, сид=сид)
        оценки.append({"точек": K, "отделимость": round(отделимость(выборка, ц, м), 3)})
    if not оценки:
        raise ValueError("отсчётов мало для поиска числа точек")
    лучший = max(оценки, key=lambda о: о["отделимость"])
    return лучший["точек"], оценки


def _выборка(z: np.ndarray, сид: int = 1, сколько: int = ВЫБОРКА) -> np.ndarray:
    if len(z) <= сколько:
        return np.asarray(z)
    return np.asarray(z)[np.sort(np.random.default_rng(сид).choice(len(z), сколько, replace=False))]


def привести(z: np.ndarray, центры: np.ndarray, веса: np.ndarray) -> tuple[complex, float]:
    """Центр и масштаб облака: среднее центров (по весам) и корень средней мощности центров."""
    веса = np.asarray(веса, dtype=float) / max(1.0, float(np.sum(веса)))
    середина = complex(np.sum(центры * веса))
    масштаб = math.sqrt(float(np.sum(np.abs(центры - середина) ** 2 * веса))) or 1.0
    return середина, масштаб


# -- поворот -----------------------------------------------------------------------------------

def _стоимость(ц: np.ndarray, веса: np.ndarray, идеал: np.ndarray, φ: np.ndarray) -> np.ndarray:
    """Сумма по центрам (с весами) квадрата расстояния до ближайшей идеальной точки при повороте на φ (массив)."""
    повёрнуто = ц[None, :] * np.exp(1j * φ)[:, None]
    до = np.abs(повёрнуто[:, :, None] - идеал[None, None, :]).min(axis=2) ** 2
    return (до * веса[None, :]).sum(axis=1)


def выровнять(центры: np.ndarray, веса: np.ndarray, идеал: np.ndarray, *, шаг: float = 360.0) -> dict[str, Any]:
    """Поворот (градусы, против часовой) и инверсия, при которых центры ложатся на идеальные точки.

    ``центры`` — уже приведённые (центр 0, мощность 1); ``идеал`` — точки плоскости
    (комплексные, тоже приведённые). Поворот — в [0, шаг): повороты на шаг симметрии
    плоскости неразличимы по облаку. Итог: {поворот, инверсия, ошибка} — ошибка —
    корень среднего квадрата расстояния центров до точек.
    """
    веса = np.asarray(веса, dtype=float) / max(1e-12, float(np.sum(веса)))
    лучшее = None
    for инверсия in (False, True):
        ц = np.conj(центры) if инверсия else np.asarray(центры)
        φ = np.radians(np.arange(0.0, 360.0, 0.25))
        с = _стоимость(ц, веса, идеал, φ)
        i = int(np.argmin(с))
        # Уточнение: золотое сечение в окрестности ±0,25°.
        а, б = φ[i] - math.radians(0.25), φ[i] + math.radians(0.25)
        for _ in range(40):
            м1, м2 = б - (б - а) / 1.618, а + (б - а) / 1.618
            if _стоимость(ц, веса, идеал, np.array([м1]))[0] < _стоимость(ц, веса, идеал, np.array([м2]))[0]:
                б = м2
            else:
                а = м1
        угол = (а + б) / 2
        стоимость = float(_стоимость(ц, веса, идеал, np.array([угол]))[0])
        if лучшее is None or стоимость < лучшее[0] - 1e-12:
            лучшее = (стоимость, math.degrees(угол) % 360, инверсия)
    стоимость, угол, инверсия = лучшее
    угол = угол % шаг if шаг < 360 else угол
    if шаг - угол < 1e-6:
        угол = 0.0
    return {"поворот": round(угол, 3), "инверсия": инверсия, "ошибка": round(math.sqrt(стоимость), 4)}


# -- решения -----------------------------------------------------------------------------------

def повернуть(z: np.ndarray, поворот: float, инверсия: bool) -> np.ndarray:
    """Инверсия спектра (сопряжение), затем поворот на φ° против часовой стрелки."""
    z = np.conj(z) if инверсия else np.asarray(z)
    return z * np.exp(1j * math.radians(поворот))


def по_плоскости(z: np.ndarray, идеал: np.ndarray, метки: np.ndarray) -> np.ndarray:
    """Жёсткие решения: метка ближайшей идеальной точки (z — приведённые и повёрнутые отсчёты)."""
    итог = np.empty(len(z), np.int64)
    for с in range(0, len(z), 1 << 16):
        кусок = z[с:с + (1 << 16)]
        итог[с:с + len(кусок)] = np.asarray(метки)[np.abs(кусок[:, None] - идеал[None, :]).argmin(axis=1)]
    return итог


def порядок_чтения(центры: np.ndarray) -> np.ndarray:
    """Номер кластера по порядку чтения: сверху вниз, слева направо (строки — с допуском четверти расстояния)."""
    между = np.abs(центры[:, None] - центры[None, :])
    np.fill_diagonal(между, np.inf)
    допуск = float(между.min()) / 4 if len(центры) > 1 else 1.0
    порядок = sorted(range(len(центры)), key=lambda i: (-round(float(центры[i].imag) / допуск), float(центры[i].real)))
    номер = np.empty(len(центры), np.int64)
    номер[порядок] = np.arange(len(центры))
    return номер


def по_кластерам(z: np.ndarray, центры: np.ndarray) -> np.ndarray:
    """Жёсткие решения «своей разметкой»: номер ближайшего кластера по порядку чтения."""
    номер = порядок_чтения(центры)
    итог = np.empty(len(z), np.int64)
    for с in range(0, len(z), 1 << 16):
        кусок = z[с:с + (1 << 16)]
        итог[с:с + len(кусок)] = номер[np.abs(кусок[:, None] - центры[None, :]).argmin(axis=1)]
    return итог


def облако(z: np.ndarray, *, точек: int = 0, сид: int = 1) -> dict[str, Any]:
    """Облако для окна: число точек (задано или найдено), центры, веса, приведённые отсчёты для картинки."""
    выборка = _выборка(z, сид)
    оценки: list[dict[str, Any]] = []
    if not точек:
        точек, оценки = число_точек(выборка, сид=сид)
    if точек < 2 or точек & (точек - 1) or точек > 256:
        raise ValueError("число точек — степень двойки от 2 до 256")
    ц, м = k_средних(выборка, точек, сид=сид)
    веса = np.bincount(м, minlength=точек)
    середина, масштаб = привести(выборка, ц, веса)
    показ = выборка[:: max(1, len(выборка) // ОБЛАКО_ДО)][:ОБЛАКО_ДО]
    return {"точек": точек, "оценки": оценки, "центры": (ц - середина) / масштаб, "веса": веса,
            "середина": середина, "масштаб": масштаб, "показ": (показ - середина) / масштаб,
            "отделимость": round(отделимость(выборка, ц, м), 3)}
