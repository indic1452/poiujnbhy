def _ближайшее(слова: np.ndarray, принято: np.ndarray, исправляет: int) -> Tuple[np.ndarray, np.ndarray]:
    """Декодер по ближайшему слову: (номер слова, число исправленных бит; −1 — не исправимо)."""
    расстояния = np.bitwise_count(принято[:, None] ^ слова[None, :]).astype(np.int64)
    номер = расстояния.argmin(axis=1)
    ошибок = расстояния[np.arange(len(номер)), номер]
    return номер, np.where(ошибок <= исправляет, ошибок, -1)


def _число(биты: np.ndarray) -> np.ndarray:
    """Строки бит → целые (старший бит первым)."""
    веса = (1 << np.arange(биты.shape[1] - 1, -1, -1)).astype(np.int64)
    return биты.astype(np.int64) @ веса


# -- BPTC (196, 96) -------------------------------------------------------------------------

def _хэмминг(уравнения: List[List[int]], k: int) -> Tuple[np.ndarray, Dict[int, int]]:
    """Проверочная матрица из уравнений кодера Hamming.cpp и таблица синдром → бит."""
    n = k + len(уравнения)
    H = np.zeros((len(уравнения), n), dtype=np.uint8)
    for j, у in enumerate(уравнения):
        H[j, у] = 1
        H[j, k + j] = 1
    место = {int(sum(int(H[j, i]) << j for j in range(len(уравнения)))): i for i in range(n)}
    return H, место


#: encode15113_2 и encode1393 (Hamming.cpp).
H15, МЕСТО15 = _хэмминг([[0, 1, 2, 3, 5, 7, 8], [1, 2, 3, 4, 6, 8, 9], [2, 3, 4, 5, 7, 9, 10],
                         [0, 1, 2, 4, 6, 7, 10]], 11)
H13, МЕСТО13 = _хэмминг([[0, 1, 3, 5, 6], [0, 1, 2, 4, 6, 7], [0, 1, 2, 3, 5, 7, 8], [0, 2, 4, 5, 8]], 9)
ПЕРЕМЕЖЕНИЕ = (np.arange(196) * 181) % 196
СТРОКИ = np.array([[r * 15 + 1 + i for i in range(15)] for r in range(9)])
СТОЛБЦЫ = np.array([[c + 1 + 15 * a for a in range(13)] for c in range(15)])
ДАННЫЕ_BPTC = np.array(list(range(4, 12)) + [a for r in range(1, 9) for a in range(r * 15 + 1, r * 15 + 12)])


def _исправить(матрица: np.ndarray, места: np.ndarray, H: np.ndarray, место: Dict[int, int]) -> int:
    """Одна ошибка на слово Хэмминга по всем пакетам сразу; число исправленных бит."""
    слова = матрица[:, места]                                  # (пакеты, слов, n)
    синдром = (np.einsum("psn,jn->psj", слова, H) & 1)
    номер = (синдром * (1 << np.arange(H.shape[0]))).sum(axis=2)
    исправлено = 0
    for с, i in место.items():
        p, s = np.nonzero(номер == с)
        if len(p):
            матрица[p, места[s, i]] ^= 1
            исправлено += len(p)
    return исправлено


def bptc(сырые: np.ndarray) -> Tuple[np.ndarray, int]:
    """BPTC (196, 96): (пакеты, 196) принятых бит → (пакеты, 96) данных и число исправлений."""
    принято = np.asarray(сырые, dtype=np.uint8)[:, ПЕРЕМЕЖЕНИЕ]
    d = принято.copy()
    for _ in range(5):                                        # как decodeErrorCheck: до 5 проходов
        if not (_исправить(d, СТОЛБЦЫ, H13, МЕСТО13) + _исправить(d, СТРОКИ, H15, МЕСТО15)):
            break
    return d[:, ДАННЫЕ_BPTC], int((d != принято).sum())


def bptc_кодировать(данные: np.ndarray) -> np.ndarray:
    """Кодер BPTC (196, 96) (для проверок): строки (15, 11), столбцы (13, 9), перемежение."""
    d = np.zeros(196, dtype=np.uint8)
    d[ДАННЫЕ_BPTC] = данные
    for r in range(9):
        с = СТРОКИ[r]
        d[с[11:]] = (H15[:, :11] @ d[с[:11]]) & 1
    for c in range(15):
        с = СТОЛБЦЫ[c]
        d[с[9:]] = (H13[:, :9] @ d[с[:9]]) & 1
    сырые = np.zeros(196, dtype=np.uint8)
    сырые[ПЕРЕМЕЖЕНИЕ] = d
    return сырые


# -- RS (12, 9) и CRC ----------------------------------------------------------------------

_EXP = [0] * 512
_LOG = [0] * 256
_x = 1
for _i in range(255):
    _EXP[_i] = _x
    _LOG[_x] = _i
    _x <<= 1
    if _x & 0x100:
        _x ^= 0x11D
for _i in range(255, 512):
    _EXP[_i] = _EXP[_i - 255]


def _умн(a: int, b: int) -> int:
    return 0 if a == 0 or b == 0 else _EXP[_LOG[a] + _LOG[b]]


def rs129_проверка(данные: bytes) -> bytes:
    """Проверочные байты RS (12, 9) в порядке передачи (RS129.cpp: POLY 64, 56, 14; GF(2⁸), 0x11D)."""
    многочлен = (64, 56, 14)
    п = [0, 0, 0]
    for байт in данные[:9]:
        d = байт ^ п[2]
        п = [_умн(многочлен[0], d), п[0] ^ _умн(многочлен[1], d), п[1] ^ _умн(многочлен[2], d)]
    return bytes([п[2], п[1], п[0]])


def crc_ccitt(данные: bytes) -> int:
    """CRC-CCITT DMR (CRC.cpp checkCCITT162): x¹⁶ + x¹² + x⁵ + 1, начальное 0, инверсия в конце."""
    crc = 0
    for байт in данные:
        crc ^= байт << 8
        for _ in range(8):
            crc = ((crc << 1) ^ 0x1021) & 0xFFFF if crc & 0x8000 else (crc << 1) & 0xFFFF
    return crc ^ 0xFFFF


# -- поиск и разбор пакетов ----------------------------------------------------------------

def синхрослова(биты: np.ndarray) -> List[Tuple[int, str, int]]:
    """Места синхрослов DMR (не больше ОШИБОК_СИНХРО несовпадений): (бит, вид, ошибок)."""
    биты = np.asarray(биты, dtype=np.uint8)
    итог = []
    for сдвиг in range(8):
        часть = биты[сдвиг:]
        байты = np.packbits(часть[:len(часть) // 8 * 8]).astype(np.int64)
        if len(байты) < 6:
            continue
        окна = np.zeros(len(байты) - 5, dtype=np.int64)
        for k in range(6):
            окна = (окна << 8) | байты[k:len(байты) - 5 + k]
        for вид, слово in СИНХРО.items():
            ошибок = np.bitwise_count(окна ^ слово)
            for м in np.nonzero(ошибок <= ОШИБОК_СИНХРО)[0]:
                итог.append((int(м) * 8 + сдвиг, вид, int(ошибок[м])))
    итог.sort()
    return итог


def разобрать_пакеты(биты: np.ndarray, начала: List[int]) -> Dict[str, object]:
    """Тип слота, BPTC и поля пакетов данных, начинающихся в ``начала``."""
    биты = np.asarray(биты, dtype=np.uint8)
    пакеты = np.stack([биты[н:н + ПАКЕТ] for н in начала])
    тип, ошибок = _ближайшее(СЛОВА_ТИПА, _число(np.concatenate([пакеты[:, 98:108], пакеты[:, 156:166]], axis=1)), 3)
    данные, исправлено = bptc(np.concatenate([пакеты[:, :98], пакеты[:, 166:]], axis=1))
    return {"цвет": тип >> 4, "тип": тип & 15, "golay": ошибок, "данные": данные, "исправлено": исправлено}


def _id(б: bytes) -> int:
    return int.from_bytes(б, "big")


def поля(тип: int, данные: np.ndarray) -> Optional[Tuple[str, str]]:
    """Содержимое 96 бит по типу данных: (вид, строка) — только при верной проверке."""
    б = bytearray(np.packbits(данные).tobytes())
    if тип in МАСКИ_LC:
        for i in (9, 10, 11):
            б[i] ^= МАСКИ_LC[тип]
        if rs129_проверка(bytes(б[:9])) != bytes(б[9:12]):
            return None
        flco = б[0] & 0x3F
        вызов = FLCO.get(flco, f"FLCO {flco}")
        return ("LC", f"{вызов} вызов: {_id(б[6:9])} → {_id(б[3:6])} (FID {б[1]}, параметры 0x{б[2]:02X})")
    if тип in МАСКИ_CRC:
        маска = МАСКИ_CRC[тип]
        if crc_ccitt(bytes(б[:10])) ^ маска != int.from_bytes(б[10:12], "big"):
            return None
        if тип == 3:
            код = б[0] & 0x3F
            имя = CSBKO.get(код, f"код 0x{код:02X}")
            if код in (0x26,) or (код == 0x24 and б[3] != 0x80):
                return ("CSBK", f"{имя}: {_id(б[4:7])} → {_id(б[7:10])} (FID {б[1]})")
            return ("CSBK", f"{имя}: {_id(б[7:10])} → {_id(б[4:7])} (FID {б[1]})")
        if тип == 6:
            dpf = б[0] & 0x0F
            вид = "групповой" if б[0] & 0x80 else "индивидуальный"
            return ("данные", f"заголовок данных ({DPF.get(dpf, dpf)}, {вид}): {_id(б[5:8])} → {_id(б[2:5])}")
        if тип == 0:
            return ("PI", f"заголовок PI: алгоритм {б[0] & 7}, ключ {б[2]}")
        return ("MBC", f"заголовок MBC: код 0x{б[0] & 0x3F:02X}")
    return None


def emb_сверхкадров(биты: np.ndarray, речь: List[int], слот: int) -> str:
    """EMB пакетов B–F каждого сверхкадра (через ``слот`` бит в том же слоте): цвет, PI, LCSS."""
    слова = []
    for м in речь:
        for k in range(1, 6):
            н = м + k * слот
            if н + 48 <= len(биты):
                слова.append(np.concatenate([биты[н:н + 8], биты[н + 40:н + 48]]))
    if not слова:
        return ""
    номер, ошибок = _ближайшее(СЛОВА_EMB, _число(np.array(слова)), 2)
    верные = номер[ошибок >= 0]
    if not len(верные):
        return f"EMB пакетов B–F: верных QR (16, 7) нет из {len(слова)}"
    цвета = Counter((верные >> 3).tolist())
    pi = int(((верные >> 2) & 1).sum())
    return (f"EMB пакетов B–F (QR (16, 7)): верны {len(верные)} из {len(слова)}; цветовой код "
            + ", ".join(f"{ц} × {с}" for ц, с in цвета.most_common())
            + (f"; признак шифрования PI у {pi}" if pi else ""))


def найти(биты: np.ndarray) -> Optional[Находка]:
    """DMR: синхрослова с шагом, кратным 264 (или 288 у БС), тип слота с верным Golay, поля пакетов."""
    биты = np.asarray(биты, dtype=np.uint8)
    места = синхрослова(биты)
    if len(места) < НАЙТИ_ОТ:
        return None
    # Пакеты одного потока: расстояния между синхрословами кратны 288 (БС: CACH + пакет) или 264.
    шаги = Counter()
    for (а, _, _), (б, _, _) in zip(места, места[1:], strict=False):
        for шаг in (288, 264):                                 # 264: пакеты подряд, без CACH и пауз
            if (б - а) % шаг == 0:
                шаги[шаг] += 1
    if not шаги:
        return None
    шаг, согласно = шаги.most_common(1)[0]
    if согласно < 0.7 * (len(места) - 1):
        return None
    виды = Counter(в for _, в, _ in места)
    начала = [м - 108 for м, в, _ in места if "данные" in в and м >= 108 and м - 108 + ПАКЕТ <= len(биты)]
    подробно = [f"синхрослов DMR: {len(места)} — " + ", ".join(f"{в} × {с}" for в, с in виды.most_common()),
                f"расстояния между ними кратны {шаг} бит"
                + (" (CACH 24 + пакет 264: передаёт базовая станция)" if шаг == 288 else "")]
    типы: Counter = Counter()
    цвета: Counter = Counter()
    содержимое: Counter = Counter()
    годных = 0
    исправлено = 0
    if начала:
        р = разобрать_пакеты(биты, начала)
        верные = р["golay"] >= 0
        годных = int(верные.sum())
        исправлено = int(р["исправлено"])
        for т, ц, д, в in zip(р["тип"], р["цвет"], р["данные"], верные, strict=True):
            if not в:
                continue
            типы[ТИПЫ.get(int(т), f"тип {int(т)}")] += 1
            цвета[int(ц)] += 1
            что = поля(int(т), д)
            if что is not None:
                содержимое[что] += 1
        подробно.append(f"пакетов данных: {len(начала)}, тип слота (Golay (20, 8)) верен у {годных}; "
                        f"цветовой код: " + ", ".join(f"{ц} × {с}" for ц, с in цвета.most_common()))
        if типы:
            подробно.append("типы данных: " + ", ".join(f"{т} × {с}" for т, с in типы.most_common()))
        if исправлено:
            подробно.append(f"BPTC (196, 96): исправлено бит {исправлено}")
        for (вид, строка), с in содержимое.most_common(20):
            подробно.append(f"{вид}: {строка}" + (f" — × {с}" if с > 1 else ""))
    речь = [м for м, в, _ in места if "речь" in в]
    if речь:
        подробно.append(f"сверхкадров речи (синхрослово речи — пакет A): {len(речь)}")
        emb = emb_сверхкадров(биты, речь, 2 * шаг)
        if emb:
            подробно.append(emb)
    доля = годных / len(начала) if начала else согласно / max(1, len(места) - 1)
    проверено = sum(содержимое.values())
    return Находка(
        уровень="канальный",
        что="DMR (ETSI TS 102 361): пакеты слотов" + (", " + ", ".join(т for т, _ in типы.most_common(3)) if типы else ""),
        уверенность=доля,
        мера=f"{len(места)} синхрослов с шагом {шаг}; тип слота верен у {годных} из {len(начала)} пакетов данных"
             + (f"; LC/CSBK/заголовки с верной проверкой: {проверено}" if проверено else ""),
        подробно=подробно, свойства={"шаг": шаг, "цвет": цвета.most_common(1)[0][0] if цвета else None})


def пакет_данных(тип: int, данные96: np.ndarray, цвет: int = 1, синхро: str = "БС, данные") -> np.ndarray:
    """Пакет 264 бита (для проверок): BPTC, тип слота Golay, синхрослово — как в MMDVMHost."""
    сырые = bptc_кодировать(данные96)
    слово = int(СЛОВА_ТИПА[(цвет << 4) | тип])
    тип_биты = np.array([(слово >> (19 - i)) & 1 for i in range(20)], dtype=np.uint8)
    синхро_биты = np.array([(СИНХРО[синхро] >> (47 - i)) & 1 for i in range(48)], dtype=np.uint8)
    return np.concatenate([сырые[:98], тип_биты[:10], синхро_биты, тип_биты[10:], сырые[98:]])
