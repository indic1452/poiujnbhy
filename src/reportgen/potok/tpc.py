# -- строки ------------------------------------------------------------------------------------

def _накоп(биты: np.ndarray) -> np.ndarray:
    return np.concatenate([[0], np.bitwise_xor.accumulate(биты.astype(np.uint8))]).astype(np.uint8)


def _чётность_окон(биты: np.ndarray, L: int) -> np.ndarray:
    """Чётность окна [a, a + L) для всех a (1 — нечётный вес)."""
    накоп = _накоп(биты)
    return накоп[L:] ^ накоп[:-L]


def _без_кратных(итог: list[dict[str, float]], лучших: int, по_началу: bool) -> list[dict[str, float]]:
    """Кратные длины (две строки подряд тоже чётны) уступают своей основе."""
    итог.sort(key=lambda к: -к["z"])
    отобрано: list[dict[str, float]] = []
    for к in итог:
        if any(к["длина"] % о["длина"] == 0
               and (not по_началу or (к["начало"] - о["начало"]) % о["длина"] == 0)
               for о in отобрано):
            continue
        отобрано.append(к)
        if len(отобрано) >= лучших:
            break
    return отобрано


def строки_по_чётности(биты: np.ndarray, *, до: int = ДЛИНА_ДО, от: int = ДЛИНА_ОТ,
                       лучших: int = 5) -> list[dict[str, float]]:
    """Кандидаты (длина строки, начало) по доле окон с чётным весом, лучшие первыми.

    Отрыв считается от половины в обе стороны: скремблер со сбросом на
    каждой строке делает чётность постоянной, но не обязательно нулевой.
    """
    накоп = _накоп(биты)
    итог = []
    for L in range(от, min(до, len(биты) // 16) + 1):
        окна = накоп[L:] ^ накоп[:-L]
        слов = len(окна) // L
        if слов < 16:
            break
        доли = окна[:слов * L].reshape(слов, L).mean(axis=0)       # по началу o
        o = int(np.argmax(np.abs(доли - 0.5)))
        z = abs(1 - 2 * float(доли[o])) * np.sqrt(слов)
        итог.append({"z": float(z), "длина": L, "начало": o, "чётных": 1 - float(доли[o])})
    return _без_кратных(итог, лучших, по_началу=True)


def мера_строк(биты: np.ndarray, *, до: int = ДЛИНА_ДО) -> float:
    """Отрыв (в разбросах) лучшей длины строки по чётности — мера для подбора плоскости."""
    кандидаты = строки_по_чётности(биты, до=до, лучших=1)
    return кандидаты[0]["z"] if кандидаты else 0.0


#: Кадр, почти целиком повторяющий один из стольких прежних, — заполнение.
ПОВТОР_ДО = 16
#: Повтор — расхождение не больше этой доли бит.
ПОВТОР_РАСХОЖДЕНИЕ = 0.05
_ЕДИНИЦ = np.array([bin(i).count("1") for i in range(256)], dtype=np.int32)


def без_повторов(окна: np.ndarray) -> np.ndarray:
    """Маска кадров, не повторяющих ни один из ПОВТОР_ДО прежних (кадры заполнения — повторы).

    Модем без данных шлёт заполнение, и кадры повторяются (у Comtech — через
    4): чётность любого окна в них постоянна, и мера строк кода обманывается.
    Для поиска строк, столбцов и обучения проверок берутся кадры с данными.
    """
    n = len(окна)
    повтор = np.zeros(n, bool)
    if n < 2:
        return ~повтор
    упаковано = np.packbits(окна, axis=1)
    допуск = ПОВТОР_РАСХОЖДЕНИЕ * окна.shape[1]
    for m in range(1, min(ПОВТОР_ДО, n - 1) + 1):
        d = _ЕДИНИЦ[np.bitwise_xor(упаковано[m:], упаковано[:-m])].sum(axis=1)
        повтор[m:] |= d <= допуск
    return ~повтор


def различные_плоскости(блоки: np.ndarray, *, образцов: int = 64) -> np.ndarray:
    """Маска трёхмерных блоков (блоков × n3 × …), где ни одна плоскость не повторяет другую.

    Кадры заполнения повторяются (у Comtech — через 4), и чётность вдоль
    «нитей» через плоскости у них бывает и без третьего измерения кода:
    x ⊕ x = 0. Блок, собранный из разных плоскостей, этим не объясняется.
    Сравниваются плоскости на расстоянии до ПОВТОР_ДО внутри блока; смотрятся
    первые ``образцов`` блоков (маска — только для них).
    """
    блоки = блоки[:образцов]
    nb, n3 = блоки.shape[:2]
    плоские = np.packbits(блоки.reshape(nb, n3, -1), axis=2)
    допуск = ПОВТОР_РАСХОЖДЕНИЕ * int(np.prod(блоки.shape[2:]))
    повтор = np.zeros(nb, bool)
    for m in range(1, min(n3, ПОВТОР_ДО + 1)):
        d = _ЕДИНИЦ[np.bitwise_xor(плоские[:, m:], плоские[:, :-m])].sum(axis=2)
        повтор |= (d <= допуск).any(axis=1)
    return ~повтор


#: Сколько блоков из разных плоскостей нужно, чтобы судить о третьем измерении по ним.
РАЗЛИЧНЫХ_ОТ = 8
#: Сколько блоков из разных плоскостей искать для этого (по всему потоку).
РАЗЛИЧНЫХ_ИСКАТЬ = 64
#: Участок строк — «с данными», если различных строк в нём не меньше этой доли.
РАЗЛИЧНЫХ_СТРОК_ОТ = 0.5


def отобрать_без_повторов(окна: np.ndarray, нужно: int, *, часть: int = 512) -> np.ndarray:
    """Номера первых ``нужно`` окон (кадров, блоков), не повторяющих ни одно из ПОВТОР_ДО прежних.

    Запись часто начинается с долгой паузы — сотен одинаковых кадров
    заполнения, и по первым окнам не найти ни строк, ни проверок кода. Окна
    смотрятся по всему ряду частями (с ПОВТОР_ДО прежними для сравнения),
    пока различных не наберётся ``нужно``.
    """
    n = len(окна)
    итог: list[np.ndarray] = []
    найдено = 0
    for i in range(0, n, часть):
        от = max(0, i - ПОВТОР_ДО)
        кусок = окна[от:i + часть]
        годные = np.flatnonzero(без_повторов(кусок.reshape(len(кусок), -1))[i - от:]) + i
        итог.append(годные)
        найдено += len(годные)
        if найдено >= нужно:
            break
    return np.concatenate(итог)[:нужно] if итог else np.zeros(0, dtype=int)


def _кадры_с_данными(биты: np.ndarray, начала: Sequence[int], длина: int, нужно: int) -> list[int]:
    """Начала первых ``нужно`` кадров, не повторяющих соседей, — по всему потоку, частями."""
    итог: list[int] = []
    часть = max(64, нужно)
    for i in range(0, len(начала), часть):
        от = max(0, i - ПОВТОР_ДО)
        окна = _окна_кадров(биты, начала[от:i + часть], длина, 0)
        годные = без_повторов(окна)[i - от:]
        итог += [int(начала[i + j]) for j in np.flatnonzero(годные)]
        if len(итог) >= нужно:
            break
    return итог[:нужно]


def начало_данных(биты: np.ndarray, начала: Sequence[int], длина: int, *, окно: int = 64,
                  различных: int = 8) -> int:
    """Номер кадра, с которого идут данные: от него в ``окно`` кадрах не меньше ``различных`` различных.

    Запись часто начинается с долгой паузы — одинаковых кадров заполнения (или
    повторяющихся через несколько): по ним ни плоскость, ни код не подобрать.
    Нет такого места — 0.
    """
    годные = [int(н) for н in начала if 0 <= н and н + длина <= len(биты)]
    номер = {н: i for i, н in enumerate(int(н) for н in начала)}
    отбор = [номер[н] for н in _кадры_с_данными(биты, годные, длина, 4 * окно)]
    for j in range(len(отбор) - различных + 1):
        if отбор[j + различных - 1] - отбор[j] < окно:
            return отбор[j]
    return 0


def _участок_с_данными(таблица: np.ndarray, строк: int) -> int:
    """Первая строка участка из ``строк`` строк подряд, где строки в основном различны.

    Одинаковые блоки заполнения в начале записи дают участок из немногих
    различных строк — по нему не найти столбцов. Участки смотрятся с шагом в
    четверть участка (и последний — по концу таблицы: данные бывают короче
    участка); берётся первый, где различных строк не меньше
    РАЗЛИЧНЫХ_СТРОК_ОТ, иначе — с наибольшей их долей (при равенстве — первый).
    Хэши строк считаются частями по мере надобности.
    """
    n = len(таблица)
    if n <= строк:
        return 0
    шаг = max(1, строк // 4)
    начала = list(range(0, n - строк + 1, шаг))
    if начала[-1] != n - строк:
        начала.append(n - строк)
    хэши = np.zeros(0, dtype=np.uint64)
    лучший, доля_лучшего = 0, -1.0
    for r0 in начала:
        if len(хэши) < r0 + строк:
            хэши = np.concatenate([хэши, _хэши_строк(таблица[len(хэши):r0 + строк + 16 * строк])])
        доля = len(np.unique(хэши[r0:r0 + строк])) / строк
        if доля >= РАЗЛИЧНЫХ_СТРОК_ОТ:
            return r0
        if доля > доля_лучшего:
            лучший, доля_лучшего = r0, доля
    return лучший


def _окна_кадров(биты: np.ndarray, начала: Sequence[int], длина: int, запас: int) -> np.ndarray:
    """Кадры из сплошного потока с заходом за конец кадра: (кадров × (длина + запас))."""
    начала = [int(н) for н in начала if 0 <= н and н + длина + запас <= len(биты)]
    if not начала:
        return np.zeros((0, длина + запас), np.uint8)
    индексы = np.asarray(начала)[:, None] + np.arange(длина + запас)[None, :]
    return биты[индексы].astype(np.uint8)


def строки_в_кадрах(биты: np.ndarray, начала: Sequence[int], длина: int, *, до: int = ДЛИНА_ДО,
                    от: int = ДЛИНА_ОТ, лучших: int = 5) -> list[dict[str, float]]:
    """Строки внутри кадров модема: длина n1, начало первой строки и сколько строк в кадре.

    ``биты`` — сплошной поток, ``начала`` — начала кадров (по синхрослову),
    ``длина`` — длина кадра. Строка может заходить за конец кадра: начало
    кадра по синхрослову известно лишь приблизительно, а у Comtech кадр
    2964 = 20 + 2944 — запаса нет ни бита.

    У каждого места строки (начало o + j·L) — своя чётность: при скремблере
    со сбросом на кадре она постоянна, но не обязательно нулевая. Мера места
    — квадрат перекоса (1 − 2p)²: у случайных бит около 1/F (F — кадров), у
    строк кода — близок к 1. Строки кадра — самая длинная серия подряд
    идущих мест с перекосом больше половины.
    """
    окна = _окна_кадров(биты, начала, длина, до)
    окна = окна[без_повторов(окна[:, :длина])]
    F = len(окна)
    if F < 8:
        return []
    накоп = np.concatenate([np.zeros((F, 1), np.uint8), np.bitwise_xor.accumulate(окна, axis=1)], axis=1)
    порог = max(СИЛЬНАЯ_СТРОКА, 8 / F)
    итог = []
    for L in range(от, min(до, длина // 2) + 1):
        перекос = (1 - 2 * (накоп[:, L:] ^ накоп[:, :-L]).mean(axis=0)) ** 2   # по началу окна a
        лучший = None
        for o in range(L):
            места = перекос[o:длина:L]
            if len(места) < 2:
                break
            # Самая длинная серия сильных мест — строки блока в кадре. Сильное
            # место — перекос заметно выше шума 1/F: строка с 30 % нечётных
            # (плохое ОСШ, слабые биты символа) — ещё строка кода.
            сильные = места > порог
            серия, конец, текущая = 0, 0, 0
            for j, с in enumerate(сильные):
                текущая = текущая + 1 if с else 0
                if текущая > серия:
                    серия, конец = текущая, j + 1
            if серия < 2:
                continue
            # Все строки кадра умещаются в кадре (остальное — синхрослово): серия
            # длиннее — захватила случайно сильное место за концом кадра;
            # оставляем самый сильный отрезок из длина // L мест подряд.
            влезет = длина // L
            if серия > влезет:
                отрезок = места[конец - серия:конец]
                суммы = np.convolve(отрезок, np.ones(влезет), mode="valid")
                конец = конец - серия + int(np.argmax(суммы)) + влезет
                серия = влезет
            s_ = float(места[конец - серия:конец].mean())
            z = (s_ - 1 / F) * F * np.sqrt(серия / 2)
            if лучший is None or z > лучший[0]:
                лучший = (z, o + (конец - серия) * L, серия, s_)
        if лучший is not None:
            z, начало, строк, s_ = лучший
            итог.append({"z": float(z), "длина": L, "начало": int(начало), "строк": int(строк),
                         "перекос": s_})
    итог.sort(key=lambda к: -к["z"])
    отобрано: list[dict[str, float]] = []
    for к in итог:
        # Кратная длина уступает основе, только если лежит в её серии: две строки
        # подряд — это серия основы. Серия в другом месте кадра (строки кода
        # рядом с полосой заполнения, у которой чётно любое окно из 8 бит) — своя.
        if any(к["длина"] % о["длина"] == 0 and о["начало"] <= к["начало"]
               and к["начало"] + к["строк"] * к["длина"] <= о["начало"] + о["строк"] * о["длина"]
               for о in отобрано):
            continue
        отобрано.append(к)
        if len(отобрано) >= лучших:
            break
    return отобрано


def мера_в_кадрах(биты: np.ndarray, начала: Sequence[int], длина: int, *, до: int = ДЛИНА_ДО) -> float:
    """Отрыв лучшей длины строки внутри кадров — быстрая мера для подбора плоскости.

    Без поиска серии строк (он нужен для снятия, не для сравнения вариантов):
    для каждой длины L и начала o — средний квадрат перекоса чётности мест
    o + j·L по всему кадру, векторно по o.
    """
    окна = _окна_кадров(биты, начала, длина, до)
    окна = окна[без_повторов(окна[:, :длина])]
    F = len(окна)
    if F < 8:
        return 0.0
    накоп = np.concatenate([np.zeros((F, 1), np.uint8), np.bitwise_xor.accumulate(окна, axis=1)], axis=1)
    лучшее = 0.0
    for L in range(ДЛИНА_ОТ, min(до, длина // 2) + 1):
        J = длина // L
        перекос = (1 - 2 * (накоп[:, L:L + J * L] ^ накоп[:, :J * L]).mean(axis=0)) ** 2
        s_ = float(перекос.reshape(J, L).mean(axis=0).max())
        лучшее = max(лучшее, (s_ - 1 / F) * F * np.sqrt(J / 2))
    return лучшее


_ХЭШ_ОСНОВА = np.uint64(0x9E3779B97F4A7C15)
_ХЭШ_ОБРАТНАЯ = np.uint64(pow(0x9E3779B97F4A7C15, -1, 1 << 64))
#: Доля одинаковых строк таблицы, с которой повторы учитываются (окна считаются по разным).
ПОВТОРНЫХ_СТРОК_ОТ = 0.01


def _хэши_строк(таблица: np.ndarray) -> np.ndarray:
    """Хэш каждой строки таблицы (uint64): у строк до 64 бит — сама строка."""
    упаковано = np.packbits(таблица.astype(np.uint8), axis=1)
    добавить = (-упаковано.shape[1]) % 8
    if добавить:
        упаковано = np.pad(упаковано, ((0, 0), (0, добавить)))
    куски = np.ascontiguousarray(упаковано).view(">u8").astype(np.uint64)
    хэш = np.zeros(len(таблица), dtype=np.uint64)
    with np.errstate(over="ignore"):
        for j in range(куски.shape[1]):
            хэш = (хэш * np.uint64(0x100000001B3)) ^ куски[:, j]
    return хэш


def _хэши_окон(хэши: np.ndarray, L: int) -> np.ndarray:
    """Хэш содержимого окна из L строк подряд для каждого начала (скользящий, по модулю 2⁶⁴)."""
    n = len(хэши)
    with np.errstate(over="ignore"):
        степени = np.concatenate([[np.uint64(1)], np.cumprod(np.full(n, _ХЭШ_ОСНОВА, dtype=np.uint64))])
        обратные = np.concatenate([[np.uint64(1)], np.cumprod(np.full(n, _ХЭШ_ОБРАТНАЯ, dtype=np.uint64))])
        суммы = np.concatenate([[np.uint64(0)], np.cumsum(хэши * степени[:n], dtype=np.uint64)])
        return (суммы[L:] - суммы[:-L]) * обратные[:n - L + 1]


def столбцы_по_чётности(таблица: np.ndarray, *, до: int = ДЛИНА_ДО, от: int = 2,
                        лучших: int = 3, длины: Sequence[int] | None = None) -> list[dict[str, float]]:
    """Длина столбца и строка начала блока — по чётности вдоль столбцов таблицы строк.

    Перекос считается у каждого столбца отдельно: скремблер со сбросом делает
    часть столбцов нечётными, и средняя по столбцам доля нечётных обманула
    бы. Годится и для глубины: «таблица» — плоскости, развёрнутые в строки.

    Повторяющиеся блоки (заполнение при скремблере со сбросом на блоке) дают
    постоянную чётность у ЛЮБОГО окна внутри блока — и короткое окно,
    встречаясь чаще, обгоняет настоящий столбец. Поэтому, если в таблице есть
    одинаковые строки, окна с одинаковым содержимым считаются один раз.
    """
    T, C = таблица.shape
    накоп = np.concatenate([np.zeros((1, C), np.uint8),
                            np.bitwise_xor.accumulate(таблица.astype(np.uint8), axis=0)])
    хэши = _хэши_строк(таблица)
    повторы = len(np.unique(хэши)) < (1 - ПОВТОРНЫХ_СТРОК_ОТ) * T
    итог = []
    for L in (range(от, min(до, T // 8) + 1) if длины is None
              else sorted({int(д) for д in длины if от <= int(д) <= min(до, T // 8)})):
        окна = накоп[L:] ^ накоп[:-L]                                  # (T − L + 1) × C
        слов = len(окна) // L
        if слов < 8:
            break
        if not повторы:
            доли = окна[:слов * L].reshape(слов, L, C).mean(axis=0)   # L × C: по началу и столбцу
            перекос = ((1 - 2 * доли) ** 2).mean(axis=1)               # по началу
            o = int(np.argmax(перекос))
            z = (float(перекос[o]) - 1 / слов) * слов * np.sqrt(C / 2)
            итог.append({"z": float(z), "длина": L, "начало": o, "чётных": float(1 - доли[o].mean()),
                         "перекос": float(перекос[o])})
            continue
        # Окна a = o + j·L; у каждого начала o — только первые окна с данным содержимым.
        места = np.arange(слов * L)
        начала = места % L
        хэши_окон = _хэши_окон(хэши, L)[места]
        порядок = np.lexsort((места, хэши_окон, начала))
        первые = np.ones(len(порядок), bool)
        первые[1:] = (начала[порядок][1:] != начала[порядок][:-1]) | \
            (хэши_окон[порядок][1:] != хэши_окон[порядок][:-1])
        разные = порядок[первые]                                      # по возрастанию начала
        o_разных = начала[разные]
        сколько = np.bincount(o_разных, minlength=L)
        есть = np.flatnonzero(сколько)
        суммы = np.add.reduceat(окна[разные].astype(np.int32), np.searchsorted(o_разных, есть), axis=0)
        доли = суммы / сколько[есть][:, None]
        перекос_o = ((1 - 2 * доли) ** 2).mean(axis=1)
        n_o = сколько[есть]
        z_o = np.where(n_o >= 8, (перекос_o - 1 / n_o) * n_o * np.sqrt(C / 2), -np.inf)
        i = int(np.argmax(z_o))
        if np.isfinite(z_o[i]):
            итог.append({"z": float(z_o[i]), "длина": L, "начало": int(есть[i]),
                         "чётных": float(1 - доли[i].mean()), "перекос": float(перекос_o[i])})
    return _без_кратных(итог, лучших, по_началу=False)


# -- проверки, синдромы, исправление ------------------------------------------------------------

def _с_единицей(слова: np.ndarray) -> np.ndarray:
    return np.hstack([слова, np.ones((len(слова), 1), dtype=слова.dtype)])


def синдромы(слова: np.ndarray, H: np.ndarray) -> np.ndarray:
    """Синдромы слов по аффинным проверкам: строка H — (h, c), проверка h·x = c."""
    return ((слова.astype(np.int32) @ H[:, :-1].T.astype(np.int32)) + H[:, -1]) & 1


def проверки(слова: np.ndarray) -> np.ndarray:
    """Пространство проверок кода по словам с ошибками: строки (h, c) — проверка h·x = c.

    Проверки аффинные: скремблер со сбросом на каждой строке (или столбце)
    делает вес строки нечётным, и проверка «сумма бит = 0» становится
    «= 1». Поэтому к слову добавляется постоянная единица — аффинная
    проверка над ним становится обычной линейной.

    Слово с ошибкой среди опорных «съедает» часть проверок: у (64, 57) при
    ошибках 10⁻³ с первого прохода выделяются 4 проверки из 7. Поэтому
    первые опорные — слова с чётностью большинства (одиночная ошибка её
    ломает), затем уточнение: опорные — слова, уже удовлетворяющие найденным
    проверкам; новые проверки сверяются со всеми словами, пока пространство
    растёт.
    """
    n = слова.shape[1]
    # Повторы (кадры заполнения повторяются) схлопываются: иначе связи,
    # случайно общие у повторяющихся слов, выполнялись бы в «большинстве» слов.
    слова, сколько = np.unique(слова, axis=0, return_counts=True)
    # У короткого кода кодовых слов мало, и каждое повторяется, а слова с одиночной
    # ошибкой почти все разные — после схлопывания повторов их среди различных
    # большинство, и связи не выделяются. Слово рядом с заметно более частым — шум.
    слова = слова[~искажённые(слова, сколько)]
    # np.unique сортирует: подряд идут слова с общими ведущими битами — опорные
    # из них вырождены. Перемешиваем (зерно постоянное — разбор повторяем).
    слова = слова[np.random.default_rng(1).permutation(len(слова))]
    полные = _с_единицей(слова)
    чётность = слова.sum(axis=1) & 1
    своя = int(чётность.mean() > 0.5)
    опорные = полные[чётность == своя]
    if abs(чётность.mean() - 0.5) < 0.2 or len(опорные) < n + 16 + 64:
        опорные = полные
    H = _годные(dlinnye.пространство(опорные, n + 1), полные)
    for _ in range(УТОЧНЕНИЙ):
        if not len(H):
            break
        чистые = полные[~синдромы(слова, H).any(axis=1)]
        if len(чистые) < n + 16 + 64:
            break
        новые = _годные(dlinnye.пространство(чистые, n + 1), полные)
        if not len(новые):
            break
        приведённая, _ = gf2.привести(gf2.упаковать(np.vstack([H, новые])), n + 1)
        вместе = gf2.распаковать(приведённая, n + 1)
        if len(вместе) <= len(H):
            break
        H = вместе
    # Проверка без бит слова (только «1 = 0») — след шума, не проверка.
    return H[H[:, :-1].any(axis=1)] if len(H) else H


#: Слово — искажённое, если слово на расстоянии 1 от него встречается во столько раз чаще.
ЧАЩЕ_СОСЕДА = 8


def искажённые(слова: np.ndarray, сколько: np.ndarray) -> np.ndarray:
    """Маска различных слов, которые — одиночная ошибка в заметно более частом слове.

    У кода с проверками два кодовых слова не бывают на расстоянии 1, так что
    слово рядом с частым (в ЧАЩЕ_СОСЕДА раз и больше) — искажённое. Слова до 64
    бит (у длинных кодов слова и так не повторяются).
    """
    n = слова.shape[1]
    итог = np.zeros(len(слова), dtype=bool)
    if n > 64 or not len(слова) or int(сколько.max()) < ЧАЩЕ_СОСЕДА:
        return итог
    упаковано = np.packbits(слова.astype(np.uint8), axis=1)
    упаковано = np.pad(упаковано, ((0, 0), (0, 8 - упаковано.shape[1])))
    значения = np.ascontiguousarray(упаковано).view(">u8").astype(np.uint64).reshape(-1)
    порядок = np.argsort(значения)
    отсорт, сч = значения[порядок], сколько[порядок]
    for j in range(n):
        сосед = значения ^ np.uint64(1 << (63 - j))
        i = np.minimum(np.searchsorted(отсорт, сосед), len(отсорт) - 1)
        итог |= (отсорт[i] == сосед) & (сч[i] >= ЧАЩЕ_СОСЕДА * сколько)
    return итог


def _годные(H: np.ndarray, полные: np.ndarray) -> np.ndarray:
    if not len(H):
        return H
    return H[dlinnye.нарушения(полные, H) < dlinnye.НАРУШЕНИЙ_ДО]


def _таблица_синдромов(H: np.ndarray) -> dict[bytes, int]:
    """Синдром одиночной ошибки → позиция (только однозначные); H — без столбца единицы."""
    таблица: dict[bytes, int] = {}
    повторы = set()
    for j in range(H.shape[1]):
        ключ = np.packbits(H[:, j]).tobytes()
        if not H[:, j].any():
            continue
        if ключ in таблица:
            повторы.add(ключ)
        таблица[ключ] = j
    for ключ in повторы:
        del таблица[ключ]
    return таблица


def _синдромы_мест(слова: np.ndarray, H: np.ndarray, смещения: np.ndarray | None) -> np.ndarray:
    """Синдромы с поправкой места: слова идут блок за блоком, у места p — своя поправка."""
    синдр = синдромы(слова, H)
    if смещения is not None and len(смещения):
        синдр = синдр ^ np.tile(смещения, (len(слова) // len(смещения), 1))
    return синдр


def исправить(слова: np.ndarray, H: np.ndarray, смещения: np.ndarray | None = None
              ) -> tuple[np.ndarray, int]:
    """Одиночные ошибки по синдрому: (исправленные слова, сколько исправлено).

    ``смещения`` — поправки синдрома по месту слова в блоке (места × проверки),
    если на блок наложена постоянная маска; слова тогда — целое число блоков.
    """
    if not len(H):
        return слова, 0
    синдр = _синдромы_мест(слова, H, смещения)
    таблица = _таблица_синдромов(H[:, :-1])
    слова = слова.copy()
    исправлено = 0
    for i in np.flatnonzero(синдр.any(axis=1)):
        j = таблица.get(np.packbits(синдр[i].astype(np.uint8)).tobytes())
        if j is not None:
            слова[i, j] ^= 1
            исправлено += 1
    return слова, исправлено


def _без_нарушений(слова: np.ndarray, H: np.ndarray, смещения: np.ndarray | None = None) -> float:
    if not len(H) or not len(слова):
        return 1.0
    return float(np.mean(~_синдромы_мест(слова, H, смещения).any(axis=1)))


def проверки_оси(блоки: np.ndarray, ось: int) -> tuple[np.ndarray, np.ndarray | None]:
    """Проверки слов вдоль оси и поправки синдрома по месту слова в блоке (или None).

    Скремблер со сбросом на блоке, наложенный ПОСЛЕ кода, прибавляет к
    каждому блоку одну и ту же маску M: слово на месте p — кодовое ⊕ m_p.
    Общая аффинная проверка (постоянная единица) это покрывает, только если
    поправка у всех мест одна; иначе проверки, задевающие места с разными
    поправками, отбрасываются, и код выглядит слабее. Разность двух блоков
    маску гасит: по разностям соседних блоков выделяется полное пространство
    проверок, а поправка синдрома каждого места — большинством по блокам.
    Берётся тот способ, что дал больше проверок.
    """
    nb = len(блоки)
    слова = _слова_оси(блоки, ось)
    H = проверки(слова)
    if nb < 4:
        return H, None
    n = слова.shape[1]
    места = слова.reshape(nb, -1, n)
    разности = (места[1:] ^ места[:-1]).reshape(-1, n)
    H_р = проверки(разности)
    if len(H_р) <= len(H):
        return H, None
    H_р = H_р.copy()
    H_р[:, -1] = 0
    поправки = (синдромы(слова, H_р).reshape(nb, места.shape[1], -1).mean(axis=0) > 0.5)
    return H_р, поправки.astype(np.uint8)


# -- блоки любой размерности --------------------------------------------------------------------

def _слова_оси(блоки: np.ndarray, ось: int) -> np.ndarray:
    """Слова вдоль оси ``ось`` блоков (блоков × … × n1): строки матрицы (…, n_ось)."""
    return np.moveaxis(блоки, ось, -1).reshape(-1, блоки.shape[ось])


def _вернуть_оси(слова: np.ndarray, блоки: np.ndarray, ось: int) -> np.ndarray:
    форма = np.moveaxis(блоки, ось, -1).shape
    return np.moveaxis(слова.reshape(форма), -1, ось)


def декодировать(блоки: np.ndarray, H1: np.ndarray, H2: np.ndarray, H3: np.ndarray | None = None,
                 итераций: int = ИТЕРАЦИЙ, *, поправки: Sequence[np.ndarray | None] | None = None
                 ) -> tuple[np.ndarray, dict[str, object]]:
    """Итеративное жёсткое декодирование блоков: (блоков × n2 × n1) или (блоков × n3 × n2 × n1).

    H1 — проверки строк (последняя ось), H2 — столбцов, H3 — глубины (для
    трёхмерного блока); ``поправки`` — поправки синдрома по месту слова в
    блоке для каждого измерения (см. ``проверки_оси``) или None.
    """
    блоки = блоки.copy()
    поправки = list(поправки or [None, None, None])
    оси = [(блоки.ndim - 1, H1, поправки[0]), (блоки.ndim - 2, H2, поправки[1])]
    if блоки.ndim == 4:
        if H3 is None:
            raise ValueError("у трёхмерного блока нужны проверки глубины")
        оси.append((1, H3, поправки[2] if len(поправки) > 2 else None))
    до = [_без_нарушений(_слова_оси(блоки, ось), H, п) for ось, H, п in оси]
    всего = 0
    for _ in range(итераций):
        за_круг = 0
        for ось, H, п in оси:
            слова, исправлено = исправить(_слова_оси(блоки, ось), H, п)
            блоки = _вернуть_оси(слова, блоки, ось)
            за_круг += исправлено
        всего += за_круг
        if not за_круг:
            break
    после = [_без_нарушений(_слова_оси(блоки, ось), H, п) for ось, H, п in оси]
    nb = len(блоки)
    плохие = np.zeros(nb, bool)
    for ось, H, п in оси:
        if len(H):
            # Слова оси идут блок за блоком (ось блоков остаётся первой).
            плохие |= _синдромы_мест(_слова_оси(блоки, ось), H, п).any(axis=1).reshape(nb, -1).any(axis=1)
    сводка: dict[str, object] = {"исправлено": всего, "блоков_чисто": float(np.mean(~плохие))}
    for имя, д, п in zip(ИЗМЕРЕНИЯ, до, после, strict=False):
        сводка[f"{имя}_до"] = д
        сводка[f"{имя}_после"] = п
    return блоки, сводка


