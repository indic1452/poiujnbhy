"""ТКБ — турбокод блочный (код произведения, в зарубежной литературе TPC) вслепую: двумерный и трёхмерный.

Блок TPC — таблица n2 × n1 (двумерный) или n3 × n2 × n1 (трёхмерный): каждая
строка — слово кода строк (обычно расширенный Хэмминг (64, 57), (32, 26),
(16, 11), (256, 247) или код с проверкой на чётность), каждый столбец — слово
кода столбцов, у трёхмерного каждая «нить» вдоль плоскостей — слово кода
глубины. Блок передаётся по строкам, плоскость за плоскостью; укороченные
коды (46, 39) и т. п. — без части строк, столбцов или плоскостей. Так
устроены TPC модемов Comtech (например, (64, 57) × (46, 39) со скоростью 3/4
в кадре 2964 бит: синхрослово 20 бит и блок 2944), AHA, IESS-315 и др.
Параметры кода производитель не раскрывает — поэтому всё восстанавливается
по потоку:

1. **Строки.** У расширенного Хэмминга и кода чётности вес каждого слова
   чётный. Для каждой длины окна L и начала o считается доля окон с чётным
   весом: у верной (n1, o1) она близка к 1 (минус ошибки линии), у
   прочих — к половине. Мера — отрыв в разбросах (z): у случайного потока
   максимум по всем (L, o) — 4–5, у TPC — десятки. В кадрах модема (между
   синхрословами) строки ищутся от начала каждого кадра: блок начинается в
   кадре на одном и том же месте, и синхрослово не нужно вырезать с
   точностью до бита.
2. **Проверки** — пространство проверок слов ранговым методом с учётом шума
   (как у длинных кодов): не только чётность, а все проверки кода, при любом
   расположении проверочных бит; аффинные — скремблер со сбросом на строке
   делает чётность нечётной, и это не мешает.
3. **Столбцы.** Чётность вдоль столбцов таблицы строк — у каждого столбца
   отдельно (перекос его доли нечётных окон): длина столбца n2 и строка, с
   которой начинается блок.
4. **Глубина.** Та же чётность вдоль «нитей» через плоскости n2 × n1 —
   третье измерение, если оно есть: длина n3 и плоскость начала блока.
5. **Декодирование** — итеративное жёсткое: строки, столбцы, нити глубины по
   очереди, исправление одиночной ошибки по синдрому; двойные ошибки
   расширенный Хэмминг обнаруживает и оставляет другим измерениям. Так TPC
   и работает — «турбо» в названии за счёт этих итераций. Второй круг —
   проверки заново по исправленным блокам.
6. **Данные** — информационные позиции каждого измерения (где код
   систематичен), по строкам блока.

Над кодом бывает модуляционная неоднозначность (поворот созвездия ФМ,
иной код меток) — тогда строки не видны, пока плоскость не подобрана;
меры ``мера_строк`` и ``мера_в_кадрах`` для этого и отданы подбору плоскости.
"""

