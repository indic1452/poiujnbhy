#: Бит для поиска строк и столбцов по пространству проверок (ранговым методом).
ВЫБОРКА_ПРОВЕРОК = 1 << 18
#: Секунд на такой поиск: при снятии вручную и в окне поиска.
БЮДЖЕТ_ПРОВЕРОК = 8.0
#: То же в автомате (он зовёт снятие ТКБ на каждом уровне разбора): только короткие слова.
АВТОМАТ_ПРОВЕРОК = 1.5


def по_проверкам(биты: np.ndarray, *, до: int = ДЛИНА_ДО, от: int = ДЛИНА_ОТ,
                 бюджет: float = БЮДЖЕТ_ПРОВЕРОК) -> dict[str, float] | None:
    """Длина и начало слова по пространству проверок — когда чётности у слов нет.

    У кода Хэмминга без бита общей чётности, БЧХ (31, 21) и других кодов
    нечётного веса доля чётных окон не выделяется. Зато в окне, где слово
    лежит целиком, есть линейные связи бит (ранговый метод длинных кодов).
    Окно берётся длиной L (а не 2L, где слово целиком при любом начале):
    при ошибках линии слово из 2L бит чаще искажено, и искажённые опорные
    слова «съедают» связи. Поэтому у каждой длины L пробуются начала с
    шагом L/8 (у связей Хэмминга носитель широкий — у начала, сдвинутого на
    несколько бит, связей меньше, но они есть), затем начало уточняется
    туда, где связей больше.
    """
    выборка = биты[:ВЫБОРКА_ПРОВЕРОК]
    конец = time.monotonic() + бюджет
    for L in range(max(от, 4), до + 1):
        if len(dlinnye.слова(выборка, L)) < L + 16 + 64:
            return None
        шаг = max(1, L // 8)
        лучший = None
        for o in range(0, L, шаг):
            if time.monotonic() > конец:
                return None
            c = dlinnye._проверок(выборка, L, o)
            if c and (лучший is None or c > лучший[0]):
                лучший = (c, o)
        if лучший is None:
            continue
        c, o = лучший
        for знак in (1, -1):
            while True:
                соседний = dlinnye._проверок(выборка, L, (o + знак) % L)
                if соседний <= c:
                    break
                o, c = (o + знак) % L, соседний
        return {"длина": int(L), "начало": int(o), "проверок": int(c), "z": float(ПОРОГ_Z),
                "чётных": float("nan")}
    return None


def _начало_столбцов(таблица: np.ndarray, n2: int, слов: int = 4096) -> tuple[int, int]:
    """Строка начала блока по числу связей в словах-столбцах (все столбцы сразу): (начало, связей)."""
    лучший = (0, -1)
    for b in range(n2):
        блоков = (len(таблица) - b) // n2
        if блоков < 1:
            break
        W = таблица[b:b + блоков * n2].reshape(блоков, n2, -1).transpose(0, 2, 1).reshape(-1, n2)[:слов]
        опорных = n2 + 16
        if len(W) < опорных + 64:
            break
        _, доли = dlinnye.зависимости(W, опорных)
        c = int(np.count_nonzero(доли < dlinnye.НАРУШЕНИЙ_ДО))
        if c > лучший[1]:
            лучший = (b, c)
    return лучший


def _параметры_строк(выборка: np.ndarray, строка: int | None, начало: int | None, до: int,
                     проверками: float = БЮДЖЕТ_ПРОВЕРОК) -> tuple[int, int, float, float]:
    if строка is None:
        кандидаты = строки_по_чётности(выборка, до=до)
        if not кандидаты or кандидаты[0]["z"] < ПОРОГ_Z:
            # Чётности у строк нет — код без бита общей чётности: строки по проверкам.
            лучший = по_проверкам(выборка, до=до, бюджет=проверками) if проверками > 0 else None
            if лучший is None or not лучший["проверок"]:
                raise ValueError("строки ТКБ не найдены: нет длины окна ни с чётным весом, ни с "
                                 "линейными связями бит")
            return int(лучший["длина"]), int(лучший["начало"]), -float(лучший["проверок"]), лучший["чётных"]
        лучший = кандидаты[0]
        return int(лучший["длина"]), int(лучший["начало"]), лучший["z"], лучший["чётных"]
    начало = int(начало or 0) % строка
    окна = _чётность_окон(выборка[начало:], строка)[::строка]
    чётных = 1 - float(окна.mean()) if len(окна) else 0.0
    return int(строка), начало, abs(2 * чётных - 1) * np.sqrt(max(1, len(окна))), чётных


def _глубина_подтверждена(блоки: np.ndarray, H3: np.ndarray, поправки3: np.ndarray | None,
                         сводка3: dict[str, object], сводка2: dict[str, object]) -> bool:
    """Третье измерение настоящее: проверки глубины выполнены в блоках из разных плоскостей.

    Такие блоки ищутся по всему потоку (до РАЗЛИЧНЫХ_ИСКАТЬ): в начале записи
    бывает долгое заполнение из одинаковых плоскостей.
    """
    номера: list[np.ndarray] = []
    найдено = 0
    for i in range(0, len(блоки), 4 * РАЗЛИЧНЫХ_ИСКАТЬ):
        различные = различные_плоскости(блоки[i:i + 4 * РАЗЛИЧНЫХ_ИСКАТЬ], образцов=4 * РАЗЛИЧНЫХ_ИСКАТЬ)
        номера.append(np.flatnonzero(различные) + i)
        найдено += int(различные.sum())
        if найдено >= РАЗЛИЧНЫХ_ИСКАТЬ:
            break
    выбор_ = np.concatenate(номера)[:РАЗЛИЧНЫХ_ИСКАТЬ] if номера else np.zeros(0, dtype=int)
    if len(выбор_) < РАЗЛИЧНЫХ_ОТ:
        return float(сводка3["блоков_чисто"]) > float(сводка2["блоков_чисто"])
    выбор = блоки[выбор_]
    нарушены = _синдромы_мест(_слова_оси(выбор, 1), H3, поправки3).any(axis=1)
    return float(np.mean(~нарушены.reshape(len(выбор), -1).any(axis=1))) >= БЛОКОВ_ЧИСТО_ОТ


def снять(биты: np.ndarray, *, строка: int | None = None, начало: int | None = None,
          столбец: int | None = None, блок: int | None = None,
          глубина: int | None = None, плоскость: int | None = None,
          трёхмерный: bool | None = None, до: int = ДЛИНА_ДО,
          столбцы: Sequence[int] | None = None,
          проверками: float = БЮДЖЕТ_ПРОВЕРОК) -> tuple[np.ndarray, Находка]:
    """Снять TPC: параметры, которых не задано, находятся по потоку.

    ``строка``, ``начало`` — длина строки n1 и бит начала строки;
    ``столбец``, ``блок`` — длина столбца n2 и номер строки, с которой
    начинается плоскость (блок двумерного кода); ``глубина``, ``плоскость`` —
    число плоскостей n3 и номер плоскости начала трёхмерного блока.
    ``трёхмерный`` — True/False, чтобы не искать (или обязательно найти)
    третье измерение; None — искать. ``столбцы`` — вероятные длины столбца
    (в кадрах модема — кратные и делители числа строк в кадре): ищутся
    первыми, остальные — если среди них ничего не выделилось. ``проверками``
    — секунд на поиск строк и столбцов по пространству проверок, если общей
    чётности у них нет (0 — не искать). Возвращает (данные, находка).
    """
    выборка = биты[:ВЫБОРКА]
    n1, начало, z_строк, чётных = _параметры_строк(выборка, строка, начало, до, проверками)
    try:
        return _снять_со_строк(биты, n1, начало, z_строк, чётных, столбец=столбец, блок=блок,
                               глубина=глубина, плоскость=плоскость, трёхмерный=трёхмерный, до=до,
                               столбцы=столбцы, проверками=проверками)
    except ValueError:
        if строка is not None or z_строк < 0 or проверками <= 0:
            raise
        # Чётные окна бывают и не у строк (сумма строк кода с чётными столбцами): строки — по проверкам.
        другие = по_проверкам(выборка, до=до, бюджет=проверками)
        if другие is None or not другие["проверок"] or (другие["длина"], другие["начало"]) == (n1, начало):
            raise
        return _снять_со_строк(биты, int(другие["длина"]), int(другие["начало"]), -float(другие["проверок"]),
                               float("nan"), столбец=столбец, блок=блок, глубина=глубина, плоскость=плоскость,
                               трёхмерный=трёхмерный, до=до, столбцы=столбцы, проверками=проверками)


def _снять_со_строк(биты: np.ndarray, n1: int, начало: int, z_строк: float, чётных: float, *,
                    столбец: int | None, блок: int | None, глубина: int | None, плоскость: int | None,
                    трёхмерный: bool | None, до: int, столбцы: Sequence[int] | None, проверками: float
                    ) -> tuple[np.ndarray, Находка]:
    """Снятие, когда строки (длина n1 и начало) уже известны."""
    таблица = dlinnye.слова(биты, n1, начало)
    if len(таблица) < 64:
        raise ValueError("слишком короткий поток для ТКБ")
    учебных = max(64, min(ВЫБОРКА // n1, СТРОК_ДЛЯ_ПОИСКА))
    # Долгое заполнение в начале записи: столбцы и глубина ищутся по участку с данными.
    r0 = _участок_с_данными(таблица, учебных) if столбец is None or глубина is None else 0
    if столбец is None:
        учебные = таблица[r0:r0 + учебных]
        кандидаты2 = столбцы_по_чётности(учебные, до=до, длины=столбцы) if столбцы else []
        if not кандидаты2 or кандидаты2[0]["z"] < ПОРОГ_Z:
            кандидаты2 = столбцы_по_чётности(учебные, до=до)
        if not кандидаты2 or кандидаты2[0]["z"] < ПОРОГ_Z:
            # Столбцы без общей чётности — по проверкам вдоль одного столбца таблицы строк.
            по_столбцу = None
            срок = time.monotonic() + проверками / 2
            for c in range(min(4, n1) if проверками > 0 else 0):
                по_столбцу = по_проверкам(учебные[:, c].copy(), до=до, от=2,
                                          бюджет=max(0.0, срок - time.monotonic()))
                if по_столбцу is not None and по_столбцу["проверок"] or time.monotonic() > срок:
                    break
            if по_столбцу is None or not по_столбцу["проверок"]:
                raise ValueError(f"строки по {n1} бит нашлись, а столбцов ни с чётным весом, ни с "
                                 f"линейными связями нет — это не ТКБ (ищите блочный код строк)")
            # Начало блока — по связям всех столбцов сразу (у циклического кода столбец,
            # сдвинутый на строку, тоже почти весь — слово кода: одного столбца мало).
            b, связей = _начало_столбцов(учебные, int(по_столбцу["длина"]))
            по_столбцу.update({"начало": b, "проверок": max(связей, по_столбцу["проверок"])})
            кандидаты2 = [по_столбцу]
            по_столбцу["z"] = -float(по_столбцу["проверок"])
        столбец = int(кандидаты2[0]["длина"])
        блок = (r0 + int(кандидаты2[0]["начало"])) % столбец
        z_столбцов = кандидаты2[0]["z"]
    else:
        блок = int(блок or 0) % столбец
        z_столбцов = 0.0
    n2 = int(столбец)
    плоскостей = (len(таблица) - блок) // n2
    if плоскостей < 2:
        raise ValueError("меньше двух блоков ТКБ")
    плоскости = таблица[блок:блок + плоскостей * n2].reshape(плоскостей, n2, n1)
    # Третье измерение: чётность вдоль нитей через плоскости.
    n3 = 0
    z_глубины = 0.0
    if глубина is not None:
        n3, плоскость = int(глубина), int(плоскость or 0) % int(глубина)
    elif трёхмерный is not False:
        # Нити глубины — по выборке мест плоскости: перекос у каждой нити свой, и
        # сотен мест хватает с запасом (у плоскости 64 × 46 их почти три тысячи).
        места = np.linspace(0, n2 * n1 - 1, min(n2 * n1, МЕСТ_ГЛУБИНЫ)).astype(int)
        p0 = min(max(0, -(-(r0 - блок) // n2)), max(0, плоскостей - 64))   # первая плоскость участка
        кандидаты3 = столбцы_по_чётности(
            плоскости.reshape(плоскостей, n2 * n1)[p0:p0 + max(64, учебных // n2)][:, места],
            до=min(ГЛУБИНА_ДО, плоскостей // 4), от=2)
        if кандидаты3 and кандидаты3[0]["z"] >= ПОРОГ_Z:
            n3 = int(кандидаты3[0]["длина"])
            плоскость, z_глубины = (p0 + int(кандидаты3[0]["начало"])) % n3, кандидаты3[0]["z"]
        elif трёхмерный:
            raise ValueError("третьего измерения (чётности вдоль плоскостей) нет")
    def собрать(n3: int, плоскость: int):
        """Блоки нужной размерности, проверки и декодирование: (H, чистые, сводка, блоков, плоскость)."""
        if n3:
            блоков = (плоскостей - плоскость) // n3
            if блоков < 2:
                raise ValueError("меньше двух трёхмерных блоков")
            блоки = плоскости[плоскость:плоскость + блоков * n3].reshape(блоков, n3, n2, n1)
        else:
            блоков, плоскость = плоскостей, 0
            блоки = плоскости
        # Обучение — по блокам без повторов со всего потока: в начале записи бывает
        # долгое заполнение, и проверки, выученные по одинаковым блокам, лишние.
        учить = отобрать_без_повторов(блоки, max(2, ВЫБОРКА // блоки[0].size))
        if len(учить) < 2:
            учить = np.arange(min(2, len(блоки)))
        обучение = блоки[учить]
        оси = [обучение.ndim - 1, обучение.ndim - 2] + ([1] if n3 else [])
        выучено = [проверки_оси(обучение, ось) for ось in оси]
        H = [h for h, _ in выучено]
        поправки = [п for _, п in выучено]
        if not all(len(h) for h in H):
            raise ValueError("проверки " + ", ".join(имя for имя, h in zip(ИЗМЕРЕНИЯ, H, strict=False) if not len(h))
                             + " не выделились")
        чистые, сводка = декодировать(блоки, *H, поправки=поправки)
        # Второй круг: по исправленным блокам проверки выделяются полнее (в опорных
        # словах меньше ошибок) — и декодирование по полным проверкам точнее.
        for _ in range(ПЕРЕУЧИТЬ):
            учёба = чистые[учить]
            новые = [проверки_оси(учёба, ось) for ось in оси]
            if all(len(н) <= len(h) for (н, _), h in zip(новые, H, strict=False)):
                break
            for i, (н, п) in enumerate(новые):
                if len(н) > len(H[i]):
                    H[i], поправки[i] = н, п
            чистые, итог = декодировать(блоки, *H, поправки=поправки)
            сводка = {**итог, **{к: з for к, з in сводка.items() if к.endswith("_до")}}
        сводка["поправки"] = [п is not None for п in поправки]
        return H, чистые, сводка, блоков, плоскость, поправки

    if n3 and глубина is None:
        # Глубина найдена сама: чётность вдоль плоскостей бывает и у повторов
        # (кадры заполнения через 4). Судят блоки из РАЗНЫХ плоскостей: у
        # настоящего трёхмерного кода проверки глубины выполнены и в них, у
        # повторов — нет. Если таких блоков мало, трёхмерное принимается,
        # только если декодирует лучше двумерного.
        try:
            трёх = собрать(n3, плоскость)
        except ValueError:
            трёх = None
        двух = собрать(0, 0)
        if трёх is None or not _глубина_подтверждена(трёх[1], трёх[0][2], трёх[5][2], трёх[2], двух[2]):
            n3, z_глубины = 0, 0.0
            H, чистые, сводка, блоков, плоскость, поправки = двух
        else:
            H, чистые, сводка, блоков, плоскость, поправки = трёх
    else:
        H, чистые, сводка, блоков, плоскость, поправки = собрать(n3, плоскость or 0)
    инфо = [dlinnye.информационные(h[:, :-1]) for h in H]       # строк, столбцов[, глубины]
    выбор = чистые
    if n3:
        выбор = выбор[:, инфо[2]]
        выбор = выбор[:, :, инфо[1]][:, :, :, инфо[0]]
    else:
        выбор = выбор[:, инфо[1]][:, :, инфо[0]]
    данные = выбор.reshape(-1)
    k = [len(и) for и in инфо]
    n = [n1, n2] + ([n3] if n3 else [])
    систем = all(np.array_equal(и, np.arange(len(и))) for и in инфо)
    коды = " × ".join(f"({nn}, {kk})" for nn, kk in zip(n, k, strict=False))
    скорость_ч, скорость_з = int(np.prod(k)), int(np.prod(n))
    подробно = [
        (f"строка {n1} бит с бита {начало} (чётных строк {чётных * 100:.1f} %, отрыв "
         f"{z_строк:.0f} разбросов)" if z_строк >= 0 else
         f"строка {n1} бит с бита {начало} — по пространству проверок (общей чётности у строк нет: "
         f"в окне из {n1} бит {-z_строк:.0f} линейных связей)")
        + f"; проверок строки {len(H[0])} → k1 = {k[0]}",
        f"столбец {n2} строк, плоскость с {блок}-й строки ({n1 * n2} бит)"
        + (f", отрыв {z_столбцов:.0f} разбросов" if z_столбцов > 0 else
           " — по пространству проверок (общей чётности у столбцов нет)" if z_столбцов < 0 else "")
        + f"; проверок столбца {len(H[1])} → k2 = {k[1]}",
    ]
    if n3:
        подробно.append(f"глубина {n3} плоскостей, блок с {плоскость}-й плоскости "
                        f"({n1 * n2 * n3} бит)" + (f", отрыв {z_глубины:.0f} разбросов" if z_глубины else "")
                        + f"; проверок глубины {len(H[2])} → k3 = {k[2]}")
    начало_блока = начало + (блок + плоскость * n2) * n1
    подробно += [
        f"начало первого блока — бит {начало_блока}; блоков {блоков}; исправлено одиночных "
        f"ошибок {сводка['исправлено']} (итераций до {ИТЕРАЦИЙ}); без нарушений после: "
        + ", ".join(f"{имя} — {сводка[f'{имя}_после'] * 100:.1f} %"
                    for имя in ИЗМЕРЕНИЯ[:len(n)]),
        "данные — " + ("первые k бит в каждом измерении" if систем
                       else "информационные позиции каждого измерения")
        + " (в предположении систематического кодера)",
    ]
    с_маской = [имя for имя, п in zip(ИЗМЕРЕНИЯ, поправки, strict=False) if п is not None]
    if с_маской:
        подробно.append(
            "на блок наложена постоянная маска (скремблер со сбросом на блоке после кода): "
            f"проверки {', '.join(с_маской)} выделены по разностям соседних блоков, синдромы — "
            "с поправкой по месту слова; данные остаются под маской — её снимает ПСП блока")
    находка = Находка(
        уровень="код",
        что=f"ТКБ (турбокод блочный{', трёхмерный' if n3 else ''}) {коды}, скорость "
            f"{скорость_ч}/{скорость_з}",
        # Блок без нарушений после декодирования — все проверки всех измерений
        # выполнены сразу: у случайных бит так не бывает.
        уверенность=float(сводка["блоков_чисто"]),
        мера=", ".join(f"{имя} без нарушений {сводка[f'{имя}_до'] * 100:.1f} %"
                       for имя in ИЗМЕРЕНИЯ[:len(n)])
        + f"; после итеративного декодирования блоков без нарушений "
          f"{сводка['блоков_чисто'] * 100:.1f} %",
        подробно=подробно, дальше=данные, вид_дальше="биты",
        сверка=float(сводка["строк_до"]),
        свойства={"строка": n1, "начало": int(начало), "столбец": n2, "блок": int(блок),
                  "глубина": n3, "плоскость": int(плоскость), "k1": k[0], "k2": k[1],
                  "k3": k[2] if n3 else 0, "начало_блока": int(начало_блока),
                  "данных_в_блоке": скорость_ч,
                  # Доля ошибок в линии до декодирования — по исправленным (оценка снизу:
                  # в блоках с нарушениями остались и неисправленные).
                  "ошибок_в_линии": float(сводка["исправлено"]) / max(1, блоков * скорость_з)})
    return данные, находка


#: Сколько лучших кандидатов строк в кадрах пробовать снятием.
СТРОК_ПРОБОВАТЬ = 3


def снять_в_кадрах(биты: np.ndarray, начала: Sequence[int], длина: int, *,
                   строка: int | None = None, начало: int | None = None,
                   строк: int | None = None, до: int = ДЛИНА_ДО,
                   **параметры) -> tuple[np.ndarray, Находка]:
    """TPC в кадрах модема: строки ищутся от начала каждого кадра.

    ``начала`` — начала кадров в ``биты`` (по синхрослову), ``длина`` — длина
    кадра. Найдя длину строки n1, начало первой строки o и число строк R в
    кадре, из каждого кадра берутся биты [o, o + R·n1) и складываются подряд —
    дальше как у сплошного потока (столбцы, глубина, декодирование).
    Синхрослово вырезать с точностью до бита не нужно.

    Чётность «строк» бывает и не у кода: в полосе заполнения флагами HDLC
    чётно любое окно из 8 бит (в флаге шесть единиц), и под постоянной ПСП
    блока эта полоса выделяется почти как строки кода. Поэтому лучшие
    кандидаты строк пробуются снятием, и берётся тот, что объясняет больше
    проверок.
    """
    начала = [int(н) for н in начала]
    if строка is None or начало is None or строк is None:
        # Кадры с данными — со всего потока: запись часто начинается с долгой паузы.
        годные = [н for н in начала if 0 <= н and н + длина + до <= len(биты)]
        отбор = _кадры_с_данными(биты, годные, длина, max(64, ВЫБОРКА // длина))
        кандидаты = [к for к in строки_в_кадрах(биты, отбор, длина, до=до)
                     if к["z"] >= ПОРОГ_Z and (строка is None or к["длина"] == строка)]
        if not кандидаты:
            raise ValueError("строк ТКБ в кадрах нет")
        попытки = [(строка or int(к["длина"]), int(к["начало"]) if начало is None else int(начало),
                    int(к["строк"]) if строк is None else int(строк)) for к in кандидаты[:СТРОК_ПРОБОВАТЬ]]
    else:
        попытки = [(int(строка), int(начало), int(строк))]
    итоги: list[tuple[np.ndarray, Находка]] = []
    ошибка: ValueError | None = None
    for строка_, начало_, строк_ in попытки:
        try:
            итоги.append(_снять_строки_в_кадрах(биты, начала, длина, строка_, начало_, строк_, до,
                                                параметры))
        except ValueError as е:
            ошибка = е
            continue
        if итоги[-1][1].уверенность >= 0.99:
            break
    if not итоги:
        raise ошибка or ValueError("ТКБ в кадрах не снимается")
    return max(итоги, key=_качество)


def _качество(итог: tuple[np.ndarray, Находка]) -> tuple[bool, int, float]:
    """Какое толкование кода лучше: доказано, больше проверок, чище блоки."""
    находка = итог[1]
    return находка.уверенность >= БЛОКОВ_ЧИСТО_ОТ, проверок(находка), находка.уверенность


def _снять_строки_в_кадрах(биты: np.ndarray, начала: list[int], длина: int, строка: int, начало: int,
                           строк: int, до: int, параметры: dict[str, object]
                           ) -> tuple[np.ndarray, Находка]:
    """Снять код, когда строки в кадре известны: столбцы, глубина, декодирование."""
    окна = _окна_кадров(биты, [н + начало for н in начала], строк * строка, 0)
    if len(окна) < 2:
        raise ValueError("слишком мало кадров для ТКБ")
    # Столбцы и глубина — сперва по кадрам с данными (повторы заполнения
    # обманывают чётность), декодирование — всех кадров по найденному. Если
    # блок кода длиннее кадра, выброшенный повтор сдвинул бы блоки — поэтому
    # параметры ищутся и по всем кадрам, и берётся толкование с большим числом
    # проверок (сдвинутые блоки тоже «декодируются» — по случайной общей связи).
    # Блок кода — обычно целый кадр или несколько: столбец кратен числу строк
    # в кадре (или делит его) — эти длины пробуются первыми.
    if параметры.get("столбец") is None and "столбцы" not in параметры:
        параметры = {**параметры, "столбцы": sorted({строк * m for m in range(1, 5)}
                                                    | {д for д in range(2, строк + 1) if строк % д == 0})}
    варианты: list[dict[str, object]] = []
    различные = без_повторов(окна)
    if 2 <= int(различные.sum()) < len(окна):
        try:
            _, пробная = снять(окна[различные].reshape(-1), строка=строка, начало=0, до=до, **параметры)
        except ValueError:
            пробная = None
        if пробная is not None:
            с = пробная.свойства
            варианты.append({**параметры, "столбец": с["столбец"], "блок": с["блок"],
                             "глубина": с["глубина"] or None, "плоскость": с["плоскость"],
                             "трёхмерный": bool(с["глубина"])})
    варианты.append(параметры)
    итоги: list[tuple[np.ndarray, Находка]] = []
    ошибка: ValueError | None = None
    for вариант in варианты:
        try:
            итоги.append(снять(окна.reshape(-1), строка=строка, начало=0, до=до, **вариант))
        except ValueError as е:
            ошибка = е
    if not итоги:
        raise ошибка or ValueError("ТКБ в кадрах не снимается")
    данные, находка = max(итоги, key=_качество)
    находка.подробно.insert(0, f"в кадрах по {длина} бит: {строк} строк по {строка} бит с {начало}-го бита "
                               f"кадра ({строк * строка} бит), остальные {длина - строк * строка} бит "
                               f"кадра — служебные (синхрослово)")
    находка.свойства.update({"кадр": длина, "начало_в_кадре": int(начало), "строк_в_кадре": int(строк)})
    return данные, находка


def проверок(находка: Находка) -> int:
    """Сколько проверок у найденного кода: Σ (n − k) по измерениям."""
    с = находка.свойства
    return sum(n - k for n, k in ((с.get("строка", 0), с.get("k1", 0)), (с.get("столбец", 0), с.get("k2", 0)),
                                  (с.get("глубина", 0), с.get("k3", 0))) if n)


def найти(биты: np.ndarray, *, до: int = ДЛИНА_ДО) -> Находка | None:
    """Код произведения, если он есть и доказан декодированием; иначе None.

    Чётность окон бывает и у структур, которые не код (заполнение, служебные
    поля); доказательство — блоки, где после декодирования выполнены все
    проверки всех измерений сразу.
    """
    try:
        _, находка = снять(биты, до=до, проверками=АВТОМАТ_ПРОВЕРОК)
    except ValueError:
        return None
    return находка if находка.уверенность >= БЛОКОВ_ЧИСТО_ОТ else None


def найти_в_кадрах(биты: np.ndarray, начала: Sequence[int], длина: int, *,
                   до: int = ДЛИНА_ДО) -> Находка | None:
    """То же в кадрах модема: ``начала`` кадров в ``биты`` и длина кадра."""
    try:
        _, находка = снять_в_кадрах(биты, начала, длина, до=до, проверками=АВТОМАТ_ПРОВЕРОК)
    except ValueError:
        return None
    return находка if находка.уверенность >= БЛОКОВ_ЧИСТО_ОТ else None


def измерения(находка: Находка) -> Sequence[int]:
    """(n1, n2[, n3]) найденного кода — для отчёта и ручного слоя."""
    с = находка.свойства
    return tuple(x for x in (с.get("строка"), с.get("столбец"), с.get("глубина")) if x)
