# -*- coding: utf-8 -*-
"""Код произведения (TPC — «турбокод произведения») вслепую.

Блок TPC — таблица n2 × n1: каждая строка — слово кода строк (обычно
расширенный Хэмминг (64, 57), (32, 26), (16, 11), (256, 247) или код с
проверкой на чётность), каждый столбец — слово кода столбцов; блок
передаётся по строкам (укороченные коды — без части строк и столбцов).
Так устроены TPC модемов Comtech, AHA, IESS-315 и др. Параметры кода
производитель не раскрывает — поэтому всё восстанавливается по потоку:

1. **Строки.** У расширенного Хэмминга и кода чётности вес каждого слова
   чётный. Для каждой длины окна L и начала o считается доля окон с чётным
   весом: у верной (n1, o1) она близка к 1 (минус ошибки линии), у
   прочих — к половине. Мера — отрыв в разбросах (z): у случайного потока
   максимум по всем (L, o) — 4–5, у TPC — десятки.
2. **Проверки строк** — пространство проверок слов длины n1 ранговым методом
   с учётом шума (как у длинных кодов): не только чётность, а все m + 1
   проверок Хэмминга, при любом расположении проверочных бит.
3. **Столбцы.** Та же чётность, но вдоль столбцов таблицы строк: длина
   столбца n2 и строка, с которой начинается блок.
4. **Декодирование** — итеративное жёсткое: строки, затем столбцы,
   исправление одиночной ошибки по синдрому (синдром совпал со столбцом
   матрицы проверок); двойные ошибки строки расширенный Хэмминг
   обнаруживает и оставляет столбцам. Так TPC и работает — «турбо» в
   названии за счёт этих итераций.
5. **Данные** — информационные позиции строк и столбцов (где код
   систематичен), по строкам блока.

Над кодом бывает модуляционная неоднозначность (поворот созвездия ФМ) —
тогда строки не видны, пока плоскость не подобрана; мера ``мера_строк``
для этого и отдана подбору плоскости.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

import numpy as np

from . import dlinnye, gf2
from .nahodka import Находка

#: Наибольшая длина строки (и столбца) при поиске.
ДЛИНА_ДО = 300
#: Наименьшая длина строки: короче — не код произведения.
ДЛИНА_ОТ = 4
#: По скольким битам ищется.
ВЫБОРКА = 1 << 20
#: Отрыв доли чётных окон (в разбросах), с которого строки считаются найденными.
ПОРОГ_Z = 10.0
#: Итераций декодирования (строки + столбцы).
ИТЕРАЦИЙ = 4
#: Кругов «декодировать — выделить проверки по исправленному заново».
ПЕРЕУЧИТЬ = 2


def _чётность_окон(биты: np.ndarray, L: int) -> np.ndarray:
    """Чётность окна [a, a + L) для всех a (1 — нечётный вес)."""
    накоп = np.concatenate([[0], np.bitwise_xor.accumulate(биты.astype(np.uint8))]).astype(np.uint8)
    return накоп[L:] ^ накоп[:-L]


def строки_по_чётности(биты: np.ndarray, *, до: int = ДЛИНА_ДО, от: int = ДЛИНА_ОТ,
                       лучших: int = 5) -> List[Dict[str, float]]:
    """Кандидаты (длина строки, начало) по доле окон с чётным весом, лучшие первыми.

    Отрыв считается от половины в обе стороны: скремблер со сбросом на
    каждой строке делает чётность постоянной, но не обязательно нулевой.
    """
    накоп = np.concatenate([[0], np.bitwise_xor.accumulate(биты.astype(np.uint8))]).astype(np.uint8)
    итог = []
    for L in range(от, min(до, len(биты) // 16) + 1):
        окна = накоп[L:] ^ накоп[:-L]
        слов = len(окна) // L
        if слов < 16:
            break
        доли = окна[:слов * L].reshape(слов, L).mean(axis=0)       # по началу o
        o = int(np.argmax(np.abs(доли - 0.5)))
        z = abs(1 - 2 * float(доли[o])) * np.sqrt(слов)
        итог.append({"z": float(z), "длина": L, "начало": o, "чётных": 1 - float(доли[o])})
    итог.sort(key=lambda к: -к["z"])
    # Кратные длины (две строки подряд тоже чётны) уступают своей основе.
    отобрано: List[Dict[str, float]] = []
    for к in итог:
        if any(к["длина"] % о["длина"] == 0 and (к["начало"] - о["начало"]) % о["длина"] == 0
               for о in отобрано):
            continue
        отобрано.append(к)
        if len(отобрано) >= лучших:
            break
    return отобрано


def мера_строк(биты: np.ndarray, *, до: int = ДЛИНА_ДО) -> float:
    """Отрыв (в разбросах) лучшей длины строки по чётности — мера для подбора плоскости."""
    кандидаты = строки_по_чётности(биты, до=до, лучших=1)
    return кандидаты[0]["z"] if кандидаты else 0.0


def столбцы_по_чётности(таблица: np.ndarray, *, до: int = ДЛИНА_ДО, от: int = 2,
                        лучших: int = 3) -> List[Dict[str, float]]:
    """Длина столбца и строка начала блока — по чётности вдоль столбцов таблицы строк."""
    накоп = np.concatenate([np.zeros((1, таблица.shape[1]), np.uint8),
                            np.bitwise_xor.accumulate(таблица.astype(np.uint8), axis=0)])
    итог = []
    for L in range(от, min(до, len(таблица) // 8) + 1):
        окна = (накоп[L:] ^ накоп[:-L]).mean(axis=1)               # доля нечётных столбцов
        слов = len(окна) // L
        if слов < 8:
            break
        доли = окна[:слов * L].reshape(слов, L).mean(axis=0)
        o = int(np.argmax(np.abs(доли - 0.5)))
        z = abs(1 - 2 * float(доли[o])) * np.sqrt(слов * таблица.shape[1])
        итог.append({"z": float(z), "длина": L, "начало": o, "чётных": 1 - float(доли[o])})
    итог.sort(key=lambda к: -к["z"])
    отобрано: List[Dict[str, float]] = []
    for к in итог:
        if any(к["длина"] % о["длина"] == 0 for о in отобрано):
            continue
        отобрано.append(к)
        if len(отобрано) >= лучших:
            break
    return отобрано


#: Проходов уточнения пространства проверок.
УТОЧНЕНИЙ = 4


def _с_единицей(слова: np.ndarray) -> np.ndarray:
    return np.hstack([слова, np.ones((len(слова), 1), dtype=слова.dtype)])


def синдромы(слова: np.ndarray, H: np.ndarray) -> np.ndarray:
    """Синдромы слов по аффинным проверкам: строка H — (h, c), проверка h·x = c."""
    return ((слова.astype(np.int32) @ H[:, :-1].T.astype(np.int32)) + H[:, -1]) & 1


def проверки(слова: np.ndarray) -> np.ndarray:
    """Пространство проверок кода по словам с ошибками: строки (h, c) — проверка h·x = c.

    Проверки аффинные: скремблер со сбросом на каждой строке (или столбце)
    делает вес строки нечётным, и проверка «сумма бит = 0» становится
    «= 1». Поэтому к слову добавляется постоянная единица — аффинная
    проверка над ним становится обычной линейной.

    Слово с ошибкой среди опорных «съедает» часть проверок: у (64, 57) при
    ошибках 10⁻³ с первого прохода выделяются 4 проверки из 7. Поэтому
    первые опорные — слова с чётностью большинства (одиночная ошибка её
    ломает), затем уточнение: опорные — слова, уже удовлетворяющие найденным
    проверкам; новые проверки сверяются со всеми словами, пока пространство
    растёт.
    """
    n = слова.shape[1]
    полные = _с_единицей(слова)
    чётность = слова.sum(axis=1) & 1
    своя = int(чётность.mean() > 0.5)
    опорные = полные[чётность == своя]
    if abs(чётность.mean() - 0.5) < 0.2 or len(опорные) < n + 16 + 64:
        опорные = полные
    H = _годные(dlinnye.пространство(опорные, n + 1), полные)
    for _ in range(УТОЧНЕНИЙ):
        if not len(H):
            break
        чистые = полные[~синдромы(слова, H).any(axis=1)]
        if len(чистые) < n + 16 + 64:
            break
        новые = _годные(dlinnye.пространство(чистые, n + 1), полные)
        if not len(новые):
            break
        приведённая, _ = gf2.привести(gf2.упаковать(np.vstack([H, новые])), n + 1)
        вместе = gf2.распаковать(приведённая, n + 1)
        if len(вместе) <= len(H):
            break
        H = вместе
    # Проверка без бит слова (только «1 = 0») — след шума, не проверка.
    return H[H[:, :-1].any(axis=1)] if len(H) else H


def _годные(H: np.ndarray, полные: np.ndarray) -> np.ndarray:
    if not len(H):
        return H
    return H[dlinnye.нарушения(полные, H) < dlinnye.НАРУШЕНИЙ_ДО]


def _таблица_синдромов(H: np.ndarray) -> Dict[bytes, int]:
    """Синдром одиночной ошибки → позиция (только однозначные); H — без столбца единицы."""
    таблица: Dict[bytes, int] = {}
    повторы = set()
    for j in range(H.shape[1]):
        ключ = np.packbits(H[:, j]).tobytes()
        if not H[:, j].any():
            continue
        if ключ in таблица:
            повторы.add(ключ)
        таблица[ключ] = j
    for ключ in повторы:
        del таблица[ключ]
    return таблица


def исправить(слова: np.ndarray, H: np.ndarray) -> Tuple[np.ndarray, int]:
    """Одиночные ошибки по синдрому: (исправленные слова, сколько исправлено)."""
    if not len(H):
        return слова, 0
    синдр = синдромы(слова, H)
    таблица = _таблица_синдромов(H[:, :-1])
    слова = слова.copy()
    исправлено = 0
    for i in np.flatnonzero(синдр.any(axis=1)):
        j = таблица.get(np.packbits(синдр[i].astype(np.uint8)).tobytes())
        if j is not None:
            слова[i, j] ^= 1
            исправлено += 1
    return слова, исправлено


def _без_нарушений(слова: np.ndarray, H: np.ndarray) -> float:
    if not len(H) or not len(слова):
        return 1.0
    return float(np.mean(~синдромы(слова, H).any(axis=1)))


def декодировать(блоки: np.ndarray, H1: np.ndarray, H2: np.ndarray, итераций: int = ИТЕРАЦИЙ
                 ) -> Tuple[np.ndarray, Dict[str, object]]:
    """Итеративное жёсткое декодирование блоков (блоков × n2 × n1)."""
    nb, n2, n1 = блоки.shape
    блоки = блоки.copy()
    до = (_без_нарушений(блоки.reshape(-1, n1), H1),
          _без_нарушений(блоки.transpose(0, 2, 1).reshape(-1, n2), H2))
    всего = 0
    for _ in range(итераций):
        строки, и1 = исправить(блоки.reshape(-1, n1), H1)
        блоки = строки.reshape(nb, n2, n1)
        столбцы, и2 = исправить(блоки.transpose(0, 2, 1).reshape(-1, n2), H2)
        блоки = столбцы.reshape(nb, n1, n2).transpose(0, 2, 1)
        всего += и1 + и2
        if not и1 + и2:
            break
    строки_ок = _без_нарушений(блоки.reshape(-1, n1), H1)
    столбцы_ок = _без_нарушений(блоки.transpose(0, 2, 1).reshape(-1, n2), H2)
    синдр1 = синдромы(блоки.reshape(nb * n2, n1), H1).reshape(nb, -1).any(axis=1) \
        if len(H1) else np.zeros(nb, bool)
    синдр2 = синдромы(блоки.transpose(0, 2, 1).reshape(nb * n1, n2), H2).reshape(nb, -1).any(axis=1) \
        if len(H2) else np.zeros(nb, bool)
    return блоки, {"строк_до": до[0], "столбцов_до": до[1], "строк_после": строки_ок,
                   "столбцов_после": столбцы_ок, "исправлено": всего,
                   "блоков_чисто": float(np.mean(~(синдр1 | синдр2)))}


def снять(биты: np.ndarray, *, строка: Optional[int] = None, начало: Optional[int] = None,
          столбец: Optional[int] = None, блок: Optional[int] = None,
          до: int = ДЛИНА_ДО) -> Tuple[np.ndarray, Находка]:
    """Снять TPC: параметры, которых не задано, находятся по потоку.

    ``строка``, ``начало`` — длина строки n1 и бит начала строки;
    ``столбец``, ``блок`` — длина столбца n2 и номер строки, с которой
    начинается блок. Возвращает (данные, находка).
    """
    выборка = биты[:ВЫБОРКА]
    if строка is None:
        кандидаты = строки_по_чётности(выборка, до=до)
        if not кандидаты or кандидаты[0]["z"] < ПОРОГ_Z:
            raise ValueError("строки кода произведения не найдены: нет длины окна с чётным весом")
        лучший = кандидаты[0]
        строка, начало = int(лучший["длина"]), int(лучший["начало"])
        z_строк, чётных = лучший["z"], лучший["чётных"]
    else:
        начало = int(начало or 0) % строка
        окна = _чётность_окон(выборка[начало:], строка)[::строка]
        чётных = 1 - float(окна.mean()) if len(окна) else 0.0
        z_строк = abs(2 * чётных - 1) * np.sqrt(max(1, len(окна)))
    n1 = int(строка)
    таблица = dlinnye.слова(биты, n1, начало)
    if len(таблица) < 64:
        raise ValueError("слишком короткий поток для кода произведения")
    H1 = проверки(таблица[:(ВЫБОРКА // n1)])
    if столбец is None:
        кандидаты2 = столбцы_по_чётности(таблица[:(ВЫБОРКА // n1)], до=до)
        if not кандидаты2 or кандидаты2[0]["z"] < ПОРОГ_Z:
            raise ValueError(f"строки по {n1} бит нашлись, а столбцов с чётным весом нет — "
                             f"это не код произведения (ищите блочный код строк)")
        столбец, блок = int(кандидаты2[0]["длина"]), int(кандидаты2[0]["начало"])
        z_столбцов = кандидаты2[0]["z"]
    else:
        блок = int(блок or 0) % столбец
        z_столбцов = 0.0
    n2 = int(столбец)
    блоков = (len(таблица) - блок) // n2
    if блоков < 2:
        raise ValueError("меньше двух блоков кода произведения")
    блоки = таблица[блок:блок + блоков * n2].reshape(блоков, n2, n1)
    обучение = блоки[:max(2, (ВЫБОРКА // (n1 * n2)))]
    H2 = проверки(обучение.transpose(0, 2, 1).reshape(-1, n2))
    if not len(H1) or not len(H2):
        raise ValueError("проверки строк или столбцов не выделились")
    чистые, сводка = декодировать(блоки, H1, H2)
    # Второй круг: по исправленным блокам проверки выделяются полнее (в опорных
    # словах меньше ошибок) — и декодирование по полным проверкам точнее.
    for _ in range(ПЕРЕУЧИТЬ):
        учёба = чистые[:len(обучение)]
        новые1 = проверки(учёба.reshape(-1, n1))
        новые2 = проверки(учёба.transpose(0, 2, 1).reshape(-1, n2))
        if len(новые1) <= len(H1) and len(новые2) <= len(H2):
            break
        H1 = новые1 if len(новые1) > len(H1) else H1
        H2 = новые2 if len(новые2) > len(H2) else H2
        чистые, итог = декодировать(блоки, H1, H2)
        сводка = {**итог, "строк_до": сводка["строк_до"], "столбцов_до": сводка["столбцов_до"]}
    инфо1 = dlinnye.информационные(H1[:, :-1])
    инфо2 = dlinnye.информационные(H2[:, :-1])
    данные = чистые[:, инфо2][:, :, инфо1].reshape(-1)
    k1, k2 = len(инфо1), len(инфо2)
    систем = (np.array_equal(инфо1, np.arange(k1)) and np.array_equal(инфо2, np.arange(k2)))
    находка = Находка(
        уровень="код",
        что=f"код произведения (TPC) ({n1}, {k1}) × ({n2}, {k2}), скорость {k1 * k2}/{n1 * n2}",
        # Блок без нарушений после декодирования — все проверки строк и столбцов
        # выполнены сразу: у случайных бит так не бывает.
        уверенность=сводка["блоков_чисто"],
        мера=f"строк без нарушений {сводка['строк_до'] * 100:.1f} %, столбцов "
             f"{сводка['столбцов_до'] * 100:.1f} %; после итеративного декодирования блоков без "
             f"нарушений {сводка['блоков_чисто'] * 100:.1f} %",
        подробно=[
            f"строка {n1} бит с бита {начало} (чётных строк {чётных * 100:.1f} %, отрыв "
            f"{z_строк:.0f} разбросов); проверок строки {len(H1)} → k1 = {k1}",
            f"столбец {n2} строк, блок с {блок}-й строки ({n1 * n2} бит, начало блока — бит "
            f"{начало + блок * n1})" + (f", отрыв {z_столбцов:.0f} разбросов" if z_столбцов else "")
            + f"; проверок столбца {len(H2)} → k2 = {k2}",
            f"блоков {блоков}; исправлено одиночных ошибок {сводка['исправлено']} за "
            f"{ИТЕРАЦИЙ} итерации строки/столбцы; строк без нарушений после — "
            f"{сводка['строк_после'] * 100:.1f} %, столбцов — {сводка['столбцов_после'] * 100:.1f} %",
            "данные — " + ("первые k бит первых k строк блока" if систем
                           else "информационные позиции строк и столбцов")
            + " (в предположении систематического кодера)",
        ],
        дальше=данные, вид_дальше="биты",
        сверка=сводка["строк_до"],
        свойства={"строка": n1, "начало": int(начало), "столбец": n2, "блок": int(блок),
                  "k1": k1, "k2": k2})
    return данные, находка


#: Доля блоков без нарушений после декодирования, с которой код произведения доказан.
БЛОКОВ_ЧИСТО_ОТ = 0.5


def найти(биты: np.ndarray, *, до: int = ДЛИНА_ДО) -> Optional[Находка]:
    """Код произведения, если он есть и доказан декодированием; иначе None.

    Чётность окон бывает и у структур, которые не код (заполнение, служебные
    поля); доказательство — блоки, где после декодирования выполнены все
    проверки строк и столбцов сразу.
    """
    try:
        _, находка = снять(биты, до=до)
    except ValueError:
        return None
