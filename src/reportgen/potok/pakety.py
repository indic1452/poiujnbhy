"""Пакетный уровень: IPv4/IPv6, UDP/TCP/ICMP, Ethernet II, PPP.

Заголовок IPv4 опознаётся не по «похоже на 0x45», а по контрольной сумме:
случайные двадцать байт дают верную сумму раз на 65 536 — а у настоящего
пакета она верна всегда. Для IPv6 контрольной суммы в заголовке нет, и его
признаём по согласию длины из заголовка с длиной кадра.

Ищем в кадрах (после HDLC, из .Sig) — со смещения 0 (голый IP), после PPP
(FF 03 00 21 / 00 57), после Ethernet II (тип 0x0800 / 0x86DD), — а в
сплошном потоке — цепочкой: нашли заголовок, прыгнули на его «полную
длину», проверили следующий.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Iterable, Sequence
from dataclasses import dataclass

import numpy as np

from .nahodka import Находка

ПРОТОКОЛЫ = {1: "ICMP", 2: "IGMP", 6: "TCP", 17: "UDP", 41: "IPv6-в-IPv4", 47: "GRE",
             50: "ESP", 51: "AH", 58: "ICMPv6", 89: "OSPF", 132: "SCTP"}
ПОРТЫ = {20: "FTP-данные", 21: "FTP", 22: "SSH", 23: "Telnet", 25: "SMTP", 53: "DNS",
         67: "DHCP", 68: "DHCP", 69: "TFTP", 80: "HTTP", 110: "POP3", 123: "NTP",
         161: "SNMP", 162: "SNMP-trap", 443: "HTTPS", 514: "Syslog", 1701: "L2TP",
         1812: "RADIUS", 5060: "SIP", 5061: "SIP-TLS"}


@dataclass
class Пакет:
    версия: int
    источник: str
    получатель: str
    протокол: int
    длина: int
    порт_от: int = 0
    порт_к: int = 0
    обёртка: str = ""             # «IP», «PPP», «Ethernet»
    #: Сам пакет (заголовок IP и дальше) — для выгрузки в pcap.
    сырые: bytes = b""


def _сумма_верна(заголовок: bytes) -> bool:
    if len(заголовок) < 20 or len(заголовок) % 2:
        return False
    слова = np.frombuffer(заголовок, dtype=">u2").astype(np.uint32)
    сумма = int(слова.sum())
    while сумма >> 16:
        сумма = (сумма & 0xFFFF) + (сумма >> 16)
    return сумма == 0xFFFF


def ipv4(данные: bytes, место: int = 0) -> Пакет | None:
    """Заголовок IPv4 с этого места — только если контрольная сумма верна."""
    if len(данные) - место < 20:
        return None
    первый = данные[место]
    if первый >> 4 != 4 or (первый & 0x0F) < 5:
        return None
    длина_заголовка = (первый & 0x0F) * 4
    заголовок = данные[место:место + длина_заголовка]
    if len(заголовок) < длина_заголовка or not _сумма_верна(заголовок):
        return None
    полная = int.from_bytes(данные[место + 2:место + 4], "big")
    if полная < длина_заголовка:
        return None
    протокол = данные[место + 9]
    пакет = Пакет(4, ".".join(map(str, данные[место + 12:место + 16])),
                  ".".join(map(str, данные[место + 16:место + 20])), протокол, полная)
    if протокол in (6, 17) and len(данные) >= место + длина_заголовка + 4:
        порты = данные[место + длина_заголовка:место + длина_заголовка + 4]
        пакет.порт_от = int.from_bytes(порты[:2], "big")
        пакет.порт_к = int.from_bytes(порты[2:], "big")
    пакет.сырые = bytes(данные[место:место + полная])
    return пакет


def ipv6(данные: bytes, место: int = 0, *, ждать_длину: int | None = None) -> Пакет | None:
    """Заголовок IPv6 — по согласию длины с кадром (суммы в заголовке нет)."""
    if len(данные) - место < 40 or данные[место] >> 4 != 6:
        return None
    нагрузка = int.from_bytes(данные[место + 4:место + 6], "big")
    следующий = данные[место + 6]
    if ждать_длину is not None and нагрузка + 40 != ждать_длину:
        return None
    if следующий not in ПРОТОКОЛЫ and следующий not in (0, 43, 44, 60):
        return None
    def адрес(кусок: bytes) -> str:
        return ":".join(f"{int.from_bytes(кусок[i:i + 2], 'big'):x}" for i in range(0, 16, 2))
    пакет = Пакет(6, адрес(данные[место + 8:место + 24]), адрес(данные[место + 24:место + 40]),
                  следующий, нагрузка + 40)
    if следующий in (6, 17) and len(данные) >= место + 44:
        пакет.порт_от = int.from_bytes(данные[место + 40:место + 42], "big")
        пакет.порт_к = int.from_bytes(данные[место + 42:место + 44], "big")
    пакет.сырые = bytes(данные[место:место + нагрузка + 40])
    return пакет


#: RFC 2684 / RFC 1483 (IP над ATM, Frame Relay): LLC AA-AA-03, OUI 00-00-00 и EtherType;
#: мостовой Ethernet — OUI 00-80-C2, PID 00-07 (без FCS), два байта набивки, кадр Ethernet.
LLC_SNAP_IP = (b"\xaa\xaa\x03\x00\x00\x00\x08\x00", b"\xaa\xaa\x03\x00\x00\x00\x86\xdd")
LLC_SNAP_МОСТ = (b"\xaa\xaa\x03\x00\x80\xc2\x00\x07", b"\xaa\xaa\x03\x00\x80\xc2\x00\x01")


def в_кадре(кадр: bytes) -> Пакет | None:
    """IP в кадре: голый, в PPP, в Ethernet II, за LLC/SNAP (RFC 2684) и в мостовом Ethernet."""
    for место, обёртка in ((0, "IP"), (4, "PPP"), (2, "PPP"), (14, "Ethernet"),
                           (8, "LLC/SNAP"), (24, "LLC/SNAP, мост")):
        if обёртка == "PPP" and место == 4 and кадр[:2] != b"\xff\x03":
            continue
        if обёртка == "Ethernet" and кадр[12:14] not in (b"\x08\x00", b"\x86\xdd"):
            continue
        if обёртка == "LLC/SNAP" and кадр[:8] not in LLC_SNAP_IP:
            continue
        if обёртка == "LLC/SNAP, мост" and (кадр[:8] not in LLC_SNAP_МОСТ
                                            or кадр[22:24] not in (b"\x08\x00", b"\x86\xdd")):
            continue
        пакет = ipv4(кадр, место) or ipv6(кадр, место, ждать_длину=len(кадр) - место)
        if пакет is not None:
            пакет.обёртка = обёртка
            return пакет
    return None


def цепочка(данные: bytes, *, предел: int = 1 << 22) -> list[Пакет]:
    """Пакеты IPv4 подряд в сплошном потоке: заголовок → прыжок на длину → заголовок."""
    данные = данные[:предел]
    массив = np.frombuffer(данные, dtype=np.uint8)
    кандидаты = np.flatnonzero((массив >> 4 == 4) & ((массив & 0x0F) >= 5))
    лучшая: list[Пакет] = []
    проверено = 0
    for начало in кандидаты[:20000]:
        пакет = ipv4(данные, int(начало))
        if пакет is None:
            continue
        проверено += 1
        цепь = [пакет]
        место = int(начало) + пакет.длина
        while место_годно(данные, место):
            следующий = ipv4(данные, место)
            if следующий is None:
                break
            цепь.append(следующий)
            место += следующий.длина
        if len(цепь) > len(лучшая):
            лучшая = цепь
        if len(лучшая) >= 50 or проверено > 200:
            break
    return лучшая


def место_годно(данные: bytes, место: int) -> bool:
    return 0 <= место <= len(данные) - 20


def найти_в_кадрах(кадры: Sequence[bytes], откуда: str = "кадров") -> Находка | None:
    """IP в кадрах: доля кадров с опознанным пакетом и сводка."""
    if not кадры:
        return None
    пакеты = [пакет for пакет in (в_кадре(кадр) for кадр in кадры) if пакет is not None]
    if not пакеты:
        return None
    доля = len(пакеты) / len(кадры)
    if доля < 0.05:
        return None
    return _находка(пакеты, доля, f"IP опознан в {len(пакеты)} из {len(кадры)} {откуда} "
                                 f"({round(доля * 100)} %) — по контрольной сумме заголовка")


def найти_в_потоке(данные: bytes) -> Находка | None:
    цепь = цепочка(данные)
    if len(цепь) < 3:
        return None
    return _находка(цепь, min(1.0, len(цепь) / 10),
                    f"{len(цепь)} пакетов IPv4 подряд, каждый с верной контрольной "
                    f"суммой заголовка и длиной, приводящей точно к следующему")


def _esp(пакеты: list[Пакет]) -> list[str]:
    """ESP (IPsec, RFC 4303, разд. 2): SPI и номер последовательности — открыты, остальное зашифровано.

    По номерам видно, сколько пакетов сеанса нет в записи (пропуски между
    наименьшим и наибольшим номером).
    """
    номера: dict[int, list[int]] = {}
    for п in пакеты:
        if п.протокол != 50 or not п.сырые:
            continue
        заголовок = (п.сырые[0] & 0x0F) * 4 if п.версия == 4 else 40
        if len(п.сырые) < заголовок + 8:
            continue
        spi = int.from_bytes(п.сырые[заголовок:заголовок + 4], "big")
        номера.setdefault(spi, []).append(int.from_bytes(п.сырые[заголовок + 4:заголовок + 8], "big"))
    if not номера:
        return []
    сеансы = []
    for spi, н in sorted(номера.items(), key=lambda с: -len(с[1]))[:6]:
        разных = len(set(н))
        пропущено = max(н) - min(н) + 1 - разных
        сеансы.append(f"SPI 0x{spi:08x} — {len(н)} пакетов, номера {min(н)}…{max(н)}"
                      + (f", пропущено {пропущено}" if пропущено else ", без пропусков"))
    return ["ESP (IPsec, RFC 4303): нагрузка зашифрована — без ключей не читается; открыты SPI и "
            "номер последовательности: " + "; ".join(сеансы)]


def _находка(пакеты: Iterable[Пакет], уверенность: float, мера: str) -> Находка:
    пакеты = list(пакеты)
    протоколы = Counter(ПРОТОКОЛЫ.get(п.протокол, f"протокол {п.протокол}") for п in пакеты)
    обёртки = Counter(п.обёртка or "IP" for п in пакеты)
    пары = Counter(f"{п.источник} → {п.получатель}" for п in пакеты)
    порты = Counter(п.порт_к for п in пакеты if п.порт_к)
    версии = Counter(f"IPv{п.версия}" for п in пакеты)
    подробно = [
        "версии: " + ", ".join(f"{в}×{с}" for в, с in версии.most_common()),
        "обёртка: " + ", ".join(f"{в}×{с}" for в, с in обёртки.most_common()),
        "протоколы: " + ", ".join(f"{в}×{с}" for в, с in протоколы.most_common(6)),
        "частые направления: " + "; ".join(f"{в} ({с})" for в, с in пары.most_common(5)),
    ]
    if порты:
        подробно.append("частые порты получателя: " + ", ".join(
            f"{порт}{' (' + ПОРТЫ[порт] + ')' if порт in ПОРТЫ else ''}×{с}"
            for порт, с in порты.most_common(6)))
    подробно += _esp(пакеты)
    return Находка(уровень="сетевой", что="пакеты IP", уверенность=уверенность,
                   мера=мера, подробно=подробно, дальше=пакеты, вид_дальше="пакеты")
