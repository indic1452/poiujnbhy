"""Симметрии созвездия ФМ-4 (QPSK) над парами бит: обмен бит символа (I ↔ Q) и инверсия каждого бита.

Демодулятор без снятой фазовой неоднозначности отдаёт символы повёрнутыми на 90°, 180° или 270°, а при
инвертированном спектре — ещё и отражёнными. Для пары бит символа (a, b) это восемь преобразований:
обмен (a, b) → (b, a) или нет и инверсия каждого из двух бит после обмена. При разметке Грея поворот на
180° — инверсия обоих бит, на ±90° — обмен с инверсией одного, отражения — инверсия одного бита, обмен,
обмен с инверсией обоих. Инверсия всех бит потока — частный случай (поворот на 180°).

Пары выровнены по символам: символ — биты (ф + 2j, ф + 2j + 1) ряда, где ф — фаза (0 или 1). Если в
потоке есть пилот-символ (вставка из двух бит, ``vstavka``), фаза известна — по его месту; иначе
перебираются обе. Без обмена фаза важна лишь для инверсии одного бита, поэтому различных преобразований
при неизвестной фазе — 12, а не 16.

Какое из преобразований верное, по самим битам не видно (синхрослово и пилот постоянны при любом) —
решают проверки кода: у верного преобразования проверки LDPC выполняются (``ldpc_nagruzka``).
"""

from __future__ import annotations

import re
from dataclasses import dataclass

import numpy as np


@dataclass(frozen=True)
class Симметрия:
    обмен: bool = False          # (a, b) → (b, a)
    инв_первого: bool = False    # после обмена: инверсия первого бита символа
    инв_второго: bool = False    # и второго

    @property
    def тождество(self) -> bool:
        return not (self.обмен or self.инв_первого or self.инв_второго)

    @property
    def зависит_от_фазы(self) -> bool:
        """Без обмена и с одинаковой инверсией обоих бит — от выравнивания пар не зависит."""
        return self.обмен or self.инв_первого != self.инв_второго

    def имя(self) -> str:
        if self.тождество:
            return "как есть"
        if not self.обмен and self.инв_первого and self.инв_второго:
            return "инверсия всех бит (поворот ФМ-4 на 180°)"
        части = []
        if self.обмен:
            части.append("обмен бит символа (I ↔ Q)")
        if self.инв_первого and self.инв_второго:
            части.append("инверсия обоих бит")
        elif self.инв_первого:
            части.append("инверсия первого бита символа")
        elif self.инв_второго:
            части.append("инверсия второго бита символа")
        смысл = ("поворот ФМ-4 на 90° или 270° (при разметке Грея)" if self.обмен and self.инв_первого != self.инв_второго
                 else "отражение созвездия ФМ-4")
        return ", ".join(части) + f" ({смысл})"

    def слой(self, фаза: int = 0) -> str:
        """Ручной слой (стол, «снять»): «пары [обмен] [инв 1] [инв 2] [фаза 1]»."""
        части = ["пары"]
        if self.обмен:
            части.append("обмен")
        if self.инв_первого:
            части.append("инв 1")
        if self.инв_второго:
            части.append("инв 2")
        if фаза % 2 and self.зависит_от_фазы:
            части.append("фаза 1")
        return " ".join(части)

    def взять(self, ряд: np.ndarray, места: np.ndarray, фаза: int = 0) -> np.ndarray:
        """Биты преобразованного ряда на местах ``места`` (любой формы) — без преобразования всего ряда."""
        места = np.asarray(места, dtype=np.int64)
        первый = ((места - фаза) % 2) == 0                    # бит — первый в своём символе
        откуда = места
        if self.обмен:
            откуда = np.clip(np.where(первый, места + 1, места - 1), 0, len(ряд) - 1)
        биты = np.asarray(ряд, dtype=np.uint8)[откуда]
        if self.инв_первого or self.инв_второго:
            маска = np.where(первый, np.uint8(self.инв_первого), np.uint8(self.инв_второго)).astype(np.uint8)
            биты = биты ^ маска
        return биты

    def применить(self, ряд: np.ndarray, фаза: int = 0) -> np.ndarray:
        """Весь ряд после преобразования (у неполной пары на краю обмен берёт тот же бит)."""
        ряд = np.asarray(ряд, dtype=np.uint8)
        if self.тождество:
            return ряд.copy()
        return self.взять(ряд, np.arange(len(ряд)), фаза)


ВСЕ = tuple(Симметрия(о, а, б) for о in (False, True) for а in (False, True) for б in (False, True))
КАК_ЕСТЬ = Симметрия()
ИНВЕРСИЯ = Симметрия(False, True, True)


def варианты(фаза: int | None = None) -> list[tuple[Симметрия, int]]:
    """Различные преобразования (симметрия, фаза): при известной фазе — 8, при неизвестной — 12 (без обмена
    инверсия одного бита при фазе 1 — та же, что инверсия другого при фазе 0). Первое — «как есть», второе —
    инверсия всех бит."""
    итог: list[tuple[Симметрия, int]] = []
    виденные: set[tuple] = set()
    for ф in ((фаза % 2,) if фаза is not None else (0, 1)):
        for с in ВСЕ:
            ключ = (с.обмен, ф if с.обмен else None,
                    (с.инв_первого, с.инв_второго) if ф == 0 or с.обмен else (с.инв_второго, с.инв_первого))
            if ключ in виденные:
                continue
            виденные.add(ключ)
            итог.append((с, ф if с.зависит_от_фазы else 0))
    итог.sort(key=lambda п: (not п[0].тождество, п[0] != ИНВЕРСИЯ))
    return итог


def разобрать_слой(слова: str) -> tuple[Симметрия, int]:
    """«пары [обмен] [инв 1] [инв 2] [фаза 1]» → (симметрия, фаза)."""
    слова = слова.lower()
    инв = {int(ч) for ч in re.findall(r"инв\w*\s+([12])", слова)}
    if re.search(r"инв\w*\s+(обоих|все)", слова):
        инв = {1, 2}
    фаза = re.search(r"фаз\w*\s+(\d+)", слова)
    return Симметрия("обмен" in слова, 1 in инв, 2 in инв), (int(фаза.group(1)) % 2 if фаза else 0)
