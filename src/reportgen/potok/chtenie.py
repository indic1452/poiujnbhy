"""Чтение потока: .bin, .Sig, текст «0101…» или шестнадцатеричный.

.Sig у отдела — это пакеты, каждый с двухбайтовым заголовком — указателем
длины. Что именно в этих двух байтах, заранее не сказано: порядок байт
(старший первым или младший), входит ли в длину сам заголовок, есть ли в
начале файла свой заголовок. Угадывать нельзя, поэтому проверяем: вариант
годится, только если по нему файл проходится от пакета к пакету ровно до
конца. На случайных данных такое совпадение практически невозможно, на
настоящем .Sig — обязательно.

Разметка проверяется и по файлу на диске — окнами, не читая его в память
(``разметка_sig``): так её выбирает и анализ пакетов для файлов любого размера.
Места пакетов (``Места``) держатся двумя массивами чисел, а не списком пар:
у гигабайтного .Sig их миллионы.
"""

from __future__ import annotations

from array import array
from collections.abc import Iterator, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import numpy as np

from .bity import из_текста

#: Сколько байт в начале файла проверять на собственный заголовок файла.
ЗАГОЛОВОК_ФАЙЛА_ДО = 64
#: Пакеты с двухбайтовой длиной: .Sig и .dpo — один и тот же формат.
РАСШИРЕНИЯ_SIG = (".sig", ".dpo")
#: Короткая проба разметки — по первым байтам (полный проход по всем вариантам занял бы минуты).
ПРОБА = 1 << 16
#: Окно чтения файла при проходе по длинам.
ОКНО = 8 << 20


class Места(Sequence):
    """Места пакетов (начало, длина) — двумя массивами: восемь байт на число вместо сотни на пару."""

    def __init__(self, начала: Sequence[int] | np.ndarray = (), длины: Sequence[int] | np.ndarray = ()):
        self.начала = np.asarray(начала, dtype=np.int64)
        self.длины = np.asarray(длины, dtype=np.int64)

    def __len__(self) -> int:
        return len(self.начала)

    def __getitem__(self, i):
        if isinstance(i, slice):
            return [(int(н), int(д)) for н, д in zip(self.начала[i].tolist(), self.длины[i].tolist(), strict=True)]
        return int(self.начала[i]), int(self.длины[i])

    def __iter__(self) -> Iterator[tuple[int, int]]:
        return zip(self.начала.tolist(), self.длины.tolist(), strict=True)

    def __eq__(self, другое: object) -> bool:
        if isinstance(другое, (Места, list, tuple)):
            return len(self) == len(другое) and all(а == б for а, б in zip(self, другое, strict=True))
        return NotImplemented

    __hash__ = None  # type: ignore[assignment]


@dataclass
class Поток:
    """Что прочитали и как."""

    имя: str
    вид: str                       # «bin», «sig», «текст»
    данные: bytes                  # сплошной поток (у .Sig — тела пакетов подряд)
    пакеты: Sequence[tuple[int, int]] = field(default_factory=list)  # (начало, длина) в данных
    формат: str = ""               # как понят файл — словами
    заметки: list[str] = field(default_factory=list)
    #: Сколько байт во всём потоке, если ``данные`` — лишь его начало (файл больше памяти).
    всего_байт: int = 0
    #: Точная длина потока в битах, если хвост последнего байта — не данные (текст «0101…»); 0 — байт × 8.
    бит: int = 0

    @property
    def байт(self) -> int:
        return max(self.всего_байт, len(self.данные))

    @property
    def целиком(self) -> bool:
        """Весь поток в ``данные`` (а не только начало большого файла)."""
        return len(self.данные) >= self.всего_байт

    @property
    def бит_всего(self) -> int:
        """Сколько бит во всём потоке."""
        return self.бит if self.бит and self.целиком else self.байт * 8

    def пакет(self, номер: int) -> bytes:
        начало, длина = self.пакеты[номер]
        return self.данные[начало:начало + длина]


class _Источник:
    """Байты (в памяти) или файл на диске — читаются кусками по месту."""

    def __init__(self, источник: bytes | bytearray | memoryview | str | Path):
        if isinstance(источник, (bytes, bytearray, memoryview)):
            self.байты: bytes | None = bytes(источник) if isinstance(источник, memoryview) else источник
            self.файл = None
            self.размер = len(источник)
        else:
            self.байты = None
            self.файл = open(источник, "rb")  # noqa: SIM115 — закрывает закрыть()
            self.размер = self.файл.seek(0, 2)

    def прочитать(self, место: int, сколько: int) -> bytes:
        if self.байты is not None:
            return self.байты[место:место + сколько]
        self.файл.seek(место)
        return self.файл.read(сколько)

    def закрыть(self) -> None:
        if self.файл is not None:
            self.файл.close()


def _пройти(источник: _Источник, порядок: str, включает: bool, смещение: int, предел: int | None = None, *,
            места: bool = False, гистограмма: list[int] | None = None) -> tuple[int, int, bool, Места | None]:
    """Пройти файл по длинам (заголовки — только до ``предел``, тела могут уходить дальше). Возвращает,
    сколько пакетов, сколько байт пройдено, дошли ли ровно до конца и (``места``) места пакетов в файле.
    ``гистограмма`` — 65 536 счётчиков длин тел (для медианы без списка длин)."""
    размер = источник.размер
    конец = размер if предел is None else min(размер, предел)
    начала, длины = (array("q"), array("q")) if места else (None, None)
    старший = порядок == "big"
    сдвиг = 2 if включает else 0
    место = смещение
    пакетов = 0
    while место + 2 <= конец:
        # Окно: заголовки, что в него влезают, проходятся без чтения с диска.
        окно = источник.прочитать(место, min(ОКНО, конец - место))
        начало_окна = место
        n = len(окно) - 1                      # заголовок — два байта: i + 1 < len
        i = 0
        while i < n:
            длина = (окно[i] << 8 | окно[i + 1]) if старший else (окно[i] | окно[i + 1] << 8)
            тело = длина - сдвиг
            if тело < 0:
                return пакетов, место, место == размер, Места(начала, длины) if места else None
            if место + 2 + тело > размер:
                return пакетов, место, место == размер, Места(начала, длины) if места else None
            if места:
                начала.append(место + 2)
                длины.append(тело)
            if гистограмма is not None:
                гистограмма[тело] += 1
            пакетов += 1
            место += 2 + тело
            i = место - начало_окна
        if len(окно) < 2:
            break                                  # файл укоротился посреди прохода
    return пакетов, место, место == размер, Места(начала, длины) if места else None


def _медиана(гистограмма: list[int], пакетов: int) -> int:
    """Медиана длин по гистограмме — как ``int(np.median(длины))``."""
    нужно = sorted({(пакетов - 1) // 2, пакетов // 2})
    значения = []
    накоплено = 0
    for длина, сколько in enumerate(гистограмма):
        if not сколько:
            continue
        накоплено += сколько
        while нужно and нужно[0] < накоплено:
            значения.append(длина)
            нужно.pop(0)
        if not нужно:
            break
    return int((значения[0] + значения[-1]) / 2)


def разметка_sig(источник: bytes | bytearray | str | Path) -> dict[str, Any] | None:
    """Вариант разметки .Sig, по которому файл (байты или путь — файл читается окнами, не целиком)
    проходится от пакета к пакету ровно до конца: {"смещение", "порядок", "включает", "пакетов",
    "формат", "заметки"} — или None, если ни один вариант не подошёл."""
    и = _Источник(источник)
    try:
        годные = []
        for смещение in range(0, ЗАГОЛОВОК_ФАЙЛА_ДО + 1):
            for порядок in ("big", "little"):
                for включает in (False, True):
                    # Сначала коротко — по первым 64 КБ: полный проход по всем вариантам и смещениям
                    # на ста мегабайтах занял бы минуты.
                    пакетов, _, до_конца, _ = _пройти(и, порядок, включает, смещение, предел=ПРОБА)
                    if пакетов < 3 and not до_конца:
                        continue
                    гистограмма = [0] * 65536
                    пакетов, _, до_конца, _ = _пройти(и, порядок, включает, смещение, гистограмма=гистограмма)
                    if до_конца and пакетов >= 2:
                        годные.append((смещение, порядок, включает, пакетов, гистограмма))
            if годные:
                break                  # меньшее смещение — правдоподобнее
    finally:
        и.закрыть()
    if not годные:
        return None
    # Оба порядка байт проходят файл до конца только при симметричных длинах (например, все по
    # 0x0101). Тогда берём тот, где пакетов больше, и честно говорим, что выбор неоднозначен.
    годные.sort(key=lambda вариант: (-вариант[3], вариант[1] != "big"))
    смещение, порядок, включает, пакетов, гистограмма = годные[0]
    заметки = []
    if len({(в[1], в[2]) for в in годные}) > 1:
        заметки.append("разметка .Sig неоднозначна: файл проходится до конца при "
                       "нескольких толкованиях заголовка; выбрано то, где пакетов больше")
    наименьшая = next(д for д, н in enumerate(гистограмма) if н)
    наибольшая = max(д for д, н in enumerate(гистограмма) if н)
    формат = (f".Sig: {пакетов} пакетов, длина в заголовке — два байта, "
              f"{'старший' if порядок == 'big' else 'младший'} байт первым, "
              f"{'включая' if включает else 'без'} сам заголовок"
              + (f"; в начале файла свой заголовок в {смещение} байт" if смещение else "")
              + f"; длина пакета от {наименьшая} до {наибольшая} байт, "
                f"медиана {_медиана(гистограмма, пакетов)}")
    return {"смещение": смещение, "порядок": порядок, "включает": включает, "пакетов": пакетов,
            "формат": формат, "заметки": заметки}


def разобрать_sig(сырые: bytes) -> tuple[Места, str, list] | None:
    """Найти вариант разметки .Sig, по которому файл проходится до конца.

    Возвращает места пакетов (начало, длина) в файле, описание формата и заметки,
    либо None, если ни один вариант не подошёл.
    """
    разметка = разметка_sig(сырые)
    if разметка is None:
        return None
    и = _Источник(сырые)
    _, _, _, места = _пройти(и, разметка["порядок"], разметка["включает"], разметка["смещение"], места=True)
    return места, разметка["формат"], разметка["заметки"]


def тела_подряд(сырые: bytes, места: Места) -> tuple[bytes, Места]:
    """Тела пакетов подряд, без заголовков (это и есть поток), и их места в нём."""
    длины = места.длины
    всего = int(длины.sum()) if len(длины) else 0
    итог = bytearray(всего)
    вид = memoryview(сырые)
    место = 0
    for начало, длина in места:
        итог[место:место + длина] = вид[начало:начало + длина]
        место += длина
    начала = np.concatenate(([0], np.cumsum(длины)[:-1])) if len(длины) else np.zeros(0, dtype=np.int64)
    return bytes(итог), Места(начала, длины)


def прочитать(путь: str | Path | None = None, *, данные: bytes | None = None,
              имя: str = "") -> Поток:
    """Прочитать поток из файла или из байтов.

    Вид определяется по расширению, а для .Sig — ещё и проверкой разметки:
    файл, который по ней не проходится, читается как сырой поток, и об этом
    говорится.
    """
    if данные is None:
        путь = Path(путь)
        данные = путь.read_bytes()
        имя = имя or путь.name
    имя = имя or "поток"
    расширение = Path(имя).suffix.lower()

    # Текстом прислали биты или шестнадцатеричный дамп.
    if расширение in (".txt", ".hex", ".bits", "") and len(данные) < 64 << 20:
        try:
            текст = данные.decode("ascii")
        except UnicodeDecodeError:
            текст = ""
        биты = из_текста(текст) if текст else None
        if биты is not None:
            # Хвост короче байта — тоже данные: дополнен нулями, точная длина — в «бит».
            return Поток(имя, "текст", np.packbits(np.asarray(биты, dtype=np.uint8)).tobytes(),
                         формат=f"текст: {len(биты)} бит", бит=len(биты))

    if расширение in РАСШИРЕНИЯ_SIG:
        найдено = разобрать_sig(данные)
        if найдено is not None:
            места, формат, заметки = найдено
            # Тела пакетов — подряд, без заголовков: это и есть поток.
            тела, пакеты = тела_подряд(данные, места)
            return Поток(имя, "sig", тела, пакеты, формат, заметки)
        return Поток(имя, "bin", данные,
                     формат=f"сырой поток, {len(данные)} байт",
                     заметки=[f"файл назван {расширение}, но разметкой «двухбайтовая длина + "
                              "пакет» не проходится ни при каком толковании — "
                              "разобран как сырой поток"])

    return Поток(имя, "bin", данные, формат=f"сырой поток, {len(данные)} байт")


# -- большой .Sig с диска: тот же выбор разметки, без чтения файла в память ------------------

#: Начало файла для быстрой пробы вариантов разметки: не меньше 64 КБ пробы + самый длинный пакет
#: (65 537 байт) — иначе проба по началу отсеяла бы не то, что проба по всему файлу в памяти.
ГОЛОВА_SIG = 256 << 10
#: Кусок чтения при проходе файла по длинам.
КУСОК_SIG = 16 << 20


def _пройти_файл(путь: Path, размер: int, порядок: str, включает: bool, смещение: int
                 ) -> tuple[np.ndarray, np.ndarray, bool]:
    """``_пройти`` по файлу на диске: начала и длины тел пакетов, дошли ли ровно до конца."""
    from array import array  # noqa: PLC0415
    начала, длины = array("q"), array("q")
    место = смещение
    буфер, от = b"", 0
    with open(путь, "rb") as файл:
        while место + 2 <= размер:
            if место + 2 > от + len(буфер):
                файл.seek(место)
                буфер, от = файл.read(КУСОК_SIG), место
            длина = int.from_bytes(буфер[место - от:место - от + 2], порядок)
            тело = длина - 2 if включает else длина
            if тело < 0 or место + 2 + тело > размер:
                break
            начала.append(место + 2)
            длины.append(тело)
            место += 2 + тело
    return np.frombuffer(начала, dtype=np.int64), np.frombuffer(длины, dtype=np.int64), место == размер


def разобрать_sig_файл(путь: str | Path) -> tuple[np.ndarray, np.ndarray, str, list] | None:
    """``разобрать_sig`` для файла на диске любого размера: тот же выбор варианта (проба по началу,
    проход по всему файлу), итог — начала и длины тел в файле, описание формата и заметки."""
    путь = Path(путь)
    размер = путь.stat().st_size
    with open(путь, "rb") as файл:
        голова = файл.read(ГОЛОВА_SIG)
    if размер <= len(голова):
        найдено = разобрать_sig(голова)
        if найдено is None:
            return None
        пакеты, формат, заметки = найдено
        return (np.array([н for н, _ in пакеты], dtype=np.int64), np.array([д for _, д in пакеты], dtype=np.int64),
                формат, заметки)
    заметки: list = []
    годные = []
    for смещение in range(0, ЗАГОЛОВОК_ФАЙЛА_ДО + 1):
        for порядок in ("big", "little"):
            for включает in (False, True):
                пакетов, _, до_конца, _ = _пройти(_Источник(голова), порядок, включает, смещение, предел=1 << 16)
                if пакетов < 3 and not до_конца:
                    continue
                начала, длины, до_конца = _пройти_файл(путь, размер, порядок, включает, смещение)
                if до_конца and len(начала) >= 2:
                    годные.append((смещение, порядок, включает, начала, длины))
        if годные:
            break
    if not годные:
        return None
    годные.sort(key=lambda в: (-len(в[3]), в[1] != "big"))
    смещение, порядок, включает, начала, длины = годные[0]
    if len({(в[1], в[2]) for в in годные}) > 1:
        заметки.append("разметка .Sig неоднозначна: файл проходится до конца при "
                       "нескольких толкованиях заголовка; выбрано то, где пакетов больше")
    формат = (f".Sig: {len(начала)} пакетов, длина в заголовке — два байта, "
              f"{'старший' if порядок == 'big' else 'младший'} байт первым, "
              f"{'включая' if включает else 'без'} сам заголовок"
              + (f"; в начале файла свой заголовок в {смещение} байт" if смещение else "")
              + f"; длина пакета от {int(длины.min())} до {int(длины.max())} байт, "
                f"медиана {int(np.median(длины))}")
    return начала, длины, формат, заметки


def тела_в_файл(путь: str | Path, начала: np.ndarray, длины: np.ndarray, куда: str | Path,
                от: int = 0, сколько: int = 0) -> int:
    """Тела пакетов подряд — в файл ``куда`` кусками; ``от``/``сколько`` — часть сплошного потока
    (байты; 0 — до конца). Итог — сколько байт записано."""
    конец_потока = int(длины.sum())
    до = конец_потока if not сколько else min(конец_потока, от + сколько)
    записано = 0
    место = 0                                         # байт сплошного потока до текущего пакета
    with open(путь, "rb") as вход, open(куда, "wb") as выход:
        for начало, длина in zip(начала.tolist(), длины.tolist(), strict=True):
            a, b = max(от, место), min(до, место + длина)
            if a < b:
                вход.seek(начало + a - место)
                выход.write(вход.read(b - a))
                записано += b - a
            место += длина
            if место >= до:
                break
    return записано
