"""Чтение потока: .bin, .Sig, текст «0101…» или шестнадцатеричный.

.Sig у отдела — это пакеты, каждый с двухбайтовым заголовком — указателем
длины. Что именно в этих двух байтах, заранее не сказано: порядок байт
(старший первым или младший), входит ли в длину сам заголовок, есть ли в
начале файла свой заголовок. Угадывать нельзя, поэтому проверяем: вариант
годится, только если по нему файл проходится от пакета к пакету ровно до
конца. На случайных данных такое совпадение практически невозможно, на
настоящем .Sig — обязательно.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import numpy as np

from .bity import в_байты, из_текста

#: Сколько байт в начале файла проверять на собственный заголовок файла.
ЗАГОЛОВОК_ФАЙЛА_ДО = 64
#: Пакеты с двухбайтовой длиной: .Sig и .dpo — один и тот же формат.
РАСШИРЕНИЯ_SIG = (".sig", ".dpo")


@dataclass
class Поток:
    """Что прочитали и как."""

    имя: str
    вид: str                       # «bin», «sig», «текст»
    данные: bytes                  # сплошной поток (у .Sig — тела пакетов подряд)
    пакеты: list[tuple[int, int]] = field(default_factory=list)  # (начало, длина) в данных
    формат: str = ""               # как понят файл — словами
    заметки: list[str] = field(default_factory=list)
    #: Сколько байт во всём потоке, если ``данные`` — лишь его начало (файл больше памяти).
    всего_байт: int = 0

    @property
    def байт(self) -> int:
        return max(self.всего_байт, len(self.данные))

    def пакет(self, номер: int) -> bytes:
        начало, длина = self.пакеты[номер]
        return self.данные[начало:начало + длина]


def _пройти(сырые: bytes, порядок: str, включает: bool, смещение: int,
            предел: int | None = None) -> tuple[list, int, bool]:
    """Пройти файл по длинам. Возвращает пакеты (начало, длина) в файле,
    сколько байт пройдено, и дошли ли ровно до конца."""
    пакеты = []
    место = смещение
    конец = len(сырые) if предел is None else min(len(сырые), предел)
    while место + 2 <= конец:
        длина = int.from_bytes(сырые[место:место + 2], порядок)
        тело = длина - 2 if включает else длина
        if тело < 0:
            break
        if место + 2 + тело > len(сырые):
            break
        пакеты.append((место + 2, тело))
        место += 2 + тело
    return пакеты, место, место == len(сырые)


def разобрать_sig(сырые: bytes) -> tuple[list, str, list] | None:
    """Найти вариант разметки .Sig, по которому файл проходится до конца.

    Возвращает пакеты (начало, длина) в файле, описание формата и заметки,
    либо None, если ни один вариант не подошёл.
    """
    заметки: list = []
    годные = []
    for смещение in range(0, ЗАГОЛОВОК_ФАЙЛА_ДО + 1):
        for порядок in ("big", "little"):
            for включает in (False, True):
                # Сначала коротко — по первым 64 КБ: полный проход по всем
                # вариантам и смещениям на ста мегабайтах занял бы минуты.
                пакеты, _, до_конца = _пройти(сырые, порядок, включает, смещение,
                                              предел=1 << 16)
                if len(пакеты) < 3 and not до_конца:
                    continue
                пакеты, место, до_конца = _пройти(сырые, порядок, включает, смещение)
                if до_конца and len(пакеты) >= 2:
                    годные.append((смещение, порядок, включает, пакеты))
        if годные:
            break                  # меньшее смещение — правдоподобнее
    if not годные:
        return None
    # Оба порядка байт проходят файл до конца только при симметричных длинах
    # (например, все по 0x0101). Тогда берём тот, где пакетов больше, и
    # честно говорим, что выбор неоднозначен.
    годные.sort(key=lambda вариант: (-len(вариант[3]), вариант[1] != "big"))
    смещение, порядок, включает, пакеты = годные[0]
    if len({(в[1], в[2]) for в in годные}) > 1:
        заметки.append("разметка .Sig неоднозначна: файл проходится до конца при "
                       "нескольких толкованиях заголовка; выбрано то, где пакетов больше")
    длины = np.array([длина for _, длина in пакеты])
    формат = (f".Sig: {len(пакеты)} пакетов, длина в заголовке — два байта, "
              f"{'старший' if порядок == 'big' else 'младший'} байт первым, "
              f"{'включая' if включает else 'без'} сам заголовок"
              + (f"; в начале файла свой заголовок в {смещение} байт" if смещение else "")
              + f"; длина пакета от {int(длины.min())} до {int(длины.max())} байт, "
                f"медиана {int(np.median(длины))}")
    return пакеты, формат, заметки


def прочитать(путь: str | Path | None = None, *, данные: bytes | None = None,
              имя: str = "") -> Поток:
    """Прочитать поток из файла или из байтов.

    Вид определяется по расширению, а для .Sig — ещё и проверкой разметки:
    файл, который по ней не проходится, читается как сырой поток, и об этом
    говорится.
    """
    if данные is None:
        путь = Path(путь)
        данные = путь.read_bytes()
        имя = имя or путь.name
    имя = имя or "поток"
    расширение = Path(имя).suffix.lower()

    # Текстом прислали биты или шестнадцатеричный дамп.
    if расширение in (".txt", ".hex", ".bits", "") and len(данные) < 64 << 20:
        try:
            текст = данные.decode("ascii")
        except UnicodeDecodeError:
            текст = ""
        биты = из_текста(текст) if текст else None
        if биты is not None:
            return Поток(имя, "текст", в_байты(биты),
                         формат=f"текст: {len(биты)} бит")

    if расширение in РАСШИРЕНИЯ_SIG:
        найдено = разобрать_sig(данные)
        if найдено is not None:
            пакеты_файла, формат, заметки = найдено
            # Тела пакетов — подряд, без заголовков: это и есть поток.
            тела = []
            пакеты = []
            место = 0
            for начало, длина in пакеты_файла:
                тела.append(данные[начало:начало + длина])
                пакеты.append((место, длина))
                место += длина
            return Поток(имя, "sig", b"".join(тела), пакеты, формат, заметки)
        return Поток(имя, "bin", данные,
                     формат=f"сырой поток, {len(данные)} байт",
                     заметки=[f"файл назван {расширение}, но разметкой «двухбайтовая длина + "
                              "пакет» не проходится ни при каком толковании — "
                              "разобран как сырой поток"])

    return Поток(имя, "bin", данные, формат=f"сырой поток, {len(данные)} байт")


# -- большой .Sig с диска: тот же выбор разметки, без чтения файла в память ------------------

#: Начало файла для быстрой пробы вариантов разметки (64 КБ пакетов + самый длинный пакет).
ГОЛОВА_SIG = 256 << 10
#: Кусок чтения при проходе файла по длинам.
КУСОК_SIG = 16 << 20


def _пройти_файл(путь: Path, размер: int, порядок: str, включает: bool, смещение: int
                 ) -> tuple[np.ndarray, np.ndarray, bool]:
    """``_пройти`` по файлу на диске: начала и длины тел пакетов, дошли ли ровно до конца."""
    from array import array  # noqa: PLC0415
    начала, длины = array("q"), array("q")
    место = смещение
    буфер, от = b"", 0
    with open(путь, "rb") as файл:
        while место + 2 <= размер:
            if место + 2 > от + len(буфер):
                файл.seek(место)
                буфер, от = файл.read(КУСОК_SIG), место
            длина = int.from_bytes(буфер[место - от:место - от + 2], порядок)
            тело = длина - 2 if включает else длина
            if тело < 0 or место + 2 + тело > размер:
                break
            начала.append(место + 2)
            длины.append(тело)
            место += 2 + тело
    return np.frombuffer(начала, dtype=np.int64), np.frombuffer(длины, dtype=np.int64), место == размер


def разобрать_sig_файл(путь: str | Path) -> tuple[np.ndarray, np.ndarray, str, list] | None:
    """``разобрать_sig`` для файла на диске любого размера: тот же выбор варианта (проба по началу,
    проход по всему файлу), итог — начала и длины тел в файле, описание формата и заметки."""
    путь = Path(путь)
    размер = путь.stat().st_size
    with open(путь, "rb") as файл:
        голова = файл.read(ГОЛОВА_SIG)
    if размер <= len(голова):
        найдено = разобрать_sig(голова)
        if найдено is None:
            return None
        пакеты, формат, заметки = найдено
        return (np.array([н for н, _ in пакеты], dtype=np.int64), np.array([д for _, д in пакеты], dtype=np.int64),
                формат, заметки)
    заметки: list = []
    годные = []
    for смещение in range(0, ЗАГОЛОВОК_ФАЙЛА_ДО + 1):
        for порядок in ("big", "little"):
            for включает in (False, True):
                пакеты, _, до_конца = _пройти(голова, порядок, включает, смещение, предел=1 << 16)
                if len(пакеты) < 3 and not до_конца:
                    continue
                начала, длины, до_конца = _пройти_файл(путь, размер, порядок, включает, смещение)
                if до_конца and len(начала) >= 2:
                    годные.append((смещение, порядок, включает, начала, длины))
        if годные:
            break
    if not годные:
        return None
    годные.sort(key=lambda в: (-len(в[3]), в[1] != "big"))
    смещение, порядок, включает, начала, длины = годные[0]
    if len({(в[1], в[2]) for в in годные}) > 1:
        заметки.append("разметка .Sig неоднозначна: файл проходится до конца при "
                       "нескольких толкованиях заголовка; выбрано то, где пакетов больше")
    формат = (f".Sig: {len(начала)} пакетов, длина в заголовке — два байта, "
              f"{'старший' if порядок == 'big' else 'младший'} байт первым, "
              f"{'включая' if включает else 'без'} сам заголовок"
              + (f"; в начале файла свой заголовок в {смещение} байт" if смещение else "")
              + f"; длина пакета от {int(длины.min())} до {int(длины.max())} байт, "
                f"медиана {int(np.median(длины))}")
    return начала, длины, формат, заметки


def тела_в_файл(путь: str | Path, начала: np.ndarray, длины: np.ndarray, куда: str | Path,
                от: int = 0, сколько: int = 0) -> int:
    """Тела пакетов подряд — в файл ``куда`` кусками; ``от``/``сколько`` — часть сплошного потока
    (байты; 0 — до конца). Итог — сколько байт записано."""
    конец_потока = int(длины.sum())
    до = конец_потока if not сколько else min(конец_потока, от + сколько)
    записано = 0
    место = 0                                         # байт сплошного потока до текущего пакета
    with open(путь, "rb") as вход, open(куда, "wb") as выход:
        for начало, длина in zip(начала.tolist(), длины.tolist(), strict=True):
            a, b = max(от, место), min(до, место + длина)
            if a < b:
                вход.seek(начало + a - место)
                выход.write(вход.read(b - a))
                записано += b - a
            место += длина
            if место >= до:
                break
    return записано
