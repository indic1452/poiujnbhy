# -*- coding: utf-8 -*-
"""HDLC и битстаффинг: флаги, вставленные нули, кадры, FCS.

Признак HDLC-подобного канала — флаг 01111110 на БИТОВОМ уровне, не
обязательно по границе байта. Внутри кадра шесть единиц подряд не бывает:
после пяти передатчик вставляет ноль (битстаффинг), и его надо убрать,
прежде чем читать кадр. Правильность разбора проверяется FCS в конце
кадра: CRC-16 (X.25) или CRC-32. Совпала FCS у большинства кадров — это не
догадка, а доказательство: и граница кадров, и порядок бит, и снятие
вставленных нулей выбраны верно.

Октеты HDLC передаются МЛАДШИМ битом вперёд, поэтому кадр после снятия
нулей собирается в байты младшим битом вперёд.
"""

from __future__ import annotations

from collections import Counter
from typing import List

import numpy as np

from .bity import в_байты, инвертировать
from .nahodka import Находка

ФЛАГ = np.array([0, 1, 1, 1, 1, 1, 1, 0], dtype=np.uint8)
#: Меньше скольких флагов на миллион бит даже не рассматриваем: в
#: случайном потоке 01111110 встречается раз на 256 бит, но там же почти
#: сразу рядом стоят шесть единиц в «данных» — отсев по FCS это ловит.
ПРОВЕРЯТЬ_КАДРОВ = 3000
ОСТАТОК_16 = 0xF0B8
ОСТАТОК_32 = 0xDEBB20E3


def _таблица16() -> List[int]:
    таблица = []
    for байт in range(256):
        crc = байт
        for _ in range(8):
            crc = (crc >> 1) ^ 0x8408 if crc & 1 else crc >> 1
        таблица.append(crc)
    return таблица


def _таблица32() -> List[int]:
    таблица = []
    for байт in range(256):
        crc = байт
        for _ in range(8):
            crc = (crc >> 1) ^ 0xEDB88320 if crc & 1 else crc >> 1
        таблица.append(crc)
    return таблица


_Т16 = _таблица16()
_Т32 = _таблица32()


def fcs16(данные: bytes) -> int:
    """CRC-16/X.25 без финального обращения — для проверки по остатку."""
    crc = 0xFFFF
    for байт in данные:
        crc = (crc >> 8) ^ _Т16[(crc ^ байт) & 0xFF]
    return crc


def fcs32(данные: bytes) -> int:
    crc = 0xFFFFFFFF
    for байт in данные:
        crc = (crc >> 8) ^ _Т32[(crc ^ байт) & 0xFF]
    return crc


def fcs16_верна(кадр: bytes) -> bool:
    return len(кадр) >= 3 and fcs16(кадр) == ОСТАТОК_16


def fcs32_верна(кадр: bytes) -> bool:
    return len(кадр) >= 5 and fcs32(кадр) == ОСТАТОК_32


def флаги(биты: np.ndarray) -> np.ndarray:
    """Позиции флага 01111110 в битовом ряду."""
    if len(биты) < 8:
        return np.array([], dtype=np.int64)
    значение = np.zeros(len(биты) - 7, dtype=np.uint8)
    for сдвиг in range(8):
        значение = (значение << 1) | биты[сдвиг:len(биты) - 7 + сдвиг]
    return np.flatnonzero(значение == 0x7E)


def снять_вставку(биты: np.ndarray) -> np.ndarray:
    """Убрать ноль, стоящий сразу после пяти единиц подряд.

    Правило задано на ПЕРЕДАННОМ ряду, и вставленный ноль сам обрывает серию
    единиц — поэтому его можно искать сразу по всему ряду, без счётчика.
    """
    if len(биты) < 6:
        return биты
    пять = np.ones(len(биты) - 5, dtype=bool)
    for сдвиг in range(5):
        пять &= биты[сдвиг:len(биты) - 5 + сдвиг] == 1
    вставлено = np.flatnonzero(пять & (биты[5:] == 0)) + 5
    return np.delete(биты, вставлено)


def кадры(биты: np.ndarray) -> List[bytes]:
    """Кадры между флагами, со снятой вставкой, в байтах (младший бит первым)."""
    места = флаги(биты)
    итог = []
    for начало, конец in zip(места[:-1], места[1:]):
        if конец - начало < 8 + 32:          # между соседними флагами пусто
            continue
        тело = снять_вставку(биты[начало + 8:конец])
        if len(тело) % 8:
            continue                          # кадр не кратен октету — не наш
        итог.append(в_байты(тело, "младший"))
    return итог


def найти(биты: np.ndarray) -> Находка | None:
    """HDLC в битовом ряду — в любом порядке бит и полярности.

    Решает FCS: без совпавшей FCS находка не засчитывается. Проверяются оба
    порядка бит в байте и инверсия (перепутанная полярность линии).
    """
    лучшее = None
    for порядок in ("старший", "младший"):
        # Ряд пришёл в порядке «старший первым»; другой порядок — это
        # переворот бит внутри каждого байта.
        ряд = биты if порядок == "старший" else _перевернуть_в_байтах(биты)
        for инверсия in (False, True):
            проба = инвертировать(ряд) if инверсия else ряд
            места = флаги(проба)
            if len(места) < 4:
                continue
            собрано = кадры(проба)[:ПРОВЕРЯТЬ_КАДРОВ]
            if not собрано:
                continue
            верно16 = sum(fcs16_верна(кадр) for кадр in собрано)
            верно32 = sum(fcs32_верна(кадр) for кадр in собрано)
            верно, вид = (верно32, 32) if верно32 > верно16 else (верно16, 16)
            доля = верно / len(собрано)
            if лучшее is None or доля > лучшее[0]:
                лучшее = (доля, вид, порядок, инверсия, места, собрано, верно)
    if лучшее is None or лучшее[0] < 0.2:
        return None
    доля, вид, порядок, инверсия, места, собрано, верно = лучшее
    годные = [кадр[:-(вид // 8)] for кадр in собрано
              if (fcs32_верна(кадр) if вид == 32 else fcs16_верна(кадр))]
    длины = Counter(len(кадр) for кадр in годные)
    адреса = Counter(кадр[0] for кадр in годные if кадр)
    управление = Counter(кадр[1] for кадр in годные if len(кадр) > 1)
    подробно = [
        f"порядок бит в байте: {порядок} бит первым"
        + ("; полярность обратная (биты инвертированы)" if инверсия else ""),
        f"флагов 01111110: {len(места)} в {len(биты)} битах",
        f"кадров проверено: {len(собрано)}, FCS-{вид} верна у {верно}",
        "длины кадров (байт, без FCS): " + ", ".join(
            f"{длина}×{счёт}" for длина, счёт in длины.most_common(6)),
        "частые первые байты кадра (в HDLC — адрес): " + ", ".join(
            f"0x{байт:02X}×{счёт}" for байт, счёт in адреса.most_common(4)),
        "частые вторые байты кадра (в HDLC — управление): " + ", ".join(
            f"0x{байт:02X}×{счёт}" for байт, счёт in управление.most_common(4)),
    ]
    годных, отрезков = счёт(биты, порядок=порядок, инверсия=инверсия, fcs=вид)
    if отрезков and годных < отрезков:
        подробно.append(f"отрезков между флагами {отрезков}, кадров с верной FCS среди них {годных} "
                        f"({годных / отрезков * 100:.1f} %): остальные порваны — ошибками линии или "
                        f"вставками (не кратные октету в долю FCS выше не входят)")
    if годные and all(кадр[:2] == b"\xff\x03" for кадр in годные[:50] if len(кадр) > 2):
        подробно.append("адрес 0xFF и управление 0x03 — похоже на PPP в HDLC-подобном "
                        "обрамлении (RFC 1662)")
    return Находка(
        уровень="канальный", что=f"HDLC-подобное обрамление с битстаффингом, FCS-{вид}",
        уверенность=доля,
        мера=f"FCS верна у {round(доля * 100)} % из {len(собрано)} кадров",
        подробно=подробно, дальше=годные, вид_дальше="кадры",
        свойства={"порядок": порядок, "инверсия": инверсия, "fcs": вид, "годных": годных,
                  "отрезков": отрезков})


def счёт(биты: np.ndarray, *, порядок: str = "старший", инверсия: bool = False, fcs: int = 16
         ) -> tuple[int, int]:
    """(кадров с верной FCS, отрезков между флагами) — по всему ряду, без предела.

    Для сравнения толкований одного ряда (где кончается служебное поле кадра
    модема): кадр, порванный вставкой не кратного октету числа бит, в долю
    FCS не входит вовсе (он не кратен октету) — доля его не видит, а число
    годных видит: их меньше.
    """
    ряд = биты if порядок == "старший" else _перевернуть_в_байтах(биты)
    if инверсия:
        ряд = инвертировать(ряд)
    места = флаги(ряд)
    отрезков = int(np.sum(np.diff(места) >= 8 + 32)) if len(места) > 1 else 0
    верна = fcs32_верна if fcs == 32 else fcs16_верна
    return sum(1 for кадр in кадры(ряд) if верна(кадр)), отрезков


def _перевернуть_в_байтах(биты: np.ndarray) -> np.ndarray:
    целых = len(биты) - len(биты) % 8
    return биты[:целых].reshape(-1, 8)[:, ::-1].reshape(-1)
