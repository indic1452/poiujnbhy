"""Скремблер: полином — из самого потока, проверка — снятием.

Два способа найти полином, и оба работают без подсказки стандарта.

1. Берлекэмп — Мэсси по окнам. Где исходные данные постоянны (заполнение,
   простой канала, флаги между кадрами), выход скремблера — чисто линейная
   последовательность, и алгоритм выдаёт её полином прямо: у случайных
   данных линейная сложность окна в 256 бит — около 128, у скремблированного
   заполнения — степень полинома, 7–43. Работает и для мультипликативных
   скремблеров, и для аддитивных (ПСП).
2. Перебор. Мультипликативный скремблер y[n] = x[n] ⊕ y[n−a] ⊕ y[n−b]
   снимается тремя сдвигами: x = y ⊕ y≫a ⊕ y≫b. Всех одно- и двухотводных
   полиномов до степени 64 — около двух тысяч, на выборке в полмиллиона
   бит это секунды. Плюс известные: V.35, V.22, V.32/V.34, SDH x⁴³+1, 10GBASE-R.

Решает не полином, а результат: после снятия в потоке должна появиться
структура — упасть энтропия, появиться флаги HDLC, цикл, заголовки. Кандидат,
после которого поток остался случайным, не засчитывается.
"""

