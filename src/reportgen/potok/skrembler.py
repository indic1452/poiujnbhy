def рандомизатор_802_16(длина: int, начальное: str = РАНДОМИЗАТОР_802_16) -> np.ndarray:
    """ПСП рандомизатора 802.16 по Figure 170: ячейки 1…15 — начальное слева направо; выход — сумма
    ячеек 14 и 15, он же входит в ячейку 1, остальные сдвигаются на одну."""
    ячейки = [int(ч) for ч in начальное]
    if len(ячейки) != 15:
        raise ValueError("начальное состояние рандомизатора 802.16 — 15 бит")
    итог = np.zeros(длина, np.uint8)
    for i in range(длина):
        выход = ячейки[13] ^ ячейки[14]
        итог[i] = выход
        ячейки = [выход] + ячейки[:14]
    return итог


