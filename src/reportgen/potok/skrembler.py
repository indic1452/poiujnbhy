# -*- coding: utf-8 -*-
"""Скремблер: полином — из самого потока, проверка — снятием.

Два способа найти полином, и оба работают без подсказки стандарта.

1. Берлекэмп — Мэсси по окнам. Где исходные данные постоянны (заполнение,
   простой канала, флаги между кадрами), выход скремблера — чисто линейная
   последовательность, и алгоритм выдаёт её полином прямо: у случайных
   данных линейная сложность окна в 256 бит — около 128, у скремблированного
   заполнения — степень полинома, 7–43. Работает и для самосинхронизирующихся
   скремблеров, и для аддитивных (ПСП).
2. Перебор. Самосинхронизирующийся скремблер y[n] = x[n] ⊕ y[n−a] ⊕ y[n−b]
   снимается тремя сдвигами: x = y ⊕ y≫a ⊕ y≫b. Всех одно- и двухотводных
   полиномов до степени 64 — около двух тысяч, на выборке в полмиллиона
   бит это секунды. Плюс известные: V.35, V.22, V.32/V.34, SDH x⁴³+1, 10GBASE-R.

Решает не полином, а результат: после снятия в потоке должна появиться
структура — упасть энтропия, появиться флаги HDLC, цикл, заголовки. Кандидат,
после которого поток остался случайным, не засчитывается.
"""

from __future__ import annotations

from collections import Counter
from typing import Dict, List, Sequence, Tuple

import numpy as np

from .bity import в_байты
from .nahodka import Находка
from .statistika import энтропия

#: Известные самосинхронизирующиеся скремблеры: отводы (степени x^-k).
ИЗВЕСТНЫЕ: Dict[str, Tuple[int, ...]] = {
    "ITU-T V.35 (1 + x⁻³ + x⁻²⁰)": (3, 20),
    "ITU-T V.22/V.22bis, Intelsat IESS (1 + x⁻¹⁴ + x⁻¹⁷)": (14, 17),
    "ITU-T V.32/V.34, вызывающий (1 + x⁻¹⁸ + x⁻²³)": (18, 23),
    "ITU-T V.32/V.34, отвечающий (1 + x⁻⁵ + x⁻²³)": (5, 23),
    "SDH/SONET, ATM, POS (1 + x⁻⁴³)": (43,),
    "IEEE 802.3 10GBASE-R (1 + x⁻³⁹ + x⁻⁵⁸)": (39, 58),
    "ITU-T V.27/V.29 (1 + x⁻⁶ + x⁻⁷)": (6, 7),
    "DVB, аддитивная ПСП (1 + x⁻¹⁴ + x⁻¹⁵)": (14, 15),
    "ITU-T O.151 ПСП 2¹⁵−1 (1 + x⁻¹⁴ + x⁻¹⁵)": (14, 15),
}
#: Выборка для перебора, бит.
ВЫБОРКА = 1 << 19
#: Окно Берлекэмпа — Мэсси, бит, и сколько окон смотреть.
ОКНО_БМ = 256
ОКОН_БМ = 1200
НАИБОЛЬШАЯ_СТЕПЕНЬ = 64
#: Во сколько разбросов лучший кандидат должен отстоять от толпы неверных.
ВЫДЕЛЯЕТСЯ = 12.0


def снять(биты: np.ndarray, отводы: Sequence[int]) -> np.ndarray:
    """x[n] = y[n] ⊕ y[n−a] ⊕ … — снятие самосинхронизирующегося скремблера."""
    выход = биты.copy()
    for отвод in отводы:
        выход[отвод:] ^= биты[:-отвод]
    return выход[max(отводы):]


def берлекэмп_мэсси(биты: Sequence[int]) -> Tuple[int, int]:
    """Линейная сложность и полином связи (бит i — коэффициент при x^i)."""
    c, b, l, m = 1, 1, 0, 1
    история = 0
    for n, бит in enumerate(биты):
        история = (история << 1) | int(бит)
        d = (c & история).bit_count() & 1
        if d:
            t = c
            c ^= b << m
            if 2 * l <= n:
                l, b, m = n + 1 - l, t, 1
            else:
                m += 1
        else:
            m += 1
    return l, c


def полином_словами(отводы: Sequence[int]) -> str:
    return "1 + " + " + ".join(f"x^-{о}" for о in sorted(отводы))


def мера_структуры(биты: np.ndarray) -> float:
    """Насколько поток НЕ случаен: 0 — случаен, больше — порядок.

    Падение байтовой энтропии (лучшее по восьми выравниваниям) и перекос
    нулей и единиц. У случайного ряда в 64 тыс. бит мера около 0,02 — это
    погрешность оценки энтропии по выборке, — а у снятого скремблером HDLC
    с IP внутри уже 0,4.
    """
    if len(биты) < 4096:
        return 0.0
    лучшая = 0.0
    for сдвиг in range(8):
        байты = np.frombuffer(в_байты(биты[сдвиг:]), dtype=np.uint8)
        лучшая = max(лучшая, 8.0 - энтропия(байты))
    return лучшая + abs(float(биты.mean()) - 0.5) * 4


def мера_полная(биты: np.ndarray) -> float:
    """Мера структуры плюс ПРОВЕРЕННАЯ структура: кадры с верной FCS, цикл.

    Грубая мера различает «случайно» и «не случайно», но между двумя
    неслучайными вариантами — верно снятым потоком и потоком, испорченным
    неверной гипотезой, — различает слабо: 0,9 против 0,86. Решают
    проверяемые признаки: у верно снятого HDLC сходится FCS, у цикла
    совпадает синхрослово. Дорого, поэтому — только для лучших кандидатов.
    """
    from . import cikl, hdlc  # noqa: PLC0415 — круговой импорт

    выборка = биты[:1 << 18]
    мера = мера_структуры(выборка)
    кадры = hdlc.найти(выборка)
    if кадры is not None:
        мера += 3 * кадры.уверенность
    цикл = cikl.найти(выборка)
    if цикл is not None:
        мера += 2 * цикл.уверенность
    return мера


def кандидаты_бм(биты: np.ndarray) -> List[Tuple[Tuple[int, ...], int]]:
    """Полиномы, найденные Берлекэмпом — Мэсси в окнах с малой сложностью."""
    найдено: Counter = Counter()
    шаг = max(ОКНО_БМ, (len(биты) - ОКНО_БМ) // ОКОН_БМ)
    for начало in range(0, len(биты) - ОКНО_БМ, шаг):
        окно = биты[начало:начало + ОКНО_БМ]
        сложность, полином = берлекэмп_мэсси(окно.tolist())
        # 0–2 — постоянное окно без скремблера; больше 64 — случайное.
        if 3 <= сложность <= НАИБОЛЬШАЯ_СТЕПЕНЬ:
            отводы = tuple(i for i in range(1, сложность + 1) if полином >> i & 1)
            # Скремблеры — редкие полиномы в два-три отвода. Густой полином —
            # это произведение полинома скремблера на период самих данных
            # (флагов, заполнения): верный, но в отчёте он только путает.
            if 1 <= len(отводы) <= 4:
                найдено[отводы] += 1
    return найдено.most_common(8)


def псп(отводы: Sequence[int], начало: np.ndarray, длина: int) -> np.ndarray:
    """Продолжить линейную последовательность s[n] = ⊕ s[n−t] на длину бит."""
    степень = max(отводы)
    ряд = np.zeros(длина, dtype=np.uint8)
    ряд[:степень] = начало[:степень]
    for n in range(степень, длина):
        значение = 0
        for отвод in отводы:
            значение ^= ряд[n - отвод]
        ряд[n] = значение
    return ряд


def _простой(длина: int) -> List[Tuple[str, np.ndarray]]:
    """Чем бывают заполнены паузы: нули, единицы, флаги HDLC в любой фазе."""
    флаг = np.array([0, 1, 1, 1, 1, 1, 1, 0], dtype=np.uint8)
    варианты = [("нули", np.zeros(длина, dtype=np.uint8)),
                ("единицы", np.ones(длина, dtype=np.uint8))]
    for фаза in range(8):
        варианты.append((f"флаги HDLC (фаза {фаза})",
                         np.resize(np.roll(флаг, -фаза), длина)))
    return варианты


def аддитивный(биты: np.ndarray, отводы: Sequence[int]
               ) -> Tuple[float, np.ndarray, int, str] | None:
    """Снять аддитивную ПСП с этим полиномом: мера, снятый ряд, откуда, чем заполнены паузы.

    Самосинхронизирующее снятие тем же полиномом ПСП гасит, но и данные
    портит: получается x ⊕ x≫a ⊕ x≫b. В нём есть структура, но это не
    исходные данные. Поэтому ПСП восстанавливается честно: в паузе, где
    исходные данные известны (нули, единицы или флаги HDLC), выход за вычетом
    заполнения и есть ПСП, и из этого места она продолжается на весь поток.
    """
    степень = max(отводы)
    выборка = биты[:1 << 18]
    окно = ОКНО_БМ
    лучшая = None
    for имя, заполнение in _простой(len(выборка)):
        # Пауза заполнена нулями, единицами или флагами — в одной из фаз.
        остаток = выборка ^ заполнение            # в паузе — чистая ПСП
        гашёное = снять(остаток, отводы)            # нули там, где остаток — ПСП
        нули = np.flatnonzero(np.convolve(гашёное, np.ones(окно, dtype=np.int32),
                                          mode="valid") == 0)
        if not len(нули):
            continue
        место = int(нули[0]) + степень
        ряд = псп(отводы, остаток[место:место + степень], len(выборка) - место)
        снятое = выборка[место:] ^ ряд
        мера = мера_полная(снятое)
        if лучшая is None or мера > лучшая[0]:
            лучшая = (мера, снятое, место, имя, ряд)
    if лучшая is None:
        return None
    # Снимаем со ВСЕГО потока, а не с выборки: ПСП продолжается до конца.
    мера, _, место, имя, _ = лучшая
    степень_ = max(отводы)
    остаток = биты[место:место + степень_] ^ next(
        заполнение for вариант, заполнение in _простой(место + степень_)
        if вариант == имя)[место:место + степень_]
    ряд = псп(отводы, остаток, len(биты) - место)
    return мера, биты[место:] ^ ряд, место, имя


def найти(биты: np.ndarray, *, исходная_мера: float | None = None) -> Находка | None:
    """Скремблер в битовом ряду: полином, проверка снятием, снятый поток дальше."""
    выборка = биты[:ВЫБОРКА]
    if len(выборка) < 8192:
        return None
    было = мера_структуры(выборка) if исходная_мера is None else исходная_мера
    бм = кандидаты_бм(выборка)
    кандидаты: Dict[Tuple[int, ...], str] = {}
    for имя, отводы in ИЗВЕСТНЫЕ.items():
        кандидаты.setdefault(tuple(sorted(отводы)), имя)
    for отводы, счёт in бм:
        кандидаты.setdefault(отводы, f"найден по линейной сложности в {счёт} окнах")
    for a in range(1, НАИБОЛЬШАЯ_СТЕПЕНЬ + 1):
        кандидаты.setdefault((a,), "")
        for b in range(1, a):
            кандидаты.setdefault((b, a), "")

    # Отсев на малой выборке — по всем кандидатам сразу. Решает не величина
    # меры, а то, насколько лучший выделяется из толпы: неверный полином
    # оставляет поток случайным, и таких — почти две тысячи, их разброс и
    # есть шум. Верный отстоит от них на десятки разбросов.
    малая = выборка[:1 << 16]
    грубо = sorted(((мера_структуры(снять(малая, отводы)), отводы) for отводы in кандидаты),
                   reverse=True)
    значения = np.array([оценка for оценка, _ in грубо])
    середина = float(np.median(значения))
    разброс = 1.4826 * float(np.median(np.abs(значения - середина))) + 1e-4
    выделяется = (грубо[0][0] - середина) / разброс
    лучшие = [отводы for _, отводы in грубо[:6]]
    оценки = sorted(((мера_полная(снять(выборка, отводы)), отводы) for отводы in лучшие),
                    reverse=True)
    мера, отводы = оценки[0]
    второй = оценки[1][0] if len(оценки) > 1 else 0.0
    # Засчитываем, только если структура появилась (снятый поток упорядоченнее
    # исходного), лучший выделяется из толпы и не делит первенство с соседом.
    if (мера < мера_полная(выборка) + 0.1 or выделяется < ВЫДЕЛЯЕТСЯ
            or мера < второй + 0.05):
        return None

    # Тот же полином может гасить и АДДИТИВНУЮ ПСП: проверяем и эту гипотезу —
    # с самим полиномом и с его квадратным корнем (у квадрата все отводы чётные:
    # (1 + x¹⁴ + x¹⁵)² = 1 + x²⁸ + x³⁰).
    # Сначала — самый «короткий» полином: ПСП полинома P гасит и P², и в отчёт
    # должен попасть сам P, а не его квадрат.
    гипотезы = [tuple(отводы)]
    while all(о % 2 == 0 for о in гипотезы[0]):
        гипотезы.insert(0, tuple(о // 2 for о in гипотезы[0]))
    for полином in гипотезы:
        снято = аддитивный(биты, полином)
        if снято is not None and снято[0] > мера + 0.1:
            мера_псп, снятое, место, пауза = снято
            return Находка(
                уровень="скремблер",
                что=f"аддитивная ПСП {полином_словами(полином)}",
                уверенность=min(1.0, выделяется / 50),
                мера=f"после сложения с восстановленной ПСП мера структуры выросла с "
                     f"{было:.2f} до {мера_псп:.2f} (самосинхронизирующее снятие давало "
                     f"лишь {мера:.2f})",
                подробно=[
                    f"полином: {полином_словами(полином)}",
                    f"ПСП восстановлена по паузе в данных (бит {место}, заполнение — "
                    f"{пауза}) и продолжена вперёд без сброса",
                    "если структура открылась не на всём протяжении — ПСП "
                    "сбрасывается по циклам (как в DVB — раз в 8 пакетов), и снимать её "
                    "надо от начала цикла",
                ],
                дальше=снятое, вид_дальше="биты")

    имя = кандидаты.get(отводы) or "найден перебором"
    бм_подтвердил = any(отводы == о for о, _ in бм)
    подробно = [
        f"полином: {полином_словами(отводы)} ({имя})",
        f"мера структуры до снятия {было:.2f}, после — {мера:.2f}, у следующего "
        f"кандидата — {второй:.2f}; лучший отстоит от {len(кандидаты)} прочих на "
        f"{выделяется:.0f} разбросов",
    ]
    if бм:
        подробно.append("Берлекэмп — Мэсси по окнам по 256 бит: " + "; ".join(
            f"{полином_словами(о)} — в {с} окнах" for о, с in бм[:3]))
    if бм_подтвердил:
        подробно.append("полином подтверждён независимо: линейная сложность окон "
                        "с постоянными данными совпала со степенью полинома")
    снятое = снять(биты, отводы)
    уверенность = min(1.0, выделяется / 50) * (1.0 if бм_подтвердил or мера > второй + 0.2
                                               else 0.7)
    return Находка(
        уровень="скремблер",
        что=f"самосинхронизирующийся скремблер {полином_словами(отводы)}",
        уверенность=уверенность,
        мера=f"после снятия мера структуры выросла с {было:.2f} до {мера:.2f}"
             + ("; полином подтверждён Берлекэмпом — Мэсси" if бм_подтвердил else ""),
        подробно=подробно, дальше=снятое, вид_дальше="биты")
