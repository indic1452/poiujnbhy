def _годен(отводы) -> bool:
    from .svyortka import делить  # noqa: PLC0415
    if len(отводы) < 2 or max(отводы) < СТЕПЕНЬ_ОТ:
        return False
    п = _как_число(отводы)
    return all(делить((1 << m) | 1, п)[1] for m in range(8, БАЙТОВЫЙ_ПЕРИОД_ДО + 1, 8))


def снять(биты: np.ndarray, отводы: Sequence[int]) -> np.ndarray:
    """x[n] = y[n] ⊕ y[n−a] ⊕ … — снятие мультипликативного скремблера."""
    выход = биты.copy()
    for отвод in отводы:
        выход[отвод:] ^= биты[:-отвод]
    return выход[max(отводы):]


def берлекэмп_мэсси(биты: Sequence[int]) -> tuple[int, int]:
    """Линейная сложность и полином связи (бит i — коэффициент при x^i)."""
    c, b, l, m = 1, 1, 0, 1
    история = 0
    for n, бит in enumerate(биты):
        история = (история << 1) | int(бит)
        d = (c & история).bit_count() & 1
        if d:
            t = c
            c ^= b << m
            if 2 * l <= n:
                l, b, m = n + 1 - l, t, 1
            else:
                m += 1
        else:
            m += 1
    return l, c


def полином_словами(отводы: Sequence[int]) -> str:
    return "1 + " + " + ".join(f"x^-{о}" for о in sorted(отводы))


def мера_структуры(биты: np.ndarray) -> float:
    """Насколько поток НЕ случаен: 0 — случаен, больше — порядок.

    Падение байтовой энтропии (лучшее по восьми выравниваниям) и перекос
    нулей и единиц. У случайного ряда в 64 тыс. бит мера около 0,02 — это
    погрешность оценки энтропии по выборке, — а у снятого скремблером HDLC
    с IP внутри уже 0,4.
    """
    if len(биты) < 4096:
        return 0.0
    лучшая = 0.0
    for сдвиг in range(8):
        байты = np.frombuffer(в_байты(биты[сдвиг:]), dtype=np.uint8)
        лучшая = max(лучшая, 8.0 - энтропия(байты))
    return лучшая + abs(float(биты.mean()) - 0.5) * 4


def мера_полная(биты: np.ndarray) -> float:
    """Мера структуры плюс ПРОВЕРЕННАЯ структура: кадры с верной FCS, цикл.

    Грубая мера различает «случайно» и «не случайно», но между двумя
    неслучайными вариантами — верно снятым потоком и потоком, испорченным
    неверной гипотезой, — различает слабо: 0,9 против 0,86. Решают
    проверяемые признаки: у верно снятого HDLC сходится FCS, у цикла
    совпадает синхрослово. Дорого, поэтому — только для лучших кандидатов.
    """
    from . import cikl, hdlc  # noqa: PLC0415 — круговой импорт

    выборка = биты[:1 << 18]
    мера = мера_структуры(выборка)
    кадры = hdlc.найти(выборка)
    if кадры is not None:
        мера += 3 * кадры.уверенность
    цикл = cikl.найти(выборка)
    if цикл is not None:
        мера += 2 * цикл.уверенность
    return мера


def _как_число(отводы: Sequence[int]) -> int:
    return 1 | sum(1 << t for t in отводы)


def _в_отводы(полином: int) -> tuple[int, ...]:
    return tuple(i for i in range(1, полином.bit_length()) if полином >> i & 1)


def кандидаты_бм(биты: np.ndarray) -> list[tuple[tuple[int, ...], int]]:
    """Полиномы, найденные Берлекэмпом — Мэсси в окнах с малой сложностью.

    Число отводов не ограничено: у многоотводного скремблера (5, 7, 9
    отводов) в окне, где данные постоянны, выход — чистая последовательность
    его регистра, и БМ отдаёт полином целиком. Густой полином бывает и
    произведением полинома скремблера на период самих данных (флаги,
    заполнение): лишний множитель делит 1 + x^T, и частные после его снятия
    добавляются кандидатами — верный отберёт полная проверка. Случайное окно даёт
    сложность около половины окна и в разных окнах не повторяется, поэтому
    засчитываются только полиномы, найденные хотя бы в двух окнах.
    """
    from .svyortka import нод  # noqa: PLC0415 — общая арифметика GF(2)[x]
    найдено: Counter = Counter()
    шаг = max(ОКНО_БМ, (len(биты) - ОКНО_БМ) // ОКОН_БМ)
    for начало in range(0, len(биты) - ОКНО_БМ, шаг):
        окно = биты[начало:начало + ОКНО_БМ]
        сложность, полином = берлекэмп_мэсси(окно.tolist())
        # 0–2 — постоянное окно без скремблера; больше 64 — случайное. Многочлен
        # связи без отводов (1) при ненулевой сложности — окно, где после первых
        # бит одни нули: рекуррентности скремблера в нём нет.
        if 3 <= сложность <= НАИБОЛЬШАЯ_СТЕПЕНЬ and полином >> 1:
            найдено[_в_отводы(полином)] += 1
    # Данные с периодом T (флаги, заполнение, циклы) удовлетворяют
    # рекуррентности 1 + x^T, поэтому лишний множитель в произведении делит
    # 1 + x^T: снимаем общий делитель с 1 + x^T для T до 64 — остаётся
    # полином самого скремблера.
    from .svyortka import делить, умножить  # noqa: PLC0415
    for отводы, счёт in list(найдено.items()):
        if счёт < 2:
            continue
        исходный = _как_число(отводы)
        частные = set()
        for T in range(1, 65):
            # Каждое промежуточное частное — кандидат: у самого скремблера
            # тоже может быть множитель из 1 + x^T (например, 1 + x при чётном
            # числе членов), и снимать его до конца нельзя.
            полином = исходный
            while True:
                общий = нод(полином, (1 << T) | 1)
                if общий.bit_length() <= 1:
                    break
                полином = делить(полином, общий)[0]
                частные.add(полином)
        множитель, j = 3, 1                                  # (1 + x)^j
        while j <= 16:
            частное, остаток = делить(исходный, множитель)
            if остаток:
                break
            частные.add(частное)
            множитель, j = умножить(множитель, 3), j + 1
        for полином in частные:
            if полином & 1 and 3 <= полином.bit_length() - 1 < исходный.bit_length() - 1:
                найдено[_в_отводы(полином)] = max(найдено[_в_отводы(полином)], счёт)
    # Редкие полиномы — вперёд: скремблеры чаще в 2–3 отвода, а густой —
    # часто произведение; но и густые остаются в списке.
    итог = sorted(((о, с) for о, с in найдено.items() if с >= 2),
                  key=lambda п: (-п[1], len(п[0])))
    return итог[:40]


def псп(отводы: Sequence[int], начало: np.ndarray, длина: int) -> np.ndarray:
    """Продолжить линейную последовательность s[n] = ⊕ s[n−t] на длину бит.

    Регистр — целое число: бит (t − 1) держит s[n − t]; новый бит — чётность
    регистра под маской отводов. Так в десятки раз быстрее, чем по элементам массива.
    """
    степень = max(отводы)
    ряд = np.zeros(длина, dtype=np.uint8)
    начальные = np.asarray(начало, dtype=np.uint8)[:min(степень, длина)]
    ряд[:len(начальные)] = начальные
    if длина <= степень:
        return ряд
    маска = 0
    for отвод in отводы:
        маска |= 1 << (отвод - 1)
    регистр = 0
    for t in range(1, степень + 1):
        регистр |= int(ряд[степень - t]) << (t - 1)
    полный = (1 << степень) - 1
    хвост = bytearray(длина - степень)
    for i in range(len(хвост)):
        бит = (регистр & маска).bit_count() & 1
        хвост[i] = бит
        регистр = ((регистр << 1) | бит) & полный
    ряд[степень:] = np.frombuffer(bytes(хвост), dtype=np.uint8)
    return ряд


def псп_назад(отводы: Sequence[int], состояние: np.ndarray, сколько: int) -> np.ndarray:
    """Биты ПСП перед местом, где она равна «состоянию» (степень бит): «сколько» бит до него.

    Из s[n] = ⊕ s[n − t] при старшем отводе t = степень: s[n − степень] = s[n] ⊕ ⊕_{t < степень} s[n − t].
    """
    степень = max(отводы)
    младшие = [t for t in отводы if t != степень]
    ряд = [0] * сколько + [int(б) for б in np.asarray(состояние, dtype=np.uint8)[:степень]]
    for n in range(сколько + степень - 1, степень - 1, -1):
        бит = ряд[n]
        for t in младшие:
            бит ^= ряд[n - t]
        ряд[n - степень] = бит
    return np.array(ряд[:сколько], dtype=np.uint8)


def _простой(длина: int) -> list[tuple[str, np.ndarray]]:
    """Чем бывают заполнены паузы: нули, единицы, флаги HDLC в любой фазе."""
    флаг = np.array([0, 1, 1, 1, 1, 1, 1, 0], dtype=np.uint8)
    варианты = [("нули", np.zeros(длина, dtype=np.uint8)),
                ("единицы", np.ones(длина, dtype=np.uint8))]
    for фаза in range(8):
        варианты.append((f"флаги HDLC (фаза {фаза})",
                         np.resize(np.roll(флаг, -фаза), длина)))
    return варианты


def аддитивный(биты: np.ndarray, отводы: Sequence[int]
               ) -> tuple[float, np.ndarray, int, str] | None:
    """Снять аддитивную ПСП с этим полиномом: мера, снятый ряд, откуда, чем заполнены паузы.

    Мультипликативное снятие тем же полиномом ПСП гасит, но и данные
    портит: получается x ⊕ x≫a ⊕ x≫b. В нём есть структура, но это не
    исходные данные. Поэтому ПСП восстанавливается честно: в паузе, где
    исходные данные известны (нули, единицы или флаги HDLC), выход за вычетом
    заполнения и есть ПСП, и из этого места она продолжается на весь поток.
    """
    степень = max(отводы)
    выборка = биты[:1 << 18]
    окно = ОКНО_БМ
    лучшая = None
    for имя, заполнение in _простой(len(выборка)):
        # Пауза заполнена нулями, единицами или флагами — в одной из фаз.
        остаток = выборка ^ заполнение            # в паузе — чистая ПСП
        гашёное = снять(остаток, отводы)            # нули там, где остаток — ПСП
        нули = np.flatnonzero(np.convolve(гашёное, np.ones(окно, dtype=np.int32),
                                          mode="valid") == 0)
        if not len(нули):
            continue
        место = int(нули[0]) + степень
        ряд = псп(отводы, остаток[место:место + степень], len(выборка) - место)
        снятое = выборка[место:] ^ ряд
        мера = мера_полная(снятое)
        if лучшая is None or мера > лучшая[0]:
            лучшая = (мера, снятое, место, имя, ряд)
    if лучшая is None:
        return None
    # Снимаем со ВСЕГО потока, а не с выборки: ПСП продолжается до конца.
    мера, _, место, имя, _ = лучшая
    степень_ = max(отводы)
    остаток = биты[место:место + степень_] ^ next(
        заполнение for вариант, заполнение in _простой(место + степень_)
        if вариант == имя)[место:место + степень_]
    ряд = псп(отводы, остаток, len(биты) - место)
    return мера, биты[место:] ^ ряд, место, имя


def _кандидаты(выборка: np.ndarray, бм) -> dict[tuple[int, ...], str]:
    кандидаты: dict[tuple[int, ...], str] = {}
    for имя, отводы in ИЗВЕСТНЫЕ.items():
        кандидаты.setdefault(tuple(sorted(отводы)), имя)
    for отводы, счёт in бм:
        кандидаты.setdefault(отводы, f"найден по линейной сложности в {счёт} окнах")
    for a in range(1, НАИБОЛЬШАЯ_СТЕПЕНЬ + 1):
        кандидаты.setdefault((a,), "")
        for b in range(1, a):
            кандидаты.setdefault((b, a), "")
    return кандидаты


def _толпа(выборка: np.ndarray, кандидаты) -> tuple[float, list]:
    """Насколько лучший полином выделяется из толпы — и толпа, лучшими вперёд.

    Решает не величина меры, а отрыв: неверный полином оставляет поток
    случайным, и таких — почти две тысячи, их разброс и есть шум. Верный
    отстоит от них на десятки разбросов.
    """
    малая = выборка[:1 << 16]
    грубо = sorted(((мера_структуры(снять(малая, отводы)), отводы) for отводы in кандидаты),
                   reverse=True)
    значения = np.array([оценка for оценка, _ in грубо])
    середина = float(np.median(значения))
    разброс = 1.4826 * float(np.median(np.abs(значения - середина))) + 1e-4
    return (грубо[0][0] - середина) / разброс, грубо


def отрыв(биты: np.ndarray) -> float:
    """Отрыв лучшего мультипликативного полинома от толпы — мера «здесь скремблер».

    Для перебора гипотез выше скремблера (модуляционная плоскость): у верной
    гипотезы скремблер «проявляется» — отрыв в десятки разбросов, у неверной
    — на уровне шума.
    """
    выборка = биты[:1 << 16]
    if len(выборка) < 8192:
        return 0.0
    return _толпа(выборка, _кандидаты(выборка, []))[0]


#: Окно «Поиск скремблера»: сочетаний одной степени не больше стольких за запрос
#: (C(30,3) = 4060 — степень 31 с четырьмя отводами — около полутора секунд).
ПЕРЕБОР_ДО = 20_000
ВЫБОРКА_ПЕРЕБОРА = 1 << 16
ОТВОДОВ_ДО = 8


def перебор_степени(биты: np.ndarray, степень: int, отводов: int, *, лучших: int = 20
                    ) -> dict[str, Any]:
    """Все мультипликативные полиномы одной степени с заданным числом отводов.

    Старший отвод — сама степень, остальные — любые меньше неё. Для каждого:
    мера структуры снятого и доля нулей; лучшие первыми. Медиана и разброс мер
    всей толпы — чтобы окно поиска считало отрыв лучших по всем степеням сразу:
    верный полином отстоит от толпы на десятки разбросов.
    """
    степень, отводов = int(степень), int(отводов)
    if not 1 <= степень <= НАИБОЛЬШАЯ_СТЕПЕНЬ:
        raise ValueError(f"степень полинома — от 1 до {НАИБОЛЬШАЯ_СТЕПЕНЬ}")
    if not 1 <= отводов <= min(степень, ОТВОДОВ_ДО):
        raise ValueError(f"отводов — от 1 до {ОТВОДОВ_ДО} и не больше степени")
    сочетаний = math.comb(степень - 1, отводов - 1)
    if сочетаний > ПЕРЕБОР_ДО:
        raise ValueError(f"степень {степень} с {отводов} отводами — {сочетаний} полиномов, больше "
                         f"{ПЕРЕБОР_ДО}: уменьшите число отводов")
    выборка = биты[:ВЫБОРКА_ПЕРЕБОРА]
    if len(выборка) < 4096 + степень:
        raise ValueError("мало бит для перебора: нужно хотя бы 4096 после первого бита")
    итог = []
    for младшие in combinations(range(1, степень), отводов - 1):
        отводы = (*младшие, степень)
        снятое = снять(выборка, отводы)
        итог.append((мера_структуры(снятое), 1.0 - float(снятое.mean()), отводы))
    меры = np.array([м for м, _, _ in итог])
    середина = float(np.median(меры))
    итог.sort(key=lambda х: -х[0])
    return {"степень": степень, "отводов": отводов, "сочетаний": сочетаний,
            "медиана": round(середина, 5),
            "разброс": round(1.4826 * float(np.median(np.abs(меры - середина))), 5),
            "лучшие": [{"отводы": list(отводы), "мера": round(мера, 4), "нули": round(нули, 4),
                        "полином": полином_словами(отводы)}
                       for мера, нули, отводы in итог[:max(1, int(лучших))]]}


#: Пауза короче ОКНО_БМ, но не короче этого, — ещё годится как опора ПСП: у случайного
#: ряда совпадение рекурсии на 32 битах подряд — один раз на 4 млрд мест.
КОРОТКАЯ_ПАУЗА = 32
#: Снятие считается подтверждённым, если мера структуры выросла хотя бы на столько.
ПРИРОСТ_МЕРЫ = 0.1
#: ПСП со сбросом в кадре подтверждена, если с устойчивыми столбцами кадров совпала на столько.
КАДР_СОВПАЛО = 0.95
#: Сколько самых длинных пауз каждого заполнения проверить на ненулевой регистр.
ПАУЗ_ПРОВЕРИТЬ = 16


def _строка(биты: np.ndarray) -> str:
    return "".join("1" if б else "0" for б in np.asarray(биты).tolist())


def _лучшая_пауза(выборка: np.ndarray, отводы: Sequence[int]) -> tuple[int, int, str] | None:
    """Самый длинный участок, где данные — одно заполнение: (длина, начало ПСП, заполнение).

    В паузе снятие мультипликативным тем же полиномом даёт нули (данные там
    известны — нули, единицы или флаги HDLC), значит, выход за вычетом
    заполнения — сама ПСП.
    """
    степень = max(отводы)
    лучшая = None
    for имя, заполнение in _простой(len(выборка)):
        остаток = выборка ^ заполнение
        гашёное = снять(остаток, отводы)
        if not len(гашёное):
            continue
        края = np.diff(np.concatenate(([1], гашёное, [1])).astype(np.int8))
        начала, концы = np.flatnonzero(края == -1), np.flatnonzero(края == 1)
        # Нули гашёного с j — рекурсия верна для бит с j + степень: ПСП — с бита j. Участок, где
        # остаток сам нулевой (поток — то же заполнение, скремблера там нет), опорой не служит:
        # нулевой регистр даёт нулевую ПСП.
        for i in np.argsort(-(концы - начала), kind="stable")[:ПАУЗ_ПРОВЕРИТЬ]:
            длина, j = int(концы[i] - начала[i]), int(начала[i])
            if лучшая is not None and длина <= лучшая[0]:
                break
            if остаток[j:j + степень].any():
                лучшая = (длина, j, имя)
                break
    return лучшая


def начальная_установка(биты: np.ndarray, отводы: Sequence[int], *, кадр: int = 0,
                        начало_кадра: int = 0) -> dict[str, Any]:
    """Начальная установка скремблера с этим полиномом — находится всегда.

    Мультипликативный скремблер заполняет регистр самим потоком: его
    начальная установка — первые «степень» бит (``самосинхр``). Для аддитивного
    (ПСП складывается с данными) регистр ищется четырьмя способами, берётся тот,
    после снятия которым поток структурнее всего:

    - **паузы** — участок не короче ОКНО_БМ, где данные — заполнение (нули,
      единицы, флаги HDLC): там выход за вычетом заполнения и есть ПСП; она
      продолжается вперёд и назад — до первого бита;
    - **кадр** — ПСП сбрасывается в каждом кадре длиной ``кадр`` (с бита
      ``начало_кадра``): состояние — по устойчивым столбцам кадра;
    - **короткая пауза** — самый длинный такой участок, если он короче ОКНО_БМ,
      но не короче КОРОТКАЯ_ПАУЗА;
    - **начало** — опоры нет: считается, что данные с первого ненулевого бита потока —
      нули (нулевой регистр дал бы нулевую ПСП; по той же причине не берутся и паузы,
      где сам поток нулевой).

    ``в_начале`` — состояние регистра на первом бите (ПСП продолжена назад);
    ``уверенно`` — мера структуры после снятия выросла на ПРИРОСТ_МЕРЫ и больше
    (у сброса в кадре — ПСП совпала с устойчивыми столбцами кадров на КАДР_СОВПАЛО).
    ``слой`` — шаг обработки, который снимает ПСП именно так.
    """
    отводы = tuple(sorted(int(t) for t in отводы))
    степень = max(отводы)
    выборка = np.asarray(биты[:ВЫБОРКА_ПЕРЕБОРА], dtype=np.uint8)
    n = len(выборка)
    было = мера_полная(выборка)
    перечень = ",".join(map(str, отводы))
    варианты: list[tuple[float, dict[str, Any]]] = []

    def непрерывная(место: int, регистр: np.ndarray, способ: str, **ещё: Any) -> None:
        вперёд = псп(отводы, регистр, n - место)
        ряд = np.concatenate([псп_назад(отводы, регистр, место), вперёд])
        мера = мера_полная(выборка ^ ряд)
        варианты.append((мера, {"способ": способ, "место": int(место), "регистр": _строка(регистр[:степень]),
                                "в_начале": _строка(ряд[:степень]), "мера": round(float(мера), 4),
                                "слой": f"аддитивный отводы {перечень} начальное {_строка(регистр[:степень])} с бита {место}",
                                **ещё}))

    пауза = _лучшая_пауза(выборка, отводы) if n > степень else None
    if пауза is not None and пауза[0] >= КОРОТКАЯ_ПАУЗА:
        длина, место, имя = пауза
        заполнение = dict(_простой(место + степень))[имя][место:место + степень]
        непрерывная(место, выборка[место:место + степень] ^ заполнение,
                    "паузы" if длина >= ОКНО_БМ else "короткая пауза", заполнение=имя, пауза=длина)
    if кадр and 2 * степень <= кадр <= n // 4:
        начало = int(начало_кадра) % кадр
        найдено = найти_по_кадру(выборка, кадр, начало=начало, отводы=отводы)
        if найдено is not None:
            начальное = np.array([int(ч) for ч in найдено["начальное"]], dtype=np.uint8)
            снятое = снять_по_кадру(выборка, отводы, начальное, кадр, начало=начало)
            мера = мера_полная(снятое)
            варианты.append((мера, {"способ": "кадр", "место": начало, "регистр": найдено["начальное"],
                                    "в_начале": найдено["начальное"], "мера": round(float(мера), 4), "кадр": int(кадр),
                                    "совпало": найдено["совпало"],
                                    "слой": f"аддитивный отводы {перечень} кадр {кадр} начальное {найдено['начальное']} "
                                            f"начало {начало}"}))
    if not варианты:
        # Опоры нет: данные с первого бита, где поток не нулевой, считаются нулями (нулевой
        # регистр — нулевая ПСП, от него толку нет).
        ненулевые = np.flatnonzero(выборка)
        место = int(ненулевые[0]) if len(ненулевые) else 0
        место = max(0, min(место, n - степень))
        непрерывная(место, выборка[место:место + степень], "начало")
    мера, итог = max(варианты, key=lambda в: в[0])
    # Сброс в кадре сам делает поток периодичным (мера «до» высока) — его подтверждают
    # устойчивые столбцы кадров; остальное — рост меры структуры.
    итог["уверенно"] = bool(мера >= было + ПРИРОСТ_МЕРЫ
                            or (итог["способ"] == "кадр" and итог["совпало"] >= КАДР_СОВПАЛО))
    итог["было"] = round(float(было), 4)
    итог["самосинхр"] = _строка(выборка[:степень])
    # Прежние имена: «заполнение» есть у пауз; у остальных — как найдено.
    итог.setdefault("заполнение", {"кадр": f"сброс в каждом кадре {кадр} бит", "начало": "опоры нет — "
                                   "данные в начале считаются нулями"}.get(итог["способ"], ""))
    return итог


def найти(биты: np.ndarray, *, исходная_мера: float | None = None) -> Находка | None:
    """Скремблер в битовом ряду: полином, проверка снятием, снятый поток дальше."""
    выборка = биты[:ВЫБОРКА]
    if len(выборка) < 8192:
        return None
    было = мера_структуры(выборка) if исходная_мера is None else исходная_мера
    бм = кандидаты_бм(выборка)
    кандидаты = _кандидаты(выборка, бм)

    выделяется, грубо = _толпа(выборка, кандидаты)
    лучшие = [отводы for _, отводы in грубо[:6]]
    # Полиномы Берлекэмпа — Мэсси и их частные — на полную проверку все:
    # по грубой мере произведение «скремблер × период данных» выглядит
    # упорядоченнее верного полинома (паузы гасятся в нули), и верный мог бы
    # не войти в шестёрку; решает проверяемая структура (FCS, цикл).
    лучшие += [отводы for отводы, _ in бм if отводы not in лучшие][:24]
    оценки = sorted(((мера_полная(снять(выборка, отводы)), отводы) for отводы in лучшие
                     if _годен(отводы)), reverse=True)
    if not оценки:
        return None
    from .svyortka import делить  # noqa: PLC0415

    def кратен(a, b) -> bool:
        """Один полином делит другой — одно семейство, а не соперники."""
        x, y = _как_число(a), _как_число(b)
        return not делить(x, y)[1] or not делить(y, x)[1]

    мера, отводы = оценки[0]
    # «Сосед» — лучший из НЕродственных: произведения верного полинома на
    # период данных и его делители соперниками не считаются.
    второй = next((м for м, о in оценки[1:] if not кратен(о, отводы)), 0.0)
    # Засчитываем, только если структура появилась (снятый поток упорядоченнее
    # исходного), лучший выделяется из толпы и не делит первенство с соседом.
    if (мера < мера_полная(выборка) + 0.1 or выделяется < ВЫДЕЛЯЕТСЯ
            or мера < второй + 0.05):
        return None

    # Тот же полином может гасить и АДДИТИВНУЮ ПСП: проверяем и эту гипотезу —
    # с самим полиномом и с его квадратным корнем (у квадрата все отводы чётные:
    # (1 + x¹⁴ + x¹⁵)² = 1 + x²⁸ + x³⁰).
    # Сначала — самый «короткий» полином: ПСП полинома P гасит и P², и в отчёт
    # должен попасть сам P, а не его квадрат.
    гипотезы = [tuple(отводы)]
    while all(о % 2 == 0 for о in гипотезы[0]):
        гипотезы.insert(0, tuple(о // 2 for о in гипотезы[0]))
    # Полиномы БМ, делящие выбранный, — тоже в гипотезы, самые редкие вперёд:
    # выбранный бывает произведением «ПСП × период пауз» (так паузы гасятся в
    # нули и грубая мера выше), а ПСП порождает сам делитель.
    делители = sorted((о for о, _ in бм if о != tuple(отводы)
                       and not делить(_как_число(отводы), _как_число(о))[1]), key=len)
    гипотезы = делители[:6] + [г for г in гипотезы if г not in делители]
    for полином in (г for г in гипотезы if _годен(г)):
        снято = аддитивный(биты, полином)
        if снято is not None and снято[0] > мера + 0.1:
            мера_псп, снятое, место, пауза = снято
            return Находка(
                уровень="скремблер",
                что=f"аддитивная ПСП {полином_словами(полином)}",
                уверенность=min(1.0, выделяется / 50),
                мера=f"после сложения с восстановленной ПСП мера структуры выросла с "
                     f"{было:.2f} до {мера_псп:.2f} (мультипликативное снятие давало "
                     f"лишь {мера:.2f})",
                подробно=[
                    f"полином: {полином_словами(полином)}",
                    f"ПСП восстановлена по паузе в данных (бит {место}, заполнение — "
                    f"{пауза}) и продолжена вперёд без сброса",
                    "если структура открылась не на всём протяжении — ПСП "
                    "сбрасывается по циклам (как в DVB — раз в 8 пакетов), и снимать её "
                    "надо от начала цикла",
                ],
                дальше=снятое, вид_дальше="биты",
                свойства={"вид": "аддитивный", "отводы": list(полином), "место": int(место)})

    имя = кандидаты.get(отводы) or "найден перебором"
    бм_подтвердил = any(отводы == о for о, _ in бм)
    подробно = [
        f"полином: {полином_словами(отводы)} ({имя})",
        f"мера структуры до снятия {было:.2f}, после — {мера:.2f}, у следующего "
        f"кандидата — {второй:.2f}; лучший отстоит от {len(кандидаты)} прочих на "
        f"{выделяется:.0f} разбросов",
    ]
    if бм:
        подробно.append("Берлекэмп — Мэсси по окнам по 256 бит: " + "; ".join(
            f"{полином_словами(о)} — в {с} окнах" for о, с in бм[:3]))
    if бм_подтвердил:
        подробно.append("полином подтверждён независимо: линейная сложность окон "
                        "с постоянными данными совпала со степенью полинома")
    снятое = снять(биты, отводы)
    уверенность = min(1.0, выделяется / 50) * (1.0 if бм_подтвердил or мера > второй + 0.2
                                               else 0.7)
    return Находка(
        уровень="скремблер",
        что=f"мультипликативный скремблер {полином_словами(отводы)}",
        уверенность=уверенность,
        мера=f"после снятия мера структуры выросла с {было:.2f} до {мера:.2f}"
             + ("; полином подтверждён Берлекэмпом — Мэсси" if бм_подтвердил else ""),
        подробно=подробно, дальше=снятое, вид_дальше="биты",
        свойства={"вид": "самосинхронизирующийся", "отводы": list(отводы)})


# -- кадровый аддитивный скремблер: сброс в начальное состояние в каждом кадре -------------
#
# Так устроены кадровые скремблеры SDH, DVB и многих РРЛ: в начале кадра (после
# синхрокомбинации) регистр встаёт в заданное состояние, и ПСП в каждом кадре
# одна и та же. Значит, в растре по длине кадра столбец — это бит ПСП ⊕ бит
# данных: где данные постоянны (заполнение, нули), столбец постоянен и равен
# биту ПСП (или его инверсии). По таким столбцам ПСП и восстанавливается:
# без отводов — Берлекэмпом — Мэсси по самому длинному устойчивому участку
# (он даёт и полином, и состояние), с известными отводами — решением
# линейной системы над GF(2) для начального состояния.
#
# Начальное состояние здесь — первые L бит ПСП после сброса (L — степень).
# Стандарты пишут содержимое регистра в разном порядке ячеек; первые L бит
# ПСП однозначны при любом порядке — по ним и сверяйте с документом.

#: Столбец считается устойчивым, если в нём одно значение не реже чем в стольких кадрах.
УСТОЙЧИВЫЙ = 0.9


def столбцы_кадра(биты: np.ndarray, длина: int, начало: int = 0, кадров_до: int = 4000
                  ) -> tuple[np.ndarray, np.ndarray]:
    """Большинство по каждому столбцу растра и его устойчивость (0,5…1)."""
    ряд = биты[начало:]
    кадров = min(кадров_до, len(ряд) // длина)
    if кадров < 8:
        raise ValueError(f"нужно хотя бы 8 кадров по {длина} бит")
    доли = ряд[:кадров * длина].reshape(кадров, длина).mean(axis=0)
    return (доли >= 0.5).astype(np.uint8), np.maximum(доли, 1 - доли)


def _назад(ряд: np.ndarray, отводы: Sequence[int], сколько: int) -> np.ndarray:
    """Продолжить ПСП назад на ``сколько`` бит: s[m−1] = s[m−1+L] ⊕ ⊕ s[m−1+L−t] (t < L)."""
    L = max(отводы)
    младшие = [t for t in отводы if t < L]
    назад: list[int] = []                       # s[m−1], s[m−2], … по порядку
    окно = [int(б) for б in ряд[:L]]            # s[m] … s[m+L−1]
    for _ in range(сколько):
        # a[j] = s[m−1+j] после вставки; s[m−1] = a[L] ⊕ ⊕ a[L−t] — через окно:
        значение = окно[L - 1]
        for t in младшие:
            значение ^= окно[L - 1 - t]
        назад.append(значение)
        окно = [значение] + окно[:L - 1]
    return np.concatenate([np.array(назад[::-1], dtype=np.uint8),
                           np.asarray(ряд, dtype=np.uint8)])


def _устойчивый_участок(уст: np.ndarray, пропуск: int) -> tuple[int, int]:
    """Самый длинный участок подряд устойчивых столбцов после пропуска: (начало, длина)."""
    хорошие = np.concatenate([[False], уст[пропуск:] >= УСТОЙЧИВЫЙ, [False]])
    края = np.flatnonzero(np.diff(хорошие.astype(np.int8)))
    if not len(края):
        return пропуск, 0
    начала, концы = края[::2], края[1::2]
    i = int(np.argmax(концы - начала))
    return пропуск + int(начала[i]), int(концы[i] - начала[i])


def _базис(отводы: Sequence[int], длина: int) -> np.ndarray:
    """ПСП от каждого единичного начального состояния: L × длина (ПСП линейна по состоянию)."""
    L = max(отводы)
    return np.array([псп(отводы, np.eye(L, dtype=np.uint8)[i], длина) for i in range(L)],
                    dtype=np.uint8)


def _решить(A: np.ndarray, y: np.ndarray) -> np.ndarray | None:
    """x: A·x = y над GF(2) (A — уравнения × L); None, если несовместно."""
    from . import gf2  # noqa: PLC0415
    L = A.shape[1]
    ред, опорные = gf2.привести(gf2.упаковать(np.concatenate([A, y[:, None]], axis=1)
                                              .astype(np.uint8)), L + 1)
    if L in опорные:
        return None
    строки = gf2.распаковать(ред, L + 1)
    x = np.zeros(L, dtype=np.uint8)
    for r, p in enumerate(опорные):
        x[p] = строки[r, L]
    return x


def начальное_по_отводам(главные: np.ndarray, уст: np.ndarray, отводы: Sequence[int],
                         пропуск: int = 0) -> tuple[np.ndarray | None, float]:
    """Начальное состояние при известных отводах: по устойчивым столбцам кадра.

    В устойчивом участке данные постоянны — нули или единицы (заполнение),
    но разные участки бывают заполнены по-разному (нули здесь, единицы
    там, постоянный заголовок). Поэтому система решается по каждому
    участку из не менее L подряд устойчивых столбцов отдельно, в двух
    предположениях (нули или единицы), и берётся решение, с которым
    согласно больше всего устойчивых столбцов всего кадра.
    """
    L = max(отводы)
    N = len(главные) - пропуск
    базис = _базис(отводы, N)
    хорошие = уст[пропуск:] >= УСТОЙЧИВЫЙ
    опорные = np.flatnonzero(хорошие)
    if len(опорные) < L:
        return None, 0.0
    y = главные[пропуск:]
    края = np.flatnonzero(np.diff(np.concatenate([[0], хорошие.astype(np.int8), [0]])))
    участки = sorted(zip(края[::2], края[1::2], strict=False), key=lambda у: у[0] - у[1])
    лучшее: tuple[np.ndarray | None, float] = (None, 0.0)
    for от, до in участки[:12]:
        if до - от < L:
            break
        столбцы = np.arange(от, до)
        for инверсия in (0, 1):
            x = _решить(базис[:, столбцы].T, y[столбцы] ^ инверсия)
            if x is None:
                continue
            маска = (x.astype(np.int64) @ базис[:, опорные].astype(np.int64)) & 1
            # Согласие по всему кадру: столбец объясняется ПСП ⊕ 0 или ПСП ⊕ 1.
            доля = float(np.mean(маска == y[опорные]))
            доля = max(доля, 1 - доля) if инверсия else доля
            if доля > лучшее[1]:
                лучшее = (x.astype(np.uint8), доля)
    if лучшее[0] is None:
        return None, 0.0
    return псп(отводы, лучшее[0], L), лучшее[1]


def найти_по_кадру(биты: np.ndarray, длина: int, *, начало: int = 0, пропуск: int = 0,
                   отводы: Sequence[int] | None = None) -> dict[str, object] | None:
    """Кадровый аддитивный скремблер: отводы (если не даны) и начальное состояние."""
    главные, уст = столбцы_кадра(биты, длина, начало)
    устойчивых = int(np.sum(уст[пропуск:] >= УСТОЙЧИВЫЙ))
    способ = ""
    if not отводы:
        от, сколько = _устойчивый_участок(уст, пропуск)
        L, полином = берлекэмп_мэсси(главные[от:от + сколько]) if сколько else (0, 1)
        if not L or сколько < 2 * L + 8 or L > НАИБОЛЬШАЯ_СТЕПЕНЬ:
            return None
        отводы = tuple(i for i in range(1, L + 1) if (полином >> i) & 1)
        if not отводы or max(отводы) != L:
            return None
        # Участок — это ПСП ⊕ постоянные данные; если данные там единицы,
        # полином тот же (ПСП ⊕ 1 при чётном числе членов — тоже решение).
        ряд = _назад(главные[от:от + сколько], отводы, от - пропуск)
        начальное = ряд[:L]
        способ = (f"Берлекэмп — Мэсси по устойчивому участку столбцов {от}…{от + сколько - 1} "
                  f"(линейная сложность {L})")
    else:
        отводы = tuple(sorted(int(t) for t in отводы))
        начальное, _ = начальное_по_отводам(главные, уст, отводы, пропуск)
        if начальное is None:
            return None
        способ = "решение системы над GF(2) по устойчивым столбцам (отводы заданы)"
    L = max(отводы)
    маска = псп(отводы, начальное, длина - пропуск)
    опорные = np.flatnonzero(уст[пропуск:] >= УСТОЙЧИВЫЙ)
    совпало = float(np.mean(маска[опорные] == главные[пропуск:][опорные])) if len(опорные) else 0.0
    return {"отводы": list(отводы), "полином": полином_словами(отводы),
            "начальное": "".join(map(str, начальное[:L].tolist())),
            "совпало": round(max(совпало, 1 - совпало), 4), "устойчивых": устойчивых,
            "длина": длина, "пропуск": пропуск, "способ": способ}


def снять_по_кадру(биты: np.ndarray, отводы: Sequence[int], начальное: np.ndarray, длина: int,
                   пропуск: int = 0, начало: int = 0) -> np.ndarray:
    """Сложить каждый кадр (от ``начало``) с ПСП от начального состояния; пропуск не трогается."""
    ряд = биты[начало:]
    кадров = len(ряд) // длина
    маска = np.zeros(длина, dtype=np.uint8)
    маска[пропуск:] = псп(отводы, np.asarray(начальное, dtype=np.uint8), длина - пропуск)
    return (ряд[:кадров * длина].reshape(кадров, длина) ^ маска).reshape(-1)


# -- ПСП со сбросом на каждом блоке при любом заполнении ----------------------------------
#
# Скремблер модема с кодом произведения (и многих других) складывает данные
# каждого блока кода с одной и той же ПСП: регистр в начале блока встаёт в
# одно и то же состояние. ``найти_по_кадру`` берёт такую ПСП из постоянных
# столбцов растра — там, где данные постоянны. Но заполнение бывает не
# постоянным, а периодическим: флаги HDLC 01111110 идут подряд через границы
# блоков, и фаза флагов в каждом блоке своя — столбцы растра не постоянны.
# Тогда так. В окне, где идёт заполнение, выход — ПСП ⊕ периодическое
# заполнение, и Берлекэмп — Мэсси даёт произведение полинома ПСП на множитель
# периода (у флагов — (1 + x)⁷). Множители периода (делители 1 + x^T при
# малых T) отделяются, окно раскладывается на две составляющие решением
# системы над GF(2) — и состояние ПСП, отнесённое к началу блока, у всех
# таких окон одно и то же. Это и есть проверка сброса на блоке: у сплошной
# ПСП (без сброса) состояния в разных блоках разные.
#
# Сбрасывается ПСП бывает и не на каждом блоке, а через m блоков (сверхблок):
# внутри сверхблока она идёт непрерывно, и состояние в начале блока — сдвиг
# состояния сверхблока на r·длина тактов (r — место блока в сверхблоке). Такие
# состояния по кругу узнаются продолжением ПСП от каждого частого состояния.

#: Окно Берлекэмпа — Мэсси в блоке, бит.
ОКНО_БЛОКА = 256
#: Сколько блоков смотреть и сколько окон в каждом.
БЛОКОВ_ДО = 300
ОКОН_В_БЛОКЕ = 8
#: Периоды заполнения, которые отделяются от ПСП: до 16 бит и кратные байту до 64.
ПЕРИОДЫ_ЗАПОЛНЕНИЯ = tuple(range(1, 17)) + (24, 32, 40, 48, 56, 64)
#: Наименьшая степень ПСП: короче — это период заполнения, а не скремблер.
СТЕПЕНЬ_ПСП_ОТ = 5
#: Какая доля блоков с разложением должна сойтись по состоянию в начале блока (сверхблока).
ОДНО_СОСТОЯНИЕ_ОТ = 0.5
#: Сколько окон должно дать один полином ПСП.
ОКОН_С_СОСТОЯНИЕМ_ОТ = 3
#: В скольких разных блоках (сверхблоках) должно сойтись состояние — иначе сброс не доказан.
БЛОКОВ_С_СОСТОЯНИЕМ_ОТ = 3
#: Через сколько блоков самое большее сбрасывается ПСП (сверхблок из m блоков).
СБРОС_ЧЕРЕЗ_ДО = 8
#: Сколько самых частых состояний пробовать началом сверхблока.
НАЧАЛ_ПРОБОВАТЬ = 8


def разделить_период(полином: int) -> tuple[int, int]:
    """Полином связи окна → (множитель периода заполнения, полином ПСП)."""
    from .svyortka import делить, нод  # noqa: PLC0415
    остаток = полином
    for T in ПЕРИОДЫ_ЗАПОЛНЕНИЯ:
        while True:
            общий = нод(остаток, (1 << T) | 1)
            if общий.bit_length() <= 1:
                break
            остаток = делить(остаток, общий)[0]
    return делить(полином, остаток)[0], остаток


def период_заполнения(множитель: int) -> int:
    """Наименьший период T из ПЕРИОДЫ_ЗАПОЛНЕНИЯ, у которого 1 + x^T делится на множитель (0 — нет)."""
    from .svyortka import делить  # noqa: PLC0415
    if множитель.bit_length() <= 1:
        return 1
    return next((T for T in ПЕРИОДЫ_ЗАПОЛНЕНИЯ if not делить((1 << T) | 1, множитель)[1]), 0)


def _заполнение_словами(множитель: int) -> str:
    T = период_заполнения(множитель)
    if T == 1:
        return "постоянное (нули или единицы)"
    if T == 8:
        return "с периодом 8 бит (флаги HDLC 01111110 или байтовое заполнение)"
    return f"с периодом {T} бит" if T else "периодическое"


def характеристический(отводы: Sequence[int]) -> str:
    """Тот же полином в записи характеристического многочлена: x^L + … + 1 (s[n] = ⊕ s[n − t])."""
    L = max(отводы)
    степени = sorted({L} | {L - t for t in отводы if t != L} | {0}, reverse=True)
    return " + ".join("1" if с == 0 else "x" if с == 1 else f"x^{с}" for с in степени)


def период_лрп(отводы: Sequence[int], *, степень_до: int = 20) -> int | None:
    """Период ПСП (порядок x по модулю характеристического многочлена) — до степени ``степень_до``."""
    L = max(отводы)
    if L > степень_до:
        return None
    многочлен = (1 << L) | 1 | sum(1 << (L - t) for t in отводы if t != L)
    x, n = 2, 1
    if x >> L & 1:                     # степень 1: сам x уже приводится
        x ^= многочлен
    while x != 1:
        x <<= 1
        if x >> L & 1:
            x ^= многочлен
        n += 1
        if n > (1 << L):
            return None
    return n


def блоковая_псп(биты: np.ndarray, длина: int) -> Находка | None:
    """Аддитивная ПСП со сбросом в начале каждого блока длиной ``длина`` бит — при любом заполнении.

    Поток должен начинаться с начала блока (так отдаёт данные декодер кода
    произведения). Возвращает находку со снятым потоком или None.
    """
    блоков = len(биты) // длина
    W = min(ОКНО_БЛОКА, длина)
    if блоков < 8 or W < 64:
        return None
    биты = np.asarray(биты, dtype=np.uint8)
    шаг = max(1, (длина - W) // max(1, ОКОН_В_БЛОКЕ - 1))
    смещения = list(range(0, длина - W + 1, шаг))[:ОКОН_В_БЛОКЕ]
    окна: list[tuple[int, int, int, int]] = []          # (блок, смещение, множитель, ПСП)
    for b in range(min(блоков, БЛОКОВ_ДО)):
        for o in смещения:
            начало = b * длина + o
            сложность, полином = берлекэмп_мэсси(биты[начало:начало + W].tolist())
            # Случайное окно — сложность около W/2; окно с заполнением — степень произведения.
            if not 3 <= сложность <= W // 2 - 16:
                continue
            множитель, псп_ = разделить_период(полином)
            if псп_.bit_length() - 1 >= СТЕПЕНЬ_ПСП_ОТ:
                окна.append((b, o, множитель, псп_))
    if len(окна) < ОКОН_С_СОСТОЯНИЕМ_ОТ:
        return None
    полином_псп, сколько = Counter(о[3] for о in окна).most_common(1)[0]
    if сколько < ОКОН_С_СОСТОЯНИЕМ_ОТ:
        return None
    отводы = _в_отводы(полином_псп)
    L = max(отводы)
    базис_блока = _базис(отводы, длина)                  # ПСП от начала блока: L × длина
    базисы: dict[int, np.ndarray] = {}
    по_блокам: dict[int, Counter] = {}
    заполнения: Counter = Counter()
    for b, o, множитель, псп_ in окна:
        if псп_ != полином_псп:
            continue
        if множитель not in базисы:
            базисы[множитель] = (_базис(_в_отводы(множитель), W) if множитель.bit_length() > 1
                                 else np.zeros((0, W), dtype=np.uint8))
        A = np.concatenate([базис_блока[:, o:o + W], базисы[множитель]]).T
        x = _решить(A, биты[b * длина + o:b * длина + o + W])
        if x is None:
            continue
        по_блокам.setdefault(b, Counter())[x[:L].tobytes()] += 1
        заполнения[множитель] += 1
    # Каждый блок голосует одним состоянием — большинством своих окон: у сплошной
    # ПСП все окна одного блока тоже дают одно состояние, и блок, где заполнения
    # много, не должен перевешивать остальные.
    состояние_блока = {b: сч.most_common(1)[0][0] for b, сч in по_блокам.items()}
    сброс = _сброс(состояние_блока, отводы, длина)
    if сброс is None:
        # Состояния в разных блоках разные и не сдвиги одного — ПСП не сбрасывается ни
        # на блоке, ни на сверхблоке.
        return None
    m, начальное, фаза, совпало = сброс
    всего = len(состояние_блока)
    маски = псп(отводы, начальное, m * длина).reshape(m, длина)
    места = (np.arange(блоков + 1) - фаза) % m              # место блока в сверхблоке
    полных = блоков * длина
    снятое = биты.copy()
    снятое[:полных] = (биты[:полных].reshape(блоков, длина) ^ маски[места[:блоков]]).reshape(-1)
    снятое[полных:] ^= маски[места[блоков]][:len(биты) - полных]
    было, стало = мера_полная(биты), мера_полная(снятое)
    if стало < было + 0.1:
        return None
    заполнение = заполнения.most_common(1)[0][0]
    if m == 1:
        вид = f"со сбросом в начале каждого блока {длина} бит"
        где = "в начале блока одно и то же"
        сброс_словами = [f"сброс на блоке: у сплошной ПСП состояния в начале блоков были бы разными, "
                         f"здесь — одно у {совпало} из {всего} блоков"]
    else:
        блоков_ = "блока" if m < 5 else "блоков"
        вид = f"со сбросом через каждые {m} {блоков_} по {длина} бит (сверхблок {m * длина} бит)"
        где = "в начале блока — сдвиг состояния сверхблока на место блока в нём, как у одной ПСП"
        сброс_словами = [
            f"сброс через {m} {блоков_}: внутри сверхблока ПСП идёт непрерывно — состояние в начале "
            f"блока совпало со сдвигом состояния сверхблока у {совпало} из {всего} блоков; "
            f"первый блок потока — {(-фаза) % m + 1}-й блок сверхблока"]
    известная = ИЗВЕСТНЫЕ_ПСП.get((tuple(sorted(отводы)), "".join(map(str, начальное.tolist())))) \
        if m == 1 else None
    return Находка(
        уровень="скремблер",
        что=f"аддитивная ПСП {полином_словами(отводы)} {вид}" + (f" — {известная}" if известная else ""),
        уверенность=min(1.0, совпало / всего),
        мера=f"состояние ПСП {где} у {совпало} из {всего} блоков с заполнением; "
             f"после снятия мера структуры выросла с {было:.2f} до {стало:.2f}",
        подробно=[
            f"полином: {полином_словами(отводы)} (степень {L}; характеристический — "
            f"{характеристический(отводы)}); первые {L} бит ПСП от начала блока "
            f"(начальное состояние): {''.join(map(str, начальное.tolist()))}",
        ] + ([f"период ПСП — {период} бит" + (f" = 2^{L} − 1: полином примитивный" if период == (1 << L) - 1
                                            else "") for период in [период_лрп(отводы)] if период]) + [
            f"найден Берлекэмпом — Мэсси по окнам {W} бит в {min(блоков, БЛОКОВ_ДО)} блоках: окно с "
            f"заполнением — ПСП ⊕ заполнение {_заполнение_словами(заполнение)}; множитель периода "
            f"отделён, окно разложено на ПСП и заполнение над GF(2)",
        ] + сброс_словами,
        дальше=снятое, вид_дальше="биты",
        свойства={"отводы": list(отводы), "начальное": "".join(map(str, начальное.tolist())),
                  "длина_блока": длина, "блоков_в_сбросе": m, "фаза": int(фаза)})


def _сброс(состояние_блока: dict[int, bytes], отводы: Sequence[int], длина: int
           ) -> tuple[int, np.ndarray, int, int] | None:
    """Через сколько блоков сбрасывается ПСП: (m, начальное, фаза, совпало) или None.

    ``состояние_блока`` — блок → первые L бит ПСП от начала блока (по одному на
    блок). При сбросе через m блоков блок b, (b − фаза) mod m = r, начинается с
    состояния сверхблока, сдвинутого на r·длина тактов. Берётся наименьшее m,
    при котором так сходится не меньше ОДНО_СОСТОЯНИЕ_ОТ блоков с состоянием —
    и в разных сверхблоках (не меньше БЛОКОВ_С_СОСТОЯНИЕМ_ОТ): у сплошной ПСП
    без сброса сходится лишь один сверхблок. m = 1 — сброс на каждом блоке.
    """
    L = max(отводы)
    всего = len(состояние_блока)
    частые = [к for к, _ in Counter(состояние_блока.values()).most_common(НАЧАЛ_ПРОБОВАТЬ)]
    сдвиги = []
    for ключ in частые:
        ряд = псп(отводы, np.frombuffer(ключ, dtype=np.uint8), (СБРОС_ЧЕРЕЗ_ДО - 1) * длина + L)
        сдвиги.append([ряд[r * длина:r * длина + L].tobytes() for r in range(СБРОС_ЧЕРЕЗ_ДО)])
    for m in range(1, СБРОС_ЧЕРЕЗ_ДО + 1):
        лучший = None
        for ключ, свои in zip(частые, сдвиги, strict=False):
            место = {свои[r]: r for r in range(m - 1, -1, -1)}     # при совпадении — меньшее место
            фазы: Counter = Counter((b - место[к]) % m for b, к in состояние_блока.items() if к in место)
            if not фазы:
                continue
            фаза, совпало = фазы.most_common(1)[0]
            сверхблоков = len({(b - фаза) // m for b, к in состояние_блока.items()
                               if к in место and (b - место[к]) % m == фаза})
            if (совпало >= ОДНО_СОСТОЯНИЕ_ОТ * всего and сверхблоков >= БЛОКОВ_С_СОСТОЯНИЕМ_ОТ
                    and (лучший is None or совпало > лучший[3])):
                лучший = (m, np.frombuffer(ключ, dtype=np.uint8).copy(), фаза, совпало)
        if лучший is not None:
            return лучший
    return None


#: Маска-кандидат засчитывается, если встретилась хотя бы в стольких блоках (и доле блоков).
МАСКА_БЛОКОВ_ОТ = 3
МАСКА_ДОЛЯ_ОТ = 0.05
#: Сколько самых частых масок-кандидатов проверять снятием.
МАСОК_ПРОВЕРИТЬ = 10


def маска_блока(биты: np.ndarray, длина: int) -> Находка | None:
    """Постоянная маска на каждом блоке — любая, не только ЛРП, — по блокам заполнения.

    Блок = маска ⊕ данные. В блоке, где идёт заполнение известного вида
    (нули, единицы, флаги HDLC в любой фазе), маска = блок ⊕ заполнение: у
    всех таких блоков она одна и та же, у прочих сочетаний «блок ⊕ заполнение»
    — случайная. Поэтому маска — самый частый кандидат по всем блокам и
    видам заполнения; при равенстве (все блоки заполнения в одной фазе
    флагов) решает структура после снятия. Маска бывает не ЛРП: ПСП блока ⊕
    инверсия бита метки при неоднозначности созвездия, фиксированный
    заголовок и т. п.
    """
    блоков = min(len(биты) // длина, БЛОКОВ_ДО)
    if блоков < 8 or длина < 16:
        return None
    биты = np.asarray(биты, dtype=np.uint8)
    таблица = биты[:блоков * длина].reshape(блоков, длина)
    заполнения = _простой(длина)
    порог = max(МАСКА_БЛОКОВ_ОТ, int(МАСКА_ДОЛЯ_ОТ * блоков))
    # Кандидаты «блок ⊕ заполнение»: у блоков заполнения маска одна и та же.
    варианты = np.stack([таблица ^ заполнение for _, заполнение in заполнения], axis=1)
    кандидаты: list[tuple[bytes, int, str]] = []
    сборка = _маска_по_кускам(варианты, порог)
    if сборка is not None:
        маска_, сколько_ = сборка
        кандидаты.append((np.packbits(маска_).tobytes(), сколько_, "по кускам 64 бит в разных блоках"))
    счёт: Counter = Counter()
    откуда: dict[bytes, tuple[int, str]] = {}
    for b in range(блоков):
        for i, (имя, _) in enumerate(заполнения):
            ключ = np.packbits(варианты[b, i]).tobytes()
            счёт[ключ] += 1
            откуда.setdefault(ключ, (b, имя))
    кандидаты += [(к, с, "блок {} ⊕ заполнение ({})".format(*откуда[к]))
                  for к, с in счёт.most_common(МАСОК_ПРОВЕРИТЬ) if с >= порог]
    if not кандидаты:
        return None
    было = мера_полная(биты)
    полных = (len(биты) // длина) * длина
    лучшая = None
    for ключ, сколько, как in кандидаты:
        маска = np.unpackbits(np.frombuffer(ключ, dtype=np.uint8))[:длина]
        if not маска.any():
            continue
        снятое = биты.copy()
        снятое[:полных] = (биты[:полных].reshape(-1, длина) ^ маска).reshape(-1)
        снятое[полных:] ^= маска[:len(биты) - полных]
        мера = мера_полная(снятое)
        if лучшая is None or мера > лучшая[0]:
            лучшая = (мера, маска, снятое, сколько, как)
    if лучшая is None or лучшая[0] < было + 0.1:
        return None
    мера, маска, снятое, сколько, как = лучшая
    сложность, полином = берлекэмп_мэсси(маска.tolist())
    подробно = [
        f"маска {длина} бит (начало, hex): {в_байты(маска[:256]).hex()}"
        + ("…" if длина > 256 else ""),
        f"найдена по заполнению (нули, единицы, флаги HDLC в любой фазе): маска = блок ⊕ "
        f"заполнение — {как}; подтверждена {сколько} блоками из {блоков}",
    ]
    if 3 <= сложность <= min(НАИБОЛЬШАЯ_СТЕПЕНЬ, длина // 2 - 8):
        отводы = _в_отводы(полином)
        подробно.append(f"маска — ЛРП: {полином_словами(отводы)}, первые {сложность} бит "
                        f"(начальное состояние) {''.join(map(str, маска[:сложность].tolist()))}")
        вид = f"аддитивная ПСП {полином_словами(отводы)} со сбросом в начале каждого блока {длина} бит"
        свойства = {"отводы": list(отводы), "начальное": "".join(map(str, маска[:сложность].tolist())),
                    "длина_блока": длина}
    else:
        подробно.append(f"маска не ЛРП степени до {НАИБОЛЬШАЯ_СТЕПЕНЬ} (линейная сложность "
                        f"{сложность}): фиксированный узор блока — ПСП со сбросом вместе с "
                        f"инверсией бит (неоднозначность меток созвездия), заголовок и т. п.")
        вид = f"постоянная маска на каждом блоке {длина} бит (сброс на блоке)"
        свойства = {"маска": в_байты(маска).hex(), "длина_блока": длина}
    return Находка(
        уровень="скремблер", что=вид, уверенность=min(1.0, сколько / max(1, 0.2 * блоков)),
        мера=f"маска одна и та же у {сколько} из {блоков} блоков; после снятия мера структуры "
             f"выросла с {было:.2f} до {мера:.2f}",
        подробно=подробно, дальше=снятое, вид_дальше="биты", свойства=свойства)


#: Кусок маски, собираемый по разным блокам, бит.
КУСОК_МАСКИ = 64
#: Кусок засчитан, если лучший кандидат чаще второго во столько раз.
КУСОК_ОТРЫВ = 1.5


def _маска_по_кускам(варианты: np.ndarray, порог: int) -> tuple[np.ndarray, int] | None:
    """Маска по кускам: у каждого куска — свой самый частый кандидат (блоки × заполнения × длина).

    Пауза бывает короче блока, и целиком заполненных блоков нет; но куски
    маски видны в разных блоках — у каждого места свои. Кусок засчитан, если
    его лучший кандидат встретился не реже ``порог`` раз и заметно чаще
    второго. Возвращает (маска, наименьшее число подтверждений) или None.
    """
    блоков, _, длина = варианты.shape
    маска = np.zeros(длина, dtype=np.uint8)
    наименьшее = блоков
    for начало in range(0, длина, КУСОК_МАСКИ):
        кусок = варианты[:, :, начало:начало + КУСОК_МАСКИ].reshape(-1, min(КУСОК_МАСКИ, длина - начало))
        счёт = Counter(map(bytes, np.packbits(кусок, axis=1)))
        (лучший, сколько), *прочие = счёт.most_common(2)
        второй = прочие[0][1] if прочие else 0
        if сколько < порог or сколько < КУСОК_ОТРЫВ * второй:
            return None
        маска[начало:начало + кусок.shape[1]] = np.unpackbits(
            np.frombuffer(лучший, dtype=np.uint8))[:кусок.shape[1]]
        наименьшее = min(наименьшее, сколько)
    return маска, наименьшее


def по_блоку(биты: np.ndarray, длина: int) -> Находка | None:
    """Скремблер со сбросом на каждом блоке: ЛРП при любом заполнении, иначе маска по заполнению."""
    найдено = блоковая_псп(биты, длина)
    if найдено is not None:
        return найдено
    return маска_блока(биты, длина)
