@dataclass
class Ветвь:
    находки: List[Находка] = field(default_factory=list)
    не_найдено: List[str] = field(default_factory=list)
    ограничения: List[str] = field(default_factory=list)
    другие: List[str] = field(default_factory=list)
    оценка: float = 0.0

    def проверяемая(self, находка: Находка, путь: str) -> None:
        self.находки.append(_с_путём(находка, путь))
        self.оценка += ВЕС_ПРОВЕРЯЕМОЙ * находка.уверенность
        if _ТЕКУЩИЙ.бюджет is not None:
            _ТЕКУЩИЙ.бюджет.сказать(f"найдено: {находка.что} ({находка.мера})")

    def влить(self, другая: "Ветвь") -> None:
        self.находки += другая.находки
        self.не_найдено += другая.не_найдено
        self.ограничения += другая.ограничения
        self.другие += другая.другие
        self.оценка += другая.оценка


@dataclass
class Бюджет:
    конец: float
    профиль: dict = field(default_factory=lambda: ПРОФИЛИ["быстро"])
    исчерпан: bool = False
    #: Куда сообщать ход разбора («пробую скремблер…») и найденные этапы —
    #: для страницы, где этапы появляются по мере разбора.
    ход: Optional[Callable[[str], None]] = None
    этап: Optional[Callable[[Находка], None]] = None
    #: Бит на символ КАМ, если известно, — для подбора модуляционной плоскости.
    символ: tuple = ()
    #: Бит на символ ФМ (1 — BPSK, 2 — QPSK, 3 — 8PSK…) — то же для ФМ.
    фм: tuple = ()

    def сказать(self, строка: str) -> None:
        if self.ход is not None:
            self.ход(строка)

    @property
    def глубоко(self) -> bool:
        return self.профиль["выколотые"]

    def вышел(self) -> bool:
        if time.monotonic() > self.конец:
            self.исчерпан = True
        return self.исчерпан


class _Текущий:
    """Бюджет идущего разбора — чтобы ветви могли сообщать о находках."""
    бюджет: Optional["Бюджет"] = None


_ТЕКУЩИЙ = _Текущий()


def _дальше(путь: str, шаг: str) -> str:
    return (путь + " → " if путь else "") + шаг


def _кадры_без_ip(ветвь: Ветвь, кадры: Sequence[bytes], путь: str, откуда: str) -> None:
    """Кадры, в которых нет IP: формат полей и контрольная сумма."""
    формат = polya.найти(кадры, откуда)
    if формат is not None:
        ветвь.проверяемая(формат, путь)
    else:
        ветвь.не_найдено.append(f"IP и известный формат в {откуда}: нет")


def _проверяемые(выборка: np.ndarray, глубина: int, путь: str, б: Бюджет) -> Ветвь | None:
    """Уровни, которые доказывают себя сами. None — ни одного не нашлось."""
    ветвь = Ветвь()
    где = f" ({путь})" if путь else ""

    # 1. Пакеты прямо в байтах и транспортный поток (с кодом DVB).
    байты = в_байты(выборка)
    найдено = pakety.найти_в_потоке(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        return ветвь
    найдено = kod.mpeg_ts(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        длина, сдвиг = найдено.дальше
        if длина == dvb.ДЛИНА:
            канал = dvb.найти(байты, сдвиг)
            if канал is not None:
                ветвь.проверяемая(канал, путь)
            else:
                ветвь.не_найдено.append(f"код Рида — Соломона (204, 188) в пакетах{где}: "
                                        f"синдромы не нулевые ни как есть, ни после снятия "
                                        f"перемежения DVB")
        return ветвь
    ветвь.не_найдено.append(f"пакеты IP подряд и MPEG-TS{где}: нет")

    # 2. HDLC: битстаффинг, затем октетный (асинхронный PPP, SLIP) — и что в кадрах.
    кадры = hdlc.найти(выборка)
    if кадры is None:
        ветвь.не_найдено.append(f"HDLC с битстаффингом{где}: флагов с верной FCS нет")
        кадры = oktety.найти(выборка)
        if кадры is None:
            ветвь.не_найдено.append(f"октетный стаффинг{где} (асинхронное HDLC/PPP 0x7E/0x7D, "
                                    f"SLIP 0xC0/0xDB): нет")
            # Кадры по контрольной сумме заголовка: GFP (G.7041) и ячейки ATM.
            кадры = gfp.найти(выборка)
            if кадры is None:
                ветвь.не_найдено.append(f"GFP (cHEC) и ячейки ATM (HEC){где}: нет")
                # Ethernet 64b/66b: синхрозаголовки 01/10, скремблер, кадры с верной FCS.
                кадры = pcs.найти(выборка)
                if кадры is None:
                    ветвь.не_найдено.append(f"Ethernet 64b/66b (10GBASE-R){где}: нет")
    if кадры is not None:
        ветвь.проверяемая(кадры, путь)
        if not кадры.дальше:
            return ветвь
        внутри = pakety.найти_в_кадрах(кадры.дальше)
        if внутри is not None:
            ветвь.проверяемая(внутри, _дальше(путь, "кадры"))
        else:
            _кадры_без_ip(ветвь, кадры.дальше, _дальше(путь, "кадры"), "кадрах")
        return ветвь

    # 2а. OTN (G.709): кадр 4 × 4080 по FAS, скремблер вслепую, MFAS, BIP-8, синдромы RS(255,239);
    #     нагрузка OPUk — дальше, как весь поток (GFP, SDH, …).
    оптика = otn.найти(выборка)
    if оптика is not None:
        ветвь.проверяемая(оптика, путь)
        if оптика.дальше is not None and len(оптика.дальше) >= 8192:
            ветвь.влить(_ступень(np.asarray(оптика.дальше, dtype=np.uint8), глубина,
                                 _дальше(путь, "нагрузка OPU"), б))
        return ветвь
    ветвь.не_найдено.append(f"OTN (G.709){где}: нет")

    # 3. SDH/SONET: кадр по A1 A2, скремблер по B1, VC по B3, TU-12 по V5, E1 по FAS;
    #    нагрузка VC и притоки разбираются так же, как весь поток.
    синхронная = sdh.найти(выборка)
    if синхронная is not None:
        ветвь.проверяемая(синхронная, путь)
        притоки = синхронная.дальше or {}
        for имя, ряд in list(притоки.items())[:ПРИТОКОВ_ГЛУБЖЕ]:
            ветвь.влить(_ступень(ряд, глубина, _дальше(путь, имя), б))
        if len(притоки) > ПРИТОКОВ_ГЛУБЖЕ:
            ветвь.ограничения.append(f"SDH{где}: глубже разобраны первые {ПРИТОКОВ_ГЛУБЖЕ} притоков "
                                     f"из {len(притоки)} — остальные выделяются по одному на странице")
        return ветвь
    ветвь.не_найдено.append(f"SDH/SONET (G.707){где}: нет")

    # 3а. PDH со стаффингом согласования скоростей — притоки разбираются так же.
    иерархия = pdh.найти(выборка)
    if иерархия is not None:
        ветвь.проверяемая(иерархия, путь)
        for номер, приток in иерархия.дальше.items():
            ветвь.влить(_ступень(приток, глубина, _дальше(путь, f"приток {номер}"), б))
        return ветвь
    ветвь.не_найдено.append(f"PDH E2/E3/E4 (G.742/G.751){где}: нет")

    # 3б. PDH Северной Америки: T1 (SF/ESF с CRC-6), DS2 (M12), DS3 (M23, C-bit parity).
    америка = pdh_na.найти(выборка)
    if америка is not None:
        ветвь.проверяемая(америка, путь)
        if америка.вид_дальше == "притоки":
            for номер, приток in америка.дальше.items():
                ветвь.влить(_ступень(приток, глубина, _дальше(путь, f"приток {номер}"), б))
        elif америка.дальше:
            _каналы(америка.дальше, ветвь, путь)
        return ветвь
    ветвь.не_найдено.append(f"PDH T1/DS2/DS3 (G.704, G.743, G.752){где}: нет")

    # 4. Цикл и каналы — и HDLC в каналах.
    цикл = cikl.найти(выборка)
    if цикл is not None:
        ветвь.проверяемая(цикл, путь)
        было = len(ветвь.находки)
        if цикл.дальше:
            _каналы(цикл.дальше, ветвь, путь)
        # В каналах ничего не нашлось — цикл не байтовый мультиплекс, а кадр
        # модема: служебные слова вырезаются, нагрузка разбирается дальше.
        if len(ветвь.находки) == было and цикл.свойства.get("длина"):
            _нагрузка_цикла(выборка, цикл, ветвь, глубина, путь, б)
        return ветвь
    ветвь.не_найдено.append(f"цикл и синхрослово{где}: нет")
    ветвь.оценка = 0.0
    return None if not ветвь.находки else ветвь


def _плоскости(выборка: np.ndarray, б: Бюджет, глубина: int, путь: str = ""
               ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Подбор модуляционной плоскости — сразу за демодулятором.

    На самом верху или в нагрузке кадра модема (служебные слова вырезаны,
    символы не сдвинулись), если плоскость на пути ещё не подбиралась. Если
    число бит на символ известно (или названо в имени файла: «8PSK»,
    «16QAM») — идёт первым; в глубоком профиле без подсказки пробуются
    КАМ-16, 64 и 256 — последними: это долго.
    """
    if "плоскост" in путь or not (глубина == 0 or путь.endswith("нагрузка цикла")):
        return []
    кам = б.символ or ((4, 6, 8) if б.глубоко and not б.фм else ())
    return [(f"модуляционная плоскость ФМ-{1 << k}", (lambda k=k: ploskost.найти_фм(выборка, k)),
             f"в плоскости ФМ-{1 << k}") for k in б.фм] + [
        (f"модуляционная плоскость КАМ-{1 << k}", (lambda k=k: ploskost.найти(выборка, k)),
         f"в плоскости КАМ-{1 << k}") for k in кам]


def _детекторы(выборка: np.ndarray, б: Бюджет, глубина: int = 1, путь: str = ""
               ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Детекторы преобразований — от дешёвых к дорогим: (имя, вызов, шаг пути)."""
    длинные = б.профиль["длинные"]
    плоскости = _плоскости(выборка, б, глубина, путь)
    известна = bool(б.символ or б.фм)
    return (плоскости if известна else []) + [
        ("кодирование в линии (манчестерский, 4B/5B, 8B/10B)", lambda: lineynye.найти(выборка),
         "после снятия кодирования в линии"),
        # Код произведения дёшев (~0,5 с) и доказывает себя сам (блоки без нарушений
        # после декодирования) — раньше скремблера: иначе тот «находится» сквозь код.
        ("код произведения (TPC)", lambda: tpc.найти(выборка), "после снятия кода произведения"),
        ("свёрточный 1/2 и короткий блочный код", lambda: kod.найти(выборка, длинные=False),
         "после снятия кода"),
        ("свёрточный код 1/3, 1/4", lambda: svyortka.найти(выборка), "после снятия кода"),
        ("турбокод 1/3", lambda: turbo.найти(выборка), "после турбодекодирования"),
        ("скремблер", lambda: skrembler.найти(выборка), "после снятия скремблера"),
        ("блочное перемежение над кодом", lambda: peremezhenie.найти(выборка),
         "после снятия перемежения и кода"),
    ] + ([
        ("свёрточное перемежение Форни (I × M)", lambda: forni.найти(
            выборка, I_до=б.профиль["форни"]["I_до"], M_до=б.профиль["форни"]["M_до"],
            бюджет=max(1.0, min(б.профиль["форни"]["бюджет"], б.конец - time.monotonic()))),
         "после снятия свёрточного перемежения"),
    ] if б.профиль.get("форни") else []) + [
        ("выколотый свёрточный код", lambda: vykalyvanie.найти(
            выборка, глубоко=б.глубоко, бюджет=max(1.0, min(60.0, б.конец - time.monotonic()))),
         "после снятия выколотого кода"),
        ("длинный блочный код (LDPC, Рида — Соломона, БЧХ)", lambda: dlinnye.найти(
            выборка, до=длинные["до"],
            бюджет=max(1.0, min(длинные["бюджет"], б.конец - time.monotonic()))),
         "после снятия кода"),
    ] + ([] if известна else плоскости)


def _варианты(найдено: Находка) -> List[tuple[Находка, np.ndarray]]:
    """Находка → (находка, снятый ряд); у манчестерского — по варианту на толкование."""
    if найдено.вид_дальше == "варианты":
        return [(Находка(**{**найдено.__dict__, "что": f"{найдено.что}, {вариант}",
                           "дальше": ряд, "вид_дальше": "биты"}), ряд)
                for вариант, ряд in найдено.дальше.items()]
    if найдено.дальше is not None and len(найдено.дальше):
        return [(найдено, np.asarray(найдено.дальше, dtype=np.uint8))]
    return [(найдено, np.zeros(0, dtype=np.uint8))]


