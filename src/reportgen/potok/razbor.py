# -*- coding: utf-8 -*-
"""Слепой разбор по уровням — перебором гипотез: от линии до пакетов.

Поток неизвестен, и неизвестно, на каком он этапе: сразу за демодулятором
(кодирование в линии, помехоустойчивый код), после снятия кода (скремблер,
цикл), на канальном уровне (HDLC, стаффинг) или уже пакеты. Поэтому уровни
не задаются, а пробуются, и не одной цепочкой, а деревом:

- **проверяемые находки** — пакеты IP (контрольные суммы), MPEG-TS и код
  DVB (синдромы), HDLC (FCS), PDH (FAS в каждом притоке), цикл с
  синхрословом — сами себя доказывают и завершают ветвь;
- **преобразования** — кодирование в линии, свёрточные коды любой скорости и
  выколотые, турбокод, короткие и длинные блочные (LDPC, РС, БЧХ),
  перемежение, скремблер — собираются на уровне ВСЕ, и каждое снимается и
  разбирается дальше. Какое верное, решает то, что открылось под ним:
  ветвь, приведшая к проверяемой находке, весит больше ветви, приведшей в
  пустоту. Остальные ветви не пропадают — в отчёте они в разделе «ДРУГИЕ
  ГИПОТЕЗЫ» с оценкой.

Всё, что проверено и НЕ найдено, тоже записывается: без этого вывод
«структуры нет» неотличим от «не смотрели».

Разбор ограничен по времени и глубине; «глубокий» разбор (команда
``reportgen potok --глубоко``) снимает часть ограничений: длинные коды до
2048 бит, выколотые коды до 7/8 со всеми материнскими.

Ручное управление: ``снять`` — список слоёв, которые аналитик уже знает
(«скремблер 3,20», «свёрточный 171/133 K=7», «манчестер»…); они снимаются
первыми, дальше — вслепую.
"""

