# -*- coding: utf-8 -*-
"""Слепой разбор по уровням: от кода до пакетов.

Поток неизвестен, поэтому уровни не задаются, а пробуются. На каждом шаге
детекторы идут от дешёвого к дорогому: пакеты и MPEG-TS, HDLC, цикл, код,
скремблер. Найденное преобразование — снятый код или скремблер — даёт
новый поток, и разбор повторяется уже на нём: так складывается цепочка
«свёрточный код → скремблер V.35 → HDLC → IPv4/UDP». Глубина цепочки
ограничена: каждый уровень — это время, а поток в сто мегабайт анализу не
ждёт.

Всё, что проверено и НЕ найдено, тоже записывается. Без этого вывод
«структуры нет» неотличим от «не смотрели», а модель, толкующая отчёт,
должна знать разницу.
"""

from __future__ import annotations

import time
from dataclasses import dataclass, field
from pathlib import Path
from typing import List, Optional

import numpy as np

from . import cikl, hdlc, kod, pakety, skrembler
from .bity import в_байты, в_биты
from .chtenie import Поток, прочитать
from .nahodka import Находка
from .statistika import Статистика, посчитать

#: Сколько уровней преобразований (код, скремблер) снимать подряд.
ГЛУБИНА = 3
#: Сколько бит потока смотреть на каждом уровне: разбор — по выборке,
#: а не по всем ста мегабайтам.
ВЫБОРКА_БИТ = 1 << 23
#: Сколько каналов мультиплексора разбирать глубже.
КАНАЛОВ_ГЛУБЖЕ = 32


@dataclass
class Разбор:
    поток: Поток
    статистика: Статистика
    находки: List[Находка] = field(default_factory=list)
    не_найдено: List[str] = field(default_factory=list)
    ограничения: List[str] = field(default_factory=list)
    секунд: float = 0.0

    def отчёт(self, предел: int = 7000) -> str:
        return собрать_отчёт(self, предел)


def _ступень(биты: np.ndarray, глубина: int, разбор: Разбор, путь: str) -> None:
    """Разобрать битовый ряд на этом уровне и, если нашлось преобразование, — глубже."""
    выборка = биты[:ВЫБОРКА_БИТ]
    где = f" ({путь})" if путь else ""

    # 1. Пакеты прямо в байтах этого ряда и транспортный поток.
    байты = в_байты(выборка)
    for найти, имя in ((pakety.найти_в_потоке, "пакеты IP подряд"),
                       (kod.mpeg_ts, "MPEG-TS")):
        найдено = найти(байты)
        if найдено is not None:
            разбор.находки.append(_с_путём(найдено, путь))
            return
    разбор.не_найдено.append(f"пакеты IP подряд и MPEG-TS{где}: нет")

    # 2. HDLC — и сразу пакеты в его кадрах.
    кадры = hdlc.найти(выборка)
    if кадры is not None:
        разбор.находки.append(_с_путём(кадры, путь))
        внутри = pakety.найти_в_кадрах(кадры.дальше)
        if внутри is not None:
            разбор.находки.append(_с_путём(внутри, путь + " → кадры HDLC" if путь
                                           else "кадры HDLC"))
        else:
            разбор.не_найдено.append("IP в кадрах HDLC: нет — кадры несут другой протокол")
        return
    разбор.не_найдено.append(f"HDLC{где}: флагов с верной FCS нет")

    # 3. Цикл и каналы — и HDLC в каналах.
    цикл = cikl.найти(выборка)
    if цикл is not None:
        разбор.находки.append(_с_путём(цикл, путь))
        if цикл.дальше:
            _каналы(цикл.дальше, разбор, путь)
        return
    разбор.не_найдено.append(f"цикл и синхрослово{где}: нет")

    if глубина >= ГЛУБИНА:
        разбор.ограничения.append(f"разбор остановлен на глубине {глубина}{где}")
        return

    # 4. Помехоустойчивый код — снять и разбирать дальше.
    код = kod.найти(выборка)
    if код is not None:
        разбор.находки.append(_с_путём(код, путь))
        _ступень(код.дальше, глубина + 1, разбор,
                 (путь + " → " if путь else "") + "после снятия кода")
        return
    разбор.не_найдено.append(f"помехоустойчивый код{где}: нет (блочные n ≤ 16 и "
                             f"свёрточные 1/2, K ≤ 9 — устойчиво к ошибкам; длинные "
                             f"блочные — только без ошибок)")

    # 5. Скремблер — снять и разбирать дальше.
    скр = skrembler.найти(выборка)
    if скр is not None:
        разбор.находки.append(_с_путём(скр, путь))
        _ступень(скр.дальше, глубина + 1, разбор,
                 (путь + " → " if путь else "") + "после снятия скремблера")
        return
    разбор.не_найдено.append(f"скремблер{где}: нет (самосинхронизирующиеся до степени 64 "
                             f"с 1–2 отводами, известные стандарты, аддитивные ПСП)")


def _каналы(каналы: dict, разбор: Разбор, путь: str) -> None:
    """В каналах мультиплексора — HDLC и IP в нём."""
    for номер in sorted(каналы)[:КАНАЛОВ_ГЛУБЖЕ]:
        ряд = каналы[номер]
        if len(ряд) < 4096:
            continue
        кадры = hdlc.найти(ряд)
        if кадры is None:
            continue
        канал = (путь + " → " if путь else "") + f"КИ{номер}"
        разбор.находки.append(_с_путём(кадры, канал))
        внутри = pakety.найти_в_кадрах(кадры.дальше)
        if внутри is not None:
            разбор.находки.append(_с_путём(внутри, канал + " → кадры HDLC"))


def _с_путём(находка: Находка, путь: str) -> Находка:
    if путь:
        находка.что = f"{находка.что} — в потоке {путь}"
    return находка


def разобрать(путь: str | Path | None = None, *, данные: bytes | None = None,
              имя: str = "") -> Разбор:
    """Разобрать поток из файла или из байтов."""
    начало = time.monotonic()
    поток = прочитать(путь, данные=данные, имя=имя)
    разбор = Разбор(поток=поток, статистика=посчитать(поток.данные))

    # .Sig: сперва сами пакеты — может, это уже IP.
    if поток.пакеты:
        тела = [поток.пакет(номер) for номер in range(min(len(поток.пакеты), 20000))]
        внутри = pakety.найти_в_кадрах(тела, "пакетов файла")
        if внутри is not None:
            разбор.находки.append(внутри)
        else:
            разбор.не_найдено.append("IP в пакетах .Sig: нет — разбираем тела пакетов "
                                     "подряд как поток")
    if not разбор.находки:
        _ступень(в_биты(поток.данные[:ВЫБОРКА_БИТ // 8]), 0, разбор, "")
        # Порядок бит в байте: для детекторов битового уровня (цикл, код,
        # скремблер) пробуем и «младшим битом вперёд», если прямой ничего не дал.
        if not разбор.находки:
            разбор.не_найдено.append("всё выше — при порядке «старший бит байта первым»; "
                                     "повторено при порядке «младший бит первым»")
            _ступень(в_биты(поток.данные[:ВЫБОРКА_БИТ // 8], "младший"), 0, разбор,
                     "младший бит первым")
    if len(поток.данные) * 8 > ВЫБОРКА_БИТ:
        разбор.ограничения.append(
            f"битовые уровни разобраны по первым {ВЫБОРКА_БИТ // 8 // (1 << 20)} МБ "
            f"из {len(поток.данные) / (1 << 20):.1f} МБ; статистика — по всему файлу")
    разбор.секунд = time.monotonic() - начало
    return разбор


def собрать_отчёт(разбор: Разбор, предел: int = 7000) -> str:
    """Отчёт для модели и для человека: сперва найденное, потом проверенное впустую."""
    с = разбор.статистика
    п = разбор.поток
    строки = [
        f"### РАЗБОР ПОТОКА «{п.имя}» — анализатор системы, не модель",
        f"Файл: {п.формат}.",
        f"Общее: {с.байт} байт; энтропия {с.энтропия:.3f} бит/байт; единиц "
        f"{с.единиц * 100:.2f} %; самые длинные серии — нулей {с.серия_нулей}, "
        f"единиц {с.серия_единиц}. {с.вывод().capitalize()}.",
    ]
    if с.частые:
        строки.append("Частые байты: " + ", ".join(
            f"0x{байт:02X} ({доля * 100:.1f} %)" for байт, доля in с.частые[:5]) + ".")
    if с.повторы:
        строки.append("Повторяющиеся слова с постоянным шагом: " + "; ".join(
            f"{слово} через {шаг} байт ({доля * 100:.0f} % повторов)"
            for слово, шаг, доля in с.повторы) + ".")
    строки += [f"Заметка: {заметка}" for заметка in п.заметки]
    строки.append("")
    if разбор.находки:
        строки.append("НАЙДЕНО (уверенность — проверяемая мера, указана в скобках):")
        for номер, находка in enumerate(разбор.находки, start=1):
            строки.append(f"{номер}. {находка.строка()}")
            строки += [f"   - {строка}" for строка in находка.подробно]
    else:
        строки.append("НАЙДЕНО: ничего с достаточной уверенностью.")
    if разбор.не_найдено:
        строки.append("")
        строки.append("ПРОВЕРЕНО И НЕ НАЙДЕНО:")
        строки += [f"- {строка}" for строка in разбор.не_найдено]
    if разбор.ограничения:
        строки.append("")
        строки.append("ОГРАНИЧЕНИЯ РАЗБОРА:")
        строки += [f"- {строка}" for строка in разбор.ограничения]
    строки.append("")
    строки.append(f"Разбор занял {разбор.секунд:.1f} с. Числа и выводы выше получены "
                  f"вычислением по потоку; толкуй их по стандартам библиотеки, не "
                  f"пересчитывай и не домысливай уровни, которых здесь нет.")
    текст = "\n".join(строки)
    if len(текст) > предел:
        текст = текст[:предел - 60].rsplit("\n", 1)[0] + "\n… (отчёт сокращён по объёму)"
    return текст
