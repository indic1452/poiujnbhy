def разобрать(путь: str | Path | None = None, *, данные: bytes | None = None,
              имя: str = "", глубоко: bool = False, снять: Sequence[str] = (),
              профиль: str = "быстро", ход: Optional[Callable[[str], None]] = None,
              этап: Optional[Callable[[Находка], None]] = None,
              символ: Sequence[int] = (), фм: Sequence[int] = ()) -> Разбор:
    """Разобрать поток из файла или из байтов. ``глубоко`` — то же, что профиль «глубоко».

    ``ход`` получает строки о том, что пробуется сейчас; ``этап`` — каждую
    находку итоговой цепочки по мере того, как она складывается.
    """
    начало = time.monotonic()
    настройки = ПРОФИЛИ["глубоко" if глубоко else профиль]
    б = Бюджет(конец=начало + настройки["время"], профиль=настройки, ход=ход, этап=этап,
               символ=tuple(int(k) for k in символ if 2 <= int(k) <= 12 and int(k) % 2 == 0),
               фм=tuple(int(k) for k in фм if 1 <= int(k) <= 6))
    _ТЕКУЩИЙ.бюджет = б
    try:
        return _разобрать(путь, данные, имя, снять, б, начало)
    finally:
        _ТЕКУЩИЙ.бюджет = None


def _содержимое(биты: np.ndarray, где: str) -> List[str]:
    """Что узнаётся в потоке само по себе: файлы, имена файлов, адреса, текст."""
    from . import poisk  # noqa: PLC0415
    итог = []
    for ф in poisk.сигнатуры(биты, любой_сдвиг=True, инверсия=True, предел=40):
        итог.append(f"{где}: {ф['что']} (.{ф['расширение']}) с бита {ф['бит']}"
                    + (" — поток инверсный" if ф["инверсия"] else "")
                    + (f", длина {ф['длина']} байт" if ф["длина"] else ", длина не определяется"))
    текст = poisk.строки(биты[:1 << 23], наименьшая=10, сдвиги=range(8), инверсия=True, предел=300)
    if текст["имена_файлов"]:
        имена = list(dict.fromkeys(и["имя"] for и in текст["имена_файлов"]))
        итог.append(f"{где}: имена файлов — " + ", ".join(имена[:15]))
    if текст["адреса"]:
        адреса = list(dict.fromkeys(а["адрес"] for а in текст["адреса"]))
        итог.append(f"{где}: адреса — " + ", ".join(адреса[:15]))
    длинные = sorted(текст["строки"], key=lambda с: -с["длина"])[:5]
    for с in длинные:
        итог.append(f"{где}: текст ({с['кодировка']}) с бита {с['бит']}"
                    + (" (инверсно)" if с["инверсия"] else "") + f": «{с['текст'][:120]}»")
    return итог


def _разобрать(путь, данные, имя, снять, б: "Бюджет", начало: float) -> Разбор:
    поток = прочитать(путь, данные=данные, имя=имя)
    разбор = Разбор(поток=поток, статистика=посчитать(поток.данные))
    if not (б.символ or б.фм):
        # Модуляция в имени файла («…_8PSK_…», «QPSK.bin») — подсказка аналитика.
        название = имя or (Path(путь).name if путь else "")
        кам, фм = ploskost.модуляции(название, числа=False)
        if кам or фм:
            б.символ, б.фм = tuple(кам), tuple(фм)
            разбор.ограничения.append(
                "модуляция взята из имени файла: " + ", ".join(
                    [f"ФМ-{1 << k}" for k in фм] + [f"КАМ-{1 << k}" for k in кам])
                + " — подбор плоскости идёт первым")

    разбор.карта = karta.описать(поток.данные[:64 << 20])
    захват = karta.pcap(поток.данные)
    if захват is not None:
        канал, пакеты = захват
        внутри = pakety.найти_в_кадрах(пакеты, f"пакетов pcap ({канал})")
        if внутри is not None:
            разбор.находки.append(внутри)
        else:
            ветвь = Ветвь()
            _кадры_без_ip(ветвь, пакеты, "", f"пакетах pcap ({канал})")
            разбор.находки += ветвь.находки
            разбор.не_найдено += ветвь.не_найдено
        разбор.секунд = time.monotonic() - начало
        return разбор

    # .Sig: сперва сами пакеты — может, это уже IP или известный формат.
    if поток.пакеты and not снять:
        тела = [поток.пакет(номер) for номер in range(min(len(поток.пакеты), 20000))]
        внутри = pakety.найти_в_кадрах(тела, "пакетов файла")
        if внутри is not None:
            разбор.находки.append(внутри)
        else:
            формат = polya.найти(тела, "пакетов файла")
            if формат is not None:
                разбор.находки.append(формат)
            разбор.не_найдено.append("IP в пакетах .Sig: нет — разбираем тела пакетов "
                                     "подряд как поток")
    if not any(н.уровень == "сетевой" for н in разбор.находки):
        биты = в_биты(поток.данные[:ВЫБОРКА_БИТ // 8])
        путь_ = ""
        for указание in снять:
            биты, запись = снять_вручную(биты, указание)
            разбор.находки.append(_с_путём(запись, путь_))
            путь_ = _дальше(путь_, указание.strip())
        ветвь = _ступень(биты, 0, путь_, б)
        # Порядок бит в байте: если прямой ничего не дал — «младшим битом вперёд».
        if not ветвь.находки and not снять:
            ветвь.не_найдено.append("всё выше — при порядке «старший бит байта первым»; "
                                    "повторено при порядке «младший бит первым»")
            обратная = _ступень(в_биты(поток.данные[:ВЫБОРКА_БИТ // 8], "младший"), 0,
                                "младший бит первым", б)
            ветвь.не_найдено += обратная.не_найдено
            ветвь.находки += обратная.находки
            ветвь.ограничения += обратная.ограничения
            ветвь.другие += обратная.другие
        разбор.находки += ветвь.находки
        разбор.не_найдено += ветвь.не_найдено
        разбор.ограничения += ветвь.ограничения
        разбор.другие += ветвь.другие
    # Содержимое: файлы по сигнатурам (при любом сдвиге и в инверсии), имена
    # файлов, адреса, текст — на входе и в потоке после цепочки.
    try:
        б.сказать("ищу файлы по сигнатурам, строки и имена файлов")
        разбор.содержимое = _содержимое(в_биты(поток.данные[:ВЫБОРКА_БИТ // 8]), "на входе")
        последний = next((н for н in reversed(разбор.находки)
                          if н.вид_дальше == "биты" and н.дальше is not None and len(н.дальше)), None)
        if последний is not None:
            разбор.содержимое += _содержимое(последний.дальше, f"после «{последний.суть}»")
    except Exception as ошибка:           # noqa: BLE001 — поиск содержимого не роняет разбор
        разбор.ограничения.append(f"поиск содержимого прерван: {ошибка}")
    if len(поток.данные) * 8 > ВЫБОРКА_БИТ:
        разбор.ограничения.append(
            f"битовые уровни разобраны по первым {ВЫБОРКА_БИТ // 8 // (1 << 20)} МБ "
            f"из {len(поток.данные) / (1 << 20):.1f} МБ; статистика и карта — по всему файлу")
    if б.этап is not None:
        for находка in разбор.находки:
            б.этап(находка)
    if б.исчерпан:
        разбор.ограничения.append(
            f"время разбора ({б.конец - начало:.0f} с) исчерпано — часть гипотез не проверена"
            + ("" if б.глубоко else "; глубокий разбор: reportgen potok --глубоко"))
    разбор.секунд = time.monotonic() - начало
    return разбор


def этапы(разбор: Разбор) -> List[dict]:
    """Итоговая цепочка — этапами для страницы: что, мера, подробно, альтернативы."""
    итог = []
    for номер, находка in enumerate(разбор.находки, start=1):
        дальше = находка.дальше
        выход = ""
        if находка.вид_дальше == "биты" and дальше is not None:
            выход = f"{len(дальше)} бит"
        elif находка.вид_дальше in ("кадры", "пакеты") and дальше is not None:
            выход = f"{len(дальше)} {'кадров' if находка.вид_дальше == 'кадры' else 'пакетов'}"
        elif находка.вид_дальше == "притоки" and дальше:
            выход = f"{len(дальше)} притока"
        ключ = (находка.путь or "поток") + ":"
        итог.append({
            "номер": номер, "уровень": находка.уровень, "что": находка.суть,
            "путь": находка.путь, "уверенность": round(float(находка.уверенность), 3),
            "мера": находка.мера, "подробно": list(находка.подробно), "выход": выход,
            "альтернативы": [с[len(ключ):].strip() for с in разбор.другие if с.startswith(ключ)],
        })
    return итог


def _сгруппировать(находки: List[Находка]) -> List[List[Находка]]:
    """Одинаковые находки подряд (притоки, каналы) — в одну строку отчёта.

    Четыре притока E2 с одинаковым E1 внутри — это одна мысль, а не четыре
    экрана текста: отчёт ограничен по объёму, и повторы вытеснили бы главное.
    """
    группы: List[List[Находка]] = []
    for находка in находки:
        ключ = (находка.уровень, находка.суть)
        for группа in группы:
            if (группа[0].уровень, группа[0].суть) == ключ:
                группа.append(находка)
                break
        else:
            группы.append([находка])
    return группы


def собрать_отчёт(разбор: Разбор, предел: int = 7000) -> str:
    """Отчёт для модели и для человека: сперва найденное, потом проверенное впустую."""
    с = разбор.статистика
    п = разбор.поток
    строки = [
        f"### РАЗБОР ПОТОКА «{п.имя}» — анализатор системы, не модель",
        f"Файл: {п.формат}.",
        f"Общее: {с.байт} байт; энтропия {с.энтропия:.3f} бит/байт; единиц "
        f"{с.единиц * 100:.2f} %; самые длинные серии — нулей {с.серия_нулей}, "
        f"единиц {с.серия_единиц}. {с.вывод().capitalize()}.",
    ]
    if с.частые:
        строки.append("Частые байты: " + ", ".join(
            f"0x{байт:02X} ({доля * 100:.1f} %)" for байт, доля in с.частые[:5]) + ".")
    if с.повторы:
        строки.append("Повторяющиеся слова с постоянным шагом: " + "; ".join(
            f"{слово} через {шаг} байт ({доля * 100:.0f} % повторов)"
            for слово, шаг, доля in с.повторы) + ".")
    строки += [f"Заметка: {заметка}" for заметка in п.заметки]
    if разбор.карта is not None:
        строки.append(f"Карта файла: {разбор.карта.что}.")
        строки += [f"   - {строка}" for строка in разбор.карта.подробно]
    if разбор.содержимое:
        строки.append("ФАЙЛЫ И ТЕКСТ В ПОТОКЕ:")
        строки += [f"   - {строка}" for строка in разбор.содержимое]
    строки.append("")
    if разбор.находки:
        строки.append("НАЙДЕНО (уверенность — проверяемая мера, указана в скобках):")
        for номер, группа in enumerate(_сгруппировать(разбор.находки), start=1):
            первая = группа[0]
            строки.append(f"{номер}. {первая.строка()}")
            строки += [f"   - {строка}" for строка in первая.подробно]
            if len(группа) > 1:
                строки.append(f"   - то же ещё в {len(группа) - 1}: " + "; ".join(
                    f"{н.путь or 'основном потоке'} ({round(н.уверенность * 100)} %: {н.мера})"
                    for н in группа[1:]))
    else:
        строки.append("НАЙДЕНО: ничего с достаточной уверенностью.")
    if разбор.другие:
        строки.append("")
        строки.append("ДРУГИЕ ГИПОТЕЗЫ (проверены и отвергнуты в пользу найденного или "
                      "не разобраны):")
        строки += [f"- {строка}" for строка in разбор.другие[:12]]
    if разбор.не_найдено:
        строки.append("")
        строки.append("ПРОВЕРЕНО И НЕ НАЙДЕНО:")
        строки += [f"- {строка}" for строка in разбор.не_найдено]
    if разбор.ограничения:
        строки.append("")
        строки.append("ОГРАНИЧЕНИЯ РАЗБОРА:")
        строки += [f"- {строка}" for строка in разбор.ограничения]
    строки.append("")
    строки.append(f"Разбор занял {разбор.секунд:.1f} с. Числа и выводы выше получены "
                  f"вычислением по потоку; толкуй их по стандартам библиотеки, не "
                  f"пересчитывай и не домысливай уровни, которых здесь нет.")
    текст = "\n".join(строки)
    if len(текст) > предел:
        текст = текст[:предел - 60].rsplit("\n", 1)[0] + "\n… (отчёт сокращён по объёму)"
    return текст
