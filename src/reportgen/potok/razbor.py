def _аддитивный_вручную(биты: np.ndarray, слова: str) -> tuple[np.ndarray, List[str]]:
    """«аддитивный [отводы a,b,…] [кадр N [начальное СЛОВО] [пропуск P] [начало S]]».

    Без «кадр» — непрерывная ПСП (восстанавливается по паузе); с «кадр» —
    сброс в начальное состояние в каждом кадре: не задано начальное — оно
    ищется по устойчивым столбцам, не заданы отводы — и они (Берлекэмп — Мэсси).
    """
    отводы_ = re.search(r"отвод\w*\s+([\d\s,]+)", слова)
    отводы = tuple(int(ч) for ч in re.findall(r"\d+", отводы_.group(1))) if отводы_ else ()
    длина = _число_после(слова, "кадр")
    if длина is None:
        if not отводы:
            raise ValueError("аддитивный: нужны отводы («аддитивный отводы 14,15») или длина "
                             "кадра («аддитивный кадр 1000») для скремблера со сбросом")
        найдено = skrembler.аддитивный(биты, отводы)
        if найдено is None:
            raise ValueError("ПСП не восстановилась: в потоке нет паузы (нулей, единиц, "
                             "флагов HDLC) — если скремблер сбрасывается в кадре, укажите «кадр N»")
        мера, ряд, место, заполнение = найдено
        return ряд, [f"ПСП {skrembler.полином_словами(отводы)} восстановлена по паузе "
                     f"(заполнение — {заполнение}) с бита {место}"]
    пропуск = _число_после(слова, "пропуск") or 0
    # «начало N», но не «начальное …»: иначе началом станет само состояние.
    начало = _число_после(слова, r"начало\b") or 0
    if not 0 <= пропуск < длина:
        raise ValueError("пропуск должен быть меньше длины кадра")
    нач_ = re.search(r"начальн\w*\s+(\S+)", слова)
    if нач_:
        from . import sinhro  # noqa: PLC0415
        if not отводы:
            raise ValueError("с начальным состоянием нужны и отводы")
        начальное = sinhro.слово(нач_.group(1))
        if len(начальное) < max(отводы):
            raise ValueError(f"начальное состояние — не меньше {max(отводы)} бит (степень полинома)")
        способ = "начальное состояние задано"
    else:
        найдено = skrembler.найти_по_кадру(биты, длина, начало=начало, пропуск=пропуск,
                                           отводы=отводы or None)
        if найдено is None and not пропуск:
            # Заполнение не постоянное (флаги HDLC в каждом кадре в своей фазе) —
            # ЛРП по окнам с разложением на ПСП и заполнение, иначе маска по заполнению.
            блочная = skrembler.по_блоку(биты[начало:], длина)
            if блочная is not None and (not отводы or блочная.свойства.get("отводы") == list(отводы)):
                return блочная.дальше, [f"{блочная.что} — {блочная.мера}"] + блочная.подробно
        if найдено is None:
            raise ValueError("ПСП со сбросом по кадру не восстановилась: мало устойчивых "
                             "столбцов, и по заполнению (флаги, нули, единицы) тоже нет "
                             "(проверьте длину кадра и начало — поток должен быть "
                             "засинхронизирован)")
        отводы = tuple(найдено["отводы"])
        начальное = np.array([int(c) for c in найдено["начальное"]], dtype=np.uint8)
        способ = f"{найдено['способ']}; устойчивых столбцов после снятия — нули в " \
                 f"{найдено['совпало'] * 100:.1f} %"
    ряд = skrembler.снять_по_кадру(биты, отводы, начальное, длина, пропуск, начало)
    return ряд, [f"кадровый аддитивный скремблер {skrembler.полином_словами(отводы)}, сброс в "
                 f"каждом кадре {длина} бит (с бита {начало}, первые {пропуск} бит кадра не "
                 f"скремблированы)",
                 f"начальное состояние (первые {max(отводы)} бит ПСП после сброса): "
                 f"{''.join(map(str, начальное[:max(отводы)].tolist()))}; {способ}"]


def _кратко(указание: str) -> str:
    """Длинные перечни позиций в указании — сжато, чтобы заголовок этапа читался:
    подряд идущие — диапазоном, а если и так длинно — начало, конец и сколько всего."""
    def сжать(м: "re.Match[str]") -> str:
        числа = [int(ч) for ч in re.findall(r"\d+", м.group(0))]
        части, начало = [], 0
        for i in range(1, len(числа) + 1):
            if i == len(числа) or числа[i] != числа[i - 1] + 1:
                части.append(str(числа[начало]) if i - 1 == начало else f"{числа[начало]}-{числа[i - 1]}")
                начало = i
        текст = ",".join(части)
        if len(части) > 8:
            текст = f"{','.join(части[:3])} … {части[-1]} ({len(числа)} позиций)"
        return текст
    return re.sub(r"\d+(?:\s*,\s*\d+){8,}", сжать, указание)


def _позиции(текст: str) -> List[int]:
    """«23-40, 45» → [23, …, 40, 45]."""
    итог: List[int] = []
    for a, b, одна in re.findall(r"(\d+)\s*[-–]\s*(\d+)|(\d+)", текст):
        итог += [int(одна)] if одна else list(range(int(a), int(b) + 1))
    return итог


def _стаффинг_вручную(биты: np.ndarray, слова: str) -> tuple:
    """«стаффинг период N [сдвиг S] данные … управление … возможность … [знак ±] [полярность 0]
    [управление … возможность … …]» — приток мультиплекса со стаффингом.

    Правил может быть несколько (каждое начинается словом «управление»), у
    правила — несколько мест возможности: «возможность 190,191 знак +» или со
    знаком у каждого места: «возможность 190+,195−».
    """
    части = re.split(r"(?<!\w)(?=управл)", слова)
    голова, куски = части[0], части[1:]
    период = _число_после(голова, "период")
    if not период:
        raise ValueError("стаффинг: нужен период кадра — «стаффинг период N …»")
    м = re.search(r"(?<!\w)данн\w*\s+([\d\s,\-–]+)", голова)
    данные = _позиции(м.group(1)) if м else []
    if not данные or not куски:
        raise ValueError("стаффинг: нужны «данные …» и хотя бы одно «управление … возможность … знак ±»")
    правила = []
    for кусок in куски:
        управление = _позиции(re.match(r"управл\w*\s+([\d\s,\-–]*)", кусок).group(1))
        общий = re.search(r"(?<!\w)знак\w*\s+([+\-−])", кусок)
        полярность = _число_после(кусок, "полярн")
        м = re.search(r"(?<!\w)возможн\w*\s+((?:\d+\s*(?:[-–]\s*\d+|[+\-−])?[\s,]*)+)", кусок)
        if not управление or not м:
            raise ValueError("стаффинг: у правила нужны «управление …» и «возможность …»")
        места = []
        for a, b, одна, знак in re.findall(r"(\d+)\s*[-–]\s*(\d+)|(\d+)\s*([+\-−])?", м.group(1)):
            позиции = [int(одна)] if одна else list(range(int(a), int(b) + 1))
            знак = знак or (общий.group(1) if общий else "")
            if not знак:
                raise ValueError("стаффинг: у места возможности нет знака — «знак +|−» или «190+»")
            места += [(п, знак) for п in позиции]
        правила.append(stafing.правило(управление, места, 1 if полярность is None else полярность))
    ряд, сводка = stafing.разуплотнить_по_правилам(биты, период, _число_после(голова, r"сдвиг\b") or 0,
                                                  данные, правила)
    подробно = [f"приток: {сводка['данных_в_кадре']} бит данных в кадре {период} бит, "
                f"всего бит в кадре от {сводка['бит_в_кадре']['от']} до {сводка['бит_в_кадре']['до']} "
                f"(в среднем {сводка['бит_в_кадре']['среднее']:g})"]
    for п, св in zip(правила, сводка["правила"]):
        знаки = {з for _, з in п["возможности"]}
        вид = ("положительный" if знаки == {"+"} else "отрицательный" if знаки == {"−"}
               else "положительный и отрицательный")
        подробно.append(
            f"управление {', '.join(map(str, п['управление']))} (большинство из {len(п['управление'])}, "
            f"несогласных кадров {св['несогласных'] * 100:.2f} %): стаффинг {вид} в "
            f"{св['доля_стаффинга'] * 100:.1f} % кадров, мест {св['мест']}: "
            + ", ".join(f"{м}{з}" for м, з in п["возможности"]))
    return ряд, подробно


def снять_вручную(биты: np.ndarray, указание: str) -> tuple[np.ndarray, Находка]:
    """Снять слой, который аналитик уже знает. Возвращает ряд и запись для отчёта.

    Многочлены свёрточных кодов — в записи стандартов (171/133); «свёрточный g0/g1/g2 K=7
    кольцо 40» — блоки по 40 бит с циклическим хвостом (LTE).

    Понимает: «инверсия», «сдвиг N», «nrzi», «накопление» (дифференциальный кодер —
    обратное к nrzi), «манчестер», «4b5b», «8b10b», «bbframe» (DVB-S2 после LDPC: БЧХ,
    скремблер BB, поля данных), «скремблер a,b…»,
    «свёрточный g1/g2[/g3] K=k», «выколотый g1/g2 K=k шаблон 1101…»,
    «перемежение R n», «форни I M [фаза]», «pdh E2|E3|E4 приток N»,
    «плоскость k [вариант]», «v110» (данные пользователя V.110), «trau» (данные из кадров TRAU через V.110); битовые операции: «синхро СЛОВО [ошибок e]»
    (поток с первой синхрокомбинации), «кадры СЛОВО длина N [ошибок e]»
    (кадры, выровненные каждый по своей синхрокомбинации), «реверс [N]»,
    «xor СЛОВО», «прореживание k [фаза f]»; «ldpc ИМЯ [выколоты a-b,…]
    [укорочены a-b,…] [начало N] [итераций K]» — LDPC по загруженной матрице;
    «фм k [поворот r] [отражение] [натуральный] [биты 2-0-1]» — плоскость ФМ (без
    параметров — лучший вариант перебором); «tpc [строка N] [начало o] [столбец M]
    [блок b] [глубина n3] [плоскость p] [двумерный|трёхмерный] [кадр L [строк R]]» — код
    произведения (в кадрах модема — строки от начала каждого кадра); «метки k: …» — перестановка
    меток символа; «биты символа k: …» — перестановка бит внутри символа;
    «аддитивный [отводы a,b,…] [кадр N [начальное СЛОВО] [пропуск P]]» —
    аддитивная ПСП, непрерывная или со сбросом в каждом кадре (блоке кода: при
    флагах в паузах — по окнам заполнения); «стаффинг период N
    данные … управление … возможность K знак +|−» — приток мультиплекса со стаффингом.
    """
    слова = указание.strip().lower()
    вид = слова.split()[0] if слова else ""
    числа = [int(ч) for ч in re.findall(r"\d+", слова)]
    подробно: List[str] = []
    if вид == "инверсия":
        ряд = инвертировать(биты)
    elif вид == "сдвиг":
        ряд = биты[числа[0]:]
    elif вид in ("nrzi", "дифференциальное", "дифференциальный"):
        ряд = lineynye.nrzi(биты)
    elif вид.startswith("накоплен") or вид in ("дифкодер", "nrzi-код"):
        # Обратное к nrzi: бит — сумма по модулю 2 всех бит до него (дифференциальный кодер).
        ряд = np.bitwise_xor.accumulate(биты.astype(np.uint8))
        подробно.append("накопление по модулю 2 (дифференциальный кодер): y[i] = y[i−1] ⊕ x[i]")
    elif вид in ("4b5b", "4b/5b"):
        найдено = lineynye.код_4b5b(биты)
        if найдено is None:
            raise ValueError("4B/5B: разрешённых символов меньше 99 % ни при одном выравнивании")
        ряд = найдено.дальше
        подробно += [f"{найдено.что}: {найдено.мера}"] + list(найдено.подробно)
    elif вид in ("8b10b", "8b/10b"):
        найдено = lineynye.код_8b10b(биты)
        if найдено is None or найдено.дальше is None:
            raise ValueError("8B/10B: запятая K28.5 не найдена или таблица кода с потоком не сошлась")
        ряд = найдено.дальше
        подробно += [f"{найдено.что}: {найдено.мера}"] + list(найдено.подробно)
    elif вид in ("bbframe", "dvb-s2", "dvbs2"):
        # DVB-S2 после LDPC: слова БЧХ (исправление), скремблер BB, поля данных BBFRAME подряд.
        найдено_код = dvbs2.длина_слова(np.asarray(биты, dtype=np.uint8))
        if найдено_код is None:
            raise ValueError("DVB-S2: BBHEADER с верной CRC-8 в начале слов БЧХ не найден ни при одной длине")
        кадры_ = dvbs2.снять(np.asarray(биты, dtype=np.uint8), найдено_код[0], кадров=len(биты))
        поля = [п for з, п in zip(кадры_.заголовки, кадры_.поля, strict=True) if з.crc_верна]
        ряд = np.unpackbits(np.frombuffer(b"".join(поля), dtype=np.uint8))
        код_ = кадры_.код
