#: Сколько уровней преобразований снимать подряд.
ГЛУБИНА = 4
#: Сколько бит потока смотреть на каждом уровне: разбор — по выборке.
ВЫБОРКА_БИТ = 1 << 23
#: Сколько каналов мультиплексора разбирать глубже.
КАНАЛОВ_ГЛУБЖЕ = 32
#: Сколько притоков синхронной иерархии (TU-12 и т. п.) разбирать глубже; остальные — сводкой.
ПРИТОКОВ_ГЛУБЖЕ = 32
#: Сколько гипотез-преобразований одного уровня разбирать дальше.
ВЕТВЕЙ = 3
#: Профили разбора: время на весь разбор и пределы тяжёлых поисков.
#: «быстро» — вложение в помощнике, «обычно» — команда и страница разбора,
#: «глубоко» — всё, что есть.
ПРОФИЛИ = {
    "быстро": {"время": 90.0, "длинные": {"до": 256, "бюджет": 8.0}, "выколотые": False,
               "глубина": ГЛУБИНА, "форни": None},
    "обычно": {"время": 600.0, "длинные": {"до": 1024, "бюджет": 90.0}, "выколотые": False,
               "глубина": ГЛУБИНА + 1, "форни": {"I_до": 64, "M_до": 64, "бюджет": 60.0}},
    "глубоко": {"время": 3600.0, "длинные": {"до": 2048, "бюджет": 900.0}, "выколотые": True,
                "глубина": ГЛУБИНА + 2, "форни": {"I_до": 128, "M_до": 128, "бюджет": 600.0}},
}
#: Вес находок в оценке ветви: проверяемая (контрольная сумма, синхрослово)
#: и преобразование (код, скремблер — вывод статистический).
ВЕС_ПРОВЕРЯЕМОЙ = 10.0
ВЕС_ПРЕОБРАЗОВАНИЯ = 1.0


