#: Сколько уровней преобразований снимать подряд.
ГЛУБИНА = 4
#: Сколько бит потока смотреть на каждом уровне: разбор — по выборке.
ВЫБОРКА_БИТ = 1 << 23
#: Сколько каналов мультиплексора разбирать глубже.
КАНАЛОВ_ГЛУБЖЕ = 32
#: Сколько гипотез-преобразований одного уровня разбирать дальше.
ВЕТВЕЙ = 3
#: Профили разбора: время на весь разбор и пределы тяжёлых поисков.
#: «быстро» — вложение в помощнике, «обычно» — команда и страница разбора,
#: «глубоко» — всё, что есть.
ПРОФИЛИ = {
    "быстро": {"время": 90.0, "длинные": {"до": 256, "бюджет": 8.0}, "выколотые": False,
               "глубина": ГЛУБИНА},
    "обычно": {"время": 600.0, "длинные": {"до": 1024, "бюджет": 90.0}, "выколотые": False,
               "глубина": ГЛУБИНА + 1},
    "глубоко": {"время": 3600.0, "длинные": {"до": 2048, "бюджет": 900.0}, "выколотые": True,
                "глубина": ГЛУБИНА + 2},
}
#: Вес находок в оценке ветви: проверяемая (контрольная сумма, синхрослово)
#: и преобразование (код, скремблер — вывод статистический).
ВЕС_ПРОВЕРЯЕМОЙ = 10.0
ВЕС_ПРЕОБРАЗОВАНИЯ = 1.0


@dataclass
class Разбор:
    поток: Поток
    статистика: Статистика
    находки: List[Находка] = field(default_factory=list)
    не_найдено: List[str] = field(default_factory=list)
    ограничения: List[str] = field(default_factory=list)
    другие: List[str] = field(default_factory=list)
    карта: Optional[Находка] = None
    секунд: float = 0.0

    def отчёт(self, предел: int = 7000) -> str:
        return собрать_отчёт(self, предел)


@dataclass
class Ветвь:
    находки: List[Находка] = field(default_factory=list)
    не_найдено: List[str] = field(default_factory=list)
    ограничения: List[str] = field(default_factory=list)
    другие: List[str] = field(default_factory=list)
    оценка: float = 0.0

    def проверяемая(self, находка: Находка, путь: str) -> None:
        self.находки.append(_с_путём(находка, путь))
        self.оценка += ВЕС_ПРОВЕРЯЕМОЙ * находка.уверенность
        if _ТЕКУЩИЙ.бюджет is not None:
            _ТЕКУЩИЙ.бюджет.сказать(f"найдено: {находка.что} ({находка.мера})")

    def влить(self, другая: "Ветвь") -> None:
        self.находки += другая.находки
        self.не_найдено += другая.не_найдено
        self.ограничения += другая.ограничения
        self.другие += другая.другие
        self.оценка += другая.оценка


@dataclass
class Бюджет:
    конец: float
    профиль: dict = field(default_factory=lambda: ПРОФИЛИ["быстро"])
    исчерпан: bool = False
    #: Куда сообщать ход разбора («пробую скремблер…») и найденные этапы —
    #: для страницы, где этапы появляются по мере разбора.
    ход: Optional[Callable[[str], None]] = None
    этап: Optional[Callable[[Находка], None]] = None
    #: Бит на символ КАМ, если известно, — для подбора модуляционной плоскости.
    символ: tuple = ()

    def сказать(self, строка: str) -> None:
        if self.ход is not None:
            self.ход(строка)

    @property
    def глубоко(self) -> bool:
        return self.профиль["выколотые"]

    def вышел(self) -> bool:
        if time.monotonic() > self.конец:
            self.исчерпан = True
        return self.исчерпан


class _Текущий:
    """Бюджет идущего разбора — чтобы ветви могли сообщать о находках."""
    бюджет: Optional["Бюджет"] = None


_ТЕКУЩИЙ = _Текущий()


def _дальше(путь: str, шаг: str) -> str:
    return (путь + " → " if путь else "") + шаг


def _кадры_без_ip(ветвь: Ветвь, кадры: Sequence[bytes], путь: str, откуда: str) -> None:
    """Кадры, в которых нет IP: формат полей и контрольная сумма."""
    формат = polya.найти(кадры, откуда)
    if формат is not None:
        ветвь.проверяемая(формат, путь)
    else:
        ветвь.не_найдено.append(f"IP и известный формат в {откуда}: нет")


def _проверяемые(выборка: np.ndarray, глубина: int, путь: str, б: Бюджет) -> Ветвь | None:
    """Уровни, которые доказывают себя сами. None — ни одного не нашлось."""
    ветвь = Ветвь()
    где = f" ({путь})" if путь else ""

    # 1. Пакеты прямо в байтах и транспортный поток (с кодом DVB).
    байты = в_байты(выборка)
    найдено = pakety.найти_в_потоке(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        return ветвь
    найдено = kod.mpeg_ts(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        длина, сдвиг = найдено.дальше
        if длина == dvb.ДЛИНА:
            канал = dvb.найти(байты, сдвиг)
            if канал is not None:
                ветвь.проверяемая(канал, путь)
            else:
                ветвь.не_найдено.append(f"код Рида — Соломона (204, 188) в пакетах{где}: "
                                        f"синдромы не нулевые ни как есть, ни после снятия "
                                        f"перемежения DVB")
        return ветвь
    ветвь.не_найдено.append(f"пакеты IP подряд и MPEG-TS{где}: нет")

    # 2. HDLC: битстаффинг, затем октетный (асинхронный PPP, SLIP) — и что в кадрах.
    кадры = hdlc.найти(выборка)
    if кадры is None:
        ветвь.не_найдено.append(f"HDLC с битстаффингом{где}: флагов с верной FCS нет")
        кадры = oktety.найти(выборка)
        if кадры is None:
            ветвь.не_найдено.append(f"октетный стаффинг{где} (асинхронное HDLC/PPP 0x7E/0x7D, "
                                    f"SLIP 0xC0/0xDB): нет")
            # Кадры по контрольной сумме заголовка: GFP (G.7041) и ячейки ATM.
            кадры = gfp.найти(выборка)
            if кадры is None:
                ветвь.не_найдено.append(f"GFP (cHEC) и ячейки ATM (HEC){где}: нет")
    if кадры is not None:
        ветвь.проверяемая(кадры, путь)
        if not кадры.дальше:
            return ветвь
        внутри = pakety.найти_в_кадрах(кадры.дальше)
        if внутри is not None:
            ветвь.проверяемая(внутри, _дальше(путь, "кадры"))
        else:
            _кадры_без_ip(ветвь, кадры.дальше, _дальше(путь, "кадры"), "кадрах")
        return ветвь

    # 3. PDH со стаффингом согласования скоростей — притоки разбираются так же.
    иерархия = pdh.найти(выборка)
    if иерархия is not None:
        ветвь.проверяемая(иерархия, путь)
        for номер, приток in иерархия.дальше.items():
            ветвь.влить(_ступень(приток, глубина, _дальше(путь, f"приток {номер}"), б))
        return ветвь
    ветвь.не_найдено.append(f"PDH E2/E3/E4 (G.742/G.751){где}: нет")

    # 4. Цикл и каналы — и HDLC в каналах.
    цикл = cikl.найти(выборка)
    if цикл is not None:
        ветвь.проверяемая(цикл, путь)
        if цикл.дальше:
            _каналы(цикл.дальше, ветвь, путь)
        return ветвь
    ветвь.не_найдено.append(f"цикл и синхрослово{где}: нет")
    ветвь.оценка = 0.0
    return None if not ветвь.находки else ветвь


def _плоскости(выборка: np.ndarray, б: Бюджет, глубина: int
               ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Подбор модуляционной плоскости — только на самом верху, сразу за демодулятором.

    Если число бит на символ известно — идёт первым; в глубоком профиле без
    подсказки пробуются КАМ-16, 64 и 256 — последними: это долго.
    """
    if глубина:
        return []
    k_список = б.символ or ((4, 6, 8) if б.глубоко else ())
    return [(f"модуляционная плоскость КАМ-{1 << k}", (lambda k=k: ploskost.найти(выборка, k)),
             f"в плоскости КАМ-{1 << k}") for k in k_список]


def _детекторы(выборка: np.ndarray, б: Бюджет, глубина: int = 1
               ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Детекторы преобразований — от дешёвых к дорогим: (имя, вызов, шаг пути)."""
    длинные = б.профиль["длинные"]
    плоскости = _плоскости(выборка, б, глубина)
    return (плоскости if б.символ else []) + [
        ("кодирование в линии (манчестерский, 4B/5B, 8B/10B)", lambda: lineynye.найти(выборка),
         "после снятия кодирования в линии"),
        ("свёрточный 1/2 и короткий блочный код", lambda: kod.найти(выборка, длинные=False),
         "после снятия кода"),
        ("свёрточный код 1/3, 1/4", lambda: svyortka.найти(выборка), "после снятия кода"),
        ("турбокод 1/3", lambda: turbo.найти(выборка), "после турбодекодирования"),
        ("скремблер", lambda: skrembler.найти(выборка), "после снятия скремблера"),
        ("блочное перемежение над кодом", lambda: peremezhenie.найти(выборка),
         "после снятия перемежения и кода"),
        ("выколотый свёрточный код", lambda: vykalyvanie.найти(
            выборка, глубоко=б.глубоко, бюджет=max(1.0, min(60.0, б.конец - time.monotonic()))),
         "после снятия выколотого кода"),
        ("длинный блочный код (LDPC, Рида — Соломона, БЧХ)", lambda: dlinnye.найти(
            выборка, до=длинные["до"],
            бюджет=max(1.0, min(длинные["бюджет"], б.конец - time.monotonic()))),
         "после снятия кода"),
    ] + ([] if б.символ else плоскости)


def _варианты(найдено: Находка) -> List[tuple[Находка, np.ndarray]]:
    """Находка → (находка, снятый ряд); у манчестерского — по варианту на толкование."""
    if найдено.вид_дальше == "варианты":
        return [(Находка(**{**найдено.__dict__, "что": f"{найдено.что}, {вариант}",
                           "дальше": ряд, "вид_дальше": "биты"}), ряд)
                for вариант, ряд in найдено.дальше.items()]
    if найдено.дальше is not None and len(найдено.дальше):
        return [(найдено, np.asarray(найдено.дальше, dtype=np.uint8))]
    return [(найдено, np.zeros(0, dtype=np.uint8))]


#: Оценка ветви, при которой гипотеза подтверждена проверяемой находкой ниже
#: и остальные детекторы уровня можно не звать.
ПОДТВЕРЖДЕНО = 0.9 * ВЕС_ПРОВЕРЯЕМОЙ


def _сводка(ветвь: Ветвь) -> str:
    if not ветвь.находки:
        return "дальше ничего не открылось"
    return "дальше: " + " → ".join(н.суть for н in ветвь.находки[:4])


def _ступень(биты: np.ndarray, глубина: int, путь: str, б: Бюджет) -> Ветвь:
    """Разобрать ряд на этом уровне: проверяемые находки или лучшая ветвь преобразований."""
    выборка = биты[:ВЫБОРКА_БИТ]
    где = f" ({путь})" if путь else ""
    проверено = _проверяемые(выборка, глубина, путь, б)
    if проверено is not None:
        return проверено
    ветвь = Ветвь()
    ветвь.не_найдено += [f"пакеты IP подряд и MPEG-TS{где}: нет",
                         f"HDLC (битовый и октетный стаффинг), GFP, ATM{где}: нет",
                         f"PDH, цикл и синхрослово{где}: нет"]
    if глубина >= б.профиль["глубина"]:
        ветвь.ограничения.append(f"разбор остановлен на глубине {глубина}{где}")
        return ветвь
    if б.вышел():
        ветвь.ограничения.append(f"время разбора исчерпано{где}")
        return ветвь
    оценённые = []
    не_звали: List[str] = []
    for имя, найти, шаг in _детекторы(выборка, б, глубина):
        if оценённые and max(о[0] for о in оценённые) >= ПОДТВЕРЖДЕНО:
            не_звали.append(имя)
            continue
        if б.вышел():
            ветвь.не_найдено.append(f"{имя}{где}: не проверено — время разбора исчерпано")
            continue
        б.сказать(f"{путь or 'поток'}: пробую — {имя}")
        найдено = найти()
        if найдено is not None:
            б.сказать(f"{путь or 'поток'}: гипотеза — {найдено.что}; проверяю, что под ней")
        if найдено is None:
            ветвь.не_найдено.append(f"{имя}{где}: нет")
            continue
        for находка, ряд in _варианты(найдено):
            if len([о for о in оценённые if о[3]]) >= ВЕТВЕЙ:
                оценённые.append((ВЕС_ПРЕОБРАЗОВАНИЯ * находка.уверенность, находка, Ветвь(),
                                  False))
                continue
            ниже = (_ступень(ряд, глубина + 1, _дальше(путь, шаг), б) if len(ряд) >= 8192
                    else Ветвь())
            оценённые.append((ВЕС_ПРЕОБРАЗОВАНИЯ * находка.уверенность + ниже.оценка, находка,
                              ниже, True))
    if не_звали:
        ветвь.другие.append(f"{путь or 'поток'}: гипотеза подтверждена проверяемой находкой "
                            f"ниже — не проверялись: {', '.join(не_звали)}")
    if not оценённые:
        return ветвь
    оценённые.sort(key=lambda о: о[0], reverse=True)
    лучшая_оценка, лучшая, ниже, _ = оценённые[0]
    ветвь.находки.append(_с_путём(лучшая, путь))
    ветвь.оценка = лучшая_оценка
    ветвь.не_найдено += ниже.не_найдено
    ветвь.ограничения += ниже.ограничения
    ветвь.находки += ниже.находки
    ветвь.другие += ниже.другие
    for оценка, находка, другая, разобрана in оценённые[1:]:
        if разобрана:
            ветвь.другие.append(f"{путь or 'поток'}: {находка.суть} — оценка {оценка:.1f} "
                                f"против {лучшая_оценка:.1f} у выбранной; {_сводка(другая)}")
        else:
            ветвь.другие.append(f"{путь or 'поток'}: {находка.суть} (уверенность "
                                f"{round(находка.уверенность * 100)} %) — глубже не разбиралась")
    return ветвь


def _каналы(каналы: dict, ветвь: Ветвь, путь: str) -> None:
    """В каналах мультиплексора — HDLC и IP в нём."""
    for номер in sorted(каналы)[:КАНАЛОВ_ГЛУБЖЕ]:
        ряд = каналы[номер]
        if len(ряд) < 4096:
            continue
        кадры = hdlc.найти(ряд)
        if кадры is None:
            continue
        канал = _дальше(путь, f"КИ{номер}")
        ветвь.проверяемая(кадры, канал)
        внутри = pakety.найти_в_кадрах(кадры.дальше)
        if внутри is not None:
            ветвь.проверяемая(внутри, канал + " → кадры HDLC")


def _с_путём(находка: Находка, путь: str) -> Находка:
    if путь and not находка.путь:
        находка.путь = путь
        находка.что = f"{находка.что} — в потоке {путь}"
    return находка


# -- ручное управление ---------------------------------------------------------------

def _восьмеричные(текст: str) -> List[int]:
    return [int(ч, 8) for ч in re.findall(r"[0-7]+", текст)]


def _вариант_плоскости(слова: str) -> Optional[dict]:
    """«плоскость 6 поворот 270° грей половинами старший» → вариант; без слов — None."""
    симметрия = next((имя for имя in ploskost.СИММЕТРИИ
                      if имя.lower().replace("°", "") in слова.replace("°", "")), None)
    if симметрия is None:
        return None
    return {"симметрия": симметрия,
            "код": "натуральный" if "натурал" in слова else "Грей",
            "раскладка": "вперемешку" if "вперемешку" in слова else "половинами",
            "порядок": "младший" if "младш" in слова else "старший"}


def снять_вручную(биты: np.ndarray, указание: str) -> tuple[np.ndarray, Находка]:
    """Снять слой, который аналитик уже знает. Возвращает ряд и запись для отчёта.

    Понимает: «инверсия», «сдвиг N», «nrzi», «манчестер», «скремблер a,b…»,
    «свёрточный g1/g2[/g3] K=k», «выколотый g1/g2 K=k шаблон 1101…»,
    «перемежение R n», «pdh E2|E3|E4 приток N», «плоскость k [вариант]».
    """
    слова = указание.strip().lower()
    вид = слова.split()[0] if слова else ""
    числа = [int(ч) for ч in re.findall(r"\d+", слова)]
    подробно: List[str] = []
    if вид == "инверсия":
        ряд = инвертировать(биты)
    elif вид == "сдвиг":
        ряд = биты[числа[0]:]
    elif вид in ("nrzi", "дифференциальное", "дифференциальный"):
        ряд = lineynye.nrzi(биты)
    elif вид.startswith("манчестер"):
        найдено = lineynye.манчестер(биты)
        if найдено is None:
            raise ValueError("манчестерский код не подтвердился: пары без перехода есть")
        ряд = найдено.дальше["IEEE 802.3"]
    elif вид == "скремблер":
        ряд = skrembler.снять(биты, числа)
        подробно.append(f"полином {skrembler.полином_словами(числа)}")
    elif вид.startswith("свёрточн") or вид.startswith("сверточн"):
        K = int(re.search(r"k\s*=\s*(\d+)", слова).group(1))
        многочлены = _восьмеричные(слова.split("k")[0].split(None, 1)[1])
        n = len(многочлены)
        лучшее = None
        for сдвиг in range(n):
            ряд_ = биты[сдвиг:сдвиг + (1 << 18)]
            данные = svyortka.витерби(ряд_, многочлены, K)
            ошибок = float(np.mean(svyortka.кодировать(данные, многочлены, K)[:len(ряд_)]
                                   != ряд_[:len(данные) * n]))
            if лучшее is None or ошибок < лучшее[0]:
                лучшее = (ошибок, сдвиг, данные)
        ряд = лучшее[2]
        подробно.append(f"начало тройки/пары — бит {лучшее[1]}; расхождение перекодированного "
                        f"с принятым {лучшее[0] * 100:.2f} %")
    elif вид.startswith("выколот"):
        K = int(re.search(r"k\s*=\s*(\d+)", слова).group(1))
        g1, g2 = _восьмеричные(слова.split("k")[0].split(None, 1)[1])[:2]
        шаблон = tuple(int(ч) for ч in re.search(r"шаблон\s*([01]+)", слова).group(1))
        k = len(шаблон) // 2
        лучшее = None
        for начало in range(sum(шаблон)):
            H = vykalyvanie.проверки_кандидата(g1, g2, K, шаблон, k)
            нарушено = vykalyvanie._нарушено(биты, H, sum(шаблон), начало, 2000)
            if нарушено is not None and (лучшее is None or нарушено < лучшее[0]):
                лучшее = (нарушено, начало)
        материнский, известно = vykalyvanie.вставить_стирания(биты[лучшее[1]:], шаблон)
        ряд = svyortka.витерби(материнский[:1 << 19], [g1, g2], K, известно[:1 << 19])
        подробно.append(f"начало периода — бит {лучшее[1]}")
    elif вид == "перемежение":
        ряд, начало = peremezhenie.собрать(биты, числа[0], числа[1])
        подробно.append(f"начало блока — фаза {начало}")
    elif вид == "плоскость":
        k = числа[0]
        вариант = _вариант_плоскости(слова)
        if вариант is None:
            найдено = ploskost.найти(биты, k, лучших=1)
            if найдено is None:
                raise ValueError(f"для КАМ-{1 << k} ни один вариант плоскости не проявил структуру")
            имя, ряд = next(iter(найдено.дальше.items()))
            подробно.append(f"выбран лучший вариант: {имя}")
            подробно += найдено.подробно
        else:
            ряд = ploskost.преобразовать(биты[:len(биты) - len(биты) % k], k, **вариант)
    elif вид == "pdh":
        имя = re.search(r"e[234]", слова).group(0).upper()
        иерархия = next(и for и in pdh.ИЕРАРХИИ if и.имя == имя)
        найдено = pdh._начало_цикла(биты, иерархия)
        if найдено is None:
            raise ValueError(f"цикл {имя} не найден")
        притоки, _ = pdh.разнести(биты, иерархия, найдено[0])
        приток = числа[-1] if len(числа) > 1 else 1
        ряд = притоки[приток - 1]
    else:
        raise ValueError(f"не понимаю указание «{указание}»")
    return ряд, Находка(уровень="вручную", что=f"снято по указанию: {указание.strip()}",
                        уверенность=1.0, мера="слой задан аналитиком, не найден анализатором",
                        подробно=подробно, дальше=ряд, вид_дальше="биты")


def разобрать(путь: str | Path | None = None, *, данные: bytes | None = None,
              имя: str = "", глубоко: bool = False, снять: Sequence[str] = (),
              профиль: str = "быстро", ход: Optional[Callable[[str], None]] = None,
              этап: Optional[Callable[[Находка], None]] = None,
              символ: Sequence[int] = ()) -> Разбор:
    """Разобрать поток из файла или из байтов. ``глубоко`` — то же, что профиль «глубоко».

    ``ход`` получает строки о том, что пробуется сейчас; ``этап`` — каждую
    находку итоговой цепочки по мере того, как она складывается.
    """
    начало = time.monotonic()
    настройки = ПРОФИЛИ["глубоко" if глубоко else профиль]
    б = Бюджет(конец=начало + настройки["время"], профиль=настройки, ход=ход, этап=этап,
               символ=tuple(int(k) for k in символ if 2 <= int(k) <= 12 and int(k) % 2 == 0))
    _ТЕКУЩИЙ.бюджет = б
    try:
        return _разобрать(путь, данные, имя, снять, б, начало)
    finally:
        _ТЕКУЩИЙ.бюджет = None


def _разобрать(путь, данные, имя, снять, б: "Бюджет", начало: float) -> Разбор:
    поток = прочитать(путь, данные=данные, имя=имя)
    разбор = Разбор(поток=поток, статистика=посчитать(поток.данные))

    разбор.карта = karta.описать(поток.данные[:64 << 20])
    захват = karta.pcap(поток.данные)
    if захват is not None:
        канал, пакеты = захват
        внутри = pakety.найти_в_кадрах(пакеты, f"пакетов pcap ({канал})")
        if внутри is not None:
            разбор.находки.append(внутри)
        else:
            ветвь = Ветвь()
            _кадры_без_ip(ветвь, пакеты, "", f"пакетах pcap ({канал})")
            разбор.находки += ветвь.находки
            разбор.не_найдено += ветвь.не_найдено
        разбор.секунд = time.monotonic() - начало
        return разбор

    # .Sig: сперва сами пакеты — может, это уже IP или известный формат.
    if поток.пакеты and not снять:
        тела = [поток.пакет(номер) for номер in range(min(len(поток.пакеты), 20000))]
        внутри = pakety.найти_в_кадрах(тела, "пакетов файла")
        if внутри is not None:
            разбор.находки.append(внутри)
        else:
            формат = polya.найти(тела, "пакетов файла")
            if формат is not None:
                разбор.находки.append(формат)
            разбор.не_найдено.append("IP в пакетах .Sig: нет — разбираем тела пакетов "
                                     "подряд как поток")
    if not any(н.уровень == "сетевой" for н in разбор.находки):
        биты = в_биты(поток.данные[:ВЫБОРКА_БИТ // 8])
        путь_ = ""
        for указание in снять:
            биты, запись = снять_вручную(биты, указание)
            разбор.находки.append(_с_путём(запись, путь_))
            путь_ = _дальше(путь_, указание.strip())
        ветвь = _ступень(биты, 0, путь_, б)
        # Порядок бит в байте: если прямой ничего не дал — «младшим битом вперёд».
        if not ветвь.находки and not снять:
            ветвь.не_найдено.append("всё выше — при порядке «старший бит байта первым»; "
                                    "повторено при порядке «младший бит первым»")
            обратная = _ступень(в_биты(поток.данные[:ВЫБОРКА_БИТ // 8], "младший"), 0,
                                "младший бит первым", б)
            ветвь.не_найдено += обратная.не_найдено
            ветвь.находки += обратная.находки
            ветвь.ограничения += обратная.ограничения
            ветвь.другие += обратная.другие
        разбор.находки += ветвь.находки
        разбор.не_найдено += ветвь.не_найдено
        разбор.ограничения += ветвь.ограничения
        разбор.другие += ветвь.другие
    if len(поток.данные) * 8 > ВЫБОРКА_БИТ:
        разбор.ограничения.append(
            f"битовые уровни разобраны по первым {ВЫБОРКА_БИТ // 8 // (1 << 20)} МБ "
            f"из {len(поток.данные) / (1 << 20):.1f} МБ; статистика и карта — по всему файлу")
    if б.этап is not None:
        for находка in разбор.находки:
            б.этап(находка)
    if б.исчерпан:
        разбор.ограничения.append(
            f"время разбора ({б.конец - начало:.0f} с) исчерпано — часть гипотез не проверена"
            + ("" if б.глубоко else "; глубокий разбор: reportgen potok --глубоко"))
    разбор.секунд = time.monotonic() - начало
    return разбор


def этапы(разбор: Разбор) -> List[dict]:
    """Итоговая цепочка — этапами для страницы: что, мера, подробно, альтернативы."""
    итог = []
    for номер, находка in enumerate(разбор.находки, start=1):
        дальше = находка.дальше
        выход = ""
        if находка.вид_дальше == "биты" and дальше is not None:
            выход = f"{len(дальше)} бит"
        elif находка.вид_дальше in ("кадры", "пакеты") and дальше is not None:
            выход = f"{len(дальше)} {'кадров' if находка.вид_дальше == 'кадры' else 'пакетов'}"
        elif находка.вид_дальше == "притоки" and дальше:
            выход = f"{len(дальше)} притока"
        ключ = (находка.путь or "поток") + ":"
        итог.append({
            "номер": номер, "уровень": находка.уровень, "что": находка.суть,
            "путь": находка.путь, "уверенность": round(float(находка.уверенность), 3),
            "мера": находка.мера, "подробно": list(находка.подробно), "выход": выход,
            "альтернативы": [с[len(ключ):].strip() for с in разбор.другие if с.startswith(ключ)],
        })
    return итог


def _сгруппировать(находки: List[Находка]) -> List[List[Находка]]:
    """Одинаковые находки подряд (притоки, каналы) — в одну строку отчёта.

    Четыре притока E2 с одинаковым E1 внутри — это одна мысль, а не четыре
    экрана текста: отчёт ограничен по объёму, и повторы вытеснили бы главное.
    """
    группы: List[List[Находка]] = []
    for находка in находки:
        ключ = (находка.уровень, находка.суть)
        for группа in группы:
            if (группа[0].уровень, группа[0].суть) == ключ:
                группа.append(находка)
                break
        else:
            группы.append([находка])
    return группы


def собрать_отчёт(разбор: Разбор, предел: int = 7000) -> str:
    """Отчёт для модели и для человека: сперва найденное, потом проверенное впустую."""
    с = разбор.статистика
    п = разбор.поток
    строки = [
        f"### РАЗБОР ПОТОКА «{п.имя}» — анализатор системы, не модель",
        f"Файл: {п.формат}.",
        f"Общее: {с.байт} байт; энтропия {с.энтропия:.3f} бит/байт; единиц "
        f"{с.единиц * 100:.2f} %; самые длинные серии — нулей {с.серия_нулей}, "
        f"единиц {с.серия_единиц}. {с.вывод().capitalize()}.",
    ]
    if с.частые:
        строки.append("Частые байты: " + ", ".join(
            f"0x{байт:02X} ({доля * 100:.1f} %)" for байт, доля in с.частые[:5]) + ".")
    if с.повторы:
        строки.append("Повторяющиеся слова с постоянным шагом: " + "; ".join(
            f"{слово} через {шаг} байт ({доля * 100:.0f} % повторов)"
            for слово, шаг, доля in с.повторы) + ".")
    строки += [f"Заметка: {заметка}" for заметка in п.заметки]
    if разбор.карта is not None:
        строки.append(f"Карта файла: {разбор.карта.что}.")
        строки += [f"   - {строка}" for строка in разбор.карта.подробно]
    строки.append("")
    if разбор.находки:
        строки.append("НАЙДЕНО (уверенность — проверяемая мера, указана в скобках):")
        for номер, группа in enumerate(_сгруппировать(разбор.находки), start=1):
            первая = группа[0]
            строки.append(f"{номер}. {первая.строка()}")
            строки += [f"   - {строка}" for строка in первая.подробно]
            if len(группа) > 1:
                строки.append(f"   - то же ещё в {len(группа) - 1}: " + "; ".join(
                    f"{н.путь or 'основном потоке'} ({round(н.уверенность * 100)} %: {н.мера})"
                    for н in группа[1:]))
    else:
        строки.append("НАЙДЕНО: ничего с достаточной уверенностью.")
    if разбор.другие:
        строки.append("")
        строки.append("ДРУГИЕ ГИПОТЕЗЫ (проверены и отвергнуты в пользу найденного или "
                      "не разобраны):")
        строки += [f"- {строка}" for строка in разбор.другие[:12]]
    if разбор.не_найдено:
        строки.append("")
        строки.append("ПРОВЕРЕНО И НЕ НАЙДЕНО:")
        строки += [f"- {строка}" for строка in разбор.не_найдено]
    if разбор.ограничения:
        строки.append("")
        строки.append("ОГРАНИЧЕНИЯ РАЗБОРА:")
        строки += [f"- {строка}" for строка in разбор.ограничения]
    строки.append("")
    строки.append(f"Разбор занял {разбор.секунд:.1f} с. Числа и выводы выше получены "
                  f"вычислением по потоку; толкуй их по стандартам библиотеки, не "
                  f"пересчитывай и не домысливай уровни, которых здесь нет.")
    текст = "\n".join(строки)
    if len(текст) > предел:
        текст = текст[:предел - 60].rsplit("\n", 1)[0] + "\n… (отчёт сокращён по объёму)"
    return текст
