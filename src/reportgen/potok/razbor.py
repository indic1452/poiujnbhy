def _дальше(путь: str, шаг: str) -> str:
    return (путь + " → " if путь else "") + шаг


def _кадры_без_ip(ветвь: Ветвь, кадры: Sequence[bytes], путь: str, откуда: str) -> None:
    """Кадры, в которых нет IP: канальный протокол (ОКС-7, ISDN, FR, X.25, AX.25) — и дальше
    его разборщиками; не он — формат полей и контрольная сумма."""
    протокол = kanal.найти(кадры, откуда)
    if протокол is not None:
        ветвь.проверяемая(протокол, путь)
        return
    ветвь.не_найдено.append(f"канальный протокол в {откуда} (MTP2, LAPD, Frame Relay, LAPB, AX.25): "
                            f"признаки ни одного не сошлись у большинства кадров")
    формат = polya.найти(кадры, откуда)
    if формат is not None:
        ветвь.проверяемая(формат, путь)
    else:
        ветвь.не_найдено.append(f"IP и известный формат в {откуда}: нет")


def _таблицы_ts(ветвь: Ветвь, байты: bytes, длина: int, сдвиг: int, путь: str) -> None:
    """Таблицы PSI/SI транспортного потока и IP в MPE — если PAT собралась."""
    таблицы = mpeg_ts.находка(байты, длина, сдвиг)
    if таблицы is None:
        return
    ветвь.проверяемая(таблицы, путь)
    if таблицы.дальше:
        внутри = pakety.найти_в_кадрах(таблицы.дальше, "датаграммах MPE")
        if внутри is not None:
            ветвь.проверяемая(внутри, _дальше(путь, "MPE"))


def _проверяемые(выборка: np.ndarray, глубина: int, путь: str, б: Бюджет) -> Ветвь | None:
    """Уровни, которые доказывают себя сами. None — ни одного не нашлось."""
    ветвь = Ветвь()
    где = f" ({путь})" if путь else ""

    # 1. Пакеты прямо в байтах и транспортный поток (с кодом DVB).
    байты = в_байты(выборка)
    найдено = pakety.найти_в_потоке(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        return ветвь
    найдено = kod.mpeg_ts(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        длина, сдвиг = найдено.дальше
        _таблицы_ts(ветвь, байты, длина, сдвиг, путь)
        if длина == dvb.ДЛИНА:
            канал = dvb.найти(байты, сдвиг)
            if канал is not None:
                ветвь.проверяемая(канал, путь)
            else:
                ветвь.не_найдено.append(f"код Рида — Соломона (204, 188) в пакетах{где}: "
                                        f"синдромы не нулевые ни как есть, ни после снятия "
                                        f"перемежения DVB")
        return ветвь
    ветвь.не_найдено.append(f"пакеты IP подряд и MPEG-TS{где}: нет")

    # 1б. DVB-S2 после LDPC: слова БЧХ, BBFRAME с верной CRC-8 заголовка, пакеты TS или GSE.
    найдено = dvbs2.найти(выборка)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        if найдено.вид_дальше == "пакеты TS" and найдено.дальше is not None and len(найдено.дальше):
            _таблицы_ts(ветвь, bytes(найдено.дальше), 188, 0, _дальше(путь, "BBFRAME"))
        elif найдено.вид_дальше == "кадры" and найдено.дальше:
            внутри = pakety.найти_в_кадрах(найдено.дальше, "PDU GSE")
            if внутри is not None:
                ветвь.проверяемая(внутри, _дальше(путь, "GSE"))
        return ветвь
    ветвь.не_найдено.append(f"DVB-S2 после LDPC{где} (BBHEADER с верной CRC-8 в начале слов БЧХ): нет")

    # 1б′. Gigabit Ethernet 1000BASE-X: 8B/10B, /S/ … /T/, кадры Ethernet с верной FCS.
    найдено = gbe.найти(выборка)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        внутри = pakety.найти_в_кадрах(найдено.дальше, "кадрах Ethernet")
        if внутри is not None:
            ветвь.проверяемая(внутри, _дальше(путь, "1000BASE-X"))
        return ветвь
    ветвь.не_найдено.append(f"Gigabit Ethernet 1000BASE-X{где} (кадры между /S/ и /T/ с верной FCS): нет")

    # 1в. CCSDS TM/AOS: счётчик кадров +1, заголовки, FECF; Space Packet через границы кадров.
    найдено = ccsds.найти(байты)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        return ветвь
    ветвь.не_найдено.append(f"кадры CCSDS TM/AOS{где} (счётчик кадров, заголовки, FECF): нет")

    # 1г. V.110 (ISDN, GSM CSD): кадр 80 бит по 17 битам синхрокомбинации, прямо или через RA2
    #     из 64 кбит/с; данные пользователя (RA1 обратно) разбираются так же, как весь поток.
    найдено = v110.найти(выборка)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        if найдено.дальше is not None and len(найдено.дальше) >= 4096:
            ветвь.влить(_ступень(найдено.дальше, глубина, _дальше(путь, "V.110"), б))
        return ветвь
    ветвь.не_найдено.append(f"V.110{где} (кадр 80 бит: октет нулей и девять октетов с 1 в начале): нет")

    # 1г′. TRAU (GSM Abis): кадры 320 бит прямо или в подканалах 16 кбит/с канала 64 кбит/с;
    #      кадры данных — кадры V.110, данные пользователя разбираются дальше.
    найдено = trau.найти(выборка)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        if найдено.дальше is not None and len(найдено.дальше) >= 4096:
            ветвь.влить(_ступень(найдено.дальше, глубина, _дальше(путь, "TRAU → V.110"), б))
        return ветвь
    ветвь.не_найдено.append(f"TRAU GSM Abis{где} (кадр 320 бит: 16 нулей и 1 в начале каждого слова): нет")

    # 1д. DMR (ETSI TS 102 361): синхрослова с шагом 288/264, тип слота (Golay), LC (RS (12, 9)),
    #     CSBK и заголовки данных (CRC с масками), EMB речи (QR (16, 7)).
    найдено = dmr.найти(выборка)
    if найдено is not None:
        ветвь.проверяемая(найдено, путь)
        return ветвь
    ветвь.не_найдено.append(f"DMR{где} (синхрослова пакетов с шагом 288 или 264 бит): нет")

    # 2. HDLC: битстаффинг, затем октетный (асинхронный PPP, SLIP) — и что в кадрах.
    кадры = hdlc.найти(выборка)
    if кадры is None:
        ветвь.не_найдено.append(f"HDLC с битстаффингом{где}: флагов с верной FCS нет")
        кадры = oktety.найти(выборка)
        if кадры is None:
            ветвь.не_найдено.append(f"октетный стаффинг{где} (асинхронное HDLC/PPP 0x7E/0x7D, "
                                    f"SLIP 0xC0/0xDB): нет")
            # Кадры по контрольной сумме заголовка: GFP (G.7041) и ячейки ATM.
            кадры = gfp.найти(выборка)
            if кадры is None:
                ветвь.не_найдено.append(f"GFP (cHEC) и ячейки ATM (HEC){где}: нет")
                # Ethernet 64b/66b: синхрозаголовки 01/10, скремблер, кадры с верной FCS.
                кадры = pcs.найти(выборка)
                if кадры is None:
                    ветвь.не_найдено.append(f"Ethernet 64b/66b (10GBASE-R){где}: нет")
    if кадры is not None:
        ветвь.проверяемая(кадры, путь)
        if кадры.дальше:
            внутри = pakety.найти_в_кадрах(кадры.дальше)
            if внутри is not None:
                ветвь.проверяемая(внутри, _дальше(путь, "кадры"))
            else:
                _кадры_без_ip(ветвь, кадры.дальше, _дальше(путь, "кадры"), "кадрах")
        if _доля_годных(кадры) < ЧАСТИЧНО_ДО:
            ветвь.частично = кадры
            return _или_по_циклу(ветвь, кадры, выборка, глубина, путь, б)
        return ветвь

    # 2а. OTN (G.709): кадр 4 × 4080 по FAS, скремблер вслепую, MFAS, BIP-8, синдромы RS(255,239);
    #     нагрузка OPUk — дальше, как весь поток (GFP, SDH, …).
    оптика = otn.найти(выборка)
    if оптика is not None:
        ветвь.проверяемая(оптика, путь)
        if оптика.дальше is not None and len(оптика.дальше) >= 8192:
            ветвь.влить(_ступень(np.asarray(оптика.дальше, dtype=np.uint8), глубина,
                                 _дальше(путь, "нагрузка OPU"), б))
        return ветвь
    ветвь.не_найдено.append(f"OTN (G.709){где}: нет")

    # 3. SDH/SONET: кадр по A1 A2, скремблер по B1, VC по B3, TU-12 по V5, E1 по FAS;
    #    нагрузка VC и притоки разбираются так же, как весь поток.
    синхронная = sdh.найти(выборка)
    if синхронная is not None:
        ветвь.проверяемая(синхронная, путь)
        притоки = синхронная.дальше or {}
        for имя, ряд in list(притоки.items())[:ПРИТОКОВ_ГЛУБЖЕ]:
            ветвь.влить(_ступень(ряд, глубина, _дальше(путь, имя), б))
        if len(притоки) > ПРИТОКОВ_ГЛУБЖЕ:
            ветвь.ограничения.append(f"SDH{где}: глубже разобраны первые {ПРИТОКОВ_ГЛУБЖЕ} притоков "
                                     f"из {len(притоки)} — остальные выделяются по одному на странице")
        return ветвь
    ветвь.не_найдено.append(f"SDH/SONET (G.707){где}: нет")

    # 3а. PDH со стаффингом согласования скоростей — притоки разбираются так же.
    иерархия = pdh.найти(выборка)
    if иерархия is not None:
        ветвь.проверяемая(иерархия, путь)
        for номер, приток in иерархия.дальше.items():
            ветвь.влить(_ступень(приток, глубина, _дальше(путь, f"приток {номер}"), б))
        return ветвь
    ветвь.не_найдено.append(f"PDH E2/E3/E4 (G.742/G.751){где}: нет")

    # 3б. PDH Северной Америки: T1 (SF/ESF с CRC-6), DS2 (M12), DS3 (M23, C-bit parity).
    америка = pdh_na.найти(выборка)
    if америка is not None:
        ветвь.проверяемая(америка, путь)
        if америка.вид_дальше == "притоки":
            for номер, приток in америка.дальше.items():
                ветвь.влить(_ступень(приток, глубина, _дальше(путь, f"приток {номер}"), б))
        elif америка.дальше:
            _каналы(америка.дальше, ветвь, путь)
        return ветвь
    ветвь.не_найдено.append(f"PDH T1/DS2/DS3 (G.704, G.743, G.752){где}: нет")

    # 4. Цикл и каналы — и HDLC в каналах.
    по_циклу = _по_циклу(выборка, глубина, путь, б)
    if по_циклу is not None:
        ветвь.влить(по_циклу[0])
        return ветвь
    ветвь.не_найдено.append(f"цикл и синхрослово{где}: нет")
    ветвь.оценка = 0.0
    return None if not ветвь.находки else ветвь


def _по_циклу(выборка: np.ndarray, глубина: int, путь: str, б: Бюджет
              ) -> Optional[Tuple[Ветвь, float]]:
    """Цикл и каналы в нём; если в каналах пусто — нагрузка цикла (кадр модема).

    Возвращает ветвь и оценку того, что открылось ПОД циклом (без самого
    цикла); None — цикла нет.
    """
    цикл = cikl.найти(выборка)
    if цикл is None:
        return None
    ветвь = Ветвь()
    ветвь.проверяемая(цикл, путь)
    свой = ветвь.оценка
    if цикл.дальше:
        _каналы(цикл.дальше, ветвь, путь)
    # В каналах ничего не нашлось — цикл не байтовый мультиплекс, а кадр
    # модема: служебные слова вырезаются, нагрузка разбирается дальше.
    if len(ветвь.находки) == 1 and цикл.свойства.get("длина"):
        след = _цикл_сквозь_код(выборка, цикл)
        if след:
            # Нагрузка такого цикла — нагрузка кода: её разбор съел бы бюджет впустую.
            ветвь.находки[0].свойства["след_кода"] = True
            ветвь.другие.append(f"{путь or 'поток'}: {цикл.суть} — {след}; нагрузка цикла не "
                                f"разбиралась: сначала снимается код")
        else:
            _нагрузка_цикла(выборка, цикл, ветвь, глубина, путь, б)
    return ветвь, ветвь.оценка - свой


def _цикл_сквозь_код(выборка: np.ndarray, цикл: Находка) -> str:
    """Цикл — след синхрослова сквозь свёрточный код: поток — свёрточный код, и после
    декодирования виден цикл с периодом в n раз короче (n — ветвей кода, CCSDS: ASM за 171/133).
    Пустая строка — не след."""
    длина = int(цикл.свойства.get("длина") or 0)
    код = kod.свёрточный(выборка[:1 << 19])
    if not длина or код is None or код.дальше is None:
        return ""
    после = cikl.найти(np.asarray(код.дальше, dtype=np.uint8))
    период = int(после.свойства.get("длина") or 0) if после is not None else 0
    for n in (2, 3, 4):
        if период and период * n == длина:
            return (f"поток — {код.что}, после декодирования — цикл {период} бит: цикл {длина} бит — "
                    f"след синхрослова сквозь код")
    return ""


def _или_по_циклу(напрямую: Ветвь, кадры: Находка, выборка: np.ndarray, глубина: int,
                  путь: str, б: Бюджет) -> Ветвь:
    """Кадры проверились лишь частично: может быть, они в нагрузке кадра модема.

    В сыром потоке кадры рвут вставки кадра модема — синхрослово, служебные
    слова, проверочные символы кода (CCSDS, IESS-308/309, EDMAC), и у части
    кадров FCS не сходится. Тогда пробуется и путь через цикл: он берётся,
    если ПОД циклом (без самого цикла — он есть и у кадров постоянной длины)
    открылось больше, чем напрямую.
    """
    где = f" ({путь})" if путь else ""
    б.сказать(f"{путь or 'поток'}: {кадры.суть} — {кадры.мера}; пробую путь через цикл")
    по_циклу = _по_циклу(выборка, глубина, путь, б)
    if по_циклу is None:
        напрямую.не_найдено.append(f"цикл и синхрослово{где}, в нагрузке которого кадры "
                                   f"проверились бы лучше: нет")
        return напрямую
    через_цикл, под_циклом = по_циклу
    if под_циклом >= напрямую.оценка + ЗАМЕТНО_ЛУЧШЕ:
        через_цикл.другие.append(
            f"{путь or 'поток'}: {кадры.суть} прямо в потоке ({кадры.мера}) — оценка "
            f"{напрямую.оценка:.1f} против {под_циклом:.1f} под циклом: кадры в нагрузке "
            f"цикла, в сыром потоке их рвут вставки кадра")
        через_цикл.не_найдено += напрямую.не_найдено
        return через_цикл
    напрямую.другие.append(
        f"{путь or 'поток'}: {через_цикл.находки[0].суть} — под циклом оценка {под_циклом:.1f} "
        f"против {напрямую.оценка:.1f} у кадров прямо в потоке; {_сводка(через_цикл)}")
    return напрямую


def _плоскости(выборка: np.ndarray, б: Бюджет, глубина: int, путь: str = ""
               ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Подбор модуляционной плоскости — сразу за демодулятором.

    На самом верху или в нагрузке кадра модема (служебные слова вырезаны,
    символы не сдвинулись), если плоскость на пути ещё не подбиралась. Если
    число бит на символ известно (или названо в имени файла: «8PSK»,
    «16QAM») — идёт первым; в глубоком профиле без подсказки пробуются
    КАМ-16, 64 и 256 — последними: это долго.
    """
    if "плоскост" in путь or not (глубина == 0 or путь.endswith("нагрузка цикла")):
        return []
    кам = б.символ or ((4, 6, 8) if б.глубоко and not б.фм else ())

    def срок() -> float:
        return max(1.0, min(б.профиль.get("плоскость", 60.0), б.конец - time.monotonic()))

    return [(f"модуляционная плоскость ФМ-{1 << k}",
             (lambda k=k: ploskost.найти_фм(выборка, k, бюджет=срок())), f"в плоскости ФМ-{1 << k}")
            for k in б.фм] + [
        (f"модуляционная плоскость КАМ-{1 << k}", (lambda k=k: ploskost.найти(выборка, k, бюджет=срок())),
         f"в плоскости КАМ-{1 << k}") for k in кам]


def _детекторы(выборка: np.ndarray, б: Бюджет, глубина: int = 1, путь: str = "",
               блок: Optional[int] = None) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Детекторы преобразований — от дешёвых к дорогим: (имя, вызов, шаг пути).

    ``блок`` — длина блока данных, если ряд — выход декодера блочного кода или
    нагрузка кадра без служебных слов (данные идут блок за блоком от начала
    блока): тогда первыми пробуются ПСП со сбросом на каждом блоке и код
    Рида — Соломона в блоке (с чередованием слов, в обычном и двойном базисе).
    """
    длинные = б.профиль["длинные"]
    плоскости = _плоскости(выборка, б, глубина, путь)
    известна = bool(б.символ or б.фм)
    по_блоку = [(f"ПСП со сбросом на каждом блоке ({блок} бит)",
                 lambda: skrembler.по_блоку(выборка, блок), "после снятия ПСП блока")] if блок else []
    if блок and блок % 8 == 0:
        по_блоку.append((f"код Рида — Соломона в блоке ({блок // 8} байт)",
                         lambda: dlinnye.рс_в_блоке(выборка, блок,
                                                    бюджет=max(1.0, min(30.0, б.конец - time.monotonic()))),
                         "после декодирования РС"))
    return по_блоку + _по_матрицам(выборка, б, блок, глубина) + (плоскости if известна else []) + [
        ("кодирование в линии (манчестерский, 4B/5B, 8B/10B)", lambda: lineynye.найти(выборка),
         "после снятия кодирования в линии"),
        # Код произведения дёшев (~0,5 с) и доказывает себя сам (блоки без нарушений
        # после декодирования) — раньше скремблера: иначе тот «находится» сквозь код.
        ("код произведения (TPC)", lambda: tpc.найти(выборка), "после снятия кода произведения"),
        ("свёрточный 1/2 и короткий блочный код", lambda: kod.найти(выборка, длинные=False),
         "после снятия кода"),
        ("свёрточный код 1/3, 1/4", lambda: svyortka.найти(выборка), "после снятия кода"),
        ("турбокод 1/3", lambda: turbo.найти(выборка), "после турбодекодирования"),
        ("скремблер", lambda: skrembler.найти(выборка), "после снятия скремблера"),
        ("блочное перемежение над кодом", lambda: peremezhenie.найти(выборка),
         "после снятия перемежения и кода"),
    ] + ([
        ("свёрточное перемежение Форни (I × M)", lambda: forni.найти(
            выборка, I_до=б.профиль["форни"]["I_до"], M_до=б.профиль["форни"]["M_до"],
            бюджет=max(1.0, min(б.профиль["форни"]["бюджет"], б.конец - time.monotonic()))),
         "после снятия свёрточного перемежения"),
    ] if б.профиль.get("форни") else []) + [
        ("выколотый свёрточный код", lambda: vykalyvanie.найти(
            выборка, глубоко=б.глубоко, бюджет=max(1.0, min(60.0, б.конец - time.monotonic()))),
         "после снятия выколотого кода"),
        ("длинный блочный код (LDPC, Рида — Соломона, БЧХ)", lambda: dlinnye.найти(
            выборка, до=длинные["до"],
            бюджет=max(1.0, min(длинные["бюджет"], б.конец - time.monotonic()))),
         "после снятия кода"),
    ] + ([] if известна else плоскости)


def _по_матрицам(выборка: np.ndarray, б: Бюджет, блок: Optional[int], глубина: int = 1
                 ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """LDPC по загруженным и встроенным матрицам стандартов.

    Встроенные (5G NR, DVB-S2/S2X/T2 и др.) пробуются, когда известна длина
    блока данных — тогда лишь те, чьё слово ложится в блок, — и, по профилю,
    на самом потоке («обычно») или на каждом уровне («глубоко»); загруженные —
    всегда. Нет ни того, ни другого — не зовётся и в отчёт не пишется.
    """
    режим = б.профиль.get("встроенные_ldpc", "при блоке")
    встроенные = bool(блок) or режим == "везде" or (режим == "наверху" and глубина == 0)
    if not встроенные and not ldpc.список():
        return []
    return [("LDPC по загруженным и встроенным матрицам" if встроенные else "LDPC по загруженным матрицам",
             lambda: ldpc.найти_по_матрицам(выборка, блок=блок, встроенные=встроенные,
                                            бюджет=max(1.0, min(30.0, б.конец - time.monotonic()))),
             "после снятия LDPC")]


def _систематические(выборка: np.ndarray, б: Бюджет, блок: Optional[int], глубина: int = 1
                     ) -> List[tuple[str, Callable[[], Optional[Находка]], str]]:
    """Систематические коды: данные в потоке видны как есть, проверочные символы — рядом.

    Сквозь такой код кадры видны, но у части FCS не сходится: их рвут
    проверочные символы или ошибки, которые код исправил бы. Порядок — от
    дешёвых: код Рида — Соломона в блоке известной длины, код произведения,
    длинные блочные (LDPC, РС, БЧХ).
    """
    длинные = б.профиль["длинные"]
    # Кадры под систематическим кодом видны — его длинный поиск короче обычного
    # (кроме глубокого разбора): частичные кадры бывают и от одних ошибок линии.
    срок = длинные["бюджет"] if б.глубоко else min(длинные["бюджет"], СИСТЕМАТИЧЕСКИЙ_СРОК)
    итог = []
    if блок and блок % 8 == 0:
        итог.append((f"код Рида — Соломона в блоке ({блок // 8} байт)",
                     lambda: dlinnye.рс_в_блоке(выборка, блок,
                                                бюджет=max(1.0, min(30.0, б.конец - time.monotonic()))),
                     "после декодирования РС"))
    return итог + _по_матрицам(выборка, б, блок, глубина) + [
        ("код произведения (TPC)", lambda: tpc.найти(выборка), "после снятия кода произведения"),
        ("длинный блочный код (LDPC, Рида — Соломона, БЧХ)", lambda: dlinnye.найти(
            выборка, до=длинные["до"], бюджет=max(1.0, min(срок, б.конец - time.monotonic()))),
         "после снятия кода"),
    ]


def _или_систематический(напрямую: Ветвь, выборка: np.ndarray, глубина: int, путь: str,
                         б: Бюджет, блок: Optional[int]) -> Ветвь:
    """Кадры проверились частично — пробуются систематические коды под ними.

    Декодирование берётся, если после него проверяемое заметно лучше, чем
    напрямую (FCS сходится у большей доли кадров): ложный код кадры не чинит,
    а портит.
    """
    кадры = напрямую.частично
    где = f" ({путь})" if путь else ""
    if глубина >= б.профиль["глубина"] or б.вышел():
        напрямую.ограничения.append(
            f"{кадры.суть}{где} проверены частично ({кадры.мера}); систематический код под ними не "
            f"искался — " + ("время разбора исчерпано" if б.вышел() else f"предел глубины {глубина}"))
        return напрямую
    лучшее = None
    пробовали = []
    for имя, найти, шаг in _систематические(выборка, б, блок, глубина):
        if б.вышел():
            напрямую.не_найдено.append(f"{имя}{где}: не проверено — время разбора исчерпано")
            continue
        б.сказать(f"{путь or 'поток'}: {кадры.суть} — {кадры.мера}; пробую под ними: {имя}")
        найдено = найти()
        пробовали.append(имя)
        if найдено is None:
            continue
        for находка, ряд in _варианты(найдено):
            if len(ряд) < 8192:
                continue
            ниже = _ступень(ряд, глубина + 1, _дальше(путь, шаг), б, _блок_данных(находка))
            if (ниже.оценка >= напрямую.оценка + ЗАМЕТНО_ЛУЧШЕ
                    and (лучшее is None or ниже.оценка > лучшее[1].оценка)):
                лучшее = (находка, ниже)
            else:
                напрямую.другие.append(
                    f"{путь or 'поток'}: {находка.суть} (уверенность {round(находка.уверенность * 100)} %) "
                    f"— после декодирования оценка {ниже.оценка:.1f} против {напрямую.оценка:.1f} у кадров "
                    f"напрямую: не лучше; {_сводка(ниже)}")
        if лучшее is not None and лучшее[1].частично is None:
            break
    if лучшее is None:
        напрямую.не_найдено.append(
            f"систематический код под частично проверенными кадрами{где} ({', '.join(пробовали)}): "
            f"нет такого, после декодирования которого кадры проверялись бы лучше")
        return напрямую
    находка, ниже = лучшее
    ветвь = Ветвь()
    ветвь.находки.append(_с_путём(находка, путь))
    ветвь.оценка = ВЕС_ПРЕОБРАЗОВАНИЯ * находка.уверенность
    ветвь.влить(ниже)
    ветвь.частично = ниже.частично
    ветвь.другие.append(
        f"{путь or 'поток'}: {кадры.суть} прямо в потоке ({кадры.мера}) — оценка {напрямую.оценка:.1f} "
        f"против {ниже.оценка:.1f} после декодирования: {находка.суть}")
    ветвь.не_найдено += напрямую.не_найдено
    return ветвь


def _варианты(найдено: Находка) -> List[tuple[Находка, np.ndarray]]:
    """Находка → (находка, снятый ряд); у манчестерского — по варианту на толкование."""
    if найдено.вид_дальше == "варианты":
        return [(Находка(**{**найдено.__dict__, "что": f"{найдено.что}, {вариант}",
                           "дальше": ряд, "вид_дальше": "биты"}), ряд)
                for вариант, ряд in найдено.дальше.items()]
    if найдено.дальше is not None and len(найдено.дальше):
        return [(найдено, np.asarray(найдено.дальше, dtype=np.uint8))]
    return [(найдено, np.zeros(0, dtype=np.uint8))]


#: Оценка ветви, при которой гипотеза подтверждена проверяемой находкой ниже
#: и остальные детекторы уровня можно не звать.
ПОДТВЕРЖДЕНО = 0.9 * ВЕС_ПРОВЕРЯЕМОЙ
