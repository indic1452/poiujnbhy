"""Блочное перемежение: слова кода по строкам, передача по столбцам.

Перемежитель R × C пишет кодовые слова в строки таблицы и читает её по
столбцам: соседние биты линии принадлежат разным словам, и пакет ошибок
размазывается по многим словам. Для анализатора это значит: код в потоке
не виден — у слова биты разнесены на R позиций.

Ключ к слепому разбору — прореживание: если взять из потока каждый R-й бит,
получится одна строка за другой, то есть обычный поток кодовых слов. Фаза
прореживания не важна — любая фаза даёт какую-то строку. Поэтому перебор
идёт только по глубине R: на каждой проверяем, появилась ли в прореженном
ряду проверочная связь (метод Уолша — Адамара, как у кодов). Верная R даёт
связь в десятки сигм, неверная — шум.

Восстановление порядка. Выравнивание слов в разных фазах прореживания
отличается на один бит ровно у фаз, стоящих до «нулевой» строки блока: так
находится начало блока, и строки собираются обратно в исходный порядок. Это
делается в предположении «одна строка — одно слово» (C = n) — самом частом;
при нескольких словах в строке слова целы, но их порядок может быть иным,
о чём и сказано в отчёте.
"""

from __future__ import annotations

import re

import numpy as np

from . import cikl, kod
from .nahodka import Находка

ГЛУБИНА_ДО = 64
ОКНО = 16
#: Сколько бит прореженного ряда смотреть при отсеве глубины.
ОТСЕВ = 1 << 15
#: Во сколько сигм шума должна быть связь, чтобы глубина засчитывалась.
ПОРОГ_СИГМ = 10.0
#: Во сколько раз связь при верной глубине сильнее медианы по всем глубинам.
ВЫДЕЛЯЕТСЯ = 2.0
#: Сколько глубин-кандидатов проверять поиском кода.
КАНДИДАТОВ = 6
#: Пик автокорреляции, выше которого поток считается строго периодическим.
ПЕРИОДИЧЕСКИЙ = 0.15


def _сила(ряд: np.ndarray) -> float:
    """Сильнейшая проверочная связь в скользящем окне — в сигмах шума."""
    смещения, окон = kod.проверки(ряд, ОКНО, 1)
    if окон < 256:
        return 0.0
    смещения[0] = 0
    return float(np.abs(смещения).max() * np.sqrt(окон))


def глубины(биты: np.ndarray) -> list[tuple[int, float]]:
    """Глубины перемежения R, при которых прореженный ряд похож на код, — с силой.

    Порог — относительный: у структурированных данных без кода (заголовки,
    флаги, текст) слабые связи есть при любом прореживании, и абсолютный
    порог в сигмах их принял бы. Верная глубина выделяется над медианой всех
    глубин минимум вдвое. Кандидатов обычно несколько: делитель истинной
    глубины берёт строки вперемежку (код вдвое длиннее), кратная при нечётной
    длине строки обходит строку в переставленном порядке (тот же код). Выбор
    между ними — по найденному коду, в ``найти``.
    """
    силы = []
    for R in range(2, ГЛУБИНА_ДО + 1):
        ряд = биты[::R][:ОТСЕВ]
        if len(ряд) < ОТСЕВ // 2:
            break
        силы.append((R, _сила(ряд)))
    if len(силы) < 4:
        return []
    база = float(np.median([сила for _, сила in силы]))
    сильные = [(R, сила) for R, сила in силы
               if сила >= ПОРОГ_СИГМ and сила >= ВЫДЕЛЯЕТСЯ * база]
    if not сильные:
        return []
    наибольшая = max(сила for _, сила in сильные)
    return [(R, сила) for R, сила in сильные if сила >= 0.5 * наибольшая][:КАНДИДАТОВ]


def _длина_слова(код: Находка) -> int:
    найдено = re.search(r"\((\d+), \d+\)", код.что)
    return int(найдено.group(1)) if найдено else 2


def _выравнивание(ряд: np.ndarray, n: int) -> int:
    """С какого бита начинаются слова длины n: больше всего сильных проверок."""
    лучший, счёт = 0, -1
    for сдвиг in range(n):
        смещения, слов = kod.проверки(ряд, n, n, сдвиг)
        смещения[0] = 0
        сильных = int(np.count_nonzero(np.abs(смещения) > max(0.4, 8 / np.sqrt(max(1, слов)))))
        if сильных > счёт:
            лучший, счёт = сдвиг, сильных
    return лучший


def собрать(биты: np.ndarray, R: int, n: int) -> tuple[np.ndarray, int]:
    """Обратное перемежение при C = n: поток слов в исходном порядке и начало блока."""
    фазы = [биты[φ::R] for φ in range(R)]
    выравнивания = [_выравнивание(ф[:ОТСЕВ], n) for ф in фазы]
    # Фазы до нулевой строки (φ < o) выровнены на бит позже, по модулю n;
    # последняя фаза всегда из «поздних» по строке, но не по выравниванию:
    # её выравнивание — опорное q.
    q = выравнивания[-1]
    o = 0
    while o < R - 1 and n > 1 and выравнивания[o] == (q + 1) % n:
        o += 1
    начала: list[int] = [q + 1 if φ < o else q for φ in range(R)]
    блоков = min((len(фазы[φ]) - начала[φ]) // n for φ in range(R))
    строки = []
    for r in range(R):
        φ = (o + r) % R
        строки.append(фазы[φ][начала[φ]:начала[φ] + блоков * n].reshape(блоков, n))
    собрано = np.stack(строки, axis=1).reshape(-1)
    return собрано, o


def найти(биты: np.ndarray) -> Находка | None:
    """Блочное перемежение над кодом: глубина, код в строках, обратный порядок."""
    if len(биты) < ОТСЕВ * 4:
        return None
    # Строго периодический поток (цикл без данных, повторяющийся текст) при
    # любом прореживании остаётся периодическим и «похож на код». У
    # перемежённого кода над реальными данными пик автокорреляции слабый.
    цикл = cikl.длина_цикла(биты)
    if цикл is not None and цикл[1] > ПЕРИОДИЧЕСКИЙ:
        return None
    # Из кандидатов — сперва по сверке с потоком (доля слов с нулевым
    # синдромом, совпадение перекодированного): ложное толкование сходится
    # хуже. Затем — где слово кода короче (делитель глубины даёт слово вдвое
    # длиннее), при равной длине — наименьшая глубина (кратная даёт тот же
    # код в переставленном порядке).
    лучший = None
    for R, сила in глубины(биты):
        код = kod.найти(биты[::R])
        if код is None:
            continue
        ключ = (-round(код.сверка, 2), _длина_слова(код), R)
        if лучший is None or ключ < лучший[0]:
            лучший = (ключ, R, сила, код)
    if лучший is None:
        return None
    _, R, сила, код = лучший
    подробно = [
        f"глубина перемежения R = {R}: в каждом {R}-м бите — проверочная связь "
        f"в {сила:.0f} сигм шума, заметно сильнее, чем при других глубинах",
        f"в строке перемежителя: {код.что} ({код.мера})",
    ]
    дальше = None
    вид_дальше = ""
    if "блочный" in код.что:
        n = int(код.что.split("(", 1)[1].split(",", 1)[0])
        собрано, o = собрать(биты, R, n)
        повторно = kod.найти(собрано)
        if повторно is not None:
            дальше, вид_дальше = повторно.дальше, повторно.вид_дальше
            подробно.append(
                f"порядок восстановлен: начало блока — фаза {o}; в предположении «строка = "
                f"одно слово» (C = n = {n}, блок {R * n} бит). Если в строке несколько "
                f"слов, слова целы, но их порядок между строками может отличаться")
            подробно += повторно.подробно[:2]
    else:
        подробно.append("для свёрточного кода порядок не восстанавливается: длина строки "
                        "перемежителя неизвестна; код и его многочлены определены по "
                        "прореженному ряду")
    return Находка(
        уровень="перемежение", что=f"блочное перемежение глубиной {R}, в строках — {код.что}",
        уверенность=min(1.0, сила / 50) * код.уверенность,
        мера=f"после прореживания через {R} бит {код.мера}",
        подробно=подробно, дальше=дальше, вид_дальше=вид_дальше)
