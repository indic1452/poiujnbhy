"""Находка анализатора: что найдено, насколько уверенно, что дальше.

Уверенность — не ощущение, а мера, которую можно пересчитать: доля кадров
с верной FCS, доля циклов с совпавшим синхрословом, во сколько раз упал
ранг матрицы. Модель получает её рядом с выводом и обязана на неё
опираться: «найдено HDLC» без «FCS верна у 97 %» — не находка, а догадка.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class Находка:
    уровень: str                  # «код», «скремблер», «цикл», «канальный», «сетевой» …
    что: str                      # коротко: «HDLC, FCS-16»
    уверенность: float            # 0…1
    мера: str                     # на чём держится уверенность — словами и числом
    подробно: list[str] = field(default_factory=list)
    #: Что передать следующему уровню разбора: биты, байты или кадры.
    дальше: Any = None
    вид_дальше: str = ""          # «биты», «байты», «кадры»
    #: Доля потока, на которой находка подтверждается (слова с нулевым
    #: синдромом, совпадение перекодированного) — для выбора между
    #: соперничающими толкованиями одного ряда.
    сверка: float = 0.0
    #: Где в цепочке найдено: «после снятия кода → приток 2 → КИ1».
    путь: str = ""
    #: Числа находки для следующих шагов разбора (длина цикла и т. п.).
    свойства: dict = field(default_factory=dict)

    @property
    def суть(self) -> str:
        """«Что» без пути — для сведения одинаковых находок в разных притоках."""
        хвост = f" — в потоке {self.путь}"
        return self.что[:-len(хвост)] if self.путь and self.что.endswith(хвост) else self.что

    def строка(self) -> str:
        return (f"[{self.уровень}] {self.что} — уверенность "
                f"{round(self.уверенность * 100)} % ({self.мера})")
