#: Известные блочные коды: (n, k) → название.
ИЗВЕСТНЫЕ: Dict[Tuple[int, int], str] = {
    (7, 4): "Хэмминга (7, 4)", (8, 4): "расширенный Хэмминга (8, 4)",
    (15, 11): "Хэмминга (15, 11)", (15, 7): "БЧХ (15, 7)", (15, 5): "БЧХ (15, 5)",
    (23, 12): "Голея (23, 12)", (24, 12): "расширенный Голея (24, 12)",
    (31, 26): "Хэмминга (31, 26)", (31, 21): "БЧХ (31, 21)", (31, 16): "БЧХ (31, 16)",
    (63, 57): "Хэмминга (63, 57)", (63, 51): "БЧХ (63, 51)", (63, 45): "БЧХ (63, 45)",
    (127, 120): "Хэмминга (127, 120)", (127, 113): "БЧХ (127, 113)",
}
#: Известные свёрточные коды скорости 1/2: (g1, g2) восьмерично → название.
СВЁРТОЧНЫЕ: Dict[Tuple[int, int], str] = {
    (0o171, 0o133): "K=7, 171/133 (NASA, DVB-S, IEEE 802.11, Intelsat)",
    (0o7, 0o5): "K=3, 7/5", (0o15, 0o17): "K=4, 15/17", (0o23, 0o35): "K=5, 23/35",
    (0o53, 0o75): "K=6, 53/75", (0o561, 0o753): "K=9, 561/753 (CDMA IS-95)",
}
#: До какой длины строки смотреть ранг, бит.
НАИБОЛЬШАЯ_L = 160
#: Витерби находит ближайшее кодовое слово к ЛЮБОМУ ряду: у случайных бит
#: перекодированное расходится с принятым лишь на 12–16 %, а не на половину.
#: Поэтому сравнение — с этим же декодером на случайных битах: в каждой
#: восьмой части выборки расхождение должно быть не больше этой доли от
#: случайного (у настоящего кода при 7 % ошибок линии — около 0,56).
ДОЛЯ_ОТ_СЛУЧАЙНОГО = 0.75
#: Во сколько раз расхождение перекодированного может превышать ошибки линии, оценённые по связи.
СОГЛАСИЕ_СВЯЗИ = 1.5
#: Доля слов, где выполнены все проверки блочного кода сразу, — меньше не код (связи заполнения).
НУЛЕВОЙ_СИНДРОМ_ОТ = 0.25
#: Смещение проверочной связи, от которого она считается связью кода. При
#: доле ошибок p связь веса w смещена на (1 − 2p)^w: у K = 7 (w = 10) при 5 %
#: ошибок — около 0,35, при 7 % — 0,23. Ложные связи структурированных
#: данных отсекает проверка перекодированием (СОВПАДЕНИЕ_СВЁРТОЧНОГО).
ПОРОГ_СВЯЗИ_СВЁРТОЧНОГО = 0.2


def ранг(строки: Sequence[int]) -> Tuple[int, List[int]]:
    """Ранг над GF(2) строк-целых и базис (строки в ступенчатом виде)."""
    базис: Dict[int, int] = {}              # старший бит → строка
    for строка in строки:
        while строка:
            старший = строка.bit_length() - 1
            if старший not in базис:
                базис[старший] = строка
                break
            строка ^= базис[старший]
    return len(базис), list(базис.values())


def _строки(биты: np.ndarray, длина: int, сколько: int, начало: int = 0) -> List[int]:
    """Строки заданной длины подряд — как целые (старший бит — первый)."""
    сколько = min(сколько, (len(биты) - начало) // длина)
    if сколько <= 0:
        return []
    таблица = биты[начало:начало + длина * сколько].reshape(сколько, длина)
    добавить = (-длина) % 8
    if добавить:
        таблица = np.pad(таблица, ((0, 0), (добавить, 0)))
    упаковано = np.packbits(таблица, axis=1)
    return [int.from_bytes(строка.tobytes(), "big") for строка in упаковано]


def недостача(биты: np.ndarray, длина: int, начало: int = 0) -> int:
    """На сколько ранг матрицы из строк этой длины меньше полного."""
    строки = _строки(биты, длина, 2 * длина + 16, начало)
    if len(строки) < длина + 10:
        return 0
    return длина - ранг(строки)[0]


def профиль(биты: np.ndarray, наибольшая: int = НАИБОЛЬШАЯ_L) -> Dict[int, int]:
    """d(L) — недостача ранга для каждой длины строки."""
    return {длина: недостача(биты, длина) for длина in range(2, наибольшая + 1)}


def блочный(биты: np.ndarray, d: Dict[int, int]) -> Находка | None:
    """Блочный код по профилю недостачи: падения только на кратных n."""
    с_недостачей = [длина for длина, недо in d.items() if недо > 0]
    if len(с_недостачей) < 2:
        return None
    n = 0
    for длина in с_недостачей:
        n = gcd(n, длина)
    if n < 3:
        return None
    # Падения должны быть на кратных n и почти только на них.
    чужие = [длина for длина in с_недостачей if длина % n]
    if len(чужие) > len(с_недостачей) // 10:
        return None
    # Выравнивание: при верном ранг строк длины n меньше всего.
    выравнивания = [(недостача(биты, n, сдвиг), сдвиг) for сдвиг in range(n)]
    лучшая, сдвиг = max(выравнивания)
    if лучшая <= 0:
        return None
    k = n - лучшая
    строки = _строки(биты, n, 3 * n + 20, сдвиг)
    _, базис = ранг(строки)
    # Информационные позиции — опорные столбцы ступенчатого базиса.
    опорные = sorted(n - 1 - строка.bit_length() + 1 for строка in базис)
    информационные = _информационные(биты[сдвиг:], n, k)
    # Совпадение (n, k) с известным кодом — ещё не опознание: у БЧХ (31, 21) и
    # случайного линейного кода (31, 21) параметры одни. Говорим как есть.
    имя = f"линейный блочный ({n}, {k})" + (
        f" — параметры как у кода {ИЗВЕСТНЫЕ[(n, k)]}" if (n, k) in ИЗВЕСТНЫЕ else "")
    слов = (len(биты) - сдвиг) // n
    таблица = биты[сдвиг:сдвиг + слов * n].reshape(слов, n)
    данные = таблица[:, информационные].reshape(-1)
    # Проверка: доля слов, удовлетворяющих всем проверочным соотношениям.
    проверки = _ядро(строки, n)
    if проверки:
        матрица = np.array([[(h >> (n - 1 - i)) & 1 for i in range(n)] for h in проверки],
                           dtype=np.uint8)
        синдромы = (таблица.astype(np.int64) @ матрица.T.astype(np.int64)) % 2
        верных = float(np.mean(~синдромы.any(axis=1)))
    else:
        верных = 1.0
    return Находка(
        уровень="код", что=f"{имя}, скорость {k}/{n}",
        уверенность=верных,
        мера=f"все проверочные соотношения выполнены у {round(верных * 100, 1)} % слов; "
             f"ранг строк длины {n} при верном выравнивании — {k} из {n}",
        подробно=[
            f"длина слова n = {n}, информационных бит k = {k}, проверочных {n - k}",
            f"начало слова — бит {сдвиг}",
            "недостача ранга по длине строки: " + ", ".join(
                f"L={длина}: {d[длина]}" for длина in с_недостачей[:6]),
            f"информационные позиции в слове: {', '.join(map(str, информационные))}",
            f"проверочных соотношений найдено: {len(проверки)}",
            "доля слов с нулевым синдромом ниже 100 % — это ошибки линии: код их "
            "исправляет, а наш разбор берёт информационные биты как есть",
        ],
        дальше=данные, вид_дальше="биты")


def _информационные(биты: np.ndarray, n: int, k: int) -> List[int]:
    """k столбцов, линейно независимых в кодовых словах, — информационное множество.

    Для систематического кода это ровно позиции данных; для несистематического
    — позиции, из которых данные однозначно восстанавливаются.
    """
    слов = min(len(биты) // n, 4 * n + 40)
    столбцы = биты[:слов * n].reshape(слов, n).T
    выбранные: List[int] = []
    базис: Dict[int, int] = {}
    for номер, столбец in enumerate(столбцы):
        значение = int("".join(map(str, столбец.tolist())), 2)
        исходное = значение
        while значение:
            старший = значение.bit_length() - 1
            if старший not in базис:
                базис[старший] = значение
                выбранные.append(номер)
                break
            значение ^= базис[старший]
        if len(выбранные) == k:
            break
        del исходное
    return выбранные


def _ядро(строки: Sequence[int], n: int) -> List[int]:
    """Базис ядра (проверочные соотношения) матрицы из строк-слов длины n."""
    матрица = np.array([[(строка >> (n - 1 - i)) & 1 for i in range(n)] for строка in строки],
                       dtype=np.uint8)
    # Приведение к ступенчатому виду по столбцам.
    m = матрица.copy()
    опорные = []
    ряд = 0
    for столбец in range(n):
        строки_с = np.flatnonzero(m[ряд:, столбец]) + ряд if ряд < len(m) else []
        if not len(строки_с):
            continue
        опора = строки_с[0]
        m[[ряд, опора]] = m[[опора, ряд]]
        лишние = np.flatnonzero(m[:, столбец])
        лишние = лишние[лишние != ряд]
        m[лишние] ^= m[ряд]
        опорные.append(столбец)
        ряд += 1
        if ряд == len(m):
            break
    свободные = [столбец for столбец in range(n) if столбец not in опорные]
    ядро = []
    for свободный in свободные:
        вектор = np.zeros(n, dtype=np.uint8)
        вектор[свободный] = 1
        for строка, опорный in enumerate(опорные):
            вектор[опорный] = m[строка, свободный]
        ядро.append(int("".join(map(str, вектор.tolist())), 2))
    return ядро


def уолш(вектор: np.ndarray) -> np.ndarray:
    """Быстрое преобразование Уолша — Адамара."""
    a = вектор.astype(np.float64).copy()
    h = 1
    while h < len(a):
        a = a.reshape(-1, 2 * h)
        x = a[:, :h].copy()
        a[:, :h] += a[:, h:]
        a[:, h:] = x - a[:, h:]
        a = a.reshape(-1)
        h *= 2
    return a


def _окна(биты: np.ndarray, ширина: int, шаг: int, начало: int = 0) -> np.ndarray:
    """Окна заданной ширины с шагом — как целые (старший бит — самый ранний)."""
    ряд = биты[начало:].astype(np.int64)
    сколько = (len(ряд) - ширина) // шаг + 1
    if сколько <= 0:
        return np.array([], dtype=np.int64)
    значения = np.zeros(сколько, dtype=np.int64)
    for j in range(ширина):
        значения = (значения << 1) | ряд[j:j + шаг * сколько:шаг][:сколько]
    return значения


def проверки(биты: np.ndarray, ширина: int, шаг: int, начало: int = 0
             ) -> Tuple[np.ndarray, int]:
    """Для КАЖДОЙ проверки h на окне этой ширины — насколько часто она выполнена.

    Возвращает смещения (bias) по всем 2^ширина проверкам — от −1 до 1; у
    верной проверочной связи кода при доле ошибок p смещение около
    (1 − 2p)^вес, у случайной — около 1/√N. Ошибки линии не ломают метод, в
    отличие от ранга: связь просто выполняется чуть реже.
    """
    окна = _окна(биты, ширина, шаг, начало)
    гистограмма = np.bincount(окна, minlength=1 << ширина).astype(np.float64)
    return уолш(гистограмма) / max(1, len(окна)), len(окна)


def свёрточный(биты: np.ndarray) -> Находка | None:
    """Свёрточный код скорости 1/2 — по проверочной связи, устойчиво к ошибкам.

    Проверочная связь h кода с ограничением K занимает ровно K пар бит.
    Ищем наименьшее K, при котором есть сильная связь (смещение > 0,35), по
    обоим выравниваниям пары: при сбитом выравнивании тот же код выглядит
    как код с K + 1, и название было бы неверным.
    """
    выборка = биты[:1 << 18]
    лучшее = None
    for сдвиг in (0, 1):
        for k in range(3, 10):
            ширина = 2 * k
            смещения, окон = проверки(выборка, ширина, 2, сдвиг)
            порог = max(ПОРОГ_СВЯЗИ_СВЁРТОЧНОГО, 8 / np.sqrt(max(1, окон)))
            смещения[0] = 0
            сильные = np.flatnonzero(np.abs(смещения) > порог)
            годные = []
            for h in сильные:
                h = int(h)
                первая = h >> (ширина - 2)          # первая пара окна
                последняя = h & 0b11                # последняя пара окна
                if первая and последняя:
                    годные.append((abs(смещения[h]), h))
            if годные:
                сила, h = max(годные)
                if лучшее is None or (k, -сила) < (лучшее[0], -лучшее[1]):
                    лучшее = (k, сила, h, сдвиг)
                break
    if лучшее is None:
        return None
    k, сила, h, сдвиг = лучшее
    ширина = 2 * k
    биты_h = [(h >> (ширина - 1 - i)) & 1 for i in range(ширина)]
    # Окно идёт от старого бита к новому, в многочлене старший бит — самый
    # старый вход: порядок совпадает. c1·g2 + c2·g1 = 0 → h1 = g2, h2 = g1.
    g2 = int("".join(map(str, биты_h[0::2])), 2)
    g1 = int("".join(map(str, биты_h[1::2])), 2)
    if not g1 or not g2:
        return None                      # вырожденный «код»: одна из ветвей пуста
    if bin(g1).count("1") == 1 and bin(g2).count("1") == 1:
        # Обе ветви — чистые задержки: проверочного бита нет, это просто
        # корреляция бит данных (у текста — бит через четыре), а не код. У
        # систематического кода одна ветвь — задержка, но другая — сумма.
        return None
    данные = витерби(биты[сдвиг:сдвиг + (1 << 18)], g1, g2, k)
    перекодировано = _кодировать(данные, g1, g2, k)
    длина = min(len(перекодировано), len(биты) - сдвиг)
    совпало = float(np.mean(перекодировано[:длина] == биты[сдвиг:сдвиг + длина]))
    # Связь веса w при ошибках линии p выполнена с перекосом (1 − 2p)^w: по перекосу
    # видно, сколько ошибок в линии. У кода перекодированное расходится с принятым
    # не больше, чем на эти ошибки; у ложной связи (данные сами линейны — ПСП,
    # заполнение) расхождение много больше, чем «позволяет» связь.
    ошибок_по_связи = (1 - сила ** (1 / bin(h).count("1"))) / 2
    if 1 - совпало > СОГЛАСИЕ_СВЯЗИ * ошибок_по_связи + 0.005:
        return None
    # Декодированное и перекодированное совпадает с принятым с точностью до
    # ошибок линии — и так в каждой части выборки, а не в среднем: код лишь
    # в части потока или случайная связь дают участки на уровне случайного.
    база = _расхождение_на_случайном(g1, g2, k)
    расходится = (перекодировано[:длина] != биты[сдвиг:сдвиг + длина])
    части = [float(ч.mean()) for ч in np.array_split(расходится, 8) if len(ч)]
    if max(части) > ДОЛЯ_ОТ_СЛУЧАЙНОГО * база:
        return None
    имя = СВЁРТОЧНЫЕ.get((g1, g2)) or СВЁРТОЧНЫЕ.get((g2, g1)) or f"K={k}"
    if (g1, g2) not in СВЁРТОЧНЫЕ and (g2, g1) not in СВЁРТОЧНЫЕ:
        имя = f"K={k}, {g1:o}/{g2:o}"
    return Находка(
        уровень="код", что=f"свёрточный код скорости 1/2, {имя}",
        уверенность=min(1.0, сила / 0.5) * (1.0 if совпало > 0.9 else 0.7),
        мера=f"проверочная связь выполнена в {round((1 + сила) / 2 * 100, 1)} % окон; "
             f"поток, перекодированный из декодированных бит, совпал с исходным "
             f"в {round(совпало * 100, 2)} % бит",
        подробно=[
            f"порождающие многочлены (восьмерично): g1 = {g1:o}, g2 = {g2:o}, "
            f"кодовое ограничение K = {k}",
            f"первый бит пары — бит {сдвиг} потока",
            f"оценка доли ошибок в линии: {round((1 - совпало) * 100, 2)} % "
            f"(расхождение перекодированного с принятым; у случайного ряда этот же "
            f"декодер дал бы {round(база * 100, 1)} %)",
            f"декодер Витерби (жёсткие решения) по первым {min(len(биты) - сдвиг, 1 << 18)} "
            f"бит потока — эта часть данных отдана следующему уровню",
        ],
        дальше=данные, вид_дальше="биты", сверка=совпало)


@lru_cache(maxsize=64)
def _расхождение_на_случайном(g1: int, g2: int, k: int) -> float:
    """Доля расхождения перекодированного с принятым, если принят случайный ряд."""
    случайные = np.random.default_rng(12345).integers(0, 2, 1 << 14, dtype=np.uint8)
    данные = витерби(случайные, g1, g2, k)
    перекодировано = _кодировать(данные, g1, g2, k)
    return float(np.mean(перекодировано != случайные[:len(перекодировано)]))


def блочный_устойчивый(биты: np.ndarray, наибольшая_n: int = 16) -> Находка | None:
    """Короткий блочный код (n ≤ 16) — по проверкам, устойчиво к ошибкам.

    При верных n и выравнивании сильные проверки образуют подпространство
    из 2^(n−k) проверок (вместе с нулевой): отсюда n − k. Ранговый метод
    ниже этого не умеет при ошибках линии: одна ошибка в строке — и
    зависимость строк пропадает.
    """
    выборка = биты[:1 << 18]
    лучшее = None
    for n in range(3, наибольшая_n + 1):
        for сдвиг in range(n):
            смещения, слов = проверки(выборка, n, n, сдвиг)
            if слов < 64:
                break
            порог = max(0.4, 8 / np.sqrt(слов))
            смещения[0] = 0
            сильных = int(np.count_nonzero(np.abs(смещения) > порог))
            if not сильных:
                continue
            проверочных = int(round(np.log2(сильных + 1)))
            if (1 << проверочных) != сильных + 1:
                continue                         # не подпространство — не код
            if проверочных >= n:
                # Выполнены все связи — слова одинаковые (заполнение с периодом,
                # кратным n): данных в них нет, это не код.
                continue
            # Сравниваем все n по доле проверок (n − k)/n: на половине длины
            # настоящего слова одна связь выполняется в половине слов и даёт
            # ложный (n/2, n/2 − 1); на кратной длине доля та же, что у
            # настоящей, — и при равенстве побеждает меньшая n.
            доля = проверочных / n
            if лучшее is None or доля > лучшее[0] + 1e-9:
                лучшее = (доля, n, сдвиг, проверочных, смещения, сильных)
    if лучшее is None:
        return None
    _, n, сдвиг, проверочных, смещения, сильных = лучшее
    k = n - проверочных
    сильные = [int(h) for h in np.flatnonzero(np.abs(смещения) > max(0.4, 0.0)) if h]
    средняя = float(np.mean([abs(смещения[h]) for h in сильные]))
    имя = f"линейный блочный ({n}, {k})" + (
        f" — параметры как у кода {ИЗВЕСТНЫЕ[(n, k)]}" if (n, k) in ИЗВЕСТНЫЕ else "")
    информационные = _информационные(биты[сдвиг:], n, k)
    слов = (len(биты) - сдвиг) // n
    слова = биты[сдвиг:сдвиг + слов * n].reshape(слов, n)
    данные = слова[:, информационные].reshape(-1)
    # Доля слов, где выполнены ВСЕ найденные проверки, — нулевой синдром. Хватает
    # базиса подпространства (проверочных векторов), а не всех 2^(n−k) − 1 связей.
    базис: List[int] = []
    for h in сильные:
        for b in базис:
            h = min(h, h ^ b)
        if h:
            базис.append(h)
    проверки_ = np.array([[(h >> (n - 1 - i)) & 1 for i in range(n)] for h in базис],
                         dtype=np.int64)
    образец = слова[:1 << 15].astype(np.int64)
    синдром_нулевой = float(np.mean(np.all((образец @ проверки_.T) % 2 == 0, axis=1)))
    if синдром_нулевой < НУЛЕВОЙ_СИНДРОМ_ОТ:
        # Связи выполнены по отдельности, но все сразу — редко: это постоянные
        # (аффинные) связи периодического заполнения, а не проверки кода.
        return None
    return Находка(
        уровень="код", что=f"{имя}, скорость {k}/{n}",
        уверенность=min(1.0, средняя / 0.6),
        мера=f"{сильных} проверочных связей (подпространство размерности {проверочных}) "
             f"выполнены в среднем в {round((1 + средняя) / 2 * 100, 1)} % слов; все "
             f"сразу — в {round(синдром_нулевой * 100, 1)} % слов",
        подробно=[f"длина слова n = {n}, информационных бит k = {k}, начало слова — бит {сдвиг}",
                  f"информационные позиции в слове: {', '.join(map(str, информационные))}",
                  "найдено по проверкам Уолша — Адамара: метод терпит ошибки линии",
                  "информационные биты взяты как есть, без исправления ошибок"],
        дальше=данные, вид_дальше="биты", сверка=синдром_нулевой)


def _кодировать(данные: np.ndarray, g1: int, g2: int, k: int) -> np.ndarray:
    регистр = 0
    выход = np.zeros(2 * len(данные), dtype=np.uint8)
    for номер, бит in enumerate(данные):
        регистр = ((регистр << 1) | int(бит)) & ((1 << k) - 1)
        выход[2 * номер] = bin(регистр & g1).count("1") & 1
        выход[2 * номер + 1] = bin(регистр & g2).count("1") & 1
    return выход


#: Ячеек обратного хода (шаг × состояние) в памяти: больше — решения выдаются окнами.
ЯЧЕЕК_ДО = 1 << 24
#: Глубина обратного хода в кодовых ограничениях: решения старше неё уже не меняются.
ГЛУБИНА_В_K = 10


def витерби_n(биты: np.ndarray, многочлены: Sequence[int], K: int,
              известно: np.ndarray | None = None) -> np.ndarray:
    """Декодер Витерби кода 1/n с жёсткими решениями, векторно по состояниям.

    Регистр — (s << 1) | бит, выход ветви j — чётность (регистр & g_j).
    ``известно`` — маска переданных бит (у выколотого кода выброшенные — стирания,
    в метрику не входят). Память ограничена: таблица обратного хода держит
    не больше ЯЧЕЕК_ДО ячеек, и решения выдаются окнами с перекрытием в
    ГЛУБИНА_В_K·K шагов — при K = 15 и сотнях тысяч шагов полная таблица заняла
    бы гигабайты.
    """
    n = len(многочлены)
    состояний = 1 << (K - 1)
    шагов = len(биты) // n
    итог = np.zeros(шагов, dtype=np.uint8)
    if not шагов:
        return итог
    блоки = биты[:n * шагов].reshape(шагов, n).astype(np.int32)
    маска = (np.ones((шагов, n), dtype=np.int32) if известно is None
             else известно[:n * шагов].reshape(шагов, n).astype(np.int32))
    s = np.arange(состояний)
    выходы = np.zeros((состояний, 2, n), dtype=np.int32)
    for b in (0, 1):
        регистр = (s << 1) | b
        for j, g in enumerate(многочлены):
            выходы[:, b, j] = np.array([bin(int(r) & int(g)).count("1") & 1 for r in регистр])
    куда = (((s[:, None] << 1) | np.array([0, 1])[None, :]) & (состояний - 1)).reshape(-1)
    метрика = np.full(состояний, 10 ** 6, dtype=np.int64)
    метрика[0] = 0
    глубина = ГЛУБИНА_В_K * K
    окно = min(шагов, max(2 * глубина, ЯЧЕЕК_ДО // состояний))
    откуда = np.zeros((окно, состояний), dtype=np.int32)
    бит = np.zeros((окно, состояний), dtype=np.uint8)
    база, заполнено = 0, 0

    def назад(выдать: int) -> None:
        состояние = int(np.argmin(метрика))
        решения = np.zeros(заполнено, dtype=np.uint8)
        for r in range(заполнено - 1, -1, -1):
            решения[r] = бит[r, состояние]
            состояние = int(откуда[r, состояние])
        итог[база:база + выдать] = решения[:выдать]

    for шаг in range(шагов):
        стоимость = ((выходы != блоки[шаг][None, None, :]) * маска[шаг][None, None, :]).sum(axis=2)
        значения = (метрика[:, None] + стоимость).reshape(-1)
        порядок = np.argsort(значения, kind="stable")[::-1]
        новая = np.full(состояний, 10 ** 9, dtype=np.int64)
        новая[куда[порядок]] = значения[порядок]
        откуда[заполнено, куда[порядок]] = (порядок // 2).astype(np.int32)
        бит[заполнено, куда[порядок]] = (порядок % 2).astype(np.uint8)
        метрика = новая - новая.min()
        заполнено += 1
        if заполнено == окно and шаг < шагов - 1:
            выдать = окно - глубина
            назад(выдать)
            откуда[:глубина] = откуда[выдать:окно]
            бит[:глубина] = бит[выдать:окно]
            база += выдать
            заполнено = глубина
    назад(заполнено)
    return итог


def витерби(биты: np.ndarray, g1: int, g2: int, k: int) -> np.ndarray:
    """Декодер Витерби кода 1/2 с жёсткими решениями (см. ``витерби_n``)."""
    return витерби_n(биты, [g1, g2], k)


def mpeg_ts(данные: bytes) -> Находка | None:
    """Транспортный поток MPEG-TS: 0x47 через 188 или 204 байта."""
    массив = np.frombuffer(данные[:1 << 22], dtype=np.uint8)
    for длина in (188, 204):
        for сдвиг in range(длина):
            синхро = массив[сдвиг::длина]
            if len(синхро) < 32:
                break
            доля = float(np.mean((синхро == 0x47) | (синхро == 0xB8)))
            if доля > 0.9:
                инверсных = float(np.mean(синхро == 0xB8))
                подробно = [f"пакет {длина} байт, синхробайт 0x47 с байта {сдвиг}"]
                if длина == 204:
                    подробно.append("204 = 188 + 16 проверочных байт Рида — Соломона "
                                    "(204, 188, t = 8) — DVB")
                if 0.1 < инверсных < 0.15:
                    подробно.append("каждый восьмой синхробайт инвертирован (0xB8) — метка "
                                    "начала ПСП рандомизации DVB 1 + x¹⁴ + x¹⁵")
                return Находка(
                    уровень="транспортный", что=f"MPEG-TS, пакеты по {длина} байт",
                    уверенность=доля,
                    мера=f"синхробайт на месте в {round(доля * 100, 1)} % пакетов",
                    подробно=подробно, дальше=(длина, сдвиг), вид_дальше="разметка")
    return None


def найти(биты: np.ndarray, *, длинные: bool = True) -> Находка | None:
    """Код в битовом ряду: свёрточный, короткий блочный (устойчиво), длинный блочный.

    Длинный блочный код (n > 16) ищется рангом и виден только в потоке без
    ошибок: при ошибках линии ранговая зависимость пропадает. ``длинные=False``
    — без него: слепой разбор сперва пробует перемежение, потому что
    перемежённый короткий код ранговый метод видит как один длинный
    (Хэмминг (7, 4) × 10 строк — «код (70, 40)»), и данные из такого «кода»
    выходят в чужом порядке.
    """
    if len(биты) < 1 << 13:
        return None
    # Оба детектора могут увидеть «свой» код в одном ряду: проверочная связь
    # блочного кода иногда выполняется и в скользящем окне свёрточного, и
    # наоборот. Решает сверка с самим потоком: у верного толкования доля
    # слов с нулевым синдромом (или совпадение перекодированного) выше. При
    # равенстве — толкование, объясняющее больше проверок на бит: без ошибок
    # свёрточный поток «проходит» и как блочный (16, 14), но свёрточный 1/2
    # объясняет проверку на каждые два бита, а не две на шестнадцать.
    кандидаты = [н for н in (блочный_устойчивый(биты), свёрточный(биты)) if н is not None]
    if кандидаты:
        return max(кандидаты, key=lambda н: (round(н.сверка, 3), _избыточность(н)))
    return длинный(биты) if длинные else None


def длинный(биты: np.ndarray) -> Находка | None:
    """Длинный блочный код рангом — только для потока без ошибок."""
    if len(биты) < 1 << 13:
        return None
    return блочный(биты, профиль(биты[:1 << 16]))


def _избыточность(находка: Находка) -> float:
    """Доля проверочных бит: 1 − скорость кода из «скорость k/n»."""
    найдено = re.search(r"скорост\S* (\d+)/(\d+)", находка.что)   # «скорость», «скорости»
    return 1 - int(найдено.group(1)) / int(найдено.group(2)) if найдено else 0.0


