"""Помехоустойчивый код: блочный и свёрточный — вслепую, по рангу над GF(2).

Нарежем поток на строки длины L и сложим в матрицу. У случайного ряда
строки линейно независимы: ранг равен L. У закодированного — нет: внутри
строки, где целиком лежат кодовые слова, проверочные биты — линейные
комбинации информационных, и ранг падает. По тому, КАК он падает, код и
узнаётся:

* блочный (n, k) — падение только при L, кратных n: d(L) = (L/n − 1)(n − k)
  при сбитом выравнивании и L/n · (n − k) при верном. Отсюда n, выравнивание
  и k; ядро матрицы — проверочная матрица; позиции опорных столбцов —
  информационные биты, их и отдаём следующему уровню;
* свёрточный скорости 1/2 — падение растёт с L ровно: d(L) ≈ L/2 − (K − 1).
  Вектор ядра — проверочное соотношение h, из него — порождающие
  многочлены (g1 = h2, g2 = h1), а декодер Витерби снимает код.

MPEG-TS узнаётся отдельно — по байту 0x47 через 188 или 204 байта (204 —
пакет с проверочными байтами Рида — Соломона (204, 188)); у DVB каждый
восьмой синхробайт инвертирован (0xB8) — это метка начала ПСП.
"""

from __future__ import annotations

