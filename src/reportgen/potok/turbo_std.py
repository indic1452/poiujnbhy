def _многочлен(вектор: str) -> int:
    """Вектор CCSDS («10011») → многочлен битами (бит i — D^i)."""
    return sum(int(c) << i for i, c in enumerate(вектор))


def _умножить(a: int, b: int) -> int:
    итог = 0
    while b:
        if b & 1:
            итог ^= a
        a <<= 1
        b >>= 1
    return итог


def _разделить(a: int, b: int) -> tuple[int, int]:
    частное = 0
    степень_b = b.bit_length() - 1
    while a and a.bit_length() - 1 >= степень_b:
        сдвиг = a.bit_length() - 1 - степень_b
        частное |= 1 << сдвиг
        a ^= b << сдвиг
    return частное, a


def _период(g0: int) -> int:
    """Наименьшее L: g0 делит 1 + D^L (период обратной связи)."""
    for L in range(1, 1 << 12):
        if _разделить((1 << L) | 1, g0)[1] == 0:
            return L
    raise ValueError("нет периода")


@dataclass
class Составляющий:
    имя: str
    обратная: str
    прямая: str


#: Составляющие коды стандартов для поиска вслепую (обратная и первая прямая).
СОСТАВЛЯЮЩИЕ = (Составляющий("13/15 (UMTS, LTE)", "1011", "1101"),
                Составляющий("CCSDS 23/33", "10011", "11011"))


def _нарушения(u: np.ndarray, p: np.ndarray, с: Составляющий, чётный: bool) -> tuple[np.ndarray, int]:
    """Нарушения связи (1 + D^L)·p = g1·(1 + D^L)/g0 · u для каждого шага (0/1).

    Для RSC p = (g1/g0)·u; g0 делит 1 + D^L при L, кратном периоду обратной связи, и связь
    держит лишь p[t] и p[t − L] — годится, когда p известно через шаг (L чётное).
    """
    g0, g1 = _многочлен(с.обратная), _многочлен(с.прямая)
    L = _период(g0)
    if чётный and L % 2:
        L *= 2
    q, остаток = _разделить((1 << L) | 1, g0)
    assert остаток == 0
    h = _умножить(g1, q)
    отводы = np.array([(h >> i) & 1 for i in range(h.bit_length())], dtype=np.int64)
    hu = np.convolve(u.astype(np.int64), отводы)[:len(u)] & 1
    v = (p ^ np.roll(p, L) ^ hu).astype(np.uint8)
    глубина = max(L, len(отводы) - 1)
    v[:глубина] = 0
    return v, глубина


def _кандидаты_схем(с: Составляющий, пар: int, тройки: bool) -> list[tuple[Схема, str]]:
    """Схемы каталога с блоком ``пар`` шагов (пары для 1/2, тройки для 1/3)."""
    итог = []
    if с.обратная == "10011":
        скорость = "1/3" if тройки else "1/2"
        асм = len(CCSDS_ASM[скорость]) * 4 // (3 if тройки else 2)
        for k in CCSDS_K:
            if пар == k + 4:
                итог.append((ccsds(k, скорость), ""))
            if пар == k + 4 + асм:
                итог.append((ccsds(k, скорость), CCSDS_ASM[скорость]))
    else:
        K = пар - 4
        if 40 <= K <= 5114:
            итог.append((umts(K) if тройки else umts(K, 2 * пар), ""))
            if not тройки:
                итог.append((umts_шаблон(K, "11/10/01"), ""))
                итог.append((umts_шаблон(K, "11/01/10"), ""))
        if тройки and K in LTE_QPP:
            итог.append((lte(K), ""))
    return итог


def _поток_схемы(схема: Схема, маркер: str, блоков: int, сид: int = 7) -> np.ndarray:
    данные = np.random.default_rng(сид).integers(0, 2, (блоков, схема.K), dtype=np.uint8)
    кодовые = схема.закодировать(данные)
    if маркер:
        м = np.tile(_маркер_бит(маркер), (блоков, 1))
        кодовые = np.concatenate([м, кодовые], axis=1)
    return кодовые.reshape(-1)


def опознать(биты: np.ndarray) -> dict | None:
    """Выколотый 1/2 или полный 1/3 PCCC составляющего кода стандарта: раскладка и нарушения.

    Перебираются: составляющий код, n (2 или 3), сдвиг кортежа, место систематики, место
    первой проверки и (для 1/2) шаг, на котором она передана. Турбокод — если связь с одной
    проверкой держится (нарушений ≤ 25 %), а со второй — нет (иначе это свёрточный RSC).
    """
    биты = np.asarray(биты[:1 << 17], dtype=np.uint8)
    лучший = None
    for n in (2, 3):
        for с in СОСТАВЛЯЮЩИЕ:
            for сдвиг in range(n):
                к = биты[сдвиг:]
                к = к[:len(к) // n * n].reshape(-1, n)
                for x in range(n):
                    for пр in range(n):
                        if пр == x:
                            continue
                        v, глубина = _нарушения(к[:, x], к[:, пр], с, чётный=n == 2)
                        фазы = (0, 1) if n == 2 else (None,)
                        for ψ in фазы:
                            годные = v[глубина:] if ψ is None else v[глубина + ((ψ - глубина) % 2)::2]
                            доля = float(годные.mean())
                            if лучший is None or доля < лучший["доля"]:
                                лучший = {"n": n, "составляющий": с, "сдвиг": сдвиг, "x": x, "p": пр,
                                          "ψ": ψ, "доля": доля, "нарушения": v, "глубина": глубина}
    if лучший is None or лучший["доля"] > 0.25:
        return None
    # Вторая проверка: у свёрточного RSC 1/2 связь держится на всех шагах — это не турбокод.
    n, с = лучший["n"], лучший["составляющий"]
    к = биты[лучший["сдвиг"]:]
    к = к[:len(к) // n * n].reshape(-1, n)
    v = лучший["нарушения"]
    if n == 2:
        другие = v[лучший["глубина"] + ((1 - лучший["ψ"] - лучший["глубина"]) % 2)::2]
    else:
        третья = 3 - лучший["x"] - лучший["p"]
        другие = _нарушения(к[:, лучший["x"]], к[:, третья], с, чётный=False)[0][лучший["глубина"]:]
    if float(другие.mean()) < 0.35:
        return None
    лучший["вторая"] = float(другие.mean())
    if n == 3 and лучший["x"]:
        # Кортеж начат не с систематики: (p2, x, p1) — тот же код; начало сдвигается на x.
        лучший["сдвиг"] += лучший["x"]
        лучший["p"] -= лучший["x"]
        лучший["x"] = 0
    return лучший


def _профиль(v: np.ndarray, период: int) -> np.ndarray:
    """Доля нарушений на каждом шаге блока (сложено по блокам)."""
    циклов = len(v) // период
    return v[:циклов * период].reshape(циклов, период).astype(np.float64).mean(axis=0)


def _период_блока(v: np.ndarray, глубина: int, до: int = 6000) -> tuple[int, float] | None:
    """Длина блока по нарушениям связи: они сгущаются на стыке блоков (хвост, новый блок).

    Автокорреляция — с шага больше окна связи (ошибка линии даёт нарушения на расстояниях
    между отводами связи, это не блок); основной период — наименьший с пиком не слабее
    60 % лучшего; точный — при котором сложенный профиль контрастнее всего (стык — полоса).
    """
    x = v.astype(np.float64) - v.mean()
    n = len(x)
    if not x.any():
        return None
    размер = 1 << int(np.ceil(np.log2(2 * n)))
    спектр = np.fft.rfft(x, размер)
    r = np.fft.irfft(спектр * np.conj(спектр), размер)[:min(до, n // 4) + 1]
    r /= r[0]
    от = 2 * глубина + 8
    if len(r) <= от + 1:
        return None
    лучший = int(np.argmax(r[от:])) + от
    шум = 1 / np.sqrt(n)
    if r[лучший] < 6 * шум:
        return None
    основной = next(P for P in range(от, лучший + 1) if r[P] >= 0.6 * r[лучший])
    точный = max(range(max(от, основной - 24), основной + 25),
                 key=lambda P: float(_профиль(v, P).var()))
    return точный, float(r[лучший] / шум)


def найти(биты: np.ndarray, *, бюджет: float = 60.0, блоков_до: int = 400):
    """Турбокод стандарта вслепую: выколотый 1/2 (UMTS, CCSDS, шаблон) или 1/3 (UMTS, CCSDS, LTE).

    Составляющий код и раскладка — по связи систематики с одной из проверок; длина блока —
    по периоду нарушений связи (хвост и стык блоков); схема — из каталога по длине; начало
    блока — сравнением профиля нарушений с профилем, посчитанным на своём кодере схемы;
    схема принимается, если перекодированные решения декодера сходятся с потоком.
    Опознан турбокод, но схемы в каталоге нет — находка без данных (данные не выдумываются).
    """
    import time  # noqa: PLC0415

    from .nahodka import Находка  # noqa: PLC0415
    конец = time.monotonic() + бюджет
    о = опознать(биты)
    if о is None:
        return None
    n, с = о["n"], о["составляющий"]
    # Для длины блока выборка побольше: блоков в 2^17 бит у CCSDS 1/3 — десяток.
    к = np.asarray(биты[о["сдвиг"]:(1 << 20) + о["сдвиг"]], dtype=np.uint8)
    к = к[:len(к) // n * n].reshape(-1, n)
    v, _ = _нарушения(к[:, о["x"]], к[:, о["p"]], с, чётный=n == 2)
    if о["ψ"] is not None:
        v = v.copy()
        v[(np.arange(len(v)) % 2) != о["ψ"]] = 0
    шаг_ = 1 if о["ψ"] is None else 2
    # Проверка первого кодера у 1/2 — через шаг: период ищется по этим шагам (блок — чётное
    # число пар: у CCSDS k + 4, у UMTS 1/2 — K + 4).
    найдено_ = _период_блока(v[(о["ψ"] or 0)::шаг_], о["глубина"] // шаг_)
    период = None if найдено_ is None else (найдено_[0] * шаг_, найдено_[1])
    вид = "выколотый 1/2" if n == 2 else "1/3"
    подробно = [f"составляющий код RSC {с.имя}: связь систематики с проверкой держится "
                f"(нарушений {о['доля'] * 100:.1f} %), со второй проверкой — нет "
                f"({о['вторая'] * 100:.0f} %) — параллельный турбокод, не свёрточный",
                f"раскладка: кортежи по {n} бита с бита {о['сдвиг']}, систематика — место {о['x']}, "
                f"проверка первого кодера — место {о['p']}"
                + (f", передана через шаг (фаза {о['ψ']}), в остальные — второго кодера"
                   if n == 2 else "")]
    испытано: list[str] = []

    def принять(схема: Схема, начало_бит: int, маркер: str):
        try:
            _, св = снять_блоки(биты, схема, начало_бит, маркер, блоков=4)
        except ValueError:
            return None
        испытано.append(f"{схема.имя}{' с маркером ASM' if маркер else ''}: начало {начало_бит}, "
                        f"расхождение перекодированного {св['расхождение'] * 100:.1f} %")
        if св["расхождение"] >= 0.1:
            return None
        всего = min(блоков_до, (len(биты) - начало_бит) // (схема.длина + 4 * len(маркер)))
        данные, св = снять_блоки(биты, схема, начало_бит, маркер, блоков=всего)
        итог = подробно + испытано[:-1] + [
            f"схема: {схема.имя} ({схема.источник})",
            f"начало первого блока — бит {начало_бит}" + (f"; перед блоком маркер ASM {маркер}" if маркер else ""),
            f"турбодекодирование (max-log-MAP, до 8 итераций) {св['блоков']} блоков: перекодированные "
            f"данные расходятся с потоком в {св['расхождение'] * 100:.2f} % бит (это доля ошибок линии); "
            f"оба декодера согласны в {св['сошлось'] * 100:.0f} % блоков"]
        return Находка(
            уровень="код", что=f"турбокод {схема.имя}", уверенность=1.0 - св["расхождение"],
            мера=f"перекодированные решения совпали с потоком в {100 - св['расхождение'] * 100:.2f} % "
                 f"бит ({св['блоков']} блоков)",
            подробно=итог, дальше=данные, вид_дальше="биты", сверка=1.0 - св["расхождение"],
            свойства={"турбо": True, "данных_в_блоке": схема.K,
                      "указание": указание(схема, начало_бит, маркер)})

    шагов = None
    if период is not None:
        шагов = период[0]
        подробно.append(f"блок — {шагов} кортежей ({шагов * n} бит): период нарушений связи на стыках "
                        f"(хвост, обнуление регистров), пик {период[1]:.0f} σ")
        наблюдаемый = _профиль(v, шагов)
        for схема, маркер in _кандидаты_схем(с, шагов, n == 3):
            if time.monotonic() > конец:
                break
            # Свой профиль схемы: тот же расчёт нарушений на закодированном своим кодером потоке.
            свой = _поток_схемы(схема, маркер, 12)
            кс = свой[:len(свой) // n * n].reshape(-1, n)
            vс, глубина = _нарушения(кс[:, о["x"]], кс[:, о["p"]], с, чётный=n == 2)
            сдвиги = range(шагов)
            if о["ψ"] is not None:
                # На каком шаге от начала блока схема передаёт проверку первого кодера.
                ψс = min((0, 1), key=lambda ф: float(vс[глубина + ф::2].mean()))
                vс[(np.arange(len(vс)) % 2) != ψс] = 0
                сдвиги = range((о["ψ"] - ψс) % 2, шагов, 2)
            шаблон = _профиль(vс[шагов:], шагов)
            # Блок потока начинается с кортежа d: набл[o] ≈ шаблон[(o − d) mod шагов].
            _, d = min((float(np.abs(np.roll(шаблон, d) - наблюдаемый).sum()), d) for d in сдвиги)
            найдено = принять(схема, о["сдвиг"] + n * (d % шагов), маркер)
            if найдено is not None:
                return найдено
    if с.обратная == "10011":
        # CCSDS без маркера: хвост кодера a идёт в той же систематике, регистр после него
        # нулевой — связь с первой проверкой через стык не рвётся, блока по ней не видно.
        # Длина — одна из четырёх; начало — по связи второй проверки с перемежёнными данными.
        скорость = "1/3" if n == 3 else "1/2"
        for k in CCSDS_K:
            if time.monotonic() > конец:
                break
            схема = ccsds(k, скорость)
            начало_бит = _начало_по_второй(биты, схема, с, о["сдвиг"], n, конец)
            if начало_бит is not None:
                найдено = принять(схема, начало_бит, "")
                if найдено is not None:
                    return найдено
    if n == 3:
        # 1/3 вне каталога — дело слепого поиска перестановки (turbo.найти): там p2 целиком.
        return None
    if шагов is None:
        подробно.append("стык блоков по нарушениям связи не виден")
    подробно += испытано or ["в каталоге (UMTS, LTE, CCSDS, шаблоны 1/2) нет схемы с таким блоком"]
    подробно.append("перемежитель вне каталога: по половине второй проверки он не восстанавливается — "
                    "данные не декодировались и дальше не отдаются")
    return Находка(уровень="код",
                   что=f"турбокод (PCCC) {вид}, RSC {с.имя}"
                       + (f", блок {шагов * n} бит" if шагов else "") + " — схема не опознана",
                   уверенность=0.6, мера=подробно[0], подробно=подробно, дальше=None,
                   вид_дальше="биты", свойства={"турбо": True})


def _начало_по_второй(биты: np.ndarray, схема: Схема, с: Составляющий, сдвиг: int, n: int,
                      конец: float, блоков: int = 2) -> int | None:
    """Начало блока, при котором вторая проверка связана с перемежёнными данными.

    Та же связь (1 + D^L)·p2 = g1·(1 + D^L)/g0 · (u∘π), что и у первой проверки, но на
    данных, переставленных перемежителем схемы: при верном начале нарушений мало (ошибки
    линии), при неверном — половина.
    """
    import time  # noqa: PLC0415
    р = схема.раскладка
    K = схема.K
    иш = р[(р[:, 0] == СИСТ1) & (р[:, 1] < K)]
    где_u = np.flatnonzero((р[:, 0] == СИСТ1) & (р[:, 1] < K))[np.argsort(иш[:, 1])]
    где_p = np.flatnonzero((р[:, 0] == ПРОВ2) & (р[:, 1] < K) & (р[:, 2] == 0))
    шаги_p = р[где_p, 1]
    известно = np.zeros(K, dtype=bool)
    известно[шаги_p] = True
    g0, g1 = _многочлен(с.обратная), _многочлен(с.прямая)
    L = _период(g0)
    if L % 2:
        L *= 2
    q, _ = _разделить((1 << L) | 1, g0)
    h = _умножить(g1, q)
    отводы = np.array([(h >> i) & 1 for i in range(h.bit_length())], dtype=np.int64)
    годные = известно & np.roll(известно, L)
    годные[:max(L, len(отводы))] = False
    лучшее = None
    for d in range(0, схема.длина, n):
        if time.monotonic() > конец:
            break
        начало = сдвиг + d
        б = биты[начало:начало + блоков * схема.длина]
        if len(б) < блоков * схема.длина:
            break
        б = б.reshape(блоков, схема.длина).astype(np.int64)
        доли = []
        for ряд in б:
            u = ряд[где_u][схема.π]
            p2 = np.zeros(K, dtype=np.int64)
            p2[шаги_p] = ряд[где_p]
            v = p2 ^ np.roll(p2, L) ^ (np.convolve(u, отводы)[:K] & 1)
            доли.append(float(v[годные].mean()))
        доля = float(np.mean(доли))
        if лучшее is None or доля < лучшее[0]:
            лучшее = (доля, начало)
    if лучшее is None or лучшее[0] > 0.3:
        return None
    return лучшее[1] % схема.длина


