def _lte_d(K: int) -> list[np.ndarray]:
    """Потоки d0, d1, d2 (K + 4 бит) → строки раскладки (п. 5.1.3.2.2, стр. PDF 17)."""
    d = [[(СИСТ1, k, 0) for k in range(K)], [(ПРОВ1, k, 0) for k in range(K)],
         [(ПРОВ2, k, 0) for k in range(K)]]
    x = [(СИСТ1, K + t, 0) for t in range(3)]
    z = [(ПРОВ1, K + t, 0) for t in range(3)]
    x2 = [(СИСТ2, K + t, 0) for t in range(3)]
    z2 = [(ПРОВ2, K + t, 0) for t in range(3)]
    d[0] += [x[0], z[1], x2[0], z2[1]]
    d[1] += [z[0], x[2], z2[0], x2[2]]
    d[2] += [x[1], z[2], x2[1], z2[2]]
    return [np.array(п, dtype=np.int64) for п in d]


def lte_буфер(K: int) -> tuple[np.ndarray, int]:
    """Кольцевой буфер w (п. 5.1.4.1.1–5.1.4.1.2): номер строки раскладки или −1 (<NULL>)."""
    D = K + 4
    C = 32
    R = -(-D // C)
    KП = R * C
    ND = KП - D
    v = []
    for i in range(3):
        y = np.concatenate([np.full(ND, -1), np.arange(D) + i * D])
        if i < 2:
            v.append(np.array([y[LTE_P[j] + C * r] for j in range(C) for r in range(R)]))
        else:
            k = np.arange(KП)
            v.append(y[(np.array(LTE_P)[k // R] + C * (k % R) + 1) % KП])
    w = np.empty(3 * KП, dtype=np.int64)
    w[:KП] = v[0]
    w[KП::2] = v[1]
    w[KП + 1::2] = v[2]
    return w, R


def lte(K: int, E: int | None = None, rv: int = 0) -> Схема:
    """LTE: E бит после согласования скорости (по умолчанию 3K + 12), версия rv 0…3, N_cb = K_w."""
    π = lte_перемежитель(K)
    d = np.concatenate(_lte_d(K))
    w, R = lte_буфер(K)
    Ncb = len(w)
    E = 3 * K + 12 if E is None else E
    if not 0 <= rv <= 3 or E < 1:
        raise ValueError("LTE: rv от 0 до 3, E > 0")
    k0 = R * (2 * -(-Ncb // (8 * R)) * rv + 2)
    годные = np.flatnonzero(np.roll(w, -k0) >= 0)
    повторов = -(-E // len(годные))
    выбор = np.roll(w, -k0)[np.tile(годные, повторов)[:E]]
    return Схема(f"LTE (TS 36.212) K = {K}, E = {E}, rv = {rv}", K, UMTS_РСК, UMTS_РСК, π, 3,
                 d[выбор], источник="ETSI TS 136 212 V17.1.0, п. 5.1.3.2, 5.1.4.1")


