#: Каналы раскладки: систематика кодера 1 (все шаги, в т. ч. хвост), проверки кодера 1,
#: систематика кодера 2 (только хвост — данные у него перемежённые данные кодера 1),
#: проверки кодера 2.
СИСТ1, ПРОВ1, СИСТ2, ПРОВ2 = range(4)


@dataclass
class Схема:
    """Турбокод одного размера и скорости: кодеры, перемежитель, раскладка блока в потоке."""
    имя: str
    K: int                                  # бит данных в блоке
    р1: Решётка
    р2: Решётка
    π: np.ndarray                           # перемежённый символ j — символ π[j] данных
    хвост: int                              # шагов хвоста у каждого кодера (0 — кольцо)
    #: Раскладка: для каждого бита кодового блока — (канал, шаг, номер бита в канале).
    раскладка: np.ndarray
    кольцо: bool = False
    #: Для дуобинарного: на чётных j пара (A, B) меняется местами (EN 301 790 уровень 1).
    обмен_чётных: bool = False
    источник: str = ""
    кольцевое: Callable[[np.ndarray, int], np.ndarray] | None = None

    @property
    def символов(self) -> int:
        return self.K // self.р1.бит_входа

    @property
    def длина(self) -> int:
        """Бит в кодовом блоке потока."""
        return len(self.раскладка)

    def _перемежить(self, x: np.ndarray) -> np.ndarray:
        y = x[:, self.π]
        if self.обмен_чётных:                   # метрики (A, B) → (B, A): m = 2A + B ↔ 2B + A
            y[:, 0::2] = y[:, 0::2][:, :, [0, 2, 1, 3]]
        return y

    def _обратно(self, y: np.ndarray) -> np.ndarray:
        if self.обмен_чётных:
            y = y.copy()
            y[:, 0::2] = y[:, 0::2][:, :, [0, 2, 1, 3]]
        x = np.empty_like(y)
        x[:, self.π] = y
        return x

    # ---- кодирование (для сверки перекодированием и тестов раскладки)

    def _кодер(self, р: Решётка, символы: np.ndarray, хвост: int) -> tuple[np.ndarray, ...]:
        B, T = символы.shape
        if self.кольцо:
            s = self.кольцевое(символы, T) if self.кольцевое else np.zeros(B, dtype=np.int64)
        else:
            s = np.zeros(B, dtype=np.int64)
        сист = np.zeros((B, T + хвост), dtype=np.int64)
        пров = np.zeros((B, T + хвост, р.выходы.shape[2]), dtype=np.uint8)
        начало = s.copy()
        for t in range(T + хвост):
            m = символы[:, t] if t < T else р.хвост_вход[s]
            сист[:, t] = m
            пров[:, t] = р.выходы[s, m]
            s = р.следующее[s, m]
        if self.кольцо:
            assert np.array_equal(s, начало), "кольцевой код не замкнулся"
        elif хвост:
            assert not s.any(), "хвост не обнулил регистр"
        return сист, пров

    def закодировать(self, данные: np.ndarray) -> np.ndarray:
        """Блоки данных (B × K бит) → кодовые блоки потока (B × длина)."""
        данные = np.asarray(данные, dtype=np.int64).reshape(-1, self.K)
        б = self.р1.бит_входа
        символы = данные.reshape(len(данные), -1, б) @ (1 << np.arange(б - 1, -1, -1))
        с1, п1 = self._кодер(self.р1, символы, self.хвост)
        перем = символы[:, self.π].copy()
        if self.обмен_чётных:                   # (A, B) → (B, A) на чётных j
            перем[:, 0::2] = ((перем[:, 0::2] & 1) << 1) | (перем[:, 0::2] >> 1)
        с2, п2 = self._кодер(self.р2, перем, self.хвост)
        каналы = [self._в_биты(с1, б), п1, self._в_биты(с2, б), п2]
        итог = np.zeros((len(данные), self.длина), dtype=np.uint8)
        for к in range(4):
            где = np.flatnonzero(self.раскладка[:, 0] == к)
            if len(где):
                итог[:, где] = каналы[к][:, self.раскладка[где, 1], self.раскладка[где, 2]]
        return итог

    @staticmethod
    def _в_биты(символы: np.ndarray, б: int) -> np.ndarray:
        return np.stack([(символы >> (б - 1 - j)) & 1 for j in range(б)], axis=2).astype(np.uint8)

    # ---- декодирование

    def разложить(self, llr: np.ndarray) -> tuple[np.ndarray, ...]:
        """LLR кодовых блоков (B × длина) → LLR каналов кодеров (выколотое — ноль)."""
        B = len(llr)
        б = self.р1.бит_входа
        T1 = self.символов + self.хвост
        размеры = [(T1, б), (T1, self.р1.выходы.shape[2]), (T1, б), (T1, self.р2.выходы.shape[2])]
        каналы = [np.zeros((B,) + р, dtype=np.float32) for р in размеры]
        for к in range(4):
            где = np.flatnonzero(self.раскладка[:, 0] == к)
            # Повторы (согласование скорости с повторением) складываются.
            np.add.at(каналы[к], (slice(None), self.раскладка[где, 1], self.раскладка[где, 2]),
                      llr[:, где])
        return tuple(каналы)

    def декодировать(self, llr: np.ndarray, итераций: int = 8, масштаб: float = 0.75
                     ) -> tuple[np.ndarray, dict]:
        """Мягкие значения блоков (B × длина; > 0 — ноль) → данные (B × K) и сведения."""
        llr = np.asarray(llr, dtype=np.float32).reshape(-1, self.длина)
        итог = np.zeros((len(llr), self.K), dtype=np.uint8)
        сошлось = []
        for начало in range(0, len(llr), 16):
            д, с = self._декодировать(llr[начало:начало + 16], итераций, масштаб)
            итог[начало:начало + len(д)] = д
            сошлось.append(с)
        return итог, {"сошлось": float(np.concatenate(сошлось).mean()) if сошлось else 0.0,
                      "сошлось_блоков": np.concatenate(сошлось)}

    def _декодировать(self, llr: np.ndarray, итераций: int, масштаб: float
                      ) -> tuple[np.ndarray, np.ndarray]:
        б = self.р1.бит_входа
        Ks = self.символов
        с1, п1, с2, п2 = self.разложить(llr)
        м1 = _метрики(с1, б)                                  # B × T × M
        м2 = _метрики(с2, б)
        м2[:, :Ks] = self._перемежить(м1[:, :Ks])
        B, _, M = м1.shape
        апр1 = np.zeros((B, Ks, M), dtype=np.float32)
        край = "кольцо" if self.кольцо else "ноль"
        прежнее = None
        for _ in range(итераций):
            вход1 = м1.copy()
            вход1[:, :Ks] += апр1
            а1 = _мап(вход1, п1, self.р1, край, край)
            внеш1 = (а1[:, :Ks] - вход1[:, :Ks]) * масштаб
            внеш1 -= внеш1[:, :, :1]
            апр2 = self._перемежить(внеш1)
            вход2 = м2.copy()
            вход2[:, :Ks] += апр2
            а2 = _мап(вход2, п2, self.р2, край, край)
            внеш2 = (а2[:, :Ks] - вход2[:, :Ks]) * масштаб
            внеш2 -= внеш2[:, :, :1]
            апр1 = self._обратно(внеш2)
            решение = (м1[:, :Ks] + апр1 + внеш1).argmax(axis=2)
            if прежнее is not None and np.array_equal(решение, прежнее):
                break
            прежнее = решение
        решение2 = self._обратно(а2[:, :Ks]).argmax(axis=2)
        сошлось = (решение == решение2).mean(axis=1) == 1.0
        биты = self._в_биты(решение, б).reshape(B, -1)
        return биты, сошлось


