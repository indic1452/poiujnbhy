def umts_перемежитель(K: int) -> np.ndarray:
    """Перемежитель турбокода UMTS: x'_k = x_{π[k]} (п. 4.2.3.2.3, стр. PDF 25–28)."""
    if not 40 <= K <= 5114:
        raise ValueError("UMTS: K от 40 до 5114 (п. 4.2.3.2.3)")
    R = 5 if K <= 159 else 10 if (160 <= K <= 200 or 481 <= K <= 530) else 20
    if 481 <= K <= 530:
        p = C = 53
    else:
        p = min(q for q in UMTS_ПРОСТЫЕ if K <= R * (q + 1))
        C = p - 1 if K <= R * (p - 1) else p if K <= R * p else p + 1
    v = UMTS_ПРОСТЫЕ[p]
    s = np.ones(p - 1, dtype=np.int64)
    for j in range(1, p - 1):
        s[j] = v * s[j - 1] % p
    простые = [q for q in range(7, 400) if all(q % d for d in range(2, int(q ** 0.5) + 1))]
    q = [1] + [0] * (R - 1)
    for i in range(1, R):
        q[i] = next(x for x in простые if x > q[i - 1] and math.gcd(x, p - 1) == 1)
    T = UMTS_T[R] if R < 20 else UMTS_T["20a" if (2281 <= K <= 2480 or 3161 <= K <= 3210) else "20b"]
    r = [0] * R
    for i in range(R):
        r[T[i]] = q[i]
    j = np.arange(p - 1)
    U = np.zeros((R, C), dtype=np.int64)
    for i in range(R):
        база = s[(j * r[i]) % (p - 1)]
        if C == p:
            U[i] = np.concatenate([база, [0]])
        elif C == p + 1:
            U[i] = np.concatenate([база, [0, p]])
        else:
            U[i] = база - 1
    if C == p + 1 and K == R * C:
        U[R - 1, [0, p]] = U[R - 1, [p, 0]]
    исходные = np.array(T)[:, None] * C + U[np.array(T)]        # R × C: откуда бит
    π = исходные.T.reshape(-1)                                  # вывод по столбцам
    π = π[π < K]
    assert len(π) == K
    return π


def _umts_мать(K: int) -> np.ndarray:
    """Раскладка выхода 3K + 12 (п. 4.2.3.2.1–4.2.3.2.2): x z z' по шагам, хвост x z ×3, x' z' ×3."""
    строки = []
    for k in range(K):
        строки += [(СИСТ1, k, 0), (ПРОВ1, k, 0), (ПРОВ2, k, 0)]
    for t in range(3):
        строки += [(СИСТ1, K + t, 0), (ПРОВ1, K + t, 0)]
    for t in range(3):
        строки += [(СИСТ2, K + t, 0), (ПРОВ2, K + t, 0)]
    return np.array(строки, dtype=np.int64)


def umts_выкалывание(N: int, E: int) -> np.ndarray:
    """Какие из N = 3K + 12 бит остаются (п. 4.2.7.2.2.3 и 4.2.7.5; b = 1 не выкалывается)."""
    if not (N % 3 == 0 and 0 < E <= N):
        raise ValueError("UMTS: E бит после согласования — не больше 3K + 12")
    X = N // 3
    dN = E - N
    оставить = np.ones((X, 3), dtype=bool)
    for b, a, dNi in ((1, 2, math.floor(dN / 2)), (2, 1, math.ceil(dN / 2))):
        if dNi == 0:
            continue
        e, плюс, минус = X, a * X, a * abs(dNi)
        for m in range(X):
            e -= минус
            if e <= 0:
                оставить[m, b] = False
                e += плюс
    return оставить.reshape(-1)


def umts(K: int, E: int | None = None) -> Схема:
    мать = _umts_мать(K)
    раскладка = мать if E is None else мать[umts_выкалывание(len(мать), E)]
    return Схема(f"UMTS (TS 25.212) K = {K}" + (f", E = {E} (согласование скорости)" if E else ", 1/3"),
                 K, UMTS_РСК, UMTS_РСК, umts_перемежитель(K), 3, раскладка,
                 источник="ETSI TS 125 212 V17.0.0, п. 4.2.3.2, 4.2.7.2.2.3, 4.2.7.5")


