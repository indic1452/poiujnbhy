def rcs_перемежитель(N: int) -> np.ndarray:
    if N not in RCS_ПАРАМЕТРЫ:
        raise ValueError(f"DVB-RCS: N = {N} нет в табл. 9 ({', '.join(map(str, sorted(RCS_ПАРАМЕТРЫ)))})")
