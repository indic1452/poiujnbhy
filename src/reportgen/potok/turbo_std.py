# ---------------------------------------------------------------- max-log-MAP

МИНУС = np.float32(-1e30)


def _мап(вход: np.ndarray, пров: np.ndarray, р: Решётка, начало: str, конец: str,
         разгон: int = 48) -> np.ndarray:
    """Апостериорные метрики символов (B × T × M) по max-log-MAP.

    ``вход`` — метрики входных символов (систематические + априорные), ``пров`` — LLR
    проверочных бит (B × T × n, > 0 — ноль вероятнее, 0 — выколот). ``начало``/``конец``:
    «ноль» — регистр обнулён, «любое» — неизвестно, «кольцо» — кольцевой код (разгон
    по концу/началу блока).
    """
    B, T, M = вход.shape
    S = р.следующее.shape[0]
    γ = (вход[:, :, None, :]
         - np.tensordot(пров, р.выходы.astype(np.float32), axes=([2], [2]))).astype(np.float32)
    пред_s, пред_m, след = р.пред_s, р.пред_m, р.следующее

    def вперёд(α: np.ndarray, t: int) -> np.ndarray:
        кандидаты = α[:, пред_s] + γ[:, t][:, пред_s, пред_m]
        новое = кандидаты.max(axis=2)
        return новое - новое.max(axis=1, keepdims=True)

    def назад(β: np.ndarray, t: int) -> np.ndarray:
        новое = (γ[:, t] + β[:, след]).max(axis=2)
        return новое - новое.max(axis=1, keepdims=True)

    α = np.empty((T + 1, B, S), dtype=np.float32)
    if начало == "ноль":
        α[0] = МИНУС
        α[0][:, 0] = 0
    else:
        α[0] = 0
        if начало == "кольцо":
            for t in range(max(0, T - разгон), T):
                α[0] = вперёд(α[0], t)
    for t in range(T):
        α[t + 1] = вперёд(α[t], t)
    β = np.zeros((B, S), dtype=np.float32)
    if конец == "ноль":
        β[:] = МИНУС
        β[:, 0] = 0
    elif конец == "кольцо":
        for t in range(min(T, разгон) - 1, -1, -1):
            β = назад(β, t)
    апост = np.empty((B, T, M), dtype=np.float32)
    for t in range(T - 1, -1, -1):
        далее = γ[:, t] + β[:, след]                   # B × S × M
        апост[:, t] = (α[t][:, :, None] + далее).max(axis=1)
        β = далее.max(axis=2)
        β -= β.max(axis=1, keepdims=True)
    return апост - апост[:, :, :1]


def _метрики(llr: np.ndarray, бит: int) -> np.ndarray:
    """LLR входных бит (… × бит) → метрики символов (… × 2^бит): −Σ L·b (b — бит символа)."""
    M = 1 << бит
    биты = np.array([[(m >> (бит - 1 - j)) & 1 for j in range(бит)] for m in range(M)],
                    dtype=np.float32)
    return -(llr @ биты.T)


