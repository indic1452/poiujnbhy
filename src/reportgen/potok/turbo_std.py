def rcs(N: int, скорость: str, порядок: str = "естественный") -> Схема:
    """Порядок передачи (п. 6.4.4.4, стр. 33): естественный — A,B; Y1,Y2; W1,W2 — или обратный."""
    if скорость not in RCS_ВЫКАЛЫВАНИЕ:
        raise ValueError("DVB-RCS: скорость " + ", ".join(RCS_ВЫКАЛЫВАНИЕ))
    if N % 7 == 0:
        raise ValueError("DVB-RCS: N кратно 7 — кольцевого состояния нет (табл. 10)")
    шY, шW = RCS_ВЫКАЛЫВАНИЕ[скорость]
    AB = [(СИСТ1, j, b) for j in range(N) for b in (0, 1)]
    Y = [(к, j, 0) for j in range(N) if шY[j % len(шY)] == "1" for к in (ПРОВ1, ПРОВ2)]
    W = [(к, j, 1) for j in range(N) if шW[j % len(шW)] == "1" for к in (ПРОВ1, ПРОВ2)]
    строки = AB + Y + W if порядок.startswith("естеств") else Y + W + AB
    return Схема(f"DVB-RCS (EN 301 790) N = {N} пар, скорость {скорость}", 2 * N,
                 RCS_РЕШЁТКА, RCS_РЕШЁТКА, rcs_перемежитель(N), 0,
                 np.array(строки, dtype=np.int64), кольцо=True, обмен_чётных=True,
                 источник="ETSI EN 301 790 V1.5.1, п. 6.4.4, табл. 9–11", кольцевое=_rcs_кольцевое)


def umts_шаблон(K: int, шаблон: str) -> Схема:
    """PCCC UMTS, выколотый периодическим шаблоном по строкам x / y1 / y2 («11/10/01» — 1/2);
    хвост 12 бит передаётся целиком. Шаблон — не стандарт 3GPP, а общий вид «по шаблону»."""
    строки = шаблон.replace(" ", "").split("/")
    if len(строки) != 3 or len({len(с) for с in строки}) != 1 or set("".join(строки)) - {"0", "1"}:
        raise ValueError("шаблон — три строки 0/1 одной длины через «/»: x / y1 / y2, например 11/10/01")
    мать = _umts_мать(K)
    оставить = np.ones(len(мать), dtype=bool)
    for k in range(K):
        for b in range(3):
            оставить[3 * k + b] = строки[b][k % len(строки[b])] == "1"
    return Схема(f"UMTS K = {K}, выкалывание по шаблону {шаблон}", K, UMTS_РСК, UMTS_РСК,
                 umts_перемежитель(K), 3, мать[оставить],
                 источник="ETSI TS 125 212 V17.0.0, п. 4.2.3.2 (кодер); шаблон — задан аналитиком")


# ---------------------------------------------------------------- поток: блоки и мягкие значения


def блоки(биты: np.ndarray, схема: Схема, начало: int = 0, маркер: str = "") -> np.ndarray:
    """Кодовые блоки подряд с бита ``начало`` (при маркере — маркер перед каждым блоком)."""
    шаг = схема.длина + 4 * len(маркер)
    биты = np.asarray(биты, dtype=np.uint8)[начало:]
    целых = len(биты) // шаг
    if not целых:
        raise ValueError(f"{схема.имя}: в потоке меньше одного блока ({шаг} бит)")
    return биты[:целых * шаг].reshape(целых, шаг)[:, 4 * len(маркер):]


def _маркер_бит(hex_: str) -> np.ndarray:
    return np.unpackbits(np.frombuffer(bytes.fromhex(hex_), dtype=np.uint8))


def начало_по_маркеру(биты: np.ndarray, маркер: str, шаг: int, ошибок: int = 4) -> int | None:
    """Первое вхождение маркера (до ``ошибок`` несовпадений), повторяющегося с шагом ``шаг``."""
    м = _маркер_бит(маркер).astype(np.int64)
    n = len(м)
    окно = min(len(биты) - n, 2 * шаг)
    if окно <= 0:
        return None
    б = np.asarray(биты[:окно + n + шаг], dtype=np.int64)
    for сдвиг in range(окно):
        if int((б[сдвиг:сдвиг + n] != м).sum()) <= ошибок:
            след = б[сдвиг + шаг:сдвиг + шаг + n]
            if len(след) < n or int((след != м).sum()) <= ошибок:
                return сдвиг
    return None


def снять_блоки(биты: np.ndarray, схема: Схема, начало: int = 0, маркер: str = "",
                итераций: int = 8, блоков: int | None = None) -> tuple[np.ndarray, dict]:
    """Декодировать блоки потока (жёсткие решения → ±1): данные подряд и сведения."""
    б = блоки(биты, схема, начало, маркер)
    if блоков:
        б = б[:блоков]
    данные, сведения = схема.декодировать(1.0 - 2.0 * б, итераций)
    перекод = схема.закодировать(данные)
    сведения["блоков"] = len(б)
    сведения["расхождение"] = float((перекод != б).mean())
    сведения["расхождение_блоков"] = (перекод != б).mean(axis=1)
    return данные.reshape(-1), сведения


