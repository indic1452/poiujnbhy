"""Турбосвёрточные коды стандартов (TCC): кодирование, max-log-MAP, раскладка в потоке.

Вкладка «TCC» декодера отдела — турбокоды со свёрточными составляющими (в
отличие от ТКБ). Всё здесь — по первоисточникам в ``istochniki/turbo/``:

- **UMTS** (ETSI TS 125 212 V17.0.0): PCCC 1/3, RSC g0 = 1 + D² + D³,
  g1 = 1 + D + D³ (п. 4.2.3.2.1, стр. PDF 24), хвост 12 бит (п. 4.2.3.2.2,
  стр. 25), перемежитель по строкам и столбцам с простым p и первообразным
  корнем v (п. 4.2.3.2.3, табл. 2 и 3, стр. 25–28), согласование скорости
  выкалыванием (п. 4.2.7.2.2.3, стр. 40; алгоритм п. 4.2.7.5, стр. 45;
  разделение и сборка — п. 4.2.7.4, стр. 44–45);
- **LTE** (ETSI TS 136 212 V17.1.0): тот же составляющий код, QPP
  (табл. 5.1.3-3, стр. 17–18), хвост d0/d1/d2 (п. 5.1.3.2.2, стр. 17),
  согласование скорости кольцевым буфером (п. 5.1.4.1, стр. 19–23);
- **CCSDS** (131.0-B-5, п. 6, стр. PDF 41–45): 16 состояний, G0 = 10011,
  G1 = 11011, G2 = 10101, G3 = 11111; k = 1784, 3568, 7136, 8920; скорости
  1/2, 1/3, 1/4, 1/6; маркеры ASM турбокода (п. 9.3, стр. 66);
- **DVB-RCS** (EN 301 790 V1.5.1, п. 6.4.4, стр. 30–33): дуобинарный
  кольцевой код 8 состояний (обратная 15, Y — 13, W — 11), перемежитель
  по табл. 9, кольцевые состояния по табл. 10, выкалывание по табл. 11.

Декодер один на всех: max-log-MAP по решётке с любым числом входов (2 —
двоичный код, 4 — дуобинарный), внешняя информация — по символам.
Раскладка — где в кодовом блоке потока лежит каждый бит кодера: по ней же
кодируется (для проверки) и раскладываются мягкие значения (выколотые места
— ноль, повторы складываются).
"""

