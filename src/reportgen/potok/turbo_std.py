def указание(схема: Схема, начало: int, маркер: str) -> str:
    """Указание слоя для стола (повторяет найденное автоматом)."""
    имя = схема.имя
    if имя.startswith("CCSDS"):
        k = схема.K
        скорость = имя.rsplit(" ", 1)[1]
        return f"tcc ccsds {k} {скорость}" + (" asm" if маркер else f" начало {начало}")
    if "шаблону" in имя:
        return f"tcc umts {схема.K} шаблон {имя.rsplit(' ', 1)[1]} начало {начало}"
    if имя.startswith("UMTS"):
        E = схема.длина
        return f"tcc umts {схема.K}" + (f" e {E}" if E != 3 * схема.K + 12 else "") + f" начало {начало}"
    if имя.startswith("LTE"):
        return f"tcc lte {схема.K} e {схема.длина} начало {начало}"
    return f"tcc начало {начало}"


def схема_по_указанию(слова: str) -> tuple[Схема, int, str]:
    """«tcc umts K [e E] [шаблон 11/10/01] | lte K [e E] [rv r] | ccsds k 1/2 [asm] |
    rcs N 1/2 [обратный]» и «[начало N]» → (схема, начало, маркер)."""
    import re  # noqa: PLC0415
    слова = слова.lower()
    def число(ключ: str) -> int | None:
        м = re.search(r"(?<!\w)" + ключ + r"\s*=?\s*(\d+)", слова)
        return int(м.group(1)) if м else None
    м = re.search(r"(umts|lte|ccsds|rcs)\s+(\d+)", слова)
    if not м:
        raise ValueError("TCC: «tcc umts K [e E] [шаблон x/y1/y2]», «tcc lte K e E [rv r]», "
                         "«tcc ccsds k 1/2 [asm]», «tcc rcs N 1/2 [обратный]» и «[начало N]»")
    семья, размер = м.group(1), int(м.group(2))
    скорость_ = re.search(r"\b(\d)/(\d)\b", слова.replace(м.group(0), ""))
    скорость = f"{скорость_.group(1)}/{скорость_.group(2)}" if скорость_ else ""
    начало = число("начало") or 0
    маркер = ""
    if семья == "umts":
        шаблон = re.search(r"шаблон\s+([01]+/[01]+/[01]+)", слова)
        схема = umts_шаблон(размер, шаблон.group(1)) if шаблон else umts(размер, число("e"))
    elif семья == "lte":
        схема = lte(размер, число("e"), число("rv") or 0)
    elif семья == "ccsds":
        схема = ccsds(размер, скорость or "1/2")
        if "asm" in слова or "маркер" in слова:
            маркер = CCSDS_ASM[скорость or "1/2"]
    else:
        схема = rcs(размер, скорость or "1/2", "обратный" if "обратн" in слова else "естественный")
    return схема, начало, маркер


def снять(биты: np.ndarray, слова: str) -> tuple[np.ndarray, list[str]]:
    """Слой «tcc …» вручную: данные подряд и строки отчёта. «tcc авто» — поиск по каталогу."""
    if "авто" in слова.lower():
        найдено = найти(биты)
        if найдено is None:
            raise ValueError("TCC: связи систематики с проверкой составляющего кода стандарта "
                             "(13/15 UMTS/LTE, CCSDS 23/33) нет ни при какой раскладке 1/2 и 1/3")
        if найдено.дальше is None:
            raise ValueError(найдено.что + ": " + "; ".join(найдено.подробно[-2:]))
        return np.asarray(найдено.дальше, dtype=np.uint8), [найдено.что + " — " + найдено.мера,
                                                             *найдено.подробно,
                                                             f"слой с параметрами: {найдено.свойства['указание']}"]
    схема, начало, маркер = схема_по_указанию(слова)
    if маркер and "начало" not in слова:
        найдено = начало_по_маркеру(биты, маркер, схема.длина + 4 * len(маркер))
        if найдено is None:
            raise ValueError(f"маркер ASM {маркер} с шагом {схема.длина + 4 * len(маркер)} бит не найден")
        начало = найдено
    данные, св = снять_блоки(биты, схема, начало, маркер)
    подробно = [f"{схема.имя} — {схема.источник}",
                f"блок {схема.длина} бит кода → {схема.K} бит данных; начало {начало}"
                + (f", маркер ASM {маркер} перед каждым блоком" if маркер else ""),
                f"max-log-MAP до 8 итераций, {св['блоков']} блоков; перекодированные данные расходятся "
                f"с потоком в {св['расхождение'] * 100:.2f} % бит; оба декодера согласны в "
                f"{св['сошлось'] * 100:.0f} % блоков"]
    if св["расхождение"] > 0.2:
        подробно.append("расхождение велико — вероятно, не та схема или не то начало блока")
    return данные, подробно
