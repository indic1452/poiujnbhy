@dataclass
class Решётка:
    """Составляющий код: следующее состояние и выходы (проверочные биты) по (состояние, вход)."""
    имя: str
    следующее: np.ndarray                 # S × M
    выходы: np.ndarray                    # S × M × n — проверочные биты
    бит_входа: int                        # 1 — двоичный, 2 — дуобинарный (A, B)
    хвост_вход: np.ndarray | None = None  # S — вход, обнуляющий регистр (для хвоста)
    пред_s: np.ndarray = field(init=False)
    пред_m: np.ndarray = field(init=False)

    def __post_init__(self) -> None:
        S, M = self.следующее.shape
        self.пред_s = np.zeros((S, M), dtype=np.int64)
        self.пред_m = np.zeros((S, M), dtype=np.int64)
        счёт = np.zeros(S, dtype=np.int64)
        for s in range(S):
            for m in range(M):
                s2 = int(self.следующее[s, m])
                self.пред_s[s2, счёт[s2]] = s
                self.пред_m[s2, счёт[s2]] = m
                счёт[s2] += 1
        assert (счёт == M).all(), "решётка без однозначных предков"


def _вектор(строка: str) -> list[int]:
    return [int(c) for c in строка]


def решётка_rsc(обратная: str, прямые: list[str], имя: str) -> Решётка:
    """Двоичный RSC. Векторы — как в CCSDS 131.0-B-5 п. 6.3 h): левый бит — текущий вход
    сумматора (a), дальше ячейки D1…Dm; состояние s = Σ D_i · 2^(i−1)."""
    g0 = _вектор(обратная)
    m = len(g0) - 1
    G = [_вектор(g) for g in прямые]
    assert g0[0] == 1 and all(len(g) == m + 1 for g in G)
    S = 1 << m
    следующее = np.zeros((S, 2), dtype=np.int64)
    выходы = np.zeros((S, 2, len(G)), dtype=np.uint8)
    хвост = np.zeros(S, dtype=np.int64)
    for s in range(S):
        D = [(s >> i) & 1 for i in range(m)]
        обр = sum(g0[i + 1] & D[i] for i in range(m)) & 1
        хвост[s] = обр
        for u in (0, 1):
            a = u ^ обр
            for n, g in enumerate(G):
                выходы[s, u, n] = (g[0] & a) ^ (sum(g[i + 1] & D[i] for i in range(m)) & 1)
            новое = [a] + D[:-1]
            следующее[s, u] = sum(b << i for i, b in enumerate(новое))
    return Решётка(имя, следующее, выходы, 1, хвост)


def решётка_rcs() -> Решётка:
    """EN 301 790 рис. 16: S = 4·s1 + 2·s2 + s3; обратная 1 + D + D³ (15), Y: 1 + D² + D³ (13),
    W: 1 + D³ (11); A — в отвод «1», B — в отводы «1», D и D² (стр. 30). Вход m = 2A + B."""
    следующее = np.zeros((8, 4), dtype=np.int64)
    выходы = np.zeros((8, 4, 2), dtype=np.uint8)
    for S in range(8):
        s1, s2, s3 = (S >> 2) & 1, (S >> 1) & 1, S & 1
        for m in range(4):
            A, B = m >> 1, m & 1
            вход = A ^ B ^ s1 ^ s3
            следующее[S, m] = 4 * вход + 2 * (s1 ^ B) + (s2 ^ B)
            выходы[S, m] = (вход ^ s2 ^ s3, вход ^ s3)
    return Решётка("DVB-RCS (дуобинарный, 8 состояний)", следующее, выходы, 2)


