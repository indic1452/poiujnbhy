    if N % 7 == 0:
        raise ValueError("DVB-RCS: N кратно 7 — кольцевого состояния нет (табл. 10)")
    шY, шW = RCS_ВЫКАЛЫВАНИЕ[скорость]
    AB = [(СИСТ1, j, b) for j in range(N) for b in (0, 1)]
    Y = [(к, j, 0) for j in range(N) if шY[j % len(шY)] == "1" for к in (ПРОВ1, ПРОВ2)]
