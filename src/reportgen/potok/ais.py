"""AIS (ITU-R M.1371): сообщения 1–5, 18, 19, 21, 24 по битам; «броня» NMEA (!AIVDM) — 6 бит на знак.

Раскладка полей — как у pyais (messages.py, по описанию gpsd AIVDM): тип 6 бит, повтор 2, MMSI 30;
координаты — в 1/600000 градуса со знаком (долгота 28 бит, широта 27), 181° / 91° — нет данных;
скорость — 0,1 узла (1023 — нет), курс — 0,1° (3600 — нет), истинный курс 511 — нет;
текст — 6-битовый набор (@ — конец, значения меньше 32 — плюс 64). NMEA: знак − 0x30, начиная с 0x60 — − 0x38
(как decode_into_bit_array у pyais), последние «заполняющие» биты отбрасываются.

В эфире (HDLC с NRZI и битстаффингом, FCS X.25) байты идут младшим битом вперёд; после обычного
приёмника HDLC биты сообщения — байты кадра, прочитанные старшим битом вперёд.
"""

from __future__ import annotations

from typing import Dict, List, Optional, Tuple

import numpy as np

СОСТОЯНИЯ = {0: "на ходу под двигателем", 1: "на якоре", 2: "не управляется", 3: "ограничен в маневре",
             4: "стеснён осадкой", 5: "ошвартован", 6: "на мели", 7: "ведёт лов", 8: "на ходу под парусом",
             11: "буксирует за кормой", 12: "толкает или буксирует лагом", 14: "AIS-SART активен",
             15: "не определено"}
ТИПЫ = {1: "положение (класс A)", 2: "положение (класс A)", 3: "положение (класс A)",
        4: "базовая станция", 5: "статические и рейсовые данные", 18: "положение (класс B)",
        19: "расширенное положение (класс B)", 21: "средство навигационного оборудования",
        24: "статические данные (класс B)"}
#: Длина сообщения в битах по типу (ITU-R M.1371): у 21 — 272…360, у 24 — 160 или 168.
ДЛИНЫ = {1: (168,), 2: (168,), 3: (168,), 4: (168,), 5: (424,), 18: (168,), 19: (312,),
         21: tuple(range(272, 361)), 24: (160, 168)}
ТИПЫ_СУДОВ = {30: "рыболовное", 31: "буксир", 32: "буксир (длинная буксировка)", 33: "дноуглубительное",
              35: "военное", 36: "парусное", 37: "прогулочное", 50: "лоцманское", 51: "поисково-спасательное",
              52: "буксир", 55: "правоохранительное", 58: "медицинское"}


def тип_судна(код: int) -> str:
    if код in ТИПЫ_СУДОВ:
        return ТИПЫ_СУДОВ[код]
    return {2: "экраноплан", 4: "высокоскоростное", 6: "пассажирское", 7: "грузовое", 8: "танкер",
            9: "прочее"}.get(код // 10, f"код {код}") if 20 <= код < 100 else f"код {код}"


def _целое(биты: np.ndarray, от: int, длина: int, знак: bool = False) -> int:
    ч = int("".join(str(int(б)) for б in биты[от:от + длина]) or "0", 2)
    if знак and длина and ч >> (длина - 1):
        ч -= 1 << длина
    return ч


def _текст(биты: np.ndarray, от: int, длина: int) -> str:
    итог = []
    for i in range(от, от + длина - 5, 6):
        n = _целое(биты, i, 6)
        if n == 0:
            break
        итог.append(chr(n + 64 if n < 32 else n))
    return "".join(итог).strip()


def из_nmea(полезная: str, заполнение: int = 0) -> np.ndarray:
    """Полезная часть !AIVDM → биты (6 на знак)."""
    биты = []
    for с in полезная:
        n = (ord(с) - (0x30 if ord(с) < 0x60 else 0x38)) & 0x3F
        биты.extend((n >> (5 - k)) & 1 for k in range(6))
    return np.array(биты[:len(биты) - заполнение] if заполнение else биты, dtype=np.uint8)


def в_nmea(биты: np.ndarray) -> Tuple[str, int]:
    """Биты → полезная часть и число заполняющих бит (для синтеза)."""
    биты = list(np.asarray(биты, dtype=np.uint8))
    заполнение = -len(биты) % 6
    биты += [0] * заполнение
    знаки = []
    for i in range(0, len(биты), 6):
        n = int("".join(map(str, биты[i:i + 6])), 2)
        знаки.append(chr(n + 48 if n < 40 else n + 56))
    return "".join(знаки), заполнение


def _координаты(биты: np.ndarray, от: int) -> Optional[Tuple[float, float]]:
    """(широта, долгота) из долготы 28 и широты 27 бит; None — «нет данных» (181° / 91°)."""
    долгота = _целое(биты, от, 28, True) / 600000
    широта = _целое(биты, от + 28, 27, True) / 600000
    if abs(долгота) > 180 or abs(широта) > 90:
        return None
    return round(широта, 6), round(долгота, 6)


def разобрать(биты: np.ndarray) -> Optional[Dict[str, object]]:
    """Поля сообщения; None — тип не поддержан или бит не хватает."""
    биты = np.asarray(биты, dtype=np.uint8)
    if len(биты) < 38:
        return None
    тип = _целое(биты, 0, 6)
    п: Dict[str, object] = {"тип": тип, "повтор": _целое(биты, 6, 2), "mmsi": _целое(биты, 8, 30)}
    if тип in (1, 2, 3) and len(биты) >= 168:
        п["состояние"] = СОСТОЯНИЯ.get(_целое(биты, 38, 4), "резерв")
        п["скорость"] = None if _целое(биты, 50, 10) == 1023 else _целое(биты, 50, 10) / 10
        п["координаты"] = _координаты(биты, 61)
        п["курс"] = None if _целое(биты, 116, 12) == 3600 else _целое(биты, 116, 12) / 10
        п["истинный_курс"] = None if _целое(биты, 128, 9) == 511 else _целое(биты, 128, 9)
        п["секунда"] = _целое(биты, 137, 6)
    elif тип == 4 and len(биты) >= 168:
        п["время"] = (f"{_целое(биты, 38, 14):04d}-{_целое(биты, 52, 4):02d}-{_целое(биты, 56, 5):02d} "
                      f"{_целое(биты, 61, 5):02d}:{_целое(биты, 66, 6):02d}:{_целое(биты, 72, 6):02d} UTC")
        п["координаты"] = _координаты(биты, 79)
    elif тип == 5 and len(биты) >= 422:
        п["imo"] = _целое(биты, 40, 30)
        п["позывной"] = _текст(биты, 70, 42)
        п["название"] = _текст(биты, 112, 120)
        п["тип_судна"] = тип_судна(_целое(биты, 232, 8))
        п["размеры"] = tuple(_целое(биты, о, д) for о, д in ((240, 9), (249, 9), (258, 6), (264, 6)))
        п["осадка"] = _целое(биты, 294, 8) / 10
        п["назначение"] = _текст(биты, 302, 120)
    elif тип in (18, 19) and len(биты) >= 168:
        п["скорость"] = None if _целое(биты, 46, 10) == 1023 else _целое(биты, 46, 10) / 10
        п["координаты"] = _координаты(биты, 57)
        п["курс"] = None if _целое(биты, 112, 12) == 3600 else _целое(биты, 112, 12) / 10
        п["истинный_курс"] = None if _целое(биты, 124, 9) == 511 else _целое(биты, 124, 9)
        if тип == 19 and len(биты) >= 312:
            п["название"] = _текст(биты, 143, 120)
            п["тип_судна"] = тип_судна(_целое(биты, 263, 8))
    elif тип == 21 and len(биты) >= 219:                  # до конца широты; продолжение имени — после 272
        п["вид_средства"] = _целое(биты, 38, 5)
        п["название"] = (_текст(биты, 43, 120) + (_текст(биты, 272, len(биты) - 272) if len(биты) > 272
                                                   else "")).strip()
        п["координаты"] = _координаты(биты, 164)
    elif тип == 24 and len(биты) >= 160:
        часть = _целое(биты, 38, 2)
        п["часть"] = "A" if часть == 0 else "B"
        if часть == 0:
            п["название"] = _текст(биты, 40, 120)
        elif len(биты) >= 168:
            п["тип_судна"] = тип_судна(_целое(биты, 40, 8))
            п["позывной"] = _текст(биты, 90, 42)
    elif тип not in ТИПЫ:
        return п
    else:
        return None
    return п


def описание(п: Dict[str, object]) -> str:
    """Строка для отчёта."""
    тип = int(п["тип"])
    части = [f"MMSI {п['mmsi']}", ТИПЫ.get(тип, f"тип {тип}")]
    for ключ, подпись in (("название", ""), ("позывной", "позывной "), ("тип_судна", "")):
        if п.get(ключ):
            части.append(f"{подпись}{п[ключ]}")
    if п.get("координаты"):
        ш, д = п["координаты"]
        части.append(f"{ш:.5f}, {д:.5f}")
    if п.get("скорость") is not None:
        части.append(f"{п['скорость']} уз")
    if п.get("курс") is not None:
        части.append(f"курс {п['курс']}°")
    if п.get("состояние"):
        части.append(str(п["состояние"]))
    if п.get("назначение"):
        части.append(f"в {п['назначение']}")
    if п.get("время"):
        части.append(str(п["время"]))
    return ", ".join(части)


def годное_по_длине(биты_длина: int, тип: int) -> bool:
    return биты_длина in ДЛИНЫ.get(тип, ())


def сводка(сообщения: List[Dict[str, object]], сколько: int = 40) -> List[str]:
    """Строки по судам: последнее известное о каждом MMSI."""
    суда: Dict[int, Dict[str, object]] = {}
    for п in сообщения:
        суда.setdefault(int(п["mmsi"]), {}).update({к: з for к, з in п.items() if з is not None})
    строки = [f"сообщений AIS: {len(сообщения)}, судов и станций (MMSI): {len(суда)}"]
    for mmsi, п in list(суда.items())[:сколько]:
        строки.append(описание({**п, "mmsi": mmsi}))
    return строки
