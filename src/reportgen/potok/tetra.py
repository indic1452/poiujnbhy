"""TETRA (ETSI EN 300 392-2), нисходящий канал: пачки, нижний MAC, SYNC, AACH, MAC-PDU.

Как у osmo-tetra (phy/tetra_burst.c, lower_mac/*.c, tetra_mac_pdu.c, tetra_common.c):
- пачка — 510 бит (255 символов π/4-DQPSK), подряд; синхронизирующая (SB): обучающая y (38 бит)
  с бита 214, блок 1 (120) с 94, широковещательный блок (30) с 252, блок 2 (216) с 282;
  обычная (NDB): обучающая n (один канал — SCH/F из двух половин) или p (два канала) с бита 244,
  блок 1 (216) с 14, широковещательный блок — 14 бит с 230 и 16 бит с 266, блок 2 (216) с 282;
- нижний MAC: скремблер (32-битовый регистр, отводы 32 26 23 22 16 12 11 10 8 7 5 4 2 1; начальное
  для BSCH — 3, иначе ((цвет | MNC << 6 | MCC << 20) << 2) | 3), блочное перемежение
  k = 1 + (a·i mod K), выкалывание 2/3 материнского кода 1/4 (K = 5, G1 = 1 + D + D⁴,
  G2 = 1 + D² + D³ + D⁴, G3 = 1 + D + D² + D⁴, G4 = 1 + D + D³ + D⁴), хвост 4 нуля,
  CRC-16 ITU-T (начальное 0xFFFF) — остаток 0x1D0F; широковещательный блок (AACH) — RM(30, 14);
- SYNC (BSCH, 60 бит): код системы, цвет, TN, FN, MN, MCC, MNC; по ним — скремблер ячейки;
- MAC-PDU: тип (RESOURCE, FRAG/END, BROADCAST — SYSINFO/ACCESS-DEFINE, SUPPLEMENTARY);
  RESOURCE — шифрование, адрес (SSI, событие, USSI, SMI); SYSINFO — несущая, диапазон, LA, службы.
"""

