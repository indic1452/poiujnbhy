def sync_биты(сеть: Сеть, tn: int = 1, fn: int = 1, mn: int = 1) -> list[int]:
    б = [0] * 60
    for от, n, v in ((0, 4, сеть.код_системы), (4, 6, сеть.цвет), (10, 2, tn - 1), (12, 5, fn), (17, 6, mn),
                     (31, 10, сеть.mcc), (41, 14, сеть.mnc)):
        for i in range(n):
            б[от + i] = (v >> (n - 1 - i)) & 1
    return б


def пачка_sb(сеть: Сеть, блок2: Sequence[int], aach: int, tn: int = 1, fn: int = 1, mn: int = 1) -> np.ndarray:
    б = np.zeros(ПАЧКА, dtype=np.uint8)
    б[SB_Y:SB_Y + 38] = Y_БИТЫ
    б[SB_БЛОК1:SB_БЛОК1 + 120] = закодировать_блок(sync_биты(сеть, tn, fn, mn), СКРЕМБЛЕР_BSCH, SB1)
    б[SB_BB:SB_BB + 30] = _bb(aach, сеть)
    б[SB_БЛОК2:SB_БЛОК2 + 216] = закодировать_блок(блок2, сеть.скремблер, ПОЛБЛОКА)
    б[:12], б[500:] = Q_БИТЫ[10:], Q_БИТЫ[:10]
    return б


def _bb(aach: int, сеть: Сеть) -> np.ndarray:
    с = rm_кодировать(aach)
    return np.array([(с >> (29 - i)) & 1 for i in range(30)], dtype=np.uint8) ^ гамма(сеть.скремблер, 30)


def пачка_ndb(сеть: Сеть, блоки: Sequence[Sequence[int]], aach: int) -> np.ndarray:
    """Один блок из 268 бит — SCH/F (обучающая n), два по 124 — две половины (обучающая p)."""
    б = np.zeros(ПАЧКА, dtype=np.uint8)
    bb = _bb(aach, сеть)
    б[NDB_BB1:NDB_BB1 + 14], б[NDB_BB2:NDB_BB2 + 16] = bb[:14], bb[14:]
    if len(блоки) == 1:
        полный = закодировать_блок(блоки[0], сеть.скремблер, SCH_F)
        б[NDB_ОБУЧ:NDB_ОБУЧ + 22] = N_БИТЫ
        б[NDB_БЛОК1:NDB_БЛОК1 + 216], б[NDB_БЛОК2:NDB_БЛОК2 + 216] = полный[:216], полный[216:]
    else:
        б[NDB_ОБУЧ:NDB_ОБУЧ + 22] = P_БИТЫ
        б[NDB_БЛОК1:NDB_БЛОК1 + 216] = закодировать_блок(блоки[0], сеть.скремблер, ПОЛБЛОКА)
        б[NDB_БЛОК2:NDB_БЛОК2 + 216] = закодировать_блок(блоки[1], сеть.скремблер, ПОЛБЛОКА)
    б[:12], б[500:] = Q_БИТЫ[10:], Q_БИТЫ[:10]
    return б
