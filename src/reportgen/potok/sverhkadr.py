"""Сверхкадр модема с известными символами и словами LDPC в нагрузке (не PLFRAME DVB-S2).

Модем кладёт кодовые слова LDPC (DVB-S2 и др.) не в PLFRAME, а в свой сверхкадр: заголовок, блоки
пилотов и короткие маркеры — известные символы, одни и те же в каждом сверхкадре, остальное — слова
кода подряд. Цикл автомат видит (заголовок — синхрослово), но нагрузка — не «кадр без синхрослова»:
пилоты и маркеры разбросаны по всему сверхкадру. Поэтому:

1. Поток складывается по периоду сверхкадра P: позиция, где бит совпадает почти во всех сверхкадрах
   (не реже ПОСТОЯННО_ОТ), — известная; берутся участки не короче УЧАСТОК_ОТ бит подряд (у случайной
   позиции такое совпадение — редкость, у нескольких подряд — исключено).
2. Нагрузка — остальные позиции, сверхкадр за сверхкадром. Если в ней целое число слов встроенного кода,
   опознаватель LDPC ищет код и границу слова: проверки H на нагрузке — мера, которую шум и чужой код не
   набирают (у случайных бит нарушена половина проверок).
3. Порядок бит в байте файла неизвестен: демодулятор пишет символы старшим битом вперёд, младшим или
   тетрадами (младшая тетрада байта — первой). Период, кратный байту, виден при любом порядке, проверки
   кода сходятся только в верном.

После LDPC у кода DVB-S2 сверяется внешний БЧХ стандарта (остаток слова nbch бит); не сходится — так и
пишется: последние nbch − kbch бит — не проверочные биты БЧХ (у слов с одинаковыми данными они разные).
"""

from __future__ import annotations

import time
from collections import Counter

import numpy as np

from .nahodka import Находка

#: Порядки бит в байте файла: (как, перестановка бит байта от «старший первым», слои стола).
ПОРЯДКИ = (
    ("старший бит первым", None, ()),
    ("младший бит первым", (7, 6, 5, 4, 3, 2, 1, 0), ("реверс 8",)),
    ("тетрады байта переставлены (младшая — первой)", (4, 5, 6, 7, 0, 1, 2, 3), ("реверс 8", "реверс 4")),
    ("тетрады переставлены, младший бит первым", (3, 2, 1, 0, 7, 6, 5, 4), ("реверс 4",)),
)
#: Позиция известна, если бит в ней совпал не меньше чем в такой доле сверхкадров…
ПОСТОЯННО_ОТ = 0.9
#: …и таких позиций подряд не меньше стольких (маркер — два символа QPSK).
УЧАСТОК_ОТ = 4
#: Сверхкадров в выборке не меньше стольких; складывается не больше стольких бит (весь файл, если короче).
СВЕРХКАДРОВ_ОТ = 8
СКЛАДЫВАТЬ_ДО = 1 << 26
#: Если нагрузка не делится на длину слова, но до кратного не дальше стольких бит, известных позиций берётся
#: ровно столько, сколько нужно, — по убыванию совпадения (на краях участков бывают случайно «постоянные»
#: биты данных, а у ошибок линии известный бит совпадает не в каждом сверхкадре).
ПОПРАВКА_ДО = 64
#: Слов кода короче этого не ищем: короткий код в нагрузке длинного сверхкадра — не этот путь.
СЛОВО_ОТ = 1024
#: Блоки пилотов — известные участки одной длины, не короче стольких бит и не меньше стольких штук.
ПИЛОТ_ОТ = 16
ПИЛОТОВ_ОТ = 3


def в_порядке(биты: np.ndarray, перестановка) -> np.ndarray:
    """Биты в другом порядке внутри каждого байта (перестановка позиций «старший первым»)."""
    if перестановка is None:
        return биты
    б = np.asarray(биты[:len(биты) // 8 * 8], dtype=np.uint8).reshape(-1, 8)
    return np.ascontiguousarray(б[:, list(перестановка)]).reshape(-1)


def совпадение(биты: np.ndarray, P: int) -> np.ndarray | None:
    """Для каждой позиции сверхкадра (длины P) — доля сверхкадров, где бит такой же, как в большинстве;
    None — сверхкадров мало."""
    n = min(len(биты), СКЛАДЫВАТЬ_ДО) // P
    if n < СВЕРХКАДРОВ_ОТ:
        return None
    доля = np.asarray(биты[:n * P], dtype=np.uint8).reshape(n, P).mean(axis=0)
    return np.maximum(доля, 1 - доля)


def известные(биты: np.ndarray, P: int, согласие: np.ndarray | None = None) -> np.ndarray | None:
    """Маска известных позиций сверхкадра (длины P); None — сверхкадров мало."""
    согласие = совпадение(биты, P) if согласие is None else согласие
    if согласие is None:
        return None
    маска = np.zeros(P, dtype=bool)
    for н, д in участки(согласие >= ПОСТОЯННО_ОТ):
        if д >= УЧАСТОК_ОТ:
            маска[н:н + д] = True
    return маска


def под_слово(маска: np.ndarray, согласие: np.ndarray, L: int) -> np.ndarray | None:
    """Маска, у которой нагрузка кратна L: известных позиций — ближайшее подходящее число, лучшие по совпадению
    (ближе ПОПРАВКА_ДО бит к найденному порогом); None — не выходит."""
    P = len(маска)
    Q0 = int((~маска).sum())
    Q = int(round(Q0 / L)) * L
    if not 0 < Q < P or abs(Q - Q0) > ПОПРАВКА_ДО:
        return None
    if Q == Q0:
        return маска
    # Кандидаты в известные — найденные и их соседи по краям участков; порядок — по совпадению.
    рядом = маска | np.concatenate([[False], маска[:-1]]) | np.concatenate([маска[1:], [False]])
    порядок = np.flatnonzero(рядом)[np.argsort(-согласие[рядом], kind="stable")]
    if len(порядок) < P - Q:
        return None
    итог = np.zeros(P, dtype=bool)
    итог[порядок[:P - Q]] = True
    return итог


def участки(маска: np.ndarray) -> list[tuple[int, int]]:
    """Участки подряд идущих True: (начало, длина)."""
    м = np.concatenate([[False], np.asarray(маска, dtype=bool), [False]]).astype(np.int8)
    края = np.flatnonzero(np.diff(м))
    return [(int(a), int(b - a)) for a, b in zip(края[::2], края[1::2], strict=True)]


def строение(маска: np.ndarray) -> dict[str, object]:
    """Известные участки сверхкадра словами: заголовок (самый длинный), блоки пилотов (одной длины ≥ ПИЛОТ_ОТ,
    их шаг) и маркеры (остальные короткие)."""
    у = участки(маска)
    if not у:
        return {"участков": 0}
    заголовок = max(у, key=lambda п: п[1])
    прочие = [п for п in у if п != заголовок]
    длины = Counter(д for _, д in прочие if д >= ПИЛОТ_ОТ)
    пилот, пилотов = (длины.most_common(1)[0] if длины else (0, 0))
    if пилотов < ПИЛОТОВ_ОТ:
        пилот, пилотов = 0, 0
    места = [н for н, д in прочие if д == пилот] if пилот else []
    шаг = Counter(np.diff(места).tolist()).most_common(1)[0][0] if len(места) > 1 else 0
    маркеры = [д for _, д in прочие if д != пилот]
    return {"участков": len(у), "заголовок": заголовок, "пилот": int(пилот), "пилотов": int(пилотов),
            "шаг_пилотов": int(шаг), "маркеров": len(маркеры),
            "маркер": Counter(маркеры).most_common(1)[0][0] if маркеры else 0,
            "шаг_маркеров": (Counter(np.diff([н for н, д in прочие if д != пилот]).tolist()).most_common(1)[0][0]
                             if len(маркеры) > 1 else 0)}


def нагрузка(биты: np.ndarray, P: int, маска: np.ndarray) -> np.ndarray:
    """Неизвестные позиции сверхкадров подряд (целые сверхкадры выборки)."""
    n = len(биты) // P
    return np.ascontiguousarray(np.asarray(биты[:n * P], dtype=np.uint8).reshape(n, P)[:, ~маска]).reshape(-1)


def _описание(с: dict[str, object], P: int, Q: int) -> str:
    части = [f"сверхкадр {P} бит: известных {P - Q}"]
    if с.get("заголовок"):
        части.append(f"заголовок {с['заголовок'][1]} бит с бита {с['заголовок'][0]}")
    if с.get("пилотов"):
        части.append(f"блоков пилотов {с['пилотов']} по {с['пилот']} бит" + (
            f" через {с['шаг_пилотов']}" if с.get("шаг_пилотов") else ""))
    if с.get("маркеров"):
        части.append(f"маркеров {с['маркеров']} по {с['маркер']} бит" + (
            f" через {с['шаг_маркеров']}" if с.get("шаг_маркеров") else ""))
    return ", ".join(части) + f"; нагрузка {Q} бит"


def _бчх(данные: np.ndarray, имя: str, n_данных: int) -> list[str]:
    """Сверка внешнего БЧХ DVB-S2 на словах после LDPC — строками отчёта (пусто — код не DVB-S2)."""
    from . import dvbs2  # noqa: PLC0415
    if not имя.startswith("dvb-s2"):
        return []
    коды = [к for к in dvbs2.КОДЫ if к.nbch == n_данных]
    if not коды:
        return []
    слова = np.asarray(данные[:len(данные) // n_данных * n_данных], dtype=np.uint8).reshape(-1, n_данных)[:8]
    if not len(слова):
        return []
    for код in sorted(коды, key=lambda к: -к.t):
        if sum(dvbs2.остаток(с, код.g) == 0 for с in слова) * 2 >= len(слова):
            return [f"внешний БЧХ DVB-S2 ({код.nbch} → {код.kbch}, t = {код.t}): остаток нулевой — сходится"]
    код = коды[0]
    строка = (f"внешний БЧХ DVB-S2 ({код.nbch} → {код.kbch}): остаток не нулевой ни у одного из {len(слова)} "
              f"слов — последние {код.nbch - код.kbch} бит слова не проверочные биты БЧХ стандарта")
    все = np.asarray(данные[:len(данные) // n_данных * n_данных], dtype=np.uint8).reshape(-1, n_данных)
    по_данным: dict[bytes, int] = {}
    различны = 0
    for i, с in enumerate(все):
        ключ = np.packbits(с[:код.kbch]).tobytes()
        if ключ in по_данным:
            различны += int((все[по_данным[ключ], код.kbch:] != с[код.kbch:]).any())
        else:
            по_данным[ключ] = i
    if различны:
        строка += (f" (у {различны} пар слов с одинаковыми первыми {код.kbch} битами они разные — не функция "
                   f"данных)")
    return [строка + f"; данные — первые {код.kbch} бит слова"]


#: Пробное декодирование опознанного кода: слов и наименьшая доля сошедшихся.
ПРОБА_СЛОВ = 8
СОШЛОСЬ_ОТ = 0.5


def найти(биты: np.ndarray, P: int, *, верх: bool = True, срок: float = 60.0,
          больше: np.ndarray | None = None) -> Находка | None:
    """Слова LDPC в нагрузке сверхкадра длины P (бит): находка кода (данные — дальше) или None.

    ``верх`` — ряд прочитан прямо из байт файла: пробуются и другие порядки бит в байте; ``больше`` — тот же
    ряд длиннее выборки (с того же бита): по нему складываются сверхкадры — известные позиции надёжнее."""
    from . import ldpc_opoznanie, ldpc_std  # noqa: PLC0415
    конец = time.monotonic() + срок
    биты = np.asarray(биты, dtype=np.uint8)
    for как, перестановка, слои in (ПОРЯДКИ if верх and P % 8 == 0 else ПОРЯДКИ[:1]):
        if time.monotonic() > конец:
            break
        ряд = в_порядке(биты, перестановка)
        складено = в_порядке(больше, перестановка) if больше is not None and len(больше) > len(биты) else ряд
        согласие = совпадение(складено, P)
        if согласие is None:
            return None
        найдено = известные(ряд, P, согласие)
        Q0 = int((~найдено).sum())
        if not найдено.any() or Q0 < СЛОВО_ОТ:
            return None
        # Длины встроенных кодов, которые укладываются в нагрузку целым числом (с поправкой на край участков).
        по_длине: dict[int, list[str]] = {}
        for и in ldpc_std.подходящие(None):
            L = ldpc_std.длина_в_потоке(и)
            if СЛОВО_ОТ <= L <= Q0 + ПОПРАВКА_ДО:
                по_длине.setdefault(L, []).append(и)
        к = None
        for L, имена in sorted(по_длине.items(), key=lambda п: -п[0]):
            маска = под_слово(найдено, согласие, L)
            if маска is None or time.monotonic() > конец:
                continue
            Q = int((~маска).sum())
            поток = нагрузка(ряд, P, маска)
            кандидаты, сведения = ldpc_opoznanie.опознать(поток, имена=имена, срок=max(1.0, конец - time.monotonic()),
                                                          младший=False, маска_дольше=False)
            к, выбор = ldpc_opoznanie.выбрать(поток, кандидаты)
            if к is not None and ldpc_opoznanie.пробное(поток, к, слов=ПРОБА_СЛОВ)[0] < СОШЛОСЬ_ОТ:
                # Совпал по проверкам, но слова не сходятся — чужой код: декодировать тысячи слов незачем.
                к = None
            if к is not None:
                break
        if к is None:
            continue
        с = строение(маска)
        находка = ldpc_opoznanie.находка(поток, к, сведения=сведения, выбор=выбор)
        L = ldpc_std.длина_в_потоке(к.имя)
        находка.что = (f"{находка.что.split(';')[0]}; в нагрузке сверхкадра {P} бит ({Q // L} слов на сверхкадр)"
                       + (f"; {как}" if перестановка is not None else ""))
        находка.подробно[:0] = [
            _описание(с, P, Q) + f" = {Q // L} × {L} — слова кода «{к.имя}» подряд, первое — с бита {к.начало} "
            f"нагрузки",
            "известные позиции — по совпадению бита в ≥ "
            f"{ПОСТОЯННО_ОТ * 100:.0f} % из {min(len(складено), СКЛАДЫВАТЬ_ДО) // P} "
            f"сверхкадров, участками от {УЧАСТОК_ОТ} бит" + (
                f"; по краям участков поправлено {abs(Q - Q0)} бит до целого числа слов" if Q != Q0 else ""),
        ] + ([f"порядок бит в байте файла — {как}: в других порядках проверки кода не сходятся"]
             if перестановка is not None else [])
        n_данных = int(находка.свойства.get("данных_в_блоке") or 0)
        находка.подробно += _бчх(np.asarray(находка.дальше, dtype=np.uint8), к.имя, n_данных)
        # Слоями стола: порядок бит в байте, «сверхкадр P слово L» (нагрузка без известных позиций), «ldpc …».
        находка.свойства.update({"сверхкадр": P, "нагрузка_сверхкадра": Q, "строение_сверхкадра": с,
                                 "порядок_байта": как, "перед": list(слои) + [f"сверхкадр {P} слово {L}"]})
        return находка
    return None
