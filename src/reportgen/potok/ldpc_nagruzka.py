"""LDPC в нагрузке длинного кадра: в кадре после синхрослова — одно или несколько слов кода подряд.

Кадр модема длиннее 8192 бит (``ldpc_kadr`` берёт кадр целиком словом — там слов из выборки хватает лишь
на короткие кадры): нагрузка — кадр без служебного слова (синхрослова), в ней m слов по n = нагрузка/m бит
(модем CASC: кадр 16 632 бит, синхрослово 504, два слова по 8064). Слова берутся со всего файла (не с
выборки разбора): при n в тысячи бит различных слов должно быть больше n — тогда пространство проверок даёт
ядро (``ldpc_yadro``), а при нехватке — частичный Гаусс со Штерном (``ldpc_vosst``).

**Сколько слов в кадре.** Нарезки m — делители нагрузки (n не короче СЛОВО_ОТ), по порядку правдоподобия:
у слов с проверками и данными столбцы разные по смыслу (у заполнения под скремблером со сбросом на слове
доля единиц по столбцу повторяется через n), поэтому сперва — нарезки, у которых профиль столбцов
повторяется через n. Проба нарезки — ядро всех различных слов и пара перестановок Ли — Брикелла: у верной
нарезки разреженных проверок сотни, у неверной — нет.

**Повторный разбор.** Восстановленная H сохраняется файлом alist в папку матриц отдела (с позициями
данных); при следующем разборе того же потока она находится по словам сразу (``ldpc_yadro.сохранённая``).

**Пилоты поверх бит кода.** Если выше вырезана вставка, а места её — не вставлены между битами кода, а
заменили биты слова (выколоты), код в потоке без вставки — укороченный по проверкам: связей ядра меньше, чем
проверочных позиций, и часть позиций не входит ни в одну проверку без выколотых (нулевые столбцы ядра). Это
пишется в находке: ошибки на таких позициях не исправить без полной H.
"""

from __future__ import annotations

import time
from collections.abc import Callable
from dataclasses import dataclass

import numpy as np

from . import cikl, ldpc_yadro
from .nahodka import Находка

#: Слово кода в нагрузке — не короче; слов в кадре — не больше.
СЛОВО_ОТ = 512
СЛОВ_В_КАДРЕ_ДО = 8
#: Служебное слово кадра (синхрослово) вырезается из нагрузки, если не короче: короткие постоянные участки
#: — постоянство заполнения в данных.
СЛУЖЕБНОЕ_ОТ = 16
#: Кадров — не меньше.
КАДРОВ_ОТ = 16
#: Проба нарезки удалась: разреженных проверок не меньше max(ПРОБА_ОТ, n / ПРОБА_ДОЛЯ).
ПРОБА_ОТ = 16
ПРОБА_ДОЛЯ = 64
#: Профиль столбцов повторяется через n, если расхождение меньше стольких «шумов» доли единиц.
ПРОФИЛЬ_ШУМОВ = 4.0
#: Доля срока на пробы нарезок.
ПРОБЫ_ДОЛЯ = 0.3


@dataclass
class Нагрузка:
    начала: list[int]            # начала кадров в потоке (начало служебного слова)
    кадр: int
    поля: list[tuple[int, int]]   # вырезанные служебные слова (место от начала кадра, длина)
    столбцы: np.ndarray          # места нагрузки от начала кадра
    W: np.ndarray                # кадры × нагрузка


def нагрузка_кадров(биты: np.ndarray, L: int, *, все_поля: bool = False) -> Нагрузка | None:
    """Кадры длины L по служебным словам с маховиком; из нагрузки вырезается синхрослово (самое длинное
    служебное слово), с ``все_поля`` — и прочие служебные слова не короче СЛУЖЕБНОЕ_ОТ (постоянные участки
    короче бывают и у данных заполнения). Чередующееся синхрослово — не берётся."""
    найдено = cikl.кадры(биты, L)
    if найдено is None:
        return None
    начала, сведения = найдено
    if сведения.get("чередование") or int(сведения["кадр"]) != L:
        return None
    слова = [(int(н), int(д)) for н, д in сведения["слова"]]
    if not слова:
        return None
    главное = max(слова, key=lambda с: с[1])
    поля = [с for с in слова if с[1] >= СЛУЖЕБНОЕ_ОТ] if все_поля else [главное]
    if главное[1] < СЛУЖЕБНОЕ_ОТ:
        return None
    оставить = np.ones(L, dtype=bool)
    for н, д in поля:
        оставить[(н + np.arange(д)) % L] = False
    столбцы = np.flatnonzero(оставить)
    начала = [int(н) for н in начала if н + L <= len(биты)]
    if len(начала) < КАДРОВ_ОТ:
        return None
    W = np.stack([биты[н:н + L][столбцы] for н in начала])
    return Нагрузка(начала, L, поля, столбцы, W)


def нарезки(W: np.ndarray) -> list[tuple[int, int, float]]:
    """(m, n, расхождение профиля): делители нагрузки — от правдоподобных (профиль столбцов повторяется через
    n), при равенстве — длинные слова раньше."""
    F, B = W.shape
    профиль = W.mean(axis=0)
    шум = 0.56 / np.sqrt(max(1, F))
    итог = []
    for m in range(1, СЛОВ_В_КАДРЕ_ДО + 1):
        if B % m or B // m < СЛОВО_ОТ:
            continue
        n = B // m
        if m == 1:
            расхождение = 0.0
        else:
            куски = профиль.reshape(m, n)
            расхождение = float(np.abs(куски[1:] - куски[0]).mean())
        итог.append((m, n, расхождение))
    return sorted(итог, key=lambda т: (т[2] > ПРОФИЛЬ_ШУМОВ * шум, т[0]))


def _слова(н: Нагрузка, m: int) -> np.ndarray:
    F, B = н.W.shape
    return н.W.reshape(F * m, B // m)


_КЭШ: dict = {}


def _нагрузка(биты: np.ndarray, L: int, все_поля: bool = False) -> Нагрузка | None:
    """Нагрузка кадров (с кэшем на последний поток: проба по сохранённым матрицам и поиск берут одну)."""
    ключ = (id(биты), len(биты), L, все_поля)
    if ключ not in _КЭШ:
        _КЭШ.clear()
        _КЭШ[ключ] = нагрузка_кадров(биты, L, все_поля=все_поля)
    return _КЭШ[ключ]


def найти(биты: np.ndarray, L: int, *, срок: float = 180.0, стоп: Callable[[], bool] | None = None,
          ход: Callable[[str], None] | None = None, только_сохранённые: bool = False
          ) -> tuple[Находка | None, str]:
    """LDPC в нагрузке кадра длины L по всему потоку ``биты``: (находка или None, почему нет).
    ``только_сохранённые`` — лишь матрицы, восстановленные раньше (быстро, до прочих поисков кода); нагрузка
    кадров после такой пробы остаётся в кэше для поиска, после поиска — сбрасывается."""
    try:
        return _найти(биты, L, срок=срок, стоп=стоп, ход=ход, только_сохранённые=только_сохранённые)
    finally:
        if not только_сохранённые:
            _КЭШ.clear()


def _найти(биты: np.ndarray, L: int, *, срок: float, стоп: Callable[[], bool] | None,
           ход: Callable[[str], None] | None, только_сохранённые: bool) -> tuple[Находка | None, str]:
    начато = time.monotonic()

    def сказать(строка: str) -> None:
        if ход is not None:
            ход(строка)

    def остаток() -> float:
        return срок - (time.monotonic() - начато)

    н = _нагрузка(биты, L)
    if н is None:
        return None, f"кадры {L} бит с синхрословом от {СЛУЖЕБНОЕ_ОТ} бит не выделились"
    варианты = нарезки(н.W)
    if not варианты:
        другая = _нагрузка(биты, L, все_поля=True)
        if другая is not None and другая.W.shape[1] != н.W.shape[1] and нарезки(другая.W):
            н, варианты = другая, нарезки(другая.W)
    F, B = н.W.shape
    if not варианты:
        return None, f"нагрузка {B} бит не делится на слова от {СЛОВО_ОТ} бит"
    сказать(f"LDPC в нагрузке кадра {L} бит: {F} кадров, нагрузка {B} бит; нарезки: "
            + ", ".join(f"{m}×{n}" for m, n, _ in варианты))
    # Матрица, восстановленная раньше (папка отдела), — сразу.
    for m, n, _ in варианты:
        сохранённая = ldpc_yadro.сохранённая(_слова(н, m))
        if сохранённая is not None:
            имя, проверки, данные = сохранённая
            сказать(f"слова {n} бит: подошла сохранённая матрица «{имя}»")
            return _находка(н, m, проверки, данные, имя=имя, итог=None), ""
    if только_сохранённые:
        return None, "сохранённой матрицы для этих слов нет"
    выбрана = None
    почему: list[str] = []
    for m, n, _ in варианты:
        W = _слова(н, m)
        различных = len(ldpc_yadro.различные(W))
        if различных < ldpc_yadro.слов_нужно(n):
            почему.append(f"{m}×{n}: различных слов {различных} — меньше {ldpc_yadro.слов_нужно(n)}")
            continue
        if остаток() <= 5:
            почему.append("время вышло")
            break
        сказать(f"пробую нарезку {m}×{n} бит (ядро и пара перестановок)")
        проба = ldpc_yadro.восстановить(W, срок=max(5.0, min(ПРОБЫ_ДОЛЯ * срок, остаток())), стоп=стоп,
                                        проба=True)
        нужно = max(ПРОБА_ОТ, n // ПРОБА_ДОЛЯ)
        if проба.ранг >= нужно:
            выбрана = (m, n)
            сказать(f"нарезка {m}×{n}: разреженных проверок {проба.ранг} — код есть")
            break
        почему.append(f"{m}×{n}: разреженных проверок {проба.ранг} (нужно от {нужно})")
    if выбрана is None:
        return None, "; ".join(почему) or "нарезок нет"
    m, n = выбрана
    W = _слова(н, m)
    итог = ldpc_yadro.восстановить(W, срок=max(10.0, остаток() * 0.75), стоп=стоп, ход=ход)
    if итог.ранг < max(ПРОБА_ОТ, n // ПРОБА_ДОЛЯ) or getattr(итог, "данные", None) is None:
        return None, f"{m}×{n}: проверок {итог.ранг} — мало для снятия ({итог.почему})"
    имя = ""
    from . import ldpc  # noqa: PLC0415
    if ldpc.КАТАЛОГ is not None:
        try:
            имя = ldpc_yadro.сохранить(итог, откуда=f"автомат: кадр {L} бит, {m} слов по {n} бит в нагрузке")
        except (ValueError, OSError):
            имя = ""
    return _находка(н, m, итог.проверки, итог.данные, имя=имя, итог=итог), ""


def _находка(н: Нагрузка, m: int, проверки: list[np.ndarray], данные: np.ndarray, *, имя: str, итог
             ) -> Находка:
    W = _слова(н, m)
    n = W.shape[1]
    исправленные, ок, исправлено = ldpc_yadro.декодировать(W, проверки)
    k = len(данные)
    выход = np.ascontiguousarray(исправленные[:, данные])
    в_начале = bool(len(данные) and данные[0] > 0)
    поле = н.поля[0]
    подробно = [
        f"кадр {н.кадр} бит: служебное слово {поле[1]} бит (с бита {поле[0]} кадра) вырезано, нагрузка "
        f"{н.W.shape[1]} бит — {m} слов по {n} бит; кадров {len(н.начала)} (со всего файла), слов {len(W)}",
        f"проверочная часть — в {'начале' if в_начале else 'конце'} слова: данные — биты "
        f"{int(данные[0])}…{int(данные[-1])} слова ({k} бит)",
        f"исправлено бит {исправлено}; синдром нулевой у {ок.mean() * 100:.2f} % слов",
    ]
    if итог is not None:
        подробно.insert(1, f"матрица восстановлена ядром по {итог.слов} различным словам: связей ядра "
                           f"{итог.размерность}, разреженных независимых проверок {итог.ранг} (вес "
                           f"{min(map(len, проверки))}…{max(map(len, проверки))})"
                           + (f", {итог.оператор}" if итог.оператор else "")
                           + f"; BER ≈ {итог.ошибок:.1e}; {итог.секунд:.0f} с")
        без = getattr(итог, "без_проверок", np.zeros(0, dtype=np.int64))
        if len(без):
            в_данных = int(np.isin(без, данные).sum())
            подробно.append(f"позиций слова без проверок {len(без)} (из них в данных {в_данных}): ни одна найденная "
                            "проверка их не содержит — ошибки на них не исправляются; так бывает, когда часть бит "
                            "слова не передана (выколота: пилоты поставлены поверх бит кода) и проверки через них в "
                            "потоке без выколотых не видны")
        if getattr(итог, "непарных", 0):
            подробно.append(f"в проверочной части {итог.непарных} позиций без опорного столбца: размерность кода "
                            f"по словам {n - max(итог.размерность, итог.ранг)}, а данных на виду {k} — часть данных "
                            "слова не передана (выколота: например, пилоты поставлены поверх бит кода), их не "
                            "восстановить без полной H")
        подробно += итог.ход[-3:]
    else:
        подробно.insert(1, f"матрица — сохранённая раньше «{имя}» (восстановлена по этому же потоку)")
    подробно.append(f"матрица сохранена в папку отдела: «{имя}»" if имя and итог is not None else
                    ("" if имя else "матрица не сохранена: папка матриц отдела не задана"))
    подробно = [п for п in подробно if п]
    свойства = {"n": n, "k": k, "кадр": н.кадр, "слов_в_кадре": m, "данных_в_блоке": k, "матрица_файл": имя,
                "проверки_в_начале": в_начале, "начала_кадров": н.начала[:1], "поля": н.поля}
    if итог is not None:
        свойства["восстановлена"] = итог.словарь()
    if имя:
        свойства["слой"] = (f"ldpc {имя} начало {н.начала[0] + int(н.столбцы[0])} шаг {н.кадр}"
                            + (f" смещения {','.join(str(int(н.столбцы[j * n]) - int(н.столбцы[0])) for j in range(m))}"
                               if m > 1 else ""))
    что = (f"LDPC ({n}, {n - max(итог.размерность, итог.ранг) if итог is not None else k}) — {m} слов"
           f"{'а' if 1 < m < 5 else ''} в нагрузке кадра {н.кадр} бит, проверки в "
           f"{'начале' if в_начале else 'конце'} слова; матрица "
           + ("восстановлена по словам" if итог is not None else f"«{имя}»"))
    мера = (f"проверок {len(проверки)}, синдром нулевой у {ок.mean() * 100:.2f} % слов после декодирования; "
            f"исправлено бит {исправлено}")
    return Находка(уровень="код", что=что, уверенность=float(min(1.0, ок.mean())), мера=мера, подробно=подробно,
                   дальше=выход.reshape(-1), вид_дальше="биты", сверка=float(ок.mean()), свойства=свойства)
