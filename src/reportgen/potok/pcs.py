ДЛИНА_БЛОКА = 66
ПОЛЕЗНЫХ = 64
#: Бит на опознавание фазы и выбор толкования (≈ 16 тыс. блоков).
ВЫБОРКА = ДЛИНА_БЛОКА * 16000
#: Сколько бит разбирать целиком (≈ 8 МБ файла) — дальше память дороже пользы.
ПРЕДЕЛ = 1 << 26
#: Меньше скольких блоков не рассматриваем.
НАИМЕНЬШЕ_БЛОКОВ = 200
#: Доля годных заголовков на верной фазе (при ошибках 1e-3 — около 99,8 %).
ПОРОГ_ЗАГОЛОВКОВ = 0.9
#: Медиана по всем фазам — у скремблированного потока около 50 %.
ПОРОГ_ПРОЧИХ_ФАЗ = 0.7
#: Доля блоков управления с типом из допустимого набора (у случайных — 6 %).
ПОРОГ_ТИПОВ = 0.9
#: Меньше скольких блоков управления долю типов не считаем.
НАИМЕНЬШЕ_УПРАВЛЕНИЯ = 16
#: Блоков на перебор полиномов вслепую.
ПЕРЕБОР_БЛОКОВ = 600

ДАННЫЕ, УПРАВЛЕНИЕ = 1, 2          # синхрозаголовок 01 и 10 как число h0·2 + h1

ТИПЫ: dict[int, str] = {
    0x1E: "управляющие символы",
    0x2D: "управляющие + упорядоченный набор",
    0x33: "начало кадра в 4-й позиции",
    0x66: "упорядоченный набор + начало кадра в 4-й позиции",
    0x55: "два упорядоченных набора",
    0x78: "начало кадра в 0-й позиции",
    0x4B: "упорядоченный набор",
    0x87: "конец кадра, 0 октетов", 0x99: "конец кадра, 1 октет",
    0xAA: "конец кадра, 2 октета", 0xB4: "конец кадра, 3 октета",
    0xCC: "конец кадра, 4 октета", 0xD2: "конец кадра, 5 октетов",
    0xE1: "конец кадра, 6 октетов", 0xFF: "конец кадра, 7 октетов",
}
ДОПУСТИМЫЕ = np.array(sorted(ТИПЫ), dtype=np.uint8)
#: Начало кадра: с какого октета блока (0 — поле типа) идут октеты кадра.
НАЧАЛО: dict[int, int] = {0x78: 1, 0x33: 5, 0x66: 5}
#: Конец кадра: сколько октетов данных стоит перед /T/ (с 1-го октета блока).
КОНЕЦ: dict[int, int] = {0x87: 0, 0x99: 1, 0xAA: 2, 0xB4: 3,
                         0xCC: 4, 0xD2: 5, 0xE1: 6, 0xFF: 7}
ПРЕАМБУЛА = b"\x55" * 6 + b"\xd5"
#: Коды управляющих символов в блоке 0x1E.
СИМВОЛ_ПРОСТОЯ, СИМВОЛ_ОШИБКИ = 0x00, 0x1E

ОТВОДЫ_802_3: tuple[int, ...] = next(
    tuple(отводы) for имя, отводы in skrembler.ИЗВЕСТНЫЕ.items() if "10GBASE-R" in имя)

ПОРЯДКИ_В_ФАЙЛЕ = ("как передан", "обратный в байте", "обратный в блоке")


@dataclass
class Разбор66:
    """Всё, что удалось снять с потока 64b/66b, — для отчёта и для проверок."""
    порядок_в_файле: str
    инверсия: bool
    порядок_в_октете: str             # «младший» (по 802.3) или «старший» бит первым
    фаза: int                         # с какого бита ряда (после переворота) идёт заголовок
    отводы: tuple[int, ...]
    откуда_полином: str
    годных_заголовков: float
    прочие_фазы: float                # медиана доли годных по всем фазам
    годных_типов: float
    блоков: int = 0
    данных: int = 0
    управления: int = 0
    негодных: int = 0                 # заголовок 00 или 11
    типы: Counter = field(default_factory=Counter)
    простой: int = 0                  # блоки 0x1E из одних /I/
    с_ошибкой: int = 0                # блоки 0x1E с символом /E/
    наборы: Counter = field(default_factory=Counter)
    собрано: int = 0                  # кадров от начала до конца
    оборвано: int = 0                 # начало без конца (помешал другой блок)
    с_преамбулой: int = 0
    верных: int = 0                   # с верной FCS
    кадры: list[bytes] = field(default_factory=list)   # без преамбулы и FCS
    концы: dict[int, tuple[int, int, int]] = field(default_factory=dict)  # тип → (октетов, верно, всего)
    поправки: list[str] = field(default_factory=list)
    разобрано_бит: int = 0

    @property
    def доля_fcs(self) -> float:
        return self.верных / self.собрано if self.собрано else 0.0


# -- блоки --------------------------------------------------------------------------------


def перевернуть_в_байтах(биты: np.ndarray) -> np.ndarray:
    целых = len(биты) - len(биты) % 8
    return биты[:целых].reshape(-1, 8)[:, ::-1].reshape(-1)


def годность_по_фазам(ряд: np.ndarray) -> np.ndarray:
    """Доля пар 01/10 (бит ≠ следующему) на каждой из 66 фаз."""
    блоков = (len(ряд) - 1) // ДЛИНА_БЛОКА
    if блоков < 1:
        return np.zeros(ДЛИНА_БЛОКА)
    переход = ряд[1:блоков * ДЛИНА_БЛОКА + 1] != ряд[:блоков * ДЛИНА_БЛОКА]
    return переход.reshape(блоков, ДЛИНА_БЛОКА).mean(axis=0)


def блоки(ряд: np.ndarray, фаза: int, в_блоке: bool = False) -> tuple[np.ndarray, np.ndarray]:
    """Синхрозаголовки (1 — данные, 2 — управление, 0/3 — негодный) и полезные части.

    ``в_блоке`` — каждый 66-битовый блок записан задом наперёд: заголовок
    стоит в его конце, и блок начинается через два бита после найденной фазы.
    """
    начало = (фаза + 2) % ДЛИНА_БЛОКА if в_блоке else фаза
    сколько = (len(ряд) - начало) // ДЛИНА_БЛОКА
    блок = ряд[начало:начало + сколько * ДЛИНА_БЛОКА].reshape(сколько, ДЛИНА_БЛОКА)
    if в_блоке:
        блок = блок[:, ::-1]
    заголовки = блок[:, 0].astype(np.int8) * 2 + блок[:, 1].astype(np.int8)
    return заголовки, np.ascontiguousarray(блок[:, 2:])


def снять_скремблер(полезная: np.ndarray, отводы: Sequence[int]) -> np.ndarray:
    """Снять скремблер со склеенной полезной частью; первый блок отбрасывается.

    Мультипликативному дескремблеру нужно max(отводы) бит разгона —
    они попадают в первый блок, поэтому он выбрасывается целиком.
    """
    if not отводы:
        return полезная[1:]
    ряд = skrembler.снять(полезная.reshape(-1), отводы)
    ряд = np.concatenate([np.zeros(max(отводы), dtype=np.uint8), ряд])
    return ряд.reshape(-1, ПОЛЕЗНЫХ)[1:]


def октеты(полезная: np.ndarray, порядок: str = "младший") -> np.ndarray:
    """Полезные части → строки по 8 октетов (младший бит первым — по 802.3)."""
    return np.packbits(полезная, axis=1, bitorder="little" if порядок == "младший" else "big")


def годность_типов(заголовки: np.ndarray, полезная: np.ndarray) -> tuple[float, int]:
    """Доля блоков управления с типом из допустимого набора и их число."""
    типы = np.packbits(полезная[заголовки == УПРАВЛЕНИЕ, :8], axis=1, bitorder="little")[:, 0]
    if len(типы) < НАИМЕНЬШЕ_УПРАВЛЕНИЯ:
        return 0.0, len(типы)
    return float(np.isin(типы, ДОПУСТИМЫЕ).mean()), len(типы)


# -- кадры --------------------------------------------------------------------------------


def пары(заголовки: np.ndarray, строки: np.ndarray
         ) -> tuple[list[tuple[bytes, bytes, int]], int]:
    """Кадры от начала до конца: (октеты до блока конца, 7 октетов блока конца, его тип).

    Между началом и концом должны стоять только блоки данных; встретился
    другой блок (ошибка, негодный заголовок, простой) — кадр оборван.
    Сколько октетов блока конца принадлежит кадру, решает таблица (или FCS).
    """
    данные = заголовки == ДАННЫЕ
    типы = np.where(заголовки == УПРАВЛЕНИЕ, строки[:, 0].astype(np.int16), -1)
    маска = np.zeros(строки.shape, dtype=bool)
    маска[данные] = True
    for тип, с in НАЧАЛО.items():
        маска[типы == тип, с:] = True
    смещение = np.concatenate([[0], np.cumsum(маска.sum(axis=1))])
    плоско = строки[маска]
    начала = np.flatnonzero(np.isin(типы, list(НАЧАЛО)))
    прочие = np.flatnonzero(~данные)
    следующие = np.searchsorted(прочие, начала, side="right")
    итог: list[tuple[bytes, bytes, int]] = []
    оборвано = 0
    for s, i in zip(начала.tolist(), следующие.tolist(), strict=False):
        if i >= len(прочие):
            break                                   # поток кончился посреди кадра
        t = int(прочие[i])
        if int(типы[t]) not in КОНЕЦ:
            оборвано += 1
            continue
        итог.append((плоско[смещение[s]:смещение[t]].tobytes(), строки[t, 1:].tobytes(),
                     int(типы[t])))
    return итог, оборвано


def fcs_верна(тело: bytes) -> bool:
    """FCS Ethernet: CRC-32 (отражённая, 0x04C11DB7) в конце, младшим октетом вперёд."""
    return len(тело) >= 18 and zlib.crc32(тело[:-4]) == int.from_bytes(тело[-4:], "little")


def без_преамбулы(сырой: bytes) -> tuple[bytes, bool]:
    """Снять преамбулу 55…55 D5; второе — была ли она ровно такой, как в 802.3."""
    if сырой[:7] == ПРЕАМБУЛА:
        return сырой[7:], True
    серия = len(сырой) - len(сырой.lstrip(b"\x55"))
    if серия <= 7 and сырой[серия:серия + 1] == b"\xd5":
        return сырой[серия + 1:], False
    return сырой, False


def собрать(пары_: Sequence[tuple[bytes, bytes, int]], концы: dict[int, int]
            ) -> list[tuple[int, bytes, bool, bool]]:
    """(тип конца, тело без преамбулы, преамбула верна, FCS верна) для каждого кадра."""
    итог = []
    for база, хвост, тип in пары_:
        тело, преамбула = без_преамбулы(база + хвост[:концы[тип]])
        итог.append((тип, тело, преамбула, fcs_верна(тело)))
    return итог


def сверить_концы(пары_: Sequence[tuple[bytes, bytes, int]]
                  ) -> tuple[dict[int, int], list[str]]:
    """Число октетов перед /T/ для каждого типа конца — по таблице, проверенной FCS.

    Для типа, у которого FCS сходится меньше чем у половины кадров, пробуются
    все 0…7 октетов; если другое число даёт больше верных FCS — берём его.
    """
    концы = dict(КОНЕЦ)
    поправки: list[str] = []
    по_типу: dict[int, list[tuple[bytes, bytes, int]]] = {}
    for пара in пары_:
        по_типу.setdefault(пара[2], []).append(пара)
    for тип, свои in по_типу.items():
        if len(свои) < 3:
            continue
        def верных(k: int, свои: list = свои) -> int:
            return sum(fcs_верна(без_преамбулы(б + х[:k])[0]) for б, х, _ in свои)
        было = верных(концы[тип])
        if было >= len(свои) / 2:
            continue
        лучшее = max(range(8), key=верных)
        стало = верных(лучшее)
        if стало > было:
            поправки.append(f"тип 0x{тип:02X}: по таблице {концы[тип]} окт. перед /T/ — "
                            f"FCS верна у {было} из {len(свои)}; по FCS — {лучшее} окт. "
                            f"(верна у {стало}); принято по данным")
            концы[тип] = лучшее
    return концы, поправки


# -- выбор толкования ---------------------------------------------------------------------


@dataclass
class _Вариант:
    порядок_в_файле: str
    инверсия: bool
    фаза: int
    годных_заголовков: float
    прочие_фазы: float
    отводы: tuple[int, ...] = ()
    откуда_полином: str = ""
    годных_типов: float = 0.0


def _ряд(биты: np.ndarray, порядок_в_файле: str, инверсия: bool) -> np.ndarray:
    ряд = перевернуть_в_байтах(биты) if порядок_в_файле == "обратный в байте" else биты
    return ряд ^ np.uint8(1) if инверсия else ряд


def _фазы(выборка: np.ndarray) -> list[_Вариант]:
    """Варианты порядка бит и полярности, у которых нашлась фаза заголовков."""
    варианты = []
    for порядок in ПОРЯДКИ_В_ФАЙЛЕ:
        доли = годность_по_фазам(_ряд(выборка, порядок, False))
        фаза = int(np.argmax(доли))
        лучшая, прочие = float(доли[фаза]), float(np.median(доли))
        if лучшая < ПОРОГ_ЗАГОЛОВКОВ or прочие > ПОРОГ_ПРОЧИХ_ФАЗ:
            continue
        # Инверсия меняет 01 ↔ 10 — годность заголовков та же, решают типы.
        for инверсия in (False, True):
            варианты.append(_Вариант(порядок, инверсия, фаза, лучшая, прочие))
    return варианты


def _сырые_блоки(выборка: np.ndarray, в: _Вариант) -> tuple[np.ndarray, np.ndarray]:
    return блоки(_ряд(выборка, в.порядок_в_файле, в.инверсия), в.фаза,
                 в.порядок_в_файле == "обратный в блоке")


def _полиномы(выборка: np.ndarray, варианты: list[_Вариант]) -> list[_Вариант]:
    """Полином скремблера для каждого варианта — только если после снятия есть структура."""
    сырые = {id(в): _сырые_блоки(выборка, в) for в in варианты}

    def проба(отводы: tuple[int, ...], откуда: str, блоков: int | None = None) -> list[_Вариант]:
        годные = []
        for в in варианты:
            заголовки, полезная = сырые[id(в)]
            if блоков:
                заголовки, полезная = заголовки[:блоков], полезная[:блоков]
            доля, _ = годность_типов(заголовки[1:], снять_скремблер(полезная, отводы))
            if доля >= ПОРОГ_ТИПОВ:
                годные.append(_Вариант(в.порядок_в_файле, в.инверсия, в.фаза,
                                       в.годных_заголовков, в.прочие_фазы, tuple(отводы),
                                       откуда, доля))
        return годные

    годные = проба(ОТВОДЫ_802_3, "IEEE 802.3 cl. 49, подтверждён типами блоков")
    if годные:
        return годные
    годные = проба((), "скремблера нет: типы блоков годны без снятия")
    if годные:
        return годные
    # Вслепую: все одно- и двухотводные полиномы до степени 64 на малой выборке,
    # признак — тот же (типы блоков управления из допустимого набора).
    лучшие: dict[int, tuple[float, tuple[int, ...]]] = {}
    for b in range(1, skrembler.НАИБОЛЬШАЯ_СТЕПЕНЬ + 1):
        for a in range(0, b):
            отводы = (a, b) if a else (b,)
            for в in варианты:
                заголовки, полезная = сырые[id(в)]
                доля, _ = годность_типов(заголовки[1:ПЕРЕБОР_БЛОКОВ],
                                         снять_скремблер(полезная[:ПЕРЕБОР_БЛОКОВ], отводы))
                if доля >= ПОРОГ_ТИПОВ and доля > лучшие.get(id(в), (0.0, ()))[0]:
                    лучшие[id(в)] = (доля, отводы)
    итог = []
    for в in варианты:
        if id(в) in лучшие:
            отводы = лучшие[id(в)][1]
            итог += [г for г in проба(отводы, "найден перебором по типам блоков")
                     if (г.порядок_в_файле, г.инверсия) == (в.порядок_в_файле, в.инверсия)]
    return итог


def _разобрать(биты: np.ndarray, в: _Вариант, порядок_в_октете: str,
               сверять: bool = True) -> Разбор66:
    заголовки, полезная = _сырые_блоки(биты, в)
    полезная = снять_скремблер(полезная, в.отводы)
    заголовки = заголовки[1:]
    строки = октеты(полезная, порядок_в_октете)
    р = Разбор66(в.порядок_в_файле, в.инверсия, порядок_в_октете, в.фаза, в.отводы,
                 в.откуда_полином, в.годных_заголовков, в.прочие_фазы, в.годных_типов)
    р.разобрано_бит = len(биты)
    р.блоков = len(заголовки)
    р.данных = int(np.sum(заголовки == ДАННЫЕ))
    р.управления = int(np.sum(заголовки == УПРАВЛЕНИЕ))
    р.негодных = р.блоков - р.данных - р.управления
    упр = заголовки == УПРАВЛЕНИЕ
    типы = строки[:, 0]
    р.типы = Counter(типы[упр].tolist())
    # Управляющие символы блока 0x1E — восемь по 7 бит после поля типа.
    простые = упр & (типы == 0x1E)
    символы = полезная[простые, 8:].reshape(-1, 8, 7) @ (1 << np.arange(7))
    р.простой = int(np.sum(np.all(символы == СИМВОЛ_ПРОСТОЯ, axis=1)))
    р.с_ошибкой = int(np.sum(np.any(символы == СИМВОЛ_ОШИБКИ, axis=1)))
    наборы = упр & (типы == 0x4B)
    р.наборы = Counter(" ".join(f"{б:02X}" for б in строка[1:4]) for строка in строки[наборы][:5000])
    пары_, р.оборвано = пары(заголовки, строки)
    концы, р.поправки = сверить_концы(пары_) if сверять else (dict(КОНЕЦ), [])
    кадры = собрать(пары_, концы)
    р.собрано = len(кадры)
    р.с_преамбулой = sum(1 for _, _, п, _ in кадры if п)
    р.верных = sum(1 for _, _, _, f in кадры if f)
    р.кадры = [тело[:-4] for _, тело, _, f in кадры if f]
    итоги: dict[int, list[int]] = {}
    for тип, _, _, f in кадры:
        итоги.setdefault(тип, [0, 0])
        итоги[тип][0] += f
        итоги[тип][1] += 1
    р.концы = {тип: (концы[тип], в_, всего) for тип, (в_, всего) in итоги.items()}
    return р


def разобрать(биты: np.ndarray) -> Разбор66 | None:
    """Поток 64b/66b целиком: фаза, порядок бит, скремблер, блоки, кадры. None — не он."""
    биты = np.asarray(биты, dtype=np.uint8)[:ПРЕДЕЛ]
    if len(биты) < НАИМЕНЬШЕ_БЛОКОВ * ДЛИНА_БЛОКА:
        return None
    выборка = биты[:ВЫБОРКА]
    варианты = _фазы(выборка)
    if not варианты:
        return None
    варианты = _полиномы(выборка, варианты)
    if not варианты:
        return None
    # Порядок в октете по типам не различить (набор замкнут относительно
    # переворота) — решают преамбула и FCS на выборке.
    лучший = None
    for в in варианты:
        for порядок in ("младший", "старший"):
            р = _разобрать(выборка, в, порядок, сверять=False)
            ключ = (р.доля_fcs, р.с_преамбулой / max(р.собрано, 1), р.годных_типов,
                    порядок == "младший")
            if лучший is None or ключ > лучший[0]:
                лучший = (ключ, в, порядок)
    _, в, порядок = лучший
    return _разобрать(биты, в, порядок)


# -- находка ------------------------------------------------------------------------------


def _проценты(доля: float) -> str:
    return f"{доля * 100:.2f} %"


def находка(р: Разбор66) -> Находка:
    """Находка канального уровня по разбору."""
    if р.собрано:
        уверенность = р.доля_fcs
        мера_fcs = f"FCS верна у {round(р.доля_fcs * 100)} % из {р.собрано} кадров"
    else:
        уверенность = 0.5 * min(р.годных_заголовков, р.годных_типов)
        мера_fcs = "кадров нет — подтвердить FCS нечем (в потоке только простой/служебное)"
    порядок = {"как передан": "как передан (802.3: октет младшим битом вперёд)",
               "обратный в байте": "обратный порядку передачи в каждом байте файла",
               "обратный в блоке": "обратный порядку передачи в каждом 66-битовом блоке"}
    подробно = [
        f"синхрозаголовки: годных (01/10) {_проценты(р.годных_заголовков)} на фазе {р.фаза}; "
        f"медиана по всем 66 фазам — {_проценты(р.прочие_фазы)} (у случайного ряда 50 %)",
        f"порядок бит в файле: {порядок[р.порядок_в_файле]}"
        + ("; полярность обратная (биты инвертированы)" if р.инверсия else "")
        + f"; октеты полезной части — {р.порядок_в_октете} бит первым"
        + (" (как в 802.3)" if р.порядок_в_октете == "младший" else " (не по 802.3; решила FCS)"),
        (f"скремблер: {skrembler.полином_словами(р.отводы)} — {р.откуда_полином}"
         if р.отводы else f"скремблер: {р.откуда_полином}")
        + f"; типы блоков управления из допустимого набора — {_проценты(р.годных_типов)} "
          f"(у неверного полинома около 6 %)",
        f"блоков: {р.блоков} (данных {р.данных}, управления {р.управления}, "
        f"с негодным заголовком {р.негодных})",
        "типы блоков управления: " + ", ".join(
            f"0x{т:02X}×{с}{'' if т in ТИПЫ else ' (недопустимый)'}"
            for т, с in р.типы.most_common(10)),
        f"простой (блоки 0x1E из одних /I/): {р.простой}; блоков с символом ошибки /E/: "
        f"{р.с_ошибкой}",
        f"кадров от начала до конца: {р.собрано}, FCS верна у {р.верных}, преамбула "
        f"55…55 D5 — у {р.с_преамбулой}; оборвано (начало без конца): {р.оборвано}",
    ]
    if р.концы:
        подробно.append("концы кадра по FCS: " + ", ".join(
            f"0x{т:02X} ({k} окт.) — {в}/{всего}" for т, (k, в, всего) in sorted(р.концы.items())))
    подробно += р.поправки
    if р.наборы:
        подробно.append("упорядоченные наборы 0x4B (октеты 1–3): " + ", ".join(
            f"{н}×{с}" for н, с in р.наборы.most_common(4))
            + " (00 00 01 — местный сбой, 00 00 02 — удалённый сбой)")
    if р.кадры:
        длины = Counter(len(к) + 4 for к in р.кадры)
        типы_кадров = Counter(к[12:14].hex().upper() for к in р.кадры if len(к) >= 14)
        подробно.append("длины кадров (октетов с FCS): " + ", ".join(
            f"{д}×{с}" for д, с in длины.most_common(6)))
        подробно.append("EtherType: " + ", ".join(
            f"0x{т}×{с}" for т, с in типы_кадров.most_common(5)))
    подробно.append("дальше — кадры Ethernet с верной FCS, без преамбулы и без FCS")
    return Находка(
        уровень="канальный",
        что="Ethernet 64b/66b (PCS 10GBASE-R, IEEE 802.3 cl. 49)",
        уверенность=уверенность,
        мера=f"годных синхрозаголовков {_проценты(р.годных_заголовков)}; типов блоков из "
             f"допустимого набора {_проценты(р.годных_типов)}; {мера_fcs}",
        подробно=подробно, дальше=р.кадры, вид_дальше="кадры",
        сверка=р.годных_заголовков)


def найти(биты: np.ndarray) -> Находка | None:
    """Ethernet 64b/66b в битовом ряду: None, если заголовков 01/10 с шагом 66 нет."""
    р = разобрать(биты)
    return None if р is None else находка(р)
