"""Ethernet 64b/66b: физический кодирующий подуровень (PCS) 10GBASE-R и родственных.

IEEE 802.3, раздел 49 (10GBASE-R); тот же блок 64b/66b и тот же скремблер —
у 25GBASE-R (раздел 107) и у 40G/100G на одной линии. Поток режется на
блоки по 66 бит:

- **синхрозаголовок**, 2 бита, передаётся первым: 01 — блок данных, 10 —
  блок управления; 00 и 11 не бывает никогда. Это и есть признак: при
  верной фазе годны ~100 % заголовков, при любой другой — около 50 %
  (там на месте заголовка два бита скремблированной полезной части);
- **полезная часть**, 64 бита, скремблирована мультипликативным
  скремблером 1 + x^39 + x^58 — непрерывно через все блоки, заголовки мимо
  скремблера; снимается сдвигами (``skrembler.снять``) по склеенной
  полезной части;
- в блоке данных — восемь октетов; в блоке управления первый октет — поле
  типа блока (Block Type Field), дальше — октеты данных, семибитовые
  управляющие символы (/I/ простой — 0x00, /E/ ошибка — 0x1E) или
  упорядоченный набор. Октеты передаются младшим битом вперёд.

Таблица типов блоков (802.3 рис. 49-7), как она здесь принята:

======  ============================================================
0x1E    восемь управляющих символов (простой, ошибка)
0x2D    управляющие символы + упорядоченный набор в 4-й позиции
0x33    управляющие символы + начало кадра (/S/) в 4-й позиции
0x66    упорядоченный набор + начало кадра в 4-й позиции
0x55    два упорядоченных набора
0x78    начало кадра в 0-й позиции, дальше семь октетов
0x4B    упорядоченный набор (например, «местный/удалённый сбой»)
0x87…   конец кадра (/T/) после 0…7 октетов данных: 0x87 — 0, 0x99 — 1,
0xFF    0xAA — 2, 0xB4 — 3, 0xCC — 4, 0xD2 — 5, 0xE1 — 6, 0xFF — 7
======  ============================================================

Что из стандарта проверяется данными, а не принимается на веру:

- **полином скремблера** — сначала пробуется известный 1 + x^39 + x^58, но
  засчитывается, только если после снятия типы блоков управления почти все
  из допустимого набора (у неверного полинома — 15 из 256, около 6 %).
  Не подошёл — пробуем «без скремблера» и перебор всех одно- и двухотводных
  полиномов до степени 64 по тому же признаку;
- **порядок бит** — в файле он бывает обратным порядку передачи (в каждом
  байте файла или в каждом 66-битовом блоке), полярность бывает обратной, а
  октеты полезной части кто-то собирает старшим битом вперёд. Любопытно:
  набор допустимых типов блоков ЗАМКНУТ относительно переворота бит в октете
  (0x1E ↔ 0x78, 0x33 ↔ 0xCC, 0x87 ↔ 0xE1 …), и порядок в октете по типам не
  различить — его решают преамбула 55…55 D5 и FCS собранных кадров;
- **число октетов данных у конца кадра** — по таблице; для каждого типа
  конца, у которого FCS не сходится, перебираются 0…7 октетов, и если
  другое число даёт верную FCS, берётся оно (и это пишется в отчёт);
- **преамбула** — /S/ занимает место первого 0x55, дальше 55×6 и D5;
  сверяется у каждого кадра;
- **FCS** — CRC-32 Ethernet (та же, что FCS-32 HDLC), в конце кадра
  младшим октетом вперёд. Доля кадров с верной FCS — уверенность находки.

Дальше уходят кадры Ethernet с верной FCS: без преамбулы и без FCS — от
адреса получателя до конца данных (как у ``hdlc.найти``), чтобы
``pakety.найти_в_кадрах`` нашёл IP после EtherType.
"""

