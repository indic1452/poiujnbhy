# -- проверка кандидатов по словам --------------------------------------------------------------

def нарушения(W: np.ndarray, проверки: list[np.ndarray]) -> np.ndarray:
    """Доля слов W (строки), где каждая проверка (номера позиций) нарушена."""
    if not проверки:
        return np.zeros(0)
    итог = np.empty(len(проверки))
    for i, с in enumerate(проверки):
        итог[i] = np.bitwise_xor.reduce(W[:, с], axis=1).mean()
    return итог


def нарушены_в_словах(W: np.ndarray, проверки: list[np.ndarray]) -> np.ndarray:
    """Число нарушенных проверок в каждом слове."""
    итог = np.zeros(len(W), dtype=np.int32)
    for с in проверки:
        итог += np.bitwise_xor.reduce(W[:, с], axis=1)
    return итог


def порог_нарушений(отсчётов: int, кандидатов: int) -> int:
    """Наибольшее число нарушенных из ``отсчётов``, при котором кандидат — проверка, а не случайность: у
    случайного вектора столько и меньше — с вероятностью не больше СЛУЧАЙНО_ДО/кандидатов (и доля ≤ ДОЛЯ_ДО)."""
    from .ldpc_opoznanie import _лог_хвосты  # noqa: PLC0415
    if отсчётов <= 0:
        return -1
    хвосты = _лог_хвосты(int(отсчётов))
    предел = math.log(СЛУЧАЙНО_ДО / max(1, кандидатов))
    k = int(np.searchsorted(хвосты, предел, side="right")) - 1
    return min(k, int(ДОЛЯ_ДО * отсчётов))


def оценка_шума(доля: float, вес: int) -> float:
    """BER линии по доле нарушенных проверки веса w: f = (1 − (1 − 2τ)^w)/2."""
    if доля <= 0 or вес <= 0:
        return 0.0
    return float((1 - max(1e-12, 1 - 2 * min(доля, 0.499)) ** (1 / вес)) / 2)


# -- частичный Гаусс и коллизии Штерна -----------------------------------------------------------

def частичный_гаусс(строки: np.ndarray, n: int, t: int, порядок: np.ndarray
                    ) -> tuple[np.ndarray, list[int], list[int]]:
    """Упакованные строки (r × ⌈n/64⌉) → (приведённые строки, опорные столбцы по строкам, номера опорных
    строк): столбцы перебираются в ``порядок``, пока опорных не станет t. Опорные строки — первые."""
    a = строки.copy()
    r = len(a)
    опорные: list[int] = []
    п = 0
    for j in порядок.tolist():
        if п >= t or п >= r:
            break
        w, b = divmod(j, 64)
        маска = np.uint64(1) << np.uint64(b)
        есть = np.flatnonzero((a[п:, w] & маска) != 0)
        if not len(есть):
            continue
        q = п + int(есть[0])
        if q != п:
            a[[п, q]] = a[[q, п]]
        с_единицей = (a[:, w] & маска) != 0
        с_единицей[п] = False
        if с_единицей.any():
            a[с_единицей] ^= a[п]
        опорные.append(j)
        п += 1
    return a, опорные, list(range(п))


def _ключи(биты: np.ndarray) -> np.ndarray:
    """Столбцы (ℓ × N, ℓ ≤ 64) → ключи uint64 (бит i — строка i)."""
    ключи = np.zeros(биты.shape[1], dtype=np.uint64)
    for i in range(биты.shape[0]):
        ключи |= биты[i].astype(np.uint64) << np.uint64(i)
    return ключи


def _совпадения(ключи_а: np.ndarray, ключи_б: np.ndarray, до: int) -> tuple[np.ndarray, np.ndarray]:
    """Пары (i, j) с ключи_а[i] == ключи_б[j] (не больше ``до``). Номер записи — в младших битах ключа:
    сортировка значений (а не argsort) и поиск отсортированных в отсортированных — в разы быстрее."""
    if not len(ключи_а) or not len(ключи_б):
        return np.zeros(0, dtype=np.int64), np.zeros(0, dtype=np.int64)
    сдвиг = max(1, int(max(len(ключи_а), len(ключи_б)) - 1).bit_length())
    маска = np.uint64((1 << сдвиг) - 1)
    с = np.uint64(сдвиг)
    а = np.sort((ключи_а << с) | np.arange(len(ключи_а), dtype=np.uint64))
    б = np.sort((ключи_б << с) | np.arange(len(ключи_б), dtype=np.uint64))
    ка, кб = а >> с, б >> с
    лево = np.searchsorted(кб, ка, "left")
    право = np.searchsorted(кб, ка, "right")
    сколько = право - лево
    есть = np.flatnonzero(сколько)
    if not len(есть):
        return np.zeros(0, dtype=np.int64), np.zeros(0, dtype=np.int64)
    сколько = сколько[есть]
    i = np.repeat(есть, сколько)
    шаг = np.arange(len(i)) - np.repeat(np.cumsum(сколько) - сколько, сколько)
    j = np.repeat(лево[есть], сколько) + шаг
    i, j = i[:до], j[:до]
    return (а[i] & маска).astype(np.int64), (б[j] & маска).astype(np.int64)


def _пары(n: int, до: int, rng: np.random.Generator) -> tuple[np.ndarray, np.ndarray]:
    """Пары индексов (a < b) из n — все или случайное подмножество элементов, чтобы пар было не больше ``до``."""
    if n * (n - 1) // 2 > до:
        m = int((1 + math.sqrt(1 + 8 * до)) / 2)
        выбор = np.sort(rng.choice(n, size=m, replace=False))
    else:
        выбор = np.arange(n)
    a, b = np.triu_indices(len(выбор), 1)
    return выбор[a], выбор[b]


def итерация(W: np.ndarray, rng: np.random.Generator, *, t: int, эль: int, p: int, вес_до: int,
             строки: np.ndarray | None = None, столбцы: np.ndarray | None = None, цель: int | None = None
             ) -> tuple[list[np.ndarray], np.ndarray]:
    """Одна итерация: r = t + ℓ строк W (``строки`` — из них, по умолчанию все), частичный Гаусс по t
    столбцам в случайном порядке (``столбцы`` — только из них: без постоянных), коллизии по ℓ строкам.
    ``цель`` — искать только проверки, содержащие эту позицию (направленный поиск: к позиции, которую не
    покрыла ни одна найденная проверка): она не берётся в опорные, а её столбец C — цель коллизий.
    Возвращает кандидатов (номера позиций, ещё не сверенных) и номера взятых строк (их сверка не считает:
    они кандидатов выполняют по построению)."""
    M, n = W.shape
    пул = np.arange(M) if строки is None else строки
    r = min(len(пул), t + эль)
    if r < 8:
        return [], np.zeros(0, dtype=np.int64)
    выбор = rng.choice(пул, size=r, replace=False)
    годные = np.arange(n) if столбцы is None else столбцы
    порядок = rng.permutation(годные if цель is None else годные[годные != цель])
    a, опорные, _ = частичный_гаусс(gf2.упаковать(W[выбор]), n, min(t, r - 1), порядок)
    t_ = len(опорные)
    if r - t_ < 4:
        return [], выбор
    R = gf2.распаковать(a, n)
    занято = np.zeros(n, dtype=bool)
    занято[опорные] = True
    if столбцы is not None:
        прочие_маска = np.zeros(n, dtype=bool)
        прочие_маска[годные] = True
        прочие = np.flatnonzero(прочие_маска & ~занято)
    else:
        прочие = np.flatnonzero(~занято)
    C = R[t_:, прочие][:64]
    B = R[:t_, прочие]                                  # t × |прочие|
    ключи = _ключи(C)
    Bупак = gf2.упаковать(np.ascontiguousarray(B.T))     # |прочие| × ⌈t/64⌉
    опорные_ = np.array(опорные, dtype=np.int64)
    итог: list[np.ndarray] = []
    if цель is not None:
        return _к_цели(прочие, ключи, Bупак, опорные_, t_, int(np.searchsorted(прочие, цель)), rng, p, вес_до), выбор
    половина = rng.permutation(len(прочие))
    X, Y = половина[:len(прочие) // 2], половина[len(прочие) // 2:]

    def собрать(слева: list[np.ndarray], справа: list[np.ndarray], остаток: int) -> None:
        b = Bупак[слева[0]].copy()
        for с in слева[1:] + справа:
            b ^= Bупак[с]
        вес = np.bitwise_count(b).sum(axis=1)
        годно = np.flatnonzero(вес <= остаток)
        if not len(годно):
            return
        биты_b = gf2.распаковать(b[годно], t_)
        for g, строка_b in zip(годно.tolist(), биты_b, strict=True):
            носитель = np.concatenate([прочие[[int(с[g]) for с in слева + справа]], опорные_[строка_b.astype(bool)]])
            итог.append(np.unique(носитель))

    # p = 1: столбец с нулевым ключом (C·e_j = 0).
    нули = np.flatnonzero(ключи == 0)
    if len(нули):
        собрать([нули], [], вес_до - 1)
    if p >= 2:
        i, j = _совпадения(ключи[X], ключи[Y], КОЛЛИЗИЙ_ДО)
        if len(i):
            собрать([X[i]], [Y[j]], вес_до - 2)
    if p >= 4 and вес_до >= 4:
        a1, a2 = _пары(len(X), СПИСОК_ДО, rng)
        b1, b2 = _пары(len(Y), СПИСОК_ДО, rng)
        ka = ключи[X[a1]] ^ ключи[X[a2]]
        kb = ключи[Y[b1]] ^ ключи[Y[b2]]
        i, j = _совпадения(ka, kb, КОЛЛИЗИЙ_ДО)
        if len(i):
            собрать([X[a1[i]], X[a2[i]]], [Y[b1[j]], Y[b2[j]]], вес_до - 4)
    return [h for h in итог if 2 <= len(h) <= вес_до], выбор


def _к_цели(прочие: np.ndarray, ключи: np.ndarray, Bупак: np.ndarray, опорные: np.ndarray, t: int, ц: int,
            rng: np.random.Generator, p: int, вес_до: int) -> list[np.ndarray]:
    """Направленный поиск: h_прочие = e_ц + (сумма p − 1 столбцов), C·h_прочие = 0 ⇔ ключи суммы = ключ цели."""
    ключ_ц = ключи[ц]
    b_ц = Bупак[ц]
    остальные = np.delete(np.arange(len(прочие)), ц)
    итог: list[np.ndarray] = []

    def собрать(наборы: list[np.ndarray], остаток: int) -> None:
        b = np.broadcast_to(b_ц, (len(наборы[0]), len(b_ц))).copy()
        for с in наборы:
            b ^= Bупак[с]
        годно = np.flatnonzero(np.bitwise_count(b).sum(axis=1) <= остаток)
        if not len(годно):
            return
        биты_b = gf2.распаковать(b[годно], t)
        for g, строка_b in zip(годно.tolist(), биты_b, strict=True):
            носитель = np.concatenate([прочие[[ц] + [int(с[g]) for с in наборы]], опорные[строка_b.astype(bool)]])
            итог.append(np.unique(носитель))

    # Ещё один столбец вне опорных: его ключ — ключ цели.
    одиночные = остальные[ключи[остальные] == ключ_ц]
    if len(одиночные):
        собрать([одиночные], вес_до - 2)
    половина = rng.permutation(остальные)
    X, Y = половина[:len(половина) // 2], половина[len(половина) // 2:]
    i, j = _совпадения(ключи[X], ключи[Y] ^ ключ_ц, КОЛЛИЗИЙ_ДО)
    if len(i):
        собрать([X[i], Y[j]], вес_до - 3)
    if p >= 4 and вес_до >= 5:
        a1, a2 = _пары(len(X), СПИСОК_ДО, rng)
        b1, b2 = _пары(len(Y), СПИСОК_ДО, rng)
        i, j = _совпадения(ключи[X[a1]] ^ ключи[X[a2]], ключи[Y[b1]] ^ ключи[Y[b2]] ^ ключ_ц, КОЛЛИЗИЙ_ДО)
        if len(i):
            собрать([X[a1[i]], X[a2[i]], Y[b1[j]], Y[b2[j]]], вес_до - 5)
    return [h for h in итог if 2 <= len(h) <= вес_до]


# -- структура: циркулянт и «сдвиг» IRA ------------------------------------------------------------

def сдвиг_qc(h: np.ndarray, Z: int, s: int = 1) -> np.ndarray:
    """Проверка, сдвинутая внутри блоков по Z на s."""
    return np.sort((h // Z) * Z + (h % Z + s) % Z)


def сдвиг_qc_смещ(h: np.ndarray, Z: int, s: int, o: int, n: int) -> np.ndarray | None:
    """Сдвиг внутри блоков, которые в окне начинаются с бита Z − o (окна сдвинуты на o по модулю Z): None —
    сдвинутая выходит за окно (её блок разрезан краем окна)."""
    p = h + o
    g = np.sort((p // Z) * Z + (p % Z + s) % Z - o)
    return None if g[0] < 0 or g[-1] >= n else g


def сдвиг_ira(h: np.ndarray, n: int, k: int, s: int = 1, группа: int = 360) -> np.ndarray:
    """«Сдвиг» DVB-подобного IRA: данные — внутри групп по 360 на s, чётность — на s·q, q = (n − k)/360."""
    m = n - k
    q = m // группа
    данные = h[h < k]
    чётность = h[h >= k] - k
    return np.sort(np.concatenate([(данные // группа) * группа + (данные % группа + s) % группа,
                                   k + (чётность + s * q) % m]))


def операторы(n: int) -> list[tuple[str, int, Callable[[np.ndarray, int], np.ndarray]]]:
    """Операторы структуры для пробы: QC с Z — делителем n (от меньших блоков), IRA с группами 360 и k кратным 360.
    (имя, порядок орбиты, функция сдвига на s)."""
    итог = []
    for Z in range(Z_ОТ, n // 2 + 1):
        if n % Z == 0 and n // Z <= БЛОКОВ_ДО:
            итог.append((f"квазициклический, Z = {Z}", Z, lambda h, s, Z=Z: сдвиг_qc(h, Z, s)))
    if n % 360 == 0:
        for k in range(360, n, 360):
            if (n - k) % 360 == 0:
                итог.append((f"IRA по группам 360 (как DVB-S2), k = {k}", 360,
                              lambda h, s, k=k: сдвиг_ira(h, n, k, s)))
    return итог


def найти_оператор(W: np.ndarray, проверки: list[np.ndarray], порог: float, *, проб: int = 32
                   ) -> tuple[str, int, Callable] | None:
    """Оператор, при котором сдвинутые найденные проверки — тоже проверки: с наибольшей долей выполненных
    сдвинутых (не меньше ОПЕРАТОР_ГОДИТСЯ). Делитель настоящего Z сдвигает верно лишь проверки, не задевшие
    границ малых блоков, — у него доля меньше, поэтому берётся наибольшая, а не первая."""
    n = W.shape[1]
    # Проверки веса 2 (равенство двух позиций с одним сдвигом в блоках) переходят в себя при любом
    # согласованном сдвиге — по ним оператор не различить.
    образцы = [h for h in проверки if len(h) >= 3][:проб]
    if len(образцы) < 2:
        return None
    выборка = W[:min(len(W), 512)]
    лучший, ключ_лучшего = None, (ОПЕРАТОР_ГОДИТСЯ - 1e-9, 0, 0)
    for имя, порядок, f in операторы(n):
        # Сдвиг на 1 и на половину порядка: у делителя настоящего Z сдвиг на 1 верен у проверок, не задевших
        # границ малых блоков (часто), а на половину — почти никогда; у кратного — наоборот.
        сдвиги = sorted({1, max(1, порядок // 2), max(1, порядок // 3)})
        сдвинутые = [f(h, s) for s in сдвиги for h in образцы]
        доля = float(np.mean(нарушения(выборка, сдвинутые) <= порог))
        # При равенстве — больший порядок (меньшие — делители), затем квазициклический (IRA с k = n − 360
        # — то же самое).
        ключ = (round(доля, 6), порядок, int(имя.startswith("квазициклический")))
        if ключ > ключ_лучшего:
            лучший, ключ_лучшего = (имя, порядок, f), ключ
    if лучший is None and len(образцы) >= 3:
        лучший = _qc_со_смещением(выборка, образцы, порог, n)
    return лучший


#: Смещение блоков ищется для Z не больше.
СМЕЩЕНИЕ_Z_ДО = 1024


def _qc_со_смещением(выборка: np.ndarray, образцы: list[np.ndarray], порог: float, n: int
                     ) -> tuple[str, int, Callable] | None:
    """Квазициклический код в сдвинутых окнах: блоки начинаются не с бита 0 окна. Перебор Z и смещения o —
    сначала дёшево (одна проверка, сдвиг на 1, 128 слов), затем полностью."""
    малая = выборка[:128]
    первая = образцы[0]
    лучший, ключ_лучшего = None, (ОПЕРАТОР_ГОДИТСЯ - 1e-9, 0)
    for Z in range(Z_ОТ, min(n // 2, СМЕЩЕНИЕ_Z_ДО) + 1):
        if n % Z or n // Z > БЛОКОВ_ДО:
            continue
        for o in range(1, Z):
            g = сдвиг_qc_смещ(первая, Z, 1, o, n)
            if g is None or нарушения(малая, [g])[0] > порог:
                continue
            сдвинутые = [x for s in sorted({1, max(1, Z // 2), max(1, Z // 3)}) for h in образцы
                         if (x := сдвиг_qc_смещ(h, Z, s, o, n)) is not None]
            if len(сдвинутые) < 3:
                continue
            доля = float(np.mean(нарушения(выборка, сдвинутые) <= порог))
            if (round(доля, 6), Z) > ключ_лучшего:
                лучший = (f"QC, Z = {Z}, блоки окна сдвинуты на {o}", Z,
                          lambda h, s, Z=Z, o=o: сдвиг_qc_смещ(h, Z, s, o, n))
                ключ_лучшего = (round(доля, 6), Z)
    return лучший


def орбита(h: np.ndarray, порядок: int, f: Callable) -> list[np.ndarray]:
    return [g for s in range(1, порядок) if (g := f(h, s)) is not None]


# -- независимые и ранг -----------------------------------------------------------------------------

class Базис:
    """Нарастающее исключение (базис XOR): у каждой взятой строки свой опорный столбец — её младшая единица;
    новая проверка сокращается по опорным, пока не обнулится (зависима) или не найдёт свой опорный. Строки —
    целые Python (XOR длинных целых в разы быстрее поштучных операций numpy)."""

    def __init__(self, n: int):
        self.n = n
        self.по_опорному: dict[int, int] = {}
        self.взятые: list[np.ndarray] = []

    def добавить(self, h: np.ndarray) -> bool:
        строка = 0
        for i in np.asarray(h).tolist():
            строка ^= 1 << i
        по_опорному = self.по_опорному
        while строка:
            опорный = (строка & -строка).bit_length() - 1
            другая = по_опорному.get(опорный)
            if другая is None:
                по_опорному[опорный] = строка
                self.взятые.append(h)
                return True
            строка ^= другая
        return False

    @property
    def ранг(self) -> int:
        return len(self.взятые)


# -- декодирование по найденным проверкам ----------------------------------------------------------

def декодировать(W: np.ndarray, проверки: list[np.ndarray], итераций: int = 30, пачка: int = 64
                 ) -> tuple[np.ndarray, np.ndarray]:
    """Слова, исправленные «минимумом — суммой» по найденным проверкам, и признак «синдром нулевой»."""
    from . import ldpc  # noqa: PLC0415
    n = W.shape[1]
    м = ldpc.Матрица(n, [np.asarray(h, dtype=np.int64) for h in проверки], "восстановлена")
    связи = м.связи()
    слова, ок = [], []
    for от in range(0, len(W), пачка):
        кусок = W[от:от + пачка]
        с, о = ldpc.мин_сумма(1.0 - 2.0 * кусок.astype(np.float32), связи, n, итераций)
        слова.append(с)
        ок.append(о)
    return np.concatenate(слова), np.concatenate(ок)


# -- достройка по чистым словам: точное пространство проверок ------------------------------------------

#: Достройка (ядро матрицы чистых слов) — при длине слова не больше этой (плотный Гаусс n × n).
ДОСТРОЙКА_ДО = 8192
#: Случайных подмножеств чистых слов для ядра и запас слов сверх нужного числа строк (у квазициклического —
#: чтобы сдвиги наверняка покрыли код).
ПОДМНОЖЕСТВ = 4
ЗАПАС_СЛОВ = 16
#: Достройка — не дольше (с) и до стольких отвергнутых проверок (ядро ненадёжно).
ДОСТРОЙКА_СЕКУНД = 60.0
ОТВЕРГНУТО_ДО = 64


def слов_для_ядра(n: int, ранг: int, Z: int = 0) -> int:
    """Сколько чистых слов нужно на ядро: строк (со сдвигами) больше наибольшей размерности кода n − ранг."""
    нужно = max(0, n - ранг) + 64
    return -(-нужно // Z) + ЗАПАС_СЛОВ if Z else нужно


def ядро_чистых(чистые_слова: np.ndarray, ранг: int, Z: int = 0, rng: np.random.Generator | None = None
                ) -> tuple[np.ndarray | None, int]:
    """Пространство проверок по словам, сошедшимся у декодера: ядро матрицы слов (у квазициклического — со
    всеми сдвигами в блоках). «Сошлось» — только по найденным проверкам: слово, ошибочно приведённое к слову
    надкода, лишь сужает ядро — поэтому ядро считается по нескольким подмножествам (первое — самые надёжные
    слова: слова упорядочены по числу исправленных бит, остальные — случайные из вдвое большего числа
    надёжных) и берётся наибольшее. Возвращает (ядро, сколько подмножеств дали его размерность); None — слов
    не хватает."""
    M, n = чистые_слова.shape
    сдвигов = Z if Z else 1
    слов = слов_для_ядра(n, ранг, Z)
    if M < слов:
        return None, 0
    rng = rng if rng is not None else np.random.default_rng(0)
    лучшее, раз = None, 0
    for номер in range((ПОДМНОЖЕСТВ if n <= 4096 else 2) if M > слов else 1):
        выбор = np.arange(слов) if номер == 0 else np.sort(rng.choice(min(M, 2 * слов), size=слов, replace=False))
        часть = чистые_слова[выбор]
        строки = np.concatenate([сдвинуть_слова(часть, Z, s) for s in range(сдвигов)]) if Z else часть
        я = gf2.ядро(строки)
        if лучшее is None or len(я) > len(лучшее):
            лучшее, раз = я, 1
        elif len(я) == len(лучшее):
            раз += 1
    return лучшее, раз


def достроить(ядро: np.ndarray, базис: Базис, *, срок: float, rng: np.random.Generator, вес_до: int,
              пора: Callable[[], bool], годится: Callable[[list[np.ndarray]], list[bool]]
              ) -> tuple[list[np.ndarray], int]:
    """Разреженные проверки ядра, которых нет в пространстве найденных, — Ли — Брикелл: случайная
    перестановка столбцов, ступенчатый вид — лёгкие строки и есть проверки (у LDPC их много). Каждая
    сверяется с принятыми словами (``годится``). Возвращает (новые, цель — ранг найденных вместе с ядром)."""
    d, n = ядро.shape
    новые: list[np.ndarray] = []
    if not d:
        return новые, базис.ранг
    плотный = np.zeros((базис.ранг, n), dtype=np.uint8)
    for i, h in enumerate(базис.взятые):
        плотный[i, h] = 1
    цель = gf2.ранг(np.concatenate([плотный, ядро]))
    конец = time.monotonic() + срок
    упаковано = gf2.упаковать(ядро)
    отвергнуто = 0
    while (базис.ранг < цель and time.monotonic() < конец and not пора()
           and отвергнуто < max(ОТВЕРГНУТО_ДО, 2 * len(новые))):
        порядок = rng.permutation(n)
        переставлено = gf2.упаковать(gf2.распаковать(упаковано, n)[:, порядок])
        приведено, _ = gf2.привести(переставлено, n)
        строки = gf2.распаковать(приведено, n)
        веса = строки.sum(axis=1)
        лёгкие = [np.sort(порядок[np.flatnonzero(с)]) for с in строки[(веса >= 2) & (веса <= вес_до)]]
        if not лёгкие:
            continue
        for h, да in zip(лёгкие, годится(лёгкие), strict=True):
            if not да:
                отвергнуто += 1
            elif базис.добавить(h):
                новые.append(h)
    return новые, цель


# -- поиск целиком ------------------------------------------------------------------------------------

def постоянные_столбцы(W: np.ndarray, доля: float = 0.98) -> np.ndarray:
    """Столбцы, почти одинаковые во всех словах (укорочение нулями, заполнение) — их нет в проверках кода."""
    if len(W) < 8:
        return np.zeros(0, dtype=np.int64)
    m = W.mean(axis=0)
    return np.flatnonzero((m <= 1 - доля) | (m >= доля))


#: Опорных столбцов — в долях от «шумового» 2/(w·τ) по раундам: у тяжёлых проверок выгоднее больше опорных,
#: у лёгких — меньше (шум в строках реже задевает носитель).
РАЗБРОС_T = (1.0, 2.0, 0.5, 4.0)
#: Слов на сверку кандидатов — не меньше стольких (их в Гаусс не берут).
СВЕРКА_ОТ = 64
#: Строк Гаусса (у квазициклического — со сдвигами слов) — не больше стольких.
СТРОК_ДО = 4096


def _параметры(n: int, строк: int, τ: float, вес: int, раз: float = 1.0) -> tuple[int, int, int]:
    """(t, ℓ, p): опорных столбцов ≈ раз·2/(w·τ) (не больше строк и n/2), ℓ — чтобы коллизий было немного."""
    t = int(np.clip(раз * 2.0 / max(1e-6, вес * τ), 40, min(n // 2, 3000)))
    t = max(8, min(t, строк - 24))
    прочие = n - t
    # p = 4 — когда прочих столбцов много (носитель веса w ложится парой в каждую половину вероятнее).
    p = 4 if прочие >= 600 else 2
    список = min(СПИСОК_ДО, (прочие // 2) ** 2 // 2) if p == 4 else прочие // 2
    эль = int(np.clip(math.ceil(math.log2(max(2, список))) + 2, 8, ЭЛЬ_ДО))
    эль = min(эль, max(4, строк - t))
    return t, эль, p


def сдвинуть_слова(W: np.ndarray, Z: int, s: int) -> np.ndarray:
    """Слова, сдвинутые внутри блоков по Z на s (у квазициклического кода — тоже кодовые)."""
    M, n = W.shape
    return np.roll(W.reshape(M, n // Z, Z), s, axis=2).reshape(M, n)


def восстановить(W: np.ndarray, *, срок: float = 60.0, стоп: Callable[[], bool] | None = None,
                 ход: Callable[[float, str], None] | None = None, сид: int = 1, вес_до: int = ВЕС_ДО,
                 τ: float = 1e-3, начало: int = 0, шаг: int = 0,
                 начальные: list[np.ndarray] | None = None,
                 граница_видна: Callable[[list[np.ndarray]], bool] | None = None,
                 снимок: Callable[[list[np.ndarray], dict], None] | None = None,
                 по_смещению: bool = True, раундов_до: int | None = None) -> Итог:
    """Проверки кода по словам W (слов × n): прогрессивный поиск с частичным Гауссом и коллизиями Штерна,
    структура (QC, IRA), декодирование по найденным. ``ход(доля, строка)`` — ход для окна; ``стоп()`` —
    остановить и вернуть найденное; ``начальные`` — уже найденные проверки (с прошлого этапа; сверяются);
    ``граница_видна(проверки)`` — True: окна сдвинуты относительно слов, поиск прекращается (сдвигает вызвавший);
    ``снимок(проверки, сведения)`` — после каждого раунда: найденное на случай остановки силой."""
    начато = time.monotonic()
    конец = начато + срок
    W = np.ascontiguousarray(np.asarray(W, dtype=np.uint8))
    M, n = W.shape
    итог = Итог(n=n, начало=начало, шаг=шаг or n, слов=M)
    rng = np.random.default_rng(сид)
    постоянные = постоянные_столбцы(W)
    итог.постоянные = постоянные
    живые = np.setdiff1d(np.arange(n), постоянные)
    if len(живые) < 16:
        итог.почему = "почти все столбцы постоянны — кода в словах нет"
        return итог

    def сказать(строка: str, доля: float | None = None) -> None:
        итог.ход.append(строка)
        if ход is not None:
            ход(доля if доля is not None else min(0.99, (time.monotonic() - начато) / max(1e-6, срок)), строка)

    def пора() -> bool:
        return time.monotonic() > конец or (стоп is not None and стоп())

    найдено: dict[bytes, np.ndarray] = {}
    развёрнуто: set[bytes] = set()          # проверки, чья орбита уже добавлена
    базис = Базис(n)
    чистые = np.zeros(M, dtype=bool)          # слова, сошедшиеся по найденной H (без ошибок на её носителе)
    исправленные = np.zeros((0, n), dtype=np.uint8)
    оператор = None
    стоит, раунд = 0, 0
    ранг_был = 0
    ранг_декодирования = 0
    ранг_достройки = 0
    рост = начато
    вес_тип = 6
    if начальные:
        проба = W[:min(M, 1024)]
        порог = порог_нарушений(len(проба), len(начальные))
        for h, д in zip(начальные, нарушения(проба, начальные).tolist(), strict=True):
            if д * len(проба) <= порог:
                найдено[h.tobytes()] = h
                базис.добавить(h)
        ранг_был = базис.ранг
    сказать(f"слов {M} по {n} бит; постоянных столбцов {len(постоянные)}; "
            + (f"с прошлого этапа проверок {базис.ранг}; " if начальные else "")
            + "ищу проверки (частичный Гаусс + коллизии)")
    while not пора() and (раундов_до is None or раунд < раундов_до):
        раунд += 1
        # Строки для Гаусса: чистые слова (если их хватает), иначе — слова с наименьшим числом нарушенных
        # найденных проверок (шум — реже); слов на сверку остаётся не меньше СВЕРКА_ОТ.
        раз = РАЗБРОС_T[(раунд - 1) % len(РАЗБРОС_T)]
        if базис.ранг >= 8:
            нар = нарушены_в_словах(W, базис.взятые[:256])
            порядок_слов = np.argsort(нар + np.where(чистые, -10**6, 0), kind="stable")
        else:
            порядок_слов = rng.permutation(M)
        пул = порядок_слов[:max(8, M - СВЕРКА_ОТ)]
        # Сошедшиеся слова берутся исправленными (декодер снял их ошибки на носителе найденных проверок).
        источник = W
        if чистые.any():
            источник = W.copy()
            источник[:len(исправленные)][чистые[:len(исправленные)]] = исправленные[чистые[:len(исправленные)]]
        τ_строк = τ / 20 if чистые[пул].mean() > 0.8 else τ
        if оператор is not None and оператор[0].startswith("квазициклический"):
            # Квазициклический: каждое слово со сдвигами внутри блоков — Z слов: строк Гаусса хватает и на
            # много опорных столбцов (когда шум мал).
            t_нужно = _параметры(len(живые), СТРОК_ДО, τ_строк, вес_тип, раз)[0] + ЭЛЬ_ДО
            if t_нужно > len(пул):
                сдвигов = min(оператор[1], -(-t_нужно // len(пул)), max(1, СТРОК_ДО // len(пул)))
                источник = np.concatenate([сдвинуть_слова(источник[пул], оператор[1], s_) for s_ in range(сдвигов)])
                пул = np.arange(len(источник))
        t, эль, p = _параметры(len(живые), len(пул), τ_строк, вес_тип, раз)
        # Ранг стоит — часть итераций направлена к позициям, которых не покрыла ни одна найденная проверка
        # (у кода с лестницей чётности — к чётности ненайденных строк): проверки, где они есть, редки по весу.
        цели: list[int] = []
        if стоит >= 1 and базис.ранг:
            покрыто = np.zeros(n, dtype=np.int64)
            for h in базис.взятые:
                покрыто[h] += 1
            наименее = живые[покрыто[живые] == покрыто[живые].min()]
            цели = rng.permutation(наименее)[:ИТЕРАЦИЙ_В_РАУНДЕ // 2].tolist()
        for номер_итерации in range(ИТЕРАЦИЙ_В_РАУНДЕ):
            if пора():
                break
            итог.итераций += 1
            цель = цели[номер_итерации] if номер_итерации < len(цели) else None
            кандидаты, взяты = итерация(источник, rng, t=t, эль=эль, p=p, вес_до=вес_до, строки=пул, столбцы=живые,
                                        цель=цель)
            if not кандидаты:
                continue
            новые = [h for h in кандидаты if h.tobytes() not in найдено]
            if not новые:
                continue
            занятые = порядок_слов[:max(8, M - СВЕРКА_ОТ)] if len(источник) != M else взяты
            сверка = np.setdiff1d(np.arange(M), занятые)
            if len(сверка) < 32:
                continue
            проба = W[rng.choice(сверка, size=min(len(сверка), СВЕРКА_СЛОВ), replace=False)]
            отсчётов = len(проба)
            порог = порог_нарушений(отсчётов, max(1, итог.итераций * 64))
            доли = нарушения(проба, новые)
            for h, д in zip(новые, доли.tolist(), strict=True):
                if д * отсчётов <= порог:
                    найдено[h.tobytes()] = h
                    if not базис.добавить(h):
                        развёрнуто.add(h.tobytes())       # зависимая — её орбита тоже в пространстве найденных
        # Структура: оператор по первым найденным (лёгким) проверкам — и орбиты всех.
        if оператор is None and sum(1 for h in найдено.values() if len(h) >= 3) >= 3:
            легчайшие = sorted(найдено.values(), key=len)
            порог_оп = max(0.15, min(ДОЛЯ_ДО, 4 * float(np.median(нарушения(W[:512], легчайшие[:6])))))
            оператор = найти_оператор(W, легчайшие, порог_оп)
            if оператор is not None:
                итог.оператор = оператор[0]
                итог.Z = оператор[1]
                сдвинуты = re.search(r"сдвинуты на (\d+)", оператор[0])
                итог.смещение = int(сдвинуты.group(1)) if сдвинуты else 0
                сказать(f"структура: {оператор[0]} — сдвинутые проверки выполнены")
                if итог.смещение and граница_видна is not None and по_смещению:
                    итог.почему = "окна сдвинуты относительно слов (блоки QC начинаются не с начала окна)"
                    break
        if оператор is not None:
            имя, порядок, f = оператор
            проба = W[:min(M, 512)]
            порог = порог_нарушений(len(проба), порядок * max(1, len(найдено)))
            for ключ, h in list(найдено.items()):
                if ключ in развёрнуто:
                    continue
                развёрнуто.add(ключ)
                for g in орбита(h, порядок, f):
                    развёрнуто.add(g.tobytes())
                    if g.tobytes() in найдено:
                        continue
                    if нарушения(проба, [g])[0] * len(проба) <= порог:
                        найдено[g.tobytes()] = g
                        базис.добавить(g)
                if len(найдено) > НАЙДЕНО_ДО:
                    # Память: зависимые (не в базисе) проверки забываются — орбиты нужны только у базисных.
                    свои = {h.tobytes() for h in базис.взятые}
                    найдено = {к: в for к, в in найдено.items() if к in свои}
        if базис.ранг:
            доли = нарушения(W[:min(M, 1024)], базис.взятые[:512])
            веса = np.array([len(h) for h in базис.взятые[:512]])
            вес_тип = int(np.median(веса))
            # τ — по сумме: доля нарушенных у проверки веса w при малом τ ≈ w·τ (по одной проверке нули
            # частые — медиана занизила бы).
            τ = float(np.clip(оценка_шума(float(доли.mean()), max(1, int(round(веса.mean())))), 1e-5, 0.05))
            итог.ошибок = τ
        # Сошедшихся слов (со сдвигами) больше n − ранг — ядро их матрицы содержит недостающие (тяжёлые)
        # проверки: Ли — Брикелл по ядру, каждая — со сверкой по принятым словам.
        # Слова — заново по всем найденным (раннее «сошлось» по меньшему числу проверок чаще ошибочно).
        Z_qc = оператор[1] if оператор is not None and оператор[0].startswith("квазициклический") else 0
        if (n <= ДОСТРОЙКА_ДО and базис.ранг >= 16 and базис.ранг != ранг_достройки
                and M >= слов_для_ядра(n, базис.ранг, Z_qc)
                and (базис.ранг <= 1.02 * ранг_был or раунд % 4 == 0) and not пора()):
            ранг_достройки = базис.ранг
            # Без сдвигов слов нужно больше n − ранг: декодируются вдвое больше (на два подмножества).
            часть = min(M, max(ДЕКОДИРОВАТЬ_СЛОВ, 2 * слов_для_ядра(n, базис.ранг, Z_qc)))
            исправленные, ок = декодировать(W[:часть], базис.взятые, итераций=20)
            ранг_декодирования = базис.ранг
            чистые = np.zeros(M, dtype=bool)
            чистые[:часть] = ок
            исправлено = (исправленные != W[:часть]).sum(axis=1)
            надёжные = np.flatnonzero(ок)[np.argsort(исправлено[ок], kind="stable")]
            ядро, раз = ядро_чистых(исправленные[надёжные], базис.ранг, Z_qc, rng)
            # «Сошлось» значит «без ошибок» только на столбцах, которые найденные проверки покрывают: ошибка
            # вне их не видна. Поэтому достройка — когда непокрытых столбцов так мало, что хоть одно
            # подмножество слов на них чистое с заметной вероятностью (берётся наибольшее ядро).
            покрыто = np.zeros(n, dtype=bool)
            for h in базис.взятые:
                покрыто[h] = True
            непокрытых = int((~покрыто[живые]).sum())
            полностью = (слов_для_ядра(n, базис.ранг, Z_qc) * непокрытых * math.log1p(-min(τ, 0.5))
                         >= math.log(0.2))
            if ядро is not None and раз >= 2 and len(ядро):
                # Столбцы, которых нет ни в одной проверке пространства (и ни в одной найденной), — край окна:
                # кусок соседнего слова.
                непокрыто = ~ядро.any(axis=0) & ~покрыто
                голова = int(np.argmax(~непокрыто)) if (~непокрыто).any() else 0
                хвост = int(np.argmax(~непокрыто[::-1])) if (~непокрыто).any() else 0
                if 0 < голова + хвост < n and непокрыто.sum() == голова + хвост and (шаг or n) == n:
                    итог.граница = голова if голова >= хвост else n - хвост
                    итог.почему = "окна сдвинуты относительно слов (край окна — ни в одной проверке)"
                    сказать(f"по ядру исправленных слов: биты {('0–' + str(голова - 1)) if голова >= хвост else (str(n - хвост) + '–' + str(n - 1))} "
                            "окна — ни в одной проверке: это кусок соседнего слова")
                    break
            if ядро is not None and полностью:
                проба_д = W[:min(M, 1024)]

                def годится(кандидаты: list[np.ndarray], проба_д=проба_д) -> list[bool]:
                    порог_д = порог_нарушений(len(проба_д), max(1, len(кандидаты)) * 64)
                    return (нарушения(проба_д, кандидаты) * len(проба_д) <= порог_д).tolist()

                был = базис.ранг
                новые, цель = достроить(ядро, базис, срок=min(ДОСТРОЙКА_СЕКУНД, max(1.0, конец - time.monotonic()) / 2),
                                       rng=rng, вес_до=max(вес_до, 30), пора=пора, годится=годится)
                for h in новые:
                    найдено[h.tobytes()] = h
                итог.размерность = цель
                итог.точно = раз >= 2 and базис.ранг >= цель
                сказать(f"по {len(надёжные)} исправленным словам: ядро {len(ядро)}, вместе с найденными — "
                        f"{цель}; достроено проверок {базис.ранг - был}")
                if базис.ранг > был:
                    ранг_декодирования = 0          # пересчитать исправленные по полной H
                    ранг_достройки = базис.ранг
                if итог.точно:
                    итог.почему = ("найдены все проверки: ранг = размерности ядра исправленных слов "
                                   f"({раз} подмножеств из {ПОДМНОЖЕСТВ} согласны)")
                    итог.раундов = раунд
                    break
        # Прогрессивно: декодировать по найденным — сошедшиеся слова чистые для следующих раундов.
        if базис.ранг >= 16 and базис.ранг > 1.2 * ранг_декодирования and not пора():
            часть = min(M, ДЕКОДИРОВАТЬ_СЛОВ)
            ранг_декодирования = базис.ранг
            исправленные, ок = декодировать(W[:часть], базис.взятые, итераций=20)
            чистые = np.zeros(M, dtype=bool)
            чистые[:часть] = ок
        итог.раундов = раунд
        if снимок is not None:
            снимок(базис.взятые, {"раунд": раунд, "ранг": базис.ранг, "Z": итог.Z, "оператор": итог.оператор,
                                  "ошибок": итог.ошибок, "слов": M})
        сказать(f"раунд {раунд}: найдено проверок {len(найдено)}, независимых {базис.ранг}; τ ≈ {τ:.1e}; "
                f"опорных {t}, ℓ = {эль}, p = {p}; чистых слов {int(чистые.sum())}")
        if базис.ранг > ранг_был:
            ранг_был, стоит = базис.ранг, 0
            рост = time.monotonic()
            if граница_видна is not None and граница_видна(базис.взятые):
                итог.почему = "окна сдвинуты относительно слов"
                break
        else:
            стоит += 1
            # Стоит и раундами, и временем (короткие раунды малой задачи — не повод сдаться за секунды).
            if стоит >= СТОЯТЬ_ДО and time.monotonic() - рост >= min(СТОЯТЬ_СЕКУНД, 0.25 * срок):
                итог.почему = f"ранг найденных не растёт {СТОЯТЬ_ДО} раундов подряд"
                break
    if not итог.почему:
        итог.почему = "остановлено" if (стоп is not None and стоп()) else "вышел срок"
    итог.проверки = sorted(базис.взятые, key=len)
    итог.найдено = len(найдено)
    итог.ранг = базис.ранг
    итог.k = n - базис.ранг
    if итог.проверки:
        доли = нарушения(W[:min(M, 2048)], итог.проверки)
        итог.доля = float(1 - доли.mean())
        _, ок = декодировать(W[:min(M, 512)], итог.проверки)
        итог.сошлось = float(ок.mean())
    итог.секунд = time.monotonic() - начато
    сказать(f"итог: независимых проверок {итог.ранг}, k ≈ {итог.k} (скорость {итог.k / n:.3f}); выполнены в "
            f"{итог.доля * 100:.1f} % слов; декодер сошёлся у {итог.сошлось * 100:.0f} % слов — {итог.почему}", 1.0)
    return итог


