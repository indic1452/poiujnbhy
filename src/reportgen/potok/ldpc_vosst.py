def позиции_данных(проверки: list[np.ndarray], n: int) -> np.ndarray:
    """Позиции данных: дополнение опорных столбцов H, приведённой с конца слова (опорный строки — её старшая
    единица): проверочные позиции — как можно ближе к концу, данные — в начале (как у систематических
    кодов стандартов). Нарастающим исключением по разреженным строкам — без плотной H n × n."""
    обратный = Базис(n)
    for h in проверки:
        обратный.добавить(np.sort(n - 1 - np.asarray(h, dtype=np.int64)))
    проверочные = {n - 1 - j for j in обратный.по_опорному}
    return np.array([j for j in range(n) if j not in проверочные], dtype=np.int64)


def матрица(итог: Итог, откуда: str = ""):
    """Найденные проверки — матрица LDPC проекта (с позициями данных)."""
    from . import ldpc  # noqa: PLC0415
    м = ldpc.Матрица(итог.n, [np.sort(np.asarray(h, dtype=np.int64)) for h in итог.проверки],
                     откуда or f"восстановлена по {итог.слов} словам")
    м.данные = позиции_данных(итог.проверки, итог.n)
    return м


def имя_файла(итог: Итог) -> str:
    import hashlib  # noqa: PLC0415
    отпечаток = hashlib.sha1(b"".join(np.sort(np.asarray(h, dtype=np.int64)).tobytes() for h in итог.проверки)).hexdigest()[:6]
    return f"восст-{итог.n}-{итог.k}-{отпечаток}"


def в_alist(итог: Итог, откуда: str = "") -> str:
    """Текст файла матрицы для папки отдела: примечания (откуда, данные, структура) и alist."""
    from . import ldpc  # noqa: PLC0415
    м = матрица(итог, откуда)
    строки = [f"# откуда: {откуда or 'восстановлена по потоку'} — {итог.слов} слов по {итог.n} бит, независимых "
              f"проверок {итог.ранг}" + (f", {итог.оператор}" if итог.оператор else "")
              + f", выполнены в {итог.доля * 100:.1f} % слов, BER ≈ {итог.ошибок:.1e}",
              f"# данные: {ldpc.позиции_строкой(м.данные)}"]
    return "\n".join(строки) + "\n" + ldpc.в_alist(м)


def сохранить(итог: Итог, откуда: str = "", имя: str | None = None) -> str:
    """Положить найденную H файлом alist в папку матриц отдела: имя файла (без расширения) — имя кода."""
    from . import ldpc  # noqa: PLC0415
    if ldpc.КАТАЛОГ is None:
        raise ValueError("папка матриц LDPC не задана")
    имя = имя or имя_файла(итог)
    if not ldpc.ИМЯ.fullmatch(имя):
        raise ValueError("имя матрицы — буквы, цифры, «_», «-», «.» (до 60 знаков)")
    путь = ldpc.КАТАЛОГ / f"{имя}.alist"
    путь.write_text(в_alist(итог, откуда), encoding="utf-8")
    return имя


