def записать_снимок(путь, проверки: list[np.ndarray], сведения: dict) -> None:
    """Найденное (проверки и сведения) — файлом .npz: на случай «Стоп» силой; запись — через временный файл."""
    import json  # noqa: PLC0415
    import os  # noqa: PLC0415
    длины = np.array([len(h) for h in проверки], dtype=np.int64)
    подряд = np.concatenate([np.asarray(h, dtype=np.int32) for h in проверки]) if проверки else np.zeros(0, np.int32)
    временный = f"{путь}.tmp.npz"
    np.savez(временный, длины=длины, подряд=подряд,
             сведения=np.frombuffer(json.dumps(сведения, ensure_ascii=False).encode("utf-8"), dtype=np.uint8))
    os.replace(временный, путь)


def прочитать_снимок(путь) -> Итог:
    """Итог по снимку: проверки, длина, начало, ранг и оценки (что известно)."""
    import json  # noqa: PLC0415
    with np.load(путь) as ф:
        длины, подряд = ф["длины"], ф["подряд"]
        сведения = json.loads(bytes(ф["сведения"]).decode("utf-8"))
    края = np.concatenate([[0], np.cumsum(длины)])
    проверки = [подряд[края[i]:края[i + 1]].astype(np.int64) for i in range(len(длины))]
    n = int(сведения["n"])
    базис = Базис(n)
    for h in проверки:
        базис.добавить(h)
    итог = Итог(n=n, начало=int(сведения.get("начало", 0)), шаг=int(сведения.get("шаг") or n),
                слов=int(сведения.get("слов", 0)), проверки=sorted(базис.взятые, key=len), ранг=базис.ранг,
                Z=int(сведения.get("Z", 0)), оператор=str(сведения.get("оператор", "")),
                ошибок=float(сведения.get("ошибок", 0.0)), раундов=int(сведения.get("раунд", 0)),
                почему=str(сведения.get("почему", "остановлено")))
    итог.k = n - итог.ранг
    итог.доля = float(сведения.get("доля", 0.0))
    итог.сошлось = float(сведения.get("сошлось", 0.0))
    return итог


def снять_по_итогу(биты: np.ndarray, итог: Итог, имя: str, вывод: str = "данные") -> tuple[np.ndarray, list[str]]:
    """Декодировать поток по сохранённой матрице ``имя`` с найденного начала (как слой «ldpc ИМЯ начало N»)."""
    from . import ldpc  # noqa: PLC0415
    return ldpc.снять(биты, ldpc.схема_сохранённая(имя), начало=итог.начало, вывод=вывод)


def находка(биты: np.ndarray, итог: Итог, имя: str, почему: str = ""):
    """Находка разбора: поток снят по восстановленной матрице (сохранена в папку отдела под ``имя``)."""
    from . import ldpc  # noqa: PLC0415
    from .nahodka import Находка  # noqa: PLC0415
    схема = ldpc.схема_сохранённая(имя)
    данные, подробно = снять_по_итогу(биты, итог, имя)
    k = len(ldpc.информационные(схема.матрица))
    return Находка(
        уровень="код",
        что=f"LDPC ({итог.n}, {k}) — матрица восстановлена по потоку и сохранена в папку отдела: «{имя}»",
        уверенность=float(min(1.0, итог.сошлось)),
        мера=(f"независимых проверок {итог.ранг}" + (f" (все: {итог.почему})" if итог.точно else "")
              + f", выполнены в {итог.доля * 100:.1f} % слов; декодер сошёлся у {итог.сошлось * 100:.0f} % слов"),
        подробно=([почему] if почему else []) + [
            f"слова по {итог.n} бит с бита {итог.начало}; " + (итог.оператор or "структура не найдена")
            + f"; BER ≈ {итог.ошибок:.1e}; за {итог.секунд:.0f} с"] + итог.ход[-4:] + подробно,
        дальше=данные, вид_дальше="биты",
        свойства={"n": итог.n, "k": k, "матрица": имя, "начало": итог.начало, "шаг": итог.шаг,
                  "выколото": 0, "укорочено": 0, "схема": схема, "данных_в_блоке": k,
                  "восстановлена": итог.словарь()})


# -- слова из потока: длина, начало, граница по проверкам -------------------------------------------

def слова(биты: np.ndarray, n: int, начало: int = 0, шаг: int = 0, слов_до: int | None = None) -> np.ndarray:
    """Слова потока (слов × n): с бита ``начало`` через ``шаг`` (по умолчанию n — подряд)."""
    шаг = шаг or n
    б = np.asarray(биты, dtype=np.uint8)
    всего = max(0, (len(б) - начало - n) // шаг + 1)
    if слов_до is not None:
        всего = min(всего, слов_до)
    if шаг == n:
        return б[начало:начало + всего * n].reshape(всего, n)
    return np.stack([б[начало + i * шаг:начало + i * шаг + n] for i in range(всего)]) if всего else np.zeros((0, n), np.uint8)


def граница(проверки: list[np.ndarray], n: int) -> tuple[int, str, int, int]:
    """Где в окне граница слов, если окна сдвинуты: проверки лежат по одну её сторону (суммы проверок двух
    соседних слов — тоже «проверки» и её пересекают, но их мало). Место 1 … n − 1, которое пересекает не больше
    2 % проверок и по обе стороны которого есть проверки («пересечение»), иначе непокрытый проверками край окна
    («край»). Возвращает (b, вид, от, до): граница может быть где угодно в [от, до] (между проверками —
    промежуток без их концов; у края — весь непокрытый кусок); (0, "", 0, 0) — окна выровнены (или не видно)."""
    if len(проверки) < 8:
        return 0, "", 0, 0
    крыто = np.zeros(n + 1, dtype=np.int64)
    for h in проверки:
        крыто[int(h.min()) + 1] += 1
        крыто[int(h.max()) + 1] -= 1
    пересекают = np.cumsum(крыто)[:n]            # пересекают[b] — сколько проверок с min < b ≤ max
    концы = np.sort(np.array([int(h.max()) for h in проверки]))
    слева = np.searchsorted(концы, np.arange(n), side="left")           # проверок целиком левее b
    всего = len(проверки)
    годные = np.flatnonzero((пересекают <= 0.02 * всего) & (слева >= max(2, 0.01 * всего))
                            & (всего - слева - пересекают >= max(2, 0.01 * всего)))
    годные = годные[годные > 0]
    if len(годные):
        # Наименьше пересечений; при равенстве — где проверки делятся ровнее.
        b = int(min(годные.tolist(), key=lambda b: (int(пересекают[b]), -min(int(слева[b]), всего - int(слева[b])))))
        от = до = b
        while от > 1 and пересекают[от - 1] == пересекают[b] and слева[от - 1] == слева[b]:
            от -= 1
        while до < n - 1 and пересекают[до + 1] == пересекают[b] and слева[до + 1] == слева[b]:
            до += 1
        return b, "пересечение", от, до
    # Проверки — только у одного слова (у куска другого полных проверок нет: там одна чётность): этот кусок
    # не покрыт ни одной проверкой, а остальное — плотно. Непокрытое начало (или конец) окна, которое при
    # случайном покрытии с той же плотностью вышло бы с вероятностью меньше 10⁻⁶, — кусок соседнего слова.
    покрыто = np.zeros(n, dtype=bool)
    for h in проверки:
        покрыто[h] = True
    занятые = np.flatnonzero(покрыто)
    if not len(занятые):
        return 0, "", 0, 0
    голова, хвост = int(занятые[0]), n - 1 - int(занятые[-1])
    for длина, b, от, до in ((голова, голова, 1, голова), (хвост, n - хвост, n - хвост, n - 1)):
        if длина < 16:
            continue
        плотность = min(1.0, float(покрыто.mean()) * n / max(1, n - длина))
        if длина * math.log(max(1e-12, 1 - плотность)) < math.log(1e-6):
            return b, "край", от, до
    return 0, "", 0, 0


def _перенести(проверки: list[np.ndarray], n: int, b: int) -> list[np.ndarray]:
    """Проверки окна в окна, начатые на b бит позже: левее b — хвост прошлого слова (на n − b дальше),
    правее — то же слово (на b ближе); пересекающие b отбрасываются."""
    итог = [h + (n - b) if h.max() < b else h - b for h in проверки if h.max() < b or h.min() >= b]
    return [h for h in итог if h.min() >= 0 and h.max() < n]


def _сдвинуть_окна(биты, n: int, начало: int, шаг: int, слов_до: int, проверки: list[np.ndarray],
                   край: bool = True, b: int = 0) -> tuple[int, int, np.ndarray, list[np.ndarray]] | None:
    """Если по проверкам видно, что окна сдвинуты, — (b, новое начало, новые слова, перенесённые проверки);
    ``край`` — верить и непокрытому краю окна (только когда поиск в этих окнах завершён); ``b`` — граница
    уже известна (по ядру)."""
    вид = "ядро"
    if not b:
        b, вид, _, _ = граница(проверки, n)
    if not b or (шаг or n) != n or (вид == "край" and not край):
        return None
    перенесённые = _перенести(проверки, n, b)
    новые = слова(биты, n, (начало + b) % n, шаг, слов_до)
    if not перенесённые or float(np.mean(нарушения(новые[:512], перенесённые[:256]) <= ДОЛЯ_ДО)) < 0.9:
        return None
    return b, (начало + b) % n, новые, перенесённые


#: Этапов поиска по потоку (после каждого — сверка границы слов) не больше; раундов в пробе границы.
ЭТАПОВ_ДО = 6
ПРОБА_РАУНДОВ = 8


def восстановить_по_потоку(биты: np.ndarray, n: int, *, начало: int = 0, шаг: int = 0, слов_до: int = 8192,
                           срок: float = 60.0, стоп: Callable[[], bool] | None = None,
                           ход: Callable[[float, str], None] | None = None, сид: int = 1,
                           снимок: Callable[[list[np.ndarray], dict], None] | None = None) -> Итог:
    """Восстановление по потоку с известной длиной слова n: слова с ``начало`` через ``шаг``. Если начало
    неверно (окна сдвинуты), найденные проверки лежат по одну сторону границы слов. Поиск — этапами; этап
    прерывается, как только граница видна по пересечению (проверки по обе стороны), а непокрытый край окна
    принимается за кусок соседнего слова только после завершённого этапа (ранг перестал расти) и только для
    ещё не пройденного начала. При сдвиге найденные проверки переносятся в новые окна и продолжают поиск.
    Итог — этап с наибольшим рангом."""
    начато = time.monotonic()
    W = слова(биты, n, начало, шаг, слов_до)
    if len(W) < 16:
        raise ValueError(f"слов по {n} бит меньше 16 — восстанавливать не по чему")

    def остаток() -> float:
        return срок - (time.monotonic() - начато)

    видеть = [True]               # прерывать этап, как только граница видна по пересечению
    пробные: list = [None]        # (граница, проверки в её окнах) — что нашла выбранная проба

    def видна(проверки: list[np.ndarray]) -> bool:
        return видеть[0] and (шаг or n) == n and граница(проверки, n)[1] == "пересечение"

    def выбрать(проверки: list[np.ndarray], этап: int, край: bool) -> int:
        """Граница по проверкам; если она где-то в промежутке — короткие пробы поиска в окнах с несколькими
        границами из него: в выровненных окнах проверок много, в сдвинутых — мало."""
        b, вид, от, до = граница(проверки, n)
        Z_, o_ = смещение[0] if смещение[0] else (0, 0)
        if not b or (вид == "край" and not край):
            if not o_:
                return 0                 # граница не видна (или край — рано), блоки на месте
            b, от, до = 0, 1, n - 1      # блоки QC сдвинуты: граница — где-то в окне
        if Z_:
            # Квазициклический: граница — на границе блоков (у сдвинутых окон — ≡ Z − o по модулю Z).
            остаток_Z = (Z_ - o_) % Z_
            кандидаты = sorted((x for x in range(от, до + 1) if x % Z_ == остаток_Z),
                               key=lambda x: abs(x - b))[:6]
        elif до - от >= 2:
            кандидаты = sorted({int(round(от + (до - от) * q)) for q in (0.0, 1 / 3, 2 / 3, 1.0)} - {0, n})
        else:
            кандидаты = [b]
        if not кандидаты:
            return 0
        if o_ and len(кандидаты) == 1:
            return кандидаты[0]
        if not o_:
            # Без сдвига блоков окна могут быть и выровнены: промежуток между проверками бывает и внутри
            # слова (найдена часть строк), непокрытый край — и тяжёлыми строками. «Остаться» — тоже кандидат.
            кандидаты = [0] + [к for к in кандидаты if к]
        if остаток() < 8:
            return b if вид == "пересечение" else (кандидаты[-1] if o_ else 0)
        # Пробы — последовательным отсевом: все кандидаты по ПРОБА_РАУНДОВ раундов, лучшая половина — вдвое
        # дольше (с найденным в своих окнах), и так до одного. Поровну раундов, не секунд: сравнение не
        # зависит от загрузки машины.
        состояние: dict[int, tuple[np.ndarray, list[np.ndarray]]] = {}
        for кандидат in кандидаты:
            W_к = слова(биты, n, (начало + кандидат) % n, шаг, слов_до)
            if len(W_к) >= 16:
                состояние[кандидат] = (W_к, _перенести(проверки, n, кандидат) if кандидат else проверки)
        if not состояние:
            return b
        срок_проб = остаток() * 0.5
        начаты = time.monotonic()
        раундов = ПРОБА_РАУНДОВ
        живые = list(состояние)
        оценки: list[tuple] = []
        while True:
            оценки = []
            for кандидат in живые:
                W_к, свои = состояние[кандидат]
                осталось = срок_проб - (time.monotonic() - начаты)
                п = восстановить(W_к, срок=max(1.0, осталось / max(1, len(живые))), стоп=стоп, сид=сид + 100,
                                 начало=начало, шаг=шаг, начальные=свои, раундов_до=раундов)
                состояние[кандидат] = (W_к, п.проверки)
                покрыто = np.zeros(n, dtype=bool)
                for h in п.проверки:
                    покрыто[h] = True
                # Ранг, затем покрытие (в окнах, сдвинутых на блок, кусок соседнего слова не покрыт), затем —
                # остаться (без перевеса в пробах окна не двигаются: найденные проверки лежат и в сдвинутых
                # окнах), затем ближе к границе по проверкам.
                оценки.append((п.ранг, int(покрыто.sum()), кандидат == 0, -abs(кандидат - b), кандидат))
            оценки.sort(reverse=True)
            if len(оценки) == 1 or time.monotonic() - начаты > срок_проб or (стоп is not None and стоп()):
                break
            живые = [о[4] for о in оценки[:max(1, (len(оценки) + 1) // 2)]]
            if len(живые) == 1:
                break
            раундов *= 2
        лучший = оценки[0][4]
        на_месте = next((о for о in оценки if о[4] == 0), None)
        if лучший and на_месте is not None and оценки[0][0] - на_месте[0] < max(8, 2 * Z_, 0.05 * на_месте[0]):
            лучший = 0                   # перевес в пробах мал (случайность поиска) — окна не двигаются
        if лучший in состояние:
            пробные[0] = (лучший, состояние[лучший][1])     # найденное пробой — не терять
        if ход is not None:
            ход(min(0.99, 1 - остаток() / срок), f"граница слов — где-то в битах {от}–{до} окна; пробы: "
                + ", ".join(f"{о[4] or 'на месте'} → {о[0]}" for о in оценки)
                + f"; {'беру ' + str(лучший) if лучший else 'окна не двигаю'}")
        return лучший

    лучший: Итог | None = None
    проверки: list[np.ndarray] = []
    пройдены = {начало}
    смещение: list = [0]
    по_смещению = True
    for этап in range(ЭТАПОВ_ДО):
        бюджет = остаток() if этап else min(срок * 0.25, 60.0)
        if бюджет < 1 or (стоп is not None and стоп()):
            break
        начало_этапа = начало

        def снимок_этапа(п: list[np.ndarray], св: dict, начало_этапа=начало_этапа) -> None:
            if снимок is not None:
                снимок(п, {**св, "n": n, "начало": начало_этапа, "шаг": шаг or n})

        итог = восстановить(W, срок=бюджет, стоп=стоп, ход=ход, сид=сид + этап, начало=начало, шаг=шаг,
                            начальные=проверки, граница_видна=видна, снимок=снимок_этапа,
                            по_смещению=по_смещению)
        if лучший is None or итог.ранг >= лучший.ранг:
            лучший = итог
        проверки = итог.проверки
        завершён = итог.точно or итог.почему.startswith("ранг найденных не растёт")
        # Квазициклический: граница слов — на границе блоков (у сдвинутых окон — со смещением).
        смещение[0] = (итог.Z, итог.смещение) if итог.Z and (итог.смещение or итог.оператор.startswith(
            "квазициклический")) else 0
        пробные[0] = None
        b_выбор = итог.граница or выбрать(проверки, этап, завершён or этап == 0)
        сдвиг = _сдвинуть_окна(биты, n, начало, шаг, слов_до, проверки, край=завершён or этап == 0,
                               b=b_выбор) if b_выбор else None
        if пробные[0] is not None and пробные[0][0] == 0 and len(пробные[0][1]) > len(проверки):
            проверки = пробные[0][1]                   # окна на месте — с найденным пробой
        if сдвиг is not None and пробные[0] is not None and пробные[0][0] == сдвиг[0]:
            сдвиг = (*сдвиг[:3], пробные[0][1])        # в новых окнах — найденное пробой в них
        сдвинуты = итог.почему.startswith("окна сдвинуты")
        if сдвиг is None or (сдвиг[1] in пройдены and not сдвинуты):
            if итог.смещение and по_смещению:
                по_смещению = False      # сдвиг виден по блокам, а граница — ещё нет: дальше в этих окнах
                continue
            if сдвинуты and not завершён:
                видеть[0] = False        # пробы оставили окна на месте — искать дальше, не прерываясь
                continue
            if завершён:
                break
            continue                     # этап кончился по сроку пробы — дальше по тем же окнам
        по_смещению = True
        видеть[0] = True
        b, начало, W, проверки = сдвиг
        пройдены.add(начало)
        итог.ход.append(f"окна сдвинуты: граница слов — бит {b} окна; начало слова — бит {начало}")
        if ход is not None:
            ход(min(0.99, 1 - остаток() / срок), итог.ход[-1])
        if остаток() < 1:
            # Сдвиг — после последнего этапа: проверки перенесены, поиска по новым окнам не было.
            базис = Базис(n)
            for h in проверки:
                базис.добавить(h)
            if базис.ранг >= лучший.ранг:
                итог.проверки = sorted(базис.взятые, key=len)
                итог.ранг = базис.ранг
                итог.k = n - базис.ранг
                итог.начало = начало
                итог.точно = False
                итог.доля = float(1 - нарушения(W[:2048], итог.проверки).mean()) if итог.проверки else 0.0
                лучший = итог
    assert лучший is not None
    лучший.секунд = time.monotonic() - начато
    return лучший
