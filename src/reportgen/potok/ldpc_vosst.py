"""Восстановление матрицы проверок нестандартного LDPC по зашумлённым словам, когда слов меньше длины.

Ранговый метод (``dlinnye``) ищет проверки Гауссом по всем n столбцам на ≈ ¾·n словах — и все эти
слова должны быть без ошибок на носителе проверки: вероятность ((1 + (1 − 2τ)^w)/2)^P. У длинного
кода и слов не хватает (у 9 МБ при n = 65 000 их около 1100), и шум убивает. Но для LDPC слов нужно
мало — логарифмически по n (Клюзо — Тийх, ISIT 2008); узкое место — счёт. Здесь — метод, которому
M ≥ n не нужно:

**Частичный Гаусс + коллизии Штерна** (Картье — Тийх, DCC 2019; диссертация Картье 2020, гл. 3):
r = t + ℓ случайных слов (строк), Гаусс только по t опорным столбцам (в случайном порядке):
[I_t | B ; 0 | C]. Проверка h = (h_опорн, h_прочие) зануляет эти строки, если C·h_прочие = 0 и
h_опорн = B·h_прочие. Разреженное h_прочие веса p ищется коллизиями: прочие столбцы — две половины,
суммы p/2 столбцов C каждой половины сравниваются (p = 2: столбцы; p = 4: пары); на совпадении
вес B·h_прочие должен быть мал (≤ w − p). Кандидат сверяется по всем остальным словам: доля
нарушенных у проверки веса w — (1 − (1 − 2τ)^w)/2, у случайного вектора — ½ (точный хвост
биномиального распределения). Опорных столбцов t — порядка 1…3/(w·τ): больше — чаще шум в строках,
меньше — реже носитель ложится как нужно.

**Структура.** Квазициклический код (циркулянт Z, делитель n): сдвиг проверки внутри блоков — снова
проверка; у DVB-подобного IRA (группы по 360, Z = 360) — свой «сдвиг»: данные внутри групп на 1,
чётность — на q = (n − k)/360 (наш опыт на кодах DVB-S2: сдвинутое слово нарушает не больше двух
проверок). Оператор ищется по первым найденным проверкам и проверяется по словам; дальше каждая
найденная проверка даёт свою орбиту (до Z проверок).

**Прогрессивно** (Клюзо 2006, Тиксье 2015, Ми и др. ISIT 2024): найденные проверки — частичная H;
слова декодируются по ней («минимум — сумма»), сошедшиеся слова — чистые строки для следующих
раундов (шум в опорных строках уходит — можно брать больше опорных столбцов). Слова для Гаусса —
сначала с наименьшим числом нарушенных найденных проверок. Стоп — ранг найденных перестал расти
несколько раундов подряд, вышел срок или «Стоп».

**Достройка по ядру.** Слова, сошедшиеся у декодера, — кодовые (если найденные проверки покрывают все
столбцы: ошибка вне их не видна). У квазициклического кода каждое такое слово со сдвигами в блоках даёт Z
строк, и уже ⌈(n − ранг)/Z⌉ + 16 слов дают матрицу, ядро которой — всё пространство проверок. Ошибочно
«исправленное» слово только сужает ядро, поэтому ядро считается по нескольким подмножествам (первое — самые
надёжные слова) и берётся наибольшее. Недостающие (тяжёлые) проверки — разреженные векторы ядра — ищутся
Ли — Брикеллом (случайная перестановка, ступенчатый вид, лёгкие строки) и каждая сверяется с принятыми
словами. Ранг найденных = размерности ядра у двух подмножеств и больше — «найдены все проверки», k точно.

**Граница слов.** Окна могут быть сдвинуты относительно слов. Признаки: проверки по обе стороны места,
которое ни одна не пересекает; непокрытый край окна; блоки QC, начинающиеся не с бита 0 окна (оператор со
смещением o — граница ≡ Z − o по модулю Z); столбцы, которых нет ни в одной проверке ядра. Где граница может
быть в промежутке, решают пробы — поиск в окнах с каждой возможной границей поровну раундов, с отсевом
худшей половины; найденные проверки переносятся в новые окна.

Итог — независимые разреженные проверки (H), скорость k = n − ранг, Z/оператор, позиции данных,
постоянные столбцы (укорочение) — и файл alist для папки матриц отдела.
"""

