def корень_j(п: dict) -> int:
    """Степень α первого корня: β^fcr, β = α^шаг."""
    return (п["шаг"] * п["fcr"]) % ((1 << п["m"]) - 1)


def чистые_начала(с: np.ndarray, N: int, I: int, п: dict) -> np.ndarray:
    """Начала всех слов (N символов с шагом I) с нулевыми синдромами: кандидаты — равенство
    префикса в первом корне на расстоянии N·I, затем синдромы."""
    P = префикс(с, I, корень_j(п), п["многочлен"])
    d = N * I
    равны = np.flatnonzero(P[:-d] == P[d:])
    равны = равны[равны + (N - 1) * I < len(с)]
    if not len(равны):
        return равны
    S = rs_bch.синдромы(слова_по_началам(с, равны, N, I), п["многочлен"], п["fcr"], п["корней"], п["шаг"])
    return равны[~S.any(axis=1)]


def лучшая_фаза(биты: np.ndarray, m: int, I: int, N: int, п: dict, порядок: str, базис: str,
                фазы: Iterable[int] | None = None, символов: int | None = None) -> tuple[int, np.ndarray]:
    """Фаза бита, при которой чистых слов больше всего: (фаза, их начала). На сдвинутой фазе
    отбор по корню 1 частично срабатывает тоже — уточнение по известному коду."""
    лучшее = (0, np.zeros(0, dtype=np.int64))
    for ф in (range(m) if фазы is None else фазы):
        с = символы(биты[:ф + символов * m] if символов else биты, m, ф, порядок, базис)
        ч = чистые_начала(с, N, I, п)
        if len(ч) > len(лучшее[1]):
            лучшее = (ф, ч)
    return лучшее


def _начало_блока(чистые: np.ndarray, модуль: int, I: int) -> tuple[int, float]:
    """Вычет r (по модулю ``модуль``), с которого I соседних вычетов собирают больше всего начал."""
    h = np.bincount(чистые % модуль, minlength=модуль).astype(np.int64)
    окно = h.copy()
    for i in range(1, I):
        окно += np.roll(h, -i)
    r = int(np.argmax(окно))
    return r, float(окно[r]) / max(1, len(чистые))


def раскладка(длина: int, чистые: np.ndarray, N: int, I: int
              ) -> tuple[bool, int, tuple[int, ...], np.ndarray]:
    """(сплошь, период кадра F, начала блоков в кадре, начала блоков) по началам чистых слов.

    Сплошь — если ≥ 80 % чистых начал попадают в I соседних вычетов по модулю N·I. Иначе
    кадры: представители блоков (первое начало в группе соседних), период F — из частых
    разностей между ними (и сумм двух: несколько блоков в кадре), вычеты начал блоков по модулю
    F должны собрать ≥ 80 % чистых начал.
    """
    d = N * I
    чистые = np.unique(np.asarray(чистые, dtype=np.int64))
    if not len(чистые):
        return True, 0, (), np.zeros(0, dtype=np.int64)
    r, доля = _начало_блока(чистые, d, I)
    сплошь = (True, 0, (), np.arange(r % d, длина - d + 1, d, dtype=np.int64))
    if доля >= СПЛОШЬ_ОТ or len(чистые) < 6:
        return сплошь
    группы = np.concatenate(([True], np.diff(чистые) >= I))
    предст = чистые[группы]
    частые = [δ for δ, _ in Counter(np.diff(предст).tolist()).most_common(8) if δ > d]
    кандидаты = sorted({δ for δ in частые} | {δ + δ2 for δ in частые for δ2 in частые})
    for F in кандидаты:
        h = np.bincount(чистые % F, minlength=F)
        годные = np.flatnonzero(h >= max(2, 0.25 * h.max()))
        if h[годные].sum() < СПЛОШЬ_ОТ * len(чистые):
            continue
        # Начала блоков — первые годные вычеты в сериях не длиннее I.
        в_кадре: list[int] = []
        for r_ in годные.tolist():
            if not any((r_ - н) % F < I for н in в_кадре):
                в_кадре.append(int(r_))
        if len(в_кадре) * d > F:
            continue
        блоки = (np.arange(длина // F + 1, dtype=np.int64)[:, None] * F
                 + np.asarray(в_кадре, dtype=np.int64)[None, :]).reshape(-1)
        return False, int(F), tuple(sorted(в_кадре)), np.sort(блоки[блоки + d <= длина])
    return сплошь


def снять(с: np.ndarray, *, m: int, I: int, N: int, корней: int, p: int, fcr: int, шаг: int,
          порядок: str, базис: str, блоки: np.ndarray
          ) -> tuple[np.ndarray, np.ndarray, int, float]:
    """Исправить слова блоков: (данные битами, исправлено по слову, слов, доля нулевых синдромов до).

    ``с`` — символы обычного базиса; данные — первые I·k символов каждого блока после
    исправления, обратно в базис и порядок бит потока.
    """
    блоки = np.asarray(блоки, dtype=np.int64)[:БЛОКОВ_ДО]
    if not len(блоки):
        return np.zeros(0, dtype=np.uint8), np.zeros(0, dtype=np.int64), 0, 0.0
    индексы = (блоки[:, None, None] + np.arange(I)[None, :, None]
               + I * np.arange(N)[None, None, :])                   # блок × слово × символ
    слова = с[индексы].reshape(-1, N)
    S = rs_bch.синдромы(слова, p, fcr, корней, шаг)
    чистых = float((~S.any(axis=1)).mean())
    исправленные, исправлено = rs_bch.исправить(слова, p, fcr, корней, шаг)
    k = N - корней
    данные = исправленные.reshape(len(блоки), I, N)[:, :, :k].transpose(0, 2, 1).reshape(-1)
    return в_биты(данные, m, порядок, базис), исправлено, len(слова), чистых


def собрать(биты: np.ndarray, *, m: int, фаза: int, I: int, N: int, п: dict, порядок: str, базис: str,
            ступень: int = 0, мера_: float = 0.0, чистые: np.ndarray | None = None) -> Код | None:
    """Раскладка блоков по чистым словам, исправление и итог — код или None (чистых слов мало)."""
    с = символы(биты, m, фаза, порядок, базис)
    if чистые is None:
        чистые = чистые_начала(с, N, I, п)
    if len(чистые) < 2:
        return None
    сплошь, F, в_кадре, блоки = раскладка(len(с), чистые, N, I)
    данные, исправлено, слов, чистых = снять(с, m=m, I=I, N=N, корней=п["корней"], p=п["многочлен"],
                                             fcr=п["fcr"], шаг=п["шаг"], порядок=порядок, базис=базис,
                                             блоки=блоки)
    if not слов or int(round(чистых * слов)) < min(ЧИСТЫХ_СЛОВ_ОТ, max(2, слов // 4)):
        return None
    итог, _ = rs_bch.итог_словами(исправлено, "символов", "символ", слов * N)
    return Код(m=m, фаза=фаза, I=I, N=N, k=N - п["корней"], p=п["многочлен"], fcr=п["fcr"], шаг=п["шаг"],
               порядок=порядок, базис=базис, доля_корней=float(п.get("доля", чистых)), ступень=ступень,
               мера=мера_, блоки=блоки, сплошь=сплошь, кадр=F, в_кадре=в_кадре, чистых_до=чистых,
               исправлено=int(исправлено[исправлено > 0].sum()), исправлено_слов=int((исправлено > 0).sum()),
               неисправимых=int((исправлено < 0).sum()), слов=слов, данные=данные, итог=итог)


def искать_в(биты: np.ndarray, конф: Конфигурация, *, глубоко: bool = False,
             стоп: Callable[[], bool] | None = None) -> Код | None:
    """Поиск в одной конфигурации: кандидаты всех её фаз (лучшие первыми), проверка корней,
    уточнение фазы по известному коду, раскладка и снятие."""
    сколько = _выборка(конф, глубоко)
    кандидаты: list[_Кандидат] = []
    for ф in конф.фазы:
        с = символы(биты[:ф + сколько * конф.m], конф.m, ф, конф.порядок, конф.базис)
        кандидаты += _кандидаты(с, конф, ф, глубоко, стоп)
    кандидаты.sort(key=lambda к: -к.s)
    for канд in кандидаты[:КАНДИДАТОВ]:
        if стоп is not None and стоп():
            return None
        проверено = _проверить(биты, конф, канд, глубоко)
        if проверено is None:
            continue
        п, порядок, базис = проверено
        фаза, чистые = лучшая_фаза(биты, конф.m, конф.I, канд.N, п, порядок, базис, символов=сколько)
        if len(чистые) < 2:
            continue
        код = собрать(биты, m=конф.m, фаза=фаза, I=конф.I, N=канд.N, п=п, порядок=порядок, базис=базис,
                      ступень=конф.ступень, мера_=канд.s)
        if код is not None:
            return мельче(биты, код)
    return None


def мельче(биты: np.ndarray, код: Код) -> Код:
    """Чередование глубже найденного: d слов по N/d символов при глубине I·d.

    Слово, сложенное из d слов кода вперемешку, само кодовое — с корнями в корнях степени d
    (шаг корней 127 при d = 2 и т. п.), поэтому при глубине I находится и «код» длины d·N′.
    Если слова глубины I·d длины N/d опознаются в том же поле с цепочкой ≥ ПОДРЯД_ОТ — берётся
    это, более мелкое описание (проверяется до тех пор, пока мельчится).
    """
    while True:
        лучше = None
        for d in range(2, ГЛУБИНА_ДО // код.I + 1):
            if код.N % d or код.N // d < N_ОТ or not код.сплошь:
                continue
            I2, N2 = код.I * d, код.N // d
            с = символы(биты, код.m, код.фаза, код.порядок, код.базис)
            блоки = код.блоки[:max(1, СЛОВ_ОПОЗНАНИЯ // I2 + 1)]
            начала = (блоки[:, None] + np.arange(I2)[None, :]).reshape(-1)
            слова = слова_по_началам(с, начала, N2, I2)
            if not len(слова):
                continue
            п = опознать(слова, код.m, [код.p])
            if п is None:
                continue
            новый = собрать(биты, m=код.m, фаза=код.фаза, I=I2, N=N2, п=п, порядок=код.порядок,
                            базис=код.базис, ступень=код.ступень, мера_=код.мера)
            if новый is not None and новый.чистых_до >= код.чистых_до:
                лучше = новый
                break
        if лучше is None:
            return код
        код = лучше


# -- полный поиск ---------------------------------------------------------------------------------

def поиск(биты: np.ndarray, *, профиль: str = "обычно", с: int = 0, по: int | None = None,
          срок: float | None = None, все: bool = False, ход: Callable[[str], None] | None = None,
          стоп: Callable[[], bool] | None = None) -> dict:
    """Конфигурации плана с номерами [с, по): найденные коды. ``все`` — не останавливаться на первом.

    Возвращает {"найдено": [Код], "по": следующий номер, "всего": конфигураций плана}.
    """
    биты = np.asarray(биты, dtype=np.uint8)
    конфигурации = план(профиль)
    по = len(конфигурации) if по is None else min(по, len(конфигурации))
    конец = time.monotonic() + срок if срок else None
    глубоко = профиль == "глубоко"
    найдено: list[Код] = []
    ключи: set[tuple] = set()
    i = с
    while i < по:
        if стоп is not None and стоп():
            break
        конф = конфигурации[i]
        i += 1
        if ход is not None:
            ход(f"РС вслепую: {i}/{len(конфигурации)} — {конф.подпись()}")
        код = искать_в(биты, конф, глубоко=глубоко, стоп=стоп)
        if код is not None and код.ключ() not in ключи:
            ключи.add(код.ключ())
            найдено.append(код)
            if not все:
                break
        if конец is not None and time.monotonic() > конец:
            break
    return {"найдено": найдено, "по": i, "всего": len(конфигурации)}


def описать(код: Код, всего_бит: int = 0) -> Находка:
    """Находка уровня «код» по найденному коду."""
    β = "α" if код.шаг == 1 else f"β = α^{код.шаг}"
    что = (f"код Рида — Соломона ({код.N}, {код.k}) над GF(2^{код.m}), t = {код.корней // 2}"
           + (f", чередование {код.I} слов по символам" if код.I > 1 else "")
           + (", двойной базис (как у CCSDS)" if код.базис == "двойной" else "")
           + (", младший бит символа первым" if код.порядок == "младший" else "")
           + (" — слова сплошь" if код.сплошь else f" — в кадрах по {код.кадр * код.m} бит"))
    конец_блоков = код.фаза + код.m * (int(код.блоки[-1]) + код.N * код.I) if len(код.блоки) else 0
    подробно = [
        f"поле GF(2^{код.m}) по многочлену 0x{код.p:X}; корни — степени {β} с {код.fcr}-й по "
        f"{код.fcr + код.корней - 1}-ю ({код.корней} подряд: fcr = {код.fcr}, шаг {код.шаг})",
        f"блок {код.I * код.N} символов = {код.I} × {код.N}: символ j·{код.I} + i — i-го слова; данные — "
        f"первые {код.I * код.k} символов блока, проверочные — последние {код.I * код.корней}"
        if код.I > 1 else f"слово {код.N} символов: данные — первые {код.k}, проверочные — последние {код.корней}",
        f"символ {код.m} бит, {код.порядок} бит первым; битовая фаза {код.фаза}"
        + ("; символы в двойном базисе Берлекэмпа — для расчёта переводятся в обычный (таблица как у libfec)"
           if код.базис == "двойной" else ""),
        f"первый блок — с бита {код.сдвиг} (до него {код.сдвиг} бит потока)"
        + (f"; после последнего блока — {max(0, всего_бит - конец_блоков)} бит хвоста" if всего_бит else ""),
    ]
    if not код.сплошь:
        заголовок = (код.кадр - len(код.в_кадре) * код.N * код.I) * код.m
        подробно.append(f"слова не сплошь: кадр {код.кадр * код.m} бит, блоков в кадре {len(код.в_кадре)}, "
                        f"остальные {заголовок} бит кадра — заголовок или служебные поля")
    подробно += [
        "параметры заданы слоем (не найдены вслепую)" if not код.ступень else
        f"найдено ступенью {код.ступень} ("
        + ("XOR символов слова = 0 — корень 1, не зависит от поля, базиса и порядка бит"
           if код.ступень == 1 else "префикс P_j по выборке степеней j в поле, базисе и порядке бит перебора")
        + f"), мера {код.мера:.0f} (−ln вероятности случайного совпадения)",
        f"нулевые синдромы до исправления — у {код.чистых_до * 100:.1f} % из {код.слов} слов",
        "исправление алгебраическое (Берлекэмп — Мэсси, Ченя, Форни): " + код.итог,
        f"снять вручную — слой «{код.слой()}»",
    ]
    return Находка(
        уровень="код", что=что, уверенность=max(код.чистых_до, min(1.0, код.доля_корней)),
        мера=(f"слова зануляются в корнях порождающего многочлена в {код.доля_корней * 100:.1f} % отобранных; "
              f"нулевой синдром до исправления — у {код.чистых_до * 100:.1f} % слов"),
        подробно=подробно, дальше=код.данные, вид_дальше="биты", сверка=код.чистых_до,
        свойства={"N": код.N, "k": код.k, "глубина": код.I, "базис": код.базис, "многочлен": код.p,
                  "fcr": код.fcr, "шаг": код.шаг, "m": код.m, "порядок": код.порядок, "фаза": код.фаза,
                  "сдвиг": код.сдвиг, "сплошь": код.сплошь, "кадр_бит": код.кадр * код.m,
                  "исправлено": код.исправлено, "неисправимых": код.неисправимых,
                  "слой": код.слой(), "ступень": код.ступень,
                  **({"данных_в_блоке": код.m * код.I * код.k} if код.сплошь else {})})


def найти(биты: np.ndarray, *, профиль: str = "обычно", бюджет: float = 60.0,
          ход: Callable[[str], None] | None = None, стоп: Callable[[], bool] | None = None) -> Находка | None:
    """Код Рида — Соломона вслепую в битовом потоке (или None) — первый найденный по плану."""
    биты = np.asarray(биты, dtype=np.uint8)
    if len(биты) < 4096:
        return None
    итог = поиск(биты, профиль=профиль, срок=бюджет, ход=ход, стоп=стоп)
    if not итог["найдено"]:
        return None
    return описать(итог["найдено"][0], len(биты))


# -- слой стола: «рс вслепую» и «рс N K …» --------------------------------------------------------

#: Подсказка к слою — в ошибках разбора указания.
СЛОЙ_ПОДСКАЗКА = ("«рс вслепую [быстро|обычно|глубоко]» или «рс N K [поле 0x11D] [fcr F] [шаг S] [глубина I] "
                  "[базис обычный|двойной] [порядок старший|младший] [символ m] [сдвиг s] [кадр L блоки a,b…]»")


def разобрать_слой(слова: str) -> dict:
    """Параметры слоя «рс N K …» (без начального «рс»): словарь или ValueError."""
    import re  # noqa: PLC0415
    т = слова.lower().replace(",", " , ")
    м = re.match(r"\s*(?:рс|rs)\s+(\d+)\s+(\d+)\b", т)
    if not м:
        raise ValueError("слой РС: " + СЛОЙ_ПОДСКАЗКА)
    N, k = int(м.group(1)), int(м.group(2))

    def число(имя: str, по: int | None) -> int | None:
        н = re.search(rf"\b{имя}\s+(0x[0-9a-f]+|-?\d+)", т)
        return по if н is None else int(н.group(1), 0)

    m = число("символ", 8)
    if not 3 <= m <= 12:
        raise ValueError(f"слой РС: символ — от 3 до 12 бит (получено {m})")
    p = число("поле", None)
    if p is None:
        p = многочлены_поля(m)[0]
    п = {"N": N, "k": k, "m": m, "многочлен": p, "fcr": число("fcr", 0), "шаг": число("шаг", 1),
         "I": число("глубина", 1), "сдвиг": число("сдвиг", None), "кадр": число("кадр", None),
         "базис": "двойной" if re.search(r"базис\s+двойн", т) else "обычный",
         "порядок": "младший" if re.search(r"порядок\s+младш", т) else "старший"}
    б = re.search(r"\bблоки\s+([\d\s,]+)", т)
    п["блоки"] = [int(x) for x in re.findall(r"\d+", б.group(1))] if б else []
    q1 = (1 << m) - 1
    if not rs_bch.примитивный(p) or p.bit_length() - 1 != m:
        raise ValueError(f"слой РС: многочлен поля 0x{p:X} не примитивный степени {m}")
    if not (0 < k < N <= q1) or (N - k) % 2:
        raise ValueError(f"слой РС: нужно 0 < K < N ≤ {q1} и N − K чётно (получено N = {N}, K = {k})")
    if not 1 <= п["I"] <= 255 or math.gcd(п["шаг"], q1) != 1:
        raise ValueError("слой РС: глубина — от 1 до 255, шаг корней — взаимно простой с 2^m − 1")
    if п["базис"] == "двойной" and m != 8:
        raise ValueError("слой РС: двойной базис — только у символов 8 бит")
    if п["кадр"] is not None and (п["кадр"] % m or not п["блоки"] or any(b % m for b in п["блоки"])):
        raise ValueError("слой РС: «кадр L блоки a,b…» — длина кадра и начала блоков в нём кратны размеру символа")
    return п


def снять_слоем(биты: np.ndarray, слова: str) -> tuple[np.ndarray, list[str], dict]:
    """Слой стола: «рс вслепую [профиль]» — поиск и снятие; «рс N K …» — снять по параметрам.

    Без «сдвиг» начало находится по чистым словам (лучшая битовая фаза и вычет начала блока).
    Возвращает (данные, подробности, свойства находки).
    """
    import re  # noqa: PLC0415
    биты = np.asarray(биты, dtype=np.uint8)
    т = слова.lower()
    if re.search(r"вслеп|blind|поиск", т):
        профиль = next((п for п in ("быстро", "обычно", "глубоко") if п in т), "обычно")
        итог = поиск(биты, профиль=профиль)
        if not итог["найдено"]:
            raise ValueError(f"код Рида — Соломона вслепую не найден (профиль «{профиль}», "
                             f"конфигураций {итог['по']} из {итог['всего']})")
        находка = описать(итог["найдено"][0], len(биты))
        return находка.дальше, [f"{находка.что}: {находка.мера}"] + list(находка.подробно), находка.свойства
    п = разобрать_слой(т)
    m, I, N = п["m"], п["I"], п["N"]
    код_ = {"многочлен": п["многочлен"], "fcr": п["fcr"], "шаг": п["шаг"], "корней": N - п["k"], "m": m}
    if п["сдвиг"] is None:
        фаза, чистые = лучшая_фаза(биты, m, I, N, код_, п["порядок"], п["базис"])
        if not len(чистые):
            raise ValueError(f"RS({N}, {п['k']}): слов с нулевыми синдромами нет ни при одной фазе и начале — "
                             f"параметры не те")
        код = собрать(биты, m=m, фаза=фаза, I=I, N=N, п=код_, порядок=п["порядок"], базис=п["базис"],
                      чистые=чистые)
        if код is None:
            # Чистых слов мало для проверки — снимаем по лучшей раскладке как есть.
            с = символы(биты, m, фаза, п["порядок"], п["базис"])
            сплошь, F, в_кадре, блоки = раскладка(len(с), чистые, N, I)
            код = _код_по_блокам(биты, п, код_, фаза, блоки, сплошь, F, в_кадре)
    else:
        фаза = п["сдвиг"] % m
        с = символы(биты, m, фаза, п["порядок"], п["базис"])
        первый = (п["сдвиг"] - фаза) // m
        if п["кадр"]:
            F = п["кадр"] // m
            в_кадре = tuple(первый + b // m for b in п["блоки"])
            блоки = (np.arange(len(с) // F + 1, dtype=np.int64)[:, None] * F
                     + np.asarray(в_кадре, dtype=np.int64)[None, :]).reshape(-1)
            блоки = np.sort(блоки[блоки + N * I <= len(с)])
            код = _код_по_блокам(биты, п, код_, фаза, блоки, False, F, в_кадре)
        else:
            блоки = np.arange(первый, len(с) - N * I + 1, N * I, dtype=np.int64)
            код = _код_по_блокам(биты, п, код_, фаза, блоки, True, 0, ())
    находка = описать(код, len(биты))
    return находка.дальше, [f"{находка.что}: {находка.мера}"] + list(находка.подробно), находка.свойства


def _код_по_блокам(биты: np.ndarray, п: dict, код_: dict, фаза: int, блоки: np.ndarray, сплошь: bool,
                   F: int, в_кадре: tuple[int, ...]) -> Код:
    """Снять по заданной раскладке блоков (без проверки доли чистых слов)."""
    m, I, N = п["m"], п["I"], п["N"]
    с = символы(биты, m, фаза, п["порядок"], п["базис"])
    if not len(блоки):
        raise ValueError(f"RS({N}, {п['k']}): в потоке нет ни одного целого блока {N * I * m} бит")
    данные, исправлено, слов, чистых = снять(с, m=m, I=I, N=N, корней=код_["корней"], p=код_["многочлен"],
                                             fcr=код_["fcr"], шаг=код_["шаг"], порядок=п["порядок"],
                                             базис=п["базис"], блоки=блоки)
    итог, _ = rs_bch.итог_словами(исправлено, "символов", "символ", слов * N)
    return Код(m=m, фаза=фаза, I=I, N=N, k=п["k"], p=код_["многочлен"], fcr=код_["fcr"], шаг=код_["шаг"],
               порядок=п["порядок"], базис=п["базис"], доля_корней=чистых, ступень=0, мера=0.0, блоки=блоки,
               сплошь=сплошь, кадр=F, в_кадре=в_кадре, чистых_до=чистых,
               исправлено=int(исправлено[исправлено > 0].sum()), исправлено_слов=int((исправлено > 0).sum()),
               неисправимых=int((исправлено < 0).sum()), слов=слов, данные=данные, итог=итог)
