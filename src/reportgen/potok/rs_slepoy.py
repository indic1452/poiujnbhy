# -- символы и обратно ---------------------------------------------------------------------------

def _двойной_базис() -> tuple[np.ndarray, np.ndarray]:
    from .dlinnye import В_ДВОЙНОЙ, ИЗ_ДВОЙНОГО  # noqa: PLC0415
    return В_ДВОЙНОЙ.astype(np.int64), ИЗ_ДВОЙНОГО.astype(np.int64)


def символы(биты: np.ndarray, m: int, фаза: int = 0, порядок: str = "старший",
            базис: str = "обычный") -> np.ndarray:
    """Биты с бита ``фаза`` → m-битовые символы; «младший» — младший бит символа первым;
    «двойной» (m = 8) — байты в двойном базисе Берлекэмпа переводятся в обычный."""
    б = np.asarray(биты[фаза:], dtype=np.uint8)
    n = len(б) // m
    if m == 8 and порядок in ("старший", "младший"):
        с = np.packbits(б[:8 * n], bitorder="big" if порядок == "старший" else "little").astype(np.int64)
    else:
        веса = (1 << (np.arange(m - 1, -1, -1) if порядок == "старший" else np.arange(m))).astype(np.int64)
        с = б[:n * m].reshape(n, m).astype(np.int64) @ веса
    if базис == "двойной":
        if m != 8:
            raise ValueError("двойной базис — только у символов 8 бит")
        с = _двойной_базис()[1][с]
    return с


def в_биты(символы_: np.ndarray, m: int, порядок: str = "старший", базис: str = "обычный") -> np.ndarray:
    """Обратное к ``символы``: символы обычного базиса → биты потока."""
    с = np.asarray(символы_, dtype=np.int64).ravel()
    if базис == "двойной":
        с = _двойной_базис()[0][с]
    сдвиги = np.arange(m - 1, -1, -1) if порядок == "старший" else np.arange(m)
    return ((с[:, None] >> сдвиги) & 1).astype(np.uint8).ravel()


# -- префикс и пары равных значений --------------------------------------------------------------

def префикс(с: np.ndarray, I: int = 1, j: int = 0, p: int | None = None) -> np.ndarray:
    """P(t) = XOR r_u·α^(−j·⌊u/I⌋) по u < t, u ≡ t (mod I), для t = 0 … ⌊T/I⌋·I + I − 1.

    P(t + N·I) = P(t) ⇔ слово полосы t из N символов с шагом I зануляется в α^j.
    """
    T = len(с) // I * I
    v = np.asarray(с[:T], dtype=np.int64)
    if j:
        степень, логарифм, _ = rs_bch.поле(p)
        Q = len(логарифм) - 1
        # Показатель α^(−j·строка) по модулю Q — периодичен по строке с периодом Q: таблица на Q строк.
        строка = np.arange(T, dtype=np.int64) // I % Q
        сдвиг = (-j * np.arange(Q, dtype=np.int64)) % Q
        v = np.where(v == 0, 0, степень[логарифм[v] + сдвиг[строка]])
    P = np.zeros((T // I + 1, I), dtype=np.int64)
    P[1:] = np.bitwise_xor.accumulate(v.reshape(T // I, I), axis=0)
    return P.ravel()


def пары(P: np.ndarray, I: int, d_от: int, d_до: int, шагов: int = ПАР_ШАГОВ_ДО
         ) -> tuple[np.ndarray, np.ndarray]:
    """Все пары t < t′ с P(t) = P(t′), t′ − t кратно I и d_от ≤ t′ − t ≤ d_до: (t, t′ − t).

    Сортировка по (значение, t mod I); в группе равных — по t (устойчиво), так что пара
    (i, i + k) отсортированного ряда — k-й следующий равный. Если на шаге k нет ни одной пары
    ближе d_до, дальше их тоже нет.
    """
    ключ = P * I + np.arange(len(P), dtype=np.int64) % I
    if ключ.max(initial=0) < 1 << 16:
        ключ = ключ.astype(np.uint16)                 # устойчивая сортировка 16-битных — поразрядная, O(n)
    порядок = np.argsort(ключ, kind="stable")
    кс = ключ[порядок]
    начала, расстояния = [], []
    for k in range(1, min(шагов, len(P) - 1) + 1):
        d = порядок[k:] - порядок[:-k]
        ок = (кс[k:] == кс[:-k]) & (d <= d_до)
        if not ок.any():
            break
        ок &= d >= d_от
        начала.append(порядок[:-k][ок])
        расстояния.append(d[ок])
    if not начала:
        return np.zeros(0, dtype=np.int64), np.zeros(0, dtype=np.int64)
    return np.concatenate(начала), np.concatenate(расстояния)


def мера(c: np.ndarray, λ: np.ndarray) -> np.ndarray:
    """Граница Чернова −ln P(X ≥ c) для X ~ Пуассон(λ): c·ln(c/λ) − c + λ при c > λ, иначе 0."""
    c = np.asarray(c, dtype=np.float64)
    λ = np.maximum(np.asarray(λ, dtype=np.float64), 1e-12)
    with np.errstate(divide="ignore", invalid="ignore"):
        s = np.where(c > λ, c * np.log(np.maximum(c, 1e-300) / λ) - c + λ, 0.0)
    return s


@dataclass
class _Клетки:
    """Клетки свёртки для конфигурации (I, N_до, длина префикса L): (N, строка начала mod N)."""
    I: int
    N_от: int
    N_до: int
    L: int
    смещение: np.ndarray = field(default=None)       # начало клеток длины N
    N: np.ndarray = field(default=None)              # N клетки
    строка: np.ndarray = field(default=None)         # строка клетки
    окон: np.ndarray = field(default=None)           # окон (начал t) в клетке
    сосед: np.ndarray = field(default=None)          # следующая строка той же N

    def __post_init__(self) -> None:
        Nы = np.arange(self.N_от, self.N_до + 1, dtype=np.int64)
        self.смещение = np.concatenate(([0], np.cumsum(Nы)))
        self.N = np.repeat(Nы, Nы)
        self.строка = np.arange(len(self.N), dtype=np.int64) - np.repeat(self.смещение[:-1], Nы)
        U = np.maximum(self.L - self.N * self.I, 0)               # начала t ∈ [0, U)
        R, остаток = U // self.I, U % self.I
        self.окон = (self.I * (R // self.N + (self.строка < R % self.N))
                     + np.where(self.строка == R % self.N, остаток, 0)).astype(np.float64)
        self.сосед = np.repeat(self.смещение[:-1], Nы) + (self.строка + 1) % self.N

    def клетка(self, начала: np.ndarray, d: np.ndarray) -> np.ndarray:
        N = d // self.I
        return self.смещение[N - self.N_от] + (начала // self.I) % N


@lru_cache(maxsize=64)
def _клетки(I: int, N_от: int, N_до: int, L: int) -> _Клетки:
    return _Клетки(I, N_от, N_до, L)


def _фон(P: np.ndarray, m: int) -> float:
    """Вероятность случайного равенства: не меньше 2^−m и вероятности совпадения значений P."""
    частоты = np.bincount(P) / len(P)
    return max(2.0 ** -m, float((частоты ** 2).sum()))


def счёт(начала: np.ndarray, d: np.ndarray, кл: _Клетки, фон: float) -> tuple[np.ndarray, np.ndarray]:
    """(мера клетки, мера длины N без свёртки) — по парам равных значений префикса."""
    c = np.bincount(кл.клетка(начала, d), minlength=len(кл.N)).astype(np.float64)
    окон = кл.окон
    if кл.I > 1:
        # Блок из I слов — I соседних начал: они в одной-двух соседних строках свёртки.
        c = c + c[кл.сосед]
        окон = окон + окон[кл.сосед]
    s = мера(c, окон * фон)
    Nы = np.arange(кл.N_от, кл.N_до + 1)
    всего = np.bincount(d // кл.I - кл.N_от, minlength=len(Nы)).astype(np.float64)
    s_N = мера(всего, (кл.L - Nы * кл.I) * фон)              # окон ≤ 0 — пар нет, мера 0
    return s, s_N


# -- опознание корней по отобранным словам -------------------------------------------------------

def слова_по_началам(с: np.ndarray, начала: np.ndarray, N: int, I: int) -> np.ndarray:
    """Слова из N символов с шагом I от каждого начала (не вышедшие за конец)."""
    начала = np.asarray(начала, dtype=np.int64)
    начала = начала[начала + (N - 1) * I < len(с)]
    return с[начала[:, None] + I * np.arange(N, dtype=np.int64)[None, :]]


def _разнообразны(слова: np.ndarray) -> bool:
    """Слова — не одно и то же и не почти нули: у кода над данными они разные."""
    if len(слова) < 4:
        return False
    различных = len({bytes(np.asarray(с, dtype=np.uint16).tobytes()) for с in слова})
    return различных >= 0.5 * len(слова) and float((слова != 0).mean()) >= 0.2


def опознать(слова: np.ndarray, m: int, многочлены: Iterable[int], отобран_j: int | None = None
             ) -> dict | None:
    """Корни слов по многочленам поля (по порядку): первый многочлен с цепочкой ≥ ПОДРЯД_ОТ корней.

    Корень — степень j, где зануляется не меньше доли КОРЕНЬ_ОТ слов и не меньше 0,8 от
    лучшей (как rs_bch.опознать). ``отобран_j`` — степень, по равенству в которой слова
    отобраны: там зануляются все — в счёт доли не идёт, но корнем остаётся и обязан входить в
    цепочку. Отвергается: k < 2 (корней подряд больше N − 2) и лишние корни вне цепочки (больше
    ЛИШНИХ_КОРНЕЙ_ДО — так зануляются вырожденные слова, а не код).
    """
    q1 = (1 << m) - 1
    N = слова.shape[1]
    j0 = None if отобран_j is None else отобран_j % q1
    for p in многочлены:
        другие = (rs_bch.значения(слова, p) == 0).mean(axis=0)
        if j0 is not None:
            другие[j0] = 0.0
        порог = max(КОРЕНЬ_ОТ, 0.8 * float(другие.max()))
        свои = np.flatnonzero(другие >= порог)
        корни = sorted(set(свои.tolist()) | ({j0} if j0 is not None else set()))
        b, подряд, шаг = rs_bch._подряд_с_шагом(корни, q1)
        корней = подряд - подряд % 2
        if подряд < ПОДРЯД_ОТ or подряд > N - 2 or len(корни) > подряд + ЛИШНИХ_КОРНЕЙ_ДО:
            continue
        if j0 is not None and not _в_цепочке(j0, b, подряд, шаг, q1):
            continue                                  # корень отбора не в цепочке — цепочка чужая
        return {"многочлен": p, "корни": корни, "fcr": b, "подряд": подряд, "корней": корней,
                "доля": float(другие[свои].mean()), "m": m, "шаг": шаг}
    return None


def _в_цепочке(j: int, b: int, подряд: int, шаг: int, q1: int) -> bool:
    """Степень j входит в цепочку β^b … β^(b+подряд−1), β = α^шаг."""
    return any((шаг * (b + i)) % q1 == j for i in range(подряд))


#: Распространённые многочлены поля сверх наименьшего примитивного: у GF(256) — 0x11D (DVB, ATSC,
#: OTN, большинство), 0x187 (CCSDS, IESS). У других полей распространённый и есть наименьший
#: (0xB, 0x13, 0x25, 0x43, 0x83, 0x211, 0x409).
ЧАСТЫЕ_МНОГОЧЛЕНЫ = {8: (0x11D, 0x187)}


def многочлены_поля(m: int, сначала: Sequence[int] = ()) -> list[int]:
    """Примитивные многочлены степени m: сперва ``сначала`` и распространённые, затем по возрастанию."""
    все = rs_bch.примитивные(m)
    порядок = [p for p in (*сначала, *ЧАСТЫЕ_МНОГОЧЛЕНЫ.get(m, ())) if p in все]
    return list(dict.fromkeys(порядок + list(все)))


