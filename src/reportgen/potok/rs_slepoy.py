@dataclass(frozen=True)
class Конфигурация:
    """Что перебирается: ступень, размер символа, битовые фазы, глубина чередования; на ступени 2 —
    ещё многочлен поля, порядок бит и базис (на ступени 1 они не важны). Фазы одной
    конфигурации считаются вместе: проверяется сперва фаза с лучшей мерой (на сдвинутой фазе
    равенство XOR частично выполняется тоже — по битам внутри символов)."""
    ступень: int
    m: int
    фазы: tuple[int, ...]
    I: int
    p: int = 0
    порядок: str = "старший"
    базис: str = "обычный"

    def подпись(self) -> str:
        ф = (f"фаза {self.фазы[0]}" if len(self.фазы) == 1
             else f"фазы {self.фазы[0]}…{self.фазы[-1]}")
        т = f"ступень {self.ступень}: символ {self.m} бит, {ф}, глубина {self.I}"
        if self.ступень == 2:
            т += f", поле 0x{self.p:X}, {self.порядок} бит первым, базис {self.базис}"
        return т


#: Популярные конфигурации ступени 2: (многочлен, порядок бит, базис) — CCSDS, IESS, 0x11D с fcr ≠ 0.
ПОПУЛЯРНЫЕ = ((0x187, "старший", "двойной"), (0x187, "старший", "обычный"), (0x11D, "старший", "обычный"))
#: То же с младшим битом первым.
ПОПУЛЯРНЫЕ_МЛАДШИЙ = ((0x11D, "младший", "обычный"), (0x187, "младший", "обычный"), (0x187, "младший", "двойной"))
#: Частые глубины чередования.
ЧАСТЫЕ_ГЛУБИНЫ = (1, 2, 4, 5, 3, 8)


def план(профиль: str = "обычно") -> list[Конфигурация]:
    """Конфигурации перебора — от частого к редкому.

    «быстро» — ступень 1 для всех размеров символа (байты — с частыми глубинами) и популярные
    конфигурации ступени 2 на частых глубинах при фазе 0; «обычно» — ещё фазы 1…7 и младший бит
    первым на ступени 2,
    редкие глубины до 16 для байтов, глубины до 8 для других размеров; «глубоко» — все
    многочлены поля, базисы и порядки бит на ступени 2, все глубины."""
    итог: list[Конфигурация] = []
    другие = [м for м in РАЗМЕРЫ if м != 8]

    def первая(ms: Iterable[int], глубины: Iterable[int]) -> None:
        for m in ms:
            for I in глубины:
                итог.append(Конфигурация(1, m, tuple(range(m)), I))

    def вторая(ms: Iterable[int], фазы: Callable[[int], tuple[int, ...]], глубины: Iterable[int],
               виды: Sequence[tuple[int | None, str, str]]) -> None:
        for m in ms:
            for p, порядок, базис in виды:
                if базис == "двойной" and m != 8:
                    continue
                for I in глубины:
                    for p_ in ([p] if p else многочлены_поля(m)):
                        итог.append(Конфигурация(2, m, фазы(m), I, p_, порядок, базис))

    первая([8], ЧАСТЫЕ_ГЛУБИНЫ)
    вторая([8], lambda m: (0,), ЧАСТЫЕ_ГЛУБИНЫ, ПОПУЛЯРНЫЕ)
    первая(другие, (1, 2) if профиль == "быстро" else (1, 2, 4))
    if профиль != "быстро":
        вторая([8], lambda m: tuple(range(1, 8)), ЧАСТЫЕ_ГЛУБИНЫ, ПОПУЛЯРНЫЕ)
        вторая([8], lambda m: tuple(range(8)), ЧАСТЫЕ_ГЛУБИНЫ, ПОПУЛЯРНЫЕ_МЛАДШИЙ)
        первая([8], [I for I in ГЛУБИНЫ if I not in ЧАСТЫЕ_ГЛУБИНЫ])
        первая(другие, (5, 3, 8))
    if профиль == "глубоко":
        первая(другие, [I for I in ГЛУБИНЫ if I not in ЧАСТЫЕ_ГЛУБИНЫ])
        вторая([8], lambda m: tuple(range(8)), [I for I in ГЛУБИНЫ if I not in ЧАСТЫЕ_ГЛУБИНЫ],
               ПОПУЛЯРНЫЕ + ПОПУЛЯРНЫЕ_МЛАДШИЙ)
        вторая([8], lambda m: tuple(range(8)), ЧАСТЫЕ_ГЛУБИНЫ,
               [(None, порядок, базис) for порядок, базис in ВИДЫ])
        вторая(другие, lambda m: tuple(range(m)), (1, 2, 4),
               [(None, "старший", "обычный"), (None, "младший", "обычный")])
    return list(dict.fromkeys(итог))


