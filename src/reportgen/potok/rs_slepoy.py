"""Код Рида — Соломона вслепую: длина слова, начало, поле и корни — прямо по потоку символов.

**Префикс.** Слово c длины N (укороченное тоже) идёт символами r_t0 … r_(t0+N−1), первый —
старшая степень: c(x) = Σ r_(t0+i)·x^(N−1−i). Тогда c(α^j) = α^(j(t0+N−1))·Σ r_u·α^(−ju) по
u = t0 … t0+N−1, и

    c(α^j) = 0  ⇔  P_j(t0 + N) = P_j(t0),   P_j(t) = Σ_(u<t) r_u·α^(−ju)  (сумма — XOR).

На границах чистых слов префикс повторяется через N — длина слова и начало находятся без знания
N заранее, а слово с ошибкой ломает только своё равенство.

**Ступень 1** (j = 0, α⁰ = 1): P_0 — просто XOR символов до t. Корень 1 есть у всех кодов с
fcr = 0 (DVB, IESS-подобные с fcr = 0, OTN, ATSC и многие другие). Этот тест не зависит ни от
многочлена поля, ни от базиса (двойной базис CCSDS), ни от порядка бит в символе — ни от какого
линейного над GF(2) отображения символов. Перебираются только размер символа m, битовая фаза и
глубина чередования I.

**Ступень 2** (корни не включают 1 — CCSDS fcr = 112, шаг 11; IESS fcr = 120): многочлен поля,
базис, порядок бит, фаза, I и выборка степеней j (каждая s-я из 2^m − 1) — так, чтобы
гарантированно попасть в корни. Порядок перебора — от частого к редкому, с бюджетом времени.

**Счёт.** Пары равных значений P на расстоянии d ≤ I·(2^m − 1) находятся сортировкой: в отрезке
длины d у случайного потока в среднем ≈ d/(I·2^m) ≤ 1 совпадение, так что пар — порядка длины
выборки, и все длины N считаются разом. Для каждой N пары сворачиваются по строке начала
(⌊t/I⌋ mod N): у истинного (N, начало) равенство выполняется у доли чистых слов, у фона — с
вероятностью 2^−m. Мера клетки — граница Чернова для пуассоновского хвоста:
S = c·ln(c/λ) − c + λ (−ln вероятности случайно набрать c при ожидании λ). На ступени 2
меры по выборке j складываются (каждая — сверх небольшого порога). Ещё считается мера всей длины
N без свёртки — для слов в кадрах с заголовками, где начала по модулю N не постоянны.

**Чередование.** Слова одного индекса чередования идут через I символов; префикс берётся по
каждому вычету по модулю I отдельно: P(t) — XOR символов u < t, u ≡ t (mod I). Равенство на
расстоянии N·I — слово одной полосы; блок из I слов занимает I соседних начал, они попадают в
одну-две соседние строки свёртки.

**Проверка.** Слова, у которых равенство выполнилось, отдаются опознанию корней
(rs_bch.значения по всем многочленам поля, порядкам бит и базисам): нужна цепочка корней ≥ 2
(корень выборки не в счёт доли — слова отобраны по нему), слова разнообразны, а затем доля
слов всей раскладки с нулевыми синдромами — не случайная.

**Снятие.** Раскладка блоков — сплошь (≥ 80 % чистых слов начинаются в тех же вычетах) или в
кадрах (период кадра F и вычеты начал блоков по модулю F); слова исправляются
(Берлекэмп — Мэсси, Ченя, Форни), выход — информационные символы (первые I·k символов блока)
в исходном виде (обратно в базис и порядок бит потока).
"""

