@dataclass
class Код:
    """Найденный код: параметры, раскладка и итог исправления."""
    m: int
    фаза: int
    I: int
    N: int
    k: int
    p: int
    fcr: int
    шаг: int
    порядок: str
    базис: str
    доля_корней: float
    ступень: int
    мера: float
    #: Начала блоков (в символах потока с этой фазой); блок — I слов с шагом I.
    блоки: np.ndarray = field(default=None, repr=False)
    сплошь: bool = True
    кадр: int = 0                          # период кадра в символах (если не сплошь)
    в_кадре: tuple[int, ...] = ()          # начала блоков в кадре (вычеты по модулю кадра)
    чистых_до: float = 0.0                 # доля слов с нулевыми синдромами до исправления
    исправлено: int = 0
    исправлено_слов: int = 0
    неисправимых: int = 0
    слов: int = 0
    данные: np.ndarray = field(default=None, repr=False)
    итог: str = ""

    @property
    def корней(self) -> int:
        return self.N - self.k

    @property
    def сдвиг(self) -> int:
        """Бит потока, с которого начинается первый блок."""
        return self.фаза + self.m * int(self.блоки[0]) if len(self.блоки) else self.фаза

    def слой(self) -> str:
        """Слой «рс N K …» — снять этот код по известным параметрам (стол, ручная обработка)."""
        т = (f"рс {self.N} {self.k} поле 0x{self.p:X} fcr {self.fcr} шаг {self.шаг} глубина {self.I} "
             f"базис {self.базис} порядок {self.порядок}")
        if self.m != 8:
            т += f" символ {self.m}"
        т += f" сдвиг {self.сдвиг}"
        if not self.сплошь and self.кадр:
            начало = int(self.блоки[0])
            т += f" кадр {self.кадр * self.m} блоки " + ",".join(
                str(((r - начало) % self.кадр) * self.m) for r in self.в_кадре)
        return т

    def ключ(self) -> tuple:
        """Один и тот же код (для сведения повторов в списке вариантов)."""
        return (self.m, self.N, self.k, self.I, self.p, self.fcr, self.шаг, self.порядок, self.базис,
                self.сдвиг % (self.m * self.N * self.I) if self.сплошь else self.сдвиг)

    def в_словарь(self) -> dict:
        """Вариант для окна поиска."""
        return {"подпись": f"RS({self.N},{self.k}) GF(2^{self.m}) 0x{self.p:X} fcr {self.fcr}"
                           + (f" шаг {self.шаг}" if self.шаг != 1 else "") + f" I={self.I}"
                           + (" двойной" if self.базис == "двойной" else "")
                           + (" младший" if self.порядок == "младший" else "")
                           + ("" if self.сплошь else f" кадр {self.кадр * self.m}"),
                "N": self.N, "k": self.k, "m": self.m, "многочлен": f"0x{self.p:X}", "fcr": self.fcr,
                "шаг": self.шаг, "глубина": self.I, "базис": self.базис, "порядок": self.порядок,
                "сдвиг": self.сдвиг, "сплошь": self.сплошь, "кадр": self.кадр * self.m,
                "чисто": round(self.чистых_до, 4), "исправлено": self.исправлено,
                "неисправимых": self.неисправимых, "слов": self.слов, "ступень": self.ступень,
                "мера": round(self.мера, 1), "слой": self.слой(), "итог": self.итог,
                "ключ": " ".join(map(str, self.ключ()))}


def _выборка(конф: Конфигурация, глубоко: bool = False) -> int:
    """Сколько символов брать для поиска: СЛОВ_НА_КЛЕТКУ слов наибольшей длины на полосу
    (глубоко — вчетверо больше: при ошибках 2·10⁻³ на ступени 2 нужно ~200 слов на полосу)."""
    N_до = (1 << конф.m) - 1
    слов = СЛОВ_НА_КЛЕТКУ[конф.ступень] * (4 if глубоко else 1)
    return int(min(ВЫБОРКА_ДО, max(ВЫБОРКА_ОТ[конф.ступень], слов * N_до * конф.I)))


def _степени_j(m: int, глубоко: bool) -> list[int]:
    """Выборка степеней j для ступени 2 (без j = 0 — это ступень 1): при m ≤ 6 — все, иначе
    каждая s-я: s = 8 при m ≤ 8 (32 степени из 255: у кода с 2t ≥ 16 корнями подряд попадает
    ≥ 2), s = 32 при m > 8; глубоко — каждая вторая."""
    q1 = (1 << m) - 1
    if m <= 6:
        return list(range(1, q1))
    шаг = 2 if глубоко else (8 if m <= 8 else 32)
    return [j for j in range(0, q1, шаг) if j] + ([1] if шаг > 1 else [])


@dataclass
class _Кандидат:
    s: float
    фаза: int
    N: int
    строка: int
    j: int
    начала: np.ndarray
    без_свёртки: bool = False


def _кандидаты(с: np.ndarray, конф: Конфигурация, фаза: int, глубоко: bool,
               стоп: Callable[[], bool] | None) -> list[_Кандидат]:
    """Лучшие клетки (N, строка начала) одной фазы с мерой ≥ МЕРА_ОТ."""
    m, I = конф.m, конф.I
    N_до = min((1 << m) - 1, len(с) // I // 4)
    if N_до < N_ОТ:
        return []
    j_список = [0] if конф.ступень == 1 else _степени_j(m, глубоко)
    кл: _Клетки | None = None
    сумма = сумма_N = лучшая_j_мера = лучший_j = None
    пары_по_j: dict[int, tuple[np.ndarray, np.ndarray]] = {}
    for j in j_список:
        if стоп is not None and стоп():
            return []
        P = префикс(с, I, j, конф.p if j else None)
        if кл is None:
            кл = _клетки(I, N_ОТ, N_до, len(P))
            сумма = np.zeros(len(кл.N))
            лучшая_j_мера = np.zeros(len(кл.N))
            лучший_j = np.zeros(len(кл.N), dtype=np.int64)
            сумма_N = np.zeros(N_до - N_ОТ + 1)
        начала, d = пары(P, I, N_ОТ * I, N_до * I)
        if not len(d):
            continue
        s, s_N = счёт(начала, d, кл, _фон(P, m))
        пары_по_j[j] = (начала, d)
        if конф.ступень == 1:
            сумма, сумма_N = s, s_N
        else:
            сумма += np.maximum(s - МЕРА_J_ОТ, 0.0)
            сумма_N += np.maximum(s_N - МЕРА_J_ОТ, 0.0)
        лучше = s > лучшая_j_мера
        лучшая_j_мера[лучше] = s[лучше]
        лучший_j[лучше] = j
    if кл is None:
        return []
    итог: list[_Кандидат] = []
    for i in np.argsort(-сумма)[:КАНДИДАТОВ]:
        if сумма[i] < МЕРА_ОТ:
            break
        N, строка, j = int(кл.N[i]), int(кл.строка[i]), int(лучший_j[i])
        начала, d = пары_по_j[j]
        свои = начала[d == N * I]
        строки = (свои // I) % N
        отбор = свои[(строки == строка) | ((строки == (строка + 1) % N) & (I > 1))]
        итог.append(_Кандидат(float(сумма[i]), фаза, N, строка, j, отбор))
    # Слова в кадрах с заголовками: начала по модулю N не постоянны, но повторяются с периодом
    # кадра F. Для лучших длин без свёртки — F по частой разности начал, свёртка по модулю F.
    for i_N in np.argsort(-сумма_N)[:КАНДИДАТОВ]:
        if сумма_N[i_N] < МЕРА_N_ОТ:
            break
        N = N_ОТ + int(i_N)
        j = max(пары_по_j, key=lambda j_: int((пары_по_j[j_][1] == N * I).sum()))
        начала, d = пары_по_j[j]
        к = в_кадрах(np.sort(начала[d == N * I]), N, I)
        if к is not None and к[0] >= МЕРА_ОТ and (not итог or к[0] > итог[0].s):
            итог.insert(0, _Кандидат(к[0], фаза, N, -1, j, к[1], без_свёртки=True))
    return итог


def в_кадрах(начала: np.ndarray, N: int, I: int, соседей: int = 8) -> tuple[float, np.ndarray, int] | None:
    """Начала равенств длины N, повторяющиеся с периодом кадра: (мера, начала в лучших вычетах, F).

    F — самая частая разность между началами (до ``соседей`` следующих) больше N·I; начала
    сворачиваются по модулю F, мера — у I соседних вычетов против равномерного фона.
    """
    if len(начала) < 6:
        return None
    разности = np.concatenate([начала[k:] - начала[:-k] for k in range(1, min(соседей, len(начала) - 1) + 1)])
    разности = разности[разности > N * I]
    if not len(разности):
        return None
    F = int(np.bincount(разности).argmax())
    h = np.bincount(начала % F, minlength=F)
    окно = h.copy()
    for i in range(1, I):
        окно += np.roll(h, -i)
    r = int(np.argmax(окно))
    # Период выбран по тем же началам — фон берётся с запасом: как если бы вычетов было F/(2I).
    λ = len(начала) * I / F * 2.0
    свои = начала[(начала - r) % F < I]
    return float(мера(np.array([окно[r]]), np.array([λ]))[0]), свои, F


def _равномерно(массив: np.ndarray, сколько: int) -> np.ndarray:
    if len(массив) <= сколько:
        return массив
    return массив[np.linspace(0, len(массив) - 1, сколько).astype(np.int64)]


def _проверить(биты: np.ndarray, конф: Конфигурация, канд: _Кандидат, глубоко: bool
               ) -> tuple[dict, str, str] | None:
    """Опознание корней по отобранным словам: (код, порядок, базис) или None.

    На ступени 1 порядок бит, базис и поле неизвестны — перебираются (у отобранных слов
    корень 1 — по отбору); на ступени 2 — те, что у конфигурации. Снаружи — многочлены от
    частого к редкому, внутри — порядок бит и базис: младший бит первым при многочлене p —
    то же, что старший при обратном многочлене (разворот бит — умножение на постоянную в поле
    обратного многочлена), и берётся описание с распространённым многочленом.
    """
    m, I, N = конф.m, конф.I, канд.N
    if конф.ступень == 2:
        виды = [(конф.порядок, конф.базис)]
        многочлены = [конф.p]
    else:
        виды = [в for в in ВИДЫ if m == 8 or в[1] == "обычный"]
        многочлены = многочлены_поля(m)
        if not глубоко and m == 8:
            многочлены = многочлены[:8]
    начала = _равномерно(np.unique(канд.начала), СЛОВ_ОПОЗНАНИЯ)
    слова_вида = {}
    for порядок, базис in виды:
        слова = слова_по_началам(символы(биты, m, канд.фаза, порядок, базис), начала, N, I)
        if not _разнообразны(слова):
            return None
        слова_вида[порядок, базис] = слова
    for p in многочлены:
        for вид, слова in слова_вида.items():
            п = опознать(слова, m, [p], канд.j)
            if п is not None:
                return (п, *вид)
    return None


