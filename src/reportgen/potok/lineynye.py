"""Кодирование в линии: NRZI, 4B/5B, 8B/10B.

То, что стоит сразу за демодулятором: код, который обеспечивает переходы
для синхронизации и баланс нулей и единиц. Каждый узнаётся по свойству,
которое у него есть всегда и которого почти не бывает у случайного ряда:

- **4B/5B** — из 32 пятибитовых комбинаций разрешены 16 данных и несколько
  служебных; при верном выравнивании все символы — разрешённые;
- **8B/10B** — в каждой десятке от 4 до 6 единиц, серии не длиннее 5,
  запятая K28.5 (0011111010 / 1100000101) стоит на границе символа.

NRZI (дифференциальное кодирование: 1 — есть переход) по самому ряду не
узнать — любой ряд можно так «декодировать». Его находит скремблер как
«1 + x^-1» и — в переборе гипотез — проверка следующим уровнем.
"""

from __future__ import annotations

from collections import Counter

import numpy as np

from .nahodka import Находка

#: Выборка начала для опознания кода (выравнивание, доля символов); данные — по всему ряду.
ВЫБОРКА = 1 << 20


def nrzi(биты: np.ndarray) -> np.ndarray:
    """Декодирование NRZI / дифференциального: 1 — есть переход."""
    return np.concatenate([[0], (биты[1:] != биты[:-1]).astype(np.uint8)])


# -- 4B/5B -------------------------------------------------------------------------------

#: Таблица 4B/5B (FDDI, 100BASE-X): полубайт → пятибитовый символ.
ДАННЫЕ_4B5B = (0b11110, 0b01001, 0b10100, 0b10101, 0b01010, 0b01011, 0b01110, 0b01111,
               0b10010, 0b10011, 0b10110, 0b10111, 0b11010, 0b11011, 0b11100, 0b11101)
#: Служебные: I (пауза), J, K (начало), T, R (конец), H, Q.
СЛУЖЕБНЫЕ_4B5B = {0b11111: "I", 0b11000: "J", 0b10001: "K", 0b01101: "T", 0b00111: "R",
                  0b00100: "H", 0b00000: "Q"}


def _символы(биты: np.ndarray, ширина: int, сдвиг: int) -> np.ndarray:
    ряд = np.asarray(биты[сдвиг:], dtype=np.uint8)
    сколько = len(ряд) // ширина
    столбцы = ряд[:сколько * ширина].reshape(сколько, ширина)
    итог = np.zeros(сколько, dtype=np.uint16)             # по столбцу — без промежуточного int64 на каждый бит
    for j in range(ширина):
        итог = (итог << 1) | столбцы[:, j]
    return итог


#: Символов за раз при декодировании всего ряда (память — на кусок).
СИМВОЛОВ_ЗА_РАЗ = 1 << 22


def декодировать(биты: np.ndarray, ширина: int, сдвиг: int, таблица: np.ndarray, бит: int
                 ) -> tuple[np.ndarray, np.ndarray]:
    """Весь ряд символами по ``ширина`` бит с бита ``сдвиг`` через ``таблица`` (символ → значение, −1 —
    выбросить): биты значений (по ``бит`` на символ, старший первым) и счёт каждого символа."""
    сколько = (len(биты) - сдвиг) // ширина if len(биты) > сдвиг else 0
    счёт = np.zeros(1 << ширина, dtype=np.int64)
    части = []
    разряды = np.arange(бит - 1, -1, -1, dtype=np.int16)
    for a in range(0, сколько, СИМВОЛОВ_ЗА_РАЗ):
        б = min(сколько, a + СИМВОЛОВ_ЗА_РАЗ)
        символы = _символы(биты[сдвиг + a * ширина:сдвиг + б * ширина], ширина, 0)
        счёт += np.bincount(символы, minlength=1 << ширина)
        значения = таблица[символы]
        значения = значения[значения >= 0].astype(np.int16)
        части.append(((значения[:, None] >> разряды) & 1).astype(np.uint8).reshape(-1))
    return (np.concatenate(части) if части else np.zeros(0, dtype=np.uint8)), счёт


def _выравнивание_4b5b(выборка: np.ndarray) -> tuple[float, int, np.ndarray]:
    """Выравнивание с наибольшей долей разрешённых символов: (доля, сдвиг, символы выборки)."""
    разрешённые = np.zeros(32, dtype=bool)
    разрешённые[list(ДАННЫЕ_4B5B)] = True
    разрешённые[list(СЛУЖЕБНЫЕ_4B5B)] = True
    лучшее = None
    for сдвиг in range(5):
        символы = _символы(выборка, 5, сдвиг)
        доля = float(разрешённые[символы].mean()) if len(символы) else 0.0
        if лучшее is None or доля > лучшее[0]:
            лучшее = (доля, сдвиг, символы)
    return лучшее


def код_4b5b(биты: np.ndarray) -> Находка | None:
    выборка = биты[:ВЫБОРКА]
    доля, сдвиг, символы = _выравнивание_4b5b(выборка)
    if len(символы) < 1000 or доля < 0.99:
        return None
    # Случайный ряд даёт 23/32 ≈ 72 % разрешённых — порог 99 % от него далёк.
    # Выравнивание и доля — по выборке, данные — по всему ряду (таблицей, кусками).
    таблица = np.full(32, -1, dtype=np.int16)
    таблица[list(ДАННЫЕ_4B5B)] = np.arange(16)
    биты_данных, счёт = декодировать(биты, 5, сдвиг, таблица, 4)
    служебные = Counter({СЛУЖЕБНЫЕ_4B5B[с]: int(счёт[с]) for с in СЛУЖЕБНЫЕ_4B5B if счёт[с]})
    return Находка(
        уровень="линия", что="код 4B/5B", уверенность=(доля - 0.72) / 0.28,
        мера=f"разрешённых символов {доля * 100:.2f} % при выравнивании с бита {сдвиг} "
             f"(у случайного ряда — 72 %)",
        подробно=["служебные символы: " + (", ".join(f"{к}×{с}" for к, с in
                                                        служебные.most_common()) or "нет"),
                  "данные — полубайты по таблице 4B/5B, служебные символы выброшены"],
        дальше=биты_данных.reshape(-1).astype(np.uint8), вид_дальше="биты", свойства={"слой": "4b5b"})


# -- 8B/10B ------------------------------------------------------------------------------

K28_5 = (0b0011111010, 0b1100000101)

#: 5b/6b, RD− (abcdei), индекс — EDCBA.
_6B = (0b100111, 0b011101, 0b101101, 0b110001, 0b110101, 0b101001, 0b011001, 0b111000,
       0b111001, 0b100101, 0b010101, 0b110100, 0b001101, 0b101100, 0b011100, 0b010111,
       0b011011, 0b100011, 0b010011, 0b110010, 0b001011, 0b101010, 0b011010, 0b111010,
       0b110011, 0b100110, 0b010110, 0b110110, 0b001110, 0b101110, 0b011110, 0b101011)
#: 3b/4b, RD− (fghj), индекс — HGF; 7 — первичный вариант P7.
_4B = (0b1011, 0b1001, 0b0101, 0b1100, 0b1101, 0b1010, 0b0110, 0b1110)
_4B_A7 = 0b0111


def _таблица_8b10b() -> dict[int, int]:
    """10-битовый символ → байт, для обоих знаков текущей несбалансированности.

    RD+ для несбалансированных подблоков — дополнение RD−; у D.7 (111000) и
    D.x.3 (1100) дополнения тоже берутся (так устроен код). Самопроверка по
    потоку (доля декодируемых символов) страхует от ошибки в таблице.
    """
    таблица: dict[int, int] = {}
    for x in range(32):
        for y in range(8):
            for rd in (0, 1):
                шесть = _6B[x]
                if rd:
                    if bin(шесть).count("1") != 3 or шесть == 0b111000:
                        шесть ^= 0b111111
                четыре = _4B[y]
                if y == 7 and ((rd == 0 and x in (17, 18, 20)) or (rd == 1 and x in (11, 13, 14))):
                    четыре = _4B_A7
                # Знак после 6b-подблока определяет, какой вариант 4b берётся.
                после = rd ^ (bin(шесть).count("1") != 3)
                if после:
                    if bin(четыре).count("1") != 2 or четыре == 0b1100:
                        четыре ^= 0b1111
                таблица[(шесть << 4) | четыре] = (y << 5) | x
    return таблица


ТАБЛИЦА_8B10B = _таблица_8b10b()


def _выравнивание_8b10b(выборка: np.ndarray) -> tuple[float, int, int, np.ndarray] | None:
    """Выравнивание с наибольшим числом запятых K28.5 (затем — балансом единиц): (баланс, запятых, сдвиг,
    символы выборки); None — выборка коротка."""
    лучшее = None
    for сдвиг in range(10):
        символы = _символы(выборка, 10, сдвиг)
        if len(символы) < 500:
            return None
        единиц = np.array([bin(с).count("1") for с in символы[:20000].tolist()])
        баланс = float(np.mean((единиц >= 4) & (единиц <= 6)))
        запятых = int(np.isin(символы, K28_5).sum())
        if лучшее is None or (запятых, баланс) > (лучшее[1], лучшее[0]):
            лучшее = (баланс, запятых, сдвиг, символы)
    return лучшее


def выравнивание(биты: np.ndarray, ширина: int) -> int | None:
    """С какого бита идут символы кода 4B/5B (ширина 5) или 8B/10B (10) — по выборке начала, как у
    ``код_4b5b``/``код_8b10b``; None — кода не видно."""
    выборка = биты[:ВЫБОРКА]
    if ширина == 5:
        доля, сдвиг, символы = _выравнивание_4b5b(выборка)
        return сдвиг if len(символы) >= 1000 and доля >= 0.99 else None
    лучшее = _выравнивание_8b10b(выборка)
    return лучшее[2] if лучшее is not None and лучшее[0] >= 0.99 and лучшее[1] >= 3 else None


def код_8b10b(биты: np.ndarray) -> Находка | None:
    выборка = биты[:ВЫБОРКА]
    лучшее = _выравнивание_8b10b(выборка)
    if лучшее is None:
        return None
    баланс, запятых, сдвиг, символы = лучшее
    if баланс < 0.99 or запятых < 3:
        return None
    декодируемых = float(np.mean([с in ТАБЛИЦА_8B10B or с in K28_5 for с in символы[:20000].tolist()]))
    подробно = [f"символы по 10 бит с бита {сдвиг}; запятых K28.5 на границе символа: "
                f"{запятых}; символов с 4–6 единицами {баланс * 100:.2f} %"]
    дальше = None
    if декодируемых >= 0.99:
        # Выравнивание и доля — по выборке, данные — по всему ряду (таблицей, кусками).
        таблица = np.full(1024, -1, dtype=np.int16)
        таблица[list(ТАБЛИЦА_8B10B)] = list(ТАБЛИЦА_8B10B.values())
        дальше, _ = декодировать(биты, 10, сдвиг, таблица, 8)
        подробно.append(f"декодировано по таблице 8B/10B: {декодируемых * 100:.2f} % "
                        f"символов (служебные K-символы выброшены)")
    else:
        подробно.append(f"по таблице декодируются лишь {декодируемых * 100:.1f} % символов — "
                        f"данные не извлекаются (возможно, другая разновидность кода)")
    return Находка(
        уровень="линия", что="код 8B/10B", уверенность=баланс,
        мера=f"запятая K28.5 на границе символа {запятых} раз; баланс единиц соблюдён в "
             f"{баланс * 100:.2f} % символов (у случайного ряда — около 66 %)",
        подробно=подробно, дальше=дальше, вид_дальше="биты" if дальше is not None else "",
        свойства={"слой": "8b10b"} if дальше is not None else {})


def закодировать_8b10b(байты: bytes, запятая_каждые: int = 64) -> np.ndarray:
    """Кодер 8B/10B (для проверок): те же правила, что у таблицы декодера."""
    rd = 0                                   # 0 — RD−, 1 — RD+
    символы: list[int] = []
    for номер, байт in enumerate(байты):
        if номер % запятая_каждые == 0:
            символы.append(K28_5[rd])
            rd ^= 1                          # у K28.5 оба подблока несбалансированы
        x, y = байт & 31, байт >> 5
        шесть = _6B[x]
        if rd and (bin(шесть).count("1") != 3 or шесть == 0b111000):
            шесть ^= 0b111111
        rd ^= bin(шесть).count("1") != 3
        четыре = _4B[y]
        if y == 7 and ((rd == 0 and x in (17, 18, 20)) or (rd == 1 and x in (11, 13, 14))):
            четыре = _4B_A7
        if rd and (bin(четыре).count("1") != 2 or четыре == 0b1100):
            четыре ^= 0b1111
        rd ^= bin(четыре).count("1") != 2
        символы.append((шесть << 4) | четыре)
    return np.array([(с >> (9 - i)) & 1 for с in символы for i in range(10)], dtype=np.uint8)


def найти(биты: np.ndarray) -> Находка | None:
    return код_4b5b(биты) or код_8b10b(биты)
