def проверить(биты) -> dict[str, Any]:
    """Все тесты над последовательностью. У каждого — p-значения, пройден ли, хватило ли бит.

    Тест на короче рекомендованного NIST всё равно считается, но помечается:
    на коротком ряду он слабее, и его «пройден» мало что значит.
    """
    b = _биты(биты)
    n = len(b)
    итог = []
    for ключ, имя, наименьшая, функция in ТЕСТЫ:
        запись = {"ключ": ключ, "имя": имя, "наименьшая": наименьшая, "мало": n < наименьшая}
        try:
            значение = функция(b) if n else None
        except (ValueError, ZeroDivisionError, OverflowError):
            значение = None
        if значение is None:
            запись.update(p=[], годен=None)
        else:
            p = [float(v) for v in (значение if isinstance(значение, (tuple, list)) else [значение])]
            запись.update(p=[round(v, 6) for v in p], годен=all(v >= УРОВЕНЬ for v in p))
        итог.append(запись)
    пройдено = sum(1 for з in итог if з["годен"])
    проверено = sum(1 for з in итог if з["годен"] is not None)
    return {"бит": n, "единиц": int(b.sum()), "тесты": итог, "пройдено": пройдено, "проверено": проверено,
            "ent": ent(np.packbits(b).tobytes()) if n >= 8 else None}
