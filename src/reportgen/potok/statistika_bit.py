"""Статистика битовой последовательности: тесты NIST SP 800-22 и характеристики ENT.

Структурно-статистический анализ начинается с вопроса «случайна ли
последовательность и чем именно не случайна»: перекос единиц, серии,
повторы шаблонов, линейная сложность, периодичность в спектре. Здесь —
тесты из набора NIST SP 800-22 rev. 1a и характеристики программы ENT
(Fourmilab): энтропия, χ², среднее, коэффициент последовательной корреляции.

Вычисления — перевод открытых эталонных реализаций: NIST Statistical Test
Suite (sts/src/*.c) и ENT (randtest.c) — вплоть до целочисленных делений и
таблиц вероятностей, взятых из этих исходников. Тесты сверяются с самими
эталонами, собранными из исходников: p-значения совпадают до 1e-9.

p-значение — вероятность получить такое или ещё более «неслучайное» значение
у истинно случайной последовательности; меньше 0,01 — тест не пройден
(уровень значимости NIST).
"""

from __future__ import annotations

import math
from collections.abc import Sequence
from typing import Any

import numpy as np

#: Уровень значимости NIST SP 800-22 (ALPHA в defs.h).
УРОВЕНЬ = 0.01

_MACHEP = 1.11022302462515654042e-16
_MAXLOG = 7.09782712893383996732224e2
_BIG = 4.503599627370496e15
_BIGINV = 2.22044604925031308085e-16


def igamc(a: float, x: float) -> float:
    """Дополнительная неполная гамма-функция Q(a, x) — как cephes_igamc в NIST STS."""
    if x <= 0 or a <= 0:
        return 1.0
    if x < 1.0 or x < a:
        return 1.0 - igam(a, x)
    ax = a * math.log(x) - x - math.lgamma(a)
    if ax < -_MAXLOG:
        return 0.0
    ax = math.exp(ax)
    y = 1.0 - a
    z = x + y + 1.0
    c = 0.0
    pkm2, qkm2 = 1.0, x
    pkm1, qkm1 = x + 1.0, z * x
    ответ = pkm1 / qkm1
    while True:
        c += 1.0
        y += 1.0
        z += 2.0
        yc = y * c
        pk = pkm1 * z - pkm2 * yc
        qk = qkm1 * z - qkm2 * yc
        if qk != 0:
            r = pk / qk
            t = abs((ответ - r) / r)
            ответ = r
        else:
            t = 1.0
        pkm2, pkm1, qkm2, qkm1 = pkm1, pk, qkm1, qk
        if abs(pk) > _BIG:
            pkm2 *= _BIGINV
            pkm1 *= _BIGINV
            qkm2 *= _BIGINV
            qkm1 *= _BIGINV
        if t <= _MACHEP:
            return ответ * ax


def igam(a: float, x: float) -> float:
    """Неполная гамма-функция P(a, x) — как cephes_igam."""
    if x <= 0 or a <= 0:
        return 0.0
    if x > 1.0 and x > a:
        return 1.0 - igamc(a, x)
    ax = a * math.log(x) - x - math.lgamma(a)
    if ax < -_MAXLOG:
        return 0.0
    ax = math.exp(ax)
    r, c, ответ = a, 1.0, 1.0
    while True:
        r += 1.0
        c *= x / r
        ответ += c
        if c / ответ <= _MACHEP:
            return ответ * ax / a


def _нормальное(x: float) -> float:
    """Функция стандартного нормального распределения — как cephes_normal."""
    return 0.5 * (1 + math.erf(x / math.sqrt(2)))


def _делить(a: int, b: int) -> int:
    """Целочисленное деление с отбрасыванием дробной части — как «/» в C (к нулю)."""
    q = abs(a) // abs(b)
    return q if (a >= 0) == (b > 0) else -q


def _биты(биты: Sequence[int] | np.ndarray) -> np.ndarray:
    return np.asarray(биты, dtype=np.uint8) & 1


# -- тесты NIST SP 800-22 --------------------------------------------------------------

def частотный(биты) -> float:
    """2.1 Частотный (monobit): доля единиц около половины."""
    b = _биты(биты)
    n = len(b)
    s = abs(2 * int(b.sum()) - n) / math.sqrt(n)
    return math.erfc(s / math.sqrt(2))


def частотный_в_блоках(биты, M: int = 128) -> float:
    """2.2 Частотный в блоках по M бит."""
    b = _биты(биты)
    N = len(b) // M
    доли = b[:N * M].reshape(N, M).sum(axis=1) / M
    хи = 4.0 * M * float(((доли - 0.5) ** 2).sum())
    return igamc(N / 2.0, хи / 2.0)


def _суммы_p(n: int, z: int) -> float:
    сумма1 = 0.0
    for k in range(_делить(_делить(-n, z) + 1, 4), _делить(_делить(n, z) - 1, 4) + 1):
        сумма1 += _нормальное(((4 * k + 1) * z) / math.sqrt(n)) - _нормальное(((4 * k - 1) * z) / math.sqrt(n))
    сумма2 = 0.0
    for k in range(_делить(_делить(-n, z) - 3, 4), _делить(_делить(n, z) - 1, 4) + 1):
        сумма2 += _нормальное(((4 * k + 3) * z) / math.sqrt(n)) - _нормальное(((4 * k + 1) * z) / math.sqrt(n))
    return 1.0 - сумма1 + сумма2


def кумулятивные_суммы(биты) -> tuple[float, float]:
    """2.13 Кумулятивные суммы: вперёд и назад."""
    b = _биты(биты)
    n = len(b)
    S = np.cumsum(2 * b.astype(np.int64) - 1)
    вверх, вниз = max(0, int(S.max())), min(0, int(S.min()))
    z = max(вверх, -вниз)
    обратно = max(вверх - int(S[-1]), int(S[-1]) - вниз)
    return _суммы_p(n, z), _суммы_p(n, обратно)


def серии(биты) -> float:
    """2.3 Серии: число смен 0↔1. При перекосе единиц больше 2/√n — сразу 0 (предусловие теста)."""
    b = _биты(биты)
    n = len(b)
    pi = float(b.sum()) / n
    if abs(pi - 0.5) > 2.0 / math.sqrt(n):
        return 0.0
    V = 1 + int(np.count_nonzero(b[1:] != b[:-1]))
    return math.erfc(abs(V - 2.0 * n * pi * (1 - pi)) / (2.0 * pi * (1 - pi) * math.sqrt(2 * n)))


#: Длиннейшая серия единиц: (наименьшее n, M, границы V, вероятности π) — таблицы из longestRunOfOnes.c.
_ДЛИННЕЙШАЯ = (
    (750000, 10000, (10, 11, 12, 13, 14, 15, 16), (0.0882, 0.2092, 0.2483, 0.1933, 0.1208, 0.0675, 0.0727)),
    (6272, 128, (4, 5, 6, 7, 8, 9), (0.1174035788, 0.242955959, 0.249363483, 0.17517706, 0.102701071, 0.112398847)),
    (128, 8, (1, 2, 3, 4), (0.21484375, 0.3671875, 0.23046875, 0.1875)),
)


def длиннейшая_серия(биты) -> float | None:
    """2.4 Длиннейшая серия единиц в блоке. None — меньше 128 бит."""
    b = _биты(биты)
    n = len(b)
    параметры = next((п for п in _ДЛИННЕЙШАЯ if n >= п[0]), None)
    if параметры is None:
        return None
    _, M, V, pi = параметры
    K = len(V) - 1
    N = n // M
    блоки = b[:N * M].reshape(N, M)
    # Длиннейшая серия единиц в каждом блоке: по перепадам с нулями по краям.
    края = np.diff(np.concatenate([np.zeros((N, 1), np.int8), блоки.astype(np.int8), np.zeros((N, 1), np.int8)], axis=1), axis=1)
    длиннейшие = np.zeros(N, dtype=np.int64)
    for i in range(N):
        начала, концы = np.flatnonzero(края[i] == 1), np.flatnonzero(края[i] == -1)
        if len(начала):
            длиннейшие[i] = int((концы - начала).max())
    nu = [0] * (K + 1)
    for v in длиннейшие:
        if v < V[0]:
            nu[0] += 1
        for j in range(K + 1):
            if v == V[j]:
                nu[j] += 1
        if v > V[K]:
            nu[K] += 1
    хи = sum((nu[i] - N * pi[i]) ** 2 / (N * pi[i]) for i in range(K + 1))
    return igamc(K / 2.0, хи / 2.0)


def _ранг_gf2(строки: list[int]) -> int:
    ранг = 0
    строки = list(строки)
    for бит in range(31, -1, -1):
        опора = next((i for i in range(ранг, len(строки)) if строки[i] >> бит & 1), None)
        if опора is None:
            continue
        строки[ранг], строки[опора] = строки[опора], строки[ранг]
        for i in range(len(строки)):
            if i != ранг and строки[i] >> бит & 1:
                строки[i] ^= строки[ранг]
        ранг += 1
    return ранг


def ранг_матриц(биты) -> float | None:
    """2.5 Ранг двоичных матриц 32×32. None — ни одной матрицы."""
    b = _биты(биты)
    N = len(b) // 1024
    if not N:
        return None

    def вероятность(r: int) -> float:
        произведение = 1.0
        for i in range(r):
            произведение *= ((1.0 - 2.0 ** (i - 32)) ** 2) / (1.0 - 2.0 ** (i - r))
        return 2.0 ** (r * (64 - r) - 1024) * произведение

    p32, p31 = вероятность(32), вероятность(31)
    p30 = 1 - (p32 + p31)
    строки = np.packbits(b[:N * 1024].reshape(N * 32, 32), axis=1).view(">u4").reshape(N, 32)
    ранги = [_ранг_gf2([int(x) for x in м]) for м in строки]
    F32, F31 = ранги.count(32), ранги.count(31)
    F30 = N - (F32 + F31)
    хи = (F32 - N * p32) ** 2 / (N * p32) + (F31 - N * p31) ** 2 / (N * p31) + (F30 - N * p30) ** 2 / (N * p30)
    return math.exp(-хи / 2.0)


def спектральный(биты) -> float:
    """2.6 Дискретное преобразование Фурье: доля пиков ниже порога √(ln(1/0,05)·n)."""
    b = _биты(биты)
    n = len(b)
    модули = np.abs(np.fft.rfft(2.0 * b - 1.0))
    порог = math.sqrt(2.995732274 * n)
    ниже = int(np.count_nonzero(модули[:n // 2] < порог))
    d = (ниже - 0.95 * n / 2.0) / math.sqrt(n / 4.0 * 0.95 * 0.05)
    return math.erfc(abs(d) / math.sqrt(2.0))


def перекрывающиеся_шаблоны(биты, m: int = 9) -> float | None:
    """2.8 Перекрывающиеся шаблоны из m единиц в блоках по 1032 бита."""
    b = _биты(биты)
    M, K = 1032, 5
    N = len(b) // M
    if not N:
        return None
    lam = (M - m + 1) / 2.0 ** m
    eta = lam / 2.0
    pi = []
    for u in range(K):
        if u == 0:
            pi.append(math.exp(-eta))
        else:
            pi.append(sum(math.exp(-eta - u * math.log(2) + l * math.log(eta) - math.lgamma(l + 1) + math.lgamma(u)
                                   - math.lgamma(l) - math.lgamma(u - l + 1)) for l in range(1, u + 1)))
    pi.append(1 - sum(pi))
    блоки = b[:N * M].reshape(N, M).astype(np.int32)
    окна = np.lib.stride_tricks.sliding_window_view(блоки, m, axis=1).sum(axis=2)
    совпадений = (окна == m).sum(axis=1)
    nu = [int(np.count_nonzero(совпадений == i)) for i in range(K)] + [int(np.count_nonzero(совпадений > 4))]
    хи = sum((nu[i] - N * pi[i]) ** 2 / (N * pi[i]) for i in range(K + 1))
    return igamc(K / 2.0, хи / 2.0)


#: Универсальный тест Маурера: ожидание и дисперсия по L — таблицы из universal.c.
_МАУРЕР_ОЖИДАНИЕ = (0, 0, 0, 0, 0, 0, 5.2177052, 6.1962507, 7.1836656, 8.1764248, 9.1723243, 10.170032,
                    11.168765, 12.168070, 13.167693, 14.167488, 15.167379)
_МАУРЕР_ДИСПЕРСИЯ = (0, 0, 0, 0, 0, 0, 2.954, 3.125, 3.238, 3.311, 3.356, 3.384, 3.401, 3.410, 3.416, 3.419, 3.421)
_МАУРЕР_L = ((1059061760, 16), (496435200, 15), (231669760, 14), (107560960, 13), (49643520, 12),
             (22753280, 11), (10342400, 10), (4654080, 9), (2068480, 8), (904960, 7), (387840, 6))


def универсальный(биты) -> float | None:
    """2.9 Универсальный тест Маурера (сжимаемость). None — меньше 387 840 бит."""
    b = _биты(биты)
    n = len(b)
    L = next((l for граница, l in _МАУРЕР_L if n >= граница), 5)
    if L < 6:
        return None
    Q = 10 * 2 ** L
    K = n // L - Q
    c = 0.7 - 0.8 / L + (4 + 32 / L) * K ** (-3 / L) / 15
    sigma = c * math.sqrt(_МАУРЕР_ДИСПЕРСИЯ[L] / K)
    слова = b[:(Q + K) * L].reshape(Q + K, L).astype(np.int64) @ (1 << np.arange(L - 1, -1, -1))
    # Таблица: последний номер блока (с 1), где встретилось слово; сначала — первые Q блоков.
    последний = np.zeros(2 ** L, dtype=np.int64)
    np.maximum.at(последний, слова[:Q], np.arange(1, Q + 1))   # при повторах — последний номер
    сумма = 0.0
    for i, с in enumerate(слова[Q:].tolist(), start=Q + 1):
        сумма += math.log(i - int(последний[с])) / math.log(2)
        последний[с] = i
    phi = сумма / K
    return math.erfc(abs(phi - _МАУРЕР_ОЖИДАНИЕ[L]) / (math.sqrt(2) * sigma))


def _частоты_слов(b: np.ndarray, m: int) -> np.ndarray:
    """Частоты всех m-битовых слов по кругу (последовательность замкнута в кольцо)."""
    n = len(b)
    if m <= 0:
        return np.zeros(0, dtype=np.int64)
    кольцо = np.concatenate([b, b[:m - 1]]).astype(np.int64)
    слова = np.zeros(n, dtype=np.int64)
    for j in range(m):
        слова = (слова << 1) | кольцо[j:j + n]
    return np.bincount(слова, minlength=2 ** m)


def приближённая_энтропия(биты, m: int = 10) -> float:
    """2.12 Приближённая энтропия: частоты m- и (m+1)-битовых слов по кругу."""
    b = _биты(биты)
    n = len(b)
    ApEn = []
    for размер in (m, m + 1):
        if размер == 0:
            ApEn.append(0.0)
            continue
        P = _частоты_слов(b, размер)
        P = P[P > 0]
        ApEn.append(float((P * np.log(P / n)).sum()) / n)
    apen = ApEn[0] - ApEn[1]
    хи = 2.0 * n * (math.log(2) - apen)
    return igamc(2.0 ** (m - 1), хи / 2.0)


def _psi2(b: np.ndarray, m: int) -> float:
    if m in (0, -1):
        return 0.0
    n = len(b)
    P = _частоты_слов(b, m).astype(np.float64)
    return float((P ** 2).sum()) * 2.0 ** m / n - n


def серийный(биты, m: int = 16) -> tuple[float, float]:
    """2.11 Серийный: равномерность m-битовых слов (две статистики ∇ψ² и ∇²ψ²)."""
    b = _биты(биты)
    п0, п1, п2 = _psi2(b, m), _psi2(b, m - 1), _psi2(b, m - 2)
    return igamc(2.0 ** (m - 1) / 2, (п0 - п1) / 2.0), igamc(2.0 ** (m - 2) / 2, (п0 - 2.0 * п1 + п2) / 2.0)


def линейная_сложность_блока(биты) -> int:
    """Линейная сложность (Берлекэмп — Мэсси над GF(2)): длина кратчайшего РСЛОС."""
    c, bb, L, m = 1, 1, 0, -1
    история = 0
    for N_, бит in enumerate(биты):
        история = (история << 1) | int(бит)
        # Невязка: бит ⊕ Σ c_i·s_{N−i}; история хранит s_{N−i} в бите i.
        d = (c & история).bit_count() & 1
        if d:
            t = c
            c ^= bb << (N_ - m)
            if L <= N_ // 2:
                L, m, bb = N_ + 1 - L, N_, t
    return L


def линейная_сложность(биты, M: int = 500) -> float | None:
    """2.10 Линейная сложность в блоках по M бит. None — ни одного блока."""
    b = _биты(биты)
    N = len(b) // M
    if not N:
        return None
    pi = (0.01047, 0.03125, 0.12500, 0.50000, 0.25000, 0.06250, 0.020833)
    знак = -1 if (M + 1) % 2 == 0 else 1
    среднее = M / 2.0 + (9.0 + знак) / 36.0 - 1.0 / 2.0 ** M * (M / 3.0 + 2.0 / 9.0)
    знак = 1 if M % 2 == 0 else -1
    nu = [0] * 7
    границы = (-2.5, -1.5, -0.5, 0.5, 1.5, 2.5)
    for i in range(N):
        L = линейная_сложность_блока(b[i * M:(i + 1) * M])
        T = знак * (L - среднее) + 2.0 / 9.0
        nu[next((k for k, г in enumerate(границы) if T <= г), 6)] += 1
    хи = sum((nu[i] - N * pi[i]) ** 2 / (N * pi[i]) for i in range(7))
    return igamc(3.0, хи / 2.0)


_ЭКСКУРСИИ_PI = ((0, 0, 0, 0, 0, 0),
                 (0.5, 0.25, 0.125, 0.0625, 0.03125, 0.03125),
                 (0.75, 0.0625, 0.046875, 0.03515625, 0.0263671875, 0.0791015625),
                 (0.8333333333, 0.02777777778, 0.02314814815, 0.01929012346, 0.01607510288, 0.0803755143),
                 (0.875, 0.015625, 0.013671875, 0.01196289063, 0.0104675293, 0.0732727051))


def _блуждание(b: np.ndarray) -> tuple[np.ndarray, int, int]:
    S = np.cumsum(2 * b.astype(np.int64) - 1)
    нулей = int(np.count_nonzero(S == 0))
    J = нулей + (1 if S[-1] != 0 else 0)
    return S, J, max(int(0.005 * math.sqrt(len(b))), 500)


def случайные_экскурсии(биты) -> list[float] | None:
    """2.14 Случайные экскурсии: состояния −4…−1, 1…4. None — циклов меньше 500."""
    b = _биты(биты)
    S, J, нужно = _блуждание(b)
    if J < max(0.005 * math.sqrt(len(b)), 500):
        return None
    цикл = np.cumsum(S == 0) - (S == 0)                 # номер цикла: нулей строго раньше
    итог = []
    for x in (-4, -3, -2, -1, 1, 2, 3, 4):
        посещений = np.bincount(цикл[S == x], minlength=J)[:J]
        nu = [int(np.count_nonzero(посещений == k)) for k in range(5)] + [int(np.count_nonzero(посещений >= 5))]
        пи = _ЭКСКУРСИИ_PI[abs(x)]
        сумма = sum((nu[k] - J * пи[k]) ** 2 / (J * пи[k]) for k in range(6))
        итог.append(igamc(2.5, сумма / 2.0))
    return итог


def случайные_экскурсии_вариант(биты) -> list[float] | None:
    """2.15 Вариант случайных экскурсий: число посещений состояний −9…9. None — циклов меньше 500."""
    b = _биты(биты)
    S, J, нужно = _блуждание(b)
    if J < нужно:
        return None
    итог = []
    for x in list(range(-9, 0)) + list(range(1, 10)):
        count = int(np.count_nonzero(S == x))
        итог.append(math.erfc(abs(count - J) / math.sqrt(2.0 * J * (4.0 * abs(x) - 2))))
    return итог


# -- ENT (Fourmilab) ------------------------------------------------------------------

def ent(данные: bytes) -> dict[str, float]:
    """Характеристики ENT по байтам: энтропия (бит на байт), χ² и его p, среднее, π Монте-Карло,
    коэффициент последовательной корреляции (как randtest.c)."""
    a = np.frombuffer(данные, dtype=np.uint8)
    n = len(a)
    счёт = np.bincount(a, minlength=256).astype(np.float64)
    ожидание = n / 256.0
    хи = float(((счёт - ожидание) ** 2 / ожидание).sum())
    p = счёт[счёт > 0] / n
    энтропия = float(-(p * np.log2(p)).sum())
    среднее = float((np.arange(256) * счёт).sum() / n)
    # Монте-Карло: по 6 байт — координаты x и y по 24 бита, попадание в четверть круга.
    тройки = a[:n // 6 * 6].reshape(-1, 6).astype(np.float64)
    x = тройки[:, 0] * 65536 + тройки[:, 1] * 256 + тройки[:, 2]
    y = тройки[:, 3] * 65536 + тройки[:, 4] * 256 + тройки[:, 5]
    внутри = int(np.count_nonzero(x * x + y * y <= (256.0 ** 3 - 1) ** 2))
    пи = 4.0 * внутри / len(тройки) if len(тройки) else 0.0
    u = a.astype(np.float64)
    t1 = float((u[:-1] * u[1:]).sum() + u[-1] * u[0])
    t2 = float(u.sum()) ** 2
    t3 = float((u * u).sum())
    знам = n * t3 - t2
    корреляция = (n * t1 - t2) / знам if знам else float("nan")
    return {"байт": n, "энтропия": энтропия, "хи": хи, "хи_p": igamc(127.5, хи / 2.0), "среднее": среднее,
            "пи": пи, "корреляция": корреляция}


