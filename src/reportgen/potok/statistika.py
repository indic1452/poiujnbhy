"""Общая статистика потока: с чего начинает аналитик.

По одной энтропии уже многое видно. Около 8 бит на байт — поток случайный
на вид: зашифрован, скремблирован или сжат, и структура откроется только
после снятия этого слоя. Заметно меньше — в потоке есть порядок: заголовки,
заполнение, синхрослова, и его можно искать прямо.
"""

from __future__ import annotations

from dataclasses import dataclass, field

import numpy as np

from .bity import в_биты, единиц_доля, самые_длинные_серии


@dataclass
class Статистика:
    байт: int
    энтропия: float                 # бит на байт
    единиц: float                   # доля единиц в битах
    серия_нулей: int
    серия_единиц: int
    частые: list[tuple[int, float]] = field(default_factory=list)   # (байт, доля)
    повторы: list[tuple[str, int, float]] = field(default_factory=list)  # (слово, шаг, доля)

    def вывод(self) -> str:
        """Что это значит — одной фразой."""
        if self.энтропия > 7.9 and abs(self.единиц - 0.5) < 0.01:
            return ("поток случайный на вид: структура скрыта скремблером, "
                    "шифрованием или сжатием")
        if self.энтропия > 7.5:
            return "поток близок к случайному, но порядок в нём есть"
        return "в потоке заметный порядок: заголовки, заполнение или синхрослова"


def энтропия(массив: np.ndarray) -> float:
    if not len(массив):
        return 0.0
    return энтропия_частот(np.bincount(массив, minlength=256))


def энтропия_частот(частоты: np.ndarray) -> float:
    """Энтропия (бит на байт) по счёту байт — так её можно считать по кускам файла."""
    всего = int(частоты.sum())
    if not всего:
        return 0.0
    частоты = np.asarray(частоты).astype(np.float64)
    доли = частоты[частоты > 0] / всего
    return float(-(доли * np.log2(доли)).sum())


def частоты_кусками(куски) -> np.ndarray:
    """Счёт байт по всему файлу, читаемому кусками (``Источник.байты_кусками``)."""
    частоты = np.zeros(256, dtype=np.int64)
    for кусок in куски:
        частоты += np.bincount(np.frombuffer(кусок, dtype=np.uint8), minlength=256)
    return частоты


def посчитать(данные: bytes, *, выборка_бит: int = 1 << 24, частоты: np.ndarray | None = None
              ) -> Статистика:
    """Статистика по всему потоку — байтовая; битовая — по выборке.

    ``частоты`` — счёт байт всего файла, если ``данные`` — лишь его начало (файл больше
    памяти): байтовая статистика тогда по всему файлу, битовая и повторы — по началу.
    """
    массив = np.frombuffer(данные, dtype=np.uint8)
    биты = в_биты(массив[:выборка_бит // 8])
    нулей, единиц = самые_длинные_серии(биты)
    if частоты is None:
        частоты = np.bincount(массив, minlength=256)
    всего = int(частоты.sum())
    порядок = np.argsort(частоты)[::-1][:6]
    частые = [(int(байт), float(частоты[байт] / max(1, всего)))
              for байт in порядок if частоты[байт]]
    return Статистика(
        байт=всего, энтропия=энтропия_частот(частоты), единиц=единиц_доля(биты),
        серия_нулей=нулей, серия_единиц=единиц, частые=частые,
        повторы=повторяющиеся_слова(массив[:1 << 22]))


def повторяющиеся_слова(массив: np.ndarray, *, длина: int = 4,
                        наибольший_шаг: int = 4096) -> list[tuple[str, int, float]]:
    """Байтовые слова, повторяющиеся с постоянным шагом: кандидат в синхрослово.

    Ищем самые частые четырёхбайтовые слова и смотрим, стоят ли они на
    равном расстоянии друг от друга. MPEG-TS даёт 0x47 через 188 байт,
    заголовок пакетного протокола — одно и то же слово через длину пакета.
    """
    if len(массив) < длина * 16:
        return []
    слова = (массив[:-3].astype(np.uint32) << 24 | массив[1:-2].astype(np.uint32) << 16
             | массив[2:-1].astype(np.uint32) << 8 | массив[3:].astype(np.uint32))
    значения, счёт = np.unique(слова, return_counts=True)
    лучшие = значения[np.argsort(счёт)[::-1][:8]]
    итог = []
    for слово in лучшие:
        места = np.flatnonzero(слова == слово)
        if len(места) < 8:
            continue
        шаги = np.diff(места)
        шаги = шаги[шаги <= наибольший_шаг]
        if not len(шаги):
            continue
        шаг = int(np.bincount(шаги).argmax())
        доля = float((шаги == шаг).mean())
        if доля >= 0.5 and шаг >= длина:
            итог.append((f"{int(слово):08X}", шаг, доля))
    return итог[:4]
