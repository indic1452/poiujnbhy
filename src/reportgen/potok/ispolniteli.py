class Пул:
    """Пул исполнителей с честной очередью между владельцами (людьми)."""

    def __init__(self, имя: str, размер: int, *, процессы: bool = True, на_владельца: int | None = None,
                 срок: float | None = None, простой: float = ПРОСТОЙ, понизить: int = 5):
        self.имя = имя
        self._размер = max(1, int(размер))
        self._на_владельца = на_владельца
        self.процессы = bool(процессы)
        self.срок = срок
        self.простой = простой
        self.понизить = понизить
        self._lock = threading.RLock()
        self._очереди: dict[Any, deque[Задача]] = {}
        self._идут: dict[Any, int] = {}
        self._обслужен: dict[Any, int] = {}      # отметка последнего обслуживания владельца
        self._пришёл: dict[Any, int] = {}        # отметка, когда владелец впервые встал в очередь
        self._отметки = itertools.count(1)
        self._номера = itertools.count(1)
        self._места: list[Any] = []
        self._сторож: threading.Thread | None = None
        self._закрыт = False
        self._запуск_не_удался = ""

    # -- настройки ----------------------------------------------------------------------

    @property
    def размер(self) -> int:
        return self._размер

    @размер.setter
    def размер(self, значение: int) -> None:
        with self._lock:
            self._размер = max(1, int(значение))
        self._раздать()

    @property
    def на_владельца(self) -> int:
        return max(1, min(self._размер, self._на_владельца or self._размер))

    @на_владельца.setter
    def на_владельца(self, значение: int | None) -> None:
        with self._lock:
            self._на_владельца = значение
        self._раздать()

    # -- подача, отмена, очередь ----------------------------------------------------------

    def подать(self, функция: Callable[..., Any], *args: Any, владелец: Any = 0, имя: str = "",
               срок: float | None = None, при_сообщении: Callable[[str, Any], None] | None = None,
               при_конце: Callable[[Задача], None] | None = None, **kwargs: Any) -> Задача:
        """Поставить задачу в очередь владельца; исполнится, когда до неё дойдёт черёд."""
        with self._lock:
            if self._закрыт:
                raise ОшибкаИсполнителя(f"пул «{self.имя}» закрыт")
            задача = Задача(next(self._номера), функция, args, kwargs, владелец=владелец, имя=имя,
                            срок=self.срок if срок is None else срок, при_сообщении=при_сообщении,
                            при_конце=при_конце)
            if владелец not in self._пришёл:
                self._пришёл[владелец] = next(self._отметки)
            self._очереди.setdefault(владелец, deque()).append(задача)
        self._раздать()
        return задача

    def выполнить(self, функция: Callable[..., Any], *args: Any, владелец: Any = 0, срок: float | None = None,
                  ждать: float | None = None, **kwargs: Any) -> Any:
        """Подать и дождаться итога (ошибка задачи поднимается здесь)."""
        задача = self.подать(функция, *args, владелец=владелец, срок=срок, **kwargs)
        try:
            return задача.ждать(ждать)
        except TimeoutError:
            self.отменить(задача)
            raise

    def отменить(self, задача: Задача) -> str:
        """Отменить задачу: «снята» — из очереди, «отменяется» — идёт (флаг; не отзовётся — процесс снимут),
        пусто — уже закончена."""
        with self._lock:
            if задача.готова():
                return ""
            if задача.состояние == "ждёт":
                self._убрать_из_очереди(задача)
                снята = True
            else:
                снята = False
                задача.отмена_запрошена = задача.отмена_запрошена or time.monotonic()
                место = next((м for м in self._места if м.задача is задача), None)
                if место is not None:
                    место.отменить(задача)
        if снята:
            self._закончить(задача, "отменено", None, None)
            return "снята"
        return "отменяется"

    def снять(self, задачи: Iterable[Задача]) -> bool:
        """Атомарно убрать задачи из очереди: если хоть одна уже идёт — ничего не трогать (False)."""
        задачи = [з for з in задачи if not з.готова()]
        with self._lock:
            if any(з.состояние != "ждёт" for з in задачи):
                return False
            for з in задачи:
                self._убрать_из_очереди(з)
        for з in задачи:
            self._закончить(з, "отменено", None, None)
        return True

    def перед(self, задача: Задача) -> int:
        """Сколько задач будут взяты раньше этой (по правилу очереди, если ничего не изменится)."""
        with self._lock:
            if задача.состояние != "ждёт":
                return 0
            очереди = {в: list(о) for в, о in self._очереди.items() if о}
            идут = dict(self._идут)
            обслужен = dict(self._обслужен)
            отметка = max(обслужен.values(), default=0)
            до = 0
            while очереди:
                владелец = min(очереди, key=lambda в: self._ключ(в, идут, обслужен))
                следующая = очереди[владелец].pop(0)
                if следующая is задача:
                    return до
                до += 1
                if not очереди[владелец]:
                    del очереди[владелец]
                идут[владелец] = идут.get(владелец, 0) + 1
                отметка += 1
                обслужен[владелец] = отметка
            return до

    def сведения(self) -> dict[str, Any]:
        with self._lock:
            return {"имя": self.имя, "размер": self._размер, "на_владельца": self.на_владельца,
                    "процессы": self.процессы, "исполнителей": len(self._места),
                    "заняты": sum(1 for м in self._места if м.задача is not None),
                    "в_очереди": sum(len(о) for о in self._очереди.values()),
                    "по_людям": {str(в): {"ждут": len(self._очереди.get(в, ())), "идут": self._идут.get(в, 0)}
                                 for в in set(self._очереди) | {в for в, н in self._идут.items() if н}}}

    def закрыть(self) -> None:
        """Снять очередь и погасить исполнителей (идущие задачи — отменены)."""
        with self._lock:
            self._закрыт = True
            ждущие = [з for о in self._очереди.values() for з in о]
            self._очереди.clear()
            места, self._места = list(self._места), []
        for з in ждущие:
            self._закончить(з, "отменено", None, None)
        for м in места:
            задача = м.задача
            м.задача = None
            м.закрыть(0.5)
            if задача is not None and not задача.готова():
                with self._lock:
                    self._идут[задача.владелец] = max(0, self._идут.get(задача.владелец, 1) - 1)
                self._закончить(задача, "отменено", None, None)

    # -- внутреннее ----------------------------------------------------------------------

    def _ключ(self, владелец: Any, идут: dict[Any, int], обслужен: dict[Any, int]) -> tuple:
        """Порядок владельцев: меньше идущих задач — раньше; дольше не обслуживали — раньше; кто раньше пришёл."""
        return (идут.get(владелец, 0), обслужен.get(владелец, 0), self._пришёл.get(владелец, 0))

    def _убрать_из_очереди(self, задача: Задача) -> None:
        очередь = self._очереди.get(задача.владелец)
        if очередь is not None:
            try:
                очередь.remove(задача)
            except ValueError:
                pass
            if not очередь:
                del self._очереди[задача.владелец]

    def _следующая(self) -> Задача | None:
        """Задача, которую исполнитель возьмёт следующей (под блокировкой), — или None."""
        предел = self.на_владельца
        годные = [в for в, о in self._очереди.items() if о and self._идут.get(в, 0) < предел]
        if not годные:
            return None
        владелец = min(годные, key=lambda в: self._ключ(в, self._идут, self._обслужен))
        очередь = self._очереди[владелец]
        задача = очередь.popleft()
        if not очередь:
            del self._очереди[владелец]
        self._идут[владелец] = self._идут.get(владелец, 0) + 1
        self._обслужен[владелец] = next(self._отметки)
        return задача

    def _новое_место(self) -> Any:
        имя = f"reportgen-{self.имя}-{len(self._места) + 1}"
        if self.процессы and not self._запуск_не_удался:
            try:
                return _МестоПроцесс(имя, self.понизить)
            except (OSError, RuntimeError, ImportError) as ошибка:
                # Процессы не запускаются (ограничения среды) — считаем в нитях, но не молча.
                self._запуск_не_удался = str(ошибка)
                import logging  # noqa: PLC0415
                logging.getLogger("reportgen.potok").warning(
                    "исполнители «%s»: процессы не запускаются (%s) — счёт идёт в нитях сервера", self.имя, ошибка)
        return _МестоНить(self, имя)

    def _раздать(self) -> None:
        """Свободным исполнителям — задачи по правилу очереди; не хватает исполнителей — поднять новых.

        Задача передаётся исполнителю вне блокировки пула: передача большой задачи только что
        запущенному процессу ждёт, пока он поднимется, — подача и опрос очереди в это время не стоят.
        """
        неудачи: list[tuple[Задача, BaseException]] = []
        послать: list[tuple[Any, Задача]] = []
        with self._lock:
            if self._закрыт:
                return
            while True:
                место = next((м for м in self._места if м.задача is None and м.жив()), None)
                if место is None and len(self._места) >= self._размер:
                    break
                if not any(self._очереди.values()):
                    break
                задача = self._следующая()
                if задача is None:
                    break
                if место is None:
                    try:
                        место = self._новое_место()
                    except Exception as ошибка:  # noqa: BLE001
                        self._идут[задача.владелец] -= 1
                        неудачи.append((задача, ОшибкаИсполнителя(f"исполнитель не запустился: {ошибка}")))
                        continue
                    self._места.append(место)
                задача.состояние = "идёт"
                задача.начата = time.monotonic()
                место.задача = задача
                послать.append((место, задача))
            if any(м.процессом for м in self._места) and (self._сторож is None or not self._сторож.is_alive()):
                self._сторож = threading.Thread(target=self._сторожить, name=f"reportgen-{self.имя}-storozh",
                                                daemon=True)
                self._сторож.start()
        for место, задача in послать:
            try:
                место.послать(задача)
            except Exception as ошибка:  # noqa: BLE001 — задачу не передать (pickle, канал) — её ошибка
                with self._lock:
                    if место.задача is not задача:
                        continue
                    место.задача = None
                    место.свободно_с = time.monotonic()
                    self._идут[задача.владелец] = max(0, self._идут.get(задача.владелец, 1) - 1)
                неудачи.append((задача, ОшибкаИсполнителя(
                    f"задачу не передать исполнителю: {type(ошибка).__name__}: {ошибка}")))
        for задача, ошибка in неудачи:
            self._закончить(задача, "ошибка", None, ошибка)
        if неудачи:
            self._раздать()

    def _сообщение(self, задача: Задача, вид: str, данные: Any) -> None:
        if задача.при_сообщении is not None:
            try:
                задача.при_сообщении(вид, данные)
            except Exception:  # noqa: BLE001 — обработчик хода не роняет пул
                import logging  # noqa: PLC0415
                logging.getLogger("reportgen.potok").exception("обработчик хода задачи «%s»", задача.имя)

    def _итог(self, место: Any, ответ: tuple) -> None:
        """Ответ исполнителя: задача закончилась (итог, ошибка или отмена)."""
        вид, номер, данные = ответ
        with self._lock:
            задача = место.задача
            if задача is None or задача.номер != номер:
                return
            место.задача = None
            место.свободно_с = time.monotonic()
            self._идут[задача.владелец] = max(0, self._идут.get(задача.владелец, 1) - 1)
        if вид == "итог":
            self._закончить(задача, "готово", данные, None)
        elif вид == "отменено":
            self._закончить(задача, "отменено", None, None)
        else:
            self._закончить(задача, "ошибка", None, _распаковать_ошибку(данные))
        self._раздать()

    def _закончить(self, задача: Задача, состояние: str, итог: Any, ошибка: BaseException | None) -> None:
        if задача.готова():
            return
        задача.состояние, задача.итог, задача.ошибка = состояние, итог, ошибка
        задача.закончена = time.monotonic()
        задача._событие.set()
        if задача.при_конце is not None:
            try:
                задача.при_конце(задача)
            except Exception:  # noqa: BLE001
                import logging  # noqa: PLC0415
                logging.getLogger("reportgen.potok").exception("обработчик конца задачи «%s»", задача.имя)

    def _погиб(self, место: Any) -> None:
        """Процесс исполнителя завершился сам или снят: его задача — ошибка (или отмена)."""
        with self._lock:
            if место in self._места:
                self._места.remove(место)
            задача = место.задача
            место.задача = None
            if задача is not None:
                self._идут[задача.владелец] = max(0, self._идут.get(задача.владелец, 1) - 1)
        try:
            место.закрыть(0)
        except Exception:  # noqa: BLE001
            pass
        if задача is not None:
            if место.снято == "отмена" or задача.отмена_запрошена:
                self._закончить(задача, "отменено", None, None)
            elif место.снято == "срок":
                self._закончить(задача, "ошибка", None,
                                СрокВышел(f"задача «{задача.имя}» не уложилась в {задача.срок:g} с — остановлена"))
            else:
                код = getattr(getattr(место, "процесс", None), "exitcode", None)
                self._закончить(задача, "ошибка", None, ОшибкаИсполнителя(
                    f"исполнитель завершился аварийно (код {код}): не хватило памяти или сбой в счёте"))
        self._раздать()

    def _сторожить(self) -> None:
        """Нить сервера: принимает ход и итоги исполнителей, следит за сроками, отменами и простоем."""
        from multiprocessing import connection  # noqa: PLC0415
        while True:
            with self._lock:
                места = [м for м in self._места if м.процессом]
                if not места and (self._закрыт or not any(self._очереди.values())):
                    self._сторож = None
                    return
            каналы = {м.итоги: м for м in места}
            сторожа = {м.процесс.sentinel: м for м in места}
            try:
                готовые = connection.wait([*каналы, *сторожа], timeout=ШАГ_СТОРОЖА)
            except (OSError, ValueError):
                готовые = []
            погибшие = []
            for объект in готовые:
                место = каналы.get(объект)
                if место is not None:
                    try:
                        while место.итоги.poll():
                            ответ = место.итоги.recv()
                            if ответ[0] == "сообщение":
                                задача = место.задача
                                if задача is not None and задача.номер == ответ[1]:
                                    self._сообщение(задача, ответ[2], ответ[3])
                            else:
                                self._итог(место, ответ)
                    except (EOFError, OSError):
                        погибшие.append(место)
                    continue
                место = сторожа.get(объект)
                if место is not None:
                    # Сначала дочитать, что процесс успел прислать (итог мог прийти перед выходом).
                    try:
                        while место.итоги.poll():
                            ответ = место.итоги.recv()
                            if ответ[0] != "сообщение":
                                self._итог(место, ответ)
                    except (EOFError, OSError):
                        pass
                    погибшие.append(место)
            for место in dict.fromkeys(погибшие):
                self._погиб(место)
            self._проверить_сроки()

    def _проверить_сроки(self) -> None:
        сейчас = time.monotonic()
        снять: list[tuple[Any, str]] = []
        погасить: list[Any] = []
        with self._lock:
            for м in self._места:
                з = м.задача
                if з is not None:
                    if з.отмена_запрошена and сейчас - з.отмена_запрошена > ЖДАТЬ_ОТМЕНУ:
                        снять.append((м, "отмена"))
                    elif з.срок and з.начата and сейчас - з.начата > з.срок:
                        снять.append((м, "срок"))
                elif сейчас - м.свободно_с > self.простой:
                    погасить.append(м)
            for м in погасить:
                self._места.remove(м)
        for м, почему in снять:
            if м.процессом:
                м.снять(почему)            # сторож увидит завершение и вызовет _погиб
            elif почему == "срок" and not м.задача.отмена_запрошена:
                self.отменить(м.задача)   # нить — только попросить остановиться
        for м in погасить:
            м.закрыть(0.5)


# -- общие пулы приложения ---------------------------------------------------------------------

_общие: dict[str, Пул] = {}
_общие_lock = threading.Lock()


def общий(имя: str, размер: int, **параметры: Any) -> Пул:
    """Пул на всё приложение (один на имя): задания разных папок делят одних исполнителей.

    Повторный вызов с другим размером или пределом на человека — меняет их у того же пула.
    """
    with _общие_lock:
        пул = _общие.get(имя)
        if пул is None or пул._закрыт or пул.процессы != параметры.get("процессы", True):
            if пул is not None:
                пул.закрыть()
            пул = _общие[имя] = Пул(имя, размер, **параметры)
            return пул
    if пул.размер != размер:
        пул.размер = размер
    if "на_владельца" in параметры and параметры["на_владельца"] != пул._на_владельца:
        пул.на_владельца = параметры["на_владельца"]
    if "срок" in параметры:
        пул.срок = параметры["срок"]
    return пул


def закрыть_общие() -> None:
    with _общие_lock:
        пулы = list(_общие.values())
        _общие.clear()
    for пул in пулы:
        пул.закрыть()


atexit.register(закрыть_общие)
