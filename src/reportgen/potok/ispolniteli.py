"""Исполнители тяжёлого счёта анализа потоков: пул процессов с честной очередью.

Разбор потока и тяжёлые операции стола (поиск периода, «Дек. всех», ТКБ, разметка
вслепую…) — чистый счёт на питоне и numpy. В одном процессе с веб-сервером они
делят с ним глобальную блокировку интерпретатора (GIL): пока идёт счёт, лёгкие
запросы остальных людей (страница, список, окно бит) ждут своей очереди к
интерпретатору — и десять человек мешают друг другу. Поэтому счёт идёт в
отдельных процессах-исполнителях, а сервер только раздаёт задачи и принимает
итоги.

Устройство:

* ``Пул`` — несколько процессов (``размер``), запускаются по мере надобности
  (способом «spawn» — как на Windows, на любой системе одинаково) и гаснут после
  ``простой`` секунд без работы. Каждому — своя пара каналов (задачи туда, итоги
  и ход обратно): аварийное завершение одного не портит общих очередей.
* Очередь честная между людьми: следующую задачу берёт тот, у кого сейчас меньше
  всего идущих задач, при равенстве — кого дольше не обслуживали. Человек с
  двадцатью файлами не задерживает остальных: задача пришедшего позже встаёт
  первой, как только освободится исполнитель. ``на_владельца`` — сколько задач
  одного человека идут одновременно самое большее.
* Задача внутри исполнителя сообщает ход (``сообщить``) — он приходит в сервер
  сразу, вызовом ``при_сообщении``. Отмена: флаг виден задаче (``сообщить`` и
  ``проверить_отмену`` поднимают ``Отменено``); не отозвалась за ``ЖДАТЬ_ОТМЕНУ``
  секунд — процесс снимается и заменяется новым. Так же — по сроку задачи.
* ``режим="потоки"`` — то же самое в нитях этого процесса (запасной путь, где
  процессов нет: снять зависшую задачу силой тогда нельзя).

Функции и их аргументы для процессов должны передаваться pickle: функции — уровня
модуля, аргументы — простые (пути, числа, словари). Обратные вызовы
(``при_сообщении``, ``при_конце``) пул зовёт без своей блокировки — из них можно
обращаться к пулу.
"""

from __future__ import annotations

import atexit
import itertools
import os
import pickle
import sys
import threading
import time
import traceback
from collections import deque
from collections.abc import Callable, Iterable
