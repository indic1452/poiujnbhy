#: Переменные окружения (то же — поля настроек ``potok_*``, см. config.py и docs/20-potok.md).
ПЕРЕМЕННАЯ_РАЗБОРОВ = "REPORTGEN_POTOK_RAZBOROV"
ПЕРЕМЕННАЯ_СТОЛА = "REPORTGEN_POTOK_STOL"
ПЕРЕМЕННАЯ_ПРОЦЕССОВ = "REPORTGEN_POTOK_PROCESSY"
ПЕРЕМЕННАЯ_НА_ЧЕЛОВЕКА = "REPORTGEN_POTOK_NA_CHELOVEKA"
#: Сколько секунд ждать, пока отменённая задача сама остановится, прежде чем снять процесс.
ЖДАТЬ_ОТМЕНУ = 3.0
#: Исполнитель без работы гаснет через столько секунд (новый поднимется при новой задаче).
ПРОСТОЙ = 300.0
#: Как часто сторож пула проверяет сроки, отмены и простой, с.
ШАГ_СТОРОЖА = 0.25


class Отменено(BaseException):
    """Задачу отменили. От BaseException: широкие ``except Exception`` в счёте её не глотают."""


class ОшибкаИсполнителя(RuntimeError):
    """Исполнитель не смог выполнить задачу: упал, задачу или итог не передать, срок вышел."""


class СрокВышел(ОшибкаИсполнителя):
    """Задача не уложилась в свой срок — процесс снят."""


# -- что видит задача внутри исполнителя ---------------------------------------------------

_текущая = threading.local()


def сообщить(вид: str, данные: Any = None) -> None:
    """Передать в сервер ход задачи (``вид`` — «ход», «этап»…); отменённая задача здесь и останавливается."""
    связь = getattr(_текущая, "связь", None)
    if связь is not None:
        связь(вид, данные)


def отменено() -> bool:
    """Отменили ли текущую задачу (вне исполнителя — всегда нет)."""
    флаг = getattr(_текущая, "отмена", None)
    return bool(флаг is not None and флаг())


def проверить_отмену() -> None:
    if отменено():
        raise Отменено


# -- настройки по умолчанию ------------------------------------------------------------------

def _целое_из_окружения(имя: str) -> int:
    try:
        return max(0, int(os.environ.get(имя, "") or 0))
    except ValueError:
        return 0


def ядер() -> int:
    return max(1, os.cpu_count() or 1)


def размер_разборов(задано: int = 0) -> int:
    """Сколько разборов идут одновременно: задано (настройка, переменная) или по числу ядер."""
    return max(1, задано or _целое_из_окружения(ПЕРЕМЕННАЯ_РАЗБОРОВ) or ядер())


def размер_стола(задано: int = 0) -> int:
    """Сколько тяжёлых операций стола считаются одновременно: задано или половина ядер, не меньше двух."""
    return max(1, задано or _целое_из_окружения(ПЕРЕМЕННАЯ_СТОЛА) or max(2, ядер() // 2))


def на_человека(размер: int, задано: int = 0) -> int:
    """Сколько разборов одного человека идут одновременно: при трёх исполнителях и больше один всегда
    остаётся свободным для других (не ждать, пока человек с двадцатью файлами закончит свой)."""
    задано = задано or _целое_из_окружения(ПЕРЕМЕННАЯ_НА_ЧЕЛОВЕКА)
    if задано:
        return max(1, min(задано, размер))
    return размер - 1 if размер >= 3 else размер


def процессами(задано: bool | None = None) -> bool:
    """Считать в процессах (по умолчанию) или в нитях сервера (``REPORTGEN_POTOK_PROCESSY=0``)."""
    if задано is not None:
        return bool(задано)
    return os.environ.get(ПЕРЕМЕННАЯ_ПРОЦЕССОВ, "1").strip().lower() not in ("0", "нет", "no", "false", "off")


# -- задача ---------------------------------------------------------------------------------

class Задача:
    """Задача пула: ждёт → идёт → готово | ошибка | отменено."""

    def __init__(self, номер: int, функция: Callable[..., Any], args: tuple, kwargs: dict, *, владелец: Any,
                 имя: str, срок: float | None, при_сообщении: Callable[[str, Any], None] | None,
                 при_конце: Callable[[Задача], None] | None):
        self.номер, self.функция, self.args, self.kwargs = номер, функция, args, kwargs
        self.владелец, self.имя, self.срок = владелец, имя or getattr(функция, "__name__", "задача"), срок
        self.при_сообщении, self.при_конце = при_сообщении, при_конце
        self.состояние = "ждёт"
        self.итог: Any = None
        self.ошибка: BaseException | None = None
        self.подана = time.monotonic()
        self.начата: float | None = None
        self.закончена: float | None = None
        self.отмена_запрошена: float | None = None
        self._событие = threading.Event()

    def готова(self) -> bool:
        return self._событие.is_set()

    def ждать(self, срок: float | None = None) -> Any:
        """Итог задачи; её ошибка поднимается здесь же (отмена — ``Отменено``)."""
        if not self._событие.wait(срок):
            raise TimeoutError(f"задача «{self.имя}» не закончилась за {срок:g} с")
        if self.состояние == "отменено":
            raise Отменено
        if self.ошибка is not None:
            raise self.ошибка
        return self.итог

    def __repr__(self) -> str:
        return f"<Задача {self.номер} {self.имя} {self.состояние}>"


def _упаковать_ошибку(ошибка: BaseException) -> tuple:
    """Ошибка из исполнителя — объектом, если он передаётся pickle, иначе типом и текстом."""
    след = "".join(traceback.format_exception(type(ошибка), ошибка, ошибка.__traceback__))[-8000:]
    try:
        сырое = pickle.dumps(ошибка)
        pickle.loads(сырое)
        return ("объект", сырое, след)
    except Exception:  # noqa: BLE001 — любая непередаваемая ошибка передаётся текстом
        return ("текст", type(ошибка).__name__, str(ошибка), след)


_ВСТРОЕННЫЕ = {к.__name__: к for к in (ValueError, KeyError, TypeError, IndexError, MemoryError, OSError,
                                        FileNotFoundError, ZeroDivisionError, RuntimeError, OverflowError,
                                        ArithmeticError, LookupError, NotImplementedError, PermissionError)}


def _распаковать_ошибку(упаковано: tuple) -> BaseException:
    if упаковано[0] == "объект":
        try:
            return pickle.loads(упаковано[1])
        except Exception:  # noqa: BLE001
            return ОшибкаИсполнителя("ошибка исполнителя не передалась")
    _, тип, текст, _след = упаковано
    класс = _ВСТРОЕННЫЕ.get(тип)
    return класс(текст) if класс is not None else ОшибкаИсполнителя(f"{тип}: {текст}")


# -- исполнитель в процессе -------------------------------------------------------------------

def _понизить_приоритет(насколько: int) -> None:
    """Счёт — фоном: веб-сервер и лёгкие запросы людей получают процессор первыми."""
    if насколько <= 0:
        return
    try:
        if sys.platform == "win32":
            import ctypes  # noqa: PLC0415
            ниже_обычного = 0x00004000                  # BELOW_NORMAL_PRIORITY_CLASS
            ядро = ctypes.windll.kernel32
            ядро.SetPriorityClass(ядро.GetCurrentProcess(), ниже_обычного)
        else:
            os.nice(насколько)
    except (OSError, AttributeError, ValueError):
        pass


def _сторожить_родителя() -> None:
    """Сервер завершился (в том числе снятый силой) — исполнитель тоже: не висеть сиротой."""
    import multiprocessing  # noqa: PLC0415
    родитель = multiprocessing.parent_process()
    if родитель is None:
        return

    def ждать() -> None:
        родитель.join()
        os._exit(3)

    threading.Thread(target=ждать, daemon=True, name="reportgen-ispolnitel-storozh").start()


def _исполнитель(задачи, итоги, флаг, понизить: int) -> None:
    """Главный цикл процесса-исполнителя: задача из канала → итог (или ошибка) в канал итогов."""
    import signal  # noqa: PLC0415
    try:
        signal.signal(signal.SIGINT, signal.SIG_IGN)   # Ctrl+C в окне сервера останавливает сервер, а он — нас
    except (ValueError, OSError):
        pass
    _понизить_приоритет(понизить)
    _сторожить_родителя()
    while True:
        try:
            задача = задачи.recv()
        except (EOFError, OSError):
            return
        if задача is None:
            return
        номер, функция, args, kwargs = задача

        def связь(вид: str, данные: Any, номер: int = номер) -> None:
            if флаг.value == номер:
                raise Отменено
            итоги.send(("сообщение", номер, вид, данные))

        _текущая.связь, _текущая.отмена = связь, (lambda номер=номер: флаг.value == номер)
        try:
            ответ = ("итог", номер, функция(*args, **kwargs))
        except Отменено:
            ответ = ("отменено", номер, None)
        except BaseException as ошибка:  # noqa: BLE001 — любая ошибка задачи уходит в сервер
            ответ = ("ошибка", номер, _упаковать_ошибку(ошибка))
        finally:
            _текущая.связь = _текущая.отмена = None
        try:
            итоги.send(ответ)
        except OSError:
            return
        except Exception as ошибка:  # noqa: BLE001 — итог не передаётся pickle
            try:
                итоги.send(("ошибка", номер, _упаковать_ошибку(ОшибкаИсполнителя(
                    f"итог задачи не передать из процесса: {type(ошибка).__name__}: {ошибка}"))))
            except OSError:
                return


class _МестоПроцесс:
    """Один процесс-исполнитель и его каналы."""

    процессом = True

    def __init__(self, имя: str, понизить: int):
        import multiprocessing  # noqa: PLC0415
        ctx = multiprocessing.get_context("spawn")
        задачи_чт, задачи_зп = ctx.Pipe(duplex=False)
        итоги_чт, итоги_зп = ctx.Pipe(duplex=False)
        self.флаг = ctx.Value("q", 0, lock=False)
        self.процесс = ctx.Process(target=_исполнитель, args=(задачи_чт, итоги_зп, self.флаг, понизить),
                                   name=имя, daemon=True)
        self.процесс.start()
        задачи_чт.close()
        итоги_зп.close()
        self.задачи, self.итоги = задачи_зп, итоги_чт
        self.задача: Задача | None = None
        self.свободно_с = time.monotonic()
        self.снято: str = ""          # почему процесс сняли силой: «отмена», «срок»

    def послать(self, задача: Задача) -> None:
        self.флаг.value = задача.номер if задача.отмена_запрошена else 0
        self.задачи.send((задача.номер, задача.функция, задача.args, задача.kwargs))

    def отменить(self, задача: Задача) -> None:
        self.флаг.value = задача.номер

    def жив(self) -> bool:
        return self.процесс.is_alive()

    def снять(self, почему: str) -> None:
        self.снято = почему
        if self.процесс.is_alive():
            self.процесс.terminate()
            self.процесс.join(2)
            if self.процесс.is_alive():
                self.процесс.kill()
                self.процесс.join(2)

    def закрыть(self, ждать: float = 2.0) -> None:
        try:
            self.задачи.send(None)
        except (OSError, ValueError):
            pass
        self.процесс.join(ждать)
        if self.процесс.is_alive():
            self.снять("закрытие")
        for канал in (self.задачи, self.итоги):
            try:
                канал.close()
            except OSError:
                pass


class _МестоНить:
    """Исполнитель-нить (режим «потоки»): то же, но в этом процессе; силой не снимается."""

    процессом = False

    def __init__(self, пул: Пул, имя: str):
        import queue  # noqa: PLC0415
        self.пул = пул
        self.очередь: queue.Queue = queue.Queue()
        self.отменить_номер = 0
        self.задача: Задача | None = None
        self.свободно_с = time.monotonic()
        self.снято = ""
        self.нить = threading.Thread(target=self._цикл, name=имя, daemon=True)
        self.нить.start()

    def _цикл(self) -> None:
        while True:
            задача = self.очередь.get()
            if задача is None:
                return

            def связь(вид: str, данные: Any, задача: Задача = задача) -> None:
                if self.отменить_номер == задача.номер:
                    raise Отменено
                self.пул._сообщение(задача, вид, данные)

            _текущая.связь, _текущая.отмена = связь, (lambda з=задача: self.отменить_номер == з.номер)
            try:
                ответ = ("итог", задача.номер, задача.функция(*задача.args, **задача.kwargs))
            except Отменено:
                ответ = ("отменено", задача.номер, None)
            except BaseException as ошибка:  # noqa: BLE001
                ответ = ("ошибка", задача.номер, _упаковать_ошибку(ошибка))
            finally:
                _текущая.связь = _текущая.отмена = None
            self.пул._итог(self, ответ)

    def послать(self, задача: Задача) -> None:
        self.отменить_номер = задача.номер if задача.отмена_запрошена else 0
        self.очередь.put(задача)

    def отменить(self, задача: Задача) -> None:
        self.отменить_номер = задача.номер

    def жив(self) -> bool:
        return self.нить.is_alive()

    def снять(self, почему: str) -> None:       # нить силой не остановить — только отметить
        self.снято = почему

    def закрыть(self, ждать: float = 0.0) -> None:
        self.очередь.put(None)


