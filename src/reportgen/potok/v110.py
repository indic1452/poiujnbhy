"""V.110 (ISDN, GSM CSD): адаптация скорости пользователя к 8/16/32/64 кбит/с.

Кадр — 80 бит, десять октетов (V.110 5.1.2): октет 0 — восемь нулей, у остальных
первый бит — единица; это 17 бит синхрокомбинации, по ним кадр и находится. Прочие
биты (номер октета · 8 + бит, как в libosmocore src/isdn/v110.c):

- D — 48 бит данных: октеты 1–4 и 6–9, биты 1–6;
- E1–E7 — октет 5, биты 1–7: E1 E2 E3 задают вид адаптации RA1 (V.110 табл. 5);
- S1, S3, S4, S6, S8, S9 — бит 7 октетов 1, 3, 4, 6, 8, 9; X — бит 7 октетов 2 и 7
  (состояния цепей V.24: 0 — ON, 1 — OFF).

RA1 (V.110 табл. 6): 600, 1200 и 2400 бит/с — каждый бит повторён 8, 4 и 2 раза;
N × 4800 — все 48 бит D; N × 3600 — 36 бит и заполнение; N × 12000 — 30 бит и заполнение.
Промежуточная скорость (IR) из кадра не видна: 011 — это 4800 при IR 8 кбит/с, 9600 при
16 и т. д. RA2: IR 8/16/32 кбит/с в канале 64 кбит/с — первые 1/2/4 бита каждого октета.
"""

from __future__ import annotations

import numpy as np

from .nahodka import Находка

ДЛИНА = 80
#: Позиции синхрокомбинации: нули октета 0 и первые биты октетов 1–9.
НУЛИ = np.arange(8)
ЕДИНИЦЫ = np.arange(1, 10) * 8
#: Биты D (48), E1–E7, S (S1, S3, S4, S6, S8, S9) и X (X1, X2) в кадре.
D = np.array([о * 8 + б for о in (1, 2, 3, 4, 6, 7, 8, 9) for б in range(1, 7)])
E = np.arange(5 * 8 + 1, 6 * 8)
S = np.array([о * 8 + 7 for о in (1, 3, 4, 6, 8, 9)])
X = np.array([2 * 8 + 7, 7 * 8 + 7])

КАДРОВ_ОТ = 32
ОБРАЗЕЦ = 400
СОГЛАСИЕ = 0.9


def _места(отрезки: list[tuple[str, int]]) -> np.ndarray:
    """Номера бит D с данными по отрезкам «данные n» / «заполнение n» (V.110 табл. 6d, 6f)."""
    места, i = [], 0
    for вид, n in отрезки:
        if вид == "Д":
            места += range(i, i + n)
        i += n
    assert i == 48
    return np.array(места)


#: D1–D10, F×2, D11–12, F×2, D13–14, F×2, D15–28, F×2, D29–30, F×2, D31–32, F×2, D33–36.
N3600 = _места([("Д", 10), ("F", 2), ("Д", 2), ("F", 2), ("Д", 2), ("F", 2), ("Д", 14),
                ("F", 2), ("Д", 2), ("F", 2), ("Д", 2), ("F", 2), ("Д", 4)])
#: D1–D10, F×2, D11–12, F×2, D13–14, F×2, D15, F×3, D16–25, F×2, D26–27, F×2, D28–29, F×2, D30, F×3.
N12000 = _места([("Д", 10), ("F", 2), ("Д", 2), ("F", 2), ("Д", 2), ("F", 2), ("Д", 1), ("F", 3),
                 ("Д", 10), ("F", 2), ("Д", 2), ("F", 2), ("Д", 2), ("F", 2), ("Д", 1), ("F", 3)])

#: E1 E2 E3 → (вид, повтор каждого бита, места данных в D, {IR кбит/с: скорость бит/с}).
РЕЖИМЫ: dict[tuple[int, int, int], tuple[str, int, np.ndarray, dict[int, int]]] = {
    (1, 0, 0): ("600 бит/с, бит × 8", 8, np.arange(48), {8: 600}),
    (0, 1, 0): ("1200 бит/с, бит × 4", 4, np.arange(48), {8: 1200}),
    (1, 1, 0): ("2400 бит/с, бит × 2", 2, np.arange(48), {8: 2400}),
    (0, 1, 1): ("N × 4800: 48 бит данных", 1, np.arange(48), {8: 4800, 16: 9600, 32: 19200, 64: 38400}),
    (1, 0, 1): ("N × 3600: 36 бит данных и заполнение", 1, N3600, {16: 7200, 32: 14400, 64: 28800}),
    (0, 0, 1): ("N × 12000: 30 бит данных и заполнение", 1, N12000, {32: 12000, 64: 24000}),
}


def _верные(кадры: np.ndarray) -> np.ndarray:
    return (кадры[:, НУЛИ] == 0).all(1) & (кадры[:, ЕДИНИЦЫ] == 1).all(1)


def выровнять(биты: np.ndarray) -> tuple[int, float, np.ndarray] | None:
    """Начало кадра по 17 битам синхрокомбинации: (сдвиг, доля верных кадров, кадры).

    Сдвиг ищется по первым ОБРАЗЕЦ кадрам, доля и кадры — по всему потоку."""
    биты = np.asarray(биты, dtype=np.uint8)
    кадров = (len(биты) - ДЛИНА) // ДЛИНА
    if кадров < КАДРОВ_ОТ:
        return None
    образец = min(кадров, ОБРАЗЕЦ)
    лучший = None
    for сдвиг in range(ДЛИНА):
        верно = float(_верные(биты[сдвиг:сдвиг + образец * ДЛИНА].reshape(образец, ДЛИНА)).mean())
        if лучший is None or верно > лучший[1]:
            лучший = (сдвиг, верно)
    if лучший[1] < СОГЛАСИЕ:
        return None
    сдвиг = лучший[0]
    кадров = (len(биты) - сдвиг) // ДЛИНА
    кадры = биты[сдвиг:сдвиг + кадров * ДЛИНА].reshape(кадров, ДЛИНА)
    верно = float(_верные(кадры).mean())
    return (сдвиг, верно, кадры) if верно >= СОГЛАСИЕ else None


def данные(кадры: np.ndarray, режим: tuple[int, int, int]) -> tuple[np.ndarray, float]:
    """Биты пользователя (RA1 обратно) и доля согласных повторов (у N × … — 1)."""
    _, повтор, места, _ = РЕЖИМЫ[режим]
    d = кадры[:, D][:, места]
    if повтор == 1:
        return d.reshape(-1), 1.0
    группы = d.reshape(len(d), -1, повтор)
    единиц = группы.sum(axis=2)
    согласно = float(((единиц == 0) | (единиц == повтор)).mean())
    return (2 * единиц > повтор).astype(np.uint8).reshape(-1), согласно


def _ra2(биты: np.ndarray) -> list[tuple[int, int, np.ndarray]]:
    """Варианты RA2 из 64 кбит/с: (ширина 1/2/4 бита, первый бит в октете, поток IR)."""
    октеты = np.asarray(биты[:len(биты) // 8 * 8], dtype=np.uint8).reshape(-1, 8)
    return [(w, p, октеты[:, p:p + w].reshape(-1)) for w in (1, 2, 4) for p in range(0, 9 - w)]


def найти(биты: np.ndarray) -> Находка | None:
    """Кадры V.110 прямо в потоке или в канале 64 кбит/с через RA2; дальше — данные пользователя."""
    биты = np.asarray(биты, dtype=np.uint8)
    ra2 = None
    найдено = выровнять(биты)
    if найдено is None:
        for w, p, поток in _ra2(биты):
            найдено = выровнять(поток)
            if найдено is not None:
                ra2 = (w, p)
                break
    if найдено is None:
        return None
    сдвиг, верно, кадры = найдено
    годные = кадры[_верные(кадры)]
    e = годные[:, E]
    виды, счёт = np.unique(e[:, :3], axis=0, return_counts=True)
    режим = tuple(int(x) for x in виды[int(np.argmax(счёт))])
    доля_режима = float(счёт.max() / len(годные))
    подробно = [f"кадр 80 бит (V.110 5.1.2) с бита {сдвиг}: 17 бит синхрокомбинации верны в "
                f"{верно * 100:.1f} % из {len(кадры)} кадров"]
    ir = None
    if ra2 is not None:
        w, p = ra2
        ir = 8 * w
        подробно.append(f"RA2: канал 64 кбит/с, биты {p + 1}–{p + w} каждого октета → промежуточная "
                        f"скорость {ir} кбит/с" if w > 1 else
                        f"RA2: канал 64 кбит/с, бит {p + 1} каждого октета → промежуточная скорость 8 кбит/с")
    if режим not in РЕЖИМЫ:
        подробно.append(f"E1 E2 E3 = {''.join(map(str, режим))} — вид RA1 не из V.110 табл. 5")
        return Находка(уровень="цикл", что="V.110: кадры адаптации скорости (вид RA1 неизвестен)",
                       уверенность=верно, мера=f"синхрокомбинация верна в {верно * 100:.0f} % кадров",
                       подробно=подробно)
    имя, повтор, _, скорости = РЕЖИМЫ[режим]
    отбор = годные[(годные[:, E[:3]] == np.array(режим)).all(1)]
    поток, согласно = данные(отбор, режим)
    if ir is not None and ir in скорости:
        скорость = f"{скорости[ir]} бит/с"
    else:
        скорость = " или ".join(f"{с} бит/с при IR {к} кбит/с" for к, с in скорости.items())
    подробно.append(f"E1 E2 E3 = {''.join(map(str, режим))} (V.110 табл. 5): {имя} — {скорость}; "
                    f"так размечены {доля_режима * 100:.1f} % кадров")
    if повтор > 1:
        подробно.append(f"повторы бит согласны в {согласно * 100:.1f} % групп")
    e47 = "".join(str(int(x)) for x in (e[:, 3:].mean(axis=0) > 0.5))
    s_on = float((годные[:, S] == 0).mean())
    x_on = float((годные[:, X] == 0).mean())
    подробно.append(f"E4–E7 = {e47}; S-биты ON (0) в {s_on * 100:.0f} %, X-биты ON в {x_on * 100:.0f} %"
                    + (" — соединение не установлено (цепи OFF)" if s_on < 0.5 else ""))
    if len(поток) and (поток == поток[0]).all():
        подробно.append(f"данные — сплошь {int(поток[0])}: пауза")
    return Находка(
        уровень="цикл", что=f"V.110: адаптация скорости, {скорость if ir in скорости else имя}",
        уверенность=верно * доля_режима * (согласно if повтор > 1 else 1.0),
        мера=f"синхрокомбинация 17 бит верна в {верно * 100:.0f} % кадров, E1 E2 E3 одинаковы в "
             f"{доля_режима * 100:.0f} %",
        подробно=подробно, дальше=поток, вид_дальше="биты",
        свойства={"режим": режим, "IR": ir, "сдвиг": сдвиг})


def закодировать(данные_: np.ndarray, режим: tuple[int, int, int] = (0, 1, 1), s: int = 0, x: int = 0,
                 заполнение: int = 1) -> np.ndarray:
    """Кодер V.110 (для проверок): биты пользователя → кадры по 80 бит (как osmo_v110_encode_frame)."""
    _, повтор, места, _ = РЕЖИМЫ[режим]
    на_кадр = len(места) // повтор
    кадров = len(данные_) // на_кадр
    итог = np.zeros((кадров, ДЛИНА), dtype=np.uint8)
    итог[:, ЕДИНИЦЫ] = 1
    итог[:, E[:3]] = режим
    итог[:, S] = s
    итог[:, X] = x
    d = np.full((кадров, 48), заполнение, dtype=np.uint8)
    d[:, места] = np.repeat(np.asarray(данные_[:кадров * на_кадр], dtype=np.uint8).reshape(кадров, на_кадр),
                            повтор, axis=1)
    итог[:, D] = d
    return итог.reshape(-1)


def в_64к(ir_поток: np.ndarray, w: int = 1, p: int = 0, заполнение: int = 1) -> np.ndarray:
    """RA2 (для проверок): поток IR 8·w кбит/с → октеты 64 кбит/с, биты p…p+w−1 — данные."""
    ir_поток = np.asarray(ir_поток[:len(ir_поток) // w * w], dtype=np.uint8).reshape(-1, w)
    октеты = np.full((len(ir_поток), 8), заполнение, dtype=np.uint8)
    октеты[:, p:p + w] = ir_поток
    return октеты.reshape(-1)
