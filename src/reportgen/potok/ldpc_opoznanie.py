def схема_кандидата(к: Кандидат):
    """Схема передачи кандидата: стандарта (или загруженная), с выколотым хвостом, если слово в потоке
    короче."""
    база = к.схема if к.схема is not None else ldpc_std.схема(к.имя, к.вид)
    d = к.L - к.длина_слова
    if d <= 0:
        return база
    return ldpc.Схема(база.матрица, np.union1d(база.выколоты, база.переданы[к.L - d:]), база.укорочены,
                      база.переданы[:к.L - d] if база.порядок is not None else None)


def начала_слов(биты: np.ndarray, к: Кандидат, схема, слов_до: int) -> np.ndarray:
    """Начала слов во всём ряду: группы слов (смещения внутри периода) от начала кандидата с его шагом,
    а если начало найдено не первым — и назад до начала ряда."""
    L = схема.длина
    шаг = max(к.шаг, L) if len(к.смещения) == 1 else к.шаг
    t = к.начало - (к.начало // шаг) * шаг if к.начала else к.начало
    итог = (t + шаг * np.arange(max(0, (len(биты) - t) // шаг + 1), dtype=np.int64))[:, None] + \
        np.asarray(к.смещения, dtype=np.int64)[None, :]
    итог = итог.reshape(-1)
    return итог[итог + L <= len(биты)][:слов_до]


def слова_кандидата(биты: np.ndarray, к: Кандидат, схема, слов_до: int = 4000) -> np.ndarray:
    """Принятые слова (слов × длина в потоке) с инверсией и снятым рандомизатором."""
    if к.младший:
        биты = биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1].reshape(-1)
    начала = начала_слов(биты, к, схема, слов_до)
    L = схема.длина
    if not len(начала):
        return np.zeros((0, L), dtype=np.uint8)
    слова = биты[начала[:, None] + np.arange(L)[None, :]].astype(np.uint8)
    if к.инверсия:
        слова ^= 1
    if к.рандомизатор:
        слова ^= псп_ccsds(к.L)[:L]
    return слова


def _повторы(биты: np.ndarray, к: Кандидат, схема, слов: int) -> np.ndarray:
    """Мягкие значения повторённых за словом бит (слов × (шаг − L)); где повтора нет (конец записи) — 0."""
    if к.младший:
        биты = биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1].reshape(-1)
    начала = начала_слов(биты, к, схема, слов)
    L, d = схема.длина, max(0, к.шаг - схема.длина)
    итог = np.zeros((len(начала), d), dtype=np.float32)
    есть = начала + L + d <= len(биты)
    доп = биты[начала[есть][:, None] + L + np.arange(d)[None, :]].astype(np.float32)
    if к.инверсия:
        доп = 1.0 - доп
    итог[есть] = 1.0 - 2.0 * доп
    return итог


# -- маска на слове: оценка и снятие ---------------------------------------------------------------

#: Слов одного класса маски для её оценки (разности с первым словом декодируются, маска — большинством).
МАСКА_СЛОВ_ОЦЕНКИ = 32
#: Проверок для решения системы «маска — ПСП известного многочлена» (неизвестных до 64).
МАСКА_ПРОВЕРОК = 384
#: Скремблер 5G NR (38.211, 5.2.1): x1(n+31) = x1(n+3) + x1(n), x2(n+31) = x2(n+3) + x2(n+2) + x2(n+1) + x2(n),
#: c(n) = x1(n + Nc) + x2(n + Nc), Nc = 1600; x1(0) = 1, остальные нули; x2 — c_init (7.3.1.1: n_RNTI·2¹⁵ +
#: q·2¹⁴ + n_ID — номера слота нет, поэтому маска одна и та же у слов с теми же RNTI и E).
NR_NC = 1600
NR_X1 = (28, 31)
NR_X2 = (28, 29, 30, 31)


@lru_cache(maxsize=4)
def _голд_nr(длина: int) -> tuple[np.ndarray, np.ndarray]:
    """(часть x1 — постоянная, базис части x2 — 31 × длина): c = x1 ⊕ базисᵀ·σ, σ — биты c_init."""
    from . import skrembler  # noqa: PLC0415
    x1 = skrembler.псп(NR_X1, np.eye(31, dtype=np.uint8)[0], NR_NC + длина)[NR_NC:]
    базис = skrembler._базис(NR_X2, NR_NC + длина)[:, NR_NC:]
    return x1, базис


def голд_nr(c_init: int, длина: int) -> np.ndarray:
    """Последовательность скремблера 5G NR длиной ``длина`` при данном c_init."""
    x1, базис = _голд_nr(длина)
    σ = np.array([(c_init >> i) & 1 for i in range(31)], dtype=np.int64)
    return (x1 ^ ((σ @ базис.astype(np.int64)) & 1)).astype(np.uint8)


def _чётности(проверки: list[np.ndarray], векторы: np.ndarray) -> np.ndarray:
    """Чётность каждой проверки на каждом векторе: (векторов × проверок)."""
    return np.stack([np.bitwise_xor.reduce(векторы[..., с], axis=-1) for с in проверки], axis=-1).astype(np.uint8)


def _маска_nr(оценки: np.ndarray, проверки: list[np.ndarray], L: int) -> tuple[np.ndarray, int, int] | None:
    """Маска — Голд 5G NR: c_init из системы «синдром маски = синдром оценки» (31 неизвестное, линейно по
    x2); класс r — кодовый блок (r + φ) mod C транспортного блока, φ перебирается. (маски, c_init, φ) или None."""
    from . import skrembler  # noqa: PLC0415
    C = len(оценки)
    x1, базис = _голд_nr(C * L)
    синдромы = _чётности(проверки, оценки)                  # C × проверок
    for φ in range(C):
        A, y = [], []
        for r in range(C):
            сдвиг = ((r + φ) % C) * L
            for j, с in enumerate(проверки):
                места = сдвиг + с
                A.append(np.bitwise_xor.reduce(базис[:, места], axis=1))
                y.append(синдромы[r, j] ^ (int(x1[места].sum()) & 1))
        σ = skrembler._решить(np.array(A, dtype=np.uint8), np.array(y, dtype=np.uint8))
        if σ is None:
            continue
        c_init = int(sum(int(b) << i for i, b in enumerate(σ.tolist())))
        полная = голд_nr(c_init, C * L)
        маски = np.stack([полная[((r + φ) % C) * L:((r + φ) % C + 1) * L] for r in range(C)])
        return маски, c_init, φ
    return None


def _маска_псп(оценка: np.ndarray, проверки: list[np.ndarray]) -> tuple[np.ndarray, str] | None:
    """Маска — ПСП известного многочлена (скремблер кадра, заново на каждом слове) с неизвестным начальным
    состоянием и, может быть, инверсией: система «синдром маски = синдром оценки» (неизвестных — степень + 1)."""
    from . import skrembler  # noqa: PLC0415
    L = len(оценка)
    синдром = _чётности(проверки, оценка[None, :])[0]
    единицы = _чётности(проверки, np.ones((1, L), dtype=np.uint8))[0]
    виды: dict[tuple[int, ...], str] = {}
    for имя, отводы in skrembler.ИЗВЕСТНЫЕ.items():
        виды.setdefault(tuple(sorted(отводы)), имя)
    for (отводы, _), имя in skrembler.ИЗВЕСТНЫЕ_ПСП.items():
        виды.setdefault(tuple(sorted(отводы)), имя)
    for отводы, имя in виды.items():
        if max(отводы) + 1 >= len(проверки) // 2:
            continue
        базис = skrembler._базис(отводы, L)
        A = np.concatenate([np.stack([np.bitwise_xor.reduce(базис[:, с], axis=1) for с in проверки]),
                            единицы[:, None]], axis=1)
        σ = skrembler._решить(A.astype(np.uint8), синдром)
        if σ is None or not σ.any():
            continue
        маска = ((σ[:-1].astype(np.int64) @ базис.astype(np.int64)) & 1).astype(np.uint8) ^ σ[-1]
        return маска, f"ПСП {имя}, начальное состояние {''.join(map(str, σ[:-1].tolist()))}" + (
            ", инверсно" if σ[-1] else "")
    return None


def оценить_маску(принятые: np.ndarray, к: Кандидат, схема, итераций: int = 50) -> tuple[np.ndarray, list[str]]:
    """Маски классов слов (C × длина слова в потоке) и строки отчёта.

    Разность слова класса с первым словом класса — кодовое слово (маска сокращается): она декодируется,
    и каждое слово, сложенное со своей декодированной разностью, даёт маску ⊕ первое кодовое слово —
    большинством по словам без ошибок линии. Это маска с точностью до кодового слова; точно — если она
    ПСП: Голд 5G NR (c_init) или известный многочлен кадрового скремблера — из системы уравнений по
    синдрому. Иначе данные выходят относительно первого слова класса (сложенными с его данными)."""
    C = max(1, к.маска)
    L = схема.длина
    связи = схема.связи_декодера()
    оценки = np.zeros((C, L), dtype=np.uint8)
    for r in range(C):
        Y = принятые[r::C][:МАСКА_СЛОВ_ОЦЕНКИ + 1]
        if len(Y) < 2:
            оценки[r] = Y[0] if len(Y) else 0
            continue
        # Опорное слово — то, с которым разности сходятся у большинства (первое бывает чужим: кусок записи
        # до первого целого слова, слово с пачкой ошибок).
        лучшее = None
        for j in range(min(4, len(Y))):
            другие = np.delete(np.arange(len(Y)), j)
            X = Y[другие] ^ Y[j]
            слова, ок = ldpc.мин_сумма(схема.llr(X), связи, схема.матрица.n, итераций)
            if лучшее is None or ок.sum() > лучшее[0]:
                лучшее = (int(ок.sum()), j, другие, слова, ок)
            if ок.mean() >= 0.75:
                break
        _, j, другие, слова, ок = лучшее
        голоса = np.concatenate([Y[j:j + 1], Y[другие][ок] ^ слова[ок][:, схема.переданы]], axis=0)
        оценки[r] = (2 * голоса.sum(axis=0, dtype=np.int64) > len(голоса)).astype(np.uint8)
    проверки = ldpc.проверки_для_пробы(схема, МАСКА_ПРОВЕРОК)[0]
    if к.имя.startswith("nr-") and проверки:
        nr = _маска_nr(оценки, проверки, L)
        if nr is not None:
            маски, c_init, φ = nr
            return маски, [f"маска — скремблер 5G NR (Голд, 38.211, 5.2.1): c_init = {c_init} (0x{c_init:08X}; n_RNTI = "
                           f"{c_init >> 15}, q = {(c_init >> 14) & 1}, n_ID = {c_init & 0x3FFF})"
                           + (f", кодовых блоков в транспортном {C}, первое слово — блок {φ}" if C > 1 else "")
                           + "; снята — данные точные"]
    if C == 1 and проверки:
        псп = _маска_псп(оценки[0], проверки)
        if псп is not None:
            return псп[0][None, :], [f"маска — {псп[1]}; снята — данные точные"]
    return оценки, ["маска найдена с точностью до кодового слова (не Голд NR и не ПСП известного многочлена): "
                    "данные каждого слова сложены с данными опорного слова своего класса (из первых)"
                    + (f" (классов {C})" if C > 1 else "")]


def снять(биты: np.ndarray, к: Кандидат, *, схема=None, итераций: int = 50, слов_до: int = 4000,
          пачка: int = 16) -> tuple[np.ndarray, list[str], float]:
    """Декодирование (нормированный «минимум — сумма», 0,75) и данные k бит каждого слова подряд:
    (данные, строки отчёта, доля слов с обнулившимся синдромом)."""
    схема = схема or схема_кандидата(к)
    принятые = слова_кандидата(np.asarray(биты, dtype=np.uint8), к, схема, слов_до)
    слов = len(принятые)
    if not слов:
        raise ValueError("в потоке нет ни одного целого слова")
    о_маске: list[str] = []
    if к.маска:
        маски, о_маске = оценить_маску(принятые, к, схема, итераций)
        принятые = принятые ^ маски[np.arange(слов) % len(маски)]
    связи = схема.связи_декодера()
    данные = ldpc.информационные(схема.матрица)
    повторы = _повторы(np.asarray(биты, dtype=np.uint8), к, схема, слов) if к.повтор else None
    итог, сошлось, исправлено = [], 0, 0
    for от in range(0, слов, пачка):
        кусок = принятые[от:от + пачка]
        llr = схема.llr(кусок)
        if повторы is not None:
            # Повторённые биты — ещё одно наблюдение тех же позиций: мягкие значения складываются.
            доп = повторы[от:от + пачка]
            куда = схема.переданы[np.arange(доп.shape[1]) % схема.длина]
            np.add.at(llr, (slice(None), куда), доп)
        слова, ок = ldpc.мин_сумма(llr, связи, схема.матрица.n, итераций)
        сошлось += int(ок.sum())
        исправлено += int((слова[:, схема.переданы] != кусок).sum())
        итог.append(слова[:, данные])
    L = схема.длина
    подробно = [
        f"код ({схема.матрица.n}, {len(данные)}), {схема.матрица.откуда}; в потоке слово {L} бит: "
        f"выколото {len(схема.выколоты)}, укорочено {len(схема.укорочены)}",
        f"слов {слов}: синдром обнулился у {сошлось} ({сошлось / слов * 100:.1f} %); исправлено бит "
        f"{исправлено} ({исправлено / (слов * L) * 100:.3f} % принятых — оценка ошибок линии)",
        f"на выходе — информационные биты: {ldpc.информационные_сводка(схема.матрица)[1]}",
    ] + о_маске
    if сошлось < слов * 0.5:
        подробно.append("меньше половины слов сошлось — ошибок больше, чем исправляет код, или схема не та")
    return np.concatenate(итог, axis=0).reshape(-1), подробно, сошлось / слов


def пробное(биты: np.ndarray, к: Кандидат, слов: int = ПРОБНЫХ_СЛОВ) -> tuple[float, float]:
    """Пробное декодирование нескольких слов: (доля сошедшихся, доля исправленных принятых бит)."""
    схема = схема_кандидата(к)
    принятые = слова_кандидата(np.asarray(биты, dtype=np.uint8), к, схема, max(слов, 2 * к.маска + 1) if к.маска else слов)
    if not len(принятые):
        return 0.0, 1.0
    if к.маска:
        маски, _ = оценить_маску(принятые, к, схема)
        принятые = (принятые ^ маски[np.arange(len(принятые)) % len(маски)])[:слов]
    слова, ок = ldpc.мин_сумма(схема.llr(принятые), схема.связи_декодера(), схема.матрица.n, 50)
    return float(ок.mean()), float((слова[:, схема.переданы] != принятые).mean())


def выбрать(биты: np.ndarray, кандидаты: list[Кандидат]) -> tuple[Кандидат | None, str]:
    """Лучший кандидат: по доле нарушенных проверок; почти равные — пробным декодированием."""
    if not кандидаты:
        return None, ""
    лучший = кандидаты[0]
    почти = [к for к in кандидаты if к.нарушено <= лучший.нарушено + max(РАВНЫЕ_ДО, 0.5 * лучший.нарушено)]
    if len(почти) < 2:
        return лучший, ""
    почти = почти[:РАВНЫХ_ПРОБОВАТЬ]
    пробы = [пробное(биты, к) for к in почти]
    i = min(range(len(почти)), key=lambda i: (-пробы[i][0], пробы[i][1], почти[i].нарушено))
    return почти[i], ("почти равные по проверкам варианты различены пробным декодированием "
                      f"{ПРОБНЫХ_СЛОВ} слов (сошлось, исправлено принятых бит): " + "; ".join(
                          f"«{к.имя}» {к.вариант()}, начало {к.начало} — {п[0] * 100:.0f} %, {п[1] * 100:.2f} %"
                          + (" ← выбран" if j == i else "") for j, (к, п) in enumerate(zip(почти, пробы, strict=True))))


def находка(биты: np.ndarray, к: Кандидат, *, сведения: dict | None = None, выбор: str = "",
            итераций: int = 50, слов_до: int = 4000, перебор: str | None = None):
    """Снять код кандидата и оформить находкой разбора."""
    from .nahodka import Находка  # noqa: PLC0415
    схема = схема_кандидата(к)
    данные, подробно, сошлось = снять(биты, к, схема=схема, итераций=итераций, слов_до=слов_до)
    м = схема.матрица
    k = len(ldpc.информационные(м))
    сведения = сведения or {}
    перебор = перебор or (f"опознан по синдрому: вариантов кодов {сведения.get('вариантов', '?')}, проверено "
               f"{сведения.get('проверено', '?')}" + (" (срок вышел раньше)" if сведения.get("срок_вышел") else "")
               + f"; начало слова — бит {к.начало}" + (f", шаг {к.шаг}" if к.шаг != к.L else "")
               + (f", смещения слов в периоде {', '.join(map(str, к.смещения))}" if len(к.смещения) > 1 else ""))
    return Находка(
        уровень="код",
        что=f"LDPC ({м.n}, {k}) по матрице «{к.имя}»" + (f" ({м.откуда})" if м.откуда else "") + f"; {к.вариант()}",
        уверенность=float(сошлось),
        мера=f"проверки H при найденной границе слова выполнены в {к.доля * 100:.1f} % ({к.отсчётов} отсчётов; "
             f"при чужой границе — около {(1 - к.медиана) * 100:.0f} %); синдром обнулился у {сошлось * 100:.1f} % слов",
        подробно=[перебор] + ([выбор] if выбор else []) + подробно,
        дальше=данные, вид_дальше="биты",
        свойства={"n": м.n, "k": k, "матрица": к.имя, "начало": к.начало, "шаг": к.шаг,
                  "выколото": int(len(схема.выколоты)), "укорочено": int(len(схема.укорочены)),
                  "схема": схема, "данных_в_блоке": k, "кандидат": к.словарь(), "объект_кандидата": к,
                  "перемежение": к.вид, "инверсия": к.инверсия, "младший": к.младший})


def найти(биты: np.ndarray, *, имена: Sequence[str] | None = None, срок: float = 20.0,
          наборы: Sequence[Набор] | None = None, младший: bool = True):
    """Опознать и снять: находка разбора или None."""
    кандидаты, сведения = опознать(биты, имена=имена, срок=срок, наборы=наборы, младший=младший)
    к, выбор = выбрать(биты, кандидаты)
    if к is None:
        return None
    return находка(биты, к, сведения=сведения, выбор=выбор)
