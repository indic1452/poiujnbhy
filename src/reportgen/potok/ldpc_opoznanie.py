@lru_cache(maxsize=4)
def псп_ccsds(сколько: int) -> np.ndarray:
    """ПСП рандомизатора CCSDS (131.0-B-5, 10.4.1): h(x) = x⁸+x⁷+x⁵+x³+1, начальное — все единицы."""
    р = [1] * 8
    итог = np.empty(сколько, dtype=np.uint8)
    for i in range(сколько):
        итог[i] = р[0]
        р = р[1:] + [р[0] ^ р[3] ^ р[5] ^ р[7]]
    return итог


def ранние(схема, сколько: int) -> list[np.ndarray]:
    """Проверки, которые кончаются раньше всех: по началу переданного слова.

    Одиночные строки без выколотых позиций — по наибольшей позиции; не хватает (выколотые
    входят почти во все строки: 5G NR, AR4JA) — суммы строк с одними и теми же выколотыми
    позициями (они сокращаются), тоже по наибольшей позиции суммы.
    """
    м = схема.матрица
    столбцы, границы = м.подряд()
    номер = м._номера_строк()
    выколото = np.zeros(м.n, dtype=bool)
    выколото[схема.выколоты] = True
    укорочено = np.zeros(м.n, dtype=bool)
    укорочено[схема.укорочены] = True
    куда = np.full(м.n, -1, dtype=np.int64)
    куда[схема.переданы] = np.arange(схема.длина)
    поз = куда[столбцы]
    с_выколотыми = np.bincount(номер[выколото[столбцы]], minlength=м.m) > 0
    наибольшая = np.full(м.m, -1, dtype=np.int64)
    np.maximum.at(наибольшая, номер, поз)
    годные = np.flatnonzero(~с_выколотыми & (наибольшая >= 0))
    итог: list[tuple[int, np.ndarray]] = []
    for i in годные[np.argsort(наибольшая[годные], kind="stable")][:сколько]:
        с = столбцы[границы[i]:границы[i + 1]]
        итог.append((int(наибольшая[i]), np.sort(куда[с[~укорочено[с]]])))
    if len(итог) < сколько and выколото.any():
        группы: dict[tuple[int, ...], list[int]] = {}
        for i in np.flatnonzero(с_выколотыми).tolist():
            с = столбцы[границы[i]:границы[i + 1]]
            группы.setdefault(tuple(с[выколото[с]].tolist()), []).append(i)
        пары = []
        for строки in группы.values():
            if len(строки) < 2:
                continue
            строки = sorted(строки, key=lambda i: наибольшая[i])
            for a, b in zip(строки, строки[1:], strict=False):
                пары.append((max(наибольшая[a], наибольшая[b]), a, b))
        пары.sort()
        for край, a, b in пары:
            if len(итог) >= сколько:
                break
            все, раз = np.unique(np.concatenate([столбцы[границы[a]:границы[a + 1]],
                                                 столбцы[границы[b]:границы[b + 1]]]), return_counts=True)
            сумма = все[(раз % 2 == 1) & ~укорочено[все]]
            if len(сумма) and not выколото[сумма].any():
                итог.append((int(край), np.sort(куда[сумма])))
    if выколото.any():
        # Ещё суммы — строка с опорными (по строке с единственной выколотой позицией на каждую её
        # выколотую): так у AR4JA, где одинаково выколотых строк мало.
        есть = {с.tobytes() for _, с in итог}
        for с in ldpc.сложенные(схема, max(4096, 8 * сколько)):
            с = np.sort(с)
            if len(с) and с.tobytes() not in есть:
                итог.append((int(с.max()), с))
    итог.sort(key=lambda п: п[0])
    return [с for _, с in итог[:сколько] if len(с)]


def _без(проверки: list[np.ndarray], занятые: list[np.ndarray]) -> list[np.ndarray]:
    """Проверки, которых нет среди занятых: сверка не должна повторять отбор (иначе оценка смещена)."""
    ключи = {с.tobytes() for с in занятые}
    return [с for с in проверки if с.tobytes() not in ключи]


def набор_схемы(имя: str, схема, вид: str = "", своя: bool = False) -> Набор:
    """Набор проверок схемы: ранние на отбор, следующие ранние — на сверку начал, равномерные — на
    сверку слов подряд (без повторов отбора). ``своя`` — загруженная матрица (схема хранится в наборе)."""
    ран = ранние(схема, ПРОВЕРОК_ОТБОР + ПРОВЕРОК_РАННИХ_СВЕРКА)
    отбор, ран_сверка = ран[:ПРОВЕРОК_ОТБОР], ран[ПРОВЕРОК_ОТБОР:]
    сверка = _без(ldpc.проверки_для_пробы(схема, ПРОВЕРОК_СВЕРКА + ПРОВЕРОК_ОТБОР)[0], отбор)[:ПРОВЕРОК_СВЕРКА]
    края = [int(с.max()) for с in отбор if len(с)]
    return Набор(имя, вид, схема.длина, отбор, сверка, (max(края) + 1) if края else схема.длина,
                 "CCSDS" if имя.startswith(CCSDS_ПРЕФИКСЫ) and not своя else "", схема if своя else None,
                 ран_сверка)


#: Наборы встроенных кодов строятся один раз (все — около 15 с) и кладутся на диск: следующий
#: процесс-исполнитель читает их за доли секунды. Ключ файла — версия и состояние таблиц и модулей.
ВЕРСИЯ_НАБОРОВ = 1
_НАБОРЫ: dict[tuple[str, str], Набор] = {}
_С_ДИСКА: dict[str, bool] = {"прочитано": False, "изменено": False}


def _путь_кэша() -> Path:
    h = hashlib.sha1(f"{ВЕРСИЯ_НАБОРОВ}:{ПРОВЕРОК_ОТБОР}:{ПРОВЕРОК_СВЕРКА}:{ПРОВЕРОК_РАННИХ_СВЕРКА}".encode())
    здесь = Path(__file__).parent
    for путь in sorted(здесь.glob("ldpc*.py")) + sorted((здесь / "data").glob("ldpc_*.json")):
        ст = путь.stat()
        h.update(f"{путь.name}:{ст.st_size}:{int(ст.st_mtime)}".encode())
    return Path(tempfile.gettempdir()) / f"reportgen-ldpc-nabory-{h.hexdigest()[:16]}.pickle"


def _прочитать_кэш() -> None:
    if _С_ДИСКА["прочитано"]:
        return
    _С_ДИСКА["прочитано"] = True
    try:
        with _путь_кэша().open("rb") as ф:
            данные = pickle.load(ф)
        for (имя, вид), (L, ран, сверка, край, ранд, ран_сверка) in данные.items():
            _НАБОРЫ.setdefault((имя, вид), Набор(имя, вид, L, ран, сверка, край, ранд, None, ран_сверка))
    except (OSError, EOFError, pickle.UnpicklingError, ValueError, TypeError, AttributeError):
        return


def сохранить_кэш() -> None:
    """Записать построенные наборы на диск (если появились новые) — атомарно, через переименование."""
    if not _С_ДИСКА["изменено"]:
        return
    путь = _путь_кэша()
    данные = {к: (н.L, н.ранние, н.сверка, н.край, н.рандомизатор, н.ранние_сверка) for к, н in _НАБОРЫ.items()}
    try:
        with tempfile.NamedTemporaryFile("wb", dir=путь.parent, delete=False, suffix=".tmp") as ф:
            pickle.dump(данные, ф, protocol=pickle.HIGHEST_PROTOCOL)
        os.replace(ф.name, путь)
        _С_ДИСКА["изменено"] = False
    except OSError:
        return


def набор(имя: str, вид: str = "") -> Набор:
    """Набор проверок встроенного кода со схемой стандарта (и перемежением ``вид``) — строится один раз."""
    _прочитать_кэш()
    ключ = (имя, вид)
    if ключ not in _НАБОРЫ:
        _НАБОРЫ[ключ] = набор_схемы(имя, ldpc_std.схема(имя, вид), вид)
        _С_ДИСКА["изменено"] = True
    return _НАБОРЫ[ключ]


_СВОИ: dict[tuple, Набор] = {}


def набор_своей(имя: str, схема) -> Набор:
    """Набор проверок загруженной матрицы (файла отдела) — строится один раз на её содержимое."""
    столбцы, границы = схема.матрица.подряд()
    ключ = (имя, схема.матрица.n, схема.матрица.m, hashlib.sha1(столбцы.tobytes() + границы.tobytes()
                                                              + np.asarray(схема.переданы).tobytes()).hexdigest())
    if ключ not in _СВОИ:
        if len(_СВОИ) > 256:
            _СВОИ.clear()
        _СВОИ[ключ] = набор_схемы(имя, схема, своя=True)
    return _СВОИ[ключ]


def наборы_загруженных() -> list[Набор]:
    """Наборы проверок всех загруженных матриц и файлов отдела (битые пропускаются)."""
    итог = []
    for м in ldpc.список():
        if "ошибка" in м:
            continue
        try:
            итог.append(набор_своей(str(м["имя"]), ldpc.схема_сохранённая(str(м["имя"]))))
        except (ValueError, OSError, KeyError):
            continue
    return итог


#: Очередь семейств в переборе (срок может выйти раньше): спутниковые и космические — первыми.
ОЧЕРЕДЬ = ("dvb-s2-", "dvb-s2x-", "fldpc-", "ar4ja-", "ccsds-", "dvb-t2-", "nr-", "wifi-", "wimax-", "docsis",
           "atsc", "80211", "dtmb", "abs-s", "cmmb", "beidou", "ghn", "10gbase", "wran")


def _очередь(имя: str) -> int:
    return next((i for i, п in enumerate(ОЧЕРЕДЬ) if имя.startswith(п)), len(ОЧЕРЕДЬ))


def варианты(имена: Sequence[str] | None = None, *, перемежения: bool = True) -> list[tuple[str, str]]:
    """(код, перемежение) для перебора: схема стандарта и перемежения бит по стандарту кода."""
    итог = []
    for имя in sorted(ldpc_std.подходящие(None) if имена is None else имена, key=_очередь):
        if not ldpc_std.есть(имя):
            continue
        итог.append((имя, ""))
        if перемежения:
            итог += [(имя, вид) for вид, _ in ldpc_std.перемежения(имя)]
    return итог


# -- счёт по всем сдвигам ---------------------------------------------------------------------------

def нарушения_по_сдвигам(биты: np.ndarray, проверки: Sequence[np.ndarray], сдвигов: int,
                         перевороты: Sequence[np.ndarray] = ()) -> list[np.ndarray]:
    """Для каждого сдвига t < ``сдвигов`` — число нарушенных проверок s(t): без переворотов и для
    каждого вектора переворотов f (у проверки с f = 1 ожидаемая чётность — единица: инверсия у
    проверок нечётного веса, рандомизатор — по чётности ПСП на её позициях). Считается одним
    проходом: s_f = s − 2·Σ_{f=1} чётность + |f|."""
    s = np.zeros(сдвигов, dtype=np.int16)
    части = [np.zeros(сдвигов, dtype=np.int16) for _ in перевороты]
    for i, с in enumerate(проверки):
        p0 = int(с[0])
        чётность = биты[p0:p0 + сдвигов].copy()
        for p in с[1:].tolist():
            чётность ^= биты[p:p + сдвигов]
        s += чётность
        for f, часть in zip(перевороты, части, strict=True):
            if f[i]:
                часть += чётность
    return [s] + [s - 2 * часть + int(f.sum()) for f, часть in zip(перевороты, части, strict=True)]


def нарушения_в(биты: np.ndarray, проверки: Sequence[np.ndarray], начала: np.ndarray,
                переворот: np.ndarray | None = None) -> np.ndarray:
    """Нарушенные проверки при данных началах: (начал × проверок) из 0/1."""
    начала = np.asarray(начала, dtype=np.int64)
    итог = np.zeros((len(начала), len(проверки)), dtype=np.uint8)
    for i, с in enumerate(проверки):
        ч = np.bitwise_xor.reduce(биты[начала[:, None] + с[None, :]], axis=1)
        if переворот is not None and переворот[i]:
            ч ^= 1
        итог[:, i] = ч
    return итог


def переворот(н: Набор, проверки: list[np.ndarray], инверсия: bool, рандомизатор: str) -> np.ndarray:
    """Ожидаемая чётность каждой проверки: инверсия меняет её у проверок нечётного веса,
    рандомизатор — по чётности ПСП на её позициях."""
    f = np.zeros(len(проверки), dtype=np.uint8)
    if инверсия:
        f ^= np.array([len(с) & 1 for с in проверки], dtype=np.uint8)
    if рандомизатор:
        f ^= н.поправки(проверки)
    return f


def виды_переворота(н: Набор) -> list[tuple[bool, str]]:
    """(инверсия, рандомизатор) для перебора: как есть, инверсно (если есть проверки нечётного веса) и,
    у кодов CCSDS, — с рандомизатором поверх блока."""
    итог = [(False, "")]
    if any(len(с) & 1 for с in н.ранние):
        итог.append((True, ""))
    if н.рандомизатор:
        итог += [(инв, н.рандомизатор) for инв, _ in list(итог)]
    return итог


def _выборка(биты: np.ndarray, L: int, край: int) -> tuple[np.ndarray, int, int]:
    """Выборка для счёта: (биты, сдвигов, слов для сложения)."""
    слов = int(np.clip(БИТ_НА_ОТБОР // max(1, L), СЛОВ_ОТ, СЛОВ_ДО))
    слов = min(слов, len(биты) // L - 1)
    if слов < 1:
        return биты, 0, 0
    сдвигов = слов * L
    return биты[:сдвигов + max(L, край)], сдвигов, слов


@lru_cache(maxsize=512)
def _лог_хвосты(отсчётов: int) -> np.ndarray:
    """ln P(Bin(отсчётов, ½) ≤ k) для всех k — таблицей (один раз на число отсчётов)."""
    k = np.arange(отсчётов + 1)
    лог = np.array([math.lgamma(отсчётов + 1) - math.lgamma(i + 1) - math.lgamma(отсчётов - i + 1)
                    for i in range(отсчётов + 1)]) - отсчётов * math.log(2)
    return np.logaddexp.accumulate(лог)[k]


def случайно(нарушено: float, отсчётов: int, начал: int) -> float:
    """Вероятность, что у случайных бит лучшее из ``начал`` даст не больше ``нарушено`` нарушенных из
    ``отсчётов`` (каждая — с вероятностью ½; оценка сверху) — то же, что ``ldpc.случайно``, таблицей."""
    if отсчётов <= 0:
        return 1.0
    k = min(отсчётов, max(0, int(round(нарушено * отсчётов))))
    return float(min(1.0, начал * math.exp(_лог_хвосты(отсчётов)[k])))


@lru_cache(maxsize=256)
def порог_начала(проверок: int) -> int:
    """Наибольшее число нарушенных из ``проверок``, при котором у случайных бит вероятность не больше
    НАЧАЛО_СЛУЧАЙНО_ДО (−1 — проверок мало)."""
    k = -1
    while 0 < проверок and k + 1 <= проверок and случайно((k + 1) / проверок, проверок, 1) <= НАЧАЛО_СЛУЧАЙНО_ДО:
        k += 1
    return k


def _подряд(выборка, н: Набор, sv: np.ndarray, слов: int, инв: bool, ранд: str, младший: bool) -> Кандидат | None:
    """Слова подряд: s(t) складывается по словам, лучшие начала сверяются проверками, которых не было
    в отборе; совпадение — по хвосту биномиального распределения с поправкой на L начал."""
    L, C = н.L, len(н.ранние)
    сверка = н.сверка or н.ранние_сверка
    if len(сверка) < 3:
        return None
    по_началу = sv[:слов * L].reshape(слов, L).sum(axis=0, dtype=np.int64)
    медиана = float(np.median(по_началу)) / (слов * C)
    if медиана < 0.25 or случайно(float(по_началу.min()) / (слов * C), слов * C, L) > ОТБОР_СЛУЧАЙНО_ДО:
        return None
    лучшие = np.argpartition(по_началу, ЛУЧШИХ)[:ЛУЧШИХ] if L > ЛУЧШИХ else np.arange(L)
    начала_слов = лучшие[:, None] + L * np.arange(слов)[None, :]
    нар = нарушения_в(выборка, сверка, начала_слов.reshape(-1), переворот(н, сверка, инв, ранд))
    нар = нар.reshape(len(лучшие), слов * len(сверка)).mean(axis=1)
    j = int(np.argmin(нар))
    отсчётов = слов * len(сверка)
    p = случайно(float(нар[j]), отсчётов, L)
    if нар[j] <= НАРУШЕНО_ДО and p <= СЛУЧАЙНО_ДО:
        return Кандидат(н.имя, н.вид, L, int(лучшие[j]), L, float(нар[j]), медиана, p, инв,
                        ранд, младший, отсчётов=отсчётов, схема=н.схема)
    return None


#: Начало слова со вставками уточняется в стольких битах в обе стороны.
УТОЧНИТЬ = 3


def _уточнить(выборка, н: Набор, начала: list[int], инв: bool, ранд: str) -> list[int]:
    """Каждое начало — сдвиг в ±УТОЧНИТЬ бит, при котором нарушено меньше всего проверок (ранних
    сверочных и равномерных, умещающихся до следующего начала); при равенстве — исходное."""
    if len(начала) < 2:
        return начала
    короче = min(b - a for a, b in zip(начала, начала[1:], strict=False))
    проверки = н.ранние_сверка + [с for с in н.сверка if int(с.max()) < короче - УТОЧНИТЬ]
    if not проверки:
        return начала
    f = переворот(н, проверки, инв, ранд)
    сдвиги = np.arange(-УТОЧНИТЬ, УТОЧНИТЬ + 1)
    итог = []
    for t in начала:
        места = t + сдвиги
        места = места[(места >= 0) & (места + max(int(с.max()) for с in проверки) < len(выборка))]
        if not len(места):
            итог.append(t)
            continue
        нар = нарушения_в(выборка, проверки, места, f).sum(axis=1)
        лучшее = int(места[np.argmin(np.where(места == t, нар - 0.5, нар))])
        итог.append(лучшее)
    return итог


def _со_вставками(выборка, н: Набор, sv: np.ndarray, инв: bool, ранд: str, младший: bool) -> Кандидат | None:
    """Слова со вставками (заголовки, ASM, синхрослова) или иной длины (выколот хвост, повтор):
    позиции, где ранних проверок нарушено меньше всего, сверяются следующими ранними проверками —
    каждая отдельно (у случайных бит — вероятность не больше НАЧАЛО_СЛУЧАЙНО_ДО); принятые — начала
    слов, самый частый шаг между ними — период."""
    C2 = len(н.ранние_сверка)
    порог = порог_начала(C2)
    if порог < 0:
        return None
    места = np.flatnonzero(sv <= ОТБОР_НАЧАЛА_ДО * len(н.ранние))
    if len(места) < 2 or len(места) > len(sv) // 4:
        return None                     # проверки выполнены почти везде — заполнение, а не код
    if len(места) > ПОЗИЦИЙ_СВЕРКА:
        места = места[np.argpartition(sv[места], ПОЗИЦИЙ_СВЕРКА)[:ПОЗИЦИЙ_СВЕРКА]]
    нар = нарушения_в(выборка, н.ранние_сверка, места, переворот(н, н.ранние_сверка, инв, ранд)).sum(axis=1)
    годные = места[нар <= порог]
    if len(годные) < 2:
        return None
    порядок = np.argsort(годные)
    годные, нар = годные[порядок], нар[нар <= порог][порядок]
    # Одно слово — одно начало: соседние кандидаты ближе 64 бит — одно и то же (берётся лучший).
    начала: list[int] = []
    лучшее: list[int] = []
    for t, k in zip(годные.tolist(), нар.tolist(), strict=True):
        if начала and t - начала[-1] < 64:
            if k < лучшее[-1]:
                начала[-1], лучшее[-1] = t, k
            continue
        начала.append(t)
        лучшее.append(k)
    if len(начала) < 2:
        return None
    # У квазициклического кода слово, сдвинутое на бит, — почти кодовое (рвутся только проверки на
    # стыках циркулянтов): каждое начало уточняется в ±УТОЧНИТЬ бит всеми проверками, что умещаются.
    начала = _уточнить(выборка, н, начала, инв, ранд)
    шаг = период(начала, н.край)
    if шаг is None:
        return None
    # Слова внутри периода: остатки начал по периоду (кадр модема — ASM и несколько слов).
    остатки = _остатки(начала, шаг)
    if not остатки:
        return None
    свои = [i for i, t in enumerate(начала) if any(min((t - r) % шаг, шаг - (t - r) % шаг) <= 1 for r in остатки)]
    лучшее = [лучшее[i] for i in свои]
    if len(свои) < 2:
        return None
    повтор = False
    if len(остатки) == 1:
        # Ранние проверки выполняются и на повторе начала слова (5G NR при E > N): период, найденный по
        # ним, бывает долей настоящего. Берётся наименьшее кратное, при котором выполнены и проверки,
        # уходящие дальше в слово (все, что умещаются в период).
        шаг = _кратное(выборка, н, остатки[0] % шаг, шаг, инв, ранд)
        if шаг is None:
            return None
        смещения, слово = (0,), min(н.L, шаг)
        t0 = остатки[0] % шаг
        начала = list(range(t0, len(выборка) - н.край, шаг))
        повтор = шаг > н.L and _повтор(выборка, начала, н.L, шаг)
    else:
        t0 = остатки[0]
        смещения = tuple(r - t0 for r in остатки)
        промежутки = [b - a for a, b in zip(остатки, остатки[1:], strict=False)] + [остатки[0] + шаг - остатки[-1]]
        слово = min(н.L, min(промежутки))
        if слово < н.край:
            return None
        начала = sorted(t0 + f * шаг + о for f in range(len(выборка) // шаг + 1) for о in смещения
                        if t0 + f * шаг + о + н.край <= len(выборка))
        if not _годится(выборка, н, начала, слово, инв, ранд):
            return None
    if len(начала) < 2:
        return None
    доля = float(sum(лучшее)) / (len(лучшее) * C2)
    p = min(1.0, ПОЗИЦИЙ_СВЕРКА * случайно(max(лучшее) / C2, C2, 1) ** min(len(лучшее), 4))
    return Кандидат(н.имя, н.вид, н.L, начала[0], шаг, доля, 0.5, p, инв, ранд, младший,
                    начала=начала, отсчётов=len(лучшее) * C2, схема=н.схема, повтор=повтор,
                    смещения=смещения, слово=слово if слово < н.L or len(смещения) > 1 else 0)


def _остатки(начала: list[int], шаг: int) -> list[int]:
    """Остатки начал по периоду, что повторяются хотя бы дважды (соседние ±1 бит — один), по возрастанию."""
    счёт = Counter(t % шаг for t in начала)
    итог: list[tuple[int, int]] = []
    for r in sorted(счёт):
        if итог and r - итог[-1][0] <= 1:
            if счёт[r] > итог[-1][1]:
                итог[-1] = (r, итог[-1][1] + счёт[r])
            else:
                итог[-1] = (итог[-1][0], итог[-1][1] + счёт[r])
            continue
        итог.append((r, счёт[r]))
    return [r for r, c in итог if c >= 2] or ([итог[0][0]] if len(итог) == 1 else [])


def _годится(выборка: np.ndarray, н: Набор, начала: list[int], слово: int, инв: bool, ранд: str) -> bool:
    """У начал выполнены проверки, умещающиеся в слово (у трёх четвертей начал — не больше порога)."""
    проверки = [с for с in н.ранние_сверка + н.сверка if int(с.max()) < слово - 1]
    начала_ = np.array([t for t in начала if t + слово <= len(выборка)][:16], dtype=np.int64)
    if len(проверки) < 8 or not len(начала_):
        return False
    нар = нарушения_в(выборка, проверки, начала_, переворот(н, проверки, инв, ранд)).sum(axis=1)
    return bool((нар <= порог_начала(len(проверки))).mean() >= 0.75)


#: Кратных найденного периода — не больше стольких (и не длиннее 4 слов).
КРАТНЫХ_ДО = 16


def _кратное(выборка: np.ndarray, н: Набор, t0: int, D: int, инв: bool, ранд: str) -> int | None:
    """Наименьшее m·D, при котором у начал t0 + w·m·D выполнены проверки, умещающиеся в m·D (и в слово)."""
    for m in range(1, КРАТНЫХ_ДО + 1):
        шаг = m * D
        if шаг > 4 * н.L + 4096:
            break
        проверки = [с for с in н.ранние_сверка + н.сверка if int(с.max()) < min(шаг, н.L) - 1]
        начала = np.arange(t0, len(выборка) - min(шаг, н.L), шаг)[:8]
        if len(проверки) < 8 or len(начала) < 1:
            continue
        нар = нарушения_в(выборка, проверки, начала, переворот(н, проверки, инв, ранд)).sum(axis=1)
        if (нар <= порог_начала(len(проверки))).mean() >= 0.75:
            return шаг
    return None


def период(начала: list[int], наименьший: int) -> int | None:
    """Период слов по найденным началам (часть слов может быть пропущена, редкие — ложные): из
    разностей пар и их НОД — тот, которому кратно больше всего разностей (±1 бит); при равенстве —
    больший (половине периода кратны те же разности, но слова не там). Не меньше ``наименьший``."""
    if len(начала) < 2:
        return None
    н = np.array(sorted(начала)[:64], dtype=np.int64)
    разности = (н[None, :] - н[:, None])[np.triu_indices(len(н), 1)]
    разности = разности[разности >= max(1, наименьший)]
    if not len(разности):
        return None
    кандидаты = set(np.unique(разности)[:64].tolist())
    малые = np.unique(разности)[:12].tolist()
    кандидаты |= {math.gcd(a, b) for a in малые for b in малые if math.gcd(a, b) >= наименьший}
    лучший, счёт = None, -1
    for D in sorted(кандидаты):
        r = разности % D
        k = int(np.count_nonzero(np.minimum(r, D - r) <= 1))
        if k >= счёт:
            лучший, счёт = D, k
    return лучший


def _повтор(выборка: np.ndarray, начала: list[int], L: int, шаг: int) -> bool:
    """Вставка за словом — повтор его начала (круговой буфер 5G NR): совпадает почти бит в бит."""
    d = шаг - L
    годные = [t for t in начала if t + шаг <= len(выборка)]
    if not годные:
        return False
    вставки = np.array([выборка[t + L:t + шаг] for t in годные])
    начала_слов = np.array([выборка[t + np.arange(d) % L] for t in годные])
    return bool((вставки == начала_слов).mean() >= 0.9)


def опознать_вариант(биты: np.ndarray, н: Набор, *, младший: bool = False) -> list[Кандидат]:
    """Совпадения одного варианта: подряд (по сложению s(t) по словам) и со вставками (по позициям)."""
    L = н.L
    if len(н.ранние) < 3 or len(биты) < 2 * L:
        return []
    выборка, сдвигов, слов = _выборка(биты, L, н.край)
    if сдвигов <= 0:
        return []
    виды = виды_переворота(н)
    счёты = нарушения_по_сдвигам(выборка, н.ранние, сдвигов,
                                 [переворот(н, н.ранние, инв, ранд) for инв, ранд in виды[1:]])
    итог: list[Кандидат] = []
    for (инв, ранд), sv in zip(виды, счёты, strict=True):
        к = (_подряд(выборка, н, sv, слов, инв, ранд, младший)
             or _со_вставками(выборка, н, sv, инв, ранд, младший))
        if к is not None:
            итог.append(к)
    return итог


def опознать(биты: np.ndarray, *, имена: Sequence[str] | None = None, срок: float = 20.0,
             наборы: Sequence[Набор] | None = None, младший: bool = True,
             перемежения: bool = True) -> tuple[list[Кандидат], dict[str, object]]:
    """Все совпавшие варианты кодов, лучшие первыми, и сведения о переборе.

    ``имена`` — только эти встроенные коды (по умолчанию все, что умещаются в поток хотя бы дважды);
    ``наборы`` — ещё и свои (загруженные матрицы); ``младший`` — если в прямом порядке бит ничего
    нет, повторить в порядке «младший бит байта первым».
    """
    конец = time.monotonic() + срок
    биты = np.asarray(биты, dtype=np.uint8)
    список_ = list(наборы or [])
    свои = {н.имя for н in список_}
    вар = [(и, в) for и, в in варианты(имена, перемежения=перемежения)
           if и not in свои and 2 * ldpc_std.длина_в_потоке(и) <= len(биты)]
    сведения: dict[str, object] = {"вариантов": len(вар) + len(список_), "проверено": 0, "срок_вышел": False,
                                   "порядки": ["старший"]}
    найдено: list[Кандидат] = []
    for проход in ("старший", "младший"):
        if проход == "младший":
            if найдено or not младший or time.monotonic() > конец:
                break
            сведения["порядки"].append("младший")
            биты = биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1].reshape(-1)
        for н in список_:
            if time.monotonic() > конец:
                сведения["срок_вышел"] = True
                break
            найдено += опознать_вариант(биты, н, младший=проход == "младший")
            сведения["проверено"] += 1
        for имя, вид in вар:
            if time.monotonic() > конец:
                сведения["срок_вышел"] = True
                break
            строить = (имя, вид) not in _НАБОРЫ
            начато = time.monotonic()
            try:
                н = набор(имя, вид)
            except ValueError:
                continue
            if строить:
                # Построение набора (один раз на процесс, дальше — с диска) в срок перебора не входит.
                конец += time.monotonic() - начато
            найдено += опознать_вариант(биты, н, младший=проход == "младший")
            сведения["проверено"] += 1
    найдено.sort(key=lambda к: (к.нарушено, к.случайно))
    сохранить_кэш()
    return найдено, сведения


