CCSDS_ПРЕФИКСЫ = ("ar4ja-", "ccsds-")


@dataclass
class Набор:
    """Проверки одного варианта кода (код, схема стандарта, перемежение) — в номерах переданного слова."""
    имя: str
    вид: str
    L: int
    ранние: list[np.ndarray]
    сверка: list[np.ndarray]
    край: int                 # ранние проверки — в позициях 0 … край − 1
    рандомизатор: str = ""
    схема: object = None      # своя схема (загруженная матрица); у встроенного — по стандарту
    ранние_сверка: list[np.ndarray] = field(default_factory=list)   # следующие ранние — сверка начал

    def поправки(self, проверки: list[np.ndarray]) -> np.ndarray:
        """Чётность ПСП рандомизатора на позициях каждой проверки (без рандомизатора — нули)."""
        if not self.рандомизатор:
            return np.zeros(len(проверки), dtype=np.uint8)
        пс = псп_ccsds(self.L)
        return np.array([int(пс[с].sum() & 1) for с in проверки], dtype=np.uint8)


@dataclass
class Кандидат:
    """Код в потоке: что, где границы, насколько уверенно."""
    имя: str
    вид: str                  # перемежение бит перед модуляцией («» — нет)
    L: int                    # длина слова в потоке по схеме
    начало: int               # первое начало слова в выборке
    шаг: int                  # период: от начала группы слов до начала следующей (подряд — L)
    нарушено: float           # доля нарушенных проверок сверки при найденных началах
    медиана: float            # у чужих начал
    случайно: float           # вероятность случайного совпадения (с поправкой на число начал)
    инверсия: bool = False
    рандомизатор: str = ""
    младший: bool = False     # порядок «младший бит байта первым»
    начала: list[int] = field(default_factory=list)
    отсчётов: int = 0
    повтор: bool = False      # вставка — повтор начала слова (согласование скорости 5G NR, E > N)
    схема: object = None      # своя схема (загруженная матрица); None — встроенный код по стандарту
    смещения: tuple = (0,)    # начала слов внутри периода (ASM и несколько слов в кадре — несколько)
    слово: int = 0            # слово в потоке, бит (0 — L, а если шаг короче L при одном слове — шаг)

    @property
    def длина_слова(self) -> int:
        """Сколько бит слова в потоке: меньше L — выколот хвост (согласование скорости)."""
        if self.слово:
            return self.слово
        return min(self.L, self.шаг) if len(self.смещения) == 1 else self.L

    @property
    def доля(self) -> float:
        """Доля выполненных проверок."""
        return 1.0 - self.нарушено

    def вариант(self) -> str:
        if self.схема is not None:
            база = ("по схеме, сохранённой с матрицей" if len(self.схема.выколоты) or len(self.схема.укорочены)
                    else "слово передаётся целиком")
        else:
            база = "по схеме стандарта" if ldpc_std.выколоты_по_стандарту(self.имя) else "слово передаётся целиком"
        части = [база]
        if self.вид:
            части.append(f"перемежение бит {self.вид} ({ldpc_std.столбцы_перемежения(self.имя, self.вид)})"
                         if self.вид != ldpc_std.КАНАЛ_1367 else "перемежение 1367·i mod M")
        длина = self.длина_слова
        if длина < self.L:
            части.append(f"выколоты последние {self.L - длина} переданных позиций (согласование скорости)")
        вставка = self.шаг - len(self.смещения) * длина
        if len(self.смещения) > 1:
            части.append(f"в периоде {self.шаг} бит слов — {len(self.смещения)} (смещения "
                         f"{', '.join(map(str, self.смещения))})" + (f", вставка {вставка} бит" if вставка > 0 else ""))
        elif self.повтор and вставка > 0:
            части.append(f"за словом повторены его первые {вставка} бит (согласование скорости)")
        elif вставка > 0:
            части.append(f"между словами вставки по {вставка} бит")
        if self.инверсия:
            части.append("поток инверсный")
        if self.рандомизатор:
            части.append(f"рандомизатор {self.рандомизатор} поверх блока")
        if self.младший:
            части.append("порядок бит в байте файла — младший первым")
        return "; ".join(части)

    def словарь(self) -> dict[str, object]:
        return {"код": self.имя, "перемежение": self.вид, "L": self.L, "начало": self.начало, "шаг": self.шаг,
                "доля": round(self.доля, 4), "медиана": round(1 - self.медиана, 4),
                "случайно": float(f"{self.случайно:.2e}"), "инверсия": self.инверсия,
                "рандомизатор": self.рандомизатор, "младший": self.младший, "вариант": self.вариант(),
                "начал": len(self.начала), "повтор": self.повтор, "смещения": list(self.смещения),
                "слово": self.длина_слова}


