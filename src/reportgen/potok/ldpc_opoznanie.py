def схема_кандидата(к: Кандидат):
    """Схема передачи кандидата: стандарта (или загруженная), с выколотым хвостом, если слово в потоке
    короче."""
    база = к.схема if к.схема is not None else ldpc_std.схема(к.имя, к.вид)
    d = к.L - к.длина_слова
    if d <= 0:
        return база
    return ldpc.Схема(база.матрица, np.union1d(база.выколоты, база.переданы[к.L - d:]), база.укорочены,
                      база.переданы[:к.L - d] if база.порядок is not None else None)


def начала_слов(биты: np.ndarray, к: Кандидат, схема, слов_до: int) -> np.ndarray:
    """Начала слов во всём ряду: группы слов (смещения внутри периода) от начала кандидата с его шагом,
    а если начало найдено не первым — и назад до начала ряда."""
    L = схема.длина
    шаг = max(к.шаг, L) if len(к.смещения) == 1 else к.шаг
    t = к.начало - (к.начало // шаг) * шаг if к.начала else к.начало
    итог = (t + шаг * np.arange(max(0, (len(биты) - t) // шаг + 1), dtype=np.int64))[:, None] + \
        np.asarray(к.смещения, dtype=np.int64)[None, :]
    итог = итог.reshape(-1)
    return итог[итог + L <= len(биты)][:слов_до]


def слова_кандидата(биты: np.ndarray, к: Кандидат, схема, слов_до: int = 4000) -> np.ndarray:
    """Принятые слова (слов × длина в потоке) с инверсией и снятым рандомизатором."""
    if к.младший:
        биты = биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1].reshape(-1)
    начала = начала_слов(биты, к, схема, слов_до)
    L = схема.длина
    if not len(начала):
        return np.zeros((0, L), dtype=np.uint8)
    слова = биты[начала[:, None] + np.arange(L)[None, :]].astype(np.uint8)
    if к.инверсия:
        слова ^= 1
    if к.рандомизатор:
        слова ^= псп_ccsds(к.L)[:L]
    return слова


def _повторы(биты: np.ndarray, к: Кандидат, схема, слов: int) -> np.ndarray:
    """Мягкие значения повторённых за словом бит (слов × (шаг − L)); где повтора нет (конец записи) — 0."""
    if к.младший:
        биты = биты[:len(биты) // 8 * 8].reshape(-1, 8)[:, ::-1].reshape(-1)
    начала = начала_слов(биты, к, схема, слов)
    L, d = схема.длина, max(0, к.шаг - схема.длина)
    итог = np.zeros((len(начала), d), dtype=np.float32)
    есть = начала + L + d <= len(биты)
    доп = биты[начала[есть][:, None] + L + np.arange(d)[None, :]].astype(np.float32)
    if к.инверсия:
        доп = 1.0 - доп
    итог[есть] = 1.0 - 2.0 * доп
    return итог


def снять(биты: np.ndarray, к: Кандидат, *, схема=None, итераций: int = 50, слов_до: int = 4000,
          пачка: int = 16) -> tuple[np.ndarray, list[str], float]:
    """Декодирование (нормированный «минимум — сумма», 0,75) и данные k бит каждого слова подряд:
    (данные, строки отчёта, доля слов с обнулившимся синдромом)."""
    схема = схема or схема_кандидата(к)
    принятые = слова_кандидата(np.asarray(биты, dtype=np.uint8), к, схема, слов_до)
    слов = len(принятые)
    if not слов:
        raise ValueError("в потоке нет ни одного целого слова")
    связи = схема.матрица.связи()
    данные = ldpc.информационные(схема.матрица)
    повторы = _повторы(np.asarray(биты, dtype=np.uint8), к, схема, слов) if к.повтор else None
    итог, сошлось, исправлено = [], 0, 0
    for от in range(0, слов, пачка):
        кусок = принятые[от:от + пачка]
        llr = схема.llr(кусок)
        if повторы is not None:
            # Повторённые биты — ещё одно наблюдение тех же позиций: мягкие значения складываются.
            доп = повторы[от:от + пачка]
            куда = схема.переданы[np.arange(доп.shape[1]) % схема.длина]
            np.add.at(llr, (slice(None), куда), доп)
        слова, ок = ldpc.мин_сумма(llr, связи, схема.матрица.n, итераций)
        сошлось += int(ок.sum())
        исправлено += int((слова[:, схема.переданы] != кусок).sum())
        итог.append(слова[:, данные])
    L = схема.длина
    подробно = [
        f"код ({схема.матрица.n}, {len(данные)}), {схема.матрица.откуда}; в потоке слово {L} бит: "
        f"выколото {len(схема.выколоты)}, укорочено {len(схема.укорочены)}",
        f"слов {слов}: синдром обнулился у {сошлось} ({сошлось / слов * 100:.1f} %); исправлено бит "
        f"{исправлено} ({исправлено / (слов * L) * 100:.3f} % принятых — оценка ошибок линии)",
        f"на выходе — информационные биты: {ldpc.информационные_сводка(схема.матрица)[1]}",
    ]
    if сошлось < слов * 0.5:
        подробно.append("меньше половины слов сошлось — ошибок больше, чем исправляет код, или схема не та")
    return np.concatenate(итог, axis=0).reshape(-1), подробно, сошлось / слов


def пробное(биты: np.ndarray, к: Кандидат, слов: int = ПРОБНЫХ_СЛОВ) -> tuple[float, float]:
    """Пробное декодирование нескольких слов: (доля сошедшихся, доля исправленных принятых бит)."""
    схема = схема_кандидата(к)
    принятые = слова_кандидата(np.asarray(биты, dtype=np.uint8), к, схема, слов)
    if not len(принятые):
        return 0.0, 1.0
    слова, ок = ldpc.мин_сумма(схема.llr(принятые), схема.матрица.связи(), схема.матрица.n, 50)
    return float(ок.mean()), float((слова[:, схема.переданы] != принятые).mean())


def выбрать(биты: np.ndarray, кандидаты: list[Кандидат]) -> tuple[Кандидат | None, str]:
    """Лучший кандидат: по доле нарушенных проверок; почти равные — пробным декодированием."""
    if not кандидаты:
        return None, ""
    лучший = кандидаты[0]
    почти = [к for к in кандидаты if к.нарушено <= лучший.нарушено + max(РАВНЫЕ_ДО, 0.5 * лучший.нарушено)]
    if len(почти) < 2:
        return лучший, ""
    почти = почти[:РАВНЫХ_ПРОБОВАТЬ]
    пробы = [пробное(биты, к) for к in почти]
    i = min(range(len(почти)), key=lambda i: (-пробы[i][0], пробы[i][1], почти[i].нарушено))
    return почти[i], ("почти равные по проверкам варианты различены пробным декодированием "
                      f"{ПРОБНЫХ_СЛОВ} слов (сошлось, исправлено принятых бит): " + "; ".join(
                          f"«{к.имя}» {к.вариант()}, начало {к.начало} — {п[0] * 100:.0f} %, {п[1] * 100:.2f} %"
                          + (" ← выбран" if j == i else "") for j, (к, п) in enumerate(zip(почти, пробы, strict=True))))


def находка(биты: np.ndarray, к: Кандидат, *, сведения: dict | None = None, выбор: str = "",
            итераций: int = 50, слов_до: int = 4000, перебор: str | None = None):
    """Снять код кандидата и оформить находкой разбора."""
    from .nahodka import Находка  # noqa: PLC0415
    схема = схема_кандидата(к)
    данные, подробно, сошлось = снять(биты, к, схема=схема, итераций=итераций, слов_до=слов_до)
    м = схема.матрица
    k = len(ldpc.информационные(м))
    сведения = сведения or {}
    перебор = перебор or (f"опознан по синдрому: вариантов кодов {сведения.get('вариантов', '?')}, проверено "
               f"{сведения.get('проверено', '?')}" + (" (срок вышел раньше)" if сведения.get("срок_вышел") else "")
               + f"; начало слова — бит {к.начало}" + (f", шаг {к.шаг}" if к.шаг != к.L else "")
               + (f", смещения слов в периоде {', '.join(map(str, к.смещения))}" if len(к.смещения) > 1 else ""))
    return Находка(
        уровень="код",
        что=f"LDPC ({м.n}, {k}) по матрице «{к.имя}»" + (f" ({м.откуда})" if м.откуда else "") + f"; {к.вариант()}",
        уверенность=float(сошлось),
        мера=f"проверки H при найденной границе слова выполнены в {к.доля * 100:.1f} % ({к.отсчётов} отсчётов; "
             f"при чужой границе — около {(1 - к.медиана) * 100:.0f} %); синдром обнулился у {сошлось * 100:.1f} % слов",
        подробно=[перебор] + ([выбор] if выбор else []) + подробно,
        дальше=данные, вид_дальше="биты",
        свойства={"n": м.n, "k": k, "матрица": к.имя, "начало": к.начало, "шаг": к.шаг,
                  "выколото": int(len(схема.выколоты)), "укорочено": int(len(схема.укорочены)),
                  "схема": схема, "данных_в_блоке": k, "кандидат": к.словарь(), "объект_кандидата": к,
                  "перемежение": к.вид, "инверсия": к.инверсия, "младший": к.младший})


def найти(биты: np.ndarray, *, имена: Sequence[str] | None = None, срок: float = 20.0,
          наборы: Sequence[Набор] | None = None, младший: bool = True):
    """Опознать и снять: находка разбора или None."""
    кандидаты, сведения = опознать(биты, имена=имена, срок=срок, наборы=наборы, младший=младший)
    к, выбор = выбрать(биты, кандидаты)
    if к is None:
        return None
    return находка(биты, к, сведения=сведения, выбор=выбор)
