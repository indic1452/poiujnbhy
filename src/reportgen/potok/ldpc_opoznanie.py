"""Опознаватель кодов LDPC по синдрому: какой из встроенных (и загруженных) кодов в потоке и где границы слов.

Матрица проверок разрежена: проверка — 3…30 позиций слова. Если слово начинается в позиции t, то
сумма бит потока на позициях проверки, сдвинутых на t, равна нулю (у ошибки линии — изредка
единице); при чужом t или чужом коде — нулю или единице поровну. Так считается сразу для всех
сдвигов: для каждой проверки — XOR нескольких сдвинутых копий потока (по позиции на каждую единицу
строки), и число нарушенных проверок s(t) — для каждого t одним проходом. Это и есть «свёртка
по позициям»: БПФ не нужно, потому что строка H — несколько единиц, а не плотный вектор.

Дальше по s(t) — два вида границы:

- **слова подряд** (длина слова L по схеме стандарта): s(t) складывается по словам — для каждого
  начала o сумма s(o + w·L) по W словам; лучшие начала сверяются большим набором проверок;
- **слова со вставками или неизвестной длины** (заголовки PLHEADER, ASM CCSDS, синхрослова
  кадров модема, согласование скорости 5G NR/802.11n): проверки берутся «ранние» — по началу
  слова, — позиции с почти нулевым s(t) — начала слов; шаг между ними — период, его разность с
  L — вставка (или выколотый хвост, если период короче слова).

Совпадение засчитывается по точному хвосту биномиального распределения: доля нарушенных проверок
при лучшем начале у случайных бит (каждая нарушена с вероятностью ½) получилась бы с вероятностью
не больше ``СЛУЧАЙНО_ДО`` с поправкой на число перебранных начал. Ошибки линии повышают долю
нарушенных проверок веса d до (1 − (1 − 2p)^d)/2: при p = 10⁻² и d = 30 — до 0,23, а выборка в
сотни проверок на начало отделяет это от ½ с запасом.

Сразу же, без пересчёта, проверяются: инверсия всех бит (у проверки нечётного веса чётность
меняется), рандомизатор CCSDS поверх кодового блока (сумма ПСП по позициям проверки — постоянная
поправка к чётности); перемежение бит DVB-S2/S2X перед модуляцией — отдельные наборы проверок;
порядок «младший бит байта первым» — второй проход, если в прямом ничего нет.
"""

