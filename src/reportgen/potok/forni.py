"""Свёрточное перемежение Форни любых параметров — вслепую.

Перемежитель Форни: I ветвей, в ветви j — задержка j·M ячеек; единица
(бит или байт) номер k идёт по ветви k mod I. Снимается он, если известны
I, M и фаза ветвей (какая единица шла по ветви 0).

Перебор строится на свойстве, которое легко проверить выкладкой: если
снимать с верными I, M, но неверной фазой, исходный поток восстанавливается
почти весь, только кусками с двумя постоянными сдвигами — внутри куска
проверки кода, стоявшего до перемежения, уже видны. Поэтому сперва грубый
перебор (I, M) при одной фазе — по силе проверок кода в снятом потоке, —
затем для лучших пар — все фазы. Для малых I (где куски короче окна
проверок) фазы перебираются сразу.

Задержка у ветвей бывает и в обратном порядке (у ветви 0 — наибольшая);
это тот же перемежитель с другой фазой, и перебор фаз его покрывает.
"""

from __future__ import annotations

import numpy as np

from .kod import проверки
from .nahodka import Находка

ОКНО = 16
#: Пределы перебора: ветвей и ячеек.
I_ДО = 64
M_ДО = 64
#: Сколько бит снятого потока смотреть при переборе.
ОТСЕВ = 1 << 14
ВЫБОРКА = 1 << 20


def _сила(ряд: np.ndarray) -> float:
    смещения, окон = проверки(ряд, ОКНО, 1)
    if окон < 256:
        return 0.0
    смещения[0] = 0
    return float(np.abs(смещения).max() * np.sqrt(окон))


def снять(единицы: np.ndarray, I: int, M: int, фаза: int) -> np.ndarray:
    """Обратное перемежение: единица m исходного лежит на m + j·M·I, j = (m − фаза) mod I."""
    сколько = max(0, len(единицы) - (I - 1) * M * I)
    m = np.arange(сколько)
    j = (m - фаза) % I
    return единицы[m + j * M * I]


def перемежить(единицы: np.ndarray, I: int, M: int, фаза: int = 0) -> np.ndarray:
    k = np.arange(len(единицы))
    j = (k - фаза) % I
    откуда = k - j * M * I
    итог = np.zeros(len(единицы), dtype=единицы.dtype)
    годные = откуда >= 0
    итог[годные] = единицы[откуда[годные]]
    return итог


def найти(биты: np.ndarray, *, I_до: int = I_ДО, M_до: int = M_ДО,
          бюджет: float = 120.0) -> Находка | None:
    """Свёрточный перемежитель над кодом: I, M, фаза (по битам)."""
    import time
    конец = time.monotonic() + бюджет
    выборка = биты[:ВЫБОРКА]
    if len(выборка) < 1 << 16:
        return None
    как_есть = _сила(выборка[:1 << 16])
    грубо = []
    for I in range(2, I_до + 1):
        for M in range(1, M_до + 1):
            if (I - 1) * M * I + ОТСЕВ > len(выборка) or time.monotonic() > конец:
                break
            фазы = range(I) if I < ОКНО else (0,)
            лучшая = max(_сила(снять(выборка[:ОТСЕВ + (I - 1) * M * I], I, M, ф)[:ОТСЕВ])
                         for ф in фазы)
            грубо.append((лучшая, I, M))
    if len(грубо) < 8:
        return None
    база = float(np.median([с for с, _, _ in грубо]))
    грубо.sort(reverse=True)
    if грубо[0][0] < max(10.0, 2 * база, 1.5 * как_есть):
        return None
    итог: tuple[float, int, int, int] | None = None
    # Пары с одним произведением M·I сдвигают соседние биты одинаково и на
    # грубом переборе почти неотличимы (24 × 3 и 36 × 2): на уточнение идут
    # все разложения произведений лучших пар.
    уточнить = []
    for _, I, M in грубо[:4]:
        for I_ in range(2, I_до + 1):
            if (I * M) % I_ == 0 and (I_, I * M // I_) not in уточнить:
                уточнить.append((I_, I * M // I_))
    for I, M in уточнить:
        for фаза in range(I):
            снято = снять(выборка, I, M, фаза)
            if len(снято) < 1 << 15:
                continue
            сила = _сила(снято[:1 << 16])
            # При равной силе — меньшее произведение M·I: кратные пары (2I, M/2)
            # дают тот же сдвиг у части ветвей.
            if итог is None or сила > итог[0] + 1e-9:
                итог = (сила, I, M, фаза)
    # Порог уже пройден на грубом переборе: уточнение перебирает и ту же
    # пару, так что итог не слабее грубого лучшего.
    if итог is None:
        return None
    сила, I, M, фаза = итог
    снято = снять(биты, I, M, фаза)
    return Находка(
        уровень="перемежение",
        что=f"свёрточное перемежение Форни: I = {I} ветвей, M = {M}, по битам",
        уверенность=min(1.0, сила / 60),
        мера=f"после снятия проверки кода — {сила:.0f} сигм шума, до — {как_есть:.0f} "
             f"(медиана по всем парам I, M — {база:.0f})",
        подробно=[f"перебрано пар (I, M): {len(грубо)}; фаза ветвей — {фаза} (ветвь с "
                  f"нулевой задержкой)",
                  f"соседние биты исходного потока стоят через 1 + M·I = {1 + M * I}",
                  f"снято: {len(снято)} бит; хвост {(I - 1) * M * I} бит восстановить нельзя — "
                  f"его части ещё в задержках"],
        дальше=снято, вид_дальше="биты")
