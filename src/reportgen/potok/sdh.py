# -*- coding: utf-8 -*-
"""SDH и SONET (ITU-T G.707, ANSI T1.105): STM-0…STM-64, AU-4 и AU-3, VC-4/VC-3,
TU-12 → VC-12 → E1 и TU-3 → VC-3.

Всё держится на проверках, которые стандарт сам закладывает в кадр, — они и
доказывают, что разбор верен, а не выдуман по памяти:

- **кадр** — A1 A1 A1 A2 A2 A2 (F6 F6 F6 28 28 28) через ровно 6480·M бит, где
  M — число единиц STS-1 (1 — STM-0/STS-1, 3 — STM-1, 12 — STM-4 …);
- **кадровый скремблер** — ищется вслепую по устойчивым столбцам (как у любого
  кадрового скремблера, модуль skrembler), первая строка RSOH (3·M байт) не
  скремблируется; подтверждение — **B1**: BIP-8 по всему скремблированному
  предыдущему кадру совпадает с байтом B1 текущего после снятия;
- **указатели** H1 H2 — у каждой единицы STS-1; единицы с признаком сцепки
  (1001 SS 11 1111 1111) продолжают предыдущую: три — AU-4, 3·X — AU-4-Xc;
- **VC-4 / VC-3** — по указателю; подтверждение — **B3**: BIP-8 по предыдущему
  VC совпадает с байтом B3; трассы J0 и J1, метка C2 — как есть (что значит
  метка — не по памяти: спросите помощника, стандарт — в библиотеке);
- **TU-12** — в VC-4 (через TUG-3 и TUG-2) и в VC-3 (через TUG-2): фаза
  сверхцикла из четырёх кадров — по годности указателей V1 V2, VC-12 — по
  указателю; подтверждение — **V5**, BIP-2 по предыдущему VC-12. Асинхронное
  отображение E1 — со стаффингом по битам C1 C2 (большинство из трёх);
  подтверждение — **FAS E1** в выделенном притоке;
- **TU-3** — в TUG-3 с указателем H1 H2 H3; подтверждение — B3 VC-3.

Где стандарт допускает два прочтения (с какого байта считается смещение
указателя TU-3, входит ли V5 в BIP-2), пробуются оба — решает проверка.
Цифры, которые проверками не подтвердились, находкой не считаются.
"""

from __future__ import annotations

from collections import Counter
from typing import Dict, List, Optional, Sequence, Tuple

import numpy as np

from . import cikl, skrembler, sinhro
from .nahodka import Находка

A1, A2 = 0xF6, 0x28
СТРОК = 9
#: Единиц STS-1 в кадре и имена уровней.
ИМЕНА = {1: "STM-0 (STS-1)", 3: "STM-1 (STS-3)", 12: "STM-4 (STS-12)",
         48: "STM-16 (STS-48)", 192: "STM-64 (STS-192)"}
#: Кадров на разбор: у STM-1 это 64 мс, у STM-64 — 125 мкс × 64.
КАДРОВ_ДО = 512
#: Сколько VC-12 разбирать до притоков E1 (у STM-1 их 63).
TU12_ДО = 63
ВЫБОРКА = 1 << 23


# -- кадр ---------------------------------------------------------------------------------

def _байтами(значения: Sequence[int]) -> np.ndarray:
    return np.unpackbits(np.array([int(в) for в in значения], dtype=np.uint8))


def выравнивание(биты: np.ndarray) -> Optional[Tuple[int, int]]:
    """Начало кадра (бит) и M — число единиц STS-1; None — кадра SDH нет."""
    for слово, смещение_байт in ((_байтами([A1] * 3 + [A2] * 3), None), (_байтами([A1, A2]), 0)):
        н = sinhro.несовпадения(биты, слово)
        места = np.flatnonzero(н == 0)
        if len(места) < 4:
            continue
        шаги = Counter(np.diff(места).tolist())
        for шаг, раз in шаги.most_common(3):
            if шаг % 6480 or шаг // 6480 not in ИМЕНА or раз < 3:
                continue
            M = шаг // 6480
            if смещение_байт is None and M < 3:
                continue
            if смещение_байт == 0 and M != 1:
                continue
            сдвиг = (M - 3) * 8 if смещение_байт is None else 0
            есть = set(места.tolist())
            for п in места.tolist():
                if п + шаг in есть and п + 2 * шаг in есть and п - сдвиг >= 0:
                    return п - сдвиг, M
    return None


def _колонки(M: int) -> Tuple[np.ndarray, np.ndarray]:
    """Столбец кадра → (единица STS-1, её местный столбец 0…89).

    STM-N — это N кадров STM-1, чередующихся по байтам, а в STM-1 чередуются
    три единицы: столбец c принадлежит STM-1 № c mod N, в нём — единице
    (c div N) mod 3; местный столбец — c div 3N.
    """
    c = np.arange(90 * M)
    if M == 1:
        return np.zeros_like(c), c
    N = M // 3
    return (c % N) * 3 + (c // N) % 3, c // M


def _ксор(кадры: np.ndarray) -> np.ndarray:
    return np.bitwise_xor.reduce(кадры, axis=1)


def _снять_скремблер(байты: np.ndarray, M: int, отводы, начальное) -> np.ndarray:
    L = байты.shape[1] * 8
    пропуск = 3 * M * 8
    маска = np.packbits(skrembler.псп(отводы, np.asarray(начальное, dtype=np.uint8), L - пропуск))
    снято = байты.copy()
    снято[:, 3 * M:] ^= маска
    return снято


def _b1(скремблированные: np.ndarray, снятые: np.ndarray, M: int) -> float:
    if len(снятые) < 2:
        return 0.0
    return float(np.mean(_ксор(скремблированные[:-1]) == снятые[1:, 90 * M]))


def _трасса(байты: np.ndarray) -> str:
    """Трасса J0/J1: 16 байт со старшим битом первого (CRC-7), 64 байта с CR LF или один байт."""
    ряд = [int(б) for б in байты[:128]]
    if not ряд:
        return ""
    if len(set(ряд)) == 1:
        return f"один байт 0x{ряд[0]:02X}"
    for длина in (16, 64):
        if len(ряд) < 2 * длина:
            continue
        if all(ряд[i] == ряд[i + длина] for i in range(длина)):
            кусок = ряд[:длина]
            if длина == 16:
                старт = next((i for i in range(16) if кусок[i] & 0x80), 0)
                кусок = кусок[старт:] + кусок[:старт]
                текст = bytes(б & 0x7F for б in кусок[1:])
            else:
                текст = bytes(кусок)
            печатное = "".join(chr(б) if 32 <= б < 127 else "·" for б in текст).rstrip("· ")
            return f"{длина} байт: «{печатное}»"
    return "переменная (" + " ".join(f"{б:02X}" for б in ряд[:8]) + " …)"


# -- указатели ----------------------------------------------------------------------------

def указатель(h1: int, h2: int) -> Tuple[str, int]:
    """(вид, значение): «норма», «новые данные», «сцепка», «AIS» или «ошибка»."""
    слово = (int(h1) << 8) | int(h2)
    ndf, значение = слово >> 12, слово & 0x3FF
    if слово == 0xFFFF:
        return "AIS", -1
    if ndf == 0b1001 and значение == 0x3FF:
        return "сцепка", -1
    if ndf == 0b0110:
        return "норма", значение
    if ndf == 0b1001:
        return "новые данные", значение
    return "ошибка", значение


def _большинство(значения: Sequence[int]) -> int:
    return Counter(int(в) for в in значения).most_common(1)[0][0]


# -- VC по указателю ----------------------------------------------------------------------

def _vc(область: np.ndarray, указатели: Sequence[int], единица: int, база_строк: int
        ) -> Tuple[List[np.ndarray], int]:
    """VC по кадрам из области нагрузки (кадры × 9 × R): J1 — по указателю кадра.

    Смещение 0 — первый байт строки ``база_строк``; дальше строки подряд и
    первые строки следующего кадра. Возвращает VC и число смен указателя.
    """
    кадров, _, R = область.shape
    ряд = область.reshape(-1)
    размер = СТРОК * R
    итог, смен, прежний = [], 0, None
    for f in range(кадров):
        p = указатели[f]
        if p < 0:
            p = прежний
        if p is None:
            continue
        if прежний is not None and p != прежний:
            смен += 1
        прежний = p
        начало = f * размер + база_строк * R + p * единица
        if начало + размер <= len(ряд):
            итог.append(ряд[начало:начало + размер])
    return итог, смен


def _b3(vc: List[np.ndarray], R: int) -> float:
    if len(vc) < 2:
        return 0.0
    return float(np.mean([_ксор(vc[i - 1][None, :])[0] == vc[i][R] for i in range(1, len(vc))]))


# -- TU-12 → VC-12 → E1 ------------------------------------------------------------------

def _tu12_столбцы_vc4(t: int, m: int, n: int) -> List[int]:
    """Столбцы VC-4 (0…260), занятые TU-12 (TUG-3 t, TUG-2 m, TU-12 n; с нуля).

    VC-4: столбец POH, два столбца заполнения, дальше три TUG-3 вперемежку;
    в TUG-3 два первых столбца служебные, дальше семь TUG-2 вперемежку; в TUG-2
    три TU-12 вперемежку, по 4 столбца у каждого.
    """
    return [3 + t + 3 * (2 + m + 7 * (n + 3 * i)) for i in range(4)]


def _tu12_столбцы_vc3(m: int, n: int) -> List[int]:
    """Столбцы VC-3 из 87 (с заполнением 29 и 58), занятые TU-12 (TUG-2 m, TU-12 n)."""
    нагрузка = [c for c in range(1, 87) if c not in (29, 58)]
    return [нагрузка[m + 7 * (n + 3 * i)] for i in range(4)]


def _bip2(байты: np.ndarray) -> int:
    биты = np.unpackbits(байты.astype(np.uint8)).reshape(-1, 8)
    нечётные = int(биты[:, 0::2].sum()) & 1
    чётные = int(биты[:, 1::2].sum()) & 1
    return (нечётные << 1) | чётные


def vc12(tu: np.ndarray) -> Optional[Dict[str, object]]:
    """Байты TU-12 по кадрам (кадры × 36) → VC-12 по сверхциклам, с проверкой V5.

    Фаза сверхцикла (какой кадр несёт V1) — та, при которой указатели V1 V2
    годны (NDF 0110, размер 10, значение 0…139) чаще всего.
    """
    кадров = len(tu)
    if кадров < 12:
        return None
    лучшая = None
    for фаза in range(4):
        циклов = (кадров - фаза) // 4
        if циклов < 3:
            continue
        s = tu[фаза:фаза + 4 * циклов].reshape(циклов, 144)
        v1, v2 = s[:, 0].astype(int), s[:, 36].astype(int)
        слово = (v1 << 8) | v2
        годен = ((слово >> 12) == 0b0110) & (((слово >> 10) & 3) == 0b10) & ((слово & 0x3FF) <= 139)
        доля = float(годен.mean())
        if лучшая is None or доля > лучшая[0]:
            лучшая = (доля, фаза, s, слово & 0x3FF, годен)
    if лучшая is None or лучшая[0] < 0.5:
        return None
    доля, фаза, s, значения, годен = лучшая
    p = _большинство(значения[годен])
    циклов = len(s)
    # Смещение 0 — байт после V2; порядок: после V2, после V3, после V4, после V1 следующего.
    q = np.concatenate([np.concatenate([s[k, 37:72], s[k, 73:108], s[k, 109:144], s[k + 1, 1:36]])
                        for k in range(циклов - 1)])
    vc = [q[140 * k + p:140 * k + p + 140] for k in range(циклов - 2)]
    if len(vc) < 3:
        return None
    совпало = {}
    for с_v5 in (True, False):
        верных = sum(((int(vc[i][0]) >> 6) & 3) == _bip2(vc[i - 1] if с_v5 else vc[i - 1][1:])
                     for i in range(1, len(vc)))
        совпало[с_v5] = верных / (len(vc) - 1)
    с_v5 = совпало[True] >= совпало[False]
    return {"vc": vc, "указатель": p, "фаза": фаза, "годных_указателей": доля,
            "v5": совпало[с_v5], "v5_с_собой": с_v5}


def e1_из_vc12(vc: Sequence[np.ndarray]) -> Tuple[np.ndarray, Dict[str, float]]:
    """Асинхронное отображение E1 в VC-12: данные, C1/C2 большинством, S1/S2 по ним."""
    части, s1_стафф, s2_стафф = [], 0, 0
    for в in vc:
        биты = np.unpackbits(np.asarray(в, dtype=np.uint8)).reshape(140, 8)
        c1 = int(биты[[36, 71, 106], 0].sum()) >= 2
        c2 = int(биты[[36, 71, 106], 1].sum()) >= 2
        s1_стафф += c1
        s2_стафф += c2
        кусок = [биты[2:34].reshape(-1), биты[37:69].reshape(-1), биты[72:104].reshape(-1)]
        if not c1:
            кусок.append(биты[106, 7:8])
        if not c2:
            кусок.append(биты[107, 0:1])
        кусок += [биты[107, 1:8], биты[108:139].reshape(-1)]
        части.append(np.concatenate(кусок))
    n = max(1, len(vc))
    return (np.concatenate(части).astype(np.uint8) if части else np.zeros(0, np.uint8),
            {"S1_пустой": s1_стафф / n, "S2_пустой": s2_стафф / n})


# -- разбор ------------------------------------------------------------------------------

def _группы(указатели_единиц: List[Tuple[str, int]]) -> List[Tuple[int, int, int]]:
    """(первая единица, сколько единиц, указатель) — AU-3, AU-4 и сцепки."""
    итог = []
    for u, (вид, значение) in enumerate(указатели_единиц):
        if вид in ("норма", "новые данные") and 0 <= значение <= 782:
            итог.append([u, 1, значение])
        elif вид == "сцепка" and итог and итог[-1][0] + итог[-1][1] == u:
            итог[-1][1] += 1
    return [tuple(г) for г in итог]


def найти(биты: np.ndarray) -> Находка | None:
    """SDH/SONET: кадр, скремблер по B1, AU/VC по указателям с B3, TU-12/TU-3 внутри."""
    выборка = биты[:ВЫБОРКА]
    кадр = выравнивание(выборка)
    if кадр is None:
        return None
    начало, M = кадр
    L = 6480 * M
    кадров = min(КАДРОВ_ДО, (len(биты) - начало) // L)
    if кадров < 4:
        return None
    ряд = биты[начало:начало + кадров * L]
    байты = np.packbits(ряд.reshape(кадров, L), axis=1)
    имя = ИМЕНА[M]

    # Скремблер: вслепую по устойчивым столбцам; решает B1.
    кандидаты = []
    найдено = skrembler.найти_по_кадру(ряд, L, пропуск=3 * M * 8)
    if найдено is not None:
        кандидаты.append((tuple(найдено["отводы"]), [int(ч) for ч in найдено["начальное"]],
                          "найден вслепую: " + найдено["способ"]))
    # Запасная гипотеза — многочлен кадрового скремблера SDH (принимается только по B1).
    кандидаты.append(((6, 7), [1] * 7, "гипотеза 1 + x⁶ + x⁷, начальное 1111111 — подтверждена B1"))
    лучший = (_b1(байты, байты, M), байты, None, "без скремблера")
    for отводы, начальное, способ in кандидаты:
        снято = _снять_скремблер(байты, M, отводы, начальное)
        b1 = _b1(байты, снято, M)
        if b1 > лучший[0] + 1e-9:
            лучший = (b1, снято, (отводы, начальное), способ)
    b1, снято, скремблер, способ = лучший
    if b1 < 0.5:
        return None
    подробно = [
        f"кадр {L} бит (9 строк × {90 * M} байт), начало — бит {начало}, кадров в разборе {кадров}",
        (f"кадровый скремблер {skrembler.полином_словами(скремблер[0])}, начальное "
         f"{''.join(map(str, скремблер[1]))} ({способ})" if скремблер else "кадр не скремблирован"),
        f"B1 (BIP-8 по предыдущему кадру) сошёлся в {b1 * 100:.1f} % кадров",
        f"J0: {_трасса(байты[:, 2 * M])}",
    ]
    единица, местный = _колонки(M)
    строка4 = 3 * 90 * M

    def столбец(u: int, л: int) -> int:
        return int(np.flatnonzero((единица == u) & (местный == л))[0])

    указатели = []
    for u in range(M):
        h1 = снято[:, строка4 + столбец(u, 0)]
        h2 = снято[:, строка4 + столбец(u, 1)]
        указатели.append(указатель(_большинство(h1), _большинство(h2)))
    группы = _группы(указатели)
    if not группы:
        подробно.append("годных указателей AU нет (AIS или неоснащённый)")
    дальше: Dict[str, np.ndarray] = {}
    сводка_vc = []
    проверки = [b1]
    for первая, сколько, _ in группы:
        состав = set(range(первая, первая + сколько))
        столбцы = [c for c in range(90 * M) if int(единица[c]) in состав and int(местный[c]) >= 3]
        R = len(столбцы)
        область = снято.reshape(кадров, СТРОК, 90 * M)[:, :, столбцы]
        по_кадрам = []
        for f in range(кадров):
            вид, значение = указатель(снято[f, строка4 + столбец(первая, 0)],
                                      снято[f, строка4 + столбец(первая, 1)])
            по_кадрам.append(значение if вид in ("норма", "новые данные") and 0 <= значение <= 782 else -1)
        vc, смен = _vc(область, по_кадрам, сколько, 3)
        if len(vc) < 3:
            continue
        b3 = _b3(vc, R)
        вид_vc = ("VC-3 (AU-3)" if сколько == 1 else "VC-4 (AU-4)" if сколько == 3
                  else f"VC-4-{сколько // 3}c (AU-4-{сколько // 3}c)" if сколько % 3 == 0
                  else f"VC сцепки из {сколько} единиц")
        номер = f"{вид_vc.split(' ')[0]} №{len(сводка_vc) + 1}"
        с2 = _большинство([в[2 * R] for в in vc])
        сводка_vc.append(f"{номер}: указатель {_большинство([p for p in по_кадрам if p >= 0])}"
                         f"{f' (смен {смен})' if смен else ''}, B3 сошёлся в {b3 * 100:.1f} %, "
                         f"C2 = 0x{с2:02X}, J1: {_трасса(np.array([в[0] for в in vc]))}")
        if b3 < 0.5:
            continue
        проверки.append(b3)
        матрица = np.stack(vc).reshape(len(vc), СТРОК, R)
        # Что внутри: TU-12 (через TUG-2), TU-3 — пробуем, решают V5 и B3.
        притоки = _tu12(матрица, сколько, номер) if сколько in (1, 3) else {}
        if сколько == 3 and not притоки:
            притоки = _tu3(матрица, номер)
        if притоки:
            сводка_vc += [с for с in притоки.pop("_сводка", [])]
            дальше.update(притоки)
            continue
        # Нагрузка целиком: без POH и столбцов фиксированного заполнения.
        убрать = {0} | ({29, 58} if сколько == 1 else set(range(1, сколько // 3)) if сколько > 3 else set())
        оставить = [c for c in range(R) if c not in убрать]
        дальше[f"{номер} нагрузка"] = np.unpackbits(матрица[:, :, оставить].reshape(-1))
    подробно += сводка_vc
    уверенность = float(np.mean(проверки))
    return Находка(
        уровень="SDH", что=f"SDH {имя} (G.707): " + (", ".join(
            ("VC-3" if с == 1 else "VC-4" if с == 3 else f"VC-4-{с // 3}c") for _, с, _ in группы) or "без нагрузки"),
        уверенность=уверенность,
        мера=f"B1 сошёлся в {b1 * 100:.1f} % кадров"
             + (f"; B3 — в {np.mean(проверки[1:]) * 100:.1f} %" if len(проверки) > 1 else ""),
        подробно=подробно, дальше=дальше or None, вид_дальше="притоки" if дальше else "")


def _tu12(vc: np.ndarray, единиц: int, откуда: str) -> Dict[str, object]:
    """TU-12 внутри VC-4 или VC-3: VC-12 с проверкой V5, E1 — с проверкой FAS."""
    if единиц == 3:
        адреса = [((t, m, n), _tu12_столбцы_vc4(t, m, n)) for t in range(3) for m in range(7) for n in range(3)]
    else:
        адреса = [((0, m, n), _tu12_столбцы_vc3(m, n)) for m in range(7) for n in range(3)]
    итог: Dict[str, object] = {}
    сводка = []
    годных, e1_годных = 0, 0
    for (t, m, n), столбцы in адреса[:TU12_ДО]:
        tu = vc[:, :, столбцы].reshape(len(vc), 36)
        р = vc12(tu)
        имя = f"TU-12 {t + 1}-{m + 1}-{n + 1}" if единиц == 3 else f"TU-12 {m + 1}-{n + 1}"
        if р is None:
            continue
        e1, стафф = e1_из_vc12(р["vc"])
        fas = cikl.e1(e1) if len(e1) >= 512 * 40 else None
        есть_e1 = fas is not None and fas.уверенность >= 0.5
        # VC-12 годен, если сошёлся V5 — или если в нём найден E1 с FAS: FAS сам
        # доказывает, что выделение верно, а BIP-2 бывает и испорчен линией.
        if р["v5"] < 0.5 and not есть_e1:
            continue
        годных += 1
        v5 = f"V5 (BIP-2) сошёлся в {р['v5'] * 100:.0f} %" + (" — не сошёлся, приток подтверждён FAS"
                                                               if р["v5"] < 0.5 else "")
        if есть_e1:
            e1_годных += 1
            итог[f"{откуда} {имя} E1"] = e1
            crc4 = fas.свойства.get("crc4")
            сводка.append(f"{имя}: указатель {р['указатель']}, {v5}, "
                          f"E1 с FAS в {fas.уверенность * 100:.0f} % циклов"
                          + (f", CRC-4 сошлась в {crc4 * 100:.0f} % подсверхциклов" if crc4 is not None else "")
                          + f"; S2 пустой в {стафф['S2_пустой'] * 100:.0f} % сверхциклов")
        else:
            итог[f"{откуда} {имя} VC-12"] = np.unpackbits(np.concatenate([в[1:] for в in р["vc"]]))
            сводка.append(f"{имя}: указатель {р['указатель']}, V5 сошёлся в {р['v5'] * 100:.0f} %; "
                          f"асинхронного E1 с FAS нет — нагрузка VC-12 как есть")
    if not годных:
        return {}
    сводка.insert(0, f"{откуда}: TU-12 с годным VC-12 — {годных}, из них E1 с FAS — {e1_годных}")
    итог["_сводка"] = сводка
    return итог


def _tu3(vc4: np.ndarray, откуда: str) -> Dict[str, object]:
    """TU-3 в TUG-3: указатель H1 H2 в первом столбце TUG-3, VC-3 — 85 столбцов, проверка B3."""
    итог: Dict[str, object] = {}
    сводка = []
    кадров = len(vc4)
    for t in range(3):
        столбцы = [3 + t + 3 * i for i in range(86)]
        tug3 = vc4[:, :, столбцы]
        по_кадрам = []
        for f in range(кадров):
            вид, значение = указатель(tug3[f, 0, 0], tug3[f, 1, 0])
            по_кадрам.append(значение if вид in ("норма", "новые данные") and 0 <= значение <= 764 else -1)
        if sum(p >= 0 for p in по_кадрам) < 0.5 * кадров:
            continue
        область = tug3[:, :, 1:]
        # С какого байта считается смещение — решает B3.
        лучший = max(((_b3(v, 85), v, база) for база in (2, 3)
                      for v in [_vc(область, по_кадрам, 1, база)[0]]), key=lambda x: x[0])
        b3, vc, база = лучший
        if b3 < 0.5 or len(vc) < 3:
            continue
        имя = f"TU-3 {t + 1}"
        матрица = np.stack(vc).reshape(len(vc), СТРОК, 85)
        итог[f"{откуда} {имя} нагрузка"] = np.unpackbits(матрица[:, :, 1:].reshape(-1))
        сводка.append(f"{имя}: указатель {_большинство([p for p in по_кадрам if p >= 0])}, "
                      f"B3 VC-3 сошёлся в {b3 * 100:.0f} %, C2 = 0x{_большинство([в[2 * 85] for в in vc]):02X}")
    if not итог:
        return {}
    итог["_сводка"] = сводка
    return итог
