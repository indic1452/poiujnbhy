"""Ссылки на источники в тексте ответа: [S1], [S1, S2], [S1—S3].

Метка вида «[S1]» — это то, чем ответ помощника связан с библиотекой отдела.
По ней человек открывает фрагмент, по ней же система считает, опирается ли
ответ на источники вообще.

Разбиралась она одним строгим образцом: закрывающая скобка обязана стоять
сразу за цифрами. Модель же, когда утверждение опирается на два документа,
пишет по-русски естественно — «[S1, S2]». Такая метка не становилась ссылкой
(человек не мог открыть источник), в панель уходили первые три фрагмента
подборки вместо тех, на которые ответ сослался, а счётчик процитированного
показывал ноль — и рядом с ответом висело «ответ не опирается на библиотеку».
Про ответ, сославшийся на всё, что нужно.

Тот же образец стоял ещё в четырёх местах — в проверке отчёта, в метриках и
в подсветке редактора, — поэтому разбор собран сюда, в одно место, и все
пользуются им.

Что понимаем: несколько меток в одной скобке через запятую, точку с запятой
или «и»; диапазон через дефис или тире; строчную «s»; русскую «С» вместо
латинской «S» (её ставят по раскладке); ведущие нули; пробелы внутри скобок.
"""

from __future__ import annotations

import re
from typing import List, Set

__all__ = ["CITATION_BOX", "MAX_RANGE", "labels_in", "expand_box"]

#: Скобка с метками целиком. Внутри — «S» в любом виде и цифры, дальше
#: сколько угодно повторов через разделитель.
CITATION_BOX = re.compile(
    r"\[\s*[SsСс]\s*0*\d+"
    r"(?:\s*(?:[,;]|—|–|-|и)\s*(?:[SsСс]\s*)?0*\d+)*"
    r"\s*\]"
)

#: Сколько меток разворачиваем из одного диапазона. «[S1—S9999]» — это не
#: ссылка, а опечатка, и разворачивать её в тысячи кнопок незачем.
MAX_RANGE = 50

_PARTS = re.compile(r"\s*(?:[,;]|(?<=\d)\s*и\s*(?=[SsСс\d])|и)\s*")
_DASH = re.compile(r"[-–—]")
_NUMBER = re.compile(r"\d+")


def expand_box(box: str) -> List[str]:
    """Метки из одной скобки, по порядку и без повторов.

    ``"[S1, S2]"`` → ``["S1", "S2"]``; ``"[S1—S3]"`` → ``["S1", "S2", "S3"]``.
    """
    inner = str(box or "").strip()
    if inner.startswith("["):
        inner = inner[1:]
    if inner.endswith("]"):
        inner = inner[:-1]

    out: List[str] = []
    seen: Set[str] = set()
    for part in _PARTS.split(inner):
        numbers = [int(found) for found in _NUMBER.findall(part)]
        if not numbers:
            continue
        first = numbers[0]
        if len(numbers) >= 2 and _DASH.search(part):
            # Диапазон. Записанный наоборот («[S3—S1]») разворачиваем от
            # меньшего к большему: обе метки настоящие, и терять их молча
            # хуже, чем показать не в том порядке, в каком написали.
            low, high = sorted((first, numbers[1]))
            span = range(low, min(high, low + MAX_RANGE) + 1)
        else:
            span = range(first, first + 1)
        for number in span:
            label = f"S{number}"
            if label not in seen:
                seen.add(label)
                out.append(label)
    return out


def labels_in(text: str) -> Set[str]:
    """Все метки источников, встреченные в тексте."""
    found: Set[str] = set()
    for box in CITATION_BOX.findall(str(text or "")):
        found.update(expand_box(box))
    return found
