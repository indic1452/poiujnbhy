"""Конфигурация приложения.

Значения берутся из переменных окружения ``REPORTGEN_*`` и (при наличии) из
JSON-файла, путь к которому задан в ``REPORTGEN_CONFIG``. Явные аргументы
конструктора важнее и того, и другого.

Ядро (facts/corpus/retrieval/pipeline/verify) конфигурацию не использует —
оно остаётся библиотекой без зависимостей и без глобального состояния.
Конфигурация нужна только приложению: веб-серверу, приёму документов и CLI.
"""

from __future__ import annotations

import json
import os
from dataclasses import asdict, dataclass, field, fields
from pathlib import Path
from typing import Any

ENV_PREFIX = "REPORTGEN_"


def default_data_dir() -> Path:
    """Корень изменяемых данных. Читается в момент создания Settings, а не импорта."""
    return Path(os.environ.get(f"{ENV_PREFIX}DATA_DIR", "./var")).resolve()


@dataclass
class Settings:
    """Все настройки установки в одном месте."""

    # -- пути ---------------------------------------------------------------
    # Подкаталоги по умолчанию выводятся из data_dir: задав только его, вы
    # переносите всю установку целиком (это же поведение нужно тестам).
    data_dir: Path = field(default_factory=default_data_dir)
    db_path: Path | None = None
    library_dir: Path | None = None
    upload_dir: Path | None = None
    export_dir: Path | None = None
    templates_dir: Path = Path("templates")
    glossary_path: Path = Path("templates/glossary.json")
    #: Справочник направлений техники. None — искать рядом с пакетом.
    domains_path: Path | None = None
    #: Двуязычный словарь терминов: русский запрос — английские документы
    #: (RFC, паспорта микросхем). Пусто — берётся templates/terms.json.
    terms_path: Path | None = None
    #: Справочник состава: из чего собрано целое. Вопрос называет целое
    #: («тракт приёма РРЛС»), а в библиотеке лежат паспорта его узлов, и слов
    #: «тракт приёма» в них нет. Пусто — берётся templates/parts.json.
    parts_path: Path | None = None
    docx_template: Path | None = None

    # -- языковая модель ---------------------------------------------------
    llm_kind: str = "openai"
    llm_base_url: str = "http://127.0.0.1:8000/v1"
    llm_model: str = "local-model"
    llm_api_key: str = "not-needed"
    #: Окно контекста модели в токенах — то же число, что стоит в «-c» при
    #: запуске llama-server. Ниже него промпт обязан уместиться ЦЕЛИКОМ:
    #: системная инструкция, вопрос, история, материал и место под ответ.
    #:
    #: Отдел получил «36061 токенов, а размер 32768» — то есть промпт вылез
    #: за окно и модель не ответила вовсе. Считался при этом не промпт, а его
    #: части по отдельности, и в счёт не входили ни системная инструкция, ни
    #: шапки шаблона, ни блок «документы, названные в вопросе». Теперь
    #: собранный промпт меряется целиком и режется, пока не влезет.
    llm_context_tokens: int = 32768
    #: Сколько ЗНАКОВ приходится на один токен. Величина зависит от
    #: токенизатора модели и от языка: для русского технического текста она
    #: заметно меньше, чем для английского, — редкие слова вроде
    #: «демодулятор» и «плезиохронный» разбиваются на много кусков.
    #:
    #: Полтора — с запасом вниз. Прежняя оценка в 2,4 знака на токен и
    #: привела к переполнению: по ней 52 000 знаков материала — это 21 700
    #: токенов, а на деле вышло около 35 000.
    #:
    #: Ошибаться здесь можно только в одну сторону: заниженное значение
    #: отнимает у ответа немного материала, завышенное роняет ответ целиком.
    assistant_chars_per_token: float = 1.5
    #: Сколько ждать ответа модели. 900 с — столько же стоит в образце
    #: настроек, который копирует установщик: развёрнутый разбор на 4000
    #: токенов при 20 токенах в секунду занимает больше трёх минут, а на
    #: холодном старте с догрузкой весов — заметно больше.
    llm_timeout: float = 900.0
    llm_seed: int | None = 0
    llm_temperature: float = 0.2
    #: Отбор токенов — по карточке Qwen3 для режима размышления: TopK=20,
    #: TopP=0.95, MinP=0. Главный ответ помощника модель пишет, размышляя, а
    #: для этого режима карточка прямо запрещает почти жадный выбор: «ведёт
    #: к ухудшению качества и бесконечным повторам». Повтор в размышлении
    #: съедает весь потолок, и ответ не начинается. Служебные заходы идут
    #: при температуре 0, и на них эти три числа не влияют.
    llm_top_k: int | None = 20
    llm_top_p: float | None = 0.95
    llm_min_p: float | None = 0.0
    llm_parallel_sections: int = 2

    # -- эмбеддинги и реранкер --------------------------------------------
    embed_enabled: bool = False
    embed_base_url: str = "http://127.0.0.1:8001/v1"
    embed_model: str = "bge-m3"
    embed_api_key: str = "not-needed"
    embed_batch: int = 16
    embed_timeout: float = 120.0

    rerank_enabled: bool = False
    #: Реранкер — ОТДЕЛЬНЫЙ сервер, на своём порту: 8001 занят эмбеддингами
    #: (см. scripts/windows/start-embed.ps1 и док. 11). Здесь стоял 8001, и
    #: установка, включившая реранк без явного адреса, спрашивала оценки у
    #: эмбеддера: тот отвечал ошибкой, реранк молча пропускался.
    rerank_base_url: str = "http://127.0.0.1:8002/v1"
    rerank_model: str = "bge-reranker-v2-m3"
    rerank_api_key: str = "not-needed"
    rerank_timeout: float = 120.0

    # -- поиск -------------------------------------------------------------
    retrieval_candidates: int = 60
    #: Сколько кандидатов пересуживает реранк. Ноль — всех.
    #:
    #: Прежде здесь стояло двадцать, зашитые в код и в настройки не выведенные,
    #: при шестидесяти кандидатах. Сорок нижних реранк не видел никогда: если
    #: первый проход поставил нужный фрагмент двадцать первым — а на русском
    #: вопросе по английскому стандарту так и бывает, — поднять его было
    #: нечем, и в ответ он не попадал.
    #:
    #: Реранку отдельной службой (кросс-энкодер на видеокарте) шестьдесят пар
    #: стоят около полусекунды. Запасному реранку самой моделью — нет: для
    #: него потолок остаётся двадцать, см. search.build_retriever.
    rerank_top_n: int = 0
    #: Сколько фрагментов библиотеки попадает в промпт. Больше — ответ полнее и
    #: лучше подкреплён ссылками, но длиннее промпт и медленнее генерация.
    retrieval_top_k: int = 8

    # -- развёрнутость ответа помощника --------------------------------------
    # Величины, от которых зависит полнота ответа. Их держат вместе, потому
    # что вместе они упираются в окно контекста модели.
    #
    # АРИФМЕТИКА ОКНА. Раньше она стояла здесь числом, которое надо было
    # держать в голове согласованным с четырьмя другими. Это не сработало:
    # отдел получил «36061 токенов, а размер 32768» — модель не ответила
    # вовсе, при формально соблюдённом бюджете.
    #
    # Теперь предел не задаётся, а ВЫВОДИТСЯ из окна модели, и считает его
    # assistant._context_chars():
    #
    #   (окно модели − assistant_max_tokens − запас на токенизацию)
    #       × assistant_chars_per_token
    #       − системная инструкция − шаблон промпта − задание
    #
    # На умолчаниях: (32768 − 7000 − 512) × 1,5 − 5750 − 370 − 4534 ≈ 27 200
    # знаков.
    #
    # Окно модели здесь — НЕ llm_context_tokens: помощник спрашивает его у
    # самого llama-server (GET /props), а настройка остаётся запасным
    # вариантом на случай, когда сервер про окно не говорит. Поставите
    # «--parallel 2» — сервер сам сообщит вдвое меньшее пооткошное число, и
    # всё остальное пересчитается само.
    #
    # И это ещё не всё: собранный промпт меряется целиком ПЕРЕД отправкой
    # (assistant._fit_tokens) и режется, пока не влезет. Вывод по формуле —
    # первое приближение, проверка по готовой строке — гарантия. То, что не
    # поместилось, не выбрасывается: оно прочитывается отдельными проходами
    # (assistant_digest_passes) и входит в ответ выписками.
    #
    # Что бывает, если границу не держать: llama.cpp либо отвечает ошибкой
    # («the request exceeds the available context size»), либо молча
    # выбрасывает начало промпта вместе с системной инструкцией — и модель
    # перестаёт ставить ссылки [S1], округляет числа и отвечает по памяти.
    # Со стороны выглядит как «модель поглупела».

    #: Сколько знаков каждого найденного фрагмента видит модель. Значение
    #: подобрано под нарезку корпуса: TARGET_CHARS в corpus.py — 2200, то
    #: есть при 2200 фрагмент доходит до модели целиком. При 1400 (как было)
    #: у каждого третьего фрагмента отрезалась треть — ровно та, где стояла
    #: таблица допусков или конец описания поля кадра.
    assistant_source_chars: int = 2200
    #: Верхний предел на материал в знаках. Ноль — не ограничивать сверх
    #: того, что вывелось из окна модели (см. арифметику выше). Значение
    #: больше выведенного не действует: раньше стояло 52 000 при реальных
    #: 34 700, и ровно это переполняло окно. Меньшее — действует: маленькое
    #: окно ставят осознанно.
    assistant_context_chars: int = 0
    #: Сколько фрагментов ищем для разговора. Больше, чем для отчёта: в
    #: отчёте материал ограничен факт-пакетом, в разговоре — только вопросом.
    #: Восемнадцать — под окно в 32768 токенов (один слот). При двух слотах
    #: половина из них всё равно не влезет и будет отброшена: ставьте 12.
    assistant_top_k: int = 18
    #: Сколько найденного помощник ЧИТАЕТ всего, в глубоком режиме.
    #:
    #: Лучшие фрагменты идут в промпт целиком — столько, сколько вмещает
    #: окно модели. Остальные, до этого числа, прочитываются отдельными
    #: проходами и доходят до ответа выписками: модель просматривает каждый
    #: и выписывает то, что относится к вопросу, а лишнее пропускает.
    #:
    #: Прежде найденное за все заходы разбора сводилось и обрезалось до
    #: assistant_top_k — восемнадцати. Всё, что заходы нашли сверх этого,
    #: исчезало молча: не шло ни целиком, ни выпиской. Меньше
    #: assistant_top_k не бывает: тогда действует assistant_top_k.
    assistant_read_limit: int = 48
    #: Сколько соседних фрагментов подтягивать к найденному с каждой стороны.
    #: Таблица параметров или описание поля кадра редко умещается в один
    #: фрагмент: начало осталось в предыдущем, продолжение — в следующем.
    assistant_neighbours: int = 1
    #: Для скольких лучших фрагментов подтягивать соседей. Всем подряд не
    #: нужно: хвост выдачи и так на грани относимости.
    assistant_neighbour_top: int = 8
    #: Показывать ли модели оглавление документов, из которых взяты фрагменты.
    #: С ним она видит, что ещё есть в документе, и может сказать, где искать
    #: недостающее, вместо «в источниках этого нет».
    assistant_outlines: bool = True
    #: Сколько знаков приложенных файлов (дампов, логов, документов) видит
    #: модель — ВСЕХ вместе, а не каждого. Дамп на 40 МБ в окно не влезет
    #: никогда, поэтому берётся начало: там заголовки сессии и первые
    #: ошибки, по которым обычно и понятно, что случилось. Предел делится
    #: между файлами поровну, но короткий файл не занимает чужого — то,
    #: что он не выбрал, достаётся длинным. Входит в общий бюджет
    #: assistant_context_chars.
    assistant_attachment_chars: int = 8000
    #: Сколько знаков подсказки занимает карта библиотеки: перечень полок с
    #: числами и названия документов. Без неё помощник знает о библиотеке
    #: только то, что попало в найденные фрагменты, и не может ни отправить
    #: к соседнему тому, ни честно сказать «по этой линии у нас ничего нет».
    #: Ноль — не показывать карту вовсе.
    assistant_catalog_chars: int = 2500
    #: Сколько заходов разбора делает помощник, прежде чем отвечать. В каждом
    #: заходе он сам решает, что сделать: поискать другими словами, посмотреть
    #: оглавление тома, прочитать конкретную главу — или сказать, что материала
    #: достаточно. Ноль — прежнее поведение: один поиск и один проход модели.
    #: Каждый заход стоит короткого обращения к модели (одна строка ответа),
    #: поэтому на медленной машине число имеет смысл снизить.
    assistant_rounds: int = 4
    #: Сколько узлов разбирать по справочнику состава, прежде чем звать
    #: модель. Каждый узел — отдельный поиск по библиотеке (обращения к
    #: модели он не стоит). Ноль — не разбирать состав вовсе.
    #:
    #: Зачем это нужно: на вопрос «расскажи про тракт приёма РРЛС» поиск
    #: находит общие слова про организацию связи, а паспорта узлов тракта —
    #: «АДЭ-5», «МШУ-2», «ПЧ-70», «ДМА 256» — не находит вовсе: слов «тракт
    #: приёма» в них нет и быть не должно. Разбор состава ищет каждый узел
    #: отдельно, и в материал для ответа попадают все четыре.
    assistant_parts: int = 8
    #: Сколько отдельных проходов делать по материалу, не поместившемуся в
    #: окно модели. Найденного по вопросу бывает больше, чем помещается за
    #: один раз; прежде лишнее просто отбрасывалось, и ответ собирался по
    #: половине найденного — молча.
    #:
    #: Теперь лишнее прочитывается по частям: в каждом проходе модель
    #: выписывает из своей части то, что относится к вопросу, сохраняя метки
    #: источников, и на последнем проходе ответ собирается по всему.
    #:
    #: Цена честная: каждый проход — отдельное обращение к модели, то есть
    #: несколько секунд ожидания на машине отдела. Ноль выключает разбор
    #: частями совсем — тогда лишнее отбрасывается, но об этом говорится
    #: словами в замечании к ответу.
    assistant_digest_passes: int = 3
    #: Сколько фрагментов отдавать модели за один такой проход. Ноль — по
    #: окну модели: столько, сколько в него войдёт.
    #:
    #: Прежде стояло шесть. Проход по шести фрагментам занимал около пятой
    #: части окна, и три прохода прочитывали восемнадцать фрагментов там, где
    #: могли бы полсотни. Время прохода определяет не длина промпта —
    #: видеокарта читает его за секунды, — а длина выписки, и она от числа
    #: фрагментов не зависит.
    assistant_digest_chunk: int = 0
    #: Насколько длинной должна быть одна выписка, в словах. Она идёт в
    #: итоговый промпт, и место там не бесплатно.
    assistant_digest_words: int = 300
    #: Сколько документов подтягивать по ссылкам ИЗ НАЙДЕННОГО ТЕКСТА.
    #:
    #: Отдел: «в чём разница G.733 от G.734? Помимо словесного описания в
    #: файлах, есть ещё и ссылка в этих документах на G.704, где для каждого
    #: описана байтовая структура». Сами G.733 и G.734 байтовую структуру не
    #: приводят — они на неё ссылаются, и без G.704 ответ выходит словесным
    #: пересказом отличий без единой цифры.
    #:
    #: Правило то же, по которому работает инженер: увидел ссылку на норму —
    #: открыл норму. Ноль выключает. Больше двух ставить не стоит: одна
    #: рекомендация МСЭ ссылается на десяток соседних, и выдача расплывётся.
    assistant_follow_refs: int = 2
    #: Сколько документов подкладывать ПО НАЗВАНИЮ, когда в вопросе не
    #: названо ни одного обозначения.
    #:
    #: Отдел: «вновь спрашиваю, что такое E1 уплотнение и его структура, в
    #: конце пишет, что нет стандарта ITU-T G.703; проверяю в библиотеке — он
    #: конечно же есть и на месте». Вопрос русский и словесный, документы
    #: английские, обозначений в вопросе нет вовсе — общих слов у вопроса и
    #: документа попросту нет, и поиск до G.703 не дотягивается.
    #:
    #: Тогда система спрашивает у модели, КАК называется нужный документ, и
    #: ищет его по описи по имени. Отвечает при этом опись, а не модель:
    #: чего в библиотеке нет, того и не придёт.
    #:
    #: Порог по объёму выдачи здесь не годится, и это замерено: по вопросу
    #: про E1 поиск вернул ПЯТЬ документов — и ни одного нужного. Полнота
    #: выдачи о её верности не говорит.
    #:
    #: Цена — одно короткое обращение к модели на вопрос без обозначений.
    #: Ноль выключает заход: тогда на таких вопросах ответ снова пишется по
    #: памяти модели.
    assistant_name_pass: int = 3
    #: Сколько документов добирать по сверке комплектности материала.
    #:
    #: Перед тем как модель сядет писать, ей показывают список уже добытых
    #: документов и спрашивают, чего в нём не хватает. Названное сверяется с
    #: описью и подкладывается — и только потом пишется ответ.
    #:
    #: Прежде эта сверка стояла ПОСЛЕ ответа: готовый текст проверяли на
    #: упоминание непрочитанного тома, и если оно находилось — ответ стирали
    #: и писали заново. Отдел: «почему она старый ответ затёрла и начала
    #: новый писать, но уже по другим документам, не пойму, первый уже лучше
    #: был».
    #:
    #: Второй ответ и правда выходил хуже, но не из-за окна. Дозаказанное
    #: вставало в начало подборки, а бюджет окна расходуется по порядку, —
    #: и выдача поиска, на которой стоял первый ответ, до промпта не
    #: доходила вовсе. Теперь
    #: недостающее выясняется до письма, ряды материала сливаются вперемежку,
    #: ответ пишется один раз и стирать нечего.
    #:
    #: Цена — одно короткое обращение к модели (две сотни токенов) на вопрос,
