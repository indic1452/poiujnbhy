#: Сколько двоичных знаков подряд — уже не данные для ответа, а переписывание
#: источника. Отдел: модель нашла в литературе огромную двоичную комбинацию и
#: переписывала её, пока не кончился потолок, — до разбора дело не дошло. У
#: Qwen каждая цифра — отдельный токен, и четыре тысячи бит — это четыре
#: тысячи токенов ответа. Настоящему разбору и 256 знаков хватает с лихвой:
#: длинную последовательность инженер откроет в источнике по ссылке.
ДВОИЧНЫХ_ПОДРЯД = 512
#: То же для шестнадцатеричного дампа: символ дампа — тоже токен.
ШЕСТНАДЦАТЕРИЧНЫХ_ПОДРЯД = 1024
#: Сколько знаков хвоста должны повторять один и тот же кусок, чтобы счесть
#: это зацикливанием, — и не меньше четырёх повторов. Восемьсот знаков одной
#: и той же строки подряд в живом разборе не встречаются (пустые строки рамки
#: в битовой диаграмме RFC идут по две-три), а в зациклившемся — это первые
#: секунды.
ПОВТОР_ЗНАКОВ = 800
ПОВТОРОВ = 4
#: Самый длинный повторяющийся кусок, который ищем, — строка таблицы.
ПОВТОР_ПЕРИОД = 300


def _вырождение(текст: str) -> tuple[int, str] | None:
    """Где хвост ответа выродился и во что. None — хвост живой.

    Возвращает, с какого знака текст пора отрезать, и что случилось:
    «двоичная» или «шестнадцатеричная» последовательность, «повтор». Смотрим
    только на хвост: вырождение растёт в конце ответа, а начало уже прочтено.
    """
    хвост_из = max(0, len(текст) - 4 * ДВОИЧНЫХ_ПОДРЯД)
    хвост = текст[хвост_из:]

    # Длинная последовательность, переписанная из источника: хвост целиком из
    # цифр и разделителей между ними.
    #
    # У дампа разделители — только пробелы, запятые и двоеточия: точка и палка
    # стоят в обычной таблице десятичных чисел, и с ними таблица замеров
    # принималась за дамп. И в дампе обязательно есть буквы a–f: без них это
    # десятичные числа, а сплошь нули ловит проверка на повтор ниже.
    for знаки, разделители, предел, вид, буквы in (
            ("01", " \t\n,.;|_-·", ДВОИЧНЫХ_ПОДРЯД, "двоичная", ""),
            ("0123456789abcdefABCDEF", " \t\n,;:xX", ШЕСТНАДЦАТЕРИЧНЫХ_ПОДРЯД,
             "шестнадцатеричная", "abcdefABCDEF")):
        начало = len(хвост)
        while начало > 0 and (хвост[начало - 1] in знаки or хвост[начало - 1] in разделители):
            начало -= 1
        отрезок = хвост[начало:]
        цифр = sum(1 for знак in отрезок if знак in знаки)
        if буквы and sum(1 for знак in отрезок if знак in буквы) * 20 < цифр:
            continue
        if цифр >= предел:
            # Первые знаки оставляем: по ним видно, что за последовательность.
            # Резать с начала отрезка — значит отрезать и строку перед ней.
            while начало < len(хвост) and хвост[начало] not in знаки:
                начало += 1
            return хвост_из + начало + 64, вид

    # Зацикливание: хвост из одного и того же куска подряд.
    for период in range(1, ПОВТОР_ПЕРИОД + 1):
        длина = max(ПОВТОР_ЗНАКОВ, (ПОВТОРОВ - 1) * период)
        if len(текст) < длина + период:
            break
        отрезок = текст[-(длина + период):]
        if отрезок[период:] != отрезок[:-период]:
            continue
        # Нашли — ведём начало повтора назад, пока он держится, и оставляем
        # один его экземпляр: видно, что повторялось.
        начало = len(текст) - длина
        while начало > 0 and текст[начало - 1] == текст[начало - 1 + период]:
            начало -= 1
        return начало + период, "повтор"
    return None


class СторожПовтора:
    """Следит за ответом по мере генерации и останавливает вырождение.

    Зачем останавливать, а не дать дописать: потолок ответа — это и время, и
    очередь отдела. Модель, переписывающая двоичную комбинацию на четыре
    тысячи знаков, держит модель минуты, а ответ всё равно обрывается на
    середине — и следующий в очереди ждёт впустую.
    """

    #: Как часто смотреть: проверка стоит сотни тысяч сравнений знаков.
    ШАГ = 64

    def __init__(self) -> None:
        self.текст = ""
        self.вид = ""
        self._проверено = 0

    def добавить(self, кусок: str) -> str:
        """Принять кусок ответа. Непусто — вырождение найдено, пора остановить."""
        self.текст += кусок
        if len(self.текст) - self._проверено < self.ШАГ:
            return ""
        self._проверено = len(self.текст)
        найдено = _вырождение(self.текст)
        if найдено is not None:
            self.вид = найдено[1]
        return self.вид

    def чистый(self) -> str:
        """Ответ без выродившегося хвоста — с пометкой, что он отрезан."""
        найдено = _вырождение(self.текст)
        if найдено is None:
            return self.текст
        return self.текст[:найдено[0]].rstrip() + " …"


