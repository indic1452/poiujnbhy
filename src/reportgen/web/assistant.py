def _основа_продолжения(текст: str, обрыв: str) -> str:
    """Что оставить от оборванного ответа перед продолжением.

    По длине обрывается почти всегда посреди строки: недописанную строку
    таблицы или пункт убираем, и модель напишет её заново целиком. Длинную
    строку — абзац — не трогаем: терять абзац из-за хвоста в пару слов хуже.
    """
    текст = (текст or "").rstrip()
    if обрыв == "length" and "\n" in текст:
        голова, последняя = текст.rsplit("\n", 1)
        if len(последняя) < 400 and голова.strip():
            return голова.rstrip()
    return текст


_РАЗДЕЛИТЕЛЬ_ТАБЛИЦЫ = re.compile(r"^\s*\|?\s*:?-{3,}")


def _сшить(основа: str, продолжение: str) -> str:
    """Склеить ответ и его продолжение так, чтобы шов не был виден.

    Модель, как её ни проси, нередко повторяет последнюю строку написанного
    и шапку таблицы, на которой оборвалась. Повтор строки убираем; шапку с
    разделителем посреди таблицы — тоже: она разорвала бы таблицу надвое.
    """
    строки = (продолжение or "").strip("\n").splitlines()
    последние = {строка.strip() for строка in основа.splitlines()[-5:] if строка.strip()}
    while строки and (not строки[0].strip() or строки[0].strip() in последние):
        строки.pop(0)
    хвост_основы = основа.splitlines()[-1].strip() if основа.strip() else ""
    в_таблице = хвост_основы.startswith("|")
    if (в_таблице and len(строки) >= 2 and строки[0].lstrip().startswith("|")
            and _РАЗДЕЛИТЕЛЬ_ТАБЛИЦЫ.match(строки[1])):
        строки = строки[2:]
    if not строки:
        return основа
    стык = "\n" if в_таблице and строки[0].lstrip().startswith("|") else "\n\n"
    return основа + стык + "\n".join(строки)


def _сократить(text: str, limit: int) -> str:
    """Текст не длиннее ``limit`` знаков, по границе строки или фразы.

    Для выписки, не вошедшей в отведённое место: начало у неё — самое
    относящееся к вопросу, а обрыв посреди числа хуже, чем на точке.
    """
    if len(text) <= limit:
        return text
    окно = text[:max(0, limit - 1)]
    край = max(окно.rfind("\n"), окно.rfind(". "))
    if край >= int(limit * 0.6):
        окно = окно[:край + 1]
    return окно.rstrip() + "…"


def _tidy(text: str, limit: int) -> str:
    """Фрагмент для промпта и панели источников. См. corpus.tidy_quote."""
    from ..corpus import tidy_quote  # noqa: PLC0415 — не тянуть корпус при импорте

    return tidy_quote(text, limit)


def _tidy_end(text: str, limit: int) -> str:
    """То же, что :func:`_tidy`, но лишнее срезается спереди.

    Нужно ровно для одного случая — предыдущего соседа найденного фрагмента.
    """
    whole = _tidy(text, len(text or "") + 1)
    if len(whole) <= limit:
        return whole
    return "…" + whole[len(whole) - limit:].lstrip()


def _share_chars(sizes: Sequence[int], total: int) -> list[int]:
    """Разделить общий предел знаков между файлами.

    Поровну, но короткий файл не занимает чужого: то, что он не выбрал,
    достаётся длинным. Предел был на КАЖДЫЙ файл, и десять приложенных
    файлов выносили промпт за окно модели втрое — а переполнение окна
    llama.cpp не сообщает, он молча выбрасывает начало промпта вместе с
    системной инструкцией, и модель перестаёт ставить ссылки.
    """
    shares = [0] * len(sizes)
    pending = [i for i, size in enumerate(sizes) if size > 0]
    left = max(int(total), 0)
    while pending and left > 0:
        share = left // len(pending)
        if share <= 0:
            break
        modest = [i for i in pending if sizes[i] <= share]
        if not modest:
            for i in pending:
                shares[i] = share
            break
        for i in modest:
            shares[i] = sizes[i]
            left -= sizes[i]
        pending = [i for i in pending if i not in set(modest)]
    return shares


def _clip(text: str, limit: int) -> str:
    text = text.strip()
    return text if len(text) <= limit else text[:limit].rstrip() + "…"


def _make_title(question: str) -> str:
    words = " ".join(question.split())
    title = words[:60].rstrip()
    if len(words) > 60:
        title = title.rsplit(" ", 1)[0] + "…"
    return title or DEFAULT_TITLE
