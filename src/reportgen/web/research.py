"""Разбор в несколько заходов: помощник ищет, читает и ищет снова.

Раньше на вопрос приходился один поиск и один проход модели. Не нашлось с
первого запроса — ответа не будет, и модель об этом не узнает: она честно
разбирала двенадцать случайных фрагментов и не подозревала, что спросили
другими словами, чем написано в книге. Инженер в такой ситуации поступает
иначе: ищет, смотрит, чего не хватает, лезет в оглавление тома, читает
нужную главу и ищет ещё раз другими словами.

Здесь это и заведено. Между вопросом и ответом идут несколько коротких
заходов, в каждом модель делает ОДИН шаг:

* ``ИСКАТЬ: <запрос>`` — ещё один поиск по библиотеке своими словами;
* ``ОГЛАВЛЕНИЕ: <документ>`` — что вообще есть в этом томе;
* ``ЧИТАТЬ: <документ> | <раздел>`` — прочитать конкретную главу;
* ``ХВАТИТ`` — материала достаточно, можно отвечать.

Почему протокол текстовый, а не «вызов функции» по-openai'ному. Модель здесь
локальная и меняется от установки к установке: сегодня Qwen, завтра
что-нибудь ещё. Строгий JSON-протокол такие модели держат неровно и молча
ломаются на первом же лишнем слове, а разобрать «ИСКАТЬ: кадр BBFrame» можно
как угодно снисходительно. Тем же способом в системе уже работает реранк
моделью (:mod:`reportgen.rerank`): протокол простой, разбор терпимый.

Терпимость важнее строгости ещё по одной причине: непонятый шаг — это не
ошибка, а конец разбора. Помощник просто отвечает по тому, что успел
собрать, и никогда не остаётся без ответа из-за того, что модель написала
не то слово.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import List, Sequence

__all__ = [
    "STEP_KINDS",
    "Step",
    "found_note",
    "parse_step",
    "render_found",
    "render_trail",
]

#: Что помощник умеет делать между вопросом и ответом.
STEP_KINDS = ("искать", "оглавление", "читать", "хватит")

#: Слова, которыми модель называет шаг. Английские — на случай, если модель
#: сбилась на язык обучения: ронять из-за этого весь разбор незачем.
_WORDS = {
    "искать": ("искать", "поиск", "найти", "search", "find", "query"),
    "оглавление": ("оглавление", "содержание", "разделы", "outline", "toc"),
    "читать": ("читать", "прочитать", "открыть", "read", "open"),
    "хватит": ("хватит", "достаточно", "ответ", "довольно", "готово",
               "answer", "enough", "done", "stop"),
}

#: Строка шага: «ИСКАТЬ: запрос», «читать — том | глава», «ХВАТИТ».
_STEP_RE = re.compile(
    r"^\s*[-*>\s]*\[?\s*(?P<word>[A-Za-zА-Яа-яЁё]+)\s*\]?\s*[:—–-]?\s*(?P<rest>.*)$"
)

#: Длиннее этого запрос к библиотеке не имеет смысла: поиск всё равно режет.
MAX_ARGUMENT = 300


@dataclass
class Step:
    """Один шаг разбора: что делаем, с чем и что из этого вышло."""

    kind: str
    argument: str = ""
    section: str = ""
    #: Что шаг вернул словами. Для «ОГЛАВЛЕНИЕ» это и есть весь его смысл:
    #: без ответа модель просит оглавление, не видит его и просит снова.
    note: str = ""

    @property
    def is_final(self) -> bool:
        return self.kind == "хватит"

    def title(self) -> str:
        """Как шаг называется в интерфейсе — инженер видит ход разбора."""
        if self.kind == "искать":
            return f"ищу: {self.argument}"
        if self.kind == "оглавление":
            return f"смотрю оглавление: {self.argument}"
        if self.kind == "читать":
            where = f" → {self.section}" if self.section else ""
            return f"читаю: {self.argument}{where}"
        return "материала достаточно"


def parse_step(text: str) -> Step | None:
    """Разбирает ответ модели в шаг. Не разобралось — ``None``.

    Смотрим первую строку, в которой удалось узнать шаг: модель любит
    предварять ответ рассуждением («Мне нужно уточнить…»), и требовать от
    неё чистоты бессмысленно.
    """
    for line in str(text or "").splitlines():
        step = _parse_line(line)
        if step is not None:
            return step
    return None


def _parse_line(line: str) -> Step | None:
    match = _STEP_RE.match(line)
    if match is None:
        return None
    word = match.group("word").strip().lower().replace("ё", "е")
    rest = match.group("rest").strip()
    for kind, words in _WORDS.items():
        if any(word == item.replace("ё", "е") for item in words):
            if kind == "хватит":
                return Step("хватит")
            if not rest:
                # «ИСКАТЬ» без запроса — не шаг: искать нечего, и молча
                # искать пустоту хуже, чем закончить разбор.
                return None
            return _with_argument(kind, rest)
    return None


def _with_argument(kind: str, rest: str) -> Step:
    argument = rest.strip().strip('«»"\'')[:MAX_ARGUMENT]
    if kind != "читать":
        return Step(kind, argument)
    # «ЧИТАТЬ: том | глава» — раздел отделён вертикальной чертой. Её может
    # и не быть: тогда читаем начало документа.
    document, _, section = argument.partition("|")
    return Step("читать", document.strip().strip('«»"\''),
                section.strip().strip('«»"\''))


def render_found(sources: Sequence[dict]) -> str:
    """Что уже собрано — одной строкой на фрагмент, без текста.

    В заходах разбора модель видит только опись собранного: метку, документ
    и заголовок раздела. Полные тексты пошли бы в окно по второму разу и
    вытеснили бы всё остальное, а для решения «чего ещё не хватает» они не
    нужны — нужен перечень.
    """
    if not sources:
        return "(пока ничего не найдено)"
    lines = []
    for number, item in enumerate(sources, start=1):
        where = item.get("citation") or item.get("title") or item.get("doc_id")
        # Нумеруем по-своему, а не метками [S1]: в готовом ответе метки свои,
        # и совпадать они не обязаны — путать их нельзя.
        lines.append(f"{number}) {where}")
    return "\n".join(lines)


def render_trail(trail: Sequence[Step]) -> str:
    """Что уже спрашивали. Без этого модель ищет одно и то же по кругу."""
    if not trail:
        return "(это первый заход)"
    lines = []
    for step in trail:
        lines.append(f"- {step.title()}")
        if step.note:
            # Ответ шага — там же, где сам шаг: иначе модель просит
            # оглавление, не видит его и просит снова, и так до конца заходов.
            lines.append(f"  {step.note}")
    return "\n".join(lines)


def found_note(fresh: int) -> str:
    """Чем кончился шаг. Пустой заход надо назвать пустым.

    Без этого модель не отличает «нашлось, но не то» от «не нашлось ничего»
    и переспрашивает теми же словами до конца заходов.
    """
    if fresh <= 0:
        return "ничего нового не нашлось"
    if fresh == 1:
        return "новый фрагмент: 1"
    return f"новых фрагментов: {fresh}"
