# -*- coding: utf-8 -*-
"""Состав изделия: целое и его узлы.

Отдел прислал жалобу, и она глубже, чем кажется. В библиотеке лежат
документы на аппаратуру, входящую в тракт приёма РРЛС, — антенна, МШУ,
преобразователь частоты, демодулятор. Названы они обозначениями: «АДЭ-5»,
«МШУ-2», «ПЧ-70», «ДМА 256». На вопрос «расскажи про тракт приёма РРЛС»
помощник отвечает общими словами и ни один из этих документов не читает.

Это замерено, а не предположено. На библиотеке из пяти документов, четыре
из которых и составляют тракт, поиск по вопросу «тракт приёма РРЛС» дал:

    4.943  Организация связи в войсках     ← общие слова, ничего по существу
    0.319  АДЭ-5
           (МШУ-2, ПЧ-70, ДМА 256 — ноль)

Причина не в модели и не в качестве поиска. **Вопрос называет ЦЕЛОЕ, а в
библиотеке лежат его ЧАСТИ, и связать их нечем.** Слов «тракт приёма» в
паспорте демодулятора нет и быть не должно: паспорт описывает демодулятор.
Сколько ни улучшай поиск по словам и по смыслу, он ищет похожее на запрос,
а нужно другое — то, из чего запрошенное СОСТОИТ.

Инженер на этом месте поступает так: слышит «тракт приёма», вспоминает, из
чего тракт собран, и идёт смотреть паспорта узлов по отдельности. Здесь
заведено то же самое: справочник знает, из чего состоит целое, и помощник
ищет каждый узел отдельным запросом. Четыре узла — четыре поиска, и все
четыре документа оказываются в материале для ответа.

Почему справочником, а не моделью. Модель здесь локальная, слабая и
работает на изолированной машине; спросить у неё «из чего состоит тракт
приёма» можно, но ответ будет разным от раза к разу, а половина установок
получит выдуманные узлы. Справочник же отдел пополняет сам — это обычный
JSON рядом со словарём терминов, правки подхватываются без перезапуска, и
то, что помощник искал, инженер видит в следе разбора и может оспорить.

Одно не отменяет другого: если целое справочнику незнакомо, разобрать его
на узлы по-прежнему может модель в заходах разбора. Справочник лишь
снимает с неё ту часть работы, где ошибаться нельзя.
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Dict, List, Sequence, Tuple

from .terms import mentions, normalize

__all__ = [
    "MAX_UNITS",
    "MIN_WHOLE",
    "Composition",
    "PartsBook",
    "book",
    "default_path",
    "forget",
    "units_for",
]

DEFAULT_PATH = Path("templates") / "parts.json"

#: Сколько узлов разбирать по одному вопросу. Каждый узел — отдельный поиск
#: по библиотеке, а на изолированной машине поиск с реранком не бесплатный.
#: Восемь покрывают тракт приёма целиком (антенна, облучатель, МШУ, СВЧ-тракт,
#: преобразователь, гетеродин, УПЧ, демодулятор) и ставят предел составам,
#: которые в отделе распишут на полсотни позиций.
MAX_UNITS = 8

#: Короче этого название целого в справочник не берётся: «ТП» или «ПЧ»
#: встретятся в любом вопросе и разберут на узлы то, что никто не спрашивал.
#: Три, а не четыре, — тот же предел, что у словаря терминов, и по той же
#: причине: АФУ, МШУ, АЦП, ЗИП — это три буквы, и печатают их постоянно.
#: Короткое сличается по границам слова, внутрь другого слова не попадает.
MIN_WHOLE = 3

#: Короче этого основу не обрезаем: от «связи» остаётся «связ», и дальше
#: резать нечего — «свя» поймает «свяжите» и «связка».
MIN_STEM = 4

#: Окончания русских слов, длинные вперёд. Справочник состава пополняет
#: отдел, и писать в нём «земн станц спутников связ» (как принято в словаре
#: терминов) нельзя: то же слово идёт в поиск как запрос, и запрос должен
#: быть человеческим. Поэтому основу выделяем сами.
#:
#: Это стоило одного измерения: «земная станция спутниковой связи» не
#: находилась в вопросе «состав земной станциИ спутниковой связи» — сличение
#: идёт подстрокой, а «земная» подстрокой в «земной» не входит.
_ОКОНЧАНИЯ = (
    "иями", "ями", "ами", "ого", "его", "ему", "ому", "ыми", "ими",
    "ая", "яя", "ое", "ее", "ые", "ие", "ий", "ый", "ой", "ом", "ем",
    "ам", "ям", "ах", "ях", "ов", "ев", "ей", "ью", "ия", "ии", "ых", "их",
    "у", "ю", "а", "я", "ы", "и", "е", "о", "ь",
)


@dataclass(frozen=True)
class Composition:
    """Одна запись справочника: целое и узлы, из которых оно собрано."""

    whole: str
    units: Tuple[str, ...]
    #: Другие написания целого: «приёмный тракт» — тот же тракт приёма.
    also: Tuple[str, ...] = ()
    note: str = ""

    @property
    def names(self) -> Tuple[str, ...]:
        return (self.whole,) + self.also


def default_path() -> Path:
    """Где искать справочник, если путь не задан.

    Порядок тот же, что у словаря терминов: переменная окружения, каталог
    запуска, каталог рядом с установленным пакетом. Инструкция велит
    запускать приём из scripts\\windows, где никакого templates нет.
    """
    override = os.environ.get("REPORTGEN_PARTS_PATH")
    if override:
        return Path(override)
    if DEFAULT_PATH.is_file():
        return DEFAULT_PATH
    beside_package = Path(__file__).resolve().parents[2] / "templates" / "parts.json"
    if beside_package.is_file():
        return beside_package
    return DEFAULT_PATH


class PartsBook:
    """Справочник составов, прочитанный из JSON."""

    def __init__(self, compositions: Sequence[Composition], *,
                 source: Path | None = None, problems: Sequence[str] = ()):
        # Длинные названия вперёд: «тракт приёма РРЛС» точнее, чем «тракт
        # приёма», и если сработали оба — разбирать надо по точному.
        self.compositions: List[Composition] = sorted(
            compositions, key=lambda item: len(item.whole), reverse=True)
        self.source = source
        #: Записи, которые справочник отбросил, и почему. Пополняют его люди,
        #: и молча выбрасывать их работу нельзя: печатает этот список команда
        #: «reportgen parts».
        self.problems: List[str] = list(problems)

    def __len__(self) -> int:
        return len(self.compositions)

    @classmethod
    def load(cls, path: str | Path | None = None) -> "PartsBook":
        """Читает справочник. Нет файла или он испорчен — пустой справочник.

        Молча: разбор состава — усиление, а не условие работы. Помощник без
        него отвечает как раньше, и ронять вопрос инженера из-за справочника
        нельзя.
        """
        resolved = Path(path) if path else default_path()
        problems: List[str] = []
        try:
            raw = json.loads(resolved.read_text(encoding="utf-8-sig"))
        except OSError as error:
            return cls([], source=None, problems=[f"файл не прочитан: {error}"])
        except ValueError as error:
            return cls([], source=resolved,
                       problems=[f"файл не разобран как JSON: {error}"])

        rows = raw.get("parts", raw) if isinstance(raw, dict) else raw
        if not isinstance(rows, list):
            return cls([], source=resolved,
                       problems=["в файле нет списка «parts»"])

        составы: List[Composition] = []
        занято: Dict[str, str] = {}
        for номер, строка in enumerate(rows, start=1):
            состав, беда = _разобрать(номер, строка)
            if беда:
                problems.append(беда)
            if состав is None:
                continue
            повтор = [имя for имя in состав.names if normalize(имя) in занято]
            if повтор:
                problems.append(
                    f"запись {номер} «{состав.whole}»: написание «{повтор[0]}» "
                    f"уже занято записью «{занято[normalize(повтор[0])]}» — пропущена")
                continue
            for имя in состав.names:
                занято[normalize(имя)] = состав.whole
            составы.append(состав)
        return cls(составы, source=resolved, problems=problems)

    def match(self, question: str) -> List[Composition]:
        """Какие составы названы в вопросе. Точное совпадение — первым.

        «Точное» — это длина СОВПАВШЕГО написания, а не длина названия
        целого. В вопросе «расскажи про тракт приёма РРЛС» сходятся два
        состава: тракт приёма (по написанию «тракт приема РРЛС») и
        радиорелейная линия (по написанию «РРЛС»). Спрошено про тракт, и
        разбирать надо тракт — хотя само слово «радиорелейная линия» длиннее.

        Проверено измерением: сортировка по длине целого ставила первым
        состав станции РРЛ и вытесняла узлы тракта за предел.
        """
        текст = str(question or "")
        if not текст.strip():
            return []
        отобранные: List[Tuple[int, int, Composition]] = []
        for место, состав in enumerate(self.compositions):
            совпало = [имя for имя in состав.names if mentions(_основа(имя), текст)]
            if совпало:
                отобранные.append((-max(len(имя) for имя in совпало), место, состав))
        отобранные.sort(key=lambda строка: (строка[0], строка[1]))
        return [состав for _длина, _место, состав in отобранные]

    def units_for(self, question: str, *, limit: int = MAX_UNITS) -> List[str]:
        """Узлы, которые стоит поискать отдельно по этому вопросу.

        Порядок сохраняется таким, как записан в справочнике: он не
        случайный, а по ходу сигнала — антенна, усилитель, преобразователь,
        демодулятор. Инженер читает след разбора и должен узнавать в нём
        свой тракт.
        """
        предел = max(0, int(limit))
        if not предел:
            return []
        видели = set()
        узлы: List[str] = []
        for состав in self.match(question):
            for узел in состав.units:
                ключ = normalize(узел)
                if ключ in видели:
                    continue
                видели.add(ключ)
                узлы.append(узел)
                if len(узлы) >= предел:
                    return узлы
        return узлы


def _основа(name: str) -> str:
    """Название целого в виде, пригодном для сличения с вопросом.

    Сличение идёт подстрокой, поэтому в справочнике должна лежать основа, а
    не словарная форма: «земная» подстрокой в «земной» не входит, и запись
    «земная станция спутниковой связи» не находилась в вопросе «состав
    земной станции спутниковой связи».

    Словарь терминов решает это тем, что основы пишет человек («абонентск
    устройств»). Здесь так нельзя: то же название идёт в поиск как запрос, и
    запрос должен быть человеческим. Поэтому основу выделяем сами.
    """
    слова = []
    for слово in normalize(str(name or "")).split():
        слова.append(_обрезать(слово))
    return " ".join(слова)


def _обрезать(word: str) -> str:
    """Снять русское окончание, если после него остаётся настоящая основа."""
    for окончание in _ОКОНЧАНИЯ:
        if word.endswith(окончание) and len(word) - len(окончание) >= MIN_STEM:
            return word[: -len(окончание)]
    return word


def _разобрать(номер: int, строка: object) -> Tuple[Composition | None, str]:
    """Одна запись справочника: что вышло и что с ней не так."""
    if not isinstance(строка, dict):
        return None, f"запись {номер}: не объект — пропущена"
    целое = str(строка.get("whole", "")).strip()
    if not целое:
        return None, f"запись {номер}: не названо целое («whole») — пропущена"
    if len(normalize(целое)) < MIN_WHOLE:
        return None, (f"запись {номер} «{целое}»: название целого короче "
                      f"{MIN_WHOLE} знаков — оно встретится в любом вопросе "
                      f"и разберёт то, о чём не спрашивали; пропущена")

    сырые = строка.get("units") or []
    if isinstance(сырые, str):
        сырые = [сырые]
    узлы: List[str] = []
    видели = set()
    for узел in сырые:
        значение = " ".join(str(узел or "").split())
        ключ = normalize(значение)
        if not ключ or ключ in видели:
            continue
        видели.add(ключ)
        узлы.append(значение)
    if not узлы:
        return None, (f"запись {номер} «{целое}»: не перечислены узлы "
                      f"(«units») — разбирать не на что; пропущена")

    прочие = строка.get("also") or []
    if isinstance(прочие, str):
        прочие = [прочие]
    written: List[str] = []
    беды: List[str] = []
    for имя in прочие:
        значение = " ".join(str(имя or "").split())
        if not значение:
            continue
        if len(normalize(значение)) < MIN_WHOLE:
            беды.append(значение)
            continue
        written.append(значение)

    состав = Composition(whole=целое, units=tuple(узлы), also=tuple(written),
                         note=str(строка.get("note", "") or ""))
    беда = ""
    if беды:
        беда = (f"запись {номер} «{целое}»: написание «{беды[0]}» короче "
                f"{MIN_WHOLE} знаков — не взято")
    return состав, беда


_CACHE: Dict[str, Tuple[float, PartsBook]] = {}


def _mtime(path: Path) -> float:
    try:
        return path.stat().st_mtime
    except OSError:
        return 0.0


def book(path: str | Path | None = None) -> PartsBook:
    """Справочник с перечитыванием при правке файла.

    Отдел пополняет состав по ходу работы, и перезапускать ради этого
    сервер он не станет — значит, правка должна подхватываться сама.
    """
    resolved = Path(path) if path else default_path()
    ключ = str(resolved)
    отметка = _mtime(resolved)
    сохранённое = _CACHE.get(ключ)
    if сохранённое is not None and сохранённое[0] == отметка:
        return сохранённое[1]
    прочитанное = PartsBook.load(resolved)
    _CACHE[ключ] = (отметка, прочитанное)
    return прочитанное


def units_for(question: str, path: str | Path | None = None, *,
              limit: int = MAX_UNITS) -> List[str]:
    """Узлы названного в вопросе целого. Ничего не названо — пустой список."""
    return book(path).units_for(question, limit=limit)


def forget() -> None:
    """Забыть прочитанное. Нужно тестам и смене настроек на ходу."""
    _CACHE.clear()
