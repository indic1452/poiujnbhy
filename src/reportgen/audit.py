# -*- coding: utf-8 -*-
"""Сплошная проверка находимости: какие документы помощник не увидит.

Отдел: «делаю запрос на структуру этого стандарта — он не находит и вообще
не ссылается на этот документ. И так со многим… Нужно решать, чтобы не было
пропусков и был полноценный анализ по всей библиотеке».

Ключевое здесь — «по всей библиотеке». Разбирать по одному документу, когда
их тридцать тысяч, бессмысленно: пока найдёшь причину для одного, остальные
двадцать девять тысяч девятьсот девяносто девять останутся такими же, и
никто не знает, сколько их и что с ними.

Беда у ненаходимого документа тихая и всегда одинаковая по последствиям: он
числится в библиотеке, виден в списке, а в ответ не попадает никогда. Со
стороны это выглядит как «модель глупая» — и правится совсем не там, где
ищут. Причин же немного, и все они видны прямо в базе, без чтения файлов:

* **фрагментов нет вовсе** — файл не разобрался. Скан без распознавания,
  битый архив, PDF из одних картинок;
* **текста почти нет** — разобрался, но пусто: две строки колонтитула;
* **текст склеен** без пробелов — словесный поиск по такому не находит
  ничего, в указателе одно длинное «слово»;
* **векторов нет** — смысловой поиск документ не видит, остаётся словесный;
* **название негодное** — «Оглавление», «document»: помощник строит из
  названий карту библиотеки и по такой карте не знает, что у него на полках;
* **обозначение только в названии** — тот самый случай G.732. В названии
  «T-REC-G.732» номер есть, а в тексте документа его нет ни разу. Вопрос
  «структура цикла G.732» такой документ словесным поиском не достаёт;
* **статус не действующий** — документ намеренно убран из поиска, но знать
  об этом надо: на вопрос о нём ответ «не числится» будет ложью.

Проверка идёт по описи и по фрагментам, файлы не читаются: на тридцати
тысячах документов это минуты, а не сутки. Ничего не меняется — это
диагностика, и все её выводы человек проверяет сам.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Dict, List, Sequence, Tuple

from .designations import designations_in
from .ingest import titles
from .store.models import SEARCHABLE_STATUSES

__all__ = [
    "MIN_DOC_CHARS",
    "Finding",
    "DocumentReport",
    "audit_library",
    "summarize",
]

#: Меньше этого числа знаков во всех фрагментах вместе — документ пуст.
#: Двести знаков это две строки: столько остаётся от скана, когда со
#: страницы удалось снять только колонтитул.
MIN_DOC_CHARS = 200

#: Короче этого числа номер обозначения не проверяем: «25» из «X.25» есть в
#: любом документе, и жалоба вышла бы ложной. Промолчать здесь дешевле.
MIN_DESIGNATION_DIGITS = 3

#: Беды по убыванию тяжести. Порядок задаёт и вывод, и сортировку.
ПОРЯДОК = (
    "нет-фрагментов",
    "текста-почти-нет",
    "текст-склеен",
    "обозначение-только-в-названии",
    "название-негодное",
    "нет-векторов",
    "не-действующий",
)


@dataclass(frozen=True)
class Finding:
    """Одна беда одного документа: что не так, чем грозит, что делать."""

    code: str
    problem: str
    advice: str
    #: Документ не находится ВООБЩЕ ничем. Отличать обязательно: «находится
    #: хуже» и «не находится никак» — разные беды и разной срочности.
    blocking: bool = False


@dataclass
class DocumentReport:
    doc_id: str
    title: str = ""
    doc_type: str = ""
    domain: str = ""
    status: str = "current"
    chunks: int = 0
    chars: int = 0
    vectors: int = 0
    findings: List[Finding] = field(default_factory=list)

    @property
    def blocked(self) -> bool:
        return any(беда.blocking for беда in self.findings)

    @property
    def codes(self) -> List[str]:
        return [беда.code for беда in self.findings]


def audit_library(repos: Any, *, doc_type: str | None = None,
                  domain: str | None = None) -> List[DocumentReport]:
    """Проверить всю библиотеку. Возвращает только документы с бедами."""
    документы = repos.documents.list(doc_type, domain)
    if not документы:
        return []
    статистика = _chunk_stats(repos)
    повторы = titles.repeated_titles(str(документ.title or "")
                                     for документ in документы)
    # Векторов нет НИ У КОГО — это одна беда всей библиотеки (не поднята
    # служба эмбеддингов), а не тридцать тысяч отдельных. Писать её в каждую
    # строку значит утопить в ней всё остальное; про неё скажет сводка.
    всего_векторов = sum(строка[2] for строка in статистика.values())

    отчёты: List[DocumentReport] = []
    for документ in документы:
        куски, знаки, векторы = статистика.get(документ.id, (0, 0, 0))
        отчёт = DocumentReport(
            doc_id=документ.doc_id, title=str(документ.title or ""),
            doc_type=документ.doc_type, domain=документ.domain or "",
            status=документ.status, chunks=куски, chars=знаки, vectors=векторы)
        отчёт.findings = _findings(repos, документ, отчёт, повторы,
                                   векторы_есть=всего_векторов > 0)
        if отчёт.findings:
            отчёты.append(отчёт)
    отчёты.sort(key=_вес)
    return отчёты


def summarize(reports: Sequence[DocumentReport], *, total: int,
              vectors: int | None = None, chunks: int | None = None) -> List[str]:
    """Итог словами: сколько документов и по какой причине не находится."""
    if not total:
        return ["библиотека пуста"]
    счёт: Dict[str, int] = {}
    for отчёт in reports:
        for код in отчёт.codes:
            счёт[код] = счёт.get(код, 0) + 1
    немые = sum(1 for отчёт in reports if отчёт.blocked)

    строки = [f"документов в библиотеке: {total}",
              f"с замечаниями: {len(reports)}"]
    if немые:
        доля = немые * 100 / total
        # «Почти» здесь честное: у документа с двумя строками колонтитула
        # текст формально есть, и по этим двум строкам он даже найдётся —
        # но ни на один вопрос по существу он не выйдет никогда.
        строки.append(f"НЕ НАХОДЯТСЯ ИЛИ ПОЧТИ НЕ НАХОДЯТСЯ: {немые} ({доля:.1f}%)")
    for код in ПОРЯДОК:
        if счёт.get(код):
            строки.append(f"  {код}: {счёт[код]}")
    прочие = sorted(set(счёт) - set(ПОРЯДОК))
    for код in прочие:
        строки.append(f"  {код}: {счёт[код]}")

    # Векторов нет ни у кого — беда одна на всю библиотеку, и в строках
    # документов её намеренно нет: тридцать тысяч одинаковых строк утопили бы
    # всё остальное. Но промолчать о ней нельзя, это половина поиска.
    if chunks and not vectors:
        строки.append("")
        строки.append("СМЫСЛОВОЙ ПОИСК НЕ РАБОТАЕТ: векторов нет ни одного "
                      f"при {chunks} фрагментах.")
        строки.append("  Поднимите службу эмбеддингов и выполните "
                      "«reportgen embed» — сейчас ищет только словесный канал, "
                      "и англоязычная половина библиотеки не находится вовсе.")
    return строки


