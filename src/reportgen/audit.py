def _findings(repos: Any, document: Any, отчёт: DocumentReport,
              повторы: Dict[str, int], *, векторы_есть: bool = True
              ) -> List[Finding]:
    беды: List[Finding] = []

    if отчёт.chunks == 0:
        беды.append(Finding(
            "нет-фрагментов",
            "ни одного фрагмента — файл не разобрался",
            "скан или битый файл: распознайте его (reportgen ocr) либо "
            "пересохраните и примите заново с --force",
            blocking=True))
    elif отчёт.chars < MIN_DOC_CHARS:
        беды.append(Finding(
            "текста-почти-нет",
            f"текста {отчёт.chars} знаков на {отчёт.chunks} фрагм. — "
            f"похоже на скан без распознавания",
            "распознайте документ: без текста он не находится ничем, "
            "кроме названия",
            blocking=True))

    if str(document.meta.get("text_quality") or "") == "glued":
        беды.append(Finding(
            "текст-склеен",
            "текст склеен без пробелов — в указателе одно длинное «слово»",
            "переложите файл через OCR или сохраните в другом формате: "
            "словесный поиск по такому документу не находит почти ничего"))

    if векторы_есть and отчёт.chunks and отчёт.vectors < отчёт.chunks:
        нет = отчёт.chunks - отчёт.vectors
        беды.append(Finding(
            "нет-векторов",
            f"фрагментов без векторов {нет} из {отчёт.chunks} — "
            f"смысловой поиск их не видит",
            "поднимите службу эмбеддингов и выполните «reportgen embed»"))

    изъян = titles.title_problem(отчёт.title)
    повтор = повторы.get(titles.normalize_title(отчёт.title), 0)
    if изъян or повтор:
        причина = изъян or f"одно название на {повтор} документов — из бланка"
        беды.append(Finding(
            "название-негодное",
            f"название «{отчёт.title}» — {причина}",
            "посмотрите «reportgen retitle»: помощник строит из названий "
            "карту библиотеки и по такой карте не знает, что у него на полках"))

    потерянные = _designations_missing(repos, document, отчёт)
    if потерянные:
        беды.append(Finding(
            "обозначение-только-в-названии",
            "обозначение " + ", ".join(потерянные)
            + " есть в названии, но НИ РАЗУ не встречается в тексте",
            "словесный поиск по номеру такой документ не достаёт. Помощник "
            "подложит его, когда номер назван в вопросе прямо, — но если "
            "текст пуст или это скан, проверьте разбор файла"))

    if отчёт.status not in SEARCHABLE_STATUSES:
        беды.append(Finding(
            "не-действующий",
            f"статус «{отчёт.status}» — в поиске документ не участвует",
            "так и задумано; знать об этом нужно, чтобы не считать документ "
            "пропавшим"))
    return беды


def _designations_missing(repos: Any, document: Any,
                          отчёт: DocumentReport) -> List[str]:
    """Обозначения из названия, которых нет в тексте документа.

    Тот самый случай G.732: в названии «T-REC-G.732» номер есть, в тексте
    его нет ни разу, и вопрос «структура цикла G.732» словесным поиском
    документ не достаёт.
    """
    if not отчёт.chunks:
        return []
    обозначения = designations_in(отчёт.title)
    if not обозначения:
        return []
    потерянные = []
    for обозначение in обозначения:
        if not _text_mentions(repos, document.id, обозначение):
            потерянные.append(обозначение)
    return потерянные


def _text_mentions(repos: Any, document_id: int, designation: str) -> bool:
    """Встречается ли обозначение в тексте документа хоть раз.

    Сличаем по САМОМУ ДЛИННОМУ числу обозначения, а не по строке целиком и
    не по всем его цифрам подряд. Строка целиком не годится: в названии
    стоит «ГОСТ Р 53363-2009» через дефис, а в самом тексте ГОСТа —
    «ГОСТ Р 53363—2009» через тире, и сличение подстрок дало бы ложную
    жалобу на каждый второй ГОСТ. Все цифры подряд не годятся тем более:
    из «РД 45.298-2002» вышло бы «452982002», чего нет нигде.

    Число короче трёх знаков проверять не будем: «X.25» дало бы «25», а
    двузначное число есть в любом документе. Здесь лучше промолчать, чем
    сказать неправду: жалоба на находимый документ дороже пропущенной.
    """
    числа = re.findall(r"\d+", str(designation or ""))
    if not числа:
        return True
    число = max(числа, key=len)
    if len(число) < MIN_DESIGNATION_DIGITS:
        return True
    строки = repos.db.query(
        "SELECT 1 FROM chunks WHERE document_id = ? AND text LIKE ? LIMIT 1",
        (document_id, f"%{число}%"))
    return bool(строки)


def _chunk_stats(repos: Any) -> Dict[int, Tuple[int, int, int]]:
    """Фрагменты, знаки и векторы по каждому документу — одним запросом.

    Именно одним: тридцать тысяч отдельных запросов превратили бы минутную
    проверку в получасовую, и её перестали бы запускать.
    """
    строки = repos.db.query(
        "SELECT c.document_id AS document_id, "
        "       COUNT(*) AS chunks, "
        "       COALESCE(SUM(LENGTH(c.text)), 0) AS chars, "
        "       COUNT(e.chunk_uid) AS vectors "
        "FROM chunks c "
        "LEFT JOIN embeddings e ON e.chunk_uid = c.chunk_uid "
        "GROUP BY c.document_id")
    return {int(строка["document_id"]):
            (int(строка["chunks"]), int(строка["chars"]), int(строка["vectors"]))
            for строка in строки}


def _вес(отчёт: DocumentReport) -> Tuple[int, str]:
    """По тяжести самой тяжёлой беды, при равенстве — по имени.

    Отдельного «сначала ненаходимые» здесь нет намеренно: беды, от которых
    документ не находится вовсе, стоят В НАЧАЛЕ ``ПОРЯДОК``, и порядок сам
    ставит их первыми. Вторая проверка того же самого прикрывала бы первую,
    и ошибка в порядке осталась бы невидимой. Что это правда, а не
    договорённость на словах, стережёт тест.
    """
    места = [ПОРЯДОК.index(код) if код in ПОРЯДОК else len(ПОРЯДОК)
             for код in отчёт.codes]
    return (min(места) if места else len(ПОРЯДОК), отчёт.doc_id)
