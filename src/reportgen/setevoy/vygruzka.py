def статистика(сводки: Sequence[Сводка], поля: Sequence[dict[str, list[Any]]], нагрузки: Sequence[bytes | None]
               ) -> dict[str, Any]:
    """Все таблицы статистики по отобранным пакетам (как вкладки страницы)."""
    дерево = statistika.иерархия(сводки)[0]
    время = statistika.по_времени(сводки)
    return {
        "иерархия": statistika.иерархия_строками(дерево),
        **{f"диалоги-{у}": statistika.диалоги(сводки, у) for у in ("eth", "ip", "tcp", "udp")},
        "узлы": statistika.узлы(сводки),
        "время": [{"начало": round(время["начало"] + i * время["шаг"], 6), "шаг": время["шаг"], "пакетов": п, "байт": б}
                  for i, (п, б) in enumerate(zip(время["пакетов"], время["байт"], strict=True))],
        "dns": statistika.dns(сводки, поля), "http": statistika.http(сводки, поля),
        "tls": statistika.tls(сводки, поля), "ошибки": statistika.ошибки(сводки),
        "неизвестные": statistika.неизвестные(сводки, нагрузки),
    }


