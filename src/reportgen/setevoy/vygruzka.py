def список_пакетов(сводки: Sequence[Сводка], пояс: int = 0) -> list[dict[str, Any]]:
    return [{"номер": с["номер"], "время": с["время"], "время_iso": время_iso(с["время"], пояс),
             "источник": с["источник"], "получатель": с["получатель"], "протокол": с["протокол"],
             "длина": с["длина"], "стек": "/".join(с["стек"]), "сведения": с["инфо"],
             "ошибки": " | ".join(с["ошибки"])} for с in сводки]


def _в_путь(сводка: Сводка, путь: Sequence[str]) -> bool:
    return list(сводка["стек"][:len(путь)]) == list(путь)


def разбор(пакеты: Iterable[dict[str, Any]]) -> Iterable[dict[str, Any]]:
    """Полный разбор: номер, время, длина, канал, уровни с деревом полей (имя, ключ, значение, место, дети)."""
    for п in пакеты:
        yield {"номер": п["номер"], "время": п["время"], "длина": п["длина"], "канал": п.get("канал", ""),
               "протокол": п["протокол"], "уровни": п["уровни"],
               **({"собранный": п["собранный"]["уровни"]} if п.get("собранный") else {})}


def _поля_плоско(поля: Sequence[dict[str, Any]], итог: dict[str, list[str]], приставка: str = "") -> None:
    for п in поля:
        ключ = п.get("ключ") or (приставка + п["имя"])
        итог.setdefault(ключ, []).append(п["текст"])
        _поля_плоско(п.get("дети") or [], итог, ключ + ".")


def поля_по_протоколам(пакеты: Iterable[dict[str, Any]], путь: Sequence[str] = ()
                       ) -> dict[str, list[dict[str, Any]]]:
    """Протокол → строки (номер, время, поле → значения): поля каждого уровня разбора. С ``путь`` — только
    уровень узла дерева (на месте len(путь) − 1 у пакетов, чей стек начинается путём)."""
    итог: dict[str, list[dict[str, Any]]] = {}
    for п in пакеты:
        уровни = п["уровни"]
        стек = [у["протокол"] for у in уровни]
        if путь:
            if стек[:len(путь)] != list(путь):
                continue
            уровни = [уровни[len(путь) - 1]]
        for у in уровни:
            плоско: dict[str, list[str]] = {}
            _поля_плоско(у["поля"], плоско)
            итог.setdefault(у["протокол"], []).append(
                {"номер": п["номер"], "время": п["время"], **{к: " | ".join(з) for к, з in плоско.items()}})
    return итог


