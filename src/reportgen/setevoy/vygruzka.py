def csv_байты(строки: Sequence[dict[str, Any]], столбцы: Sequence[str] | None = None) -> bytes:
    """CSV для Excel: «;», UTF-8 с BOM; столбцы — заданные или ключи строк по первому появлению."""
    if столбцы is None:
        столбцы = list(dict.fromkeys(к for с in строки for к in с))
    буфер = io.StringIO()
    запись = csv.DictWriter(буфер, fieldnames=list(столбцы), delimiter=";", extrasaction="ignore")
    запись.writeheader()
    for с in строки:
        запись.writerow({к: _ячейка(з) for к, з in с.items()})
    return ("﻿" + буфер.getvalue()).encode("utf-8")


def csv_кусками(строки: Iterable[dict[str, Any]], кусок: int = 1 << 16) -> Iterator[bytes]:
    """CSV байт в байт как csv_байты(list(строки)), но без всех строк в памяти: столбцы известны лишь после
    последней строки, поэтому строки сперва — во временный файл, затем CSV — кусками."""
    столбцы: dict[str, None] = {}
    with tempfile.TemporaryFile() as запас:
        for с in строки:
            столбцы.update(dict.fromkeys(с))
            pickle.dump(с, запас, protocol=pickle.HIGHEST_PROTOCOL)
        запас.seek(0)
        буфер = io.StringIO()
        запись = csv.DictWriter(буфер, fieldnames=list(столбцы), delimiter=";", extrasaction="ignore")
        буфер.write("\ufeff")
        запись.writeheader()
        while True:
            try:
                с = pickle.load(запас)
            except EOFError:
                break
            запись.writerow({к: _ячейка(з) for к, з in с.items()})
            if буфер.tell() >= кусок:
                yield буфер.getvalue().encode("utf-8")
                буфер.seek(0)
                буфер.truncate()
        yield буфер.getvalue().encode("utf-8")


def _ячейка(значение: Any) -> Any:
    if isinstance(значение, (list, tuple)):
        return " | ".join(map(str, значение))
    if isinstance(значение, dict):
        return json.dumps(значение, ensure_ascii=False)
    return значение


def json_байты(данные: Any, отступ: bool = False) -> bytes:
    return json.dumps(данные, ensure_ascii=False, indent=2 if отступ else None, default=str).encode("utf-8")


def json_список_кусками(строки: Iterable[Any], отступ: bool = False) -> Iterable[bytes]:
    """Список JSON кусками — байт в байт как json_байты(list(строки), отступ), но без списка в памяти."""
    первый = True
    for строка in строки:
        тело = json_байты(строка, отступ)
        if отступ:
            тело = b"\n".join(b"  " + с for с in тело.split(b"\n"))
            yield (b"[\n" if первый else b",\n") + тело
        else:
            yield (b"[" if первый else b", ") + тело
        первый = False
    yield b"[]" if первый else (b"\n]" if отступ else b"]")


def время_iso(время: float, пояс: int) -> str:
    return obekty.время_текстом(время, пояс)


def безопасно(текст: str) -> str:
    """Часть имени в архиве: только буквы, цифры, «.», «-», «_»."""
    return re.sub(r"[^\w.-]+", "_", текст, flags=re.U).strip("_") or "x"


