def потоки(сводки: Sequence[Сводка], нагрузки: Sequence[bytes | None], путь: Sequence[str] = ()
           ) -> list[tuple[str, bytes, obekty.Сторона, str]]:
    """Сырые потоки TCP/UDP по направлениям: (имя файла, байты, сторона, транспорт). С ``путь`` — только
    соединения, где есть пакеты этого узла дерева протоколов."""
    нужные = {с["номер"] for с in сводки if _в_путь(с, путь)} if путь else None
    соединения, _ = obekty.соединения(сводки, нагрузки)
    итог = []
    for соед in соединения:
        стороны = list(соед.стороны.values())
        if соед.транспорт == "UDP":
            стороны = []
            for отправитель, сторона in соед.стороны.items():
                собранная = obekty.Сторона("UDP", сторона.от, сторона.к)
                for о, д, н, _ in соед.датаграммы:
                    if о == отправитель:
                        собранная.добавить(д, н)
                стороны.append(собранная)
        for сторона in стороны:
            if нужные is not None and not нужные.intersection(н for _, н in сторона.карта):
                continue
            имя = f"{соед.номер:04d}-{соед.транспорт}-{безопасно(сторона.от)}-{безопасно(сторона.к)}.bin"
            итог.append((имя, bytes(сторона.данные), сторона, соед.транспорт))
    return итог


