ОПИСЬ = ("путь", "что", "поток", "пакеты", "протокол", "время", "размер", "sha256")


class Архив:
    """ZIP во временном файле (до 64 МБ — в памяти) и опись: путь, что, откуда (поток, пакеты, протокол), время
    первого пакета, размер, SHA-256. Что не вошло по пределу объёма — в «не вошло»."""

    def __init__(self, предел: int = 1 << 62, пояс: int = 0) -> None:
        self.файл = tempfile.SpooledTemporaryFile(max_size=64 << 20)
        self.zip = zipfile.ZipFile(self.файл, "w", zipfile.ZIP_DEFLATED, compresslevel=1)
        self.опись: list[dict[str, Any]] = []
        self.занято: set[str] = set()
        self.предел, self.пояс, self.байт = предел, пояс, 0
        self.не_вошло: list[str] = []

    def положить(self, путь: str, данные: bytes, что: str, *, поток: str = "", пакеты: Sequence[int] = (),
                 протокол: str = "", время: float | None = None) -> str | None:
        if self.байт + len(данные) > self.предел:
            self.не_вошло.append(f"{путь} ({len(данные)} байт) — сверх предела объёма {self.предел} байт")
            return None
        self.байт += len(данные)
        основа, точка, расширение = путь.rpartition(".")
        итог, n = путь, 1
        while итог.lower() in self.занято:
            n += 1
            итог = f"{основа}-{n}.{расширение}" if точка else f"{путь}-{n}"
        self.занято.add(итог.lower())
        self.zip.writestr(итог, данные)
        self.опись.append({"путь": итог, "что": что, "поток": поток,
                           "пакеты": " ".join(map(str, пакеты[:1000])) + (" …" if len(пакеты) > 1000 else ""),
                           "протокол": протокол, "время": время_iso(время, self.пояс) if время is not None else "",
                           "размер": len(данные), "sha256": hashlib.sha256(данные).hexdigest()})
        return итог

    def положить_поток(self, путь: str, куски: Iterable[bytes], что: str, *, размер: int | None = None,
                       поток: str = "", пакеты: Sequence[int] = (), протокол: str = "",
                       время: float | None = None) -> str | None:
        """Как ``положить``, но байты идут кусками (выгрузка миллионов пакетов не собирается в памяти).
        Известный заранее ``размер`` сверяется с пределом сразу; неизвестный — по ходу: сверх предела
        запись обрывается и это отмечается в «не вошло»."""
        if размер is not None and self.байт + размер > self.предел:
            self.не_вошло.append(f"{путь} ({размер} байт) — сверх предела объёма {self.предел} байт")
            return None
        основа, точка, расширение = путь.rpartition(".")
        итог, n = путь, 1
        while итог.lower() in self.занято:
            n += 1
            итог = f"{основа}-{n}.{расширение}" if точка else f"{путь}-{n}"
        self.занято.add(итог.lower())
        хэш = hashlib.sha256()
        длина = 0
        with self.zip.open(итог, "w", force_zip64=True) as ф:
            for кусок in куски:
                if self.байт + длина + len(кусок) > self.предел:
                    кусок = кусок[:max(0, self.предел - self.байт - длина)]
                    self.не_вошло.append(f"{итог} — обрезан по пределу объёма {self.предел} байт")
                    ф.write(кусок)
                    хэш.update(кусок)
                    длина += len(кусок)
                    break
                ф.write(кусок)
                хэш.update(кусок)
                длина += len(кусок)
        self.байт += длина
        self.опись.append({"путь": итог, "что": что, "поток": поток,
                           "пакеты": " ".join(map(str, пакеты[:1000])) + (" …" if len(пакеты) > 1000 else ""),
                           "протокол": протокол, "время": время_iso(время, self.пояс) if время is not None else "",
                           "размер": длина, "sha256": хэш.hexdigest()})
        return итог

    def закрыть(self, заметки: Sequence[str] = (), отступ: bool = False):
        if заметки or self.не_вошло:
            self.zip.writestr("заметки.txt", "".join(з + "\n" for з in [*заметки, *self.не_вошло]).encode())
        self.zip.writestr("опись.csv", csv_байты(self.опись, ОПИСЬ))
        self.zip.writestr("опись.json", json_байты(self.опись, отступ))
        self.zip.close()
        self.файл.seek(0)
        return self.файл


def собрать_выгрузку(захваты, ид: str, фильтр: str, пункты: Sequence[str], настройки: obekty.Настройки):
    """Отмеченное (``пункты`` из КЛЮЧИ) — одним ZIP: папки по видам, опись.csv и опись.json. Пакеты и списки
    идут в архив потоком с диска; пока разбор идёт — выгружается разобранное к этому мигу."""
    from pathlib import Path  # noqa: PLC0415

    import numpy as np  # noqa: PLC0415

    from . import vydacha  # noqa: PLC0415
    отбор = захваты.отбор(ид, фильтр)
    х = захваты.хранилище(ид)
    номера = отбор.номера()
    число = len(номера)
    свои = (номера[:1001] + 1).tolist()                # опись называет первую тысячу номеров
    начало = х.сводки_по(номера[:1])[0]["время"] if число else None
    а = Архив(настройки.байт_до, настройки.пояс)
    заметки: list[str] = []
    if not отбор.ход()["готово"]:
        заметки.append(f"разбор или отбор ещё шёл: выгружено {число} пакетов, отобранных к этому мигу")
    основа = безопасно(Path(захваты.прочитать(ид)["имя"]).stem)
    if "pcap" in пункты or "pcapng" in пункты:
        длины = np.zeros(0, dtype=np.int64)
        for от in range(0, число, 65536):
            длины = np.concatenate([длины, х.записи_по(номера[от:от + 65536])["длина"].astype(np.int64)])
        if "pcap" in пункты:
            а.положить_поток(f"пакеты/{основа}-отбор.pcap", захваты.поток_pcap(ид, номера), "отобранные пакеты (pcap)",
                             размер=24 + 16 * число + int(длины.sum()), пакеты=свои, время=начало)
        if "pcapng" in пункты:
            а.положить_поток(f"пакеты/{основа}-отбор.pcapng", захваты.поток_pcapng(ид, номера),
                             "отобранные пакеты (pcapng)", размер=28 + 32 * число + int((длины + (-длины % 4)).sum()),
                             пакеты=свои, время=начало)
    if "list-csv" in пункты or "list-json" in пункты:
        def строки():
            for сводки in vydacha.сводки_порциями(х, номера):
                yield from список_пакетов(сводки, настройки.пояс)
        if "list-csv" in пункты:
            def csv_куски():
                шапка = True
                порция: list[dict[str, Any]] = []
                for строка in строки():
                    порция.append(строка)
                    if len(порция) >= 4096:
                        yield _csv_часть(порция, шапка)
                        порция, шапка = [], False
                if порция or шапка:
                    yield _csv_часть(порция, шапка)
            а.положить_поток("пакеты/список.csv", csv_куски(), "список пакетов (CSV)", пакеты=свои, время=начало)
        if "list-json" in пункты:
            а.положить_поток("пакеты/список.json", json_список_кусками(строки(), настройки.json_отступ),
                             "список пакетов (JSON)", пакеты=свои, время=начало)
    if "dissect-json" in пункты or "fields-csv" in пункты:
        пакеты = [захваты.пакет(ид, н) for н in свои[:min(РАЗБОР_ДО, число)]]
        if число > РАЗБОР_ДО:
            заметки.append(f"полный разбор и поля — первые {РАЗБОР_ДО} пакетов из {число}")
        if "dissect-json" in пункты:
            а.положить("пакеты/разбор.json", json_байты(list(разбор(пакеты)), настройки.json_отступ),
                       "полный разбор пакетов (дерево полей)", пакеты=свои[:РАЗБОР_ДО], время=начало)
        if "fields-csv" in пункты:
            for протокол, строки_ in поля_по_протоколам(пакеты).items():
                а.положить(f"поля/{безопасно(протокол)}.csv", csv_байты(строки_), f"поля протокола {протокол}",
                           пакеты=[с["номер"] for с in строки_], протокол=протокол, время=строки_[0]["время"])
    if "stats" in пункты:
        ключ = (ид, захваты.прочитать(ид).get("поколение", 1), фильтр)
        for имя in vydacha.ТАБЛИЦЫ:
            таблица = vydacha.таблица_статистики(отбор, имя, ключ)
            а.положить(f"статистика/{имя}.csv", csv_байты(таблица), f"статистика: {имя} (CSV)", время=начало)
            а.положить(f"статистика/{имя}.json", json_байты(таблица, настройки.json_отступ),
                       f"статистика: {имя} (JSON)", время=начало)
    if "objects" in пункты or "rtp" in пункты or "report" in пункты:
        итог = захваты.объекты(ид, фильтр, настройки)
        if итог["отброшено"]["объектов"]:
            заметки.append(f"объектов отброшено по пределам: {итог['отброшено']['объектов']}, "
                           f"байт {итог['отброшено']['байт']}")
        заметки += итог["заметки"]
        for о in итог["объекты"]:
            ртп = о.вид in RTP_ВИДЫ
            if ртп and "rtp" not in пункты or not ртп and "objects" not in пункты:
                continue
            время = итог["время"].get(о.пакеты[0]) if о.пакеты else None
            папка = "rtp/" if ртп else f"объекты/{безопасно(о.вид)}/"
            а.положить(папка + obekty.имя_выгрузки(о, настройки, время), о.данные,
                       f"{о.вид}: {о.содержимое}" + (f" — {'; '.join(о.заметки)}" if о.заметки else ""),
                       поток=о.поток, пакеты=о.пакеты, протокол=о.вид, время=время)
    if "streams" in пункты:
        from .zahvaty import ОБЪЕКТЫ_БАЙТ_ДО  # noqa: PLC0415
        до = vydacha.до_предела_нагрузки(отбор, ОБЪЕКТЫ_БАЙТ_ДО)
        if до < число:
            заметки.append(f"сырые потоки собраны по первым {до} пакетам отбора из {число}")
        сводки_п = list(vydacha.первые(отбор, "сводки", до))
        for имя, данные, сторона, транспорт in потоки(сводки_п, list(vydacha.первые(отбор, "нагрузки_тр", до))):
            пакеты_потока = [н for _, н in сторона.карта]
            а.положить(f"потоки/{имя}", данные, "сырой поток по направлению", поток=сторона.поток,
                       пакеты=пакеты_потока, протокол=транспорт,
                       время=х.сводка(пакеты_потока[0] - 1)["время"] if пакеты_потока else None)
    if "report" in пункты:
        обзор = vydacha.обзор(отбор, отбор.ход())
        дерево = statistika.иерархия_строками(vydacha.иерархия(отбор)[0])
        страница, текст = отчёт(захваты.прочитать(ид)["имя"], обзор, дерево, obekty.по_видам(итог), итог["объекты"],
                                настройки.пояс)
        а.положить("отчёт/обзор.html", страница.encode(), "отчёт-обзор (HTML)", время=начало)
        а.положить("отчёт/обзор.txt", текст.encode(), "отчёт-обзор (текст)", время=начало)
    return а.закрыть(заметки, настройки.json_отступ)


def _csv_часть(строки: list[dict[str, Any]], шапка: bool) -> bytes:
    """Кусок CSV списка пакетов: как csv_байты, но с шапкой (и BOM) только у первого куска."""
    данные = csv_байты(строки, list(строки[0]) if строки else ["номер", "время", "время_iso", "источник",
                                                                "получатель", "протокол", "длина", "стек",
                                                                "сведения", "ошибки"])
    if шапка:
        return данные
    текст = данные.decode("utf-8-sig")
    return текст.split("\r\n", 1)[1].encode("utf-8") if "\r\n" in текст else текст.split("\n", 1)[1].encode("utf-8")
