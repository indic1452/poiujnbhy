def _amqp_длина(д, н) -> int:
    тип, канал, размер = д[н], б16(д, н + 1), б32(д, н + 3)
    if тип not in AMQP_КАДРЫ or (тип == 8 and (канал or размер)):
        raise _Чужое("кадр AMQP")
    if тип == 1 and (размер < 4 or (н + 11 <= len(д) and б16(д, н + 9) not in AMQP_МЕТОДЫ.get(б16(д, н + 7), {}))):
        raise _Чужое("метод AMQP")
    if тип == 2 and (размер < 14 or (н + 11 <= len(д) and б16(д, н + 9))):
        raise _Чужое("заголовок содержимого AMQP")
    if н + 8 + размер <= len(д) and д[н + 7 + размер] != 0xCE:
        raise _Чужое("кадр AMQP без 0xCE")
    return 8 + размер


@_откат
def amqp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    у = None
    if д.startswith(b"AMQP", м):
        if конец - м != 8:
            return False
        у = р.уровень("AMQP", "Advanced Message Queuing Protocol", м)
        версия = ".".join(str(б) for б in д[м + 5:м + 8])
        у.поле("Заголовок протокола", "amqp.init.protocol", "AMQP", м, 4)
        у.поле("Класс протокола", "amqp.init.id", д[м + 4], м + 4, 1)
        у.поле("Версия", "amqp.init.version", версия, м + 5, 3)
        у.длина = 8
        у.итог = f"заголовок протокола {д[м + 4]}-{версия.replace('.', '-')}"
        р.п.инфо = "AMQP " + у.итог
        return True
    куски, хвост = _нарезать(д, м, lambda н: _amqp_длина(д, н), 7)
    if not _полных(куски, конец) and not (д[м] == 1 and м + 11 <= конец):
        return False                                   # один оборванный кадр — только метод (класс и метод известны)
    у = р.уровень("AMQP", "Advanced Message Queuing Protocol", м)
    итоги = []
    for н, к in куски:
        итоги.append(_amqp_кадр(у, д, н, min(к, конец), к > конец))
    if хвост is not None:
        _хвост(у, хвост, конец, "amqp.continuation_data")
    у.длина = конец - м
    у.итог = _свести(итоги)
    р.п.инфо = "AMQP " + у.итог
    if _оборван(куски, хвост, конец):
        р.ошибка("AMQP: кадр продолжается в следующем сегменте")
    return True


def _amqp_кадр(у, д, н, к, оборван) -> str:
    тип, канал, размер = д[н], б16(д, н + 1), б32(д, н + 3)
    узел = у.поле(f"{AMQP_КАДРЫ[тип]}, канал {канал}, {размер} байт", "amqp.type", AMQP_КАДРЫ[тип], н, к - н, тип)
    у.поле("Тип", "amqp.type", f"{AMQP_КАДРЫ[тип]} ({тип})", н, 1, тип, родитель=узел)
    у.поле("Канал", "amqp.channel", канал, н + 1, 2, родитель=узел)
    у.поле("Размер", "amqp.length", размер, н + 3, 4, родитель=узел)
    т = н + 7
    if not оборван:
        у.поле("Конец кадра", "amqp.frame_end", "0xce", н + 7 + размер, 1, 0xCE, родитель=узел)
    if тип == 1:
        класс, метод = б16(д, т), б16(д, т + 2)
        имя = f"{AMQP_КЛАССЫ[класс]}.{AMQP_МЕТОДЫ[класс][метод]}"
        у.поле("Класс", "amqp.method.class", f"{AMQP_КЛАССЫ[класс]} ({класс})", т, 2, класс, родитель=узел)
        у.поле("Метод", "amqp.method.method", f"{AMQP_МЕТОДЫ[класс][метод]} ({метод})", т + 2, 2, метод, родитель=узел)
        узел.текст = имя
        доп = []
        место = т + 4
        try:
            for вид, подпись, ключ in AMQP_АРГУМЕНТЫ.get((класс, метод), []):
                if вид == "s":
                    n = д[место]
                    значение = _текст(_байты(д, место + 1, n))
                    у.поле(подпись, f"amqp.method.arguments.{ключ}", значение, место, 1 + n, родитель=узел)
                    место += 1 + n
                    if ключ in ("exchange", "routing_key", "queue", "virtual_host", "reply_text"):
                        доп.append(f"{ключ}={значение}")
                else:
                    n = 1 if вид == "b" else int(вид)
                    значение = _ч(д, место, n)
                    if ключ != "reserved_1":
                        у.поле(подпись, f"amqp.method.arguments.{ключ}", значение, место, n, родитель=узел)
                    место += n
        except Мало:
            pass
        return f"{имя} ({канал})" + (" " + " ".join(доп) if доп else "")
    if тип == 2:
        класс = б16(д, т)
        у.поле("Класс", "amqp.header.class", AMQP_КЛАССЫ.get(класс, str(класс)), т, 2, класс, родитель=узел)
        у.поле("Размер содержимого", "amqp.header.body_size", б64(д, т + 4), т + 4, 8, родитель=узел)
        у.поле("Флаги свойств", "amqp.header.property_flags", f"0x{б16(д, т + 12):04x}", т + 12, 2, б16(д, т + 12),
               родитель=узел)
        return f"заголовок содержимого, {б64(д, т + 4)} байт"
    if тип == 3:
        сколько = min(размер, к - т)
        у.поле("Содержимое", "amqp.payload", f"{размер} байт: {печатное(д[т:т + сколько], 40)}", т, сколько,
               родитель=узел)
        return f"содержимое {размер} байт"
    return "heartbeat"


