def _smpp_pdu(у, д, н, к) -> str:
    д = д[:к]
    дл, команда, статус, номер = б32(д, н), б32(д, н + 4), б32(д, н + 8), б32(д, н + 12)
    имя = SMPP_КОМАНДЫ[команда]
    узел = у.поле(f"{имя}, номер {номер}", "smpp.command_id", имя, н, к - н, команда)
    у.поле("Длина", "smpp.command_length", дл, н, 4, родитель=узел)
    у.поле("Команда", "smpp.command_id", f"{имя} (0x{команда:08x})", н + 4, 4, команда, родитель=узел)
    у.поле("Состояние", "smpp.command_status", SMPP_СТАТУСЫ.get(статус, f"0x{статус:08x}"), н + 8, 4, статус,
           родитель=узел)
    у.поле("Номер", "smpp.sequence_number", номер, н + 12, 4, родитель=узел)
    т = н + 16
    итог = имя + (f" {SMPP_СТАТУСЫ.get(статус, hex(статус))}" if статус else "")
    if команда in (0x01, 0x02, 0x09):
        место = т
        for предел, подпись, ключ in ((16, "System ID", "system_id"), (9, "Пароль", "password"),
                                      (13, "Тип системы", "system_type")):
            значение, после = _c_строка(д, место, предел)
            у.поле(подпись, f"smpp.{ключ}", значение if ключ != "password" else "***", место, после - место,
                   родитель=узел)
            if ключ == "system_id":
                итог += " " + значение
            место = после
        _байты(д, место, 3)
        у.поле("Версия интерфейса", "smpp.interface_version", f"0x{д[место]:02x}", место, 1, д[место], родитель=узел)
        адрес, после = _c_строка(д, место + 3, 41)
        у.поле("Диапазон адресов", "smpp.address_range", адрес, место + 3, после - место - 3, родитель=узел)
        if после != к:
            raise _Чужое("bind: длина")
    elif команда in (0x80000001, 0x80000002, 0x80000009) and т < к:
        значение, после = _c_строка(д, т, 16)
        у.поле("System ID", "smpp.system_id", значение, т, после - т, родитель=узел)
        _smpp_tlv(у, д, после, к, узел)
    elif команда in (0x04, 0x05):
        итог += " " + _smpp_sm(у, д, т, к, узел)
    elif команда in (0x80000004, 0x80000005) and т < к:
        значение, после = _c_строка(д, т, 65)
        у.поле("Message ID", "smpp.message_id", значение, т, после - т, родитель=узел)
        if после != к:
            raise _Чужое("submit_sm_resp: длина")
        if значение:
            итог += " " + значение
    return итог


def _smpp_tlv(у, д, м, к, узел) -> None:
    место = м
    while место < к:
        тег, дл = б16(д, место), б16(д, место + 2)
        if место + 4 + дл > к:
            raise _Чужое("TLV SMPP за концом PDU")
        т = у.поле(f"Параметр 0x{тег:04x}, {дл} байт", "smpp.opt_param_tag", тег, место, 4 + дл, родитель=узел)
        у.поле("Длина", "smpp.opt_param_len", дл, место + 2, 2, родитель=т)
        место += 4 + дл


def _smpp_sm(у, д, т, к, узел) -> str:
    """submit_sm / deliver_sm (SMPP 3.4, 4.4.1 и 4.6.1)."""
    место = т
    служба, место_ = _c_строка(д, место, 6)
    у.поле("Тип службы", "smpp.service_type", служба, место, место_ - место, родитель=узел)
    место = место_
    адреса = []
    for что in ("source", "dest"):
        ton, npi = _байты(д, место, 2)
        у.поле("TON", f"smpp.{что}_addr_ton", ton, место, 1, родитель=узел)
        у.поле("NPI", f"smpp.{что}_addr_npi", npi, место + 1, 1, родитель=узел)
        адрес, после = _c_строка(д, место + 2, 21)
        у.поле("Отправитель" if что == "source" else "Получатель",
               "smpp.source_addr" if что == "source" else "smpp.destination_addr", адрес, место + 2,
               после - место - 2, родитель=узел)
        адреса.append(адрес)
        место = после
    esm, pid, приоритет = _байты(д, место, 3)
    у.поле("ESM class", "smpp.esm_class", f"0x{esm:02x}", место, 1, esm, родитель=узел)
    у.поле("Protocol ID", "smpp.protocol_id", pid, место + 1, 1, родитель=узел)
    у.поле("Приоритет", "smpp.priority_flag", приоритет, место + 2, 1, родитель=узел)
    место += 3
    for подпись, ключ in (("Время доставки", "schedule_delivery_time"), ("Срок годности", "validity_period")):
        время, после = _c_строка(д, место, 17)
        if len(время) not in (0, 16):
            raise _Чужое("время SMPP: не 0 и не 16 знаков")
        у.поле(подпись, f"smpp.{ключ}", время or "—", место, после - место, время, родитель=узел)
        место = после
    отчёт, замена, кодировка, по_умолчанию, дл = _байты(д, место, 5)
    у.поле("Отчёт о доставке", "smpp.registered_delivery", отчёт, место, 1, родитель=узел)
    у.поле("Заменять", "smpp.replace_if_present_flag", замена, место + 1, 1, родитель=узел)
    у.поле("Кодировка", "smpp.data_coding", f"0x{кодировка:02x}", место + 2, 1, кодировка, родитель=узел)
    у.поле("Шаблон", "smpp.sm_default_msg_id", по_умолчанию, место + 3, 1, родитель=узел)
    у.поле("Длина сообщения", "smpp.sm_length", дл, место + 4, 1, родитель=узел)
    место += 5
    сообщение = _байты(д, место, дл)
    тело = сообщение[1 + сообщение[0]:] if esm & 0x40 and сообщение else сообщение    # UDHI: пропустить UDH
    текст = _текст(тело, "utf-16-be") if кодировка == 8 else _текст(тело, "latin-1")
    у.поле("Короткое сообщение", "smpp.message_text", текст, место, дл, родитель=узел)
    _smpp_tlv(у, д, место + дл, к, узел)
    return f"{адреса[0]} → {адреса[1]}: {текст[:60]}"


# -- CoAP (RFC 7252) --------------------------------------------------------------------------------------------

COAP_ТИПЫ = {0: "CON", 1: "NON", 2: "ACK", 3: "RST"}
COAP_КОДЫ = {(0, 0): "Empty", (0, 1): "GET", (0, 2): "POST", (0, 3): "PUT", (0, 4): "DELETE", (0, 5): "FETCH",
             (0, 6): "PATCH", (0, 7): "iPATCH", (2, 1): "Created", (2, 2): "Deleted", (2, 3): "Valid",
             (2, 4): "Changed", (2, 5): "Content", (2, 31): "Continue", (4, 0): "Bad Request",
             (4, 1): "Unauthorized", (4, 2): "Bad Option", (4, 3): "Forbidden", (4, 4): "Not Found",
             (4, 5): "Method Not Allowed", (4, 6): "Not Acceptable", (4, 8): "Request Entity Incomplete",
             (4, 9): "Conflict", (4, 12): "Precondition Failed", (4, 13): "Request Entity Too Large",
             (4, 15): "Unsupported Content-Format", (4, 22): "Unprocessable Entity",
             (5, 0): "Internal Server Error", (5, 1): "Not Implemented", (5, 2): "Bad Gateway",
             (5, 3): "Service Unavailable", (5, 4): "Gateway Timeout", (5, 5): "Proxying Not Supported"}
#: Номер → (имя, ключ, формат, наименьшая и наибольшая длина, повторяемая) — RFC 7252, 5.10; 7641; 7959.
COAP_ОПЦИИ = {1: ("If-Match", "if_match", "o", 0, 8, True), 3: ("Uri-Host", "uri_host", "s", 1, 255, False),
              4: ("ETag", "etag", "o", 1, 8, True), 5: ("If-None-Match", "if_none_match", "e", 0, 0, False),
              6: ("Observe", "observe", "u", 0, 3, False), 7: ("Uri-Port", "uri_port", "u", 0, 2, False),
              8: ("Location-Path", "location_path", "s", 0, 255, True),
              11: ("Uri-Path", "uri_path", "s", 0, 255, True),
              12: ("Content-Format", "ctype", "u", 0, 2, False), 14: ("Max-Age", "max_age", "u", 0, 4, False),
              15: ("Uri-Query", "uri_query", "s", 0, 255, True), 17: ("Accept", "accept", "u", 0, 2, False),
              20: ("Location-Query", "location_query", "s", 0, 255, True),
              23: ("Block2", "block2", "u", 0, 3, False), 27: ("Block1", "block1", "u", 0, 3, False),
              28: ("Size2", "size2", "u", 0, 4, False), 35: ("Proxy-Uri", "proxy_uri", "s", 1, 1034, False),
              39: ("Proxy-Scheme", "proxy_scheme", "s", 1, 255, False), 60: ("Size1", "size1", "u", 0, 4, False)}
COAP_ФОРМАТЫ = {0: "text/plain; charset=utf-8", 40: "application/link-format", 41: "application/xml",
                42: "application/octet-stream", 47: "application/exi", 50: "application/json", 60: "application/cbor"}


@_откат
def coap(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    б0, код = д[м], д[м + 1]
    версия, тип, tkl = б0 >> 6, (б0 >> 4) & 3, б0 & 15
    класс, деталь = код >> 5, код & 31
    имя_кода = COAP_КОДЫ.get((класс, деталь))
    if версия != 1 or tkl > 8 or имя_кода is None:
        return False
    пустое = код == 0
    if пустое and (tkl or конец - м != 4):
        return False                                   # Empty: только 4 байта заголовка (RFC 7252, 4.1)
    if (тип == 3 and not пустое) or (тип == 1 and пустое) or (тип == 2 and класс == 0 and not пустое):
        return False                                   # RST — только Empty; NON не Empty; ACK не несёт запрос
    mid = б16(д, м + 2)
    token = _байты(д, м + 4, tkl)
    у = р.уровень("CoAP", "Constrained Application Protocol", м)
    у.поле("Версия", "coap.version", 1, м, 1)
    у.поле("Тип", "coap.type", COAP_ТИПЫ[тип], м, 1, тип)
    у.поле("Длина токена", "coap.token_len", tkl, м, 1)
    у.поле("Код", "coap.code", f"{класс}.{деталь:02d} {имя_кода}", м + 1, 1, код)
    у.поле("Message ID", "coap.mid", mid, м + 2, 2)
    if tkl:
        у.поле("Токен", "coap.token", token.hex(), м + 4, tkl)
    место = м + 4 + tkl
    номер = 0
    были = set()
    путь, узел_ = [], ""
    формат = None
    while место < конец and д[место] != 0xFF:
        б = д[место]
        дельта, дл = б >> 4, б & 15
        if дельта == 15 or дл == 15:
            raise _Чужое("CoAP: 15 в дельте или длине")
        п = место + 1
        if дельта == 13:
            дельта = 13 + _ч(д, п, 1)
            п += 1
        elif дельта == 14:
            дельта = 269 + _ч(д, п, 2)
            п += 2
        if дл == 13:
            дл = 13 + _ч(д, п, 1)
            п += 1
        elif дл == 14:
            дл = 269 + _ч(д, п, 2)
            п += 2
        номер += дельта
        значение = _байты(д, п, дл)
        сведения = COAP_ОПЦИИ.get(номер)
        if сведения is None:
            raise _Чужое("CoAP: неизвестная опция")
        имя, ключ, формат_оп, наим, наиб, повтор = сведения
        if not наим <= дл <= наиб or (номер in были and not повтор):
            raise _Чужое("CoAP: длина или повтор опции")
        были.add(номер)
        if формат_оп == "s":
            показ = значение.decode("utf-8")
        elif формат_оп == "u":
            показ = int.from_bytes(значение, "big")
            if номер in (12, 17):
                показ = f"{COAP_ФОРМАТЫ.get(показ, показ)}"
        else:
            показ = значение.hex() or "(пусто)"
        о = у.поле(f"{имя}: {показ}", f"coap.opt.{ключ}", показ, место, п + дл - место)
        у.поле("Дельта", "coap.opt.delta", дельта, место, 1, родитель=о)
        у.поле("Длина", "coap.opt.length", дл, место, 1, родитель=о)
        if номер == 11:
            путь.append(показ)
        elif номер == 3:
            узел_ = показ
        elif номер == 12:
            формат = int.from_bytes(значение, "big")
        место = п + дл
    if место < конец:
        if место + 1 == конец:
            raise _Чужое("CoAP: маркер 0xFF без данных")
        у.поле("Маркер данных", "coap.payload_marker", "0xff", место, 1)
        данные_ = д[место + 1:конец]
        показ = _текст(данные_) if формат in (0, 40, 41, 50) else f"{len(данные_)} байт: {печатное(данные_, 40)}"
        у.поле("Данные", "coap.payload", показ, место + 1, конец - место - 1)
        у.поле("Длина данных", "coap.payload_length", конец - место - 1, место + 1, 0)
    у.длина = конец - м
    итог = f"{COAP_ТИПЫ[тип]} {имя_кода} MID {mid}"
    if путь or узел_:
        итог += f" {узел_}/" + "/".join(путь)
    у.итог = итог
    р.п.инфо = "CoAP " + итог
    return True


