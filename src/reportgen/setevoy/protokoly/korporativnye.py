def _байты(д: bytes, м: int, n: int) -> bytes:
    if n < 0 or м + n > len(д):
        raise Мало()
    return д[м:м + n]


def _сишная(д: bytes, м: int, предел: int = 1 << 20) -> tuple:
    """Строка до нуля: (байты, место за нулём). Нет нуля в пределе — чужое."""
    ноль = д.find(b"\0", м, м + предел)
    if ноль < 0:
        if len(д) - м < предел:
            raise Мало()
        raise _Чужое("строка без завершающего нуля")
    return д[м:ноль], ноль + 1


def _текст(данные_: bytes, кодировка: str = "utf-8") -> str:
    return данные_.decode(кодировка, "replace")


def _снимок(р: Разбор):
    return (len(р.п.уровни), р.п.инфо, р.п.нагрузка, р.п.нагрузка_смещение, len(р.п.ошибки))


def _вернуть(р: Разбор, снимок) -> None:
    уровней, инфо, нагрузка, смещение, ошибок = снимок
    del р.п.уровни[уровней:]
    del р.п.ошибки[ошибок:]
    р.п.инфо, р.п.нагрузка, р.п.нагрузка_смещение = инфо, нагрузка, смещение


def _попробовать(разборщик, р: Разбор, *арг, **кл) -> bool:
    """Вызвать разборщик; не его данные или обрыв — всё, что он оставил, убирается."""
    снимок = _снимок(р)
    try:
        if разборщик(р, *арг, **кл):
            return True
    except _ОШИБКИ:
        pass
    _вернуть(р, снимок)
    return False


def _откат(разборщик):
    """Разборщик (р, м, конец) → bool: False или исключение — уровни откатываются."""
    @functools.wraps(разборщик)
    def обёртка(р, м, конец, *арг, **кл):
        return _попробовать(разборщик, р, м, конец, *арг, **кл)
    return обёртка


class _Уровни:
    """Один уровень на протокол в пределах сегмента (несколько PDU — узлы одного уровня)."""

    def __init__(self, р: Разбор):
        self.р = р
        self.есть = {}

    def __call__(self, протокол: str, полное: str, м: int):
        у = self.живые().get(протокол)
        if у is None:
            у = self.есть[протокол] = self.р.уровень(протокол, полное, м)
            у._итоги = []
        return у

    def живые(self):
        """Уровни, которые не убраны откатом вложенного разборщика."""
        return {имя: у for имя, у in self.есть.items() if any(у is в for в in self.р.п.уровни)}

    def закрыть(self, конец: int) -> None:
        for у in self.живые().values():
            у.длина = max(у.длина, конец - у.смещение)
            у.итог = _свести(у._итоги)


def _свести(итоги) -> str:
    текст = "; ".join(и for и in итоги if и)
    return текст if len(текст) <= 160 else текст[:159] + "…"


def _к_серверу(р: Разбор, порт: int) -> bool:
    """Направление по порту службы; порт не наш («разбирать как») — служба на меньшем порту."""
    от, к = р.п.порт_от, р.п.порт_к
    if к == порт and от != порт:
        return True
    if от == порт and к != порт:
        return False
    return (к or 0) < (от or 0)


def _нарезать(д: bytes, м: int, длина_pdu, заголовок: int):
    """PDU подряд до конца сегмента: ([(начало, конец)], хвост).

    ``длина_pdu(место)`` — полная длина PDU по его заголовку (бросает _Чужое, если
    заголовок не этого протокола). Последний PDU может выходить за сегмент —
    его продолжение в следующем; ``хвост`` — начало неполного заголовка в самом
    конце сегмента (или None). Решать, верить ли неполному, — вызывающему.
    """
    куски = []
    место = м
    while место < len(д):
        if место + заголовок > len(д):
            if not куски:
                raise Мало()
            return куски, место
        n = длина_pdu(место)
        if n < заголовок:
            raise _Чужое("длина PDU меньше заголовка")
        куски.append((место, место + n))
        if место + n > len(д):
            break
        место += n
    if not куски:
        raise Мало()
    return куски, None


def _полных(куски, конец: int) -> int:
    return sum(1 for _н, к in куски if к <= конец)


def _оборван(куски, хвост, конец: int) -> bool:
    return хвост is not None or куски[-1][1] > конец


def _хвост(у, м: int, конец: int, ключ: str) -> None:
    у.поле("Начало следующего PDU (продолжение в следующем сегменте)", ключ, f"{конец - м} байт", м, конец - м)


def _pad4(n: int) -> int:
    return (n + 3) & ~3


