def _печатный(данные_: bytes) -> bool:
    try:
        текст = данные_.decode("utf-8")
    except UnicodeDecodeError:
        # Обрыв посреди многобайтного символа в конце — не порча.
        try:
            текст = данные_[:-3].decode("utf-8") if len(данные_) > 3 else ""
        except UnicodeDecodeError:
            return False
    return all(с.isprintable() or с in "\t\r\n" for с in текст)


def _mysql_приветствие_ли(д, т, к) -> bool:
    if д[т] != 0x0A:
        return False
    версия, после = _сишная(д, т + 1, 64)
    if not версия or not all(0x20 <= б < 0x7F for б in версия):
        return False
    return после + 4 + 8 + 1 <= к and д[после + 12] == 0


def _mysql_длина(д, н) -> int:
    """Длина пакета с заголовком; пустое тело отвергает нарезка (заголовок с байтом команды — 5)."""
    return 4 + л24(д, н)


@_откат
def mysql(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    к_серверу = _к_серверу(р, 3306)
    куски, хвост = _нарезать(д, м, lambda н: _mysql_длина(д, н), 5)
    if not _полных(куски, конец):
        # Один пакет начат и не уместился: верим только приветствию сервера или тексту запроса.
        н = куски[0][0]
        т = н + 4
        if к_серверу:
            if not (д[н + 3] == 0 and д[т] in (0x03, 0x16) and конец - т >= 17 and _печатный(д[т + 1:конец])):
                return False
        elif not (д[н + 3] == 0 and _mysql_приветствие_ли(д, т, конец)):
            return False
    у = р.уровень("MySQL", "MySQL Protocol", м)
    итоги = []
    for н, к in куски:
        итоги.append(_mysql_пакет(у, д, н, min(к, конец), к_серверу, к > конец))
    if хвост is not None:
        _хвост(у, хвост, конец, "mysql.continuation_data")
    у.длина = конец - м
    у.итог = _свести(итоги)
    р.п.инфо = "MySQL " + у.итог
    if _оборван(куски, хвост, конец):
        р.ошибка("MySQL: пакет продолжается в следующем сегменте")
    return True


def _lenenc(д, м) -> tuple:
    п = д[м]
    if п < 0xFB:
        return п, м + 1
    n = {0xFC: 2, 0xFD: 3, 0xFE: 8}.get(п)
    if n is None:
        raise _Чужое("целое переменной длины MySQL")
    return _ч(д, м + 1, n, "little"), м + 1 + n


def _mysql_пакет(у, д, н, к, к_серверу, оборван) -> str:
    дл, номер = л24(д, н), д[н + 3]
    т = н + 4
    узел = у.поле(f"Пакет {номер}, {дл} байт", "mysql.packet_length", дл, н, к - н)
    у.поле("Длина", "mysql.packet_length", дл, н, 3, родитель=узел)
    у.поле("Номер пакета", "mysql.packet_number", номер, н + 3, 1, родитель=узел)
    п = д[т]
    if к_серверу:
        if номер == 0:
            if п not in MYSQL_КОМАНДЫ:
                raise _Чужое("неизвестная команда MySQL")
            у.поле("Команда", "mysql.command", MYSQL_КОМАНДЫ[п], т, 1, п, родитель=узел)
            узел.текст = MYSQL_КОМАНДЫ[п]
            if п in MYSQL_ТЕКСТОВЫЕ:
                текст = _текст(д[т + 1:к])
                у.поле("Запрос" if п != 0x02 else "База", MYSQL_ТЕКСТОВЫЕ[п], текст, т + 1, к - т - 1, родитель=узел)
                return f"{MYSQL_КОМАНДЫ[п]} {текст[:80]}" + ("…" if оборван else "")
            return MYSQL_КОМАНДЫ[п]
        if номер == 1 and дл >= 32 and not any(д[т + 9:т + 32]):
            возм = л32(д, т)
            у.поле("Возможности клиента", "mysql.caps.client", f"0x{возм:08x}", т, 4, возм, родитель=узел)
            у.поле("Кодировка", "mysql.charset", д[т + 8], т + 8, 1, родитель=узел)
            if дл == 32:
                return "запрос TLS (SSLRequest)"
            имя, после = _сишная(д, т + 32, 256)
            у.поле("Пользователь", "mysql.user", _текст(имя), т + 32, после - т - 32, родитель=узел)
            return f"вход пользователя {_текст(имя)}"
        у.поле("Данные", "mysql.payload", f"{к - т} байт", т, к - т, родитель=узел)
        return f"пакет {номер}"
    if номер == 0 and п == 0x0A and _mysql_приветствие_ли(д, т, к):
        версия, после = _сишная(д, т + 1, 64)
        у.поле("Версия протокола", "mysql.protocol", 10, т, 1, родитель=узел)
        у.поле("Версия сервера", "mysql.version", _текст(версия), т + 1, после - т - 1, родитель=узел)
        у.поле("Номер соединения", "mysql.thread_id", л32(д, после), после, 4, родитель=узел)
        возм = л16(д, после + 13)
        у.поле("Возможности сервера (младшие)", "mysql.caps.server", f"0x{возм:04x}", после + 13, 2, возм,
               родитель=узел)
        if после + 31 <= к:
            if any(д[после + 21:после + 31]):
                raise _Чужое("резерв приветствия MySQL не нули")
            у.поле("Кодировка", "mysql.charset", д[после + 15], после + 15, 1, родитель=узел)
            у.поле("Состояние", "mysql.server_status", f"0x{л16(д, после + 16):04x}", после + 16, 2,
                   л16(д, после + 16), родитель=узел)
        узел.текст = "Приветствие сервера"
        return f"приветствие сервера {_текст(версия)}"
    if п == 0xFF and дл >= 3:
        код = л16(д, т + 1)
        у.поле("Код ошибки", "mysql.error_code", код, т + 1, 2, родитель=узел)
        место = т + 3
        if д[место:место + 1] == b"#":
            у.поле("SQLSTATE", "mysql.sqlstate", _текст(д[место + 1:место + 6], "ascii"), место, 6, родитель=узел)
            место += 6
        сообщение = _текст(д[место:к])
        у.поле("Сообщение", "mysql.error.message", сообщение, место, к - место, родитель=узел)
        узел.текст = "ERR"
        return f"ошибка {код}: {сообщение[:60]}"
    if п == 0x00 and дл >= 7:
        строк, место = _lenenc(д, т + 1)
        у.поле("Затронуто строк", "mysql.affected_rows", строк, т + 1, место - т - 1, родитель=узел)
        узел.текст = "OK"
        return f"OK, строк {строк}"
    if п == 0xFE and дл < 9:
        узел.текст = "EOF"
        return "EOF"
    у.поле("Данные результата", "mysql.payload", f"{к - т} байт", т, к - т, родитель=узел)
    return f"пакет {номер}"


