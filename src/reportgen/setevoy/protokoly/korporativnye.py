NBDS_ТИПЫ = {0x10: "прямая уникальная", 0x11: "прямая групповая", 0x12: "широковещательная",
             0x13: "ошибка", 0x14: "запрос", 0x15: "положительный ответ", 0x16: "отрицательный ответ"}
NBDS_ОШИБКИ = {0x82: "нет имени получателя", 0x83: "неверное имя источника",
               0x84: "неверное имя получателя"}


@_откат
def nbds(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    тип, флаги = д[м], д[м + 1]
    if тип not in NBDS_ТИПЫ or флаги & 0xF0:
        return False
    _байты(д, м, 10)
    у = р.уровень("NBDS", "NetBIOS Datagram Service", м)
    у.поле("Тип сообщения", "nbdgm.type", NBDS_ТИПЫ[тип], м, 1, тип)
    п = у.поле("Флаги", "nbdgm.flags", f"0x{флаги:02x}", м + 1, 1, флаги)
    у.поле("Тип узла (SNT)", "nbdgm.node_type", "BPMN"[(флаги >> 2) & 3] + "-узел"
           if (флаги >> 2) & 3 < 3 else "NBDD", м + 1, 1, (флаги >> 2) & 3, родитель=п)
    у.поле("Первый фрагмент", "nbdgm.first", флаги >> 1 & 1, м + 1, 1, родитель=п)
    у.поле("Есть ещё фрагменты", "nbdgm.next", флаги & 1, м + 1, 1, родитель=п)
    у.поле("Идентификатор", "nbdgm.dgram_id", f"0x{б16(д, м + 2):04x}", м + 2, 2, б16(д, м + 2))
    у.поле("IP источника", "nbdgm.src.ip", ip4(д, м + 4), м + 4, 4)
    у.поле("Порт источника", "nbdgm.src.port", б16(д, м + 8), м + 8, 2)
    итог = NBDS_ТИПЫ[тип]
    if тип in (0x10, 0x11, 0x12):
        длина, смещение = б16(д, м + 10), б16(д, м + 12)
        if м + 14 + длина != конец:
            return False
        у.поле("Длина датаграммы", "nbdgm.dgram_len", длина, м + 10, 2)
        у.поле("Смещение пакета", "nbdgm.pkt_offset", смещение, м + 12, 2)
        от, после = _nb_имя(д, м + 14, м, сжатие=False)[0::2]
        у.поле("Имя источника", "nbdgm.source_name", от, м + 14, после - м - 14)
        к, после2 = _nb_имя(д, после, м, сжатие=False)[0::2]
        у.поле("Имя получателя", "nbdgm.destination_name", к, после, после2 - после)
        у.длина = после2 - м
        итог += f" {от} → {к}"
        у.итог = итог
        р.п.инфо = "NBDS " + итог
        if после2 < конец:
            if д[после2:после2 + 4] == b"\xffSMB":
                уровни = _Уровни(р)
                if not _попробовать(_smb, р, уровни, после2, конец):
                    данные(р, после2, "данные NBDS", конец)
            else:
                данные(р, после2, "данные NBDS", конец)
        return True
    if тип == 0x13:
        if конец - м != 11 or д[м + 10] not in NBDS_ОШИБКИ:
            return False
        у.поле("Код ошибки", "nbdgm.error_code", NBDS_ОШИБКИ[д[м + 10]], м + 10, 1, д[м + 10])
        итог += ": " + NBDS_ОШИБКИ[д[м + 10]]
        у.длина = 11
    else:
        к, после = _nb_имя(д, м + 10, м, сжатие=False)[0::2]
        if после != конец:
            return False
        у.поле("Имя получателя", "nbdgm.destination_name", к, м + 10, после - м - 10)
        итог += " " + к
        у.длина = после - м
    у.итог = итог
    р.п.инфо = "NBDS " + итог
    return True


# -- NBSS (RFC 1002, 4.3) и Direct TCP ([MS-SMB2] 2.1) ------------------------------------------------

NBSS_ТИПЫ = {0x00: "сообщение сеанса", 0x81: "запрос сеанса", 0x82: "положительный ответ",
             0x83: "отрицательный ответ", 0x84: "перенаправление", 0x85: "поддержание (keep-alive)"}
NBSS_ОШИБКИ = {0x80: "не слушает вызываемое имя", 0x81: "не слушает вызывающее имя",
               0x82: "вызываемого имени нет", 0x83: "не хватает ресурсов", 0x8F: "неуказанная ошибка"}
SMB_ПОДПИСИ = (b"\xffSMB", b"\xfeSMB", b"\xfdSMB")


def _nbss_длина(д: bytes, место: int, прямой: bool) -> int:
    if прямой:
        дл = б24(д, место + 1)
        if д[место] != 0 or дл < 35:                   # меньше заголовка SMB1 с WordCount и ByteCount
            raise _Чужое("Direct TCP: первый байт не ноль или SMB короче 35 байт")
        return 4 + дл
    тип, флаги = д[место], д[место + 1]
    if тип not in NBSS_ТИПЫ or флаги & 0xFE:
        raise _Чужое("тип или флаги NBSS")
    дл = ((флаги & 1) << 16) | б16(д, место + 2)
    нужно = {0x82: дл == 0, 0x85: дл == 0, 0x83: дл == 1, 0x84: дл == 6, 0x81: дл >= 68}.get(тип, True)
    if not нужно:
        raise _Чужое("длина служебного пакета NBSS")
    return 4 + дл


def _nbss(р: Разбор, м: int, конец: int, *, прямой: bool) -> bool:
    д = р.д[:конец]
    куски, хвост = _нарезать(д, м, lambda место: _nbss_длина(д, место, прямой), 4)
    for н, к in куски:
        smb = д[н + 4:н + 8] in SMB_ПОДПИСИ
        if прямой and н + 8 <= конец and not smb:
            return False                               # по Direct TCP ходит только SMB
    н, к = куски[0]
    if к > конец and not (д[н] == 0 and д[н + 4:н + 8] in SMB_ПОДПИСИ):
        return False                                   # первый PDU не уместился — верим только подписи SMB
    у = р.уровень("NBSS", "NetBIOS Session Service" if not прямой else "SMB Direct TCP ([MS-SMB2] 2.1)", м)
    уровни = _Уровни(р)
    итоги, smb_итоги = [], []
    for н, к in куски:
        тип = д[н]
        дл = к - н - 4
        узел = у.поле(f"{NBSS_ТИПЫ[тип] if not прямой else 'Сообщение SMB'}, {дл} байт", "nbss.type",
                      NBSS_ТИПЫ.get(тип, str(тип)), н, min(к, конец) - н, тип)
        if прямой:
            у.поле("Ноль", "nbss.type", 0, н, 1, родитель=узел)
            у.поле("Длина (24 бита)", "nbss.length", дл, н + 1, 3, родитель=узел)
        else:
            у.поле("Флаги", "nbss.flags", f"0x{д[н + 1]:02x}", н + 1, 1, д[н + 1], родитель=узел)
            у.поле("Длина", "nbss.length", дл, н + 1, 3, родитель=узел)
        тело = н + 4
        if тип != 0 and к > конец:
            итоги.append(NBSS_ТИПЫ[тип] + " (продолжение в следующем сегменте)")
        elif тип == 0x81:
            вызываемое, после = _nb_имя(д, тело, тело, сжатие=False)[0::2]
            вызывающее, после2 = _nb_имя(д, после, тело, сжатие=False)[0::2]
            if после2 != к:
                return False
            у.поле("Вызываемое имя", "nbss.called_name", вызываемое, тело, после - тело, родитель=узел)
            у.поле("Вызывающее имя", "nbss.calling_name", вызывающее, после, после2 - после, родитель=узел)
            итоги.append(f"запрос сеанса {вызывающее} → {вызываемое}")
        elif тип == 0x83:
            код = д[тело]
            if код not in NBSS_ОШИБКИ:
                return False
            у.поле("Код ошибки", "nbss.error_code", NBSS_ОШИБКИ[код], тело, 1, код, родитель=узел)
            итоги.append("отказ: " + NBSS_ОШИБКИ[код])
        elif тип == 0x84:
            у.поле("Новый адрес", "nbss.retarget_ip_address", ip4(д, тело), тело, 4, родитель=узел)
            у.поле("Новый порт", "nbss.retarget_port", б16(д, тело + 4), тело + 4, 2, родитель=узел)
            итоги.append(f"перенаправление на {ip4(д, тело)}:{б16(д, тело + 4)}")
        elif тип == 0:
            итоги.append(f"сообщение сеанса, {дл} байт")
            if дл and тело < конец:
                if not _попробовать(_smb, р, уровни, тело, min(к, конец), полон=к <= конец):
                    данные(р, тело, "сообщение сеанса NetBIOS", min(к, конец))
        else:
            итоги.append(NBSS_ТИПЫ[тип])
    if хвост is not None:
        _хвост(у, хвост, конец, "nbss.continuation_data")
    у.длина = min(куски[-1][1], конец) - м
    у.итог = _свести(итоги)
    уровни.закрыть(min(куски[-1][1], конец))
    живые = уровни.живые()
    for имя in ("SMB2", "SMB"):
        if имя in живые:
            smb_итоги.append(живые[имя].итог)
    р.п.инфо = (("SMB2 " if "SMB2" in живые else "SMB ") + _свести(smb_итоги)) if smb_итоги \
        else "NBSS " + у.итог
    if _оборван(куски, хвост, конец):
        р.ошибка("NBSS: последний PDU продолжается в следующем сегменте")
    return True


@_откат
def nbss(р: Разбор, м: int, конец: int) -> bool:
    return _nbss(р, м, конец, прямой=False)


@_откат
def smb_прямой(р: Разбор, м: int, конец: int) -> bool:
    return _nbss(р, м, конец, прямой=True)


@_откат
def smb_эвристика(р: Разбор, м: int, конец: int) -> bool:
    """SMB без порта: Direct TCP или NBSS с подписью SMB сразу за 4 байтами заголовка."""
    д = р.д
    if конец - м < 4 + 32 or д[м + 4:м + 8] not in SMB_ПОДПИСИ:
        return False
    return _попробовать(_nbss, р, м, конец, прямой=False) or _попробовать(_nbss, р, м, конец, прямой=True)


# -- SMB1 ([MS-CIFS] 2.2.3.1, 2.2.4) --------------------------------------------------------------------

SMB1_КОМАНДЫ = {0x04: "Close", 0x06: "Delete", 0x24: "Locking AndX", 0x25: "Trans", 0x2B: "Echo",
                0x2D: "Open AndX", 0x2E: "Read AndX", 0x2F: "Write AndX", 0x32: "Trans2",
                0x71: "Tree Disconnect", 0x72: "Negotiate Protocol", 0x73: "Session Setup AndX",
                0x74: "Logoff AndX", 0x75: "Tree Connect AndX", 0xA0: "NT Trans", 0xA2: "NT Create AndX",
                0xA4: "NT Cancel"}


def _smb(р: Разбор, уровни: _Уровни, м: int, конец: int, *, полон: bool = True) -> bool:
    подпись = р.д[м:м + 4]
    if подпись == b"\xffSMB":
        return _smb1(р, уровни, м, конец)
    if подпись == b"\xfeSMB":
        return _smb2(р, уровни, м, конец)
    if подпись == b"\xfdSMB":
        return _smb2_transform(р, уровни, м, конец, полон)
    return False


def _smb_строка(д: bytes, м: int, юникод: bool, начало: int) -> tuple:
    """SMB_STRING: в Юникоде выровнена на 2 от начала заголовка SMB, завершается нулём."""
    if юникод:
        if (м - начало) % 2:
            м += 1
        i = м
        while True:
            if _байты(д, i, 2) == b"\0\0":
                return _текст(д[м:i], "utf-16-le"), i + 2
            i += 2
    сырое, после = _сишная(д, м)
    return _текст(сырое, "latin-1"), после


def _smb1(р: Разбор, уровни: _Уровни, h: int, конец: int) -> bool:
    д = р.д[:конец]
    _байты(д, h, 33)
    команда, статус, флаги, флаги2 = д[h + 4], л32(д, h + 5), д[h + 9], л16(д, h + 10)
    ответ = флаги >> 7
    у = уровни("SMB", "Server Message Block (SMB1, [MS-CIFS])", h)
    имя = SMB1_КОМАНДЫ.get(команда, f"0x{команда:02x}")
    узел = у.поле(f"{имя} {'ответ' if ответ else 'запрос'}", "smb.cmd", имя, h, 32, команда)
    у.поле("Подпись", "smb.server_component", "\\xffSMB", h, 4, родитель=узел)
    у.поле("Команда", "smb.cmd", имя, h + 4, 1, команда, родитель=узел)
    у.поле("Статус", "smb.nt_status", _статус(статус), h + 5, 4, статус, родитель=узел)
    ф = у.поле("Флаги", "smb.flags", f"0x{флаги:02x}", h + 9, 1, флаги, родитель=узел)
    у.поле("Ответ", "smb.flags.response", ответ, h + 9, 1, родитель=ф)
    у.поле("Флаги 2", "smb.flags2", f"0x{флаги2:04x}", h + 10, 2, флаги2, родитель=узел)
    у.поле("TID", "smb.tid", л16(д, h + 24), h + 24, 2, родитель=узел)
    у.поле("PID", "smb.pid", (л16(д, h + 12) << 16) | л16(д, h + 26), h + 26, 2, родитель=узел)
    у.поле("UID", "smb.uid", л16(д, h + 28), h + 28, 2, родитель=узел)
    у.поле("MID", "smb.mid", л16(д, h + 30), h + 30, 2, родитель=узел)
    wc = д[h + 32]
    у.поле("Число слов", "smb.wct", wc, h + 32, 1, родитель=узел)
    слова = h + 33
    итог = f"{имя} {'ответ' if ответ else 'запрос'}"
    if статус:
        итог += f", {_статус(статус)}"
    if слова + 2 * wc + 2 <= конец:
        bc = л16(д, слова + 2 * wc)
        байты = слова + 2 * wc + 2
        у.поле("Число байт", "smb.bcc", bc, байты - 2, 2, родитель=узел, плохо=байты + bc > конец)
        if байты + bc > конец:
            р.ошибка("SMB: ByteCount выходит за конец данных")
        юникод = bool(флаги2 & 0x8000)
        if not ответ and команда == 0x72:
            место, диалекты = байты, []
            while место < min(байты + bc, конец) and д[место] == 0x02:
                сырое, после = _сишная(д, место + 1)
                диалекты.append(_текст(сырое, "latin-1"))
                у.поле(f"Диалект {диалекты[-1]}", "smb.dialect", диалекты[-1], место, после - место, родитель=узел)
                место = после
            итог += f" ({len(диалекты)} диалектов)"
        elif not ответ and команда == 0x75 and wc == 4:
            пароль = л16(д, слова + 6)
            путь, после = _smb_строка(д, байты + пароль, юникод, h)
            у.поле("Путь", "smb.path", путь, байты + пароль, после - байты - пароль, родитель=узел)
            итог += " " + путь
        elif not ответ and команда == 0xA2 and wc == 24:
            дл_имени = л16(д, слова + 5)
            место = байты + (1 if юникод and (байты - h) % 2 else 0)
            сырое = _байты(д, место, дл_имени)
            имя_ф = _текст(сырое, "utf-16-le" if юникод else "latin-1").rstrip("\0")
            у.поле("Имя файла", "smb.file", имя_ф, место, дл_имени, родитель=узел)
            итог += " " + имя_ф
        elif not ответ and команда == 0x25 and wc >= 14:
            имя_т, после = _smb_строка(д, байты, юникод, h)
            у.поле("Имя транзакции", "smb.trans_name", имя_т, байты, после - байты, родитель=узел)
            итог += " " + имя_т
    у._итоги.append(итог)
    р.п.инфо = "SMB " + итог
    return True


# -- SMB2/3 ([MS-SMB2] 2.2) ---------------------------------------------------------------------------

SMB2_КОМАНДЫ = {0x00: "NEGOTIATE", 0x01: "SESSION_SETUP", 0x02: "LOGOFF", 0x03: "TREE_CONNECT",
                0x04: "TREE_DISCONNECT", 0x05: "CREATE", 0x06: "CLOSE", 0x07: "FLUSH", 0x08: "READ",
                0x09: "WRITE", 0x0A: "LOCK", 0x0B: "IOCTL", 0x0C: "CANCEL", 0x0D: "ECHO",
                0x0E: "QUERY_DIRECTORY", 0x0F: "CHANGE_NOTIFY", 0x10: "QUERY_INFO", 0x11: "SET_INFO",
                0x12: "OPLOCK_BREAK"}
#: StructureSize тела ([MS-SMB2] 2.2.3–2.2.26): команда → (запрос, ответ).
SMB2_РАЗМЕРЫ = {0x00: ({36}, {65}), 0x01: ({25}, {9}), 0x02: ({4}, {4}), 0x03: ({9}, {16}),
                0x04: ({4}, {4}), 0x05: ({57}, {89}), 0x06: ({24}, {60}), 0x07: ({24}, {4}),
                0x08: ({49}, {17}), 0x09: ({49}, {17}), 0x0A: ({48}, {4}), 0x0B: ({57}, {49}),
                0x0C: ({4}, set()), 0x0D: ({4}, {4}), 0x0E: ({33}, {9}), 0x0F: ({32}, {9}),
                0x10: ({41}, {9}), 0x11: ({33}, {2}), 0x12: ({24, 36}, {24, 44, 36})}
SMB2_ФЛАГИ = ((0x00000001, "SERVER_TO_REDIR"), (0x00000002, "ASYNC_COMMAND"),
              (0x00000004, "RELATED_OPERATIONS"), (0x00000008, "SIGNED"),
              (0x10000000, "DFS_OPERATIONS"), (0x20000000, "REPLAY_OPERATION"))
SMB2_ФЛАГИ_ВСЕ = 0x3000007F
SMB2_ДИАЛЕКТЫ = {0x0202: "2.0.2", 0x0210: "2.1", 0x0300: "3.0", 0x0302: "3.0.2", 0x0311: "3.1.1",
                 0x02FF: "2.???"}
SMB2_РЕСУРСЫ = {1: "диск", 2: "именованный канал", 3: "принтер"}
SMB2_РАСПОРЯЖЕНИЯ = {0: "SUPERSEDE", 1: "OPEN", 2: "CREATE", 3: "OPEN_IF", 4: "OVERWRITE",
                     5: "OVERWRITE_IF"}
SMB2_ДЕЙСТВИЯ = {0: "SUPERSEDED", 1: "OPENED", 2: "CREATED", 3: "OVERWRITTEN"}


def _smb2(р: Разбор, уровни: _Уровни, м: int, конец: int) -> bool:
    д = р.д[:конец]
    h = м
    сообщений = 0
    while True:
        _байты(д, h, 64)
        if д[h:h + 4] != b"\xfeSMB" or л16(д, h + 4) != 64:
            if not сообщений:
                return False
            р.ошибка("SMB2: следующий в цепочке заголовок неверен")
            break
        команда, флаги, следующий = л16(д, h + 12), л32(д, h + 16), л32(д, h + 20)
        if команда not in SMB2_КОМАНДЫ or флаги & ~SMB2_ФЛАГИ_ВСЕ:
            if not сообщений:
                return False
            р.ошибка("SMB2: следующий в цепочке заголовок неверен")
            break
        у = уровни("SMB2", "SMB2/3 ([MS-SMB2])", м)
        if следующий and (следующий % 8 or следующий < 64):
            р.ошибка("SMB2: NextCommand не кратен 8 или меньше заголовка")
            _smb2_сообщение(р, у, д, h, конец, плохой_следующий=True)
            сообщений += 1
            break
        _smb2_сообщение(р, у, д, h, min(h + следующий, конец) if следующий else конец)
        сообщений += 1
        if not следующий or h + следующий >= конец or сообщений >= 64:
            break
        h += следующий
    р.п.инфо = "SMB2 " + _свести(у._итоги)
    return True


def _smb2_сообщение(р, у, д, h, конец, *, плохой_следующий=False) -> None:
    статус_или_канал = л32(д, h + 8)
    команда, кредиты, флаги, следующий = л16(д, h + 12), л16(д, h + 14), л32(д, h + 16), л32(д, h + 20)
    mid = л64(д, h + 24)
    ответ = флаги & 1
    имя = SMB2_КОМАНДЫ[команда]
    узел = у.поле(f"{имя} {'ответ' if ответ else 'запрос'}", "smb2.cmd", имя, h, конец - h, команда)
    з = у.поле("Заголовок", "smb2.header", "64 байта", h, 64, родитель=узел)
    у.поле("Подпись протокола", "smb2.protocol_id", "\\xfeSMB", h, 4, родитель=з)
    у.поле("Длина заголовка", "smb2.header_len", 64, h + 4, 2, родитель=з)
    у.поле("Плата кредитов", "smb2.credit.charge", л16(д, h + 6), h + 6, 2, родитель=з)
    if ответ:
        у.поле("Статус", "smb2.nt_status", _статус(статус_или_канал), h + 8, 4, статус_или_канал, родитель=з)
    else:
        у.поле("Последовательность канала", "smb2.channel_sequence", статус_или_канал & 0xFFFF, h + 8, 2,
               родитель=з)
    у.поле("Команда", "smb2.cmd", f"{имя} ({команда})", h + 12, 2, команда, родитель=з)
    у.поле("Кредиты " + ("выдано" if ответ else "запрошено"),
           "smb2.credits.granted" if ответ else "smb2.credits.requested", кредиты, h + 14, 2, родитель=з)
    имена = [и for бит, и in SMB2_ФЛАГИ if флаги & бит]
    ф = у.поле("Флаги", "smb2.flags", f"0x{флаги:08x} ({', '.join(имена) or 'нет'})", h + 16, 4, флаги, родитель=з)
    у.поле("Ответ", "smb2.flags.response", ответ, h + 16, 4, родитель=ф)
    у.поле("Асинхронно", "smb2.flags.async", флаги >> 1 & 1, h + 16, 4, родитель=ф)
    у.поле("Связанная операция", "smb2.flags.chained", флаги >> 2 & 1, h + 16, 4, родитель=ф)
    у.поле("Подписано", "smb2.flags.signature", флаги >> 3 & 1, h + 16, 4, родитель=ф)
    у.поле("Следующая команда (NextCommand)", "smb2.chain_offset", следующий, h + 20, 4, родитель=з,
           плохо=плохой_следующий)
    у.поле("MessageId", "smb2.msg_id", mid, h + 24, 8, родитель=з)
    if флаги & 2:
        у.поле("AsyncId", "smb2.aid", f"0x{л64(д, h + 32):016x}", h + 32, 8, л64(д, h + 32), родитель=з)
        дерево = None
    else:
        дерево = л32(д, h + 36)
        у.поле("TreeId", "smb2.tid", f"0x{дерево:08x}", h + 36, 4, дерево, родитель=з)
    сеанс = л64(д, h + 40)
    у.поле("SessionId", "smb2.sesid", f"0x{сеанс:016x}", h + 40, 8, сеанс, родитель=з)
    у.поле("Подпись", "smb2.signature", д[h + 48:h + 64].hex(), h + 48, 16, родитель=з)
    итог = f"{имя} {'ответ' if ответ else 'запрос'}"
    if ответ and статус_или_канал:
        итог += f", {_статус(статус_или_канал)}"
    тело = h + 64
    if тело + 2 <= конец:
        размер = л16(д, тело)
        ждём = SMB2_РАЗМЕРЫ[команда][1 if ответ else 0]
        ошибка = ответ and размер == 9 and статус_или_канал != 0
        верно = размер in ждём or ошибка
        у.поле("Размер структуры тела", "smb2.buffer_code", размер, тело, 2, родитель=узел, плохо=not верно)
        if not верно:
            р.ошибка(f"SMB2 {имя}: StructureSize {размер}, ожидалось {sorted(ждём)}")
        elif ошибка:
            у.поле("Длина данных ошибки", "smb2.error.byte_count", л32(д, тело + 4), тело + 4, 4, родитель=узел)
        else:
            try:
                доп = _smb2_тело(у, д, h, тело, команда, ответ, узел)
            except (Мало, _Чужое, ValueError):
                доп = ""
                у.поле("Тело оборвано", "", "…", тело, конец - тело, родитель=узел)
            if доп:
                итог += " " + доп
    у._итоги.append(итог)


def _fileid(у, д, м, узел) -> str:
    текст = f"{л64(д, м):016x}-{л64(д, м + 8):016x}"
    у.поле("FileId", "smb2.fid", текст, м, 16, родитель=узел)
    return текст


def _smb2_тело(у, д, h, т, команда, ответ, узел) -> str:
    if команда == 0x00 and not ответ:
        число = л16(д, т + 2)
        у.поле("Диалектов", "smb2.dialect_count", число, т + 2, 2, родитель=узел)
        у.поле("Клиентский GUID", "smb2.client_guid", _байты(д, т + 12, 16).hex(), т + 12, 16, родитель=узел)
        диалекты = []
        for i in range(число):
            код = л16(д, т + 36 + 2 * i)
            диалекты.append(SMB2_ДИАЛЕКТЫ.get(код, f"0x{код:04x}"))
            у.поле(f"Диалект {диалекты[-1]}", "smb2.dialect", диалекты[-1], т + 36 + 2 * i, 2, код, родитель=узел)
        return "(" + ", ".join(диалекты) + ")"
    if команда == 0x00:
        код = л16(д, т + 4)
        у.поле("Диалект", "smb2.dialect", SMB2_ДИАЛЕКТЫ.get(код, f"0x{код:04x}"), т + 4, 2, код, родитель=узел)
        у.поле("GUID сервера", "smb2.server_guid", _байты(д, т + 8, 16).hex(), т + 8, 16, родитель=узел)
        у.поле("Наибольшее чтение", "smb2.max_read_size", л32(д, т + 32), т + 32, 4, родитель=узел)
        у.поле("Наибольшая запись", "smb2.max_write_size", л32(д, т + 36), т + 36, 4, родитель=узел)
        return "диалект " + SMB2_ДИАЛЕКТЫ.get(код, f"0x{код:04x}")
    if команда == 0x01:
        место = т + (12 if not ответ else 4)
        у.поле("Длина буфера безопасности", "smb2.security_blob_len", л16(д, место + 2), место + 2, 2,
               родитель=узел)
        return ""
    if команда == 0x03 and not ответ:
        флаги, смещение, длина = л16(д, т + 2), л16(д, т + 4), л16(д, т + 6)
        if флаги & 0x0004:                              # EXTENSION_PRESENT: путь внутри расширения
            return ""
        путь = _текст(_байты(д, h + смещение, длина), "utf-16-le")
        у.поле("Путь", "smb2.tree", путь, h + смещение, длина, родитель=узел)
        return путь
    if команда == 0x03:
        тип = д[т + 2]
        у.поле("Тип ресурса", "smb2.share_type", SMB2_РЕСУРСЫ.get(тип, str(тип)), т + 2, 1, тип, родитель=узел)
        return SMB2_РЕСУРСЫ.get(тип, "")
    if команда == 0x05 and not ответ:
        у.поле("Доступ", "smb2.access_mask", f"0x{л32(д, т + 24):08x}", т + 24, 4, л32(д, т + 24), родитель=узел)
        расп = л32(д, т + 36)
        у.поле("Распоряжение", "smb2.create.disposition", SMB2_РАСПОРЯЖЕНИЯ.get(расп, str(расп)), т + 36, 4, расп,
               родитель=узел)
        у.поле("Параметры создания", "smb2.create_options", f"0x{л32(д, т + 40):08x}", т + 40, 4, л32(д, т + 40),
               родитель=узел)
        смещение, длина = л16(д, т + 44), л16(д, т + 46)
        имя = _текст(_байты(д, h + смещение, длина), "utf-16-le") if длина else ""
        у.поле("Имя файла", "smb2.filename", имя or "(корень ресурса)", h + смещение, длина, имя, родитель=узел)
        return имя or "(корень)"
    if команда == 0x05:
        действие = л32(д, т + 4)
        у.поле("Действие", "smb2.create.action", SMB2_ДЕЙСТВИЯ.get(действие, str(действие)), т + 4, 4, действие,
               родитель=узел)
        у.поле("Размер файла", "smb2.end_of_file", л64(д, т + 48), т + 48, 8, родитель=узел)
        return "FileId " + _fileid(у, д, т + 64, узел)
    if команда == 0x06 and not ответ:
        return "FileId " + _fileid(у, д, т + 8, узел)
    if команда == 0x08 and not ответ:
        у.поле("Длина чтения", "smb2.read_length", л32(д, т + 4), т + 4, 4, родитель=узел)
        у.поле("Смещение в файле", "smb2.file_offset", л64(д, т + 8), т + 8, 8, родитель=узел)
        _fileid(у, д, т + 16, узел)
        return f"{л32(д, т + 4)} байт с {л64(д, т + 8)}"
    if команда == 0x08:
        у.поле("Смещение данных", "smb2.data_offset", д[т + 2], т + 2, 1, родитель=узел)
        у.поле("Длина данных", "smb2.read_length", л32(д, т + 4), т + 4, 4, родитель=узел)
        return f"{л32(д, т + 4)} байт"
    if команда == 0x09 and not ответ:
        у.поле("Смещение данных", "smb2.data_offset", л16(д, т + 2), т + 2, 2, родитель=узел)
        у.поле("Длина записи", "smb2.write_length", л32(д, т + 4), т + 4, 4, родитель=узел)
        у.поле("Смещение в файле", "smb2.file_offset", л64(д, т + 8), т + 8, 8, родитель=узел)
        _fileid(у, д, т + 16, узел)
        return f"{л32(д, т + 4)} байт с {л64(д, т + 8)}"
    if команда == 0x09:
        у.поле("Записано", "smb2.write.count", л32(д, т + 4), т + 4, 4, родитель=узел)
        return f"{л32(д, т + 4)} байт"
    return ""


def _smb2_transform(р, уровни, м, конец, полон) -> bool:
    д = р.д[:конец]
    _байты(д, м, 52)
    размер, резерв, флаги, сеанс = л32(д, м + 36), л16(д, м + 40), л16(д, м + 42), л64(д, м + 44)
    if флаги != 1 or резерв or размер < 64:
        return False
    у = уровни("SMB2", "SMB2/3 ([MS-SMB2])", м)
    узел = у.поле("Зашифрованное сообщение (Transform)", "smb2.header.transform", "Transform", м, конец - м)
    у.поле("Подпись протокола", "smb2.protocol_id", "\\xfdSMB", м, 4, родитель=узел)
    у.поле("Подпись (MAC)", "smb2.transform_signature", д[м + 4:м + 20].hex(), м + 4, 16, родитель=узел)
    у.поле("Nonce", "smb2.nonce", д[м + 20:м + 36].hex(), м + 20, 16, родитель=узел)
    зашифровано = конец - м - 52
    плохо = полон and зашифровано != размер
    у.поле("Исходный размер сообщения", "smb2.transform_msg_size", размер, м + 36, 4, родитель=узел, плохо=плохо)
    if плохо:
        р.ошибка(f"SMB2 Transform: зашифровано {зашифровано} байт, а исходный размер {размер}")
    у.поле("Флаги (шифрование)", "smb2.transform_flags", флаги, м + 42, 2, родитель=узел)
    у.поле("SessionId", "smb2.sesid", f"0x{сеанс:016x}", м + 44, 8, сеанс, родитель=узел)
    у.поле("Зашифрованные данные", "smb2.transform_data", f"{зашифровано} байт", м + 52, зашифровано, родитель=узел)
    у._итоги.append(f"зашифровано, сеанс 0x{сеанс:016x}, {размер} байт")
    р.п.инфо = "SMB2 " + _свести(у._итоги)
    return True


# -- DHCPv6 (RFC 8415) ----------------------------------------------------------------------------------

DHCP6_ТИПЫ = {1: "SOLICIT", 2: "ADVERTISE", 3: "REQUEST", 4: "CONFIRM", 5: "RENEW", 6: "REBIND",
              7: "REPLY", 8: "RELEASE", 9: "DECLINE", 10: "RECONFIGURE", 11: "INFORMATION-REQUEST",
              12: "RELAY-FORW", 13: "RELAY-REPL"}
DHCP6_ОПЦИИ = {1: "Client Identifier", 2: "Server Identifier", 3: "IA_NA", 4: "IA_TA", 5: "IA Address",
               6: "Option Request", 7: "Preference", 8: "Elapsed Time", 9: "Relay Message",
               11: "Authentication", 12: "Server Unicast", 13: "Status Code", 14: "Rapid Commit",
               15: "User Class", 16: "Vendor Class", 17: "Vendor-specific Information", 18: "Interface-Id",
               19: "Reconfigure Message", 20: "Reconfigure Accept", 23: "DNS Recursive Name Server",
               24: "Domain Search List", 25: "IA_PD", 26: "IA Prefix", 82: "SOL_MAX_RT", 83: "INF_MAX_RT"}
DHCP6_СТАТУСЫ = {0: "Success", 1: "UnspecFail", 2: "NoAddrsAvail", 3: "NoBinding", 4: "NotOnLink",
                 5: "UseMulticast", 6: "NoPrefixAvail"}
DUID_ТИПЫ = {1: "DUID-LLT", 2: "DUID-EN", 3: "DUID-LL", 4: "DUID-UUID"}
#: Точная длина или нижняя граница значения опции (RFC 8415, 21; RFC 3646).
DHCP6_ТОЧНО = {7: 1, 8: 2, 12: 16, 14: 0, 19: 1, 20: 0, 82: 4, 83: 4}
DHCP6_НЕ_МЕНЬШЕ = {1: 2, 2: 2, 3: 12, 4: 4, 5: 24, 9: 4, 11: 11, 13: 2, 16: 4, 17: 4, 25: 12, 26: 25}


@_откат
def dhcpv6(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    if д[м] not in DHCP6_ТИПЫ:
        return False
    у = р.уровень("DHCPv6", "Dynamic Host Configuration Protocol for IPv6", м)
    итог = _dhcp6_сообщение(у, д, м, конец, None, 0)
    у.длина = конец - м
    у.итог = итог
    р.п.инфо = "DHCPv6 " + итог
    return True


def _dhcp6_сообщение(у, д, м, конец, родитель, глубина) -> str:
    тип = д[м]
    if тип not in DHCP6_ТИПЫ or глубина > 32:
        raise _Чужое("тип сообщения DHCPv6")
    у.поле("Тип сообщения", "dhcpv6.msgtype", f"{DHCP6_ТИПЫ[тип]} ({тип})", м, 1, тип, родитель=родитель)
    if тип in (12, 13):
        _байты(д, м, 34)
        у.поле("Число переходов", "dhcpv6.hopcount", д[м + 1], м + 1, 1, родитель=родитель)
        у.поле("Адрес канала", "dhcpv6.linkaddr", ip6(д, м + 2), м + 2, 16, родитель=родитель)
        у.поле("Адрес соседа", "dhcpv6.peeraddr", ip6(д, м + 18), м + 18, 16, родитель=родитель)
        место = м + 34
    else:
        xid = б24(д, м + 1)
        у.поле("Идентификатор транзакции", "dhcpv6.xid", f"0x{xid:06x}", м + 1, 3, xid, родитель=родитель)
        место = м + 4
    сведения = {"коды": [], "вложенное": "", "адреса": []}
    _dhcp6_опции(у, д, место, конец, родитель, глубина, сведения)
    коды = сведения["коды"]
    if тип in (12, 13):
        if 9 not in коды:
            raise _Чужое("у ретранслятора нет Relay Message")
        return f"{DHCP6_ТИПЫ[тип]} [{сведения['вложенное']}]"
    if 1 not in коды and 2 not in коды:
        raise _Чужое("нет ни Client ID, ни Server ID")
    итог = f"{DHCP6_ТИПЫ[тип]} XID 0x{б24(д, м + 1):06x}"
    if сведения["адреса"]:
        итог += " " + ", ".join(сведения["адреса"][:3])
    return итог


def _duid(у, д, м, дл, родитель) -> str:
    тип = б16(д, м)
    if тип not in DUID_ТИПЫ or дл > 130:
        raise _Чужое("тип DUID")
    нужно = {1: 8, 2: 6, 3: 4, 4: 18}[тип]
    if дл < нужно or (тип == 4 and дл != 18):
        raise _Чужое("длина DUID")
    у.поле("Тип DUID", "dhcpv6.duid.type", DUID_ТИПЫ[тип], м, 2, тип, родитель=родитель)
    if тип in (1, 3):
        у.поле("Тип оборудования", "dhcpv6.duid.hwtype", б16(д, м + 2), м + 2, 2, родитель=родитель)
        адрес_м = м + (8 if тип == 1 else 4)
        if тип == 1:
            у.поле("Время", "dhcpv6.duid.time", б32(д, м + 4), м + 4, 4, родитель=родитель)
        адрес = д[адрес_м:м + дл].hex(":")
        у.поле("Адрес канального уровня", "dhcpv6.duid.linklayer_address", адрес, адрес_м, м + дл - адрес_м,
               родитель=родитель)
        return f"{DUID_ТИПЫ[тип]} {адрес}"
    if тип == 2:
        у.поле("Номер предприятия", "dhcpv6.duid.enterprise", б32(д, м + 2), м + 2, 4, родитель=родитель)
    return f"{DUID_ТИПЫ[тип]} {д[м + 2:м + дл].hex()}"


def _dhcp6_опции(у, д, м, конец, родитель, глубина, сведения) -> None:
    место = м
    while место < конец:
        код, дл = б16(д, место), б16(д, место + 2)
        т = место + 4
        _байты(д, т, дл)
        if т + дл > конец or код == 0:
            raise _Чужое("опция DHCPv6 выходит за границу")
        if код in DHCP6_ТОЧНО and дл != DHCP6_ТОЧНО[код] or дл < DHCP6_НЕ_МЕНЬШЕ.get(код, 0):
            raise _Чужое(f"длина опции DHCPv6 {код}")
        имя = DHCP6_ОПЦИИ.get(код, f"опция {код}")
        о = у.поле(имя, "dhcpv6.option.type", имя, место, 4 + дл, код, родитель=родитель)
        у.поле("Код", "dhcpv6.option.type", код, место, 2, родитель=о)
        у.поле("Длина", "dhcpv6.option.length", дл, место + 2, 2, родитель=о)
        сведения["коды"].append(код)
        if код in (1, 2):
            о.текст = f"{имя}: {_duid(у, д, т, дл, о)}"
        elif код in (3, 4, 25):
            у.поле("IAID", "dhcpv6.iaid", f"0x{б32(д, т):08x}", т, 4, б32(д, т), родитель=о)
            вложенные = т + 4
            if код != 4:
                у.поле("T1, с", "dhcpv6.iaid.t1", б32(д, т + 4), т + 4, 4, родитель=о)
                у.поле("T2, с", "dhcpv6.iaid.t2", б32(д, т + 8), т + 8, 4, родитель=о)
                вложенные = т + 12
            _dhcp6_опции(у, д, вложенные, т + дл, о, глубина, сведения)
        elif код == 5:
            адрес = ip6(д, т)
            у.поле("Адрес", "dhcpv6.iaaddr.ip", адрес, т, 16, родитель=о)
            у.поле("Предпочтительное время, с", "dhcpv6.iaaddr.pref_lifetime", б32(д, т + 16), т + 16, 4, родитель=о)
            у.поле("Действительное время, с", "dhcpv6.iaaddr.valid_lifetime", б32(д, т + 20), т + 20, 4, родитель=о)
            о.текст = f"{имя}: {адрес}"
            сведения["адреса"].append(адрес)
            _dhcp6_опции(у, д, т + 24, т + дл, о, глубина, сведения)
        elif код == 26:
            длина_префикса = д[т + 8]
            if длина_префикса > 128:
                raise _Чужое("длина префикса больше 128")
            префикс = f"{ip6(д, т + 9)}/{длина_префикса}"
            у.поле("Предпочтительное время, с", "dhcpv6.iaprefix.pref_lifetime", б32(д, т), т, 4, родитель=о)
            у.поле("Действительное время, с", "dhcpv6.iaprefix.valid_lifetime", б32(д, т + 4), т + 4, 4, родитель=о)
            у.поле("Длина префикса", "dhcpv6.prefix_length", длина_префикса, т + 8, 1, родитель=о)
            у.поле("Префикс", "dhcpv6.iaprefix.pref_addr", префикс, т + 9, 16, родитель=о)
            о.текст = f"{имя}: {префикс}"
            сведения["адреса"].append(префикс)
            _dhcp6_опции(у, д, т + 25, т + дл, о, глубина, сведения)
        elif код == 6:
            if дл % 2:
                raise _Чужое("Option Request нечётной длины")
            for i in range(т, т + дл, 2):
                у.поле(DHCP6_ОПЦИИ.get(б16(д, i), str(б16(д, i))), "dhcpv6.requested_option_code", б16(д, i), i, 2,
                       родитель=о)
        elif код == 7:
            у.поле("Предпочтение", "dhcpv6.preference", д[т], т, 1, родитель=о)
        elif код == 8:
            у.поле("Прошло, 1/100 с", "dhcpv6.elapsed_time", б16(д, т), т, 2, родитель=о)
        elif код == 9:
            о.текст = f"{имя}: вложенное сообщение"
            сведения["вложенное"] = _dhcp6_сообщение(у, д, т, т + дл, о, глубина + 1)
        elif код == 12:
            у.поле("Адрес сервера", "dhcpv6.unicast", ip6(д, т), т, 16, родитель=о)
        elif код == 13:
            статус = б16(д, т)
            текст = _текст(д[т + 2:т + дл])
            у.поле("Код состояния", "dhcpv6.status_code", DHCP6_СТАТУСЫ.get(статус, str(статус)), т, 2, статус,
                   родитель=о)
            у.поле("Сообщение", "dhcpv6.status_msg", текст, т + 2, дл - 2, родитель=о)
            о.текст = f"{имя}: {DHCP6_СТАТУСЫ.get(статус, статус)}"
        elif код == 23:
            if дл == 0 or дл % 16:
                raise _Чужое("DNS-серверы: длина не кратна 16")
            серверы = [ip6(д, i) for i in range(т, т + дл, 16)]
            for i, адрес in zip(range(т, т + дл, 16), серверы):
                у.поле("DNS-сервер", "dhcpv6.dns_server", адрес, i, 16, родитель=о)
            о.текст = f"{имя}: {', '.join(серверы)}"
        elif код == 24:
            for имя_д, i, n in _dns_имена(д, т, т + дл):
                у.поле("Домен", "dhcpv6.domain", имя_д, i, n, родитель=о)
        elif код == 16:
            у.поле("Номер предприятия", "dhcpv6.vendorclass.enterprise", б32(д, т), т, 4, родитель=о)
        elif код == 17:
            у.поле("Номер предприятия", "dhcpv6.vendoropts.enterprise", б32(д, т), т, 4, родитель=о)
        место = т + дл


def _dns_имена(д, м, конец):
    """Имена DNS без сжатия (RFC 1035, 3.1): [(имя, место, длина)]."""
    итог = []
    место = м
    while место < конец:
        начало, метки = место, []
        while True:
            if место >= конец:
                raise _Чужое("имя домена обрывается")
            n = д[место]
            if n == 0:
                место += 1
                break
            if n > 63 or место + 1 + n > конец:
                raise _Чужое("метка домена")
            метки.append(_текст(д[место + 1:место + 1 + n], "ascii"))
            место += 1 + n
        итог.append((".".join(метки) or ".", начало, место - начало))
    return итог


# -- RDP: TPKT (RFC 1006), X.224 (COTP), согласование ([MS-RDPBCGR] 2.2.1.1–2.2.1.2) -----------------

COTP_ТИПЫ = {0xE0: "CR", 0xD0: "CC", 0x80: "DR", 0xC0: "DC", 0xF0: "DT", 0x10: "ED", 0x60: "AK",
             0x20: "EA", 0x50: "RJ", 0x70: "ER"}
COTP_ИМЕНА = {"CR": "запрос соединения", "CC": "подтверждение соединения", "DR": "запрос разъединения",
              "DC": "подтверждение разъединения", "DT": "данные", "ED": "срочные данные",
              "AK": "подтверждение данных", "EA": "подтверждение срочных", "RJ": "отказ", "ER": "ошибка"}
RDP_ПРОТОКОЛЫ = ((0x1, "TLS"), (0x2, "CredSSP"), (0x4, "RDSTLS"), (0x8, "CredSSP EX"), (0x10, "RDS AAD"))
RDP_ОТКАЗЫ = {1: "SSL_REQUIRED_BY_SERVER", 2: "SSL_NOT_ALLOWED_BY_SERVER", 3: "SSL_CERT_NOT_ON_SERVER",
              4: "INCONSISTENT_FLAGS", 5: "HYBRID_REQUIRED_BY_SERVER", 6: "SSL_WITH_USER_AUTH_REQUIRED_BY_SERVER"}


def _протоколы_rdp(код: int) -> str:
    return ", ".join(и for б, и in RDP_ПРОТОКОЛЫ if код & б) or "стандартная защита RDP"


def _tpkt_длина(д, место) -> int:
    if д[место] != 3 or д[место + 1] != 0:
        raise _Чужое("не TPKT")
    дл = б16(д, место + 2)
    if дл < 7:
        raise _Чужое("TPKT короче 7 байт")
    return дл


def _cotp_проверка(д, н, к) -> str:
    """Тип X.224 и проверка его заголовка (X.224, 13.3–13.7); чужое — _Чужое."""
    li = д[н + 4]
    код = д[н + 5]
    тип = COTP_ТИПЫ.get(код & 0xF0)
    if тип is None or li == 255 or н + 5 + li > к:
        raise _Чужое("X.224: тип или LI")
    if тип == "DT" and (li != 2 or код != 0xF0):
        raise _Чужое("X.224 DT класса 0: LI 2")
    if тип in ("CR", "CC", "DR") and li < 6:
        raise _Чужое("X.224 CR/CC/DR: LI не меньше 6")
    if тип in ("CR", "CC") and (код & 0x0F or д[н + 10] >> 4 > 4):
        raise _Чужое("X.224 CR/CC: CDT или класс")
    if тип == "CR" and б16(д, н + 6):
        raise _Чужое("X.224 CR: DST-REF не ноль")
    return тип


@_откат
def tpkt(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    куски, хвост = _нарезать(д, м, lambda место: _tpkt_длина(д, место), 4)
    for н, к in куски:
        if н + 6 <= конец:
            тип = _cotp_проверка(д, н, min(к, конец))
            if н == м and к > конец and тип != "DT":
                return False                           # не уместился — верим только данным X.224 DT
        elif н == м:
            return False
    уровни = _Уровни(р)
    у = уровни("TPKT", "ISO on TCP (RFC 1006)", м)
    for н, к in куски:
        if н + 6 > конец:
            _хвост(у, н, конец, "tpkt.continuation_data")
            break
        _tpkt_pdu(р, уровни, д, н, к, конец)
    if хвост is not None:
        _хвост(у, хвост, конец, "tpkt.continuation_data")
    уровни.закрыть(min(куски[-1][1], конец))
    живые = уровни.живые()
    rdp, cotp = живые.get("RDP"), живые.get("COTP")
    р.п.инфо = ("RDP " + rdp.итог) if rdp else ("COTP " + cotp.итог if cotp else "TPKT " + у.итог)
    if _оборван(куски, хвост, конец):
        р.ошибка("TPKT: последний пакет продолжается в следующем сегменте")
    return True


def _tpkt_pdu(р, уровни, д, н, к, конец) -> None:
    у = уровни("TPKT", "ISO on TCP (RFC 1006)", н)
    узел = у.поле(f"TPKT, {к - н} байт", "tpkt.length", к - н, н, 4)
    у.поле("Версия", "tpkt.version", д[н], н, 1, родитель=узел)
    у.поле("Резерв", "tpkt.reserved", д[н + 1], н + 1, 1, родитель=узел)
    у.поле("Длина", "tpkt.length", к - н, н + 2, 2, родитель=узел)
    у._итоги.append(f"{к - н} байт")
    с = уровни("COTP", "ISO 8073/X.224 COTP", н + 4)
    li, код = д[н + 4], д[н + 5]
    тип = COTP_ТИПЫ[код & 0xF0]
    к_ = min(к, конец)
    узел = с.поле(f"{тип} ({COTP_ИМЕНА[тип]})", "cotp.type", тип, н + 4, min(1 + li, к_ - н - 4), код & 0xF0)
    с.поле("Длина заголовка (LI)", "cotp.li", li, н + 4, 1, родитель=узел)
    с.поле("Тип TPDU", "cotp.type", f"0x{код & 0xF0:02x} ({тип})", н + 5, 1, код & 0xF0, родитель=узел)
    итог = COTP_ИМЕНА[тип]
    if тип == "DT":
        с.поле("Конец TSDU (EOT)", "cotp.eot", д[н + 6] >> 7, н + 6, 1, родитель=узел)
        с.поле("Номер TPDU", "cotp.tpdu-number", д[н + 6] & 0x7F, н + 6, 1, родитель=узел)
        с._итоги.append(итог)
        if н + 7 < к_:
            данные(р, н + 7, "MCS (T.125)", к_)
        return
    if тип in ("CR", "CC", "DR"):
        с.поле("DST-REF", "cotp.dst_ref", f"0x{б16(д, н + 6):04x}", н + 6, 2, б16(д, н + 6), родитель=узел)
        с.поле("SRC-REF", "cotp.src_ref", f"0x{б16(д, н + 8):04x}", н + 8, 2, б16(д, н + 8), родитель=узел)
        if тип == "DR":
            с.поле("Причина", "cotp.reason", д[н + 10], н + 10, 1, родитель=узел)
        else:
            с.поле("Класс", "cotp.class", д[н + 10] >> 4, н + 10, 1, родитель=узел)
            с.поле("Параметры класса", "cotp.opts", д[н + 10] & 0x0F, н + 10, 1, родитель=узел)
    с._итоги.append(итог)
    if тип in ("CR", "CC"):
        _rdp_согласование(р, уровни, д, н + 11, min(н + 5 + li, к_), тип)


def _rdp_согласование(р, уровни, д, м, конец, тип) -> None:
    """Переменная часть CR/CC у RDP — cookie и RDP_NEG_REQ/RSP/FAILURE ([MS-RDPBCGR] 2.2.1.1)."""
    if м >= конец:
        return
    место = м
    cookie = None
    if тип == "CR" and д.startswith(b"Cookie: ", место):
        перевод = д.find(b"\r\n", место, конец)
        if перевод < 0:
            raise _Чужое("cookie RDP без \\r\\n")
        cookie = (место, перевод + 2)
        место = перевод + 2
    остаток = конец - место
    виды = (1,) if тип == "CR" else (2, 3)
    if остаток and not (д[место] in виды and л16(д, место + 2) == 8
                        and (остаток == 8 or (тип == "CR" and остаток == 44 and д[место + 1] & 0x08))):
        if cookie is None:
            return                                      # не RDP: переменная часть X.224 — не трогаем
        raise _Чужое("после cookie RDP — не RDP_NEG_REQ")
    у = уровни("RDP", "Remote Desktop Protocol", м)
    итог = ""
    if cookie:
        текст = _текст(д[cookie[0] + 8:cookie[1] - 2], "latin-1")
        у.поле("Cookie", "rdp.rt_cookie", текст, cookie[0], cookie[1] - cookie[0])
        итог = текст
    if остаток:
        вид, флаги, значение = д[место], д[место + 1], л32(д, место + 4)
        имя = {1: "RDP_NEG_REQ", 2: "RDP_NEG_RSP", 3: "RDP_NEG_FAILURE"}[вид]
        узел = у.поле(имя, "rdp.neg_type", имя, место, 8, вид)
        у.поле("Тип", "rdp.neg_type", вид, место, 1, родитель=узел)
        у.поле("Флаги", "rdp.neg_flags", f"0x{флаги:02x}", место + 1, 1, флаги, родитель=узел)
        у.поле("Длина", "rdp.neg_length", 8, место + 2, 2, родитель=узел)
        if вид == 1:
            у.поле("Запрошенные протоколы", "rdp.requestedProtocols", f"0x{значение:08x} ({_протоколы_rdp(значение)})",
                   место + 4, 4, значение, родитель=узел)
            итог += (", " if итог else "") + "запрошено: " + _протоколы_rdp(значение)
        elif вид == 2:
            у.поле("Выбранный протокол", "rdp.selectedProtocol",
                   f"0x{значение:08x} ({_протоколы_rdp(значение)})", место + 4, 4, значение, родитель=узел)
            итог = "выбрано: " + _протоколы_rdp(значение)
        else:
            у.поле("Код отказа", "rdp.neg_failure.code", RDP_ОТКАЗЫ.get(значение, str(значение)), место + 4, 4,
                   значение, родитель=узел)
            итог = "отказ: " + RDP_ОТКАЗЫ.get(значение, str(значение))
        if остаток > 8:
            у.поле("Сведения о корреляции", "rdp.correlation_info", f"{остаток - 8} байт", место + 8, остаток - 8)
    у._итоги.append(итог or "согласование")


# -- HTTP/2 (RFC 9113) ----------------------------------------------------------------------------------

H2_ПРЕАМБУЛА = b"PRI * HTTP/2.0\r\n\r\nSM\r\n\r\n"
H2_ТИПЫ = {0: "DATA", 1: "HEADERS", 2: "PRIORITY", 3: "RST_STREAM", 4: "SETTINGS", 5: "PUSH_PROMISE",
           6: "PING", 7: "GOAWAY", 8: "WINDOW_UPDATE", 9: "CONTINUATION"}
H2_ФЛАГИ = {0: 0x09, 1: 0x2D, 2: 0, 3: 0, 4: 0x01, 5: 0x0C, 6: 0x01, 7: 0, 8: 0, 9: 0x04}
H2_ИМЕНА_ФЛАГОВ = {0x01: "END_STREAM", 0x04: "END_HEADERS", 0x08: "PADDED", 0x20: "PRIORITY"}
H2_ПАРАМЕТРЫ = {1: "HEADER_TABLE_SIZE", 2: "ENABLE_PUSH", 3: "MAX_CONCURRENT_STREAMS", 4: "INITIAL_WINDOW_SIZE",
                5: "MAX_FRAME_SIZE", 6: "MAX_HEADER_LIST_SIZE", 8: "ENABLE_CONNECT_PROTOCOL",
                9: "NO_RFC7540_PRIORITIES"}
H2_ОШИБКИ = {0: "NO_ERROR", 1: "PROTOCOL_ERROR", 2: "INTERNAL_ERROR", 3: "FLOW_CONTROL_ERROR",
             4: "SETTINGS_TIMEOUT", 5: "STREAM_CLOSED", 6: "FRAME_SIZE_ERROR", 7: "REFUSED_STREAM",
             8: "CANCEL", 9: "COMPRESSION_ERROR", 10: "CONNECT_ERROR", 11: "ENHANCE_YOUR_CALM",
             12: "INADEQUATE_SECURITY", 13: "HTTP_1_1_REQUIRED"}


def _h2_проверка(д, н, строго: bool) -> int:
    """Длина кадра с заголовком; нарушение RFC 9113 (4.1, 6.x) — _Чужое."""
    дл, тип, флаги, поток = б24(д, н), д[н + 3], д[н + 4], б32(д, н + 5)
    if тип not in H2_ТИПЫ:
        if строго:
            raise _Чужое("неизвестный тип кадра HTTP/2")
        return 9 + дл
    if строго and (дл > 16384 or поток >> 31 or флаги & ~H2_ФЛАГИ[тип]):
        raise _Чужое("длина, бит R или флаги кадра HTTP/2")
    поток &= 0x7FFFFFFF
    if (тип in (4, 6, 7)) != (поток == 0) and тип != 8:
        raise _Чужое("поток кадра HTTP/2")
    нужно = {2: дл == 5, 3: дл == 4, 6: дл == 8, 8: дл == 4, 7: дл >= 8, 5: дл >= 4,
             4: дл % 6 == 0 and not (флаги & 1 and дл)}.get(тип, True)
    if not нужно:
        raise _Чужое("длина кадра HTTP/2 не по типу")
    if тип in (0, 1, 5) and флаги & 0x08 and (дл < 1 or д[н + 9] >= дл):
        raise _Чужое("длина заполнения HTTP/2")
    if тип == 8 and н + 13 <= len(д) and not б32(д, н + 9) & 0x7FFFFFFF:
        raise _Чужое("WINDOW_UPDATE с нулевым приращением")
    if тип == 4 and н + 9 + дл <= len(д):
        for i in range(н + 9, н + 9 + дл, 6):
            ид, значение = б16(д, i), б32(д, i + 2)
            if (ид in (2, 8, 9) and значение > 1) or (ид == 4 and значение > 0x7FFFFFFF) or \
                    (ид == 5 and not 16384 <= значение <= 0xFFFFFF):
                raise _Чужое("значение параметра SETTINGS вне пределов")
    return 9 + дл


def _http2(р: Разбор, м: int, конец: int, *, эвристика: bool) -> bool:
    д = р.д[:конец]
    преамбула = д.startswith(H2_ПРЕАМБУЛА, м)
    начало = м + 24 if преамбула else м
    строго = not преамбула
    куски, хвост = ([], None) if начало >= конец and преамбула else \
        _нарезать(д, начало, lambda н: _h2_проверка(д, н, строго), 9)
    if not преамбула and _оборван(куски, хвост, конец) and (эвристика or not _полных(куски, конец)):
        return False
    у = р.уровень("HTTP2", "HyperText Transfer Protocol 2", м)
    итоги = []
    if преамбула:
        у.поле("Преамбула соединения", "http2.magic", "PRI * HTTP/2.0", м, 24)
        итоги.append("преамбула")
    for н, к in куски:
        итоги.append(_h2_кадр(у, д, н, min(к, конец)))
    if хвост is not None:
        _хвост(у, хвост, конец, "http2.continuation_data")
    у.длина = конец - м
    у.итог = _свести(итоги)
    р.п.инфо = "HTTP/2 " + у.итог
    return True


def _h2_кадр(у, д, н, к) -> str:
    дл, тип, флаги, поток = б24(д, н), д[н + 3], д[н + 4], б32(д, н + 5) & 0x7FFFFFFF
    имя = H2_ТИПЫ.get(тип, f"тип {тип}")
    флаги_текст = ", ".join(и for б, и in H2_ИМЕНА_ФЛАГОВ.items() if флаги & б and H2_ФЛАГИ.get(тип, 0) & б)
    if тип in (4, 6) and флаги & 1:
        флаги_текст = "ACK"
    узел = у.поле(f"{имя}, поток {поток}, {дл} байт", "http2.type", имя, н, к - н, тип)
    у.поле("Длина", "http2.length", дл, н, 3, родитель=узел)
    у.поле("Тип", "http2.type", f"{имя} ({тип})", н + 3, 1, тип, родитель=узел)
    у.поле("Флаги", "http2.flags", f"0x{флаги:02x}" + (f" ({флаги_текст})" if флаги_текст else ""), н + 4, 1, флаги,
           родитель=узел)
    у.поле("Поток", "http2.streamid", поток, н + 5, 4, родитель=узел)
    т = н + 9
    итог = имя + (f"[{поток}]" if поток else "") + (" ACK" if тип in (4, 6) and флаги & 1 else "")
    if к < т + дл:
        у.поле("Кадр оборван", "", f"{к - т} из {дл} байт", т, к - т, родитель=узел)
        return итог
    заполнение = 0
    if тип in (0, 1, 5) and флаги & 0x08:
        заполнение = д[т]
        у.поле("Длина заполнения", "http2.pad_length", заполнение, т, 1, родитель=узел)
        т += 1
    if тип == 4:
        for i in range(т, т + дл, 6):
            ид, значение = б16(д, i), б32(д, i + 2)
            п = у.поле(f"{H2_ПАРАМЕТРЫ.get(ид, f'параметр {ид}')} = {значение}", "http2.settings.id", ид, i, 6,
                       родитель=узел)
            у.поле("Значение", "http2.settings.value", значение, i + 2, 4, родитель=п)
    elif тип == 8:
        у.поле("Приращение окна", "http2.window_update.window_size_increment", б32(д, т) & 0x7FFFFFFF, т, 4,
               родитель=узел)
        итог += f" +{б32(д, т) & 0x7FFFFFFF}"
    elif тип == 3:
        у.поле("Код ошибки", "http2.rst_stream.error", H2_ОШИБКИ.get(б32(д, т), str(б32(д, т))), т, 4, б32(д, т),
               родитель=узел)
    elif тип == 7:
        код = б32(д, т + 4)
        у.поле("Последний поток", "http2.goaway.last_stream_id", б32(д, т) & 0x7FFFFFFF, т, 4, родитель=узел)
        у.поле("Код ошибки", "http2.goaway.error", H2_ОШИБКИ.get(код, str(код)), т + 4, 4, код, родитель=узел)
        if дл > 8:
            у.поле("Отладочные данные", "http2.goaway.addata", печатное(д[т + 8:т + дл]), т + 8, дл - 8, родитель=узел)
        итог += " " + H2_ОШИБКИ.get(код, str(код))
    elif тип == 6:
        у.поле("Данные PING", "http2.ping", д[т:т + 8].hex(), т, 8, родитель=узел)
    elif тип == 2 or (тип == 1 and флаги & 0x20):
        у.поле("Исключительная", "http2.exclusive", б32(д, т) >> 31, т, 4, родитель=узел)
        у.поле("Зависит от потока", "http2.stream_dependency", б32(д, т) & 0x7FFFFFFF, т, 4, родитель=узел)
        у.поле("Вес", "http2.weight", д[т + 4] + 1, т + 4, 1, родитель=узел)
        if тип == 1:
            т += 5
    elif тип == 5:
        у.поле("Обещанный поток", "http2.push_promise.promised_stream_id", б32(д, т) & 0x7FFFFFFF, т, 4,
               родитель=узел)
        т += 4
    if тип in (1, 5, 9):
        сколько = н + 9 + дл - заполнение - т
        у.поле("Блок заголовков (HPACK, не раскрыт)", "http2.header_block", f"{сколько} байт", т, сколько,
               родитель=узел)
    elif тип == 0:
        сколько = н + 9 + дл - заполнение - т
        у.поле("Данные", "http2.data.data", f"{сколько} байт: {печатное(д[т:т + сколько], 40)}", т, сколько,
               родитель=узел)
    if заполнение:
        у.поле("Заполнение", "http2.padding", заполнение, н + 9 + дл - заполнение, заполнение, родитель=узел)
    return итог


