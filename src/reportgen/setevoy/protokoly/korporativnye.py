# -- WebSocket (RFC 6455, 5.2) -----------------------------------------------------------------------------

WS_ОПКОДЫ = {0: "продолжение", 1: "текст", 2: "двоичные", 8: "закрытие", 9: "ping", 10: "pong"}


def _ws_разметка(д, н):
    """(начало данных, длина данных, ключ маски или None) кадра; нарушение RFC 6455 — _Чужое."""
    б0, б1 = _байты(д, н, 2)
    fin, rsv, оп = б0 >> 7, (б0 >> 4) & 7, б0 & 15
    if оп not in WS_ОПКОДЫ or rsv & 3 or (rsv & 4 and оп not in (1, 2)):
        raise _Чужое("опкод или RSV WebSocket")
    маска, дл = б1 >> 7, б1 & 0x7F
    место = н + 2
    if дл == 126:
        дл = б16(д, место)
        место += 2
        if дл < 126:
            raise _Чужое("длина WebSocket не в наименьшей записи")
    elif дл == 127:
        дл = б64(д, место)
        место += 8
        if дл >> 63 or дл < 65536:
            raise _Чужое("длина WebSocket не в наименьшей записи")
    if оп >= 8 and (not fin or дл > 125):
        raise _Чужое("управляющий кадр WebSocket фрагментирован или длиннее 125")
    ключ = _байты(д, место, 4) if маска else None
    место += 4 if маска else 0
    return место, дл, ключ


def _ws_данные(д, т, дл, ключ) -> bytes:
    сырые = д[т:т + дл]
    if ключ is None:
        return сырые
    return bytes(б ^ ключ[i & 3] for i, б in enumerate(сырые))


def _ws_длина(д, н) -> int:
    т, дл, ключ = _ws_разметка(д, н)
    if т + дл <= len(д):
        б0 = д[н]
        оп, данные_ = б0 & 15, _ws_данные(д, т, дл, ключ)
        if оп == 1 and б0 & 0x80 and not б0 & 0x40:
            данные_.decode("utf-8")                    # целый текстовый кадр — только UTF-8
        if оп == 8:
            if дл == 1:
                raise _Чужое("кадр закрытия длиной 1")
            if дл >= 2:
                код = int.from_bytes(данные_[:2], "big")
                if not (1000 <= код <= 1003 or 1007 <= код <= 1014 or 3000 <= код <= 4999):
                    raise _Чужое("код закрытия WebSocket")
                данные_[2:].decode("utf-8")
    return т + дл - н


def _websocket(р: Разбор, м: int, конец: int, *, эвристика: bool) -> bool:
    д = р.д[:конец]
    куски, хвост = _нарезать(д, м, lambda н: _ws_длина(д, н), 2)
    if _оборван(куски, хвост, конец) and (эвристика or not _полных(куски, конец)):
        return False
    if эвристика:
        # Без порта и без рукопожатия Upgrade: сегмент не начинается продолжением,
        # а пустыми бывают только управляющие кадры (иначе нули заполнения — «кадры»).
        if д[м] & 15 == 0:
            return False
        for н, к in куски:
            т, дл, _ключ = _ws_разметка(д, н)
            if дл == 0 and д[н] & 15 < 8:
                return False
    у = р.уровень("WebSocket", "WebSocket (RFC 6455)", м)
    итоги = []
    for н, к in куски:
        if к > конец:
            _хвост(у, н, конец, "websocket.continuation_data")
            break
        т, дл, ключ = _ws_разметка(д, н)
        б0 = д[н]
        оп = б0 & 15
        узел = у.поле(f"{WS_ОПКОДЫ[оп]}{'' if б0 & 0x80 else ' (не последний фрагмент)'}, {дл} байт",
                      "websocket.opcode", WS_ОПКОДЫ[оп], н, к - н, оп)
        у.поле("FIN", "websocket.fin", б0 >> 7, н, 1, родитель=узел)
        у.поле("RSV", "websocket.rsv", (б0 >> 4) & 7, н, 1, родитель=узел)
        у.поле("Опкод", "websocket.opcode", f"{оп} ({WS_ОПКОДЫ[оп]})", н, 1, оп, родитель=узел)
        у.поле("Маска", "websocket.mask", int(ключ is not None), н + 1, 1, родитель=узел)
        у.поле("Длина данных", "websocket.payload_length", дл, н + 1, т - н - 1 - (4 if ключ else 0), родитель=узел)
        if ключ:
            у.поле("Ключ маски", "websocket.masking_key", ключ.hex(), т - 4, 4, родитель=узел)
        данные_ = _ws_данные(д, т, дл, ключ)
        итог = WS_ОПКОДЫ[оп]
        if оп == 8 and дл >= 2:
            код = int.from_bytes(данные_[:2], "big")
            у.поле("Код закрытия", "websocket.payload.close.status_code", код, т, 2, родитель=узел)
            if дл > 2:
                у.поле("Причина", "websocket.payload.close.reason", данные_[2:].decode("utf-8"), т + 2, дл - 2,
                       родитель=узел)
            итог += f" {код}"
        elif оп == 1 and not б0 & 0x40:
            текст = _текст(данные_)
            у.поле("Текст", "websocket.payload.text", текст[:200], т, дл, текст, родитель=узел)
            итог += f" «{текст[:40]}»"
        elif дл:
            у.поле("Данные", "websocket.payload", f"{дл} байт: {печатное(данные_, 40)}", т, дл, данные_.hex(),
                   родитель=узел)
        итоги.append(итог)
    if хвост is not None:
        _хвост(у, хвост, конец, "websocket.continuation_data")
    у.длина = конец - м
    у.итог = _свести(итоги)
    р.п.инфо = "WebSocket " + у.итог
    return True


@_откат
def websocket(р: Разбор, м: int, конец: int) -> bool:
    return _websocket(р, м, конец, эвристика=False)


@_откат
def websocket_эвристика(р: Разбор, м: int, конец: int) -> bool:
    return _websocket(р, м, конец, эвристика=True)


# -- ONC RPC (RFC 5531) и программы: portmap, NFS, MOUNT ----------------------------------------------------

RPC_ПРОГРАММЫ = {100000: "portmap", 100003: "NFS", 100005: "MOUNT", 100011: "rquota", 100021: "NLM",
                 100024: "status (NSM)", 100227: "NFS_ACL"}
RPC_АУТ = {0: "AUTH_NONE", 1: "AUTH_SYS", 2: "AUTH_SHORT", 3: "AUTH_DH", 6: "RPCSEC_GSS"}
RPC_ПРИНЯТО = {0: "SUCCESS", 1: "PROG_UNAVAIL", 2: "PROG_MISMATCH", 3: "PROC_UNAVAIL", 4: "GARBAGE_ARGS",
               5: "SYSTEM_ERR"}
RPC_ОТКАЗ = {0: "RPC_MISMATCH", 1: "AUTH_ERROR"}
RPC_АУТ_ОШИБКИ = {0: "AUTH_OK", 1: "AUTH_BADCRED", 2: "AUTH_REJECTEDCRED", 3: "AUTH_BADVERF",
                  4: "AUTH_REJECTEDVERF", 5: "AUTH_TOOWEAK", 6: "AUTH_INVALIDRESP", 7: "AUTH_FAILED",
                  13: "RPCSEC_GSS_CREDPROBLEM", 14: "RPCSEC_GSS_CTXPROBLEM"}
NFS2_ПРОЦЕДУРЫ = ("NULL", "GETATTR", "SETATTR", "ROOT", "LOOKUP", "READLINK", "READ", "WRITECACHE", "WRITE",
                  "CREATE", "REMOVE", "RENAME", "LINK", "SYMLINK", "MKDIR", "RMDIR", "READDIR", "STATFS")
NFS3_ПРОЦЕДУРЫ = ("NULL", "GETATTR", "SETATTR", "LOOKUP", "ACCESS", "READLINK", "READ", "WRITE", "CREATE",
                  "MKDIR", "SYMLINK", "MKNOD", "REMOVE", "RMDIR", "RENAME", "LINK", "READDIR", "READDIRPLUS",
                  "FSSTAT", "FSINFO", "PATHCONF", "COMMIT")
NFS4_ПРОЦЕДУРЫ = ("NULL", "COMPOUND")
PORTMAP2_ПРОЦЕДУРЫ = ("NULL", "SET", "UNSET", "GETPORT", "DUMP", "CALLIT")
RPCBIND_ПРОЦЕДУРЫ = ("NULL", "SET", "UNSET", "GETADDR", "DUMP", "CALLIT", "GETTIME", "UADDR2TADDR",
                     "TADDR2UADDR")
MOUNT3_ПРОЦЕДУРЫ = ("NULL", "MNT", "DUMP", "UMNT", "UMNTALL", "EXPORT")


def _процедура(прог: int, верс: int, проц: int) -> str:
    таблица = {(100003, 2): NFS2_ПРОЦЕДУРЫ, (100003, 3): NFS3_ПРОЦЕДУРЫ, (100003, 4): NFS4_ПРОЦЕДУРЫ,
               (100000, 2): PORTMAP2_ПРОЦЕДУРЫ, (100000, 3): RPCBIND_ПРОЦЕДУРЫ,
               (100000, 4): RPCBIND_ПРОЦЕДУРЫ, (100005, 3): MOUNT3_ПРОЦЕДУРЫ,
               (100005, 1): MOUNT3_ПРОЦЕДУРЫ}.get((прог, верс), ())
    return таблица[проц] if проц < len(таблица) else str(проц)


def _xdr_строка(д, м, предел) -> tuple:
    """Строка/opaque XDR (RFC 4506, 4.10–4.11): (байты, место за выравниванием)."""
    n = б32(д, м)
    if n > предел:
        raise _Чужое("строка XDR длиннее предела")
    значение = _байты(д, м + 4, n)
    хвост = _байты(д, м + 4 + n, _pad4(n) - n)
    if any(хвост):
        raise _Чужое("выравнивание XDR не нулями")
    return значение, м + 4 + _pad4(n)


def _rpc_ауть(у, д, м, узел, что) -> int:
    вид, дл = б32(д, м), б32(д, м + 4)
    if вид not in RPC_АУТ or дл > 400 or (вид == 0 and дл):
        raise _Чужое("аутентификация RPC")
    тело, после = м + 8, м + 8 + _pad4(дл)
    _байты(д, тело, _pad4(дл))
    а = у.поле(f"{что}: {RPC_АУТ[вид]}", "rpc.auth.flavor", RPC_АУТ[вид], м, после - м, вид, родитель=узел)
    у.поле("Длина", "rpc.auth.length", дл, м + 4, 4, родитель=а)
    if вид == 1:
        имя, место = _xdr_строка(д, тело + 4, 255)
        uid, gid, групп = б32(д, место), б32(д, место + 4), б32(д, место + 8)
        if групп > 16 or место + 12 + 4 * групп != тело + дл:
            raise _Чужое("AUTH_SYS: группы или длина")
        у.поле("Отметка", "rpc.auth.stamp", f"0x{б32(д, тело):08x}", тело, 4, б32(д, тело), родитель=а)
        у.поле("Имя машины", "rpc.auth.machinename", _текст(имя), тело + 4, 4 + _pad4(len(имя)), родитель=а)
        у.поле("UID", "rpc.auth.uid", uid, место, 4, родитель=а)
        у.поле("GID", "rpc.auth.gid", gid, место + 4, 4, родитель=а)
        у.поле("Дополнительных групп", "rpc.auth.gids", групп, место + 8, 4 + 4 * групп, родитель=а)
    return после


def _rpc_сообщение(р, уровни, д, м, конец) -> str:
    д = д[:конец]
    xid, вид = б32(д, м), б32(д, м + 4)
    if вид == 0:
        верс_rpc, прог, верс, проц = б32(д, м + 8), б32(д, м + 12), б32(д, м + 16), б32(д, м + 20)
        if верс_rpc != 2:
            raise _Чужое("версия RPC не 2")
    elif вид == 1:
        стат = б32(д, м + 8)
        if стат not in (0, 1):
            raise _Чужое("reply_stat RPC")
    else:
        raise _Чужое("msg_type RPC")
    у = уровни("RPC", "Remote Procedure Call (ONC RPC)", м)
    узел = у.поле(f"{'Вызов' if вид == 0 else 'Ответ'} XID 0x{xid:08x}", "rpc.xid", xid, м, конец - м)
    у.поле("XID", "rpc.xid", f"0x{xid:08x}", м, 4, xid, родитель=узел)
    у.поле("Тип сообщения", "rpc.msgtyp", "CALL" if вид == 0 else "REPLY", м + 4, 4, вид, родитель=узел)
    if вид == 0:
        узел.текст = f"Вызов XID 0x{xid:08x}"
        у.поле("Версия RPC", "rpc.version", 2, м + 8, 4, родитель=узел)
        имя = RPC_ПРОГРАММЫ.get(прог, str(прог))
        у.поле("Программа", "rpc.program", f"{имя} ({прог})", м + 12, 4, прог, родитель=узел)
        у.поле("Версия программы", "rpc.programversion", верс, м + 16, 4, родитель=узел)
        процедура = _процедура(прог, верс, проц)
        у.поле("Процедура", "rpc.procedure", f"{процедура} ({проц})", м + 20, 4, проц, родитель=узел)
        место = _rpc_ауть(у, д, м + 24, узел, "Удостоверение")
        место = _rpc_ауть(у, д, место, узел, "Проверка")
        итог = f"вызов {имя} v{верс} {процедура}"
        доп = _rpc_программа(уровни, д, место, конец, прог, верс, проц, процедура)
        итог += (f" {доп}" if доп else "") + f" XID 0x{xid:08x}"
        у._итоги.append(итог)
        return итог
    стат = б32(д, м + 8)
    у.поле("Состояние ответа", "rpc.replystat", "MSG_ACCEPTED" if стат == 0 else "MSG_DENIED", м + 8, 4, стат,
           родитель=узел)
    if стат == 0:
        место = _rpc_ауть(у, д, м + 12, узел, "Проверка")
        принято = б32(д, место)
        if принято not in RPC_ПРИНЯТО:
            raise _Чужое("accept_stat RPC")
        у.поле("Результат", "rpc.state_accept", RPC_ПРИНЯТО[принято], место, 4, принято, родитель=узел)
        if принято == 2:
            у.поле("Версии", "rpc.programversion.min", f"{б32(д, место + 4)}–{б32(д, место + 8)}", место + 4, 8,
                   родитель=узел)
        итог = f"ответ {RPC_ПРИНЯТО[принято]}"
    else:
        отказ = б32(д, м + 12)
        if отказ not in RPC_ОТКАЗ:
            raise _Чужое("reject_stat RPC")
        у.поле("Отказ", "rpc.state_reject", RPC_ОТКАЗ[отказ], м + 12, 4, отказ, родитель=узел)
        if отказ == 1:
            ошибка = б32(д, м + 16)
            if ошибка not in RPC_АУТ_ОШИБКИ:
                raise _Чужое("auth_stat RPC")
            у.поле("Ошибка аутентификации", "rpc.state_auth", RPC_АУТ_ОШИБКИ[ошибка], м + 16, 4, ошибка, родитель=узел)
            итог = f"отказ {RPC_АУТ_ОШИБКИ[ошибка]}"
        else:
            у.поле("Версии RPC", "rpc.version.min", f"{б32(д, м + 16)}–{б32(д, м + 20)}", м + 16, 8, родитель=узел)
            итог = "отказ RPC_MISMATCH"
    итог += f" XID 0x{xid:08x}"
    у._итоги.append(итог)
    return итог


def _rpc_программа(уровни, д, м, конец, прог, верс, проц, процедура) -> str:
    """Уровень программы над RPC: NFS, portmap, MOUNT — процедура и главные аргументы."""
    имя, полное, ключ = {100003: ("NFS", "Network File System", "nfs"),
                         100000: ("Portmap", "Portmapper / rpcbind", "portmap"),
                         100005: ("MOUNT", "Mount Protocol", "mount")}.get(прог, (None, None, None))
    if имя is None:
        return ""
    у = уровни(имя, полное, м)
    ключ_процедуры = f"{ключ}.procedure_v{верс}" if прог == 100003 else f"{ключ}.procedure"
    узел = у.поле(f"{имя} v{верс} {процедура}", ключ_процедуры, процедура, м, конец - м, проц)
    доп = ""
    try:
        if прог == 100003 and верс == 3 and процедура in ("LOOKUP", "CREATE", "MKDIR", "REMOVE", "RMDIR", "SYMLINK",
                                                           "MKNOD"):
            fh, место = _xdr_строка(д, м, 64)
            у.поле("Дескриптор каталога", "nfs.fhandle", fh.hex(), м, место - м, родитель=узел)
            имя_ф, после = _xdr_строка(д, место, 1024)
            доп = _текст(имя_ф)
            у.поле("Имя", "nfs.name", доп, место, после - место, родитель=узел)
        elif прог == 100000 and верс == 2 and процедура in ("SET", "UNSET", "GETPORT"):
            п, в, пр, порт = б32(д, м), б32(д, м + 4), б32(д, м + 8), б32(д, м + 12)
            у.поле("Программа", "portmap.prog", f"{RPC_ПРОГРАММЫ.get(п, п)} ({п})", м, 4, п, родитель=узел)
            у.поле("Версия", "portmap.version", в, м + 4, 4, родитель=узел)
            у.поле("Протокол", "portmap.proto", {6: "TCP", 17: "UDP"}.get(пр, str(пр)), м + 8, 4, пр, родитель=узел)
            у.поле("Порт", "portmap.port", порт, м + 12, 4, родитель=узел)
            доп = f"{RPC_ПРОГРАММЫ.get(п, п)} v{в}"
        elif прог == 100005 and процедура in ("MNT", "UMNT"):
            путь, после = _xdr_строка(д, м, 1024)
            доп = _текст(путь)
            у.поле("Путь", "mount.path", доп, м, после - м, родитель=узел)
    except (Мало, _Чужое):
        pass
    у._итоги.append(f"v{верс} {процедура}" + (f" {доп}" if доп else ""))
    return доп


def _rpc_udp(р: Разбор, м: int, конец: int, *, эвристика: bool) -> bool:
    д = р.д[:конец]
    if эвристика and not _rpc_вызов_известный(д, м):
        return False
    уровни = _Уровни(р)
    итог = _rpc_сообщение(р, уровни, д, м, конец)
    уровни.закрыть(конец)
    р.п.инфо = "RPC " + итог
    return True


def _rpc_вызов_известный(д, м) -> bool:
    """Для угадывания без порта: вызов RPC v2 известной программы."""
    return (м + 24 <= len(д) and б32(д, м + 4) == 0 and б32(д, м + 8) == 2
            and б32(д, м + 12) in RPC_ПРОГРАММЫ and б32(д, м + 16) < 10)


def _rpc_tcp(р: Разбор, м: int, конец: int, *, эвристика: bool) -> bool:
    """RPC по TCP: записи с маркером (RFC 5531, 11) — бит последнего фрагмента и 31 бит длины."""
    д = р.д[:конец]

    def длина(н):
        return 4 + (б32(д, н) & 0x7FFFFFFF)
    if эвристика and not _rpc_вызов_известный(д, м + 4):
        return False
    куски, хвост = _нарезать(д, м, длина, 4)
    уровни = _Уровни(р)
    у = уровни("RPC", "Remote Procedure Call (ONC RPC)", м)
    итоги = []
    начало_сообщения = True
    for н, к in куски:
        маркер = б32(д, н)
        последний = маркер >> 31
        ф = у.поле(f"Маркер записи: {к - н - 4} байт{', последний фрагмент' if последний else ''}",
                   "rpc.fraglen", к - н - 4, н, 4)
        у.поле("Последний фрагмент", "rpc.lastfrag", последний, н, 4, родитель=ф)
        if начало_сообщения:
            if н + 12 <= конец:
                итоги.append(_rpc_сообщение(р, уровни, д, н + 4, min(к, конец)))
            elif н == м:
                return False
        начало_сообщения = bool(последний)
    if not итоги:
        return False
    if хвост is not None:
        _хвост(у, хвост, конец, "rpc.continuation_data")
    уровни.закрыть(min(куски[-1][1], конец))
    р.п.инфо = "RPC " + _свести(итоги)
    if _оборван(куски, хвост, конец):
        р.ошибка("RPC: запись продолжается в следующем сегменте")
    return True


@_откат
def rpc_udp(р, м, конец):
    return _rpc_udp(р, м, конец, эвристика=False)


@_откат
def rpc_udp_эвристика(р, м, конец):
    return _rpc_udp(р, м, конец, эвристика=True)


@_откат
def rpc_tcp(р, м, конец):
    return _rpc_tcp(р, м, конец, эвристика=False)


@_откат
def rpc_tcp_эвристика(р, м, конец):
    return _rpc_tcp(р, м, конец, эвристика=True)


