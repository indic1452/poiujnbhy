_ОШИБКИ = (Мало, IndexError, ValueError, struct.error, RecursionError)


class _Чужое(ValueError):
    """Данные не этого протокола."""


def _ч(д: bytes, м: int, n: int, порядок: str = "big") -> int:
    if м < 0 or м + n > len(д):
        raise Мало()
    return int.from_bytes(д[м:м + n], порядок)


def б16(д, м):
    return _ч(д, м, 2)


def б24(д, м):
    return _ч(д, м, 3)


def б32(д, м):
    return _ч(д, м, 4)


def б64(д, м):
    return _ч(д, м, 8)


