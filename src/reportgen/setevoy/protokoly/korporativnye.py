# -- имена NetBIOS (RFC 1001, 14.1; RFC 1002, 4.1) ---------------------------------------------------

def _nb_имя(д: bytes, м: int, начало: int, *, сжатие: bool = True):
    """Имя в кодировке NetBIOS: (показ, суффикс, место за именем).

    Первая метка — 32 буквы 'A'–'P' (по полубайту на букву), дальше метки
    области (scope). Указатель 0xC0 (как в DNS) — только назад.
    """
    метки = []
    после = None
    граница = м
    while True:
        if м >= len(д):
            raise Мало()
        дл = д[м]
        if дл == 0:
            м += 1
            break
        if дл & 0xC0 == 0xC0 and сжатие:
            if м + 1 >= len(д):
                raise Мало()
            if после is None:
                после = м + 2
            цель = начало + (((дл & 0x3F) << 8) | д[м + 1])
            if цель >= граница:
                raise _Чужое("указатель в имени NetBIOS ведёт не назад")
            м = граница = цель
            continue
        if дл & 0xC0 or (not метки and дл != 32) or len(метки) > 32:
            raise _Чужое("не имя NetBIOS")
        метки.append(_байты(д, м + 1, дл))
        м += 1 + дл
    if not метки:
        raise _Чужое("пустое имя NetBIOS")
    первая = метки[0]
    if any(not 0x41 <= б <= 0x50 for б in первая):
        raise _Чужое("первая метка имени NetBIOS — не буквы A–P")
    сырое = bytes(((первая[2 * i] - 0x41) << 4) | (первая[2 * i + 1] - 0x41) for i in range(16))
    имя = сырое[:15].rstrip(b" ").rstrip(b"\0")
    суффикс = сырое[15]
    показ = печатное(имя, 15) + f"<{суффикс:02x}>"
    if len(метки) > 1:
        показ += "." + ".".join(_текст(м_, "ascii") for м_ in метки[1:])
    return показ, суффикс, (после if после is not None else м)


# -- NBNS (RFC 1002, 4.2) ------------------------------------------------------------------------------

NBNS_ОПЕРАЦИИ = {0: "запрос имени", 5: "регистрация", 6: "освобождение", 7: "WACK",
                 8: "обновление", 9: "обновление (альт. код)", 15: "регистрация (несколько адресов)"}
NBNS_RCODE = {0: "нет ошибки", 1: "ошибка формата", 2: "сбой сервера", 3: "нет такого имени",
              4: "не поддерживается", 5: "отказано", 6: "имя занято", 7: "конфликт имён"}
NBNS_ТИПЫ = {0x01: "A", 0x02: "NS", 0x0A: "NULL", 0x20: "NB", 0x21: "NBSTAT"}


@_откат
def nbns(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    флаги = б16(д, м + 2)
    ответ, операция, rcode = флаги >> 15, (флаги >> 11) & 0xF, флаги & 0xF
    if операция not in NBNS_ОПЕРАЦИИ or флаги & 0x0060 or (not ответ and rcode):
        return False
    счётчики = [б16(д, м + 4 + 2 * i) for i in range(4)]
    if not any(счётчики) or max(счётчики) > 64:
        return False
    у = р.уровень("NBNS", "NetBIOS Name Service", м)
    у.поле("Идентификатор", "nbns.id", f"0x{б16(д, м):04x}", м, 2, б16(д, м))
    п = у.поле("Флаги", "nbns.flags", f"0x{флаги:04x}", м + 2, 2, флаги)
    у.поле("Ответ", "nbns.flags.response", ответ, м + 2, 2, родитель=п)
    у.поле("Операция", "nbns.flags.opcode", NBNS_ОПЕРАЦИИ[операция], м + 2, 2, операция, родитель=п)
    for имя, бит, ключ in (("Авторитетный", 10, "authoritative"), ("Обрезан", 9, "truncated"),
                           ("Нужна рекурсия", 8, "recdesired"), ("Рекурсия доступна", 7, "recavail"),
                           ("Широковещательный", 4, "broadcast")):
        у.поле(имя, f"nbns.flags.{ключ}", флаги >> бит & 1, м + 2, 2, родитель=п)
    у.поле("Код ответа", "nbns.flags.rcode", NBNS_RCODE.get(rcode, str(rcode)), м + 2, 2, rcode, родитель=п)
    for i, (имя, ключ) in enumerate((("Вопросов", "queries"), ("Ответов", "answers"),
                                     ("Авторитетных", "auth_rr"), ("Дополнительных", "add_rr"))):
        у.поле(имя, f"nbns.count.{ключ}", счётчики[i], м + 4 + 2 * i, 2)
    место = м + 12
    имена, адреса = [], []
    for _ in range(счётчики[0]):
        показ, _суф, после = _nb_имя(д, место, м)
        тип, класс = б16(д, после), б16(д, после + 2)
        if тип not in (0x20, 0x21) or класс != 1:
            return False
        в = у.поле(f"Вопрос: {показ}", "nbns.name", показ, место, после + 4 - место)
        у.поле("Тип", "nbns.type", NBNS_ТИПЫ[тип], после, 2, тип, родитель=в)
        у.поле("Класс", "nbns.class", "IN", после + 2, 2, класс, родитель=в)
        имена.append(показ)
        место = после + 4
    for раздел, число in (("Ответ", счётчики[1]), ("Авторитетная", счётчики[2]),
                          ("Дополнительная", счётчики[3])):
        for _ in range(число):
            место = _nbns_rr(у, д, место, м, раздел, операция, имена, адреса)
    if место != конец:
        return False
    у.длина = конец - м
    что = NBNS_ОПЕРАЦИИ[операция] + (" — ответ" if ответ else "")
    у.итог = f"{что}: {', '.join(имена[:3])}" + (f" → {', '.join(адреса[:3])}" if адреса else "")
    if ответ and rcode:
        у.итог += f" ({NBNS_RCODE.get(rcode, rcode)})"
    р.п.инфо = "NBNS " + у.итог
    return True


def _nbns_rr(у, д, место, начало, раздел, операция, имена, адреса) -> int:
    показ, _суф, после = _nb_имя(д, место, начало)
    тип, класс, ttl, дл = б16(д, после), б16(д, после + 2), б32(д, после + 4), б16(д, после + 8)
    if тип not in NBNS_ТИПЫ or класс != 1:
        raise _Чужое("тип или класс записи NBNS")
    тело = после + 10
    _байты(д, тело, дл)
    з = у.поле(f"{раздел}: {показ}, {NBNS_ТИПЫ[тип]}", "nbns.name", показ, место, тело + дл - место)
    у.поле("Тип", "nbns.type", NBNS_ТИПЫ[тип], после, 2, тип, родитель=з)
    у.поле("Класс", "nbns.class", "IN", после + 2, 2, класс, родитель=з)
    у.поле("TTL, с", "nbns.ttl", ttl, после + 4, 4, родитель=з)
    у.поле("Длина данных", "nbns.data_length", дл, после + 8, 2, родитель=з)
    if not имена:
        имена.append(показ)
    if тип == 0x20:
        if операция == 7 and дл == 2:                  # WACK: копия флагов запроса
            у.поле("Флаги запроса", "nbns.wack.flags", f"0x{б16(д, тело):04x}", тело, 2, родитель=з)
        elif дл % 6:
            raise _Чужое("длина NB не кратна 6")
        else:
            for i in range(тело, тело + дл, 6):
                nb = б16(д, i)
                адрес = ip4(д, i + 2)
                а = у.поле(f"Адрес {адрес}", "nbns.addr", адрес, i, 6, родитель=з)
                у.поле("Флаги NB", "nbns.nb_flags", f"0x{nb:04x} ({'группа' if nb >> 15 else 'уникальное'}, "
                       f"{'BPMH'[(nb >> 13) & 3]}-узел)", i, 2, nb, родитель=а)
                адреса.append(адрес)
    elif тип == 0x21 and дл:
        число = д[тело]
        if 1 + 18 * число > дл:
            raise _Чужое("NBSTAT: имён больше, чем данных")
        у.поле("Имён", "nbns.number_of_names", число, тело, 1, родитель=з)
        for i in range(тело + 1, тело + 1 + 18 * число, 18):
            имя = печатное(д[i:i + 15].rstrip(b" \0"), 15) + f"<{д[i + 15]:02x}>"
            у.поле(f"Имя {имя}", "nbns.netbios_name", имя, i, 18, родитель=з)
    elif тип == 0x01 and дл == 4:
        у.поле("Адрес", "nbns.addr", ip4(д, тело), тело, 4, родитель=з)
    return тело + дл


