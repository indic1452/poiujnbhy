PG_КЛИЕНТ = {"Q": "Query", "P": "Parse", "B": "Bind", "E": "Execute", "D": "Describe", "C": "Close",
             "S": "Sync", "H": "Flush", "X": "Terminate", "p": "PasswordMessage", "d": "CopyData",
             "c": "CopyDone", "f": "CopyFail", "F": "FunctionCall"}
