"""Канальные протоколы Cisco: ISL, DTP, VTP, UDLD, PVST+.

Открытых стандартов нет; форматы — документация Cisco и разбор Wireshark, по которому сверены места
полей, маски и значения:

* ISL (Inter-Switch Link) — packet-isl.c и packet-eth.c: кадр 802.3 с получателем 01-00-0C-00-00-xx
  или 0C-00-0C-00-00-xx; в последнем байте получателя — вид кадра (старший полубайт: 0 Ethernet,
  1 Token-Ring, 2 FDDI, 3 ATM) и «пользователь» (у Ethernet — приоритет, 2 бита); затем отправитель,
  длина, AA-AA-03, HSA (3 байта), VLAN (15 бит) и бит BPDU, индекс, резерв — всего 26 байт; дальше —
  кадр Ethernet клиента с FCS (длина из заголовка минус 12) и CRC ISL.
* DTP — packet-dtp.c: версия и TLV (вид 2 байта, длина 2 байта вместе с заголовком): 1 домен VTP
  (строка с нулём, до 32 знаков), 2 состояние транка (бит 7 — рабочее: access/trunk; 3 младших —
  заданное: on/off/desirable/auto), 3 тип транка (биты 7–5 — рабочий, 2–0 — заданный: native, ISL,
  802.1Q, negotiated), 4 отправитель (MAC).
* VTP — packet-vtp.c: версия и код (1 Summary, 2 Subset, 3 Advertisement Request, 4 Join/Prune);
  домен — длина и 32 байта; Summary: число последующих Subset, номер ревизии, IP обновившего,
  отметка времени (12 знаков ГГММДДччммсс), MD5; Subset: номер, ревизия, записи VLAN (длина,
  состояние, тип, длина имени, ISL VLAN ID, MTU, индекс 802.10, имя, выровненное до 4, и TLV);
  Advertisement Request — начальное значение; Join — первый и последний VLAN и битовая карта
  неотсечённых VLAN (старший бит — первый).
* UDLD — packet-udld.c: версия (3 бита) и код (5 бит: 1 Probe, 2 Echo, 3 Flush), флаги (RT 0x01,
  RSY 0x02), контрольная сумма, TLV (вид и длина по 2 байта, длина — с заголовком): Device ID, Port ID,
  Echo, интервалы, имя, номер.
* PVST+ — packet-bpdu.c: BPDU 802.1D/802.1w с SNAP PID 0x010B; с байта 36 — TLV (вид и длина по 2 байта),
  вид 0 «Originating VLAN» (2 байта) обязателен.
Номера PID SNAP Cisco (OUI 00-00-0C) — packet-cisco-pid.h: 0x010B PVST+, 0x0111 UDLD, 0x2003 VTP,
0x2004 DTP.
"""

from __future__ import annotations

from ..pole import ip4, mac, u16, u32
from ..razbor import ДОП_ETHERNET, ДОП_ETHERTYPE, ДОП_УРОВНИ, Разбор, ethernet, stp, данные
from .kanalnye import _конец_802_3

# -- общий признак SNAP Cisco -------------------------------------------------------------


def _snap_cisco(р: Разбор, м: int, pid: int) -> bool:
    """Перед данными — SNAP с OUI Cisco и этим PID (в LLC или Frame Relay), а не EtherType."""
    # При м < 5 срез короче пяти байт и с образцом не совпадёт.
    return (р.д[м - 5:м] == b"\x00\x00\x0c" + pid.to_bytes(2, "big") and bool(р.п.уровни)
            and р.п.уровни[-1].протокол in ("LLC", "FR"))


def _строка(б: bytes) -> str:
    return б.partition(b"\x00")[0].decode("latin-1")


# -- ISL ----------------------------------------------------------------------------------

ВИДЫ_ISL = {0: "Ethernet", 1: "Token-Ring", 2: "FDDI", 3: "ATM"}
ПРИОРИТЕТ_ISL = {0: "обычный", 1: "приоритет 1", 2: "приоритет 2", 3: "наивысший"}


def isl(р: Разбор, м: int) -> bool:
    д = р.д
    if (len(д) - м < 26 or д[м] not in (0x01, 0x0C) or д[м + 1:м + 5] != b"\x00\x0c\x00\x00"
            or u16(д, м + 12) > 1500):
        return False
    у = р.уровень("ISL", "Cisco Inter-Switch Link", м)
    вид, пользователь = д[м + 5] >> 4, д[м + 5] & 0x0F
    п = у.поле("Получатель", "isl.dst", mac(д, м), м, 6)
    у.поле("Вид кадра", "isl.type", ВИДЫ_ISL.get(вид, вид), м + 5, 1, вид, родитель=п)
    if вид == 0:
        у.поле("Приоритет", "isl.user_eth", ПРИОРИТЕТ_ISL[пользователь & 3], м + 5, 1, пользователь & 3, родитель=п)
    else:
        у.поле("Пользователь", "isl.user", пользователь, м + 5, 1, родитель=п)
    у.поле("Отправитель", "isl.src", mac(д, м + 6), м + 6, 6)
    длина = u16(д, м + 12)
    у.поле("Длина", "isl.len", длина, м + 12, 2)
    у.поле("HSA", "isl.hsa", д[м + 17:м + 20].hex(":"), м + 17, 3)
    слово = u16(д, м + 20)
    у.поле("VLAN", "isl.vlan_id", слово >> 1, м + 20, 2)
    у.поле("BPDU/CDP/VTP", "isl.bpdu", слово & 1, м + 20, 2)
    у.поле("Индекс", "isl.index", u16(д, м + 22), м + 22, 2)
    у.длина = 26
    у.итог = f"VLAN {слово >> 1}, {ВИДЫ_ISL.get(вид, f'вид {вид}')}" + (", BPDU" if слово & 1 else "")
    р.адреса(mac(д, м + 6), mac(д, м))
    р.п.инфо = "ISL " + у.итог
    if вид == 0 and (длина == 0 or длина >= 12):
        ethernet(р, м + 26)
    else:
        данные(р, м + 26, f"ISL: {ВИДЫ_ISL.get(вид, вид)}")
    return True


# -- DTP ----------------------------------------------------------------------------------

DTP_TLV = {1: "домен", 2: "состояние транка", 3: "тип транка", 4: "отправитель"}
DTP_TOS = {0: "access", 1: "trunk"}
DTP_TAS = {1: "on", 2: "off", 3: "desirable", 4: "auto"}
DTP_TOT = {1: "native", 2: "ISL", 5: "802.1Q"}
DTP_TAT = {0: "negotiated", 1: "native", 2: "ISL", 5: "802.1Q"}


def dtp(р: Разбор, м: int) -> None:
    if not _snap_cisco(р, м, 0x2004):
        данные(р, м, "EtherType 0x2004")
        return
    д = р.д
    р.нужно(м, 1)
    конец = _конец_802_3(р, len(д))
    у = р.уровень("DTP", "Dynamic Trunking Protocol", м)
    у.поле("Версия", "dtp.version", д[м], м, 1)
    место, итог = м + 1, []
    while место < конец:
        if конец - место < 4:
            р.ошибка("DTP: TLV оборван")
            break
        вид, дл = u16(д, место), u16(д, место + 2)
        п = у.поле(f"TLV {DTP_TLV.get(вид, вид)}", "dtp.tlv_type", вид, место, max(дл, 4))
        у.поле("Длина", "dtp.tlv_len", дл, место + 2, 2, родитель=п)
        if дл <= 4:
            р.ошибка("DTP: длина TLV не больше 4")
            break
        x, n = место + 4, дл - 4
        if вид == 1 and n <= 33:
            домен = _строка(д[x:x + n])
            у.поле("Домен", "dtp.domain", домен, x, n, родитель=п)
            итог.append(f"домен «{домен}»")
        elif вид == 2 and n == 1:
            рабочее, заданное = д[x] >> 7, д[x] & 7
            у.поле("Рабочее состояние", "dtp.tos", DTP_TOS[рабочее], x, 1, рабочее, родитель=п)
            у.поле("Заданное состояние", "dtp.tas", DTP_TAS.get(заданное, заданное), x, 1, заданное, родитель=п)
            итог.append(f"{DTP_TOS[рабочее]}/{DTP_TAS.get(заданное, заданное)}")
        elif вид == 3 and n == 1:
            рабочий, заданный = д[x] >> 5, д[x] & 7
            у.поле("Рабочий тип", "dtp.tot", DTP_TOT.get(рабочий, рабочий), x, 1, рабочий, родитель=п)
            у.поле("Заданный тип", "dtp.tat", DTP_TAT.get(заданный, заданный), x, 1, заданный, родитель=п)
            итог.append(f"{DTP_TOT.get(рабочий, рабочий)}/{DTP_TAT.get(заданный, заданный)}")
        elif вид == 4 and n == 6:
            у.поле("Отправитель", "dtp.senderid", mac(д, x), x, 6, родитель=п)
        elif вид in DTP_TLV:
            п.плохо = True
            р.ошибка(f"DTP: неверная длина TLV {DTP_TLV[вид]}")
        место += дл
    у.длина = место - м
    у.итог = ", ".join(итог) or "без TLV"
    р.п.инфо = "DTP " + у.итог


# -- VTP ----------------------------------------------------------------------------------

VTP_КОДЫ = {1: "Summary Advertisement", 2: "Subset Advertisement", 3: "Advertisement Request",
            4: "Join/Prune"}
VTP_ВИДЫ_VLAN = {1: "Ethernet", 2: "FDDI", 3: "TrCRF", 4: "FDDI-net", 5: "TrBRF"}
VTP_TLV_VLAN = {1: "номер кольца SR", 2: "номер моста SR", 3: "вид STP", 4: "родительский VLAN",
                5: "транслируемые VLAN", 6: "отсечение", 7: "вид моста", 8: "наибольший ARE", 9: "наибольший STE",
                10: "резервный CRF"}


def _vtp_vlan(у, д: bytes, м: int, край: int):
    """Запись VLAN в Subset Advertisement; возвращает длину записи и (ID, имя)."""
    дл, состояние, вид, дл_имени = д[м], д[м + 1], д[м + 2], д[м + 3]
    ид, mtu = u16(д, м + 4), u16(д, м + 6)
    имя = _строка(д[м + 12:м + 12 + дл_имени])
    п = у.поле(f"VLAN {ид} «{имя}»", "vtp.vlan_info", ид, м, дл)
    у.поле("Длина записи", "vtp.vlan.info_len", дл, м, 1, родитель=п)
    у.поле("Приостановлен", "vtp.vlan.status.vlan_susp", состояние & 1, м + 1, 1, родитель=п)
    у.поле("Вид", "vtp.vlan.type", VTP_ВИДЫ_VLAN.get(вид, вид), м + 2, 1, вид, родитель=п)
    у.поле("ISL VLAN ID", "vtp.vlan.isl_vlan_id", ид, м + 4, 2, родитель=п)
    у.поле("MTU", "vtp.vlan.mtu_size", mtu, м + 6, 2, родитель=п)
    у.поле("Индекс 802.10", "vtp.vlan.802_10_index", f"0x{u32(д, м + 8):08x}", м + 8, 4, u32(д, м + 8),
           родитель=п)
    выровнено = 4 * ((дл_имени + 3) // 4)
    у.поле("Имя", "vtp.vlan.vlan_name", имя, м + 12, выровнено, родитель=п)
    x = м + 12 + выровнено
    while x + 2 <= min(м + дл, край):
        вид_tlv, дл_tlv = д[x], д[x + 1]
        у.поле(f"TLV {VTP_TLV_VLAN.get(вид_tlv, вид_tlv)}", "vtp.vlan.tlvtype", вид_tlv, x, 2 + 2 * дл_tlv,
               родитель=п)
        x += 2 + 2 * дл_tlv
    return дл, ид, имя


def vtp(р: Разбор, м: int) -> None:
    if not _snap_cisco(р, м, 0x2003):
        данные(р, м, "EtherType 0x2003")
        return
    д = р.д
    р.нужно(м, 36)
    конец = _конец_802_3(р, len(д))
    у = р.уровень("VTP", "VLAN Trunking Protocol", м)
    версия, код, дл_домена = д[м], д[м + 1], д[м + 3]
    домен = _строка(д[м + 4:м + 4 + min(дл_домена, 32)])
    у.поле("Версия", "vtp.version", версия, м, 1)
    у.поле("Код", "vtp.code", VTP_КОДЫ.get(код, код), м + 1, 1, код)
    у.поле("Длина домена", "vtp.md_len", дл_домена, м + 3, 1)
    у.поле("Домен", "vtp.md", домен, м + 4, 32)
    место = м + 36
    итог = f"{VTP_КОДЫ.get(код, f'код {код}')}, домен «{домен}»"
    if код == 1:
        у.поле("Последующих Subset", "vtp.followers", д[м + 2], м + 2, 1)
        р.нужно(место, 36)
        ревизия, время = u32(д, место), д[место + 8:место + 20].decode("latin-1")
        у.поле("Ревизия", "vtp.conf_rev_num", ревизия, место, 4)
        у.поле("Обновил", "vtp.upd_id", ip4(д, место + 4), место + 4, 4)
        if len(время) == 12 and время.isdigit():
            показ = f"20{время[:2]}-{время[2:4]}-{время[4:6]} {время[6:8]}:{время[8:10]}:{время[10:]}"
        else:
            показ = время
        у.поле("Время обновления", "vtp.upd_ts", показ, место + 8, 12, время)
        у.поле("MD5", "vtp.md5_digest", д[место + 20:место + 36].hex(), место + 20, 16)
        место += 36
        итог += f", ревизия {ревизия}, обновил {ip4(д, место - 32)}"
    elif код == 2:
        у.поле("Номер", "vtp.seq_num", д[м + 2], м + 2, 1)
        р.нужно(место, 4)
        ревизия = u32(д, место)
        у.поле("Ревизия", "vtp.conf_rev_num", ревизия, место, 4)
        место += 4
        vlan = []
        while место + 12 <= конец:
            дл, ид, _ = _vtp_vlan(у, д, место, конец)
            if дл < 12:
                р.ошибка("VTP: запись VLAN короче 12 байт")
                break
            vlan.append(ид)
            место += дл
        итог += f", ревизия {ревизия}, VLAN: {', '.join(map(str, vlan)) or 'нет'}"
    elif код == 3:
        р.нужно(место, 2)
        у.поле("Начальное значение", "vtp.start_value", u16(д, место), место, 2)
        место += 2
    elif код == 4:
        р.нужно(место, 4)
        первый, последний = u16(д, место), u16(д, место + 2)
        у.поле("Первый VLAN", "vtp.pruning.first", первый, место, 2)
        у.поле("Последний VLAN", "vtp.pruning.last", последний, место + 2, 2)
        активные, ид = [], первый
        for x in range(место + 4, конец):
            for бит in range(8):
                if д[x] & (0x80 >> бит):
                    активные.append(ид)
                ид += 1
        у.поле("Неотсечённые VLAN", "vtp.pruning.active", ", ".join(map(str, активные)) or "нет",
               место + 4, конец - место - 4, активные)
        место = конец
        итог += f", VLAN {первый}–{последний}, активных {len(активные)}"
    у.длина = место - м
    у.итог = итог
    р.п.инфо = "VTP " + итог


# -- UDLD ---------------------------------------------------------------------------------

UDLD_КОДЫ = {0: "Reserved", 1: "Probe", 2: "Echo", 3: "Flush"}
UDLD_TLV = {1: "Device ID", 2: "Port ID", 3: "Echo", 4: "Message interval", 5: "Timeout interval",
            6: "Device name", 7: "Sequence number"}


def udld(р: Разбор, м: int) -> None:
    if not _snap_cisco(р, м, 0x0111):
        данные(р, м, "UDLD?")
        return
    д = р.д
    р.нужно(м, 4)
    конец = _конец_802_3(р, len(д))
    у = р.уровень("UDLD", "Unidirectional Link Detection", м)
    версия, код, флаги = д[м] >> 5, д[м] & 0x1F, д[м + 1]
    у.поле("Версия", "udld.version", версия, м, 1)
    у.поле("Код", "udld.opcode", UDLD_КОДЫ.get(код, код), м, 1, код)
    п = у.поле("Флаги", "udld.flags", f"0x{флаги:02x}", м + 1, 1, флаги)
    у.поле("RT (рекомендуемый тайм-аут)", "udld.flags.rt", флаги & 1, м + 1, 1, родитель=п)
    у.поле("RSY (пересинхронизация)", "udld.flags.rsy", (флаги >> 1) & 1, м + 1, 1, родитель=п)
    у.поле("Контрольная сумма", "udld.checksum", f"0x{u16(д, м + 2):04x}", м + 2, 2, u16(д, м + 2))
    место, сведения = м + 4, {}
    while место + 4 <= конец:
        вид, дл = u16(д, место), u16(д, место + 2)
        т = у.поле(f"TLV {UDLD_TLV.get(вид, вид)}", "udld.tlv.type", вид, место, max(дл, 4))
        у.поле("Длина", "udld.tlv.len", дл, место + 2, 2, родитель=т)
        if дл < 4:
            т.плохо = True
            р.ошибка(f"UDLD: длина TLV {дл} < 4")
            место += 4
            break
        знач = д[место + 4:место + дл]
        if вид in (1, 2, 6):
            сведения[вид] = _строка(знач)
            у.поле(UDLD_TLV[вид], {1: "udld.device_id", 2: "udld.sent_through_interface",
                                   6: "udld.device_name"}[вид], сведения[вид], место + 4, дл - 4, родитель=т)
        elif вид in (4, 5) and len(знач) == 1:
            у.поле(UDLD_TLV[вид] + ", с", f"udld.{'msg' if вид == 4 else 'timeout'}_interval", знач[0],
                   место + 4, 1, родитель=т)
        elif вид == 7 and len(знач) == 4:
            у.поле("Номер", "udld.seq_num", u32(знач, 0), место + 4, 4, родитель=т)
        elif знач:
            у.поле("Данные", "udld.data", знач.hex(), место + 4, дл - 4, родитель=т)
        место += дл
    у.длина = место - м
    у.итог = UDLD_КОДЫ.get(код, f"код {код}") + (f", {сведения[1]}" if 1 in сведения else "") \
        + (f" порт {сведения[2]}" if 2 in сведения else "")
    р.п.инфо = "UDLD " + у.итог


# -- PVST+ --------------------------------------------------------------------------------

def pvst(р: Разбор, м: int) -> None:
    if not _snap_cisco(р, м, 0x010B):
        данные(р, м, "PVST+?")
        return
    конец = _конец_802_3(р, len(р.д))
    stp(р, м)
    у = р.п.уровни[-1]
    у.протокол, у.полное = "PVST+", "Cisco Per-VLAN Spanning Tree Plus"
    д, место, vlan = р.д, м + 36, None
    while место + 4 <= конец:
        вид, дл = u16(д, место), u16(д, место + 2)
        if место + 4 + дл > конец:
            р.ошибка("PVST+: TLV оборван")
            break
        т = у.поле("TLV Originating VLAN" if вид == 0 else f"TLV {вид}", "stp.pvst.tlvtype", вид, место, 4 + дл)
        у.поле("Длина", "stp.pvst.tlvlength", дл, место + 2, 2, родитель=т)
        if вид == 0 and дл == 2:
            vlan = u16(д, место + 4)
            у.поле("Исходный VLAN", "stp.pvst.origvlan", vlan, место + 4, 2, родитель=т)
        elif вид == 0:
            т.плохо = True
            р.ошибка("PVST+: Originating VLAN — не 2 байта")
        место += 4 + дл
    if vlan is None:
        р.ошибка("PVST+: нет TLV Originating VLAN")
    у.длина = max(у.длина, место - м)
    у.итог = (f"VLAN {vlan}, " if vlan is not None else "") + у.итог
    р.п.инфо = "PVST+: " + у.итог


ДОП_ETHERNET.append(isl)
ДОП_ETHERTYPE.setdefault(0x2004, dtp)
ДОП_ETHERTYPE.setdefault(0x2003, vtp)
ДОП_ETHERTYPE.setdefault(0x0111, udld)
ДОП_ETHERTYPE.setdefault(0x010B, pvst)
for _протокол in ("ISL", "DTP", "VTP", "UDLD", "PVST+"):
    ДОП_УРОВНИ[_протокол] = "канальный"
