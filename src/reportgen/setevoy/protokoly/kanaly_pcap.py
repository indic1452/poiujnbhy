"""Каналы pcap глобальных сетей: байт направления, псевдозаголовки MTP2 и SunATM, ATM RFC 1483, ERF.

Форматы — по описаниям tcpdump.org (linktypes/LINKTYPE_*.html) и Wireshark (wiretap/pcap-common.c,
epan/dissectors/packet-erf.c, packet-mtp2.c):
  204 PPP_WITH_DIR, 205 C_HDLC_WITH_DIR, 206 FRELAY_WITH_DIR — байт направления (0 — принят этим
      узлом, иначе — передан), затем кадр PPP (RFC 1661/1662, FF 03 необязательны), Cisco HDLC
      (RFC 1547, 4.3.1) или LAPF (Q.922, 2);
  139 MTP2_WITH_PHDR — направление, признак расширенных номеров (Q.703 прил. A: 0 — нет, 1 — да,
      2 — неизвестно), номер звена (2 байта, старший первым), затем сигнальная единица без FCS;
  123 SUNATM — флаги (младшая тетрада — вид: 0 сырой, 1 LANE, 2 LLC, 3 MARS, 4 IFMP, 5 ILMI, 6 Q.2931;
      бит 0x80 — направление), VPI (1 байт), VCI (2 байта, старший первым), затем нагрузка;
  100 и 11 ATM_RFC1483 — нагрузка AAL5 с заголовком LLC/SNAP (RFC 2684);
  197 ERF — запись Endace: время (8 байт, младший первым), тип (бит 0x80 — есть расширенные
      заголовки по 8 байт), флаги, rlen, lctr, wlen (старший первым); дальше — подзаголовок по типу
      (многоканальный — 4 байта, Ethernet — 2) и кадр: HDLC/PoS — Cisco HDLC, если первый байт
      0x0F или 0x8F, иначе PPP (как ERF_HDLC_GUESS у Wireshark); Ethernet; ATM/AAL5 — 4 байта
      заголовка ячейки без HEC; IPv4/IPv6.
"""

from __future__ import annotations

from ..chtenie import КАНАЛЫ
from ..pole import u16
from ..razbor import (
    ДОП_УРОВНИ,
    КАНАЛ_В_РАЗБОРЩИК,
    Разбор,
    cisco_hdlc,
    ethernet,
    ipv4,
    ipv6,
    llc,
    ppp,
    данные,
)
from .kanalnye import fr
