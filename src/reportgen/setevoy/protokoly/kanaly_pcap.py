ВИДЫ_SUNATM = {0: "сырой", 1: "LANE", 2: "LLC", 3: "MARS", 4: "IFMP", 5: "ILMI", 6: "Q.2931"}
ТИПЫ_ERF = {1: "HDLC/PoS", 2: "Ethernet", 3: "ATM", 4: "AAL5", 5: "многоканальный HDLC",
            6: "многоканальный сырой", 7: "многоканальный ATM", 8: "многоканальный сырой канал",
            9: "многоканальный AAL5", 10: "HDLC/PoS (цвет)", 11: "Ethernet (цвет)", 12: "многоканальный AAL2",
            15: "HDLC/PoS (DSM)", 16: "Ethernet (DSM)", 17: "многоканальный HDLC/PoS (цвет)", 18: "AAL2",
            19: "HDLC/PoS (хеш)", 20: "Ethernet (хеш)", 22: "IPv4", 23: "IPv6", 24: "сырое звено",
            27: "метаданные", 48: "заполнение"}
ERF_HDLC = {1, 5, 10, 15, 17, 19}
ERF_ETHERNET = {2, 11, 16, 20}
ERF_МНОГОКАНАЛЬНЫЕ = {5, 6, 7, 8, 9, 12, 17}
ERF_ФЛАГИ = ((0x04, "переменная длина"), (0x08, "обрезана"), (0x10, "ошибка приёма"), (0x20, "ошибка DS"))


def _направление(р: Разбор, м: int, итог_ниже: str) -> None:
    у = р.уровень("Направление", "Псевдозаголовок направления (pcap)", м)
    р.нужно(м, 1)
    передан = р.д[м] != 0
    у.поле("Направление", "pcap.direction", "передан этим узлом" if передан else "принят этим узлом", м, 1,
           р.д[м])
    у.длина = 1
    у.итог = ("передан" if передан else "принят") + f" ({итог_ниже})"


def ppp_с_направлением(р: Разбор, м: int) -> None:
    _направление(р, м, "PPP")
    ppp(р, м + 1)


def chdlc_с_направлением(р: Разбор, м: int) -> None:
    _направление(р, м, "Cisco HDLC")
    cisco_hdlc(р, м + 1)


def fr_с_направлением(р: Разбор, м: int) -> None:
    _направление(р, м, "Frame Relay")
    fr(р, м + 1)


def mtp2_расширенный(р: Разбор, м: int) -> None:
    """Сигнальная единица с расширенными номерами (Q.703 прил. A, раскладка Wireshark packet-mtp2.c):
    BSN 12 бит + BIB, FSN 12 бит + FIB, LI 9 бит — по 2 байта, младший первым."""
    д = р.д
    у = р.уровень("MTP2", "Message Transfer Part Level 2 (Q.703, прил. A)", м)
    р.нужно(м, 6)
    бсн, фсн, ли = (int.from_bytes(д[м + к:м + к + 2], "little") for к in (0, 2, 4))
    bsn, bib, fsn, fib, li = бсн & 0x0FFF, бсн >> 15, фсн & 0x0FFF, фсн >> 15, ли & 0x01FF
    у.поле("BSN", "mtp2.ext.bsn", bsn, м, 2)
    у.поле("BIB", "mtp2.ext.bib", bib, м, 2)
    у.поле("FSN", "mtp2.ext.fsn", fsn, м + 2, 2)
    у.поле("FIB", "mtp2.ext.fib", fib, м + 2, 2)
    у.поле("LI", "mtp2.ext.li", li, м + 4, 2)
    у.длина = 6
    вид = "FISU" if li == 0 else ("LSSU" if li in (1, 2) else "MSU")
    у.итог = f"{вид}, BSN {bsn}/{bib}, FSN {fsn}/{fib}"
    всего = len(д) - м - 6
    if li != всего:                  # Q.703 A.2.3.3: 9 бит LI вмещают все допустимые длины (0–273)
        у.поле("", "mtp2.li_mismatch", 1, м + 4, 0)
        р.ошибка("MTP2: LI не сходится с длиной сигнальной единицы")
        у.итог += " [LI не сходится]"
        р.п.инфо = "MTP2 " + у.итог
        данные(р, м + 6, "не сигнальная единица MTP2")
        return
    р.п.инфо = "MTP2 " + у.итог
    if вид == "MSU":
        mtp3(р, м + 6, len(д))
    elif вид == "LSSU":
        у.поле("Поле состояния", "mtp2.sf", д[м + 6] & 7 if м + 6 < len(д) else 0, м + 6, li)


def mtp2_с_заголовком(р: Разбор, м: int) -> None:
    у = р.уровень("MTP2 PHDR", "Псевдозаголовок MTP2 (pcap)", м)
    р.нужно(м, 4)
    направление, прил_a, звено = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    у.поле("Направление", "mtp2.phdr.sent", направление, м, 1)
    у.поле("Расширенные номера (Q.703 прил. A)", "mtp2.phdr.annex_a_used",
           {0: "нет", 1: "да", 2: "неизвестно"}.get(прил_a, str(прил_a)), м + 1, 1, прил_a)
    у.поле("Номер звена", "mtp2.phdr.link_number", звено, м + 2, 2)
    у.длина = 4
    у.итог = f"звено {звено}, направление {направление}" + (", расширенные номера" if прил_a == 1 else "")
    if прил_a == 1:
        mtp2_расширенный(р, м + 4)
    else:
        mtp2(р, м + 4)


def sunatm(р: Разбор, м: int) -> None:
    у = р.уровень("SunATM", "Псевдозаголовок SunATM (pcap)", м)
    р.нужно(м, 4)
    флаги, vpi, vci = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    вид = флаги & 0x0F
    у.поле("Вид", "sunatm.type", ВИДЫ_SUNATM.get(вид, str(вид)), м, 1, вид)
    у.поле("Направление", "sunatm.direction", "из сети" if флаги & 0x80 else "в сеть", м, 1, флаги >> 7)
    у.поле("VPI", "atm.vpi", vpi, м + 1, 1)
    у.поле("VCI", "atm.vci", vci, м + 2, 2)
    у.длина = 4
    у.итог = f"VPI/VCI {vpi}/{vci}, {ВИДЫ_SUNATM.get(вид, f'вид {вид}')}"
    р.п.инфо = "SunATM " + у.итог
    if вид == 2 or (вид == 0 and р.д[м + 4:м + 7] == b"\xaa\xaa\x03"):
        llc(р, м + 4, len(р.д))
    elif вид == 1:
        р.нужно(м + 4, 2)
        у.поле("LECID (LANE)", "lane.lecid", u16(р.д, м + 4), м + 4, 2)
        у.длина = 6
        ethernet(р, м + 6)
    else:
        данные(р, м + 4, f"ATM {у.итог}")


def atm_rfc1483(р: Разбор, м: int) -> None:
    llc(р, м, len(р.д))


def erf(р: Разбор, м: int) -> None:
    у = р.уровень("ERF", "Endace Extensible Record Format", м)
    р.нужно(м, 16)
    д = р.д
    время = int.from_bytes(д[м:м + 8], "little")
    тип_байт, флаги, rlen, lctr, wlen = д[м + 8], д[м + 9], u16(д, м + 10), u16(д, м + 12), u16(д, м + 14)
    тип = тип_байт & 0x7F
    у.поле("Время", "erf.ts", f"{(время >> 32) + (время & 0xFFFFFFFF) / 2 ** 32:.9f} с", м, 8, время)
    у.поле("Тип записи", "erf.types.type", f"{тип} ({ТИПЫ_ERF.get(тип, 'неизвестный')})", м + 8, 1, тип)
    у.поле("Интерфейс", "erf.flags.cap", флаги & 0x03, м + 9, 1)
    for бит, имя in ERF_ФЛАГИ:
        if флаги & бит:
            у.поле(имя.capitalize(), "erf.flags", имя, м + 9, 1, флаги, плохо=бит in (0x10, 0x20))
    у.поле("Длина записи (rlen)", "erf.rlen", rlen, м + 10, 2)
    у.поле("Счётчик потерь / цвет", "erf.lctr", lctr, м + 12, 2)
    у.поле("Длина в линии (wlen)", "erf.wlen", wlen, м + 14, 2)
    место = м + 16
    расширенный = тип_байт & 0x80
    while расширенный:
        р.нужно(место, 8)
        у.поле(f"Расширенный заголовок, тип {д[место] & 0x7F}", "erf.ehdr", д[место:место + 8].hex(),
               место, 8, д[место] & 0x7F)
        расширенный = д[место] & 0x80
        место += 8
    конец_записи = min(len(д), м + rlen) if rlen >= 16 else len(д)
    if тип in ERF_МНОГОКАНАЛЬНЫЕ:
        р.нужно(место, 4)
        mc = int.from_bytes(д[место:место + 4], "big")
        у.поле("Номер канала", "erf.mchdlc.cn", mc & 0x03FF, место, 4, mc & 0x03FF)
        место += 4
    elif тип in ERF_ETHERNET:
        р.нужно(место, 2)
        у.поле("Смещение", "erf.eth.off", д[место], место, 1)
        место += 2
    у.длина = место - м
    # Запись дополнена до кратной 8: кадр — не длиннее wlen (в него входит FCS).
    конец = min(конец_записи, место + wlen) if wlen else конец_записи
    р.д = д[:конец]
    у.итог = ТИПЫ_ERF.get(тип, f"тип {тип}") + f", интерфейс {флаги & 3}"
    if флаги & 0x10:
        у.итог += ", ошибка приёма"
    р.п.инфо = "ERF " + у.итог
    if место >= конец:
        return
    if тип in ERF_HDLC:
        if д[место] in (0x0F, 0x8F):
            cisco_hdlc(р, место)
        else:
            ppp(р, место)
    elif тип in ERF_ETHERNET:
        ethernet(р, место)
    elif тип == 22:
        ipv4(р, место)
    elif тип == 23:
        ipv6(р, место)
    elif тип in (3, 4, 7, 9):
        р.нужно(место, 4)
        ячейка = int.from_bytes(д[место:место + 4], "big")
        vpi, vci = (ячейка >> 20) & 0xFF, (ячейка >> 4) & 0xFFFF
        а = р.уровень("ATM", "Заголовок ячейки ATM (без HEC)", место)
        а.поле("VPI", "atm.vpi", vpi, место, 4)
        а.поле("VCI", "atm.vci", vci, место, 4)
        а.длина = 4
        а.итог = f"VPI/VCI {vpi}/{vci}"
        if тип in (4, 9) and д[место + 4:место + 7] == b"\xaa\xaa\x03":
            llc(р, место + 4, конец)
        else:
            данные(р, место + 4, f"ATM {а.итог}", конец)
    else:
        данные(р, место, у.итог, конец)


for _номер, _канал, _разборщик in ((204, "PPP с направлением", ppp_с_направлением),
                                   (205, "Cisco HDLC с направлением", chdlc_с_направлением),
                                   (206, "Frame Relay с направлением", fr_с_направлением),
                                   (139, "MTP2 с псевдозаголовком", mtp2_с_заголовком),
                                   (123, "SunATM", sunatm), (100, "ATM RFC 1483", atm_rfc1483),
                                   (11, "ATM RFC 1483", atm_rfc1483), (197, "ERF", erf)):
    КАНАЛЫ.setdefault(_номер, _канал)
    КАНАЛ_В_РАЗБОРЩИК.setdefault(_канал, _разборщик)
for _имя in ("Направление", "MTP2 PHDR", "SunATM", "ERF", "ATM"):
    ДОП_УРОВНИ.setdefault(_имя, "канальный")
