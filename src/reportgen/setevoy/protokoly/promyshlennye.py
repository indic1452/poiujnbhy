SES_ТИПЫ = {1: "DATA TRANSFER / GIVE TOKENS", 13: "CONNECT", 14: "ACCEPT", 12: "REFUSE", 9: "FINISH",
            10: "DISCONNECT", 25: "ABORT", 26: "ABORT ACCEPT"}
SES_ПАРАМЕТРЫ = {0x05: "Connect/Accept Item", 0x14: "Session User Requirements", 0x33: "Calling Session Selector",
                 0x34: "Called Session Selector", 0xC1: "Session User Data", 0xC2: "Extended User Data"}


def _ses_заголовок(д: bytes, м: int, конец: int) -> tuple[int, int, int] | None:
    """SI, LI, начало параметров — или None."""
    if м + 2 > конец or д[м] not in SES_ТИПЫ:
        return None
    if д[м + 1] == 0xFF:
        if м + 4 > конец:
            return None
        return д[м], (д[м + 2] << 8) | д[м + 3], м + 4
    return д[м], д[м + 1], м + 2


def ses(р: Разбор, м: int, конец: int) -> bool:
    """Сеансовый уровень ISO 8327-1 (X.225, разд. 8): SPDU → представление → MMS."""
    д = р.д
    первый = _ses_заголовок(д, м, конец)
    if первый is None:
        return False
    si, li, начало = первый
    if начало + li > конец:
        return False
    второй = None
    if si == 1:
        # Базовое сцепление: GIVE TOKENS (SI 1) + DATA TRANSFER (SI 1), за ним — данные пользователя.
        if li != 0:
            return False
        второй = _ses_заголовок(д, начало + li, конец)
        if второй is None or второй[0] != 1 or второй[2] + второй[1] > конец:
            return False
        данные_с = второй[2] + второй[1]
        if данные_с >= конец:
            return False
    elif начало + li != конец:
        return False
    у = р.уровень("SES", "ISO 8327-1 Session", м)
    у.поле("Вид SPDU", "ses.type", SES_ТИПЫ[si] if si != 1 else "GIVE TOKENS", м, 1, si)
    у.поле("Длина (LI)", "ses.length", li, м + 1, начало - м - 1)
    if второй is not None:
        у.поле("Вид SPDU", "ses.type", "DATA TRANSFER", начало + li, 1, 1)
        у.поле("Длина (LI)", "ses.length", второй[1], начало + li + 1, второй[2] - начало - li - 1)
        у.длина = второй[2] + второй[1] - м
        у.итог = "DATA TRANSFER"
        if not pres(р, второй[2] + второй[1], конец):
            данные(р, второй[2] + второй[1], "данные сеанса", конец)
        return True
    у.длина = конец - м
    у.итог = SES_ТИПЫ[si]
    место, данные_польз = начало, None
    while место + 2 <= конец:
        код, дл, значение = д[место], д[место + 1], место + 2
        if дл == 0xFF and место + 4 <= конец:
            дл, значение = (д[место + 2] << 8) | д[место + 3], место + 4
        if значение + дл > конец:
            break
        у.поле(SES_ПАРАМЕТРЫ.get(код, f"Параметр 0x{код:02x}"), "ses.parameter", д[значение:значение + дл].hex(),
               место, значение + дл - место, код)
        if код == 0xC1:
            данные_польз = (значение, значение + дл)
        место = значение + дл
    р.п.инфо = "SES " + у.итог
    if данные_польз and данные_польз[0] < данные_польз[1]:
        pres(р, *данные_польз)
    return True


def _ber(д: bytes, м: int, конец: int) -> tuple[int, bool, int, int, int]:
    """BER (X.690): класс, составной, номер тега, начало значения, длина."""
    if м >= конец:
        raise Мало()
    б = д[м]
    класс, составной, номер, i = б >> 6, bool(б & 0x20), б & 0x1F, м + 1
    if номер == 0x1F:
        номер = 0
        while True:
            if i >= конец or i - м > 5:
                raise Мало()
            номер = (номер << 7) | (д[i] & 0x7F)
            i += 1
            if not д[i - 1] & 0x80:
                break
    if i >= конец:
        raise Мало()
    дл = д[i]
    i += 1
    if дл & 0x80:
        n = дл & 0x7F
        if n == 0 or n > 4:
            raise ValueError("BER: неопределённая длина")
        if i + n > конец:
            raise Мало()
        дл = int.from_bytes(д[i:i + n], "big")
        i += n
    if i + дл > конец:
        raise Мало()
    return класс, составной, номер, i, дл


def pres(р: Разбор, м: int, конец: int) -> bool:
    """Представительный уровень ISO 8823-1 (X.226, разд. 8): fully-encoded-data → PDV-list."""
    д = р.д
    try:
        класс, составной, номер, начало, дл = _ber(д, м, конец)
    except (Мало, ValueError):
        return False
    if (класс, составной) == (0, True) and номер == 17 and начало + дл == конец:
        у = р.уровень("PRES", "ISO 8823-1 Presentation", м)
        у.поле("CP-type / CPA-type", "pres.cptype", f"{дл} байт", м, конец - м)
        у.длина = конец - м
        у.итог = "установление соединения представления (ACSE и начальный MMS внутри не разбираются)"
        return True
    if (класс, составной, номер) != (1, True, 1) or начало + дл != конец:
        return False
    # Проверка PDV-list до создания уровня.
    try:
        кл, сост, ном, н_списка, дл_списка = _ber(д, начало, конец)
        if (кл, сост, ном) != (0, True, 16) or н_списка + дл_списка != конец:
            return False
        место, контекст, значение = н_списка, None, None
        while место < конец:
            кл, сост, ном, н, дл_ = _ber(д, место, конец)
            if (кл, ном) == (0, 2):
                контекст = (место, int.from_bytes(д[н:н + дл_], "big"), н + дл_ - место)
            elif кл == 2 and ном in (0, 1, 2):
                значение = (место, ном, н, н + дл_)
            место = н + дл_
    except (Мало, ValueError):
        return False
    if контекст is None or значение is None:
        return False
    у = р.уровень("PRES", "ISO 8823-1 Presentation", м)
    у.поле("fully-encoded-data", "pres.fully_encoded_data", f"{дл} байт", м, конец - м)
    у.поле("Идентификатор контекста представления", "pres.presentation_context_identifier", контекст[1],
           контекст[0], контекст[2])
    вид = {0: "single-ASN1-type", 1: "octet-aligned", 2: "arbitrary"}[значение[1]]
    у.поле("Значения", "pres.presentation_data_values", вид, значение[0], значение[3] - значение[0], значение[1])
    у.длина = значение[2] - м
    у.итог = f"контекст {контекст[1]}, {вид}"
    н, к = значение[2], значение[3]
    if значение[1] == 0 and н < к:
        if 0x60 <= д[н] <= 0x64:
            у.поле("ACSE", "pres.acse", {0x60: "AARQ", 0x61: "AARE", 0x62: "RLRQ", 0x63: "RLRE",
                                          0x64: "ABRT"}[д[н]], н, к - н, д[н])
            у.итог += ", ACSE (не разбирается)"
            данные(р, н, "ACSE", к)
            return True
        уровней = len(р.п.уровни)
        try:
            if mms(р, н, к):
                return True
        except (Мало, IndexError, ValueError):
            pass
        del р.п.уровни[уровней:]
    данные(р, н, "данные представления", к)
    return True


MMS_PDU = {0: "confirmed-RequestPDU", 1: "confirmed-ResponsePDU", 2: "confirmed-ErrorPDU", 3: "unconfirmed-PDU",
           4: "rejectPDU", 5: "cancel-RequestPDU", 6: "cancel-ResponsePDU", 7: "cancel-ErrorPDU",
           8: "initiate-RequestPDU", 9: "initiate-ResponsePDU", 10: "initiate-ErrorPDU",
           11: "conclude-RequestPDU", 12: "conclude-ResponsePDU", 13: "conclude-ErrorPDU"}
MMS_СЕРВИСЫ = {0: "status", 1: "getNameList", 2: "identify", 3: "rename", 4: "read", 5: "write",
               6: "getVariableAccessAttributes", 11: "defineNamedVariableList",
               12: "getNamedVariableListAttributes", 13: "deleteNamedVariableList",
               72: "fileOpen", 73: "fileRead", 74: "fileClose", 75: "fileRename", 76: "fileDelete",
               77: "fileDirectory"}
MMS_НЕПОДТВ = {0: "informationReport", 1: "unsolicitedStatus", 2: "eventNotification"}


def mms(р: Разбор, м: int, конец: int) -> bool:
    """MMS (ISO 9506-2): MMSpdu — выбор PDU, invokeID и сервис; остальное — деревом BER."""
    д = р.д
    try:
        класс, составной, номер, начало, дл = _ber(д, м, конец)
    except (Мало, ValueError):
        return False
    if класс != 2 or номер not in MMS_PDU or начало + дл != конец:
        return False
    простые = {5, 6, 11, 12}
    if составной == (номер in простые):
        return False
    if номер in (11, 12) and дл != 0:
        return False
    ид = None
    if номер in (0, 1, 2):
        try:
            кл, сост, ном, н, дл_ = _ber(д, начало, конец)
        except (Мало, ValueError):
            return False
        if (кл, сост, ном) != (0, False, 2) or not 1 <= дл_ <= 5:
            return False
        ид = (начало, int.from_bytes(д[н:н + дл_], "big"), н + дл_ - начало)
    у = р.уровень("MMS", "Manufacturing Message Specification (ISO 9506)", м)
    п = у.поле("PDU", "mms.pdu", MMS_PDU[номер], м, конец - м, номер)
    у.длина = конец - м
    итог = MMS_PDU[номер]
    место = начало
    if ид:
        у.поле("invokeID", "mms.invokeid", ид[1], ид[0], ид[2], родитель=п)
        итог += f", invokeID {ид[1]}"
        место = ид[0] + ид[2]
    elif номер in (5, 6):
        значение = int.from_bytes(д[начало:начало + дл], "big")
        у.поле("invokeID", "mms.invokeid", значение, начало, дл, родитель=п)
        итог += f", invokeID {значение}"
    if номер in (0, 1, 3):
        try:
            кл, сост, ном, н, дл_ = _ber(д, место, конец)
            if номер == 0 and (кл, ном) == (0, 16):             # listOfModifier
                место = н + дл_
                кл, сост, ном, н, дл_ = _ber(д, место, конец)
            if номер == 3 and (кл, ном) == (0, 16):             # Unconfirmed-PDU ::= SEQUENCE { service }
                место = н
                кл, сост, ном, н, дл_ = _ber(д, место, конец)
            if кл == 2:
                таблица = MMS_НЕПОДТВ if номер == 3 else MMS_СЕРВИСЫ
                ключ = {0: "mms.confirmedservicerequest", 1: "mms.confirmedserviceresponse",
                        3: "mms.unconfirmedservice"}[номер]
                сервис = таблица.get(ном, f"[{ном}]")
                с = у.поле(f"Сервис: {сервис}", ключ, сервис, место, н + дл_ - место, ном, родитель=п)
                итог += f", {сервис}"
                имена = []
                if сост:
                    _ber_дерево(у, д, н, н + дл_, с, 0, имена)
                if имена:
                    итог += " " + ", ".join(имена[:3]) + (" …" if len(имена) > 3 else "")
        except (Мало, ValueError):
            р.ошибка("MMS: сервис оборван или закодирован неверно")
    elif составной and место < конец:
        _ber_дерево(у, д, место, конец, п, 0, [])
    у.итог = итог
    р.п.инфо = "MMS " + итог
    return True


_BER_КЛАССЫ = ("U", "A", "", "P")
_BER_УНИВЕРСАЛЬНЫЕ = {1: "BOOLEAN", 2: "INTEGER", 3: "BIT STRING", 4: "OCTET STRING", 5: "NULL", 10: "ENUMERATED",
                      16: "SEQUENCE", 26: "VisibleString"}


def _ber_дерево(у: Уровень, д: bytes, м: int, конец: int, родитель: Поле, глубина: int, имена: list[str],
                счёт: list[int] | None = None) -> None:
    """Элементы BER деревом (не глубже 8, не больше 128); VisibleString — имена MMS."""
    счёт = счёт if счёт is not None else [0]
    while м < конец and счёт[0] < 128:
        класс, составной, номер, н, дл = _ber(д, м, конец)
        счёт[0] += 1
        тег = f"{_BER_КЛАССЫ[класс]}[{номер}]" if класс != 0 else _BER_УНИВЕРСАЛЬНЫЕ.get(номер, f"U[{номер}]")
        значение = д[н:н + дл]
        if составной:
            узел = у.поле(тег, "", f"{дл} байт", м, н + дл - м, родитель=родитель)
            if глубина < 8:
                _ber_дерево(у, д, н, н + дл, узел, глубина + 1, имена, счёт)
        elif класс == 0 and номер == 26:
            текст = значение.decode("ascii", "replace")
            имена.append(текст)
            у.поле(f"{тег}: {текст}", "mms.identifier", текст, м, н + дл - м, родитель=родитель)
        elif класс == 0 and номер in (2, 10) and 0 < дл <= 8:
            у.поле(f"{тег}: {int.from_bytes(значение, 'big', signed=True)}", "", int.from_bytes(значение, "big",
                   signed=True), м, н + дл - м, родитель=родитель)
        else:
            текст = значение.hex() if not (значение and all(32 <= б < 127 for б in значение)) else \
                f"«{значение.decode('ascii')}»"
            у.поле(f"{тег}: {текст or '—'}", "", текст, м, н + дл - м, родитель=родитель)
        м = н + дл


# == EtherNet/IP и CIP =========================================================================

ENIP_КОМАНДЫ = {0x0000: "NOP", 0x0004: "ListServices", 0x0063: "ListIdentity", 0x0064: "ListInterfaces",
                0x0065: "RegisterSession", 0x0066: "UnRegisterSession", 0x006F: "SendRRData",
                0x0070: "SendUnitData", 0x0072: "IndicateStatus", 0x0073: "Cancel"}
ENIP_СТАТУСЫ = {0x0000: "успех", 0x0001: "неверная или неподдерживаемая команда", 0x0002: "мало памяти",
                0x0003: "неверные данные", 0x0064: "неверный описатель сеанса", 0x0065: "неверная длина",
                0x0069: "неподдерживаемая версия протокола"}
CPF_ТИПЫ = {0x0000: "Null Address", 0x000C: "CIP Identity", 0x00A1: "Connected Address",
            0x00B1: "Connected Data", 0x00B2: "Unconnected Data", 0x0100: "List Services Response",
            0x8000: "Sockaddr Info O→T", 0x8001: "Sockaddr Info T→O", 0x8002: "Sequenced Address"}
CIP_СЕРВИСЫ = {0x01: "Get_Attributes_All", 0x02: "Set_Attributes_All", 0x03: "Get_Attribute_List",
               0x04: "Set_Attribute_List", 0x05: "Reset", 0x06: "Start", 0x07: "Stop", 0x08: "Create",
               0x09: "Delete", 0x0A: "Multiple_Service_Packet", 0x0E: "Get_Attribute_Single",
               0x10: "Set_Attribute_Single"}
CIP_МЕНЕДЖЕР = {0x52: "Unconnected_Send", 0x54: "Forward_Open", 0x4E: "Forward_Close",
                0x5B: "Large_Forward_Open"}
CIP_КЛАССЫ = {0x01: "Identity", 0x02: "Message Router", 0x04: "Assembly", 0x06: "Connection Manager",
              0xF5: "TCP/IP Interface", 0xF6: "Ethernet Link"}
CIP_СТАТУСЫ = {0x00: "успех", 0x01: "ошибка соединения", 0x04: "ошибка сегмента пути",
               0x05: "назначение пути неизвестно", 0x08: "сервис не поддерживается",
               0x0E: "атрибут не устанавливается", 0x14: "атрибут не поддерживается",
               0x16: "объект не существует"}


def _cpf_тиражирован(д: bytes, м: int, конец: int) -> bool:
    """CPF: число элементов и элементы ровно до конца данных."""
    if м + 2 > конец:
        return False
    число, место = д[м] | (д[м + 1] << 8), м + 2
    for _ in range(число):
        if место + 4 > конец:
            return False
        место += 4 + (д[место + 2] | (д[место + 3] << 8))
    return место == конец


def _enip_заголовок(д: bytes, м: int, конец: int, полный_нужен: bool) -> int | None:
    """Длина данных инкапсуляции, если заголовок верен (и тело — там, где оно проверяемо)."""
    if м + 24 > конец:
        return None
    команда, дл = д[м] | (д[м + 1] << 8), д[м + 2] | (д[м + 3] << 8)
    if команда not in ENIP_КОМАНДЫ or д[м + 20:м + 24] != b"\0\0\0\0":
        return None
    полный = м + 24 + дл <= конец
    if not полный:
        return None if полный_нужен else дл
    статус = int.from_bytes(д[м + 8:м + 12], "little")
    тело = м + 24
    if команда == 0x0065 and статус == 0:
        if дл != 4 or д[тело] | (д[тело + 1] << 8) != 1:
            return None
    elif команда == 0x0066 and дл != 0:
        return None
    elif команда in (0x006F, 0x0070) and статус == 0:
        if дл < 8 or not _cpf_тиражирован(д, тело + 6, тело + дл):
            return None
    elif команда in (0x0063, 0x0004, 0x0064) and дл and not _cpf_тиражирован(д, тело, тело + дл):
        return None
    return дл


def enip_tcp(р: Разбор, м: int, конец: int) -> bool:
    return _enip(р, м, конец, udp=False)


def enip_udp(р: Разбор, м: int, конец: int) -> bool:
    return _enip(р, м, конец, udp=True)


def _enip(р: Разбор, м: int, конец: int, *, udp: bool) -> bool:
    """EtherNet/IP (CIP т. 2, гл. 2): заголовок 24 байта, CPF, CIP в элементах данных."""
    д = р.д
    дл = _enip_заголовок(д, м, конец, True)
    if дл is None or (udp and м + 24 + дл != конец):
        return False
    место, итоги = м, []
    while место + 24 <= конец:
        дл = _enip_заголовок(д, место, конец, False)     # первый уже проверен целиком
        if дл is None:
            break
        итоги.append(_enip_один(р, место, min(конец, место + 24 + дл), дл))
        место += 24 + дл
    if место < конец:
        данные(р, место, "продолжение EtherNet/IP", конец)
    р.п.инфо = "ENIP " + "; ".join(итоги)
    return True


def _enip_один(р: Разбор, м: int, конец: int, дл: int) -> str:
    д = р.д
    команда = _le(д, м, 2)
    статус, сеанс = _le(д, м + 8, 4), _le(д, м + 4, 4)
    у = р.уровень("ENIP", "EtherNet/IP (инкапсуляция)", м)
    у.поле("Команда", "enip.command", f"0x{команда:04x} ({ENIP_КОМАНДЫ[команда]})", м, 2, команда)
    у.поле("Длина", "enip.length", дл, м + 2, 2)
    у.поле("Описатель сеанса", "enip.session", f"0x{сеанс:08x}", м + 4, 4, сеанс)
    у.поле("Состояние", "enip.status", f"0x{статус:08x} ({ENIP_СТАТУСЫ.get(статус, '?')})", м + 8, 4, статус,
           плохо=статус != 0)
    у.поле("Контекст отправителя", "enip.context", д[м + 12:м + 20].hex(), м + 12, 8)
    у.поле("Опции", "enip.options", 0, м + 20, 4)
    у.длина = 24
    итог = ENIP_КОМАНДЫ[команда] + (f", сеанс 0x{сеанс:08x}" if сеанс else "")
    if статус:
        итог += f", ошибка: {ENIP_СТАТУСЫ.get(статус, hex(статус))}"
    тело = м + 24
    if конец < тело + дл:
        р.ошибка("EtherNet/IP: сообщение продолжается за пределами сегмента")
    try:
        if команда == 0x0065 and дл >= 4 and тело + 4 <= конец:
            у.поле("Версия протокола", "enip.rs.version", _le(д, тело, 2), тело, 2)
            у.поле("Флаги опций", "enip.rs.flags", _le(д, тело + 2, 2), тело + 2, 2)
            у.длина += 4
        elif команда in (0x006F, 0x0070) and дл >= 8:
            у.поле("Описатель интерфейса", "enip.srrd.iface", _le(д, тело, 4, конец), тело, 4)
            у.поле("Время ожидания", "enip.timeout", _le(д, тело + 4, 2, конец), тело + 4, 2)
            у.длина += 6
            cip = _cpf(р, у, тело + 6, конец, команда)
            у.длина = конец - м
            у.итог = итог
            for начало, кон, соединённый in cip:
                уровней = len(р.п.уровни)
                try:
                    итог += ", " + _cip(р, начало, кон, соединённый)
                except (Мало, IndexError, ValueError):
                    del р.п.уровни[уровней:]
                    данные(р, начало, "CIP (оборван)", кон)
        elif команда in (0x0063, 0x0004, 0x0064) and дл >= 2:
            _cpf(р, у, тело, конец, команда)
            у.длина = конец - м
            имя = next((п.текст for п in _все_поля(у) if п.ключ == "enip.lir.name"), "")
            if имя:
                итог += f" «{имя}»"
    except Мало:
        р.ошибка("EtherNet/IP: данные команды оборваны")
    у.итог = итог
    return итог


def _все_поля(у: Уровень):
    стек = list(у.поля)
    while стек:
        п = стек.pop()
        yield п
        стек.extend(п.дети)


def _cpf(р: Разбор, у: Уровень, м: int, конец: int, команда: int) -> list[tuple[int, int, bool]]:
    """Элементы CPF; возвращает места сообщений CIP (начало, конец, «соединённое»)."""
    д = р.д
    число = _le(д, м, 2, конец)
    у.поле("Число элементов CPF", "enip.cpf.itemcount", число, м, 2)
    место, cip = м + 2, []
    for i in range(число):
        if место + 4 > конец:
            break
        тип, дл = _le(д, место, 2), _le(д, место + 2, 2)
        э = у.поле(f"Элемент {i + 1}: {CPF_ТИПЫ.get(тип, f'0x{тип:04x}')}", "enip.cpf.typeid",
                   CPF_ТИПЫ.get(тип, f"0x{тип:04x}"), место, 4 + дл, тип)
        у.поле("Длина", "enip.cpf.length", дл, место + 2, 2, родитель=э)
        н, к = место + 4, min(конец, место + 4 + дл)
        if тип == 0x00A1 and дл == 4 and к == н + 4:
            у.поле("Идентификатор соединения", "enip.cpf.cai.connid", f"0x{_le(д, н, 4):08x}", н, 4, _le(д, н, 4),
                   родитель=э)
        elif тип == 0x8002 and дл == 8 and к == н + 8:
            у.поле("Идентификатор соединения", "enip.cpf.sai.connid", f"0x{_le(д, н, 4):08x}", н, 4, _le(д, н, 4),
                   родитель=э)
            у.поле("Номер", "enip.cpf.sai.seq", _le(д, н + 4, 4), н + 4, 4, родитель=э)
        elif тип == 0x000C:
            _идентичность(у, д, н, к, э)
        elif тип == 0x00B2 and к > н and команда == 0x006F:
            cip.append((н, к, False))
        elif тип == 0x00B1 and к > н + 2 and команда == 0x0070:
            у.поле("Номер (последовательность)", "enip.cpf.cdi.seqcnt", _le(д, н, 2), н, 2, родитель=э)
            cip.append((н + 2, к, True))
        elif тип == 0x00B1 and к > н:
            у.поле("Данные ввода-вывода", "enip.cpf.cdi.data", f"{к - н} байт", н, к - н, родитель=э)
        место += 4 + дл
    return cip


def _идентичность(у: Уровень, д: bytes, м: int, конец: int, родитель: Поле) -> None:
    """Элемент CIP Identity ответа ListIdentity (CIP т. 2, гл. 2, команда ListIdentity)."""
    if м + 33 > конец:
        return
    у.поле("Версия протокола", "enip.lir.version", _le(д, м, 2), м, 2, родитель=родитель)
    у.поле("Адрес (sin_addr)", "enip.lir.sa.sinaddr", ip4(д, м + 6), м + 6, 4, родитель=родитель)
    у.поле("Порт (sin_port)", "enip.lir.sa.sinport", _be(д, м + 4, 2), м + 4, 2, родитель=родитель)
    у.поле("Производитель", "enip.lir.vendor", _le(д, м + 18, 2), м + 18, 2, родитель=родитель)
    у.поле("Тип устройства", "enip.lir.devtype", _le(д, м + 20, 2), м + 20, 2, родитель=родитель)
    у.поле("Код изделия", "enip.lir.prodcode", _le(д, м + 22, 2), м + 22, 2, родитель=родитель)
    у.поле("Ревизия", "enip.lir.revision", f"{д[м + 24]}.{д[м + 25]}", м + 24, 2, родитель=родитель)
    у.поле("Серийный номер", "enip.lir.serial", f"0x{_le(д, м + 28, 4):08x}", м + 28, 4, _le(д, м + 28, 4),
           родитель=родитель)
    дл = д[м + 32]
    if м + 33 + дл <= конец:
        имя = д[м + 33:м + 33 + дл].decode("latin-1")
        у.поле("Имя изделия", "enip.lir.name", имя, м + 32, 1 + дл, родитель=родитель)
        if м + 33 + дл < конец:
            у.поле("Состояние", "enip.lir.state", д[м + 33 + дл], м + 33 + дл, 1, родитель=родитель)


def _epath(у: Уровень, д: bytes, м: int, конец: int, родитель: Поле) -> tuple[str, int | None]:
    """EPATH (CIP т. 1, прил. C-1): логические сегменты, порт, символьный сегмент ANSI."""
    части, класс = [], None
    имена = {0: ("класс", "cip.class"), 1: ("экземпляр", "cip.instance"), 2: ("член", "cip.member"),
             3: ("точка подключения", "cip.connpoint"), 4: ("атрибут", "cip.attribute")}
    место = м
    while место < конец:
        сегмент = д[место]
        if сегмент >> 5 == 1:
            вид, формат = (сегмент >> 2) & 7, сегмент & 3
            if формат == 0:
                значение, дл = _le(д, место + 1, 1, конец), 2
            elif формат == 1:
                значение, дл = _le(д, место + 2, 2, конец), 4
            elif формат == 2:
                значение, дл = _le(д, место + 2, 4, конец), 6
            else:
                break
            подпись, ключ = имена.get(вид, (f"логический {вид}", "cip.logical"))
            if вид == 0:
                класс = значение
                текст = f"0x{значение:02x}" + (f" ({CIP_КЛАССЫ[значение]})" if значение in CIP_КЛАССЫ else "")
            else:
                текст = str(значение)
            у.поле(f"{подпись.capitalize()}: {текст}", ключ, значение, место, дл, родитель=родитель)
            части.append(f"{подпись} {текст}")
            место += дл
        elif сегмент == 0x91:
            n = _le(д, место + 1, 1, конец)
            if место + 2 + n > конец:
                raise Мало()
            символ = д[место + 2:место + 2 + n].decode("latin-1")
            у.поле(f"Символ: {символ}", "cip.symbol", символ, место, 2 + n + (n & 1), родитель=родитель)
            части.append(f"«{символ}»")
            место += 2 + n + (n & 1)
        elif сегмент >> 5 == 0 and not сегмент & 0x10 and сегмент & 15 != 15:
            адрес = _le(д, место + 1, 1, конец)
            у.поле(f"Порт {сегмент & 15}, адрес {адрес}", "cip.port", сегмент & 15, место, 2, родитель=родитель)
            части.append(f"порт {сегмент & 15}/{адрес}")
            место += 2
        else:
            у.поле("Сегмент пути (не разбирается)", "cip.path.segment", д[место:конец].hex(), место, конец - место,
                   родитель=родитель)
            break
    return ", ".join(части), класс


def _cip(р: Разбор, м: int, конец: int, соединённый: bool) -> str:
    """Запрос/ответ маршрутизатора сообщений CIP (CIP т. 1, гл. 2: формат запроса и ответа Message Router)."""
    д = р.д
    сервис = _le(д, м, 1, конец)
    ответ, код = сервис >> 7, сервис & 0x7F
    у = р.уровень("CIP", "Common Industrial Protocol", м)
    у.длина = конец - м
    if ответ:
        имя = CIP_СЕРВИСЫ.get(код) or CIP_МЕНЕДЖЕР.get(код) or f"0x{код:02x}"
        у.поле("Сервис", "cip.sc", f"0x{код:02x} ({имя}), ответ", м, 1, код)
        у.поле("Ответ", "cip.rr", 1, м, 1)
        статус, доп = _le(д, м + 2, 1, конец), _le(д, м + 3, 1, конец)
        у.поле("Общее состояние", "cip.genstat", f"0x{статус:02x} ({CIP_СТАТУСЫ.get(статус, '?')})", м + 2, 1, статус,
               плохо=статус != 0)
        у.поле("Слов дополнительного состояния", "cip.addstat_size", доп, м + 3, 1)
        if доп:
            у.поле("Дополнительное состояние", "cip.ext_status", д[м + 4:м + 4 + 2 * доп].hex(), м + 4, 2 * доп)
        начало = м + 4 + 2 * доп
        if начало < конец:
            у.поле("Данные ответа", "cip.data", f"{конец - начало} байт: {печатное(д[начало:конец], 40)}", начало,
                   конец - начало)
        у.итог = f"{имя}: {CIP_СТАТУСЫ.get(статус, hex(статус))}"
        return у.итог
    слов = _le(д, м + 1, 1, конец)
    if м + 2 + 2 * слов > конец:
        raise Мало()
    путь = у.поле("Путь запроса", "cip.path", д[м + 2:м + 2 + 2 * слов].hex(), м + 1, 1 + 2 * слов)
    у.поле("Размер пути (слов)", "cip.request_path_size", слов, м + 1, 1, родитель=путь)
    описание, класс = _epath(у, д, м + 2, м + 2 + 2 * слов, путь)
    путь.текст = описание or путь.текст
    имя = CIP_СЕРВИСЫ.get(код) or (CIP_МЕНЕДЖЕР.get(код) if класс == 6 else None) or f"0x{код:02x}"
    у.поля.insert(0, у.поля.pop(у.поля.index(путь)))
    у.поля.insert(0, Поле("Сервис", "cip.sc", f"0x{код:02x} ({имя})", код, м, 1))
    начало = м + 2 + 2 * слов
    итог = f"{имя} ({описание})" if описание else имя
    if код == 0x52 and класс == 6 and начало + 4 <= конец:
        дл = _le(д, начало + 2, 2, конец)
        у.поле("Приоритет / тик", "cip.cm.priority", д[начало], начало, 1)
        у.поле("Тиков ожидания", "cip.cm.timeout_tick", д[начало + 1], начало + 1, 1)
        у.поле("Размер вложенного запроса", "cip.cm.msg_req_size", дл, начало + 2, 2)
        у.итог = итог
        if начало + 4 + дл <= конец and дл >= 2:
            итог += " → " + _cip(р, начало + 4, начало + 4 + дл, соединённый)
        return итог
    if начало < конец:
        у.поле("Данные запроса", "cip.data", f"{конец - начало} байт", начало, конец - начало)
    у.итог = итог
    return итог


def cip_io(р: Разбор, м: int, конец: int) -> bool:
    """UDP 2222: ввод-вывод CIP (класс 0/1) — CPF без заголовка инкапсуляции:
    ровно два элемента, адрес с номером (0x8002, 8 байт) и соединённые данные (0x00B1)."""
    д = р.д
    if конец - м < 18 or _le(д, м, 2) != 2 or _le(д, м + 2, 2) != 0x8002 or _le(д, м + 4, 2) != 8:
        return False
    if _le(д, м + 14, 2) != 0x00B1 or м + 18 + _le(д, м + 16, 2) != конец:
        return False
    у = р.уровень("ENIP", "EtherNet/IP ввод-вывод (CPF)", м)
    _cpf(р, у, м, конец, 0)
    у.длина = конец - м
    соединение, номер = _le(д, м + 6, 4), _le(д, м + 10, 4)
    у.итог = f"ввод-вывод, соединение 0x{соединение:08x}, номер {номер}, данных {конец - м - 18} байт"
    р.п.инфо = "ENIP " + у.итог
    return True


