def _le(д: bytes, м: int, n: int, конец: int | None = None) -> int:
    """Целое «от младшего» с проверкой границы (Мало, а не struct.error)."""
    предел = len(д) if конец is None else min(конец, len(д))
    if м < 0 or м + n > предел:
        raise Мало()
    return int.from_bytes(д[м:м + n], "little")


def _be(д: bytes, м: int, n: int, конец: int | None = None) -> int:
    предел = len(д) if конец is None else min(конец, len(д))
    if м < 0 or м + n > предел:
        raise Мало()
    return int.from_bytes(д[м:м + n], "big")


def _откат(р: Разбор, уровней: int) -> bool:
    """Данные не наши: убрать всё, что успели положить, и сказать «не моё»."""
    del р.п.уровни[уровней:]
    return False


def _текст(данные_: bytes) -> str:
    return данные_.decode("utf-8", "replace")


# == DNP3 (IEEE 1815) =======================================================================

def _таблица_crc_dnp() -> list[int]:
    """CRC-16 DNP: многочлен 0x3D65, отражённый (0xA6BC), начальное 0, итог инвертируется."""
    таблица = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ 0xA6BC if c & 1 else c >> 1
        таблица.append(c)
    return таблица


_ТАБЛИЦА_CRC_DNP = _таблица_crc_dnp()


def crc_dnp(данные_: bytes) -> int:
    crc = 0
    for б in данные_:
        crc = (crc >> 8) ^ _ТАБЛИЦА_CRC_DNP[(crc ^ б) & 0xFF]
    return ~crc & 0xFFFF


