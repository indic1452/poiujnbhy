def _ua_строка(д: bytes, м: int, конец: int) -> tuple[bytes | None, int]:
    """String/ByteString (Part 6, 5.2.2.4): Int32 длина (−1 — null) и байты."""
    дл = int.from_bytes(д[м:м + 4], "little", signed=True) if м + 4 <= конец else None
    if дл is None or дл < -1 or м + 4 + max(дл, 0) > конец:
        raise Мало()
    if дл == -1:
        return None, м + 4
    return bytes(д[м + 4:м + 4 + дл]), м + 4 + дл


def _ua_сообщение(д: bytes, м: int, конец: int, строго: bool) -> int | None:
    """Размер сообщения, если заголовок верен и (когда сообщение целиком) тело сходится."""
    if м + 8 > конец:
        return None
    тип, признак = bytes(д[м:м + 3]), д[м + 3]
    if тип not in OPCUA_ТИПЫ or признак not in b"FCA":
        return None
    if тип != b"MSG" and признак != ord("F"):
        return None
    размер = _le(д, м + 4, 4)
    if размер < 8 or размер > 0x1000000:
        return None
    if м + размер > конец:
        if строго or тип in (b"HEL", b"ACK", b"ERR", b"RHE", b"CLO"):
            return None
        return размер if размер >= 24 else None
    к = м + размер
    try:
        if тип == b"HEL":
            if размер < 32:
                return None
            url, после = _ua_строка(д, м + 28, к)
            return размер if после == к and (url is None or len(url) <= 4096) else None
        if тип == b"ACK":
            return размер if размер == 28 else None
        if тип == b"ERR":
            if размер < 16:
                return None
            return размер if _ua_строка(д, м + 12, к)[1] == к else None
        if тип == b"RHE":
            после = _ua_строка(д, м + 8, к)[1]
            return размер if _ua_строка(д, после, к)[1] == к else None
        if тип == b"OPN":
            политика, после = _ua_строка(д, м + 12, к)
            _, после = _ua_строка(д, после, к)
            _, после = _ua_строка(д, после, к)
            return размер if после + 8 <= к and (политика or b"").startswith(b"http") else None
        return размер if размер >= 24 else None
    except Мало:
        return None


def opcua(р: Разбор, м: int, конец: int, *, строго: bool = False) -> bool:
    """OPC UA TCP (IEC 62541-6, 7.1): сообщения подряд; при угадывании — только целиком."""
    д = р.д
    место = м
    while место < конец:
        размер = _ua_сообщение(д, место, конец, строго)
        if размер is None:
            if место == м or строго:
                return False
            break
        место += размер
    у = р.уровень("OPCUA", "OPC UA Binary", м)
    итоги, место = [], м
    while место < конец:
        размер = _ua_сообщение(д, место, конец, False)
        if размер is None:
            у.поле("Продолжение / лишние байты", "opcua.trailing", f"{конец - место} байт", место, конец - место)
            break
        итоги.append(_ua_одно(р, у, место, min(конец, место + размер), размер))
        место += размер
    у.длина = min(место, конец) - м
    у.итог = "; ".join(итоги)
    р.п.инфо = "OPC UA " + у.итог
    return True


def _ua_одно(р: Разбор, у: Уровень, м: int, конец: int, размер: int) -> str:
    д = р.д
    тип = bytes(д[м:м + 3])
    имя = OPCUA_ТИПЫ[тип]
    с = у.поле(f"{имя} ({тип.decode()}{chr(д[м + 3])}), {размер} байт", "opcua.transport", имя, м, конец - м)
    у.поле("Тип сообщения", "opcua.transport.type", тип.decode(), м, 3, родитель=с)
    у.поле("Признак куска", "opcua.transport.chunk", chr(д[м + 3]), м + 3, 1, родитель=с)
    у.поле("Размер", "opcua.transport.size", размер, м + 4, 4, родитель=с)
    итог = имя
    if конец < м + размер:
        р.ошибка("OPC UA: сообщение продолжается за пределами сегмента")
        с.текст += " [продолжение в следующем сегменте]"
    try:
        if тип in (b"HEL", b"ACK"):
            for i, (подпись, ключ) in enumerate((("Версия протокола", "ver"), ("Буфер приёма", "rbs"),
                                                  ("Буфер передачи", "sbs"), ("Наибольшее сообщение", "mms"),
                                                  ("Наибольшее число кусков", "mcc"))):
                у.поле(подпись, f"opcua.transport.{ключ}", _le(д, м + 8 + 4 * i, 4, конец), м + 8 + 4 * i, 4,
                       родитель=с)
            if тип == b"HEL":
                url, после = _ua_строка(д, м + 28, конец)
                текст = _текст(url) if url is not None else "(null)"
                у.поле("Адрес конечной точки", "opcua.transport.endpoint", текст, м + 28, после - м - 28, родитель=с)
                итог += f" {текст}"
        elif тип == b"ERR":
            код = _le(д, м + 8, 4, конец)
            у.поле("Ошибка (StatusCode)", "opcua.transport.error", f"0x{код:08x}", м + 8, 4, код, родитель=с)
            причина, после = _ua_строка(д, м + 12, конец)
            у.поле("Причина", "opcua.transport.reason", _текст(причина or b""), м + 12, после - м - 12, родитель=с)
            итог += f" 0x{код:08x}"
        elif тип == b"RHE":
            сервер, после = _ua_строка(д, м + 8, конец)
            у.поле("URI сервера", "opcua.transport.server_uri", _текст(сервер or b""), м + 8, после - м - 8, родитель=с)
            адрес, после2 = _ua_строка(д, после, конец)
            у.поле("Адрес конечной точки", "opcua.transport.endpoint", _текст(адрес or b""), после, после2 - после,
                   родитель=с)
        else:
            канал = _le(д, м + 8, 4, конец)
            у.поле("Безопасный канал", "opcua.transport.scid", канал, м + 8, 4, родитель=с)
            итог += f", канал {канал}"
            место, открыто = м + 12, True
            if тип == b"OPN":
                политика, после = _ua_строка(д, место, конец)
                текст = _текст(политика or b"")
                у.поле("Политика безопасности", "opcua.transport.spu", текст, место, после - место, родитель=с)
                сертификат, после2 = _ua_строка(д, после, конец)
                у.поле("Сертификат отправителя", "opcua.transport.scert",
                       f"{len(сертификат)} байт" if сертификат is not None else "(null)", после, после2 - после,
                       родитель=с)
                отпечаток, после3 = _ua_строка(д, после2, конец)
                у.поле("Отпечаток сертификата получателя", "opcua.transport.rcthumb",
                       отпечаток.hex() if отпечаток else "(null)", после2, после3 - после2, родитель=с)
                место, открыто = после3, текст == OPCUA_БЕЗ_ЗАЩИТЫ
            else:
                у.поле("Идентификатор маркера", "opcua.security.tokenid", _le(д, место, 4, конец), место, 4, родитель=с)
                место += 4
            if not открыто:
                у.поле("Тело", "opcua.encrypted", "зашифровано", место, конец - место, родитель=с)
                return итог + ", зашифровано"
            у.поле("Номер последовательности", "opcua.security.seq", _le(д, место, 4, конец), место, 4, родитель=с)
            у.поле("Идентификатор запроса", "opcua.security.rqid", _le(д, место + 4, 4, конец), место + 4, 4,
                   родитель=с)
            сервис = _ua_nodeid(д, место + 8, конец)
            if сервис is not None and сервис[0] in OPCUA_СЕРВИСЫ:
                у.поле("Тип тела (NodeId)", "opcua.servicenodeid.numeric",
                       f"i={сервис[0]} ({OPCUA_СЕРВИСЫ[сервис[0]]})", место + 8, сервис[1], сервис[0], родитель=с)
                итог += f", {OPCUA_СЕРВИСЫ[сервис[0]]}"
            else:
                у.поле("Тело", "opcua.body", "не распознано (возможно, зашифровано)", место + 8,
                       max(0, конец - место - 8), родитель=с)
    except Мало:
        р.ошибка("OPC UA: сообщение оборвано")
    return итог


def _ua_nodeid(д: bytes, м: int, конец: int) -> tuple[int, int] | None:
    """Числовой NodeId в пространстве 0 (Part 6, 5.2.2.9): (идентификатор, длина кодировки)."""
    if м >= конец:
        return None
    вид = д[м]
    if вид == 0x00 and м + 2 <= конец:
        return д[м + 1], 2
    if вид == 0x01 and м + 4 <= конец and д[м + 1] == 0:
        return д[м + 2] | (д[м + 3] << 8), 4
    if вид == 0x02 and м + 7 <= конец and д[м + 1] == д[м + 2] == 0:
        return int.from_bytes(д[м + 3:м + 7], "little"), 7
    return None


