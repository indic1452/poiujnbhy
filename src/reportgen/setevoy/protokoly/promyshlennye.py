def s7comm(р: Разбор, м: int, конец: int) -> bool:
    """S7comm: заголовок 10/12 байт; длины параметров и данных ровно до конца TPDU."""
    д = р.д
    if м + 10 > конец or д[м] != 0x32 or д[м + 1] not in S7_ROSCTR:
        return False
    rosctr = д[м + 1]
    заголовок = 12 if rosctr in (2, 3) else 10
    парам, дан = _be(д, м + 6, 2), _be(д, м + 8, 2)
    if м + заголовок + парам + дан != конец:
        return False
    у = р.уровень("S7comm", "S7 Communication", м)
    у.поле("Идентификатор протокола", "s7comm.header.protid", "0x32", м, 1, 0x32)
    у.поле("ROSCTR", "s7comm.header.rosctr", f"{rosctr} ({S7_ROSCTR[rosctr]})", м + 1, 1, rosctr)
    у.поле("Резерв (избыточность)", "s7comm.header.redid", f"0x{_be(д, м + 2, 2):04x}", м + 2, 2, _be(д, м + 2, 2))
    ссылка = _be(д, м + 4, 2)
    у.поле("Ссылка PDU", "s7comm.header.pduref", ссылка, м + 4, 2)
    у.поле("Длина параметров", "s7comm.header.parlg", парам, м + 6, 2)
    у.поле("Длина данных", "s7comm.header.datlg", дан, м + 8, 2)
    итог = S7_ROSCTR[rosctr]
    if заголовок == 12:
        у.поле("Класс ошибки", "s7comm.header.errcls", д[м + 10], м + 10, 1)
        у.поле("Код ошибки", "s7comm.header.errcod", д[м + 11], м + 11, 1)
        if д[м + 10] or д[м + 11]:
            итог += f", ошибка 0x{д[м + 10]:02x}{д[м + 11]:02x}"
    п = м + заголовок
    у.длина = конец - м
    if парам and rosctr != 7:
        функция = д[п]
        имя = S7_ФУНКЦИИ.get(функция, f"0x{функция:02x}")
        пп = у.поле("Параметры", "s7comm.param", имя, п, парам)
        у.поле("Функция", "s7comm.param.func", f"0x{функция:02x} ({имя})", п, 1, функция, родитель=пп)
        итог += f", {имя}"
        if функция == 0xF0 and парам >= 8:
            у.поле("Max AmQ (вызывающий)", "s7comm.param.maxamq_calling", _be(д, п + 2, 2), п + 2, 2, родитель=пп)
            у.поле("Max AmQ (вызываемый)", "s7comm.param.maxamq_called", _be(д, п + 4, 2), п + 4, 2, родитель=пп)
            у.поле("Длина PDU", "s7comm.param.neg_pdu_length", _be(д, п + 6, 2), п + 6, 2, родитель=пп)
            итог += f", PDU {_be(д, п + 6, 2)}"
        elif функция in (0x04, 0x05) and парам >= 2:
            число = д[п + 1]
            у.поле("Число элементов", "s7comm.param.itemcount", число, п + 1, 1, родитель=пп)
            итог += f", элементов {число}"
            if rosctr == 1:
                место = п + 2
                for i in range(число):
                    if место + 2 > п + парам or д[место] != 0x12:
                        break
                    дл = д[место + 1]
                    if дл == 10 and д[место + 2] == 0x10 and место + 12 <= п + парам:
                        область, db = д[место + 8], _be(д, место + 6, 2)
                        адрес = _be(д, место + 9, 3)
                        имя_о = S7_ОБЛАСТИ.get(область, f"0x{область:02x}")
                        текст = (f"{имя_о}" + (f" {db}" if область == 0x84 else "")
                                 + f", {адрес >> 3}.{адрес & 7}, {_be(д, место + 4, 2)} ед. (размер {д[место + 3]})")
                        э = у.поле(f"Элемент {i + 1}: {текст}", "s7comm.param.item", текст, место, 2 + дл, родитель=пп)
                        у.поле("Область", "s7comm.param.item.area", имя_о, место + 8, 1, область, родитель=э)
                        у.поле("Номер DB", "s7comm.param.item.db", db, место + 6, 2, родитель=э)
                        у.поле("Адрес (байт.бит)", "s7comm.param.item.address", f"{адрес >> 3}.{адрес & 7}",
                               место + 9, 3, родитель=э)
                        у.поле("Количество", "s7comm.param.item.length", _be(д, место + 4, 2), место + 4, 2,
                               родитель=э)
                    else:
                        у.поле(f"Элемент {i + 1}", "s7comm.param.item", д[место:место + 2 + дл].hex(), место, 2 + дл,
                               родитель=пп)
                    место += 2 + дл
    elif парам:
        у.поле("Параметры Userdata", "s7comm.param", д[п:п + парам].hex(), п, парам)
        итог += ", служебные данные"
    if дан:
        у.поле("Данные", "s7comm.data", f"{дан} байт", п + парам, дан)
    у.итог = f"{итог}, ссылка {ссылка}"
    р.п.инфо = "S7comm " + у.итог
    return True


