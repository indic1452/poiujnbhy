_МЕГАКО = re.compile(rb"\s*(?:(?:Authentication|AU)\s*=\s*[^\s]+\s+)?(MEGACO|!)/(\d{1,2})\s+"
                     rb"(\[[0-9A-Fa-f.:]+\](?::\d+)?|<[^>\s]+>(?::\d+)?|MTP\{[0-9A-Fa-f]+\}|[A-Za-z][\w./-]*)",
                     re.I)
_МЕГАКО_ТОКЕН = re.compile(rb"((?:[OW]-){0,2})([A-Za-z]+)\s*=\s*([^\s{},\"]+)")
МЕГАКО_ТРАНЗАКЦИИ = {"transaction": "запрос", "t": "запрос", "reply": "ответ", "p": "ответ",
                     "pending": "в работе", "pn": "в работе", "transactionresponseack": "подтверждение ответа",
                     "k": "подтверждение ответа", "error": "ошибка", "er": "ошибка"}
МЕГАКО_КОМАНДЫ = {"add": "Add", "a": "Add", "modify": "Modify", "mf": "Modify", "subtract": "Subtract",
                  "s": "Subtract", "move": "Move", "mv": "Move", "auditvalue": "AuditValue", "av": "AuditValue",
                  "auditcapability": "AuditCapability", "ac": "AuditCapability", "notify": "Notify", "n": "Notify",
                  "servicechange": "ServiceChange", "sc": "ServiceChange", "error": "Error", "er": "Error"}


def megaco_текст(р: Разбор, м: int, конец: int) -> bool:
    """Megaco, текстовое кодирование (RFC 3525, прил. B): версия, mId, транзакции,
    контексты и команды — по уровню вложенности скобок."""
    д = р.д
    сов = _МЕГАКО.match(д, м, конец)
    if not сов:
        return False
    тело = д[сов.end():конец]
    if тело and not тело[:1].isspace():
        return False
    # Структура: токены транзакций на верхнем уровне, скобки уравновешены.
    записи, глубина, место = [], 0, сов.end()
    while место < конец:
        б = д[место]
        if б == 0x7B:
            глубина += 1
        elif б == 0x7D:
            глубина -= 1
            if глубина < 0:
                return False
        elif б == 0x22:                                  # строка в кавычках — внутрь не смотрим
            закрыта = д.find(b"\"", место + 1, конец)
            if закрыта < 0:
                return False
            место = закрыта
        elif глубина <= 2 and (место == сов.end() or not chr(д[место - 1]).isalnum()) and chr(б).isalpha():
            т = _МЕГАКО_ТОКЕН.match(д, место, конец)
            if т:
                записи.append((глубина, т))
                место = т.end()
                continue
        место += 1
    верхние = [т for г, т in записи if г == 0 and т.group(2).decode().lower() in МЕГАКО_ТРАНЗАКЦИИ]
    if глубина != 0 or not верхние:
        return False
    у = р.уровень("MEGACO", "H.248 / Megaco (текст)", м)
    у.поле("Версия", "megaco.version", int(сов.group(2)), сов.start(1), сов.end(2) - сов.start(1))
    mid = сов.group(3).decode("utf-8", "replace")
    у.поле("Идентификатор (mId)", "megaco.mid", mid, сов.start(3), len(сов.group(3)))
    итоги, транзакция, контекст = [], None, None
    for г, т in записи:
        токен = т.group(2).decode().lower()
        значение = т.group(3).decode("utf-8", "replace")
        if г == 0 and токен in МЕГАКО_ТРАНЗАКЦИИ:
            вид = МЕГАКО_ТРАНЗАКЦИИ[токен]
            транзакция = у.поле(f"Транзакция ({вид}) {значение}", "megaco.transid", значение, т.start(),
                                т.end() - т.start())
            у.поле("Вид", "megaco.transaction", вид, т.start(2), len(т.group(2)), родитель=транзакция)
            итоги.append(f"{вид} {значение}")
            контекст = None
        elif г == 1 and токен in ("context", "c") and транзакция is not None:
            контекст = у.поле(f"Контекст {значение}", "megaco.context", значение, т.start(), т.end() - т.start(),
                              родитель=транзакция)
            итоги[-1] += f", контекст {значение}"
        elif г == 2 and токен in МЕГАКО_КОМАНДЫ and (контекст or транзакция) is not None:
            команда = МЕГАКО_КОМАНДЫ[токен]
            к = у.поле(f"{т.group(1).decode()}{команда} = {значение}", "megaco.command", команда, т.start(),
                       т.end() - т.start(), родитель=контекст or транзакция)
            у.поле("Окончание (terminationID)", "megaco.termid", значение, т.start(3), len(т.group(3)), родитель=к)
            итоги[-1] += f", {команда} {значение}"
    у.длина = конец - м
    у.итог = f"{mid}: " + "; ".join(итоги)
    р.п.инфо = "MEGACO " + у.итог
    return True


def h248_двоичный(р: Разбор, м: int, конец: int) -> bool:
    """H.248 двоичное (прил. A, ASN.1 BER) — только опознание: MegacoMessage ::=
    SEQUENCE { authHeader [0] OPTIONAL, mess [1] Message { version [0], mId [1], … } }."""
    д = р.д
    try:
        кл, сост, ном, н, дл = _ber(д, м, конец)
        if (кл, сост, ном) != (0, True, 16) or н + дл != конец:
            return False
        кл, сост, ном, н2, дл2 = _ber(д, н, конец)
        if (кл, сост, ном) == (2, True, 0):
            кл, сост, ном, н2, дл2 = _ber(д, н2 + дл2, конец)
        if (кл, сост, ном) != (2, True, 1) or н2 + дл2 != конец:
            return False
        кл, сост, ном, нв, длв = _ber(д, н2, конец)
        if (кл, сост, ном) != (2, False, 0) or длв != 1 or not 1 <= д[нв] <= 3:
            return False
        кл, сост, ном, нм, длм = _ber(д, нв + 1, конец)
        if (кл, сост, ном) != (2, True, 1):
            return False
    except (Мало, ValueError):
        return False
    у = р.уровень("H.248", "H.248 / Megaco (двоичное, только опознание)", м)
    у.поле("Версия", "h248.version", д[нв], нв - 2, 3)
    у.поле("mId", "h248.mid", д[нм:нм + длм].hex(), нм - 2, длм + 2)
    у.поле("Сообщение", "h248.message", f"{конец - м} байт (ASN.1 BER — не разбирается)", м, конец - м)
    у.длина = конец - м
    у.итог = f"версия {д[нв]}, двоичное кодирование"
    р.п.инфо = "H.248 " + у.итог
    return True


def megaco_udp(р: Разбор, м: int, конец: int) -> bool:
    return megaco_текст(р, м, конец) or h248_двоичный(р, м, конец)


