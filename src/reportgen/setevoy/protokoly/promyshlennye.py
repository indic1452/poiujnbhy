#: Биты первого байта APDU, которые у данного типа зарезервированы (должны быть нулями).
APDU_РЕЗЕРВ = {0: 0x01, 1: 0x0F, 2: 0x0F, 3: 0x03, 4: 0x0C, 5: 0x0F, 6: 0x0F, 7: 0x0E}
