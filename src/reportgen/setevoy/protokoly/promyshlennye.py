SDP_СТРОКИ = {"v": ("Версия", "sdp.version"), "o": ("Источник (o=)", "sdp.owner"),
              "s": ("Имя сеанса", "sdp.session_name"), "i": ("Сведения", "sdp.session_info"),
              "u": ("URI", "sdp.uri"), "e": ("Почта", "sdp.email"), "p": ("Телефон", "sdp.phone"),
              "c": ("Подключение (c=)", "sdp.connection_info"), "b": ("Полоса", "sdp.bandwidth"),
              "t": ("Время (t=)", "sdp.time"), "r": ("Повтор", "sdp.repeat_time"),
              "z": ("Часовой пояс", "sdp.timezone"),
              "k": ("Ключ", "sdp.encryption_key"), "a": ("Атрибут", "sdp.session_attr"),
              "m": ("Поток (m=)", "sdp.media")}
_SDP_СТРОКА = re.compile(rb"([a-z])=([\x20-\x7e\x80-\xff\t]*)")
#: Кому отдать описания потоков разобранного SDP: функция(р, [{"вид", "порт", "протокол", "форматы",
#: "адрес", "rtpmap": {тип: "кодировка/частота"}}]) — так модуль media узнаёт RTP и T.38 по адресу и порту.
SDP_ОПИСАНИЯ: list[Callable] = []


def sdp(р: Разбор, м: int, конец: int) -> bool:
    """SDP (RFC 8866, разд. 5): строки «x=значение» деревом; m= — родитель своих строк."""
    д = р.д
    if д[м:м + 3] != b"v=0":
        return False
    строки = [(место, с) for место, с in _строки(д, м, конец)]
    while строки and not строки[-1][1]:
        строки.pop()
    if not строки or any(not _SDP_СТРОКА.fullmatch(с) or chr(с[0]) not in SDP_СТРОКИ for _, с in строки):
        return False
    # Одной «v=0» мало: описание сеанса несёт источник (o=) или поток (m=); короткие
    # SDP в MGCP (так в примерах RFC 3435) бывают без o=, но поток в них есть.
    if not any(с[:2] in (b"o=", b"m=") for _, с in строки):
        return False
    у = р.уровень("SDP", "Session Description Protocol", м)
    поток, итог_потоки, адрес = None, [], ""
    описания: list = []
    for место, строка in строки:
        буква, значение = chr(строка[0]), строка[2:].decode("utf-8", "replace")
        имя, ключ = SDP_СТРОКИ[буква]
        if буква == "a" and поток is not None:
            ключ = "sdp.media_attr"
        if буква == "i" and поток is not None:
            ключ = "sdp.media_title"
        родитель = поток if буква != "m" else None
        п = у.поле(f"{имя}: {значение}", ключ, значение, место, len(строка), родитель=родитель)
        н = место + 2
        # Части значения с их местом: байтовые смещения (значение может быть не ASCII).
        части = [(н + с.start(), с.group().decode("utf-8", "replace"), len(с.group()))
                 for с in re.finditer(rb"\S+", строка[2:])]
        if буква == "m":
            поток = п
            for подпись, ключ_ч, (где, часть, дл) in zip(("Вид", "Порт", "Протокол"),
                                                         ("sdp.media.media", "sdp.media.port", "sdp.media.proto"),
                                                         части[:3], strict=False):
                у.поле(подпись, ключ_ч, int(часть) if часть.isdigit() else часть, где, дл, родитель=п)
            for где, формат, дл in части[3:]:
                у.поле("Формат", "sdp.media.format", формат, где, дл, родитель=п)
            итог_потоки.append(" ".join(ч for _, ч, _ in части[:2]))
            if len(части) >= 3 and части[1][1].isdigit():
                описания.append({"вид": части[0][1], "порт": int(части[1][1]), "протокол": части[2][1],
                                 "форматы": [ч for _, ч, _ in части[3:]], "адрес": None, "rtpmap": {}})
        elif буква == "o" and len(части) == 6:
            for подпись, ключ_ч, (где, часть, дл) in zip(
                    ("Пользователь", "Сеанс", "Версия", "Сеть", "Вид адреса", "Адрес"),
                    ("username", "sessionid", "version", "network_type", "address_type", "address"), части,
                    strict=False):
                у.поле(подпись, f"sdp.owner.{ключ_ч}", часть, где, дл, родитель=п)
        elif буква == "c" and len(части) == 3:
            for подпись, ключ_ч, (где, часть, дл) in zip(("Сеть", "Вид адреса", "Адрес"),
                                                         ("network_type", "address_type", "address"), части,
                                                         strict=False):
                у.поле(подпись, f"sdp.connection_info.{ключ_ч}", часть, где, дл, родитель=п)
            адрес = адрес or части[2][1]
            if описания and поток is not None:
                описания[-1]["адрес"] = части[2][1]
        elif буква == "a" and значение.startswith("rtpmap:"):
            сов = re.fullmatch(r"rtpmap:(\d+)\s+([^/\s]+)/(\d+)(?:/(\d+))?\s*", значение)
            if сов:
                у.поле("Тип нагрузки", "sdp.rtpmap.pt", int(сов.group(1)), н + сов.start(1), len(сов.group(1)),
                       родитель=п)
                у.поле("Кодировка", "sdp.mime.type", сов.group(2), н + сов.start(2), len(сов.group(2)), родитель=п)
                у.поле("Частота", "sdp.sample_rate", int(сов.group(3)), н + сов.start(3), len(сов.group(3)),
                       родитель=п)
                if описания and поток is not None:
                    описания[-1]["rtpmap"][int(сов.group(1))] = f"{сов.group(2)}/{сов.group(3)}"
        if поток is not None and буква != "m":
            поток.длина = место + len(строка) - поток.смещение
    у.длина = конец - м
    у.итог = ", ".join(итог_потоки) + (f", адрес {адрес}" if адрес else "")
    for описание in описания:
        описание["адрес"] = описание["адрес"] or адрес
    for получатель in SDP_ОПИСАНИЯ:
        получатель(р, описания)
    return True


