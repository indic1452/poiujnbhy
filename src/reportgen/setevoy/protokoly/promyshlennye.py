def _104_apdu(д: bytes, м: int, конец: int) -> str | None:
    """Вид APDU («I», «S», «U»), если APCI верен; для I-формата, когда APDU целиком
    в данных, ещё и длина ASDU должна сойтись с типом и числом объектов."""
    if м + 6 > конец or д[м] != 0x68:
        return None
    дл = д[м + 1]
    if not 4 <= дл <= 253:
        return None
    c1, c2, c3, c4 = д[м + 2], д[м + 3], д[м + 4], д[м + 5]
    if c3 & 1:
        return None
    if not c1 & 1:
        if дл < 10:
            return None
        if м + 2 + дл <= конец:
            тип, vsq, причина = д[м + 6], д[м + 7], д[м + 8] & 0x3F
            if тип == 0 or причина == 0:
                return None
            if тип in ASDU_ТИПЫ:
                n, размер = vsq & 0x7F, ASDU_ТИПЫ[тип][1]
                if n == 0:
                    return None
                нужно = 6 + (3 + n * размер if vsq & 0x80 else n * (3 + размер))
                if нужно != дл - 4:
                    return None
        return "I"
    if дл != 4:
        return None
    if c1 & 3 == 1:
        return "S" if c1 == 1 and c2 == 0 else None
    if c2 or c3 or c4 or (c1 >> 2) << 2 not in U_ФУНКЦИИ:
        return None
    return "U"


def iec104(р: Разбор, м: int, конец: int) -> bool:
    """IEC 60870-5-104: все APDU сегмента подряд; последний может продолжиться в следующем."""
    д = р.д
    # Проверка до создания уровня: APDU должны лечь подряд до конца данных.
    место, целых = м, 0
    while место < конец:
        if _104_apdu(д, место, конец) is None:
            return False
        if место + 2 + д[место + 1] > конец:
            if not целых:
                return False
            break
        целых += 1
        место += 2 + д[место + 1]
    у = р.уровень("IEC104", "IEC 60870-5-104", м)
    итоги, место, номер = [], м, 0
    while место < конец:
        номер += 1
        итоги.append(_104_один(р, у, место, конец, номер if целых > 1 else 0))
        место += 2 + д[место + 1]
    у.длина = min(место, конец) - м
    у.итог = "; ".join(итоги)
    р.п.инфо = "IEC 104 " + у.итог
    return True


def _104_один(р: Разбор, у: Уровень, м: int, конец: int, номер: int) -> str:
    д = р.д
    дл = д[м + 1]
    кон = min(конец, м + 2 + дл)
    вид = _104_apdu(д, м, конец)
    c1 = д[м + 2]
    а = у.поле((f"APDU {номер}" if номер else "APDU") + f": формат {вид}", "iec60870_104.apdu", вид,
               м, кон - м)
    у.поле("Начало", "iec60870_104.start", "0x68", м, 1, 0x68, родитель=а)
    у.поле("Длина APDU", "iec60870_104.apdulen", дл, м + 1, 1, родитель=а)
    у.поле("Формат", "iec60870_104.type", вид, м + 2, 1, {"I": 0, "S": 1, "U": 3}[вид], родитель=а)
    nr = (д[м + 4] >> 1) | (д[м + 5] << 7)
    if вид == "U":
        функция = U_ФУНКЦИИ[c1 & 0xFC]
        у.поле("Функция U", "iec60870_104.utype", функция, м + 2, 1, c1 & 0xFC, родитель=а)
        return функция
    if вид == "S":
        у.поле("N(R)", "iec60870_104.rx", nr, м + 4, 2, родитель=а)
        return f"S (N(R)={nr})"
    ns = (c1 >> 1) | (д[м + 3] << 7)
    у.поле("N(S)", "iec60870_104.tx", ns, м + 2, 2, родитель=а)
    у.поле("N(R)", "iec60870_104.rx", nr, м + 4, 2, родитель=а)
    итог = f"I (N(S)={ns}, N(R)={nr})"
    if кон < м + 2 + дл:
        р.ошибка("IEC 104: APDU продолжается за пределами сегмента")
        а.текст += " [продолжение в следующем сегменте]"
        if кон < м + 12:
            return итог + " [оборван]"
    return итог + " " + _asdu(р, у, м + 6, кон, а)


def _cp56(д: bytes, м: int) -> str:
    мс = д[м] | (д[м + 1] << 8)
    минуты, часы, день, месяц, год = д[м + 2] & 0x3F, д[м + 3] & 0x1F, д[м + 4] & 0x1F, д[м + 5] & 0x0F, д[м + 6] & 0x7F
    текст = f"{2000 + год:04d}-{месяц:02d}-{день:02d} {часы:02d}:{минуты:02d}:{мс / 1000:06.3f}"
    if д[м + 2] & 0x80:
        текст += " (IV — время недостоверно)"
    if д[м + 3] & 0x80:
        текст += " (SU — летнее)"
    return текст


def _качество(q: int) -> str:
    флаги = [и for и, б in (("OV", 0), ("BL", 4), ("SB", 5), ("NT", 6), ("IV", 7)) if q >> б & 1]
    return ", ".join(флаги) or "норма"


def _asdu(р: Разбор, у: Уровень, м: int, конец: int, родитель: Поле) -> str:
    д = р.д
    тип, vsq, cot, инициатор = д[м], д[м + 1], д[м + 2], д[м + 3]
    общий = д[м + 4] | (д[м + 5] << 8)
    sq, n = vsq >> 7, vsq & 0x7F
    причина = cot & 0x3F
    обозначение, размер = ASDU_ТИПЫ.get(тип, (str(тип), None))
    а = у.поле("ASDU", "iec60870_asdu", обозначение, м, конец - м, тип, родитель=родитель)
    у.поле("Идентификатор типа", "iec60870_asdu.typeid", f"{тип} ({обозначение})", м, 1, тип, родитель=а)
    у.поле("SQ (последовательность)", "iec60870_asdu.sq", sq, м + 1, 1, родитель=а)
    у.поле("Число объектов", "iec60870_asdu.numix", n, м + 1, 1, родитель=а)
    у.поле("Причина передачи", "iec60870_asdu.causetx", f"{причина} ({ПРИЧИНЫ.get(причина, '?')})", м + 2, 1,
           причина, родитель=а)
    у.поле("P/N (отрицательное подтверждение)", "iec60870_asdu.nega", (cot >> 6) & 1, м + 2, 1, родитель=а)
    у.поле("T (проверка)", "iec60870_asdu.test", cot >> 7, м + 2, 1, родитель=а)
    у.поле("Адрес инициатора", "iec60870_asdu.oa", инициатор, м + 3, 1, родитель=а)
    у.поле("Общий адрес ASDU", "iec60870_asdu.addr", общий, м + 4, 2, родитель=а)
    итог = f"{обозначение} {ПРИЧИНЫ.get(причина, причина)}" + (" (отриц.)" if cot & 0x40 else "") + f", CA {общий}"
    место = м + 6
    if размер is None:
        у.поле("Объекты информации", "iec60870_asdu.data", f"{конец - место} байт (тип не разбирается)",
               место, конец - место, родитель=а)
        return итог
    адрес = None
    адреса = []
    for i in range(n):
        if i >= 64:
            у.поле("…", "", f"ещё объектов: {n - 64}", место, 0, родитель=а)
            break
        if not sq or i == 0:
            if место + 3 > конец:
                break
            адрес = д[место] | (д[место + 1] << 8) | (д[место + 2] << 16)
            начало, место = место, место + 3
        else:
            адрес += 1
            начало = место
        if место + размер > конец:
            break
        о = у.поле(f"Объект IOA {адрес}", "iec60870_asdu.ioa", адрес, начало, место + размер - начало, родитель=а)
        _104_элемент(у, д, место, тип, размер, о)
        адреса.append(адрес)
        место += размер
    if адреса:
        итог += f", IOA {адреса[0]}" + (f"…{адреса[-1]}" if len(адреса) > 1 else "")
    return итог


