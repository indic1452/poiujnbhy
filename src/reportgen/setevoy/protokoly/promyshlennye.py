def _iax2_ie_тиражированы(д: bytes, м: int, конец: int) -> bool:
    место = м
    while место < конец:
        if место + 2 > конец:
            return False
        место += 2 + д[место + 1]
    return место == конец


def _iax2_полный_верен(д: bytes, м: int, конец: int) -> bool:
    if конец - м < 12:                                # вызывается только при F = 1
        return False
    тип, sub = д[м + 10], д[м + 11]
    данных = конец - м - 12
    c, значение = sub >> 7, sub & 0x7F
    if тип == 0x06:
        return not c and значение in IAX2_ПОДКЛАССЫ and _iax2_ie_тиражированы(д, м + 12, конец)
    if тип == 0x02:                                   # голос: подкласс — один кодек (степень двойки)
        return данных > 0 and bool(значение < 32 if c else значение and not значение & (значение - 1))
    if тип == 0x01:                                   # DTMF: цифра, данных нет
        return not c and данных == 0 and chr(значение) in "0123456789*#ABCD"
    if тип == 0x04:
        return not c and данных == 0 and значение in IAX2_УПРАВЛЕНИЕ
    if тип == 0x05:
        return sub == 0 and данных == 0
    if тип == 0x07:
        return данных > 0 and all(32 <= б < 127 or б in (0, 9, 10, 13) for б in д[м + 12:конец])
    return False


def iax2(р: Разбор, м: int, конец: int) -> bool:
    """IAX2 (RFC 5456, разд. 8): полный кадр — проверяется по типу, подклассу и IE;
    мини-кадр проверить нечем, поэтому он признаётся, только если оба порта 4569
    или аналитик сам выбрал «разбирать как IAX2»."""
    д = р.д
    if конец - м < 4:
        return False
    if д[м] & 0x80:
        if not _iax2_полный_верен(д, м, конец):
            return False
        return _iax2_полный(р, м, конец)
    порты = (р.п.порт_от, р.п.порт_к)
    выбран = any(р.как.get(f"udp:{п}") == "IAX2" for п in порты if п)
    источник = ((д[м] & 0x7F) << 8) | д[м + 1]
    if not источник or конец - м < 5 or not (порты == (4569, 4569) or выбран):
        return False
    у = р.уровень("IAX2", "Inter-Asterisk eXchange v2", м)
    у.поле("Вид пакета", "iax2.packet_type", "мини-кадр", м, 1, 0)
    у.поле("Номер вызова источника", "iax2.src_call", источник, м, 2)
    у.поле("Отметка времени (младшие 16 бит)", "iax2.minits", _be(д, м + 2, 2), м + 2, 2)
    у.поле("Голос", "iax2.voicedata", f"{конец - м - 4} байт", м + 4, конец - м - 4)
    у.длина = 4
    у.итог = f"мини-кадр, вызов {источник}, время {_be(д, м + 2, 2)}, {конец - м - 4} байт"
    р.нагрузка(м + 4, конец)
    р.п.инфо = "IAX2 " + у.итог
    return True


def _iax2_полный(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    источник, получатель = ((д[м] & 0x7F) << 8) | д[м + 1], ((д[м + 2] & 0x7F) << 8) | д[м + 3]
    тип, sub = д[м + 10], д[м + 11]
    подкласс = (1 << (sub & 0x7F)) if sub & 0x80 else sub
    у = р.уровень("IAX2", "Inter-Asterisk eXchange v2", м)
    у.поле("Вид пакета", "iax2.packet_type", "полный кадр", м, 1, 1)
    у.поле("Номер вызова источника", "iax2.src_call", источник, м, 2)
    у.поле("Повтор (R)", "iax2.retransmission", д[м + 2] >> 7, м + 2, 1)
    у.поле("Номер вызова получателя", "iax2.dst_call", получатель, м + 2, 2)
    у.поле("Отметка времени, мс", "iax2.timestamp", _be(д, м + 4, 4), м + 4, 4)
    у.поле("Исходящий номер (OSeqno)", "iax2.oseqno", д[м + 8], м + 8, 1)
    у.поле("Входящий номер (ISeqno)", "iax2.iseqno", д[м + 9], м + 9, 1)
    у.поле("Тип кадра", "iax2.type", f"{тип} ({IAX2_ТИПЫ[тип]})", м + 10, 1, тип)
    if тип == 0x06:
        имя = IAX2_ПОДКЛАССЫ[подкласс]
        у.поле("Подкласс IAX", "iax2.iax.subclass", f"{подкласс} ({имя})", м + 11, 1, подкласс)
    elif тип == 0x04:
        имя = IAX2_УПРАВЛЕНИЕ[подкласс]
        у.поле("Подкласс управления", "iax2.control.subclass", f"{подкласс} ({имя})", м + 11, 1, подкласс)
    elif тип == 0x01:
        имя = chr(подкласс)
        у.поле("Цифра DTMF", "iax2.dtmf.csub", имя, м + 11, 1)
    elif тип == 0x02:
        имя = f"кодек 0x{подкласс:x}"
        у.поле("Кодек (подкласс)", "iax2.voice.csub", f"0x{подкласс:x}", м + 11, 1, подкласс)
    else:
        имя = IAX2_ТИПЫ[тип]
        у.поле("Подкласс", "iax2.subclass", подкласс, м + 11, 1)
    у.длина = 12
    итог = f"{IAX2_ТИПЫ[тип]} {имя}, вызов {источник} → {получатель}, номера {д[м + 8]}/{д[м + 9]}"
    место = м + 12
    if тип == 0x06:
        while место + 2 <= конец:
            ie, дл = д[место], д[место + 1]
            значение = д[место + 2:место + 2 + дл]
            подпись, ключ, вид = IAX2_IE.get(ie, (f"IE 0x{ie:02x}", "ie", "х"))
            if вид == "т":
                текст = значение.decode("utf-8", "replace")
            elif вид == "ч" and 1 <= дл <= 4:
                текст = str(int.from_bytes(значение, "big"))
            else:
                текст = значение.hex() or "—"
            у.поле(f"{подпись}: {текст}", f"iax2.iax.{ключ}", текст, место, 2 + дл)
            if ie in (0x01, 0x06) and текст:
                итог += f", {подпись.lower()} {текст}"
            место += 2 + дл
        у.длина = конец - м
    elif место < конец:
        у.поле("Данные", "iax2.data", f"{конец - место} байт", место, конец - место)
        р.нагрузка(место, конец)
    у.итог = итог
    р.п.инфо = "IAX2 " + итог
    return True


