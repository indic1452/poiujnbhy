def _dnp3_кадр(д: bytes, м: int, конец: int) -> int | None:
    """Полная длина кадра FT3, если заголовок верен (начало, длина ≥ 5, CRC заголовка)."""
    if м + 10 > конец or д[м] != 0x05 or д[м + 1] != 0x64 or д[м + 2] < 5:
        return None
    if crc_dnp(д[м:м + 8]) != д[м + 8] | (д[м + 9] << 8):
        return None
    польз = д[м + 2] - 5
    return 10 + польз + 2 * ((польз + 15) // 16)


def dnp3(р: Разбор, м: int, конец: int) -> bool:
    """DNP3 поверх TCP/UDP (IEEE 1815, разд. 9, 8, 4): кадры канального уровня подряд."""
    д = р.д
    if _dnp3_кадр(д, м, конец) is None:
        return False
    у = р.уровень("DNP3", "Distributed Network Protocol 3 (IEEE 1815)", м)
    место, итоги, номер = м, [], 0
    while место < конец:
        всего = _dnp3_кадр(д, место, конец)
        if всего is None:
            у.поле("Лишние байты", "dnp3.trailing", f"{конец - место} байт", место, конец - место)
            р.ошибка("DNP3: после кадров байты без начала 0x0564")
            break
        номер += 1
        итоги.append(_dnp3_один(р, у, место, конец, всего, номер))
        место += всего
    у.длина = min(место, конец) - м
    у.итог = "; ".join(итоги)
    р.п.инфо = "DNP3 " + у.итог
    return True


def _dnp3_один(р: Разбор, у: Уровень, м: int, конец: int, всего: int, номер: int) -> str:
    д = р.д
    дл, упр = д[м + 2], д[м + 3]
    получатель, источник = д[м + 4] | (д[м + 5] << 8), д[м + 6] | (д[м + 7] << 8)
    dir_, prm = упр >> 7, (упр >> 6) & 1
    функция = упр & 15
    имя_функции = (DNP3_ПЕРВИЧНЫЕ if prm else DNP3_ВТОРИЧНЫЕ).get(функция, str(функция))
    приставка = f"Кадр {номер}: " if номер > 1 else ""
    к = у.поле(приставка + "Канальный уровень", "dnp3.link", f"{источник} → {получатель}, {имя_функции}",
               м, 10, упр)
    у.поле("Начало", "dnp3.start", "0x0564", м, 2, 0x0564, родитель=к)
    у.поле("Длина", "dnp3.len", дл, м + 2, 1, родитель=к)
    п = у.поле("Управление", "dnp3.ctl", f"0x{упр:02x}", м + 3, 1, упр, родитель=к)
    у.поле("Направление (DIR)", "dnp3.ctl.dir", dir_, м + 3, 1, родитель=п)
    у.поле("Первичный (PRM)", "dnp3.ctl.prm", prm, м + 3, 1, родитель=п)
    if prm:
        у.поле("FCB", "dnp3.ctl.fcb", (упр >> 5) & 1, м + 3, 1, родитель=п)
        у.поле("FCV", "dnp3.ctl.fcv", (упр >> 4) & 1, м + 3, 1, родитель=п)
        у.поле("Функция", "dnp3.ctl.prifunc", f"{функция} ({имя_функции})", м + 3, 1, функция, родитель=п)
    else:
        у.поле("DFC", "dnp3.ctl.dfc", (упр >> 4) & 1, м + 3, 1, родитель=п)
        у.поле("Функция", "dnp3.ctl.secfunc", f"{функция} ({имя_функции})", м + 3, 1, функция, родитель=п)
    у.поле("Получатель", "dnp3.dst", получатель, м + 4, 2, родитель=к)
    у.поле("Источник", "dnp3.src", источник, м + 6, 2, родитель=к)
    _скрытые(у, "dnp3.addr", (получатель, источник))
    crc = д[м + 8] | (д[м + 9] << 8)
    у.поле("CRC заголовка", "dnp3.hdr.crc", f"0x{crc:04x} [верна]", м + 8, 2, crc, родитель=к)
    # Данные пользователя: блоки по 16 байт, за каждым — своя CRC. Собираем их
    # подряд, помня место каждого байта в пакете (для подсветки полей).
    польз, байты, карта = дл - 5, bytearray(), []
    место, блок, оборван = м + 10, 0, False
    while польз > 0:
        n = min(16, польз)
        доступно = max(0, min(n, конец - место))
        байты += д[место:место + доступно]
        карта.extend(range(место, место + доступно))
        блок += 1
        if доступно < n or место + n + 2 > конец:
            оборван = True
            break
        crc = д[место + n] | (д[место + n + 1] << 8)
        верна = crc_dnp(д[место:место + n]) == crc
        у.поле(f"CRC блока {блок}", "dnp3.data_chunk_crc", f"0x{crc:04x} [{'верна' if верна else 'НЕВЕРНА'}]",
               место + n, 2, crc, плохо=not верна, родитель=к)
        if not верна:
            р.ошибка(f"DNP3: неверная CRC блока данных {блок}")
        место += n + 2
        польз -= n
    к.длина = min(м + всего, конец) - м
    if оборван:
        р.ошибка("DNP3: кадр оборван")
    итог = f"{источник} → {получатель}"
    if not байты:
        return f"{итог}, {имя_функции}"
    итог_пр = _dnp3_транспорт_и_прикладной(у, байты, карта, приставка)
    return f"{итог}, {итог_пр}"


def _скрытые(у: Уровень, ключ: str, значения) -> None:
    for значение in значения:
        у.поле("", ключ, значение, у.смещение, 0)


def _dnp3_транспорт_и_прикладной(у: Уровень, байты: bytearray, карта: list[int], приставка: str) -> str:
    def место(i: int, n: int) -> tuple[int, int]:
        n = max(1, min(n, len(карта) - i))
        return карта[i], карта[i + n - 1] - карта[i] + 1

    тр = байты[0]
    fin, fir, номер = тр >> 7, (тр >> 6) & 1, тр & 0x3F
    т = у.поле(приставка + "Транспортный уровень", "dnp3.tr.ctl",
               f"0x{тр:02x} (FIN={fin}, FIR={fir}, номер {номер})", *место(0, 1), тр)
    у.поле("FIN", "dnp3.tr.fin", fin, *место(0, 1), родитель=т)
    у.поле("FIR", "dnp3.tr.fir", fir, *место(0, 1), родитель=т)
    у.поле("Номер", "dnp3.tr.seq", номер, *место(0, 1), родитель=т)
    if len(байты) < 2:
        return "транспортный сегмент без данных"
    if not fir:
        у.поле(приставка + "Продолжение фрагмента прикладного уровня", "dnp3.al.fragment",
               f"{len(байты) - 1} байт", *место(1, len(байты) - 1))
        return f"продолжение фрагмента (номер {номер})"
    if len(байты) < 3:
        у.поле(приставка + "Прикладной уровень (оборван)", "dnp3.al", "оборван", *место(1, 1))
        return "прикладной уровень оборван"
    упр, функция = байты[1], байты[2]
    имя = DNP3_ФУНКЦИИ.get(функция, str(функция))
    а = у.поле(приставка + "Прикладной уровень", "dnp3.al", имя, *место(1, len(байты) - 1), функция)
    п = у.поле("Управление", "dnp3.al.ctl", f"0x{упр:02x}", *место(1, 1), упр, родитель=а)
    for подпись, ключ, бит in (("FIR", "fir", 7), ("FIN", "fin", 6), ("CON", "con", 5), ("UNS", "uns", 4)):
        у.поле(подпись, f"dnp3.al.{ключ}", (упр >> бит) & 1, *место(1, 1), родитель=п)
    у.поле("Номер", "dnp3.al.seq", упр & 15, *место(1, 1), родитель=п)
    у.поле("Функция", "dnp3.al.func", f"{функция} ({имя})", *место(2, 1), функция, родитель=а)
    итог = имя
    i = 3
    if функция in (129, 130):
        if len(байты) < 5:
            return итог + " (оборван)"
        iin = (байты[3] << 8) | байты[4]
        ii = у.поле("Внутренние индикаторы (IIN)", "dnp3.al.iin", f"0x{iin:04x}", *место(3, 2), iin, родитель=а)
        взведены = []
        for бит, ключ, подпись in DNP3_IIN:
            значение = (iin >> бит) & 1
            у.поле(подпись, f"dnp3.al.iin.{ключ}", значение, *место(3 if бит >= 8 else 4, 1), родитель=ii)
            if значение:
                взведены.append(подпись)
        if iin & 0x00C0:
            у.поле("Зарезервированные биты IIN2.6–2.7", "dnp3.al.iin.reserved", "взведены", *место(4, 1),
                   плохо=True, родитель=ii)
        if взведены:
            ii.текст += " (" + ", ".join(взведены) + ")"
        i = 5
    объекты = _dnp3_объекты(у, байты, карта, i, функция, а, место)
    if объекты:
        итог += " " + ", ".join(объекты[:4]) + (" …" if len(объекты) > 4 else "")
    return итог


def _dnp3_объекты(у, байты, карта, i, функция, родитель, место) -> list[str]:
    """Заголовки объектов. В запросе READ данных у объектов нет — разбираются все
    заголовки; в прочих сообщениях размер данных зависит от группы/вариации,
    поэтому разбирается только первый заголовок."""
    итоги = []
    while i + 3 <= len(байты) and len(итоги) < 64:
        группа, вариация, кв = байты[i], байты[i + 1], байты[i + 2]
        префикс, диапазон = (кв >> 4) & 7, кв & 15
        размер, вид = DNP3_ДИАПАЗОНЫ.get(диапазон, (None, ""))
        имя = f"g{группа}v{вариация}"
        о = у.поле(f"Объект {имя} ({DNP3_ГРУППЫ.get(группа, 'группа ' + str(группа))})", "dnp3.al.obj",
                   имя, *место(i, 3 + (размер or 0)), (группа << 8) | вариация, родитель=родитель)
        у.поле("Группа", "dnp3.al.obj.group", группа, *место(i, 1), родитель=о)
        у.поле("Вариация", "dnp3.al.obj.variation", вариация, *место(i + 1, 1), родитель=о)
        к = у.поле("Квалификатор", "dnp3.al.objq", f"0x{кв:02x}", *место(i + 2, 1), кв, родитель=о)
        у.поле("Код префикса", "dnp3.al.objq.prefix", префикс, *место(i + 2, 1), родитель=к)
        у.поле("Код диапазона", "dnp3.al.objq.range", диапазон, *место(i + 2, 1), родитель=к)
        итоги.append(имя)
        if размер is None or i + 3 + размер > len(байты):
            break
        j = i + 3
        количество = 0
        if вид == "пределы":
            половина = размер
            начало = int.from_bytes(байты[j:j + половина], "little")
            конец_ = int.from_bytes(байты[j + половина:j + 2 * половина], "little")
            у.поле("Начало", "dnp3.al.range.start", начало, *место(j, половина), родитель=о)
            у.поле("Конец", "dnp3.al.range.stop", конец_, *место(j + половина, половина), родитель=о)
            количество = max(0, конец_ - начало + 1)
            размер *= 2
            итоги[-1] += f" [{начало}–{конец_}]"
        elif вид == "число":
            количество = int.from_bytes(байты[j:j + размер], "little")
            у.поле("Количество", "dnp3.al.range.quantity", количество, *место(j, размер), родитель=о)
            итоги[-1] += f" ×{количество}"
        i = j + размер
        if функция != 1 or диапазон == 0xB:
            break
        # READ с префиксом индекса: за заголовком — индексы (по 1, 2 или 4 байта).
        if префикс in (1, 2, 3):
            i += количество * {1: 1, 2: 2, 3: 4}[префикс]
    return итоги


