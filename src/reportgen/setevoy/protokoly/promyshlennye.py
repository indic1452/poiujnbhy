def _skinny_длина(д: bytes, м: int, конец: int) -> int | None:
    """Полная длина сообщения (длина + 8), если заголовок похож на Skinny."""
    if м + 12 > конец:
        return None
    дл = _le(д, м, 4)
    if дл < 4 or дл > 0xFFFF or д[м + 5:м + 8] != b"\0\0\0" or д[м + 10:м + 12] != b"\0\0":
        return None
    return дл + 8


def skinny(р: Разбор, м: int, конец: int) -> bool:
    """SCCP (Cisco Skinny), TCP 2000: сообщения подряд ровно до конца сегмента
    (последнее может продолжиться в следующем)."""
    д = р.д
    место, n = м, 0
    while место < конец:
        всего = _skinny_длина(д, место, конец)
        if всего is None:
            return False
        n += 1
        место += всего
    у = р.уровень("SKINNY", "Cisco Skinny Client Control Protocol", м)
    итоги, место = [], м
    while место < конец:
        всего = _skinny_длина(д, место, конец)
        кон = min(конец, место + всего)
        ид = _le(д, место + 8, 4)
        имя = SKINNY_СООБЩЕНИЯ.get(ид, f"0x{ид:04x}")
        с = у.поле(f"Сообщение {имя}" + (" [продолжение в следующем сегменте]" if кон < место + всего else ""),
                   "skinny.message", имя, место, кон - место, ид)
        у.поле("Длина", "skinny.data_length", всего - 8, место, 4, родитель=с)
        у.поле("Версия заголовка (резерв)", "skinny.hdr_version", f"0x{д[место + 4]:02x}", место + 4, 4,
               д[место + 4], родитель=с)
        у.поле("Номер сообщения", "skinny.messageid", f"0x{ид:04x} ({SKINNY_СООБЩЕНИЯ.get(ид, '?')})", место + 8, 4, ид,
               родитель=с)
        if ид == 0x0001 and место + 28 <= кон:
            имя_у = д[место + 12:место + 28].split(b"\0")[0].decode("ascii", "replace")
            у.поле("Имя устройства", "skinny.devicename", имя_у, место + 12, 16, родитель=с)
            имя += f" «{имя_у}»"
        elif ид == 0x0003 and место + 16 <= кон:
            кнопка = _le(д, место + 12, 4)
            у.поле("Кнопка", "skinny.keypadbutton", кнопка, место + 12, 4, родитель=с)
            имя += f" {кнопка}"
        итоги.append(имя)
        место += всего
    у.длина = min(место, конец) - м
    у.итог = ", ".join(итоги)
    р.п.инфо = "Skinny " + у.итог
    return True


