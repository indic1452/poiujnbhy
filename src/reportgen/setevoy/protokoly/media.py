"""Медиа по описанию SDP: RTP с названием кодека, события DTMF (RFC 4733), факс T.38 поверх UDPTL и T.30.

Документы (структуры — строго по ним):

* SDP — RFC 8866: m= (вид, порт, протокол, форматы), c= (адрес: у потока или у сеанса), a=rtpmap.
  Поток, описанный в SIP или MGCP, запоминается для захвата (общий словарь ``р.шаблоны`` с номером
  пакета описания); пакеты UDP на этот адрес и порт (и порт + 1 — RTCP, RFC 3550, 11) разбираются
  как RTP/RTCP или UDPTL — так же, как Wireshark связывает потоки по SDP.
* RTP — RFC 3550, 5.1 и 5.3.1 (P — добивка, число в последнем байте; X — расширение: профиль и длина
  в 32-битных словах; CSRC); статические типы нагрузки — RFC 3551, табл. 4 и 5; динамические — по
  a=rtpmap. RTCP на том же порту (RFC 5761) — по типам 200–204.
* События — RFC 4733, 2.3: событие (байт), E (конец), R, громкость (6 бит, −дБм0), длительность
  (16 бит, в тактах отметки времени); коды 0–15 — DTMF 0–9, *, #, A–D, 16 — flash (2.3.1 и 3.2).
* UDPTL и T.38 — ITU-T T.38 (04/2007), прил. A (ASN.1) и 9.1: UDPTLPacket — номер (16 бит), IFP в
  открытом типе (определитель длины), восстановление; IFPPacket в выровненном PER (X.691): бит
  наличия data-field, бит выбора (t30-indicator / t30-data), бит расширения перечисления и значение
  (4 бита корня; расширение — бит 0 и 6 бит номера после корня 16/9, X.691 10.6), data-field — SEQUENCE OF {бит наличия field-data, field-type — 3 бита (запись до
  поправки 2002 г., как по умолчанию у Wireshark packet-t38.c), field-data — длина−1 в 16 битах и
  байты}. Имена индикаторов, скоростей и видов полей — таблицы t38_T30_indicator_vals,
  t38_T30_data_vals, t38_T_field_type_vals Wireshark.
* T.30 — ITU-T T.30, 5.3.6: кадр HDLC в hdlc-data — адрес 0xFF, управление 0xC0/0xC8 (бит конца),
  FCF — группа 1000 XXXX (DTC, CIG, PWD, …) целиком, остальные без бита X (имена —
  t30_facsimile_control_field_vals Wireshark packet-t30.c); CSI, TSI, SUB, SID, CIG, PWD, SEP, PSA — номер
  из 20 знаков, каждый байт в обратном порядке бит, знаки — от конца (5.3.6.2.4; t30_get_string_numbers).
"""

