"""OSPFv2 полностью: Hello, DBD, LSR, LSU с LSA, LSAck; суммы пакета и LSA.

Документы (структуры полей — строго по ним):

* RFC 2328, прил. A.3.1 (заголовок; сумма — как у IP, по всему пакету без 64-битового поля
  подлинности), A.3.2 (Hello), A.3.3 (DBD, флаги I, M, MS), A.3.4 (LSR), A.3.5 (LSU), A.3.6 (LSAck),
  A.4.1 (заголовок LSA; сумма Флетчера ISO 8473 — от поля «параметры» до конца LSA, без возраста),
  A.4.2 (Router-LSA: флаги, связи — вид, ID, данные, метрика, TOS), A.4.3 (Network-LSA), A.4.4
  (Summary-LSA 3 и 4), A.4.5 (AS-External-LSA); RFC 3101 (NSSA, тип 7 — как 5); RFC 5250 (Opaque 9–11);
* значения видов пакетов и LSA, видов связей, битов параметров и флагов Router-LSA — как в Wireshark
  (packet-ospf.c: OSPF_HELLO…, OSPF_LSTYPE_…, OSPF_LINK_…, OSPF_V2_OPTIONS_…, OSPF_V2_ROUTER_LSA_FLAG_…).

OSPFv3 (RFC 5340) — заголовок, как прежде (razbor.ospf).
"""

from __future__ import annotations

from ..pole import ip4, u16, u32, сумма16
from ..razbor import ДОП_IP, Разбор, ospf as ospf_заголовок

ПАКЕТЫ = {1: "Hello", 2: "описание базы (DBD)", 3: "запрос состояния (LSR)", 4: "обновление состояния (LSU)",
          5: "подтверждение (LSAck)"}
LSA = {1: "Router-LSA", 2: "Network-LSA", 3: "Summary-LSA (сеть)", 4: "Summary-LSA (ASBR)", 5: "AS-External-LSA",
       6: "Group Membership LSA", 7: "NSSA AS-External-LSA", 8: "External Attributes LSA",
       9: "Opaque LSA (канал)", 10: "Opaque LSA (область)", 11: "Opaque LSA (AS)"}
СВЯЗИ = {1: "точка — точка", 2: "транзитная сеть", 3: "тупиковая сеть", 4: "виртуальная"}
ПАРАМЕТРЫ = ((0x80, "DN"), (0x40, "O"), (0x20, "DC"), (0x10, "L"), (0x08, "N/P"), (0x04, "MC"), (0x02, "E"),
             (0x01, "MT"))
ФЛАГИ_ROUTER = ((0x80, "H"), (0x20, "S"), (0x10, "N"), (0x08, "W"), (0x04, "V"), (0x02, "E"), (0x01, "B"))
ПОДЛИННОСТЬ = {0: "нет", 1: "простой пароль", 2: "криптографическая"}


def биты(значение: int, таблица) -> str:
    return " ".join(имя for маска, имя in таблица if значение & маска) or "—"


def флетчер_верен(данные: bytes) -> bool:
    """Сумма ISO 8473: при верных проверочных байтах обе суммы C0 и C1 — нули по модулю 255."""
    c0 = c1 = 0
    for б in данные:
        c0 = (c0 + б) % 255
        c1 = (c1 + c0) % 255
    return c0 == 0 and c1 == 0


def _заголовок_lsa(у, д: bytes, м: int, родитель, полный: bool) -> tuple:
    возраст, параметры, тип = u16(д, м), д[м + 2], д[м + 3]
    ид, кто, номер, длина = ip4(д, м + 4), ip4(д, м + 8), u32(д, м + 12), u16(д, м + 18)
    п = у.поле(f"{LSA.get(тип, f'LSA {тип}')}: {ид} от {кто}", "ospf.lsa", тип, м, длина if полный else 20,
               родитель=родитель)
    у.поле("Возраст, с", "ospf.lsa.age", возраст & 0x7FFF, м, 2, родитель=п)
    у.поле("Параметры", "ospf.lsa.options", биты(параметры, ПАРАМЕТРЫ), м + 2, 1, параметры, родитель=п)
    у.поле("Link State ID", "ospf.lsa.id", ид, м + 4, 4, родитель=п)
    у.поле("Объявил", "ospf.advrouter", кто, м + 8, 4, родитель=п)
    у.поле("Номер", "ospf.lsa.seqnum", f"0x{номер:08x}", м + 12, 4, номер, родитель=п)
    у.поле("Длина", "ospf.lsa.length", длина, м + 18, 2, родитель=п)
    return п, тип, длина


def _тело_lsa(у, д: bytes, м: int, тип: int, длина: int, п) -> None:
    тело, край = м + 20, м + длина
    if тип == 1 and тело + 4 <= край:
        флаги, связей = д[тело], u16(д, тело + 2)
        у.поле("Флаги", "ospf.v2.router.lsa.flags", биты(флаги, ФЛАГИ_ROUTER), тело, 1, флаги, родитель=п)
        место = тело + 4
        for _ in range(связей):
            if место + 12 > край:
                break
            вид, tos = д[место + 8], д[место + 9]
            у.поле(f"связь ({СВЯЗИ.get(вид, вид)})", "ospf.lsa.router.link_type",
                   f"ID {ip4(д, место)}, данные {ip4(д, место + 4)}, метрика {u16(д, место + 10)}", место,
                   12 + 4 * tos, вид, родитель=п)
            место += 12 + 4 * tos
    elif тип == 2 and тело + 4 <= край:
        у.поле("Маска", "ospf.lsa.net.netmask", ip4(д, тело), тело, 4, родитель=п)
        у.поле("Маршрутизаторы", "ospf.lsa.net.attachrtr",
               " ".join(ip4(д, x) for x in range(тело + 4, край - 3, 4)), тело + 4, край - тело - 4, родитель=п)
    elif тип in (3, 4) and тело + 8 <= край:
        у.поле("Маска", "ospf.lsa.summary.netmask", ip4(д, тело), тело, 4, родитель=п)
        у.поле("Метрика", "ospf.lsa.summary.metric", u32(д, тело + 4) & 0xFFFFFF, тело + 5, 3, родитель=п)
    elif тип in (5, 7) and тело + 16 <= край:
        e = д[тело + 4] >> 7
        у.поле("Маска", "ospf.lsa.asext.netmask", ip4(д, тело), тело, 4, родитель=п)
        у.поле("Метрика", "ospf.lsa.asext.metric",
               f"{u32(д, тело + 4) & 0xFFFFFF} ({'тип 2' if e else 'тип 1'})", тело + 4, 4,
               u32(д, тело + 4) & 0xFFFFFF, родитель=п)
        у.поле("Адрес пересылки", "ospf.lsa.asext.fwdaddr", ip4(д, тело + 8), тело + 8, 4, родитель=п)
        у.поле("Метка маршрута", "ospf.lsa.asext.extrttag", u32(д, тело + 12), тело + 12, 4, родитель=п)


def ospf(р: Разбор, м: int, конец: int) -> None:
    д = р.д
    if конец - м < 24 or д[м] != 2:
        ospf_заголовок(р, м, конец)
        return
    у = р.уровень("OSPF", "Open Shortest Path First", м)
    тип, длина, подлинность = д[м + 1], u16(д, м + 2), u16(д, м + 14)
    у.поле("Версия", "ospf.version", 2, м, 1)
    у.поле("Тип", "ospf.msg", f"{тип} ({ПАКЕТЫ.get(тип, 'неизвестный')})", м + 1, 1, тип)
    у.поле("Длина", "ospf.packet_length", длина, м + 2, 2)
    у.поле("Router ID", "ospf.srcrouter", ip4(д, м + 4), м + 4, 4)
    у.поле("Area ID", "ospf.area_id", ip4(д, м + 8), м + 8, 4)
    край = min(м + длина, конец) if длина >= 24 else конец
    if подлинность != 2 and длина >= 24 and м + длина <= конец:
        верна = сумма16(д[м:м + 16] + д[м + 24:м + длина]) == 0
        у.поле("Сумма", "ospf.checksum", f"0x{u16(д, м + 12):04x} ({'верна' if верна else 'НЕВЕРНА'})", м + 12, 2,
               u16(д, м + 12), плохо=not верна)
        if not верна:
            р.ошибка("OSPF: неверная контрольная сумма пакета")
    у.поле("Подлинность", "ospf.auth.type", ПОДЛИННОСТЬ.get(подлинность, подлинность), м + 14, 2, подлинность)
    место = м + 24
    итог = ПАКЕТЫ.get(тип, str(тип))
    if тип == 1 and место + 20 <= край:
        у.поле("Маска", "ospf.hello.network_mask", ip4(д, место), место, 4)
        у.поле("Интервал Hello, с", "ospf.hello.hello_interval", u16(д, место + 4), место + 4, 2)
        у.поле("Параметры", "ospf.v2.options", биты(д[место + 6], ПАРАМЕТРЫ), место + 6, 1, д[место + 6])
        у.поле("Приоритет", "ospf.hello.router_priority", д[место + 7], место + 7, 1)
        у.поле("Интервал отказа, с", "ospf.hello.router_dead_interval", u32(д, место + 8), место + 8, 4)
        у.поле("DR", "ospf.hello.designated_router", ip4(д, место + 12), место + 12, 4)
        у.поле("BDR", "ospf.hello.backup_designated_router", ip4(д, место + 16), место + 16, 4)
        соседи = [ip4(д, x) for x in range(место + 20, край - 3, 4)]
        у.поле("Соседи", "ospf.hello.active_neighbor", " ".join(соседи) or "нет", место + 20, 4 * len(соседи))
        итог = f"Hello, DR {ip4(д, место + 12)}, соседей {len(соседи)}"
    elif тип == 2 and место + 8 <= край:
        флаги = д[место + 3]
        у.поле("MTU", "ospf.db.interface_mtu", u16(д, место), место, 2)
        у.поле("Параметры", "ospf.v2.options", биты(д[место + 2], ПАРАМЕТРЫ), место + 2, 1, д[место + 2])
        у.поле("Флаги", "ospf.db.flags", " ".join(и for б, и in ((4, "I"), (2, "M"), (1, "MS")) if флаги & б) or "—",
               место + 3, 1, флаги)
        у.поле("Номер DD", "ospf.db.dd_sequence", u32(д, место + 4), место + 4, 4)
        заголовков = 0
        for x in range(место + 8, край - 19, 20):
            _заголовок_lsa(у, д, x, None, False)
            заголовков += 1
        итог = f"DBD, заголовков LSA {заголовков}"
    elif тип == 3:
        запросов = 0
        for x in range(место, край - 11, 12):
            у.поле(f"запрос {LSA.get(u32(д, x), u32(д, x))}", "ospf.link_state_id",
                   f"{ip4(д, x + 4)} от {ip4(д, x + 8)}", x, 12, u32(д, x))
            запросов += 1
        итог = f"LSR, запросов {запросов}"
    elif тип == 4 and место + 4 <= край:
        число = u32(д, место)
        у.поле("Число LSA", "ospf.ls_number_of_lsas", число, место, 4)
        x, виды = место + 4, []
        for _ in range(число):
            if x + 20 > край:
                break
            п, вид, дл = _заголовок_lsa(у, д, x, None, True)
            if дл < 20 or x + дл > край:
                р.ошибка("OSPF: LSA неверной длины (короче заголовка или длиннее пакета)")
                break
            верна = флетчер_верен(д[x + 2:x + дл])
            у.поле("Сумма LSA", "ospf.lsa.chksum", f"0x{u16(д, x + 16):04x} ({'верна' if верна else 'НЕВЕРНА'})",
                   x + 16, 2, u16(д, x + 16), плохо=not верна, родитель=п)
            if not верна:
                р.ошибка("OSPF: неверная сумма LSA")
            _тело_lsa(у, д, x, вид, дл, п)
            виды.append(LSA.get(вид, str(вид)))
            x += дл
        итог = f"LSU: {', '.join(виды) or 'нет LSA'}"
    elif тип == 5:
        заголовков = 0
        for x in range(место, край - 19, 20):
            _заголовок_lsa(у, д, x, None, False)
            заголовков += 1
        итог = f"LSAck, заголовков LSA {заголовков}"
    у.длина = край - м
    у.итог = f"{итог}, router {ip4(д, м + 4)}, area {ip4(д, м + 8)}"
    р.п.инфо = "OSPF " + у.итог


ДОП_IP[89] = ospf
