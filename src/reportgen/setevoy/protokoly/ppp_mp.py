"""PPP: многоканальный PPP (MP, RFC 1990), PAP (RFC 1334), CHAP (RFC 1994), EAP (RFC 3748), BAP (RFC 2125).

Раскладка — как у Wireshark (epan/dissectors/packet-ppp.c: dissect_mp, dissect_pap, dissect_chap,
dissect_bap; номера протоколов — packet-ppp.h).

MP (RFC 1990, 3): заголовок длинный — байт B E CLS(4) 00 и 24-битовый номер — по умолчанию; короткий
(B E CLS(2) и 12-битовый номер) — если договорено опцией LCP 18 (SSNH). Из самого заголовка длину не
узнать (так и у Wireshark — настройка). Здесь: короткий, если захват видел Configure-Ack с опцией 18
(правило «ppp:mp» → «короткие», ставит сборщик захвата) либо у длинного заняты зарезервированные биты.
Фрагмент с B и E сразу — целый пакет PPP; прочие собираются по номерам (``zahvaty.Сборщик``).
"""

from __future__ import annotations

from .. import obshee
from ..pole import u16
from ..razbor import ДОП_PPP, Разбор, ppp, данные
from .kanalnye import eap

PAP_КОДЫ = {1: "Authenticate-Request", 2: "Authenticate-Ack", 3: "Authenticate-Nak"}
CHAP_КОДЫ = {1: "Challenge", 2: "Response", 3: "Success", 4: "Failure"}
BAP_ТИПЫ = {1: "Call-Request", 2: "Call-Response", 3: "Callback-Request", 4: "Callback-Response",
            5: "Link-Drop-Query-Request", 6: "Link-Drop-Query-Response", 7: "Call-Status-Indication",
            8: "Call-Status-Response"}
BAP_ОТВЕТЫ = {0: "Request-Ack", 1: "Request-Nak", 2: "Request-Rej", 3: "Request-Full-Nak"}
#: Правило «разбирать как» для заголовка MP.
MP_КОРОТКИЕ = ("ppp:mp", "короткие")


def _текст(байты: bytes) -> str:
    return байты.decode("utf-8", "replace")


def mp_заголовок(р: Разбор, м: int) -> tuple:
    """(короткий, B, E, класс, номер, длина заголовка)."""
    р.нужно(м, 2)
    б = р.д[м]
    короткий = obshee.правило(р, MP_КОРОТКИЕ[0]) == MP_КОРОТКИЕ[1] or bool(б & 0x03)
    if короткий:
        return True, bool(б & 0x80), bool(б & 0x40), (б & 0x30) >> 4, u16(р.д, м) & 0x0FFF, 2
    р.нужно(м, 4)
    return False, bool(б & 0x80), bool(б & 0x40), (б & 0x3C) >> 2, int.from_bytes(р.д[м + 1:м + 4], "big"), 4


def mp(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("MP", "PPP Multilink (RFC 1990)", м)
    короткий, первый, последний, класс, номер, дл = mp_заголовок(р, м)
    у.поле("Первый фрагмент (B)", "mp.first", первый, м, 1, первый)
    у.поле("Последний фрагмент (E)", "mp.last", последний, м, 1, последний)
    у.поле("Класс", "mp.short_sequence_num_cls" if короткий else "mp.sequence_num_cls", класс, м, 1)
    у.поле("Номер" + (" (12 бит)" if короткий else " (24 бита)"), "mp.sseq" if короткий else "mp.seq",
           номер, м + (0 if короткий else 1), 2 if короткий else 3, номер)
    у.длина = дл
    место = ("B" if первый else "") + ("E" if последний else "")
    у.итог = f"фрагмент {номер}" + (f" [{место}]" if место else "") + (", класс " + str(класс) if класс else "")
    р.п.инфо = "MP " + у.итог
    if первый and последний:
        ppp(р, м + дл, с_адресом=False)
    else:
        данные(р, м + дл, "фрагмент MP", конец)


def pap(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("PAP", "Password Authentication Protocol", м)
    р.нужно(м, 4)
    код, ид, длина = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    у.поле("Код", "pap.code", PAP_КОДЫ.get(код, str(код)), м, 1, код)
    у.поле("Идентификатор", "pap.identifier", ид, м + 1, 1)
    у.поле("Длина", "pap.length", длина, м + 2, 2)
    у.длина = длина
    у.итог = PAP_КОДЫ.get(код, f"код {код}")
    место = м + 4
    if код == 1:
        р.нужно(место, 1)
        дл = р.д[место]
        имя = _текст(р.д[место + 1:место + 1 + дл])
        у.поле("Имя (Peer-ID)", "pap.peer_id", имя, место, 1 + дл)
        место += 1 + дл
        р.нужно(место, 1)
        дл = р.д[место]
        пароль = _текст(р.д[место + 1:место + 1 + дл])
        у.поле("Пароль", "pap.password", пароль, место, 1 + дл)
        у.итог += f": «{имя}», пароль «{пароль}»"
    elif код in (2, 3) and длина > 4:
        р.нужно(место, 1)
        дл = р.д[место]
        сообщение = _текст(р.д[место + 1:место + 1 + дл])
        у.поле("Сообщение", "pap.message", сообщение, место, 1 + дл)
        у.итог += f": «{сообщение}»"
    р.п.инфо = "PAP " + у.итог


def chap(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("CHAP", "Challenge Handshake Authentication Protocol", м)
    р.нужно(м, 4)
    код, ид, длина = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    у.поле("Код", "chap.code", CHAP_КОДЫ.get(код, str(код)), м, 1, код)
    у.поле("Идентификатор", "chap.identifier", ид, м + 1, 1)
    у.поле("Длина", "chap.length", длина, м + 2, 2)
    у.итог = CHAP_КОДЫ.get(код, f"код {код}")
    if длина < 4:
        у.длина = 4
        у.итог += " (длина меньше 4)"
        р.п.инфо = "CHAP " + у.итог
        return
    у.длина = длина
    конец = min(конец, len(р.д), м + длина)
    место = м + 4
    if код in (1, 2) and место < конец:
        размер = р.д[место]
        if место + 1 + размер > конец:
            у.поле("Размер значения", "chap.value_size", f"{размер} (больше, чем осталось)", место, 1, размер)
            у.итог += " (размер значения испорчен)"
        else:
            у.поле("Размер значения", "chap.value_size", размер, место, 1)
            значение = р.д[место + 1:место + 1 + размер]
            у.поле("Значение", "chap.value", значение.hex(), место + 1, размер)
            имя = _текст(р.д[место + 1 + размер:конец])
            if имя:
                у.поле("Имя", "chap.name", имя, место + 1 + размер, конец - место - 1 - размер)
            у.итог += (f": «{имя}», " if имя else ": ") + f"значение {значение.hex()}"
    elif код in (3, 4) and место < конец:
        сообщение = _текст(р.д[место:конец])
        у.поле("Сообщение", "chap.message", сообщение, место, конец - место)
        у.итог += f": «{сообщение}»"
    р.п.инфо = "CHAP " + у.итог


def bap(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("BAP", "Bandwidth Allocation Protocol", м)
    р.нужно(м, 4)
    тип, ид, длина = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    у.поле("Тип", "bap.type", BAP_ТИПЫ.get(тип, str(тип)), м, 1, тип)
    у.поле("Идентификатор", "bap.identifier", ид, м + 1, 1)
    у.поле("Длина", "bap.length", длина, м + 2, 2)
    у.длина = длина
    у.итог = BAP_ТИПЫ.get(тип, f"тип {тип}")
    if тип in (2, 4, 6, 8) and длина >= 5:
        р.нужно(м + 4, 1)
        ответ = р.д[м + 4]
        у.поле("Код ответа", "bap.response_code", BAP_ОТВЕТЫ.get(ответ, str(ответ)), м + 4, 1, ответ)
        у.итог += f", {BAP_ОТВЕТЫ.get(ответ, ответ)}"
    р.п.инфо = "BAP " + у.итог


def eap_ppp(р: Разбор, м: int, конец: int) -> None:
    eap(р, м, конец)


for _номер, _разборщик in ((0x003D, mp), (0xC023, pap), (0xC223, chap), (0xC02D, bap), (0xC227, eap_ppp)):
    ДОП_PPP.setdefault(_номер, _разборщик)
