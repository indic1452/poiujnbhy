def _строка(б: bytes) -> str:
    return б.decode("latin-1").rstrip("\x00")


def _имя(формат: int, б: bytes, md: bool) -> str:
    """Имя MD или MA по формату 802.1Q 21.6.5 (и Y.1731, прил. A, для ICC)."""
    if md and формат == 3 and len(б) == 8:
        return f"{mac(б, 0)} / {u16(б, 6)}"
    if not md and формат in (1, 3) and len(б) == 2:
        return str(u16(б, 0))
    if not md and формат == 4 and len(б) == 7:
        return f"OUI {б[:3].hex(':')}, индекс {u32(б, 3)}"
    if формат in ((2, 4) if md else (2, 32, 33)):
        return _строка(б)
    return б.hex()


def _время(д: bytes, м: int) -> float:
    """Метка времени формата IEEE 1588: 32 бита секунд и 32 бита наносекунд."""
    return u32(д, м) + u32(д, м + 4) / 1e9


def _метки(у, д: bytes, м: int, имена) -> list:
    значения = []
    for i, (имя, ключ) in enumerate(имена):
        т = _время(д, м + 8 * i)
        значения.append(т)
        у.поле(имя, ключ, f"{т:.9f} с", м + 8 * i, 8, т)
    return значения


def _счётчики(у, д: bytes, м: int, имена) -> None:
    for i, (имя, ключ) in enumerate(имена):
        у.поле(имя, ключ, u32(д, м + 4 * i), м + 4 * i, 4)


def _maid(у, д: bytes, м: int, родитель) -> str:
    """MAID 48 байт: формат и имя MD (нет при формате 1), формат и имя MA; остаток — нули."""
    место, имя_md = м, ""
    формат_md = д[место]
    у.поле("Формат имени MD", "cfm.maid.md.name.format", ФОРМАТЫ_MD.get(формат_md, формат_md), место, 1,
           формат_md, родитель=родитель)
    место += 1
    if формат_md != 1:
        дл = д[место]
        имя_md = _имя(формат_md, д[место + 1:место + 1 + дл], True)
        у.поле("Имя MD", "cfm.maid.md.name", имя_md, место, 1 + дл, родитель=родитель)
        место += 1 + дл
    формат_ma, дл = д[место], д[место + 1]
    у.поле("Формат имени MA", "cfm.maid.ma.name.format", ФОРМАТЫ_MA.get(формат_ma, формат_ma), место, 1,
           формат_ma, родитель=родитель)
    имя_ma = _имя(формат_ma, д[место + 2:место + 2 + дл], False)
    у.поле("Имя MA", "cfm.maid.ma.name", имя_ma, место + 1, 1 + дл, родитель=родитель)
    if место + 2 + дл > м + 48:
        у.поле("Имена длиннее MAID (48 байт)", "cfm.maid.bad", "да", м, 48, плохо=True, родитель=родитель)
    return f"{имя_md}/{имя_ma}" if имя_md else имя_ma


def _tlv(р: Разбор, у, м: int, конец: int) -> list:
    д, виды = р.д, []
    while м < конец:
        вид = д[м]
        if вид == 0:
            у.поле("TLV End", "cfm.tlv.type", 0, м, 1)
            break
        if м + 3 > конец:
            break
        дл = u16(д, м + 1)
        if м + 3 + дл > конец:
            р.ошибка(f"CFM: TLV {TLV.get(вид, вид)} длиннее PDU")
            break
        знач = д[м + 3:м + 3 + дл]
        п = у.поле(f"TLV {TLV.get(вид, вид)}", "cfm.tlv.type", вид, м, 3 + дл)
        у.поле("Длина", "cfm.tlv.len", дл, м + 1, 2, родитель=п)
        виды.append(TLV.get(вид, str(вид)))
        x = м + 3
        if вид == 2 and дл >= 1:
            у.поле("Состояние порта", "cfm.tlv.port.status.value", ПОРТ.get(знач[0], знач[0]), x, 1, знач[0],
                   родитель=п)
        elif вид == 4 and дл >= 1:
            у.поле("Состояние интерфейса", "cfm.tlv.interface.status.value", ИНТЕРФЕЙС.get(знач[0], знач[0]),
                   x, 1, знач[0], родитель=п)
        elif вид in (5, 6) and дл >= 7:
            у.поле("Действие", "cfm.tlv.reply.action", (ВХОД if вид == 5 else ВЫХОД).get(знач[0], знач[0]),
                   x, 1, знач[0], родитель=п)
            у.поле("MAC", "cfm.tlv.reply.mac", mac(знач, 1), x + 1, 6, родитель=п)
        elif вид == 7 and дл >= 8:
            у.поле("Egress ID", "cfm.tlv.egress.id", f"{u16(знач, 0)} / {mac(знач, 2)}", x, 8, родитель=п)
        elif вид == 8 and дл >= 16:
            у.поле("Last Egress ID", "cfm.tlv.egress.last", f"{u16(знач, 0)} / {mac(знач, 2)}", x, 8,
                   родитель=п)
            у.поле("Next Egress ID", "cfm.tlv.egress.next", f"{u16(знач, 8)} / {mac(знач, 10)}", x + 8, 8,
                   родитель=п)
        elif вид == 1 and знач and знач[0] and дл >= 2 + знач[0]:
            шасси = знач[0]
            подтип, ид = знач[1], знач[2:2 + шасси]
            у.поле("Шасси", "cfm.tlv.chassis.id",
                   f"{ШАССИ.get(подтип, подтип)}: {mac(ид, 0) if подтип == 4 and шасси == 6 else _строка(ид)}",
                   x, 2 + шасси, родитель=п)
        elif вид == 31 and дл >= 4:
            у.поле("OUI", "cfm.tlv.org.oui", знач[:3].hex(":"), x, 3, родитель=п)
            у.поле("Подтип", "cfm.tlv.org.subtype", знач[3], x + 3, 1, родитель=п)
        elif вид == 32 and дл >= 1:
            у.поле("Образец", "cfm.tlv.tst.test.pattern.type", ОБРАЗЕЦ_TST.get(знач[0], знач[0]), x, 1, знач[0],
                   родитель=п)
        elif вид == 3:
            у.поле("Данные", "cfm.tlv.data.value", f"{дл} байт", x, дл, знач.hex(), родитель=п)
        м += 3 + дл
    return виды


def cfm(р: Разбор, м: int) -> None:
    д = р.д
    р.нужно(м, 4)
    у = р.уровень("CFM", "Connectivity Fault Management (IEEE 802.1ag / Y.1731)", м)
    уровень_md, версия, код, флаги, смещение = д[м] >> 5, д[м] & 0x1F, д[м + 1], д[м + 2], д[м + 3]
    имя = КОДЫ.get(код, f"код {код}")
    у.поле("Уровень MD", "cfm.md.level", уровень_md, м, 1)
    у.поле("Версия", "cfm.version", версия, м, 1)
    у.поле("Код", "cfm.opcode", f"{код} ({ПОЛНЫЕ.get(код, имя)})", м + 1, 1, код)
    п = у.поле("Флаги", "cfm.flags", f"0x{флаги:02x}", м + 2, 1, флаги)
    у.поле("Смещение первого TLV", "cfm.first.tlv.offset", смещение, м + 3, 1)
    тело, конец = м + 4, len(д)
    р.нужно(тело, смещение)
    подробно = ""
    if код == 1:
        # CCM: флаги RDI и интервал; номер, MEP ID, MAID, счётчики Y.1731.
        у.поле("RDI", "cfm.flags.RDI", флаги >> 7, м + 2, 1, родитель=п)
        у.поле("Интервал", "cfm.flags.Interval", ИНТЕРВАЛЫ[флаги & 7], м + 2, 1, флаги & 7, родитель=п)
        р.нужно(тело, 70)
        мep = u16(д, тело + 4) & 0x1FFF
        у.поле("Номер", "cfm.ccm.seq.num", u32(д, тело), тело, 4)
        у.поле("MEP ID", "cfm.ccm.mep.id", мep, тело + 4, 2)
        пм = у.поле("MAID", "cfm.ccm.maid", "", тело + 6, 48)
        maid = _maid(у, д, тело + 6, пм)
        пм.текст = пм.сырое = maid
        _счётчики(у, д, тело + 54, (("TxFCf", "cfm.ccm.itu.t.y1731.txfcf"), ("RxFCb", "cfm.ccm.itu.t.y1731.rxfcb"),
                                     ("TxFCb", "cfm.ccm.itu.t.y1731.txfcb")))
        подробно = f"MEP {мep}, MA {maid}, {ИНТЕРВАЛЫ[флаги & 7]}" + (", RDI" if флаги & 0x80 else "")
    elif код in (2, 3):
        р.нужно(тело, 4)
        у.поле("Номер транзакции", "cfm.lb.transaction.id", u32(д, тело), тело, 4)
        подробно = f"транзакция {u32(д, тело)}"
    elif код == 0:
        р.нужно(тело, 17)
        у.поле("UseFDBonly", "cfm.flags.UseFDBonly", флаги >> 7, м + 2, 1, родитель=п)
        у.поле("Номер транзакции", "cfm.lt.transaction.id", u32(д, тело), тело, 4)
        у.поле("TTL", "cfm.lt.ttl", д[тело + 4], тело + 4, 1)
        у.поле("Исходный MAC", "cfm.ltm.orig.addr", mac(д, тело + 5), тело + 5, 6)
        у.поле("Целевой MAC", "cfm.ltm.targ.addr", mac(д, тело + 11), тело + 11, 6)
        подробно = f"к {mac(д, тело + 11)}, TTL {д[тело + 4]}"
    elif код == 4:
        р.нужно(тело, 6)
        у.поле("FwdYes", "cfm.flags.FwdYes", (флаги >> 6) & 1, м + 2, 1, родитель=п)
        у.поле("TerminalMEP", "cfm.flags.TerminalMEP", (флаги >> 5) & 1, м + 2, 1, родитель=п)
        у.поле("Номер транзакции", "cfm.lt.transaction.id", u32(д, тело), тело, 4)
        у.поле("TTL", "cfm.lt.ttl", д[тело + 4], тело + 4, 1)
        у.поле("Действие реле", "cfm.ltr.relay.action", РЕЛЕ.get(д[тело + 5], д[тело + 5]), тело + 5, 1,
               д[тело + 5])
        подробно = f"TTL {д[тело + 4]}, {РЕЛЕ.get(д[тело + 5], д[тело + 5])}"
    elif код in (33, 35):
        у.поле("Период", "cfm.flags.Period", ПЕРИОД_AIS.get(флаги & 7, f"{флаги & 7} (неверный)"), м + 2, 1,
               флаги & 7, родитель=п)
        подробно = ПЕРИОД_AIS.get(флаги & 7, "")
    elif код == 52:
        вид = (флаги >> 3) & 7
        у.поле("Вид", "cfm.csf.flags.Type", CSF.get(вид, вид), м + 2, 1, вид, родитель=п)
        подробно = CSF.get(вид, str(вид))
    elif код == 37:
        р.нужно(тело, 4)
        у.поле("Номер", "cfm.tst.sequence.num", u32(д, тело), тело, 4)
        подробно = f"номер {u32(д, тело)}"
    elif код == 39:
        р.нужно(тело, 4)
        запрос = д[тело] >> 4
        у.поле("Запрос/состояние", "cfm.aps.req_st", APS.get(запрос, запрос), тело, 1, запрос)
        у.поле("Тип защиты (A B D R)", "cfm.aps.protec.type", f"{д[тело] & 0xF:04b}", тело, 1, д[тело] & 0xF)
        у.поле("Запрошенный сигнал", "cfm.aps.req_signal", д[тело + 1], тело + 1, 1)
        у.поле("Мостовой сигнал", "cfm.aps.bridged_signal", д[тело + 2], тело + 2, 1)
        у.поле("Тип моста", "cfm.aps.bridge_type", "широковещательный" if д[тело + 3] & 0x80 else "селектор",
               тело + 3, 1, д[тело + 3] >> 7)
        подробно = APS.get(запрос, str(запрос))
    elif код == 40:
        р.нужно(тело, 8)
        запрос, состояние = д[тело] >> 4, д[тело + 1]
        у.поле("Запрос/состояние", "cfm.raps.req_st", R_APS.get(запрос, запрос), тело, 1, запрос)
        у.поле("Подкод", "cfm.raps.event.subcode", д[тело] & 0xF, тело, 1)
        пс = у.поле("Состояние", "cfm.raps.status", f"0x{состояние:02x}", тело + 1, 1, состояние)
        for маска, имя_бита, ключ in ((0x80, "RPL заблокирован (RB)", "rb"), (0x40, "не сбрасывать (DNF)", "dnf"),
                                      (0x20, "BPR", "bpr")):
            у.поле(имя_бита, f"cfm.raps.status.{ключ}", int(bool(состояние & маска)), тело + 1, 1, родитель=пс)
        у.поле("Узел", "cfm.raps.node_id", mac(д, тело + 2), тело + 2, 6)
        подробно = f"{R_APS.get(запрос, запрос)}, узел {mac(д, тело + 2)}" + (", RB" if состояние & 0x80 else "")
    elif код in (42, 43):
        р.нужно(тело, 12)
        _счётчики(у, д, тело, (("TxFCf", "cfm.lmm.lmr.txfcf"), ("RxFCf", "cfm.lmm.lmr.rxfcf"),
                               ("TxFCb", "cfm.lmm.lmr.txfcb")))
        подробно = f"TxFCf {u32(д, тело)}"
    elif код == 45:
        р.нужно(тело, 16)
        _метки(у, д, тело, (("TxTimeStampf", "cfm.1dm.txtimestampf"), ("RxTimeStampf", "cfm.1dm.rxtimestampf")))
    elif код in (46, 47):
        р.нужно(тело, 32)
        tx_f, rx_f, tx_b, rx_b = _метки(у, д, тело, (
            ("TxTimeStampf", "cfm.dmm.dmr.txtimestampf"), ("RxTimeStampf", "cfm.dmm.dmr.rxtimestampf"),
            ("TxTimeStampb", "cfm.dmm.dmr.txtimestampb"), ("RxTimeStampb", "cfm.dmm.dmr.rxtimestampb")))
        if код == 46 and tx_f and rx_f and tx_b and rx_b:
            задержка = (rx_b - tx_f) - (tx_b - rx_f)
            у.поле("Задержка кадра (Y.1731, 8.2.2)", "cfm.dmr.delay", f"{задержка * 1e6:.3f} мкс", тело, 32,
                   задержка)
            подробно = f"задержка {задержка * 1e6:.3f} мкс"
    elif код in (53, 54, 55):
        р.нужно(тело, 16)
        у.поле("MEP источника", "cfm.slm.src_mep", u16(д, тело), тело, 2)
        if код == 54:
            у.поле("MEP ответчика", "cfm.slm.resp_mep", u16(д, тело + 2), тело + 2, 2)
        у.поле("Test ID", "cfm.slm.testid", u32(д, тело + 4), тело + 4, 4)
        у.поле("TxFCf", "cfm.slm.txfcf", u32(д, тело + 8), тело + 8, 4)
        if код == 54:
            у.поле("TxFCb", "cfm.slm.txfcb", u32(д, тело + 12), тело + 12, 4)
        подробно = f"MEP {u16(д, тело)}, тест {u32(д, тело + 4)}"
    виды = _tlv(р, у, тело + смещение, конец)
    у.длина = конец - м
    у.итог = f"{имя}, уровень MD {уровень_md}" + (f", {подробно}" if подробно else "") \
        + (f"; TLV: {', '.join(виды)}" if виды else "")
    р.п.инфо = "CFM " + у.итог


# -- ERSPAN -------------------------------------------------------------------------------

ИНКАПСУЛЯЦИЯ = {0: "без метки VLAN", 1: "была ISL", 2: "была 802.1Q", 3: "метка VLAN сохранена в кадре"}
BSO = {0: "целый или неизвестно", 1: "короткий кадр", 2: "слишком длинный кадр", 3: "ошибка CRC или выравнивания"}
ТОЧНОСТЬ = {0: "100 мкс", 1: "100 нс", 2: "IEEE 1588", 3: "своя"}
ВИД_КАДРА = {0: "Ethernet", 2: "IP"}


def _бит_s_gre(р: Разбор) -> bool:
    """Бит S (есть номер) заголовка GRE, под которым лежит ERSPAN; без GRE — считаем, что номер есть."""
    у = р.п.уровни[-1] if р.п.уровни else None
    if у is None or у.протокол != "GRE":
        return True
    return bool(у.поля[0].сырое & 0x1000)


def erspan(р: Разбор, м: int) -> None:
    д = р.д
    номер_есть = _бит_s_gre(р)
    у = р.уровень("ERSPAN", "Cisco Encapsulated Remote SPAN", м)
    if not номер_есть:
        у.итог = "тип I (без заголовка)"
        р.п.инфо = "ERSPAN " + у.итог
        ethernet(р, м)
        return
    р.нужно(м, 8)
    версия, vlan, слово = д[м] >> 4, u16(д, м) & 0x0FFF, u16(д, м + 2)
    сеанс = слово & 0x03FF
    у.поле("Версия", "erspan.version", {1: "1 (тип II)", 2: "2 (тип III)"}.get(версия, версия), м, 2, версия)
    у.поле("VLAN", "erspan.vlan", vlan, м, 2)
    у.поле("CoS", "erspan.cos", слово >> 13, м + 2, 2)
    усечён = (слово >> 10) & 1
    место, вид_кадра, итог = м + 8, 0, ""
    if версия == 1:
        инк = (слово >> 11) & 3
        у.поле("Исходная инкапсуляция", "erspan.encap", ИНКАПСУЛЯЦИЯ[инк], м + 2, 2, инк)
        у.поле("Усечён", "erspan.truncated", усечён, м + 2, 2)
        у.поле("Сеанс", "erspan.spanid", сеанс, м + 2, 2)
        у.поле("Индекс порта", "erspan.index", u32(д, м + 4) & 0xFFFFF, м + 4, 4)
        итог = f"тип II, сеанс {сеанс}, VLAN {vlan}"
    elif версия == 2:
        р.нужно(м, 12)
        bso = (слово >> 11) & 3
        у.поле("Целостность (BSO)", "erspan.bso", BSO[bso], м + 2, 2, bso)
        у.поле("Усечён", "erspan.truncated", усечён, м + 2, 2)
        у.поле("Сеанс", "erspan.spanid", сеанс, м + 2, 2)
        флаги = u16(д, м + 10)
        точность = (флаги >> 1) & 3
        у.поле("Отметка времени", "erspan.timestamp", f"{u32(д, м + 4)} × {ТОЧНОСТЬ[точность]}", м + 4, 4,
               u32(д, м + 4))
        у.поле("SGT", "erspan.sgt", u16(д, м + 8), м + 8, 2)
        вид_кадра = (флаги >> 10) & 0x1F
        у.поле("P (кадр с преамбулой)", "erspan.p", флаги >> 15, м + 10, 2)
        у.поле("Вид кадра", "erspan.ft", ВИД_КАДРА.get(вид_кадра, вид_кадра), м + 10, 2, вид_кадра)
        у.поле("Hw ID", "erspan.hw", (флаги >> 4) & 0x3F, м + 10, 2)
        у.поле("Направление", "erspan.direction", "выход" if флаги & 8 else "вход", м + 10, 2, (флаги >> 3) & 1)
        у.поле("Точность отметки", "erspan.granularity", ТОЧНОСТЬ[точность], м + 10, 2, точность)
        место = м + 12
        if флаги & 1:
            р.нужно(место, 8)
            у.поле("Платформенный подзаголовок", "erspan.platid", f"платформа {д[место] >> 2}", место, 8,
                   д[место] >> 2)
            место += 8
        итог = f"тип III, сеанс {сеанс}, VLAN {vlan}, {'выход' if флаги & 8 else 'вход'}"
    else:
        р.ошибка(f"ERSPAN: неизвестная версия {версия}")
        итог = f"версия {версия}"
    у.длина = место - м
    у.итог = итог + (", усечён" if усечён else "")
    р.п.инфо = "ERSPAN " + у.итог
    if версия not in (1, 2):
        данные(р, место, "ERSPAN")
    elif вид_кадра == 2:
        (ipv6 if место < len(д) and д[место] >> 4 == 6 else ipv4)(р, место)
    elif вид_кадра == 0:
        ethernet(р, место)
    else:
        данные(р, место, f"ERSPAN: вид кадра {вид_кадра}")


# -- Juniper Packet Mirror ----------------------------------------------------------------

def jmirror(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    начало = д[м + 8:min(м + 12, конец)]
    if len(начало) != 4:
        return False
    б0, б1, б2, б3 = начало
    if б0 == 0x45:
        дальше = ipv4
    elif б0 >> 4 == 6:
        дальше = ipv6
    elif б0 == 0xFF and б1 == 0x03 and (б2 & 0x0F == 0 and б3 == 0x21 or б2 == 0 and б3 == 0x57):
        дальше = ppp
    else:
        return False
    у = р.уровень("Jmirror", "Juniper Packet Mirror", м)
    mid, sid = u32(д, м), u32(д, м + 4)
    у.поле("Идентификатор перехвата (MID)", "jmirror.mid", f"0x{mid:08x}", м, 4, mid)
    у.поле("Идентификатор сеанса (SID)", "jmirror.sid", f"0x{sid:08x}", м + 4, 4, sid)
    у.длина = 8
    у.итог = f"MID 0x{mid:08x}, SID 0x{sid:08x}"
    р.п.инфо = "Jmirror " + у.итог
    дальше(р, м + 8)
    return True


