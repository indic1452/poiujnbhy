"""Морская навигация: NMEA 0183 по UDP (!AIVDM/!AIVDO и $-предложения) и сообщения AIS.

NMEA 0183: предложение «!» или «$», поля через запятую, «*HH» — сумма: XOR всех знаков между
начальным знаком и «*». AIVDM: число частей, номер части, номер последовательности, канал,
полезная часть («броня» 6 бит на знак), число заполняющих бит. Многочастные сообщения
собираются в пределах пакета. Поля сообщения AIS — ``potok.ais`` (раскладка pyais / gpsd).
Канал «AIS» — сам кадр сообщения (из потока после HDLC): биты — байты старшим битом вперёд.
"""

from __future__ import annotations

import numpy as np

from ...potok import ais as ais_коды
from ..prilozh import КАК, ЭВРИСТИКИ_UDP
from ..razbor import ДОП_УРОВНИ, КАНАЛ_В_РАЗБОРЩИК, Разбор, Уровень

#: Не больше стольких байт нагрузки считаются текстом NMEA.
NMEA_ДО = 4096


def сумма_nmea(тело: str) -> int:
    итог = 0
    for с in тело:
        итог ^= ord(с)
    return итог


def _поля_ais(у: Уровень, п: dict[str, object], м: int, длина: int) -> None:
    у.поле("Тип сообщения", "ais.type", f"{п['тип']} ({ais_коды.ТИПЫ.get(int(п['тип']), 'другой')})", м, длина,
           п["тип"])
    у.поле("MMSI", "ais.mmsi", п["mmsi"], м, длина)
    for ключ, имя, поле_ in (("название", "Название", "ais.name"), ("позывной", "Позывной", "ais.callsign"),
                             ("тип_судна", "Тип судна", "ais.ship_type"), ("назначение", "Назначение", "ais.destination"),
                             ("состояние", "Состояние", "ais.status"), ("время", "Время", "ais.time")):
        if п.get(ключ):
            у.поле(имя, поле_, п[ключ], м, длина)
    if п.get("координаты"):
        широта, долгота = п["координаты"]
        у.поле("Широта", "ais.lat", f"{широта:.6f}", м, длина, широта)
        у.поле("Долгота", "ais.lon", f"{долгота:.6f}", м, длина, долгота)
    for ключ, имя, поле_ in (("скорость", "Скорость, уз", "ais.speed"), ("курс", "Курс, °", "ais.course")):
        if п.get(ключ) is not None:
            у.поле(имя, поле_, п[ключ], м, длина)
    у.итог = ais_коды.описание(п)


def ais_канал(р: Разбор, м: int) -> None:
    """Кадр сообщения AIS (из потока, после HDLC и FCS)."""
    у = р.уровень("AIS", "AIS (ITU-R M.1371)", м)
    р.нужно(м, 5)
    п = ais_коды.разобрать(np.unpackbits(np.frombuffer(р.д[м:], dtype=np.uint8)))
    у.длина = len(р.д) - м
    if п is None:
        у.итог = "сообщение AIS не разобрано (мало бит для своего типа)"
    else:
        _поля_ais(у, п, м, у.длина)
    р.п.инфо = "AIS " + у.итог


def nmea_udp(р: Разбор, м: int, конец: int) -> bool:
    """Предложения NMEA 0183 в UDP: верная «*HH» у каждого; AIVDM/AIVDO — сообщения AIS."""
    if not 8 <= конец - м <= NMEA_ДО or р.д[м] not in b"!$":
        return False
    try:
        текст = р.д[м:конец].decode("ascii")
    except UnicodeDecodeError:
        return False
    строки = [с for с in текст.replace("\r", "").split("\n") if с]
    разобранные = []
    for строка in строки:
        if строка[0] not in "!$" or len(строка) < 4 or строка[-3] != "*":
            return False
        try:
            сумма = int(строка[-2:], 16)
        except ValueError:
            return False
        if сумма != сумма_nmea(строка[1:-3]):
            return False
        разобранные.append(строка)
    у = р.уровень("NMEA", "NMEA 0183", м)
    у.длина = конец - м
    виды: list[str] = []
    части: dict[str, list[str]] = {}
    сообщения: list[dict[str, object]] = []
    for строка in разобранные:
        поля = строка[1:-3].split(",")
        вид = поля[0]
        виды.append(вид)
        у.поле(f"Предложение {вид}", "nmea.sentence", строка, м, конец - м, вид)
        if вид[2:] in ("VDM", "VDO") and len(поля) >= 7:
            всего, номер, ключ = поля[1], поля[2], поля[3] + поля[4]
            части.setdefault(ключ, []).append(поля[5])
            if номер == всего:
                try:
                    заполнение = int(поля[6] or 0)
                except ValueError:
                    заполнение = 0
                п = ais_коды.разобрать(ais_коды.из_nmea("".join(части.pop(ключ)), заполнение))
                if п is not None:
                    сообщения.append(п)
    у.итог = f"{len(разобранные)} предложений: " + ", ".join(dict.fromkeys(виды))
    for п in сообщения:
        а = р.уровень("AIS", "AIS (ITU-R M.1371)", м)
        а.длина = конец - м
        _поля_ais(а, п, м, конец - м)
    р.п.инфо = ("AIS " + "; ".join(ais_коды.описание(п) for п in сообщения)) if сообщения else "NMEA " + у.итог
    return True


КАНАЛ_В_РАЗБОРЩИК.setdefault("AIS", ais_канал)
if nmea_udp not in ЭВРИСТИКИ_UDP:
    ЭВРИСТИКИ_UDP.append(nmea_udp)
КАК["udp"].setdefault("NMEA/AIS", nmea_udp)
for _имя in ("NMEA", "AIS"):
    ДОП_УРОВНИ.setdefault(_имя, "прикладной")
