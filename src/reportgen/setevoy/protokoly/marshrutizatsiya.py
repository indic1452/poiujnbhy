def _на_порт(таблица: dict, порт: int, разборщик: Callable) -> None:
    """Порт уже занят другим модулем — пробуем оба: сначала прежний, потом свой."""
    прежний = таблица.get(порт)
    if прежний is None:
        таблица[порт] = разборщик
        return

    def оба(р: Разбор, м: int, конец: int) -> bool:
        уровней = len(р.п.уровни)
        try:
            if прежний(р, м, конец):
                return True
        except (Мало, IndexError, ValueError, struct.error):
            pass
        del р.п.уровни[уровней:]
        return разборщик(р, м, конец)

    таблица[порт] = оба


