class _Не(Exception):
    """Данные не этого протокола (или разобрать их по стандарту нельзя)."""


def _нужно(место: int, сколько: int, конец: int) -> None:
    if место + сколько > конец:
        raise _Не("данные короче структуры")


def _строго(функция: Callable) -> Callable:
    """Разборщик по порту: чужие данные — False и ни одного оставленного уровня."""
    @functools.wraps(функция)
    def обёртка(р: Разбор, м: int, конец: int, *арг, **имен) -> bool:
        уровней = len(р.п.уровни)
        try:
            if функция(р, м, конец, *арг, **имен):
                return True
        except _Не:
            pass
        del р.п.уровни[уровней:]
        return False
    return обёртка


def _дальше(р: Разбор, функция: Callable, *арг) -> None:
    """Вложенный протокол: его обрыв не отменяет уже разобранный внешний уровень."""
    try:
        функция(р, *арг)
    except Мало:
        р.ошибка("пакет оборван: заголовок длиннее записанных байт")
        if р.п.уровни:
            р.п.уровни[-1].итог += " [оборван]"


def _попробовать(р: Разбор, функция: Callable, м: int, конец: int, что: str) -> None:
    """Вложенный разборщик прикладного уровня; не подошёл — нагрузка остаётся данными."""
    уровней = len(р.п.уровни)
    try:
        if функция(р, м, конец):
            return
    except (Мало, IndexError, ValueError, struct.error):
        pass
    del р.п.уровни[уровней:]
    данные(р, м, что, конец)


def _не_моё(р: Разбор, м: int, конец: int, имя: str, причина: str) -> None:
    """Номер протокола IP есть, а данные не сходятся: показываем байтами, с пометкой."""
    р.ошибка(f"{имя}: {причина} — не разобрано как {имя}")
    данные(р, м, f"протокол IP ({имя}?)", конец)


def _ip_уровень(р: Разбор) -> Уровень | None:
    for у in reversed(р.п.уровни):
        if у.протокол in ("IPv4", "IPv6"):
            return у
    return None


def _псевдо(р: Разбор) -> tuple[bytes, int] | None:
    """Адреса объемлющего IP для псевдозаголовка (разборщики ДОП_IP его не получают)."""
    у = _ip_уровень(р)
    if у is None:
        return None
    if у.протокол == "IPv4":
        return р.д[у.смещение + 12:у.смещение + 20], 4
    return р.д[у.смещение + 8:у.смещение + 40], 6


def _обрезан(р: Разбор, конец: int) -> bool:
    """IP объявляет больше байт, чем записано: сумму по всему сообщению не проверить."""
    у = _ip_уровень(р)
    if у is None:
        return False
    if у.протокол == "IPv4":
        объявлено = у.смещение + u16(р.д, у.смещение + 2)
    else:
        объявлено = у.смещение + 40 + u16(р.д, у.смещение + 4)
    return объявлено > конец


def _сумма_псевдо(псевдо: tuple[bytes, int], протокол: int, длина: int, покрыто: bytes) -> int:
    """Сумма RFC 1071 с псевдозаголовком IPv4 (RFC 768) или IPv6 (RFC 8200, 8.1)."""
    адреса, версия = псевдо
    if версия == 4:
        заголовок = адреса + struct.pack(">BBH", 0, протокол, длина & 0xFFFF)
    else:
        заголовок = адреса + struct.pack(">IxxxB", длина, протокол)
    return сумма16(заголовок + покрыто)


def _ip_целый(д: bytes, м: int, конец: int, *, только6: bool = False) -> bool:
    """Вложенный пакет IP ровно до конца данных: IPv4 — длина и сумма заголовка, IPv6 — длина."""
    if м >= конец:
        return False
    версия = д[м] >> 4
    if версия == 4 and not только6:
        ihl = (д[м] & 15) * 4
        return (ihl >= 20 and конец - м >= ihl and u16(д, м + 2) == конец - м
                and сумма16(д[м:м + ihl]) == 0)
    if версия == 6:
        return конец - м >= 40 and 40 + u16(д, м + 4) == конец - м
    return False


def _текст(данные_: bytes) -> str:
    return данные_.decode("utf-8", "replace")


def _флаги(у: Уровень, п, место: int, длина: int, значение: int, биты) -> None:
    """Биты флагов — детьми поля: (подпись, ключ, номер бита)."""
    for подпись, ключ, бит in биты:
        у.поле(подпись, ключ, (значение >> бит) & 1, место, длина, родитель=п)


# == PIM (RFC 7761) ======================================================================

PIM_ТИПЫ = {0: "Hello", 1: "Register", 2: "Register-Stop", 3: "Join/Prune", 4: "Bootstrap",
            5: "Assert", 6: "Graft", 7: "Graft-Ack", 8: "Candidate-RP-Advertisement"}
PIM_ОПЦИИ = {1: "Holdtime", 2: "LAN Prune Delay", 19: "DR Priority", 20: "Generation ID",
             24: "Address List"}


def _pim_адрес(р: Разбор, место: int, конец: int, вид: str):
    """Закодированный адрес (RFC 7761, 4.9.1): вид «u» — одноадресный, «g» — группа, «s» — источник.

    Возвращает (адрес, маска, флаги, длина). Семейство — 1 (IPv4) или 2 (IPv6), кодировка 0.
    """
    д = р.д
    р.нужно(место, 2)
    семейство, кодировка = д[место], д[место + 1]
    n = {1: 4, 2: 16}.get(семейство)
    if n is None or кодировка != 0:
        raise _Не(f"закодированный адрес: семейство {семейство}, кодировка {кодировка} не разбираются")
    заголовок = 2 if вид == "u" else 4
    р.нужно(место, заголовок + n)
    if место + заголовок + n > конец:
        raise _Не("закодированный адрес выходит за сообщение")
    адрес = ip4(д, место + заголовок) if n == 4 else ip6(д, место + заголовок)
    if вид == "u":
        return адрес, None, None, заголовок + n
    return адрес, д[место + 3], д[место + 2], заголовок + n


def _pim_поле_адреса(у: Уровень, место: int, разбор, вид: str, подпись: str, ключ: str, родитель=None):
    адрес, маска, флаги, длина = разбор
    if вид == "u":
        return у.поле(f"{подпись}: {адрес}", ключ, адрес, место, длина, родитель=родитель)
    п = у.поле(f"{подпись}: {адрес}/{маска}", ключ, адрес, место, длина, родитель=родитель)
    у.поле("Длина маски", ключ + ".mask_len", маска, место + 3, 1, родитель=п)
    if вид == "g":
        _флаги(у, п, место + 2, 1, флаги, (("Двунаправленная (B)", "pim.group.bidir", 7),
                                           ("Зона (Z)", "pim.group.admin_scope", 0)))
    else:
        _флаги(у, п, место + 2, 1, флаги, (("Разреженный режим (S)", "pim.src_flags.s", 2),
                                           ("Шаблон (W)", "pim.src_flags.w", 1),
                                           ("Дерево RP (R)", "pim.src_flags.r", 0)))
    return п


def pim(р: Разбор, м: int, конец: int) -> None:
    """PIM (RFC 7761, разд. 4.9): версия 2, тип, сумма — по всему сообщению.

    Сумма — RFC 1071; для IPv6 — с псевдозаголовком (протокол 103). У Register сумма
    берётся только по первым 8 байтам (для IPv6 длина в псевдозаголовке — 8); по
    RFC 7761, 4.9.3 принимается и сумма по всему сообщению.
    """
    д = р.д
    if конец - м < 4 or д[м] >> 4 != 2:
        _не_моё(р, м, конец, "PIM", "версия не 2 или сообщение короче заголовка")
        return
    тип, сумма = д[м] & 15, u16(д, м + 2)
    if _обрезан(р, конец):
        if тип not in PIM_ТИПЫ:
            _не_моё(р, м, конец, "PIM", f"неизвестный тип {тип}")
            return
        состояние = "не проверена: пакет оборван"
    else:
        псевдо = _псевдо(р)

        def сходится(n: int) -> bool:
            if м + n > конец:
                return False
            if псевдо is not None and псевдо[1] == 6:
                return _сумма_псевдо(псевдо, 103, n, д[м:м + n]) == 0
            return сумма16(д[м:м + n]) == 0

        if сходится(конец - м):
            состояние = "верна"
        elif тип == 1 and сходится(8):
            состояние = "верна (по заголовку Register)"
        else:
            _не_моё(р, м, конец, "PIM", "контрольная сумма не сошлась")
            return
    у = р.уровень("PIM", "Protocol Independent Multicast", м)
    имя = PIM_ТИПЫ.get(тип, f"тип {тип}")
    у.поле("Версия", "pim.version", 2, м, 1)
    у.поле("Тип", "pim.type", f"{тип} ({PIM_ТИПЫ.get(тип, 'неизвестный')})", м, 1, тип)
    у.поле("Зарезервировано", "pim.reserved", f"0x{д[м + 1]:02x}", м + 1, 1, д[м + 1])
    у.поле("Контрольная сумма", "pim.checksum", f"0x{сумма:04x} [{состояние}]", м + 2, 2, сумма)
    у.длина = конец - м
    у.итог = имя
    р.п.инфо = "PIM " + имя
    разбор = {0: _pim_hello, 1: _pim_register, 2: _pim_register_stop, 3: _pim_join, 4: _pim_bootstrap,
              5: _pim_assert, 6: _pim_join, 7: _pim_join, 8: _pim_crp}.get(тип)
    if разбор is None:
        if м + 4 < конец:
            у.поле("Тело", "pim.data", д[м + 4:конец].hex(), м + 4, конец - м - 4)
        return
    try:
        разбор(р, у, м + 4, конец)
    except _Не as причина:
        р.ошибка(f"PIM: {причина}")
    if тип != 1:
        р.п.инфо = "PIM " + у.итог


def _pim_hello(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    д = р.д
    место, сведения = м, []
    while место < конец:
        р.нужно(место, 4)
        тип, дл = u16(д, место), u16(д, место + 2)
        if место + 4 + дл > конец:
            raise _Не("опция Hello выходит за сообщение")
        р.нужно(место + 4, дл)
        имя = PIM_ОПЦИИ.get(тип, f"опция {тип}")
        п = у.поле(имя, "pim.option", имя, место, 4 + дл, тип)
        у.поле("Тип", "pim.option_type", тип, место, 2, родитель=п)
        у.поле("Длина", "pim.option_length", дл, место + 2, 2, родитель=п)
        т = место + 4
        if тип == 1 and дл == 2:
            время = u16(д, т)
            у.поле("Время удержания, с", "pim.holdtime", "бесконечно" if время == 0xFFFF else время, т, 2, время,
                   родитель=п)
            сведения.append(f"удержание {время} с")
        elif тип == 2 and дл == 4:
            у.поле("Бит T", "pim.lan_prune_delay.t", д[т] >> 7, т, 1, родитель=п)
            у.поле("Задержка распространения, мс", "pim.propagation_delay", u16(д, т) & 0x7FFF, т, 2, родитель=п)
            у.поле("Интервал переопределения, мс", "pim.override_interval", u16(д, т + 2), т + 2, 2, родитель=п)
        elif тип == 19 and дл == 4:
            у.поле("Приоритет DR", "pim.dr_priority", u32(д, т), т, 4, родитель=п)
            сведения.append(f"приоритет DR {u32(д, т)}")
        elif тип == 20 and дл == 4:
            у.поле("Generation ID", "pim.generation_id", f"0x{u32(д, т):08x}", т, 4, u32(д, т), родитель=п)
        elif тип == 24:
            а = т
            while а < т + дл:
                разбор = _pim_адрес(р, а, т + дл, "u")
                _pim_поле_адреса(у, а, разбор, "u", "Вторичный адрес", "pim.address_list", родитель=п)
                а += разбор[3]
        elif дл:
            у.поле("Значение", "pim.option_value", д[т:т + дл].hex(), т, дл, родитель=п)
        место += 4 + дл
    у.итог = "Hello" + (", " + ", ".join(сведения) if сведения else "")


def _pim_register(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    д = р.д
    р.нужно(м, 4)
    флаги = u32(д, м)
    п = у.поле("Флаги Register", "pim.register_flags", f"0x{флаги:08x}", м, 4, флаги)
    у.поле("Граничный (B)", "pim.register_flags.border", флаги >> 31, м, 1, родитель=п)
    у.поле("Пустой, Null-Register (N)", "pim.register_flags.null", (флаги >> 30) & 1, м, 1, родитель=п)
    у.длина = 8
    у.итог = "Register" + (", Null-Register" if (флаги >> 30) & 1 else "")
    р.п.инфо = "PIM " + у.итог
    if м + 4 < конец:
        _дальше(р, голый_ip, м + 4)


def _pim_register_stop(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    группа = _pim_адрес(р, м, конец, "g")
    _pim_поле_адреса(у, м, группа, "g", "Группа", "pim.group")
    источник = _pim_адрес(р, м + группа[3], конец, "u")
    _pim_поле_адреса(у, м + группа[3], источник, "u", "Источник", "pim.source")
    у.итог = f"Register-Stop, группа {группа[0]}, источник {источник[0]}"


def _pim_join(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    """Join/Prune (RFC 7761, 4.9.5); Graft и Graft-Ack (RFC 3973) — тот же формат."""
    д = р.д
    сосед = _pim_адрес(р, м, конец, "u")
    _pim_поле_адреса(у, м, сосед, "u", "Сосед выше по дереву", "pim.upstream_neighbor")
    место = м + сосед[3]
    р.нужно(место, 4)
    групп, удержание = д[место + 1], u16(д, место + 2)
    у.поле("Групп", "pim.numgroups", групп, место + 1, 1)
    у.поле("Время удержания, с", "pim.holdtime", удержание, место + 2, 2)
    место += 4
    присоединено = отсечено = 0
    for _ in range(групп):
        начало = место
        группа = _pim_адрес(р, место, конец, "g")
        п = _pim_поле_адреса(у, место, группа, "g", "Группа", "pim.group")
        место += группа[3]
        р.нужно(место, 4)
        joins, prunes = u16(д, место), u16(д, место + 2)
        у.поле("Присоединяемых источников", "pim.numjoins", joins, место, 2, родитель=п)
        у.поле("Отсекаемых источников", "pim.numprunes", prunes, место + 2, 2, родитель=п)
        место += 4
        for i in range(joins + prunes):
            источник = _pim_адрес(р, место, конец, "s")
            if i < joins:
                _pim_поле_адреса(у, место, источник, "s", "Присоединить источник", "pim.join_src", родитель=п)
            else:
                _pim_поле_адреса(у, место, источник, "s", "Отсечь источник", "pim.prune_src", родитель=п)
            место += источник[3]
        п.длина = место - начало
        присоединено += joins
        отсечено += prunes
    if место != конец:
        raise _Не("группы Join/Prune не сходятся с длиной сообщения")
    у.итог = f"{у.итог}, групп {групп}, присоединить {присоединено}, отсечь {отсечено}"


def _pim_assert(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    д = р.д
    группа = _pim_адрес(р, м, конец, "g")
    _pim_поле_адреса(у, м, группа, "g", "Группа", "pim.group")
    место = м + группа[3]
    источник = _pim_адрес(р, место, конец, "u")
    _pim_поле_адреса(у, место, источник, "u", "Источник", "pim.source")
    место += источник[3]
    р.нужно(место, 8)
    слово = u32(д, место)
    у.поле("Дерево RP (R)", "pim.rpt", слово >> 31, место, 1)
    у.поле("Предпочтение метрики", "pim.metric_pref", слово & 0x7FFFFFFF, место, 4)
    у.поле("Метрика", "pim.metric", u32(д, место + 4), место + 4, 4)
    у.итог = f"Assert, группа {группа[0]}, источник {источник[0]}, метрика {u32(д, место + 4)}"


def _pim_bootstrap(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    """Bootstrap (RFC 5059, 4.1): метка фрагмента, маска хеша, приоритет и адрес BSR, группы с RP."""
    д = р.д
    р.нужно(м, 4)
    у.поле("Метка фрагмента", "pim.bsr_fragment_tag", u16(д, м), м, 2)
    у.поле("Длина маски хеша", "pim.hash_mask_len", д[м + 2], м + 2, 1)
    у.поле("Приоритет BSR", "pim.bsr_priority", д[м + 3], м + 3, 1)
    bsr = _pim_адрес(р, м + 4, конец, "u")
    _pim_поле_адреса(у, м + 4, bsr, "u", "Адрес BSR", "pim.bsr_address")
    место, групп = м + 4 + bsr[3], 0
    while место < конец:
        начало = место
        группа = _pim_адрес(р, место, конец, "g")
        п = _pim_поле_адреса(у, место, группа, "g", "Группа", "pim.group")
        место += группа[3]
        р.нужно(место, 4)
        у.поле("RP всего", "pim.rp_count", д[место], место, 1, родитель=п)
        у.поле("RP в этом фрагменте", "pim.frag_rp_count", д[место + 1], место + 1, 1, родитель=п)
        rp_здесь = д[место + 1]
        место += 4
        for _ in range(rp_здесь):
            rp = _pim_адрес(р, место, конец, "u")
            к = _pim_поле_адреса(у, место, rp, "u", "RP", "pim.rp_address", родитель=п)
            место += rp[3]
            р.нужно(место, 4)
            у.поле("Время удержания RP, с", "pim.rp_holdtime", u16(д, место), место, 2, родитель=к)
            у.поле("Приоритет RP", "pim.rp_priority", д[место + 2], место + 2, 1, родитель=к)
            место += 4
        п.длина = место - начало
        групп += 1
    у.итог = f"Bootstrap, BSR {bsr[0]}, групп {групп}"


def _pim_crp(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    """Candidate-RP-Advertisement (RFC 5059, 4.2)."""
    д = р.д
    р.нужно(м, 4)
    префиксов = д[м]
    у.поле("Префиксов групп", "pim.prefix_count", префиксов, м, 1)
    у.поле("Приоритет", "pim.priority", д[м + 1], м + 1, 1)
    у.поле("Время удержания, с", "pim.holdtime", u16(д, м + 2), м + 2, 2)
    rp = _pim_адрес(р, м + 4, конец, "u")
    _pim_поле_адреса(у, м + 4, rp, "u", "RP", "pim.rp_address")
    место = м + 4 + rp[3]
    for _ in range(префиксов):
        группа = _pim_адрес(р, место, конец, "g")
        _pim_поле_адреса(у, место, группа, "g", "Группа", "pim.group")
        место += группа[3]
    у.итог = f"Candidate-RP-Advertisement, RP {rp[0]}"


# == EIGRP (RFC 7868) ====================================================================

EIGRP_ОПКОДЫ = {1: "Update", 2: "Request", 3: "Query", 4: "Reply", 5: "Hello", 10: "SIA-Query",
                11: "SIA-Reply"}
EIGRP_TLV = {0x0001: "Parameters", 0x0002: "Authentication", 0x0003: "Sequence", 0x0004: "Software Version",
             0x0005: "Next Multicast Sequence", 0x0007: "Peer Termination", 0x0008: "Peer TID List",
             0x0102: "IPv4 Internal Route", 0x0103: "IPv4 External Route", 0x0402: "IPv6 Internal Route",
             0x0403: "IPv6 External Route"}


def eigrp(р: Разбор, м: int, конец: int) -> None:
    """EIGRP (RFC 7868, разд. 6.4): версия 2, опкод, сумма RFC 1071 по всему пакету, TLV деревом."""
    д = р.д
    if конец - м < 20 or д[м] != 2 or д[м + 1] not in EIGRP_ОПКОДЫ:
        _не_моё(р, м, конец, "EIGRP", "версия не 2, неизвестный опкод или пакет короче заголовка")
        return
    сумма = u16(д, м + 2)
    if _обрезан(р, конец):
        состояние = "не проверена: пакет оборван"
    elif сумма16(д[м:конец]) == 0:
        состояние = "верна"
    else:
        _не_моё(р, м, конец, "EIGRP", "контрольная сумма не сошлась")
        return
    опкод, флаги = д[м + 1], u32(д, м + 4)
    у = р.уровень("EIGRP", "Enhanced Interior Gateway Routing Protocol", м)
    у.поле("Версия", "eigrp.version", 2, м, 1)
    у.поле("Опкод", "eigrp.opcode", f"{опкод} ({EIGRP_ОПКОДЫ[опкод]})", м + 1, 1, опкод)
    у.поле("Контрольная сумма", "eigrp.checksum", f"0x{сумма:04x} [{состояние}]", м + 2, 2, сумма)
    п = у.поле("Флаги", "eigrp.flags", f"0x{флаги:08x}", м + 4, 4, флаги)
    _флаги(у, п, м + 4, 4, флаги, (("Начало (INIT)", "eigrp.flags.init", 0),
                                   ("Условный приём (CR)", "eigrp.flags.condrecv", 1),
                                   ("Перезапуск (RS)", "eigrp.flags.restart", 2),
                                   ("Конец таблицы (EOT)", "eigrp.flags.eot", 3)))
    у.поле("Номер", "eigrp.seq", u32(д, м + 8), м + 8, 4)
    у.поле("Подтверждение", "eigrp.ack", u32(д, м + 12), м + 12, 4)
    у.поле("Виртуальный маршрутизатор", "eigrp.vrid", u16(д, м + 16), м + 16, 2)
    у.поле("Автономная система", "eigrp.as", u16(д, м + 18), м + 18, 2)
    у.длина = конец - м
    имя = EIGRP_ОПКОДЫ[опкод]
    if опкод == 5 and u32(д, м + 12) and конец - м == 20:
        имя = "Hello (подтверждение)"
    у.итог = f"{имя}, AS {u16(д, м + 18)}"
    р.п.инфо = "EIGRP " + у.итог
    место, маршруты = м + 20, []
    while место < конец:
        р.нужно(место, 4)
        тип, дл = u16(д, место), u16(д, место + 2)
        if дл < 4 or место + дл > конец:
            р.ошибка("EIGRP: TLV не сходится с длиной пакета")
            break
        р.нужно(место, дл)
        имя_tlv = EIGRP_TLV.get(тип, f"TLV 0x{тип:04x}")
        т = у.поле(имя_tlv, "eigrp.tlv_type", f"0x{тип:04x} ({EIGRP_TLV.get(тип, 'неизвестный')})", место, дл, тип)
        у.поле("Длина", "eigrp.tlv_len", дл, место + 2, 2, родитель=т)
        з = место + 4
        if тип == 0x0001 and дл == 12:
            for i in range(6):
                у.поле(f"K{i + 1}", f"eigrp.par.k{i + 1}", д[з + i], з + i, 1, родитель=т)
            у.поле("Время удержания, с", "eigrp.par.holdtime", u16(д, з + 6), з + 6, 2, родитель=т)
        elif тип == 0x0004 and дл == 8:
            у.поле("Версия ОС", "eigrp.sw.os", f"{д[з]}.{д[з + 1]}", з, 2, u16(д, з), родитель=т)
            у.поле("Версия TLV EIGRP", "eigrp.sw.tlv", f"{д[з + 2]}.{д[з + 3]}", з + 2, 2, u16(д, з + 2), родитель=т)
        elif тип == 0x0102 and дл >= 25:
            у.поле("Следующий переход", "eigrp.ipv4.nexthop", ip4(д, з), з, 4, родитель=т)
            у.поле("Задержка", "eigrp.old_metric.delay", u32(д, з + 4), з + 4, 4, родитель=т)
            у.поле("Полоса", "eigrp.old_metric.bw", u32(д, з + 8), з + 8, 4, родитель=т)
            у.поле("MTU", "eigrp.old_metric.mtu", u24(д, з + 12), з + 12, 3, родитель=т)
            у.поле("Переходов", "eigrp.old_metric.hopcount", д[з + 15], з + 15, 1, родитель=т)
            у.поле("Надёжность", "eigrp.old_metric.rel", д[з + 16], з + 16, 1, родитель=т)
            у.поле("Загрузка", "eigrp.old_metric.load", д[з + 17], з + 17, 1, родитель=т)
            а = з + 20
            while а < место + дл:
                префикс = д[а]
                n = (префикс + 7) // 8
                if префикс > 32 or а + 1 + n > место + дл:
                    р.ошибка("EIGRP: префикс маршрута не сходится с длиной TLV")
                    break
                адрес = ip4(д[а + 1:а + 1 + n] + bytes(4 - n), 0)
                п_ = у.поле(f"Назначение {адрес}/{префикс}", "eigrp.ipv4.destination", адрес, а, 1 + n, родитель=т)
                у.поле("Длина префикса", "eigrp.ipv4.prefixlen", префикс, а, 1, родитель=п_)
                маршруты.append(f"{адрес}/{префикс}")
                а += 1 + n
        elif тип == 0x0103 and дл >= 8:
            у.поле("Следующий переход", "eigrp.ipv4.nexthop", ip4(д, з), з, 4, родитель=т)
            у.поле("Значение", "eigrp.tlv.data", д[з + 4:место + дл].hex(), з + 4, дл - 8, родитель=т)
        elif дл > 4:
            у.поле("Значение", "eigrp.tlv.data", д[з:место + дл].hex(), з, дл - 4, родитель=т)
        место += дл
    if маршруты:
        у.итог += ", маршруты " + ", ".join(маршруты[:4]) + (" …" if len(маршруты) > 4 else "")
        р.п.инфо = "EIGRP " + у.итог


# == RSVP (RFC 2205) =====================================================================

RSVP_ТИПЫ = {1: "Path", 2: "Resv", 3: "PathErr", 4: "ResvErr", 5: "PathTear", 6: "ResvTear", 7: "ResvConf",
             12: "Bundle", 13: "Ack", 15: "Srefresh", 20: "Hello"}
RSVP_КЛАССЫ = {1: "SESSION", 3: "RSVP_HOP", 4: "INTEGRITY", 5: "TIME_VALUES", 6: "ERROR_SPEC", 7: "SCOPE",
               8: "STYLE", 9: "FLOWSPEC", 10: "FILTER_SPEC", 11: "SENDER_TEMPLATE", 12: "SENDER_TSPEC",
               13: "ADSPEC", 14: "POLICY_DATA", 15: "RESV_CONFIRM", 16: "LABEL", 19: "LABEL_REQUEST",
               20: "EXPLICIT_ROUTE", 21: "RECORD_ROUTE", 207: "SESSION_ATTRIBUTE"}
RSVP_СТИЛИ = {0x0A: "FF (Fixed Filter)", 0x11: "WF (Wildcard Filter)", 0x12: "SE (Shared Explicit)"}


def rsvp(р: Разбор, м: int, конец: int) -> None:
    """RSVP (RFC 2205, разд. 3.1): версия 1, тип, сумма (0 — не передаётся), длина, объекты.

    Объекты: длина кратна 4 и не меньше 4, цепочка ровно до конца сообщения.
    """
    д = р.д
    if конец - м < 8 or д[м] >> 4 != 1 or д[м + 1] not in RSVP_ТИПЫ or д[м + 5] != 0:
        _не_моё(р, м, конец, "RSVP", "версия не 1, неизвестный тип или ненулевой резерв")
        return
    длина, сумма = u16(д, м + 6), u16(д, м + 2)
    обрезан = _обрезан(р, конец)
    if длина < 8 or (длина != конец - м and not (обрезан and длина > конец - м)):
        _не_моё(р, м, конец, "RSVP", f"длина {длина} не сходится с данными ({конец - м})")
        return
    конец_с = min(конец, м + длина)
    место = м + 8
    while not обрезан and место < конец_с:
        дл = u16(д, место) if место + 4 <= конец_с else 0
        if дл < 4 or дл % 4 or место + дл > конец_с:
            _не_моё(р, м, конец, "RSVP", "объекты не сходятся с длиной сообщения")
            return
        место += дл
    if обрезан:
        состояние = "не проверена: пакет оборван"
    elif сумма == 0:
        состояние = "не передаётся"
    elif сумма16(д[м:конец_с]) == 0:
        состояние = "верна"
    else:
        _не_моё(р, м, конец, "RSVP", "контрольная сумма не сошлась")
        return
    тип = д[м + 1]
    у = р.уровень("RSVP", "Resource ReSerVation Protocol", м)
    у.поле("Версия", "rsvp.version", 1, м, 1)
    у.поле("Флаги", "rsvp.flags", f"0x{д[м] & 15:x}", м, 1, д[м] & 15)
    у.поле("Тип сообщения", "rsvp.msg", f"{тип} ({RSVP_ТИПЫ[тип]})", м + 1, 1, тип)
    у.поле("Контрольная сумма", "rsvp.checksum", f"0x{сумма:04x} [{состояние}]", м + 2, 2, сумма)
    у.поле("Send_TTL", "rsvp.ttl", д[м + 4], м + 4, 1)
    у.поле("Зарезервировано", "rsvp.reserved", 0, м + 5, 1)
    у.поле("Длина", "rsvp.length", длина, м + 6, 2)
    у.длина = длина
    у.итог = RSVP_ТИПЫ[тип]
    р.п.инфо = "RSVP " + у.итог
    место, сессия = м + 8, ""
    while место < конец_с:
        р.нужно(место, 4)
        дл, класс, ctype = u16(д, место), д[место + 2], д[место + 3]
        if дл < 4:
            break
        р.нужно(место, дл)
        имя = RSVP_КЛАССЫ.get(класс, f"класс {класс}")
        п = у.поле(f"{имя} (C-тип {ctype})", "rsvp.object", имя, место, дл, класс)
        у.поле("Длина", "rsvp.obj_length", дл, место, 2, родитель=п)
        у.поле("Класс", "rsvp.class", класс, место + 2, 1, родитель=п)
        у.поле("C-тип", "rsvp.ctype", ctype, место + 3, 1, родитель=п)
        т = место + 4
        if класс == 1 and ctype in (1, 2) and дл == (12 if ctype == 1 else 24):
            n = 4 if ctype == 1 else 16
            адрес = ip4(д, т) if n == 4 else ip6(д, т)
            у.поле("Адрес получателя", "rsvp.session.ip", адрес, т, n, родитель=п)
            у.поле("Протокол", "rsvp.session.proto", д[т + n], т + n, 1, родитель=п)
            у.поле("Флаги", "rsvp.session.flags", д[т + n + 1], т + n + 1, 1, родитель=п)
            у.поле("Порт получателя", "rsvp.session.port", u16(д, т + n + 2), т + n + 2, 2, родитель=п)
            сессия = f"{адрес}, порт {u16(д, т + n + 2)}, протокол {д[т + n]}"
        elif класс == 1 and ctype == 7 and дл == 16:
            у.поле("Конец туннеля", "rsvp.session.ip", ip4(д, т), т, 4, родитель=п)
            у.поле("ID туннеля", "rsvp.session.tunnel_id", u16(д, т + 6), т + 6, 2, родитель=п)
            у.поле("Расширенный ID туннеля", "rsvp.session.ext_tunnel_id", ip4(д, т + 8), т + 8, 4, родитель=п)
            сессия = f"туннель LSP {ip4(д, т)}, ID {u16(д, т + 6)}"
        elif класс == 3 and ctype in (1, 2) and дл == (12 if ctype == 1 else 24):
            n = 4 if ctype == 1 else 16
            у.поле("Адрес перехода", "rsvp.hop.ip", ip4(д, т) if n == 4 else ip6(д, т), т, n, родитель=п)
            у.поле("Дескриптор интерфейса (LIH)", "rsvp.hop.lih", u32(д, т + n), т + n, 4, родитель=п)
        elif класс == 5 and ctype == 1 and дл == 8:
            у.поле("Период обновления, мс", "rsvp.time.refresh", u32(д, т), т, 4, родитель=п)
        elif класс == 8 and ctype == 1 and дл == 8:
            вектор = u24(д, т + 1)
            у.поле("Флаги", "rsvp.style.flags", д[т], т, 1, родитель=п)
            у.поле("Стиль", "rsvp.style", RSVP_СТИЛИ.get(вектор & 0x1F, f"0x{вектор:06x}"), т + 1, 3, вектор,
                   родитель=п)
        elif класс in (10, 11) and ctype in (1, 7) and дл == 12:
            у.поле("Адрес отправителя", "rsvp.sender.ip", ip4(д, т), т, 4, родитель=п)
            if ctype == 1:
                у.поле("Порт отправителя", "rsvp.sender.port", u16(д, т + 6), т + 6, 2, родитель=п)
            else:
                у.поле("ID LSP", "rsvp.sender.lsp_id", u16(д, т + 6), т + 6, 2, родитель=п)
        elif класс == 16 and ctype == 1 and дл == 8:
            у.поле("Метка", "rsvp.label", u32(д, т), т, 4, родитель=п)
        elif дл > 4:
            у.поле("Значение", "rsvp.object.data", д[т:место + дл].hex(), т, дл - 4, родитель=п)
        место += дл
    if сессия:
        у.итог += ", сессия " + сессия
        р.п.инфо = "RSVP " + у.итог


# == DCCP (RFC 4340) =====================================================================

DCCP_ТИПЫ = {0: "Request", 1: "Response", 2: "Data", 3: "Ack", 4: "DataAck", 5: "CloseReq", 6: "Close",
             7: "Reset", 8: "Sync", 9: "SyncAck"}
DCCP_СБРОС = {0: "Unspecified", 1: "Closed", 2: "Aborted", 3: "No Connection", 4: "Packet Error",
              5: "Option Error", 6: "Mandatory Error", 7: "Connection Refused", 8: "Bad Service Code",
              9: "Too Busy", 10: "Bad Init Cookie", 11: "Aggression Penalty"}
DCCP_ОПЦИИ = {0: "Padding", 1: "Mandatory", 2: "Slow Receiver", 32: "Change L", 33: "Confirm L",
              34: "Change R", 35: "Confirm R", 36: "Init Cookie", 37: "NDP Count", 38: "Ack Vector [Nonce 0]",
              39: "Ack Vector [Nonce 1]", 40: "Data Dropped", 41: "Timestamp", 42: "Timestamp Echo",
              43: "Elapsed Time", 44: "Data Checksum"}


def dccp(р: Разбор, м: int, конец: int) -> None:
    """DCCP (RFC 4340): общий заголовок (5.1), подзаголовки по типу, опции (5.8), сумма (9).

    Проверяется: тип 0–9 (10–15 зарезервированы — пакет игнорируется), X=1 для всех
    типов, кроме Data/Ack/DataAck; смещение данных не меньше заголовка и не за пакетом;
    CsCov (9.2): (CsCov−1)·4 не больше данных; сумма с псевдозаголовком (протокол 33,
    длина — весь пакет) по заголовку, опциям и покрытой части данных.
    """
    д = р.д
    if конец - м < 12:
        _не_моё(р, м, конец, "DCCP", "пакет короче общего заголовка")
        return
    смещение = д[м + 4] * 4
    ccval, cscov = д[м + 5] >> 4, д[м + 5] & 15
    тип, x = (д[м + 8] >> 1) & 15, д[м + 8] & 1
    if тип not in DCCP_ТИПЫ or (not x and тип not in (2, 3, 4)):
        _не_моё(р, м, конец, "DCCP", "зарезервированный тип или короткий номер там, где он запрещён")
        return
    заголовок = (16 if x else 12) + (0 if тип in (0, 2) else (8 if x else 4)) \
        + (4 if тип in (0, 1, 7) else 0)
    обрезан = _обрезан(р, конец)
    if смещение < заголовок or (not обрезан and м + смещение > конец):
        _не_моё(р, м, конец, "DCCP", f"смещение данных {смещение} не сходится с заголовком и пакетом")
        return
    сумма = u16(д, м + 6)
    if обрезан:
        состояние = "не проверена: пакет оборван"
    else:
        длина = конец - м
        покрыто = длина if cscov == 0 else смещение + (cscov - 1) * 4
        псевдо = _псевдо(р)
        if покрыто > длина:
            _не_моё(р, м, конец, "DCCP", f"CsCov {cscov} покрывает больше, чем есть данных")
            return
        if псевдо is None or _сумма_псевдо(псевдо, 33, длина, д[м:м + покрыто]) != 0:
            _не_моё(р, м, конец, "DCCP", "контрольная сумма не сошлась")
            return
        состояние = "верна" if cscov == 0 else f"верна, покрыто {покрыто} байт"
    от, к = u16(д, м), u16(д, м + 2)
    у = р.уровень("DCCP", "Datagram Congestion Control Protocol", м)
    у.поле("Порт источника", "dccp.srcport", от, м, 2)
    у.поле("Порт получателя", "dccp.dstport", к, м + 2, 2)
    _скрытые(у, "dccp.port", [от, к])
    у.поле("Смещение данных", "dccp.data_offset", f"{д[м + 4]} слов ({смещение} байт)", м + 4, 1, д[м + 4])
    у.поле("CCVal", "dccp.ccval", ccval, м + 5, 1)
    у.поле("Покрытие суммы (CsCov)", "dccp.cscov", cscov, м + 5, 1)
    у.поле("Контрольная сумма", "dccp.checksum", f"0x{сумма:04x} [{состояние}]", м + 6, 2, сумма)
    у.поле("Зарезервировано", "dccp.res1", д[м + 8] >> 5, м + 8, 1)
    у.поле("Тип", "dccp.type", f"{тип} ({DCCP_ТИПЫ[тип]})", м + 8, 1, тип)
    у.поле("Длинные номера (X)", "dccp.x", x, м + 8, 1)
    р.нужно(м, заголовок)
    if x:
        номер = (u16(д, м + 10) << 32) | u32(д, м + 12)
        у.поле("Номер", "dccp.seq", номер, м + 10, 6)
        место = м + 16
    else:
        номер = u24(д, м + 9)
        у.поле("Номер", "dccp.seq", номер, м + 9, 3)
        место = м + 12
    подтв = None
    if тип not in (0, 2):
        if x:
            подтв = (u16(д, место + 2) << 32) | u32(д, место + 4)
            у.поле("Подтверждение", "dccp.ack", подтв, место + 2, 6)
            место += 8
        else:
            подтв = u24(д, место + 1)
            у.поле("Подтверждение", "dccp.ack", подтв, место + 1, 3)
            место += 4
    if тип in (0, 1):
        у.поле("Код службы", "dccp.service_code", u32(д, место), место, 4)
        место += 4
    elif тип == 7:
        у.поле("Код сброса", "dccp.reset_code", f"{д[место]} ({DCCP_СБРОС.get(д[место], 'неизвестный')})",
               место, 1, д[место])
        у.поле("Данные сброса", "dccp.data", д[место + 1:место + 4].hex(), место + 1, 3)
        место += 4
    конец_оп = min(конец, м + смещение)
    if место < конец_оп:
        п = у.поле("Опции", "dccp.options", f"{конец_оп - место} байт", место, конец_оп - место)
        while место < конец_оп:
            вид = д[место]
            if вид < 32:
                у.поле(DCCP_ОПЦИИ.get(вид, f"опция {вид}"), "dccp.option_type", вид, место, 1, родитель=п)
                место += 1
                continue
            дл = д[место + 1] if место + 1 < конец_оп else 0
            if дл < 2 or место + дл > конец_оп:
                р.ошибка("DCCP: опция выходит за заголовок")
                break
            у.поле(f"{DCCP_ОПЦИИ.get(вид, f'опция {вид}')}: {д[место + 2:место + дл].hex() or '—'}",
                   "dccp.option_type", вид, место, дл, родитель=п)
            место += дл
    у.длина = смещение
    р.п.порт_от, р.п.порт_к = от, к
    у.итог = f"{от} → {к} [{DCCP_ТИПЫ[тип]}] seq={номер}" + (f" ack={подтв}" if подтв is not None else "")
    р.п.инфо = "DCCP " + у.итог
    if м + смещение < конец:
        данные(р, м + смещение, "DCCP", конец)


# == UDP-Lite (RFC 3828) =================================================================

def udplite(р: Разбор, м: int, конец: int) -> None:
    """UDP-Lite (RFC 3828, разд. 3.1): покрытие 0 (всё) или 8…длина, сумма не нуль и сходится.

    Псевдозаголовок — как у UDP, протокол 136, длина — вся дейтаграмма из IP (разд. 3.2).
    Нагрузка — по портам тем же выбором, что у UDP.
    """
    д = р.д
    if конец - м < 8:
        _не_моё(р, м, конец, "UDP-Lite", "дейтаграмма короче заголовка")
        return
    от, к, покрытие, сумма = u16(д, м), u16(д, м + 2), u16(д, м + 4), u16(д, м + 6)
    длина = конец - м
    обрезан = _обрезан(р, конец)
    if покрытие and (покрытие < 8 or (покрытие > длина and not обрезан)):
        _не_моё(р, м, конец, "UDP-Lite", f"покрытие {покрытие} вне 8…{длина}")
        return
    if сумма == 0:
        _не_моё(р, м, конец, "UDP-Lite", "нулевая сумма запрещена")
        return
    if обрезан:
        состояние = "не проверена: пакет оборван"
    else:
        охват = покрытие or длина
        псевдо = _псевдо(р)
        if псевдо is None or _сумма_псевдо(псевдо, 136, длина, д[м:м + охват]) != 0:
            _не_моё(р, м, конец, "UDP-Lite", "контрольная сумма не сошлась")
            return
        состояние = "верна"
    у = р.уровень("UDP-Lite", "Lightweight User Datagram Protocol", м)
    у.поле("Порт источника", "udplite.srcport", от, м, 2)
    у.поле("Порт получателя", "udplite.dstport", к, м + 2, 2)
    _скрытые(у, "udplite.port", [от, к])
    у.поле("Покрытие суммы", "udplite.checksum_coverage",
           f"{покрытие} ({'вся дейтаграмма' if покрытие == 0 else f'{покрытие} байт'})", м + 4, 2, покрытие)
    у.поле("Контрольная сумма", "udplite.checksum", f"0x{сумма:04x} [{состояние}]", м + 6, 2, сумма)
    у.длина = 8
    р.п.порт_от, р.п.порт_к = от, к
    у.итог = f"{от} → {к}, данных {длина - 8}, покрытие {покрытие or 'всё'}"
    р.п.инфо = "UDP-Lite " + у.итог
    if конец > м + 8:
        р.нагрузка(м + 8, конец)
        уровней = len(р.п.уровни)
        try:
            prilozh.по_портам(р, "udp", от, к, м + 8, конец)
        except struct.error:
            # Разборщики нагрузки ловят Мало/IndexError/ValueError, а чтение struct за
            # краем оборванного захвата бросает struct.error — нагрузка остаётся данными.
            del р.п.уровни[уровней:]
            данные(р, м + 8, "нагрузка UDP-Lite", конец)


# == LDP (RFC 5036) ======================================================================

LDP_СООБЩЕНИЯ = {0x0001: "Notification", 0x0100: "Hello", 0x0200: "Initialization", 0x0201: "KeepAlive",
                 0x0300: "Address", 0x0301: "Address Withdraw", 0x0400: "Label Mapping",
                 0x0401: "Label Request", 0x0402: "Label Withdraw", 0x0403: "Label Release",
                 0x0404: "Label Abort Request"}
LDP_TLV = {0x0100: "FEC", 0x0101: "Address List", 0x0103: "Hop Count", 0x0104: "Path Vector",
           0x0200: "Generic Label", 0x0300: "Status", 0x0301: "Extended Status", 0x0302: "Returned PDU",
           0x0303: "Returned Message", 0x0400: "Common Hello Parameters", 0x0401: "IPv4 Transport Address",
           0x0402: "Configuration Sequence Number", 0x0403: "IPv6 Transport Address",
           0x0500: "Common Session Parameters", 0x0600: "Label Request Message ID"}


def _адрес_семейства(д: bytes, место: int, семейство: int, n: int) -> str:
    if семейство == 1 and n == 4:
        return ip4(д, место)
    if семейство == 2 and n == 16:
        return ip6(д, место)
    return д[место:место + n].hex()


def _ldp_tlv(у: Уровень, д: bytes, место: int, конец: int, родитель) -> None:
    """TLV сообщения (RFC 5036, 3.3–3.4): U, F, тип (14 бит), длина; цепочка ровно до конца."""
    while место < конец:
        _нужно(место, 4, конец)
        слово, дл = u16(д, место), u16(д, место + 2)
        тип = слово & 0x3FFF
        _нужно(место + 4, дл, конец)
        имя = LDP_TLV.get(тип, f"TLV 0x{тип:04x}")
        п = у.поле(имя, "ldp.msg.tlv.type", f"0x{тип:04x} ({LDP_TLV.get(тип, 'неизвестный')})", место, 4 + дл, тип,
                   родитель=родитель)
        у.поле("Неизвестный TLV: сообщить (U)", "ldp.msg.tlv.ubit", слово >> 15, место, 1, родитель=п)
        у.поле("Неизвестный TLV: переслать (F)", "ldp.msg.tlv.fbit", (слово >> 14) & 1, место, 1, родитель=п)
        у.поле("Длина", "ldp.msg.tlv.len", дл, место + 2, 2, родитель=п)
        т, к = место + 4, место + 4 + дл
        if тип == 0x0400 and дл == 4:
            у.поле("Время удержания, с", "ldp.msg.tlv.hello.hold", u16(д, т), т, 2, родитель=п)
            у.поле("Направленный (T)", "ldp.msg.tlv.hello.targeted", д[т + 2] >> 7, т + 2, 1, родитель=п)
            у.поле("Запрос направленных (R)", "ldp.msg.tlv.hello.req", (д[т + 2] >> 6) & 1, т + 2, 1, родитель=п)
        elif тип == 0x0401 and дл == 4:
            у.поле("Транспортный адрес IPv4", "ldp.msg.tlv.ipv4.taddr", ip4(д, т), т, 4, родитель=п)
        elif тип == 0x0403 and дл == 16:
            у.поле("Транспортный адрес IPv6", "ldp.msg.tlv.ipv6.taddr", ip6(д, т), т, 16, родитель=п)
        elif тип == 0x0402 and дл == 4:
            у.поле("Номер конфигурации", "ldp.msg.tlv.hello.cnf_seq", u32(д, т), т, 4, родитель=п)
        elif тип == 0x0500 and дл == 14:
            у.поле("Версия протокола", "ldp.msg.tlv.sess.ver", u16(д, т), т, 2, родитель=п)
            у.поле("KeepAlive, с", "ldp.msg.tlv.sess.ka", u16(д, т + 2), т + 2, 2, родитель=п)
            у.поле("Нисходящая по запросу (A)", "ldp.msg.tlv.sess.advbit", д[т + 4] >> 7, т + 4, 1, родитель=п)
            у.поле("Обнаружение петель (D)", "ldp.msg.tlv.sess.ldetbit", (д[т + 4] >> 6) & 1, т + 4, 1, родитель=п)
            у.поле("Предел длины пути", "ldp.msg.tlv.sess.pvlim", д[т + 5], т + 5, 1, родитель=п)
            у.поле("Наибольшая длина PDU", "ldp.msg.tlv.sess.mxpdu", u16(д, т + 6), т + 6, 2, родитель=п)
            у.поле("LDP ID получателя", "ldp.msg.tlv.sess.rxlsr", f"{ip4(д, т + 8)}:{u16(д, т + 12)}", т + 8, 6,
                   родитель=п)
        elif тип == 0x0200 and дл == 4:
            у.поле("Метка", "ldp.msg.tlv.generic.label", u32(д, т) & 0xFFFFF, т, 4, родитель=п)
        elif тип == 0x0103 and дл == 1:
            у.поле("Переходов", "ldp.msg.tlv.hc.value", д[т], т, 1, родитель=п)
        elif тип == 0x0104 and дл % 4 == 0:
            for а in range(т, к, 4):
                у.поле("LSR", "ldp.msg.tlv.pv.lsrid", ip4(д, а), а, 4, родитель=п)
        elif тип == 0x0600 and дл == 4:
            у.поле("ID сообщения Label Request", "ldp.msg.tlv.lbl_req_msg_id", u32(д, т), т, 4, родитель=п)
        elif тип == 0x0300 and дл == 10:
            у.поле("Фатальная (E)", "ldp.msg.tlv.status.ebit", д[т] >> 7, т, 1, родитель=п)
            у.поле("Переслать (F)", "ldp.msg.tlv.status.fbit", (д[т] >> 6) & 1, т, 1, родитель=п)
            у.поле("Код состояния", "ldp.msg.tlv.status.data", f"0x{u32(д, т) & 0x3FFFFFFF:08x}", т, 4,
                   u32(д, т) & 0x3FFFFFFF, родитель=п)
            у.поле("ID сообщения", "ldp.msg.tlv.status.msg.id", u32(д, т + 4), т + 4, 4, родитель=п)
            у.поле("Тип сообщения", "ldp.msg.tlv.status.msg.type", f"0x{u16(д, т + 8):04x}", т + 8, 2,
                   u16(д, т + 8), родитель=п)
        elif тип == 0x0101 and дл >= 2:
            семейство = u16(д, т)
            у.поле("Семейство адресов", "ldp.msg.tlv.addrl.addr_family", семейство, т, 2, родитель=п)
            n = {1: 4, 2: 16}.get(семейство)
            if n and (дл - 2) % n == 0:
                for а in range(т + 2, к, n):
                    у.поле("Адрес", "ldp.msg.tlv.addrl.addr", _адрес_семейства(д, а, семейство, n), а, n, родитель=п)
        elif тип == 0x0100:
            а = т
            while а < к:
                элемент = д[а]
                if элемент == 1:
                    у.поле("Элемент FEC: Wildcard", "ldp.msg.tlv.fec.type", 1, а, 1, родитель=п)
                    а += 1
                    continue
                if элемент not in (2, 3) or а + 4 > к:
                    у.поле("Элемент FEC", "ldp.msg.tlv.fec.type", элемент, а, к - а, родитель=п)
                    break
                семейство, дл_префикса = u16(д, а + 1), д[а + 3]
                n = (дл_префикса + 7) // 8 if элемент == 2 else дл_префикса
                _нужно(а + 4, n, к)
                полный = {1: 4, 2: 16}.get(семейство, n)
                адрес = _адрес_семейства(д[а + 4:а + 4 + n] + bytes(max(0, полный - n)), 0, семейство, полный)
                текст = f"{адрес}/{дл_префикса}" if элемент == 2 else адрес
                э = у.поле(f"Элемент FEC: {'префикс' if элемент == 2 else 'узел'} {текст}", "ldp.msg.tlv.fec.type",
                           элемент, а, 4 + n, родитель=п)
                у.поле("Семейство адресов", "ldp.msg.tlv.fec.af", семейство, а + 1, 2, родитель=э)
                у.поле("Длина префикса", "ldp.msg.tlv.fec.len", дл_префикса, а + 3, 1, родитель=э)
                у.поле("Префикс", "ldp.msg.tlv.fec.pfval", текст, а + 4, n, родитель=э)
                а += 4 + n
        elif дл:
            у.поле("Значение", "ldp.msg.tlv.value", д[т:к].hex(), т, дл, родитель=п)
        место = к


def _ldp(р: Разбор, м: int, конец: int, tcp: bool) -> bool:
    """LDP (RFC 5036): PDU — версия 1, длина PDU, LDP ID (LSR ID и пространство меток), сообщения.

    Проверяется вложенность длин: сообщения ровно заполняют PDU, TLV — сообщение.
    По UDP (Hello) — ровно один PDU на дейтаграмму; по TCP — цепочка PDU ровно до конца сегмента.
    """
    д = р.д
    у = Уровень("LDP", "Label Distribution Protocol", м)
    место, имена, lsr = м, [], ""
    while место < конец:
        _нужно(место, 10, конец)
        версия, дл = u16(д, место), u16(д, место + 2)
        if версия != 1 or дл < 6 + 8 or место + 4 + дл > конец:
            raise _Не("не PDU LDP")
        конец_pdu = место + 4 + дл
        lsr = f"{ip4(д, место + 4)}:{u16(д, место + 8)}"
        п = у.поле(f"PDU, LDP ID {lsr}", "ldp.hdr", lsr, место, 4 + дл)
        у.поле("Версия", "ldp.hdr.version", версия, место, 2, родитель=п)
        у.поле("Длина PDU", "ldp.hdr.pdu_len", дл, место + 2, 2, родитель=п)
        у.поле("LSR ID", "ldp.hdr.ldp_id", ip4(д, место + 4), место + 4, 4, родитель=п)
        у.поле("Пространство меток", "ldp.hdr.label_space", u16(д, место + 8), место + 8, 2, родитель=п)
        с = место + 10
        while с < конец_pdu:
            _нужно(с, 8, конец_pdu)
            слово, дл_с = u16(д, с), u16(д, с + 2)
            тип = слово & 0x7FFF
            if дл_с < 4:
                raise _Не("сообщение LDP короче идентификатора")
            _нужно(с + 4, дл_с, конец_pdu)
            имя = LDP_СООБЩЕНИЯ.get(тип, f"сообщение 0x{тип:04x}")
            с_п = у.поле(имя, "ldp.msg.type", f"0x{тип:04x} ({LDP_СООБЩЕНИЯ.get(тип, 'неизвестное')})", с, 4 + дл_с,
                         тип, родитель=п)
            у.поле("Неизвестное: сообщить (U)", "ldp.msg.ubit", слово >> 15, с, 1, родитель=с_п)
            у.поле("Длина", "ldp.msg.len", дл_с, с + 2, 2, родитель=с_п)
            у.поле("ID сообщения", "ldp.msg.id", u32(д, с + 4), с + 4, 4, родитель=с_п)
            _ldp_tlv(у, д, с + 8, с + 4 + дл_с, с_п)
            имена.append(имя)
            с += 4 + дл_с
        место = конец_pdu
        if not tcp and место != конец:
            raise _Не("по UDP — один PDU на дейтаграмму")
    у.длина = конец - м
    у.итог = ", ".join(имена[:6]) + (" …" if len(имена) > 6 else "") + f" (LDP ID {lsr})"
    р.п.уровни.append(у)
    р.п.инфо = "LDP " + у.итог
    return True


@_строго
def ldp_udp(р: Разбор, м: int, конец: int) -> bool:
    return _ldp(р, м, конец, tcp=False)


@_строго
def ldp_tcp(р: Разбор, м: int, конец: int) -> bool:
    return _ldp(р, м, конец, tcp=True)


# == Geneve (RFC 8926) ===================================================================

@_строго
def geneve(р: Разбор, м: int, конец: int) -> bool:
    """Geneve (RFC 8926, 3.4–3.5): версия 0, длина опций, флаги O/C, тип протокола, VNI, опции.

    Проверяется: версия 0; зарезервированные биты заголовка и опций — нули; опции
    ровно заполняют объявленную длину; C=1 тогда и только тогда, когда у какой-то опции
    стоит бит критичности; тип протокола — известный EtherType; внутри есть данные.
    """
    д = р.д
    _нужно(м, 8, конец)
    версия, опций = д[м] >> 6, (д[м] & 0x3F) * 4
    o, c, резерв = д[м + 1] >> 7, (д[м + 1] >> 6) & 1, д[м + 1] & 0x3F
    тип, vni = u16(д, м + 2), u24(д, м + 4)
    if версия != 0 or резерв or д[м + 7] or not (тип in ETHERTYPE or тип in ДОП_ETHERTYPE):
        raise _Не("не заголовок Geneve")
    конец_оп = м + 8 + опций
    if конец_оп >= конец:
        raise _Не("опции Geneve выходят за данные")
    у = Уровень("Geneve", "Generic Network Virtualization Encapsulation", м)
    у.поле("Версия", "geneve.version", версия, м, 1)
    у.поле("Длина опций", "geneve.options_length", f"{опций} байт", м, 1, опций)
    п = у.поле("Флаги", "geneve.flags", f"0x{д[м + 1]:02x}", м + 1, 1, д[м + 1])
    у.поле("Служебный пакет (O)", "geneve.flags.oam", o, м + 1, 1, родитель=п)
    у.поле("Есть критичные опции (C)", "geneve.flags.critical", c, м + 1, 1, родитель=п)
    у.поле("Зарезервировано", "geneve.flags.reserved", резерв, м + 1, 1, родитель=п)
    у.поле("Тип протокола", "geneve.proto_type", f"0x{тип:04x} ({ETHERTYPE.get(тип, 'неизвестный')})", м + 2, 2, тип)
    у.поле("VNI", "geneve.vni", vni, м + 4, 3)
    у.поле("Зарезервировано", "geneve.reserved", 0, м + 7, 1)
    место, критичные = м + 8, 0
    while место < конец_оп:
        _нужно(место, 4, конец_оп)
        класс, вид, байт = u16(д, место), д[место + 2], д[место + 3]
        дл = (байт & 0x1F) * 4
        if байт >> 5:
            raise _Не("зарезервированные биты опции Geneve")
        _нужно(место + 4, дл, конец_оп)
        критичные |= вид >> 7
        оп = у.поле(f"Опция: класс 0x{класс:04x}, тип 0x{вид:02x}", "geneve.option", f"0x{класс:04x}/0x{вид:02x}",
                    место, 4 + дл)
        у.поле("Класс", "geneve.option.class", f"0x{класс:04x}", место, 2, класс, родитель=оп)
        у.поле("Тип", "geneve.option.type", f"0x{вид:02x}", место + 2, 1, вид, родитель=оп)
        у.поле("Критичная", "geneve.option.type.critical", вид >> 7, место + 2, 1, родитель=оп)
        у.поле("Длина", "geneve.option.length", f"{дл} байт", место + 3, 1, дл, родитель=оп)
        if дл:
            у.поле("Данные", "geneve.option.data", д[место + 4:место + 4 + дл].hex(), место + 4, дл, родитель=оп)
        место += 4 + дл
    if критичные != c:
        raise _Не("флаг C не сходится с битами критичности опций")
    у.длина = 8 + опций
    у.итог = f"VNI {vni}, {ETHERTYPE.get(тип, f'0x{тип:04x}')}" + (", служебный" if o else "")
    р.п.уровни.append(у)
    р.п.инфо = "Geneve " + у.итог
    _дальше(р, по_типу, тип, конец_оп)
    return True


# == LISP (RFC 9300, RFC 9301) ===========================================================

LISP_ТИПЫ = {1: "Map-Request", 2: "Map-Reply", 3: "Map-Register", 4: "Map-Notify", 5: "Map-Notify-Ack",
             8: "Encapsulated Control Message"}
LISP_ДЕЙСТВИЯ = {0: "No-Action", 1: "Natively-Forward", 2: "Send-Map-Request", 3: "Drop/No-Reason",
                 4: "Drop/Policy-Denied", 5: "Drop/Auth-Failure"}


@_строго
def lisp_данные(р: Разбор, м: int, конец: int) -> bool:
    """Заголовок данных LISP (RFC 9300, 5.1, 5.3): флаги N L E V I, 3 резервных бита, затем IP.

    Проверяется: резервные биты — нули; N и V вместе не ставятся; внутри — целый пакет IP
    (IPv4 — длина и сумма заголовка, IPv6 — длина).
    """
    д = р.д
    _нужно(м, 8, конец)
    ф = д[м]
    n, l, e, v, i = ф >> 7, (ф >> 6) & 1, (ф >> 5) & 1, (ф >> 4) & 1, (ф >> 3) & 1
    if ф & 7 or (n and v) or not _ip_целый(д, м + 8, конец):
        raise _Не("не заголовок данных LISP")
    у = Уровень("LISP", "Locator/ID Separation Protocol (данные)", м)
    п = у.поле("Флаги", "lisp-data.flags", f"0x{ф:02x}", м, 1, ф)
    _флаги(у, п, м, 1, ф, (("Есть nonce (N)", "lisp-data.flags.nonce", 7), ("Есть LSB (L)", "lisp-data.flags.lsb", 6),
                            ("Запрос эха nonce (E)", "lisp-data.flags.enr", 5),
                            ("Есть версии карты (V)", "lisp-data.flags.mv", 4),
                            ("Есть Instance ID (I)", "lisp-data.flags.iid", 3)))
    у.поле("Зарезервировано", "lisp-data.flags.reserved", 0, м, 1, родитель=п)
    if n:
        у.поле("Nonce", "lisp-data.nonce", f"0x{u24(д, м + 1):06x}", м + 1, 3, u24(д, м + 1))
    elif v:
        у.поле("Версия карты источника", "lisp-data.sversion", u24(д, м + 1) >> 12, м + 1, 2)
        у.поле("Версия карты получателя", "lisp-data.dversion", u24(д, м + 1) & 0xFFF, м + 2, 2)
    итог = []
    if i:
        у.поле("Instance ID", "lisp-data.iid", u24(д, м + 4), м + 4, 3)
        итог.append(f"IID {u24(д, м + 4)}")
        if l:
            у.поле("Биты состояния локаторов", "lisp-data.lsb", f"0x{д[м + 7]:02x}", м + 7, 1, д[м + 7])
    elif l:
        у.поле("Биты состояния локаторов", "lisp-data.lsb", f"0x{u32(д, м + 4):08x}", м + 4, 4, u32(д, м + 4))
    у.длина = 8
    у.итог = "данные" + (", " + ", ".join(итог) if итог else "") + (", запрос эха" if n and e else "")
    р.п.уровни.append(у)
    р.п.инфо = "LISP " + у.итог
    _дальше(р, голый_ip, м + 8)
    return True


def _lisp_afi(д: bytes, место: int, конец: int) -> tuple[str, int]:
    """Адрес с AFI (RFC 9301, 5.1): 0 — пусто, 1 — IPv4, 2 — IPv6, 16387 — LCAF (RFC 8060)."""
    _нужно(место, 2, конец)
    afi = u16(д, место)
    if afi == 0:
        return "—", 2
    if afi in (1, 2):
        n = 4 if afi == 1 else 16
        _нужно(место + 2, n, конец)
        return (ip4(д, место + 2) if n == 4 else ip6(д, место + 2)), 2 + n
    if afi == 16387:
        _нужно(место + 2, 6, конец)
        дл = u16(д, место + 6)
        _нужно(место + 8, дл, конец)
        return f"LCAF тип {д[место + 4]}", 8 + дл
    raise _Не(f"AFI {afi} не разбирается")


def _lisp_адрес(у: Уровень, д: bytes, место: int, конец: int, подпись: str, ключ: str, родитель=None):
    текст, дл = _lisp_afi(д, место, конец)
    п = у.поле(f"{подпись}: {текст}", ключ, текст, место, дл, родитель=родитель)
    у.поле("AFI", ключ + ".afi", u16(д, место), место, 2, родитель=п)
    return текст, дл


def _lisp_запись(у: Уровень, д: bytes, место: int, конец: int) -> tuple[int, str]:
    """Запись сопоставления (RFC 9301, 5.4): TTL, число локаторов, маска EID, ACT/A, версия, EID, локаторы."""
    _нужно(место, 12, конец)
    ttl, локаторов, маска = u32(д, место), д[место + 4], д[место + 5]
    act, a, версия = д[место + 6] >> 5, (д[место + 6] >> 4) & 1, u16(д, место + 8) & 0xFFF
    префикс, дл = _lisp_afi(д, место + 10, конец)
    п = у.поле(f"Запись: EID {префикс}/{маска}", "lisp.mapping.eid.prefix", префикс, место, 0)
    у.поле("TTL, мин", "lisp.mapping.ttl", ttl, место, 4, родитель=п)
    у.поле("Локаторов", "lisp.mapping.loc_count", локаторов, место + 4, 1, родитель=п)
    у.поле("Длина маски EID", "lisp.mapping.eid.prefix_length", маска, место + 5, 1, родитель=п)
    у.поле("Действие (ACT)", "lisp.mapping.act", LISP_ДЕЙСТВИЯ.get(act, act), место + 6, 1, act, родитель=п)
    у.поле("Авторитетный (A)", "lisp.mapping.auth", a, место + 6, 1, родитель=п)
    у.поле("Версия карты", "lisp.mapping.version", версия, место + 8, 2, родитель=п)
    _lisp_адрес(у, д, место + 10, конец, "Префикс EID", "lisp.mapping.eid", родитель=п)
    после = место + 10 + дл
    for _ in range(локаторов):
        _нужно(после, 6, конец)
        приоритет, вес, мприоритет, мвес = д[после:после + 4]
        флаги = u16(д, после + 4)
        лок, дл_л = _lisp_afi(д, после + 6, конец)
        л = у.поле(f"Локатор {лок}, приоритет {приоритет}, вес {вес}", "lisp.loc.locator", лок, после, 6 + дл_л,
                   родитель=п)
        у.поле("Приоритет", "lisp.loc.priority", приоритет, после, 1, родитель=л)
        у.поле("Вес", "lisp.loc.weight", вес, после + 1, 1, родитель=л)
        у.поле("Приоритет групповой", "lisp.loc.multicast_priority", мприоритет, после + 2, 1, родитель=л)
        у.поле("Вес групповой", "lisp.loc.multicast_weight", мвес, после + 3, 1, родитель=л)
        _флаги(у, л, после + 4, 2, флаги, (("Локальный (L)", "lisp.loc.local", 2), ("Проба (p)", "lisp.loc.probe", 1),
                                           ("Достижим (R)", "lisp.loc.reach", 0)))
        после += 6 + дл_л
    п.длина = после - место
    return после, f"{префикс}/{маска}"


@_строго
def lisp_управление(р: Разбор, м: int, конец: int) -> bool:
    """Управляющие сообщения LISP (RFC 9301, 5.1–5.8).

    Каждое сообщение разбирается до последнего байта: адреса — только известных AFI,
    записей не меньше одной, структура ровно до конца дейтаграммы (у Map-Register и
    Map-Notify допускается хвост xTR-ID и site-ID, 24 байта).
    """
    д = р.д
    _нужно(м, 4, конец)
    тип = д[м] >> 4
    if тип not in LISP_ТИПЫ:
        raise _Не("неизвестный тип LISP")
    у = Уровень("LISP", "Locator/ID Separation Protocol (управление)", м)
    у.поле("Тип", "lisp.type", f"{тип} ({LISP_ТИПЫ[тип]})", м, 1, тип)
    итог = LISP_ТИПЫ[тип]
    if тип == 8:
        ф = д[м]
        п = у.поле("Флаги", "lisp.ecm.flags", f"0x{ф & 15:x}", м, 1, ф & 15)
        _флаги(у, п, м, 1, ф, (("Защищено (S)", "lisp.ecm.flags.sec", 3), ("От DDT (D)", "lisp.ecm.flags.ddt", 2),
                               ("К ETR (E)", "lisp.ecm.flags.etr", 1), ("К Map-Server (M)", "lisp.ecm.flags.ms", 0)))
        if not _ip_целый(д, м + 4, конец):
            raise _Не("внутри ECM нет целого пакета IP")
        у.длина = 4
        у.итог = итог
        р.п.уровни.append(у)
        р.п.инфо = "LISP " + итог
        _дальше(р, голый_ip, м + 4)
        return True
    записей = д[м + 3]
    if записей == 0:
        raise _Не("нет записей")
    _нужно(м, 12, конец)
    ф = д[м]
    if тип == 1:
        irc = д[м + 2] & 0x1F
        п = у.поле("Флаги", "lisp.flags", f"0x{ф & 15:x}", м, 1, ф & 15)
        _флаги(у, п, м, 1, ф, (("Авторитетный (A)", "lisp.mreq.flags.auth", 3),
                               ("Есть запись Map-Reply (M)", "lisp.mreq.flags.map_data", 2),
                               ("Проба (P)", "lisp.mreq.flags.probe", 1), ("SMR (S)", "lisp.mreq.flags.smr", 0)))
        у.поле("Адресов ITR-RLOC − 1 (IRC)", "lisp.irc", irc, м + 2, 1)
        у.поле("Записей", "lisp.records", записей, м + 3, 1)
        у.поле("Nonce", "lisp.nonce", f"0x{u64(д, м + 4):016x}", м + 4, 8, u64(д, м + 4))
        место = м + 12
        _, дл = _lisp_адрес(у, д, место, конец, "EID источника", "lisp.mreq.srceid")
        место += дл
        for _ in range(irc + 1):
            _, дл = _lisp_адрес(у, д, место, конец, "ITR-RLOC", "lisp.mreq.itr_rloc")
            место += дл
        запросы = []
        for _ in range(записей):
            _нужно(место, 4, конец)
            маска = д[место + 1]
            префикс, дл = _lisp_afi(д, место + 2, конец)
            п = у.поле(f"Запрос EID {префикс}/{маска}", "lisp.mreq.record.prefix", префикс, место, 2 + дл)
            у.поле("Длина маски EID", "lisp.mreq.record.prefix_length", маска, место + 1, 1, родитель=п)
            запросы.append(f"{префикс}/{маска}")
            место += 2 + дл
        if ф & 4:
            место, _ = _lisp_запись(у, д, место, конец)
        if место != конец:
            raise _Не("Map-Request не сходится с длиной")
        итог += " " + ", ".join(запросы)
    elif тип == 2:
        п = у.поле("Флаги", "lisp.flags", f"0x{ф & 15:x}", м, 1, ф & 15)
        _флаги(у, п, м, 1, ф, (("Проба (P)", "lisp.mrep.flags.probe", 3), ("Эхо nonce (E)", "lisp.mrep.flags.enlr", 2),
                               ("Защищено (S)", "lisp.mrep.flags.sec", 1)))
        у.поле("Записей", "lisp.records", записей, м + 3, 1)
        у.поле("Nonce", "lisp.nonce", f"0x{u64(д, м + 4):016x}", м + 4, 8, u64(д, м + 4))
        место, eid = м + 12, []
        for _ in range(записей):
            место, текст = _lisp_запись(у, д, место, конец)
            eid.append(текст)
        if место != конец:
            raise _Не("Map-Reply не сходится с длиной")
        итог += " " + ", ".join(eid)
    else:
        _нужно(м, 16, конец)
        if тип == 3:
            п = у.поле("Флаги", "lisp.flags", f"0x{ф & 15:x}", м, 1, ф & 15)
            _флаги(у, п, м, 1, ф, (("Прокси-ответ (P)", "lisp.mreg.flags.proxy", 3),
                                   ("Защищено (S)", "lisp.mreg.flags.sec", 2),
                                   ("Есть xTR-ID (I)", "lisp.mreg.flags.xtrid", 1)))
        у.поле("Записей", "lisp.records", записей, м + 3, 1)
        у.поле("Nonce", "lisp.nonce", f"0x{u64(д, м + 4):016x}", м + 4, 8, u64(д, м + 4))
        дл_подписи = u16(д, м + 14)
        у.поле("Ключ (Key ID)", "lisp.mreg.keyid", f"0x{u16(д, м + 12):04x}", м + 12, 2, u16(д, м + 12))
        у.поле("Длина данных аутентификации", "lisp.mreg.authlen", дл_подписи, м + 14, 2)
        _нужно(м + 16, дл_подписи, конец)
        if дл_подписи:
            у.поле("Данные аутентификации", "lisp.mreg.auth", д[м + 16:м + 16 + дл_подписи].hex(), м + 16, дл_подписи)
        место, eid = м + 16 + дл_подписи, []
        for _ in range(записей):
            место, текст = _lisp_запись(у, д, место, конец)
            eid.append(текст)
        хвост = конец - место
        if тип == 3 and хвост != (24 if ф & 2 else 0) or тип != 3 and хвост not in (0, 24):
            raise _Не(f"{LISP_ТИПЫ[тип]} не сходится с длиной")
        if хвост:
            у.поле("xTR-ID", "lisp.xtrid", д[место:место + 16].hex(), место, 16)
            у.поле("site-ID", "lisp.siteid", д[место + 16:место + 24].hex(), место + 16, 8)
        итог += " " + ", ".join(eid)
    у.длина = конец - м
    у.итог = итог
    р.п.уровни.append(у)
    р.п.инфо = "LISP " + итог
    return True


# == CAPWAP (RFC 5415) ===================================================================

CAPWAP_СООБЩЕНИЯ = {1: "Discovery Request", 2: "Discovery Response", 3: "Join Request", 4: "Join Response",
                    5: "Configuration Status Request", 6: "Configuration Status Response",
                    7: "Configuration Update Request", 8: "Configuration Update Response",
                    9: "WTP Event Request", 10: "WTP Event Response", 11: "Change State Event Request",
                    12: "Change State Event Response", 13: "Echo Request", 14: "Echo Response",
                    15: "Image Data Request", 16: "Image Data Response", 17: "Reset Request",
                    18: "Reset Response", 19: "Primary Discovery Request", 20: "Primary Discovery Response",
                    21: "Data Transfer Request", 22: "Data Transfer Response", 23: "Clear Configuration Request",
                    24: "Clear Configuration Response", 25: "Station Configuration Request",
                    26: "Station Configuration Response"}
CAPWAP_ЭЛЕМЕНТЫ = {1: "AC Descriptor", 4: "AC Name", 20: "Discovery Type", 37: "Vendor Specific Payload",
                   38: "WTP Board Data", 39: "WTP Descriptor", 45: "WTP Name"}
CAPWAP_ОБНАРУЖЕНИЕ = {0: "Unknown", 1: "Static Configuration", 2: "DHCP", 3: "DNS", 4: "AC Referral"}


def _capwap_элементы(у: Уровень, д: bytes, место: int, конец: int, родитель=None) -> None:
    """Элементы сообщения (RFC 5415, 4.6): тип, длина, значение — цепочка ровно до конца."""
    while место < конец:
        _нужно(место, 4, конец)
        тип, дл = u16(д, место), u16(д, место + 2)
        _нужно(место + 4, дл, конец)
        имя = CAPWAP_ЭЛЕМЕНТЫ.get(тип, f"элемент {тип}")
        п = у.поле(имя, "capwap.message_element.type", f"{тип} ({CAPWAP_ЭЛЕМЕНТЫ.get(тип, 'неизвестный')})", место,
                   4 + дл, тип, родитель=родитель)
        у.поле("Длина", "capwap.message_element.length", дл, место + 2, 2, родитель=п)
        т = место + 4
        if тип in (4, 45) and дл:
            у.поле("Имя", "capwap.control.ac_name" if тип == 4 else "capwap.control.wtp_name", _текст(д[т:т + дл]),
                   т, дл, родитель=п)
        elif тип == 20 and дл == 1:
            у.поле("Способ обнаружения", "capwap.control.discovery_type", CAPWAP_ОБНАРУЖЕНИЕ.get(д[т], д[т]), т, 1,
                   д[т], родитель=п)
        elif тип == 37 and дл >= 6:
            у.поле("Поставщик", "capwap.control.vendor_id", u32(д, т), т, 4, родитель=п)
            у.поле("ID элемента", "capwap.control.vendor_element_id", u16(д, т + 4), т + 4, 2, родитель=п)
        elif дл:
            у.поле("Значение", "capwap.message_element.value", д[т:т + дл].hex(), т, дл, родитель=п)
        место += 4 + дл


def _capwap(р: Разбор, м: int, конец: int, управление: bool) -> bool:
    """CAPWAP (RFC 5415, разд. 4): преамбула (версия 0, тип 0/1), заголовок, флаги, фрагментация.

    Тип 1 — за преамбулой заголовок DTLS (4.2: 3 резервных байта нуля), затем записи DTLS.
    Проверяется: резервные биты и флаги — нули; HLEN покрывает ровно 8 байт, MAC радио
    (M) и сведения о беспроводной сети (W); WBID — 1 (IEEE 802.11) или 3 (EPCGlobal); у
    сообщения управления флаги — нуль, длина элементов и сами элементы сходятся с данными.
    """
    д = р.д
    _нужно(м, 4, конец)
    версия, вид = д[м] >> 4, д[м] & 15
    if версия != 0 or вид not in (0, 1):
        raise _Не("не преамбула CAPWAP")
    у = Уровень("CAPWAP", "CAPWAP (" + ("управление" if управление else "данные") + ")", м)
    п = у.поле("Преамбула", "capwap.preamble", f"0x{д[м]:02x}", м, 1, д[м])
    у.поле("Версия", "capwap.preamble.version", версия, м, 1, родитель=п)
    у.поле("Тип", "capwap.preamble.type", "DTLS" if вид else "открытый", м, 1, вид, родитель=п)
    if вид == 1:
        if u24(д, м + 1):
            raise _Не("ненулевой резерв заголовка DTLS CAPWAP")
        у.поле("Зарезервировано", "capwap.dtls.reserved", 0, м + 1, 3)
        у.длина = 4
        у.итог = "в DTLS"
        р.п.уровни.append(у)
        р.п.инфо = "CAPWAP " + у.итог
        if not dtls(р, м + 4, конец):
            raise _Не("за заголовком DTLS CAPWAP нет записей DTLS")
        return True
    _нужно(м, 8, конец)
    б = u24(д, м + 1)
    hlen, rid, wbid = (б >> 19) * 4, (б >> 14) & 31, (б >> 9) & 31
    t, f, l, w, mb, k, флаги = (б >> 8) & 1, (б >> 7) & 1, (б >> 6) & 1, (б >> 5) & 1, (б >> 4) & 1, (б >> 3) & 1, б & 7
    фрагмент, слово = u16(д, м + 4), u16(д, м + 6)
    if флаги or слово & 7 or wbid not in (1, 3) or hlen < 8 or м + hlen > конец:
        raise _Не("не заголовок CAPWAP")
    место = м + 8
    у.поле("Длина заголовка (HLEN)", "capwap.header.length", f"{hlen} байт", м + 1, 1, hlen)
    у.поле("ID радио", "capwap.header.rid", rid, м + 1, 2)
    у.поле("Беспроводная связь (WBID)", "capwap.header.wbid",
           {1: "IEEE 802.11", 3: "EPCGlobal"}[wbid], м + 2, 1, wbid)
    фп = у.поле("Флаги", "capwap.header.flags", f"0x{б & 0x1FF:03x}", м + 2, 2, б & 0x1FF)
    _флаги(у, фп, м + 2, 2, б, (("Родной формат кадра (T)", "capwap.header.flags.t", 8),
                                ("Фрагмент (F)", "capwap.header.flags.f", 7),
                                ("Последний фрагмент (L)", "capwap.header.flags.l", 6),
                                ("Есть сведения о сети (W)", "capwap.header.flags.w", 5),
                                ("Есть MAC радио (M)", "capwap.header.flags.m", 4),
                                ("Keep-Alive (K)", "capwap.header.flags.k", 3)))
    у.поле("Зарезервировано", "capwap.header.flags.reserved", 0, м + 3, 1, родитель=фп)
    у.поле("ID фрагмента", "capwap.header.fragment.id", фрагмент, м + 4, 2)
    у.поле("Смещение фрагмента", "capwap.header.fragment.offset", (слово >> 3) * 8, м + 6, 2, слово >> 3)
    for есть, подпись, ключ in ((mb, "MAC радио", "capwap.header.mac"),
                                (w, "Сведения о беспроводной сети", "capwap.header.wireless")):
        if not есть:
            continue
        _нужно(место, 1, м + hlen)
        дл = д[место]
        if mb and ключ == "capwap.header.mac" and дл not in (6, 8):
            raise _Не("длина MAC радио не 6 и не 8")
        _нужно(место + 1, дл, м + hlen)
        значение = mac(д, место + 1) if ключ == "capwap.header.mac" and дл == 6 else д[место + 1:место + 1 + дл].hex()
        о = у.поле(подпись, ключ, значение, место, 1 + дл)
        у.поле("Длина", ключ + ".length", дл, место, 1, родитель=о)
        место += (1 + дл + 3) // 4 * 4
    if место != м + hlen:
        raise _Не("HLEN не сходится с необязательными полями")
    у.длина = hlen
    место = м + hlen
    if f:
        у.итог = f"фрагмент {фрагмент}, смещение {(слово >> 3) * 8}" + (", последний" if l else "")
        р.п.уровни.append(у)
        р.п.инфо = "CAPWAP " + у.итог
        данные(р, место, "фрагмент CAPWAP", конец)
        return True
    if управление:
        if t or k:
            raise _Не("у сообщения управления биты T и K — нули")
        _нужно(место, 8, конец)
        предприятие, тип, номер = u24(д, место), д[место + 3], д[место + 4]
        дл_эл, флаги_у = u16(д, место + 5), д[место + 7]
        if флаги_у or (предприятие == 0 and тип not in CAPWAP_СООБЩЕНИЯ):
            raise _Не("не сообщение управления CAPWAP")
        # «Число байт за номером» (4.5.1): длина, флаги и элементы; принимается и счёт без длины.
        if дл_эл not in (конец - место - 5, конец - место - 7):
            raise _Не("длина элементов не сходится с данными")
        имя = CAPWAP_СООБЩЕНИЯ.get(тип, f"тип {тип}") if предприятие == 0 else f"предприятие {предприятие}, тип {тип}"
        с = у.поле(имя, "capwap.control.header.msg_type", имя, место, 8, (предприятие << 8) | тип)
        у.поле("Предприятие (IANA)", "capwap.control.header.msg_type.enterprise_number", предприятие, место, 3,
               родитель=с)
        у.поле("Тип", "capwap.control.header.msg_type.enterprise_specific", тип, место + 3, 1, родитель=с)
        у.поле("Номер", "capwap.control.header.seq_number", номер, место + 4, 1, родитель=с)
        у.поле("Длина элементов", "capwap.control.header.msg_element_length", дл_эл, место + 5, 2, родитель=с)
        у.поле("Флаги", "capwap.control.header.flags", 0, место + 7, 1, родитель=с)
        _capwap_элементы(у, д, место + 8, конец)
        у.длина = конец - м
        у.итог = f"{имя}, номер {номер}"
        р.п.уровни.append(у)
        р.п.инфо = "CAPWAP " + у.итог
        return True
    if k:
        _нужно(место, 2, конец)
        дл_эл = u16(д, место)
        if дл_эл != конец - место - 2:
            raise _Не("длина элементов keep-alive не сходится")
        у.поле("Длина элементов", "capwap.control.header.msg_element_length", дл_эл, место, 2)
        _capwap_элементы(у, д, место + 2, конец)
        у.длина = конец - м
        у.итог = "Keep-Alive"
        р.п.уровни.append(у)
        р.п.инфо = "CAPWAP " + у.итог
        return True
    if место >= конец:
        raise _Не("кадр данных CAPWAP пуст")
    у.итог = "кадр IEEE 802.11" if t and wbid == 1 else ("кадр IEEE 802.3" if not t else f"родной кадр WBID {wbid}")
    р.п.уровни.append(у)
    р.п.инфо = "CAPWAP " + у.итог
    if not t:
        _дальше(р, ethernet, место)
    else:
        данные(р, место, у.итог, конец)
    return True


