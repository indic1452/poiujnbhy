def openvpn_tcp(р: Разбор, м: int, конец: int) -> bool:
    return _openvpn(р, м, конец, "tcp")


# == WireGuard ===========================================================================

WIREGUARD_ТИПЫ = {1: "Handshake Initiation", 2: "Handshake Response", 3: "Cookie Reply", 4: "Transport Data"}
#: Поля сообщений 1–3 (разд. 5.4.2–5.4.7): (подпись, ключ, длина) после type и reserved.
WIREGUARD_ПОЛЯ = {
    1: (("Отправитель", "wg.sender", 4), ("Эфемерный ключ", "wg.ephemeral", 32),
        ("Зашифрованный статический ключ", "wg.encrypted_static", 48),
        ("Зашифрованная отметка времени", "wg.encrypted_timestamp", 28), ("mac1", "wg.mac1", 16),
        ("mac2", "wg.mac2", 16)),
    2: (("Отправитель", "wg.sender", 4), ("Получатель", "wg.receiver", 4), ("Эфемерный ключ", "wg.ephemeral", 32),
        ("Зашифрованное пустое", "wg.encrypted_empty", 16), ("mac1", "wg.mac1", 16), ("mac2", "wg.mac2", 16)),
    3: (("Получатель", "wg.receiver", 4), ("Nonce", "wg.nonce", 24),
        ("Зашифрованная cookie", "wg.encrypted_cookie", 32)),
}
WIREGUARD_ДЛИНЫ = {1: 148, 2: 92, 3: 64}


@_строго
def wireguard(р: Разбор, м: int, конец: int) -> bool:
    """WireGuard (разд. 5.4): тип 1–4 и три нулевых байта; длины 148, 92, 64 строго;
    данные — 16 байт заголовка и шифротекст кратный 16 (не меньше 16 — тег Poly1305)."""
    д = р.д
    _нужно(м, 4, конец)
    тип, длина = д[м], конец - м
    if тип not in WIREGUARD_ТИПЫ or д[м + 1:м + 4] != b"\0\0\0":
        raise _Не("не заголовок WireGuard")
    if тип in WIREGUARD_ДЛИНЫ and длина != WIREGUARD_ДЛИНЫ[тип]:
        raise _Не("длина сообщения WireGuard не та")
    if тип == 4 and (длина < 32 or (длина - 16) % 16):
        raise _Не("длина данных WireGuard не кратна 16")
    у = Уровень("WireGuard", "WireGuard", м)
    у.поле("Тип", "wg.type", f"{тип} ({WIREGUARD_ТИПЫ[тип]})", м, 1, тип)
    у.поле("Зарезервировано", "wg.reserved", "000000", м + 1, 3, 0)
    место = м + 4
    получатель = отправитель = None
    if тип == 4:
        получатель = int.from_bytes(д[место:место + 4], "little")
        у.поле("Получатель", "wg.receiver", f"0x{получатель:08x}", место, 4, получатель)
        у.поле("Счётчик", "wg.counter", int.from_bytes(д[место + 4:место + 12], "little"), место + 4, 8)
        у.поле("Зашифрованный пакет", "wg.encrypted_packet", f"{длина - 16} байт", место + 12, длина - 16)
    else:
        for подпись, ключ, n in WIREGUARD_ПОЛЯ[тип]:
            if n == 4:
                значение = int.from_bytes(д[место:место + 4], "little")
                у.поле(подпись, ключ, f"0x{значение:08x}", место, 4, значение)
                if ключ == "wg.sender":
                    отправитель = значение
                else:
                    получатель = значение
            else:
                у.поле(подпись, ключ, д[место:место + n].hex(), место, n)
            место += n
    у.длина = длина
    у.итог = WIREGUARD_ТИПЫ[тип] + (f", отправитель 0x{отправитель:08x}" if отправитель is not None else "") \
        + (f", получатель 0x{получатель:08x}" if получатель is not None else "")
    р.п.уровни.append(у)
    р.п.инфо = "WireGuard " + у.итог
    return True


