# == OpenVPN =============================================================================

OPENVPN_ОПКОДЫ = {1: "P_CONTROL_HARD_RESET_CLIENT_V1", 2: "P_CONTROL_HARD_RESET_SERVER_V1",
                  3: "P_CONTROL_SOFT_RESET_V1", 4: "P_CONTROL_V1", 5: "P_ACK_V1", 6: "P_DATA_V1",
                  7: "P_CONTROL_HARD_RESET_CLIENT_V2", 8: "P_CONTROL_HARD_RESET_SERVER_V2", 9: "P_DATA_V2",
                  10: "P_CONTROL_HARD_RESET_CLIENT_V3", 11: "P_CONTROL_WKC_V1"}
#: Размеры HMAC при tls-auth (SHA1, SHA256, SHA512, MD5, SHA384); 0 — без tls-auth.
OPENVPN_HMAC = (0, 20, 32, 64, 16, 48)
#: Наибольшее число подтверждений в пакете (RELIABLE_ACK_SIZE в reliable.h).
OPENVPN_ПОДТВЕРЖДЕНИЙ = 8


def _tls_запись_начинается(д: bytes, м: int, конец: int) -> bool:
    return (конец - м >= 5 and д[м] in (20, 21, 22, 23) and д[м + 1] == 3 and д[м + 2] <= 4
            and 0 < u16(д, м + 3) <= 16384 + 2048)


def _tlv_цепочка(д: bytes, м: int, конец: int) -> bool:
    while м < конец:
        if м + 4 > конец:
            return False
        м += 4 + u16(д, м + 2)
    return м == конец


def _openvpn_раскладка(д: bytes, м: int, конец: int, опкод: int, строго: bool) -> dict | None:
    """Раскладка пакета управления: session_id, [HMAC, packet-id, net_time], подтверждения, remote
    session_id, message packet-id, нагрузка. Подбирается размер HMAC, при котором всё сходится.
    """
    for hmac in OPENVPN_HMAC:
        место = м + 1 + 8
        if hmac:
            место += hmac + 8
        if место + 1 > конец:
            continue
        n = д[место]
        acks = место + 1
        место = acks + 4 * n
        if n > OPENVPN_ПОДТВЕРЖДЕНИЙ or место > конец:
            continue
        удалённый = None
        if n:
            удалённый = место
            место += 8
        mpid = None
        if опкод != 5:
            mpid = место
            место += 4
        if место > конец:
            continue
        хвост = конец - место
        if опкод == 5:
            годится = n > 0 and хвост == 0
        elif опкод in (1, 2, 7, 8):
            # Первое надёжное сообщение ключевого сеанса — номер 0; нагрузка пуста или цепочка TLV.
            годится = u32(д, mpid) == 0 and (хвост == 0 or _tlv_цепочка(д, место, конец))
        elif опкод == 3:
            годится = хвост == 0
        else:
            годится = хвост > 0 and (not строго or _tls_запись_начинается(д, место, конец))
        if годится:
            return {"hmac": hmac, "n": n, "acks": acks, "удалённый": удалённый, "mpid": mpid, "нагрузка": место}
    return None


def _openvpn_пакет(р: Разбор, у: Уровень, м: int, конец: int, режим: str, родитель=None) -> str:
    """Один пакет OpenVPN (опкод/key_id, затем по опкоду). Режим: «udp» — только проверяемые
    пакеты управления, «tcp» (длина кадра уже проверена) и «как» — все опкоды."""
    д = р.д
    _нужно(м, 1, конец)
    опкод, ключ = д[м] >> 3, д[м] & 7
    if опкод not in OPENVPN_ОПКОДЫ:
        raise _Не("неизвестный опкод OpenVPN")
    имя = OPENVPN_ОПКОДЫ[опкод]
    у.поле("Опкод", "openvpn.type", f"{опкод} ({имя})", м, 1, опкод, родитель=родитель)
    у.поле("ID ключа", "openvpn.keyid", ключ, м, 1, родитель=родитель)
    if опкод in (6, 9):
        if режим == "udp":
            raise _Не("пакет данных OpenVPN по одному порту не доказать")
        место = м + 1
        if опкод == 9:
            _нужно(место, 3, конец)
            у.поле("ID узла", "openvpn.peerid", u24(д, место), место, 3, родитель=родитель)
            место += 3
        у.поле("Зашифрованные данные", "openvpn.data", f"{конец - место} байт", место, конец - место,
               родитель=родитель)
        return f"{имя}, ключ {ключ}"
    раскладка = None if опкод in (10, 11) else _openvpn_раскладка(д, м, конец, опкод, режим == "udp")
    if раскладка is None:
        if режим == "udp":
            raise _Не("раскладка пакета управления OpenVPN не сходится")
        _нужно(м + 1, 8, конец)
        у.поле("ID сеанса", "openvpn.sessionid", f"0x{u64(д, м + 1):016x}", м + 1, 8, u64(д, м + 1), родитель=родитель)
        у.поле("Далее", "openvpn.data", f"{конец - м - 9} байт (tls-crypt или неизвестная раскладка)", м + 9,
               конец - м - 9, родитель=родитель)
        return f"{имя}, ключ {ключ}"
    у.поле("ID сеанса", "openvpn.sessionid", f"0x{u64(д, м + 1):016x}", м + 1, 8, u64(д, м + 1), родитель=родитель)
    место, hmac = м + 9, раскладка["hmac"]
    if hmac:
        у.поле("HMAC (tls-auth)", "openvpn.hmac", д[место:место + hmac].hex(), место, hmac, родитель=родитель)
        у.поле("Номер от повтора", "openvpn.pid", u32(д, место + hmac), место + hmac, 4, родитель=родитель)
        у.поле("Время", "openvpn.net_time", u32(д, место + hmac + 4), место + hmac + 4, 4, родитель=родитель)
        место += hmac + 8
    n = раскладка["n"]
    а = у.поле("Подтверждений", "openvpn.mpid_arraylength", n, место, 1, родитель=родитель)
    for i in range(n):
        у.поле("Подтверждённый номер", "openvpn.mpid_arrayelement", u32(д, раскладка["acks"] + 4 * i),
               раскладка["acks"] + 4 * i, 4, родитель=а)
    if раскладка["удалённый"] is not None:
        у.поле("ID сеанса собеседника", "openvpn.rsessionid", f"0x{u64(д, раскладка['удалённый']):016x}",
               раскладка["удалённый"], 8, u64(д, раскладка["удалённый"]), родитель=родитель)
    if раскладка["mpid"] is not None:
        у.поле("Номер сообщения", "openvpn.mpid", u32(д, раскладка["mpid"]), раскладка["mpid"], 4, родитель=родитель)
    нагрузка = раскладка["нагрузка"]
    if нагрузка < конец:
        у.поле("Нагрузка", "openvpn.data", f"{конец - нагрузка} байт", нагрузка, конец - нагрузка, родитель=родитель)
    return f"{имя}, ключ {ключ}" + (f", номер {u32(д, раскладка['mpid'])}" if раскладка["mpid"] is not None else "")


def _openvpn(р: Разбор, м: int, конец: int, режим: str) -> bool:
    """OpenVPN: по UDP пакет целиком; по TCP — кадры с 2-байтовой длиной ровно до конца сегмента."""
    д = р.д
    у = Уровень("OpenVPN", "OpenVPN", м)
    итоги, tls_с = [], None
    if режим == "tcp":
        место = м
        while место < конец:
            _нужно(место, 3, конец)
            дл = u16(д, место)
            _нужно(место + 2, дл, конец)
            if дл < 1:
                raise _Не("пустой кадр OpenVPN")
            п = у.поле(f"Пакет, {дл} байт", "openvpn.plen", дл, место, 2 + дл)
            итоги.append(_openvpn_пакет(р, у, место + 2, место + 2 + дл, режим, родитель=п))
            место += 2 + дл
    else:
        итоги.append(_openvpn_пакет(р, у, м, конец, режим))
        опкод = д[м] >> 3
        if опкод == 4:
            раскладка = _openvpn_раскладка(д, м, конец, 4, True)
            if раскладка is not None:
                tls_с = раскладка["нагрузка"]
    у.длина = конец - м
    у.итог = "; ".join(итоги[:3]) + (" …" if len(итоги) > 3 else "")
    р.п.уровни.append(у)
    р.п.инфо = "OpenVPN " + у.итог
    if tls_с is not None:
        _попробовать(р, prilozh.tls, tls_с, конец, "TLS в OpenVPN (продолжение записи)")
        р.п.инфо = "OpenVPN " + у.итог
    return True


@_строго
def openvpn_udp(р: Разбор, м: int, конец: int) -> bool:
    return _openvpn(р, м, конец, "udp")


@_строго
def openvpn_как(р: Разбор, м: int, конец: int) -> bool:
    return _openvpn(р, м, конец, "как")


