# -*- coding: utf-8 -*-
"""Чтение захватов: pcap (микро- и наносекундный, оба порядка байт), pcapng, .sig.

pcapng читается по блокам: SHB задаёт порядок байт раздела, IDB — тип
канала и разрешение времени интерфейса, EPB/SPB/OPB — пакеты. Блоки прочих
видов пропускаются по их длине. Файл, оборванный на полуслове (захват
прервали), читается до последнего целого пакета — и это отмечается.
"""

from __future__ import annotations

import struct
from dataclasses import dataclass
from pathlib import Path
from typing import List, Optional, Tuple

#: Типы канального уровня pcap/pcapng (LINKTYPE_*), которые умеет разборщик.
КАНАЛЫ = {0: "loopback", 1: "Ethernet", 9: "PPP", 12: "IP", 14: "IP", 50: "PPP-HDLC",
          101: "IP", 104: "Cisco HDLC", 113: "Linux SLL", 228: "IPv4", 229: "IPv6",
          276: "Linux SLL2"}
#: Больше пакетов в просмотрщик не берём: остальное — в отметке «прочитано не всё».
ПАКЕТОВ_ДО = 200_000


@dataclass
class Запись:
    время: float
    данные: bytes
    длина: int          # исходная длина пакета в линии (может быть больше записанной)
    канал: str


@dataclass
class Захват:
    формат: str
    записи: List[Запись]
    заметки: List[str]


def _канал(номер: int) -> str:
    return КАНАЛЫ.get(номер, f"тип {номер}")


def pcap(сырые: bytes) -> Optional[Захват]:
    if len(сырые) < 24:
        return None
    магия = сырые[:4]
    варианты = {b"\xd4\xc3\xb2\xa1": ("<", 1e-6), b"\xa1\xb2\xc3\xd4": (">", 1e-6),
                b"\x4d\x3c\xb2\xa1": ("<", 1e-9), b"\xa1\xb2\x3c\x4d": (">", 1e-9)}
    if магия not in варианты:
        return None
    порядок, доля = варианты[магия]
    канал = _канал(struct.unpack_from(порядок + "I", сырые, 20)[0] & 0xFFFF)
    записи: List[Запись] = []
    заметки: List[str] = []
    место = 24
    while место + 16 <= len(сырые):
        сек, дробь, записано, исходно = struct.unpack_from(порядок + "IIII", сырые, место)
        if записано > 1 << 20:
            заметки.append(f"запись на смещении {место} испорчена (длина {записано}) — дальше не читаю")
            break
        if место + 16 + записано > len(сырые):
            заметки.append("файл оборван: последний пакет записан не целиком")
            break
        записи.append(Запись(сек + дробь * доля, сырые[место + 16:место + 16 + записано],
                             исходно, канал))
        место += 16 + записано
        if len(записи) >= ПАКЕТОВ_ДО:
            заметки.append(f"прочитаны первые {ПАКЕТОВ_ДО} пакетов")
            break
    return Захват("pcap", записи, заметки)


def pcapng(сырые: bytes) -> Optional[Захват]:
    if len(сырые) < 28 or сырые[:4] != b"\x0a\x0d\x0d\x0a":
        return None
    записи: List[Запись] = []
    заметки: List[str] = []
    интерфейсы: List[Tuple[str, float, int]] = []      # канал, доля секунды, snaplen
    порядок = "<"
    место = 0
    while место + 12 <= len(сырые):
        вид = struct.unpack_from(порядок + "I", сырые, место)[0]
        if вид == 0x0A0D0D0A:
            магия = сырые[место + 8:место + 12]
            порядок = "<" if магия == b"\x4d\x3c\x2b\x1a" else ">"
            интерфейсы = []
        длина = struct.unpack_from(порядок + "I", сырые, место + 4)[0]
        if длина < 12 or длина % 4 or место + длина > len(сырые):
            заметки.append(f"блок на смещении {место} оборван или испорчен — дальше не читаю")
            break
        тело = сырые[место + 8:место + длина - 4]
        if вид == 1 and len(тело) >= 8:                  # IDB
            тип, _, snap = struct.unpack_from(порядок + "HHI", тело, 0)
            доля = 1e-6
            опции = 8
            while опции + 4 <= len(тело):
                код, дл = struct.unpack_from(порядок + "HH", тело, опции)
                if код == 0:
                    break
                if код == 9 and дл >= 1:                 # if_tsresol
                    v = тело[опции + 4]
                    доля = 2.0 ** -(v & 0x7F) if v & 0x80 else 10.0 ** -v
                опции += 4 + (дл + 3) // 4 * 4
            интерфейсы.append((_канал(тип), доля, snap))
        elif вид in (6, 2) and интерфейсы:                # EPB, устаревший OPB
            if вид == 6:
                номер, старшие, младшие, записано, исходно = struct.unpack_from(
                    порядок + "IIIII", тело, 0)
                начало = 20
            else:
                номер, _, старшие, младшие, записано, исходно = struct.unpack_from(
                    порядок + "HHIIII", тело, 0)
                начало = 20
            if номер < len(интерфейсы):
                канал, доля, _ = интерфейсы[номер]
                записи.append(Запись(((старшие << 32) | младшие) * доля,
                                     тело[начало:начало + записано], исходно, канал))
        elif вид == 3 and интерфейсы:                    # SPB — без времени
            исходно = struct.unpack_from(порядок + "I", тело, 0)[0]
            канал, _, snap = интерфейсы[0]
            записано = min(исходно, snap or исходно, len(тело) - 4)
            записи.append(Запись(0.0, тело[4:4 + записано], исходно, канал))
        место += длина
        if len(записи) >= ПАКЕТОВ_ДО:
            заметки.append(f"прочитаны первые {ПАКЕТОВ_ДО} пакетов")
            break
    return Захват("pcapng", записи, заметки)


def кадры(кадры_: List[bytes], формат: str = ".sig") -> Захват:
    """Кадры без канального заголовка (из .sig, после HDLC): канал угадывается по кадру."""
    return Захват(формат, [Запись(float(i), bytes(к), len(к), "авто")
                           for i, к in enumerate(кадры_[:ПАКЕТОВ_ДО])],
                  [f"прочитаны первые {ПАКЕТОВ_ДО} кадров"] if len(кадры_) > ПАКЕТОВ_ДО else [])


def прочитать_захват(путь: str | Path | None = None, *, данные: bytes | None = None,
                     имя: str = "") -> Захват:
    """Захват из файла: pcap, pcapng или .sig (кадры с двухбайтовой длиной)."""
    if данные is None:
        данные = Path(путь).read_bytes()
    for читатель in (pcap, pcapng):
        захват = читатель(данные)
        if захват is not None:
            return захват
    from ..potok.chtenie import разобрать_sig  # noqa: PLC0415
    разобрано = разобрать_sig(данные)
    if разобрано is not None:
        места, формат, заметки = разобрано
        захват = кадры([данные[начало:начало + длина] for начало, длина in места])
        захват.заметки = [формат] + list(заметки) + захват.заметки
        return захват
    raise ValueError("файл не похож на захват: ни pcap, ни pcapng, ни .sig (кадры с длиной)")
