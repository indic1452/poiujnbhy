"""Фоновая работа «Анализа пакетов»: разбор захвата и отбор по фильтру — потоково.

**Разбор** читает захват запись за записью (``chtenie.ЧтецЗахвата``: pcap, pcapng,
.sig/.dpo; файл может ещё загружаться кусками) или куски идущего приёма с сети
(``progon.Кадры``), разбирает каждый пакет, собирает фрагменты, кладёт сводки и поля в
хранилище на диске (``hranilishe``) и копит статистику (``nakopitel``). Раз в
секунду пишет ход (``ход.json``: разобрано, байт, скорость, осталось) и изменившиеся
разделы статистики (``статистика/<раздел>.json``) — страница видит их сразу, дерево
протоколов растёт у неё на глазах. Память разбора не растёт с размером файла.

**Отбор** идёт следом за разбором по уже разобранным пакетам: проверяет фильтр,
дописывает номера подходящих (``номера.u32``) и копит такую же статистику только по
ним; когда разбор кончился и всё проверено — отбор готов.

Обе работы идут отдельным процессом (``python -m reportgen.setevoy.fon …``) или потоком
в сервере (маленькие файлы, тесты); команды — строками JSON в stdin процесса или в
очередь потока: пауза, продолжить, стоп. Закрытый stdin (сервер выключился) — стоп.
"""

from __future__ import annotations

import contextlib
import json
import queue
import sys
import threading
import time
from pathlib import Path
from typing import Any

from ..fayly import записать_атомарно
from .hranilishe import Писатель, Хранилище, отпечаток_потока, прочитать_json, убрать
from .nakopitel import РАЗДЕЛЫ, Накопитель

#: Как часто писать ход (секунд). Крупные разделы статистики пишутся реже: не чаще, чем
#: в ``ДОЛЯ_ЗАПИСИ`` раз от времени их сборки (чтобы запись не отнимала больше ~10 % разбора).
ХОД_КАЖДЫЕ = 1.0
ДОЛЯ_ЗАПИСИ = 10.0
#: Окно, по которому считается скорость (секунд).
ОКНО_СКОРОСТИ = 10.0
#: Сколько ждать новых данных загрузки, пока не счесть её прерванной (секунд).
ЖДАТЬ_ЗАГРУЗКУ = 30 * 60
ИДУТ = ("в очереди", "идёт", "ждёт данных", "пауза")
КОНЕЦ = ("готово", "остановлен", "ошибка", "прерван")


class Стоп(Exception):
    pass


class Команды:
    """Команды работе: пауза, продолжить, стоп — из очереди (поток) или stdin (процесс)."""

    def __init__(self, очередь: queue.Queue):
        self.очередь = очередь
        self.пауза = False
        self.стоп = ""

    def разобрать(self, ждать: float = 0.0) -> None:
        конец = time.monotonic() + ждать
        while True:
            остаток = конец - time.monotonic()
            try:
                к = self.очередь.get(timeout=остаток) if остаток > 0 else self.очередь.get_nowait()
            except queue.Empty:
                return
            вид = к.get("к")
            if вид == "стоп":
                self.стоп = к.get("почему") or "остановлен"
                return
            if вид == "пауза":
                self.пауза = True
            elif вид == "продолжить":
                self.пауза = False


class Снимки:
    """Разделы статистики накопителя — файлами ``папка/статистика/<раздел>.json`` по мере изменения."""

    def __init__(self, папка: Path):
        self.папка = Path(папка) / "статистика"
        self.папка.mkdir(parents=True, exist_ok=True)
        self.следующий: dict[str, float] = {}
        self.рев = 0

    def записать(self, н: Накопитель, *, всё: bool = False) -> bool:
        сейчас = time.monotonic()
        записано = False
        for имя in РАЗДЕЛЫ:
            if имя not in н.грязные:
                continue
            if not всё and сейчас < self.следующий.get(имя, 0.0):
                continue
            начало = time.monotonic()
            данные = json.dumps(н.раздел(имя), ensure_ascii=False, separators=(",", ":"))
            записать_атомарно(self.папка / f"{имя}.json", данные)
            стоило = time.monotonic() - начало
            self.следующий[имя] = time.monotonic() + max(ХОД_КАЖДЫЕ, ДОЛЯ_ЗАПИСИ * стоило)
            н.грязные.discard(имя)
            записано = True
        if записано:
            self.рев += 1
        return записано


class Скорость:
    """Пакеты и байты в секунду по скользящему окну; оценка оставшегося времени."""

    def __init__(self):
        self.точки: list[tuple[float, int, int]] = []

    def учесть(self, пакетов: int, байт: int) -> tuple[float, float]:
        сейчас = time.monotonic()
        self.точки.append((сейчас, пакетов, байт))
        while len(self.точки) > 2 and сейчас - self.точки[0][0] > ОКНО_СКОРОСТИ:
            self.точки.pop(0)
        t0, п0, б0 = self.точки[0]
        прошло = сейчас - t0
        if прошло <= 0:
            return 0.0, 0.0
        return (пакетов - п0) / прошло, (байт - б0) / прошло


def прочитать_мету(папка: Path) -> dict[str, Any]:
    return прочитать_json(Path(папка) / "захват.json", {}) or {}


# -- разбор ---------------------------------------------------------------------------------------------

class Разбор:
    """Разбор одного захвата: читает, разбирает, пишет хранилище, ход и статистику."""

    def __init__(self, папка: Path, команды: queue.Queue):
        self.папка = Path(папка)
        self.команды = Команды(команды)
        self.мета = прочитать_мету(self.папка)
        self.поколение = self.мета.get("поколение", 0)
        self.ход: dict[str, Any] = {"поколение": self.поколение, "состояние": "идёт", "разобрано": 0,
                                    "прочитано": 0, "всего_байт": 0, "скорость_пакетов": 0.0,
                                    "скорость_байт": 0.0, "осталось": None, "формат": "", "заметки": [],
                                    "ошибка": "", "начато": time.time(), "рев": 0}
        self.скорость = Скорость()
        self._записан_ход = 0.0
        self._данные_были = time.monotonic()
        self._прочитано_было = -1
        self.писатель: Писатель | None = None

    # -- источник --

    def _загрузка_готова(self) -> bool:
        мета = прочитать_мету(self.папка)
        загрузка = мета.get("загрузка") or {}
        if мета.get("поколение", self.поколение) != self.поколение:
            raise Стоп("захват разбирается заново")
        return not загрузка.get("идёт")

    def _чтец(self):
        источник = self.мета.get("источник") or {"вид": "файл"}
        if источник.get("вид") == "захват":
            from .zahvat_seti.progon import Кадры  # noqa: PLC0415
            return _ЧтецПриёма(Кадры({"вид": "захват", "папка": источник["папка"]}))
        from .chtenie import ЧтецЗахвата  # noqa: PLC0415
        if источник.get("вид") == "ссылка":
            from ..fayly_ssylki import проверить_отпечаток  # noqa: PLC0415
            беда = проверить_отпечаток(Path(источник["путь"]), источник)
            if беда:
                raise Стоп(беда)
            return ЧтецЗахвата(Path(источник["путь"]), готов=lambda: True)
        return ЧтецЗахвата(self.папка / "исходник", готов=self._загрузка_готова)

    # -- ход --

    def _писать_ход(self, состояние: str | None = None, *, сразу: bool = False, чтец=None) -> None:
        if состояние:
            self.ход["состояние"] = состояние
        сейчас = time.monotonic()
        if not сразу and сейчас - self._записан_ход < ХОД_КАЖДЫЕ:
            return
        self._записан_ход = сейчас
        if self.писатель is not None:
            self.ход["разобрано"] = self.писатель.записано      # видно читателям хранилища
        if чтец is not None:
            self.ход["прочитано"] = чтец.место()
            self.ход["всего_байт"] = чтец.размер()
            self.ход["формат"] = чтец.формат
            self.ход["заметки"] = list(чтец.заметки)[-50:]
        п, б = self.скорость.учесть(self.ход["разобрано"], self.ход["прочитано"])
        self.ход["скорость_пакетов"], self.ход["скорость_байт"] = round(п, 1), round(б)
        загрузка = (self.мета.get("загрузка") or {})
        осталось_байт = max(0, (загрузка.get("всего") or self.ход["всего_байт"]) - self.ход["прочитано"])
        self.ход["осталось"] = round(осталось_байт / б, 1) if б > 0 and self.ход["состояние"] == "идёт" else None
        with contextlib.suppress(OSError):
            записать_атомарно(self.папка / "ход.json", json.dumps(self.ход, ensure_ascii=False))

    def _ждать(self, чтец) -> None:
        """Целой записи пока нет: файл догружается или приём ещё идёт."""
        if чтец.место() != self._прочитано_было or чтец.размер() != self.ход["всего_байт"]:
            self._данные_были = time.monotonic()
            self._прочитано_было = чтец.место()
        elif time.monotonic() - self._данные_были > ЖДАТЬ_ЗАГРУЗКУ and \
                (self.мета.get("источник") or {}).get("вид") != "захват":
            raise Стоп("загрузка прервалась: новых данных нет больше 30 минут — разобрано то, что пришло")
        self._писать_ход("ждёт данных", чтец=чтец)
        self.команды.разобрать(0.2)

    # -- работа --

    def работать(self) -> None:
        from .razbor import разобрать_пакет  # noqa: PLC0415
        from .sborka import Сборка, _для_фильтра, _сводка  # noqa: PLC0415
        from .statistika import ключ_потока  # noqa: PLC0415

        убрать(self.папка)
        import shutil  # noqa: PLC0415
        shutil.rmtree(self.папка / "собранные", ignore_errors=True)
        shutil.rmtree(self.папка / "статистика", ignore_errors=True)
        источник = self.мета.get("источник") or {"вид": "файл"}
        писатель = self.писатель = Писатель(self.папка, копировать=источник.get("вид") == "захват")
        накопитель = Накопитель()
        снимки = Снимки(self.папка)
        как = dict(self.мета.get("как") or {})
        сборка = Сборка(self.папка, как)
        шаблоны: dict[str, Any] = {}
        шаблонов_записано = 0.0
        чтец = None
        номер = 0
        try:
            чтец = self._чтец()
            self._писать_ход("идёт", сразу=True)
            while True:
                self.команды.разобрать()
                if self.команды.стоп:
                    raise Стоп(self.команды.стоп)
                if self.команды.пауза:
                    писатель.сбросить()
                    снимки.записать(накопитель, всё=True)
                    self.ход["рев"] = снимки.рев
                    self._писать_ход("пауза", сразу=True, чтец=чтец)
                    while self.команды.пауза and not self.команды.стоп:
                        self.команды.разобрать(0.5)
                    self._писать_ход("идёт", сразу=True, чтец=чтец)
                    continue
                запись = чтец.следующий()
                if запись is False:
                    break
                if запись is None:
                    писатель.сбросить()
                    if снимки.записать(накопитель):
                        self.ход["рев"] = снимки.рев
                    self._ждать(чтец)
                    continue
                if self.ход["состояние"] != "идёт":
                    self.ход["состояние"] = "идёт"
                время, данные, исходно, канал, место = запись
                номер += 1
                п = разобрать_пакет(данные, канал, номер=номер, время=время, исходная_длина=исходно,
                                    как=сборка.как, шаблоны=шаблоны)
                поля, собран = сборка.пакет(п)
                сводка = _сводка(п, поля)
                для_фильтра = _для_фильтра(поля)
                писатель.добавить(данные=данные, место=место, канал=канал, сводка=сводка, поля=для_фильтра,
                                  время=сводка["время"], длина=п.исходная_длина,
                                  поток=отпечаток_потока(ключ_потока(сводка)))
                if собран:
                    писатель.отметить_собранный()
                накопитель.добавить(сводка, для_фильтра, len(данные))
                if сборка.mp_короткие_с is not None:
                    self.ход["mp_короткие_с"] = сборка.mp_короткие_с
                if номер % 256 == 0:
                    сейчас = time.monotonic()
                    if сейчас - self._записан_ход >= ХОД_КАЖДЫЕ:
                        писатель.сбросить()
                        if снимки.записать(накопитель):
                            self.ход["рев"] = снимки.рев
                        if шаблоны and сейчас - шаблонов_записано > 5.0:
                            self._шаблоны(шаблоны)
                            шаблонов_записано = сейчас
                        self._писать_ход(чтец=чтец)
            итог, ошибка = "готово", ""
        except Стоп as причина:
            итог, ошибка = ("прерван" if "загрузка прервалась" in str(причина) or "сервер" in str(причина)
                            else "остановлен"), str(причина)
            if "заново" in str(причина):
                return
        except Exception as е:  # noqa: BLE001 — разбор не роняет сервер; что успели — видно
            итог, ошибка = "ошибка", f"{type(е).__name__}: {е}"
        try:
            self._закончить(писатель, шаблоны, снимки, накопитель, итог, ошибка, чтец)
        except OSError:
            # Папку записи удалили посреди разбора (человек удалил запись) — дописывать некуда.
            with contextlib.suppress(Exception):
                if чтец is not None:
                    чтец.закрыть()

    def _закончить(self, писатель, шаблоны, снимки, накопитель, итог: str, ошибка: str, чтец) -> None:
        писатель.закрыть()
        self._шаблоны(шаблоны)
        снимки.записать(накопитель, всё=True)
        self.ход.update(состояние=итог, ошибка=ошибка if итог != "готово" else "", разобрано=писатель.записано,
                        закончено=time.time(), рев=снимки.рев + 1)
        if итог == "готово" and not self.ход.get("осталось"):
            self.ход["осталось"] = None
        if чтец is not None:
            self._записан_ход = 0.0
            self._писать_ход(сразу=True, чтец=чтец)
            чтец.закрыть()
        else:
            self._писать_ход(сразу=True)

    def _шаблоны(self, шаблоны: dict[str, Any]) -> None:
        with contextlib.suppress(OSError, TypeError, ValueError):
            записать_атомарно(self.папка / "шаблоны.json", json.dumps(шаблоны, ensure_ascii=False, default=str))


class _ЧтецПриёма:
    """Записи идущего приёма с сети (progon.Кадры) — в виде ЧтецЗахвата: байты пакетов копируются."""

    def __init__(self, кадры):
        self.кадры = кадры
        self.формат = "pcapng (приём с сети)"
        self._байт = 0

    @property
    def заметки(self) -> list[str]:
        return self.кадры.заметки

    def следующий(self):
        запись = self.кадры.следующий()
        if запись is None or запись is False:
            return запись
        время, данные, исходно, канал = запись
        self._байт += len(данные) + 16
        return время, данные, исходно, канал, None

    def место(self) -> int:
        return self._байт

    def размер(self) -> int:
        return self._байт

    def закрыть(self) -> None:
        self.кадры.закрыть()


# -- отбор по фильтру -------------------------------------------------------------------------------------

class Отбор:
    """Отбор пакетов захвата по фильтру следом за разбором: номера и статистика отобранных."""

    ПОРЦИЯ = 4096

    def __init__(self, папка: Path, папка_отбора: Path, команды: queue.Queue):
        self.папка = Path(папка)
        self.папка_отбора = Path(папка_отбора)
        self.команды = Команды(команды)

    def работать(self) -> None:
        from .filtr import нужны_байты, собрать  # noqa: PLC0415
        фильтр = (self.папка_отбора / "фильтр.txt").read_text(encoding="utf-8")
        поколение = прочитать_json(self.папка_отбора / "ход.json", {}).get("поколение", 0)
        ход: dict[str, Any] = {"поколение": поколение, "состояние": "идёт", "проверено": 0, "отобрано": 0,
                               "ошибка": "", "рев": 0, "начато": time.time()}
        х = Хранилище(self.папка)
        накопитель = Накопитель()
        снимки = Снимки(self.папка_отбора)
        записан = 0.0
        try:
            условие = собрать(фильтр)
            байты = нужны_байты(фильтр)
            with open(self.папка_отбора / "номера.u32", "wb") as номера:
                while True:
                    self.команды.разобрать()
                    if self.команды.стоп:
                        raise Стоп(self.команды.стоп)
                    while self.команды.пауза and not self.команды.стоп:
                        self.команды.разобрать(0.5)
                    всего = х.число()
                    if ход["проверено"] >= всего:
                        разбор = прочитать_json(self.папка / "ход.json", {}) or {}
                        if разбор.get("поколение", 0) != поколение:
                            raise Стоп("захват разбирается заново")
                        if разбор.get("состояние") in КОНЕЦ and х.число() <= ход["проверено"]:
                            break
                        ход["состояние"] = "ждёт данных"
                        if снимки.записать(накопитель):
                            ход["рев"] = снимки.рев
                        self._ход(ход)
                        self.команды.разобрать(0.3)
                        continue
                    ход["состояние"] = "идёт"
                    от, до = ход["проверено"], min(всего, ход["проверено"] + self.ПОРЦИЯ)
                    сводки, поля = х.сводки(от, до), х.поля(от, до)
                    кадры = х.кадры(от, до) if байты else None
                    подошли = []
                    for j, (с, п) in enumerate(zip(сводки, поля, strict=True)):
                        if кадры is not None:
                            нагр = с.get("нагр")
                            к = кадры[j]
                            п = {**п, "_frame": к, "_payload": к[нагр[0]:нагр[0] + нагр[1]] if нагр else b""}
                        if условие(п):
                            подошли.append(от + j)
                            if кадры is not None:
                                del п["_frame"], п["_payload"]
                            накопитель.добавить(с, п, len(кадры[j]) if кадры is not None else 0)
                    if подошли:
                        import numpy as np  # noqa: PLC0415
                        номера.write(np.asarray(подошли, dtype="<u4").tobytes())
                        номера.flush()
                    ход["проверено"] = до
                    ход["отобрано"] += len(подошли)
                    if time.monotonic() - записан >= ХОД_КАЖДЫЕ:
                        записан = time.monotonic()
                        if снимки.записать(накопитель):
                            ход["рев"] = снимки.рев
                        self._ход(ход)
            итог = "готово"
        except Стоп as причина:
            итог = "остановлен"
            ход["ошибка"] = str(причина)
        except Exception as е:  # noqa: BLE001
            итог = "ошибка"
            ход["ошибка"] = f"{type(е).__name__}: {е}"
        with contextlib.suppress(OSError):              # отбор удалили (запись удалена или разбирается заново)
            снимки.записать(накопитель, всё=True)
            ход.update(состояние=итог, рев=снимки.рев + 1, закончено=time.time())
            self._ход(ход)

    def _ход(self, ход: dict[str, Any]) -> None:
        with contextlib.suppress(OSError):
            записать_атомарно(self.папка_отбора / "ход.json", json.dumps(ход, ensure_ascii=False))


# -- отдельный процесс --------------------------------------------------------------------------------------

def _читать_команды(очередь: queue.Queue) -> None:
    """Команды из stdin строками JSON; конец stdin (сервер выключился или закрыл связь) — стоп."""
    for строка in sys.stdin:
        with contextlib.suppress(ValueError):
            к = json.loads(строка)
            if isinstance(к, dict):
                очередь.put(к)
    очередь.put({"к": "стоп", "почему": "сервер закрыл связь с разбором"})


def main(аргументы: list[str]) -> int:
    очередь: queue.Queue = queue.Queue()
    threading.Thread(target=_читать_команды, args=(очередь,), daemon=True).start()
    if аргументы[1] == "разбор":
        Разбор(Path(аргументы[2]), очередь).работать()
    elif аргументы[1] == "отбор":
        Отбор(Path(аргументы[2]), Path(аргументы[3]), очередь).работать()
    else:
        print(f"неизвестная работа: {аргументы[1]}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
