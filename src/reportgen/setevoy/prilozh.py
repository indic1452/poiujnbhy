def l2tp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 6:
        return False
    флаги = u16(д, м)
    if флаги & 0x000F != 2:
        return False
    t, l, s, o = флаги >> 15, (флаги >> 14) & 1, (флаги >> 11) & 1, (флаги >> 9) & 1
    у = р.уровень("L2TP", "Layer 2 Tunneling Protocol v2", м)
    у.поле("Флаги", "l2tp.flags", f"0x{флаги:04x} ({'управление' if t else 'данные'})", м, 2, флаги)
    место = м + 2
    if l:
        у.поле("Длина", "l2tp.length", u16(д, место), место, 2)
        место += 2
    у.поле("Туннель", "l2tp.tunnel", u16(д, место), место, 2)
    у.поле("Сеанс", "l2tp.session", u16(д, место + 2), место + 2, 2)
    место += 4
    if s:
        место += 4
    if o:
        место += 2 + u16(д, место)
    у.длина = место - м
    у.итог = f"{'управление' if t else 'данные'}, туннель {u16(д, м + (4 if l else 2))}"
    if not t and место < конец:
        ppp(р, место)
    else:
        р.п.инфо = "L2TP " + у.итог
    return True


def bgp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 19 or д[м:м + 16] != b"\xff" * 16:
        return False
    у = р.уровень("BGP", "Border Gateway Protocol", м)
    типы = {1: "OPEN", 2: "UPDATE", 3: "NOTIFICATION", 4: "KEEPALIVE", 5: "ROUTE-REFRESH"}
    итоги, место = [], м
    while место + 19 <= конец and д[место:место + 16] == b"\xff" * 16:
        дл, тип = u16(д, место + 16), д[место + 18]
        п = у.поле(f"{типы.get(тип, тип)}, {дл} байт", "bgp.type", типы.get(тип, str(тип)), место, дл, тип)
        if тип == 1 and место + 29 <= конец:
            у.поле("Версия", "bgp.open.version", д[место + 19], место + 19, 1, родитель=п)
            у.поле("Номер AS", "bgp.open.myas", u16(д, место + 20), место + 20, 2, родитель=п)
            у.поле("Время удержания", "bgp.open.holdtime", u16(д, место + 22), место + 22, 2, родитель=п)
            у.поле("BGP ID", "bgp.open.identifier", ip4(д, место + 24), место + 24, 4, родитель=п)
        итоги.append(типы.get(тип, str(тип)))
        if дл < 19:
            break
        место += дл
    у.длина = место - м
    у.итог = ", ".join(итоги)
    р.п.инфо = "BGP " + у.итог
    return True


