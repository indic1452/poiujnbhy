def tftp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 4:
        return False
    код = u16(д, м)
    коды = {1: "чтение (RRQ)", 2: "запись (WRQ)", 3: "данные", 4: "подтверждение", 5: "ошибка", 6: "OACK"}
    if код not in коды:
        return False
    у = р.уровень("TFTP", "Trivial File Transfer Protocol", м)
    у.поле("Операция", "tftp.opcode", коды[код], м, 2, код)
    if код in (1, 2):
        части = д[м + 2:конец].split(b"\0")
        у.поле("Файл", "tftp.source_file", части[0].decode("utf-8", "replace"), м + 2, len(части[0]))
        if len(части) > 1:
            у.поле("Режим", "tftp.type", части[1].decode("ascii", "replace"), м + 3 + len(части[0]), len(части[1]))
        у.итог = f"{коды[код]} «{части[0].decode('utf-8', 'replace')}»"
    elif код in (3, 4):
        у.поле("Блок", "tftp.block", u16(д, м + 2), м + 2, 2)
        у.итог = f"{коды[код]}, блок {u16(д, м + 2)}" + (f", {конец - м - 4} байт" if код == 3 else "")
    else:
        у.итог = коды[код]
    у.длина = конец - м
    р.п.инфо = "TFTP " + у.итог
    return True


def radius(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 20 or u16(д, м + 2) != конец - м:
        return False
    коды = {1: "Access-Request", 2: "Access-Accept", 3: "Access-Reject", 4: "Accounting-Request",
            5: "Accounting-Response", 11: "Access-Challenge"}
    у = р.уровень("RADIUS", "RADIUS", м)
    у.поле("Код", "radius.code", коды.get(д[м], д[м]), м, 1, д[м])
    у.поле("Идентификатор", "radius.id", д[м + 1], м + 1, 1)
    у.поле("Длина", "radius.length", u16(д, м + 2), м + 2, 2)
    у.поле("Аутентификатор", "radius.authenticator", д[м + 4:м + 20].hex(), м + 4, 16)
    атрибуты = {1: "User-Name", 4: "NAS-IP-Address", 5: "NAS-Port", 8: "Framed-IP-Address",
                30: "Called-Station-Id", 31: "Calling-Station-Id", 32: "NAS-Identifier", 44: "Acct-Session-Id"}
    место, пользователь = м + 20, ""
    while место + 2 <= конец:
        тип, дл = д[место], max(2, д[место + 1])
