# -- DNS ----------------------------------------------------------------------------------

DNS_ТИПЫ = {1: "A", 2: "NS", 5: "CNAME", 6: "SOA", 12: "PTR", 15: "MX", 16: "TXT", 28: "AAAA",
            33: "SRV", 41: "OPT", 43: "DS", 46: "RRSIG", 47: "NSEC", 48: "DNSKEY", 64: "SVCB",
            65: "HTTPS", 255: "ANY"}
DNS_ОТВЕТЫ = {0: "нет ошибки", 1: "ошибка формата", 2: "сбой сервера", 3: "нет такого имени",
              4: "не реализовано", 5: "отказано"}


def имя_dns(д: bytes, м: int, начало: int) -> Tuple[str, int]:
    """Имя с учётом сжатия (указатели 0xC0): имя и место за ним в исходной записи.

    Указатель ведёт на прежнее вхождение имени (RFC 1035, 4.1.4) — строго
    раньше всего, что уже прочитано. Так петля указателей невозможна: граница
    с каждым переходом только убывает.
    """
    части: List[str] = []
    конец_записи = None
    граница = м
    while True:
        if м >= len(д):
            raise Мало()
        дл = д[м]
        if дл == 0:
            м += 1
            break
        if дл & 0xC0 == 0xC0:
            if м + 1 >= len(д):
                raise Мало()
            if конец_записи is None:
                конец_записи = м + 2
            м = начало + (((дл & 0x3F) << 8) | д[м + 1])
            if м >= граница:
                raise ValueError("DNS: указатель в имени ведёт не назад (петля или порча)")
            граница = м
            continue
        части.append(д[м + 1:м + 1 + дл].decode("ascii", "replace"))
        м += 1 + дл
    return ".".join(части) or ".", (конец_записи if конец_записи is not None else м)


def dns(р: Разбор, м: int, конец: int, *, tcp: bool = False, имя: str = "DNS") -> bool:
    начало_tcp = м
    if tcp:
        if м + 2 > конец:
            return False
        м += 2
    if конец - м < 12:
        return False
    д = р.д
    вопросов, ответов, власть, доп = u16(д, м + 4), u16(д, м + 6), u16(д, м + 8), u16(д, м + 10)
    if вопросов > 64 or ответов > 512 or власть > 512 or доп > 512:
        return False
    у = р.уровень(имя, {"DNS": "Domain Name System", "mDNS": "Multicast DNS",
                        "LLMNR": "Link-Local Multicast Name Resolution"}.get(имя, имя), начало_tcp)
    флаги = u16(д, м + 2)
    ответ, код_оп, rcode = флаги >> 15, (флаги >> 11) & 15, флаги & 15
    if tcp:
        у.поле("Длина (TCP)", "dns.length", u16(д, начало_tcp), начало_tcp, 2)
    у.поле("Идентификатор", "dns.id", f"0x{u16(д, м):04x}", м, 2, u16(д, м))
    п = у.поле("Флаги", "dns.flags", f"0x{флаги:04x} ({'ответ' if ответ else 'запрос'}"
               + (f", {DNS_ОТВЕТЫ.get(rcode, rcode)}" if ответ else "") + ")", м + 2, 2, флаги)
    у.поле("Ответ", "dns.flags.response", ответ, м + 2, 2, родитель=п)
    у.поле("Код операции", "dns.flags.opcode", код_оп, м + 2, 2, родитель=п)
    for имя_, бит in (("Авторитетный", 10), ("Усечён", 9), ("Нужна рекурсия", 8), ("Рекурсия доступна", 7)):
        у.поле(имя_, "", флаги >> бит & 1, м + 2, 2, родитель=п)
    у.поле("Код ответа", "dns.flags.rcode", f"{rcode} ({DNS_ОТВЕТЫ.get(rcode, '?')})", м + 2, 2, rcode,
           родитель=п)
    у.поле("Вопросов", "dns.count.queries", вопросов, м + 4, 2)
    у.поле("Ответов", "dns.count.answers", ответов, м + 6, 2)
    у.поле("Записей власти", "dns.count.auth_rr", власть, м + 8, 2)
    у.поле("Дополнительных", "dns.count.add_rr", доп, м + 10, 2)
    место = м + 12
    запросы = []
    try:
        if вопросов:
            группа = у.поле("Вопросы", "", str(вопросов), место, 0)
            for _ in range(вопросов):
                имя_q, после = имя_dns(д, место, м)
                тип, класс = u16(д, после), u16(д, после + 2)
                т = DNS_ТИПЫ.get(тип, str(тип))
                q = у.поле(f"{имя_q}: {т}", "dns.qry.name", имя_q, место, после + 4 - место, родитель=группа)
                у.поле("Тип", "dns.qry.type", т, после, 2, тип, родитель=q)
                у.поле("Класс", "dns.qry.class", класс & 0x7FFF, после + 2, 2, родитель=q)
                группа.длина = после + 4 - группа.смещение
                запросы.append(f"{т} {имя_q}")
                место = после + 4
        ответы_текст = []
        for раздел, сколько, ключ in (("Ответы", ответов, "dns.resp"), ("Власть", власть, "dns.auth"),
                                      ("Дополнительно", доп, "dns.add")):
            if not сколько:
                continue
            группа = у.поле(раздел, "", str(сколько), место, 0)
            for _ in range(сколько):
                имя_r, после = имя_dns(д, место, м)
                тип, класс, ttl, дл = u16(д, после), u16(д, после + 2), u32(д, после + 4), u16(д, после + 8)
                данные_rr = после + 10
                if данные_rr + дл > конец:
                    raise Мало()
                значение = _rdata(д, тип, данные_rr, дл, м)
                т = DNS_ТИПЫ.get(тип, str(тип))
                rr = у.поле(f"{имя_r}: {т} {значение}", ключ + ".name", имя_r, место,
                            данные_rr + дл - место, родитель=группа)
                у.поле("Тип", ключ + ".type", т, после, 2, тип, родитель=rr)
                у.поле("TTL", ключ + ".ttl", ttl, после + 4, 4, родитель=rr)
                у.поле("Данные", {1: "dns.a", 28: "dns.aaaa", 5: "dns.cname", 15: "dns.mx.mail_exchange",
                                  12: "dns.ptr.domain_name", 2: "dns.ns", 16: "dns.txt"}.get(тип, ключ + ".data"),
                       значение, данные_rr, дл, родитель=rr)
                группа.длина = данные_rr + дл - группа.смещение
                if раздел == "Ответы":
                    ответы_текст.append(f"{т} {значение}")
                место = данные_rr + дл
    except Мало:
        р.ошибка(f"{имя}: сообщение оборвано")
    у.длина = место - начало_tcp
    ид = f"0x{u16(д, м):04x}"
    if ответ:
        у.итог = (f"Ответ {ид} {' '.join(запросы)}"
                  + (f" → {', '.join(ответы_текст[:4])}" if ответы_текст else "")
                  + (f" [{DNS_ОТВЕТЫ.get(rcode, rcode)}]" if rcode else ""))
    else:
        у.итог = f"Запрос {ид} " + " ".join(запросы)
    р.п.инфо = f"{имя} {у.итог}"
    return True


def _rdata(д: bytes, тип: int, м: int, дл: int, начало: int) -> str:
    if тип == 1 and дл == 4:
        return ip4(д, м)
    if тип == 28 and дл == 16:
        return ip6(д, м)
    if тип in (2, 5, 12):
        return имя_dns(д, м, начало)[0]
    if тип == 15 and дл >= 3:
        return f"{u16(д, м)} {имя_dns(д, м + 2, начало)[0]}"
    if тип == 16:
        части, место = [], м
        while место < м + дл:
            n = д[место]
            части.append(д[место + 1:место + 1 + n].decode("utf-8", "replace"))
            место += 1 + n
        return " ".join(f"\"{ч}\"" for ч in части)
    if тип == 33 and дл >= 7:
        return f"приоритет {u16(д, м)}, вес {u16(д, м + 2)}, порт {u16(д, м + 4)}, {имя_dns(д, м + 6, начало)[0]}"
    if тип == 6:
        первичный, после = имя_dns(д, м, начало)
        почта, после = имя_dns(д, после, начало)
        return f"{первичный} {почта} serial {u32(д, после)}"
    if тип == 41:
        return f"EDNS, размер {дл} байт опций"
    return д[м:м + дл].hex()


# -- DHCP -----------------------------------------------------------------------------------

DHCP_ТИПЫ = {1: "DISCOVER", 2: "OFFER", 3: "REQUEST", 4: "DECLINE", 5: "ACK", 6: "NAK",
             7: "RELEASE", 8: "INFORM"}
DHCP_ОПЦИИ = {1: "Маска подсети", 3: "Маршрутизатор", 6: "DNS-серверы", 12: "Имя узла",
              15: "Домен", 28: "Широковещательный адрес", 42: "NTP-серверы", 50: "Запрошенный адрес",
              51: "Срок аренды", 53: "Тип сообщения", 54: "Сервер DHCP", 55: "Список запрошенных параметров",
              57: "Наибольший размер", 58: "T1", 59: "T2", 60: "Класс поставщика", 61: "Идентификатор клиента",
              81: "Полное имя клиента", 82: "Агент ретрансляции"}


def dhcp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 240 or д[м + 236:м + 240] != b"\x63\x82\x53\x63":
        return False
    у = р.уровень("DHCP", "Dynamic Host Configuration Protocol", м)
    у.поле("Операция", "dhcp.type", "запрос" if д[м] == 1 else "ответ", м, 1, д[м])
    у.поле("Идентификатор (xid)", "dhcp.id", f"0x{u32(д, м + 4):08x}", м + 4, 4, u32(д, м + 4))
    for имя, ключ, место in (("Адрес клиента", "dhcp.ip.client", 12), ("Выданный адрес", "dhcp.ip.your", 16),
                             ("Адрес сервера", "dhcp.ip.server", 20), ("Адрес ретранслятора", "dhcp.ip.relay", 24)):
        у.поле(имя, ключ, ip4(д, м + место), м + место, 4)
    клиент = mac(д, м + 28)
    у.поле("MAC клиента", "dhcp.hw.mac_addr", клиент, м + 28, 6)
    у.поле("Магическое число", "dhcp.cookie", "63825363", м + 236, 4)
    место, тип_сообщения = м + 240, None
    группа = у.поле("Опции", "", "", место, 0)
    while место < конец:
        код = д[место]
        if код == 0:
            место += 1
            continue
        if код == 255:
            у.поле("Конец", "dhcp.option.end", "", место, 1, родитель=группа)
            место += 1
            break
        if место + 2 > конец:
            break
        дл = д[место + 1]
        значение = д[место + 2:место + 2 + дл]
        if код == 53 and дл == 1:
            тип_сообщения = значение[0]
            текст = DHCP_ТИПЫ.get(значение[0], str(значение[0]))
        elif код in (1, 3, 6, 28, 42, 50, 54) and дл % 4 == 0 and дл:
            текст = ", ".join(ip4(значение, i) for i in range(0, дл, 4))
        elif код in (51, 58, 59) and дл == 4:
            текст = f"{u32(значение, 0)} с"
        elif код in (12, 15, 60):
            текст = значение.decode("utf-8", "replace")
        elif код == 55:
            текст = ", ".join(str(б) for б in значение)
        else:
            текст = значение.hex()
        у.поле(f"({код}) {DHCP_ОПЦИИ.get(код, 'опция')}: {текст}", f"dhcp.option.{код}", текст, место, 2 + дл,
               родитель=группа)
        место += 2 + дл
    группа.длина = место - группа.смещение
    у.длина = место - м
    у.итог = f"{DHCP_ТИПЫ.get(тип_сообщения, 'BOOTP')}, xid 0x{u32(д, м + 4):08x}, клиент {клиент}"
    if д[м + 16:м + 20] != b"\0\0\0\0":
        у.итог += f", адрес {ip4(д, м + 16)}"
    р.п.инфо = "DHCP " + у.итог
    return True


# -- NTP ---------------------------------------------------------------------------------------

def ntp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 48:
        return False
    li, версия, режим = д[м] >> 6, (д[м] >> 3) & 7, д[м] & 7
    if версия not in (1, 2, 3, 4):
        return False
    у = р.уровень("NTP", "Network Time Protocol", м)
    режимы = {1: "симметричный активный", 2: "симметричный пассивный", 3: "клиент", 4: "сервер",
              5: "широковещание", 6: "управление", 7: "частный"}
    у.поле("Индикатор секунды (LI)", "ntp.flags.li", li, м, 1)
    у.поле("Версия", "ntp.flags.vn", версия, м, 1)
    у.поле("Режим", "ntp.flags.mode", режимы.get(режим, режим), м, 1, режим)
    у.поле("Стратум", "ntp.stratum", д[м + 1], м + 1, 1)
    у.поле("Интервал опроса", "ntp.ppoll", f"2^{д[м + 2]} с", м + 2, 1, д[м + 2])
    опорный = ip4(д, м + 12) if д[м + 1] >= 2 else д[м + 12:м + 16].decode("ascii", "replace").strip("\0")
    у.поле("Опорный идентификатор", "ntp.refid", опорный, м + 12, 4)
    for имя, место in (("Опорное время", 16), ("Время отправки клиента", 24), ("Время приёма", 32),
                       ("Время передачи", 40)):
        сек, дробь = u32(д, м + место), u32(д, м + место + 4)
        у.поле(имя, "ntp." + {16: "reftime", 24: "org", 32: "rec", 40: "xmt"}[место],
               _ntp_время(сек, дробь), м + место, 8, сек + дробь / 2 ** 32)
    у.длина = 48
    у.итог = f"{режимы.get(режим, режим)}, версия {версия}, стратум {д[м + 1]}"
    р.п.инфо = "NTP " + у.итог
    return True


def _ntp_время(сек: int, дробь: int) -> str:
    if not сек:
        return "0"
    import datetime  # noqa: PLC0415
    эпоха = datetime.datetime(1900, 1, 1, tzinfo=datetime.timezone.utc)
    момент = эпоха + datetime.timedelta(seconds=сек + дробь / 2 ** 32)
    return момент.strftime("%Y-%m-%d %H:%M:%S.%f UTC")


# -- ASN.1 BER (SNMP) ---------------------------------------------------------------------------

def _ber(д: bytes, м: int) -> Tuple[int, int, int]:
    """Тег, длина, начало значения."""
    тег = д[м]
    дл = д[м + 1]
    м += 2
    if дл & 0x80:
        n = дл & 0x7F
        if n == 0 or n > 4:
            raise ValueError("BER: неопределённая длина")
        дл = int.from_bytes(д[м:м + n], "big")
        м += n
    if м + дл > len(д):
        raise Мало()
    return тег, дл, м


def _oid(данные: bytes) -> str:
    if not данные:
        return ""
    части = [str(данные[0] // 40), str(данные[0] % 40)]
    значение = 0
    for б in данные[1:]:
        значение = (значение << 7) | (б & 0x7F)
        if not б & 0x80:
            части.append(str(значение))
            значение = 0
    return ".".join(части)


def _ber_значение(тег: int, данные: bytes) -> str:
    if тег == 0x02:
        return str(int.from_bytes(данные, "big", signed=True))
    if тег == 0x04:
        return данные.decode("utf-8") if all(32 <= б < 127 for б in данные) else данные.hex()
    if тег == 0x06:
        return _oid(данные)
    if тег == 0x05:
        return "NULL"
    if тег == 0x40 and len(данные) == 4:
        return ip4(данные, 0)
    if тег in (0x41, 0x42, 0x43, 0x46):
        return str(int.from_bytes(данные, "big"))
    if тег in (0x80, 0x81, 0x82):
        return {0x80: "noSuchObject", 0x81: "noSuchInstance", 0x82: "endOfMibView"}[тег]
    return данные.hex()


def snmp(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[:конец]
    try:
        тег, дл, место = _ber(д, м)
        if тег != 0x30:
            return False
        т, дл_в, мв = _ber(д, место)
        if т != 0x02:
            return False
        версия = int.from_bytes(д[мв:мв + дл_в], "big")
        у = р.уровень("SNMP", "Simple Network Management Protocol", м)
        у.поле("Версия", "snmp.version", {0: "v1", 1: "v2c", 3: "v3"}.get(версия, версия), мв, дл_в, версия)
        место = мв + дл_в
        if версия == 3:
            у.итог = "SNMPv3 (сообщение защищено — разбирается только заголовок)"
            у.длина = конец - м
            р.п.инфо = у.итог
            return True
        т, дл_с, мс = _ber(д, место)
        сообщество = д[мс:мс + дл_с].decode("utf-8", "replace")
        у.поле("Сообщество", "snmp.community", сообщество, мс, дл_с)
        место = мс + дл_с
        pdu, дл_p, мп = _ber(д, место)
        виды = {0xA0: "get-request", 0xA1: "get-next-request", 0xA2: "get-response", 0xA3: "set-request",
                0xA4: "trap (v1)", 0xA5: "getBulkRequest", 0xA6: "inform", 0xA7: "trap (v2)", 0xA8: "report"}
        вид = виды.get(pdu, f"0x{pdu:02x}")
        п = у.поле(f"PDU: {вид}", "snmp.data", вид, место, мп + дл_p - место, pdu)
        привязки = []
        if pdu != 0xA4:
            м2 = мп
            for имя, ключ in (("Идентификатор запроса", "snmp.request_id"), ("Статус ошибки", "snmp.error_status"),
                              ("Индекс ошибки", "snmp.error_index")):
                т, дл2, мз = _ber(д, м2)
                у.поле(имя, ключ, int.from_bytes(д[мз:мз + дл2], "big", signed=True), м2, мз + дл2 - м2, родитель=п)
                м2 = мз + дл2
            т, дл_v, мv = _ber(д, м2)
            конец_v = мv + дл_v
            while мv < конец_v:
                т, дл_b, мb = _ber(д, мv)
                т_o, дл_o, мo = _ber(д, мb)
                oid = _oid(д[мo:мo + дл_o])
                т_з, дл_з, мз = _ber(д, мo + дл_o)
                значение = _ber_значение(т_з, д[мз:мз + дл_з])
                у.поле(f"{oid} = {значение}", "snmp.name", oid, мv, мb + дл_b - мv, родитель=п)
                привязки.append(oid)
                мv = мb + дл_b
        у.длина = мп + дл_p - м
        у.итог = f"{вид}, сообщество «{сообщество}»" + (f", {' '.join(привязки[:3])}" if привязки else "")
        р.п.инфо = "SNMP " + у.итог
        return True
    except (Мало, ValueError, IndexError):
        return False


# -- текстовые протоколы ------------------------------------------------------------------------

HTTP_МЕТОДЫ = (b"GET ", b"POST ", b"PUT ", b"DELETE ", b"HEAD ", b"OPTIONS ", b"PATCH ", b"CONNECT ",
               b"TRACE ")


def http(р: Разбор, м: int, конец: int, *, протокол: str = "HTTP") -> bool:
    д = р.д[м:конец]
    запрос = д.startswith(HTTP_МЕТОДЫ) or (протокол != "HTTP" and д[:1].isalpha())
    ответ = д.startswith(b"HTTP/1.") or д.startswith(b"SIP/2.0 ") or д.startswith(b"RTSP/1.0 ")
    if not (запрос or ответ):
        return False
    граница = д.find(b"\r\n\r\n")
    заголовки = д[:граница if граница >= 0 else len(д)]
    строки = заголовки.split(b"\r\n")
    первая = строки[0].decode("utf-8", "replace")
    if протокол == "HTTP" and запрос and " HTTP/" not in первая:
        return False
    полное = {"HTTP": "Hypertext Transfer Protocol", "SIP": "Session Initiation Protocol",
              "RTSP": "Real Time Streaming Protocol", "SSDP": "Simple Service Discovery Protocol"}
    у = р.уровень(протокол, полное.get(протокол, протокол), м)
    ключ = протокол.lower()
    if ответ:
        части = первая.split(" ", 2)
        у.поле("Строка состояния", f"{ключ}.response", первая, м, len(строки[0]))
        if len(части) >= 2 and части[1].isdigit():
            у.поле("Код ответа", f"{ключ}.response.code", int(части[1]), м + len(части[0]) + 1, len(части[1]))
    else:
        части = первая.split(" ")
        у.поле("Строка запроса", f"{ключ}.request", первая, м, len(строки[0]))
        у.поле("Метод", f"{ключ}.request.method", части[0], м, len(части[0]))
        if len(части) > 1:
            у.поле("Адрес (URI)", f"{ключ}.request.uri", части[1], м + len(части[0]) + 1, len(части[1]))
    место = м + len(строки[0]) + 2
    узел = ""
    for строка in строки[1:]:
        текст = строка.decode("utf-8", "replace")
        имя = текст.split(":", 1)[0].strip().lower()
        значение = текст.split(":", 1)[1].strip() if ":" in текст else ""
        у.поле(текст.split(":", 1)[0].strip() if ":" in текст else текст,
               f"{ключ}.{имя.replace('-', '_')}", значение, место, len(строка))
        if имя == "host":
            узел = значение
        место += len(строка) + 2
    тело = len(д) - граница - 4 if граница >= 0 else 0
    if тело > 0:
        у.поле("Тело", f"{ключ}.file_data", f"{тело} байт: {печатное(д[граница + 4:], 60)}", м + граница + 4, тело)
    у.длина = len(д)
    у.итог = первая + (f" (узел {узел})" if узел and not ответ else "")
    р.п.инфо = f"{протокол} {у.итог}"
    return True


def строковый(р: Разбор, м: int, конец: int, протокол: str) -> bool:
    """FTP, SMTP, POP3, IMAP, Telnet, SSH-приветствие, IRC — строки текста."""
    д = р.д[м:конец]
    if not д or sum(1 for б in д[:200] if 32 <= б < 127 or б in (9, 10, 13)) < 0.9 * min(len(д), 200):
        return False
    у = р.уровень(протокол, протокол, м)
    место = м
    for строка in д.split(b"\n")[:40]:
        if строка.strip():
            у.поле(строка.decode("utf-8", "replace").rstrip("\r"), f"{протокол.lower()}.line",
                   строка.decode("utf-8", "replace").rstrip("\r"), место, len(строка))
        место += len(строка) + 1
    у.длина = len(д)
    у.итог = печатное(д.split(b"\n")[0].rstrip(b"\r"), 80)
    р.п.инфо = f"{протокол} {у.итог}"
    return True


def syslog(р: Разбор, м: int, конец: int) -> bool:
    д = р.д[м:конец]
    if not д.startswith(b"<") or b">" not in д[:5]:
        return False
    pri = д[1:д.index(b">")]
    if not pri.isdigit():
        return False
    pri = int(pri)
    у = р.уровень("Syslog", "Syslog", м)
    уровни = ("EMERG", "ALERT", "CRIT", "ERR", "WARNING", "NOTICE", "INFO", "DEBUG")
    у.поле("Приоритет", "syslog.pri", pri, м, д.index(b">") + 1)
    у.поле("Источник (facility)", "syslog.facility", pri >> 3, м, д.index(b">") + 1)
    у.поле("Важность", "syslog.level", уровни[pri & 7], м, д.index(b">") + 1, pri & 7)
    текст = д[д.index(b">") + 1:].decode("utf-8", "replace").strip()
    у.поле("Сообщение", "syslog.msg", текст, м + д.index(b">") + 1, len(д) - д.index(b">") - 1)
    у.длина = len(д)
    у.итог = f"{уровни[pri & 7]}: {текст[:100]}"
    р.п.инфо = "Syslog " + у.итог
    return True


# -- TLS ------------------------------------------------------------------------------------------

TLS_ЗАПИСИ = {20: "ChangeCipherSpec", 21: "Alert", 22: "Handshake", 23: "Application Data", 24: "Heartbeat"}
TLS_РУКОПОЖАТИЕ = {0: "HelloRequest", 1: "ClientHello", 2: "ServerHello", 4: "NewSessionTicket",
                   8: "EncryptedExtensions", 11: "Certificate", 12: "ServerKeyExchange",
                   13: "CertificateRequest", 14: "ServerHelloDone", 15: "CertificateVerify",
                   16: "ClientKeyExchange", 20: "Finished"}
TLS_ВЕРСИИ = {0x0300: "SSL 3.0", 0x0301: "TLS 1.0", 0x0302: "TLS 1.1", 0x0303: "TLS 1.2", 0x0304: "TLS 1.3"}


def tls(р: Разбор, м: int, конец: int) -> bool:
    д = р.д
    if конец - м < 5 or д[м] not in TLS_ЗАПИСИ or д[м + 1] != 3 or д[м + 2] > 4:
        return False
    у = р.уровень("TLS", "Transport Layer Security", м)
    итоги = []
    место = м
    while место + 5 <= конец:
        тип, версия, дл = д[место], u16(д, место + 1), u16(д, место + 3)
        if тип not in TLS_ЗАПИСИ or д[место + 1] != 3:
            break
        запись = у.поле(f"Запись: {TLS_ЗАПИСИ[тип]}, {TLS_ВЕРСИИ.get(версия, hex(версия))}, {дл} байт",
                        "tls.record.content_type", TLS_ЗАПИСИ[тип], место, 5 + дл, тип)
        у.поле("Версия записи", "tls.record.version", TLS_ВЕРСИИ.get(версия, hex(версия)), место + 1, 2, версия,
               родитель=запись)
        тело = место + 5
        if тип == 22 and тело + 4 <= min(конец, тело + дл):
            вид = д[тело]
            имя = TLS_РУКОПОЖАТИЕ.get(вид, f"тип {вид}")
            у.поле("Тип рукопожатия", "tls.handshake.type", имя, тело, 1, вид, родитель=запись)
            if вид in (1, 2):
                итоги.append(_hello(р, у, запись, тело, min(конец, тело + дл), вид))
            elif тело + 4 + u24(д, тело + 1) <= тело + дл or вид in TLS_РУКОПОЖАТИЕ:
                итоги.append(имя if вид in TLS_РУКОПОЖАТИЕ else "зашифрованное сообщение рукопожатия")
        elif тип == 21 and дл >= 2 and тело + 2 <= конец:
            у.поле("Уровень", "tls.alert_message.level", {1: "предупреждение", 2: "фатальная"}.get(д[тело], д[тело]),
                   тело, 1, д[тело], родитель=запись)
            у.поле("Описание", "tls.alert_message.desc", д[тело + 1], тело + 1, 1, родитель=запись)
            итоги.append("Alert" if дл == 2 else "Alert (зашифровано)")
        else:
            итоги.append(TLS_ЗАПИСИ[тип])
        место += 5 + дл
    у.длина = место - м
    у.итог = ", ".join(итоги)
    р.п.инфо = "TLS " + у.итог
    return True


def u24(д: bytes, м: int) -> int:
    return (д[м] << 16) | (д[м + 1] << 8) | д[м + 2]


def _hello(р: Разбор, у, запись, м: int, конец: int, вид: int) -> str:
    д = р.д
    имя = TLS_РУКОПОЖАТИЕ[вид]
    версия = u16(д, м + 4)
    у.поле("Версия", "tls.handshake.version", TLS_ВЕРСИИ.get(версия, hex(версия)), м + 4, 2, версия, родитель=запись)
    у.поле("Случайное", "tls.handshake.random", д[м + 6:м + 38].hex(), м + 6, 32, родитель=запись)
    место = м + 38
    дл_сеанса = д[место]
    у.поле("Идентификатор сеанса", "tls.handshake.session_id", д[место + 1:место + 1 + дл_сеанса].hex() or "—",
           место, 1 + дл_сеанса, родитель=запись)
    место += 1 + дл_сеанса
    if вид == 1:
        дл_наборов = u16(д, место)
        наборы = [f"0x{u16(д, место + 2 + i):04x}" for i in range(0, дл_наборов, 2)]
        # Имена наборов шифров не подставляются: таблица IANA здесь не хранится.
        у.поле(f"Наборы шифров: {len(наборы)}", "tls.handshake.ciphersuite", ", ".join(наборы), место,
               2 + дл_наборов, родитель=запись)
        место += 2 + дл_наборов
        место += 1 + д[место]                                   # методы сжатия
    else:
        набор = u16(д, место)
        у.поле("Выбранный набор шифров", "tls.handshake.ciphersuite", f"0x{набор:04x}", место, 2, набор,
               родитель=запись)
        место += 3
    sni, alpn, версии = "", [], []
    if место + 2 <= конец:
        дл_расш = u16(д, место)
        место += 2
        предел = min(конец, место + дл_расш)
        while место + 4 <= предел:
            тип, дл = u16(д, место), u16(д, место + 2)
            тело = место + 4
            if тип == 0 and дл >= 5:
                дл_имени = u16(д, тело + 3)
                sni = д[тело + 5:тело + 5 + дл_имени].decode("ascii", "replace")
                у.поле(f"Имя сервера (SNI): {sni}", "tls.handshake.extensions_server_name", sni, место, 4 + дл,
                       родитель=запись)
            elif тип == 16 and дл >= 2:
                i = тело + 2
                while i < тело + дл:
                    n = д[i]
                    alpn.append(д[i + 1:i + 1 + n].decode("ascii", "replace"))
                    i += 1 + n
                у.поле(f"ALPN: {', '.join(alpn)}", "tls.handshake.extensions_alpn_str", ", ".join(alpn), место,
                       4 + дл, родитель=запись)
            elif тип == 43:
                if вид == 1 and дл >= 1:
                    версии = [TLS_ВЕРСИИ.get(u16(д, тело + 1 + i), hex(u16(д, тело + 1 + i)))
                              for i in range(0, д[тело], 2)]
                elif дл == 2:
                    версии = [TLS_ВЕРСИИ.get(u16(д, тело), hex(u16(д, тело)))]
                у.поле(f"Поддерживаемые версии: {', '.join(версии)}", "tls.handshake.extensions.supported_version",
                       ", ".join(версии), место, 4 + дл, родитель=запись)
            else:
                у.поле(f"Расширение {тип}", "tls.handshake.extension.type", тип, место, 4 + дл, родитель=запись)
            место = тело + дл
    текст = имя + (f" SNI={sni}" if sni else "") + (f" ALPN={','.join(alpn)}" if alpn else "")
    if версии and вид == 2:
        текст += f" ({версии[0]})"
    return текст


