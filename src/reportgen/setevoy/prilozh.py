#: «Разбирать как»: разборщики по имени для каждого транспорта. Разборщик и
#: при выборе аналитика проверяет, что данные его, — выбор не заставит
#: читать мусор как протокол, а только укажет, что пробовать.
КАК: Dict[str, Dict[str, Разборщик]] = {
    "udp": {"DNS": dns, "mDNS": ПОРТЫ_UDP[5353], "LLMNR": ПОРТЫ_UDP[5355], "DHCP": dhcp, "TFTP": tftp,
            "NTP": ntp, "SNMP": snmp, "Syslog": syslog, "RIP": rip, "RADIUS": radius, "VXLAN": vxlan,
            "GTP-U": gtp_u, "L2TP": l2tp, "SIP": ПОРТЫ_UDP[5060], "SSDP": ПОРТЫ_UDP[1900], "QUIC": quic,
            "IKE": isakmp, "NetFlow/IPFIX": netflow, "BFD": bfd, "RTP/RTCP": rtp},
    "tcp": {"HTTP": http, "TLS": tls, "DNS": _dns_tcp, "BGP": bgp, "Modbus/TCP": modbus, "MQTT": mqtt,
            "SIP": ПОРТЫ_TCP[5060], "RTSP": ПОРТЫ_TCP[554], "FTP": ПОРТЫ_TCP[21], "SMTP": ПОРТЫ_TCP[25],
            "POP3": ПОРТЫ_TCP[110], "IMAP": ПОРТЫ_TCP[143], "Telnet": ПОРТЫ_TCP[23], "SSH": ПОРТЫ_TCP[22],
            "IRC": ПОРТЫ_TCP[6667]},
}
#: Особое имя: не разбирать нагрузку на этом порту (угадывание ошибается).
КАК_ДАННЫЕ = "данные"
#: Сколько правил «разбирать как» на захват.
ПРАВИЛ_ДО = 64


def проверить_как(правила: Dict[str, str]) -> Dict[str, str]:
    """Правила «транспорт:порт» → имя разборщика; ошибка — ValueError с понятным текстом."""
    if not isinstance(правила, dict):
        raise ValueError("правила «разбирать как» — словарь «транспорт:порт» → протокол")
    if len(правила) > ПРАВИЛ_ДО:
        raise ValueError(f"правил «разбирать как» не больше {ПРАВИЛ_ДО}")
    итог = {}
    for ключ, имя in правила.items():
        м = re.fullmatch(r"(tcp|udp):(\d{1,5})", str(ключ).strip().lower())
        if not м or not 1 <= int(м.group(2)) <= 65535:
            raise ValueError(f"«{ключ}»: нужно tcp:ПОРТ или udp:ПОРТ, порт 1–65535")
        транспорт = м.group(1)
        if имя != КАК_ДАННЫЕ and имя not in КАК[транспорт]:
            raise ValueError(f"«{имя}» по {транспорт.upper()} разбирать не умею")
        итог[f"{транспорт}:{int(м.group(2))}"] = имя
    return итог


def по_портам(р: Разбор, транспорт: str, от: int, к: int, м: int, конец: int) -> None:
    таблица = ПОРТЫ_TCP if транспорт == "tcp" else ПОРТЫ_UDP
    уровней = len(р.п.уровни)
    # Выбор аналитика («разбирать как») — раньше таблицы портов и угадывания.
    for порт in sorted((от, к)):
        имя = р.как.get(f"{транспорт}:{порт}")
        if имя is None:
            continue
        if имя == КАК_ДАННЫЕ:
            данные(р, м, f"нагрузка (порт {порт} — не разбирать)", конец)
            return
        try:
            if КАК[транспорт][имя](р, м, конец):
                return
        except (Мало, IndexError, ValueError):
            del р.п.уровни[уровней:]
        р.п.ошибки.append(f"разбирать как {имя} (порт {порт}): данные не подошли")
        break
    # Меньший порт — обычно служба; сначала он, потом другой.
    for порт in sorted((от, к)):
        разборщик = таблица.get(порт)
        if разборщик is None:
            continue
        try:
            if разборщик(р, м, конец):
                return
        except (Мало, IndexError, ValueError):
            del р.п.уровни[уровней:]
    try:
        if транспорт == "tcp":
            if tls(р, м, конец) or http(р, м, конец):
                return
            if 22 in (от, к) or р.д[м:м + 4] == b"SSH-":
                if строковый(р, м, конец, "SSH"):
                    return
        else:
            if (от in TLS_ПОРТЫ or к in TLS_ПОРТЫ) and quic(р, м, конец):
                return
            if min(от, к) >= 1024 and rtp(р, м, конец):
                return
    except (Мало, IndexError, ValueError):
        del р.п.уровни[уровней:]
    if len(р.п.уровни) == уровней:
        инфо = р.п.инфо
        данные(р, м, "нагрузка без известного разборщика", конец)
        р.п.инфо = инфо
