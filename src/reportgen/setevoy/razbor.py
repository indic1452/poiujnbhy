def ipv4(р: Разбор, м: int) -> None:
    у = р.уровень("IPv4", "Internet Protocol v4", м)
    р.нужно(м, 20)
    ihl = (р.д[м] & 15) * 4
    всего = u16(р.д, м + 2)
    флаги_смещение = u16(р.д, м + 6)
    протокол = р.д[м + 9]
    от, к = ip4(р.д, м + 12), ip4(р.д, м + 16)
    у.поле("Версия", "ip.version", р.д[м] >> 4, м, 1)
    у.поле("Длина заголовка", "ip.hdr_len", ihl, м, 1)
    у.поле("DSCP", "ip.dsfield.dscp", р.д[м + 1] >> 2, м + 1, 1)
    у.поле("ECN", "ip.dsfield.ecn", р.д[м + 1] & 3, м + 1, 1)
    у.поле("Полная длина", "ip.len", всего, м + 2, 2)
    у.поле("Идентификатор", "ip.id", f"0x{u16(р.д, м + 4):04x} ({u16(р.д, м + 4)})", м + 4, 2,
           u16(р.д, м + 4))
    df, mf, смещение = (флаги_смещение >> 14) & 1, (флаги_смещение >> 13) & 1, (флаги_смещение & 0x1FFF) * 8
    флаги = у.поле("Флаги", "ip.flags", ", ".join(и for и, ф in (("DF", df), ("MF", mf)) if ф) or "нет",
                   м + 6, 2, флаги_смещение >> 13)
    у.поле("Не фрагментировать (DF)", "ip.flags.df", df, м + 6, 2, родитель=флаги)
    у.поле("Есть ещё фрагменты (MF)", "ip.flags.mf", mf, м + 6, 2, родитель=флаги)
    у.поле("Смещение фрагмента", "ip.frag_offset", смещение, м + 6, 2)
    у.поле("TTL", "ip.ttl", р.д[м + 8], м + 8, 1)
    у.поле("Протокол", "ip.proto", f"{протокол} ({IP_ПРОТОКОЛЫ.get(протокол, 'неизвестный')})",
           м + 9, 1, протокол)
    сумма = u16(р.д, м + 10)
    верна = ihl >= 20 and м + ihl <= len(р.д) and сумма16(р.д[м:м + ihl]) == 0
    у.поле("Контрольная сумма заголовка", "ip.checksum",
           f"0x{сумма:04x} [{'верна' if верна else 'НЕВЕРНА'}]", м + 10, 2, сумма, плохо=not верна)
    if not верна:
        р.ошибка("IPv4: неверная контрольная сумма заголовка")
    у.поле("Источник", "ip.src", от, м + 12, 4)
    у.поле("Получатель", "ip.dst", к, м + 16, 4)
    _скрытые(у, "ip.addr", [от, к])
    if ihl > 20:
        у.поле("Опции", "ip.options", р.д[м + 20:м + ihl].hex(), м + 20, ihl - 20)
    у.длина = ihl
    р.адреса(от, к)
    конец = min(len(р.д), м + всего) if всего >= ihl else len(р.д)
    if всего > len(р.д) - м:
        р.ошибка(f"IPv4: пакет короче полной длины ({len(р.д) - м} < {всего})")
    у.итог = f"{от} → {к}, {IP_ПРОТОКОЛЫ.get(протокол, протокол)}, TTL {р.д[м + 8]}"
    if mf or смещение:
        у.итог += f", фрагмент (смещение {смещение}{', ещё будут' if mf else ', последний'})"
        р.п.инфо = f"Фрагмент IPv4, id 0x{u16(р.д, м + 4):04x}, смещение {смещение}"
        if смещение:
            данные(р, м + ihl, "фрагмент IPv4", конец)
            return
    по_протоколу(р, протокол, м + ihl, конец, псевдо=(р.д[м + 12:м + 20], 4))


def ipv6(р: Разбор, м: int) -> None:
    у = р.уровень("IPv6", "Internet Protocol v6", м)
    р.нужно(м, 40)
    слово = u32(р.д, м)
    длина = u16(р.д, м + 4)
    следующий = р.д[м + 6]
    от, к = ip6(р.д, м + 8), ip6(р.д, м + 24)
    у.поле("Версия", "ipv6.version", слово >> 28, м, 1)
    у.поле("Класс трафика", "ipv6.tclass", f"0x{(слово >> 20) & 0xFF:02x}", м, 2, (слово >> 20) & 0xFF)
    у.поле("Метка потока", "ipv6.flow", f"0x{слово & 0xFFFFF:05x}", м + 1, 3, слово & 0xFFFFF)
    у.поле("Длина нагрузки", "ipv6.plen", длина, м + 4, 2)
    у.поле("Следующий заголовок", "ipv6.nxt",
           f"{следующий} ({IP_ПРОТОКОЛЫ.get(следующий, 'неизвестный')})", м + 6, 1, следующий)
    у.поле("Предел переходов", "ipv6.hlim", р.д[м + 7], м + 7, 1)
    у.поле("Источник", "ipv6.src", от, м + 8, 16)
    у.поле("Получатель", "ipv6.dst", к, м + 24, 16)
    _скрытые(у, "ipv6.addr", [от, к])
    у.длина = 40
    р.адреса(от, к)
    конец = min(len(р.д), м + 40 + длина)
    место = м + 40
    # Заголовки расширения: переходы, маршрут, опции получателя, фрагмент, AH.
    while следующий in (0, 43, 60, 44, 51) and место + 8 <= конец:
        if следующий == 44:
            смещение_фр = u16(р.д, место + 2)
            п = у.поле("Заголовок фрагмента", "ipv6.fraghdr",
                       f"смещение {(смещение_фр >> 3) * 8}, ещё {'да' if смещение_фр & 1 else 'нет'}, "
                       f"id 0x{u32(р.д, место + 4):08x}", место, 8)
            у.поле("Идентификатор", "ipv6.fragment.id", u32(р.д, место + 4), место + 4, 4, родитель=п)
            следующий_ = р.д[место]
            дл = 8
            if смещение_фр >> 3:
                р.п.инфо = "Фрагмент IPv6"
                данные(р, место + 8, "фрагмент IPv6", конец)
                return
        elif следующий == 51:
            следующий_, дл = р.д[место], (р.д[место + 1] + 2) * 4
            у.поле("AH", "ah.spi", f"SPI 0x{u32(р.д, место + 4):08x}", место, дл, u32(р.д, место + 4))
        else:
            следующий_, дл = р.д[место], (р.д[место + 1] + 1) * 8
            у.поле(IP_ПРОТОКОЛЫ.get(следующий, str(следующий)), "ipv6.ext",
                   f"{дл} байт", место, дл, следующий)
        следующий = следующий_
        место += дл
    у.итог = f"{от} → {к}, {IP_ПРОТОКОЛЫ.get(следующий, следующий)}, предел {р.д[м + 7]}"
    по_протоколу(р, следующий, место, конец, псевдо=(р.д[м + 8:м + 40], 6))


def по_протоколу(р: Разбор, протокол: int, м: int, конец: int, псевдо) -> None:
    р.глубина += 1
    if р.глубина > 8:
        данные(р, м, "слишком глубокая вложенность", конец)
        return
    if протокол == 6:
        tcp(р, м, конец, псевдо)
    elif протокол == 17:
        udp(р, м, конец, псевдо)
    elif протокол == 1:
        icmp(р, м, конец)
    elif протокол == 58:
        icmpv6(р, м, конец, псевдо)
    elif протокол == 4:
        ipv4(р, м)
    elif протокол == 41:
        ipv6(р, м)
    elif протокол == 47:
        gre(р, м, конец)
    elif протокол == 2:
        igmp(р, м, конец)
    elif протокол == 50:
        esp(р, м, конец)
    elif протокол == 51:
        ah(р, м, конец, псевдо)
    elif протокол == 89:
        ДОП_IP.get(89, ospf)(р, м, конец)                  # полный разбор — в protokoly, если есть
    elif протокол == 112:
        vrrp(р, м, конец, псевдо)
    elif протокол == 132:
        sctp(р, м, конец)
    elif протокол in ДОП_IP:
        # Псевдозаголовок (адреса IP) — для контрольных сумм вложенного протокола.
        р.псевдо = псевдо
        ДОП_IP[протокол](р, м, конец)
    else:
        данные(р, м, f"протокол IP {протокол}", конец)


def _псевдо_сумма(псевдо, протокол: int, сегмент: bytes) -> int:
    адреса, версия = псевдо
    if версия == 4:
        заголовок = адреса + struct.pack(">BBH", 0, протокол, len(сегмент))
    else:
        заголовок = адреса + struct.pack(">IxxxB", len(сегмент), протокол)
    return сумма16(заголовок + сегмент)


