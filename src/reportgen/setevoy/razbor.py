TCP_ФЛАГИ = (("CWR", 7), ("ECE", 6), ("URG", 5), ("ACK", 4), ("PSH", 3), ("RST", 2),
             ("SYN", 1), ("FIN", 0))


def tcp(р: Разбор, м: int, конец: int, псевдо) -> None:
    у = р.уровень("TCP", "Transmission Control Protocol", м)
    р.нужно(м, 20)
    от, к = u16(р.д, м), u16(р.д, м + 2)
    seq, ack = u32(р.д, м + 4), u32(р.д, м + 8)
    дл = (р.д[м + 12] >> 4) * 4
    флаги = р.д[м + 13] | ((р.д[м + 12] & 1) << 8)
    окно = u16(р.д, м + 14)
    сумма = u16(р.д, м + 16)
    у.поле("Порт источника", "tcp.srcport", от, м, 2)
    у.поле("Порт получателя", "tcp.dstport", к, м + 2, 2)
    _скрытые(у, "tcp.port", [от, к])
    у.поле("Номер последовательности", "tcp.seq_raw", seq, м + 4, 4)
    у.поле("Номер подтверждения", "tcp.ack_raw", ack, м + 8, 4)
    у.поле("Длина заголовка", "tcp.hdr_len", дл, м + 12, 1)
    имена = [имя for имя, бит in TCP_ФЛАГИ if флаги >> бит & 1]
    п = у.поле("Флаги", "tcp.flags", f"0x{флаги:03x} ({', '.join(имена) or 'нет'})", м + 12, 2, флаги)
    for имя, бит in TCP_ФЛАГИ:
        у.поле(имя, f"tcp.flags.{имя.lower()}", флаги >> бит & 1, м + 13, 1, родитель=п)
    у.поле("Окно", "tcp.window_size_value", окно, м + 14, 2)
    сегмент = р.д[м:конец]
    верна = len(сегмент) >= 20 and _псевдо_сумма(псевдо, 6, сегмент) == 0
    у.поле("Контрольная сумма", "tcp.checksum", f"0x{сумма:04x} [{'верна' if верна else 'не сошлась'}]",
           м + 16, 2, сумма, плохо=not верна)
    if not верна:
        # Нередко это разгрузка подсчёта суммы на сетевую карту при захвате на передающем узле.
        р.ошибка("TCP: контрольная сумма не сошлась (или захват до подсчёта на сетевой карте)")
    у.поле("Указатель срочности", "tcp.urgent_pointer", u16(р.д, м + 18), м + 18, 2)
    if дл > 20:
        _tcp_опции(р, у, м + 20, м + дл)
    данных = max(0, конец - м - дл)
    у.поле("Длина данных", "tcp.len", данных, м + дл, 0)
    у.длина = дл
    р.п.порт_от, р.п.порт_к = от, к
    у.итог = f"{от} → {к} [{', '.join(имена)}] seq={seq} ack={ack} окно={окно} данных={данных}"
    р.п.инфо = у.итог
    if данных:
        р.нагрузка(м + дл, конец)
        from .prilozh import по_портам  # noqa: PLC0415 — круговой импорт
        по_портам(р, "tcp", от, к, м + дл, конец)


def _tcp_опции(р: Разбор, у: Уровень, м: int, конец: int) -> None:
    п = у.поле("Опции", "tcp.options", f"{конец - м} байт", м, конец - м)
    while м < конец:
        вид = р.д[м]
        if вид == 0:
            у.поле("Конец опций", "", "EOL", м, 1, родитель=п)
            break
        if вид == 1:
            у.поле("NOP", "", "NOP", м, 1, родитель=п)
            м += 1
            continue
        if м + 1 >= конец:
            break
        дл = max(2, р.д[м + 1])
        тело = р.д[м + 2:м + дл]
        if вид == 2 and len(тело) == 2:
            у.поле(f"MSS {u16(тело, 0)}", "tcp.options.mss_val", u16(тело, 0), м, дл, родитель=п)
        elif вид == 3 and len(тело) == 1:
            у.поле(f"Масштаб окна ×{1 << тело[0]}", "tcp.options.wscale.shift", тело[0], м, дл, родитель=п)
        elif вид == 4:
            у.поле("SACK разрешён", "tcp.options.sack_perm", 1, м, дл, родитель=п)
        elif вид == 5:
            блоки = [f"{u32(тело, i)}–{u32(тело, i + 4)}" for i in range(0, len(тело) - 7, 8)]
            у.поле("SACK " + ", ".join(блоки), "tcp.options.sack", ", ".join(блоки), м, дл, родитель=п)
        elif вид == 8 and len(тело) == 8:
            у.поле(f"Отметки времени {u32(тело, 0)} / {u32(тело, 4)}", "tcp.options.timestamp.tsval",
                   u32(тело, 0), м, дл, родитель=п)
        else:
            у.поле(f"Опция {вид}", "tcp.option_kind", тело.hex() or "—", м, дл, вид, родитель=п)
        м += дл


def udp(р: Разбор, м: int, конец: int, псевдо) -> None:
    у = р.уровень("UDP", "User Datagram Protocol", м)
    р.нужно(м, 8)
    от, к, длина, сумма = u16(р.д, м), u16(р.д, м + 2), u16(р.д, м + 4), u16(р.д, м + 6)
    у.поле("Порт источника", "udp.srcport", от, м, 2)
    у.поле("Порт получателя", "udp.dstport", к, м + 2, 2)
    _скрытые(у, "udp.port", [от, к])
    у.поле("Длина", "udp.length", длина, м + 4, 2)
    if длина >= 8:
        конец = min(конец, м + длина)
    if сумма == 0 and псевдо[1] == 4:
        у.поле("Контрольная сумма", "udp.checksum", "0x0000 (не используется)", м + 6, 2, 0)
    else:
        верна = _псевдо_сумма(псевдо, 17, р.д[м:конец]) == 0
        у.поле("Контрольная сумма", "udp.checksum", f"0x{сумма:04x} [{'верна' if верна else 'не сошлась'}]",
               м + 6, 2, сумма, плохо=not верна)
        if not верна:
            р.ошибка("UDP: контрольная сумма не сошлась")
    у.длина = 8
    р.п.порт_от, р.п.порт_к = от, к
    у.итог = f"{от} → {к}, данных {конец - м - 8}"
    р.п.инфо = у.итог
    if конец > м + 8:
        р.нагрузка(м + 8, конец)
        from .prilozh import по_портам  # noqa: PLC0415
        по_портам(р, "udp", от, к, м + 8, конец)


def sctp(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("SCTP", "Stream Control Transmission Protocol", м)
    р.нужно(м, 12)
    от, к = u16(р.д, м), u16(р.д, м + 2)
    у.поле("Порт источника", "sctp.srcport", от, м, 2)
    у.поле("Порт получателя", "sctp.dstport", к, м + 2, 2)
    _скрытые(у, "sctp.port", [от, к])
    у.поле("Метка проверки", "sctp.verification_tag", f"0x{u32(р.д, м + 4):08x}", м + 4, 4, u32(р.д, м + 4))
    сумма = struct.unpack_from("<I", р.д, м + 8)[0]
    пакет = р.д[м:конец]
    верна = _crc32c(пакет[:8] + b"\0\0\0\0" + пакет[12:]) == сумма
    у.поле("CRC32c", "sctp.checksum", f"0x{u32(р.д, м + 8):08x} [{'верна' if верна else 'НЕВЕРНА'}]",
           м + 8, 4, сумма, плохо=not верна)
    if not верна:
        р.ошибка("SCTP: неверная CRC32c")
    типы = {0: "DATA", 1: "INIT", 2: "INIT ACK", 3: "SACK", 4: "HEARTBEAT", 5: "HEARTBEAT ACK",
            6: "ABORT", 7: "SHUTDOWN", 8: "SHUTDOWN ACK", 9: "ERROR", 10: "COOKIE ECHO",
            11: "COOKIE ACK", 14: "SHUTDOWN COMPLETE"}
    место, куски = м + 12, []
    первый_data = None
    while место + 4 <= конец:
        тип, дл = р.д[место], u16(р.д, место + 2)
        if дл < 4:
            break
        п = у.поле(f"Кусок {типы.get(тип, тип)}", "sctp.chunk_type", типы.get(тип, str(тип)), место, дл, тип)
        if тип == 0 and дл >= 16 and место + 16 <= конец:
            у.поле("TSN", "sctp.data_tsn", u32(р.д, место + 4), место + 4, 4, родитель=п)
            у.поле("Поток", "sctp.data_sid", u16(р.д, место + 8), место + 8, 2, родитель=п)
            у.поле("PPID", "sctp.data_payload_proto_id", u32(р.д, место + 12), место + 12, 4, родитель=п)
            р.нагрузка(место + 16, место + дл)
            if первый_data is None:
                первый_data = (u32(р.д, место + 12), место + 16, место + дл)
        куски.append(типы.get(тип, str(тип)))
        место += (дл + 3) // 4 * 4
    у.длина = 12
    р.п.порт_от, р.п.порт_к = от, к
    у.итог = f"{от} → {к}: " + ", ".join(куски)
    р.п.инфо = "SCTP " + у.итог
    # Нагрузка первого куска DATA — по PPID, затем по порту (SIGTRAN, Diameter, S1AP…).
    if первый_data is not None:
        ppid, от_, до_ = первый_data
        кандидаты = [ДОП_SCTP_PPID.get(ppid)] + [ДОП_SCTP_ПОРТ.get(п) for п in sorted((от, к))]
        уровней = len(р.п.уровни)
        for разборщик in кандидаты:
            if разборщик is None:
                continue
            try:
                if разборщик(р, от_, до_):
                    break
            except (Мало, IndexError, ValueError, struct.error):
                del р.п.уровни[уровней:]


def _crc32c(данные: bytes) -> int:
    таблица = _ТАБЛИЦА_CRC32C
    crc = 0xFFFFFFFF
    for б in данные:
        crc = таблица[(crc ^ б) & 0xFF] ^ (crc >> 8)
    return crc ^ 0xFFFFFFFF


def _таблица_crc32c():
    итог = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ 0x82F63B78 if c & 1 else c >> 1
        итог.append(c)
    return итог


_ТАБЛИЦА_CRC32C = _таблица_crc32c()


def данные(р: Разбор, м: int, что: str, конец: int | None = None) -> None:
    конец = len(р.д) if конец is None else конец
    if м >= конец:
        return
    у = р.уровень("Данные", "Данные: " + что, м)
    у.длина = конец - м
    from .pole import печатное  # noqa: PLC0415
    у.поле("Байты", "data.data", f"{конец - м} байт: {печатное(р.д[м:конец], 40)}", м, конец - м,
           р.д[м:конец].hex())
    у.итог = f"{конец - м} байт"
    р.нагрузка(м, конец)
    if not р.п.инфо:
        р.п.инфо = f"{что}, {конец - м} байт"


