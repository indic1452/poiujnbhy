def gre(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("GRE", "Generic Routing Encapsulation", м)
    р.нужно(м, 4)
    флаги, протокол = u16(р.д, м), u16(р.д, м + 2)
    c, k, s, a, версия = флаги >> 15, (флаги >> 13) & 1, (флаги >> 12) & 1, (флаги >> 7) & 1, флаги & 7
    у.поле("Флаги и версия", "gre.flags_and_version", f"0x{флаги:04x} (C={c} K={k} S={s}, версия {версия})",
           м, 2, флаги)
    у.поле("Протокол", "gre.proto", f"0x{протокол:04x} ({ETHERTYPE.get(протокол, 'неизвестный')})",
           м + 2, 2, протокол)
    место = м + 4
    if c:
        у.поле("Контрольная сумма", "gre.checksum", f"0x{u16(р.д, место):04x}", место, 2, u16(р.д, место))
        место += 4
    if k:
        if версия == 1:
            у.поле("Длина нагрузки / Call ID", "gre.key", f"{u16(р.д, место)} / {u16(р.д, место + 2)}",
                   место, 4, u32(р.д, место))
        else:
            ключ = у.поле("Ключ", "gre.key", f"0x{u32(р.д, место):08x}", место, 4, u32(р.д, место))
            if протокол == 0x6558:
                # NVGRE (RFC 7637): ключ — идентификатор виртуальной сети (24 бита) и FlowID.
                у.поле("VSID", "nvgre.vsid", u32(р.д, место) >> 8, место, 3, родитель=ключ)
                у.поле("FlowID", "nvgre.flow_id", р.д[место + 3], место + 3, 1, родитель=ключ)
        место += 4
    if s:
        у.поле("Номер", "gre.sequence_number", u32(р.д, место), место, 4)
        место += 4
    if a and версия == 1:
        у.поле("Подтверждение", "gre.ack_number", u32(р.д, место), место, 4)
        место += 4
    у.длина = место - м
    у.итог = ETHERTYPE.get(протокол, f"0x{протокол:04x}")
    if место < конец:
        по_типу(р, протокол, место)


