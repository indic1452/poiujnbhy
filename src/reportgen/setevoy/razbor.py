def авто(р: Разбор, м: int) -> None:
    """Кадр без типа канала (из .sig, после HDLC): по признакам."""
    д = р.д[м:]
    if len(д) >= 20 and д[0] >> 4 == 4 and сумма16(д[:(д[0] & 15) * 4]) == 0:
        ipv4(р, м)
    elif len(д) >= 40 and д[0] >> 4 == 6 and u16(д, 4) + 40 == len(д):
        ipv6(р, м)
    elif д[:2] == b"\xff\x03":
        ppp(р, м)
    elif len(д) >= 4 and д[0] in (0x0F, 0x8F) and д[1] == 0 and u16(д, 2) in ETHERTYPE:
        cisco_hdlc(р, м)
    elif len(д) >= 14 and u16(д, 12) in ETHERTYPE:
        ethernet(р, м)
    else:
        # MTP2, LAPD, Frame Relay, LAPB, AX.25 — по признакам, которые стандарт требует у кадра.
        вид = vid_kadra.вид(bytes(д))
        разборщик = КАНАЛ_В_РАЗБОРЩИК.get(АВТО_КАНАЛЫ.get(вид, ""))
        if разборщик is not None:
            разборщик(р, м)
        else:
            данные(р, м, "кадр неизвестного формата")


