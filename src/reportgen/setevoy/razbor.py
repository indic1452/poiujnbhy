VRRP_ПОДЛИННОСТЬ = {0: "нет", 1: "простой пароль", 2: "IP AH"}


def vrrp(р: Разбор, м: int, конец: int, псевдо=None) -> None:
    """VRRP: версия 2 (RFC 3768) и 3 (RFC 5798; в IPv6 — адреса по 16 байт).

    Контрольная сумма: у версии 2 — по сообщению, у версии 3 — ещё и с
    псевдозаголовком IP; реализации VRRPv3 поверх IPv4 бывают и без него —
    сверяются оба способа, и в поле сказано, какой сошёлся.
    """
    у = р.уровень("VRRP", "Virtual Router Redundancy Protocol", м)
    р.нужно(м, 8)
    версия, тип, vrid, приоритет, адресов = р.д[м] >> 4, р.д[м] & 15, р.д[м + 1], р.д[м + 2], р.д[м + 3]
    у.поле("Версия", "vrrp.version", версия, м, 1)
    у.поле("Тип", "vrrp.type", "объявление" if тип == 1 else тип, м, 1, тип)
    у.поле("VRID", "vrrp.virt_rtr_id", vrid, м + 1, 1)
    у.поле("Приоритет", "vrrp.prio", приоритет, м + 2, 1)
    у.поле("Адресов", "vrrp.addr_count", адресов, м + 3, 1)
    if версия == 3:
        интервал = u16(р.д, м + 4) & 0x0FFF
        у.поле("Наибольший интервал объявлений, с/100", "vrrp.max_adver_int", интервал, м + 4, 2)
    else:
        подлинность = р.д[м + 4]
        у.поле("Проверка подлинности", "vrrp.auth_type",
               VRRP_ПОДЛИННОСТЬ.get(подлинность, подлинность), м + 4, 1, подлинность)
        у.поле("Интервал объявлений, с", "vrrp.adver_int", р.д[м + 5], м + 5, 1)
    сумма = u16(р.д, м + 6)
    ipv6 = версия == 3 and псевдо is not None and псевдо[1] == 6
    ширина = 16 if ipv6 else 4
    место = м + 8
    for _ in range(адресов):
        if версия not in (2, 3) or место + ширина > конец:
            break
        у.поле("Виртуальный адрес", "vrrp.ip_addr",
               ip6(р.д, место) if ipv6 else ip4(р.д, место), место, ширина)
        место += ширина
    if версия == 2 and место + 8 <= конец:
        у.поле("Данные подлинности", "vrrp.auth_data", р.д[место:место + 8].hex(), место, 8)
        место += 8
    сообщение = р.д[м:место]
    if версия == 2:
        способ = "по сообщению" if сумма16(сообщение) == 0 else ""
    else:
        способ = ("с псевдозаголовком" if псевдо is not None and _псевдо_сумма(псевдо, 112, сообщение) == 0
                  else "без псевдозаголовка" if not ipv6 and сумма16(сообщение) == 0 else "")
    у.поле("Контрольная сумма", "vrrp.checksum",
           f"0x{сумма:04x} [" + (f"верна, {способ}" if способ else "не сошлась") + "]", м + 6, 2, сумма,
           плохо=not способ)
    if not способ:
        р.ошибка("VRRP: контрольная сумма не сошлась")
    у.длина = место - м
    у.итог = f"VRID {vrid}, приоритет {приоритет}"
    р.п.инфо = "VRRP " + у.итог


