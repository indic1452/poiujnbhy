def icmp(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("ICMP", "Internet Control Message Protocol", м)
    р.нужно(м, 4)
    тип, код, сумма = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    у.поле("Тип", "icmp.type", f"{тип} ({ICMP_ТИПЫ.get(тип, 'неизвестный')})", м, 1, тип)
    текст_кода = ICMP_НЕДОСТИЖИМ.get(код, str(код)) if тип == 3 else str(код)
    у.поле("Код", "icmp.code", f"{код}" + (f" ({текст_кода})" if тип == 3 else ""), м + 1, 1, код)
    верна = сумма16(р.д[м:конец]) == 0
    у.поле("Контрольная сумма", "icmp.checksum", f"0x{сумма:04x} [{'верна' if верна else 'НЕВЕРНА'}]",
           м + 2, 2, сумма, плохо=not верна)
    if not верна:
        р.ошибка("ICMP: неверная контрольная сумма")
    у.длина = 4
    у.итог = ICMP_ТИПЫ.get(тип, f"тип {тип}")
    if тип in (0, 8) and м + 8 <= конец:
        ид, номер = u16(р.д, м + 4), u16(р.д, м + 6)
        у.поле("Идентификатор", "icmp.ident", ид, м + 4, 2)
        у.поле("Номер", "icmp.seq", номер, м + 6, 2)
        у.длина = 8
        у.итог += f", id {ид}, номер {номер}"
        р.нагрузка(м + 8, конец)
    elif тип in (3, 4, 5, 11, 12) and м + 8 < конец:
        if тип == 3:
            у.итог += f" ({текст_кода})"
        if тип == 5:
            у.поле("Шлюз", "icmp.redir_gw", ip4(р.д, м + 4), м + 4, 4)
        у.длина = 8
        р.п.инфо = f"ICMP {у.итог}"
        # Внутри — заголовок исходного пакета: разбираем его тоже.
        вложенный = Разбор(Пакет(0, 0, р.д[:конец], конец, ""))
        вложенный.глубина = р.глубина + 1
        try:
            ipv4(вложенный, м + 8)
        except Мало:
            pass
        for вл in вложенный.п.уровни:
            вл.протокол = "исходный " + вл.протокол
            вл.полное = "Исходный пакет: " + вл.полное
            р.п.уровни.append(вл)
        return
    р.п.инфо = f"ICMP {у.итог}"


