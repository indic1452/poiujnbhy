КАНАЛ_В_РАЗБОРЩИК: dict[str, Callable[[Разбор, int], None]] = {
    "Ethernet": ethernet, "IP": голый_ip, "IPv4": ipv4, "IPv6": ipv6, "PPP": ppp,
    "PPP-HDLC": ppp, "Cisco HDLC": cisco_hdlc, "Linux SLL": linux_sll,
    "Linux SLL2": lambda р, м: linux_sll(р, м, 2), "loopback": loopback, "авто": авто,
}


def разобрать_пакет(данные_: bytes, канал: str = "Ethernet", *, номер: int = 1,
                    время: float = 0.0, исходная_длина: int | None = None,
                    как: dict[str, str] | None = None, шаблоны: dict | None = None) -> Пакет:
    """Разобрать один пакет. Ошибки разбора не бросаются — они в ``пакет.ошибки``.

    ``как`` — «разбирать как»: {"tcp:8888": "HTTP", "udp:5000": "данные"};
    ``шаблоны`` — общий словарь шаблонов NetFlow v9/IPFIX захвата (пополняется разбором).
    ``как["правила"]`` — правила «Декодировать как» и «убрать протокол» (dekodirovat_kak.py).
    """
    if как and как.get("правила"):
        from .dekodirovat_kak import разобрать_по_правилам  # noqa: PLC0415
        return разобрать_по_правилам(данные_, канал, номер=номер, время=время, исходная_длина=исходная_длина,
                                     как=как, шаблоны=шаблоны)
    пакет = Пакет(номер, время, bytes(данные_), исходная_длина or len(данные_), канал)
    р = Разбор(пакет, как, шаблоны)
    разборщик = КАНАЛ_В_РАЗБОРЩИК.get(канал)
    try:
        if разборщик is None:
            данные(р, 0, f"канал «{канал}» разбирать не умею")
        else:
            разборщик(р, 0)
    except Мало:
        пакет.ошибки.append("пакет оборван: заголовок длиннее записанных байт")
        if пакет.уровни:
            пакет.уровни[-1].итог += " [оборван]"
    except (struct.error, IndexError, ValueError) as ошибка:
        пакет.ошибки.append(f"разбор прерван: {ошибка}")
    if not пакет.инфо and пакет.уровни:
        пакет.инфо = пакет.уровни[-1].итог
    return пакет


