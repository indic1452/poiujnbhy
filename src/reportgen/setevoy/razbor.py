def ethernet(р: Разбор, м: int) -> None:
    for признак in ДОП_ETHERNET:
        if признак(р, м):
            return
    у = р.уровень("Ethernet", "Ethernet II", м)
    р.нужно(м, 14)
    у.поле("Получатель", "eth.dst", mac(р.д, м), м, 6)
    у.поле("Отправитель", "eth.src", mac(р.д, м + 6), м + 6, 6)
    тип = u16(р.д, м + 12)
    у.длина = 14
    if тип <= 1500:
        у.полное = "IEEE 802.3"
        у.поле("Длина", "eth.len", тип, м + 12, 2)
        у.итог = f"{mac(р.д, м + 6)} → {mac(р.д, м)}, 802.3, длина {тип}"
        р.адреса(mac(р.д, м + 6), mac(р.д, м))
        _скрытые(у, "eth.addr", [mac(р.д, м), mac(р.д, м + 6)])
        llc(р, м + 14, м + 14 + тип)
        return
    у.поле("Тип", "eth.type", f"0x{тип:04x} ({ETHERTYPE.get(тип, 'неизвестный')})", м + 12, 2, тип)
    у.итог = f"{mac(р.д, м + 6)} → {mac(р.д, м)}, {ETHERTYPE.get(тип, hex(тип))}"
    р.адреса(mac(р.д, м + 6), mac(р.д, м))
    _скрытые(у, "eth.addr", [mac(р.д, м), mac(р.д, м + 6)])
    по_типу(р, тип, м + 14)


def _скрытые(у: Уровень, ключ: str, значения) -> None:
    """Поля только для фильтра (ip.addr, tcp.port…): длина 0, в дереве не видны."""
    for значение in значения:
        у.поле("", ключ, значение, у.смещение, 0)


def по_типу(р: Разбор, тип: int, м: int) -> None:
    разборщик = {0x0800: ipv4, 0x86DD: ipv6, 0x0806: arp, 0x8035: arp, 0x8100: vlan,
                 0x88A8: vlan, 0x9100: vlan, 0x8847: mpls, 0x8848: mpls, 0x8863: pppoe,
                 0x8864: pppoe, 0x88CC: lldp, 0x6558: ethernet, 0x880B: ppp, 0x88D8: cesoeth}.get(тип) \
        or ДОП_ETHERTYPE.get(тип)
    if разборщик is None:
        данные(р, м, f"EtherType 0x{тип:04x}")
    else:
        разборщик(р, м)


def llc(р: Разбор, м: int, конец: int) -> None:
    у = р.уровень("LLC", "IEEE 802.2 LLC", м)
    р.нужно(м, 3)
    dsap, ssap, упр = р.д[м], р.д[м + 1], р.д[м + 2]
    у.поле("DSAP", "llc.dsap", f"0x{dsap:02x}", м, 1, dsap)
    у.поле("SSAP", "llc.ssap", f"0x{ssap:02x}", м + 1, 1, ssap)
    у.поле("Управление", "llc.control", f"0x{упр:02x}", м + 2, 1, упр)
    у.длина = 3
    if dsap == 0xAA and ssap == 0xAA:
        р.нужно(м + 3, 5)
        тип = u16(р.д, м + 6)
        у.поле("OUI (SNAP)", "llc.oui", р.д[м + 3:м + 6].hex(":"), м + 3, 3)
        у.поле("Тип (SNAP)", "llc.pid", f"0x{тип:04x}", м + 6, 2, тип)
        у.длина = 8
        у.итог = f"SNAP, тип 0x{тип:04x}"
        по_типу(р, тип, м + 8)
    elif dsap == 0x42:
        у.итог = "STP"
        stp(р, м + 3)
    elif dsap in ДОП_LLC:
        ДОП_LLC[dsap](р, м + 3, конец)
    else:
        у.итог = f"DSAP 0x{dsap:02x}, SSAP 0x{ssap:02x}"
        данные(р, м + 3, "LLC", конец)


def stp(р: Разбор, м: int) -> None:
    """BPDU остовного дерева (IEEE 802.1D): конфигурационный и RST."""
    у = р.уровень("STP", "Spanning Tree Protocol", м)
    р.нужно(м, 4)
    версия, вид = р.д[м + 2], р.д[м + 3]
    у.поле("Протокол", "stp.protocol", u16(р.д, м), м, 2)
    у.поле("Версия", "stp.version", {0: "STP", 2: "RSTP", 3: "MSTP"}.get(версия, версия), м + 2, 1, версия)
    у.поле("Тип BPDU", "stp.type", {0: "конфигурационный", 0x80: "уведомление TCN",
                                     2: "RST/MST"}.get(вид, f"0x{вид:02x}"), м + 3, 1, вид)
    у.длина = 4
    if вид in (0, 2) and м + 35 <= len(р.д):
        у.поле("Флаги", "stp.flags", f"0x{р.д[м + 4]:02x}", м + 4, 1, р.д[м + 4])
        корень = f"{u16(р.д, м + 5)} / {mac(р.д, м + 7)}"
        мост = f"{u16(р.д, м + 17)} / {mac(р.д, м + 19)}"
        у.поле("Корень (приоритет / MAC)", "stp.root", корень, м + 5, 8)
        у.поле("Стоимость пути к корню", "stp.root.cost", u32(р.д, м + 13), м + 13, 4)
        у.поле("Мост (приоритет / MAC)", "stp.bridge", мост, м + 17, 8)
        у.поле("Порт", "stp.port", f"0x{u16(р.д, м + 25):04x}", м + 25, 2, u16(р.д, м + 25))
        for имя, место in (("Возраст сообщения", 27), ("Наибольший возраст", 29),
                           ("Интервал hello", 31), ("Задержка пересылки", 33)):
            у.поле(имя + ", с", "", f"{u16(р.д, м + место) / 256:g}", м + место, 2)
        у.длина = 35
        у.итог = f"корень {корень}, стоимость {u32(р.д, м + 13)}, порт 0x{u16(р.д, м + 25):04x}"
    р.п.инфо = "STP: " + (у.итог or "уведомление TCN")


def vlan(р: Разбор, м: int) -> None:
    у = р.уровень("VLAN", "IEEE 802.1Q VLAN", м)
    р.нужно(м, 4)
    tci = u16(р.д, м)
    у.поле("Приоритет (PCP)", "vlan.priority", tci >> 13, м, 2)
    у.поле("DEI", "vlan.dei", (tci >> 12) & 1, м, 2)
    у.поле("VLAN ID", "vlan.id", tci & 0xFFF, м, 2)
    тип = u16(р.д, м + 2)
    у.поле("Тип", "vlan.etype", f"0x{тип:04x} ({ETHERTYPE.get(тип, 'неизвестный')})", м + 2, 2, тип)
    у.длина = 4
    у.итог = f"VLAN {tci & 0xFFF}, приоритет {tci >> 13}"
    по_типу(р, тип, м + 4)


def mpls(р: Разбор, м: int) -> None:
    у = р.уровень("MPLS", "MPLS", м)
    метки = []
    while True:
        р.нужно(м, 4)
        слово = u32(р.д, м)
        метка, tc, дно, ttl = слово >> 12, (слово >> 9) & 7, (слово >> 8) & 1, слово & 0xFF
        п = у.поле(f"Метка {метка}", "mpls.label", метка, м, 4)
        у.поле("Класс трафика", "mpls.exp", tc, м, 4, родитель=п)
        у.поле("Дно стека", "mpls.bottom", дно, м, 4, родитель=п)
        у.поле("TTL", "mpls.ttl", ttl, м, 4, родитель=п)
        метки.append(str(метка))
        м += 4
        if дно:
            break
    у.длина = 4 * len(метки)
    у.итог = "метки " + ", ".join(метки)
    if м >= len(р.д):
        return
    версия = р.д[м] >> 4
    if версия == 4:
        ipv4(р, м)
    elif версия == 6:
        ipv6(р, м)
    elif версия == 1:
        pw_ach(р, м)
    elif версия == 0 and м + 4 <= len(р.д):
        # Управляющее слово псевдопровода (RFC 4385: первые 4 бита — нули). Под ним Ethernet —
        # если в нём тип кадра из известных; иначе — TDM (SAToP, CESoPSN) или иной псевдопровод.
        if м + 4 + 14 <= len(р.д) and _похоже_на_ethernet(р.д, м + 4):
            у.поле("Управляющее слово", "pwach.cw", f"0x{u32(р.д, м):08x}", м, 4, u32(р.д, м))
            ethernet(р, м + 4)
        else:
            pw_tdm(р, м, len(р.д))
    else:
        ethernet(р, м)


#: Типы кадров, по которым нагрузка псевдопровода признаётся Ethernet.
ETH_В_PW = frozenset({0x0800, 0x86DD, 0x0806, 0x8100, 0x88A8, 0x8847, 0x8848, 0x88CC, 0x8902, 0x8863, 0x8864})


def _похоже_на_ethernet(д: bytes, м: int) -> bool:
    return u16(д, м + 12) in ETH_В_PW or u16(д, м + 12) <= 1500 and д[м + 14:м + 16] in (b"\xaa\xaa", b"\x42\x42", b"\xfe\xfe")


#: Типы канала G-ACh (Wireshark packet-mpls.h PW_ACH_TYPE_*; RFC 5586, 5718, 6428, 6374).
ACH_ТИПЫ = {0x0001: "MCC (RFC 5718)", 0x0002: "SCC", 0x0007: "BFD", 0x000A: "DLM (RFC 6374)",
            0x000B: "ILM", 0x000C: "DM", 0x000D: "DLM+DM", 0x000E: "ILM+DM", 0x0021: "IPv4",
            0x0022: "BFD CC (RFC 6428)", 0x0023: "BFD CV", 0x0024: "PSC (RFC 6378)",
            0x0025: "on-demand CV", 0x0027: "PW OAM", 0x0028: "MAC", 0x0057: "IPv6",
            0x0058: "MPLS-TP FM (RFC 6427)", 0x8902: "Y.1731 (RFC 6371)"}


def pw_ach(р: Разбор, м: int) -> None:
    """Связанный канал G-ACh (RFC 4385/5586): первый полубайт 0001, версия, тип канала."""
    у = р.уровень("PWACH", "PW Associated Channel Header", м)
    р.нужно(м, 4)
    тип = u16(р.д, м + 2)
    у.поле("Версия", "pwach.ver", р.д[м] & 0x0F, м, 1)
    у.поле("Тип канала", "pwach.channel_type", ACH_ТИПЫ.get(тип, f"0x{тип:04x}"), м + 2, 2, тип)
    у.длина = 4
    у.итог = ACH_ТИПЫ.get(тип, f"тип 0x{тип:04x}")
    р.п.инфо = "G-ACh " + у.итог
    if тип == 0x0021:
        ipv4(р, м + 4)
    elif тип == 0x0057:
        ipv6(р, м + 4)
    elif тип in ДОП_ETHERTYPE and тип == 0x8902:
        # Y.1731 в MPLS-TP (RFC 6371): PDU OAM прямо за словом G-ACh.
        ДОП_ETHERTYPE[тип](р, м + 4)
    elif м + 4 < len(р.д):
        данные(р, м + 4, "G-ACh")


#: Биты L и M управляющего слова TDM (RFC 5086; Wireshark packet-pw-cesopsn.c vals_cw_lm).
LM_TDM = {0x0: "норма", 0x2: "отказ стыка: RDI", 0x3: "сигнализация CESoPSN", 0x8: "отказ стыка: данные TDM неверны"}


def pw_tdm(р: Разбор, м: int, конец: int) -> None:
    """Псевдопровод TDM: управляющее слово SAToP (RFC 4553) / CESoPSN (RFC 5086) и нагрузка.

    Слово: 0000, L, R, M(2) — у SAToP вместо M резерв; FRG(2), LEN(6); номер 16 бит.
    Нагрузка SAToP — поток E1/T1 целиком (кадр E1 — 32 байта), CESoPSN — N КИ × кадров."""
    у = р.уровень("PW-TDM", "TDM pseudowire (SAToP / CESoPSN)", м)
    р.нужно(м, 4)
    б0, б1, номер = р.д[м], р.д[м + 1], u16(р.д, м + 2)
    lm = б0 & 0x0B
    у.поле("L+M", "pwtdm.cw.lm", LM_TDM.get(lm, f"0x{lm:x} (резерв)"), м, 1, lm)
    у.поле("R: потеря пакетов у приёмника", "pwtdm.cw.rbit", (б0 >> 2) & 1, м, 1)
    у.поле("Фрагментация", "pwtdm.cw.frag", (б1 >> 6) & 3, м + 1, 1)
    длина_cw = б1 & 0x3F
    у.поле("Длина (при нагрузке < 64 байт)", "pwtdm.cw.length", длина_cw, м + 1, 1)
    у.поле("Номер", "pwtdm.cw.seqno", номер, м + 2, 2)
    нагрузка = (длина_cw - 4 if длина_cw else конец - м - 4)
    нагрузка = max(0, min(нагрузка, конец - м - 4))
    у.поле("Нагрузка TDM", "pwtdm.payload", f"{нагрузка} байт", м + 4, нагрузка)
    у.длина = конец - м
    вид = (f"E1 целиком — {нагрузка // 32} кадров G.704 (SAToP) или n×64" if нагрузка and нагрузка % 32 == 0
           else f"T1 целиком — {нагрузка // 24} кадров" if нагрузка and нагрузка % 24 == 0 and нагрузка % 32
           else "n×64 кбит/с (CESoPSN)")
    у.итог = f"номер {номер}, {нагрузка} байт: {вид}"
    р.п.инфо = "PW TDM " + у.итог


def cesoeth(р: Разбор, м: int) -> None:
    """CESoETH (MEF 8, EtherType 0x88D8): ECID 20 бит + резерв 0x102, затем слово TDM и нагрузка."""
    у = р.уровень("CESoETH", "Circuit Emulation over Ethernet (MEF 8)", м)
    р.нужно(м, 8)
    слово = u32(р.д, м)
    у.поле("ECID", "cesoeth.ecid", f"0x{слово >> 12:05x}", м, 4, слово >> 12)
    у.поле("Резерв", "cesoeth.reserved", f"0x{слово & 0xFFF:03x}" + ("" if слово & 0xFFF == 0x102 else " — не 0x102"),
           м, 4, слово & 0xFFF)
    у.длина = 4
    у.итог = f"ECID 0x{слово >> 12:05x}"
    pw_tdm(р, м + 4, len(р.д))


def arp(р: Разбор, м: int) -> None:
    у = р.уровень("ARP", "Address Resolution Protocol", м)
    р.нужно(м, 8)
    htype, ptype, hlen, plen, операция = u16(р.д, м), u16(р.д, м + 2), р.д[м + 4], р.д[м + 5], u16(р.д, м + 6)
    у.поле("Тип оборудования", "arp.hw.type", htype, м, 2)
    у.поле("Тип протокола", "arp.proto.type", f"0x{ptype:04x}", м + 2, 2, ptype)
    у.поле("Длина адреса оборудования", "arp.hw.size", hlen, м + 4, 1)
    у.поле("Длина адреса протокола", "arp.proto.size", plen, м + 5, 1)
    имя = {1: "запрос", 2: "ответ", 3: "RARP-запрос", 4: "RARP-ответ"}.get(операция, str(операция))
    у.поле("Операция", "arp.opcode", имя, м + 6, 2, операция)
    р.нужно(м + 8, 2 * hlen + 2 * plen)
    места = [м + 8, м + 8 + hlen, м + 8 + hlen + plen, м + 8 + 2 * hlen + plen]

    def адрес(место, длина, ip):
        if ip and длина == 4:
            return ip4(р.д, место)
        if not ip and длина == 6:
            return mac(р.д, место)
        return р.д[место:место + длина].hex()

    sha, spa = адрес(места[0], hlen, False), адрес(места[1], plen, True)
    tha, tpa = адрес(места[2], hlen, False), адрес(места[3], plen, True)
    у.поле("MAC отправителя", "arp.src.hw_mac", sha, места[0], hlen)
    у.поле("IP отправителя", "arp.src.proto_ipv4", spa, места[1], plen)
    у.поле("MAC получателя", "arp.dst.hw_mac", tha, места[2], hlen)
    у.поле("IP получателя", "arp.dst.proto_ipv4", tpa, места[3], plen)
    у.длина = 8 + 2 * hlen + 2 * plen
    if операция == 1:
        у.итог = (f"Кто {tpa}? Сообщите {spa}" if spa != tpa else f"Объявление {spa} (gratuitous)")
    elif операция == 2:
        у.итог = f"{spa} — это {sha}"
    else:
        у.итог = имя
    р.п.инфо = у.итог


def pppoe(р: Разбор, м: int) -> None:
    у = р.уровень("PPPoE", "PPP over Ethernet", м)
    р.нужно(м, 6)
    код, сеанс, длина = р.д[м + 1], u16(р.д, м + 2), u16(р.д, м + 4)
    коды = {0x00: "данные сеанса", 0x09: "PADI", 0x07: "PADO", 0x19: "PADR", 0x65: "PADS", 0xA7: "PADT"}
    у.поле("Версия / тип", "pppoe.version", f"{р.д[м] >> 4} / {р.д[м] & 15}", м, 1, р.д[м])
    у.поле("Код", "pppoe.code", коды.get(код, f"0x{код:02x}"), м + 1, 1, код)
    у.поле("Сеанс", "pppoe.session_id", f"0x{сеанс:04x}", м + 2, 2, сеанс)
    у.поле("Длина", "pppoe.payload_length", длина, м + 4, 2)
    у.длина = 6
    у.итог = f"{коды.get(код, hex(код))}, сеанс 0x{сеанс:04x}"
    if код == 0:
        ppp(р, м + 6, с_адресом=False)
        return
    теги = {0x0101: "Service-Name", 0x0102: "AC-Name", 0x0103: "Host-Uniq", 0x0104: "AC-Cookie",
            0x0110: "Relay-Session-Id", 0x0201: "Service-Name-Error", 0x0202: "AC-System-Error",
            0x0203: "Generic-Error"}
    место, конец = м + 6, min(len(р.д), м + 6 + длина)
    while место + 4 <= конец:
        тег, дл = u16(р.д, место), u16(р.д, место + 2)
        значение = р.д[место + 4:место + 4 + дл]
        текст = значение.decode("utf-8", "replace") if тег in (0x0101, 0x0102) else значение.hex()
        у.поле(теги.get(тег, f"тег 0x{тег:04x}"), "pppoe.tag", текст or "(пусто)", место, 4 + дл)
        место += 4 + дл
    р.п.инфо = "PPPoE " + у.итог


def ppp(р: Разбор, м: int, *, с_адресом: bool = True) -> None:
    у = р.уровень("PPP", "Point-to-Point Protocol", м)
    р.нужно(м, 2)
    начало = м
    if с_адресом and р.д[м:м + 2] == b"\xff\x03":
        у.поле("Адрес", "ppp.address", "0xff", м, 1, 0xFF)
        у.поле("Управление", "ppp.control", "0x03", м + 1, 1, 3)
        м += 2
    р.нужно(м, 2)
    if р.д[м] & 1:                                      # сжатое поле протокола (1 байт)
        протокол, дл = р.д[м], 1
    else:
        протокол, дл = u16(р.д, м), 2
    у.поле("Протокол", "ppp.protocol",
           f"0x{протокол:04x} ({PPP_ПРОТОКОЛЫ.get(протокол, 'неизвестный')})", м, дл, протокол)
    у.длина = м + дл - начало
    у.итог = PPP_ПРОТОКОЛЫ.get(протокол, f"0x{протокол:04x}")
    м += дл
    if протокол == 0x0021:
        ipv4(р, м)
    elif протокол == 0x0057:
        ipv6(р, м)
    elif протокол == 0x0281:
        mpls(р, м)
    elif протокол in PPP_УПРАВЛЯЮЩИЕ:
        ppp_управление(р, м, PPP_УПРАВЛЯЮЩИЕ[протокол])
    elif протокол in ДОП_PPP:
        ДОП_PPP[протокол](р, м, len(р.д))
    else:
        данные(р, м, у.итог)


