class Разбор:
    """Состояние разбора одного пакета."""

    def __init__(self, пакет: Пакет, как: dict[str, str] | None = None, шаблоны: dict | None = None):
        self.п = пакет
        self.д = пакет.данные
        self.глубина = 0
        # «Разбирать как»: {"udp:5000": "DNS"} — выбор аналитика важнее таблицы портов.
        self.как = как or {}
        # Шаблоны NetFlow v9/IPFIX, пришедшие в прежних пакетах (общий словарь захвата).
        self.шаблоны = шаблоны if шаблоны is not None else {}

    def уровень(self, протокол: str, полное: str, м: int) -> Уровень:
        у = Уровень(протокол, полное, м)
        self.п.уровни.append(у)
        return у

    def нужно(self, м: int, сколько: int) -> None:
        if м + сколько > len(self.д):
            raise Мало()

    def ошибка(self, текст: str) -> None:
        self.п.ошибки.append(текст)

    def адреса(self, от: str, к: str) -> None:
        self.п.источник, self.п.получатель = от, к

    def нагрузка(self, м: int, конец: int | None = None) -> None:
        self.п.нагрузка = self.д[м:конец]
        self.п.нагрузка_смещение = м


