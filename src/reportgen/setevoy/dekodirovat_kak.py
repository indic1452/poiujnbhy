"""«Декодировать как» и «убрать протокол»: реестр разборщиков и таблица правил аналитика.

Так же, как в Wireshark (Руководство пользователя Wireshark, раздел «Control
Protocol Dissection»: «Enabled Protocols» и «User Specified Decodes»,
doc/wsug_src/wsug_customize.adoc), аналитик управляет выбором разборщика двумя
видами правил:

* **правило по полю** (Decode As): «если у протокола P поле K равно V, то
  вложенное в P разбирать разборщиком D» — порт TCP/UDP/SCTP, EtherType, номер
  протокола IP, PPID SCTP, VLAN, тип сообщения GTP и любое другое поле P;
* **правило по протоколу** (Enabled Protocols): протокол X (везде или только
  поверх P) — «данные» (байты X и всё вложенное — данными: разбор на X
  прекращается, как у выключенного протокола Wireshark), «снять» (заголовок X —
  данными, вложенное — обычным путём или разборщиком D по выбору) или «вместо»
  (на месте X — разборщик D).

Разборщик D выбирается из реестра всех разборщиков анализатора (канальные,
по EtherType, по номеру протокола IP, поверх UDP/TCP/SCTP/PPP/LLC) — с поиском
по названию и описанию.

Точка в ядре разбора одна: ``razbor.разобрать_пакет`` передаёт пакет сюда, если
в правилах «разбирать как» (``как``) есть ключ ``"правила"`` — список правил
этого модуля. Разбор идёт теми же разборщиками; класс ``РазборПоПравилам``
перехватывает создание уровня (``Разбор.уровень`` — через него проходит каждый
протокол): если правило велит на этом месте другое, создание прерывается
исключением ``Перехват``, стек разборщиков сворачивается до входа, и разбор
продолжается отсюда — нужным разборщиком с того же смещения. Таблицы
разборщиков ``razbor``/``prilozh``/``protokoly`` при этом не меняются: новые
разборщики попадают в реестр сами.
"""

