class Перехват(BaseException):  # noqa: N818 — не ошибка, а поворот разбора
    """Разбор на этом месте поворачивает по правилу. От BaseException — чтобы пройти сквозь
    ``except (Мало, ValueError, …)`` и ``except Exception`` разборщиков до входа разбора."""

    def __init__(self, м: int, конец: int, как: str, правило: dict[str, Any], снять: Уровень | None = None):
        super().__init__(м)
        self.м, self.конец, self.как, self.правило, self.снять = м, конец, как, правило, снять


def _поля(у: Уровень) -> Iterable[Any]:
    стек = list(у.поля)
    while стек:
        п = стек.pop()
        yield п
        стек.extend(п.дети)


def _совпало(у: Уровень, ключ: str, значение: int | str) -> bool:
    for п in _поля(у):
        if п.ключ != ключ:
            continue
        if п.сырое == значение or п.текст == str(значение) or п.текст.split(" ", 1)[0] == str(значение):
            return True
    return False


def _число(у: Уровень, ключ: str) -> int | None:
    for п in у.поля:
        if п.ключ == ключ and isinstance(п.сырое, int):
            return п.сырое
    return None


def конец_вложенного(р: Any, м: int) -> int:
    """Где кончается вложенное, начатое на ``м``: по нагрузке, отмеченной уровнем ниже, или по
    длинам UDP (RFC 768), IPv4 (RFC 791, Total Length) и IPv6 (RFC 8200, Payload Length)."""
    конец = len(р.д)
    if р.п.нагрузка is not None and р.п.нагрузка_смещение == м:
        return min(конец, м + len(р.п.нагрузка))
    for у in reversed(р.п.уровни):
        длина = None
        if у.протокол == "UDP":
            длина = _число(у, "udp.length")
            длина = длина if длина is not None and длина >= 8 else None
        elif у.протокол == "IPv4":
            длина = _число(у, "ip.len")
        elif у.протокол == "IPv6":
            полезная = _число(у, "ipv6.plen")
            длина = None if полезная is None else 40 + полезная
        if длина is not None and у.смещение + длина > м:
            return min(конец, у.смещение + длина)
    return конец


def _снятый(у: Уровень, до: int, д: bytes) -> Уровень:
    """Заголовок убранного протокола — уровнем «Данные» на его месте."""
    длина = max(0, до - у.смещение)
    з = Уровень("Данные", f"Данные: заголовок {у.протокол} (протокол убран правилом)", у.смещение, длина)
    з.поле("Байты", "data.data", f"{длина} байт: {печатное(д[у.смещение:до], 40)}", у.смещение, длина,
           д[у.смещение:до].hex())
    з.итог = f"{у.протокол} убран, {длина} байт"
    return з


def _разбор_по_правилам():
    from .razbor import Разбор  # noqa: PLC0415

    class РазборПоПравилам(Разбор):
        """Разбор, у которого создание уровня сверяется с таблицей правил."""

        def __init__(self, пакет: Пакет, как: dict[str, Any], шаблоны: dict | None, т: Таблица):
            super().__init__(пакет, как, шаблоны)
            self.т = т
            self.перехватов = 0
            self.пропустить: int | None = None     # номер уровня, который создаёт сам поворот
            self.сработали: list[str] = []

        def уровень(self, протокол: str, полное: str, м: int) -> Уровень:
            номер = len(self.п.уровни)
            if self.пропустить == номер:
                self.пропустить = None
            elif self.перехватов < ПЕРЕХВАТОВ_ДО:
                self._свериться(протокол, м)
            return super().уровень(протокол, полное, м)

        def _свериться(self, протокол: str, м: int) -> None:
            верх = self.п.уровни[-1] if self.п.уровни else None
            ниже = верх.протокол if верх is not None else ""
            for п in self.т.по_протоколу.get(протокол, ()):
                if not п.get("после") or п["после"] == ниже:
                    raise Перехват(м, конец_вложенного(self, м), п["как"] or ДАННЫЕ, п)
            if верх is None:
                return
            for п in self.т.снять_дальше.get(ниже, ()):
                if п["как"] and (not п.get("после") or (len(self.п.уровни) > 1
                                                         and self.п.уровни[-2].протокол == п["после"])):
                    raise Перехват(м, конец_вложенного(self, м), п["как"], п, снять=верх)
            for п in self.т.по_полю.get(ниже, ()):
                if _совпало(верх, п["поле"], п["значение"]):
                    raise Перехват(м, конец_вложенного(self, м), п["как"], п)

        def повернуть(self, п: Перехват) -> None:
            """Продолжить разбор по сработавшему правилу с места перехвата."""
            from .razbor import данные  # noqa: PLC0415
            self.перехватов += 1
            self.сработали.append(п.правило["ид"])
            if п.снять is not None and п.снять in self.п.уровни:
                i = self.п.уровни.index(п.снять)
                self.п.уровни[i] = _снятый(п.снять, п.м, self.д)
            что = описать(п.правило)
            if п.как == ДАННЫЕ:
                self.пропустить = len(self.п.уровни)
                данные(self, п.м, что, п.конец)
                return
            разборщик = реестр().get(п.как)
            self.пропустить = len(self.п.уровни)
            if разборщик is None or not разборщик.вызвать(self, п.м, п.конец):
                self.п.ошибки.append(f"разобрать как {п.как}: данные не подошли ({что})")
                self.пропустить = len(self.п.уровни)
                данные(self, п.м, f"не подошло к {п.как}", п.конец)

        def снять_заголовки(self) -> None:
            """«Снять заголовок X, вложенное — как обычно»: уровень X — данными своего заголовка."""
            if not self.т.снять_дальше:
                return
            for i, у in enumerate(self.п.уровни):
                for п in self.т.снять_дальше.get(у.протокол, ()):
                    if п["как"] or (п.get("после") and (i == 0 or self.п.уровни[i - 1].протокол != п["после"])):
                        continue
                    self.п.уровни[i] = _снятый(у, у.смещение + у.длина, self.д)
                    self.сработали.append(п["ид"])
                    break

    return РазборПоПравилам


