#: Особое имя «разборщика»: байты — данными, дальше не разбирать.
ДАННЫЕ = "данные"
#: Сколько правил у одного человека.
ПРАВИЛ_ДО = 64
#: Сколько раз за пакет правило может перехватить разбор (защита от зацикливания:
#: «UDP 4789 → Ethernet» внутри себя снова встретит UDP 4789).
ПЕРЕХВАТОВ_ДО = 8
ВИДЫ = ("поле", "протокол")
ДЕЙСТВИЯ = ("данные", "снять", "вместо")
#: Поля, по которым правило «по полю» предлагается сразу (как таблицы Decode As
#: Wireshark: tcp.port, udp.port, sctp.port, sctp.ppi, ethertype, ip.proto, vlan.id…).
#: Остальные поля протокола тоже годятся — проверяется любое поле уровня P.
ПОЛЯ_ПРЕДЛОЖЕНИЯ = {
    "UDP": ("udp.port",), "TCP": ("tcp.port",), "SCTP": ("sctp.data_payload_proto_id", "sctp.port"),
    "Ethernet": ("eth.type",), "VLAN": ("vlan.etype", "vlan.id"), "IPv4": ("ip.proto",),
    "IPv6": ("ipv6.nxt",), "GTP": ("gtp.message",), "SLL": ("sll.etype",), "CHDLC": ("chdlc.protocol",),
}
_ИМЯ = re.compile(r"[^\x00-\x1f\\<>]{1,64}")
_КЛЮЧ = re.compile(r"[a-z0-9_.]{1,64}")


