# -- правила --------------------------------------------------------------------------------

def _строка(значение: Any, что: str, *, пусто: bool = False) -> str:
    текст = str(значение if значение is not None else "").strip()
    if not текст and пусто:
        return ""
    if not _ИМЯ.fullmatch(текст):
        raise ValueError(f"{что}: нужна строка от 1 до 64 знаков без управляющих")
    return текст


def _значение(значение: Any) -> int | str:
    if isinstance(значение, bool):
        raise ValueError("значение поля: число или строка")
    if isinstance(значение, int):
        if not 0 <= значение < 1 << 64:
            raise ValueError("значение поля: от 0 до 2^64−1")
        return значение
    текст = _строка(значение, "значение поля")
    if re.fullmatch(r"0x[0-9a-fA-F]{1,16}", текст):
        return int(текст, 16)
    if re.fullmatch(r"\d{1,19}", текст):
        return int(текст)
    return текст


def проверить_правило(данные: Any, *, имена: Iterable[str] | None = None) -> dict[str, Any]:
    """Одно правило из запроса → правило в каноническом виде или ValueError с причиной."""
    if not isinstance(данные, dict):
        raise ValueError("правило — объект JSON")
    имена = set(реестр() if имена is None else имена)
    вид = str(данные.get("вид") or "").strip()
    if вид not in ВИДЫ:
        raise ValueError("вид правила: «поле» (разобрать как по значению поля) или «протокол» (убрать протокол)")
    ид = str(данные.get("ид") or "").strip() or secrets.token_hex(4)
    if not re.fullmatch(r"[0-9a-f]{8}", ид):
        raise ValueError("ид правила: 8 шестнадцатеричных знаков")
    правило: dict[str, Any] = {"ид": ид, "вкл": данные.get("вкл", True) is not False, "вид": вид}
    как = _строка(данные.get("как"), "разборщик", пусто=True)
    if вид == "поле":
        правило["над"] = _строка(данные.get("над"), "протокол, в котором поле")
        поле = str(данные.get("поле") or "").strip().lower()
        if not _КЛЮЧ.fullmatch(поле):
            raise ValueError("поле: ключ поля вида udp.port, eth.type, sctp.data_payload_proto_id")
        правило["поле"] = поле
        правило["значение"] = _значение(данные.get("значение"))
        if not как:
            raise ValueError("укажите, как разбирать: разборщик из списка или «данные»")
    else:
        правило["протокол"] = _строка(данные.get("протокол"), "протокол")
        правило["после"] = _строка(данные.get("после"), "протокол ниже", пусто=True)
        действие = str(данные.get("действие") or "данные").strip()
        if действие not in ДЕЙСТВИЯ:
            raise ValueError("действие: «данные», «снять» или «вместо»")
        правило["действие"] = действие
        if действие == "данные":
            как = ""
        elif действие == "вместо" and not как:
            raise ValueError("«вместо»: укажите разборщик")
    if как and как != ДАННЫЕ and как not in имена:
        raise ValueError(f"разборщика «{как}» нет в анализаторе")
    правило["как"] = как
    return правило


def проверить_правила(данные: Any) -> list[dict[str, Any]]:
    if not isinstance(данные, list):
        raise ValueError("правила — список")
    if len(данные) > ПРАВИЛ_ДО:
        raise ValueError(f"правил не больше {ПРАВИЛ_ДО}")
    имена = set(реестр())
    итог = [проверить_правило(п, имена=имена) for п in данные]
    иды = [п["ид"] for п in итог]
    if len(set(иды)) != len(иды):
        raise ValueError("у двух правил одинаковый ид")
    return итог


def описать(п: dict[str, Any]) -> str:
    """Правило словами — для списка правил и для заметок."""
    if п["вид"] == "поле":
        как = "данные (не разбирать)" if п["как"] == ДАННЫЕ else п["как"]
        return f"{п['над']}: {п['поле']} = {п['значение']} → {как}"
    где = п["протокол"] + (f" поверх {п['после']}" if п.get("после") else "")
    if п["действие"] == "данные":
        return f"{где}: убрать — байты и всё вложенное как данные"
    if п["действие"] == "снять":
        return f"{где}: снять заголовок, вложенное — " + (п["как"] or "как обычно")
    return f"{где}: разбирать как {п['как']}"


class Таблица:
    """Включённые правила, разложенные для быстрого поиска при создании уровня."""

    def __init__(self, правила: Iterable[dict[str, Any]]):
        self.по_полю: dict[str, list[dict[str, Any]]] = {}
        self.по_протоколу: dict[str, list[dict[str, Any]]] = {}
        self.снять_дальше: dict[str, list[dict[str, Any]]] = {}
        for п in правила:
            if not п.get("вкл", True):
                continue
            if п["вид"] == "поле":
                self.по_полю.setdefault(п["над"], []).append(п)
            elif п["действие"] == "снять":
                self.снять_дальше.setdefault(п["протокол"], []).append(п)
            else:
                self.по_протоколу.setdefault(п["протокол"], []).append(п)

    def пуста(self) -> bool:
        return not (self.по_полю or self.по_протоколу or self.снять_дальше)


_кэш_таблиц: dict[int, tuple[list[dict[str, Any]], str, Таблица]] = {}


def таблица(правила: list[dict[str, Any]]) -> Таблица:
    """Таблица по списку правил. Разбор захвата передаёт один и тот же список для каждого
    пакета — он узнаётся по себе (ссылка держится, id не займёт другой список), а если его
    поменяли на месте — по содержимому."""
    запись = _кэш_таблиц.get(id(правила))
    if запись is not None and запись[0] is правила and len(запись[1]) and запись[1] == _снимок(правила):
        return запись[2]
    if len(_кэш_таблиц) > 32:
        _кэш_таблиц.clear()
    т = Таблица(правила)
    _кэш_таблиц[id(правила)] = (правила, _снимок(правила), т)
    return т


def _снимок(правила: list[dict[str, Any]]) -> str:
    return repr(правила)


