def разобрать_по_правилам(данные_: bytes, канал: str = "Ethernet", *, номер: int = 1, время: float = 0.0,
                          исходная_длина: int | None = None, как: dict[str, Any] | None = None,
                          шаблоны: dict | None = None) -> Пакет:
    """То же, что ``razbor.разобрать_пакет``, но с правилами ``как["правила"]``."""
    global _класс
    from .razbor import КАНАЛ_В_РАЗБОРЩИК, данные  # noqa: PLC0415
    if _класс is None:
        _класс = _разбор_по_правилам()
    как = dict(как or {})
    т = таблица(как.pop("правила", None) or [])
    пакет = Пакет(номер, время, bytes(данные_), исходная_длина or len(данные_), канал)
    р = _класс(пакет, как, шаблоны, т)
    разборщик = КАНАЛ_В_РАЗБОРЩИК.get(канал)

    def начать() -> None:
        if разборщик is None:
            данные(р, 0, f"канал «{канал}» разбирать не умею")
        else:
            разборщик(р, 0)

    шаг: Callable[[], None] | None = начать
    while шаг is not None:
        текущий, шаг = шаг, None
        try:
            текущий()
        except Перехват as п:
            шаг = (lambda п=п: р.повернуть(п))
        except Мало:
            пакет.ошибки.append("пакет оборван: заголовок длиннее записанных байт")
            if пакет.уровни:
                пакет.уровни[-1].итог += " [оборван]"
        except (struct.error, IndexError, ValueError) as ошибка:
            пакет.ошибки.append(f"разбор прерван: {ошибка}")
    р.снять_заголовки()
    if р.сработали:
        пакет.правила = list(dict.fromkeys(р.сработали))   # type: ignore[attr-defined]
    if not пакет.инфо and пакет.уровни:
        пакет.инфо = пакет.уровни[-1].итог
    return пакет


def с_правилами(как: dict[str, Any] | None, правила: list[dict[str, Any]]) -> dict[str, Any]:
    """Правила «разбирать как» захвата (порты) плюс включённые правила человека."""
    итог = {к: з for к, з in (как or {}).items() if к != "правила"}
    включённые = [п for п in правила if п.get("вкл", True)]
    if включённые:
        итог["правила"] = включённые
    return итог


