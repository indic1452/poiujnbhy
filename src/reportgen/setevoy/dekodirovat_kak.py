def реестр() -> dict[str, Разборщик]:
    """Все разборщики анализатора по именам. Строится при первом вызове и заново, когда модули
    ``protokoly`` дописали свои таблицы (меняется размер какой-либо таблицы)."""
    global _реестр, _подпись_реестра
    подпись = tuple(len(т) for т in _таблицы())
    with _замок_реестра:
        if подпись != _подпись_реестра or not _реестр:
            _реестр = _собрать_реестр()
            _подпись_реестра = подпись
        return _реестр


def _собрать_реестр() -> dict[str, Разборщик]:
    from . import prilozh, razbor  # noqa: PLC0415
    итог: dict[str, Разборщик] = {}
    виденные: dict[int, str] = {}

    def добавить(имя: str, группа: str, ключ: str, функция: Callable[..., Any], описание: str = "") -> None:
        if функция is None:
            return
        прежнее = виденные.get(id(функция))
        if прежнее is not None and итог[прежнее].группа == группа:
            return                                  # тот же разборщик под другим ключом той же группы
        if any(и.lower() == имя.lower() and р.группа == группа for и, р in итог.items()):
            return                                  # то же имя в той же группе (OpenVPN и OPENVPN)
        if имя in итог and итог[имя].функция is not функция:
            имя = f"{имя} ({группа})"
            if имя in итог:
                return
        итог[имя] = Разборщик(имя, группа, описание or _описание(функция), ключ, функция, _обязательных(функция))
        виденные.setdefault(id(функция), имя)

    for канал, функция in razbor.КАНАЛ_В_РАЗБОРЩИК.items():
        if re.search(r"\(SSN \d+\)$", канал):
            continue                                 # TCAP по каждой подсистеме — один «TCAP»
        добавить("Авто (по признакам)" if канал == "авто" else канал, "канал", f"тип канала «{канал}»", функция,
                 "кадр целиком с этого места" if канал != "авто" else "IPv4, IPv6, PPP, Cisco HDLC, Ethernet, "
                 "MTP2, LAPD, Frame Relay — по признакам заголовка")
    встроенные_eth = {0x0806: ("ARP", razbor.arp), 0x8100: ("VLAN (802.1Q)", razbor.vlan),
                      0x8847: ("MPLS", razbor.mpls), 0x8863: ("PPPoE", razbor.pppoe), 0x88CC: ("LLDP", razbor.lldp),
                      0x88D8: ("CESoETH (MEF 8)", razbor.cesoeth)}
    for тип, (имя, функция) in встроенные_eth.items():
        добавить(имя, "EtherType", f"EtherType 0x{тип:04x}", функция)
    for тип, функция in razbor.ДОП_ETHERTYPE.items():
        добавить(_имя_из(функция, razbor.ETHERTYPE.get(тип, "")), "EtherType", f"EtherType 0x{тип:04x}", функция)
    встроенные_ip = {6: razbor.tcp, 17: razbor.udp, 1: razbor.icmp, 58: razbor.icmpv6, 2: razbor.igmp, 47: razbor.gre,
                     50: razbor.esp, 51: razbor.ah, 89: razbor.ДОП_IP.get(89, razbor.ospf), 112: razbor.vrrp,
                     132: razbor.sctp}
    for номер, функция in встроенные_ip.items():
        добавить(razbor.IP_ПРОТОКОЛЫ.get(номер, str(номер)), "IP", f"протокол IP {номер}", функция)
    for номер, функция in razbor.ДОП_IP.items():
        добавить(_имя_из(функция, razbor.IP_ПРОТОКОЛЫ.get(номер, "")), "IP", f"протокол IP {номер}", функция)
    for транспорт, порты in (("udp", prilozh.ПОРТЫ_UDP), ("tcp", prilozh.ПОРТЫ_TCP)):
        по_функции = {id(ф): п for п, ф in порты.items()}
        for имя, функция in prilozh.КАК[транспорт].items():
            порт = по_функции.get(id(функция))
            добавить(имя, транспорт.upper(), f"{транспорт.upper()} порт {порт}" if порт else f"поверх {транспорт.upper()}",
                     функция)
        for порт, функция in порты.items():
            добавить(_имя_из(функция, ""), транспорт.upper(), f"{транспорт.upper()} порт {порт}", функция)
    for ppid, функция in razbor.ДОП_SCTP_PPID.items():
        добавить(_имя_из(функция, ""), "SCTP", f"SCTP PPID {ppid}", функция)
    for порт, функция in razbor.ДОП_SCTP_ПОРТ.items():
        добавить(_имя_из(функция, ""), "SCTP", f"SCTP порт {порт}", функция)
    for номер, функция in razbor.ДОП_PPP.items():
        добавить(_имя_из(функция, razbor.PPP_ПРОТОКОЛЫ.get(номер, "")), "PPP", f"протокол PPP 0x{номер:04x}", функция)
    for dsap, функция in razbor.ДОП_LLC.items():
        добавить(_имя_из(функция, ""), "LLC", f"LLC DSAP 0x{dsap:02x}", функция)
    добавить("LLC (802.2)", "EtherType", "длина вместо EtherType", razbor.llc)
    return итог


