class ПравилаЛюдей:
    """Правила каждого человека — файл ``<папка>/<ид>.json``: применяются ко всем его захватам."""

    def __init__(self, папка: Path):
        self.папка = Path(папка)
        self._lock = threading.Lock()

    def _путь(self, пользователь: int) -> Path:
        return self.папка / f"{int(пользователь)}.json"

    def прочитать(self, пользователь: int) -> list[dict[str, Any]]:
        try:
            данные = json.loads(self._путь(пользователь).read_text(encoding="utf-8"))
            return проверить_правила(данные.get("правила") or [])
        except (OSError, ValueError, AttributeError):
            return []

    def записать(self, пользователь: int, правила: Any) -> list[dict[str, Any]]:
        правила = проверить_правила(правила)
        with self._lock:
            self.папка.mkdir(parents=True, exist_ok=True)
            записать_атомарно(self._путь(пользователь), json.dumps({"правила": правила}, ensure_ascii=False))
        return правила

    def добавить(self, пользователь: int, правило: Any) -> list[dict[str, Any]]:
        новое = проверить_правило(правило)
        прежние = [п for п in self.прочитать(пользователь) if п["ид"] != новое["ид"] and not _то_же(п, новое)]
        return self.записать(пользователь, прежние + [новое])

    def изменить(self, пользователь: int, ид: str, *, вкл: bool) -> list[dict[str, Any]]:
        правила = self.прочитать(пользователь)
        if not any(п["ид"] == ид for п in правила):
            raise KeyError(ид)
        for п in правила:
            if п["ид"] == ид:
                п["вкл"] = bool(вкл)
        return self.записать(пользователь, правила)

    def удалить(self, пользователь: int, ид: str) -> list[dict[str, Any]]:
        правила = self.прочитать(пользователь)
        if not any(п["ид"] == ид for п in правила):
            raise KeyError(ид)
        return self.записать(пользователь, [п for п in правила if п["ид"] != ид])


def _то_же(а: dict[str, Any], б: dict[str, Any]) -> bool:
    """Правило для того же места (новое заменяет прежнее, а не копится рядом)."""
    if а["вид"] != б["вид"]:
        return False
    if а["вид"] == "поле":
        return (а["над"], а["поле"], а["значение"]) == (б["над"], б["поле"], б["значение"])
    return (а["протокол"], а.get("после", "")) == (б["протокол"], б.get("после", ""))
