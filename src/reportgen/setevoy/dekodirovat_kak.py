@dataclass(frozen=True)
class Разборщик:
    """Разборщик анализатора под именем для выбора человеком."""

    имя: str
    группа: str               # где обычно стоит: канал, EtherType, IP, UDP, TCP, SCTP, PPP, LLC
    описание: str
    ключ: str                 # как узнаётся без правил: «EtherType 0x0806», «UDP 53»…
    функция: Callable[..., Any]
    нужно: int                # обязательных аргументов: 2 — (р, м), 3 — (р, м, конец), 4 — и псевдозаголовок

    def вызвать(self, р: Any, м: int, конец: int) -> bool:
        """Разобрать с места ``м`` до ``конец``; False — данные не подошли (уровни откатываются)."""
        уровней = len(р.п.уровни)
        try:
            if self.нужно <= 2:
                итог = self.функция(р, м)
            elif self.нужно == 3:
                итог = self.функция(р, м, конец)
            else:
                итог = self.функция(р, м, конец, _псевдо(р))
        except (Мало, IndexError, ValueError, struct.error):
            del р.п.уровни[уровней:]
            return False
        if итог is False:
            del р.п.уровни[уровней:]
            return False
        return True

    def в_словарь(self) -> dict[str, str]:
        return {"имя": self.имя, "группа": self.группа, "описание": self.описание, "ключ": self.ключ}


def _псевдо(р: Any) -> tuple[bytes, int]:
    """Псевдозаголовок для сумм TCP/UDP — адреса ближайшего IP ниже (или нули)."""
    for у in reversed(р.п.уровни):
        if у.протокол == "IPv4" and у.смещение + 20 <= len(р.д):
            return р.д[у.смещение + 12:у.смещение + 20], 4
        if у.протокол == "IPv6" and у.смещение + 40 <= len(р.д):
            return р.д[у.смещение + 8:у.смещение + 40], 6
    return b"\0" * 8, 4


def _обязательных(функция: Callable[..., Any]) -> int:
    try:
        параметры = inspect.signature(функция).parameters.values()
    except (TypeError, ValueError):
        return 3
    return sum(1 for п in параметры if п.default is inspect.Parameter.empty
               and п.kind in (п.POSITIONAL_ONLY, п.POSITIONAL_OR_KEYWORD))


def _описание(функция: Callable[..., Any]) -> str:
    return " ".join((inspect.getdoc(функция) or "").split("\n\n")[0].split())[:240]


def _имя_из(функция: Callable[..., Any], запас: str) -> str:
    """Имя для выбора: начало описания («PIM (RFC 7761…)» → PIM) или имя функции."""
    описание = _описание(функция)
    м = re.match(r"([A-Za-z0-9][\w./+'-]{0,23})\s*[(:,—]", описание)
    if м and not м.group(1).islower():
        return м.group(1)
    if запас:
        return запас
    имя = функция.__name__.strip("_")
    for хвост in ("_ethertype", "_udp", "_tcp", "_ppp", "_эвристика", "_признаки"):
        имя = имя.removesuffix(хвост)
    return имя.upper() if имя.isascii() else имя.replace("_", " ").capitalize()


