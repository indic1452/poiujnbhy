class _Дописчик:
    """Файлы хранилища записи — дописываются; при открытии укорачиваются до сшитого (после сбоя)."""

    ИМЕНА = (ИНДЕКС, СВОДКИ, ПОЛЯ, ВРЕМЯ, ДЛИНА, ПОТОК)

    def __init__(self, папка: Path, размеры: dict[str, int]):
        self.ф: dict[str, Any] = {}
        self.размеры: dict[str, int] = {}
        for имя in self.ИМЕНА:
            путь = папка / имя
            if not путь.exists():
                путь.write_bytes(b"")
            ф = open(путь, "r+b")  # noqa: SIM115 — закрывает закрыть()
            размер = int(размеры.get(имя, 0))
            ф.truncate(размер)
            ф.seek(размер)
            self.ф[имя], self.размеры[имя] = ф, размер

    def дописать(self, имя: str, данные: bytes) -> int:
        место = self.размеры[имя]
        self.ф[имя].write(данные)
        self.размеры[имя] += len(данные)
        return место

    def дописать_файл(self, имя: str, путь: Path) -> int:
        """Файл целиком (кусками, не через память) — в конец; итог — где он начался."""
        место = self.размеры[имя]
        with open(путь, "rb") as ф:
            while True:
                кусок = ф.read(4 << 20)
                if not кусок:
                    break
                self.ф[имя].write(кусок)
                self.размеры[имя] += len(кусок)
        return место

    def сбросить(self, *имена: str) -> None:
        for имя in имена or self.ИМЕНА:
            self.ф[имя].flush()

    def закрыть(self) -> None:
        for ф in self.ф.values():
            with contextlib.suppress(OSError):
                ф.close()


def _кандидаты(путь: Path) -> Iterator[tuple[int, Any]]:
    with open(путь, "rb") as ф:
        while True:
            try:
                yield pickle.load(ф)  # noqa: S301 — файл пишет сам сервер
            except EOFError:
                return


class Сшивка:
    """Состояние сшивки записи: настоящее общее состояние, сборка, статистика, файлы хранилища."""

    def __init__(self, папка: Path, задание: dict[str, Any]):
        from .fon import Снимки  # noqa: PLC0415
        from .nakopitel import Накопитель  # noqa: PLC0415
        from .sborka import Сборка  # noqa: PLC0415
        self.папка = Path(папка)
        self.поколение = задание.get("поколение")
        self.путь = Path(задание["путь"])
        состояние = self._прочитать()
        if состояние is None:
            состояние = {"сшито": 0, "пакетов": 0, "прочитано": int(задание.get("прочитано") or 0), "размеры": {},
                         "каналы": [], "шаблоны": {}, "сборка": Сборка(self.папка, dict(задание.get("как") or {})),
                         "накопитель": Накопитель(), "рев": 0, "каналов_записано": -1}
        self.сшито: int = состояние["сшито"]
        self.пакетов: int = состояние["пакетов"]
        self.прочитано: int = состояние["прочитано"]
        self.каналы: list[str] = состояние["каналы"]
        self._каналов_записано: int = состояние.get("каналов_записано", -1)
        self.шаблоны: dict[str, Any] = состояние["шаблоны"]
        self.сборка = состояние["сборка"]
        self.сборка.папка = self.папка
        self.сборка.собранные.папка = self.папка
        self.накопитель = состояние["накопитель"]
        self.снимки = Снимки(self.папка)
        self.снимки.рев = состояние["рев"]
        self.д = _Дописчик(self.папка, состояние["размеры"])
        self._источник = None

    def _прочитать(self) -> dict[str, Any] | None:
        путь = self.папка / СШИВКА / "состояние.pkl"
        try:
            состояние = pickle.loads(путь.read_bytes())  # noqa: S301 — файл пишет сам сервер
        except (OSError, EOFError, pickle.UnpicklingError):
            return None
        return состояние if состояние.get("поколение") == self.поколение else None

    def закрыть(self) -> None:
        self.д.закрыть()
        self.сборка.закрыть()
        if self._источник is not None:
            self._источник.close()

    def номер_канала(self, канал: str) -> int:
        try:
            return self.каналы.index(канал)
        except ValueError:
            self.каналы.append(канал)
            return len(self.каналы) - 1

    def _данные(self, место: int, длина: int) -> bytes:
        if self._источник is None:
            self._источник = open(self.путь, "rb")  # noqa: SIM115 — закрывает закрыть()
        self._источник.seek(место)
        return self._источник.read(длина)

    # -- одна пачка --

    def пачка(self, k: int) -> None:
        from . import obshee  # noqa: PLC0415
        from .nakopitel import поля_накопителя  # noqa: PLC0415
        from .razbor import разобрать_пакет  # noqa: PLC0415
        from .sborka import _для_фильтра, _сводка  # noqa: PLC0415
        from .statistika import ключ_потока  # noqa: PLC0415
        d = папка_пачки(self.папка, k)
        итог = json.loads((d / "итог.json").read_text(encoding="utf-8"))
        n, первый = итог["пакетов"], итог["номер"]
        if первый != self.пакетов + 1:
            raise RuntimeError(f"пачка {k} начинается с пакета {первый}, а сшито {self.пакетов}")
        индекс = np.fromfile(d / ИНДЕКС, dtype=ЗАПИСЬ_ТИП)
        поток = np.fromfile(d / ПОТОК, dtype="<u8")
        точно = np.fromfile(d / "точно.f8", dtype="<f8")
        исходно = np.fromfile(d / "исходно.u4", dtype="<u4")
        журнал = dict(pickle.loads(zlib.decompress((d / "журнал.z").read_bytes())))  # noqa: S301
        нк = pickle.loads(zlib.decompress((d / "накопитель.z").read_bytes()))  # noqa: S301
        ssnh = set(итог["ssnh"])
        кандидаты = _кандидаты(d / "кандидаты.pkl")
        следующий = next(кандидаты, None)
        свои_каналы = итог["каналы"]
        канал_пачки = индекс["канал"].copy()
        карта = np.array([self.номер_канала(к) for к in свои_каналы] or [0], dtype="<u2")
        индекс["канал"] = карта[канал_пачки]
        особые = sorted(set(журнал) | ssnh | set(итог["кандидаты"]))
        j = 0
        длины = индекс["длина"].tolist()
        изменено: dict[int, tuple[dict[str, Any], dict[str, Any]]] = {}
        добавить = self.накопитель.добавить
        with open(d / СВОДКИ, "rb") as фс:
            for b, (с_м, с_д, _п_м, _п_д, строк) in enumerate(итог["блоки"]):
                от = b * СТРОК_В_БЛОКЕ
                до = от + строк
                фс.seek(с_м)
                сводки = pickle.loads(zlib.decompress(фс.read(с_д)))  # noqa: S301
                # Особые пакеты блока — по порядку: повтор действий с общим состоянием, сборка.
                while j < len(особые) and особые[j] < до:
                    i = особые[j]
                    j += 1
                    номер = первый + i
                    п = None
                    заново = i in журнал and not obshee.повторить(журнал[i], self.шаблоны, self.сборка.как)
                    if следующий is not None and следующий[0] == i:
                        if not заново:
                            п = следующий[1]
                        следующий = next(кандидаты, None)
                    if заново:
                        п = разобрать_пакет(self._данные(int(индекс[i]["место"]), длины[i]),
                                            свои_каналы[int(канал_пачки[i])], номер=номер, время=float(точно[i]),
                                            исходная_длина=int(исходно[i]), как=self.сборка.как,
                                            шаблоны=self.шаблоны)
                    if п is None:
                        if i in ssnh:
                            self.сборка.lcp({"lcp.opt.ssnh": [True]}, номер)
                        continue
                    поля, собран = self.сборка.пакет(п)
                    if заново or собран:
                        сводка = _сводка(п, поля)
                        изменено[i] = (сводка, _для_фильтра(поля))
                        поток[i] = отпечаток_потока(ключ_потока(сводка))
                        if собран:
                            индекс["признаки"][i] |= СОБРАННЫЙ
                # Статистика — по порядку пакетов.
                for r in range(строк):
                    i = от + r
                    з = изменено.get(i)
                    if з is not None:
                        добавить(з[0], поля_накопителя(з[0]["стек"], з[1]) or {}, длины[i])
                    else:
                        добавить(сводки[r], нк.get(i) or {}, длины[i])
        # Блоки пачки — в хранилище байт в байт; места в индексе сдвигаются на место пачки в файлах хранилища.
        с_место = self.д.дописать_файл(СВОДКИ, d / СВОДКИ)
        п_место = self.д.дописать_файл(ПОЛЯ, d / ПОЛЯ)
        индекс["сводки"] += с_место
        индекс["поля"] += п_место
        # Изменившиеся пакеты — новыми блоками (по порядку); их записи индекса указывают туда.
        номера = sorted(изменено)
        for от in range(0, len(номера), СТРОК_В_БЛОКЕ):
            часть = номера[от:от + СТРОК_В_БЛОКЕ]
            сжато_с = zlib.compress(pickle.dumps([изменено[i][0] for i in часть], pickle.HIGHEST_PROTOCOL), СЖАТИЕ)
            сжато_п = zlib.compress(pickle.dumps([изменено[i][1] for i in часть], pickle.HIGHEST_PROTOCOL), СЖАТИЕ)
            м_с = self.д.дописать(СВОДКИ, сжато_с)
            м_п = self.д.дописать(ПОЛЯ, сжато_п)
            где = np.asarray(часть, dtype=np.int64)
            индекс["сводки"][где], индекс["сводки_длина"][где] = м_с, len(сжато_с)
            индекс["поля"][где], индекс["поля_длина"][где] = м_п, len(сжато_п)
            индекс["в_блоке"][где] = np.arange(len(часть))
        # Порядок записи — как у Писателя: блоки, собранные, столбцы, имена каналов и последним — индекс.
        self.д.сбросить(СВОДКИ, ПОЛЯ)
        self.д.дописать(ВРЕМЯ, (d / ВРЕМЯ).read_bytes())
        self.д.дописать(ДЛИНА, (d / ДЛИНА).read_bytes())
        self.д.дописать(ПОТОК, поток.tobytes())
        self.д.сбросить(ВРЕМЯ, ДЛИНА, ПОТОК)
        if len(self.каналы) != self._каналов_записано:
            записать_атомарно(self.папка / КАНАЛЫ, json.dumps(self.каналы, ensure_ascii=False))
            self._каналов_записано = len(self.каналы)
        self.д.дописать(ИНДЕКС, индекс.tobytes())
        self.д.сбросить(ИНДЕКС)
        self.пакетов += n
        self.прочитано = итог["конец"]
        self.сшито = k + 1

    # -- на диск --

    def кратко(self) -> dict[str, Any]:
        return {"сшито": self.сшито, "пакетов": self.пакетов, "прочитано": self.прочитано, "рев": self.снимки.рев,
                "mp_короткие_с": self.сборка.mp_короткие_с, "поколение": self.поколение}

    def сохранить(self, *, всё: bool = False) -> None:
        """Статистику, шаблоны, затравку и состояние сшивки — на диск (после того, как файлы хранилища сброшены)."""
        from .obshee import ВЫЗОВЫ  # noqa: PLC0415
        self.д.сбросить()
        self.снимки.записать(self.накопитель, всё=всё)
        with contextlib.suppress(OSError, TypeError, ValueError):
            записать_атомарно(self.папка / "шаблоны.json",
                              json.dumps(self.шаблоны, ensure_ascii=False, default=str))
        (self.папка / СШИВКА).mkdir(exist_ok=True)
        _атомарно_pickle(self.папка / СШИВКА / "затравка.pkl",
                         {"поколение": self.поколение, "как": self.сборка.как, "пакетов": self.пакетов,
                          "сшито": self.сшито, "шаблоны": {к: з for к, з in self.шаблоны.items() if к != ВЫЗОВЫ}})
        _атомарно_pickle(self.папка / СШИВКА / "состояние.pkl",
                         {"поколение": self.поколение, "сшито": self.сшито, "пакетов": self.пакетов,
                          "прочитано": self.прочитано, "размеры": dict(self.д.размеры), "каналы": self.каналы,
                          "каналов_записано": self._каналов_записано, "шаблоны": self.шаблоны,
                          "сборка": self.сборка, "накопитель": self.накопитель, "рев": self.снимки.рев})
        записать_атомарно(self.папка / СШИВКА / "ход.json", json.dumps(self.кратко(), ensure_ascii=False))


def сшить(папка: str, задание: dict[str, Any]) -> dict[str, Any]:
    """Исполнитель: сшить готовые пачки с ``сшито`` по ``задание["до"]`` (по порядку), сколько успеется за
    ``СШИВКА_ДО`` секунд. Статистика пишется вся, если ``всё`` или ``конец`` (это последние пачки записи) и
    сшито всё, или если лежит метка «стоп» (разбор останавливается: сшитое сохраняется на границе пачки).
    Итог — сколько сшито (``Сшивка.кратко``); по ходу — ``сообщить("сшито", …)`` после каждой пачки."""
    with _без_сборщика_мусора():
        return _сшить(Path(папка), задание)


def _сшить(папка: Path, задание: dict[str, Any]) -> dict[str, Any]:
    цп = time.process_time()
    стоп = папка / СШИВКА / СТОП
    ст = Сшивка(папка, задание)
    остановлена = False
    try:
        начато = time.monotonic()
        до = int(задание["до"])
        while ст.сшито <= до:
            if стоп.exists():
                остановлена = True
                break
            _проверить_отмену()
            ст.пачка(ст.сшито)
            ст.снимки.записать(ст.накопитель)
            _сообщить("сшито", ст.кратко())
            if time.monotonic() - начато > СШИВКА_ДО:
                break
        всё = bool(задание.get("всё")) or остановлена or (bool(задание.get("конец")) and ст.сшито > до)
        ст.сохранить(всё=всё)
    finally:
        ст.закрыть()
    # Сшитые пачки больше не нужны (состояние, что их покрывает, уже на диске).
    for k in range(int(задание.get("от", 0)), ст.сшито):
        shutil.rmtree(папка_пачки(папка, k), ignore_errors=True)
    return {**ст.кратко(), "цп": round(time.process_time() - цп, 2)}


