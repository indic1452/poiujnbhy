    ф_кандидатов = open(врем / "кандидаты.pkl", "wb")  # noqa: SIM115

    def блок() -> None:
        запись = []
        for имя, строки in ((СВОДКИ, сводки_блока), (ПОЛЯ, поля_блока)):
            сжато = zlib.compress(pickle.dumps(строки, pickle.HIGHEST_PROTOCOL), СЖАТИЕ)
            файлы[имя].write(сжато)
            запись += [места[имя], len(сжато)]
            места[имя] += len(сжато)
        блоки.append([*запись, len(сводки_блока)])
        сводки_блока.clear()
        поля_блока.clear()

    try:
        with Окна(задание["путь"], начало) as окна:
            конец = int(задание["конец"])
            for i in range(пакетов):
                if i % ХОД_ПАЧКИ == 0:
                    _проверить_отмену()
                    if i:
                        _сообщить("ход", i)
                запись = окна.следующая(конец)
                if запись is None:
                    raise RuntimeError(f"пачка {k}: записей меньше разметки ({i} из {пакетов})"
                                       + (f": {окна.испорчен}" if окна.испорчен else ""))
                в, данные, исх, канал, место = запись
                номер = первый + i
                шаблоны.записи = []
                п = разобрать_пакет(данные, канал, номер=номер, время=в, исходная_длина=исх, как=как,
                                    шаблоны=шаблоны)
                поля = п.поля_фильтра()
                if шаблоны.записи:
                    журнал.append((i, шаблоны.записи))
                if Сборка.нужна(п, поля):
                    кандидаты.append(i)
                    pickle.dump((i, п), ф_кандидатов, pickle.HIGHEST_PROTOCOL)
                elif True in поля.get("lcp.opt.ssnh", []):
                    ssnh.append(i)
                if not короткие and True in поля.get("lcp.opt.ssnh", []):
                    как = {**как, "ppp:mp": "короткие"}           # как сборка: дальше номера MP короткие
                    короткие = True
                сводка = _сводка(п, поля)
                дф = _для_фильтра(поля)
                пн = поля_накопителя(сводка["стек"], дф)
                if пн is not None:
                    нк[i] = пн
                try:
                    к = каналы.index(канал)
                except ValueError:
                    каналы.append(канал)
                    к = len(каналы) - 1
                индекс[i]["место"], индекс[i]["длина"], индекс[i]["канал"] = место, len(данные), к
                индекс[i]["в_блоке"] = len(сводки_блока)
                время[i], точно[i], длина[i], исходно[i] = сводка["время"], в, п.исходная_длина, исх
                поток[i] = отпечаток_потока(ключ_потока(сводка))
                сводки_блока.append(сводка)
                поля_блока.append(дф)
                if len(сводки_блока) == СТРОК_В_БЛОКЕ:
                    блок()
            if сводки_блока:
                блок()
    finally:
        for ф in (*файлы.values(), ф_кандидатов):
            ф.close()
    # Места блоков в индексе — внутри пачки (сшивка сдвинет их на место в хранилище).
    for b, (с_м, с_д, п_м, п_д, строк) in enumerate(блоки):
        срез = slice(b * СТРОК_В_БЛОКЕ, b * СТРОК_В_БЛОКЕ + строк)
        индекс["сводки"][срез], индекс["сводки_длина"][срез] = с_м, с_д
        индекс["поля"][срез], индекс["поля_длина"][срез] = п_м, п_д
    for имя, массив in ((ИНДЕКС, индекс), (ВРЕМЯ, время), ("точно.f8", точно), (ДЛИНА, длина),
                        ("исходно.u4", исходно), (ПОТОК, поток)):
        (врем / имя).write_bytes(массив.tobytes())
    (врем / "журнал.z").write_bytes(zlib.compress(pickle.dumps(журнал, pickle.HIGHEST_PROTOCOL), 1))
    (врем / "накопитель.z").write_bytes(zlib.compress(pickle.dumps(нк, pickle.HIGHEST_PROTOCOL), 1))
    итог = {"пачка": k, "поколение": задание.get("поколение"), "номер": первый, "пакетов": пакетов,
            "конец": int(задание["конец"]), "каналы": каналы, "блоки": блоки, "кандидаты": кандидаты,
            "ssnh": ssnh, "журнал": len(журнал)}
    (врем / "итог.json").write_text(json.dumps(итог, ensure_ascii=False), encoding="utf-8")
    shutil.rmtree(цель, ignore_errors=True)
    os.replace(врем, цель)
    return {"пачка": k, "пакетов": пакетов, "журнал": len(журнал), "кандидатов": len(кандидаты),
            "цп": round(time.process_time() - цп, 2)}


