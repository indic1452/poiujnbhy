def предел_пачки(k: int, размер: dict[str, Any] | None = None) -> int:
    р = размер or РАЗМЕР
    первые = list(р.get("первые") or [])
    return int(первые[k]) if k < len(первые) else int(р["пакетов"])


class _Разведка:
    """Разведка общего состояния при разметке: пакеты с метками (``РАЗВЕДКА_МЕТКИ``) разбираются со своим
    состоянием, их записи состояния (``ЗАПИСИ_СОСТОЯНИЯ``) — в журнал разведки. ``место`` — сколько байт
    журнала годны (разметка продолжается): состояние восстанавливается повтором записей, лишнее отрезается."""

    def __init__(self, папка: Path, как: dict[str, Any], место: int):
        from .obshee import Журнал  # noqa: PLC0415
        self.путь = Path(папка) / ПАЧКИ / РАЗВЕДКА
        self.путь.parent.mkdir(parents=True, exist_ok=True)
        self.как = dict(как)
        self.шаблоны = Журнал()
        if not self.путь.exists():
            self.путь.write_bytes(b"")
        if место:
            дополнить_записями(self.шаблоны, self.путь, 0, 0, 1 << 62, до_места=место)
        self.ф = open(self.путь, "r+b")  # noqa: SIM115 — закрывает закрыть()
        self.ф.truncate(место)
        self.ф.seek(место)

    def пакет(self, данные: bytes, канал: str, номер: int, время: float, исходно: int) -> None:
        if b"\r\n" not in данные and b"\nm=" not in данные:
            return
        for метка in РАЗВЕДКА_МЕТКИ:
            if метка in данные:
                break
        else:
            return
        from .obshee import ВЫЗОВЫ  # noqa: PLC0415
        from .razbor import разобрать_пакет  # noqa: PLC0415
        self.шаблоны.записи = []
        разобрать_пакет(данные, канал, номер=номер, время=время, исходная_длина=исходно, как=self.как,
                        шаблоны=self.шаблоны)
        self.шаблоны.pop(ВЫЗОВЫ, None)                     # вызовы SIP затравке не нужны
        записи = [(имя, арг) for имя, арг, _ in self.шаблоны.записи if имя in ЗАПИСИ_СОСТОЯНИЯ]
        if записи:
            pickle.dump((номер, записи), self.ф, pickle.HIGHEST_PROTOCOL)

    def место(self) -> int:
        """Сколько байт журнала записано (и сброшено на диск: исполнители читают его, пока разметка идёт)."""
        self.ф.flush()
        return self.ф.tell()

    def закрыть(self) -> None:
        with contextlib.suppress(OSError):
            self.ф.close()


def дополнить_записями(шаблоны: dict, путь: Path, от: int, после: int, до: int, *, до_места: int | None = None) -> int:
    """Записи журнала разведки (с места ``от``) пакетов с номерами после ``после`` и до ``до`` — поверх
    ``шаблоны``; ``до_места`` — не дальше этого места журнала. Итог — сколько пакетов дополнено.
    Недописанная запись в конце (разметка ещё пишет) — конец чтения."""
    from .obshee import ДЕЙСТВИЯ, Доступ  # noqa: PLC0415
    д = Доступ(шаблоны)
    n = 0
    try:
        ф = open(путь, "rb")  # noqa: SIM115
    except OSError:
        return 0
    with ф:
        ф.seek(от)
        while до_места is None or ф.tell() < до_места:
            try:
                номер, записи = pickle.load(ф)  # noqa: S301 — файл пишет сам сервер
            except (EOFError, pickle.UnpicklingError, ValueError, TypeError, AttributeError, IndexError):
                break
            if номер >= до:
                break
            if номер <= после:
                continue
            for имя, аргументы in записи:
                ДЕЙСТВИЯ[имя](д, *аргументы)
            n += 1
    return n


def разметить(путь: str, задание: dict[str, Any]) -> dict[str, Any]:
    """Исполнитель: границы пачек с ``задание["начало"]`` (нет — с начала файла, узнав его вид), сколько
    позволяют байты файла; заодно — разведка общего состояния (если дана ``папка`` записи). Каждая пачка
    сразу уходит в сервер: ``сообщить("пачка", [начало, пакетов, начало_следующей, место журнала разведки в
    начале пачки и в конце])``.
    Итог: {"итог": "конец" | "ждать" | "дальше", "начало": где продолжить, "разведка": место журнала там,
    "заметки"}.

    ``готов`` — файл больше не растёт: тогда недописанный хвост — заметка, а не «ждать»."""
    готов = bool(задание.get("готов", True))
    р = {**РАЗМЕР, **(задание.get("размер") or {})}
    начало = задание.get("начало")
    место_разведки = int(задание.get("разведка") or 0)
    if начало is None:
        начало, формат, заметки = начало_файла(путь, готов=готов)
        if начало is None:
            return {"итог": "ждать", "начало": None, "разведка": 0}
        место_разведки = 0
        _сообщить("вид", {"начало": начало, "формат": формат, "заметки": заметки})
    размер = Path(путь).stat().st_size
    k = int(задание.get("пачка", 0))
    от = int(начало["место"])
    разведка = (_Разведка(Path(задание["папка"]), задание.get("как") or {}, место_разведки)
                if задание.get("папка") else None)
    try:
        with Окна(путь, начало, данные=разведка is not None) as окна:
            while True:
                _проверить_отмену()
                с = окна.начало()
                с_разведки = разведка.место() if разведка is not None else 0
                предел = предел_пачки(k, р)
                n = 0
                while n < предел and окна.место - с["место"] < р["байт"]:
                    номер = окна.номер
                    запись = окна.следующая(размер)
                    if запись is None:
                        break
                    if разведка is not None:
                        разведка.пакет(запись[1], запись[3], номер, запись[0], запись[2])
                    n += 1
                if n and (n == предел or окна.место - с["место"] >= р["байт"]):
                    _сообщить("пачка", [с, n, окна.начало(), с_разведки,
                                        разведка.место() if разведка is not None else 0])
                    k += 1
                    if окна.место - от >= РАЗМЕТКА_ЗА_РАЗ:
                        return {"итог": "дальше", "начало": окна.начало(),
                                "разведка": разведка.место() if разведка is not None else 0}
                    continue
                if окна.испорчен or готов:
                    if n:
                        _сообщить("пачка", [с, n, окна.начало(), с_разведки,
                                            разведка.место() if разведка is not None else 0])
                    хвост = окна.хвост(размер)
                    return {"итог": "конец", "начало": окна.начало(), "заметки": [хвост] if хвост else [],
                            "разведка": разведка.место() if разведка is not None else 0}
                # Файл ещё растёт: неполную пачку не отдаём — разметка (и разведка) продолжится с её начала.
                return {"итог": "ждать", "начало": с, "разведка": с_разведки}
    finally:
        if разведка is not None:
            разведка.закрыть()


