@contextlib.contextmanager
def _без_сборщика_мусора() -> Iterator[None]:
    """В процессе-исполнителе — без циклического сборщика мусора: разбор и сшивка создают миллионы
    живущих до конца задачи объектов (сводки, поля, блоки), и сборщик обходил бы их снова и снова (до трети
    времени). Циклов у них нет — память освобождается подсчётом ссылок. В нитях сервера сборщик не трогаем:
    он общий на весь процесс."""
    import multiprocessing  # noqa: PLC0415
    свой_процесс = multiprocessing.parent_process() is not None
    был = gc.isenabled()
    if свой_процесс:
        gc.disable()
    try:
        yield
    finally:
        if свой_процесс and был:
            gc.enable()


