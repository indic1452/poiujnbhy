def _атомарно_pickle(путь: Path, объект: Any) -> None:
    записать_атомарно(путь, pickle.dumps(объект, pickle.HIGHEST_PROTOCOL))


def прочитать_затравку(папка: Path) -> dict[str, Any]:
    путь = Path(папка) / СШИВКА / "затравка.pkl"
    for _ in range(3):
        try:
            return pickle.loads(путь.read_bytes())  # noqa: S301 — файл пишет сам сервер
        except FileNotFoundError:
            return {}
        except (OSError, EOFError, pickle.UnpicklingError):
            time.sleep(0.05)
    return {}


def разобрать_пачку(папка: str, задание: dict[str, Any]) -> dict[str, Any]:
    """Исполнитель: пачка ``задание["пачка"]`` — в ``папка/пачки/NNNNNN`` (через ``.tmp`` и переименование).

    Каждый пакет разбирается с общим состоянием «затравки» (последнее сшитое) и тем, что пришло в этой
    пачке раньше него; действия с состоянием — в журнал пачки. Пакеты, которые возьмёт сборщик, — в
    «кандидаты» целиком (разобранными), у прочих — сводка и поля, как у разбора подряд."""
    with _без_сборщика_мусора():
        return _разобрать_пачку(Path(папка), задание)


def _разобрать_пачку(папка: Path, задание: dict[str, Any]) -> dict[str, Any]:
    цп = time.process_time()
    from .nakopitel import поля_накопителя  # noqa: PLC0415
