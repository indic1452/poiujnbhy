"""Разбор захвата пачками: файл любого размера — окнами, параллельно по ядрам, итог — как у разбора подряд.

Файл (pcap, pcapng, .sig/.dpo — сколько угодно гигабайт) делится на **пачки** по
границам записей; пачки разбираются параллельно исполнителями (``potok.ispolniteli``:
пул процессов с честной очередью между людьми), а **сшивка** по порядку собирает их
в хранилище записи (``hranilishe`` — того же вида, что у разбора подряд: страница,
отборы, выгрузки, объекты читают его как прежде) и копит статистику (``nakopitel``).
Память не растёт с размером файла: исполнитель держит одну пачку, сшивка — состояние
захвата и один блок сводок.

Что тянется от пакета к пакету, сшивка доводит так, что итог **ровно** равен разбору
всего файла одним куском:

* **общее состояние** (потоки из SDP, каналы FTP, вызовы SIP, шаблоны NetFlow/IPFIX,
  правило «ppp:mp» — ``obshee``): исполнитель разбирает пачку со своим состоянием
  («затравка» — последнее известное сшивке, плюс то, что пришло в самой пачке) и
  записывает действия каждого пакета; сшивка повторяет их над настоящим состоянием —
  итоги совпали, значит, разбор пакета тот же; нет — пакет разбирается заново;
* **сборка** (фрагменты IPv4, MP, сегменты SCCP, договорённость LCP — ``sborka``):
  пакеты, которые возьмёт сборщик, исполнитель отдаёт сшивке разобранными, и сшивка
  прогоняет их через те же сборщики по порядку — собранное на стыке пачек
  собирается так же, как внутри пачки;
* **статистика** копится сшивкой по порядку пакетов (из сводок и тех полей, что ей
  нужны, — ``nakopitel.поля_накопителя``).

Чтобы сшивке почти не приходилось разбирать заново, затравка исполнителя — свежая:
**разведка** (идёт вместе с разметкой, впереди разбора) разбирает только те пакеты,
что могут пополнить общее состояние (по меткам в байтах: SIP, SDP, команды и ответы
FTP), и пишет их записи состояния в журнал разведки; исполнитель пачки дополняет
затравку записями журнала до начала своей пачки. Разведка лишь подсказывает — верность
по-прежнему проверяет сшивка: пропущенный разведкой пакет стоит только повторного
разбора.

Блоки сводок и полей пачки сшивка дописывает в хранилище как есть (байт в байт);
изменившиеся у неё пакеты (собранные, разобранные заново) — новыми блоками, и запись
индекса такого пакета указывает на новый блок. Блоки не распаковываются и не
сжимаются заново, кроме сводок для статистики.

Ход разбора: **разметка** (задача пула) идёт по файлу окнами и шлёт границы пачек
(первые — маленькие: первые строки на экране через секунды); **ведущий** (в сервере,
лёгкий) ставит пачки в пул, держа их в работе не больше, чем позволяет место
человека в пуле, и сшивку — первой в очереди человека; пишет ход (``ход.json``:
пачек N из M, пакетов, скорость, осталось). Пауза снимает идущие пачки (их
разберут заново), стоп оставляет сшитое. Сшивка после каждой задачи кладёт своё
состояние на диск (``сшивка/``): после перезапуска сервера разбор продолжается с
последней сшитой пачки, готовые пачки не разбираются заново.
"""

