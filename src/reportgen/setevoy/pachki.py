class Ведущий:
    """Разбор одной записи пачками: ставит разметку, пачки и сшивку в пул, слушает их и пишет ход.

    Сам ничего тяжёлого не считает (живёт в процессе сервера): решает, что ставить в пул следующим,
    по событиям задач и раз в полсекунды (растёт ли загружаемый файл, не изменился ли файл по ссылке).
    """

    def __init__(self, папка: Path, пул: Any, *, владелец: Any, путь: Path, как: dict[str, Any] | None,
                 поколение: int, ссылка: dict[str, Any] | None = None, размер: dict[str, Any] | None = None,
                 при_конце: Callable[[Ведущий], None] | None = None):
        self.папка = Path(папка)
        self.пул = пул
        self.владелец = владелец
        self.путь = Path(путь)
        self.как = dict(как or {})
        self.поколение = поколение
        self.ссылка = ссылка
        self.размер = {**РАЗМЕР, **(размер or {})}
        self.при_конце = при_конце
        self._lock = threading.RLock()
        self.состояние = "в очереди"
        self.ошибка = ""
        self.пауза = False
        self.стоп = ""
        self.кончен = threading.Event()
        self._заново = False
        self._последняя_сшивка = False                       # после стопа: дописать статистику целиком
        self._всё_записано = False                           # на паузе статистика уже записана целиком
        self.готов = True                                     # файл больше не растёт
        self._прервана = ""                                   # загрузка встала: дочитать и кончить «прерван»
        self._данные_были = time.monotonic()
        self._размер_было = -1
        self._ждём_роста: int | None = None                  # размер файла, при котором разметка ждала данных
        self.разметка_задача: Any = None
        self.сшивка_задача: Any = None
        self.в_работе: dict[int, Any] = {}
        self.сделано: dict[int, int] = {}                     # пачка в работе → пакетов разобрано (по ходу)
        self.начато = time.time()
        self._точки: list[tuple[float, int, int]] = []
        self._ход_записан = 0.0
        self._план_записан = 0.0
        self._поток: threading.Thread | None = None
        self._загрузить()

    # -- состояние на диске --

    def _загрузить(self) -> None:
        план = прочитать_json(self.папка / ПАЧКИ / "план.json")
        if not план or план.get("поколение") != self.поколение:
            # Разбор с нуля: прежнее разобранное (другого поколения) — прочь.
            for имя in (ПАЧКИ, СШИВКА, "статистика"):
                shutil.rmtree(self.папка / имя, ignore_errors=True)
            убрать(self.папка)
            with contextlib.suppress(OSError):
                (self.папка / "шаблоны.json").unlink()
            план = {"поколение": self.поколение, "формат": "", "заметки": [], "пачки": [], "дальше": None,
                    "итог": "идёт", "размер": self.размер}
        self.размер = {**РАЗМЕР, **(план.get("размер") or self.размер)}
        self.план = план
        кратко = прочитать_json(self.папка / СШИВКА / "ход.json") or {}
        if кратко.get("поколение") != self.поколение:
            кратко = {}
        with contextlib.suppress(OSError):
            (self.папка / СШИВКА / СТОП).unlink()
        self.сшито = int(кратко.get("сшито", 0))
        self._затравка_сшито = self.сшито                     # сколько пачек покрывает затравка на диске
        self.пакетов = int(кратко.get("пакетов", 0))
        self.прочитано = int(кратко.get("прочитано", 0))
        self.рев = int(кратко.get("рев", 0))
        self.mp = кратко.get("mp_короткие_с")
        (self.папка / ПАЧКИ).mkdir(parents=True, exist_ok=True)
        self.готовые: set[int] = set()
        for п in (self.папка / ПАЧКИ).iterdir():
            if not п.is_dir():
                continue
            if п.name.endswith(".tmp") or not п.name.isdigit() or int(п.name) < self.сшито:
                shutil.rmtree(п, ignore_errors=True)
            elif int(п.name) < len(план["пачки"]) and пачка_готова(self.папка, int(п.name), self.поколение):
                self.готовые.add(int(п.name))

    def _записать_план(self, *, сразу: bool = False) -> None:
        if not сразу and time.monotonic() - self._план_записан < 1.0:
            return
        self._план_записан = time.monotonic()
        with contextlib.suppress(OSError):
            записать_атомарно(self.папка / ПАЧКИ / "план.json", json.dumps(self.план, ensure_ascii=False))

    # -- снаружи --

    def запустить(self) -> None:
        self._осмотреться(True)                                # идёт ли загрузка — до первой разметки
        self._писать_ход(сразу=True)
        self._поток = threading.Thread(target=self._цикл, daemon=True, name="reportgen-pakety-vedushiy")
        self._поток.start()
        self._шаг()

    def жив(self) -> bool:
        return not self.кончен.is_set()

    def команда(self, команда: str) -> bool:
        """Пауза (идущие пачки снимаются — их разберут заново), продолжить или стоп (сшитое остаётся)."""
        if команда == "стоп":
            self.остановить("остановлен по команде", ждать=0)
            return True
        with self._lock:
            if self.кончен.is_set() or self.стоп:
                return False
            if команда == "пауза" and not self.пауза:
                self.пауза = True
                self._всё_записано = False
                for задача in [*self.в_работе.values(), self.разметка_задача]:
                    if задача is not None:
                        self.пул.отменить(задача)
            elif команда == "продолжить":
                self.пауза = False
            self._обновить_состояние()
            self._писать_ход(сразу=True)
        self._шаг()
        return True

    def остановить(self, почему: str = "остановлен", *, ждать: float = 10.0, ход: bool = True) -> None:
        """Остановить разбор. ``ход=True`` (стоп человека): идущие пачки снимаются, сшивка заканчивает на
        границе пачки, статистика сшитого дописывается целиком — и разбор кончается «остановлен» (не
        дожидаясь: ``ждать=0``). ``ход=False`` — запись разбирается заново, удаляется или сервер выключается:
        сшивка снимается (её несохранённое начнётся заново), ход не пишется; ждём до ``ждать`` секунд, пока
        задачи отпустят файлы."""
        with self._lock:
            if self.кончен.is_set():
                return
            if self.стоп and ход:
                return
            self.стоп = почему
            self._заново = not ход
            for задача in [*self.в_работе.values(), self.разметка_задача]:
                if задача is not None:
                    self.пул.отменить(задача)
            сшивка = self.сшивка_задача
            if сшивка is not None:
                with contextlib.suppress(OSError):
                    (self.папка / СШИВКА).mkdir(exist_ok=True)
                    (self.папка / СШИВКА / СТОП).write_bytes(b"1")
            if ход:
                self._последняя_сшивка = True
                self._обновить_состояние()
                self._писать_ход(сразу=True)
        if ход:
            self._шаг()
            if ждать:
                self.кончен.wait(ждать)
            return
        конец = time.monotonic() + ждать
        for задача in [сшивка, *list(self.в_работе.values()), self.разметка_задача]:
            if задача is None:
                continue
            with contextlib.suppress(BaseException):
                задача.ждать(max(0.0, конец - time.monotonic()))
        if сшивка is not None and not сшивка.готова():
            self.пул.отменить(сшивка)
            with contextlib.suppress(BaseException):
                сшивка.ждать(max(0.5, конец - time.monotonic()))
        with self._lock:
            if not self.кончен.is_set():
                self._кончить("остановлен", почему, ход=False)

    def ждать(self, секунд: float | None = None) -> bool:
        return self.кончен.wait(секунд)

    # -- цикл и шаги --

    def _цикл(self) -> None:
        проверено = 0.0
        while not self.кончен.wait(0.5):
            try:
                ссылку = time.monotonic() - проверено > 2.0
                self._осмотреться(ссылку)
                if ссылку:
                    проверено = time.monotonic()
                self._шаг()
            except Exception as ошибка:  # noqa: BLE001 — ведущий не роняет сервер
                with self._lock:
                    if not self.кончен.is_set():
                        self._кончить("ошибка", f"{type(ошибка).__name__}: {ошибка}")

    def _осмотреться(self, ссылку: bool) -> None:
        """Загрузка (растёт ли файл, кончилась ли), поколение записи, файл по ссылке не изменился ли."""
        мета = прочитать_json(self.папка / "захват.json", {}) or {}
        if мета.get("поколение", self.поколение) != self.поколение:
            self.остановить("запись разбирается заново", ждать=0, ход=False)
            return
        загрузка = мета.get("загрузка") or {}
        with self._lock:
            self.готов = not загрузка.get("идёт") or bool(self._прервана)
            try:
                размер = self.путь.stat().st_size
            except OSError:
                размер = 0
            if размер != self._размер_было:
                self._размер_было, self._данные_были = размер, time.monotonic()
            elif not self.готов and time.monotonic() - self._данные_были > ЖДАТЬ_ЗАГРУЗКУ:
                # Загрузка встала: разобрать то, что пришло, и кончить «прерван».
                self._прервана = "загрузка прервалась: новых данных нет больше 30 минут — разобрано то, что пришло"
                self.готов = True
        if ссылку and self.ссылка is not None:
            from ..fayly_ssylki import проверить_отпечаток  # noqa: PLC0415
            беда = проверить_отпечаток(self.путь, self.ссылка)
            if беда:
                self.остановить(беда, ждать=0)

    def _шаг(self) -> None:
        with self._lock:
            if self.кончен.is_set() or self._заново:
                return
            if not self.стоп:
                self._разметка()
                if not self.пауза:
                    self._пачки()
            self._сшивка()
            self._обновить_состояние()
            self._писать_ход()

    def _разметка(self) -> None:
        if self.пауза or self.план["итог"] == "конец" or self.разметка_задача is not None:
            return
        if not self.готов:
            размер = self._размер_было
            if self._ждём_роста is not None and размер <= self._ждём_роста:
                return                                        # разметка уже ждала — данных не прибавилось
        готов = self.готов
        self.разметка_задача = self.пул.подать(
            разметить, str(self.путь), {"начало": self.план["дальше"], "пачка": len(self.план["пачки"]), "готов": готов,
                                        "размер": self.размер, "папка": str(self.папка), "как": self.как,
                                        "разведка": int(self.план.get("разведка") or 0)},
            владелец=self.владелец, имя="разметка пачек", первой=True,
            при_сообщении=self._сообщение_разметки, при_конце=lambda з, г=готов: self._разметка_кончилась(з, г))

    def _мест(self) -> int:
        return max(1, int(getattr(self.пул, "на_владельца", 1) or 1))

    def _пачки(self) -> None:
        мест = self._мест()
        # В очереди человека — на одну пачку больше мест: освободилось место — следующая уже ждёт.
        можно = мест + 1 - (1 if self.сшивка_задача is not None else 0)
        if len(self.готовые) >= ГОТОВЫХ_НА_МЕСТО * мест:
            return
        k = self.сшито
        пачки = self.план["пачки"]
        while len(self.в_работе) < можно and k < len(пачки):
            if k not in self.готовые and k not in self.в_работе:
                начало, пакетов, дальше = пачки[k][:3]
                # Затравку дополнят записи разведки — с начала первой несшитой пачки до начала этой.
                z = min(self._затравка_сшито, k)
                разведка = пачки[z][3] if len(пачки[z]) > 3 else None
                self.в_работе[k] = self.пул.подать(
                    разобрать_пачку, str(self.папка),
                    {"пачка": k, "путь": str(self.путь), "начало": начало, "пакетов": пакетов,
                     "конец": дальше["место"], "как": self.как, "поколение": self.поколение, "разведка": разведка},
                    владелец=self.владелец, имя=f"пачка {k}",
                    при_сообщении=lambda вид, д, k=k: self._ход_пачки(k, вид, д),
                    при_конце=lambda з, k=k: self._пачка_кончилась(k, з))
            k += 1

    def _сшивка(self) -> None:
        if self.сшивка_задача is not None:
            return
        всего = len(self.план["пачки"])
        всё = False
        if self.сшито in self.готовые and not self.стоп:
            до = self.сшито
            while до + 1 in self.готовые:
                до += 1
            конец = self.план["итог"] == "конец" and до == всего - 1
        elif self.план["итог"] == "конец" and self.сшито >= всего and not self.стоп:
            до, конец = self.сшито - 1, True                   # всё сшито — дописать статистику целиком и кончить
        elif self.стоп and self._последняя_сшивка:
            до, конец, всё = self.сшито - 1, False, True       # стоп: статистику сшитого — целиком
        elif self.пауза and not self.в_работе and not self._всё_записано and self.пакетов:
            до, конец, всё = self.сшито - 1, False, True       # пауза: статистику сшитого — целиком
        else:
            return
        задание = {"до": до, "от": self.сшито, "конец": конец, "всё": всё, "путь": str(self.путь), "как": self.как,
                   "поколение": self.поколение}
        self.сшивка_задача = self.пул.подать(
            сшить, str(self.папка), задание, владелец=self.владелец, имя="сшивка пачек", первой=True,
            при_сообщении=self._сообщение_сшивки, при_конце=lambda з, з_=задание: self._сшивка_кончилась(з, з_))

    # -- события задач (из нитей пула) --

    def _сообщение_разметки(self, вид: str, данные: Any) -> None:
        with self._lock:
            if вид == "вид":
                self.план.update(формат=данные["формат"], заметки=list(данные["заметки"]), дальше=данные["начало"],
                                 разведка=0)
            elif вид == "пачка":
                начало, пакетов, дальше, с_разведки, д_разведки = данные
                # Пачка — продолжение размеченного (повтор после снятой разметки не дублирует пачек).
                if начало["номер"] == (self.план["дальше"] or {}).get("номер", 1):
                    self.план["пачки"].append([начало, пакетов, дальше, с_разведки])
                    self.план["дальше"], self.план["разведка"] = дальше, д_разведки
            self._записать_план()
        self._шаг()

    def _разметка_кончилась(self, задача: Any, готов: bool) -> None:
        with self._lock:
            self.разметка_задача = None
            if задача.состояние == "готово":
                итог = задача.итог
                if итог.get("начало") is not None and итог["итог"] != "ждать":
                    self.план["дальше"], self.план["разведка"] = итог["начало"], итог.get("разведка", 0)
                if итог["итог"] == "конец":
                    self.план["итог"] = "конец"
                    self.план["заметки"] = [*self.план["заметки"], *итог.get("заметки", [])]
                    self._ждём_роста = None
                elif итог["итог"] == "ждать":
                    self._ждём_роста = self._размер_было
                self._записать_план(сразу=True)
            elif задача.состояние == "ошибка" and not self.стоп:
                ошибка = задача.ошибка
                self._кончить("ошибка", str(ошибка) if isinstance(ошибка, ValueError)
                              else f"{type(ошибка).__name__}: {ошибка}")
                return
        self._шаг()

    def _ход_пачки(self, k: int, вид: str, данные: Any) -> None:
        if вид == "ход":
            self.сделано[k] = int(данные)

    def _пачка_кончилась(self, k: int, задача: Any) -> None:
        with self._lock:
            self.в_работе.pop(k, None)
            self.сделано.pop(k, None)
            if задача.состояние == "готово":
                self.готовые.add(k)
            elif задача.состояние == "ошибка" and not self.стоп:
                self._кончить("ошибка", f"пачка {k}: {type(задача.ошибка).__name__}: {задача.ошибка}")
                return
        self._шаг()

    def _сообщение_сшивки(self, вид: str, данные: Any) -> None:
        if вид == "сшито":
            with self._lock:
                self._учесть_сшитое(данные)
                self._обновить_состояние()
                self._писать_ход()

    def _учесть_сшитое(self, кратко: dict[str, Any]) -> None:
        for k in range(self.сшито, int(кратко["сшито"])):
            self.готовые.discard(k)
        self.сшито, self.пакетов, self.прочитано = int(кратко["сшито"]), int(кратко["пакетов"]), int(кратко["прочитано"])
        self.рев, self.mp = int(кратко.get("рев", self.рев)), кратко.get("mp_короткие_с")

    def _сшивка_кончилась(self, задача: Any, задание: dict[str, Any]) -> None:
        with self._lock:
            self.сшивка_задача = None
            if задача.состояние == "готово":
                self._учесть_сшитое(задача.итог)
                self._затравка_сшито = self.сшито
                if задание["всё"]:
                    self._всё_записано = True
                if self.стоп:
                    if задание["всё"] or not self._последняя_сшивка:
                        self._последняя_сшивка = False
                        if not self._заново:
                            self._кончить("остановлен", self.стоп)
                        return
                elif задание["конец"] and self.план["итог"] == "конец" and self.сшито >= len(self.план["пачки"]):
                    self._кончить("прерван" if self._прервана else "готово", self._прервана)
                    return
            elif задача.состояние == "ошибка" and not self._заново:
                self._кончить("ошибка", f"сшивка: {type(задача.ошибка).__name__}: {задача.ошибка}")
                return
            elif self.стоп and not self._заново:
                self._последняя_сшивка = True                   # сшивку сняли силой — статистику дописать новой
        self._шаг()

    # -- ход --

    def _обновить_состояние(self) -> None:
        if self.кончен.is_set():
            return
        if self.стоп:
            self.состояние = "останавливается"
            return
        if self.пауза:
            self.состояние = "пауза"
            return
        задачи = [з for з in (*self.в_работе.values(), self.разметка_задача, self.сшивка_задача) if з is not None]
        if any(з.состояние == "идёт" for з in задачи):
            self.состояние = "идёт"
        elif задачи:
            self.состояние = "в очереди" if not self.пакетов else "идёт"
        elif not self.готов:
            self.состояние = "ждёт данных"

    def _обработано(self) -> tuple[int, int]:
        """Пакетов и байт файла, разобранных к этому мигу (сшитые, готовые и доля идущих пачек)."""
        пакетов, байт = self.пакетов, self.прочитано
        for k in list(self.готовые) + list(self.сделано):
            if k >= len(self.план["пачки"]) or k < self.сшито:
                continue
            начало, n, дальше = self.план["пачки"][k][:3]
            доля = 1.0 if k in self.готовые else min(1.0, self.сделано.get(k, 0) / max(1, n))
            пакетов += int(n * доля)
            байт += int((дальше["место"] - начало["место"]) * доля)
        return пакетов, байт

    def ход(self) -> dict[str, Any]:
        try:
            всего_байт = self.путь.stat().st_size
        except OSError:
            всего_байт = 0
        мета = прочитать_json(self.папка / "захват.json", {}) or {}
        всего_байт = max(всего_байт, int((мета.get("загрузка") or {}).get("всего") or 0))
        пакетов, байт = self._обработано()
        сейчас = time.monotonic()
        self._точки.append((сейчас, пакетов, байт))
        while len(self._точки) > 2 and сейчас - self._точки[0][0] > ОКНО_СКОРОСТИ:
            self._точки.pop(0)
        t0, п0, б0 = self._точки[0]
        прошло = сейчас - t0
        скорость_п = (пакетов - п0) / прошло if прошло > 0 else 0.0
        скорость_б = (байт - б0) / прошло if прошло > 0 else 0.0
        идёт = self.состояние == "идёт"
        пачек = len(self.план["пачки"])
        if self.план["итог"] != "конец" and пачек:
            размечено = self.план["пачки"][-1][2]["место"]
            пачек = max(пачек, round(пачек * всего_байт / max(1, размечено)))
        ход = {"поколение": self.поколение, "состояние": self.состояние, "разобрано": self.пакетов,
               "прочитано": байт, "всего_байт": всего_байт, "скорость_пакетов": round(скорость_п, 1),
               "скорость_байт": round(скорость_б), "формат": self.план["формат"], "заметки": self.план["заметки"][-50:],
               "ошибка": self.ошибка, "начато": self.начато, "рев": self.рев,
               "осталось": round(max(0, всего_байт - байт) / скорость_б, 1) if идёт and скорость_б > 0 else None,
               "пачки": {"сшито": self.сшито, "всего": пачек, "точно": self.план["итог"] == "конец",
                         "идут": len(self.в_работе), "разобрано": пакетов}}
        if self.mp is not None:
            ход["mp_короткие_с"] = self.mp
        if self.кончен.is_set() or self.состояние in КОНЕЦ:
            ход["закончено"] = time.time()
            ход["осталось"] = None
        return ход

    def _писать_ход(self, *, сразу: bool = False) -> None:
        if self._заново:
            return
        if not сразу and time.monotonic() - self._ход_записан < ХОД_КАЖДЫЕ:
            return
        self._ход_записан = time.monotonic()
        with contextlib.suppress(OSError):
            записать_атомарно(self.папка / "ход.json", json.dumps(self.ход(), ensure_ascii=False))

    def _кончить(self, состояние: str, ошибка: str = "", *, ход: bool = True) -> None:
        self.состояние = состояние
        self.ошибка = ошибка if состояние != "готово" else ""
        for задача in [*self.в_работе.values(), self.разметка_задача]:
            if задача is not None:
                self.пул.отменить(задача)
        with contextlib.suppress(OSError):
            (self.папка / СШИВКА / СТОП).unlink()
        self._записать_план(сразу=True)
        if not self._заново:
            # Разбор кончен: несшитые пачки и состояние сшивки больше не нужны (продолжать нечего).
            for п in (self.папка / ПАЧКИ).glob("[0-9]*"):
                shutil.rmtree(п, ignore_errors=True)
            shutil.rmtree(self.папка / СШИВКА, ignore_errors=True)
        # Ход — до «кончен»: кто дождался конца, читает уже итоговый ход.
        if ход and not self._заново:
            self._писать_ход(сразу=True)
        self.кончен.set()
        if self.при_конце is not None:
            with contextlib.suppress(Exception):
                self.при_конце(self)
