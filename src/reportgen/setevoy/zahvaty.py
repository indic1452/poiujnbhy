#: Сколько записей хранить на пользователя.
ХРАНИТЬ = 30
#: Сколько отборов (фильтров) держать у записи и сколько из них — идущими следом за разбором.
ОТБОРОВ = 8
ОТБОРОВ_ИДУТ = 3
#: Файл меньше — разбирается потоком в сервере (процесс запускается дольше).
ПРОЦЕССОМ_ОТ = 8 << 20
#: Отбор потоком, пока пакетов меньше; больше — процессом.
ОТБОР_ПРОЦЕССОМ_ОТ = 50_000
#: Объекты (сборка потоков) — по первым пакетам отбора, пока их нагрузка не больше (сборка держит
#: потоки в памяти сервера; страница говорит, по скольким пакетам собрано).
ОБЪЕКТЫ_БАЙТ_ДО = 256 << 20
ОБЪЕКТЫ_ПАКЕТОВ_ДО = 2_000_000
ИД = "[0-9]{8}-[0-9]{6}-[0-9a-f]{6}"


class ОшибкаЗагрузки(ValueError):
    pass


class Отбор:
    """Пакеты записи под фильтр: номера (с 0), сколько проверено, статистика отобранных."""

    def __init__(self, захваты: Захваты, ид: str, фильтр: str, папка: Path | None):
        self.з, self.ид, self.фильтр, self.папка = захваты, ид, фильтр, папка
        self.х = захваты.хранилище(ид)

    def ход(self) -> dict[str, Any]:
        разбор = self.з.прочитать(self.ид)
        всего = self.х.число()
        if self.папка is None:
            готово = разбор["состояние"] in КОНЕЦ and всего >= разбор.get("разобрано", 0)
            return {"готово": готово, "проверено": всего, "отобрано": всего, "всего": всего,
                    "рев": разбор.get("рев", 0), "состояние": разбор["состояние"]}
        ход = прочитать_json(self.папка / "ход.json", {}) or {}
        отобрано = self.число()
        готово = ход.get("состояние") == "готово" and разбор["состояние"] in КОНЕЦ
        return {"готово": готово, "проверено": min(ход.get("проверено", 0), всего), "отобрано": отобрано,
                "всего": всего, "рев": ход.get("рев", 0), "состояние": ход.get("состояние", "в очереди"),
                "ошибка": ход.get("ошибка", "")}

    def число(self) -> int:
        if self.папка is None:
            return self.х.число()
        try:
            return (self.папка / "номера.u32").stat().st_size // 4
        except OSError:
            return 0

    def номера(self, от: int = 0, до: int | None = None) -> np.ndarray:
        """Номера отобранных пакетов (с 0) с ``от`` по ``до`` (по порядку отбора)."""
        n = self.число()
        до = n if до is None else min(до, n)
        от = max(0, от)
        if до <= от:
            return np.zeros(0, dtype=np.int64)
        if self.папка is None:
            return np.arange(от, до, dtype=np.int64)
        with open(self.папка / "номера.u32", "rb") as ф:
            ф.seek(от * 4)
            сырые = ф.read((до - от) * 4)
        return np.frombuffer(сырые, dtype="<u4").astype(np.int64)

    def снимок(self, раздел: str, по_умолчанию: Any = None) -> Any:
        папка = self.папка or (self.з.папка / self.ид)
        return прочитать_json(папка / "статистика" / f"{раздел}.json", по_умолчанию)

    def сводки(self, от: int = 0, до: int | None = None) -> list[dict[str, Any]]:
        return self.х.сводки_по(self.номера(от, до))

    def ряд(self, вид: str, до: int | None = None) -> Ряд:
        return Ряд(self.х, вид, None if self.папка is None and до is None else self.номера(0, до),
                   число=self.х.число() if self.папка is None and до is None else None)


class Захваты:
    def __init__(self, папка: Path, *, разборов: int = 0, отборов: int = 0, процессы: bool = True,
                 процессом_от: int = ПРОЦЕССОМ_ОТ):
        self.папка = Path(папка)
        self.процессом_от = процессом_от
        self.диспетчер = Диспетчер(разборов=разборов, отборов=отборов, процессы=процессы)
        self._lock = threading.Lock()
        self._замки: dict[str, threading.Lock] = {}
        self._хранилища: OrderedDict[tuple[str, int], Хранилище] = OrderedDict()
        self._объекты: OrderedDict[tuple, dict[str, Any]] = OrderedDict()
        self._объекты_замок = threading.Semaphore(2)
        self._возобновить()

    def _замок(self, ид: str) -> threading.Lock:
        with self._lock:
            return self._замки.setdefault(ид, threading.Lock())

    # -- приём ---------------------------------------------------------------------

    def создать(self, *, владелец: int, имя: str, данные: bytes = b"", от: str = "", путь: Path | None = None,
                как: dict[str, Any] | None = None, источник: dict[str, Any] | None = None,
                загрузка: int | None = None) -> str:
        """Новая запись из байтов, из файла на диске (``путь`` — копируется потоком, не через память), из
        идущего приёма с сети (``источник`` = {"вид": "захват", "папка": …}) или под загрузку кусками
        (``загрузка`` — сколько байт придёт; разбор начинается с первого куска). ``как`` — правила «разбирать
        как» с самого начала (в том числе «Декодировать как» человека)."""
        ид = time.strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)
        папка = self.папка / ид
        папка.mkdir(parents=True, exist_ok=True)
        if путь is not None:
            shutil.copyfile(путь, папка / "исходник")
        else:
            (папка / "исходник").write_bytes(данные)
        мета: dict[str, Any] = {"ид": ид, "владелец": владелец, "имя": имя, "от": от, "создано": time.time(),
                                "байт": (папка / "исходник").stat().st_size, "поколение": 1,
                                **({"как": как} if как else {})}
        if источник is not None:
            мета["источник"] = источник
        if загрузка is not None:
            мета["загрузка"] = {"идёт": True, "принято": 0, "всего": int(загрузка), "обновлено": time.time()}
            мета["байт"] = int(загрузка)
        self._записать_мету(ид, мета)
        self._поставить(ид, мета)
        self._прибрать(владелец)
        return ид

    def дописать(self, ид: str, место: int, данные: bytes) -> int:
        """Кусок загрузки по месту ``место``; вернуть, сколько принято. Место не там, где кончается принятое,
        — ОшибкаЗагрузки (страница повторит с верного места). Повтор уже принятого куска — не ошибка."""
        with self._замок(ид):
            мета = self._мета(ид)
            загрузка = мета.get("загрузка") or {}
            if not загрузка.get("идёт"):
                raise ОшибкаЗагрузки("загрузка уже закончена")
            путь = self.папка / ид / "исходник"
            принято = путь.stat().st_size
            if место + len(данные) <= принято and место < принято:
                return принято                               # повтор (ответ на прежний кусок потерялся)
            if место != принято:
                raise ОшибкаЗагрузки(f"ждём кусок с места {принято}")
            if принято + len(данные) > загрузка["всего"]:
                raise ОшибкаЗагрузки("кусок выходит за объявленный размер файла")
            with open(путь, "ab") as ф:
                ф.write(данные)
            принято += len(данные)
            загрузка.update(принято=принято, обновлено=time.time())
            self._записать_мету(ид, мета)
            return принято

    def закончить_загрузку(self, ид: str) -> dict[str, Any]:
        with self._замок(ид):
            мета = self._мета(ид)
            загрузка = мета.get("загрузка") or {}
            принято = (self.папка / ид / "исходник").stat().st_size
            if загрузка.get("идёт"):
                if принято != загрузка.get("всего"):
                    raise ОшибкаЗагрузки(f"принято {принято} байт из {загрузка.get('всего')}")
                загрузка.update(идёт=False, принято=принято, обновлено=time.time(), закончено=time.time())
                мета["байт"] = принято
                self._записать_мету(ид, мета)
        return self.прочитать(ид)

    def _поставить(self, ид: str, мета: dict[str, Any]) -> None:
        источник = мета.get("источник") or {}
        размер = (мета.get("загрузка") or {}).get("всего") or мета.get("байт", 0)
        процессом = источник.get("вид") == "захват" or размер >= self.процессом_от
        папка = self.папка / ид
        with contextlib.suppress(OSError):
            (папка / "ход.json").unlink()
        self.диспетчер.поставить(Работа("разбор", str(папка), мета.get("владелец", 0), [str(папка)],
                                        процессом=процессом, ход_файл=папка / "ход.json"))

    def разбирать_как(self, ид: str, правила: dict[str, str]) -> dict[str, str]:
        """Задать «разбирать как» и разобрать запись заново (в фоне, как при приёме)."""
        from .prilozh import проверить_как  # noqa: PLC0415 — круговой импорт
        правила = проверить_как(правила)
        with self._замок(ид):
            мета = self._мета(ид)
            if (мета.get("загрузка") or {}).get("идёт"):
                raise ValueError("файл ещё загружается — дождитесь конца загрузки")
            self.диспетчер.остановить(str(self.папка / ид), "разбирается заново")
            self._убрать_отборы(ид)
            мета.update(как=правила, поколение=мета.get("поколение", 1) + 1)
            self._записать_мету(ид, мета)
            self._забыть(ид)
            self._поставить(ид, мета)
        return правила

    def команда(self, ид: str, команда: str) -> bool:
        """Пауза, продолжить или стоп разбора (и отборов следом за ним)."""
        if команда not in ("пауза", "продолжить", "стоп"):
            raise ValueError("команда: пауза, продолжить или стоп")
        ключ = str(self.папка / ид)
        if команда == "стоп":
            if self.диспетчер.снять_из_очереди(ключ):
                self._записать_ход(ид, {"поколение": self._мета(ид).get("поколение", 1), "состояние": "остановлен",
                                        "разобрано": 0, "ошибка": "остановлен до начала разбора"})
            self.диспетчер.остановить(ключ, "остановлен по команде", ждать=10)
            with self._замок(ид):
                мета = self._мета(ид)
                загрузка = мета.get("загрузка") or {}
                if загрузка.get("идёт"):
                    загрузка.update(идёт=False, прервана=True, обновлено=time.time())
                    self._записать_мету(ид, мета)
            return True
        return self.диспетчер.команда(ключ, {"к": команда})

    # -- чтение --------------------------------------------------------------------

    def _мета(self, ид: str) -> dict[str, Any]:
        мета = прочитать_json(self.папка / ид / "захват.json")
        if мета is None:
            if (self.папка / ид / "состояние.json").exists():
                return self._перенести(ид)
            raise KeyError(ид)
        return мета

    def _перенести(self, ид: str) -> dict[str, Any]:
        """Запись прежнего вида (всё в состояние.json, индекс в памяти): мета — в захват.json, разбор — заново."""
        with self._замок(ид):
            старое = прочитать_json(self.папка / ид / "состояние.json", {}) or {}
            if (self.папка / ид / "захват.json").exists():
                return прочитать_json(self.папка / ид / "захват.json", {})
            мета = {к: старое[к] for к in ("ид", "владелец", "имя", "от", "создано", "байт", "как") if к in старое}
            мета["поколение"] = 1
            self._записать_мету(ид, мета)
            for имя in ("индекс.json", "сводки.jsonl", "поля.jsonl", "пакеты.bin", "состояние.json"):
                with contextlib.suppress(OSError):
                    (self.папка / ид / имя).unlink()
            self._поставить(ид, мета)
            return мета

    def прочитать(self, ид: str) -> dict[str, Any]:
        """Состояние записи: мета, ход загрузки и разбора (как одно целое для страницы)."""
        мета = self._мета(ид)
        ход = прочитать_json(self.папка / ид / "ход.json", {}) or {}
        ключ = str(self.папка / ид)
        if ход.get("поколение") != мета.get("поколение"):
            ход = {}
        место = self.диспетчер.в_очереди(ключ)
        итог = dict(мета)
        итог.update({к: з for к, з in ход.items() if к != "поколение"})
        if not ход:
            итог.update(состояние="в очереди" if место else "идёт" if self.диспетчер.идёт(ключ) else "ждёт",
                        разобрано=0)
        elif ход.get("состояние") in ИДУТ and not self.диспетчер.идёт(ключ) and not место:
            журнал = ""
            with contextlib.suppress(OSError):
                журнал = (self.папка / ид / "журнал.txt").read_text(encoding="utf-8", errors="replace")[-600:].strip()
            итог.update(состояние="прерван", ошибка="разбор прервался" + (f": {журнал}" if журнал else ""))
        итог["очередь"] = место
        итог["пакетов"] = итог.get("разобрано", 0)
        итог.setdefault("формат", "")
        итог.setdefault("заметки", [])
        итог.setdefault("ошибка", "")
        return итог

    def список(self, владелец: int) -> list[dict[str, Any]]:
        if not self.папка.exists():
            return []
        итог = []
        for папка in sorted(self.папка.iterdir(), reverse=True):
            if not папка.is_dir() or папка.name == "_":
                continue
            мета = прочитать_json(папка / "захват.json") or прочитать_json(папка / "состояние.json")
            if мета and мета.get("владелец") == владелец:
                with contextlib.suppress(KeyError):
                    итог.append(self.прочитать(папка.name))
        return итог

    def хранилище(self, ид: str) -> Хранилище:
        поколение = self._мета(ид).get("поколение", 1)
        ключ = (ид, поколение)
        with self._lock:
            х = self._хранилища.get(ключ)
            if х is None:
                х = self._хранилища[ключ] = Хранилище(self.папка / ид)
                while len(self._хранилища) > 16:
                    self._хранилища.popitem(last=False)
            else:
                self._хранилища.move_to_end(ключ)
            return х

    def _забыть(self, ид: str) -> None:
        with self._lock:
            for ключ in [к for к in self._хранилища if к[0] == ид]:
                del self._хранилища[ключ]
            for ключ in [к for к in self._объекты if к[0] == ид]:
                del self._объекты[ключ]

    def дождаться(self, ид: str, секунд: float = 60.0) -> dict[str, Any]:
        """Ждать конца разбора (тесты, выгрузки целиком)."""
        конец = time.monotonic() + секунд
        while True:
            с = self.прочитать(ид)
            if с["состояние"] in КОНЕЦ or time.monotonic() > конец:
                return с
            time.sleep(0.02)

    # -- отборы ----------------------------------------------------------------------

    def отбор(self, ид: str, фильтр: str, *, ждать: float = 0.0) -> Отбор:
        """Отбор по фильтру (пустой — все пакеты): идёт следом за разбором, ``ждать`` — сколько секунд ждать
        его конца (маленькие записи отбираются за доли секунды — страница сразу видит итог)."""
        фильтр = (фильтр or "").strip()
        if not фильтр:
            return Отбор(self, ид, "", None)
        from .filtr import собрать  # noqa: PLC0415
        собрать(фильтр)                                  # ошибка фильтра — сразу, до работы
        мета = self._мета(ид)
        поколение = мета.get("поколение", 1)
        ключ = hashlib.sha1(фильтр.encode("utf-8")).hexdigest()[:16]
        папка = self.папка / ид / "отборы" / ключ
        работа = str(папка)
        with self._замок(ид):
            ход = прочитать_json(папка / "ход.json", {}) or {}
            годен = ход.get("поколение") == поколение and (
                ход.get("состояние") == "готово" or self.диспетчер.идёт(работа)
                or self.диспетчер.в_очереди(работа) is not None)
            if not годен:
                self.диспетчер.остановить(работа, "отбор заново")
                shutil.rmtree(папка, ignore_errors=True)
                папка.mkdir(parents=True, exist_ok=True)
                (папка / "фильтр.txt").write_text(фильтр, encoding="utf-8")
                (папка / "номера.u32").write_bytes(b"")
                записать_атомарно(папка / "ход.json", json.dumps({"поколение": поколение, "состояние": "в очереди",
                                                                  "проверено": 0, "отобрано": 0}))
                процессом = (self.хранилище(ид).число() >= ОТБОР_ПРОЦЕССОМ_ОТ
                             or (мета.get("источник") or {}).get("вид") == "захват"
                             or ((мета.get("загрузка") or {}).get("всего") or мета.get("байт", 0)) >= self.процессом_от)
                self.диспетчер.поставить(Работа("отбор", работа, мета.get("владелец", 0),
                                                [str(self.папка / ид), работа], процессом=процессом,
                                                ход_файл=папка / "ход.json"))
            with contextlib.suppress(OSError):
                папка.touch()
                (папка / "фильтр.txt").touch()
            self._прибрать_отборы(ид, ключ)
        отбор = Отбор(self, ид, фильтр, папка)
        if ждать > 0:
            конец = time.monotonic() + ждать
            while not отбор.ход()["готово"] and time.monotonic() < конец:
                if отбор.ход().get("состояние") in ("ошибка", "остановлен"):
                    break
                time.sleep(0.02)
        return отбор

    def _прибрать_отборы(self, ид: str, свой: str) -> None:
        корень = self.папка / ид / "отборы"
        if not корень.is_dir():
            return
        отборы = sorted((п for п in корень.iterdir() if п.is_dir()),
                        key=lambda п: (п / "фильтр.txt").stat().st_mtime if (п / "фильтр.txt").exists() else 0,
                        reverse=True)
        идущих = 0
        for i, п in enumerate(отборы):
            работа = str(п)
            if п.name == свой:
                continue
            идёт = self.диспетчер.идёт(работа) or self.диспетчер.в_очереди(работа) is not None
            if i >= ОТБОРОВ:
                self.диспетчер.остановить(работа, "отбор вытеснен новыми")
                shutil.rmtree(п, ignore_errors=True)
            elif идёт:
                идущих += 1
                if идущих >= ОТБОРОВ_ИДУТ:
                    self.диспетчер.остановить(работа, "отбор вытеснен новыми")

    def _убрать_отборы(self, ид: str) -> None:
        корень = self.папка / ид / "отборы"
        if корень.is_dir():
            for п in корень.iterdir():
                self.диспетчер.остановить(str(п), "запись разбирается заново")
            shutil.rmtree(корень, ignore_errors=True)

    def отобрать(self, ид: str, фильтр: str) -> list[int]:
        """Номера (с 0) пакетов под фильтр — все, по законченному разбору (ждёт его и отбора)."""
        self.дождаться(ид, 3600)
        отбор = self.отбор(ид, фильтр, ждать=3600)
        return отбор.номера().tolist()

