"""Захваты для страницы «Пакеты»: приём, разбор в фоне, хранение, выборки.

Каждый захват — папка: исходный файл, пакеты подряд (пакеты.bin) с
индексом, сводки для списка и плоские поля для фильтров (по строке JSON на
пакет). Разбор идёт в фоновом потоке, страница видит, сколько разобрано.
Подробный разбор одного пакета (дерево полей) не хранится — он строится
заново по запросу: это доли миллисекунды, а хранить его для сотни тысяч
пакетов — сотни мегабайт.

IPv4, разрезанный на фрагменты, собирается: к последнему фрагменту
добавляется разбор собранного пакета (уровни «собранный …»), а его байты
лежат отдельно — их показывает шестнадцатеричный дамп. Так же собираются
фрагменты многоканального PPP (MP, RFC 1990): по классу и номерам от
фрагмента с B до фрагмента с E подряд; если в захвате договорены короткие
номера (Configure-Ack LCP с опцией 18), дальше заголовки MP читаются короткими.
Сегменты SCCP (XUDT с параметром сегментации) собираются в данные пользователя и
разбираются как TCAP (канал «TCAP»).
"""

from __future__ import annotations

import json
import secrets
import struct
import threading
import time
from collections import OrderedDict
from pathlib import Path
from typing import Any

from .chtenie import прочитать_захват
from .filtr import нужны_байты, собрать
from .pole import Пакет, сумма16
from .razbor import разобрать_пакет

#: Сколько захватов хранить на пользователя.
ХРАНИТЬ = 30
#: Поля, которые в фильтр не берём: длинные и бесполезные для отбора.
БЕЗ_ФИЛЬТРА = {"data.data", "tls.handshake.random", "radius.authenticator", "tcp.options"}
#: Сколько захватов держать разобранными в памяти (для фильтров и статистики).
В_ПАМЯТИ = 2


def _сводка(п: Пакет, поля: dict[str, list[Any]]) -> dict[str, Any]:
    с = п.сводка()
    с["порт_от"], с["порт_к"] = п.порт_от, п.порт_к
    if "eth.src" in поля and "eth.dst" in поля:
        с["mac"] = [поля["eth.src"][0], поля["eth.dst"][0]]
    if "tcp.seq_raw" in поля:
        с["seq"] = поля["tcp.seq_raw"][-1]
    if п.нагрузка is not None:
        с["нагр"] = [п.нагрузка_смещение, len(п.нагрузка)]
    return с


def _для_фильтра(поля: dict[str, list[Any]]) -> dict[str, list[Any]]:
    итог = {}
    for к, значения in поля.items():
        if к in БЕЗ_ФИЛЬТРА:
            continue
        итог[к] = [з if isinstance(з, (int, float, bool)) or з is None else str(з)[:200] for з in значения]
    return итог


class Сборщик:
    """Сборка фрагментов IPv4 по (источник, получатель, id, протокол)."""

    def __init__(self):
        self.куски: dict[tuple, dict[str, Any]] = {}

    def добавить(self, п: Пакет, поля: dict[str, list[Any]]) -> bytes | None:
        if "ipv4" not in поля or not поля.get("ip.flags.mf") or "ip.frag_offset" not in поля:
            return None
        mf, смещение = поля["ip.flags.mf"][0], поля["ip.frag_offset"][0]
        if not mf and not смещение:
            return None
        уровень = next(у for у in п.уровни if у.протокол == "IPv4")
        начало = уровень.смещение
        ihl, всего = уровень.длина, struct.unpack_from(">H", п.данные, начало + 2)[0]
        ключ = (поля["ip.src"][0], поля["ip.dst"][0], поля["ip.id"][0], поля["ip.proto"][0])
        з = self.куски.setdefault(ключ, {"части": {}, "конец": None, "заголовок": None, "номера": []})
        з["части"][смещение] = п.данные[начало + ihl:начало + всего]
        з["номера"].append(п.номер)
        if смещение == 0:
            з["заголовок"] = п.данные[начало:начало + ihl]
        if not mf:
            з["конец"] = смещение + всего - ihl
        if з["заголовок"] is None or з["конец"] is None:
            return None
        собрано, место = b"", 0
        while место < з["конец"]:
            часть = з["части"].get(место)
            if часть is None or not часть:
                return None
            собрано += часть
            место += len(часть)
        del self.куски[ключ]
        заголовок = bytearray(з["заголовок"])
        struct.pack_into(">HH", заголовок, 2, len(заголовок) + len(собрано), 0)
        struct.pack_into(">H", заголовок, 10, 0)
        struct.pack_into(">H", заголовок, 10, сумма16(bytes(заголовок)))
        self.последние_номера = з["номера"]
        return bytes(заголовок) + собрано


class СборщикMP:
    """Сборка фрагментов MP (RFC 1990, 4): от B до E номера идут подряд (по модулю 2²⁴ или 2¹²)."""

    #: Сколько фрагментов одного класса держать в ожидании.
    ЖДАТЬ = 4096

    def __init__(self):
        self.куски: dict[int, dict[int, tuple[bool, bool, bytes, int]]] = {}
        self.последние_номера: list[int] = []

    def добавить(self, п: Пакет, поля: dict[str, list[Any]]) -> bytes | None:
        уровень = next((у for у in п.уровни if у.протокол == "MP"), None)
        if уровень is None:
            return None
        короткий = "mp.sseq" in поля
        номер = поля["mp.sseq" if короткий else "mp.seq"][0]
        первый, последний = bool(поля["mp.first"][0]), bool(поля["mp.last"][0])
        if первый and последний:
            return None
        класс = поля["mp.short_sequence_num_cls" if короткий else "mp.sequence_num_cls"][0]
        модуль = 1 << (12 if короткий else 24)
        куски = self.куски.setdefault(класс, {})
        if len(куски) >= self.ЖДАТЬ:
            куски.clear()
        куски[номер] = (первый, последний, п.данные[уровень.смещение + уровень.длина:], п.номер)
        # Конец — этот фрагмент или ближайший с E после него; начало — ближайший с B до него.
        конец = номер
        while not куски[конец][1]:
            конец = (конец + 1) % модуль
            if конец not in куски:
                return None
        начало = номер
        while not куски[начало][0]:
            начало = (начало - 1) % модуль
            if начало not in куски:
                return None
        части, n = [], начало
        while True:
            части.append(n)
            if n == конец:
                break
            n = (n + 1) % модуль
        # Собранное начинается с поля протокола PPP: канал «PPP» (адрес FF 03 не спутать — протокола
        # 0xFF03 не бывает, старший байт номера чётный, RFC 1661, 2).
        собрано = b"".join(куски[n][2] for n in части)
        self.последние_номера = [куски[n][3] for n in части]
        for n in части:
            del куски[n]
        return собрано


class СборщикSCCP:
    """Сборка сегментов SCCP (Q.714 4.1.1.2; параметр сегментации — Q.713 3.17): первый
    сегмент (F=1) объявляет, сколько осталось, следующие идут с убывающим остатком до нуля.
    Ключ — вызывающий адрес (PC, SSN, цифры GT) и местная ссылка сегментации."""

    #: Сколько начатых сборок держать.
    ЖДАТЬ = 4096

    def __init__(self):
        self.куски: dict[tuple, dict[str, Any]] = {}
        self.последние_номера: list[int] = []
        #: Канал разбора собранного: «TCAP (SSN n)» по подсистеме получателя (иначе отправителя).
        self.канал = "TCAP"

    def добавить(self, п: Пакет, поля: dict[str, list[Any]]) -> bytes | None:
        if "sccp.segmentation.remaining" not in поля:
            return None
        первый, осталось = поля["sccp.segmentation.first"][0], поля["sccp.segmentation.remaining"][0]
        уровень = next(у for у in п.уровни if у.протокол == "SCCP")
        данные_ = next((ф for ф in уровень.поля if ф.ключ == "sccp.parameter" and ф.сырое == 0x0F), None)
        if данные_ is None or первый and осталось == 0:
            return None
        часть = п.данные[данные_.смещение + 1:данные_.смещение + данные_.длина]
        ключ = (tuple(поля.get("sccp.calling.pc", ())), tuple(поля.get("sccp.calling.ssn", ())),
                tuple(поля.get("sccp.calling.digits", ())), поля["sccp.segmentation.slr"][0])
        if первый:
            if len(self.куски) >= self.ЖДАТЬ:
                self.куски.pop(next(iter(self.куски)))
            ssn = (поля.get("sccp.called.ssn") or поля.get("sccp.calling.ssn") or [None])[0]
            self.куски[ключ] = {"ждём": осталось, "части": [часть], "номера": [п.номер],
                                "канал": "TCAP" if ssn is None else f"TCAP (SSN {ssn})"}
            return None
        з = self.куски.get(ключ)
        if з is None or осталось != з["ждём"] - 1:          # пропуск или чужой порядок — сборку бросаем
            self.куски.pop(ключ, None)
            return None
        з["части"].append(часть)
        з["номера"].append(п.номер)
        з["ждём"] = осталось
        if осталось:
            return None
        del self.куски[ключ]
        self.последние_номера, self.канал = з["номера"], з["канал"]
        return b"".join(з["части"])


class Захваты:
    def __init__(self, папка: Path):
        self.папка = Path(папка)
        self._lock = threading.Lock()
        self._кэш: OrderedDict[str, dict[str, Any]] = OrderedDict()

    # -- приём ---------------------------------------------------------------------

    def создать(self, *, владелец: int, имя: str, данные: bytes, от: str = "") -> str:
        ид = time.strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)
        папка = self.папка / ид
        папка.mkdir(parents=True, exist_ok=True)
        (папка / "исходник").write_bytes(данные)
        self._записать(ид, {"ид": ид, "владелец": владелец, "имя": имя, "от": от, "состояние": "ждёт",
                            "создано": time.time(), "байт": len(данные), "пакетов": 0, "разобрано": 0,
                            "формат": "", "заметки": [], "ошибка": ""})
        threading.Thread(target=self._разобрать, args=(ид,), daemon=True, name="reportgen-pakety").start()
        self._прибрать(владелец)
        return ид

    def _разобрать(self, ид: str) -> None:
        папка = self.папка / ид
        try:
            состояние = self.прочитать(ид)
            захват = прочитать_захват(данные=(папка / "исходник").read_bytes())
            состояние.update(состояние="идёт", формат=захват.формат, заметки=захват.заметки,
                             пакетов=len(захват.записи))
            self._записать(ид, состояние)
            сборщик, сборщик_mp, сборщик_sccp = Сборщик(), СборщикMP(), СборщикSCCP()
            состояние.pop("mp_короткие_с", None)             # при пересборке узнаётся заново
            шаблоны: dict[str, Any] = {}                      # NetFlow v9/IPFIX: ключ → [[номер, поля], …]
            как = состояние.get("как") or {}
            if (папка / "собранные").exists():             # пересборка: прежние собранные — прочь
                for старый in (папка / "собранные").iterdir():
                    старый.unlink()
            индекс, каналы = [], []
            with open(папка / "пакеты.bin", "wb") as пакеты, \
                    open(папка / "сводки.jsonl", "w", encoding="utf-8") as сводки, \
                    open(папка / "поля.jsonl", "w", encoding="utf-8") as поля_ф:
                место = 0
                for номер, з in enumerate(захват.записи, start=1):
                    п = разобрать_пакет(з.данные, з.канал, номер=номер, время=з.время, исходная_длина=з.длина,
                                        как=как, шаблоны=шаблоны)
                    поля = п.поля_фильтра()
                    собрано = сборщик.добавить(п, поля)
                    if собрано is not None:
                        self._собранный(папка, п, собрано, сборщик.последние_номера, как)
                        поля = п.поля_фильтра()
                    собрано = сборщик_mp.добавить(п, поля)
                    if собрано is not None:
                        self._собранный(папка, п, собрано, сборщик_mp.последние_номера, как,
                                        канал="PPP", имя="PPP", из="фрагментов MP")
                        поля = п.поля_фильтра()
                    собрано = сборщик_sccp.добавить(п, поля)
                    if собрано is not None:
                        self._собранный(папка, п, собрано, сборщик_sccp.последние_номера, как,
                                        канал=сборщик_sccp.канал, имя="TCAP", из="сегментов SCCP")
                        поля = п.поля_фильтра()
                    if True in поля.get("lcp.opt.ssnh", []) and "mp_короткие_с" not in состояние:
                        как = {**как, "ppp:mp": "короткие"}      # договорены короткие номера MP
                        состояние["mp_короткие_с"] = номер + 1
                    if з.канал not in каналы:
                        каналы.append(з.канал)
                    пакеты.write(з.данные)
                    индекс.append([место, len(з.данные), каналы.index(з.канал)])
                    место += len(з.данные)
                    сводки.write(json.dumps(_сводка(п, поля), ensure_ascii=False) + "\n")
                    поля_ф.write(json.dumps(_для_фильтра(поля), ensure_ascii=False) + "\n")
                    if номер % 2000 == 0:
                        состояние["разобрано"] = номер
                        self._записать(ид, состояние)
            (папка / "индекс.json").write_text(json.dumps({"каналы": каналы, "пакеты": индекс}), encoding="utf-8")
            состояние.update(состояние="готово", разобрано=len(захват.записи), закончено=time.time(),
                             netflow_шаблоны=шаблоны)
        except FileNotFoundError:
            return
        except Exception as ошибка:                     # noqa: BLE001 — поток не роняет приложение
            состояние = self.прочитать(ид)
            состояние.update(состояние="ошибка", ошибка=str(ошибка))
        self._записать(ид, состояние)

    def разбирать_как(self, ид: str, правила: dict[str, str]) -> dict[str, str]:
        """Задать «разбирать как» и разобрать захват заново (в фоне, как при приёме)."""
        from .prilozh import проверить_как  # noqa: PLC0415 — круговой импорт
        правила = проверить_как(правила)
        with self._lock:
            состояние = self.прочитать(ид)
            if состояние["состояние"] not in ("готово", "ошибка"):
                raise ValueError("захват ещё разбирается")
            состояние.update(как=правила, состояние="ждёт", разобрано=0, ошибка="")
            self._записать(ид, состояние)
            self._кэш.pop(ид, None)
        threading.Thread(target=self._разобрать, args=(ид,), daemon=True, name="reportgen-pakety").start()
        return правила

    def _собранный(self, папка: Path, п: Пакет, собрано: bytes, номера: list[int],
                   как: dict[str, str] | None = None, *, канал: str = "IPv4", имя: str = "IPv4",
                   из: str = "фрагментов") -> None:
        (папка / "собранные").mkdir(exist_ok=True)
        (папка / "собранные" / f"{п.номер}.bin").write_bytes(собрано)
        if канал != "IPv4":
            (папка / "собранные" / f"{п.номер}.канал").write_text(канал, encoding="utf-8")
        собранный = разобрать_пакет(собрано, канал, номер=п.номер, время=п.время, как=как)
        первый = собранный.уровни[0]
        первый.протокол = f"собранный {имя}"
        первый.полное = f"{имя}, собран из {из} {', '.join(map(str, номера))}"
        п.уровни += собранный.уровни
        п.инфо = собранный.инфо + f" [собран из {len(номера)} {из}]"
        п.ошибки += собранный.ошибки
        п.порт_от, п.порт_к = собранный.порт_от, собранный.порт_к
        п.нагрузка, п.нагрузка_смещение = None, 0

    # -- чтение --------------------------------------------------------------------

    def прочитать(self, ид: str) -> dict[str, Any]:
        путь = self.папка / ид / "состояние.json"
        if not путь.exists():
            raise KeyError(ид)
        return json.loads(путь.read_text(encoding="utf-8"))

    def список(self, владелец: int) -> list[dict[str, Any]]:
        if not self.папка.exists():
            return []
        итог = []
        for папка in sorted(self.папка.iterdir(), reverse=True):
            путь = папка / "состояние.json"
            if путь.exists():
                с = json.loads(путь.read_text(encoding="utf-8"))
                if с.get("владелец") == владелец:
                    итог.append(с)
        return итог

    def _загрузить(self, ид: str) -> dict[str, Any]:
        with self._lock:
            if ид in self._кэш:
                self._кэш.move_to_end(ид)
                return self._кэш[ид]
        папка = self.папка / ид
        if self.прочитать(ид)["состояние"] != "готово":
            raise ValueError("захват ещё разбирается")
        данные = {
            "сводки": [json.loads(с) for с in (папка / "сводки.jsonl").read_text(encoding="utf-8").splitlines()],
            "поля": [json.loads(с) for с in (папка / "поля.jsonl").read_text(encoding="utf-8").splitlines()],
            "индекс": json.loads((папка / "индекс.json").read_text(encoding="utf-8")),
            "фильтры": OrderedDict(),
        }
        with self._lock:
            self._кэш[ид] = данные
            while len(self._кэш) > В_ПАМЯТИ:
                self._кэш.popitem(last=False)
        return данные

    def отобрать(self, ид: str, фильтр: str) -> list[int]:
        """Номера (с 0) пакетов под фильтр; последние фильтры запоминаются."""
        д = self._загрузить(ид)
        фильтр = (фильтр or "").strip()
        if фильтр in д["фильтры"]:
            return д["фильтры"][фильтр]
        условие = собрать(фильтр)
        if нужны_байты(фильтр):
            кадры, нагрузки = self.кадры(ид), self.нагрузки(ид)
            итог = [i for i, п in enumerate(д["поля"])
                    if условие({**п, "_frame": кадры[i], "_payload": нагрузки[i] or b""})]
        else:
            итог = [i for i, п in enumerate(д["поля"]) if условие(п)]
        д["фильтры"][фильтр] = итог
        while len(д["фильтры"]) > 8:
            д["фильтры"].popitem(last=False)
        return итог

    def сводки(self, ид: str) -> list[dict[str, Any]]:
        return self._загрузить(ид)["сводки"]

    def поля(self, ид: str) -> list[dict[str, list[Any]]]:
        return self._загрузить(ид)["поля"]

    def байты(self, ид: str, номер: int) -> tuple[bytes, str]:
        д = self._загрузить(ид)
        место, длина, канал = д["индекс"]["пакеты"][номер - 1]
        with open(self.папка / ид / "пакеты.bin", "rb") as файл:
            файл.seek(место)
            return файл.read(длина), д["индекс"]["каналы"][канал]

    def пакет(self, ид: str, номер: int) -> dict[str, Any]:
        """Подробный разбор одного пакета — заново, с деревом полей."""
        данные, канал = self.байты(ид, номер)
        с = self.сводки(ид)[номер - 1]
        состояние = self.прочитать(ид)
        как = dict(состояние.get("как") or {})
        if номер >= состояние.get("mp_короткие_с", 1 << 62):
            как["ppp:mp"] = "короткие"
        п = разобрать_пакет(данные, канал, номер=номер, время=с["время"], исходная_длина=с["длина"], как=как,
                            шаблоны=состояние.get("netflow_шаблоны") or {})
        итог = п.в_словарь()
        собранный = self.папка / ид / "собранные" / f"{номер}.bin"
        if собранный.exists():
            байты = собранный.read_bytes()
            канал_с = собранный.with_suffix(".канал")
            с_п = разобрать_пакет(байты, канал_с.read_text(encoding="utf-8") if канал_с.exists() else "IPv4",
                                  номер=номер, время=с["время"], как=как)
            итог["собранный"] = с_п.в_словарь()
        return итог

    def кадры(self, ид: str) -> list[bytes]:
        """Байты всех пакетов (для фильтров по байтам и матрицы) — один раз на захват в памяти."""
        д = self._загрузить(ид)
        if "кадры" not in д:
            with open(self.папка / ид / "пакеты.bin", "rb") as файл:
                весь = файл.read()
            д["кадры"] = [весь[место:место + длина] for место, длина, _ in д["индекс"]["пакеты"]]
        return д["кадры"]

    def нагрузки(self, ид: str) -> list[bytes | None]:
        д = self._загрузить(ид)
        if "нагрузки" not in д:
            кадры = self.кадры(ид)
            д["нагрузки"] = [к[с["нагр"][0]:с["нагр"][0] + с["нагр"][1]] if с.get("нагр") else None
                             for к, с in zip(кадры, д["сводки"], strict=False)]
        return д["нагрузки"]

    def выгрузить_pcap(self, ид: str, номера: list[int]) -> bytes:
        """Отобранные пакеты — в pcap (канал — первого пакета; смешанные каналы — Ethernet)."""
        д = self._загрузить(ид)
        каналы = {д["индекс"]["каналы"][д["индекс"]["пакеты"][i][2]] for i in номера} or {"Ethernet"}
        from .chtenie import КАНАЛЫ  # noqa: PLC0415
        # Каналы с двумя номерами — под основным: IP — 101, ATM RFC 1483 — 100 (не 11).
        обратно = {имя: номер for номер, имя in КАНАЛЫ.items() if номер not in (11, 12, 14)}
        тип = обратно.get(next(iter(каналы)), 1) if len(каналы) == 1 else 1
        итог = bytearray(struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 262144, тип))
        with open(self.папка / ид / "пакеты.bin", "rb") as файл:
            весь = файл.read()
        for i in номера:
            место, длина, _ = д["индекс"]["пакеты"][i]
            с = д["сводки"][i]
            сек = int(с["время"])
            итог += struct.pack("<IIII", сек, int(round((с["время"] - сек) * 1e6)) % 1000000, длина, с["длина"])
            итог += весь[место:место + длина]
        return bytes(итог)

    # -- хранение ------------------------------------------------------------------

    def удалить(self, ид: str) -> None:
        папка = self.папка / ид
        with self._lock:
            self._кэш.pop(ид, None)
        for путь in sorted(папка.rglob("*"), reverse=True):
            путь.unlink() if путь.is_file() else путь.rmdir()
        папка.rmdir()

    def _записать(self, ид: str, состояние: dict[str, Any]) -> None:
        путь = self.папка / ид / "состояние.json"
        временный = путь.with_suffix(".tmp")
        временный.write_text(json.dumps(состояние, ensure_ascii=False), encoding="utf-8")
        временный.replace(путь)

    def _прибрать(self, владелец: int) -> None:
        свои = [з for з in self.список(владелец) if з["состояние"] in ("готово", "ошибка")]
        for лишнее in свои[ХРАНИТЬ:]:
            self.удалить(лишнее["ид"])
