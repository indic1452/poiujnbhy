    def _возобновить(self) -> None:
        """После перезапуска сервера: прерванные разборы — заново (файл на месте), загрузки ждут докачки."""
        if not self.папка.is_dir():
            return
        for папка in sorted(self.папка.iterdir()):
            мета = прочитать_json(папка / "захват.json") if папка.is_dir() else None
            if not мета:
                continue
            ход = прочитать_json(папка / "ход.json", {}) or {}
            if ход.get("поколение") == мета.get("поколение") and ход.get("состояние") in КОНЕЦ:
                continue
            if (мета.get("источник") or {}).get("вид") == "захват":
                ход.update(состояние="прерван", ошибка="сервер перезапускался во время приёма",
                           поколение=мета.get("поколение"))
                with contextlib.suppress(OSError):
                    self._записать_ход(папка.name, ход)
                continue
            self._поставить(папка.name, мета)

