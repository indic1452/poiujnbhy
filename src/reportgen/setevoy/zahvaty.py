"""Записи «Анализа пакетов»: приём файла (целиком или кусками), разбор в фоне, хранение, выборки.

Каждая запись — папка: исходный файл, ``захват.json`` (чей, имя, правила «разбирать
как», ход загрузки — пишет сервер), ``ход.json`` (ход разбора — пишет фоновая работа),
хранилище разобранного на диске (``hranilishe``), ``статистика/`` (разделы ``nakopitel``)
и ``отборы/`` — отборы по фильтрам со своей статистикой.

Разбор начинается сразу — пока файл ещё загружается, — и идёт в фоне
(``raboty``/``fon``): страница видит, сколько разобрано, список пакетов, дерево
протоколов и статистику растущими. Ни файл, ни разобранное в память не читаются
целиком: сервер держит постоянную память при любом размере захвата, и параллельные
разборы разных людей идут в отдельных процессах — честной очередью.

Подробный разбор одного пакета (дерево полей) не хранится — он строится заново по
запросу: это доли миллисекунды.

Сборка фрагментов (IPv4, MP, сегменты SCCP), сводки и поля — в ``sborka``.
"""

