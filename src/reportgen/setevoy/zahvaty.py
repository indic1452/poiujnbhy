    def объекты(self, ид: str, фильтр: str = "", настройки: Any = None) -> dict[str, Any]:
        """Объекты записи (setevoy.obekty) по отобранным пакетам — по первым, пока их нагрузка не больше
        ``ОБЪЕКТЫ_БАЙТ_ДО``; последние расчёты запоминаются."""
        from .obekty import Настройки, собрать  # noqa: PLC0415
        настройки = настройки or Настройки()
        отбор = self.отбор(ид, фильтр, ждать=5.0)
        ход = отбор.ход()
        число = отбор.число()
        поколение = self._мета(ид).get("поколение", 1)
        ключ = (ид, поколение, (фильтр or "").strip(), настройки.ключ(), число)
        with self._lock:
            if ключ in self._объекты:
                self._объекты.move_to_end(ключ)
                return self._объекты[ключ]
        with self._объекты_замок:
            х = отбор.х
            номера = отбор.номера(0, число)
            взято, байт = 0, 0
            for от in range(0, len(номера), 8192):
                часть = номера[от:от + 8192]
                for с in х.сводки_по(часть):
                    место = с.get("тр") or с.get("тр_с") or с.get("нагр")
                    байт += место[1] if место else 0
                    if байт > ОБЪЕКТЫ_БАЙТ_ДО or взято >= ОБЪЕКТЫ_ПАКЕТОВ_ДО:
                        break
                    взято += 1
                else:
                    continue
                break
            сводки = Ряд(х, "сводки", номера[:взято])
            груз = Ряд(х, "нагрузки_тр", номера[:взято])
            sdp = self.шаблоны(ид).get("sdp-потоки") or {}
            итог = собрать(list(сводки), list(груз), sdp=sdp, настройки=настройки)
            if взято < число:
                итог["заметки"] = [f"объекты собраны по первым {взято} пакетам отбора из {число} — их нагрузка уже "
                                   f"{ОБЪЕКТЫ_БАЙТ_ДО >> 20} МБ (сборка потоков держит их в памяти сервера); "
                                   "сузьте отбор фильтром, чтобы собрать остальное", *итог["заметки"]]
            if not ход["готово"]:
                итог["заметки"] = [f"разбор ещё идёт: собрано по {число} пакетам, разобранным к этому мигу",
                                   *итог["заметки"]]
            итог["по_пакетам"] = взято
        with self._lock:
            self._объекты[ключ] = итог
            while len(self._объекты) > 2:
                self._объекты.popitem(last=False)
        return итог

    # -- выгрузка ------------------------------------------------------------------

    def _тип_канала(self, х: Хранилище, номера: np.ndarray) -> int:
        from .chtenie import КАНАЛЫ  # noqa: PLC0415
        # Каналы с двумя номерами — под основным: IP — 101, ATM RFC 1483 — 100 (не 11).
        обратно = {имя: номер for номер, имя in КАНАЛЫ.items() if номер not in (11, 12, 14)}
        каналы = х.каналы()
        виды: set[int] = set()
        for от in range(0, len(номера), 65536):
            виды.update(np.unique(х.записи_по(номера[от:от + 65536])["канал"]).tolist())
            if len(виды) > 1:
                return 1
        if not виды:
            return 1
        к = next(iter(виды))
        return обратно.get(каналы[к] if к < len(каналы) else "Ethernet", 1)

    def поток_pcap(self, ид: str, номера: Sequence[int] | np.ndarray) -> Iterator[bytes]:
        """Отобранные пакеты — pcap кусками (канал — общий у всех; смешанные каналы — Ethernet)."""
        х = self.хранилище(ид)
        номера = np.asarray(номера, dtype=np.int64)
        yield struct.pack("<IHHiIII", 0xA1B2C3D4, 2, 4, 0, 0, 262144, self._тип_канала(х, номера))
        for от in range(0, len(номера), 4096):
            часть = номера[от:от + 4096]
            кусок = bytearray()
            for с, к in zip(х.сводки_по(часть), х.кадры_по(часть), strict=True):
                сек = int(с["время"])
                кусок += struct.pack("<IIII", сек, int(round((с["время"] - сек) * 1e6)) % 1000000, len(к), с["длина"])
                кусок += к
            yield bytes(кусок)

    def поток_pcapng(self, ид: str, номера: Sequence[int] | np.ndarray) -> Iterator[bytes]:
        """Отобранные пакеты — pcapng кусками (draft-ietf-opsawg-pcapng): SHB, IDB на каждый вид канала (время в
        микросекундах — if_tsresol по умолчанию), EPB с исходной длиной; добивка данных до 32 бит."""
        from .chtenie import КАНАЛЫ  # noqa: PLC0415
        обратно = {имя: номер for номер, имя in КАНАЛЫ.items() if номер not in (11, 12, 14)}
        х = self.хранилище(ид)
        номера = np.asarray(номера, dtype=np.int64)

        def блок(тип: int, тело: bytes) -> bytes:
            тело += b"\x00" * (-len(тело) % 4)
            return struct.pack("<II", тип, 12 + len(тело)) + тело + struct.pack("<I", 12 + len(тело))

        yield блок(0x0A0D0D0A, struct.pack("<IHHq", 0x1A2B3C4D, 1, 0, -1))
        интерфейсы: dict[int, int] = {}
        каналы = х.каналы()
        for от in range(0, len(номера), 4096):
            часть = номера[от:от + 4096]
            записи = х.записи_по(часть)
            кусок = bytearray()
            for з, с, к in zip(записи["канал"].tolist(), х.сводки_по(часть), х.кадры_по(часть), strict=True):
                if з not in интерфейсы:
                    интерфейсы[з] = len(интерфейсы)
                    кусок += блок(1, struct.pack("<HHI", обратно.get(каналы[з] if з < len(каналы) else "", 1), 0,
                                                 262144))
                мкс = int(round(с["время"] * 1e6))
                кусок += блок(6, struct.pack("<IIIII", интерфейсы[з], мкс >> 32, мкс & 0xFFFFFFFF, len(к), с["длина"])
                              + к)
            yield bytes(кусок)

    def выгрузить_pcap(self, ид: str, номера: list[int]) -> bytes:
        return b"".join(self.поток_pcap(ид, номера))

    def выгрузить_pcapng(self, ид: str, номера: list[int]) -> bytes:
        return b"".join(self.поток_pcapng(ид, номера))

