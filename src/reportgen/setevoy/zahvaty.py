    def удалить(self, ид: str) -> None:
        папка = self.папка / ид
        self._убрать_отборы(ид)
        self.диспетчер.остановить(str(папка), "запись удалена")
        self._забыть(ид)
        for пауза in (0.05, 0.2, 0.5, 1.0, None):
            shutil.rmtree(папка, ignore_errors=пауза is None)
            if not папка.exists() or пауза is None:
                break
            time.sleep(пауза)
        with self._lock:
            self._замки.pop(ид, None)

