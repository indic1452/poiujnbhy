# -*- coding: utf-8 -*-
"""Статистика захвата: протоколы, диалоги, узлы, время, DNS/HTTP/TLS, ошибки, поток TCP.

Всё считается по сводкам пакетов (без повторного разбора): у сводки есть
стек протоколов, адреса, порты, длина, время и плоские поля для фильтров.
"""

from __future__ import annotations

from collections import Counter, defaultdict
from typing import Any, Dict, Iterable, List, Optional, Sequence, Tuple

Сводка = Dict[str, Any]


def иерархия(сводки: Sequence[Сводка]) -> List[Dict[str, Any]]:
    """Дерево протоколов: у каждого узла пакеты и байты (как «Protocol Hierarchy»)."""
    корень: Dict[str, Any] = {"протокол": "Кадры", "пакетов": 0, "байт": 0, "дети": {}}
    for с in сводки:
        узел = корень
        узел["пакетов"] += 1
        узел["байт"] += с["длина"]
        for протокол in с["стек"]:
            узел = узел["дети"].setdefault(протокол, {"протокол": протокол, "пакетов": 0, "байт": 0, "дети": {}})
            узел["пакетов"] += 1
            узел["байт"] += с["длина"]

    def в_список(у: Dict[str, Any]) -> Dict[str, Any]:
        return {**{к: у[к] for к in ("протокол", "пакетов", "байт")},
                "дети": sorted((в_список(д) for д in у["дети"].values()), key=lambda д: -д["пакетов"])}

    return [в_список(корень)]


def диалоги(сводки: Sequence[Сводка], уровень: str = "ip") -> List[Dict[str, Any]]:
    """Пары узлов (ip), MAC (eth) или пары «адрес:порт» (tcp, udp) — в обе стороны."""
    таблица: Dict[Tuple, Dict[str, Any]] = {}
    for с in сводки:
        if уровень == "eth":
            if not с.get("mac"):
                continue
            а, б = с["mac"]
        elif уровень in ("tcp", "udp"):
            if уровень.upper() not in с["стек"] or с.get("порт_от") is None:
                continue
            а, б = f"{с['источник']}:{с['порт_от']}", f"{с['получатель']}:{с['порт_к']}"
        else:
            if not ({"IPv4", "IPv6"} & set(с["стек"])):
                continue
            а, б = с["источник"], с["получатель"]
        ключ = tuple(sorted((а, б)))
        з = таблица.setdefault(ключ, {"а": ключ[0], "б": ключ[1], "пакетов_аб": 0, "байт_аб": 0,
                                      "пакетов_ба": 0, "байт_ба": 0, "начало": с["время"], "конец": с["время"],
                                      "протоколы": Counter()})
        сторона = "аб" if а == ключ[0] else "ба"
        з["пакетов_" + сторона] += 1
        з["байт_" + сторона] += с["длина"]
        з["начало"] = min(з["начало"], с["время"])
        з["конец"] = max(з["конец"], с["время"])
        з["протоколы"][с["протокол"]] += 1
    итог = []
    for з in таблица.values():
        з["пакетов"] = з["пакетов_аб"] + з["пакетов_ба"]
        з["байт"] = з["байт_аб"] + з["байт_ба"]
        з["длительность"] = round(з["конец"] - з["начало"], 6)
        з["протоколы"] = ", ".join(f"{п} ×{н}" for п, н in з["протоколы"].most_common(4))
        итог.append(з)
    return sorted(итог, key=lambda з: -з["байт"])


def узлы(сводки: Sequence[Сводка]) -> List[Dict[str, Any]]:
    таблица: Dict[str, Dict[str, Any]] = {}
    for с in сводки:
        if not ({"IPv4", "IPv6"} & set(с["стек"])):
            continue
        for адрес, сторона in ((с["источник"], "отправлено"), (с["получатель"], "получено")):
            у = таблица.setdefault(адрес, {"адрес": адрес, "пакетов": 0, "байт": 0, "отправлено": 0,
                                           "получено": 0, "порты": Counter()})
            у["пакетов"] += 1
            у["байт"] += с["длина"]
            у[сторона] += с["длина"]
            порт = с.get("порт_к") if сторона == "получено" else с.get("порт_от")
            if порт is not None and порт < 1024:
                у["порты"][порт] += 1
    итог = []
    for у in таблица.values():
        у["службы"] = ", ".join(str(п) for п, _ in у["порты"].most_common(5))
        del у["порты"]
        итог.append(у)
    return sorted(итог, key=lambda у: -у["байт"])


def по_времени(сводки: Sequence[Сводка], столбцов: int = 120) -> Dict[str, Any]:
    """Пакеты и байты по интервалам — для графика нагрузки."""
    if not сводки:
        return {"шаг": 0, "начало": 0, "пакетов": [], "байт": []}
    начало = min(с["время"] for с in сводки)
    конец = max(с["время"] for с in сводки)
    шаг = max((конец - начало) / столбцов, 1e-6)
    пакетов, байт = [0] * столбцов, [0] * столбцов
    for с in сводки:
        i = min(столбцов - 1, int((с["время"] - начало) / шаг))
        пакетов[i] += 1
        байт[i] += с["длина"]
    return {"шаг": шаг, "начало": начало, "пакетов": пакетов, "байт": байт}


def dns(сводки: Sequence[Сводка], поля: Sequence[Dict[str, List[Any]]]) -> List[Dict[str, Any]]:
    итог = []
    for с, п in zip(сводки, поля):
        if not {"DNS", "mDNS", "LLMNR"} & set(с["стек"]):
            continue
        ответ = bool(п.get("dns.flags.response", [0])[0])
        итог.append({"номер": с["номер"], "время": с["время"], "клиент": с["получатель"] if ответ else с["источник"],
                     "сервер": с["источник"] if ответ else с["получатель"], "ответ": ответ,
                     "имя": ", ".join(map(str, п.get("dns.qry.name", []))),
                     "тип": ", ".join(map(str, п.get("dns.qry.type", []))),
                     "ответы": ", ".join(map(str, п.get("dns.a", []) + п.get("dns.aaaa", []) + п.get("dns.cname", []))),
                     "код": п.get("dns.flags.rcode", [""])[0] if ответ else ""})
    return итог


def http(сводки: Sequence[Сводка], поля: Sequence[Dict[str, List[Any]]]) -> List[Dict[str, Any]]:
    итог, ждут = [], defaultdict(list)
    for с, п in zip(сводки, поля):
        if "HTTP" not in с["стек"]:
            continue
        ключ = (с["источник"], с.get("порт_от"), с["получатель"], с.get("порт_к"))
        if "http.request.method" in п:
            запись = {"номер": с["номер"], "время": с["время"], "клиент": с["источник"], "сервер": с["получатель"],
                      "метод": п["http.request.method"][0], "узел": (п.get("http.host") or [""])[0],
                      "адрес": (п.get("http.request.uri") or [""])[0], "код": "",
                      "агент": (п.get("http.user_agent") or [""])[0]}
            итог.append(запись)
            ждут[ключ].append(запись)
        elif "http.response.code" in п:
            обратный = (с["получатель"], с.get("порт_к"), с["источник"], с.get("порт_от"))
            if ждут[обратный]:
                ждут[обратный].pop(0)["код"] = п["http.response.code"][0]
    return итог


def tls(сводки: Sequence[Сводка], поля: Sequence[Dict[str, List[Any]]]) -> List[Dict[str, Any]]:
    итог = []
    for с, п in zip(сводки, поля):
        if "TLS" not in с["стек"] or "ClientHello" not in [str(т) for т in п.get("tls.handshake.type", [])]:
            continue
        итог.append({"номер": с["номер"], "время": с["время"], "клиент": с["источник"], "сервер": с["получатель"],
                     "порт": с.get("порт_к"), "sni": (п.get("tls.handshake.extensions_server_name") or [""])[0],
                     "alpn": (п.get("tls.handshake.extensions_alpn_str") or [""])[0],
                     "версии": (п.get("tls.handshake.extensions.supported_version") or [""])[0]})
    return итог


def ошибки(сводки: Sequence[Сводка]) -> List[Dict[str, Any]]:
    по_видам: Dict[str, Dict[str, Any]] = {}
    for с in сводки:
        for текст in с["ошибки"]:
            вид = текст.split(":")[0] + ": " + текст.split(":", 1)[-1].split("(")[0].strip() if ":" in текст else текст
            з = по_видам.setdefault(вид, {"что": вид, "пакетов": 0, "первые": []})
            з["пакетов"] += 1
            if len(з["первые"]) < 20:
                з["первые"].append(с["номер"])
    return sorted(по_видам.values(), key=lambda з: -з["пакетов"])


def ключ_потока(с: Сводка) -> Optional[Tuple]:
    if с.get("порт_от") is None:
        return None
    транспорт = "TCP" if "TCP" in с["стек"] else "UDP" if "UDP" in с["стек"] else "SCTP" if "SCTP" in с["стек"] else ""
    if not транспорт:
        return None
    а, б = (с["источник"], с["порт_от"]), (с["получатель"], с["порт_к"])
    return (транспорт,) + tuple(sorted((а, б)))


def поток(сводки: Sequence[Сводка], нагрузки: Sequence[Optional[bytes]], номер: int,
          предел: int = 4 << 20) -> Dict[str, Any]:
    """«Следовать за потоком»: нагрузки в обе стороны по порядку; у TCP — по номерам, без повторов."""
    опорная = next((с for с in сводки if с["номер"] == номер), None)
    if опорная is None or ключ_потока(опорная) is None:
        raise ValueError("у этого пакета нет потока TCP/UDP/SCTP")
    ключ = ключ_потока(опорная)
    клиент = None
    куски: List[Dict[str, Any]] = []
    следующий: Dict[str, int] = {}
    всего = 0
    for с, нагрузка in zip(сводки, нагрузки):
        if ключ_потока(с) != ключ or not нагрузка:
            continue
        сторона = (с["источник"], с["порт_от"])
        if клиент is None:
            клиент = сторона
        направление = "→" if сторона == клиент else "←"
        данные = bytes(нагрузка)
        if ключ[0] == "TCP" and с.get("seq") is not None:
            seq = с["seq"]
            ожидаем = следующий.get(направление)
            if ожидаем is not None:
                сдвиг = (ожидаем - seq) & 0xFFFFFFFF
                if сдвиг and сдвиг < 1 << 31:          # повтор или перекрытие: берём только новое
                    if сдвиг >= len(данные):
                        continue
                    данные = данные[сдвиг:]
                    seq = ожидаем
            следующий[направление] = (seq + len(данные)) & 0xFFFFFFFF
        if всего + len(данные) > предел:
            break
        всего += len(данные)
        if куски and куски[-1]["направление"] == направление:
            куски[-1]["данные"] += данные
            куски[-1]["пакеты"].append(с["номер"])
        else:
            куски.append({"направление": направление, "данные": данные, "пакеты": [с["номер"]]})
    return {"транспорт": ключ[0], "клиент": f"{клиент[0]}:{клиент[1]}" if клиент else "",
            "сервер": next((f"{a}:{p}" for a, p in ключ[1:] if (a, p) != клиент), ""),
            "куски": [{"направление": к["направление"], "hex": к["данные"].hex(),
                       "текст": к["данные"].decode("utf-8", "replace"), "байт": len(к["данные"]),
                       "пакеты": к["пакеты"]} for к in куски],
            "байт": всего}


def неизвестные(сводки: Sequence[Сводка], нагрузки: Sequence[Optional[bytes]],
                групп_до: int = 12) -> List[Dict[str, Any]]:
    """Нагрузка без известного разборщика — по группам (транспорт и порт службы):
    поля неизвестного формата и CRC вслепую, как для кадров потока."""
    from ..potok import polya  # noqa: PLC0415 — numpy только здесь
    группы: Dict[str, List[Tuple[int, bytes]]] = defaultdict(list)
    for с, нагрузка in zip(сводки, нагрузки):
        if not нагрузка or с["стек"][-1] != "Данные":
            continue
        свои = [п for п in с["стек"] if п not in ("Данные",)]
        верх = свои[-1] if свои else "кадры"
        if с.get("порт_от") is not None:
            ключ = f"{верх} порт {min(с['порт_от'], с['порт_к'])}"
        else:
            ключ = f"{верх}"
        группы[ключ].append((с["номер"], bytes(нагрузка)))
    итог = []
    for ключ, пакеты in sorted(группы.items(), key=lambda г: -len(г[1]))[:групп_до]:
        кадры = [н for _, н in пакеты]
        запись = {"группа": ключ, "пакетов": len(пакеты), "первые": [н for н, _ in пакеты[:10]],
                  "длины": f"{min(map(len, кадры))}–{max(map(len, кадры))}", "что": "", "подробно": []}
        if len(кадры) >= 20:
            найдено = polya.найти(кадры[:5000], "пакетов")
            if найдено is not None:
                запись["что"], запись["подробно"] = найдено.что, list(найдено.подробно)
        else:
            запись["что"] = "мало пакетов для статистики полей (нужно от 20)"
        итог.append(запись)
    return итог


# -- матрица байт: пакеты — строки, смещения — столбцы --------------------------------------

def _энтропия(счёт: Counter, всего: int) -> float:
    import math  # noqa: PLC0415
    return round(-sum(н / всего * math.log2(н / всего) for н in счёт.values()) if всего else 0.0, 3)


def профиль_столбцов(ряды: Sequence[bytes], от: int, сколько: int) -> List[Dict[str, Any]]:
    """Для каждого столбца: сколько пакетов до него дотягивается, энтропия, различных, постоянное значение."""
    итог = []
    for место in range(от, от + сколько):
        значения = Counter(р[место] for р in ряды if len(р) > место)
        есть = sum(значения.values())
        частое, раз = значения.most_common(1)[0] if значения else (None, 0)
        итог.append({"место": место, "есть": есть, "энтропия": _энтропия(значения, есть),
                     "различных": len(значения),
                     "постоянное": f"{частое:02x}" if есть and раз >= 0.98 * есть else None})
    return итог


def столбец(ряды: Sequence[bytes], место: int, ширина: int = 1) -> Dict[str, Any]:
    """Полная статистика поля (1–8 байт с места): значения, энтропия, счётчик, длина, биты, полубайты."""
    значения, длины = [], []
    for р in ряды:
        if len(р) >= место + ширина:
            значения.append(int.from_bytes(р[место:место + ширина], "big"))
            длины.append(len(р))
    всего = len(значения)
    if not всего:
        return {"всего": 0, "есть": 0}
    счёт = Counter(значения)
    модуль = 1 << (8 * ширина)
    подряд = sum(1 for а, б in zip(значения, значения[1:]) if (б - а) % модуль == 1)
    шаг_счёт = Counter((б - а) % модуль for а, б in zip(значения, значения[1:]))
    шаг, шаг_раз = шаг_счёт.most_common(1)[0] if шаг_счёт else (0, 0)
    # Поле длины: значение = длина пакета − k для одного k у большинства пакетов.
    разности = Counter(д - з for з, д in zip(значения, длины))
    k, k_раз = разности.most_common(1)[0]
    биты = [round(sum((з >> (8 * ширина - 1 - b)) & 1 for з in значения) / всего, 3) for b in range(8 * ширина)]
    итог = {
        "всего": len(ряды), "есть": всего, "ширина": ширина, "место": место,
        "различных": len(счёт), "энтропия": _энтропия(счёт, всего),
        "наибольшая_энтропия": round(min(8 * ширина, __import__("math").log2(всего)) if всего > 1 else 0, 3),
        "мин": f"{min(значения):0{2 * ширина}x}", "макс": f"{max(значения):0{2 * ширина}x}",
        "значения": [{"hex": f"{з:0{2 * ширина}x}", "dec": з, "раз": н, "доля": round(н / всего, 4)}
                     for з, н in счёт.most_common(64)],
        "счётчик": round(подряд / max(1, всего - 1), 3),
        "шаг": {"значение": шаг, "доля": round(шаг_раз / max(1, всего - 1), 3)},
        "длина": {"k": k, "доля": round(k_раз / всего, 3)},
        "биты": биты,
    }
    if ширина == 1:
        итог["полубайты"] = {
            "старший": [sum(1 for з in значения if з >> 4 == h) for h in range(16)],
            "младший": [sum(1 for з in значения if з & 15 == h) for h in range(16)],
        }
    вывод = []
    if итог["значения"][0]["доля"] >= 0.98:
        вывод.append(f"постоянное поле: 0x{итог['значения'][0]['hex']}")
    elif итог["счётчик"] >= 0.8:
        вывод.append(f"счётчик: +1 у {итог['счётчик'] * 100:.0f} % соседних пакетов")
    elif итог["шаг"]["доля"] >= 0.8 and шаг:
        вывод.append(f"растёт с шагом {шаг} у {итог['шаг']['доля'] * 100:.0f} % соседних пакетов")
    if итог["длина"]["доля"] >= 0.9 and len(set(длины)) > 1:
        вывод.append(f"поле длины: значение = длина пакета {'−' if k >= 0 else '+'} {abs(k)} у "
                     f"{итог['длина']['доля'] * 100:.0f} % пакетов")
    if 1 < len(счёт) <= 16 and итог["значения"][0]["доля"] < 0.98:
        вывод.append(f"поле типа: {len(счёт)} значений")
    if итог["энтропия"] > 0.9 * итог["наибольшая_энтропия"] and len(счёт) > 16 and not вывод:
        вывод.append("похоже на случайные данные (шифр, сжатие, хэш)")
    итог["вывод"] = вывод
    return итог
