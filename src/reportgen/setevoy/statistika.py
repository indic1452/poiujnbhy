def _энтропия(счёт: Counter, всего: int) -> float:
    import math  # noqa: PLC0415
    return round(-sum(н / всего * math.log2(н / всего) for н in счёт.values()) if всего else 0.0, 3)


def профиль_столбцов(ряды: Sequence[bytes], от: int, сколько: int) -> list[dict[str, Any]]:
    """Для каждого столбца: сколько пакетов до него дотягивается, энтропия, различных, постоянное значение."""
    итог = []
    for место in range(от, от + сколько):
        значения = Counter(р[место] for р in ряды if len(р) > место)
        есть = sum(значения.values())
        частое, раз = значения.most_common(1)[0] if значения else (None, 0)
        итог.append({"место": место, "есть": есть, "энтропия": _энтропия(значения, есть),
                     "различных": len(значения),
                     "постоянное": f"{частое:02x}" if есть and раз >= 0.98 * есть else None})
    return итог


def столбец(ряды: Sequence[bytes], место: int, ширина: int = 1) -> dict[str, Any]:
    """Полная статистика поля (1–8 байт с места): значения, энтропия, счётчик, длина, биты, полубайты."""
    значения, длины = [], []
    for р in ряды:
        if len(р) >= место + ширина:
            значения.append(int.from_bytes(р[место:место + ширина], "big"))
            длины.append(len(р))
    всего = len(значения)
    if not всего:
        return {"всего": 0, "есть": 0}
    счёт = Counter(значения)
    модуль = 1 << (8 * ширина)
    подряд = sum(1 for а, б in zip(значения, значения[1:], strict=False) if (б - а) % модуль == 1)
    шаг_счёт = Counter((б - а) % модуль for а, б in zip(значения, значения[1:], strict=False))
    шаг, шаг_раз = шаг_счёт.most_common(1)[0] if шаг_счёт else (0, 0)
    # Поле длины: значение = длина пакета − k для одного k у большинства пакетов.
    разности = Counter(д - з for з, д in zip(значения, длины, strict=False))
    k, k_раз = разности.most_common(1)[0]
    биты = [round(sum((з >> (8 * ширина - 1 - b)) & 1 for з in значения) / всего, 3) for b in range(8 * ширина)]
    итог = {
        "всего": len(ряды), "есть": всего, "ширина": ширина, "место": место,
        "различных": len(счёт), "энтропия": _энтропия(счёт, всего),
        "наибольшая_энтропия": round(min(8 * ширина, __import__("math").log2(всего)) if всего > 1 else 0, 3),
        "мин": f"{min(значения):0{2 * ширина}x}", "макс": f"{max(значения):0{2 * ширина}x}",
        "значения": [{"hex": f"{з:0{2 * ширина}x}", "dec": з, "раз": н, "доля": round(н / всего, 4)}
                     for з, н in счёт.most_common(64)],
        "счётчик": round(подряд / max(1, всего - 1), 3),
        "шаг": {"значение": шаг, "доля": round(шаг_раз / max(1, всего - 1), 3)},
        "длина": {"k": k, "доля": round(k_раз / всего, 3)},
        "биты": биты,
    }
    if ширина == 1:
        итог["полубайты"] = {
            "старший": [sum(1 for з in значения if з >> 4 == h) for h in range(16)],
            "младший": [sum(1 for з in значения if з & 15 == h) for h in range(16)],
        }
    вывод = []
    if итог["значения"][0]["доля"] >= 0.98:
        вывод.append(f"постоянное поле: 0x{итог['значения'][0]['hex']}")
    elif итог["счётчик"] >= 0.8:
        вывод.append(f"счётчик: +1 у {итог['счётчик'] * 100:.0f} % соседних пакетов")
    elif итог["шаг"]["доля"] >= 0.8 and шаг:
        вывод.append(f"растёт с шагом {шаг} у {итог['шаг']['доля'] * 100:.0f} % соседних пакетов")
    if итог["длина"]["доля"] >= 0.9 and len(set(длины)) > 1:
        вывод.append(f"поле длины: значение = длина пакета {'−' if k >= 0 else '+'} {abs(k)} у "
                     f"{итог['длина']['доля'] * 100:.0f} % пакетов")
    if 1 < len(счёт) <= 16 and итог["значения"][0]["доля"] < 0.98:
        вывод.append(f"поле типа: {len(счёт)} значений")
    if итог["энтропия"] > 0.9 * итог["наибольшая_энтропия"] and len(счёт) > 16 and not вывод:
        вывод.append("похоже на случайные данные (шифр, сжатие, хэш)")
    итог["вывод"] = вывод
    return итог


# -- файлы внутри потоков ---------------------------------------------------------------------

def направления(сводки: Sequence[Сводка], нагрузки: Sequence[bytes | None],
                предел: int = 64 << 20) -> dict[tuple, dict[str, Any]]:
    """Все потоки TCP/UDP/SCTP по направлениям: собранные байты и откуда какой кусок.

    У TCP — по номерам последовательности, повторы и перекрытия отбрасываются
    (как в «следовать за потоком»); у UDP — нагрузки подряд.
    """
    итог: dict[tuple, dict[str, Any]] = {}
    всего = 0
    for с, нагрузка in zip(сводки, нагрузки, strict=False):
        ключ = ключ_потока(с)
        if ключ is None or not нагрузка:
            continue
        направление = (ключ, (с["источник"], с["порт_от"]))
        з = итог.setdefault(направление, {"данные": bytearray(), "карта": [], "следующий": None,
                                          "от": f"{с['источник']}:{с['порт_от']}",
                                          "к": f"{с['получатель']}:{с['порт_к']}", "транспорт": ключ[0]})
        данные = bytes(нагрузка)
        if ключ[0] == "TCP" and с.get("seq") is not None:
            seq = с["seq"]
            if з["следующий"] is not None:
                сдвиг = (з["следующий"] - seq) & 0xFFFFFFFF
                if сдвиг and сдвиг < 1 << 31:
                    if сдвиг >= len(данные):
                        continue
                    данные = данные[сдвиг:]
                    seq = з["следующий"]
            з["следующий"] = (seq + len(данные)) & 0xFFFFFFFF
        if всего + len(данные) > предел:
            break
        з["карта"].append((len(з["данные"]), с["номер"]))
        з["данные"] += данные
        всего += len(данные)
    return итог


def файлы(сводки: Sequence[Сводка], нагрузки: Sequence[bytes | None],
          предел: int = 64 << 20) -> list[dict[str, Any]]:
    """Файлы в собранных потоках: сигнатура и структура сошлись (по границе байта)."""
    import numpy as np  # noqa: PLC0415

    from ..potok import poisk  # noqa: PLC0415
    итог = []
    for з in направления(сводки, нагрузки, предел).values():
        данные = bytes(з["данные"])
        if len(данные) < 8:
            continue
        биты = np.unpackbits(np.frombuffer(данные, dtype=np.uint8))
        for н in poisk.сигнатуры(биты, любой_сдвиг=False, предел=200):
            место = н["байт"]
            пакет = next((номер for начало, номер in reversed(з["карта"]) if начало <= место), з["карта"][0][1])
            итог.append({"что": н["что"], "расширение": н["расширение"], "длина": н["длина"],
                         "поток": f"{з['транспорт']} {з['от']} → {з['к']}", "смещение": место,
                         "пакет": пакет})
    return итог


def вырезать_из_потока(сводки: Sequence[Сводка], нагрузки: Sequence[bytes | None], поток: str,
                       смещение: int, длина: int) -> bytes:
    """Байты файла из собранного потока; длина 0 (конец неизвестен) — до предела вырезки поиска."""
    from ..potok import poisk  # noqa: PLC0415
    for з in направления(сводки, нагрузки).values():
        if f"{з['транспорт']} {з['от']} → {з['к']}" == поток:
            return bytes(з["данные"][смещение:смещение + min(длина or poisk.ФАЙЛ_ДО, poisk.ФАЙЛ_ДО)])
    raise ValueError("поток не найден")


# -- обзор захвата: главное одним взглядом ---------------------------------------------------

#: Протоколы, которые передают учётные данные и содержимое открытым текстом.
ОТКРЫТЫЕ = ("HTTP", "FTP", "Telnet", "POP3", "IMAP", "SMTP", "SNMP", "TFTP", "Syslog")


def обзор(сводки: Sequence[Сводка], поля: Sequence[dict[str, list[Any]]],
          нагрузки: Sequence[bytes | None], *, файлов_в: int = 16 << 20) -> dict[str, Any]:
    """Сводка захвата для первого взгляда: объём, протоколы, главные диалоги, имена,
    ошибки, файлы в потоках, неразобранное — и приметы, на что посмотреть."""
    if not сводки:
        return {"пакетов": 0}
    начало = min(с["время"] for с in сводки)
    длительность = max(с["время"] for с in сводки) - начало
    байт = sum(с["длина"] for с in сводки)
    протоколы = Counter(с["протокол"] for с in сводки)
    с_ошибками = sum(1 for с in сводки if с["ошибки"])
    dns_ = dns(сводки, поля)
    имена = Counter(з["имя"] for з in dns_ if not з["ответ"] and з["имя"])
    запросы = {(з["клиент"], з["порт"], з["ид"]) for з in dns_ if not з["ответ"]}
    ответы = {(з["клиент"], з["порт"], з["ид"]) for з in dns_ if з["ответ"]}
    sni = Counter(з["sni"] for з in tls(сводки, поля) if з["sni"])
    узлы_http = Counter(з["узел"] for з in http(сводки, поля) if з["узел"])
    найдено = файлы(сводки, нагрузки, файлов_в)
    неразобрано = Counter()
    for с in сводки:
        if с["стек"][-1] == "Данные" and с.get("порт_от") is not None:
            свои = [п for п in с["стек"] if п != "Данные"]
            неразобрано[f"{свои[-1] if свои else 'кадры'} порт {min(с['порт_от'], с['порт_к'])}"] += 1
    приметы = []
    открытые = Counter(п for с in сводки for п in с["стек"] if п in ОТКРЫТЫЕ)
    if открытые:
        приметы.append({"что": "открытым текстом: " + ", ".join(f"{п} ×{н}" for п, н in открытые.most_common()),
                        "фильтр": " or ".join(п.lower() for п in открытые)})
    без_ответа = запросы - ответы
    if без_ответа and ответы:
        приметы.append({"что": f"DNS-запросов без ответа: {len(без_ответа)} из {len(запросы)}", "фильтр": "dns"})
    tcp_суммы = sum(1 for с in сводки if any(о.startswith("TCP: контрольная") for о in с["ошибки"]))
    if tcp_суммы and tcp_суммы >= 0.5 * sum(1 for с in сводки if "TCP" in с["стек"]):
        приметы.append({"что": "у большинства TCP не сошлась сумма — похоже на захват на передающем узле "
                               "(сумму считает сетевая карта), а не на порчу", "фильтр": "expert and tcp"})
    if неразобрано:
        группа, раз = неразобрано.most_common(1)[0]
        приметы.append({"что": f"больше всего неразобранного: {группа} ({раз} пакетов) — вкладка «Неизвестные "
                               "форматы» или «Разбирать как»", "фильтр": ""})
    if найдено:
        приметы.append({"что": f"в потоках найдено файлов: {len(найдено)} — вкладка «Объекты и файлы»", "фильтр": ""})
    return {
        "пакетов": len(сводки), "байт": байт, "длительность": round(длительность, 6),
        "скорость": round(8 * байт / длительность) if длительность > 0 else 0,
        "протоколы": [{"протокол": п, "пакетов": н, "доля": round(н / len(сводки), 4)} for п, н in протоколы.most_common(10)],
        "диалоги": [{к: д[к] for к in ("а", "б", "пакетов", "байт", "протоколы")} for д in диалоги(сводки, "ip")[:5]],
        "ошибок": с_ошибками, "виды_ошибок": ошибки(сводки)[:5],
        "dns": [{"имя": и, "раз": н} for и, н in имена.most_common(10)], "имён_dns": len(имена),
        "sni": [{"имя": и, "раз": н} for и, н in sni.most_common(10)],
        "http": [{"имя": и, "раз": н} for и, н in узлы_http.most_common(10)],
        "файлов": len(найдено), "файлы": найдено[:10],
        "неразобрано": [{"группа": г, "пакетов": н} for г, н in неразобрано.most_common(5)],
        "приметы": приметы,
    }
