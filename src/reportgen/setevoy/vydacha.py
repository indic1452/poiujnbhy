"""Данные вкладок «Анализа пакетов» по отбору — из снимков статистики и с диска, с постоянной памятью.

Что копится по ходу разбора (дерево, диалоги, узлы, ошибки, DNS/HTTP/TLS, обзор,
соотношения узлов дерева, группы неизвестного), берётся из снимка отбора
(``zahvaty.Отбор.снимок``) — запрос отвечает за миллисекунды при любом числе пакетов.
График времени строится по столбцам времени и длины (numpy) — точно как
``statistika.по_времени``. Что требует байт (матрица, столбец, файлы в потоках, поиск
полей неизвестного формата, поток TCP), читается с диска по номерам отбора — по
первым ``…_ДО`` пакетам, если отбор больше (ответ говорит, по скольким).
"""

from __future__ import annotations

import threading
from collections import OrderedDict
from collections.abc import Iterator, Sequence
from typing import Any

import numpy as np

from . import statistika
from .hranilishe import Ряд, нагрузки, отпечаток_потока
from .nakopitel import узел_из_снимка

#: По скольким первым пакетам отбора считать то, что требует байт.
ПРОФИЛЬ_ДО = 100_000
СТОЛБЕЦ_ДО = 200_000
ФАЙЛЫ_ПАКЕТОВ_ДО = 1_000_000
#: Обзор ищет файлы в потоках и собирает объекты сам, когда разбор кончился и отбор не больше этого
#: (иначе — по запросу вкладки «Объекты и файлы»): поиск идёт в процессе сервера, итог запоминается.
ОБЗОР_ЦЕЛИКОМ_ДО = 50_000
#: Сколько строк таблиц отдаёт страница (как прежде).
СТРОК_НА_СТРАНИЦЕ = 2000

_кэш_полей: OrderedDict[tuple, dict[str, Any]] = OrderedDict()
_кэш_замок = threading.Lock()


def пустое_дерево() -> list[dict[str, Any]]:
    return statistika.иерархия([])


def иерархия(отбор) -> list[dict[str, Any]]:
    return отбор.снимок("иерархия") or пустое_дерево()


def диалоги(отбор, уровень: str, полностью: bool = False) -> list[dict[str, Any]]:
    """Диалоги уровня: для страницы — первые СТРОК_НА_СТРАНИЦЕ (лёгкий снимок), для выгрузки — все сохранённые."""
    return (отбор.снимок("диалоги" + (".полный" if полностью else "")) or отбор.снимок("диалоги") or {}).get(уровень, [])


def узлы(отбор, полностью: bool = False) -> list[dict[str, Any]]:
    return отбор.снимок("узлы" + (".полный" if полностью else "")) or отбор.снимок("узлы") or []


def ошибки(отбор) -> list[dict[str, Any]]:
    return отбор.снимок("ошибки") or []


def таблица(отбор, вид: str) -> list[dict[str, Any]]:
    """Строки DNS, HTTP или TLS (каждая — пакет; до потолка накопителя)."""
    return отбор.снимок(вид) or []


def узел_протокола(отбор, путь: list[str]) -> dict[str, Any]:
    return узел_из_снимка(отбор.снимок("узлы_дерева") or {}, путь)


def _времена_длины(отбор) -> tuple[np.ndarray, np.ndarray]:
    х = отбор.х
    if отбор.папка is None:
        n = х.число()
        return х.времена(0, n), х.длины(0, n)
    номера = отбор.номера()
    if not len(номера):
        return np.zeros(0), np.zeros(0, dtype=np.uint32)
    до = int(номера.max()) + 1
    return х.времена(0, до)[номера], х.длины(0, до)[номера]


def по_времени(отбор, столбцов: int = 120) -> dict[str, Any]:
    """Как statistika.по_времени — по столбцам хранилища (те же действия над теми же числами)."""
    времена, длины = _времена_длины(отбор)
    if not len(времена):
        return {"шаг": 0, "начало": 0, "пакетов": [], "байт": []}
    начало = float(времена.min())
    конец = float(времена.max())
    шаг = max((конец - начало) / столбцов, 1e-6)
    i = np.minimum(столбцов - 1, ((времена - начало) / шаг).astype(np.int64))
    пакетов = np.bincount(i, minlength=столбцов)
    байт = np.bincount(i, weights=длины.astype(np.float64), minlength=столбцов)
    return {"шаг": шаг, "начало": начало, "пакетов": [int(x) for x in пакетов],
            "байт": [int(x) for x in байт]}


def время_строками(отбор) -> list[dict[str, Any]]:
    время = по_времени(отбор)
    return [{"начало": round(время["начало"] + i * время["шаг"], 6), "шаг": время["шаг"], "пакетов": п, "байт": б}
            for i, (п, б) in enumerate(zip(время["пакетов"], время["байт"], strict=True))]


def первые(отбор, вид: str, до: int) -> Ряд:
    """Сводки, поля, кадры или нагрузки первых ``до`` пакетов отбора — с диска по мере обращения."""
    return отбор.ряд(вид, до if отбор.число() > до else None)


def неизвестные(отбор, ид_ключ: tuple = ()) -> list[dict[str, Any]]:
    """Как statistika.неизвестные: группы — из снимка, поля неизвестного формата — по первым 5000
    нагрузкам группы (с диска; итог по одной и той же выборке запоминается)."""
    from ..potok import polya  # noqa: PLC0415 — numpy только здесь
    итог = []
    х = отбор.х
    for г in отбор.снимок("неизвестные") or []:
        запись = {"группа": г["группа"], "пакетов": г["пакетов"], "первые": г["первые"], "длины": г["длины"],
                  "что": "", "подробно": []}
        if г["пакетов"] >= 20:
            образцы = г["образцы"][:5000]
            ключ = (*ид_ключ, г["группа"], len(образцы))
            with _кэш_замок:
                найдено = _кэш_полей.get(ключ)
            if найдено is None:
                номера = np.asarray(образцы, dtype=np.int64) - 1
                порядок = np.argsort(номера, kind="stable")
                сводки = х.сводки_по(номера[порядок])
                кадры = х.кадры_по(номера[порядок])
                груз = нагрузки(х, сводки, кадры)
                по_порядку: list[bytes] = [b""] * len(образцы)
                for j, i in enumerate(порядок.tolist()):
                    по_порядку[i] = груз[j] or b""
                н = polya.найти(по_порядку, "пакетов")
                найдено = {"что": н.что, "подробно": list(н.подробно)} if н is not None else {"что": "", "подробно": []}
                with _кэш_замок:
                    _кэш_полей[ключ] = найдено
                    while len(_кэш_полей) > 64:
                        _кэш_полей.popitem(last=False)
            запись.update(найдено)
        else:
            запись["что"] = "мало пакетов для статистики полей (нужно от 20)"
        итог.append(запись)
    return итог


def ряды(отбор, база: str, от: int, до: int) -> tuple[list[dict[str, Any]], list[bytes]]:
    """Сводки и байты (кадр или нагрузка) пакетов отбора [от, до)."""
    номера = отбор.номера(от, до)
    х = отбор.х
    сводки = х.сводки_по(номера)
    кадры = х.кадры_по(номера)
    if база == "payload":
        return сводки, [н or b"" for н in нагрузки(х, сводки, кадры)]
    return сводки, кадры


def матрица(отбор, база: str, начало: int, столбцов: int, смещение: int, строк: int) -> dict[str, Any]:
    """Матрица байт: строки — страница отбора, профиль столбцов — по первым ПРОФИЛЬ_ДО пакетам."""
    число = отбор.число()
    счёт = отбор.снимок("счёт") or {}
    наибольшая = счёт.get("макс_нагрузка" if база == "payload" else "макс_кадр", 0)
    до = min(число, ПРОФИЛЬ_ДО)
    профиль_ряды: list[bytes] = []
    for от in range(0, до, 8192):
        профиль_ряды += ряды(отбор, база, от, min(до, от + 8192))[1]
    сводки, байты = ряды(отбор, база, смещение, смещение + строк)
    итог = {"отобрано": число, "наибольшая_длина": наибольшая,
            "столбцы": statistika.профиль_столбцов(профиль_ряды, начало, столбцов),
            "строки": [{"номер": с["номер"], "протокол": с["протокол"], "длина": len(р),
                        "hex": р[начало:начало + столбцов].hex()} for с, р in zip(сводки, байты, strict=True)]}
    if число > до:
        итог["профиль_по"] = до
    return итог


def столбец(отбор, база: str, место: int, ширина: int) -> dict[str, Any]:
    число = отбор.число()
    до = min(число, СТОЛБЕЦ_ДО)
    все: list[bytes] = []
    for от in range(0, до, 8192):
        все += ряды(отбор, база, от, min(до, от + 8192))[1]
    итог = statistika.столбец(все, место, ширина)
    if число > до:
        итог["по_пакетам"] = до
        итог["всего"] = число
    return итог


def файлы(отбор, предел: int = 64 << 20) -> tuple[list[dict[str, Any]], int]:
    """Файлы в потоках (statistika.файлы) по первым ФАЙЛЫ_ПАКЕТОВ_ДО пакетам отбора; (находки, по скольким)."""
    до = min(отбор.число(), ФАЙЛЫ_ПАКЕТОВ_ДО)
    return statistika.файлы(первые(отбор, "сводки", до), первые(отбор, "нагрузки", до), предел), до


def вырезать(отбор, поток: str, смещение: int, длина: int) -> bytes:
    до = min(отбор.число(), ФАЙЛЫ_ПАКЕТОВ_ДО)
    return statistika.вырезать_из_потока(первые(отбор, "сводки", до), первые(отбор, "нагрузки", до), поток,
                                         смещение, длина)


def поток(х, номер: int) -> dict[str, Any]:
    """«Следовать за потоком» по всей записи: кандидаты — по отпечатку потока (столбец), без чтения сводок."""
    if not 1 <= номер <= х.число():
        raise ValueError("нет такого пакета")
    опорная = х.сводка(номер - 1)
    ключ = statistika.ключ_потока(опорная)
    if ключ is None:
        raise ValueError("у этого пакета нет потока TCP/UDP/SCTP")
    отпечатки = х.потоки()
    свои = np.flatnonzero(отпечатки == np.uint64(отпечаток_потока(ключ)))
    сводки: list[dict[str, Any]] = []
    груз: list[bytes | None] = []
    for от in range(0, len(свои), 4096):
        часть = свои[от:от + 4096]
        с_ = х.сводки_по(часть)
        сводки += с_
        груз += нагрузки(х, с_, х.кадры_по(часть))
    return statistika.поток(сводки, груз, номер)


def обзор(отбор, ход: dict[str, Any]) -> dict[str, Any]:
    """Обзор из снимка; файлы в потоках — сразу, пока отбор не больше ОБЗОР_ЦЕЛИКОМ_ДО."""
    итог = dict(отбор.снимок("обзор") or {"пакетов": 0})
    if not итог.get("пакетов"):
        return {"пакетов": 0}
    число = отбор.число()
    if ход.get("готово") and число <= ОБЗОР_ЦЕЛИКОМ_ДО:
        ключ = ("обзор-файлы", str(отбор.х.папка), отбор.фильтр, число)
        with _кэш_замок:
            найдено = _кэш_полей.get(ключ)
        if найдено is None:
            найдено = statistika.файлы(первые(отбор, "сводки", ОБЗОР_ЦЕЛИКОМ_ДО),
                                       первые(отбор, "нагрузки", ОБЗОР_ЦЕЛИКОМ_ДО), 16 << 20)
            with _кэш_замок:
                _кэш_полей[ключ] = найдено
                while len(_кэш_полей) > 64:
                    _кэш_полей.popitem(last=False)
        итог["файлов"], итог["файлы"] = len(найдено), найдено[:10]
        if найдено:
            итог["приметы"] = [*итог.get("приметы", []),
                               {"что": f"в потоках найдено файлов: {len(найдено)} — вкладка «Объекты и файлы»",
                                "фильтр": ""}]
    else:
        итог["файлов"], итог["файлы"] = None, []
        итог["файлы_заметка"] = ("файлы в потоках ищет вкладка «Объекты и файлы»" if число > ОБЗОР_ЦЕЛИКОМ_ДО
                                 else "файлы в потоках — когда разбор кончится")
    if not ход.get("готово"):
        итог["идёт"] = True
    return итог


def номера_узла(отбор, путь: Sequence[str], до: int | None = None) -> np.ndarray:
    """Номера пакетов отбора (с 0), чей стек начинается путём узла дерева (``до`` — не больше стольких)."""
    путь = list(путь)
    итог: list[np.ndarray] = []
    найдено = 0
    for от in range(0, отбор.число(), 8192):
        номера = отбор.номера(от, от + 8192)
        свои = [н for н, с in zip(номера.tolist(), отбор.х.сводки_по(номера), strict=True) if с["стек"][:len(путь)] == путь]
        итог.append(np.asarray(свои, dtype=np.int64))
        найдено += len(свои)
        if до is not None and найдено >= до:
            break
    номера = np.concatenate(итог) if итог else np.zeros(0, dtype=np.int64)
    return номера[:до] if до is not None else номера


def до_предела_нагрузки(отбор, предел: int) -> int:
    """Сколько первых пакетов отбора уложится в ``предел`` байт нагрузки TCP/UDP (сборка потоков держит их в памяти)."""
    байт, взято = 0, 0
    for от in range(0, отбор.число(), 8192):
        for с in отбор.сводки(от, от + 8192):
            место = с.get("тр") or с.get("тр_с") or с.get("нагр")
            байт += место[1] if место else 0
            if байт > предел:
                return взято
            взято += 1
    return взято


def все_номера(отбор, путь: Sequence[str] = ()) -> np.ndarray:
    return номера_узла(отбор, путь) if путь else отбор.номера()


def сводки_порциями(х, номера: np.ndarray, порция: int = 4096) -> Iterator[list[dict[str, Any]]]:
    for от in range(0, len(номера), порция):
        yield х.сводки_по(номера[от:от + порция])


def таблица_статистики(отбор, вид: str, ид_ключ: tuple = ()) -> list[dict[str, Any]]:
    """Таблица выгрузки статистики (как vygruzka.статистика) — из снимка отбора."""
    if вид == "иерархия":
        return statistika.иерархия_строками(иерархия(отбор)[0])
    if вид.startswith("диалоги-"):
        return диалоги(отбор, вид.split("-", 1)[1], полностью=True)
    if вид == "узлы":
        return узлы(отбор, полностью=True)
    if вид == "время":
        return время_строками(отбор)
    if вид in ("dns", "http", "tls"):
        return таблица(отбор, вид)
    if вид == "ошибки":
        return ошибки(отбор)
    if вид == "неизвестные":
        return неизвестные(отбор, ид_ключ)
    raise ValueError(вид)


