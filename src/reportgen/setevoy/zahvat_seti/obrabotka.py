"""Обработка захвата после остановки: какие порты UDP в нём есть и нагрузка порта — одним потоком.

Файл читается поблочно (pcapng: SHB задаёт порядок байт, IDB — тип канала,
EPB/SPB — пакеты; draft-ietf-opsawg-pcapng), без предела числа пакетов и без
загрузки целиком в память — захват бывает в сотни мегабайт.

Нагрузка порта — тела датаграмм UDP с этим портом получателя подряд, в
порядке прихода; из каждой можно отбросить N байт заголовка или ровно
заголовок RTP (RFC 3550 §5.1: 12 байт + 4·CC, расширение при X = 1 — ещё
4 + 4·длина байт, дополнение при P = 1 — последний октет говорит, сколько
байт с конца отбросить). Упорядочивание по номеру RTP — по расширенному
номеру (16-битный номер с учётом переходов через 65535, RFC 3550 §A.1):
пропуски и перестановки считаются и попадают в заметки.
"""

from __future__ import annotations

import struct
from collections.abc import Iterator
from pathlib import Path
from typing import Any, BinaryIO

from . import zapis

#: Порядок номеров RTP: разница номеров меньше половины круга — вперёд (RFC 3550 §A.1).
ПОЛКРУГА = 1 << 15
КРУГ = 1 << 16
#: RFC 3550 §A.1: скачок номера больше MAX_DROPOUT считается разрывом, а не потерей.
MAX_DROPOUT = 3000


def опции_блока(тело: bytes, место: int, порядок: str) -> dict[int, bytes]:
    """Опции блока pcapng (TLV: код u16, длина u16, значение с дополнением до 4) до opt_endofopt.

    Значение режется по объявленной длине, но не дальше конца тела: испорченная
    длина даёт короткое (или пустое) значение, а не чтение за концом. Повтор кода
    — берётся первое значение.
    """
    итог: dict[int, bytes] = {}
    while место + 4 <= len(тело):
        код, дл = struct.unpack_from(порядок + "HH", тело, место)
        if код == zapis.OPT_ENDOFOPT:
            break
        итог.setdefault(код, тело[место + 4:место + 4 + дл])
        место += 4 + дл + (-дл % 4)
    return итог


def доля_секунды(if_tsresol: bytes) -> float:
    """Единица времени интерфейса: if_tsresol — 10^-v, при старшем бите — 2^-(v & 0x7F); нет опции — 10^-6."""
    if not if_tsresol:
        return 1e-6
    v = if_tsresol[0]
    return 2.0 ** -(v & 0x7F) if v & 0x80 else 10.0 ** -v


def кадры_pcapng(файл: BinaryIO) -> Iterator[tuple[float, bytes, int]]:
    """(время, данные, тип канала) каждого пакета файла pcapng — по одному, потоком."""
    порядок = "<"
    каналы: list[tuple[int, float]] = []
    while True:
        голова = файл.read(8)
        if len(голова) < 8:
            return
        if голова[:4] == b"\x0a\x0d\x0d\x0a":                 # SHB: тип одинаков при любом порядке байт
            магия = файл.read(4)
            порядок = "<" if магия == b"\x4d\x3c\x2b\x1a" else ">"
            каналы = []
            голова += магия
        вид, длина = struct.unpack_from(порядок + "II", голова)
        if длина < len(голова) + 4 or длина % 4:
            return                                      # испорчен — дальше не читаем
        тело = голова[8:] + файл.read(длина - len(голова) - 4)
        if len(тело) + 12 < длина or len(файл.read(4)) < 4:
            return                                      # оборван (захват ещё пишется)
        if вид == zapis.БЛОК_IDB and len(тело) >= 8:
            каналы.append((struct.unpack_from(порядок + "H", тело)[0],
                           доля_секунды(опции_блока(тело, 8, порядок).get(zapis.IF_TSRESOL, b""))))
        elif вид == zapis.БЛОК_EPB and len(тело) >= 20:
            номер, старшие, младшие, записано, _ = struct.unpack_from(порядок + "IIIII", тело)
            if номер < len(каналы):
                тип, доля = каналы[номер]
                yield ((старшие << 32) | младшие) * доля, тело[20:20 + записано], тип


def _в_ethernet(данные: bytes, тип: int) -> bytes | None:
    if тип == zapis.LINKTYPE_ETHERNET:
        return данные
    if тип == zapis.LINKTYPE_RAW:
        return zapis.кадр_из_ip(данные)
    return None


def датаграммы(путь: Path) -> Iterator[tuple[float, zapis.Сведения]]:
    """Разобранные кадры UDP захвата (кадры других протоколов и уровней пропускаются)."""
    with open(путь, "rb") as файл:
        for время, данные, тип in кадры_pcapng(файл):
            кадр = _в_ethernet(данные, тип)
            if кадр is None:
                continue
            с = zapis.разобрать_кадр(кадр)
            if с.протокол == zapis.IP_UDP and с.порт_к >= 0:
                yield время, с


def порты(путь: Path, предел: int = 64) -> list[dict[str, Any]]:
    """Порты получателя UDP в захвате: датаграмм, байт нагрузки, отправители (до 8)."""
    итог: dict[int, dict[str, Any]] = {}
    for _, с in датаграммы(путь):
        п = итог.get(с.порт_к)
        if п is None:
            if len(итог) >= 1024:
                continue
            п = итог[с.порт_к] = {"порт": с.порт_к, "датаграмм": 0, "байт": 0, "источники": {}}
        п["датаграмм"] += 1
        п["байт"] += len(с.нагрузка or b"")
        if с.от not in п["источники"] and len(п["источники"]) < 8:
            п["источники"][с.от] = 0
        if с.от in п["источники"]:
            п["источники"][с.от] += 1
    список = sorted(итог.values(), key=lambda п: -п["датаграмм"])[:предел]
    for п in список:
        п["источники"] = [{"адрес": а, "датаграмм": н} for а, н in п["источники"].items()]
    return список


def заголовок_rtp(данные: bytes) -> tuple[int, int, int, int] | None:
    """RTP (RFC 3550 §5.1): (номер, SSRC, длина заголовка, длина дополнения) или None, если не RTP."""
    if len(данные) < 12 or данные[0] >> 6 != 2:
        return None
    cc = данные[0] & 0x0F
    длина = 12 + 4 * cc
    if данные[0] & 0x10:                                    # X: расширение заголовка
        if len(данные) < длина + 4:
            return None
        длина += 4 + 4 * struct.unpack_from("!H", данные, длина + 2)[0]
    дополнение = данные[-1] if данные[0] & 0x20 else 0      # P: последний октет — сколько отбросить
    if длина + дополнение > len(данные) or (данные[0] & 0x20 and дополнение == 0):
        return None
    номер, ssrc = struct.unpack_from("!H", данные, 2)[0], struct.unpack_from("!I", данные, 8)[0]
    return номер, ssrc, длина, дополнение


def расширить_номера(номера: list[int]) -> list[int]:
    """16-битные номера RTP в порядке прихода → расширенные (с числом кругов), RFC 3550 §A.1."""
    итог: list[int] = []
    наибольший: int | None = None
    for номер in номера:
        if наибольший is None:
            наибольший = номер
            итог.append(номер)
            continue
        разница = (номер - наибольший) % КРУГ
        if разница < ПОЛКРУГА:
            расширенный = наибольший + разница
            наибольший = расширенный
        else:
            расширенный = наибольший - (КРУГ - разница)
        итог.append(расширенный)
    return итог


def нагрузка(путь: Path, порт: int, *, срез: int | str = 0, упорядочить: bool = False,
             источник: str = "", предел: int) -> tuple[bytes, list[str], dict[str, Any]]:
    """Нагрузка порта одним потоком байт, заметки словами и сводка (счётчики)."""
    по_rtp = срез == "rtp"
    нужен_rtp = по_rtp or упорядочить
    куски: list[tuple[int, int, bytes]] = []            # (ssrc, номер, данные)
    сводка = {"датаграмм": 0, "не_rtp": 0, "короче_среза": 0, "фрагменты": 0,
              "пропущено_rtp": 0, "переставлено_rtp": 0, "повторы_rtp": 0, "разрывы_rtp": 0,
              "обрезано_пределом": False, "ssrc": []}
    всего = 0
    for _, с in датаграммы(путь):
        if с.порт_к != порт or (источник and с.от != источник):
            continue
        сводка["датаграмм"] += 1
        if с.нагрузка is None:
            сводка["фрагменты"] += 1
            continue
        данные = с.нагрузка
        ssrc = номер = 0
        if нужен_rtp:
            rtp = заголовок_rtp(данные)
            if rtp is None:
                сводка["не_rtp"] += 1
                continue
            номер, ssrc, длина, дополнение = rtp
            if по_rtp:
                данные = данные[длина:len(данные) - дополнение]
        if not по_rtp and срез:
            if len(данные) < int(срез):
                сводка["короче_среза"] += 1
            данные = данные[int(срез):]
        if всего + len(данные) > предел:
            сводка["обрезано_пределом"] = True
            break
        всего += len(данные)
        куски.append((ssrc, номер, данные))
    if упорядочить and куски:
        куски = _упорядочить(куски, сводка)
    сводка["взято"] = len(куски)
    поток = b"".join(к[2] for к in куски)
    return поток, _заметки(порт, срез, упорядочить, источник, сводка, len(поток)), сводка


def _упорядочить(куски: list[tuple[int, int, bytes]], сводка: dict[str, Any]) -> list[tuple[int, int, bytes]]:
    """По каждому SSRC — по расширенному номеру, без повторов; потоки SSRC — в порядке появления."""
    по_ssrc: dict[int, list[tuple[int, bytes]]] = {}
    for ssrc, номер, данные in куски:
        по_ssrc.setdefault(ssrc, []).append((номер, данные))
    итог: list[tuple[int, int, bytes]] = []
    for ssrc, список in по_ssrc.items():
        расширенные = расширить_номера([н for н, _ in список])
        наибольший = расширенные[0]
        for р in расширенные[1:]:
            if р < наибольший:
                сводка["переставлено_rtp"] += 1
            наибольший = max(наибольший, р)
        порядок = sorted(range(len(список)), key=lambda i: расширенные[i])
        прежний = None
        for i in порядок:
            р = расширенные[i]
            if прежний is not None:
                if р == прежний:
                    сводка["повторы_rtp"] += 1
                    continue
                скачок = р - прежний - 1
                if скачок > MAX_DROPOUT:
                    сводка["разрывы_rtp"] += 1
                else:
                    сводка["пропущено_rtp"] += скачок
            итог.append((ssrc, р, список[i][1]))
            прежний = р
        сводка["ssrc"].append(f"{ssrc:08x}")
    return итог


def _заметки(порт: int, срез: int | str, упорядочить: bool, источник: str, с: dict[str, Any],
             байт: int) -> list[str]:
    заметки = [f"захват с сети: нагрузка UDP порта {порт}" + (f" от {источник}" if источник else "")
               + f" — датаграмм {с['взято']} из {с['датаграмм']}, {байт} байт"]
    if срез == "rtp":
        заметки.append("отброшен заголовок RTP каждой датаграммы (с CSRC, расширением и дополнением)")
    elif срез:
        заметки.append(f"отброшено по {int(срез)} байт в начале каждой датаграммы")
    if с["короче_среза"]:
        заметки.append(f"датаграмм короче среза: {с['короче_среза']} (от них ничего не осталось)")
    if с["не_rtp"]:
        заметки.append(f"не RTP (версия не 2 или заголовок длиннее датаграммы) — пропущено: {с['не_rtp']}")
    if с["фрагменты"]:
        заметки.append(f"фрагментированные датаграммы IP не собираются — пропущено: {с['фрагменты']}")
    if упорядочить:
        заметки.append(f"упорядочено по номеру RTP: переставлено {с['переставлено_rtp']}, "
                       f"пропущено номеров {с['пропущено_rtp']}, повторов убрано {с['повторы_rtp']}"
                       + (f", разрывов нумерации {с['разрывы_rtp']}" if с["разрывы_rtp"] else ""))
        if len(с["ssrc"]) > 1:
            заметки.append("несколько источников RTP (SSRC " + ", ".join(с["ssrc"]) + ") — их потоки идут друг за другом")
    if с["обрезано_пределом"]:
        заметки.append("нагрузка обрезана пределом объёма")
    return заметки
