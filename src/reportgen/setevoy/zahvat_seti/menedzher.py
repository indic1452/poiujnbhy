"""Менеджер захватов с сети: запуск в фоне, живые счётчики, остановка, хранение.

Захват — папка ``<data_dir>/zahvat/<ид>/``: куски ``куски/000000.pcapng``,
``000001.pcapng``… пишутся по мере приёма (цепочка, как dumpcap -b: смена куска по
объёму, числу пакетов или времени; кольцо — хранить последние N кусков), указатель
закрытых кусков ``куски.jsonl`` и ``состояние.json`` — счётчики и итог. Пакеты в
памяти не копятся: каждый сразу уходит в файл, поэтому захват идёт часами и сутками
при любом потоке. Ид создаёт сервер (время и случайный хвост, как у захватов
«Пакетов»), путь от пользователя не берётся — писать вне каталога данных нечем.

Пределы времени, пакетов и объёма — только если их задал человек (или потолки в
настройках сервера). Без них захват останавливает кнопка «Стоп», выключение
сервера — или нехватка места: если свободного места на диске стало меньше запаса
(``запас_диска``, диск делят база и остальные данные сервера), захват честно
останавливается с причиной, а записанное остаётся целым. Против перегрузки: один
захват на карту и один на порт UDP; всего не больше ``ОДНОВРЕМЕННО`` захватов и
``НА_ЧЕЛОВЕКА`` у одного человека.

Петля (lo) — только если разрешил вызывающий (``петля_можно``): на ней ходит
внутренний трафик сервера.
"""

from __future__ import annotations

import collections
import contextlib
import json
import re
import secrets
import shutil
import socket
import threading
import time
from pathlib import Path
from typing import Any

from ...fayly import записать_атомарно
from . import istochniki, karty, zapis
from .istochniki import ОшибкаЗахвата
from .parametry import Параметры
from .pcap_bib import Libpcap, загрузить

#: Сколько законченных захватов хранить на человека.
ХРАНИТЬ = 10
#: Сколько захватов может идти одновременно — на всех и у одного человека.
ОДНОВРЕМЕННО = 4
НА_ЧЕЛОВЕКА = 2
#: Запас свободного места на диске: меньше — захват не начинается, а идущий останавливается.
ЗАПАС_ДИСКА = 256 << 20
#: Сколько разных портов и источников помнить в счётчиках (дальше — «прочие»).
ПОРТОВ_В_СЧЁТЧИКАХ = 64
ИД = re.compile(r"[0-9]{8}-[0-9]{6}-[0-9a-f]{6}")


class Захват:
    """Идущий захват: источник, поток, счётчики."""

    def __init__(self, ид: str, состояние: dict[str, Any], источник: istochniki.Источник,
                 фильтр_py: Any, ключи: list[str]):
        self.ид = ид
        self.с = состояние
        self.источник = источник
        self.фильтр = фильтр_py
        self.ключи = ключи
        self.стоп = threading.Event()
        self.причина = ""
        self.поток: threading.Thread | None = None
        self.цепочка: zapis.ЦепочкаPcapng | None = None
        self.таймер: threading.Timer | None = None
        self.отсчёты: collections.deque[tuple[float, int, int]] = collections.deque(maxlen=16)


def новый_ид() -> str:
    return time.strftime("%Y%m%d-%H%M%S-") + secrets.token_hex(3)


def номер_карты(карта: dict[str, Any]) -> int:
    """Номер карты в системе (ifindex): Windows — IfIndex из GetAdaptersAddresses, иначе по имени
    (if_nametoindex(3)); 0 — неизвестен."""
    if карта.get("индекс"):
        return int(карта["индекс"])
    try:
        return socket.if_nametoindex(str(карта.get("ид") or ""))
    except (OSError, ValueError, AttributeError):
        return 0


class Менеджер:
    def __init__(self, папка: Path, *, путь_libpcap: str = "", потолок_секунд: int = 0,
                 потолок_байт: int = 0, фабрика_сокетов: Any = None, запас_диска: int = ЗАПАС_ДИСКА,
                 кусок_до: int = 0):
        """``потолок_секунд``/``потолок_байт`` — потолки из настроек (0 — без потолка);
        ``кусок_до`` — наибольший кусок цепочки, байт (0 — без ограничения сверху)."""
        self.папка = Path(папка)
        self.путь_libpcap = путь_libpcap
        self.потолок_секунд = потолок_секунд
        self.потолок_байт = потолок_байт
        self.запас_диска = запас_диска
        self.кусок_до = кусок_до
        self.фабрика = фабрика_сокетов
        self._lock = threading.Lock()
        self._идут: dict[str, Захват] = {}
        self._занято: dict[str, str] = {}
        self._бронь_места: dict[str, int] = {}     # ид → предел объёма захвата, байт (у захватов с пределом)
        self._прервать_прежние()

    # -- что умеет машина ----------------------------------------------------------------

    def библиотека(self) -> tuple[Libpcap | None, str]:
        return загрузить(self.путь_libpcap)

    def возможности(self) -> dict[str, dict[str, Any]]:
        lib, причина = self.библиотека()
        return istochniki.возможности(lib, причина, фабрика=self.фабрика)

    def карты(self) -> tuple[list[dict[str, Any]], list[str]]:
        lib, _ = self.библиотека()
        устройства = None
        заметки: list[str] = []
        if lib is not None:
            try:
                устройства = lib.устройства()
            except OSError as ошибка:
                заметки.append(f"список устройств libpcap: {ошибка}")
        список, ещё = karty.перечень(устройства)
        with self._lock:
            занято = dict(self._занято)
            идут = {ид: з.с for ид, з in self._идут.items()}
        for к in список:
            ид = занято.get("карта:" + к["ид"])
            к["занята"] = {"ид": ид, "кто": идут[ид].get("кто", "")} if ид in идут else None
        return список, заметки + ещё

    # -- запуск и остановка --------------------------------------------------------------

    def свободно(self) -> int:
        """Свободное место на диске папки захватов, байт (папки ещё нет — на диске её родителя)."""
        for место in (self.папка, self.папка.parent):
            if место.exists():
                return shutil.disk_usage(место).free
        return 0

    def _недописано(self) -> int:
        """Сколько ещё могут дописать начатые захваты (и те, что открываются): бронь минус записанное.
        Вызывать под self._lock."""
        итог = 0
        for ид, байт in self._бронь_места.items():
            з = self._идут.get(ид)
            записано = з.цепочка.записано if з is not None and з.цепочка is not None else 0
            итог += max(0, байт - записано)
        return итог

    def начать(self, п: Параметры, *, владелец: int, кто: str, петля_можно: bool = False) -> str:
        """Открыть источник (ошибки — сразу, понятными словами) и запустить поток приёма.

        ``петля_можно`` — можно ли снимать петлю (решает вызывающий: только создателю системы)."""
        карта: dict[str, Any] | None = None
        if п.режим == "карта" or п.карта:
            список, _ = self.карты()
            карта = next((к for к in список if к["ид"] == п.карта), None)
            if карта is None:
                raise ОшибкаЗахвата(f"карты «{п.карта}» на этой машине нет", "адрес")
        if п.режим == "карта" and карта is not None and карта.get("петля") and not петля_можно:
            raise ОшибкаЗахвата("петлю снимает только создатель системы: на ней ходит внутренний трафик "
                                "сервера (сессии, запросы к службам)", "права")
        ключи = [f"udp:{порт}" for порт in п.порты] if п.режим == "udp" else [f"карта:{п.карта}"]
        ид = новый_ид()
        with self._lock:
            свободно = self.свободно()
            недописано = self._недописано()
            if свободно - недописано < п.байт + self.запас_диска:
                идущие = f", из них {недописано >> 20} МБ ещё допишут идущие захваты" if недописано else ""
                предел = f"предел захвата {п.байт >> 20} МБ и " if п.байт else ""
                raise ОшибкаЗахвата(f"мало места на диске сервера: свободно {свободно >> 20} МБ{идущие}, "
                                    f"а нужно {предел}запас {self.запас_диска >> 20} МБ", "занято")
            if len(self._идут) >= ОДНОВРЕМЕННО:
                raise ОшибкаЗахвата(f"на сервере уже идут {ОДНОВРЕМЕННО} захвата — дождитесь их конца", "занято")
            if sum(1 for з in self._идут.values() if з.с["владелец"] == владелец) >= НА_ЧЕЛОВЕКА:
                raise ОшибкаЗахвата(f"у вас уже идут {НА_ЧЕЛОВЕКА} захвата — остановите один", "занято")
            for ключ in ключи:
                if ключ in self._занято:
                    чей = getattr(self._идут.get(self._занято[ключ]), "с", {"имя": "запускается", "кто": ""})
                    что = f"порт UDP {ключ[4:]} уже занят" if ключ.startswith("udp:") else "карта уже занята"
                    raise ОшибкаЗахвата(f"{что} захватом «{чей['имя']}» ({чей.get('кто') or 'другой человек'})",
                                        "занято")
            for ключ in ключи:
                self._занято[ключ] = ид                  # бронь — до открытия источника
            if п.байт:
                self._бронь_места[ид] = п.байт
        try:
            return self._запустить(ид, п, карта, ключи, владелец=владелец, кто=кто)
        except BaseException:
            with self._lock:
                for ключ in ключи:
                    if self._занято.get(ключ) == ид:
                        del self._занято[ключ]
                self._бронь_места.pop(ид, None)
            raise

    def _источник(self, п: Параметры, карта: dict[str, Any] | None) -> tuple[istochniki.Источник, str, list[str]]:
        заметки: list[str] = []
        if п.режим == "udp":
            карта_ipv4, индекс = "", 0
            if п.группа and карта is not None:
                карта_ipv4 = next((а["адрес"] for а in карта.get("ipv4") or []), "")
                индекс = номер_карты(карта)
            источник = istochniki.ПриёмUDP(п.адрес, п.порты, группа=п.группа, карта_ipv4=карта_ipv4, индекс=индекс,
                                           **({"фабрика": self.фабрика} if self.фабрика else {}))
            if п.группа:
                if карта is not None and (карта_ipv4 or индекс):
                    заметки.append(f"группа {п.группа} — на карте {карта.get('имя') or карта['ид']}")
                elif источник.любой:
                    заметки.append(f"группа {п.группа} — на карте, которую выбрала система (по маршруту): "
                                   "карта не выбрана")
            if источник.любой and not источник.pktinfo:
                заметки.append("слушаются все адреса: адрес получателя в заголовке IP неизвестен и записан нулями")
            заметки.append("заголовки Ethernet/IP/UDP синтезированы: сокет отдаёт только нагрузку (MAC — нули)")
            return источник, "udp", заметки
        assert карта is not None
        способ = istochniki.выбрать_способ(self.возможности(), п.способ)
        выражение = п.фильтр.bpf()
        if способ in ("npcap", "libpcap"):
            lib, _ = self.библиотека()
            assert lib is not None
            устройство = карта.get("устройство_pcap")
            if not устройство:
                raise ОшибкаЗахвата("Npcap не видит эту карту (нет устройства \\Device\\NPF_…)", "нет")
            return istochniki.ЗахватPcap(lib, устройство, фильтр=выражение, фильтр_без_vlan=п.фильтр.bpf(vlan=False),
                                         неразборчиво=п.неразборчиво), способ, заметки
        if способ == "af_packet":
            программа = None
            lib, _ = self.библиотека()
            if выражение and lib is not None and карта.get("arphrd") in (karty.ARPHRD_ETHER, karty.ARPHRD_LOOPBACK):
                try:
                    программа = lib.скомпилировать(выражение)
                except OSError as ошибка:
                    заметки.append(f"BPF не собран ({ошибка}) — отбор идёт в программе")
            return istochniki.ЗахватAFPacket(карта["ид"], arphrd=карта.get("arphrd") or 1, неразборчиво=п.неразборчиво,
                                             bpf=программа, bpf_текст=выражение if программа else "",
                                             **({"фабрика": self.фабрика} if self.фабрика else {})), способ, заметки
        ipv4 = [а["адрес"] for а in карта.get("ipv4", [])]
        if not ipv4:
            raise ОшибкаЗахвата("у карты нет адреса IPv4 — сырой сокет SIO_RCVALL слушать нечего", "нет")
        заметки.append("SIO_RCVALL: видны только пакеты IPv4 (без ARP и IPv6); заголовок Ethernet синтезирован")
        return istochniki.ЗахватSioRcvall(ipv4[0], **({"фабрика": self.фабрика} if self.фабрика else {})), способ, заметки

    def _запустить(self, ид: str, п: Параметры, карта: dict[str, Any] | None, ключи: list[str], *,
                   владелец: int, кто: str) -> str:
        источник, способ, заметки = self._источник(п, карта)
        папка = self.папка / ид
        з: Захват | None = None
        try:
            папка.mkdir(parents=True, exist_ok=True)
            имя_карты = (карта or {}).get("имя") or ""
            описание = (карта or {}).get("описание") or ""
            if п.режим == "udp":
                подпись = f"UDP {п.адрес}:{','.join(map(str, п.порты))}"
            else:
                подпись = f"{имя_карты} ({способ})"
            имя = п.имя or (time.strftime("%d.%m %H:%M ") + подпись)
            ipv4 = (карта or {}).get("ipv4") or []
            mac = bytes.fromhex((карта or {}).get("mac", "").replace(":", "")) if (карта or {}).get("mac") else b""
            интерфейс = dict(
                канал=источник.канал, имя=((карта or {}).get("устройство_pcap") or п.карта or подпись),
                описание=(имя_карты + (" — " + описание if описание else "")) or подпись,
                фильтр=источник.bpf or (п.фильтр.bpf() if п.режим == "карта" else ""),
                mac=mac if len(mac) == 6 else b"",
                ipv4=(ipv4[0]["адрес"], ipv4[0]["префикс"] or 32) if ipv4 and п.режим == "карта" else None,
                скорость=(карта or {}).get("скорость") or 0)
            начато = time.time()
            состояние = {
                "ид": ид, "владелец": владелец, "кто": кто, "имя": имя, **п.в_словарь(), "способ": способ,
                "карта_имя": имя_карты, "канал": источник.канал, "bpf": источник.bpf,
                "состояние": "идёт", "причина": "", "ошибка": "", "заметки": заметки,
                "начато": начато, "закончено": None, "принято": 0, "отфильтровано": 0, "пакетов": 0,
                "байт": 0, "отброшено": None, "файл_байт": 0, "на_диске": 0, "кусков": 1, "кусков_удалено": 0,
                "по_портам": {}, "источники": {}, "скорость_пакетов": 0.0, "скорость_бит": 0.0,
            }
            фильтр_py = None if п.режим == "udp" or п.фильтр.пуст() else п.фильтр
            з = Захват(ид, состояние, источник, фильтр_py, ключи)
            с = состояние
            з.цепочка = zapis.ЦепочкаPcapng(
                папка, интерфейс=интерфейс, байт_куска=п.кусок_байт, пакетов_куска=п.кусок_пакетов,
                секунд_куска=п.кусок_секунд, кусков=п.кольцо,
                счётчики=lambda: dict(начало=с["начато"], конец=time.time(), принято=с["принято"],
                                      отброшено=с["отброшено"],
                                      отфильтровано_принято=с["принято"] - с["отфильтровано"],
                                      доставлено=с["пакетов"]))
            состояние["файл_байт"] = состояние["на_диске"] = з.цепочка.записано
            з.поток = threading.Thread(target=self._работать, args=(з, п), daemon=True, name=f"reportgen-zahvat-{ид}")
            if п.секунд:
                з.таймер = threading.Timer(п.секунд, self.остановить, args=(ид, "достигнут предел времени"))
                з.таймер.daemon = True
            with self._lock:
                self._идут[ид] = з
            self._записать(ид, состояние)
            з.поток.start()                              # дальше источник и файлы закрывает поток
        except BaseException:
            # Что бы ни упало до старта потока (запись SHB/IDB, адрес или MAC карты, нет места),
            # дескриптор pcap с неразборчивым режимом, файл и папка не остаются висеть.
            with self._lock:
                self._идут.pop(ид, None)
            with contextlib.suppress(Exception):
                источник.закрыть()
            if з is not None and з.цепочка is not None:
                with contextlib.suppress(Exception):
                    з.цепочка.закрыть()
            shutil.rmtree(папка, ignore_errors=True)
            raise
        if з.таймер is not None:
            з.таймер.start()
        return ид

    def _работать(self, з: Захват, п: Параметры) -> None:
        с = з.с
        цепочка = з.цепочка
        assert цепочка is not None
        конец_времени = с["начато"] + п.секунд if п.секунд else None
        сохранено = 0.0
        ethernet = з.источник.канал == zapis.LINKTYPE_ETHERNET
        try:
            while not з.стоп.is_set():
                if конец_времени is not None and time.time() >= конец_времени:
                    з.причина = з.причина or "достигнут предел времени"
                    break
                пачка = з.источник.прочитать(0.2)
                # Приём UDP сам знает порт и отправителя каждой датаграммы — кадр не разбирается.
                готовые = getattr(з.источник, "сведения", None) if з.фильтр is None else None
                for i, (время, кадр, длина) in enumerate(пачка):
                    с["принято"] += 1
                    сведения = zapis.разобрать_кадр(кадр) if ethernet and готовые is None else None
                    if з.фильтр is not None and сведения is not None and not з.фильтр.подходит(сведения):
                        с["отфильтровано"] += 1
                        continue
                    # Предел объёма — по всем кускам с их заголовками и итогами: не переходится ни на байт.
                    if п.байт and цепочка.записано + цепочка.стоимость(время, len(кадр)) + zapis.ISB_НАИБОЛЬШИЙ > п.байт:
                        з.причина = "достигнут предел объёма"
                        break
                    цепочка.пакет(время, кадр, длина)
                    с["пакетов"] += 1
                    с["байт"] += len(кадр)
                    if готовые is not None:
                        порт_к, от, нагрузка = готовые[i]
                        self._учесть(с["по_портам"], str(порт_к), нагрузка)
                        self._учесть(с["источники"], от, 0)
                    elif сведения is not None and сведения.протокол == zapis.IP_UDP and сведения.порт_к >= 0:
                        self._учесть(с["по_портам"], str(сведения.порт_к), len(сведения.нагрузка or b""))
                        self._учесть(с["источники"], f"{сведения.от}:{сведения.порт_от}", 0)
                    if п.пакетов and с["пакетов"] >= п.пакетов:
                        з.причина = "достигнут предел пакетов"
                        break
                if з.причина:
                    break
                сейчас = time.time()
                if not з.отсчёты or сейчас - з.отсчёты[-1][0] >= 0.25:
                    з.отсчёты.append((сейчас, с["пакетов"], с["байт"]))
                if сейчас - сохранено >= 1.0:
                    self._обновить(з)
                    self._записать(з.ид, с)
                    сохранено = сейчас
                    свободно = self.свободно()
                    if свободно < self.запас_диска:
                        з.причина = (f"мало места на диске сервера: свободно {свободно >> 20} МБ, запас "
                                     f"{self.запас_диска >> 20} МБ — захват остановлен, записанное цело")
                        break
        except ОшибкаЗахвата as ошибка:
            с["ошибка"] = str(ошибка)
        except OSError as ошибка:
            # Запись куска не удалась (диск кончился раньше проверки, сняли носитель): честно и без падения.
            с["ошибка"] = f"запись захвата прервана: {ошибка.strerror or ошибка}"
        except Exception as ошибка:                  # noqa: BLE001 — поток не роняет сервер
            с["ошибка"] = f"{type(ошибка).__name__}: {ошибка}"
        finally:
            if з.таймер is not None:
                з.таймер.cancel()
            try:
                self._обновить(з)
            finally:
                з.источник.закрыть()
            try:
                цепочка.закрыть()                    # итог ISB последнего куска и строка указателя
            except (OSError, ValueError) as ошибка:
                с["заметки"] = [*с["заметки"], f"последний кусок закрыт без итога: {ошибка}"]
            с.update(состояние="ошибка" if с["ошибка"] else "готово",
                     причина=з.причина or ("ошибка захвата" if с["ошибка"] else "остановлен"),
                     закончено=time.time(), файл_байт=цепочка.записано, на_диске=цепочка.на_диске(),
                     кусков=цепочка.номер + 1, кусков_удалено=цепочка.удалено_кусков,
                     скорость_пакетов=0.0, скорость_бит=0.0)
            with self._lock:
                self._идут.pop(з.ид, None)
                self._бронь_места.pop(з.ид, None)
                for ключ in з.ключи:
                    if self._занято.get(ключ) == з.ид:
                        del self._занято[ключ]
            self._записать(з.ид, с)
            self._прибрать(с["владелец"])

    @staticmethod
    def _учесть(счётчики: dict[str, Any], ключ: str, байт: int) -> None:
        if ключ not in счётчики and len(счётчики) >= ПОРТОВ_В_СЧЁТЧИКАХ:
            ключ = "прочие"
        запись = счётчики.setdefault(ключ, [0, 0])
        запись[0] += 1
        запись[1] += байт

    @staticmethod
    def _обновить(з: Захват) -> None:
        """Счётчики, которые не считаются на каждом пакете: потери ядра, размер и число кусков."""
        с = з.с
        with contextlib.suppress(OSError, ОшибкаЗахвата):
            с["отброшено"] = з.источник.отброшено()
        ц = з.цепочка
        if ц is not None:
            с.update(файл_байт=ц.записано, на_диске=ц.на_диске(), кусков=ц.номер + 1,
                     кусков_удалено=ц.удалено_кусков)
            with contextlib.suppress(OSError, ValueError):
                ц.сбросить()

    @staticmethod
    def скорость(отсчёты: list[tuple[float, int, int]], сейчас: float, пакетов: int, байт: int,
                 окно: float = 3.0) -> tuple[float, float]:
        """Пакетов/с и бит/с за последние ``окно`` секунд: от самого раннего отсчёта в окне
        (или последнего до него) до «сейчас». Без трафика отсчёты не копятся — скорость падает к нулю."""
        база = None
        for отсчёт in отсчёты:
            if отсчёт[0] >= сейчас - окно:
                база = база or отсчёт
                break
            база = отсчёт
        if база is None or сейчас <= база[0]:
            return 0.0, 0.0
        прошло = сейчас - база[0]
        return round((пакетов - база[1]) / прошло, 1), round((байт - база[2]) * 8 / прошло, 1)

    def остановить(self, ид: str, причина: str = "остановлен по команде", *, ждать: float = 5.0) -> bool:
        """Остановить захват; True — он шёл. Повторный вызов безвреден."""
        with self._lock:
            з = self._идут.get(ид)
        if з is None:
            return False
        if not з.причина:
            з.причина = причина
        з.стоп.set()
        with contextlib.suppress(Exception):
            з.источник.прервать()
        if з.поток is not None and з.поток is not threading.current_thread() and ждать:
            з.поток.join(ждать)
        return True

    def остановить_все(self) -> None:
        with self._lock:
            иды = list(self._идут)
        for ид in иды:
            self.остановить(ид, "сервер выключается")

    # -- чтение -------------------------------------------------------------------------

    def состояние(self, ид: str) -> dict[str, Any]:
        """Состояние захвата (живое, если идёт); KeyError — нет такого."""
        if not ИД.fullmatch(ид or ""):
            raise KeyError(ид)
        with self._lock:
            з = self._идут.get(ид)
            if з is not None:
                с = dict(з.с)
                с["по_портам"] = dict(з.с["по_портам"])
                с["источники"] = dict(з.с["источники"])
                сейчас = time.time()
                if з.цепочка is not None:
                    ц = з.цепочка
                    с.update(файл_байт=ц.записано, на_диске=ц.на_диске(), кусков=ц.номер + 1,
                             кусков_удалено=ц.удалено_кусков)
                с["длится"] = round(сейчас - с["начато"], 1)
                с["скорость_пакетов"], с["скорость_бит"] = self.скорость(list(з.отсчёты), сейчас, с["пакетов"], с["байт"])
                return с
        путь = self.папка / ид / "состояние.json"
        try:
            с = json.loads(путь.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            raise KeyError(ид) from None
        с["длится"] = round((с.get("закончено") or с["начато"]) - с["начато"], 1)
        return с

    def список(self, владелец: int) -> list[dict[str, Any]]:
        итог = []
        for папка in sorted(self.папка.glob("*"), reverse=True) if self.папка.is_dir() else []:
            if not ИД.fullmatch(папка.name):
                continue
            try:
                с = self.состояние(папка.name)
            except KeyError:
                continue
            if с.get("владелец") == владелец:
                итог.append({к: с.get(к) for к in ("ид", "имя", "режим", "способ", "состояние", "причина",
                                                    "начато", "закончено", "пакетов", "байт", "порты",
                                                    "карта_имя", "длится", "на_диске", "кусков")})
        return итог

    def идущие(self) -> list[dict[str, Any]]:
        with self._lock:
            return [{"ид": з.ид, "имя": з.с["имя"], "кто": з.с.get("кто", ""), "режим": з.с["режим"],
                     "порты": з.с["порты"], "карта": з.с["карта"]} for з in self._идут.values()]

    def куски(self, ид: str) -> list[dict[str, Any]]:
        """Куски захвата по порядку: закрытые — из указателя, идущий — последним («идёт»: True).
        У каждого: номер, путь, есть ли файл (кольцо удаляет старшие), пакетов, байт, первый
        номер пакета во всём захвате, время первого и последнего пакета. KeyError — нет захвата."""
        if not ИД.fullmatch(ид or ""):
            raise KeyError(ид)
        папка = self.папка / ид
        if not (папка / "состояние.json").is_file():
            raise KeyError(ид)
        итог: dict[int, dict[str, Any]] = {з["кусок"]: dict(з) for з in zapis.прочитать_указатель(папка)}
        with self._lock:
            з = self._идут.get(ид)
            if з is not None and з.цепочка is not None and з.цепочка.сведения:
                ц = з.цепочка
                итог[ц.номер] = {**ц.сведения, "байт": ц.писатель.записано if ц.писатель else 0, "идёт": True}
        for путь in (папка / zapis.КУСКИ).glob("*.pcapng"):
            if путь.stem.isdigit() and int(путь.stem) not in итог:
                # Кусок без строки указателя — оборван перезапуском сервера: сведения — по файлу.
                итог[int(путь.stem)] = {"кусок": int(путь.stem), "файл": путь.name, "пакетов": None,
                                        "байт": путь.stat().st_size, "оборван": True}
        список = [итог[к] for к in sorted(итог)]
        for к in список:
            путь = папка / zapis.КУСКИ / zapis.имя_куска(к["кусок"])
            к["путь"] = путь
            к["есть"] = путь.is_file()
        return список

    def файлы(self, ид: str) -> list[Path]:
        """Файлы кусков, что есть на диске, по порядку (для обработки и выгрузки)."""
        return [к["путь"] for к in self.куски(ид) if к["есть"]]

    def отметить(self, ид: str, **поля: Any) -> dict[str, Any]:
        """Дописать в состояние захвата, куда ушли его куски после обработки. У идущего — в живое
        состояние (его сохраняет поток захвата), у законченного — в файл."""
        with self._lock:
            з = self._идут.get(ид)
            if з is not None:
                з.с.update(поля)
                return dict(з.с)
        с = self.состояние(ид)
        с.pop("длится", None)
        с.update(поля)
        self._записать(ид, с)
        return с

    def удалить(self, ид: str) -> None:
        if not ИД.fullmatch(ид or ""):
            raise KeyError(ид)
        with self._lock:
            if ид in self._идут:
                raise ValueError("захват ещё идёт — сначала остановите")
        shutil.rmtree(self.папка / ид, ignore_errors=True)

    # -- служебное ----------------------------------------------------------------------

    def _записать(self, ид: str, состояние: dict[str, Any]) -> None:
        with contextlib.suppress(OSError):
            записать_атомарно(self.папка / ид / "состояние.json", json.dumps(состояние, ensure_ascii=False))

    def _прервать_прежние(self) -> None:
        """Захваты, шедшие при прошлом запуске сервера, — «прерван»: файл цел, итога нет."""
        for путь in self.папка.glob("*/состояние.json") if self.папка.is_dir() else []:
            try:
                с = json.loads(путь.read_text(encoding="utf-8"))
            except (OSError, ValueError):
                continue
            if с.get("состояние") == "идёт":
                с.update(состояние="прерван", причина="сервер перезапускался во время захвата: записанное "
                         "цело, у последнего куска нет итога", закончено=путь.stat().st_mtime)
                self._записать(путь.parent.name, с)

    def _прибрать(self, владелец: int) -> None:
        свои = [з for з in self.список(владелец) if з["состояние"] != "идёт"]
        for з in свои[ХРАНИТЬ:]:
            shutil.rmtree(self.папка / з["ид"], ignore_errors=True)
