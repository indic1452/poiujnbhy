"""Статистика захвата по ходу разбора: пакет за пакетом, с постоянной памятью.

``Накопитель`` получает сводку и поля каждого пакета (как они ложатся в хранилище) и
держит всё, что показывает вкладка «Анализ пакетов»: дерево протоколов с долями и
«кончаются здесь», диалоги Ethernet/IP/TCP/UDP, узлы, ошибки, таблицы DNS/HTTP/TLS,
обзор (протоколы, имена, приметы), неизвестные форматы и соотношения каждого узла
дерева. Итог тот же, что у функций ``statistika`` над всеми пакетами сразу (это
проверяют тесты), — пока таблицы не упираются в потолки: сверх потолка новые ключи не
заводятся, а в снимке об этом сказано («неполно»). Числа пакетов и байт при этом
остаются точными.

``снимок()`` отдаёт разделы для страницы; фоновый разбор пишет их на диск раз в
секунду (крупные — реже, чтобы запись не съедала разбор).
"""

from __future__ import annotations

import heapq
import re
from collections import Counter, defaultdict
from typing import Any

from .statistika import ОТКРЫТЫЕ, уровень_протокола

#: Потолки: сколько ключей держать в таблицах (сверх — не заводятся, снимок отмечает «неполно»). Подобраны так,
#: чтобы работа держала не больше ~200 МБ при любом трафике (десять людей — десять таких работ сразу).
ДИАЛОГОВ_ДО = 50_000
УЗЛОВ_ДО = 50_000
УЗЛОВ_ДЕРЕВА_ДО = 5000
СТРОК_ДО = 20_000
ИМЁН_ДО = 50_000
НАБОР_DNS_ДО = 100_000
ПАР_УЗЛА_ДО = 4096
ПАР_ВСЕГО_ДО = 100_000
АДРЕСОВ_УЗЛА_ДО = 8192
ГРУПП_ДО = 256
ОБРАЗЦОВ = 5000
ЖДУТ_HTTP_ДО = 20_000
#: Сколько строк таблиц отдавать в снимке (страница показывает первые 2000, выгрузка — все сохранённые).
ДИАЛОГОВ_В_СНИМКЕ = 20_000
УЗЛОВ_В_СНИМКЕ = 20_000

РАЗДЕЛЫ = ("счёт", "иерархия", "диалоги", "узлы", "ошибки", "dns", "http", "tls", "обзор", "узлы_дерева",
           "неизвестные")
#: Поля пакета, которые читает накопитель (всё остальное он берёт из сводки), и протоколы, у которых он их
#: читает: разбор пачками передаёт сшивке только их (``поля_накопителя``), а не все поля каждого пакета.
ПОЛЯ = ("dns.flags.response", "dns.qry.name", "dns.qry.type", "dns.a", "dns.aaaa", "dns.cname", "dns.flags.rcode",
        "dns.id", "http.request.method", "http.host", "http.request.uri", "http.user_agent", "http.response.code",
        "tls.handshake.type", "tls.handshake.extensions_server_name", "tls.handshake.extensions_alpn_str",
        "tls.handshake.extensions.supported_version")
ПОЛЯ_У = frozenset({"DNS", "mDNS", "LLMNR", "HTTP", "TLS"})
_ПРИСТАВКА = re.compile(r"^(исходный|собранный) ")


class _Узел:
    __slots__ = ("пакетов", "байт", "дети", "первый", "последний", "пары", "адреса", "неполно")

    def __init__(self):
        self.пакетов = 0
        self.байт = 0
        self.дети: dict[str, _Узел] = {}
        self.первый: tuple[float, int] | None = None
        self.последний: tuple[float, int] | None = None
        self.пары: dict[tuple[str, str], list] = {}
        self.адреса: set[str] = set()
        self.неполно = False


class Накопитель:
    def __init__(self):
        self.пакетов = 0
        self.байт = 0
        self.время_от: float | None = None
        self.время_до: float | None = None
        self.корень = _Узел()
        self.узлов_дерева = 1
        self.пар_всего = 0
        self.диалоги: dict[str, dict[tuple, list]] = {у: {} for у in ("eth", "ip", "tcp", "udp")}
        self.диалогов_мимо: Counter = Counter()
        self.узлы: dict[str, list] = {}
        self.узлов_мимо = 0
        self.ошибки: dict[str, dict[str, Any]] = {}
        self.протоколы: Counter = Counter()
        self.с_ошибками = 0
        self.dns: list[dict[str, Any]] = []
        self.dns_всего = 0
        self.http: list[dict[str, Any]] = []
        self.http_всего = 0
        self.ждут_http: defaultdict = defaultdict(list)
        self.ждут_http_всего = 0
        self.tls: list[dict[str, Any]] = []
        self.tls_всего = 0
        self.имена_dns: Counter = Counter()
        self.sni: Counter = Counter()
        self.узлы_http: Counter = Counter()
        self.запросы_dns: set = set()
        self.ответы_dns: set = set()
        self.tcp_суммы = 0
        self.tcp_всего = 0
        self.открытые: Counter = Counter()
        self.неразобрано: Counter = Counter()
        self.неизвестные: dict[str, dict[str, Any]] = {}
        self.макс_кадр = 0
        self.макс_нагрузка = 0
        #: Потоки TCP/UDP (для «Выходных данных»: сколько сырых потоков выгрузится).
        self.потоки: set[tuple] = set()
        self.неполно: set[str] = set()
        #: Какие разделы изменились с последнего снимка (фоновый разбор пишет только их).
        self.грязные: set[str] = set(РАЗДЕЛЫ)

    # -- пакет --

    def добавить(self, с: dict[str, Any], п: dict[str, list[Any]], длина_кадра: int = 0) -> None:
        длина, время, номер, стек = с["длина"], с["время"], с["номер"], с["стек"]
        self.пакетов += 1
        self.байт += длина
        if self.время_от is None or время < self.время_от:
            self.время_от = время
        if self.время_до is None or время > self.время_до:
            self.время_до = время
        self.макс_кадр = max(self.макс_кадр, длина_кадра)
        нагр = с.get("нагр")
        if нагр:
            self.макс_нагрузка = max(self.макс_нагрузка, нагр[1])
        грязные = self.грязные
        грязные.update(("счёт", "иерархия", "обзор", "узлы_дерева"))
        self._дерево(с, стек, длина, время, номер)
        набор = set(стек)
        self._диалоги(с, набор, длина, время)
        if "IPv4" in набор or "IPv6" in набор:
            self._узлы(с, длина)
        if с["ошибки"]:
            self._ошибки(с)
        self.протоколы[с["протокол"]] += 1
        if "DNS" in набор or "mDNS" in набор or "LLMNR" in набор:
            self._dns(с, п)
        if "HTTP" in набор:
            self._http(с, п)
        if "TLS" in набор:
            self._tls(с, п)
        if с.get("порт_от") is not None and ("TCP" in набор or "UDP" in набор):
            ключ = ("TCP" in набор, *sorted(((с["источник"], с["порт_от"]), (с["получатель"], с["порт_к"]))))
            if ключ in self.потоки or len(self.потоки) < ДИАЛОГОВ_ДО:
                self.потоки.add(ключ)
            else:
                self.неполно.add("потоки TCP/UDP: больше потолка — посчитаны не все")
        if "TCP" in набор:
            self.tcp_всего += 1
        # Как statistika.обзор: ошибки суммы TCP считаются у всех пакетов (у собранных — и без уровня TCP в стеке).
        if с["ошибки"] and any(о.startswith("TCP: контрольная") for о in с["ошибки"]):
            self.tcp_суммы += 1
        for протокол in стек:
            if протокол in ОТКРЫТЫЕ:
                self.открытые[протокол] += 1
        if стек and стек[-1] == "Данные":
            свои = [п_ for п_ in стек if п_ != "Данные"]
            верх = свои[-1] if свои else "кадры"
            if с.get("порт_от") is not None:
                группа = f"{верх} порт {min(с['порт_от'], с['порт_к'])}"
                self.неразобрано[группа] += 1
            else:
                группа = верх
            if нагр and нагр[1]:
                self._неизвестный(группа, номер, нагр[1])

    def _дерево(self, с: dict[str, Any], стек: list[str], длина: int, время: float, номер: int) -> None:
        а, б = с["источник"], с["получатель"]
        # Пара адресов и сторона — одни на все уровни пакета (считаются один раз).
        if а and б:
            ключ = (а, б) if а <= б else (б, а)
            сторона = 0 if а == ключ[0] else 2
        else:
            ключ = None
            сторона = 0
        узел = self.корень
        self._узел(узел, ключ, сторона, а, б, длина, время, номер)
        for протокол in стек:
            следующий = узел.дети.get(протокол)
            if следующий is None:
                if self.узлов_дерева >= УЗЛОВ_ДЕРЕВА_ДО:
                    self.неполно.add("дерево протоколов: узлов больше потолка — лишние сведены в «…прочие»")
                    протокол = "…прочие"
                    следующий = узел.дети.get(протокол)
                if следующий is None:
                    следующий = узел.дети[протокол] = _Узел()
                    self.узлов_дерева += 1
            узел = следующий
            self._узел(узел, ключ, сторона, а, б, длина, время, номер)

    def _узел(self, узел: _Узел, ключ: tuple | None, сторона: int, а: str, б: str, длина: int, время: float,
              номер: int) -> None:
        узел.пакетов += 1
        узел.байт += длина
        # Соотношения узла (statistika.узел_протокола): первый — с наименьшим временем (первый из равных),
        # последний — с наибольшим (последний из равных).
        первый = узел.первый
        if первый is None or время < первый[0]:
            узел.первый = (время, номер)
        последний = узел.последний
        if последний is None or время >= последний[0]:
            узел.последний = (время, номер)
        if ключ is None:
            return
        з = узел.пары.get(ключ)
        if з is None:
            if len(узел.пары) >= ПАР_УЗЛА_ДО or self.пар_всего >= ПАР_ВСЕГО_ДО:
                узел.неполно = True
                return
            з = узел.пары[ключ] = [0, 0, 0, 0]
            self.пар_всего += 1
            адреса = узел.адреса
            if len(адреса) < АДРЕСОВ_УЗЛА_ДО:
                адреса.add(а)
                адреса.add(б)
            elif а not in адреса or б not in адреса:
                узел.неполно = True
        з[сторона] += 1
        з[сторона + 1] += длина

    def _диалоги(self, с: dict[str, Any], набор: set[str], длина: int, время: float) -> None:
        for уровень in ("eth", "ip", "tcp", "udp"):
            if уровень == "eth":
                if not с.get("mac"):
                    continue
                а, б = с["mac"]
            elif уровень == "tcp" or уровень == "udp":
                if уровень.upper() not in набор or с.get("порт_от") is None:
                    continue
                а, б = f"{с['источник']}:{с['порт_от']}", f"{с['получатель']}:{с['порт_к']}"
            else:
                if "IPv4" not in набор and "IPv6" not in набор:
                    continue
                а, б = с["источник"], с["получатель"]
            ключ = (а, б) if а <= б else (б, а)
            таблица = self.диалоги[уровень]
            з = таблица.get(ключ)
            if з is None:
                if len(таблица) >= ДИАЛОГОВ_ДО:
                    self.диалогов_мимо[уровень] += 1
                    continue
                з = таблица[ключ] = [0, 0, 0, 0, время, время, Counter()]
                self.грязные.add("диалоги")
            if а == ключ[0]:
                з[0] += 1
                з[1] += длина
            else:
                з[2] += 1
                з[3] += длина
            if время < з[4]:
                з[4] = время
            if время > з[5]:
                з[5] = время
            з[6][с["протокол"]] += 1
        self.грязные.add("диалоги")

    def _узлы(self, с: dict[str, Any], длина: int) -> None:
        self.грязные.add("узлы")
        for адрес, сторона in ((с["источник"], 2), (с["получатель"], 3)):
            у = self.узлы.get(адрес)
            if у is None:
                if len(self.узлы) >= УЗЛОВ_ДО:
                    self.узлов_мимо += 1
                    continue
                у = self.узлы[адрес] = [0, 0, 0, 0, Counter()]
            у[0] += 1
            у[1] += длина
            у[сторона] += длина
            порт = с.get("порт_к") if сторона == 3 else с.get("порт_от")
            if порт is not None and порт < 1024:
                у[4][порт] += 1

    def _ошибки(self, с: dict[str, Any]) -> None:
        self.с_ошибками += 1
        self.грязные.add("ошибки")
        for текст in с["ошибки"]:
            вид = текст.split(":")[0] + ": " + текст.split(":", 1)[-1].split("(")[0].strip() if ":" in текст else текст
            з = self.ошибки.get(вид)
            if з is None:
                з = self.ошибки[вид] = {"что": вид, "пакетов": 0, "первые": []}
            з["пакетов"] += 1
            if len(з["первые"]) < 20:
                з["первые"].append(с["номер"])

    def _сосчитать(self, счёт: Counter, ключ: Any, что: str) -> None:
        if ключ in счёт or len(счёт) < ИМЁН_ДО:
            счёт[ключ] += 1
        else:
            self.неполно.add(f"{что}: различных больше {ИМЁН_ДО} — редкие не учтены")

    def _dns(self, с: dict[str, Any], п: dict[str, list[Any]]) -> None:
        ответ = bool(п.get("dns.flags.response", [0])[0])
        з = {"номер": с["номер"], "время": с["время"], "клиент": с["получатель"] if ответ else с["источник"],
             "сервер": с["источник"] if ответ else с["получатель"], "ответ": ответ,
             "имя": ", ".join(map(str, п.get("dns.qry.name", []))),
             "тип": ", ".join(map(str, п.get("dns.qry.type", []))),
             "ответы": ", ".join(map(str, п.get("dns.a", []) + п.get("dns.aaaa", []) + п.get("dns.cname", []))),
             "код": п.get("dns.flags.rcode", [""])[0] if ответ else "",
             "ид": п.get("dns.id", [None])[0],
             "порт": с.get("порт_к") if ответ else с.get("порт_от")}
        self.dns_всего += 1
        self.грязные.add("dns")
        if len(self.dns) < СТРОК_ДО:
            self.dns.append(з)
        ключ = (з["клиент"], з["порт"], з["ид"])
        if not ответ:
            if з["имя"]:
                self._сосчитать(self.имена_dns, з["имя"], "имена DNS")
            набор = self.запросы_dns
        else:
            набор = self.ответы_dns
        if ключ in набор or len(набор) < НАБОР_DNS_ДО:
            набор.add(ключ)
        else:
            self.неполно.add("DNS без ответа: запросов больше потолка — посчитаны не все")

    def _http(self, с: dict[str, Any], п: dict[str, list[Any]]) -> None:
        self.грязные.add("http")
        ключ = (с["источник"], с.get("порт_от"), с["получатель"], с.get("порт_к"))
        if "http.request.method" in п:
            запись = {"номер": с["номер"], "время": с["время"], "клиент": с["источник"], "сервер": с["получатель"],
                      "метод": п["http.request.method"][0], "узел": (п.get("http.host") or [""])[0],
                      "адрес": (п.get("http.request.uri") or [""])[0], "код": "",
                      "агент": (п.get("http.user_agent") or [""])[0]}
            self.http_всего += 1
            if len(self.http) < СТРОК_ДО:
                self.http.append(запись)
            if запись["узел"]:
                self._сосчитать(self.узлы_http, запись["узел"], "узлы HTTP")
            if self.ждут_http_всего < ЖДУТ_HTTP_ДО:
                self.ждут_http[ключ].append(запись)
                self.ждут_http_всего += 1
            else:
                self.неполно.add("HTTP: запросов без ответа больше потолка — коды ответов у части не сопоставлены")
        elif "http.response.code" in п:
            обратный = (с["получатель"], с.get("порт_к"), с["источник"], с.get("порт_от"))
            ждут = self.ждут_http.get(обратный)
            if ждут:
                ждут.pop(0)["код"] = п["http.response.code"][0]
                self.ждут_http_всего -= 1
                if not ждут:
                    del self.ждут_http[обратный]

    def _tls(self, с: dict[str, Any], п: dict[str, list[Any]]) -> None:
        if "ClientHello" not in [str(т) for т in п.get("tls.handshake.type", [])]:
            return
        self.грязные.add("tls")
        з = {"номер": с["номер"], "время": с["время"], "клиент": с["источник"], "сервер": с["получатель"],
             "порт": с.get("порт_к"), "sni": (п.get("tls.handshake.extensions_server_name") or [""])[0],
             "alpn": (п.get("tls.handshake.extensions_alpn_str") or [""])[0],
             "версии": (п.get("tls.handshake.extensions.supported_version") or [""])[0]}
        self.tls_всего += 1
        if len(self.tls) < СТРОК_ДО:
            self.tls.append(з)
        if з["sni"]:
            self._сосчитать(self.sni, з["sni"], "имена TLS")

    def _неизвестный(self, группа: str, номер: int, длина: int) -> None:
        self.грязные.add("неизвестные")
        г = self.неизвестные.get(группа)
        if г is None:
            if len(self.неизвестные) >= ГРУПП_ДО:
                self.неполно.add(f"неизвестные форматы: групп больше {ГРУПП_ДО} — новые не заводятся")
                return
            г = self.неизвестные[группа] = {"пакетов": 0, "мин": длина, "макс": длина, "образцы": []}
        г["пакетов"] += 1
        г["мин"] = min(г["мин"], длина)
        г["макс"] = max(г["макс"], длина)
        if len(г["образцы"]) < ОБРАЗЦОВ:
            г["образцы"].append(номер)

    # -- снимок --

    def длительность(self) -> float:
        return round(self.время_до - self.время_от, 6) if self.пакетов else 0.0

    def раздел(self, имя: str) -> Any:
        return getattr(self, "_р_" + имя)()

    def снимок(self, разделы: tuple[str, ...] = РАЗДЕЛЫ) -> dict[str, Any]:
        return {имя: self.раздел(имя) for имя in разделы}

    def _р_счёт(self) -> dict[str, Any]:
        return {"пакетов": self.пакетов, "байт": self.байт, "время_от": self.время_от, "время_до": self.время_до,
                "длительность": self.длительность(), "макс_кадр": self.макс_кадр,
                "макс_нагрузка": self.макс_нагрузка, "неполно": sorted(self.неполно),
                "диалогов": {у: len(т) for у, т in self.диалоги.items()},
                "диалогов_мимо": dict(self.диалогов_мимо), "узлов": len(self.узлы), "узлов_мимо": self.узлов_мимо,
                "dns": self.dns_всего, "http": self.http_всего, "tls": self.tls_всего, "с_ошибками": self.с_ошибками,
                "потоков": len(self.потоки), "tcp": self.tcp_всего, "tcp_суммы": self.tcp_суммы, "пар": self.пар_всего,
                "узлов_дерева": self.узлов_дерева}

    def _р_иерархия(self) -> list[dict[str, Any]]:
        """Как statistika.иерархия."""
        def в_список(имя: str, у: _Узел, предки: tuple[str, ...], корень: bool) -> dict[str, Any]:
            дети = sorted((в_список(к, д, предки + (() if корень else (имя,)), False) for к, д in у.дети.items()),
                          key=lambda д: -д["пакетов"])
            return {"протокол": имя, "пакетов": у.пакетов, "байт": у.байт,
                    "уровень": "все" if корень else уровень_протокола(имя, предки),
                    "кончаются": у.пакетов - sum(д["пакетов"] for д in дети),
                    "кончаются_байт": у.байт - sum(д["байт"] for д in дети),
                    "дети": дети}

        итог = в_список("Кадры", self.корень, (), True)
        итог["длительность"] = self.длительность()
        return [итог]

    def _р_диалоги(self) -> dict[str, list[dict[str, Any]]]:
        """Как statistika.диалоги (первые ДИАЛОГОВ_В_СНИМКЕ по байтам) — по уровням."""
        итог = {}
        for уровень, таблица in self.диалоги.items():
            лучшие = heapq.nlargest(ДИАЛОГОВ_В_СНИМКЕ, таблица.items(), key=lambda кз: кз[1][1] + кз[1][3])
            итог[уровень] = [{"а": к[0], "б": к[1], "пакетов_аб": з[0], "байт_аб": з[1], "пакетов_ба": з[2],
                              "байт_ба": з[3], "начало": з[4], "конец": з[5],
                              "протоколы": ", ".join(f"{п} ×{н}" for п, н in з[6].most_common(4)),
                              "пакетов": з[0] + з[2], "байт": з[1] + з[3], "длительность": round(з[5] - з[4], 6)}
                             for к, з in лучшие]
        return итог

    def _р_узлы(self) -> list[dict[str, Any]]:
        """Как statistika.узлы (первые УЗЛОВ_В_СНИМКЕ по байтам)."""
        лучшие = heapq.nlargest(УЗЛОВ_В_СНИМКЕ, self.узлы.items(), key=lambda кз: кз[1][1])
        return [{"адрес": а, "пакетов": у[0], "байт": у[1], "отправлено": у[2], "получено": у[3],
                 "службы": ", ".join(str(п) for п, _ in у[4].most_common(5))} for а, у in лучшие]

    def _р_ошибки(self) -> list[dict[str, Any]]:
        return sorted(({**з, "первые": list(з["первые"])} for з in self.ошибки.values()), key=lambda з: -з["пакетов"])

    def _р_dns(self) -> list[dict[str, Any]]:
        return list(self.dns)

    def _р_http(self) -> list[dict[str, Any]]:
        return [dict(з) for з in self.http]

    def _р_tls(self) -> list[dict[str, Any]]:
        return list(self.tls)

    def _р_обзор(self) -> dict[str, Any]:
        """Как statistika.обзор — без файлов в потоках (их ищет страница по запросу)."""
        if not self.пакетов:
            return {"пакетов": 0}
        длительность = self.время_до - self.время_от
        без_ответа = self.запросы_dns - self.ответы_dns
        приметы = []
        if self.открытые:
            приметы.append({"что": "открытым текстом: " + ", ".join(f"{п} ×{н}" for п, н in self.открытые.most_common()),
                            "фильтр": " or ".join(п.lower() for п in self.открытые)})
        if без_ответа and self.ответы_dns:
            приметы.append({"что": f"DNS-запросов без ответа: {len(без_ответа)} из {len(self.запросы_dns)}",
                            "фильтр": "dns"})
        if self.tcp_суммы and self.tcp_суммы >= 0.5 * self.tcp_всего:
            приметы.append({"что": "у большинства TCP не сошлась сумма — похоже, запись сделана на передающем узле "
                                   "(сумму считает сетевая карта), а не на порчу", "фильтр": "expert and tcp"})
        if self.неразобрано:
            группа, раз = self.неразобрано.most_common(1)[0]
            приметы.append({"что": f"больше всего неразобранного: {группа} ({раз} пакетов) — вкладка «Неизвестные "
                                   "форматы» или «Разбирать как»", "фильтр": ""})
        диалоги = self._р_диалоги_ip(5)
        return {
            "пакетов": self.пакетов, "байт": self.байт, "длительность": round(длительность, 6),
            "скорость": round(8 * self.байт / длительность) if длительность > 0 else 0,
            "протоколы": [{"протокол": п, "пакетов": н, "доля": round(н / self.пакетов, 4)}
                          for п, н in self.протоколы.most_common(10)],
            "диалоги": [{к: д[к] for к in ("а", "б", "пакетов", "байт", "протоколы")} for д in диалоги],
            "ошибок": self.с_ошибками, "виды_ошибок": self._р_ошибки()[:5],
            "dns": [{"имя": и, "раз": н} for и, н in self.имена_dns.most_common(10)], "имён_dns": len(self.имена_dns),
            "sni": [{"имя": и, "раз": н} for и, н in self.sni.most_common(10)],
            "http": [{"имя": и, "раз": н} for и, н in self.узлы_http.most_common(10)],
            "неразобрано": [{"группа": г, "пакетов": н} for г, н in self.неразобрано.most_common(5)],
            "приметы": приметы,
        }

    def _р_диалоги_ip(self, сколько: int) -> list[dict[str, Any]]:
        лучшие = heapq.nlargest(сколько, self.диалоги["ip"].items(), key=lambda кз: кз[1][1] + кз[1][3])
        return [{"а": к[0], "б": к[1], "пакетов": з[0] + з[2], "байт": з[1] + з[3],
                 "протоколы": ", ".join(f"{п} ×{н}" for п, н in з[6].most_common(4))} for к, з in лучшие]

    def _р_узлы_дерева(self) -> dict[str, dict[str, Any]]:
        """Соотношения каждого узла дерева (как statistika.узел_протокола), ключ — путь «Ethernet/IPv4/TCP»."""
        итог: dict[str, dict[str, Any]] = {}

        def обойти(у: _Узел, путь: tuple[str, ...]) -> None:
            for имя, д in ([("", у)] if not путь and у is self.корень else []) + list(у.дети.items()):
                п = путь + ((имя,) if имя else ())
                направления = heapq.nlargest(10, д.пары.items(), key=lambda кз: кз[1][1] + кз[1][3])
                итог["/".join(п)] = {
                    "направления": [{"а": к[0], "б": к[1], "пакетов_аб": з[0], "байт_аб": з[1], "пакетов_ба": з[2],
                                     "байт_ба": з[3]} for к, з in направления],
                    "диалогов": len(д.пары), "узлов": len(д.адреса),
                    "первый": {"номер": д.первый[1], "время": д.первый[0]} if д.первый else None,
                    "последний": {"номер": д.последний[1], "время": д.последний[0]} if д.последний else None,
                    **({"неполно": True} if д.неполно else {})}
                if д is not у:
                    обойти(д, п)

        обойти(self.корень, ())
        return итог

    def _р_неизвестные(self) -> list[dict[str, Any]]:
        """Группы неизвестной нагрузки (первые 12 по числу пакетов) с номерами образцов — поля по ним
        ищет страница по запросу (statistika.неизвестные)."""
        лучшие = sorted(self.неизвестные.items(), key=lambda г: -г[1]["пакетов"])[:12]
        return [{"группа": к, "пакетов": г["пакетов"], "первые": г["образцы"][:10], "длины": f"{г['мин']}–{г['макс']}",
                 "образцы": list(г["образцы"])} for к, г in лучшие]


def поля_накопителя(стек: list[str], поля: dict[str, list[Any]]) -> dict[str, list[Any]] | None:
    """Те поля пакета, что нужны накопителю (``ПОЛЯ``), или None — у пакета их нет (нет DNS, HTTP, TLS):
    ``добавить(сводка, поля_накопителя(…) or {})`` даёт ту же статистику, что и со всеми полями."""
    if ПОЛЯ_У.isdisjoint(стек):
        return None
    return {к: поля[к] for к in ПОЛЯ if к in поля}


def узел_из_снимка(узлы_дерева: dict[str, Any], путь: list[str]) -> dict[str, Any]:
    """Соотношения узла по пути; пустой путь или нет такого — как у statistika.узел_протокола без пакетов."""
    return узлы_дерева.get("/".join(путь)) or {"направления": [], "диалогов": 0, "узлов": 0, "первый": None,
                                               "последний": None}


def без_приставки(протокол: str) -> str:
    return _ПРИСТАВКА.sub("", протокол)
