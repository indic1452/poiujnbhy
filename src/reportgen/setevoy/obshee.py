"""Общее состояние разбора захвата: то, что тянется от пакета к пакету.

Разбор одного пакета почти всегда зависит только от его байт. Исключения — то, что
захват «помнит»: потоки RTP/RTCP/UDPTL, описанные в SDP (SIP, MGCP), каналы данных
FTP (PORT/PASV/EPRT/EPSV), вызовы SIP, шаблоны NetFlow v9/IPFIX и договорённость LCP
о коротких номерах MP. Это общий словарь захвата (``Разбор.шаблоны``) и правило
«ppp:mp» в ``Разбор.как``.

Разборщики обращаются к нему только **действиями** этого модуля (``сделать``):
каждое действие — функция над «доступом» к словарю (взять, задать, завести раздел),
её итог — всё, что из состояния узнаёт разбор. Так разбор пачками (``pachki``)
проверяет пакеты, разобранные отдельно от начала файла: исполнитель разбирает пачку
со своим словарём (``Журнал``) и записывает действия каждого пакета; сшивка
повторяет их по порядку над настоящим состоянием (``повторить``) — совпали итоги
всех действий пакета, значит, и разбор пакета тот же, что при разборе файла
подряд (разбор детерминирован, а из состояния он узнаёт только итоги действий), и
записи пакета применяются; не совпали — пакет разбирается заново с настоящим
состоянием.
"""

from __future__ import annotations

from collections.abc import Callable
from typing import Any

#: Ключи общего словаря захвата (их же видит выгрузка шаблоны.json и подробный разбор пакета).
ПОТОКИ = "sdp-потоки"                  # «адрес|порт» → [номер пакета SDP, описание потока]
КАНАЛЫ_FTP = "ftp-data"                # «адрес|порт» → [номер пакета, назначение]
ПОСЛЕДНИЙ_FTP = "ftp-data-последний"   # ключ последнего объявленного канала (на верхнем уровне)
ВЫЗОВЫ = "sip-вызовы"                  # Call-ID → [номер первого пакета, от, к]
КАК = "как"                            # «раздел» действия чтения правила ``Разбор.как`` (не словарь шаблонов)


class Журнал(dict):
    """Общий словарь захвата, который ещё и записывает действия текущего пакета (``записи``)."""

    def __init__(self, *args: Any, **kwargs: Any):
        super().__init__(*args, **kwargs)
        self.записи: list[tuple[str, tuple, Any]] = []


class Доступ:
    """Чтение и запись общего словаря: раздел (словарь внутри) и ключ; раздел None — верхний уровень."""

    __slots__ = ("ш",)

    def __init__(self, ш: dict):
        self.ш = ш

    def взять(self, раздел: str | None, ключ: Any) -> Any:
        if раздел is None:
            return self.ш.get(ключ)
        словарь = self.ш.get(раздел)
        return None if словарь is None else словарь.get(ключ)

    def задать(self, раздел: str | None, ключ: Any, значение: Any) -> None:
        if раздел is None:
            self.ш[ключ] = значение
        else:
            self.ш.setdefault(раздел, {})[ключ] = значение

    def завести(self, раздел: str) -> None:
        self.ш.setdefault(раздел, {})


class Наложение:
    """Доступ поверх словаря без его изменения: записи копятся и применяются ``применить()`` (по порядку)
    — или отбрасываются. Им сшивка проверяет пакет, не трогая настоящее состояние до конца проверки."""

    def __init__(self, ш: dict):
        self.ш = ш
        self._основа = Доступ(ш)
        self._новое: dict[tuple, Any] = {}
        self._порядок: list[tuple] = []

    def взять(self, раздел: str | None, ключ: Any) -> Any:
        к = (раздел, ключ)
        if к in self._новое:
            return self._новое[к]
        return self._основа.взять(раздел, ключ)

    def задать(self, раздел: str | None, ключ: Any, значение: Any) -> None:
        self._новое[(раздел, ключ)] = значение
        self._порядок.append(("з", раздел, ключ, значение))

    def завести(self, раздел: str) -> None:
        self._порядок.append(("р", раздел, None, None))

    def применить(self) -> None:
        for вид, раздел, ключ, значение in self._порядок:
            if вид == "з":
                self._основа.задать(раздел, ключ, значение)
            else:
                self._основа.завести(раздел)
        self._новое.clear()
        self._порядок.clear()


ДЕЙСТВИЯ: dict[str, Callable[..., Any]] = {}


def действие(имя: str) -> Callable[[Callable[..., Any]], Callable[..., Any]]:
    def зарегистрировать(функция: Callable[..., Any]) -> Callable[..., Any]:
        ДЕЙСТВИЯ[имя] = функция
        return функция
    return зарегистрировать


def сделать(р: Any, имя: str, *аргументы: Any) -> Any:
    """Действие разборщика над общим словарём захвата (``р.шаблоны``); у ``Журнал`` — записывается."""
    ш = р.шаблоны
    итог = ДЕЙСТВИЯ[имя](Доступ(ш), *аргументы)
    if type(ш) is Журнал:
        ш.записи.append((имя, аргументы, итог))
    return итог


def правило(р: Any, ключ: str) -> Any:
    """Правило «разбирать как», которое меняет сам захват (сейчас — «ppp:mp» после LCP с опцией 18)."""
    значение = р.как.get(ключ)
    ш = р.шаблоны
    if type(ш) is Журнал:
        ш.записи.append((КАК, (ключ,), значение))
    return значение


def повторить(записи: list[tuple[str, tuple, Any]], ш: dict, как: dict) -> bool:
    """Повторить действия пакета над настоящим состоянием ``ш`` (и правилами ``как``): все итоги совпали —
    записи применены, True; нет — состояние не тронуто, False (пакет надо разобрать заново)."""
    наложение = Наложение(ш)
    for имя, аргументы, итог in записи:
        if имя == КАК:
            if как.get(аргументы[0]) != итог:
                return False
            continue
        if ДЕЙСТВИЯ[имя](наложение, *аргументы) != итог:
            return False
    наложение.применить()
    return True


# -- действия ------------------------------------------------------------------------------------

@действие("sdp+")
def _sdp_запомнить(д: Доступ, номер: int, потоки: list[tuple[str, dict]]) -> None:
    д.завести(ПОТОКИ)
    for ключ, описание in потоки:
        д.задать(ПОТОКИ, ключ, [номер, описание])


@действие("sdp?")
def _sdp_найти(д: Доступ, ключ: str, номер: int) -> dict | None:
    """Описание потока на «адрес|порт», объявленного раньше этого пакета, или None."""
    запись = д.взять(ПОТОКИ, ключ)
    return запись[1] if запись is not None and запись[0] < номер else None


@действие("ftp+")
def _ftp_канал(д: Доступ, ключ: str, номер: int, откуда: str) -> None:
    д.задать(КАНАЛЫ_FTP, ключ, [номер, откуда])
    д.задать(None, ПОСЛЕДНИЙ_FTP, ключ)


@действие("ftp=")
def _ftp_назначение(д: Доступ, текст: str) -> None:
    """Команда передачи (RETR, STOR, LIST…) — назначение последнего объявленного канала."""
    ключ = д.взять(None, ПОСЛЕДНИЙ_FTP)
    запись = None if ключ is None else д.взять(КАНАЛЫ_FTP, ключ)
    if запись is not None:
        д.задать(КАНАЛЫ_FTP, ключ, [запись[0], текст])


@действие("ftp?")
def _ftp_найти(д: Доступ, ключ: str, номер: int) -> str | None:
    """Назначение канала данных на «адрес|порт», объявленного раньше этого пакета, или None."""
    запись = д.взять(КАНАЛЫ_FTP, ключ)
    return запись[1] if запись is not None and запись[0] < номер else None


@действие("sip+")
def _sip_вызов(д: Доступ, call_id: str, значение: list) -> None:
    д.завести(ВЫЗОВЫ)
    if д.взять(ВЫЗОВЫ, call_id) is None:
        д.задать(ВЫЗОВЫ, call_id, значение)


@действие("nf+")
def _netflow_запомнить(д: Доступ, ключ: str, номер: int, поля: list) -> None:
    """Шаблон NetFlow v9/IPFIX: новая версия — если отличается от последней."""
    версии = д.взять(None, ключ) or []
    if not версии or версии[-1][1] != поля:
        д.задать(None, ключ, [*версии, [номер, поля]])


@действие("nf?")
def _netflow_найти(д: Доступ, ключ: str, номер: int) -> list[tuple] | None:
    """Последнее определение шаблона, пришедшее не позже этого пакета."""
    годные = [поля for н, поля in (д.взять(None, ключ) or []) if н <= номер]
    return [tuple(x) for x in годные[-1]] if годные else None
