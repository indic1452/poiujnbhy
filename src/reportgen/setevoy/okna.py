"""Записи захвата окнами: pcap, pcapng и .sig/.dpo — с любого места, где начинается запись.

Разбор пачками (``pachki``) делит файл на пачки по границам записей и разбирает их
параллельно. Для этого запись нужно уметь читать не только с начала файла, а с любой
границы: у каждой границы есть **начало** — небольшой словарь со всем, что нужно
читателю с этого места (вид файла, порядок байт, единица времени и канал pcap,
интерфейсы и время последнего пакета pcapng — его берёт SPB, разметка .sig). Файл
читается окнами (``ОКНО`` байт), записи разбираются в памяти окна — без чтения файла
целиком и без обращения к диску на каждую запись.

Поведение — ровно как у ``chtenie.ЧтецЗахвата`` (тот читает по записи с начала, это
сверяют тесты): те же записи, те же места данных в файле, те же заметки об оборванном
хвосте и испорченной записи.
"""

from __future__ import annotations

import struct
from pathlib import Path
from typing import Any

from .zahvat_seti.chtec import БЛОК_ДО, PCAP_МАГИИ, SHB, ЗАПИСЬ_ДО, доля_секунды, канал_по_типу, опции_блока

#: Окно чтения файла.
ОКНО = 4 << 20
_ЗАПИСЬ_PCAP = {порядок: struct.Struct(порядок + "IIII") for порядок in "<>"}
_ГОЛОВА_БЛОКА = {порядок: struct.Struct(порядок + "II") for порядок in "<>"}
_ДЛИНА = {порядок: struct.Struct(порядок + "I") for порядок in "<>"}
_EPB = {порядок: struct.Struct(порядок + "IIIII") for порядок in "<>"}
_OPB = {порядок: struct.Struct(порядок + "HHIIII") for порядок in "<>"}
_IDB = {порядок: struct.Struct(порядок + "HHI") for порядок in "<>"}


def начало_файла(путь: str | Path, *, готов: bool) -> tuple[dict[str, Any] | None, str, list[str]]:
    """Вид файла и начало первой записи: (начало, формат, заметки). Начало None — байт пока мало
    (файл ещё грузится); не захват — ValueError."""
    from .chtenie import PCAP_МАГИИ as МАГИИ  # noqa: PLC0415
    from .chtenie import PCAPNG_МАГИЯ, SIG_ПРОБА, SIG_ЦЕЛИКОМ_ДО, выбрать_разметку_sig  # noqa: PLC0415
    путь = Path(путь)
    размер = путь.stat().st_size
    with open(путь, "rb") as ф:
        проба = ф.read(min(размер, SIG_ПРОБА))
    if len(проба) < 4 and not готов:
        return None, "", []
    if проба[:4] in МАГИИ:
        if len(проба) < 24:
            if not готов:
                return None, "", []
            # Заголовок файла оборван: записей нет (как у ЧтецЗахвата — «файл оборван»).
            return ({"вид": "pcap", "место": размер, "номер": 1, "порядок": "<", "доля": 1e-6, "канал": "",
                     "время": 0.0}, "pcap", ["файл оборван: последний пакет записан не целиком"])
        порядок, доля = PCAP_МАГИИ[проба[:4]]
        канал = канал_по_типу(struct.unpack_from(порядок + "I", проба, 20)[0])
        return {"вид": "pcap", "место": 24, "номер": 1, "порядок": порядок, "доля": доля, "канал": канал,
                "время": 0.0}, "pcap", []
    if проба[:4] == PCAPNG_МАГИЯ:
        return {"вид": "pcapng", "место": 0, "номер": 1, "порядок": "<", "интерфейсы": [], "время": 0.0}, "pcapng", []
    if not готов and len(проба) < SIG_ПРОБА:
        return None, "", []                      # .sig судим по пробе — ждём, пока наберётся
    if готов and размер <= SIG_ЦЕЛИКОМ_ДО:
        from ..potok.chtenie import разметка_sig  # noqa: PLC0415
        разметка = разметка_sig(путь)
        if разметка is None:
            raise ValueError("файл не похож на сетевую запись: ни pcap, ни pcapng, ни .sig (кадры с длиной)")
        return ({"вид": "sig", "место": разметка["смещение"], "номер": 1, "порядок": разметка["порядок"],
                 "включает": разметка["включает"]}, ".sig", [разметка["формат"], *разметка["заметки"]])
    разметка_ = выбрать_разметку_sig(проба)
    if разметка_ is None:
        raise ValueError("файл не похож на сетевую запись: ни pcap, ни pcapng, ни .sig (кадры с длиной)")
    смещение, порядок, включает = разметка_
    заметка = (f".Sig: длина в заголовке — два байта, {'старший' if порядок == 'big' else 'младший'} байт "
               f"первым, {'включая' if включает else 'без'} сам заголовок"
               + (f"; в начале файла свой заголовок в {смещение} байт" if смещение else "")
               + f"; разметка выбрана по первым {len(проба) >> 20 or 1} МБ")
    return {"вид": "sig", "место": смещение, "номер": 1, "порядок": порядок, "включает": включает}, ".sig", [заметка]


class Окна:
    """Записи файла от ``начало`` подряд, окнами.

    ``следующая(размер)`` — запись (время, данные, исходная длина, канал, место данных) или ``None`` —
    целой записи до ``размер`` байт файла нет (файл кончился или ещё дописывается); ``испорчен`` — почему
    дальше читать нельзя. ``начало()`` — начало следующей записи (его можно отдать другому читателю).
    ``данные=False`` — данные записей не нужны (разметка пачек): вместо них — пустые байты.
    """

    def __init__(self, путь: str | Path, начало: dict[str, Any], *, данные: bool = True, окно: int = ОКНО):
        self.путь = Path(путь)
        self.вид = начало["вид"]
        self.место = int(начало["место"])
        self.номер = int(начало.get("номер", 1))
        self.порядок = начало.get("порядок", "<")
        self.доля = начало.get("доля", 1e-6)
        self.канал = начало.get("канал", "")
        self.интерфейсы: list[tuple[str, float, int]] = [tuple(и) for и in начало.get("интерфейсы", [])]
        self.время = float(начало.get("время", 0.0))
        self.включает = bool(начало.get("включает", False))
        self.нужны_данные = данные
        self.размер_окна = окно
        self.испорчен = ""
        self._файл = open(self.путь, "rb")  # noqa: SIM115 — закрывает закрыть()
        self._окно = b""
        self._с = 0

    def закрыть(self) -> None:
        self._файл.close()

    def __enter__(self) -> Окна:
        return self

    def __exit__(self, *_: Any) -> None:
        self.закрыть()

    def начало(self) -> dict[str, Any]:
        итог: dict[str, Any] = {"вид": self.вид, "место": self.место, "номер": self.номер, "порядок": self.порядок}
        if self.вид == "pcap":
            итог.update(доля=self.доля, канал=self.канал, время=self.время)
        elif self.вид == "pcapng":
            итог.update(интерфейсы=[list(и) for и in self.интерфейсы], время=self.время)
        else:
            итог["включает"] = self.включает
        return итог

    def _байты(self, место: int, сколько: int, размер: int) -> bytes | None:
        """Байты [место, место + сколько) или None — их ещё нет в файле (его ``размер`` байт)."""
        if место + сколько > размер:
            return None
        от = место - self._с
        if от < 0 or от + сколько > len(self._окно):
            self._файл.seek(место)
            self._окно = self._файл.read(max(сколько, min(self.размер_окна, размер - место)))
            self._с = место
            if len(self._окно) < сколько:
                return None
            от = 0
        return self._окно[от:от + сколько]

    def следующая(self, размер: int) -> tuple[float, bytes, int, str, int] | None:
        if self.испорчен:
            return None
        if self.вид == "pcap":
            return self._pcap(размер)
        if self.вид == "pcapng":
            return self._pcapng(размер)
        return self._sig(размер)

    def _pcap(self, размер: int):
        голова = self._байты(self.место, 16, размер)
        if голова is None:
            return None
        сек, дробь, записано, исходно = _ЗАПИСЬ_PCAP[self.порядок].unpack(голова)
        if записано > ЗАПИСЬ_ДО:
            self.испорчен = f"запись на смещении {self.место} испорчена (длина {записано})"
            return None
        if self.место + 16 + записано > размер:
            return None
        данные = self._байты(self.место + 16, записано, размер) if self.нужны_данные else b""
        if данные is None:
            return None
        место_данных = self.место + 16
        self.место += 16 + записано
        self.номер += 1
        self.время = сек + дробь * self.доля
        return self.время, данные, исходно, self.канал, место_данных

    def _pcapng(self, размер: int):
        while True:
            голова = self._байты(self.место, 12, размер)
            if голова is None:
                return None
            if голова[:4] == SHB:
                self.порядок = "<" if голова[8:] == b"\x4d\x3c\x2b\x1a" else ">"
                self.интерфейсы = []
            вид, длина = _ГОЛОВА_БЛОКА[self.порядок].unpack_from(голова)
            if длина < 12 or длина % 4 or длина > БЛОК_ДО:
                self.испорчен = f"блок на смещении {self.место} испорчен (длина {длина})"
                return None
            блок = self._байты(self.место, длина, размер)
            if блок is None:
                return None
            if _ДЛИНА[self.порядок].unpack_from(блок, длина - 4)[0] != длина:
                self.испорчен = f"блок на смещении {self.место}: длины в начале и в конце разные"
                return None
            начало_блока = self.место
            self.место += длина
            тело = блок[8:длина - 4]
            if вид == 1 and len(тело) >= 8:                                   # IDB
                тип, _, snap = _IDB[self.порядок].unpack_from(тело)
                доля = доля_секунды(опции_блока(тело, 8, self.порядок).get(9, b""))
                self.интерфейсы.append((канал_по_типу(тип), доля, snap))
            elif вид in (6, 2) and len(тело) >= 20:                           # EPB, OPB
                if вид == 6:
                    номер, старшие, младшие, записано, исходно = _EPB[self.порядок].unpack_from(тело)
                else:
                    номер, _, старшие, младшие, записано, исходно = _OPB[self.порядок].unpack_from(тело)
                if номер < len(self.интерфейсы):
                    канал, доля, _ = self.интерфейсы[номер]
                    self.время = ((старшие << 32) | младшие) * доля
                    self.номер += 1
                    return (self.время, тело[20:20 + записано] if self.нужны_данные else b"", исходно, канал,
                            начало_блока + 8 + 20)
            elif вид == 3 and len(тело) >= 4 and self.интерфейсы:             # SPB — без времени
                исходно = _ДЛИНА[self.порядок].unpack_from(тело)[0]
                канал, _, snap = self.интерфейсы[0]
                записано = min(исходно, snap or исходно)
                self.номер += 1
                return (self.время, тело[4:4 + записано] if self.нужны_данные else b"", исходно, канал,
                        начало_блока + 8 + 4)

    def _sig(self, размер: int):
        голова = self._байты(self.место, 2, размер)
        if голова is None:
            return None
        длина = int.from_bytes(голова, self.порядок)
        тело = длина - 2 if self.включает else длина
        if тело < 0:
            self.испорчен = f"на смещении {self.место} длина пакета {длина} меньше заголовка"
            return None
        if self.место + 2 + тело > размер:
            return None
        начало = self.место + 2
        данные = self._байты(начало, тело, размер) if self.нужны_данные else b""
        if данные is None:
            return None
        self.место = начало + тело
        self.номер += 1
        return float(self.номер - 2), данные, тело, "авто", начало

    def хвост(self, размер: int) -> str:
        """Заметка о конце готового файла (записей больше нет): оборван ли он и как — как у ЧтецЗахвата."""
        if self.испорчен:
            return f"{self.испорчен} — дальше не читаю"
        if self.вид == "sig":
            if self.место + 2 > размер:
                return "файл оборван: в конце неполный заголовок пакета" if self.место < размер else ""
            return "файл оборван: последний пакет записан не целиком"
        return "файл оборван: последний пакет записан не целиком" if self.место < размер else ""
