# -*- coding: utf-8 -*-
"""Годность названия документа.

Название документа — не украшение. Помощник строит из названий карту
библиотеки и по ней решает, где искать; человек по названию узнаёт источник
в ответе. Когда в карте стоят «УТВЕРЖДЕН», «Оглавление» и «document», обе
работы ломаются разом: модель не понимает, что у неё на полках, а инженер
не понимает, на что ему сослались.

Отдел столкнулся с этим на живой библиотеке в тридцать тысяч файлов. В одном
ответе помощник перечислил свои источники так:

    рооооооооооооооооо.
    АЛГОРИТМЫ
    Содержание
    Оглавление
    <4D6963726F736F667420576F7264202D20CFEEEDEEECE0...
    УТВЕРЖДЕН
    I. ОБЩИЕ ПОЛОЖЕНИЯ
    P300C3
    document

Здесь четыре разные беды, и лечатся они по-разному:

* **шестнадцатеричная строка** — название взято из метаданных PDF сырым,
  прямо в том виде, в каком оно лежит в файле: ``<4D6963...>``. Внутри
  «Microsoft Word - Поном…» в CP1251;
* **не та кодировка** — те же байты, прочитанные как Latin-1, дают
  «Ïîíîìàðåíêî» вместо «Пономаренко». Это чинится обратным разбором;
* **вырожденный текст** — «рооооооооооооооооо»: в PDF сломана таблица
  ToUnicode, и все глифы легли в одну букву. Чинить нечего, название надо
  брать другое;
* **служебный заголовок** — «Оглавление», «УТВЕРЖДЕН», «I. ОБЩИЕ
  ПОЛОЖЕНИЯ». Это не название документа, а первый заголовок внутри него.
  У русских ГОСТов и инструкций так почти всегда.

Порядок выбора был такой: метаданные → первый заголовок → имя файла, и ни
на одной ступени не спрашивалось, годится ли то, что получилось. Поэтому
негодное с первой ступени побеждало годное имя файла. Здесь порядок тот же,
но с проверкой на каждой ступени: имя файла человек выбирал сам, и оно
почти всегда лучше служебного заголовка из середины документа.
"""

from __future__ import annotations

import re
from typing import Iterable, List, Sequence, Tuple

__all__ = [
    "MIN_MOJIBAKE_RUN",
    "MIN_TITLE_LETTERS",
    "clean_title",
    "title_problem",
    "choose_title",
    "repair_mojibake",
    "decode_hex_title",
    "is_degenerate",
    "title_from_filename",
]

#: Меньше этого числа букв — не название, а обрывок. Три буквы оставляют
#: место коротким настоящим именам вроде «ЗИП» или «КВ».
MIN_TITLE_LETTERS = 3

#: Сколько знаков верхней половины таблицы должно идти ПОДРЯД, чтобы счесть
#: строку испорченной кодировкой. Русское слово, прочитанное как Latin-1,
#: даёт сплошную цепочку таких знаков («Ïîíîìàðåíêî» — одиннадцать подряд).
#: Настоящее латинское название даёт их поодиночке: «Håkan», «Größe»,
#: «2×2 MIMO» — по одному-два знака между обычными буквами.
MIN_MOJIBAKE_RUN = 3

#: Служебные заголовки: они стоят В НАЧАЛЕ почти любого документа и потому
#: чаще всего и попадают в название. Сверяем по нормализованной форме —
#: без номеров, знаков препинания и регистра.
СЛУЖЕБНЫЕ = frozenset({
    "оглавление", "содержание", "утвержден", "утверждено", "утверждаю",
    "введение", "предисловие", "аннотация", "реферат", "общие положения",
    "область применения", "назначение", "назначение и область применения",
    "термины и определения", "нормативные ссылки", "обозначения и сокращения",
    "приложение", "приложение а", "приложение б", "приложение в",
    "лист регистрации изменений", "перечень сокращений", "список литературы",
    "заключение", "выводы", "содержание отчета", "титульный лист",
    "contents", "table of contents", "introduction", "abstract", "foreword",
    "preface", "scope", "references", "appendix", "annex", "index",
})

#: Что подставляют вместо названия сами преобразователи форматов.
ЗАГЛУШКИ = frozenset({
    "document", "документ", "untitled", "unnamed", "без имени", "безымянный",
    "doc", "docx", "pdf", "new document", "новый документ", "noname",
    "microsoft word", "microsoft powerpoint", "microsoft excel", "temp",
})

#: Приставки, которые Word и подобные кладут в метаданные перед именем файла.
ПРИСТАВКИ = (
    "microsoft word -", "microsoft powerpoint -", "microsoft excel -",
    "microsoft word –", "adobe acrobat -",
)

#: Обозначения нормативных документов. Название вида «ГОСТ Р 53363-2009» или
#: «RFC 4818» — законное и самодостаточное, сколько бы в нём ни было цифр.
#: Половина библиотеки отдела состоит именно из таких.
_ОБОЗНАЧЕНИЕ = re.compile(
    r"(?:^|\s)(?:ГОСТ(?:\s*Р)?|ОСТ|РД|СТО|ТУ|СанПиН|СП|RFC|STD|BCP|FYI|IEN"
    r"|МСЭ[\-‑]?[ТРTR]?|ITU[\-‑]?[TR]|ETSI|EN|TS|TR|IEC|ISO"
    r"|IEEE|MIL[\-‑]?STD|MIL[\-‑]?HDBK|FED[\-‑]?STD|STANAG"
    r"|CCSDS|3GPP|DVB|ECSS)"
    r"[\s ]*[-‑]?[\s ]*[A-ZА-Я]?[\s ]*\d",
    re.I)

_НОМЕР = re.compile(r"^\s*(?:[IVXLC]+|\d+(?:\.\d+)*)[.)]?\s+", re.I)
_HEX = re.compile(r"^<?\s*(?:[0-9A-Fa-f]{2}\s*){8,}>?$")
_РАСШИРЕНИЕ = re.compile(
    r"\.(?:pdf|docx?|xlsx?|pptx?|rtf|txt|djvu|odt|ods|odp|tiff?|jpe?g|png)$", re.I)


def repair_mojibake(text: str) -> str:
    """Вернуть кириллицу, прочитанную как Latin-1: «Ïîíîìàðåíêî» → «Пономаренко».

    Признаков два, и нужны оба, потому что цена ошибки несимметрична. Не
    починить порчу — оставить негодное название, его человек увидит и
    поправит. Починить то, что не было испорчено, — подменить ПРАВИЛЬНОЕ
    название на кракозябру, и в описи на тридцать тысяч файлов этого уже
    никто не заметит.

    Первый признак — цепочка: в строке есть ``MIN_MOJIBAKE_RUN`` знаков
    верхней половины таблицы ПОДРЯД. Русское слово, прочитанное не в той
    кодировке, даёт именно сплошную цепочку. Второй — после разбора
    кириллицы прибавилось не меньше, чем на ту же длину.

    Одного «кириллицы стало больше» мало, и это проверено на живых
    названиях: в «Andrew VHLP2-11W 2×2 MIMO» знак умножения в CP1251 —
    буква «Ч», и правило по одному приросту молча делало из названия
    «2Ч2 MIMO». Так же страдали «Håkan», «Größe» и французские заголовки.
    """
    строка = str(text or "")
    if not строка:
        return строка
    if _цепочка_верхних(строка) < MIN_MOJIBAKE_RUN:
        return строка
    try:
        вышло = строка.encode("latin1").decode("cp1251")
    except (UnicodeEncodeError, UnicodeDecodeError):
        return строка
    if _кириллицы(вышло) - _кириллицы(строка) >= MIN_MOJIBAKE_RUN:
        return вышло
    return строка


def decode_hex_title(text: str) -> str:
    """Раскодировать строку PDF вида ``<4D6963...>``, если это она.

    В PDF строку можно записать шестнадцатерично, и некоторые читалки
    отдают её как есть. Внутри обычно UTF-16 с меткой порядка байт либо
    однобайтовая кириллица.
    """
    строка = str(text or "").strip()
    if not _HEX.match(строка):
        return строка
    чистая = re.sub(r"[^0-9A-Fa-f]", "", строка)
    if len(чистая) % 2:
        чистая = чистая[:-1]
    try:
        байты = bytes.fromhex(чистая)
    except ValueError:
        return строка
    if байты[:2] in (b"\xfe\xff", b"\xff\xfe"):
        try:
            return байты.decode("utf-16").strip()
        except UnicodeDecodeError:
            return строка
    # Без метки — пробуем CP1251: так пишет русский Word.
    try:
        вышло = байты.decode("cp1251")
    except UnicodeDecodeError:
        return строка
    return вышло.strip()


def is_degenerate(text: str) -> bool:
    """Текст выродился в одну букву: «рооооооооооооооооо».

    Так выглядит PDF со сломанной таблицей ToUnicode — все глифы легли в
    один символ. Порог 0,6 взят с запасом: в осмысленном русском названии
    самая частая буква занимает около 0,12 (замерено на описи отдела).
    """
    буквы = [знак.lower() for знак in str(text or "") if знак.isalpha()]
    # Восемь, а не четыре: в коротком сокращении повтор буквы — обычное дело
    # («IEEE», «СССР»), и на такой длине признак ничего не значит.
    if len(буквы) < 8:
        return False
    самая = max(буквы.count(знак) for знак in set(буквы))
    return самая / len(буквы) > 0.6


def title_from_filename(name: str) -> str:
    """Название из имени файла: убрать расширение и разделители.

    Имя файла человек выбирал сам, поэтому оно почти всегда осмысленнее
    служебного заголовка из середины документа.
    """
    основа = _РАСШИРЕНИЕ.sub("", str(name or "").strip())
    основа = основа.replace("_", " ").replace("+", " ")
    # Дефис оставляем: в обозначениях он значащий («ГОСТ Р 53363-2009»).
    return re.sub(r"\s+", " ", основа).strip()


def clean_title(text: str) -> str:
    """Починить в названии всё, что чинится, ничего не выбрасывая по смыслу."""
    строка = decode_hex_title(str(text or ""))
    строка = repair_mojibake(строка)
    строка = строка.replace(chr(0), " ")
    низ = строка.strip().lower()
    for приставка in ПРИСТАВКИ:
        if низ.startswith(приставка):
            строка = строка.strip()[len(приставка):]
            break
    строка = _РАСШИРЕНИЕ.sub("", строка.strip())
    return re.sub(r"\s+", " ", строка).strip(" .;,-—–")


def title_problem(text: str) -> str | None:
    """Чем плохо название. ``None`` — годится.

    Возвращается не «да/нет», а причина словами: она попадает в опись и в
    журнал приёма, и по ней видно, что именно чинить.
    """
    строка = str(text or "").strip()
    if not строка:
        return "пусто"
    if _HEX.match(строка):
        return "шестнадцатеричная строка из метаданных, не текст"
    # Обозначение стандарта — законное название, и придираться к нему нельзя.
    # Проверка идёт ПЕРВОЙ: в «ГОСТ Р 53363-2009» пять букв на семнадцать
    # знаков, а в «IEEE 802.11» три буквы из четырёх — одна и та же «E».
    # Любое правило про буквы отвергло бы половину библиотеки отдела,
    # которая из таких обозначений и состоит.
    if _ОБОЗНАЧЕНИЕ.search(строка):
        return None
    if is_degenerate(строка):
        return "текст выродился в одну букву — в файле сломана раскодировка"

    буквы = sum(знак.isalpha() for знак in строка)
    if буквы < MIN_TITLE_LETTERS:
        return f"букв меньше {MIN_TITLE_LETTERS}"

    нормальная = _НОМЕР.sub("", строка)
    нормальная = re.sub(r"[^0-9A-Za-zА-Яа-яЁё ]+", " ", нормальная)
    нормальная = re.sub(r"\s+", " ", нормальная).strip().lower().replace("ё", "е")
    if нормальная in ЗАГЛУШКИ:
        return "подстановка преобразователя, а не название"
    if нормальная in СЛУЖЕБНЫЕ:
        return "служебный заголовок из начала документа, а не название"
    return None


def choose_title(candidates: Sequence[str], *, filename: str = "",
                 ) -> Tuple[str, str, List[str]]:
    """Выбрать годное название. Возвращает (название, откуда, отвергнутое).

    Ступени пробуются по порядку, и каждая проверяется. Имя файла стоит
    последним не потому, что оно хуже, а потому что метаданные и заголовок
    точнее — КОГДА они годные. Негодное с первой ступени больше не
    побеждает годное имя файла: ровно на этом и держалась беда.
    """
    отвергнуто: List[str] = []
    ступени: List[Tuple[str, str]] = [(str(значение or ""), "документ")
                                      for значение in candidates]
    if filename:
        ступени.append((title_from_filename(filename), "имя файла"))

    for сырое, откуда in ступени:
        готовое = clean_title(сырое)
        изъян = title_problem(готовое)
        if изъян is None:
            return готовое, откуда, отвергнуто
        if сырое.strip():
            отвергнуто.append(f"{откуда}: «{_коротко(сырое)}» — {изъян}")

    # Ничего не годится: отдаём имя файла как есть, но честно говорим об этом.
    запас = title_from_filename(filename) or clean_title(
        next((значение for значение in candidates if str(значение or "").strip()), ""))
    return запас.strip(), "нечего взять", отвергнуто


def _кириллицы(text: str) -> int:
    return sum(1 for знак in text if "А" <= знак <= "я" or знак in "Ёё")


def _цепочка_верхних(text: str) -> int:
    """Самая длинная цепочка подряд идущих знаков из диапазона 0x80–0xFF."""
    самая = текущая = 0
    for знак in text:
        if 0x80 <= ord(знак) <= 0xFF:
            текущая += 1
            самая = max(самая, текущая)
        else:
            текущая = 0
    return самая


def _коротко(text: str, предел: int = 40) -> str:
    строка = re.sub(r"\s+", " ", str(text or "")).strip()
    return строка if len(строка) <= предел else строка[: предел - 1] + "…"
