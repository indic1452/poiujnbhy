"""Определение типа документа по содержимому.

Тип берётся из имени каталога верхнего уровня: ``standards/ГОСТ.pdf`` — это
стандарт. Правило простое и предсказуемое, но работает только тогда, когда
библиотека уже разложена. А приносят её обычно как есть: папка «Разное», папка
с фамилией военнослужащего, выгрузка со старого файлового сервера. Всё это уезжало
в ``literature`` и там перемешивалось: паспорт модема оказывался «литературой»,
приказ по предприятию — тоже, и поиск по книгам начинал выдавать приказы.

Здесь — определение типа по самому документу. Правила намеренно грубые и
опираются на устойчивые обороты, которые в документе своего типа встречаются
почти всегда, а в чужом почти никогда: «настоящий стандарт распространяется» —
это стандарт, «руководство по эксплуатации» и «состав изделия» — паспорт,
«по результатам анализа» и «заказчик» — отчёт (эти слова ищутся в тексте
самих документов прошлых лет, а не употребляются системой от себя).

Уверенности требуется больше, чем при определении направления: ошибка типа
уводит документ в чужую выборку целиком. Не набралось — ``misc``, полка
«Прочее»: там документ виден и его можно разложить руками, а не потерян среди
книг.
"""

from __future__ import annotations

