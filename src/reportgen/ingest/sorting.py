def _count(text: str, needle: str) -> int:
    """Сколько раз оборот встретился. Ограничиваем тремя: важен факт, не частота."""
    return min(3, text.count(needle))


def score_doc_types(title: str = "", filename: str = "", text: str = "") -> Dict[str, int]:
    """Вес каждого типа для этого документа. Пусто — ничего не опознано."""
    head = (text or "")[:SCAN_CHARS].lower()
    name = f"{title} {filename}".lower()
    scores: Dict[str, int] = {}
    for doc_type, rules in RULES.items():
        total = 0
        for needle, weight in rules:
            if needle in name:
                total += weight * TITLE_WEIGHT
            total += weight * _count(head, needle)
        if total:
            scores[doc_type] = total
    return scores


def detect_doc_type(title: str = "", filename: str = "", text: str = "",
                    meta: Dict[str, object] | None = None) -> Tuple[str, str]:
    """Тип документа и то, почему он выбран.

    Возвращает ``(тип, пояснение)``. Пояснение попадает в карточку документа:
    инженер должен видеть, на чём основано решение, иначе исправлять его
    придётся вслепую.
    """
    meta = meta or {}
    # RFC разбирается своим конвертером и сомнений не вызывает.
    if meta.get("rfc") or str(meta.get("source_format", "")) == "rfc":
        return "standards", "RFC"

    scores = score_doc_types(title=title, filename=filename, text=text)
    if not scores:
        return "misc", "признаков ни одного типа не найдено"

    ranked: List[Tuple[int, str]] = sorted(
        ((value, key) for key, value in scores.items()), reverse=True
    )
    best_score, best_type = ranked[0]
    if best_score < MIN_SCORE:
        return "misc", f"слабые признаки (вес {best_score})"
    # Ничья — повод не гадать: тип уводит документ в чужую выборку целиком.
    if len(ranked) > 1 and ranked[1][0] == best_score:
        return "misc", f"поровну признаков: {best_type} и {ranked[1][1]}"
    return best_type, f"по содержимому (вес {best_score})"
