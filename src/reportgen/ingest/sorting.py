#: Во сколько раз совпадение в названии весомее, чем в тексте. Название пишет
#: человек и пишет по делу: «Руководство по эксплуатации ХХ-100» — это точно
#: паспорт, а то же словосочетание в середине книги ничего не значит.
TITLE_WEIGHT = 3


def _rule(*words: str) -> Tuple[str, ...]:
    return tuple(words)


