def записать_биты(путь: Path, биты: np.ndarray) -> None:
    with Приёмник(путь) as п:
        п.записать(биты)
        п.закрыть()


def сверить_этапы(тест: unittest.TestCase, вход: np.ndarray, находки, этапов: int,
                  допуск: float = 0.0) -> list[list[str]]:
    """Этап автомата по выборке == начало его пересчёта по всему файлу: шаги этапов (``razbor.шаги_по_этапам``;
    цикл без слоя отдаёт шаги следующему этапу, как в плане) через ``potokovo.выполнить`` от пересчитанного потока
    прежнего этапа (этап 0 — вход). ``этапов`` — сколько этапов пересчитывается; итог — их шаги. ``допуск`` — доля
    несовпавших бит (у кода, который автомат декодировал своим декодером по восстановленным проверкам)."""
    шаги_этапов = razbor.шаги_по_этапам(находки)
    итог: list[list[str]] = []
    with tempfile.TemporaryDirectory() as tmp:
        путь = Path(tmp) / "вход.bin"
        записать_биты(путь, np.asarray(вход, dtype=np.uint8))
        источник = Источник(путь, бит=len(вход))
        копится: list[dict] = []
        for номер, (шаги, находка) in enumerate(zip(шаги_этапов, находки, strict=False), start=1):
            if находка.уровень == "цикл" and not (находка.свойства or {}).get("слой"):
                копится += шаги
                continue
            куда = Path(tmp) / f"этап-{номер}.bin"
            бит, _ = potokovo.выполнить(источник, копится + шаги, куда)
            весь = np.unpackbits(np.frombuffer(куда.read_bytes(), dtype=np.uint8))[:бит]
            выборка = np.asarray(находка.дальше, dtype=np.uint8)
            тест.assertGreaterEqual(len(весь), len(выборка), f"этап {номер}: {находка.что}")
            несовпало = float(np.mean(выборка != весь[:len(выборка)])) if len(выборка) else 0.0
            тест.assertLessEqual(несовпало, допуск, f"этап {номер}: {находка.что}; не совпало {несовпало:.2e}")
            итог.append([ш["слой"] for ш in копится + шаги])
            источник, копится = Источник(куда, бит=бит), []
    тест.assertEqual(этапов, len(итог), итог)
    return итог


def ряд_с_кадрами(сид: int = 1) -> np.ndarray:
    """Кадры по 1504 бит с синхрословом 00011011, мусор в начале, ошибка и проскальзывание."""
    rng = np.random.default_rng(сид)
    слово = np.array([0, 0, 0, 1, 1, 0, 1, 1], np.uint8)
    кадры = [np.concatenate([слово, rng.integers(0, 2, 1496).astype(np.uint8)]) for _ in range(60)]
    ряд = np.concatenate([rng.integers(0, 2, 333).astype(np.uint8)] + кадры)
    ряд[5000] ^= 1
    return np.concatenate([ряд[:9000], ряд[9003:]])


