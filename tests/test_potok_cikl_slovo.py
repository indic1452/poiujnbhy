"""Цикл по повторам слова, каналы управления стаффингом блоками, окна БМ без отводов.

- Цикл по повторам слова: когда автокорреляцию забивает нагрузка (флаги
  HDLC) или запись коротка для пика автокорреляции, кадр с синхрословом
  находится по тому, что слово повторяется ровно через длину кадра по всей
  выборке.
- Каналы управления стаффингом: попарное согласие столбцов считается
  блоками, хранятся лишь списки согласных — итог тот же, что у прямого
  перебора по всей матрице (он здесь же, как эталон).
- Берлекэмп — Мэсси в окне, где после первых бит одни нули, даёт многочлен
  связи 1 (без отводов) при ненулевой сложности — кандидатом скремблера он
  не становится.
"""

import unittest
from unittest import mock

import numpy as np

import _bootstrap  # noqa: F401
import potok_sintez as с
from reportgen.potok import cikl, skrembler, stafing
from reportgen.potok.bity import в_биты

ASM = np.unpackbits(np.frombuffer(bytes.fromhex("1ACFFC1D"), np.uint8))


def кадры_с_asm(кадров, длина, *, сдвиг=0, нагрузка=None, сид=1):
    rng = np.random.default_rng(сид)
    k = rng.integers(0, 2, (кадров, длина)).astype(np.uint8)
    if нагрузка is not None:
        k[:, 32:] = np.resize(нагрузка, кадров * (длина - 32)).reshape(кадров, длина - 32)
    k[:, :32] = ASM
    return np.concatenate([rng.integers(0, 2, сдвиг).astype(np.uint8), k.reshape(-1)])


class ЦиклПоСлову(unittest.TestCase):
    def test_короткая_запись_без_пика(self):
        """64 кадра по 8192 бит: пик ASM (32/8192) ниже порога автокорреляции, а повторы — видны."""
        биты = кадры_с_asm(64, 8192, сдвиг=5)
        self.assertIsNone(cikl.длина_цикла(биты))
        self.assertIsNone(cikl.гребёнка(биты))
        найдено = cikl.найти(биты)
        self.assertIsNotNone(найдено)
        self.assertEqual(найдено.свойства["длина"], 8192)
        self.assertIn("синхрослово 32 бит", найдено.что)
        self.assertIn("цикл по повторам слова: 63 вхождений ровно через 8192 бит", найдено.подробно[0])
        self.assertIn("запись для него коротка", найдено.подробно[0])
        self.assertIn("синхрослово — ASM CCSDS 0x1ACFFC1D", найдено.подробно[1])

    def test_незнакомое_слово_не_названо(self):
        rng = np.random.default_rng(9)
        k = rng.integers(0, 2, (64, 4096)).astype(np.uint8)
        k[:, :32] = np.unpackbits(np.frombuffer(bytes.fromhex("E4B51C27"), np.uint8))
        найдено = cikl.найти(k.reshape(-1))
        self.assertEqual(найдено.свойства["длина"], 4096)
        self.assertFalse(any(п.startswith("синхрослово — ") for п in найдено.подробно))

    def test_кадр_не_кратный_байту(self):
        """8191 бит: окна по 24 бита с шагом 8 видят ASM лишь в каждом восьмом кадре — берут окна по
        32 бита с каждого бита."""
        найдено = cikl.найти(кадры_с_asm(64, 8191))
        self.assertEqual(найдено.свойства["длина"], 8191)

    def test_сверхцикл_делится_до_кадра(self):
        """2964 бит (кратно 4, не 8): повторы окна с шагом 8 — через два кадра, цикл потом
        делится пополам, и так и сказано."""
        найдено = cikl.найти(кадры_с_asm(40, 2964, сдвиг=3))
        self.assertEqual(найдено.свойства["длина"], 2964)
        self.assertIn("через 5928 бит", найдено.подробно[0])
        self.assertIn("синхрослово стоит и через 2964 бит — цикл в 2 раза короче найденного",
                      найдено.подробно[0])

    def test_сверхцикл_из_пяти_кадров(self):
        """Найден цикл в 5 кадров (как бывает из-за медленных полей) — сокращается до кадра."""
        биты = кадры_с_asm(300, 4000, сид=12)
        with mock.patch.object(cikl, "длина_цикла", return_value=(20000, 0.01, 0.001)):
            найдено = cikl.найти(биты)
        self.assertEqual(найдено.свойства["длина"], 4000)
        self.assertIn("цикл в 5 раз короче найденного", найдено.подробно[0])
        self.assertEqual(cikl._простые_делители(20000), [2, 5])
        self.assertEqual(cikl._простые_делители(4053), [3, 7, 193])

    def test_мало_кадров_нет_цикла(self):
        """12 кадров: повторов меньше ПОВТОР_ВХОЖДЕНИЙ_ОТ — цикла нет (не угадываем)."""
        self.assertIsNone(cikl.найти(кадры_с_asm(12, 8192)))

    def test_нагрузка_забивает_автокорреляцию(self):
        """HDLC с долгими паузами из флагов в кадрах по 8192 бит: пик автокорреляции — от флагов
        (32 бит), кадр — по повторам ASM."""
        поток = в_биты(с.hdlc(с.пакеты_ip(700), флагов_между=40))
        биты = кадры_с_asm(150, 8192, сдвиг=296, нагрузка=поток)
        пик = cikl.длина_цикла(биты)
        self.assertIsNotNone(пик)
        self.assertLess(пик[0], 100)
        найдено = cikl.найти(биты)
        self.assertEqual(найдено.свойства["длина"], 8192)
        self.assertIn("автокорреляцию забивает нагрузка", найдено.подробно[0])

    def test_длинный_кадр_ррл(self):
        """Кадр РРЛ в 100 000 бит (длиннее ЦИКЛ_ДО автокорреляции) с синхрословом 240 бит."""
        rng = np.random.default_rng(10)
        слово = rng.integers(0, 2, 240).astype(np.uint8)
        k = rng.integers(0, 2, (30, 100_000)).astype(np.uint8)
        k[:, :240] = слово
        биты = np.concatenate([rng.integers(0, 2, 1234).astype(np.uint8), k.reshape(-1)])
        self.assertGreater(100_000, cikl.ЦИКЛ_ДО)
        найдено = cikl.найти(биты)
        self.assertIsNotNone(найдено)
        self.assertEqual(найдено.свойства["длина"], 100_000)
        self.assertIn("синхрослово 240 бит", найдено.что)
        with mock.patch.object(cikl, "ПОВТОР_ЦИКЛ_ДО", cikl.ЦИКЛ_ДО):
            self.assertIsNone(cikl._цикл_по_слову(биты, cikl.ПОВТОР_БЕЗ_ПИКА))

    def test_случайный_ряд_без_цикла(self):
        биты = np.random.default_rng(3).integers(0, 2, 1 << 21).astype(np.uint8)
        self.assertIsNone(cikl._цикл_по_слову(биты, cikl.ПОВТОР_БЕЗ_ПИКА))
        self.assertIsNone(cikl._цикл_по_слову(биты))

    def test_покрытие_отсекает_повтор_в_части(self):
        """Слово повторяется ровно через 4096 бит, но лишь в первой четверти выборки — не кадр."""
        rng = np.random.default_rng(4)
        биты = rng.integers(0, 2, 1 << 20).astype(np.uint8)
        for к in range(0, (1 << 18) - 64, 4096):
            биты[к:к + 32] = ASM
        self.assertIsNone(cikl._цикл_по_слову(биты, cikl.ПОВТОР_БЕЗ_ПИКА))

    def test_окна(self):
        """Слова из окна: старший бит — первый, шаг — через сколько бит начало следующего."""
        биты = np.array([1, 0, 1, 1, 0, 0, 1, 0, 1, 1], np.uint8)
        self.assertEqual(cikl._окна(биты, 4, 1).tolist()[:3], [0b1011, 0b0110, 0b1100])
        self.assertEqual(cikl._окна(биты, 4, 3).tolist(), [0b1011, 0b1001, 0b1011])
        короткое = cikl._окна(биты, 24, 1)                  # короче окна — пусто, не ошибка
        self.assertEqual((короткое.dtype, len(короткое)), (np.uint32, 0))


def группы_прямо(таблица, наименьшая=2, наибольшая=7):
    """Эталон: вся матрица согласия, перебор как в описании — копии одного бита."""
    доли = таблица.mean(axis=0)
    кандидаты = np.flatnonzero((доли > stafing.МЕНЯЕТСЯ[0]) & (доли < stafing.МЕНЯЕТСЯ[1]))
    if len(кандидаты) < 2:
        return []
    x = таблица[:, кандидаты].astype(np.float32) * 2 - 1
    согласие = (x.T @ x / len(таблица) + 1) / 2
    свободен = np.ones(len(кандидаты), dtype=bool)
    группы = []
    for i in np.argsort(-np.abs(доли[кандидаты] - 0.5)):
        if not свободен[i]:
            continue
        члены = [j for j in range(len(кандидаты)) if свободен[j] and согласие[i, j] >= stafing.СОГЛАСИЕ]
        if not наименьшая <= len(члены) <= наибольшая:
            continue
        if min(согласие[a, b] for a in члены for b in члены) < stafing.СОГЛАСИЕ:
            continue
        группы.append(sorted(int(кандидаты[j]) for j in члены))
        for j in члены:
            свободен[j] = False
    return sorted(группы)


class ГруппыУправления(unittest.TestCase):
    def таблица(self, сид, кадров=300, столбцов=400, групп=6, заполнение=0.0):
        rng = np.random.default_rng(сид)
        т = rng.integers(0, 2, (кадров, столбцов)).astype(np.uint8)
        if заполнение:
            # Почти постоянные столбцы: много согласных у каждого — списки не хранятся.
            почти = rng.choice(столбцов, int(заполнение * столбцов), replace=False)
            т[:, почти] = (rng.random((кадров, len(почти))) < 0.015).astype(np.uint8)
        for g in range(групп):
            бит = (rng.random(кадров) < rng.uniform(0.1, 0.9)).astype(np.uint8)
            места = rng.choice(столбцов, int(rng.integers(2, 6)), replace=False)
            т[:, места] = бит[:, None]
            т[rng.integers(0, кадров, 3), места[0]] ^= 1      # ошибки линии в копиях
        return т

    def test_как_прямой_перебор(self):
        for сид, заполнение in ((1, 0.0), (2, 0.0), (3, 0.3), (4, 0.6)):
            with self.subTest(сид=сид, заполнение=заполнение):
                т = self.таблица(сид, заполнение=заполнение)
                эталон = группы_прямо(т)
                self.assertTrue(эталон)
                итог = [г["столбцы"] for г in stafing.группы_управления(т)]
                self.assertEqual(sorted(итог), эталон)

    def test_блоками_и_без_хранения_соседей(self):
        """Крошечные блоки и списки соседей — итог тот же (пересчёт строки по требованию)."""
        т = self.таблица(5, заполнение=0.5)
        эталон = группы_прямо(т)
        with mock.patch.multiple(stafing, ЧИСЕЛ_ЗА_РАЗ=1000, СОСЕДЕЙ_ХРАНИТЬ=1):
            итог = [г["столбцы"] for г in stafing.группы_управления(т)]
        self.assertEqual(sorted(итог), эталон)

    def test_согласие_группы(self):
        т = self.таблица(6)
        for г in stafing.группы_управления(т):
            столбцы = т[:, г["столбцы"]]
            попарно = min(float(np.mean(столбцы[:, a] == столбцы[:, b]))
                          for a in range(len(г["столбцы"])) for b in range(len(г["столбцы"])))
            self.assertAlmostEqual(г["согласие"], round(попарно, 4), places=4)

    def test_длинный_цикл_стаффинг_не_ищется(self):
        """Цикл длиннее СТАФФИНГ_ЦИКЛ_ДО: поиск не делается, и так и сказано."""
        найдено = cikl.найти(кадры_с_asm(40, 9000))
        self.assertTrue(any("стаффинг не искался: цикл длиннее 8192 бит" in п for п in найдено.подробно))
        with mock.patch.object(stafing, "найти", side_effect=AssertionError("не должен звать")):
            cikl.найти(кадры_с_asm(40, 9000))


class ОкнаБезОтводов(unittest.TestCase):
    def test_многочлен_единица_не_кандидат(self):
        """Окна «101…» и дальше нули: сложность 3, многочлен связи 1 — не скремблер."""
        сложность, многочлен = skrembler.берлекэмп_мэсси([1, 0, 1] + [0] * 253)
        self.assertEqual((сложность, многочлен), (3, 1))
        биты = np.zeros(1 << 16, np.uint8)
        биты[::256] = 1
        биты[2::256] = 1
        self.assertNotIn((), [о for о, _ in skrembler.кандидаты_бм(биты)])
        skrembler.найти(биты)                      # не падает на пустом наборе отводов


