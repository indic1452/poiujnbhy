#: Шестнадцатеричная строка PDF с экрана заказчика: внутри «Microsoft Word -
#: Пономаренко» в CP1251, без метки порядка байт.
HEX_ЗАГОЛОВОК = "<4D6963726F736F667420576F7264202D20CFEEEDEEECE0F0E5EDEAEE>"
#: Та же строка, но уже раскодированная читалкой не в той кодировке.
МОЙИБЕЙК = "Microsoft Word - Ïîíîìàðåíêî"


def _кириллицы(строка: str) -> int:
    """Столько же, сколько считает сам разбор: буквы русского алфавита."""
    return sum(1 for знак in строка if "А" <= знак <= "я" or знак in "Ёё")


class ПорчаКодировки(unittest.TestCase):
    """Кириллица, прочитанная как Latin-1, читается обратно."""

    def test_мойибейк_чинится(self):
        self.assertEqual("Microsoft Word - Пономаренко", repair_mojibake(МОЙИБЕЙК))

    def test_настоящая_латиница_не_трогается(self):
        """Признак починки честный: кириллицы должно стать больше."""
        for целое in ("Reverse Engineering for Beginners",
                      "MAX2769 GNSS receiver", "ETSI EN 302 217-2"):
            with self.subTest(целое=целое):
                self.assertEqual(целое, repair_mojibake(целое))

    def test_русское_название_не_портится(self):
        целое = "ГОСТ Р 53363-2009. Цифровые радиорелейные линии"
        self.assertEqual(целое, repair_mojibake(целое))

    def test_одиночный_верхний_знак_не_повод_чинить(self):
        """Самое дорогое здесь — подменить ПРАВИЛЬНОЕ название.

        Все эти строки при слепом обратном разборе МЕНЯЮТСЯ, и кириллицы в
        них при этом прибавляется: «×» в CP1251 — буква «Ч», «å» — «е»,
        «é» — «й». Правило «стало больше кириллицы» на них срабатывало и
        молча выдавало «2Ч2 MIMO» вместо «2×2 MIMO». В описи на тридцать
        тысяч файлов такую подмену уже никто не заметит и не вернёт.

        Отличает порчу от настоящей латиницы не прирост, а цепочка: русское
        слово даёт знаки верхней половины таблицы СПЛОШЬ, а диакритика —
        поодиночке между обычными буквами.
        """
        живые = (
            "Andrew VHLP2-11W 0,6 m, 2×2 MIMO",
            "Ericsson MINI-LINK, Håkan Andersson",
            "Réseau numérique à intégration de services",
            "Größe der Antenne",
        )
        for целое in живые:
            with self.subTest(целое=целое):
                испорчено = целое.encode("latin1").decode("cp1251")
                self.assertNotEqual(
                    целое, испорчено,
                    "образец подобран неудачно: слепой разбор его не меняет, "
                    "и проверка ничего не стережёт")
                self.assertEqual(целое, repair_mojibake(целое))

    def test_цепочка_есть_а_кириллицы_из_неё_не_вышло(self):
        """Второй порог: одной случайной буквы мало, чтобы переписать название.

        Строка собрана нарочно и живым названием не притворяется — это
        проверка на границе. Три знака верхней половины таблицы идут подряд,
        цепочка порог берёт, но в CP1251 это «§», «Ё» и «©»: кириллицы
        прибавилось на одну букву вместо трёх. Слова здесь не было, и
        переписывать название не с чего.
        """
        проба = "Norm \xa7\xa8\xa9 12"
        разбор = проба.encode("latin1").decode("cp1251")
        прирост = _кириллицы(разбор) - _кириллицы(проба)
        self.assertNotEqual(проба, разбор, "образец подобран неудачно")
        self.assertTrue(0 < прирост < MIN_MOJIBAKE_RUN,
                        f"образец должен стоять на границе, прирост {прирост}")
        self.assertEqual(проба, repair_mojibake(проба))

    def test_цепочка_короче_порога_не_чинится(self):
        """Граница названа числом, а не подобрана на глаз."""
        self.assertEqual(3, MIN_MOJIBAKE_RUN)
        короткая = "Wi-Fi " + "Ïî"  # два знака подряд — меньше порога
        self.assertEqual(короткая, repair_mojibake(короткая))
        длиннее = "Wi-Fi " + "Ïîí"  # три подряд — уже порча
        self.assertEqual("Wi-Fi Пон", repair_mojibake(длиннее))


