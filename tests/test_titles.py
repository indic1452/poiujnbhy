"""Годность названия документа.

Жалоба отдела на живой библиотеке в тридцать тысяч файлов: на вопрос про
тракт приёма РРЛС помощник отвечает не по делу. В блоке «Ответ собран по 15
документам» он перечислил свои источники, и это оказался список такого вида:

    рооооооооооооооооо.   АЛГОРИТМЫ   Содержание   Оглавление
    <4D6963726F736F667420576F7264202D20CFEEEDEEECE0...
    УТВЕРЖДЕН   I. ОБЩИЕ ПОЛОЖЕНИЯ   P300C3   document

Помощник строит из названий карту библиотеки и по ней решает, где искать. По
такой карте он не знает, что у него на полках, — и притаскивает «Reverse
Engineering for Beginners» на вопрос о радиорелейной линии.

Выбор названия был «первое непустое»: метаданные, потом первый заголовок,
потом имя файла. Ни на одной ступени не спрашивалось, годится ли то, что
вышло, поэтому негодное с первой ступени побеждало годное имя файла.
"""

