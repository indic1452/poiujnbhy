class ВырожденныйТекст(unittest.TestCase):
    """«рооооооооооооооооо» — в PDF сломана таблица раскодировки глифов."""

    def test_повтор_одной_буквы_опознан(self):
        self.assertTrue(is_degenerate("рооооооооооооооооо."))
        self.assertTrue(is_degenerate("ааааааааааа"))

    def test_короткое_сокращение_не_вырождено(self):
        """Порог по длине: на четырёх буквах повтор ничего не значит.

        В «IEEE» три буквы из четырёх — одна и та же «E», в «СССР» три из
        четырёх — «С». По доле повтора это вырождение (0,75 при пороге 0,6),
        по существу — обычные сокращения из библиотеки отдела. Признак
        работает только там, где длина делает повтор невозможным случайно.
        """
        for целое in ("IEEE", "СССР"):
            with self.subTest(целое=целое):
                буквы = [з.lower() for з in целое if з.isalpha()]
                доля = max(буквы.count(з) for з in set(буквы)) / len(буквы)
                self.assertGreater(
                    доля, 0.6,
                    "образец подобран неудачно: он не вырожден и по доле, "
                    "и проверка порога ничего не стережёт")
                self.assertFalse(is_degenerate(целое),
                                 f"сокращение «{целое}» сочтено вырожденным")

    def test_граница_длины_названа_числом(self):
        """Семь одинаковых букв — ещё сокращение, восемь — уже поломка."""
        self.assertFalse(is_degenerate("ооооооо"))
        self.assertTrue(is_degenerate("оооооооо"))

    def test_осмысленное_название_не_опознано(self):
        для_проверки = (
            "ГОСТ Р 53363-2009. Цифровые радиорелейные линии",
            "Тракт приёма РРЛС",
            "MAX2769. Универсальный приёмник ГНСС",
            "Reverse Engineering for Beginners",
            "СЛС", "КВ",
        )
        for целое in для_проверки:
            with self.subTest(целое=целое):
                self.assertFalse(is_degenerate(целое))


