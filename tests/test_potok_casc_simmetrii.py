class ВосстановлениеПриИнверсии(unittest.TestCase):

    def test_ядро_по_инвертированным_словам(self):
        """Слова кода инвертированы целиком (у части проверок нечётный вес — синдром H·1): ядро по разностям с
        опорным словом находит все проверки, декодер — исправляет."""
        к = cs.код(Z=32, mb=8, kb=24, сид=7)
        rng = np.random.default_rng(3)
        u = rng.integers(0, 2, (1400, к.k), dtype=np.uint8)
        слова = к.закодировать(u)
        нечётных = sum(len(h) % 2 for h in к.строки())
        self.assertGreater(нечётных, 0)
        W = 1 - слова
        W[[3, 50], [10, 700]] ^= 1
        итог = ldpc_yadro.восстановить(W, срок=60)
        self.assertEqual(к.r, итог.ранг)
        for h in итог.проверки:
            self.assertFalse(np.bitwise_xor.reduce(слова[:, h], axis=1).any())
        исправленные, ок, исправлено = ldpc_yadro.декодировать(W, итог.проверки, опора=итог.опора)
        self.assertTrue(ок.all())
        self.assertEqual(2, исправлено)
        self.assertTrue(np.array_equal(1 - слова, исправленные))


