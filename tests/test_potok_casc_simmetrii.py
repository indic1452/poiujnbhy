        б = razbor.Бюджет(конец=0.0)
        б.после_декодера.append("п → нагрузка цикла → после снятия LDPC")
        ниже = "п → нагрузка цикла → после снятия LDPC → после снятия ПСП блока → нагрузка цикла"
