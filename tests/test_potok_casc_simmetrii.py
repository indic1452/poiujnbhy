_ПОТОКИ: dict = {}


def поток_casc(приёмник=(False, False, True), кадров: int = 60, ber: float = 1e-2) -> cs.ПотокCASC:
    """По умолчанию — как запись 11.bin: приёмник инвертирует второй бит символа (пилот «11» в файле — «10»)."""
    ключ = (приёмник, кадров, ber)
    if ключ not in _ПОТОКИ:
        _ПОТОКИ[ключ] = cs.поток_casc(кадров, ber=ber, приёмник=приёмник)
    return _ПОТОКИ[ключ]


def без_пилотов(байты: bytes, порядок: str = "little") -> tuple[np.ndarray, vstavka.Вставка]:
    биты = np.unpackbits(np.frombuffer(байты, dtype=np.uint8), bitorder=порядок)
    в = vstavka.проверить(биты, 128)
    return vstavka.снять(биты, в), в


class Симметрии(unittest.TestCase):

    def test_число_вариантов(self):
        self.assertEqual(12, len(simvoly.варианты()))
        self.assertEqual(8, len(simvoly.варианты(0)))
        self.assertTrue(simvoly.варианты()[0][0].тождество)
        self.assertEqual(simvoly.ИНВЕРСИЯ, simvoly.варианты()[1][0])

    def test_как_у_приёмника_и_группа(self):
        rng = np.random.default_rng(1)
        x = rng.integers(0, 2, 1001, dtype=np.uint8)
        места = rng.integers(0, len(x), (7, 9))
        for с in simvoly.ВСЕ:
            for ф in (0, 1):
                y = с.применить(x, ф)
                # Края (неполная пара) — без сверки: приёмник их не трогает, симметрия берёт тот же бит.
                self.assertTrue(np.array_equal(cs.пары(x, с.обмен, с.инв_первого, с.инв_второго, ф)[2:1000],
                                               y[2:1000]))
                self.assertTrue(np.array_equal(y[места], с.взять(x, места, ф)))
                # У каждой симметрии есть обратная среди тех же восьми.
                self.assertTrue(any(np.array_equal(о.применить(y, ф)[2:1000], x[2:1000]) for о in simvoly.ВСЕ))

    def test_слой(self):
        rng = np.random.default_rng(2)
        x = rng.integers(0, 2, 4096, dtype=np.uint8)
        for с, ф in simvoly.варианты():
            слой = с.слой(ф)
            self.assertEqual((с, ф), simvoly.разобрать_слой(слой))
            if not с.тождество:
                ряд, _ = снять_вручную(x, слой)
                self.assertTrue(np.array_equal(с.применить(x, ф), ряд))


class КодCASC(unittest.TestCase):

    def test_кодер_и_встроенная_матрица(self):
        п = поток_casc()
        self.assertFalse(cs.синдром_casc(п.слова).any())
        _, сошлось, исправлено = ldpc.декодировать(п.слова[:4], ldpc_std.схема("casc-8064-6048"), вывод="слова")
        self.assertEqual((4, 0), (сошлось, исправлено))

    def test_опознание_при_любом_повороте(self):
        """Повороты и отражения символов ФМ-4 (пары, выровненные по пилоту) — код и преобразование находятся;
        после преобразования слова совпадают с переданными с точностью до шума."""
        for приёмник in ((False, False, False), (False, True, True), (False, True, False), (True, False, True),
                         (True, True, True)):
            п = поток_casc(приёмник, кадров=24)
            ряд, в = без_пилотов(п.байты)
            оп, почему = ldpc_nagruzka.опознать_встроенный(ряд, 16632, фаза=в.места[0] % 2)
            self.assertIsNotNone(оп, f"{приёмник}: {почему}")
            self.assertEqual(("casc-8064-6048", 2, 8064), (оп.имя, оп.m, оп.n))
            self.assertLess(оп.нарушено, 0.3)
            н = ldpc_nagruzka.нагрузка_кадров(ряд, 16632)
            места = ldpc_nagruzka._места_слов(н, 2)
            W = оп.симметрия.взять(ряд, места, оп.фаза)
            # Первый кадр выборки — первый целый кадр с синхрословом: какой по счёту — по расхождению слов.
            сдвиг = min(range(0, 8, 2), key=lambda s: float((W[:4] != п.слова[s:s + 4]).mean()))
            слова = п.слова[сдвиг:сдвиг + len(W)]
            self.assertLess(float((W[:len(слова)] != слова).mean()), 0.03, приёмник)

    def test_в_старшем_порядке_кода_нет(self):
        п = поток_casc(кадров=24)
        ряд, _ = без_пилотов(п.байты, "big")
        оп, почему = ldpc_nagruzka.опознать_встроенный(ряд, 16632)
        self.assertIsNone(оп)
        self.assertIn("не код", почему)


class Автомат(unittest.TestCase):

    def test_цепочка_casc_с_шумом(self):
        """Автомат сам: пилоты (порядок «младший первым») → кадр 16632 → casc-8064-6048 (символ: инверсия
        второго бита) с исправлением при BER 10⁻² → ПСП 12, 9, 3, 2 со сбросом на слове → цикл 8192."""
        п = поток_casc()
        with mock.patch.object(ldpc, "КАТАЛОГ", None):
            разбор = razbor.разобрать(данные=п.байты, имя="casc.bin", профиль="обычно")
        уровни = [н.уровень for н in разбор.находки]
        self.assertEqual(["вставка", "цикл", "код", "скремблер", "цикл"], уровни[:5], разбор.отчёт())
        вставка, цикл, код, псп, цикл_данных = разбор.находки[:5]
        self.assertIn("младший первым", вставка.что)
        self.assertEqual(["реверс 8", "пилоты период 128 места 32,33 значения 10"], слои_находки(вставка))
        self.assertEqual(16632, int(цикл.свойства["длина"]))
        self.assertIn("casc-8064-6048", код.что)
        self.assertGreaterEqual(код.свойства["сошлось"], 0.95)
        self.assertIn("инверсия второго бита", код.свойства["симметрия"])
        self.assertEqual("пары инв 2", слои_находки(код)[0])
        self.assertEqual([2, 3, 9, 12], sorted(псп.свойства["отводы"]))
        self.assertEqual(6048, псп.свойства["длина_блока"])
        self.assertEqual(8192, int(цикл_данных.свойства["длина"]))
        # Данные после ПСП — переданные (по сошедшимся словам — без ошибок).
        выход = np.asarray(псп.дальше, dtype=np.uint8)
        слов = len(выход) // 6048
        сдвиг = min(range(0, 8), key=lambda s: float((выход[:6048] != п.данные[s]).mean()))
        расхождение = float((выход[:слов * 6048].reshape(слов, 6048) != п.данные[сдвиг:сдвиг + слов]).mean())
        self.assertLess(расхождение, 1e-3)


