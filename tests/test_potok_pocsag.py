"""POCSAG: BCH (31, 21) + чётность, адреса (RIC = адрес·8 + кадр), цифровые и текстовые сообщения.

Проверка кода — постоянными стандарта: слово простоя 0x7A89C197 и синхрослово 0x7CD215D8 (MMDVMHost,
multimon-ng) — кодовые слова; кодер из 21 бита данных должен дать их же. Таблица цифр — multimon-ng.
"""

import unittest

import numpy as np

import _bootstrap  # noqa: F401
from reportgen.potok import pocsag as p
from reportgen.potok.razbor import разобрать as разобрать_поток

ВЫЗОВЫ = [(1234567, 0, "5551234"), (200, 3, "Hello, world!"), (8, 0, "0-12 [3]")]


class КодTests(unittest.TestCase):
    def test_кодер_даёт_постоянные_стандарта(self):
        for слово in (p.ПРОСТОЙ, p.СИНХРО):
            self.assertEqual(слово, p.закодировать(слово >> 11), hex(слово))

    def test_исправление_одной_и_двух(self):
        слово = p.закодировать((1 << 20) | 0x5A5A5)
        for ошибки in ([0], [31], [5], [7, 20], [0, 13], [3, 30]):
            испорчено = слово
            for б in ошибки:
                испорчено ^= 1 << б
            with self.subTest(ошибки=ошибки):
                self.assertEqual((слово, len(ошибки)), p.исправить(испорчено))
        self.assertEqual((слово, 0), p.исправить(слово))

    def test_три_ошибки_не_исправляются(self):
        слово = p.закодировать(0x12345)
        отказов = 0
        for а, б, в in ((1, 2, 3), (4, 17, 30), (0, 8, 25), (10, 11, 12)):
            отказов += p.исправить(слово ^ (1 << а) ^ (1 << б) ^ (1 << в)) is None
        self.assertEqual(4, отказов)

    def test_цифры_и_текст(self):
        # «1» = 0001 младшим битом вперёд → 1000 → ЦИФРЫ[8]; пробел (0xC) → 0011 → ЦИФРЫ[3].
        self.assertEqual(("1", " "), (p.ЦИФРЫ[8], p.ЦИФРЫ[3]))
        self.assertEqual("12", p.цифровое([0b10000100001100110011]))
        # «A» (1000001) младшим битом вперёд — 1000001; «B» (1000010) — 0100001.
        кусок = int("1000001" + "0100001" + "001000", 2)         # A, B, начало EOT (0000100 → 0010000)
        self.assertEqual("AB", p.текстовое([кусок, 0]))


class ПотокTests(unittest.TestCase):
    def test_вызовы(self):
        р = p.разобрать(p.передать(ВЫЗОВЫ))
        self.assertEqual([(1234567, 0, "5551234"), (200, 3, "Hello, world!"), (8, 0, "0-12 [3]")],
                         [(с.адрес, с.функция, с.текст()) for с in р["сообщения"]])
        self.assertEqual(0, р["неисправимых"])

    def test_адрес_в_своём_кадре(self):
        """RIC mod 8 — номер кадра: адрес 1234567 (mod 8 = 7) стоит в словах 14–15 пакета."""
        биты = p.передать([(1234567, 0, "1")], преамбула=0)
        слова = [int("".join(map(str, биты[32 + 32 * n:64 + 32 * n])), 2) for n in range(16)]
        self.assertEqual([p.ПРОСТОЙ] * 14, слова[:14])
        self.assertEqual(1234567 >> 3, (слова[14] >> 13) & 0x3FFFF)

    def test_ошибки_и_инверсия(self):
        г = np.random.default_rng(3)
        биты = p.передать(ВЫЗОВЫ * 3)
        места = г.choice(len(биты), 25, replace=False)
        биты[места] ^= 1
        н = p.найти(1 - биты)
        self.assertIsNotNone(н)
        текст = "\n".join(н.подробно)
        self.assertIn("полярность обратная", текст)
        self.assertIn("RIC 200, функция 3: Hello, world!", текст)
        self.assertGreater(н.свойства["исправлено"], 0)

    def test_сообщение_через_границу_пакета(self):
        длинное = "Сообщение длиннее пакета: " + "x" * 80
        длинное = длинное.encode("ascii", "replace").decode()
        р = p.разобрать(p.передать([(16, 3, длинное)]))
        self.assertEqual(длинное, р["сообщения"][0].текст())
        self.assertGreater(р["пакетов"], 1)

    def test_ошибки_в_синхрословах(self):
        """По 2 ошибки в каждом синхрослове (прямом и инверсном) — пакеты находятся; 3 — уже нет."""
        биты = p.передать(ВЫЗОВЫ * 3)
        места = [м for м, _ in p.синхрослова(биты)]
        for ошибок, пакетов in ((2, len(места)), (3, 0)):
            испорчено = биты.copy()
            for м in места:
                испорчено[м + np.arange(ошибок) * 7] ^= 1
            with self.subTest(ошибок=ошибок):
                self.assertEqual(пакетов, p.разобрать(испорчено)["пакетов"])
                self.assertEqual(пакетов, p.разобрать(1 - испорчено)["пакетов"])

    def test_простой_и_неисправимое_обрывают_сообщение(self):
        сообщение = p.закодировать((1 << 20) | 0b10000100001100110011)            # «12»
        адрес = p.закодировать((5 << 2) | 0)
        def пакет(слова):
            слова = слова + [p.ПРОСТОЙ] * (16 - len(слова))
            return "".join(format(с, "032b") for с in [p.СИНХРО] + слова)
        испорченное = сообщение ^ 0b111 << 20
        поток = пакет([адрес, сообщение, p.ПРОСТОЙ, сообщение]) + пакет([адрес, сообщение, испорченное, сообщение])
        р = p.разобрать(np.array([int(б) for б in поток], np.uint8))
        self.assertEqual(["12", "12 [оборвано: неисправимое слово]"], [с.текст() for с in р["сообщения"]])
        self.assertEqual(1, р["неисправимых"])

    def test_текст_ровно_кратный_семи(self):
        буквы = "ABCDEFGHIJKLMNOPQRST"                                  # 20 символов = 140 бит = 7 кусков
        биты = "".join(format(ord(с), "07b")[::-1] for с in буквы)
        self.assertEqual(буквы, p.текстовое([int(биты[i:i + 20], 2) for i in range(0, 140, 20)]))

    def test_не_pocsag(self):
        г = np.random.default_rng(5)
        self.assertIsNone(p.найти(г.integers(0, 2, 200_000).astype(np.uint8)))
        # Одно синхрослово и мусор вместо кодовых слов — не POCSAG.
        мусор = г.integers(0, 2, 544 * 4).astype(np.uint8)
        for k in range(4):
            мусор[544 * k:544 * k + 32] = [(p.СИНХРО >> (31 - i)) & 1 for i in range(32)]
        self.assertIsNone(p.найти(мусор))

    def test_один_пакет_мало(self):
        биты = p.передать([(8, 0, "1")])
        self.assertEqual(1, p.разобрать(биты)["пакетов"])
        self.assertIsNone(p.найти(биты))

    def test_автомат(self):
        биты = p.передать(ВЫЗОВЫ * 6)
        биты = биты[:len(биты) // 8 * 8]
        р = разобрать_поток(данные=np.packbits(биты).tobytes(), профиль="быстро")
        найдено = [н for н in р.находки if н.что.startswith("POCSAG")]
        self.assertTrue(найдено, [н.что for н in р.находки])
        self.assertIn("RIC 1234567, функция 0: 5551234", найдено[0].подробно)


if __name__ == "__main__":
    unittest.main()
