"""Для потоков РРЛ: модуляционная плоскость, многоотводные скремблеры.

Цепочки — как у аналитика вручную: метки демодулятора КАМ с неизвестным
поворотом плоскости → скремблер → HDLC; многоотводный мультипликативный
скремблер над кадрами с паузами.
"""

import unittest

import numpy as np

import _bootstrap  # noqa: F401
import potok_sintez as с
from reportgen.potok import forni, gfp, hdlc, kod, pakety, ploskost, skrembler, разобрать
from reportgen.potok.bity import в_байты, в_биты
from reportgen.potok.razbor import снять_вручную

КАДРЫ = в_биты(с.hdlc(с.пакеты_ip(400), флагов_между=4))
V35 = с.скремблировать(КАДРЫ, (3, 20))


def повернуть(биты, k, **вариант):
    return ploskost.преобразовать(биты[:len(биты) // k * k], k, **вариант)


class ПлоскостьTests(unittest.TestCase):
    def test_симметрии_это_группа(self):
        биты = с.случайные_биты(6000)
        for k in (4, 6, 8):
            with self.subTest(k=k):
                x = биты[:len(биты) // k * k]
                for _ in range(4):
                    x = повернуть(x, k, порядок="старший", раскладка="половинами", код="Грей",
                                  симметрия="поворот 90°")
                self.assertTrue(np.array_equal(биты[:len(x)], x), "4 поворота — тождество")
                y = повернуть(биты, k, порядок="младший", раскладка="вперемешку",
                              код="натуральный", симметрия="обмен I и Q")
                y = повернуть(y, k, порядок="младший", раскладка="вперемешку",
                              код="натуральный", симметрия="обмен I и Q")
                self.assertTrue(np.array_equal(биты[:len(y)], y))

    def test_грей_отрицание_уровня_это_старший_бит(self):
        # Независимая сверка: в коде Грея отражение уровня m → L−1−m меняет
        # только старший бит метки.
        уровни = np.arange(8)
        грей = уровни ^ (уровни >> 1)
        отражённые = (7 - уровни) ^ ((7 - уровни) >> 1)
        self.assertTrue(np.array_equal(грей ^ 0b100, отражённые))

    def test_поворот_найден_и_под_ним_скремблер_и_hdlc(self):
        for k, вариант in ((6, {"симметрия": "поворот 90°", "код": "Грей", "раскладка": "половинами"}),
                           (8, {"симметрия": "обмен с поворотом", "код": "Грей",
                                    "раскладка": "половинами"})):
            with self.subTest(k=k):
                метки = повернуть(V35, k, порядок="старший", **вариант)
                self.assertIsNone(skrembler.найти(метки), "в неверной плоскости скремблера нет")
                найдено = ploskost.найти(метки, k)
                сошлось = []
                for _имя, ряд in найдено.дальше.items():
                    с_ = skrembler.найти(ряд)
                    сошлось.append(bool(с_ and hdlc.найти(с_.дальше)))
                self.assertTrue(сошлось[0], "лучший вариант должен открывать HDLC")

    def test_слои_вариантов_как_выход(self):
        """Каждый вариант плоскости КАМ — со свойством «слой» (симметрия, код, раскладка, порядок): ручной слой
        даёт ровно выход варианта."""
        from reportgen.potok.razbor import _варианты  # noqa: PLC0415
        метки = повернуть(V35, 6, порядок="старший", симметрия="поворот 90°", код="Грей", раскладка="половинами")
        найдено = ploskost.найти(метки, 6)
        for находка, ряд in _варианты(найдено):
            with self.subTest(вариант=находка.что):
                слой = находка.свойства["слой"]
                self.assertTrue(слой.startswith("плоскость 6 "), слой)
                self.assertTrue(np.array_equal(ряд, снять_вручную(метки, слой)[0]))

    def test_случайный_поток_плоскости_не_даёт(self):
        self.assertIsNone(ploskost.найти(с.случайные_биты(200_000), 6))

    def test_ручное_указание(self):
        метки = повернуть(V35, 6, порядок="старший", симметрия="поворот 90°", код="Грей",
                          раскладка="половинами")
        ряд, запись = снять_вручную(метки, "плоскость 6 поворот 270° Грей половинами старший")
        self.assertTrue(np.array_equal(V35[:len(ряд)], ряд))
        ряд, запись = снять_вручную(метки, "плоскость 6")
        self.assertIn("выбран лучший вариант", " ".join(запись.подробно))

    def test_вся_цепочка_с_числом_бит(self):
        метки = повернуть(V35, 6, порядок="старший", симметрия="поворот 90°", код="Грей",
                          раскладка="половинами")
        # Профиль «обычно» (600 с): на «быстро» (90 с) цепочка сходится за ~60 с, и под нагрузкой
        # машины (параллельные прогоны) срок кончался сразу после плоскости — проверка была не о том.
        разбор = разобрать(данные=в_байты(метки), имя="ррл.bin", символ=[6], профиль="обычно")
        self.assertEqual(["плоскость", "скремблер", "канальный", "сетевой"],
                         [н.уровень for н in разбор.находки])


class МногоотводныеTests(unittest.TestCase):
    ПАУЗЫ = в_биты(с.hdlc(с.пакеты_ip(260), флагов_между=40))[:400_000]

    def test_до_десяти_отводов(self):
        for отводы in ((1, 5, 9, 17, 23), (2, 3, 7, 11, 13, 19, 31),
                       (1, 2, 4, 6, 9, 13, 17, 22, 29, 37)):
            with self.subTest(отводы=отводы):
                найдено = skrembler.найти(с.скремблировать(self.ПАУЗЫ, отводы))
                self.assertIn(skrembler.полином_словами(отводы), найдено.что)
                self.assertEqual(1.0, hdlc.найти(найдено.дальше).уверенность)

    def test_произведение_на_период_данных_снимается(self):
        # БМ в окне с флагами даёт P·D, D | 1 + x^8; кандидатом должен
        # стать сам P — даже когда P делится на 1 + x (чётное число членов).
        бм = skrembler.кандидаты_бм(с.скремблировать(self.ПАУЗЫ, (2, 3, 7, 11, 13, 19, 31))[:1 << 18])
        self.assertIn((2, 3, 7, 11, 13, 19, 31), [о for о, _ in бм])

    def test_аддитивные_многоотводные(self):
        # Произведения «ПСП × период пауз» соперниками верному полиному не
        # считаются, а сама ПСП восстанавливается по паузе.
        исходный = в_биты(с.hdlc(с.пакеты_ip(120), флагов_между=60))[:400_000]
        for отводы in ((14, 15), (3, 5, 9, 23), (2, 11, 17, 31)):
            with self.subTest(отводы=отводы):
                ряд = skrembler.псп(отводы, np.ones(max(отводы), dtype=np.uint8),
                                    len(исходный))
                найдено = skrembler.найти(исходный ^ ряд)
                self.assertEqual(f"аддитивная ПСП {skrembler.полином_словами(отводы)}",
                                 найдено.что)
                self.assertEqual(1.0, hdlc.найти(найдено.дальше).уверенность)

    def test_случайный_поток_без_скремблера(self):
        self.assertIsNone(skrembler.найти(с.случайные_биты(400_000, сид=3)))



class GfpAtmTests(unittest.TestCase):
    ПАКЕТЫ = с.пакеты_ip(120)

    def test_пустой_кадр_gfp_на_линии_b6ab31e0(self):
        # Сверка со стандартом, а не с генератором: пустой кадр G.7041 (PLI = 0,
        # cHEC = 0) после маски выглядит как B6 AB 31 E0.
        self.assertEqual("b6ab31e0", с.gfp([с.ethernet(self.ПАКЕТЫ[0])])[:4].hex())
        self.assertEqual(0, gfp.hec16(b"\0\0"))

    def test_gfp_при_любом_сдвиге_до_ip(self):
        поток = с.gfp([с.ethernet(п) for п in self.ПАКЕТЫ])
        for сдвиг in (0, 5):
            with self.subTest(сдвиг=сдвиг):
                биты = np.concatenate([np.zeros(сдвиг, np.uint8), в_биты(b"\x55" * 7 + поток)])
                найдено = gfp.найти(биты)
                self.assertEqual("GFP (G.7041): Ethernet (кадровое отображение)", найдено.что)
                self.assertIn("с верным tHEC — в 119 из 119", " ".join(найдено.подробно))
                self.assertIn("119 из 119", pakety.найти_в_кадрах(найдено.дальше).мера)

    def test_atm_и_aal5(self):
        найдено = gfp.найти(в_биты(b"\0" * 11 + с.atm(self.ПАКЕТЫ[:60])))
        self.assertEqual("ячейки ATM (53 байта)", найдено.что)
        self.assertIn("AAL5: собрано PDU 60, CRC-32 сошлась у 60", " ".join(найдено.подробно))
        self.assertIn("60 из 60", pakety.найти_в_кадрах(найдено.дальше).мера)

    def test_gfp_и_atm_в_разборе(self):
        for имя, данные in (("gfp.bin", с.gfp([с.ethernet(п) for п in self.ПАКЕТЫ])),
                            ("atm.bin", b"\0" * 11 + с.atm(self.ПАКЕТЫ[:60]))):
            with self.subTest(имя):
                разбор = разобрать(данные=данные, имя=имя)
                self.assertEqual(["канальный", "сетевой"], [н.уровень for н in разбор.находки])

    def test_случайный_не_gfp_и_не_atm(self):
        self.assertIsNone(gfp.найти(с.случайные_биты(400_000)))


class ФМиСимволTests(unittest.TestCase):
    def test_фм_повороты_и_отражения(self):
        for k, поворот, отражение in ((2, 1, False), (3, 5, True), (4, 7, True)):
            with self.subTest(k=k):
                x = V35[:len(V35) // k * k]
                метки = ploskost.преобразовать_фм(x, k, порядок="старший", код="Грей",
                                                  поворот=поворот, отражение=отражение)
                найдено = ploskost.найти_фм(метки, k)
                ряд = next(iter(найдено.дальше.values()))
                self.assertTrue(np.array_equal(x[:len(ряд)], ряд))
                self.assertEqual(1.0, hdlc.найти(skrembler.найти(ряд).дальше).уверенность)
        self.assertIsNone(ploskost.найти_фм(с.случайные_биты(300_000), 3))

    def test_фм_вручную_и_операции_над_символом(self):
        x = V35[:len(V35) // 3 * 3]
        метки = ploskost.преобразовать_фм(x, 3, порядок="старший", код="Грей", поворот=5,
                                          отражение=True)
        ряд, запись = снять_вручную(метки, "фм 3 поворот 5 отражение")
        self.assertTrue(np.array_equal(x, ряд))
        self.assertIn("поворот 5 (225°), отражение, Грей", запись.подробно[0])
        ряд, _ = снять_вручную(метки, "фм 3")
        self.assertTrue(np.array_equal(x[:len(ряд)], ряд))
        # Перестановка меток: 2 бита, 0→0, 1→1, 2→3, 3→2 (натуральный ↔ Грей).
        y = np.array([0, 0, 0, 1, 1, 0, 1, 1], dtype=np.uint8)
        self.assertEqual([0, 0, 0, 1, 1, 1, 1, 0], снять_вручную(y, "метки 2: 0 1 3 2")[0].tolist())
        self.assertEqual([0, 0, 1, 0, 0, 1, 1, 1],
                         снять_вручную(y, "биты символа 2: 1 0")[0].tolist())
        # Несимметричная перестановка 3 бит: новый бит i — старый откуда[i].
        self.assertEqual([1, 0, 0, 1, 0, 1], снять_вручную(np.array([0, 0, 1, 0, 1, 1], np.uint8),
                                                           "биты символа 3: 2 0 1")[0].tolist())
        for плохое in ("метки 2: 0 1 2 2", "биты символа 3: 0 1", "фм 9"):
            with self.subTest(плохое=плохое), self.assertRaises(ValueError):
                снять_вручную(y, плохое)


class КадровыйСкремблерTests(unittest.TestCase):
    """Аддитивная ПСП со сбросом в каждом кадре: отводы и начальное состояние."""

    @staticmethod
    def линия(отводы, начальное, сид=3):
        rng = np.random.default_rng(сид)
        данные = np.zeros((300, 1000), np.uint8)
        данные[:, 400:700] = rng.integers(0, 2, (300, 300))       # нагрузка
        данные[:, 800:850] = 1                                      # заполнение единицами
        данные[:, :32] = np.unpackbits(np.frombuffer(bytes.fromhex("1ACFFC1D"), np.uint8))
        н = np.array([int(c) for c in начальное], np.uint8)
        return данные.reshape(-1), skrembler.снять_по_кадру(данные.reshape(-1), отводы, н, 1000, 32)

    def test_вслепую_и_по_отводам(self):
        for отводы, начальное in (((6, 7), "1111111"), ((14, 15), "100101010000000"),
                                  ((3, 5, 9, 23), "1" * 23), ((2, 11, 17, 31), "1010" * 7 + "101")):
            with self.subTest(отводы=отводы):
                данные, линия = self.линия(отводы, начальное)
                вслепую = skrembler.найти_по_кадру(линия, 1000, пропуск=32)
                self.assertEqual((list(отводы), начальное), (вслепую["отводы"], вслепую["начальное"]))
                по_отводам = skrembler.найти_по_кадру(линия, 1000, пропуск=32, отводы=отводы)
                self.assertEqual(начальное, по_отводам["начальное"])

    def test_слоем(self):
        данные, линия = self.линия((3, 5, 9, 23), "1" * 23)
        # Поток начинается не с кадра: 77 лишних бит, начало кадра — «начало 77».
        поток = np.concatenate([с.случайные_биты(77), линия])
        for указание in ("аддитивный кадр 1000 пропуск 32 начало 77",
                         "аддитивный отводы 3,5,9,23 кадр 1000 пропуск 32 начало 77",
                         "аддитивный отводы 3,5,9,23 кадр 1000 начальное " + "1" * 23 +
                         " пропуск 32 начало 77"):
            with self.subTest(указание=указание):
                ряд, запись = снять_вручную(поток, указание)
                self.assertTrue(np.array_equal(данные, ряд))
                self.assertIn("начальное состояние (первые 23 бит ПСП после сброса): " + "1" * 23,
                              запись.подробно[1])
        for плохое in ("аддитивный", "аддитивный отводы 6,7 кадр 1000 начальное 101",
                       "аддитивный кадр 1000 пропуск 2000"):
            with self.subTest(плохое=плохое), self.assertRaises(ValueError):
                снять_вручную(поток, плохое)

    def test_непрерывная_по_паузе(self):
        исходный = в_биты(с.hdlc(с.пакеты_ip(120), флагов_между=60))[:400_000]
        ряд = skrembler.псп((14, 15), np.ones(15, dtype=np.uint8), len(исходный))
        снято, запись = снять_вручную(исходный ^ ряд, "аддитивный отводы 14,15")
        self.assertIn("восстановлена по паузе", запись.подробно[0])
        self.assertEqual(1.0, hdlc.найти(снято).уверенность)

    def test_устойчивый_участок_не_у_начала(self):
        # Перед нулями — 68 случайных столбцов: ПСП продлевается назад до пропуска.
        rng = np.random.default_rng(5)
        данные = np.zeros((300, 1000), np.uint8)
        данные[:, 32:100] = rng.integers(0, 2, (300, 68))
        данные[:, 500:900] = rng.integers(0, 2, (300, 400))
        данные[:, :32] = np.unpackbits(np.frombuffer(bytes.fromhex("1ACFFC1D"), np.uint8))
        начальное = "1010011" + "0" * 4 + "1101"
        линия = skrembler.снять_по_кадру(данные.reshape(-1), (14, 15),
                                         np.array([int(c) for c in начальное], np.uint8), 1000, 32)
        итог = skrembler.найти_по_кадру(линия, 1000, пропуск=32)
        self.assertEqual(([14, 15], начальное), (итог["отводы"], итог["начальное"]))

    def test_случайный_поток_не_даёт(self):
        self.assertIsNone(skrembler.найти_по_кадру(с.случайные_биты(300_000), 1000))


class ФорниTests(unittest.TestCase):
    КОД = с.свёрточный(с.случайные_биты(300_000))

    def test_перестановка_обратима(self):
        x = с.случайные_биты(50_000)
        снято = forni.снять(forni.перемежить(x, 12, 17, 3), 12, 17, 3)
        self.assertTrue(np.array_equal(x[:len(снято)], снято))

    def test_параметры_вслепую(self):
        # 24 × 3 и 36 × 2 дают одно произведение M·I — выбрать надо верную пару.
        for I, M, фаза, доля in ((24, 3, 5, 0.0), (8, 5, 3, 0.01)):
            with self.subTest(I=I, M=M):
                поток = forni.перемежить(self.КОД, I, M, фаза)[1000:]
                поток = поток ^ (np.random.default_rng(1).random(len(поток)) < доля).astype(np.uint8)
                найдено = forni.найти(поток)
                self.assertIn(f"I = {I} ветвей, M = {M}", найдено.что)
                self.assertIn("171/133", kod.найти(найдено.дальше[:300_000], длинные=False).что)

    def test_ручное_снятие(self):
        x = с.случайные_биты(60_000)
        ряд, запись = снять_вручную(forni.перемежить(x, 12, 17, 3), "форни 12 17 3")
        self.assertTrue(np.array_equal(x[:len(ряд)], ряд))
        self.assertEqual(len(x) - 11 * 17 * 12, len(ряд))
        self.assertIn("I = 12 ветвей, M = 17, фаза ветвей 3", запись.подробно[0])
        for плохое in ("форни 12", "форни 1 5"):
            with self.subTest(плохое=плохое), self.assertRaises(ValueError):
                снять_вручную(x, плохое)

    def test_случайный_и_код_без_перемежения(self):
        self.assertIsNone(forni.найти(с.случайные_биты(600_000)))
        self.assertIsNone(forni.найти(self.КОД[:600_000]))

