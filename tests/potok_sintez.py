# -- пакеты -------------------------------------------------------------------

def _сумма(данные: bytes) -> int:
    if len(данные) % 2:
        данные += b"\0"
    сумма = sum(struct.unpack(f"!{len(данные) // 2}H", данные))
    while сумма >> 16:
        сумма = (сумма & 0xFFFF) + (сумма >> 16)
    return (~сумма) & 0xFFFF


def ipv4(источник: str, получатель: str, протокол: int, тело: bytes,
         идентификатор: int = 1) -> bytes:
    src = bytes(int(x) for x in источник.split("."))
    dst = bytes(int(x) for x in получатель.split("."))
    заголовок = struct.pack("!BBHHHBBH4s4s", 0x45, 0, 20 + len(тело), идентификатор,
                            0x4000, 64, протокол, 0, src, dst)
    заголовок = заголовок[:10] + struct.pack("!H", _сумма(заголовок)) + заголовок[12:]
    return заголовок + тело


def udp(источник: str, получатель: str, порт_от: int, порт_к: int, данные: bytes,
        идентификатор: int = 1) -> bytes:
    длина = 8 + len(данные)
    src = bytes(int(x) for x in источник.split("."))
    dst = bytes(int(x) for x in получатель.split("."))
    псевдо = src + dst + struct.pack("!BBH", 0, 17, длина)
    дейт = struct.pack("!HHHH", порт_от, порт_к, длина, 0) + данные
    сумма = _сумма(псевдо + дейт) or 0xFFFF
    дейт = дейт[:6] + struct.pack("!H", сумма) + дейт[8:]
    return ipv4(источник, получатель, 17, дейт, идентификатор)


def tcp(источник: str, получатель: str, порт_от: int, порт_к: int, данные: bytes,
        идентификатор: int = 1) -> bytes:
    сегмент = struct.pack("!HHIIBBHHH", порт_от, порт_к, 1000, 0, 0x50, 0x18,
                          65535, 0, 0) + данные
    return ipv4(источник, получатель, 6, сегмент, идентификатор)


def пакеты_ip(сколько: int, *, сид: int = 1) -> list[bytes]:
    случай = random.Random(сид)
    итог = []
    for номер in range(сколько):
        данные = bytes(случай.randrange(256) for _ in range(случай.randrange(20, 200)))
        if номер % 3:
            итог.append(udp("10.1.2.3", "10.9.8.7", 5000 + номер % 4, 53, данные, номер))
        else:
            итог.append(tcp("192.168.1.10", "192.168.1.20", 40000, 80, данные, номер))
    return итог


# -- HDLC ---------------------------------------------------------------------

def hdlc(кадры: Sequence[bytes], *, fcs: int = 16, флагов_между: int = 2,
         порядок: str = "старший") -> bytes:
    """Кадры → поток HDLC с битстаффингом и FCS, упакованный в байты.

    Октеты передаются младшим битом первым; ряд затем пакуется в байты
    «прибора» старшим битом первым (или младшим — по ``порядок``).
    """
    флаг = [0, 1, 1, 1, 1, 1, 1, 0]
    ряд: list[int] = флаг * флагов_между
    for кадр in кадры:
        if fcs == 16:
            проверка = (fcs16(кадр) ^ 0xFFFF).to_bytes(2, "little")
        else:
            проверка = (fcs32(кадр) ^ 0xFFFFFFFF).to_bytes(4, "little")
        биты = list(в_биты(кадр + проверка, "младший"))
        подряд = 0
        for бит in биты:
            ряд.append(int(бит))
            подряд = подряд + 1 if бит else 0
            if подряд == 5:
                ряд.append(0)
                подряд = 0
        ряд += флаг * флагов_между
    ряд += [0] * ((-len(ряд)) % 8)
    return в_байты(np.array(ряд, dtype=np.uint8), порядок)


# -- скремблер ------------------------------------------------------------------

def скремблировать(биты: np.ndarray, отводы: Sequence[int]) -> np.ndarray:
    """Мультипликативный скремблер: y[n] = x[n] ^ y[n-a] ^ y[n-b] …"""
    выход = np.zeros(len(биты), dtype=np.uint8)
    регистр = [0] * (max(отводы) + 1)
    for номер, бит in enumerate(биты):
        значение = int(бит)
        for отвод in отводы:
            значение ^= регистр[-отвод]
        выход[номер] = значение
        регистр.append(значение)
        регистр.pop(0)
    return выход


# -- E1, G.704 ------------------------------------------------------------------

FAS = [0, 0, 1, 1, 0, 1, 1]


def e1(циклов: int, *, каналы=None, сид: int = 3) -> bytes:
    """Цикл E1 по G.704: 32 канальных интервала по 8 бит, 8000 циклов в секунду.

    КИ0: в чётных циклах — Si + FAS 0011011, в нечётных — Si, 1, A, Sa4–Sa8.
    ``каналы`` — функция (цикл, КИ) → байт; по умолчанию речь (почти
    случайные байты), КИ16 — сигнализация, часть каналов свободна (0xD5).
    """
    случай = random.Random(сид)
    итог = bytearray()
    for цикл in range(циклов):
        for ки in range(32):
            if ки == 0:
                if цикл % 2 == 0:
                    байт = (1 << 7) | int("".join(map(str, FAS)), 2)
                else:
                    байт = 0b11011111
            elif каналы is not None:
                байт = каналы(цикл, ки)
            elif ки == 16:
                байт = 0x0B if цикл % 16 == 0 else 0x99
            elif ки > 24:
                байт = 0xD5                    # свободный канал: тишина A-закона
            else:
                байт = случай.randrange(256)
            итог.append(байт)
    return bytes(итог)


# -- коды -------------------------------------------------------------------------

def хэмминг74(биты: np.ndarray) -> np.ndarray:
    """Систематический код Хэмминга (7,4): d1 d2 d3 d4 p1 p2 p3."""
    целых = len(биты) - len(биты) % 4
    d = биты[:целых].reshape(-1, 4)
    p1 = d[:, 0] ^ d[:, 1] ^ d[:, 3]
    p2 = d[:, 0] ^ d[:, 2] ^ d[:, 3]
    p3 = d[:, 1] ^ d[:, 2] ^ d[:, 3]
    return np.column_stack([d, p1, p2, p3]).reshape(-1).astype(np.uint8)


def свёрточный(биты: np.ndarray, g1: int = 0o171, g2: int = 0o133, k: int = 7) -> np.ndarray:
    """Свёрточный код скорости 1/2 (по умолчанию стандартный K=7, 171/133).

    Многочлены — в записи стандартов (старший бит — текущий вход), как в libfec
    (0x4F/0x6D при регистре (r << 1) | бит) и GNU Radio.
    """
    from reportgen.potok.svyortka import зеркало
    g1, g2 = зеркало(g1, k), зеркало(g2, k)
    регистр = 0
    выход = np.zeros(2 * len(биты), dtype=np.uint8)
    for номер, бит in enumerate(биты):
        регистр = ((регистр << 1) | int(бит)) & ((1 << k) - 1)
        выход[2 * номер] = bin(регистр & g1).count("1") & 1
        выход[2 * номер + 1] = bin(регистр & g2).count("1") & 1
    return выход


def случайные_биты(сколько: int, сид: int = 5) -> np.ndarray:
    return np.random.default_rng(сид).integers(0, 2, сколько, dtype=np.uint8)


def sig(пакеты: Sequence[bytes], *, порядок: str = "big", включает: bool = False,
        заголовок_файла: bytes = b"") -> bytes:
    итог = bytearray(заголовок_файла)
    for пакет in пакеты:
        длина = len(пакет) + (2 if включает else 0)
        итог += длина.to_bytes(2, порядок) + пакет
    return bytes(итог)


# -- октетный стаффинг --------------------------------------------------------------

def hdlc_асинхронный(кадры: Sequence[bytes], *, fcs: int = 16) -> bytes:
    """Асинхронное HDLC (RFC 1662): 0x7E, экран 0x7D, ACCM — все байты < 0x20."""
    итог = bytearray([0x7E])
    for кадр in кадры:
        if fcs == 16:
            проверка = (fcs16(кадр) ^ 0xFFFF).to_bytes(2, "little")
        else:
            проверка = (fcs32(кадр) ^ 0xFFFFFFFF).to_bytes(4, "little")
        for байт in кадр + проверка:
            if байт in (0x7E, 0x7D) or байт < 0x20:
                итог += bytes([0x7D, байт ^ 0x20])
            else:
                итог.append(байт)
        итог.append(0x7E)
    return bytes(итог)


def slip(пакеты: Sequence[bytes]) -> bytes:
    итог = bytearray([0xC0])
    for пакет in пакеты:
        for байт in пакет:
            if байт == 0xC0:
                итог += b"\xdb\xdc"
            elif байт == 0xDB:
                итог += b"\xdb\xdd"
            else:
                итог.append(байт)
        итог.append(0xC0)
    return bytes(итог)


# -- PDH со стаффингом ----------------------------------------------------------------

def pdh(притоки: Sequence[np.ndarray], иерархия, циклов: int,
        доли: Sequence[float]) -> np.ndarray:
    """Мультиплексор PDH: побитное чередование и положительный стаффинг.

    ``доли`` — доля циклов со стаффингом у каждого притока; решение — по
    накопителю, как у настоящего буфера согласования. Возвращает биты агрегата;
    каждый приток уходит в него с начала, подряд.
    """
    from reportgen.potok.pdh import разметка
    данные, cj, стаффинг = разметка(иерархия)
    L = иерархия.цикл
    итог = np.zeros(циклов * L, dtype=np.uint8)
    места = [0] * len(притоки)
    накопитель = [0.0] * len(притоки)
    fas = np.array(иерархия.fas, dtype=np.uint8)
    for цикл in range(циклов):
        кадр = итог[цикл * L:(цикл + 1) * L]
        кадр[:len(fas)] = fas
        for t, приток in enumerate(притоки):
            накопитель[t] += доли[t]
            пустой = накопитель[t] >= 1.0
            if пустой:
                накопитель[t] -= 1.0
            for позиция in cj[t]:
                кадр[позиция] = 1 if пустой else 0
            позиции = sorted(данные[t] + [стаффинг[t]])
            if пустой:
                позиции.remove(стаффинг[t])
                кадр[стаффинг[t]] = 1
            кусок = приток[места[t]:места[t] + len(позиции)]
            кадр[позиции[:len(кусок)]] = кусок
            места[t] += len(позиции)
    return итог


# -- перемежение ------------------------------------------------------------------------

def перемежить_блочно(биты: np.ndarray, строк: int, столбцов: int) -> np.ndarray:
    """Пишем по строкам (строка — слово кода), читаем по столбцам."""
    блок = строк * столбцов
    целых = len(биты) - len(биты) % блок
    return биты[:целых].reshape(-1, строк, столбцов).transpose(0, 2, 1).reshape(-1)


def dvb(пакетов: int, *, сид: int = 4, перемежать: bool = True) -> bytes:
    """MPEG-TS → рандомизация → RS(204, 188) → свёрточное перемежение (DVB)."""
    from reportgen.potok import dvb as канал
    случай = np.random.default_rng(сид)
    пакеты = случай.integers(0, 256, (пакетов, 188), dtype=np.uint8)
    пакеты[:, 0] = 0x47
    pid = np.array([0x100, 0x101, 0x1FFF])[случай.integers(0, 3, пакетов)]
    пакеты[:, 1] = (pid >> 8) & 0x1F
    пакеты[:, 2] = pid & 0xFF
    рандомизированные = канал.рандомизировать(пакеты, 0)
    рандомизированные[::8, 0] = 0xB8
    поток = канал.закодировать(рандомизированные).reshape(-1)
    if перемежать:
        поток = канал.перемежить(поток, 0)
    return поток.tobytes()


# -- LDPC, турбо, РС ------------------------------------------------------------------

def qc_ldpc(строк: int = 12, столбцов: int = 24, Z: int = 27, вес: int = 7, сид: int = 2
            ) -> np.ndarray:
    """Квазициклическая H: блоки Z × Z — нули или сдвинутые единичные (свой код, не стандарт)."""
    случай = np.random.default_rng(сид)
    H = np.zeros((строк * Z, столбцов * Z), np.uint8)
    единичная = np.eye(Z, dtype=np.uint8)
    for i in range(строк):
        for j in случай.choice(столбцов, вес, replace=False):
            H[i * Z:(i + 1) * Z, j * Z:(j + 1) * Z] = np.roll(единичная, случай.integers(Z), axis=1)
    return H


def систематический(H: np.ndarray):
    """Порождающая матрица в ступенчатом виде и информационные позиции."""
    from reportgen.potok import gf2
    n = H.shape[1]
    приведённая, опорные = gf2.привести(gf2.упаковать(gf2.ядро(H)), n)
    return gf2.распаковать(приведённая, n), опорные


def rsc(данные: np.ndarray, обратная: int = 0o13, прямая: int = 0o15, K: int = 4
        ) -> tuple:
    """RSC с хвостом (обнуление регистра): проверки и хвост (u, p) × (K − 1).

    Многочлены — в записи стандартов: по умолчанию как в LTE (36.212 5.1.3.2.1:
    g0 = 1 + D² + D³ — 13, g1 = 1 + D + D³ — 15).
    """
    from reportgen.potok import svyortka
    обратная, прямая = svyortka.зеркало(обратная, K), svyortka.зеркало(прямая, K)
    пары = svyortka.кодировать_rsc(данные, обратная, прямая, K)
    память = (1 << (K - 1)) - 1
    s = 0
    for u in данные:
        a = int(u) ^ (bin((s << 1) & обратная).count("1") & 1)
        s = ((s << 1) | a) & память
    хвост = []
    for _ in range(K - 1):
        u = bin((s << 1) & обратная).count("1") & 1       # вход, при котором a = 0
        r = s << 1
        хвост += [u, bin(r & прямая).count("1") & 1]
        s = r & память
    return пары[1::2], np.array(хвост, dtype=np.uint8)


def турбо(блоков: int, K: int = 160, f1: int = 21, f2: int = 120, сид: int = 3):
    """PCCC 1/3 (u, p1, p2) с перемежителем QPP и хвостами обоих кодеров, как в LTE."""
    случай = np.random.default_rng(сид)
    i = np.arange(K)
    π = (f1 * i + f2 * i * i) % K
    поток, данные = [], []
    for _ in range(блоков):
        u = случай.integers(0, 2, K, dtype=np.uint8)
        p1, хвост1 = rsc(u)
        p2, хвост2 = rsc(u[π])
        поток.append(np.concatenate([np.column_stack([u, p1, p2]).reshape(-1), хвост1, хвост2]))
        данные.append(u)
    return np.concatenate(поток), np.array(данные), π


def рс(слов: int, n: int, k: int, *, многочлен: int = 0x11D, первый: int = 0, сид: int = 1
       ) -> np.ndarray:
    """Систематический код Рида — Соломона над GF(256): слова × n байт."""
    from reportgen.potok import rs_bch
    степень, _, умножение = rs_bch.поле(многочлен)
    g = [1]
    for i in range(n - k):
        корень = int(степень[первый + i])
        новый = [0] * (len(g) + 1)
        for j, c in enumerate(g):
            новый[j] ^= c
            новый[j + 1] ^= int(умножение[c, корень])
        g = новый
    случай = np.random.default_rng(сид)
    итог = np.zeros((слов, n), dtype=np.uint8)
    for w in range(слов):
        d = случай.integers(0, 256, k).tolist()
        остаток = [0] * (n - k)
        for b in d:
            обратная = b ^ остаток[0]
            остаток = остаток[1:] + [0]
            for j in range(n - k):
                остаток[j] ^= int(умножение[g[j + 1], обратная])
        итог[w] = d + остаток
    return итог


# -- GFP и ATM -------------------------------------------------------------------------

def gfp(кадры: Sequence[bytes], *, пустых_между: int = 2, upi: int = 0x01) -> bytes:
    """GFP (G.7041): основной заголовок с cHEC и маской B6AB31E0, заголовок типа
    с tHEC, нагрузка под мультипликативным скремблером x⁴³ + 1. CRC — своя
    (эталонный генератор gfp_sintez), не код анализатора."""
    from gfp_sintez import crc16

    def hec(данные):
        return crc16(данные).to_bytes(2, "big")

    маска = bytes.fromhex("B6AB31E0")
    пустой = bytes(a ^ b for a, b in zip(b"\0\0" + hec(b"\0\0"), маска, strict=False))
    # Нагрузки скремблируются сплошным потоком — сперва собираем их все.
    нагрузки = []
    for кадр in кадры:
        тип = bytes([0b000_0_0000, upi])
        нагрузки.append(тип + hec(тип) + кадр)
    сплошь = в_биты(b"".join(нагрузки))
    скр = в_байты(скремблировать(сплошь, (43,)))
    итог = bytearray(пустой * пустых_между)
    место = 0
    for нагрузка in нагрузки:
        pli = len(нагрузка).to_bytes(2, "big")
        итог += bytes(a ^ b for a, b in zip(pli + hec(pli), маска, strict=False))
        итог += скр[место:место + len(нагрузка)]
        место += len(нагрузка)
        итог += пустой * пустых_между
    return bytes(итог)


def ethernet(пакет: bytes) -> bytes:
    return bytes.fromhex("0011223344550066778899aa0800") + пакет


def atm(пакеты: Sequence[bytes], vpi: int = 1, vci: int = 32) -> bytes:
    """AAL5 над ATM: PDU с длиной и CRC-32, ячейки по 53 байта с HEC (x⁸+x²+x+1, ⊕0x55)."""
    from reportgen.potok import crc as crc_
    итог = bytearray()
    for пакет in пакеты:
        набивка = (-(len(пакет) + 8)) % 48
        pdu = пакет + bytes(набивка) + b"\0\0" + len(пакет).to_bytes(2, "big")
        pdu += crc_.crc(pdu, 32, 0x04C11DB7, 0xFFFFFFFF, False, False, 0xFFFFFFFF).to_bytes(4, "big")
        for номер in range(0, len(pdu), 48):
            последняя = номер + 48 >= len(pdu)
            заголовок = bytes([(vpi >> 4) & 0x0F, ((vpi & 0x0F) << 4) | (vci >> 12),
                               (vci >> 4) & 0xFF, ((vci & 0x0F) << 4) | (0b001 << 1 if последняя else 0)])
            hec = crc_.crc(заголовок, 8, 0x07, 0, False, False, 0) ^ 0x55
            итог += заголовок + bytes([hec]) + pdu[номер:номер + 48]
    return bytes(итог)
