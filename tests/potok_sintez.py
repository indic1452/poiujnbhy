"""Синтетические потоки с ИЗВЕСТНЫМ ответом — для проверки анализатора.

Слепой разбор проверить можно только так: собрать поток, строение которого
известно до бита, и посмотреть, найдёт ли анализатор ровно его. Здесь —
кадры HDLC с битстаффингом и FCS, пакеты IPv4/UDP/TCP с верными
контрольными суммами, цикл E1 по G.704, самосинхронизирующиеся скремблеры,
коды Хэмминга и свёрточный код.
"""

