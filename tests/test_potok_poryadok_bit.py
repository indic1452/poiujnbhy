"""Порядок бит в байте файла: демодуляторы и BitView пишут младшим битом вперёд.

При неверном порядке и цикле, не кратном 8, синхромаркер в каждой второй строке
растра переставлен внутри байта — «размазан»; при верном — ровный столбец. Файл
при добавлении в сессию читается в порядке линии (авто — по маркеру), и дальше
просмотр, поиск периода и операции видят один и тот же поток.
"""

import time
import unittest

import numpy as np

import _bootstrap  # noqa: F401
from reportgen.potok import rastr
from test_potok_sessii import поток_с_маркером

МАРКЕР = "111010110010000111"          # 18 бит, как у образца 8PSK (кадр 2964)


def файл(биты, порядок):
    return np.packbits(биты, bitorder="little" if порядок == "младший" else "big").tobytes()


class РазворотTests(unittest.TestCase):
    def test_таблица_и_разворот(self):
        self.assertEqual(256, len(rastr.НАОБОРОТ_В_БАЙТЕ))
        for b in range(256):
            self.assertEqual(int(f"{b:08b}"[::-1], 2), rastr.НАОБОРОТ_В_БАЙТЕ[b])
        данные = bytes(range(256)) * 3
        ждём = np.packbits(np.unpackbits(np.frombuffer(данные, np.uint8), bitorder="little")).tobytes()
        self.assertEqual(ждём, rastr.развернуть_биты(данные))
        self.assertEqual(данные, rastr.развернуть_биты(rastr.развернуть_биты(данные)))
        self.assertEqual(b"", rastr.развернуть_биты(b""))
        self.assertEqual(b"\x80\x01", rastr.развернуть_биты(bytearray(b"\x01\x80")))


class ОпределениеTests(unittest.TestCase):
    def test_цикл_не_кратный_8(self):
        # При неверном порядке маркер 2964 размазан — ровный столбец только на кратном 5928.
        биты = поток_с_маркером(2964, МАРКЕР, 1 << 22, начало=1000, ошибок=0.002)
        for порядок, другой in (("младший", "старшем"), ("старший", "младшем")):
            with self.subTest(порядок=порядок):
                итог = rastr.порядок_бит(файл(биты, порядок))
                self.assertEqual(порядок, итог["порядок"], итог)
                self.assertTrue(итог["причина"].startswith(
                    f"{порядок} бит байта первым: цикл 2964 бит, маркер 18 бит; при {другой} первым — цикл 5928 бит"),
                    итог["причина"])
                self.assertTrue(итог["причина"].endswith("(только на кратном цикле: перестановка бит в байте "
                                                         "размазывает маркер на основном)"))

    def test_образец_comtech(self):
        # Синхрослово чередуется целиком — маркер только на 5928 (кратен 8) при обоих порядках,
        # но при неверном у него рвутся края: 16 бит против 18.
        from test_potok_comtech import образец  # noqa: PLC0415
        for порядок, как in (("младший", "little"), ("старший", "big")):
            with self.subTest(порядок=порядок):
                итог = rastr.порядок_бит(образец(порядок=как))
                self.assertEqual(порядок, итог["порядок"], итог)
                self.assertIn("цикл 5928 бит, маркер 18 бит", итог["причина"])
                self.assertIn("маркер мельче: у него рвутся края", итог["причина"])

    def test_неразличимо_и_без_маркера(self):
        # Цикл кратен 8, маркер выровнен по байтам: одинаков при обоих порядках — остаётся «старший».
        биты = поток_с_маркером(2048, МАРКЕР[:16], 1 << 22, начало=8)
        итог = rastr.порядок_бит(файл(биты, "младший"))
        self.assertEqual("старший", итог["порядок"])
        self.assertIn("маркер одинаков при обоих порядках", итог["причина"])
        # Случайный поток: маркера нет.
        итог = rastr.порядок_бит(np.random.default_rng(3).integers(0, 256, 1 << 18, dtype=np.uint8).tobytes())
        self.assertEqual(("старший", {"старший": None, "младший": None}), (итог["порядок"], итог["маркеры"]))
        self.assertIn("синхромаркера цикла нет", итог["причина"])
        # Короткий файл — тоже без ошибки.
        self.assertEqual("старший", rastr.порядок_бит(b"\x00\x01")["порядок"])

    def test_правила_на_заданных_маркерах(self):
        # Поиск периода подменён: маркеры при каждом порядке заданы — проверяются сами правила.
        исходный = rastr.поиск_периода
        маркеры = {}

        def поиск(биты, **_):
            return маркеры[int(биты[0])]

        rastr.поиск_периода = поиск
        self.addCleanup(setattr, rastr, "поиск_периода", исходный)
        данные = b"\x80" + bytes(100)           # первый бит: 1 при «старшем», 0 при «младшем»

        def м(период, глубина, вес=1.0):
            return {"период": период, "глубина": глубина, "вес": вес, "первый_бит": 0, "маркер": "", "заметка": ""}

        случаи = [
            ([м(100, 10)], [м(200, 30)], "старший"),              # основной цикл виден только при «старшем»
            ([м(200, 30)], [м(100, 10)], "младший"),
            ([м(100, 10)], [м(150, 30)], "младший"),              # несвязанные циклы: сильнее с запасом
            ([м(100, 10)], [м(150, 14.5)], "старший"),            # 14,5 = 1,25·10 + 2 — ещё не сильнее
            ([м(100, 10)], [м(150, 15)], "младший"),
            ([м(150, 15)], [м(100, 10)], "старший"),
            ([м(100, 16)], [м(100, 18)], "младший"),              # один цикл: глубже на 2 — выигрывает
            ([м(100, 18)], [м(100, 16)], "старший"),
            ([м(100, 17)], [м(100, 18)], "старший"),              # на 1 — одинаков
            ([м(100, 10, 0.79)], [м(100, 10, 0.79)], "старший"),  # слабые маркеры не в счёт
            ([м(100, 10, 0.79)], [м(300, 10, 0.8)], "младший"),
            ([], [м(300, 10)], "младший"),
            ([м(300, 10)], [], "старший"),
            # Из нескольких маркеров берётся самый короткий цикл (при равных — самый глубокий).
            ([м(300, 40), м(100, 9), м(100, 12)], [м(300, 40), м(200, 50)], "старший"),
            ([м(300, 40), м(100, 12)], [м(100, 9), м(100, 14)], "младший"),
        ]
        for старший, младший, ждём in случаи:
            маркеры.update({1: старший, 0: младший})
            with self.subTest(старший=старший, младший=младший):
                self.assertEqual(ждём, rastr.порядок_бит(данные)["порядок"])
        маркеры.update({1: [м(100, 10)], 0: []})
        итог = rastr.порядок_бит(данные)
        self.assertEqual(("старший бит байта первым: цикл 100 бит, маркер 10 бит; при младшем первым — маркера нет",
                          {"старший": {"период": 100, "глубина": 10, "вес": 1.0}, "младший": None}),
                         (итог["причина"], итог["маркеры"]))
        маркеры.update({1: [м(100, 10)], 0: [м(150, 15)]})
        self.assertIn("(маркер слабее)", rastr.порядок_бит(данные)["причина"])


class ЗагрузкаTests(unittest.TestCase):
    def setUp(self):
        from test_web import WebTestCase  # noqa: PLC0415

        class Сеть(WebTestCase):
            def runTest(себя):
                pass

        self.сеть = Сеть()
        self.сеть.setUp()
        self.addCleanup(self.сеть.tearDown)
        self.к = self.сеть.client
        self.сеть.login("engineer")
        self.сид = self.к.post("/api/sessions", json={"name": "порядок"}).json()["id"]

    def добавить(self, имя, данные, **поля):
        return self.к.post(f"/api/sessions/{self.сид}/files", files={"file": (имя, данные, "application/octet-stream")},
                           data=поля)

    def сырые(self, ид):
        for _ in range(600):
            с = self.к.get(f"/api/potok/{ид}").json()
            if с["состояние"] in ("готово", "ошибка"):
                break
            time.sleep(0.05)
        return self.к.get(f"/api/potok/{ид}/raw", params={"stage": 0}).content, с

    def test_авто_развернуть_и_задать(self):
        биты = поток_с_маркером(2964, МАРКЕР, 1 << 21, начало=1000)
        в_линии = np.packbits(биты).tobytes()
        младшим = файл(биты, "младший")
        # Авто (по умолчанию): файл младшим битом вперёд — поток в порядке линии.
        ответ = self.добавить("a.bit", младшим).json()
        self.assertEqual("lsb", ответ["bit_order"])
        self.assertIn("порядок бит в байте определён: младший бит байта первым: цикл 2964 бит", ответ["bit_order_note"])
        данные, состояние = self.сырые(ответ["id"])
        self.assertEqual(в_линии, данные)
        self.assertIn(ответ["bit_order_note"], состояние.get("происхождение") or [])
        # Тот же файл старшим битом вперёд — не трогается.
        ответ = self.добавить("b.bit", в_линии, bit_order="auto").json()
        self.assertEqual("msb", ответ["bit_order"])
        self.assertEqual(в_линии, self.сырые(ответ["id"])[0])
        # Задан явно: lsb разворачивает всегда, msb — никогда.
        ответ = self.добавить("c.bin", в_линии, bit_order="LSB").json()
        self.assertEqual(("lsb", "порядок бит в байте задан: младший бит байта первым"),
                         (ответ["bit_order"], ответ["bit_order_note"]))
        self.assertEqual(младшим, self.сырые(ответ["id"])[0])
        ответ = self.добавить("d.bin", младшим, bit_order="msb").json()
        self.assertEqual("msb", ответ["bit_order"])
        self.assertEqual(младшим, self.сырые(ответ["id"])[0])
        # Часть файла, вырезанная браузером, — тоже по маркеру.
        ответ = self.добавить("e.bit", младшим[1000:200000], sliced="1", start="1000").json()
        self.assertEqual("lsb", ответ["bit_order"])
        self.assertEqual(в_линии[1000:200000], self.сырые(ответ["id"])[0])
        # Неверное значение — 400.
        self.assertEqual(400, self.добавить("f.bin", младшим, bit_order="наоборот").status_code)

    def test_текст_с_битами_не_разворачивается_сам(self):
        текст = ("10110000" * 64).encode()
        ответ = self.добавить("x.bits", текст).json()
        self.assertEqual(("msb", ""), (ответ["bit_order"], ответ["bit_order_note"]))
        self.assertEqual(bytes([0xB0]) * 64, self.сырые(ответ["id"])[0])
        ответ = self.добавить("y.bits", текст, bit_order="lsb").json()
        self.assertEqual(bytes([0x0D]) * 64, self.сырые(ответ["id"])[0])


