class Автомат(unittest.TestCase):
    def test_после_цикла_разбирает_нагрузку(self):
        """В нагрузке кадра модема — HDLC: автомат доходит до кадров с верной FCS."""
        пакеты = с.пакеты_ip(400)
        байты = с.hdlc(пакеты)
        источник = np.unpackbits(np.frombuffer(байты, np.uint8))
        кадров = len(источник) // (ДЛИНА - СЛОВО)
        поток, _, _ = модем(кадров, источник=источник)
        р = razbor.разобрать(данные=np.packbits(поток).tobytes(), имя="модем")
        отчёт = razbor.собрать_отчёт(р, 20000)
        self.assertIn("нагрузка цикла:", отчёт)
        hdlc = [н for н in р.находки if н.уровень != "цикл" and "HDLC" in н.что]
        self.assertTrue(hdlc, отчёт)
        self.assertIn("нагрузка цикла", hdlc[0].путь)


class МусорныеСтроки(unittest.TestCase):
    def test_одно_слово_из_обрывков_не_текст(self):
        for мусор in ("ЩОЖ-@В_R\\мо", "vD2/То-ЮЧС", "Мёйя4.яэ_2"):
            self.assertFalse(poisk._одно_слово_годное(мусор), мусор)
        for текст in ("Передача", "отчёт_2024.doc", "Передача данных", "ЩОЖ мо"):
            self.assertTrue(poisk._одно_слово_годное(текст), текст)

    def test_строки_отсеивают_обрывки(self):
        поток = b"\x00\x01" + "ЩОЖ-@В_R\\мо".encode("cp1251") + b"\x00\x02" \
            + "Передача данных".encode("cp1251") + b"\x00"
        найдено = [н["текст"] for н in poisk.строки(в_биты(поток), наименьшая=8)["строки"]]
        self.assertIn("Передача данных", найдено)
        self.assertFalse(any("ЩОЖ" in т for т in найдено), найдено)


