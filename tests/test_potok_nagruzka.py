"""Кадр модема: повторы циклов, маховик, нагрузка без служебных слов, служебный бит.

Поток собирается здесь же, независимо от анализатора: кадр начинается
служебным словом (постоянные биты, между ними — признак, повторённый дважды,
и переменный бит), дальше — нагрузка. Заполнение без данных повторяется
через четыре кадра, как у модема со сверхциклом.
"""

import unittest
from unittest import mock

import numpy as np

import _bootstrap  # noqa: F401
import potok_sintez as с
from reportgen.potok import cikl, dlinnye, poisk, razbor, stafing
from reportgen.potok.bity import в_биты

ДЛИНА = 1000
ГОЛОВА = np.array([1, 1, 1], np.uint8)
ХВОСТ = np.array([int(x) for x in "001101011100110011"], np.uint8)
СЛОВО = 3 + 3 + len(ХВОСТ)          # 24 бита: 111, признак ×2, переменный бит, 18 постоянных


def модем(кадров, *, источник=None, заполнение=0.0, ошибок=0.0, срыв=None, сид=7):
    """(поток, нагрузки по кадрам, признаки) — кадры по ДЛИНА бит.

    ``заполнение`` — доля кадров без данных: они идут сериями и повторяют один
    из четырёх образцов по номеру кадра (сверхцикл 4). ``срыв`` — номер кадра,
    в нагрузке которого пропадают три бита (проскальзывание).
    """
    rng = np.random.default_rng(сид)
    нагрузка = ДЛИНА - СЛОВО
    образцы = rng.integers(0, 2, (4, нагрузка)).astype(np.uint8)
    if источник is None:
        источник = rng.integers(0, 2, кадров * нагрузка).astype(np.uint8)
    пустые = np.zeros(кадров, bool)
    i = 0
    while i < кадров:
        серия = int(rng.integers(3, 12))
        пустые[i:i + серия] = rng.random() < заполнение
        i += серия
    кадры, нагрузки, признаки, место = [], [], [], 0
    for к in range(кадров):
        признак = int(rng.integers(0, 2))
        слово = np.concatenate([ГОЛОВА, [признак, признак, rng.integers(0, 2)], ХВОСТ]).astype(np.uint8)
        if пустые[к]:
            тело = образцы[к % 4]
        else:
            тело = источник[место:место + нагрузка]
            место += нагрузка
        нагрузки.append(тело)
        признаки.append(признак)
        кадр = np.concatenate([слово, тело])
        if срыв is not None and к == срыв:
            кадр = np.delete(кадр, [500, 501, 502])
        кадры.append(кадр)
    поток = np.concatenate(кадры)
    if ошибок:
        поток = поток ^ (rng.random(len(поток)) < ошибок).astype(np.uint8)
    # Начинаем с середины кадра — как с середины записи.
    return поток[337:], нагрузки, признаки


class Повторы(unittest.TestCase):
    def test_сверхцикл_и_ошибки_линии_по_повторам(self):
        поток, _, _ = модем(1500, заполнение=0.5, ошибок=1e-3)
        найдено = cikl.найти(поток)
        self.assertEqual(найдено.свойства["длина"], ДЛИНА)
        п = найдено.свойства["повторы"]
        self.assertEqual(п["шаг"], 4)
        self.assertGreater(п["доля"], 0.25)
        self.assertLess(п["доля"], 0.75)
        self.assertGreater(п["ошибок"], 0.6e-3)
        self.assertLess(п["ошибок"], 1.6e-3)
        self.assertTrue(any("повторы циклов" in с_ and "через 4" in с_ for с_ in найдено.подробно))

    def test_без_заполнения_повторов_нет(self):
        поток, _, _ = модем(600, заполнение=0.0)
        self.assertIsNone(cikl.найти(поток).свойства["повторы"])

    def test_повтор_дальше_допуска_не_повтор(self):
        rng = np.random.default_rng(1)
        образец = rng.integers(0, 2, 400).astype(np.uint8)
        таблица = np.stack([образец] * 40)
        порча = rng.random(таблица.shape) < 0.08           # 8 % расхождений — больше 5 %
        self.assertIsNone(cikl.повторы(таблица ^ порча.astype(np.uint8)))
        порча = rng.random(таблица.shape) < 0.01
        п = cikl.повторы(таблица ^ порча.astype(np.uint8))
        self.assertEqual(п["шаг"], 1)
        self.assertAlmostEqual(п["ошибок"], 0.01, delta=0.004)


class Нагрузка(unittest.TestCase):
    def test_нагрузка_без_служебного_слова_и_маховик(self):
        поток, нагрузки, _ = модем(400, срыв=150)
        ряд, сводка = cikl.нагрузка(поток, ДЛИНА)
        self.assertEqual(сводка["бит"], ДЛИНА - СЛОВО)
        self.assertEqual(сводка["вырезано"], [(0, СЛОВО)])
        self.assertEqual(сводка["проскальзываний"], 1)
        строки = ряд.reshape(-1, ДЛИНА - СЛОВО)
        # Первый целый кадр — второй в записи (запись начата с середины кадра 0).
        верных = sum(np.array_equal(строка, нагрузки[1 + i]) for i, строка in enumerate(строки))
        self.assertGreaterEqual(верных, len(строки) - 1)       # портится лишь кадр со срывом
        self.assertGreaterEqual(len(строки), 395)

    def test_заполнение_не_портит_шаблон(self):
        """Куски из одних кадров заполнения не берутся: там «постоянны» и столбцы нагрузки."""
        for сид in (7, 11, 12):
            поток, _, _ = модем(900, заполнение=0.5, сид=сид)
            _, сводка = cikl.нагрузка(поток, ДЛИНА)
            self.assertEqual(сводка["вырезано"], [(0, СЛОВО)], сид)

    def test_короткое_синхрослово_не_даёт_ложных_срывов(self):
        """Шаблон — все постоянные столбцы, а не одно слово: случайных совпадений рядом нет."""
        поток, _, _ = модем(600, ошибок=2e-3)
        _, сводка = cikl.нагрузка(поток, ДЛИНА)
        self.assertEqual(сводка["проскальзываний"], 0)
        self.assertEqual(сводка["нет_на_месте"], 0)

    def test_маховик_держит_место_при_потере_слова(self):
        rng = np.random.default_rng(3)
        поток = rng.integers(0, 2, 50 * 200).astype(np.uint8)
        места = np.arange(0, 24)
        образец = rng.integers(0, 2, 24).astype(np.uint8)
        for к in range(50):
            if к != 20:                                   # в кадре 20 слово стёрто
                поток[к * 200 + места] = образец
        начала, сводка = cikl.маховик(поток, 200, места, образец)
        self.assertEqual(начала, [к * 200 for к in range(50)])
        self.assertEqual(сводка["нет_на_месте"], 1)
        self.assertEqual(сводка["проскальзываний"], 0)

    def test_маховик_берёт_самое_точное_и_ближнее_совпадение(self):
        rng = np.random.default_rng(8)
        поток = rng.integers(0, 2, 10 * 200 + 40).astype(np.uint8)
        места = np.arange(0, 24)
        образец = rng.integers(0, 2, 24).astype(np.uint8)
        for к in range(10):
            поток[к * 200 + места] = образец
        # Кадр 5: на месте слова нет; с двумя ошибками — на 14 бит раньше, точное — на 10 позже.
        поток[1000 + места] ^= 1
        испорченное = образец.copy()
        испорченное[:2] ^= 1
        поток[986 + места] = испорченное
        поток[1010 + места] = образец
        начала, сводка = cikl.маховик(поток, 200, места, образец)
        self.assertEqual(начала[5], 1010)
        self.assertEqual(начала[6], 1200)                     # и обратно на место
        self.assertEqual(сводка["проскальзываний"], 2)

    def test_служебное_слово_с_переменными_битами_одно(self):
        участки = [(6, 18, "0" * 18), (0, 3, "111"), (500, 4, "1010")]
        self.assertEqual(cikl._служебные_слова(участки, 1000), [(0, 24), (500, 4)])
        участки = [(12, 18, "0" * 18), (0, 3, "111")]         # зазор 9 — два слова
        self.assertEqual(cikl._служебные_слова(участки, 1000), [(0, 3), (12, 18)])
        участки = [(11, 18, "0" * 18), (0, 3, "111")]         # зазор 8 — ещё одно
        self.assertEqual(cikl._служебные_слова(участки, 1000), [(0, 29)])


def поток_с_кратным_словом(кадров=500, сид=9):
    """Кадр 500 бит: синхрослово 10 бит в начале и трёхбитная метка через каждые 100 бит."""
    rng = np.random.default_rng(сид)
    поток = rng.integers(0, 2, кадров * 500).astype(np.uint8).reshape(кадров, 500)
    поток[:, :10] = [1, 0, 1, 1, 0, 0, 1, 1, 1, 0]
    for к in range(5):
        поток[:, 50 + 100 * к:53 + 100 * к] = [1, 1, 0]
    return поток.reshape(-1)


def корреляция_с_пиками(биты, наибольший):
    """Подменная автокорреляция: узкие пики на 100 (слово там — 3 бита) и 500,
    широкий (сосед почти так же высок) — на 1000."""
    r = np.zeros(наибольший + 1)
    r[0], r[100], r[500] = 1.0, 0.2, 0.1
    r[1000], r[999] = 0.3, 0.29
    return r


class УзкийПик(unittest.TestCase):
    def test_узкий_пик_с_настоящим_синхрословом(self):
        поток = поток_с_кратным_словом()
        with mock.patch.object(cikl, "автокорреляция", корреляция_с_пиками):
            длина, *_ = cikl._узкий_цикл(поток)
        self.assertEqual(длина, 500)

    def test_слабый_узкий_пик_не_цикл(self):
        """Пик ниже порога (8 сигм шума) не берётся, даже если синхрослово там есть."""
        поток = поток_с_кратным_словом()

        def слабая(биты, наибольший):
            r = np.zeros(наибольший + 1)
            r[0], r[500] = 1.0, 6 / np.sqrt(len(поток))
            return r
        with mock.patch.object(cikl, "автокорреляция", слабая):
            self.assertIsNone(cikl._узкий_цикл(поток))

    def test_найти_переходит_на_узкий_пик_при_коротком_слове(self):
        поток = поток_с_кратным_словом()
        with mock.patch.object(cikl, "автокорреляция", корреляция_с_пиками), \
                mock.patch.object(cikl, "длина_цикла", return_value=(100, 0.2, 0.002)):
            найдено = cikl.найти(поток)
        self.assertEqual(найдено.свойства["длина"], 500)
        self.assertIn("синхрослово 10 бит", найдено.что)


class СлужебныйБит(unittest.TestCase):
    def test_признак_дважды_не_стаффинг(self):
        поток, _, признаки = модем(1500, заполнение=0.5)
        найдено = cikl.найти(поток)
        текст = "\n".join(найдено.подробно)
        self.assertIn("служебный бит, повторённый в столбцах", текст)
        self.assertNotIn("стаффинг: канал управления", текст)

    def test_место_возможности_должно_быть_пустым(self):
        rng = np.random.default_rng(2)
        n = 4000
        решение = rng.integers(0, 2, n).astype(np.uint8)
        таблица = rng.integers(0, 2, (n, 10)).astype(np.uint8)
        таблица[:, 0] = таблица[:, 1] = решение
        # Столбец 5: при «1» лишь смещён (10 % единиц) — не пустой бит.
        таблица[решение == 1, 5] = (rng.random(int(решение.sum())) < 0.1)
        # Столбец 7: при «1» постоянен — настоящая возможность.
        таблица[решение == 1, 7] = 1
        столбцы = [в["столбец"] for в in stafing.возможность(таблица, [0, 1], лучших=8)]
        self.assertIn(7, столбцы)
        self.assertNotIn(5, столбцы)


