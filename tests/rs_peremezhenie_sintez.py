"""Синтетика для РС со свёрточным перемежением символов — независимый эталон для тестов rs_peremezhenie.

Всё написано здесь по документам, без функций анализатора:

- кодер РС на списках Python (поле и порождающий многочлен строятся заново, систематический, первый
  символ — старшая степень); у J.83B — расширенный символ c(α^6) (ITU-T J.83 прил. B, п. B.5.1);
- перемежители — пошаговой моделью из документа, а не формулой положения:
  * Рэмси II (МСЭ-R BO.1516-1, п. 5.4.2, рис. 24b, система B — DSS): сдвиговый регистр с отводами
    через (D − 1) = 12 ячеек, коммутатор по I = 146 положениям; на каждый байт — «добавить в отвод
    коммутатора, выдать ячейку 0, сдвинуть, сдвинуть коммутатор» (задержка байта k — 12·k);
  * Форни (EN 300 421 / BO.1516 п. 5.4.1 — I = 12, M = 17; ATSC A/53 ч. 2 п. 5.2.3 — B = 52, M = 4;
    J.83 прил. B п. B.5.2 — I, J): I ветвей-очередей, в ветви j — j·M ячеек, входной и выходной
    коммутаторы шагают вместе на каждый символ;
- синхробайт DSS 0x1D перед каждой группой из 146 байт после перемежения (BO.1516 п. 5.3.2);
- свёрточный 171/133 K = 7 и выкалывание BO.1516 табл. 7b (1/2: X=1 Y=1; 2/3: X=10 Y=11;
  6/7: X=100101 Y=111010), порядок выхода в такте — X, затем Y;
- внешний РС IESS (ETR 192 — выдержка IESS-308, п. 6.1: поле 0x187, корни α^120…) с Рэмси II глубины 8/4
  и разностным кодером после перемежителя;
- ошибки: случайные по битам (до Витерби) и пачками (после Витерби), сдвиг начала, инверсия.
"""

from __future__ import annotations

from collections import deque

import numpy as np

# -- поле и кодер РС ---------------------------------------------------------------------------------


class Поле:
    """GF(2^m) по многочлену p — таблицами степеней и логарифмов (списки)."""

    def __init__(self, p: int):
        self.p = p
        self.m = p.bit_length() - 1
        self.q1 = (1 << self.m) - 1
        self.exp, self.log = [0] * (2 * self.q1), [0] * (self.q1 + 1)
        x = 1
        for i in range(self.q1):
            self.exp[i] = self.exp[i + self.q1] = x
            self.log[x] = i
            x <<= 1
            if x >> self.m:
                x ^= p

    def умн(self, a: int, b: int) -> int:
        return 0 if not a or not b else self.exp[self.log[a] + self.log[b]]

    def степень(self, j: int) -> int:
        return self.exp[j % self.q1]

    def значение(self, слово, j: int) -> int:
        """c(α^j) по схеме Горнера (первый символ — старшая степень)."""
        x = self.степень(j)
        s = 0
        for c in слово:
            s = self.умн(s, x) ^ int(c)
        return s


def кодировать(данные, F: Поле, fcr: int, корней: int) -> list[int]:
    """Систематическое слово: данные, затем остаток D(x)·x^корней по g(x) = Π (x − α^(fcr+i))."""
    g = [1]
    for i in range(корней):
        к = F.степень(fcr + i)
        g = [a ^ F.умн(b, к) for a, b in zip(g + [0], [0] + g, strict=True)]
    r = [int(x) for x in данные] + [0] * корней
    for i in range(len(данные)):
        c = r[i]
        if c:
            for j in range(1, корней + 1):
                r[i + j] ^= F.умн(c, g[j])
    return [int(x) for x in данные] + r[len(данные):]


def кодировать_j83b(данные, F: Поле) -> list[int]:
    """J.83B: RS(127,122) с корнями α^1…α^5 и расширенный символ c(α^6) последним (128 символов)."""
    c = кодировать(данные, F, 1, 5)
    return c + [F.значение(c, 6)]


# -- перемежители по документам (пошагово) -----------------------------------------------------------


def рэмси_ii(символы, I: int = 146, D: int = 13) -> list[int]:
    """Рэмси II по рис. 24b BO.1516: регистр с отводом k на ячейке (D − 1)·k, k = 0…I − 1.

    На каждый символ: добавить его в ячейку отвода, на который смотрит коммутатор (в остальные
    отводы добавляется 0); выдать ячейку 0; сдвинуть регистр на ячейку к выходу (сверху входят
    нули); коммутатор — на следующее положение. Коммутатор в 0 на первом символе (начало пакета).
    """
    S = (D - 1) * (I - 1)                      # ячейки 0 … S
    R = S + 1
    кольцо = [0] * R
    основа = 0                                 # ячейка s — кольцо[(основа + s) % R]
    k = 0
    выход = []
    for x in символы:
        кольцо[(основа + (D - 1) * k) % R] ^= int(x)
        выход.append(кольцо[основа % R])
        кольцо[основа % R] = 0                 # уходит в выход; верхняя ячейка после сдвига — нуль
        основа += 1
        k = (k + 1) % I
    return выход


def форни(символы, I: int, M: int) -> list[int]:
    """Форни: ветвь j — очередь из j·M ячеек (ветвь 0 без задержки), коммутаторы шагают вместе."""
    ветви = [deque([0] * (j * M)) for j in range(I)]
    выход = []
    for n, x in enumerate(символы):
        j = n % I
        if j == 0:
            выход.append(int(x))
        else:
            ветви[j].append(int(x))
            выход.append(ветви[j].popleft())
    return выход


# -- свёрточный код с выкалыванием (BO.1516 табл. 7b) ------------------------------------------------

#: Шаблоны выкалывания системы B (X — 171, Y — 133).
ВЫКАЛЫВАНИЕ = {"1/2": ("1", "1"), "2/3": ("10", "11"), "6/7": ("100101", "111010")}


def свёрточный(биты, скорость: str = "1/2") -> np.ndarray:
    """171/133 K = 7 (старший бит многочлена — текущий вход), выкалывание по шаблону; в такте — X, затем Y."""
    X, Y = ВЫКАЛЫВАНИЕ[скорость]
    g1, g2 = 0o171, 0o133
    регистр = 0
    выход = []
    for n, b in enumerate(биты):
        регистр = ((регистр >> 1) | (int(b) << 6)) & 0x7F          # бит 6 — текущий вход
        x = bin(регистр & g1).count("1") & 1
        y = bin(регистр & g2).count("1") & 1
        i = n % len(X)
        if X[i] == "1":
            выход.append(x)
        if Y[i] == "1":
            выход.append(y)
    return np.array(выход, dtype=np.uint8)


# -- символы, ошибки ---------------------------------------------------------------------------------


def в_биты(символы, m: int = 8, младший: bool = False) -> np.ndarray:
    с = np.asarray(символы, dtype=np.int64)
    сдвиги = np.arange(m) if младший else np.arange(m - 1, -1, -1)
    return ((с[:, None] >> сдвиги) & 1).astype(np.uint8).reshape(-1)


def ошибки_случайные(биты: np.ndarray, ber: float, г) -> np.ndarray:
    return биты ^ (г.random(len(биты)) < ber).astype(np.uint8) if ber else биты


def ошибки_пачками(биты: np.ndarray, ber: float, г, длина: int = 12) -> np.ndarray:
    """Пачки, как на выходе Витерби: начало пачки — с частотой ber/(длина/2), внутри пачки
    каждый бит ошибочен с вероятностью 1/2 (в среднем ber ошибок на бит)."""
    if not ber:
        return биты
    итог = биты.copy()
    начала = np.flatnonzero(г.random(len(биты)) < ber / (длина / 2))
    for н in начала.tolist():
        кусок = итог[н:н + длина]
        итог[н:н + длина] = кусок ^ (г.random(len(кусок)) < 0.5).astype(np.uint8)
    return итог


# -- потоки целиком ----------------------------------------------------------------------------------


def _прогретый(поток: list[int], задержка: int, группа: int) -> list[int]:
    """Запись начинается, когда перемежитель давно работает: выход до заполнения ячеек (нули в начале)
    отбрасывается — задержка, округлённая вверх до группы символов."""
    return поток[-(-задержка // группа) * группа:]


def dss(слов: int = 600, *, синхро: bool = True, скорость: str | None = None, ber: float = 0.0,
        сдвиг: int = 0, инверсия: bool = False, младший: bool = False, сид: int = 1
        ) -> tuple[np.ndarray, np.ndarray]:
    """DSS: RS(146,130) (0x11D, корни α^0…α^15) → Рэмси II (13, 146) → [0x1D перед группой 146 байт]
    → [свёрточный 171/133 со скоростью] → ошибки → сдвиг начала → инверсия.

    Запись — с работающего перемежителя (первые 12·145 байт выхода отброшены). Возвращает (биты линии,
    данные — байты всех слов подряд, 130 на слово; первые слова в записи целиком не попали).
    """
    г = np.random.default_rng(сид)
    F = Поле(0x11D)
    данные = г.integers(0, 256, (слов, 130))
    слова = [кодировать(д.tolist(), F, 0, 16) for д in данные]
    поток = _прогретый(рэмси_ii([x for с in слова for x in с], 146, 13), 12 * 145, 146)
    if синхро:
        группы = np.array(поток, dtype=np.int64).reshape(-1, 146)
        поток = np.concatenate([np.full((len(группы), 1), 0x1D), группы], axis=1).reshape(-1).tolist()
    биты = в_биты(поток, 8, младший)
    return _линия(биты, г, скорость, ber, сдвиг, инверсия), данные.astype(np.uint8).reshape(-1)


def atsc(слов: int = 400, *, ber: float = 0.0, сдвиг: int = 0, инверсия: bool = False, сид: int = 2
         ) -> tuple[np.ndarray, np.ndarray]:
    """ATSC: RS(207,187) (0x11D, корни α^0…α^19) → Форни B = 52, M = 4 (с первого байта поля)."""
    г = np.random.default_rng(сид)
    F = Поле(0x11D)
    данные = г.integers(0, 256, (слов, 187))
    слова = [кодировать(д.tolist(), F, 0, 20) for д in данные]
    поток = _прогретый(форни([x for с in слова for x in с], 52, 4), 208 * 51, 1)
    биты = в_биты(поток, 8)
    return _линия(биты, г, None, ber, сдвиг, инверсия), данные.astype(np.uint8).reshape(-1)


def j83b(слов: int = 600, *, I: int = 128, J: int = 1, ber: float = 0.0, сдвиг: int = 0,
         инверсия: bool = False, хвост: bool = False, сид: int = 3) -> tuple[np.ndarray, np.ndarray]:
    """J.83B: RS(128,122) над GF(128) (x^7 + x^3 + 1) → Форни (I, J) по 7-битным символам →
    [хвост кадра FEC 64-КАМ: 42 бита (синхро 1110101 0101100 0001101 1101100, режим, нули) после 60 слов].
    Рандомизатор и ТКМ не моделируются (их снимают до РС)."""
    г = np.random.default_rng(сид)
    F = Поле(0x89)
    данные = г.integers(0, 128, (слов, 122))
    слова = [кодировать_j83b(д.tolist(), F) for д in данные]
    поток = _прогретый(форни([x for с in слова for x in с], I, J), I * J * (I - 1), 60 * 128)
    биты = в_биты(поток, 7)
    if хвост:
        кадр = 60 * 128 * 7
        синхро = [int(ч) for ч in "1110101" "0101100" "0001101" "1101100"]
        вставка = np.array(синхро + [0, 0, 0, 1] + [0] * 10, dtype=np.uint8)
        куски = [биты[i:i + кадр] for i in range(0, len(биты), кадр)]
        биты = np.concatenate([np.concatenate([к, вставка]) if len(к) == кадр else к for к in куски])
    return _линия(биты, г, None, ber, сдвиг, инверсия), данные.astype(np.uint8).reshape(-1)


def разностно(биты: np.ndarray) -> np.ndarray:
    """Разностный (дифференциальный) кодер: y[n] = x[n] ^ y[n − 1], y[−1] = 0."""
    return (np.cumsum(np.asarray(биты, dtype=np.int64)) % 2).astype(np.uint8)


def iess(слов: int = 300, *, N: int = 225, K: int = 205, глубина: int = 8, разностное: bool = True,
         данные: np.ndarray | None = None, ber: float = 0.0, сдвиг: int = 0, инверсия: bool = False, сид: int = 6
         ) -> tuple[np.ndarray, np.ndarray]:
    """Внешний РС модема IESS: RS(N, K) над GF(256) x^8 + x^7 + x^2 + x + 1, корни α^120…α^(119 + N − K) (ETR 192
    п. 6.1) → Рэмси II (N1 = глубина, N2 = N) → [разностный кодер] → ошибки пачками → сдвиг → инверсия.

    ``данные`` — байты (слов × K), иначе случайные. Возвращает (биты, данные всех слов подряд)."""
    г = np.random.default_rng(сид)
    F = Поле(0x187)
    if данные is None:
        данные = г.integers(0, 256, (слов, K))
    данные = np.asarray(данные, dtype=np.int64).reshape(-1, K)
    слова = [кодировать(д.tolist(), F, 120, N - K) for д in данные]
    поток = _прогретый(рэмси_ii([x for с in слова for x in с], N, глубина), (глубина - 1) * (N - 1), N)
    биты = в_биты(поток, 8)
    if разностное:
        биты = разностно(биты)
    return _линия(биты, г, None, ber, сдвиг, инверсия), данные.astype(np.uint8).reshape(-1)


def _линия(биты: np.ndarray, г, скорость: str | None, ber: float, сдвиг: int, инверсия: bool) -> np.ndarray:
    if скорость:
        биты = ошибки_случайные(свёрточный(биты, скорость), ber, г)
    else:
        биты = ошибки_пачками(биты, ber, г)
    if сдвиг:
        биты = np.concatenate([г.integers(0, 2, сдвиг).astype(np.uint8), биты])
    if инверсия:
        биты = биты ^ 1
    return биты.astype(np.uint8)


def случайный_rs(N: int, K: int, слов: int, сид: int = 4) -> np.ndarray:
    """Обычный RS(N, K) над GF(256) 0x11D без перемежения, слова подряд — биты."""
    г = np.random.default_rng(сид)
    F = Поле(0x11D)
    поток = [x for _ in range(слов) for x in кодировать(г.integers(0, 256, K).tolist(), F, 0, N - K)]
    return в_биты(поток, 8)
