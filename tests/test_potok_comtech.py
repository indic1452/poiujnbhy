"""Сквозной разбор потока как образец Comtech 8PSK: всё вслепую, от меток до IP.

Как в образце аналитика (250_V_8085_8PSK_7556_K2964): кадры Ethernet с IP в
HDLC с длинными паузами из флагов; данные каждого блока TPC сложены с ПСП
1 + x⁻² + x⁻³ + x⁻⁹ + x⁻¹² со сбросом в начале блока; TPC (64, 57) × (46, 39)
в кадрах 2964 бит с чередующимся синхрословом; метки 8PSK в чужой нумерации;
в файле — младшим битом байта вперёд. Автомат знает только «8PSK» из имени.
"""

import unittest

import numpy as np

import _bootstrap  # noqa: F401
import potok_sintez as с
from reportgen.potok import ploskost, razbor
from test_potok_blok import НАЧАЛЬНОЕ, ОТВОДЫ, лрп
from test_potok_tpc3 import ЧУЖИЕ, comtech


def образец(пакетов=90, флагов=300, сид=1, порядок="little"):
    кадры = [с.ethernet(п) for п in с.пакеты_ip(пакетов, сид=сид)]
    биты = np.unpackbits(np.frombuffer(с.hdlc(кадры, флагов_между=флагов), np.uint8))
    F = len(биты) // 2223
    данные = биты[:F * 2223].reshape(F, 2223) ^ лрп(ОТВОДЫ, НАЧАЛЬНОЕ, 2223)
    поток, _ = comtech(данные.reshape(F, 39, 57), приставка=1001)
    поток = поток[:len(поток) // 3 * 3]
    метки = ploskost.преобразовать_фм(поток, 3, **ЧУЖИЕ)
    метки ^= (np.random.default_rng(сид).random(len(метки)) < 1e-3).astype(np.uint8)
    return np.packbits(метки, bitorder=порядок).tobytes()


class КакОбразец(unittest.TestCase):
    def test_от_меток_до_ip(self):
        р = razbor.разобрать(данные=образец(), имя="250_V_8PSK_K2964.bit", профиль="обычно")
        уровни = [н.уровень for н in р.находки]
        отчёт = razbor.собрать_отчёт(р, 20000)
        self.assertEqual(уровни[:6], ["цикл", "плоскость", "код", "скремблер", "канальный", "сетевой"],
                         отчёт)
        цикл, плоскость, код, псп, кадры, пакеты = р.находки[:6]
        self.assertIn("кадр 2964 бит, синхрослово чередуется", цикл.что)
        self.assertIn("младший бит байта первым", плоскость.путь)
        self.assertTrue(any("порядок бит в байте файла — младший бит байта первым" in п
                            for п in плоскость.подробно))
        self.assertIn("поворот 3", плоскость.что)
        self.assertIn("натуральный → Грей", плоскость.что)
        self.assertIn("(64, 57) × (46, 39)", код.что)
        self.assertEqual(код.свойства["данных_в_блоке"], 2223)
        self.assertIn("аддитивная ПСП 1 + x^-2 + x^-3 + x^-9 + x^-12 со сбросом в начале каждого "
                      "блока 2223 бит", псп.что)
        self.assertEqual(псп.свойства["начальное"], НАЧАЛЬНОЕ)
        self.assertIn("FCS-16", кадры.что)
        # При ошибках 10⁻³ TPC оставляет единицы блоков с нарушениями — кадр HDLC на
        # таком блоке FCS не проходит (у образца так же: 403 из 404).
        self.assertGreaterEqual(кадры.уверенность, 0.95)
        self.assertGreaterEqual(пакеты.уверенность, 0.99)
        self.assertTrue(any("Ethernet" in п for п in пакеты.подробно), пакеты.подробно)


if __name__ == "__main__":
    unittest.main()
