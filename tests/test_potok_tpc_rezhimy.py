class Многочлены(unittest.TestCase):
    #: [istochniki/tpc/ieee802/802161pc-00_35.pdf, стр. 5 PDF, Table 1]
    PC0035 = {(7, 4): "x3 + x + 1", (15, 11): "x4 + x + 1", (31, 26): "x5 + x2 + 1", (63, 57): "x6 + x + 1",
              (127, 120): "x7 +x3 + 1"}
    #: [istochniki/tpc/ieee802/C80216a-02_55.pdf, стр. 16, Table 203]
    T203 = {(7, 4): "X3+X1+1", (15, 11): "X4+X1+1", (31, 26): "X5+X2+1", (63, 57): "X6+X+1"}

    def test_таблица_хэмминга_как_в_двух_источниках(self):
        self.assertEqual(set(т.МНОГОЧЛЕНЫ_ХЭММИНГА), set(self.PC0035))
        for nk, g in т.МНОГОЧЛЕНЫ_ХЭММИНГА.items():
            self.assertEqual(т.многочлен(g), т.многочлен(self.PC0035[nk].replace(" ", "")))
            if nk in self.T203:
                self.assertEqual(т.многочлен(g), т.многочлен(self.T203[nk].replace("X1", "x").lower()))
        self.assertEqual(т.многочлен("x7+x3+1"), 0b10001001)
        self.assertEqual(т.многочлен("x"), 2)
        with self.assertRaisesRegex(ValueError, "член многочлена «y2»"):
            т.многочлен("y2+1")

    def test_многочлены_примитивны(self):
        for (n, _), g in т.МНОГОЧЛЕНЫ_ХЭММИНГА.items():
            g = т.многочлен(g)
            порядок, x = 1, 2
            while x != 1:
                x <<= 1
                if x >> (g.bit_length() - 1) & 1:
                    x ^= g
                порядок += 1
            self.assertEqual(порядок, n)

    def test_бчх_m584(self):
        # [istochniki/tpc/itu/ITU-R_M.584-2.pdf, стр. 4, п. 1.4]
        self.assertEqual(т.многочлен(т.МНОГОЧЛЕН_БЧХ_31_21), т.многочлен(к.БЧХ_31_21.replace(" ", "")))
        # Произведение минимальных многочленов α и α³ поля GF(2^5) по x^5+x^2+1 (порождающий БЧХ (31,21)).
        def умн(a, b):
            r = 0
            while b:
                if b & 1:
                    r ^= a
                a, b = a << 1, b >> 1
            return r
        self.assertEqual(т.многочлен(т.МНОГОЧЛЕН_БЧХ_31_21), умн(0b100101, 0b111101))


class СоставляющиеКоды(unittest.TestCase):
    def test_проверки_анализатора_принимают_слова_эталона(self):
        """Слово независимого кодера (регистр деления) — кодовое для H анализатора."""
        rng = np.random.default_rng(1)
        for код, эталон in ((т.Х8, к.Составляющий("Х", 8)), (т.Х16, к.Составляющий("Х", 16)),
                            (т.Х32, к.Составляющий("Х", 32)), (т.Х64, к.Составляющий("Х", 64)),
                            (т.Х128, к.Составляющий("Х", 128)), (т.Ч16, к.Составляющий("Ч", 16)),
                            (т.Б32, к.Составляющий("БЧХ", 32)), (т.хэмминг(63), к.Составляющий("Хб", 63))):
            H = т.проверочная(код)
            self.assertEqual(H.shape, (код.n - код.k, код.n))
            for _ in range(20):
                д = rng.integers(0, 2, код.k).astype(np.uint8)
                слово = np.array(эталон(list(д)), np.uint8)
                self.assertFalse(((H.astype(int) @ слово) & 1).any(), код)
                # И порождающая анализатора даёт то же слово (данные первыми, проверки — как у регистра).
                self.assertEqual(((д.astype(int) @ т.порождающая(код).astype(int)) & 1).tolist(), слово.tolist())

    def test_расстояния(self):
        self.assertEqual(т.мин_расстояние(т.Х8), 4)
        self.assertEqual(т.мин_расстояние(т.Х16), 4)
        self.assertEqual(т.мин_расстояние(т.Ч16), 2)
        self.assertEqual(т.мин_расстояние(т.хэмминг(15)), 3)
        self.assertIsNone(т.мин_расстояние(т.Х32))

    def test_таблица_исправлений(self):
        # Расширенный Хэмминг: одиночные — однозначно, двойные — нет (d = 4).
        H = т.проверочная(т.Х16)
        таблица = т.таблица_исправлений(H, 1)
        self.assertEqual(int((таблица[:, 0] >= 0).sum()), 16)
        вес = 1 << np.arange(H.shape[0])
        for j in range(16):
            self.assertEqual(таблица[int((H[:, j] * вес).sum()), 0], j)
        self.assertEqual(таблица[0, 0], -1)
        # (32,21) БЧХ + чётность: исправляет две — все 32 + 496 синдромов различны (d = 6).
        таблица = т.таблица_исправлений(т.проверочная(т.Б32), 2)
        self.assertEqual(int((таблица[:, 0] >= 0).sum()), 32 + 32 * 31 // 2)
        # Столбцы-двойники: такой синдром не исправляется.
        H = np.array([[1, 1, 0], [0, 0, 1]], np.uint8)
        self.assertEqual(т.таблица_исправлений(H, 1)[1, 0], -1)
        self.assertIsNone(т.таблица_исправлений(np.ones((1, 4), np.uint8), 0))
        self.assertIsNone(т.таблица_исправлений(np.ones((17, 20), np.uint8), 1))

    def test_ошибки_кодов(self):
        with self.assertRaisesRegex(ValueError, "длины 12"):
            т.хэмминг_расширенный(12)
        with self.assertRaisesRegex(ValueError, "длины 64"):
            т.хэмминг(64)
        with self.assertRaisesRegex(ValueError, "степень многочлена"):
            т.порождающая(т.Код(16, 10, "Хэмминг+", т.многочлен("x4+x+1")))
        with self.assertRaisesRegex(ValueError, "укорочение 11"):
            т._укороченная(т.Х16, 11)


