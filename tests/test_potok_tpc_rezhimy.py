def коды_режима(р):
    вид = {"Хэмминг+": "Х", "чётность": "Ч", "БЧХ+": "БЧХ", "Хэмминг": "Хб"}
    return [к.Составляющий(вид[c.вид], c.n) for c in р.оси]


def кодер_режима(р, B=None, **доп):
    укор = tuple(р.укор) + (0,) * (3 - len(р.укор))
    параметры = dict(укор=укор, строк=р.строк_укор, B=р.бит_укор if B is None else B, Q=р.нулей,
                     гипер=р.гипер, выколоть=р.выколото, спираль=р.спираль)
    параметры.update(доп)
    return к.кодер(коды_режима(р), **параметры)


def поток_режима(р, блоков=24, ошибок=5e-4, приставка=137, синхро=None, B=None, сид=1, **доп):
    """Поток режима с синхрословом кадра: (поток, данные, T, фаза первого блока)."""
    кодировать, k = кодер_режима(р, B, **доп)
    Nt = len(кодировать(np.zeros(k, np.uint8)))
    T = р.кадр or Nt
    S = T - Nt if синхро is None else синхро
    слово = np.random.default_rng(9).integers(0, 2, S).astype(np.uint8) if S else None
    ряд, данные = к.поток(кодировать, k, блоков, синхро=слово, ошибок=ошибок, приставка=приставка, сид=сид)
    return ряд, данные, S + Nt, (приставка + S) % (S + Nt)


def данные_совпали(выход, данные, k, T, фаза, приставка=137, S=0):
    """Доля совпавших бит данных (блоки до первого целого отбрасываются)."""
    лишних = (приставка + S - фаза) // T                     # блоков до первого настоящего
    выход = выход[лишних * k:]
    m = min(len(выход) // k, len(данные))
    return float((выход[:m * k].reshape(m, k) == данные[:m]).mean()) if m else 0.0, m


