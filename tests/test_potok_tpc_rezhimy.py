class Геометрия(unittest.TestCase):
    def test_порядок_передачи_и_данные_802_16(self):
        """Кодер-эталон и раскладка анализатора дают одни и те же места данных и проверок."""
        р = т.режим("802.16-OFDM-768-4/5")                  # B = 44, Q = 3, Ix = 6, Iy = 2
        кодировать, k = кодер_режима(р)
        г = т.геометрия(р)
        self.assertEqual((k, г.передаётся, г.форма), (len(г.данные), 768, (1, 14, 58)))
        rng = np.random.default_rng(3)
        for _ in range(3):
            д = rng.integers(0, 2, k).astype(np.uint8)
            блок = np.zeros(г.размер, np.uint8)
            блок[г.порядок] = кодировать(д)
            self.assertEqual(блок[г.данные].tolist(), д.tolist())
            self.assertFalse(блок[г.закреплено].any())
            for ось in г.оси:
                self.assertFalse(т.синдромы(блок[None], ось).any(), ось.имя)
        self.assertEqual(г.закреплено.tolist(), list(range(44)))
        # Нули Q — сразу за укороченными битами, в данных их нет.
        self.assertEqual(int(г.данные[0]), 44 + 3)

    def test_трёхмерный_с_укорочением_строк(self):
        р = т.режим("802.16.1-2544-1096")
        г = т.геометрия(р)
        кодировать, k = кодер_режима(р)
        self.assertEqual((г.основа, г.данных_по_осям, len(г.закреплено)), ((4, 25, 26), (3, 19, 20), 56))
        д = np.random.default_rng(4).integers(0, 2, k).astype(np.uint8)
        блок = np.zeros(г.размер, np.uint8)
        блок[г.порядок] = кодировать(д)
        self.assertEqual(блок[г.данные].tolist(), д.tolist())
        for ось in г.оси:
            self.assertFalse(т.синдромы(блок[None], ось).any(), ось.имя)

    def test_гипердиагональ_по_патенту(self):
        """Строка гиперчётности эталона (пошагово) — чётность слов гипердиагонали анализатора."""
        for ид in ("AHA4524-0.863", "отдел-0.729-16384", "Advantech-0.872-129"):
            р = т.режим(ид)
            г = т.геометрия(р)
            кодировать, k = кодер_режима(р)
            блок = np.zeros(г.размер, np.uint8)
            блок[г.порядок] = кодировать(np.random.default_rng(5).integers(0, 2, k).astype(np.uint8))
