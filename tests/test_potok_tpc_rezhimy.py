"""ТКБ по режимам модемов (tpc_rezhimy): таблицы из первоисточников, кодер-эталон, снятие, поиск.

Эталон — независимый кодер tkb_koder (регистр деления по многочленам таблиц
источников, пошаговая гипердиагональ патента, укорочение «нулями и выбросить»),
а не матрицы анализатора. Таблицы режимов переписаны сюда из файлов (путь и
страница у каждой) и сверяются с каталогом анализатора числом в число.
"""

import unittest
