class Рандомизатор802_16(unittest.TestCase):
    """Рандомизатор IEEE 802.16 перед кодером ТКБ: 1 + x¹⁴ + x¹⁵, предустановка 100101010000000 в начале
    пакета (C80216a-02/55, стр. 3, п. 8.3.3.1.1; 802163c-01/05, стр. 13, п. 3.1.1)."""

    def test_как_эталон_и_известная_псп(self):
        from reportgen.potok import skrembler  # noqa: PLC0415
        self.assertEqual(skrembler.рандомизатор_802_16(3000).tolist(), к.рандомизатор_802_16(3000).tolist())
        # Та же последовательность — продолжение по отводам 14 и 15 от первых 15 бит.
        п = к.рандомизатор_802_16(500)
        self.assertEqual(skrembler.псп((14, 15), п[:15], 500).tolist(), п.tolist())
        self.assertIn(((14, 15), "".join(map(str, п[:15].tolist()))), skrembler.ИЗВЕСТНЫЕ_ПСП)
        self.assertEqual(int(np.packbits(п[:16])[0]), 0x03)
        with self.assertRaisesRegex(ValueError, "15 бит"):
            skrembler.рандомизатор_802_16(4, "101")
        # Текст источника — дословно.
        текст = _текст("ieee802/C80216a-02_55.pdf.txt")
        self.assertIn("characteris-|tic polynomial 1 + X14 + X15. The LFSR shall be preset at the beginning of "
                      "each burst to the value|100101010000000", текст)

    def поток(self, заполнение: bool):
        р = т.режим("802.16-OFDM-576-1/2")
        кодировать, k = кодер_режима(р)
        rng = np.random.default_rng(6)
        исходные = rng.integers(0, 2, (120, k)).astype(np.uint8)
        if заполнение:
            исходные[::2] = 0                                        # паузы — нули (у каждого второго блока)
        данные = исходные ^ к.рандомизатор_802_16(k)[None, :]
        ряд = np.concatenate([rng.integers(0, 2, 55).astype(np.uint8)] + [кодировать(д) for д in данные])
        ряд ^= (rng.random(len(ряд)) < 1e-3).astype(np.uint8)
        return ряд, исходные, k

    def test_по_заполнению_узнаётся(self):
        ряд, исходные, k = self.поток(True)
        выход, н = razbor.снять_вручную(ряд, "ткб режим 802.16-OFDM-576-1/2 фаза 55")
        self.assertIn("рандомизатор IEEE 802.16", " ".join(н.подробно))
        self.assertEqual(выход[:120 * k].tolist(), исходные.reshape(-1).tolist())

    def test_на_случайных_данных_по_указанию(self):
        ряд, исходные, k = self.поток(False)
        выход, н = razbor.снять_вручную(ряд, "ткб режим 802.16-OFDM-576-1/2 фаза 55 скремблер 802.16")
        self.assertEqual(выход[:120 * k].tolist(), исходные.reshape(-1).tolist())
        self.assertIn("снят рандомизатор IEEE 802.16", н.подробно[-1])
        выход, н = razbor.снять_вручную(ряд, "ткб режим 802.16-OFDM-576-1/2 фаза 55")
        self.assertNotEqual(выход[:k].tolist(), исходные[0].tolist())


class Перебор(unittest.TestCase):
    """Блоки, которые итерации не очистили: единственный наименьший набор мест, дающий все проверки."""

    РЕЖИМ = т.Режим("тест-ЧЧ+", (т.Ч16, т.Ч16), (0, 1), гипер=True, источник="тест")

    def блок(self, р=None):
        р = р or self.РЕЖИМ
        г = т.геометрия(р)
        кодировать, k = кодер_режима(р)
        блок = np.zeros((1, г.размер), np.uint8)
        блок[0, г.порядок] = кодировать(np.random.default_rng(5).integers(0, 2, k).astype(np.uint8))
        return г, блок

    def test_две_ошибки_в_строке_кода_чётности(self):
        """Строка чётности двух ошибок не видит; столбцы и гипердиагонали видят — набор единственный."""
        г, блок = self.блок()
        чистый = блок.copy()
        блок[0, [4 * 16 + 3, 4 * 16 + 10]] ^= 1
        итог, сводка = т.декодировать(г, блок)
        self.assertEqual(итог.tolist(), чистый.tolist())
        self.assertEqual((сводка["исправлено"], сводка["блоков_чисто"]), (2, 1.0))
        # Столбцы через 8 (половина строки): (4,3),(4,11),(12,3),(12,11) — слово кода веса 4 (гипердиагональ
        # со сдвигом 1 проходит через (4,3) и (12,11)); два набора — неоднозначно, блок не трогается.
        блок2 = чистый.copy()
        блок2[0, [4 * 16 + 3, 4 * 16 + 11]] ^= 1
        итог, сводка = т.декодировать(г, блок2)
        self.assertEqual(итог.tolist(), блок2.tolist())
        self.assertEqual(сводка["исправлено"], 0)

    def test_ошибка_в_бите_гиперчётности(self):
        """Бит гиперстроки входит в одно слово — его находит только перебор."""
        г, блок = self.блок()
        чистый = блок.copy()
        блок[0, 15 * 16 + 6] ^= 1
        итог, сводка = т.декодировать(г, блок)
        self.assertEqual(итог.tolist(), чистый.tolist())
        self.assertEqual(сводка["исправлено"], 1)
        self.assertTrue(сводка["чистые"][0])

    def test_три_ошибки_и_предел_мест(self):
        """Три ошибки (две в строке и одна в гиперстроке) — набор из трёх; при пределе мест 1 — не трогается."""
        г, блок = self.блок()
        чистый = блок.copy()
        блок[0, [2 * 16 + 1, 2 * 16 + 6, 15 * 16 + 13]] ^= 1
        итог, сводка = т.декодировать(г, блок)
        self.assertEqual(итог.tolist(), чистый.tolist())
        старый = т.ПЕРЕБОР_МЕСТ_ДО
        т.ПЕРЕБОР_МЕСТ_ДО = 1
        self.addCleanup(setattr, т, "ПЕРЕБОР_МЕСТ_ДО", старый)
        итог, сводка = т.декодировать(г, блок)
        self.assertEqual(итог.tolist(), блок.tolist())
        self.assertFalse(сводка["чистые"][0])

    def test_предел_ошибок(self):
        г, блок = self.блок()
        блок[0, [2 * 16 + 1, 2 * 16 + 6, 15 * 16 + 13]] ^= 1
        старый = т.ПЕРЕБОР_ОШИБОК_ДО
        т.ПЕРЕБОР_ОШИБОК_ДО = 2
        self.addCleanup(setattr, т, "ПЕРЕБОР_ОШИБОК_ДО", старый)
        итог, _ = т.декодировать(г, блок)
        self.assertEqual(итог.tolist(), блок.tolist())

    def test_закреплённые_места_не_переворачиваются(self):
        """Укороченные (известные нули) места не кандидаты: ошибка «на них» не исправляется ценой данных."""
        р = т.Режим("тест-ЧЧ+B", (т.Ч16, т.Ч16), (0, 1), бит_укор=3, гипер=True, источник="тест")
        г, блок = self.блок(р)
        блок[0, 1] ^= 1                                           # закреплённое место (B)
        итог, сводка = т.декодировать(г, блок)
        self.assertEqual(int(итог[0, 1]), 1)
        self.assertFalse(сводка["чистые"][0])

    def test_выколотые_без_перебора(self):
        г, блок = self.блок(т.Режим("тест-ЧЧ+в", (т.Ч16, т.Ч16), (0, 1), гипер=True, выколото=4, источник="тест"))
        self.assertEqual(т._перебор(блок, г, г.оси + [г.гипер], [None] * 3), 0)
        г2, блок2 = self.блок()
        self.assertEqual(т._перебор(блок2[:0], г2, г2.оси + [г2.гипер], [None] * 3), 0)


class ЗащитаОтЛожных(unittest.TestCase):
    """Крошечные коды 802.16 на чужом потоке: перебор мест не «очищает» случайные блоки, фаза на
    служебном слове кадра не берётся, автомат не берёт режим с долей чистых блоков ниже АВТОМАТ_ОТ."""

    def test_предел_перебора_по_запасу_проверок(self):
        малый, большой = т.геометрия(т.режим("802.16-OFDM-96-3/4")), т.геометрия(т.режим("AHA4524-0.954"))
        # 96 бит, 96 − 72 − 5 (Q) = 19 проверок: log₂ 96 + 10 = 16,6 ≤ 19, а с двумя местами — 22,2 > 19.
        self.assertEqual(т.предел_перебора(малый), 1)
        self.assertEqual(т.предел_перебора(большой), т.ПЕРЕБОР_ОШИБОК_ДО)
        self.assertTrue(т.перебор_осмыслен(малый))
        # Граница — число проверок против log₂ числа наборов из 1…w мест плюс запас.
        г = т.геометрия(т.Режим("тест-ЧЧ+", (т.Ч16, т.Ч16), (0, 1), гипер=True, источник="тест"))
        проверок = г.передаётся - len(г.данные)
        до = {w: math.log2(sum(math.comb(г.размер, i) for i in range(1, w + 1))) for w in (1, 2, 3)}
        старый = т.ПЕРЕБОР_ЗАПАС
        self.addCleanup(setattr, т, "ПЕРЕБОР_ЗАПАС", старый)
        т.ПЕРЕБОР_ЗАПАС = проверок - до[3] - 0.01
        self.assertEqual(т.предел_перебора(г), 3)
        т.ПЕРЕБОР_ЗАПАС = проверок - до[3] + 0.01
        self.assertEqual(т.предел_перебора(г), 2)
        т.ПЕРЕБОР_ЗАПАС = проверок - до[1] + 0.01
        self.assertEqual(т.предел_перебора(г), 0)
        self.assertFalse(т.перебор_осмыслен(г))
        # Без смысла — перебор не трогает блок, который иначе исправил бы.
        т.ПЕРЕБОР_ЗАПАС = старый
        кодировать, k = кодер_режима(г.режим)
        блок = np.zeros((1, г.размер), np.uint8)
        блок[0, г.порядок] = кодировать(np.random.default_rng(5).integers(0, 2, k).astype(np.uint8))
        блок[0, 15 * 16 + 6] ^= 1                                       # ошибка в бите гиперстроки
        оси = г.оси + [г.гипер]
        self.assertEqual(т._перебор(блок.copy(), г, оси, [None] * 3), 1)
        т.ПЕРЕБОР_ЗАПАС = 10 ** 6
        self.assertEqual(т._перебор(блок.copy(), г, оси, [None] * 3), 0)

    def test_случайные_блоки_не_очищаются(self):
        """Случайные биты вместо блоков: решение по кандидатам «очищает» сверх итераций не больше 1 % блоков
        (итерации сами очищают часть случайных блоков крошечного кода — от этого защищает порог автомата)."""
        rng = np.random.default_rng(12)
        старый = т.ПЕРЕБОР_ЗАПАС
        self.addCleanup(setattr, т, "ПЕРЕБОР_ЗАПАС", старый)
        for ид in ("802.16-OFDM-96-3/4", "802.16-OFDM-96-1/2", "802.16-OFDM-144-5/6", "AHA4524-0.954",
                   "AHA4501-0.473"):
            with self.subTest(ид):
                г = т.геометрия(т.режим(ид))
                блоки = rng.integers(0, 2, (1000 if г.размер < 1000 else 60, г.размер)).astype(np.uint8)
                т.ПЕРЕБОР_ЗАПАС = старый
                _, с = т.декодировать(г, блоки)
                т.ПЕРЕБОР_ЗАПАС = 10 ** 6
                _, без = т.декодировать(г, блоки)
                self.assertLessEqual(float(с["блоков_чисто"]), float(без["блоков_чисто"]) + 0.01)
                self.assertLess(float(с["блоков_чисто"]), т.АВТОМАТ_ОТ / 2)

    def test_q_не_проверки(self):
        г = т.геометрия(т.режим("802.16-OFDM-96-1/2"))             # Q = 6: 96 − 48 − 6 = 42 проверки
        наборов = [math.log2(sum(math.comb(96, i) for i in range(1, w + 1))) + т.ПЕРЕБОР_ЗАПАС for w in range(1, 9)]
        self.assertEqual(т.предел_перебора(г), sum(1 for v in наборов if v <= 42))

