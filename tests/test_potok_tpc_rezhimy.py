class ВсеРежимыКаталога(unittest.TestCase):
    """Каждый режим каталога: поток эталонного кодера (по источникам, не по анализатору) с ошибками линии
    1e-3 и синхрословом кадра → оценка находит кадр и фазу, снятие отдаёт ровно данные эталона.

    Бит в бит — у каждого блока, где ошибок линии не больше гарантированно исправимого кодом
    произведения ((d − 1) // 2, d — произведение расстояний осей); блок с большим числом ошибок
    (у крошечного кода чётности 802.16 две ошибки неисправимы в принципе) — только не больше 0,1 %.
    """

    def test_все_режимы(self):
        итог_бит_в_бит = []
        for р in т.КАТАЛОГ:
            with self.subTest(р.ид):
                блоков = 8 if т.геометрия(р).размер > 8000 else 24
                ряд, данные, T, фаза = поток_режима(р, блоков, 1e-3)
                чистый, _, _, _ = поток_режима(р, блоков, 0.0)
                в = т.оценить(ряд, р, T)
                self.assertIsNotNone(в)
                self.assertEqual((в.T, в.фаза), (T, фаза))
                # У eTPC из кодов чётности (Datum-0.950-4k) при 1e-3 неисправимы 3 блока из 24 (см. ниже).
                self.assertGreaterEqual(в.чисто, 0.85)
                выход, н = т.снять(ряд, р, T=T, фаза=в.фаза, бит_укор=в.бит_укор,
                                  гипер=(в.гипер_сдвиг + в.гипер_смещение) if р.гипер else None)
                г = т.геометрия(р, бит_укор=в.бит_укор)
                k = len(г.данные)
                доля, m = данные_совпали(выход, данные, k, T, фаза, S=T - г.передаётся)
                self.assertEqual(m, блоков)
                радиус = (math.prod(РАССТОЯНИЕ[c.вид] for c in р.оси) - 1) // 2
                лишних = (137 + T - г.передаётся - фаза) // T
                выход = выход[лишних * k:лишних * k + блоков * k].reshape(блоков, k)
                ошибок = [int((ряд[фаза + i * T:фаза + i * T + г.передаётся]
                               != чистый[фаза + i * T:фаза + i * T + г.передаётся]).sum()) for i in range(блоков)]
                for i in range(блоков):
                    if ошибок[i] <= радиус:
                        self.assertEqual(выход[i].tolist(), данные[i].tolist(), f"блок {i}, ошибок {ошибок[i]}")
                self.assertGreaterEqual(доля, 0.999)
                self.assertGreaterEqual(н.уверенность, 0.85)
                if доля == 1.0:
                    итог_бит_в_бит.append(р.ид)
        # Все, кроме крошечного (12,11)² 802.16 с двумя ошибками в одном блоке этого потока и eTPC из кодов
        # чётности Datum-0.950-4k: в трёх блоках по 5–8 ошибок, и у пяти ошибок блока 16 два разных набора
        # мест одного наименьшего веса дают тот же синдром — жёсткими решениями неразличимо.
        self.assertEqual(set(р.ид for р in т.КАТАЛОГ) - set(итог_бит_в_бит), {"802.16-OFDM-144-5/6", "Datum-0.950-4k"})


