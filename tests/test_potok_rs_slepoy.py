def слова_64(сколько, *, ошибок=None, сид=1, I=1):
    """Блоки RS(64, 48) по I слов; ``ошибок`` — {номер слова: число испорченных символов}. → (символы, данные)."""
    г = np.random.default_rng(сид)
    слова = [кодировать(г.integers(0, 256, 48).tolist(), 0x11D, 0, 16) for _ in range(сколько * I)]
    данные = [np.array(слова[b * I:(b + 1) * I])[:, :48].T.reshape(-1) for b in range(сколько)]
    for н, e in (ошибок or {}).items():
        for i in г.choice(64, e, replace=False):
            слова[н][i] ^= int(г.integers(1, 256))
    с = np.concatenate([np.array(слова[b * I:(b + 1) * I]).T.reshape(-1) for b in range(сколько)])
    return с.astype(np.int64), данные


