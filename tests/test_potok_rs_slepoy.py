    def test_опознать_края(self):
        """Цепочка ≥ 4, k ≥ 2, лишние корни вне цепочки — до четырёх; порог 0,8 от лучшей и 0,15."""
        F = Поле(0x11D)
        г = np.random.default_rng(9)

        def слова_с_корнями(n, корни, сколько=40):
            g = [1]
            for j in корни:
                к = F.степень(j)
                g = [a ^ F.умн(b, к) for a, b in zip(g + [0], [0] + g)]
            итог = []
            for _ in range(сколько):
                d = г.integers(0, 256, n - len(корни)).tolist()
                r = d + [0] * len(корни)
                for i in range(len(d)):
                    c = r[i]
                    if c:
                        for jj in range(1, len(корни) + 1):
                            r[i + jj] ^= F.умн(c, g[jj])
                итог.append(d + r[len(d):])
            return np.array(итог)

        п = R.опознать(слова_с_корнями(30, [5, 6, 7, 8]), 8, [0x11D])
        self.assertEqual((п["fcr"], п["подряд"], п["корней"], п["корни"], п["доля"], п["шаг"]), (5, 4, 4, [5, 6, 7, 8], 1.0, 1))
        self.assertIsNone(R.опознать(слова_с_корнями(30, [5, 6, 7]), 8, [0x11D]))
        self.assertEqual(R.опознать(слова_с_корнями(30, [5, 6, 7, 8, 9]), 8, [0x11D])["корней"], 4)
        лишние = [100, 120, 140, 160]
        self.assertIsNotNone(R.опознать(слова_с_корнями(40, [1, 2, 3, 4] + лишние), 8, [0x11D]))
        self.assertIsNone(R.опознать(слова_с_корнями(40, [1, 2, 3, 4] + лишние + [180]), 8, [0x11D]))
        self.assertIsNotNone(R.опознать(слова_с_корнями(8, [1, 2, 3, 4, 5, 6]), 8, [0x11D]))        # k = 2
        self.assertIsNone(R.опознать(слова_с_корнями(8, [1, 2, 3, 4, 5, 6, 7]), 8, [0x11D]))        # k = 1
        # Порог — 0,8 от лучшей доли: α^4 у 32 слов из 40 (ровно 0,8) — корень, у 31 — нет.
        смесь = np.concatenate([слова_с_корнями(30, [4, 5, 6, 7, 8], 32), слова_с_корнями(30, [5, 6, 7, 8], 8)])
        п = R.опознать(смесь, 8, [0x11D])
        self.assertEqual((п["fcr"], п["подряд"]), (4, 5))
        self.assertAlmostEqual(п["доля"], (0.8 + 4) / 5)
        смесь = np.concatenate([слова_с_корнями(30, [4, 5, 6, 7, 8], 31), слова_с_корнями(30, [5, 6, 7, 8], 9)])
        п = R.опознать(смесь, 8, [0x11D])
        self.assertEqual((п["fcr"], п["подряд"], п["доля"]), (5, 4, 1.0))
        # И не меньше 0,15: кодовых слов 6 из 40 — код, 5 из 40 — нет.
        шум = г.integers(0, 256, (40, 30))
        смесь = np.concatenate([слова_с_корнями(30, [5, 6, 7, 8], 6), шум[:34]])
        п = R.опознать(смесь, 8, [0x11D])
        self.assertEqual((п["fcr"], п["подряд"]), (5, 4))
        self.assertIsNone(R.опознать(np.concatenate([слова_с_корнями(30, [5, 6, 7, 8], 5), шум[:35]]), 8, [0x11D]))
        # Отбор: корень отбора в счёт доли не идёт.
        с = слова_с_корнями(30, [0, 1, 2, 3])
        п = R.опознать(с, 8, [0x11D], отобран_j=255)
        self.assertEqual((п["fcr"], п["подряд"], п["доля"]), (0, 4, 1.0))
        self.assertEqual(R.опознать(с, 8, [0x187, 0x11D])["многочлен"], 0x11D)

