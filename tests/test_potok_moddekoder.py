def токены(текст: str) -> list[tuple[str, float, float]]:
    """Посимвольный проход: серии 0/1, не прилепленные к буквам и цифрам; (метка, середина, −2·строка)."""
    итог = []
    for номер, строка in enumerate(текст.splitlines()):
        строка = строка.expandtabs(8)
        i = 0
        while i < len(строка):
            if строка[i] in "01" and (i == 0 or not (строка[i - 1].isalnum() or строка[i - 1] == "_")):
                j = i
                while j < len(строка) and строка[j] in "01":
                    j += 1
                if j == len(строка) or not (строка[j].isalnum() or строка[j] == "_"):
                    итог.append((строка[i:j], (i + j - 1) / 2, -2.0 * номер))
                i = j
            else:
                i += 1
    return итог


def по_углу(точки) -> list[str]:
    """Метки ФМ по углу от наименьшего неотрицательного — через комплексные числа."""
    центр = sum(complex(x, y) for _, x, y in точки) / len(точки)
    def угол(т):
        у = math.degrees(cmath.phase(complex(т[1], т[2]) - центр))
        return round(у, 7) % 360
    return [т[0] for т in sorted(точки, key=угол)]


def грей_отражением(k: int) -> list[int]:
    """Отражённый двоичный код: G(k+1) = 0·G(k), затем 1·(G(k) задом наперёд)."""
    код = [0]
    for б in range(k):
        код = код + [(1 << б) | g for g in reversed(код)]
    return код


def переставить(метка: str, p) -> str:
    return "".join(метка[i - 1] for i in p)


def эталон_фм(дем, код, *, поворот=0.0, инверсия=False, вход=None, выход=None, относительная=False):
    """Таблица (абсолютная) или (номера, метки) — «вручную», комплексными числами."""
    дм, км = по_углу(дем), по_углу(код)
    M, k = len(дм), len(дм[0])
    вход, выход = вход or list(range(1, k + 1)), выход or list(range(1, k + 1))
    e = [cmath.exp(2j * math.pi * n / M) for n in range(M)]
    поток = [format(v, f"0{k}b") for v in range(M)]
    if относительная:
        углы = [round(((-1 if инверсия else 1) * n * 360 / M + поворот), 7) % 360 for n in range(M)]
        ранг = {n: sorted(range(M), key=lambda j: углы[j]).index(n) for n in range(M)}
        номера = [ранг[дм.index(переставить(s, вход))] for s in поток]
        метки = [int(переставить(км[d], выход), 2) for d in range(M)]
        return номера, метки
    таблица = []
    полрасстояния = abs(e[1] - e[0]) / 2
    for s in поток:
        z = e[дм.index(переставить(s, вход))]
        z = (z.conjugate() if инверсия else z) * cmath.exp(1j * math.radians(поворот))
        до = [abs(z - т) for т in e]
        m = min(range(M), key=lambda j: до[j])
        if до[m] >= полрасстояния - 1e-9:
            return None
        таблица.append(int(переставить(км[m], выход), 2))
    return таблица


def применить_вручную(биты, k, таблица=None, номера=None, метки=None):
    """Подстановка по символу, в цикле."""
    итог, прежний = [], 0
    for i in range(len(биты) // k):
        v = int("".join(map(str, биты[i * k:(i + 1) * k])), 2)
        if номера is not None:
            n = номера[v]
            v, прежний = метки[(n - прежний) % (1 << k)], n
        else:
            v = таблица[v]
        итог += [int(ч) for ч in format(v, f"0{k}b")]
    return np.array(итог, dtype=np.uint8)


