def hdlc_биты(пакетов=80, сид=3) -> np.ndarray:
    кадры = [с.ethernet(п) for п in с.пакеты_ip(пакетов, сид=сид)]
    x = np.unpackbits(np.frombuffer(с.hdlc(кадры, флагов_между=20), np.uint8))
    return x[:len(x) // 3 * 3]


def передать(x: np.ndarray, дем, код, поворот: float, инверсия: bool) -> np.ndarray:
    """Передатчик — метки вида кода, канал — поворот и инверсия (обратные декодеру), приём — метки демодулятора."""
    дм, км = по_углу(дем.точки), по_углу(код.точки)
    M, k = len(дм), len(дм[0])
    итог = []
    for i in range(len(x) // k):
        m = км.index("".join(map(str, x[i * k:(i + 1) * k])))
        угол = m * 360 / M - поворот                      # до поворота декодера
        угол = -угол if инверсия else угол              # до инверсии
        n = round(угол / (360 / M)) % M
        итог += [int(ч) for ч in дм[n]]
    return np.array(итог, dtype=np.uint8)


