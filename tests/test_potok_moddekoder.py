# -- до 1024 точек: КАМ-512 и КАМ-1024 ------------------------------------------------------------

def приведённые(с: мд.Созвездие) -> dict[str, complex]:
    """Метка → точка, приведённая к центру и единичной средней мощности — комплексными числами, без moddekoder."""
    z = {м: complex(x, y) for м, x, y in с.точки}
    центр = sum(z.values()) / len(z)
    мощность = math.sqrt(sum(abs(v - центр) ** 2 for v in z.values()) / len(z))
    return {м: (v - центр) / мощность for м, v in z.items()}


def передать_кам(метки: list[int], дем: мд.Созвездие, код: мд.Созвездие, поворот: float, инверсия: bool,
                 шум: float = 0.0, сид: int = 1) -> np.ndarray:
    """Передатчик — точки вида кода, канал — обратный декодеру поворот и инверсия плюс шум, приём — ближайшая точка
    демодулятора перебором (метки — биты строками)."""
    k = код.k
    кп, дп = приведённые(код), приведённые(дем)
    дм = list(дп)
    дт = np.array([дп[м] for м in дм])
    rng = np.random.default_rng(сид)
    z = np.array([кп[format(v, f"0{k}b")] for v in метки]) * cmath.exp(-1j * math.radians(поворот))
    z = np.conj(z) if инверсия else z
    z = z + шум * (rng.standard_normal(len(z)) + 1j * rng.standard_normal(len(z)))
    ближайшие = [int(np.argmin(np.abs(дт - т))) for т in z]
    return np.array([int(ч) for i in ближайшие for ч in дм[i]], dtype=np.uint8)


