    def test_шаг_и_симметрии_общих_плоскостей(self):
        """Шаг поворота и симметрии — прямой проверкой: семиугольник с центром (шаг 360/7°, без центральной симметрии),
        «вертушка» из 32 точек (шаг 45°, отражением в себя не переходит), прямоугольник 2 × 4 (только 180°)."""
        def общая(точки):
            k = len(точки).bit_length() - 1
            return мд.Созвездие("x", tuple((format(n, f"0{k}b"), round(x, 12), round(y, 12)) for n, (x, y) in enumerate(точки)),
                                точные=True, вид="общее")
        семь = общая([(0.0, 0.0)] + [(math.cos(2 * math.pi * n / 7), math.sin(2 * math.pi * n / 7)) for n in range(7)])
        вертушка = общая([(r * math.cos(math.radians(у)), r * math.sin(math.radians(у))) for r, шаг, сдвиг, n in
                          ((1, 45, 0, 8), (2, 45, 10, 8), (3, 22.5, 5, 16)) for у in (сдвиг + шаг * i for i in range(n))])
        прямоугольник = общая([(x, y) for x in (-3, -1, 1, 3) for y in (-1, 1)])
        for с_, шаг in ((семь, 360 / 7), (вертушка, 45.0), (прямоугольник, 180.0)):
            п = мд.плоскость(с_)
            self.assertAlmostEqual(шаг, п.шаг, msg=с_.точки[:2])
            xy = np.array(п.xy)
            ждём = set()
            for r in range(round(360 / шаг)):
                for инверсия in (False, True):
                    z = (xy[:, 0] + 1j * xy[:, 1])
                    z = (np.conj(z) if инверсия else z) * cmath.exp(1j * math.radians(r * шаг))
                    до = np.abs(z[:, None] - (xy[:, 0] + 1j * xy[:, 1])[None, :])
                    if до.min(axis=1).max() < 1e-6:
                        ждём.add(tuple(до.argmin(axis=1).tolist()))
            self.assertEqual(ждём, {σ for _, σ in мд.симметрии(с_)})
        self.assertFalse(any("инверсия" in о for о, _ in мд.симметрии(вертушка)))
        self.assertEqual(8, len(мд.симметрии(вертушка)))

