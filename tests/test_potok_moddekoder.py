    def test_кам16(self):
        """КАМ: уровни I и Q — поворот на 90° переставляет их, инверсия — отражает Q."""
        натуральный = "\n".join(" ".join(format(i * 4 + q, "04b") for i in range(4)) for q in range(3, -1, -1))
        свой = мд.разобрать_etl(натуральный, "кам-натуральный.etl")
        грей = мд.найти("КАМ16 Грей")
        уровни = {}
        for с_ in (свой, грей):
            xs = sorted({x for _, x, _ in с_.точки})
            ys = sorted({y for _, _, y in с_.точки})
            уровни[с_.имя] = {м: complex(xs.index(x) - 1.5, ys.index(y) - 1.5) for м, x, y in с_.точки}
        for поворот, инверсия in itertools.product((0, 90, 180, 270, 45), (False, True)):
            н = мд.настройки({"модуляция": "КАМ16", "демодулятор": свой.имя, "вид_кода": грей.имя,
                              "поворот": поворот, "инверсия": инверсия},
                             найти_=lambda и: свой if и == свой.имя else мд.найти(и))
            if поворот == 45:
                with self.assertRaises(ValueError) as о:
                    мд.декодер(н)
                self.assertEqual("поворот 45° не переводит созвездие в себя; для КАМ-16 шаг 90°", str(о.exception))
                continue
            ждём = []
            for v in range(16):
                z = уровни[свой.имя][format(v, "04b")]
                z = (z.conjugate() if инверсия else z) * 1j ** (поворот // 90)
                ждём.append(int(next(м for м, т in уровни[грей.имя].items() if abs(т - z) < 1e-9), 2))
            self.assertEqual(ждём, list(мд.декодер(н).таблица), (поворот, инверсия))

