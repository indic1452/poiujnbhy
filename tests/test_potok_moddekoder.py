    def test_фм16_обходом_гиперкуба(self):
        """Гамильтоновы циклы Q4 из вершины 0 (1344 цикла, в обе стороны — 2688), с любой из 16 точек начала."""
        def циклы(путь, было):
            if len(путь) == 16:
                return 1 if bin(путь[-1]).count("1") == 1 else 0
            return sum(циклы(путь + [путь[-1] ^ (1 << б)], было | {путь[-1] ^ (1 << б)})
                       for б in range(4) if путь[-1] ^ (1 << б) not in было)
        из_нуля = циклы([0], {0})
        self.assertEqual(2688, из_нуля)
        н = мд.настройки({"модуляция": "ФМ16", "демодулятор": "ФМ16 Грей", "вид_кода": "ФМ16 натуральный"})
        self.assertEqual(16 * из_нуля, мд.число_вариантов(н))
        варианты = [мд.разметка(н, i) for i in range(1, 16 * из_нуля + 1)]
        self.assertEqual(sorted(set(варианты)), варианты)                      # различны, по возрастанию
        self.assertTrue(all(грей_цикл(в) for в in варианты[::97]))
        self.assertEqual(из_нуля, sum(1 for в in варианты if в[0] == 0))
        with self.assertRaises(ValueError) as о:
            мд.число_вариантов(мд.настройки({"модуляция": "ФМ16", "демодулятор": "ФМ16 Грей",
                                             "вид_кода": "ФМ16 Грей", "только_грей": False}))
