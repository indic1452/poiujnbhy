"""Обозначение документа, названное в вопросе без слова впереди.

Отдел: «у меня есть рекомендация "t-Rex-g.732.pdf", делаю запрос на структуру
и так далее этого стандарта — он не находит и вообще не ссылается на этот
документ. И так со многим».

Причина замерена. Обозначение опознавалось только рядом со словом
«рекомендация», «МСЭ» или «ITU»:

    designations_in("рекомендация G.732")   -> ['G.732']
    designations_in("структура цикла G.732") -> []          ← так и пишут

Не опознав обозначение, система не сверяла его с описью и не подкладывала
документ в материал: помощник отвечал по соседям, всплывшим на словах
«структура» и «цикл». «И так со многим» — потому что слово «рекомендация»
перед номером не печатает никто.
"""

import unittest

import _bootstrap  # noqa: F401
from reportgen.designations import (
    designations_in,
    implied_designations,
    name_parts,
)


class ОбозначениеБезСловаВпереди(unittest.TestCase):
    def test_так_и_пишут_в_отделе(self):
        для_проверки = (
            ("структура цикла G.732", ["G.732"]),
            ("расскажи про структуру G.732", ["G.732"]),
            ("что описано в G.732", ["G.732"]),
            ("G.703 и G.704", ["G.703", "G.704"]),
            ("стык E.164 и X.25", ["E.164", "X.25"]),
            ("ITU-R SM.1600", ["SM.1600"]),
            ("параметры по Y.1541", ["Y.1541"]),
        )
        for вопрос, ждём in для_проверки:
            with self.subTest(вопрос=вопрос):
                self.assertEqual(ждём, designations_in(вопрос))

    def test_имя_файла_из_выгрузки_мсэ(self):
        """Файл называется «T-REC-G.732.pdf» — обозначение внутри имени."""
        self.assertEqual(["G.732"], designations_in("T-REC-G.732.pdf"))

    def test_прежняя_форма_со_словом_не_сломана(self):
        for вопрос in ("рекомендация G.732", "МСЭ-Т G.732",
                       "Recommendation G.732"):
            with self.subTest(вопрос=вопрос):
                self.assertEqual(["G.732"], designations_in(вопрос))

    def test_порядок_по_месту_в_тексте_а_не_по_шаблонам(self):
        """На порядке стоят двое, и обоим важно первое, а не любое.

        Следование ссылкам берёт обозначения из самых относимых фрагментов,
        поиск по названию — из того, что назвала модель, а она называет
        главное раньше. Оба обрезают список по пределу. Пока разбор шёл по
        шаблонам подряд, «G.703, G.704, RFC 4818» с пределом в два давало
        RFC и одну рекомендацию вместо двух названных первыми.
        """
        self.assertEqual(["G.703", "G.704", "RFC 4818"],
                         designations_in("G.703, G.704, RFC 4818"))
        self.assertEqual(["RFC 4818", "G.703"],
                         designations_in("RFC 4818 и G.703"))
        self.assertEqual(["ГОСТ Р 53363", "G.703"],
                         designations_in("ГОСТ Р 53363 ссылается на G.703"))

    def test_обозначение_названо_один_раз(self):
        """Обе проверки видят один и тот же номер — задваивать его нельзя."""
        self.assertEqual(["G.732"], designations_in("рекомендация G.732: "
                                                    "в G.732 сказано"))


