class НомерЧерезПробелИБезСерии(unittest.TestCase):
    """Как отдел спросил на самом деле.

    «Опыт в примечаниях пишет, что нет документа ITU-T G.733, хотя вот он в
    библиотеке» — документ на полке, пять фрагментов, а вопрос был такой:

        В чем разница стандарта g 733 от 734?

    Ни одно из двух обозначений не опознавалось. У первого серию от номера
    отделял пробел, а не точка; у второго серии не было вовсе — она
    подразумевалась от первого. Сверять с описью было нечего, поиск двух
    рекомендаций не принёс, и модель написала, чего ей не хватает.
    """

    def test_вопрос_отдела_дословно(self):
        вопрос = "В чем разница стандарта g 733 от 734?"
        self.assertEqual(["G.733"], designations_in(вопрос))
        self.assertEqual(["G.734"], implied_designations(вопрос))

    def test_пробел_и_дефис_вместо_точки(self):
        for вопрос in ("стандарт G 733", "ITU-T G 733", "МСЭ-Т G-733",
                       "рекомендация G 733"):
            with self.subTest(вопрос=вопрос):
                self.assertEqual(["G.733"], designations_in(вопрос))

    def test_серия_наследуется_соседом(self):
        для_проверки = (
            ("G.703, 704 и 711", ["G.704", "G.711"]),
            ("RFC 4818 или 4819", ["RFC 4819"]),
            ("ГОСТ Р 53363 и 53364", ["ГОСТ Р 53364"]),
            ("разница G.733 от G.734", []),        # обе названы полностью
        )
        for вопрос, ждём in для_проверки:
            with self.subTest(вопрос=вопрос):
                self.assertEqual(ждём, implied_designations(вопрос))

    def test_без_слова_впереди_это_догадка_а_не_обозначение(self):
        """«g 733» без якоря — уже не утверждение, но и не потеря.

        Одного пробела мало, чтобы объявить число документом: «поток E 12»
        выглядит так же. Поэтому такая запись идёт в догадки — их сверяют с
        описью молча.
        """
        вопрос = "чем отличается g 733 от 734"
        self.assertEqual([], designations_in(вопрос))
        self.assertEqual(["G.733", "G.734"], implied_designations(вопрос))

    def test_догадки_не_плодятся_на_счётных_числах(self):
        """Цена ошибки та же, что и у обозначений, только тише.

        Догадка, которой в библиотеке нет, до инженера не доходит — но она
        стоит запроса к описи на каждом заходе, и разводить их незачем.
        """
        для_проверки = (
            "X.25 и 30 каналов",
            "G.732 использует 32 канала",
            "рекомендация G.703 от 1988 года",
            "полоса 30 кГц, усреднение по 64 сегментам",
            "уровень E 1 и поток E 2",
            "цикл 125 мкс и 32 канальных интервала",
        )
        for вопрос in для_проверки:
            with self.subTest(вопрос=вопрос):
                self.assertEqual([], implied_designations(вопрос))

    def test_русский_предлог_с_номером_не_обозначение(self):
        """«стандарты с 733 по 745» — это диапазон, а не рекомендация С.733.

        Кириллическая «с» в латинскую «C» не сводится ни здесь, ни в разборе
        точечной записи: подменять предлог серией нельзя.
        """
        вопрос = "стандарты с 733 по 745"
        self.assertEqual([], designations_in(вопрос))
        self.assertEqual([], implied_designations(вопрос))

    def test_запись_приводится_к_единому_виду(self):
        """«g 733» и «G.733» — один документ, а не два.

        Иначе сверка с описью пойдёт дважды, а в подсказке модель увидит два
        разных названия одного и того же.
        """
        self.assertEqual(["G.733"],
                         designations_in("стандарт g 733 и рекомендация G.733"))


