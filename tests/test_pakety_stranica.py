"""Страница «Анализ пакетов»: источник «Файл/Сеть», отбор, дерево протоколов, ручной стек — функции app.js в node
и устройство страницы (что случайный щелчок не отбирает, что захват — внутри анализа)."""

import json
import re
import shutil
import subprocess
import unittest
from pathlib import Path

import _bootstrap
from test_oblik import вырезать

NODE = shutil.which("node")
JS = (Path(_bootstrap.ROOT) / "src" / "reportgen" / "web" / "static" / "app.js").read_text(encoding="utf-8")


def выполнить(код: str):
    итог = subprocess.run([NODE, "-e", код], capture_output=True, text=True, encoding="utf-8", timeout=60)
    if итог.returncode:
        raise AssertionError(итог.stderr)
    return json.loads(итог.stdout.strip().splitlines()[-1])


def функции(*имена: str) -> str:
    return "\n".join(вырезать(JS, и) for и in имена)


def постоянная(имя: str) -> str:
    м = re.search(r"^    const " + имя + r" = .*?;$", JS, re.M | re.S)
    if not м:
        raise AssertionError(f"в app.js нет {имя}")
    return м.group(0)


@unittest.skipUnless(NODE, "node не установлен")
class ОтборTests(unittest.TestCase):
    """Отбор: текст из поля и условия-плашки из меню, «Назад» на несколько шагов."""

    def test_выражение_из_текста_и_условий(self):
        код = функции("выражениеОтбора") + r"""
        console.log(JSON.stringify([
            выражениеОтбора({ текст: '', условия: [] }), выражениеОтбора(null),
            выражениеОтбора({ текст: ' tcp ', условия: [] }),
            выражениеОтбора({ текст: '', условия: [{ выр: 'udp.port == 53' }] }),
            выражениеОтбора({ текст: 'tcp or udp', условия: [{ выр: 'dns' }, { выр: '!(ip.addr == 10.0.0.1)' }] }),
            выражениеОтбора({ текст: 'frame[3]', условия: [{ выр: 'eth.addr' }, { выр: ' ' }] }),
        ]));"""
        self.assertEqual(["", "", "tcp", "udp.port == 53", "(tcp or udp) and dns and (!(ip.addr == 10.0.0.1))",
                          "frame[3] and eth.addr"], выполнить(код))

    def test_условие_плашкой_без_повторов(self):
        код = функции("отборСУсловием") + r"""
        const а = отборСУсловием({ текст: 'tcp', условия: [] }, 'dns', 'DNS');
        const б = отборСУсловием(а, 'dns', 'ещё раз');
        const в = отборСУсловием(б, '  ', 'пусто');
        console.log(JSON.stringify([а, б, в, отборСУсловием({ условия: [] }, 'x').условия]));"""
        а, б, в, без_подписи = выполнить(код)
        self.assertEqual({"текст": "tcp", "условия": [{"выр": "dns", "подпись": "DNS"}]}, а)
        self.assertEqual(а, б, "то же условие второй раз не добавляется")
        self.assertEqual(а, в, "пустое — не условие")
        self.assertEqual([{"выр": "x", "подпись": "x"}], без_подписи)

    def test_смена_и_назад_на_несколько_шагов(self):
        код = функции("выражениеОтбора", "сменитьОтбор", "отборНазад") + "\n" + постоянная("ОТБОР_ШАГОВ") + r"""
        const с = { отбор: { текст: '', условия: [] }, отборНазад: [] };
        const итог = [];
        итог.push(сменитьОтбор(с, { текст: 'tcp', условия: [] }), с.фильтр);
        итог.push(сменитьОтбор(с, { текст: ' tcp ', условия: [] }));             // то же — не шаг
        сменитьОтбор(с, { текст: 'tcp', условия: [{ выр: 'dns', подпись: 'DNS' }] });
        сменитьОтбор(с, { текст: '', условия: [] });                               // «Сбросить»
        итог.push(с.фильтр, с.отборНазад.length);
        итог.push(отборНазад(с), с.фильтр);
        итог.push(отборНазад(с), с.фильтр);
        итог.push(отборНазад(с), с.фильтр, отборНазад(с));
        for (let i = 0; i < 40; i++) сменитьОтбор(с, { текст: 'frame.len > ' + i, условия: [] });
        итог.push(с.отборНазад.length);
        console.log(JSON.stringify(итог));"""
        self.assertEqual([True, "tcp", False, "", 3, True, "tcp and dns", True, "tcp", True, "", False, 30], выполнить(код))


@unittest.skipUnless(NODE, "node не установлен")
class ДеревоTests(unittest.TestCase):
    """Дерево протоколов: мелкие ветви — в «прочее», ни одного куска уже минимума."""

    def раскладка(self, *вызовы):
        код = функции("раскладкаДетей") + "\nconsole.log(JSON.stringify([" + ", ".join(
            f"раскладкаДетей({з}, {в}, {ш}, {м})" for з, в, ш, м in вызовы) + "]));"
        return выполнить(код)

    def test_крупные_сами_мелкие_вместе(self):
        [итог] = self.раскладка(("[500, 300, 1, 1, 1, 1]", 900, 1000, 36))
        self.assertEqual([[0], [1], [2, 3, 4, 5]], [к["индексы"] for к in итог])
        self.assertEqual([False, False, True], [к["прочее"] for к in итог])
        self.assertGreaterEqual(min(к["ш"] for к in итог), 36 - 1e-9)
        self.assertLessEqual(sum(к["ш"] for к in итог), 1000 + 1e-9)
        self.assertEqual(0, итог[0]["x"])
        self.assertAlmostEqual(итог[1]["x"], итог[0]["ш"])

    def test_сотни_мелких_и_узкий_родитель(self):
        сотни, узкий, пара, один, пусто, нули = self.раскладка(
            ("Array(300).fill(2)", 600, 1000, 36), ("[5, 3, 2]", 10, 50, 36), ("[1, 1]", 2, 1000, 36),
            ("[1]", 100, 1000, 36), ("[]", 0, 1000, 36), ("[0, 0, 7]", 7, 1000, 36))
        # Сотни россыпью: самые крупные — по минимуму, остальное — «прочее», его можно раскрыть дальше.
        self.assertEqual(27, len(сотни))
        self.assertTrue(сотни[-1]["прочее"])
        self.assertEqual(300 - 26, len(сотни[-1]["индексы"]))
        self.assertGreaterEqual(min(к["ш"] for к in сотни), 36 - 1e-9)
        self.assertLessEqual(sum(к["ш"] for к in сотни), 1000 + 1e-9)
        self.assertEqual([[[0, 1, 2], True, 50]], [[к["индексы"], к["прочее"], round(к["ш"])] for к in узкий],
                         "в узкий родитель влезает один кусок — «прочее»")
        self.assertEqual([[0], [1]], [к["индексы"] for к in пара])
        self.assertEqual([[[0], False, 36]], [[к["индексы"], к["прочее"], round(к["ш"])] for к in один],
                         "один мелкий — сам, но не уже минимума")
        self.assertEqual([], пусто)
        self.assertEqual([[2]], [к["индексы"] for к in нули], "нулевые не рисуются")

    def test_список_и_полоса(self):
        код = функции("делениеДетей", "слитьМелкие") + r"""
        const доли = [0.5, 0.2, 0.1, 0.05, 0.05, 0.03, 0.02, 0.012, 0.005, 0.004, 0.003];
        console.log(JSON.stringify([
            делениеДетей([0.5, 0.5], 8, 0.01), делениеДетей(доли, 8, 0.01), делениеДетей(доли.slice(0, 9), 8, 0.01),
            слитьМелкие([{ протокол: 'A', доля: 90 }, { протокол: 'B', доля: 2 }, { протокол: 'C', доля: 1 }], 3),
            слитьМелкие([{ протокол: 'A', доля: 90 }, { протокол: 'B', доля: 2 }], 3)]));"""
        два, много, девять, слито, один = выполнить(код)
        self.assertEqual({"видны": [0, 1], "прочие": []}, два)
        self.assertEqual({"видны": [0, 1, 2, 3, 4, 5, 6, 7], "прочие": [8, 9, 10]}, много)
        self.assertEqual({"видны": list(range(9)), "прочие": []}, девять, "один в «прочее» не уходит")
        self.assertEqual(["A", "прочее (2)"], [ч["протокол"] for ч in слито])
        self.assertEqual(3, слито[1]["доля"])
        self.assertEqual(["B", "C"], слито[1]["состав"])
        self.assertEqual(["A", "B"], [ч["протокол"] for ч in один])

    def test_устройство(self):
        вид = JS.split("function иерархия(data) {")[1].split("function диалогиТаблица(data) {")[0]
        self.assertIn("раскладкаДетей(у.дети.map(значение), значение(у), ш, у.прочее ? СХЕМА_МИН_РАСКРЫТО : СХЕМА_МИН)", вид)
        self.assertIn("if (у.прочее && у !== фокус) return;", вид, "«прочее» — лист схемы, иначе бесконечная вложенность")
        self.assertIn("г.addEventListener('click', () => (у.прочее ? приблизить(у) : выбрать(у, true)));", вид)
        self.assertIn("делениеДетей(", вид)
        self.assertNotIn("отфильтровать(фильтрПротокола(у))", вид.split("function рисоватьКарточку")[0],
                         "двойной щелчок и Enter в дереве не отбирают")
