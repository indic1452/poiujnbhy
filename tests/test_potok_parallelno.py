def узел_с_планом(задания, папка_заданий, данные, планы, весь="ждёт", владелец=1):
    """Готовое задание, этапы которого найдены по началу файла (четверть), и план их пересчёта по всему
    файлу (шаги каждого этапа — от потока прежнего): автомат не нужен, шаги — настоящие."""
    ид = задания.создать(владелец=владелец, имя="п.bin", данные=данные, разбирать=False)
    assert дождаться(lambda: задания.прочитать(ид)["состояние"] == "готово" and ид not in задания.идущие(), 30)
    папка = Path(папка_заданий) / ид
    выборка = np.unpackbits(np.frombuffer(данные, np.uint8))[:len(данные) * 2 - 3]   # не кратно 8
    этапы = []
    for номер, _ in enumerate(планы, start=1):
        (папка / f"этап-{номер}.bin").write_bytes(np.packbits(выборка).tobytes())
        этапы.append({"номер": номер, "уровень": "вручную", "что": f"слой {номер}", "выгрузка": "bin",
                      "выход": f"{len(выборка)} бит — по началу файла", "по_выборке": True, "бит": len(выборка),
                      "выгрузка_байт": (len(выборка) + 7) // 8, "весь": весь})
    с = json.loads((папка / "состояние.json").read_text(encoding="utf-8"))
    с.update(этапы=этапы, весь_файл={"состояние": весь, "план": [{"номер": н, "шаги": ш}
                                                                 for н, ш in enumerate(планы, start=1)]})
    (папка / "состояние.json").write_text(json.dumps(с, ensure_ascii=False), encoding="utf-8")
    return ид


def биты_файла(путь, бит=None):
    биты = np.unpackbits(np.frombuffer(Path(путь).read_bytes(), np.uint8))
    return биты if бит is None else биты[:бит]


