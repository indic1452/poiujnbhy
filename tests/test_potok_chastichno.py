"""Частично проверенные кадры: другое толкование берётся, только если заметно лучше.

- Кадры HDLC в нагрузке кадра модема (синхрослово и служебное поле вставлены
  в поток): в сыром потоке у части кадров FCS не сходится — путь через цикл
  даёт все кадры целыми и берётся.
- Ошибки линии без кода и кадра: FCS сходится частично, и так и остаётся —
  цикла и систематического кода нет, и это записано как проверенное.
- Кадры постоянной длины с одинаковыми заголовками дают «цикл» — он не
  уводит от кадров, если под ним не лучше.
"""

