def ветвь(оценка, *находки, частично=None):
    в = razbor.Ветвь(находки=list(находки), оценка=оценка)
    в.частично = частично
    return в


def бюджет(профиль="обычно"):
    return razbor.Бюджет(конец=time.monotonic() + 10 ** 6, профиль=razbor.ПРОФИЛИ[профиль])


class ЗаметноЛучше(unittest.TestCase):
    """Другое толкование берётся, только если проверяемое под ним лучше на ЗАМЕТНО_ЛУЧШЕ."""

    кадры = Находка(уровень="канальный", что="HDLC", уверенность=0.55, мера="FCS 55 %")
    цикл = Находка(уровень="цикл", что="цикл 8192 бит", уверенность=1.0, мера="100 %")

    def через_цикл(self, под_циклом):
        напрямую = ветвь(15.5, self.кадры, частично=self.кадры)
        иная = ветвь(10.0 + под_циклом, self.цикл)
        with mock.patch.object(razbor, "_по_циклу", return_value=(иная, под_циклом)):
            return razbor._или_по_циклу(напрямую, self.кадры, np.zeros(10, np.uint8), 0, "", бюджет())

    def test_через_цикл_чуть_лучше_не_берётся(self):
        итог = self.через_цикл(15.5 + razbor.ЗАМЕТНО_ЛУЧШЕ - 0.01)
        self.assertEqual(итог.находки[0].уровень, "канальный")
        self.assertIn("под циклом оценка", "\n".join(итог.другие))

    def test_через_цикл_заметно_лучше_берётся(self):
        итог = self.через_цикл(15.5 + razbor.ЗАМЕТНО_ЛУЧШЕ)
        self.assertEqual(итог.находки[0].уровень, "цикл")
        self.assertIn("прямо в потоке (FCS 55 %)", "\n".join(итог.другие))

    def систематический(self, ниже_оценки, частично_ниже=False):
        код = Находка(уровень="код", что="РС", уверенность=0.8, мера="", дальше=np.zeros(9000, np.uint8),
                      вид_дальше="биты")
        напрямую = ветвь(15.5, self.кадры, частично=self.кадры)
        ниже = [ветвь(о, Находка(уровень="канальный", что="HDLC", уверенность=1.0, мера=""),
                      частично=self.кадры if частично_ниже else None) for о in ниже_оценки]
        детекторы = [(f"код {i}", (lambda: код), "после декодирования") for i in range(len(ниже_оценки))]
        with mock.patch.object(razbor, "_систематические", return_value=детекторы), \
                mock.patch.object(razbor, "_ступень", side_effect=ниже) as ступень:
            итог = razbor._или_систематический(напрямую, np.zeros(10, np.uint8), 0, "", бюджет(), None)
        return итог, ступень.call_count

    def test_систематический_чуть_лучше_не_берётся(self):
        итог, _ = self.систематический([15.5 + razbor.ЗАМЕТНО_ЛУЧШЕ - 0.01])
        self.assertEqual(итог.находки[0].уровень, "канальный")
        self.assertIn("не лучше", "\n".join(итог.другие))
        self.assertIn("нет такого, после декодирования которого кадры проверялись бы лучше",
                      "\n".join(итог.не_найдено))

    def test_систематический_заметно_лучше_берётся_и_дальше_не_ищется(self):
        итог, вызовов = self.систематический([20.0, 30.0])
        self.assertEqual([н.уровень for н in итог.находки], ["код", "канальный"])
        self.assertAlmostEqual(итог.оценка, razbor.ВЕС_ПРЕОБРАЗОВАНИЯ * 0.8 + 20.0)
        self.assertEqual(вызовов, 1)                   # кадры сошлись полностью — второй не звали

    def test_систематический_частично_лучше_ищется_дальше(self):
        итог, вызовов = self.систематический([20.0, 30.0], частично_ниже=True)
        self.assertEqual(вызовов, 2)
        self.assertAlmostEqual(итог.оценка, razbor.ВЕС_ПРЕОБРАЗОВАНИЯ * 0.8 + 30.0)

    def test_срок_длинного_кода(self):
        """Под частичными кадрами длинный код ищется не дольше СИСТЕМАТИЧЕСКИЙ_СРОК (кроме глубокого)."""
        for профиль, срок in (("обычно", razbor.СИСТЕМАТИЧЕСКИЙ_СРОК),
                              ("глубоко", razbor.ПРОФИЛИ["глубоко"]["длинные"]["бюджет"])):
            with self.subTest(профиль=профиль), \
                    mock.patch.object(razbor.dlinnye, "найти", return_value=None) as найти:
                детекторы = razbor._систематические(np.zeros(10, np.uint8), бюджет(профиль), None)
                детекторы[-1][1]()
                self.assertAlmostEqual(найти.call_args.kwargs["бюджет"], срок, places=0)

    def test_рс_в_блоке_первым_при_известном_блоке(self):
        имена = [и for и, _, _ in razbor._систематические(np.zeros(10, np.uint8), бюджет(), 8160)]
        self.assertEqual(имена[0], "код Рида — Соломона в блоке (1020 байт)")
        имена = [и for и, _, _ in razbor._систематические(np.zeros(10, np.uint8), бюджет(), None)]
        self.assertNotIn("код Рида — Соломона в блоке", " ".join(имена))


class СлабыйЦиклИПреобразования(unittest.TestCase):
    """Цикл найден, кадры под ним — частично: преобразование уровня берётся, если заметно лучше."""

    def разобрать(self, оценка_преобразования):
        цикл = Находка(уровень="цикл", что="цикл", уверенность=1.0, мера="")
        кадры = Находка(уровень="канальный", что="HDLC", уверенность=0.5, мера="")
        проверено = ветвь(15.0, цикл, кадры)
        код = Находка(уровень="код", что="свёрточный", уверенность=1.0, мера="",
                      дальше=np.zeros(9000, np.uint8), вид_дальше="биты")
        # Оценка ветви преобразования — вес находки кода (1,0) и то, что под ним.
        ниже = ветвь(оценка_преобразования - razbor.ВЕС_ПРЕОБРАЗОВАНИЯ,
                     Находка(уровень="канальный", что="HDLC", уверенность=1.0, мера=""))
        исходная = razbor._ступень

        def ступень(биты, глубина, путь, б, блок=None):
            return исходная(биты, глубина, путь, б, блок) if глубина == 0 else ниже

        with mock.patch.object(razbor, "_проверяемые", return_value=проверено), \
                mock.patch.object(razbor, "_детекторы", return_value=[("код", lambda: код, "после кода")]), \
                mock.patch.object(razbor, "_ступень", side_effect=ступень):
            return исходная(np.zeros(20000, np.uint8), 0, "", бюджет())

    def test_заметно_лучше_преобразование(self):
        итог = self.разобрать(15.0 + razbor.ЗАМЕТНО_ЛУЧШЕ + 0.5)
        self.assertEqual(итог.находки[0].уровень, "код")
        self.assertIn("цикл виден сквозь преобразование", "\n".join(итог.другие))

    def test_не_лучше_остаётся_цикл(self):
        итог = self.разобрать(15.0 + razbor.ЗАМЕТНО_ЛУЧШЕ - 0.5)
        self.assertEqual(итог.находки[0].уровень, "цикл")
        self.assertIn("у проверяемого напрямую", "\n".join(итог.другие))


