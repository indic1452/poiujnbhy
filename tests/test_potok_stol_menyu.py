def код_стола() -> str:
    """Функции и константы меню из app.js и то, что идёт сразу за списком операций (доп. пункты, единые имена)."""
    текст = APP_JS.read_text(encoding="utf-8")
    код = функции_js(ФУНКЦИИ, КОНСТАНТЫ)
    начало = текст.index("    ОПЕРАЦИИ_СТОЛА.push(")
    конец = текст.index("    /**\n     * Меню стола по категориям")
    return код + "\n" + текст[начало:конец]


