# -*- coding: utf-8 -*-
"""Разбор вопроса на узлы: целое ищется по частям.

Жалоба отдела: «у меня есть комплексы разные, отвечающие за построение
тракта (включая антенну), они просто названы как ДМА 256 — почему модель не
анализирует содержимое и не строит из них тракт».

Замер на библиотеке, повторяющей этот случай (четыре паспорта узлов плюс
один общий документ), подтвердил: на вопрос «тракт приёма РРЛС» поиск
находит ТОЛЬКО общий документ, а из четырёх узлов — ни одного. Причина не в
качестве поиска: слов «тракт приёма» в паспорте демодулятора нет и быть не
должно. Вопрос называет целое, библиотека хранит части, связать их нечем.
"""

import json
import shutil
import tempfile
import unittest
from pathlib import Path

import _bootstrap  # noqa: F401
from reportgen.parts import (
    MAX_UNITS,
    MIN_WHOLE,
    PartsBook,
    book,
    forget,
)

#: Состав, повторяющий тракт приёма отдела: по ходу сигнала.
ТРАКТ = {
    "whole": "тракт приёма",
    "also": ["приёмный тракт", "тракт приема РРЛС"],
    "units": ["антенна", "малошумящий усилитель",
              "преобразователь частоты", "демодулятор"],
}


class Справочник(unittest.TestCase):
    def setUp(self):
        self.tmp = Path(tempfile.mkdtemp(prefix="reportgen-parts-"))
        self.addCleanup(shutil.rmtree, self.tmp, ignore_errors=True)
        self.addCleanup(forget)

    def записать(self, данные) -> Path:
        путь = self.tmp / "parts.json"
        путь.write_text(json.dumps(данные, ensure_ascii=False), encoding="utf-8")
        return путь

    def книга(self, записи) -> PartsBook:
        return PartsBook.load(self.записать({"parts": записи}))


class ЧтениеСправочника(Справочник):
    def test_состав_читается(self):
        книга = self.книга([ТРАКТ])
        self.assertEqual(1, len(книга))
        self.assertEqual([], книга.problems)
        self.assertEqual(("антенна", "малошумящий усилитель",
                          "преобразователь частоты", "демодулятор"),
                         книга.compositions[0].units)

    def test_нет_файла_пустой_справочник_а_не_падение(self):
        """Разбор состава — усиление, а не условие работы помощника."""
        книга = PartsBook.load(self.tmp / "нет-такого.json")
        self.assertEqual(0, len(книга))
        self.assertTrue(книга.problems)

    def test_битый_json_назван_словами(self):
        путь = self.tmp / "parts.json"
        путь.write_text('{"parts": [ , ]}', encoding="utf-8")
        книга = PartsBook.load(путь)
        self.assertEqual(0, len(книга))
        self.assertIn("JSON", книга.problems[0])

    def test_запись_без_узлов_пропущена_и_названа(self):
        книга = self.книга([{"whole": "тракт приёма", "units": []}])
        self.assertEqual(0, len(книга))
        self.assertIn("units", книга.problems[0])

    def test_слишком_короткое_целое_пропущено_и_названо(self):
        """«ПЧ» встретится в любом вопросе и разберёт то, о чём не спрашивали."""
        книга = self.книга([{"whole": "ПЧ", "units": ["гетеродин"]}])
        self.assertEqual(0, len(книга))
        self.assertIn(str(MIN_WHOLE), книга.problems[0])

    def test_трёхбуквенное_сокращение_проходит(self):
        """АФУ, МШУ, АЦП — три буквы, и печатают их постоянно."""
        книга = self.книга([{"whole": "АФУ", "units": ["облучатель"]}])
        self.assertEqual(1, len(книга))
        self.assertEqual(["облучатель"], книга.units_for("состав АФУ"))

    def test_повтор_написания_пропущен_и_назван(self):
        """Одно написание не может вести к двум разным составам."""
        книга = self.книга([
            ТРАКТ,
            {"whole": "приёмный тракт", "units": ["смеситель"]},
        ])
        self.assertEqual(1, len(книга))
        self.assertIn("уже занято", книга.problems[0])

    def test_узлы_не_повторяются(self):
        книга = self.книга([{"whole": "тракт приёма",
                             "units": ["антенна", "Антенна", "антенна "]}])
        self.assertEqual(("антенна",), книга.compositions[0].units)


class СличениеСВопросом(Справочник):
    def test_вопрос_в_другом_падеже(self):
        """Сличение идёт подстрокой, и словарная форма в падеж не входит.

        Это стоило одного замера: «земная станция спутниковой связи» не
        находилась в вопросе «состав земной станциИ спутниковой связи».
        Словарь терминов решает это тем, что основы пишет человек; здесь
        так нельзя — то же название идёт в поиск как запрос.
        """
        книга = self.книга([{"whole": "земная станция спутниковой связи",
                             "units": ["антенна", "модем"]}])
        for вопрос in ("состав земной станции спутниковой связи",
                       "земная станция спутниковой связи",
                       "что входит в земную станцию спутниковой связи"):
            with self.subTest(вопрос=вопрос):
                self.assertEqual(["антенна", "модем"], книга.units_for(вопрос))

    def test_основа_не_режется_до_чужого_слова(self):
        """Обрезать окончание надо, но не до огрызка.

        От «поле» без предела остаётся «пол», а «пол» находится и в «полоса»,
        и в «полный». Вопрос «какая полоса пропускания у ствола» разобрался бы
        тогда на узлы поля кадра, и инженер получил бы горсть поисков не по
        делу — молча, потому что разбор состава он не заказывал.
        """
        книга = self.книга([{"whole": "поле", "units": ["признак"]}])
        self.assertEqual(["признак"], книга.units_for("что записано в поле кадра"),
                         "своё же название перестало находиться")
        for чужой in ("какая полоса пропускания у ствола",
                      "полный состав аппаратуры"):
            with self.subTest(вопрос=чужой):
                self.assertEqual([], книга.units_for(чужой))

    def test_короткое_название_ловит_не_все_падежи(self):
        """Честная граница правила, а не скрытый изъян.

        «Поле» длиной в четыре знака сличается целиком: от него уже нечего
        отрезать, не сделав из него «пол». Значит, по такой записи не
        найдутся ни «поля», ни «полем» — те формы, где меняется четвёртая
        буква. Это осознанный размен: лишний разбор вредит больше, чем
        пропущенный, и лучше не найти состав, чем разобрать на узлы вопрос
        про полосу пропускания.

        Удлинить запись до «поле кадра» не поможет — коротким остаётся
        первое слово. Годится название, у которого основа и без окончания
        не короче четырёх знаков: «полоса», «станция», «антенна».
        """
        короткое = self.книга([{"whole": "поле", "units": ["признак"]}])
        self.assertEqual([], короткое.units_for("какие поля в кадре"))
        self.assertEqual([], self.книга([{"whole": "поле кадра",
                                          "units": ["признак"]}])
                         .units_for("какие поля в кадре"))
        длинное = self.книга([{"whole": "полоса пропускания", "units": ["фильтр"]}])
        for вопрос in ("какая полоса пропускания", "в полосе пропускания",
                       "по полосам пропускания стволов"):
            with self.subTest(вопрос=вопрос):
                self.assertEqual(["фильтр"], длинное.units_for(вопрос))

    def test_другое_написание_целого_работает(self):
        книга = self.книга([ТРАКТ])
        self.assertEqual(книга.units_for("тракт приёма"),
                         книга.units_for("что в приёмном тракте"))

    def test_чужой_вопрос_состава_не_называет(self):
        книга = self.книга([ТРАКТ])
        for вопрос in ("какой коэффициент шума у МШУ-2",
                       "как оформить заключение по письму",
                       "что такое КАМ-16", ""):
            with self.subTest(вопрос=вопрос):
                self.assertEqual([], книга.units_for(вопрос))

    def test_точное_совпадение_вытесняет_общее(self):
        """В вопросе «тракт приёма РРЛС» сходятся два состава.

        Тракт приёма назван написанием «тракт приема РРЛС» (17 знаков),
        радиорелейная линия — написанием «РРЛС» (4). Спрошено про тракт, и
        разбирать надо тракт, хотя само слово «радиорелейная линия» длиннее.

        Замер: сортировка по длине ЦЕЛОГО ставила первым состав станции РРЛ
        и вытесняла узлы тракта за предел.
        """
        книга = self.книга([
            ТРАКТ,
            {"whole": "радиорелейная линия", "also": ["РРЛС"],
             "units": ["антенно-фидерное устройство", "приёмопередатчик"]},
        ])
        узлы = книга.units_for("расскажи про тракт приёма РРЛС", limit=4)
        self.assertEqual(list(ТРАКТ["units"]), узлы)

    def test_порядок_узлов_сохраняется(self):
        """Узлы записаны по ходу сигнала, и инженер узнаёт в них свой тракт."""
        книга = self.книга([ТРАКТ])
        self.assertEqual(list(ТРАКТ["units"]), книга.units_for("тракт приёма"))

    def test_предел_числа_узлов(self):
        книга = self.книга([ТРАКТ])
        self.assertEqual(2, len(книга.units_for("тракт приёма", limit=2)))
        self.assertEqual([], книга.units_for("тракт приёма", limit=0))

    def test_предел_по_умолчанию_назван_числом(self):
        много = [f"узел {номер}" for номер in range(MAX_UNITS + 5)]
        книга = self.книга([{"whole": "большой комплекс", "units": много}])
        self.assertEqual(MAX_UNITS, len(книга.units_for("большой комплекс")))


class ПравкаПодхватываетсяСама(Справочник):
    def test_справочник_перечитывается_после_правки(self):
        """Отдел пополняет состав на ходу и сервер ради этого не перезапустит."""
        путь = self.записать({"parts": [ТРАКТ]})
        self.assertEqual(["антенна", "малошумящий усилитель",
                          "преобразователь частоты", "демодулятор"],
                         book(путь).units_for("тракт приёма"))
        # Перезаписываем с другой отметкой времени: иначе кэш не отличит.
        import os
        отметка = путь.stat().st_mtime
        путь.write_text(json.dumps(
            {"parts": [{"whole": "тракт приёма", "units": ["гетеродин"]}]},
            ensure_ascii=False), encoding="utf-8")
        os.utime(путь, (отметка + 10, отметка + 10))
        self.assertEqual(["гетеродин"], book(путь).units_for("тракт приёма"))


class СправочникОтдела(unittest.TestCase):
    """Тот файл, который поедет на машину отдела."""

    def setUp(self):
        self.addCleanup(forget)
        self.книга = PartsBook.load(Path("templates") / "parts.json")

    def test_читается_без_пропусков(self):
        self.assertEqual([], self.книга.problems,
                         "в справочнике отдела есть отброшенные записи")
        self.assertGreaterEqual(len(self.книга), 5)

    def test_тракт_приёма_разбирается_по_ходу_сигнала(self):
        узлы = self.книга.units_for("расскажи про тракт приёма РРЛС")
        self.assertIn("антенна", узлы)
        self.assertIn("малошумящий усилитель", узлы)
        self.assertIn("демодулятор", узлы)
        self.assertLess(узлы.index("антенна"), узлы.index("демодулятор"),
                        "узлы перечислены не по ходу сигнала")

    def test_ни_один_узел_не_пуст(self):
        for состав in self.книга.compositions:
            with self.subTest(состав=состав.whole):
                self.assertTrue(состав.units)
                for узел in состав.units:
                    self.assertTrue(узел.strip())


