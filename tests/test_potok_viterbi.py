"""Декодер Витерби отрезками и инвертированные ветви свёрточного кода.

Эталон — прямой декодер здесь же: метрики всех состояний на каждом шаге,
полная таблица предков, один обратный ход с лучшего состояния в конце; кодер —
свой. Декодер анализатора режет поток на отрезки с перекрытием в глубину
обратного хода и идёт по ним одновременно — решения должны совпасть с эталоном.
"""

import contextlib
import unittest
from unittest import mock

import numpy as np

import _bootstrap  # noqa: F401
from reportgen.potok import kod, svyortka, vykalyvanie


def закодировать(данные, многочлены, K, регистр=0):
    """Кодер 1/n: регистр (s << 1) | бит, выход ветви — чётность (регистр & g)."""
    выход = []
    for б in данные:
        регистр = ((регистр << 1) | int(б)) & ((1 << K) - 1)
        выход += [bin(регистр & g).count("1") & 1 for g in многочлены]
    return np.array(выход, np.uint8)


def витерби_эталон(биты, многочлены, K, известно=None):
    """Прямой декодер по всему потоку; начальное состояние не известно (метрики равны)."""
    n = len(многочлены)
    S = 1 << (K - 1)
    шагов = len(биты) // n
    y = np.asarray(биты[:n * шагов]).reshape(шагов, n)
    м = (np.ones((шагов, n), int) if известно is None
         else np.asarray(известно[:n * шагов]).reshape(шагов, n))
    выход = np.array([[[bin(((s << 1) | b) & g).count("1") & 1 for g in многочлены]
                       for b in (0, 1)] for s in range(S)])
    метрика = np.zeros(S)
    предок = np.zeros((шагов, S), int)
    for k in range(шагов):
        новая = np.full(S, np.inf)
        цена = ((выход != y[k]) * м[k]).sum(axis=2)          # (S, 2)
        for s in range(S):                                  # по возрастанию: при равенстве — меньший
            for b in (0, 1):
                t = ((s << 1) | b) & (S - 1)
                if метрика[s] + цена[s, b] < новая[t]:
                    новая[t] = метрика[s] + цена[s, b]
                    предок[k, t] = s
        метрика = новая
    t = int(np.argmin(метрика))
    данные = np.zeros(шагов, np.uint8)
    for k in range(шагов - 1, -1, -1):
        данные[k] = t & 1
        t = предок[k, t]
    return данные


#: Коды в записи стандартов (CCSDS 131.0-B: 171/133; 36.212: 133/171/165) — внутрь зеркалом:
#: регистр здесь (s << 1) | бит, новейший бит — младший.
НАСА = [svyortka.зеркало(g, 7) for g in (0o171, 0o133)]
LTE = [svyortka.зеркало(g, 7) for g in (0o133, 0o171, 0o165)]


def с_ошибками(биты, p, сид):
    return биты ^ (np.random.default_rng(сид).random(len(биты)) < p).astype(np.uint8)


class ОтрезкамиКакЦеликом(unittest.TestCase):
    """Короткий ОТРЕЗОК — много отрезков и стыков на коротком потоке."""

    def сверить(self, многочлены, K, шагов, p, известно_шаблон=None, сид=1, **заплатки):
        rng = np.random.default_rng(сид)
        данные = rng.integers(0, 2, шагов).astype(np.uint8)
        принято = с_ошибками(закодировать(данные, многочлены, K), p, сид + 1)
        известно = None
        if известно_шаблон is not None:
            известно = np.resize(np.array(известно_шаблон, np.uint8), len(принято))
            принято = принято & известно
        with (mock.patch.multiple(kod, **заплатки) if заплатки else contextlib.nullcontext()):
            итог = kod.витерби_n(принято, многочлены, K, известно)
        эталон = витерби_эталон(принято, многочлены, K, известно)
        self.assertEqual(len(итог), шагов)
        self.assertTrue(np.array_equal(итог, эталон),
                        f"расходится в {int((итог != эталон).sum())} решениях")
        return итог, данные

    def test_k5_и_k7_много_отрезков(self):
        for многочлены, K in (([0o23, 0o35], 5), ([0o171, 0o133], 7)):
            with self.subTest(K=K):
                итог, данные = self.сверить(многочлены, K, 1500, 0.03, ОТРЕЗОК=200)
                self.assertLess(int((итог != данные).sum()), 60)

    def test_стирания_выколотого_кода(self):
        """3/4 из 1/2: шаблон 110110 — выколотые биты в метрику не входят."""
        self.сверить([0o171, 0o133], 7, 1200, 0.01, известно_шаблон=[1, 1, 0, 1, 1, 0],
                     ОТРЕЗОК=150)

    def test_скорость_одна_треть(self):
        self.сверить([0o133, 0o171, 0o165], 7, 1000, 0.05, ОТРЕЗОК=128)

    def test_память_по_частям(self):
        """ЯЧЕЕК_ДО мала — отрезки идут по нескольку за раз, а итог тот же."""
        self.сверить([0o171, 0o133], 7, 1400, 0.02, ОТРЕЗОК=100, ЯЧЕЕК_ДО=64 * 400)

    def test_короче_отрезка(self):
        self.сверить([0o7, 0o5], 3, 40, 0.0)

    def test_пусто(self):
        self.assertEqual(len(kod.витерби_n(np.zeros(1, np.uint8), [0o7, 0o5], 3)), 0)

    def test_запись_с_середины_потока(self):
        """Кодер к началу записи уже не в нуле: первые биты всё равно верны."""
        rng = np.random.default_rng(5)
        данные = rng.integers(0, 2, 3000).astype(np.uint8)
        регистр = 0b1011011                              # хвост предыдущих бит
        принято = закодировать(данные, [0o171, 0o133], 7, регистр=регистр)
        итог = kod.витерби_n(принято, [0o171, 0o133], 7)
        self.assertTrue(np.array_equal(итог, данные))


class Длина(unittest.TestCase):
    def test_шагов_декодера(self):
        self.assertEqual(kod.шагов_декодера(7), kod.ДЕКОДИРОВАТЬ_ШАГОВ)
        self.assertEqual(kod.шагов_декодера(11), kod.ЯЧЕЕК_ЗА_РАЗБОР >> 10)
        self.assertEqual(kod.шагов_декодера(15), kod.ДЕКОДИРОВАТЬ_ОТ)

    def test_декодируется_весь_поток(self):
        """Дальше отдаётся весь поток (до ДЕКОДИРОВАТЬ_ШАГОВ), а не первые 2¹⁸ бит."""
        rng = np.random.default_rng(6)
        данные = rng.integers(0, 2, 300_000).astype(np.uint8)
        найдено = kod.свёрточный(с_ошибками(закодировать(данные, НАСА, 7), 0.005, 7))
        self.assertIsNotNone(найдено)
        self.assertEqual(len(найдено.дальше), 300_000)
        self.assertLess(float(np.mean(найдено.дальше != данные)), 1e-3)


class ВесьПоток(unittest.TestCase):
    """Выколотый и 1/3: дальше отдаётся весь поток, а не образец опознания (2¹⁸ бит)."""

    def test_выколотый(self):
        rng = np.random.default_rng(20)
        данные = rng.integers(0, 2, 240_000).astype(np.uint8)
        мать = закодировать(данные, НАСА, 7)
        передано = мать[np.resize(np.array([1, 1, 0, 1], np.uint8), len(мать)).astype(bool)]
        self.assertGreater(len(передано), 1 << 18)
        найдено = vykalyvanie.найти(передано)
        дальше = найдено.дальше if найдено.вид_дальше == "биты" else next(iter(найдено.дальше.values()))
        self.assertGreater(len(дальше), 230_000)

    def test_одна_треть(self):
        rng = np.random.default_rng(21)
        данные = rng.integers(0, 2, 120_000).astype(np.uint8)
        поток = закодировать(данные, LTE, 7)
        self.assertGreater(len(поток), 1 << 18)
        найдено = svyortka.найти(поток)
        self.assertGreater(len(найдено.дальше), 115_000)


class ИнверсияВетвей(unittest.TestCase):
    """Ветвь передана инвертированной (CCSDS: вторая, 133): находится и снимается."""

    def test_ccsds_вторая_ветвь(self):
        rng = np.random.default_rng(8)
        данные = rng.integers(0, 2, 80_000).astype(np.uint8)
        поток = закодировать(данные, НАСА, 7)
        поток[1::2] ^= 1
        найдено = kod.свёрточный(с_ошибками(поток, 0.01, 9))
        self.assertIsNotNone(найдено)
        self.assertIn("ветвь 2 (133) передана инвертированной", найдено.что)
        self.assertTrue(any("как у CCSDS/NASA-GSFC" in п for п in найдено.подробно))
        self.assertLess(float(np.mean(найдено.дальше != данные)), 2e-3)

    def test_без_инверсии_не_сказано(self):
        rng = np.random.default_rng(10)
        данные = rng.integers(0, 2, 80_000).astype(np.uint8)
        найдено = kod.свёрточный(закодировать(данные, НАСА, 7))
        self.assertNotIn("инвертирован", найдено.что)
        self.assertTrue(np.array_equal(найдено.дальше, данные))

    def test_инверсия_всех_ветвей_это_инверсия_данных(self):
        """Обе ветви нечётного веса инвертированы — то же, что инвертированные данные:
        берётся маска без инверсии, а данные выходят инвертированными."""
        rng = np.random.default_rng(11)
        данные = rng.integers(0, 2, 40_000).astype(np.uint8)
        поток = закодировать(данные, НАСА, 7) ^ 1
        self.assertEqual(kod.инверсия_ветвей(поток, НАСА, 7), (0, 0))

    def test_скорость_одна_треть_третья_ветвь(self):
        rng = np.random.default_rng(12)
        данные = rng.integers(0, 2, 60_000).astype(np.uint8)
        поток = закодировать(данные, LTE, 7)
        поток[2::3] ^= 1
        найдено = svyortka.найти(с_ошибками(поток, 0.01, 13))
        self.assertIsNotNone(найдено)
        self.assertIn("ветвь 3 (165) передана инвертированной", найдено.что)
        сдвиг = len(данные) - len(найдено.дальше)
        self.assertLess(float(np.mean(найдено.дальше != данные[сдвиг:])), 2e-3)

    def test_выколотый_с_инверсией(self):
        """3/4 из 171/133 (X 101 / Y 110), вторая ветвь инвертирована до выкалывания: по коду
        инверсия неразличима — среди вариантов есть верный, и он даёт исходные данные."""
        rng = np.random.default_rng(14)
        данные = rng.integers(0, 2, 90_000).astype(np.uint8)
        мать = закодировать(данные, НАСА, 7)
        мать[1::2] ^= 1
        шаблон = np.array([1, 1, 0, 1, 1, 0], np.uint8)   # X1 Y1 X2 Y2 X3 Y3 → X 101, Y 110
        передано = мать[np.resize(шаблон, len(мать)).astype(bool)]
        найдено = vykalyvanie.найти(с_ошибками(передано, 0.003, 15))
        self.assertIsNotNone(найдено)
        self.assertIn("3/4", найдено.что)
        self.assertEqual("варианты", найдено.вид_дальше)
        верный = найдено.дальше["ветвь 2 (133) передана инвертированной"]
        self.assertLess(float(np.mean(верный != данные[:len(верный)])), 1e-3)
        другой = найдено.дальше["без инверсии ветвей"]
        self.assertGreater(float(np.mean(другой != данные[:len(другой)])), 0.2)
        # По расхождению верный чуть лучше, но при почти равных это не довод: порядок вариантов
        # один и тот же при любом шуме — первым «без инверсии».
        self.assertEqual(list(найдено.дальше), ["без инверсии ветвей", "ветвь 2 (133) передана инвертированной"])

    def test_классы_масок(self):
        """Маска и она же с инверсией данных — один класс; у кода 1/2 без выкалывания класс один."""
        rng = np.random.default_rng(16)
        данные = rng.integers(0, 2, 30_000).astype(np.uint8)
        поток = закодировать(данные, НАСА, 7)
        self.assertEqual(kod.инверсии_ветвей(поток, НАСА, 7), [(0, 0)])
        поток[0::2] ^= 1                                   # первая ветвь — класс {(1,0), (0,1)}
        self.assertEqual(kod.инверсии_ветвей(поток, НАСА, 7), [(0, 1)])
        # У многочлена чётного веса инверсия данных его ветвь не трогает: (7, 5) — класс
        # {(0,0), (1,0)}, инверсия второй ветви — другой класс.
        поток = закодировать(данные, [0o7, 0o5], 3)
        поток[1::2] ^= 1
        self.assertEqual(kod.инверсии_ветвей(поток, [0o7, 0o5], 3), [(0, 1)])

