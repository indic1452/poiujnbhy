"""Ветки таблицы массивов: удалить любую ветку, отметить несколько (Ctrl) и удалить разом.

Узел таблицы — вход задания (этап 0) или выход этапа автомата (этап k). Ветка
входа — задание целиком со всем, что из него получено; ветка этапа k — этапы
k, k+1, … задания (файлы, сведения в состоянии, журнал, разметка, запомненные
итоги) и производные задания, выросшие из этих этапов. Пачку веток сервер
удаляет одним запросом: права — на каждую, ушедшие вместе с выбранной выше
пропускаются. Браузер отмечает ветки и решает, что посылать, — его функции
берутся прямо из app.js и выполняются в node.
"""

