        # Тысяча — ещё можно: несуществующие ветки пропускаются.
        ответ = к.post("/api/potok/delete-many", json={"items": [{"job": "20990101-000000-000000"}] * 1000}).json()
        self.assertEqual((1000, [], 0), (ответ["skipped"], ответ["deleted"], ответ["arrays"]))


