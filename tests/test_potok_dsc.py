    def test_годный_но_неверный_знак_правится_по_ecc(self):
        """DX заменён другим годным знаком (ошибка в двух битах): выбор «DX, если годен» ошибается,
        ECC не сходится — перебор расхождений DX/RX находит вариант с верным ECC."""
        б = dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ)
        dx_ecc = 20 + 10 * (2 * (6 + len(ИЗБИРАТЕЛЬНЫЙ)))              # ECC в DX
        dx_от = 20 + 10 * (2 * (6 + 9))                                # первый знак «от» в DX
        for где, чем in ((dx_ecc, dsc.ecc(ИЗБИРАТЕЛЬНЫЙ) ^ 1), (dx_от, 22), (dx_ecc + 50, 3)):
            with self.subTest(где=где):
                испорчено = б.copy()
                испорчено[где:где + 10] = dsc.в_биты(чем)
                вв = dsc.вызовы(поток(испорчено))
                self.assertEqual([ИЗБИРАТЕЛЬНЫЙ], [в.знаки[:-1] for в in вв])
                self.assertEqual(0 if где == dx_ecc + 50 else 1, вв[0].по_ecc)
        испорчено = б.copy()
        for где in (dx_ecc, dx_ecc + 50):                              # оба экземпляра ECC неверны
            испорчено[где:где + 10] = dsc.в_биты(dsc.ecc(ИЗБИРАТЕЛЬНЫЙ) ^ 1)
        self.assertEqual([], dsc.вызовы(поток(испорчено)))

    def test_перебор_не_убирает_конец(self):
        """RX на месте конца — другой годный знак Z, DX ECC подобран так, что вариант «Z и DX ECC» сходится
        по ECC: такой вариант без знака конца не принимается, берётся следующий — с верным концом."""
        б = dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ)
        конец, верный = ИЗБИРАТЕЛЬНЫЙ[-1], dsc.ecc(ИЗБИРАТЕЛЬНЫЙ)
        z = 50
        dx_ecc = 20 + 10 * (2 * (6 + len(ИЗБИРАТЕЛЬНЫЙ)))
        rx_конца = dx_ecc - 20 + 50
        б[dx_ecc:dx_ecc + 10] = dsc.в_биты(верный ^ конец ^ z)
        б[rx_конца:rx_конца + 10] = dsc.в_биты(z)
        вв = dsc.вызовы(поток(б))
        self.assertEqual([ИЗБИРАТЕЛЬНЫЙ + [верный]], [в.знаки for в in вв])

