"""ЦИВ (DSC, ITU-R M.493): знаки 10 бит и фазирование — как в SDRangel (dscdemodsink.cpp: образцы
фазирования в битах), поля и ECC — как в SDRangel dsc.cpp; место судна — 1 + 2 + 2 + 3 + 2 цифры."""

import unittest

import numpy as np

import _bootstrap  # noqa: F401
from reportgen.potok import dsc
from reportgen.potok.razbor import разобрать as разобрать_поток

КОМУ = [23, 51, 23, 45, 60]                               # 235123456, 0
ОТ = [21, 14, 56, 78, 90]                                 # 211456789, 0
ИЗБИРАТЕЛЬНЫЙ = [120, 120] + КОМУ + [100] + ОТ + [100, 126] + [126] * 3 + [126] * 3 + [117]
БЕДСТВИЕ = [112, 112] + ОТ + [106] + [0, 52, 30, 1, 15] + [12, 34] + [109] + [127]


def поток(биты, сид=1, до=333, после=400):
    г = np.random.default_rng(сид)
    return np.concatenate([г.integers(0, 2, до), биты, г.integers(0, 2, после)]).astype(np.uint8)


def место(i, точки=20):
    """Бит начала знакового места i (0 — первый DX фазирования) в ``поток(закодировать(…))``."""
    return 333 + точки + 10 * i


class ЗнакиTests(unittest.TestCase):
    def test_образцы_фазирования_sdrangel(self):
        """Три знака подряд — как m_phasingPatterns в dscdemodsink.cpp (первый переданный бит — старший)."""
        образцы = {(125, 111, 125): 0b1011111001_1111011001_1011111001,
                   (111, 125, 110): 0b1111011001_1011111001_0111011010,
                   (109, 125, 108): 0b1011011010_1011111001_0011011011,
                   (107, 125, 106): 0b1101011010_1011111001_0101011011}
        for знаки, образец in образцы.items():
            биты = sum((dsc.в_биты(s) for s in знаки), [])
            self.assertEqual(образец, int("".join(map(str, биты)), 2), знаки)

    def test_знак_и_проверка(self):
        for s in range(128):
            self.assertEqual(s, dsc.знак(np.array(dsc.в_биты(s))))
        б = np.array(dsc.в_биты(125))
        for i in range(10):
            испорчено = б.copy()
            испорчено[i] ^= 1
            self.assertEqual(-1, dsc.знак(испорчено), i)

    def test_обратная_полярность_тоже_годна(self):
        """Число нулей инверсии = 7 − z, проверка инверсии = 7 − c: знак годен, но это 127 − s."""
        for s in (0, 5, 104, 125):
            self.assertEqual(127 - s, dsc.знак(1 - np.array(dsc.в_биты(s))))

    def test_знаки_везде(self):
        б = np.array(sum((dsc.в_биты(s) for s in (7, 99, 125)), []), dtype=np.uint8)
        зн = dsc.знаки_везде(б)
        self.assertEqual((21,), зн.shape)
        self.assertEqual([7, 99, 125], зн[[0, 10, 20]].tolist())
        self.assertEqual([dsc.знак(б[i:i + 10]) for i in range(21)], зн.tolist())

    def test_ecc(self):
        """Исключающее ИЛИ от указателя формата (второго — первый такой же) до конца."""
        self.assertEqual(120, dsc.ecc([120, 120]))
        self.assertEqual(120 ^ 5 ^ 117, dsc.ecc([120, 120, 5, 117]))
        self.assertEqual(120 ^ 5 ^ 117, dsc.ecc([0, 120, 5, 117]))


