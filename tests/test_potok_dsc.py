class ФазированиеTests(unittest.TestCase):
    """Правило M.493: два DX и один RX, один DX и два RX или три RX на своих местах; три DX — мало."""

    def испортить(self, места):
        б = поток(dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ))
        for i in места:
            б[место(i) + 3] ^= 1
        return dsc.вызовы(б)

    def test_достаточно(self):
        все_dx = list(range(0, 12, 2))
        все_rx = list(range(1, 12, 2)) + [13, 15]
        for dx, rx in ((2, 1), (1, 2), (0, 3)):
            with self.subTest(dx=dx, rx=rx):
                self.assertEqual(1, len(self.испортить(все_dx[dx:] + все_rx[rx:])))

    def test_мало(self):
        все_dx = list(range(0, 12, 2))
        все_rx = list(range(1, 12, 2)) + [13, 15]
        for dx, rx in ((6, 0), (1, 1), (0, 2), (2, 0)):
            with self.subTest(dx=dx, rx=rx):
                self.assertEqual([], self.испортить(все_dx[dx:] + все_rx[rx:]))

    def test_rx_105_и_104_тоже_фазирование(self):
        все_dx = list(range(0, 12, 2))
        self.assertEqual(1, len(self.испортить(все_dx[1:] + list(range(1, 12, 2)))))


class НайтиTests(unittest.TestCase):
    def test_сводка(self):
        б = np.concatenate([поток(dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ)), поток(dsc.закодировать(БЕДСТВИЕ), сид=2),
                            поток(dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ), сид=3)])
        н = dsc.найти(б)
        self.assertEqual({"вызовов": 3, "станций": 1}, н.свойства)
