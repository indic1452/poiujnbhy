    def test_расхождений_не_больше_четырёх(self):
        """До четырёх годных, но неверных DX правятся по ECC (все 2⁴ вариантов); пятое — уже нет.
        Негодный DX (взят RX) расхождением не считается. Искажения разные — иначе они гасятся в ECC."""
        б = dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ)

        def dx(k):
            return 20 + 10 * (2 * (6 + k))

        for сколько, негодный, есть in ((4, False, True), (4, True, True), (5, False, False)):
            испорчено = б.copy()
            for i in range(сколько):                                   # DX знаков «кому» — другие годные
                испорчено[dx(2 + i):dx(2 + i) + 10] = dsc.в_биты(КОМУ[i] ^ (1 << i))
            if негодный:
                испорчено[dx(8) + 1] ^= 1                              # DX первого знака «от» — негоден
            with self.subTest(сколько=сколько, негодный=негодный):
                вв = dsc.вызовы(поток(испорчено))
                self.assertEqual([ИЗБИРАТЕЛЬНЫЙ] if есть else [], [в.знаки[:-1] for в in вв])
                if есть:
                    self.assertEqual((сколько, int(негодный)), (вв[0].по_ecc, вв[0].исправлено))

    def test_негодный_знак_не_принимается_и_при_сошедшемся_ecc(self):
        """Оба экземпляра знака и оба ECC негодны: −1 ^ … может «сойтись» с −1 — такой вызов отброшен."""
        м = list(ИЗБИРАТЕЛЬНЫЙ)
        for последний in range(100):
            м[6] = последний
            if dsc.ecc(м) in м[2:-1]:
                break
        k = м.index(dsc.ecc(м), 2)
        б = dsc.закодировать(м)
        for место_знака in (k, len(м)):                               # знак и ECC: DX и RX негодны
            for где in (20 + 10 * (2 * (6 + место_знака)), 20 + 10 * (2 * (6 + место_знака) + 5)):
                б[где + 1] ^= 1
        self.assertEqual([], dsc.вызовы(поток(б)))

    def test_запись_обрывается(self):
        """Обрыв сразу за фазированием и ровно на месте RX — без падения и без вызова."""
        б = dsc.закодировать(ИЗБИРАТЕЛЬНЫЙ)
        начало = 20 + 120                                             # первый указатель формата
        for конец in (начало + 9, начало + 10 + 9, начало + 50 + 60 + 9):
            with self.subTest(конец=конец):
                self.assertEqual([], dsc.вызовы(б[:конец]))
        self.assertEqual(1, len(dsc.вызовы(б)))

