        "# Перечень контрольных точек тракта\n"
        "## Точка 1. Выход возбудителя, уровень минус 10 дБм\n"
        "## Точка 2. Вход усилителя мощности, уровень 12,5 дБм\n"
        "## Точка 3. Выход фильтра гармоник, уровень 40,5 дБм\n"
