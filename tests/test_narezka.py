class НомераСтраниц(unittest.TestCase):
    """Ссылка «с. 42» под цитатой обязана быть верной."""

    def test_номер_страницы_не_съезжает_при_склейке(self):
        текст = "".join(
            convert.page_marker(n) + f"\n\n## Раздел {n}\n\nМетка_{n}. Уровень {n} дБм.\n\n"
            for n in range(1, 13))
        for кусок in chunks_from_markdown(текст, "d", "standards", {"title": "Документ"}):
            метки = sorted(int(x) for x in re.findall(r"Метка_(\d+)", кусок.text))
            self.assertTrue(метки)
            self.assertEqual(метки[0], кусок.meta.get("page"))

    def test_маркеры_не_попадают_в_текст_фрагмента(self):
        текст = convert.page_marker(1) + "\n\n# Раздел\n\n" + "Текст. " * 60
        for кусок in chunks_from_markdown(текст, "d", "standards", {"title": "Д"}):
            self.assertNotIn("<!--", кусок.text)


class ПриёмБезМолчания(unittest.TestCase):
    """Текст есть, фрагментов ноль — это отказ, а не «добавлено 1»."""

    def test_документ_без_фрагментов_не_записывается_молча(self):
        import tempfile
        from pathlib import Path

        from reportgen.ingest import pipeline as конвейер
        from reportgen.ingest.pipeline import ingest_path
        from reportgen.store.db import Database
        from reportgen.store.repo import Repositories

        with tempfile.TemporaryDirectory() as каталог:
            корень = Path(каталог)
            (корень / "standards").mkdir()
            файл = корень / "standards" / "перечень.md"
            файл.write_text("# Перечень контрольных точек\n", encoding="utf-8")
            репозитории = Repositories(Database(корень / "база.sqlite"))

            # Нарезка перечень разбирает — значит, случай «текст есть, а
            # фрагментов ноль» надо создать честно: подменяем нарезку.
            было = конвейер.chunks_from_markdown
            конвейер.chunks_from_markdown = lambda *a, **k: []
            try:
                итог = ingest_path(репозитории, файл, root=корень)
            finally:
                конвейер.chunks_from_markdown = было

            self.assertEqual(0, итог.added + итог.updated,
                             "документ без фрагментов записан как принятый")
            self.assertEqual(1, итог.failed)
            self.assertTrue(итог.failures, "о потере не сказано ни слова")
            self.assertIsNone(репозитории.documents.by_doc_id("standards/перечень"),
                              "пустой документ остался в библиотеке")


if __name__ == "__main__":
    unittest.main()
