# -*- coding: utf-8 -*-
"""Нарезка библиотеки на фрагменты: без потерь и без раздувания.

Хозяин системы пересобирает библиотеку отдела — 13 600 документов, полмиллиона
фрагментов — и требует, чтобы всё собралось «без потерь и правильно». Сплошная
проверка нашла четыре беды, каждая из которых на такой библиотеке стоит дорого:

* документ из одних заголовков (перечень контрольных точек, оглавление ГОСТа)
  принимался с нулём фрагментов и без единого предупреждения — терялся целиком;
* предел длины фрагмента не соблюдался вовсе: абзац любой длины ложился в
  буфер целиком, и скан книги давал фрагменты по 17 тысяч знаков, от которых до
  модели доходила восьмая часть;
* в перекрытие уходил ЦЕЛЫЙ предыдущий абзац вместо 250 знаков — у скана, где
  абзац равен странице, указатель раздувался вдвое;
* таблица, разорванная по страницам PDF, теряла шапку: во втором куске
  оставались ряды цифр без имён столбцов.

Здесь всё это заперто замерами на настоящем коде нарезки.
"""

import re
import unittest

import _bootstrap  # noqa: F401

from reportgen import corpus
from reportgen.corpus import (MIN_CHARS, TARGET_CHARS, merge_short_sections,
                              split_document)
from reportgen.ingest.pipeline import chunks_from_markdown
from reportgen.ingest import convert
from reportgen.retrieval import tokenize


def нарезать(text):
    return list(merge_short_sections(split_document(text)))


def тексты(text):
    return [body for _, body in нарезать(text)]


СТРАНИЦА = "Измерение занимаемой полосы частот по методике отдела. " * 45


def скан(страниц=40):
    """Скан книги: страница — один абзац, как его отдаёт разбор DjVu."""
    return "\n\n".join(f"Страница {n}. {СТРАНИЦА}" for n in range(1, страниц + 1))


class ДлинаФрагмента(unittest.TestCase):
    """Предел длины обязан соблюдаться: всё сверх него модель не увидит."""

    def test_длинный_абзац_делится(self):
        текст = "Измерение занимаемой полосы частот. " * 500
        куски = тексты(текст)
        self.assertGreater(len(куски), 1, "абзац на 18 тысяч знаков остался одним куском")
        self.assertLessEqual(max(len(x) for x in куски), TARGET_CHARS)

    def test_скан_книги_не_даёт_фрагментов_длиннее_предела(self):
        куски = тексты(скан())
        self.assertLessEqual(max(len(x) for x in куски), TARGET_CHARS)

    def test_строка_без_знаков_препинания_тоже_делится(self):
        """Распознавание отдаёт страницу одной строкой без точек."""
        куски = тексты("слово " * 4000)
        self.assertLessEqual(max(len(x) for x in куски), TARGET_CHARS + MIN_CHARS)

    def test_одно_длинное_слово_режется_по_счёту_знаков(self):
        """Сплошной ряд цифр из распознанной таблицы — тоже текст документа.

        Границы слова тут нет вовсе, и молча выбросить остаток нельзя.
        """
        куски = тексты("А" * 9000)
        self.assertGreater(len(куски), 1)
        self.assertLessEqual(max(len(x) for x in куски), TARGET_CHARS + MIN_CHARS)
        # Ни одного знака сверх исходника и перекрытий: только «А» и переводы
        # строк от склейки.
        self.assertEqual({"А", "\n"}, set("".join(куски)))
        self.assertGreaterEqual(sum(x.count("А") for x in куски), 9000)


class Перекрытие(unittest.TestCase):
    """Перекрытие — 250 знаков, а не целый абзац."""

    def доля(self, текст):
        куски = тексты(текст)
        return sum(len(x) for x in куски) * 100 // len(текст)

    def test_скан_книги_не_раздувается_вдвое(self):
        """Абзац равен странице: раньше текст каждой страницы лежал дважды."""
        self.assertLess(self.доля(скан()), 130)

    def test_обычная_проза_не_раздувается(self):
        проза = "\n\n".join(f"Абзац {i}. " + "Слово " * 20 for i in range(120))
        self.assertLess(self.доля(проза), 120)

    def test_перекрытие_есть_и_не_пустое(self):
        """Совсем без перекрытия фраза на стыке фрагментов не находится."""
        куски = тексты(скан(20))
        общее = 0
        for предыдущий, следующий in zip(куски, куски[1:]):
            хвост = предыдущий[-120:]
            общее += sum(1 for слово in хвост.split() if слово in следующий)
        self.assertGreater(общее, 0, "фрагменты стыкуются встык, без перекрытия")


class ОдниЗаголовки(unittest.TestCase):
    """Документ, у которого текст только в заголовках, не должен пропадать."""

