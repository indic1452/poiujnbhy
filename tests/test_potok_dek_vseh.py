class МаскаДанных(unittest.TestCase):
    def test_двумерный_в_кадрах_как_снятие(self):
        """Маска на кадрах → данные под кодом: данные потока с маской = данные без неё ⊕ маска_данных."""
        rng = np.random.default_rng(3)
        данные = rng.integers(0, 2, (170, 39, 57)).astype(np.uint8)
        поток, начала = comtech(данные, приставка=501, ошибок=1e-3)
        код = tpc.найти_в_кадрах(поток, начала, 2964)
        self.assertTrue(код.свойства["систематический"])
        # Маска — слово кода в каждом кадре (как инверсия бит метки у Comtech): код снимается так же.
        слово = тпк(rng.integers(0, 2, (1, 39, 57)).astype(np.uint8), 57, 6, 39, 6)
        с_ = код.свойства
        маска_кадра = np.zeros(2964, np.uint8)
        маска_кадра[с_["начало_в_кадре"]:с_["начало_в_кадре"] + 2944] = слово
        код2 = tpc.найти_в_кадрах(поток ^ np.resize(np.roll(маска_кадра, 501), len(поток)), начала, 2964)
        окна = np.stack([маска_кадра[с_["начало_в_кадре"]:с_["начало_в_кадре"] + 2944]] * len(начала))
        м = tpc.маска_данных(с_, окна)
        self.assertEqual(len(код.дальше), len(м))
        np.testing.assert_array_equal(np.asarray(код2.дальше), np.asarray(код.дальше) ^ м)

    def test_маска_инверсии_по_кадрам(self):
        """Инверсия бит c у каждой метки (с бита 0) → окна кадров (с начала строк в кадре) → данные:
        сверка с прямым вырезом из маски всего ряда; кадры за краями ряда не берутся."""
        k, длина_ряда = 3, 600
        с_ = {"строка": 8, "столбец": 4, "k1": 5, "k2": 3, "блок": 0, "глубина": 0, "систематический": True,
              "начало": 0, "начало_в_кадре": 19, "строк_в_кадре": 4}
        ширина = 32
        for c in range(8):
            ряд = np.tile([(c >> 2) & 1, (c >> 1) & 1, c & 1], длина_ряда // 3).astype(np.uint8)
            # −19: начало строк в бите 0 (берётся); −20: до начала ряда; 549: конец ровно у края; 550: за краем.
            кадры = [-20, -19, 100, 205, 549, 550]
            годные = [н + 19 for н in кадры if 0 <= н + 19 and н + 19 + ширина <= длина_ряда]
            self.assertEqual([0, 119, 224, 568], годные)
            ждать = tpc.маска_данных(с_, np.stack([ряд[g:g + ширина] for g in годные]))
            np.testing.assert_array_equal(ждать, modem._маска_инверсии(c, k, кадры, длина_ряда, с_))
        self.assertEqual(4 * 15, len(ждать))
        self.assertIsNone(modem._маска_инверсии(5, k, [-20, 550], длина_ряда, с_))
        self.assertIsNone(modem._маска_инверсии(5, k, [100], длина_ряда, {**с_, "строка": 0}))
        self.assertIsNone(modem._маска_инверсии(5, k, [100], длина_ряда, {**с_, "строк_в_кадре": 0}))
        без_начала = {к: в for к, в in с_.items() if к != "начало_в_кадре"}
        np.testing.assert_array_equal(
            tpc.маска_данных(без_начала, np.stack([np.tile([1, 0, 1], 200)[g:g + ширина] for g in (100, 205)])),
            modem._маска_инверсии(5, k, [100, 205], длина_ряда, без_начала))

    def test_трёхмерный_и_несистематический(self):
        rng = np.random.default_rng(4)
        данные = rng.integers(0, 2, (24, 11, 11, 11)).astype(np.uint8)
        поток = тпк3(данные).reshape(-1)
        _, код = tpc.снять(поток)
        с_ = dict(код.свойства)
        self.assertEqual(16, с_["глубина"])
        слово = тпк3(rng.integers(0, 2, (1, 11, 11, 11)).astype(np.uint8)).reshape(-1)
        маска = np.resize(слово, len(поток))
        _, код2 = tpc.снять(поток ^ маска)
        м = tpc.маска_данных(с_, маска[None, :])
        np.testing.assert_array_equal(np.asarray(код2.дальше), np.asarray(код.дальше) ^ м[:len(код.дальше)])
        self.assertIsNone(tpc.маска_данных({**с_, "систематический": False}, маска[None, :]))
        self.assertIsNone(tpc.маска_данных({**с_, "строка": 0}, маска[None, :]))
        self.assertIsNone(tpc.маска_данных(с_, маска[None, :2 * с_["строка"] * с_["столбец"]]))
        with_2d = {**с_, "глубина": 0, "k3": 0}
        self.assertEqual(int(с_["k1"] * с_["k2"]) * ((len(поток) // с_["строка"] - с_["блок"]) // с_["столбец"]),
                         len(tpc.маска_данных(with_2d, маска[None, :])))
        self.assertIsNone(tpc.маска_данных({**с_, "плоскость": len(поток)}, маска[None, :]))


class ФактыНаСинтетике(unittest.TestCase):
    """Синтетика как K2964: истинная разметка — пятая по мере окна; автомат выбирает её по ПСП блока."""

    @classmethod
    def setUpClass(cls):
        cls.поток = поток_comtech()
        cls.биты = метки_по_таблице(cls.поток, ИСТИННАЯ)
        cls.начала, cls.длина, _ = razbor._кадры_модема(cls.биты, 2964)

    def test_маска_как_проба_и_выбор_автомата(self):
        группа = [list(т) for т in мд.по_инверсии([6, 7, 5, 4, 0, 1, 3, 2])]
        факты = modem.факты_равноценных(self.биты, 3, группа, self.начала, self.длина)
        self.assertTrue(факты["уложилась"])
        self.assertEqual(["проба"] + ["маска"] * 7, [факты["таблицы"][" ".join(map(str, т))]["путь"] for т in группа])
        # Каждая таблица отдельно (свой поиск кода) — те же факты.
        for т in группа[1:4]:
            один = modem.факты_равноценных(self.биты, 3, [т], self.начала, self.длина)["таблицы"][" ".join(map(str, т))]
            общий = факты["таблицы"][" ".join(map(str, т))]
            for поле in ("снят", "проверок", "уверенность", "блок"):
                self.assertEqual(один[поле], общий[поле], (т, поле))
            self.assertAlmostEqual(один["структура"], общий["структура"], places=12)
        # Первая — пробой, как у автомата (_снять_лучший): метки всей выборки, кадры с участка с данными.
        старт = tpc.начало_данных(self.биты, self.начала, self.длина)
        код = tpc.найти_в_кадрах(ploskost.с_фазой(self.биты, 3, {"таблица": группа[0]}, 0),
                                 self.начала[старт:старт + modem.КАДРОВ_ПРОБЫ], self.длина)
        первая = факты["таблицы"][" ".join(map(str, группа[0]))]
