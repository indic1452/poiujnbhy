def поток_comtech():
    """Как образец K2964: HDLC с паузами из флагов под ПСП блока, TPC (64, 57) × (46, 39) в кадрах 2964 бит."""
    кадры = [с.ethernet(п) for п in с.пакеты_ip(180, сид=3)]
    hdlc = b"".join(с.hdlc(кадры[i:i + 15], флагов_между=4) + b"\x7e" * 700 for i in range(0, len(кадры), 15))
    биты = np.unpackbits(np.frombuffer(hdlc, np.uint8))
    F = len(биты) // 2223
    данные = биты[:F * 2223].reshape(F, 2223) ^ лрп(ОТВОДЫ, НАЧАЛЬНОЕ, 2223)
    поток, _ = comtech(данные.reshape(F, 39, 57), приставка=1001)
    return поток[:len(поток) // 3 * 3]


def метки_по_таблице(поток, таблица):
    """Истинные символы → принятые метки так, что таблица (принятая → истинная) их возвращает."""
    s = поток.reshape(-1, 3) @ np.array([4, 2, 1])
    принятые = np.argsort(таблица)[s]
    return ((принятые[:, None] >> np.array([2, 1, 0])) & 1).astype(np.uint8).reshape(-1)


def таблица_автомата(биты, кадр=None):
    """Таблица плоскости, которую выбирает сам автомат (кадры по служебным словам, код в кадрах)."""
