def слить(лучшие, новые, сколько=50):
    """Как слитьВарианты окна: по мере, при равной — геометрические, затем по номеру; без повторов."""
    по = {}
    for в in лучшие + новые:
        по.setdefault(в["номер"], в)
    return sorted(по.values(), key=lambda в: (-в["мера"], not в["как"], в["номер"]))[:сколько]


