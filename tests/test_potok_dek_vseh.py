def простота_полностью(структура, лрп_, отрыв):
    """Прежний выбор (до ленивого): простота у всех, максимум (ступень, мера), при равной — первый:
    (номер, ступень; 0 — никто не проще прочих, взят первый)."""
    n = len(структура)
    оценки = [(3, структура[j]) if структура[j] >= modem.СТРУКТУРА_СРАЗУ else (2, структура[j]) if лрп_[j]
              else (1, отрыв[j]) for j in range(n)]
    i = max(range(n), key=lambda j: (оценки[j], -j))
    ступень, мера = оценки[i]
    if ступень == 1:
        прочие = sorted((м for j, (_, м) in enumerate(оценки) if j != i), reverse=True)
        if мера < skrembler.ВЫДЕЛЯЕТСЯ or (прочие and мера < 1.5 * прочие[0]):
            return 0, 0
    return i, ступень


class ВыборПоПростоте(unittest.TestCase):
    def test_как_прежний_максимум_и_лениво(self):
        """Случайные наборы: выбор тот же, что у полного расчёта простоты; ПСП блока — только до первого «да»
        по убыванию меры структуры, отрыв — только если ни ступени 3, ни 2 нет."""
        случай = random.Random(5)
        for _ in range(4000):
            n = случай.randint(2, 9)            # автомат зовёт выбор от двух равноценных
            структура = [случай.choice([0.01, 0.05, 0.05, 0.2, 0.3, 0.5, случай.random() * 0.4]) for _ in range(n)]
            лрп_ = [случай.random() < 0.3 for _ in range(n)]
            отрыв = [случай.choice([3.0, 11.9, 12.0, 20.0, 30.0, случай.random() * 100]) for _ in range(n)]
            вызовы = {"лрп": [], "отрыв": []}

            def л(j, вызовы=вызовы, лрп_=лрп_):
                вызовы["лрп"].append(j)
                return лрп_[j]

            def о(j, вызовы=вызовы, отрыв=отрыв):
                вызовы["отрыв"].append(j)
                return отрыв[j]

            i, пояснение = modem.выбрать_по_простоте(n, lambda j, с_=структура: с_[j], л, о)
            ждать, ступень = простота_полностью(структура, лрп_, отрыв)
            self.assertEqual(ждать, i, (структура, лрп_, отрыв))
            if any(x >= modem.СТРУКТУРА_СРАЗУ for x in структура):
                self.assertEqual([], вызовы["лрп"])
                self.assertIn("открываются сразу", пояснение)
            else:
                по_мере = sorted(range(n), key=lambda j: (-структура[j], j))
                до = next((k for k, j in enumerate(по_мере) if лрп_[j]), n - 1)
                self.assertEqual(по_мере[:до + 1], вызовы["лрп"])
            if ступень >= 2 or any(лрп_) or any(x >= modem.СТРУКТУРА_СРАЗУ for x in структура):
                self.assertEqual([], вызовы["отрыв"])
            else:
                self.assertEqual(list(range(n)), вызовы["отрыв"])
                self.assertEqual(ступень == 0, "ни под одним не проще" in пояснение)

    def test_данные_под_кодом_первые_2_в_20(self):
        """Автомат судит по первым 2^20 бит данных под кодом — как прежде: структура дальше не в счёт."""
        rng = np.random.default_rng(1)
        М = 1 << 20
        # A: 2^20 случайных, дальше нули (структура — за пределом); B: последняя четверть 2^20 — нули.
        a = np.concatenate([rng.integers(0, 2, М), np.zeros(М)]).astype(np.uint8)
        b = np.concatenate([rng.integers(0, 2, 3 * М // 4), np.zeros(М // 4)]).astype(np.uint8)
        равные = [(None, SimpleNamespace(дальше=x, свойства={})) for x in (a, b)]
        i, пояснение = modem._выбрать_равноценный(равные)
        self.assertEqual(1, i)
        self.assertIn("открываются сразу", пояснение)

