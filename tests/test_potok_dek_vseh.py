@unittest.skipUnless(shutil.which("node"), "нужен node")
class ОкноВБраузере(unittest.TestCase):
    ФУНКЦИИ = ["ключИнверсии", "строкаАвтомата", "вариантыДляАвтомата", "описаниеВарианта"]

    def выполнить(self, случаи):
        код = функции_js(self.ФУНКЦИИ, []) + """
const случаи = JSON.parse(require('fs').readFileSync(0, 'utf8'));
process.stdout.write(JSON.stringify(случаи.map((с) => {
    switch (с.что) {
    case 'ключ': return ключИнверсии(с.т);
    case 'строка': return строкаАвтомата(с.в);
    case 'варианты': return вариантыДляАвтомата(с.л);
    case 'описание': return описаниеВарианта(с.в, с.р);
    default: return null;
    }
})));
"""
        готово = subprocess.run(["node", "-e", код], input=json.dumps(случаи), capture_output=True, text=True, timeout=60)
        self.assertEqual(0, готово.returncode, готово.stderr)
        return json.loads(готово.stdout)

    def test_ключ_как_группа_на_сервере(self):
        случай = random.Random(2)
        таблицы = ["23104576", "45762310", "01326754", "10", "0123", "3210"]
        for M in (2, 4, 8, 16, 32):
            for _ in range(5):
                т = list(range(M))
                случай.shuffle(т)
                таблицы.append(мд.запись(т))
        таблицы += ["", "x1", "0 1 2 -3"]
        итоги = self.выполнить([{"что": "ключ", "т": т} for т in таблицы])
        for т, к in zip(таблицы, итоги, strict=True):
            if т in ("", "x1", "0 1 2 -3"):
                self.assertEqual(т, к)
                continue
            метки = [int(x) for x in (т.split() if " " in т else т)]
            if len(метки) > 16:
                self.assertEqual(т, к)
            else:
                self.assertEqual(min(мд.запись(x) for x in мд.по_инверсии(метки)), к, т)
        # Вся группа ⊕ c — один ключ.
        self.assertEqual(1, len(set(self.выполнить([{"что": "ключ", "т": мд.запись(x)} for x in мд.по_инверсии(ИСТИННАЯ)]))))

