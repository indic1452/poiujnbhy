# -*- coding: utf-8 -*-
"""E1 по G.704: сверхцикл CRC-4 — выравнивание по MFAS и проверка CRC-4.

Поток собирается здесь же, заново, по описанию структуры (G.704, п. 2.3.3) —
сверено с открытой реализацией кадрирования E1 no2e1 (osmocom icE1usb:
e1_tx_framer.v, e1_crc4.v):

- сверхцикл — 16 циклов, два подсверхцикла по 8;
- КИ0 чётных циклов: C + FAS 0011011, биты C1…C4 — в циклах 0, 2, 4, 6
  подсверхцикла; КИ0 нечётных: Si, 1, A, Sa4…Sa8;
- биты Si нечётных циклов 1, 3, 5, 7, 9, 11 — MFAS 001011, циклов 13 и 15 —
  биты E (0 — удалённая сторона приняла подсверхцикл с ошибкой CRC);
- CRC-4: x⁴ + x + 1, начальное 0, по 2048 битам подсверхцикла, где биты C
  заменены нулями; остаток передаётся в битах C СЛЕДУЮЩЕГО подсверхцикла,
  C1 — старший бит.

CRC здесь считается побитным регистром (как в кадрирователе), а не матрицей
вкладов, как в анализаторе: совпадение проверяет разметку, а не повторяет её.
"""

import unittest

import numpy as np

import _bootstrap  # noqa: F401
from reportgen.potok import cikl

FAS = [0, 0, 1, 1, 0, 1, 1]
MFAS = [0, 0, 1, 0, 1, 1]


def crc4_побитно(биты):
    """Регистр CRC-4: вход складывается со старшим битом, при единице — xor 0011."""
    r = 0
    for б in биты:
        обратная = ((r >> 3) & 1) ^ int(б)
        r = ((r << 1) & 0xF) ^ (0b0011 if обратная else 0)
    return [(r >> 3) & 1, (r >> 2) & 1, (r >> 1) & 1, r & 1]


def e1_crc4(сверхциклов, *, сид=7, e=None, a=0, sa=None):
    """Биты потока E1 со сверхциклом CRC-4 (в порядке передачи), по 256 бит на цикл.

    ``e`` — функция (номер сверхцикла, 0 или 1) → бит E; по умолчанию 1 (ошибок нет).
    ``a`` — бит A (или функция номера цикла → бит), ``sa`` — функция номера цикла → биты
    Sa4…Sa8; по умолчанию — единицы.
    """
    rng = np.random.default_rng(сид)
    циклов = 16 * сверхциклов
    кадры = rng.integers(0, 2, (циклов, 256)).astype(np.uint8)
    c = [1, 1, 1, 1]                           # до первого расчёта — единицы
    for п in range(2 * сверхциклов):          # подсверхцикл: циклы 8п … 8п + 7
        for f in range(8):
            g = 8 * п + f
            if f % 2 == 0:
                кадры[g, :8] = [c[f // 2]] + FAS
            else:
                j = (g % 16) // 2               # нечётные циклы 1, 3, …, 15 → 0 … 7
                si = MFAS[j] if j < 6 else (e(g // 16, j - 6) if e else 1)
                бит_a = a(g) if callable(a) else a
                кадры[g, :8] = [si, 1, бит_a] + list(sa(g) if sa else [1, 1, 1, 1, 1])
        подсверхцикл = кадры[8 * п:8 * п + 8].copy()
        подсверхцикл[0::2, 0] = 0               # биты C при расчёте — нули
        c = crc4_побитно(подсверхцикл.reshape(-1))
    return кадры.reshape(-1)


class СверхциклCrc4(unittest.TestCase):
    def test_выравнивание_и_crc_сходятся(self):
        """Поток начат с середины сверхцикла и не с начала КИ0: MFAS находится, CRC сходится везде."""
        поток = e1_crc4(200)
        сдвиг = 5 * 256 + 3
        найдено = cikl.e1(np.concatenate([np.ones(77, np.uint8), поток[сдвиг:]]))
        self.assertIsNotNone(найдено)
        self.assertIn("CRC-4", найдено.что)
        self.assertEqual(найдено.свойства["crc4"], 1.0)
        self.assertEqual(найдено.свойства["mfas"], 1.0)
        текст = "\n".join(найдено.подробно)
        self.assertIn("MFAS 001011", текст)
        self.assertIn("CRC-4 (x⁴ + x + 1) сошлась во всех", текст)
        # Начало сверхцикла: первый полный сверхцикл — с цикла 16 исходного потока, т. е.
        # с цикла 11 обрезанного; цикл 11 — это бит 77 + 11·256 − 3 выборки.
        self.assertEqual(найдено.свойства["начало_сверхцикла"], 77 + 11 * 256 - 3)

    def test_ошибки_линии_видны_по_crc(self):
        """Ошибки 1e-4: доля подсверхциклов с ошибкой CRC ≈ 1 − (1 − p)^2048 ≈ 18 %."""
        поток = e1_crc4(400, сид=8)
        rng = np.random.default_rng(9)
        поток = поток ^ (rng.random(len(поток)) < 1e-4).astype(np.uint8)
        найдено = cikl.e1(поток)
        доля = найдено.свойства["crc4"]
        self.assertGreater(доля, 0.7)
        self.assertLess(доля, 0.92)
        оценка = найдено.свойства["ошибок_в_линии"]
        self.assertGreater(оценка, 0.5e-4)
        self.assertLess(оценка, 2e-4)
        self.assertTrue(any("ошибок в линии — около" in п for п in найдено.подробно))

    def test_оценка_ошибок_по_доле(self):
        """По одной ошибке в каждом десятом подсверхцикле: CRC-4 видит каждую, и оценка ошибок —
        p = −ln(доля сошедшихся) / 2048."""
        поток = e1_crc4(100, сид=15).reshape(-1, 256)
        for п in range(1, 200, 10):
            поток[8 * п + 3, 100] ^= 1                  # КИ12 цикла 3 подсверхцикла п
        найдено = cikl.e1(поток.reshape(-1))
        всего = найдено.свойства["подсверхциклов"]
        доля = (всего - 20) / всего
        self.assertAlmostEqual(найдено.свойства["crc4"], доля)
        self.assertAlmostEqual(найдено.свойства["ошибок_в_линии"], -np.log(доля) / 2048)

    def test_si_своего_назначения(self):
        """Биты Si заняты национальным использованием (случайны): MFAS нет — и CRC-4 не проверяется."""
        поток = e1_crc4(100, сид=16).reshape(-1, 256)
        поток[:, 0] = np.random.default_rng(17).integers(0, 2, len(поток))
        найдено = cikl.e1(поток.reshape(-1))
        self.assertNotIn("crc4", найдено.свойства)
        self.assertFalse(any("CRC-4" in п for п in найдено.подробно))

    def test_mfas_целиком(self):
        """MFAS — все шесть бит: узор 001010 (последний бит не тот) сверхциклом CRC-4 не считается."""
        поток = e1_crc4(100, сид=18).reshape(-1, 256)
        for g in range(11, len(поток), 16):
            поток[g, 0] = 0                            # цикл 11 сверхцикла: 1 → 0
        найдено = cikl.e1(поток.reshape(-1))
        self.assertNotIn("crc4", найдено.свойства)

    def test_бит_a_и_биты_sa(self):
        """Бит A = 1 в каждом десятом цикле без FAS, Sa4 занят (единиц ~70 %), Sa5–Sa8 — единицы."""
        rng = np.random.default_rng(20)
        поток = e1_crc4(100, сид=19, a=lambda g: int(g // 2 % 10 == 0),
                        sa=lambda g: [int(rng.random() < 0.7), 1, 1, 1, 1])
        найдено = cikl.e1(поток)
        текст = "\n".join(найдено.подробно)
        self.assertIn("бит A (удалённая авария) = 1 в 10.0 % циклов без FAS", текст)
        self.assertIn("Sa4 меняется", текст)
        self.assertIn("Sa5 = 1, Sa6 = 1, Sa7 = 1, Sa8 = 1 — занятые Sa: канал данных или SSM", текст)
        self.assertEqual(найдено.свойства["crc4"], 1.0)
        чистый = cikl.e1(e1_crc4(100, сид=19))
        текст = "\n".join(чистый.подробно)
        self.assertIn("бит A (удалённая авария) — 0 во всех циклах", текст)
        self.assertIn("биты Sa4–Sa8: Sa4 = 1, Sa5 = 1, Sa6 = 1, Sa7 = 1, Sa8 = 1", текст)
        self.assertNotIn("занятые Sa", текст)

    def test_испорченные_биты_c(self):
        """Бит C1 испорчен в трёх подсверхциклах — ровно у трёх расчётов CRC нет совпадения."""
        поток = e1_crc4(100, сид=10).reshape(-1, 256)
        for п in (7, 40, 91):
            поток[8 * п, 0] ^= 1
        найдено = cikl.e1(поток.reshape(-1))
        всего = найдено.свойства["подсверхциклов"]
        self.assertAlmostEqual(найдено.свойства["crc4"], (всего - 3) / всего)

    def test_биты_e(self):
        """E = 0 в каждом десятом сверхцикле (второй подсверхцикл): видно в отчёте."""
        поток = e1_crc4(200, сид=11, e=lambda м, i: 0 if (м % 10 == 0 and i == 1) else 1)
        найдено = cikl.e1(поток)
        self.assertEqual(найдено.свойства["crc4"], 1.0)
        текст = "\n".join(найдено.подробно)
        self.assertIn("биты E", текст)
        self.assertIn("нули в 5.0 %", текст)

    def test_без_crc4(self):
        """Si = 1 во всех циклах — сверхцикла CRC-4 нет, и CRC не проверяется."""
        поток = e1_crc4(100, сид=12).reshape(-1, 256)
        поток[:, 0] = 1
        найдено = cikl.e1(поток.reshape(-1))
        self.assertIsNotNone(найдено)
        self.assertNotIn("CRC-4", найдено.что)
        self.assertNotIn("crc4", найдено.свойства)
        self.assertTrue(any("биты Si — единицы в 100.0 % циклов" in п for п in найдено.подробно))

    def test_crc_другого_многочлена_не_сходится(self):
        """Биты C посчитаны с x⁴ + x³ + 1 — MFAS есть, а CRC-4 G.704 не сходится: так и сказано."""
        поток = e1_crc4(100, сид=13).reshape(-1, 256)
        c = [1, 1, 1, 1]
        for п in range(len(поток) // 8):
            поток[8 * п:8 * п + 8:2, 0] = c
            подсверхцикл = поток[8 * п:8 * п + 8].copy()
            подсверхцикл[0::2, 0] = 0
            r = 0
            for б in подсверхцикл.reshape(-1):
                обратная = ((r >> 3) & 1) ^ int(б)
                r = ((r << 1) & 0xF) ^ (0b1001 if обратная else 0)
            c = [(r >> 3) & 1, (r >> 2) & 1, (r >> 1) & 1, r & 1]
        найдено = cikl.e1(поток.reshape(-1))
        self.assertEqual(найдено.свойства["mfas"], 1.0)
        self.assertLess(найдено.свойства["crc4"], 0.2)
        self.assertNotIn("CRC-4", найдено.что)
        self.assertTrue(any("CRC-4 не сошлась" in п for п in найдено.подробно))

    def test_матрица_вкладов_как_регистр(self):
        """Матрица вкладов анализатора даёт тот же остаток, что и побитный регистр."""
        rng = np.random.default_rng(14)
        for _ in range(20):
            биты = rng.integers(0, 2, 2048).astype(np.uint8)
            self.assertEqual(cikl.crc4(биты[None, :]).tolist()[0], crc4_побитно(биты))


if __name__ == "__main__":
    unittest.main()
