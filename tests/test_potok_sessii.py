class ПолеКадровTests(unittest.TestCase):
    """Поле кадра любой ширины в битах (таблица кадров): значения, отбор по битам, поиск своего значения."""

    def setUp(self):
        g = np.random.default_rng(41)
        self.период, self.сдвиг = 45, 7
        self.б = g.integers(0, 2, 45 * 300 + 7 + 20, dtype=np.uint8)
        # Счётчик 6 бит с бита 10 и постоянный флаг в бите 40.
        for r in range(300):
            s = self.сдвиг + r * 45
            self.б[s + 10:s + 16] = [int(c) for c in format(r % 64, "06b")]
            self.б[s + 40] = 1
        self.строки = self.б[7:7 + 300 * 45].reshape(300, 45)

    def поле(self, от, ширина, младшим=False):
        return [int("".join(map(str, (р[от:от + ширина][::-1] if младшим else р[от:от + ширина]))), 2) for р in self.строки]

    def test_значения_поля_как_перебор(self):
        строки = rastr.строки_бит(self.б, self.период, self.сдвиг)
        self.assertEqual((300, 45), строки.shape)
        self.assertEqual((0, 45), rastr.строки_бит(self.б[:40], 45, 0).shape)
        self.assertEqual((1, 8), rastr.строки_бит(self.б[:9], 3, 1).shape)     # период не меньше 8
        for от, ширина, младшим in ((0, 1, False), (10, 6, False), (3, 13, True), (0, 45, False), (44, 1, True), (5, 40, True)):
            with self.subTest(от=от, ширина=ширина, младшим=младшим):
                self.assertEqual(self.поле(от, ширина, младшим), rastr.значения_поля(строки, от, ширина, младшим).tolist())
        длинное = np.ones((2, 70), dtype=np.uint8)
        self.assertEqual([2 ** 64 - 1] * 2, rastr.значения_поля(длинное, 6, 64).tolist())
        for от, ширина in ((-1, 3), (0, 0), (0, 65), (40, 6), (45, 1)):
            with self.subTest(от=от, ширина=ширина), self.assertRaises(ValueError):
                rastr.значения_поля(строки, от, ширина)

    def test_статистика_поля(self):
        с = rastr.поле_кадров(self.б, 45, 7, 10, 6, искать=5)
        self.assertEqual((300, 300, 64, 10, 6, False), (с["всего"], с["отобрано"], с["различных"], с["бит"], с["ширина"], с["младшим"]))
        self.assertEqual(1.0, с["счётчик"])
        self.assertEqual({"значение": 1, "доля": 1.0}, с["шаг"])
        self.assertEqual(["счётчик: +1 у 100 % соседних кадров"], с["вывод"])
        self.assertEqual({"значение": "5", "число": 5, "доля": round(5 / 300, 5), "кадры": [5, 69, 133, 197, 261]}, с["искомое"])
        self.assertEqual(6.0, с["наибольшая_энтропия"])
        self.assertAlmostEqual(-sum(н / 300 * np.log2(н / 300) for н in np.unique(self.поле(10, 6), return_counts=True)[1]), с["энтропия"], 3)
        # Значения — чаще выше, при равенстве — по значению; доли; не больше предела.
        self.assertEqual([str(з) for з in range(64)][:44], [з["значение"] for з in с["значения"]][:44])
        self.assertEqual((5, round(5 / 300, 5)), (с["значения"][0]["число"], с["значения"][0]["доля"]))
        доли = [round(float(д), 3) for д in self.строки[:, 10:16].mean(axis=0)]
        self.assertEqual(доли, с["доля_единиц"])
        self.assertEqual(доли[::-1], rastr.поле_кадров(self.б, 45, 7, 10, 6, младшим=True)["доля_единиц"])
        флаг = rastr.поле_кадров(self.б, 45, 7, 40, 1)
        self.assertEqual((["постоянное поле: 1"], 1, 0.0), (флаг["вывод"], флаг["различных"], флаг["энтропия"]))
        # Поиск значения за пределами ширины — по младшим битам; несуществующее — ноль кадров.
        self.assertEqual(5, rastr.поле_кадров(self.б, 45, 7, 10, 6, искать=64 + 5)["искомое"]["число"])
        self.assertEqual(0, rastr.поле_кадров(self.б, 45, 7, 40, 1, искать=0)["искомое"]["число"])
        # Отбор по полю бит и по байту вместе; «не».
        отбор = [{"бит": 10, "ширина": 6, "значение": 3}, {"бит": 40, "ширина": 1, "значение": 1}]
        с = rastr.поле_кадров(self.б, 45, 7, 10, 6, отбор)
        self.assertEqual((5, ["постоянное поле: 3"]), (с["отобрано"], с["вывод"]))
        кроме = rastr.поле_кадров(self.б, 45, 7, 10, 6, [{"бит": 10, "ширина": 6, "значение": 3, "не": True}])
        self.assertEqual(295, кроме["отобрано"])
        пусто = rastr.поле_кадров(self.б, 45, 7, 10, 6, [{"бит": 40, "ширина": 1, "значение": 0}])
        self.assertEqual({"всего": 300, "отобрано": 0, "бит": 10, "ширина": 6, "младшим": False, "различных": 0, "значения": [],
                          "вывод": ["нет кадров"]}, пусто)
        с = rastr.поле_кадров(self.б, 45, 7, 10, 6, [{"бит": 10, "ширина": 6, "значение": 3, "младшим": True}])
        self.assertEqual(self.поле(10, 6, True).count(3), с["отобрано"])

    def test_выводы_и_предел_значений(self):
        g = np.random.default_rng(42)
        б = g.integers(0, 2, 64 * 5000, dtype=np.uint8)
        случайное = rastr.поле_кадров(б, 64, 0, 0, 16)
        self.assertEqual(["похоже на случайные данные (шифр, сжатие, скремблер)"], случайное["вывод"])
        self.assertEqual((rastr.ЗНАЧЕНИЙ_ПОЛЯ_ДО, rastr.ЗНАЧЕНИЙ_ПОЛЯ_ДО), (len(случайное["значения"]), случайное["показано"]))
        self.assertGreater(случайное["различных"], rastr.ЗНАЧЕНИЙ_ПОЛЯ_ДО)
        # Шаг 3 по модулю 2^ширины; поле типа — мало значений.
        for r in range(5000):
            б[r * 64:r * 64 + 8] = [int(c) for c in format(3 * r % 256, "08b")]
            б[r * 64 + 8:r * 64 + 10] = [int(c) for c in format(r % 3, "02b")]
        шаг = rastr.поле_кадров(б, 64, 0, 0, 8)
        self.assertEqual((["растёт с шагом 3 у 100 % соседних кадров"], {"значение": 3, "доля": 1.0}), (шаг["вывод"], шаг["шаг"]))
        тип = rastr.поле_кадров(б, 64, 0, 8, 2)
        self.assertIn("поле типа: 3 значений", тип["вывод"])
        одно = rastr.поле_кадров(б[:64], 64, 0, 0, 8)
        self.assertEqual((0.0, 0, 0.0), (одно["наибольшая_энтропия"], одно["шаг"]["доля"], одно["счётчик"]))

    def test_таблица_и_столбец_с_отбором_по_битам(self):
        отбор = [{"бит": 10, "ширина": 6, "значение": 7}]
        т = rastr.кадры_таблицей(self.б, 45, 7, 0, 10, отбор)
        self.assertEqual((300, 5, [7, 71, 135, 199, 263]), (т["всего"], т["отобрано"], т["номера"]))
        с = rastr.столбец_кадров(self.б, 45, 7, 1, 1, отбор)
        self.assertEqual(5, с["есть"])
        with self.assertRaises(ValueError):
            rastr.отбор_кадров(np.zeros((3, 6), np.uint8), отбор)


