            строк = int(g.integers(1, (n - сдвиг) // W + 1))
            разность = bool(g.integers(0, 2))
            ряды = биты[сдвиг:сдвиг + строк * W].reshape(строк, W).astype(int)
            if разность:
                ряды = np.vstack([ряды[:1], ряды[1:] ^ ряды[:-1]])
            случаи.append({"что": "веса", "байты": байты.tolist(), "W": W, "сдвиг": сдвиг, "n": n, "строк": строк, "разность": разность})
            ждём.append([ряды.sum(axis=0).tolist(), [строк] * W])
