    def test_пики_автокорреляции_по_весу(self):
        # Независимый расчёт: местные максимумы выше 3σ (лаг ≥ 2), по весу r/σ; ближе 2 лагов к сильнейшему — сливаются;
        # «кратен» — наименьший найденный пик не короче 8 и не слабее половины веса, которому лаг кратен с точностью ±1.
        def пики(r, шум, наибольше=50):
            σ = шум if шум > 0 else 1e-9
            все = [(к, r[к]) for к in range(2, len(r))
                   if r[к] > 3 * σ and r[к] >= r[к - 1] and r[к] > (r[к + 1] if к + 1 < len(r) else -np.inf)]
            все.sort(key=lambda п: (-п[1] / σ, п[0]))
            итог = []
            for к, v in все:
                if len(итог) >= наибольше:
                    break
                if all(abs(к - о[0]) > 2 for о in итог):
                    итог.append((к, v))
            out = []
            for к, v in итог:
                основы = [о for о, w in итог if 8 <= о < к and w >= 0.5 * v and round(к / о) >= 2 and abs(к - round(к / о) * о) <= 1]
                out.append({"лаг": к, "r": v, "вес": v / σ, "кратен": min(основы) if основы else 0})
            return out

        # Синтетика: цикл 2964 (вес 40σ) с кратными, тесный кластер у 700 (699, 700, 701 — сливаются в 700),
        # пик ровно на 3σ (не пик) и чуть выше (пик), конец ряда.
        шум = 0.01
        r = np.random.default_rng(5).normal(0, шум * 0.3, 8193)
        r[0] = 1.0
        for к, v in ((2964, 0.40), (5928, 0.33), (5929, 0.20), (1482, 0.05), (699, 0.12), (700, 0.15), (701, 0.14),
                     (100, 0.03), (150, 0.0301), (8192, 0.2), (2, 0.5), (750, 0.06), (1501, 0.12), (40, 0.1), (400, 0.04)):
            r[к] = v
        r = [round(float(x), 4) for x in r]
        итог = self.выполнить([{"что": "пики", "r": r, "шум": шум}, {"что": "пики", "r": r, "шум": шум, "наибольше": 3},
                               {"что": "пики", "r": [1.0, 0.0, 0.0], "шум": 0.0}])
        ждём = пики(r, шум)
        self.assertEqual([(п["лаг"], п["кратен"]) for п in ждём], [(п["лаг"], п["кратен"]) for п in итог[0]])
        for а, б in zip(ждём, итог[0], strict=True):
            self.assertAlmostEqual(а["вес"], б["вес"], places=9)
        self.assertEqual([2, 2964, 5928], [п["лаг"] for п in итог[0][:3]])            # сильнейшие первыми
        # 2964 не кратен ни слабому 1482, ни короткому 2; 5928 — кратен 2964; 1501 — кратен 750 (вес ровно половина,
        # с точностью ±1); 400 — кратен 40 (сильнее), а 40 — ничему.
        кр = {п["лаг"]: п["кратен"] for п in итог[0]}
        self.assertEqual((0, 0, 2964, 0, 750, 40, 0), (кр[2964], кр[1482], кр[5928], кр[700], кр[1501], кр[400], кр[40]))
        self.assertNotIn(5929, [п["лаг"] for п in итог[0]])                              # соседний с 5928 — слит
        self.assertNotIn(699, [п["лаг"] for п in итог[0]])
        self.assertNotIn(100, [п["лаг"] for п in итог[0]])                               # 3σ ровно — не пик
        self.assertIn(150, [п["лаг"] for п in итог[0]])
        self.assertIn(8192, [п["лаг"] for п in итог[0]])                                 # последний лаг — пик
        self.assertEqual([(п["лаг"], п["кратен"]) for п in ждём[:3]], [(п["лаг"], п["кратен"]) for п in итог[1]])  # «наибольше»
        self.assertEqual([], итог[2])
        # Границы правил — каждая отдельным случаем (фон — нули, шум 0,01: 3σ = 0,03).
        def ряд(точки, длина=64):
            р = [0.0] * длина
            р[0] = 1.0
            for к, v in точки.items():
                р[к] = v
            return р

        случаи = {
            "лаг1": ряд({1: 1.0, 10: 0.2}),                                 # лаг 1 — не период
            "плато": ряд({20: 0.2, 21: 0.2}),                               # пик — правый край плато
            "справа_выше": ряд({20: 0.2, 21: 0.3, 22: 0.0}),                 # 20 не пик: справа выше
            "два_через_2": ряд({20: 0.2, 22: 0.19}),                        # ровно 2 лага — сливаются
            "два_через_3": ряд({20: 0.2, 23: 0.19}),                        # 3 лага — два пика
            "равный_вес": ряд({40: 0.2, 20: 0.2}),                          # при равном весе — меньший лаг первым
            "основа_8": ряд({8: 0.3, 24: 0.3}),                             # основа от 8 лагов
            "основа_7": ряд({7: 0.3, 21: 0.3}),                             # 7 — не основа
            "вес_045": ряд({10: 0.045, 20: 0.1}),                           # основа слабее половины — не основа
            "последний": ряд({63: 0.2}),                                    # последний лаг — пик
        }
        по = self.выполнить([{"что": "пики", "r": р, "шум": 0.01} for р in случаи.values()]
                            + [{"что": "пики", "r": ряд({10: 0.5}), "шум": 0.0},
                               {"что": "пики", "r": [1.0] + [0.0, 0.0, 0.5] * 60, "шум": 0.01}])
        лаги = {имя: [(п["лаг"], п["кратен"]) for п in по[i]] for i, имя in enumerate(случаи)}
        self.assertEqual({"лаг1": [(10, 0)], "плато": [(21, 0)], "справа_выше": [(21, 0)], "два_через_2": [(20, 0)],
                          "два_через_3": [(20, 0), (23, 0)], "равный_вес": [(20, 0), (40, 20)], "основа_8": [(8, 0), (24, 8)],
                          "основа_7": [(7, 0), (21, 0)], "вес_045": [(20, 0), (10, 0)], "последний": [(63, 0)]}, лаги)
        self.assertEqual([], по[len(случаи)])                              # без оценки шума — пиков нет
        self.assertEqual(50, len(по[len(случаи) + 1]))                     # не больше 50 по умолчанию
        # Равный вес в допуске — берётся первый по списку (меньший лаг).
        равные = по[5]
        self.assertEqual([20], self.выполнить([{"что": "пикРядом", "пики": равные, "v": [[30, 10]]}])[0])
        # Указатель притягивается к сильнейшему пику в допуске; вне допуска — нет пика.
        сп = итог[0]
        рядом = self.выполнить([{"что": "пикРядом", "пики": сп, "v": [[2960, 5], [2958, 5], [2958, 6], [705, 5], [705, 4], [4000, 50], [5925, 10]]}])[0]
