        код = функции_js(["битМассива", "единицВОтрезке", "битыСтрокой", "пустаяРазметка", "изменитьОтрезки", "слитьОтрезки",
                          "маскаМеток", "итогРазметки", "описатьРазметку", "латиницей"], ["ЕДИНИЦ_В_БАЙТЕ", "ЛАТИНИЦА"])
