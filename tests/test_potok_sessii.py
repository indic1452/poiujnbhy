    @staticmethod
    def байты_с_бита(биты: np.ndarray, i: int, число: int, порядок: str) -> bytes:
        куски = []
        for j in range(число):
            кусок = биты[i + 8 * j:i + 8 * j + 8]
            if len(кусок) < 8:
                break
            куски.append(int(np.packbits(кусок[::-1] if порядок == "младший" else кусок)[0]))
        return bytes(куски)

    def ждём_инспектор(self, байты: np.ndarray, i: int, n: int, w: int, порядок: str) -> dict:
        import struct  # noqa: PLC0415
        биты = np.unpackbits(байты)[:n]
        б = self.байты_с_бита(биты, i, 8, порядок)
        итог = {"Байт (двоично)": format(б[0], "08b") if б else "—",
                "HEX (8 байт)": " ".join(f"{v:02X}" for v in б) if б else "—",
                "uint8": str(б[0]) if б else "—", "int8": str(struct.unpack("b", б[:1])[0]) if б else "—"}
        for имя, код, к in (("uint16", "H", 2), ("int16", "h", 2), ("uint32", "I", 4), ("int32", "i", 4),
                            ("uint64", "Q", 8), ("int64", "q", 8)):
            for порядок_байт, знак in (("BE", ">"), ("LE", "<")):
                итог[f"{имя} {порядок_байт}"] = str(struct.unpack(знак + код, б[:к])[0]) if len(б) >= к else "—"
        for имя, код, к in (("float32", "f", 4), ("float64", "d", 8)):
            for порядок_байт, знак in (("BE", ">"), ("LE", "<")):
                итог[f"{имя} {порядок_байт}"] = struct.unpack(знак + код, б[:к])[0] if len(б) >= к else "—"
        if len(б) >= 4:
            цифры = [ц for v in б[:4] for ц in (v >> 4, v & 15)]
            итог["BCD (4 байта)"] = "".join(map(str, цифры)) if max(цифры) <= 9 else "не BCD"
        else:
            итог["BCD (4 байта)"] = "—"
        if б:
            g, v = б[0], б[0]
            while g:
                g >>= 1
                v ^= g
            обратный = int(format(б[0], "08b")[::-1], 2)
            итог["Грей → двоичный (байт)"] = str(v)
            итог["Байт наоборот"] = f"0x{обратный:02X} = {обратный}"
            с = б[0]
            итог["Символ CP1251"] = (bytes([с]).decode("cp1251") if 32 <= с < 128 or с >= 0xC0 or с in (0xA8, 0xB8) else "·")
        else:
            итог.update({"Грей → двоичный (байт)": "—", "Байт наоборот": "—", "Символ CP1251": "—"})
        ш = max(1, min(64, w))
        for имя, прямо in ((f"Поле {ш} бит", True), (f"Поле {ш} бит, младшим вперёд", False)):
            if i + ш > n:
                итог[имя] = "—"
                continue
            строка = "".join(str(int(x)) for x in биты[i:i + ш])
            v = int(строка if прямо else строка[::-1], 2)
            со_знаком = v - (1 << ш) if v >= 1 << (ш - 1) else v
            итог[имя] = f"{v} (0x{v:0{(ш + 3) // 4}X}, со знаком {со_знаком})"
        return итог

    def test_инспектор_как_struct(self):
        g = np.random.default_rng(31)
        случаи, ждём = [], []
        for _ in range(120):
            байты = g.integers(0, 256, int(g.integers(1, 20)), dtype=np.uint8)
            n = len(байты) * 8 - int(g.integers(0, 8))
            i = int(g.integers(0, n))
            w, порядок = int(g.integers(1, 70)), ["старший", "младший"][int(g.integers(0, 2))]
            случаи.append({"что": "инспектор", "байты": байты.tolist(), "i": i, "n": n, "w": w, "порядок": порядок})
            ждём.append(self.ждём_инспектор(байты, i, n, w, порядок))
        # Особые float: ±∞, не число, отрицательный ноль; BCD и не BCD; поле 64 бит.
        for hexs in ("7F800000 00000000", "FF800000 00000000", "7FC00000 00000000", "80000000 00000000",
                     "12345678 90123456", "3FF00000 00000000", "FFFFFFFF FFFFFFFF", "00000000 00000001"):
            байты = np.frombuffer(bytes.fromhex(hexs.replace(" ", "")), dtype=np.uint8)
            случаи.append({"что": "инспектор", "байты": байты.tolist(), "i": 0, "n": 64, "w": 64, "порядок": "старший"})
            ждём.append(self.ждём_инспектор(байты, 0, 64, 64, "старший"))
        for получено, надо, случай in zip(self.выполнить(случаи), ждём, случаи, strict=True):
            получено = dict(получено)
            with self.subTest(случай=случай):
                self.assertEqual(list(надо), list(получено))
                for ключ, значение in надо.items():
                    if isinstance(значение, float):
                        текст = получено[ключ]
                        if значение != значение:
                            self.assertEqual("не число", текст)
                        elif значение in (float("inf"), float("-inf")):
                            self.assertEqual("+∞" if значение > 0 else "-∞", текст)
                        elif ключ.startswith("float64"):
                            self.assertEqual(значение, float(текст.replace(",", ".")), ключ)
                        else:
                            # float32 — девять значащих цифр: этого хватает, чтобы число вернулось точно.
                            self.assertEqual(np.float32(значение), np.float32(float(текст.replace(",", "."))), ключ)
                            self.assertLessEqual(len(текст.replace(",", "").replace("-", "").split("e")[0].strip("0")), 9)
                    else:
                        self.assertEqual(значение, получено[ключ], ключ)

