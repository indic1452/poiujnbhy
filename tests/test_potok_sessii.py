    def test_начальная_установка(self):
        g = np.random.default_rng(4)
        псп = skrembler.псп((14, 15), np.ones(15, dtype=np.uint8), 1 << 16)
        данные = g.integers(0, 2, 1 << 16, dtype=np.uint8)
        данные[:3000] = 0
        w = данные ^ псп
        уст = skrembler.начальная_установка(w, (14, 15))
        self.assertEqual(("паузы", "нули", True), (уст["способ"], уст["заполнение"], уст["уверенно"]))
        место = уст["место"]
        self.assertEqual("".join(str(int(б)) for б in псп[место:место + 15]), уст["регистр"])
        # На первом бите — состояние, от которого ПСП и шла; слой снимает её со всего потока.
        self.assertEqual("1" * 15, уст["в_начале"])
        self.assertEqual(f"аддитивный отводы 14,15 начальное {уст['регистр']} с бита {место}", уст["слой"])
        self.assertTrue(np.array_equal(данные, снять_вручную(w, уст["слой"])[0]))
        self.assertEqual("".join(str(int(б)) for б in w[:15]), уст["самосинхр"])
        # Флаги HDLC в паузе — регистр за вычетом заполнения.
        флаги = np.resize(np.array([0, 1, 1, 1, 1, 1, 1, 0], dtype=np.uint8), 1 << 16)
        флаги[20_000:] = g.integers(0, 2, (1 << 16) - 20_000)
        уст = skrembler.начальная_установка(флаги ^ псп, (14, 15))
        self.assertTrue(уст["заполнение"].startswith("флаги HDLC"))
        self.assertEqual("".join(str(int(б)) for б in псп[уст["место"]:уст["место"] + 15]), уст["регистр"])

    def test_короткая_пауза_и_без_опоры(self):
        g = np.random.default_rng(7)
        отводы = (2, 3, 9, 12)
        псп = skrembler.псп(отводы, np.array([1, 0, 1, 1, 0, 0, 1, 0, 1, 1, 1, 0], np.uint8), 1 << 16)
        # Данные — текст (структура есть), нулей подряд всего 60 бит — пауза короче ОКНО_БМ.
        данные = np.unpackbits(np.frombuffer((b"The quick brown fox jumps over the lazy dog. " * 2000)[:1 << 13], np.uint8))
        данные[30_000:30_060] = 0
        уст = skrembler.начальная_установка(данные ^ псп, отводы)
        self.assertEqual(("короткая пауза", "нули", True), (уст["способ"], уст["заполнение"], уст["уверенно"]), уст)
        self.assertGreaterEqual(уст["пауза"], skrembler.КОРОТКАЯ_ПАУЗА)
        self.assertLess(уст["пауза"], skrembler.ОКНО_БМ)
        self.assertEqual("101100101110", уст["в_начале"])
        self.assertTrue(уст["слой"].startswith("аддитивный отводы 2,3,9,12 начальное "))
        self.assertTrue(np.array_equal(данные, снять_вручную(данные ^ псп, уст["слой"])[0]))
        # Опоры нет (случайные данные): установка всё равно есть — с первого бита, неуверенно.
        случайные = g.integers(0, 2, 1 << 16, dtype=np.uint8)
        уст = skrembler.начальная_установка(случайные, (14, 15))
        self.assertEqual(("начало", 0, False), (уст["способ"], уст["место"], уст["уверенно"]))
        self.assertEqual("".join(str(int(б)) for б in случайные[:15]), уст["регистр"])
        self.assertEqual("опоры нет — данные в начале считаются нулями", уст["заполнение"])
        self.assertEqual("аддитивный отводы 14,15 начальное " + уст["регистр"] + " с бита 0", уст["слой"])
        # Поток начинается нулями (преамбула без скремблера): нулевой регистр не берётся — ни как
        # «пауза», ни как «начало»; опора — с первого ненулевого бита.
        с_нулями = случайные.copy()
        с_нулями[:5000] = 0
        с_нулями[5000] = 1
        уст = skrembler.начальная_установка(с_нулями, (14, 15))
        self.assertEqual(("начало", 5000), (уст["способ"], уст["место"]), уст)
        self.assertEqual("1" + "".join(map(str, с_нулями[5001:5015])), уст["регистр"])
        self.assertNotEqual("0" * 15, уст["регистр"])
        # Весь поток — нули: регистр с первого бита (другого нет), неуверенно.
        уст = skrembler.начальная_установка(np.zeros(1 << 13, np.uint8), (14, 15))
        self.assertEqual(("начало", 0, "0" * 15, False), (уст["способ"], уст["место"], уст["регистр"], уст["уверенно"]))
        # Нулевой участок в начале потока с паузой из нулей дальше — опора — пауза, а не нулевой участок.
        данные = g.integers(0, 2, 1 << 16, dtype=np.uint8)
        данные[40_000:40_600] = 0
        поток = данные ^ skrembler.псп((14, 15), np.ones(15, np.uint8), 1 << 16)
        поток[:3000] = 0
        уст = skrembler.начальная_установка(поток, (14, 15))
        self.assertEqual(("паузы", "нули"), (уст["способ"], уст["заполнение"]), уст)
        self.assertGreaterEqual(уст["место"], 40_000 - 15)

