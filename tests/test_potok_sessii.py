        self.assertEqual([{"период": 256, "сдвиг": 3, "ширина": 1, "от": 0, "до": 0}], р["правила"])
        self.assertEqual({"отрезки": [], "правила": [], "закладки": []}, rastr.проверить_разметку({}))
