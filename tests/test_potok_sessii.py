    def test_веса_столбцов(self):
        g = np.random.default_rng(33)
        случаи, ждём = [], []
        for _ in range(40):
            байты = g.integers(0, 256, int(g.integers(1, 80)), dtype=np.uint8)
            биты = np.unpackbits(байты)
            n, W = len(биты), int(g.integers(1, 40))
            if g.integers(0, 2):
                сдвиг = int(g.integers(0, 20))
                начала = list(range(сдвиг, n, W))
                концы = [min(n, s + W) for s in начала]
            else:
                начала = sorted(set(int(x) for x in g.integers(0, n, int(g.integers(1, 12)))))
                концы = [min(n, s + W, начала[r + 1] if r + 1 < len(начала) else n) for r, s in enumerate(начала)]
            разность = bool(g.integers(0, 2))
            единиц, всего = np.zeros(W, int), np.zeros(W, int)
            for r, (н, к) in enumerate(zip(начала, концы, strict=True)):
                for c in range(к - н):
                    бит = int(биты[н + c])
                    if разность and r > 0 and начала[r - 1] + c < концы[r - 1]:
                        бит ^= int(биты[начала[r - 1] + c])
                    единиц[c] += бит
                    всего[c] += 1
            случаи.append({"что": "веса", "байты": байты.tolist(), "W": W, "начала": начала, "концы": концы, "разность": разность})
