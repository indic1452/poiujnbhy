        # Строки по длине, считаются не все (как профиль по началу массива): лишняя строка или строка «−1» дали бы другое.
        for _ in range(30):
            байты = g.integers(0, 256, int(g.integers(4, 60)), dtype=np.uint8)
            биты = np.unpackbits(байты)
