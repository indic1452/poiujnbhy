# ---------- 5. IEEE 802.16 BTC: правило укорочения и таблица OFDM ----------
# [ieee802/C80216a-02_55.pdf, стр. 17]: блок (nx-Ix)(ny-Iy)-B, данных (kx-Ix)(ky-Iy)-B-Q.
def btc(nx, kx, ny, ky, Ix, Iy, B, Q):
    return (nx - Ix) * (ny - Iy) - B, (kx - Ix) * (ky - Iy) - B - Q


