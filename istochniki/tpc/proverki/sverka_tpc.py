# ---------- 1. Порождающие многочлены кодов Хэмминга: два независимых источника ----------
# [ieee802/802161pc-00_35.pdf, стр. 5 (Table 1 «Generators Polynomials of Hamming Codes»)]
многочлены_802161pc_00_35 = {(7, 4): 'x3+x+1', (15, 11): 'x4+x+1', (31, 26): 'x5+x2+1',
                             (63, 57): 'x6+x+1', (127, 120): 'x7+x3+1'}
# [ieee802/C80216a-02_55.pdf, стр. 16 (Table 203 «Hamming code generator polynomials»)]
многочлены_C80216a_02_55 = {(7, 4): 'X3+X1+1', (15, 11): 'X4+X1+1', (31, 26): 'X5+X2+1',
                            (63, 57): 'X6+X+1'}


def разобрать(s):
    """'x5+x2+1' -> целое (бит i = коэффициент при x^i)."""
    v = 0
    for член in s.lower().split('+'):
        член = член.strip()
        if член == '1':
            v |= 1
        elif член == 'x':
            v |= 2
        else:
            v |= 1 << int(член[1:])
    return v


for nk, g in многочлены_C80216a_02_55.items():
    assert разобрать(g) == разобрать(многочлены_802161pc_00_35[nk]), nk


def примитивный(g):
    """Порядок x по модулю g равен 2^m-1 (m = степень g) — тогда код Хэмминга длины 2^m-1."""
    m = g.bit_length() - 1
    x, e = 2, 1
    while x != 1:
        x <<= 1
        if x >> m & 1:
            x ^= g
        e += 1
    return e == (1 << m) - 1


for (n, k), g in многочлены_802161pc_00_35.items():
    gi = разобрать(g)
    assert gi.bit_length() - 1 == n - k and n == (1 << (n - k)) - 1 and примитивный(gi), (n, k)


# ---------- 2. Кодер расширенного Хэмминга (систематический, чётность в конце) ----------
# [802161pc-00_35.pdf, стр. 5–6: данные идут первыми, затем ECC Хэмминга, затем общий бит чётности;
#  Table 203 C80216a-02_55: «an overall even parity check bit is added at the end of each Hamming code word»]
def кодер_расш_хэмминг(g, n, данные):
    r = n - 1 - len(данные)  # проверочных бит Хэмминга
    рег = 0
    for b in данные:  # деление на g (LFSR), старший бит первым
        вых = ((рег >> (r - 1)) & 1) ^ b
        рег = ((рег << 1) & ((1 << r) - 1)) ^ (g & ((1 << r) - 1) if вых else 0)
    проверки = [(рег >> (r - 1 - i)) & 1 for i in range(r)]
    слово = list(данные) + проверки
    return слово + [sum(слово) & 1]


def мин_вес(g, n, k):
    лучший = n
    for d in range(1, 1 << k):
        w = sum(кодер_расш_хэмминг(g, n, [(d >> i) & 1 for i in range(k)]))
        лучший = min(лучший, w)
    return лучший


assert мин_вес(разобрать('x3+x+1'), 8, 4) == 4
assert мин_вес(разобрать('x4+x+1'), 16, 11) == 4

