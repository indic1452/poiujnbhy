# ---------- 4. eTPC AHA4524, Table 1 [aha/dzsc_200902051616359075.pdf (PB4524_0204), стр. 3] ----------
# «In enhanced codes, the Y axis is shortened by one. The shortening and addition of hyper axis
#  is included in the code description.» => (n,k)x(64,62)+ : ось Y = (64,63) без одной строки (63,62)
#  плюс строка гиперчётности => снова 64 строки.
def етпк_2d(nx, kx, ny_четн):
    ky = ny_четн - 1           # код чётности (ny, ny-1)
    строк = ny_четн - 1 + 1    # укорочение на 1 и +1 строка гипердиагонали
    return nx * строк, kx * (ky - 1)


