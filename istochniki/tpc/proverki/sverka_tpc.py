# ---------- 9. Гипердиагональ eTPC: два описания в патенте US7356752 ----------
# [patenty/opis.txt, строки 47–50 (формула (1): «right rotating the ith row by i+1 bits, then adding each column»)
#  и строки 204–208 («1. parity row = 0; 2. rotate right by 1; 3. XOR incoming bits; 4. store; ...
#  once the result for the last row is placed ..., rotated by 1 to the right and output»)]
import random


def повернуть_вправо(v, s):
    s %= len(v)
    return v[-s:] + v[:-s] if s else list(v)


def гипер_по_шагам(строки):
    p = [0] * len(строки[0])
    for r in строки:
        p = повернуть_вправо(p, 1)
        p = [a ^ b for a, b in zip(p, r)]
    return повернуть_вправо(p, 1)


def гипер_по_формуле(строки):
    p = [0] * len(строки[0])
    for i, r in enumerate(строки):
        p = [a ^ b for a, b in zip(p, повернуть_вправо(r, i + 1))]
    return p


random.seed(1)
блок = [[random.randint(0, 1) for _ in range(8)] for _ in range(7)]
# По шагам строка r сдвигается на (R - r); по формуле — на (r + 1): это одно и то же при обратном порядке строк.
assert гипер_по_шагам(блок) == гипер_по_формуле(блок[::-1])
# В общем случае направления различаются => направление диагонали у конкретного модема надо подбирать (оба варианта).
assert гипер_по_шагам(блок) != гипер_по_формуле(блок)
print('гипердиагональ: оба описания патента согласованы с точностью до порядка строк')
print('сверка ТКБ: все проверки прошли')
