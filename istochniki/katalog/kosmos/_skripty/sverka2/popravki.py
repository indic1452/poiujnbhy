    e['проверка'] = 'skripty/sverka2/sverka_a.py: оба G(X) = ∏(X−α^i) (8-кортежи табл.), найдена опечатка в столбце Exponent табл. 6.3.1; уравнения Хэмминга: столбцы H различны, вес ≥2'
    log(e, 'добавлены RS(236,216), уравнения Хэмминга и опечатка табл. 6.3.1 первоисточника')

