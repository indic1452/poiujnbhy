    e['проверка'] += '; сверка-2: разложение многочленов на неприводимые (своим кодом), делимость x^n+1; первоисточник МСЭ-R M.1850-2 (SRI-D = Iridium) — скорости кодов'
    log(e, 'уточнены коды БЧХ (465 — БЧХ(15,7), 3545 = 1207·(x+1)), добавлены скорости из МСЭ-R M.1850-2')

    e = najti(vse, 'S-MIM (Eutelsat')
    e['параметры']['скремблер'] = 'отрезок М-последовательности 1+X^4+X^9, начальная загрузка 101000000, сброс в начале каждого пакета PDCH'
    e['источник'].append(S('istochniki/smim/ts_10272103v010201p.pdf', r'initial loading of the shift register shall be equal to 101000000'))
    log(e, 'добавлено начальное состояние скремблера 101000000')

    e = najti(vse, 'SDR (спутниковое цифровое радио')
    e['параметры']['скремблер (внутр. физ. уровень)'] = 'X^11+X^9+1 (O.153), начальное 11001110001, длина 2064 на CU (TS 102 551-1); многочастотный режим — запись «SDR многочастотный»'
    e['источник'].append(S('istochniki/sdr/ts_10255101v010101p.pdf', r'initial state is set to "11001110001"'))
    log(e, 'уточнён скремблер: многочлен и начальное состояние')

    e = najti(vse, 'NavIC L1 SPS')
    e['параметры']['TOI'] = 'BCH(52,9), dmin=20, g(x)=x^9+x^8+x^7+x^6+x^5+x^4+x^2+x+1 = 1767₈ (не примитивен); 9 бит TOI — начальное состояние 9-разрядного ЛРС, 52 сдвига → 52 символа'
