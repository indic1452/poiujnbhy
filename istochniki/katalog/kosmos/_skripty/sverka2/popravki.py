    e['параметры']['внутренний'] = 'укороченный Хэмминг (12,8): p0=i0⊕i1⊕i3⊕i5⊕i7, p1=i0⊕i2⊕i3⊕i6⊕i7, p2=i0⊕i4⊕i5⊕i6⊕i7, p3=i1⊕i2⊕i3⊕i4⊕i5⊕i6⊕i7 (d=3)'
