    e['проверка'] = 'параметры решётки — текст 413.0-G-3 стр. 40–43 (сверка-2); образцов и второго источника нет'
    e['имя'] = 'CCSDS 401.0-B / 413.0-G: 4D-8PSK TCM 64 состояния (h3=050, h2=024, h1=006, h0=103), 2–2,75 бит/символ'
