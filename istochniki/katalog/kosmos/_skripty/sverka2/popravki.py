KOR = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
ZHURNAL = []


def najti(vse, nachalo):
    r = [e for e in vse if e['имя'].startswith(nachalo)]
    assert len(r) == 1, (nachalo, len(r))
    return r[0]


def log(e, chto):
    ZHURNAL.append({'запись': e['имя'], 'поправка': chto})


