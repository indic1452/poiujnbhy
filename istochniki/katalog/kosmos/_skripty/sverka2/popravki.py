    log(e, 'отмечена опечатка первоисточника в уравнении c(5k+4)')

    e = najti(vse, 'GMR-1 РС(15,9)')
    e['параметры']['порядок бит'] = 'n-кортеж табл. 4.6/4.8 записан X^0 слева; столбец «Decimal» = тот же кортеж, прочитанный как двоичное число старшим слева (≠ числовому значению элемента в обычной записи: α^6 → «0011» → 3, а α^2+α^3 = 12)'
    log(e, 'уточнён смысл столбца Decimal табл. 4.8')

    e = najti(vse, 'Iridium: BCH')
    M1850 = 'istochniki/itu/R-REC-M.1850-2-201409-I.pdf'
    e['параметры']['BCH (десятичные многочлены)'] = ('сообщения 1897 (0x769) = (x^5+x^2+1)(x^5+x^4+x^3+x^2+1) → (31,21); кольцевой вызов 1207 (0x4B7) → (31,21); ACCH 3545 (0xDD9) = 1207·(x+1) → (31,20); '
                                                     'заголовок IBC и LCW1: 29 = (x+1)(x^3+x+1) → (7,3); LCW2: 465 = (x^4+x+1)(x^4+x^3+x^2+x+1) — порождающий БЧХ(15,7) t=2 (в коде комментарий «BCH(13,16)»); LCW3: 41 = x^5+x^3+1 → укороченный (26,21)')
    e['параметры']['скорости свёрточного кода (МСЭ-R M.1850-2, SRI-D, табл. 23)'] = 'TCH-голос 1/3, TCH-данные 1/2, BCCH 1/2, RACH 1/6, SDCCH 1/4; мягкое решение; перемежение внутри пакета (голос) и по 4 пакетам (данные); слот 6 кбит/с, 36 кбит/с на 6 слотов'
