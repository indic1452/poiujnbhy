# SCCC перемежитель: формула и биективность — своя программа
def P(B):
    L = 1 << (B - 1).bit_length(); out = [(89 * i * (i + 1) // 2) % L for i in range(L)]
    return [x for x in out if x < B]
for B in (2112, 552, 4 * 528):
    p = P(B); assert sorted(p) == list(range(B))
