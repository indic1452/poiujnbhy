def podnyat(baza, pod):
    """«0» → [[Pi, −], [−, Pi]]; «1» → [[−, Pi], [Pi, −]]; «−1» (нулевой блок) → нули 2Z×2Z."""
    R, C = len(baza), len(baza[0])
    nov = [[-1] * (2 * C) for _ in range(2 * R)]
    for r in range(R):
        for c in range(C):
            if baza[r][c] < 0:
                assert pod[r][c] == -1, (r, c)
                continue
            assert pod[r][c] in (0, 1), (r, c)
            if pod[r][c] == 0:
                nov[2 * r][2 * c] = nov[2 * r + 1][2 * c + 1] = baza[r][c]
            else:
                nov[2 * r][2 * c + 1] = nov[2 * r + 1][2 * c] = baza[r][c]
    return nov


