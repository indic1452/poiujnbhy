def tablicy_docx(imya):
    """Таблицы docx: ряды клеток (текст клетки; пустая — '')."""
    x = zipfile.ZipFile(os.path.join(ST, imya)).read('word/document.xml').decode()
    itog = []
    for t in re.findall(r'<w:tbl>.*?</w:tbl>', x, re.S):
        ryady = []
        for r in re.findall(r'<w:tr[ >].*?</w:tr>', t, re.S):
            ryady.append([''.join(re.findall(r'<w:t(?: [^>]*)?>([^<]*)</w:t>', c)).strip()
                          for c in re.findall(r'<w:tc>.*?</w:tc>', r, re.S)])
        itog.append(ryady)
    return itog


def tablicy_pptx(imya, slajd):
    z = zipfile.ZipFile(os.path.join(ST, imya))
    x = z.read('ppt/slides/slide%d.xml' % slajd).decode()
    itog = []
    for t in re.findall(r'<a:tbl>.*?</a:tbl>', x, re.S):
        itog.append([[''.join(re.findall(r'<a:t>([^<]*)</a:t>', c)).strip() for c in re.findall(r'<a:tc.*?</a:tc>', r, re.S)]
                     for r in re.findall(r'<a:tr .*?</a:tr>', t, re.S)])
    return itog, ' '.join(re.findall(r'<a:t>([^<]*)</a:t>', x))


def chisla(tablica, pusto=-1):
    return [[int(c) if c not in ('', '-') else pusto for c in r] for r in tablica]


def iz_bazy(baza, z=Z):
    """H по базовой матрице: s ≥ 0 — единичная Z×Z со столбцами, сдвинутыми вправо на s (21.3.8)."""
    R, C = len(baza), len(baza[0])
    H = np.zeros((R * z, C * z), np.uint8)
    for r in range(R):
        for c in range(C):
            s = baza[r][c]
            if s >= 0:
                i = np.arange(z)
                H[r * z + i, c * z + (i + s) % z] ^= 1
    return H


def shest_ciklov(H):
    """Число 6-циклов графа Таннера: по тройкам разных проверок (a, b, c) и разным переменным
    x ∈ N(a)∩N(b), y ∈ N(b)∩N(c), w ∈ N(c)∩N(a): tr(P₀³) − 3·Σ_v (d_v − 2)·Σ_{a≠b∈N(v)} P₀[a,b]
    + 2·Σ_v d_v(d_v − 1)(d_v − 2), делённое на 6 (P₀ = H·Hᵀ без диагонали)."""
    Hi = H.astype(np.int64)
    P = Hi @ Hi.T
    np.fill_diagonal(P, 0)
    sled = int(np.trace(P @ P @ P))
    d = Hi.sum(axis=0)
    popr = 0
    for v in range(H.shape[1]):
        s = np.flatnonzero(Hi[:, v])
        popr += (d[v] - 2) * int(P[np.ix_(s, s)].sum())
    troiki = int((d * (d - 1) * (d - 2)).sum())
    ch = sled - 3 * popr + 2 * troiki
    assert ch % 6 == 0, ch
    return ch // 6


