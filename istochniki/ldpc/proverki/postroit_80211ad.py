"""IEEE 802.11ad (DMG, 60 ГГц) и 802.11ay (EDMG): LDPC 672 (1/2, 5/8, 3/4, 13/16), 7/8 (624) и 1344.

Стандарт IEEE 802.11ad-2012 платный; матрицы — из открытых документов рабочей группы IEEE 802.11
(mentor.ieee.org, скачаны 2026-09-30):

- 11-10/0433r2 «CP specification» (TGad, 05/2010) — текст объединённого предложения, ставший черновиком
  D0.1: п. 21.3.8 «Common LDPC parity matrices», табл. 69–72 (четыре базовые матрицы 16 столбцов,
  Z = 42; пустая клетка — нулевой блок; «Pi … cyclically shifting the columns to the right by i»);
  кодер систематический: c = (b1…bk, p1…p(n−k)), H·cᵀ = 0 (21.5.3.2.2.2, 21.6.3.2.2);
- 11-16/0676r1 (Samsung, TGay, 05/2016), слайды 5–8 — те же четыре матрицы как «11ad base matrix»
  (второй источник, число в число), табл. слайдов 5–8 — матрицы подъёма 1344; слайд 18 — число
  6-циклов графа Таннера L672 (11ad) и L1344 — сверяется подсчётом;
- 11-16/0692r0 (Samsung, TGay) — текст SFD: правило подъёма («0» → [[Pi, −], [−, Pi]], «1» →
  [[−, Pi], [Pi, −]], «−1» → нули) и те же матрицы подъёма;
- 11-17/1061r1 (Huawei, TGay) — 7/8 длины 1344: подъём 3/4 по табл. 30 и сумма строк 1+5, 2+6, 3+7,
  4+8 даёт табл. 31 — сверяется (и тем самым ещё раз матрица 3/4 802.11ad);
- 11-16/1495r1 (Huawei, TGay), слайд 2: «7/8 … adopted in 802.11REVmc … generated by puncturing the
  first 48 parity bits from rate 13/16 … codeword length is 624».

Третий голос (только сверка, в репозиторий не кладётся — нет лицензии): 802.11ad-phy-sim
(github.com/jirimilos/802.11ad-phy-sim, f986bfc, LDPC_matrix.m, «case 672» и «case 624»), если путь
передан первым аргументом.

Пишет src/reportgen/potok/data/ldpc_80211ad.json. Запуск из корня репозитория.
"""
